"""Контракт канонических ссылок Yummy: entity_id → canonical_path → сущность.

Зачем
-----

Карточки карусели открывают битые страницы. Причина не в шаблоне: шаблон
берёт `url` из каталога, а каталог собран разбором отрисованной разметки —
`/anime/{slug}` без завершающей косой черты, из снимка пятичасовой давности,
где `title` на самом деле alt-текст постера, а `poster` пуст у всех 1080
записей до единой.

Единственный источник адреса, которому можно верить, — таблица
`PublicTitleRoute` самой витрины: витрина объявляет в ней, какой адрес какому
произведению принадлежит. Здесь она и читается.

Правило
-------

    entity_id (providerTitleId) → canonical_path → существующая страница

Ни одно звено не выводится и не угадывается. Запись, у которой нет
`entity_id` или чей `canonical_path` не разрешается, в публичную проекцию не
попадает вовсе: карточка, ведущая в никуда, хуже отсутствующей карточки —
она выглядит рабочей.
"""

from __future__ import annotations

import dataclasses
import enum
import json
import subprocess
from pathlib import Path

КОНТРАКТ = "yummy-canonical-link/1.0.0"

#: Префикс адресов страниц произведений. Объявлен, а не выведен из данных:
#: выведенный префикс менялся бы вместе с опечаткой в первой же записи.
ПРЕФИКС = "/anime/"


class Исход(str, enum.Enum):
    """Перечень закрыт: запись, не попавшая ни в один исход, означала бы,
    что мы её не рассматривали."""

    РАЗРЕШЁН = "RESOLVED"
    НЕТ_ИДЕНТИФИКАТОРА = "ENTITY_ID_MISSING"
    НЕТ_В_ТАБЛИЦЕ = "NOT_IN_ROUTE_TABLE"
    НЕКАНОНИЧЕСКИЙ = "NON_CANONICAL_ALIAS"
    СТОЛКНОВЕНИЕ = "ROUTE_COLLISION"


@dataclasses.dataclass(frozen=True, slots=True)
class Ссылка:
    entity_id: str
    canonical_path: str
    outcome: Исход
    reason: str

    @property
    def публикуема(self) -> bool:
        return self.outcome is Исход.РАЗРЕШЁН

    def as_dict(self) -> dict:
        return {"entityId": self.entity_id, "canonicalPath": self.canonical_path,
                "outcome": self.outcome.value, "reason": self.reason,
                "contract": КОНТРАКТ}


def путь_по_слагу(слаг: str) -> str:
    """Адрес страницы. Завершающая косая черта обязательна.

    Каталог витрины хранит `/anime/{slug}` без неё, а приложение отвечает по
    адресу с ней. Одна и та же страница под двумя написаниями — это два
    разных адреса для поисковой системы и лишний переход для посетителя.
    """
    return f"{ПРЕФИКС}{слаг.strip('/')}/"


class Резолвер:
    """Разрешает идентификатор в адрес по объявлению витрины."""

    def __init__(self, маршруты: list[dict]) -> None:
        self._по_id: dict[str, list[dict]] = {}
        for м in маршруты:
            ид = str(м.get("providerTitleId") or "")
            if ид:
                self._по_id.setdefault(ид, []).append(м)
        self.всего = len(маршруты)

    def разрешить(self, entity_id: str) -> Ссылка:
        ид = str(entity_id or "").strip()
        if not ид:
            return Ссылка("", "", Исход.НЕТ_ИДЕНТИФИКАТОРА,
                          "у записи нет идентификатора произведения; адрес "
                          "выводить не из чего")
        группа = self._по_id.get(ид)
        if not группа:
            return Ссылка(ид, "", Исход.НЕТ_В_ТАБЛИЦЕ,
                          "витрина не объявляет адреса для этого произведения")
        канонические = [м for м in группа if м.get("canonical")]
        if len(канонические) > 1:
            return Ссылка(ид, "", Исход.СТОЛКНОВЕНИЕ,
                          f"витрина объявляет {len(канонические)} канонических "
                          f"адреса; выбор одного приписал бы страницу произвольно")
        if not канонические:
            return Ссылка(ид, "", Исход.НЕКАНОНИЧЕСКИЙ,
                          "у произведения только псевдонимы; канонического "
                          "адреса витрина не объявила")
        return Ссылка(ид, путь_по_слагу(str(канонические[0]["slug"])),
                      Исход.РАЗРЕШЁН, "адрес объявлен витриной")


def маршруты_из_базы(контейнер: str) -> list[dict]:
    """Таблица маршрутов витрины. Только чтение.

    Запрос идёт стандартным вводом, а не частью командной строки: в нём есть
    кавычки, и подстановка их в строку оболочки — это либо синтаксическая
    ошибка, либо место, где чужое значение станет командой.
    """
    запрос = ('SELECT "providerTitleId", slug, canonical FROM '
              '"PublicTitleRoute" ORDER BY slug;')
    р = subprocess.run(
        ["docker", "exec", "-i", контейнер, "sh", "-lc",
         'psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -qtA -F"|" -f -'],
        input=запрос, capture_output=True, text=True, timeout=300)
    if р.returncode != 0:
        raise RuntimeError(f"чтение маршрутов не удалось: {р.stderr[:200]}")
    итог = []
    for строка in р.stdout.splitlines():
        части = строка.split("|")
        if len(части) < 3 or not части[0].strip():
            continue
        итог.append({"providerTitleId": части[0], "slug": части[1],
                     "canonical": части[2] == "t"})
    if not итог:
        raise RuntimeError("таблица маршрутов пуста; пустая витрина и "
                           "нечитаемая таблица выглядят одинаково")
    return итог
