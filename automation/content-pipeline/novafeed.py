"""Событийный слой каталога витрины: публикация как событие, а не как год.

Зачем этот модуль вообще есть
-----------------------------

Витрину обслуживает `lords-frontend.py`, и «Новинки» он берёт так:

    новые = [з for з in д.items if з.get("poster")][:12]

То есть головой списка. Список приходит отсортированным по паре
(год убыв., название), поэтому в «Новинках» месяцами стоят «100 дней до
прощания», «102-предложение руки и сердца» и «800 метров» — самые ранние по
алфавиту среди записей текущего года. Свежая запись туда не попадает никогда,
сколько её ни обновляй: год у неё тот же, а название дальше по алфавиту.

Разметку витрины трогать нельзя — это чужой контур. Но порядок элементов
принадлежит данным, и он здесь и исправляется: список отдаётся упорядоченным
по фактическому событию публикации, и та же голова списка становится
правильной.

Что считается событием публикации
---------------------------------

`published_at` — момент, когда запись впервые появилась на витрине. Он
хранится в журнале событий и переживает перезапуск: иначе каждый прогон
объявлял бы «новым» весь каталог.

При первом заполнении журнала (когда его ещё нет) время берётся из
авторитетного кэша каталога по `created_at`, а не выдумывается: иначе все
52 тысячи записей получили бы одно и то же время и «Новинки» остались бы
произвольными. Записи, которой в кэше нет, достаётся 1 января её года —
это заведомо грубо, поэтому такая оценка помечается `estimated`.

Дальше журнал ведёт себя строго событийно: новый слаг получает время
наблюдения, известный сохраняет своё. Ни одна запись не «молодеет».
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import re
import unicodedata
from pathlib import Path
from typing import Any

СХЕМА = "nova-catalog/2.0.0"

#: Сколько записей отдаётся в каждой ленте. Лента длиннее полки бессмысленна,
#: короче — не переживёт добавления нескольких записей за один прогон.
ДЛИНА_ЛЕНТЫ = 60

#: Окно новизны. Запись старше него новинкой не является, сколько бы точно ни
#: было известно время её публикации.
ОКНО_НОВИЗНЫ_ДНЕЙ = 30


def сейчас() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def слаг(название: str) -> str:
    """Тот же слаг, каким витрина адресует произведение.

    Повторяет `factory.lords.live_catalog.slugify`. Повторяет намеренно и с
    оговоркой: модуль движка недоступен из окружения службы, а расхождение
    правил дало бы несовпадение по части записей — то есть потерю времени
    публикации там, где оно на самом деле известно. Несовпадение не портит
    выдачу: запись просто получит оценочное время.
    """
    т = unicodedata.normalize("NFKD", название or "").lower()
    т = "".join(с for с in т if not unicodedata.combining(с))
    т = ПЕРЕВОД_РЕ.sub(lambda м: ТАБЛИЦА[м.group(0)], т)
    т = re.sub(r"[^a-z0-9]+", "-", т).strip("-")
    return т


ТАБЛИЦА = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "",
    "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}
ПЕРЕВОД_РЕ = re.compile("|".join(sorted(ТАБЛИЦА, key=len, reverse=True)))


def отпечаток(записи: list[dict[str, Any]]) -> str:
    """Отпечаток содержимого каталога без времён наблюдения.

    Время публикации в отпечаток не входит: иначе первый же прогон, проставив
    журнал, объявил бы каталог изменившимся, и служба перезапускалась бы на
    каждом цикле без причины.
    """
    основа = [{k: з.get(k) for k in ("slug", "title", "poster", "kind", "year")}
              for з in записи]
    основа.sort(key=lambda з: з["slug"] or "")
    сырое = json.dumps(основа, ensure_ascii=False, sort_keys=True,
                       separators=(",", ":")).encode()
    return hashlib.blake2b(сырое, digest_size=16).hexdigest()


def загрузить_журнал(путь: Path) -> dict[str, dict[str, Any]]:
    if not путь.exists():
        return {}
    try:
        d = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        # Испорченный журнал — не повод объявить весь каталог новым. Пустой
        # журнал ниже приведёт к пересеву из кэша каталога, а не к тому, что
        # 52 тысячи записей разом окажутся «новинками».
        return {}
    return d.get("slugs") or {}


def сохранить_журнал(путь: Path, журнал: dict[str, dict[str, Any]]) -> None:
    путь.parent.mkdir(parents=True, exist_ok=True)
    врем = путь.with_suffix(".tmp")
    врем.write_text(json.dumps(
        {"schema": СХЕМА, "updatedAt": сейчас(), "count": len(журнал),
         "slugs": журнал}, ensure_ascii=False), encoding="utf-8")
    врем.replace(путь)


def времена_каталога(кэш: Path) -> dict[str, str]:
    """Слаг → `created_at` из авторитетного кэша каталога.

    Нужен только для первого заполнения журнала. При столкновении слагов
    берётся самое раннее время: запись, появившаяся раньше, и есть та, чей
    адрес был занят первым.
    """
    if not кэш.exists():
        return {}
    try:
        записи = json.loads(кэш.read_text(encoding="utf-8"))["items"]
    except (OSError, ValueError, KeyError):
        return {}
    итог: dict[str, str] = {}
    for з in записи:
        с = слаг(str(з.get("name") or ""))
        созд = str(з.get("created_at") or "")
        if not с or not созд:
            continue
        прежнее = итог.get(с)
        if прежнее is None or созд < прежнее:
            итог[с] = созд
    return итог


def применить_события(записи: list[dict[str, Any]],
                      журнал: dict[str, dict[str, Any]],
                      кэш_времён: dict[str, str],
                      наблюдение: str) -> tuple[list[dict[str, Any]], int]:
    """Проставить `published_at` и вернуть (записи, сколько новых).

    Журнал изменяется на месте: вызывающий обязан его сохранить, и только
    после того, как публикация принята. Сохранённый раньше журнал объявил бы
    записи опубликованными, не опубликовав их.
    """
    первое_заполнение = not журнал
    новых = 0
    for з in записи:
        с = з.get("slug") or ""
        известно = журнал.get(с)
        if известно is None:
            if первое_заполнение:
                # Пересев: время берётся из каталога, а не из наблюдения.
                когда = кэш_времён.get(с)
                оценка = когда is None
                if когда is None:
                    год = з.get("year")
                    когда = f"{int(год):04d}-01-01T00:00:00Z" if год else "1970-01-01T00:00:00Z"
            else:
                когда, оценка = наблюдение, False
                новых += 1
            журнал[с] = {"first_seen": когда, "estimated": оценка}
            известно = журнал[с]
        з["published_at"] = известно["first_seen"]
        з["published_at_estimated"] = bool(известно.get("estimated"))
    return записи, новых


def упорядочить(записи: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """По событию публикации, новые первыми.

    Вторичный ключ — название, а не случайный порядок: одинаковое время у
    тысяч записей после пересева иначе давало бы разный вывод на каждом
    прогоне, и витрина «менялась» бы, ничего не публикуя.
    """
    return sorted(записи, key=lambda з: (з.get("published_at") or "",
                                         з.get("title") or ""),
                  reverse=True)


def ленты(записи: list[dict[str, Any]], журнал: dict[str, dict[str, Any]],
          предыдущие: dict[str, Any] | None) -> dict[str, Any]:
    """Три ленты с разным смыслом, а не три среза одного каталога.

    `new` — появление произведения на витрине.
    `episodes` — появление новых серий у уже известного произведения.
    `available` — появление потока там, где его не было.

    Ленты `episodes` и `available` заполняются только при наличии прежнего
    снимка: без него «изменение» неотличимо от «первого наблюдения», и
    заполнять их значило бы объявить весь каталог событием.
    """
    прежние = {з["slug"]: з for з in ((предыдущие or {}).get("items") or [])}
    # «Новинки» — события за окно, а не всё, у чего известна дата. Первый
    # вариант этой функции возвращал сюда весь каталог: условием стояло
    # «время не оценочное», а после пересева оно не оценочное почти у всех.
    # Лента, совпадающая с каталогом, — ровно тот дефект, который здесь и
    # исправляется, и допустить его в самой ленте было бы смешно.
    порог = (dt.datetime.now(dt.timezone.utc)
             - dt.timedelta(days=ОКНО_НОВИЗНЫ_ДНЕЙ)).strftime("%Y-%m-%dT%H:%M:%SZ")
    новые = [з for з in записи
             if not з.get("published_at_estimated")
             and (з.get("published_at") or "") >= порог]
    серии, доступно = [], []
    for з in записи:
        было = прежние.get(з.get("slug"))
        if не_пусто(было):
            if (з.get("episodes") or 0) > (было.get("episodes") or 0):
                серии.append(з)
            if з.get("poster") and not было.get("poster"):
                доступно.append(з)
    return {
        "new": [з["slug"] for з in новые[:ДЛИНА_ЛЕНТЫ]],
        "episodes": [з["slug"] for з in серии[:ДЛИНА_ЛЕНТЫ]],
        "available": [з["slug"] for з in доступно[:ДЛИНА_ЛЕНТЫ]],
        "note": ("new — появление произведения; episodes — появление серий; "
                 "available — появление потока. Общим каталогом не подменяются: "
                 "пустая лента означает отсутствие событий, а не отсутствие данных"),
    }


def не_пусто(з: dict[str, Any] | None) -> bool:
    return isinstance(з, dict) and bool(з)
