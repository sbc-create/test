"""Воспроизведение дефекта: свежая запись не доходит до главной.

Тесты работают по РАЗВЁРНУТОМУ каталогу витрины — тому самому файлу, который
читает `lords-frontend.py`. Это сделано намеренно: дефект не в том, что код
плохо написан, а в том, что до витрины не доезжают данные, и проверять надо
доехавшее, а не задуманное.

До исправления падают все четыре.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import novafeed  # noqa: E402

ВИТРИНЫ = ["lords-01", "lords-02", "lords-03",
           "animedia-01", "animedia-02", "zona-01"]
ФРОНТ = Path("/srv/lords/.frontend")

#: Сколько записей витрина берёт головой списка под «Новинки»
#: (`lords-frontend.py`, строка 441). Число принадлежит чужому контуру,
#: поэтому оно здесь названо, а не подразумевается.
ГОЛОВА = 12

#: Обещанный срок свежести: от появления у поставщика до публичной страницы.
СРОК_МИНУТ = 15


def каталог(витрина: str) -> dict:
    п = ФРОНТ / f"{витрина}-catalog.json"
    if not п.exists():
        pytest.skip(f"каталог {витрина} не развёрнут")
    return json.loads(п.read_text(encoding="utf-8"))


def test_конвейер_отработал_недавно() -> None:
    """Конвейер прошёл по всем витринам не позже обещанного срока.

    Проверяется отметка прогона, а НЕ время правки файла каталога. Каталог
    переписывается только когда содержимое изменилось: на спокойном каталоге
    его mtime стареет сколь угодно долго, и это исправность, а не отказ.
    Первая версия этой проверки смотрела на mtime и позеленела бы только
    потому, что поставщик добавляет записи каждые несколько минут, — то есть
    измеряла бы активность поставщика, а не работу конвейера.

    Падает на дефекте: отметки не существовало вовсе, регенератора на хосте
    не было, и каталоги стояли замороженными с ручной сборки.
    """
    п = Path("/srv/site-factory/content-pipeline/state/heartbeat.json")
    assert п.exists(), "конвейер не оставил отметки о прогоне: он не запускался"
    д = json.loads(п.read_text(encoding="utf-8"))
    снято = dt.datetime.strptime(д["at"], "%Y-%m-%dT%H:%M:%SZ").replace(
        tzinfo=dt.timezone.utc)
    возраст = (dt.datetime.now(dt.timezone.utc) - снято).total_seconds() / 60
    assert возраст <= СРОК_МИНУТ, (
        f"последний прогон конвейера был {возраст:.0f} мин назад; "
        f"обещано не более {СРОК_МИНУТ}")
    assert д["sites"] == len(ВИТРИНЫ), (
        f"прогон охватил {д['sites']} витрин из {len(ВИТРИНЫ)}")
    assert д["errors"] == 0, f"в последнем прогоне отказов: {д['errors']}"


@pytest.mark.parametrize("витрина", ВИТРИНЫ)
def test_каталог_витрины_опубликован(витрина: str) -> None:
    """Каталог собран нашим конвейером, а не остался ручным снимком."""
    д = каталог(витрина)
    assert д.get("schema") == "nova-catalog/2.0.0", (
        f"{витрина}: каталог версии {д.get('version')} без схемы — "
        f"это ручной снимок, а не публикация конвейера")
    assert д.get("revision"), f"{витрина}: у каталога нет ревизии"


@pytest.mark.parametrize("витрина", ВИТРИНЫ)
def test_у_записей_есть_событие_публикации(витрина: str) -> None:
    """У каждой записи есть время публикации.

    Падает на дефекте: в каталоге версии 1 поля `published_at` нет вовсе,
    поэтому упорядочить по событию нечем.
    """
    д = каталог(витрина)
    записи = д["items"]
    без = [з["slug"] for з in записи if not з.get("published_at")]
    assert not без, (
        f"{витрина}: у {len(без)} записей из {len(записи)} нет published_at; "
        f"например {без[:3]}")


@pytest.mark.parametrize("витрина", ВИТРИНЫ)
def test_новинки_это_самые_свежие(витрина: str) -> None:
    """Голова списка — действительно самые свежие записи.

    Витрина берёт под «Новинки» первые двенадцать записей списка. Значит
    список обязан быть упорядочен по событию публикации, иначе в «Новинках»
    окажется то, что просто раньше по алфавиту.

    Падает на дефекте: список отсортирован по (год убыв., название), и
    головой стоят «100 дней до прощания», «102-предложение руки и сердца»,
    «800 метров».
    """
    д = каталог(витрина)
    записи = [з for з in д["items"] if з.get("poster")]
    if len(записи) <= ГОЛОВА:
        pytest.skip("записей меньше головы списка")
    голова = записи[:ГОЛОВА]
    самые_свежие = novafeed.упорядочить(записи)[:ГОЛОВА]
    assert [з["slug"] for з in голова] == [з["slug"] for з in самые_свежие], (
        f"{витрина}: в «Новинках» стоит не самое свежее.\n"
        f"  стоит:  {[з['title'][:26] for з in голова[:4]]}\n"
        f"  должно: {[з['title'][:26] for з in самые_свежие[:4]]}")


@pytest.mark.parametrize("витрина", ВИТРИНЫ)
def test_ленты_не_подменяются_общим_каталогом(витрина: str) -> None:
    """Событийные ленты объявлены отдельно от каталога.

    Падает на дефекте: «Каталог», «Новинки» и «Подборки» получают один и тот
    же срез, а отдельных лент в данных нет.
    """
    д = каталог(витрина)
    ленты = д.get("feeds")
    assert isinstance(ленты, dict), (
        f"{витрина}: в каталоге нет блока feeds — событийные разделы "
        f"нечем наполнить, кроме общего каталога")
    for имя in ("new", "episodes", "available"):
        assert имя in ленты, f"{витрина}: нет ленты {имя!r}"
