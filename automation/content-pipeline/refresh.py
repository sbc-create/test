#: Обвал каталога больше чем на эту долю считается порчей источника, а не
#: правкой ассортимента. Поставщик вправе убрать часть записей; вчетверо
#: меньший каталог допуском не объясняется.
ДОПУСК_ОБВАЛА = 0.10
ПОПЫТОК = 3
ПАУЗА_БАЗОВАЯ = 5


def журнал(*ч: Any) -> None:
    print("[nova-refresh]", *ч, flush=True)


def состояние(витрина: str) -> Path:
    п = СОСТОЯНИЕ / витрина
    п.mkdir(parents=True, exist_ok=True)
    return п


def прочитать(п: Path, умолчание: Any) -> Any:
    try:
        return json.loads(п.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return умолчание


def записать_атомарно(п: Path, данные: Any) -> None:
    """Запись через временный файл и переименование.

    Витрина читает этот файл на старте. Запись на месте означала бы, что
    перезапуск, случившийся в середине записи, поднимет службу на обрезанном
    JSON — и витрина останется лежать до следующего цикла.
    """
    п.parent.mkdir(parents=True, exist_ok=True)
    врем = п.with_suffix(п.suffix + ".tmp")
    врем.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
    os.replace(врем, п)


def извлечь(витрина: str, корень: Path, куда: Path) -> tuple[bool, str]:
    """Запустить извлекатель. Его код не изменялся."""
    if not корень.exists():
        return False, f"legacy-релиз не найден: {корень}"
    куда.parent.mkdir(parents=True, exist_ok=True)
    # Часть релизов Lords лежит под правами 0700 пользователя lords: служба
    # ходит под root и читает их прямо, а проверочный прогон от обычной
    # учётной записи — через sudo. Различие в способе чтения, а не в данных.
    команда = [sys.executable, str(ИЗВЛЕКАТЕЛЬ), "--site-root", str(корень),
               "--out", str(куда)]
    if not os.access(корень, os.R_OK | os.X_OK):
        команда = ["sudo", "-n", "/usr/bin/python3", str(ИЗВЛЕКАТЕЛЬ),
                   "--site-root", str(корень), "--out", str(куда)]
    р = subprocess.run(команда, capture_output=True, text=True, timeout=1800)
    if р.returncode != 0:
        return False, (р.stderr or р.stdout).strip()[:300]
    return True, (р.stderr or "").strip()[:200]


#: Сколько ссылок на произведения обязано быть на главной. Двенадцать — это
#: одна полка; меньше означает, что каталог до витрины не доехал.
МИНИМУМ_ССЫЛОК = 12


def проба(порт: int, ожидаемый: str = "") -> tuple[bool, str]:
    """Витрина отвечает содержимым, и содержимое — то самое, что опубликовано.

    Код 200 при пустой странице — самый дорогой из возможных ответов: он
    выглядит исправностью. Поэтому проверяются три вещи.

    Проверка ведётся по ссылкам на произведения, а не по именам классов.
    Первый вариант искал `class="card"` — разметку legacy-витрины — и на
    nova не совпадал никогда: там карточка называется `class="c"`. Проба
    отклонила исправную публикацию и откатила её. Имена классов принадлежат
    чужому контуру и могут меняться без предупреждения; ссылка на
    произведение — это содержание, и она не может измениться, оставшись
    той же страницей.

    `ожидаемый` — слаг записи, которая обязана появиться после публикации.
    Без него проба подтверждает лишь то, что витрина жива, но не то, что она
    отдаёт именно новую ревизию: старый каталог отвечает содержимым ничуть
    не хуже нового.
    """
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{порт}/", timeout=20) as о:
            тело = о.read().decode("utf-8", "replace")
    except Exception as ош:  # noqa: BLE001
        return False, f"главная не ответила: {type(ош).__name__}"
    if len(тело) < 4000:
        return False, f"главная короче 4000 байт ({len(тело)})"
    ссылок = тело.count('href="/title/')
    if ссылок < МИНИМУМ_ССЫЛОК:
        return False, f"на главной {ссылок} ссылок на произведения"
    if ожидаемый and f'href="/title/{ожидаемый}/' not in тело:
        return False, (f"опубликованная запись {ожидаемый!r} на главной не "
                       f"появилась — витрина отдаёт не ту ревизию")
    return True, f"{len(тело)} байт, ссылок {ссылок}" + (
        f", {ожидаемый} на месте" if ожидаемый else "")


def перезапустить(юнит: str) -> tuple[bool, str]:
    """Витрина читает каталог один раз при старте (`lords-frontend.py:621`).

    Поэтому публикация без перезапуска не доезжает вовсе. Перезапуск делается
    только когда каталог действительно изменился: безусловный давал бы
    сотни рестартов в сутки и секундные окна с 502.
    """
    команда = ["systemctl", "restart", юнит]
    if os.geteuid() != 0:
        команда = ["sudo", "-n", "systemctl", "restart", юнит]
    р = subprocess.run(команда, capture_output=True, text=True, timeout=120)
    if р.returncode != 0:
        return False, (р.stderr or "").strip()[:200]
    time.sleep(3)
    return True, ""


def один(витрина: str, принудительно: bool = False,
         куда: Path | None = None) -> dict[str, Any]:
    """`куда` — иной каталог назначения для проверки без влияния на витрину.

    Проверочный прогон обязан быть возможен без перезапуска публичной службы:
    иначе единственный способ убедиться, что данные собираются верно, — это
    выкатить их на живую витрину и посмотреть.
    """
    сост = состояние(витрина)
    проверка = куда is not None
    цель = (куда / f"{витрина}-catalog.json") if куда else (ФРОНТ / f"{витрина}-catalog.json")
    лкг = сост / "catalog.lkg.json"
    метрики: dict[str, Any] = {
        "site": витрина, "startedAt": novafeed.сейчас(), "schema": novafeed.СХЕМА,
        "published": False, "restarted": False, "error": None, "attempts": 0,
    }
    опис = ВИТРИНЫ[витрина]
    врем = сост / "extract.json"

    последняя_ошибка = "не запускалось"
    for попытка in range(1, ПОПЫТОК + 1):
        метрики["attempts"] = попытка
        ок, сообщение = извлечь(витрина, Path(опис["root"]), врем)
        if ок:
            последняя_ошибка = ""
            break
        последняя_ошибка = сообщение
        журнал(f"{витрина}: извлечение не удалось (попытка {попытка}): {сообщение}")
        if попытка < ПОПЫТОК:
            time.sleep(ПАУЗА_БАЗОВАЯ * (2 ** (попытка - 1)))

    if последняя_ошибка:
        # Последний хороший каталог остаётся на месте: витрина продолжает
        # отвечать вчерашним содержимым, а не пустотой.
        записать_атомарно(сост / "dlq.json", {
            "site": витрина, "at": novafeed.сейчас(), "stage": "extract",
            "error": последняя_ошибка,
            "note": "последний хороший каталог оставлен нетронутым"})
        метрики["error"] = последняя_ошибка
        return метрики

    свежее = прочитать(врем, {})
    записи = свежее.get("items") or []
    if not записи:
        метрики["error"] = "извлечён пустой каталог"
        записать_атомарно(сост / "dlq.json", {
            "site": витрина, "at": novafeed.сейчас(), "stage": "guard-empty",
            "error": метрики["error"]})
        return метрики

    прежний = прочитать(лкг, None) or прочитать(цель, None)
    было = len((прежний or {}).get("items") or [])
    if было and len(записи) < было * (1 - ДОПУСК_ОБВАЛА):
        метрики["error"] = f"обвал каталога: было {было}, стало {len(записи)}"
        записать_атомарно(сост / "dlq.json", {
            "site": витрина, "at": novafeed.сейчас(), "stage": "guard-shrink",
            "error": метрики["error"],
            "note": "публикация отклонена, витрина осталась на прежнем каталоге"})
        return метрики

    отп = novafeed.отпечаток(записи)
    чекпоинт = прочитать(сост / "checkpoint.json", {})
    метрики["digest"] = отп
    метрики["previousDigest"] = чекпоинт.get("digest")

    журн = novafeed.загрузить_журнал(сост / "events.json")
    времена = novafeed.времена_каталога(КЭШ_КАТАЛОГА) if not журн else {}
    наблюдение = novafeed.сейчас()
    записи, новых = novafeed.применить_события(записи, журн, времена, наблюдение)
    записи = novafeed.упорядочить(записи)
    метрики["newRecords"] = новых
    метрики["lastEventAt"] = max((з.get("published_at") or "" for з in записи),
                                 default="")

    if отп == чекпоинт.get("digest") and not принудительно:
        # Идемпотентность: тот же вход — та же публикация. Ни записи, ни
        # перезапуска. Журнал событий при этом уже сохранён выше по времени
        # только в памяти, поэтому сохраняем его и здесь: новых слагов нет.
        novafeed.сохранить_журнал(сост / "events.json", журн)
        метрики["skipped"] = "вход не изменился"
        метрики["finishedAt"] = novafeed.сейчас()
        записать_атомарно(сост / "metrics.json", метрики)
        журнал(f"{витрина}: вход не изменился ({отп[:12]}) — публикация не нужна")
        return метрики

    свежее.update({
        "schema": novafeed.СХЕМА, "version": 2, "site": витрина,
        "revision": отп, "builtAt": наблюдение,
        "items": записи,
        "feeds": novafeed.ленты(записи, журн, прежний),
        "producer": "content-pipeline/nova-catalog-refresh",
    })

    предыдущий_снимок = цель.read_bytes() if цель.exists() else None
    записать_атомарно(цель, свежее)
    метрики["published"] = True

    if проверка:
        # Проверочный прогон: ни перезапуска, ни чекпоинта. Журнал событий
        # тоже не сохраняется — иначе проверка объявила бы записи
        # опубликованными, и настоящая публикация сочла бы их старыми.
        метрики["mode"] = "проверка"
        метрики["target"] = str(цель)
        метрики["finishedAt"] = novafeed.сейчас()
        метрики["records"] = len(записи)
        журнал(f"{витрина}: ПРОВЕРКА — собрано {len(записи)} записей в {цель}")
        return метрики

    ок, почему = перезапустить(опис["unit"])
    метрики["restarted"] = ок
    if ок:
        # Ожидается самая свежая запись с постером: витрина ставит в полку
        # только их, и её отсутствие означает, что доехал не тот каталог.
        свежая = next((з["slug"] for з in записи if з.get("poster")), "")
        метрики["expectedSlug"] = свежая
        ок, почему = проба(опис["port"], свежая)
    метрики["probe"] = почему

    if not ок:
        журнал(f"{витрина}: приёмка не пройдена ({почему}) — откат")
        if предыдущий_снимок is not None:
            цель.write_bytes(предыдущий_снимок)
            перезапустить(опис["unit"])
            назад, _ = проба(опис["port"])
            метрики["rollbackHealthy"] = назад
        метрики["error"] = f"откат: {почему}"
        метрики["published"] = False
        записать_атомарно(сост / "dlq.json", {
            "site": витрина, "at": novafeed.сейчас(), "stage": "probe",
            "error": почему, "note": "каталог возвращён к прежнему"})
        записать_атомарно(сост / "metrics.json", метрики)
        return метрики

    # Приёмка пройдена — и только теперь принимаются журнал и чекпоинт.
    # Записанные раньше, они объявили бы опубликованным то, что не доехало.
    novafeed.сохранить_журнал(сост / "events.json", журн)
    shutil.copyfile(цель, лкг)
    записать_атомарно(сост / "checkpoint.json", {
        "digest": отп, "publishedAt": novafeed.сейчас(),
        "records": len(записи), "site": витрина})
    (сост / "dlq.json").unlink(missing_ok=True)
    метрики["finishedAt"] = novafeed.сейчас()
    метрики["records"] = len(записи)
    записать_атомарно(сост / "metrics.json", метрики)
    журнал(f"{витрина}: опубликовано {len(записи)} записей, ревизия {отп[:12]}, "
           f"новых {новых}, проба {почему}")
    return метрики


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--site", action="append", help="только эта витрина")
    р.add_argument("--force", action="store_true",
                   help="опубликовать даже если вход не изменился (адресный replay)")
    р.add_argument("--check-into", metavar="КАТАЛОГ",
                   help="проверочный прогон: писать сюда, витрину не трогать")
    args = р.parse_args()
    куда = Path(args.check_into) if args.check_into else None
    if куда:
        куда.mkdir(parents=True, exist_ok=True)

    цели = args.site or list(ВИТРИНЫ)
    неизвестные = [c for c in цели if c not in ВИТРИНЫ]
    if неизвестные:
        журнал("неизвестные витрины:", неизвестные)
        return 2

    СОСТОЯНИЕ.mkdir(parents=True, exist_ok=True)
    итоги = []
    for витрина in цели:
        try:
            итоги.append(один(витрина, принудительно=args.force, куда=куда))
        except Exception as ош:  # noqa: BLE001
            журнал(f"{витрина}: непредвиденный отказ: {ош!r}")
            итоги.append({"site": витрина, "error": repr(ош)})

    отказов = sum(1 for и in итоги if и.get("error"))
    # Общая отметка принадлежит полному обходу. Адресный прогон одной витрины
    # её не трогает: иначе ручной replay объявлял бы, что конвейер прошёл по
    # одной витрине, и следящий за отметкой считал бы остальные пять
    # необслуженными.
    if not args.site:
        записать_атомарно(СОСТОЯНИЕ / "heartbeat.json", {
            "at": novafeed.сейчас(), "sites": len(итоги), "errors": отказов,
            "published": sum(1 for и in итоги if и.get("published")),
            "results": итоги})
    журнал(f"готово: витрин {len(итоги)}, отказов {отказов}")
    # Отказ одной витрины не должен помечать весь прогон неуспешным: остальные
    # опубликовались, и таймер обязан продолжать ходить.
    return 1 if отказов == len(итоги) else 0


if __name__ == "__main__":
    sys.exit(main())
