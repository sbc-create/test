#!/usr/bin/env python3
"""Что браузер реально получает вместо постера: формат, вес, пиксели, запас.

Только чтение публичных страниц и изображений. Ничего не меняет, ничего не
сохраняет в продакшен.

ПОЧЕМУ СЧЁТЧИКИ НЕ ЗАПРАШИВАЮТСЯ. В разметке витрин стоит пиксель Метрики
(`<img src="https://mc.yandex.ru/watch/…">`). Технический обход, который его
запросит, запишет визит, которого не было, и испортит те самые данные, по
которым потом считают трафик. Поэтому адреса счётчиков исключаются по ХОСТУ
до любой сетевой операции, и это свойство закреплено проверкой.

ЧТО ИНСТРУМЕНТ ИЗМЕРЯЕТ:

  доставку      код, тип содержимого, ФАКТИЧЕСКИЕ байты (не Content-Length);
  геометрию     ширину и высоту из заголовка файла (PIL), а не из разметки;
  объявление    width/height, srcset, sizes, loading, decoding из разметки;
  запас         во сколько раз пиксели файла шире объявленного места показа.

ЧЕГО ОН НЕ ИЗМЕРЯЕТ, и это важнее:

* РЕАЛЬНЫЙ размер показа в вёрстке. Без браузера известен только объявленный
  `width`/`height` (и `sizes`, если он есть). CSS может показать картинку
  меньше или больше объявленного; `object-fit:cover` ещё и обрезает. Поэтому
  «запас» считается от ОБЪЯВЛЕННОГО размера и называется оценкой снизу: если
  CSS уменьшает место показа, запас только больше.
* плотность экрана посетителя. Она не наблюдаема со стороны сервера, поэтому
  печатаются два порога: достаточно для DPR 1 и для DPR 2.
* выбор браузера из `srcset`. Если `srcset` есть, инструмент печатает все
  варианты и считает запас по тому, который браузер взял бы при DPR 2.

    python3 automation/local/poster-delivery-audit.py --domain animedia.icu
    python3 automation/local/poster-delivery-audit.py --all --csv out.csv

Коды: 0 — измерено всё, 1 — есть избыточное разрешение, 2 — не измерено ничего.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import pathlib
import re
import subprocess
import sys

АГЕНТ = "factory-poster-delivery-audit"

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ОЧЕРЕДИ = КОРЕНЬ / "config" / "domain-queues"

#: Хосты счётчиков. Запрашивать их техническим обходом запрещено: это испортит
#: данные, по которым считают трафик. Список закрытый — расширять его можно,
#: сокращать нельзя.
СЧЁТЧИКИ = (
    "mc.yandex.ru", "yandex.ru/metrika", "google-analytics.com",
    "googletagmanager.com", "top-fwz1.mail.ru", "counter.yadro.ru",
)

#: Агент называет себя своим именем и не попадает в класс роботов
#: (bot/crawler/spider/curl/python/wget), который витрины ограничивают.

#: ОТКУДА БЕРЁТСЯ PIL, и почему это важно знать читателю отчёта.
#: Pillow установлен в каталоге ПОЛЬЗОВАТЕЛЯ (`~/.local/lib/python3.10/
#: site-packages`), а не в системном python3. Следствия, оба измерены 23.10:
#: инструмент работает от имени `claude` и не работает под `python3 -s`; и
#: КОД ВИТРИНЫ, запускаемый службой системным интерпретатором, PIL не видит
#: вовсе — соседняя линия выпустила на этом уменьшение обложек и получила ноль
#: эффекта, потому что проверяла функцию в своём окружении, а не в том, где она
#: работает. Поэтому отказ здесь называет не только ошибку импорта, но и место
#: установки: иначе читатель будет искать её в коде.
ГДЕ_PIL = ("Pillow недоступен ИМЕННО ЭТОМУ интерпретатору. Измерено 23.10:"
           " библиотека стояла только в каталоге пользователя"
           " (~/.local/lib/python3.10/site-packages), и системный python3"
           " службы её не видел — выпущенная правка полдня не действовала."
           " С 23.10 на узле стоит системный python3-pil 9.0.1; если отказ"
           " виден сейчас, значит запуск идёт другим интерпретатором или в"
           " другом окружении. Проверять окружением службы:"
           " automation/local/service-image-support-check.py")


АГЕНТ_СТОЛ = "factory-poster-audit"
АГЕНТ_МОБ = ("factory-poster-audit (mobile profile;"
             " viewport=390x844; dpr=2)")

ПУТИ_КАТАЛОГА = ("/catalog/", "/catalog", "/filmy/", "/anime/", "/serialy/",
                 "/top/", "/new/")
#: Запас считается от объявленного места показа. Порог «достаточно для DPR 2»
#: взят как 2.0: больше этого браузер не использует ни на одном экране.
ПОРОГ_DPR2 = 2.0

ТЕГ_IMG = re.compile(r"<img\b[^>]{0,900}>", re.I)
АТРИБУТ = re.compile(r'([a-zA-Z-]+)\s*=\s*"([^"]*)"')
#: Атрибуты БЕЗ значения (`data-poster`, `loading`, `hidden`). Без них ветка
#: «атрибут data-poster» не срабатывала ни разу: пары `имя="значение"` её не
#: содержат. Нашла проверка, а не чтение.
АТРИБУТ_БЕЗ_ЗНАЧЕНИЯ = re.compile(r'(?:^|\s)([a-zA-Z][a-zA-Z0-9-]*)(?=[\s>])')
ССЫЛКА_ТАЙТЛА = re.compile(r'href="(/(?:title|anime)/[a-z0-9._-]+/?)"', re.I)


def счётчик(адрес: str) -> bool:
    """Адрес принадлежит счётчику и запрашиваться не должен."""
    низкий = (адрес or "").lower()
    return any(х in низкий for х in СЧЁТЧИКИ)


def страница(url: str, агент: str = АГЕНТ_СТОЛ,
             таймаут: int = 25) -> tuple[int, str]:
    г = subprocess.run(
        ["curl", "-sL", "-m", str(таймаут), "-H", f"User-Agent: {агент}",
         "-w", "\n@@%{http_code}", url], capture_output=True, text=True)
    если = (г.stdout or "").rsplit("@@", 1)
    if len(если) != 2:
        return 0, ""
    try:
        код = int(если[1].strip())
    except ValueError:
        код = 0
    return код, если[0]


def изображение(url: str, агент: str, таймаут: int = 25) -> dict:
    """Фактические байты и пиксели. Счётчик не запрашивается никогда."""
    if счётчик(url):
        return {"ок": False, "почему": "адрес счётчика — не запрашивается"}
    г = subprocess.run(
        ["curl", "-sL", "-m", str(таймаут), "-H", f"User-Agent: {агент}",
         "-D", "-", "-o", "-", url], capture_output=True)
    if г.returncode != 0:
        return {"ок": False, "почему": f"curl код {г.returncode}"}
    тело = г.stdout
    разрыв = тело.find(b"\r\n\r\n")
    заголовки, данные = (тело[:разрыв], тело[разрыв + 4:]) if разрыв > 0 else (b"", тело)
    текст = заголовки.decode("latin-1", "replace")
    код = 0
    м = re.search(r"HTTP/[\d.]+\s+(\d{3})", текст)
    if м:
        код = int(м.group(1))
    тип = ""
    м = re.search(r"(?im)^content-type:\s*([^\r\n;]+)", текст)
    if м:
        тип = м.group(1).strip().lower()
    итог = {"ок": True, "код": код, "тип": тип, "байт": len(данные),
            "ширина": None, "высота": None, "формат": ""}
    try:
        from PIL import Image
        с = Image.open(io.BytesIO(данные))
        итог["ширина"], итог["высота"] = с.size
        итог["формат"] = (с.format or "").lower()
    except Exception as сбой:                        # noqa: BLE001
        итог["почему_без_пикселей"] = f"{type(сбой).__name__}: {сбой}"[:120]
    return итог


def атрибуты(тег: str) -> dict[str, str]:
    """Пары и атрибуты без значения. Второе — не мелочь: см. АТРИБУТ_БЕЗ_ЗНАЧЕНИЯ."""
    итог = {к.lower(): з for к, з in АТРИБУТ.findall(тег)}
    тело = тег[4:]  # без "<img"
    со_значением = set()
    for к, _ in АТРИБУТ.findall(тег):
        со_значением.add(к.lower())
    for к in АТРИБУТ_БЕЗ_ЗНАЧЕНИЯ.findall(тело):
        н = к.lower()
        if н not in со_значением and н not in итог:
            итог[н] = ""
    return итог


def постер_ли(а: dict[str, str]) -> str:
    """Почему этот `img` считается постером. Пустая строка — не постер.

    Признак называется, а не угадывается: по нему потом видно, на чём основан
    отбор, и ошибку отбора можно отличить от ошибки измерения.
    """
    if "data-poster" in а:
        return "атрибут data-poster"
    адрес = а.get("src") or ""
    if "/poster/" in адрес or "poster.cdnvideohub.com" in адрес:
        return "адрес постера"
    alt = (а.get("alt") or "").lower()
    if "постер" in alt:
        return "подпись «постер»"
    try:
        ш, в = int(а.get("width") or 0), int(а.get("height") or 0)
    except ValueError:
        return ""
    if ш and в and в > ш * 1.2:
        return "вертикальное соотношение в разметке"
    return ""


def постеры_страницы(html: str, предел: int) -> list[dict]:
    найдено = []
    for тег in ТЕГ_IMG.findall(html):
        а = атрибуты(тег)
        адрес = а.get("src") or ""
        if not адрес or счётчик(адрес):
            continue
        причина = постер_ли(а)
        if not причина:
            continue
        найдено.append({"src": адрес, "признак": причина,
                        "width": а.get("width", ""), "height": а.get("height", ""),
                        "srcset": а.get("srcset", ""), "sizes": а.get("sizes", ""),
                        "loading": а.get("loading", ""),
                        "decoding": а.get("decoding", "")})
        if len(найдено) >= предел:
            break
    return найдено


def абсолютный(адрес: str, домен: str) -> str:
    if адрес.startswith("http"):
        return адрес
    if адрес.startswith("//"):
        return "https:" + адрес
    return f"https://{домен}{адрес if адрес.startswith('/') else '/' + адрес}"


def домены() -> list[tuple[str, str, str]]:
    итог = []
    for ф in sorted(ОЧЕРЕДИ.glob("*.json")):
        о = json.loads(ф.read_text(encoding="utf-8"))
        итог.append((о["family"], о["site_id"], о["domain"]))
    return итог


def страницы_домена(домен: str, агент: str) -> list[tuple[str, str, str]]:
    """[(вид, url, html)] — главная, каталог, карточка. Вид называется явно."""
    собрано = []
    код, html = страница(f"https://{домен}/", агент)
    собрано.append(("главная", f"https://{домен}/", html if код == 200 else ""))

    for путь in ПУТИ_КАТАЛОГА:
        код, html = страница(f"https://{домен}{путь}", агент)
        if код == 200 and постеры_страницы(html, 1):
            собрано.append(("каталог", f"https://{домен}{путь}", html))
            break
    else:
        собрано.append(("каталог", "", ""))

    ссылка = ""
    for вид, url, html in собрано:
        м = ССЫЛКА_ТАЙТЛА.search(html or "")
        if м:
            ссылка = м.group(1)
            break
    if ссылка:
        код, html = страница(f"https://{домен}{ссылка}", агент)
        собрано.append(("карточка", f"https://{домен}{ссылка}",
                        html if код == 200 else ""))
    else:
        собрано.append(("карточка", "", ""))
    return собрано


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--all", action="store_true")
    р.add_argument("--per-page", type=int, default=2)
    р.add_argument("--csv", default="")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    #: Сказать о нехватке PIL ОДИН раз и громко. Без этого та же причина
    #: печаталась в каждой строке как «НЕ ИЗМЕРЕНО: ModuleNotFoundError», и
    #: читатель видел шесть одинаковых отказов вместо одной названной причины.
    try:
        import PIL  # noqa: F401
    except ImportError as сбой:
        print(f"ВНИМАНИЕ: пиксели измерены НЕ БУДУТ — {type(сбой).__name__}:"
              f" {сбой}. {ГДЕ_PIL}")

    цели = [(с, и, д) for с, и, д in домены()
            if а.all or д in а.domain] or []
    if not цели:
        print("нужен --domain или --all")
        return 2


    строки: list[dict] = []
    измеренные: dict[str, dict] = {}
    for семейство, сайт, домен in цели:
        for профиль, агент in (("стол", АГЕНТ_СТОЛ), ("моб", АГЕНТ_МОБ)):
            for вид, url, html in страницы_домена(домен, агент):
                if not html:
                    строки.append({"семейство": семейство, "сайт": сайт,
                                   "домен": домен, "профиль": профиль,
                                   "вид": вид, "страница": url,
                                   "исход": "НЕ ИЗМЕРЕНО",
                                   "почему": "страница не ответила 200"})
                    continue
                for п in постеры_страницы(html, а.per_page):
                    полный = абсолютный(п["src"], домен)
                    ключ = f"{полный}|{агент}"
                    if ключ not in измеренные:
                        измеренные[ключ] = изображение(полный, агент)
                    изм = измеренные[ключ]
                    запись = {"семейство": семейство, "сайт": сайт,
                              "домен": домен, "профиль": профиль, "вид": вид,
                              "страница": url, "адрес_картинки": полный,
                              "признак_отбора": п["признак"],
                              "объявлено_w": п["width"],
                              "объявлено_h": п["height"],
                              "srcset": п["srcset"][:200],
                              "sizes": п["sizes"], "loading": п["loading"],
                              "свой_хост": "да" if домен in полный else "нет"}
                    if not изм.get("ок"):
                        запись["исход"] = "НЕ ИЗМЕРЕНО"
                        запись["почему"] = изм.get("почему", "")
                        строки.append(запись)
                        continue
                    запись.update({"код": изм["код"], "тип": изм["тип"],
                                   "байт": изм["байт"], "формат": изм["формат"],
                                   "пиксели_w": изм["ширина"],
                                   "пиксели_h": изм["высота"]})
                    try:
                        объявл = int(п["width"] or 0)
                    except ValueError:
                        объявл = 0
                    if изм["ширина"] and объявл:
                        запас = изм["ширина"] / объявл
                        запись["запас_к_объявленному"] = round(запас, 2)
                        запись["исход"] = ("ИЗБЫТОК" if запас > ПОРОГ_DPR2
                                           else "в пределах DPR2")
                    else:
                        запись["исход"] = "НЕ ИЗМЕРЕНО"
                        запись["почему"] = (изм.get("почему_без_пикселей")
                                            or "в разметке нет width")
                    строки.append(запись)

    поля = ["семейство", "сайт", "домен", "профиль", "вид", "страница",
            "адрес_картинки", "признак_отбора", "свой_хост", "код", "тип",
            "формат", "байт", "пиксели_w", "пиксели_h", "объявлено_w",
            "объявлено_h", "запас_к_объявленному", "srcset", "sizes",
            "loading", "исход", "почему"]
    if а.csv:
        with open(а.csv, "w", newline="", encoding="utf-8") as ф:
            п = csv.DictWriter(ф, fieldnames=поля, extrasaction="ignore")
            п.writeheader()
            for с in строки:
                п.writerow(с)
        print(f"CSV: {а.csv} — строк {len(строки)}")
    if а.json:
        print(json.dumps(строки, ensure_ascii=False, indent=1))
    else:
        измерено = [с for с in строки if с["исход"] != "НЕ ИЗМЕРЕНО"]
        избыток = [с for с in измерено if с["исход"] == "ИЗБЫТОК"]
        print(f"строк {len(строки)}: измерено {len(измерено)},"
              f" не измерено {len(строки) - len(измерено)};"
              f" ИЗБЫТОК разрешения {len(избыток)}")
        print("запас считается от ОБЪЯВЛЕННОГО места показа и это оценка СНИЗУ:"
              " CSS и object-fit могут показывать картинку меньше.")
        for с in строки[:40]:
            if с["исход"] == "НЕ ИЗМЕРЕНО":
                print(f"  {с['домен']:22} {с['профиль']:4} {с['вид']:9}"
                      f" НЕ ИЗМЕРЕНО: {с.get('почему','')[:70]}")
                continue
            print(f"  {с['домен']:22} {с['профиль']:4} {с['вид']:9}"
                  f" {с['формат']:5} {с['байт']:7} Б"
                  f" {с['пиксели_w']}x{с['пиксели_h']}"
                  f" при {с['объявлено_w']}x{с['объявлено_h']}"
                  f" запас x{с.get('запас_к_объявленному','—')}"
                  f" {с['исход']}")
    if not [с for с in строки if с["исход"] != "НЕ ИЗМЕРЕНО"]:
        return 2
    return 1 if [с for с in строки if с["исход"] == "ИЗБЫТОК"] else 0


if __name__ == "__main__":
    sys.exit(главное())
