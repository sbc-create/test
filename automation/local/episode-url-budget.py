"""Сколько адресов серий добавила бы карта семейства Lords (MOD-79).

Запись MOD-79 измерена: слой карты не выпускает адресов серий ни доступных, ни
пустых. Прежде чем это менять, нужен БЮДЖЕТ: сколько адресов добавится, сколько
файлов карты это даст и какие из них индексируемы. Правка без этого числа —
обещание, а не план: у Yummy, где серии в карте есть, это 123 188 адресов на
7 386 произведений.

Считается по боковому файлу подробностей, потоком и без разбора всего файла в
память: суммируются объявленные `avail` (сколько серий доступно) и `eps`
(сколько объявлено). Индексируема страница серии только при наличии дорожки —
правка 18.10 закрыла пустые серии `noindex, follow`, поэтому в карту имеет
право идти ТОЛЬКО доступное.
"""
import pathlib
import re
import sys

ПУТЬ = (sys.argv[1] if len(sys.argv) > 1
        else "/srv/site-1lordserials1-online/data/lords-03-details.json")
ПРЕДЕЛ_ФАЙЛА = 50000          # максимум адресов в одном файле карты

ф = pathlib.Path(ПУТЬ)
размер = ф.stat().st_size
avail = eps = сезонов = 0
образец_avail = re.compile(rb'"avail"\s*:\s*(\d+)')
образец_eps = re.compile(rb'"eps"\s*:\s*(\d+)')
хвост = b""
прочитано = 0
with ф.open("rb") as поток:
    while кусок := поток.read(8 << 20):
        прочитано += len(кусок)
        данные = хвост + кусок
        for м in образец_avail.finditer(данные):
            avail += int(м.group(1))
        for м in образец_eps.finditer(данные):
            eps += int(м.group(1))
            сезонов += 1
        хвост = данные[-64:]

print(f"файл {ф.name}: {размер / 2**20:.0f} МиБ, прочитано "
      f"{прочитано / 2**20:.0f} МиБ")
print(f"сезонов в подробностях: {сезонов}")
print(f"серий объявлено (сумма eps):   {eps}")
print(f"серий доступно (сумма avail):  {avail}")
print()
print(f"адресов серий, имеющих право на карту (доступные): {avail}")
print(f"файлов карты по {ПРЕДЕЛ_ФАЙЛА}: "
      f"{(avail + ПРЕДЕЛ_ФАЙЛА - 1) // ПРЕДЕЛ_ФАЙЛА}")
print(f"недоступных серий, которые в карту идти НЕ должны "
      f"(noindex, follow с 18.10): {max(0, eps - avail)}")
