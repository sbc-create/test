#!/usr/bin/env python3
"""Откуда пробел постеров: поставщик, ввоз или сопоставление. Только чтение.

Вопрос поставлен линией SEO по 14 карточкам `lordserial33.biz` и имеет ровно
три версии. Инструмент отвечает на все три числами, а не рассуждением:

1. ОТВЕТ ПОСТАВЩИКА — сколько записей в его кеше без `poster_url`;
2. ПРАВИЛО ВВОЗА — сколько записей без постера в ДОСТАВЛЕННОМ каталоге. Если
   числа из (1) и (2) совпадают, ввоз не теряет ничего; если в каталоге больше,
   теряет именно он;
3. СОПОСТАВЛЕНИЕ — есть ли у записей без постера внешние идентификаторы. Если
   есть, произведение найдено верно и дело не в сопоставлении.

Отдельно печатается МЕХАНИЗМ: сравнение двух групп по всем полям ответа. У
lords-02 измерено 20.10 — у записей без постера `kinopoisk_rating` непусто в
1.5 % против 38.8 %, `year` в 62.1 % против 96.4 %. То есть у поставщика беднее
ВСЯ карточка, а не только картинка.

И печатается то, что признаком НЕ является: `licensed` стоит `False` у всех
67 685 записей каталога, поэтому по нему ничего не различить. Поле, у которого
одно значение на всю совокупность, вывода не несёт, и проход говорит это сам.

    python3 automation/local/poster-source-gap.py \\
        --provider /srv/site-factory/repo/var/lords/lords/catalog-cache/lords-02.json \\
        --delivered /srv/lords/.frontend/lords-02-catalog.json
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

#: Разница долей, при которой поле считается РАЗЛИЧАЮЩИМ группы.
#: Порог назван числом: измеренные различающие поля дают 25-37 пунктов
#: (`kinopoisk_rating` 1.5 против 38.8, `year` 62.1 против 96.4), а
#: неразличающие — 0-6 (`imdb_rating` 37.6 против 58.0 близко, и он намеренно
#: НЕ объявляется различающим: 20 пунктов при 37 % основе — слабый сигнал).
РАЗЛИЧАЕТ_ПУНКТОВ = 25


def загрузить(путь: Path) -> dict:
    return json.loads(путь.read_text(encoding="utf-8"))


def записи(д: dict | list) -> list[dict]:
    if isinstance(д, list):
        return [з for з in д if isinstance(з, dict)]
    for ключ in ("items", "records", "catalog"):
        если = д.get(ключ)
        if isinstance(если, list):
            return [з for з in если if isinstance(з, dict)]
    return []


def без_постера(набор: list[dict], поле: str) -> list[dict]:
    return [з for з in набор if not str(з.get(поле) or "").strip()]


def доли_полей(группа: list[dict], поля: list[str]) -> dict[str, float]:
    if not группа:
        return {}
    итог = {}
    for п in поля:
        непустых = sum(1 for з in группа
                       if з.get(п) not in (None, "", [], {}))
        итог[п] = непустых * 100 / len(группа)
    return итог


def разобрать(поставщик: list[dict], доставлено: list[dict]) -> dict:
    """Три версии и механизм — числами."""
    п_без = без_постера(поставщик, "poster_url")
    д_без = без_постера(доставлено, "poster")
    поля = sorted({к for з in поставщик[:500] for к in з} - {"poster_url"})
    с_постером = [з for з in поставщик
                  if str(з.get("poster_url") or "").strip()]
    без_доли = доли_полей(п_без, поля)
    с_доли = доли_полей(с_постером, поля)
    различают = sorted(
        (п for п in поля
         if abs(без_доли.get(п, 0) - с_доли.get(п, 0)) >= РАЗЛИЧАЕТ_ПУНКТОВ),
        key=lambda п: -abs(без_доли.get(п, 0) - с_доли.get(п, 0)))
    одно_значение = [п for п in поля
                     if len({json.dumps(з.get(п), ensure_ascii=False,
                                        sort_keys=True)
                             for з in поставщик[:2000]}) == 1]
    с_внешними = sum(1 for з in п_без if з.get("external_ids"))
    return {
        "поставщик_всего": len(поставщик),
        "поставщик_без_постера": len(п_без),
        "доставлено_всего": len(доставлено),
        "доставлено_без_постера": len(д_без),
        "теряет_ввоз": len(д_без) - len(п_без),
        "без_постера_с_внешними_ид": с_внешними,
        "различающие_поля": [
            {"поле": п, "без_постера_%": round(без_доли.get(п, 0), 1),
             "с_постером_%": round(с_доли.get(п, 0), 1)} for п in различают],
        "поля_с_одним_значением": одно_значение,
    }


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--provider", required=True)
    р.add_argument("--delivered", required=True)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    пп, дп = Path(а.provider), Path(а.delivered)
    for путь in (пп, дп):
        if not путь.exists():
            print(f"НЕ ИЗМЕРЕНО: нет файла {путь}")
            return 2
    сырой_п = загрузить(пп)
    поставщик, доставлено = записи(сырой_п), записи(загрузить(дп))
    if not поставщик or not доставлено:
        print("НЕ ИЗМЕРЕНО: в одном из файлов нет списка записей")
        return 2

    итог = разобрать(поставщик, доставлено)
    снято = сырой_п.get("fetched_at_ms") if isinstance(сырой_п, dict) else None
    если_время = (dt.datetime.fromtimestamp(снято / 1000, dt.timezone.utc)
                  .isoformat() if снято else "—")
    if а.json:
        print(json.dumps({**итог, "ответ_поставщика_снят": если_время},
                         ensure_ascii=False, indent=1))
        return 1 if итог["поставщик_без_постера"] else 0

    print(f"ответ поставщика снят: {если_время}")
    print(f"у поставщика записей {итог['поставщик_всего']}, "
          f"без poster_url {итог['поставщик_без_постера']} "
          f"({итог['поставщик_без_постера'] * 100 / итог['поставщик_всего']:.2f} %)")
    print(f"в доставленном каталоге {итог['доставлено_всего']}, "
          f"без poster {итог['доставлено_без_постера']}")
    if итог["теряет_ввоз"] > 0:
        print(f"   ВВОЗ ТЕРЯЕТ {итог['теряет_ввоз']} постеров: в каталоге без"
              f" постера больше, чем в ответе поставщика")
    elif итог["теряет_ввоз"] < 0:
        print(f"   ввоз ДОБАВИЛ {-итог['теряет_ввоз']} постеров (наследование"
              f" от прежнего снимка)")
    else:
        print("   ввоз не теряет и не добавляет: числа совпадают")
    print(f"из записей без постера имеют внешние идентификаторы: "
          f"{итог['без_постера_с_внешними_ид']} из "
          f"{итог['поставщик_без_постера']} — сопоставление на месте, если это"
          f" почти все")

    print("\nмеханизм — чем записи без постера отличаются у поставщика:")
    if итог["различающие_поля"]:
        for р_ in итог["различающие_поля"]:
            print(f"   {р_['поле']:<20} непусто у без постера"
                  f" {р_['без_постера_%']:>5} %, у с постером"
                  f" {р_['с_постером_%']:>5} %")
    else:
        print("   ни одно поле не различает группы на"
              f" {РАЗЛИЧАЕТ_ПУНКТОВ} пунктов — механизм НЕ установлен")
    if итог["поля_с_одним_значением"]:
        print(f"\nполя с ОДНИМ значением на всю совокупность:"
              f" {', '.join(итог['поля_с_одним_значением'])}")
        print("   вывода они не несут: признак, у которого одно значение у"
              " всех, не умеет отвечать иначе")
    return 1 if итог["поставщик_без_постера"] else 0


if __name__ == "__main__":
    sys.exit(главное())
