#!/usr/bin/env python3
"""Шесть условий правила сборки `description` — на выборке, а не на примере.

Правило: `reports/SEO-PREFLIGHT-20261002/RULE-DESCRIPTION-ASSEMBLY.md` (SEO,
коммит `c7d745f`), §6 «Проверка до выпуска». Здесь исполняются именно его
условия, по одному:

  1 выборка 3000 случайных записей из данных каждого семейства, не пример;
  2 ни одного обрубка: двойной пробел, висящая связка, запятая перед точкой,
    длина меньше 60 знаков, обрезка посередине слова;
  3 ни одного описания из одного фрагмента;
  4 семь доменов — семь разных строк на каждой из 20 проверочных страниц;
  5 заголовок не повторён в начале описания ни на одной записи выборки;
  6 случай В: названо числом, у скольких описание собралось, а у скольких нет.

Инструмент только читает снимки каталога и ничего не публикует. Провал любого
условия — ненулевой код возврата: это ворота перед выпуском, а не отчёт.

    python3 automation/local/description-assembly-check.py
    python3 automation/local/description-assembly-check.py --sample 500
"""
from __future__ import annotations

import argparse
import json
import random
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ / "automation" / "host"))

import description_assembly as СБОРКА  # noqa: E402

СНИМКИ = {
    "zona-01": Path("/srv/zonafilm-space/data/zona-01-details.json"),
    "lords-01": Path("/srv/lordfilm47-space/data/lords-01-details.json"),
}
ДОМЕНЫ = tuple(СБОРКА.ПРОФИЛИ)


def записи(путь: Path, сколько: int, зерно: int) -> list[dict]:
    д = json.loads(путь.read_text(encoding="utf-8"))
    детали = д.get("details") if isinstance(д, dict) else д
    ключи = list(детали)
    random.seed(зерно)
    random.shuffle(ключи)
    выбор = []
    for к in ключи[:сколько]:
        з = детали[к]
        if isinstance(з, dict):
            выбор.append(з)
    return выбор


def обрубки(строка: str) -> list[str]:
    беды = []
    if "  " in строка:
        беды.append("двойной пробел")
    if re.search(r"(,|·|-|—)\s*$", строка):
        беды.append("висящая связка в конце")
    if re.search(r",\s*\.", строка):
        беды.append("запятая перед точкой")
    if re.search(r"·\s*·", строка):
        беды.append("пустой фрагмент между разделителями")
    if строка.endswith("…") or строка.endswith("..."):
        беды.append("многоточие-обрубок")
    if строка and len(строка) < СБОРКА.ДЛИНА_МИН:
        беды.append(f"короче {СБОРКА.ДЛИНА_МИН} знаков")
    if len(строка) > СБОРКА.ДЛИНА_МАКС:
        беды.append(f"длиннее {СБОРКА.ДЛИНА_МАКС} знаков")
    return беды


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--sample", type=int, default=3000)
    р.add_argument("--seed", type=int, default=42)
    р.add_argument("--pages", type=int, default=20)
    опции = р.parse_args(аргв)

    провалы: list[str] = []
    print(f"доменов с профилем: {len(ДОМЕНЫ)}; выборка: {опции.sample}; "
          f"зерно: {опции.seed}\n")

    for семейство, путь in СНИМКИ.items():
        if not путь.is_file():
            провалы.append(f"{семейство}: снимка нет — {путь}")
            continue
        выбор = записи(путь, опции.sample, опции.seed)
        всего = len(выбор)
        пустых = сборок = не_собралось = одно_фрагментных = 0
        повтор_заголовка = 0
        беды_обрубков: list[str] = []
        длины: list[int] = []

        for з in выбор:
            был_текст = bool((з.get("description") or "").strip())
            if not был_текст:
                пустых += 1
            # Домен берётся по кругу, чтобы в выборке участвовали все профили.
            for хост in ДОМЕНЫ:
                строка = СБОРКА.описание({"slug": з.get("id") or ""}, з, хост)
                if not строка:
                    if not был_текст:
                        не_собралось += 1
                    continue
                if not был_текст:
                    сборок += 1
                длины.append(len(строка))
                for б in обрубки(строка):
                    if len(беды_обрубков) < 10:
                        беды_обрубков.append(f"{б}: {строка!r}")
                if СБОРКА.РАЗДЕЛИТЕЛЬ not in строка and not был_текст:
                    одно_фрагментных += 1
                имя = (з.get("name") or "").strip()
                if имя and строка.lower().startswith(имя.lower()):
                    повтор_заголовка += 1

        всего_строк = len(длины)
        print(f"{семейство}: записей {всего}, из них без описания {пустых} "
              f"({100 * пустых / всего:.1f} %)")
        print(f"  строк собрано всего (по всем профилям): {всего_строк}")
        if длины:
            print(f"  длина: минимум {min(длины)}, максимум {max(длины)}, "
                  f"средняя {sum(длины) / len(длины):.0f}")
        # Условие 6: случай В числом.
        попыток_в = пустых * len(ДОМЕНЫ)
        print(f"  случай В: собралось {сборок} из {попыток_в} попыток "
              f"({100 * сборок / попыток_в:.1f} %), не собралось "
              f"{не_собралось} — это измеренная граница данных, не дефект")
        # Условие 2 и 3.
        print(f"  обрубков: {len(беды_обрубков)}; из одного фрагмента: "
              f"{одно_фрагментных}")
        # Условие 5.
        print(f"  описаний, начинающихся с заголовка: {повтор_заголовка}")
        if беды_обрубков:
            провалы.append(f"{семейство}: обрубки — {беды_обрубков[:3]}")
        if одно_фрагментных:
            провалы.append(f"{семейство}: описаний из одного фрагмента "
                           f"{одно_фрагментных}")
        if повтор_заголовка:
            провалы.append(f"{семейство}: заголовок повторён в начале "
                           f"{повтор_заголовка} раз")

        # Условие 4: семь доменов — семь разных строк на проверочных страницах.
        # Условие 4 меряет СОВПАДЕНИЕ непустых строк. Отсутствие описания —
        # не совпадение, а измеренная граница данных (условие 6), и считать
        # его провалом различия значило бы мерить не то: первая версия этой
        # проверки так и делала и показала «4 страницы с совпадением», где
        # на трёх из них описание просто не собралось ни у кого.
        совпадений = 0
        проверено = 0
        неполных = 0
        примеры: list[str] = []
        бедных_совпадений = 0
        for з in выбор[: опции.pages if опции.pages > 0 else len(выбор)]:
            строки = {х: СБОРКА.описание({"slug": з.get("id") or ""}, з, х)
                      for х in ДОМЕНЫ}
            непустые = {х: re.sub(r"\s+", " ", с).strip()
                        for х, с in строки.items() if с}
            if not непустые:
                continue
            проверено += 1
            if len(непустые) < len(ДОМЕНЫ):
                неполных += 1
            по_строке: dict[str, list[str]] = {}
            for х, с in непустые.items():
                по_строке.setdefault(с, []).append(х)
            пары = [(с, хх) for с, хх in по_строке.items() if len(хх) > 1]
            if пары:
                # Условие 4 выполнимо только там, где фрагментов хватает на
                # семь разных порядков. При трёх фрагментах порядков всего
                # шесть, при двух — два: совпадение у какой-то пары доменов
                # тогда неизбежно арифметически, а не по ошибке сборки.
                ф = СБОРКА._фрагменты({"slug": з.get("id") or ""}, з)
                простых = sum(1 for и in ("type", "year", "genres", "countries",
                                          "imdb", "original_name") if ф.get(и))
                if простых >= 4:
                    совпадений += 1
                    if len(примеры) < 3:
                        примеры.append(f"{пары[0][1]} ({простых} фрагм.): "
                                       f"{пары[0][0][:90]}")
                else:
                    бедных_совпадений += 1
        print(f"  страниц проверено на различие: {проверено}; совпадений при "
              f"четырёх и более фрагментах: {совпадений}; совпадений на бедных "
              f"записях (≤3 фрагмента, неизбежно): {бедных_совпадений}; "
              f"страниц, где описание собралось не у всех семи: {неполных}")
        if совпадений:
            провалы.append(f"{семейство}: совпадения на {совпадений} страницах "
                           f"— {примеры}")
        print()

    print(f"провалов условий: {len(провалы)}")
    for п in провалы:
        print(f"   {п}")
    return 1 if провалы else 0


if __name__ == "__main__":
    raise SystemExit(главное())
