#!/usr/bin/env python3
"""Чем витрина закрыта от индексации и прочтёт ли робот этот запрет.

Только чтение публичных адресов и реестра ячеек.

ПОВОД. Официальная документация Яндекса («Метатеги, которые учитывает Яндекс»,
прочитана 21.10) говорит две вещи, которые меняют оценку закрытости:

1. «Если страница запрещена в файле robots.txt, то директива метатега или
   заголовка **не действует**». Значит `noindex` на странице, обход которой
   запрещён, роботом НЕ ЧИТАЕТСЯ: закрытость держится только на запрете
   обхода, а адрес всё равно может быть известен поиску.
2. «**Разрешающие директивы имеют приоритет** в сочетании с запрещающими».
   Значит явный `index`/`all` в заголовке рядом с `noindex` в метатеге
   открывает страницу, а не закрывает.

Отсюда исходы, и ни один не подменяет другой:

* ``ЗАКРЫТО НАДЁЖНО``       — запрет в метатеге или заголовке, и обход
  robots.txt РАЗРЕШЁН, то есть робот этот запрет прочтёт;
* ``ЗАПРЕТ НЕ ПРОЧИТАЕТСЯ`` — запрет есть, но обход той же страницы запрещён
  в robots.txt: по источнику директива не действует;
* ``ЗАКРЫТО ТОЛЬКО ОБХОДОМ``— обход запрещён, запрета индексации на странице
  нет;
* ``РАЗРЕШАЮЩАЯ ПОБЕЖДАЕТ``  — явный `index`/`all` рядом с `noindex`/`none`;
* ``ОТКРЫТО``               — ни запрета обхода, ни запрета индексации;
* ``НЕ ИЗМЕРЕНО``           — страница или robots.txt не получены.

Отдельно сверяется ЗАМЫСЕЛ из реестра (`indexing.desired_state`,
`indexing.open_authorized`): исход «открыто» у витрины, которая должна быть
закрыта, — расхождение, и наоборот.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `indexing-registry-vs-live.py`, КОТОРЫЙ УЖЕ ЕСТЬ. Тот
сверяет запись реестра с метатегом и заголовком и различает два рода
расхождений (устаревшая запись против открытия без разрешения) — им найден
MOD-71, и дублировать его не нужно. Здесь добавлено третье утверждение:
`robots.txt`. Без него «закрыто» неразличимо: витрина с `noindex` и запретом
обхода выглядит закрытой надёжнее, чем она есть, потому что по источнику её
`noindex` не читается. Расхождение записи с живым режимом эта мера тоже
увидит, но записывать его нужно в MOD-71.

    python3 automation/local/robots-closure-consistency.py [--json]
    python3 automation/local/robots-closure-consistency.py --domain lordfilm.group

Коды: 0 — расхождений с замыслом нет; 1 — есть; 2 — ничего не измерено.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys

РЕЕСТР = pathlib.Path("/home/claude/wt-nova-publish-memory-02/"
                      "config/site-cells.json")

ЗАКРЫТО_НАДЁЖНО = "ЗАКРЫТО НАДЁЖНО"
НЕ_ПРОЧИТАЕТСЯ = "ЗАПРЕТ НЕ ПРОЧИТАЕТСЯ"
ТОЛЬКО_ОБХОД = "ЗАКРЫТО ТОЛЬКО ОБХОДОМ"
РАЗРЕШАЮЩАЯ = "РАЗРЕШАЮЩАЯ ПОБЕЖДАЕТ"
ОТКРЫТО = "ОТКРЫТО"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"

#: Явные запрещающие и явные разрешающие директивы. ОТСУТСТВИЕ директивы
#: разрешающей директивой не является: это не «index», это «ничего не сказано».
#: Пример не выдуманный: цепочка Yummy публичный `X-Robots-Tag` не отдаёт
#: ВОВСЕ, и это решение, записанное в её же конфигурации — приложение само
#: закрывает `/search`, `/admin`, `/dev`, а глобальный `index` на слое nginx
#: перекрыл бы эти решения (MOD-58).
ЗАПРЕЩАЮЩИЕ = ("noindex", "none")
РАЗРЕШАЮЩИЕ = ("index", "all")


def директивы(строка: str) -> set[str]:
    """Директивы из значения `robots`. `nofollow` к индексации не относится."""
    если = {ч.strip().lower() for ч in re.split(r"[,\s]+", строка or "") if ч}
    return {д for д in если if д in ЗАПРЕЩАЮЩИЕ + РАЗРЕШАЮЩИЕ}


def обход_запрещён(robots_txt: str, путь: str = "/") -> bool:
    """Запрещает ли robots.txt обход пути для `*` или `Yandex`.

    Разбор нарочно грубый и осторожный: учитываются группы `*` и `Yandex`,
    `Allow` считается исключением из `Disallow` по длине правила, как это
    описано в том же источнике.
    """
    группа_наша = False
    правила: list[tuple[str, bool]] = []
    for строка in (robots_txt or "").splitlines():
        строка = строка.split("#", 1)[0].strip()
        if not строка or ":" not in строка:
            continue
        поле, _, значение = строка.partition(":")
        поле, значение = поле.strip().lower(), значение.strip()
        if поле == "user-agent":
            группа_наша = значение == "*" or значение.lower().startswith("yandex")
        elif поле in ("disallow", "allow") and группа_наша:
            if поле == "disallow" and значение == "":
                continue  # пустой Disallow — это разрешение
            правила.append((значение, поле == "disallow"))
    подходящие = [(ш, з) for ш, з in правила
                  if путь.startswith(ш.rstrip("*")) or ш in ("/", "*")]
    if not подходящие:
        return False
    # Самое длинное правило сильнее; при равной длине разрешение сильнее.
    подходящие.sort(key=lambda п: (len(п[0]), п[1]))
    return подходящие[-1][1]


def сверить(замер: dict, замысел: str) -> dict:
    """Исход и расхождение с замыслом. Чистая функция."""
    if замер.get("ошибка"):
        return {"исход": НЕ_ИЗМЕРЕНО, "почему": замер["ошибка"],
                "расхождение": False}

    из_мета = директивы(замер.get("мета_robots", ""))
    из_заголовка = директивы(замер.get("x_robots_tag", ""))
    все = из_мета | из_заголовка
    запрет = bool(все & set(ЗАПРЕЩАЮЩИЕ))
    разрешение = bool(все & set(РАЗРЕШАЮЩИЕ))
    запрещён_обход = bool(замер.get("обход_запрещён"))

    if запрет and разрешение:
        исход = РАЗРЕШАЮЩАЯ
        почему = (f"рядом стоят {sorted(все & set(РАЗРЕШАЮЩИЕ))} и"
                  f" {sorted(все & set(ЗАПРЕЩАЮЩИЕ))}; по источнику побеждает"
                  f" разрешающая")
    elif запрет and запрещён_обход:
        исход = НЕ_ПРОЧИТАЕТСЯ
        почему = ("запрет индексации есть, но обход этой страницы запрещён в"
                  " robots.txt — по источнику директива не действует")
    elif запрет:
        исход = ЗАКРЫТО_НАДЁЖНО
        почему = (f"{sorted(все & set(ЗАПРЕЩАЮЩИЕ))} и обход разрешён —"
                  f" робот этот запрет прочтёт")
    elif запрещён_обход:
        исход = ТОЛЬКО_ОБХОД
        почему = ("обход запрещён в robots.txt, запрета индексации на самой"
                  " странице нет: адрес может остаться известным поиску")
    else:
        исход = ОТКРЫТО
        почему = "ни запрета обхода, ни запрета индексации"

    закрытые_исходы = (ЗАКРЫТО_НАДЁЖНО, НЕ_ПРОЧИТАЕТСЯ, ТОЛЬКО_ОБХОД)
    if замысел == "CLOSED":
        расхождение = исход in (ОТКРЫТО, РАЗРЕШАЮЩАЯ)
    elif замысел == "OPEN":
        расхождение = исход in закрытые_исходы
    else:
        расхождение = False
    return {"исход": исход, "почему": почему, "расхождение": расхождение,
            "замысел": замысел}


def достать(url: str) -> tuple[int, str, str]:
    """Код, заголовки и тело одного адреса."""
    п = subprocess.run(
        ["curl", "-sS", "--max-time", "35", "-D", "-", url],
        capture_output=True, text=True)
    текст = п.stdout or ""
    for разделитель in ("\r\n\r\n", "\n\n"):
        граница = текст.find(разделитель)
        if граница >= 0:
            заголовки, тело = текст[:граница], текст[граница + len(разделитель):]
            break
    else:
        заголовки, тело = текст, ""
    код = 0
    первая = заголовки.splitlines()[0] if заголовки.splitlines() else ""
    м = re.search(r"\s(\d{3})\s?", первая)
    if м:
        код = int(м.group(1))
    return код, заголовки, тело


def замерить(домен: str, путь: str = "/") -> dict:
    код, заголовки, тело = достать(f"https://{домен}{путь}")
    if код == 0:
        return {"домен": домен, "ошибка": "главная не получена"}
    x_robots = ""
    for строка in заголовки.splitlines():
        if строка.lower().startswith("x-robots-tag:"):
            x_robots = строка.split(":", 1)[1].strip()
    мета = re.search(r'name=["\']robots["\'][^>]*content=["\']([^"\']*)',
                     тело, re.I)
    if not мета:
        мета = re.search(r'content=["\']([^"\']*)["\'][^>]*name=["\']robots',
                         тело, re.I)
    код_rt, _, robots_txt = достать(f"https://{домен}/robots.txt")
    return {
        "домен": домен, "путь": путь, "код": код,
        "мета_robots": мета.group(1) if мета else "",
        "x_robots_tag": x_robots,
        "robots_txt_код": код_rt,
        "обход_запрещён": обход_запрещён(robots_txt if код_rt == 200 else "",
                                        путь),
        "robots_txt_строк": len((robots_txt or "").splitlines()),
    }


СОГЛАСИЯ = pathlib.Path("/var/lib/site-cells/owner-consent")


def замысел_ячейки(ячейка: dict, *, согласия: pathlib.Path = СОГЛАСИЯ) -> str:
    """Замысел по индексации: OPEN, CLOSED или «НЕ НАЗВАН».

    ПОРЯДОК ПОЛЕЙ ЗДЕСЬ ВАЖЕН, и первая редакция его перепутала. В реестре у
    шестнадцати ячеек стоит И `desired_state: CLOSED`, И `open_authorized:
    true` со ссылкой на файл согласия владельца. Разрешение сильнее:
    `desired_state` в этих записях — снимок прежнего состояния, а сами витрины
    живут открытыми (измерено 21.10). Если судить по `desired_state`, восемь
    работающих витрин объявляются «расхождением», которого нет.

    Разрешением считается не флаг, а ФАЙЛ согласия: так сказано в самой
    записи («флаг в реестре без него разрешением не считается»).

    Исключение из ПРОДВИЖЕНИЯ замыслом по индексации не является: общий
    профиль шаблона исключается из продвижения, оставаясь открытым (решение
    D208). Поэтому `promotion.excluded` здесь не читается вовсе.
    """
    и = ячейка.get("indexing") or {}
    домен = ячейка.get("domain") or ""
    if и.get("open_authorized") is True:
        ссылка = и.get("open_authorization_ref") or ""
        файл = pathlib.Path(ссылка) if ссылка else (согласия / f"{домен}.json")
        if файл.is_file():
            return "OPEN"
        return "CLOSED"  # флаг без файла согласия разрешением не считается
    if и.get("open_authorized") is False or и.get("desired_state") == "CLOSED":
        return "CLOSED"
    return "НЕ НАЗВАН"


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    ячейки = json.loads(РЕЕСТР.read_text(encoding="utf-8")).get("cells") or []
    по_домену = {я.get("domain"): я for я in ячейки}
    for я in ячейки:
        я.setdefault("domain", "")
    домены = а.domain or [я["domain"] for я in ячейки
                          if я.get("status") == "live"
                          and not str(я.get("domain", "")).endswith(
                              (".localhost", ".localhost.test"))]

    итоги = []
    for домен in домены:
        замер = замерить(домен)
        замер.update(сверить(замер, замысел_ячейки(по_домену.get(домен, {}))))
        итоги.append(замер)

    if а.json:
        print(json.dumps({"витрин": len(итоги), "витрины": итоги},
                         ensure_ascii=False, indent=2))
    else:
        for и in итоги:
            метка = "РАСХОЖДЕНИЕ" if и.get("расхождение") else ""
            print(f"{и['домен']:24} замысел {и.get('замысел', '—'):10}"
                  f" {и['исход']:24} {метка}")
            print(f"{'':24} мета «{и.get('мета_robots', '')}»"
                  f" | X-Robots-Tag «{и.get('x_robots_tag', '')}»"
                  f" | обход запрещён"
                  f" {'да' if и.get('обход_запрещён') else 'нет'}"
                  f" (robots.txt {и.get('robots_txt_код', '—')},"
                  f" строк {и.get('robots_txt_строк', '—')})")
            print(f"{'':24} {и.get('почему', '')}")

    if all(и["исход"] == НЕ_ИЗМЕРЕНО for и in итоги):
        return 2
    return 1 if any(и.get("расхождение") for и in итоги) else 0


if __name__ == "__main__":
    sys.exit(main())
