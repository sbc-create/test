"""Доступность источника у плеера по всей сети — приоритет владельца 2.

ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. `playback-check.py` отвечает на вопрос «играет ли
ЭТА серия», и отвечает дорого: шестнадцать замеров `currentTime` по две секунды.
Вопрос владельца шире — доступен ли плеер НА СЕТИ, — и для него нужен не факт
воспроизведения, а факт наличия источника: витрина либо отдаёт плееру рабочий
источник, либо честно печатает посетителю «Видео для этой серии не пришло».
Первое проверяется за секунды, второе и есть потеря.

ПОЧЕМУ НЕ ДЕШЁВЫМИ ЗАПРОСАМИ. Измерено 23.10: выдача сервера у страницы С
источником и БЕЗ источника различается только идентификатором произведения.
Оба HTML несут все пять значений `data-state` (`awaiting`, `unavailable`,
`nosource`, `idle`, `resolving`) — это словарь состояний для CSS и JS, а не
текущее состояние, — и оба несут идентификатор cdnvideohub. Состояние
выясняется уже в браузере, когда плеер спрашивает поставщика. Значит замер по
HTTP невозможен в принципе, и браузер здесь не роскошь.

ЧЕГО ИНСТРУМЕНТ НЕ ДЕЛАЕТ. Он не спрашивает поставщика напрямую: хост
cdnvideohub не в инвентаре, и обращаться к нему мимо витрины значило бы мерить
не свою поверхность. Он не называет «нет источника» поломкой плеера — витрина
сообщает об этом нарочно, и это состояние данных, а не кода. И он не выдаёт
нерешённое состояние за отказ: исход «не разрешилось» печатается отдельно.

ИСХОДЫ НА СТРАНИЦУ:
  `источник`      — появился `<video>` или кадр плеера с настоящим адресом;
  `нет источника` — витрина показала сообщение посетителю (её текст печатается);
  `не разрешилось`— за отведённое время ни того, ни другого;
  `страница не отдалась` — переход не состоялся (код, таймаут).

КОД ВЫХОДА: 0 — у каждой измеренной витрины источник есть хотя бы на одной
странице выборки; 1 — есть витрина, где источника нет НИ НА ОДНОЙ; 3 — измерить
не удалось нигде (тогда числа ничего не значат, и ноль был бы ложью).
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

from playwright.sync_api import sync_playwright

КОРЕНЬ_ФАБРИКИ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ_ФАБРИКИ))

from factory.seo.render_check import chromium_path  # noqa: E402

#: Те же проверенные формы адреса карточки, что в `playback-check.py`.
ПРЕФИКСЫ = ("/title/", "/anime/")

#: Состояние плеера в живой странице. Читается обходом теневых корней: плеер
#: VK создаёт `<video>` внутри своего shadow DOM, и обычный `querySelector`
#: его не видит.
СОСТОЯНИЕ = """
() => {
  const видео = [];
  const обойти = (корень) => {
    корень.querySelectorAll('video').forEach(в => видео.push({
      t: в.currentTime, ready: в.readyState, src: (в.currentSrc || в.src || '')
    }));
    корень.querySelectorAll('*').forEach(э => {
      if (э.shadowRoot) обойти(э.shadowRoot);
    });
  };
  обойти(document);
  const рамка = document.querySelector('[data-player]');
  const сост = document.querySelector('[data-player-state]');
  const обойти_кадры = (корень) => {
    let n = 0;
    корень.querySelectorAll('iframe').forEach(ф => {
      if ((ф.src || '').includes('cdnvideohub')) n += 1;
    });
    корень.querySelectorAll('*').forEach(э => {
      if (э.shadowRoot) n += обойти_кадры(э.shadowRoot);
    });
    return n;
  };
  const кадры = обойти_кадры(document);
  return {
    state: рамка ? рамка.getAttribute('data-state') : null,
    msg: (сост && !сост.hasAttribute('hidden'))
           ? сост.innerText.trim().slice(0, 160) : '',
    видео: видео.length,
    кадры: кадры
  };
}
"""


def _запрет_счётчиков(цель):
    """Технический прогон не должен попадать в Метрику (требование владельца).

    Модуль один на все браузерные инструменты — `counter_guard.py`.
    """
    import importlib.util
    п = pathlib.Path(__file__).resolve().parent / "counter_guard.py"
    с = importlib.util.spec_from_file_location("counter_guard", п)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м.запретить_счётчики(цель)


def витрины(названные):
    """Домены для замера: названные или все действующие из реестра.

    Домены со состоянием `awaiting_replacement` не берутся: по заданию
    владельца они ждут замены и продвижение по ним не запускается.
    """
    if названные:
        return [д.strip() for д in названные.split(",") if д.strip()]
    реестр = json.loads(
        (КОРЕНЬ_ФАБРИКИ / "config/active-domains.json").read_text("utf-8"))
    ждут = {з["domain"] for з in реестр.get("awaiting_replacement") or []}
    return [з["domain"] for з in реестр["domains"]
            if з.get("state") == "active" and з["domain"] not in ждут]


def страницы_произведений(домен, сколько):
    """Адреса карточек с главной: читаются HTTP-запросом, браузер не нужен."""
    готово = subprocess.run(
        ["curl", "-sS", "--max-time", "30", "--compressed",
         "-A", "factory-player-availability", f"https://{домен}/"],
        capture_output=True, text=True, timeout=60)
    if готово.returncode != 0:
        return [], (готово.stderr or "").strip()[:120]
    пути = []
    for префикс in ПРЕФИКСЫ:
        образец = r'href="(' + re.escape(префикс) + r'[a-z0-9][a-z0-9-]*/?)"'
        for путь in re.findall(образец, готово.stdout):
            чистый = "/" + путь.strip("/") + "/"
            if чистый not in пути:
                пути.append(чистый)
        if пути:
            break
    return пути[:сколько], ""


def читать_пути(путь_файла):
    """Пути из файла: `домен<TAB>путь` или просто `путь` для всех витрин.

    Выборка с главной — это НОВИНКИ, и у новинки источника может не быть
    законно: поставщик её ещё не отдал. Чтобы отделить «витрина не работает»
    от «новинка не доехала», тот же замер нужен на страницах, которые уже
    получают поисковые визиты. Их список приходит сюда файлом.
    """
    по_домену = {}
    общие = []
    for строка in pathlib.Path(путь_файла).read_text("utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        if "\t" in строка:
            домен, путь = строка.split("\t", 1)
            по_домену.setdefault(домен.strip(), []).append(
                "/" + путь.strip().strip("/") + "/")
        else:
            общие.append("/" + строка.strip("/") + "/")
    if общие:
        for домен in по_домену:
            по_домену[домен].extend(общие)
    return по_домену or {"": общие}


def состояние_страницы(контекст, адрес, предел_сек, шаг_мс=500):
    """Дождаться, пока плеер решит: источник, сообщение или ничего."""
    стр = контекст.new_page()
    стр.route("**mc.yandex.*/**", lambda м: м.abort())  # технический прогон не шлёт события в Метрику
    try:
        try:
            стр.goto(адрес, wait_until="load", timeout=45000)
        except Exception as ош:  # noqa: BLE001
            return "страница не отдалась", f"{type(ош).__name__}", {}
        прошло = 0
        последнее = {}
        while прошло < предел_сек * 1000:
            try:
                последнее = стр.evaluate(СОСТОЯНИЕ)
            except Exception:  # noqa: BLE001
                последнее = {}
            # Список кадров Playwright видит кадр плеера независимо от
            # теневого DOM. Без этого инструмент не дал бы ни одного
            # положительного исхода — и не давал: контроль на заведомо
            # играющей странице отвечал «не разрешилось».
            кадры_плеера = [ф for ф in стр.frames
                            if "player.cdnvideohub" in (ф.url or "")]
            if кадры_плеера:
                последнее = dict(последнее or {})
                последнее["кадры"] = max(последнее.get("кадры") or 0,
                                         len(кадры_плеера))
            if последнее.get("msg"):
                return "нет источника", последнее["msg"].splitlines()[0], последнее
            if последнее.get("видео") or последнее.get("кадры"):
                return "источник", "", последнее
            стр.wait_for_timeout(шаг_мс)
            прошло += шаг_мс
        return "не разрешилось", f"{предел_сек} с", последнее
    finally:
        стр.close()


def main():
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--domains", default="",
                   help="список домéнов через запятую; по умолчанию все"
                        " действующие из config/active-domains.json")
    р.add_argument("--titles", type=int, default=3,
                   help="сколько карточек брать с главной каждой витрины")
    р.add_argument("--paths-file", default="",
                   help="файл со списком путей (по одному в строке) вместо"
                        " ссылок с главной; строка вида `домен<TAB>путь`"
                        " задаёт путь конкретной витрине. Нужен, чтобы мерить"
                        " НЕ новинки с главной, а страницы, на которые"
                        " приходят люди из поиска")
    р.add_argument("--control", default="lordserials22.info/title/mentalist",
                   help="страница, которая ЗАВЕДОМО играет: прогоняется первой."
                        " Если источник не разрешился и на ней, замер"
                        " объявляется несостоявшимся целиком, а не «у всех нет"
                        " источника». Пустая строка выключает контроль")
    р.add_argument("--settle", type=int, default=14,
                   help="сколько секунд ждать решения плеера")
    а = р.parse_args()

    хром = chromium_path()
    if not хром:
        print("НЕ ИЗМЕРЕНО: сборка Chromium не найдена")
        raise SystemExit(3)

    заданные = читать_пути(а.paths_file) if а.paths_file else {}
    # Файл путей задаёт и состав витрин. Прежде инструмент шёл по всему
    # реестру и витринам, которых в файле нет, печатал «на главной нет ссылок
    # проверенных форм» — причину, которую он даже не проверял. Ложная причина
    # хуже отсутствия строки.
    только_из_файла = bool(заданные) and not а.domains
    список = ([д for д in заданные if д] if только_из_файла
              else витрины(а.domains))
    print(f"витрин к замеру: {len(список)}, карточек на витрину:"
          f" {а.titles}, предел ожидания: {а.settle} с")
    print()
    print(f'{"витрина":<24} {"источник":>9} {"нет ист.":>9} {"не разр.":>9}'
          f' {"не отдалась":>12}  примечание')

    всего = {}
    без_источника_нигде = []
    измерено = 0
    with sync_playwright() as p:
        браузер = p.chromium.launch(
            executable_path=хром,
            args=["--autoplay-policy=no-user-gesture-required"])
        if а.control:
            к_домен, _, к_путь = а.control.partition("/")
            контекст = браузер.new_context(ignore_https_errors=True)
            контекст.route("**mc.yandex.*/**", lambda м: м.abort())  # технический прогон не шлёт события в Метрику
            _запрет_счётчиков(контекст)
            исход, пояснение, _ = состояние_страницы(
                контекст, f"https://{к_домен}/{к_путь.strip('/')}/", а.settle)
            контекст.close()
            print(f'контроль {а.control}: {исход}'
                  + (f' ({пояснение})' if пояснение else ''))
            if исход != "источник":
                print()
                print("НЕ ИЗМЕРЕНО: страница контроля, которая заведомо"
                      f" играет, дала «{исход}». Значит мерить нечем — среда,"
                      " сеть или предел ожидания, а не витрины. Числа по"
                      " витринам в таком прогоне ничего не значат.")
                браузер.close()
                raise SystemExit(3)
            print()
        for домен in список:
            if заданные:
                пути, сбой = заданные.get(домен, [])[:а.titles], ""
            else:
                пути, сбой = страницы_произведений(домен, а.titles)
            if not пути:
                if заданные:
                    причина = "в файле путей нет строк для этой витрины"
                else:
                    причина = сбой or (
                        "на главной нет ссылок проверенных форм: "
                        + ", ".join(ПРЕФИКСЫ))
                print(f'{домен:<24} {"—":>9} {"—":>9} {"—":>9} {"—":>12}'
                      f'  НЕ ИЗМЕРЕНО: {причина}')
                всего[домен] = None
                continue
            контекст = браузер.new_context(
                ignore_https_errors=True,
                viewport={"width": 1280, "height": 800},
                user_agent=("Mozilla/5.0 (X11; Linux x86_64) "
                            "AppleWebKit/537.36 (KHTML, like Gecko) "
                            "Chrome/140.0 Safari/537.36"))
            контекст.route("**mc.yandex.*/**", lambda м: м.abort())  # технический прогон не шлёт события в Метрику
            _запрет_счётчиков(контекст)
            счёт = {"источник": 0, "нет источника": 0,
                    "не разрешилось": 0, "страница не отдалась": 0}
            заметки = []
            for путь in пути:
                исход, пояснение, _ = состояние_страницы(
                    контекст, f"https://{домен}{путь}", а.settle)
                счёт[исход] += 1
                if исход != "источник":
                    заметки.append(f"{путь} — {исход}"
                                   + (f": {пояснение}" if пояснение else ""))
            контекст.close()
            всего[домен] = счёт
            измерено += 1
            if счёт["источник"] == 0 and счёт["нет источника"]:
                без_источника_нигде.append(домен)
            примечание = заметки[0][:60] if заметки else ""
            print(f'{домен:<24} {счёт["источник"]:>9}'
                  f' {счёт["нет источника"]:>9} {счёт["не разрешилось"]:>9}'
                  f' {счёт["страница не отдалась"]:>12}  {примечание}')
            for з in заметки[1:]:
                print(f'{"":<24} {"":>9} {"":>9} {"":>9} {"":>12}  {з[:60]}')
        браузер.close()

    print()
    if not измерено:
        print("НЕ ИЗМЕРЕНО НИ НА ОДНОЙ ВИТРИНЕ: числа отсутствуют, и ноль"
              " здесь был бы ложью")
        raise SystemExit(3)
    с_источником = sum(1 for с in всего.values() if с and с["источник"])
    страниц = sum(sum(с.values()) for с in всего.values() if с)
    нет = sum(с["нет источника"] for с in всего.values() if с)
    нераз = sum(с["не разрешилось"] for с in всего.values() if с)
    print(f"измерено витрин {измерено} из {len(список)};"
          f" источник есть хотя бы на одной карточке у {с_источником}")
    print(f"страниц проверено {страниц}: без источника {нет},"
          f" не разрешилось {нераз}")
    if not с_источником:
        print("НЕ ИЗМЕРЕНО: источник не разрешился НИ НА ОДНОЙ витрине."
              f" Страниц {страниц}, из них не разрешилось {нераз}. Это не"
              " вывод о витринах: объявлять успех здесь нельзя.")
        raise SystemExit(3)
    if без_источника_нигде:
        print("ВЫВОД: у этих витрин источника нет НИ НА ОДНОЙ карточке"
              f" выборки — {', '.join(без_источника_нигде)}")
        raise SystemExit(1)
    print("ВЫВОД: у каждой измеренной витрины источник есть хотя бы на одной"
          " карточке выборки")
    raise SystemExit(0)


if __name__ == "__main__":
    main()
