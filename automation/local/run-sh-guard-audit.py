#!/usr/bin/env python3
"""Молчащие проверки в `checks/run.sh` ячеек: осиротевшие вызовы и сторож счёта.

Зачем. 12.10 на трёх витринах AnimeGo строка `check "visible-breadcrumbs" …`
стояла в файле, где обёртка называется `step`. bash отвечает «command not
found» с кодом 127 и код прогона от этого НЕ меняется: проверка молчала, а
отсутствие крошек выглядело как исправность. Нашлось это случайно, на полном
прогоне одной ячейки.

Случайность — не способ. Инструмент отвечает на два вопроса по каждой ячейке:

1. есть ли ВЫЗОВЫ обёртки, которой в этом файле не определено (осиротевшие) —
   это и есть молчащая проверка прямо сейчас;
2. есть ли сторож счёта (`checks-all-ran`) — то есть заметит ли сама ячейка
   следующий такой случай без нас.

Первое — дефект, второе — его отсутствие защиты. Разница важна: ячейка без
сторожа сегодня исправна, но следующую скопированную строку проглотит молча.

Ничего не меняет: только читает. Файлы `run.sh` ячеек шаблоном НЕ порождаются
— в них от 12 до 48 проверок, выросших по-своему, — поэтому сторож приходит в
каждую отдельной правкой, а не доставкой шаблона.

    python3 automation/local/run-sh-guard-audit.py
    python3 automation/local/run-sh-guard-audit.py --repos <путь>
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

РЕПОЗИТОРИИ = Path("/home/claude/wt-portable-site-cell-01/var/site-repos")
ОБЁРТКИ = ("check", "step")
СТОРОЖ = "checks-all-ran"


def разобрать(текст: str) -> dict:
    """Определённые обёртки, число вызовов каждой и наличие сторожа."""
    определены = set(re.findall(r"^(%s)\(\)" % "|".join(ОБЁРТКИ),
                                текст, re.M))
    вызовы = {и: len(re.findall(rf"^{и} ", текст, re.M)) for и in ОБЁРТКИ}
    осиротевшие = {и: n for и, n in вызовы.items()
                   if n and и not in определены}
    return {"определены": sorted(определены), "вызовы": вызовы,
            "осиротевшие": осиротевшие, "сторож": СТОРОЖ in текст}


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--repos", type=Path, default=РЕПОЗИТОРИИ)
    опции = р.parse_args(аргв)

    if not опции.repos.is_dir():
        print(f"каталога рабочих копий нет: {опции.repos}", file=sys.stderr)
        return 2

    молчащие: list[str] = []
    без_сторожа: list[str] = []
    всего = 0
    for ячейка in sorted(опции.repos.iterdir()):
        файл = ячейка / "checks" / "run.sh"
        if not файл.is_file():
            continue
        всего += 1
        итог = разобрать(файл.read_text(encoding="utf-8", errors="replace"))
        обёртка = ",".join(итог["определены"]) or "—"
        счёт = " ".join(f"{и}={итог['вызовы'][и]}" for и in ОБЁРТКИ)
        метка = "[!!]" if итог["осиротевшие"] else (
            "[! ]" if not итог["сторож"] else "[ок]")
        строка = (f"   {метка} {ячейка.name:26s} обёртка={обёртка:12s} "
                  f"{счёт:20s} сторож={'есть' if итог['сторож'] else 'НЕТ'}")
        print(строка)
        if итог["осиротевшие"]:
            молчащие.append(ячейка.name)
            for имя, n in sorted(итог["осиротевшие"].items()):
                print(f"        вызовов `{имя}` — {n}, а обёртки `{имя}` в "
                      "файле НЕТ: эти проверки молчат")
        if not итог["сторож"]:
            без_сторожа.append(ячейка.name)

    print(f"\nячеек с `checks/run.sh`: {всего}")
    print(f"молчащие проверки прямо сейчас: {len(молчащие)}")
    for имя in молчащие:
        print(f"   {имя}")
    print(f"без сторожа счёта (следующий такой случай проглотят молча): "
          f"{len(без_сторожа)}")
    if без_сторожа:
        print("   " + ", ".join(без_сторожа))

    if всего == 0:
        print("ни одного run.sh не найдено — это предел измерения, "
              "а не «всё исправно»", file=sys.stderr)
        return 2
    if молчащие:
        return 1
    # Отсутствие сторожа — не провал сегодняшнего состояния, но и не «ок».
    return 3 if без_сторожа else 0


if __name__ == "__main__":
    raise SystemExit(главное())
