#!/usr/bin/env python3
"""Порядок блока обновлений на главной: по дате, по убыванию. Только чтение.

    python3 automation/local/updates-order-check.py <домен> [<домен> …]

Зачем отдельный инструмент. Прежнее наблюдение («на 1lordserials1.online 42 даты
в целом не упорядочены») снято со ВСЕЙ страницы, а на главной несколько блоков:
общий порядок дат по странице ничего не говорит о порядке ВНУТРИ блока
обновлений. Здесь берётся именно блок обновлений — по его заголовку и секции, —
и проверяется порядок его собственных дат.

Исход «блока нет» — не провал: у семейств главные разные, и блока обновлений
может не быть вовсе. Он печатается отдельным словом.
"""
from __future__ import annotations

import re
import subprocess
import sys

#: Как блок обновлений называется у семейств. Заголовок ищется в разметке, а не
#: угадывается по порядку секций.
ЗАГОЛОВКИ = ("Обновления", "Новые серии", "Недавно добавлено", "Новинки",
             "Свежие серии", "Последние поступления")


def достать(url: str, таймаут: int = 60) -> tuple[str, str]:
    г = subprocess.run(["curl", "-sS", "-L", "-w", "\n%{http_code}",
                        "--max-time", str(таймаут), url],
                       capture_output=True, text=True)
    т = г.stdout or ""
    return т.rsplit("\n", 1)[-1], (т[: т.rfind("\n")] if "\n" in т else т)


def блок(страница: str) -> tuple[str, str]:
    """`(заголовок, разметка блока)` или `("", "")`."""
    for имя in ЗАГОЛОВКИ:
        for м in re.finditer(re.escape(имя), страница):
            начало = м.start()
            # Блок — до следующего заголовка второго уровня либо до конца секции.
            след = страница.find("<h2", м.end())
            конец = след if след > 0 else min(len(страница), м.end() + 24000)
            кусок = страница[начало:конец]
            if re.search(r"\d{2}\.\d{2}\.\d{4}|\d{4}-\d{2}-\d{2}", кусок):
                return имя, кусок
    return "", ""


def даты(кусок: str) -> list[tuple[int, int, int]]:
    итог = []
    for д, м, г in re.findall(r"(\d{2})\.(\d{2})\.(\d{4})", кусок):
        итог.append((int(г), int(м), int(д)))
    for г, м, д in re.findall(r"(\d{4})-(\d{2})-(\d{2})", кусок):
        итог.append((int(г), int(м), int(д)))
    return итог


def главная(argv: list[str]) -> int:
    домены = argv[1:]
    if not домены:
        print(__doc__)
        return 2
    плохих = 0
    for домен in домены:
        код, страница = достать(f"https://{домен}/")
        if код != "200":
            print(f"{домен:24} главная код {код} — не проверяется")
            continue
        имя, кусок = блок(страница)
        if not кусок:
            print(f"{домен:24} блока обновлений с датами на главной нет")
            continue
        д = даты(кусок)
        убывает = all(д[i] >= д[i + 1] for i in range(len(д) - 1))
        нарушения = [i for i in range(len(д) - 1) if д[i] < д[i + 1]]
        плохих += int(not убывает)
        print(f"{домен:24} блок «{имя}»: дат {len(д)}, "
              f"{'по убыванию' if убывает else f'НАРУШЕНИЙ порядка {len(нарушения)}'}")
        if нарушения:
            i = нарушения[0]
            print(f"{'':24}    первое: {д[i]} перед {д[i + 1]}")
    print(f"\nдоменов {len(домены)}, с нарушением порядка {плохих}")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv))
