#!/usr/bin/env python3
"""Приёмка T335: выбор варианта обложки ПО МЕСТУ ПОКАЗА на шести окнах.

T335 дала каждому месту показа свою строку `sizes` вместо одной общей:
карусель главной «(min-width:768px) 180px, 120px», сетки главной и карточки
«200/220/180», каталог «150/170/330/180» с кандидатом 720w. Числа взяты из
замера фактических ширин отрисовки.

ЧТО ПРОВЕРЯЕТСЯ, тремя вопросами ведущей линии:

1. карусель на окне 390 должна брать вариант 240, а не 480 — прежняя общая
   строка `sizes=176px` требовала кандидата ≥352 и заставляла брать 480;
2. каталог на окне 700 должен по-прежнему брать 720: там ячейка рисуется
   329 px, и при плотности 2 нужно 658;
3. ни одна обложка не стала растянутой сильнее, чем на контроле.

КАК СЧИТАЕТСЯ. Только строки с НАСТОЯЩИМ выбором браузера (`выбрано`), и
только по ПЕРЕСЕЧЕНИЮ постеров канарейки и контроля: иначе разница наборов
выдаёт себя за разницу доставки. Место показа определяется по классам
предков, а не по классу картинки: на главной и карусель, и сетки носят
`zt__img`.

    python3 automation/local/t335-acceptance.py --after <замер.json>
    python3 automation/local/t335-acceptance.py --after <новый> --before <старый>
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import sys

КАНАРЕЙКА = "animedia.icu"
КОНТРОЛЬ = "animedia.space"
UUID = re.compile(r"([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}"
                  r"-[0-9a-f]{12})")


def место(строка: dict) -> str:
    """Место показа по классам предков. На главной карусель и сетки носят
    один класс картинки, и различить их можно только так."""
    цепь = " ".join(строка.get("предки") or [])
    # Порядок важен: `aeps` (серии) стоит раньше `zsec`, потому что цепочка
    # серий содержит оба. `zg` — класс сетки КАТАЛОГА, и без него каталог
    # уходил в «прочее», а проверка возвращала «строк нет» при живых данных.
    for метка, имя in (("ahero", "карусель"), ("zrl", "карусель"),
                       ("zhub", "подборка"), ("aeps", "серии"),
                       ("zg", "сетка"), ("grid", "сетка"),
                       ("zsec", "сетка")):
        if метка in цепь:
            return имя
    return "прочее"


def ключ(строка: dict) -> str | None:
    м = UUID.search(строка.get("адрес") or "")
    return м.group(1) if м else None


def параметр(адрес: str) -> str:
    return адрес.split("?w=")[1].split("&")[0] if "?w=" in адрес else "без"


def загрузить(путь: pathlib.Path) -> list[dict]:
    строки = [с for с in json.loads(путь.read_text("utf-8"))
              if с.get("показ_ш")]
    с_выбором = [с for с in строки if с.get("выбрано")]
    print(f"строк {len(строки)}, с настоящим выбором браузера"
          f" {len(с_выбором)}")
    if not с_выбором:
        print("ВНИМАНИЕ: поля «выбрано» в выгрузке нет — отличить выбор"
              " браузера от разметки невозможно")
        return строки
    return с_выбором


def справка_выбора(строки: list[dict], страница: str, окно: int,
                   место_показа: str) -> None:
    """Что выбрано на разрезе — БЕЗ вердикта.

    Ожидание для сеток главной после T335 я выдумать не могу: строка там
    «200/220/180», и верный выбор зависит от плотности и ширины. Печатать
    по такому ожиданию ГОДНО/НЕ ГОДНО значило бы выдавать свою догадку за
    приёмку.
    """
    свои = [с for с in строки
            if с["домен"] == КАНАРЕЙКА and с["страница"] == страница
            and с["окно"] == окно and место(с) == место_показа]
    if not свои:
        print(f"   справка {страница}/{место_показа} окно {окно}: строк нет")
        return
    выбор = collections.Counter(параметр(с["адрес"]) for с in свои)
    ширины = collections.Counter(с["показ_ш"] for с in свои)
    print(f"   справка {страница}/{место_показа} окно {окно}:"
          f" обложек {len(свои)}, выбор {dict(выбор)},"
          f" ширина показа {dict(ширины.most_common(2))}")


def проверка_выбора(строки: list[dict], страница: str, окно: int,
                    место_показа: str, ожидание: str) -> bool:
    свои = [с for с in строки
            if с["домен"] == КАНАРЕЙКА and с["страница"] == страница
            and с["окно"] == окно and место(с) == место_показа]
    if not свои:
        print(f"   {страница}/{место_показа} окно {окно}: НЕ ИЗМЕРЕНО —"
              f" строк нет")
        return False
    выбор = collections.Counter(параметр(с["адрес"]) for с in свои)
    доля = выбор.get(ожидание, 0) * 100.0 / len(свои)
    годно = доля >= 80
    print(f"   {страница}/{место_показа} окно {окно}: обложек {len(свои)},"
          f" выбор {dict(выбор)} → ожидался «{ожидание}» у ≥80 %,"
          f" получено {доля:.0f} % — {'ГОДНО' if годно else 'НЕ ГОДНО'}")
    return годно


def карта_разреза(строки: list[dict], домен: str, страница: str,
                  окно: int) -> dict[str, dict]:
    """Постеры одного разреза по UUID. Отдельной функцией, а не замыканием
    внутри цикла: линтер справедливо ловит замыкание на переменных цикла, и
    у меня это уже было в t331-acceptance."""
    итог: dict[str, dict] = {}
    for с in строки:
        if (с["домен"] == домен and с["страница"] == страница
                and с["окно"] == окно and с.get("истинная_ш")):
            к = ключ(с)
            if к:
                итог[к] = с
    return итог


def сумма_веса(строки: list[dict], домен: str, окно: int) -> dict[str, int]:
    """Вес по UUID на главной для одного окна."""
    итог: dict[str, int] = {}
    for с in строки:
        if (с["домен"] == домен and с["страница"] == "главная"
                and с["окно"] == окно and с.get("байт_файла")):
            к = ключ(с)
            if к:
                итог[к] = с["байт_файла"]
    return итог


def растяжение(строки: list[dict]) -> list[str]:
    """Разрезы, где канарейка растягивает хуже контроля (по пересечению)."""
    хуже = []
    for страница in ("главная", "каталог", "карточка"):
        for окно in (390, 700, 768, 1024, 1280, 1440):
            к = карта_разреза(строки, КАНАРЕЙКА, страница, окно)
            ц = карта_разреза(строки, КОНТРОЛЬ, страница, окно)
            общие = sorted(set(к) & set(ц))
            if not общие:
                continue
            кр = sum(1 for п in общие
                     if к[п]["истинная_ш"] < к[п]["нужно_px"])
            цр = sum(1 for п in общие
                     if ц[п]["истинная_ш"] < ц[п]["нужно_px"])
            метка = ("ХУЖЕ" if кр > цр else ("лучше" if кр < цр else "так же"))
            if кр > цр:
                хуже.append(f"{страница} окно {окно}: {кр} из {len(общие)}"
                            f" против {цр}")
            print(f"   {страница:9s} окно {окно:5d} общих {len(общие):3d}"
                  f" растянуто {кр:3d} против {цр:3d} — {метка}")
    return хуже


def вес(строки: list[dict], до: list[dict] | None) -> None:
    """Вес по пересечению: канарейка против контроля и против прошлого."""
    for имя, набор in (("против контроля", строки),
                       ("против прошлого замера", до or [])):
        if not набор:
            continue
        print(f"   {имя}:")
        for окно in (390, 700, 1280):
            if имя == "против контроля":
                a = сумма_веса(строки, КАНАРЕЙКА, окно)
                b = сумма_веса(строки, КОНТРОЛЬ, окно)
            else:
                a = сумма_веса(строки, КАНАРЕЙКА, окно)
                b = сумма_веса(набор, КАНАРЕЙКА, окно)
            общие = set(a) & set(b)
            if not общие:
                continue
            сa = sum(a[п] for п in общие) / 1024
            сb = sum(b[п] for п in общие) / 1024
            тяжелее = sum(1 for п in общие if a[п] > b[п])
            print(f"      главная окно {окно}: общих {len(общие)},"
                  f" {сb:.0f} → {сa:.0f} КиБ"
                  f" ({(сa - сb) * 100.0 / сb:+.1f} %), потяжелевших"
                  f" {тяжелее}")


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--after", required=True)
    р.add_argument("--before", default="")
    а = р.parse_args(аргв)
    после = загрузить(pathlib.Path(а.after))
    до = загрузить(pathlib.Path(а.before)) if а.before else None

    print("=" * 74)
    print("1. ВЫБОР ВАРИАНТА ПО МЕСТУ ПОКАЗА")
    годно = []
    годно.append(проверка_выбора(после, "главная", 390, "карусель", "240"))
    годно.append(проверка_выбора(после, "каталог", 700, "сетка", "720"))
    справка_выбора(после, "главная", 390, "сетка")
    справка_выбора(после, "главная", 1280, "сетка")
    справка_выбора(после, "карточка", 390, "сетка")

    print("=" * 74)
    print("2. РАСТЯЖЕНИЕ ПО ПЕРЕСЕЧЕНИЮ (канарейка против контроля)")
    хуже = растяжение(после)

    print("=" * 74)
    print("3. ВЕС ПО ПЕРЕСЕЧЕНИЮ")
    вес(после, до)

    print("=" * 74)
    print("ИТОГ")
    print(f"   карусель на 390 берёт 240: {'да' if годно[0] else 'НЕТ'}")
    print(f"   каталог на 700 берёт 720: {'да' if годно[1] else 'НЕТ'}")
    print(f"   разрезов хуже контроля: {len(хуже)}"
          + ("" if not хуже else " — " + "; ".join(хуже)))
    всё = all(годно) and not хуже
    print("ЗАВЕРШЕНО: приёмка T335 "
          + ("ПРОЙДЕНА" if всё else "НЕ ПРОЙДЕНА"), file=sys.stderr)
    return 0 if всё else 1


if __name__ == "__main__":
    sys.exit(main())
