#!/usr/bin/env python3
"""Запрет счётчиков для браузерных проверок. Один модуль на все инструменты.

ЗАЧЕМ. Браузерная проверка исполняет JavaScript страницы, а значит исполняет и
счётчик Метрики. Технический просмотр записал бы визит, которого не было, и
испортил бы те самые данные, по которым потом считают трафик. Требование
владельца 23.10: «Технические просмотры не должны отправлять события в
Метрику». Проверено в коде: ни один из браузерных инструментов
(`playback-check.py`, `player-page-probe.py`, `mobile-render-probe.py`,
`browser-audit-cell.py`) счётчики не блокировал.

КАК. Контексту браузера ставится маршрут-перехватчик: запрос к любому хосту из
списка обрывается до отправки (`route.abort()`), и факт обрыва записывается.
Поэтому после прогона видно не «вероятно не отправилось», а список
перехваченного.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДАЁТ. Он не мешает странице СЧИТАТЬ что-то у себя и не
прячет сам факт визита от сервера витрины: запрос к витрине нужен, иначе
проверять нечего. Он блокирует только отправку в сторонние счётчики.

    from counter_guard import запретить_счётчики
    перехвачено = запретить_счётчики(контекст)   # до первого goto
    ...
    print(перехвачено)   # что именно обрвано
"""
from __future__ import annotations

#: Хосты счётчиков. Список закрытый: расширять можно, сокращать нельзя.
#: Каждый добавлен потому, что встречается в разметке наших витрин либо в
#: загружаемых ими скриптах.
СЧЁТЧИКИ = (
    "mc.yandex.ru",
    "mc.yandex.com",
    "yandex.ru/metrika",
    "metrika.yandex.ru",
    "google-analytics.com",
    "googletagmanager.com",
    "analytics.google.com",
    "top-fwz1.mail.ru",
    "counter.yadro.ru",
    "top100.rambler.ru",
    "stat.sputnik.ru",
)


def это_счётчик(адрес: str) -> bool:
    низкий = (адрес or "").lower()
    return any(х in низкий for х in СЧЁТЧИКИ)


def запретить_счётчики(контекст) -> list[str]:
    """Повесить перехват на контекст. Возвращает список, который наполняется.

    Список возвращается ДО прогона и наполняется по ходу: так вызывающий код
    получает не обещание, а запись о том, что было обрвано.
    """
    перехвачено: list[str] = []

    def обработчик(маршрут, запрос):
        if это_счётчик(запрос.url):
            перехвачено.append(запрос.url[:200])
            маршрут.abort()
        else:
            маршрут.continue_()

    контекст.route("**/*", обработчик)
    return перехвачено


if __name__ == "__main__":
    примеры = [
        "https://mc.yandex.ru/watch/113288667",
        "https://www.googletagmanager.com/gtag/js?id=X",
        "https://animedia.icu/poster/01a1.webp",
        "https://poster.cdnvideohub.com/01a1.webp",
    ]
    for а in примеры:
        print(f"{'ОБРЫВ ' if это_счётчик(а) else 'пропуск'}  {а}")
