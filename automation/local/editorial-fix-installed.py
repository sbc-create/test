#!/usr/bin/env python3
"""Установлена ли правка записи редакционных правок — и перечитана ли службой.

Повод. В первой редакции команды установки шагом проверки стоял
`post-integration-check.py`. Он печатает «внедрено во всех службах» и ДО
установки: проверяет он совсем другое — права через живой канал. То есть шаг
проверки ничего не проверял, а отчёт выглядел бы убедительно. Правило проекта
на этот счёт прямое: формулировка «проверено» без запуска — ошибка отчёта.

Что проверяется здесь, тремя независимыми способами:

1. **Код на месте.** В дереве службы `factory/qwen/editorial.py` содержит
   `_живые_правки`, а `factory/cell/editorial_store.py` — чтение живого файла.
   Без этого говорить не о чем.
2. **Состав собирается из живого файла.** Модуль дерева службы импортируется и
   вызывается на временном файле с ручным полем: после «публикации описания»
   поле обязано остаться. Это и есть сам дефект, воспроизведённый на деле, а
   не проверка наличия строки в тексте.
3. **Служба код перечитала.** Время запуска службы позже времени правки
   файлов. Иначе правка лежит на диске, а в памяти работает прежняя.

Пункт 3 требует `systemctl show` — без него проверка честно говорит, что
перезапуск подтвердить не смогла, и возвращает ненулевой код: «не знаю» здесь
не то же самое, что «да».

Только чтение. Постоянные данные сайтов не трогаются: пункт 2 работает на
временном файле в каталоге, созданном этим сценарием.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ДЕРЕВО_ПО_УМОЛЧАНИЮ = Path("/home/claude/wt-portable-site-cell-01")
СЛУЖБА = "site-factory-mcp.service"

ФАЙЛЫ_ПРАВКИ = ("factory/qwen/editorial.py", "factory/cell/editorial_store.py")


def шаг(что: str, ок: bool, подробно: str = "") -> bool:
    метка = "ок " if ок else "НЕТ"
    print(f"   [{метка}] {что}" + (f" — {подробно}" if подробно else ""))
    return ок


def код_на_месте(дерево: Path) -> bool:
    """Самое грубое: есть ли правка в текстах дерева службы."""
    цел = True
    путь = дерево / "factory" / "qwen" / "editorial.py"
    try:
        текст = путь.read_text(encoding="utf-8")
    except OSError as сбой:
        return шаг("код правки в дереве службы", False, f"{путь} — {сбой}")
    цел &= шаг("editorial.py содержит _живые_правки",
               "_живые_правки" in текст)
    # Засев состава живыми полями — не наличие функции, а её ВЫЗОВ в
    # публикации. Функция, которую никто не зовёт, дефект не закрывает.
    цел &= шаг("издатель зовёт _живые_правки при публикации",
               "for ключ, запись in _живые_правки(" in текст)
    return цел


def _модуль(дерево: Path, имя: str, путь: str):
    полный = дерево / путь
    спец = importlib.util.spec_from_file_location(имя, полный)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


def живой_файл_читается(дерево: Path) -> bool:
    """Правка читает ЖИВОЙ файл витрины — на деле, а не по наличию строки.

    Проверяется та самая функция, которой издатель засевает состав перед
    добавлением описаний (`_живые_правки`). Ей подставляется временный файл с
    ручным полем: если функции нет или она живой файл не читает, дефект
    воспроизводится ровно так, как 11 октября.

    Постоянные данные витрин не трогаются: путь доставки подменяется на
    временный файл, и запись не выполняется вовсе — функция только читает.
    """
    sys.path.insert(0, str(дерево))
    try:
        издатель = _модуль(дерево, "_проверка_editorial",
                           "factory/qwen/editorial.py")
    except Exception as сбой:
        return шаг("модуль издателя импортируется", False,
                   f"{type(сбой).__name__}: {сбой}")
    живые = getattr(издатель, "_живые_правки", None)
    if живые is None:
        return шаг("у издателя есть _живые_правки()", False,
                   "правка не установлена: состав собирается из одних своих "
                   "описаний, а файл правок заменяется целиком — значит "
                   "пропадёт ЛЮБАЯ запись наложения, которой нет в списке "
                   "публикуемых описаний. Не гипотеза: ручное название на "
                   "zonafilm.space/title/silsila-badalte-rishton-ka/ уже было "
                   "потеряно прогоном редактора 2026-10-11 13:07Z и "
                   "восстановлено в 17:05Z (причина записана в самом "
                   "наложении). Публикация на витрине, где таких записей нет, "
                   "ущерба не наносит — поэтому «исчезнут на первой "
                   "публикации» было бы сказано шире, чем доказано")

    class Витрина:
        site_id = "проверка"
        domain = "проверка.test"

    живое = {
        "schema_version": 1,
        "site_id": "проверка",
        "overrides": {
            "некий-слаг": {
                "fields": {"name": "Ручное название",
                           "description": "старое описание"},
                "actor": "ЗОНА",
                "reason": "решение D200",
            },
        },
    }
    прежний = getattr(издатель.registry, "путь_доставки", None)
    with tempfile.TemporaryDirectory() as каталог:
        файл = Path(каталог) / "editorial-overrides.json"
        файл.write_text(json.dumps(живое, ensure_ascii=False),
                        encoding="utf-8")
        издатель.registry.путь_доставки = lambda _s, _ф=файл: str(_ф)
        try:
            записи = живые(Витрина())
        except Exception as сбой:
            return шаг("_живые_правки() выполняется", False,
                       f"{type(сбой).__name__}: {сбой}")
        finally:
            if прежний is not None:
                издатель.registry.путь_доставки = прежний

    запись = (записи or {}).get("некий-слаг") or {}
    поля = (запись.get("fields") or {})
    цел = шаг("живой файл прочитан", bool(записи),
              f"записей: {len(записи and записи or {})}")
    цел &= шаг("РУЧНОЕ ПОЛЕ видно издателю перед публикацией",
               поля.get("name") == "Ручное название",
               f"name: {поля.get('name')!r}")
    цел &= шаг("авторство ручного поля сохранено",
               запись.get("actor") == "ЗОНА",
               f"actor: {запись.get('actor')!r}")
    return цел


def служба_перечитала(дерево: Path) -> bool:
    """Запуск службы позже правки файлов — иначе в памяти прежний код."""
    времена = []
    for отн in ФАЙЛЫ_ПРАВКИ:
        путь = дерево / отн
        try:
            времена.append(путь.stat().st_mtime)
        except OSError:
            pass
    if not времена:
        return шаг("время правки файлов известно", False)
    правка = datetime.fromtimestamp(max(времена), tz=timezone.utc)

    try:
        итог = subprocess.run(
            ["systemctl", "show", "-p", "ActiveEnterTimestamp", СЛУЖБА],
            capture_output=True, text=True, timeout=20)
    except Exception as сбой:
        return шаг("перезапуск службы подтверждён", False,
                   f"systemctl недоступен: {type(сбой).__name__}")
    строка = (итог.stdout or "").strip()
    значение = строка.partition("=")[2].strip()
    if итог.returncode or not значение:
        return шаг("перезапуск службы подтверждён", False,
                   "systemctl не дал времени запуска — подтвердить нечем")
    for образец in ("%a %Y-%m-%d %H:%M:%S %Z", "%Y-%m-%d %H:%M:%S %Z"):
        try:
            запуск = datetime.strptime(значение, образец)
            break
        except ValueError:
            запуск = None
    if запуск is None:
        return шаг("перезапуск службы подтверждён", False,
                   f"не разобрал время запуска: {значение!r}")
    запуск = запуск.replace(tzinfo=timezone.utc)
    return шаг("служба запущена ПОСЛЕ правки файлов", запуск > правка,
               f"правка {правка:%Y-%m-%d %H:%M:%S}, запуск "
               f"{запуск:%Y-%m-%d %H:%M:%S}")


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--tree", type=Path, default=ДЕРЕВО_ПО_УМОЛЧАНИЮ,
                   help="дерево службы (по умолчанию wt-portable-site-cell-01)")
    р.add_argument("--skip-service", action="store_true",
                   help="не проверять перезапуск: для прогона до установки")
    а = р.parse_args(аргв)

    print(f"дерево службы: {а.tree}")
    print("1. код правки на месте")
    цел = код_на_месте(а.tree)
    print("2. живой файл читается перед публикацией")
    цел &= живой_файл_читается(а.tree)
    if а.skip_service:
        print("3. перезапуск службы — проверка пропущена по --skip-service")
    else:
        print("3. служба перечитала код")
        цел &= служба_перечитала(а.tree)

    print()
    if цел:
        print("ИТОГ: правка записи правок установлена и перечитана службой")
        return 0
    print("ИТОГ: правка НЕ подтверждена — публикации возобновлять нельзя")
    return 1


if __name__ == "__main__":
    sys.exit(главное())
