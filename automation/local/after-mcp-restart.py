#!/usr/bin/env python3
"""Приёмка перезапуска моста одной командой. Только чтение.

Перезапуск `site-factory-mcp` — действие владельца (`systemctl` и `sudo` в
профиле сессии запрещены). А вот проверка после него должна быть одной командой,
иначе «перезапустили» и «работает исправленный код» опять окажутся разными
утверждениями, как 12.10.

Что проверяется по порядку:

1. **процесс новый** — время запуска службы позже времени правки кода
   (`service-code-freshness.py`);
2. **процесс соответствует юниту** — строка запуска живого процесса
   совпадает с ДЕЙСТВУЮЩИМ `ExecStart` (описание юнита плюс
   дополнения, последнее непустое значение выигрывает). Искать
   конкретный флаг нельзя: дополнение `10-write-mode.conf`
   намеренно снимает `--read-only`, иначе мост не смог бы
   публиковать, и проверка по флагу назвала бы правильный
   перезапуск провалом
   (12.10 живой процесс шёл без него, хотя юнит его объявляет);
3. **авторство записей** — снимок `overlay-provenance-diff.py` по всей сети ДО
   первой публикации: эти числа станут основанием для сравнения.

Инструмент НИЧЕГО не перезапускает и не публикует: он печатает состояние и
следующий шаг. Коды: 0 — перезапуск состоялся и проверки пройдены; 1 — ещё нет;
2 — измерить не удалось.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ЮНИТ = "site-factory-mcp.service"


def _запустить(аргументы: list[str], таймаут: int = 600) -> tuple[int, str]:
    г = subprocess.run(аргументы, capture_output=True, text=True, timeout=таймаут)
    return г.returncode, (г.stdout or "") + (г.stderr or "")


def разобрать_свежесть(вывод: str) -> dict:
    """Положительный признак, а не отсутствие плохой строки.

    Первая версия считала измерением любой непустой вывод, и тогда
    остановленная служба («процесс не найден», «не измерено: 1») и падение
    инструмента свежести читались как «перезапуск состоялся». Поэтому здесь
    требуется строка ПРО НАШ ЮНИТ с одним из двух распознанных исходов и
    сводка, в которой неизмеренных служб нет.
    """
    строки = [с for с in вывод.splitlines() if с.startswith(ЮНИТ)]
    if not строки:
        return {"измерено": False, "почему": "строки про юнит в выводе нет",
                "вывод": вывод.strip().splitlines()[:4]}
    строка = строки[0]
    сводка = re.search(r"служб с устаревшим кодом: (\d+); не измерено: (\d+)", вывод)
    if not сводка:
        return {"измерено": False, "почему": "сводки в выводе нет",
                "вывод": вывод.strip().splitlines()[:4]}
    if int(сводка.group(2)):
        return {"измерено": False,
                "почему": f"не измерено служб: {сводка.group(2)} — {строка.split('  ')[-1].strip()}",
                "вывод": вывод.strip().splitlines()[:4]}
    устарел = "ИСПОЛНЯЕТ СТАРЫЙ КОД" in строка
    if not устарел and "код не новее запуска" not in строка:
        return {"измерено": False,
                "почему": f"исход не распознан: {строка.split('  ')[-1].strip()}",
                "вывод": вывод.strip().splitlines()[:4]}
    м = re.search(r"правка новее запуска на ([\d.]+) ч", строка)
    return {"измерено": True, "код_устарел": устарел,
            "отставание_ч": float(м.group(1)) if м else None,
            "вывод": вывод.strip().splitlines()[:4]}


def свежесть_кода() -> dict:
    _, вывод = _запустить([sys.executable,
                           str(КОРЕНЬ / "automation/local/service-code-freshness.py"),
                           "--unit", ЮНИТ])
    return разобрать_свежесть(вывод)


#: Описание юнита и его дополнения. Последний непустой `ExecStart` после
#: очистки — ДЕЙСТВУЮЩАЯ команда запуска.
ЮНИТ_ФАЙЛ = pathlib.Path("/etc/systemd/system/site-factory-mcp.service")
ДОПОЛНЕНИЯ = pathlib.Path("/etc/systemd/system/site-factory-mcp.service.d")


def действующий_execstart(*, юнит: pathlib.Path | None = None,
                          дополнения: pathlib.Path | None = None) -> dict:
    """Команда запуска по описанию юнита С ДОПОЛНЕНИЯМИ, в порядке systemd.

    Почему не искать флаг. Прежняя проверка требовала `--read-only` в строке
    процесса. Это была ОШИБКА, и она пометила бы правильный перезапуск как
    провал: дополнение `10-write-mode.conf` ОЧИЩАЕТ `ExecStart` базового юнита
    и задаёт запуск БЕЗ `--read-only` — намеренно, потому что в режиме только
    чтения мост не может публиковать. Измерено 2026-10-20: базовый юнит несёт
    `--read-only`, дополнение его снимает, и живой процесс соответствует
    дополнению. Значит сверять надо с действующим описанием, а не с флагом,
    выбранным заранее.
    """
    юнит = юнит or ЮНИТ_ФАЙЛ
    дополнения = дополнения or ДОПОЛНЕНИЯ
    файлы = [юнит]
    if дополнения.is_dir():
        файлы += sorted(п for п in дополнения.iterdir()
                        if п.suffix == ".conf")
    команда = ""
    откуда = ""
    прочитано = []
    for ф in файлы:
        try:
            текст = ф.read_text(encoding="utf-8")
        except OSError:
            continue
        прочитано.append(ф.name)
        for строка in текст.splitlines():
            с = строка.strip()
            if not с.startswith("ExecStart="):
                continue
            значение = с.split("=", 1)[1].strip()
            # Пустое значение ОЧИЩАЕТ прежние команды — так устроен systemd.
            команда = значение
            откуда = ф.name
    if not команда:
        return {"измерено": False,
                "почему": f"ExecStart не найден в {прочитано or 'описании юнита'}"}
    return {"измерено": True, "команда": команда, "откуда": откуда,
            "файлы": прочитано}


def командная_строка(*, корень: pathlib.Path | None = None,
                     юнит: pathlib.Path | None = None,
                     дополнения: pathlib.Path | None = None) -> dict:
    """Соответствует ли строка живого процесса действующему описанию юнита."""
    корень = корень or pathlib.Path("/proc")
    описание = действующий_execstart(юнит=юнит, дополнения=дополнения)
    for п in sorted(корень.iterdir(), key=lambda д: д.name):
        if not п.name.isdigit():
            continue
        try:
            строка = (п / "cmdline").read_bytes().replace(b"\0", b" ").decode(
                "utf-8", "replace")
        except OSError:
            continue
        if "factory.qwen.mcp" in строка:
            живая = " ".join(строка.split())
            ожидаемая = " ".join((описание.get("команда") or "").split())
            return {"измерено": True, "pid": п.name,
                    "строка": живая[:160],
                    "ожидаемая": ожидаемая[:160],
                    "откуда": описание.get("откуда"),
                    "совпала": bool(ожидаемая) and живая == ожидаемая,
                    "описание_прочитано": описание.get("измерено", False)}
    return {"измерено": False, "почему": "процесс моста не найден"}


def разобрать_авторство(код: int, вывод: str) -> dict:
    м = re.search(r"измерено (\d+) из (\d+); подмен авторства (\d+)", вывод)
    return {"измерено": bool(м), "код": код,
            "домены": (int(м.group(1)), int(м.group(2))) if м else None,
            "подмен": int(м.group(3)) if м else None,
            "хвост": вывод.strip().splitlines()[-3:]}


def авторство() -> dict:
    код, вывод = _запустить([sys.executable,
                             str(КОРЕНЬ / "automation/local/overlay-provenance-diff.py")])
    return разобрать_авторство(код, вывод)


def вердикт(свежесть: dict, строка: dict, авт: dict) -> tuple[bool, list[str]]:
    """Перезапуск состоялся ТОЛЬКО если пройден каждый из трёх пунктов.

    Пункт 3 требует измеримости, а не нуля подмен: 11 записей уже лежат в
    данных 12–18.10, и обнулить их перезапуск не может — снимок нужен как
    основание сравнения для первой публикации после него.
    """
    почему: list[str] = []
    if not свежесть.get("измерено"):
        почему.append(f"свежесть кода не измерена: {свежесть.get('почему')}")
    elif свежесть.get("код_устарел"):
        отст = свежесть.get("отставание_ч")
        почему.append("служба держит код старше правки"
                      + (f" на {отст} ч" if отст else ""))
    if not строка.get("измерено"):
        почему.append(f"живой процесс моста: {строка.get('почему')}")
    elif not строка.get("описание_прочитано"):
        почему.append("описание юнита не прочитано — соответствие не проверено")
    elif not строка.get("совпала"):
        почему.append(
            f"строка запуска процесса не совпала с действующим описанием юнита"
            f" (ожидалось из {строка.get('откуда')!r}): "
            f"{строка.get('ожидаемая')!r} против {строка.get('строка')!r}")
    if not авт.get("измерено"):
        почему.append("авторство по сети не измерено: снимка ДО публикации нет")
    return (not почему), почему


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="приёмка перезапуска моста")
    р.add_argument("--json", action="store_true")
    дов = р.parse_args(аргв)

    свежесть = свежесть_кода()
    строка = командная_строка()
    авт = авторство()
    перезапущен, почему = вердикт(свежесть, строка, авт)

    if дов.json:
        print(json.dumps({"свежесть": свежесть, "командная_строка": строка,
                          "авторство": авт, "перезапущен": перезапущен,
                          "почему": почему},
                         ensure_ascii=False, indent=2))
    else:
        print("1. код службы против правок:")
        for с in свежесть.get("вывод") or ["— нет вывода"]:
            print(f"      {с}")
        print("2. командная строка живого процесса:")
        if not строка.get("измерено"):
            print(f"      НЕ ИЗМЕРЕНО — {строка.get('почему')}")
        else:
            print(f"      pid {строка['pid']}, строка запуска"
                  f" {'совпала' if строка.get('совпала') else 'НЕ совпала'}"
                  f" с действующим описанием ({строка.get('откуда')})")
            print(f"      {строка['строка']}")
        print("3. подмена авторства по сети (снимок ДО публикации):")
        if not авт.get("измерено"):
            print("      НЕ ИЗМЕРЕНО")
        else:
            изм, всего = авт["домены"]
            print(f"      измерено {изм} из {всего}; подмен {авт['подмен']}")
        print()
        if перезапущен:
            print("ПЕРЕЗАПУСК СОСТОЯЛСЯ. Следующий шаг — по одной витрине:")
            print("   1) линия SEO снимает паузу ТОЛЬКО на zonafilm.space;")
            print("   2) одна публикация описания;")
            print("   3) python3 automation/local/overlay-provenance-diff.py"
                  " --domain zonafilm.space — новых подмен быть не должно;")
            print("   4) затем прогон по всей сети без аргументов и следующая витрина.")
        else:
            print("ПРИЁМКА НЕ ПРОЙДЕНА — пауза публикаций Lords/Zona в силе.")
            for с in почему:
                print(f"   — {с}")
            print("   Блок владельца: docs/OWNER_BLOCK_MCP_RESTART.md")
    if перезапущен:
        return 0
    return 2 if not свежесть.get("измерено") else 1


if __name__ == "__main__":
    sys.exit(main())
