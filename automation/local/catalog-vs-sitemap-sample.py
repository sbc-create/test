#!/usr/bin/env python3
"""Какие именно адреса каталога не названы в карте — выборкой по листалке.

Только чтение публичных страниц.

ЗАЧЕМ. `sitemap-completeness.py` сравнивает ЧИСЛА и на `1lordserials1.online`
упирается в честный тупик: в карте 67 830 адресов при 68 451 объявленных
записях, расхождение 621 (0.9 %). Сам инструмент там и говорит: прежде чем
называть это потерей, у недостающих адресов нужно проверить
ИНДЕКСИРУЕМОСТЬ — страница с `noindex` в карте быть не должна, и её
отсутствие дефектом не является.

Полный обход 2 444 страниц листалки стоит столько же запросов. Поэтому здесь
ВЫБОРКА, и она названа выборкой: страницы берутся равномерно по всему
диапазону с заданным шагом, слаги с них сверяются с множеством адресов карты,
а каждый ненайденный слаг ОТКРЫВАЕТСЯ и классифицируется:

* ``НЕ НАЗВАНА, ИНДЕКСИРУЕМА`` — страница отдаёт 200 и не запрещает
  индексацию: вот это потеря;
* ``НЕ НАЗВАНА, ЗАКРЫТА``      — `noindex`/`none` на самой странице:
  правильное отсутствие в карте;
* ``НЕ НАЗВАНА, НЕ ОТКРЫЛАСЬ`` — код не 200: отдельный исход, в потери не
  записывается без разбора;
* ``НАЗВАНА``                  — адрес в карте есть.

РАЗЛИЧАЮЩИЙ КОНТРОЛЬ. Тот же проход запускается на витрине, у которой числа
СОШЛИСЬ (`--control`). Если метод и там находит ненайденные индексируемые
адреса, он измеряет свою ошибку разбора, а не потерю витрины, и вывод об этом
говорит прямо.

    python3 automation/local/catalog-vs-sitemap-sample.py 1lordserials1.online \\
        --pages 40 --control zonafilm.space

Коды: 0 — потерь в выборке нет; 1 — есть; 2 — не измерено.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile

КАРТОЧКА = re.compile(r'href="(/(?:title|anime|film)/[^"?#]+)"')
АДРЕС_КАРТЫ = re.compile(r"<loc>\s*([^<\s]+)\s*</loc>")
КАРТА_КАРТ = re.compile(r"<sitemap>.*?</sitemap>", re.S)
ЗАПРЕТ = re.compile(r'name=["\']robots["\'][^>]*content=["\']([^"\']*)', re.I)

НАЗВАНА = "НАЗВАНА"
ПОТЕРЯ = "НЕ НАЗВАНА, ИНДЕКСИРУЕМА"
ЗАКРЫТА = "НЕ НАЗВАНА, ЗАКРЫТА"
НЕ_ОТКРЫЛАСЬ = "НЕ НАЗВАНА, НЕ ОТКРЫЛАСЬ"


def выборка_страниц(всего: int, сколько: int) -> list[int]:
    """Номера страниц листалки, равномерно по диапазону, с первой и последней.

    Детерминирована: ни случайности, ни зависимости от времени. Повторный
    прогон обязан взять те же страницы, иначе два прогона несравнимы.
    """
    if всего <= 0 or сколько <= 0:
        return []
    if всего <= сколько:
        return list(range(1, всего + 1))
    if сколько == 1:
        return [1]
    шаг = (всего - 1) / (сколько - 1)
    return sorted({max(1, min(всего, round(1 + i * шаг)))
                   for i in range(сколько)})


def классифицировать(слаг: str, в_карте: bool, код: int,
                     robots: str) -> str:
    """Исход по одному слагу. Чистая функция."""
    if в_карте:
        return НАЗВАНА
    if код != 200:
        return НЕ_ОТКРЫЛАСЬ
    директивы = {ч.strip().lower()
                 for ч in re.split(r"[,\s]+", robots or "") if ч}
    if директивы & {"noindex", "none"}:
        return ЗАКРЫТА
    return ПОТЕРЯ


def достать(url: str, таймаут: int = 50) -> tuple[int, str]:
    with tempfile.NamedTemporaryFile(suffix=".html") as б:
        г = subprocess.run(
            ["curl", "-sS", "-L", "--max-time", str(таймаут), "-o", б.name,
             "-w", "%{http_code}", url], capture_output=True, text=True)
        try:
            код = int((г.stdout or "0").strip()[:3])
        except ValueError:
            код = 0
        with open(б.name, encoding="utf-8", errors="replace") as ф:
            return код, ф.read()


def адреса_карты(домен: str) -> set[str]:
    """Все адреса из карты домена, включая вложенные карты."""
    код, тело = достать(f"https://{домен}/sitemap.xml", таймаут=90)
    if код != 200:
        return set()
    адреса: set[str] = set()
    if КАРТА_КАРТ.search(тело):
        for часть in АДРЕС_КАРТЫ.findall(тело):
            к, т = достать(часть, таймаут=120)
            if к == 200:
                адреса.update(АДРЕС_КАРТЫ.findall(т))
    else:
        адреса.update(АДРЕС_КАРТЫ.findall(тело))
    return {а.split("://", 1)[-1].split("/", 1)[-1].rstrip("/")
            if "://" in а else а.strip("/") for а in адреса}


def страниц_в_листалке(домен: str) -> tuple[int, int]:
    """(объявленных страниц, карточек на первой)."""
    код, тело = достать(f"https://{домен}/catalog/")
    if код != 200:
        return 0, 0
    страницы = [int(н) for н in re.findall(r'href="[^"]*[?&]page=(\d+)"', тело)]
    return (max(страницы) if страницы else 0), len(set(КАРТОЧКА.findall(тело)))


def пройти(домен: str, *, страниц: int, предел_проверок: int = 60) -> dict:
    всего, на_первой = страниц_в_листалке(домен)
    if всего == 0:
        return {"домен": домен, "ошибка": "листалка каталога не прочитана"}
    карта = адреса_карты(домен)
    if not карта:
        return {"домен": домен, "ошибка": "карта не прочитана"}

    номера = выборка_страниц(всего, страниц)
    исходы: dict[str, int] = {}
    примеры: dict[str, list[str]] = {}
    по_страницам: list[dict] = []
    слагов = 0
    проверок = 0
    for номер in номера:
        код, тело = достать(f"https://{домен}/catalog/?page={номер}")
        if код != 200:
            continue
        на_странице = {"страница": номер, "слагов": 0, "вне_карты": 0}
        по_страницам.append(на_странице)
        for путь in dict.fromkeys(КАРТОЧКА.findall(тело)):
            слагов += 1
            на_странице["слагов"] += 1
            ключ = путь.strip("/")
            в_карте = ключ in карта or f"{ключ}/" in карта
            if в_карте:
                исход = НАЗВАНА
            else:
                на_странице["вне_карты"] += 1
                if проверок >= предел_проверок:
                    исход = "НЕ НАЗВАНА, НЕ ПРОВЕРЕНА"
                else:
                    проверок += 1
                    к, т = достать(f"https://{домен}{путь}")
                    м = ЗАПРЕТ.search(т)
                    исход = классифицировать(ключ, False, к,
                                             м.group(1) if м else "")
            исходы[исход] = исходы.get(исход, 0) + 1
            примеры.setdefault(исход, [])
            if исход != НАЗВАНА and len(примеры[исход]) < 5:
                примеры[исход].append(путь)
    return {"домен": домен, "страниц_в_листалке": всего,
            "карточек_на_первой": на_первой, "адресов_в_карте": len(карта),
            "страниц_взято": len(номера), "номера": номера[:12],
            "слагов_в_выборке": слагов, "исходы": исходы, "примеры": примеры,
            "страниц_открыто_для_проверки": проверок,
            "по_страницам": по_страницам}


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("домен")
    р.add_argument("--pages", type=int, default=40)
    р.add_argument("--control", default="")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    итоги = [пройти(а.домен, страниц=а.pages)]
    if а.control:
        итоги.append(пройти(а.control, страниц=max(6, а.pages // 4)))

    if а.json:
        print(json.dumps({"проходы": итоги}, ensure_ascii=False, indent=2))
    else:
        for и in итоги:
            print(f"\n=== {и['домен']}")
            if и.get("ошибка"):
                print(f"   НЕ ИЗМЕРЕНО: {и['ошибка']}")
                continue
            print(f"   листалка объявляет {и['страниц_в_листалке']} страниц,"
                  f" в карте {и['адресов_в_карте']} адресов")
            print(f"   взято страниц {и['страниц_взято']}"
                  f" ({', '.join(str(н) for н in и['номера'])}…),"
                  f" слагов {и['слагов_в_выборке']},"
                  f" открыто для проверки {и['страниц_открыто_для_проверки']}")
            for исход, сколько in sorted(и["исходы"].items(),
                                         key=lambda п: -п[1]):
                строка = f"   {исход:28} {сколько}"
                if и["примеры"].get(исход):
                    строка += f"   например: {', '.join(и['примеры'][исход][:3])}"
                print(строка)
            # Где именно теряется: у свежего конца каталога или по всему
            # диапазону. Без этого «4.7 % потеряно» не указывает на причину.
            вне = [с for с in и.get("по_страницам", []) if с["вне_карты"]]
            if вне:
                print(f"   страниц выборки с потерями: {len(вне)} из"
                      f" {len(и['по_страницам'])};"
                      f" худшие: " + ", ".join(
                          f"стр. {с['страница']} — {с['вне_карты']} из"
                          f" {с['слагов']}"
                          for с in sorted(вне, key=lambda с: -с["вне_карты"])[:4]))

    основной = итоги[0]
    if основной.get("ошибка"):
        return 2
    потери = основной["исходы"].get(ПОТЕРЯ, 0)
    if len(итоги) > 1 and not итоги[1].get("ошибка"):
        контроль = итоги[1]["исходы"].get(ПОТЕРЯ, 0)
        print(f"\nРАЗЛИЧАЮЩИЙ КОНТРОЛЬ ({итоги[1]['домен']}):"
              f" потерь в выборке {контроль}.", end=" ")
        if контроль and потери:
            print("Метод находит потери и там, где числа сошлись —"
                  " значит он измеряет свой разбор, а не витрину.")
            return 2
        print("Метод на сошедшейся витрине потерь не находит.")
    return 1 if потери else 0


if __name__ == "__main__":
    sys.exit(main())
