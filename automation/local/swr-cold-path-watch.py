"""Доказать холодный путь SWR без прогрева: дождаться устаревания инвентаря.

Задание требует проверки ХОЛОДНОГО запроса «без помощи прогрева». Прямо сейчас
инвентарь тёплый (`fresh; age≈300`), и быстрый ответ ничего не доказывает.
TTL — 3600 с, поэтому состояние сменится само примерно через час. Сценарий
ждёт смены и фиксирует ДВА числа одновременно:

* состояние инвентаря (заголовок на порту приложения — край его снимает);
* время ответа ПУБЛИЧНОГО адреса в этот момент.

Смысл исправления именно в том, что при несвежем инвентаре ответ остаётся
быстрым: прежний код строил инвентарь синхронно 40–48 с, а у yummyani7
отдавал 504. Если в момент `stale`/`cold` публичный ответ быстрый — исправление
работает; если медленный или 504 — не работает, и это надо знать.

Выход: 0 — состояние, отличное от `fresh`, поймано и измерено; 3 — за отведённое
время инвентарь не устарел (тогда ничего не доказано, и это сказано прямо).
"""
import re
import subprocess
import sys
import time

ПОРТЫ = {"yummyani.org": 3102, "yummyani.biz": 3103}
ПРЕДЕЛ_С = 4500
ПАУЗА = 60


def состояние(домен: str, порт: int) -> str:
    г = subprocess.run(
        ["curl", "-sS", "-o", "/dev/null", "-D", "-", "--max-time", "90",
         "-H", f"Host: {домен}", f"http://127.0.0.1:{порт}/sitemap/titles.xml"],
        capture_output=True, text=True, timeout=120)
    м = re.search(r"(?im)^x-sitemap-inventory:\s*(.+)$", г.stdout or "")
    return м.group(1).strip() if м else "заголовка нет"


def публичный(домен: str) -> tuple[str, float]:
    г = subprocess.run(
        ["curl", "-sS", "-o", "/dev/null", "-w", "%{http_code} %{time_total}",
         "--max-time", "120", f"https://{домен}/sitemap/titles.xml"],
        capture_output=True, text=True, timeout=150)
    части = (г.stdout or "").split()
    return (части[0] if части else "нет"), (float(части[1]) if len(части) > 1 else -1.0)


конец = time.monotonic() + ПРЕДЕЛ_С
поймано = False
while time.monotonic() < конец:
    строки = []
    for домен, порт in ПОРТЫ.items():
        с = состояние(домен, порт)
        код, сек = публичный(домен)
        строки.append(f"{домен}: {с} | публичный {код} за {сек:.1f} с")
        if not с.startswith("fresh") and с != "заголовка нет":
            поймано = True
    print(f"{time.strftime('%H:%M:%SZ', time.gmtime())} " + " ; ".join(строки),
          flush=True)
    if поймано:
        print("состояние, отличное от fresh, поймано вместе со временем ответа")
        sys.exit(0)
    time.sleep(ПАУЗА)

print(f"за {ПРЕДЕЛ_С} с инвентарь не устарел: холодный путь НЕ проверен")
sys.exit(3)
