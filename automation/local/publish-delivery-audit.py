#!/usr/bin/env python3
"""Сверка доставки каталогов: поколение и содержимое, а не время файла.

    python3 automation/local/publish-delivery-audit.py

Зачем. Прерванный прогон публикации оставляет вопрос «кому доставили»: 9 и 10
октября шаг публикации убивал OOM killer, и ответ по `mtime` был бы неверным —
файл мог быть переписан прежним поколением. Поэтому сверяется ПОКОЛЕНИЕ
(`revision`, `builtAt`, `count` внутри файла) и совпадение каталога с
подробностями, а время файла печатается рядом как справка.

Что печатается:

* поколение production-цели каждой витрины (`/srv/lords/.frontend`);
* контрольные суммы фактических файлов против тех, которые издатель записал в
  свой отчёт, и потоковая проверка, что ни один файл не оборван (`--no-checksums`
  выключает этот раздел, когда нужна только быстрая сверка поколения);
* поколение в каталоге данных каждой ячейки по реестру;
* отставшие ячейки — те, чьё поколение не совпало с production;
* частичные файлы (`*.tmp`, `*.new`) в обоих местах;
* сохранность редакционных правок ячейки (`editorial-overrides.json`) и
  пользовательских данных (`site-data`, `*-community.json`): файл есть, читается
  и не пуст.

Инструмент ТОЛЬКО ЧИТАЕТ. Выход: 0 — все ячейки на поколении production и
частичных файлов нет; 1 — есть отставшие или частичные; 2 — читать нечем.
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import re
import sys
import time

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ФРОНТ = pathlib.Path("/srv/lords/.frontend")
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ОТЧЁТЫ = pathlib.Path("/srv/site-factory/repo/var/lords/publish-reports")

#: Размер куска при потоковом чтении. Файл подробностей витрины — 85–118 МиБ, а
#: на хосте в тесные часы свободно около двух гигабайт: читать такие файлы
#: целиком в память значит повторять ту самую ошибку, которую эта задача
#: устраняет.
КУСОК = 1024 * 1024


def _сумма(путь: pathlib.Path) -> str:
    """sha256 потоком: постоянная память независимо от размера файла."""
    х = hashlib.sha256()
    with путь.open("rb") as ф:
        while кусок := ф.read(КУСОК):
            х.update(кусок)
    return х.hexdigest()


def _целостность(путь: pathlib.Path) -> str:
    """Не оборван ли файл. Потоковый разбор структуры, без построения объектов.

    Проверяется именно то, чем грозит прерванная запись: обрыв на середине.
    Сканер ведёт глубину вложенности и состояние строки и требует, чтобы
    глубина вернулась к нулю ровно на конце файла. Полного разбора значений
    здесь нет сознательно: `json.loads` на файле подробностей стоит больше
    гигабайта оперативной памяти, а усечение он ловит не лучше.
    """
    глубина = 0
    в_строке = экран = False
    открылось = закрылось = False
    последний = ""
    try:
        with путь.open("rb") as ф:
            while кусок := ф.read(КУСОК):
                for б in кусок:
                    з = chr(б)
                    if в_строке:
                        if экран:
                            экран = False
                        elif з == "\\":
                            экран = True
                        elif з == '"':
                            в_строке = False
                        continue
                    if з == '"':
                        в_строке = True
                    elif з in "{[":
                        глубина += 1
                        открылось = True
                    elif з in "}]":
                        глубина -= 1
                        if глубина == 0:
                            закрылось = True
                        if глубина < 0:
                            return "структура нарушена: закрывающая скобка без парной"
                    if not з.isspace():
                        последний = з
    except OSError as ош:
        return f"не читается: {type(ош).__name__}"
    if в_строке:
        return "ОБОРВАН внутри строки"
    if глубина != 0:
        return f"ОБОРВАН: не закрыто вложений {глубина}"
    if not (открылось and закрылось) or последний not in "}]":
        return "не похоже на документ JSON"
    return "цел"


def _поколение_подробностей(путь: pathlib.Path) -> str:
    """`catalog_revision` из файла подробностей, без разбора всего файла.

    Поле лежит в голове документа (издатель пишет ключи по алфавиту), поэтому
    читается первый килобайт, а не восемьдесят мегабайт.
    """
    try:
        with путь.open("rb") as ф:
            голова = ф.read(2048).decode("utf-8", "replace")
    except OSError:
        return ""
    м = re.search(r'"catalog_revision"\s*:\s*"([0-9a-f]{8,64})"', голова)
    return м.group(1) if м else ""


def _последний_отчёт() -> tuple[pathlib.Path | None, dict]:
    if not ОТЧЁТЫ.is_dir():
        return None, {}
    отчёты = sorted(ОТЧЁТЫ.glob("daily-*.json"))
    if not отчёты:
        return None, {}
    путь = отчёты[-1]
    try:
        return путь, json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        print(f"отчёт {путь.name} не читается: {type(ош).__name__}: {ош}",
              file=sys.stderr)
        return путь, {}


def сверить_суммы() -> int:
    """Фактические файлы против сумм, записанных самим издателем.

    Это сильнее сверки поколения: совпадение sha256 означает, что файл на диске
    побайтно тот, который издатель записал и проверил чтением цели. Расхождение
    означает либо чужую запись после публикации, либо повреждение.
    """
    путь, отчёт = _последний_отчёт()
    if not отчёт:
        print("\n=== контрольные суммы: отчёта публикации нет, сверять нечем")
        return 0
    расхождения = 0
    print(f"\n=== контрольные суммы по отчёту {путь.name}")
    print(f"    прогон {отчёт.get('run_id')}: "
          f"{отчёт.get('started_at')} → {отчёт.get('finished_at')}")
    записанные = отчёт.get("written_sha256") or {}
    print("--- production-цели")
    for ключ in sorted(записанные):
        site_id, вид = ключ.rsplit(".", 1)
        файл = ФРОНТ / f"{site_id}-{'catalog' if вид == 'catalog' else 'details'}.json"
        if not файл.exists():
            print(f"   {ключ:22} файла нет: {файл}")
            расхождения += 1
            continue
        факт = _сумма(файл)
        совпало = факт == записанные[ключ]
        цел = _целостность(файл)
        if not совпало or цел != "цел":
            расхождения += 1
        print(f"   {ключ:22} {'совпала' if совпало else 'РАСХОДИТСЯ'}  {цел}"
              + ("" if совпало else f"  факт {факт[:12]} ≠ отчёт {записанные[ключ][:12]}"))
    print("--- каталоги данных ячеек")
    # Поколение берётся из САМОГО опубликованного файла витрины, а не из полей
    # отчёта: сравнивать надо с тем, что лежит в production, иначе сверка
    # измеряет отчёт, а не диск.
    поколения_отчёта = {
        ключ.rsplit(".", 1)[0]: _поколение_подробностей(
            ФРОНТ / f"{ключ.rsplit('.', 1)[0]}-details.json")
        for ключ in записанные if ключ.endswith(".details")}
    for site_id, итог in sorted((отчёт.get("cell_delivery") or {}).items()):
        if "skipped" in итог:
            print(f"   {site_id:12} доставка пропущена: {итог['skipped']}")
            continue
        if "error" in итог:
            print(f"   {site_id:12} ДОСТАВКА ОТКАЗАЛА: {итог['error']}")
            расхождения += 1
            continue
        каталог = pathlib.Path(итог.get("data_dir", ""))
        for вид, сумма in (итог.get("sha256") or {}).items():
            файл = каталог / f"{site_id}-{вид}.json"
            if not файл.exists():
                print(f"   {site_id:12} {вид:8} файла нет: {файл}")
                расхождения += 1
                continue
            try:
                факт = _сумма(файл)
            except PermissionError:
                print(f"   {site_id:12} {вид:8} закрыт правами — не читаем")
                continue
            if факт == сумма:
                print(f"   {site_id:12} {вид:8} совпала   {каталог}")
                continue
            # Расхождение суммы — ещё не повреждение. У файла подробностей
            # ячейки есть законный дописывающий: служба согласования
            # доступности серий (`nova-<домен>-episodes`) правит его каждые
            # пятнадцать минут от учётной записи сайта. Отличить одно от
            # другого можно измеримо: дописывающий сохраняет ПОКОЛЕНИЕ
            # (`catalog_revision` каталога, из которого файл собран) и
            # оставляет файл целым, а повреждение или чужая запись — нет.
            своё = _поколение_подробностей(файл)
            цел = _целостность(файл)
            поколение_prod = (поколения_отчёта.get(site_id) or "")
            законно = (своё and поколение_prod and своё == поколение_prod
                       and цел == "цел")
            if законно:
                print(f"   {site_id:12} {вид:8} дописана ячейкой: поколение то же "
                      f"({своё[:12]}), файл {цел}   {каталог}")
            else:
                расхождения += 1
                print(f"   {site_id:12} {вид:8} РАСХОДИТСЯ  факт {факт[:12]} ≠ "
                      f"отчёт {сумма[:12]}; поколение в файле {своё[:12] or '?'}, "
                      f"в отчёте {поколение_prod[:12] or '?'}; {цел}   {каталог}")
    print(f"\nрасхождений и отказов доставки: {расхождения}")
    return расхождения


def _поколение(путь: pathlib.Path) -> dict:
    """Поколение файла каталога: то, что внутри, а не время на диске."""
    if not путь.is_file():
        return {"есть": False}
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        return {"есть": True, "ошибка": f"{type(ош).__name__}: {ош}"}
    return {"есть": True,
            "revision": str(данные.get("revision") or "")[:12],
            "builtAt": str(данные.get("builtAt") or "")[:19],
            "count": данные.get("count"),
            "mtime": time.strftime("%d.%m %H:%M", time.gmtime(путь.stat().st_mtime))}


def _частичные(каталог: pathlib.Path) -> list[str]:
    if not каталог.is_dir():
        return []
    return sorted([ф.name for ф in каталог.glob("*.tmp")]
                  + [ф.name for ф in каталог.glob("*.new")])


def _данные_посетителей(каталог: pathlib.Path) -> list[str]:
    """Что в этом каталоге принадлежит посетителям и редактору."""
    итог = []
    for образец in ("editorial-overrides.json", "*-community.json", "site-data"):
        for п in sorted(каталог.glob(образец)):
            if п.is_dir():
                сколько = sum(1 for _ in п.rglob("*"))
                итог.append(f"{п.name}/ ({сколько} файлов)")
                continue
            try:
                размер = п.stat().st_size
                json.loads(п.read_text(encoding="utf-8"))
                итог.append(f"{п.name} ({размер} Б, читается)")
            except PermissionError:
                # Хранилище сообщества принадлежит учётной записи сайта и
                # закрыто правами 0600. Это порядок, а не повреждение:
                # проверка его не читает и не должна.
                итог.append(f"{п.name} (закрыт правами, на месте)")
            except (OSError, ValueError) as ош:
                итог.append(f"{п.name} — НЕ ЧИТАЕТСЯ: {type(ош).__name__}")
    return итог


def главное() -> int:
    if not РЕЕСТР.is_file():
        print(f"нет реестра ячеек {РЕЕСТР}", file=sys.stderr)
        return 2
    реестр = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    отставшие, частичные = [], []

    print("=== production-цели")
    поколения_prod = {}
    for ф in sorted(ФРОНТ.glob("*-catalog.json")):
        site_id = ф.name[: -len("-catalog.json")]
        п = _поколение(ф)
        поколения_prod[site_id] = п
        print(f"   {site_id:12} count={str(п.get('count')):>6} "
              f"revision={п.get('revision')} builtAt={п.get('builtAt')} "
              f"файл {п.get('mtime')}")
    мусор = _частичные(ФРОНТ)
    if мусор:
        частичные.append((str(ФРОНТ), мусор))

    print("\n=== каталоги данных ячеек")
    for ячейка in реестр.get("cells") or []:
        site_id = ячейка["site_id"]
        рантайм = ячейка.get("runtime") or {}
        каталог_данных = рантайм.get("data_dir")
        if not каталог_данных:
            continue
        # Доставку ЭТИМ конвейером получает не всякая ячейка: условие то же,
        # что у издателя (`managed_by == cell`, `data_owner == pipeline`).
        # Витрины Yummy наполняет другой механизм, и сравнивать их поколение с
        # production этого конвейера значило бы называть отставанием чужую
        # работу.
        наш_конвейер = (рантайм.get("managed_by") == "cell"
                        and рантайм.get("data_owner") == "pipeline")
        каталог = pathlib.Path(каталог_данных)
        if not каталог.is_dir():
            print(f"   {site_id:12} каталога данных нет: {каталог}")
            continue
        п = _поколение(каталог / f"{site_id}-catalog.json")
        пp = поколения_prod.get(site_id) or {}
        # Признак «витрина этого конвейера» берётся из содержимого, а не из
        # списка в коде: издатель каталога Lords/Zona ставит в файл `revision`,
        # а конвейер Yummy — нет. Так профиль не приходится держать вторым
        # перечнем, который разойдётся с первым.
        наш_конвейер = наш_конвейер and bool(пp.get("revision"))
        if not наш_конвейер:
            метка = "доставка не этим конвейером"
        elif not пp:
            метка = "цели в production нет (заимствованный снимок)"
        else:
            совпало = (п.get("revision") == пp.get("revision")
                       and п.get("builtAt") == пp.get("builtAt")
                       and п.get("count") == пp.get("count"))
            метка = "ок" if совпало else "ОТСТАЁТ"
            if not совпало:
                отставшие.append(site_id)
        print(f"   {site_id:12} count={str(п.get('count')):>6} "
              f"revision={п.get('revision')} builtAt={п.get('builtAt')} "
              f"файл {п.get('mtime')}  {метка}")
        мусор = _частичные(каталог)
        if мусор:
            частичные.append((str(каталог), мусор))
            print(f"                ЧАСТИЧНЫЕ ФАЙЛЫ: {мусор}")
        своё = _данные_посетителей(каталог)
        if своё:
            print(f"                данные посетителей и редактора: {'; '.join(своё)}")

    print(f"\nотстающих ячеек: {len(отставшие)} {отставшие}")
    print(f"мест с частичными файлами: {len(частичные)}")
    for место, файлы in частичные:
        print(f"   {место}: {файлы}")

    расхождения = сверить_суммы() if "--no-checksums" not in sys.argv else 0
    return 1 if (отставшие or частичные or расхождения) else 0


if __name__ == "__main__":
    raise SystemExit(главное())
