#!/usr/bin/env python3
"""Поисковый трафик сети за ДВЕ недели из одной устоявшейся выгрузки.

Только чтение архива выгрузок кабинета. Сегменты и перечень автоматизации
берутся у `traffic-segments.py`, чтобы определение «очищенного» было ОДНО.

ЗАЧЕМ ОДНА ВЫГРУЗКА, А НЕ ДВЕ. Сравнивать окна двух выгрузок нельзя: значение
суток в выгрузке не окончательно, и ранняя неделя оказывается занижена —
измерено `metrika-day-settled.py` (сутки 11.10 читались как 11 % от итога).
Разрез `daily_traffic_profile` выгрузки 19.10 содержит 14 суток, то есть обе
недели задания (05–11.10 и 12–18.10) целиком, и все они устоялись.

ЧТО СЧИТАЕТСЯ РАЗДЕЛЬНО, и почему смешивать нельзя:

* **весь трафик** — то, что на дашборде;
* **очищенный** — без роботов Метрики и без автоматизации по браузеру: у
  `yummyani.site` за 12–18.10 это разница между 88 467 и 16 970 визитами;
* **поиск** — визиты с источником «переход из поисковой системы» ВНУТРИ
  очищенного среза. Брать поиск из общего разреза `по_источнику` — ошибка:
  он считается по всем строкам, включая роботов (моя же, 22.10, исправлена);
* **визиты и посетители** — разные показатели, и посетители здесь не
  печатаются вовсе, чтобы не выдать одно за другое.

Домен без счётчика и домен без разреза дают `НЕ ИЗМЕРЕНО` с причиной и в ноль
не превращаются.

    python3 automation/local/network-search-two-weeks.py
    python3 automation/local/network-search-two-weeks.py --json \\
        --snapshot analytics-2026-10-19.json \\
        --week1 2026-10-05 2026-10-11 --week2 2026-10-12 2026-10-18

Коды: 0 — посчитано; 2 — выгрузки нет или ни один домен не измерен.
"""
from __future__ import annotations

import argparse
import datetime
import importlib.util
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
АРХИВЫ = [
    pathlib.Path("/home/claude/wt-portable-site-cell-01/artifacts/analytics"),
    КОРЕНЬ / "artifacts" / "analytics",
]
ЦЕЛЬ_В_СУТКИ = 5000
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"


def _сегменты_модуль():
    путь = КОРЕНЬ / "automation" / "local" / "traffic-segments.py"
    спец = importlib.util.spec_from_file_location("traffic_segments", путь)
    модуль = importlib.util.module_from_spec(спец)
    assert спец.loader is not None
    спец.loader.exec_module(модуль)
    return модуль


ТС = _сегменты_модуль()


def поиск(источник: str) -> bool:
    """Источник — переход из поисковой системы.

    Признак по названию источника, а не по наличию системы: у строки может
    стоять источник «переход из поисковой системы» без названной системы.
    """
    return "earch engine" in источник or "оисков" in источник


def срез(профиль: list[dict], с: str, по: str, *,
         очищенный: bool) -> list[dict]:
    стр = [x for x in профиль if с <= x["дата"] <= по]
    if очищенный:
        стр = [x for x in стр if x["робот"] != "Robots"
               and not ТС.автоматизация(x["браузер"])]
    return стр


def числа(профиль: list[dict], с: str, по: str) -> dict:
    """Визиты недели по трём срезам плюс поиск внутри очищенного."""
    весь = срез(профиль, с, по, очищенный=False)
    чистый = срез(профиль, с, по, очищенный=True)
    без_роботов = [x for x in весь if x["робот"] != "Robots"]
    return {
        "визиты_весь": sum(x["визиты"] for x in весь),
        "визиты_без_роботов": sum(x["визиты"] for x in без_роботов),
        "визиты_очищенные": sum(x["визиты"] for x in чистый),
        "поиск_весь": sum(x["визиты"] for x in весь if поиск(x["источник"])),
        "поиск_очищенный": sum(x["визиты"] for x in чистый
                               if поиск(x["источник"])),
        "суток_со_строками": len({x["дата"] for x in весь}),
    }


def длина_окна(с: str, по: str) -> int:
    """Сколько СУТОК в окне по календарю, включая оба края."""
    начало = datetime.date.fromisoformat(с)
    конец = datetime.date.fromisoformat(по)
    return max((конец - начало).days + 1, 1)


def прирост(было: float, стало: float) -> float | None:
    """Прирост в процентах; от нуля прирост не считается, а называется None."""
    return ((стало - было) / было * 100) if было else None


def профиль_домена(выгрузка: dict, домен: str) -> tuple[list[dict], str]:
    цель = next((x for x in (выгрузка.get("domains") or [])
                 if x.get("domain") == домен), None)
    if цель is None:
        return [], f"домена {домен} в выгрузке нет"
    м = next((x for x in (цель.get("measurements") or [])
              if x.get("key") == "daily_traffic_profile"), None)
    if м is None:
        return [], "разреза daily_traffic_profile в выгрузке нет"
    if not м.get("measured"):
        return [], str(м.get("reason") or м.get("state")
                       or "разрез не измерен")
    стр = ТС.строки(м.get("value"))
    return стр, "" if стр else "разрез пуст"


def сдвиг_окна(окно: tuple[str, str], суток: int) -> tuple[str, str]:
    """То же окно, сдвинутое на N суток по календарю."""
    д = datetime.timedelta(days=суток)
    return ((datetime.date.fromisoformat(окно[0]) + д).isoformat(),
            (datetime.date.fromisoformat(окно[1]) + д).isoformat())


def устойчивость(профиль: list[dict], неделя1: tuple[str, str],
                 неделя2: tuple[str, str],
                 сдвиги: tuple[int, ...] = (-2, -1, 1, 2)) -> dict:
    """Меняет ли сдвиг окна ЗНАК прироста.

    ПОВОД ИЗМЕРЕННЫЙ, 24.10. По одному окну у `yummyani.site` вышло −30 %, и
    это число я назвала владельцу дважды. На том же ряде 14 суток другие окна
    дают +16,6 %, +2,1 %, −15,3 % и −3,1 % — при разбросе внутри ряда 4,4 раза
    (715 входов 15.10 против 3 113 десятого и 2 921 двадцать третьего). Сам
    ряд волатилен, и сравнение «неделя к неделе» на нём знака не определяет.

    Поэтому процент без этой проверки печатать нельзя: он выглядит как
    измерение тренда, а является выбором окна. Если знак у сдвинутых окон
    расходится, инструмент обязан сказать «тренд не определён», а не назвать
    число.
    """
    базовый = прирост(числа(профиль, *неделя1)["поиск_очищенный"],
                      числа(профиль, *неделя2)["поиск_очищенный"])
    знаки = []
    пробы = []
    for с in сдвиги:
        о1, о2 = сдвиг_окна(неделя1, с), сдвиг_окна(неделя2, с)
        н1 = числа(профиль, *о1)["поиск_очищенный"]
        н2 = числа(профиль, *о2)["поиск_очищенный"]
        if not н1 or not н2:
            continue  # окно вышло за выгрузку: это не расхождение знака
        п = прирост(н1, н2)
        if п is None:
            continue
        пробы.append((с, п))
        знаки.append(1 if п > 0 else (-1 if п < 0 else 0))
    if базовый is not None and пробы:
        знаки.append(1 if базовый > 0 else (-1 if базовый < 0 else 0))
    устойчив = bool(знаки) and len(set(знаки)) == 1
    return {"устойчив": устойчив, "проб": len(пробы), "пробы": пробы,
            "базовый": базовый}


def устойчивость_сети(выгрузка: dict, неделя1: tuple[str, str],
                      неделя2: tuple[str, str],
                      сдвиги: tuple[int, ...] = (-2, -1, 1, 2)) -> dict:
    """Решает ли выбор окна ЗНАК сетевого прироста.

    ПОВОД ИЗМЕРЕННЫЙ, 24.10: сетевые «−9,2 %» я называла владельцу как
    измерение. На тех же данных сдвиг окна даёт +45,6 % (−2 суток) и −30,3 %
    (+2 суток). Сводное число тем опаснее построчного, что по нему судят о
    сети целиком.
    """
    пробы = []
    for с in сдвиги:
        св = свод(разобрать(выгрузка, сдвиг_окна(неделя1, с),
                            сдвиг_окна(неделя2, с)))
        р = св.get("прирост_поиска")
        if р is not None and св.get("поиск_н1"):
            пробы.append((с, р))
    база = свод(разобрать(выгрузка, неделя1, неделя2)).get("прирост_поиска")
    знаки = [1 if п > 0 else (-1 if п < 0 else 0) for _, п in пробы]
    if база is not None and пробы:
        знаки.append(1 if база > 0 else (-1 if база < 0 else 0))
    return {"устойчив": bool(знаки) and len(set(знаки)) == 1,
            "пробы": пробы, "базовый": база}


def разобрать(выгрузка: dict, неделя1: tuple[str, str],
              неделя2: tuple[str, str]) -> list[dict]:
    итоги = []
    for домен in sorted(x.get("domain", "") for x in
                        (выгрузка.get("domains") or [])):
        профиль, почему = профиль_домена(выгрузка, домен)
        if not профиль:
            итоги.append({"домен": домен, "измерено": False,
                          "почему": почему})
            continue
        н1 = числа(профиль, *неделя1)
        н2 = числа(профиль, *неделя2)
        # Делитель — КАЛЕНДАРНАЯ длина недели, а не число суток со строками.
        # Это не отмена правила «пропуск — не ноль»: здесь ноль ИЗМЕРЕН.
        # Метрика не отдаёт нулевых строк, а покрытие окна проверено
        # отдельной мерой (`metrika-day-settled.py`): у всех 17 доменов со
        # счётчиком выгрузка 19.10 покрывает все сутки 05–18.10. Делить на
        # число суток со строками значило бы у домена с тремя пустыми днями
        # завысить среднесуточное почти вдвое.
        дней = длина_окна(*неделя2)
        в_сутки = н2["поиск_очищенный"] / дней
        итоги.append({
            "домен": домен, "измерено": True,
            "неделя1": н1, "неделя2": н2,
            "прирост_очищенных_визитов": прирост(н1["визиты_очищенные"],
                                                 н2["визиты_очищенные"]),
            "прирост_очищенного_поиска": прирост(н1["поиск_очищенный"],
                                                 н2["поиск_очищенный"]),
            "устойчивость_тренда": устойчивость(профиль, неделя1, неделя2),
            "очищенного_поиска_в_сутки": в_сутки,
            "делитель_суток": дней,
            "суток_со_строками_н2": н2["суток_со_строками"],
            "до_цели_в_сутки": ЦЕЛЬ_В_СУТКИ - в_сутки,
        })
    return итоги


def свод(строки: list[dict], *, кроме: str = "") -> dict:
    """Сумма по сети; `кроме` исключает один домен и называется в выводе."""
    взятые = [с for с in строки if с.get("измерено")
              and с["домен"] != кроме]
    if not взятые:
        return {"доменов": 0}
    def сумма(поле, неделя):
        return sum(с[неделя][поле] for с in взятые)
    return {
        "доменов": len(взятые),
        "очищенные_н1": сумма("визиты_очищенные", "неделя1"),
        "очищенные_н2": сумма("визиты_очищенные", "неделя2"),
        "поиск_н1": сумма("поиск_очищенный", "неделя1"),
        "поиск_н2": сумма("поиск_очищенный", "неделя2"),
        "прирост_поиска": прирост(сумма("поиск_очищенный", "неделя1"),
                                  сумма("поиск_очищенный", "неделя2")),
    }


def найти(имя: str) -> pathlib.Path | None:
    for каталог in АРХИВЫ:
        п = каталог / имя
        if п.is_file():
            return п
    return None


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--snapshot", default="analytics-2026-10-19.json")
    р.add_argument("--week1", nargs=2, default=["2026-10-05", "2026-10-11"])
    р.add_argument("--week2", nargs=2, default=["2026-10-12", "2026-10-18"])
    р.add_argument("--without", default="",
                   help="домен, который исключается из отдельной суммы")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    путь = найти(а.snapshot)
    if путь is None:
        print(f"{НЕ_ИЗМЕРЕНО}: выгрузки {а.snapshot} нет в архиве",
              file=sys.stderr)
        return 2
    выгрузка = json.loads(путь.read_text(encoding="utf-8"))
    строки = разобрать(выгрузка, tuple(а.week1), tuple(а.week2))
    измеренные = [с for с in строки if с.get("измерено")]
    if not измеренные:
        print(f"{НЕ_ИЗМЕРЕНО}: ни одного домена с разрезом профиля",
              file=sys.stderr)
        return 2

    if а.json:
        print(json.dumps({
            "выгрузка": а.snapshot, "собрана": выгрузка.get("collected_at"),
            "неделя1": а.week1, "неделя2": а.week2, "строки": строки,
            "сеть": свод(строки),
            "сеть_без": {"домен": а.without,
                         **свод(строки, кроме=а.without)} if а.without else None,
        }, ensure_ascii=False, indent=1))
        return 0

    print(f"выгрузка {а.snapshot}, собрана {выгрузка.get('collected_at')};"
          f" часовой пояс счётчика Europe/Moscow")
    print(f"недели: {а.week1[0]}..{а.week1[1]} против"
          f" {а.week2[0]}..{а.week2[1]}\n")
    print(f"{'домен':22} {'весь н2':>8} {'чист н2':>8} {'поиск н1':>9} "
          f"{'поиск н2':>9} {'Δ поиск':>8} {'в сутки':>8} {'до 5000':>8}")
    for с in строки:
        if not с.get("измерено"):
            print(f"{с['домен']:22} {НЕ_ИЗМЕРЕНО} — {с['почему']}")
            continue
        д = с["прирост_очищенного_поиска"]
        у = с.get("устойчивость_тренда") or {}
        # Процент печатается ТОЛЬКО когда сдвиг окна не меняет знак. Иначе это
        # не измерение тренда, а выбор окна (повод измеренный, 24.10:
        # yummyani.site, −30 % против +16,6 % на том же ряде).
        if д is None:
            знак = "—"
        elif у.get("проб") and not у.get("устойчив"):
            знак = "окно?"
        else:
            знак = f"{д:+.0f}%"
        print(f"{с['домен']:22} {с['неделя2']['визиты_весь']:8.0f} "
              f"{с['неделя2']['визиты_очищенные']:8.0f} "
              f"{с['неделя1']['поиск_очищенный']:9.0f} "
              f"{с['неделя2']['поиск_очищенный']:9.0f} "
              f"{знак:>8} "
              f"{с['очищенного_поиска_в_сутки']:8.0f} "
              f"{с['до_цели_в_сутки']:8.0f}")
        if знак == "окно?":
            пробы = ", ".join(f"сдвиг {сд:+d} сут → {п:+.0f}%"
                              for сд, п in у.get("пробы") or [])
            print(f"{'':22} ТРЕНД НЕ ОПРЕДЕЛЁН: по окну {д:+.0f}%, но"
                  f" {пробы} — знак решает выбор окна, а не данные")

    сеть = свод(строки)
    рост = сеть["прирост_поиска"]
    print(f"\nсеть ({сеть['доменов']} домен(ов) с разрезом):")
    print(f"   очищенные визиты {сеть['очищенные_н1']:.0f} →"
          f" {сеть['очищенные_н2']:.0f}")
    _уст = устойчивость_сети(выгрузка, tuple(а.week1), tuple(а.week2))
    if _уст["пробы"] and not _уст["устойчив"]:
        пробы = ", ".join(f"сдвиг {с:+d} сут → {п:+.1f}%"
                          for с, п in _уст["пробы"])
        print(f"   ТРЕНД СЕТИ НЕ ОПРЕДЕЛЁН: по окну"
              f" {_уст['базовый']:+.1f}%, но {пробы} — знак решает выбор окна,"
              " а не данные")
    print(f"   очищенный поиск  {сеть['поиск_н1']:.0f} →"
          f" {сеть['поиск_н2']:.0f}"
          f" ({'—' if рост is None else format(рост, '+.1f') + ' %'})")
    if а.without:
        б = свод(строки, кроме=а.without)
        рост_б = б["прирост_поиска"]
        print(f"   без {а.without}: очищенный поиск {б['поиск_н1']:.0f} →"
              f" {б['поиск_н2']:.0f}"
              f" ({'—' if рост_б is None else format(рост_б, '+.1f') + ' %'})")
    упали = [с["домен"] for с in измеренные
             if с["неделя2"]["поиск_очищенный"] < с["неделя1"]["поиск_очищенный"]]
    выросли = [с["домен"] for с in измеренные
               if с["неделя2"]["поиск_очищенный"] > с["неделя1"]["поиск_очищенный"]]
    print(f"   очищенный поиск вырос у {len(выросли)}, упал у {len(упали)}"
          f"{': ' + ', '.join(упали) if упали else ''}")
    на_цели = [с["домен"] for с in измеренные
               if с["очищенного_поиска_в_сутки"] >= ЦЕЛЬ_В_СУТКИ]
    print(f"   доменов с ≥{ЦЕЛЬ_В_СУТКИ} очищенных поисковых визитов в сутки:"
          f" {len(на_цели)} — {', '.join(на_цели) or 'ни один'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
