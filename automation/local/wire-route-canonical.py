#!/usr/bin/env python3
"""Вид, заданный МАРШРУТОМ, не попадает в канонический адрес. Перенос по ячейкам.

    python3 automation/local/wire-route-canonical.py --repo var/site-repos/<проект> [--dry-run]
    python3 automation/local/wire-route-canonical.py --all-animedia [--dry-run]

Зачем. У семейств Animedia и AnimeGo маршрут `/movies/` сам подставляет в запрос
`type=movie`, а `/series/` — `type=tv`:

    if обрезанный in self.МАРШРУТЫ_ТИПА:
        зпр = dict(зпр)
        зпр["type"] = [self.МАРШРУТЫ_ТИПА[обрезанный]]

Построитель canonical собирает адрес из ВЫБРАННОГО, и подставленный вид попадает
в него: измерено 2026-10-06 на пяти доменах — `/movies/` объявлял каноническим
`/movies/?type=movie`, `/series/` — `/series/?type=tv`. Читатель этого параметра
не просил, ссылка в навигации ведёт на чистый адрес, и страница объявляет дублем
саму себя. Намерение было обратным — в самом файле написано
«Canonical = own path (/movies/, /series/, /animation/), not a silent rewrite».

Тот же дефект у семейства zona исправлен иначе (там параметр подставлял не
маршрут, а значение по умолчанию у сортировки), и решение общее: отбор помечает
то, что выставил НЕ читатель, а построитель canonical это отбрасывает. Здесь
пометку ставит обработчик — он и подставляет.

Правка идёт тремя точными подменами, и отсутствие любой — ОТКАЗ с названием
места: молчаливая замена «нуля вхождений» выдала бы правку, которой нет.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕПОЗИТОРИИ = КОРЕНЬ / "var" / "site-repos"
ЯЧЕЙКИ = ("animedia-icu", "animedia-space", "an1mego-site", "an1meg0-site",
          "animeg0-site")

#: 1. Обработчик помечает подставленное маршрутом.
ЯКОРЬ_ТИП = """        if обрезанный in self.МАРШРУТЫ_ТИПА:
            зпр = dict(зпр)
            зпр["type"] = [self.МАРШРУТЫ_ТИПА[обрезанный]]
"""
ВСТАВКА_ТИП = """        if обрезанный in self.МАРШРУТЫ_ТИПА:
            зпр = dict(зпр)
            зпр["type"] = [self.МАРШРУТЫ_ТИПА[обрезанный]]
            # Вид задан МАРШРУТОМ, а не читателем: в каноническом адресе ему
            # места нет. Иначе `/movies/` объявляет каноническим
            # `/movies/?type=movie` — адрес, которого нет ни в навигации, ни в
            # карте сайта, и страница объявляет дублем саму себя.
            зпр["_подразумеваемое"] = ["type"]
"""

ЯКОРЬ_ВИД = """        if обрезанный in self.МАРШРУТЫ_ВИДА:
            kind = self.МАРШРУТЫ_ВИДА[обрезанный]
            зпр = dict(зпр)
            зпр["kind"] = [kind]
"""
ВСТАВКА_ВИД = """        if обрезанный in self.МАРШРУТЫ_ВИДА:
            kind = self.МАРШРУТЫ_ВИДА[обрезанный]
            зпр = dict(зпр)
            зпр["kind"] = [kind]
            # То же и для вида записи, заданного маршрутом.
            зпр["_подразумеваемое"] = ["kind"]
"""

#: 2. Отбор переносит пометку в «выбранное».
ЯКОРЬ_ОТБОР = """    if неизвестный_фильтр:
        выбрано["_unknown"] = "1"
    return набор, выбрано
"""
ВСТАВКА_ОТБОР = """    if неизвестный_фильтр:
        выбрано["_unknown"] = "1"
    # Что выставил МАРШРУТ, а не читатель: пометку ставит обработчик, который
    # подставляет значение, и канонический адрес её учитывает. Поле служебное —
    # `запрос_строкой` пропускает поля с ведущим подчёркиванием, поэтому в
    # ссылках его не видно.
    подразумеваемые = [к for к in (зпр.get("_подразумеваемое") or [])
                       if выбрано.get(к)]
    if подразумеваемые:
        выбрано["_подразумеваемое"] = ",".join(подразумеваемые)
    return набор, выбрано
"""

#: 3. Построитель canonical отбрасывает подразумеваемое.
ЯКОРЬ_КАНОН = """        канон = разд + "/" + (запрос_строкой(выбрано, page=None) if any(
            выбрано.get(k) for k in ("genre", "year", "kind", "country", "type",
                                     "sort", "exclude", "rating", "ongoing")) else "")
"""
ВСТАВКА_КАНОН = """        подразум = {к for к in (выбрано.get("_подразумеваемое") or "").split(",") if к}
        канон_поля = {к: з for к, з in выбрано.items() if к not in подразум}
        канон = SEO.канонический_путь(разд + "/" + (
            запрос_строкой(канон_поля, page=None) if any(
                канон_поля.get(k) for k in ("genre", "year", "kind", "country",
                                            "type", "sort", "exclude", "rating",
                                            "ongoing")) else ""))
"""


class Отказ(RuntimeError):
    """Якоря нет: перенос не состоялся."""


def рантайм(репо: pathlib.Path) -> pathlib.Path:
    """Файл, в котором живёт обработчик ЭТОЙ витрины.

    У animedia-icu в `src/` лежат два файла: своё оформление
    (`animedia-frontend.py`) и общее ядро (`lords-frontend.py`), которое оно
    исполняет. Правка нужна в своём — там обработчик и построитель canonical.
    Поэтому имя ячейки важнее числа файлов: выбирается тот, чьё имя совпадает с
    семейством, и только если он один.
    """
    свои = [p for p in (репо / "src").glob("*frontend*.py")
            if "__pycache__" not in str(p)]
    if len(свои) == 1:
        return свои[0]
    for узор in ("animedia-frontend.py", "animego-frontend.py"):
        для_семейства = [p for p in свои if p.name == узор]
        if len(для_семейства) == 1:
            return для_семейства[0]
    raise Отказ(f"рантаймов в src/: {[p.name for p in свои]}")


def главная(argv: list[str]) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--repo", action="append", default=[])
    р.add_argument("--all-animedia", action="store_true")
    р.add_argument("--dry-run", action="store_true")
    о = р.parse_args(argv[1:])

    цели: list[pathlib.Path] = []
    if о.all_animedia:
        цели += [РЕПОЗИТОРИИ / и for и in ЯЧЕЙКИ]
    for р_ in о.repo:
        п_ = pathlib.Path(р_)
        цели.append(п_ if п_.is_absolute() else КОРЕНЬ / п_)
    if not цели:
        print(__doc__)
        return 2

    отказов = 0
    for цель in цели:
        try:
            файл = рантайм(цель)
        except Отказ as ош:
            print(f"{цель.name:18} ОТКАЗ: {ош}")
            отказов += 1
            continue
        т = файл.read_text(encoding="utf-8")
        было = т
        сделано: list[str] = []
        пары = ((ЯКОРЬ_ТИП, ВСТАВКА_ТИП, "маршрут типа", True),
                (ЯКОРЬ_ВИД, ВСТАВКА_ВИД, "маршрут вида", False),
                (ЯКОРЬ_ОТБОР, ВСТАВКА_ОТБОР, "пометка в отборе", True),
                (ЯКОРЬ_КАНОН, ВСТАВКА_КАНОН, "построитель canonical", True))
        for якорь, вставка, что, обязательно in пары:
            if вставка in т:
                сделано.append(f"{что}: уже")
                continue
            if т.count(якорь) != 1:
                if обязательно:
                    print(f"{цель.name:18} ОТКАЗ: {что} — вхождений "
                          f"{т.count(якорь)}, ожидалось одно")
                    отказов += 1
                    т = было
                    break
                сделано.append(f"{что}: нет (не обязателен)")
                continue
            т = т.replace(якорь, вставка)
            сделано.append(что)
        else:
            if т != было and not о.dry_run:
                файл.write_text(т, encoding="utf-8")
            print(f"{цель.name:18} {', '.join(сделано)}")
    return 1 if отказов else 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv))
