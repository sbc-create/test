#!/usr/bin/env python3
"""Замок: неполный реестр опытов не разрешает трогать экспериментальную группу.

ПОВОД ИЗМЕРЕННЫЙ, 24.10. Реестр опытов разошёлся между рабочими копиями (2
записи против 8), и по неполной копии был предложен порядок снятия паузы
публикации на витринах Lords — всех четырёх, которые на самом деле канарейка
либо контроль двух действующих опытов с оценкой 28.10. Расхождение не
«вопрос учёта»: оно один раз почти стоило двух опытов на седьмые сутки
наблюдения.

ЧТО ЗАМОК ДЕЛАЕТ. Отвечает на два разных вопроса, и их нельзя путать:

  --gate            можно ли сейчас вообще менять экспериментальную группу
                    или снимать паузу. Можно ТОЛЬКО когда все известные копии
                    реестра согласованы. Неполнота — запрет, а не замечание.
  --domain <домен>  участвует ли КОНКРЕТНЫЙ домен в действующем опыте
                    канарейкой или контролем. Нужен ровно для того, чтобы
                    ограничение не расползалось на независимые сайты: запрет
                    обязан быть адресным.

Почему адресность важна не меньше запрета: ограничение, наложенное «на всё
семейство на всякий случай», останавливает работу там, где опыта нет, и его
начинают обходить. Замок называет домены по именам.

Исходы различаются кодом выхода: 0 — согласовано (и домен свободен), 1 —
расхождение либо домен занят опытом, 2 — измерить нечем (копия одна).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_слияние = КОРЕНЬ / "automation" / "local" / "experiments-merge.py"
import importlib.util  # noqa: E402

_с = importlib.util.spec_from_file_location("experiments_merge", _слияние)
СЛИЯНИЕ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(СЛИЯНИЕ)

#: Фазы, при которых опыт ещё измеряется и его группу трогать нельзя.
ДЕЙСТВУЮТ = ("proposed", "dry_run", "canary", "observing")
#: Домен ячейки берётся из паспорта ячеек, а не угадывается по имени.
ЯЧЕЙКИ = КОРЕНЬ / "config" / "site-cells.json"


def домен_ячейки() -> dict[str, str]:
    д = json.loads(ЯЧЕЙКИ.read_text(encoding="utf-8"))
    яч = д.get("cells") or д
    яч = list(яч.values()) if isinstance(яч, dict) else яч
    return {з.get("site_id"): з.get("domain") for з in яч if isinstance(з, dict)}


def согласованность() -> tuple[bool, list[str], int]:
    """(согласовано, список недостающего по копиям, число копий)."""
    пути = СЛИЯНИЕ.копии()
    if len(пути) < 2:
        return False, [f"найдена одна копия реестра: {пути}"], len(пути)
    слитые, конфликты, _ = СЛИЯНИЕ.собрать()
    все = {з["experiment_id"] for з in слитые["experiments"]}
    беда = list(конфликты)
    for п in пути:
        свои = set(СЛИЯНИЕ.записи(СЛИЯНИЕ.прочитать(п)))
        нет = sorted(все - свои)
        if нет:
            беда.append(f"копии {п.parent.parent.name} не хватает записей: "
                        f"{', '.join(нет)}")
    return (not беда), беда, len(пути)


def ячейки_из_текста(текст: str) -> set[str]:
    """Идентификаторы ячеек, названные в применимости, включая ДИАПАЗОНЫ.

    Контроль записывают по-разному: доменом («контроль — lordfilm47.space»),
    одиночной ячейкой и диапазоном («контроль — прочие тайтлы lords-05 и
    lords-01..03»). Измерено 24.10: без разбора диапазона замок не увидел, что
    lordserial33.biz (lords-02) — контроль `exp-lords-title-kind-year`, и
    сказал бы про домен меньше, чем записано. Недообнаружение здесь опаснее
    ложной тревоги: по нему публикуют на контроле.
    """
    из: set[str] = set()
    for м in re.finditer(r"([a-z0-9]+)-(\d+)\s*\.\.\s*(\d+)", текст):
        семья, а, б = м.group(1), int(м.group(2)), int(м.group(3))
        ширина = len(м.group(2))
        for н in range(а, б + 1):
            из.add(f"{семья}-{str(н).zfill(ширина)}")
    из |= set(re.findall(r"\b[a-z0-9]+-\d{2}\b", текст))
    return из


def ограничение(з: dict) -> str:
    """Своими словами опыта: что он запрещает менять до оценки.

    Замок НЕ выдумывает запрет шире записанного. У `exp-country-links-cards`
    записано «разделы стран (адреса, карта, тексты) … не менять» — это не то
    же самое, что «ничего не публиковать на домене». Ограничение, наложенное
    шире, чем нужно, останавливает работу там, где опыт её не трогает, и его
    начинают обходить.
    """
    текст = " ".join((з.get("applicability") or "").split())
    for кусок in re.split(r"(?<=[.;])\s+", текст):
        if "не менять" in кусок or "не трогать" in кусок:
            return кусок.strip()
    return ""


def занятость(домен: str) -> list[tuple[str, str, str, str]]:
    """Где домен участвует: (опыт, роль, фаза, записанное ограничение).

    Контроль ищется в `applicability`: это единственное место, где он вообще
    записан — ни отдельного поля, ни списка схемой не предусмотрено.
    """
    слитые, _, _ = СЛИЯНИЕ.собрать()
    карта = домен_ячейки()
    обратно = {д: я for я, д in карта.items() if д}
    из: list[tuple[str, str, str, str]] = []
    for з in слитые["experiments"]:
        фаза = з.get("phase") or ""
        if фаза not in ДЕЙСТВУЮТ:
            continue
        канарейка = карта.get(з.get("site_id")) or з.get("site_id") or ""
        прим = з.get("applicability") or ""
        огр = ограничение(з)
        моя_ячейка = обратно.get(домен, "")
        if домен == канарейка:
            из.append((з["experiment_id"], "канарейка", фаза, огр))
        elif домен and домен in прим:
            из.append((з["experiment_id"], "контроль (назван доменом)", фаза, огр))
        elif моя_ячейка and моя_ячейка in ячейки_из_текста(прим):
            из.append((з["experiment_id"],
                       f"контроль (назван ячейкой {моя_ячейка})", фаза, огр))
    return из


def контроль() -> int:
    """Замок обязан уметь и запретить, и разрешить."""
    ошибки = []
    согл, беда, копий = согласованность()
    if копий < 2:
        ошибки.append("копий реестра меньше двух — замку нечего сверять")
    карта = домен_ячейки()
    if not карта:
        ошибки.append("паспорт ячеек пуст — домены опытов не разрешаются")
    слитые, _, _ = СЛИЯНИЕ.собрать()
    действующих = [з for з in слитые["experiments"]
                   if (з.get("phase") or "") in ДЕЙСТВУЮТ]
    if not действующих:
        ошибки.append("действующих опытов в объединении нет — проверять нечего")
    for о in ошибки:
        print(f"КОНТРОЛЬ НЕ ПРОЙДЕН: {о}")
    if ошибки:
        return 1
    print(f"контроль пройден: копий {копий}, действующих опытов"
          f" {len(действующих)}, ячеек в паспорте {len(карта)}")
    return 0


def главное(argv: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--gate", action="store_true")
    р.add_argument("--domain")
    р.add_argument("--control", action="store_true")
    а = р.parse_args(argv)
    if not any((а.gate, а.domain, а.control)):
        р.print_help()
        return 2

    код = 0
    if а.control:
        код |= контроль()

    if а.gate or а.domain:
        согл, беда, копий = согласованность()
        if копий < 2:
            print(f"НЕ ИЗМЕРЕНО: {беда[0]}")
            return 2
        if согл:
            print(f"реестр опытов СОГЛАСОВАН по {копий} копиям —"
                  " изменение экспериментальной группы и снятие паузы"
                  " разрешены замком")
        else:
            print(f"реестр опытов НЕ СОГЛАСОВАН по {копий} копиям:")
            for б in беда:
                print(f"   {б}")
            print("ИЗМЕНЕНИЕ ЭКСПЕРИМЕНТАЛЬНОЙ ГРУППЫ И СНЯТИЕ ПАУЗЫ"
                  " НЕ РАЗРЕШЕНЫ: по неполному реестру нельзя узнать, чей это"
                  " контроль. Согласовать: experiments-merge.py --check")
            код |= 1

    if а.domain:
        зан = занятость(а.domain)
        if зан:
            print(f"{а.domain} участвует в действующих опытах:")
            for опыт, роль, фаза, огр in зан:
                print(f"   {опыт} — {роль}, фаза {фаза}")
                if огр:
                    print(f"      записанное ограничение: {огр}")
                else:
                    print("      ограничение в записи опыта НЕ названо —"
                          " решает владелец опыта, а не этот замок")
            print("   объём запрета — тот, что записан в опыте; шире замок его"
                  " не распространяет")
            код |= 1
        else:
            print(f"{а.domain} в действующих опытах не участвует —"
                  " ограничение опытов на него НЕ распространяется")
    return код


if __name__ == "__main__":
    sys.exit(главное())
