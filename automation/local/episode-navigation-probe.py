#!/usr/bin/env python3
"""Есть ли со страницы серии переход на следующую. Только чтение.

Задание ночи требует проверить переходы между сериями. Для посетителя это путь
«смотреть дальше», для обходчика — связность самой многочисленной поверхности
сайта: страниц серий десятки тысяч, и если с каждой нельзя уйти на соседнюю,
обход идёт только из карточки произведения.

Что считается переходом, и почему именно так:

* **соседняя серия того же сезона** — ссылка на `episode-(N±1)`. Это и есть
  «смотреть дальше»;
* **любая другая серия того же произведения** — слабее, но тоже путь: список
  серий на странице серии;
* **возврат к произведению** — ссылка на карточку. Без неё серия висит в
  воздухе.

Ссылка на СЕБЯ переходом не считается: страница, ссылающаяся сама на себя,
никуда не ведёт. Первая редакция этого признака считала все ссылки с `episode-`
в адресе и давала «переходы есть» там, где был только адрес текущей серии.

    python3 automation/local/episode-navigation-probe.py --all
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys

АГЕНТ = "factory-episode-navigation-probe"

ВИТРИНЫ = ("lordserial33.biz", "zonafilm.space", "animedia.space",
           "animeg0.site", "yummyani.biz")


def достать(адрес: str, таймаут: int = 40) -> str | None:
    try:
        г = subprocess.run(["curl", "-A", АГЕНТ, "-sSL", "-w", "\n@@КОД@@%{http_code}",
                            "--max-time", str(таймаут), адрес],
                           capture_output=True, text=True, timeout=таймаут + 20)
    except subprocess.TimeoutExpired:
        return None
    тело, _, код = г.stdout.rpartition("@@КОД@@")
    return тело if код.strip() == "200" else None


#: Два вида адресов серий в сети: `/season-1/episode-2` и `/season/1/episode/2`.
#: Хвостовой слэш в адресе серии необязателен, и из-за его отсутствия в
#: первой редакции признака ни одна серия Lords, Zona и Animedia не нашлась:
#: там адреса оканчиваются слэшем (`/season-1/episode-2/`), а выражение
#: требовало закрывающей кавычки сразу после цифр. Проход печатал «НЕ
#: ИЗМЕРЕНО» у четырёх витрин из пяти — то есть молчал там, где серии есть.
СЕРИЯ = re.compile(
    r"""href=["']((/(?:title|anime)/[^"'#?]+?)/(?:season-(\d+)/episode-(\d+)"""
    r"""|season/(\d+)/episode/(\d+)))/?["']""")


def серии_на(тело: str) -> list[tuple[str, str, int, int]]:
    """`(адрес, произведение, сезон, серия)` для каждой ссылки на серию."""
    итог = []
    for м in СЕРИЯ.finditer(тело):
        адрес, работа = м.group(1), м.group(2)
        сезон = int(м.group(3) or м.group(5))
        серия = int(м.group(4) or м.group(6))
        итог.append((адрес, работа, сезон, серия))
    return итог


def найти_серию(домен: str, одиночки: list[str] | None = None
                ) -> tuple[str, str, int, int] | None:
    """Первая страница серии МНОГОСЕРИЙНОГО произведения, достижимая с главной."""
    одиночки = одиночки if одиночки is not None else []
    главная = достать(f"https://{домен}/")
    if главная is None:
        return None
    for путь in sorted(set(re.findall(
            r"""href=["'](/(?:title|anime)/[^"'#?]+)["']""", главная)))[:12]:
        тело = достать(f"https://{домен}{путь}")
        if тело is None:
            continue
        серии = [с for с in серии_на(тело) if с[1] == путь.rstrip("/")]
        # Произведение с ОДНОЙ серией для этой проверки не годится: «следующей»
        # у него нет по определению, и проход объявил бы дефектом исправную
        # витрину. Первая редакция так и сделала на lordserial33.biz, взяв
        # работу с единственной серией.
        if len({(с[2], с[3]) for с in серии}) >= 2:
            return sorted(серии, key=lambda с: (с[2], с[3]))[0]
        if серии:
            одиночки.append(путь)
    return None


def проверить(домен: str) -> dict:
    итог: dict = {"домен": домен, "замечания": []}
    одиночки: list[str] = []
    найдено = найти_серию(домен, одиночки)
    if найдено is None:
        итог["односерийных_встречено"] = len(одиночки)
        итог["замечания"].append(
            "многосерийного произведения от главной не найдено —"
            " НЕ ИЗМЕРЕНО"
            + (f" (встречено односерийных: {len(одиночки)})" if одиночки else ""))
        return итог
    адрес, работа, сезон, номер = найдено
    итог["серия"] = адрес
    тело = достать(f"https://{домен}{адрес}")
    if тело is None:
        итог["замечания"].append("страница серии не прочитана — НЕ ИЗМЕРЕНО")
        return итог
    ссылки = серии_на(тело)
    свои = [с for с in ссылки if с[1] == работа]
    # Ссылка на себя переходом не считается.
    другие = [с for с in свои if (с[2], с[3]) != (сезон, номер)]
    соседние = [с for с in другие if с[2] == сезон and abs(с[3] - номер) == 1]
    итог["всего_ссылок_на_серии"] = len(ссылки)
    итог["на_другие_серии_той_же_работы"] = len(другие)
    итог["на_соседнюю_серию"] = len(соседние)
    итог["возврат_к_произведению"] = bool(
        re.search(r"""href=["']""" + re.escape(работа) + r"""/?["']""", тело))
    if not другие:
        итог["замечания"].append(
            "со страницы серии нет ни одной ссылки на другую серию этого же"
            " произведения: «смотреть дальше» некуда")
    elif not соседние:
        итог["замечания"].append(
            "ссылки на другие серии есть, но соседней среди них нет:"
            " «следующая» не названа")
    if not итог["возврат_к_произведению"]:
        итог["замечания"].append("нет ссылки назад на карточку произведения")
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--all", action="store_true")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    домены = а.domain or (list(ВИТРИНЫ) if а.all else [])
    if not домены:
        print("не названо ни одной витрины: --domain или --all")
        return 2
    итоги = [проверить(д) for д in домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
        return 1 if any(и["замечания"] for и in итоги) else 0
    for и in итоги:
        метка = "НЕТ" if и["замечания"] else "ок "
        print(f"[{метка}] {и['домен']:20} {и.get('серия', '—')[:44]:<44}"
              f" соседняя {и.get('на_соседнюю_серию', '—')}"
              f" другие {и.get('на_другие_серии_той_же_работы', '—')}"
              f" назад {'есть' if и.get('возврат_к_произведению') else 'нет'}")
        for з in и["замечания"]:
            print(f"       → {з}")
    плохих = [и["домен"] for и in итоги if и["замечания"]]
    print(f"\nвитрин проверено {len(итоги)}, с замечаниями {len(плохих)}")
    print("ссылка на СЕБЯ переходом не считается: страница, ссылающаяся сама на"
          " себя, никуда не ведёт")
    return 1 if плохих else 0


if __name__ == "__main__":
    sys.exit(main())
