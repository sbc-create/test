#!/usr/bin/env python3
"""Ворота ночного прогона одной командой: запуск, продолжение, выдача.

ЗАЧЕМ. 24.10 отчёт к 10:00 МСК не вышел, и причина была не в данных. Ночная
работа шла ВНУТРИ хода сессии: когда ход закончился в 02:31Z, ворота 03:30Z,
05:15Z и 05:30Z никто не открыл. Продолжение было записано документом
(контрольная точка с командами и часами), а документ не срабатывает по времени.

Этот инструмент — исполняемая часть того, что было обещанием. Он открывает все
ворота подряд, печатает исход каждых и возвращает код, по которому видно,
состоялась выдача или нет. Его можно поставить в существующий механизм
(таймер или очередь `status: queued`) без правки логики: он не требует
аргументов и ничего не выпускает.

ЧТО ОН ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Только чтение и замеры: суточный издатель,
свежесть доставки K2, повторный проход по закреплённому набору первого экрана,
наличие свежей выгрузки кабинета. Ни выпуска, ни записи в данные витрин, ни
изменения конфигурации — поэтому его безопасно запускать по расписанию.

КОД ВЫХОДА: 0 — все ворота открыты и каждый дал исход; 1 — хотя бы одни ворота
дали отказ (это РЕЗУЛЬТАТ, а не сбой инструмента); 2 — инструмент не смог
выполнить ворота (нет файла, нет сети): тогда исходов нет и выдачи нет.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import subprocess

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ВЫГРУЗКА = pathlib.Path("/home/claude/wt-portable-site-cell-01/var/analytics"
                        "/cabinet-latest.json")
НАБОР = КОРЕНЬ / "artifacts/evidence/source-arrival-cohort-20261024.tsv"


def прогон(имя: str, команда: list[str], предел: int = 600) -> dict:
    """Один шаг ворот: команда, код выхода, последние строки вывода."""
    начало = dt.datetime.now(dt.timezone.utc)
    try:
        г = subprocess.run(команда, capture_output=True, text=True,
                           timeout=предел, cwd=КОРЕНЬ)
        вывод = (г.stdout or "") + (г.stderr or "")
        код = г.returncode
    except subprocess.TimeoutExpired:
        вывод, код = f"превышен предел {предел} с", None
    except FileNotFoundError as ош:
        вывод, код = f"инструмента нет: {ош}", None
    конец = dt.datetime.now(dt.timezone.utc)
    хвост = [с for с in вывод.splitlines() if с.strip()][-6:]
    return {"имя": имя, "команда": " ".join(команда), "код": код,
            "начато": начало.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "секунд": round((конец - начало).total_seconds(), 1),
            "хвост": хвост}


def ворота_выгрузки() -> dict:
    """Свежесть выгрузки кабинета — чтение файла, а не запуск инструмента."""
    if not ВЫГРУЗКА.is_file():
        return {"имя": "свежая выгрузка кабинета", "команда": f"stat {ВЫГРУЗКА}",
                "код": None, "начато": "", "секунд": 0.0,
                "хвост": ["файла выгрузки нет — НЕ ИЗМЕРЕНО"]}
    собрана = dt.datetime.fromtimestamp(ВЫГРУЗКА.stat().st_mtime,
                                        dt.timezone.utc)
    часов = (dt.datetime.now(dt.timezone.utc) - собрана).total_seconds() / 3600
    свежа = часов <= 26
    return {"имя": "свежая выгрузка кабинета",
            "команда": f"stat {ВЫГРУЗКА.name}",
            "код": 0 if свежа else 1,
            "начато": собрана.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "секунд": 0.0,
            "хвост": [f"собрана {собрана:%Y-%m-%dT%H:%M:%SZ},"
                      f" возраст {часов:.1f} ч,"
                      f" {'свежая' if свежа else 'УСТАРЕЛА (>26 ч)'}"]}


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true",
                   help="выдать исходы машиночитаемо")
    р.add_argument("--skip-browser", action="store_true",
                   help="без браузерных ворот: быстрый прогон для проверки"
                        " самого механизма")
    а = р.parse_args(аргв)

    шаги = [
        прогон("суточный издатель",
               ["python3", "automation/local/daily-publish-health.py"], 300),
        прогон("штатная доставка K2",
               ["python3", "automation/local/k2-freshness.py"], 300),
        ворота_выгрузки(),
    ]
    if not а.skip_browser and НАБОР.is_file():
        шаги.append(прогон(
            "второй проход по набору первого экрана",
            ["python3", "automation/local/player-availability-sweep.py",
             "--paths-file", str(НАБОР), "--titles", "25", "--settle", "20"],
            900))
    elif not а.skip_browser:
        шаги.append({"имя": "второй проход по набору первого экрана",
                     "команда": f"нет файла набора {НАБОР.name}", "код": None,
                     "начато": "", "секунд": 0.0,
                     "хвост": ["НЕ ИЗМЕРЕНО: набор не найден"]})

    if а.json:
        print(json.dumps({"ворота": шаги}, ensure_ascii=False, indent=1))
    else:
        for ш in шаги:
            исход = ("НЕ ВЫПОЛНЕНО" if ш["код"] is None
                     else ("исход получен" if ш["код"] in (0, 1, 3)
                           else f"код {ш['код']}"))
            print(f'=== {ш["имя"]} — {исход} (код {ш["код"]},'
                  f' {ш["секунд"]} с) ===')
            for с in ш["хвост"]:
                print(f'   {с}')
            print()

    невыполненные = [ш for ш in шаги if ш["код"] is None]
    отказы = [ш for ш in шаги if ш["код"] not in (0, None)]
    print(f'ворот всего {len(шаги)}; исход получен у'
          f' {len(шаги) - len(невыполненные)}; не выполнено'
          f' {len(невыполненные)}; с отказом {len(отказы)}')
    if невыполненные:
        print("ВЫДАЧА НЕПОЛНАЯ: у этих ворот исхода нет — "
              + ", ".join(ш["имя"] for ш in невыполненные))
        return 2
    if отказы:
        print("ВЫДАЧА ПОЛНАЯ, но есть отказы: "
              + ", ".join(f'{ш["имя"]} (код {ш["код"]})' for ш in отказы))
        return 1
    print("ВЫДАЧА ПОЛНАЯ: все ворота открыты без отказов")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
