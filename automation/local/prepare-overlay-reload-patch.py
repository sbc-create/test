import tempfile
import types
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
УСТАНОВЛЕНО = Path("/srv/site-1lordserials1-online/current/overlay/freshness.py")
ПАТЧ = КОРЕНЬ / "var" / "patches" / "overlay-reload-core-fields.patch"
ЛОВУШКИ = ("/app/", "/app.prev/", "/candidate/")

ЯКОРЬ = """            self.поступления.пересчитать(данные, подробности)
            self.набор = Набор(данные, подробности, индекс, метка,
                               shelves.собрать(данные, подробности, self.поступления))
            self.перечитано += 1"""

ЗАМЕНА = """            self.поступления.пересчитать(данные, подробности)
            self.набор = Набор(данные, подробности, индекс, метка,
                               shelves.собрать(данные, подробности, self.поступления))
            # ПОКОЛЕНИЕ ОТДАЁТСЯ И ЯДРУ, иначе о нём знает только наложение.
            #
            # Поток карты в ядре сравнивает `(revision, len(items))` у
            # `Обработчик.данные` и пересобирает файлы только при различии
            # (`src/seo_layer.py`). Без этих трёх строк поле остаётся от
            # старта, поколение не меняется никогда, и карта застывает:
            # измерено 18.10 и 21.10 — 770 индексируемых произведений вне
            # карты при выросшем каталоге (MOD-81).
            #
            # Присваивание стоит ПОСЛЕ успешной сборки набора: на битом
            # снимке `_перестроить` уходит в except выше, и ядро остаётся на
            # прежнем поколении — отдавать половину поколения хуже, чем
            # отдавать прежнее целиком.
            #
            # Порядок как у прецедента `lords-02` (`src/lords02_reload.py`):
            # сначала данные, потом подробности и индекс. Окно между
            # присваиваниями есть при любом порядке, этот даёт безопасную
            # сторону — новая запись пока не находится по старому индексу.
            #
            # Кэши НЕ сбрасываются: причина — в комментарии выше по тексту
            # (двухшаговый читатель кэша и недельный контракт полки).
            self.ядро.Обработчик.данные = данные
            self.ядро.Обработчик.подробности = подробности
            self.ядро.Обработчик.индекс = индекс
            self.перечитано += 1"""


def переписать(текст: str) -> str:
    if "self.ядро.Обработчик.данные = данные" in текст:
        raise SystemExit("в установленном файле правка УЖЕ есть — патч не нужен")
    сколько = текст.count(ЯКОРЬ)
    if сколько != 1:
        raise SystemExit(
            f"якорь встречается {сколько} раз вместо одного: установленный файл"
            " изменился. Патч собирать заново, а не подгонять по похожим местам.")
    return текст.replace(ЯКОРЬ, ЗАМЕНА, 1)


# --- модель ядра для репетиции -------------------------------------------------
#
# Наложение импортируется целиком (`from . import newness, shelves`), поэтому
# для репетиции копируется ВЕСЬ каталог наложения, а ядро подменяется моделью:
# настоящее ядро тянет снимок на 16.7 МБ и подробности на 75.8 МБ, а проверять
# надо не их чтение, а передачу поколения.


def _каталог(путь: Path, сколько: int, ревизия: str) -> None:
    путь.write_text(json.dumps({
        "revision": ревизия, "built_at": "2026-10-21T00:00:00Z",
        "items": [{"slug": f"s{i}", "url": f"/title/s{i}/", "title": f"T{i}",
                   "year": 2020, "kind": "Фильм",
                   "published_at": "2026-10-20T00:00:00Z"}
                  for i in range(сколько)]}), encoding="utf-8")


def _модель_ядра(каталог: Path, подробности: Path):
    class Данные:
        def __init__(self, п):
            d = json.loads(Path(п).read_text(encoding="utf-8"))
            self.revision = d["revision"]
            self.built_at = d["built_at"]
            self.items = d["items"]
            self.by_slug = {з["slug"]: з for з in self.items}

    class Подробности(dict):
        """Ядро обращается к подробностям и как к объекту, и как к словарю."""

        def __init__(self, п):
            super().__init__()
            self.записи = {}

    class Обработчик:
        данные = None
        подробности = None
        индекс = None

    return types.SimpleNamespace(
        КАТАЛОГ_ФАЙЛ=str(каталог), ПОДРОБНОСТИ_ФАЙЛ=str(подробности),
        Данные=Данные, Подробности=Подробности, Обработчик=Обработчик,
        построить_индекс_исходный=lambda д, п: {"записей": len(д.items)})


def _поколение(ядро) -> tuple:
    """Ровно то, что читает поток карты в ядре."""
    данные = getattr(getattr(ядро, "Обработчик", None), "данные", None)
    return (getattr(данные, "revision", ""), len(getattr(данные, "items", ()) or ()))


def _прогон(дерево: Path, имя: str) -> dict:
    """Прогнать перечитывание на модели ядра и вернуть, что увидели."""
    sys.path.insert(0, str(дерево))
    for м in [к for к in sys.modules if к.startswith("overlay")]:
        del sys.modules[м]
    try:
        import importlib

        freshness = importlib.import_module("overlay.freshness")
        каталог = дерево / "catalog.json"
        подробности = дерево / "details.json"
        _каталог(каталог, 3, "r3")
        подробности.write_text(json.dumps({"items": {}}), encoding="utf-8")
        ядро = _модель_ядра(каталог, подробности)
        с = freshness.Слежение(ядро)
        д0 = ядро.Данные(каталог)
        ядро.Обработчик.данные = д0
        ядро.Обработчик.подробности = ядро.Подробности(подробности)
        ядро.Обработчик.индекс = {"записей": len(д0.items)}
        с.принять(д0, ядро.Обработчик.подробности, ядро.Обработчик.индекс)
        было = _поколение(ядро)

        _каталог(каталог, 5, "r5")
        с._перестроить()
        итог = {
            "имя": имя,
            "поколение_до": было,
            "поколение_после": _поколение(ядро),
            "набор_записей": len(с.набор.данные.items) if с.набор else None,
            "перечитано": с.перечитано,
            "ошибка": с.последняя_ошибка,
        }

        # Отрицательный контроль: битый снимок НЕ имеет права передать ядру
        # половину поколения.
        каталог.write_text("{ это не json", encoding="utf-8")
        с._перестроить()
        итог["поколение_после_битого"] = _поколение(ядро)
        итог["ошибка_битого"] = с.последняя_ошибка
        return итог
    finally:
        sys.path.remove(str(дерево))


def _вызовы_сброса(текст: str) -> int:
    """Сколько РАБОЧИХ вызовов сброса кэша в тексте.

    Подстрока здесь не годится: в наложении есть длинный комментарий, который
    объясняет, почему сброс не вызывается, и само имя в нём встречается. Первая
    редакция этой проверки считала комментарий вызовом и роняла верный патч —
    признак давал один ответ и на исправном, и на неисправном тексте.
    """
    счёт = 0
    for строка in текст.splitlines():
        голая = строка.strip()
        if голая.startswith("#"):
            continue
        без_хвоста = голая.split("#", 1)[0]
        счёт += без_хвоста.count("сброс_популярного_кэша(")
    return счёт


def репетиция(исходный: Path, стало_текст: str) -> list[str]:
    итог: list[str] = []
    with tempfile.TemporaryDirectory() as врем:
        врем = Path(врем)
        до = врем / "до"
        после = врем / "после"
        for цель in (до, после):
            shutil.copytree(исходный.parent, цель / "overlay")
        (после / "overlay" / исходный.name).write_text(стало_текст,
                                                       encoding="utf-8")
        а = _прогон(до, "до")
        б = _прогон(после, "после")

    for п in (а, б):
        итог.append(
            f"{п['имя']:>6}: поколение ядра {п['поколение_до']} →"
            f" {п['поколение_после']}, набор наложения {п['набор_записей']},"
            f" перечитано {п['перечитано']}, ошибка {п['ошибка'] or '—'}")
    итог.append("ок: ДО патча поколение ядра не менялось — дефект воспроизведён"
                if а["поколение_до"] == а["поколение_после"]
                else "ПРОВАЛ: дефект не воспроизводится, предмет правки не тот")
    итог.append("ок: ПОСЛЕ патча поколение ядра обновилось"
                if б["поколение_после"] == ("r5", 5)
                else f"ПРОВАЛ: после патча поколение {б['поколение_после']}")
    итог.append("ок: набор наложения обновляется в обоих состояниях"
                if а["набор_записей"] == б["набор_записей"] == 5
                else "ПРОВАЛ: патч задел перечитывание наложения")
    итог.append("ок: перечитывание посчитано в обоих состояниях"
                if а["перечитано"] == б["перечитано"] == 1
                else "ПРОВАЛ: счётчик перечитываний разошёлся")
    итог.append("ок: битый снимок не передал ядру новое поколение"
                if б["поколение_после_битого"] == ("r5", 5)
                and б["ошибка_битого"]
                else f"ПРОВАЛ: на битом снимке ядро получило"
                     f" {б['поколение_после_битого']},"
                     f" ошибка {б['ошибка_битого'] or 'нет'}")
    было_вызовов = _вызовы_сброса(исходный.read_text(encoding="utf-8"))
    стало_вызовов = _вызовы_сброса(стало_текст)
    итог.append(f"вызовов сброса кэша: было {было_вызовов}, стало"
                f" {стало_вызовов}")
    итог.append("ок: патч кэши не сбрасывает (их сброс даёт 500 на главной)"
                if стало_вызовов == было_вызовов == 0
                else "ПРОВАЛ: патч сбрасывает кэш, чего делать нельзя")
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--source", default=str(УСТАНОВЛЕНО))
    р.add_argument("--verify", action="store_true")
    р.add_argument("--allow-stale", action="store_true")
    а = р.parse_args(аргв)

    исходный = Path(а.source)
    if not исходный.is_file():
        print(f"НЕ СОБРАНО: нет установленного файла {исходный}")
        return 2
    if any(л in str(исходный) for л in ЛОВУШКИ) and not а.allow_stale:
        print(f"НЕ СОБРАНО: {исходный} — не обслуживаемое витриной дерево."
              f" Работающий файл берётся через `current`.")
        return 2
    print(f"работающий выпуск: {исходный.resolve().parent.parent.name}")
    было = исходный.read_text(encoding="utf-8")
    стало = переписать(было)
    патч = "".join(difflib.unified_diff(
        было.splitlines(keepends=True), стало.splitlines(keepends=True),
        fromfile="a/overlay/freshness.py", tofile="b/overlay/freshness.py"))
    ПАТЧ.parent.mkdir(parents=True, exist_ok=True)
    ПАТЧ.write_text(патч, encoding="utf-8")
    print(f"патч: {ПАТЧ} ({len(патч.splitlines())} строк)")
    print(f"установленный файл: {исходный} ({исходный.stat().st_size} Б)")
    if not а.verify:
        return 0

    провалов = 0
    with tempfile.TemporaryDirectory() as врем:
        к = Path(врем) / "freshness.py"
        к.write_text(стало, encoding="utf-8")
        try:
            py_compile.compile(str(к), doraise=True)
        except py_compile.PyCompileError as ош:
            print(f"ПРОВЕРКА НЕ ПРОЙДЕНА: не компилируется: {ош}")
            return 1
        print("исправленный файл компилируется")
        проба = Path(врем) / "проба"
        (проба / "overlay").mkdir(parents=True)
        shutil.copy(исходный, проба / "overlay" / "freshness.py")
        г = subprocess.run(["patch", "-p1", "--dry-run", "-i", str(ПАТЧ)],
                           cwd=проба, capture_output=True, text=True)
        print((г.stdout or г.stderr).strip())
        if г.returncode != 0:
            print("ПРОВЕРКА НЕ ПРОЙДЕНА: патч не прикладывается")
            return 1
        print("патч прикладывается к установленному файлу (--dry-run)")

    print("\nрепетиция на модели ядра: ДО против ПОСЛЕ")
    for строка in репетиция(исходный, стало):
        print(f"   {строка}")
        провалов += 1 if "ПРОВАЛ" in строка else 0
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(главное())
