#!/usr/bin/env python3
"""Точечный патч MOD-81: наложение перечитало снимок, а ядро об этом не знает.

Дефект (MOD-81, P0), измерен 18.10 и подтверждён 21.10: карта
`1lordserials1.online` описывает поколение каталога, застывшее на момент
запуска службы. Сегодня в каталоге 68 451 запись, в карте 67 681, вне карты
**770** произведений, и выборка из 12 отсутствующих дала 12 `index` — то есть
это индексируемые страницы, которых поисковику не назвали.

ПРИЧИНА, прочитанная в установленном дереве, а не предположенная. Поток карты
в ядре берёт поколение так (`src/seo_layer.py:554`):

    данные = getattr(getattr(рантайм, "Обработчик", None), "данные", None)
    поколение = (getattr(данные, "revision", ""), len(данные.items))
    if поколение != прошлое: обновить_карту(...)

а наложение, перечитав снимок, обновляет ТОЛЬКО свой набор
(`overlay/freshness.py`, `_перестроить`): `self.набор = Набор(...)`. Классовые
поля ядра остаются от старта, поколение не меняется никогда, и поток карты не
получает повода пересобрать файлы. `адреса_карты` читает те же классовые поля,
и больше ничего, — проверено чтением.

ПРАВКА — ТРИ ПРИСВАИВАНИЯ, без перезапуска и без сброса кэшей. Прецедент в
сети: `lords-02` делает это у себя (`src/lords02_reload.py:226-228`), и карта
там сегодняшняя.

ЧЕГО ПАТЧ НЕ ДЕЛАЕТ, намеренно: не вызывает `сброс_популярного_кэша()` и не
обнуляет `Снимок._снимок`. У наложения прямо записано, почему: читатель кэша в
ядре двухшаговый, и `clear()` из потока перечитывания даёт `KeyError` и 500 на
главной; недельный порядок полки — объявленный контракт. Перезапуск витриной
тоже НЕ является исправлением: он соберёт карту один раз, а причину не уберёт.

Порядок присваивания взят у прецедента и он не случаен: сначала `данные`,
потом `подробности` и `индекс`. Окно между присваиваниями есть в любом порядке;
этот даёт безопасную сторону — новая запись ещё не находится по старому индексу
(«пока не в списке»), тогда как обратный порядок дал бы индекс со слагами,
которых в данных нет.

    python3 automation/local/prepare-overlay-reload-patch.py --verify
"""
