#!/usr/bin/env python3
"""Называет ли себя фасетная страница — жанр, страна, год. Только чтение.

    python3 automation/local/facet-pages-check.py            # вся сеть
    python3 automation/local/facet-pages-check.py <домен> …   # выбранные

Зачем. Фасет — это посадочная поверхность: по запросу «боевик сериалы» нечего
предъявить, если страница жанра объявляет себя копией каталога. Измерено
2026-10-18 на восьми витринах партии K2: `/genre/boevik/` отдавал 11 830
записей из 66 159, а title и h1 были «Каталог», canonical — `/catalog/`. То
есть двенадцать ссылок с главной вели на страницы, которые сами от себя
отказываются.

Остальные двенадцать витрин сети этим не болели — проверено тем же
инструментом в тот же день, — и именно поэтому проверка нужна постоянно: дефект
пришёл с новой партией, а не был в семействе всегда.

Что считается дефектом, и почему именно это:

* `title` совпадает с title каталога — страница не называет себя;
* `canonical` указывает НЕ на себя — страница сама говорит поиску, что
  индексировать надо другую. Для формы с запросом каноном считается тот же
  запрос: у семейств Zona и Animedia канонична именно она.

Что НЕ считается дефектом: отсутствие ссылок на жанры вовсе (так у витрин
Yummy — это записано отдельно, R-01), и пустая выборка (жанр может быть
редким).

Код жанра НЕ выводится транслитерацией, а берётся из ссылок самой витрины.
Причина измеренная: 2026-10-18 моя же проверка объявила 404 у четырёх жанров,
потому что её таблица не знала «ё» и запрашивала адрес, которого витрина не
выдаёт.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1].parent
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ИСПЫТАТЕЛЬНЫЕ = (".localhost", ".test", ".invalid", ".example")


def домены_реестра(путь: Path) -> list[str]:
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        print(f"реестр ячеек не прочитан ({путь}): {сбой}", file=sys.stderr)
        return []
    ячейки = документ.get("cells") or []
    ячейки = list(ячейки.values()) if isinstance(ячейки, dict) else ячейки
    return [я["domain"] for я in ячейки
            if я.get("domain") and not я["domain"].endswith(ИСПЫТАТЕЛЬНЫЕ)]


def тело(адрес: str, таймаут: int) -> str:
    г = subprocess.run(["curl", "-sSL", "--max-time", str(таймаут), адрес],
                       capture_output=True, text=True)
    return г.stdout or ""


def мета(т: str) -> tuple[str, str, str]:
    """(title, h1, canonical) — без разметки и без лишних пробелов."""
    def чисто(м):
        return (re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", м.group(1))).strip()
                if м else "")
    return (чисто(re.search(r"<title>(.*?)</title>", т, re.S)),
            чисто(re.search(r"<h1[^>]*>(.*?)</h1>", т, re.S)),
            (lambda м: м.group(1) if м else "")(
                re.search(r'<link rel="canonical" href="([^"]+)"', т)))


def ссылки_фасетов(т: str) -> list[str]:
    """Адреса фасетов в разметке. Путь и запрос — обе формы сети."""
    путевые = re.findall(r'href="(/(?:genre|country)/[^"?#]+)"', т)
    парам = re.findall(r'href="(/catalog/\?(?:genre|country)=[^"&]+)"', т)
    return sorted(set(путевые)) or sorted(set(парам))


def канон_свой(канон: str, путь: str) -> bool:
    """Указывает ли canonical на эту же страницу.

    Для формы с запросом сравнивается сам запрос: у Zona и Animedia канонична
    именно она, и требовать путь значило бы объявлять дефектом их устройство.
    """
    if not канон:
        return False
    if "?" in путь:
        return путь.split("?", 1)[1] in канон
    return канон.rstrip("/").endswith(путь.rstrip("/"))


def проверить(домен: str, таймаут: int) -> dict:
    дом = тело(f"https://{домен}/", таймаут)
    адреса = ссылки_фасетов(дом)
    if not адреса:
        адреса = ссылки_фасетов(тело(f"https://{домен}/catalog/", таймаут))
    if not адреса:
        return {"домен": домен, "вывод": "ссылок на фасеты нет"}
    путь = адреса[0]
    титул_каталога = мета(тело(f"https://{домен}/catalog/", таймаут))[0]
    титул, h1, канон = мета(тело(f"https://{домен}{путь}", таймаут))
    назвал = bool(титул) and титул != титул_каталога
    свой = канон_свой(канон, путь)
    вывод = ("называет себя" if назвал and свой else
             "ЗАГОЛОВОК КАК У КАТАЛОГА" if not назвал and свой else
             "КАНОН НЕ НА СЕБЯ" if назвал else
             "ЗАГОЛОВОК КАК У КАТАЛОГА И КАНОН НЕ НА СЕБЯ")
    return {"домен": домен, "путь": путь, "title": титул, "h1": h1,
            "canonical": канон, "назвал": назвал, "канон_свой": свой,
            "вывод": вывод}


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("domains", nargs="*")
    р.add_argument("--registry", type=Path, default=РЕЕСТР)
    р.add_argument("--timeout", type=int, default=40)
    а = р.parse_args(аргв)
    список = а.domains or домены_реестра(а.registry)
    if not список:
        return 2
    плохих = 0
    print(f"{'домен':24} {'фасет':30} {'h1':20} вывод")
    for домен in список:
        итог = проверить(домен, а.timeout)
        if итог["вывод"] == "ссылок на фасеты нет":
            print(f"{домен:24} {'—':30} {'—':20} ссылок на фасеты нет")
            continue
        if итог["вывод"] != "называет себя":
            плохих += 1
        print(f"{домен:24} {итог['путь'][-30:]:30} {итог['h1'][:20]:20} "
              f"{итог['вывод']}")
    print(f"\nфасетов, которые себя не называют или канонизируют на другую "
          f"страницу: {плохих}")
    print("Пустая выборка и отсутствие ссылок на фасеты дефектом здесь не "
          "считаются: жанр бывает редким, а витрина — без фасетов вовсе "
          "(R-01).")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(главная())
