def файлы_рантайма(корень: pathlib.Path) -> list[pathlib.Path]:
    """Файлы, в которых живёт публичный текст витрины.

    Берутся ВСЕ свои модули `src/*.py`, а не только `*frontend*`: у семейств
    Lords-02 и Animedia часть публичных строк живёт в отдельных файлах вида и
    подборок (`lords02_view.py`, `lords02_collections.py`), и ограничение одним
    именем оставило бы их нетронутыми — проверено, семь строк в двух ячейках.
    Таблица подмены точная, поэтому расширение набора файлов ничего лишнего не
    задевает: отсутствующая строка просто не встречается.

    Закреплённый артефакт (`template/<выпуск>/`) НЕ ПРАВИТСЯ: он закрыт замком
    версий, и правка идёт переходником (`src/public_wording.py`).
    """
    # Наложение сайта (`overlay/`) — ПЯТАЯ действующая форма рантайма: у
    # 1lordserials1.online лаунчер исполняет `overlay/main.py`, а оно уже
    # закреплённое ядро из `src/`. Пока инструмент знал только `src/`, описание
    # главной этой витрины оставалось прежним, и поведенческий ярус проверки
    # поймал это на живом стенде: «Каталог, новинки и подборки из утверждённого
    # снимка» в `overlay/view.py`.
    каталоги = [корень / "src", корень / "overlay"]
    итог: list[pathlib.Path] = []
    for к in каталоги:
        if к.is_dir():
            итог += [ф for ф in sorted(к.glob("*.py"))
                     if "__pycache__" not in str(ф) and ф.name != "public_wording.py"]
    if итог:
        return итог
    к = корень / "src"
    if not к.is_dir():
        return []
    # `public_wording.py` ИСКЛЮЧЁН: это сам модуль подмены для ячейки с
    # закреплённым артефактом, и он ОБЯЗАН называть то, что заменяет. Один
    # прогон без этого исключения переписал его таблицу в «старое → старое»,
    # то есть обезвредил правку, сообщив об успехе.
    return [ф for ф in sorted(к.glob("*.py"))
            if "__pycache__" not in str(ф) and ф.name != "public_wording.py"]


def править(файлы: list[pathlib.Path], сухо: bool) -> tuple[int, list[str]]:
    """Заменить по таблице. Режим «только чтение» снимается и ВОЗВРАЩАЕТСЯ.

    У трёх репозиториев часть файлов рантайма лежит в режиме `0444` — след
    копирования с защищённого источника, а не правило фабрики: ни один
    инструмент такого режима не ставит, и у остальных тринадцати те же файлы
    обычные. Правка этих файлов — установившийся порядок (`refresh-pins-lock.py`
    существует именно для неё), поэтому режим снимается на время записи и
    ставится обратно: тихо оставить файл открытым на запись значило бы изменить
    то, о чём не просили.
    """
    import os
    import stat

    сделано = 0
    не_найдено: list[str] = []
    for ф in файлы:
        т = ф.read_text(encoding="utf-8")
        было = т
        for старое, новое in ЗАМЕНЫ:
            if старое in т:
                сделано += т.count(старое)
                т = т.replace(старое, новое)
        if т != было and not сухо:
            режим = ф.stat().st_mode
            закрыт = not (режим & stat.S_IWUSR)
            if закрыт:
                os.chmod(ф, режим | stat.S_IWUSR)
                print(f"   {ф.name}: режим только для чтения снят на время записи")
            try:
                ф.write_text(т, encoding="utf-8")
            finally:
                if закрыт:
                    os.chmod(ф, режим)
    весь = "".join(ф.read_text(encoding="utf-8") for ф in файлы)
    for старое, новое in ЗАМЕНЫ:
        if старое not in весь and новое not in весь:
            не_найдено.append(старое[:46])
    return сделано, не_найдено


