def файлы_рантайма(корень: pathlib.Path) -> list[pathlib.Path]:
    """Файлы, в которых живёт публичный текст витрины.

    Берутся ВСЕ свои модули `src/*.py`, а не только `*frontend*`: у семейств
    Lords-02 и Animedia часть публичных строк живёт в отдельных файлах вида и
    подборок (`lords02_view.py`, `lords02_collections.py`), и ограничение одним
    именем оставило бы их нетронутыми — проверено, семь строк в двух ячейках.
    Таблица подмены точная, поэтому расширение набора файлов ничего лишнего не
    задевает: отсутствующая строка просто не встречается.

    Закреплённый артефакт (`template/<выпуск>/`) НЕ ПРАВИТСЯ: он закрыт замком
    версий, и правка идёт переходником (`src/public_wording.py`).
    """
    # Наложение сайта (`overlay/`) — ПЯТАЯ действующая форма рантайма: у
    # 1lordserials1.online лаунчер исполняет `overlay/main.py`, а оно уже
    # закреплённое ядро из `src/`. Пока инструмент знал только `src/`, описание
    # главной этой витрины оставалось прежним, и поведенческий ярус проверки
    # поймал это на живом стенде: «Каталог, новинки и подборки из утверждённого
    # снимка» в `overlay/view.py`.
    каталоги = [корень / "src", корень / "overlay"]
    итог: list[pathlib.Path] = []
    for к in каталоги:
        if к.is_dir():
            итог += [ф for ф in sorted(к.glob("*.py"))
                     if "__pycache__" not in str(ф) and ф.name != "public_wording.py"]
    if итог:
        return итог
    к = корень / "src"
    if not к.is_dir():
        return []
    # `public_wording.py` ИСКЛЮЧЁН: это сам модуль подмены для ячейки с
    # закреплённым артефактом, и он ОБЯЗАН называть то, что заменяет. Один
    # прогон без этого исключения переписал его таблицу в «старое → старое»,
    # то есть обезвредил правку, сообщив об успехе.
    return [ф for ф in sorted(к.glob("*.py"))
            if "__pycache__" not in str(ф) and ф.name != "public_wording.py"]


def править(файлы: list[pathlib.Path], сухо: bool) -> tuple[int, list[str]]:
    """Заменить по таблице. Режим «только чтение» снимается и ВОЗВРАЩАЕТСЯ.

    У трёх репозиториев часть файлов рантайма лежит в режиме `0444` — след
    копирования с защищённого источника, а не правило фабрики: ни один
    инструмент такого режима не ставит, и у остальных тринадцати те же файлы
    обычные. Правка этих файлов — установившийся порядок (`refresh-pins-lock.py`
    существует именно для неё), поэтому режим снимается на время записи и
    ставится обратно: тихо оставить файл открытым на запись значило бы изменить
    то, о чём не просили.
    """
    import os
    import stat

    сделано = 0
    не_найдено: list[str] = []
    for ф in файлы:
        т = ф.read_text(encoding="utf-8")
        было = т
        for старое, новое in ЗАМЕНЫ:
            if старое in т:
                сделано += т.count(старое)
                т = т.replace(старое, новое)
        if т != было and not сухо:
            режим = ф.stat().st_mode
            закрыт = not (режим & stat.S_IWUSR)
            if закрыт:
                os.chmod(ф, режим | stat.S_IWUSR)
                print(f"   {ф.name}: режим только для чтения снят на время записи")
            try:
                ф.write_text(т, encoding="utf-8")
            finally:
                if закрыт:
                    os.chmod(ф, режим)
    весь = "".join(ф.read_text(encoding="utf-8") for ф in файлы)
    for старое, новое in ЗАМЕНЫ:
        if старое not in весь and новое not in весь:
            не_найдено.append(старое[:46])
    return сделано, не_найдено


СТРОКА_ПРОГОНА = """
# Публичный текст без внутренних слов. Измерено 2026-10-06: «витрина», «снимок
# каталога» и «тестовая витрина» стояли в описаниях страниц, в подвале, в 404 и
# в сообщениях плеера у всех шестнадцати не-Yummy ячеек и были живы на десяти
# домен из двенадцати. Полезные пояснения проверка не запрещает: часовой пояс,
# различие эфира и появления серии и смысл сообщений плеера остаются.
check "public-wording"     python3 checks/public_wording.py
"""


def внести_проверку(цель: pathlib.Path) -> str:
    """Доставить проверку и внести её в прогон проекта. Возвращает, что сделано."""
    import shutil

    проверки = цель / "checks"
    if not проверки.is_dir():
        return "каталога checks/ нет — проверка не доставлена"
    shutil.copy2(ПРОВЕРКА, проверки / "public_wording.py")
    сказано = ["доставлено checks/public_wording.py"]
    прогон = проверки / "run.sh"
    if прогон.is_file():
        т = прогон.read_text(encoding="utf-8")
        if "public_wording.py" in т:
            сказано.append("в прогоне уже есть")
        elif т.count('exit "$fail"') == 1:
            прогон.write_text(
                т.replace('\nexit "$fail"', СТРОКА_ПРОГОНА + '\nexit "$fail"'),
                encoding="utf-8")
            сказано.append("внесено в checks/run.sh")
        else:
            сказано.append('ОТКАЗ: в checks/run.sh нет единственного exit "$fail"')
    return ", ".join(сказано)


def главная(argv: list[str]) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--repo", action="append", default=[])
    р.add_argument("--all", action="store_true", help="все репозитории сайтов")
    р.add_argument("--template", action="store_true", help="общий шаблон фабрики")
    р.add_argument("--no-check", action="store_true", help="не доставлять проверку")
    р.add_argument("--dry-run", action="store_true")
    о = р.parse_args(argv[1:])

    цели: list[pathlib.Path] = []
    if о.template:
        цели.append(ШАБЛОН.parent)
    if о.all:
        # Витрины Yummy ИСКЛЮЧЕНЫ: ими распоряжается другое окно, и правка их
        # рабочего дерева — вмешательство в чужую работу, даже без выкладки.
        # Измерено 2026-10-07: один проход таблицы изменил по строке в пяти их
        # рантаймах, и правка была снята. Та же строка у них есть — она названа
        # в отчёте владельцу, а чинит её владеющее окно.
        цели += [п for п in sorted(РЕПОЗИТОРИИ.iterdir())
                 if (п / ".git").is_dir() and not п.name.startswith("yummy")]
    for р_ in о.repo:
        п_ = pathlib.Path(р_)
        цели.append(п_ if п_.is_absolute() else КОРЕНЬ / п_)
    if not цели:
        print(__doc__)
        return 2

    всего = 0
    for цель in цели:
        if цель == ШАБЛОН.parent:
            файлы = [ШАБЛОН]
            имя = "общий шаблон"
        else:
            файлы = файлы_рантайма(цель)
            имя = цель.name
        if not файлы:
            print(f"{имя:24} рантайма в своих файлах нет — правка переходником "
                  "(src/public_wording.py), этим инструментом не вносится")
            continue
        сделано, не_найдено = править(файлы, о.dry_run)
        всего += сделано
        print(f"{имя:24} замен {сделано:3}"
              + (f", нет строк: {len(не_найдено)}" if не_найдено else ""))
        if not о.no_check and not о.dry_run and цель != ШАБЛОН.parent:
            сказано = внести_проверку(цель)
            if сказано:
                print(f"   {сказано}")
    print(f"\nвсего замен: {всего}" + ("  (сухой прогон)" if о.dry_run else ""))
    return 0


