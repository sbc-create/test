#!/usr/bin/env python3
"""Перенос доказательства «в чужие данные мы не писали» в соседние ячейки.

    python3 automation/local/wire-neighbours-guard.py --repo var/site-repos/<проект> [--dry-run]

Зачем. Проверки изоляции сверяли каталог соседней площадки ПОБАЙТНО и требовали
полного совпадения до и после прогона. Утверждение неверно по существу: у соседа
свой таймер обновления, и его собственная служба законно переписывает свои
снимки прямо во время нашей проверки. Измерено 2026-10-07 01:03 UTC на
an1meg0.site: `checks/community_storage.py` упал строкой
«не тронуты данные: /srv/animedia-space/data», тогда как в ту же минуту служба
`animedia-space` штатно записала свои `episode-state` и `episode-events`.
Проверка, отказывающая от чужой штатной работы, перестаёт что-либо значить.

Правильное доказательство уже написано и работает — у ячейки `animeg0-site`
(`checks/neighbours.py`): наш процесс работает под своим пользователем, сосед —
под своим, и файл, написанный нами, принадлежал бы нам. Поэтому проверяется, что
ни один файл соседа не ПЕРЕШЁЛ к нашему пользователю, что набор путей не
пополнился и что ничего не исчезло. Изменение содержимого файла, оставшегося за
своим владельцем, — работа самого соседа.

Инструмент переносит этот модуль в ячейки, где его нет, и переключает места
сверки на него. Якоря точные: нет якоря — ОТКАЗ с названием места, а не тихий
пропуск.
"""
from __future__ import annotations

import argparse
import pathlib
import shutil
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ОБРАЗЕЦ = КОРЕНЬ / "var" / "site-repos" / "animeg0-site" / "checks" / "neighbours.py"

ИМПОРТ_ЯКОРЬ = "from pathlib import Path\n"
ИМПОРТ_ВСТАВКА = (
    "from pathlib import Path\n"
    "\n"
    "sys.path.insert(0, str(Path(__file__).resolve().parent))\n"
    "from neighbours import слепок_владения, чужое_не_тронуто  # noqa: E402\n"
)

#: Места сверки: «как было» → «как стало». Форм несколько, потому что у проверок
#: разные имена переменной слепка и разные подписи исхода.
СВЕРКИ: tuple[tuple[str, str], ...] = (
    (
        """        for к, было in чужие_до.items():
            итог(f"не тронуты данные: {к}", слепок(Path(к)) == было)""",
        """        for к, было in чужие_до.items():
            ок, чем = чужое_не_тронуто(Path(к), было)
            итог(f"в данные соседа не писали: {к}", ок, чем)""",
    ),
    (
        """        for к, было_ин in чужие_до.items():
            итог(f"данные соседа не изменились: {к}",
                 слепок(Path(к)) == было_ин)""",
        """        for к, было_ин in чужие_до.items():
            ок, чем = чужое_не_тронуто(Path(к), было_ин)
            итог(f"в данные соседа не писали: {к}", ок, чем)""",
    ),
)

#: Снятие слепка: байты → владельцы.
СЛЕПКИ: tuple[tuple[str, str], ...] = (
    ("чужие_до = {str(к): слепок(к) for к in ЧУЖИЕ}",
     "чужие_до = {str(к): слепок_владения(к) for к in ЧУЖИЕ}"),
)


class Отказ(RuntimeError):
    """Якоря нет: перенос не состоялся."""


def главная(argv: list[str]) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--repo", required=True)
    р.add_argument("--dry-run", action="store_true")
    о = р.parse_args(argv[1:])

    репо = pathlib.Path(о.repo)
    if not репо.is_absolute():
        репо = КОРЕНЬ / репо
    проверки = репо / "checks"
    if not проверки.is_dir():
        print(f"нет checks/: {репо}", file=sys.stderr)
        return 2

    цели = [ф for ф in sorted(проверки.glob("*.py"))
            if "ЧУЖИЕ = [Path(" in ф.read_text(encoding="utf-8", errors="replace")]
    if not цели:
        print(f"{репо.name}: проверок с перечнем соседей нет — переносить нечего")
        return 0

    модуль = проверки / "neighbours.py"
    надо_модуль = not модуль.is_file()
    тронуто: list[str] = []
    for ф in цели:
        т = ф.read_text(encoding="utf-8")
        было = т
        if "from neighbours import" not in т:
            if т.count(ИМПОРТ_ЯКОРЬ) < 1:
                raise Отказ(f"{ф.name}: нет строки «{ИМПОРТ_ЯКОРЬ.strip()}»")
            т = т.replace(ИМПОРТ_ЯКОРЬ, ИМПОРТ_ВСТАВКА, 1)
        for старое, новое in СЛЕПКИ:
            if старое in т:
                т = т.replace(старое, новое)
        # Уже переведённая проверка узнаётся по вызову, а не по точной форме
        # строки: у соседних копий разные имена переменной слепка (`было`,
        # `было_ин`, `было_вл`), и требовать одну форму значило бы объявлять
        # отказом уже сделанный перенос.
        сверено = "чужое_не_тронуто(" in т
        for старое, новое in СВЕРКИ:
            if новое in т:
                сверено = True
            elif старое in т:
                т = т.replace(старое, новое)
                сверено = True
        if not сверено:
            raise Отказ(f"{ф.name}: места сверки с соседом не найдено ни в одной "
                        "из известных форм")
        if т != было:
            тронуто.append(ф.name)
            if not о.dry_run:
                ф.write_text(т, encoding="utf-8")

    print(f"{репо.name}: проверок с соседями {len(цели)}, "
          f"переключено {len(тронуто)}" + (f" ({', '.join(тронуто)})" if тронуто else ""))
    if надо_модуль:
        print(f"   {'доставить' if о.dry_run else 'доставлен'} checks/neighbours.py "
              f"из {ОБРАЗЕЦ.parent.parent.name}")
        if not о.dry_run:
            shutil.copy2(ОБРАЗЕЦ, модуль)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(главная(sys.argv))
    except Отказ as ош:
        print(f"ОТКАЗ: {ош}", file=sys.stderr)
        raise SystemExit(1)
