#!/usr/bin/env python3
"""Чем подборки витрины отличаются друг от друга. Только чтение публичных страниц.

Зачем. Подборка — отдельная индексируемая страница, то есть обещание: «здесь
другой набор». Если две подборки отдают почти один и тот же первый экран, они
конкурируют между собой за один запрос, и посетителю вторая не даёт ничего.
MOD-95 зафиксировал такое пересечение у прежних двенадцати подборок Zona;
здесь проверяются те, что стоят на главной СЕЙЧАС.

Измерено 20.10 этим инструментом на zonafilm12.site (восемь подборок, все
`index, follow`, по 60 карточек на первой странице):

    recently_added ↔ recently_added_movies   общих 48 из 60   80.0 %
    top_rated      ↔ video_available         общих 50 из 60   83.3 %
    current_season ↔ new_movie_releases      общих 42 из 60   70.0 %

Остальные пары — 1.7–30 %, то есть различаются честно: вывод «почти одно и то
же» инструмент делает не всегда, и это его главное свойство.

Мера — пересечение множеств адресов произведений на первой странице, доля
общего от МЕНЬШЕГО из двух наборов. Иначе короткая подборка, целиком входящая в
длинную, давала бы маленькую долю и пряталась.

Предел назван прямо: сравниваются ПЕРВЫЕ СТРАНИЦЫ. Полный состав подборки в
тысячу страниц так не проверить, и вывод относится к первому экрану — к тому,
что видит посетитель и что робот обходит первым.

Коды возврата: 0 — пар с высоким пересечением нет, 3 — есть, 2 — измерять
нечего (на главной нет ссылок на подборки либо ни одна не прочитана).
"""
from __future__ import annotations

import argparse
import itertools
import re
import sys
import urllib.error
import urllib.request

АГЕНТ = "factory-collections-overlap"
ТАЙМАУТ = 30

#: Выше этой доли общего два набора считаются почти одинаковыми. Порог — не
#: «на глаз»: у честно различающихся пар той же витрины он 0.017–0.30, у
#: дублирующих — 0.70–0.83, и разрыв между этими группами широкий.
ПОРОГ = 0.70


def добыть(адрес: str) -> str:
    запрос = urllib.request.Request(адрес, headers={"User-Agent": АГЕНТ})
    try:
        with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ) as о:
            return о.read().decode("utf-8", "replace")
    except (urllib.error.URLError, OSError, TimeoutError):
        return ""


def ключи_подборок(тело_главной: str) -> list[str]:
    """Ключи подборок в порядке появления на главной, без повторов."""
    return list(dict.fromkeys(
        re.findall(r'href="/collection/([^"/]+)/"', тело_главной)))


def разобрать(тело: str) -> dict:
    """Набор адресов произведений и подписи страницы подборки."""
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело, re.S)
    страниц = re.search(r"страница\s+\d+\s+из\s+(\d+)", тело)
    роботы = re.search(r'name="robots" content="([^"]*)"', тело)
    return {
        "пути": set(re.findall(r'href="(/title/[^"#?]+)"', тело)),
        "имя": re.sub(r"<[^>]+>", "", h1.group(1)).strip() if h1 else "—",
        "страниц": страниц.group(1) if страниц else "?",
        "роботы": роботы.group(1) if роботы else "?",
    }


def пересечения(наборы: dict[str, set], порог: float = ПОРОГ) -> list[dict]:
    """Пары с долей общего от МЕНЬШЕГО набора, по убыванию доли."""
    итог = []
    for а, б in itertools.combinations(sorted(наборы), 2):
        общие = наборы[а] & наборы[б]
        меньший = min(len(наборы[а]), len(наборы[б]))
        if not меньший:
            continue
        доля = len(общие) / меньший
        итог.append({"а": а, "б": б, "общих": len(общие), "меньший": меньший,
                     "доля": доля, "почти_одно": доля >= порог})
    return sorted(итог, key=lambda п: -п["доля"])


def собрать(домен: str, загрузчик=None, из_индекса: bool = False) -> dict:
    """Наборы подборок домена. Непрочитанная страница — НЕ пустой набор.

    Пустой набор пересекался бы с чем угодно на ноль процентов и читался бы как
    «различаются», поэтому непрочитанные перечисляются отдельно.

    Загрузчик берётся из модуля, а не привязывается в объявлении: иначе подмена
    `добыть` в проверках не действовала бы, и проверки ходили бы в сеть.
    """
    загрузчик = загрузчик or добыть
    # Полка главной — ПОДМНОЖЕСТВО: измерено 20.10 на zonafilm12.site, где на
    # главной 8 подборок, а в разделе `/collections/` их 12 (добавляются четыре
    # жанровых). Вывод по восьми говорил бы о витрине меньше, чем кажется,
    # поэтому источник перечня выбирается явно.
    откуда = f"https://{домен}/collections/" if из_индекса else f"https://{домен}/"
    ключи = ключи_подборок(загрузчик(откуда))
    if not ключи:
        где = "в разделе /collections/" if из_индекса else "на главной"
        return {"не_измерено": f"{где} нет ссылок на подборки",
                "ключи": [], "наборы": {}, "подписи": {}, "непрочитанные": []}
    наборы: dict[str, set] = {}
    подписи: dict[str, dict] = {}
    непрочитанные: list[str] = []
    for ключ in ключи:
        тело = загрузчик(f"https://{домен}/collection/{ключ}/")
        if not тело:
            непрочитанные.append(ключ)
            continue
        разбор = разобрать(тело)
        наборы[ключ] = разбор["пути"]
        подписи[ключ] = разбор
    return {"ключи": ключи, "наборы": наборы, "подписи": подписи,
            "непрочитанные": непрочитанные}


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("домен")
    р.add_argument("--threshold", type=float, default=ПОРОГ,
                   help="доля общего, выше которой наборы считаются дублем")
    р.add_argument("--from-index", action="store_true",
                   help="брать перечень из /collections/, а не с главной:"
                        " полка главной — подмножество")
    дов = р.parse_args(аргв)

    итог = собрать(дов.домен, из_индекса=дов.from_index)
    if "не_измерено" in итог:
        print(f"НЕ ИЗМЕРЕНО: {итог['не_измерено']} ({дов.домен})")
        return 2

    откуда = "в разделе /collections/" if дов.from_index else "на главной"
    print(f"{дов.домен}: подборок {откуда} {len(итог['ключи'])}")
    for ключ in итог["ключи"]:
        if ключ in итог["непрочитанные"]:
            print(f"   {ключ:26} НЕ ИЗМЕРЕНО: страница не прочитана")
            continue
        п = итог["подписи"][ключ]
        print(f"   {ключ:26} «{п['имя'][:30]:32}»"
              f" карточек {len(п['пути']):3}"
              f" страниц {п['страниц']:>5} robots {п['роботы']}")

    if not итог["наборы"]:
        print("\nНЕ ИЗМЕРЕНО: ни одна подборка не прочитана")
        return 2

    пары = пересечения(итог["наборы"], дов.threshold)
    print("\nпересечения первых страниц (доля общего от меньшего набора):")
    for п in пары:
        if not п["общих"]:
            continue
        метка = "  ПОЧТИ ОДНО И ТО ЖЕ" if п["почти_одно"] else ""
        print(f"   {п['а']:24} ↔ {п['б']:24} общих {п['общих']:3}"
              f" из {п['меньший']:3}  {п['доля'] * 100:5.1f} %{метка}")

    похожие = [п for п in пары if п["почти_одно"]]
    print()
    if похожие:
        print(f"пар с пересечением {дов.threshold * 100:.0f} % и выше:"
              f" {len(похожие)}")
        return 3
    print("пар с высоким пересечением нет: первые страницы подборок различаются")
    return 0


if __name__ == "__main__":
    sys.exit(main())
