"""Чем подборки витрины отличаются друг от друга. Только чтение публичных страниц.

Зачем. Подборка — отдельная индексируемая страница, то есть обещание: «здесь
другой набор». Если две подборки отдают почти один и тот же первый экран, они
конкурируют между собой за один запрос, и посетителю вторая не даёт ничего.
MOD-95 уже зафиксировал такое пересечение у прежних двенадцати подборок Zona;
здесь проверяются те, что стоят на главной СЕЙЧАС.

Мера — пересечение множеств адресов произведений на первой странице каждой
подборки, в обе стороны (доля общего от меньшей из двух). Сравнение по первой
странице названо прямо: полный состав подборки в тысячу страниц так не
проверить, и вывод делается про первый экран, который и видит посетитель.
"""
import itertools
import re
import sys
import urllib.error
import urllib.request

ДОМЕН = sys.argv[1] if len(sys.argv) > 1 else "zonafilm12.site"
ПОРОГ = 0.70  # выше этого два набора считаются почти одинаковыми


def добыть(адрес: str) -> str:
    запрос = urllib.request.Request(
        адрес, headers={"User-Agent": "factory-collections-overlap"})
    try:
        with urllib.request.urlopen(запрос, timeout=30) as о:
            return о.read().decode("utf-8", "replace")
    except (urllib.error.URLError, OSError, TimeoutError):
        return ""


главная = добыть(f"https://{ДОМЕН}/")
ключи = list(dict.fromkeys(re.findall(r'href="/collection/([^"/]+)/"', главная)))
if not ключи:
    print(f"НЕ ИЗМЕРЕНО: на главной {ДОМЕН} ссылок на подборки не найдено")
    raise SystemExit(2)

print(f"{ДОМЕН}: подборок на главной {len(ключи)}")
наборы: dict[str, set] = {}
для_отчёта = {}
for ключ in ключи:
    тело = добыть(f"https://{ДОМЕН}/collection/{ключ}/")
    if not тело:
        print(f"   {ключ:26} НЕ ИЗМЕРЕНО: страница не прочитана")
        continue
    пути = set(re.findall(r'href="(/title/[^"#?]+)"', тело))
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело, re.S)
    имя = re.sub(r"<[^>]+>", "", h1.group(1)).strip() if h1 else "—"
    страниц = re.search(r"страница\s+\d+\s+из\s+(\d+)", тело)
    роботы = re.search(r'name="robots" content="([^"]*)"', тело)
    наборы[ключ] = пути
    для_отчёта[ключ] = (имя, len(пути), страниц.group(1) if страниц else "?",
                        роботы.group(1) if роботы else "?")
    print(f"   {ключ:26} «{имя[:30]:32}» карточек {len(пути):3}"
          f" страниц {для_отчёта[ключ][2]:>5} robots {для_отчёта[ключ][3]}")

print("\nпересечения первых страниц (доля общего от меньшего набора):")
похожие = []
for а, б in itertools.combinations(sorted(наборы), 2):
    общие = наборы[а] & наборы[б]
    меньший = min(len(наборы[а]), len(наборы[б])) or 1
    доля = len(общие) / меньший
    if доля > 0:
        метка = "  ПОЧТИ ОДНО И ТО ЖЕ" if доля >= ПОРОГ else ""
        print(f"   {а:24} ↔ {б:24} общих {len(общие):3} из {меньший:3}"
              f"  {доля * 100:5.1f} %{метка}")
    if доля >= ПОРОГ:
        похожие.append((а, б, доля))

print()
if похожие:
    print(f"пар с пересечением {ПОРОГ * 100:.0f} % и выше: {len(похожие)}")
    raise SystemExit(3)
print("пар с высоким пересечением нет: первые страницы подборок различаются")
