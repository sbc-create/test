#!/usr/bin/env python3
"""Пробное сжатие постеров: что даёт уменьшение до размера показа. НЕ внедрение.

Опыт на копиях. Ничего не меняет в продакшене, ничего не выкладывает и не
создаёт вторую коллекцию: файлы пишутся в указанный временный каталог, по
умолчанию десятки, а не десятки тысяч.

ЧТО СРАВНИВАЕТСЯ. Сегодняшний файл (как он приходит браузеру) против того же
изображения, уменьшенного до РЕАЛЬНОГО размера показа с запасом на плотность
экрана 2 и закодированного в WebP и AVIF. Сравнение веса — прямое. Сравнение
качества — на том размере, на котором картинку видят, а не на оригинальном:
уменьшенная версия на своём размере показа может быть НЕОТЛИЧИМА, и именно это
проверяется.

КАК СЧИТАЕТСЯ КАЧЕСТВО, и почему не «на глаз». Эталон — исходник, уменьшенный
до размера показа лучшим фильтром (LANCZOS) без потерь сжатия. Кандидат —
уменьшенный и сжатый. Считается RMS разницы и PSNR по всему кадру, а затем
ОТДЕЛЬНО по двум местам, где потери заметнее всего:

  худшая девятая часть   кадр делится на 3x3, берётся плитка с худшим PSNR —
                         так находятся надписи и лица, если они пострадали;
  тёмные участки         маска по яркости < 64; на тёмном бандинг виден глазом
                         раньше, чем средний PSNR успевает упасть.

PSNR 40 дБ и выше на размере показа принято считать «различий не видно»; 35–40
— «видно при сравнении рядом»; ниже 35 — «видно сразу». Порог не мой: это
общепринятая шкала для фотографий, и она названа здесь ради проверяемости, а
не как гарантия.

ЧЕГО ОПЫТ НЕ ДАЁТ: вывода о всей коллекции по нескольким тяжёлым файлам.
Поэтому печатается распределение (медиана, p95), а не средняя экономия, и
указывается, сколько файлов измерено.

    python3 automation/local/poster-recompress-trial.py --from-csv … --limit 60
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import math
import pathlib
import statistics
import subprocess
import sys


#: ОТКУДА БЕРЁТСЯ PIL, и почему это важно знать читателю отчёта.
#: Pillow установлен в каталоге ПОЛЬЗОВАТЕЛЯ (`~/.local/lib/python3.10/
#: site-packages`), а не в системном python3. Следствия, оба измерены 23.10:
#: инструмент работает от имени `claude` и не работает под `python3 -s`; и
#: КОД ВИТРИНЫ, запускаемый службой системным интерпретатором, PIL не видит
#: вовсе — соседняя линия выпустила на этом уменьшение обложек и получила ноль
#: эффекта, потому что проверяла функцию в своём окружении, а не в том, где она
#: работает. Поэтому отказ здесь называет не только ошибку импорта, но и место
#: установки: иначе читатель будет искать её в коде.
ГДЕ_PIL = ("Pillow недоступен ИМЕННО ЭТОМУ интерпретатору. Измерено 23.10:"
           " библиотека стояла только в каталоге пользователя"
           " (~/.local/lib/python3.10/site-packages), и системный python3"
           " службы её не видел — выпущенная правка полдня не действовала."
           " С 23.10 на узле стоит системный python3-pil 9.0.1; если отказ"
           " виден сейчас, значит запуск идёт другим интерпретатором или в"
           " другом окружении. Проверять окружением службы:"
           " automation/local/service-image-support-check.py")


АГЕНТ = "factory-poster-trial"
#: Запас на плотность экрана. Два — потому что больше не использует ни один
#: экран, а меньше означало бы мягкую картинку на retina.
ЗАПАС_DPR = 2
#: Лестница качества, а не одно число. «Экономия N %» без названного качества
#: — бессмысленное число: подобрать качество можно только перебором с
#: измерением. Порядок от высокого к низкому, и берётся первое, которое
#: укладывается в целевой PSNR.
ЛЕСТНИЦА = {
    "webp": (95, 90, 85, 80),
    "avif": (80, 70, 60),
}
#: Целевое качество на размере показа. 40 дБ — общепринятая граница «различий
#: не видно»; ниже она названа в описании вместе с остальной шкалой.
ЦЕЛЬ_PSNR = 40.0


def psnr(rms: float) -> float:
    if rms <= 0:
        return 99.0
    return 20 * math.log10(255.0 / rms)


def метрики(эталон, кандидат) -> dict:
    from PIL import Image, ImageChops, ImageStat

    э = эталон.convert("RGB")
    к = кандидат.convert("RGB")
    if э.size != к.size:
        к = к.resize(э.size, Image.LANCZOS)
    разница = ImageChops.difference(э, к)
    общий = psnr(ImageStat.Stat(разница).rms[0])

    ш, в = э.size
    худшая = 99.0
    for i in range(3):
        for j in range(3):
            окно = (ш * i // 3, в * j // 3, ш * (i + 1) // 3, в * (j + 1) // 3)
            плитка = ImageStat.Stat(разница.crop(окно)).rms[0]
            худшая = min(худшая, psnr(плитка))

    серый = э.convert("L")
    маска = серый.point(lambda з: 255 if з < 64 else 0)
    доля_тёмного = ImageStat.Stat(маска).mean[0] / 255
    тёмное = 99.0
    if доля_тёмного > 0.01:
        тёмное = psnr(ImageStat.Stat(разница, mask=маска).rms[0])
    return {"psnr": round(общий, 1), "psnr_худшая_плитка": round(худшая, 1),
            "psnr_тёмное": round(тёмное, 1),
            "доля_тёмного": round(доля_тёмного, 3)}


def достать(url: str, таймаут: int = 25) -> bytes:
    г = subprocess.run(["curl", "-s", "-m", str(таймаут), "-H",
                        f"User-Agent: {АГЕНТ}", url], capture_output=True)
    return г.stdout if г.returncode == 0 else b""


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--from-csv", required=True,
                   help="CSV от poster-delivery-audit.py")
    р.add_argument("--limit", type=int, default=60)
    р.add_argument("--min-excess", type=float, default=0.0,
                   help="брать только адреса с запасом разрешения выше этого")
    р.add_argument("--all-steps", action="store_true",
                   help="записать всю лестницу качества, а не первое попадание")
    р.add_argument("--work", default="", help="куда писать копии (временный)")
    р.add_argument("--csv", default="")
    а = р.parse_args(аргв)

    try:
        from PIL import Image
    except ImportError as сбой:
        print(f"НЕ ИЗМЕРЕНО: {type(сбой).__name__}: {сбой}. {ГДЕ_PIL}")
        return 2

    работа = pathlib.Path(а.work) if а.work else None
    if работа:
        работа.mkdir(parents=True, exist_ok=True)

    взято: dict[str, dict] = {}
    with open(а.from_csv, encoding="utf-8") as ф:
        for с in csv.DictReader(ф):
            if с["исход"] == "НЕ ИЗМЕРЕНО" or not с.get("объявлено_w"):
                continue
            try:
                запас = float(с.get("запас_к_объявленному") or 0)
            except ValueError:
                запас = 0.0
            if запас < а.min_excess:
                continue
            ключ = с["адрес_картинки"]
            if ключ in взято:
                continue
            взято[ключ] = с
            if len(взято) >= а.limit:
                break
    if not взято:
        print("НЕ ИЗМЕРЕНО: в CSV нет подходящих строк")
        return 2

    строки = []
    for url, исх in взято.items():
        данные = достать(url)
        if not данные:
            строки.append({"адрес": url, "исход": "НЕ ИЗМЕРЕНО",
                           "почему": "изображение не получено"})
            continue
        try:
            кадр = Image.open(io.BytesIO(данные))
            кадр.load()
        except Exception as сбой:                    # noqa: BLE001
            строки.append({"адрес": url, "исход": "НЕ ИЗМЕРЕНО",
                           "почему": f"{type(сбой).__name__}"})
            continue
        объявл = int(исх["объявлено_w"] or 0)
        цель_ш = min(кадр.size[0], объявл * ЗАПАС_DPR) if объявл else кадр.size[0]
        цель_в = max(1, round(кадр.size[1] * цель_ш / кадр.size[0]))
        эталон = кадр.convert("RGB").resize(
            (цель_ш, цель_в), Image.LANCZOS)

        запись = {"адрес": url, "домен": исх["домен"], "вид": исх["вид"],
                  "сейчас_формат": исх["формат"], "сейчас_байт": len(данные),
                  "сейчас_пиксели": f"{кадр.size[0]}x{кадр.size[1]}",
                  "объявлено_w": объявл,
                  "цель_пиксели": f"{цель_ш}x{цель_в}", "исход": "измерено"}
        for имя, лестница in ЛЕСТНИЦА.items():
            подошло = None
            for качество in лестница:
                буфер = io.BytesIO()
                параметры = {"format": имя.upper(), "quality": качество}
                if имя == "webp":
                    параметры["method"] = 6
                try:
                    эталон.save(буфер, **параметры)
                except Exception as сбой:            # noqa: BLE001
                    запись[f"{имя}_почему"] = f"{type(сбой).__name__}: {сбой}"[:80]
                    break
                байты = буфер.getvalue()
                try:
                    обратно = Image.open(io.BytesIO(байты))
                    обратно.load()
                    м = метрики(эталон, обратно)
                except Exception as сбой:            # noqa: BLE001
                    запись[f"{имя}_почему"] = f"разбор: {type(сбой).__name__}"
                    break
                if а.all_steps:
                    запись[f"{имя}_q{качество}_байт"] = len(байты)
                    запись[f"{имя}_q{качество}_экономия"] = round(
                        100 * (1 - len(байты) / len(данные)), 1)
                    запись[f"{имя}_q{качество}_psnr"] = м["psnr"]
                    запись[f"{имя}_q{качество}_psnr_тёмное"] = м["psnr_тёмное"]
                if м["psnr"] >= ЦЕЛЬ_PSNR:
                    подошло = (качество, байты, м)
                elif not а.all_steps:
                    break
            if подошло is None:
                запись[f"{имя}_байт"] = ""
                запись.setdefault(
                    f"{имя}_почему",
                    f"ни одно качество из {лестница} не дало PSNR"
                    f" {ЦЕЛЬ_PSNR:.0f} дБ")
                continue
            качество, байты, м = подошло
            запись[f"{имя}_качество"] = качество
            запись[f"{имя}_байт"] = len(байты)
            запись[f"{имя}_экономия_проц"] = round(
                100 * (1 - len(байты) / len(данные)), 1)
            for к, з in м.items():
                запись[f"{имя}_{к}"] = з
            if работа:
                (работа / f"{url.rsplit('/', 1)[-1]}.{имя}").write_bytes(байты)
        строки.append(запись)

    измерено = [с for с in строки if с["исход"] == "измерено"]
    print(f"файлов измерено {len(измерено)} из {len(строки)} взятых")
    for имя in ("webp", "avif"):
        эк = [с[f"{имя}_экономия_проц"] for с in измерено
              if с.get(f"{имя}_экономия_проц") is not None
              and с.get(f"{имя}_байт")]
        if not эк:
            причины = {с.get(f"{имя}_почему", "") for с in измерено}
            print(f"  {имя}: НЕ ИЗМЕРЕНО — {', '.join(п for п in причины if п)}")
            continue
        p = sorted(эк)
        пс = [с[f"{имя}_psnr"] for с in измерено if с.get(f"{имя}_psnr")]
        худ = [с[f"{имя}_psnr_худшая_плитка"] for с in измерено
               if с.get(f"{имя}_psnr_худшая_плитка")]
        тём = [с[f"{имя}_psnr_тёмное"] for с in измерено
               if с.get(f"{имя}_psnr_тёмное")]
        качества = [с[f"{имя}_качество"] for с in измерено
                    if с.get(f"{имя}_качество")]
        print(f"  {имя}: качество (первое, уложившееся в"
              f" {ЦЕЛЬ_PSNR:.0f} дБ) медиана"
              f" {statistics.median(качества):.0f}, разброс"
              f" {min(качества)}–{max(качества)}")
        print(f"  {имя}: экономия медиана {statistics.median(p):.1f} %,"
              f" p05 {p[max(0, int(0.05*len(p)))]:.1f} %,"
              f" p95 {p[min(len(p)-1, int(0.95*len(p)))]:.1f} %;"
              f" PSNR медиана {statistics.median(пс):.1f} дБ,"
              f" худшая плитка медиана {statistics.median(худ):.1f} дБ,"
              f" тёмное медиана {statistics.median(тём):.1f} дБ")
        ниже = [з for з in пс if з < 35]
        print(f"      файлов с PSNR ниже 35 дБ (различие видно сразу):"
              f" {len(ниже)} из {len(пс)}")
    if а.csv and строки:
        поля = sorted({к for с in строки for к in с})
        with open(а.csv, "w", newline="", encoding="utf-8") as ф:
            п = csv.DictWriter(ф, fieldnames=поля)
            п.writeheader()
            for с in строки:
                п.writerow(с)
        print(f"CSV: {а.csv} — строк {len(строки)}")
    return 0 if измерено else 2


if __name__ == "__main__":
    sys.exit(главное())
