#: (`cell_delivery`), а не по имени домена.
ВИТРИНЫ = {
    "1lordserials1.online": ("/srv/site-1lordserials1-online/data", "lords-03"),
    "lordfilm47.space": ("/srv/lordfilm47-space/data", "lords-01"),
    "lordserial33.biz": ("/srv/lordserial33-biz/data", "lords-02"),
    "lordserials22.info": ("/srv/lordserials22-info/data", "lords-05"),
    "zonafilm.space": ("/srv/zonafilm-space/data", "zona-01"),
    "zonafilm.cc": ("/srv/zonafilm-cc/data", "zona-02"),
    "zonafilm12.site": ("/srv/zonafilm12-site/data", "zona-03"),
    "animedia.icu": ("/srv/animedia-icu/data", "animedia-01"),
    "animedia.space": ("/srv/animedia-space/data", "animedia-02"),
    # Добавлены 21.10 после проверки, что сверка по ним ВОЗМОЖНА: каталог на
    # диске собран в то же поколение, что и у соседей (8 691 запись,
    # builtAt 2026-10-21T03:15:26Z), а состав карты совпадает с ним ТОЧНО —
    # 8 691 = 8 691, ни одного отсутствующего, ни одного лишнего. До этого они
    # печатались в регулярной сверке как «не измерено».
    "an1mego.site": ("/srv/an1mego-site/data", "animego-02"),
    "animeg0.site": ("/srv/animeg0-site/data", "animego-03"),
    "an1meg0.site": ("/srv/an1meg0-site/data", "animego-04"),
}

#: Отставание файла карты от снимка, с которого стоит смотреть состав.
ПОРОГ_ОТСТАВАНИЯ_Ч = 0.5

#: ПОЧЕМУ ЗДЕСЬ НЕТ ВИТРИН YUMMY, и это измерено, а не выбрано. Их выгрузка
#: каталога на диске (`<data>/yummy-*-catalog.json`) УСТАРЕЛА: у
#: `yummyani7.site` она собрана 2026-09-28T14:41:47Z и содержит 7 386 записей,
#: тогда как её живая карта перечисляет 8 378 произведений. Сравнение по ней
#: дало бы 1 078 «лишних адресов» и 86 «отсутствующих» — около 1 164 ложных
#: находок на одной витрине. Проверено поимённо: `adskaya-mishen` в выгрузке
#: ОТСУТСТВУЕТ, а живая страница отвечает 200 с `<h1>Адская мишень`, то есть
#: страницы отдаются не из этой выгрузки.
#:
#: Пока не установлено, ЧТО именно читает эту выгрузку (паспорт ячейки
#: объявляет её в `LORDS_CATALOG`, а живое поведение этому противоречит),
#: добавлять Yummy сюда нельзя: проход начал бы врать о пяти витринах.
#: Их полноту измеряет `sitemap-completeness.py`, который сравнивает карту с
#: ЛИСТАЛКОЙ витрины, а не с файлом на диске.
НЕ_СРАВНИВАЕМ = {
    "yummyani.site": "выгрузка каталога на диске устарела (28.09) и не"
                     " является источником страниц",
    "yummyani.biz": "то же",
    "yummyani.org": "то же",
    "yummyani7.site": "то же: 7 386 записей в выгрузке против 8 378 в карте",
    "yummyani7.info": "то же",
}


def _когда(п: Path) -> dt.datetime | None:
    try:
        return dt.datetime.fromtimestamp(п.stat().st_mtime, dt.timezone.utc)
    except OSError:
        return None


def добыть(url: str, таймаут: int = 60) -> str:
    г = subprocess.run(["curl", "-sS", "--max-time", str(таймаут), url],
                       capture_output=True, text=True, timeout=таймаут + 30)
    return г.stdout


def слаги_карты(домен: str, каталог_данных: Path) -> tuple[set[str], str]:
    """Слаги произведений из карты: (набор, откуда прочитано).

    Файлы карты принадлежат учётной записи витрины и закрыты от чужого чтения
    (`-rw-------`) — и это правильно: данные сайта чужому процессу не
    принадлежат. Поэтому карта читается ПО СЕТИ, и это честнее: обходчик видит
    именно её.
    """
    индекс = добыть(f"https://{домен}/sitemap.xml", 60)
    части = [ч for ч in re.findall(r"<loc>([^<]+)</loc>", индекс)
             if "sitemap" in ч]
    итог: set[str] = set()
    for ч in части or [f"https://{домен}/sitemap.xml"]:
        тело = добыть(ч, 180)
        итог |= {м.group(1) for м in
                 re.finditer(r"<loc>[^<]*/title/([^/<]+)/?</loc>", тело)}
    return итог, f"по сети, частей {len(части)}"


#: Сколько отсутствующих страниц опрашивать на индексируемость. Ноль — не
#: опрашивать вовсе (тогда вывод честно скажет «не измерено»).
ПРОБ_ПО_УМОЛЧАНИЮ = 12


def индексируемость(домен: str, слаги: list[str], *, загрузчик=None) -> dict:
    """index или noindex у выборки отсутствующих страниц.

    ЗАЧЕМ ЭТО ЗДЕСЬ, И БЕЗ ЭТОГО ПРОХОД ЛГАЛ. Первая версия объявляла
    «РАСХОЖДЕНИЕ СОСТАВА» при любом отсутствии записи в карте — и выдала его
    трём витринам, из которых две чисты: у `animedia.icu` и `animedia.space`
    карта переписана через минуты после доставки, а 463 отсутствующие записи
    стоят `noindex` (очередь тематического допуска, измерено 20.10 на всех 448
    прежних). Карта обязана описывать индексируемое, и отсутствие `noindex`
    записи — согласованность, а не пробел.
    """
    загрузить = загрузчик or (lambda url: добыть(url, 30))
    итог = {"проверено": 0, "index": [], "noindex": 0, "иное": 0}
    for слаг in слаги:
        тело = загрузить(f"https://{домен}/title/{слаг}/")
        итог["проверено"] += 1
        м = re.search(r'<meta name="robots" content="([^"]*)"', тело)
        если = (м.group(1) if м else "")
        if "noindex" in если:
            итог["noindex"] += 1
        elif "index" in если:
            итог["index"].append(слаг)
        else:
            итог["иное"] += 1
    return итог


def разобрать(домен: str, *, проб: int = ПРОБ_ПО_УМОЛЧАНИЮ,
              загрузчик=None) -> dict:
    каталог_данных, site_id = ВИТРИНЫ[домен]
    д = Path(каталог_данных)
    файл_карты = д / "sitemap" / "sitemap.xml"
    файл_каталога = д / f"{site_id}-catalog.json"
    когда_карта = _когда(файл_карты)
    когда_каталог = _когда(файл_каталога)
    итог: dict = {"домен": домен, "site_id": site_id,
                  "карта переписана": когда_карта.isoformat() if когда_карта else None,
                  "каталог доставлен": (когда_каталог.isoformat()
                                        if когда_каталог else None)}
    if когда_карта is None:
        итог["итог"] = "НЕ ИЗМЕРЕНО"
        итог["почему"] = "файлов карты у витрины нет"
        return итог
    if когда_каталог is None:
        итог["итог"] = "НЕ ИЗМЕРЕНО"
        итог["почему"] = "снимка каталога у витрины нет"
        return итог
    итог["отставание_ч"] = round(
        (когда_каталог - когда_карта).total_seconds() / 3600, 1)

    каталог = json.loads(файл_каталога.read_text(encoding="utf-8"))
    слаги_каталога = {str(з.get("slug")) for з in (каталог.get("items") or [])
                      if з.get("slug")}
    в_карте, откуда = слаги_карты(домен, д)
    нет_в_карте = sorted(слаги_каталога - в_карте)
    лишние = sorted(в_карте - слаги_каталога)
    итог.update({
        "записей в каталоге": len(слаги_каталога),
        "произведений в карте": len(в_карте),
        "нет в карте": len(нет_в_карте),
        "лишних в карте": len(лишние),
        "примеры отсутствующих": нет_в_карте[:10],
        "примеры лишних": лишние[:10],
        "карта прочитана": откуда,
        "поколение каталога": каталог.get("revision"),
        "каталог собран": каталог.get("builtAt"),
    })
    if нет_в_карте and проб:
        случ = random.Random(len(нет_в_карте))
        выборка = sorted(случ.sample(нет_в_карте, min(проб, len(нет_в_карте))))
        п = индексируемость(домен, выборка, загрузчик=загрузчик)
        итог["проба отсутствующих"] = {
            "охват": f"{п['проверено']} из {len(нет_в_карте)}",
            "index (пробел карты)": п["index"],
            "noindex (отсутствие согласовано)": п["noindex"],
            "без метки robots": п["иное"],
        }
    if лишние:
        итог["итог"] = "ЛИШНИЕ АДРЕСА В КАРТЕ"
    elif нет_в_карте and not проб:
        итог["итог"] = "НЕ ИЗМЕРЕНО"
        итог["почему"] = (f"{len(нет_в_карте)} записей нет в карте, а"
                          " индексируемость не опрашивалась (--probe 0)")
    elif нет_в_карте and итог.get("проба отсутствующих", {}).get(
            "index (пробел карты)"):
        итог["итог"] = "ПРОБЕЛ КАРТЫ"
    elif нет_в_карте:
        итог["итог"] = "отсутствия согласованы с допуском"
        итог["почему"] = (
            f"{len(нет_в_карте)} записей каталога нет в карте, и у всех"
            f" проверенных стоит `noindex` — карта описывает индексируемое")
    elif итог["отставание_ч"] > ПОРОГ_ОТСТАВАНИЯ_Ч:
        итог["итог"] = "состав совпал"
        итог["почему"] = (
            f"файл карты старше снимка на {итог['отставание_ч']} ч, но состав"
            " тот же: снимок перезаписан прежним содержимым. Дефектом это не"
            " является")
    else:
        итог["итог"] = "ок"
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", default="")
    р.add_argument("--json", action="store_true")
    р.add_argument("--probe", type=int, default=ПРОБ_ПО_УМОЛЧАНИЮ,
                   help="сколько отсутствующих страниц опросить на"
                        " индексируемость; 0 — не опрашивать")
    а = р.parse_args(аргв)
    домены = [а.domain] if а.domain else sorted(ВИТРИНЫ)
    исключённые = [д for д in домены if д in НЕ_СРАВНИВАЕМ]
    for д in исключённые:
        print(f"\n{д}: НЕ СРАВНИВАЕТСЯ — {НЕ_СРАВНИВАЕМ[д]}."
              f" Полноту этой витрины измеряет sitemap-completeness.py")
    домены = [д for д in домены if д not in НЕ_СРАВНИВАЕМ]
    нет = [д for д in домены if д not in ВИТРИНЫ]
    if нет:
        print(f"НЕ ИЗМЕРЕНО: нет в перечне витрин: {', '.join(нет)}")
        return 2
    if not домены:
        # ИСКЛЮЧЁННАЯ ВИТРИНА — НЕ «ок». Код 2 означает «не измерено», и
        # регулярная сверка печатает именно это. Код 0 здесь был ошибкой: в
        # прогоне 21.10 07:00Z пять витрин Yummy получили «ок» в столбце, где
        # проход их даже не сравнивал.
        return 2
    итоги = [разобрать(д, проб=а.probe) for д in домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            print(f"\n{и['домен']} ({и['site_id']}): {и['итог']}")
            print(f"   карта переписана {и['карта переписана']},"
                  f" каталог доставлен {и['каталог доставлен']}")
            if "отставание_ч" in и:
                print(f"   отставание файла: {и['отставание_ч']} ч")
            if "записей в каталоге" in и:
                print(f"   записей в каталоге {и['записей в каталоге']},"
                      f" произведений в карте {и['произведений в карте']},"
                      f" нет в карте {и['нет в карте']},"
                      f" лишних {и['лишних в карте']}")
                if и["примеры отсутствующих"]:
                    print(f"   примеры отсутствующих:"
                          f" {', '.join(и['примеры отсутствующих'][:6])}")
            if и.get("проба отсутствующих"):
                п = и["проба отсутствующих"]
                print(f"   проба отсутствующих ({п['охват']}):"
                      f" noindex {п['noindex (отсутствие согласовано)']},"
                      f" index {len(п['index (пробел карты)'])},"
                      f" без метки {п['без метки robots']}")
                if п["index (пробел карты)"]:
                    print(f"   ПРОБЕЛ КАРТЫ, примеры:"
                          f" {', '.join(п['index (пробел карты)'][:6])}")
            if и.get("почему"):
                print(f"   {и['почему']}")
        print("\nЧЕГО ЭТОТ ПРОХОД НЕ ГОВОРИТ:")
        print("   — ВСЮ разницу: индексируемость опрашивается ВЫБОРКОЙ, и её"
              " охват напечатан выше. Полный опрос всех отсутствующих —"
              " `sitemap-catalog-reconcile-anime.py` без предела (на"
              " 1lordserials1.online он дал 770 из 770 `index`);")
        print("   — почему витрина не переписала карту: время файла этого не"
              " говорит. Оно говорит, что не переписала.")
    расхождений = sum(1 for и in итоги
                      if и["итог"] in ("ПРОБЕЛ КАРТЫ", "ЛИШНИЕ АДРЕСА В КАРТЕ"))
    не_измерено = sum(1 for и in итоги if и["итог"] == "НЕ ИЗМЕРЕНО")
    if расхождений:
        return 1
    return 2 if не_измерено else 0


if __name__ == "__main__":
    sys.exit(главное())
