#!/usr/bin/env python3
"""Отстаёт ли карта витрины от доставленного каталога. Только чтение.

Признак, которого не было ни у одной прежней проверки карты. Те отвечают на
вопросы о СОДЕРЖИМОМ карты (полна ли, согласован ли индекс, верны ли даты), а
этот — на вопрос «описывает ли карта ТО ЖЕ ПОКОЛЕНИЕ каталога, из которого
витрина отдаёт страницы». Между ними разница в сутки может уместиться
незамеченной.

Измерено 21.10, и ровно так дефект и нашёлся:

| витрина | карта переписана | снимок каталога | отставание |
| --- | --- | --- | --- |
| **1lordserials1.online** | 20.10 06:19:15Z | 21.10 04:14:42Z | **21,9 ч** |
| lordfilm47.space | 21.10 04:17:30Z | 21.10 04:14:37Z | нет |
| lordserial33.biz | 21.10 04:18:08Z | 21.10 04:14:40Z | нет |
| lordserials22.info | 21.10 05:43:49Z | 21.10 05:42:16Z | нет |
| zonafilm.space | 21.10 04:16:42Z | 21.10 04:14:55Z | нет |
| zonafilm.cc | 21.10 04:20:36Z | 21.10 04:14:58Z | нет |
| zonafilm12.site | 21.10 04:18:41Z | 21.10 04:15:01Z | нет |
| animedia.space | 21.10 04:26:30Z | 21.10 04:49:46Z | нет |

Семь витрин переписали карту через 2-4 минуты после доставки, одна не
переписала сутки. Отставание — не свойство устройства, а отказ ОДНОЙ витрины,
и именно это делает его дефектом, а не нормой.

ПЕРВАЯ ВЕРСИЯ ЭТОГО ПРОХОДА ДАВАЛА ЛОЖНЫЕ НАХОДКИ, и это исправлено здесь же.
Она объявляла расхождением любое отсутствие записи в карте — и назвала
«расхождением» ещё и `animedia.icu` с `animedia.space`, где карта переписана
через минуты после доставки, а 463 отсутствующие записи стоят `noindex`
(очередь тематического допуска). Карта обязана описывать ИНДЕКСИРУЕМОЕ,
поэтому проход опрашивает выборку отсутствующих страниц и различает:
`index` — пробел карты, `noindex` — согласованность.

ЧЕГО ОТСТАВАНИЕ ПО ВРЕМЕНИ САМО ПО СЕБЕ НЕ ЗНАЧИТ. Снимок могли перезаписать
тем же содержимым: обновлятель пишет файл безусловно, и у `animedia.icu`
измерено отставание 1,2 ч при полностью согласованной карте. Поэтому время —
только повод посмотреть СОСТАВ, и проход считает расхождение состава сам:
сколько записей каталога карта не называет.

    python3 automation/local/sitemap-generation-lag.py
    python3 automation/local/sitemap-generation-lag.py --domain 1lordserials1.online --json
"""
