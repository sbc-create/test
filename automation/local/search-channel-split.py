#!/usr/bin/env python3
"""Поисковый канал раздельно по Яндексу и Google: окна и суточный ряд.

Только чтение артефактов кабинета Метрики. Ничего не пишет и никуда не ходит.

Зачем отдельный инструмент. План недели (§7.1) требует органику раздельно по
Яндексу и Google, а сводка визитов из поиска этого не различает. Разница не
косметическая: домен может расти одним каналом и одновременно терять другой, и
тогда сценарий, который меряет позиции по Вебмастеру (только Яндекс), меряет
не тот канал, которым домен растёт.

Измерено этим инструментом 20.10 (окна 03–09.10 против 13–19.10, визиты):

    lordserials22.info   Яндекс 188 → 165,  Google  61 → 664
    yummyani.site        Яндекс 16002 → 11543, Google 11 → 4
    zonafilm.cc          Яндекс 0 → 0,      Google   0 → 328
    animedia.icu         Яндекс 80 → 746,   Google   0 → 61

Суточный ряд нужен рядом с окнами: окна показывают разницу, ряд — момент
перелома. У lordserials22.info поисковые посетители Яндекса идут
14, 9, 20, 111, 50, 28, 27, 21, 26, 21, 16, 5, 9, 6 (06–19.10) — то есть канал
не «вырос на 2 %», а осыпался после 09.10, и в сводке окон это не видно.

ЧЕСТНОСТЬ ЧИСЕЛ — три правила, за каждым своя ошибка, которую они ловят.

1. **«Не измерено» не равно нулю.** Домен без счётчика и домен с нулём
   посетителей печатаются по-разному, и в итоги «не измерено» не складывается.
2. **Посетители и визиты не смешиваются.** `daily_search` отдаёт обе метрики
   (`ym:s:users, ym:s:visits`), и подпись каждой строки называет, какая
   напечатана. Владелец запретил подменять посетителей визитами.
3. **Обрезанную разбивку нельзя складывать как полную.** Сводка
   `search_engines` просит ровно `BREAKDOWN_LIMIT = 20` строк; если строк
   пришло столько же, остаток мог быть отброшен источником, и инструмент
   помечает такую сумму как нижнюю границу. Суточный ряд этим не страдает:
   он приходит отдельным запросом с другим пределом.

Коды возврата: 0 — измерено по всем запрошенным доменам, 1 — измерено
частично, 2 — не измерено ничего.
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import sys

#: Предел строк разбивки в сборщике (`seo_operator/analytics_collect.py`).
#: Равенство числа строк этому пределу — признак возможной обрезки.
ПРЕДЕЛ_РАЗБИВКИ = 20

#: Корни поисковиков, которые разделяем. Остальное идёт в «прочие»: сливать
#: Bing и Mail с Google нельзя, а заводить им колонки не за чем — объём единицы.
ЯНДЕКС = "yandex"
ГУГЛ = "google"

#: Метрики `daily_search` в порядке запроса сборщика.
ПОСЕТИТЕЛИ, ВИЗИТЫ = 0, 1


def загрузить(путь: pathlib.Path) -> dict:
    return json.loads(путь.read_text(encoding="utf-8"))


def _строки(измерение: dict) -> list:
    значение = измерение.get("value")
    if isinstance(значение, dict):
        return значение.get("data") or []
    return значение or []


def _корень(измерения: list, место: int) -> str:
    if len(измерения) <= место:
        return ""
    поле = измерения[место]
    return (поле.get("id") or поле.get("name") or "").lower()


def канал_по_суткам(снимок: dict, домен: str, метрика: int = ВИЗИТЫ) -> dict:
    """Суточный ряд по поисковикам. None, если показатель не измерен.

    Возвращает {"ряд": {поисковик: {дата: число}}, "источник": …} либо
    {"не_измерено": причина}.
    """
    домены = {з.get("domain"): з for з in снимок.get("domains") or []}
    запись = домены.get(домен)
    if запись is None:
        return {"не_измерено": "домена нет в выгрузке"}
    измерения = {и["key"]: и for и in запись.get("measurements") or []}
    и = измерения.get("daily_search")
    if и is None:
        return {"не_измерено": "показателя daily_search в выгрузке нет"}
    if not и.get("measured"):
        return {"не_измерено": и.get("reason") or "причина не названа"}
    ряд: dict[str, collections.Counter] = collections.defaultdict(
        collections.Counter)
    for строка in _строки(и):
        измер = строка.get("dimensions") or []
        дата = (измер[0].get("name") if измер else None) or "?"
        поисковик = _корень(измер, 2)
        если = (ЯНДЕКС if ЯНДЕКС in поисковик
                else ГУГЛ if ГУГЛ in поисковик else "прочие")
        метрики = строка.get("metrics") or []
        if len(метрики) > метрика:
            ряд[если][дата] += метрики[метрика]
    return {"ряд": {к: dict(v) for к, v in ряд.items()},
            "источник": и.get("source"),
            "выборка": и.get("sampled"),
            "доля_выборки": и.get("sample_share")}


def канал_за_окно(снимок: dict, домен: str) -> dict:
    """Сумма визитов по поисковикам из сводки `search_engines`.

    Помечает сумму как нижнюю границу, если строк пришло ровно столько,
    сколько просит сборщик: остаток мог быть отброшен источником.
    """
    домены = {з.get("domain"): з for з in снимок.get("domains") or []}
    запись = домены.get(домен)
    if запись is None:
        return {"не_измерено": "домена нет в выгрузке"}
    измерения = {и["key"]: и for и in запись.get("measurements") or []}
    и = измерения.get("search_engines")
    if и is None:
        return {"не_измерено": "показателя search_engines в выгрузке нет"}
    if not и.get("measured"):
        return {"не_измерено": и.get("reason") or "причина не названа"}
    строки = _строки(и)
    итог: collections.Counter = collections.Counter()
    for строка in строки:
        имя = ((строка.get("dimensions") or [{}])[0].get("name") or "").lower()
        визиты = (строка.get("metrics") or [0])[0]
        если = (ЯНДЕКС if ЯНДЕКС in имя
                else ГУГЛ if ГУГЛ in имя else "прочие")
        итог[если] += визиты
    return {"визиты": dict(итог),
            "строк": len(строки),
            "нижняя_граница": len(строки) >= ПРЕДЕЛ_РАЗБИВКИ,
            "источник": и.get("source")}


def чем_растёт(было: dict, стало: dict, порог_данных: int = 10) -> str:
    """Словесный вывод по двум окнам. «Мало данных» — тоже ответ."""
    if "не_измерено" in стало:
        return "не измерено"
    б = (было or {}).get("визиты") or {}
    с = стало["визиты"]
    я, г = с.get(ЯНДЕКС, 0), с.get(ГУГЛ, 0)
    dя, dг = я - б.get(ЯНДЕКС, 0), г - б.get(ГУГЛ, 0)
    if я + г < порог_данных:
        return "мало данных"
    if dг > dя and dг > 0:
        return "Google, Яндекс падает" if dя < 0 else "Google"
    if dя > 0:
        return "Яндекс, Google падает" if dг < 0 else "Яндекс"
    return "не растёт"


def _печать_окон(до: dict, после: dict, домены: list[str]) -> int:
    без_данных = 0
    шапка = (f"{'домен':24}{'Я было':>8}{'Я стало':>8}{'Я изм':>7}"
             f"{'G было':>8}{'G стало':>8}{'G изм':>7}   чем растёт")
    print(шапка)
    print("-" * len(шапка))
    for домен in домены:
        б = канал_за_окно(до, домен) if до else {"не_измерено": "окна «до» нет"}
        с = канал_за_окно(после, домен)
        if "не_измерено" in с:
            print(f"{домен:24}НЕ ИЗМЕРЕНО — {с['не_измерено'][:46]}")
            без_данных += 1
            continue
        бв = б.get("визиты") or {}
        св = с["визиты"]
        пометка = " (нижняя граница: разбивка обрезана)" if с["нижняя_граница"] else ""
        print(f"{домен:24}{бв.get(ЯНДЕКС, 0):8.0f}{св.get(ЯНДЕКС, 0):8.0f}"
              f"{св.get(ЯНДЕКС, 0) - бв.get(ЯНДЕКС, 0):+7.0f}"
              f"{бв.get(ГУГЛ, 0):8.0f}{св.get(ГУГЛ, 0):8.0f}"
              f"{св.get(ГУГЛ, 0) - бв.get(ГУГЛ, 0):+7.0f}"
              f"   {чем_растёт(б, с)}{пометка}")
    return без_данных


def _печать_ряда(после: dict, домены: list[str], метрика: int,
                 подпись: str) -> None:
    даты: set[str] = set()
    ряды = {}
    for домен in домены:
        р = канал_по_суткам(после, домен, метрика)
        ряды[домен] = р
        if "ряд" in р:
            for поисковик in р["ряд"].values():
                даты |= set(поисковик)
    порядок = sorted(д for д in даты if д != "?")
    print(f"\nпоисковые {подпись} по суткам (Я — Яндекс, G — Google)")
    print(f"{'домен':22}{'иск':4}" + " ".join(д[-2:].rjust(4) for д in порядок))
    for домен in домены:
        р = ряды[домен]
        if "ряд" not in р:
            print(f"{домен:22}НЕ ИЗМЕРЕНО — {р['не_измерено'][:44]}")
            continue
        for поисковик, метка in ((ЯНДЕКС, "Я"), (ГУГЛ, "G")):
            по_датам = р["ряд"].get(поисковик)
            if not по_датам:
                continue
            числа = " ".join(f"{по_датам.get(д, 0):4.0f}" for д in порядок)
            print(f"{домен:22}{метка:4}{числа}")


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--after", required=True,
                   help="выгрузка кабинета за текущее окно")
    р.add_argument("--before", default="",
                   help="выгрузка за базовое окно (без неё печатается только ряд)")
    р.add_argument("--domain", action="append", default=[],
                   help="домен; по умолчанию все домены выгрузки")
    р.add_argument("--series", choices=("users", "visits", "none"),
                   default="users",
                   help="какой суточный ряд печатать (по умолчанию посетители)")
    дов = р.parse_args(аргв)

    после = загрузить(pathlib.Path(дов.after))
    до = загрузить(pathlib.Path(дов.before)) if дов.before else None
    домены = дов.domain or [з.get("domain") for з in после.get("domains") or []]

    print(f"окно «после»: собрано {после.get('collected_at')},"
          f" период {после.get('period')}")
    if до is not None:
        print(f"окно «до»:    собрано {до.get('collected_at')},"
              f" период {до.get('period')}")
    print()

    без_данных = _печать_окон(до, после, домены)
    if дов.series != "none":
        метрика = ПОСЕТИТЕЛИ if дов.series == "users" else ВИЗИТЫ
        подпись = "ПОСЕТИТЕЛИ" if дов.series == "users" else "ВИЗИТЫ"
        _печать_ряда(после, домены, метрика, подпись)

    if без_данных == len(домены):
        return 2
    return 1 if без_данных else 0


if __name__ == "__main__":
    sys.exit(main())
