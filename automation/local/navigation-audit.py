#!/usr/bin/env python3
"""Навигация витрины: по собственным ссылкам, с проверкой СОДЕРЖИМОГО.

Зачем ещё один проход, когда доступность уже проверяется. `availability-sweep`
проверяет четыре типа страниц (главная, карточка, серия, плеер) и берёт их по
известной форме адреса. Здесь вопрос другой: работает ли то, КУДА САМА ВИТРИНА
ВЕДЁТ ПОСЕТИТЕЛЯ. Список типов не задаётся — он собирается из ссылок главной,
иначе проход проверял бы мои представления о витрине, а не витрину.

Повод назван измерением 20.10: на всех пяти витринах Yummy страницы каталога
335-349 отдают HTTP 200 и НИ ОДНОЙ карточки (MOD-108). Проверка кода ответа
такую страницу пропускает, и ровно поэтому каждая ссылка здесь оценивается по
содержимому:

* `пусто` — код 200, но ни карточек, ни `h1`, ни заметного текста. Это находка:
  страница обещает раздел и не несёт ничего;
* `не 200` — отдельная находка с кодом;
* `ок` — отвечает и несёт хотя бы одно из: карточки, `h1`, текст сверх порога.

Ссылки берутся только внутренние и только разных ВИДОВ: по одному образцу на
первый сегмент пути, чтобы не проверять восемь тысяч карточек. Виды печатаются,
а не угадываются.

    python3 automation/local/navigation-audit.py zonafilm.space
    python3 automation/local/navigation-audit.py yummyani.site --json
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys

ТАЙМАУТ = 45
#: Ниже этого числа видимых символов страница считается бессодержательной.
ПОРОГ_ТЕКСТА = 400


def достать(url: str) -> tuple[int, str]:
    """(код, тело). Двоичный ответ не роняет проход, а читается с заменой.

    Измерено 20.10: ссылка на файл без узнаваемого расширения отдала PNG, и
    `text=True` уронил весь проход на `UnicodeDecodeError` в первом же домене.
    Падение инструмента хуже находки: оно оставляет без ответа остальные
    десять витрин. Двоичный ответ просто не несёт ни карточек, ни `h1`, и
    оценивается как любая другая страница.
    """
    г = subprocess.run(
        ["curl", "-sSL", "--max-time", str(ТАЙМАУТ), "-w", "\n%{http_code}",
         url], capture_output=True)
    вывод = (г.stdout or b"").decode("utf-8", errors="replace")
    строки = вывод.rsplit("\n", 1)
    if len(строки) != 2 or not строки[1].strip().isdigit():
        return 0, ""
    return int(строки[1].strip()), строки[0]


def видимый(тело: str) -> str:
    без = re.sub(r"(?is)<(script|style)\b.*?</\1\s*>", " ", тело)
    без = re.sub(r"(?s)<!--.*?-->", " ", без)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", без)).strip()


def виды_ссылок(тело: str, домен: str) -> dict[str, str]:
    """{вид: один образец пути}. Вид — первый сегмент пути, «/» для главной."""
    пути = re.findall(r'href="(/[^"#?]*)"', тело)
    пути += re.findall(rf'href="https://{re.escape(домен)}(/[^"#?]*)"', тело)
    виды: dict[str, str] = {}
    for путь in пути:
        сегменты = [с for с in путь.split("/") if с]
        вид = f"/{сегменты[0]}/" if сегменты else "/"
        # Статический файл — не страница навигации. Измерено 20.10 на
        # zonafilm.space: `/favicon.svg` давал находку «ПУСТО», и она была
        # ложной — иконка и не должна нести ни карточек, ни h1. Исключается по
        # РАСШИРЕНИЮ файла, а не по имени: перечень имён разошёлся бы с сайтом.
        if re.search(r"\.(svg|png|jpe?g|webp|ico|css|js|json|xml|txt|woff2?)$",
                     сегменты[-1] if сегменты else "", re.I):
            continue
        виды.setdefault(вид, путь)
    return виды


def оценить(код: int, тело: str) -> tuple[str, str]:
    """(исход, чем измерено). Код 200 содержанием не считается."""
    if код == 0:
        return "НЕ ОТВЕТИЛА", "соединение не состоялось"
    if код != 200:
        return "НЕ 200", f"код {код}"
    карточек = len(set(re.findall(r'href="(/(?:title|anime)/[^"?#]+)"', тело)))
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело, re.S)
    текста = len(видимый(тело))
    чем = (f"карточек {карточек}, h1 {'есть' if h1 else 'нет'},"
           f" видимого текста {текста}")
    if карточек or h1 or текста >= ПОРОГ_ТЕКСТА:
        return "ок", чем
    return "ПУСТО", чем


def проверить(домен: str, *, загрузчик=None) -> dict:
    загрузить = загрузчик or достать
    код, главная = загрузить(f"https://{домен}/")
    if код != 200 or not главная:
        return {"домен": домен, "ok": False,
                "почему": f"главная ответила {код}", "строки": []}
    строки = []
    for вид, путь in sorted(виды_ссылок(главная, домен).items()):
        к, тело = загрузить(f"https://{домен}{путь}")
        исход, чем = оценить(к, тело)
        строки.append({"вид": вид, "путь": путь, "код": к,
                       "исход": исход, "чем": чем})
    return {"домен": домен, "ok": True, "строки": строки}


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("домены", nargs="+")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    итоги = [проверить(д) for д in а.домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
        return 1 if any(с["исход"] != "ок" for и in итоги if и["ok"]
                        for с in и["строки"]) else 0

    находок = 0
    for и in итоги:
        print(f"\n=== {и['домен']}")
        if not и["ok"]:
            print(f"   НЕ ИЗМЕРЕНО: {и['почему']}")
            continue
        for с in и["строки"]:
            метка = "" if с["исход"] == "ок" else "  ← "
            print(f"   {с['вид']:<18} {с['исход']:<12} {с['чем']}{метка}"
                  f"{с['путь'] if с['исход'] != 'ок' else ''}")
            находок += 0 if с["исход"] == "ок" else 1
    print(f"\n{'=' * 60}\nнаходок: {находок}")
    print("вид страницы берётся из ссылок САМОЙ витрины, по одному образцу на"
          " первый сегмент пути;")
    print("код 200 содержанием не считается: страница без карточек, h1 и"
          " текста — это «ПУСТО», а не «ок».")
    return 1 if находок else 0


if __name__ == "__main__":
    sys.exit(главное())
