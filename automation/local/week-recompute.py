#!/usr/bin/env python3
"""Пересчёт недельных чисел по правилам сопоставимости. Только чтение.

    python3 automation/local/week-recompute.py [--json <файл>]

Зачем. Отчёт недели 11–17.10 сравнивал СУММЫ за периоды с разным числом дней,
считал дни «5000+» по чужому периоду и сводил вклад одного произведения по
трём страницам из шести. Каждая из этих ошибок делает вывод неверным в свою
сторону, поэтому числа пересчитываются здесь по единым правилам:

1. СРЕДНЕЕ В СУТКИ, а не сумма. Делитель — число дней, за которые API вернул
   строки; делитель печатается всегда. Сумма за 6 дней против суммы за 7 —
   не сравнение, а разница длины окна;
2. ОДИНАКОВОЕ ОКНО. Дополнительно считается сравнение по последним N дням,
   общим для обоих периодов (N = минимум из двух делителей);
3. ПРОПУСК — НЕ НОЛЬ. День без строк не входит ни в сумму, ни в делитель, и
   называется в выводе;
4. ФИЛЬТРЫ НАЗЫВАЮТСЯ. Визиты — без роботов и без HeadlessChrome; разрез
   поиска по роботам в API отсутствует, поэтому поисковые числа отфильтрованы
   ИНАЧЕ, и сравнивать их с визитами как однородные нельзя;
5. ДНИ 5000+ — по каждому периоду отдельно. В отчёте 11–17.10 этот столбец
   нёс день 09.10, то есть день БАЗОВОГО периода.

Источники: `var/seo-audit/week-20261011-17-vs-04-10.json` (посуточные значения,
собран из штатной выгрузки Метрики) и две выгрузки кабинета для разреза по
страницам входа.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import statistics
import sys

КОРЕНЬ_ДАННЫХ = pathlib.Path("/home/claude/wt-portable-site-cell-01")
НЕДЕЛЯ = КОРЕНЬ_ДАННЫХ / "var/seo-audit/week-20261011-17-vs-04-10.json"
БАЗА_КАБИНЕТ = КОРЕНЬ_ДАННЫХ / "artifacts/analytics/analytics-2026-10-11.json"
ТЕКУЩИЙ_КАБИНЕТ = КОРЕНЬ_ДАННЫХ / "var/analytics/cabinet-latest.json"

ПОРОГ_ЦЕЛИ = 5000


def загрузить(путь: pathlib.Path):
    try:
        return json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        print(f"не прочитан {путь}: {сбой}", file=sys.stderr)
        return None


def дни(словарь: dict, период: tuple[str, str]) -> dict:
    """Только дни периода, у которых есть значение."""
    с, по = период
    return {д: v for д, v in sorted((словарь or {}).items())
            if с <= д <= по and v is not None}


def свод_домена(запись: dict, базовый: tuple, текущий: tuple) -> dict:
    визиты = запись.get("daily_human_visits") or {}
    органика = запись.get("daily_organic_visits_human") or {}
    б, т = дни(визиты, базовый), дни(визиты, текущий)
    бо, то = дни(органика, базовый), дни(органика, текущий)

    # Одинаковое окно: последние N дней каждого периода, где N — минимум.
    n = min(len(б), len(т)) if б and т else 0
    б_окно = dict(list(б.items())[-n:]) if n else {}
    т_окно = dict(list(т.items())[-n:]) if n else {}

    def среднее(d):
        return round(statistics.fmean(d.values()), 1) if d else None

    return {
        "дней_с_данными": {"база": len(б), "текущий": len(т)},
        "пропущено": {"база": sorted(set(_перечень(базовый)) - set(б)),
                      "текущий": sorted(set(_перечень(текущий)) - set(т))},
        "в_сутки": {"база": среднее(б), "текущий": среднее(т)},
        "в_сутки_органика": {"база": среднее(бо), "текущий": среднее(то)},
        "одинаковое_окно": {
            "дней": n,
            "база": среднее(б_окно), "текущий": среднее(т_окно),
            "изменение": (round(среднее(т_окно) - среднее(б_окно), 1)
                          if n else None)},
        "дней_5000плюс": {
            "база": sum(1 for v in б.values() if v >= ПОРОГ_ЦЕЛИ),
            "текущий": sum(1 for v in т.values() if v >= ПОРОГ_ЦЕЛИ)},
        "сумма_визитов": {"база": round(sum(б.values())),
                          "текущий": round(sum(т.values()))},
    }


def _перечень(период: tuple[str, str]) -> list[str]:
    import datetime as dt
    с = dt.date.fromisoformat(период[0])
    по = dt.date.fromisoformat(период[1])
    out = []
    while с <= по:
        out.append(с.isoformat())
        с += dt.timedelta(days=1)
    return out


def страницы_входа(выгрузка, домен: str) -> list[tuple[float, str]]:
    for дом in (выгрузка or {}).get("domains") or []:
        if дом.get("domain") != домен:
            continue
        for м in дом.get("measurements") or []:
            if м.get("key") != "search_landing_pages" or not м.get("measured"):
                continue
            итог = []
            for r in м.get("value") or []:
                адрес = [x.get("name") for x in r.get("dimensions") or []
                         if str(x.get("name", "")).startswith("/")]
                итог.append((float(r["metrics"][0]),
                             адрес[0] if адрес else "—"))
            return итог
    return []


def вклад(база: list, текущий: list, образец: str) -> dict:
    """Вклад группы страниц (по подстроке адреса) в изменение поиска.

    Группа задаётся ПОДСТРОКОЙ адреса, а состав печатается: отчёт 11–17.10
    свёл произведение по трём страницам, тогда как в выгрузке их шесть в
    каждом периоде, и числа «было 11 114, стало 4 920» не сходятся ни с одной
    из выгрузок.
    """
    def разбор(s):
        всего = sum(v for v, _ in s)
        группа = [(v, p) for v, p in s if образец in p]
        return всего, sum(v for v, _ in группа), len(группа)

    вб, гб, nб = разбор(база)
    вт, гт, nт = разбор(текущий)
    дельта = вт - вб
    return {
        "страниц_в_группе": {"база": nб, "текущий": nт},
        "визиты_группы": {"база": round(гб), "текущий": round(гт)},
        "визиты_всего": {"база": round(вб), "текущий": round(вт)},
        "изменение_группы": round(гт - гб),
        "изменение_остального": round((вт - гт) - (вб - гб)),
        "доля_группы_в_изменении": (round(100 * (гт - гб) / дельта, 1)
                                    if дельта else None),
        "страниц_входа_всего": {"база": len(база), "текущий": len(текущий)},
    }


def главная(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", default="")
    а = р.parse_args(аргв)

    неделя = загрузить(НЕДЕЛЯ)
    if not неделя:
        return 2
    периоды = неделя["periods"]
    базовый = tuple(периоды["base"].split(".."))
    текущий = tuple(периоды["current"].split(".."))

    итог = {"источник": str(НЕДЕЛЯ), "периоды": периоды,
            "правила": ["среднее в сутки с названным делителем",
                        "одинаковое окно по минимуму делителей",
                        "пропуск не считается нулём",
                        "фильтры визитов и поиска названы раздельно",
                        "дни 5000+ по каждому периоду отдельно"],
            "домены": {}}

    print(f"{'домен':24} {'дней б/т':9} {'в сутки: база → текущий':26} "
          f"{'одинаковое окно':22} {'5000+ б/т':10}")
    for домен, запись in sorted(неделя["domains"].items()):
        с = свод_домена(запись, базовый, текущий)
        итог["домены"][домен] = с
        дб, дт = с["дней_с_данными"]["база"], с["дней_с_данными"]["текущий"]
        вб, вт = с["в_сутки"]["база"], с["в_сутки"]["текущий"]
        ок = с["одинаковое_окно"]
        строка_ок = (f"{ок['база']} → {ок['текущий']} ({ок['дней']} дн)"
                     if ок["дней"] else "нет общего окна")
        print(f"{домен:24} {дб}/{дт:<7} "
              f"{str(вб) + ' → ' + str(вт):26} {строка_ок:22} "
              f"{с['дней_5000плюс']['база']}/{с['дней_5000плюс']['текущий']}")

    # Разрез по страницам входа для yummyani.site: вклад ДжоДжо.
    база_каб = загрузить(БАЗА_КАБИНЕТ)
    тек_каб = загрузить(ТЕКУЩИЙ_КАБИНЕТ)
    if база_каб and тек_каб:
        в = вклад(страницы_входа(база_каб, "yummyani.site"),
                  страницы_входа(тек_каб, "yummyani.site"),
                  "dzhodzho-gonka-stalnoy-shar")
        итог["вклад_джоджо_yummyani_site"] = в
        print()
        print("yummyani.site, вклад «ДжоДжо: Гонка «Стальной шар»» в изменение "
              "поисковых визитов:")
        print(f"  страниц группы: база {в['страниц_в_группе']['база']}, "
              f"текущий {в['страниц_в_группе']['текущий']}")
        print(f"  визиты группы:  {в['визиты_группы']['база']} → "
              f"{в['визиты_группы']['текущий']} "
              f"({в['изменение_группы']:+})")
        print(f"  остальные страницы: {в['изменение_остального']:+}")
        print(f"  доля группы в изменении: "
              f"{в['доля_группы_в_изменении']} %")
        print(f"  страниц входа всего: "
              f"{в['страниц_входа_всего']['база']} → "
              f"{в['страниц_входа_всего']['текущий']}")

    всего_5000 = {
        "база": sum(d["дней_5000плюс"]["база"] for d in итог["домены"].values()),
        "текущий": sum(d["дней_5000плюс"]["текущий"]
                       for d in итог["домены"].values())}
    итог["дней_5000плюс_по_сети"] = всего_5000
    print()
    print(f"дней «5000+ визитов» по всей сети: база {всего_5000['база']}, "
          f"текущий {всего_5000['текущий']} — цель 5000 в сутки на КАЖДОМ "
          f"сайте не достигнута ни одним доменом ни в одном периоде")

    неравные = [д for д, с in итог["домены"].items()
                if с["дней_с_данными"]["база"] != с["дней_с_данными"]["текущий"]]
    итог["домены_с_неравными_периодами"] = неравные
    print(f"домены, где делители периодов РАЗНЫЕ: {len(неравные)}"
          + (f" — {', '.join(неравные)}" if неравные else ""))

    if а.json:
        pathlib.Path(а.json).write_text(
            json.dumps(итог, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
        print(f"\nразбор записан: {а.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная())
