#!/usr/bin/env python3
"""Виден ли комментарий «Редакции» ПОСЕТИТЕЛЮ. Браузер, а не код ответа.

    python3 automation/local/comment-visible-check.py <домен> <слаг> ["<фрагмент>"]

Зачем отдельный инструмент. Блок комментариев у витрин Yummy рисуется на
стороне клиента: страница приходит с заглушкой «Загрузка комментариев…», а
список приходит отдельным запросом. Поэтому ни `curl`, ни поиск по HTML ответа
ничего не докажут — измерено 2026-10-09: текст был в базе и отдавался API, а в
HTML его не было вовсе.

Второе измерение того же дня: тред запрашивается НЕ публичным слагом, а
идентификатором тайтла в приложении. Комментарий, записанный с публичным
слагом, читался запросом по тому же слагу и при этом не показывался ни на одной
странице. Отсюда правило: подтверждением считается только то, что увидел
браузер на АДРЕСЕ ПРОИЗВЕДЕНИЯ.

Что проверяется и что печатается:

* блок комментариев найден на странице (`section.comment-thread`);
* в нём есть подпись «Редакция»;
* в нём есть переданный фрагмент текста (если фрагмент не передан — печатается
  начало каждого комментария, чтобы вызывающий сверил сам);
* сколько всего комментариев видит посетитель.

Выход: 0 — фрагмент виден (или, без фрагмента, блок с комментариями найден);
1 — блок есть, но фрагмента в нём нет; 2 — блока нет или страница не открылась.
Код выхода — для часового запуска редактора: он решает по нему, считать
публикацию подтверждённой или нет, и не обязан разбирать текст вывода.

Инструмент ТОЛЬКО ЧИТАЕТ: ничего не публикует и не меняет.
"""

from __future__ import annotations

import glob
import sys

ХРОМ_ШАБЛОН = "/home/claude/.cache/ms-playwright/chromium*/chrome-linux*/chrome"
ОЖИДАНИЕ_МС = 4000


def главное(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    домен, слаг = argv[0].strip(), argv[1].strip()
    фрагмент = argv[2].strip() if len(argv) > 2 else ""

    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("playwright не установлен: проверка видимости невозможна",
              file=sys.stderr)
        return 2
    кандидаты = sorted(glob.glob(ХРОМ_ШАБЛОН))
    if not кандидаты:
        print("Chromium playwright не найден", file=sys.stderr)
        return 2

    # Форма адреса у Yummy — /anime/<слаг> БЕЗ косой черты в конце; у витрин с
    # нашим рантаймом — /title/<слаг>/. Угадывать нельзя: 308 и 404 выглядят
    # по-разному, но оба означают «проверено не то».
    адреса = ([f"https://{домен}/anime/{слаг}"] if "yummyani" in домен
              else [f"https://{домен}/title/{слаг}/"])

    with sync_playwright() as p:
        браузер = p.chromium.launch(executable_path=кандидаты[0],
                                    args=["--no-sandbox"])
        try:
            страница = браузер.new_page()
            for адрес in адреса:
                страница.goto(адрес, wait_until="networkidle", timeout=90000)
                страница.wait_for_timeout(ОЖИДАНИЕ_МС)
                блок = страница.query_selector("section.comment-thread")
                if блок is None:
                    print(f"{адрес}: блока комментариев на странице нет")
                    return 2
                текст = блок.inner_text()
                строки = [с.strip() for с in текст.splitlines() if с.strip()]
                заголовок = строки[0] if строки else ""
                подпись = "Редакция" in текст
                print(f"{адрес}")
                print(f"  блок: {заголовок}")
                print(f"  подпись «Редакция»: {'да' if подпись else 'НЕТ'}")
                if фрагмент:
                    виден = фрагмент in текст
                    print(f"  фрагмент виден: {'да' if виден else 'НЕТ'}")
                    return 0 if виден else 1
                # Без фрагмента печатаем начала, чтобы вызывающий сверил сам.
                for с in строки[1:8]:
                    print(f"    {с[:110]}")
                return 0 if подпись else 1
        finally:
            браузер.close()
    return 2


if __name__ == "__main__":
    raise SystemExit(главное(sys.argv[1:]))
