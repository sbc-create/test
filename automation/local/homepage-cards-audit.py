#!/usr/bin/env python3
"""Ревизия первых карточек главной: почему показаны и чем подтверждены.

Только чтение: живые страницы и данные ячеек (`docs/RUNTIME_DATA_OWNERSHIP.md`).

Что проверяется по каждой карточке первых N (по умолчанию 24) в порядке
документа:

* **блок** — заголовок полки, под которой карточка стоит. «Почему показана» —
  это и есть ответ блока, других оснований у страницы нет;
* **три разные даты**, которые нельзя путать: `год` произведения из каталога,
  `в каталоге с` (`published_at`, помеченный `published_at_estimated`, если он
  оценочный) и `серии` — число доступных против объявленных. Даты ВЫХОДА новой
  серии в данных ячейки нет вовсе: `seasons` несут только `avail` и `eps`,
  поэтому утверждать «новая серия вышла тогда-то» по этим данным нельзя, и
  инструмент этого не делает;
* **постер** — есть ли изображение и не заглушка ли оно;
* **доступное видео** — сумма `avail` по сезонам больше нуля. Карточка без
  доступных серий на полке, обещающей просмотр, — это обещание, которого
  страница не выполняет;
* **повтор** — одна карточка в нескольких блоках;
* **обещание блока**: полка с заголовком про популярность обязана нести
  признаки происхождения (`data-popular-mode`, `data-popular-week`), иначе её
  заголовок — утверждение без данных.

Коды: 0 — расхождений нет, 1 — есть, 2 — не измерено ничего.
"""
from __future__ import annotations

import argparse
import datetime as dt
import html
import json
import pathlib
import re
import subprocess
import sys

РЕЕСТР = pathlib.Path(__file__).resolve().parents[2] / "config/site-cells.json"
КАРТОЧЕК = 24
СТАРЫМ_СЧИТАЕМ_ДО = 10  # лет: порог печати, не приговор


def домены_реестра() -> list[tuple[str, pathlib.Path]]:
    """Живые ячейки и каталог их данных: (домен, каталог данных)."""
    try:
        ячейки = json.loads(РЕЕСТР.read_text(encoding="utf-8")).get("cells") or []
    except (OSError, ValueError):
        return []
    итог = []
    for я in ячейки:
        домен = str(я.get("domain") or "")
        if not домен or я.get("status") != "live":
            continue
        if домен.endswith((".test", ".localhost")):
            continue
        итог.append((домен, каталог_данных(домен)))
    return итог


def каталог_данных(домен: str) -> pathlib.Path | None:
    """Каталог данных ячейки по домену.

    Поле `data` реестра несёт не путь, а описание хранилищ
    (`{"database": null, "media": null}`), поэтому путь строится по правилу
    площадки: `/srv/<домен с дефисами вместо точек>/data`. Отсутствие каталога
    означает «данных ячейки нет» — это «не измерено» для трёх дат, а не ноль.
    """
    п = pathlib.Path("/srv") / домен.replace(".", "-") / "data"
    return п if п.is_dir() else None


def добыть(адрес: str, таймаут: int = 40) -> str:
    г = subprocess.run(["curl", "-sSL", "--max-time", str(таймаут), адрес],
                       capture_output=True, text=True)
    return г.stdout if г.returncode == 0 else ""


def _чисто(т: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", " ", т)).strip()


def блоки(тело: str) -> list[dict]:
    """Полки страницы: заголовок, его атрибуты и карточки под ним по порядку."""
    точки = [(м.start(), м.group(0), _чисто(м.group(1)))
             for м in re.finditer(r"<h2[^>]*>(.*?)</h2>", тело, re.S)]
    карточки = [(м.start(), м.group(1))
                for м in re.finditer(r'href="(/(?:title|anime)/[^"#?]+)"', тело)]
    итог = []
    for и, (поз, тег, имя) in enumerate(точки):
        конец = точки[и + 1][0] if и + 1 < len(точки) else len(тело)
        свои = [п for поз2, п in карточки if поз < поз2 < конец]
        # атрибуты полки ищутся в куске до первой карточки: там живёт её корень
        кусок = тело[max(0, поз - 400):поз + 400]
        итог.append({
            "заголовок": имя,
            "карточек": len(свои),
            "пути": свои,
            "признаки_популярности": sorted(set(
                re.findall(r'data-popular-[a-z]+', кусок))),
        })
    return итог


def обещает_популярность(заголовок: str) -> bool:
    """Заголовок, утверждающий востребованность, а не состав каталога."""
    низ = заголовок.lower()
    return any(с in низ for с in ("популярн", "востребован", "смотрят",
                                  "в тренде", "хиты"))


def карточки_по_порядку(тело: str, сколько: int = КАРТОЧЕК) -> list[dict]:
    """Первые карточки в порядке документа с их блоком и постером."""
    полки = блоки(тело)
    принадлежность: dict[str, str] = {}
    for п in полки:
        for путь in п["пути"]:
            принадлежность.setdefault(путь, п["заголовок"])
    повторы: dict[str, int] = {}
    for п in полки:
        for путь in set(п["пути"]):
            повторы[путь] = повторы.get(путь, 0) + 1

    итог: list[dict] = []
    видели: set[str] = set()
    for м in re.finditer(r'href="(/(?:title|anime)/[^"#?]+)"', тело):
        путь = м.group(1)
        if путь in видели:
            continue
        видели.add(путь)
        кусок = тело[м.start():м.start() + 900]
        изо = re.search(r'<img[^>]+src="([^"]+)"', кусок)
        заглушка = bool(re.search(r'class="[^"]*__ph|placeholder', кусок))
        слаг = путь.strip("/").split("/")[-1]
        итог.append({
            "путь": путь, "слаг": слаг,
            "блок": принадлежность.get(путь, "(вне полок)"),
            "в_блоках": повторы.get(путь, 0),
            "постер": изо.group(1) if изо else "",
            "заглушка_постера": заглушка and not изо,
        })
        if len(итог) >= сколько:
            break
    return итог


def данные_ячейки(каталог: pathlib.Path | None) -> tuple[dict, dict]:
    """Каталог и подробности ячейки по слагу. Отсутствие — пустые словари."""
    if not каталог or not каталог.is_dir():
        return {}, {}
    кат: dict[str, dict] = {}
    дет: dict[str, dict] = {}
    for ф in sorted(каталог.glob("*catalog*.json")):
        try:
            записи = json.loads(ф.read_text(encoding="utf-8")).get("items") or []
        except (OSError, ValueError):
            continue
        for з in записи:
            if з.get("slug"):
                кат.setdefault(str(з["slug"]), з)
        break
    # Скрытые и служебные файлы пропускаются, и выход — только на НЕПУСТОМ
    # разборе: первый замер 19.10 обрывался на `.zona-02-details-avail-ring.json`
    # (служебное кольцо доступности без ключа `details`), подробности выходили
    # пустыми, и все карточки печатались как «0/0 серий» — ложный дефект на
    # исправной полке.
    for ф in sorted(каталог.glob("*details*.json")):
        if ф.name.startswith(".") or ".nums." in ф.name:
            continue
        try:
            д = json.loads(ф.read_text(encoding="utf-8")).get("details") or {}
        except (OSError, ValueError):
            continue
        if д:
            дет = {str(к): v for к, v in д.items()}
            break
    return кат, дет


def сведения(карточка: dict, кат: dict, дет: dict, сегодня: dt.date) -> dict:
    """Три даты и доступность по данным ячейки."""
    запись = кат.get(карточка["слаг"]) or {}
    деталь = дет.get(карточка["слаг"]) or {}
    if not деталь and запись.get("title"):
        имя = str(запись["title"]).strip().casefold()
        деталь = next((v for v in дет.values()
                       if str(v.get("name") or "").strip().casefold() == имя), {})
    # Доступность считается ПО ВИДУ записи. У фильма `seasons` равен null, и
    # сумма `avail` по нему даёт ноль — первый замер 19.10 из-за этого объявил
    # «24 карточки без доступных серий» на полке фильмов, где всё исправно.
    # Для фильма доступность — это playable и статус источника, для сериала —
    # число доступных серий.
    сезоны = деталь.get("seasons") or []
    источники = деталь.get("sources") or []
    доступные_источники = sum(
        1 for и in источники
        if str((и or {}).get("availability_status") or "") == "available")
    если_сериал = str(деталь.get("type") or "") == "tv" or bool(сезоны)
    if если_сериал:
        доступно = sum(int((с or {}).get("avail") or 0) for с in сезоны)
        объявлено = sum(int((с or {}).get("eps") or 0) for с in сезоны)
    else:
        доступно = 1 if (деталь.get("playable") and доступные_источники) else 0
        объявлено = 1 if деталь else 0
    год = str(запись.get("year") or "")
    появилась = str(запись.get("published_at") or "")[:10]
    возраст = None
    if год.isdigit():
        возраст = сегодня.year - int(год)
    свежая_запись = None
    if появилась:
        try:
            свежая_запись = (сегодня - dt.date.fromisoformat(появилась)).days
        except ValueError:
            свежая_запись = None
    return {
        "в_каталоге": bool(запись),
        "год": год or "—",
        "возраст_лет": возраст,
        "в_каталоге_с": появилась or "—",
        "оценочная_дата": bool(запись.get("published_at_estimated")),
        "дней_в_каталоге": свежая_запись,
        "серий_доступно": доступно,
        "серий_объявлено": объявлено,
        "вид": str(деталь.get("type") or запись.get("kind") or "—"),
        "это_сериал": если_сериал,
        "доступных_источников": доступные_источники,
    }


def проверить(домен: str, каталог: pathlib.Path | None, сколько: int,
              сегодня: dt.date | None = None) -> dict:
    сегодня = сегодня or dt.date.today()
    тело = добыть(f"https://{домен}/")
    if not тело:
        return {"измерено": False, "почему": "главная не получена"}
    полки = блоки(тело)
    карточки = карточки_по_порядку(тело, сколько)
    if not карточки:
        return {"измерено": False, "почему": "карточек на главной не найдено"}
    кат, дет = данные_ячейки(каталог)
    строки = []
    for к in карточки:
        с = сведения(к, кат, дет, сегодня)
        строки.append({**к, **с})
    # Возраст по полкам: жалоба «на главной много старых тайтлов» становится
    # проверяемой только так. Год произведения, дата появления в каталоге и
    # доступность считаются РАЗДЕЛЬНО: запись 1932 года, добавленная вчера, —
    # не новинка, и обновление файла каталога новинкой её не делает.
    по_полкам: dict[str, dict] = {}
    for с in строки:
        полка = по_полкам.setdefault(с["блок"], {"карточек": 0, "годы": [],
                                                 "свежих_в_каталоге": 0,
                                                 "без_видео": 0})
        полка["карточек"] += 1
        if с["возраст_лет"] is not None:
            полка["годы"].append(int(с["год"]))
        if (с["дней_в_каталоге"] if с["дней_в_каталоге"] is not None else 999) <= 7:
            полка["свежих_в_каталоге"] += 1
        if с["в_каталоге"] and с["серий_доступно"] == 0:
            полка["без_видео"] += 1
    for имя, п in по_полкам.items():
        годы = sorted(п["годы"])
        п["медиана_года"] = годы[len(годы) // 2] if годы else None
        п["старше_порога"] = sum(1 for г in годы
                                 if сегодня.year - г > СТАРЫМ_СЧИТАЕМ_ДО)
        п["самый_старый"] = годы[0] if годы else None
        п["самый_новый"] = годы[-1] if годы else None

    замечания = []
    без_видео = [с for с in строки if с["в_каталоге"] and с["серий_доступно"] == 0]
    без_постера = [с for с in строки if not с["постер"]]
    повторы = [с for с in строки if с["в_блоках"] > 1]
    вне_каталога = [с for с in строки if not с["в_каталоге"]]
    пустые_полки = [п for п in полки if п["карточек"] == 0
                    and "подборк" not in п["заголовок"].lower()
                    and "жанр" not in п["заголовок"].lower()
                    and "раздел" not in п["заголовок"].lower()]
    голословная_популярность = [п for п in полки
                                if обещает_популярность(п["заголовок"])
                                and not п["признаки_популярности"]]
    if без_видео:
        замечания.append(f"карточек без доступных серий: {len(без_видео)}")
    if без_постера:
        замечания.append(f"карточек без изображения: {len(без_постера)}")
    if повторы:
        замечания.append(f"карточек в нескольких блоках: {len(повторы)}")
    if вне_каталога:
        замечания.append(f"карточек вне каталога ячейки: {len(вне_каталога)}")
    if голословная_популярность:
        замечания.append("полка обещает популярность без признаков происхождения: "
                         + ", ".join(п["заголовок"] for п in голословная_популярность))
    return {"измерено": True, "полки": полки, "карточки": строки,
            "по_полкам": по_полкам,
            "замечания": замечания, "пустые_полки": пустые_полки}


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="ревизия первых карточек главной")
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--cards", type=int, default=КАРТОЧЕК)
    р.add_argument("--json", action="store_true")
    р.add_argument("--full", action="store_true", help="печатать каждую карточку")
    дов = р.parse_args(аргв)

    пары = домены_реестра()
    if дов.domain:
        известные = dict(пары)
        пары = [(д, известные.get(д)) for д in дов.domain]

    итоги: dict[str, dict] = {}
    for домен, каталог in пары:
        итоги[домен] = проверить(домен, каталог, дов.cards)

    if дов.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=2, default=str))
    else:
        for домен, и in итоги.items():
            if not и.get("измерено"):
                print(f"\n=== {домен}: НЕ ИЗМЕРЕНО — {и.get('почему')}")
                continue
            полки = и["полки"]
            print(f"\n=== {домен}: полок {len(полки)},"
                  f" карточек разобрано {len(и['карточки'])}")
            for п in полки:
                признаки = (" ".join(п["признаки_популярности"])
                            if п["признаки_популярности"] else "—")
                print(f"   полка «{п['заголовок'][:44]:46}» карточек {п['карточек']:3}"
                      f"  признаки: {признаки}")
            if и.get("по_полкам"):
                print(f"   {'полка (первые карточки)':30} {'карт':>4} {'медиана':>8}"
                      f" {'старейший':>10} {'новейший':>9}"
                      f" {'старше ' + str(СТАРЫМ_СЧИТАЕМ_ДО):>11}"
                      f" {'свежих в кат.':>14} {'без видео':>10}")
                for имя, п in и["по_полкам"].items():
                    print(f"   {имя[:30]:30} {п['карточек']:4}"
                          f" {str(п['медиана_года'] or '—'):>8}"
                          f" {str(п['самый_старый'] or '—'):>10}"
                          f" {str(п['самый_новый'] or '—'):>9}"
                          f" {п['старше_порога']:11} {п['свежих_в_каталоге']:14}"
                          f" {п['без_видео']:10}")
            if дов.full:
                print(f"   {'слаг':34} {'блок':26} {'год':>5} {'в каталоге с':>13}"
                      f" {'дней':>5} {'серии':>9} {'блоков':>6}")
                for с in и["карточки"]:
                    серии = f"{с['серий_доступно']}/{с['серий_объявлено']}"
                    дней = с["дней_в_каталоге"]
                    print(f"   {с['слаг'][:34]:34} {с['блок'][:26]:26}"
                          f" {с['год']:>5} {с['в_каталоге_с']:>13}"
                          f" {('—' if дней is None else дней):>5} {серии:>9}"
                          f" {с['в_блоках']:>6}")
            for з in и["замечания"]:
                print(f"   ЗАМЕЧАНИЕ: {з}")
            if и["пустые_полки"]:
                print("   ЗАМЕЧАНИЕ: пустые полки: "
                      + ", ".join(п["заголовок"] for п in и["пустые_полки"]))

    измерено = [и for и in итоги.values() if и.get("измерено")]
    if not измерено:
        return 2
    есть_замечания = any(и["замечания"] or и["пустые_полки"] for и in измерено)
    print(f"\nвитрин измерено {len(измерено)} из {len(итоги)};"
          f" с замечаниями {sum(1 for и in измерено if и['замечания'] or и['пустые_полки'])}")
    return 1 if есть_замечания else 0


if __name__ == "__main__":
    sys.exit(main())
