import datetime as dt
import html
import json
import pathlib
import re
import subprocess
import sys

РЕЕСТР = pathlib.Path(__file__).resolve().parents[2] / "config/site-cells.json"
КАРТОЧЕК = 24
СТАРЫМ_СЧИТАЕМ_ДО = 10  # лет: порог печати, не приговор


def домены_реестра() -> list[tuple[str, pathlib.Path]]:
    """Живые ячейки и каталог их данных: (домен, каталог данных)."""
    try:
        ячейки = json.loads(РЕЕСТР.read_text(encoding="utf-8")).get("cells") or []
    except (OSError, ValueError):
        return []
    итог = []
    for я in ячейки:
        домен = str(я.get("domain") or "")
        if not домен or я.get("status") != "live":
            continue
        if домен.endswith((".test", ".localhost")):
            continue
        итог.append((домен, каталог_данных(домен)))
    return итог


def каталог_данных(домен: str) -> pathlib.Path | None:
    """Каталог данных ячейки по домену.

    Поле `data` реестра несёт не путь, а описание хранилищ
    (`{"database": null, "media": null}`), поэтому путь строится по правилу
    площадки: `/srv/<домен с дефисами вместо точек>/data`. Отсутствие каталога
    означает «данных ячейки нет» — это «не измерено» для трёх дат, а не ноль.
    """
    п = pathlib.Path("/srv") / домен.replace(".", "-") / "data"
    return п if п.is_dir() else None


def добыть(адрес: str, таймаут: int = 40) -> str:
    г = subprocess.run(["curl", "-sSL", "--max-time", str(таймаут), адрес],
                       capture_output=True, text=True)
    return г.stdout if г.returncode == 0 else ""


def _чисто(т: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", " ", т)).strip()


def основное(тело: str) -> str:
    """Кусок страницы без подвала и шапки.

    Заголовки подвала («Наши ресурсы», «Информация о сайте», «Техническая
    поддержка») — это h2, и первый живой замер 19.10 объявил их пустыми
    полками. Полка — это область карточек, поэтому подвал и шапка из подсчёта
    исключаются, а если разметка их не выделяет, берётся вся страница.
    """
    def без_служебного(кусок: str) -> str:
        б = re.sub(r"<footer[^>]*>.*?</footer>", " ", кусок, flags=re.S)
        return re.sub(r"<header[^>]*>.*?</header>", " ", б, flags=re.S)

    м = re.search(r"<main[^>]*>(.*?)</main>", тело, re.S)
    целиком = без_служебного(тело)
    if not м:
        return целиком
    внутри = без_служебного(м.group(1))
    # Откат обязателен: у витрин Yummy карточки лежат ВНЕ <main>, и сужение до
    # него дало «карточек на главной не найдено» на странице с 90 ссылками.
    если_есть = re.search(r'href="/(?:title|anime)/', внутри)
    return внутри if если_есть else целиком


def блоки(тело: str) -> list[dict]:
    """Полки страницы: заголовок, его атрибуты и карточки под ним по порядку."""
    тело = основное(тело)
    # Полку может возглавлять и h1: у zonafilm.space лента «Сейчас на Zona»
    # подписана именно им, и поиск только по h2 относил её шестнадцать
    # карточек к «вне полок» — ложная тревога инструмента, не дефект витрины.
    # Заголовок страницы без карточек отсеется ниже как пустая полка.
    точки = [(м.start(), м.group(0), _чисто(м.group(2)))
             for м in re.finditer(r"<(h1|h2)[^>]*>(.*?)</\1>", тело, re.S)]
    карточки = [(м.start(), м.group(1))
                for м in re.finditer(r'href="(/(?:title|anime)/[^"#?]+)"', тело)]
    итог = []
    for и, (поз, тег, имя) in enumerate(точки):
        конец = точки[и + 1][0] if и + 1 < len(точки) else len(тело)
        свои = [п for поз2, п in карточки if поз < поз2 < конец]
        # атрибуты полки ищутся в куске до первой карточки: там живёт её корень
        кусок = тело[max(0, поз - 400):поз + 400]
        # Проза блока нужна, чтобы отличить ПУСТУЮ ПОЛКУ от ТЕКСТОВОГО
        # РАЗДЕЛА. У zonafilm.space блок «Смотреть кино и сериалы на Zona» —
        # это раздел с текстом (section class="zsec--seo"), карточек он не
        # обещает, а инструмент 20.10 печатал его как пустую полку: ложное
        # замечание про витрину, у которой нечего исправлять.
        внутри_блока = тело[поз:конец]
        проза = sum(len(_чисто(м.group(1)))
                    for м in re.finditer(r"<p[^>]*>(.*?)</p>",
                                         внутри_блока, re.S))
        итог.append({
            "заголовок": имя,
            "карточек": len(свои),
            "пути": свои,
            "прозы_знаков": проза,
            "признаки_популярности": sorted(set(
                re.findall(r'data-popular-[a-z]+', кусок))),
        })
    return итог


#: Сколько знаков прозы делает блок текстовым РАЗДЕЛОМ, а не пустой полкой.
#: Порог назван числом, а не «на глаз»: подпись полки и ссылка «Весь раздел»
#: дают десятки знаков, а раздел с текстом — сотни. Измерено 20.10 на
#: zonafilm.space: у блока «Смотреть кино и сериалы на Zona» прозы 650 знаков,
#: у полок с карточками — 0.
ПРОЗА_РАЗДЕЛА = 200

#: Ячейки, где поле доступности видео проверено зондом показа и признано
#: недостоверным (MOD-97). Для них число печатается наблюдением, а не
#: замечанием: исправлять на странице нечего. Список именной, а не «все»:
#: там, где поле не проверялось, замечание остаётся — отсутствие проверки не
#: повод доверять полю и не повод ему не доверять.
ПОЛЕ_ДОСТУПНОСТИ_НЕДОСТОВЕРНО = frozenset({
    "zonafilm12.site", "zonafilm.space", "zonafilm.cc", "lordserials22.info",
})


def пустые_среди(полки: list[dict], название: str = "") -> list[dict]:
    """Полки, которые обещают карточки и не дают ни одной.

    Полкой не считается то, что полкой и не является: ссылочные разделы
    (подборки, жанры, разделы), заголовок-название страницы, повторяющий h1
    (ложное замечание на animedia.icu), и блок с прозой — текстовый раздел
    (ложное замечание на zonafilm.space).
    """
    низ_названия = (название or "").casefold()
    return [п for п in полки if п["карточек"] == 0
            and "подборк" not in п["заголовок"].lower()
            and "жанр" not in п["заголовок"].lower()
            and "раздел" not in п["заголовок"].lower()
            and п["заголовок"].casefold() != низ_названия
            and п.get("прозы_знаков", 0) < ПРОЗА_РАЗДЕЛА]


def обещает_популярность(заголовок: str) -> bool:
    """Заголовок, утверждающий востребованность, а не состав каталога."""
    низ = заголовок.lower()
    return any(с in низ for с in ("популярн", "востребован", "смотрят",
                                  "в тренде", "хиты"))


def карточки_по_порядку(тело: str, сколько: int = КАРТОЧЕК) -> list[dict]:
    """Первые карточки в порядке документа с их блоком и постером."""
    тело = основное(тело)
    полки = блоки(тело)
    принадлежность: dict[str, str] = {}
    for п in полки:
        for путь in п["пути"]:
            принадлежность.setdefault(путь, п["заголовок"])
    повторы: dict[str, int] = {}
    for п in полки:
        for путь in set(п["пути"]):
            повторы[путь] = повторы.get(путь, 0) + 1

    итог: list[dict] = []
    видели: set[str] = set()
    for м in re.finditer(r'href="(/(?:title|anime)/[^"#?]+)"', тело):
        путь = м.group(1)
        if путь in видели:
            continue
        видели.add(путь)
        кусок = тело[м.start():м.start() + 900]
        изо = re.search(r'<img[^>]+src="([^"]+)"', кусок)
        заглушка = bool(re.search(r'class="[^"]*__ph|placeholder', кусок))
        слаг = слаг_произведения(путь)
        итог.append({
            "путь": путь, "слаг": слаг,
            "блок": принадлежность.get(путь, "(вне полок)"),
            "в_блоках": повторы.get(путь, 0),
            "постер": изо.group(1) if изо else "",
            "заглушка_постера": заглушка and not изо,
        })
        if len(итог) >= сколько:
            break
    return итог


def слаг_произведения(путь: str) -> str:
    """Слаг произведения из адреса карточки.

    Брать последний сегмент нельзя: у ссылки на серию
    `/title/chernyy-klever/season-2/episode-3/` последним окажется
    `episode-3`, и запись не найдётся в каталоге. Первый живой замер 19.10
    из-за этого объявил «8 карточек вне каталога» на полке «Новые серии»
    animedia.icu, где все восемь есть в каталоге.
    """
    части = [ч for ч in (путь or "").split("/") if ч]
    if len(части) > 1 and части[0] in ("title", "anime"):
        return части[1]
    return части[-1] if части else ""


def данные_ячейки(каталог: pathlib.Path | None) -> tuple[dict, dict]:
    """Каталог и подробности ячейки по слагу. Отсутствие — пустые словари."""
    if not каталог or not каталог.is_dir():
        return {}, {}
    кат: dict[str, dict] = {}
    дет: dict[str, dict] = {}
    for ф in sorted(каталог.glob("*catalog*.json")):
        try:
            записи = json.loads(ф.read_text(encoding="utf-8")).get("items") or []
        except (OSError, ValueError):
            continue
        for з in записи:
            if з.get("slug"):
                кат.setdefault(str(з["slug"]), з)
        break
    # Скрытые и служебные файлы пропускаются, и выход — только на НЕПУСТОМ
    # разборе: первый замер 19.10 обрывался на `.zona-02-details-avail-ring.json`
    # (служебное кольцо доступности без ключа `details`), подробности выходили
    # пустыми, и все карточки печатались как «0/0 серий» — ложный дефект на
    # исправной полке.
    for ф in sorted(каталог.glob("*details*.json")):
        if ф.name.startswith(".") or ".nums." in ф.name:
            continue
        try:
            д = json.loads(ф.read_text(encoding="utf-8")).get("details") or {}
        except (OSError, ValueError):
            continue
        if д:
            дет = {str(к): v for к, v in д.items()}
            break
    return кат, дет


ДАННЫЕ_УСТАРЕЛИ_ЧЕРЕЗ = 14  # суток: порог, после которого сверка не проводится


def свежесть_данных(каталог: pathlib.Path | None, сегодня: dt.date) -> dict:
    """Насколько свежи данные ячейки и можно ли по ним сверять карточки.

    У витрин Yummy каталог ячейки лежит от 10.09, а подробностей нет вовсе:
    приложение обслуживает витрину из своего источника. Сверять карточки с
    такими данными нельзя — получится «13 карточек вне каталога» там, где вне
    каталога находятся сами данные. Это «сверка невозможна», а не дефект
    страницы.
    """
    if not каталог or not каталог.is_dir():
        return {"есть": False, "почему": "каталога данных ячейки нет"}
    файлы = [ф for ф in каталог.glob("*catalog*.json") if not ф.name.startswith(".")]
    if not файлы:
        return {"есть": False, "почему": "файла каталога в данных ячейки нет"}
    свежий = max(файлы, key=lambda ф: ф.stat().st_mtime)
    когда = dt.date.fromtimestamp(свежий.stat().st_mtime)
    суток = (сегодня - когда).days
    есть_подробности = any(
        ф for ф in каталог.glob("*details*.json")
        if not ф.name.startswith(".") and ".nums." not in ф.name)
    годен = суток <= ДАННЫЕ_УСТАРЕЛИ_ЧЕРЕЗ and есть_подробности
    почему = ""
    if суток > ДАННЫЕ_УСТАРЕЛИ_ЧЕРЕЗ:
        почему = (f"каталог ячейки от {когда.isoformat()} ({суток} суток назад)")
    elif not есть_подробности:
        почему = "подробностей в данных ячейки нет"
    return {"есть": годен, "почему": почему, "каталог_от": когда.isoformat(),
            "суток": суток, "подробности": есть_подробности}


def сведения(карточка: dict, кат: dict, дет: dict, сегодня: dt.date) -> dict:
    """Три даты и доступность по данным ячейки."""
    запись = кат.get(карточка["слаг"]) or {}
    деталь = дет.get(карточка["слаг"]) or {}
    if not деталь and запись.get("title"):
        имя = str(запись["title"]).strip().casefold()
        деталь = next((v for v in дет.values()
                       if str(v.get("name") or "").strip().casefold() == имя), {})
    # Доступность считается ПО ВИДУ записи. У фильма `seasons` равен null, и
    # сумма `avail` по нему даёт ноль — первый замер 19.10 из-за этого объявил
    # «24 карточки без доступных серий» на полке фильмов, где всё исправно.
    # Для фильма доступность — это playable и статус источника, для сериала —
    # число доступных серий.
    сезоны = деталь.get("seasons") or []
    источники = деталь.get("sources") or []
    доступные_источники = sum(
        1 for и in источники
        if str((и or {}).get("availability_status") or "") == "available")
    если_сериал = str(деталь.get("type") or "") == "tv" or bool(сезоны)
    if not деталь:
        # Нет подробностей — доступность НЕ ИЗМЕРЕНА. У ячеек Yummy файла
        # подробностей нет вовсе (только каталог и sqlite-читмодель), и первый
        # замер 19.10 из-за этого объявил «11 карточек без доступных серий» на
        # yummyani.site. Ноль там был не фактом, а отсутствием данных.
        доступно = None
        объявлено = None
    elif если_сериал:
        доступно = sum(int((с or {}).get("avail") or 0) for с in сезоны)
        объявлено = sum(int((с or {}).get("eps") or 0) for с in сезоны)
    else:
        доступно = 1 if (деталь.get("playable") and доступные_источники) else 0
        объявлено = 1
    год = str(запись.get("year") or "")
    появилась = str(запись.get("published_at") or "")[:10]
    возраст = None
    if год.isdigit():
        возраст = сегодня.year - int(год)
    свежая_запись = None
    if появилась:
        try:
            свежая_запись = (сегодня - dt.date.fromisoformat(появилась)).days
        except ValueError:
            свежая_запись = None
    return {
        "в_каталоге": bool(запись),
        "год": год or "—",
        "возраст_лет": возраст,
        "в_каталоге_с": появилась or "—",
        "оценочная_дата": bool(запись.get("published_at_estimated")),
        "дней_в_каталоге": свежая_запись,
        "серий_доступно": доступно,
        "серий_объявлено": объявлено,
        "вид": str(деталь.get("type") or запись.get("kind") or "—"),
        "это_сериал": если_сериал,
        "доступных_источников": доступные_источники,
    }


def проверить(домен: str, каталог: pathlib.Path | None, сколько: int,
              сегодня: dt.date | None = None) -> dict:
    сегодня = сегодня or dt.date.today()
    тело = добыть(f"https://{домен}/")
    if not тело:
        return {"измерено": False, "почему": "главная не получена"}
    полки = блоки(тело)
    карточки = карточки_по_порядку(тело, сколько)
    if not карточки:
        return {"измерено": False, "почему": "карточек на главной не найдено"}
    свежесть = свежесть_данных(каталог, сегодня)
    кат, дет = данные_ячейки(каталог) if свежесть["есть"] else ({}, {})
    строки = []
    for к in карточки:
        с = сведения(к, кат, дет, сегодня)
        строки.append({**к, **с})
    # Возраст по полкам: жалоба «на главной много старых тайтлов» становится
    # проверяемой только так. Год произведения, дата появления в каталоге и
    # доступность считаются РАЗДЕЛЬНО: запись 1932 года, добавленная вчера, —
    # не новинка, и обновление файла каталога новинкой её не делает.
    по_полкам: dict[str, dict] = {}
    for с in строки:
        полка = по_полкам.setdefault(с["блок"], {"карточек": 0, "годы": [],
                                                 "свежих_в_каталоге": 0,
                                                 "без_видео": 0})
        полка["карточек"] += 1
        if с["возраст_лет"] is not None:
            полка["годы"].append(int(с["год"]))
        if (с["дней_в_каталоге"] if с["дней_в_каталоге"] is not None else 999) <= 7:
            полка["свежих_в_каталоге"] += 1
        if с["в_каталоге"] and с["серий_доступно"] == 0:
            полка["без_видео"] += 1
        if с["серий_доступно"] is None:
            полка["доступность_не_измерена"] = \
                полка.get("доступность_не_измерена", 0) + 1
    for имя, п in по_полкам.items():
        годы = sorted(п["годы"])
        п["медиана_года"] = годы[len(годы) // 2] if годы else None
        п["старше_порога"] = sum(1 for г in годы
                                 if сегодня.year - г > СТАРЫМ_СЧИТАЕМ_ДО)
        п["самый_старый"] = годы[0] if годы else None
        п["самый_новый"] = годы[-1] if годы else None

    замечания = []
    # Наблюдения отделены от замечаний намеренно: замечание — это то, что НАДО
    # исправить на странице, а наблюдение — измеренное состояние, которое
    # исправлять на странице нечем. Смешивать их значило бы требовать работы
    # там, где её нет, и прогон переставали бы читать.
    наблюдения = []
    без_видео = [с for с in строки
                 if с["в_каталоге"] and с["серий_доступно"] == 0]
    доступность_не_измерена = [с for с in строки if с["серий_доступно"] is None]
    без_постера = [с for с in строки if not с["постер"]]
    повторы = [с for с in строки if с["в_блоках"] > 1]
    вне_каталога = [с for с in строки if not с["в_каталоге"]]
    # Пустой полкой не считается то, что полкой и не является: ссылочные
    # разделы (подборки, жанры, разделы) и заголовок-название страницы,
    # повторяющий h1. Последнее дало ложное замечание на animedia.icu.
    название = ""
    м1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело, re.S)
    if м1:
        название = _чисто(м1.group(1)).casefold()
    пустые_полки = пустые_среди(полки, название)
    # Полка без карточек ничего о составе не обещает: заголовок страницы
    # «Animedia Space — новое в каталоге и популярное аниме» давал ложное
    # замечание, потому что содержит слово «популярное».
    голословная_популярность = [п for п in полки
                                if п["карточек"]
                                and обещает_популярность(п["заголовок"])
                                and not п["признаки_популярности"]]
    if без_видео:
        # НЕ замечание о странице, а состояние ДАННЫХ — и на ячейках, где это
        # измерено, прямо так и сказано. MOD-97: поле `playable` и пустой
        # `sources` ошибочны примерно в 94 % случаев на zona-03 (из 18
        # проверенных карточек играют 17), и зонд показа подтвердил это и на
        # zona-02, и на lords-05. Печатать такое как дефект страницы значило бы
        # кричать «пожар» на каждом прогоне: исправить его на странице нельзя,
        # потому что страница исправна.
        if домен in ПОЛЕ_ДОСТУПНОСТИ_НЕДОСТОВЕРНО:
            наблюдения.append(
                f"по данным ячейки без доступного видео: {len(без_видео)}"
                " карточек — ПОЛЕ НЕДОСТОВЕРНО (MOD-97), проверять только"
                " зондом показа; дефектом страницы это не является")
        else:
            замечания.append(f"карточек без доступных серий: {len(без_видео)}")
    if доступность_не_измерена:
        замечания.append(
            f"НЕ ИЗМЕРЕНО по данным ячейки: {len(доступность_не_измерена)} "
            f"карточек — {свежесть.get('почему') or 'подробностей нет'}"
            " (это не ноль и не дефект страницы)")
    if без_постера:
        замечания.append(f"карточек без изображения: {len(без_постера)}")
    if повторы:
        замечания.append(f"карточек в нескольких блоках: {len(повторы)}")
    if вне_каталога and свежесть["есть"]:
        замечания.append(f"карточек вне каталога ячейки: {len(вне_каталога)}")
    if голословная_популярность:
        замечания.append("полка обещает популярность без признаков происхождения: "
                         + ", ".join(п["заголовок"] for п in голословная_популярность))
    годы_всех = sorted(int(с["год"]) for с in строки if с["год"].isdigit())
    свод = {
        "карточек": len(строки),
        "медиана_года": годы_всех[len(годы_всех) // 2] if годы_всех else None,
        "старше_порога": sum(1 for г in годы_всех
                             if сегодня.year - г > СТАРЫМ_СЧИТАЕМ_ДО),
        "годов_известно": len(годы_всех),
        "размеры_полок": [п["карточек"] for п in полки if п["карточек"]],
    }
    return {"измерено": True, "полки": полки, "карточки": строки, "свод": свод,
            "по_полкам": по_полкам, "свежесть_данных": свежесть,
            "замечания": замечания, "наблюдения": наблюдения,
            "пустые_полки": пустые_полки}


def свод_полки(и: dict, имя: str, сегодня: dt.date | None = None) -> dict | None:
    """Свод по ОДНОЙ полке: её карточки, медиана года, старые, размер.

    Пороги вроде «медиана года не ниже 2025» относятся к полке, которая
    обещает новизну, и не относятся к полке «Высокие оценки недели»: там
    старое кино законно. Применять страничный порог к такой витрине значило
    бы валить приёмку за честный состав.
    """
    сегодня = сегодня or dt.date.today()
    карточки = [к for к in и.get("карточки") or [] if к["блок"] == имя]
    if not карточки:
        return None
    годы = sorted(int(к["год"]) for к in карточки if к["год"].isdigit())
    return {
        "карточек": len(карточки),
        "медиана_года": годы[len(годы) // 2] if годы else None,
        "старше_порога": sum(1 for г in годы if сегодня.year - г > СТАРЫМ_СЧИТАЕМ_ДО),
        "годов_известно": len(годы),
        "размеры_полок": [len(карточки)],
    }


def приёмка(свод: dict, *, медиана: int | None = None,
            старше: int | None = None, полки: list[int] | None = None) -> list[str]:
    """Нарушенные приёмочные пороги. Пустой список — приёмка пройдена.

    Пороги задаются снаружи и числом: «медиана года первых карточек не ниже
    2025», «карточек старше десяти лет не больше нуля», «размеры полок
    24/12/12/9». Это и есть критерий T276 в проверяемом виде — публикатор
    умеет только status/contains/absent, а числа считает эта команда.

    Отдельный случай — «не измерено»: если год неизвестен ни у одной карточки,
    порог по медиане НЕ считается пройденным. Молчание здесь было бы хуже
    отказа: приёмка по неизмеренному — та же подгонка.
    """
    нарушено: list[str] = []
    if медиана is not None:
        м = свод.get("медиана_года")
        if м is None:
            нарушено.append("медиана года НЕ ИЗМЕРЕНА: год неизвестен ни у одной карточки")
        elif м < медиана:
            нарушено.append(f"медиана года {м} ниже порога {медиана}")
    if старше is not None and свод.get("старше_порога", 0) > старше:
        нарушено.append(f"карточек старше {СТАРЫМ_СЧИТАЕМ_ДО} лет"
                        f" {свод['старше_порога']} при пороге {старше}")
    if полки:
        факт = свод.get("размеры_полок") or []
        if факт[:len(полки)] != полки:
            нарушено.append(f"размеры полок {факт[:len(полки)]} вместо {полки}")
    return нарушено


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="ревизия первых карточек главной")
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--cards", type=int, default=КАРТОЧЕК)
    р.add_argument("--json", action="store_true")
    р.add_argument("--full", action="store_true", help="печатать каждую карточку")
    р.add_argument("--expect-median-year", type=int, default=None,
                   help="медиана года разобранных карточек не ниже этого числа")
    р.add_argument("--expect-max-old", type=int, default=None,
                   help="сколько карточек старше порога допустимо")
    р.add_argument("--expect-shelf", default="",
                   help="применять пороги к одной полке по её заголовку")
    р.add_argument("--expect-shelves", default="",
                   help="ожидаемые размеры первых полок через запятую, например 24,12,12,9")
    дов = р.parse_args(аргв)

    пары = домены_реестра()
    if дов.domain:
        известные = dict(пары)
        пары = [(д, известные.get(д)) for д in дов.domain]

    итоги: dict[str, dict] = {}
    for домен, каталог in пары:
        итоги[домен] = проверить(домен, каталог, дов.cards)

    if дов.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=2, default=str))
    else:
        for домен, и in итоги.items():
            if not и.get("измерено"):
                print(f"\n=== {домен}: НЕ ИЗМЕРЕНО — {и.get('почему')}")
                continue
            полки = и["полки"]
            print(f"\n=== {домен}: полок {len(полки)},"
                  f" карточек разобрано {len(и['карточки'])}")
            с = и.get("свежесть_данных") or {}
            if not с.get("есть"):
                print(f"   данные ячейки: СВЕРКА НЕВОЗМОЖНА — {с.get('почему')}")
            else:
                print(f"   данные ячейки: каталог от {с.get('каталог_от')}"
                      f" ({с.get('суток')} суток), подробности есть")
            for п in полки:
                признаки = (" ".join(п["признаки_популярности"])
                            if п["признаки_популярности"] else "—")
                print(f"   полка «{п['заголовок'][:44]:46}» карточек {п['карточек']:3}"
                      f"  признаки: {признаки}")
            if и.get("по_полкам"):
                print(f"   {'полка (первые карточки)':30} {'карт':>4} {'медиана':>8}"
                      f" {'старейший':>10} {'новейший':>9}"
                      f" {'старше ' + str(СТАРЫМ_СЧИТАЕМ_ДО):>11}"
                      f" {'свежих в кат.':>14} {'без видео':>10}")
                for имя, п in и["по_полкам"].items():
                    print(f"   {имя[:30]:30} {п['карточек']:4}"
                          f" {str(п['медиана_года'] or '—'):>8}"
                          f" {str(п['самый_старый'] or '—'):>10}"
                          f" {str(п['самый_новый'] or '—'):>9}"
                          f" {п['старше_порога']:11} {п['свежих_в_каталоге']:14}"
                          f" {п['без_видео']:10}")
            if дов.full:
                print(f"   {'слаг':34} {'блок':26} {'год':>5} {'в каталоге с':>13}"
                      f" {'дней':>5} {'серии':>9} {'блоков':>6}")
                for с in и["карточки"]:
                    серии = ("н/д" if с["серий_доступно"] is None
                             else f"{с['серий_доступно']}/{с['серий_объявлено']}")
                    дней = с["дней_в_каталоге"]
                    print(f"   {с['слаг'][:34]:34} {с['блок'][:26]:26}"
                          f" {с['год']:>5} {с['в_каталоге_с']:>13}"
                          f" {('—' if дней is None else дней):>5} {серии:>9}"
                          f" {с['в_блоках']:>6}")
            for н in и.get("наблюдения") or []:
                print(f"   наблюдение: {н}")
            for з in и["замечания"]:
                print(f"   ЗАМЕЧАНИЕ: {з}")
            if и["пустые_полки"]:
                print("   ЗАМЕЧАНИЕ: пустые полки: "
                      + ", ".join(п["заголовок"] for п in и["пустые_полки"]))

    измерено = [и for и in итоги.values() if и.get("измерено")]
    if not измерено:
        return 2

    ждём_полки = [int(ч) for ч in дов.expect_shelves.split(",") if ч.strip().isdigit()]
    если_пороги = (дов.expect_median_year is not None
                   or дов.expect_max_old is not None or ждём_полки)
    if если_пороги:
        всего_нарушено = 0
        for домен, и in итоги.items():
            if not и.get("измерено"):
                print(f"\nПРИЁМКА {домен}: НЕ ИЗМЕРЕНО — {и.get('почему')}")
                всего_нарушено += 1
                continue
            с = и["свод"]
            если_полка = ""
            if дов.expect_shelf:
                по_полке = свод_полки(и, дов.expect_shelf)
                if по_полке is None:
                    print(f"\nПРИЁМКА {домен}: НЕ ИЗМЕРЕНО — полки"
                          f" «{дов.expect_shelf}» на странице нет")
                    всего_нарушено += 1
                    continue
                с = по_полке
                если_полка = f" (полка «{дов.expect_shelf}»)"
            нарушено = приёмка(с, медиана=дов.expect_median_year,
                               старше=дов.expect_max_old, полки=ждём_полки or None)
            print(f"\nПРИЁМКА {домен}{если_полка}: медиана года {с['медиана_года']},"
                  f" старше {СТАРЫМ_СЧИТАЕМ_ДО} лет {с['старше_порога']},"
                  f" размеры полок {с['размеры_полок'][:6]}")
            if нарушено:
                всего_нарушено += 1
                for н in нарушено:
                    print(f"   НЕ ПРОЙДЕНО: {н}")
            else:
                print("   пройдена")
        return 1 if всего_нарушено else 0
    есть_замечания = any(и["замечания"] or и["пустые_полки"] for и in измерено)
    print(f"\nвитрин измерено {len(измерено)} из {len(итоги)};"
          f" с замечаниями {sum(1 for и in измерено if и['замечания'] or и['пустые_полки'])}")
    return 1 if есть_замечания else 0


if __name__ == "__main__":
    sys.exit(main())
