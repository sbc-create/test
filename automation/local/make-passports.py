def когда() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat(
        timespec="seconds").replace("+00:00", "Z")


def раздел_препятствий(очередь: dict, по_id: dict) -> str:
    задачи = [з for з in очередь["tasks"] if з.get("defect")]
    if not задачи:
        return ("Подтверждённых препятствий уровня P0/P1 по домену нет."
                " Этап выбран по измерению, а не по порядку: задержка перед"
                " задачами роста не создаётся.")
    строки = ["| задача | недостаток | уровень | доказательство |",
              "| --- | --- | --- | --- |"]
    for з in задачи:
        н = по_id.get(з["defect"], {})
        строки.append(
            f"| `{з['id']}` | {з['defect']} | {н.get('priority', '—')} |"
            f" {з['evidence'][:160].replace(chr(10), ' ')} |")
    return "\n".join(строки)


