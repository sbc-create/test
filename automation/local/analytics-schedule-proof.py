#!/usr/bin/env python3
"""Подтверждён ли сбор аналитики РАСПИСАНИЕМ, а не ручным прогоном.

Зачем. «Данные свежие» и «сбор работает сам» — разные утверждения, и второе
легко подменяется первым. Артефакт прогона называется по дате
(`analytics-<ГГГГ-ММ-ДД>.json`), поэтому второй прогон в тот же день пишет тот
же путь и затирает метку первого. После этого по каталогу артефактов нельзя
отличить «таймер отработал в 05:0x, а позже был ручной прогон» от «таймер не
отработал, был только ручной» — и день выглядит успешным в обоих случаях.

Измерено 13.10: за 11.10 и 12.10 в каталоге по одной записи с метками 10:07Z и
10:11Z, то есть подтверждения расписания за эти дни нет ни в одну сторону.

Инструмент называет это пределом измерения, а не успехом. Исходы по дню:

  ПОДТВЕРЖДЁН    метка артефакта попала в окно таймера — сбор по расписанию был
  НЕОТЛИЧИМО     метка вне окна: поверх могли записать ручным прогоном,
                 подтвердить или опровергнуть расписание по артефакту нельзя
  НЕ ЗАПУСКАЛСЯ  артефакта за день нет вовсе
  ЕЩЁ НЕ СРОК    окно таймера в этот день ещё не наступило

Окно считается из самого юнита: `OnCalendar` + `RandomizedDelaySec` + время
сбора (`--collect-minutes`, по умолчанию 15 — измерено по 09.10 и 10.10, где
метки 05:07:44Z и 05:10:49Z). Руками окно не вписано: если расписание в юните
поменяют, поменяется и окно.

Отдельно печатается то, что таймер вообще связан с target: юнит без симлинка в
`*.wants` не запускается, а строка `OnCalendar` в нём читается точно так же,
как в работающем.

Ничего не меняет: только `stat` и чтение юнитов. Сети не касается.

    python3 automation/local/analytics-schedule-proof.py
    python3 automation/local/analytics-schedule-proof.py --days 7
"""
from __future__ import annotations

import argparse
import datetime as _dt
import re
import sys
from pathlib import Path

ЮНИТ = Path("/etc/systemd/system/analytics-cabinet.timer")
СВЯЗЬ = Path("/etc/systemd/system/timers.target.wants/analytics-cabinet.timer")
МЕТКА = Path("/var/lib/systemd/timers/stamp-analytics-cabinet.timer")
АРТЕФАКТЫ = Path("/home/claude/wt-portable-site-cell-01/artifacts/analytics")
# Имя дня, а не точное имя файла: у 10.10 утренний прогон назван
# `analytics-2026-10-10.morning-0510.json` рядом с `analytics-2026-10-10.json`.
# Образец только на `.json` после даты объявил бы этот день неотличимым,
# хотя как раз он единственный и разделён. «Не нашёл по одному пути» — не
# «нет по признаку».
ОБРАЗЕЦ = re.compile(r"^analytics-(\d{4}-\d{2}-\d{2})(?:\.[^/]*)?\.json$")

ПОДТВЕРЖДЁН = "ПОДТВЕРЖДЁН"
НЕОТЛИЧИМО = "НЕОТЛИЧИМО"
НЕ_ЗАПУСКАЛСЯ = "НЕ ЗАПУСКАЛСЯ"
ЕЩЁ_НЕ_СРОК = "ЕЩЁ НЕ СРОК"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"
ДРУГОЕ_РАСПИСАНИЕ = "ДР. РАСПИСАНИЕ"


def окно_юнита(текст: str) -> tuple[_dt.time | None, int]:
    """Начало окна и случайная задержка в секундах — из строк самого юнита.

    Комментарии юнита пропускаются намеренно: в `analytics-cabinet.timer`
    закомментировано прежнее время 06:10, и разбор, не отличающий комментарий
    от настройки, взял бы именно его.
    """
    начало: _dt.time | None = None
    задержка = 0
    for строка in текст.splitlines():
        с = строка.strip()
        if с.startswith("#") or "=" not in с:
            continue
        ключ, значение = (ч.strip() for ч in с.split("=", 1))
        if ключ == "OnCalendar":
            совпало = re.search(r"(\d{2}):(\d{2}):(\d{2})", значение)
            if совпало:
                ч, м, сек = (int(г) for г in совпало.groups())
                начало = _dt.time(ч, м, сек)
        elif ключ == "RandomizedDelaySec":
            try:
                задержка = int(значение.rstrip("s"))
            except ValueError:
                задержка = 0
    return начало, задержка


def расписание_в_силе_с(юнит: Path) -> tuple[_dt.datetime | None, str]:
    """С какой даты действует ТЕКУЩЕЕ расписание — по снимкам прежнего юнита.

    Окно считается из нынешнего `OnCalendar`, а он менялся: рядом с юнитом
    лежат снимки `analytics-cabinet.timer.before-seo-regular-<метка>`, и в
    самом юните записано, что прежнее время было 06:10. Сравнивать день до
    смены с нынешним окном — значит мерить по расписанию, которое тогда не
    действовало; именно так метки 06:13Z и 06:19Z выглядели бы промахом.
    """
    снимки = sorted(юнит.parent.glob(юнит.name + ".before-*"))
    if not снимки:
        return None, "снимков прежнего расписания рядом с юнитом нет"
    метки = []
    for с in снимки:
        найдено = re.search(r"(\d{8})T(\d{6})Z$", с.name)
        if найдено:
            когда = _dt.datetime.strptime(
                найдено.group(1) + найдено.group(2), "%Y%m%d%H%M%S"
            ).replace(tzinfo=_dt.timezone.utc)
            метки.append((когда, с.name))
    if not метки:
        return None, f"у снимков ({len(снимки)}) нет разборчивой метки времени в имени"
    когда, имя = max(метки)
    return когда, (f"последняя смена расписания — {когда:%Y-%m-%dT%H:%M:%SZ}, "
                   f"по снимку {имя}")


def сутки_артефактов(каталог: Path) -> dict[_dt.date, list[tuple[_dt.datetime, str]]]:
    """День → ВСЕ записи за этот день: метка (UTC) и имя файла."""
    итог: dict[_dt.date, list[tuple[_dt.datetime, str]]] = {}
    if not каталог.is_dir():
        return итог
    for файл in каталог.iterdir():
        совпало = ОБРАЗЕЦ.match(файл.name)
        if not совпало:
            continue
        день = _dt.date.fromisoformat(совпало.group(1))
        метка = _dt.datetime.fromtimestamp(файл.stat().st_mtime,
                                           tz=_dt.timezone.utc)
        итог.setdefault(день, []).append((метка, файл.name))
    for записи in итог.values():
        записи.sort()
    return итог


def исход(день: _dt.date, записи: list[tuple[_dt.datetime, str]],
          начало: _dt.time, ширина: int, сейчас: _dt.datetime,
          в_силе_с: _dt.date | None = None) -> tuple[str, str]:
    """Исход по дню и причина словами.

    Подтверждает день ЛЮБАЯ запись с меткой внутри окна: прогон по расписанию
    мог оставить отдельно названный файл, который позднейший ручной прогон уже
    не затирает.
    """
    открылось = _dt.datetime.combine(день, начало, tzinfo=_dt.timezone.utc)
    закрылось = открылось + _dt.timedelta(seconds=ширина)
    окно = f"{открылось:%H:%M}–{закрылось:%H:%M}Z"
    # Сравнивается момент ОТКРЫТИЯ окна, а не дата: 08.10 расписание сменили в
    # 16:08Z, то есть утренний прогон того дня шёл ещё по прежнему времени.
    if в_силе_с is not None and открылось < в_силе_с:
        метки = ", ".join(f"{м:%H:%M:%S}Z" for м, _ in записи) or "записей нет"
        return ДРУГОЕ_РАСПИСАНИЕ, (f"{НЕ_ИЗМЕРЕНО}: окно {окно} открылось до смены "
                                   f"расписания ({в_силе_с:%Y-%m-%dT%H:%M:%SZ}), "
                                   f"метки: {метки}")
    if not записи:
        if сейчас < закрылось:
            return ЕЩЁ_НЕ_СРОК, f"окно {окно} ещё не прошло"
        return НЕ_ЗАПУСКАЛСЯ, f"артефакта за {день} нет, окно закрылось {закрылось:%H:%M}Z"
    в_окне = [(м, и) for м, и in записи if открылось <= м <= закрылось]
    if в_окне:
        метка, имя = в_окне[0]
        хвост = f" (записей за день: {len(записи)})" if len(записи) > 1 else ""
        return ПОДТВЕРЖДЁН, f"метка {метка:%H:%M:%S}Z внутри окна {окно}, файл {имя}{хвост}"
    метки = ", ".join(f"{м:%H:%M:%S}Z" for м, _ in записи)
    if all(м < открылось for м, _ in записи):
        return НЕОТЛИЧИМО, (f"все метки ({метки}) РАНЬШЕ окна {открылось:%H:%M}Z "
                            "— прогоном по расписанию это быть не может")
    return НЕОТЛИЧИМО, (f"ни одна метка ({метки}) не попала в окно {окно}: "
                        "поверх мог записать ручной прогон, и тогда прогон по "
                        "расписанию в тот же день уже не виден")


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--days", type=int, default=5, help="сколько последних суток разобрать")
    р.add_argument("--collect-minutes", type=int, default=15,
                   help="сколько минут занимает сам сбор (входит в окно)")
    р.add_argument("--unit", type=Path, default=ЮНИТ)
    р.add_argument("--wants", type=Path, default=СВЯЗЬ)
    р.add_argument("--stamp", type=Path, default=МЕТКА)
    р.add_argument("--artifacts", type=Path, default=АРТЕФАКТЫ)
    а = р.parse_args(аргв)

    print("СБОР АНАЛИТИКИ: ПОДТВЕРЖДЁН ЛИ ОН РАСПИСАНИЕМ")
    print()

    if not а.unit.is_file():
        print(f"юнит {а.unit} не читается — расписание {НЕ_ИЗМЕРЕНО}")
        return 2
    начало, задержка = окно_юнита(а.unit.read_text(encoding="utf-8"))
    if начало is None:
        print(f"в юните нет разборчивой строки OnCalendar — окно {НЕ_ИЗМЕРЕНО}")
        return 2
    ширина = задержка + а.collect_minutes * 60
    print(f"окно из юнита: {начало:%H:%M:%S}Z + задержка {задержка} с "
          f"+ сбор {а.collect_minutes} мин = ширина {ширина} с")

    связан = а.wants.exists()
    print(f"связь с target: {'есть' if связан else 'НЕТ — юнит не запускается'} "
          f"({а.wants})")

    if а.stamp.exists():
        м = _dt.datetime.fromtimestamp(а.stamp.stat().st_mtime, tz=_dt.timezone.utc)
        print(f"последнее срабатывание (метка systemd): {м:%Y-%m-%dT%H:%M:%SZ}")
    else:
        print(f"метка {а.stamp.name} недоступна под этой учётной записью — "
              f"последнее срабатывание {НЕ_ИЗМЕРЕНО}")

    в_силе_с, пояснение = расписание_в_силе_с(а.unit)
    print(f"действие текущего расписания: {пояснение}")

    по_дням = сутки_артефактов(а.artifacts)
    if not по_дням:
        print(f"\nкаталог артефактов {а.artifacts} пуст или не читается — "
              f"история {НЕ_ИЗМЕРЕНО}")
        return 2

    сейчас = _dt.datetime.now(tz=_dt.timezone.utc)
    дни = [сейчас.date() - _dt.timedelta(days=с) for с in range(а.days)]
    print(f"\nпоследние {а.days} суток:\n")
    счёт: dict[str, int] = {}
    for день in sorted(дни):
        код, причина = исход(день, по_дням.get(день, []), начало, ширина,
                              сейчас, в_силе_с)
        счёт[код] = счёт.get(код, 0) + 1
        print(f"  {день}  {код:<14} {причина}")

    print()
    for код in (ПОДТВЕРЖДЁН, НЕОТЛИЧИМО, НЕ_ЗАПУСКАЛСЯ, ЕЩЁ_НЕ_СРОК,
                ДРУГОЕ_РАСПИСАНИЕ):
        if счёт.get(код):
            print(f"  {код}: {счёт[код]}")

    неотличимо = счёт.get(НЕОТЛИЧИМО, 0)
    if неотличимо:
        print()
        print("ЭТО НЕ ЗНАЧИТ «СБОР СЛОМАН». Это значит, что за "
              f"{неотличимо} сут. по артефактам")
        print("подтвердить расписание нельзя: имя артефакта несёт только дату,")
        print("и повторный прогон за те же сутки затирает метку первого.")
        print("Разделить их умеет только журнал службы:")
        print("  journalctl -u analytics-cabinet.service --since -7d")
        print("— он читается из-под владельца, не из-под учётной записи claude.")

    if not связан:
        return 2
    if счёт.get(НЕ_ЗАПУСКАЛСЯ):
        return 1
    if неотличимо:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(главная())
