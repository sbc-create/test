#!/usr/bin/env python3
"""Воспроизводится ли ОСНОВНОЕ видео: раздельные исходы, а не один PASS.

Только чтение публичных страниц.

Зачем отдельный инструмент. Прежняя проверка
(`automation/local/player-page-probe.py`) считала показ начавшимся по наличию
кадра плеера и сетевых запросов к потоковому хосту. Измерено 20.10: этого
НЕДОСТАТОЧНО. На `zonafilm12.site/title/chya-eto-sobaka/` медиаданные
загружаются и буферизуются ДО всякого нажатия (`readyState` 4, буфер 6.6 с),
а видео при этом стоит на паузе. То есть подписанные запросы к CDN
подтверждают ответ источника, а не воспроизведение.

Исходы здесь раздельные и ни один не подменяет другой:

* ``ПЛЕЕРА НЕТ``        — кадр плеера или медиаэлемент не найден;
* ``ПЛЕЕР ЗАГРУЖЕН``    — медиаэлемент есть, данных ещё нет (readyState < 3);
* ``ИСТОЧНИК ОТВЕТИЛ``  — данные загружены (readyState ≥ 3 или буфер > 0), но
  время не продвигается: ровно состояние «загрузилось и стоит»;
* ``РЕКЛАМА ИДЁТ``      — продвигается КОРОТКИЙ ролик, основное стоит;
* ``ОСНОВНОЕ ВИДЕО ИДЁТ`` — время длинной дорожки растёт в двух замерах подряд
  при `paused = false`;
* ``ОШИБКА``            — media error или отказ `play()` с причиной;
* ``НЕ ИЗМЕРЕНО``       — состояние плеера недоступно (кадр не читается).

Основное от рекламы отличается длительностью и источником: рекламные ролики
здесь 10–21 с с хоста `ds.serving-sys.ru`, фильм — 4 863 и 7 151 с с `blob:`
плеера. Порог ``ДЛИННОЕ_ВИДЕО_С`` названный, а не угаданный.

    python3 automation/local/playback-verify.py --url <адрес> [--json]
    python3 automation/local/playback-verify.py --url <адрес> --seconds 90

Коды: 0 — основное видео идёт; 1 — любой другой определённый исход;
2 — не измерено.
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
import time

ХРОМ_ШАБЛОН = "/home/claude/.cache/ms-playwright/chromium*/chrome-linux*/chrome"

#: Длиннее этого — основное видео, короче — ролик перед ним. Измерено 20.10:
#: реклама 10 и 21 с, фильмы 4 863 и 7 151 с. Порог выбран с большим запасом в
#: обе стороны, чтобы короткий трейлер не спутался с фильмом.
ДЛИННОЕ_ВИДЕО_С = 180

#: Насколько должно вырасти время, чтобы считать это продвижением. Меньше —
#: дрожание: у остановленного видео время менялось на 0.013 с за три секунды.
ШАГ_ПРОДВИЖЕНИЯ_С = 0.5

#: ПОЧЕМУ ОДИН ПРОГОН НЕ ВЕРДИКТ. Измерено 20.10 на
#: /title/kiber-protokol/: два прогона ПОДРЯД с одним и тем же окном 150 с дали
#: разное — первый «источник ответил, показ не начался», второй «основное видео
#: идёт», время дошло до 113.8 с. Значит начало показа не детерминировано
#: (реклама, сеть, сессия), и отрицательный исход одного прогона говорит о
#: прогоне, а не о карточке. Положительный исход конечен: если время выросло,
#: оно выросло. Поэтому «не играет» требует НЕСКОЛЬКИХ отрицательных прогонов,
#: и подпись исхода это называет прямо.
ПОВТОРОВ_ДЛЯ_ОТРИЦАНИЯ = 3

#: Окно наблюдения по умолчанию. Шестьдесят секунд давали ЛОЖНОЕ ОТРИЦАНИЕ:
#: /title/chya-eto-sobaka/ за 60 с показ не начинал, а за 90 с дважды доходил до
#: 51–54 с. Между предварительной загрузкой и показом стоит реклама, и её
#: длительность в окно обязана влезать вместе с началом основной дорожки.
ОКНО_ПО_УМОЛЧАНИЮ = 90

ПЛЕЕРА_НЕТ = "ПЛЕЕРА НЕТ"
ПЛЕЕР_ЗАГРУЖЕН = "ПЛЕЕР ЗАГРУЖЕН"
ИСТОЧНИК_ОТВЕТИЛ = "ИСТОЧНИК ОТВЕТИЛ"
РЕКЛАМА_ИДЁТ = "РЕКЛАМА ИДЁТ"
ОСНОВНОЕ_ИДЁТ = "ОСНОВНОЕ ВИДЕО ИДЁТ"
ОШИБКА = "ОШИБКА"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"

ПОИСК_МЕДИА = """
() => {
  const найденные = [];
  const обойти = (корень, глубина) => {
    if (!корень || глубина > 12) return;
    let узлы;
    try { узлы = корень.querySelectorAll('*'); } catch (e) { return; }
    узлы.forEach(э => {
      if (э.tagName === 'VIDEO') найденные.push(э);
      if (э.shadowRoot) обойти(э.shadowRoot, глубина + 1);
    });
  };
  обойти(document, 0);
  return найденные.map(v => ({
    время: v.currentTime,
    длительность: Number.isFinite(v.duration) ? v.duration : null,
    пауза: v.paused,
    готовность: v.readyState,
    сеть: v.networkState,
    буфер: v.buffered.length ? v.buffered.end(v.buffered.length - 1) : 0,
    ошибка: v.error ? v.error.code : null,
    источник: (v.currentSrc || v.src || '').slice(0, 80),
  }));
}
"""


def длинные(снимок: list[dict]) -> list[dict]:
    return [м for м in снимок if (м.get("длительность") or 0) >= ДЛИННОЕ_ВИДЕО_С]


def короткие(снимок: list[dict]) -> list[dict]:
    return [м for м in снимок
            if м.get("длительность") and м["длительность"] < ДЛИННОЕ_ВИДЕО_С]


def _продвинулось(ряд: list[dict]) -> bool:
    """Выросло ли время хотя бы на шаг между двумя соседними замерами.

    Именно два замера подряд, а не один: единичное значение не отличает
    воспроизведение от загруженного и остановленного видео.
    """
    времена = [м.get("время") or 0 for м in ряд]
    return any(б - а >= ШАГ_ПРОДВИЖЕНИЯ_С for а, б in zip(времена, времена[1:]))


def оценить(снимки: list[list[dict]], *, отказ_play: str = "",
            окно_с: int | None = None) -> dict:
    """Исход по ряду замеров. Чистая функция: сеть не нужна.

    Порядок проверок намеренный — от самого сильного утверждения к слабым:
    если основное видео продвинулось, остальное уже неважно; реклама
    объявляется только когда основное НЕ идёт; «источник ответил» требует
    данных, а не просто наличия элемента.
    """
    if снимки is None:
        return {"исход": НЕ_ИЗМЕРЕНО, "почему": "состояние плеера недоступно"}
    последний = снимки[-1] if снимки else []
    if not any(снимки):
        return {"исход": ПЛЕЕРА_НЕТ, "почему": "медиаэлементов на странице нет"}

    ряд_длинных = [длинные(с) for с in снимки]
    основное_по_замерам = [с[0] for с in ряд_длинных if с]
    if основное_по_замерам and _продвинулось(основное_по_замерам):
        п = основное_по_замерам[-1]
        return {"исход": ОСНОВНОЕ_ИДЁТ,
                "почему": (f"время выросло до {п['время']:.1f} с из "
                           f"{(п.get('длительность') or 0):.0f} с"),
                "длительность": п.get("длительность"),
                "источник": п.get("источник", "")}

    ошибки = [м for м in последний if м.get("ошибка")]
    if ошибки or отказ_play:
        причина = (f"код медиа {ошибки[0]['ошибка']}" if ошибки else отказ_play)
        return {"исход": ОШИБКА, "почему": причина}

    ряд_коротких = [с[0] for с in (короткие(с) for с in снимки) if с]
    if ряд_коротких and _продвинулось(ряд_коротких):
        п = ряд_коротких[-1]
        return {"исход": РЕКЛАМА_ИДЁТ,
                "почему": (f"продвигается ролик {(п.get('длительность') or 0):.0f} с "
                           f"({п.get('источник', '')[:40]}), основное стоит")}

    загружено = [м for м in последний
                 if (м.get("готовность") or 0) >= 3 or (м.get("буфер") or 0) > 0]
    if загружено:
        п = sorted(загружено, key=lambda м: -(м.get("длительность") or 0))[0]
        # Окно наблюдения названо в самом исходе. Без него «время не
        # продвигается» читается как «не воспроизводится», а это разные
        # утверждения: измерено 20.10 на /title/chya-eto-sobaka/ — за 60 с
        # показ не начался, за 90 с дважды дошёл до 51–54 с. Вывод «не играет»
        # по короткому окну был ложным отрицанием, и признак обязан об этом
        # сообщать сам.
        за_окно = (f" за {окно_с} с наблюдения" if окно_с else "")
        return {"исход": ИСТОЧНИК_ОТВЕТИЛ,
                "почему": (f"данные загружены (готовность {п.get('готовность')}, "
                           f"буфер {(п.get('буфер') or 0):.1f} с),"
                           f" показ не начался{за_окно} В ЭТОМ ПРОГОНЕ —"
                           f" один такой прогон вердиктом «не играет» не"
                           f" является, нужен повтор"),
                "длительность": п.get("длительность"),
                "окно_с": окно_с}
    return {"исход": ПЛЕЕР_ЗАГРУЖЕН,
            "почему": "медиаэлемент есть, данных ещё нет"}


def проверить(адрес: str, *, секунд: int = ОКНО_ПО_УМОЛЧАНИЮ, шаг: int = 5,
              окно: tuple[int, int] = (1280, 800)) -> dict:
    """Живая проверка одного адреса. Возвращает исход и замеры."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return {"адрес": адрес, "исход": НЕ_ИЗМЕРЕНО,
                "почему": "playwright не установлен"}
    кандидаты = sorted(glob.glob(ХРОМ_ШАБЛОН))
    if not кандидаты:
        return {"адрес": адрес, "исход": НЕ_ИЗМЕРЕНО,
                "почему": "Chromium playwright не найден"}

    снимки: list[list[dict]] = []
    отказ = ""
    with sync_playwright() as p:
        браузер = p.chromium.launch(
            executable_path=кандидаты[-1],
            args=["--no-sandbox", "--disable-dev-shm-usage",
                  "--autoplay-policy=no-user-gesture-required"])
        страница = браузер.new_page(viewport={"width": окно[0], "height": окно[1]})
        try:
            # Навигация отделена от замеров. Её срыв — «не измерено» ПО ЭТОМУ
            # адресу, а не конец прогона: раньше таймаут `goto` вылетал из
            # функции и обрывал весь список. Измерено 20.10 на
            # zonafilm.cc/title/40-dney-2/ — `load` не наступил за 45 с, и две
            # следующие карточки остались непроверенными, хотя к ним вопросов
            # не было.
            try:
                ответ = страница.goto(адрес, wait_until="load", timeout=45000)
            except Exception as сбой:  # noqa: BLE001
                return {"адрес": адрес, "исход": НЕ_ИЗМЕРЕНО, "код": 0,
                        "нажатие": False, "замеров": 0,
                        "почему": f"навигация не завершилась:"
                                  f" {type(сбой).__name__}: {str(сбой)[:80]}"}
            код = ответ.status if ответ else 0
            страница.wait_for_timeout(4000)
            кадр = next((ф for ф in страница.frames
                         if "player" in ф.url or "video" in ф.url), None)
            цель = кадр or страница.main_frame
            # Нажатие — обязательный шаг: без пользовательского жеста показ не
            # начинается, и «стоит» означало бы лишь отсутствие нажатия.
            try:
                цель.click("body", timeout=4000)
                нажали = True
            except Exception:  # noqa: BLE001
                нажали = False
            конец = time.time() + секунд
            сбоев = 0
            while time.time() < конец:
                time.sleep(шаг)
                try:
                    снимки.append(цель.evaluate(ПОИСК_МЕДИА))
                except Exception as сбой:  # noqa: BLE001
                    # Один неудачный замер проверку не хоронит: кадр плеера
                    # переоткрывается сам (измерено 20.10 на `gyulizar-2` —
                    # первый прогон отдал «не измерено», второй «основное
                    # видео идёт»). «Не измерено» остаётся, только если не
                    # удался НИ ОДИН замер.
                    сбоев += 1
                    отказ = f"{type(сбой).__name__}: {str(сбой)[:60]}"
                    continue
            if not снимки:
                снимки = None  # type: ignore[assignment]
        finally:
            браузер.close()

    итог = оценить(снимки, отказ_play=отказ if снимки is None else "",
                   окно_с=секунд)
    итог.update({"адрес": адрес, "код": locals().get("код", 0),
                 "нажатие": locals().get("нажали", False),
                 "замеров": 0 if снимки is None else len(снимки)})
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="воспроизводится ли основное видео")
    р.add_argument("--url", action="append", required=True)
    р.add_argument("--seconds", type=int, default=ОКНО_ПО_УМОЛЧАНИЮ,
                   help="окно наблюдения, с (меньше 90 даёт ложные отрицания)")
    р.add_argument("--step", type=int, default=5)
    р.add_argument("--json", action="store_true")
    дов = р.parse_args(аргв)

    итоги = [проверить(а, секунд=дов.seconds, шаг=дов.step) for а in дов.url]
    if дов.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=2))
    else:
        for и in итоги:
            print(f"{и['исход']:22} код {и.get('код')}  замеров {и.get('замеров')}"
                  f"  нажатие {'да' if и.get('нажатие') else 'нет'}  {и['адрес']}")
            print(f"   {и.get('почему', '')}")
    if any(и["исход"] == НЕ_ИЗМЕРЕНО for и in итоги):
        return 2
    return 0 if all(и["исход"] == ОСНОВНОЕ_ИДЁТ for и in итоги) else 1


if __name__ == "__main__":
    sys.exit(main())
