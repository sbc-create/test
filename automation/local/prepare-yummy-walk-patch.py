#!/usr/bin/env python3
"""D4/MOD-108: предел обхода просмотра каталога Yummy — 80 × 100 = 8 000.

Дефект, измеренный 20–21.10 на всех пяти витринах: листалка объявляет 350
страниц по провайдерскому `total` (8 378 / 24), а страницы с 335-й отдают 200 и
ноль карточек. Последняя страница с содержимым — 334-я, то есть ровно 8 000
записей, и **378 живых тайтлов каталога недостижимы**.

Причина прочитана в ЗАПУЩЕННЫХ образах (`docker create` + `docker cp`, образ не
запускался): `src/modules/catalog/catalog-query.ts` — `API_WALK_LIMIT = 100`
(строка 110) и `MAX_WALK_REQUESTS = 80` (строка 126), условие цикла на 488:
`requests < MAX_WALK_REQUESTS`. Для страницы 350 нужно 8 400 записей, то есть
84 запроса по 100 — предел 80 не даёт добрать, и срез возвращает пустоту.

Это НЕДОДЕЛАННАЯ правка B016: тот же предел 80 × 100 в обходе КАРТЫ уже снят
(`catalog-index.ts`, `walkAnimeListItems(maxPages = 300)`), а в просмотре
каталога остался. Сравнение, которого требует задание: `maxPages = 300` — это
300 × 100 = 30 000 ЗАПИСЕЙ провайдера, а «350 страниц» — страницы ИНТЕРФЕЙСА по
24 записи (8 400). Величины разных единиц, предел карты не связывает.

Что делает правка:

1. число запросов считается от запрошенной страницы (`walkBudget`): первой
   странице по-прежнему хватает трёх запросов, глубокой — ровно столько, сколько
   нужно. Поднятие константы «на всякий случай» не годится: задание требует
   доказательства полноты, а не большего числа;
2. верхний предел остаётся страховкой от бесконечного обхода
   (`WALK_SAFETY_REQUESTS = 400`, то есть 40 000 записей при каталоге 8 378 —
   пятикратный запас);
3. добавлена защита от повторяющегося курсора: повтор означает, что провайдер
   вернул тот же срез, и без проверки цикл шёл бы до предела, собирая одно и то
   же.

Патч текстовый, а не построчный: у трёх образов сети один и тот же участок
стоит на строках 110/126/488 (`site`, `fixed`) и 109/125/487 (`org`).

    python3 automation/local/prepare-yummy-walk-patch.py \\
        --source var/yummy-src/site-src --out var/yummy-build/d4-site
"""
