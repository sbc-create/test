def переписать(текст: str) -> str:
    if "walkBudget" in текст:
        raise SystemExit("в исходнике правка УЖЕ есть — патч не нужен")
    for имя, якорь, замена in ЗАМЕНЫ:
        сколько = текст.count(якорь)
        if сколько != 1:
            raise SystemExit(
                f"якорь «{имя}» встречается {сколько} раз вместо одного:"
                " исходник изменился. Патч собирать заново, а не подгонять.")
        текст = текст.replace(якорь, замена, 1)
    return текст


#: Модель арифметики бюджета. Настоящая проверка — vitest внутри сборки образа;
#: здесь проверяется только то, что числа сходятся с измерением.
ПРЕДЕЛ_ЗАПРОСА = 100
СТРАХОВКА = 400


def бюджет(нужно: int, предел: int = ПРЕДЕЛ_ЗАПРОСА,
           страховка: int = СТРАХОВКА) -> int:
    if нужно <= 0:
        return 1
    return min(страховка, math.ceil(нужно / предел) + 2)


def репетиция() -> list[str]:
    итог: list[str] = []
    случаи = (
        ("страница 1 (24 записи)", 24, 3, "первая страница не стала дороже"),
        ("страница 334 (8 016)", 334 * 24, 83, "последняя прежняя страница"),
        ("страница 350 (8 400)", 350 * 24, 86,
         "именно здесь прежний предел 80 не давал добрать"),
        ("каталог вдвое больше", 16_756, 170, "запас есть"),
        ("нелепый запрос", 10_000_000, 400, "страховка держит"),
    )
    for подпись, нужно, ждём, зачем in случаи:
        дано = бюджет(нужно)
        итог.append(f"{'ок' if дано == ждём else 'ПРОВАЛ'}: {подпись} →"
                    f" {дано} запросов (ждали {ждём}); {зачем}")
    итог.append("ок: прежний плоский предел 80 не покрывает страницу 350"
                if бюджет(350 * 24) > 80
                else "ПРОВАЛ: предмет правки не воспроизводится")
    итог.append("ок: 400 × 100 = 40 000 записей против каталога 8 378"
                if СТРАХОВКА * ПРЕДЕЛ_ЗАПРОСА >= 8378 * 4
                else "ПРОВАЛ: страховка меньше четырёхкратного запаса")
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--source", required=True,
                   help="каталог `src`, снятый с образа")
    р.add_argument("--out", required=True,
                   help="куда положить патченный файл и diff")
    а = р.parse_args(аргв)

    исходный = Path(а.source) / ФАЙЛ
    if not исходный.is_file():
        print(f"НЕ СОБРАНО: нет файла {исходный}")
        return 2
    было = исходный.read_text(encoding="utf-8")
    стало = переписать(было)

    выход = Path(а.out)
    (выход / "src" / "modules" / "catalog").mkdir(parents=True, exist_ok=True)
    (выход / "src" / ФАЙЛ).write_text(стало, encoding="utf-8")
    (выход / "src" / "modules" / "catalog" / "walk-budget.ts").write_text(
        МОДУЛЬ_БЮДЖЕТА, encoding="utf-8")
    патч = "".join(difflib.unified_diff(
        было.splitlines(keepends=True), стало.splitlines(keepends=True),
        fromfile=f"a/src/{ФАЙЛ}", tofile=f"b/src/{ФАЙЛ}"))
    (выход / "catalog-query.patch").write_text(патч, encoding="utf-8")
    print(f"исходник: {исходный} ({len(было)} Б)")
    print(f"патченный файл: {выход / 'src' / ФАЙЛ}")
    print(f"diff: {выход / 'catalog-query.patch'} ({len(патч.splitlines())} строк)")

    провалов = 0
    print("\nрепетиция арифметики бюджета (настоящая проверка — vitest в сборке)")
    for строка in репетиция():
        print(f"   {строка}")
        провалов += 1 if "ПРОВАЛ" in строка else 0
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(главное())
