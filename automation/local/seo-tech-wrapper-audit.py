def записать_очередь(корень: Path, задачи: list[dict]) -> None:
    (корень / "config" / "seo-tech-queue.json").write_text(
        json.dumps({"tasks": задачи}, ensure_ascii=False), encoding="utf-8")


def исполнитель(стенд: Path, имя: str, текст: str) -> Path:
    путь = стенд / имя
    путь.write_text(текст, encoding="utf-8")
    путь.chmod(0o755)
    return путь


def прогнать(обёртка: Path, корень: Path, бинарь: Path, *,
             предел: str = "120", ждать: int = 300) -> tuple[int, str, float]:
    окружение = {
        **os.environ,
        "CLAUDE_BIN": str(бинарь),
        "SEO_TECH_TIMEOUT": предел,
        "SEO_TECH_TRIGGER": "стенд-приёмки",
        "СТЕНД_СОСТОЯНИЕ": str(корень / "var" / "seo-tech"),
        "PYTHONPATH": str(корень),
    }
    начало = time.monotonic()
    р = subprocess.run(["bash", str(обёртка)], capture_output=True, text=True,
                       timeout=ждать, env=окружение)
    return р.returncode, (р.stdout + р.stderr), time.monotonic() - начало


def следы(корень: Path, имя: str) -> list[dict]:
    ф = корень / "var" / "seo-tech" / имя
    if not ф.exists():
        return []
    return [json.loads(с) for с in ф.read_text(encoding="utf-8").splitlines()
            if с.strip()]


def замков(корень: Path) -> list[str]:
    к = корень / "var" / "seo-tech" / "claims"
    return sorted(п.name for п in к.glob("*.claim")) if к.is_dir() else []


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--tree", type=Path, default=ДЕРЕВО)
    р.add_argument("--stand", type=Path, default=Path("/tmp/seo-tech-wrapper-stand"))
    опции = р.parse_args(аргв)

    отчёт = Отчёт()
    if not (опции.tree / ОБЁРТКА).is_file():
        print(f"обёртка не проверена: нет {опции.tree / ОБЁРТКА}", file=sys.stderr)
        return 2
    try:
        корень, обёртка = собрать_стенд(опции.tree, опции.stand)
    except Exception as сбой:  # noqa: BLE001
        print(f"обёртка не проверена: стенд не собрался — "
              f"{type(сбой).__name__}: {сбой}", file=sys.stderr)
        return 2

    работающий = исполнитель(опции.stand, "claude-работает", ИСПОЛНИТЕЛЬ_РАБОТАЮЩИЙ)
    пустой = исполнитель(опции.stand, "claude-пустой", ИСПОЛНИТЕЛЬ_ПУСТОЙ)
    зависший = исполнитель(опции.stand, "claude-зависший", ИСПОЛНИТЕЛЬ_ЗАВИСШИЙ)

    # --- 1. Задача сделана: 0 и вердикт VERIFIED именно этой задачи ---------
    код, вывод, _ = прогнать(обёртка, корень, работающий)
    записи = следы(корень, "runs.jsonl")
    последняя = записи[-1] if записи else {}
    отчёт.шаг("сделанная задача даёт код 0", код == 0, f"код {код}; {вывод.strip()[:120]}")
    отчёт.шаг("в следах стоит вердикт VERIFIED этой задачи",
              последняя.get("verdict") == "VERIFIED" and последняя.get("task_id"),
              f"{последняя.get('task_id')} → {последняя.get('verdict')}")
    отчёт.шаг("в следе записан исход исполнителя",
              "model_exit" in последняя, f"model_exit={последняя.get('model_exit')}")
    отчёт.шаг("замок прогона снят — следующий цикл может начаться",
              not _замок_держится(корень), "run.lock свободен"
              if not _замок_держится(корень) else "run.lock всё ещё занят")

    # --- 2. Второй цикл берёт ДРУГУЮ задачу, без ручного запуска ------------
    код2, вывод2, _ = прогнать(обёртка, корень, работающий)
    записи2 = следы(корень, "runs.jsonl")
    взятые = [з.get("task_id") for з in записи2 if з.get("task_id")]
    отчёт.шаг("второй цикл подряд берёт ДРУГУЮ задачу",
              код2 == 0 and len(set(взятые)) >= 2,
              f"код {код2}; задачи по следам: {взятые}")

    # --- 3. Задач нет: 0, и модель не запускается ---------------------------
    записать_очередь(корень, [])
    было = len(следы(корень, "runs.jsonl"))
    код3, вывод3, _ = прогнать(обёртка, корень, зависший, предел="5", ждать=60)
    отчёт.шаг("при пустой очереди код 0 и модель не запускается",
              код3 == 0 and len(следы(корень, "runs.jsonl")) == было,
              f"код {код3}; новых записей "
              f"{len(следы(корень, 'runs.jsonl')) - было}")

    # --- 4. Занято другим прогоном: 75 -------------------------------------
    записать_очередь(корень, [
        {"id": "СТЕНД-3", "status": "queued", "repo": "site-repo",
         "check": "checks/task.py"}])
    замок = корень / "var" / "seo-tech" / "run.lock"
    замок.touch()
    # Своя группа процессов: `flock <файл> sleep` запускает sleep ДОЧЕРНИМ, и
    # terminate() самого flock оставляет sleep держать дескриптор. В первой
    # редакции из-за этого все последующие пробы получили 75, и приёмка
    # показала семь расхождений, которых нет.
    держатель = subprocess.Popen(["flock", str(замок), "sleep", "20"],
                                 start_new_session=True)
    _дождаться(lambda: _замок_держится(корень), 10, "держатель не взял замок")
    код4, вывод4, _ = прогнать(обёртка, корень, работающий, ждать=60)
    os.killpg(os.getpgid(держатель.pid), 15)
    держатель.wait(timeout=10)
    свободен = _дождаться(lambda: not _замок_держится(корень), 10,
                          "замок остался занятым")
    отчёт.шаг("занятость другим прогоном даёт ровно 75",
              код4 == 75, f"код {код4}; {вывод4.strip()[:100]}")
    отчёт.шаг("замок освобождается после ухода держателя",
              свободен, "освободился" if свободен
              else "остался занят — дальнейшие пункты недостоверны")

    # --- 5. Модель ничего не сделала: 2 и INCOMPLETE ------------------------
    было = len(следы(корень, "runs.jsonl"))
    код5, вывод5, _ = прогнать(обёртка, корень, пустой)
    записи5 = следы(корень, "runs.jsonl")
    отчёт.шаг("пустой прогон даёт код 2, а не 0",
              код5 == 2, f"код {код5}")
    отчёт.шаг("пустой прогон получает вердикт INCOMPLETE",
              len(записи5) > было
              and записи5[-1].get("verdict") == "INCOMPLETE",
              f"{записи5[-1].get('task_id')} → {записи5[-1].get('verdict')}"
              if записи5 else "записи нет")
    взятая5 = записи5[-1].get("task_id") if записи5 else ""
    отчёт.шаг("замок задачи снимается после обычного INCOMPLETE",
              f"{взятая5}.claim" not in замков(корень),
              f"задача {взятая5}; замки: {замков(корень) or 'нет'}")

    # --- 6. Зависшая модель: внешний предел снимает её ----------------------
    записать_очередь(корень, [
        {"id": "СТЕНД-ВИС", "status": "queued", "repo": "site-repo",
         "check": "checks/task.py"}])
    было = len(следы(корень, "runs.jsonl"))
    код6, _вывод6, длилось = прогнать(обёртка, корень, зависший,
                                      предел="3", ждать=120)
    записи6 = следы(корень, "runs.jsonl")
    отчёт.шаг("зависшую модель снимает внешний предел",
              длилось < 60, f"прогон занял {длилось:.1f} с при пределе 3 с")
    отчёт.шаг("снятая по пределу модель отмечена в следе кодом 124",
              len(записи6) > было and записи6[-1].get("model_exit") == 124,
              f"model_exit={записи6[-1].get('model_exit') if записи6 else 'нет'}")
    отчёт.шаг("после снятия по пределу прогон всё равно даёт вердикт",
              код6 == 2 and len(записи6) > было,
              f"код {код6}, записей добавлено {len(записи6) - было}")
    отчёт.шаг("замок прогона снят и после предела",
              not _замок_держится(корень), "run.lock свободен")
    # Замок ЗАДАЧИ (не прогона) — отдельное свойство: он держит именно эту
    # задачу, и если остаётся, она не берётся до истечения STALE_S.
    отчёт.шаг("замок задачи снимается и после снятия модели по пределу",
              "СТЕНД-ВИС.claim" not in замков(корень),
              f"замки задач: {замков(корень) or 'нет'}")

    # --- 7. Нет файла задания: обёртка не должна звать модель вслепую -------
    записать_очередь(корень, [
        {"id": "СТЕНД-БЕЗЗАДАНИЯ", "status": "queued", "repo": "site-repo",
         "check": "checks/task.py"}])
    задание = корень / "docs" / "seo-tech" / "SEO_TECH_RUN_PROMPT.md"
    сохранённое = задание.read_text(encoding="utf-8")
    задание.unlink()
    было = len(следы(корень, "runs.jsonl"))
    код7, вывод7, _ = прогнать(обёртка, корень, пустой)
    задание.write_text(сохранённое, encoding="utf-8")
    отчёт.шаг("пропавшее задание не даёт прогону пойти с пустым заданием",
              код7 not in (0,) and "задани" in вывод7.lower(),
              f"код {код7}; в выводе о задании "
              f"{'сказано' if 'задани' in вывод7.lower() else 'НЕ сказано'}")

    # --- 8. Журнал ворот: по нему видно, что цикл вообще был ----------------
    #
    # Считаются только циклы, ДОШЕДШИЕ до захвата: выход 75 («занято»)
    # случается строкой раньше журнала, и это по устройству. Первая редакция
    # проверки требовала записи и на него — то есть обвиняла обёртку в своей
    # же арифметике. Пропуск по занятости виден в журнале systemd: юнит
    # объявляет SuccessExitStatus=0 75, так что цикл не теряется.
    ворота = следы(корень, "gate.jsonl")
    отчёт.шаг("журнал ворот пишется на каждый цикл, дошедший до захвата",
              len(ворота) == 6, f"записей {len(ворота)} при 6 таких циклах")
    отчёт.шаг("в каждой записи ворот назван исход захвата",
              bool(ворота) and all("next_rc" in з for з in ворота),
              "next_rc есть во всех записях; выход 75 идёт до журнала и виден "
              "в журнале systemd")
    отчёт.шаг("в журнале ворот назван повод запуска",
              bool(ворота) and ворота[-1].get("trigger") == "стенд-приёмки",
              f"trigger={ворота[-1].get('trigger') if ворота else 'нет'}")

    # --- 9. Опознание прогона: вердикт обязан попасть СВОЕЙ задаче ----------
    #
    # RUN_ID в обёртке — метка времени с точностью до секунды. Два прогона в
    # одну секунду получают один идентификатор, а verify() и
    # release_worktree() ищут захват через `next(...)`, то есть берут ПЕРВЫЙ
    # совпавший. Тогда вердикт уходит чужой задаче, та получает незаслуженную
    # неудачу (и приближается к пределу попыток), а настоящая остаётся под
    # замком без вердикта. Это не придирка к формату: владелец требовал,
    # чтобы проверка подтверждала результат КОНКРЕТНОЙ задачи.
    захваты = следы(корень, "claims.jsonl")
    ид = [з.get("run_id") for з in захваты]
    повторы = sorted({и for и in ид if ид.count(и) > 1})
    отчёт.шаг("идентификаторы прогонов не повторяются",
              not повторы,
              f"всего {len(ид)}, различных {len(set(ид))}"
              + (f"; повторы {повторы} — метка времени с точностью до секунды"
                 if повторы else ""))
    по_прогону: dict[str, set] = {}
    for з in захваты:
        по_прогону.setdefault(з.get("run_id"), set()).add(з.get("task_id"))
    чужие = [(з.get("run_id"), з.get("task_id"), sorted(по_прогону.get(з.get("run_id"), [])))
             for з in следы(корень, "runs.jsonl")
             if з.get("task_id") not in по_прогону.get(з.get("run_id"), {з.get("task_id")})
             or len(по_прогону.get(з.get("run_id"), [])) > 1]
    отчёт.шаг("вердикт записан той задаче, которую прогон захватил",
              not чужие,
              "совпадает у всех" if not чужие
              else f"расходится: {чужие[:3]}")
    # Два признака выше ловят коллизию только если она СЛУЧИЛАСЬ: за прогон
    # приёмки она то есть, то нет, а проверка по удаче доверия не несёт
    # (D205). Поэтому следствие воспроизводится прямым вызовом —
    # детерминированно. Вероятность коллизии — свойство обёртки (секундная
    # метка), а её цена — свойство библиотеки, и мерить надо цену.
    отчёт.шаг(*_проба_одинакового_прогона(корень, опции.stand))

    отчёт.печать()
    print(f"\nрасхождений: {отчёт.расхождений}; не измерено: {отчёт.не_измерено}")
    print(f"замки задач на стенде после всех прогонов: {замков(корень) or 'нет'}")
    return 1 if отчёт.расхождений else 0


#: Прямая проба цены коллизии: два захвата под ОДНИМ run_id, затем вердикт.
ПРОБА_ОДИНАКОВОГО = """\
import json, sys
from pathlib import Path
from seo_operator import tech_run as t

состояние = Path(sys.argv[1])
задачи = [{"id": "ДВОЙНИК-A", "status": "queued", "repo": "site-repo",
           "check": "checks/task.py"},
          {"id": "ДВОЙНИК-B", "status": "queued", "repo": "site-repo",
           "check": "checks/task.py"}]
общий = "ОДИН-И-ТОТ-ЖЕ"
# Последовательность в точности как у обёртки: прогон захватывает, получает
# вердикт и освобождает копию — и только поэтому следующий прогон с ТЕМ ЖЕ
# идентификатором может захватить снова (иначе `git worktree add` упал бы на
# существующем пути). Журнал захватов при этом хранит обе записи.
a = t.claim(задачи[0], общий, state=состояние)
t.verify(общий, state=состояние, run_all=False)
t.release_worktree(общий, state=состояние)
b = t.claim(задачи[1], общий, state=состояние)
итог = t.verify(общий, state=состояние, run_all=False)
t.release_worktree(общий, state=состояние)
замки = sorted(п.name for п in (состояние / "claims").glob("*.claim"))
print(json.dumps({"захвачено": [a["task_id"], b["task_id"]],
                  "вердикт_о_задаче": итог.get("task_id"),
                  "замки_после": замки}, ensure_ascii=False))
"""


def _проба_одинакового_прогона(корень: Path, стенд: Path):
    """(имя, ок, подробно) — цена одинакового идентификатора двух прогонов."""
    сценарий = стенд / "проба-двойника.py"
    сценарий.write_text(ПРОБА_ОДИНАКОВОГО, encoding="utf-8")
    состояние = стенд / "двойники"
    if состояние.exists():
        shutil.rmtree(состояние)
    состояние.mkdir(parents=True)
    р = subprocess.run([sys.executable, str(сценарий), str(состояние)],
                       capture_output=True, text=True, cwd=корень, timeout=300,
                       env={**os.environ, "PYTHONPATH": str(корень)})
    имя = "одинаковый идентификатор прогонов не уводит вердикт чужой задаче"
    if р.returncode != 0:
        return имя, None, f"проба не прошла: {р.stderr.strip()[-200:]}"
    итог = json.loads(р.stdout.strip().splitlines()[-1])
    взято = итог["захвачено"]
    о_задаче = итог["вердикт_о_задаче"]
    осталось = итог["замки_после"]
    верно = о_задаче == взято[-1] and not осталось
    return имя, верно, (
        f"захвачены {взято}, вердикт о {о_задаче}, замки после: "
        f"{осталось or 'нет'}"
        + ("" if верно else " — вердикт ушёл первой задаче, вторая осталась "
                            "под замком без вердикта"))


def _дождаться(условие, предел_с: float, чего: str) -> bool:
    """Ожидание всегда ограничено (D205): не дождались — это ответ, а не вечность."""
    срок = time.monotonic() + предел_с
    while time.monotonic() < срок:
        if условие():
            return True
        time.sleep(0.1)
    print(f"   (ожидание {предел_с} с исчерпано: {чего})", file=sys.stderr)
    return False


def _замок_держится(корень: Path) -> bool:
    """Занят ли run.lock: пробуем взять его сами, не блокируясь."""
    замок = корень / "var" / "seo-tech" / "run.lock"
    if not замок.exists():
        return False
    р = subprocess.run(["flock", "-n", str(замок), "true"], capture_output=True)
    return р.returncode != 0


