#!/usr/bin/env python3
"""Приёмка обёртки прогона технического SEO (`seo-tech-run.sh`) — поведением.

Юнит и таймер ставит root, и перед этим обёртку надо проверить не чтением, а
прогонами: это последние ворота перед автономным запуском. Проверяется, что
обёртка различает исходы, а не просто завершается:

* занято другим прогоном → 75 (юнит объявляет `SuccessExitStatus=0 75`, то есть
  «занято» не ошибка, и перепутать это с успехом нельзя);
* задач нет → 0 без запуска модели;
* задача сделана → 0, и в следах лежит вердикт VERIFIED ИМЕННО этой задачи;
* модель ничего не сделала → 2 (юнит падает — это уведомление), вердикт
  INCOMPLETE;
* модель зависла → внешний предел её снимает, прогон заканчивается, в следе
  стоит `model_exit=124`, и обёртка не держит замок вечно;
* замок прогона снимается при любом исходе, иначе следующий цикл не начнётся —
  а два цикла подряд и есть доказательство автопродолжения.

Живое состояние не трогается. Обёртка прошита на `/home/claude/wt-portable-
site-cell-01`, поэтому стенд — отдельное дерево, куда `seo_operator`
КОПИРУЕТСЯ: симлинк не годится, `Path(__file__).resolve()` разыменовал бы его
и состояние с очередью снова оказались бы живыми. Исполнитель модели
подменяется через `CLAUDE_BIN` — это предусмотрено самой обёрткой.
"""
