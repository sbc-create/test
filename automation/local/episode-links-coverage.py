#!/usr/bin/env python3
"""Серии, которых нет ни в ссылках карточки, ни в карте сайта.

Зачем. Страница серии может существовать, отдавать 200, несть плеер и верный
заголовок — и при этом быть недостижимой: на неё не ведёт ни одна ссылка, и в
карте сайта её нет. Такое содержимое не найдёт ни обход, ни посетитель.

Что мера НЕ значит, и это выяснилось дорого. Сравнение ссылок с полным числом
серий (`numberOfEpisodes`) давало десятки «серий без ссылки» на витринах
AnimeGo — и потери там нет. Карточка рисует серии ВЫБРАННОГО сезона, остальные
сезоны идут вкладками, каждая ведёт на первую играющую серию; со страницы серии
виден весь её сезон. За два перехода достижимо всё. А остаток разрыва — серии
без дорожки в снимке, и ссылок на них нет НАМЕРЕННО («Серия ещё не вышла»).

Поэтому сверка идёт с числом ДОСТУПНЫХ серий, которое страница пишет сама:
«2 сезона, 36 серий, доступно 12». Нет такой оговорки — сверять не с чем, и это
«не измерено», а не разрыв.

Как считается:

* доступное число — из строки «доступно N» на самой странице;
* фактическое — число РАЗНЫХ ПАР «сезон+серия» в ссылках. Не различных номеров:
  при двух сезонах номера повторяются, и счёт по номерам дал мне ложное
  расхождение 36 против 18 на `schastlivaya-karta`, где всё было верно;
* полное число (`numberOfEpisodes`) печатается справочно и разрывом не считается:
  для schema.org это число эпизодов сериала, а не число доступных к просмотру.

Ничего не меняет: только читает живые витрины и их карты.

    python3 automation/local/episode-links-coverage.py an1mego.site
    python3 automation/local/episode-links-coverage.py --limit 60 lordserial33.biz
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import ssl
import urllib.error
import urllib.request

_LD = re.compile(r"<script[^>]+application/ld\+json[^>]*>(.*?)</script>",
                 re.S | re.I)
#: Две формы адреса серии в сети. Lords, Zona и AnimeGo пишут через дефис,
#: Yummy — через косую черту. Знать одну значило выдать чистый проход по
#: витрине с наибольшим трафиком: 699 ссылок на карточке не были увидены.
_ПАРА = re.compile(r"/season[-/](\d+)/episode[-/](\d+)")
#: Есть ли в разметке хоть какое-то упоминание серии. Нужно, чтобы отличить
#: «это фильм, серий нет» от «ссылки есть, но их форма не узнана».
_ЛЮБАЯ_СЕРИЯ = re.compile(r"/episode[-/_]\d+")
_КАРТОЧКА = re.compile(r"/(?:title|anime)/[^/]+/?$")


def _открыть():
    контекст = ssl.create_default_context()
    контекст.check_hostname = False
    контекст.verify_mode = ssl.CERT_NONE
    return urllib.request.build_opener(
        urllib.request.HTTPSHandler(context=контекст))


def достать(адрес: str, предел: float, байт: int = 900_000) -> str:
    ответ = _открыть().open(
        urllib.request.Request(адрес, headers={"User-Agent":
                                               "factory-episode-coverage"}),
        timeout=предел)
    return ответ.read(байт).decode("utf-8", "replace")


def объявлено(разметка: str) -> int | None:
    """`numberOfEpisodes` из JSON-LD `TVSeries`, либо None если его нет."""
    итог: int | None = None
    for кусок in _LD.findall(разметка):
        try:
            документ = json.loads(кусок)
        except json.JSONDecodeError:
            continue
        for узел in (документ if isinstance(документ, list) else [документ]):
            if not isinstance(узел, dict) or узел.get("@type") != "TVSeries":
                continue
            значение = узел.get("numberOfEpisodes")
            if значение is None:
                continue
            try:
                итог = int(значение)
            except (TypeError, ValueError):
                continue
    return итог


#: «доступно 12» в строке характеристик. Пишет его сама страница, и это
#: единственное честное основание для сверки: полное число включает серии,
#: которых у источника ещё нет.
_ДОСТУПНО = re.compile(r"доступно\s+(\d+)", re.I)


def доступно(разметка: str) -> int | None:
    """Сколько серий страница объявляет ДОСТУПНЫМИ, либо None.

    None — «сверять не с чем»: у части тайтлов оговорки о доступности нет
    вовсе, и тогда ни одно число на странице не годится в меру.
    """
    текст = re.sub(r"<[^>]+>", " ", разметка)
    м = _ДОСТУПНО.search(текст)
    return int(м.group(1)) if м else None


def это_вкладки(по_сезонам: dict[int, int]) -> bool:
    """Узор «один сезон полностью плюс по одной ссылке на каждый другой».

    Так устроена карточка: серии выбранного сезона плюс вкладки остальных,
    каждая ведёт на первую играющую серию. Со страницы серии виден весь её
    сезон, значит за два перехода достижимо всё, и разрывом это не является.
    """
    if len(по_сезонам) < 2:
        return False
    значения = sorted(по_сезонам.values())
    # Все, кроме одного, дают ровно одну ссылку, и этот один даёт больше.
    return значения[:-1] == [1] * (len(значения) - 1) and значения[-1] > 1


def связанные(разметка: str) -> set[tuple[int, int]]:
    """Разные ПАРЫ «сезон+серия» в ссылках страницы.

    Пары, а не номера: при двух сезонах номера повторяются, и счёт по номерам
    даёт ложное расхождение там, где всё верно.
    """
    return {(int(с), int(э)) for с, э in _ПАРА.findall(разметка)}


def карточки(домен: str, предел_штук: int, предел_с: float) -> list[str]:
    """Адреса карточек из публичной карты сайта, а не угаданные."""
    try:
        корень = достать(f"https://{домен}/sitemap.xml", предел_с, 1_500_000)
    except Exception:
        return []
    свои = re.findall(r"<loc>([^<]+)</loc>", корень)
    прямые = [а for а in свои if _КАРТОЧКА.search(а)]
    if прямые:
        return прямые[:предел_штук]
    итог: list[str] = []
    for часть in свои:
        # Имя части не фильтруется: предположение «в имени есть слово title»
        # ложно — части называются `sitemap-1.xml`, и фильтр по имени оставлял
        # выборку пустой, а инструмент говорил «не измерено» на исправной карте.
        try:
            тело = достать(часть, предел_с, 1_500_000)
        except Exception:
            continue
        итог += [а for а in re.findall(r"<loc>([^<]+)</loc>", тело)
                 if _КАРТОЧКА.search(а)]
        if len(итог) >= предел_штук:
            break
    return итог[:предел_штук]


def серии_в_карте(домен: str, предел_с: float) -> int:
    """Сколько адресов серий объявлено в карте сайта.

    Если их там много, разрыв в ссылках менее тяжёл: находимость сохраняется
    другим путём. Ноль означает, что ссылки — единственный путь.
    """
    try:
        корень = достать(f"https://{домен}/sitemap.xml", предел_с, 1_500_000)
    except Exception:
        return -1
    всего = 0
    for часть in re.findall(r"<loc>([^<]+)</loc>", корень):
        try:
            тело = достать(часть, предел_с, 1_500_000)
        except Exception:
            continue
        всего += sum(1 for а in re.findall(r"<loc>([^<]+)</loc>", тело)
                     if "/episode-" in а)
    return всего


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("domains", nargs="+")
    р.add_argument("--limit", type=int, default=40,
                   help="сколько карточек брать из карты сайта")
    р.add_argument("--timeout", type=float, default=60.0)
    опции = р.parse_args(аргв)

    расхождений_всего = 0
    неузнанных_всего = 0
    for домен in опции.domains:
        print(f"=== {домен}")
        адреса = карточки(домен, опции.limit, опции.timeout)
        if not адреса:
            print("   [не измерено] карту сайта или её разделы прочитать "
                  "не удалось")
            continue
        в_карте = серии_в_карте(домен, опции.timeout)
        с_сериями = 0
        без_объявления = 0
        не_узнано = 0
        вкладками = 0
        затронуто: list[tuple[str, int, int, dict]] = []
        потеряно = 0
        for адрес in адреса:
            try:
                разметка = достать(адрес, опции.timeout, 700_000)
            except Exception:
                continue
            пары = связанные(разметка)
            if not пары:
                # Упоминание серии есть, а пар нет — форма адреса не узнана.
                # Промолчать здесь значило бы выдать чистый проход по витрине,
                # ссылки которой инструмент просто не видит.
                if _ЛЮБАЯ_СЕРИЯ.search(разметка):
                    не_узнано += 1
                continue
            с_сериями += 1
            сказано = доступно(разметка)
            всего_серий = объявлено(разметка)
            if сказано is None:
                без_объявления += 1
                continue
            if сказано > len(пары):
                по_сезонам = dict(sorted(
                    collections.Counter(с for с, _ in пары).items()))
                if это_вкладки(по_сезонам):
                    вкладками += 1
                    continue
                затронуто.append((адрес, сказано, len(пары), по_сезонам,
                                  всего_серий))
                потеряно += сказано - len(пары)

        print(f"   карточек в выборке: {len(адреса)}; с сериями: {с_сериями}")
        if не_узнано:
            print(f"   [НЕ ИЗМЕРЕНО] карточек с упоминанием серий, чью форму "
                  f"адреса инструмент не узнал: {не_узнано}. Это предел "
                  "измерения, а не исправность — вывод ниже про них молчит.")
        if без_объявления:
            print(f"   [не измерено] без оговорки «доступно N»: "
                  f"{без_объявления} — сверять не с чем. Полное число серий "
                  "мерой не годится: оно включает серии, которых у источника "
                  "ещё нет, и ссылок на них нет намеренно")
        if вкладками:
            print(f"   [ок] карточек с узором вкладок сезонов: {вкладками} — "
                  "выбранный сезон целиком плюс по одной ссылке на остальные; "
                  "со страницы серии виден весь её сезон, разрывом не считается")
        print(f"   серий в карте сайта: "
              f"{'прочитать не удалось' if в_карте < 0 else в_карте}")
        неузнанных_всего += не_узнано
        if затронуто:
            print(f"   карточек, где ссылок меньше ДОСТУПНОГО числа: "
                  f"{len(затронуто)}; серий без ссылки: {потеряно}")
            for адрес, сказано, факт, по_сезонам, всего in затронуто[:8]:
                имя = адрес.rstrip("/").rsplit("/", 1)[-1]
                # Полное число — СПРАВОЧНО, как и обещает шапка файла. До
                # 20.10 оно вычислялось и выбрасывалось: обещание в
                # документации было, вывода не было. «Нет оговорки» печатается
                # словом, а не нулём, чтобы отсутствие не читалось как ноль.
                справка = (f", всего по разметке {всего}" if всего is not None
                           else ", всего по разметке не объявлено")
                print(f"      {имя[:40]:42s} доступно {сказано}, "
                      f"в ссылках {факт}, сезоны {по_сезонам}{справка}")
            if len(затронуто) > 8:
                print(f"      … и ещё {len(затронуто) - 8}")
            if в_карте == 0:
                # Факт без вывода: карта серий не содержит, но переход по
                # вкладкам существует, и «не найдёт никто» из этого не следует.
                print("   серий в карте сайта нет — находимость держится "
                      "только на ссылках и переходах страницы")
            расхождений_всего += len(затронуто)
        else:
            # Область действия вывода называется явно. «Ни у одной карточки»
            # рядом со строкой «не измерено: N» всё равно успокаивает, хотя
            # про эти N карточек не известно ничего.
            чьи = ("ни у одной ИЗ ИЗМЕРЕННЫХ карточек"
                   if не_узнано else "ни у одной карточки")
            print(f"   ссылок не меньше доступного числа {чьи}")

    if расхождений_всего:
        return 1
    return 2 if неузнанных_всего else 0


if __name__ == "__main__":
    raise SystemExit(главное())
