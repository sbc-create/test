#!/usr/bin/env python3
"""Чем подтверждена каждая заморозка в очередях домéнов. Аудит, не правка.

Повод — MOD-163 и поручение владельца согласовать очереди и паузы вместе,
сохраняя существующие ограничения до исправления. Форма за моей линией:
очереди (`config/domain-queues/*.json`) ведёт она.

Главное решение формы: заморозка живёт ТАМ, ГДЕ ОНА УЖЕ ЕСТЬ — в поле
`blocked_by` задачи, с датой. Реестр опытов выдуманными записями не
дополняется: записи опыта требуют гипотезы, метрики, доли страниц и
наблюдения, и сочинить их значило бы подделать измерение.

Измерено 26.10 по 23 файлам очередей: задач с `blocked_by` — 106, и они
распадаются на ЧЕТЫРЕ вида, а не на три. Четвёртый — самый многочисленный, и
именно его потеряло бы правило «у каждой паузы должна быть дата»:

  опыт           ссылается на `exp-…`: подтверждается записью в
                 `config/experiments.json` либо строкой журнала изменений с
                 датой оценки (журнал есть только у линии SEO, поэтому путь к
                 нему — аргумент, а его отсутствие — названная причина, а не
                 провал);
  дата_оценки    пауза до названной даты без ссылки на опыт: подтверждается
                 самой датой и названным источником решения;
  правило        ПОСТОЯННЫЙ отказ по правилу проекта («запись в постоянные
                 данные витрины запрещена») — даты у него нет и быть не
                 должно; подтверждается ссылкой на документ правила;
  вход_владельца ждёт входа владельца: подтверждается названием того, чего
                 именно не хватает.

Проверка НИКОГДА не снимает заморозку и ничего не правит: она только говорит,
чем каждая подтверждена, и падает на неподтверждённых. Это требование линии
SEO, и оно верное: аудит, который сам снимает ограничение, однажды снимет его
по ошибке разбора.

    python3 automation/local/queue-pause-audit.py
    python3 automation/local/queue-pause-audit.py --ledger /path/CHANGES_LEDGER.md
    python3 automation/local/queue-pause-audit.py --json
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ОЧЕРЕДИ = КОРЕНЬ / "config" / "domain-queues"
ОПЫТЫ = КОРЕНЬ / "config" / "experiments.json"
#: Документы правил, ссылка на которые подтверждает постоянный отказ.
ДОКУМЕНТЫ_ПРАВИЛ = ("RUNTIME_DATA_OWNERSHIP", "UNATTENDED_SAFE", "DECISIONS",
                    "protected.py", "CLAUDE.md", "COMMON_FIX_INHERITANCE")
#: Слова, которыми в очередях называют ожидание владельца. Перечень собран
#: ПО ТЕКСТАМ очередей, а не придуман: «нужен владелец» в него не входило, и
#: заморозка lordfilm.group/Q-004 из-за этого числилась неопределённой.
СЛОВА_ВЛАДЕЛЬЦА = ("вход владельца", "решение владельца", "ждёт владельца",
                   "разрешение владельца", "нужен владелец", "BLOCKED_INPUT")
#: Пятый вид, найденный в данных: ожидание вердикта ЧУЖОЙ линии (канарейка,
#: правка на оценке). Подтверждается идентификатором вида T317 и названием
#: домена, где он идёт: по ним вердикт можно проверить у той линии.
ОБРАЗЕЦ_ЧУЖОГО = r"\bT\d{3}\b"
СЛОВА_ЧУЖОГО = ("канарейк", "вердикт", "соседняя линия", "ведёт соседняя")
#: Шестой вид: ДОКАЗАННОЕ внешнее ограничение (нет прав, нет сети, нет
#: доступа к цели). Подтверждается названным ограничением, а не датой: даты у
#: него нет и быть не может, пока ограничение не снято.
СЛОВА_ОГРАНИЧЕНИЯ = ("доказанное внешнее ограничение", "измерить нельзя",
                     "запрещён", "нет доступа", "не проходит сеть",
                     "закрыт профилем", "нет прав")


def _даты(текст: str, год: int) -> list[_dt.date]:
    итог = []
    for д, м in re.findall(r"\b(\d{1,2})\.(\d{2})(?!\.\d)", текст):
        try:
            итог.append(_dt.date(год, int(м), int(д)))
        except ValueError:
            continue
    for г, м, д in re.findall(r"\b(\d{4})-(\d{2})-(\d{2})\b", текст):
        try:
            итог.append(_dt.date(int(г), int(м), int(д)))
        except ValueError:
            continue
    return итог


def опыты_реестра() -> set[str]:
    try:
        д = json.loads(ОПЫТЫ.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    return {str(э.get("experiment_id")) for э in д.get("experiments") or []}


def опыты_журнала(путь: pathlib.Path | None) -> dict[str, str]:
    """Опыты, упомянутые в журнале изменений, и строка, где это сказано.

    Журнал есть только у линии SEO. Его отсутствие — НАЗВАННАЯ причина, а не
    провал проверки: иначе моя ветвь валила бы аудит из-за чужого файла.
    """
    if путь is None or not путь.is_file():
        return {}
    итог = {}
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        for опыт in re.findall(r"exp-[\w-]+", строка):
            итог.setdefault(опыт, строка.strip()[:120])
    return итог


def вид_заморозки(текст: str) -> str:
    """Вид заморозки по её собственному тексту.

    Порядок проверок не случаен: сначала то, что подтверждается ССЫЛКОЙ (опыт,
    чужой вердикт, правило), потом то, что подтверждается датой, и лишь потом
    словесные виды. Иначе заморозка «ждёт приёмки канарейки T317 до 28.10»
    попала бы в «дата_оценки» и потеряла бы проверяемую ссылку.
    """
    низ = текст.lower()
    if re.findall(r"exp-[\w-]+", текст):
        return "опыт"
    if re.search(ОБРАЗЕЦ_ЧУЖОГО, текст) and any(с in низ for с in СЛОВА_ЧУЖОГО):
        return "чужой_вердикт"
    if any(д in текст for д in ДОКУМЕНТЫ_ПРАВИЛ):
        return "правило"
    if any(с in низ for с in СЛОВА_ОГРАНИЧЕНИЯ):
        return "внешнее_ограничение"
    if _даты(текст, _dt.date.today().year):
        return "дата_оценки"
    if any(с.lower() in низ for с in СЛОВА_ВЛАДЕЛЬЦА):
        return "вход_владельца"
    return "не определён"


def проверить(текст: str, *, реестр: set[str], журнал: dict[str, str],
              сегодня: _dt.date) -> tuple[bool, str, str]:
    вид = вид_заморозки(текст)
    if вид == "опыт":
        опыты = re.findall(r"exp-[\w-]+", текст)
        в_реестре = [о for о in опыты if о in реестр]
        в_журнале = [о for о in опыты if о in журнал]
        if в_реестре:
            return True, вид, f"опыт в реестре: {', '.join(sorted(set(в_реестре)))}"
        if в_журнале:
            return True, вид, f"опыт в журнале изменений: {', '.join(sorted(set(в_журнале)))}"
        даты = _даты(текст, сегодня.year)
        если_будущая = [д for д in даты if д >= сегодня]
        хвост = (f"; дата оценки {min(если_будущая).isoformat()} названа"
                 if если_будущая else "; даты оценки тоже нет")
        return False, вид, (f"опыт(ы) {', '.join(sorted(set(опыты)))} не найдены ни в "
                            f"реестре, ни в журнале{хвост}")
    if вид == "правило":
        назван = [д for д in ДОКУМЕНТЫ_ПРАВИЛ if д in текст]
        return True, вид, f"правило названо: {', '.join(назван)}"
    if вид == "дата_оценки":
        даты = _даты(текст, сегодня.year)
        будущие = [д for д in даты if д >= сегодня]
        if будущие:
            return True, вид, f"ждёт оценки {min(будущие).isoformat()}"
        return False, вид, (f"дата оценки {max(даты).isoformat()} прошла — "
                            "заморозка держится без срока")
    if вид == "чужой_вердикт":
        метки = re.findall(ОБРАЗЕЦ_ЧУЖОГО, текст)
        домены = re.findall(r"\b[a-z0-9][a-z0-9.-]*\.[a-z]{2,}\b", текст)
        if метки and домены:
            return True, вид, (f"ждёт вердикта {', '.join(sorted(set(метки)))} "
                               f"на {домены[0]} — проверяемо у той линии")
        return False, вид, (f"назван вердикт {метки or 'без метки'}, но домен, где он "
                            "идёт, не назван: проверить не у кого")
    if вид == "внешнее_ограничение":
        назван = [с for с in СЛОВА_ОГРАНИЧЕНИЯ if с in текст.lower()]
        return True, вид, f"ограничение названо: {назван[0]}"
    if вид == "вход_владельца":
        return True, вид, "названо ожидание входа владельца"
    return False, вид, "ни опыта, ни даты, ни правила, ни входа владельца"


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--ledger", type=pathlib.Path, help="журнал изменений линии SEO")
    р.add_argument("--queues", type=pathlib.Path, default=ОЧЕРЕДИ)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    реестр = опыты_реестра()
    журнал = опыты_журнала(а.ledger)
    сегодня = _dt.date.today()
    записи = []
    for файл in sorted(а.queues.glob("*.json")):
        данные = json.loads(файл.read_text(encoding="utf-8"))
        for з in данные.get("tasks") or []:
            текст = str(з.get("blocked_by") or "")
            if not текст:
                continue
            ладно, вид, почему = проверить(текст, реестр=реестр, журнал=журнал,
                                           сегодня=сегодня)
            записи.append({"домен": данные.get("domain") or файл.stem,
                           "задача": з.get("id"), "вид": вид,
                           "подтверждена": ладно, "почему": почему,
                           "текст": текст[:160]})

    по_виду: dict[str, list[dict]] = {}
    for з in записи:
        по_виду.setdefault(з["вид"], []).append(з)
    неподтверждённые = [з for з in записи if not з["подтверждена"]]

    if а.json:
        print(json.dumps({"журнал": str(а.ledger) if а.ledger else None,
                          "журнал_прочитан": bool(журнал),
                          "опытов_в_реестре": len(реестр),
                          "заморозок": len(записи),
                          "неподтверждённых": len(неподтверждённые),
                          "записи": записи}, ensure_ascii=False, indent=1))
        return 0 if not неподтверждённые else 3

    print(f"опытов в реестре: {len(реестр)}")
    print("журнал изменений: " + (f"{а.ledger} — опытов в нём {len(журнал)}" if журнал
                                 else "не передан или отсутствует (это причина, а не провал)"))
    print(f"заморозок в очередях: {len(записи)}")
    for вид, набор in sorted(по_виду.items(), key=lambda п: -len(п[1])):
        плохо = sum(1 for з in набор if not з["подтверждена"])
        print(f"   {вид:16} {len(набор):>4}  не подтверждено {плохо}")
    if неподтверждённые:
        print(f"\nНЕ ПОДТВЕРЖДЕНЫ ({len(неподтверждённые)}). Заморозка НЕ снимается:")
        for з in неподтверждённые[:20]:
            print(f"   {з['домен']:22} {з['задача'] or '?':28} {з['вид']:14} {з['почему'][:90]}")
    return 0 if not неподтверждённые else 3


if __name__ == "__main__":
    raise SystemExit(главная())
