#!/usr/bin/env python3
"""Переходы к сериям и расписание на публичном сайте. Только чтение.

    python3 automation/local/episode-nav-check.py <домен> [<домен> …]

Проверяет то, что названо в задании владельца, и ничего не меняет:

  карточка сериала   на странице есть ссылки на серии
  переход к серии    первая и средняя ссылка отвечают 200
  плеер на серии     разметка плеера смонтирована именно на странице серии
  номер в заголовке  страница серии называет тот номер, который в адресе
  расписание         раздел отвечает и несёт даты, а не пустую сетку

Сериал выбирается из публичной карты сайта — то есть из того, что витрина сама
объявила к обходу, а не из придуманного адреса.
"""
from __future__ import annotations

import re
import subprocess
import sys



def номер(путь: str) -> tuple[int, int]:
    """Сезон и серия из адреса. Непонятный адрес — (0, 0), а не отказ."""
    м = re.search(r"season-(\d+)/episode-(\d+)/$", путь)
    return (int(м.group(1)), int(м.group(2))) if м else (0, 0)


def выбрать(серии: list[str]) -> tuple[list[str], list[str]]:
    """Какие серии проверять и какие из них нулевые.

    Сортировка по НОМЕРУ, а не по порядку в разметке. Порядок в разметке —
    свойство оформления: на витрине, перечисляющей серии от новых к старым,
    `серии[0]` это последняя серия, и первая не проверялась бы никогда.

    Нулевая серия проверяется ОТДЕЛЬНО. Владелец называл повторяющийся дефект
    «доступность эпизодов считается по счётчику, серия 0 теряется», а выборка
    первая-средняя-последняя её не задевает, если список начинается с единицы —
    то есть почти всегда. Отсюда и второй возвращаемый список: когда он пуст,
    прогон обязан сказать «не измерено», а не промолчать.
    """
    по_номеру = sorted(серии, key=номер)
    выборка = [по_номеру[0], по_номеру[len(по_номеру) // 2], по_номеру[-1]]
    нулевые = [п for п in по_номеру if номер(п)[1] == 0]
    for путь in нулевые:
        if путь not in выборка:
            выборка.append(путь)
    # Повторы убираются с сохранением порядка: у короткого списка первая и
    # средняя серия совпадают, и страница тянулась бы дважды.
    return list(dict.fromkeys(выборка)), нулевые

def достать(url: str, таймаут: int = 60) -> tuple[str, str]:
    г = subprocess.run(["curl", "-sS", "-L", "-w", "\n%{http_code}",
                        "--max-time", str(таймаут), url],
                       capture_output=True, text=True)
    т = г.stdout or ""
    код = т.rsplit("\n", 1)[-1]
    тело = т[: т.rfind("\n")] if "\n" in т else т
    return код, тело


def карточки_из_карты(домен: str, сколько: int = 40) -> list[str]:
    _, индекс = достать(f"https://{домен}/sitemap.xml")
    части = re.findall(r"<loc>([^<]+)</loc>", индекс)
    if not части:
        return []
    _, часть = достать(части[0], 180)
    адреса = re.findall(r"<loc>([^<]+)</loc>", часть)
    карточки = [а for а in адреса if "/title/" in а or "/anime/" in а]
    шаг = max(1, len(карточки) // сколько)
    return карточки[::шаг][:сколько]


def проверить(домен: str) -> int:
    print(f"=== {домен}")
    беды = 0
    сериал = ""
    серии: list[str] = []
    for адрес in карточки_из_карты(домен):
        код, тело = достать(адрес)
        if код != "200":
            continue
        найдено = re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+/season-\d+/episode-\d+/)"',
                             тело)
        if len(найдено) >= 3:
            сериал, серии = адрес, list(dict.fromkeys(найдено))
            break
    if not серии:
        print("   ПРОПУСК: в выборке карты не нашлось карточки со ссылками на серии")
        return 0
    print(f"   сериал {сериал.rstrip('/').rsplit('/', 1)[-1]}: ссылок на серии {len(серии)}")

    выборка, нулевые = выбрать(серии)
    for путь in выборка:
        код, тело = достать(f"https://{домен}{путь}")
        плеер = "data-player-state" in тело or "video-player" in тело
        номер = re.search(r"episode-(\d+)/$", путь)
        в_тексте = bool(номер) and (номер.group(1) in re.sub(r"<[^>]+>", " ", тело))
        ок = код == "200" and плеер and в_тексте
        беды += int(not ок)
        print(f"   {'ок ' if ок else 'НЕТ'} {путь}: код {код}, плеер {плеер}, "
              f"номер в тексте {в_тексте}")
    if not нулевые:
        print("   [не измерено] нулевой серии нет ни у этой карточки — "
              "про дефект «серия 0 теряется» прогон ничего не говорит")
    код, тело = достать(f"https://{домен}/schedule/")
    if код == "200":
        даты = len(re.findall(r"\d{2}\.\d{2}\.\d{4}|\d{4}-\d{2}-\d{2}", тело))
        строки = len(re.findall(r'href="/(?:title|anime)/', тело))
        ок = даты > 0 or строки > 0
        беды += int(not ок)
        print(f"   {'ок ' if ок else 'НЕТ'} /schedule/: код 200, дат {даты}, "
              f"ссылок на произведения {строки}")
    else:
        print(f"   расписание: код {код} — раздела у витрины нет, не проверяется")
    return беды


def главная(argv: list[str]) -> int:
    домены = argv[1:]
    if not домены:
        print(__doc__)
        return 2
    всего = sum(проверить(д) for д in домены)
    print(f"\nдоменов {len(домены)}, расхождений {всего}")
    return 1 if всего else 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv))
