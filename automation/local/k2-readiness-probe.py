#!/usr/bin/env python3
"""Готовность восьми новых витрин K2 к развитию: по признакам, а не по ощущению.

Задание требует по каждому домену отдельно: доступность HTTPS, работоспособность
приложения и плеера, свежесть каталога, наличие постеров, состояние
robots/canonical/sitemap, установлен ли счётчик и поступают ли данные, разрешено
ли продвижение. Здесь измеряется всё, кроме двух последних: поступление данных
счётчика читается только из Метрики, а доступ к ней из сессии закрыт
(`BLOCKED_SECRET`), и решение о продвижении — запись владельца, а не замер.

Что считается признаком, и почему именно это:

* **главная** — код ответа и число ссылок на карточки. Код 200 без карточек
  приложением не считается: это пустая страница;
* **карточка** — берётся со главной, проверяется код, `h1`, наличие разметки
  плеера и ссылки на серию. Наличие `iframe` проверкой воспроизведения НЕ
  считается, и в выводе это сказано прямо;
* **постеры** — доля карточек главной, у которых есть адрес изображения. Буква-
  заглушка постером не считается;
* **свежесть каталога** — время сборки доставленного снимка, прочитанное на
  узле. Это не «когда обновляли витрину», а «какого поколения её данные»;
* **индексация** — сигналы запрета. Для закрытой витрины запрет ОЖИДАЕМ, и
  находкой он не является: HTTPS не разрешение открыть индексацию.

    python3 automation/local/k2-readiness-probe.py
    python3 automation/local/k2-readiness-probe.py --json
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys

ВИТРИНЫ = {
    "lordfilm.group": "lords-10",
    "lordfilm.spb.ru": "lords-11",
    "lordfilm.msk.ru": "lords-12",
    "lordserial.su": "lords-13",
    "lordserial.group": "lords-14",
    "lordserial.spb.ru": "lords-15",
    "lordserial.msk.ru": "lords-16",
    "lordserial.net.ru": "lords-17",
}
РЕЕСТР = pathlib.Path("/home/claude/wt-nova-publish-memory-02/config/site-cells.json")


def достать(адрес: str, таймаут: int = 40) -> tuple[int, str]:
    try:
        г = subprocess.run(["curl", "-sSL", "-w", "\n@@КОД@@%{http_code}",
                            "--max-time", str(таймаут), адрес],
                           capture_output=True, text=True, timeout=таймаут + 20)
    except subprocess.TimeoutExpired:
        return 0, ""
    тело, _, код = г.stdout.rpartition("@@КОД@@")
    try:
        return int(код.strip()), тело
    except ValueError:
        return 0, тело


def реестр() -> dict:
    d = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    return {я.get("domain"): я for я in d.get("cells") or []}


def свежесть(ячейка: dict) -> str:
    """Поколение доставленных данных: время сборки снимка каталога на узле."""
    # Путь данных лежит в `runtime.data_dir`, а не в `data`: в `data` реестр
    # держит базу и медиа, и первая редакция этой проверки читала не то поле —
    # печатала «каталог данных не назван» у всех восьми витрин подряд.
    данные = (ячейка.get("runtime") or {}).get("data_dir") or ""
    if not данные:
        return "каталог данных не назван в реестре"
    корень = pathlib.Path(данные)
    if not корень.is_dir():
        цель = (ячейка.get("deploy_target") or {}).get("ref") or ""
        if цель and цель != "local":
            # Витрина живёт на другом узле. «Каталога нет» здесь означало бы,
            # что данных нет вовсе, а означает только то, что отсюда их не
            # видно: это предел измерения, а не дефект витрины.
            return (f"узел {цель}: свежесть данных отсюда НЕ ИЗМЕРЯЕТСЯ"
                    f" (каталог {корень} локально отсутствует)")
        return f"каталога данных нет: {корень}"
    снимки = sorted(корень.glob("*-catalog.json"))
    if not снимки:
        return "снимка каталога нет"
    снимок = снимки[0]
    try:
        d = json.loads(снимок.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return f"снимок не прочитан: {снимок.name}"
    когда = d.get("builtAt") or d.get("built_at") or ""
    сколько = len(d.get("items") or d.get("records") or [])
    return f"{сколько} записей, собран {когда or 'без метки времени'}"


def проверить(домен: str, ячейки: dict) -> dict:
    итог: dict = {"домен": домен, "site_id": ВИТРИНЫ[домен], "замечания": []}
    код, тело = достать(f"https://{домен}/")
    итог["главная_код"] = код
    карточки = sorted(set(re.findall(r'href="(/title/[^"#?]+/)"', тело)))
    итог["карточек_на_главной"] = len(карточки)
    if код != 200:
        итог["замечания"].append(f"главная отвечает {код}")
    elif not карточки:
        итог["замечания"].append("главная отвечает 200, но карточек нет")
    постеров = len(re.findall(r'<img[^>]+src="(?:https?:)?//[^"]+"', тело))
    итог["изображений_на_главной"] = постеров
    if карточки and постеров == 0:
        итог["замечания"].append("на главной нет ни одного изображения")

    итог["robots"] = (re.search(r'name="robots" content="([^"]*)"', тело)
                      or [None, "—"])[1] if 'name="robots"' in тело else "—"
    кан = re.search(r'rel="canonical" href="([^"]*)"', тело)
    итог["canonical"] = кан.group(1) if кан else "—"

    if карточки:
        путь = карточки[0]
        к2, т2 = достать(f"https://{домен}{путь}")
        итог["карточка"] = путь
        итог["карточка_код"] = к2
        h1 = re.search(r"<h1[^>]*>(.*?)</h1>", т2, re.S)
        итог["карточка_h1"] = (re.sub(r"<[^>]+>", "", h1.group(1)).strip()[:40]
                              if h1 else "")
        итог["плеер_разметка"] = bool(re.search(r"iframe|video-player|player", т2))
        итог["ссылок_на_серии"] = len(set(re.findall(
            re.escape(путь.rstrip("/")) + r"/season-\d+/episode-\d+", т2)))
        if к2 != 200:
            итог["замечания"].append(f"страница произведения отвечает {к2}")
        elif not итог["карточка_h1"]:
            итог["замечания"].append("на странице произведения нет h1")
    ячейка = ячейки.get(домен) or {}
    итог["статус_в_реестре"] = ячейка.get("status", "нет в реестре")
    итог["индексация_в_реестре"] = (ячейка.get("indexing") or {}).get("mode", "—")
    итог["свежесть_данных"] = свежесть(ячейка)
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    ячейки = реестр()
    итоги = [проверить(д, ячейки) for д in ВИТРИНЫ]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
        return 0
    for и in итоги:
        метка = "НЕТ" if и["замечания"] else "ок "
        print(f"[{метка}] {и['домен']:20} {и['site_id']:9}"
              f" главная {и['главная_код']} карточек {и['карточек_на_главной']:>3}"
              f" изображений {и['изображений_на_главной']:>3}"
              f" | карточка {и.get('карточка_код', '—')}"
              f" h1 {'есть' if и.get('карточка_h1') else 'нет'}"
              f" плеер {'есть' if и.get('плеер_разметка') else 'нет'}"
              f" серий {и.get('ссылок_на_серии', '—')}")
        print(f"       реестр: {и['статус_в_реестре']},"
              f" индексация {и['индексация_в_реестре']};"
              f" данные: {и['свежесть_данных']}")
        for з in и["замечания"]:
            print(f"       → {з}")
    плохих = [и["домен"] for и in итоги if и["замечания"]]
    print(f"\nвитрин проверено {len(итоги)}, с замечаниями {len(плохих)}")
    print("наличие разметки плеера воспроизведением НЕ является; поступление"
          " данных счётчика здесь не измеряется (доступ к Метрике из сессии"
          " закрыт), и разрешение на продвижение — запись владельца, а не замер")
    return 1 if плохих else 0


if __name__ == "__main__":
    sys.exit(main())
