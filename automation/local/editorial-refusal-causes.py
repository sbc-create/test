#!/usr/bin/env python3
"""Почему редактор отказался: причины со знаменателем, а не исходы.

Зачем отдельно от `editor-throughput.py`. Тот отвечает, СКОЛЬКО заданий
закончилось пусто (76 % за 6 часов 25.10). Он не отвечает, ПОЧЕМУ — а решение
владельца по MOD-168 («повторять ли задание без изменения условий») зависит
именно от этого: если у источника нет описания, повтор через сутки ничего не
изменит; если отказ из-за строгости сверки названий, повтор тоже не поможет, но
лечится иначе.

Что считается причиной. Очередь пишет причину в `detail` свободным текстом,
поэтому здесь ОБРАЗЦЫ, а не разбор смысла, и доля неразобранных печатается
отдельной строкой. Правило: лучше честная строка «причина не разобрана», чем
правдоподобная раскладка, в которой половина случаев отнесена наугад.

ЛОВУШКА, УЖЕ СРАБОТАВШАЯ. Первый мой подсчёт 25.10 отнёс 47 отказов к
«русское название расходится», потому что образец искал слово «russian». В
действительности в этих деталях сказано «russian «…» СОВПАЛ», а отказ был по
пустому описанию: подлинных расхождений названия за те же 7 суток — 6.
Поэтому признак совпадения проверяется ПЕРЕД признаком расхождения, и на это
есть прямая проверка в тестах.

    python3 automation/local/editorial-refusal-causes.py --days 7
    python3 automation/local/editorial-refusal-causes.py --days 1 --outcome SOURCES_MISSING
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import sys
from collections import Counter, defaultdict

АРЕНДЫ = pathlib.Path("/var/lib/seo-content-operator/editorial_leases.json")
ПУСТЫЕ = ("SOURCES_MISSING", "PAGE_ABSENT", "IDENTITY_UNCLEAR",
          "IDENTITY_REJECTED", "SOURCE_UNAVAILABLE", "DELIVERY_UNSUPPORTED")
#: Порядок ВАЖЕН: признак совпадения названия проверяется раньше признака
#: расхождения, иначе «russian «…» совпал» попадает в расхождения (моя ошибка
#: 25.10, см. описание модуля).
ПРИЗНАКИ: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("страница витрины не отдалась", ("страница не отдалась", "страницы нет",
                                      "PAGE_ABSENT", "404 на странице",
                                      "HTTP 404", "отдала HTTP",
                                      "отвечала HTTP")),
    ("у источника нет описания", ("description null", "description=null",
                                  "описания нет", "описание отсутствует")),
    ("описание есть, но завязки в нём нет", ("завязки нет", "Завязки нет",
                                             "нет завязки", "пересказ другого",
                                             "рекламный абзац",
                                             "формат выпуска")),
    ("название источника совпало, отказ по другой причине", ("совпа",)),
    ("внешнего идентификатора нет, искать запрещено",
     ("внешнего идентификатора", "ID пуст", "ID не числовой",
      "поиск ID запрещён")),
    ("статьи с этим IMDb ID нет", ("статьи Википедии с IMDb", "статьи с IMDb")),
    ("русское название расходится с названием страницы",
     ("название страницы", "≠ название", "расходится", "тождество не доказано")),
    ("доставка описания не поддержана", ("DELIVERY_UNSUPPORTED",
                                         "возможность", "не поддерж")),
    ("источник не ответил", ("источник не ответил", "таймаут", "HTTP 5")),
)
#: Пометка круга: очередь сама её пишет, и она НЕ причина отказа.
КРУГ = ("без изменения условий", "не менялся", "не менялись")


def аренды(путь: pathlib.Path = АРЕНДЫ) -> list[dict]:
    д = json.loads(путь.read_text(encoding="utf-8"))
    зп = д.get("leases") or д
    зп = list(зп.values()) if isinstance(зп, dict) else зп
    return [з for з in (зп or []) if isinstance(з, dict)]


def причина(detail: str, outcome: str = "") -> tuple[str, str]:
    """Пара (имя причины, откуда взята): «деталь», «исход» или «нет».

    Первое совпадение по порядку ПРИЗНАКИ. Порядок — часть правила, а не
    удобство: признак совпадения названия стоит раньше признака расхождения.

    Если деталь причины не называет — а при повторной выдаче очередь
    записывает в неё только пометку круга, и так в 198 шагах из 1 652 за 7
    суток — причина берётся из ИСХОДА задания, и это помечено. Молча выдавать
    исход за названную причину нельзя: тогда «главная причина» означала бы
    «самый частый исход», то есть ничего нового.
    """
    т = detail or ""
    for имя, образцы in ПРИЗНАКИ:
        if any(о in т for о in образцы):
            return имя, "деталь"
    if outcome:
        return f"причина не названа в детали; исход {outcome}", "исход"
    return "причина не разобрана", "нет"


def по_кругу(detail: str) -> bool:
    return any(п in (detail or "") for п in КРУГ)


def шаги(записи: list[dict], с: dt.datetime, исходы: tuple[str, ...]
         ) -> list[tuple[dict, dict]]:
    из = []
    for з in записи:
        for ш in (з.get("history") or []):
            м = str(ш.get("at") or "")
            if not м:
                continue
            try:
                т = dt.datetime.fromisoformat(м.replace("Z", "+00:00"))
            except ValueError:
                continue
            if т >= с and (not исходы or ш.get("outcome") in исходы):
                из.append((з, ш))
    return из


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--days", type=float, default=7.0)
    р.add_argument("--outcome", action="append", default=[],
                   help="только эти исходы; по умолчанию все пустые")
    р.add_argument("--leases", type=pathlib.Path, default=АРЕНДЫ)
    р.add_argument("--json", type=pathlib.Path)
    р.add_argument("--max-unparsed-share", type=float, default=0.25)
    а = р.parse_args(аргв)
    if not а.leases.is_file():
        print(f"журнала аренд нет: {а.leases} — НЕ ИЗМЕРЕНО", file=sys.stderr)
        return 2
    исходы = tuple(а.outcome) or ПУСТЫЕ
    с = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=а.days)
    пары = шаги(аренды(а.leases), с, исходы)
    if not пары:
        print(f"за последние {а.days:g} сут шагов с исходами {исходы} нет")
        return 0

    счёт = Counter()
    работы = defaultdict(set)
    круг = Counter()
    откуда = Counter()
    примеры: dict[str, str] = {}
    for з, ш in пары:
        d = str(ш.get("detail") or "")
        к, источник = причина(d, str(ш.get("outcome") or ""))
        откуда[источник] += 1
        счёт[к] += 1
        работы[к].add((з.get("site"), з.get("work_id") or з.get("content_id")))
        if по_кругу(d):
            круг[к] += 1
        примеры.setdefault(к, f"{з.get('site')} / "
                              f"{з.get('work_id') or з.get('content_id')}")

    всего = sum(счёт.values())
    print(f"окно: последние {а.days:g} сут, исходы: {', '.join(исходы)}")
    print(f"шагов отказа {всего}; различных произведений"
          f" {len({w for г in работы.values() for w in г})}")
    print()
    print(f"{'причина':52} {'шагов':>6} {'доля':>7} {'работ':>6} {'из них по кругу':>16}")
    for к, n in счёт.most_common():
        print(f"{к[:52]:52} {n:6} {n/всего:6.1%} {len(работы[к]):6}"
              f" {круг[к]:16}")
    из_исхода = откуда["исход"]
    доля = из_исхода / всего if всего else 0.0
    print()
    print(f"повторов без изменения условий: {sum(круг.values())}"
          f" ({sum(круг.values())/всего:.1%} шагов отказа)")
    print(f"причина НАЗВАНА в детали: {откуда['деталь']}"
          f" ({откуда['деталь']/всего:.1%})")
    print(f"причина взята из исхода, деталь её не повторяет: {из_исхода}"
          f" ({доля:.1%})")
    if примеры:
        print()
        print("по одному примеру на причину:")
        for к, _ in счёт.most_common():
            print(f"   {к[:52]:52} {примеры[к]}")
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        а.json.write_text(json.dumps(
            {"окно_сут": а.days, "исходы": list(исходы), "шагов": всего,
             "причины": {к: {"шагов": n, "работ": len(работы[к]),
                             "по_кругу": круг[к]} for к, n in счёт.items()}},
            ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"\nподробности: {а.json}")
    по_детали = [(к, n) for к, n in счёт.most_common()
                 if not к.startswith("причина не названа")]
    if доля > а.max_unparsed_share:
        print()
        print(f"ВЫВОД: у {доля:.0%} шагов отказа деталь не повторяет причину"
              f" (порог {а.max_unparsed_share:.0%}) — это свойство ЖУРНАЛА, а"
              " не измерения: при повторной выдаче очередь пишет в деталь"
              " только пометку круга, и первопричина остаётся лишь в первом"
              " отказе.")
        if по_детали:
            к, n = по_детали[0]
            названо = sum(x for _, x in по_детали)
            print(f"   среди названных причин главная — {к}:"
                  f" {n} из {названо} ({n/названо:.0%}),"
                  f" {len(работы[к])} произведений")
        return 1
    print()
    главная, сколько = счёт.most_common(1)[0]
    print(f"ВЫВОД: главная причина отказов — {главная}:"
          f" {сколько} из {всего} шагов ({сколько/всего:.0%}),"
          f" {len(работы[главная])} произведений")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
