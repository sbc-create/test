#!/usr/bin/env python3
"""Что делать СЕЙЧАС: выбор работы по порядку из правил сети. Только чтение.

Порядок задан заданием владельца и не обсуждается каждый раз:

1. срочные ПОДТВЕРЖДЁННЫЕ ошибки (открытые P0 по доменам);
2. приоритетные задачи домéнов из их очередей;
3. проверка опубликованного (задачи с наступившим сроком `verify_by`);
4. конкурентное исследование и обучение по конкретным пробелам.

ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. «Нет доступной задачи» и «все задачи ждут» —
разные состояния, и их путали: заблокированная очередь выглядела как пустая, и
работа останавливалась вместо перехода к другому домену. Здесь они различаются
и печатаются раздельно, а обучение предлагается ТОЛЬКО когда доступной работы
по доменам нет вовсе.

Обучение уступает всему остальному: это требование задания, а не настройка.

    python3 automation/local/pick-work.py
    python3 automation/local/pick-work.py --json

Коды: 0 — есть что делать; 1 — доступной работы по доменам нет, предложено
обучение; 2 — нет ни работы, ни обучения.
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
СПИСОК = КОРЕНЬ / "config" / "active-domains.json"
НЕДОСТАТКИ = КОРЕНЬ / "config" / "seo-module-defects.json"
ОБУЧЕНИЕ = КОРЕНЬ / "config" / "learning-queue.json"

РАБОЧИЕ = ("исследовано", "подготовлено", "проверено")
ЖДУЩИЕ = ("ожидание", "заблокировано")


def сегодня() -> str:
    return datetime.date.today().isoformat()


def очереди() -> list[dict]:
    д = json.loads(СПИСОК.read_text(encoding="utf-8"))
    итог = []
    for з in д["domains"]:
        п = КОРЕНЬ / з["queue"]
        if п.is_file():
            итог.append(json.loads(п.read_text(encoding="utf-8")))
    return итог


#: Имя этой линии. Берётся из каталога рабочего дерева — то же значение
#: очереди пишут в поле `owner`, поэтому сравнение честное, а не по догадке.
ЭТА_ЛИНИЯ = КОРЕНЬ.name


def своя(задача: dict) -> bool:
    """Моя ли это задача. Пустой `owner` считается СВОИМ, а не чужим.

    Умолчание в эту сторону намеренно: задача без владельца должна попадать в
    работу, а не выпадать из неё. Потерять задачу дороже, чем лишний раз её
    предложить.
    """
    в = str(задача.get("owner") or "").strip()
    return not в or в == ЭТА_ЛИНИЯ


def чужие(оч: list[dict]) -> list[tuple[str, dict]]:
    """Рабочие задачи, которые ведёт другая линия. Печатаются отдельно.

    Это НЕ ожидание и НЕ пустая очередь: работа по ним идёт, просто не здесь.
    Скрывать их молча нельзя — так они пропадут из виду вместе с доменом.
    """
    return [(о["domain"], з) for о in оч for з in (о.get("tasks") or [])
            if з["state"] in РАБОЧИЕ and not своя(з)]


def срочность(задача: dict, по_id: dict) -> int:
    """Вес задачи: меньше — срочнее. Чистая функция."""
    н = по_id.get(задача.get("defect") or "")
    уровень = (н or {}).get("priority")
    return {"P0": 0, "P1": 1, "P2": 2, "P3": 3}.get(уровень, 4)


def доступные(оч: list[dict], по_id: dict) -> list[tuple[int, str, dict]]:
    итог = []
    for о in оч:
        for з in о.get("tasks") or []:
            if з["state"] in РАБОЧИЕ and своя(з):
                итог.append((срочность(з, по_id), о["domain"], з))
    return sorted(итог, key=lambda т: (т[0], т[1]))


def ждущие(оч: list[dict]) -> list[tuple[str, dict]]:
    return [(о["domain"], з) for о in оч for з in (о.get("tasks") or [])
            if з["state"] in ЖДУЩИЕ]


def пора_проверять(оч: list[dict]) -> list[tuple[str, dict]]:
    """Опубликованное, у которого наступил срок проверки эффекта."""
    д = сегодня()
    итог = []
    for о in оч:
        for з in о.get("tasks") or []:
            срок = str(з.get("verify_by") or "")
            if з["state"] == "опубликовано" and срок[:10] and срок[:10] <= д:
                итог.append((о["domain"], з))
    return итог


def обучение() -> list[dict]:
    if not ОБУЧЕНИЕ.is_file():
        return []
    д = json.loads(ОБУЧЕНИЕ.read_text(encoding="utf-8"))
    return [з for з in (д.get("items") or []) if з.get("state") == "в очереди"]


def выбрать() -> dict:
    оч = очереди()
    реестр = json.loads(НЕДОСТАТКИ.read_text(encoding="utf-8"))["defects"]
    по_id = {з["id"]: з for з in реестр}
    дост = доступные(оч, по_id)
    пров = пора_проверять(оч)
    ждут = ждущие(оч)
    чуж = чужие(оч)
    уч = обучение()

    итог = {
        "домéнов": len(оч),
        "доступных_задач": len(дост),
        "ждущих_задач": len(ждут),
        "ведёт_другая_линия": [(д, з["id"], з.get("owner"))
                               for д, з in чуж],
        "пора_проверять": [(д, з["id"]) for д, з in пров],
        "учебных_в_очереди": len(уч),
    }
    if дост:
        вес, домен, з = дост[0]
        итог["что_делать"] = "задача домена"
        итог["выбор"] = {"домен": домен, "задача": з["id"],
                         "название": з["title"][:120],
                         "срочность": ["P0", "P1", "P2", "P3", "без уровня"][вес],
                         "состояние": з["state"]}
        итог["почему"] = ("самая срочная доступная задача по порядку"
                          " из правил сети, §6")
        return итог
    if пров:
        домен, з = пров[0]
        итог["что_делать"] = "проверка опубликованного"
        итог["выбор"] = {"домен": домен, "задача": з["id"],
                         "срок": з.get("verify_by")}
        итог["почему"] = "срок проверки эффекта наступил"
        return итог
    if уч:
        итог["что_делать"] = "учебный блок"
        итог["выбор"] = {"id": уч[0]["id"], "вопрос": уч[0]["question"][:160],
                         "направление": уч[0]["direction"]}
        итог["почему"] = ("доступных задач по домéнам нет"
                          f"; ждут {len(ждут)} — обучение уступает им, но"
                          " ожидание работой не является")
        return итог
    итог["что_делать"] = "нет работы"
    итог["почему"] = ("ни доступных задач, ни учебных блоков: это НЕ простой"
                      " по ресурсам, а пустая очередь — её надо наполнить"
                      " задачами этапа 2 и 3")
    if чуж:
        итог["почему"] += (
            f"; отдельно: {len(чуж)} рабочих задач ведёт ДРУГАЯ линия —"
            " это не моя доступная работа и не ожидание, по ним работа идёт"
            " не здесь")
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    и = выбрать()
    if а.json:
        print(json.dumps(и, ensure_ascii=False, indent=1))
    else:
        print(f"что делать: {и['что_делать'].upper()}")
        print(f"   {json.dumps(и.get('выбор', {}), ensure_ascii=False)}")
        print(f"   почему: {и['почему']}")
        print(f"   домéнов {и['домéнов']}, доступных задач"
              f" {и['доступных_задач']}, ждущих {и['ждущих_задач']},"
              f" учебных в очереди {и['учебных_в_очереди']}")
        if и["ведёт_другая_линия"]:
            print(f"   ведёт другая линия: {len(и['ведёт_другая_линия'])} —"
                  " в мою доступную работу они не входят, но и не потеряны:")
            for домен, ид, кто in и["ведёт_другая_линия"]:
                print(f"      {домен}/{ид} → {кто or 'владелец не назван'}")
        if и["пора_проверять"]:
            print(f"   пора проверять эффект: "
                  f"{', '.join(д + '/' + з for д, з in и['пора_проверять'])}")
    if и["что_делать"] == "нет работы":
        return 2
    return 1 if и["что_делать"] == "учебный блок" else 0


if __name__ == "__main__":
    sys.exit(main())
