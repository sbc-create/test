#!/usr/bin/env python3
"""Следующая серия против доступных: замер по разметке, в настоящем браузере.

Зачем браузер. Критерий MOD-29 назван прямо: «проверяется по разметке карточки,
БЕЗ разбора текста» — то есть по атрибуту `data-next-episode`. В серверном HTML
этого атрибута нет: он появляется при исполнении страницы. Попытка 25.10
обойтись `curl` и разбором текста дала у шести карточек одно и то же «следующая:
71» — образец зацепил постороннее число, и «противоречий 0» по такому разбору
было бы ложью. Поэтому здесь Playwright и чтение АТРИБУТА.

Что читается и откуда:

* следующая серия — атрибут `data-next-episode` (узел `p.ag-next` на витринах
  семейства AnimeGo; селектор по атрибуту, а не по классу);
* доступно серий — ячейка списка фактов `dl`. У семейств она названа
  по-разному, и обе формы читаются как есть, без догадок:
  `<dt>Эпизоды</dt><dd>12 серий, доступно 4</dd>` (AnimeGo) и
  `<dt>Доступно серий</dt><dd>4</dd>` (Animedia). Разбор ограничен ОДНОЙ
  ячейкой разметки; по всей странице числа не ищутся.

Четыре исхода, и ни один не выдаётся за другой:

  согласовано     следующая = доступные + 1
  опережает       следующая больше доступных более чем на одну серию
  противоречие    следующая НЕ больше доступных — названная серия уже вышла
  несопоставимо   сезонов больше одного: доступные считаются по всем сезонам,
                  а следующая нумеруется внутри сезона — числа разных шкал
  блока нет       атрибута на странице нет: расписание эфира неизвестно
  не измерено     страница не отдалась либо ячейки «Эпизоды» нет; причина названа

ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ ОБЯЗАТЕЛЕН. Контрольная страница заведомо содержит и
атрибут, и ячейку с «доступно». Если на ней разбор не сработал, замер НЕ
печатается и команда возвращает 2: иначе «противоречий 0» неотличимо от
сломанного селектора — ошибка, уже сделанная в этой записи дважды.

Вердикт печатается со знаменателем: сколько страниц проверено, у скольких блок
есть, и только по ним судится согласованность.

    python3 automation/local/next-episode-consistency.py --limit 12
    python3 automation/local/next-episode-consistency.py --domain animedia.icu
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ))

АГЕНТ = "factory-next-episode-consistency"
#: Витрины MOD-29: семейство аниме, где блок расписания вообще существует.
ВИТРИНЫ = ("animedia.icu", "animedia.space", "animeg0.site")
#: Страница, про которую известно, что на ней есть и атрибут, и «доступно».
КОНТРОЛЬ = "https://animeg0.site/title/fx-voin-kurumi/"
ОБРАЗЕЦ_ДОСТУПНО = re.compile(r"доступно\D{0,20}(\d+)", re.I)
ОБРАЗЕЦ_СЕЗОНОВ = re.compile(r"(\d+)\s*сезон", re.I)


def доступно_из_ячейки(текст: str) -> int | None:
    """Число доступных серий из ОДНОЙ ячейки разметки.

    Разбор ограничен ячейкой «Эпизоды» намеренно: поиск числа по всей
    странице уже дал однажды «71» вместо номера серии.
    """
    if not текст:
        return None
    м = ОБРАЗЕЦ_ДОСТУПНО.search(текст)
    return int(м.group(1)) if м else None


def сезонов_из_ячейки(текст: str) -> int | None:
    """Число сезонов из той же ячейки, если она его называет."""
    if not текст:
        return None
    м = ОБРАЗЕЦ_СЕЗОНОВ.search(текст)
    return int(м.group(1)) if м else None


def исход(следующая: int | None, доступно: int | None,
          сезонов: int | None = None) -> tuple[str, str]:
    """Исход и причина. Пара (исход, пояснение).

    Многосезонная карточка сравнению НЕ подлежит. Измерено 25.10 на
    `animeg0.site/title/blich-tysyacheletnyaya-krovavaya-voyna-bedstvie-2/`:
    ячейка говорит «4 сезона, 50 серий, доступно 49», а `data-next-episode`
    равен 10 — это номер внутри сезона, а не в сквозной нумерации. Прямое
    сравнение дало бы «серия 10 уже вышла», то есть ложное противоречие;
    такой вывод я уже готовилась записать.
    """
    if следующая is None:
        return "блока нет", "атрибута data-next-episode на странице нет"
    if доступно is None:
        return "не измерено", "ячейки «Эпизоды» с числом доступных серий нет"
    if (сезонов or 1) > 1:
        return "несопоставимо", (
            f"{сезонов} сезона: доступные ({доступно}) считаются по всем"
            f" сезонам, следующая ({следующая}) нумеруется внутри сезона")
    if следующая <= доступно:
        return "противоречие", (f"названа серия {следующая}, а доступно уже"
                                f" {доступно} — эта серия вышла")
    if следующая == доступно + 1:
        return "согласовано", f"следующая {следующая} = доступные {доступно} + 1"
    return "опережает", (f"следующая {следующая} при доступных {доступно}:"
                         " разрыв больше одной серии")


def контроль_пройден(замер: dict) -> bool:
    """Разбор сработал на заведомо пригодной странице.

    Оба числа обязательны: без атрибута не видно следующей серии, без ячейки
    «Эпизоды» не видно доступных, и в обоих случаях «противоречий 0» означало
    бы лишь то, что замер ничего не прочитал.
    """
    return замер.get("следующая") is not None and замер.get("доступно") is not None


def карточка(стр, url: str, таймаут: int = 60000) -> dict:
    """Один замер страницы произведения."""
    итог = {"url": url, "код": None, "следующая": None, "доступно": None,
            "исход": "не измерено", "почему": "", "заголовок": ""}
    try:
        ответ = стр.goto(url, wait_until="domcontentloaded", timeout=таймаут)
        итог["код"] = ответ.status if ответ else None
    except Exception as сбой:  # noqa: BLE001 — замер не падает, причина названа
        итог["почему"] = f"{type(сбой).__name__}: {сбой}"[:120]
        return итог
    if итог["код"] != 200:
        итог["почему"] = f"страница отдала {итог['код']}"
        return итог
    снято = стр.evaluate(r"""() => {
      const у = document.querySelector("[data-next-episode]");
      // Две формы одной и той же ячейки, обе настоящие:
      //   AnimeGo:  <dt>Эпизоды</dt><dd>12 серий, доступно 4</dd>
      //   Animedia: <dt>Доступно серий</dt><dd>4</dd>
      let ячейка = "";
      document.querySelectorAll("dl dt").forEach(dt => {
        if (ячейка) return;
        const метка = (dt.textContent || "").trim();
        const dd = dt.nextElementSibling;
        if (!dd || dd.tagName.toLowerCase() !== "dd") return;
        if (/эпизод/i.test(метка)) {
          ячейка = dd.textContent || "";
        } else if (/доступно\s+сери/i.test(метка)) {
          ячейка = метка + ": " + (dd.textContent || "");
        }
      });
      // Сезоны берутся и из разметки: у семейства animedia ячейка их не
      // называет, а сравнивать сквозное число с внутрисезонным нельзя.
      const метки = new Set();
      document.querySelectorAll("[data-season], [season]").forEach(э => {
        const в = э.getAttribute("data-season") || э.getAttribute("season");
        if (в) метки.add(в);
      });
      return {следующая: у ? у.getAttribute("data-next-episode") : null,
              ячейка, сезонов: метки.size || null,
              заголовок: (document.title || "").slice(0, 80)};
    }""")
    итог["заголовок"] = снято["заголовок"]
    сл = снято["следующая"]
    итог["следующая"] = int(сл) if (сл or "").strip().isdigit() else None
    итог["доступно"] = доступно_из_ячейки(снято["ячейка"])
    по_ячейке = сезонов_из_ячейки(снято["ячейка"])
    итог["сезонов"] = по_ячейке or снято.get("сезонов") or None
    итог["исход"], итог["почему"] = исход(итог["следующая"], итог["доступно"],
                                          итог["сезонов"])
    return итог


def слуги_с_главной(стр, домен: str, предел: int) -> list[str]:
    """Адреса карточек берутся С САМОЙ витрины, а не придумываются."""
    стр.goto(f"https://{домен}/", wait_until="domcontentloaded", timeout=60000)
    адреса = стр.evaluate("""() => Array.from(
        document.querySelectorAll("a[href*='/title/']"))
        .map(a => a.getAttribute("href")).filter(Boolean)""")
    итог, виденные = [], set()
    for а in адреса:
        if not а.startswith("/title/"):
            continue
        полный = f"https://{домен}{а if а.endswith('/') else а + '/'}"
        if полный in виденные:
            continue
        виденные.add(полный)
        итог.append(полный)
        if len(итог) >= предел:
            break
    return итог


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--limit", type=int, default=12, help="карточек на витрину")
    р.add_argument("--control", default=КОНТРОЛЬ)
    р.add_argument("--json", type=Path)
    а = р.parse_args(аргв)
    витрины = а.domain or list(ВИТРИНЫ)

    from playwright.sync_api import sync_playwright

    from factory.seo.render_check import chromium_path

    строки: list[dict] = []
    with sync_playwright() as p:
        браузер = p.chromium.launch(executable_path=chromium_path(),
                                    args=["--no-sandbox"])
        контекст = браузер.new_context(user_agent=АГЕНТ)
        контекст.route("**mc.yandex.*/**", lambda м: м.abort())
        стр = контекст.new_page()
        # контроль прежде замера
        к = карточка(стр, а.control)
        if not контроль_пройден(к):
            print(f"КОНТРОЛЬ НЕ ПРОЙДЕН: {а.control} — {к['почему'] or 'разбор пуст'}",
                  file=sys.stderr)
            print("замер не печатается: иначе «противоречий 0» неотличимо от"
                  " сломанного селектора", file=sys.stderr)
            браузер.close()
            return 2
        print(f"контроль: {а.control} — следующая {к['следующая']},"
              f" доступно {к['доступно']} ({к['исход']})")
        print()
        for домен in витрины:
            try:
                адреса = слуги_с_главной(стр, домен, а.limit)
            except Exception as сбой:  # noqa: BLE001
                print(f"{домен}: главная не отдалась —"
                      f" {type(сбой).__name__}: {сбой}"[:140])
                строки.append({"домен": домен, "исход": "не измерено",
                               "почему": "главная не отдалась"})
                continue
            если = [карточка(стр, u) for u in адреса]
            for з in если:
                з["домен"] = домен
            строки += если
            счёт = {и: sum(1 for з in если if з["исход"] == и)
                    for и in ("согласовано", "опережает", "противоречие",
                              "несопоставимо", "блока нет", "не измерено")}
            с_блоком = счёт["согласовано"] + счёт["опережает"] + счёт["противоречие"]
            print(f"{домен}: страниц {len(если)}, блок есть у {с_блоком};"
                  f" согласовано {счёт['согласовано']},"
                  f" опережает {счёт['опережает']},"
                  f" противоречие {счёт['противоречие']},"
                  f" несопоставимо {счёт['несопоставимо']},"
                  f" блока нет {счёт['блока нет']},"
                  f" не измерено {счёт['не измерено']}")
            for з in если:
                if з["исход"] in ("противоречие", "не измерено",
                                  "несопоставимо"):
                    print(f"    {з['исход']}: {з['url']} — {з['почему']}")
        браузер.close()

    всего = len(строки)
    с_блоком = sum(1 for з in строки if з["исход"] in
                   ("согласовано", "опережает", "противоречие"))
    против = [з for з in строки if з["исход"] == "противоречие"]
    print()
    print(f"проверено страниц {всего}; блок расписания есть у {с_блоком};"
          f" противоречий {len(против)}")
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        а.json.write_text(json.dumps(строки, ensure_ascii=False, indent=1),
                          encoding="utf-8")
        print(f"подробности: {а.json}")
    if против:
        print("ВЫВОД: названная следующая серия уже вышла —"
              f" {len(против)} из {с_блоком} страниц с блоком")
        return 1
    if с_блоком == 0:
        print("ВЫВОД: НЕ ИЗМЕРЕНО — блока расписания нет ни на одной странице"
              " выборки, судить о согласованности нечему")
        return 3
    print(f"ВЫВОД: противоречий нет на {с_блоком} страницах с блоком"
          f" (из {всего} проверенных)")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
