#!/usr/bin/env python3
"""Доставить сборщик описаний в рантайм витрины — вставкой, а не копией файла.

Зачем не целиком. Рантайм витрины — это шаблон ПЛЮС её собственные правки, и
у этого семейства они крупные: копии расходятся от 7 455 до 10 372 строк
против 8 427 в шаблоне. Положить поверх файл шаблона значило бы стереть
правки витрины и привезти заодно всё, что в шаблоне менялось по другим
поводам.

Измерено 2026-10-16 по рабочим копиям действующих витрин, и это меняет место
вставки: в шаблоне мета-описание считалось выражением `описание[:180]`, а в
ячейках уже стоит СВОЯ функция `краткое_описание(...)`, написанная другой
линией после SEO-аудита 11 октября — она обрезает по границе слова и при
пустом описании собирает фразу из фактов. То есть ячейки были впереди
шаблона, и якорь шаблона здесь не нашёлся бы ни у одной из них.

Что делает инструмент:

1. кладёт `description_assembly.py` в `src/` витрины (его там нет);
2. вставляет перед `краткое_описание` необязательный импорт и опознание
   витрины: домен берётся из переменных окружения, а если их нет — из
   `config/site.json` рядом с рантаймом (у `lordfilm47-space` и
   `lordserial33-biz` переменной с доменом нет вовсе, а конфиг есть у всех);
3. вставляет в начало тела функции делегирование сборщику. Если сборщик
   отказался (бедная запись — измерено 3,0 % страниц), управление идёт в
   ПРЕЖНЕЕ тело функции: отказ сборщика не повод терять то, что витрина
   умеет сегодня;
4. обновляет `pins.lock.json` — иначе проверка замка законно падает;
5. проверяет результат: файл разбирается, делегирование на месте, число
   определений функции не изменилось, сборщик даёт для этой витрины строку.

Ничего не выкладывает: правит рабочую копию. Выпуск — отдельный шаг линии
витрины.

    python3 automation/local/deliver-description-assembly.py --dry-run --repo /srv/lordfilm47-space/current
    python3 automation/local/deliver-description-assembly.py --repo <путь>
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import shutil
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
МОДУЛЬ = КОРЕНЬ / "automation" / "host" / "description_assembly.py"

ЯКОРЬ_ФУНКЦИИ = ("def краткое_описание(имя: str, запись: dict, деталь: dict, "
                 "описание: str, сайт: str) -> str:")
ЯКОРЬ_ТЕЛА = '    описание = " ".join(str(описание or "").split())'

ВСТАВКА_ИМПОРТА = '''# Сборщик мета-описаний по доменам. Доставлен вставкой
# (`automation/local/deliver-description-assembly.py`): рантайм витрины — это
# шаблон плюс её правки, и копия файла шаблона стёрла бы их. Отсутствие
# модуля витрину не роняет — описание считается прежним способом.
try:
    import description_assembly as СБОРКА_ОПИСАНИЯ  # noqa: E402
except ImportError:
    СБОРКА_ОПИСАНИЯ = None


def _ключ_витрины_для_сборки() -> str:
    """Чем витрина опознаётся в таблице профилей сборщика.

    Переменной окружения с доменом есть не у всех витрин (измерено:
    LORDS_SITE_DOMAIN объявлен у zonafilm12-site и zonafilm-space, у
    lordfilm47-space и lordserial33-biz её нет вовсе), а `config/site.json`
    рядом с рантаймом есть у каждой. Поэтому сначала окружение, затем конфиг,
    и ни одного значения по умолчанию: без опознания сборщик не обещает
    различия, а не угадывает профиль.
    """
    import os as _os

    for имя in ("LORDS_SITE_DOMAIN", "LORDS_SITE_HOST", "ZONA_SITE_DOMAIN",
                "LORDS_SITE_ID", "SITE_ID"):
        значение = (_os.environ.get(имя) or "").strip()
        if значение:
            return значение
    try:
        конфиг = Path(__file__).resolve().parent.parent / "config" / "site.json"
        данные = json.loads(конфиг.read_text(encoding="utf-8"))
        return str(данные.get("domain") or данные.get("site_id") or "")
    except Exception:
        return ""


КЛЮЧ_ВИТРИНЫ_ДЛЯ_СБОРКИ = _ключ_витрины_для_сборки()


'''

ВСТАВКА_ТЕЛА = '''    # Сборка по доменному профилю (правило SEO RULE-DESCRIPTION-ASSEMBLY.md):
    # семь витрин семейства предъявляли поиску ОДИН И ТОТ ЖЕ description,
    # потому что он брался прямо из поля поставщика. Пустая строка от
    # сборщика — не ошибка, а отказ на бедной записи; тогда работает прежнее
    # тело этой функции, и витрина не теряет того, что умеет сегодня.
    if СБОРКА_ОПИСАНИЯ is not None:
        собрано = СБОРКА_ОПИСАНИЯ.описание(запись, деталь or {},
                                           КЛЮЧ_ВИТРИНЫ_ДЛЯ_СБОРКИ)
        if собрано:
            return собрано
'''

ПРИМЕЧАНИЕ_ЗАМКА = (
    "Сборщик мета-описаний по доменам (правило SEO "
    "RULE-DESCRIPTION-ASSEMBLY.md): семь витрин семейства отдавали одинаковый "
    "description из поля поставщика. Доставлен вставкой в собственную функцию "
    "витрины `краткое_описание`, прежнее тело сохранено как путь для бедных "
    "записей."
)


def требуется(файл: Path, что: str, сколько: int = 1) -> str:
    t = файл.read_text(encoding="utf-8")
    if t.count(что) != сколько:
        raise SystemExit(f"{файл}: якорь встречается {t.count(что)} раз вместо "
                         f"{сколько} — состав рантайма другой, ничего не "
                         f"меняю: {что[:60]}")
    return t


def правка(текст: str) -> tuple[str, list[str]]:
    шаги: list[str] = []
    если_уже = "СБОРКА_ОПИСАНИЯ" in текст
    if если_уже:
        return текст, ["уже есть: сборщик в этой копии доставлен"]
    было_определений = текст.count(ЯКОРЬ_ФУНКЦИИ)
    текст = текст.replace(ЯКОРЬ_ФУНКЦИИ, ВСТАВКА_ИМПОРТА + ЯКОРЬ_ФУНКЦИИ, 1)
    шаги.append("импорт сборщика и опознание витрины")
    текст = текст.replace(ЯКОРЬ_ТЕЛА, ВСТАВКА_ТЕЛА + ЯКОРЬ_ТЕЛА, 1)
    шаги.append("делегирование в начале тела краткое_описание")
    if текст.count(ЯКОРЬ_ФУНКЦИИ) != было_определений:
        raise SystemExit("правка изменила число определений функции — "
                         "ничего не записываю")
    return текст, шаги


def закрепить(проект: Path, файлы: dict[str, Path]) -> None:
    замок = проект / "pins.lock.json"
    if not замок.is_file():
        print(f"   [!] {проект.name}: замка нет, закрепление пропущено")
        return
    д = json.loads(замок.read_text(encoding="utf-8"))
    записи = д.setdefault("files", {})
    for имя, файл in файлы.items():
        запись = записи.setdefault(имя, {})
        запись["sha256"] = hashlib.sha256(файл.read_bytes()).hexdigest()
        запись["bytes"] = файл.stat().st_size
        запись.setdefault("source", "automation/host/" + имя)
        запись["verified_against"] = "правка ячейки поверх git"
        прежнее = (запись.get("note") or "").strip()
        if ПРИМЕЧАНИЕ_ЗАМКА not in прежнее:
            запись["note"] = (прежнее + " " if прежнее else "") + ПРИМЕЧАНИЕ_ЗАМКА
    замок.write_text(json.dumps(д, ensure_ascii=False, indent=1) + "\n",
                     encoding="utf-8")


def проверить(рантайм: Path, ключ: str) -> list[str]:
    """Результат проверяется прогоном, а не осмотром."""
    беды: list[str] = []
    текст = рантайм.read_text(encoding="utf-8")
    try:
        ast.parse(текст)
    except SyntaxError as e:
        беды.append(f"файл не разбирается: {e}")
        return беды
    if "СБОРКА_ОПИСАНИЯ.описание(запись" not in текст:
        беды.append("делегирования в теле функции нет")
    if "КЛЮЧ_ВИТРИНЫ_ДЛЯ_СБОРКИ = _ключ_витрины_для_сборки()" not in текст:
        беды.append("опознания витрины нет")
    sys.path.insert(0, str(рантайм.parent))
    try:
        import importlib

        модуль = importlib.import_module("description_assembly")
        importlib.reload(модуль)
        проба = модуль.описание(
            {"slug": "x"},
            {"name": "Проба", "type": "tv", "year": 2020,
             "genres": ["драма", "мелодрама"], "countries": ["Мексика"],
             "imdb_rating": 7.4, "original_name": "Test", "description": ""},
            ключ)
        if not проба:
            беды.append(f"сборщик не дал строки для ключа {ключ!r}")
        elif not модуль.различается(ключ):
            беды.append(f"у витрины {ключ!r} нет своего профиля — различия "
                        f"не будет")
        else:
            print(f"   проба сборки: {проба[:90]}")
    except Exception as e:  # noqa: BLE001
        беды.append(f"сборщик не импортируется из витрины: {e}")
    finally:
        sys.path.pop(0)
    return беды


def ключ_витрины(проект: Path) -> str:
    конфиг = проект / "config" / "site.json"
    if not конфиг.is_file():
        return ""
    д = json.loads(конфиг.read_text(encoding="utf-8"))
    return str(д.get("domain") or д.get("site_id") or "")


def доставить(проект: Path, пробный: bool) -> int:
    рантайм = проект / "src" / "lords-frontend.py"
    if not рантайм.is_file():
        print(f"{проект}: рантайма lords-frontend.py нет — у витрины другой "
              f"состав, доставка не применима")
        return 1
    ключ = ключ_витрины(проект)
    print(f"{проект} (ключ витрины: {ключ or 'НЕ ОПОЗНАНА'})")
    if not ключ:
        print("   [x] витрина не опознана: без домена или site_id сборщик не "
              "выберет профиль. Ничего не меняю")
        return 1

    требуется(рантайм, ЯКОРЬ_ФУНКЦИИ)
    требуется(рантайм, ЯКОРЬ_ТЕЛА)
    текст, шаги = правка(рантайм.read_text(encoding="utf-8"))
    for ш in шаги:
        print(f"   {ш}")
    if пробный:
        print("   пробный прогон: ничего не записано")
        return 0

    копия = рантайм.with_suffix(".py.before-assembly")
    if not копия.exists():
        shutil.copy2(рантайм, копия)
    цель_модуля = проект / "src" / МОДУЛЬ.name
    shutil.copy2(МОДУЛЬ, цель_модуля)
    рантайм.write_text(текст, encoding="utf-8")
    беды = проверить(рантайм, ключ)
    if беды:
        shutil.copy2(копия, рантайм)
        print("   [x] проверка не прошла, копия возвращена:")
        for б in беды:
            print(f"       {б}")
        return 1
    закрепить(проект, {"lords-frontend.py": рантайм,
                       МОДУЛЬ.name: цель_модуля})
    print("   доставлено и проверено; замок обновлён")
    return 0


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--repo", action="append", default=[], type=Path,
                   required=True,
                   help="путь к рабочей копии витрины (каталог с src/ и "
                        "config/site.json)")
    р.add_argument("--dry-run", action="store_true")
    опции = р.parse_args(аргв)

    плохих = 0
    for проект in опции.repo:
        плохих += доставить(проект, опции.dry_run)
    print(f"\nвитрин с отказом: {плохих} из {len(опции.repo)}")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(главное())
