#!/usr/bin/env python3
"""Нумерация сезонов в снимке витрины: дыры и подмена номером части.

Зачем отдельно от проверки карты сайта. `sitemap-regression-guard.py` ищет
пропуски сезонов в АДРЕСАХ карты, и на витринах, где адресов серий в карте нет
вовсе (animedia: 0 из 8 234), он честно отвечает «не измерено». Здесь предмет
другой — сами данные витрины (`<site_id>-details.json`), и измерить их можно
всегда.

ЧТО СЧИТАЕТСЯ ДЕФЕКТОМ, А ЧТО НЕТ — измерено 20.10 на animedia-01 (8 674
записи, 6 003 с сезонами):

* **«минимальный сезон не 1» дефектом НЕ является** — таких 1 078, и это
  обычное устройство каталога: сезон вынесен в отдельную запись, а внутри неё
  нумерация своя;
* **дыра внутри нумерации** (есть 1 и 3, нет 2) — 30 записей. Но и она
  делится на три разных случая, и смешивать их нельзя;
* **сезоны у фильма** — 0 записей, то есть дефект Yummy (фантомный сезон 2 у
  полнометражного фильма) здесь НЕ повторяется.

ТРИ ПОДКЛАССА ДЫРЫ, РАЗВЕДЁННЫЕ ПО ПРИЧИНЕ:

1. **номер части в списке сезонов** (9 записей): набор сезонов равен ровно
    {1, N}, где N — номер части в НАЗВАНИИ записи («Анжелика OVA-4» → сезоны
    1 и 4, «Симфогир [ТВ-4]» → 1 и 4). Это не пропавший сезон, а номер части
    франшизы, попавший в поле сезона — тот же механизм, что у года;
2. **одна дыра** (11 записей): «Акварион» 1 и 3, «Королевство» 1, 2, 4,
   «Мутанты черепашки ниндзя» 1, 2, 3, 4, 6, 7 — похоже на настоящий пропуск;
3. **много дыр** (10 записей), среди них явные выбросы: «Югио! Поспеши!»
   сезоны 1 и **61**, «Безымянная память 2» сезоны 2 и **22** с `avail: 0`.
   Номер сезона такой величины — скорее номер серии, попавший не в то поле.

И ОТДЕЛЬНО ПРОВЕРЯЕТСЯ, НЕ ЛЕЖИТ ЛИ ПРОПУСК ОТДЕЛЬНОЙ ЗАПИСЬЮ каталога: у 6
записей из 30 пропущенный сезон найден как самостоятельное произведение с тем
же базовым названием. Такая дыра законна, и объявлять её дефектом — значит
выдать находку на различии «франшиза / произведение / сезон».

    python3 automation/local/season-numbering-audit.py /srv/animedia-icu/data/animedia-01-details.json
    python3 automation/local/season-numbering-audit.py <файл> --json
"""
from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

#: Номер сезона выше этого считается ВЫБРОСОМ: столько сезонов не бывает, и
#: такое число скорее номер серии, попавший не в то поле. Измерено: «Югио!
#: Поспеши!» — сезон 61, «Безымянная память 2» — сезон 22 при avail 0.
ВЫБРОС_НОМЕРА = 20

ПОМЕТКА_ЧАСТИ = re.compile(r"[\[(](?:ТВ|TV|OVA|ОВА)[-\s]?(\d{1,2})[\])]")
ХВОСТ_НОМЕРА = re.compile(r"(\d{1,2})\s*$")


def записи(путь: Path) -> dict[str, dict]:
    д = json.loads(путь.read_text(encoding="utf-8"))
    подробности = д.get("details") if isinstance(д, dict) else None
    if not isinstance(подробности, dict):
        raise SystemExit(f"{путь}: нет словаря `details` — это не снимок витрины")
    return подробности


def номера_сезонов(запись: dict) -> list[int]:
    сезоны = (запись or {}).get("seasons")
    if not isinstance(сезоны, list):
        return []
    итог = {с["n"] for с in сезоны
            if isinstance(с, dict) and isinstance(с.get("n"), int)}
    return sorted(итог)


def номер_части(имя: str) -> int | None:
    """Номер части из названия: «Симфогир [ТВ-4]» или «Прославленный 3»."""
    п = ПОМЕТКА_ЧАСТИ.search(имя or "")
    if п:
        return int(п.group(1))
    х = ХВОСТ_НОМЕРА.search(имя or "")
    return int(х.group(1)) if х else None


def _база_имени(имя: str) -> str:
    без_пометки = ПОМЕТКА_ЧАСТИ.sub("", имя or "")
    return ХВОСТ_НОМЕРА.sub("", без_пометки).strip().lower().replace("ё", "е")


def пропуск_отдельной_записью(подробности: dict[str, dict], слаг: str,
                              пропуски: list[int]) -> list[tuple[int, str]]:
    """Пропущенные сезоны, найденные ОТДЕЛЬНЫМИ записями того же названия."""
    имя = (подробности.get(слаг) or {}).get("name") or ""
    база = _база_имени(имя)
    if not база:
        return []
    по_базе = [с for с, з in подробности.items()
               if с != слаг and _база_имени(з.get("name") or "") == база]
    нашлось = []
    for н in пропуски:
        for с in по_базе:
            если = номер_части((подробности[с].get("name") or ""))
            if если == н:
                нашлось.append((н, с))
                break
    return нашлось


def разобрать(подробности: dict[str, dict]) -> dict:
    с_сезонами = 0
    мин_не_один = 0
    у_фильма = []
    классы: dict[str, list] = {"номер части в сезонах": [], "одна дыра": [],
                               "много дыр": []}
    законных = []
    выбросы = []
    for слаг, з in sorted(подробности.items()):
        номера = номера_сезонов(з)
        if not номера:
            continue
        с_сезонами += 1
        if номера[0] != 1:
            мин_не_один += 1
        if (з.get("type") or "") == "movie" and номера != [1]:
            у_фильма.append({"слаг": слаг, "сезоны": номера})
        если_выброс = [н for н in номера if н > ВЫБРОС_НОМЕРА]
        if если_выброс:
            выбросы.append({"слаг": слаг, "сезоны": номера,
                            "выше предела": если_выброс})
        пропуски = [н for н in range(номера[0], номера[-1] + 1)
                    if н not in номера]
        if not пропуски:
            continue
        нашлось = пропуск_отдельной_записью(подробности, слаг, пропуски)
        строка = {"слаг": слаг, "сезоны": номера, "пропуски": пропуски,
                  "name": з.get("name"),
                  "пропуск отдельной записью": нашлось}
        if нашлось and len(нашлось) == len(пропуски):
            законных.append(строка)
            continue
        часть = номер_части(з.get("name") or "")
        if часть and set(номера) == {1, часть}:
            классы["номер части в сезонах"].append(строка)
        elif len(пропуски) == 1:
            классы["одна дыра"].append(строка)
        else:
            классы["много дыр"].append(строка)
    return {
        "записей в снимке": len(подробности),
        "записей с сезонами": с_сезонами,
        "минимальный сезон не 1 (НЕ дефект)": мин_не_один,
        "сезоны у фильма": у_фильма,
        "дыра законна (пропуск лежит отдельной записью)": законных,
        "подклассы": классы,
        "номер сезона выше предела": выбросы,
        "дыр всего": sum(len(с) for с in классы.values()) + len(законных),
    }


def напечатать(итог: dict) -> None:
    for к in ("записей в снимке", "записей с сезонами",
              "минимальный сезон не 1 (НЕ дефект)", "дыр всего"):
        print(f"{к}: {итог[к]}")
    print(f"из них законных (пропуск лежит отдельной записью):"
          f" {len(итог['дыра законна (пропуск лежит отдельной записью)'])}")
    print(f"сезоны у фильма: {len(итог['сезоны у фильма'])}")
    for имя, список in итог["подклассы"].items():
        print(f"\n{имя}: {len(список)}")
        for с in список[:12]:
            print(f"   {с['слаг'][:48]:50} сезоны {с['сезоны']}"
                  f" нет {с['пропуски']}  {(с['name'] or '')[:40]!r}")
        if len(список) > 12:
            print(f"   … и ещё {len(список) - 12}")
    if итог["номер сезона выше предела"]:
        print(f"\nномер сезона выше {ВЫБРОС_НОМЕРА} (похоже на номер серии не в"
              f" том поле): {len(итог['номер сезона выше предела'])}")
        for с in итог["номер сезона выше предела"][:10]:
            print(f"   {с['слаг'][:48]:50} {с['сезоны']}")
    print("\nЧЕГО ЭТОТ ПРОХОД НЕ ГОВОРИТ:")
    print("   — «минимальный сезон не 1» дефектом не считается: сезон часто"
          " вынесен в отдельную запись каталога, и таких записей здесь"
          f" {итог['минимальный сезон не 1 (НЕ дефект)']};")
    print("   — какой из трёх подклассов править первым: подмена номером части"
          " правится в поле сезона, настоящий пропуск — у поставщика;")
    print("   — что пропуск точно отсутствует у ПОСТАВЩИКА: проход читает"
          " снимок витрины, а не его ответ.")


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("снимок")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    итог = разобрать(записи(Path(а.снимок)))
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
    else:
        напечатать(итог)
    есть_дефект = (sum(len(с) for с in итог["подклассы"].values())
                   or итог["сезоны у фильма"])
    return 1 if есть_дефект else 0


if __name__ == "__main__":
    sys.exit(главное())
