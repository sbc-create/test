#!/usr/bin/env python3
"""Живые редакционные тексты, у которых происхождение не записано нигде.

ПОВОД ИЗМЕРЕННЫЙ, 24.10, и он задевает главное правило: факт без одобренного
источника не появляется. Соседняя линия, готовя первую публикацию на
zonafilm12.site, сверила три черновика с `editorial_facts` витрины и описанием
поставщика и нашла в них подробности, которых нет ни там, ни там: «Фриц
Бреннер, Крамер, 10 000 орхидей», «Джаспер, Гранд-Джанкшен», «Чёрный рыцарь,
кролик». Источников при подготовке 19.10 не записано. Вывод её же:
`state: verified` — это ворота ФОРМЫ, а не проверка фактов.

Отсюда вопрос, который этот инструмент и отвечает: сколько ТАКИХ текстов уже
стоит на витринах. Считается в четыре шага, и каждый отделяет случай, который
нельзя смешивать с другими:

1. черновики без непустого `sources`;
2. из них — те, чьё тело УЖЕ размещено (наложение или накладка витрины);
3. из них — те, у которых нет происхождения и в реестре оператора
   (`provenance.facts_manifest` или `source_id`): у части оно записано там, и
   тогда источник есть, просто лежит в другом месте;
4. из них — те, чьё тело содержит слова, которых нет ни в записи каталога, ни
   в слаге. Текст, собранный из полей каталога (название, год, жанры),
   прослеживается к данным; текст с именем персонажа — нет.

Четвёртый шаг — не проверка правдивости. Имя может быть верным; важно, что
система не может показать, откуда оно. Правило требует прослеживаемости, а не
везения.

Память ограничена нарочно: каталоги витрин по 95–128 МиБ, и чтение всех сразу
убивает процесс (измерено). Читается по одному, нужные слаги выбираются и
каталог освобождается.
"""
from __future__ import annotations

import argparse
import gc
import glob
import importlib.util
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_о = КОРЕНЬ / "automation" / "local" / "editorial-inventory.py"
_с = importlib.util.spec_from_file_location("editorial_inventory", _о)
ОПИСЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(ОПИСЬ)

РЕЕСТР = pathlib.Path("/var/lib/seo-content-operator/registry.json")
КАТАЛОГИ = ("/srv/lords/.frontend/*-details.json", "/srv/*/data/*-details.json")
#: Слово с большой буквы длиннее трёх букв: имена, места, названия.
СЛОВО = re.compile(r"[А-ЯЁ][а-яё]{3,}")
#: Поля записи каталога, к которым текст может прослеживаться.
ПОЛЯ = ("name", "original_name", "year", "genres", "countries", "type",
        "description")


def с_происхождением_в_реестре(путь: pathlib.Path | None = None) -> set[tuple]:
    """Пути берутся при ВЫЗОВЕ, а не при объявлении.

    Значение по умолчанию заморозило бы путь в момент загрузки модуля: тогда
    ни проверка, ни запуск с другим реестром не действуют, а инструмент молча
    читает прежний файл. Измерено 24.10 на собственной проверке.
    """
    путь = путь or РЕЕСТР
    if not путь.exists():
        return set()
    из = set()
    for з in json.loads(путь.read_text(encoding="utf-8"))["items"]:
        p = з.get("provenance") or {}
        if p.get("facts_manifest") or p.get("source_id"):
            из.add((з.get("target_site"), з.get("title_id")))
    return из


def размещённые(каталог: pathlib.Path) -> set[str]:
    """Отпечатки тел, которые витрина показывает: наложение плюс накладка."""
    из: set[str] = set()
    н = каталог / "title-overlays.json"
    if н.exists():
        из |= {ОПИСЬ.отпечаток(и.get("body") or "")
               for и in ОПИСЬ._items(json.loads(н.read_text(encoding="utf-8")))}
    накл = ОПИСЬ.накладка_витрины(каталог.name)
    if накл:
        из |= ОПИСЬ.описания_накладки(накл)
    return из


def без_источников_и_живые(пров: set[tuple]) -> list[dict]:
    из = []
    for путь in sorted(glob.glob("/srv/sites/*/runtime/overlays/*/drafts.json")):
        к = pathlib.Path(путь).parent
        домен = к.name
        зп = [з for з in ОПИСЬ._items(
            json.loads(pathlib.Path(путь).read_text(encoding="utf-8")))
            if isinstance(з, dict)]
        живые = размещённые(к)
        for з in зп:
            if з.get("sources") or []:
                continue
            if ОПИСЬ.отпечаток(з.get("body") or "") not in живые:
                continue
            if (домен, з.get("slug")) in пров:
                continue
            из.append({"домен": домен, "слаг": з.get("slug"),
                       "тело": з.get("body") or "",
                       "автор": з.get("author"),
                       "подготовлен": з.get("prepared_at")})
    return из


def опора_каталога(слаги: set[str]) -> dict[str, str]:
    """Поля записи каталога по слагу. Каталоги читаются ПО ОДНОМУ."""
    из: dict[str, str] = {}
    файлы = []
    for образец in КАТАЛОГИ:
        файлы.extend(glob.glob(образец))
    for ф in sorted(set(файлы)):
        п = pathlib.Path(ф)
        if п.is_symlink():
            continue
        try:
            д = json.loads(п.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        детали = д.get("details") if isinstance(д, dict) else None
        if isinstance(детали, dict):
            for с in слаги:
                з = детали.get(с)
                if з:
                    из[с] = (из.get(с, "") + " " + " ".join(
                        str(v) for k, v in з.items() if k in ПОЛЯ))
        del д, детали
        gc.collect()
    return из


def чужие_слова(тело: str, опора: str, слаг: str) -> list[str]:
    """Слова с большой буквы ВНУТРИ предложения, которых нет в опоре.

    Слово в начале предложения отбрасывается: «Второй», «Сериал», «После» —
    обычные слова, и первая редакция ловила их как имена. Из-за этого список
    выглядел длиннее, чем есть, а на длинном списке с шумом вывод не
    защитить. Признак имени — большая буква ТАМ, ГДЕ её не требует
    пунктуация.
    """
    поле = f"{опора} {слаг}".lower()
    из = []
    for м in СЛОВО.finditer(тело):
        до = тело[:м.start()].rstrip()
        if not до or до[-1] in ".!?…»\"":
            continue  # начало предложения: большая буква обязательна
        с = м.group(0)
        if с.lower() not in поле and с not in из:
            из.append(с)
    return sorted(из)


def главное(argv: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--examples", type=int, default=10)
    р.add_argument("--json", type=pathlib.Path)
    а = р.parse_args(argv)

    пров = с_происхождением_в_реестре()
    if not пров:
        print(f"НЕ ИЗМЕРЕНО: реестр оператора не прочитан — {РЕЕСТР};"
              " без него «происхождения нет» неотличимо от «не посмотрела»")
        return 2
    кандидаты = без_источников_и_живые(пров)
    print(f"живых текстов без источников в черновике и без происхождения"
          f" в реестре: {len(кандидаты)}")
    if not кандидаты:
        print("ВЫВОД: таких текстов нет")
        return 0

    опора = опора_каталога({к["слаг"] for к in кандидаты})
    print(f"слагов найдено в каталогах витрин: {len(опора)}"
          f" из {len({к['слаг'] for к in кандидаты})}")
    строгие, мягкие = [], []
    for к in кандидаты:
        ч = чужие_слова(к["тело"], опора.get(к["слаг"], ""), к["слаг"] or "")
        (строгие if ч else мягкие).append({**к, "чужие": ч})
    print()
    print(f"собраны из полей каталога (прослеживаются): {len(мягкие)}")
    print(f"СОДЕРЖАТ слова, которых нет ни в каталоге, ни в слаге:"
          f" {len(строгие)}")
    print()
    for к in строгие[:а.examples]:
        print(f"  {к['домен']:20} {к['слаг']}")
        print(f"      непрослеживаемое: {', '.join(к['чужие'][:6])}")
        print(f"      автор {к['автор']}, подготовлен {к['подготовлен']}")
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        а.json.write_text(json.dumps(
            {"строгие": строгие, "мягкие": мягкие}, ensure_ascii=False,
            indent=1), encoding="utf-8")
        print(f"\nподробности: {а.json}")
    print()
    if строгие:
        print(f"ВЫВОД: {len(строгие)} живых текстов несут подробности, которые"
              " не прослеживаются ни к записи каталога, ни к одобренному"
              " источнику. Это не доказательство выдумки — имя может быть"
              " верным; это значит, что показать источник нечем, а правило"
              " требует именно этого.")
        return 1
    print("ВЫВОД: все такие тексты прослеживаются к полям записи каталога")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
