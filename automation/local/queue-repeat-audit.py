#!/usr/bin/env python3
"""Повторяет ли очередь задания, уже закрытые отказом, раньше срока удержания.

Зачем. Срок удержания исхода задан в `seo_operator/regular.py::RESULT_HOLD`
(например `SOURCES_MISSING` — 14 суток), и раньше срока адрес открывается
только изменением реестра источников (`REVIEW_ON_NEW_SOURCES`). Если задания
выдаются заново раньше, это прямой расход ходов редактора: он снова приходит к
тому же отказу.

Инструмент читает журнал очереди и сверяет ДВА факта. Только чтение.

1. **Что очередь объявляет сама.** В событии `task_result` она пишет
   `next_attempt_at` — когда задание вернётся к работе. Это её собственное
   обещание, и сверять его с правилом удержания можно без догадок.
2. **Что получилось.** Повторные выдачи (`task_claimed`) того же задания раньше
   объявленного срока и повторные закрытия тем же исходом.

Важно, чей это срок. Правило `RESULT_HOLD` живёт в `seo_operator/regular.py`
(мой слой), а очередь, которая реально выдаёт задания, — отдельный модуль
`seo_engine/content_operator/editorial_queue.py` в дереве оператора: мост
`factory/qwen/queue_bridge.py` вызывает именно его. Поэтому расхождение между
правилом и поведением возможно, и инструмент показывает его числом, а не
рассуждением.

    python3 automation/local/queue-repeat-audit.py
    python3 automation/local/queue-repeat-audit.py --outcome SOURCES_MISSING
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

ЖУРНАЛ = Path("/var/lib/seo-content-operator/queue_events.jsonl")
КОРЕНЬ = Path(__file__).resolve().parents[1].parent
#: Срок удержания исходов — тот же, что у оператора. Держится в одном месте:
#: расхождение между правилом и проверкой скрыло бы ровно тот дефект, который
#: проверка ищет.
СРОКИ = {
    "SOURCE_UNAVAILABLE": 1,
    "PAGE_ABSENT": 7,
    "DELIVERY_UNSUPPORTED": 7,
    "IDENTITY_UNCLEAR": 14,
    "IDENTITY_REJECTED": 14,
    "SOURCES_MISSING": 14,
}
РЕЕСТР_ИСТОЧНИКОВ = КОРЕНЬ / "config" / "editorial-sources.json"


def _время(значение: str) -> dt.datetime | None:
    try:
        return dt.datetime.strptime(значение, "%Y-%m-%dT%H:%M:%SZ").replace(
            tzinfo=dt.timezone.utc)
    except (ValueError, TypeError):
        return None


def события() -> list[dict]:
    if not ЖУРНАЛ.is_file():
        return []
    итог = []
    for строка in ЖУРНАЛ.read_text(encoding="utf-8", errors="replace").splitlines():
        строка = строка.strip()
        if not строка.startswith("{"):
            continue
        try:
            итог.append(json.loads(строка))
        except ValueError:
            continue
    return итог


УСПЕХ = ("TEXT_WRITTEN", "NO_CHANGE_NEEDED")


def переходы(записи: list[dict]) -> dict:
    """Сколько повторов отказа приводят к тексту, а сколько уходят впустую.

    Это главный вопрос к сроку удержания, и отвечать на него надо числом.
    Плоский срок убирает повторы — но вместе с теми попытками, которые ПОЗЖЕ
    дали текст. Измерено 2026-10-11: у `SOURCES_MISSING` все 13 успехов пришли
    после РОВНО ОДНОГО повтора, а после двух и более успехов нет совсем;
    значит предел «один повтор» сохраняет всю работу и срезает 22 пустых
    повтора из 24, тогда как удержание 14 суток потеряло бы все 13.
    У `SOURCE_UNAVAILABLE` наоборот: успехи рассыпаны по 1–5 повторам, и
    короткие повторы продуктивны — там неправо правило, а не очередь.
    """
    история: dict[str, list[tuple[str, str]]] = {}
    for з in записи:
        if з.get("event") != "task_result":
            continue
        ключ, исход = з.get("task_id"), з.get("outcome")
        if ключ and исход:
            история.setdefault(ключ, []).append((з.get("at") or "", исход))

    итог: dict[str, dict] = {}
    for исход in СРОКИ:
        до_успеха: dict[int, int] = {}
        впустую: dict[int, int] = {}
        for записи_задания in история.values():
            записи_задания.sort()
            цепочка = [и for _к, и in записи_задания]
            if исход not in цепочка:
                continue
            подряд, закончилось = 0, None
            for и in цепочка:
                if и == исход:
                    подряд += 1
                elif подряд:
                    закончилось = и
                    break
            if not подряд:
                continue
            куда = до_успеха if закончилось in УСПЕХ else впустую
            куда[подряд] = куда.get(подряд, 0) + 1
        if not (до_успеха or впустую):
            continue
        успехов = sum(до_успеха.values())
        пределы = {}
        for предел in (1, 2, 3):
            пределы[предел] = {
                "сохранено_успехов": sum(н for n, н in до_успеха.items()
                                         if n <= предел),
                "потеряно_успехов": sum(н for n, н in до_успеха.items()
                                        if n > предел),
                "срезано_пустых": sum(max(0, n - предел) * н
                                      for n, н in впустую.items()),
            }
        итог[исход] = {"заданий": успехов + sum(впустую.values()),
                       "успехов_потом": успехов,
                       "повторов_до_успеха": dict(sorted(до_успеха.items())),
                       "повторов_впустую": dict(sorted(впустую.items())),
                       "пределы": пределы}
    return итог


def разобрать(записи: list[dict], только: str | None = None) -> dict:
    """Объявленные сроки, повторные выдачи и повторные закрытия.

    Имена событий взяты из журнала, а не придуманы: выдача — `task_claimed`,
    результат — `task_result`. Первая версия этого разбора искала
    `task_issued`/`task_next`, не находила ничего и отвечала «повторов нет» —
    то есть молчала о дефекте, который искала.
    """
    закрыто: dict[str, tuple[dt.datetime, str, dt.datetime | None]] = {}
    повторы: list[dict] = []
    объявлено: dict[str, list[float]] = {}
    закрытия_по_ключу: dict[tuple[str, str], list[dt.datetime]] = {}
    выдач = закрытий = 0
    for з in sorted(записи, key=lambda з: з.get("at") or ""):
        когда = _время(з.get("at") or "")
        ключ = з.get("task_id") or з.get("canonical_url") or з.get("slug")
        if not когда or not ключ:
            continue
        событие = з.get("event") or ""
        if событие == "task_result":
            закрытий += 1
            исход = з.get("outcome") or ""
            if исход not in СРОКИ or (только is not None and исход != только):
                continue
            потом = _время(з.get("next_attempt_at") or "")
            закрыто[ключ] = (когда, исход, потом)
            закрытия_по_ключу.setdefault((ключ, исход), []).append(когда)
            if потом:
                объявлено.setdefault(исход, []).append(
                    round((потом - когда).total_seconds() / 3600, 1))
        elif событие == "task_reopened":
            # Переоткрытие снимает удержание законно: дальше задание можно
            # брать, и считать это повтором нельзя.
            закрыто.pop(ключ, None)
        elif событие == "task_claimed":
            выдач += 1
            прежде = закрыто.get(ключ)
            if not прежде:
                continue
            было, исход, потом = прежде
            # Повтором считается ТОЛЬКО выдача раньше срока, объявленного самой
            # очередью в `next_attempt_at`. Сравнение с правилом `RESULT_HOLD`
            # сюда не идёт намеренно: правило живёт в другом слое, и его
            # расхождение с очередью показано отдельной таблицей. Иначе в счёт
            # попадал бы обычный перезахват аренды внутри одного прогона —
            # первая версия так и выдала 371 «нарушение» на 786 выдач.
            if not потом or когда >= потом:
                continue
            повторы.append({
                "ключ": ключ, "исход": исход,
                "закрыто": было.strftime("%Y-%m-%dT%H:%M:%SZ"),
                "выдано_снова": когда.strftime("%Y-%m-%dT%H:%M:%SZ"),
                "через_ч": round((когда - было).total_seconds() / 3600, 1),
                "объявлено_не_раньше": потом.strftime("%Y-%m-%dT%H:%M:%SZ"),
            })
    расхождения = {}
    for исход, часы in объявлено.items():
        правило_ч = СРОКИ[исход] * 24
        самый_частый = max(set(часы), key=часы.count)
        if самый_частый < правило_ч:
            расхождения[исход] = {"правило_ч": правило_ч,
                                  "объявлено_ч": самый_частый,
                                  "случаев": len(часы)}
    повторные_закрытия = {
        исход: sum(1 for (к, и), времена in закрытия_по_ключу.items()
                   if и == исход and len(времена) > 1)
        for исход in СРОКИ}
    return {"выдач": выдач, "закрытий": закрытий, "повторы": повторы,
            "объявленные_сроки": {и: sorted(set(ч)) for и, ч in объявлено.items()},
            "расхождения_срока": расхождения,
            "повторные_закрытия": {и: н for и, н in повторные_закрытия.items() if н}}


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="повторы заданий раньше срока")
    р.add_argument("--outcome", default=None, help="только этот исход")
    р.add_argument("--json", action="store_true")
    р.add_argument("--transitions", action="store_true",
                   help="чем кончались повторы отказа")
    а = р.parse_args(аргв)
    записи = события()
    if not записи:
        print(f"журнал очереди не прочитан или пуст: {ЖУРНАЛ}", file=sys.stderr)
        return 2
    if а.transitions:
        разбор = переходы(записи)
        print("\nчем кончались повторы отказа (по каждому исходу):")
        for исход, д in sorted(разбор.items()):
            print(f"   {исход}: заданий {д['заданий']}, позже дали текст "
                  f"{д['успехов_потом']}")
            print(f"      повторов до успеха: {д['повторов_до_успеха'] or '—'}; "
                  f"впустую: {д['повторов_впустую'] or '—'}")
            for предел, п in д["пределы"].items():
                print(f"      предел {предел}: сохранено "
                      f"{п['сохранено_успехов']}, потеряно "
                      f"{п['потеряно_успехов']}, срезано пустых "
                      f"{п['срезано_пустых']}")
        return 0
    итог = разобрать(записи, а.outcome)
    реестр = None
    if РЕЕСТР_ИСТОЧНИКОВ.is_file():
        реестр = dt.datetime.fromtimestamp(
            РЕЕСТР_ИСТОЧНИКОВ.stat().st_mtime,
            dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    итог["реестр_источников_изменён"] = реестр
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=2))
        return 0
    print(f"событий: {len(записи)}; выдач: {итог['выдач']}, "
          f"закрытий: {итог['закрытий']}")
    print(f"реестр источников изменён: {реестр or 'неизвестно'} "
          "(изменение открывает пересмотр раньше срока)")
    print("\nчто очередь объявляет в next_attempt_at против правила:")
    for исход in sorted(СРОКИ):
        часы = итог["объявленные_сроки"].get(исход)
        вид = ", ".join(f"{ч} ч" for ч in часы) if часы else "поля нет"
        метка = " ← РАСХОЖДЕНИЕ" if исход in итог["расхождения_срока"] else ""
        print(f"   {исход:22} правило {СРОКИ[исход] * 24:>4} ч   "
              f"объявлено {вид}{метка}")
    if итог["повторные_закрытия"]:
        print("\nзаданий, закрытых тем же исходом ПОВТОРНО:")
        for исход, сколько in sorted(итог["повторные_закрытия"].items(),
                                     key=lambda п: -п[1]):
            print(f"   {исход:22} {сколько:5}")
    повторы = итог["повторы"]
    print(f"\nвыдач РАНЬШЕ объявленного очередью срока: {len(повторы)}")
    for п in повторы[:10]:
        print(f"   {п['ключ'][:30]:30} {п['исход']:18} закрыто "
              f"{п['закрыто']}, объявлено не раньше {п['объявлено_не_раньше']}"
              f", выдано через {п['через_ч']} ч")
    return 1 if (повторы or итог["расхождения_срока"]) else 0


if __name__ == "__main__":
    sys.exit(главное())
