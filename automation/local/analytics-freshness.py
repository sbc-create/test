#!/usr/bin/env python3
"""Различимость статусов аналитики и свежесть самих данных.

Зачем. Отчёт о посещаемости опасен не ошибкой в числе, а тем, что число из
позавчерашнего сбора выглядит как сегодняшнее. В артефакте сбора есть `measured`
и текст причины у неизмеренного — этого хватает на четыре статуса из пяти
нужных, а пятого, «данные устарели», нет вовсе: свежесть самого артефакта не
выражена ничем.

Статусы называются, а не выводятся из текста на глаз:

  ИЗМЕРЕНО              значение есть
  ИСТОЧНИК_НЕДОСТУПЕН   сеть до источника не дошла, повторы исчерпаны
  ОШИБКА_ДОСТУПА        источник ответил отказом в праве (401/403, токен)
  НЕ_НАСТРОЕНО          счётчика или целей нет
  ВЫКЛЮЧЕНО             источник выключен в реестре осознанно
  ПУСТОЙ_РЕЗУЛЬТАТ      источник ответил, но данных не дал
  ПРИЧИНА_НЕ_РАЗОБРАНА  текст причины не подошёл ни к одному статусу

Последний статус — главный. Без него новый вид сбоя молча попадал бы в чужую
корзину, и «источник недоступен: 86» читалось бы как прежняя известная беда.
Неразобранная причина печатается целиком и меняет код возврата.

Ничего не меняет: только читает артефакт сбора.

    python3 automation/local/analytics-freshness.py
    python3 automation/local/analytics-freshness.py --max-age-hours 12
"""
from __future__ import annotations

import argparse
import collections
import datetime as _dt
import json
import sys
from pathlib import Path

АРТЕФАКТ = Path("/home/claude/wt-portable-site-cell-01/var/analytics"
                "/cabinet-latest.json")

ИЗМЕРЕНО = "ИЗМЕРЕНО"
ИСТОЧНИК_НЕДОСТУПЕН = "ИСТОЧНИК_НЕДОСТУПЕН"
ОШИБКА_ДОСТУПА = "ОШИБКА_ДОСТУПА"
НЕ_НАСТРОЕНО = "НЕ_НАСТРОЕНО"
ВЫКЛЮЧЕНО = "ВЫКЛЮЧЕНО"
ПУСТОЙ_РЕЗУЛЬТАТ = "ПУСТОЙ_РЕЗУЛЬТАТ"
ПРИЧИНА_НЕ_РАЗОБРАНА = "ПРИЧИНА_НЕ_РАЗОБРАНА"

#: Образцы причин. Порядок значим: ошибка доступа проверяется РАНЬШЕ
#: недоступности сети, потому что «отказано в праве» — это ответ источника, а
#: не отсутствие связи, и смешивать их нельзя (`factory/secret_hub/provider.py`
#: формулирует то же правило для секретов).
ОБРАЗЦЫ: tuple[tuple[str, tuple[str, ...]], ...] = (
    (ОШИБКА_ДОСТУПА, ("403", "401", "токен отвергнут", "нет прав",
                      "доступ запрещён", "forbidden", "unauthorized")),
    (ИСТОЧНИК_НЕДОСТУПЕН, ("сеть недоступна", "повторы исчерпаны",
                           "timeout", "недоступен")),
    (НЕ_НАСТРОЕНО, ("не создан", "не созданы", "не настроен", "нет счётчика")),
    (ВЫКЛЮЧЕНО, ("выключен", "выключена", "отключен")),
    (ПУСТОЙ_РЕЗУЛЬТАТ, ("не вернула", "не вернул", "пустой ответ",
                        "данных нет")),
)


def статус(измерение: dict) -> tuple[str, str]:
    """Статус измерения и текст причины."""
    if измерение.get("measured"):
        return ИЗМЕРЕНО, ""
    причина = str(измерение.get("reason") or "").strip()
    if not причина:
        # Неизмеренное без причины — худший случай: его нельзя ни исправить,
        # ни отличить от нуля. Отдельной корзины он не получает, чтобы не
        # выглядел известным.
        return ПРИЧИНА_НЕ_РАЗОБРАНА, "причина не названа вовсе"
    низ = причина.lower()
    for имя, слова in ОБРАЗЦЫ:
        if any(с in низ for с in слова):
            return имя, причина
    return ПРИЧИНА_НЕ_РАЗОБРАНА, причина


def разобрать_время(значение: str) -> _dt.datetime | None:
    текст = (значение or "").strip().replace("Z", "+00:00")
    try:
        метка = _dt.datetime.fromisoformat(текст)
    except ValueError:
        return None
    return метка if метка.tzinfo else метка.replace(tzinfo=_dt.timezone.utc)


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--artifact", type=Path, default=АРТЕФАКТ)
    р.add_argument("--max-age-hours", type=float, default=24.0,
                   help="предел свежести: сборщики идут раз в сутки "
                        "(05:00 и 05:30 UTC)")
    р.add_argument("--now", default="",
                   help="точка отсчёта в ISO (для проверок)")
    опции = р.parse_args(аргв)

    if not опции.artifact.is_file():
        print(f"артефакта сбора нет: {опции.artifact}\n"
              "Это не «нулевая посещаемость», а отсутствие измерения.",
              file=sys.stderr)
        return 2
    try:
        д = json.loads(опции.artifact.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as сбой:
        print(f"артефакт не прочитан: {type(сбой).__name__}", file=sys.stderr)
        return 2

    собрано = разобрать_время(str(д.get("collected_at") or ""))
    сейчас = (разобрать_время(опции.now) if опции.now
              else _dt.datetime.now(_dt.timezone.utc))
    домены = д.get("domains") or []

    print(f"артефакт: {опции.artifact}")
    print(f"   собрано: {д.get('collected_at') or '—'}")
    period = д.get("period") or {}
    print(f"   период: {period.get('date1') or '—'} .. "
          f"{period.get('date2') or '—'}")

    # Часовой пояс берётся из паспорта счётчика, а не предполагается: отчёт
    # без пояса не позволяет сверить сутки с чужой выгрузкой.
    пояса = set()
    for о in домены:
        for и in о.get("measurements") or []:
            знач = и.get("value")
            if isinstance(знач, dict) and знач.get("time_zone_name"):
                пояса.add(str(знач["time_zone_name"]))
    print(f"   часовой пояс счётчиков: "
          f"{', '.join(sorted(пояса)) if пояса else 'НЕ НАЙДЕН в артефакте'}")

    if собрано is None:
        print("\nсвежесть: НЕ ИЗМЕРЕНА — метка сбора не разобрана",
              file=sys.stderr)
        возраст_ч = None
        устарело = None
    else:
        возраст_ч = (сейчас - собрано).total_seconds() / 3600
        устарело = возраст_ч > опции.max_age_hours
        слово = "УСТАРЕЛИ" if устарело else "СВЕЖИЕ"
        print(f"   возраст: {возраст_ч:.1f} ч при пределе "
              f"{опции.max_age_hours:.0f} ч → {слово}")

    счёт: collections.Counter[str] = collections.Counter()
    неразобранные: collections.Counter[str] = collections.Counter()
    for о in домены:
        for и in о.get("measurements") or []:
            имя, причина = статус(и)
            счёт[имя] += 1
            if имя == ПРИЧИНА_НЕ_РАЗОБРАНА:
                неразобранные[причина] += 1

    всего = sum(счёт.values())
    print(f"\nпоказателей: {всего} по {len(домены)} доменам")
    for имя in (ИЗМЕРЕНО, ИСТОЧНИК_НЕДОСТУПЕН, ОШИБКА_ДОСТУПА, НЕ_НАСТРОЕНО,
                ВЫКЛЮЧЕНО, ПУСТОЙ_РЕЗУЛЬТАТ, ПРИЧИНА_НЕ_РАЗОБРАНА):
        print(f"   {имя:22s} {счёт.get(имя, 0):5d}")

    if неразобранные:
        print("\nпричины, не подошедшие ни к одному статусу — их нельзя "
              "записывать в известные:")
        for причина, сколько in неразобранные.most_common(10):
            print(f"   {сколько:4d}  {причина[:150]}")

    # Код возврата различает три разных исхода, а не «хорошо/плохо».
    if собрано is None:
        return 2
    if неразобранные:
        print("\nитог: есть неразобранные причины — статусы неполны",
              file=sys.stderr)
        return 3
    if устарело:
        print(f"\nитог: данные УСТАРЕЛИ ({возраст_ч:.1f} ч). Отчёт по ним "
              "может утверждать вчерашнее как сегодняшнее.", file=sys.stderr)
        return 1
    print("\nитог: данные свежие, все причины разобраны")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
