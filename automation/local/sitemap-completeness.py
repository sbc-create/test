#!/usr/bin/env python3
"""Сколько адресов в карте сайта против того, сколько витрина объявляет записей.

Класс уже доказан: B016 — карта `yummyani.site` обрезана ровно на 8000 адресах
(`walkAnimeListItems(maxPages=80, limit=100)`), и 366 живых тайтлов в неё не
попали. Вопрос «а у остальных?» меряется, а не предполагается.

Эталон берётся **из того, что витрина объявляет о себе сама**: страница каталога
печатает число записей («N записей в выборке», «N тайтлов»). Своё
представление о размере каталога я не подставляю — по правилу, выведенному
этой же ночью: ответ не должен быть свойством выбранного мной источника.

Что считается расхождением:

* адресов в карте **меньше** объявленных записей — часть каталога поисковику не
  названа;
* круглое число адресов (8000, 10000, 20000…) при объявленных записях больше —
  признак предела в обходчике карты, а не конца каталога. Исключение измерено
  2026-10-18: 50 000 — это максимум протокола на один файл, и часть, набитая
  ровно до него, законна, если цепочка за ней ПРОДОЛЖАЕТСЯ (у yummyani.biz
  `episodes.xml` и `-2.xml` по 50 000, а `-3.xml` — 23 188). Прежнее условие
  дало на этом восемь ложных находок за один прогон;
* карта отвечает не 200 — и тогда «меньше» не считается вовсе: это НЕ ИЗМЕРЕНО.

Инструмент только читает публичные адреса.

    python3 automation/local/sitemap-completeness.py zonafilm.space
    python3 automation/local/sitemap-completeness.py --all
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import os
import sys
import tempfile
from pathlib import Path

АГЕНТ = "factory-sitemap-completeness"

#: Паспорт ячеек. Копий несколько, и они расходятся (MOD-164): в копии соседней
#: линии восьми живых витрин K2 нет, и этот инструмент молча их не проверял.
#: Читается копия ЭТОГО репозитория; путь переопределяется SITE_CELLS_PATH, а
#: прочитанная копия и число ячеек называются в выводе — иначе неполный охват
#: неотличим от полного.
ПАСПОРТ = Path(os.environ.get("SITE_CELLS_PATH")
               or Path(__file__).resolve().parents[2] / "config"
               / "site-cells.json")
#: Круглые пределы, которые ставят в обходчиках карты. Совпадение числа адресов
#: с одним из них — не доказательство предела, но повод назвать его отдельно.
КРУГЛЫЕ = (1000, 5000, 8000, 10000, 20000, 25000, 50000)

#: Максимум адресов в одном файле карты по протоколу sitemaps.org. Часть,
#: набитая ровно до него, законна, если за ней есть следующая часть.
ПРЕДЕЛ_ПРОТОКОЛА = 50000


def достать(url: str, таймаут: int = 60) -> tuple[str, str]:
    with tempfile.NamedTemporaryFile(prefix="sc-", suffix=".bin") as б:
        г = subprocess.run(
            ["curl", "-A", АГЕНТ, "-sS", "-L", "--max-time", str(таймаут), "-o", б.name,
             "-w", "%{http_code}", url],
            capture_output=True, text=True)
        тело = Path(б.name).read_text(encoding="utf-8", errors="replace")
    return (г.stdout or "").strip(), тело


def закрыта(тело: str) -> bool:
    """Закрыта ли страница от индексации по `meta robots`.

    Эта проверка здесь НЕ для красоты. 13.10 я сверил карту `animedia.space` со
    снимком, нашёл 528 адресов «в снимке есть, в карте нет», проверил у них код
    ответа и наличие `<h1>` — и записал дефект. Дефекта не было: страницы
    отвечают `200` с `noindex, follow` (записи вне тематического допуска), и
    карта опускает их верно. Признак из двух условий дал неверный ответ;
    третьего — индексируемости — не хватало.
    """
    м = re.search(r'<meta[^>]+name=["\']robots["\'][^>]*content=["\']([^"\']+)',
                  тело, re.I)
    return bool(м and "noindex" in м.group(1).lower())


def адреса_карты(домен: str) -> tuple[int, list[tuple[str, int]], str]:
    """(всего адресов, [(имя карты, адресов)], замечание про доступ).

    Счёт ведётся ПО КАЖДОЙ карте, а не только суммой: предел обходчика стоит
    внутри одной карты, и в сумме он растворяется. Измерено 13.10 на
    `yummyani.site`: всего 17 697 адресов в пяти картах, и это выглядит
    благополучно — а `titles.xml` в них ровно **8000**, что и есть B016.
    """
    код, тело = достать(f"https://{домен}/sitemap.xml")
    if код != "200":
        return -1, [], f"/sitemap.xml отвечает {код or 'пусто'}"
    вложенные = re.findall(r"<loc>([^<]+sitemap[^<]*)</loc>", тело)
    if not вложенные:
        сколько = len(re.findall(r"<loc>([^<]+)</loc>", тело))
        return сколько, [("sitemap.xml", сколько)], ""
    всего = 0
    обойдены: list[tuple[str, int]] = []
    for адрес in вложенные:
        к2, т2 = достать(адрес)
        if к2 != "200":
            return -1, обойдены, f"{адрес} отвечает {к2 or 'пусто'}"
        сколько = len(re.findall(r"<loc>([^<]+)</loc>", т2))
        всего += сколько
        обойдены.append((адрес.rsplit("/", 1)[-1], сколько))
    return всего, обойдены, ""


def видимый_текст(тело: str) -> str:
    """Текст, который ВИДИТ посетитель: без содержимого style и script.

    Срезание одних тегов недостаточно, и это измерено 20.10 на
    lordserials22.info: инструмент прочитал «витрина объявляет записей: 14»
    при 68 323 адресах в карте и напечатал расхождение 68 309 как безобидное.
    Источником четырнадцати оказался CSS-КОММЕНТАРИЙ — «Полка набирает
    РЯД_ПОЛКИ = 14 записей», — который после `re.sub("<[^>]+>")` стал обычным
    текстом страницы. Эталон брался из разметки оформления, а не из того, что
    витрина говорит посетителю.
    """
    без = re.sub(r"(?is)<(script|style)\b.*?</\1\s*>", " ", тело)
    без = re.sub(r"(?s)<!--.*?-->", " ", без)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", без))


def объявлено_записей(домен: str) -> tuple[int, str]:
    """(число, откуда). Эталон — то, что печатает сама страница каталога."""
    for путь in ("/catalog/", "/catalog"):
        код, тело = достать(f"https://{домен}{путь}", таймаут=45)
        if код != "200":
            continue
        текст = видимый_текст(тело)
        for шаблон, откуда in (
                (r"([\d\s  ]{3,})\s*записей в выборке", "«N записей в выборке»"),
                (r"([\d\s  ]{3,})\s*записей в разделе", "«N записей в разделе»"),
                (r"([\d\s  ]{3,})\s*тайтлов", "«N тайтлов»"),
                (r"([\d\s  ]{3,})\s*записей", "«N записей»")):
            м = re.search(шаблон, текст)
            if м:
                цифры = re.sub(r"[^\d]", "", м.group(1))
                if not цифры:
                    continue
                объявлено = int(цифры)
                # Страховка на любое другое нелепое прочтение: каталог не может
                # объявить записей МЕНЬШЕ, чем показывает на одной своей
                # странице. Такое число — ошибка разбора, и принимать его
                # эталоном значит объявить огромное расхождение безобидным.
                видно = _карточек(тело)
                if видно and объявлено < видно:
                    return по_листалке(
                        домен, тело,
                        f"прочитанное {откуда} дало {объявлено}, а на самой"
                        f" странице карточек {видно} — число отвергнуто")
                return объявлено, откуда
        return по_листалке(домен, тело)
    return -1, "страница каталога не отвечает"


def _карточек(тело: str) -> int:
    """Сколько карточек произведений на странице каталога."""
    return len(set(re.findall(r'href="(/(?:title|anime)/[^"?#]+)"', тело)))


def по_последней_непустой(домен: str, объявлено: int,
                          сетка: int) -> tuple[int, int] | None:
    """(размер каталога, номер последней непустой) двоичным поиском.

    Нужно там, где листалка объявляет больше страниц, чем несёт содержимого:
    измерено 20.10 на пяти витринах Yummy — объявлено 349, содержимое кончается
    на 334-й (333 × 24 + 8 = ровно 8 000, предел B016).

    Поиск двоичный, а не перебором: девять запросов вместо трёхсот. Границы
    честные — ищется первая пустая страница между второй и объявленной.
    """
    низ, верх = 2, объявлено
    if _на_странице(домен, низ) == 0:
        return None
    while низ + 1 < верх:
        середина = (низ + верх) // 2
        if _на_странице(домен, середина) > 0:
            низ = середина
        else:
            верх = середина
    на_последней = _на_странице(домен, низ)
    if на_последней <= 0:
        return None
    return (низ - 1) * сетка + на_последней, низ


def _на_странице(домен: str, номер: int) -> int:
    код, тело = достать(f"https://{домен}/catalog/?page={номер}", таймаут=45)
    return _карточек(тело) if код == "200" else 0


def по_листалке(домен: str, первая: str, почему: str = "") -> tuple[int, str]:
    """Эталон по собственной листалке каталога, когда числа записей нет.

    Измерено 20.10: ни одна из 17 индексируемых витрин не печатает «N
    записей», и проход выдавал «замечаний: 0» при НУЛЕ измерений. Но листалка
    объявляет число страниц сама (у animedia.icu — `?page=172`), и это тоже
    утверждение САМОГО сайта о размере своего каталога, а не моя оценка.

    Постоянство страницы проверяется, а не предполагается: если на второй
    странице карточек столько же, сколько на первой, итог считается точно; если
    нет — число не выдаётся вовсе. Оценка, выданная за измерение, хуже
    отсутствия измерения.
    """
    приставка = f"{почему}; " if почему else ""
    страницы = [int(н) for н in re.findall(r'href="[^"]*[?&]page=(\d+)"',
                                           первая)]
    if not страницы:
        return -1, (f"{приставка}ни числа записей, ни листалки на странице"
                    f" каталога нет")
    последняя = max(страницы)
    if последняя < 3:
        return -1, (f"{приставка}листалка объявляет всего {последняя} страниц"
                    f" — мало для сверки")

    сетка = _карточек(первая)
    if сетка == 0:
        return -1, f"{приставка}листалка есть, а карточек на первой странице нет"

    # На странице 2 и далее появляются ссылки ВНЕ сетки каталога — измерено
    # 20.10 на animedia.icu: первая 48, вторая и 171-я по 58, последняя 28.
    # Разность постоянна, и её надо вычесть, иначе итог завысится на 10 на
    # каждой странице. Постоянство ПРОВЕРЯЕТСЯ на двух серединных страницах:
    # предполагать её — значит выдать оценку за измерение.
    середины = {}
    for н in (2, max(3, последняя - 1)):
        код, тело = достать(f"https://{домен}/catalog/?page={н}", таймаут=45)
        if код != "200":
            return -1, (f"листалка объявляет {последняя} страниц, а страница"
                        f" {н} отвечает {код}")
        середины[н] = _карточек(тело)
    пустые = [н for н, к in середины.items() if к == 0]
    if пустые and сетка:
        # Пустая объявленная страница — дефект (MOD-108), но НЕ предел
        # измерения: размер каталога всё равно известен, если найти последнюю
        # страницу С СОДЕРЖИМЫМ. Прежде проход отказывался от измерения вовсе,
        # и полнота пяти витрин Yummy оставалась неизвестной при том, что
        # каталог измерим девятью запросами.
        итог = по_последней_непустой(домен, последняя, сетка)
        if итог:
            всего, где = итог
            return всего, (f"{приставка}листалка объявляет {последняя} страниц,"
                           f" но содержимое кончается на {где} — размер взят по"
                           f" ней ({где - 1} × {сетка} + остаток); объявленные"
                           f" пустые страницы это отдельный дефект")
    if пустые:
        # Отдельный исход, потому что это НАХОДКА, а не предел измерения.
        # Измерено 20.10 на всех пяти витринах Yummy: листалка объявляет 349
        # страниц, а страницы 335-349 отдают HTTP 200 и НОЛЬ карточек (350-я
        # честно 404). Пустая страница с кодом 200 тратит обход и попадает в
        # выдачу ни с чем.
        return -1, (f"{приставка}листалка объявляет {последняя} страниц, а"
                    f" страница {пустые[0]} отдаёт 200 и НОЛЬ карточек —"
                    f" объявленные пустые страницы это дефект, а не предел"
                    f" измерения")
    значения = sorted(set(середины.values()))
    if len(значения) != 1:
        return -1, (f"{приставка}листалка объявляет {последняя} страниц, но"
                    f" серединные страницы несут разное число карточек"
                    f" {середины} — точное число не выдаётся")
    лишние = значения[0] - сетка
    if лишние < 0:
        return -1, (f"{приставка}на серединной странице карточек МЕНЬШЕ,"
                    f" чем на первой"
                    f" ({значения[0]} против {сетка}) — разобраться, а не"
                    f" считать")

    код3, крайняя = достать(f"https://{домен}/catalog/?page={последняя}",
                            таймаут=45)
    if код3 != "200":
        return -1, (f"{приставка}листалка объявляет {последняя} страниц, а"
                    f" последняя отвечает {код3}")
    на_последней = _карточек(крайняя) - лишние
    if на_последней <= 0:
        return -1, (f"{приставка}листалка объявляет {последняя} страниц, а"
                    f" на последней карточек сетки нет")
    всего = (последняя - 1) * сетка + на_последней
    return всего, (f"{приставка}по собственной листалке: {последняя - 1}"
                   f" × {сетка}"
                   f" + {на_последней} на последней"
                   f" (вне сетки на странице: {лишние})")


def домены() -> list[str]:
    if not ПАСПОРТ.is_file():
        return []
    ячейки = json.loads(ПАСПОРТ.read_text(encoding="utf-8")).get("cells") or []
    print(f"паспорт ячеек: {ПАСПОРТ} (ячеек {len(ячейки)})")
    return [str(я["domain"]) for я in ячейки
            if я.get("domain")
            and not str(я["domain"]).endswith((".test", ".localhost"))]


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("домены", nargs="*")
    р.add_argument("--all", action="store_true")
    а = р.parse_args()
    цели = а.домены or (домены() if а.all else [])
    if not цели:
        print("не названо ни одной витрины: домен аргументом или --all")
        return 2

    замечания: list[str] = []
    неизмеренные: list[str] = []
    for домен in цели:
        адресов, карты, беда = адреса_карты(домен)
        записей, откуда = объявлено_записей(домен)
        print(f"\n=== {домен}")
        if адресов < 0:
            print(f"   карта НЕ ИЗМЕРЕНА: {беда}")
            неизмеренные.append(домен)
            continue
        print(f"   адресов в карте: {адресов} (карт: {len(карты)})")
        for имя, сколько in карты:
            предел = " ← РОВНО круглое число" if сколько in КРУГЛЫЕ else ""
            print(f"      {имя:24} {сколько}{предел}")
        # С каким числом сравнивать каталог. Если карта разбита по смыслу и в
        # ней есть часть произведений, сравнивать надо с НЕЙ, а не с суммой:
        # измерено 20.10 на yummyani.site — сумма 18 200 против каталога 8 000
        # дала «разницу 10 200: разделы и служебные адреса», тогда как эти
        # 10 200 — картинки, сезоны и серии. Сравнение суммы с числом
        # произведений бессмысленно, и подпись к нему была прямо неверна.
        титулы = next((с for и, с in карты if и.startswith("titles")), None)
        основа = титулы if титулы is not None else адресов
        if титулы is not None:
            print(f"   сравниваю каталог с частью произведений:"
                  f" {титулы} адресов (а не с суммой {адресов} —"
                  f" в сумме картинки, сезоны и серии)")
        адресов = основа
        # Предел внутри ОДНОЙ карты — находка сама по себе, и она не зависит от
        # того, удалось ли прочитать объявленное число записей.
        #
        # Но 50 000 — это не «круглое число», а МАКСИМУМ протокола
        # sitemaps.org на один файл, и разбиение на части ровно по нему
        # законно. Измерено 2026-10-18: у yummyani.biz `episodes.xml` и
        # `episodes-2.xml` по 50 000 адресов, а `episodes-3.xml` — 23 188, то
        # есть цепочка просто продолжается, всего 123 188. Прежнее условие
        # называло это пределом обходчика и дало восемь ложных находок на
        # четырёх витринах Yummy за один прогон.
        #
        # Поэтому часть на 50 000 замечанием НЕ является, когда за ней в
        # цепочке есть следующая часть: предел обходчика выглядит иначе —
        # цепочка на нём ОБРЫВАЕТСЯ.
        for н, (имя, сколько) in enumerate(карты):
            if сколько not in КРУГЛЫЕ:
                continue
            последняя = н == len(карты) - 1
            if сколько == ПРЕДЕЛ_ПРОТОКОЛА and not последняя:
                continue
            замечания.append(
                f"{домен}: в {имя} ровно {сколько} адресов"
                + (" (и это последняя часть цепочки)" if последняя else "")
                + " — круглое число внутри одной карты похоже на предел "
                "обходчика, а не на конец набора (так выглядит B016 у Yummy)")
        if записей < 0:
            print(f"   записей не измерено: {откуда}")
            print("   вывод о полноте НЕ делается: сравнивать не с чем")
            неизмеренные.append(домен)
            continue
        print(f"   витрина объявляет записей: {записей} — {откуда}")
        if адресов in КРУГЛЫЕ and записей > адресов:
            замечания.append(
                f"{домен}: адресов в карте РОВНО {адресов} при объявленных "
                f"{записей} записях — круглое число похоже на предел обходчика "
                "карты, а не на конец каталога")
        elif записей > адресов:
            не_названо = записей - адресов
            доля = не_названо / записей * 100
            замечания.append(
                f"{домен}: в карте {адресов} адресов при {записей} объявленных "
                f"записях — расхождение {не_названо} ({доля:.1f} %). ЭТО ЕЩЁ НЕ "
                "ДЕФЕКТ: страницу с `noindex` наша сеть в карте не перечисляет "
                "(правило сети, а не требование Яндекса), и прежде "
                "чем называть потерю, у недостающих адресов проверяется "
                "индексируемость, а не только код ответа (см. `закрыта`)")
        else:
            лишние = адресов - записей
            if титулы is not None:
                # Сравнение идёт с частью ПРОИЗВЕДЕНИЙ, значит лишние — это не
                # разделы и не страницы листалки: их в этой части нет. Это
                # произведения, которые есть в карте и недостижимы обходом
                # каталога. Измерено 20.10 на yummyani.site: 363, и это
                # ровно вторая половина MOD-108.
                print(f"   в карте произведений БОЛЬШЕ, чем достижимо обходом"
                      f" каталога: {лишние}. Это не разделы — в части"
                      f" произведений их нет; это записи, до которых посетитель"
                      f" через каталог не доходит")
            else:
                print(f"   карта не меньше каталога (разница {лишние}: разделы, "
                      "страницы листалки и служебные адреса)")

    print(f"\n{'=' * 60}\nзамечаний: {len(замечания)}")
    for з in замечания:
        print(f"  • {з}")

    # Отдельная строка, и она не вежливость. Измерено 20.10: на всех 17
    # индексируемых домéнах страница каталога перестала печатать число записей,
    # и проход выдал «замечаний: 0» — то есть главный вопрос («полна ли карта»)
    # не был измерен НИ РАЗУ, а итог читался как «всё в порядке». Код возврата
    # тоже был нулевым. Ноль замечаний при нуле измерений успехом не является.
    if неизмеренные:
        print(f"\nПОЛНОТА НЕ ИЗМЕРЕНА у {len(неизмеренные)} домéнов из"
              f" {len(цели)}: {', '.join(неизмеренные)}")
        print("   «замечаний: 0» по этим домéнам означает «не с чем сравнивать»,"
              " а НЕ «карта полна».")
    if замечания:
        return 1
    return 2 if неизмеренные else 0


