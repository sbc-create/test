#!/usr/bin/env python3
"""Сколько адресов в карте сайта против того, сколько витрина объявляет записей.

Класс уже доказан: B016 — карта `yummyani.site` обрезана ровно на 8000 адресах
(`walkAnimeListItems(maxPages=80, limit=100)`), и 366 живых тайтлов в неё не
попали. Вопрос «а у остальных?» меряется, а не предполагается.

Эталон берётся **из того, что витрина объявляет о себе сама**: страница каталога
печатает число записей («N записей в выборке», «N тайтлов»). Своё
представление о размере каталога я не подставляю — по правилу, выведенному
этой же ночью: ответ не должен быть свойством выбранного мной источника.

Что считается расхождением:

* адресов в карте **меньше** объявленных записей — часть каталога поисковику не
  названа;
* круглое число адресов (8000, 10000, 20000…) при объявленных записях больше —
  признак предела в обходчике карты, а не конца каталога. Исключение измерено
  2026-10-18: 50 000 — это максимум протокола на один файл, и часть, набитая
  ровно до него, законна, если цепочка за ней ПРОДОЛЖАЕТСЯ (у yummyani.biz
  `episodes.xml` и `-2.xml` по 50 000, а `-3.xml` — 23 188). Прежнее условие
  дало на этом восемь ложных находок за один прогон;
* карта отвечает не 200 — и тогда «меньше» не считается вовсе: это НЕ ИЗМЕРЕНО.

Инструмент только читает публичные адреса.

    python3 automation/local/sitemap-completeness.py zonafilm.space
    python3 automation/local/sitemap-completeness.py --all
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ПАСПОРТ = Path("/home/claude/wt-portable-site-cell-01/config/site-cells.json")
#: Круглые пределы, которые ставят в обходчиках карты. Совпадение числа адресов
#: с одним из них — не доказательство предела, но повод назвать его отдельно.
КРУГЛЫЕ = (1000, 5000, 8000, 10000, 20000, 25000, 50000)

#: Максимум адресов в одном файле карты по протоколу sitemaps.org. Часть,
#: набитая ровно до него, законна, если за ней есть следующая часть.
ПРЕДЕЛ_ПРОТОКОЛА = 50000


def достать(url: str, таймаут: int = 60) -> tuple[str, str]:
    with tempfile.NamedTemporaryFile(prefix="sc-", suffix=".bin") as б:
        г = subprocess.run(
            ["curl", "-sS", "-L", "--max-time", str(таймаут), "-o", б.name,
             "-w", "%{http_code}", url],
            capture_output=True, text=True)
        тело = Path(б.name).read_text(encoding="utf-8", errors="replace")
    return (г.stdout or "").strip(), тело


def закрыта(тело: str) -> bool:
    """Закрыта ли страница от индексации по `meta robots`.

    Эта проверка здесь НЕ для красоты. 13.10 я сверил карту `animedia.space` со
    снимком, нашёл 528 адресов «в снимке есть, в карте нет», проверил у них код
    ответа и наличие `<h1>` — и записал дефект. Дефекта не было: страницы
    отвечают `200` с `noindex, follow` (записи вне тематического допуска), и
    карта опускает их верно. Признак из двух условий дал неверный ответ;
    третьего — индексируемости — не хватало.
    """
    м = re.search(r'<meta[^>]+name=["\']robots["\'][^>]*content=["\']([^"\']+)',
                  тело, re.I)
    return bool(м and "noindex" in м.group(1).lower())


def адреса_карты(домен: str) -> tuple[int, list[tuple[str, int]], str]:
    """(всего адресов, [(имя карты, адресов)], замечание про доступ).

    Счёт ведётся ПО КАЖДОЙ карте, а не только суммой: предел обходчика стоит
    внутри одной карты, и в сумме он растворяется. Измерено 13.10 на
    `yummyani.site`: всего 17 697 адресов в пяти картах, и это выглядит
    благополучно — а `titles.xml` в них ровно **8000**, что и есть B016.
    """
    код, тело = достать(f"https://{домен}/sitemap.xml")
    if код != "200":
        return -1, [], f"/sitemap.xml отвечает {код or 'пусто'}"
    вложенные = re.findall(r"<loc>([^<]+sitemap[^<]*)</loc>", тело)
    if not вложенные:
        сколько = len(re.findall(r"<loc>([^<]+)</loc>", тело))
        return сколько, [("sitemap.xml", сколько)], ""
    всего = 0
    обойдены: list[tuple[str, int]] = []
    for адрес in вложенные:
        к2, т2 = достать(адрес)
        if к2 != "200":
            return -1, обойдены, f"{адрес} отвечает {к2 or 'пусто'}"
        сколько = len(re.findall(r"<loc>([^<]+)</loc>", т2))
        всего += сколько
        обойдены.append((адрес.rsplit("/", 1)[-1], сколько))
    return всего, обойдены, ""


def объявлено_записей(домен: str) -> tuple[int, str]:
    """(число, откуда). Эталон — то, что печатает сама страница каталога."""
    for путь in ("/catalog/", "/catalog"):
        код, тело = достать(f"https://{домен}{путь}", таймаут=45)
        if код != "200":
            continue
        текст = re.sub(r"<[^>]+>", " ", тело)
        текст = re.sub(r"\s+", " ", текст)
        for шаблон, откуда in (
                (r"([\d\s  ]{3,})\s*записей в выборке", "«N записей в выборке»"),
                (r"([\d\s  ]{3,})\s*записей в разделе", "«N записей в разделе»"),
                (r"([\d\s  ]{3,})\s*тайтлов", "«N тайтлов»"),
                (r"([\d\s  ]{3,})\s*записей", "«N записей»")):
            м = re.search(шаблон, текст)
            if м:
                цифры = re.sub(r"[^\d]", "", м.group(1))
                if цифры:
                    return int(цифры), откуда
        return -1, "страница каталога числа записей не печатает"
    return -1, "страница каталога не отвечает"


def домены() -> list[str]:
    if not ПАСПОРТ.is_file():
        return []
    ячейки = json.loads(ПАСПОРТ.read_text(encoding="utf-8")).get("cells") or []
    return [str(я["domain"]) for я in ячейки
            if я.get("domain")
            and not str(я["domain"]).endswith((".test", ".localhost"))]


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("домены", nargs="*")
    р.add_argument("--all", action="store_true")
    а = р.parse_args()
    цели = а.домены or (домены() if а.all else [])
    if not цели:
        print("не названо ни одной витрины: домен аргументом или --all")
        return 2

    замечания: list[str] = []
    for домен in цели:
        адресов, карты, беда = адреса_карты(домен)
        записей, откуда = объявлено_записей(домен)
        print(f"\n=== {домен}")
        if адресов < 0:
            print(f"   карта НЕ ИЗМЕРЕНА: {беда}")
            continue
        print(f"   адресов в карте: {адресов} (карт: {len(карты)})")
        for имя, сколько in карты:
            предел = " ← РОВНО круглое число" if сколько in КРУГЛЫЕ else ""
            print(f"      {имя:24} {сколько}{предел}")
        # Предел внутри ОДНОЙ карты — находка сама по себе, и она не зависит от
        # того, удалось ли прочитать объявленное число записей.
        #
        # Но 50 000 — это не «круглое число», а МАКСИМУМ протокола
        # sitemaps.org на один файл, и разбиение на части ровно по нему
        # законно. Измерено 2026-10-18: у yummyani.biz `episodes.xml` и
        # `episodes-2.xml` по 50 000 адресов, а `episodes-3.xml` — 23 188, то
        # есть цепочка просто продолжается, всего 123 188. Прежнее условие
        # называло это пределом обходчика и дало восемь ложных находок на
        # четырёх витринах Yummy за один прогон.
        #
        # Поэтому часть на 50 000 замечанием НЕ является, когда за ней в
        # цепочке есть следующая часть: предел обходчика выглядит иначе —
        # цепочка на нём ОБРЫВАЕТСЯ.
        for н, (имя, сколько) in enumerate(карты):
            if сколько not in КРУГЛЫЕ:
                continue
            последняя = н == len(карты) - 1
            if сколько == ПРЕДЕЛ_ПРОТОКОЛА and not последняя:
                continue
            замечания.append(
                f"{домен}: в {имя} ровно {сколько} адресов"
                + (" (и это последняя часть цепочки)" if последняя else "")
                + " — круглое число внутри одной карты похоже на предел "
                "обходчика, а не на конец набора (так выглядит B016 у Yummy)")
        if записей < 0:
            print(f"   записей не измерено: {откуда}")
            print("   вывод о полноте НЕ делается: сравнивать не с чем")
            continue
        print(f"   витрина объявляет записей: {записей} — {откуда}")
        if адресов in КРУГЛЫЕ and записей > адресов:
            замечания.append(
                f"{домен}: адресов в карте РОВНО {адресов} при объявленных "
                f"{записей} записях — круглое число похоже на предел обходчика "
                "карты, а не на конец каталога")
        elif записей > адресов:
            не_названо = записей - адресов
            доля = не_названо / записей * 100
            замечания.append(
                f"{домен}: в карте {адресов} адресов при {записей} объявленных "
                f"записях — расхождение {не_названо} ({доля:.1f} %). ЭТО ЕЩЁ НЕ "
                "ДЕФЕКТ: страница с `noindex` в карте быть НЕ должна, и прежде "
                "чем называть потерю, у недостающих адресов проверяется "
                "индексируемость, а не только код ответа (см. `закрыта`)")
        else:
            лишние = адресов - записей
            print(f"   карта не меньше каталога (разница {лишние}: разделы, "
                  "страницы листалки и служебные адреса)")

    print(f"\n{'=' * 60}\nзамечаний: {len(замечания)}")
    for з in замечания:
        print(f"  • {з}")
    return 1 if замечания else 0


if __name__ == "__main__":
    sys.exit(main())
