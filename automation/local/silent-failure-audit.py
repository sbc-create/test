#!/usr/bin/env python3
"""Места в сценариях оболочки, где отказ не может изменить итог.

Зачем. 12.10 на трёх витринах проверка видимых крошек молчала: строка
`check "visible-breadcrumbs" …` стояла в файле, где обёртка называется `step`.
bash ответил «command not found» с кодом 127, и код прогона от этого не
изменился. Нашлось случайно, на полном прогоне одной ячейки. Случайность — не
способ, и класс этот не единственный: за тот же вечер я дважды сам читал код
возврата из конвейера, где он принадлежит последнему звену, а не первому.

Инструмент называет четыре вида, каждый — отказ, который не доходит до итога:

  КОД_ИЗ_КОНВЕЙЕРА     `$?` после конвейера без `pipefail`: он принадлежит
                       последнему звену, и отказ первого теряется
  ОТКАЗ_ПОГЛОЩЁН       `|| true` и `|| :` — отказ объявлен несущественным.
                       Иногда это и правда так, поэтому строка печатается
                       целиком: судит человек, а не образец
  ОШИБКИ_В_НИКУДА      `2>/dev/null` без проверки кода рядом: причина отказа
                       уничтожена, а сам отказ не замечен

Чего здесь НЕТ и почему. Вид «вызов команды, которой не существует» — прямой
общий случай находки 12.10 — был написан и УБРАН: на `automation/` он дал 649
находок, потом 129, 22, 16, 10, и ни одной настоящей. Остаток требует учёта
вложенности `$( )` внутри кавычек, то есть разборщика оболочки: строка
`port="$("$PY" -c "` содержит чётное число кавычек и для наивного учёта
заканчивается вне строки, хотя на деле внутри. Признак с десятью ложными
находками приучает не читать вывод — и тогда виды ниже, которые сигнал дают,
тоже перестанут читать.

Класс без защиты не остался: в ячейках, где он и проявился, его ловит
`run-sh-guard-audit.py` — сравнением ОБЪЯВЛЕННОГО числа проверок с
ИСПОЛНЕННЫМ. Поведенческая мера надёжнее разбора: ей всё равно, почему
проверка не исполнилась.

Ничего не меняет: только читает. «Не разобрано» не выдаётся за исправность —
файл, который не прочитался, называется отдельно.

    python3 automation/local/silent-failure-audit.py
    python3 automation/local/silent-failure-audit.py --path factory/cell
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]

КОД_ИЗ_КОНВЕЙЕРА = "КОД_ИЗ_КОНВЕЙЕРА"
ОТКАЗ_ПОГЛОЩЁН = "ОТКАЗ_ПОГЛОЩЁН"
ОШИБКИ_В_НИКУДА = "ОШИБКИ_В_НИКУДА"

#: Строка, начинающаяся с этого, командой не является.
НЕ_КОМАНДА = re.compile(r"^\s*(?:#|$|\}|\{|\)|;;|\||&&|\|\||!)")
#: Ветвь `case`: образец, затем `)`, затем команда. Первое слово здесь — не
#: команда, а значение, с которым сравнивают: `deploy)   shift; …`.
ВЕТВЬ_CASE = re.compile(r"^\s*[^()\s][^()]*\)(?:\s|$)")
#: Начало heredoc: `<<МЕТКА`, `<< МЕТКА`, `<<-МЕТКА`, `<<"МЕТКА"`, `<<'МЕТКА'`.
# Метка может быть не из ASCII: в этом хозяйстве имена пишут по-русски, и
# `<<-'КОНЕЦ'` — допустимая форма. Прежний образец её не узнавал, и тело
# heredoc разбиралось как команды. Тот же подвох с не-ASCII уже встречался
# вечером в обходе дерева, где он ломал сверку путей.
НАЧАЛО_HEREDOC = re.compile(r"<<-?\s*['\"]?(\w+)['\"]?")
#: Строка продолжается: следующая строка — не начало команды.
ПРОДОЛЖЕНИЕ = re.compile(r"(?:\\|\||&&|\|\|)\s*(?:#.*)?$")


def кавычки_после(строка: str, было: str | None) -> str | None:
    """Внутри какой кавычки заканчивается строка, либо None.

    Нужна для многострочных аргументов: `sh -c "…"` на десяток строк — это
    ОДНА команда, а не десяток. Внутри одинарных кавычек обратная косая не
    экранирует — так устроена оболочка, и это не упрощение.
    """
    состояние = было
    пропустить = False
    предыдущий = " "
    for знак in строка:
        # Комментарий вне кавычек обрывает разбор строки. Без этого апостроф в
        # английском комментарии («host's own state» во второй строке
        # site-factory-backup.sh) открывал кавычку, которая не закрывается, и
        # весь учёт ниже сдвигался: питон внутри `python3 -c '…'` оказывался
        # «командами», а настоящие данные — нет. Один апостроф в комментарии
        # ломал разбор всего файла.
        if состояние is None and знак == "#" and предыдущий in " \t":
            break
        предыдущий = знак
        if пропустить:
            пропустить = False
            continue
        if состояние == "'":
            if знак == "'":
                состояние = None
            continue
        if знак == "\\":
            пропустить = True
            continue
        if состояние == '"':
            if знак == '"':
                состояние = None
            continue
        if знак in "'\"":
            состояние = знак
    return состояние


def разобрать(текст: str) -> list[tuple[int, str, str]]:
    """Находки по тексту сценария: (строка, вид, сама строка)."""
    строки = текст.splitlines()
    pipefail = bool(re.search(r"set\s+[-A-Za-z]*o\s+pipefail|set\s+-o\s+pipefail",
                              текст))
    находки: list[tuple[int, str, str]] = []
    #: Метка открытого heredoc. Пока она задана, строки — данные, не команды.
    метка: str | None = None
    #: Предыдущая строка продолжается — значит эта не начало команды.
    продолжается = False
    #: Незакрытая кавычка с предыдущей строки: тогда эта строка — данные.
    кавычка: str | None = None
    for н, строка in enumerate(строки, 1):
        без_пробелов = строка.strip()
        начали_внутри = кавычка is not None
        кавычка = кавычки_после(строка, кавычка)
        if начали_внутри:
            continue

        # Тело heredoc целиком пропускается. Это и было причиной 649 ложных
        # находок первого прогона: питон и текст сводок внутри `<<PY … PY`
        # разбирались как команды оболочки.
        if метка is not None:
            if без_пробелов == метка:
                метка = None
            continue
        начало = НАЧАЛО_HEREDOC.search(строка)
        if начало:
            метка = начало.group(1)
            # Саму строку с `<<` разобрать всё равно надо: команда в ней есть.

        предыдущее_продолжалось = продолжается
        продолжается = bool(ПРОДОЛЖЕНИЕ.search(строка))

        if НЕ_КОМАНДА.match(строка) or ВЕТВЬ_CASE.match(строка):
            continue
        if предыдущее_продолжалось:
            # Это хвост предыдущей команды, а не новая команда.
            continue

        # 2. Код возврата из конвейера.
        if "$?" in строка and not pipefail:
            # Конвейер ищется в этой же строке или в предыдущей: `$?` обычно
            # читают на следующей строке после команды.
            рядом = строки[max(0, н - 2):н]
            if any("|" in с and "||" not in с for с in рядом):
                находки.append((н, КОД_ИЗ_КОНВЕЙЕРА, без_пробелов))

        # 3. Отказ объявлен несущественным.
        if re.search(r"\|\|\s*(?:true|:)\s*(?:#.*)?$", строка):
            находки.append((н, ОТКАЗ_ПОГЛОЩЁН, без_пробелов))

        # 4. Ошибки в никуда без проверки кода.
        if "2>/dev/null" in строка and not re.search(r"\|\||&&|if |\$\?", строка):
            находки.append((н, ОШИБКИ_В_НИКУДА, без_пробелов))
    return находки


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--path", default="automation",
                   help="каталог внутри репозитория (по умолчанию automation)")
    р.add_argument("--kind", default="",
                   help="показать только один вид находок")
    опции = р.parse_args(аргв)

    корень = КОРЕНЬ / опции.path
    if not корень.exists():
        print(f"каталога нет: {корень}", file=sys.stderr)
        return 2

    файлы = sorted(п for п in корень.rglob("*.sh") if п.is_file())
    по_видам: dict[str, int] = {}
    непрочитанных: list[str] = []
    всего = 0
    for файл in файлы:
        try:
            текст = файл.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as сбой:
            непрочитанных.append(f"{файл.name}: {type(сбой).__name__}")
            continue
        находки = разобрать(текст)
        if опции.kind:
            находки = [н for н in находки if н[1] == опции.kind]
        if not находки:
            continue
        отн = файл.relative_to(КОРЕНЬ).as_posix()
        print(f"\n{отн}")
        for номер, вид, строка in находки:
            по_видам[вид] = по_видам.get(вид, 0) + 1
            всего += 1
            print(f"   {отн}:{номер}  [{вид}]")
            print(f"      {строка[:120]}")

    print(f"\nсценариев прочитано: {len(файлы) - len(непрочитанных)}")
    print(f"находок: {всего}")
    for вид in (КОД_ИЗ_КОНВЕЙЕРА, ОТКАЗ_ПОГЛОЩЁН, ОШИБКИ_В_НИКУДА):
        print(f"   {вид:22s} {по_видам.get(вид, 0)}")
    if непрочитанных:
        print(f"НЕ РАЗОБРАНО: {len(непрочитанных)} — это предел измерения, "
              "а не исправность", file=sys.stderr)
        for строка in непрочитанных:
            print(f"   {строка}", file=sys.stderr)
        return 2
    # Код возврата из конвейера — всегда дефект: отказ первого звена теряется.
    # Два других вида требуют суждения, поэтому отдельный код: их наличие не
    # обязано валить прогон, но и «ок» это не значит.
    if по_видам.get(КОД_ИЗ_КОНВЕЙЕРА):
        return 1
    return 3 if всего else 0


if __name__ == "__main__":
    raise SystemExit(главное())
