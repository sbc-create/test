#!/usr/bin/env python3
"""Какие опыты сети ДЕЙСТВУЮТ сейчас и чего из-за них нельзя. Только чтение.

ЗАЧЕМ. Задача, выросшая из исследования, может повторять гипотезу уже
идущего опыта — и тогда её исполнение нарушает правило канарейки: до
заслуженного вердикта гипотеза на другие домены не переносится. Измерено на
себе 22.10: я завела две такие задачи (серии в карте Animedia и страница
онгоингов), потому что реестр опытов В МОЕЙ копии содержит только
демонстрационный прогон, а действующие опыты живут в копии владельца
регулярного цикла. Это тот же корень, что у MOD-137: расхождение копий.

Поэтому инструмент читает реестр ТОЙ копии, которая объявлена владельцем в
`config/active-domains.json`, и печатает действующие опыты с канарейкой и
сроком вердикта. Своего реестра он не правит и ничего не публикует.

    python3 automation/local/running-experiments.py
    python3 automation/local/running-experiments.py --json

Коды: 0 — реестр прочитан (с `--domain`: домен в опытах не упомянут);
2 — реестр не прочитан (тогда задачу по гипотезе, похожей на опыт, НЕ
создавать: проверить нечем); 3 — с `--domain`: домен УПОМЯНУТ в действующем
опыте, и запись надо прочитать прежде, чем менять витрину.

ДВА РАЗНЫХ ЗАПРЕТА, и второй я чуть не нарушила 22.10 (см. ниже):
гипотеза действующего опыта не переносится на другие домены — и домен,
служащий опыту КОНТРОЛЕМ, не меняется вовсе, иначе сравнивать не с чем.
Контроли названы в поле `applicability`, а не в поле канарейки.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
СПИСОК = КОРЕНЬ / "config" / "active-domains.json"
КОПИИ = pathlib.Path("/home/claude")
#: Фазы, при которых опыт ещё НЕ завершён и правило канарейки действует.
ДЕЙСТВУЮТ = ("planned", "canary", "observing", "running", "widening")


def владелец_опытов() -> str:
    """Чья копия ведёт реестр опытов. Берётся из объявления, не из догадки."""
    д = json.loads(СПИСОК.read_text(encoding="utf-8"))
    общие = д.get("shared_components") or {}
    запись = общие.get("experiments") or общие.get("regular_cycle") or {}
    return str(запись.get("owner") or "")


def реестры() -> list[pathlib.Path]:
    """Свой реестр и реестр копии-владельца. Порядок: владелец важнее."""
    пути = []
    хозяин = владелец_опытов()
    if хозяин:
        пути.append(КОПИИ / хозяин / "config" / "experiments.json")
    пути.append(КОРЕНЬ / "config" / "experiments.json")
    return [п for п in пути if п.is_file()]


def прочитать(путь: pathlib.Path) -> list[dict]:
    д = json.loads(путь.read_text(encoding="utf-8"))
    записи = д.get("experiments") if isinstance(д, dict) else д
    return list(записи or [])


def действующие(записи: list[dict]) -> list[dict]:
    """Опыты, по которым вердикта ещё нет. Чистая функция."""
    итог = []
    for з in записи:
        if з.get("synthetic"):
            continue
        фаза = str(з.get("phase") or z_ст(з) or "")
        если_вердикт = з.get("verdict")
        if если_вердикт in (None, "", "pending") or фаза in ДЕЙСТВУЮТ:
            итог.append(з)
    return итог


def z_ст(з: dict) -> str:
    return str(з.get("status") or "")


#: Поля, упоминание в которых означает УЧАСТИЕ домена в опыте: применимость
#: перечисляет канарейку и контроли, метрика называет, что с чем сравнивается.
ПОЛЯ_УЧАСТИЯ = ("applicability", "primary_metric", "canary", "site_id")
#: Поля, упоминание в которых чаще означает ССЫЛКУ на прежнее измерение.
#: Измерено 22.10: `yummyani.site` назван в гипотезе опыта AnimeGo как
#: источник числа («77 % у yummyani.site, аудит 13.10»), а контролем не
#: является — контроли того опыта перечислены в применимости.
ПОЛЯ_ССЫЛКИ = ("hypothesis", "evidence", "notes")


def вид_упоминания(поля: list[str]) -> str:
    """Что следует из НАБОРА полей. Это подсказка к чтению, а не роль.

    Три значения, и третье обязательно: поля, которых мера не знает, не
    молчат — иначе новое поле реестра тихо превратилось бы в «ссылку».
    """
    участие = [п for п in поля if п in ПОЛЯ_УЧАСТИЯ]
    ссылка = [п for п in поля if п in ПОЛЯ_ССЫЛКИ]
    прочее = [п for п in поля if п not in ПОЛЯ_УЧАСТИЯ and п not in ПОЛЯ_ССЫЛКИ]
    if участие:
        return "участник"
    if прочее:
        return "поле не распознано"
    if ссылка:
        return "ссылка"
    return "поле не распознано"


#: Где искать упоминание домена. Поля перечислены явно: контроли живут в
#: `applicability`, и пропустить это поле значит не увидеть контроль.
ПОЛЯ_ТЕКСТА = ("hypothesis", "applicability", "primary_metric", "evidence",
               "canary", "site_id", "notes")


def упоминания(домен: str, опыты: list[dict],
               ячейка: str = "") -> list[dict]:
    """Где домен назван в действующих опытах. Это ПОВОД ПРОЧИТАТЬ, не вывод.

    Отличие от ошибки, которую я уже делала (привязка недостатка к домену по
    тексту, дважды давшая ложную область): там из упоминания делался ВЫВОД
    «дефект относится к этому домену». Здесь вывода нет — печатается «домен
    назван в таком-то поле такого-то опыта, прочти запись». Решение остаётся
    за записью опыта, и превращать это в вывод нельзя.

    Имя домена — различимая строка, поэтому поиск подстрокой надёжен; имя
    ячейки (`animego-03`) ищется наравне с доменом, потому что применимость
    пишется и так и так.
    """
    итог = []
    иглы = [и for и in (домен, ячейка) if и]
    for з in опыты:
        где = []
        for поле in ПОЛЯ_ТЕКСТА:
            зн = str(з.get(поле) or "")
            if any(и and и in зн for и in иглы):
                где.append(поле)
        if где:
            канарейка = str(з.get("canary") or з.get("site_id") or "")
            итог.append({"опыт": з.get("experiment_id") or з.get("id") or "?",
                         "канарейка": канарейка,
                         # Поле канарейки несёт то домен, то ИМЯ ЯЧЕЙКИ
                         # (`animego-04`), поэтому сравнивается с обеими
                         # иглами. Иначе канарейка читалась бы как контроль.
                         "канарейка_это_он": any(
                             и and и in канарейка for и in иглы),
                         "поля": где,
                         "вид": вид_упоминания(где),
                         "применимость": str(з.get("applicability") or "")})
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true")
    р.add_argument("--domain", default="",
                   help="упомянут ли домен в действующем опыте —"
                        " как канарейка ИЛИ как контроль")
    р.add_argument("--cell", default="",
                   help="имя ячейки домена: поле канарейки несёт то домен,"
                        " то имя ячейки")
    а = р.parse_args(аргв)

    пути = реестры()
    if not пути:
        print("реестр опытов не прочитан ни в одной копии:"
              " задачу по гипотезе, похожей на опыт, НЕ создавать —"
              " проверить нечем", file=sys.stderr)
        return 2

    итог = []
    for п in пути:
        try:
            записи = прочитать(п)
        except ValueError as e:
            print(f"{п}: не разобран ({e})", file=sys.stderr)
            continue
        дей = действующие(записи)
        итог.append({"реестр": str(п), "всего": len(записи),
                     "действующих": len(дей), "опыты": дей})

    if а.domain:
        все_опыты = [о for и in итог for о in и["опыты"]]
        найдено = упоминания(а.domain, все_опыты, а.cell)
        if а.json:
            print(json.dumps({"домен": а.domain, "упоминания": найдено},
                             ensure_ascii=False, indent=1))
            return 0 if not найдено else 3
        if not найдено:
            print(f"{а.domain}: в действующих опытах не упомянут —"
                  " ни канарейкой, ни контролем")
            return 0
        print(f"{а.domain} УПОМЯНУТ в действующих опытах — прочти записи"
              " прежде, чем менять витрину:")
        for н in найдено:
            if н["канарейка_это_он"]:
                роль = "КАНАРЕЙКА"
            elif н["вид"] == "участник":
                роль = "назван в применимости/метрике: возможен КОНТРОЛЬ"
            elif н["вид"] == "ссылка":
                роль = ("назван только в гипотезе/доказательстве: вероятно"
                        " ССЫЛКА на прежний замер, а не участие")
            else:
                роль = ("поле упоминания мере неизвестно — прочти запись"
                        " целиком")
            print(f"   {н['опыт']} | {роль} | поля: {', '.join(н['поля'])}")
            if н["применимость"]:
                print(f"      применимость: {н['применимость']}")
        print("\nЭто ПОВОД ПРОЧИТАТЬ запись, а не вывод о роли домена: роль"
              " определяет сама запись опыта. Контроль менять нельзя вовсе —"
              " иначе сравнивать не с чем.")
        return 3

    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
        return 0

    print(f"владелец реестра опытов по объявлению: {владелец_опытов() or '—'}")
    for и in итог:
        своя = и["реестр"].startswith(str(КОРЕНЬ))
        print(f"\n{'СВОЯ копия' if своя else 'копия ВЛАДЕЛЬЦА'}:"
              f" {и['реестр']}")
        print(f"   записей {и['всего']}, действующих {и['действующих']}")
        for з in и["опыты"]:
            срок = (з.get("verdict_due") or з.get("decision_due")
                    or з.get("observation_until") or "срок не назван")
            канарейка = (з.get("canary") or з.get("site_id")
                         or "канарейка не названа")
            print(f"      {з.get('experiment_id') or з.get('id') or '?'}"
                  f" | канарейка {канарейка} | вердикт {срок}")
            гип = str(з.get("hypothesis") or "")
            if гип:
                print(f"         гипотеза: {гип[:110]}")
            # Применимость печатается ПОЛНОСТЬЮ и намеренно: контроли опыта
            # названы именно здесь, а не в поле канарейки, и обрезка скрыла бы
            # как раз их. Измерено на себе 22.10 — см. docstring модуля.
            прим = str(з.get("applicability") or "")
            if прим:
                print(f"         применимость (ЗДЕСЬ НАЗВАНЫ КОНТРОЛИ): {прим}")
            else:
                print("         применимость НЕ НАЗВАНА: контроли опыта"
                      " неизвестны, и считать их отсутствующими нельзя")
    print("\nПРАВИЛО 1: до заслуженного вердикта гипотеза действующего опыта на"
          " другие домены НЕ переносится. Задача из исследования, повторяющая"
          " такую гипотезу, ставится как «заблокировано до вердикта».")
    print("ПРАВИЛО 2, которое правило 1 НЕ покрывает: домен может быть"
          " КОНТРОЛЕМ чужого опыта, и тогда менять его нельзя вовсе — контроль"
          " обязан остаться неизменным, иначе сравнивать не с чем. Контроли"
          " названы в применимости выше, а не в поле канарейки. Проверять"
          " домен так: python3 automation/local/running-experiments.py"
          " --domain <домен>.")
    print("\nСРОКОВ В РЕЕСТРЕ НЕТ — и «срок не назван» выше это честный"
          " вывод, а не сбой чтения. Даты оценок записаны в копии владельца:"
          " docs/seo-operator/CHANGES_LEDGER.md (столбцы «первая проверка» и"
          " «финал») и docs/seo-operator/PLAN_20261019_25.md, раздел «Даты"
          " оценок».")
    print("ВАЖНЕЕ ДАТЫ: политика вердикта требует минимум 14 суток И 1 000"
          " показов, а показы не измеряются (B023, нужен Вебмастер). Поэтому"
          " названные даты — это следующая ОЦЕНКА, а не гарантированный"
          " вердикт: ждать его как события нельзя.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
