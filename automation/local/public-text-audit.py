#!/usr/bin/env python3
"""Служебные слова в ПУБЛИЧНОМ тексте страниц. Только чтение.

    python3 automation/local/public-text-audit.py <домен> [<домен> …]
    python3 automation/local/public-text-audit.py --paths "/,/catalog/" <домен>

Зачем. Витрина объясняет себя посетителю, и в объяснение просачивается
внутреннее устройство: снимок каталога, поставщик данных, переходник, номер
ячейки, слово «тестовая». Посетителю это ничего не говорит, а про сеть площадок
говорит лишнее.

Что НЕ ищется и почему. Полезные пояснения остаются: часовой пояс, различие
эфира и появления серии, настоящие сообщения плеера. Они описывают то, что
посетитель видит, а не то, как это сделано.

Ищется в ТЕКСТЕ, а не в разметке: `data-*` атрибуты, имена классов и JSON-LD
посетителю не показываются. Скрипты и стили вырезаются до поиска.
"""
from __future__ import annotations

import argparse
import html as _html
import re
import subprocess
import sys

#: Служебные слова и причина, по которой каждое здесь. Слово ищется как
#: подстрока без учёта регистра — в тексте, уже очищенном от разметки.
СЛОВА: dict[str, str] = {
    "снимок каталога": "внутреннее устройство доставки",
    "снимке каталога": "внутреннее устройство доставки",
    "снимка каталога": "внутреннее устройство доставки",
    "поставщик данных": "внутреннее устройство доставки",
    "поставщика данных": "внутреннее устройство доставки",
    "провайдер не отдал": "внутренняя формулировка вместо сообщения плеера",
    "переходник": "внутреннее устройство выпуска",
    "адаптер": "внутреннее устройство выпуска",
    "тестовая витрина": "площадка объявляет себя тестовой посетителю",
    "тестовый": "площадка объявляет себя тестовой посетителю",
    "витрина": "внутреннее слово фабрики",
    "ячейка": "внутреннее слово фабрики",
    "site_id": "внутренний идентификатор площадки",
    "build_id": "внутренний идентификатор выпуска",
    "release": "внутренний идентификатор выпуска",
    "fixture": "внутреннее слово проверки",
    "заглушка": "внутреннее слово проверки",
    "sandbox": "внутреннее слово проверки",
}

#: Пояснения, которые ОСТАЮТСЯ. Совпадение внутри них находкой не считается:
#: они описывают видимое посетителю, а не устройство.
ИСКЛЮЧЕНИЯ: tuple[str, ...] = (
    "по москве", "мск", "часовой пояс", "время эфира",
    "эфир", "серия появится", "серия появилась",
)


def достать(url: str, таймаут: int = 45) -> tuple[str, str]:
    г = subprocess.run(["curl", "-sS", "-L", "-w", "\n%{http_code}",
                        "--max-time", str(таймаут), url],
                       capture_output=True, text=True)
    т = г.stdout or ""
    код = т.rsplit("\n", 1)[-1]
    return код, т[: т.rfind("\n")] if "\n" in т else т


def текст(страница: str) -> str:
    """Видимый текст: без скриптов, стилей, комментариев и атрибутов."""
    б = re.sub(r"(?is)<script.*?</script>", " ", страница)
    б = re.sub(r"(?is)<style.*?</style>", " ", б)
    б = re.sub(r"(?s)<!--.*?-->", " ", б)
    # Заголовок и описание посетитель тоже видит — оставляем их содержимое.
    б = re.sub(r"(?is)<title[^>]*>(.*?)</title>", r" \1 ", б)
    б = re.sub(r'(?is)<meta[^>]+name="description"[^>]+content="([^"]*)"', r" \1 ", б)
    б = re.sub(r"(?s)<[^>]+>", " ", б)
    return _html.unescape(re.sub(r"\s+", " ", б))


def находки(т: str) -> list[tuple[str, str, str]]:
    низ = т.lower()
    итог: list[tuple[str, str, str]] = []
    for слово, причина in СЛОВА.items():
        начало = 0
        while True:
            i = низ.find(слово, начало)
            if i < 0:
                break
            начало = i + len(слово)
            окно = т[max(0, i - 70): i + len(слово) + 70]
            if any(и in окно.lower() for и in ИСКЛЮЧЕНИЯ):
                continue
            итог.append((слово, причина, окно.strip()))
    return итог


def главная(argv: list[str]) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("domains", nargs="+")
    р.add_argument("--paths", default="/,/catalog/,/new/,/collections/,/schedule/")
    о = р.parse_args(argv[1:])
    пути = [п.strip() for п in о.paths.split(",") if п.strip()]

    всего = 0
    for домен in о.domains:
        print(f"=== {домен}")
        for путь in пути:
            код, страница = достать(f"https://{домен}{путь}")
            if код != "200":
                print(f"   {путь:14} код {код} — не проверяется")
                continue
            н = находки(текст(страница))
            всего += len(н)
            if not н:
                print(f"   {путь:14} чисто")
                continue
            for слово, причина, окно in н[:6]:
                print(f"   {путь:14} «{слово}» — {причина}")
                print(f"      …{окно}…")
    print(f"\nнаходок всего: {всего}")
    return 1 if всего else 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv))
