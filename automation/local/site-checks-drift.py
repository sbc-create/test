#!/usr/bin/env python3
"""Проверки витрин против шаблонов фабрики: какими правилами судят каждую ячейку.

Проверки из `factory/cell/site_checks/` КОПИРУЮТСЯ в репозиторий витрины при
выделении ячейки. Дальше копия живёт своей жизнью, и измерение показывает, что
живёт активно: из девяти проверок разошлись 49 копий, у `verify_pins.py` — 15
из 20.

Само расхождение дефектом НЕ считается, и это важно: копию могли осознанно
приспособить под семейство, и требовать побайтного совпадения значило бы
откатывать осмысленную работу. Опасно другое направление — когда копия
проверяет МЕНЬШЕ шаблона. Тогда ячейку судят по более слабым правилам, чем
объявляет фабрика, её собственная проверка зеленеет, и никто этого не видит.

Поэтому сравниваются не байты, а СОСТАВ ПРОВЕРОК: из каждого файла достаются
сообщения об отказе (`плохо.append(...)`, `беды.append(...)`) — каждое
соответствует одной проверке. Выводится:

* `слабее` — в копии НЕТ проверок, которые есть в шаблоне. Это расхождение;
* `иначе` — состав разошёлся в обе стороны: копия что-то потеряла и что-то
  добавила. Замечание: надо смотреть глазами, автоматика тут не судья;
* `богаче` — копия проверяет больше. Замечание, и повод перенести в шаблон;
* `совпадает` — состав тот же, даже если байты разные.

Ничего не меняет: только читает.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ШАБЛОНЫ = КОРЕНЬ / "factory" / "cell" / "site_checks"
ЯЧЕЙКИ = КОРЕНЬ / "var" / "site-repos"
#: Копия проверок, УСТАНОВЛЕННАЯ у исполнителя. Договор ячейки требует
#: побайтового совпадения с ней (`checks/deploy_request.py`), и это второй вид
#: «шаблона»: рабочее дерево фабрики и установленная копия — не одно и то же.
#: Обновление установленной копии — осознанное действие ВЛАДЕЛЬЦА, так и
#: написано в `automation/host/install-cell-executor.sh`: иначе запись в
#: рабочий каталог равнялась бы исполнению от root.
УСТАНОВЛЕННЫЕ = Path(
    "/usr/local/lib/site-factory-cell/factory/cell/site_checks")
#: Имена накопителей отказов, принятые в проверках фабрики и витрин.
НАКОПИТЕЛИ = ("плохо", "беды", "проблемы", "ошибки")


def _текст_узла(узел: ast.AST) -> str:
    """Опознаваемая часть сообщения: только литеральные куски f-строки.

    Подстановки выбрасываются нарочно — в них ИМЕНА ячеек и цифры, и из-за них
    одна и та же проверка выглядела бы разной в каждом репозитории.
    """
    куски: list[str] = []
    if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
        куски.append(узел.value)
    elif isinstance(узел, ast.JoinedStr):
        for часть in узел.values:
            if isinstance(часть, ast.Constant) and isinstance(часть.value, str):
                куски.append(часть.value)
    elif isinstance(узел, ast.BinOp):
        куски.append(_текст_узла(узел.left))
        куски.append(_текст_узла(узел.right))
    слитно = " ".join(к for к in куски if к)
    return re.sub(r"\s+", " ", слитно).strip()


def _в_стандартный_поток_ошибок(узел: ast.Call) -> bool:
    """`print(..., file=sys.stderr)` — второй принятый способ сообщить отказ."""
    for ключ in узел.keywords:
        if ключ.arg != "file":
            continue
        текст = ast.unparse(ключ.value) if hasattr(ast, "unparse") else ""
        if "stderr" in текст:
            return True
    return False


def состав(путь: Path) -> tuple[set[str], str]:
    """(множество проверок, причина). Причина непустая — файл не разобран.

    Способов сообщить об отказе в проверках фабрики ДВА, и это пришлось
    выяснить на своей же ошибке: копии витрин складывают отказы в список
    (`плохо.append(...)`), а часть шаблонов печатает их сразу в поток ошибок и
    выходит кодом 1 (`no_secrets.py` именно такой). Признак, знавший только
    первый способ, не видел в таком шаблоне НИ ОДНОЙ проверки и объявлял копию
    «богаче» — а вывод «ослабленных копий нет» на таком пропуске держаться не
    может: шаблон с одним способом и копия с другим дали бы ложную тревогу или
    ложное спокойствие.
    """
    try:
        дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
    except (SyntaxError, OSError, UnicodeDecodeError) as сбой:
        return set(), f"{type(сбой).__name__}: {сбой}"
    итог: set[str] = set()
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        это_отказ = False
        if isinstance(узел.func, ast.Attribute) and узел.func.attr == "append":
            цель = узел.func.value
            это_отказ = isinstance(цель, ast.Name) and цель.id in НАКОПИТЕЛИ
        elif isinstance(узел.func, ast.Name) and узел.func.id == "print":
            это_отказ = _в_стандартный_поток_ошибок(узел)
        if not это_отказ:
            continue
        for арг in узел.args:
            текст = _текст_узла(арг)
            # Короткий остаток — это сообщение целиком из подстановок, по нему
            # проверку не опознать; такие не сравниваются, чтобы не выдумывать
            # расхождения.
            if len(текст) >= 12:
                итог.add(текст[:80])
    return итог, ""


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--templates", type=Path, default=ШАБЛОНЫ)
    р.add_argument("--cells", type=Path, default=ЯЧЕЙКИ)
    р.add_argument("--check", action="append", default=[],
                   help="имя файла проверки; можно несколько")
    р.add_argument("--installed", type=Path, default=УСТАНОВЛЕННЫЕ,
                   help="копия проверок у исполнителя (её требует договор)")
    опции = р.parse_args(аргв)

    шаблоны = sorted(опции.templates.glob("*.py"))
    if опции.check:
        шаблоны = [ш for ш in шаблоны if ш.name in опции.check]
    if not шаблоны:
        print(f"шаблонов проверок нет в {опции.templates}", file=sys.stderr)
        return 2

    расхождений = замечаний = не_разобрано = потерявших = 0
    отстала_установленная: list[str] = []
    копий_мимо_договора: dict[str, list[str]] = {}
    for шаблон in шаблоны:
        эталон, причина = состав(шаблон)
        if причина:
            print(f"   [—  ] {шаблон.name:28} шаблон не разобран: {причина}")
            не_разобрано += 1
            continue
        копии = sorted(опции.cells.glob(f"*/checks/{шаблон.name}"))
        if not копии:
            continue

        # Договор ячейки — ПОБАЙТОВОЕ совпадение с установленной копией, а не
        # с рабочим деревом. Поэтому сверяется и она, иначе «всё сошлось» в
        # дереве означало бы «выпуск пройдёт», а это разные утверждения.
        установлен = опции.installed / шаблон.name
        if установлен.is_file():
            байты_шаблона = шаблон.read_bytes()
            байты_установленного = установлен.read_bytes()
            if байты_шаблона != байты_установленного:
                отстала_установленная.append(шаблон.name)
            мимо = [к.parts[-3] for к in копии
                    if к.read_bytes() != байты_установленного]
            if мимо:
                копий_мимо_договора[шаблон.name] = мимо
        слабее: list[tuple[str, list[str]]] = []
        иначе: list[tuple[str, list[str], list[str]]] = []
        богаче: list[tuple[str, list[str]]] = []
        совпало = 0
        for копия in копии:
            свой, причина = состав(копия)
            if причина:
                не_разобрано += 1
                print(f"   [—  ] {шаблон.name:28} {копия.parts[-3]}: "
                      f"не разобрана: {причина}")
                continue
            нет_в_копии = sorted(эталон - свой)
            лишнее = sorted(свой - эталон)
            if нет_в_копии and лишнее:
                иначе.append((копия.parts[-3], нет_в_копии, лишнее))
            elif нет_в_копии:
                слабее.append((копия.parts[-3], нет_в_копии))
            elif лишнее:
                богаче.append((копия.parts[-3], лишнее))
            else:
                совпало += 1

        знак = "НЕТ" if слабее else ("зам" if (иначе or богаче) else "ок ")
        расхождений += bool(слабее)
        if (иначе or богаче) and not слабее:
            замечаний += 1
        потерявших += len(слабее) + len(иначе)
        итог = [f"копий {len(копии)}", f"состав тот же у {совпало}"]
        if слабее:
            итог.append(f"СЛАБЕЕ у {len(слабее)}")
        if иначе:
            итог.append(f"иначе у {len(иначе)}")
        if богаче:
            итог.append(f"богаче у {len(богаче)}")
        print(f"   [{знак}] {шаблон.name:28} {'; '.join(итог)}")
        for имя, нет in слабее:
            print(f"          {имя}: НЕ проверяет {len(нет)} из "
                  f"{len(эталон)}: {'; '.join(н[:60] for н in нет[:3])}")
        for имя, нет, лишнее in иначе:
            print(f"          {имя}: потеряно {len(нет)}, добавлено "
                  f"{len(лишнее)}")
            for н in нет[:3]:
                print(f"             нет в копии: {н[:70]}")
            for л in лишнее[:3]:
                print(f"             только в копии: {л[:70]}")
        for имя, лишнее in богаче:
            print(f"          {имя}: проверяет на {len(лишнее)} больше — "
                  f"{'; '.join(л[:50] for л in лишнее[:2])}")

    print(f"\nпроверок: {len(шаблоны)}; с ослабленными копиями: {расхождений}; "
          f"с замечаниями: {замечаний}; не разобрано: {не_разобрано}")
    # Это число важнее предыдущей строки, и его нельзя прятать: копия, которая
    # потеряла проверку шаблона, слабее в этом месте, сколько бы своих она ни
    # добавила. «Ослабленных ноль» без него читается спокойнее, чем есть.
    print(f"копий, потерявших хотя бы одну проверку шаблона: {потерявших} "
          f"(из них без добавлений своих: {расхождений})")

    # Второй вид «шаблона»: установленная копия исполнителя. Без этой сверки
    # «в дереве всё сошлось» читалось бы как «выпуск пройдёт», а это разные
    # утверждения: договор ячейки требует побайтового совпадения с НЕЙ.
    if not опции.installed.is_dir():
        print(f"\nкопия исполнителя не найдена ({опции.installed}) — "
              "договор побайтового совпадения не проверен")
    else:
        print(f"\nсверка с копией исполнителя ({опции.installed}):")
        if отстала_установленная:
            print(f"   установленная копия отстала от дерева у "
                  f"{len(отстала_установленная)}: {отстала_установленная}")
            print("   обновление установленной копии — действие ВЛАДЕЛЬЦА: "
                  "sudo bash automation/host/install-cell-executor.sh")
        else:
            print("   установленная копия совпадает с деревом по всем проверкам")
        if копий_мимо_договора:
            всего = sum(len(в) for в in копий_мимо_договора.values())
            print(f"   копий ячеек, не совпадающих побайтово с установленной: "
                  f"{всего}")
            for имя, кто in sorted(копий_мимо_договора.items()):
                print(f"      {имя}: {len(кто)} — {', '.join(кто[:4])}"
                      f"{' …' if len(кто) > 4 else ''}")
            print("   договор это требует только там, где есть "
                  "checks/deploy_request.py; у остальных расхождение НИКТО не "
                  "сторожит — это и есть пробел, а не норма")
        else:
            print("   все копии ячеек совпадают с установленной побайтово")
    if замечаний:
        print("«иначе» и «богаче» — не расхождение: копию могли осознанно "
              "приспособить под семейство, и это смотрят глазами.")
    return 1 if расхождений else 0


if __name__ == "__main__":
    raise SystemExit(главное())
