#!/usr/bin/env python3
"""Два вида простоя, которые журналы видят, а человек — нет. Только чтение.

    python3 automation/local/executor-stall-check.py
    python3 automation/local/executor-stall-check.py --idle-minutes 60 --repeats 20

Зачем. «Исполнитель работает» и «работа движется» — разные утверждения, и между
ними два измеренных провала:

1. ВЫПУСКАЮЩИЙ КРУЖИТ НА ОДНОЙ ЗАДАЧЕ. Измерено 2026-10-18 по
   `var/seo-tech/publish.jsonl`: из 599 решений «ожидание» 545 (91 %)
   приходятся на одну задачу T175 — «голова ветки выпуска не равна живому»
   (356 раз) и «на ветке выпуска невыпущенный коммит» (189 раз). 17.10 таких
   решений 280 за сутки. Цикл занят задачей, которая не может сдвинуться, а
   остальная очередь ждёт. Повтор одного и того же решения — не работа, и
   задача после N повторов должна называться заблокированной.

2. ГОТОВАЯ ЗАДАЧА ЕСТЬ, ПРОГОНОВ НЕТ. Это не то же, что «нет задач»: при
   пустой очереди простой законен, при непустой — нет. Различить можно только
   сравнив состояние очереди с временем последнего прогона, что инструмент и
   делает.

Чего инструмент НЕ утверждает: он не называет причину простоя (упал ли
исполнитель, не запущен ли он, ждёт ли внешнего действия) — для этого нужен его
собственный журнал состояния. Он называет САМУ ситуацию, в которой причину
надо искать.

Источники: `var/seo-tech/publish.jsonl`, `var/seo-tech/runs.jsonl` и файл
очереди (по умолчанию из ветки SEO-линии, см. `--queue`).
"""
from __future__ import annotations

import argparse
import collections
import datetime as dt
import json
import pathlib
import subprocess
import sys

ЖУРНАЛЫ = pathlib.Path("/home/claude/wt-portable-site-cell-01/var/seo-tech")
#: ЖИВОЙ файл очереди, а не версия из ветки. Разница измерена 18.10 19:30Z:
#: в `origin/claude/nova-publish-memory-01` 188 задач и 11 `queued`, а в живом
#: файле 277 задач и `queued` ровно одна (T175). Линия SEO коммитит локально и
#: пушит позже, поэтому проверка по ветке отвечала на вопрос о прошлом
#: состоянии — и показывала одиннадцать готовых задач там, где их нет.
ОЧЕРЕДЬ_ЖИВАЯ = pathlib.Path(
    "/home/claude/wt-portable-site-cell-01/config/seo-tech-queue.json")
#: Запас на случай, если живой файл недоступен: версия из ветки с пометкой.
ОЧЕРЕДЬ_ВЕТКА = "origin/claude/nova-publish-memory-01"
ОЧЕРЕДЬ_ПУТЬ = "config/seo-tech-queue.json"

#: Сколько одинаковых «ожиданий» подряд по одной задаче считается кружением.
#: Порог не из воздуха: при паузе выпускающего около двух минут 20 повторов —
#: это примерно сорок минут цикла на задаче, которая не двигается.
ПОРОГ_ПОВТОРОВ = 20
#: Сколько минут без прогонов при непустой очереди считается провалом.
ПОРОГ_ПРОСТОЯ_МИН = 60


def записи(имя: str) -> list[dict]:
    итог: list[dict] = []
    try:
        текст = (ЖУРНАЛЫ / имя).read_text(encoding="utf-8")
    except OSError as сбой:
        print(f"не прочитан {ЖУРНАЛЫ / имя}: {сбой}", file=sys.stderr)
        return итог
    for строка in текст.splitlines():
        строка = строка.strip()
        if строка:
            try:
                итог.append(json.loads(строка))
            except ValueError:
                continue
    return итог


def очередь(ветка: str, путь: str) -> tuple[list[dict], str, str]:
    """Задачи очереди, причина отказа и ОТКУДА прочитано.

    Сначала живой файл: состояние очереди меняется чаще, чем её коммитят, и
    вопрос «есть ли готовая задача СЕЙЧАС» ответа из ветки не имеет.
    """
    if ОЧЕРЕДЬ_ЖИВАЯ.is_file():
        try:
            документ = json.loads(ОЧЕРЕДЬ_ЖИВАЯ.read_text(encoding="utf-8"))
        except ValueError as сбой:
            return ([], f"живая очередь не разобрана: {сбой}", "живой файл")
        return (документ.get("tasks") or [], "", f"живой файл {ОЧЕРЕДЬ_ЖИВАЯ}")
    г = subprocess.run(["git", "show", f"{ветка}:{путь}"],
                       capture_output=True, text=True)
    if г.returncode != 0:
        return ([], (г.stderr or "git show не удался").strip()[:120], "ветка")
    try:
        документ = json.loads(г.stdout)
    except ValueError as сбой:
        return ([], f"очередь не разобрана: {сбой}", "ветка")
    return (документ.get("tasks") or [], "",
            f"ветка {ветка} (живой файл недоступен — состояние может отставать)")


def момент(значение: str):
    try:
        return dt.datetime.fromisoformat((значение or "").replace("Z", "+00:00"))
    except ValueError:
        return None


def кружение(выпуски: list[dict], порог: int) -> list[dict]:
    """Задачи, по которым одно и то же решение повторялось подряд."""
    подряд: dict[str, dict] = {}
    итог: dict[str, dict] = {}
    for з in выпуски:
        задача = str(з.get("task_id") or "")
        исход = str(з.get("outcome") or з.get("decision") or "")
        причина = str(з.get("reason") or "")[:90]
        ключ = (исход, причина)
        д = подряд.get(задача)
        if д and д["ключ"] == ключ:
            д["повторов"] += 1
            д["последний"] = з.get("at")
        else:
            подряд[задача] = {"ключ": ключ, "повторов": 1,
                              "первый": з.get("at"), "последний": з.get("at")}
            д = подряд[задача]
        if д["повторов"] >= порог:
            прежний = итог.get(задача)
            if not прежний or д["повторов"] > прежний["повторов"]:
                итог[задача] = {"задача": задача, "исход": исход,
                                "причина": причина,
                                "повторов": д["повторов"],
                                "с": д["первый"], "по": д["последний"]}
    return sorted(итог.values(), key=lambda д: -д["повторов"])


def главная(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--repeats", type=int, default=ПОРОГ_ПОВТОРОВ)
    р.add_argument("--idle-minutes", type=int, default=ПОРОГ_ПРОСТОЯ_МИН)
    р.add_argument("--queue", default=f"{ОЧЕРЕДЬ_ВЕТКА}:{ОЧЕРЕДЬ_ПУТЬ}")
    р.add_argument("--now", default="")
    а = р.parse_args(аргв)

    выпуски = записи("publish.jsonl")
    прогоны = записи("runs.jsonl")
    if not выпуски and not прогоны:
        print("журналов нет — проверять нечего (это пробел, а не исправность)",
              file=sys.stderr)
        return 2

    находок = 0

    # 1. Кружение выпускающего.
    круги = кружение(выпуски, а.repeats)
    print(f"КРУЖЕНИЕ НА ОДНОЙ ЗАДАЧЕ (порог {а.repeats} повторов подряд): "
          f"{len(круги)}")
    for к in круги:
        находок += 1
        print(f"  {к['задача']}: {к['повторов']} раз «{к['исход']}» — "
              f"{к['причина']}")
        print(f"      с {к['с']} по {к['по']}")
    if not круги:
        print("  нет: ни по одной задаче решение не повторялось подряд "
              f"{а.repeats} раз")

    # 2. Готовая задача есть, прогонов нет.
    ветка, _, путь = а.queue.partition(":")
    задачи, беда, откуда = очередь(ветка, путь or ОЧЕРЕДЬ_ПУТЬ)
    готовые = [з for з in задачи if str(з.get("status")) == "queued"]
    последний = max((момент(з.get("finished_at") or з.get("started_at"))
                     for з in прогоны
                     if момент(з.get("finished_at") or з.get("started_at"))),
                    default=None)
    сейчас = (момент(а.now) if а.now
              else dt.datetime.now(dt.timezone.utc))
    print()
    if беда:
        print(f"ГОТОВЫЕ ЗАДАЧИ: очередь не прочитана ({беда}) — НЕ ИЗМЕРЕНО, "
              f"и это не «готовых нет»")
    elif not готовые:
        print(f"ГОТОВЫЕ ЗАДАЧИ: 0 из {len(задачи)} — простой при пустой "
              f"очереди законен")
    else:
        print(f"      источник очереди: {откуда}")
        простой = ((сейчас - последний).total_seconds() / 60
                   if последний else None)
        if простой is None:
            находок += 1
            print(f"ГОТОВЫХ ЗАДАЧ {len(готовые)}, а прогонов в журнале нет "
                  f"вовсе — исполнитель не работал ни разу")
        elif простой >= а.idle_minutes:
            находок += 1
            print(f"ГОТОВЫХ ЗАДАЧ {len(готовые)}, последний прогон "
                  f"{простой:.0f} мин назад (порог {а.idle_minutes}) — "
                  f"готовая задача есть, исполнитель не работает")
            print("      задачи: " + ", ".join(
                str(з.get("id")) for з in готовые[:10]))
        else:
            print(f"ГОТОВЫХ ЗАДАЧ {len(готовые)}, последний прогон "
                  f"{простой:.0f} мин назад — в пределах порога")

    # 3. Доля незавершённых прогонов: не находка сама по себе, но показатель.
    вердикты = collections.Counter(str(з.get("verdict")) for з in прогоны)
    всего = sum(вердикты.values())
    if всего:
        неполных = вердикты.get("INCOMPLETE", 0)
        print()
        print(f"вердикты прогонов: {dict(вердикты)}; незавершённых "
              f"{неполных} из {всего} ({100 * неполных / всего:.0f} %)")

    print()
    print("Причина простоя здесь НЕ называется: журналы не знают, упал ли "
          "исполнитель, не запущен ли он или ждёт внешнего действия. "
          "Инструмент называет ситуацию, в которой причину надо искать.")
    return 1 if находок else 0


if __name__ == "__main__":
    raise SystemExit(главная())
