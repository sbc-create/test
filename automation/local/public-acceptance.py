#: Признак номера страницы в заголовке. Шаблон сети — «— страница N», и
#: проверка ищет НОМЕР, а не конкретное слово: иначе она требовала бы от
#: витрины ровно той формулировки, которая утверждена сейчас.
НОМЕР_В_ЗАГОЛОВКЕ = re.compile(r"(?:^|\D)2(?:\D|$)")


def норма_заголовка_страницы(домен: str, где: str, тело1: str, тело2: str,
                             шаг) -> None:
    """п.7: title, H1 и description страницы N>1 несут номер страницы.

    Норма из замороженной базы дословно: «Для page 2+ используется
    утверждённый шаблон title/H1/description с номером страницы; новый
    фактический текст не генерируется». Три поля, не одно.

    До 11.10 приёмка заголовки не мерила вовсе — проверялись canonical, номер
    за пределом и редирект. Нашлось это со стороны: SEO-сессия заметила на
    коллекциях Animedia, что title страницы 2 совпадает с первой, и сказала
    «по п.3 это не нарушение». По п.3 действительно нет, а по п.7 — да, и
    первый же замер показал, что у ВСЕХ двенадцати витрин совпадает **H1**:
    title и description номер несут, H1 нет.

    Поэтому разделение строгости здесь не вкусовое:

    * **title и description** проверяются жёстко у всех: норму они уже
      соблюдают, и значит любое совпадение с первой страницей — регресс;
    * **H1** — по списку `П7_H1_СТРОГО`, который пополняется по измерению
      после выкладки. Сейчас список пуст, и это честнее обоих крайних
      вариантов: жёсткая проверка покрасила бы всю сеть на известном месте, а
      молчание вернуло бы положение, в котором норма не измеряется.

    Сравнивается не только различие, но и НАЛИЧИЕ НОМЕРА: заголовок, который
    отличается от первой страницы чем-то другим, норме не удовлетворяет.
    """
    def поля(тело: str) -> tuple[str, str, str]:
        титул = re.search(r"<title>(.*?)</title>", тело, re.S)
        h1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело, re.S)
        опис = re.search(
            r'<meta[^>]+name="description"[^>]+content="([^"]*)"', тело)
        чисто = lambda м: (re.sub(r"<[^>]+>", "", м.group(1)).strip()
                           if м else "")
        return чисто(титул), чисто(h1), (опис.group(1).strip() if опис else "")

    т1, h1_1, д1 = поля(тело1)
    т2, h1_2, д2 = поля(тело2)
    подробно = []
    плохие = []
    for имя, первое, второе, строго in (
            ("title", т1, т2, True),
            ("H1", h1_1, h1_2, домен in П7_H1_СТРОГО),
            ("description", д1, д2, True)):
        если_нет = "отсутствует" if not второе else None
        несёт = bool(второе) and второе != первое and bool(
            НОМЕР_В_ЗАГОЛОВКЕ.search(второе.replace(первое, "")))
        подробно.append(
            f"{имя}: " + (если_нет or
                          ("номер есть" if несёт else
                           "совпадает с первой" if второе == первое else
                           "отличается, но номера нет")))
        if not несёт and строго:
            плохие.append(имя)
    шаг(f"пагинация [{где}]: заголовок страницы 2 (п.7)", not плохие,
        "; ".join(подробно)
        + ("" if домен in П7_H1_СТРОГО else
           " — H1 по сети номер не несёт, строго не проверяется"))


