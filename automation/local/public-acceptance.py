#:   не `russia`), иначе 404;
#: * /new/ у Lords и Animedia — своя поверхность, у AnimeGo перенаправление
#:   в каталог;
#: * /collections/ отвечает 200 без карточек: это хаб, а не список, и в замер
#:   не идёт;
#: * /year/<гггг>/ есть у всех проверенных.
#:
#: Отсутствие раздела у витрины расхождением не считается.
РАЗДЕЛЫ_ПАГИНАЦИИ = ("/catalog/", "/genre/drama/", "/movies/", "/series/",
                     "/animation/", "/anime/", "/dorama/", "/new/",
                     "/year/2024/", "/country/rossiya/")
#: Пробы: первая страница параметром, номер за пределом, нулевой,
#: отрицательный и нечисловой.
ПРОБЫ_ПАГИНАЦИИ = ("?page=1", "?page=9999", "?page=0", "?page=-1", "?page=abc")

#: Фасеты — поверхности, чей АДРЕС несёт условие отбора (год, страна, жанр).
#: Для них canonical проверяется отдельной нормой: страница с условием не
#: может объявлять канонической страницу без условия.
ФАСЕТЫ = ("/year/", "/country/", "/genre/")


def норма_фасета(домен: str, раздел: str, основа: str,
                 набор1: set, тело1: str, шаг) -> None:
    """§1 п.4: canonical фасета не ведёт на страницу с другим составом.

    Допустимы две формы, и обе различимы измерением:

    * **на себя** — так у Lords сделан раздел жанра;
    * **на другую схему адреса** (`/year/2024/` → `/catalog/?year=2024`), если
      цель отвечает 200 и показывает ТОТ ЖЕ состав в том же порядке. Тогда это
      сведение дублей к одной схеме (п.1), а не потеря поверхности, и так
      сделаны Animedia и Zona.

    Расхождение — canonical, СБРОСИВШИЙ условие: `/year/2024/` → `/catalog/`.
    Канонической объявляется страница с ДРУГИМ набором карточек: поверхность
    не индексируется вовсе, а её карточки остаются доступны только через
    каталог. Это тяжелее расхождения п.3 на второй странице, потому что
    касается и первой.

    Проверка жёсткая и для всех доменов сразу, без списка исключений: решение
    D202 про страницы пагинации, а здесь условие отбора теряется на самой
    первой странице — спорных прочтений нормы тут нет. Измерено 11.10:
    четыре Lords и три AnimeGo — общих карточек 0-1 из 45-48.
    """
    где = раздел.rstrip("/").lstrip("/") or "корень"
    кан = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело1)
           or [None, ""])[1].replace("&amp;", "&")
    if not кан:
        шаг(f"фасет [{где}]: canonical первой страницы", False,
            "canonical отсутствует")
        return
    if кан.rstrip("/") == основа.rstrip("/"):
        шаг(f"фасет [{где}]: canonical первой страницы", True,
            "canonical на себя")
        return
    # Canonical ведёт на другой адрес. Единственный честный способ отличить
    # сведение схем от потери условия — сходить по цели и сверить состав.
    код_ц, тело_ц, _ = достать(кан)
    набор_ц = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', тело_ц))
    общих = len(набор1 & набор_ц)
    тот_же = bool(набор1) and набор1 == набор_ц
    шаг(f"фасет [{где}]: canonical первой страницы", код_ц == "200" and тот_же,
        f"canonical {кан.split(домен)[-1] or кан} код {код_ц}, "
        f"карточек у фасета {len(набор1)}, у цели {len(набор_ц)}, "
        f"общих {общих} — "
        + ("тот же состав: сведение схем (п.1)" if тот_же else
           "цель не отвечает 200" if код_ц != "200" else
           "СОСТАВ РАЗНЫЙ: canonical сбросил условие отбора (§1 п.4)"))


def _запросная_форма(домен: str, раздел: str) -> str | None:
    """Тот же отбор, выраженный запросом: `/year/2024/` → `/catalog/?year=2024`.

    `None`, если раздел не фасет: у каталога и разделов вида второй формы нет.
    """
    части = раздел.strip("/").split("/")
    if len(части) != 2 or f"/{части[0]}/" not in ФАСЕТЫ:
        return None
    return f"https://{домен}/catalog/?{части[0]}={части[1]}"


def норма_второй_схемы(домен: str, раздел: str, набор_путём: set, шаг) -> None:
    """У фасета ДВЕ формы адреса, и мерить надо обе.

    Замер ходит по форме пути (`/year/2024/`), и этого мало: тот же отбор
    доступен запросом (`/catalog/?year=2024`), и у него своя канонизация.
    Семейства свели схемы в РАЗНЫЕ стороны — у Lords и AnimeGo побеждает путь,
    у Animedia и Zona запрос, — и обе стороны одинаково ломаются:

    * **отбор применяется только одной формой.** Тогда вторая — полная копия
      каталога под своим адресом, то есть дубль, который никто не объявлял;
    * **canonical второй формы сбрасывает условие.** Ровно тот дефект, что
      нашёлся у семи витрин на форме пути, только с другой стороны.

    Измерено 11.10: все двенадцать витрин отбирают обеими формами одинаково, и
    ни одна не отвечает «неизвестный фильтр» — то есть норма применима ко всем,
    а не выдаёт за дефект неподдерживаемую форму. Эту ошибку я уже делал на
    `/genre/` у an1mego.site, когда мерил по запрошенному адресу вместо
    конечного.
    """
    где = раздел.rstrip("/").lstrip("/") or "корень"
    адрес = _запросная_форма(домен, раздел)
    if адрес is None:
        return
    код, тело, _ = достать(адрес)
    if код != "200":
        шаг(f"фасет [{где}]: вторая форма адреса", True,
            f"{адрес.split(домен)[-1]} отвечает {код} — второй формы нет")
        return
    набор = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', тело))
    общих = len(набор_путём & набор)
    шаг(f"фасет [{где}]: обе формы адреса отбирают одинаково",
        bool(набор_путём) and набор == набор_путём,
        f"{адрес.split(домен)[-1]}: карточек путём {len(набор_путём)}, "
        f"запросом {len(набор)}, общих {общих} — "
        + ("тот же отбор" if набор == набор_путём else
           "СОСТАВ РАЗНЫЙ: одна из форм условие не применяет"))

    кан = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело)
           or [None, ""])[1].replace("&amp;", "&")
    if not кан:
        шаг(f"фасет [{где}]: canonical второй формы", False, "canonical нет")
        return
    if кан.rstrip("/") == адрес.rstrip("/"):
        шаг(f"фасет [{где}]: canonical второй формы", True, "canonical на себя")
        return
    код_ц, тело_ц, _ = достать(кан)
    набор_ц = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', тело_ц))
    тот_же = bool(набор) and набор == набор_ц
    шаг(f"фасет [{где}]: canonical второй формы", код_ц == "200" and тот_же,
        f"canonical {кан.split(домен)[-1] or кан} код {код_ц}, "
        f"карточек {len(набор)}/{len(набор_ц)}, общих {len(набор & набор_ц)} — "
        + ("тот же состав: сведение схем (п.1)" if тот_же else
           "цель не отвечает 200" if код_ц != "200" else
           "СОСТАВ РАЗНЫЙ: canonical сбросил условие отбора (§1 п.4)"))


def _с_параметром(адрес: str, параметр: str) -> str:
    """Адрес с добавленным параметром: `?` или `&` по факту, а не по догадке."""
    return адрес + ("&" if "?" in адрес else "?") + параметр


#: Один тег canonical на странице. Больше одного — противоречивый сигнал, и
#: какой из них увидит обходчик, не определено.
ВСЕ_CANONICAL = re.compile(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"')


def норма_одного_canonical(тело: str, где: str, шаг) -> None:
    """В ответе ровно один тег canonical. Мерится на самой рискованной странице.

    Из двух страниц раздела рискованнее вторая: правка оформления добавляет
    canonical именно странице N>1 (с `?page=N`), а общий слой подставляет свой,
    если в теле тега нет. Поэтому норма смотрит страницу 2, когда она есть, и
    первую, когда второй нет.

    Повод. Все проверки здесь берут canonical ПЕРВЫМ совпадением регулярного
    выражения — и второй тег для них не существует. А он появляется ровно
    тогда, когда canonical ставят два источника: оформление витрины и общий
    слой. У сети уже был такой случай с другим заголовком: решение D166,
    `/healthz` у витрин на общем ядре отдавал `index, follow` от приложения и
    `noindex, nofollow` от nginx одновременно, и запрет держался только на
    одном слое.

    Сейчас это не отвлечённый риск: у `1lordserials1.online` оформление
    коллекции canonical не ставит, и его подставляет общий SEO-слой. Как
    только оформление начнёт ставить его само (а именно это и делает правка
    коллекций на четырёх Lords), источников станет два.

    Полагаться на то, что обходчик выберет «правильный», нельзя — так же, как
    нельзя было полагаться, что он выберет более строгий `robots`.
    """
    адреса = ВСЕ_CANONICAL.findall(тело)
    уникальные = sorted({а.replace("&amp;", "&") for а in адреса})
    шаг(f"один canonical [{где}]", len(адреса) <= 1,
        f"тегов {len(адреса)}"
        + ("" if len(адреса) <= 1 else
           f", адресов {len(уникальные)}: " + "; ".join(уникальные[:3])
           + (" — ПРОТИВОРЕЧИВЫЙ СИГНАЛ" if len(уникальные) > 1
              else " — дубль тега")))


