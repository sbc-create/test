def _индексируемая(код: str, тело: str, заголовки: dict) -> bool:
    """Отдаёт ли адрес ИНДЕКСИРУЕМУЮ страницу.

    Норма §3 п.4 говорит «не публикуются как indexable 200» — то есть
    запрещена не двухсотка сама по себе, а индексируемая двухсотка. 404 норму
    соблюдает, и `noindex` при 200 соблюдает тоже. Мерить надо норму, а не
    выбранный способ: SEO-сессия выбрала 404, выбор годный и более строгий, но
    требовать именно его значит требовать чужое решение.
    """
    if код != "200":
        return False
    робот = re.search(r'<meta[^>]+name="robots"[^>]+content="([^"]*)"', тело)
    из_тела = (робот.group(1) if робот else "").lower()
    из_заголовка = (заголовки.get("x-robots-tag")
                    or заголовки.get("X-Robots-Tag") or "").lower()
    return "noindex" not in из_тела and "noindex" not in из_заголовка


def _отсутствующий_год(домен: str, тело_каталога: str) -> str:
    """Год, которого у витрины НЕТ. Берётся из её же списка годов.

    Подставить «1066» было бы догадкой: у витрины может оказаться и такой год.
    Поэтому читаются объявленные ею годы (ссылки `/year/<гггг>/` на каталоге)
    и берётся первый свободный из заведомо старых — выбор детерминированный,
    чтобы замеры сравнивались между собой.
    """
    свои = {int(г) for г in re.findall(r'href="/year/(\d{4})/"', тело_каталога)}
    for год in range(1900, 1910):
        if год not in свои:
            return str(год)
    return "1066"


def нормы_фильтров(домен: str, шаг) -> None:
    """§3 п.3 и п.4: пустые, неизвестные и повторяющиеся фильтры.

    Норма дословно:

    * п.3 «Порядок параметров нормализуется; повторяющиеся и неизвестные ключи
      запрещены — это предотвращает комбинаторный взрыв URL»;
    * п.4 «Пустые категории/теги/фильтры не публикуются как indexable 200».

    Направление назвала SEO-сессия 11.10, измерив 19 нарушений по п.4 и закрыв
    их на семи витринах. Проверяя их выкладки, я заметил, что в п.3 названы
    ТРИ вещи, а измерялась одна: неизвестное ЗНАЧЕНИЕ. Неизвестный КЛЮЧ
    (`?nosuchkey=1`) и ПОВТОР ключа (`?genre=drama&genre=comedy`) не мерил
    никто — и оба отдают индексируемую двухсотку с полным каталогом на всех
    двенадцати витринах. Именно они и дают комбинаторный взрыв, от которого
    норма защищает: пустой фильтр добавляет один лишний адрес, а неизвестный
    ключ — сколько угодно.

    Порядок параметров (первая часть п.3) проверяется сверкой canonical у двух
    перестановок одного набора: если он один, порядок нормализован.
    """
    _к, тело_каталога, _з = достать(f"https://{домен}/catalog/")
    год = _отсутствующий_год(домен, тело_каталога)

    пробы = (
        ("пустой год путём", f"/year/{год}/", домен in ФИЛЬТРЫ_СТРОГО),
        ("пустой год запросом", f"/catalog/?year={год}", домен in ФИЛЬТРЫ_СТРОГО),
        ("неизвестный жанр", "/catalog/?genre=zhanra-takogo-net",
         домен in ФИЛЬТРЫ_СТРОГО),
        ("неизвестный ключ", "/catalog/?nosuchkey=1", домен in КЛЮЧИ_СТРОГО),
        ("повтор ключа", "/catalog/?genre=drama&genre=komediya",
         домен in КЛЮЧИ_СТРОГО),
    )
    for имя, путь, строго in пробы:
        код, тело, заг = достать(f"https://{домен}{путь}")
        индексируемая = _индексируемая(код, тело, заг)
        карточек = len(set(re.findall(
            r'href="(/(?:title|anime)/[a-z0-9-]+)', тело)))
        шаг(f"фильтры: {имя} (§3 п.{'4' if 'ключ' not in имя else '3'})",
            not индексируемая or not строго,
            f"код {код}, карточек {карточек}, "
            + ("индексируемая — НАРУШЕНИЕ" if индексируемая and строго else
               "индексируемая — известное расхождение, правка идёт"
               if индексируемая else
               "не индексируется — норма соблюдена"))

    # Метка трафика: от неё требуется ТРОЕ сразу, и это не то же, что от
    # неизвестного ключа. Адрес обязан работать (атрибуция ценнее лишнего
    # адреса, поэтому без перенаправления), не быть индексируемым и
    # канонизироваться на чистый адрес. Проверяются все три, иначе «не
    # индексируется» сойдёт за норму и у сломанного адреса.
    код, тело, заг = достать(f"https://{домен}/catalog/?utm_source=proba")
    индексируемая = _индексируемая(код, тело, заг)
    канон = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело)
             or [None, ""])[1].replace("&amp;", "&")
    чистый = канон.rstrip("/").endswith("/catalog") or канон.endswith("/catalog/")
    строго_метки = домен in КЛЮЧИ_СТРОГО
    шаг("фильтры: метка трафика (§3 п.2)",
        not строго_метки or (код == "200" and not индексируемая and чистый),
        f"код {код}, "
        + ("индексируемая" if индексируемая else "noindex")
        + f", canonical {канон.split(домен)[-1] or канон or '—'}"
        + ("" if строго_метки else " — правка идёт"))

    # Защита от ИЗЛИШНЕГО запрета. Правка «неизвестный ключ → noindex» легко
    # накрывает лишнее, и регрессия, которая смотрит только на запрещённые
    # адреса, этого не увидит: у неё всё зелено, когда запрещено ВСЁ.
    # Поэтому отдельно проверяется, что известный ключ остался рабочим и
    # индексируемым. Именно в эту сторону ошибаются правки такого рода.
    код, тело, заг = достать(f"https://{домен}/catalog/?genre=drama")
    карточек = len(set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', тело)))
    шаг("фильтры: известный ключ не задет (§3 п.1)",
        код == "200" and карточек > 0 and _индексируемая(код, тело, заг),
        f"код {код}, карточек {карточек}, "
        + ("индексируемая — норма соблюдена" if _индексируемая(код, тело, заг)
           else "НЕ индексируется — правка накрыла лишнее"))

    # Порядок параметров: одна выборка, две перестановки, один canonical.
    кан = []
    for хвост in ("genre=drama&year=2024", "year=2024&genre=drama"):
        _к, тело, _з = достать(f"https://{домен}/catalog/?{хвост}")
        найден = re.search(
            r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело)
        кан.append((найден.group(1).replace("&amp;", "&") if найден else ""))
    шаг("фильтры: порядок параметров (§3 п.3)", кан[0] == кан[1] and bool(кан[0]),
        f"canonical у перестановок: {кан[0] or '—'} и {кан[1] or '—'} — "
        + ("нормализован" if кан[0] == кан[1] and кан[0] else
           "canonical отсутствует" if not кан[0] else "РАЗНЫЙ"))


def _строго(карта: dict, домен: str, раздел: str) -> bool:
    """Стоит ли раздел в строгом списке домена.

    Страница коллекции попадает в замер с КОНКРЕТНЫМ ключом, взятым из хаба
    витрины (`/collection/current_season/`), а ключ может измениться: добавь
    витрина коллекцию, которая встанет в хабе раньше по алфавиту, и точный
    адрес в списке перестанет совпадать. Строгость отпала бы МОЛЧА — а это тот
    самый способ, которым регресс проходит незамеченным.
    Поэтому коллекции в списках обозначаются признаком поверхности
    `/collection/`, а не адресом конкретной коллекции: поведение canonical у
    витрины всё равно одно на все её коллекции (измерено 11.10 на 48
    коллекциях шести витрин).
    """
    разделы = карта.get(домен, ())
    if раздел.startswith("/collection/"):
        return "/collection/" in разделы
    return раздел in разделы


def коллекция_витрины(домен: str) -> str | None:
    """Путь одной страницы коллекции, ВЗЯТЫЙ из хаба самой витрины.

    Ключи коллекций у витрин разные (`comedy_series`, `current_season`,
    `genre_boevik`…), и придумывать их нельзя: пустое поле — не разрешение
    подставить значение. Поэтому читается `/collections/` и берётся первая
    ссылка по алфавиту — выбор детерминированный, чтобы замер был
    повторяемым, а не «какая попалась».

    Одной коллекции довольно: измерение 11.10 показало, что поведение
    canonical у витрины ОДНО на все её коллекции — у `1lordserials1.online`
    self-canonical на всех двенадцати, у трёх других Lords «на раздел» на всех
    своих. Различие доменное, не по коллекции, поэтому мерить каждую значит
    тратить по десятку запросов на один и тот же ответ.

    Возвращает пару (путь, причина). Путь — `None`, когда коллекции мерить
    нечего, и тогда причина РАЗЛИЧАЕТ два случая, которые нельзя смешивать:

    * `"нет"` — хаб ответил 200 и ссылок на коллекции в нём нет. Это факт о
      витрине: у трёх AnimeGo `/collections/` ведёт в каталог;
    * `"не измерено"` — хаб не ответил. Это факт об измерении, а не о витрине.

    Почему различие обязательно. Сначала я написал пробу, которая любую
    неудачу считала отсутствием, и она записала `zonafilm12.site` как витрину
    без коллекций. Коллекций у неё двенадцать, а один запрос не дошёл.
    Доклад «поверхности нет» вместо «не смог измерить» — это та же ошибка,
    что метрика `0` вместо «не измерено»: правило сети запрещает её прямо.
    """
    код, тело, _ = достать(f"https://{домен}/collections/")
    if код != "200":
        return None, f"не измерено: хаб коллекций ответил {код}"
    ссылки = sorted(set(re.findall(r'href="(/collection/[a-z0-9_-]+)/?"',
                                   тело)))
    if not ссылки:
        return None, "нет: хаб ответил 200, ссылок на коллекции нет"
    return ссылки[0] + "/", f"коллекций в хабе {len(ссылки)}"


def нормы_пагинации(домен: str, шаг, разделы=None) -> None:
    """Нормы по каждому разделу, у которого есть пагинация.

    `разделы` ограничивает проход: полный обход десяти поверхностей — около
    восьмидесяти запросов на домен, и для быстрой сверки одного раздела столько
    не нужно. По умолчанию мерится всё: пропуск поверхности и есть тот способ,
    которым /animation/ оставался непроверенным.
    """
    for раздел in (разделы or РАЗДЕЛЫ_ПАГИНАЦИИ):
        нормы_раздела(домен, раздел, шаг)
    # Страница коллекции — такая же списковая поверхность с пагинацией, но её
    # адрес нельзя записать в перечень: ключ у каждой витрины свой. Поэтому
    # она берётся из хаба витрины, а не придумывается. Пока её не мерили,
    # у пяти витрин canonical второй страницы указывал на первую, и 48-60
    # новых карточек на каждой второй странице были доступны только через неё.
    if разделы is None:
        коллекция, причина = коллекция_витрины(домен)
        if коллекция is None:
            # «Не измерено» — расхождение: неизмеренная поверхность это не
            # отсутствующая поверхность, и молчать о разнице нельзя.
            шаг("нормы пагинации [коллекция]",
                причина.startswith("нет"), причина)
        else:
            нормы_раздела(домен, коллекция, шаг)


def нормы_раздела(домен: str, раздел: str, шаг) -> None:
    """Нормы `REQ-SEO-PAGINATION` на выложенном сайте: п.2, п.3 и п.8.

    Что проверяется и почему именно так:

    * **п.8 — номер за пределом и мусор.** `?page=9999`, `?page=0`, `?page=-1`,
      `?page=abc` не должны отдавать 200 с содержимым первой страницы. Это
      ЖЁСТКАЯ проверка: такой адрес — готовый дубль раздела, и спорных случаев
      здесь нет. Измерено 2026-10-11: Animedia, Lords и Zona отвечают 404 (Zona
      ещё и 400 на нечисловой), AnimeGo отдавал 200 с полным набором карточек;
    * **п.2 — `?page=1`.** Норма требует РЕДИРЕКТ на единственный адрес первой
      страницы. Сейчас так делает только Zona (308), остальные отвечают 200 с
      canonical на раздел. Дублем это не становится, поэтому проверка
      сообщающая, а жёсткая — только на случай, когда canonical указывает на
      сам `?page=1`;
    * **п.3 — self-canonical у страниц 2+.** Расхождение сети известно и
      записано решением D202; выпуск правки готовит SEO-сессия. Поэтому пока
      проверка сообщающая: она падает, если canonical указывает НЕ на себя и НЕ
      на раздел (то есть появилось что-то новое). Когда правка выйдет, строку
      `известное_D202` надо убрать — и проверка станет жёсткой сама.

    Содержимое сверяется набором слагов, а не длиной страницы: совпадение
    наборов — это дубль, а разница в размере может быть и боковым блоком.
    """
    запрошено = f"https://{домен}{раздел}"
    где = раздел.rstrip("/").lstrip("/") or "корень"
    к1, т1, заг1 = достать(запрошено)
    if к1 != "200":
        шаг(f"нормы пагинации [{где}]", True,
            f"{раздел} отвечает {к1} — раздела у витрины нет")
        return
    # Пробы строятся на КОНЕЧНОМ адресе раздела, а не на запрошенном. У части
    # витрин раздел жанра — совместимостное перенаправление: `/genre/drama/`
    # ведёт на `/catalog/?genre=drama`, и при переходе теряется параметр
    # страницы. Если мерить по запрошенному адресу, инструмент сообщит о
    # «нарушении п.8 и п.3» там, где настоящая поверхность норму соблюдает, —
    # то есть выдаст артефакт своей пробы за дефект витрины (поймано 11.10 на
    # an1mego.site).
    основа = заг1.get("итоговый-адрес") or запрошено
    if основа != запрошено:
        шаг(f"нормы пагинации [{где}]", True,
            f"{раздел} ведёт на {основа.split(домен)[-1]} — нормы мерятся там")
    набор1 = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', т1))

    # --- §1 п.4: canonical фасета ---------------------------------------
    # Только для поверхностей с условием в адресе: у `/catalog/` и `/movies/`
    # терять нечего. Тело первой страницы уже прочитано — лишнего запроса
    # норма не делает, кроме одного похода по самой canonical-цели.
    if раздел.startswith(ФАСЕТЫ):
        норма_фасета(домен, раздел, основа, набор1, т1, шаг)
        норма_второй_схемы(домен, раздел, набор1, шаг)

    # --- п.8: за пределом и мусор ---------------------------------------
    плохие = []
    подробно = []
    for проба in ПРОБЫ_ПАГИНАЦИИ[1:]:
        код, тело, _ = достать(_с_параметром(основа, проба.lstrip("?")))
        набор = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', тело))
        # Любой 200 на номер за пределом — расхождение, и подвид называется:
        #
        # * копия первой страницы — прямой дубль раздела;
        # * иные карточки — страница, которой не должно быть;
        # * пустой шаблон — soft 404, прямо запрещённый §1 п.8 замороженной
        #   базы («пустой шаблон со статусом 200 — soft 404, запрещён»).
        #
        # Прежде пустой шаблон считался безобидным, и на animeg0.site разделы
        # вида прошли проверку, отдавая 200 без карточек. Это была дыра в мере:
        # поисковику всё равно, пусто там или нет, он видит 200.
        if код == "200":
            вид = ("копия первой" if набор and набор == набор1 else
                   "иные карточки" if набор else "пустой шаблон — soft 404")
            плохие.append(проба)
            подробно.append(f"{проба} → 200/{вид}")
        else:
            подробно.append(f"{проба} → {код}")
    шаг(f"пагинация [{где}]: номер за пределом (п.8)", not плохие,
        "; ".join(подробно))

    # --- п.2: первая страница параметром --------------------------------
    код, тело, заг = достать(_с_параметром(основа, "page=1"))
    кан = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело)
           or [None, ""])[1]
    на_себя = "page=1" in кан
    # `достать` СЛЕДУЕТ переходам, поэтому редирект виден не по коду ответа, а
    # по итоговому адресу: если `page=1` из него исчез, норма п.2 соблюдена.
    # Иначе Zona, которая отвечает 308, выглядела бы как все остальные.
    итоговый = заг.get("итоговый-адрес", "")
    перенаправление = bool(итоговый) and "page=1" not in итоговый
    строго_редирект = _строго(ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО, домен, раздел)
    шаг(f"пагинация [{где}]: ?page=1 (п.2)",
        not на_себя and (перенаправление or not строго_редирект),
        f"код {код}, canonical {кан or '—'}"
        + ("; редирект на раздел — норма соблюдена" if перенаправление
           else "; РЕГРЕСС: редирект пропал" if строго_редирект
           else "; норма просит редирект на раздел"))

    # Если редирект есть, прочие параметры обязаны его пережить: иначе
    # `?page=1&genre=drama` молча превращается в каталог без фильтра — и это
    # хуже отсутствия редиректа, потому что ломает не канонизацию, а выдачу.
    if перенаправление:
        _к, _т, заг2 = достать(_с_параметром(основа, "page=1&sort=new"))
        конечный = заг2.get("итоговый-адрес", "")
        шаг(f"пагинация [{где}]: редирект сохраняет параметры (п.2)",
            "sort=new" in конечный and "page=1" not in конечный,
            f"итоговый адрес {конечный or '—'}")

    # --- п.3: self-canonical у страниц 2+ -------------------------------
    код, тело, _ = достать(_с_параметром(основа, "page=2"))
    набор2 = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)', тело))
    кан2 = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело)
            or [None, ""])[1]
    if код != "200" or not набор2:
        # Второй страницы нет — считаем теги на первой: источников canonical
        # всё равно может быть два.
        норма_одного_canonical(т1, где, шаг)
        шаг(f"пагинация [{где}]: canonical страницы 2 (п.3)", True,
            f"код {код} — второй страницы нет, норма не применяется")
        return
    норма_одного_canonical(тело, где, шаг)
    норма_заголовка_страницы(домен, где, т1, тело, шаг)
    новых = len(набор2 - набор1)
    кан2 = кан2.replace("&amp;", "&")
    на_себя2 = "page=2" in кан2
    на_раздел = кан2.rstrip("/") == основа.rstrip("/")

    # У ФАСЕТА «page=2 в canonical» мало: условие отбора обязано дойти туда
    # вместе с номером. Иначе `/year/2024/?page=2` объявит канонической
    # `/catalog/?page=2` — вторую страницу КАТАЛОГА, с другим составом, — и
    # проверка на подстроку `page=2` это пропустит, потому что подстрока на
    # месте. Случай не выдуманный: у zonafilm.cc перечень разрешённых
    # параметров и условие из пути — два разных места, и правка одного без
    # другого даёт ровно такой canonical.
    #
    # Проверяется составом, а не именем параметра: имена у семейств разные, а
    # «цель показывает то же» означает одно и то же везде.
    if раздел.startswith(ФАСЕТЫ) and на_себя2 and not кан2.startswith(основа):
        код_ц, тело_ц, _ = достать(кан2)
        набор_ц = set(re.findall(r'href="(/(?:title|anime)/[a-z0-9-]+)',
                                 тело_ц))
        общих = len(набор2 & набор_ц)
        шаг(f"пагинация [{где}]: canonical страницы 2 несёт условие отбора",
            код_ц == "200" and bool(набор2) and набор2 == набор_ц,
            f"canonical {кан2.split(домен)[-1] or кан2} код {код_ц}, "
            f"карточек на странице {len(набор2)}, у цели {len(набор_ц)}, "
            f"общих {общих} — "
            + ("тот же состав" if набор2 == набор_ц else
               "цель не отвечает 200" if код_ц != "200" else
               "СОСТАВ РАЗНЫЙ: номер страницы дошёл, условие отбора нет"))
    # Домен, который норму УЖЕ соблюдает, проверяется строго: иначе его регресс
    # прошёл бы под видом «известного расхождения сети». Для остальных
    # расхождение известно и записано решением D202 — там проверка падает
    # только на неожиданном canonical (ни на себя, ни на раздел).
    строго = _строго(ПАГИНАЦИЯ_СТРОГО, домен, раздел)
    известное_D202 = на_раздел and not строго
    шаг(f"пагинация [{где}]: canonical страницы 2 (п.3)", на_себя2 or известное_D202,
        f"код {код}, новых карточек {новых}, canonical "
        + ("на себя" if на_себя2 else
           "на раздел — РЕГРЕСС: домен норму соблюдал" if на_раздел and строго else
           "на раздел — известное расхождение D202" if на_раздел else
           кан2 or "—"))


def проверить(домен: str) -> dict:
    отчёт: dict = {"домен": домен, "проверки": [], "беды": []}

    def шаг(имя: str, ок: bool, подробно: str) -> None:
        отчёт["проверки"].append({"что": имя, "ок": ок, "подробно": подробно})
        if not ок:
            отчёт["беды"].append(f"{имя}: {подробно}")

    код, тело, заг = достать(f"https://{домен}/")
    шаг("HTTPS и главная", код == "200", f"код {код}, {len(тело)} Б")
    билд = заг.get("x-site-factory-build-id", "")
    объявлено, вид = установленный_релиз(домен)
    шаг("build ID против установленного",
        bool(объявлено) and (билд == объявлено if вид == "app"
                             else билд.startswith(объявлено)),
        f"заголовок {билд or '—'}, объявлено {объявлено or '—'} "
        f"(раскладка {вид or 'не определена'})")
    роботы = заг.get("x-robots-tag", "")
    мета = (re.search(r'<meta[^>]+name="robots"[^>]+content="([^"]+)"', тело) or [None, ""])[1]
    шаг("режим индексации", bool(роботы or мета),
        f"X-Robots-Tag: {роботы or '—'} | meta robots: {мета or '—'}")
    кан = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', тело) or [None, ""])[1]
    шаг("canonical главной", домен in кан, кан or "—")
    карточек_главной = len(set(re.findall(r'href="/(?:title|anime)/[a-z0-9-]+', тело)))
    шаг("главная отдаёт карточки", карточек_главной > 0,
        f"{карточек_главной} карточек")

    for путь, имя in (("/catalog/", "каталог"), ("/series/", "сериалы"),
                      ("/movies/", "фильмы")):
        к2, т2, _ = достать(f"https://{домен}{путь}")
        if к2 == "404":
            отчёт["проверки"].append({"что": имя, "ок": True,
                                      "подробно": "404 — раздела у витрины нет"})
            continue
        счёт = len(set(re.findall(r'href="/(?:title|anime)/[a-z0-9-]+', т2)))
        шаг(имя, к2 == "200" and счёт > 0, f"код {к2}, карточек {счёт}")

    # Форма адреса поиска у семейств разная: lords/zona отвечают на
    # `/search/?q=`, yummy — на `/search?q=`, а второй форме отвечает
    # перенаправлением 308. Пробуются обе, и расхождением считается только то,
    # что ни одна не ответила: иначе проверка объявляет дефектом свою же форму
    # адреса (поймано в ночной регрессии 10.10 на пяти доменах yummy).
    к3, т3, _ = достать(f"https://{домен}/search/?q=%D0%B2%D0%BE%D0%BB%D0%BA")
    if к3 != "200":
        к3б, т3б, _ = достать(f"https://{домен}/search?q=%D0%B2%D0%BE%D0%BB%D0%BA")
        if к3б == "200":
            к3, т3 = к3б, т3б
    шаг("поиск", к3 == "200",
        f"код {к3}, карточек {len(set(re.findall(r'href=./(?:title|anime)/[a-z0-9-]+', т3)))}")

    адреса = карточки(тело, домен) or карточки(т3, домен)
    постеров = названий = 0
    серий_всего = 0
    for адрес in адреса:
        к4, т4, з4 = достать(адрес)
        h1 = (re.search(r"<h1[^>]*>(.*?)</h1>", т4, re.S) or [None, ""])[1]
        h1 = re.sub(r"<[^>]+>", "", h1).strip()
        # Слаг берётся из ИТОГОВОГО адреса: переход 308 на короткую форму —
        # правильное поведение витрины, и canonical обязан совпадать с тем, где
        # страница в итоге оказалась, а не с тем, что было запрошено.
        слаг = з4.get("итоговый-адрес", адрес).rstrip("/").rsplit("/", 1)[-1]
        постер = "poster.cdnvideohub.com" in т4
        серий = len(set(re.findall(rf'href="/(?:title|anime)/{слаг}/[^"]*episode[^"]*"', т4)))
        серий_всего += серий
        постеров += int(постер)
        названий += int(bool(h1))
        кан4 = (re.search(r'<link[^>]+rel="canonical"[^>]+href="([^"]+)"', т4) or [None, ""])[1]
        шаг(f"карточка {слаг[:28]}",
            к4 == "200" and bool(h1) and слаг in кан4,
            f"код {к4}, h1 {h1[:40]!r}, постер {постер}, серий {серий}, "
            f"canonical {'совпадает' if слаг in кан4 else кан4 or '—'}")
    if адреса:
        шаг("постеры и названия карточек", постеров == len(адреса) == названий,
            f"постеров {постеров}/{len(адреса)}, названий {названий}/{len(адреса)}")
        отчёт["серий_на_проверенных_карточках"] = серий_всего

    нормы_пагинации(домен, шаг)
    нормы_фильтров(домен, шаг)

    к5, т5, _ = достать(f"https://{домен}/robots.txt")
    шаг("robots.txt", к5 == "200" and "user-agent" in т5.lower(),
        f"код {к5}, {len(т5)} Б")
    for карта in ("/sitemap.xml", "/sitemap/titles.xml"):
        к6, т6, _ = достать(f"https://{домен}{карта}")
        if к6 == "200":
            адресов = len(re.findall(r"<loc>", т6))
            шаг(f"карта {карта}", адресов > 0, f"код 200, адресов {адресов}")
            break
    else:
        шаг("карта сайта", False, "ни /sitemap.xml, ни /sitemap/titles.xml не 200")
    return отчёт


def главная(argv: list[str]) -> int:
    домены = argv[1:]
    if not домены:
        print(__doc__)
        return 2
    плохих = 0
    for домен in домены:
        о = проверить(домен)
        print(f"\n=== {домен}")
        for п in о["проверки"]:
            метка = "ок " if п["ок"] else "НЕТ"
            print(f"   [{метка}] {п['что']:34} {п['подробно']}")
        if о["беды"]:
            плохих += 1
            print(f"   ИТОГ: расхождений {len(о['беды'])}")
        else:
            print("   ИТОГ: все проверки пройдены")
    print(f"\nдоменов проверено: {len(домены)}, с расхождениями: {плохих}")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv))
