#!/usr/bin/env python3
"""Устоялось ли значение СУТОК в выгрузках кабинета — и какую выгрузку брать.

Только чтение архива выгрузок `artifacts/analytics/analytics-ГГГГ-ММ-ДД.json`.

ЗАЧЕМ. Сравнение «неделя к неделе» по двум выгрузкам с разницей в семь дней
выглядит безупречно: окно каждой выгрузки — `7daysAgo…yesterday`, значит две
выгрузки дают две соседние недели. Но значение суток в выгрузке НЕ всегда
окончательно, и это измерено 22.10 на `yummyani.site` (счётчик 111881037):

| сутки | в выгрузке 12.10 | 13.10 | 14.10 | 15.10 и дальше |
| --- | --- | --- | --- | --- |
| 11.10 | 341 | 341 | **2 997** | 2 997 |
| 13.10 | — | — | 1 174 | **15 028** |
| 12.10 | — | — | 1 210 | **2 157** |

То есть сутки 11.10 читались как 341 визит в ДВУХ выгрузках подряд и доросли
до 2 997 только в третьей — 11 % от итога. Сутки же старше трёх дней не менялись
вовсе: 10.10 — 4 065 → 4 068, 16.10 — 21 607 → 21 609, 18.10 — 2 751 → 2 752.

ЭТО ТРОЕ СУТОК, А НЕ СВОЙСТВО ХВОСТА ОКНА. Проверено по десяти домéнам и всем
суткам архива: недосчитанными пришли РОВНО 11, 12 и 13 октября (первое чтение
4–91 % от итога), а остальные двадцать суток у всех десяти были полны с первого
чтения. Обобщать до «хвост всегда недосчитан» нельзя — это объявило бы негодным
весь архив вместо трёх суток. Разрез при этом ни при чём: `daily_search` ведёт
себя так же, как `daily_users`, те же трое суток.

ЧТО ИЗ ЭТОГО СЛЕДУЕТ. Неделя, чей хвост ещё досчитывался на момент сбора,
занижена, поэтому сравнение двух выгрузок ЗАВЫШАЕТ рост. У `yummyani.site`
неделя 05–11.10 по выгрузке 12.10 — 15 876 визитов, а устоявшаяся — 18 535
(+17 %); у `zonafilm12.site` 101 против 182 (+80 %).

Существующее правило «пропуск — не ноль» (`tests/unit/test_week_recompute.py`)
этого не ловит: сутки на месте, делитель верен, а число занижено. Поэтому
правило отдельное: **присутствующие, но не устоявшиеся сутки — не измеренные
сутки.**

Исходы по суткам:

* ``УСТОЯЛОСЬ``        — последние два чтения совпали в пределах допуска;
* ``НЕ УСТОЯЛОСЬ``     — последнее чтение отличается от предыдущего;
* ``СВЕРИТЬ НЕ С ЧЕМ`` — сутки встречаются в одной выгрузке;
* ``НЕ ИЗМЕРЕНО``      — суточного ряда у домена нет (счётчика нет, 429, сбой).

    python3 automation/local/metrika-day-settled.py --domain yummyani.site
    python3 automation/local/metrika-day-settled.py --domain yummyani.site \\
        --window 2026-10-05 2026-10-18

С `--window` печатается ещё и ответ на рабочий вопрос: САМАЯ РАННЯЯ выгрузка,
в которой все сутки окна уже устоялись, — её и надо брать для сравнения.

Коды: 0 — все сутки окна устоялись (или без `--window` ряд прочитан);
1 — есть не устоявшиеся сутки окна; 2 — не измерено.
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import sys

АРХИВЫ = [
    pathlib.Path("/home/claude/wt-portable-site-cell-01/artifacts/analytics"),
    pathlib.Path(__file__).resolve().parents[2] / "artifacts" / "analytics",
]

УСТОЯЛОСЬ = "УСТОЯЛОСЬ"
НЕ_УСТОЯЛОСЬ = "НЕ УСТОЯЛОСЬ"
НЕ_С_ЧЕМ = "СВЕРИТЬ НЕ С ЧЕМ"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"

#: Допуск подобран по измерению, а не на глаз: устоявшиеся сутки менялись не
#: более чем на 3 визита (0.07 % у 4 065), а не устоявшиеся — в разы. Нужны
#: ОБА условия, иначе малый домен с 4 → 85 визитов пройдёт по абсолютному
#: допуску, а большой с +3 визитами будет вечно «не устоявшимся».
ДОПУСК_ВИЗИТОВ = 5
ДОПУСК_ДОЛЯ = 0.01

#: Порядок метрик у разрезов РАЗНЫЙ, и перепутать их легко: у `daily_users`
#: источник `ym:s:users × …` при двух метриках, и визиты стоят ВТОРЫМИ, а у
#: `daily_traffic_profile` источник начинается с `ym:s:visits`, и вторая
#: метрика — процент отказов. Сложить отказы вместо визитов мера не должна,
#: поэтому ключи перечислены, а незнакомый ключ отклоняется.
ВИЗИТЫ_В_МЕТРИКЕ = {
    "daily_users": 1,
    "daily_traffic_profile": 0,
    "daily_search": 1,
}


def ряд_суток(запись_домена: dict, ключ: str = "daily_users") -> dict | None:
    """{сутки: визиты} из суточного разреза или None, если он не измерен.

    Роботы и люди СКЛАДЫВАЮТСЯ: вопрос этой меры — устоялось ли число, а не
    кто его дал. Разделение людей и роботов делает `traffic-segments.py`.
    """
    if ключ not in ВИЗИТЫ_В_МЕТРИКЕ:
        raise KeyError(
            f"разрез «{ключ}» не перечислен: неизвестно, какая метрика в нём"
            f" визиты. Известны: {', '.join(sorted(ВИЗИТЫ_В_МЕТРИКЕ))}")
    место = ВИЗИТЫ_В_МЕТРИКЕ[ключ]
    for м in запись_домена.get("measurements") or []:
        if м.get("key") != ключ:
            continue
        if not м.get("measured"):
            return None
        итог: dict[str, float] = {}
        for стр in м.get("value") or []:
            изм = стр.get("dimensions") or []
            сутки = (изм[0].get("name") if изм else "") or ""
            if not сутки:
                continue
            мт = стр.get("metrics") or [0.0]
            итог[сутки] = итог.get(сутки, 0.0) + (мт[место] if len(мт) > место
                                                  else мт[0])
        return итог
    return None


def устоялось(чтения: list[float]) -> str:
    """Исход по чтениям ОДНИХ суток, упорядоченным по дате выгрузки."""
    if not чтения:
        return НЕ_ИЗМЕРЕНО
    if len(чтения) == 1:
        return НЕ_С_ЧЕМ
    предыдущее, последнее = чтения[-2], чтения[-1]
    разница = abs(последнее - предыдущее)
    опора = max(abs(последнее), abs(предыдущее), 1.0)
    близко = разница <= ДОПУСК_ВИЗИТОВ and (разница / опора) <= ДОПУСК_ДОЛЯ
    return УСТОЯЛОСЬ if близко else НЕ_УСТОЯЛОСЬ


def конец_окна(имя: str) -> str:
    """Последние сутки, которые выгрузка МОГЛА содержать: день сбора минус один.

    Берётся из имени `analytics-ГГГГ-ММ-ДД.json`, а не из строк: верхний край
    окна — свойство сбора, а не данных. Если считать его по строкам, выгрузка,
    у которой последние сутки окна прошли без визитов, окажется «короткой» —
    ровно на этом моя мера отвергла `1lordserials1.online` и `lordserial33.biz`,
    где нет строк за 16.10 и 18.10.
    """
    try:
        дата = datetime.date.fromisoformat(имя[len("analytics-"):][:10])
    except ValueError:
        return ""
    return (дата - datetime.timedelta(days=1)).isoformat()


def покрывают(сутки: str, ряды: dict[str, dict[str, float]]) -> list[str]:
    """Выгрузки, чьё окно содержит эти сутки, — безотносительно строки.

    Нужна, чтобы отличить ДВА разных отсутствия. Сутки без строки в выгрузке,
    которая их окном покрывает, — это сутки без визитов: Метрика нулевых
    строк не отдаёт. Сутки же за пределами всех окон просто не измерены, и
    нулём их называть нельзя.

    Нижний край окна берётся по строкам (раньше первой строки мера ничего не
    знает), верхний — по дню сбора: см. `конец_окна`.
    """
    итог = []
    for имя, ряд in ряды.items():
        if not ряд:
            continue
        верх = конец_окна(имя) or max(ряд)
        if min(ряд) <= сутки <= верх:
            итог.append(имя)
    return sorted(итог)


def сутки_без_визитов(окно: list[str],
                      ряды: dict[str, dict[str, float]]) -> dict[str, int]:
    """{сутки: сколько выгрузок их покрывает} для суток без строки нигде.

    Измерено 22.10: у `zonafilm.space` суток 08.10 нет ни в одной из ДВЕНАДЦАТИ
    выгрузок, которые её покрывают, при наличии соседних суток. Это ноль
    визитов, а не пробел сбора, и объявлять из-за него всё окно непригодным —
    ошибка: ровно так моя первая редакция этой меры дала «НЕ НАЙДЕНА» у восьми
    домов из двадцати одного.
    """
    итог = {}
    for с in окно:
        если_есть = any(с in ряд for ряд in ряды.values())
        если_покрыто = покрывают(с, ряды)
        if not если_есть and если_покрыто:
            итог[с] = len(если_покрыто)
    return итог


def первая_устоявшаяся(окно: list[str],
                       ряды: dict[str, dict[str, float]]) -> str | None:
    """Самая ранняя выгрузка, где все сутки окна совпадают с итоговыми.

    Итоговым считается чтение из САМОЙ ПОЗДНЕЙ выгрузки, где сутки есть.
    Выгрузка годится, когда содержит все сутки окна С ВИЗИТАМИ и каждые из них
    читает так же, как итоговая; сутки без визитов (`сутки_без_визитов`) из
    требования исключаются, а сутки за пределами всех окон делают выбор
    невозможным.
    """
    итоговые: dict[str, float] = {}
    for имя in sorted(ряды):
        for сутки, v in ряды[имя].items():
            итоговые[сутки] = v
    нулевые = сутки_без_визитов(окно, ряды)
    нужные = [с for с in окно if с not in нулевые]
    if any(с not in итоговые for с in нужные):
        return None
    for имя in sorted(ряды):
        ряд = ряды[имя]
        if any(с not in ряд for с in нужные):
            continue
        if not all(покрывают(с, {имя: ряд}) for с in окно):
            continue
        if all(устоялось([ряд[с], итоговые[с]]) == УСТОЯЛОСЬ for с in нужные):
            return имя
    return None


def собрать_ряды(домен: str, ключ: str = "daily_users") -> dict:
    """{имя выгрузки: {сутки: визиты}} по всему архиву."""
    файлы: list[pathlib.Path] = []
    for каталог in АРХИВЫ:
        if каталог.is_dir():
            файлы += sorted(каталог.glob("analytics-????-??-??.json"))
    ряды: dict[str, dict[str, float]] = {}
    for ф in sorted(файлы, key=lambda п: п.name):
        try:
            d = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        цель = next((x for x in (d.get("domains") or [])
                     if x.get("domain") == домен), None)
        if цель is None:
            continue
        ряд = ряд_суток(цель, ключ)
        if ряд:
            ряды[ф.name] = ряд
    return ряды


def разобрать(ряды: dict[str, dict[str, float]]) -> dict:
    """Исход по каждым суткам: чтения, итог и признак устойчивости."""
    по_суткам: dict[str, list[tuple[str, float]]] = {}
    for имя in sorted(ряды):
        for сутки, v in ряды[имя].items():
            по_суткам.setdefault(сутки, []).append((имя, v))
    итог = {}
    for сутки, чтения in sorted(по_суткам.items()):
        значения = [v for _, v in чтения]
        исход = устоялось(значения)
        первое, последнее = значения[0], значения[-1]
        итог[сутки] = {
            "исход": исход,
            "чтений": len(значения),
            "первое_чтение": первое,
            "итоговое": последнее,
            "доля_первого": (первое / последнее) if последнее else None,
            "выгрузки": [и[10:20] for и, _ in чтения],
        }
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", required=True)
    р.add_argument("--key", default="daily_users")
    р.add_argument("--window", nargs=2, metavar=("С", "ПО"), default=None)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    ряды = собрать_ряды(а.domain, а.key)
    if not ряды:
        print(f"{а.domain}: {НЕ_ИЗМЕРЕНО} — суточного ряда «{а.key}» нет ни в"
              " одной выгрузке архива", file=sys.stderr)
        return 2
    разбор = разобрать(ряды)

    окно: list[str] = []
    if а.window:
        с, по = а.window
        # Окно строится по КАЛЕНДАРЮ, а не по прочитанным суткам: сутки без
        # визитов строки не имеют, и собрав окно из разбора, мера молча
        # сократила бы его и напечатала «суток 12» там, где их 14.
        д = datetime.date.fromisoformat(с)
        последний = datetime.date.fromisoformat(по)
        while д <= последний:
            окно.append(д.isoformat())
            д += datetime.timedelta(days=1)

    выбор = первая_устоявшаяся(окно, ряды) if окно else None

    if а.json:
        print(json.dumps({"домен": а.domain, "выгрузок": len(ряды),
                          "сутки": разбор, "окно": окно,
                          "первая_устоявшаяся_выгрузка": выбор},
                         ensure_ascii=False, indent=1))
    else:
        print(f"{а.domain}: выгрузок с суточным рядом «{а.key}» — {len(ряды)}")
        print(f"{'сутки':12} {'чтений':>7} {'первое':>9} {'итог':>9} "
              f"{'доля':>6} исход")
        for сутки, и in разбор.items():
            доля = и["доля_первого"]
            print(f"{сутки:12} {и['чтений']:7} {и['первое_чтение']:9.0f} "
                  f"{и['итоговое']:9.0f} "
                  f"{('—' if доля is None else f'{доля * 100:.0f} %'):>6} "
                  f"{и['исход']}")
        if окно:
            не_устоялись = [д for д in окно
                            if д in разбор
                            and разбор[д]["исход"] == НЕ_УСТОЯЛОСЬ]
            нулевые = сутки_без_визитов(окно, ряды)
            вне_окон = [д for д in окно
                        if д not in разбор and д not in нулевые]
            print(f"\nокно {окно[0]}..{окно[-1]}: суток {len(окно)},"
                  f" не устоялось {len(не_устоялись)}"
                  f"{': ' + ', '.join(не_устоялись) if не_устоялись else ''}")
            if нулевые:
                перечень = ", ".join(f"{д} (покрыта {n} выгрузками)"
                                     for д, n in sorted(нулевые.items()))
                print(f"суток без визитов (строки нет, но окно покрыто):"
                      f" {len(нулевые)} — {перечень}")
            if вне_окон:
                print(f"суток за пределами всех окон, то есть НЕ ИЗМЕРЕННЫХ:"
                      f" {len(вне_окон)} — {', '.join(вне_окон)}")
            print("самая ранняя выгрузка, где всё окно устоялось: "
                  f"{выбор or 'НЕ НАЙДЕНА — брать нечего'}")

    if окно:
        return 1 if any(д in разбор and разбор[д]["исход"] == НЕ_УСТОЯЛОСЬ
                        for д in окно) else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
