#!/usr/bin/env python3
"""Регулярная сверка полноты и свежести карт сети. Только чтение.

Зачем один проход поверх пяти существующих. Проверки карты живут по отдельности
и запускаются руками: полнота (`sitemap-completeness`), даты
(`sitemap-lastmod-check`), согласованность индекса (`sitemap-index-audit`),
границы листалки (`pager-bounds-probe`), потеря адресов
(`sitemap-regression-guard`). Пока их запускают по случаю, дефект живёт между
запусками: MOD-103 и MOD-108 простояли на витринах по несколько суток, и нашлись
не мониторингом, а разбором по заданию.

Что этот проход делает и чего НЕ делает:

* запускает перечисленные проверки по каждому домену и собирает их КОДЫ
  ВОЗВРАТА, не переписывая их выводы. Решение остаётся за самой проверкой;
* различает три исхода на каждой: `ок` (0), `провал` (1) и
  `не измерено` (2 или иной код). Два последних НЕ сливаются: «не измерено» —
  это предел измерения, а не чистая витрина;
* пишет отчёт файлом и возвращает 1, если есть хотя бы один провал, 2 — если
  провалов нет, но есть неизмеренное, 0 — только когда всё измерено и чисто.
  Код 0 при неизмеренном был бы той самой ложью, которую проход и должен
  закрыть;
* эталон для сверки потерь берётся из `var/sitemap-guard/<домен>.json`, если он
  есть. Если его нет, проход НЕ объявляет это ошибкой, а СНИМАЕТ эталон на
  будущее и говорит, что сверка потерь в этот раз не делалась.

Запуск по расписанию — `automation/host/sitemap-reconcile.timer`; установка
таймера за владельцем (`systemctl` вне профиля сессии).

    python3 automation/local/sitemap-reconcile.py --domain yummyani.site
    python3 automation/local/sitemap-reconcile.py --all-indexable
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЭТАЛОНЫ = КОРЕНЬ / "var" / "sitemap-guard"
ОТЧЁТЫ = КОРЕНЬ / "var" / "sitemap-reconcile"

#: Индексируемые витрины. Партия K2 сюда НЕ входит: её индексация закрыта
#: решением владельца (`indexing.desired_state: CLOSED`), карта отдаёт 404
#: правильно, и сверять там нечего.
ИНДЕКСИРУЕМЫЕ = [
    "yummyani.site", "yummyani7.site", "yummyani7.info", "yummyani.org",
    "yummyani.biz", "lordserials22.info", "1lordserials1.online",
    "lordfilm47.space", "lordserial33.biz", "zonafilm12.site",
    "zonafilm.space", "zonafilm.cc", "animedia.icu", "animedia.space",
    "animeg0.site", "an1meg0.site", "an1mego.site",
]

ИСХОД = {0: "ок", 1: "провал"}


#: Строки, по которым узнаётся САМА находка в выводе проверки.
МАРКЕРЫ = ("ПРОВАЛ", "провал", "→", "•", "НЕ ИЗМЕРЕНО", "не измерено",
           "замечание", "превышение")
#: Строки-оговорки, которые у некоторых проверок стоят В КОНЦЕ вывода и
#: вытесняли находку из хвоста. Выброшены измерением, а не на вкус: на
#: animedia.space проход напечатал три строки оговорки «чего инструмент НЕ
#: отвечает» вместо настоящей причины «часть не ответила».
ОГОВОРКИ = ("чего этот инструмент НЕ отвечает", "ноль провалов здесь означает",
            "а не «все страницы каталога в карте»", "Полнота —",
            "Core Web Vitals", "отсутствие превышения по ХОЛОДНОМУ",
            "код 200 содержанием не считается", "вид страницы берётся")
СТРОК = 4


def существо(вывод: str) -> list[str]:
    """Строки вывода, несущие находку, а не оговорку.

    Прежняя версия печатала последние три непустые строки, и у проверок,
    которые заканчивают вывод пояснением «чего этот инструмент НЕ отвечает»,
    находка в отчёт не попадала вовсе: на animedia.space вместо «часть не
    ответила» печаталась оговорка. Поэтому сначала берутся строки с маркерами
    находки, а хвост — только если маркеров нет.
    """
    строки = [с.rstrip() for с in вывод.splitlines() if с.strip()]
    без_оговорок = [с for с in строки
                    if not any(о in с for о in ОГОВОРКИ)]
    находки: list[str] = []
    for н, с in enumerate(без_оговорок):
        if not any(м in с for м in МАРКЕРЫ):
            continue
        # Заголовок вида «ПРОВАЛЫ:» сам причины не несёт: она на следующих
        # строках. Без этого отчёт печатал «ПРОВАЛЫ:» и «провалов: 1», а
        # настоящую причину — «части исчезли из индекса» — терял.
        находки.append(с)
        if с.rstrip().endswith(":"):
            находки += без_оговорок[н + 1:н + 3]
    if находки:
        # Порядок исходный, дубли убраны: строка могла попасть и как маркер, и
        # как продолжение заголовка.
        видели: set[str] = set()
        подряд = [с for с in находки
                  if not (с in видели or видели.add(с))]
        return подряд[:СТРОК]
    return (без_оговорок or строки)[-СТРОК:]


def запустить(части: list[str], таймаут: int) -> tuple[int, str]:
    try:
        г = subprocess.run(части, capture_output=True, text=True,
                           timeout=таймаут, cwd=str(КОРЕНЬ))
    except subprocess.TimeoutExpired:
        return 124, f"не уложилось в {таймаут} с"
    return г.returncode, (г.stdout or "") + (г.stderr or "")


def проверки(домен: str) -> list[tuple[str, list[str], int]]:
    """(имя, команда, таймаут). Порядок от дешёвых к дорогим."""
    м = str(КОРЕНЬ / "automation" / "local")
    эталон = ЭТАЛОНЫ / f"{домен}.json"
    страж = ["python3", f"{м}/sitemap-regression-guard.py", "--domain", домен]
    страж += (["--baseline", str(эталон)] if эталон.exists()
              else ["--snapshot", str(эталон)])
    return [
        ("цепочка", ["python3", f"{м}/sitemap-chain.py", "--domain", домен], 300),
        ("индекс", ["python3", f"{м}/sitemap-index-audit.py", домен], 600),
        ("даты", ["python3", f"{м}/sitemap-lastmod-check.py",
                  "--domain", домен], 900),
        ("листалка", ["python3", f"{м}/pager-bounds-probe.py", домен], 600),
        ("полнота", ["python3", f"{м}/sitemap-completeness.py", домен], 900),
        ("потери", страж, 900),
        # ПОКОЛЕНИЕ. Проверка отвечает на вопрос, которого не задавала ни одна
        # из пяти выше: описывает ли карта ТО ЖЕ поколение каталога, из
        # которого витрина отдаёт страницы. Между ними укладываются сутки
        # незамеченными — измерено 21.10 на `1lordserials1.online`: карта от
        # 20.10 06:19:15Z против каталога от 21.10 04:14:41Z, 770
        # индексируемых страниц обходчику не названы, и все пять проверок выше
        # этого НЕ видели (даты в карте законные, индекс согласован, полнота
        # считалась против прежнего поколения).
        #
        # Поставлена последней: она ходит по сети за обеими картами целиком и
        # опрашивает выборку отсутствующих страниц.
        ("поколение", ["python3", f"{м}/sitemap-generation-lag.py",
                       "--domain", домен], 1800),
    ]


def свести(домен: str) -> dict:
    строки = []
    for имя, части, таймаут in проверки(домен):
        код, вывод = запустить(части, таймаут)
        строки.append({"проверка": имя, "код": код,
                       "исход": ИСХОД.get(код, "не измерено"),
                       "вывод": вывод[-4000:]})
    провалов = sum(1 for с in строки if с["исход"] == "провал")
    неизмеренных = sum(1 for с in строки if с["исход"] == "не измерено")
    return {"домен": домен, "проверки": строки,
            "провалов": провалов, "неизмеренных": неизмеренных}


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--all-indexable", action="store_true")
    р.add_argument("--report", help="куда записать отчёт JSON")
    а = р.parse_args(аргв)

    домены = а.domain or (ИНДЕКСИРУЕМЫЕ if а.all_indexable else [])
    if not домены:
        print("не названо ни одной витрины: --domain или --all-indexable")
        return 2

    ЭТАЛОНЫ.mkdir(parents=True, exist_ok=True)
    снято = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    итоги = [свести(д) for д in домены]

    print(f"сверка карт, снято {снято}, витрин {len(итоги)}")
    print(f"{'домен':<24} " + " ".join(f"{и:>9}" for и in
                                       ("цепочка", "индекс", "даты",
                                        "листалка", "полнота", "потери")))
    for и in итоги:
        клетки = " ".join(f"{с['исход']:>9}" for с in и["проверки"])
        print(f"{и['домен']:<24} {клетки}")

    провалов = sum(и["провалов"] for и in итоги)
    неизмеренных = sum(и["неизмеренных"] for и in итоги)
    print(f"\nпровалов {провалов}, неизмеренных {неизмеренных}")
    for и in итоги:
        for с in и["проверки"]:
            if с["исход"] != "ок":
                print(f"\n{и['домен']} / {с['проверка']} ({с['исход']},"
                      f" код {с['код']}):")
                for к in существо(с["вывод"]):
                    print(f"   {к[:200]}")

    путь = Path(а.report) if а.report else (
        ОТЧЁТЫ / f"{снято[:10].replace('-', '')}.json")
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(json.dumps(
        {"снято": снято, "витрины": итоги}, ensure_ascii=False, indent=1),
        encoding="utf-8")
    print(f"\nотчёт: {путь}")
    print("код 0 даётся ТОЛЬКО когда всё измерено и чисто: неизмеренное —"
          " это предел измерения, а не чистая витрина.")

    if провалов:
        return 1
    return 2 if неизмеренных else 0


if __name__ == "__main__":
    sys.exit(главное())
