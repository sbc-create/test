"""Работает ли поиск на витринах — по СОДЕРЖИМОМУ выдачи, а не по коду.

Запрос берётся не из головы: это название произведения, взятое с самой витрины
(первая карточка её главной). Так проверяется, что поиск находит то, что у
витрины точно есть. Выдуманное слово дало бы «ничего не найдено», и это было бы
правильным ответом поиска, а не дефектом — поэтому так не проверяется.

Отрицательный контроль обязателен: заведомо отсутствующая строка должна дать
НОЛЬ карточек. Поиск, который на любой запрос отдаёт одно и то же, исправным не
является, и без этого контроля его не отличить от работающего.
"""
import re
import subprocess
import sys
import urllib.parse

ДОМЕНЫ = ["yummyani.site", "yummyani.biz", "lordserials22.info",
          "lordfilm47.space", "zonafilm.space", "zonafilm.cc",
          "animedia.icu", "animeg0.site", "lordserial.su", "lordfilm.group"]
НЕБЫЛИЦА = "щщэыъфджзщ"


def достать(url: str) -> str:
    г = subprocess.run(["curl", "-sSL", "--max-time", "40", url],
                       capture_output=True)
    return (г.stdout or b"").decode("utf-8", errors="replace")


def карточек(тело: str) -> int:
    return len(set(re.findall(r'href="(/(?:title|anime)/[^"?#]+)"', тело)))


def первое_название(тело: str, дом: str) -> tuple[str, str]:
    """(слово для запроса, адрес произведения) — из `h1` САМОЙ страницы.

    Первая версия брала название из разметки карточки и вытащила «08:49» —
    время, а не название. Отрицание «поиск своего названия не находит» было
    тогда свойством моего зонда, а не витрины, и находкой не является. Поэтому
    название берётся там, где оно заведомо название: в `h1` страницы
    произведения.
    """
    ссылки = re.findall(r'href="(/(?:title|anime)/[^"?#]+)"', тело)
    for путь in ссылки[:4]:
        стр = достать(f"https://{дом}{путь}")
        м = re.search(r"<h1[^>]*>(.*?)</h1>", стр, re.S)
        if not м:
            continue
        имя = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", м.group(1))).strip()
        слова = [с for с in re.split(r"[\s:,.!?«»\"()\[\]-]+", имя)
                 if len(с) >= 5 and not с.isdigit()]
        if слова:
            return слова[0], путь
    return "", ""


def исход(нашлось: int, небылица: int) -> str:
    """Четыре исхода, а не два: «нашёл оба» и «не нашёл ничего» — разное."""
    if нашлось > 0 and небылица == 0:
        return "исправно"
    if нашлось > 0 and небылица > 0:
        return "ПРОВАЛ: по небылице тоже находит"
    if нашлось == 0 and небылица == 0:
        return "ПРОВАЛ: своё название не находит"
    return "ПРОВАЛ: находит только небылицу"


def главное(домены: list[str] | None = None) -> int:
    цели = домены or ДОМЕНЫ
    провалов = 0
    print(f"{'домен':<22} {'слово':<18} {'найдено':>8} {'небылица':>9}  исход")
    for дом in цели:
        главная = достать(f"https://{дом}/")
        слово, _ = первое_название(главная, дом)
        if not слово:
            print(f"{дом:<22} {'—':<18} {'—':>8} {'—':>9}  НЕ ИЗМЕРЕНО:"
                  f" названия со страницы произведения не взять")
            continue
        # Адрес БЕЗ косой черты: `/search/` отдаёт 308 без `Location`, и первый
        # прогон получил на нём ноль по любому запросу. Это MOD-113, отдельный
        # дефект, а не свойство поиска — и зонд не должен на него налетать.
        корень = f"https://{дом}/search?q="
        н = карточек(достать(корень + urllib.parse.quote(слово)))
        п = карточек(достать(корень + НЕБЫЛИЦА))
        и = исход(н, п)
        провалов += 1 if и.startswith("ПРОВАЛ") else 0
        print(f"{дом:<22} {слово[:18]:<18} {н:>8} {п:>9}  {и}")
    print("\nотрицательный контроль обязателен: поиск, отдающий одно и то же на"
          " любой запрос, исправным не является.")
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(главное(sys.argv[1:] or None))
