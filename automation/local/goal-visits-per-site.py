#!/usr/bin/env python3
"""Цель владельца «5 000 реальных визитов в сутки на каждом сайте» — в числах.

Зачем отдельный инструмент. Знаменатель цели уже измерен (MOD-155: 16 витрин
из 25 открыты для поиска), а САМО значение — сколько визитов витрины дают
сегодня — в реестре не стояло ни разу. Без него «цель не достигнута» —
утверждение без величины: непонятно, речь о разах или о порядках.

Три свойства, каждое из которых меняет ответ:

* **роботы отброшены по признаку, а не по догадке.** Берётся мера
  `daily_traffic_profile` снимка аналитики: разрез включает `ym:s:isRobot`, и
  считаются только строки «People». Общий `visits` снимка роботов НЕ исключает;
* **визиты в сутки, а не за окно.** Окно снимка — 14 суток, и сумма делится на
  число РАЗЛИЧНЫХ дат в самой мере, а не на 14: если дней меньше, делитель
  меньше, и средняя не занижается;
* **«не измерено» отделено от нуля.** Витрина без счётчика (или под
  serverHold) не получает нулевой визит — она попадает в отдельный список, и
  в знаменатель доли сети не идёт.

Только чтение снимка. Сеть не опрашивается.

    python3 automation/local/goal-visits-per-site.py [--snapshot <путь>] [--goal 5000]
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import pathlib
import sys

СНИМКИ = "/home/claude/wt-portable-site-cell-01/artifacts/analytics/analytics-*.json"
ЦЕЛЬ = 5000.0
#: Признак живого посетителя в разрезе `ym:s:isRobot`: Метрика отдаёт «People»
#: с идентификатором `no`. Любое другое значение — робот, и в счёт не идёт.
ЖИВОЙ = "no"
ПОИСК = "organic"


def по_суткам(профиль: list) -> tuple[dict, dict]:
    """(визиты по датам, поисковые по датам) — только живые, роботы отброшены."""
    по_дням: dict[str, float] = collections.defaultdict(float)
    поиск: dict[str, float] = collections.defaultdict(float)
    for строка in профиль or []:
        р = строка.get("dimensions") or []
        метрики = строка.get("metrics") or []
        if len(р) < 2 or not метрики:
            continue
        if (р[-1].get("id") or "") != ЖИВОЙ:
            continue
        дата = р[0].get("name") or ""
        визиты = метрики[0] or 0.0
        по_дням[дата] += визиты
        if (р[1].get("id") or "") == ПОИСК:
            поиск[дата] += визиты
    return dict(по_дням), dict(поиск)


def медиана(значения: list[float]) -> float:
    ряд = sorted(значения)
    if not ряд:
        return 0.0
    с = len(ряд) // 2
    return ряд[с] if len(ряд) % 2 else (ряд[с - 1] + ряд[с]) / 2


def визиты_в_сутки(профиль: list, окно: int = 7) -> dict:
    """Средняя и МЕДИАНА за последнее окно, плюс всё окно меры целиком.

    ЗАЧЕМ ЗДЕСЬ ДВА ОКНА И МЕДИАНА. Измерено 25.10 на `yummyani.site`: средняя
    за все 14 суток меры — 6 440 визитов в сутки, а за последние 7 — **2 780**.
    Разницу дают три дня (13–15.10) с 15–22 тысячами визитов, почти целиком
    прямых; средняя по 14 суткам превращает трёхдневный выброс в «цель
    достигнута», чего нет. Поэтому отчёт показывает окно, медиану и признак
    выброса, а вывод делается по СВЕЖЕМУ окну.
    """
    по_дням, поиск = по_суткам(профиль)
    даты = sorted(по_дням)
    if not даты:
        return {"суток": 0, "в_сутки": 0.0, "поиск_в_сутки": 0.0,
                "медиана": 0.0, "в_сутки_всё_окно": 0.0, "выброс": False,
                "по_дням": {}, "окно": []}
    свежие = даты[-окно:]
    значения = [по_дням[д] for д in свежие]
    в_сутки = sum(значения) / len(свежие)
    всё = sum(по_дням.values()) / len(даты)
    return {
        "суток": len(даты),
        "окно": свежие,
        "в_сутки": в_сутки,
        "поиск_в_сутки": sum(поиск.get(д, 0.0) for д in свежие) / len(свежие),
        "медиана": медиана(значения),
        "в_сутки_всё_окно": всё,
        # Выброс: средняя по всей мере вдвое и более расходится со свежим окном.
        "выброс": bool(в_сутки and всё / в_сутки >= 2.0),
        "по_дням": по_дням,
    }


def разобрать(снимок: dict, окно: int = 7) -> tuple[list, list]:
    """(измеренные витрины, не измеренные) — второе не считается нулём."""
    измерено, нет = [], []
    for з in снимок.get("domains") or []:
        меры = {x.get("key"): x for x in (з.get("measurements") or [])}
        профиль = (меры.get("daily_traffic_profile") or {}).get("value")
        if not isinstance(профиль, list) or not профиль:
            причина = "мера daily_traffic_profile не измерена"
            если = меры.get("daily_traffic_profile") or {}
            if если.get("value") and not если.get("measured"):
                причина = str(если.get("value"))[:60]
            нет.append((з.get("domain"), причина))
            continue
        и = визиты_в_сутки(профиль, окно)
        измерено.append((з.get("domain"), и))
    измерено.sort(key=lambda т: -т[1]["в_сутки"])
    return измерено, нет


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--snapshot", type=pathlib.Path)
    р.add_argument("--goal", type=float, default=ЦЕЛЬ)
    р.add_argument("--window", type=int, default=7,
                   help="сколько последних суток меры брать для вывода")
    а = р.parse_args(аргв)
    путь = а.snapshot
    if путь is None:
        найдено = sorted(glob.glob(СНИМКИ))
        if not найдено:
            print("НЕ ИЗМЕРЕНО: снимка аналитики нет ни одного")
            return 2
        путь = pathlib.Path(найдено[-1])
    снимок = json.loads(pathlib.Path(путь).read_text(encoding="utf-8"))
    измерено, нет = разобрать(снимок, а.window)
    всего = sum(и["в_сутки"] for _, и in измерено)
    поиск = sum(и["поиск_в_сутки"] for _, и in измерено)
    print(f"снимок: {путь}")
    print(f"собран: {снимок.get('collected_at')}; окно меры: "
          f"{json.dumps(снимок.get('period'), ensure_ascii=False)}")
    print(f"вывод по последним {а.window} суткам меры;"
          f" цель: {а.goal:.0f} живых визитов в сутки на каждом сайте\n")
    print(f"{'витрина':24} {'в сутки':>9} {'медиана':>9} {'поиск':>9}"
          f" {'доля сети':>10} {'доля цели':>10}  выброс")
    for домен, и in измерено:
        доля = и["в_сутки"] / всего * 100 if всего else 0.0
        метка = (f"ДА: вся мера даёт {и['в_сутки_всё_окно']:.0f}" if и["выброс"] else "—")
        print(f"{домен:24} {и['в_сутки']:>9.0f} {и['медиана']:>9.0f}"
              f" {и['поиск_в_сутки']:>9.0f} {доля:>9.1f} %"
              f" {и['в_сутки'] / а.goal * 100:>9.1f} %  {метка}")
    достигли = [д for д, и in измерено if и["в_сутки"] >= а.goal]
    print(f"\nизмерено витрин {len(измерено)}; не измерено {len(нет)}")
    for домен, причина in нет:
        print(f"   НЕ ИЗМЕРЕНО: {домен} — {причина}")
    print(f"\nвсего по сети: {всего:.0f} живых визитов в сутки,"
          f" из них поисковых {поиск:.0f}")
    print(f"цель достигнута на витринах: {len(достигли)}"
          + (f" ({', '.join(достигли)})" if достигли else ""))
    if измерено:
        домен, и = измерено[0]
        доля = и["в_сутки"] / всего * 100 if всего else 0.0
        print(f"первая витрина ({домен}) несёт {доля:.1f} % живого трафика сети;"
              f" все остальные вместе — {всего - и['в_сутки']:.0f} визитов в сутки")
    выбросы = [д for д, и in измерено if и["выброс"]]
    if выбросы:
        print("ВНИМАНИЕ, СРЕДНЯЯ ПО ВСЕЙ МЕРЕ ЗАВЫШЕНА ВЫБРОСОМ у витрин: "
              + ", ".join(выбросы)
              + " — читать свежее окно, а не всю меру")
    print("\nЧЕГО ЭТОТ СЧЁТ НЕ ГОВОРИТ: причин разницы между витринами, качества"
          " визитов и состояния индекса — показатели Вебмастера в снимке стоят"
          " «не измерено» (B023).")
    return 0 if измерено else 1


if __name__ == "__main__":
    sys.exit(главное())
