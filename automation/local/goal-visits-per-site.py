#!/usr/bin/env python3
"""Цель владельца «5 000 реальных визитов в сутки на каждом сайте» — в числах.

Зачем отдельный инструмент. Знаменатель цели уже измерен (MOD-155: 16 витрин
из 25 открыты для поиска), а САМО значение — сколько визитов витрины дают
сегодня — в реестре не стояло ни разу. Без него «цель не достигнута» —
утверждение без величины: непонятно, речь о разах или о порядках.

Три свойства, каждое из которых меняет ответ:

* **роботы отброшены по признаку, а не по догадке.** Берётся мера
  `daily_traffic_profile` снимка аналитики: разрез включает `ym:s:isRobot`, и
  считаются только строки «People». Общий `visits` снимка роботов НЕ исключает;
* **визиты в сутки, а не за окно.** Окно снимка — 14 суток, и сумма делится на
  число РАЗЛИЧНЫХ дат в самой мере, а не на 14: если дней меньше, делитель
  меньше, и средняя не занижается;
* **«не измерено» отделено от нуля.** Витрина без счётчика (или под
  serverHold) не получает нулевой визит — она попадает в отдельный список, и
  в знаменатель доли сети не идёт.

Только чтение снимка. Сеть не опрашивается.

    python3 automation/local/goal-visits-per-site.py [--snapshot <путь>] [--goal 5000]
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import pathlib
import sys

СНИМКИ = "/home/claude/wt-portable-site-cell-01/artifacts/analytics/analytics-*.json"
ЦЕЛЬ = 5000.0
#: Признак живого посетителя в разрезе `ym:s:isRobot`: Метрика отдаёт «People»
#: с идентификатором `no`. Любое другое значение — робот, и в счёт не идёт.
ЖИВОЙ = "no"
ПОИСК = "organic"


def визиты_в_сутки(профиль: list) -> tuple[float, float, int]:
    """(живых визитов в сутки, из них поисковых, суток в мере).

    Делитель — число РАЗЛИЧНЫХ дат в самой мере: так средняя не зависит от того,
    сколько суток запрашивалось, и не занижается на неполном окне.
    """
    по_дням: dict[str, float] = collections.defaultdict(float)
    поиск: dict[str, float] = collections.defaultdict(float)
    for строка in профиль or []:
        р = строка.get("dimensions") or []
        метрики = строка.get("metrics") or []
        if len(р) < 2 or not метрики:
            continue
        if (р[-1].get("id") or "") != ЖИВОЙ:
            continue
        дата = р[0].get("name") or ""
        визиты = метрики[0] or 0.0
        по_дням[дата] += визиты
        if (р[1].get("id") or "") == ПОИСК:
            поиск[дата] += визиты
    суток = len(по_дням)
    if not суток:
        return 0.0, 0.0, 0
    return sum(по_дням.values()) / суток, sum(поиск.values()) / суток, суток


def разобрать(снимок: dict) -> tuple[list, list]:
    """(измеренные витрины, не измеренные) — второе не считается нулём."""
    измерено, нет = [], []
    for з in снимок.get("domains") or []:
        меры = {x.get("key"): x for x in (з.get("measurements") or [])}
        профиль = (меры.get("daily_traffic_profile") or {}).get("value")
        if not isinstance(профиль, list) or not профиль:
            причина = "мера daily_traffic_profile не измерена"
            если = меры.get("daily_traffic_profile") or {}
            if если.get("value") and not если.get("measured"):
                причина = str(если.get("value"))[:60]
            нет.append((з.get("domain"), причина))
            continue
        в, п_, суток = визиты_в_сутки(профиль)
        измерено.append((з.get("domain"), в, п_, суток))
    измерено.sort(key=lambda т: -т[1])
    return измерено, нет


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--snapshot", type=pathlib.Path)
    р.add_argument("--goal", type=float, default=ЦЕЛЬ)
    а = р.parse_args(аргв)
    путь = а.snapshot
    if путь is None:
        найдено = sorted(glob.glob(СНИМКИ))
        if not найдено:
            print("НЕ ИЗМЕРЕНО: снимка аналитики нет ни одного")
            return 2
        путь = pathlib.Path(найдено[-1])
    снимок = json.loads(pathlib.Path(путь).read_text(encoding="utf-8"))
    измерено, нет = разобрать(снимок)
    всего = sum(в for _, в, _, _ in измерено)
    поиск = sum(п_ for _, _, п_, _ in измерено)
    print(f"снимок: {путь}")
    print(f"собран: {снимок.get('collected_at')}; окно: "
          f"{json.dumps(снимок.get('period'), ensure_ascii=False)}")
    print(f"цель: {а.goal:.0f} живых визитов в сутки на каждом сайте\n")
    print(f"{'витрина':24} {'визитов/сутки':>13} {'поисковых':>10}"
          f" {'доля сети':>10} {'доля цели':>10}")
    for домен, в, п_, _ in измерено:
        доля = в / всего * 100 if всего else 0.0
        print(f"{домен:24} {в:>13.1f} {п_:>10.1f} {доля:>9.1f} %"
              f" {в / а.goal * 100:>9.1f} %")
    достигли = [д for д, в, _, _ in измерено if в >= а.goal]
    print(f"\nизмерено витрин {len(измерено)}; не измерено {len(нет)}")
    for домен, причина in нет:
        print(f"   НЕ ИЗМЕРЕНО: {домен} — {причина}")
    print(f"\nвсего по сети: {всего:.0f} живых визитов в сутки,"
          f" из них поисковых {поиск:.0f}")
    print(f"цель достигнута на витринах: {len(достигли)}"
          + (f" ({', '.join(достигли)})" if достигли else ""))
    if измерено:
        первая = измерено[0]
        доля = первая[1] / всего * 100 if всего else 0.0
        print(f"первая витрина несёт {доля:.1f} % живого трафика сети;"
              f" все остальные вместе — {всего - первая[1]:.0f} визитов в сутки")
    print("\nЧЕГО ЭТОТ СЧЁТ НЕ ГОВОРИТ: причин разницы между витринами, качества"
          " визитов и состояния индекса — показатели Вебмастера в снимке стоят"
          " «не измерено» (B023).")
    return 0 if измерено else 1


if __name__ == "__main__":
    sys.exit(главное())
