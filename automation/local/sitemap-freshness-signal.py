"""Получает ли обходчик сигнал свежести на тех адресах, которые приносят визиты.

ЗАЧЕМ. Свежесть — измеренный признак страниц с поисковыми визитами: перевес
2,2 раза на `lordserials22.info` и 3,7 на `animedia.icu` (L-009). Сигнал
свежести обходчику даёт `lastmod` в карте сайта. Значит важно не «есть ли
карта», а есть ли дата у адресов ТОГО РОДА, который зарабатывает.

ЧТО СЧИТАЕТСЯ. Адреса карты разбиваются по роду (произведение, сезон, серия,
раздел, прочее) и по каждому роду считается: сколько адресов, у скольких есть
`lastmod`, и как распределены годы. Формы адресов НЕ задаются заранее: витрины
сети объявляют и `season-2`, и `season/2`, и первая версия этой проверки,
искавшая только дефис, напечатала «сезонов 0, серий 0» на витрине с 129 814
такими адресами (класс 25 в docs/RECURRING_FAILURES.md). Поэтому род
определяется по наличию сегмента `season`/`episode` в любом написании.

ЧЕГО ИНСТРУМЕНТ НЕ ДЕЛАЕТ. Не судит, какая дата правильная: он не знает, когда
адрес менялся. Отсутствие даты он называет отсутствием, а не нулём, и не
предлагает подставить «сегодня» — ложный сигнал свежести на сотню тысяч
адресов хуже отсутствия сигнала (MOD-57).

КОД ВЫХОДА: 0 — у каждого рода, который встречается, картина напечатана;
1 — есть род, у которого `lastmod` нет НИ У ОДНОГО адреса, тогда как у другого
рода на той же витрине он есть (то есть витрина умеет его ставить, но этому
роду не ставит); 3 — ни одной карты разобрать не удалось.
"""
import argparse
import collections
import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]

#: Род адреса. Определяется по сегментам, а не по целому шаблону: в сети
#: встречаются и `/season-2/episode-3`, и `/season/2/episode/3`.
СЕГМЕНТ_СЕЗОНА = re.compile(r'(^|/)season[-/]?\d*($|/)')
СЕГМЕНТ_СЕРИИ = re.compile(r'(^|/)episode[-/]?\d*($|/)')
РАЗДЕЛЫ = ('/catalog', '/genre', '/year', '/collection', '/movies', '/series',
            '/animation', '/anime/', '/title/', '/posts', '/pages')


def род(путь: str) -> str:
    """Род адреса по его сегментам."""
    if СЕГМЕНТ_СЕРИИ.search(путь):
        return "серия"
    if СЕГМЕНТ_СЕЗОНА.search(путь):
        return "сезон"
    части = [ч for ч in путь.split('/') if ч]
    if len(части) == 2 and части[0] in ('title', 'anime'):
        return "произведение"
    if len(части) <= 1:
        return "раздел"
    return "прочее"


def добыть(адрес: str, предел: int) -> str:
    г = subprocess.run(
        ['curl', '-sSL', '--max-time', str(предел), '--compressed',
         '-A', 'factory-freshness-signal', адрес],
        capture_output=True, text=True, timeout=предел + 30)
    return г.stdout if г.returncode == 0 else ""


def закрыта_по_решению(домен: str, предел: int) -> bool:
    """Закрыта ли витрина от обхода целиком.

    У витрин партии K2 `robots.txt` содержит `Disallow: /` — это решение, а не
    поломка, и отсутствие карты у них правильно. Без этой проверки инструмент
    печатал бы «карта не разобрана», что читается как неисправность: ровно так
    закрытие K2 однажды уже попало в находки и было оттуда изъято.
    """
    т = добыть(f'https://{домен}/robots.txt', предел)
    if not т:
        return False
    для_всех = False
    for строка in т.splitlines():
        с = строка.strip().lower()
        if с.startswith('user-agent:'):
            для_всех = с.split(':', 1)[1].strip() == '*'
        elif (для_всех and с.startswith('disallow:')
                and с.split(':', 1)[1].strip() == '/'):
            return True
    return False


def части_карты(домен: str, предел: int) -> list[str]:
    индекс = добыть(f'https://{домен}/sitemap.xml', предел)
    if not индекс:
        return []
    части = [а for а in re.findall(r'<loc>([^<]+)</loc>', индекс)
             if а.endswith('.xml')]
    return части or [f'https://{домен}/sitemap.xml']


def разобрать(домен: str, предел: int):
    """По роду: всего адресов, с датой, счётчик годов."""
    итог = collections.defaultdict(
        lambda: {"всего": 0, "с_датой": 0, "годы": collections.Counter()})
    частей = 0
    for часть in части_карты(домен, предел):
        т = добыть(часть, предел)
        if not т:
            continue
        частей += 1
        for блок in re.findall(r'<url>(.*?)</url>', т, re.S):
            м = re.search(r'<loc>([^<]+)</loc>', блок)
            if not м:
                continue
            путь = м.group(1).split(домен, 1)[-1] or '/'
            р = род(путь)
            итог[р]["всего"] += 1
            д = re.search(r'<lastmod>([^<]*)</lastmod>', блок)
            if д and д.group(1).strip():
                итог[р]["с_датой"] += 1
                итог[р]["годы"][д.group(1)[:4]] += 1
    return итог, частей


def витрины(названные: str) -> list[str]:
    if названные:
        return [д.strip() for д in названные.split(',') if д.strip()]
    реестр = json.loads(
        (КОРЕНЬ / "config/active-domains.json").read_text("utf-8"))
    ждут = {з["domain"] for з in реестр.get("awaiting_replacement") or []}
    return [з["domain"] for з in реестр["domains"]
            if з.get("state") == "active" and з["domain"] not in ждут]


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domains", default="",
                   help="витрины через запятую; по умолчанию все действующие")
    р.add_argument("--timeout", type=int, default=90,
                   help="предел одного запроса, секунд")
    а = р.parse_args(аргв)

    список = витрины(а.domains)
    разобрано = закрытых = 0
    без_сигнала = []
    print(f'{"витрина":<22} {"род":<14} {"адресов":>9} {"с lastmod":>10}'
          f' {"доля":>6}  годы')
    for домен in список:
        итог, частей = разобрать(домен, а.timeout)
        if not частей:
            if закрыта_по_решению(домен, а.timeout):
                print(f'{домен:<22} — закрыта от обхода по решению'
                      f' (robots.txt: Disallow: /), карта не нужна')
                закрытых += 1
            else:
                print(f'{домен:<22} НЕ ИЗМЕРЕНО: карта не разобрана')
            continue
        разобрано += 1
        есть_где_то = any(о["с_датой"] for о in итог.values())
        for имя in ("произведение", "сезон", "серия", "раздел", "прочее"):
            о = итог.get(имя)
            if not о or not о["всего"]:
                continue
            доля = о["с_датой"] * 100.0 / о["всего"]
            годы = ', '.join(f'{г} — {n}' for г, n in о["годы"].most_common(3))
            print(f'{домен:<22} {имя:<14} {о["всего"]:>9} {о["с_датой"]:>10}'
                  f' {доля:>5.1f}%  {годы or "—"}')
            if о["с_датой"] == 0 and есть_где_то and имя in ("сезон", "серия",
                                                             "произведение"):
                без_сигнала.append((домен, имя, о["всего"]))
    print()
    if not разобрано:
        if закрытых == len(список):
            print("все названные витрины закрыты от обхода по решению —"
                  " карты им не нужны, и это не отказ замера")
            return 0
        print("НЕ ИЗМЕРЕНО: ни одной карты разобрать не удалось")
        return 3
    print(f"разобрано витрин {разобрано} из {len(список)}"
          + (f"; закрыто от обхода по решению {закрытых}" if закрытых else ""))
    if без_сигнала:
        print("ВЫВОД: у этих родов адресов сигнала свежести нет НИ У ОДНОГО"
              " адреса, тогда как на той же витрине он у кого-то есть —"
              " значит витрина умеет его ставить, но этому роду не ставит:")
        for домен, имя, сколько in без_сигнала:
            print(f"   {домен}: {имя} — {сколько} адресов без lastmod")
        return 1
    print("ВЫВОД: у каждого рода адресов, который встречается, сигнал свежести"
          " есть хотя бы у части адресов")
    return 0


if __name__ == "__main__":
    sys.exit(main())
