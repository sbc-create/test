#!/usr/bin/env python3
"""Происхождение опубликованного текста: ДВА поля, одно понятие (T043).

Повод. Происхождение записи наложения пишется в два разных поля, и проверка,
читающая одно, даёт ложный пробел:

* `provenance` — {author, prepared_by, facts_source, written_at, sources};
  этим путём опубликовано подавляющее большинство записей;
* `source_manifest` — {source_type, source_id, facts}; другой путь публикации,
  поля `author` в нём НЕТ ПО УСТРОЙСТВУ, а не потому, что авторство потеряно.

Измерено 13.10 в 11:10 МСК: 294 записи, из них 291 с `provenance` и 3 с
`source_manifest` (все три на `yummyani.site`). Единственный читатель одного
поля — `editorial.состояние()`: он берёт `provenance.author`, и у этих трёх
записей отдаёт `None`. Отчёт состояния показывает их без автора, и отсюда
один шаг до вывода «авторство потеряно у трёх записей» — вывода неверного:
тело и его отпечаток у них целы.

Поэтому исходы здесь РАЗНЫЕ, и ни один не выводится из другого:

  ПРОИСХОЖДЕНИЕ        есть `provenance`, автор назван
  ИНОЙ ПУТЬ            есть `source_manifest`; автора нет по устройству поля,
                       происхождение названо источником
  ПРОБЕЛ               нет ни одного из двух полей — вот это настоящий пробел
  НЕ ИЗМЕРЕНО          файл не прочитан; это факт о доступе, не о записи

Корни хранилищ читаются из `factory/qwen/registry.КОРНИ_ХРАНИЛИЩ`, а не
вписаны сюда: их меняют вместе с выпуском, и копия разошлась бы молча.

Ничего не меняет: только чтение файлов наложений.

    python3 automation/local/overlay-provenance.py
    python3 automation/local/overlay-provenance.py --json
    python3 automation/local/overlay-provenance.py --one-field-check
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ФАЙЛ = "title-overlays.json"

ПРОИСХОЖДЕНИЕ = "ПРОИСХОЖДЕНИЕ"
ИНОЙ_ПУТЬ = "ИНОЙ ПУТЬ"
ПРОБЕЛ = "ПРОБЕЛ"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"

#: Поля, по которым происхождение считается названным. Порядок — порядок
#: проверки, и он важен: запись может нести оба поля, и тогда главным
#: считается `provenance` (в нём есть автор).
ПОЛЯ = ("provenance", "source_manifest")


def корни_хранилищ(корень: Path = КОРЕНЬ) -> tuple[dict[str, str], str]:
    """Корни наложений по семействам — из самого реестра фабрики."""
    путь = корень / "factory" / "qwen" / "registry.py"
    спец = importlib.util.spec_from_file_location("qwen_registry_ro", путь)
    if спец is None or спец.loader is None:
        return {}, f"{путь} не загружается — корни {НЕ_ИЗМЕРЕНО}"
    модуль = importlib.util.module_from_spec(спец)
    sys.modules.setdefault("qwen_registry_ro", модуль)
    try:
        спец.loader.exec_module(модуль)
        return dict(модуль.КОРНИ_ХРАНИЛИЩ), f"из {путь.relative_to(корень)}"
    except Exception as ош:  # noqa: BLE001 — поломка называется
        return {}, f"{путь.name} не исполнился ({type(ош).__name__}) — корни {НЕ_ИЗМЕРЕНО}"


def исход(запись: dict) -> tuple[str, str]:
    """Исход по записи и чем он обоснован.

    Читаются ОБА поля. Проверка одного поля здесь была бы той самой ошибкой,
    против которой инструмент и сделан.
    """
    прov = запись.get("provenance")
    if isinstance(прov, dict) and прov:
        автор = прov.get("author") or прov.get("prepared_by")
        if автор:
            return ПРОИСХОЖДЕНИЕ, f"provenance.author={автор}"
        return ПРОИСХОЖДЕНИЕ, "provenance есть, но автор в нём не назван"
    ман = запись.get("source_manifest")
    if isinstance(ман, dict) and ман:
        тип = ман.get("source_type") or "тип не назван"
        ид = ман.get("source_id") or "идентификатор не назван"
        return ИНОЙ_ПУТЬ, f"source_manifest: {тип}/{ид}; поля author в нём нет по устройству"
    return ПРОБЕЛ, "ни provenance, ни source_manifest"


def ключ(запись: dict) -> str:
    """Чем запись называет себя. Своего имени инструмент не придумывает."""
    for имя in ("content_id", "slug", "title_id", "url"):
        if запись.get(имя):
            return f"{имя}={запись[имя]}"
    return "запись себя не называет"


def разобрать_домен(файл: Path, одно_поле: bool = False) -> dict:
    """Разбор одного файла наложений. Нечитаемый файл — не пустой файл."""
    if not файл.exists():
        return {"состояние": "файла нет", "записей": 0, "исходы": {}, "подробно": []}
    try:
        d = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        return {"состояние": f"{НЕ_ИЗМЕРЕНО}: {type(ош).__name__}",
                "записей": 0, "исходы": {}, "подробно": []}
    записи = d.get("items") or []
    исходы: dict[str, int] = {}
    подробно = []
    for з in записи:
        if одно_поле:
            # Намеренно неверный разбор: ровно то, что делает читатель одного
            # поля. Нужен затем, чтобы ложный пробел можно было ПОКАЗАТЬ.
            код = ПРОИСХОЖДЕНИЕ if (з.get("provenance") or {}).get("author") else ПРОБЕЛ
            чем = "читалось только provenance.author"
        else:
            код, чем = исход(з)
        исходы[код] = исходы.get(код, 0) + 1
        if код != ПРОИСХОЖДЕНИЕ:
            подробно.append({"запись": ключ(з), "исход": код, "обоснование": чем})
    return {"состояние": "прочитан", "записей": len(записи),
            "исходы": исходы, "подробно": подробно,
            "generation_id": d.get("generation_id")}


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true")
    р.add_argument("--one-field-check", action="store_true",
                   help="разобрать так, как это делает читатель ОДНОГО поля — "
                        "чтобы ложный пробел был виден числом")
    р.add_argument("--root", type=Path, default=КОРЕНЬ)
    а = р.parse_args(аргв)

    корни, откуда = корни_хранилищ(а.root)
    if not корни:
        print(f"ОТКАЗ: {откуда}")
        return 2

    итог = {"корни": откуда, "семейства": {}, "сводка": {}}
    сводка: dict[str, int] = {}
    всего = 0
    for семейство, путь in sorted(корни.items()):
        д = Path(путь)
        домены: dict[str, dict] = {}
        if not д.is_dir():
            итог["семейства"][семейство] = {"каталог": путь, "состояние": "каталога нет",
                                            "домены": {}}
            continue
        for поддомен in sorted(p for p in д.iterdir() if p.is_dir()):
            разбор = разобрать_домен(поддомен / ФАЙЛ, а.one_field_check)
            домены[поддомен.name] = разбор
            всего += разбор["записей"]
            for к, н in разбор["исходы"].items():
                сводка[к] = сводка.get(к, 0) + н
        итог["семейства"][семейство] = {"каталог": путь, "состояние": "прочитан",
                                        "домены": домены}
    итог["сводка"] = {"записей": всего, **сводка}

    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
    else:
        заголовок = ("ПРОИСХОЖДЕНИЕ ЗАПИСЕЙ НАЛОЖЕНИЙ"
                     + (" — РАЗБОР ПО ОДНОМУ ПОЛЮ (намеренно неверный)"
                        if а.one_field_check else ""))
        print(заголовок)
        print(f"корни хранилищ: {откуда}\n")
        for семейство, тело in итог["семейства"].items():
            if тело["состояние"] != "прочитан":
                print(f"{семейство}: {тело['состояние']} — {тело['каталог']}")
                continue
            print(f"{семейство}:")
            for домен, разбор in тело["домены"].items():
                if разбор["состояние"] != "прочитан":
                    print(f"   {домен:26} {разбор['состояние']}")
                    continue
                части = "  ".join(f"{к} {н}" for к, н in sorted(разбор["исходы"].items()))
                print(f"   {домен:26} записей {разбор['записей']:>4}  {части}")
                for п in разбор["подробно"]:
                    print(f"      {п['исход']:12} {п['запись']}")
                    print(f"      {'':12} {п['обоснование']}")
            print()

        print(f"всего записей: {всего}")
        for к in (ПРОИСХОЖДЕНИЕ, ИНОЙ_ПУТЬ, ПРОБЕЛ):
            if сводка.get(к):
                print(f"  {к}: {сводка[к]}")
        if а.one_field_check:
            print()
            print("ЭТО НЕ ПРОБЕЛ. Разбор по одному полю показан затем, чтобы")
            print("ложный пробел был виден числом: записи с source_manifest")
            print("попадают в ПРОБЕЛ, хотя их происхождение названо, а тело цело.")
            print("Правильный разбор — без --one-field-check.")
        elif сводка.get(ИНОЙ_ПУТЬ):
            print()
            print(f"{сводка[ИНОЙ_ПУТЬ]} записи несут происхождение ИНЫМ путём "
                  "(source_manifest).")
            print("Автора у них нет по устройству поля, а не потому, что он потерян:")
            print("тело и его отпечаток целы. Сведение двух полей в одно — решение")
            print("о составе фабрики (T043), и оно меняет цифру состава для владельца.")

    return 1 if сводка.get(ПРОБЕЛ) else 0


if __name__ == "__main__":
    sys.exit(главная())
