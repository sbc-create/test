#!/usr/bin/env python3
"""Опись постеров восьми витрин K2: загружается ли картинка и та ли это картинка.

Зачем отдельный инструмент. Код 200 на адрес постера не доказывает ни того, что
пришло изображение (отдать 200 и страницу ошибки умеет любой прокси), ни того,
что это постер НУЖНОГО произведения. Поэтому опись проверяет три разных
вопроса и не смешивает их:

1. Доставка: код ответа, тип содержимого, число байт, разбираемый заголовок
   формата. Байты считаются по факту, а не по `Content-Length`.
2. Геометрия: фактические ширина и высота из заголовка файла против
   объявленных в разметке (`width`/`height`). Карточка объявляет 300×450 и
   обрезает по `object-fit:cover`: сильно другое соотношение означает, что у
   посетителя кадр обрезан не так, как задумано.
3. Соответствие произведению: адрес постера и подпись карточки сверяются с
   ИСХОДНЫМИ данными по тому же слугу. Сдвиг привязки «постер не от того
   тайтла» виден только так — HTTP-кодом он не ловится.

Одинаковые адреса считаются один раз: на восьми витринах один и тот же
каталог, и без дедупликации проверка гоняла бы один файл восемь раз.

Запуск:  k2-poster-inventory.py [--sites lords-10,…] [--titles 8]
         [--catalog <каталог с <site>-catalog.json>] [--out <файл.json>]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import struct
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ИСХОДНИКИ = КОРЕНЬ / "var" / "k2-data" / "publish-stage8"

#: Страницы, где посетитель видит постеры. Разные поверхности намеренно: полки
#: главной, листинг раздела, поиск, подборка и карточка собираются РАЗНЫМ кодом.
СТРАНИЦЫ = [
    ("главная", "/"),
    ("раздел фильмов", "/movies/"),
    ("раздел сериалов", "/series/"),
    ("поступления", "/new/"),
    ("подборки", "/collections/"),
    ("каталог", "/catalog/"),
    ("поиск", "/search/?q=%D0%BB%D1%8E%D0%B1%D0%BE%D0%B2%D1%8C"),
]

# Карточка ЛЮБОГО семейства: полка (`a.zt`), сетка каталога (`a.c.c--poster`)
# и устаревшая подборочная (`a.c`) — это три разных куска кода и три набора
# классов. Первая редакция знала только полку и печатала ноль карточек на
# разделах, поиске и подборках, где постеров больше всего.
КАРТОЧКА = re.compile(
    r'<a class="(?P<класс>[^"]*)" href="(?P<адрес>/title/[^"]+)"[^>]*>'
    r'(?P<тело>.*?)</a>', re.S)
#: Тег картинки целиком: атрибуты разбираются отдельно, иначе необязательные
#: группы внутри `<img[^>]*>` не срабатывают никогда.
КАРТИНКА = re.compile(r'<img(?P<тег>[^>]*)>')
ШИРИНА = re.compile(r'width="(\d+)"')
ВЫСОТА = re.compile(r'height="(\d+)"')
ЗАГЛУШКА = re.compile(r'class="(?:zt__none|c__none|c__ph)"')


def витрины() -> dict[str, str]:
    """site_id → домен, из реестра ячеек. Домены не придумываются."""
    j = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    ячейки = j.get("cells") or []
    # `cells` в реестре — СПИСОК. Обращение как к словарю падало бы на каждом
    # запуске, а обращение `.get("cells", {})` молча дало бы пустую опись.
    записи = ячейки.values() if isinstance(ячейки, dict) else ячейки
    итог = {}
    for з in записи:
        if isinstance(з, dict) and з.get("site_id") and з.get("domain"):
            итог[з["site_id"]] = з["domain"]
    return итог


def получить(адрес: str, *, байты: bool = False):
    """Ответ по адресу: (код, тип, содержимое). Без кеша и без повторов.

    Тело пишется в ФАЙЛ, а метаданные — в stdout. Смешивать их нельзя: у
    картинки в байтах встречается перевод строки, и разделение вывода по
    последнему `\\n` отрезало бы часть файла — заголовок формата после такого
    разбирается, а размер в байтах становится неправдой.
    """
    with tempfile.NamedTemporaryFile(suffix=".bin", delete=True) as ф:
        п = subprocess.run(
            ["curl", "-sS", "--max-time", "45", "-o", ф.name,
             "-w", "%{http_code}\t%{content_type}", адрес],
            capture_output=True, text=True)
        мета = (п.stdout or "\t")
        код, _, тип = мета.partition("\t")
        данные = pathlib.Path(ф.name).read_bytes()
    if байты:
        return код.strip(), тип.strip(), данные
    return код.strip(), тип.strip(), данные.decode("utf-8", "replace")


def размер_изображения(данные: bytes) -> tuple[int, int, str] | None:
    """(ширина, высота, формат) из заголовка файла. None — не изображение.

    Разбор заголовка, а не доверие `Content-Type`: тип ставит сервер, а
    заголовок пишет кодировщик. Поддержаны три формата, которые встречаются у
    постеров сети: WebP, JPEG, PNG.
    """
    if len(данные) < 16:
        return None
    if данные[:4] == b"RIFF" and данные[8:12] == b"WEBP":
        кусок = данные[12:16]
        if кусок == b"VP8 ":
            ш, в = struct.unpack("<HH", данные[26:30])
            return ш & 0x3FFF, в & 0x3FFF, "webp/lossy"
        if кусок == b"VP8L":
            б = struct.unpack("<I", данные[21:25])[0]
            return (б & 0x3FFF) + 1, ((б >> 14) & 0x3FFF) + 1, "webp/lossless"
        if кусок == b"VP8X":
            ш = int.from_bytes(данные[24:27], "little") + 1
            в = int.from_bytes(данные[27:30], "little") + 1
            return ш, в, "webp/extended"
        return None
    if данные[:8] == b"\x89PNG\r\n\x1a\n":
        ш, в = struct.unpack(">II", данные[16:24])
        return ш, в, "png"
    if данные[:2] == b"\xff\xd8":
        i = 2
        while i < len(данные) - 9:
            if данные[i] != 0xFF:
                i += 1
                continue
            маркер = данные[i + 1]
            if маркер in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7,
                          0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
                в, ш = struct.unpack(">HH", данные[i + 5:i + 9])
                return ш, в, "jpeg"
            длина = struct.unpack(">H", данные[i + 2:i + 4])[0]
            i += 2 + длина
        return None
    return None


def карточки_страницы(html: str) -> list[dict]:
    """Карточки страницы: слуг, адрес постера, подпись, объявленная геометрия."""
    итог = []
    for м in КАРТОЧКА.finditer(html):
        тело = м.group("тело")
        к = КАРТИНКА.search(тело)
        if not к or 'src="' not in к.group("тег"):
            # Карточка без картинки — законное состояние (постера нет), но
            # только если показана заглушка. Иначе это дыра в разметке.
            итог.append({"slug": м.group("адрес").strip("/").split("/")[-1],
                         "src": None, "alt": None,
                         "заглушка": bool(ЗАГЛУШКА.search(тело))})
            continue
        тег = к.group("тег")
        a = re.search(r'alt="([^"]*)"', тег)
        itog_alt = a.group(1) if a else None
        s = re.search(r'src="([^"]+)"', тег)
        ш = ШИРИНА.search(тег)
        в = ВЫСОТА.search(тег)
        итог.append({
            "slug": м.group("адрес").strip("/").split("/")[-1],
            "src": s.group(1) if s else None,
            "alt": itog_alt,
            "объявлено": (int(ш.group(1)), int(в.group(1))) if ш and в else None,
            "заглушка": bool(ЗАГЛУШКА.search(тело)),
        })
    return итог


def исходные(site_id: str) -> dict[str, dict]:
    """slug → запись доставленного каталога. Пусто — исходника рядом нет."""
    п = ИСХОДНИКИ / f"{site_id}-catalog.json"
    if not п.is_file():
        return {}
    j = json.loads(п.read_text(encoding="utf-8"))
    return {з["slug"]: з for з in (j.get("items") or []) if з.get("slug")}


def обойти_витрину(site_id: str, домен: str, титров: int) -> dict:
    собрано: list[dict] = []
    страницы: list[dict] = []
    for имя, путь in СТРАНИЦЫ:
        код, тип, html = получить(f"https://{домен}{путь}")
        к = карточки_страницы(html) if код == "200" else []
        страницы.append({"страница": имя, "путь": путь, "код": код,
                         "карточек": len(к)})
        for з in к:
            з["страница"] = имя
        собрано.extend(к)
    # Карточки произведений: постер там свой, крупный, и собирается другим кодом.
    слуги = []
    for з in собрано:
        if з["slug"] not in слуги:
            слуги.append(з["slug"])
    for slug in слуги[:титров]:
        код, тип, html = получить(f"https://{домен}/title/{slug}/")
        if код != "200":
            страницы.append({"страница": f"карточка {slug}",
                             "путь": f"/title/{slug}/", "код": код,
                             "карточек": 0})
            continue
        постеры = re.findall(r'<img[^>]+src="([^"]+)"[^>]*alt="([^"]*)"', html)
        страницы.append({"страница": f"карточка {slug}",
                         "путь": f"/title/{slug}/", "код": код,
                         "карточек": len(постеры)})
        if постеры:
            собрано.append({"slug": slug, "src": постеры[0][0],
                            "alt": постеры[0][1], "объявлено": None,
                            "заглушка": False, "страница": "карточка"})
    return {"site_id": site_id, "домен": домен, "страницы": страницы,
            "карточки": собрано}


def главная(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--sites", default="")
    р.add_argument("--titles", type=int, default=6)
    р.add_argument("--out", default=str(КОРЕНЬ / "var" / "k2-data" /
                                       "poster-inventory.json"))
    а = р.parse_args(аргв)

    все = витрины()
    нужные = ([с.strip() for с in а.sites.split(",") if с.strip()]
              or [f"lords-{н}" for н in range(10, 18)])
    пары = [(с, все[с]) for с in нужные if с in все]
    отсутствуют = [с for с in нужные if с not in все]
    for с in отсутствуют:
        print(f"[x] {с}: в реестре ячеек домена нет — пропускаю")

    with ThreadPoolExecutor(max_workers=4) as пул:
        витринно = list(пул.map(lambda п: обойти_витрину(п[0], п[1], а.titles),
                                пары))

    # --- дедупликация адресов -------------------------------------------
    адреса: dict[str, list[tuple[str, str]]] = {}
    for в in витринно:
        for з in в["карточки"]:
            if з.get("src"):
                адреса.setdefault(з["src"], []).append((в["site_id"], з["slug"]))

    def проверить(адрес: str) -> dict:
        код, тип, данные = получить(адрес, байты=True)
        размер = размер_изображения(данные or b"")
        return {"адрес": адрес, "код": код, "тип": тип,
                "байт": len(данные or b""),
                "ширина": размер[0] if размер else None,
                "высота": размер[1] if размер else None,
                "формат": размер[2] if размер else None}

    with ThreadPoolExecutor(max_workers=8) as пул:
        проверки = list(пул.map(проверить, sorted(адреса)))
    по_адресу = {п["адрес"]: п for п in проверки}

    # --- соответствие произведению --------------------------------------
    расхождения: list[dict] = []
    for в in витринно:
        исх = исходные(в["site_id"])
        if not исх:
            continue
        for з in в["карточки"]:
            запись = исх.get(з["slug"])
            if not запись:
                continue  # слуг новее доставленного исходника — не дефект
            ожидаемый = запись.get("poster")
            if з.get("src") and ожидаемый and з["src"] != ожидаемый:
                расхождения.append({"вид": "постер не от того тайтла",
                                    "сайт": в["site_id"], "slug": з["slug"],
                                    "на странице": з["src"],
                                    "в исходнике": ожидаемый})
            if з.get("alt") and запись.get("title") and \
                    з["alt"].strip() != str(запись["title"]).strip():
                расхождения.append({"вид": "подпись не от того тайтла",
                                    "сайт": в["site_id"], "slug": з["slug"],
                                    "на странице": з["alt"],
                                    "в исходнике": запись["title"]})

    # --- печать ----------------------------------------------------------
    print(f"\n=== поверхности")
    for в in витринно:
        плохо = [с for с in в["страницы"] if с["код"] != "200"]
        пусто = [с for с in в["страницы"] if с["код"] == "200" and not с["карточек"]]
        print(f"{в['домен']}: страниц {len(в['страницы'])}, "
              f"карточек {sum(1 for з in в['карточки'] if з.get('src'))}, "
              f"не 200: {len(плохо)}, без карточек: "
              f"{', '.join(с['путь'] for с in пусто) or '—'}")

    без_картинки = [(в["домен"], з) for в in витринно
                    for з in в["карточки"] if not з.get("src")]
    print(f"\n=== доставка (уникальных адресов {len(адреса)})")
    не200 = [п for п in проверки if п["код"] != "200"]
    не_изображение = [п for п in проверки if п["код"] == "200" and not п["формат"]]
    маленькие = [п for п in проверки if п["код"] == "200" and п["байт"] < 1024]
    print(f"не 200: {len(не200)}; не разобрались как изображение: "
          f"{len(не_изображение)}; меньше 1 КиБ: {len(маленькие)}")
    for п in (не200 + не_изображение)[:10]:
        print(f"   [x] {п['код']} {п['тип']} {п['байт']} б — {п['адрес']}")

    портреты = [п for п in проверки if п["формат"] and п["высота"] and п["ширина"]]
    пейзажи = [п for п in портреты if п["высота"] <= п["ширина"]]
    print(f"\n=== геометрия (разобрано {len(портреты)})")
    print(f"не портрет: {len(пейзажи)}")
    отклонение = []
    for п in портреты:
        цель = 300 / 450
        доля = п["ширина"] / п["высота"]
        if abs(доля - цель) / цель > 0.15:
            отклонение.append((round(доля, 3), п))
    print(f"соотношение дальше 15 % от 2:3 (кадр обрежется): {len(отклонение)}")
    for доля, п in отклонение[:8]:
        print(f"   {п['ширина']}×{п['высота']} (={доля}) {п['адрес']}")

    print(f"\n=== соответствие произведению")
    print(f"карточек без картинки: {len(без_картинки)}; "
          f"из них с заглушкой: {sum(1 for _, з in без_картинки if з.get('заглушка'))}")
    print(f"расхождений с исходником: {len(расхождения)}")
    for р in расхождения[:8]:
        print(f"   [x] {р['вид']}: {р['сайт']} /{р['slug']}/\n"
              f"       страница: {р['на странице']}\n"
              f"       исходник: {р['в исходнике']}")

    чужие: dict[str, int] = {}
    for адрес in адреса:
        хост = адрес.split("/")[2] if адрес.startswith("http") else "(относительный)"
        чужие[хост] = чужие.get(хост, 0) + 1
    print(f"\n=== хосты картинок: {чужие}")

    итог = {"витрины": витринно, "проверки": проверки,
            "адреса": {а_: п for а_, п in по_адресу.items()},
            "расхождения": расхождения, "хосты": чужие}
    п_вых = pathlib.Path(а.out)
    п_вых.parent.mkdir(parents=True, exist_ok=True)
    п_вых.write_text(json.dumps(итог, ensure_ascii=False, indent=1) + "\n",
                     encoding="utf-8")
    print(f"\nсохранено: {п_вых}")
    отказ = bool(не200 or не_изображение or расхождения)
    return 1 if отказ else 0


if __name__ == "__main__":
    sys.exit(главная())
