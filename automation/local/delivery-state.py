def сумма(п: Path) -> str | None:
    """Сумма файла, либо None если содержимое недоступно этой учётной записи."""
    try:
        return hashlib.sha256(п.read_bytes()).hexdigest()
    except (PermissionError, OSError):
        return None


def коммит_правки(файл: str) -> str:
    готово = subprocess.run(
        ["git", "-C", str(ВЕТВЬ), "log", "-1", "--format=%h %cI", "--", файл],
        capture_output=True, text=True, timeout=120)
    return готово.stdout.strip() if готово.returncode == 0 else ""


def время(метка: float) -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(метка))


def старт_процесса(образец: str) -> tuple[float, int] | None:
    """Время старта процесса, чья командная строка содержит образец.

    Берётся самый РАННИЙ из подходящих: если процессов несколько, вопрос
    «исполняется ли новый код» решает тот, который стартовал раньше всех —
    остальные код уже перечитали, а он нет.
    """
    найдено: list[tuple[float, int]] = []
    тиков = os.sysconf("SC_CLK_TCK")
    try:
        загрузка = float(Path("/proc/uptime").read_text().split()[0])
    except OSError:
        return None
    мой = os.getpid()
    for каталог in Path("/proc").iterdir():
        if not каталог.name.isdigit() or int(каталог.name) == мой:
            continue
        try:
            строка = каталог.joinpath("cmdline").read_bytes()
        except OSError:
            continue
        команда = строка.replace(b"\0", b" ").decode("utf-8", "replace")
        if образец not in команда:
            continue
        # Своя же проверка не должна считаться процессом компонента: она
        # упоминает образец в собственной командной строке.
        if "delivery-state" in команда:
            continue
        try:
            поля = каталог.joinpath("stat").read_text().rsplit(")", 1)[1].split()
            возраст = загрузка - int(поля[19]) / тиков
        except (OSError, IndexError, ValueError):
            continue
        найдено.append((time.time() - возраст, int(каталог.name)))
    return min(найдено) if найдено else None


def приёмка_компонента(к: Компонент) -> tuple[str, str]:
    """Три условия вместе, и третье делает стадию честной.

    Артефакт есть; в нём есть слово подтверждения; и он НЕ СТАРШЕ кода, который
    удостоверяет. Без третьего `editorial-fix-install-20261011.md` зачёлся бы
    приёмкой исправления авторства, сделанного 12.10, — то есть артефакт
    прежней версии выглядел бы приёмкой нынешней.
    """
    if not к.приёмка:
        return НЕ_ИЗМЕРЕНО, "артефакт приёмки для этого компонента не объявлен"
    путь, слово = к.приёмка
    файл = ВЕТВЬ / путь
    if not файл.is_file():
        return НЕТ, f"артефакта {путь} нет"
    текст = файл.read_text(encoding="utf-8", errors="replace")
    if слово not in текст:
        return НЕТ, f"{путь} есть, но «{слово}» в нём нет"
    код = ВЕТВЬ / к.файл
    if код.is_file() and файл.stat().st_mtime < код.stat().st_mtime:
        return НЕТ, (f"{путь} СТАРШЕ кода: артефакт {время(файл.stat().st_mtime)}, "
                     f"код {время(код.stat().st_mtime)} — приёмка относится к "
                     "прежней версии")
    return ДА, f"{путь}: найдено «{слово}»"


def разобрать(к: Компонент) -> dict[str, tuple[str, str]]:
    итог: dict[str, tuple[str, str]] = {}
    в_ветви = ВЕТВЬ / к.файл
    цель = к.цель / (к.имя_в_цели or к.файл)

    # 1. Подготовлено.
    если_есть = в_ветви.is_file()
    с_ветви = сумма(в_ветви) if если_есть else None
    if не_готово := not если_есть:
        итог["подготовлено"] = (НЕТ, f"в ветви нет {к.файл}")
    else:
        итог["подготовлено"] = (
            ДА, f"{с_ветви[:16]}…, правка {коммит_правки(к.файл) or '—'}")

    # 2. Установлено.
    if not цель.exists():
        итог["установлено"] = (НЕТ, f"в цели нет {цель}")
    else:
        с_цели = сумма(цель)
        if с_цели is None:
            итог["установлено"] = (
                НЕ_ИЗМЕРЕНО,
                f"{цель} не читается этой учётной записью — предел измерения, "
                "а не совпадение")
        elif с_ветви is None:
            итог["установлено"] = (НЕ_ИЗМЕРЕНО, "сумму в ветви не получить")
        elif с_цели == с_ветви:
            итог["установлено"] = (ДА, f"{с_цели[:16]}… совпадает с ветвью")
        else:
            итог["установлено"] = (
                НЕТ, f"в цели {с_цели[:16]}…, в ветви {с_ветви[:16]}…")

    # 3. Загружено процессом.
    if not к.процесс:
        итог["загружено"] = (НЕ_ИЗМЕРЕНО, к.предел_процесса or
                             "живого процесса у компонента нет")
    else:
        старт = старт_процесса(к.процесс)
        if старт is None:
            итог["загружено"] = (НЕТ, f"процесса «{к.процесс}» нет")
        elif not цель.exists():
            итог["загружено"] = (НЕТ, "в цели файла нет — исполнять нечего")
        else:
            когда, pid = старт
            правка = цель.stat().st_mtime
            if когда >= правка:
                итог["загружено"] = (
                    ДА, f"pid {pid} стартовал {время(когда)} ≥ правки "
                        f"{время(правка)}")
            else:
                итог["загружено"] = (
                    НЕТ, f"pid {pid} стартовал {время(когда)}, а файл правлен "
                         f"{время(правка)} — исполняется СТАРЫЙ код")

    # 4. Проверено в работе.
    итог["проверено"] = приёмка_компонента(к)
    return итог


ЗНАК = {ДА: "+", НЕТ: "x", НЕ_ИЗМЕРЕНО: "?"}


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--component", default="",
                   help="разобрать один компонент по ключу")
    опции = р.parse_args(аргв)

    состав = [к for к in СОСТАВ
              if not опции.component or к.ключ == опции.component]
    if not состав:
        print(f"нет компонента с ключом {опции.component!r}; есть: "
              + ", ".join(к.ключ for к in СОСТАВ), file=sys.stderr)
        return 2

    не_загружено = 0
    for к in состав:
        итог = разобрать(к)
        print(f"\n{к.ключ}: {к.имя}")
        print(f"   {к.файл} → {к.цель}")
        for стадия in ("подготовлено", "установлено", "загружено", "проверено"):
            состояние, довод = итог[стадия]
            print(f"   [{ЗНАК[состояние]}] {стадия:12s} {состояние:12s} {довод}")
        if итог["загружено"][0] == НЕТ and итог["установлено"][0] == ДА:
            не_загружено += 1
            print("   ВНИМАНИЕ: правка в цели лежит, но процесс её не "
                  "исполняет — нужен перезапуск")

    print(f"\nкомпонентов разобрано: {len(состав)}")
    print(f"установлено, но не исполняется: {не_загружено}")
    # Код возврата отличает «есть что делать» от «всё на месте». Молчаливый
    # ноль при неисполняемой правке и был тем, чего не хватало весь вечер.
    return 1 if не_загружено else 0


if __name__ == "__main__":
    raise SystemExit(главное())
