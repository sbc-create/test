#!/usr/bin/env python3
"""Состояние доставки по четырём стадиям, с доказательством у каждой.

Зачем. «Исправлено» за вечер означало четыре разных вещи, и их путали:
правка лежит в ветви; правка лежит в цели; правка ИСПОЛНЯЕТСЯ процессом;
исправление подтверждено в работе. Четыре раза за сутки правка считалась
доставленной, потому что совпадала первая стадия. Мост MCP 12.10 исполнял код
на два часа старше файла, и ни один отчёт этого не называл.

Стадии и чем каждая доказывается:

  подготовлено   файл есть в ветви            сумма файла и коммит правки
  установлено    файл есть в цели и совпадает сумма в цели против суммы в ветви
  загружено      процесс стартовал ПОСЛЕ      время старта процесса из /proc
                 правки в цели                против mtime файла в цели
  проверено      есть артефакт приёмки        путь артефакта и его вердикт

Ни одна стадия не выводится из предыдущей. Это главное: «установлено» не
означает «загружено», а «загружено» не означает «работает правильно».

Ничего не меняет: только читает. Запускать без root; содержимое файлов под
правами root не читается, и это называется пределом измерения, а не совпадением.

    python3 automation/local/delivery-state.py
    python3 automation/local/delivery-state.py --component comments
"""
