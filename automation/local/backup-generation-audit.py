#!/usr/bin/env python3
"""Какие поколения суточных копий годны для восстановления. Только чтение.

Прежний подход («пересоздать обрезанную копию из живого файла») владельцем
ОТКЛОНЁН, и правильно: историческая копия `…before.daily-<метка>` — это снимок
состояния НА ТОТ МОМЕНТ, а живой файл сегодняшний. Подменять одно другим
значит выдать сегодняшние данные за вчерашние и испортить саму точку
восстановления. Поэтому повреждённая копия учитывается ОТДЕЛЬНО и не чинится,
а годность поколений проверяется по полным согласованным комплектам.

ЧТО ТАКОЕ ПОЛНЫЙ СОГЛАСОВАННЫЙ КОМПЛЕКТ. Поколение годно, если для КАЖДОЙ
витрины, которая в нём участвует, есть ОБА файла — каталог и подробности, — и
каждый проходит проверку целости. Поколение, где у витрины есть каталог без
подробностей, восстановить витрину не позволяет: данные разъедутся.

ЧЕМ ПРОВЕРЯЕТСЯ ЦЕЛОСТЬ, и чего эта проверка не даёт. Читается хвост файла:
последний значащий символ должен закрывать структуру (`}` или `]`), а хвост
должен разбираться как UTF-8. Это ловит обрыв записи — именно тот случай, что
случился 23.10 (файл обрезан на 122 880 байт посреди значения). Это НЕ
доказывает, что остальное содержимое верно: полный разбор 94 МБ на файл по
тринадцати витринам и тринадцати поколениям — часы чтения, и он включается
ключом `--full`.

    python3 automation/local/backup-generation-audit.py
    python3 automation/local/backup-generation-audit.py --dir … --full --json

Коды: 0 — есть хотя бы одно годное поколение, 1 — годных нет, 2 — не измерено.
"""
from __future__ import annotations

import argparse
import collections
import json
import os
import pathlib
import re
import sys

КАТАЛОГ = "/srv/site-factory/repo/var/lords/publish-backups"
МЕТКА = re.compile(r"^(?P<витрина>[a-z0-9-]+)-(?P<вид>catalog|details)\.json"
                   r"\.before\.(?P<поколение>[a-z0-9-]+T?\d*Z?)$")
ХВОСТ_БАЙТ = 4096


def целость(путь: str) -> tuple[bool, str]:
    """Обрыв записи ловится по хвосту. Полного разбора здесь нет намеренно."""
    try:
        размер = os.path.getsize(путь)
        if размер == 0:
            return False, "нулевой размер"
        with open(путь, "rb") as ф:
            ф.seek(max(0, размер - ХВОСТ_БАЙТ))
            хвост = ф.read()
    except OSError as сбой:
        return False, f"не читается: {type(сбой).__name__}"
    #: Окно отсчитывается от конца и может начаться посреди многобайтового
    #: символа — это свойство нарезки, а не повреждение файла. Поэтому
    #: ведущие байты отбрасываются (их не может быть больше трёх), и лишь
    #: затем проверяется содержимое. 23.10 без этого шесть целых поколений
    #: были объявлены негодными: окно у них резалось по середине символа.
    текст = None
    for сдвиг in range(4):
        try:
            текст = хвост[сдвиг:].decode("utf-8")
            break
        except UnicodeDecodeError:
            continue
    if текст is None:
        return False, "хвост не разбирается как UTF-8 даже со сдвигом"
    значащий = текст.rstrip()
    if not значащий:
        return False, "хвост пуст"
    if значащий[-1] not in "}]":
        return False, ("последний значащий символ"
                       f" {значащий[-1]!r}, а должен закрывать структуру")
    return True, ""


def полный_разбор(путь: str) -> tuple[bool, str]:
    try:
        with open(путь, encoding="utf-8") as ф:
            json.load(ф)
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as сбой:
        return False, f"{type(сбой).__name__}: {сбой}"[:120]
    return True, ""


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--dir", default=КАТАЛОГ)
    р.add_argument("--full", action="store_true",
                   help="полный разбор JSON вместо проверки хвоста (часы)")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    каталог = pathlib.Path(а.dir)
    if not каталог.is_dir():
        print(f"НЕ ИЗМЕРЕНО: каталога нет: {каталог}")
        return 2

    поколения: dict[str, dict[str, dict[str, str]]] = collections.defaultdict(
        lambda: collections.defaultdict(dict))
    вне_схемы = []
    for ф in sorted(каталог.iterdir()):
        if not ф.is_file():
            continue
        м = МЕТКА.match(ф.name)
        if not м:
            вне_схемы.append(ф.name)
            continue
        поколения[м.group("поколение")][м.group("витрина")][
            м.group("вид")] = ф.as_posix()

    if not поколения:
        print(f"НЕ ИЗМЕРЕНО: ни одного файла по схеме имён в {каталог}")
        return 2

    проверка = полный_разбор if а.full else целость
    итог = []
    повреждённые = []
    for поколение in sorted(поколения, reverse=True):
        витрины = поколения[поколение]
        полных = 0
        неполных = []
        беды = []
        байт = 0
        for витрина, виды in sorted(витрины.items()):
            если_оба = "catalog" in виды and "details" in виды
            if not если_оба:
                неполных.append(f"{витрина}: только "
                                f"{', '.join(sorted(виды))}")
                continue
            плохо = []
            for вид, путь in sorted(виды.items()):
                байт += os.path.getsize(путь)
                ладно, почему = проверка(путь)
                if not ладно:
                    плохо.append(f"{вид}: {почему}")
                    повреждённые.append({"поколение": поколение,
                                         "витрина": витрина, "вид": вид,
                                         "путь": путь, "почему": почему,
                                         "байт": os.path.getsize(путь)})
            if плохо:
                беды.append(f"{витрина}: {'; '.join(плохо)}")
            else:
                полных += 1
        исход = ("ГОДНО" if полных and not неполных and not беды
                 else "НЕ ГОДНО")
        итог.append({"поколение": поколение, "исход": исход,
                     "витрин_полных": полных, "витрин_всего": len(витрины),
                     "гиб": round(байт / 2**30, 2),
                     "неполные": неполных, "повреждённые": беды})

    годных = [з for з in итог if з["исход"] == "ГОДНО"]
    if а.json:
        print(json.dumps({"каталог": str(каталог), "поколения": итог,
                          "повреждённые_файлы": повреждённые,
                          "вне_схемы_имён": вне_схемы[:20],
                          "годных": len(годных)},
                         ensure_ascii=False, indent=1))
    else:
        способ = "полный разбор JSON" if а.full else "проверка хвоста"
        print(f"каталог {каталог}\nспособ проверки: {способ}")
        print(f"поколений {len(итог)}, годных {len(годных)}\n")
        print(f"{'поколение':28} {'исход':9} {'витрин':>7} {'ГиБ':>6}  замечания")
        for з in итог:
            замечания = "; ".join(з["неполные"] + з["повреждённые"])[:70]
            print(f"{з['поколение']:28} {з['исход']:9}"
                  f" {з['витрин_полных']:3}/{з['витрин_всего']:<3}"
                  f" {з['гиб']:6.2f}  {замечания}")
        if повреждённые:
            print(f"\nПОВРЕЖДЁННЫЕ ФАЙЛЫ — учитываются отдельно и НЕ чинятся"
                  f" подменой из живого файла:")
            for п in повреждённые:
                print(f"   {п['байт']:>12} Б  {п['почему']}")
                print(f"                  {п['путь']}")
        if вне_схемы:
            print(f"\nфайлов вне схемы имён: {len(вне_схемы)}"
                  f" (не поколения суточных прогонов)")
    return 0 if годных else 1


if __name__ == "__main__":
    sys.exit(главное())
