#!/usr/bin/env python3
"""Наряд по активным домéнам: последнее полезное действие → следующая задача →
исполнитель → причина ожидания.

Повод — поручение владельца: по каждому активному домену видеть, что сделано
последним, что следующее, кто исполнитель и почему ждём. Перечисление роли в
отчёте распределением работы не считается, поэтому исполнитель здесь берётся
из рабочей системы — поля `owner` самой задачи (а при его отсутствии —
`executor` очереди домена), а не назначается этим инструментом.

Новых реестров не заводится: это ВИД по трём существующим источникам, и
каждый столбец берётся из своего.

* активность домена — паспорт ячейки `config/site-cells.json`, признак
  `withdrawal.withdrawn` через `node-cell-list.выведена`. Выведенные домены в
  продвижение не возвращаются, поэтому они и в наряд не попадают;
* действия, состояния, исполнители — очереди `config/domain-queues/*.json`;
* причина ожидания и её вид — `queue-pause-audit.проверить`, тот же разбор,
  что в аудите пауз. Второй разбор «почему стоит» разошёлся бы с первым.

«Полезное действие» — это состояние, в котором что-то изменилось к лучшему:
опубликовано, эффект измерен, закрыто, исследовано. `снято` полезным не
считается: задача ушла, а домен от этого ничего не получил. `заблокировано`
тем более: это и есть ожидание, которое инструмент объясняет отдельно.

Только чтение. Ни одного запроса, меняющего состояние.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import importlib.util
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ОЧЕРЕДИ = КОРЕНЬ / "config" / "domain-queues"
#: Состояния, в которых домен что-то получил.
ПОЛЕЗНЫЕ = ("опубликовано", "эффект измерен", "закрыто", "исследовано")
#: Состояния, из которых берётся следующая задача.
ГОТОВЫЕ_К_РАБОТЕ = ("подготовлено", "исследовано")


def _модуль(имя: str, файл: str):
    путь = КОРЕНЬ / "automation" / "local" / файл
    сп = importlib.util.spec_from_file_location(имя, путь)
    м = importlib.util.module_from_spec(сп)
    sys.modules[имя] = м
    сп.loader.exec_module(м)
    return м


def активные_домены(реестр: pathlib.Path | None = None) -> dict[str, str]:
    """Домен → site_id для ячеек, не выведенных из работы."""
    спис = _модуль("node_cell_list", "node-cell-list.py")
    итог: dict[str, str] = {}
    for я in спис.ячейки(реестр):
        if спис.выведена(я):
            continue
        for ключ in ("domain", "primary_domain"):
            if я.get(ключ):
                итог.setdefault(str(я[ключ]), str(я.get("site_id")))
        for д in я.get("domains") or []:
            итог.setdefault(str(д), str(я.get("site_id")))
    return итог


#: Замер общих файлов состояния, который уже делает карта служб. Читается
#: ГОТОВЫЙ, а не пересчитывается: пересчёт по 18 службам занимает около
#: минуты, и наряд перестал бы быть быстрым видом.
ЗАМЕР_ОБЩИХ = КОРЕНЬ / "artifacts" / "evidence" / "service-dependency-map-20261026.json"


def общее_состояние(путь: pathlib.Path = ЗАМЕР_ОБЩИХ) -> dict:
    """Предметы, по которым параллельная работа ограничена решением D221.

    Связь, которой не было: распределение работы (это файл) и измерение общих
    файлов состояния (карта служб) жили отдельно. D221 требует, чтобы разные
    исполнители перестали быть достаточным условием параллельной работы, —
    значит наряд обязан показывать, по каким предметам согласование корней не
    достигнуто.

    Свежесть замера называется вместе с ним (D222): устаревший замер — это
    «не измерено», а не «расхождений нет».
    """
    if not путь.is_file():
        return {"есть": False, "почему": f"замера нет: {путь.name}"}
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        return {"есть": False, "почему": f"замер не читается: {сбой}"}
    пары = данные.get("общие_файлы") or []
    когда = _dt.datetime.utcfromtimestamp(путь.stat().st_mtime).strftime("%Y-%m-%d %H:%M:%SZ")
    расходятся = [п_ for п_ in пары if п_.get("исход") == "расходятся"]
    return {"есть": True, "когда": когда, "всего": len(пары),
            "расходятся": расходятся,
            "не_измерено": sum(1 for п_ in пары if п_.get("исход") == "не измерено")}


def _дата(задача: dict) -> str:
    return str(задача.get("updated") or задача.get("created") or "")


def наряд_домена(данные: dict, домен: str, *, аудит, источники, канарейки,
                 сегодня: _dt.date) -> dict:
    задачи = данные.get("tasks") or []
    исполнитель_очереди = данные.get("executor") or ""

    свободные = [з for з in задачи
                 if (з.get("state") or "") in ГОТОВЫЕ_К_РАБОТЕ and not з.get("blocked_by")]
    # Задача в состоянии «исследовано» — и достижение, и следующий шаг. Но
    # выводить её в двух столбцах значит обещать домену работу, которой не
    # было: первый прогон печатал одну и ту же строку как «последнее
    # полезное» и как «следующую» у четырёх домéнов. Следующая задача из
    # прошлого вычитается.
    идёт = {з.get("id") for з in свободные[:1]}
    полезные = [з for з in задачи
                if (з.get("state") or "") in ПОЛЕЗНЫЕ and з.get("id") not in идёт]
    последнее = max(полезные, key=_дата) if полезные else None
    ждущие = [з for з in задачи if з.get("blocked_by")]
    следующая = свободные[0] if свободные else None

    ожидание = None
    if следующая is None and ждущие:
        # Причина берётся у первой ждущей задачи: она и есть то, что откроет
        # работу по домену. Вид — из аудита пауз, а не из своего разбора.
        первая = ждущие[0]
        ладно, вид, почему = аудит.проверить(
            str(первая["blocked_by"]), реестр=аудит.опыты_реестра(), журнал={},
            сегодня=сегодня, источники=источники, канарейки=канарейки)
        ожидание = {"задача": первая.get("id"), "вид": вид,
                    "подтверждена": ладно, "почему": почему,
                    "исполнитель": первая.get("owner") or исполнитель_очереди}

    return {
        "домен": домен,
        "последнее_полезное": None if последнее is None else {
            "задача": последнее.get("id"), "состояние": последнее.get("state"),
            "когда": _дата(последнее), "что": (последнее.get("title") or "")[:80]},
        "следующая": None if следующая is None else {
            "задача": следующая.get("id"), "что": (следующая.get("title") or "")[:80],
            "исполнитель": следующая.get("owner") or исполнитель_очереди},
        "ожидание": ожидание,
        "задач_всего": len(задачи),
        "задач_ждёт": len(ждущие),
    }


def собрать(очереди: pathlib.Path, *, сегодня: _dt.date,
            реестр: pathlib.Path | None = None) -> list[dict]:
    аудит = _модуль("queue_pause_audit", "queue-pause-audit.py")
    источники = аудит.источники_ссылок(КОРЕНЬ / "docs")
    канарейки = аудит.опыты_по_домену()
    активные = активные_домены(реестр)
    итог = []
    for файл in sorted(очереди.glob("*.json")):
        данные = json.loads(файл.read_text(encoding="utf-8"))
        домен = данные.get("domain") or файл.stem
        if домен not in активные:
            continue
        запись = наряд_домена(данные, домен, аудит=аудит, источники=источники,
                              канарейки=канарейки, сегодня=сегодня)
        запись["site_id"] = активные[домен]
        итог.append(запись)
    return итог


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--queues", type=pathlib.Path, default=ОЧЕРЕДИ)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    записи = собрать(а.queues, сегодня=_dt.date.today())
    if а.json:
        print(json.dumps(записи, ensure_ascii=False, indent=1))
        return 0

    # D221: разные исполнители — не достаточное условие параллельной работы.
    общее = общее_состояние()
    if не_надо := not общее["есть"]:
        print(f"общее состояние: {общее['почему']} — ограничения D221 НЕ ИЗМЕРЕНЫ")
    else:
        if общее["расходятся"]:
            print(f"ОГРАНИЧЕНИЕ D221 (замер {общее['когда']}): общих файлов "
                  f"состояния {общее['всего']}, расходятся {len(общее['расходятся'])} "
                  f"— по ним одновременная работа двух линий не допускается, пока "
                  f"корни не согласованы:")
            for п_ in общее["расходятся"]:
                линии = ", ".join(sorted(п_.get("службы") or {}))
                print(f"   {п_['файл']}: {линии[:90]}")
        else:
            print(f"ОГРАНИЧЕНИЕ D221 (замер {общее['когда']}): расхождений нет, "
                  f"общих файлов {общее['всего']}, не измерено {общее['не_измерено']}")
    без_очереди = [з for з in записи if not з["задач_всего"]]
    свободных = [з for з in записи if з["следующая"]]
    print(f"активных домéнов с очередью: {len(записи)}; "
          f"есть незаблокированная задача у {len(свободных)}")
    for з in записи:
        print(f"\n{з['домен']}  ({з['site_id']}, задач {з['задач_всего']}, "
              f"ждёт {з['задач_ждёт']})")
        п = з["последнее_полезное"]
        print("   последнее полезное: "
              + (f"{п['задача']} {п['состояние']} {п['когда']} — {п['что']}"
                 if п else "НЕТ: по этому домену ещё ничего не доведено"))
        с = з["следующая"]
        if с:
            print(f"   следующая: {с['задача']} — {с['что']}")
            print(f"   исполнитель: {с['исполнитель']}")
        else:
            о = з["ожидание"]
            print("   следующая: нет свободной задачи")
            if о:
                print(f"   ждёт: {о['задача']} — {о['вид']}"
                      f"{'' if о['подтверждена'] else ' (НЕ ПОДТВЕРЖДЕНО)'}")
                print(f"   почему: {о['почему'][:110]}")
                print(f"   исполнитель ожидания: {о['исполнитель']}")
            else:
                print("   ждёт: ничего — очередь исчерпана")
    if без_очереди:
        print(f"\nбез задач вовсе: {', '.join(з['домен'] for з in без_очереди)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная())
