#!/usr/bin/env python3
"""Независимая проверка механизма автопродолжения технического SEO.

Зачем отдельно от `seo_operator.tech_run`. Проверяющий шаг и очередь пишет
SEO-сессия; приёмка механизма — архитектора, и она обязана быть НЕЗАВИСИМОЙ:
проверка, написанная тем же, кто писал механизм, подтверждает замысел автора, а
не свойство механизма.

Проверяются четыре требования владельца, каждое отдельным признаком:

1. **очередь одна и машинно читаемая** — файл разбирается, идентификаторы не
   повторяются, у задачи есть repo и check;
2. **сохранение состояния** — следы прогонов и захватов лежат на диске и
   разбираются; состояние задачи выводится из них, а не из памяти процесса;
3. **восстановление после прерывания** — просроченный захват перестаёт держать
   задачу, И за ним не остаётся мусора: брошенные рабочие копии должны
   убираться, иначе они копятся с каждым прерванным прогоном;
4. **защита от одновременного выполнения ОДНОЙ задачи** — два прогона не могут
   получить одну задачу. Проверяется не чтением, а поведением: два вызова
   выбора подряд, без записи захвата между ними, обязаны дать разные задачи
   либо второй обязан получить отказ.

Отдельно проверяется свойство, без которого вердикт ничего не стоит: шаг
проверки обязан РАЗЛИЧАТЬ состояния (D203), и у задачи должна быть объявлена
своя проверка.

Ничего не запускает и не меняет: только читает очередь, следы и модуль.
"""
from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import json
import sys
from pathlib import Path

#: Дерево службы, где живут очередь, модуль и следы. Задаётся явно: у
#: архитектора своя рабочая копия, и проверять надо ДЕЙСТВУЮЩЕЕ дерево.
ДЕРЕВО = Path("/home/claude/wt-portable-site-cell-01")
НЕ_ИЗМЕРЕНО = "не измерено"


def загрузить_модуль(дерево: Path):
    """(модуль, причина). Модуль не найден — причина объясняет, почему."""
    путь = дерево / "seo_operator" / "tech_run.py"
    if not путь.is_file():
        return None, f"нет {путь}"
    спец = importlib.util.spec_from_file_location("tech_run_под_проверкой", путь)
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
    except Exception as сбой:  # noqa: BLE001 — чужой модуль не должен ронять приёмку
        return None, f"{type(сбой).__name__}: {сбой}"
    return модуль, ""


def метка(сдвиг_с: int = 0) -> str:
    т = dt.datetime.now(dt.timezone.utc) - dt.timedelta(seconds=сдвиг_с)
    return т.strftime("%Y-%m-%dT%H:%M:%SZ")


class Отчёт:
    def __init__(self) -> None:
        self.строки: list[tuple[str, str, str]] = []

    def шаг(self, имя: str, ок: bool | None, подробно: str = "") -> None:
        # None — «не измерено»: это факт о приёмке, а не о механизме, и в
        # расхождения он не идёт.
        знак = "ок " if ок else ("—  " if ок is None else "НЕТ")
        self.строки.append((знак, имя, подробно))

    @property
    def расхождений(self) -> int:
        return sum(1 for з, _и, _п in self.строки if з == "НЕТ")

    @property
    def не_измерено(self) -> int:
        return sum(1 for з, _и, _п in self.строки if з == "—  ")

    def печать(self) -> None:
        for знак, имя, подробно in self.строки:
            print(f"   [{знак}] {имя:54} {подробно}")


def проверить_очередь(дерево: Path, отчёт: Отчёт) -> list[dict]:
    путь = дерево / "config" / "seo-tech-queue.json"
    if not путь.is_file():
        отчёт.шаг("очередь существует", False, f"нет {путь}")
        return []
    try:
        сырое = json.loads(путь.read_text(encoding="utf-8"))
    except ValueError as сбой:
        отчёт.шаг("очередь разбирается как JSON", False, str(сбой))
        return []
    задачи = сырое.get("tasks") if isinstance(сырое, dict) else сырое
    задачи = задачи or []
    отчёт.шаг("очередь существует и разбирается", True,
              f"{путь}, записей {len(задачи)}")
    ид = [з.get("id") for з in задачи if isinstance(з, dict)]
    отчёт.шаг("идентификаторы задач не повторяются",
              len(ид) == len(set(ид)),
              f"всего {len(ид)}, различных {len(set(ид))}")
    без_проверки = [з.get("id") for з in задачи
                    if isinstance(з, dict) and з.get("status") == "queued"
                    and not з.get("check")]
    отчёт.шаг("у каждой задачи в очереди объявлена своя проверка",
              not без_проверки,
              "все объявлены" if not без_проверки
              else f"без проверки: {без_проверки}")
    без_репо = [з.get("id") for з in задачи
                if isinstance(з, dict) and з.get("status") == "queued"
                and not з.get("repo")]
    отчёт.шаг("у каждой задачи в очереди назван репозиторий",
              not без_репо, "все названы" if not без_репо
              else f"без репозитория: {без_репо}")
    return [з for з in задачи if isinstance(з, dict)]


def проверить_состояние(модуль, дерево: Path, отчёт: Отчёт) -> None:
    состояние = дерево / "var" / "seo-tech"
    отчёт.шаг("каталог состояния существует", состояние.is_dir(), str(состояние))
    for имя in ("claims.jsonl", "runs.jsonl"):
        ф = состояние / имя
        if not ф.exists():
            отчёт.шаг(f"след {имя} читается", None,
                      "файла ещё нет — прогонов не было")
            continue
        битые = [n for n, с in enumerate(
            ф.read_text(encoding="utf-8", errors="replace").splitlines(), 1)
            if с.strip() and not _разбирается(с)]
        отчёт.шаг(f"след {имя} разбирается построчно", not битые,
                  f"строк битых {len(битые)}" if битые else "все строки целы")
    try:
        сводка = модуль.task_state(состояние)
        отчёт.шаг("состояние задач выводится из следов", True,
                  f"задач в сводке {len(сводка)}")
    except Exception as сбой:  # noqa: BLE001
        отчёт.шаг("состояние задач выводится из следов", False,
                  f"{type(сбой).__name__}: {сбой}")


def _разбирается(строка: str) -> bool:
    try:
        json.loads(строка)
        return True
    except ValueError:
        return False


def проверить_захват(модуль, отчёт: Отчёт, стенд: Path) -> None:
    """Поведение выбора задачи на подставных следах. Живое состояние не трогается."""
    задачи = [{"id": "ПРОБА-1", "status": "queued", "repo": "r1",
               "check": "checks/x.py"},
              {"id": "ПРОБА-2", "status": "queued", "repo": "r2",
               "check": "checks/y.py"}]
    стенд.mkdir(parents=True, exist_ok=True)

    def записать(имя: str, строки: list[dict]) -> None:
        (стенд / имя).write_text(
            "".join(json.dumps(с, ensure_ascii=False) + "\n" for с in строки),
            encoding="utf-8")

    записать("runs.jsonl", [])
    записать("claims.jsonl", [{"run_id": "п-1", "task_id": "ПРОБА-1",
                               "at": метка(60), "repo": "r1"}])
    выбор = модуль.next_task(задачи, state=стенд)
    отчёт.шаг("живой захват не отдаёт свою задачу второму прогону",
              выбор is not None and выбор["id"] != "ПРОБА-1",
              f"выбрано {выбор and выбор['id']}")

    записать("claims.jsonl", [{"run_id": "п-1", "task_id": "ПРОБА-1",
                               "at": метка(3 * 3600), "repo": "r1"}])
    выбор = модуль.next_task(задачи, state=стенд)
    отчёт.шаг("просроченный захват задачу возвращает",
              выбор is not None and выбор["id"] == "ПРОБА-1",
              f"выбрано {выбор and выбор['id']}")

    # Главное требование: ОДНА задача не берётся дважды.
    записать("claims.jsonl", [])
    записать("runs.jsonl", [])
    первый = модуль.next_task(задачи, state=стенд)
    второй = модуль.next_task(задачи, state=стенд)
    одна_дважды = (первый is not None and второй is not None
                   and первый["id"] == второй["id"])
    отчёт.шаг("два прогона до записи захвата не получают одну задачу",
              not одна_дважды,
              f"оба получили {первый and первый['id']} — выбор и запись "
              "захвата не атомарны" if одна_дважды else "разные задачи")

    записать("claims.jsonl", [])
    записать("runs.jsonl", [{"run_id": f"п-{i}", "task_id": "ПРОБА-1",
                             "verdict": "INCOMPLETE"} for i in range(3)])
    выбор = модуль.next_task(задачи, state=стенд)
    отчёт.шаг("предел попыток держится",
              выбор is None or выбор["id"] != "ПРОБА-1",
              f"выбрано {выбор and выбор['id']}")


def проверить_уборку(модуль, дерево: Path, отчёт: Отчёт) -> None:
    """Остаются ли брошенные рабочие копии после прерванного прогона.

    Два признака, и они независимы: сколько копий лежит СЕЙЧАС — факт о
    состоянии, а есть ли в модуле уборка — факт о механизме. Второй проверяется
    всегда: пустой каталог копий означает лишь, что прогонов не было, а не что
    брошенная копия будет убрана.
    """
    состояние = дерево / "var" / "seo-tech"
    копии = состояние / "wt"
    if not копии.is_dir():
        отчёт.шаг("брошенных рабочих копий нет", None,
                  "каталога копий ещё нет — прогонов не было")
    else:
        живые = sorted(п.name for п in копии.iterdir() if п.is_dir())
        закрытые = set()
        ф = состояние / "runs.jsonl"
        if ф.exists():
            for с in ф.read_text(encoding="utf-8", errors="replace").splitlines():
                if _разбирается(с):
                    закрытые.add(json.loads(с).get("run_id"))
        брошенные = [и for и in живые if и.split("-verify-")[0] in закрытые]
        отчёт.шаг("за закрытыми прогонами не остаётся рабочих копий",
                  not брошенные,
                  f"копий всего {len(живые)}, брошенных {len(брошенные)}: "
                  f"{брошенные[:4]}" if брошенные else f"копий {len(живые)}")
    есть_уборка = any(hasattr(модуль, и) for и in
                      ("prune_worktrees", "убрать_брошенные", "recover"))
    отчёт.шаг("в модуле есть уборка брошенных копий", есть_уборка,
              "функции уборки нет: прерванный прогон оставляет копию, и они "
              "копятся" if not есть_уборка else "есть")


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--tree", type=Path, default=ДЕРЕВО,
                   help="дерево службы с очередью, модулем и следами")
    р.add_argument("--stand", type=Path,
                   default=Path("/tmp/seo-tech-audit-stand"),
                   help="каталог для подставных следов (живое не трогается)")
    опции = р.parse_args(аргв)

    модуль, причина = загрузить_модуль(опции.tree)
    отчёт = Отчёт()
    if модуль is None:
        print(f"механизм не проверен: {причина}", file=sys.stderr)
        return 2

    задачи = проверить_очередь(опции.tree, отчёт)
    проверить_состояние(модуль, опции.tree, отчёт)
    проверить_захват(модуль, отчёт, опции.stand)
    проверить_уборку(модуль, опции.tree, отчёт)

    отчёт.печать()
    print(f"\nзадач в очереди: {len(задачи)}; расхождений: "
          f"{отчёт.расхождений}; не измерено: {отчёт.не_измерено}")
    if отчёт.не_измерено:
        print("«не измерено» в расхождения не идёт: это факт о приёмке "
              "(следов ещё нет), а не о механизме.")
    return 1 if отчёт.расхождений else 0


if __name__ == "__main__":
    raise SystemExit(главное())
