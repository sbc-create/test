def загрузить_модуль(дерево: Path):
    """(модуль, причина). Модуль не найден — причина объясняет, почему."""
    путь = дерево / "seo_operator" / "tech_run.py"
    if not путь.is_file():
        return None, f"нет {путь}"
    спец = importlib.util.spec_from_file_location("tech_run_под_проверкой", путь)
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
    except Exception as сбой:  # noqa: BLE001 — чужой модуль не должен ронять приёмку
        return None, f"{type(сбой).__name__}: {сбой}"
    return модуль, ""


class Отчёт:
    def __init__(self) -> None:
        self.строки: list[tuple[str, str, str]] = []

    def шаг(self, имя: str, ок: bool | None, подробно: str = "") -> None:
        # None — «не измерено»: это факт о приёмке, а не о механизме, и в
        # расхождения он не идёт.
        знак = "ок " if ок else ("—  " if ок is None else "НЕТ")
        self.строки.append((знак, имя, подробно))

    @property
    def расхождений(self) -> int:
        return sum(1 for з, _и, _п in self.строки if з == "НЕТ")

    @property
    def не_измерено(self) -> int:
        return sum(1 for з, _и, _п in self.строки if з == "—  ")

    def печать(self) -> None:
        for знак, имя, подробно in self.строки:
            print(f"   [{знак}] {имя:58} {подробно}")


def _разбирается(строка: str) -> bool:
    try:
        json.loads(строка)
        return True
    except ValueError:
        return False


# --------------------------------------------------------------------------- #
#  1. Очередь и 2. состояние — читаются у ДЕЙСТВУЮЩЕГО дерева, без записи.
# --------------------------------------------------------------------------- #
def проверить_очередь(дерево: Path, отчёт: Отчёт) -> list[dict]:
    путь = дерево / "config" / "seo-tech-queue.json"
    if not путь.is_file():
        отчёт.шаг("очередь существует", False, f"нет {путь}")
        return []
    try:
        сырое = json.loads(путь.read_text(encoding="utf-8"))
    except ValueError as сбой:
        отчёт.шаг("очередь разбирается как JSON", False, str(сбой))
        return []
    задачи = сырое.get("tasks") if isinstance(сырое, dict) else сырое
    задачи = задачи or []
    отчёт.шаг("очередь существует и разбирается", True,
              f"{путь}, записей {len(задачи)}")
    ид = [з.get("id") for з in задачи if isinstance(з, dict)]
    отчёт.шаг("идентификаторы задач не повторяются",
              len(ид) == len(set(ид)),
              f"всего {len(ид)}, различных {len(set(ид))}")
    без_проверки = [з.get("id") for з in задачи
                    if isinstance(з, dict) and з.get("status") == "queued"
                    and not з.get("check")]
    отчёт.шаг("у каждой задачи в очереди объявлена своя проверка",
              not без_проверки,
              "все объявлены" if not без_проверки
              else f"без проверки: {без_проверки}")
    без_репо = [з.get("id") for з in задачи
                if isinstance(з, dict) and з.get("status") == "queued"
                and not з.get("repo")]
    отчёт.шаг("у каждой задачи в очереди назван репозиторий",
              not без_репо, "все названы" if not без_репо
              else f"без репозитория: {без_репо}")
    # Здесь стоял признак «пути проверок только ASCII»: `git ls-tree -r
    # --name-only` экранирует не-ASCII пути, и проверка с кириллическим именем
    # не нашлась бы в ветке. Признак СНЯТ, потому что механизм это закрыл —
    # `ls-tree -r -z` с разбором по `\0`, — а оставленный он кричал бы волка
    # на четырёх законных задачах (T009–T012 как раз с такими именами).
    # Проверка, которая тревожит по устаревшей причине, кончается тем, что её
    # перестают читать. Вместо неё свойство проверяется ПОВЕДЕНИЕМ: ниже
    # вердикт выносится задаче с кириллическим именем файла проверки.
    не_ascii = [з.get("id") for з in задачи
                if isinstance(з, dict) and з.get("check")
                and not str(з["check"]).isascii()]
    if не_ascii:
        print(f"   (к сведению: задач с не-ASCII путём проверки {len(не_ascii)}; "
              "механизм их находит — свойство проверяется прогоном ниже)")
    return [з for з in задачи if isinstance(з, dict)]


def проверить_состояние(модуль, дерево: Path, отчёт: Отчёт) -> None:
    состояние = дерево / "var" / "seo-tech"
    отчёт.шаг("каталог состояния существует", состояние.is_dir(), str(состояние))
    for имя in ("claims.jsonl", "runs.jsonl"):
        ф = состояние / имя
        if not ф.exists():
            отчёт.шаг(f"след {имя} читается", None,
                      "файла ещё нет — прогонов не было")
            continue
        битые = [n for n, с in enumerate(
            ф.read_text(encoding="utf-8", errors="replace").splitlines(), 1)
            if с.strip() and not _разбирается(с)]
        отчёт.шаг(f"след {имя} разбирается построчно", not битые,
                  f"строк битых {len(битые)}" if битые else "все строки целы")
    try:
        сводка = модуль.task_state(состояние)
        отчёт.шаг("состояние задач выводится из следов", True,
                  f"задач в сводке {len(сводка)}")
    except Exception as сбой:  # noqa: BLE001
        отчёт.шаг("состояние задач выводится из следов", False,
                  f"{type(сбой).__name__}: {сбой}")


# --------------------------------------------------------------------------- #
#  Одноразовый стенд: свой git-репозиторий и своя очередь.
# --------------------------------------------------------------------------- #
def _git(репо: Path, *арг: str) -> None:
    subprocess.run(["git", "-C", str(репо), *арг], check=True,
                   capture_output=True, text=True, timeout=120)


def собрать_стенд(стенд: Path) -> tuple[Path, Path, list[dict]]:
    """(репозиторий, файл очереди, задачи). Всё внутри `стенд`, живое не трогается."""
    if стенд.exists():
        shutil.rmtree(стенд)
    состояние = стенд / "state"
    состояние.mkdir(parents=True)
    репо = стенд / "repo"
    (репо / "src").mkdir(parents=True)
    (репо / "checks").mkdir(parents=True)
    (репо / "src" / "flag.txt").write_text("broken\n", encoding="utf-8")
    # Имена ASCII не для красоты: `git ls-tree` экранирует не-ASCII пути
    # («checks/\320\277…»), и признак check_in_branch сравнивает строки, то
    # есть на кириллическом имени проверки он провалился бы молча. В живой
    # очереди таких путей 0 из 15, поэтому это ловушка, а не дефект — она
    # отмечена отдельным признаком ниже.
    (репо / "checks" / "discriminating.py").write_text(
        ПРОВЕРКА_РАЗЛИЧАЮЩАЯ, encoding="utf-8")
    (репо / "checks" / "nondiscriminating.py").write_text(
        ПРОВЕРКА_НЕРАЗЛИЧАЮЩАЯ, encoding="utf-8")
    (репо / "checks" / "unusable.py").write_text(
        ПРОВЕРКА_НЕПРИГОДНАЯ, encoding="utf-8")
    # Кириллическое имя — нарочно: `ls-tree` без `-z` его экранирует, и
    # признак «проверка есть в ветке» сравнивал бы строки с экранированной.
    (репо / "checks" / "кириллица.py").write_text(
        ПРОВЕРКА_РАЗЛИЧАЮЩАЯ, encoding="utf-8")
    (репо / "checks" / "run.sh").write_text("#!/bin/bash\nexit 0\n", encoding="utf-8")
    _git(репо, "init", "-q", "-b", "main")
    _git(репо, "config", "user.email", "stand@example.invalid")
    _git(репо, "config", "user.name", "стенд приёмки")
    _git(репо, "add", "-A")
    _git(репо, "commit", "-q", "-m", "стенд")
    задачи = [
        {"id": "ПРОБА-1", "status": "queued", "repo": str(репо),
         "check": "checks/discriminating.py"},
        {"id": "ПРОБА-2", "status": "queued", "repo": str(репо),
         "check": "checks/discriminating.py"},
        {"id": "ПРОБА-НЕРАЗЛ", "status": "queued", "repo": str(репо),
         "check": "checks/nondiscriminating.py"},
        {"id": "ПРОБА-НЕПРИГ", "status": "queued", "repo": str(репо),
         "check": "checks/unusable.py"},
        # Для предела попыток нужна задача, которую никто не захватывал:
        # иначе её исключит живой замок, и признак пройдёт не из-за предела.
        {"id": "ПРОБА-ПРЕДЕЛ", "status": "queued", "repo": str(репо),
         "check": "checks/discriminating.py"},
        {"id": "ПРОБА-КИРИЛЛИЦА", "status": "queued", "repo": str(репо),
         "check": "checks/кириллица.py"},
    ]
    очередь = стенд / "queue.json"
    очередь.write_text(json.dumps({"tasks": задачи}, ensure_ascii=False),
                       encoding="utf-8")
    return репо, очередь, задачи


def _состарить_замок(состояние: Path, task_id: str, модуль) -> Path:
    """Сдвинуть mtime замка за предел просрочки — так выглядит убитый прогон."""
    замок = состояние / "claims" / f"{task_id}.claim"
    древность = dt.datetime.now().timestamp() - модуль.STALE_S - 60
    os.utime(замок, (древность, древность))
    return замок


# --------------------------------------------------------------------------- #
#  4. Захват: занятость и атомарность.
# --------------------------------------------------------------------------- #
def проверить_захват(модуль, отчёт: Отчёт, стенд: Path, задачи: list[dict]) -> None:
    состояние = стенд / "state"

    запись = модуль.claim_next(задачи, "прогон-1", state=состояние)
    отчёт.шаг("захват задачи оставляет замок с именем прогона",
              запись is not None
              and (состояние / "claims" / f"{запись['task_id']}.claim").is_file(),
              f"взято {запись and запись['task_id']}")

    второй = модуль.claim_next(задачи, "прогон-2", state=состояние)
    отчёт.шаг("второй прогон получает ДРУГУЮ задачу",
              второй is not None and запись is not None
              and второй["task_id"] != запись["task_id"],
              f"первый {запись and запись['task_id']}, "
              f"второй {второй and второй['task_id']}")

    # Главное требование владельца, и теперь оно проверяется там, где
    # атомарность и живёт: в самом захвате, а не в выборе кандидата.
    занято = False
    отказ = ""
    try:
        модуль.claim(dict(задачи[0]), "прогон-3", state=состояние)
    except Exception as сбой:  # noqa: BLE001
        занято = type(сбой).__name__ == "ЗанятоДругимПрогоном"
        отказ = type(сбой).__name__
    отчёт.шаг("повторный захват ЗАНЯТОЙ задачи отклоняется",
              занято, отказ or "захват прошёл дважды — задача может пойти в два прогона")

    # Задача под живым замком не попадает даже в кандидаты.
    отчёт.шаг("задача под живым замком не предлагается",
              запись is not None
              and запись["task_id"] not in
              [з["id"] for з in модуль.candidates(задачи, state=состояние)],
              f"кандидаты: {[з['id'] for з in модуль.candidates(задачи, state=состояние)]}")

    # Просроченный замок обязан отдать задачу обратно — иначе убитый прогон
    # держал бы её вечно.
    _состарить_замок(состояние, задачи[0]["id"], модуль)
    отчёт.шаг("просроченный замок задачу возвращает",
              задачи[0]["id"] in
              [з["id"] for з in модуль.candidates(задачи, state=состояние)],
              f"кандидаты: {[з['id'] for з in модуль.candidates(задачи, state=состояние)]}")

    # Предел попыток: три неудачи — и задача больше не берётся. Задача взята
    # незахваченная и проверяется В ОБЕ СТОРОНЫ: сперва она обязана быть
    # кандидатом, иначе признак прошёл бы по другой причине (так он и прошёл
    # в первой редакции — задачу исключал живой замок, а не предел).
    было_кандидатом = "ПРОБА-ПРЕДЕЛ" in [
        з["id"] for з in модуль.candidates(задачи, state=состояние)]
    with open(состояние / "runs.jsonl", "a", encoding="utf-8") as fh:
        for i in range(модуль.MAX_ATTEMPTS):
            fh.write(json.dumps({"run_id": f"неуд-{i}", "task_id": "ПРОБА-ПРЕДЕЛ",
                                 "verdict": "INCOMPLETE"}) + "\n")
    стало = [з["id"] for з in модуль.candidates(задачи, state=состояние)]
    отчёт.шаг("предел попыток держится",
              было_кандидатом and "ПРОБА-ПРЕДЕЛ" not in стало,
              f"до неудач кандидат: {было_кандидатом}; после "
              f"{модуль.MAX_ATTEMPTS} неудач "
              f"{'не предлагается' if 'ПРОБА-ПРЕДЕЛ' not in стало else 'всё ещё предлагается'}")


# --------------------------------------------------------------------------- #
#  3. Уборка: убрать брошенное, не тронув живое.
# --------------------------------------------------------------------------- #
def проверить_уборку(модуль, отчёт: Отчёт, стенд: Path, задачи: list[dict]) -> None:
    состояние = стенд / "state"
    # Каталог копий спрашивается У САМОГО МЕХАНИЗМА, а не зашивается здесь.
    # Измерено 15.10: механизм перенёс копии из `state/wt` в
    # `state.parent/<state.name>-wt` (проверкам витрин нужен реестр фабрики на
    # той же глубине, что `var/site-repos/<репо>`). Зашитый путь превратил это
    # в ЛОЖНЫЙ провал: уборка работала верно, копия живого прогона оставалась
    # на месте, а признак смотрел в прежний каталог, которого больше нет, и
    # сообщал «осталось []» — то есть выдавал устаревшее знание проверки за
    # дефект механизма. Тот же класс ошибки, что зашитый `current` у витрин
    # прямой установки: верный признак, неверное место.
    копии = (модуль.каталог_копий(состояние)
             if hasattr(модуль, "каталог_копий") else состояние / "wt")
    было = sorted(п.name for п in копии.iterdir()) if копии.is_dir() else []

    # «прогон-1» брошен: его замок просрочен (состарен выше). «прогон-2» жив.
    убрано = модуль.prune_worktrees(состояние)
    осталось = sorted(п.name for п in копии.iterdir()) if копии.is_dir() else []
    отчёт.шаг("брошенная рабочая копия убирается следующим прогоном",
              "прогон-1" in убрано,
              f"было {было}, убрано {убрано}, осталось {осталось}")
    отчёт.шаг("копия ЖИВОГО прогона уборкой не затрагивается",
              "прогон-2" in осталось,
              f"осталось {осталось}")
    отчёт.шаг("замок брошенного прогона снимается",
              not (состояние / "claims" / f"{задачи[0]['id']}.claim").exists(),
              "снят" if not (состояние / "claims" / f"{задачи[0]['id']}.claim").exists()
              else "остался — задача осталась бы занятой навсегда")

    # Копия закрытого прогона: вердикт записан, копия должна уйти.
    закрытый = модуль.claim_next(задачи, "прогон-закрыт", state=состояние)
    if закрытый:
        модуль.record({"run_id": "прогон-закрыт", "task_id": закрытый["task_id"],
                       "verdict": "VERIFIED"}, {}, state=состояние)
        убрано2 = модуль.prune_worktrees(состояние)
        отчёт.шаг("копия закрытого прогона убирается",
                  "прогон-закрыт" in убрано2, f"убрано {убрано2}")
    else:
        отчёт.шаг("копия закрытого прогона убирается", None,
                  "свободных задач на стенде не осталось")


# --------------------------------------------------------------------------- #
#  5. Вердикт: он обязан различать. Проверяется настоящими прогонами.
# --------------------------------------------------------------------------- #
def _исправить_и_закоммитить(копия: Path, значение: str = "fixed") -> None:
    (копия / "src" / "flag.txt").write_text(значение + "\n", encoding="utf-8")
    _git(копия, "config", "user.email", "stand@example.invalid")
    _git(копия, "config", "user.name", "стенд приёмки")
    _git(копия, "commit", "-q", "-am", "правка задачи")


def проверить_вердикт(модуль, отчёт: Отчёт, стенд: Path, задачи: list[dict]) -> None:
    """Самое важное: подтверждает ли вердикт результат КОНКРЕТНОЙ задачи."""
    состояние = стенд / "state"

    def прогнать(task_id: str, run_id: str, *, править: bool) -> dict:
        задача = next(з for з in задачи if з["id"] == task_id)
        # Замок мог остаться от прежних пунктов — снимаем, это стенд.
        (состояние / "claims" / f"{task_id}.claim").unlink(missing_ok=True)
        запись = модуль.claim(dict(задача), run_id, state=состояние)
        if править:
            _исправить_и_закоммитить(Path(запись["worktree"]))
        return модуль.verify(run_id, state=состояние)

    итог = прогнать("ПРОБА-1", "в-полный", править=True)
    шаги = итог.get("steps", {})
    отчёт.шаг("исправленная задача получает вердикт VERIFIED",
              итог.get("verdict") == "VERIFIED",
              f"{итог.get('verdict')}; провалены: "
              f"{[к for к, з in шаги.items() if not з] or 'нет'}")
    отчёт.шаг("проверка падает на неисправленном состоянии (D203)",
              шаги.get("check_fails_on_base") is True,
              f"check_fails_on_base={шаги.get('check_fails_on_base')}")

    итог = прогнать("ПРОБА-1", "в-без-коммита", править=False)
    отчёт.шаг("ветка без коммита вердикта не получает",
              итог.get("verdict") != "VERIFIED"
              and итог.get("steps", {}).get("has_commit") is not True,
              f"{итог.get('verdict')}, has_commit="
              f"{итог.get('steps', {}).get('has_commit')}")

    итог = прогнать("ПРОБА-НЕРАЗЛ", "в-неразл", править=True)
    шаги = итог.get("steps", {})
    отчёт.шаг("проверка, проходящая и на базе, вердикта не даёт",
              итог.get("verdict") != "VERIFIED"
              and шаги.get("check_fails_on_base") is False,
              f"{итог.get('verdict')}, check_fails_on_base="
              f"{шаги.get('check_fails_on_base')}")

    итог = прогнать("ПРОБА-КИРИЛЛИЦА", "в-кириллица", править=True)
    отчёт.шаг("проверка с не-ASCII именем находится в ветке",
              итог.get("verdict") == "VERIFIED",
              f"{итог.get('verdict')}; check_in_branch="
              f"{итог.get('steps', {}).get('check_in_branch')}")

    итог = прогнать("ПРОБА-НЕПРИГ", "в-неприг", править=True)
    шаги = итог.get("steps", {})
    # Главное в этом пункте: собственная ошибка проверки НЕ выглядит
    # различением. Необработанное исключение Python выходит с кодом 1, поэтому
    # «ненулевой код» здесь ничего не доказывает.
    отчёт.шаг("проверка, упавшая своей ошибкой, различением не считается",
              итог.get("verdict") != "VERIFIED"
              and шаги.get("check_usable") is False,
              f"{итог.get('verdict')}, check_usable={шаги.get('check_usable')}")


def проверить_отправленную_ветку(модуль, отчёт: Отчёт, стенд: Path,
                                 задачи: list[dict]) -> None:
    """Ветка с удалённым двойником вердикта получать не должна: выпуск не наш."""
    состояние = стенд / "state"
    task_id = "ПРОБА-2"
    задача = next(з for з in задачи if з["id"] == task_id)
    (состояние / "claims" / f"{task_id}.claim").unlink(missing_ok=True)
    # Захватываем напрямую: задача могла быть исключена из кандидатов
    # прежними пунктами, а здесь проверяется не выбор, а вердикт.
    запись = модуль.claim(dict(задача), "в-отправлена", state=состояние)
    копия = Path(запись["worktree"])
    _исправить_и_закоммитить(копия)
    репо = Path(задача["repo"])
    голова = subprocess.run(["git", "-C", str(репо), "rev-parse", запись["branch"]],
                            capture_output=True, text=True).stdout.strip()
    _git(репо, "update-ref", f"refs/remotes/origin/{запись['branch']}", голова)
    итог = модуль.verify("в-отправлена", state=состояние)
    отчёт.шаг("ветка с удалённым двойником вердикта не получает",
              итог.get("verdict") != "VERIFIED"
              and итог.get("steps", {}).get("not_pushed") is False,
              f"{итог.get('verdict')}, not_pushed="
              f"{итог.get('steps', {}).get('not_pushed')}")


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--tree", type=Path, default=ДЕРЕВО,
                   help="дерево службы с очередью, модулем и следами")
    р.add_argument("--stand", type=Path,
                   default=Path("/tmp/seo-tech-audit-stand"),
                   help="каталог одноразового стенда (живое не трогается)")
    опции = р.parse_args(аргв)

    модуль, причина = загрузить_модуль(опции.tree)
    отчёт = Отчёт()
    if модуль is None:
        print(f"механизм не проверен: {причина}", file=sys.stderr)
        return 2

    задачи_очереди = проверить_очередь(опции.tree, отчёт)
    проверить_состояние(модуль, опции.tree, отчёт)

    try:
        репо, очередь, задачи = собрать_стенд(опции.stand)
    except Exception as сбой:  # noqa: BLE001
        отчёт.печать()
        print(f"\nповедение не проверено: стенд не собрался — "
              f"{type(сбой).__name__}: {сбой}", file=sys.stderr)
        return 2

    # Модуль читает очередь и корень репозиториев из своих постоянных: на
    # время стенда они переводятся на стенд, чтобы ни одна запись не ушла в
    # живое дерево. Путь репозитория в задаче абсолютный, поэтому REPO к нему
    # не прибавляется.
    #
    # Подменить QUEUE недостаточно, и это стоило мне четырёх ложных
    # расхождений: `load_queue(путь: Path = QUEUE)` связывает очередь в
    # ЗНАЧЕНИИ ПО УМОЛЧАНИЮ, то есть на момент определения функции, а verify()
    # зовёт её без аргумента. Поэтому подменяется сама функция.
    модуль.QUEUE = очередь
    модуль.STATE = опции.stand / "state"
    модуль.REPO = опции.stand
    модуль.load_queue = lambda путь=None: задачи

    try:
        проверить_захват(модуль, отчёт, опции.stand, задачи)
        проверить_уборку(модуль, отчёт, опции.stand, задачи)
        проверить_вердикт(модуль, отчёт, опции.stand, задачи)
        проверить_отправленную_ветку(модуль, отчёт, опции.stand, задачи)
    except Exception as сбой:  # noqa: BLE001
        отчёт.шаг("пункты поведения доведены до конца", False,
                  f"{type(сбой).__name__}: {сбой}")

    отчёт.печать()
    print(f"\nзадач в живой очереди: {len(задачи_очереди)}; расхождений: "
          f"{отчёт.расхождений}; не измерено: {отчёт.не_измерено}")
    if отчёт.не_измерено:
        print("«не измерено» в расхождения не идёт: это факт о приёмке "
              "(следов ещё нет), а не о механизме.")
    return 1 if отчёт.расхождений else 0


if __name__ == "__main__":
    raise SystemExit(главное())
