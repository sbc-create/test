#!/usr/bin/env python3
"""Независимая проверка механизма автопродолжения технического SEO.

Зачем отдельно от `seo_operator.tech_run`. Проверяющий шаг и очередь пишет
SEO-сессия; приёмка механизма — архитектора, и она обязана быть НЕЗАВИСИМОЙ:
проверка, написанная тем же, кто писал механизм, подтверждает замысел автора, а
не свойство механизма.

Проверяются требования владельца, каждое отдельным признаком:

1. **очередь одна и машинно читаемая** — файл разбирается, идентификаторы не
   повторяются, у задачи есть repo и check;
2. **сохранение состояния** — следы прогонов и захватов лежат на диске и
   разбираются; состояние задачи выводится из них, а не из памяти процесса;
3. **восстановление после прерывания** — просроченный захват перестаёт держать
   задачу, И за ним не остаётся мусора: брошенные рабочие копии убираются
   следующим прогоном, а копия ЖИВОГО прогона при этом не страдает;
4. **защита от одновременного выполнения ОДНОЙ задачи** — из двух захватов
   одной задачи ровно один проходит, второй получает отказ;
5. **вердикт различает** — и это проверяется на настоящих прогонах
   проверяющего шага, а не чтением кода: проверка, которая проходит и на
   неисправленном состоянии, вердикта не даёт (D203); проверка, упавшая
   собственной ошибкой, вердикта тоже не даёт; ветка с удалённым двойником
   вердикта не получает.

Контракт, под который написана приёмка (он сменился 12.10): «занято» — это
файл-замок `claims/<task_id>.claim`, свежесть по mtime; `claims.jsonl` —
журнал и на занятость не влияет. Приёмка прежнего контракта давала бы ложный
вердикт, поэтому пункты поведения переписаны целиком.

Живое состояние службы не трогается ничем: все пункты поведения идут на
одноразовом стенде — отдельный git-репозиторий и отдельная очередь в каталоге
`--stand`. Стенд создаётся вызовами git из этого сценария; других целей git
здесь нет.
"""
