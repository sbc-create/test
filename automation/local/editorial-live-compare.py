#!/usr/bin/env python3
"""Сопоставление сохранённого редакционного текста с текстом живой страницы.

Повод. В реестре оператора 58 записей со статусом `ALREADY_LIVE` и 2 с
`PUBLISHED`. Статус — это утверждение, а не измерение: он говорит, что текст
на странице, но не проверяет этого. Из 58 «живых» тело сохранено лишь у 15 —
по остальным сравнивать нечего, и это надо называть, а не считать совпадением.

Что инструмент различает (ПЯТЬ исходов, а не два):
  СОВПАЛ        — сохранённый текст найден на странице;
  СТАТУС НЕ НА ТОЙ ЗАПИСИ — текста ЭТОЙ записи на странице нет, но там лежит
                  текст ДРУГОЙ записи того же адреса; страница в порядке,
                  неверна разметка реестра;
  РАСХОДИТСЯ    — страница отдалась, и ни одна запись этого адреса на ней не
                  найдена;
  НЕЧЕГО СРАВНИТЬ — статус живой, а тела в реестре нет;
  НЕ ИЗМЕРЕНО   — страница не отдалась; причина печатается.

Пятый исход добавлен 25.10 по измерению: у `3x3-glaza`, `5-santimetrov-v-
sekundu` и `7-samuraev` статус `ALREADY_LIVE` стоял на одной редакции, а на
странице лежала другая — из соседней записи `READY_VERIFIED` того же адреса.
Прежний вывод «текста на странице нет» был неверен: текст там есть, просто
статус помечает не ту запись. Разница важна: в первом случае страница пуста
для посетителя, во втором — нет.

Положительный контроль обязателен: страница, про которую известно, что текст
на ней есть, должна дать СОВПАЛ. Если контроль не проходит, замер не
печатается — иначе «расходится» у всех неотличимо от сломанного разбора HTML.

Счётчики Метрики не вызываются: curl не исполняет JavaScript.
"""
from __future__ import annotations

import argparse
import html
import json
import pathlib
import re
import subprocess
import sys

РЕЕСТР = pathlib.Path("/var/lib/seo-content-operator/registry.json")
ЖИВЫЕ = ("PUBLISHED", "ALREADY_LIVE")


def нормализовать(т: str) -> str:
    т = html.unescape(т)
    т = т.replace(" ", " ").replace("ё", "е").replace("Ё", "Е")
    т = re.sub(r"[«»“”„\"']", "", т)
    return " ".join(т.split()).lower()


def текст_страницы(html_код: str) -> tuple[str, str]:
    """Видимый текст и содержимое meta description.

    Описание произведения живёт либо в разметке страницы, либо в
    meta description — проверяются оба, иначе совпадение теряется там, где
    текст на самом деле есть.
    """
    м = re.search(
        r'<meta[^>]+name=["\']description["\'][^>]+content=["\'](.*?)["\']',
        html_код, re.S | re.I)
    описание = нормализовать(м.group(1)) if м else ""
    без = re.sub(r"(?is)<(script|style|noscript)\b.*?</\1>", " ", html_код)
    без = re.sub(r"(?s)<[^>]+>", " ", без)
    return нормализовать(без), описание


def загрузить(url: str, таймаут: int) -> tuple[str, str]:
    """HTML страницы или причина, по которой его нет.

    КОД ОТВЕТА ПРОВЕРЯЕТСЯ. Измерено 24.10: без этой проверки инструмент
    принял тело «503 Service Unavailable: overloaded, retry later» за текст
    страницы и объявил РАСХОЖДЕНИЕ там, где измерения не было вовсе. Утилита
    без ключа -f возвращает 0 и на 503, поэтому её код выхода о странице не
    говорит ничего. Отрицательный вывод при невозможности измерить — худший
    из исходов: по нему идут исправлять то, что не сломано.
    """
    try:
        г = subprocess.run(
            ["curl", "-sS", "-L", "--max-time", str(таймаут),
             "-w", "\\n@@КОД:%{http_code}",
             "-A", "factory-editorial-live-compare",
             url],
            capture_output=True, text=True, timeout=таймаут + 10)
    except subprocess.TimeoutExpired:
        return "", f"превышен предел ожидания {таймаут} с"
    if г.returncode != 0:
        return "", (г.stderr.strip().splitlines() or ["загрузчик молча отказал"])[-1]
    тело, _, хвост = г.stdout.rpartition("@@КОД:")
    код = хвост.strip()
    if код != "200":
        return "", f"страница не отдалась: HTTP {код or 'код не получен'}"
    if not тело.strip():
        return "", "пустой ответ при HTTP 200"
    return тело, ""


def доля_фраз(тело: str, страница: str, описание: str) -> tuple[float, int, int]:
    """Какая доля фраз сохранённого текста найдена на странице.

    По фразам, а не целиком: на странице текст может быть разбит разметкой,
    урезан по длине или начинаться с другого места. Фразы короче 40 знаков
    отбрасываются — такие совпадают случайно.
    """
    фразы = [ф.strip() for ф in re.split(r"(?<=[.!?])\s+", тело)]
    фразы = [ф for ф in фразы if len(ф) >= 40]
    if not фразы:
        фразы = [тело[:120]] if len(тело) >= 40 else []
    если_нет = 0
    for ф in фразы:
        if ф in страница or ф in описание:
            если_нет += 1
    return (если_нет / len(фразы) if фразы else 0.0), если_нет, len(фразы)


def сравнить_запись(з: dict, таймаут: int, соседи: list[dict] | None = None) -> dict:
    """Сверка ОДНОЙ записи со страницей.

    `соседи` — другие записи того же адреса. Нужны, чтобы отличить «страница
    пуста» от «статус стоит не на той записи»: во втором случае текст на
    странице есть, но принадлежит соседней редакции.
    """
    тело = нормализовать((з.get("body") or "").strip())
    url = з.get("canonical_url") or ""
    итог = {"домен": з.get("target_site"), "url": url,
            "title_id": з.get("title_id"), "статус": з["status"],
            "content_id": з["content_id"]}
    if not тело:
        итог["исход"] = "НЕЧЕГО СРАВНИТЬ"
        итог["почему"] = "в реестре нет тела текста"
        return итог
    if not url:
        итог["исход"] = "НЕЧЕГО СРАВНИТЬ"
        итог["почему"] = "в записи нет публичного адреса"
        return итог
    код, причина = загрузить(url, таймаут)
    if не_отдалась := причина:
        итог["исход"] = "НЕ ИЗМЕРЕНО"
        итог["почему"] = не_отдалась
        return итог
    стр, опис = текст_страницы(код)
    доля, нашлось, всего = доля_фраз(тело, стр, опис)
    итог.update({"доля": доля, "фраз_нашлось": нашлось, "фраз_всего": всего,
                 "знаков_в_теле": len(тело)})
    if доля >= 0.5:
        итог["исход"] = "СОВПАЛ"
        return итог
    #: Прежде чем сказать «на странице нет текста», проверяется, не лежит ли
    #: там текст ДРУГОЙ записи того же адреса. Иначе ошибка разметки реестра
    #: читается как пустая страница (измерено 25.10 на четырёх страницах).
    for с in (соседи or []):
        чужое = нормализовать((с.get("body") or "").strip())
        if not чужое or с.get("content_id") == з.get("content_id"):
            continue
        д2, н2, в2 = доля_фраз(чужое, стр, опис)
        if д2 >= 0.5:
            итог["исход"] = "СТАТУС НЕ НА ТОЙ ЗАПИСИ"
            итог["почему"] = (
                f"на странице лежит текст записи {с.get('content_id')}"
                f" (статус {с.get('status')}, {len(чужое)} знаков,"
                f" совпало {н2} из {в2} фраз), а не этой"
                f" ({len(тело)} знаков). Страница в порядке, неверна разметка")
            итог["живая_запись"] = с.get("content_id")
            return итог
    итог["исход"] = "РАСХОДИТСЯ"
    начало = тело[:60]
    итог["почему"] = ("начало сохранённого текста на странице не найдено"
                      if начало not in стр and начало not in опис
                      else "найдена часть фраз, но меньше половины")
    return итог


def контроль(зп: list[dict], таймаут: int) -> tuple[bool, str]:
    """Положительный контроль разбора: текст из <title> страницы обязан найтись.

    Контроль проверяет не редакцию, а сам инструмент: что страница грузится и
    что видимый текст из неё извлекается. Берётся произведение, чей заголовок
    записан в реестре.
    """
    кандидаты = [з for з in зп if з["status"] in ЖИВЫЕ and з.get("canonical_url")
                 and (з.get("headline") or "").strip()]
    if not кандидаты:
        return False, "не нашлось ни одной живой записи с заголовком"
    з = кандидаты[0]
    код, причина = загрузить(з["canonical_url"], таймаут)
    if причина:
        return False, f"контрольная страница {з['canonical_url']} не отдалась: {причина}"
    стр, опис = текст_страницы(код)
    if len(стр) < 200:
        return False, (f"из {з['canonical_url']} извлечено лишь {len(стр)} знаков"
                       " текста — разбор HTML сломан")
    слово = нормализовать(з["headline"]).split()[0]
    if слово not in стр and слово not in опис:
        return False, (f"на контрольной странице не найдено даже слово «{слово}»"
                       " из заголовка её же произведения — разбор не доверяем")
    return True, (f"контроль: {з['canonical_url']} — извлечено {len(стр)} знаков,"
                  f" слово «{слово}» из заголовка найдено")


def главное(argv: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--limit", type=int, default=0, help="0 — все подходящие")
    р.add_argument("--timeout", type=int, default=25)
    р.add_argument("--registry", type=pathlib.Path, default=РЕЕСТР)
    р.add_argument("--json", type=pathlib.Path)
    а = р.parse_args(argv)

    if not а.registry.exists():
        print(f"НЕ ИЗМЕРЕНО: реестра нет по пути {а.registry}")
        return 2
    зп = json.loads(а.registry.read_text(encoding="utf-8"))["items"]
    живые = [з for з in зп if з["status"] in ЖИВЫЕ]
    с_телом = [з for з in живые if (з.get("body") or "").strip()]
    опубл = sum(1 for з in живые if з["status"] == "PUBLISHED")
    уже = sum(1 for з in живые if з["status"] == "ALREADY_LIVE")
    print(f"записей со статусом живых: {len(живые)}"
          f" (PUBLISHED={опубл}, ALREADY_LIVE={уже})")
    print(f"из них с сохранённым телом: {len(с_телом)};"
          f" без тела: {len(живые) - len(с_телом)} — сравнивать нечего")
    print()

    ок, сообщение = контроль(зп, а.timeout)
    print(сообщение)
    if not ок:
        print("ВЫВОД: НЕ ИЗМЕРЕНО — положительный контроль не пройден,"
              " сравнение не выполняется")
        return 3
    print()

    отбор = с_телом if not а.limit else с_телом[:а.limit]
    #: Соседи по адресу — ВСЕ записи реестра на тот же канонический адрес, а
    #: не только живые: живой текст может лежать в записи READY_VERIFIED.
    по_адресу: dict[str, list[dict]] = {}
    for з in зп:
        по_адресу.setdefault(з.get("canonical_url") or "", []).append(з)
    итоги = []
    for з in отбор:
        и = сравнить_запись(з, а.timeout,
                            по_адресу.get(з.get("canonical_url") or ""))
        итоги.append(и)
        д = f"{и['доля']:.0%} ({и['фраз_нашлось']}/{и['фраз_всего']} фраз)" if "доля" in и else "—"
        print(f"  {и['исход']:16} {д:22} {и['url']}")
        if и.get("почему"):
            print(f"      {и['почему']}")

    совпало = [и for и in итоги if и["исход"] == "СОВПАЛ"]
    не_та = [и for и in итоги if и["исход"] == "СТАТУС НЕ НА ТОЙ ЗАПИСИ"]
    разошлось = [и for и in итоги if и["исход"] == "РАСХОДИТСЯ"]
    неизмерено = [и for и in итоги if и["исход"] == "НЕ ИЗМЕРЕНО"]
    нечего = [и for и in итоги if и["исход"] == "НЕЧЕГО СРАВНИТЬ"]
    print()
    print(f"сравнено страниц {len(итоги)} из {len(живые)} живых записей"
          f" (у {len(живые) - len(с_телом)} тела в реестре нет)")
    print(f"СОВПАЛ {len(совпало)}, СТАТУС НЕ НА ТОЙ ЗАПИСИ {len(не_та)},"
          f" РАСХОДИТСЯ {len(разошлось)},"
          f" НЕ ИЗМЕРЕНО {len(неизмерено)}, НЕЧЕГО СРАВНИТЬ {len(нечего)}")
    if не_та:
        print(f"  у {len(не_та)} страниц текст НА МЕСТЕ, но статус живого стоит"
              " на другой записи того же адреса — это ошибка разметки реестра,"
              " а не пустая страница")
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        а.json.write_text(json.dumps(итоги, ensure_ascii=False, indent=1),
                          encoding="utf-8")
        print(f"подробности: {а.json}")
    if не_сравнено := len(неизмерено):
        print(f"ВЫВОД: {len(совпало)} из {len(итоги)} сохранённых текстов найдены"
              f" на своих страницах; {не_сравнено} страниц не отдались —"
              " по ним вывода нет")
        return 1
    print(f"ВЫВОД: {len(совпало)} из {len(итоги)} сохранённых текстов найдены"
          f" на своих страницах, {len(разошлось)} — нет")
    return 0 if совпало and not разошлось else 1


if __name__ == "__main__":
    sys.exit(главное())
