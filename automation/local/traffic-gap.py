#!/usr/bin/env python3
"""Разрыв до цели 5 000 визитов в сутки — по каждому домену, по полным суткам.

Цель владельца: устойчивые 5 000 реальных визитов в сутки на КАЖДОМ сайте.
Этот инструмент отвечает на первый вопрос такой работы: где мы сейчас и
сколько не хватает — по дням, а не средним по сети.

Что считается и как:

* сутки — ПОЛНЫЕ, по часовому поясу счётчика (Europe/Moscow у всех записей
  реестра); незаконченные сутки не берутся;
* роботы отделены: суточный ряд приходит с размерностью `ym:s:isRobot`, и
  людей считаем отдельно. «Визиты» и «пользователи» не смешиваются;
* отсутствие измерения — НЕ ноль. Домен без ряда называется отдельно, с
  причиной из того же артефакта;
* всплески не сглаживаются: печатается максимум и минимум суток, чтобы
  аномалию было видно, а не усреднено.

Источник — артефакт службы сбора (`var/analytics/*.json`), то есть та копия,
по которой работает `analytics-cabinet`. Утверждение о реестре без имени копии
ничего не значит (MOD-40), поэтому путь печатается.

    python3 automation/local/traffic-gap.py
    python3 automation/local/traffic-gap.py --artifact <путь>
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ЦЕЛЬ = 5000
ПО_УМОЛЧАНИЮ = Path("/home/claude/wt-portable-site-cell-01/var/analytics/"
                    "slice-20261015-refresh.json")


def суточный_ряд(измерение: dict) -> tuple[dict[str, float], dict[str, float]]:
    """(люди по дням, роботы по дням) из ряда `daily_users`.

    Метрики приходят парой [пользователи, визиты]; берутся ВИЗИТЫ — цель
    владельца сформулирована в визитах, и подменять их пользователями нельзя.
    """
    люди: dict[str, float] = {}
    роботы: dict[str, float] = {}
    for строка in измерение.get("value") or []:
        размеры = строка.get("dimensions") or []
        метрики = строка.get("metrics") or []
        if len(размеры) < 2 or len(метрики) < 2:
            continue
        день = str(размеры[0].get("name") or "")
        робот = str(размеры[1].get("id") or "").lower() == "yes"
        визиты = float(метрики[1])
        (роботы if робот else люди)[день] = визиты
    return люди, роботы


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--artifact", type=Path, default=ПО_УМОЛЧАНИЮ)
    р.add_argument("--goal", type=int, default=ЦЕЛЬ)
    опции = р.parse_args(аргв)

    if not опции.artifact.is_file():
        print(f"артефакта нет: {опции.artifact}")
        return 2
    д = json.loads(опции.artifact.read_text(encoding="utf-8"))
    период = д.get("period") or {}
    print(f"артефакт: {опции.artifact}")
    print(f"собран: {д.get('collected_at')}; период "
          f"{период.get('date1')} .. {период.get('date2')}")
    print(f"цель: {опции.goal} визитов в сутки на каждом домене\n")

    строки = []
    без_ряда = []
    for я in д.get("domains") or []:
        домен = я["domain"]
        по_ключу = {м["key"]: м for м in я.get("measurements") or []}
        ряд = по_ключу.get("daily_users") or {}
        if not ряд.get("measured"):
            без_ряда.append((домен, (ряд.get("reason") or "нет измерения")[:60]))
            continue
        люди, роботы = суточный_ряд(ряд)
        if not люди:
            без_ряда.append((домен, "ряд пуст: людей в выборке нет"))
            continue
        дни = sorted(люди)
        значения = [люди[д_] for д_ in дни]
        среднее = sum(значения) / len(значения)
        достигнуто = sum(1 for з in значения if з >= опции.goal)
        строки.append({
            "домен": домен,
            "дней": len(дни),
            "среднее": среднее,
            "минимум": min(значения),
            "максимум": max(значения),
            "достигнуто": достигнуто,
            "разрыв": max(0.0, опции.goal - среднее),
            "во_сколько": (опции.goal / среднее) if среднее else None,
            "роботов_в_сутки": (sum(роботы.values()) / len(роботы)) if роботы else 0.0,
        })

    строки.sort(key=lambda с: -с["среднее"])
    print(f"{'домен':24s} {'дней':>4s} {'сред/сут':>9s} {'мин':>7s} {'макс':>7s} "
          f"{'дней≥цели':>10s} {'разрыв':>8s} {'во сколько':>11s} {'роботов':>8s}")
    for с in строки:
        во = f"×{с['во_сколько']:.0f}" if с["во_сколько"] else "—"
        print(f"{с['домен']:24s} {с['дней']:4d} {с['среднее']:9.1f} "
              f"{с['минимум']:7.0f} {с['максимум']:7.0f} {с['достигнуто']:10d} "
              f"{с['разрыв']:8.0f} {во:>11s} {с['роботов_в_сутки']:8.1f}")

    всего = sum(с["среднее"] for с in строки)
    достигают = [с["домен"] for с in строки if с["среднее"] >= опции.goal]
    print(f"\nдоменов с суточным рядом: {len(строки)}; суммарно "
          f"{всего:.0f} визитов в сутки по сети")
    print(f"достигают цели в среднем: {', '.join(достигают) or 'ни один'}")
    print(f"общий трафик сети цель по каждому домену НЕ заменяет: "
          f"{len(строки) - len(достигают)} доменов ниже цели")
    if без_ряда:
        print(f"\nбез суточного ряда — НЕ НОЛЬ, а не измерено ({len(без_ряда)}):")
        for домен, причина in без_ряда:
            print(f"   {домен:24s} {причина}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
