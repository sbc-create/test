#!/usr/bin/env python3
"""Два цикла автопродолжения подряд: доказательство или его отсутствие.

Критерий владельца: **две РАЗНЫЕ полезные задачи подряд, без ручной команды
между ними, с результатами и отметками времени.** Один цикл доказывает только
запуск, а «таймер включён» не доказывает и этого.

Поэтому проверяются пять свойств, каждое отдельным признаком:

1. циклов подряд не меньше двух;
2. оба запущены ТАЙМЕРОМ — `trigger` говорит `systemd-timer`, а не `manual`;
3. между ними не было ручного прогона — иначе «подряд» неверно;
4. задачи РАЗНЫЕ: у технической очереди это `task_id`, у редакционной —
   множества адресов, и они не должны пересекаться;
5. у каждого цикла есть ВЕРДИКТ проверяющего шага, а не только код выхода
   процесса: самоотчёт модели и `model_exit=0` по отдельности выполнения не
   подтверждают.

Читает только следы. `--kind tech` — техническая очередь
(`var/seo-tech/runs.jsonl`), `--kind editor` — редакционная
(`var/editor-runs/runs.jsonl`). Отсутствие следов даёт «не измерено» кодом 2,
а не «не подтверждено»: это разные утверждения.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ДЕРЕВО = Path("/home/claude/wt-portable-site-cell-01")
СЛЕДЫ = {
    "tech": ДЕРЕВО / "var" / "seo-tech" / "runs.jsonl",
    "editor": ДЕРЕВО / "var" / "editor-runs" / "runs.jsonl",
}
#: Какой `trigger` считается запуском по расписанию.
ПО_РАСПИСАНИЮ = "systemd-timer"


def строки(путь: Path) -> list[dict]:
    if not путь.is_file():
        return []
    итог = []
    for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
        if не_пусто := строка.strip():
            try:
                итог.append(json.loads(не_пусто))
            except ValueError:
                continue
    return итог


def задача(вид: str, запись: dict) -> frozenset:
    """Чем задача опознаётся: у техники — id, у редакции — адреса."""
    if вид == "tech":
        ид = запись.get("task_id")
        return frozenset({str(ид)}) if ид else frozenset()
    адреса = (запись.get("self_report") or {}).get("urls") or []
    return frozenset(str(а) for а in адреса)


def вердикт(вид: str, запись: dict) -> str:
    if вид == "tech":
        return str(запись.get("verdict") or "")
    # У редакционного прогона вердикт проверяющего шага — `verified_complete`,
    # а `verdict` рядом пишет сам прогон. Берём тот, который считает ПРОВЕРКА.
    если = запись.get("verified_complete")
    return "VERIFIED" if если is True else ("" if если is None else "НЕ ПОДТВЕРЖДЁН")


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--kind", choices=sorted(СЛЕДЫ), default="tech")
    р.add_argument("--runs", type=Path, default=None,
                   help="путь к следу прогонов (по умолчанию по виду)")
    опции = р.parse_args(аргв)

    путь = опции.runs or СЛЕДЫ[опции.kind]
    все = строки(путь)
    if len(все) < 2:
        print(f"не измерено: в {путь} прогонов {len(все)} — двух циклов ещё не "
              "было", file=sys.stderr)
        return 2

    # Берутся ДВА ПОСЛЕДНИХ прогона: «подряд» — это они, а не любая пара.
    предыдущий, последний = все[-2], все[-1]
    расхождений = 0

    def шаг(имя: str, ок: bool, подробно: str = "") -> None:
        nonlocal расхождений
        расхождений += not ок
        print(f"   [{'ок ' if ок else 'НЕТ'}] {имя:52} {подробно}")

    т1, т2 = предыдущий.get("trigger"), последний.get("trigger")
    шаг("оба цикла запущены таймером, а не рукой",
        т1 == ПО_РАСПИСАНИЮ and т2 == ПО_РАСПИСАНИЮ,
        f"{т1!r} и {т2!r}")

    # Ручной прогон МЕЖДУ ними сделал бы «подряд» неверным. Между двумя
    # последними записями других записей нет по построению, поэтому
    # проверяется, что ни один из них сам не ручной, и что ручных не было
    # после предыдущего — то есть последний идёт сразу за ним.
    шаг("между циклами не было ручного прогона",
        т1 == ПО_РАСПИСАНИЮ and т2 == ПО_РАСПИСАНИЮ,
        "следующая запись идёт сразу за предыдущей")

    з1, з2 = задача(опции.kind, предыдущий), задача(опции.kind, последний)
    пересечение = з1 & з2
    шаг("задачи разные", bool(з1) and bool(з2) and not пересечение,
        f"у первого {len(з1)}, у второго {len(з2)}, "
        f"пересечение {len(пересечение)}")

    в1, в2 = вердикт(опции.kind, предыдущий), вердикт(опции.kind, последний)
    шаг("у каждого цикла есть вердикт проверяющего шага",
        в1 == "VERIFIED" and в2 == "VERIFIED", f"{в1!r} и {в2!r}")

    шаг("у каждого цикла есть отметки времени",
        all(з.get("started_at") and з.get("finished_at")
            for з in (предыдущий, последний)),
        f"{предыдущий.get('started_at')} → {предыдущий.get('finished_at')}; "
        f"{последний.get('started_at')} → {последний.get('finished_at')}")

    print(f"\nвид: {опции.kind}; прогонов в следе {len(все)}; "
          f"расхождений {расхождений}")
    if not расхождений:
        print("два цикла подряд подтверждены: разные задачи, запуск по "
              "расписанию, вердикт у обоих")
    return 1 if расхождений else 0


if __name__ == "__main__":
    raise SystemExit(главное())
