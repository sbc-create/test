#!/usr/bin/env python3
"""Перенос одной правки: canonical раздела строится по ЗАПРОШЕННОМУ.

    python3 automation/local/wire-canonical-requested.py --repo var/site-repos/<проект> \\
        [--sections "/movies/,/series/,…"] [--dry-run]

Зачем инструмент, а не правка руками в каждой ячейке. Дефект один и тот же в
трёх ячейках zona, а формы файлов у них разные: у двух рантайм лежит в
`src/lords-frontend.py`, у третьей закреплён в `template/<выпуск>/` и правится
через собственный переходник. Правка руками в трёх местах расходится на
четвёртом переносе — так уже случилось с `tools/update_pins.py` двух ячеек
AnimeGo, где блок записи модуля был только у одной из трёх.

Что делает инструмент:

1. `отбор` помечает значения, выставленные МАРШРУТОМ, а не читателем
   (`_подразумеваемое`). Пометка служебная: `запрос_строкой` пропускает поля с
   ведущим подчёркиванием, поэтому в ссылках её не видно;
2. построитель canonical отбрасывает подразумеваемое и пропускает адрес через
   общий слой (`seo_layer.канонический_путь`), где уже записано правило
   «порядок списка отдельной страницы не образует»;
3. по требованию расширяет `РАЗДЕЛЫ_КАРТЫ` — но ТОЛЬКО на переданные разделы.
   Сам инструмент разделов не придумывает: набор у семейств разный, и адрес по
   аналогии добавлять нельзя;
4. доставляет `checks/canonical_requested.py` и вносит его в `checks/run.sh`.

Подмена ищет точную строку. Если её нет — инструмент ОТКАЗЫВАЕТСЯ и говорит,
чего не нашёл: молчаливая замена «нуля вхождений» уже однажды выдала правку,
которой не было.
"""
from __future__ import annotations

import argparse
import pathlib
import shutil
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПРОВЕРКА = КОРЕНЬ / "automation" / "host" / "canonical_requested_check.py"

ЯКОРЬ_MODE = """    неизвестный_фильтр = False
    new_mode = None
"""
ВСТАВКА_MODE = """    неизвестный_фильтр = False
    new_mode = None
    #: Запрошенный режим ленты. Держится отдельно от действующего, потому что
    #: действующий выставляет маршрут, и различать их нужно за пределами отбора.
    сырой_mode = None
"""

ЯКОРЬ_ВЫБРАНО = """    if неизвестный_фильтр:
        выбрано["_unknown"] = "1"
    return набор, выбрано
"""
ВСТАВКА_ВЫБРАНО = """    if неизвестный_фильтр:
        выбрано["_unknown"] = "1"
    # Какие значения выставил МАРШРУТ, а не читатель. Различие нужно за
    # пределами отбора: канонический адрес страницы складывается из
    # ЗАПРОШЕННОГО, а подразумеваемое значение отдельного адреса не образует.
    # Без этой пометки голый `/catalog/` объявлял каноническим
    # `/catalog/?sort=newest` — адрес, которого нет ни в навигации, ни в карте
    # сайта, то есть страница объявляла дублем саму себя.
    подразумеваемые = [к for к, сырое in (("sort", сырой_сорт),
                                          ("mode", сырой_mode))
                       if выбрано.get(к) and not сырое]
    if подразумеваемые:
        выбрано["_подразумеваемое"] = ",".join(подразумеваемые)
    return набор, выбрано
"""

ЯКОРЬ_КАНОН = """        канон_q = запрос_строкой({**выбрано, **omit}, page=None)
        канон = разд + "/" + канон_q
"""
ВСТАВКА_КАНОН = """        # Канонический адрес описывает ЗАПРОШЕННУЮ страницу, а не действующую
        # выборку. Подразумеваемое маршрутом (`_подразумеваемое` из `отбор`)
        # отбрасывается, а правило «порядок списка отдельной страницы не
        # образует» применяется общим слоем (`seo_layer.канонический_путь`), а
        # не повторяется здесь: второе правило разошлось бы с первым.
        подразум = {к for к in (выбрано.get("_подразумеваемое") or "").split(",") if к}
        канон_поля = {к: з for к, з in выбрано.items() if к not in подразум}
        канон_q = запрос_строкой({**канон_поля, **omit}, page=None)
        канон = SEO.канонический_путь(разд + "/" + канон_q)
"""

СТРОКА_ПРОГОНА = """
# Канонический адрес описывает ЗАПРОШЕННУЮ страницу: порядок списка и вид,
# заданный маршрутом, адреса не образуют. Голый /catalog/ объявлял каноническим
# /catalog/?sort=newest — адреса, которого нет ни в навигации, ни в карте, —
# и шесть настоящих разделов из семи из-за этого в карту не попадали.
check "canonical-requested" python3 checks/canonical_requested.py
"""


class Отказ(RuntimeError):
    """Якоря нет: перенос не состоялся, и молчать об этом нельзя."""


def подменить(текст: str, якорь: str, вставка: str, что: str) -> str:
    if вставка in текст:
        return текст  # уже перенесено
    if текст.count(якорь) != 1:
        raise Отказ(f"{что}: якорь встречается {текст.count(якорь)} раз, ожидался один")
    return текст.replace(якорь, вставка)


def рантайм(репо: pathlib.Path) -> pathlib.Path:
    """Файл рантайма ячейки. Закреплённый артефакт не правится — это отказ."""
    свои = sorted(p for p in (репо / "src").glob("*frontend*.py")
                  if "__pycache__" not in str(p))
    if len(свои) == 1:
        return свои[0]
    if not свои:
        raise Отказ("в src/ нет рантайма витрины: ячейка исполняет закреплённый "
                    "артефакт, и правка идёт через её переходник, а не этим "
                    "инструментом")
    raise Отказ(f"в src/ несколько рантаймов: {[p.name for p in свои]}")


def главная(argv: list[str]) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--repo", required=True)
    р.add_argument("--sections", default="",
                   help="разделы карты через запятую; пусто — не менять перечень")
    р.add_argument("--dry-run", action="store_true")
    о = р.parse_args(argv[1:])

    репо = pathlib.Path(о.repo)
    if not репо.is_absolute():
        репо = КОРЕНЬ / репо
    if not (репо / ".git").is_dir():
        print(f"не репозиторий сайта: {репо}", file=sys.stderr)
        return 2

    try:
        файл = рантайм(репо)
    except Отказ as ош:
        print(f"ОТКАЗ {репо.name}: {ош}", file=sys.stderr)
        return 1

    текст = файл.read_text(encoding="utf-8")
    было = текст
    try:
        текст = подменить(текст, ЯКОРЬ_MODE, ВСТАВКА_MODE, "запрошенный режим")
        текст = подменить(текст, ЯКОРЬ_ВЫБРАНО, ВСТАВКА_ВЫБРАНО, "пометка подразумеваемого")
        текст = подменить(текст, ЯКОРЬ_КАНОН, ВСТАВКА_КАНОН, "построитель canonical")
    except Отказ as ош:
        print(f"ОТКАЗ {репо.name}: {ош}", file=sys.stderr)
        return 1

    разделы = [р_.strip() for р_ in о.sections.split(",") if р_.strip()]
    if разделы:
        старое = 'РАЗДЕЛЫ_КАРТЫ = ("/collections/",)'
        новое = ("РАЗДЕЛЫ_КАРТЫ = (" + ", ".join(f'"{р_}"' for р_ in разделы) + ",)")
        if новое not in текст:
            if текст.count(старое) != 1:
                print(f"ОТКАЗ {репо.name}: перечень разделов не в ожидаемом виде",
                      file=sys.stderr)
                return 1
            текст = текст.replace(старое, новое)

    изменилось = текст != было
    print(f"{репо.name}: рантайм {файл.relative_to(репо)} — "
          f"{'правка внесена' if изменилось else 'уже перенесено'}")
    if разделы:
        print(f"   разделы карты: {', '.join(разделы)}")

    прогон = репо / "checks" / "run.sh"
    текст_прогона = прогон.read_text(encoding="utf-8")
    нужен_прогон = "canonical_requested.py" not in текст_прогона
    if нужен_прогон:
        if текст_прогона.count('exit "$fail"') != 1:
            print(f"ОТКАЗ {репо.name}: в checks/run.sh нет единственного "
                  'exit "$fail"', file=sys.stderr)
            return 1
        текст_прогона = текст_прогона.replace(
            '\nexit "$fail"', СТРОКА_ПРОГОНА + '\nexit "$fail"')

    if о.dry_run:
        print("   сухой прогон: ничего не записано")
        return 0

    if изменилось:
        файл.write_text(текст, encoding="utf-8")
    shutil.copy2(ПРОВЕРКА, репо / "checks" / "canonical_requested.py")
    print("   доставлено: checks/canonical_requested.py")
    if нужен_прогон:
        прогон.write_text(текст_прогона, encoding="utf-8")
        print("   внесено в checks/run.sh")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv))
