"""Сколько стоит сборка карты на 565 тысяч адресов (следующий замер MOD-79).

Замер местный и ни одной витрины не касается: берётся сама функция
`построить_sitemap` из семейного рантайма и ей даются синтетические адреса.
Производство тут не при чём — мерится цена самой сборки, та же, что заплатит
поток «sitemap» при смене поколения снимка.

Сравниваются три объёма: сегодняшний (66 тысяч адресов произведений), с серией
(66 тысяч плюс 565 008 доступных серий) и промежуточный.
"""
import importlib.util
import pathlib
import sys
import time
import tracemalloc

КОРЕНЬ = pathlib.Path("/home/claude/wt-nova-publish-memory-02")
спец = importlib.util.spec_from_file_location(
    "seo_layer", КОРЕНЬ / "automation" / "host" / "seo_layer.py")
seo = importlib.util.module_from_spec(спец)
sys.modules["seo_layer"] = seo
спец.loader.exec_module(seo)


def страницы(произведений: int, серий: int):
    for н in range(произведений):
        yield {"url": f"/title/title-{н}/", "lastmod": "2026-10-18"}
    на_произведение = max(1, серий // max(1, произведений))
    выдано = 0
    for н in range(произведений):
        for э in range(1, на_произведение + 1):
            if выдано >= серий:
                return
            выдано += 1
            yield {"url": f"/title/title-{н}/season-1/episode-{э}/",
                   "lastmod": "2026-10-18"}


# Делитель объёма: замер целиком занимает около 25 секунд, и проверке этого не
# нужно — ей нужно, чтобы инструмент запускался и печатал три строки. Форма
# вывода от делителя не зависит, а числа в записи MOD-79 сняты при делителе 1.
ДЕЛИТЕЛЬ = max(1, int(sys.argv[1])) if len(sys.argv) > 1 else 1
if ДЕЛИТЕЛЬ > 1:
    print(f"объёмы уменьшены в {ДЕЛИТЕЛЬ} раз: это проверка запуска, "
          f"а не замер")

for подпись, произв, серий in (
        ("сегодня: только произведения", 66_159 // ДЕЛИТЕЛЬ, 0),
        ("плюс четверть серий", 66_159 // ДЕЛИТЕЛЬ, 141_252 // ДЕЛИТЕЛЬ),
        ("все доступные серии", 66_159 // ДЕЛИТЕЛЬ, 565_008 // ДЕЛИТЕЛЬ)):
    tracemalloc.start()
    начало = time.monotonic()
    файлы = seo.построить_sitemap("example.test",
                                  страницы(произв, серий), ("/catalog/",))
    секунды = time.monotonic() - начало
    _, пик = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    объём = sum(len(т) for _, т in файлы)
    print(f"{подпись:32} адресов {произв + серий:>8}  файлов {len(файлы):>3}  "
          f"{секунды:5.1f} с  пик памяти {пик / 2**20:6.0f} МиБ  "
          f"на диске {объём / 2**20:6.1f} МиБ")
