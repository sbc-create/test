#!/usr/bin/env python3
"""Таблица по восьми витринам — из файлов измерений, без переписывания руками.

Отчёт, в котором числа набраны вручную, расходится с измерением на второй
правке. Поэтому таблицы собираются из того, что записали инструменты:

  * `var/k2-data/audit/<site>/audit.json`       — осмотр браузером действием;
  * `var/k2-data/audit/<site>/serial.json`      — сериальная поверхность;
  * `var/k2-data/audit/<site>/shelf-order.json` — порядок полок главной;
  * `var/k2-data/audit/<site>/seo.json`         — SEO и режим индексации.

Чего в файле измерений нет, в таблице стоит «не измерено» — не «да».
"""
from __future__ import annotations

import argparse
import contextlib
import io
import json
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ОСМОТРЫ = КОРЕНЬ / "var" / "k2-data" / "audit"
ВОСЕМЬ = [f"lords-{n}" for n in range(10, 18)]


def прочитать(site: str, имя: str) -> dict:
    ф = ОСМОТРЫ / site / имя
    if not ф.is_file():
        return {}
    try:
        return json.loads(ф.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def галка(значение) -> str:
    if значение is True:
        return "да"
    if значение is False:
        return "**нет**"
    return "не измерено"


def таблицы() -> str:
    """Те же таблицы, но строкой — для вставки в документ."""
    буфер = io.StringIO()
    with contextlib.redirect_stdout(буфер):
        main(только_таблицы=True)
    return буфер.getvalue()


def main(только_таблицы: bool = False) -> int:
    строки = []
    for site in ВОСЕМЬ:
        о = прочитать(site, "audit.json")
        с = (прочитать(site, "serial.json") or {}).get("сериал") or {}
        п = прочитать(site, "shelf-order.json")
        сео = прочитать(site, "seo.json")
        гл = о.get("главная") or {}
        кат = о.get("каталог") or {}
        тел = о.get("телефон") or {}
        нав = о.get("навигация") or {}
        карт = (о.get("карточка") or {}).get("фильм") or {}
        лого = гл.get("логотип") or {}
        тлого = тел.get("логотип") or {}
        меню = гл.get("меню") or {}
        переход = с.get("переход по серии") or {}
        пер = о.get("переходы") or {}
        по_карточке = пер.get("карточка") or {}
        возврат = пер.get("возврат в раздел") or {}
        страницы = сео.get("страницы") or {}
        закрыты = [имя for имя, стр in страницы.items()
                   if "noindex" in str(стр.get("x_robots") or "")]
        к = прочитать(site, "contrast.json")
        пары = [з for замеры in (к.get("темы") or {}).values()
                for з in замеры.values()]
        пар_контраста = len(пары)
        провалов_контраста = sum(1 for з in пары
                                 if з.get("найдено") and not з.get("проходит"))
        строки.append({
            "site": site,
            "домен": о.get("domain"),
            "профиль": о.get("profile"),
            "коммит": о.get("коммит"),
            "грязных файлов": о.get("незакоммиченных файлов"),
            "имя в шапке целиком": not лого.get("clipped") if лого else None,
            "имя на телефоне целиком": not тлого.get("clipped") if тлого else None,
            "меню без потерь": not меню.get("lost") if меню else None,
            "подвал mailto": гл.get("подвал mailto"),
            "битых изображений": гл.get("битых изображений"),
            "техмаркеры": гл.get("техмаркеры"),
            "карточек в каталоге": кат.get("карточек"),
            "жанр меняет выдачу": кат.get("жанр меняет выдачу"),
            "год меняет выдачу": кат.get("год меняет выдачу"),
            "сортировка меняет порядок": кат.get("сортировка меняет порядок"),
            "вторая страница": кат.get("ссылка следующей"),
            "вторая страница отличается": кат.get("вторая страница отличается"),
            "карточек на второй": кат.get("карточек на второй"),
            "битых ссылок": len(нав.get("битых") or []) if нав else None,
            "карточка открывается": по_карточке.get("адрес совпал"),
            "заголовок соответствует карточке": по_карточке.get("заголовок соответствует"),
            "возврат в раздел": возврат.get("адрес совпал"),
            "карточек в разделе после возврата": возврат.get("карточек в разделе"),
            "404": нав.get("404 отдаёт 404"),
            "поиск нашёл": (нав.get("поиск действием") or {}).get("найдено карточек"),
            "название в карточке": карт.get("название в тексте"),
            "сюжет из источника": карт.get("сюжет из источника"),
            "похожее": карт.get("похожее"),
            "состояние плеера": карт.get("состояние плеера"),
            "сезонов": с.get("сезонов на странице"),
            "серий": с.get("серий доступно на странице"),
            "сезоны сходятся": с.get("сезонов сходится"),
            "серии сходятся": с.get("серий сходится"),
            "серия открывается": переход.get("адрес совпал с ссылкой"),
            "серия помечена текущей": переход.get("помечена текущей"),
            "полки": п.get("полки"),
            "своя полка первой": п.get("своя полка первой"),
            "горизонтальная прокрутка на телефоне":
                тел.get("горизонтальная прокрутка главной"),
            "меню на телефоне": тел.get("меню открывается"),
            "страниц проверено SEO": len(страницы),
            "страниц закрыто от индексации": len(закрыты),
            "title главной": (страницы.get("главная") or {}).get("title"),
            "описание каталога": (страницы.get("каталог") or {}).get("description"),
            "canonical главной": (страницы.get("главная") or {}).get("canonical"),
            "внутренних ссылок на главной":
                (страницы.get("главная") or {}).get("ссылок внутренних"),
            "пар контраста": пар_контраста,
            "контраст ниже порога": провалов_контраста,
        })

    (КОРЕНЬ / "var" / "k2-data" / "eight-report.json").write_text(
        json.dumps(строки, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print("| витрина | домен | коммит | имя в шапке к/т | меню | подвал | битых картинок |")
    print("| --- | --- | --- | --- | --- | --- | ---: |")
    for р in строки:
        print(f"| {р['site']} | {р['домен']} | `{р['коммит']}` | "
              f"{галка(р['имя в шапке целиком'])}/{галка(р['имя на телефоне целиком'])} | "
              f"{галка(р['меню без потерь'])} | {галка(р['подвал mailto'])} | "
              f"{р['битых изображений']} |")

    print()
    print("| витрина | карточек | жанр | год | сортировка | 2-я страница | битых ссылок | 404 | поиск | карточка открывается | возврат в раздел |")
    print("| --- | ---: | --- | --- | --- | --- | ---: | ---: | ---: | --- | --- |")
    for р in строки:
        вт = (f"{р['карточек на второй']} карт., отличается"
              if р["вторая страница отличается"] else галка(р["вторая страница отличается"]))
        print(f"| {р['site']} | {р['карточек в каталоге']} | "
              f"{галка(р['жанр меняет выдачу'])} | {галка(р['год меняет выдачу'])} | "
              f"{галка(р['сортировка меняет порядок'])} | {вт} | "
              f"{р['битых ссылок']} | {р['404']} | {р['поиск нашёл']} | "
              f"{галка(р['карточка открывается'] and р['заголовок соответствует карточке'])} | "
              f"{галка(р['возврат в раздел'])} |")

    print()
    print("| витрина | сезонов | серий | сходится с данными | серия открывается | помечена текущей | плеер |")
    print("| --- | ---: | ---: | --- | --- | --- | --- |")
    for р in строки:
        print(f"| {р['site']} | {р['сезонов']} | {р['серий']} | "
              f"{галка(bool(р['сезоны сходятся']) and bool(р['серии сходятся']))} | "
              f"{галка(р['серия открывается'])} | {галка(р['серия помечена текущей'])} | "
              f"`{р['состояние плеера']}` |")

    print()
    print("| витрина | полки главной | своя первой | прокрутка на телефоне | меню на телефоне |")
    print("| --- | --- | --- | --- | --- |")
    for р in строки:
        полки = " → ".join(р["полки"] or []) or "не измерено"
        print(f"| {р['site']} | {полки} | {галка(р['своя полка первой'])} | "
              f"{галка(not р['горизонтальная прокрутка на телефоне'])} | "
              f"{галка(р['меню на телефоне'])} |")

    print()
    print("| витрина | страниц SEO | закрыто от индексации | canonical главной | внутренних ссылок | пар контраста | ниже порога |")
    print("| --- | ---: | ---: | --- | ---: | ---: | ---: |")
    for р in строки:
        print(f"| {р['site']} | {р['страниц проверено SEO']} | "
              f"{р['страниц закрыто от индексации']} | "
              f"`{р['canonical главной']}` | {р['внутренних ссылок на главной']} | "
              f"{р['пар контраста']} | {р['контраст ниже порога']} |")

    if not только_таблицы:
        print()
        print("сводка: var/k2-data/eight-report.json")
    return 0


if __name__ == "__main__":
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--markdown", default=None,
                   help="записать таблицы в файл вместо вывода на экран")
    а = р.parse_args()
    if а.markdown:
        Path(а.markdown).write_text(таблицы(), encoding="utf-8")
        print(f"таблицы записаны: {а.markdown}")
        raise SystemExit(0)
    raise SystemExit(main())
