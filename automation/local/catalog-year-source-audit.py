def _нормализовать(название: str) -> str:
    """Для сравнения названий: без регистра, знаков, цифр и слов-служебок."""
    т = (название or "").lower().replace("ё", "е")
    т = re.sub(r"\b(season|сезон|the|tv|часть|part)\b", " ", т)
    т = re.sub(r"[^a-zа-я0-9]+", " ", т)
    return " ".join(т.split())


def _без_цифр(название: str) -> str:
    return " ".join(re.sub(r"\d+", " ", _нормализовать(название)).split())


def сопоставление(запись: dict, карточка: dict) -> tuple[str, str]:
    """(вердикт, пояснение). Вердикты: подтверждено | под вопросом | не измерено.

    Признак обязан уметь оба исхода, поэтому сравниваются ЧЕТЫРЕ названия
    (русское и оригинальное с двух сторон) и достаточно ОДНОГО вхождения без
    цифр: сезон и спецвыпуск законно переименовываются, а другое произведение
    не совпадёт ни одним из названий.
    """
    наши = [з for з in (запись.get("name"), запись.get("original_name")) if з]
    их = [з for з in (карточка.get("russian"), карточка.get("name")) if з]
    их += [з for з in (карточка.get("synonyms") or []) if з]
    if not наши or not их:
        return "не измерено", "одна из сторон без названия"
    for а in наши:
        for б in их:
            на, нб = _без_цифр(а), _без_цифр(б)
            if не_пусто_и_пересекается(на, нб):
                return "подтверждено", f"{а!r} ~ {б!r}"
    return "под вопросом", f"{наши[0]!r} против {их[0]!r}"


def не_пусто_и_пересекается(а: str, б: str) -> bool:
    if not а or not б:
        return False
    return а == б or а in б or б in а


def класс_источника(карточка: dict) -> tuple[str, str]:
    """(фильм | сериал | не измерено, пояснение) — ГРУБЫЙ класс, не вид.

    ПОЧЕМУ СУДИТСЯ ТОЛЬКО `tv` И `movie`, и это измерено, а не выбрано.
    Сначала здесь стояло правило пошире: `ona`/`ova`/`special` с одной серией
    считались фильмом, а с несколькими — сериалом. Прогон образца из 300
    записей 20.10 дал по этому правилу четыре расхождения вида, и ДВА из них
    оказались следствием самого правила, а не ошибкой записи:

    * `alkogol-dlya-supruzheskoy-pary-epizod-14` — снимок `tv`, источник `ona`
      с одной серией. Но это запись ОДНОГО эпизода веб-сериала, и «фильмом»
      его делает только моё правило;
    * `reyndzher-pokemon-put-sveta` — снимок `movie`, источник `tv_special` из
      двух частей. Двухчастный телеспецвыпуск ближе к фильму, чем к сериалу.

    Остались два расхождения, где источник говорит прямо `kind: movie`
    (`kulak-severnoy-zvezdy-rao`, `legenda-o-kristanii`), и они настоящие.
    Поэтому промежуточные виды объявляются НЕ ИЗМЕРЕННЫМИ: словарь снимка их
    не выражает, а догадка о классе даёт ложные находки в половине случаев.
    """
    вид = (карточка.get("kind") or "").strip()
    серий = карточка.get("episodes")
    серий = серий if isinstance(серий, int) else None
    if вид == "tv":
        return "сериал", "kind tv"
    if вид == "movie":
        return "фильм", "kind movie"
    if not вид:
        return "не измерено", "источник не дал kind"
    return "не измерено", (f"kind {вид}, серий {серий!r} — словарь снимка"
                           " (tv, movie) этого вида не выражает")


def класс_снимка(запись: dict) -> str:
    т = (запись.get("type") or "").strip()
    return {"tv": "сериал", "movie": "фильм"}.get(т, "")


def из_кэша(ид: str) -> dict | None:
    ф = КЭШ / f"{ид}.json"
    if not ф.exists():
        return None
    try:
        return json.loads(ф.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return None


def в_кэш(ид: str, карточка: dict) -> None:
    КЭШ.mkdir(parents=True, exist_ok=True)
    (КЭШ / f"{ид}.json").write_text(
        json.dumps({"fetched_at": dt.datetime.now(dt.timezone.utc)
                    .strftime("%Y-%m-%dT%H:%M:%SZ"), "card": карточка},
                   ensure_ascii=False),
        encoding="utf-8")


#: Минимальный интервал между обращениями к источнику, секунды.
#: ПОЧЕМУ 0.7, А НЕ 0.25. Прогон 300 записей 20.10 с паузой 0.25 с получил
#: `429` на 183 записях из 300: источник держит предел около 90 обращений в
#: минуту, а не 4 в секунду. Отказ 429 честно лёг в «не измерено» — ошибкой
#: вывода это не стало, — но измерить не дал. 0.7 с даёт ≈85 обращений в
#: минуту, то есть остаётся под пределом.
ИНТЕРВАЛ_С = 0.7
#: Сколько раз переспросить после 429, с удвоением ожидания.
ПОПЫТОК_ПОСЛЕ_429 = 3
ОЖИДАНИЕ_ПОСЛЕ_429_С = 20.0


def штатный_читатель(*, интервал: float = ИНТЕРВАЛ_С, сон=None,
                     карточка=None):
    """Чтение источника только разрешённым путём (D199), вежливым темпом.

    `429` не превращается в «нет данных»: проход переспрашивает с удвоением
    ожидания и лишь затем отдаёт отказ, который станет «не измерено».
    """
    спать = сон or time.sleep
    если_карточка = карточка
    if если_карточка is None:
        м = _загрузить_модуль("source_fetch",
                              КОРЕНЬ / "automation/local/source_fetch.py")
        если_карточка = lambda ид: м.shikimori_card(int(ид))  # noqa: E731
    последнее = [0.0]

    def читать(ид: str) -> dict:
        ожидание = ОЖИДАНИЕ_ПОСЛЕ_429_С
        for попытка in range(ПОПЫТОК_ПОСЛЕ_429 + 1):
            пауза = интервал - (time.monotonic() - последнее[0])
            if пауза > 0:
                спать(пауза)
            последнее[0] = time.monotonic()
            карта = если_карточка(ид)
            if (карта or {}).get("ok") or (карта or {}).get("status") != 429:
                return карта
            if попытка < ПОПЫТОК_ПОСЛЕ_429:
                спать(ожидание)
                ожидание *= 2
        return карта

    return читать


def разобрать_одну(слаг: str, запись: dict, карточка: dict | None) -> dict:
    итог = {
        "slug": слаг,
        "id": ид_записи(запись),
        "год_снимка": запись.get("year"),
        "вид_снимка": запись.get("type"),
        "класс_снимка": класс_снимка(запись),
        "название_снимка": запись.get("name"),
    }
    if not итог["id"]:
        итог.update(год="не измерено", причина_года="в записи нет id источника",
                    вид="не измерено", сопоставление="не измерено")
        return итог
    if not карточка or not карточка.get("ok"):
        статус = (карточка or {}).get("status")
        итог.update(год="не измерено",
                    причина_года=f"источник не ответил (status {статус!r})",
                    вид="не измерено", сопоставление="не измерено")
        return итог

    итог["название_источника"] = карточка.get("russian") or карточка.get("name")
    итог["вид_источника"] = карточка.get("kind")
    итог["aired_on"] = карточка.get("aired_on")
    вердикт_соп, поясн_соп = сопоставление(запись, карточка)
    итог["сопоставление"] = вердикт_соп
    итог["сопоставление_пояснение"] = поясн_соп

    год_снимка = итог["год_снимка"]
    вышло = (карточка.get("aired_on") or "")[:4]
    год_источника = int(вышло) if вышло.isdigit() else None
    итог["год_источника"] = год_источника
    if not isinstance(год_снимка, int):
        итог.update(год="не измерено", причина_года="в записи нет year")
    elif год_источника is None:
        итог.update(год="не измерено", причина_года="источник не дал aired_on")
    elif вердикт_соп == "под вопросом":
        # Год сравнивать нельзя, пока не ясно, то ли это произведение.
        итог.update(год="не измерено",
                    причина_года="сопоставление под вопросом: сверять год"
                                 " нечем, пока id не подтверждён названием")
    elif год_снимка == год_источника:
        итог["год"] = "совпадает"
    else:
        итог["год"] = "расходится"
        итог["разница_лет"] = год_источника - год_снимка

    класс_и, поясн_и = класс_источника(карточка)
    итог["класс_источника"] = класс_и
    итог["класс_источника_пояснение"] = поясн_и
    if класс_и == "не измерено" or not итог["класс_снимка"]:
        итог["вид"] = "не измерено"
    elif вердикт_соп == "под вопросом":
        итог["вид"] = "не измерено"
    elif класс_и == итог["класс_снимка"]:
        итог["вид"] = "совпадает"
    else:
        итог["вид"] = "расходится"
    return итог


def выбрать(подробности: dict[str, dict], *, слаги: list[str] | None,
            образец: int, семя: int, кандидаты: bool) -> list[str]:
    if слаги:
        нет = [с for с in слаги if с not in подробности]
        if нет:
            raise SystemExit(f"нет таких слагов в снимке: {', '.join(нет)}")
        return слаги
    if кандидаты:
        м = _загрузить_модуль(
            "fyo", КОРЕНЬ / "automation/local/franchise-year-order.py")
        итог = м.разобрать(подробности)
        return [к["выпадает"] for к in итог["строгие"]]
    if образец:
        сверяемые = sorted(с for с, з in подробности.items() if ид_записи(з))
        случ = random.Random(семя)
        return случ.sample(сверяемые, min(образец, len(сверяемые)))
    raise SystemExit("нужно одно из: --slugs, --sample, --candidates")


def свести(строки: list[dict]) -> dict:
    def счёт(поле: str, значение: str) -> int:
        return sum(1 for с in строки if с.get(поле) == значение)
    причины: dict[str, int] = {}
    for с in строки:
        if с.get("год") == "не измерено":
            причины[с.get("причина_года", "—")] = \
                причины.get(с.get("причина_года", "—"), 0) + 1
    return {
        "проверено записей": len(строки),
        "год совпадает": счёт("год", "совпадает"),
        "год расходится": счёт("год", "расходится"),
        "год не измерен": счёт("год", "не измерено"),
        "причины «не измерено» по году": причины,
        "вид совпадает": счёт("вид", "совпадает"),
        "вид расходится": счёт("вид", "расходится"),
        "вид не измерен": счёт("вид", "не измерено"),
        "сопоставление подтверждено": счёт("сопоставление", "подтверждено"),
        "сопоставление под вопросом": счёт("сопоставление", "под вопросом"),
    }


def прогнать(подробности: dict[str, dict], слаги: list[str], *,
             читатель=None, кэш: bool = True) -> list[dict]:
    читать = читатель or штатный_читатель()
    строки = []
    for слаг in слаги:
        запись = подробности[слаг]
        ид = ид_записи(запись)
        карточка = None
        if ид:
            сохранённое = из_кэша(ид) if кэш else None
            if сохранённое:
                карточка = сохранённое.get("card")
            else:
                карточка = читать(ид)
                # В кэш ложится ТОЛЬКО удачный ответ. Запомненный отказ
                # (429, 404, обрыв) сделал бы «не измерено» вечным: следующий
                # прогон взял бы отказ из кэша и к источнику не пошёл.
                if кэш and (карточка or {}).get("ok"):
                    в_кэш(ид, карточка)
        строки.append(разобрать_одну(слаг, запись, карточка))
    return строки


