def поправки(строки: list[dict], подробности: dict[str, dict]) -> list[dict]:
    """Записи для `config/anime-year-corrections.json` — только измеренные.

    В поправку попадает лишь то, что СВЕРЕНО: сопоставление подтверждено и
    расхождение названо числом. Ключ — постоянный `id` поставщика, не слаг:
    слаг может переехать на другое произведение, и тогда поправка приписала бы
    год чужой записи.
    """
    итог = []
    for с in строки:
        год_расходится = с.get("год") == "расходится"
        вид_расходится = с.get("вид") == "расходится"
        if not (год_расходится or вид_расходится):
            continue
        if с.get("сопоставление") != "подтверждено":
            continue
        запись = подробности.get(с["slug"]) or {}
        ид = str(запись.get("id") or "")
        if not ид:
            continue
        правка = {
            "id": ид,
            "slug_at_measure": с["slug"],
            "source_id": с.get("id"),
            "source_url": f"https://shikimori.io/animes/{с.get('id')}",
            "measured_at": dt.datetime.now(dt.timezone.utc)
            .strftime("%Y-%m-%dT%H:%M:%SZ"),
            "matching": "external_id_from_record+title_verified",
            "aired_on": с.get("aired_on"),
        }
        if год_расходится:
            правка["year_provider"] = с.get("год_снимка")
            правка["year_source"] = с.get("год_источника")
        if вид_расходится:
            правка["type_provider"] = с.get("вид_снимка")
            правка["type_source"] = ("movie"
                                     if с.get("класс_источника") == "фильм"
                                     else "tv")
        итог.append(правка)
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("снимок")
    р.add_argument("--slugs", default="")
    р.add_argument("--sample", type=int, default=0)
    р.add_argument("--seed", type=int, default=20261020)
    р.add_argument("--candidates", action="store_true")
    р.add_argument("--json", action="store_true")
    р.add_argument("--no-cache", action="store_true")
    р.add_argument("--write-corrections", default="",
                   help="куда положить записи поправок по измеренным"
                        " расхождениям (объединяется с уже лежащими там)")
    а = р.parse_args(аргв)

    подробности = записи(Path(а.снимок))
    слаги = выбрать(подробности,
                    слаги=[с for с in а.slugs.split(",") if с],
                    образец=а.sample, семя=а.seed, кандидаты=а.candidates)
    if not слаги:
        print("НЕ ИЗМЕРЕНО: выбирать нечего")
        return 2
    строки = прогнать(подробности, слаги, кэш=not а.no_cache)
    сводка = свести(строки)
    if а.json:
        print(json.dumps({"сводка": сводка, "записи": строки},
                         ensure_ascii=False, indent=1))
    else:
        напечатать(строки, сводка)
    if а.write_corrections:
        ф = Path(а.write_corrections)
        было = (json.loads(ф.read_text(encoding="utf-8"))
                if ф.exists() else {"schema_version": 1, "corrections": []})
        по_ид = {з["id"]: з for з in было.get("corrections", [])}
        новые = поправки(строки, подробности)
        for з in новые:
            по_ид[з["id"]] = з
        было["corrections"] = [по_ид[и] for и in sorted(по_ид)]
        было["updated_at"] = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")
        ф.parent.mkdir(parents=True, exist_ok=True)
        ф.write_text(json.dumps(было, ensure_ascii=False, indent=2) + "\n",
                     encoding="utf-8")
        print(f"\nпоправок записано {len(новые)}, всего в файле"
              f" {len(было['corrections'])}: {ф}")

    if сводка["год расходится"] or сводка["вид расходится"]:
        return 1
    if сводка["год совпадает"] == 0:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(главное())
