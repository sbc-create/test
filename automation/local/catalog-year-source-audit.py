#!/usr/bin/env python3
"""Сверка года и вида записей каталога с источником — по СВОЕМУ id записи.

Зачем этот проход и чем он отличается от прежних. MOD-102 сверил шесть записей
с Shikimori, а MOD-109 оценил масштаб ВНУТРЕННИМ признаком (порядок года у
нумерованных частей), и оба раза в приёмке стояло: «сверить весь каталог с
источником нечем — в записях снимка нет `shikimori_id`». **Это было неверно, и
проверено чтением снимка 20.10:**

    записей в снимке animedia-01            8 674
    с `external_ids.mal` / `myanimelist`    8 080
    с `ratings_by_source.shikimori.…`       4 911
    есть id И есть year (сверяемых)         7 765
    id двух этих мест расходятся               0

То есть сверка с источником возможна у 7 765 записей из 8 674, и выдумывать
поиск для этого не нужно: id лежит в самой записи, как того и требует D199.

ЧЕМ ЭТОТ ПРОХОД РАЗЛИЧАЕТ ТРИ ВЕЩИ, которые легко спутать:

1. **год** — `year` снимка против года из `aired_on` ТОГО ЖЕ id. Сравнивается
   только когда известны оба; иначе «не измерено» с причиной, а не «совпадает»;
2. **вид** — у снимка словарь из ДВУХ значений (`tv` 6 037, `movie` 2 637), и
   различить в нём ONA, OVA и спецвыпуск нечем. Поэтому сверяется ГРУБЫЙ класс
   «фильм / сериал», а расхождение `tv` против `ona` находкой НЕ считается:
   это предел словаря снимка, а не ошибка записи;
3. **сопоставление** — совпадает ли название источника с названием записи. Без
   этой проверки сверка года молча доверяет id: если id указывает на другое
   произведение, расхождение года будет настоящим, а вывод — ложным.

ПОЧЕМУ ПРОВЕРКА СОПОСТАВЛЕНИЯ ЗДЕСЬ ОБЯЗАТЕЛЬНА. На `iz-odnoy-komnaty-2` я
сверял год по id 36431, взятому из ЧЕРНОВИКА, и записал расхождение «2 года».
В самой записи стоит `mal: 41364` («One Room: Third Season»), источник даёт ему
`aired_on 2020-10-06`, и год снимка 2020 ВЕРЕН. Цифра 2 в слаге — не сезон, а
номер дубликата названия: в каталоге рядом лежат `iz-odnoy-komnaty` (2017),
`iz-odnoy-komnaty-2` (третий сезон!) и `iz-odnoy-komnaty-2-2`.

    python3 automation/local/catalog-year-source-audit.py <снимок> --slugs a,b
    python3 automation/local/catalog-year-source-audit.py <снимок> --sample 200 --seed 20261020
    python3 automation/local/catalog-year-source-audit.py <снимок> --candidates
"""
