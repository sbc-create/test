#!/usr/bin/env python3
"""Сверка очереди с ФАКТИЧЕСКИМ состоянием опубликованных сайтов.

Зачем. Задача в очереди живёт своей жизнью: её могли закрыть выпуском другой
линии, и тогда повторная работа по ней — не просто трата, а риск второй правки
поверх чужой. Обратное так же дорого: задача со статусом «сделано» может быть
жива на странице.

Поэтому проверяется НЕ статус в файле, а признак на живой странице, по одному
адресу на задачу. Запросов немного и они короткие: после исчерпания памяти на
узле тяжёлые обходы запрещены.

Каждая строка отвечает одно из трёх:

  ЗАКРЫТО   признак дефекта на странице не найден — задачу можно закрывать
  ЖИВО      признак найден — задача настоящая
  НЕ ИЗМЕРЕНО  адрес не ответил или признак не выражается запросом

Третье не считается ни тем, ни другим: «не измерено» — это отдельный исход.

    python3 automation/local/queue-vs-live.py
    python3 automation/local/queue-vs-live.py --only B016,T081
"""
