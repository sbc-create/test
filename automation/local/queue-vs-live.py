def достать(url: str) -> tuple[int, str]:
    г = subprocess.run(
        ["curl", "-sSL", "-w", "\n%{http_code}", "--max-time", "45", url],
        capture_output=True, text=True, timeout=75)
    части = (г.stdout or "").rsplit("\n", 1)
    тело = части[0] if len(части) > 1 else ""
    код = int(части[-1]) if части and части[-1].strip().isdigit() else 0
    return код, тело


def измерить(ид: str, url: str) -> tuple[str, str]:
    код, тело = достать(url)
    if код != 200 or len(тело) < 200:
        return "НЕ ИЗМЕРЕНО", f"код {код}, {len(тело)} байт"

    if ид == "T286":
        # Два признака вместе, потому что решение одно: убрать подборку из
        # раздела И поправить число в описании. Один без другого — половина
        # правки, и раздел обещал бы то, чего нет.
        ссылки = re.findall(r'href="/collection/([^"/]+)/"', тело)
        м = re.search(r"(\d+)\s+подборок", тело)
        объявлено = int(м.group(1)) if м else None
        if объявлено is None:
            return "НЕ ИЗМЕРЕНО", "в описании раздела нет числа подборок"
        если_нет = []
        if "video_available" in ссылки:
            если_нет.append("video_available в разделе")
        if объявлено != len(set(ссылки)):
            если_нет.append(f"описание объявляет {объявлено},"
                            f" ссылок {len(set(ссылки))}")
        return ("ЖИВО" if если_нет else "ЗАКРЫТО"), (
            "; ".join(если_нет) if если_нет
            else f"video_available убрана, объявлено {объявлено}"
                 f" = ссылок {len(set(ссылки))}")
    if ид == "T287":
        # Признак — пересечение первой страницы общей подборки с фильмовой, по
        # адресам произведений, а не по числу карточек: одинаковое число
        # ничего не значит. Порог 30 % — из приёмки передачи SEO.
        общая = set(re.findall(r'href="(/title/[^"#?]+)"', тело))
        код2, тело2 = достать(
            "https://zonafilm.space/collection/recently_added_movies/")
        if код2 != 200 or not тело2:
            return "НЕ ИЗМЕРЕНО", f"фильмовая подборка ответила {код2}"
        фильмы = set(re.findall(r'href="(/title/[^"#?]+)"', тело2))
        меньший = min(len(общая), len(фильмы))
        if not меньший:
            return "НЕ ИЗМЕРЕНО", "одна из подборок пуста"
        общих = len(общая & фильмы)
        доля = общих / меньший
        return ("ЖИВО" if доля > 0.30 else "ЗАКРЫТО"), \
            f"общих {общих} из {меньший} — {доля * 100:.1f} %"
    if ид == "T283":
        # Признак правки — число голосов в подписи оценки карточки. На
        # странице произведения такая подпись уже есть, поэтому мерить надо
        # именно главную и именно атрибут title карточки.
        подписи = re.findall(r'title="(?:IMDb|КП|Кинопоиск)[^"]*"', тело)
        с_голосами = [п for п in подписи if "голос" in п]
        if not подписи:
            return "НЕ ИЗМЕРЕНО", "подписей оценок на главной не найдено"
        return ("ЖИВО" if not с_голосами else "ЗАКРЫТО"), \
            f"подписей с голосами {len(с_голосами)} из {len(подписи)}"
    if ид == "T284":
        # Признак правки — состав ведущей полки по дате ВЫХОДА, а не
        # поступления. Выражается возрастом карточек: до правки в полке есть
        # работы старше десяти лет, после — не должно быть.
        куски = re.split(r"<h[12][^>]*>", тело)
        ведущая = next((к for к in куски if "Сейчас на Zona" in к[:80]), "")
        # Год лежит в подписи карточки вида `<span class="zt__m">2025 ·
        # Аргентина</span>`, а не отдельным span с одним числом: прежний
        # шаблон не находил ни одного года и давал «НЕ ИЗМЕРЕНО» на витрине,
        # где годы есть.
        годы = [int(г) for г in re.findall(
            r'<span[^>]*class="[^"]*zt__m[^"]*"[^>]*>\s*(\d{4})', ведущая)]
        if not годы:
            return "НЕ ИЗМЕРЕНО", "годов в ведущей полке не найдено"
        старые = [г for г in годы if г < 2016]
        return ("ЖИВО" if старые else "ЗАКРЫТО"), \
            f"карточек старше 10 лет {len(старые)} из {len(годы)}"
    if ид == "B016":
        сколько = тело.count("<loc>")
        return ("ЖИВО" if сколько <= 8000 else "ЗАКРЫТО"), f"адресов {сколько}"
    if ид == "T081":
        составные = re.findall(r'href="(/anime/[^"]*--[0-9a-f]{8}[^"]*)"', тело)
        всего = len(re.findall(r'href="/anime/[^"]+"', тело))
        return ("ЖИВО" if составные else "ЗАКРЫТО"), \
            f"составных {len(составные)} из {всего}"
    if ид == "B017":
        # Признак: раздел жанров есть, а ссылок на жанровые страницы нет.
        ссылки = re.findall(r'href="[^"]*/(?:genre|genres|zhanr)[^"]*"', тело)
        есть_слово = "анр" in тело
        if not есть_слово:
            return "НЕ ИЗМЕРЕНО", "слова «жанр» на странице нет"
        return ("ЖИВО" if not ссылки else "ЗАКРЫТО"), \
            f"ссылок на жанры {len(ссылки)}"
    if ид == "B031":
        # Признак — НЕ многоточие: обрезка идёт по границе слова и молча.
        # Первая редакция искала «…», не нашла и объявила дефект закрытым, а
        # на двух самых длинных названиях сети он жив. Сравнивается название
        # в <title> с названием в <h1>: обрезка видна тем, что первое —
        # начало второго и короче.
        м = re.search(r"<title>(.*?)</title>", тело, re.S)
        h1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело, re.S)
        if not м or not h1:
            return "НЕ ИЗМЕРЕНО", "нет <title> или <h1>"
        заголовок = re.sub(r"\s+", " ", м.group(1)).strip()
        полное = re.sub(r"<[^>]+>", " ", h1.group(1))
        полное = re.sub(r"\s+", " ", полное).strip()
        имя = заголовок.split("|")[0].split("—")[0].strip()
        if not полное or not имя:
            return "НЕ ИЗМЕРЕНО", "название не разобралось"
        обрезано = (len(имя) < len(полное) and полное.startswith(имя[:12])
                    and имя != полное)
        return ("ЖИВО" if обрезано else "ЗАКРЫТО"), \
            (f"title «{имя[:46]}» против h1 «{полное[:46]}»"
             if обрезано else f"{len(имя)} знаков, совпадает с h1")
    if ид == "T132":
        ссылки = sorted(set(re.findall(
            r'href="(/[^"]*?/season-(\d+)/episode-\d+/?)"', тело)))
        первый_сезон = [с for с, н in ссылки if н == "1"]
        return ("ЖИВО" if len(первый_сезон) == len(ссылки) and ссылки
                else "ЗАКРЫТО"), \
            f"ссылок {len(ссылки)}, из них season-1 {len(первый_сезон)}"
    # Остальные — редакционные: ищем формулировки внутренней кухни.
    плоско = (тело.replace("&quot;", '"').replace("&nbsp;", " ")
              .replace("&amp;", "&"))
    найдено = sorted({к for к in КУХНЯ if к in плоско.lower()})
    return ("ЖИВО" if найдено else "ЗАКРЫТО"), \
        (", ".join(найдено)[:90] if найдено else "формулировок не найдено")


#: Задача → адрес КОНТРОЛЯ: витрина, где правка намеренно не выпущена. Здесь
#: ожидается «ЖИВО», и это не регрессия, а доказательство, что мера различает
#: состояния. Пустая запись означает, что контроля у задачи нет.
КОНТРОЛЬ: dict[str, str] = {
    "B017": "https://yummyani.site/anime/vosstavshiy-protiv-neba-2",
    "B031": ("https://yummyani.site/anime/menya-vygnali-iz-gildii-geroev-"
             "potomu-chto-ya-byl-plohim-kompanonom-poetomu-ya-2024"),
}


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--only", default="",
                   help="список идентификаторов через запятую")
    опции = р.parse_args(аргв)
    выбор = [и.strip() for и in опции.only.split(",") if и.strip()] or list(ЗАДАЧИ)
    # Неизвестный идентификатор — отказ с перечнем, а не KeyError в потоке.
    # Измерено 20.10: `--only T283,T284` падало трассировкой, и из неё нельзя
    # было понять, что задач просто нет в таблице признаков.
    нет_признака = [и for и in выбор if и not in ЗАДАЧИ]
    if нет_признака:
        print("НЕ ИЗМЕРЕНО: признака на живой странице нет для задач: "
              + ", ".join(нет_признака))
        print("   известны: " + ", ".join(sorted(ЗАДАЧИ)))
        print("   добавить признак — в таблицу ЗАДАЧИ этого файла;"
              " без признака проверять нечего, и статус из файла"
              " доказательством не считается.")
        выбор = [и for и in выбор if и in ЗАДАЧИ]
        if not выбор:
            return 2

    with ThreadPoolExecutor(4) as ex:
        итоги = list(ex.map(lambda и: (и, *измерить(и, ЗАДАЧИ[и][0])), выбор))

    закрыто = живо = неизмерено = 0
    контрольных_ок = контрольных_нет = 0
    for ид, исход, подробно in итоги:
        адрес, что = ЗАДАЧИ[ид]
        print(f"{ид:6s} {исход:12s} {что[:44]:44s} {подробно}")
        закрыто += исход == "ЗАКРЫТО"
        живо += исход == "ЖИВО"
        неизмерено += исход == "НЕ ИЗМЕРЕНО"
        if ид in КОНТРОЛЬ:
            к_исход, к_подробно = измерить(ид, КОНТРОЛЬ[ид])
            ожидаемо = к_исход == "ЖИВО"
            контрольных_ок += ожидаемо
            контрольных_нет += not ожидаемо
            print(f"{'':6s} контроль {к_исход:4s} "
                  f"{'(ожидаемо: правка там не выпущена)' if ожидаемо else '(НЕОЖИДАННО: мера не различает состояния)'}"
                  f"  {к_подробно[:60]}")
    print(f"\nзакрыто фактически: {закрыто}; живо: {живо}; "
          f"не измерено: {неизмерено}")
    if КОНТРОЛЬ:
        print(f"отрицательных контролей: ожидаемо живы {контрольных_ок}, "
              f"неожиданно закрыты {контрольных_нет}")
    print("«не измерено» не считается ни закрытым, ни живым")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
