#:
#: Адрес — ВЫПУЩЕННАЯ витрина. Это не формальность: у B031 и B017 здесь стоял
#: `yummyani.site`, а она согласованный КОНТРОЛЬ сравнения, где правка
#: намеренно не выпущена. Сверка печатала «ЖИВО» всегда, и закрытая выпуском
#: задача читалась как регрессия. Контроль нужен, но как ОТРИЦАТЕЛЬНЫЙ: он
#: объявлен отдельно в `КОНТРОЛЬ` и печатается своей строкой.
