#!/usr/bin/env python3
"""Собрать очередь работ по каждому активному домену из ИЗМЕРЕННОГО состояния.

Только чтение источников и запись в `queue/domains/`. Ни одного обращения к
сайтам: состояние берётся из готовых замеров, чтобы сборка очередей была
воспроизводимой и не зависела от сети.

Источники, и у каждого своя роль:

* `config/active-domains.json` — КТО в работе (список из задания владельца);
* замер сети (`automation/local/network-state.py --json`) — что установлено,
  что отдаёт домен, где голова ветки. Передаётся файлом через `--state`;
* `config/seo-module-defects.json` — какие ОТКРЫТЫЕ недостатки названы по этому
  домену. Задача без доказательства не создаётся: доказательством служит
  `verify_live` либо `evidence` самого недостатка.

Почему этап считается, а не назначается по порядку. Задание владельца прямо
запрещает искусственную задержку перед задачами роста на исправном сайте.
Поэтому этап 1 ставится только домену, у которого есть ОТКРЫТЫЙ недостаток
уровня P0/P1, то есть подтверждённое препятствие; остальным — этап 2.

Задача «снять исходное состояние» создаётся только там, где состояние
действительно не измерено. Выдумывать задачи, чтобы очередь не пустовала,
запрещено: пустая очередь — честный сигнал, что домен исправен и ждёт
исследования спроса.

    python3 automation/local/make-domain-queues.py --state var/network-state.json
    python3 automation/local/make-domain-queues.py --state … --dry-run
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
СПИСОК = КОРЕНЬ / "config" / "active-domains.json"
НЕДОСТАТКИ = КОРЕНЬ / "config" / "seo-module-defects.json"
#: Очереди лежат среди ВЕРСИОНИРУЕМЫХ файлов: `queue/*/*.json`
#: исключён правилом `.git/info/exclude`, которое само не
#: версионируется, и очередь домена там не пережила бы перенос в
#: другую копию.
ОЧЕРЕДИ = КОРЕНЬ / "config" / "domain-queues"

#: Состояния недостатка, при которых он ещё НЕ закрыт на сайте. `verified`
#: означает проверенный на живом сайте результат, `not_a_defect` — снятое
#: подозрение; остальные открыты.
ОТКРЫТЫЕ = ("proposed", "measured", "implemented", "installed", "released")
#: Уровни, которые считаются подтверждённым ПРЕПЯТСТВИЕМ (этап 1).
ПРЕПЯТСТВИЕ = ("P0", "P1")
#: Сколько задач на домен создаётся из недостатков. Остальные названы числом:
#: очередь из тридцати пунктов не очередь, а список.
ПРЕДЕЛ_ЗАДАЧ = 5
ВЕС = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}


def сейчас() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat(
        timespec="seconds").replace("+00:00", "Z")


#: Поля, в которых упоминание домена УТВЕРЖДАЕТ его затронутость. `example`
#: сюда НЕ входит намеренно: в примерах домены названы как контроль сравнения.
УТВЕРЖДАЮЩИЕ = ("title", "verify_live")


def касается(запись: dict, домен: str) -> bool:
    """Касается ли недостаток домена. Чистая функция.

    Признак ОДИН: размеченная область `domains`. Привязка по тексту отменена
    как ненадёжная, и это измерено на двух ошибках подряд:

    * по всему тексту: MOD-81 — дефект карты `1lordserials1.online`, но в его
      примере названы десять домéнов как контроль сравнения, и привязка
      объявила его дефектом каждого;
    * по «утверждающим» полям: заголовок MOD-114 называет `zonafilm.cc`
      единственной витриной, которая делает ПРАВИЛЬНО, — и домен всё равно
      попадал в пострадавшие.

    Поэтому неразмеченный недостаток НЕ приписывается никому. Это не пробел
    учёта, а отказ выдавать догадку за область: сетевые недостатки модуля
    (`MOD-03`, `MOD-06`, `MOD-07` и подобные) домену не принадлежат вовсе, а
    доменные без разметки считаются отдельным числом и попадают в сетевую
    задачу «разметить область».
    """
    return домен in (запись.get("domains") or ())


def недостатки_домена(все: list[dict], домен: str) -> list[dict]:
    годные = [з for з in все
              if з.get("state") in ОТКРЫТЫЕ and касается(з, домен)]
    return sorted(годные, key=lambda з: (ВЕС.get(з.get("priority"), 9),
                                         з.get("id", "")))


def этап(найденные: list[dict], замер: dict | None) -> tuple[int, str]:
    """Этап и ПРИЧИНА этапа. Чистая функция."""
    if замер is None:
        return 1, ("состояние домена не измерено — первый этап это и есть:"
                   " снять исходное состояние")
    препятствия = [з for з in найденные if з.get("priority") in ПРЕПЯТСТВИЕ]
    if препятствия:
        имена = ", ".join(з["id"] for з in препятствия[:4])
        return 1, f"открытые препятствия уровня P0/P1: {имена}"
    if найденные:
        return 2, (f"препятствий P0/P1 нет; открытых недостатков уровня"
                   f" P2/P3 — {len(найденные)}, они не блокируют рост")
    return 2, ("подтверждённых препятствий нет: сайт отдаёт 200, установленное"
               " совпадает с объявленным — задержка перед задачами роста не"
               " создаётся")


def задача_из_недостатка(домен: str, номер: int, з: dict,
                         исполнитель: str) -> dict:
    доказательство = (з.get("verify_live") or z_ev(з) or "").strip()
    return {
        "id": f"Q-{домен}-{номер:03d}",
        "state": "исследовано",
        "title": з["title"][:150],
        "problem": з["title"],
        "evidence": доказательство[:600] or f"запись {з['id']} реестра недостатков",
        "action": (з.get("fix") or з.get("owner_action")
                   or "действие не назначено: см. запись недостатка")[:600],
        "owner": исполнитель,
        "defect": з["id"],
        "created": сейчас(),
        "updated": сейчас(),
    }


def z_ev(з: dict) -> str:
    return str(з.get("evidence") or "")


def очередь_домена(запись: dict, замеры: dict[str, dict],
                   все_недостатки: list[dict]) -> dict:
    домен = запись["domain"]
    замер = замеры.get(домен)
    найденные = недостатки_домена(все_недостатки, домен)
    ступень, причина = этап(найденные, замер)
    исполнитель = запись.get("executor") or "wt-nova-publish-memory-02"
    задачи = [задача_из_недостатка(домен, и + 1, з, исполнитель)
              for и, з in enumerate(найденные[:ПРЕДЕЛ_ЗАДАЧ])]
    if not задачи:
        # Пустую очередь не заполняем выдумкой. Но у домена без открытых
        # препятствий настоящая первая задача есть, и её назвал владелец:
        # исследование спроса и конкурентов. Доказательство здесь — ЧЕСТНОЕ
        # отсутствие данных, а не придуманная проблема.
        задачи.append({
            "id": f"Q-{домен}-001",
            "state": "исследовано",
            "title": "снять спрос и конкурентов по домену",
            "problem": ("пар «запрос — страница» по этому домену нет:"
                        " приоритеты этапа 2 выбирать не из чего"),
            "evidence": ("НЕ ИЗМЕРЕНО: паспорт домена не содержит ни групп"
                         " запросов, ни конкурентов; подтверждённых"
                         " препятствий уровня P0/P1 у домена тоже нет"),
            "action": ("по разрешённым источникам снять типы страниц и охват"
                       " поисковых потребностей, сверить с референсом"
                       " семейства, записать в паспорт домена пары"
                       " «запрос — страница»"),
            "owner": исполнитель,
            "created": сейчас(),
            "updated": сейчас(),
        })
    если_ещё = len(найденные) - len(задачи)
    итог: dict = {
        "schema_version": 1,
        "domain": домен,
        "site_id": запись["site_id"],
        "family": запись["family"],
        "executor": исполнитель,
        "stage": ступень,
        "stage_reason": причина + (
            f"; ещё открытых недостатков по домену: {если_ещё}"
            if если_ещё > 0 else ""),
        "tasks": задачи,
    }
    if замер:
        итог["baseline"] = {
            "measured_at": замеры["__время__"],
            "home_status": замер.get("код"),
            "installed": замер.get("установлено"),
            "public_build": замер.get("публичный_build"),
            "branch": замер.get("ветка"),
            "branch_ahead": bool(замер.get("голова_впереди")),
            "notes": (
                "раскладки и ветки локально нет: код витрины живёт на узле"
                " k2-zomro-01, поэтому сравнение «реестр против установленного»"
                " здесь неприменимо"
                if замер.get("раскладка") == "—" else
                "голова ветки впереди установленного: в ветке есть невыпущенная"
                " работа" if замер.get("голова_впереди") else
                "установленное совпадает с публичным ответом"),
        }
    else:
        итог["baseline"] = {"measured_at": замеры["__время__"],
                            "notes": "домен в замере сети не найден"}
    return итог


def собрать(замер_файл: pathlib.Path, список: pathlib.Path = СПИСОК,
            недостатки: pathlib.Path = НЕДОСТАТКИ) -> list[dict]:
    д = json.loads(список.read_text(encoding="utf-8"))
    сырые = json.loads(замер_файл.read_text(encoding="utf-8"))
    замеры: dict[str, dict] = {з["домен"]: з for з in сырые}
    замеры["__время__"] = datetime.datetime.fromtimestamp(
        замер_файл.stat().st_mtime, datetime.timezone.utc).isoformat(
            timespec="seconds").replace("+00:00", "Z")
    реестр = json.loads(недостатки.read_text(encoding="utf-8"))
    все = реестр["defects"] if isinstance(реестр, dict) else реестр
    return [очередь_домена(з, замеры, все) for з in д["domains"]]


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--state", required=True,
                   help="файл замера сети (network-state.py --json)")
    р.add_argument("--dry-run", action="store_true")
    а = р.parse_args(аргв)

    очереди = собрать(pathlib.Path(а.state))
    ОЧЕРЕДИ.mkdir(parents=True, exist_ok=True)
    for о in очереди:
        путь = ОЧЕРЕДИ / f"{о['domain']}.json"
        строка = json.dumps(о, ensure_ascii=False, indent=1) + "\n"
        if not а.dry_run:
            путь.write_text(строка, encoding="utf-8")
        print(f"{о['domain']:24} этап {о['stage']} задач {len(о['tasks']):2}"
              f"  {о['stage_reason'][:70]}")
    print(f"\nочередей {'собрано' if а.dry_run else 'записано'}:"
          f" {len(очереди)}; этап 1 у"
          f" {sum(1 for о in очереди if о['stage'] == 1)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
