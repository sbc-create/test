#!/usr/bin/env python3
"""Что публичный `/healthz` рассказывает о внутреннем устройстве витрины.

Повод. `/healthz` — сознательно ПУБЛИЧНЫЙ служебный путь: он нужен наблюдению,
и решения D150, D166 и D187 закрывают его только от ИНДЕКСАЦИИ, причём в двух
слоях. Но закрыть от индексации и ограничить содержимое — разные вещи, и
второе до сих пор не измерялось. Замер 12.10 на `animedia.icu` показал в
публичном ответе `runtime_path`, `runtime_sha256` и `pid`.

Инструмент НЕ выносит вердикт: публичность пути решена и не обсуждается, а
состав ответа может быть и сознательным. Он отвечает на один вопрос числом:
какие поля видны снаружи у каждой витрины и у скольких из них видно то, что
описывает устройство машины — путь в файловой системе, хеш файла рантайма,
номер процесса, имя учётной записи.

Секретов инструмент не печатает: он показывает ИМЕНА полей и, для путей,
только то, что путь присутствует. Значения путей и хешей в вывод не идут —
иначе отчёт сам стал бы способом их распространения.

Служебный путь не один. По умолчанию мерится `/healthz`, но ключ `--path`
принимает любой и повторяется: у семейства Lords рядом живёт публичный
`/__template_version`, отдающий весь манифест, у lordfilm47.space — свой
`/readyz`. Закрыть один путь и не измерить остальные — это закрыть дверь при
открытом окне.

Только чтение.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1].parent
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ИСПЫТАТЕЛЬНЫЕ = (".localhost", ".test", ".invalid", ".example")

#: Поля, которые описывают УСТРОЙСТВО машины, а не состояние службы.
#: Разделение именно такое: `ok`, `ready`, `build_id` отвечают на вопрос
#: «работает ли», а путь, хеш и номер процесса — на вопрос «как устроено».
#: Поля, раскрывающие устройство машины ПО ВИДУ. Закрытый перечень имён был
#: неверным приёмом: поля добавляются выпусками, и каждое новое по умолчанию
#: считалось безобидным. Измерено 12.10: перечень из десяти имён находил
#: четыре поля, а раскрывающих на тех же витринах около двадцати одного.
ВИДЫ_РАСКРЫТИЯ = ("_path", "_sha256", "_digest", "_commit", "_revision",
                  "_dir", "_id")
#: Имена, которые под видовой признак не подходят, но раскрывают не меньше.
ОПИСЫВАЮТ_УСТРОЙСТВО = ("pid", "process_start_time", "account", "unit",
                        "port", "python", "profile",
                        # Имя юнита systemd — та же настройка машины, что и
                        # `unit`, только названная иначе: измерено
                        # 2026-10-18, у аниме-витрин это `service_name` со
                        # значением `nova-<домен>.service`.
                        "service_name",
                        # Чем собрано, из чего собрано и из каких файлов.
                        "core_runtime", "built_from", "artifact_files")


def _раскрывает_значение(значение) -> bool:
    """Значение само говорит об устройстве, как бы поле ни называлось.

    Второй признак нужен потому, что первый — перечень видов ИМЕНИ, а имя
    выбирает тот, кто поле добавил. Измерено 2026-10-18: на animeg0.site
    разбор по смыслу дал 15 полей про устройство, признак по имени — 10.
    Разница — поля с путём или суммой внутри, названные иначе.

    Значение в вывод не идёт ни здесь, ни выше: функция отвечает да/нет.
    """
    if isinstance(значение, bool) or значение is None:
        return False
    if isinstance(значение, int):
        return False
    # Список и словарь осматриваются вглубь: поле со списком путей раскрывает
    # ровно столько же, сколько поле с одним путём, а признак по строке его
    # не видел вовсе.
    if isinstance(значение, (list, tuple)):
        return any(_раскрывает_значение(э) for э in значение)
    if isinstance(значение, dict):
        return any(_раскрывает_значение(э) for э in значение.values())
    if not isinstance(значение, str):
        return False
    т = значение.strip()
    if т.startswith("/") and т.count("/") >= 2:
        return True          # путь в файловой системе
    if len(т) in (40, 64) and all(с in "0123456789abcdef" for с in т.lower()):
        return True          # сумма файла или номер коммита
    return False


def раскрывает(имя: str, значение=None) -> bool:
    """Поле раскрывает устройство машины или содержимое выпуска.

    `ok` и `runtime_digest_match` не раскрывают: первое — состояние, второе —
    да/нет о совпадении, без самой цифры.
    """
    if имя in ("ok", "runtime_digest_match"):
        return False
    if имя in ОПИСЫВАЮТ_УСТРОЙСТВО:
        return True
    if any(имя.endswith(вид) for вид in ВИДЫ_РАСКРЫТИЯ):
        return True
    return _раскрывает_значение(значение)


def домены(путь: Path) -> list[str]:
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        print(f"реестр ячеек не прочитан ({путь}): {сбой}", file=sys.stderr)
        return []
    return [я["domain"] for я in документ.get("cells") or []
            if я.get("domain") and not я["domain"].endswith(ИСПЫТАТЕЛЬНЫЕ)]


def ответ(домен: str, таймаут: int, путь: str = "/healthz") -> tuple[str, str]:
    итог = subprocess.run(
        ["curl", "-sS", "-w", "\n%{http_code}", "--max-time", str(таймаут),
         f"https://{домен}{путь}"],
        capture_output=True, text=True)
    вывод = итог.stdout or ""
    тело, _, код = вывод.rpartition("\n")
    if итог.returncode == 6:
        return "dns", ""
    return (код.strip() or "000"), тело


def поля(тело: str) -> tuple[list[str], bool, dict]:
    """(имена полей верхнего уровня, разобрался ли JSON, сам разбор).

    Наружу инструмент печатает имена, а не значения. Разбор возвращается
    третьим значением только для СУЖДЕНИЯ о виде значения (путь, сумма,
    коммит) — ни одно значение в вывод не попадает.
    """
    try:
        документ = json.loads(тело)
    except ValueError:
        # Не JSON — тогда хотя бы скажем, похож ли ответ на служебный.
        return ([], False, {})
    if not isinstance(документ, dict):
        return ([], False, {})
    return (sorted(документ), True, документ)


def разбор(аргв=None):
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--registry", type=Path, default=РЕЕСТР)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--timeout", type=int, default=25)
    # Служебный путь не один. У семейства Lords рядом с `/healthz` живёт
    # публичный `/__template_version`, отдающий весь манифест; у
    # lordfilm47.space — свой `/readyz`. Закрыть один и не измерить
    # остальные — это закрыть дверь при открытом окне.
    р.add_argument("--path", action="append", default=[],
                   help="служебный путь; по умолчанию /healthz, можно несколько")
    р.add_argument("--json", action="store_true")
    return р.parse_args(аргв)


def главное(аргв=None) -> int:
    опции = разбор(аргв)
    список = опции.domain or домены(опции.registry)
    if not список:
        return 2
    пути = опции.path or ["/healthz"]
    итоги = []
    for путь in пути:
        for домен in список:
            код, тело = ответ(домен, опции.timeout, путь)
            имена, разобрался, разбор_ответа = поля(тело)
            устройство = [и for и in имена
                          if раскрывает(и, разбор_ответа.get(и))]
            # Отдельно — те, что опознаны ТОЛЬКО по значению: именно их
            # признак по имени и терял.
            по_значению = [и for и in устройство if not раскрывает(и)]
            итоги.append({"путь": путь, "домен": домен, "код": код,
                          "json": разобрался, "полей": len(имена),
                          "про_устройство": устройство,
                          "только_по_значению": по_значению, "имена": имена})

    if опции.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=2))
        return 0

    открытых = 0
    for путь in пути:
        свои = [и for и in итоги if и["путь"] == путь]
        print(f"\n=== {путь}")
        print(f"{'домен':24} {'код':>5} {'полей':>6}  поля про устройство машины")
        for и in свои:
            if и["про_устройство"]:
                открытых += 1
            хвост = ""
            if и["только_по_значению"]:
                хвост = f"  [по значению: {len(и['только_по_значению'])}]"
            print(f"{и['домен']:24} {и['код']:>5} {и['полей']:>6}  "
                  + (f"{len(и['про_устройство'])}: "
                     + ", ".join(и["про_устройство"][:6])
                     + (" …" if len(и["про_устройство"]) > 6 else "")
                     if и["про_устройство"]
                     else "—")
                  + хвост)
        живых = [и for и in свои if и["код"] == "200"]
        открыто_здесь = len([и for и in свои if и["про_устройство"]])
        print(f"ответили 200: {len(живых)} из {len(свои)}; "
              f"показывают устройство машины: {открыто_здесь}")
    print(f"\nвсего пар «путь + витрина», показывающих устройство: {открытых}")
    print("Счёт инструмента — НИЖНЯЯ оценка. Он опознаёт поле по виду имени и "
          "по виду значения (путь, 64-значная сумма, 40-значный коммит, и то "
          "же внутри списков). Поле, раскрывающее устройство по смыслу, но без "
          "такого имени и значения, он пропустит: измерено 2026-10-18 на "
          "animeg0.site — признак 11 полей, разбор по смыслу у линии animego "
          "15. Разница в столбце «полей» видна: что не опознано, то и остаток.")
    print("Вердикта инструмент не выносит: публичность /healthz решена "
          "(D150, D166, D187 закрывают его от ИНДЕКСАЦИИ, а не от доступа), и "
          "состав ответа может быть сознательным. Значения путей и хешей в "
          "вывод не идут — иначе отчёт сам стал бы способом их "
          "распространения.")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
