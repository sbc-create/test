#!/usr/bin/env python3
"""Сузился НАБОР страниц с поисковыми входами или упал спрос. Только чтение.

ЗАЧЕМ. Без Вебмастера нельзя посмотреть, что ушло из индекса. Но Метрика
даёт набор страниц, по которым приходят поисковые входы, и это даёт
различающий признак:

* набор страниц СУЗИЛСЯ, а на оставшихся входы держатся → страницы перестали
  приводить трафик: это похоже на потерю индексации или показов;
* набор тот ЖЕ, а входы упали на всех → упал спрос либо позиции;
* набор вырос, входы выросли → рост.

Это не доказательство индексации: Метрика не знает об индексе. Это способ
НАЗВАТЬ, какая из двух гипотез согласуется с данными, и он честно слабее
Вебмастера.

ОКНА БРАТЬ РОВНО НА СЕМЬ СУТОК ВРОЗЬ. Окно снимка — «7 дней до вчера»,
поэтому соседние суточные снимки перекрываются на шесть дней из семи, и их
разность — сдвиг окна, а не изменение. Инструмент это проверяет сам и
отказывается сравнивать перекрывающиеся окна.

    python3 automation/local/search-page-set-shift.py \\
        --before <снимок> --after <снимок>

Коды: 0 — сравнение проведено; 2 — окна перекрываются или снимки не прочитаны.
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
#: Сколько суток должно быть между снимками, чтобы окна НЕ перекрывались.
РАЗНОС_СУТОК = 7


def дата_снимка(п: pathlib.Path) -> datetime.date | None:
    м = re.search(r"(\d{4})-(\d{2})-(\d{2})", п.name)
    if not м:
        return None
    return datetime.date(int(м.group(1)), int(м.group(2)), int(м.group(3)))


def окна_не_перекрываются(а: pathlib.Path, б: pathlib.Path) -> tuple[bool, str]:
    да, дб = дата_снимка(а), дата_снимка(б)
    if да is None or дб is None:
        return False, "в имени снимка нет даты — сравнивать нечем"
    разница = abs((дб - да).days)
    if разница < РАЗНОС_СУТОК:
        return False, (f"окна перекрываются: между снимками {разница} суток"
                       f" при окне 7 суток. Разность таких окон — сдвиг окна,"
                       f" а не изменение")
    return True, f"между снимками {разница} суток — окна не перекрываются"


def _адрес(измерения: list[dict]) -> str | None:
    для_пути = [и for и in измерения
                if isinstance(и, dict)
                and (str(и.get("name") or "").startswith("/")
                     or и.get("favicon"))]
    return str(для_пути[0].get("name")) if для_пути else None


def набор(снимок: pathlib.Path) -> dict[str, dict[str, int]]:
    """{домен: {страница: входы}} из разреза поисковых входов."""
    д = json.loads(снимок.read_text(encoding="utf-8"))
    итог: dict[str, dict[str, int]] = {}
    for запись in д.get("domains") or []:
        домен = запись.get("domain")
        з = next((m for m in запись.get("measurements") or []
                  if m.get("key") == "search_landing_pages"), None)
        if not домен or not з or not з.get("measured"):
            continue
        страницы: dict[str, int] = {}
        for с in з.get("value") or []:
            путь = _адрес(с.get("dimensions") or [])
            if путь is None:
                continue
            м = с.get("metrics") or [0]
            страницы[путь] = страницы.get(путь, 0) + int(м[0] or 0)
        итог[домен] = страницы
    return итог


def истолковать(было: dict[str, int], стало: dict[str, int]) -> str:
    """Какая гипотеза согласуется с данными. Чистая функция.

    Вывод строится по ЧИСТОМУ изменению числа страниц и входов. Первая
    редакция объявляла «набор сузился» при любом уходе страницы — и ставила
    этот вывод домену, у которого набор вырос с 48 до 129 страниц. Уход
    отдельных страниц при общем росте — обычное обновление набора, а не
    потеря.

    Обмен страницами печатается всегда отдельным числом: он может быть
    велик при неизменном итоге, и молчать о нём нельзя.
    """
    if not было and not стало:
        return "нет данных ни до, ни после"
    ушли = set(было) - set(стало)
    пришли = set(стало) - set(было)
    обмен = f"обмен: ушло {len(ушли)}, пришло {len(пришли)}"
    до_стр, после_стр = len(было), len(стало)
    до_вх, после_вх = sum(было.values()), sum(стало.values())
    хвост = (f" (страниц {до_стр} → {после_стр}, входов {до_вх} →"
             f" {после_вх}; {обмен})")

    if not было:
        return "страниц с входами НЕ БЫЛО — появились" + хвост
    if not стало:
        return ("страницы с входами ИСЧЕЗЛИ ВСЕ — согласуется с потерей"
                " показов, но проверяется только Вебмастером") + хвост
    if после_стр > до_стр and после_вх >= до_вх:
        return "РОСТ: набор шире, входов не меньше" + хвост
    if после_стр < до_стр and после_вх < до_вх:
        return ("НАБОР СУЗИЛСЯ и входы упали — согласуется с потерей показов"
                " у ушедших страниц") + хвост
    if не_упало(до_стр, после_стр) and после_вх < до_вх:
        return ("НАБОР ДЕРЖИТСЯ, ВХОДЫ УПАЛИ — согласуется с падением спроса"
                " или позиций, а не с потерей страниц") + хвост
    if после_стр < до_стр and после_вх >= до_вх:
        return ("набор сузился, но входы не упали: спрос сошёлся на меньшем"
                " числе страниц") + хвост
    return "однозначного признака нет" + хвост


def не_упало(до: int, после: int, допуск: float = 0.15) -> bool:
    """Держится ли величина. Допуск нужен: небольшие колебания — не падение."""
    if до == 0:
        return после >= 0
    return после >= до * (1 - допуск)


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--before", required=True)
    р.add_argument("--after", required=True)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    до, после = pathlib.Path(а.before), pathlib.Path(а.after)
    for п in (до, после):
        if not п.is_file():
            print(f"снимок не прочитан: {п}", file=sys.stderr)
            return 2
    годно, почему = окна_не_перекрываются(до, после)
    print(f"окна: {почему}")
    if not годно:
        return 2

    а_наб, б_наб = набор(до), набор(после)
    итоги = []
    for домен in sorted(set(а_наб) | set(б_наб)):
        было, стало = а_наб.get(домен, {}), б_наб.get(домен, {})
        итоги.append({
            "домен": домен,
            "страниц_до": len(было),
            "страниц_после": len(стало),
            "входов_до": sum(было.values()),
            "входов_после": sum(стало.values()),
            "ушло": sorted(set(было) - set(стало))[:5],
            "пришло": sorted(set(стало) - set(было))[:5],
            "толкование": истолковать(было, стало),
        })
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            print(f"\n{и['домен']}: страниц {и['страниц_до']} →"
                  f" {и['страниц_после']}, входов {и['входов_до']} →"
                  f" {и['входов_после']}")
            print(f"   {и['толкование']}")
            if и["ушло"]:
                print(f"   ушли: {', '.join(с[:48] for с in и['ушло'])}")
        print("\nЭто НЕ доказательство индексации: Метрика об индексе не"
              " знает. Это способ назвать, какая гипотеза согласуется с"
              " данными, и он слабее Вебмастера.")
        print("Входы — сумма по разрезу с пределом top_n = 200, а не полный"
              " поисковый итог. Измерено на крупнейшем домене: сумма топ-N"
              " покрывает 96.7 % поискового итога (12 455 из 12 885), то есть"
              " сравнение идёт по почти всему, но не по всему. Долю хвоста"
              " при выводах учитывать, нулём её не считать.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
