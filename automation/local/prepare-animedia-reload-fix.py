"""Готовит и проверяет исправление лишних перечитываний снимка витрины Animedia.

    python3 automation/local/prepare-animedia-reload-fix.py <каталог src> [--verify]

Что исправляется и почему — измерено 2026-10-10 на animedia.icu:

1. **Источник.** `animedia-data-update.py` (таймер каждые 10 минут) пишет снимок
   через `записать_атомарно` БЕЗУСЛОВНО. Измерено: в 21:07:44 файл
   `animedia-01-details.json` был перезаписан, и у него сменилось ТОЛЬКО время —
   размер (14 781 929 Б) и sha256 содержимого остались прежними.
2. **Читатель.** Рантайм витрины сравнивает `(mtime_ns, размер)` трёх файлов и
   при любом расхождении разбирает снимок ЦЕЛИКОМ: `tracemalloc` насчитал около
   полумиллиона объектов за разбор (`json/decoder.py` плюс построение
   указателей). Прежние объекты ОСВОБОЖДАЮТСЯ — слабые ссылки на `Данные` и
   `Подробности` после подмены мертвы, — но куча остаётся фрагментированной, и
   RSS растёт ступенями: измерено от +2,8 до +6,9 МиБ за перезагрузку.

Сложение этих двух: витрина с активным обновлятелем перечитывает снимок каждые
3–10 минут впустую. За сутки это и дало измеренный избыток — animedia.icu
1504 МиБ против 449–485 МиБ у четырёх её близнецов на ТОМ ЖЕ снимке, а после
перезапуска она снова набрала 545 МиБ за 35 минут, обогнав 32-часового соседа.

Чего исправление НЕ делает: не отключает перечитывание (новый снимок обязан
доезжать), не трогает частоту обновлятеля и не снижает порог редактора.

Запуск без `--verify` только правит файлы в указанном каталоге. С `--verify`
дополнительно поднимает исправленный рантайм на КОПИИ боевых данных и
измеряет оба свойства.
"""
