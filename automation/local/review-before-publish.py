#!/usr/bin/env python3
"""Стоит ли рецензия РАНЬШЕ выпуска: порядок по журналу, а не по утверждению.

Зачем. MOD-173 требует: «без принятой рецензии выпуск запрещён». Ворота допуска
написаны и проверены, но пока они не установлены в работающей службе, сама
операция рецензии остаётся доступной — и запись о прочтении можно оформить уже
ПОСЛЕ публикации. Разница принципиальная: в первом случае текст не попадёт на
страницу без прочтения, во втором он там уже стоит, а запись лишь говорит, что
его потом прочли.

Измерено 25.10 по журналам хранилищ: публикация идёт через 28–53 секунды после
подготовки, а рецензия приходит через 18–78 минут после публикации. Поэтому
утверждение «материалы рецензируются» без порядка — бессмысленно, и его нельзя
писать в отчёт.

Что считается. `history.jsonl` каждого домена пишет операцию, время и
исполнителя. По каждому опубликованному материалу берётся ПОСЛЕДНЯЯ публикация
и рецензия, относящаяся к ней:

  рецензия раньше выпуска   ворота работают: текст прочитан до страницы
  рецензия позже выпуска    след прочтения, а не ворота; печатается задержка
  рецензии нет вовсе        материал на странице никем не прочитан

Вердикт со знаменателем: доля каждого исхода от числа ПУБЛИКАЦИЙ, а не от числа
рецензий — иначе «все рецензии вовремя» получилось бы и при одной рецензии на
тысячу публикаций.

    python3 automation/local/review-before-publish.py --days 1
    python3 automation/local/review-before-publish.py --days 7 --json out.json
"""
from __future__ import annotations

import argparse
import datetime as dt
import glob
import json
import pathlib
import sys

ЖУРНАЛЫ = "/srv/sites/*/runtime/overlays/*/history.jsonl"


def события(образец: str = ЖУРНАЛЫ) -> list[dict]:
    из: list[dict] = []
    for путь in sorted(glob.glob(образец)):
        домен = pathlib.Path(путь).parent.name
        for строка in pathlib.Path(путь).read_text(
                encoding="utf-8", errors="replace").splitlines():
            строка = строка.strip()
            if not строка:
                continue
            try:
                з = json.loads(строка)
            except ValueError:
                continue
            if isinstance(з, dict):
                из.append({**з, "домен": домен})
    return из


def _время(знач) -> dt.datetime | None:
    try:
        return dt.datetime.fromisoformat(str(знач).replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return None


def порядок(события_: list[dict], с: dt.datetime | None = None) -> dict:
    """Исход по каждому опубликованному материалу.

    Берётся ПОСЛЕДНЯЯ публикация материала: если текст переиздавали, судить
    надо о той редакции, что стоит на странице.
    """
    публикации: dict[tuple[str, str], dt.datetime] = {}
    рецензии: dict[tuple[str, str], list[dt.datetime]] = {}
    for з in события_:
        т = _время(з.get("at"))
        if т is None:
            continue
        ключ = (з.get("домен") or "", з.get("slug") or "")
        if з.get("op") == "publish":
            if ключ not in публикации or т > публикации[ключ]:
                публикации[ключ] = т
        elif з.get("op") == "review":
            рецензии.setdefault(ключ, []).append(т)
    строки = []
    for ключ, когда in публикации.items():
        if с is not None and когда < с:
            continue
        все = sorted(рецензии.get(ключ) or [])
        раньше = [т for т in все if т <= когда]
        позже = [т for т in все if т > когда]
        if раньше:
            исход, задержка = "рецензия раньше выпуска", None
        elif позже:
            исход = "рецензия позже выпуска"
            задержка = (позже[0] - когда).total_seconds() / 60.0
        else:
            исход, задержка = "рецензии нет вовсе", None
        строки.append({"домен": ключ[0], "slug": ключ[1],
                       "опубликован": когда.strftime("%Y-%m-%dT%H:%M:%SZ"),
                       "исход": исход,
                       "задержка_мин": round(задержка, 1) if задержка else None})
    return {"строки": строки}


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--days", type=float, default=1.0)
    р.add_argument("--logs", default=ЖУРНАЛЫ)
    р.add_argument("--json", type=pathlib.Path)
    а = р.parse_args(аргв)
    соб = события(а.logs)
    if not соб:
        print(f"НЕ ИЗМЕРЕНО: журналов хранилищ нет по образцу {а.logs}",
              file=sys.stderr)
        return 2
    с = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=а.days)
    итог = порядок(соб, с)
    строки = итог["строки"]
    if not строки:
        print(f"за последние {а.days:g} сут публикаций не было")
        return 0
    счёт = {и: sum(1 for з in строки if з["исход"] == и)
            for и in ("рецензия раньше выпуска", "рецензия позже выпуска",
                      "рецензии нет вовсе")}
    всего = len(строки)
    print(f"окно: последние {а.days:g} сут; публикаций {всего}")
    print()
    for и, n in счёт.items():
        print(f"  {и:26} {n:5} {n/всего:6.1%}")
    по_витринам = {}
    for з in строки:
        д_ = з["домен"]
        по_витринам.setdefault(д_, {"всего": 0, "раньше": 0})
        по_витринам[д_]["всего"] += 1
        if з["исход"] == "рецензия раньше выпуска":
            по_витринам[д_]["раньше"] += 1
    print()
    print(f"{'витрина':22} {'публикаций':>11} {'рецензия раньше':>16}")
    for д_, в in sorted(по_витринам.items(), key=lambda x: -x[1]["всего"]):
        print(f"{д_:22} {в['всего']:11} {в['раньше']:16}")
    print(f"{'ИТОГО':22} {len(строки):11} {счёт['рецензия раньше выпуска']:16}"
          f"   на {len(по_витринам)} витринах")
    поздние = [з for з in строки if з["задержка_мин"]]
    if поздние:
        задержки = sorted(з["задержка_мин"] for з in поздние)
        сред = sum(задержки) / len(задержки)
        print()
        print(f"задержка рецензии после выпуска: от {задержки[0]:.0f}"
              f" до {задержки[-1]:.0f} мин, в среднем {сред:.0f}")
    без = [з for з in строки if з["исход"] == "рецензии нет вовсе"]
    if без:
        print()
        print(f"публикации без всякой рецензии ({len(без)}), первые пять:")
        for з in без[:5]:
            print(f"   {з['домен']:18} {з['slug'][:44]:46} {з['опубликован']}")
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        а.json.write_text(json.dumps({**итог, "счёт": счёт},
                                     ensure_ascii=False, indent=1),
                          encoding="utf-8")
        print(f"\nподробности: {а.json}")
    print()
    вовремя = счёт["рецензия раньше выпуска"]
    if вовремя == всего:
        print(f"ВЫВОД: ворота работают — у всех {всего} публикаций рецензия"
              " стоит раньше выпуска")
        return 0
    print(f"ВЫВОД: ворота НЕ установлены — рецензия раньше выпуска только у"
          f" {вовремя} из {всего} публикаций."
          " Остальное — след прочтения после факта либо его отсутствие;"
          " называть это обязательной проверкой нельзя")
    return 1


if __name__ == "__main__":
    sys.exit(главное())
