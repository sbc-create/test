#!/usr/bin/env python3
"""Несут ли проекты ячеек ТЕКУЩИЙ рантайм семейства — или закреплён устаревший.

Повод измерен 26.10. В каноническом рантайме исправлен общий дефект (MOD-202:
страницы сезонов индексировались без единой входящей внутренней ссылки), а все
пять проектов новой пятёрки остались закреплены на коммите `137a3152fb20` с
рантаймом `21ae3bed93ae…` — редакцией ДО правки. То есть запуск пятёрки унёс
бы дефект в живую сеть, и заметить это по паспорту было нечем: там написано
«в работе», а не «закреплён старый шаблон».

Почему именно сравнение сумм, а не коммитов. Коммит мог бы отличаться от
текущего по безвредной причине (правка документа), и отказ по нему был бы
ложным. Расходится ли ПОВЕДЕНИЕ — видно только по сумме файла рантайма.

Три исхода, и третий существует не для красоты: проект мог не создаваться
вовсе (ячейка объявлена, но ещё не собрана), и это не то же, что устаревший.

Только чтение: ни один пин, проект и реестр не правятся.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
#: Файл, по которому сверяется поведение. Он же точка входа витрины.
РАНТАЙМ = "lords-frontend.py"
СОВПАДАЕТ, УСТАРЕЛ, НЕТ_ПРОЕКТА = "совпадает", "УСТАРЕЛ", "проекта нет"


def сумма_текущего(корень: pathlib.Path = КОРЕНЬ) -> str:
    """Сумма рантайма, который сейчас в репозитории."""
    п = корень / "automation" / "host" / РАНТАЙМ
    return hashlib.sha256(п.read_bytes()).hexdigest() if п.is_file() else ""


def закреплено(проект: pathlib.Path) -> tuple[str, str]:
    """(сумма в пинах, сумма копии в проекте) — пустые, если нет."""
    пины = проект / "pins.lock.json"
    в_пинах = ""
    if пины.is_file():
        try:
            д = json.loads(пины.read_text(encoding="utf-8"))
            в_пинах = str(((д.get("files") or {}).get(РАНТАЙМ) or {}).get("sha256") or "")
        except (OSError, ValueError):
            в_пинах = ""
    копия = проект / "src" / РАНТАЙМ
    в_копии = hashlib.sha256(копия.read_bytes()).hexdigest() if копия.is_file() else ""
    return в_пинах, в_копии


def свежесть(реестр: pathlib.Path = РЕЕСТР, корень: pathlib.Path = КОРЕНЬ) -> list[dict]:
    текущая = сумма_текущего(корень)
    итог = []
    данные = json.loads(реестр.read_text(encoding="utf-8"))
    for я in данные.get("cells") or []:
        if (я.get("withdrawal") or {}).get("withdrawn"):
            continue
        путь = ((я.get("repo") or {}).get("path") or "").strip()
        проект = (корень / путь) if путь else None
        if not проект or not проект.is_dir():
            итог.append({"site_id": я.get("site_id"), "домен": я.get("domain"),
                         "исход": НЕТ_ПРОЕКТА, "почему": f"каталога {путь or '—'} нет"})
            continue
        в_пинах, в_копии = закреплено(проект)
        if not в_пинах and not в_копии:
            итог.append({"site_id": я.get("site_id"), "домен": я.get("domain"),
                         "исход": НЕТ_ПРОЕКТА,
                         "почему": "ни пинов, ни копии рантайма в проекте"})
            continue
        совпало = (в_пинах == текущая) and (в_копии == текущая)
        итог.append({
            "site_id": я.get("site_id"), "домен": я.get("domain"),
            "исход": СОВПАДАЕТ if совпало else УСТАРЕЛ,
            "почему": (f"пины {в_пинах[:12] or '—'}, копия {в_копии[:12] or '—'}, "
                       f"репозиторий {текущая[:12]}")})
    return итог


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--registry", type=pathlib.Path, default=РЕЕСТР)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    записи = свежесть(а.registry)
    if а.json:
        print(json.dumps({"рантайм": РАНТАЙМ, "сумма_репозитория": сумма_текущего(),
                          "ячейки": записи}, ensure_ascii=False, indent=1))
        return 0
    устарели = [з for з in записи if з["исход"] == УСТАРЕЛ]
    print(f"рантайм {РАНТАЙМ}, сумма репозитория {сумма_текущего()[:12]}")
    for з in записи:
        print(f"  {з['исход']:12s} {str(з['site_id']):12s} {str(з['домен']):24s} {з['почему']}")
    print(f"\nячеек с проектом: {sum(1 for з in записи if з['исход'] != НЕТ_ПРОЕКТА)}, "
          f"устарели: {len(устарели)}")
    if устарели:
        print("Устаревший пин означает запуск с прежним поведением шаблона: "
              "перезакрепить штатным генератором на чистом дереве.")
    return 1 if устарели else 0


if __name__ == "__main__":
    raise SystemExit(главная())
