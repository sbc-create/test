#!/usr/bin/env python3
"""Пользовательские сценарии витрины: работает ли то, что выглядит рабочим.

Проверяются не кнопки, а СЦЕНАРИИ целиком — запрос, ответ, и там, где есть
сохранение, повторное чтение:

  поиск        форма шапки: своё слово из каталога даёт непустую выдачу;
  фильтры      /catalog/?genre=… и ?year=… меняют состав, а не возвращают всё;
  страницы     вторая страница каталога отличается от первой;
  произведение карточка открывается, у неё есть плеер и список серий;
  оценка       форма оценки существует и её отправка сохраняется (проверяется
               повторным чтением страницы);
  избранное    есть ли вообще такая возможность на витрине.

Отдельно отмечается «кнопка есть, действия нет»: форма или ссылка в разметке
при отсутствии обработчика.

    python3 automation/local/user-scenarios-probe.py lordfilm.group
"""
from __future__ import annotations

import re
import subprocess
import sys
from urllib.parse import quote


def взять(url: str, данные: str = "", куки: str = "") -> tuple[str, str]:
    # `-L`: перенаправление на свой же канонический адрес — это исправное
    # поведение, а не отказ. Измерено 2026-10-18: `/catalog/` на Yummy отдаёт
    # 308 на `/catalog`, и без прохода по цепочке проба печатала «карточек 0»
    # у работающей листалки.
    #
    # Код возвращается ПОСЛЕДНИЙ в цепочке, а число переходов печатается
    # рядом: иначе «прошли по 308 и получили 200» стало бы неотличимо от
    # «ответили 200 сразу», а 404 в конце цепочки — незаметным.
    арг = ["curl", "-sSL", "--max-time", "45",
           "-w", "\n@@%{http_code}/%{num_redirects}"]
    if куки:
        арг += ["-H", f"Cookie: {куки}"]
    if данные:
        арг += ["-X", "POST", "--data", данные]
    арг.append(url)
    п = subprocess.run(арг, capture_output=True, text=True)
    вывод = п.stdout or ""
    м = re.search(r"\n@@(\d+)/(\d+)$", вывод)
    if not м:
        return вывод, "0"
    код, переходов = м.group(1), int(м.group(2))
    return вывод[:м.start()], (код if not переходов else f"{код}←{переходов}")


def текст(html: str) -> str:
    т = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", html)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", т))


#: Формы адреса карточки произведения, встречающиеся в сети. Измерено
#: 2026-10-18: Lords и Zona отдают `/title/<slug>/`, Animedia — `/title/<slug>/`,
#: Yummy — `/anime/<slug>` БЕЗ завершающей косой. Признак на одну форму
#: печатал «карточек 0» там, где их 97.
ФОРМЫ_КАРТОЧКИ = ("/title/", "/anime/")


def карточки(html: str) -> list[str]:
    найдено: list[str] = []
    for форма in ФОРМЫ_КАРТОЧКИ:
        образец = r'href="(' + re.escape(форма) + r'[^"/?#]+/?)"'
        найдено += re.findall(образец, html)
    return list(dict.fromkeys(найдено))


def форма_карточек(html: str) -> str:
    """Какой формой адресуются карточки на этой странице.

    Нужна отчёту: «карточек 0» при ИЗВЕСТНОЙ форме — утверждение о странице,
    а при неизвестной — признание, что мерить нечем. Без различения второе
    читается как первое.
    """
    для_формы = {}
    for форма in ФОРМЫ_КАРТОЧКИ:
        образец = r'href="(' + re.escape(форма) + r'[^"/?#]+/?)"'
        сколько = len(set(re.findall(образец, html)))
        if сколько:
            для_формы[форма] = сколько
    if not для_формы:
        return "форма не распознана"
    return ", ".join(f"{ф} ({н})" for ф, н in sorted(для_формы.items(),
                                                     key=lambda п: -п[1]))


def слово_для_поиска(дом: str) -> tuple[str, str]:
    """Слово из СВОЕГО каталога для проверки поиска, и откуда оно взято.

    Четыре попытки, и порядок у них измеренный, а не произвольный: подпись
    карточки у семейств лежит в разных местах, и одной формы хватало только
    Lords.

      `title="…"`             семейство lords;
      текст ссылки            animego;
      `aria-label="…"`        zona — у неё подпись карточки только здесь,
                              а `alt` у постера пустой (измерено 2026-10-18,
                              zonafilm.cc: `<a class="zp" href="/title/…"
                              aria-label="Графиня де Монсоро">`);
      `\\"aria-label\\":\\"…\\"`  yummy — её страница приходит
                              сериализованным деревом Next.js, где кавычки
                              экранированы.

    Последняя попытка — слово из СЛАГА. Для рантаймов lords и zona это
    законный запрос: поисковый индекс включает и slug, и транслит названия
    (`Данные.__init__`, список `_формы`). Для чужого рантайма это
    предположение, поэтому источник слова печатается рядом с ответом.

    Пусто — значит НЕ ИЗМЕРЕНО, и это честнее, чем запрос наугад: «найдено 0»
    по выдуманному слову неотличимо от сломанного поиска.
    """
    подписи = re.findall(
        r'<a[^>]*href="(?:/title/|/anime/)[^"]+"[^>]*title="([^"]+)"', дом)
    источник = "title="
    if not подписи:
        подписи = re.findall(
            r'<a[^>]*href="(?:/title/|/anime/)[^"]+"[^>]*>\s*([^<>]{4,60}?)\s*<',
            дом)
        источник = "текст ссылки"
    if not подписи:
        # ТОЛЬКО на ссылке карточки, а не любой `aria-label` страницы.
        # Измерено 2026-10-18: без этого условия на zonafilm.cc берётся
        # «Открыть» (подпись кнопки меню), а на yummyani.site — «главную»
        # («вернуться на главную»), и поиск проверяется не тем словом. У
        # yummyani.site это дало ложную находку: запрос «главную» ответил 308
        # и нулём карточек, то есть «поиск сломан» там, где сломан был запрос.
        подписи = re.findall(
            r'<a[^>]*href="(?:/title/|/anime/)[^"]*"[^>]*aria-label="'
            r'([^"]{4,60})"', дом)
        подписи += re.findall(
            r'<a[^>]*aria-label="([^"]{4,60})"[^>]*href="(?:/title/|/anime/)',
            дом)
        источник = "aria-label карточки"
    if not подписи:
        подписи = re.findall(
            r'href\\":\\"/(?:title|anime)/[^"\\]+\\"[^}]{0,400}?'
            r'aria-label\\":\\"([^"\\]{4,60})\\"', дом)
        источник = "aria-label карточки в дереве Next.js"
    for подпись in подписи:
        части = re.findall(r"[А-Яа-яЁё]{5,}", подпись)
        if части:
            return (части[0], источник)
    for адрес in карточки(дом):
        части = [ч for ч in адрес.strip("/").split("/")[-1].split("-")
                 if len(ч) >= 5 and ч.isalpha()]
        if части:
            return (части[0], "слово из слага")
    return ("", "")


def главная_проверка(домен: str) -> int:
    база = f"https://{домен}"
    плохо = 0
    дом, код = взять(f"{база}/")
    print(f"=== {домен}: главная {код}, карточек {len(карточки(дом))} "
          f"[{форма_карточек(дом)}]")

    # 1. Поиск — словом из СВОЕГО каталога, а не наугад.
    слово, откуда = слово_для_поиска(дом)
    if слово:
        # Две формы адреса, и обе встречаются в сети: у lords/zona/animego
        # поиск отвечает на `/search/?q=`, у yummy — только на `/search?q=`
        # (со слэшем отвечает 308, измерено 2026-10-18). Пробовать одну форму
        # значило бы записать «поиск пуст» там, где не тот адрес: именно эту
        # ложную находку такая проверка и выдала.
        for хвост in ("/search/?q=", "/search?q="):
            html, код = взять(f"{база}{хвост}{quote(слово)}")
            if код == "200":
                break
        найдено = len(карточки(html))
        плохо += найдено == 0
        print(f"  поиск «{слово}» ({откуда}, {хвост}): код {код}, "
              f"найдено {найдено}"
              f"{'  ← ПУСТО' if найдено == 0 else ''}")
    else:
        print("  поиск: слово для запроса из каталога не нашлось — не измерено")

    # 2. Фильтры: жанр и год.
    жанры = list(dict.fromkeys(
        re.findall(r'href="/(?:catalog/\?genre=|genre/)([^"&]+)"', дом)))[:3]
    все_карточки = set(карточки(взять(f"{база}/catalog/")[0]))
    if жанры:
        # Проверяются ДО ТРЁХ жанров, и вывод «не сужает» делается, только
        # если не сузил ни один. Измерено 2026-10-18: по одному жанру проба
        # назвала исправный фильтр сомнительным, потому что первым в ссылках
        # у аниме-витрины стоит `anime` — жанр, равный всему каталогу.
        сузил_хоть_один = False
        for жанр in жанры:
            html, код = взять(f"{база}/catalog/?genre={жанр}")
            отбор = set(карточки(html))
            сузил = bool(отбор) and отбор != все_карточки
            сузил_хоть_один = сузил_хоть_один or сузил
            print(f"  фильтр жанра «{жанр[:20]}»: код {код}, карточек "
                  f"{len(отбор)}, состав отличается от каталога: {сузил}")
        плохо += not сузил_хоть_один
        if not сузил_хоть_один:
            print(f"  ФИЛЬТР ЖАНРА НЕ СУЖАЕТ ни по одному из {len(жанры)} "
                  "проверенных жанров")
    год = re.search(r'href="/(?:catalog/\?year=|year/)(\d{4})', дом)
    if год:
        html, код = взять(f"{база}/catalog/?year={год.group(1)}")
        отбор = set(карточки(html))
        сузил = bool(отбор) and отбор != все_карточки
        плохо += not сузил
        print(f"  фильтр года {год.group(1)}: код {код}, карточек {len(отбор)}, "
              f"состав отличается: {сузил}")

    # 3. Пагинация: вторая страница не равна первой.
    первая = карточки(взять(f"{база}/catalog/")[0])
    html2, код2 = взять(f"{база}/catalog/?page=2")
    вторая = карточки(html2)
    разные = bool(вторая) and вторая != первая
    плохо += not разные
    print(f"  вторая страница каталога: код {код2}, карточек {len(вторая)}, "
          f"отличается от первой: {разные}")

    # 4. Страница произведения: плеер и серии.
    адрес = (первая or карточки(дом) or [""])[0]
    if адрес:
        html, код = взять(f"{база}{адрес}")
        есть_плеер = bool(re.search(r"<iframe|data-player|player", html, re.I))
        серии = len(re.findall(r'href="[^"]*episode[^"]*"', html))
        оценка_форма = len(re.findall(r'<form[^>]+action="[^"]*(?:vote|rate)', html))
        print(f"  произведение {адрес[:40]}: код {код}, плеер "
              f"{'есть' if есть_плеер else 'НЕТ'}, ссылок на серии {серии}, "
              f"форм оценки {оценка_форма}")
        # 5. Возможности аккаунта: ищем вход и избранное.
        вход = len(re.findall(r'href="[^"]*(?:login|signin|auth)', html, re.I))
        избранное = len(re.findall(r'(?:favou?rite|избранн)', текст(html), re.I))
        print(f"  аккаунт на странице: ссылок входа {вход}, упоминаний "
              f"избранного {избранное}")
    return плохо


def главная(аргв: list[str]) -> int:
    домены = аргв or ["lordfilm.group"]
    плохо = 0
    for д in домены:
        плохо += главная_проверка(д)
        print()
    print(f"сомнительных сценариев: {плохо}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
