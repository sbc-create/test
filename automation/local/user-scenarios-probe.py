#!/usr/bin/env python3
"""Пользовательские сценарии витрины: работает ли то, что выглядит рабочим.

Проверяются не кнопки, а СЦЕНАРИИ целиком — запрос, ответ, и там, где есть
сохранение, повторное чтение:

  поиск        форма шапки: своё слово из каталога даёт непустую выдачу;
  фильтры      /catalog/?genre=… и ?year=… меняют состав, а не возвращают всё;
  страницы     вторая страница каталога отличается от первой;
  произведение карточка открывается, у неё есть плеер и список серий;
  оценка       форма оценки существует и её отправка сохраняется (проверяется
               повторным чтением страницы);
  избранное    есть ли вообще такая возможность на витрине.

Отдельно отмечается «кнопка есть, действия нет»: форма или ссылка в разметке
при отсутствии обработчика.

    python3 automation/local/user-scenarios-probe.py lordfilm.group
"""
from __future__ import annotations

import re
import subprocess
import sys
from urllib.parse import quote


def взять(url: str, данные: str = "", куки: str = "") -> tuple[str, str]:
    арг = ["curl", "-sS", "--max-time", "45", "-w", "\n@@%{http_code}"]
    if куки:
        арг += ["-H", f"Cookie: {куки}"]
    if данные:
        арг += ["-X", "POST", "--data", данные]
    арг.append(url)
    п = subprocess.run(арг, capture_output=True, text=True)
    вывод = п.stdout or ""
    м = re.search(r"\n@@(\d+)$", вывод)
    return (вывод[:м.start()] if м else вывод), (м.group(1) if м else "0")


def текст(html: str) -> str:
    т = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", html)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", т))


def карточки(html: str) -> list[str]:
    return list(dict.fromkeys(re.findall(r'href="(/title/[^"]+)"', html)))


def главная_проверка(домен: str) -> int:
    база = f"https://{домен}"
    плохо = 0
    дом, код = взять(f"{база}/")
    print(f"=== {домен}: главная {код}, карточек {len(карточки(дом))}")

    # 1. Поиск — словом из СВОЕГО каталога, а не наугад.
    титулы = re.findall(r'<a class="[^"]*" href="/title/[^"]+" title="([^"]+)"', дом)
    слово = ""
    for т_ in титулы:
        части = [ч for ч in re.findall(r"[А-Яа-яЁё]{5,}", т_)]
        if части:
            слово = части[0]
            break
    if слово:
        html, код = взять(f"{база}/search/?q={quote(слово)}")
        найдено = len(карточки(html))
        плохо += найдено == 0
        print(f"  поиск «{слово}»: код {код}, найдено {найдено}"
              f"{'  ← ПУСТО' if найдено == 0 else ''}")
    else:
        print("  поиск: слово для запроса из каталога не нашлось — не измерено")

    # 2. Фильтры: жанр и год.
    жанр = re.search(r'href="/(?:catalog/\?genre=|genre/)([^"&]+)"', дом)
    все_карточки = set(карточки(взять(f"{база}/catalog/")[0]))
    if жанр:
        html, код = взять(f"{база}/catalog/?genre={жанр.group(1)}")
        отбор = set(карточки(html))
        сузил = bool(отбор) and отбор != все_карточки
        плохо += not сузил
        print(f"  фильтр жанра «{жанр.group(1)[:20]}»: код {код}, карточек "
              f"{len(отбор)}, состав отличается от каталога: {сузил}")
    год = re.search(r'href="/(?:catalog/\?year=|year/)(\d{4})', дом)
    if год:
        html, код = взять(f"{база}/catalog/?year={год.group(1)}")
        отбор = set(карточки(html))
        сузил = bool(отбор) and отбор != все_карточки
        плохо += not сузил
        print(f"  фильтр года {год.group(1)}: код {код}, карточек {len(отбор)}, "
              f"состав отличается: {сузил}")

    # 3. Пагинация: вторая страница не равна первой.
    первая = карточки(взять(f"{база}/catalog/")[0])
    html2, код2 = взять(f"{база}/catalog/?page=2")
    вторая = карточки(html2)
    разные = bool(вторая) and вторая != первая
    плохо += not разные
    print(f"  вторая страница каталога: код {код2}, карточек {len(вторая)}, "
          f"отличается от первой: {разные}")

    # 4. Страница произведения: плеер и серии.
    адрес = (первая or карточки(дом) or [""])[0]
    if адрес:
        html, код = взять(f"{база}{адрес}")
        есть_плеер = bool(re.search(r"<iframe|data-player|player", html, re.I))
        серии = len(re.findall(r'href="[^"]*episode[^"]*"', html))
        оценка_форма = len(re.findall(r'<form[^>]+action="[^"]*(?:vote|rate)', html))
        print(f"  произведение {адрес[:40]}: код {код}, плеер "
              f"{'есть' if есть_плеер else 'НЕТ'}, ссылок на серии {серии}, "
              f"форм оценки {оценка_форма}")
        # 5. Возможности аккаунта: ищем вход и избранное.
        вход = len(re.findall(r'href="[^"]*(?:login|signin|auth)', html, re.I))
        избранное = len(re.findall(r'(?:favou?rite|избранн)', текст(html), re.I))
        print(f"  аккаунт на странице: ссылок входа {вход}, упоминаний "
              f"избранного {избранное}")
    return плохо


def главная(аргв: list[str]) -> int:
    домены = аргв or ["lordfilm.group"]
    плохо = 0
    for д in домены:
        плохо += главная_проверка(д)
        print()
    print(f"сомнительных сценариев: {плохо}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
