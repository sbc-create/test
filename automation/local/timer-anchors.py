#!/usr/bin/env python3
"""Таймеры, которые способны застрять молча: якорь срабатывания и его отсутствие.

Повод не теоретический, он оплачен дважды.

1. `OnUnitActiveSec` считает от последней АКТИВАЦИИ службы. Если прогон убит
   сигналом, служба больше не активируется, следующий срок становится
   `infinity`, и таймер застревает НАВСЕГДА, числясь при этом `active`. Так
   ровно и вышло 2026-09-04 07:11: каталог не обновлялся сутки при «исправном»
   таймере. Лечение — `OnUnitInactiveSec`, якорь по ЗАВЕРШЕНИЮ.
2. Связка `OnBootSec` + `OnUnitActiveSec` без календаря на живой машине дала
   `NEXT: n/a`: момент загрузки давно прошёл, активации службы ещё не было, ни
   один источник времени следующей точки не дал. Поданная заявка пролежала
   необработанной, а таймер числился `enabled` и `active`. Лечение —
   `OnCalendar`, который считает от стенных часов.

Отсюда два проверяемых признака, и оба читаются из файла юнита:

* **нет якоря по завершению** — есть `OnUnitActiveSec`, нет `OnUnitInactiveSec`
  и нет `OnCalendar`: убитый прогон останавливает расписание;
* **нет якоря вовсе** — есть `OnBootSec` и `OnUnitActiveSec`, нет `OnCalendar`
  и нет `OnUnitInactiveSec`: расписание может не начаться совсем.

`systemctl list-timers` сказал бы то же короче, но он вне профиля сессии, а
файлы юнитов читаются. Поэтому инструмент читает файлы и их drop-in'ы, и
«не измерено» от «не задано» отличает так же, как `cell-resources.py`.

Только чтение.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ЮНИТЫ = Path("/etc/systemd/system")
#: Директивы расписания, которые решают, начнётся ли оно и продолжится ли.
ИСТОЧНИКИ = ("OnCalendar", "OnBootSec", "OnStartupSec",
             "OnUnitActiveSec", "OnUnitInactiveSec", "Persistent",
             "AccuracySec", "RandomizedDelaySec")
НЕ_ЗАДАН = "не задан"
НЕ_ИЗМЕРЕНО = "не измерено"
МЕТКА_НЕЧИТАЕМОГО = "#НЕЧИТАЕМЫЙ-DROPIN"


def строки_юнита(юнит: str, корень: Path) -> list[str] | None:
    основной = корень / юнит
    куски: list[str] = []
    try:
        куски.extend(основной.read_text(encoding="utf-8",
                                        errors="replace").splitlines())
    except OSError:
        return None
    каталог = корень / f"{юнит}.d"
    if каталог.is_dir():
        for конф in sorted(каталог.glob("*.conf")):
            try:
                куски.extend(конф.read_text(encoding="utf-8",
                                            errors="replace").splitlines())
            except OSError:
                куски.append(f"{МЕТКА_НЕЧИТАЕМОГО} {конф.name}")
    return куски


def директивы(строки: list[str] | None) -> dict[str, str]:
    """Последнее присваивание побеждает; пустое значение сбрасывает.

    Та же семантика, что у systemd, и по той же причине, что в
    `cell-resources.py`: drop-in, снимающий директиву, не должен читаться как
    директива на месте.
    """
    if строки is None:
        return {и: НЕ_ИЗМЕРЕНО for и in ИСТОЧНИКИ}
    есть_нечитаемый = any(с.startswith(МЕТКА_НЕЧИТАЕМОГО) for с in строки)
    итог: dict[str, str] = {}
    for сырая in строки:
        строка = сырая.strip()
        if not строка or строка.startswith(("#", ";")):
            continue
        for имя in ИСТОЧНИКИ:
            совпало = re.fullmatch(rf"{имя}\s*=\s*(.*)", строка)
            if совпало:
                значение = совпало.group(1).strip()
                if значение:
                    итог[имя] = значение
                else:
                    итог.pop(имя, None)
    по_умолчанию = НЕ_ИЗМЕРЕНО if есть_нечитаемый else НЕ_ЗАДАН
    return {и: итог.get(и, по_умолчанию) for и in ИСТОЧНИКИ}


def задано(значение: str) -> bool:
    return значение not in (НЕ_ЗАДАН, НЕ_ИЗМЕРЕНО)


def разобрать(юнит: str, знач: dict[str, str]) -> dict:
    # Юнит не прочитан вовсе — вердикта нет. Без этой ветки «не измерено»
    # давало беду «источника времени нет», то есть факт о сессии выдавался за
    # факт о таймере. Поймано собственным тестом, и правило то же, что в
    # cell-resources.py и sitemap-chain.py.
    if all(з == НЕ_ИЗМЕРЕНО for з in знач.values()):
        return {"юнит": юнит, "директивы": знач, "беды": [],
                "замечания": [], "не_измерено": True}
    календарь = задано(знач["OnCalendar"])
    активный = задано(знач["OnUnitActiveSec"])
    завершение = задано(знач["OnUnitInactiveSec"])
    загрузка = задано(знач["OnBootSec"]) or задано(знач["OnStartupSec"])
    беды: list[str] = []
    замечания: list[str] = []
    if активный and not завершение and not календарь:
        беды.append("нет якоря по завершению: убитый прогон останавливает "
                    "расписание НАВСЕГДА, и таймер при этом числится active "
                    "(OnUnitInactiveSec)")
    if not (календарь or активный or загрузка):
        беды.append("источника времени нет: таймер не запланирует ничего")
    # Ниже — именно ЗАМЕЧАНИЯ, а не поломки, и смешивать их с бедами нельзя.
    #
    # Связка OnBootSec + OnUnitActiveSec без календаря даёт `NEXT: n/a` при
    # ОДНОВРЕМЕННОМ выполнении двух условий: момент загрузки уже прошёл И
    # служба ещё ни разу не активировалась. У таймера, который давно
    # работает и свою службу запускал, следующий срок считается от последней
    # активации и находится. Поэтому это риск ВКЛЮЧЕНИЯ (таймер включили без
    # перезагрузки, служба ещё не запускалась), а не доказательство, что
    # расписание стоит. Называть его поломкой значило бы объявить сломанными
    # таймеры, которые на этой машине исправно наполняют каталоги.
    if загрузка and активный and not календарь:
        замечания.append("OnBootSec+OnUnitActiveSec без OnCalendar: при "
                         "включении таймера без перезагрузки и без ни одной "
                         "активации службы следующий срок не находится "
                         "(NEXT: n/a). Для уже работающего таймера это не "
                         "поломка — проверять надо при включении")
    if календарь and not задано(знач["Persistent"]):
        замечания.append("OnCalendar без Persistent: пропущенный из-за "
                         "перезагрузки прогон теряется")
    return {"юнит": юнит, "директивы": знач, "беды": беды,
            "замечания": замечания, "не_измерено": False}


def разбор(аргв=None):
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--units", type=Path, default=ЮНИТЫ,
                   help="каталог юнитов (по умолчанию /etc/systemd/system)")
    р.add_argument("--timer", action="append", default=[],
                   help="проверить только эти таймеры (можно повторять)")
    р.add_argument("--json", action="store_true")
    return р.parse_args(аргв)


def главное(аргв=None) -> int:
    опции = разбор(аргв)
    корень = опции.units
    if опции.timer:
        имена = [т if т.endswith(".timer") else f"{т}.timer"
                 for т in опции.timer]
    else:
        try:
            имена = sorted(п.name for п in корень.glob("*.timer"))
        except OSError as сбой:
            print(f"каталог юнитов не прочитан ({корень}): {сбой}",
                  file=sys.stderr)
            return 2
    if not имена:
        print(f"таймеров в {корень} не найдено", file=sys.stderr)
        return 2

    итоги = []
    for юнит in имена:
        строки = строки_юнита(юнит, корень)
        итоги.append(разобрать(юнит, директивы(строки)))

    if опции.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=2))
        return 1 if any(и["беды"] for и in итоги) else 0

    плохие = [и for и in итоги if и["беды"]]
    спорные = [и for и in итоги if и["замечания"] and not и["беды"]]
    немые = [и for и in итоги if и["не_измерено"]]
    print(f"таймеров прочитано: {len(итоги) - len(немые)}; "
          f"БЕЗ ЯКОРЯ ПО ЗАВЕРШЕНИЮ: {len(плохие)}; "
          f"только с замечаниями: {len(спорные)}"
          + (f"; НЕ ИЗМЕРЕНО (юнит не прочитан): {len(немые)}"
             if немые else ""))
    if немые:
        print("   " + " ".join(и["юнит"] for и in немые)
              + "\n   это факт о сессии, а не о таймере: вердикта по ним нет.")

    def печать(запись: dict, пометки: str) -> None:
        з = запись["директивы"]
        print(f"\n{запись['юнит']}")
        print(f"   OnCalendar={з['OnCalendar']}  "
              f"OnBootSec={з['OnBootSec']}  "
              f"OnUnitActiveSec={з['OnUnitActiveSec']}  "
              f"OnUnitInactiveSec={з['OnUnitInactiveSec']}  "
              f"Persistent={з['Persistent']}")
        for строка in запись[пометки]:
            print(f"   → {строка}")

    if плохие:
        print("\n=== ПОЛОМКА: убитый прогон останавливает расписание "
              "навсегда ===")
        for и in плохие:
            печать(и, "беды")
            for строка in и["замечания"]:
                print(f"   (замечание) {строка}")
    if спорные:
        print("\n=== ЗАМЕЧАНИЯ (не поломки): проверять при включении ===")
        for и in спорные:
            печать(и, "замечания")
    if not плохие:
        print("\nни один таймер не попадает в главную ловушку: у каждого есть "
              "якорь, который переживает убитый прогон.")
    # Ненулевой код только на поломке. Замечание кода не меняет: проверка,
    # которая падает на том, что проверять надо в другой момент, перестаёт
    # читаться — ровно это и записано решением D205.
    return 1 if плохие else 0


if __name__ == "__main__":
    raise SystemExit(главное())
