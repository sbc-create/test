#!/usr/bin/env python3
"""Чем полезен каждый оставшийся снимок — и полезен ли. Только чтение.

Уникальность изображения не основание хранить его бессрочно. Поэтому снимки
разделяются по ПОЛЬЗЕ, а не по весу, и у каждой группы своё решение.

Группы, в порядке проверки (первое совпадение и есть ответ):

  нужен проверке     на файл ссылается тест или инструмент в `tests/`,
                     `automation/` — удаление сломает проверку;
  визуальный эталон  путь говорит `baseline`, `эталон`, `golden`,
                     `reference`, `snapshot` — это мера, с которой сравнивают;
  доказательство     рядом или в документах есть ссылка, и названный
  открытого недостатка  недостаток НЕ закрыт в реестре;
  текущий релиз      каталог работающего релиза, кандидата, `previous` или
                     двух свежайших — их отдаёт витрина и ими откатываются;
  живая рабочая копия  копия линии, которая работает сейчас;
  есть текстовый     рядом лежит текстовый результат того же прогона
  результат          (json/txt/md с тем же основанием имени или в том же
                     каталоге) — изображение дублирует уже записанное;
  остаток завершённой  ни одно из условий выше не выполнено.
  работы

ЧЕГО ИНСТРУМЕНТ НЕ РЕШАЕТ. Он не судит, достаточно ли текстового результата
вместо внешнего вида: «есть текстовый результат» означает только, что текст
существует. Внешний вид страницы текстом не заменяется, и для группы с
текстовым результатом решение принимает человек.

    python3 automation/local/screenshot-value-census.py --list файл.tsv --csv out.csv

Коды: 0 — разобрано, 2 — опись не прочитана.
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import os
import pathlib
import re
import sys
import time

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "seo-module-defects.json"

ЭТАЛОН = ("baseline", "эталон", "golden", "reference", "snapshot", "/ref/")
#: Признаки РЯДА состояний одной страницы: по ним снимок полезен в паре, и
#: удаление половины ряда делает бесполезной вторую. Найдено осмотром остатка
#: 23.10: `animedia-dev/shots/{before-dev,h3,h4,after-full,final}`.
СРАВНЕНИЕ = ("/before", "/after", "before-", "after-", "/до-", "/после-",
             "-before", "-after", "/final/", "/was/", "/now/")
#: Копии, которыми откатываются: лежат рядом с работающей, а не в `releases/`.
ОТКАТНЫЕ = (".prev/", "-prev/", "/previous/", ".bak/", "/rollback/")
#: Выгрузки проверок сборки: на них ссылаются разборы, и они не «остаток».
ПРОВЕРКИ_СБОРКИ = ("/checks/", "/build-", "/qa/", "/acceptance/")
#: Каталоги РАБОТАЮЩЕГО приложения рядом с релизами: отчёт в `app/` отдаёт
#: работающая копия, а не прошлый релиз.
РАБОТАЮЩЕЕ_ПРИЛОЖЕНИЕ = ("/app/", "/current/", "/.frontend/")
#: Изображения шаблонов сайта — оформление, а не снимки приёмки.
РЕСУРС_ШАБЛОНА = ("/templates/", "/brand/", "/public/", "/static/",
                  "/assets/")
#: Не снимки вовсе: данные приложений пользователя.
НЕ_СНИМКИ = ("/.local/share/", "/.cache/", "/.config/",
             "/node_modules/", "/site-packages/", "/.venv/")
#: Вход проверки. Имя фикстуры может не встречаться в тестах этой копии —
#: например когда она лежит в постоянной копии репозитория, — поэтому признак
#: по имени файла нужен отдельно от признака «упомянут в коде».
ФИКСТУРА = ("fixture", "фикстур", "/media/", "testdata", "test-data")
#: Каталоги отчётов: снимок там — часть отчёта, а не остаток.
ОТЧЁТЫ = ("/reports/", "/отчёт", "/report-")
#: Рабочие копии живых линий по ИМЕНИ: соседняя линия выпускает сейчас, а её
#: `.git` от сентября, поэтому признак по времени её не видит.
ЖИВЫЕ_ПО_ИМЕНИ = ("wt-nova-publish-memory-02", "wt-portable-site-cell-01",
                  "wt-lastmod")
ЗАКРЫТЫЕ_СОСТОЯНИЯ = ("implemented", "verified", "closed", "superseded")
ТЕКСТОВЫЕ = (".json", ".txt", ".md", ".log", ".csv", ".yaml", ".yml")
ВОЗРАСТ_ЖИВОЙ_СУТОК = 7


def открытые_недостатки() -> set[str]:
    try:
        д = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    except OSError:
        return set()
    return {з["id"] for з in д.get("defects", [])
            if str(з.get("state", "")).lower() not in ЗАКРЫТЫЕ_СОСТОЯНИЯ}


def ссылки_на_снимки(корни: list[str]) -> set[str]:
    """Имена файлов изображений, упомянутые в коде проверок и документах."""
    упомянуто: set[str] = set()
    шаблон = re.compile(r'[\w./-]+\.(?:png|jpe?g|webp|gif|avif)')
    for корень in корни:
        for каталог, подкаталоги, файлы in os.walk(корень,
                                                   onerror=lambda _: None):
            подкаталоги[:] = [п for п in подкаталоги
                              if п not in (".git", "node_modules", ".next",
                                           "__pycache__", ".pytest_cache")]
            for имя in файлы:
                if not имя.endswith((".py", ".sh", ".md", ".json", ".yaml",
                                     ".yml", ".txt")):
                    continue
                try:
                    т = pathlib.Path(каталог, имя).read_text(
                        encoding="utf-8", errors="replace")
                except OSError:
                    continue
                for м in шаблон.findall(т):
                    упомянуто.add(os.path.basename(м))
    return упомянуто


def защищённые_релизы(пути: list[str]) -> dict[str, set[str]]:
    сайты: dict[str, set[str]] = collections.defaultdict(set)
    for п in пути:
        if "/releases/" not in п:
            continue
        корень, остаток = п.split("/releases/", 1)
        сайты[корень].add(остаток.split("/", 1)[0])
    итог: dict[str, set[str]] = {}
    for корень, релизы in сайты.items():
        щит = set()
        for имя in ("current", "candidate", "previous", "last-good"):
            цель = os.path.realpath(os.path.join(корень, имя))
            if "/releases/" in цель:
                щит.add(цель.split("/releases/", 1)[1].split("/", 1)[0])
        времена = []
        for р in релизы:
            try:
                времена.append((os.path.getmtime(
                    os.path.join(корень, "releases", р)), р))
            except OSError:
                continue
        времена.sort(reverse=True)
        щит.update(р for _, р in времена[:2])
        итог[корень] = щит
    return итог


def живые_копии() -> set[str]:
    """Рабочие копии, которые трогали за последние сутки-неделю, и своя."""
    порог = time.time() - ВОЗРАСТ_ЖИВОЙ_СУТОК * 86400
    живые = {КОРЕНЬ.as_posix()}
    for путь in pathlib.Path("/home/claude").glob("wt-*"):
        try:
            свежо = путь.stat().st_mtime > порог
            гит = путь / ".git"
            если = гит.exists() and гит.stat().st_mtime > порог
        except OSError:
            continue
        if свежо or если:
            живые.add(путь.as_posix())
    return живые


def есть_текстовый_рядом(путь: str) -> str:
    """Имя текстового файла того же прогона, если он есть рядом."""
    каталог = os.path.dirname(путь)
    основа = os.path.splitext(os.path.basename(путь))[0]
    try:
        рядом = os.listdir(каталог)
    except OSError:
        return ""
    for имя in рядом:
        если_основа = os.path.splitext(имя)[0]
        if имя.endswith(ТЕКСТОВЫЕ) and (если_основа == основа
                                        or основа.startswith(если_основа)):
            return имя
    for имя in рядом:
        if имя.endswith(ТЕКСТОВЫЕ):
            return имя
    return ""


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--list", dest="перечень", required=True)
    р.add_argument("--csv", default="")
    а = р.parse_args(аргв)

    try:
        строки = pathlib.Path(а.перечень).read_text(
            encoding="utf-8", errors="replace").splitlines()
    except OSError as сбой:
        print(f"НЕ ИЗМЕРЕНО: опись не прочитана: {сбой}")
        return 2

    файлы: list[tuple[int, str]] = []
    for с in строки:
        if "\t" not in с:
            continue
        размер, путь = с.split("\t", 1)
        try:
            файлы.append((int(размер), путь))
        except ValueError:
            continue
    if not файлы:
        print("НЕ ИЗМЕРЕНО: в описи нет строк")
        return 2

    упомянуто = ссылки_на_снимки([
        (КОРЕНЬ / "tests").as_posix(), (КОРЕНЬ / "automation").as_posix(),
        (КОРЕНЬ / "docs").as_posix(), (КОРЕНЬ / "config").as_posix(),
        "/srv/site-factory/repo/docs"])
    открытые = открытые_недостатки()
    щиты = защищённые_релизы([п for _, п in файлы])
    живые = живые_копии()

    итог: list[dict] = []
    for размер, путь in файлы:
        низкий = путь.lower()
        имя = os.path.basename(путь)
        группа = ""
        почему = ""
        if any(с in путь for с in НЕ_СНИМКИ):
            группа, почему = ("не снимок приёмки",
                              "данные приложений или сторонняя библиотека")
        elif any(с in низкий for с in ФИКСТУРА):
            группа, почему = ("фикстура проверки",
                              "вход проверки: удаление ломает проверку")
        elif any(с in низкий for с in ОТЧЁТЫ):
            группа, почему = ("часть отчёта",
                              "лежит в каталоге отчёта")
        elif any(с in низкий for с in РЕСУРС_ШАБЛОНА):
            группа, почему = ("ресурс шаблона",
                              "оформление сайта, а не снимок приёмки")
        elif any(f"/{и}/" in путь for и in ЖИВЫЕ_ПО_ИМЕНИ):
            группа, почему = ("живая рабочая копия",
                              "линия работает сейчас (список по имени)")
        elif any(с in путь for с in РАБОТАЮЩЕЕ_ПРИЛОЖЕНИЕ):
            группа, почему = ("работающее приложение",
                              "каталог работающей копии, а не прошлый релиз")
        if группа:
            итог.append({"путь": путь, "байт": размер, "группа": группа,
                         "почему": почему})
            continue
        if имя in упомянуто:
            группа, почему = "нужен проверке", "упомянут в коде или документах"
        elif any(с in низкий for с in ЭТАЛОН):
            группа, почему = "визуальный эталон", "путь называет эталон"
        elif any(с in низкий for с in ОТКАТНЫЕ):
            группа, почему = ("откатная копия",
                              "копия, которой откатываются")
        elif any(с in низкий for с in СРАВНЕНИЕ):
            группа, почему = ("сравнение до/после",
                              "ряд состояний одной страницы: половина ряда"
                              " бесполезна без другой")
        elif any(с in низкий for с in ПРОВЕРКИ_СБОРКИ):
            группа, почему = ("артефакт проверки сборки",
                              "выгрузка проверки, на неё ссылается разбор")
        elif "/releases/" in путь:
            корень, остаток = путь.split("/releases/", 1)
            релиз = остаток.split("/", 1)[0]
            if релиз in щиты.get(корень, set()):
                группа, почему = ("текущий релиз",
                                  "работающий релиз, кандидат или откат")
        if not группа and any(путь.startswith(ж + "/") for ж in живые):
            группа, почему = "живая рабочая копия", "линия работает сейчас"
        if not группа:
            недостатки = [и for и in открытые if и.lower() in низкий]
            if недостатки:
                группа = "доказательство открытого недостатка"
                почему = f"путь называет {', '.join(недостатки[:3])}"
        if not группа:
            текст = есть_текстовый_рядом(путь)
            if текст:
                группа = "есть текстовый результат"
                почему = f"рядом {текст}"
        if not группа:
            группа, почему = ("остаток завершённой работы",
                              "ни одно условие пользы не выполнено")
        итог.append({"путь": путь, "байт": размер, "группа": группа,
                     "почему": почему})

    по_группе = collections.Counter()
    байт_группы = collections.Counter()
    for з in итог:
        по_группе[з["группа"]] += 1
        байт_группы[з["группа"]] += з["байт"]

    print(f"снимков {len(итог)}, объём {sum(б for б, _ in файлы)/2**20:.1f} МиБ")
    print(f"\n{'файлов':>7} {'МиБ':>9}  группа")
    for г, n in по_группе.most_common():
        print(f"{n:7} {байт_группы[г]/2**20:9.1f}  {г}")

    if а.csv:
        with open(а.csv, "w", newline="", encoding="utf-8") as ф:
            з = csv.DictWriter(ф, fieldnames=["путь", "байт", "группа",
                                              "почему"])
            з.writeheader()
            for с in итог:
                з.writerow(с)
        print(f"\nCSV: {а.csv} — строк {len(итог)}")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
