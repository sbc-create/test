#!/usr/bin/env python3
"""Сверка имён из текста с ЗАПИСАННЫМИ источниками черновика.

Зачем. Рецензия (MOD-173) требует «посторонних вставок нет», а автоматическая
проверка в `review-materials-batch.py` этого сама подтвердить не может: она
видит только запись каталога и слаг, внешних источников не открывает и прямо
об этом говорит. Поэтому каждый материал с именами персонажей, актёров или мест
уходил в «нужна сверка по внешнему источнику» и ждал ручной работы.

Что делает этот инструмент. Берёт источники ИЗ САМОГО черновика (поле
`sources`), читает их штатным путём (`source_fetch.py`: robots, своё имя,
не чаще 4 запросов в секунду) и ищет каждое отмеченное имя в ответе.

Три свойства, без которых сверка была бы видимостью работы:

* **падежи.** Сравнение идёт по ОСНОВЕ слова: источник пишет «Кошачьего
  Франциско», текст — «Кошачий Франциско»; «Тёмной триады» против «Тёмная».
  Побуквенное совпадение дало бы «не найдено» там, где источник прямо это
  называет (проверено 25.10 на четырёх материалах: три «не найдено» из четырёх
  оказались падежами);
* **письменность.** Для англоязычного источника русское имя подтверждается
  латинским написанием, и соответствие печатается явно: «Алисса (как Alyssa)».
  Соответствие задаётся парами в `--latin`, а не угадывается;
* **фрагмент.** Для каждого подтверждённого имени печатается кусок источника,
  в котором оно найдено. Подтверждение без фрагмента неотличимо от
  подтверждения по совпадению букв в другом слове.

Выход в формате `--external-verified` для `review-materials-batch.py`.

    python3 automation/local/names-against-sources.py --slug holodnaya-reka \
        --latin Алисса=Alyssa --latin Кэмпбелл=Campbell \
        --json artifacts/evidence/names-20261025.json
"""
from __future__ import annotations

import argparse
import datetime as dt
import glob
import json
import pathlib
import os
import re
import subprocess
import sys
import urllib.parse

ХРАНИЛИЩА = "/srv/sites/*/runtime/overlays/*/drafts.json"
#: Паспорт ячеек СВОЕЙ ветки: он отвечает на вопрос «чей это адрес».
ПАСПОРТ = pathlib.Path(os.environ.get("SITE_CELLS_PATH")
                       or pathlib.Path(__file__).resolve().parents[2]
                       / "config" / "site-cells.json")
ИНСТРУМЕНТ = pathlib.Path(__file__).resolve().parent / "source_fetch.py"
#: Окончания, отбрасываемые при сравнении основ. Список закрытый и назван:
#: «умное» морфологическое приведение без словаря даёт ложные совпадения.
ОКОНЧАНИЯ = ("ого", "его", "ому", "ему", "ыми", "ими", "ей", "ой", "ом", "ем",
             "ах", "ях", "ам", "ям", "ов", "ев", "ую", "юю", "ая", "яя", "ые",
             "ие", "ью", "ия", "ии", "а", "я", "ы", "и", "у", "ю", "е", "о",
             "ь", "й")
#: Остаток основы после отбрасывания окончания и минимальная длина имени,
#: которому сравнение по основе вообще разрешено. Два предела, а не один:
#: «Асты» (4 знака) обязано совпасть с «Аста», а «Ас» (2 знака) — нет, иначе
#: основа совпадёт почти с чем угодно («астрономия»).
МИН_ОСНОВА = 3
МИН_ИМЯ = 4
#: Японские имена в русских источниках пишут двумя системами, и обе законны:
#: Поливанов («Синъити», «Тиба», «Дзиро») и практическая запись с английского
#: («Шиничи», «Чиба», «Джиро»). Измерено 25.10: черновик писал «Синъити», а
#: записанный источник — «Конаном / Шиничи», и сверка объявила имя
#: неподтверждённым, хотя источник его называет. Таблица закрытая и названа:
#: приведение идёт к ОДНОЙ записи, и совпадение по ней помечается отдельно,
#: потому что это равенство систем, а не равенство букв.
ТРАНСЛИТЕРАЦИЯ = (("ши", "си"), ("щи", "си"), ("чи", "ти"), ("джи", "дзи"),
                  ("дж", "дз"), ("ё", "ьо"), ("ъ", ""), ("ь", ""))


def основа(слово: str) -> str:
    """Основа для сравнения: без окончания, без мягкого знака и конечного «и».

    Последний шаг нужен из-за пары «Кошачьего» → `кошачь` и «Кошачий» →
    `кошачи`: без него один и тот же корень давал две разные основы, и
    источник, прямо называющий имя, считался его не называющим.
    """
    #: «ё»→«е» и «э»→«е»: источник пишет «Бредфорде», черновик «Брэдфорда» —
    #: это разночтение транслитерации, а не другое имя.
    с = (слово or "").strip().lower().replace("ё", "е").replace("э", "е")
    for о in ОКОНЧАНИЯ:
        if len(с) - len(о) >= МИН_ОСНОВА and с.endswith(о):
            с = с[: len(с) - len(о)]
            break
    пока = с.rstrip("ьи")
    return пока if len(пока) >= МИН_ОСНОВА else с


def по_системам(слово: str) -> str:
    """Имя, приведённое к одной системе транслитерации."""
    с = (слово or "").strip().lower().replace("ё", "е")
    for было, стало in ТРАНСЛИТЕРАЦИЯ:
        с = с.replace(было, стало)
    return с


def слова(текст: str) -> list[str]:
    return re.findall(r"[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z\-']+", текст or "")


def найти_имя(имя: str, текст: str) -> tuple[bool, str, str]:
    """Подтверждено ли имя, каким фрагментом и по какому признаку.

    Три прохода, и каждый следующий слабее предыдущего, поэтому признак
    совпадения возвращается третьим значением и печатается:

    1. прямое вхождение по границе слова;
    2. совпадение ОСНОВ (падежи);
    3. совпадение по системам транслитерации («Шиничи» ≈ «Синъити»).

    Фрагмент возвращается всегда, когда подтверждение есть: без него нечего
    предъявить.
    """
    if not имя or не_текст(текст):
        return False, "", ""
    #: Прямое совпадение требует ГРАНИЦЫ слова: иначе «Ас» нашлось бы внутри
    #: «астрономия», и подтверждение означало бы совпадение букв.
    def фрагмент(начало: int, конец: int) -> str:
        а, б = max(0, начало - 60), min(len(текст), конец + 60)
        return текст[а:б].replace("\n", " ")

    м = re.search(r"\b" + re.escape(имя) + r"\b", текст, re.IGNORECASE)
    if not м and ("э" in имя.lower() or "ё" in имя.lower()):
        мягче = имя.lower().replace("ё", "е").replace("э", "е")
        for с in слова(текст):
            if с.lower().replace("ё", "е").replace("э", "е") == мягче:
                м = re.search(r"\b" + re.escape(с) + r"\b", текст)
                break
    if м:
        return True, фрагмент(м.start(), м.end()), "прямое вхождение"
    if len(имя.strip()) < МИН_ИМЯ:
        return False, "", ""
    цель = основа(имя)
    if len(цель) >= МИН_ОСНОВА:
        for с in слова(текст):
            if основа(с) == цель:
                место = текст.find(с)
                return True, фрагмент(место, место + len(с)), "основа слова"
    цель_с = основа(по_системам(имя))
    if len(цель_с) >= МИН_ОСНОВА:
        for с in слова(текст):
            if основа(по_системам(с)) == цель_с:
                место = текст.find(с)
                return (True, фрагмент(место, место + len(с)),
                        f"системы транслитерации: источник пишет «{с}»")
    return False, "", ""


def не_текст(текст: str) -> bool:
    return not текст


def черновик(слаг: str, домен: str = "") -> tuple[str, dict] | tuple[None, None]:
    for путь in sorted(glob.glob(ХРАНИЛИЩА)):
        д = pathlib.Path(путь).parent.name
        if домен and д != домен:
            continue
        данные = json.loads(pathlib.Path(путь).read_text(encoding="utf-8"))
        ч = (данные.get("items") or {}).get(слаг)
        if ч:
            return д, ч
    return None, None


_СНИМКИ: dict[str, dict] = {}


def запись_снимка(путь: pathlib.Path, слаг: str) -> tuple[str, str]:
    """Запись ОДНОГО произведения из снимка каталога, а не весь снимок.

    Измерено 25.10, и это чуть не стоило четырёх ложных подтверждений: снимок
    витрины — это 69 870 записей в одном файле, поэтому поиск имени по всему
    файлу подтверждал «Алиссу» описанием ДРУГОГО фильма, а «Кошачий» — фразой
    «кошачий слух» из третьего. Подтверждать имя чужой записью нельзя: сверка
    тогда проверяет лишь то, что имя встречается в русском языке.
    """
    #: Ключ кэша — строка: по `Path` он не совпадал с тем, чем кладётся, и
    #: снимок на 95 МБ разбирался заново для каждого материала.
    if str(путь) not in _СНИМКИ:
        try:
            _СНИМКИ[str(путь)] = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, ValueError) as ош:
            return "", f"снимок не прочитан: {type(ош).__name__}"
    д = _СНИМКИ.get(str(путь)) or {}
    записи = д.get("details") or д.get("items") or д
    з = записи.get(слаг) if isinstance(записи, dict) else None
    if з is None:
        return "", (f"в снимке нет записи {слаг!r}: подтверждать имя чужими"
                    " записями нельзя")
    return json.dumps(з, ensure_ascii=False), ""


def прочитать_источник(адрес: str, слаг: str = "",
                       таймаут: int = 180) -> tuple[str, str]:
    """Текст источника и причина отказа. Читается ТОЛЬКО штатным путём."""
    if адрес.startswith("snapshot:") or адрес.startswith("/"):
        п = pathlib.Path(адрес.replace("snapshot:", "", 1))
        if not п.is_file():
            return "", f"снимка нет: {п}"
        return запись_снимка(п, слаг)
    м = re.search(r"shikimori\.(?:io|one)/animes/(\d+)", адрес)
    команда = ([sys.executable, str(ИНСТРУМЕНТ), "shikimori", м.group(1)] if м
               else [sys.executable, str(ИНСТРУМЕНТ), "page", адрес])
    г = subprocess.run(команда, capture_output=True, text=True, timeout=таймаут)
    if г.returncode != 0:
        return "", f"источник не прочитан: {(г.stderr or '').strip()[-160:]}"
    try:
        д = json.loads(г.stdout)
    except ValueError:
        return "", "ответ источника не JSON"
    if not д.get("ok", True):
        return "", f"источник отказал: {str(д.get('error'))[:120]}"
    return json.dumps(д, ensure_ascii=False), ""


#: Карточка Shikimori и её РАЗДЕЛ АВТОРСТВА — два разных ответа одного
#: источника. Измерено 25.10: имена авторов манги (Тацуо Ёсида, Цукаса Ходзё,
#: Тэцухиро Косита) в описании карточки не встречаются вовсе, а в ответе
#: `credits` того же произведения стоят прямо (`original_creators[].person_ru`).
#: Поэтому сверка, читавшая только карточку, объявляла их неподтверждёнными —
#: и подтверждались они нашей же страницей, то есть собой. Читать надо оба
#: ответа: это один разрешённый путь (`source_fetch.py`) и один источник.
ОТВЕТЫ_SHIKIMORI = ("shikimori", "credits")


def источники_произведения(адрес: str, слаг: str = "",
                           таймаут: int = 180) -> tuple[list, list]:
    """Все тексты ОДНОГО записанного источника: (тексты, отказы).

    Для Shikimori это карточка и раздел авторства; для остальных адресов —
    один текст, как было. Адрес раздела авторства помечается якорем
    `#credits`, чтобы в доказательстве было видно, ЧЕМ подтверждено имя.
    """
    м = re.search(r"shikimori\.(?:io|one)/animes/(\d+)", адрес)
    if not м:
        т, причина = прочитать_источник(адрес, слаг, таймаут)
        return ([(адрес, т)] if т else []), ([] if т else [(адрес, причина)])
    тексты, отказы = [], []
    for ответ in ОТВЕТЫ_SHIKIMORI:
        г = subprocess.run([sys.executable, str(ИНСТРУМЕНТ), ответ, м.group(1)],
                           capture_output=True, text=True, timeout=таймаут)
        пометка = адрес if ответ == "shikimori" else f"{адрес}#credits"
        if г.returncode != 0:
            отказы.append((пометка, f"источник не прочитан:"
                                    f" {(г.stderr or '').strip()[-120:]}"))
            continue
        try:
            д = json.loads(г.stdout)
        except ValueError:
            отказы.append((пометка, "ответ источника не JSON"))
            continue
        if not д.get("ok", True):
            отказы.append((пометка, f"источник отказал: {str(д.get('error'))[:100]}"))
            continue
        тексты.append((пометка, json.dumps(д, ensure_ascii=False)))
    return тексты, отказы


def наши_домены(паспорт: pathlib.Path | None = None) -> set[str]:
    """Домены сети — то есть источники, которые подтверждением не считаются.

    Берутся из паспорта ячеек, а не перечисляются в коде: перечень сети
    меняется выпусками, и список в коде устарел бы молча.
    """
    п = pathlib.Path(паспорт or ПАСПОРТ)
    try:
        данные = json.loads(п.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    итог = set()
    for я in данные.get("cells") or []:
        for поле in ("domain",):
            если = (я.get(поле) or "").strip().lower()
            if если:
                итог.add(если)
        for псевдо in я.get("aliases") or []:
            если = str(псевдо).strip().lower()
            if если:
                итог.add(если)
    return итог


def внешний_источник(адрес: str, наши: set[str]) -> bool:
    """Внешний ли это источник по отношению к нашей сети.

    ЗАЧЕМ. В `sources` черновика витрина записывает и СВОЮ страницу. Текст
    черновика на ней часто уже стоит (измерено 25.10 на
    `zonafilm12.site/bratya-gonschiki-lets-i-gou`: живое описание страницы
    дословно начинается текстом черновика), поэтому имя «подтверждается» тем
    самым текстом, который проверяется. То же верно для витрины-СЕСТРЫ: один
    редакционный текст расходится по сети. Подтверждение собой — не
    подтверждение.
    """
    узел = (urllib.parse.urlsplit(адрес).hostname or "").lower()
    if узел.startswith("www."):
        узел = узел[4:]
    if not узел:
        return False
    return узел not in {д.lower() for д in наши}


def подтвердить_имя(имя: str, тексты, латиница: dict, наши: set[str]) -> dict:
    """Статус имени: подтверждено внешним источником, только своим, или нет.

    Внешние источники опрашиваются ПЕРВЫМИ, и внешнее подтверждение сильнее
    своего: если имя есть и там и там, подтверждением считается внешнее.
    """
    по_порядку = ([(а, т) for а, т in тексты if внешний_источник(а, наши)]
                  + [(а, т) for а, т in тексты if not внешний_источник(а, наши)])
    for адрес, текст in по_порядку:
        есть, фр, признак = найти_имя(имя, текст)
        if not есть and латиница.get(имя):
            есть, фр, признак = найти_имя(латиница[имя], текст)
        if есть:
            return {"статус": "внешний" if внешний_источник(адрес, наши) else "свой",
                    "фрагмент": фр, "признак": признак, "адрес": адрес}
    return {"статус": "нет", "фрагмент": "", "признак": "", "адрес": ""}


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--slug", action="append", required=True)
    р.add_argument("--domain", default="")
    р.add_argument("--name", action="append", default=[],
                   help="имя для сверки; по умолчанию берутся отмеченные "
                        "проверкой материала")
    р.add_argument("--latin", action="append", default=[],
                   help="соответствие письменностей: Алисса=Alyssa")
    р.add_argument("--json", type=pathlib.Path)
    р.add_argument("--extra-source", action="append", default=[],
                   help="РАЗРЕШЁННЫЙ источник, которого ещё нет в черновике."
                        " Читается тем же штатным путём и помечается в"
                        " доказательстве отдельно: подтверждение им законно, но"
                        " провенанс черновика неполон, и это должно быть видно")
    а = р.parse_args(аргв)
    латиница = dict(п.split("=", 1) for п in а.latin if "=" in п)

    #: Отмеченные имена берутся у той же проверки, что требует их сверки, —
    #: иначе сверяется один список, а принимает решение другой.
    import importlib.util
    спец = importlib.util.spec_from_file_location(
        "rmb", pathlib.Path(__file__).resolve().parent / "review-materials-batch.py")
    ПАЧКА = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(ПАЧКА)

    итог = {"method": ("source_fetch.py по источникам, записанным в черновике;"
                       " сравнение по основе слова; для англоязычного источника"
                       " соответствие письменностей задано парами --latin"),
            "at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "results": []}
    код = 0
    наши = наши_домены()
    for слаг in а.slug:
        домен, ч = черновик(слаг, а.domain)
        if not ч:
            print(f"{слаг}: черновика нет")
            код = 2
            continue
        записи = ПАЧКА.опора({слаг})
        проверка = ПАЧКА.проверить({**ч, "домен": домен, "slug": слаг},
                                   записи.get(слаг) or {})
        имена = а.name or проверка.get("_посторонние") or []
        источники = [и for и in (ч.get("sources") or []) if str(и).strip()]
        print(f"=== {домен} / {слаг}")
        print(f"    источников {len(источники)}, имён к сверке {len(имена)}")
        if not источники:
            print("    НЕ ИЗМЕРЕНО: у черновика не записано ни одного источника")
            итог["results"].append({"domain": домен, "slug": слаг,
                                    "confirmed": [], "not_found": list(имена),
                                    "note": "источников не записано"})
            код = код or 1
            continue
        тексты, отказы = [], []
        for и in источники:
            т_, о_ = источники_произведения(и, слаг)
            тексты.extend(т_)
            отказы.extend(о_)
        # Источники, названные флагом, читаются ТЕМ ЖЕ путём и складываются в
        # отдельный список: в доказательстве должно быть видно, что подтверждение
        # пришло не из записанных источников черновика. Иначе неполный провенанс
        # исчезнет из записи вместе с поводом его исправить.
        добавленные = []
        for и in (а.extra_source or []):
            т_, о_ = источники_произведения(и, слаг)
            тексты.extend(т_)
            отказы.extend(о_)
            добавленные.extend(а_ for а_, _ in т_)
        if отказы:
            for и, п_ in отказы:
                print(f"    источник не дал текста: {и} — {п_}")
        подтв, нет, свои, фрагменты, чем = [], [], [], {}, {}
        внешних = sum(1 for а, _ in тексты if внешний_источник(а, наши))
        print(f"    источников с текстом {len(тексты)}, из них внешних {внешних}")
        for имя in имена:
            и = подтвердить_имя(имя, тексты, латиница, наши)
            как = имя
            if (и["статус"] != "нет" and и["фрагмент"] and латиница.get(имя)
                    and имя.lower() not in и["фрагмент"].lower()):
                как = f"{имя} (как «{латиница[имя]}»)"
            если = (как if и["признак"] in ("прямое вхождение", "")
                    else f"{как} [{и['признак']}]")
            if и["статус"] == "внешний":
                подтв.append(если)
            elif и["статус"] == "свой":
                # Имя нашлось ТОЛЬКО на странице нашей же сети. Это не
                # подтверждение, а эхо проверяемого текста, и в `confirmed` оно
                # не попадает: иначе рецензия ссылалась бы на саму себя.
                свои.append(если)
            else:
                нет.append(имя)
                continue
            фрагменты[если] = и["фрагмент"][:180]
            чем[если] = и["адрес"]
        if добавленные:
            print(f"    ДОБАВЛЕННЫЕ ИСТОЧНИКИ (в черновике их НЕТ):"
                  f" {', '.join(добавленные)}")
            print("        подтверждение ими законно, но провенанс черновика"
                  " неполон — источник надо дозаписать")
        for к in подтв:
            print(f"    подтверждено: {к}")
            print(f"        источник: {чем[к]}")
            print(f"        …{фрагменты[к]}…")
        for к in свои:
            print(f"    НЕ ПОДТВЕРЖДЕНО ВНЕШНИМ: {к} — найдено только на нашей"
                  f" же странице {чем[к]}")
            print(f"        …{фрагменты[к]}…")
            print("        это эхо проверяемого текста, а не независимый источник")
        for к in нет:
            print(f"    НЕ НАЙДЕНО: {к}")
        итог["results"].append({
            "domain": домен, "slug": слаг, "sources": источники,
            "extra_sources_not_in_draft": добавленные,
            "external_sources_with_text": внешних,
            "unreadable_sources": [{"url": и, "reason": п_} for и, п_ in отказы],
            "confirmed": подтв, "not_found": нет,
            "own_network_only": свои, "fragments": фрагменты,
            "confirmed_by": чем})
        if нет or свои:
            код = код or 1
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        а.json.write_text(json.dumps(итог, ensure_ascii=False, indent=1),
                          encoding="utf-8")
        print(f"\nсверка записана: {а.json}")
    всего = sum(len(з["confirmed"]) + len(з["not_found"])
                + len(з.get("own_network_only") or []) for з in итог["results"])
    подтверждено = sum(len(з["confirmed"]) for з in итог["results"])
    свои_всего = sum(len(з.get("own_network_only") or []) for з in итог["results"])
    не_найдено = sum(len(з["not_found"]) for з in итог["results"])
    print(f"\nимён сверено {всего}; подтверждено ВНЕШНИМ источником"
          f" {подтверждено}; найдено только на своей странице {свои_всего};"
          f" не найдено {не_найдено}")
    if свои_всего:
        print("  «только на своей странице» подтверждением не считается:"
              " это тот же текст, который проверяется")
    return код


