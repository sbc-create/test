def прочитать_прежние(каталог: str | os.PathLike[str]) -> dict[str, bytes]:
    """Уже записанный набор карты. ТОЛЬКО ЧТЕНИЕ.

    Каталог карты — постоянные данные витрины: его пишет сама служба, и правка
    его не трогает. Нечитаемый или отсутствующий файл равен «прежнего нет»:
    тогда часть получает дату по максимуму внутри, а не время сборки.
    """
    цель = pathlib.Path(каталог)
    набор: dict[str, bytes] = {}
    if not цель.is_dir():
        return набор
    for файл in цель.glob("sitemap*.xml"):
        try:
            набор[файл.name] = файл.read_bytes()
        except OSError:
            continue
    return набор


def _разложить_устойчиво(
        адреса: list[tuple[str, str]],
        прежние: dict[str, bytes]) -> list[list[tuple[str, str]]]:
    """Разложить адреса по частям так, чтобы пополнение не сдвигало границы.

    Прежняя нарезка шла подряд по `ПРЕДЕЛ_URL` от начала списка,
    отсортированного по дате по убыванию: одна новая карточка сверху сдвигала
    границы ВСЕХ частей, и менялись все файлы, а не один. Здесь каждый адрес,
    уже записанный в часть, в ней и остаётся; исчезнувшие вычёркиваются; новые
    дописываются в хвост последней части, а когда она полна — новой частью.

    Часть, из которой адреса удалили, остаётся недозаполненной намеренно:
    «сжать» её можно только сдвигом, то есть ровно тем, от чего правка избавляет.
    """
    дата_по_адресу = dict(адреса)
    порядок = [а for а, _ in адреса]
    if not прежние:
        подряд = [порядок[i:i + ПРЕДЕЛ_URL]
                  for i in range(0, len(порядок), ПРЕДЕЛ_URL)] or [[]]
        return [[(а, дата_по_адресу[а]) for а in ч] for ч in подряд]
    номера = sorted(
        (int(м.group(1)), имя) for имя, м in
        ((имя, re.fullmatch(r"sitemap-(\\d+)\\.xml", имя)) for имя in прежние)
        if м)
    части: list[list[str]] = []
    размещены: set[str] = set()
    for _, имя in номера:
        остались = [а for а in _адреса_части(прежние[имя])
                    if а in дата_по_адресу and а not in размещены]
        размещены.update(остались)
        части.append(остались)
    if not части:
        части = [[]]
    for а in порядок:
        if а in размещены:
            continue
        if len(части[-1]) >= ПРЕДЕЛ_URL:
            части.append([])
        части[-1].append(а)
    return [[(а, дата_по_адресу[а]) for а in ч] for ч in части]


