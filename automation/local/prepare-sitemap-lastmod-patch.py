def переписать(текст: str) -> str:
    """Собрать редакцию 2 из любого из двух состояний источника.

    Участок заменяется ЦЕЛИКОМ — от начала сборки частей до записи индекса в
    набор. Склейка хвостов прежнего блока дала бы патч, который зависит от того,
    что в этом хвосте стояло, а стоит там в двух состояниях разное.
    """
    if "_разложить_устойчиво" in текст:
        raise SystemExit("в установленном файле редакция 2 УЖЕ есть — патч не нужен")
    if ЯКОРЬ_ПОДПИСИ not in текст:
        raise SystemExit("подпись `построить_sitemap` не найдена: источник"
                         " изменился. Патч собирать заново, а не подгонять.")
    редакция1 = "даты_частей" in текст
    якорь = ЯКОРЬ_РЕД1 if редакция1 else ЯКОРЬ_БЕЗ_ПРАВКИ
    сколько = текст.count(якорь)
    if сколько != 1:
        raise SystemExit(
            f"якорь встречается {сколько} раз вместо одного: установленный файл"
            " изменился. Патч собирать заново, а не подгонять по похожим местам.")
    начало = текст.index(якорь)
    хвост = '    файлы.append(("sitemap.xml",'
    if текст.count(хвост) != 1:
        raise SystemExit("запись индекса в набор встречается не один раз:"
                         " патч собирать заново.")
    конец = текст.index(хвост, начало)
    текст = текст[:начало] + БЛОК_РЕД2 + "\n" + текст[конец:]
    текст = текст.replace(ЯКОРЬ_ПОДПИСИ, ПОДПИСЬ_РЕД2, 1)
    сколько_вызовов = текст.count(ЯКОРЬ_ВЫЗОВА)
    if сколько_вызовов > 1:
        raise SystemExit(
            f"вызов сборщика встречается {сколько_вызовов} раз: патч не знает,"
            " какому передать прежний набор. Собирать заново.")
    if сколько_вызовов == 0:
        # Витрина, где карту собирает не этот файл (измерено на animedia.icu).
        # Правка сборщика всё равно нужна и безопасна: без прежнего набора он
        # ведёт себя как при первой записи — максимум дат внутри, никогда не
        # время сборки. Передачу набора делает тот, кто его вызывает.
        return текст
    return текст.replace(ЯКОРЬ_ВЫЗОВА, ВЫЗОВ_РЕД2, 1)


def _загрузить(файл: Path, имя: str):
    спец = importlib.util.spec_from_file_location(имя, файл)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


