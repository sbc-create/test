#!/usr/bin/env python3
"""Приёмка D1: полнота собственного каталога И сохранность прежних адресов.

Только чтение. Своих измерений здесь НЕТ — сводятся два уже существующих:

* `episode-sitemap-coverage.py` — ПОЛНОТА: ссылки на серии, которые витрина
  печатает на своей же странице произведения, против адресов этой работы в её
  собственной карте. Сравниваются МНОЖЕСТВА по каждой выбранной работе;
* `sitemap-part-monotonic.py` — СОХРАННОСТЬ: объединение частей `episodes*`
  против снимка предыдущего чтения. Ни один прежде названный адрес исчезнуть
  не должен.

ЗАЧЕМ СВОДИТЬ. Поодиночке каждая мера проходима без исправления дефекта:

* рост числа адресов приёмкой не является. У `yummyani.site` карта давала 1 679
  адресов в 23:4xZ и 464 в 00:2xZ — оба числа «выросли» относительно чего-то и
  оба меньше действительного состава каталога (8 378 работ);
* полнота без сохранности означает, что карта могла пересобраться набело,
  потеряв прежде названные адреса. Это и есть наблюдавшийся дефект: работ в
  карте ровно 36 в обоих чтениях, а состав сменился целыми работами;
* сохранность без полноты означает, что ничего не исчезло, но каталог
  по-прежнему не назван;
* полнота по работам, у которых терять нечего, не измеряет ничего. Признак
  `нечего терять` (на странице ни одной ссылки на серию) в дефект не идёт
  намеренно, поэтому выборка целиком из таких работ даёт ноль проблем при
  неизмеренной полноте. Шлюз требует хотя бы одну работу, где терять БЫЛО что.

Исход `ПРИНЯТО` возможен только когда выполнены все четыре условия сразу, и
печатаются числа каждого. Любое неизмеренное условие — отдельный исход, а не
успех: иначе отчёт утверждал бы проверку, которая не запускалась.

ПОРЯДОК ПРИЁМКИ ВЫПУСКА. Сохранность требует ДВУХ чтений, и первое чтение
расходует опору: `sitemap-part-monotonic.py` перезаписывает снимок множества в
`var/sitemap-snapshots/`. Поэтому до обновления витрины шлюз запускается один
раз (исход `СОХРАННОСТЬ НЕ СВЕРЕНА` — это норма первого запуска), после
обновления — второй раз, и принимает уже он.

    python3 automation/local/yummy-d1-acceptance.py yummyani.site
    python3 automation/local/yummy-d1-acceptance.py yummyani.site --json

Коды: 0 — принято; 1 — неполнота, потери или несведённое условие;
2 — не измерено.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]

ПРИНЯТО = "ПРИНЯТО"
НЕПОЛНО = "НЕПОЛНО"
ПОТЕРИ = "ПОТЕРИ"
СОХРАННОСТЬ_НЕ_СВЕРЕНА = "СОХРАННОСТЬ НЕ СВЕРЕНА"
ПОЛНОТА_НЕ_ИЗМЕРЕНА = "ПОЛНОТА НЕ ИЗМЕРЕНА"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"

#: Исходы меры сохранности, при которых прежнее множество ИЗВЕСТНО и сверено.
#: `ПЕРВЫЙ СНИМОК` и `НЕ ИЗМЕРЕНО` сюда не входят: сравнивать было не с чем.
СОХРАННОСТЬ_СВЕРЕНА = ("НАДМНОЖЕСТВО", "БЕЗ ИЗМЕНЕНИЙ", "ПОТЕРИ")

#: Признаки работы из меры полноты, при которых терять БЫЛО что, то есть
#: работа действительно участвовала в измерении полноты.
РАБОТА_ИЗМЕРЕНА = ("ок", "ок, но есть лишние", "НЕ НАЗВАНЫ")


def _модуль(имя: str, файл: str):
    спец = importlib.util.spec_from_file_location(
        имя, КОРЕНЬ / "automation" / "local" / файл)
    модуль = importlib.util.module_from_spec(спец)
    assert спец.loader is not None
    спец.loader.exec_module(модуль)
    return модуль


def работ_с_потерей(покрытие: dict) -> int:
    """Сколько работ выборки действительно участвовало в измерении полноты."""
    return sum(1 for р in покрытие.get("работы") or []
               if р.get("итог") in РАБОТА_ИЗМЕРЕНА)


def работ_неполных(покрытие: dict) -> int:
    return sum(1 for р in покрытие.get("работы") or []
               if р.get("итог") == "НЕ НАЗВАНЫ")


def свести(покрытие: dict, сохранность: dict) -> str:
    """Исход приёмки по двум мерам. Чистая функция.

    Порядок проверок — по цене последствий: потеря адресов дороже неполноты,
    потому что отзывает уже названную поисковику страницу.
    """
    if not покрытие.get("измерено"):
        return НЕ_ИЗМЕРЕНО
    исход_сохранности = str(сохранность.get("исход") or НЕ_ИЗМЕРЕНО)
    if исход_сохранности == ПОТЕРИ or int(сохранность.get("исчезло") or 0):
        return ПОТЕРИ
    if работ_неполных(покрытие):
        return НЕПОЛНО
    if работ_с_потерей(покрытие) == 0:
        return ПОЛНОТА_НЕ_ИЗМЕРЕНА
    if исход_сохранности not in СОХРАННОСТЬ_СВЕРЕНА:
        return СОХРАННОСТЬ_НЕ_СВЕРЕНА
    return ПРИНЯТО


def проверить(домен: str, позиции: tuple[int, ...]) -> dict:
    полнота = _модуль("episode_sitemap_coverage",
                      "episode-sitemap-coverage.py")
    монотонность = _модуль("sitemap_part_monotonic",
                           "sitemap-part-monotonic.py")
    покрытие = полнота.проверить(домен, позиции)
    сохранность = монотонность.проверить(
        "", индекс=f"https://{домен}/sitemap.xml", префикс="episodes")
    return {
        "домен": домен,
        "исход": свести(покрытие, сохранность),
        "полнота": {
            "измерено": bool(покрытие.get("измерено")),
            "частей_серий": покрытие.get("частей_серий"),
            "адресов_серий": покрытие.get("адресов_серий"),
            "работ_в_каталоге": покрытие.get("работ_в_каталоге"),
            "работ_в_выборке": len(покрытие.get("работы") or []),
            "работ_где_терять_было_что": работ_с_потерей(покрытие),
            "работ_с_неназванными": работ_неполных(покрытие),
            "проблемы": покрытие.get("проблемы") or [],
            "работы": покрытие.get("работы") or [],
        },
        "сохранность": {
            "исход": сохранность.get("исход"),
            "было": сохранность.get("было"),
            "стало": сохранность.get("стало"),
            "исчезло": сохранность.get("исчезло"),
            "добавилось": сохранность.get("добавилось"),
            "исчезли_работы": сохранность.get("исчезли_работы") or [],
            "прежний_снимок": сохранность.get("прежний_снимок"),
            "снимок": сохранность.get("снимок"),
        },
    }


def напечатать(итоги: dict) -> None:
    п, с = итоги["полнота"], итоги["сохранность"]
    print(f"{итоги['домен']}: {итоги['исход']}")
    print(f"   ПОЛНОТА: частей серий {п['частей_серий']},"
          f" адресов серий {п['адресов_серий']},"
          f" работ в каталоге {п['работ_в_каталоге']};"
          f" выборка {п['работ_в_выборке']},"
          f" из них терять было что у {п['работ_где_терять_было_что']},"
          f" с неназванными {п['работ_с_неназванными']}")
    for р in п["работы"]:
        if р.get("итог") in ("НЕ НАЗВАНЫ", "не измерено", "нечего терять"):
            print(f"      поз.{р['позиция']:>5} {str(р.get('слаг'))[:40]:<40}"
                  f" страница {р.get('на_странице', '—'):>5}"
                  f" | карта {р.get('в_карте', '—'):>5}"
                  f" | {р['итог']}")
    print(f"   СОХРАННОСТЬ: {с['исход']}, было {с['было']}, стало"
          f" {с['стало']}, исчезло {с['исчезло']}, добавилось"
          f" {с['добавилось']} (прежний снимок {с['прежний_снимок'] or '—'})")
    if с["исчезли_работы"]:
        print(f"      исчезли работы: {', '.join(с['исчезли_работы'])}")
    if итоги["исход"] == СОХРАННОСТЬ_НЕ_СВЕРЕНА:
        print("   это НОРМА первого запуска: снимок сохранён, принимает"
              " второй запуск — после обновления витрины")
    if итоги["исход"] == ПОЛНОТА_НЕ_ИЗМЕРЕНА:
        print("   ни у одной работы выборки серий на странице нет: полноту"
              " сравнивать не с чем, выборку надо менять")
    print("   рост числа адресов приёмкой НЕ является: нужны полнота по"
          " собственному каталогу И сверенная сохранность")


def main(аргв: list[str] | None = None) -> int:
    полнота = _модуль("episode_sitemap_coverage",
                      "episode-sitemap-coverage.py")
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("домены", nargs="+")
    р.add_argument("--positions",
                   default=",".join(map(str, полнота.ПОЗИЦИИ_ПО_УМОЛЧАНИЮ)),
                   help="позиции работ в titles.xml; по умолчанию те же, что"
                        " в таблице блока владельца")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    позиции = tuple(int(ч) for ч in а.positions.split(",") if ч.strip())

    итоги = [проверить(д, позиции) for д in а.домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            напечатать(и)

    исходы = {и["исход"] for и in итоги}
    if исходы == {НЕ_ИЗМЕРЕНО}:
        return 2
    return 0 if исходы == {ПРИНЯТО} else 1


if __name__ == "__main__":
    sys.exit(main())
