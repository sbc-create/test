#!/usr/bin/env python3
"""Сколько карточек первого экрана без изображения — и есть ли оно у ЗАПИСИ.

Только чтение публичных страниц.

Зачем разделять, и это главное свойство инструмента. Отсутствие постера на
КАРТОЧКЕ может быть и дефектом витрины (не подставила то, что есть), и пробелом
ЗАПИСИ (изображения нет вовсе). Это разные владельцы, и путать их — та же
ошибка, что с полем `playable`: там состояние данных сначала назвали дефектом
витрины. Поэтому инструмент для каждой карточки без постера открывает страницу
произведения и смотрит, есть ли изображение ТАМ.

Измерено 20.10 на трёх витринах Zona (первые 24 карточки главной):

    zonafilm.space    без изображения 1 — facing-grizzlies, изображения нет и
                      у записи (страница тоже показывает букву-заглушку)
    zonafilm12.site   без изображения 0
    zonafilm.cc       без изображения 0

Коды возврата: 0 — карточек без изображения нет, 3 — есть, 2 — измерять нечего.
"""
from __future__ import annotations

import argparse
import importlib.util
import pathlib
import re
import sys
import urllib.error
import urllib.request

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
АГЕНТ = "factory-poster-coverage"
ТАЙМАУТ = 30

#: Класс заглушки, которой витрина штатно закрывает отсутствующий постер.
ЗАГЛУШКА = "zt__none"
#: Хост изображений. Запросов к нему инструмент НЕ делает: он только ищет
#: упоминания в разметке. Хост не входит в список разрешённых для наших
#: запросов, и подбирать к нему параметры нельзя (MOD-96).
ХОСТ_ПОСТЕРОВ = "poster.cdnvideohub.com"


def _ревизия():
    с = importlib.util.spec_from_file_location(
        "homepage_cards_audit", КОРЕНЬ / "automation/local/homepage-cards-audit.py")
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


def добыть(адрес: str) -> str:
    запрос = urllib.request.Request(адрес, headers={"User-Agent": АГЕНТ})
    try:
        with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ) as о:
            return о.read().decode("utf-8", "replace")
    except (urllib.error.URLError, OSError, TimeoutError):
        return ""


def чьё_отсутствие(тело_страницы: str) -> dict:
    """У записи нет изображения — или витрина его не подставила.

    Смотрится блок постера ПРОИЗВЕДЕНИЯ (до `h1`), а не вся страница: ниже по
    странице стоят карточки похожих работ со своими постерами, и по ним можно
    решить, что изображение есть, когда у самого произведения его нет.
    """
    if not тело_страницы:
        return {"не_измерено": "страница произведения не прочитана"}
    # Окно кончается НА `h1`, а не после него. Блок постера произведения
    # стоит ВЫШЕ заголовка (`ztitle__poster` → `ztitle__main` → `h1`), а ниже
    # идут похожие работы со своими постерами. Прежнее окно захватывало 500
    # знаков после `h1`, и на странице, где похожие начинаются сразу, шесть
    # чужих постеров давали вывод «у записи изображение есть». Ошибку нашла
    # проверка, а не живая страница: на живых похожие стоят дальше.
    место = тело_страницы.find("<h1")
    окно = тело_страницы[max(0, место - 3000):место if место >= 0 else None]
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", тело_страницы, re.S)
    имя = re.sub(r"<[^>]+>", "", h1.group(1)).strip() if h1 else "—"
    своих = len(re.findall(re.escape(ХОСТ_ПОСТЕРОВ) + r"[^\"']*", окно))
    заглушек = окно.count(ЗАГЛУШКА)
    if своих == 0 and заглушек:
        чьё = "у записи изображения НЕТ (страница тоже показывает заглушку)"
    elif своих:
        чьё = "у записи изображение ЕСТЬ — не подставила витрина"
    else:
        чьё = "не измерено: блок постера произведения не распознан"
    return {"имя": имя, "своих_изображений": своих, "заглушек": заглушек,
            "чьё": чьё}


def по_домену(домен: str, сколько: int = 24, загрузчик=None) -> dict:
    загрузчик = загрузчик or добыть
    А = _ревизия()
    тело = А.добыть(f"https://{домен}/")
    if not тело:
        return {"не_измерено": "главная не получена"}
    карточки = А.карточки_по_порядку(тело, сколько)
    if not карточки:
        return {"не_измерено": "карточек на главной не найдено"}
    без = [к for к in карточки if not к.get("постер")]
    разбор = []
    for к in без:
        слаг = к.get("слаг") or к["путь"]
        разбор.append({"слаг": слаг, "путь": к["путь"], "блок": к.get("блок"),
                       **чьё_отсутствие(загрузчик(f"https://{домен}{к['путь']}"))})
    return {"карточек": len(карточки), "без_изображения": разбор}


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("домены", nargs="+")
    р.add_argument("--cards", type=int, default=24)
    дов = р.parse_args(аргв)

    всего_без = 0
    измерено = 0
    for домен in дов.домены:
        итог = по_домену(домен, дов.cards)
        if "не_измерено" in итог:
            print(f"\n{домен}: НЕ ИЗМЕРЕНО — {итог['не_измерено']}")
            continue
        измерено += 1
        print(f"\n{домен}: карточек {итог['карточек']},"
              f" без изображения {len(итог['без_изображения'])}")
        for з in итог["без_изображения"]:
            всего_без += 1
            если = з.get("не_измерено") or з["чьё"]
            # Полка названа рядом: без неё легко приписать карточку не той
            # полке и построить на этом ложную причинную связь.
            print(f"   {з['слаг'][:34]:36} полка «{str(з.get('блок'))[:24]:26}»"
                  f" → {если}")
    if not измерено:
        return 2
    return 3 if всего_без else 0


if __name__ == "__main__":
    sys.exit(main())
