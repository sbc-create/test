#!/usr/bin/env python3
"""Состояние счётчиков аналитики по каждому сайту: что измеримо и что нет.

Задание владельца требует установить по каждому сайту состояние Google
Analytics по четырём признакам: настройка, установленный тег, входящие события,
доступ к отчётам. Два из четырёх измеримы снаружи, два — нет, и их нельзя
выдавать ни за исправность, ни за поломку.

  объявлен        идентификатор назван в пакете сайта или в реестре
  установлен      живая страница грузит тег и несёт идентификатор
  события идут    НЕ ИЗМЕРИМО снаружи: нужен доступ к отчётам ресурса
  доступ к отчётам НЕ ИЗМЕРИМО снаружи: нужен сервисный аккаунт

Для Метрики те же два измеримых признака снимаются рядом — не для полноты, а
потому что контраст и есть ответ: если Метрика установлена, а GA нет, то дело
не в разметке и не в выкладке, а в отсутствии идентификаторов.

Идентификаторы НЕ придумываются: отсутствие объявленного значения — это
`BLOCKED_INPUT`, и инструмент называет внешнее действие, а не подставляет
заглушку.

    python3 automation/local/analytics-tags-state.py
"""
from __future__ import annotations

import argparse
import json
import glob
import hashlib
import re
import subprocess
import socket
import ssl
import sys
import urllib.error
import urllib.request
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"

#: Идентификатор ресурса GA4 в разметке: `G-` плюс минимум восемь знаков.
#: Строгая форма нужна, чтобы не считать тегом случайное «G-» в тексте.
GA_ID = re.compile(r"\bG-[A-Z0-9]{8,}\b")
#: Загрузка самой библиотеки. Без неё идентификатор в разметке ничего не делает.
GA_БИБЛИОТЕКА = re.compile(
    r"googletagmanager\.com/gtag/js|google-analytics\.com/analytics\.js", re.I)
#: Номер счётчика Метрики: вызов `ym(<номер>` ЛИБО `ym("<номер>"` — вторая
#: форма встречается у Yummy, и без кавычек в образце она терялась.
МЕТРИКА_НОМЕР = re.compile(r"""ym\(\s*["']?(\d{6,})["']?""")
МЕТРИКА_БИБЛИОТЕКА = re.compile(r"mc\.yandex\.ru/metrika", re.I)

ДА = "да"
НЕТ = "нет"
НЕ_ИЗМЕРИМО = "не измеримо снаружи"


#: Служебные имена стендов: домена в сети у них нет и быть не должно.
СТЕНДОВЫЕ = (".localhost", ".localhost.test")


#: Корни выпусков витрин на узле. Имя каталога получается из домена заменой
#: точек на дефисы; у части витрин есть приставка `site-`. Обе формы
#: измерены на узле 26.10, поэтому проверяются обе, а ненайденный каталог —
#: отдельный исход, а не «нет».
КОРЕНЬ_ВЫПУСКОВ = Path("/srv")
#: Следы отправки целей в собранном выпуске. `__sfGoal` — помощник
#: канонического слоя, `reachGoal` — сам вызов Метрики.
СЛЕДЫ_ЦЕЛЕЙ = ("__sfGoal", "reachGoal")
НЕТ_ВЫПУСКА = "выпуска нет"


def каталог_выпуска(домен: str) -> Path | None:
    """Каталог живого выпуска витрины по домену — или None."""
    основа = домен.replace(".", "-")
    for имя in (основа, f"site-{основа}"):
        п = КОРЕНЬ_ВЫПУСКОВ / имя / "current"
        if п.exists():
            return п
    return None


def цели_в_выпуске(домен: str) -> tuple[str, str]:
    """Есть ли В ЖИВОМ ВЫПУСКЕ код отправки целей — и чем это доказано.

    Зачем это здесь. Признак «события идут» снаружи не измерим, и так и
    сказано. Но его НЕВОЗМОЖНОСТЬ измерима локально: если в выпуске нет ни
    одного вызова `reachGoal`, события идти не могут, сколько бы целей ни
    стояло в реестре. Измерено 26.10 по 20 витринам узла: след есть у ОДНОЙ.
    Это и есть причина, по которой `goal_reaches` за неделю равен нулю, —
    не настройка кабинета и не счётчик (тег на страницах работает), а
    выпуски, которые старше кода канонического слоя.
    """
    к = каталог_выпуска(домен)
    if к is None:
        return НЕТ_ВЫПУСКА, "каталог выпуска на этом узле не найден"
    for след in СЛЕДЫ_ЦЕЛЕЙ:
        г = subprocess.run(["grep", "-rl", "--include=*.py", "--include=*.js",
                            "--include=*.ts", "--include=*.tsx", "--include=*.html",
                            след, str(к)], capture_output=True, text=True)
        # Проверочные сценарии и документы не отдаются посетителю: след в
        # checks/ или docs/ целей на страницу не приносит. Измерено 26.10 на
        # 1lordserials1.online — там след нашёлся в checks/player_mount.py,
        # и без этого отсечения витрина числилась бы готовой.
        отдаваемые = [с for с in г.stdout.strip().splitlines()
                      if not any(f"/{х}/" in с for х in
                                 ("checks", "docs", "artifacts", "tests", "evidence"))]
        if отдаваемые:
            return ДА, f"{след} найден: {отдаваемые[0][-60:]}"
    return НЕТ, (f"ни одного следа {'/'.join(СЛЕДЫ_ЦЕЛЕЙ)} в {к.resolve().name} — "
                 "события идти НЕ МОГУТ")


#: След отправки целей в САМОЙ разметке: самый прямой признак из всех.
СЛЕД_В_РАЗМЕТКЕ = re.compile(r"__sfGoal|reachGoal")
#: Где искать рантаймы витрин, чтобы сопоставить сумму артефакта из заголовка
#: с тем, есть ли в нём помощник целей. Заголовок
#: `x-site-factory-artifact-sha256` называет сумму ТОГО файла, который сейчас
#: обслуживает домен — проверено 26.10 на двух витринах: у zonafilm.cc сумма
#: совпала с файлом выпуска шаблона, у 1lordserials1.online — с файлом,
#: закоммиченным в репозитории витрины.
ОБРАЗЦЫ_РАНТАЙМОВ = (
    "/srv/lords/.frontend/sites/*/releases/*/template/*/lords-frontend.py",
    "/srv/*/current/src/lords-frontend.py",
    "/srv/*/releases/*/src/lords-frontend.py",
)


def карта_артефактов() -> dict[str, bool]:
    """Сумма рантайма → есть ли в нём отправка целей.

    Нужна потому, что локальный разбор выпуска отвечает только по витринам
    ЭТОГО узла: 26.10 из 29 живых домéнов у 13 выпуска здесь нет вовсе, и по
    ним признак оставался неизмеренным. Сумма из заголовка снимает это
    ограничение — но только для сумм, которые мы ВИДЕЛИ. Незнакомая сумма
    остаётся третьим исходом, а не выдаётся за «нет».
    """
    карта: dict[str, bool] = {}
    for образец in ОБРАЗЦЫ_РАНТАЙМОВ:
        for путь in glob.glob(образец):
            try:
                данные = Path(путь).read_bytes()
            except OSError:
                continue
            карта.setdefault(hashlib.sha256(данные).hexdigest(),
                             bool(СЛЕД_В_РАЗМЕТКЕ.search(
                                 данные.decode("utf-8", "replace"))))
    return карта


def цели_по_артефакту(сумма: str, карта: dict[str, bool]) -> tuple[str, str]:
    """Признак по сумме артефакта из заголовка живой страницы."""
    if not сумма:
        return НЕ_ИЗМЕРИМО, "витрина не называет сумму артефакта в заголовке"
    если = карта.get(сумма.lower())
    if если is None:
        return НЕ_ИЗМЕРИМО, (f"сумма {сумма[:12]} среди известных рантаймов "
                             f"({len(карта)}) не найдена")
    return (ДА if если else НЕТ), (f"артефакт {сумма[:12]}: помощник "
                                   + ("есть" if если else "НЕ ВХОДИТ"))


def живые(реестр: Path) -> list[dict]:
    """Записи витрин, чьё имя РАЗРЕШАЕТСЯ, а не те, чья ячейка вынута.

    Поле `status` описывает состояние ячейки. `1lordserials1.online` и
    `lordserial33.biz` стоят `not_extracted`, но домены работают, и по ним
    состояние счётчиков надо знать так же, как по остальным.
    """
    д = json.loads(реестр.read_text(encoding="utf-8"))
    ячейки = д.get("cells") or д
    берём: list[dict] = []
    for запись in ячейки:
        домен = str(запись.get("domain") or "").strip()
        if not домен or any(домен.endswith(х) for х in СТЕНДОВЫЕ):
            continue
        try:
            socket.gethostbyname(домен)
        except OSError:
            continue
        берём.append(запись)
    return sorted(берём, key=lambda з: з["domain"])


def объявленный_ga(запись: dict) -> str:
    """Идентификатор GA4, объявленный в пакете сайта или в реестре.

    Ищется в названных полях, а не по всему документу: случайное совпадение
    в комментарии не является объявлением.
    """
    for поле in ("ga4_measurement_id", "ga_measurement_id", "ga4_id"):
        значение = str(запись.get(поле) or "").strip()
        if значение:
            return значение
    аналитика = запись.get("analytics") or {}
    if isinstance(аналитика, dict):
        for поле in ("ga4_measurement_id", "ga4_id", "measurement_id"):
            значение = str(аналитика.get(поле) or "").strip()
            if значение:
                return значение
    return ""


def снять(домен: str, предел: float) -> dict:
    контекст = ssl.create_default_context()
    контекст.check_hostname = False
    контекст.verify_mode = ssl.CERT_NONE
    открыть = urllib.request.build_opener(
        urllib.request.HTTPSHandler(context=контекст))
    запрос = urllib.request.Request(
        f"https://{домен}/", headers={"User-Agent": "factory-tags-state"})
    try:
        ответ = открыть.open(запрос, timeout=предел)
        разметка = ответ.read(400_000).decode("utf-8", "replace")
    except urllib.error.HTTPError as сбой:
        return {"ошибка": f"HTTP {сбой.code}"}
    except Exception as сбой:
        return {"ошибка": f"{type(сбой).__name__}: {str(сбой)[:60]}"}
    ga = GA_ID.search(разметка)
    метрика = МЕТРИКА_НОМЕР.search(разметка)
    # Заголовки витрины снимаются тем же запросом: они называют ревизию
    # шаблона и СУММУ артефакта, который сейчас обслуживает домен.
    заголовки = {и.lower(): з for и, з in (ответ.headers or {}).items()}
    return {
        "ga_id": ga.group(0) if ga else "",
        "ga_библиотека": bool(GA_БИБЛИОТЕКА.search(разметка)),
        "метрика_номер": метрика.group(1) if метрика else "",
        "метрика_библиотека": bool(МЕТРИКА_БИБЛИОТЕКА.search(разметка)),
        "артефакт": заголовки.get("x-site-factory-artifact-sha256", ""),
        "ревизия_шаблона": заголовки.get("x-site-factory-template-revision", ""),
        "цели_в_разметке": bool(СЛЕД_В_РАЗМЕТКЕ.search(разметка)),
    }


def цели_признак(домен: str, снято: dict, карта: dict[str, bool]) -> tuple[str, str]:
    """Могут ли идти цели — по самому надёжному доступному признаку.

    Порядок именно такой, и он не произволен:

    1. САМА РАЗМЕТКА. Если в отданном HTML есть `__sfGoal`/`reachGoal`, цели
       идти могут — это прямое наблюдение, а не вывод.
    2. СУММА АРТЕФАКТА из заголовка `x-site-factory-artifact-sha256`. Работает
       и для витрин, которых на этом узле нет: 26.10 из 29 живых домéнов у 13
       выпуска здесь не было, и локальный разбор по ним молчал.
    3. ЛОКАЛЬНЫЙ ВЫПУСК. Остаётся для случаев, когда домен не ответил.

    Незнакомая сумма — «не измеримо», а не «нет»: мы отвечаем только за те
    рантаймы, которые видели.
    """
    if снято.get("цели_в_разметке"):
        return ДА, "вызов цели есть в отданной разметке"
    состояние, почему = цели_по_артефакту(снято.get("артефакт", ""), карта)
    if состояние != НЕ_ИЗМЕРИМО:
        return состояние, почему
    местное, почему_местного = цели_в_выпуске(домен)
    if местное != НЕТ_ВЫПУСКА:
        return местное, почему_местного
    return НЕ_ИЗМЕРИМО, почему


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--registry", type=Path, default=РЕЕСТР)
    р.add_argument("--timeout", type=float, default=60.0)
    опции = р.parse_args(аргв)

    записи = живые(опции.registry)
    карта = карта_артефактов()
    без_ga: list[str] = []
    неснятые: list[str] = []
    метрика_есть = 0
    номера: dict[str, list[str]] = {}

    без_целей: list[str] = []
    могут: list[str] = []
    print(f"{'домен':26s} {'GA объявлен':12s} {'GA установлен':14s} "
          f"{'Метрика':10s} {'цели в выпуске':15s} номер")
    for запись in записи:
        домен = запись["domain"]
        снято = снять(домен, опции.timeout)
        if "ошибка" in снято:
            неснятые.append(домен)
            print(f"{домен:26s} {'—':12s} {'НЕ ИЗМЕРЕНО':14s} "
                  f"{'—':10s} {снято['ошибка']}")
            continue
        объявлен = объявленный_ga(запись)
        установлен = снято["ga_id"] and снято["ga_библиотека"]
        метрика = снято["метрика_номер"] and снято["метрика_библиотека"]
        метрика_есть += bool(метрика)
        if метрика:
            номера.setdefault(снято["метрика_номер"], []).append(домен)
        if not установлен:
            без_ga.append(домен)
        цели, почему_цели = цели_признак(домен, снято, карта)
        if цели == НЕТ:
            без_целей.append(домен)
        elif цели == ДА:
            могут.append(домен)
        print(f"{домен:26s} {(объявлен or НЕТ):12s} "
              f"{(снято['ga_id'] if установлен else НЕТ):14s} "
              f"{(ДА if метрика else НЕТ):10s} {цели:15s} "
              f"{снято['метрика_номер'] or '—'}")

    print(f"\nживых доменов: {len(записи)}")
    print(f"   GA4 установлен:    {len(записи) - len(без_ga) - len(неснятые)}")
    print(f"   GA4 не установлен: {len(без_ga)}")
    print(f"   Метрика работает:  {метрика_есть}")
    # Считается ЯВНОЕ «да», а не «всё, что не нет». Первая редакция этой
    # строки печатала 14 из 29, потому что складывала «не измеримо» и «не
    # снято» в исправность — та самая ошибка, от которой предостерегает
    # заголовок этого файла. Явных «да» было одно.
    print(f"   цели МОГУТ идти:   {len(могут)}")
    print(f"   не измеримо:       {len(записи) - len(могут) - len(без_целей) - len(неснятые)}")
    if без_целей:
        print(f"   цели идти НЕ МОГУТ: {len(без_целей)} — в выпуске нет вызова "
              f"reachGoal: {', '.join(без_целей[:6])}"
              + (" …" if len(без_целей) > 6 else ""))
    if неснятые:
        print(f"   НЕ ИЗМЕРЕНО: {len(неснятые)} — {', '.join(неснятые)}")

    повторы = {н: д for н, д in номера.items() if len(д) > 1}
    if повторы:
        print("\nодин номер Метрики на нескольких доменах — данные смешаются:")
        for номер, домены in sorted(повторы.items()):
            print(f"   {номер}: {', '.join(домены)}")

    print("\nдва признака из четырёх снаружи НЕ ИЗМЕРИМЫ и исправностью "
          "не считаются:")
    print("   события идут     — нужен доступ к отчётам ресурса GA4")
    print("   доступ к отчётам — нужен сервисный аккаунт с правом чтения")

    if без_ga:
        print(f"\nВНЕШНЕЕ ДЕЙСТВИЕ (GA4 не установлен на {len(без_ga)} "
              "доменах). Нужны от владельца:")
        print("   1. ресурс GA4 на каждый домен и его measurement ID (G-…);")
        print("   2. сервисный аккаунт с правом чтения отчётов и его ключ "
              "через secret_ref;")
        print("   3. разрешение сети на googletagmanager.com, если выкладка "
              "идёт в закрытом контуре.")
        print("   Идентификаторы НЕ придумываются: пустое поле — это "
              "BLOCKED_INPUT, а не повод подставить значение.")

    if неснятые:
        return 2
    return 1 if без_ga else 0


if __name__ == "__main__":
    raise SystemExit(главное())
