#!/usr/bin/env python3
"""Зарабатывающие страницы целы, и различающий контроль это подтверждает.

Зачем. Спрос витрин сосредоточен: у `animedia.icu` один адрес несёт 32 %
поискового трафика домена, верхние десять — 82.8 %. Потеря доступности ОДНОЙ
такой страницы стоит дороже любой правки, а из общего «сайт отвечает 200»
узнать об этом нельзя: витрина отвечает, пока зарабатывающая страница лежит.

Поэтому проверяются ИМЕННО сохранённые зарабатывающие адреса — каждый по
отдельности, по пяти признакам: код ответа, `robots`, canonical на себя,
непустой `h1` и признак плеера там, где он нужен по замыслу.

РАЗЛИЧАЮЩИЙ КОНТРОЛЬ обязателен, иначе вывод неразличим. Рядом проверяются
случайные адреса той же витрины из её КАРТЫ (семя фиксировано — два прогона
сравнимы):

  беда только на зарабатывающих → беда именно на них;
  беда и там и там              → беда витрины, а не её спроса;
  исправны и те и те            → поверхность исправна СЕЙЧАС.

Перечень зарабатывающих берётся из снимка Метрики, а не из головы, и охват
снимка печатается: проверка без охвата читается как проверка всего.

    python3 automation/local/earning-pages-guard.py
    python3 automation/local/earning-pages-guard.py --domain animedia.icu --json

Коды: 0 — исправно у всех проверенных; 1 — есть беда (на зарабатывающих или
на витрине); 2 — НЕ ИЗМЕРЕНО ни по одному домену (карта или снимок не
прочитаны). «Не измерено» никогда не печатается как «исправно».
"""
from __future__ import annotations

import argparse
import json
import random
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СНИМОК = КОРЕНЬ / "config" / "demand-snapshot.json"

АГЕНТ = "factory-earning-pages-guard"
#: Семя по умолчанию — дата первого замера. Случайность с фиксированным семенем
#: даёт СРАВНИМЫЕ прогоны; случайность без семени даёт новый ответ каждый раз.
СЕМЯ = 20261022
#: Сколько случайных адресов брать в контроль. Число печатается: контроль из
#: пяти адресов и контроль из пятидесяти — разные утверждения.
КОНТРОЛЕЙ = 5

#: Разделы, где плеера нет по замыслу: главная, каталог, подборки, расписание,
#: топы и новинки. Требовать плеер от них значит выдумать дефект.
БЕЗ_ПЛЕЕРА = re.compile(
    r"^/?$|/catalog|/collections?|/schedule|/genres|/top|/new|/posts|/country")
#: Знак МОНТАЖА плеера в разметке — не доказательство воспроизведения (его
#: проверяет `playback-check.py`). Перечисление измерено 22.10 по одной
#: странице произведения на стек: `data-player-host` есть у питоновского
#: семейства (animedia 4, lordfilm 4, zona 4) и ОТСУТСТВУЕТ у Yummy на
#: Next.js, где общий знак — `data-player` (1). Первая редакция искала
#: `<iframe` и классы `player`: знак не нашёлся ни на одной странице, включая
#: контрольные, — отказ меры, а не беда витрины.
ПРИЗНАК_ПЛЕЕРА = re.compile(
    r"data-player-host|data-player\b|<iframe|class=\"[^\"]*player"
    r"|id=\"[^\"]*player", re.I)
ROBOTS = re.compile(r"<meta[^>]+name=[\"']robots[\"'][^>]*content=[\"']([^\"']*)",
                    re.I)
CANONICAL = re.compile(
    r"<link[^>]+rel=[\"']canonical[\"'][^>]*href=[\"']([^\"']*)", re.I)
H1 = re.compile(r"<h1[^>]*>(.*?)</h1>", re.I | re.S)
АДРЕС_КАРТЫ = re.compile(r"<loc>\s*([^<\s]+)\s*</loc>")


# --- чистые функции: их проверяют тесты, они ничего не читают ---------------

def не_требует_плеера(путь: str) -> bool:
    return bool(БЕЗ_ПЛЕЕРА.search(путь))


def признаки(тело: str, путь: str, домен: str) -> dict:
    """Пять признаков страницы по её телу. Чистая функция.

    Отсутствие тела — это НЕ «признаки плохие», а отсутствие измерения:
    поля остаются None, и `беда()` их таковыми не считает.
    """
    если_нет = {"robots": None, "canonical": None, "h1": None, "плеер": None}
    if not тело:
        return если_нет
    м_r = ROBOTS.search(тело)
    м_c = CANONICAL.search(тело)
    м_h = H1.search(тело)
    текст_h1 = re.sub(r"<[^>]+>", "", м_h.group(1)).strip() if м_h else ""
    канон = (м_c.group(1) or "").strip() if м_c else ""
    свой = ""
    if канон:
        путь_канона = re.sub(r"^https?://[^/]+", "", канон) or "/"
        свой = "на себя" if путь_канона.rstrip("/") == путь.rstrip("/") \
            else f"на {путь_канона}"
    return {
        "robots": (м_r.group(1) or "").strip().lower() if м_r else "",
        "canonical": свой,
        "h1": текст_h1,
        "плеер": (None if не_требует_плеера(путь)
                  else bool(ПРИЗНАК_ПЛЕЕРА.search(тело))),
    }


def беда(запись: dict) -> list[str]:
    """Чем именно страница плоха. Пустой перечень — страница исправна.

    Неизмеренный признак (None) бедой не считается: «не измерено» — не «плохо».
    """
    из_чего = []
    код = str(запись.get("код") or "")
    if код and код != "200":
        из_чего.append(f"код {код}")
    п = запись.get("признаки") or {}
    r = п.get("robots")
    if r is not None and r != "" and "noindex" in r:
        из_чего.append(f"robots «{r}»")
    if r == "":
        из_чего.append("robots отсутствует")
    к = п.get("canonical")
    if к is not None and к != "" and к != "на себя":
        из_чего.append(f"canonical {к}")
    h = п.get("h1")
    if h is not None and not h:
        из_чего.append("h1 пуст")
    if п.get("плеер") is False:
        из_чего.append("признака плеера нет")
    return из_чего


def исход(зарабатывающие: list[dict], контроль: list[dict]) -> str:
    """Различающий вывод по двум наборам. Без контроля вывода НЕТ."""
    if not зарабатывающие:
        return "НЕ ИЗМЕРЕНО: зарабатывающих страниц в снимке нет"
    if not контроль:
        return "НЕ ИЗМЕРЕНО: контроль не собран, вывод неразличим"
    плохо_з = [з for з in зарабатывающие if беда(з)]
    плохо_к = [к for к in контроль if беда(к)]
    if плохо_з and плохо_к:
        return "БЕДА ВИТРИНЫ: плохо и на зарабатывающих, и в контроле"
    if плохо_з:
        return (f"БЕДА НА ЗАРАБАТЫВАЮЩИХ: {len(плохо_з)}"
                f" из {len(зарабатывающие)} при исправном контроле")
    if плохо_к:
        return (f"БЕДА В КОНТРОЛЕ: зарабатывающие целы, но {len(плохо_к)}"
                f" из {len(контроль)} случайных плохи")
    return (f"исправно: {len(зарабатывающие)} из {len(зарабатывающие)}"
            f" зарабатывающих и {len(контроль)} из {len(контроль)} контрольных")


def выборка(адреса: list[str], семя: int, сколько: int) -> list[str]:
    """Случайные адреса с фиксированным семенем. Чистая функция."""
    уникальные = sorted(set(адреса))
    if len(уникальные) <= сколько:
        return уникальные
    return random.Random(семя).sample(уникальные, сколько)


def адреса_карты(тело: str) -> tuple[list[str], list[str]]:
    """Адреса из карты: (части индекса, страницы). Чистая функция."""
    все = АДРЕС_КАРТЫ.findall(тело or "")
    части = [а for а in все if "sitemap" in а]
    страницы = [а for а in все if "sitemap" not in а]
    return части, страницы


# --- чтение сети: отдельно от разбора ---------------------------------------

def достать(url: str, таймаут: int = 60) -> tuple[str, str]:
    try:
        р = subprocess.run(
            ["curl", "-sSL", "--max-time", str(таймаут),
             "-w", "\n@@%{http_code}", "-H", f"User-Agent: {АГЕНТ}", url],
            capture_output=True, text=True, timeout=таймаут + 30)
    except (subprocess.TimeoutExpired, OSError):
        return "таймаут", ""
    т = р.stdout
    if "@@" not in т:
        return "—", т
    тело, код = т.rsplit("@@", 1)
    return код.strip(), тело


def проверить_адрес(домен: str, путь: str) -> dict:
    код, тело = достать(f"https://{домен}{путь}")
    з = {"путь": путь, "код": код, "признаки": признаки(тело, путь, домен)}
    з["беда"] = беда(з)
    return з


def контрольные_пути(домен: str, семя: int, сколько: int) -> list[str]:
    """Случайные пути витрины ИЗ ЕЁ КАРТЫ. Пусто — карта не прочитана."""
    код, тело = достать(f"https://{домен}/sitemap.xml")
    if код != "200":
        return []
    части, страницы = адреса_карты(тело)
    if части:
        код2, тело2 = достать(части[0])
        if код2 == "200":
            _, страницы = адреса_карты(тело2)
    пути = [re.sub(r"^https?://[^/]+", "", а) or "/" for а in страницы]
    return выборка([п for п in пути if п], семя, сколько)


def проверить_домен(запись: dict, семя: int, сколько: int) -> dict:
    домен = запись["domain"]
    страницы = запись.get("search_landing_pages") or []
    итог = {
        "домен": домен,
        "охват_снимка": запись.get("search_landing_covered"),
        "страниц_в_разрезе": запись.get("search_pages_total"),
        "сохранено": len(страницы),
        "зарабатывающие": [],
        "контроль": [],
    }
    for с in страницы:
        проверка = проверить_адрес(домен, с.get("page") or "/")
        проверка["визиты"] = с.get("visits")
        итог["зарабатывающие"].append(проверка)
    for путь in контрольные_пути(домен, семя, сколько):
        итог["контроль"].append(проверить_адрес(домен, путь))
    итог["исход"] = исход(итог["зарабатывающие"], итог["контроль"])
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", help="один домен вместо всех из снимка")
    р.add_argument("--seed", type=int, default=СЕМЯ)
    р.add_argument("--controls", type=int, default=КОНТРОЛЕЙ)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    if not СНИМОК.is_file():
        print(f"НЕ ИЗМЕРЕНО: снимка спроса нет ({СНИМОК})", file=sys.stderr)
        return 2
    снимок = json.loads(СНИМОК.read_text(encoding="utf-8"))
    записи = [з for з in снимок.get("domains") or []
              if з.get("search_landing_pages")]
    if а.domain:
        записи = [з for з in записи if з["domain"] == а.domain]
        if not записи:
            print(f"НЕ ИЗМЕРЕНО: у {а.domain} сохранённых зарабатывающих"
                  " страниц в снимке нет", file=sys.stderr)
            return 2

    итоги = [проверить_домен(з, а.seed, а.controls) for з in записи]
    if а.json:
        print(json.dumps({"snapshot": снимок.get("snapshot"),
                          "seed": а.seed, "итоги": итоги},
                         ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            охват = ("не назван" if и["охват_снимка"] is None
                     else f"{и['охват_снимка']} %")
            print(f"{и['домен']}")
            print(f"  охват снимка: {охват} поискового итога;"
                  f" сохранено {и['сохранено']} страниц"
                  f" из {и['страниц_в_разрезе']} в разрезе")
            print(f"  контроль: {len(и['контроль'])} случайных адресов из"
                  f" карты, семя {а.seed}")
            for з in и["зарабатывающие"]:
                метка = "; ".join(з["беда"]) if з["беда"] else "исправно"
                print(f"    {з['визиты']:>5} визитов  {з['путь'][:70]:70}"
                      f" {з['код']:>4}  {метка}")
            for к in и["контроль"]:
                метка = "; ".join(к["беда"]) if к["беда"] else "исправно"
                print(f"    контроль   {к['путь'][:70]:70}"
                      f" {к['код']:>4}  {метка}")
            print(f"  ИСХОД: {и['исход']}")
    плохо = [и for и in итоги if и["исход"].startswith("БЕДА")]
    неизмерено = [и for и in итоги if и["исход"].startswith("НЕ ИЗМЕРЕНО")]
    if плохо:
        return 1
    if итоги and len(неизмерено) == len(итоги):
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(главное())
