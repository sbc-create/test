#!/usr/bin/env python3
"""Зарабатывающие страницы целы, и различающий контроль это подтверждает.

Зачем. Спрос витрин сосредоточен: у `animedia.icu` один адрес несёт 32 %
поискового трафика домена, верхние десять — 82.8 %. Потеря доступности ОДНОЙ
такой страницы стоит дороже любой правки, а из общего «сайт отвечает 200»
узнать об этом нельзя: витрина отвечает, пока зарабатывающая страница лежит.

Поэтому проверяются ИМЕННО сохранённые зарабатывающие адреса — каждый по
отдельности, по пяти признакам: код ответа, `robots`, canonical на себя,
непустой `h1` и признак плеера там, где он нужен по замыслу.

РАЗЛИЧАЮЩИЙ КОНТРОЛЬ обязателен, иначе вывод неразличим. Рядом проверяются
случайные адреса той же витрины из её КАРТЫ (семя фиксировано — два прогона
сравнимы). Исходов шесть, и каждый появился из ошибки предыдущей редакции,
найденной живым прогоном:

  исправно                     и зарабатывающие, и контроль целы СЕЙЧАС;
  БЕДА НА ЗАРАБАТЫВАЮЩИХ       плохо только на них при исправном контроле;
  БЕДА В КОНТРОЛЕ              зарабатывающие целы, случайные нет;
  БЕДА ВИТРИНЫ                 плохо и там и там;
  ВИТРИНА ОТКАЗЫВАЕТ / МИГАЕТ  карта не прочитана И сервер отдаёт 5xx: это
                               отказ сервера, а не беда страниц, и контроль
                               собрать неоткуда по той же причине;
  ПРЕДЕЛ ЁМКОСТИ ОТВЕТИЛ       503 с `Retry-After` — объявленный предел, не
                               отказ; но и не норма: обход последовательный.

Отдельной строкой, НЕ бедой, печатаются страницы, закрытые решением витрины:
`X-Robots-Tag` с `noindex` (решение отдающего слоя) или запрет в теле при
открытых соседях (решение преднарендера). Вход на них всё равно идёт, поэтому
они считаются в хвосте исхода. Закрытие считается ТОЛЬКО для страницы,
ответившей 200: обработчик 404 сам отдаёт `noindex`, и однажды этот признак
прикрыл живой 404 на зарабатывающем адресе.

Перечень зарабатывающих берётся из снимка Метрики, а не из головы, и охват
снимка печатается: проверка без охвата читается как проверка всего.

ЧЕГО ЭТОТ ИНСТРУМЕНТ НЕ ДЕЛАЕТ, и дублировать это здесь нельзя: он не
проверяет, объявлен ли адрес в карте — на это есть
`sitemap-demand-coverage.py`, он же независимо подтвердил находку 404. И он не
доказывает воспроизведение видео: признак плеера означает МОНТАЖ в разметке, а
воспроизведение проверяет `playback-check.py`.

    python3 automation/local/earning-pages-guard.py
    python3 automation/local/earning-pages-guard.py --domain animedia.icu --json
    python3 automation/local/earning-pages-guard.py --retries 5   # при мигании

Коды: 0 — беды нет ни у одного домена; 1 — есть беда или отказ витрины; 2 —
НЕ ИЗМЕРЕНО ни по одному домену (карта или снимок не прочитаны). «Не измерено»
никогда не печатается как «исправно».
"""
from __future__ import annotations

import argparse
import json
import random
import re
import time
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СНИМОК = КОРЕНЬ / "config" / "demand-snapshot.json"

АГЕНТ = "factory-earning-pages-guard"
#: Семя по умолчанию — дата первого замера. Случайность с фиксированным семенем
#: даёт СРАВНИМЫЕ прогоны; случайность без семени даёт новый ответ каждый раз.
СЕМЯ = 20261022
#: Сколько случайных адресов брать в контроль. Число печатается: контроль из
#: пяти адресов и контроль из пятидесяти — разные утверждения.
КОНТРОЛЕЙ = 5

#: Сколько раз повторять запрос у адреса, где отказал СЕРВЕР, и пауза между
#: попытками. Один запрос не различает «лежит» и «мигает».
ПОПЫТОК = 3
ПАУЗА_С = 2.0
#: Что считается отказом СЕРВЕРА, а не содержания: 5xx, таймаут, нет ответа.
ОТКАЗ = re.compile(r"^(?:5\d\d|таймаут|—)$")

#: Разделы, где плеера нет по замыслу: главная, каталог, подборки, расписание,
#: топы и новинки. Требовать плеер от них значит выдумать дефект.
БЕЗ_ПЛЕЕРА = re.compile(
    r"^/?$|/catalog|/collections?|/schedule|/genres|/top|/new|/posts|/country")
#: Знак МОНТАЖА плеера в разметке — не доказательство воспроизведения (его
#: проверяет `playback-check.py`). Перечисление измерено 22.10 по одной
#: странице произведения на стек: `data-player-host` есть у питоновского
#: семейства (animedia 4, lordfilm 4, zona 4) и ОТСУТСТВУЕТ у Yummy на
#: Next.js, где общий знак — `data-player` (1). Первая редакция искала
#: `<iframe` и классы `player`: знак не нашёлся ни на одной странице, включая
#: контрольные, — отказ меры, а не беда витрины.
ПРИЗНАК_ПЛЕЕРА = re.compile(
    r"data-player-host|data-player\b|<iframe|class=\"[^\"]*player"
    r"|id=\"[^\"]*player", re.I)
ROBOTS = re.compile(r"<meta[^>]+name=[\"']robots[\"'][^>]*content=[\"']([^\"']*)",
                    re.I)
CANONICAL = re.compile(
    r"<link[^>]+rel=[\"']canonical[\"'][^>]*href=[\"']([^\"']*)", re.I)
H1 = re.compile(r"<h1[^>]*>(.*?)</h1>", re.I | re.S)
АДРЕС_КАРТЫ = re.compile(r"<loc>\s*([^<\s]+)\s*</loc>")


# --- чистые функции: их проверяют тесты, они ничего не читают ---------------

def не_требует_плеера(путь: str) -> bool:
    return bool(БЕЗ_ПЛЕЕРА.search(путь))


def признаки(тело: str, путь: str, домен: str) -> dict:
    """Пять признаков страницы по её телу. Чистая функция.

    Отсутствие тела — это НЕ «признаки плохие», а отсутствие измерения:
    поля остаются None, и `беда()` их таковыми не считает.
    """
    если_нет = {"robots": None, "canonical": None, "h1": None, "плеер": None}
    if not тело:
        return если_нет
    м_r = ROBOTS.search(тело)
    м_c = CANONICAL.search(тело)
    м_h = H1.search(тело)
    текст_h1 = re.sub(r"<[^>]+>", "", м_h.group(1)).strip() if м_h else ""
    канон = (м_c.group(1) or "").strip() if м_c else ""
    свой = ""
    if канон:
        путь_канона = re.sub(r"^https?://[^/]+", "", канон) or "/"
        свой = "на себя" if путь_канона.rstrip("/") == путь.rstrip("/") \
            else f"на {путь_канона}"
    return {
        "robots": (м_r.group(1) or "").strip().lower() if м_r else "",
        "canonical": свой,
        "h1": текст_h1,
        "плеер": (None if не_требует_плеера(путь)
                  else bool(ПРИЗНАК_ПЛЕЕРА.search(тело))),
    }


def беда(запись: dict) -> list[str]:
    """Чем именно страница плоха. Пустой перечень — страница исправна.

    Неизмеренный признак (None) бедой не считается: «не измерено» — не «плохо».
    """
    из_чего = []
    код = str(запись.get("код") or "")
    if предел_ёмкости(запись):
        # Страницу не отдали — умалчивать нельзя; но это объявленный предел,
        # а не отказ, и запись обязана их различать.
        #
        # И это НЕ норма. Сторож ходит по адресам ПОСЛЕДОВАТЕЛЬНО, с паузами:
        # при таком обходе предел одновременных запросов срабатывать не должен
        # вообще. Если он сработал — находка «предел мал или отрисовка
        # медленная», и она называется прямо в строке, иначе ожидаемый код
        # прочтут как «всё в порядке». Оговорку назвала линия, выпускающая
        # предел (T323), и я с ней согласна.
        повторы = (f"; устойчиво: отказов {запись['отказов']}"
                   f" из {запись['попыток']} попыток"
                   if (запись.get("отказов") or 0) > 1 else "")
        return [f"предел ёмкости на ПОСЛЕДОВАТЕЛЬНОМ запросе: 503 с"
                f" Retry-After {str(запись.get('retry_after')).strip()}"
                f" — предел мал или отрисовка медленная{повторы}"]
    if код and код != "200":
        # Страница не ответила — её содержание не толкуется вовсе. Иначе в
        # строке 404 появлялось «закрыта по маршруту» из `noindex`, который
        # ставит сам обработчик ошибки, и запись спорила сама с собой.
        return [f"код {код}"]
    п = запись.get("признаки") or {}
    r = п.get("robots")
    if r is not None and r != "" and "noindex" in r:
        if закрыто_намеренно(запись):
            # Решение витрины, объявленное отдающим слоем. Не беда — но и не
            # молчание: на закрытую страницу идут поисковые входы, и это
            # сказано прямо.
            из_чего.append(
                f"закрыта НАМЕРЕННО: X-Robots-Tag «{запись['x_robots']}»"
                f" совпадает с телом — решение витрины, не потеря; вход на"
                f" закрытую страницу всё же идёт")
        elif запись.get("соседи_открыты"):
            # Закрыт МАРШРУТ, а не витрина: в этом же прогоне у домена есть
            # страницы с открытым телом. Устаревший снимок закрывал витрину
            # целиком — здесь это не он.
            из_чего.append(
                f"закрыта ПО МАРШРУТУ: robots «{r}» в теле, заголовка"
                f" X-Robots-Tag нет, но у соседних страниц того же домена"
                f" тело открыто — решение преднарендера, не устаревший снимок"
                f" витрины. Объявлен ли маршрут в карте — вопрос к"
                f" sitemap-demand-coverage.py")
        else:
            из_чего.append(
                f"robots «{r}» в ТЕЛЕ, заголовка X-Robots-Tag нет, и ни одной"
                f" открытой страницы у домена в этом прогоне — похоже на"
                f" устаревший преднаренденный снимок ВИТРИНЫ (класс"
                f" wire-yummy-robots), а не на решение по маршруту")
    if r == "":
        из_чего.append("robots отсутствует")
    к = п.get("canonical")
    if к is not None and к != "" and к != "на себя":
        из_чего.append(f"canonical {к}")
    h = п.get("h1")
    if h is not None and not h:
        из_чего.append("h1 пуст")
    if п.get("плеер") is False:
        из_чего.append("признака плеера нет")
    return из_чего


def закрыто_намеренно(запись: dict) -> bool:
    """Запрет индексации объявлен ОТДАЮЩИМ СЛОЕМ, а не только телом.

    Измерено 23.10: у питоновского семейства режим печатает `X-Robots-Tag` на
    каждой странице (`index, follow` у открытых, `noindex, follow` у
    `/search/`), а у Yummy заголовка нет вовсе и запрет живёт только в
    преднаренденном теле — где устаревший `noindex` известен как отдельный
    класс. Поэтому заголовок считается решением витрины, а тело без заголовка
    — подозрением.
    """
    # ТОЛЬКО для страницы, которая ответила 200. Найдено регрессией этой же
    # правки: страница 404 отдаёт `noindex` и в теле, и в заголовке — так
    # устроен обработчик ошибки, — и 404 на зарабатывающем адресе
    # `lordserials22.info/title/akademiya-minerva/` оказался прикрыт как
    # «закрыто намеренно». Код ответа сильнее любого запрета: страницы нет.
    if str(запись.get("код") or "") != "200":
        return False
    тело = str((запись.get("признаки") or {}).get("robots") or "")
    заг = str(запись.get("x_robots") or "")
    return "noindex" in тело.lower() and "noindex" in заг.lower()


def закрыто_маршрутом(запись: dict) -> bool:
    """Запрет в теле при ОТКРЫТЫХ соседях того же домена. Чистая функция.

    Слабее заголовка, но решением остаётся: устаревший снимок закрывал витрину
    целиком, а здесь закрыт маршрут при открытых соседях.
    """
    if str(запись.get("код") or "") != "200":
        return False
    тело = str((запись.get("признаки") or {}).get("robots") or "").lower()
    return ("noindex" in тело and not закрыто_намеренно(запись)
            and bool(запись.get("соседи_открыты")))


def закрыта(запись: dict) -> bool:
    """Закрыта РЕШЕНИЕМ витрины — заголовком или по маршруту.

    Такая страница не считается потерей: исход, навсегда ставший «БЕДОЙ»
    из-за намеренно закрытого `/search/`, прячет настоящую находку, когда та
    появится. Но и молчать нельзя — обе разновидности печатаются отдельной
    строкой и считаются в хвосте исхода.
    """
    return закрыто_намеренно(запись) or закрыто_маршрутом(запись)


def предел_ёмкости(запись: dict) -> bool:
    """Ответил ли ОБЪЯВЛЕННЫЙ предел ёмкости, а не отказ. Чистая функция.

    Признак один и он обязателен целиком: код 503 И непустой `Retry-After`.
    503 без него отказом и остаётся — объявления нет, значит и предела нет,
    о котором можно говорить.
    """
    return (str(запись.get("код") or "") == "503"
            and bool(str(запись.get("retry_after") or "").strip()))


def отказавшие(набор: list[dict]) -> list[dict]:
    """Адреса, где отказал СЕРВЕР (5xx, таймаут, нет ответа). Чистая.

    Объявленный предел ёмкости сюда НЕ входит: витрина ответила так, как
    задумано, и называть это отказом значит создать ложное событие.
    """
    return [з for з in набор
            if ОТКАЗ.match(str(з.get("код") or "—"))
            and not предел_ёмкости(з)]


def исход(зарабатывающие: list[dict], контроль: list[dict],
          карта_прочитана: bool = True) -> str:
    """Различающий вывод по двум наборам. Без контроля вывода НЕТ.

    Исключение одно, и оно измерено: если карта НЕ прочитана и среди
    зарабатывающих есть отказ сервера, контроль собирать неоткуда по той же
    причине, по которой лежат страницы. Называть это «не измерено» значит
    потерять уже добытое знание; называть «бедой зарабатывающих» — соврать:
    5xx есть свойство сервера, а не содержания страницы.
    """
    if not зарабатывающие:
        return "НЕ ИЗМЕРЕНО: зарабатывающих страниц в снимке нет"
    if not карта_прочитана and отказавшие(зарабатывающие):
        отк = отказавшие(зарабатывающие)
        мигают = [з for з in отк
                  if (з.get("отказов") or 0) < (з.get("попыток") or 1)]
        вид = "МИГАЕТ" if мигают else "ОТКАЗЫВАЕТ"
        return (f"ВИТРИНА {вид}: карта не прочитана и сервер отказал"
                f" на {len(отк)} из {len(зарабатывающие)} зарабатывающих"
                f" (коды {', '.join(sorted({str(з['код']) for з in отк}))})."
                f" Это отказ сервера, а не беда страниц; контроль собрать"
                f" неоткуда по той же причине")
    if not контроль:
        return "НЕ ИЗМЕРЕНО: контроль не собран, вывод неразличим"
    пределы = [з for з in зарабатывающие + контроль if предел_ёмкости(з)]
    закрытые = [з for з in зарабатывающие + контроль if закрыто_намеренно(з)]
    маршрутом = [з for з in зарабатывающие + контроль
                 if закрыто_маршрутом(з)]
    плохо_з = [з for з in зарабатывающие if беда(з) and not закрыта(з)]
    плохо_к = [к for к in контроль if беда(к) and not закрыта(к)]
    части = []
    if закрытые:
        части.append(f"{len(закрытые)} закрыто намеренно (X-Robots-Tag)")
    if маршрутом:
        части.append(f"{len(маршрутом)} закрыто по маршруту (запрет в теле"
                     f" при открытых соседях)")
    хвост = (f"; отдельно: {'; '.join(части)} — вход на них всё равно идёт"
             if части else "")
    if пределы and len(пределы) == len(плохо_з) + len(плохо_к):
        return (f"ПРЕДЕЛ ЁМКОСТИ ОТВЕТИЛ НА ПОСЛЕДОВАТЕЛЬНОМ ОБХОДЕ:"
                f" {len(пределы)} адресов из"
                f" {len(зарабатывающие) + len(контроль)} получили 503 с"
                f" Retry-After. Отказом витрины это не считается, но и нормой"
                f" не является: обход идёт по одному адресу с паузами, и"
                f" предел одновременных запросов при нём срабатывать не"
                f" должен — значит предел мал или отрисовка медленная."
                f" Страницу в этот раз всё же не отдали")
    if плохо_з and плохо_к:
        return ("БЕДА ВИТРИНЫ: плохо и на зарабатывающих, и в контроле"
                + хвост)
    if плохо_з:
        return (f"БЕДА НА ЗАРАБАТЫВАЮЩИХ: {len(плохо_з)}"
                f" из {len(зарабатывающие)} при исправном контроле" + хвост)
    if плохо_к:
        return (f"БЕДА В КОНТРОЛЕ: зарабатывающие целы, но {len(плохо_к)}"
                f" из {len(контроль)} случайных плохи" + хвост)
    return (f"исправно: {len(зарабатывающие)} из {len(зарабатывающие)}"
            f" зарабатывающих и {len(контроль)} из {len(контроль)} контрольных"
            + хвост)


def выборка(адреса: list[str], семя: int, сколько: int) -> list[str]:
    """Случайные адреса с фиксированным семенем. Чистая функция."""
    уникальные = sorted(set(адреса))
    if len(уникальные) <= сколько:
        return уникальные
    return random.Random(семя).sample(уникальные, сколько)


def адреса_карты(тело: str) -> tuple[list[str], list[str]]:
    """Адреса из карты: (части индекса, страницы). Чистая функция."""
    все = АДРЕС_КАРТЫ.findall(тело or "")
    части = [а for а in все if "sitemap" in а]
    страницы = [а for а in все if "sitemap" not in а]
    return части, страницы


# --- чтение сети: отдельно от разбора ---------------------------------------

def достать(url: str, таймаут: int = 60) -> tuple[str, str]:
    try:
        р = subprocess.run(
            ["curl", "-sSL", "--max-time", str(таймаут),
             "-w", "\n@@%{http_code}", "-H", f"User-Agent: {АГЕНТ}", url],
            capture_output=True, text=True, timeout=таймаут + 30)
    except (subprocess.TimeoutExpired, OSError):
        return "таймаут", ""
    т = р.stdout
    if "@@" not in т:
        return "—", т
    тело, код = т.rsplit("@@", 1)
    return код.strip(), тело


def заголовок(url: str, имя: str, таймаут: int = 30) -> str:
    """Один заголовок ответа через HEAD. Пусто — не прочитан.

    Запрос делается ТОЛЬКО при коде 503: витрине, у которой сработал предел,
    лишние запросы не нужны. HEAD может обслуживаться иначе, чем GET, — если
    заголовка нет, запись останавливается на «не прочитан», а не домысливает.
    """
    try:
        р = subprocess.run(
            ["curl", "-sSI", "--max-time", str(таймаут),
             "-H", f"User-Agent: {АГЕНТ}", url],
            capture_output=True, text=True, timeout=таймаут + 15)
    except (subprocess.TimeoutExpired, OSError):
        return ""
    for строка in (р.stdout or "").splitlines():
        if ":" in строка:
            ключ, значение = строка.split(":", 1)
            if ключ.strip().lower() == имя.lower():
                return значение.strip()
    return ""


def проверить_адрес(домен: str, путь: str, попыток: int = ПОПЫТОК) -> dict:
    """Один адрес, с повтором при отказе сервера.

    ИСПРАВЛЕНИЕ СОБСТВЕННОГО ВЫВОДА (23.10). Сначала я обосновала повтор своими
    двумя замерами: в 05:47:40Z девять из десяти зарабатывающих адресов
    `animedia.icu` отдали 502, в 05:48:17Z те же адреса ответили 200 — и
    назвала это миганием. Это неверно: соседняя линия показала перезапуск
    процесса в 05:47:58Z (pid 427102, выпуск ПРЕЖНИЙ 9a52f800ade1, прежнего
    pid 629446 в /proc нет), то есть мой прогон попал в окно перезапуска, когда
    апстрим не слушает и nginx отдаёт 502. Два моих замера различают «лежала и
    перезапустили», а не «мигает».

    Повтор всё равно нужен, и обоснование у него ДРУГОЕ, измеренное той же
    линией ДО перезапуска: `robots.txt` попеременно отдавал `Allow` и
    `Disallow: /`, карта 404 при живом `healthz`. Вот это мигание, и одиночный
    запрос против него бессилен в обе стороны: случайно попавший удачный ответ
    читается как «исправно», случайный отказ — как «лежит». Поэтому
    записывается доля отказавших попыток, а не последний код.
    """
    коды: list[str] = []
    тело = ""
    for номер in range(max(1, попыток)):
        код, т = достать(f"https://{домен}{путь}")
        коды.append(код)
        if not ОТКАЗ.match(код):
            тело = т
            break
        if номер + 1 < max(1, попыток):
            time.sleep(ПАУЗА_С)
    отказов = len([к for к in коды if ОТКАЗ.match(к)])
    з = {"путь": путь, "код": коды[-1],
         "попыток": len(коды), "отказов": отказов,
         "признаки": признаки(тело, путь, домен)}
    if коды[-1] == "503":
        з["retry_after"] = заголовок(f"https://{домен}{путь}", "Retry-After")
    if "noindex" in str((з["признаки"] or {}).get("robots") or "").lower():
        # Только при запрете в теле: у открытой страницы спрашивать нечего.
        з["x_robots"] = заголовок(f"https://{домен}{путь}", "X-Robots-Tag")
    з["беда"] = беда(з)
    if отказов and отказов < len(коды):
        з["беда"] = ([f"мигает: отказов {отказов} из {len(коды)}"
                      f" (коды {', '.join(коды)})"] + з["беда"])
    return з


def контрольные_пути(домен: str, семя: int, сколько: int) -> list[str]:
    """Случайные пути витрины ИЗ ЕЁ КАРТЫ. Пусто — карта не прочитана."""
    код, тело = достать(f"https://{домен}/sitemap.xml")
    if код != "200":
        return []
    части, страницы = адреса_карты(тело)
    if части:
        код2, тело2 = достать(части[0])
        if код2 == "200":
            _, страницы = адреса_карты(тело2)
    пути = [re.sub(r"^https?://[^/]+", "", а) or "/" for а in страницы]
    return выборка([п for п in пути if п], семя, сколько)


def уточнить_закрытия(записи: list[dict]) -> None:
    """Дописать каждой записи, открыты ли СОСЕДНИЕ страницы того же домена.

    Это различает «закрыт маршрут» от «закрыта витрина устаревшим снимком», и
    считается по уже собранным ответам — новых запросов не делается. Беда
    пересчитывается, потому что признак появляется только когда домен пройден
    целиком.
    """
    открытые = [з for з in записи
                if "index" in str((з.get("признаки") or {}).get("robots") or "")
                and "noindex" not in
                str((з.get("признаки") or {}).get("robots") or "")]
    for з in записи:
        з["соседи_открыты"] = bool(открытые)
        з["беда"] = беда(з)
        if (з.get("отказов") or 0) and (з["отказов"] < (з.get("попыток") or 1)):
            з["беда"] = ([f"мигает: отказов {з['отказов']}"
                          f" из {з['попыток']}"] + з["беда"])


def проверить_домен(запись: dict, семя: int, сколько: int,
                   попыток: int = ПОПЫТОК) -> dict:
    домен = запись["domain"]
    страницы = запись.get("search_landing_pages") or []
    итог = {
        "домен": домен,
        "охват_снимка": запись.get("search_landing_covered"),
        "страниц_в_разрезе": запись.get("search_pages_total"),
        "сохранено": len(страницы),
        "зарабатывающие": [],
        "контроль": [],
    }
    for с in страницы:
        проверка = проверить_адрес(домен, с.get("page") or "/", попыток)
        проверка["визиты"] = с.get("visits")
        итог["зарабатывающие"].append(проверка)
    пути = контрольные_пути(домен, семя, сколько)
    итог["карта_прочитана"] = bool(пути)
    for путь in пути:
        итог["контроль"].append(проверить_адрес(домен, путь, попыток))
    уточнить_закрытия(итог["зарабатывающие"] + итог["контроль"])
    итог["исход"] = исход(итог["зарабатывающие"], итог["контроль"],
                          итог["карта_прочитана"])
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", help="один домен вместо всех из снимка")
    р.add_argument("--seed", type=int, default=СЕМЯ)
    р.add_argument("--controls", type=int, default=КОНТРОЛЕЙ)
    р.add_argument("--retries", type=int, default=ПОПЫТОК,
                   help="повторов запроса при отказе сервера (по умолчанию"
                        f" {ПОПЫТОК})")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    if not СНИМОК.is_file():
        print(f"НЕ ИЗМЕРЕНО: снимка спроса нет ({СНИМОК})", file=sys.stderr)
        return 2
    снимок = json.loads(СНИМОК.read_text(encoding="utf-8"))
    записи = [з for з in снимок.get("domains") or []
              if з.get("search_landing_pages")]
    if а.domain:
        записи = [з for з in записи if з["domain"] == а.domain]
        if not записи:
            print(f"НЕ ИЗМЕРЕНО: у {а.domain} сохранённых зарабатывающих"
                  " страниц в снимке нет", file=sys.stderr)
            return 2

    итоги = [проверить_домен(з, а.seed, а.controls, а.retries)
             for з in записи]
    if а.json:
        print(json.dumps({"snapshot": снимок.get("snapshot"),
                          "seed": а.seed, "итоги": итоги},
                         ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            охват = ("не назван" if и["охват_снимка"] is None
                     else f"{и['охват_снимка']} %")
            print(f"{и['домен']}")
            print(f"  охват снимка: {охват} поискового итога;"
                  f" сохранено {и['сохранено']} страниц"
                  f" из {и['страниц_в_разрезе']} в разрезе")
            print(f"  контроль: {len(и['контроль'])} случайных адресов из"
                  f" карты, семя {а.seed}")
            for з in и["зарабатывающие"]:
                метка = "; ".join(з["беда"]) if з["беда"] else "исправно"
                print(f"    {з['визиты']:>5} визитов  {з['путь'][:70]:70}"
                      f" {з['код']:>4}  {метка}")
            for к in и["контроль"]:
                метка = "; ".join(к["беда"]) if к["беда"] else "исправно"
                print(f"    контроль   {к['путь'][:70]:70}"
                      f" {к['код']:>4}  {метка}")
            print(f"  ИСХОД: {и['исход']}")
    плохо = [и for и in итоги
             if и["исход"].startswith(("БЕДА", "ВИТРИНА"))]
    неизмерено = [и for и in итоги if и["исход"].startswith("НЕ ИЗМЕРЕНО")]
    if плохо:
        return 1
    if итоги and len(неизмерено) == len(итоги):
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(главное())
