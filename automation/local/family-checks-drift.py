"""Наборы проверок у РОДСТВЕННЫХ ячеек: где защиты нет там, где она нужна.

Зачем. 12.10 выпуск на `an1mego.site` снёс со страниц тайтлов «Тип», «Эпизоды»
и «Статус»: переменная `пары` была переприсвоена в методе характеристик.
Поймала это проверка `data_chain` — которая есть у `an1meg0-site` и
ОТСУТСТВУЕТ у `an1mego-site`. То есть на витрине, куда правка пошла, проверки
не было, и регрессия доехала до посетителя.

Ячейки одного семейства исполняют один код, значит и защита у них должна быть
одна. Но не всякое расхождение — дефект, и смешивать их нельзя, иначе вывод
станет шумом. Три разряда:

  БЕЗ ЗАЩИТЫ У РОДНИ  проверка есть у ЧАСТИ ячеек семейства и нет у
                      остальных. Это и есть сигнал: те, у кого она есть,
                      доказывают, что она применима, а остальные остались без
                      неё — ровно так проехала регрессия an1mego. Шаблонная
                      проверка здесь тяжелее своей, и это помечается
  СВОЯ ПРОВЕРКА       имя несёт метку конкретной ячейки (`lords02_*`).
                      Расхождение ожидаемо: проверка писалась для одной витрины
  СЕМЕЙСТВО НЕ НЕСЁТ  шаблонной проверки нет НИ У ОДНОЙ ячейки семейства.
                      НЕ дефект: набор шаблонов фабрики не универсальная
                      основа, ячейки несут относящееся к ним подмножество.
                      Печатается справочно и в счёт не идёт

Ничего не меняет: только читает рабочие копии ячеек.

    python3 automation/local/family-checks-drift.py
    python3 automation/local/family-checks-drift.py --family AnimeGo
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ШАБЛОНЫ = КОРЕНЬ / "factory" / "cell" / "site_checks"
ЯЧЕЙКИ = Path("/home/claude/wt-portable-site-cell-01/var/site-repos")

#: Семейства по рабочим копиям. Перечень не угадывается по имени каталога:
#: `site-1lordserials1-online` и `lordserials22-info` на имя не похожи, а
#: семейство одно.
СЕМЕЙСТВА: dict[str, tuple[str, ...]] = {
    "AnimeGo": ("an1mego-site", "animeg0-site", "an1meg0-site"),
    "Lords": ("lordfilm47-space", "lordserial33-biz",
              "site-1lordserials1-online", "lordserials22-info",
              "lordfilm077-site", "lordserial101-site",
              "lordserials22-site", "lordserials22-space"),
    "Zona": ("zonafilm-space", "zonafilm-cc", "zonafilm12-site"),
    "Animedia": ("animedia-icu", "animedia-space"),
    "Yummy": ("yummyani-biz", "yummyani-org", "yummyani-site",
              "yummyani7-info", "yummyani7-site"),
}

#: Имя со меткой конкретной ячейки: `lords02_history`, `zona03_feeds`.
СВОЯ = re.compile(r"^(?:lords|zona|animego|animedia|yummy)\d+_")

БЕЗ_ЗАЩИТЫ = "БЕЗ ЗАЩИТЫ У РОДНИ"
СВОЯ_ПРОВЕРКА = "своя проверка"
ПОД_ДРУГИМ_ИМЕНЕМ = "возможно под другим именем"

#: Слова, по которым узнаётся та же забота под другим именем. Короткие
#: служебные части (`no`, `check`, `test`) исключены: по ним совпало бы всё.
_НЕЗНАЧИМЫЕ = {"no", "not", "check", "checks", "test", "and", "or", "the",
               "is", "in", "of", "present", "wired"}


def слова(имя: str) -> set[str]:
    return {ч for ч in имя.split("_") if ч and ч not in _НЕЗНАЧИМЫЕ}


def похожая(имя: str, свои: set[str]) -> str:
    """Имя проверки ячейки, несущей ту же заботу, либо пустая строка.

    Нужна, чтобы переименование не выглядело потерей: у `zonafilm-cc` нет
    `no_secrets.py`, но есть `no_data_or_secrets.py` — защита не отсутствует,
    она слабее, и это другой вывод.
    """
    цель = слова(имя)
    if not цель:
        return ""
    for чужое in sorted(свои):
        if цель & слова(чужое):
            return чужое
    return ""


def шаблонные(каталог: Path) -> set[str]:
    if not каталог.is_dir():
        return set()
    return {ф.stem for ф in каталог.glob("*.py") if ф.stem != "__init__"}


def набор(ячейка: Path) -> set[str] | None:
    """Имена проверок ячейки, либо None если каталога проверок нет."""
    к = ячейка / "checks"
    if not к.is_dir():
        return None
    return {ф.stem for ф in к.glob("*.py") if ф.stem != "__init__"}


def разряд(имя: str, шаблон: set[str]) -> str:
    """Разряд расхождения. Шаблонность — мера тяжести, а не отдельный разряд.

    Проверка с меткой одной ячейки расходится ожидаемо. Всё остальное, что
    есть у части родни и нет у остальных, — сигнал: применимость доказана
    теми, у кого она есть.
    """
    if СВОЯ.match(имя):
        return СВОЯ_ПРОВЕРКА
    return БЕЗ_ЗАЩИТЫ + (" (шаблон фабрики)" if имя in шаблон else "")


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--repos", type=Path, default=ЯЧЕЙКИ)
    р.add_argument("--templates", type=Path, default=ШАБЛОНЫ)
    р.add_argument("--family", default="")
    опции = р.parse_args(аргв)

    шаблон = шаблонные(опции.templates)
    if not шаблон:
        print(f"шаблонов проверок нет в {опции.templates} — это предел "
              "измерения, а не исправность", file=sys.stderr)
        return 2

    без_защиты = 0
    шаблонных = 0
    переименований = 0
    for имя, ячейки in СЕМЕЙСТВА.items():
        if опции.family and имя != опции.family:
            continue
        наборы: dict[str, set[str]] = {}
        нет_проверок: list[str] = []
        for я in ячейки:
            н = набор(опции.repos / я)
            if н is None:
                нет_проверок.append(я)
            else:
                наборы[я] = н
        print(f"\n=== {имя}: ячеек с проверками {len(наборы)}"
              + (f", без каталога проверок {len(нет_проверок)}"
                 if нет_проверок else ""))
        if нет_проверок:
            print(f"   [не измерено] без checks/: {', '.join(нет_проверок)}")
        if len(наборы) < 2:
            print("   сравнивать нечего: нужно хотя бы две ячейки")
            continue

        все = set().union(*наборы.values())
        общие = set.intersection(*наборы.values())
        for проверка in sorted(все - общие):
            у_кого = sorted(я for я, н in наборы.items() if проверка in н)
            нет_у = sorted(я for я, н in наборы.items() if проверка not in н)
            вид = разряд(проверка, шаблон)
            if вид == СВОЯ_ПРОВЕРКА:
                print(f"   [ок] {проверка:32s} {вид}")
                print(f"        есть у {len(у_кого)}, нет у: "
                      f"{', '.join(нет_у)}")
                continue
            # Переименование — не потеря. Разделяем тех, у кого есть похожая
            # проверка, и тех, у кого нет ничего близкого.
            с_похожей: list[str] = []
            совсем_без: list[str] = []
            for я in нет_у:
                близкая = похожая(проверка, наборы[я])
                (с_похожей if близкая else совсем_без).append(
                    f"{я} (есть {близкая})" if близкая else я)
            if совсем_без:
                без_защиты += len(совсем_без)
                шаблонных += len(совсем_без) if проверка in шаблон else 0
                знак = "[!!]" if проверка in шаблон else "[! ]"
                print(f"   {знак} {проверка:32s} {вид}")
                print(f"        есть у {len(у_кого)}, нет у: "
                      f"{', '.join(совсем_без)}")
            if с_похожей:
                переименований += len(с_похожей)
                print(f"   [? ] {проверка:32s} {ПОД_ДРУГИМ_ИМЕНЕМ}")
                print(f"        {', '.join(с_похожей)} — сверить СОДЕРЖАНИЕ: "
                      "имя совпадает по смыслу, покрытие не измерено")

        # Потеря шаблона у ВСЕХ ячеек семейства не попадает в разницу наборов:
        # она одинакова, и её надо искать отдельно. Иначе семейство, целиком
        # потерявшее проверку, выглядело бы согласованным.
        # Отсутствие шаблона у ВСЕГО семейства — не дефект: набор шаблонов
        # фабрики не универсальная основа, и ячейки несут относящееся к ним
        # подмножество. Печатается справочно, в счёт не идёт.
        у_всех_нет = sorted(шаблон - все)
        if у_всех_нет:
            print(f"   [--] семейство не несёт (в счёт не идёт): "
                  f"{', '.join(у_всех_нет)}")

    print(f"\nячейка x проверка без защиты, которая есть у родни: "
          f"{без_защиты}")
    print(f"   из них шаблонных проверок фабрики: {шаблонных}")
    print(f"   возможных переименований: {переименований} — предел измерения: "
          "сравнение идёт по ИМЕНАМ, покрытие переименованной проверки "
          "инструмент не знает")
    print("«своя проверка» и «семейство не несёт» в счёт не идут: первое — "
          "метка одной ячейки, второе — набор, которым семейство не "
          "пользуется")
    if шаблонных:
        return 1
    return 3 if без_защиты else 0


if __name__ == "__main__":
    raise SystemExit(главное())
