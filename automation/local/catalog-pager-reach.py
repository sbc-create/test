#!/usr/bin/env python3
"""До какой страницы каталога ДОХОДИТ посетитель и обходчик. Только чтение.

Повод — D4/MOD-108: листалка Yummy объявляет 350 страниц по провайдерскому
`total` (8 378 / 24), а содержимое кончается на 334-й: 80 запросов × 100 записей
= 8 000. Страницы с 335-й отдают 200 и ноль карточек, и 378 живых работ
каталога недостижимы.

Проверка отвечает на три разных вопроса, и путать их нельзя:

* **объявлено** — сколько страниц обещает сама листалка (максимальный номер в
  её ссылках);
* **доходит** — номер последней страницы, на которой ЕСТЬ карточки, найденный
  двоичным поиском, и сколько карточек на ней;
* **каталог** — сколько записей витрина объявляет о себе («Найдено N»).

Расхождение «доходит × размер страницы» против «каталог» и есть недостижимая
часть. Признак, который обязан падать при неисправленном состоянии: охват,
кратный 8 000.

ЧТО ЭТА ПРОВЕРКА НЕ ГОВОРИТ: что недостижимые работы отсутствуют в карте сайта.
Карта и просмотр — разные пути, и у Yummy они обрезаны РАЗНЫМИ пределами
(`maxPages = 300` в обходе карты против плоских 80 запросов в просмотре). Их
числа сравниваются отдельно, а не подменяют друг друга.

    python3 automation/local/catalog-pager-reach.py yummyani7.info
    python3 automation/local/catalog-pager-reach.py --all --json
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys

АГЕНТ = "factory-catalog-pager-reach"

ВИТРИНЫ = ("yummyani.site", "yummyani.org", "yummyani.biz",
           "yummyani7.site", "yummyani7.info")
РАЗМЕР_СТРАНИЦЫ = 24


def достать(адрес: str, таймаут: int = 45) -> str | None:
    try:
        г = subprocess.run(["curl", "-A", АГЕНТ, "-sSL", "-w", "\n@@КОД@@%{http_code}",
                            "--max-time", str(таймаут), адрес],
                           capture_output=True, text=True, timeout=таймаут + 20)
    except subprocess.TimeoutExpired:
        return None
    тело, _, код = г.stdout.rpartition("@@КОД@@")
    return тело if код.strip() == "200" else None


def карточки(тело: str) -> set[str]:
    return set(re.findall(r'href="(/anime/[^"#?]+)"', тело))


def число_найденного(тело: str) -> int | None:
    for шаблон in (r"Найдено[^\d]{0,20}([\d\s ]{1,12})",
                   r"записей[^\d]{0,12}([\d\s ]{1,12})"):
        м = re.search(шаблон, тело)
        if м:
            цифры = re.sub(r"[^\d]", "", м.group(1))
            if цифры:
                return int(цифры)
    return None


def объявлено_страниц(тело: str) -> int | None:
    номера = [int(н) for н in re.findall(r"[?&]page=(\d+)", тело)]
    return max(номера) if номера else None


def страница(домен: str, номер: int) -> tuple[int, str] | None:
    """`(карточек, тело)` или None, если страница не прочитана."""
    хвост = "" if номер <= 1 else f"?page={номер}"
    тело = достать(f"https://{домен}/catalog/{хвост}")
    if тело is None:
        return None
    return len(карточки(тело)), тело


def последняя_с_содержимым(домен: str, предел: int) -> tuple[int, int, int]:
    """Двоичный поиск последней непустой страницы. Возвращает `(номер, карточек, запросов)`."""
    запросов = 0
    низ, верх = 1, предел
    лучший, лучших_карточек = 1, 0
    while низ <= верх:
        середина = (низ + верх) // 2
        ответ = страница(домен, середина)
        запросов += 1
        if ответ is None:
            # Непрочитанная страница не значит «пусто»: сдвигаемся вниз, но
            # запоминаем, что здесь измерения нет.
            верх = середина - 1
            continue
        сколько, _ = ответ
        if сколько > 0:
            лучший, лучших_карточек = середина, сколько
            низ = середина + 1
        else:
            верх = середина - 1
    return лучший, лучших_карточек, запросов


def проверить(домен: str, образцы: tuple[int, ...] = (1, 100)) -> dict:
    итог: dict = {"домен": домен, "замечания": []}
    первая = страница(домен, 1)
    if первая is None:
        итог["измерено"] = False
        итог["замечания"].append("каталог не прочитан — НЕ ИЗМЕРЕНО")
        return итог
    _, тело = первая
    итог["измерено"] = True
    итог["объявлено_страниц"] = объявлено_страниц(тело)
    итог["каталог_записей"] = число_найденного(тело)
    предел = итог["объявлено_страниц"] or 400
    номер, карточек, запросов = последняя_с_содержимым(домен, предел)
    итог["доходит_до_страницы"] = номер
    итог["карточек_на_ней"] = карточек
    итог["запросов_поиска"] = запросов
    охват = (номер - 1) * РАЗМЕР_СТРАНИЦЫ + карточек
    итог["охват_записей"] = охват
    итог["образцы"] = {}
    for н in образцы:
        ответ = страница(домен, н)
        итог["образцы"][н] = sorted(карточки(ответ[1]))[:200] if ответ else None
    всего = итог["каталог_записей"]
    if всего and охват < всего:
        итог["недостижимо"] = всего - охват
        итог["замечания"].append(
            f"доступ обрезан: доходит {охват} записей из {всего},"
            f" недостижимо {всего - охват}")
    if охват % 1000 == 0:
        итог["замечания"].append(
            f"охват кратен тысяче ({охват}) — признак предела в обходе, а не"
            f" конца каталога")
    if итог["объявлено_страниц"] and номер < итог["объявлено_страниц"]:
        итог["замечания"].append(
            f"страницы с {номер + 1} по {итог['объявлено_страниц']} объявлены"
            f" листалкой и пусты")
    return итог


def напечатать(и: dict) -> None:
    if not и.get("измерено"):
        print(f"[не изм.] {и['домен']}: {'; '.join(и['замечания'])}")
        return
    метка = "НЕТ" if и["замечания"] else "ок "
    print(f"[{метка}] {и['домен']}: объявлено страниц"
          f" {и['объявлено_страниц']}, доходит до {и['доходит_до_страницы']}"
          f" ({и['карточек_на_ней']} карточек), охват {и['охват_записей']}"
          f" записей, каталог {и['каталог_записей']},"
          f" запросов поиска {и['запросов_поиска']}")
    for з in и["замечания"]:
        print(f"       → {з}")


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("домены", nargs="*")
    р.add_argument("--all", action="store_true")
    р.add_argument("--json", action="store_true")
    р.add_argument("--samples", default="1,100",
                   help="номера страниц, состав которых сохранить для сверки")
    а = р.parse_args(аргв)
    домены = а.домены or (list(ВИТРИНЫ) if а.all else [])
    if not домены:
        print("не названо ни одной витрины: домен или --all")
        return 2
    образцы = tuple(int(ч) for ч in а.samples.split(",") if ч.strip())
    итоги = [проверить(д, образцы) for д in домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            напечатать(и)
        плохих = [и["домен"] for и in итоги if и.get("замечания")]
        print(f"\nвитрин проверено {len(итоги)}, с замечаниями {len(плохих)}"
              f"{': ' + ', '.join(плохих) if плохих else ''}")
    return 1 if any(и.get("замечания") for и in итоги) else 0


if __name__ == "__main__":
    sys.exit(main())
