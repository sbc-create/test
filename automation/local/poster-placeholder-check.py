#!/usr/bin/env python3
"""Видна ли буква-заглушка ПОВЕРХ загруженного постера. Только чтение.

Повод. Владелец сообщил: на карточках поверх загруженных постеров видны
буквы-заглушки. Разметка карточки такая (пример семейства Lords):

    <span class="zt__p">
      <span class="zt__none" aria-hidden="true"><b>Ж</b></span>
      <img class="zt__img" src="https://poster.cdnvideohub.com/….webp" …>
    </span>

Заглушка лежит в разметке ВСЕГДА, а порядок отрисовки решает CSS. По правилам
наложения в одном контексте позиционированный элемент (`position:absolute`)
рисуется ПОВЕРХ непозиционированного, даже если тот идёт позже в разметке.
Поэтому если у картинки карточки нет ни `position`, ни `z-index`, буква
оказывается над картинкой. Проверка измеряет ровно это: правила, а не
впечатление.

Семейства карточек НЕ перечислены в коде. Первая редакция знала только про
`zt__*` — и пропустила бы `c__none`/`c__img` сетки каталога и устаревший
`c__ph`, то есть почти всю поверхность просмотра. Поэтому пары «заглушка и
картинка» берутся из фактической разметки: проверяется то, что собрано
страницей, а не то, что помнит инструмент.

Страниц две: главная (полки и лента) и каталог (сетка). Их карточки собирает
РАЗНЫЙ код, и у них разные классы — одна страница доказывала бы половину.

Что печатается по каждому домену: найденные пары, вывод по каждой
(«буква поверх» / «картинка поверх» / «не измерено») и общий итог.

Исход «не измерено» отдельный: если стилей в разметке нет (вынесены в файл),
проверка не делает вид, что знает ответ.

    python3 automation/local/poster-placeholder-check.py
    python3 automation/local/poster-placeholder-check.py --domain lordfilm.group
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

РЕЕСТР = Path(__file__).resolve().parents[2] / "config" / "site-cells.json"
K2 = ["lordfilm.group", "lordfilm.spb.ru", "lordfilm.msk.ru", "lordserial.su",
      "lordserial.group", "lordserial.spb.ru", "lordserial.msk.ru",
      "lordserial.net.ru"]

#: Страницы, где посетитель видит карточки. Сетку каталога полки главной не
#: заменяют: это другой код и другие классы.
ПУТИ = ("/", "/catalog/")

#: Заглушка и следующая за ней картинка в одном контейнере. `aria-hidden`
#: обязателен: это признак декоративного слоя, а не любого span перед img.
#
# Тег картинки захватывается ЦЕЛИКОМ, а класс выбирается из него отдельно.
# Необязательная группа `(?:class="…")?` внутри `<img[^>]*…>` не срабатывает
# никогда: ленивый `[^>]*?` сопоставляется пустой строкой, группа пробуется
# сразу после `<img` — там пробел — и пропускается, после чего `[^>]*>`
# съедает весь тег. Измерено: инструмент печатал «(без класса)» на всех
# витринах, включая те, где класс `zt__img` в разметке есть.
# Контейнер захватывается вместе с парой: у части витрин картинка карточки
# вообще без класса, и поднять её может только правило через контейнер
# (`.ag-poster img`). Без контейнера такая пара навсегда оставалась бы
# «не измерено» — измерено на an1mego.site и animeg0.site.
ПАРА = re.compile(
    r'<(?:span|div|a)[^>]*class="(?P<контейнер>[^"]+)"[^>]*>\s*'
    r'<(?:span|div) class="(?P<заглушка>[A-Za-z0-9_-]+)" aria-hidden="true">'
    r'(?P<нутро>.{0,200}?)</(?:span|div)>\s*'
    r'<img(?P<тег_картинки>[^>]*)>', re.S)

#: Признак того, что совпадение перешагнуло границу карточки: внутри заглушки
#: открылся ещё один контейнер. Без этой проверки разбор склеивал плитку
#: подборки БЕЗ картинки со следующей плиткой И С картинкой и объявлял дефект
#: там, где в одной плитке никогда не бывает и буквы, и изображения
#: (измерено 2026-10-17: из 16 плиток обе сразу — ноль).
ЧУЖОЙ_КОНТЕЙНЕР = re.compile(r'<(?:span|div|a)\b')

#: Устаревшая карточка: заглушка ВМЕСТО картинки, у картинки класса нет вовсе.
#: Пара выводится из контейнера, иначе правило для неё не найти.
БЕЗКЛАССНАЯ = re.compile(
    r'<(?:div|span) class="(?P<контейнер>[A-Za-z0-9_-]+)">\s*'
    r'<img(?P<тег>[^>]*)>')


def домены_реестра() -> list[str]:
    try:
        д = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    ячейки = д.get("cells") or []
    записи = ячейки.values() if isinstance(ячейки, dict) else ячейки
    итог = []
    for я in записи:
        домен = (я or {}).get("domain") or (я or {}).get("exact_domain")
        if домен and not домен.endswith(".localhost") \
                and not домен.endswith(".localhost.test"):
            итог.append(домен)
    return итог


def взять(url: str, таймаут: int = 40) -> str:
    г = subprocess.run(["curl", "-sS", "--max-time", str(таймаут), url],
                       capture_output=True, text=True)
    return г.stdout or ""


def правила(стили: str, селектор: str) -> list[str]:
    """Все объявления для селектора, где он стоит отдельным или в списке.

    Комментарии CSS снимаются ДО разбора. Без этого селектор, перед которым
    стоит пояснение, слипается с ним в одну строку и перестаёт совпадать
    точно: 2026-10-17 инструмент объявил «буква поверх» на восьми уже
    исправленных витринах, потому что правило `.zt__p img` получило над собой
    комментарий. Браузерная приёмка в тот же час показывала ноль букв —
    расхождение и выдало ошибку разбора.
    """
    итог = []
    без_комментариев = re.sub(r"/\*.*?\*/", " ", стили, flags=re.S)
    for м in re.finditer(r"([^{}]+)\{([^}]*)\}", без_комментариев):
        цели = [" ".join(с.split()).rsplit("}", 1)[-1].strip()
                for с in м.group(1).split(",")]
        if any(ц == селектор or ц.endswith(" " + селектор)
               or ц.replace(" > ", ">") == селектор.replace(" > ", ">")
               for ц in цели):
            итог.append(" ".join(м.group(2).split()))
    return итог


def пары_разметки(стр: str) -> set[tuple[str, str]]:
    """Пары (класс заглушки, класс картинки) из фактической разметки.

    Класс картинки «» означает картинку без класса: правило для неё ищется по
    контейнеру.
    """
    итог: set[tuple[str, str]] = set()
    for м in ПАРА.finditer(стр):
        if ЧУЖОЙ_КОНТЕЙНЕР.search(м.group("нутро") or ""):
            continue
        к = re.search(r'class="([^"]*)"', м.group("тег_картинки"))
        классы = (к.group(1) if к else "").split()
        итог.add((м.group("заглушка"), классы[0] if классы else "",
                  м.group("контейнер").strip()))
    for м in БЕЗКЛАССНАЯ.finditer(стр):
        if "class=" in м.group("тег"):
            continue
        контейнер = м.group("контейнер")
        # Заглушка этой карточки — соседний класс того же префикса; её имя
        # берётся из разметки, если она на странице есть.
        префикс = контейнер.split("__")[0]
        for имя in re.findall(rf'class="({префикс}__[a-z]+)"', стр):
            if имя == контейнер or not ("ph" in имя or "none" in имя):
                continue
            # Пара засчитывается, только если заглушка и картинка ВСТРЕЧАЮТСЯ
            # В ОДНОМ контейнере. У плитки подборки это взаимоисключающие
            # ветви разметки: либо картинка, либо буква. Без проверки
            # инструмент объявлял дефект там, где обе сразу не бывают —
            # измерено 2026-10-17: из 16 плиток обе сразу ноль.
            вместе = False
            for к in re.finditer(rf'<(?:span|div) class="{контейнер}">(.*?)'
                                 rf'</(?:span|div)>', стр, re.S):
                тело = к.group(1)
                if имя in тело and "<img" in тело:
                    вместе = True
                    break
            if вместе:
                итог.add((имя, "", контейнер))
    return итог


def селекторы_картинки(класс_заглушки: str, класс_картинки: str,
                      контейнер: str = "") -> list[str]:
    """Селекторы, которыми стили могли бы поднять картинку этой карточки."""
    куски = []
    if класс_картинки:
        куски.append(f".{класс_картинки}")
    префикс = класс_заглушки.split("__")[0]
    куски += [f".{префикс}__p img", f".{префикс}__p>img"]
    for токен in (контейнер or "").split():
        куски += [f".{токен} img", f".{токен}>img"]
    return куски


def по_домену(домен: str) -> dict:
    страницы = {}
    пары: set[tuple[str, str]] = set()
    стили_все = []
    постеров = 0
    for путь in ПУТИ:
        стр = взять(f"https://{домен}{путь}")
        страницы[путь] = bool(стр)
        if not стр:
            continue
        пары |= пары_разметки(стр)
        постеров += len(re.findall(r'<img[^>]+data-poster', стр))
        стили_все += re.findall(r"<style[^>]*>(.*?)</style>", стр, re.S)
    if not any(страницы.values()):
        return {"домен": домен, "пары": [],
                "вывод": "НЕ ИЗМЕРЕНО: ни одна страница не ответила"}
    стили = "\n".join(стили_все)
    if not пары:
        return {"домен": домен, "пары": [], "постеров": постеров,
                "вывод": "заглушки в разметке нет — буква появиться не может"}
    if not стили:
        return {"домен": домен, "пары": sorted(пары), "постеров": постеров,
                "вывод": "НЕ ИЗМЕРЕНО: стилей в разметке нет"}

    разборы = []
    for заглушка, картинка, контейнер in sorted(пары):
        пр_заглушки = правила(стили, f".{заглушка}")
        пр_картинки = []
        for с in селекторы_картинки(заглушка, картинка, контейнер):
            пр_картинки += правила(стили, с)
        поднята = any(("z-index" in п) or ("position:relative" in п)
                      or ("position:absolute" in п) for п in пр_картинки)
        позиционирована = any("position:absolute" in п for п in пр_заглушки)
        if not пр_заглушки:
            исход = f"НЕ ИЗМЕРЕНО: правила .{заглушка} нет"
        elif not позиционирована:
            исход = "заглушка не позиционирована — поверх не встанет"
        elif not пр_картинки:
            # Стили на странице есть, правило заглушки в них найдено, а
            # правила картинки нет ни по одному из её селекторов: поднять её
            # нечему. Это вывод, а не незнание — прежняя редакция печатала
            # здесь «не измерено» и скрывала дефект (lordserials22.info).
            исход = (f"БУКВА ПОВЕРХ: правила картинки "
                     f"({картинка or 'без класса'}) в стилях нет")
        elif поднята:
            исход = "картинка поверх"
        else:
            исход = "БУКВА ПОВЕРХ"
        разборы.append({"заглушка": заглушка, "картинка": картинка or "(без класса)",
                        "исход": исход, "правила_картинки": пр_картинки[:2],
                        "правила_заглушки": пр_заглушки[:1]})

    плохие = [р for р in разборы if р["исход"].startswith("БУКВА")]
    неясные = [р for р in разборы if р["исход"].startswith("НЕ ИЗМЕРЕНО")]
    if плохие:
        вывод = ("БУКВА ПОВЕРХ: " +
                 ", ".join(f"{р['заглушка']}/{р['картинка']}" for р in плохие))
    elif неясные and len(неясные) == len(разборы):
        вывод = "НЕ ИЗМЕРЕНО: " + неясные[0]["исход"]
    else:
        вывод = f"картинка поверх во всех парах ({len(разборы)})"
    return {"домен": домен, "пары": разборы, "постеров": постеров,
            "вывод": вывод}


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--подробно", action="store_true")
    опции = р.parse_args(аргв)
    домены = опции.domain or sorted(set(домены_реестра() + K2))

    with ThreadPoolExecutor(max_workers=5) as пул:
        итоги = list(пул.map(по_домену, домены))

    плохо = 0
    for и in итоги:
        метка = "✗" if и["вывод"].startswith("БУКВА") else " "
        print(f"{метка} {и['домен']:22} постеров "
              f"{и.get('постеров', 0):3}  пар {len(и.get('пары') or []):2}  "
              f"{и['вывод']}")
        плохо += и["вывод"].startswith("БУКВА")
        if опции.подробно:
            for п in (и.get("пары") or []):
                print(f"      {п['заглушка']:10} / {п['картинка']:12} "
                      f"{п['исход']}")
    print(f"\nвитрин с буквой поверх постера: {плохо} из {len(итоги)}")
    return 0 if плохо == 0 else 1


if __name__ == "__main__":
    raise SystemExit(главное())
