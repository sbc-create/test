#!/usr/bin/env python3
"""Что стоит на витринах ЖИВЬЁМ против того, что закрыл исполнитель.

Повод. 11 октября две витрины были названы выложенными, когда выкладка ещё не
начиналась: сценарий ждал зелёного CI, его журнал был пуст, и состояние
«закоммичено и поставлено в очередь» прочиталось как «выложено». Ошибка
безобидна ровно до того момента, когда по ней включают строгую проверку или
снимают паузу публикаций.

Отличить одно от другого может только живая витрина, и спрашивать надо её, а
не сценарий выкладки. Поэтому здесь два источника и ни один не выводится из
другого:

* **заголовок `x-site-factory-build-id`** живого ответа — что отдаёт витрина
  СЕЙЧАС. Это и есть «выложено»;
* **журнал исполнителя** `/var/lib/site-cells/results/*-code-*.json` — что
  он закрыл и с каким исходом.

Расхождение между ними — не ошибка инструмента, а полезный факт, и он
называется прямо: «живёт прежний выпуск», «исполнитель закрыл, витрина не
подхватила», «заявки не было вовсе».

Только чтение: ни одного запроса, меняющего состояние, здесь нет.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

РЕЗУЛЬТАТЫ = Path("/var/lib/site-cells/results")

#: Домен → site_id. Берётся из реестра ячеек, а не придумывается: домен, о
#: котором реестр не знает, инструменту неизвестен, и это BLOCKED_INPUT, а не
#: повод угадать имя.
ИМЯ_РЕЕСТРА = Path("config") / "site-cells.json"


def где_реестр(корень: Path | None = None) -> tuple[Path | None, list[Path]]:
    """(путь, где искали). Поиск от скрипта, затем вверх от текущего каталога.

    Первая редакция считала реестр от расположения скрипта и только оттуда, а
    при неудаче печатала «реестр ячеек не прочитан» — без пути. SEO-сессия
    запустила инструмент вне моего рабочего дерева и получила ровно это:
    отказ без того, что нужно для разбора. Собственное правило дня
    («не измерено» обязано называть причину) я нарушил в том же инструменте,
    которым его и внедрял.

    Теперь: явный `--root` сильнее всего, затем каталог репозитория по
    расположению скрипта, затем подъём от текущего каталога — рабочее дерево
    у каждой сессии своё. Все проверенные пути возвращаются и печатаются при
    отказе.
    """
    кандидаты: list[Path] = []
    if корень is not None:
        кандидаты.append(корень / ИМЯ_РЕЕСТРА)
    кандидаты.append(Path(__file__).resolve().parents[2] / ИМЯ_РЕЕСТРА)
    текущий = Path.cwd().resolve()
    for каталог in [текущий, *текущий.parents]:
        кандидаты.append(каталог / ИМЯ_РЕЕСТРА)
    проверено: list[Path] = []
    for путь in кандидаты:
        if путь in проверено:
            continue
        проверено.append(путь)
        if путь.is_file():
            return путь, проверено
    return None, проверено


def домены_реестра(корень: Path | None = None) -> tuple[dict[str, str], str]:
    """(домен → site_id, причина). Пустая карта — причина объясняет, почему."""
    путь, проверено = где_реестр(корень)
    if путь is None:
        где = ", ".join(str(п) for п in проверено[:4])
        return {}, f"реестр ячеек не найден; искал: {где}"
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except OSError as сбой:
        return {}, f"{путь} не читается: {сбой}"
    except ValueError as сбой:
        return {}, f"{путь} не разбирается как JSON: {сбой}"
    пары = {}
    for ячейка in документ.get("cells") or []:
        домен = str(ячейка.get("domain") or "").strip()
        сайт = str(ячейка.get("site_id") or "").strip()
        if домен and сайт:
            пары[домен] = сайт
    if not пары:
        return {}, f"{путь} прочитан, но ни одной пары домен/site_id в нём нет"
    return пары, f"реестр {путь}, ячеек {len(пары)}"


def живой_build(домен: str, таймаут: int = 25) -> tuple[str, str]:
    """(build, причина). Пустой build — причина говорит, почему."""
    итог = subprocess.run(
        ["curl", "-sS", "-D", "-", "-o", "/dev/null", "--max-time",
         str(таймаут), f"https://{домен}/"],
        capture_output=True, text=True)
    if итог.returncode:
        return "", f"витрина не ответила (curl {итог.returncode})"
    код = ""
    build = ""
    for строка in итог.stdout.splitlines():
        низ = строка.lower()
        if низ.startswith("http/"):
            части = строка.split()
            код = части[1] if len(части) > 1 else ""
        elif низ.startswith("x-site-factory-build-id:"):
            build = строка.split(":", 1)[1].strip()
    if not build:
        return "", f"заголовка build нет (код {код or '?'})"
    return build, f"код {код}"


def выпуски(site_id: str) -> list[dict]:
    """Закрытые заявки на код этой витрины, от старых к новым."""
    записи = []
    for ф in sorted(РЕЗУЛЬТАТЫ.glob(f"{site_id}-code-*.json")):
        try:
            д = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        исход = д.get("outcome") or {}
        записи.append({
            "commit": (д.get("commit") or "")[:12],
            "исход": f"{д.get('status')}/{исход.get('stage') or '—'}",
            "когда": str(д.get("finished_at") or ""),
        })
    return sorted(записи, key=lambda з: з["когда"])


def последний_выпуск(site_id: str) -> tuple[str, str, str]:
    """(commit, исход, когда) последней ЗАКРЫТОЙ заявки на код."""
    все = выпуски(site_id)
    if not все:
        return "", "заявок на код нет", ""
    п = все[-1]
    return п["commit"], п["исход"], п["когда"][11:19] + "Z"


def разбор(домен: str, site_id: str) -> dict:
    build, причина = живой_build(домен)
    все = выпуски(site_id)
    коммит, исход, когда = последний_выпуск(site_id)
    # build витрины — это «<коммит>-<site_id>»; сверяется ПРЕФИКС, потому что
    # суффикс у части витрин отличается от site_id (`animedia-space` против
    # `animedia-02`), и равенство строк дало бы ложное расхождение.
    совпало = bool(build) and bool(коммит) and build.startswith(коммит)
    известен = bool(build) and any(build.startswith(з["commit"]) for з in все
                                   if з["commit"])
    if not build:
        состояние, вывод = "не измерено", f"НЕ ИЗМЕРЕНО: {причина}"
    elif not все:
        состояние = "вне журнала"
        вывод = "живёт выпуск, а заявок на код в журнале нет вовсе"
    elif совпало:
        состояние, вывод = "совпало", "живёт последний закрытый выпуск"
    elif not известен:
        # Витрина отдаёт то, чего в журнале нет: обычно заявка только что
        # закрылась, а запись ещё не дописана, либо выпуск пришёл не через
        # исполнителя. Это НЕ то же, что «витрина отстала», и путать их
        # нельзя: в первом случае ждать, во втором разбираться.
        состояние = "новее журнала"
        вывод = (f"живёт {build}, которого в журнале нет; последний закрытый "
                 f"{коммит} ({исход} в {когда}) — заявка свежая или выпуск "
                 f"пришёл не через исполнителя")
    else:
        состояние = "отстала"
        вывод = (f"ВИТРИНА ОТСТАЛА: живёт {build}, исполнитель закрыл "
                 f"{коммит} ({исход} в {когда})")
    return {"домен": домен, "site_id": site_id, "живой": build,
            "коммит": коммит, "исход": исход, "когда": когда,
            "совпало": совпало, "состояние": состояние, "вывод": вывод}


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("домены", nargs="*",
                   help="домены; без аргументов — все из реестра ячеек")
    р.add_argument("--json", action="store_true")
    р.add_argument("--root", type=Path, default=None,
                   help="каталог репозитория, если реестр не найден сам")
    а = р.parse_args(аргв)

    реестр, причина = домены_реестра(а.root)
    if not реестр:
        print(причина, file=sys.stderr)
        print("укажите каталог репозитория ключом --root", file=sys.stderr)
        return 2
    цели = а.домены or sorted(реестр)
    неизвестные = [д for д in цели if д not in реестр]
    if неизвестные:
        print("домены вне реестра ячеек: " + ", ".join(неизвестные),
              file=sys.stderr)
        return 2

    отчёт = [разбор(д, реестр[д]) for д in цели]
    if а.json:
        print(json.dumps(отчёт, ensure_ascii=False, indent=2))
    else:
        print(f"{'домен':24} {'живой build':30} вывод")
        for и in отчёт:
            print(f"{и['домен']:24} {и['живой'] or '—':30} {и['вывод']}")
    # «Новее журнала» в беды не идёт: это обычное состояние сразу после
    # выкладки, и объявлять его расхождением значило бы кричать на норму.
    беды = [и for и in отчёт if и["состояние"] in ("отстала", "не измерено",
                                                   "вне журнала")]
    свежие = [и for и in отчёт if и["состояние"] == "новее журнала"]
    print(f"\nвитрин: {len(отчёт)}; требуют разбора: {len(беды)}"
          + (f"; свежих выкладок: {len(свежие)}" if свежие else ""))
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(главное())
