#!/usr/bin/env python3
"""Что стоит на витринах ЖИВЬЁМ против того, что закрыл исполнитель.

Повод. 11 октября две витрины были названы выложенными, когда выкладка ещё не
начиналась: сценарий ждал зелёного CI, его журнал был пуст, и состояние
«закоммичено и поставлено в очередь» прочиталось как «выложено». Ошибка
безобидна ровно до того момента, когда по ней включают строгую проверку или
снимают паузу публикаций.

Отличить одно от другого может только живая витрина, и спрашивать надо её, а
не сценарий выкладки. Поэтому здесь два источника и ни один не выводится из
другого:

* **заголовок `x-site-factory-build-id`** живого ответа — что отдаёт витрина
  СЕЙЧАС. Это и есть «выложено»;
* **журнал исполнителя** `/var/lib/site-cells/results/*-code-*.json` — что
  он закрыл и с каким исходом.

Расхождение между ними — не ошибка инструмента, а полезный факт, и он
называется прямо: «живёт прежний выпуск», «исполнитель закрыл, витрина не
подхватила», «заявки не было вовсе».

Только чтение: ни одного запроса, меняющего состояние, здесь нет.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

РЕЗУЛЬТАТЫ = Path("/var/lib/site-cells/results")

#: Домен → site_id. Берётся из реестра ячеек, а не придумывается: домен, о
#: котором реестр не знает, инструменту неизвестен, и это BLOCKED_INPUT, а не
#: повод угадать имя.
ИМЯ_РЕЕСТРА = Path("config") / "site-cells.json"


def где_реестр(корень: Path | None = None) -> tuple[Path | None, list[Path]]:
    """(путь, где искали). Поиск от скрипта, затем вверх от текущего каталога.

    Первая редакция считала реестр от расположения скрипта и только оттуда, а
    при неудаче печатала «реестр ячеек не прочитан» — без пути. SEO-сессия
    запустила инструмент вне моего рабочего дерева и получила ровно это:
    отказ без того, что нужно для разбора. Собственное правило дня
    («не измерено» обязано называть причину) я нарушил в том же инструменте,
    которым его и внедрял.

    Теперь: явный `--root` сильнее всего, затем каталог репозитория по
    расположению скрипта, затем подъём от текущего каталога — рабочее дерево
    у каждой сессии своё. Все проверенные пути возвращаются и печатаются при
    отказе.
    """
    кандидаты: list[Path] = []
    if корень is not None:
        кандидаты.append(корень / ИМЯ_РЕЕСТРА)
    кандидаты.append(Path(__file__).resolve().parents[2] / ИМЯ_РЕЕСТРА)
    текущий = Path.cwd().resolve()
    for каталог in [текущий, *текущий.parents]:
        кандидаты.append(каталог / ИМЯ_РЕЕСТРА)
    проверено: list[Path] = []
    for путь in кандидаты:
        if путь in проверено:
            continue
        проверено.append(путь)
        if путь.is_file():
            return путь, проверено
    return None, проверено


def домены_реестра(корень: Path | None = None) -> tuple[dict[str, str], str]:
    """(домен → site_id, причина). Пустая карта — причина объясняет, почему."""
    путь, проверено = где_реестр(корень)
    if путь is None:
        где = ", ".join(str(п) for п in проверено[:4])
        return {}, f"реестр ячеек не найден; искал: {где}"
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except OSError as сбой:
        return {}, f"{путь} не читается: {сбой}"
    except ValueError as сбой:
        return {}, f"{путь} не разбирается как JSON: {сбой}"
    пары = {}
    for ячейка in документ.get("cells") or []:
        домен = str(ячейка.get("domain") or "").strip()
        сайт = str(ячейка.get("site_id") or "").strip()
        if домен and сайт:
            пары[домен] = {"site_id": сайт,
                           "status": str(ячейка.get("status") or "").strip()}
    if not пары:
        return {}, f"{путь} прочитан, но ни одной пары домен/site_id в нём нет"
    return пары, f"реестр {путь}, ячеек {len(пары)}"


def живой_build(домен: str, таймаут: int = 25) -> tuple[str, str]:
    """(build, причина). Пустой build — причина говорит, почему."""
    итог = subprocess.run(
        ["curl", "-sS", "-D", "-", "-o", "/dev/null", "--max-time",
         str(таймаут), f"https://{домен}/"],
        capture_output=True, text=True)
    if итог.returncode:
        # Код curl называется в причине НЕ для красоты: он различает состояния,
        # которые нельзя смешивать. 6 — имя не разрешилось (витрины может и не
        # быть вовсе), 28 — предел ожидания истёк (витрина ЕСТЬ и отвечает
        # слишком медленно). Измерено 12.10 на zonafilm12.site: при curl 28
        # прежняя редакция печатала «витрины, вероятно, и нет», тогда как
        # домен в тот момент отдавал посетителю 504 и 200 за 18 с. Такая
        # формулировка читается как «смотреть нечего» на падающем сайте.
        return "", f"витрина не ответила (curl {итог.returncode})"
    код = ""
    build = ""
    for строка in итог.stdout.splitlines():
        низ = строка.lower()
        if низ.startswith("http/"):
            части = строка.split()
            код = части[1] if len(части) > 1 else ""
        elif низ.startswith("x-site-factory-build-id:"):
            build = строка.split(":", 1)[1].strip()
    if not build:
        return "", f"заголовка build нет (код {код or '?'})"
    return build, f"код {код}"


def выпуски(site_id: str) -> list[dict]:
    """Закрытые заявки на код этой витрины, от старых к новым."""
    записи = []
    for ф in sorted(РЕЗУЛЬТАТЫ.glob(f"{site_id}-code-*.json")):
        try:
            д = json.loads(ф.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        исход = д.get("outcome") or {}
        записи.append({
            "commit": (д.get("commit") or "")[:12],
            "status": str(д.get("status") or ""),
            "исход": f"{д.get('status')}/{исход.get('stage') or '—'}",
            "когда": str(д.get("finished_at") or ""),
        })
    return sorted(записи, key=lambda з: з["когда"])


#: Исход заявки, после которого витрина ОБЯЗАНА отдавать новый выпуск.
#: Журнал знает и другие: `rejected` (29 записей на 11.10), `failed/failed`
#: (7) и `failed/rolled_back` (1). После любого из них витрина законно живёт
#: на прежнем выпуске, и сверять её с таким коммитом нельзя.
УДАЧНЫЙ = "ok"


def последний_выпуск(site_id: str) -> tuple[str, str, str]:
    """(commit, исход, когда) последнего УДАЧНОГО выпуска.

    Сначала здесь стояла последняя закрытая заявка — любая. Первый же проход
    по всем ячейкам реестра объявил `yummyani.site` отставшей, хотя её
    последняя заявка ОТКЛОНЕНА (`rejected`), и витрина законно отдавала
    прежний выпуск. Это та же ложная тревога, за которую утром пришлось
    править карту строгости: инструмент сравнивал не с тем, с чем надо.
    """
    for п in reversed(выпуски(site_id)):
        if п["status"] == УДАЧНЫЙ:
            return п["commit"], п["исход"], п["когда"][11:19] + "Z"
    return "", "удачных выпусков нет", ""


def последняя_заявка(site_id: str) -> dict | None:
    """Последняя закрытая заявка любого исхода — для объяснения, а не сверки."""
    все = выпуски(site_id)
    return все[-1] if все else None


#: Статус, при котором витрины, по мнению реестра, ещё нет. ТОЛЬКО `planned`:
#: `not_extracted` по схеме означает другое — «отдельный Git-проект сайта ещё
#: не выделен», и к тому, отвечает ли витрина, отношения не имеет.
#:
#: Это ПОЯСНЕНИЕ к молчанию, а не основание не мерить. Разница выяснилась на
#: собственной ошибке: первая редакция по статусам измерение ПРОПУСКАЛА, и из
#: 25 ячеек «не открытыми» оказались 15 — включая живые витрины. Авторитет
#: здесь у живого ответа, а не у записи в файле.
НЕ_ОТКРЫТА = ("planned",)

#: Чему статус противоречит, если витрина отвечает. Формулировка по
#: ИЗМЕРЕННОМУ: «реестр устарел» было бы догадкой о причине, а видно другое —
#: поле расходится с остальными полями той же записи.
#: Доменные имена, зарезервированные для испытаний (RFC 6761 и 2606): они по
#: определению не разрешаются в публичной сети, и молчание такого адреса —
#: свойство имени, а не состояние витрины. Четыре пилотных ячейки реестра
#: живут именно в них, и докладывать о них «витрина не ответила» значит
#: держать в отчёте четыре строки, которые никогда не изменятся.
ИСПЫТАТЕЛЬНЫЕ_ИМЕНА = (".localhost", ".test", ".invalid", ".example")

#: Статусы реестра, которые расходятся с живым состоянием витрины.
#:
#: Формулировка важна и была исправлена 12.10. Прежняя — «ячейка запланирована,
#: а витрина отвечает» — читается как дефект витрины или записи, и семь строк
#: каждый прогон требовали разбора. Измерение назвало причину: поле `status`
#: ПИШЕТСЯ ОДИН РАЗ при создании ячейки (`newsite.py` — `planned`,
#: `onboarding.py` — `staged`) и после активации не переводится НИ ОДНИМ
#: писателем во всём дереве. То есть расхождение не состояние сайта, а
#: свойство поля, и правка семи записей руками его не устранит: следующая
#: активация даст то же самое.
#:
#: Отдельно проверено, что на операции это не влияет:
#: `registry.extracted_sites` читает `repo.remote`, а не `status`, и
#: `require_not_extracted` отказывает публикации через общий путь всем семи —
#: проверено вызовом, `SiteAlreadyExtracted` на lords-02 и zona-03. Поэтому
#: это неточность ОТЧЁТА, а не открытая дверь.
ПРОТИВОРЕЧИТ = {
    "planned": "status=planned не переведён после активации (поле пишется "
               "один раз при создании; на операции не влияет)",
    "not_extracted": "status=not_extracted не переведён после выделения "
                     "(сторож публикации читает repo.remote, а не status)",
}


def разбор(домен: str, site_id: str, статус: str = "") -> dict:
    if домен.endswith(ИСПЫТАТЕЛЬНЫЕ_ИМЕНА):
        return {"домен": домен, "site_id": site_id, "живой": "", "коммит": "",
                "исход": "", "когда": "", "совпало": False,
                "состояние": "испытательное имя", "статус_реестра": статус,
                "реестр_устарел": False,
                "вывод": "имя зарезервировано для испытаний (RFC 6761) — "
                         "публично не разрешается"}
    build, причина = живой_build(домен)
    все = выпуски(site_id)
    коммит, исход, когда = последний_выпуск(site_id)
    # build витрины — это «<коммит>-<site_id>»; сверяется ПРЕФИКС, потому что
    # суффикс у части витрин отличается от site_id (`animedia-space` против
    # `animedia-02`), и равенство строк дало бы ложное расхождение.
    совпало = bool(build) and bool(коммит) and build.startswith(коммит)
    известен = bool(build) and any(build.startswith(з["commit"]) for з in все
                                   if з["commit"])
    if not build:
        состояние = "не измерено"
        вывод = f"НЕ ИЗМЕРЕНО: {причина}"
        # «Витрины, вероятно, и нет» законно сказать ТОЛЬКО когда молчание —
        # это неразрешённое имя. Истёкший предел ожидания означает обратное:
        # витрина есть и отвечает слишком медленно, и тогда статус реестра
        # ничего не смягчает.
        имя_не_разрешилось = "curl 6)" in причина
        предел_ожидания = "curl 28)" in причина
        if предел_ожидания:
            вывод += ("; это ПРЕДЕЛ ОЖИДАНИЯ, а не отсутствие витрины: "
                      "домен отвечает, но медленнее предела. Статус реестра "
                      "здесь ничего не смягчает")
            if статус:
                вывод += f" (в реестре {статус})"
        elif статус in НЕ_ОТКРЫТА and имя_не_разрешилось:
            # Молчание ожидаемо: имя не разрешается И реестр говорит, что
            # ячейку не открывали. Два признака вместе, а не один.
            состояние = "не открыта"
            вывод += f"; реестр: статус {статус} — витрины, вероятно, и нет"
        elif статус in НЕ_ОТКРЫТА:
            вывод += (f"; реестр: статус {статус}, но имя разрешилось — "
                      "молчание объяснено не статусом")
        elif статус == "not_extracted":
            # Про отвечаемость этот статус ничего не говорит, и выводить из
            # него «должна отвечать» нельзя.
            вывод += "; реестр: статус not_extracted — про витрину молчит"
        elif статус:
            вывод += f"; реестр: статус {статус} — должна отвечать"
    elif not все:
        состояние = "вне журнала"
        вывод = "живёт выпуск, а заявок на код в журнале нет вовсе"
    elif not коммит:
        состояние = "вне журнала"
        вывод = (f"живёт {build}, а УДАЧНЫХ выпусков в журнале нет — "
                 f"последняя заявка {все[-1]['commit']} ({все[-1]['исход']})")
    elif совпало:
        состояние, вывод = "совпало", "живёт последний удачный выпуск"
    elif not известен:
        # Витрина отдаёт то, чего в журнале нет: обычно заявка только что
        # закрылась, а запись ещё не дописана, либо выпуск пришёл не через
        # исполнителя. Это НЕ то же, что «витрина отстала», и путать их
        # нельзя: в первом случае ждать, во втором разбираться.
        состояние = "новее журнала"
        вывод = (f"живёт {build}, которого в журнале нет; последний закрытый "
                 f"{коммит} ({исход} в {когда}) — заявка свежая или выпуск "
                 f"пришёл не через исполнителя")
    else:
        состояние = "отстала"
        вывод = (f"ВИТРИНА ОТСТАЛА: живёт {build}, удачно выложен "
                 f"{коммит} ({исход} в {когда})")
    # Неудачная последняя заявка объясняет состояние и называется отдельно:
    # «живёт прежний выпуск, потому что новый отклонён» — это не отставание.
    крайняя = последняя_заявка(site_id)
    if (крайняя and крайняя["status"] != УДАЧНЫЙ
            and состояние in ("совпало", "новее журнала")):
        вывод += (f"; последняя заявка {крайняя['commit']} — "
                  f"{крайняя['исход']} в {крайняя['когда'][11:19]}Z")
    # Витрина отвечает, а статус говорит обратное — расхождение ВНУТРИ
    # реестра, и называть его надо, иначе на поле `status` будут полагаться
    # зря. Причину не выдумываем: сказано то, что видно.
    устарел = bool(build) and статус in ПРОТИВОРЕЧИТ
    if устарел:
        вывод += f"; РЕЕСТР: {ПРОТИВОРЕЧИТ[статус]}"
    return {"домен": домен, "site_id": site_id, "живой": build,
            "коммит": коммит, "исход": исход, "когда": когда,
            "совпало": совпало, "состояние": состояние,
            "статус_реестра": статус, "реестр_устарел": устарел,
            "вывод": вывод}


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("домены", nargs="*",
                   help="домены; без аргументов — все из реестра ячеек")
    р.add_argument("--json", action="store_true")
    р.add_argument("--root", type=Path, default=None,
                   help="каталог репозитория, если реестр не найден сам")
    а = р.parse_args(аргв)

    реестр, причина = домены_реестра(а.root)
    if not реестр:
        print(причина, file=sys.stderr)
        print("укажите каталог репозитория ключом --root", file=sys.stderr)
        return 2
    цели = а.домены or sorted(реестр)
    неизвестные = [д for д in цели if д not in реестр]
    if неизвестные:
        print("домены вне реестра ячеек: " + ", ".join(неизвестные),
              file=sys.stderr)
        return 2

    отчёт = [разбор(д, реестр[д]["site_id"], реестр[д]["status"])
             for д in цели]
    if а.json:
        print(json.dumps(отчёт, ensure_ascii=False, indent=2))
    else:
        print(f"{'домен':24} {'живой build':30} вывод")
        for и in отчёт:
            print(f"{и['домен']:24} {и['живой'] or '—':30} {и['вывод']}")
    # «Новее журнала» в беды не идёт: это обычное состояние сразу после
    # выкладки, и объявлять его расхождением значило бы кричать на норму.
    беды = [и for и in отчёт if и["состояние"] in ("отстала", "не измерено",
                                                   "вне журнала")]
    свежие = [и for и in отчёт if и["состояние"] == "новее журнала"]
    неоткрытые = [и for и in отчёт if и["состояние"] in
                  ("не открыта", "испытательное имя")]
    устарели = [и for и in отчёт if и.get("реестр_устарел")]
    print(f"\nячеек: {len(отчёт)}; требуют разбора: {len(беды)}"
          + (f"; свежих выкладок: {len(свежие)}" if свежие else "")
          + (f"; не открыты: {len(неоткрытые)}" if неоткрытые else "")
          + (f"; status в реестре не переведён: {len(устарели)}" if устарели
             else ""))
    if устарели:
        print("   " + " ".join(и["домен"] for и in устарели))
        print("   Причина общая и не в этих витринах: поле status пишется при "
              "создании ячейки и не переводится после активации ни одним "
              "писателем. Правка записей руками даст то же расхождение на "
              "следующей активации, а на операции поле не влияет — сторож "
              "публикации читает repo.remote.")
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(главное())
