#!/usr/bin/env python3
"""Названы ли поисковику ВСЕ серии, которые витрина сама печатает на странице.

Зачем отдельно от `sitemap-completeness.py`. Тот сравнивает ЧИСЛА: адресов в
карте против объявленных записей каталога. Здесь сравниваются МНОЖЕСТВА по
одной работе: ссылки на серии, которые домен печатает на СВОЕЙ странице
произведения, против адресов серий этого же слага в его СОБСТВЕННОЙ карте.
Числа могут совпасть при разном составе, множества — нет.

Повод. У `yummyani.site` в карте 1 644 адреса серий при каталоге 8 378 работ
(MOD-103: `DETAIL_LIMIT = 40` в `src/lib/seo/sitemap-catalog.ts` берёт
подробности только у головы обхода). Владельцу предложено пересоздать один
контейнер на образе четырёх соседей (`docs/OWNER_BLOCK_YUMMY_SITE_IMAGE.md`).
Чего в том блоке НЕ доказано — что на исправленном образе карта становится
ПОЛНОЙ. «123 302 адреса вместо 1 424» — это про масштаб, а не про состав.
Эта проверка меряет состав и отвечает, что именно покупает пересоздание.

Признаки:

* `НЕ НАЗВАНЫ` — страница печатает адрес серии, в карте его нет. Дефект:
  существующая страница поисковику не названа;
* `ЛИШНИЕ` — карта объявляет адрес, которого на странице нет. Это не дефект
  сам по себе (страница может листать серии порциями), но печатается, потому
  что молчание о расхождении в другую сторону делает «совпало» непроверяемым;
* `нечего терять` — на странице ни одной ссылки на серию. Такая работа в счёт
  дефекта не идёт: отсутствие в карте там нечем отличить от правильного
  поведения. Это и есть отрицательный контроль метода;
* `не измерено` — страница или карта не прочитаны. Нулём не подменяется.

Различающий контроль встроен: проверка запускается на ДВУХ домéнах с одним
каталогом — на исправленном образе и на отставшем. Если метод даёт один и тот
же ответ на обоих, он ничего не измеряет, и об этом сказано прямо.

    python3 automation/local/episode-sitemap-coverage.py yummyani.biz
    python3 automation/local/episode-sitemap-coverage.py yummyani.biz yummyani.site \\
        --positions 1,24,60,200,900,2500,4000,5500,7000,8300
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import tempfile
import time

#: Позиции в `titles.xml`, те же, что в таблице блока владельца.
#:
#: ЧТО ПОЗИЦИЯ ДАЁТ И ЧЕГО НЕ ДАЁТ. В ОДНОМ прогоне она берёт на всех домéнах
#: одну и ту же работу: 22.10 в 05:5xZ позиции 200 и 4000 дали `hryak` и
#: `veter-iz-loyana-pogonya-za-prestupnikom` и у `.site`, и у `.biz`, поэтому
#: сравнение витрин честное. А вот МЕЖДУ прогонами разных дней работа по
#: позиции меняется: 21.10 в 13:02 позиция 60 держала `ruy-malenkiy-sid`,
#: 22.10 в 05:5xZ — `moya-sudba-zlodeya`, потому что порядок `titles.xml` идёт
#: от обхода каталога и сдвигается. Значит «тот же замер по тем же работам»
#: позиция НЕ обеспечивает, и сохранность состава меряется не ею, а сверкой
#: множеств (`sitemap-part-monotonic.py`).
ПОЗИЦИИ_ПО_УМОЛЧАНИЮ = (1, 24, 60, 200, 900, 2500, 4000, 5500, 7000, 8300)
АДРЕС_СЕРИИ = r"/anime/{slug}/season/(\d+)/episode/(\d+)"
КЕШ = pathlib.Path(tempfile.gettempdir()) / "episode-sitemap-coverage"
#: Срок годности кеша карты, секунды. Кеш нужен затем, чтобы не тянуть
#: восьмимегабайтную часть повторно, пока разбираешься с одной витриной, —
#: четверти часа на это хватает с запасом.
#:
#: БЕЗ СРОКА КЕШ ЛОМАЕТ ПРИЁМКУ, и это измерено 22.10 в 05:4xZ: файлы кеша
#: лежали от 21.10 13:02, то есть 17 часов, и шлюз сверял ЖИВЫЕ страницы
#: произведений с картой ВЧЕРАШНЕГО чтения. После выпуска такая сверка
#: сказала бы «серии не названы» про исправленную карту — то есть отказала
#: бы годному выпуску, а при обратном знаке приняла бы негодный.
СРОК_КЕША_С = 900


def кеш_годен(файл: pathlib.Path, срок: float = СРОК_КЕША_С,
              сейчас: float | None = None) -> bool:
    """Можно ли верить этому файлу кеша. Чистая функция от времени файла."""
    if not файл.exists():
        return False
    сейчас = time.time() if сейчас is None else сейчас
    return (сейчас - файл.stat().st_mtime) < срок


def достать(адрес: str, таймаут: int = 240, кешировать: bool = False) -> str | None:
    """Тело ответа или None. None — «не прочитано», не пустая строка."""
    if кешировать:
        КЕШ.mkdir(parents=True, exist_ok=True)
        файл = КЕШ / (hashlib.sha256(адрес.encode()).hexdigest()[:24] + ".txt")
        if кеш_годен(файл):
            return файл.read_text(encoding="utf-8", errors="replace")
    try:
        г = subprocess.run(
            ["curl", "-sSL", "-w", "\n@@КОД@@%{http_code}", "--max-time",
             str(таймаут), адрес],
            capture_output=True, text=True, timeout=таймаут + 60)
    except subprocess.TimeoutExpired:
        return None
    тело, _, код = г.stdout.rpartition("@@КОД@@")
    if код.strip() != "200":
        return None
    if кешировать:
        файл.write_text(тело, encoding="utf-8")
    return тело


def карта_серий(домен: str) -> tuple[set[str], list[str]] | None:
    """Множество адресов серий из всех частей `episodes*.xml` домена."""
    индекс = достать(f"https://{домен}/sitemap.xml", 60)
    if индекс is None:
        return None
    части = [а for а in re.findall(r"<loc>([^<]+)</loc>", индекс)
             if "/episodes" in а]
    адреса: set[str] = set()
    for часть in части:
        тело = достать(часть, кешировать=True)
        if тело is None:
            return None
        адреса.update(re.findall(r"<loc>([^<]+)</loc>", тело))
    return адреса, части


def слаги_каталога(домен: str) -> list[str] | None:
    тело = достать(f"https://{домен}/sitemap/titles.xml", 120, кешировать=True)
    if тело is None:
        return None
    слаги = []
    for адрес in re.findall(r"<loc>([^<]+)</loc>", тело):
        м = re.search(r"/anime/([^/<]+)$", адрес)
        if м:
            слаги.append(м.group(1))
    return слаги


def серии_на_странице(домен: str, слаг: str) -> set[str] | None:
    тело = достать(f"https://{домен}/anime/{слаг}", 90)
    if тело is None:
        return None
    пары = re.findall(АДРЕС_СЕРИИ.format(slug=re.escape(слаг)), тело)
    return {f"/anime/{слаг}/season/{с}/episode/{э}" for с, э in пары}


def путь(адрес: str) -> str:
    return re.sub(r"^https?://[^/]+", "", адрес)


def проверить(домен: str, позиции: tuple[int, ...]) -> dict:
    итог: dict = {"домен": домен, "работы": [], "проблемы": []}
    карта = карта_серий(домен)
    слаги = слаги_каталога(домен)
    if карта is None or слаги is None:
        итог["проблемы"].append("карта или каталог не прочитаны — НЕ ИЗМЕРЕНО")
        итог["измерено"] = False
        return итог
    адреса, части = карта
    в_карте = {путь(а) for а in адреса}
    итог["измерено"] = True
    итог["частей_серий"] = len(части)
    итог["адресов_серий"] = len(в_карте)
    итог["работ_в_каталоге"] = len(слаги)
    for поз in позиции:
        if поз > len(слаги):
            итог["работы"].append({"позиция": поз, "итог": "позиции нет"})
            continue
        слаг = слаги[поз - 1]
        на_странице = серии_на_странице(домен, слаг)
        if на_странице is None:
            итог["работы"].append({"позиция": поз, "слаг": слаг,
                                   "итог": "не измерено"})
            continue
        мои = {а for а in в_карте if а.startswith(f"/anime/{слаг}/season/")}
        не_названы = на_странице - мои
        лишние = мои - на_странице
        if not на_странице:
            состояние = "нечего терять"
        elif не_названы:
            состояние = "НЕ НАЗВАНЫ"
        elif лишние:
            состояние = "ок, но есть лишние"
        else:
            состояние = "ок"
        итог["работы"].append({
            "позиция": поз, "слаг": слаг, "на_странице": len(на_странице),
            "в_карте": len(мои), "не_названы": len(не_названы),
            "лишние": len(лишние), "итог": состояние})
        if не_названы:
            итог["проблемы"].append(
                f"{слаг} (позиция {поз}): страница печатает"
                f" {len(на_странице)} серий, в карте {len(мои)},"
                f" не названы {len(не_названы)}")
    return итог


def напечатать(итог: dict) -> None:
    д = итог["домен"]
    if not итог["измерено"]:
        print(f"[не изм.] {д}: {'; '.join(итог['проблемы'])}")
        return
    плохих = sum(1 for р in итог["работы"] if р["итог"] == "НЕ НАЗВАНЫ")
    метка = "ок " if not плохих else "НЕТ"
    print(f"[{метка}] {д}: частей серий {итог['частей_серий']},"
          f" адресов серий {итог['адресов_серий']},"
          f" работ в каталоге {итог['работ_в_каталоге']}")
    for р in итог["работы"]:
        if "слаг" not in р:
            print(f"       поз.{р['позиция']:>5} {р['итог']}")
            continue
        if р["итог"] == "не измерено":
            print(f"       поз.{р['позиция']:>5} {р['слаг'][:46]:<46} не измерено")
            continue
        print(f"       поз.{р['позиция']:>5} {р['слаг'][:46]:<46}"
              f" страница {р['на_странице']:>5} | карта {р['в_карте']:>5}"
              f" | не названы {р['не_названы']:>5} | {р['итог']}")


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("домены", nargs="+")
    р.add_argument("--positions", default=",".join(map(str, ПОЗИЦИИ_ПО_УМОЛЧАНИЮ)))
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    позиции = tuple(int(ч) for ч in а.positions.split(",") if ч.strip())
    итоги = [проверить(д, позиции) for д in а.домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
    else:
        for и in итоги:
            напечатать(и)
        плохих = sum(1 for и in итоги
                     if и["измерено"] and any(р["итог"] == "НЕ НАЗВАНЫ"
                                              for р in и["работы"]))
        неизм = sum(1 for и in итоги if not и["измерено"])
        print(f"\nдоменов проверено {len(итоги)}, с неназванными сериями"
              f" {плохих}, не измерено {неизм}")
        if len(итоги) > 1:
            ответы = {tuple(р["итог"] for р in и["работы"]) for и in итоги
                      if и["измерено"]}
            if len(ответы) == 1:
                print("РАЗЛИЧАЮЩИЙ КОНТРОЛЬ НЕ ПРОЙДЕН: на всех домéнах ответ"
                      " один и тот же — признак ничего не различает")
    return 1 if any(и["проблемы"] for и in итоги) else 0


if __name__ == "__main__":
    sys.exit(main())
