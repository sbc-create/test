#!/usr/bin/env python3
"""Режим индексации обязан управлять и ТЕЛОМ страницы витрины Yummy.

    python3 automation/local/wire-yummy-robots.py --repo var/site-repos/<проект> [--dry-run]

Что было измерено
-----------------

Ячейка Yummy отдаёт страницы тайтлов и активы ИЗ ПРЕДНАРЕНДЕРЕННОГО релиза
(`СТАРЫЙ_КОРЕНЬ`), добавляя к готовому HTML только оболочку и несколько
мета-тегов. Значение `<meta name="robots">` зашито в этом HTML на момент его
сборки.

Измерено 2026-10-05 на `yummyani.biz` сразу после штатного открытия: реестр
ядра переписан (`desired_state: OPEN`, ревизия 2, идентификатор разрешения
владельца), юнит перезапущен, заголовок запрета исчез — а в теле страницы
осталось `<meta name="robots" content="noindex, follow">`. У двух ОТКРЫТЫХ
соседей (`yummyani.org`, `yummyani.site`) в теле `index, follow`: их снимки
собирались уже открытыми.

То есть режим управлял заголовком и `robots.txt`, но не телом. Открытый домен
с `noindex` в теле не открыт — и собственная проверка операции справедливо
отказалась считать режим применённым.

Почему правка здесь, а не пересборка снимков
--------------------------------------------

Преднарендеренный HTML принадлежит конвейеру (`data_owner: pipeline`), и
операция индексации вправе его только ЧИТАТЬ. Переписывать значение при
ОТДАЧЕ — не запись данных: витрина уже так и делает, вставляя свои мета-теги в
тот же `</head>`. Поэтому добавляется ровно одно действие: прежний тег
`robots` из тела убирается, а правильный приезжает вместе с остальной
вставкой.

Дубль недопустим: при двух тегах `robots` обходчик объединяет их, выбирая
самое строгое, и `index, follow` рядом с `noindex` ничего не открыл бы.

Чего инструмент НЕ делает: не трогает плеер, разметку и данные, не меняет
решение о режиме (его принимает `nova_core_indexability` по реестру ядра) и не
правит ничего вслепую — без точки вставки он отказывает с названной причиной.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ЯКОРЬ_ВСТАВКИ = "                f'<style>{СТИЛЬ}</style>')"
ЯКОРЬ_ЗАМЕНЫ = '            текст = текст.replace("</head>", вставка + "</head>", 1)'

ТЕГ_РЕЖИМА = """                f'<meta name="robots" content="{МЕТА_РОБОТОВ}">'
"""

СНЯТИЕ_ПРЕЖНЕГО = '''            # РЕЖИМ ОБЯЗАН УПРАВЛЯТЬ И ТЕЛОМ СТРАНИЦЫ, А НЕ ТОЛЬКО ЗАГОЛОВКОМ.
            #
            # Страницы отдаются из преднарендеренного релиза, и значение
            # `robots` зашито в нём на момент сборки. Измерено 2026-10-05 на
            # yummyani.biz: заголовка запрета уже нет, а в теле осталось
            # `noindex, follow`. Открытый домен с `noindex` в теле не открыт.
            #
            # Прежний тег СНИМАЕТСЯ, а не дополняется: при двух тегах обходчик
            # объединяет их и выбирает самое строгое значение.
            текст = re.sub(r'<meta\\s+name=["\\\']robots["\\\'][^>]*>', "", текст,
                           flags=re.IGNORECASE)
'''


def патч(текст: str) -> str:
    if "МЕТА_РОБОТОВ" in текст:
        return ""
    if текст.count(ЯКОРЬ_ВСТАВКИ) != 1:
        raise SystemExit(
            "нет точки вставки мета-тегов (строка со СТИЛЬ) — вслепую не правлю")
    if текст.count(ЯКОРЬ_ЗАМЕНЫ) != 1:
        raise SystemExit("нет строки подстановки в </head> — вслепую не правлю")
    if not re.search(r"(?m)^import re$", текст):
        raise SystemExit("в рантайме нет `import re`: снятие тега работать не будет")
    if "ИНДЕКСАЦИЯ_ОТКРЫТА" not in текст:
        raise SystemExit(
            "рантайм не читает режим (ИНДЕКСАЦИЯ_ОТКРЫТА) — подключать нечего")

    # 1. Значение тега считается ОДИН раз, рядом с решением о режиме.
    объявление = '''
#: Значение `<meta name="robots">` для страниц, отдаваемых из преднарендеренного
#: релиза. Считается из того же решения, что заголовок: два источника режима
#: разошлись бы, и первым разошлось бы тело страницы.
МЕТА_РОБОТОВ = "index, follow" if ИНДЕКСАЦИЯ_ОТКРЫТА else "noindex, nofollow"
'''
    маркер = "ИНДЕКСАЦИЯ_ОТКРЫТА = _nova_core_indexability.resolve_or_exit()"
    if текст.count(маркер) != 1:
        raise SystemExit("нет строки решения о режиме — вслепую не правлю")
    текст = текст.replace(маркер, маркер + объявление, 1)

    # 2. Прежний тег снимается ДО вставки нового.
    текст = текст.replace(ЯКОРЬ_ЗАМЕНЫ, СНЯТИЕ_ПРЕЖНЕГО + ЯКОРЬ_ЗАМЕНЫ, 1)

    # 3. Правильный тег приезжает вместе с остальной вставкой.
    текст = текст.replace(
        ЯКОРЬ_ВСТАВКИ,
        ТЕГ_РЕЖИМА.rstrip("\n") + "\n" + ЯКОРЬ_ВСТАВКИ.replace(
            "f'<style>{СТИЛЬ}</style>')", "f'<style>{СТИЛЬ}</style>')"), 1)
    return текст


def главная(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", required=True)
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args(argv)

    репо = pathlib.Path(args.repo)
    витрина = репо / "src" / "yummy-frontend.py"
    if not витрина.is_file():
        print(f"{репо}: нет src/yummy-frontend.py — это не витрина Yummy",
              file=sys.stderr)
        return 2
    прежний = витрина.read_text(encoding="utf-8")
    новый = патч(прежний)
    if not новый:
        print(f"{репо.name}: режим уже управляет телом страницы — ничего не меняю")
        return 0
    print(f"{репо.name}: мета-тег robots берётся из режима; прежний тег снимается")
    if args.dry_run:
        print("сухой прогон: файлы не менялись")
        return 0
    витрина.write_text(новый, encoding="utf-8")
    print("дальше обязательны: refresh-pins-lock.py и checks/run.sh в репозитории")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная())
