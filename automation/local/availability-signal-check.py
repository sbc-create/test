#!/usr/bin/env python3
"""Есть ли вообще признак, по которому доступность видео можно предсказать.

Только чтение: GET страницы витрины и GET плейлиста плеера — те же запросы,
которые делает браузер посетителя (`inventory/network-allowlist.yaml`,
`cdnvideohub-player-playlist`). Токенов нет, ничего не пишется.

Зачем. MOD-97 закрывается признаком: «названо поле (или источник), которое
ДЕЙСТВИТЕЛЬНО отвечает за доступность, и проверка совпадает с живым плеером в
обе стороны». Поля ячейки `playable` и `sources` этому не отвечают — измерено
20.10 на 18 карточках: играют 17, и среди них те, у которых `playable: false`.
Этот инструмент ищет признак ВЫШЕ данных ячейки: в разметке страницы и в ответе
провайдера.

Как он может провалиться. Инструмент не подтверждает заранее выбранную мысль:
он собирает все поля обоих источников и ищет те, что делят карточки РОВНО по
границе «играет / не играет», переданной с командной строкой. Нашлись —
печатает их как кандидатов в признак; не нашлись — печатает, что признака нет
среди собранных полей, и перечисляет, что именно сравнивалось. Оба исхода
одинаково выводимы, иначе проверка не значила бы ничего.

Предел, названный заранее. Если неиграющая карточка одна, то любое поле,
уникальное для неё, делит выборку «ровно по границе» случайно. Поэтому исход
«кандидат найден» печатается вместе с числом карточек каждого класса, и при
одном отрицательном примере он называется кандидатом, а не признаком.

Запуск:

    python3 automation/local/availability-signal-check.py \\
        --plays https://zonafilm12.site/title/kak-ryba-v-vode/ \\
        --plays https://zonafilm12.site/title/fotograf-4/ \\
        --fails https://zonafilm12.site/title/tom-i-cherri/

Коды возврата: 0 — сравнение выполнено и признака не найдено, 3 — найдены
кандидаты в признак, 2 — сравнивать нечего (страницы или плейлисты не
прочитаны).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.error
import urllib.parse
import urllib.request

ПЛЕЙЛИСТ = "https://plapi.cdnvideohub.com/api/v1/player/sv/playlist"
АГЕНТ = "factory-availability-signal-check"
ТАЙМАУТ = 30

#: Атрибуты разметки, которые описывают источник плеера.
АТРИБУТЫ = ("data-src-candidates", "data-title-id", "data-aggregator",
            "data-publisher-id", "data-state")

#: Поля, значение которых в отчёт не попадает: подписи, токены, адреса с ними.
ЗАКРЫТО = re.compile(r"sig|expires|srcip|token|secret|publisher", re.I)


def _получить(адрес: str, заголовки: dict | None = None) -> tuple[int, str]:
    запрос = urllib.request.Request(адрес, headers={"User-Agent": АГЕНТ,
                                                    **(заголовки or {})})
    try:
        with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ) as ответ:
            return ответ.status, ответ.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as ош:
        return ош.code, ""
    except (urllib.error.URLError, OSError, TimeoutError) as ош:
        return 0, f"{type(ош).__name__}"


def разметка_страницы(адрес: str) -> dict:
    """Атрибуты плеера со страницы витрины. Пусто — страница не прочитана."""
    код, тело = _получить(адрес)
    if код != 200 or not тело:
        return {"не_прочитано": f"страница ответила {код}"}
    итог = {"код": код}
    # `data-state` есть не только у плеера, и первое совпадение по странице
    # брать нельзя: оболочка статьи отдаёт своё состояние, и отчёт назвал бы
    # его состоянием плеера. Берём атрибут у элемента с `data-player`.
    # Берём ТОТ элемент, который несёт `data-state`, и отдельно проверяем, что
    # это оболочка плеера. Шаблон `data-player` сюда не годится: он совпадает
    # и с `data-player-contract` у секции страницы (граница слова проходит по
    # дефису), и отчёт назвал бы состоянием плеера отсутствие атрибута у
    # секции. Ошибка измерена на /title/tom-i-cherri/ 20.10.
    оболочка = re.search(r"<[^<>]{0,400}?data-state=\"[^\"]*\"[^<>]{0,200}?>",
                         тело)
    for имя in АТРИБУТЫ:
        где = оболочка.group(0) if (имя == "data-state" and оболочка) else тело
        м = re.search(rf'{имя}="([^"]*)"', где)
        итог[имя] = _развернуть(м.group(1)) if м else None
    if оболочка is None:
        итог["data-state"] = "элемента с data-state на странице нет"
    elif "data-player" not in оболочка.group(0):
        итог["data-state"] = f"{итог['data-state']} (элемент не оболочка плеера)"
    return итог


def _развернуть(значение: str) -> str:
    for что, на in (("&quot;", '"'), ("&amp;", "&"), ("&#39;", "'")):
        значение = значение.replace(что, на)
    return значение


def кандидат_источника(разметка: dict) -> tuple[str, str] | None:
    """Первый кандидат из `data-src-candidates`, иначе title-id + aggregator."""
    сырое = разметка.get("data-src-candidates")
    if сырое:
        try:
            список = json.loads(сырое)
        except ValueError:
            список = []
        if список and isinstance(список[0], dict):
            первый = список[0]
            агр = str(первый.get("aggregator") or "")
            ид = str(первый.get("id") or "")
            if агр and ид:
                return агр, ид
    агр = разметка.get("data-aggregator")
    ид = разметка.get("data-title-id")
    return (агр, ид) if агр and ид else None


def плейлист(издатель: str, агрегатор: str, ид: str, витрина: str) -> dict:
    """Ответ провайдера. Тем же запросом, что делает браузер посетителя."""
    адрес = (f"{ПЛЕЙЛИСТ}?" + urllib.parse.urlencode(
        {"pub": издатель, "aggr": агрегатор, "id": ид}))
    код, тело = _получить(адрес, {"Origin": f"https://{витрина}",
                                  "Referer": f"https://{витрина}/"})
    if код != 200 or not тело:
        return {"не_прочитано": f"плейлист ответил {код}"}
    try:
        return {"код": код, "ответ": json.loads(тело)}
    except ValueError:
        return {"не_прочитано": "плейлист ответил не JSON"}


def поля(узел, префикс: str = "") -> dict:
    """Плоский перечень «путь → класс значения». Значения не раскрываются.

    В сравнение идёт КЛАСС значения, а не само значение: иначе уникальные
    идентификаторы делили бы любую выборку и каждое поле оказывалось бы
    «признаком».
    """
    итог: dict[str, str] = {}
    if isinstance(узел, dict):
        for к, v in узел.items():
            итог.update(поля(v, f"{префикс}.{к}" if префикс else str(к)))
    elif isinstance(узел, list):
        итог[префикс or "."] = f"список[{len(узел)}]"
        for н, э in enumerate(узел[:1]):
            итог.update(поля(э, f"{префикс}[]"))
    else:
        if узел is None:
            итог[префикс] = "пусто"
        elif isinstance(узел, bool):
            итог[префикс] = f"логическое={узел}"
        elif isinstance(узел, (int, float)):
            итог[префикс] = "число"
        else:
            текст = str(узел)
            итог[префикс] = "строка" if текст else "пустая строка"
    return итог


def собрать(адрес: str) -> dict:
    витрина = urllib.parse.urlparse(адрес).netloc
    разметка = разметка_страницы(адрес)
    если = {"адрес": адрес, "витрина": витрина, "разметка": разметка}
    if "не_прочитано" in разметка:
        return если
    пара = кандидат_источника(разметка)
    если["кандидат"] = пара
    издатель = разметка.get("data-publisher-id")
    if not (пара and издатель):
        если["плейлист"] = {"не_прочитано":
                            "в разметке нет кандидата или номера издателя"}
        return если
    если["плейлист"] = плейлист(издатель, пара[0], пара[1], витрина)
    return если


def разделяющие(играют: list[dict], не_играют: list[dict]) -> dict:
    """Поля, чей КЛАСС значения делит выборку ровно по границе исхода."""
    def классы(записи):
        итог: dict[str, set[str]] = {}
        for з in записи:
            плоско = {}
            плоско.update({f"разметка.{к}": v for к, v in
                           поля(з.get("разметка") or {}).items()})
            ответ = (з.get("плейлист") or {}).get("ответ")
            if ответ is not None:
                плоско.update({f"плейлист.{к}": v
                               for к, v in поля(ответ).items()})
            for путь, класс in плоско.items():
                if ЗАКРЫТО.search(путь):
                    continue
                итог.setdefault(путь, set()).add(класс)
            for путь in set(итог) - set(плоско):
                итог[путь].add("поля нет")
        return итог

    а, б = классы(играют), классы(не_играют)
    пути = set(а) | set(б)
    найдено = {}
    for путь in sorted(пути):
        классы_а = а.get(путь, {"поля нет"})
        классы_б = б.get(путь, {"поля нет"})
        if len(классы_а) == 1 and len(классы_б) == 1 and классы_а != классы_б:
            найдено[путь] = (sorted(классы_а)[0], sorted(классы_б)[0])
    return {"разделяющие": найдено, "сравнено_полей": len(пути)}


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--plays", action="append", default=[],
                   help="адрес карточки, которая ИГРАЕТ (проверено плеером)")
    р.add_argument("--fails", action="append", default=[],
                   help="адрес карточки, которая НЕ ИГРАЕТ (проверено плеером)")
    р.add_argument("--json", action="store_true")
    дов = р.parse_args(аргв)

    играют = [собрать(а) for а in дов.plays]
    не_играют = [собрать(а) for а in дов.fails]
    прочитано = [з for з in играют + не_играют
                 if "не_прочитано" not in (з.get("разметка") or {})]
    if not прочитано:
        print("НЕ ИЗМЕРЕНО: ни одна страница не прочитана")
        return 2

    итог = разделяющие(играют, не_играют)
    if дов.json:
        print(json.dumps({"играют": играют, "не_играют": не_играют, **итог},
                         ensure_ascii=False, indent=1, default=str))
        return 3 if итог["разделяющие"] else 0

    print(f"карточек: играют {len(играют)}, не играют {len(не_играют)};"
          f" страниц прочитано {len(прочитано)}")
    for з in играют + не_играют:
        разм = з.get("разметка") or {}
        пл = з.get("плейлист") or {}
        ответ = пл.get("ответ") or {}
        состояние = разм.get("не_прочитано") or f"состояние {разм.get('data-state')}"
        дорожек = len(ответ.get("items") or []) if ответ else None
        print(f"   {з['адрес'][:62]:64} {состояние:22}"
              f" агрегатор {(з.get('кандидат') or ('—',))[0]:4}"
              f" плейлист {pl_код(пл)} дорожек {дорожек}")
    print(f"\nсравнено полей: {итог['сравнено_полей']}")
    if not итог["разделяющие"]:
        print("ПРИЗНАКА НЕТ среди собранных полей: ни одно поле разметки или"
              " плейлиста не делит карточки по границе «играет / не играет».")
        print("Значит доступность предсказывается только зондом показа.")
        return 0
    print("КАНДИДАТЫ В ПРИЗНАК (класс у играющих → класс у неиграющих):")
    for путь, (а, б) in итог["разделяющие"].items():
        print(f"   {путь:46} {а} → {б}")
    if len(не_играют) < 2:
        print("\nПредел: неиграющая карточка одна, поэтому это кандидаты,"
              " а не признак. Нужен второй отрицательный пример.")
    return 3


def pl_код(пл: dict) -> str:
    if "не_прочитано" in пл:
        return пл["не_прочитано"][:18]
    return str(пл.get("код"))


if __name__ == "__main__":
    sys.exit(main())
