#!/usr/bin/env python3
"""Метки времени в журнале ночного прогона не должны опережать часы.

ЗАЧЕМ. Дважды за 23 октября я писала метки вперёд часов: в журнале стояли
22:10 и 22:20 при фактических 21:48 и 21:51, а в сообщении соседней линии —
«22:2xZ» при её `date -u` 21:52Z. Второй раз ошибку нашла не я. Метка,
написанная по памяти, выглядит как измерение и ломает именно то, для чего
журнал нужен: по нему потом судят, что когда делалось и не оборвался ли
прогон.

ЧТО ПРОВЕРЯЕТСЯ. В журнале (`docs/NIGHT_RUN_*.md`) строки таблицы начинаются
с метки времени UTC вида ``| 21:48 |``. Каждая такая метка сравнивается с
часами. Метка позже текущего времени — отказ с перечнем.

ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ. Она не судит метки внутри текста: там встречаются
времена чужих выпусков, прошлых суток и приблизительные «21:4xZ». Отбор идёт
только по первому столбцу таблицы — тому, который заполняю я и по которому
читают ход прогона.

МНОГОДНЕВНЫЕ ЖУРНАЛЫ. Метка судится только если её РАЗДЕЛ относится к
сегодняшним суткам. Дата раздела берётся из ближайшего заголовка выше
(«## 22.10», «## 2026-10-22»), а при отсутствии — из имени файла
(`NIGHT_RUN_20261023.md`). Повод измеренный: соседняя линия прогнала первую
версию на своём журнале за несколько суток и получила 5 отказов из 41 метки —
все пять в разделах за 21 и 22 октября, сравнённых с часами 23-го. Проверка,
которая ругается на верные записи, будет выключена, и это хуже отсутствия
проверки.

ПРЕДЕЛ. Небольшой запас вперёд допускается (``--tolerance``, по умолчанию 2
минуты): запись делается в начале шага, и часы могут уйти на минуту-две за
время правки файла. Запас именно небольшой — иначе проверка перестанет
ловить то, ради чего написана.

    python3 automation/local/night-log-clock-check.py
    python3 automation/local/night-log-clock-check.py --file docs/NIGHT_RUN_20261023.md
"""
from __future__ import annotations

import argparse
import datetime
import glob
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ОБРАЗЕЦ_ЖУРНАЛА = "docs/NIGHT_RUN_*.md"
#: Метка первого столбца: «| 21:48 |» или «| 21:48 | …».
МЕТКА = re.compile(r"^\|\s*(\d{1,2}):(\d{2})\s*\|")


#: Заголовок таблицы журнала. Строки судятся только внутри неё: рядом стоит
#: таблица плана, где время — срок, а не метка сделанного.
ЗАГОЛОВОК_ЖУРНАЛА = re.compile(r'^\|[^|]*\|\s*взятая задача\s*\|')

#: Дата раздела: «## 23.10», «## 2026-10-23», «### 22.10.2026».
ДАТА_ЗАГОЛОВКА = re.compile(
    r"^#{1,6}\s.*?(?:(\d{4})-(\d{2})-(\d{2})|\b(\d{1,2})\.(\d{1,2})"
    r"(?:\.(\d{4}))?\b)")
#: Дата в имени файла: NIGHT_RUN_20261023.md
ДАТА_ИМЕНИ = re.compile(r"(\d{4})(\d{2})(\d{2})")


def дата_заголовка(строка: str, год_по_умолчанию: int):
    """(месяц, день) из заголовка или None, если даты в нём нет."""
    м = ДАТА_ЗАГОЛОВКА.match(строка.strip())
    if not м:
        return None
    if м.group(1):
        return int(м.group(2)), int(м.group(3))
    день, месяц = int(м.group(4)), int(м.group(5))
    # В заголовках сети принят порядок «день.месяц»: «## 22.10» — 22 октября.
    if 1 <= месяц <= 12 and 1 <= день <= 31:
        return месяц, день
    return None


def метки(текст: str, *, имя_файла: str = "",
          сегодня=None) -> list[tuple[int, int, int]]:
    """(номер строки, час, минута) для метк первого столбца.

    Если `сегодня` задано, остаются только метки из разделов СЕГОДНЯШНЕЙ
    даты: дата берётся из ближайшего заголовка выше, иначе из имени файла.
    """
    из_имени = None
    м = ДАТА_ИМЕНИ.search(имя_файла or "")
    if м:
        из_имени = (int(м.group(2)), int(м.group(3)))
    текущая = из_имени
    год = сегодня.year if сегодня else 2026
    итог = []
    # ТАБЛИЦА ПЛАНА — НЕ ЖУРНАЛ. В контрольной точке рядом с журналом стоит
    # таблица «что проверять дальше», и её время — будущее по смыслу: 07:00
    # для итогового отчёта не опережение, а срок. Поэтому судятся только
    # строки таблицы журнала: она опознаётся по своему заголовку «взятая
    # задача» и кончается следующим заголовком раздела. Если заголовка
    # журнала в файле нет вовсе, судятся все строки с метками — так работали
    # прежние вызовы, и ломать их незачем.
    # Поиск строго по строкам: образец закреплён в начало строки, а `search`
    # по целому тексту проверил бы только самое его начало и всегда давал бы
    # «журнала нет». Ровно эта ошибка и обнулила отделение плана с первого
    # раза: таблица плана продолжала судиться.
    есть_журнал = any(ЗАГОЛОВОК_ЖУРНАЛА.match(с.strip())
                      for с in текст.splitlines())
    в_журнале = not есть_журнал
    for н, строка in enumerate(текст.splitlines(), 1):
        if ЗАГОЛОВОК_ЖУРНАЛА.match(строка.strip()):
            в_журнале = True
            continue
        д = дата_заголовка(строка, год)
        if д:
            текущая = д
            if есть_журнал:
                в_журнале = False
            continue
        if строка.lstrip().startswith("## ") and есть_журнал:
            в_журнале = False
            continue
        if not в_журнале:
            continue
        м2 = МЕТКА.match(строка.strip())
        if not м2:
            continue
        час, минута = int(м2.group(1)), int(м2.group(2))
        if час > 23 or минута > 59:
            continue
        if сегодня is not None:
            если_сегодня = текущая is None or текущая == (сегодня.month,
                                                          сегодня.day)
            # НОЧЬ ПЕРЕХОДИТ ПОЛНОЧЬ, А РАЗДЕЛ ОСТАЁТСЯ ВЧЕРАШНИМ. Журнал
            # ночного прогона называется по дате начала (`NIGHT_RUN_20261023`),
            # и после полуночи его раздел перестаёт быть «сегодняшним» —
            # тогда проверка переставала судить ВСЕ метки и молчала. Ровно так
            # 24.10 в 00:04Z мимо неё прошли метки 00:25 и 00:48, написанные
            # вперёд часов. Утренние метки вчерашнего раздела — это та же
            # ночь, и судить их надо по сегодняшним часам.
            if not если_сегодня and час < 12:
                вчера = (сегодня - datetime.timedelta(days=1))
                если_сегодня = текущая == (вчера.month, вчера.day)
            if not если_сегодня:
                continue
        итог.append((н, час, минута))
    return итог


def опережающие(текст: str, сейчас: datetime.datetime,
                запас_минут: int, *, имя_файла: str = ""
                ) -> list[tuple[int, str]]:
    """Метки, которые позже часов более чем на запас.

    Сутки берутся из самих часов: журнал ведётся в пределах одной ночи, и
    метка «01:10» в 21:53 — это следующие сутки, а не опережение. Поэтому
    опережающей считается только метка в тех же сутках, что и `сейчас`, и
    только если она больше текущего времени: ночной переход через полночь
    даёт час меньше текущего и под правило не попадает.
    """
    порог = сейчас + datetime.timedelta(minutes=запас_минут)
    плохие = []
    for н, час, минута in метки(текст, имя_файла=имя_файла,
                                сегодня=сейчас):
        # Метка «после полуночи» при текущем вечернем времени — это уже
        # следующие сутки, и сравнивать её с вечерними часами нельзя.
        если_утро = час < 12 and сейчас.hour >= 12
        if если_утро:
            continue
        когда = сейчас.replace(hour=час, minute=минута, second=0,
                               microsecond=0)
        if когда > порог:
            плохие.append((н, "%02d:%02d" % (час, минута)))
    return плохие


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--file", action="append", default=[])
    р.add_argument("--tolerance", type=int, default=2,
                   help="допустимый запас вперёд в минутах")
    а = р.parse_args(аргв)
    файлы = [pathlib.Path(п) for п in а.file] or [
        pathlib.Path(п) for п in sorted(glob.glob(str(КОРЕНЬ / ОБРАЗЕЦ_ЖУРНАЛА)))]
    if not файлы:
        print(f"НЕ ИЗМЕРЕНО: журналов по образцу {ОБРАЗЕЦ_ЖУРНАЛА} нет",
              file=sys.stderr)
        return 2
    сейчас = datetime.datetime.now(datetime.timezone.utc)
    всего = плохих = разметок = 0
    for ф in файлы:
        if not ф.is_file():
            print(f"НЕ ИЗМЕРЕНО: файла нет: {ф}", file=sys.stderr)
            return 2
        текст = ф.read_text(encoding="utf-8")
        найдено = метки(текст, имя_файла=ф.name, сегодня=сейчас)
        вперёд = опережающие(текст, сейчас, а.tolerance,
                             имя_файла=ф.name)
        всего += len(найдено)
        плохих += len(вперёд)
        всех = len(метки(текст))
        разметок += всех
        print("%-34s метк всего %3d, судятся (сегодняшние) %3d, опережают часы %d"
              % (ф.name, всех, len(найдено), len(вперёд)))
        for н, метка in вперёд:
            print("   строка %d: %s — позже текущего %s"
                  % (н, метка, сейчас.strftime("%H:%M")))
    print("ЗАВЕРШЕНО: часы %s, метк всего %d, опережающих %d"
          % (сейчас.strftime("%Y-%m-%dT%H:%M:%SZ"), всего, плохих),
          file=sys.stderr)
    if плохих:
        return 1
    # НОЛЬ СУДИМЫХ МЕТОК — ЭТО «НЕ ИЗМЕРЕНО», А НЕ «НАРУШЕНИЙ НЕТ».
    # 24.10 в 00:04Z сторож напечатал «опережающих 0» и вернул ноль, не
    # рассудив ни одной из сорока метк: раздел журнала перестал быть
    # сегодняшним после полуночи. Вердикт звучал как успех. Сторож класса 22
    # сработал по классу 24, и отличить одно от другого в коде выхода было
    # нельзя. Теперь можно.
    if разметок and not всего:
        print("НЕ ИЗМЕРЕНО: метки в файлах есть (%d), но ни одна не отнесена"
              " к текущей ночи — судить было нечего, и ноль здесь не вердикт"
              % разметок, file=sys.stderr)
        return 3
    return 0


if __name__ == "__main__":
    sys.exit(main())
