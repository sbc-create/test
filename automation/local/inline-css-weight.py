#!/usr/bin/env python3
"""Сколько весят комментарии в inline-CSS страницы — до и после сжатия.

Только чтение публичных страниц.

ЗАЧЕМ. Пояснения к вёрстке (почему снят потолок высоты, какие числа измерены в
Chromium) написаны в тех же блоках `<style>`, которые уезжают в HTML каждой
страницы. В исходнике они на месте по делу: без них следующая правка повторит
ошибку. В отдаваемой странице они — байты на каждый просмотр, и ни один
посетитель их не читает. Страница не кешируется отдельно от стиля: стиль
встроен, значит байты едут снова при каждом открытии.

ЧЕСТНЫЙ СЧЁТ. Сырые байты весом не являются: страницы отдаются сжатыми, а
комментарии сжимаются хорошо. Поэтому считается И сырой размер, И прирост в
том виде, в каком это едет к посетителю: gzip всей страницы минус gzip той же
страницы без комментариев в её `<style>`. Локальный gzip взят уровня 9 —
сервер жмёт слабее, поэтому названная выгода скорее нижняя граница, чем
верхняя. Проверено на `animedia.space`: сервер отдаёт 67.0 КиБ, локальный
gzip -9 того же тела даёт 52.2 КиБ.

ИСХОДЫ РАЗДЕЛЬНЫЕ.

* ``INLINE CSS НЕТ``    — блоков `<style>` на странице нет вовсе (так у
  `yummyani.biz`). Это НЕ «комментариев 0 КиБ, всё хорошо»: мерить нечего;
* ``КОММЕНТАРИЕВ НЕТ``  — блоки есть, комментариев в них нет;
* ``В ПРЕДЕЛАХ``        — прирост после сжатия меньше ``ПОРОГ_ПРИРОСТА_КИБ``;
* ``ЗАМЕТНЫЙ ВЕС``      — прирост не меньше порога;
* ``НЕ ИЗМЕРЕНО``       — страница не получена.

    python3 automation/local/inline-css-weight.py [--domain <домен> …] [--json]

Коды: 0 — нигде не заметно; 1 — где-то заметный вес; 2 — ничего не измерено.
"""
from __future__ import annotations

import argparse
import gzip
import json
import re
import subprocess
import sys

#: Ниже этого прироста правка не стоит отдельного выпуска: на мобильной сети
#: 2 КиБ — это единицы миллисекунд. Порог назван, а не угадан.
ПОРОГ_ПРИРОСТА_КИБ = 2.0

ВИТРИНЫ_ПО_УМОЛЧАНИЮ = ("lordserial33.biz", "zonafilm.space", "animedia.space",
                        "animeg0.site", "yummyani.biz")

СТИЛЬ = re.compile(r"<style[^>]*>(.*?)</style>", re.S)
КОММЕНТАРИЙ = re.compile(r"/\*.*?\*/", re.S)

CSS_НЕТ = "INLINE CSS НЕТ"
КОММЕНТАРИЕВ_НЕТ = "КОММЕНТАРИЕВ НЕТ"
В_ПРЕДЕЛАХ = "В ПРЕДЕЛАХ"
ЗАМЕТНО = "ЗАМЕТНЫЙ ВЕС"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНО"


def разобрать(тело: str) -> dict:
    """Замер по телу страницы. Чистая функция: сеть здесь не нужна."""
    if not тело:
        return {"ошибка": "тело страницы пустое"}
    блоки = СТИЛЬ.findall(тело)
    css = "".join(блоки)
    без_блоков = [КОММЕНТАРИЙ.sub("", б) for б in блоки]
    чистое = тело
    for блок, очищенный in zip(блоки, без_блоков):
        чистое = чистое.replace(блок, очищенный, 1)
    байт_css = len("".join(блоки).encode())
    байт_без = len("".join(без_блоков).encode())
    всего = len(gzip.compress(тело.encode(), 9))
    урезано = len(gzip.compress(чистое.encode(), 9))
    return {
        "html_байт": len(тело.encode()),
        "блоков_style": len(блоки),
        "css_байт": байт_css,
        "комментариев_байт": байт_css - байт_без,
        "доля_комментариев_в_css": round(
            (байт_css - байт_без) / байт_css * 100, 1) if байт_css else 0.0,
        "gzip_байт": всего,
        "gzip_прирост_байт": всего - урезано,
    }


def оценить(замер: dict) -> dict:
    """Исход по замеру. Чистая функция."""
    if замер.get("ошибка"):
        return {"исход": НЕ_ИЗМЕРЕНО, "почему": замер["ошибка"]}
    if not замер.get("блоков_style"):
        return {"исход": CSS_НЕТ,
                "почему": "блоков <style> на странице нет — мерить нечего"}
    if not замер.get("комментариев_байт"):
        return {"исход": КОММЕНТАРИЕВ_НЕТ,
                "почему": f"{замер['блоков_style']} блок(ов) без комментариев"}
    прирост = замер["gzip_прирост_байт"] / 1024
    if прирост < ПОРОГ_ПРИРОСТА_КИБ:
        return {"исход": В_ПРЕДЕЛАХ,
                "почему": f"после сжатия {прирост:.1f} КиБ —"
                          f" ниже порога {ПОРОГ_ПРИРОСТА_КИБ} КиБ"}
    return {"исход": ЗАМЕТНО,
            "почему": f"после сжатия {прирост:.1f} КиБ на каждый просмотр"
                      f" ({замер['комментариев_байт'] / 1024:.1f} КиБ сырыми,"
                      f" {замер['доля_комментариев_в_css']}% всего inline CSS)"}


def достать(домен: str) -> tuple[str, str]:
    """Тело страницы и объявленное сервером сжатие."""
    п = subprocess.run(
        ["curl", "-sS", "--max-time", "40", "--compressed", "-D", "-",
         f"https://{домен}/"], capture_output=True, text=True)
    текст = п.stdout or ""
    кодирование = ""
    граница = -1
    for разделитель in ("\r\n\r\n", "\n\n"):
        граница = текст.find(разделитель)
        if граница >= 0:
            заголовки, тело = текст[:граница], текст[граница + len(разделитель):]
            break
    else:
        заголовки, тело = "", текст
    for строка in заголовки.splitlines():
        if строка.lower().startswith("content-encoding:"):
            кодирование = строка.split(":", 1)[1].strip()
    return тело, кодирование


def проверить(домен: str) -> dict:
    тело, кодирование = достать(домен)
    замер = разобрать(тело)
    замер["домен"] = домен
    замер["сжатие_сервера"] = кодирование or "нет"
    замер.update(оценить(замер))
    return замер


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    домены = а.domain or list(ВИТРИНЫ_ПО_УМОЛЧАНИЮ)
    итоги = [проверить(д) for д in домены]

    if а.json:
        print(json.dumps({"витрин": len(итоги), "порог_прироста_КиБ":
                          ПОРОГ_ПРИРОСТА_КИБ, "витрины": итоги},
                         ensure_ascii=False, indent=2))
    else:
        print(f"{'домен':20} {'HTML':>8} {'style':>6} {'CSS':>8}"
              f" {'коммент':>8} {'доля':>6} {'gzip':>8} {'прирост':>8} исход")
        for и in итоги:
            if и["исход"] == НЕ_ИЗМЕРЕНО:
                print(f"{и['домен']:20} {и['почему']}")
                continue
            print(f"{и['домен']:20} {и['html_байт']/1024:7.1f}К"
                  f" {и['блоков_style']:6}"
                  f" {и['css_байт']/1024:7.1f}К"
                  f" {и['комментариев_байт']/1024:7.1f}К"
                  f" {и['доля_комментариев_в_css']:5.1f}%"
                  f" {и['gzip_байт']/1024:7.1f}К"
                  f" {и['gzip_прирост_байт']/1024:7.1f}К {и['исход']}")
        for и in итоги:
            print(f"  {и['домен']}: {и['почему']}"
                  f" | сжатие сервера {и.get('сжатие_сервера', '—')}")

    if all(и["исход"] == НЕ_ИЗМЕРЕНО for и in итоги):
        return 2
    return 1 if any(и["исход"] == ЗАМЕТНО for и in итоги) else 0


if __name__ == "__main__":
    sys.exit(main())
