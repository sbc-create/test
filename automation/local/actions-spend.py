#!/usr/bin/env python3
"""Куда уходит бюджет GitHub Actions: прогоны, минуты, причина запуска.

Зачем. Бюджет исчерпан (B019: «The job was not started because an Actions
budget is preventing further use»), и прежде чем что-то сокращать, нужно
знать, ЧТО именно расходует. Инструмент отвечает на это числами из API, а не
по впечатлению.

Три ответа, которые он даёт по отдельности:

* **расход** — прогоны по репозиторию и рабочему процессу: сколько, сколько
  минут, по какой причине запущены (`event`);
* **повторная проверка одной версии** — несколько завершённых прогонов одного
  рабочего процесса на одном `head_sha`. Это и есть деньги за уже известный
  ответ;
* **прогон после правки документации** — прогон, в коммите которого изменены
  только файлы, не влияющие на сборку (`.md`, `docs/`, отчёты);
* **вытесненный прогон** — более новый прогон той же пары (рабочий процесс,
  ветвь) создан раньше, чем этот закончился. Его результат уже не относится к
  голове ветви, и отмена вытесненных убрала бы эти минуты. Это главное число:
  13.10 оно составило 64,2 % всей квоты.

Чего инструмент НЕ знает и не выдумывает: размера самого бюджета. API
биллинга (`/users/{u}/settings/billing/actions`) требует права `user`,
которого у токена нет, — и это печатается как предел измерения, а не
заменяется «обычным» числом тарифа.

Минуты РЕКОНСТРУИРУЮТСЯ по заданиям: сумма ceil(длительность/60) по тем
заданиям прогона, которые реально шли на раннере GitHub. Поле `billable` из
`/actions/runs/{id}/timing` НЕ используется: измерено 13.10, этому токену он
отдаёт 0 даже у прогона, шедшего четыре с половиной минуты (38326615302).
Множитель Linux равен 1; для других ОС реконструкция была бы заниженной, и
инструмент об этом говорит, если встретит их.

Открытые репозитории считаются ОТДЕЛЬНО: их минуты бесплатны и квоту не
тратят. Фабрика лежит в открытом `sbc-create/test`, и смешивать её расход с
расходом закрытых ячеек нельзя — вывод получится обратный.

Только чтение API. Ничего не запускает и не отменяет.

    python3 automation/local/actions-spend.py --hours 48
    python3 automation/local/actions-spend.py --hours 48 --json
    python3 automation/local/actions-spend.py --repo ott-app-sandbox --hours 168
"""
from __future__ import annotations

import argparse
import collections
import datetime as dt
import json
import math
import subprocess
import sys

ВЛАДЕЛЕЦ = "sbc-create"
НЕ_ИЗМЕРЕНО = "НЕ ИЗМЕРЕНЫ"
#: Пути, изменение которых сборку и тесты не затрагивает. Список намеренно
#: узкий: лучше не зачесть документацию, чем зачесть код за документацию.
ТОЛЬКО_ТЕКСТ = (".md", ".txt", ".rst")
ТЕКСТОВЫЕ_КАТАЛОГИ = ("docs/", "adr/", "reports/", ".github/ISSUE_TEMPLATE/")


def гх(*арг: str, предел: int = 180) -> tuple[int, str]:
    г = subprocess.run(["gh", *арг], capture_output=True, text=True,
                       timeout=предел)
    return г.returncode, (г.stdout or "")


def api(путь: str, предел: int = 180) -> object | None:
    код, вывод = гх("api", путь, предел=предел)
    if код != 0:
        return None
    try:
        return json.loads(вывод or "null")
    except ValueError:
        return None


def репозитории_с_закрытостью() -> list[tuple[str, bool]]:
    """(имя, закрыт ли). Закрытость решает, тратит ли репозиторий квоту."""
    итог: list[tuple[str, bool]] = []
    страница = 1
    while страница <= 5:
        д = api(f"user/repos?per_page=100&page={страница}&affiliation=owner")
        if not isinstance(д, list) or not д:
            break
        итог += [(str(р["name"]), bool(р.get("private"))) for р in д
                 if isinstance(р, dict) and р.get("name")]
        if len(д) < 100:
            break
        страница += 1
    return итог


def репозитории() -> list[str]:
    """Все репозитории владельца, включая ЗАКРЫТЫЕ.

    `users/<логин>/repos` отдаёт только открытые: первый замер 13.10 так и
    получил один репозиторий `test` из двадцати шести, и «расход 0 минут»
    оказался свойством выбранного пути, а не действительности. Закрытые видит
    только `/user/repos` с правами токена.
    """
    итог: list[str] = []
    страница = 1
    while страница <= 5:
        д = api(f"user/repos?per_page=100&page={страница}&affiliation=owner")
        if not isinstance(д, list) or not д:
            break
        итог += [str(р["name"]) for р in д
                 if isinstance(р, dict) and р.get("name")]
        if len(д) < 100:
            break
        страница += 1
    return итог


def прогоны(репо: str, с_даты: str) -> list[dict]:
    """Прогоны репозитория, созданные не раньше даты. Пагинация до конца."""
    итог: list[dict] = []
    страница = 1
    while страница <= 10:
        д = api(f"repos/{ВЛАДЕЛЕЦ}/{репо}/actions/runs"
                f"?per_page=100&page={страница}&created=%3E%3D{с_даты}")
        если = (д or {}).get("workflow_runs") if isinstance(д, dict) else None
        if not если:
            break
        итог += если
        if len(если) < 100:
            break
        страница += 1
    return итог


def _время(с) -> dt.datetime | None:
    if not с:
        return None
    try:
        return dt.datetime.fromisoformat(str(с).replace("Z", "+00:00"))
    except ValueError:
        return None


def минуты(репо: str, ид: int) -> tuple[int | None, int]:
    """(минуты прогона, сколько заданий посчитано).

    Считается по заданиям: GitHub списывает за каждое, округляя вверх до
    минуты. Задание без `runner_name` не шло на раннере (пропущено по `if`) и
    не стоит ничего. None — задания не получены, и это не ноль.
    """
    д = api(f"repos/{ВЛАДЕЛЕЦ}/{репо}/actions/runs/{ид}/jobs?per_page=100")
    if not isinstance(д, dict) or "jobs" not in д:
        return None, 0
    итог = 0
    посчитано = 0
    for з in д.get("jobs") or []:
        н, к = _время(з.get("started_at")), _время(з.get("completed_at"))
        if not н or not к or not з.get("runner_name"):
            continue
        секунд = (к - н).total_seconds()
        if секунд <= 0:
            continue
        итог += math.ceil(секунд / 60)
        посчитано += 1
    return итог, посчитано


def _конец_заданий(репо: str, ид: int):
    """Когда закончилось последнее задание прогона. None — не измерено.

    `updated_at` прогона для этого не годится: он меняется и после окончания
    заданий (например при загрузке артефактов и записи итога).
    """
    д = api(f"repos/{ВЛАДЕЛЕЦ}/{репо}/actions/runs/{ид}/jobs?per_page=100")
    if not isinstance(д, dict):
        return None
    концы = [_время(з.get("completed_at")) for з in (д.get("jobs") or [])]
    концы = [к for к in концы if к]
    return max(концы) if концы else None


def только_текст(файлы: list[str]) -> bool:
    """Все изменённые файлы — текст, не влияющий на сборку."""
    if not файлы:
        return False
    for ф in файлы:
        текстовый = (ф.lower().endswith(ТОЛЬКО_ТЕКСТ)
                     or any(ф.startswith(к) for к in ТЕКСТОВЫЕ_КАТАЛОГИ))
        if not текстовый:
            return False
    return True


def файлы_коммита(репо: str, sha: str) -> list[str] | None:
    д = api(f"repos/{ВЛАДЕЛЕЦ}/{репо}/commits/{sha}")
    if not isinstance(д, dict):
        return None
    файлы = д.get("files")
    if not isinstance(файлы, list):
        return None
    return [str(ф.get("filename")) for ф in файлы if isinstance(ф, dict)]


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--hours", type=float, default=48.0)
    р.add_argument("--repo", action="append", default=[],
                   help="только эти репозитории (без префикса владельца)")
    р.add_argument("--json", action="store_true")
    р.add_argument("--no-timing", action="store_true",
                   help="не спрашивать минуты (быстрее, но расход НЕ ИЗМЕРЕН)")
    р.add_argument("--no-files", action="store_true",
                   help="не спрашивать состав коммитов (быстрее)")
    р.add_argument("--budget", type=float, default=None,
                   help="месячный бюджет в минутах (вход владельца): с ним "
                        "считаются суточная норма и прогноз исчерпания")
    а = р.parse_args(аргв)

    код, _ = гх("auth", "status", предел=60)
    if код != 0:
        print("ОТКАЗ: gh не авторизован — расход НЕ ИЗМЕРЕН", file=sys.stderr)
        return 2

    граница = dt.datetime.now(dt.timezone.utc) - dt.timedelta(hours=а.hours)
    с_даты = граница.strftime("%Y-%m-%d")

    закрытость = dict(репозитории_с_закрытостью())
    список = а.repo or sorted(закрытость)
    if not список:
        print("ОТКАЗ: перечень репозиториев не получен — расход НЕ ИЗМЕРЕН",
              file=sys.stderr)
        return 2

    все: list[dict] = []
    для_отчёта: dict[str, list[dict]] = {}
    for репо in список:
        свои = [п for п in прогоны(репо, с_даты)
                if str(п.get("created_at") or "") >= граница.strftime("%Y-%m-%dT%H:%M:%SZ")]
        if not свои:
            continue
        для_отчёта[репо] = свои
        все += [{**п, "_репо": репо} for п in свои]

    # Минуты — отдельным проходом, чтобы было видно, что их может не быть.
    без_минут = 0
    заданий = 0
    for п in все:
        if а.no_timing:
            п["_минуты"] = None
            continue
        м, сколько = минуты(п["_репо"], int(п["id"]))
        п["_минуты"] = м
        заданий += сколько
        без_минут += м is None

    итог = {
        "окно_часов": а.hours,
        "с": граница.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "репозиториев_с_прогонами": len(для_отчёта),
        "прогонов": len(все),
        "минут_не_измерено_у": без_минут,
        "предел_измерения": (
            "размер БЮДЖЕТА здесь не измеряется: API биллинга требует права "
            "'user', которого у токена нет. Подставлять «обычное» число тарифа "
            "нельзя — это вход владельца."),
    }

    по_репо = collections.Counter()
    минут_по_репо = collections.Counter()
    по_процессу = collections.Counter()
    минут_по_процессу = collections.Counter()
    по_событию = collections.Counter()
    минут_по_событию = collections.Counter()
    for п in все:
        ключ_п = f"{п['_репо']}:{п.get('name')}"
        по_репо[п["_репо"]] += 1
        по_процессу[ключ_п] += 1
        по_событию[str(п.get("event"))] += 1
        м = п.get("_минуты") or 0
        минут_по_репо[п["_репо"]] += м
        минут_по_процессу[ключ_п] += м
        минут_по_событию[str(п.get("event"))] += м

    # Повторная проверка одной версии.
    по_версии: dict[tuple, list[dict]] = collections.defaultdict(list)
    for п in все:
        if п.get("status") != "completed":
            continue
        по_версии[(п["_репо"], str(п.get("name")), str(п.get("head_sha")))].append(п)
    повторы = {k: v for k, v in по_версии.items() if len(v) > 1}
    минут_повторов = 0.0
    for v in повторы.values():
        # Первый прогон нужен, остальные — повтор уже известного ответа.
        минут_повторов += sum((п.get("_минуты") or 0) for п in v[1:])

    # Вытесненные прогоны: более новый прогон той же пары создан раньше,
    # чем этот закончился. Конец берётся по заданиям — у прогона в API нет
    # поля «когда закончились задания», а `updated_at` меняется и позже.
    for п in все:
        п["_конец"] = _конец_заданий(п["_репо"], int(п["id"]))
    по_паре: dict[tuple, list[dict]] = collections.defaultdict(list)
    for п in все:
        по_паре[(п["_репо"], str(п.get("name")), str(п.get("head_branch")))].append(п)
    вытеснены: list[dict] = []
    for свои in по_паре.values():
        свои.sort(key=lambda x: str(x.get("created_at")))
        for i, п in enumerate(свои[:-1]):
            следующий = _время(свои[i + 1].get("created_at"))
            if следующий and п["_конец"] and следующий < п["_конец"]:
                вытеснены.append(п)
    минут_вытесненных = sum((п.get("_минуты") or 0) for п in вытеснены)

    # Прогоны после правки только документации.
    документация: list[dict] = []
    if not а.no_files:
        проверено: dict[tuple, bool | None] = {}
        for п in все:
            sha = str(п.get("head_sha"))
            ключ = (п["_репо"], sha)
            if ключ not in проверено:
                файлы = файлы_коммита(п["_репо"], sha)
                проверено[ключ] = None if файлы is None else только_текст(файлы)
            if проверено[ключ]:
                документация.append(п)
    минут_документации = sum((п.get("_минуты") or 0) for п in документация)

    итог["по_репозиториям"] = [
        {"репо": р, "прогонов": н, "минут": round(минут_по_репо[р], 1)}
        for р, н in по_репо.most_common()]
    итог["по_рабочим_процессам"] = [
        {"процесс": к, "прогонов": н, "минут": round(минут_по_процессу[к], 1)}
        for к, н in по_процессу.most_common()]
    итог["по_причине_запуска"] = [
        {"event": е, "прогонов": н, "минут": round(минут_по_событию[е], 1)}
        for е, н in по_событию.most_common()]
    итог["повторная_проверка_одной_версии"] = {
        "групп": len(повторы),
        "лишних_прогонов": sum(len(v) - 1 for v in повторы.values()),
        "лишних_минут": round(минут_повторов, 1),
        "примеры": [
            {"репо": k[0], "процесс": k[1], "sha": k[2][:12], "прогонов": len(v),
             "минут_всего": round(sum((п.get("_минуты") or 0) for п in v), 1)}
            for k, v in sorted(повторы.items(),
                               key=lambda kv: -sum((п.get("_минуты") or 0)
                                                   for п in kv[1]))[:10]],
    }
    итог["вытесненные_прогоны"] = {
        "прогонов": len(вытеснены),
        "минут": round(минут_вытесненных, 1),
        "доля_минут": (round(100 * минут_вытесненных / всего_минут_черновик, 1)
                       if (всего_минут_черновик := sum(минут_по_репо.values()))
                       else None),
        "примеры": [
            {"репо": п["_репо"], "процесс": п.get("name"),
             "ветвь": п.get("head_branch"), "событие": п.get("event"),
             "sha": str(п.get("head_sha"))[:12],
             "минут": round(п.get("_минуты") or 0, 1)}
            for п in sorted(вытеснены, key=lambda x: -(x.get("_минуты") or 0))[:10]],
    }
    итог["после_правки_только_документации"] = {
        "прогонов": len(документация),
        "минут": round(минут_документации, 1),
        "примеры": [{"репо": п["_репо"], "процесс": п.get("name"),
                     "sha": str(п.get("head_sha"))[:12],
                     "минут": round(п.get("_минуты") or 0, 1)}
                    for п in документация[:10]],
    }
    всего_минут = round(sum(минут_по_репо.values()), 1)
    итог["минут_всего"] = всего_минут
    итог["минут_в_сутки"] = round(всего_минут / (а.hours / 24), 1) if а.hours else None
    итог["заданий_посчитано"] = заданий

    # Направления: квоту тратят только ЗАКРЫТЫЕ репозитории. Смешивать их с
    # открытыми нельзя — вывод получится обратный.
    направления: dict[str, float] = collections.Counter()
    for р, м in минут_по_репо.items():
        if not закрытость.get(р, True):
            направления["открытые (бесплатно, квоту не тратят)"] += м
        elif р.startswith("site-"):
            направления["ячейки сайтов (закрытые)"] += м
        else:
            направления[f"{р} (закрытый)"] += м
    квота = sum(м for р, м in минут_по_репо.items() if закрытость.get(р, True))
    в_сутки_квоты = квота / (а.hours / 24) if а.hours else 0
    итог["по_направлениям"] = [
        {"направление": н, "минут": round(м, 1),
         "в_сутки": round(м / (а.hours / 24), 1) if а.hours else None,
         "доля_квоты": (round(100 * м / квота, 1)
                        if квота and закрытость.get("", True) is not None
                        and "открытые" not in н else None)}
        for н, м in направления.most_common()]
    итог["квота"] = {
        "минут_за_окно": round(квота, 1),
        "минут_в_сутки": round(в_сутки_квоты, 1),
        "бюджет": (а.budget if а.budget else None),
        "норма_в_сутки": (round(а.budget / 30, 1) if а.budget else None),
        "суток_до_исчерпания": (round(а.budget / в_сутки_квоты, 2)
                                if а.budget and в_сутки_квоты else None),
        "предел": (None if а.budget else
                   "бюджет НЕ ИЗМЕРЕН: API биллинга требует права 'user'. "
                   "Передайте --budget <минут в месяц>, и норма с прогнозом "
                   "посчитаются; подставлять число тарифа за владельца нельзя"),
    }

    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
        return 0

    print(f"РАСХОД GITHUB ACTIONS ЗА {а.hours:g} Ч (с {итог['с']})")
    print(f"\nпрогонов: {итог['прогонов']}; репозиториев с прогонами: "
          f"{итог['репозиториев_с_прогонами']}")
    print(f"минут всего: {всего_минут}; в сутки: {итог['минут_в_сутки']}")
    if без_минут:
        print(f"у {без_минут} прогонов минуты {НЕ_ИЗМЕРЕНО} — в сумму они не "
              "вошли и нулём не считаются")
    if not а.budget:
        print(f"\nПРЕДЕЛ: {итог['предел_измерения']}")

    к = итог["квота"]
    print("\nПО НАПРАВЛЕНИЯМ:")
    for с in итог["по_направлениям"]:
        доля = f"  {с['доля_квоты']} % квоты" if с.get("доля_квоты") else ""
        print(f"   {с['направление']:44} {с['минут']:>8} мин  "
              f"{с['в_сутки']:>7} мин/сут{доля}")
    print(f"\nРАСХОД КВОТЫ (только закрытые): {к['минут_за_окно']} мин за окно, "
          f"{к['минут_в_сутки']} мин/сутки")
    if к["бюджет"]:
        print(f"   бюджет: {к['бюджет']:.0f} мин/месяц → допустимо "
              f"{к['норма_в_сутки']} мин/сутки")
        print(f"   при текущем расходе бюджет исчерпается за "
              f"{к['суток_до_исчерпания']} суток")
        если_превышение = к["минут_в_сутки"] - (к["норма_в_сутки"] or 0)
        print(f"   превышение нормы: {если_превышение:+.1f} мин/сутки "
              f"({'норма соблюдена' if если_превышение <= 0 else 'норма превышена'})")
    else:
        print(f"   ПРЕДЕЛ: {к['предел']}")

