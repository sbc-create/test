#!/usr/bin/env python3
"""Заголовок первого уровня у главной каждой витрины парка — одним проходом.

ПОВОД. 27.10 на двух витринах Zona единственным H1 главной оказалось название
редакционной подборки: страница перестала называть предмет сайта. Приёмка
`home-acceptance.py` ловит это, но поднимает браузер и ходит по путям «главная
→ подборка → карточка → просмотр» — по парку её гонять дорого, и до этого дня
ни одна проверка заголовков по парку не шла вовсе. Здесь ровно один запрос на
витрину и ровно четыре признака.

ЧТО СЧИТАЕТСЯ ДЕФЕКТОМ:

* заголовков первого уровня не ровно один — ни одного или несколько;
* H1 пуст;
* H1 побайтно равен `<title>` — страница повторяет сама себя и не добавляет ни
  слова (измерено на zonafilm.cc, animedia.space и animedia.icu);
* H1 стоит ВНУТРИ рекомендательной ленты (`data-block-key="rail:…"`) либо
  равен подписи первой ленты — тогда главная называется одной полкой
  (zonafilm.space и zonafilm12.site до правки 27.10).

ЧЕГО НЕ ДЕЛАЕТ. Не судит о тексте: хорош он или плох — область линии SEO.
Не ходит по внутренним страницам. Недоступную витрину печатает «НЕ ИЗМЕРЕНО»
с причиной и НИКОГДА не «ок»: пустой ответ дефектом не является, но и
подтверждением тоже. Пустые строки не сравниваются между собой — отсутствие
значения даёт свой признак, а не ложное равенство.

    python3 automation/local/home-headings-survey.py [--domain d]… [--out-json f]
"""
from __future__ import annotations

import argparse
import html as _html
import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ЯЧЕЙКИ = КОРЕНЬ / "config" / "site-cells.json"
#: Запрос помечается собой: иначе приёмка попадает в статистику людей.
АГЕНТ = "factory-headings-survey"
ОЖИДАНИЕ_С = 60


def домены_парка() -> list:
    """Живые витрины реестра. Исключённые и не извлечённые не трогаются."""
    д = json.loads(ЯЧЕЙКИ.read_text(encoding="utf-8"))
    итог = []
    for ячейка in д.get("cells", []):
        if ячейка.get("status") != "live":
            continue
        продвижение = ячейка.get("promotion") or {}
        if isinstance(продвижение, dict) and продвижение.get("excluded"):
            continue
        домен = ячейка.get("domain")
        if домен:
            итог.append(домен)
    return итог


def _текст(кусок: str) -> str:
    return _html.unescape(re.sub(r"<[^>]*>", "", кусок)).strip()


def разобрать(страница: str) -> dict:
    заголовок = re.search(r"<title[^>]*>(.*?)</title>", страница, re.S)
    заголовок = _текст(заголовок.group(1)) if заголовок else ""
    тело = страница.split("</head>", 1)[1] if "</head>" in страница else страница
    h1 = [_текст(к) for к in re.findall(r"<h1[^>]*>(.*?)</h1>", тело, re.S)]
    h2 = [_текст(к) for к in re.findall(r"<h2[^>]*>(.*?)</h2>", тело, re.S)]
    первый = h1[0] if h1 else ""
    подпись = next((т for т in h2 if т), "")
    # H1 ВНУТРИ рекомендательной ленты — тот самый дефект, и признак здесь
    # точный: сравнение H1 с первым H2 его не ловит, потому что у ленты,
    # забравшей H1, своего H2 не остаётся. Ключ блока ставит сам рантайм.
    внутри_ленты = False
    for место in (м.start() for м in re.finditer(r'data-block-key="rail:', тело)):
        окно = тело[место:место + 800]
        if "<h1" in окно.split("</section>", 1)[0]:
            внутри_ленты = True
            break
    # Пустое с пустым не сравнивается: отсутствие значения — свой признак.
    итог = {
        "заголовков h1": len(h1),
        "h1": первый[:90],
        "title": заголовок[:90],
        "подпись первой ленты": подпись[:90],
        "h1 пуст": not первый,
        "h1 равен title": bool(первый) and bool(заголовок) and первый == заголовок,
        "h1 равен подписи ленты": bool(первый) and bool(подпись) and первый == подпись,
        "h1 внутри ленты": внутри_ленты,
    }
    return итог


def дефекты(итог: dict) -> list:
    причины = []
    if итог.get("не измерено"):
        return []
    if итог.get("заголовков h1") != 1:
        причины.append(f"заголовков h1: {итог.get('заголовков h1')}")
    if итог.get("h1 пуст"):
        причины.append("H1 пуст")
    if итог.get("h1 равен title"):
        причины.append("H1 равен <title>")
    if итог.get("h1 равен подписи ленты"):
        причины.append("H1 равен подписи первой ленты")
    if итог.get("h1 внутри ленты"):
        причины.append("H1 стоит внутри рекомендательной ленты")
    return причины


def со_схемой(домен: str) -> bool:
    return домен.startswith(("http://", "https://"))


def адрес_главной(адрес: str) -> str:
    return адрес.rstrip("/") + "/"


def опросить(домен: str) -> dict:
    адрес = домен if со_схемой(домен) else f"https://{домен}"
    try:
        готово = subprocess.run(
            ["curl", "-sS", "-A", АГЕНТ, "-m", str(ОЖИДАНИЕ_С), адрес_главной(адрес)],
            capture_output=True, text=True, timeout=ОЖИДАНИЕ_С + 15)
    except subprocess.TimeoutExpired:
        return {"домен": домен, "не измерено": f"ответа нет за {ОЖИДАНИЕ_С} с"}
    if готово.returncode != 0 or not готово.stdout.strip():
        причина = (готово.stderr or "").strip()[:120] or f"curl код {готово.returncode}"
        return {"домен": домен, "не измерено": причина}
    return {"домен": домен, **разобрать(готово.stdout)}


def главная(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--domain", action="append", default=[],
                   help="опросить только эти домены (можно повторять)")
    р.add_argument("--out-json", default="")
    а = р.parse_args(аргв)
    домены = а.domain or домены_парка()
    итоги = [опросить(д) for д in домены]
    с_дефектом = 0
    не_измерено = 0
    for и in итоги:
        причины = дефекты(и)
        if и.get("не измерено"):
            не_измерено += 1
            print(f"{и['домен']:<24} НЕ ИЗМЕРЕНО: {и['не измерено']}")
            continue
        с_дефектом += bool(причины)
        метка = "ок        " if not причины else "ДЕФЕКТ    "
        print(f"{и['домен']:<24} {метка} h1={и['заголовков h1']} "
              f"| H1: {и['h1']!r} | title: {и['title']!r}")
        for причина in причины:
            print(f"{'':<24}            — {причина}")
    print(f"\nвитрин {len(итоги)}, с дефектом {с_дефектом}, "
          f"не измерено {не_измерено}")
    if а.out_json:
        pathlib.Path(а.out_json).write_text(
            json.dumps(итоги, ensure_ascii=False, indent=1) + "\n",
            encoding="utf-8")
        print(f"отчёт: {а.out_json}")
    return 1 if с_дефектом else 0


if __name__ == "__main__":
    raise SystemExit(главная())
