#!/usr/bin/env python3
"""Масштаб ошибок года в снимке каталога — БЕЗ обращения к внешнему источнику.

Зачем так. MOD-102 измерил расхождение года с источником на шести записях (три
из шести неверны), но перенести долю на каталог нельзя: записи выбирались по
ждущим черновикам, а не случайно. Сверить весь каталог с источником тоже нельзя:
в записях снимка нет `shikimori_id` (там `provider: mali`), а выдумывать поиск
запрещено (D199). Масштаб оставался неизвестным.

Признак, который работает ВНУТРИ снимка. У нумерованного продолжения год не
может быть РАНЬШЕ, чем у предыдущей части. Измерено 20.10 на animedia.icu:

    rukovodstvo-soten-demonov    2020
    rukovodstvo-soten-demonov-2  2021
    rukovodstvo-soten-demonov-3  2022
    rukovodstvo-soten-demonov-4  2020   ← падение
    rukovodstvo-soten-demonov-5  2025

Именно у четвёртой части источник даёт `aired_on 2024-02-23`, и 2024 ложится
между 2022 и 2025. То есть внутренний признак нашёл ту же запись, что внешняя
сверка, не обращаясь к источнику вовсе.

ЧТО ЭТОТ ПРИЗНАК НЕ УМЕЕТ, и это важнее того, что умеет:

* он НЕ говорит, какая из двух записей неверна — только что неверна хотя бы
  одна. Разбирать пару надо сверкой с источником;
* он НЕ видит франшизу, у которой ВСЕ части несут один и тот же неверный год:
  последовательность не убывает, и признак молчит. Поэтому его итог — нижняя
  граница масштаба, а не оценка;
* равные годы у соседних частей находкой НЕ считаются: два сезона в одном году
  — обычное дело. Находка только строгое убывание;
* произведение без нумерованных соседей не измеряется вовсе.

    python3 automation/local/franchise-year-order.py /srv/animedia-icu/data/animedia-01-details.json
    python3 automation/local/franchise-year-order.py <файл> --json
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

#: Хвосты, означающие нумерованную часть. `chast-N` встречается наравне с `-N`.
ХВОСТ = re.compile(r"^(?P<база>.+?)-(?:chast-)?(?P<номер>\d{1,2})$")
ПРИМЕРОВ = 10


def записи(путь: Path) -> dict[str, dict]:
    """Снимок каталога: {слаг: запись}. Иные формы отвергаются явно."""
    д = json.loads(путь.read_text(encoding="utf-8"))
    подробности = д.get("details") if isinstance(д, dict) else None
    if not isinstance(подробности, dict):
        raise SystemExit(f"{путь}: нет словаря `details` — это не снимок каталога")
    return подробности


def год(запись: dict) -> int | None:
    г = (запись or {}).get("year")
    return г if isinstance(г, int) and 1900 < г < 2100 else None


def франшизы(подробности: dict[str, dict]) -> dict[str, list[tuple[int, str, int]]]:
    """{база: [(номер части, слаг, год)]}, отсортировано по номеру.

    Часть без года в список не попадает: отсутствие года — не убывание, и
    подставлять вместо него ноль значило бы выдумать находку.
    """
    собрано: dict[str, list[tuple[int, str, int]]] = {}
    for слаг, запись in подробности.items():
        м = ХВОСТ.match(слаг)
        if not м:
            continue
        г = год(запись)
        if г is None:
            continue
        номер = int(м.group("номер"))
        if номер < 2:
            continue
        собрано.setdefault(м.group("база"), []).append((номер, слаг, г))

    # Первая часть обычно лежит под базовым слагом без номера.
    for база, части in собрано.items():
        г = год(подробности.get(база) or {})
        if г is not None:
            части.append((1, база, г))
        части.sort()
    return собрано


def падения(части: list[tuple[int, str, int]]) -> list[tuple[str, int, str, int]]:
    """[(слаг предыдущей, её год, слаг следующей, её год)] при СТРОГОМ убывании."""
    итог = []
    for (_, слаг_а, год_а), (_, слаг_б, год_б) in zip(части, части[1:],
                                                      strict=False):
        if год_б < год_а:
            итог.append((слаг_а, год_а, слаг_б, год_б))
    return итог


def одиночная_выпадающая(части: list[tuple[int, str, int]]) -> str:
    """Слаг ЕДИНСТВЕННОЙ части, удаление которой делает ряд неубывающим.

    Зачем нужен признак строже простого убывания. Простое убывание ловит и
    законные случаи, и это измерено 20.10 на animedia.icu: `berserk` 2016 →
    `berserk-2` 1997 и `brodyaga-kensin-2` 2023 → `-3` 1996 — это РЕМЕЙКИ и
    разные экранизации одной франшизы, где нумерация слагов не хронологическая.
    Объявить их ошибкой года значило бы выдать 98 находок, половина которых
    законна.

    Ошибка года в СЕЗОНЕ выглядит иначе: ряд возрастает везде, кроме одного
    элемента. Так и устроен `rukovodstvo-soten-demonov`: 2020, 2021, 2022,
    **2020**, 2025 — уберите четвёртый, и ряд неубывающий, а источник даёт
    четвёртому 2024, что ложится между 2022 и 2025.

    Условия намеренно жёсткие:

    * частей не меньше ТРЁХ. На паре удаление любого элемента делает ряд
      неубывающим тривиально, и пара ремейков прошла бы как находка;
    * выпадающий элемент ровно ОДИН. Два и больше — это не «одна неверная
      запись», а другое устройство нумерации, и разбирать его надо иначе.

    Пустая строка — находки нет.
    """
    if len(части) < 3:
        return ""
    годы = [г for _, _, г in части]
    if all(б >= а for а, б in zip(годы, годы[1:], strict=False)):
        return ""
    подходят = []
    for н in range(len(годы)):
        без = годы[:н] + годы[н + 1:]
        if all(б >= а for а, б in zip(без, без[1:], strict=False)):
            подходят.append(части[н][1])
    return подходят[0] if len(подходят) == 1 else ""


def разобрать(подробности: dict[str, dict]) -> dict:
    собрано = франшизы(подробности)
    измеримые = {б: ч for б, ч in собрано.items() if len(ч) >= 2}
    находки = []
    строгие = []
    for база, части in sorted(измеримые.items()):
        пад = падения(части)
        for падение in пад:
            находки.append({
                "база": база,
                "было": {"slug": падение[0], "year": падение[1]},
                "стало": {"slug": падение[2], "year": падение[3]},
                "ряд": [{"slug": с, "year": г} for _, с, г in части],
            })
        выпадает = одиночная_выпадающая(части)
        if выпадает:
            год_выпадающей = next(г for _, с, г in части if с == выпадает)
            первая_слаг, первая_год = части[0][1], части[0][2]
            # Названная причина, а не просто «год не на месте». Измерено 20.10:
            # у шести кандидатов из четырнадцати год выпадающей части РАВЕН
            # году ПЕРВОЙ части франшизы, и среди этих шести —
            # `rukovodstvo-soten-demonov-4`, неверность которого подтверждена
            # источником независимо (aired_on 2024-02-23 против снимковых
            # 2020). То есть сезону проставлен год франшизы.
            год_франшизы = (год_выпадающей == первая_год
                            and выпадает != первая_слаг)
            строгие.append({
                "база": база,
                "выпадает": выпадает,
                "год": год_выпадающей,
                "ряд": [{"slug": с, "year": г} for _, с, г in части],
                "ожидаемый диапазон": _диапазон(части, выпадает),
                "частей": len(части),
                "год первой части": первая_год,
                "это год франшизы": год_франшизы,
            })
    return {
        "записей в снимке": len(подробности),
        "франшиз с нумерованными частями": len(собрано),
        "франшиз измеримо (две части и больше с годом)": len(измеримые),
        "франшиз с падением года": len({н["база"] for н in находки}),
        "падений": len(находки),
        "строгих кандидатов": len(строгие),
        "из них год франшизы на сезоне": sum(
            1 for с in строгие if с["это год франшизы"]),
        "находки": находки,
        "строгие": строгие,
    }


def _диапазон(части: list[tuple[int, str, int]], слаг: str) -> str:
    """Между какими годами должен лежать год выпадающей части."""
    номера = list(части)
    место = next(и for и, (_, с, _) in enumerate(номера) if с == слаг)
    до = номера[место - 1][2] if место > 0 else None
    после = номера[место + 1][2] if место + 1 < len(номера) else None
    if до is not None and после is not None:
        return f"{до}…{после}"
    return f"не раньше {до}" if до is not None else f"не позже {после}"


def напечатать(итог: dict) -> None:
    for ключ in ("записей в снимке", "франшиз с нумерованными частями",
                 "франшиз измеримо (две части и больше с годом)",
                 "франшиз с падением года", "падений", "строгих кандидатов",
                 "из них год франшизы на сезоне"):
        print(f"{ключ}: {итог[ключ]}")

    print("\nПРОСТОЕ УБЫВАНИЕ ГОДОМ НЕ ОШИБКА САМО ПО СЕБЕ. Измерено 20.10:"
          " среди падений лежат\n   `berserk` 2016 → `berserk-2` 1997 и"
          " `brodyaga-kensin-2` 2023 → `-3` 1996 — это РЕМЕЙКИ и разные\n"
          "   экранизации одной франшизы, где нумерация слагов не"
          " хронологическая. Поэтому\n   число падений кандидатом на правку"
          " НЕ является.")

    print("\nстрогие кандидаты (частей ≥ 3, выпадает ровно одна):")
    for н in итог["строгие"][:ПРИМЕРОВ]:
        ряд = ", ".join(f"{з['slug']}:{з['year']}" for з in н["ряд"])
        метка = ("  ← это год ПЕРВОЙ части франшизы"
                 if н["это год франшизы"] else "")
        print(f"  {н['выпадает']}: год {н['год']},"
              f" ожидается {н['ожидаемый диапазон']}{метка}")
        print(f"     ряд: {ряд}")
    if len(итог["строгие"]) > ПРИМЕРОВ:
        print(f"  … и ещё {len(итог['строгие']) - ПРИМЕРОВ}")

    print("\nчто этот перечень НЕ означает:")
    print("   — что каждая строка — ошибка. Это КАНДИДАТЫ: признак внутренний,"
          " и подтвердить его может только сверка с источником;")
    print("   — всю долю ошибок каталога: франшиза, где ВСЕ части несут один"
          " неверный год, этим признаком не видна. Это НИЖНЯЯ ГРАНИЦА;")
    print("   — сверить кандидатов с источником сейчас нечем: в записях снимка"
          " нет `shikimori_id` (там `provider: mali`), а выдумывать поиск"
          " запрещено (D199). Это та же нехватка, что названа в приёмке"
          " MOD-102.")


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("снимок")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    итог = разобрать(записи(Path(а.снимок)))
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
    else:
        напечатать(итог)
    return 1 if итог["падений"] else 0


if __name__ == "__main__":
    sys.exit(главное())
