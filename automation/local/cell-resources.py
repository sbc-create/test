#!/usr/bin/env python3
"""Пределы памяти и процессов у живых витрин: что объявлено и что исполняется.

Повод. Ночной цикл требует назвать пределы памяти и процессов, и соблазн — взять
круглое число. Круглое число здесь вредно: витрины читают снимки каталога, и
предел ниже рабочего размера превратит защиту хоста в падение витрины. Поэтому
инструмент сначала ИЗМЕРЯЕТ, а потом сравнивает с объявленным.

Каждый столбец из своего источника, ни один не выводится из другого:

* состав витрин, юнит и учётная запись — реестр ячеек `config/site-cells.json`;
* объявленные пределы — поле `resources` той же записи;
* ИСПОЛНЯЕМЫЕ пределы — файл юнита и его drop-in'ы в
  `/etc/systemd/system/<юнит>.d/*.conf` (последнее присваивание побеждает,
  как и у systemd);
* фактический расход — `/proc/<pid>/status` процессов, чей cgroup называет
  этот юнит; `systemctl` в профиле сессии недоступен, а cgroup процесса
  говорит о принадлежности точнее, чем совпадение имени в командной строке;
* ёмкость хоста — `/proc/meminfo`.

Различие «не задан» и «не измерено» держится всюду: отсутствующий предел — это
факт о юните, а нечитаемый юнит — факт о сессии, и путать их нельзя.

Только чтение.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1].parent
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ЮНИТЫ = Path("/etc/systemd/system")

#: Директивы, которые решают судьбу хоста при утечке в одной витрине.
ПРЕДЕЛЫ = ("MemoryMax", "MemoryHigh", "TasksMax", "CPUQuota", "LimitNPROC")
#: Поведение после гибели: без них OOM-kill уводит витрину в цикл перезапуска.
ПОСЛЕ_ГИБЕЛИ = ("Restart", "RestartSec", "StartLimitBurst",
                "StartLimitIntervalSec", "OOMPolicy")

НЕ_ИЗМЕРЕНО = "не измерено"
НЕ_ЗАДАН = "не задан"
МЕТКА_НЕЧИТАЕМОГО = "#НЕЧИТАЕМЫЙ-DROPIN"


def ячейки(путь: Path) -> list[dict]:
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        print(f"реестр ячеек не прочитан ({путь}): {сбой}", file=sys.stderr)
        return []
    return документ.get("cells") or []


def строки_юнита(юнит: str) -> list[str] | None:
    """Файл юнита плюс drop-in'ы по порядку, как их читает systemd.

    None означает «не измерено»: файла нет или он не читается. Нечитаемый
    drop-in не пропускается молча — он помечается в выдаче, потому что
    именно drop-in способен СНЯТЬ предел, и тогда отчёт назвал бы предел
    исполняемым зря.
    """
    основной = ЮНИТЫ / юнит
    куски: list[str] = []
    try:
        куски.extend(основной.read_text(encoding="utf-8",
                                        errors="replace").splitlines())
    except OSError:
        return None
    каталог = ЮНИТЫ / f"{юнит}.d"
    if каталог.is_dir():
        for конф in sorted(каталог.glob("*.conf")):
            try:
                куски.extend(конф.read_text(encoding="utf-8",
                                            errors="replace").splitlines())
            except OSError:
                куски.append(f"{МЕТКА_НЕЧИТАЕМОГО} {конф.name}")
    return куски


def директивы(строки: list[str] | None, имена) -> dict[str, str]:
    """Последнее присваивание побеждает — как у systemd.

    Пустое значение (`Имя=`) у systemd СБРАСЫВАЕТ прежнее, и инструмент
    повторяет это поведение: иначе drop-in, снимающий предел, читался бы как
    предел на месте. Так уже сделано для site-factory-mcp.service, где
    `ExecStart=` пустой строкой снимает прежнюю команду.
    """
    if строки is None:
        return {и: НЕ_ИЗМЕРЕНО for и in имена}
    есть_нечитаемый = any(с.startswith(МЕТКА_НЕЧИТАЕМОГО) for с in строки)
    итог: dict[str, str] = {}
    for сырая in строки:
        строка = сырая.strip()
        if not строка or строка.startswith(("#", ";")):
            continue
        for имя in имена:
            совпало = re.fullmatch(rf"{имя}\s*=\s*(.*)", строка)
            if совпало:
                значение = совпало.group(1).strip()
                if значение:
                    итог[имя] = значение
                else:
                    итог.pop(имя, None)
    по_умолчанию = НЕ_ИЗМЕРЕНО if есть_нечитаемый else НЕ_ЗАДАН
    return {и: итог.get(и, по_умолчанию) for и in имена}


def _юнит_из_cgroup(содержимое: str) -> str:
    """Имя юнита из `/proc/<pid>/cgroup`: последний отрезок пути.

    Сравнение подстрокой здесь ошибочно, и ошибка не теоретическая: рядом с
    `nova-lordserials22-space.service` живёт
    `nova-lordserials22-space-candidate.service`, и подстрока спутала бы
    кандидата с действующей витриной — то есть приписала бы живой витрине
    расход чужого процесса.
    """
    for строка in содержимое.splitlines():
        путь = строка.rsplit(":", 1)[-1].strip()
        if путь.endswith(".service") or путь.endswith(".scope"):
            return путь.rsplit("/", 1)[-1]
    return ""


def процессы_юнита(юнит: str) -> list[tuple[int, int]]:
    """[(pid, RSS в килобайтах)] для процессов, чей cgroup называет юнит.

    Имя в командной строке для этого не годится: у витрин один и тот же
    `run.py`, а общий загрузчик обслуживает несколько доменов сразу. RSS
    равный -1 означает, что процесс есть, а его `status` не прочитался.
    """
    найдено: list[tuple[int, int]] = []
    for запись in Path("/proc").iterdir():
        if not запись.name.isdigit():
            continue
        try:
            cgroup = (запись / "cgroup").read_text(encoding="utf-8",
                                                   errors="replace")
        except OSError:
            continue
        if _юнит_из_cgroup(cgroup) != юнит:
            continue
        rss = -1
        try:
            for строка in (запись / "status").read_text(
                    encoding="utf-8", errors="replace").splitlines():
                if строка.startswith("VmRSS:"):
                    rss = int(строка.split()[1])
                    break
            else:
                rss = 0          # ядерный поток: VmRSS отсутствует по делу
        except (OSError, ValueError, IndexError):
            rss = -1
        найдено.append((int(запись.name), rss))
    return sorted(найдено)


def cgroup_юнита(юнит: str) -> dict[str, object]:
    """Что ядро РЕАЛЬНО применяет к юниту, а не что написано в файле.

    Файл юнита — объявление; cgroup — исполнение. Расхождение возможно:
    директиву могли добавить без `daemon-reload`, и тогда предел «есть» в
    файле и отсутствует в ядре. Поэтому столбцы разные и не выводятся друг
    из друга.

    `oom_kill` у юнита СБРАСЫВАЕТСЯ при его перезапуске, и это свойство
    счётчика, а не факт о витрине: ноль здесь означает «с момента текущего
    запуска», а не «никогда». Возраст процесса печатается рядом именно
    затем, чтобы ноль нельзя было прочесть как «не случалось».
    """
    корень = Path("/sys/fs/cgroup/system.slice") / юнит
    итог: dict[str, object] = {"прочитан": False, "max": НЕ_ИЗМЕРЕНО,
                               "текущая_кб": -1, "oom_kill": -1,
                               "oom": -1, "high": -1}
    try:
        итог["max"] = (корень / "memory.max").read_text(
            encoding="utf-8").strip()
        итог["текущая_кб"] = int(
            (корень / "memory.current").read_text(encoding="utf-8")) // 1024
        события = dict(
            с.split() for с in (корень / "memory.events").read_text(
                encoding="utf-8").splitlines() if len(с.split()) == 2)
        итог["oom_kill"] = int(события.get("oom_kill", -1))
        итог["oom"] = int(события.get("oom", -1))
        итог["high"] = int(события.get("high", -1))
        итог["прочитан"] = True
    except (OSError, ValueError):
        pass
    return итог


def возраст_процесса(pid: int) -> float:
    """Секунды с запуска процесса; -1, если не измерено.

    Нужен рядом с `oom_kill`: счётчик обнуляется перезапуском, и без возраста
    ноль говорит только о том, что процесс недавно поднят.
    """
    try:
        аптайм = float(Path("/proc/uptime").read_text().split()[0])
        хвост = Path(f"/proc/{pid}/stat").read_text(encoding="utf-8")
        поля = хвост.rsplit(") ", 1)[1].split()
        тиков = float(поля[19])
    except (OSError, ValueError, IndexError):
        return -1.0
    гц = os.sysconf("SC_CLK_TCK") or 100
    return аптайм - тиков / гц


def память_хоста() -> dict[str, int]:
    итог: dict[str, int] = {}
    try:
        for строка in Path("/proc/meminfo").read_text(
                encoding="utf-8").splitlines():
            ключ, _, остальное = строка.partition(":")
            части = остальное.split()
            if части and части[0].isdigit():
                итог[ключ] = int(части[0])
    except OSError:
        pass
    return итог


def мегабайты(килобайты: int) -> str:
    return f"{килобайты / 1024:.0f}М"


def собрать(записи: list[dict]) -> list[dict]:
    итог = []
    for ячейка in записи:
        runtime = ячейка.get("runtime") or {}
        юнит = runtime.get("unit") or ""
        строки = строки_юнита(юнит) if юнит else None
        процессы = процессы_юнита(юнит) if юнит else []
        rss = sum(р for _p, р in процессы if р > 0)
        объявлено = ячейка.get("resources") or {}
        ядро = cgroup_юнита(юнит) if юнит else {"прочитан": False}
        возраст = (возраст_процесса(процессы[0][0]) if процессы else -1.0)
        итог.append({
            "cgroup": ядро,
            "возраст_с": возраст,
            "site_id": ячейка.get("site_id", "?"),
            "домен": ячейка.get("domain") or "—",
            "статус": ячейка.get("status") or "—",
            "юнит": юнит or "—",
            "юнит_прочитан": строки is not None,
            "объявлено": объявлено,
            "пределы": директивы(строки, ПРЕДЕЛЫ),
            "после_гибели": директивы(строки, ПОСЛЕ_ГИБЕЛИ),
            "процессов": len(процессы),
            "rss_кб": rss if процессы else -1,
        })
    return итог


def разбор(аргв=None):
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--registry", type=Path, default=РЕЕСТР,
                   help="реестр ячеек (по умолчанию config/site-cells.json)")
    р.add_argument("--json", action="store_true", help="вывод машиной")
    return р.parse_args(аргв)


def главное(аргв=None) -> int:
    опции = разбор(аргв)
    записи = ячейки(опции.registry)
    if not записи:
        return 2
    строки = собрать(записи)
    мем = память_хоста()

    if опции.json:
        print(json.dumps({"ячейки": строки, "meminfo": мем},
                         ensure_ascii=False, indent=2))
        return 0

    всего = мем.get("MemTotal", 0)
    print(f"хост: всего {мегабайты(всего)}, "
          f"доступно {мегабайты(мем.get('MemAvailable', 0))}"
          if всего else f"хост: память {НЕ_ИЗМЕРЕНО}")
    print()
    print(f"{'site_id':16} {'домен':22} {'RSS':>7} {'в ядре':>8} "
          f"{'MemoryMax':>10} {'ядро max':>9} {'oom':>5} {'возраст':>8}")
    живых = 0
    без_предела: list[str] = []
    расходится: list[str] = []
    сумма = 0
    for с in строки:
        ядро = с["cgroup"]
        if не_измерено(с):
            жив, rss = "—", НЕ_ИЗМЕРЕНО
        elif с["процессов"] == 0:
            жив, rss = "нет", "—"
        else:
            живых += 1
            сумма += max(с["rss_кб"], 0)
            жив, rss = str(с["процессов"]), мегабайты(с["rss_кб"])
        if без_предела_памяти(с):
            без_предела.append(с["домен"])
        if объявлено_но_не_применено(с):
            расходится.append(с["домен"])
        в_ядре = (мегабайты(int(ядро["текущая_кб"]))
                  if ядро.get("прочитан") else "—")
        предел_ядра = str(ядро.get("max", "—")) if ядро.get("прочитан") else "—"
        oom = (str(ядро["oom_kill"]) if ядро.get("прочитан")
               and int(ядро["oom_kill"]) >= 0 else "—")
        возраст = (f"{с['возраст_с'] / 86400:.1f}сут"
                   if с["возраст_с"] >= 0 else "—")
        print(f"{с['site_id']:16} {с['домен']:22} {rss:>7} {в_ядре:>8} "
              f"{с['пределы']['MemoryMax']:>10} {предел_ядра:>9} "
              f"{oom:>5} {возраст:>8}")

    print()
    доля = f" — это {сумма * 100 / всего:.1f}% памяти хоста" if всего else ""
    print(f"живых процессов витрин: {живых}; их RSS в сумме "
          f"{мегабайты(сумма)}{доля}")
    print("столбец oom читается только вместе с возрастом: счётчик юнита "
          "обнуляется его перезапуском, и ноль у витрины, поднятой часы "
          "назад, означает «с момента запуска», а не «никогда».")
    if расходится:
        print(f"\nОБЪЯВЛЕНО, НО ЯДРО НЕ ПРИМЕНЯЕТ: {len(расходится)} — "
              + ", ".join(расходится)
              + "\nПредел в файле юнита без daemon-reload не исполняется; "
                "это и есть случай, когда отчёт сказал бы «предел есть».")
    if без_предела:
        print(f"\nБЕЗ предела памяти при живом процессе: {len(без_предела)} — "
              + ", ".join(без_предела))
        print("Следствие названо прямо: утечка в ОДНОЙ витрине расходует общую "
              "память, и первым умрёт не виновник, а тот, кто попросит "
              "страницу следующим. Предел нужен не круглый, а выведенный из "
              "замера выше.")
    объявленные = [с for с in строки if с["объявлено"]]
    print(f"\nячеек с НЕПУСТЫМ полем resources в реестре: "
          f"{len(объявленные)} из {len(строки)}")
    return 0


def не_измерено(запись: dict) -> bool:
    """Юнит не прочитан — факт о сессии, а не о витрине."""
    return not запись["юнит_прочитан"]


def без_предела_памяти(запись: dict) -> bool:
    """Витрина жива, а предела памяти нет НИ в юните, НИ в ядре.

    Отдельной функцией затем, что это и есть проверяемый инвариант: ни
    «не измерено», ни мёртвый процесс поводом для тревоги не являются.
    Требуются оба источника: предел, который ядро применяет, защищает хост
    и без строки в файле, а строка без применения не защищает ничего.
    """
    ядро = запись["cgroup"]
    ядро_без_предела = (not ядро.get("прочитан")
                        or str(ядро.get("max")) == "max")
    return (запись["процессов"] > 0
            and запись["юнит_прочитан"]
            and запись["пределы"]["MemoryMax"] == НЕ_ЗАДАН
            and ядро_без_предела)


def объявлено_но_не_применено(запись: dict) -> bool:
    """Предел назван в юните, а ядро держит `max` — защита мнимая."""
    ядро = запись["cgroup"]
    return (запись["процессов"] > 0
            and запись["пределы"]["MemoryMax"] not in (НЕ_ЗАДАН, НЕ_ИЗМЕРЕНО)
            and bool(ядро.get("прочитан"))
            and str(ядро.get("max")) == "max")


if __name__ == "__main__":
    raise SystemExit(главное())
