#!/usr/bin/env python3
"""Целы ли редакционные правки витрин: кто писал последним и какие поля живы.

Повод. 2026-10-11 прогон редактора перезаписал
`/srv/zonafilm-space/data/editorial-overrides.json` одними описаниями, и
внесённое название (решение D200) исчезло — страница вернулась к оригиналу.
Причина: правка «состав файла собирается из ЖИВОГО файла плюс свои описания» в
службу MCP не установлена, а старый код собирает файл целиком из своих полей.

Пока правка не установлена, файлы надо проверять, а не надеяться. Инструмент
только читает: показывает время записи, схему, число правок, набор полей и
авторов — и отдельно называет файлы, где НЕТ ни одного поля кроме описаний,
хотя раньше были другие.

    python3 automation/local/editorial-overrides-audit.py
    python3 automation/local/editorial-overrides-audit.py --json
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

КОРНИ = Path("/srv")
#: Поля, которые ведёт не редактор: их исчезновение и есть потеря.
НЕ_ОПИСАНИЕ = ("name", "original_name", "poster_url", "year", "kind")


РЕЕСТР_ЗАЩИЩЁННЫХ = (Path(__file__).resolve().parents[2]
                     / "config" / "editorial-protected-fields.json")


def защищённые() -> dict:
    """Поля, исчезновение которых считается потерей. Реестр ведётся вручную.

    Нужен потому, что по одному файлу правок потерю не отличить от «такого
    поля тут и не было»: в обоих случаях поля просто нет. Реестр называет, что
    вносилось решением, — и тогда отсутствие становится измеримым фактом.
    """
    try:
        документ = json.loads(РЕЕСТР_ЗАЩИЩЁННЫХ.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return документ.get("sites") or {}


def сверить_с_реестром(найдено: list[dict]) -> list[dict]:
    """Какие защищённые поля пропали. Пустой список — все на месте."""
    реестр = защищённые()
    по_домену = {}
    for и in найдено:
        # Имя витрины в пути — с дефисами вместо точек; домен берём из реестра
        # и сверяем по вхождению, иначе пришлось бы держать второе отображение.
        по_домену[и["витрина"]] = и
    потери = []
    for домен, правило in реестр.items():
        ключ = домен.replace(".", "-")
        подходящие = [и for имя, и in по_домену.items()
                      if имя == ключ or имя.endswith(ключ)]
        if not подходящие:
            потери.append({"домен": домен, "почему": "файла правок не нашлось"})
            continue
        и = подходящие[0]
        пропали = [п for п in правило.get("fields", []) if п not in и.get("поля", [])]
        if пропали:
            потери.append({"домен": домен, "пропали": пропали,
                           "решение": правило.get("decision"),
                           "изменён": и.get("изменён")})
    return потери


def вне_реестра(найдено: list[dict]) -> list[dict]:
    """Живые поля, которых реестр не знает. Обратная сторона сверки.

    Реестр отвечает на вопрос «пропало ли внесённое решением». Обратного
    вопроса — «появилось ли внесённое решением, чего реестр не знает» — он не
    закрывает, а именно так дефект и возник бы снова: поле вносится решением,
    в реестр его не кладут, публикация описания его затирает, и никто не
    узнаёт, потому что защищать было нечего.

    Описания здесь не считаются: их пишет сам издатель, и для них реестр не
    нужен. Всё остальное в живом файле — ручной ввод, и ему место в реестре.

    Проверено по передаче 114: на 11.10 во всей сети такое поле одно —
    `name` у `zonafilm.space` (решение D200), и оно в реестре. То есть реестр
    полон на сегодня; эта проверка сторожит завтрашнее пополнение.
    """
    реестр = защищённые()
    известно = {}
    for домен, правило in реестр.items():
        известно[домен.replace(".", "-")] = set(правило.get("fields") or [])
    незащищённые = []
    for и in найдено:
        имя = и["витрина"]
        знакомые = set()
        for ключ, поля in известно.items():
            if имя == ключ or имя.endswith(ключ):
                знакомые = поля
                break
        свои = {п for п in (и.get("поля") or []) if п != "description"}
        лишние = sorted(свои - знакомые)
        if лишние:
            незащищённые.append({"витрина": имя, "поля": лишние,
                                 "изменён": и.get("изменён")})
    return незащищённые


def файлы() -> list[Path]:
    return sorted(КОРНИ.glob("*/data/editorial-overrides.json"))


def разобрать(путь: Path) -> dict:
    с = путь.stat()
    итог = {
        "файл": str(путь),
        "витрина": путь.parent.parent.name,
        "изменён": dt.datetime.fromtimestamp(
            с.st_mtime, dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "байт": с.st_size,
    }
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        итог["ошибка"] = str(сбой)[:120]
        return итог
    итог["схема"] = документ.get("schema_version", "—")
    правки = документ.get("overrides")
    if правки is None:
        # Прежняя раскладка: правки лежали на верхнем уровне по ключу записи.
        правки = {к: v for к, v in документ.items()
                  if isinstance(v, dict) and ("fields" in v or "name" in v)}
    итог["правок"] = len(правки)
    поля: set[str] = set()
    авторы: set[str] = set()
    for з in правки.values():
        названные = з.get("fields")
        # `fields` встречается и списком имён, и словарём «имя → значение»:
        # первая версия разбора брала его за имя поля и печатала «fields»
        # вместо состава. Разбираются оба вида, иначе мера молчит о том, что
        # ищет.
        if isinstance(названные, dict):
            поля.update(названные)
        elif isinstance(названные, (list, tuple)):
            поля.update(названные)
        else:
            поля.update(к for к in з if к not in ("actor", "reason", "at"))
        if з.get("actor"):
            авторы.add(str(з["actor"]))
    итог["поля"] = sorted(поля)
    итог["авторы"] = sorted(авторы)
    итог["только_описания"] = bool(поля) and поля <= {"description"}
    итог["есть_чужие_поля"] = sorted(п for п in поля if п in НЕ_ОПИСАНИЕ)
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="целость редакционных правок")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    найдено = [разобрать(п) for п in файлы()]
    if not найдено:
        print("файлов правок не найдено", file=sys.stderr)
        return 2
    if а.json:
        print(json.dumps(найдено, ensure_ascii=False, indent=2))
        return 0
    print(f"{'витрина':22} {'изменён':22} {'правок':>7} {'схема':>7}  поля")
    только_описания = []
    for и in найдено:
        if "ошибка" in и:
            print(f"{и['витрина']:22} НЕ ПРОЧИТАН: {и['ошибка']}")
            continue
        print(f"{и['витрина']:22} {и['изменён']:22} {и['правок']:>7} "
              f"{str(и['схема']):>7}  {', '.join(и['поля']) or '—'}")
        if и["только_описания"]:
            только_описания.append(и["витрина"])
    print(f"\nфайлов: {len(найдено)}; только описания: {len(только_описания)}")
    if только_описания:
        print("   " + " ".join(только_описания))
        print("   Это НЕ доказательство потери: у витрины могло не быть других")
        print("   полей. Доказательство — сравнение с тем, что вносилось:")
        print("   передачи 114/115/116 и журналы накладок.")
    for и in найдено:
        if и.get("есть_чужие_поля"):
            print(f"   {и['витрина']}: поля не редактора на месте — "
                  f"{', '.join(и['есть_чужие_поля'])}")
    # Обратная сверка — раньше потерь: незащищённое поле это будущая потеря,
    # и узнать о ней надо до того, как публикация описания его затрёт.
    незащищённые = вне_реестра(найдено)
    if незащищённые:
        print("\nПОЛЯ ВНЕ РЕЕСТРА — защищать нечем:")
        for н in незащищённые:
            print(f"   {н['витрина']}: {', '.join(н['поля'])} "
                  f"(файл изменён {н['изменён']})")
        print("   Это ручной ввод, которого реестр не знает: публикация")
        print("   описания затрёт его молча, как случилось с name у")
        print("   zonafilm.space 11.10. Внесите поле и решение в")
        print("   config/editorial-protected-fields.json.")

    потери = сверить_с_реестром(найдено)
    if потери:
        print("\nПОТЕРЯ защищённых полей (реестр config/"
              "editorial-protected-fields.json):")
        for п in потери:
            if "пропали" in п:
                print(f"   {п['домен']}: пропало {', '.join(п['пропали'])} "
                      f"(решение {п['решение']}), файл изменён {п['изменён']}")
            else:
                print(f"   {п['домен']}: {п['почему']}")
        print("   Восстановление: automation/local/editorial-field-write.py")
        return 1
    if защищённые():
        print(f"\nзащищённые поля на месте: "
              f"{', '.join(sorted(защищённые()))}")
    # Незащищённое поле — ненулевой код: иначе о пробеле узнают после потери.
    # Код 3 отличает его от потери (1) и от отсутствия файлов (2): это разные
    # положения и разные действия.
    return 3 if незащищённые else 0


if __name__ == "__main__":
    sys.exit(главное())
