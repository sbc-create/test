#!/usr/bin/env python3
"""Запрет служебных путей у витрин AnimeGo — в самой витрине, а не только в nginx.

Что измерено и почему это дефект
--------------------------------

2026-10-05, сразу после открытия an1mego.site и animeg0.site штатной
операцией:

    GET https://an1mego.site/healthz
      X-Robots-Tag: index, follow          <- витрина
      X-Robots-Tag: noindex, nofollow      <- слой nginx

То же на `/api/` и `/poster/`, и то же у УЖЕ ОТКРЫТОГО соседа `an1meg0.site` —
то есть дефект семейный, а не следствие этого открытия. Пока домен был закрыт,
противоречия не было: витрина отдавала `noindex, nofollow` на всех путях, и
открытие его обнажило.

Фактически путь закрыт: обходчик разрешает такую пару по более строгому
значению, и все эти пути вдобавок стоят в `Disallow` у `robots.txt`. Но
противоречивая пара на производственном ответе — дефект, а не особенность, и
держать запрет служебных путей в одном слое из двух нельзя: слой nginx
принадлежит ХОСТУ (`/etc/nginx/cells/<site_id>.robots`), а эти пути — ВИТРИНЕ.
Переезд витрины на другой хост увёз бы запрет с собой, если он в витрине, и
оставил бы его позади, если он только в nginx.

Что делает инструмент

1. заводит `СЛУЖЕБНЫЕ_ПУТИ` и `мета_роботов_пути(путь)` рядом с
   `мета_роботов()` — перечень тот же, что у слоя nginx и у `robots.txt`
   витрины: три места об одном;
2. переводит ЕДИНСТВЕННУЮ отдачу заголовка на `мета_роботов_пути(self.path)`.

Чего инструмент НЕ делает: не трогает `<meta name="robots">` страниц —
служебные пути HTML-страниц не отдают вовсе; и не трогает ЗАШИТЫЙ запрет в
ветви постера (D180) — он обязан остаться при любом режиме.

Правка требует РОВНО ОДНОГО совпадения каждого якоря и отказывается целиком,
если состав изменился: наполовину применённая правка хуже отсутствующей.

    python3 automation/local/wire-animego-service-robots.py            # проверка
    python3 automation/local/wire-animego-service-robots.py --apply    # запись
"""
from __future__ import annotations

import argparse
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕПОЗИТОРИИ = ("an1mego-site", "animeg0-site", "an1meg0-site")
ТОЧКА = "src/animego-frontend.py"

ЯКОРЬ_ВСТАВКИ = "def _тело_robots() -> str:"
ЯКОРЬ_ЗАГОЛОВКА = '        self.send_header("X-Robots-Tag", мета_роботов())'
НОВЫЙ_ЗАГОЛОВОК = ('        self.send_header("X-Robots-Tag", '
                   'мета_роботов_пути(self.path or "/"))')
ПРИЗНАК_ГОТОВО = "def мета_роботов_пути("

ВСТАВКА = '''#: СЛУЖЕБНЫЕ ПУТИ. Запрет на них от режима НЕ зависит и режимом не снимается.
#:
#: Перечень тот же, что у слоя nginx (`/etc/nginx/cells/<site_id>.robots`) и
#: тот же, что у `robots.txt` этой витрины: три места об одном, и расхождение
#: между ними означало бы, что домен закрыт не везде.
СЛУЖЕБНЫЕ_ПУТИ = ("/poster/", "/api/", "/healthz", "/__", "/.well-known/")


def мета_роботов_пути(путь: str) -> str:
    """Значение `X-Robots-Tag` ДЛЯ ЭТОГО пути.

    Измерено 2026-10-05 сразу после открытия an1mego.site: ответ `/healthz`
    несёт ДВА заголовка — `index, follow` от витрины и `noindex, nofollow` от
    слоя nginx. Пока домен был закрыт, противоречия не было, и открытие его
    обнажило. Фактически путь закрыт: обходчик разрешает такую пару по более
    строгому значению, и эти пути вдобавок стоят в `Disallow`. Но
    противоречивая пара на производственном ответе — дефект, а не
    особенность, и держать запрет служебных путей в одном слое из двух нельзя:
    слой nginx принадлежит хосту, а эти пути — витрине.

    Строка запроса не мешает: сравнение идёт по НАЧАЛУ пути.
    """
    п = путь or "/"
    if any(п.startswith(с) for с in СЛУЖЕБНЫЕ_ПУТИ):
        return "noindex, nofollow"
    return мета_роботов()


'''


def разобрать(текст: str, где: str) -> list[str]:
    """Беды правки. Пусто — правка применима; непусто — отказ целиком."""
    беды = []
    if ПРИЗНАК_ГОТОВО in текст:
        return ["уже подключено"]
    for якорь, имя in ((ЯКОРЬ_ВСТАВКИ, "место вставки"),
                       (ЯКОРЬ_ЗАГОЛОВКА, "отдача заголовка")):
        сколько = текст.count(якорь)
        if сколько != 1:
            беды.append(f"{где}: {имя} встречается {сколько} раз, а не один")
    return беды


def применить(текст: str) -> str:
    текст = текст.replace(ЯКОРЬ_ВСТАВКИ, ВСТАВКА + ЯКОРЬ_ВСТАВКИ, 1)
    return текст.replace(ЯКОРЬ_ЗАГОЛОВКА, НОВЫЙ_ЗАГОЛОВОК, 1)


def главная(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--apply", action="store_true",
                   help="записать правку; без него только проверка")
    args = p.parse_args(argv)

    планы: list[tuple[pathlib.Path, str]] = []
    отказы: list[str] = []
    готовы: list[str] = []
    for имя in РЕПОЗИТОРИИ:
        файл = КОРЕНЬ / "var" / "site-repos" / имя / ТОЧКА
        if not файл.is_file():
            отказы.append(f"{имя}: нет {файл}")
            continue
        текст = файл.read_text(encoding="utf-8")
        беды = разобрать(текст, имя)
        if беды == ["уже подключено"]:
            готовы.append(имя)
            continue
        if беды:
            отказы.extend(беды)
            continue
        планы.append((файл, применить(текст)))

    for имя in готовы:
        print(f"  {имя}: уже подключено")
    for беда in отказы:
        print(f"  ОТКАЗ {беда}", file=sys.stderr)
    if отказы:
        print("правка не применена ни к одному файлу: состав якорей изменился",
              file=sys.stderr)
        return 2
    if not args.apply:
        for файл, _ in планы:
            print(f"  применимо: {файл}")
        return 0
    # ПАКЕТНАЯ ЗАПИСЬ. Проверены все файлы, потом записаны все: иначе отказ на
    # третьем оставил бы два сайта семейства правленными, а третий нет (D164).
    for файл, новый in планы:
        файл.write_text(новый, encoding="utf-8")
        print(f"  записано: {файл}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная())
