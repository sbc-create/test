#!/usr/bin/env python3
"""Донёс ли суточный издатель каталог до витрин — и если нет, почему. Только чтение.

Зачем инструмент. Суточный прогон (`nova-daily-refresh`, 03:30 UTC) пишет
результат в `var/lords/daily-state/last-publish.json`, и ЭТОТ ФАЙЛ НЕ ЧИТАЕТ
НИКТО: 23.10 в нём вместо отчёта лежал traceback с `[Errno 28] No space left
on device`, тринадцать витрин остались на каталоге от 22.10, и обнаружилось
это случайно, при разборе другой задачи. Успешный ответ витрины ничего не
говорит о свежести её каталога — витрина с данными двухдневной давности
отвечает 200 так же бодро.

Четыре различимых исхода, потому что действия у них разные:

  ИСПРАВНО         отчёт прогона разбирается, и файлы витрин не старше прогона;
  ПРОГОН УПАЛ      вместо отчёта traceback или ошибка — называется её класс,
                   и ENOSPC называется отдельно: у него причина снаружи кода;
  ПРОГОН ПРОШЁЛ,   отчёт есть, а файлы витрин старше прогона — это НЕ то же
  ВИТРИНЫ СТАРЫЕ   самое, и лечится не местом, а разбором издателя;
  НЕ ИЗМЕРЕНО      каталога состояния, файла или прав нет — с причиной.
                   Это не «исправно» и не «упал».

Чего инструмент НЕ делает, и это важнее того, что делает:

* не судит о СОДЕРЖИМОМ каталога — только о времени файла и об отчёте прогона;
  полноту данных проверяет `automation/local/k2-freshness.py` (витрины K2) и
  `automation/local/sitemap-demand-coverage.py` (покрытие адресов);
* не проверяет витрины Yummy: у них свой конвейер и свои файлы (23.10 он
  работал, когда этот падал, — поэтому их нельзя считать вместе);
* ничего не удаляет и не переписывает. Каталог копий и обрезанные файлы —
  чтение; владение ими описано в `docs/RUNTIME_DATA_OWNERSHIP.md`.

    python3 automation/local/daily-publish-health.py
    python3 automation/local/daily-publish-health.py --state … --frontend … --json

Коды: 0 — исправно; 1 — прогон упал или витрины старые; 2 — не измерено.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
import shutil
import sys

СОСТОЯНИЕ = pathlib.Path("/srv/site-factory/repo/var/lords/daily-state")
ВИТРИНЫ = pathlib.Path("/srv/lords/.frontend")
КОПИИ = pathlib.Path("/srv/site-factory/repo/var/lords/publish-backups")

#: Какие витрины принадлежат ЭТОМУ издателю, определяется по его собственным
#: копиям, а не по содержимому каталога витрин. Причина измеренная: в
#: `/srv/lords/.frontend` лежат файлы и соседних таймеров — 23.10 первая
#: редакция насчитала 14 витрин, включив `animego-04`, который этот издатель
#: не публикует (его `…-schedule.json` и `…-episode-events.json` пишет другой
#: таймер, и в `publish-backups` его копий нет вовсе). Своё от чужого отличают
#: копии: издатель снимает копию ровно того, что собирается перезаписать.
ЧУЖИЕ = re.compile(r"^yummy")

#: Метка прогона в имени копии: `…before.daily-20261023T033423Z`.
МЕТКА = re.compile(r"\.before\.daily-(\d{8})T(\d{6})Z$")


def _время(путь: pathlib.Path) -> dt.datetime:
    return dt.datetime.fromtimestamp(путь.stat().st_mtime, dt.timezone.utc)


def разбор_отчёта(путь: pathlib.Path) -> tuple[str, str]:
    """(исход, пояснение) по содержимому `last-publish.json`.

    Отчёт — это JSON. Всё остальное в этом файле означает, что прогон упал и
    оболочка перенаправила туда стандартный поток ошибок.
    """
    if not путь.is_file():
        return "НЕ ИЗМЕРЕНО", f"файла {путь.name} нет"
    try:
        текст = путь.read_text(encoding="utf-8", errors="replace")
    except OSError as сбой:
        return "НЕ ИЗМЕРЕНО", f"{путь.name} не читается: {сбой}"
    try:
        json.loads(текст)
    except json.JSONDecodeError:
        строки = [с.strip() for с in текст.splitlines() if с.strip()]
        последняя = строки[-1] if строки else "(пусто)"
        if "Errno 28" in текст or "No space left" in текст:
            return ("ПРОГОН УПАЛ",
                    f"ENOSPC — место на диске кончилось: {последняя[:200]}")
        return "ПРОГОН УПАЛ", f"вместо отчёта: {последняя[:200]}"
    return "ИСПРАВНО", "отчёт прогона разбирается"


def копии_по_прогонам(
        каталог: pathlib.Path) -> tuple[dict[str, int], int, int, set[str]]:
    """(ГиБ по датам прогонов, файлов всего, байт всего, витрины) — чтением.

    Витрины берутся из имён копий суточных прогонов: это и есть перечень того,
    что издатель перезаписывает. Объединение по ВСЕМ суточным прогонам, а не по
    последнему: упавший прогон доходит не до всех витрин, и по нему перечень
    вышел бы короче настоящего.
    """
    по_датам: dict[str, int] = {}
    файлов = всего = 0
    витрины: set[str] = set()
    if not каталог.is_dir():
        return по_датам, 0, 0, витрины
    for ф in каталог.iterdir():
        if not ф.is_file():
            continue
        размер = ф.stat().st_size
        файлов += 1
        всего += размер
        м = МЕТКА.search(ф.name)
        if not м:
            continue
        по_датам[м.group(1)] = по_датам.get(м.group(1), 0) + размер
        имя = ф.name.split(".before.")[0]
        for хвост in ("-catalog.json", "-details.json"):
            if имя.endswith(хвост):
                витрины.add(имя[: -len(хвост)])
    return по_датам, файлов, всего, витрины


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--state", default=str(СОСТОЯНИЕ))
    р.add_argument("--frontend", default=str(ВИТРИНЫ))
    р.add_argument("--backups", default=str(КОПИИ))
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    состояние = pathlib.Path(а.state)
    отчёт = состояние / "last-publish.json"
    исход, пояснение = разбор_отчёта(отчёт)
    когда_прогон = _время(отчёт) if отчёт.is_file() else None

    по_датам, файлов, байт, свои = копии_по_прогонам(pathlib.Path(а.backups))
    откуда_перечень = "из копий суточных прогонов"
    if not свои:
        откуда_перечень = ("ПЕРЕЧЕНЬ ВЗЯТ ИЗ КАТАЛОГА ВИТРИН: копий суточных"
                           " прогонов нет, поэтому чужие файлы соседних"
                           " таймеров отличить не на чем")

    витрины: list[dict] = []
    фронт = pathlib.Path(а.frontend)
    if фронт.is_dir():
        for ф in sorted(фронт.glob("*-catalog.json")):
            имя = ф.name[: -len("-catalog.json")]
            if ЧУЖИЕ.match(имя) or (свои and имя not in свои):
                continue
            витрины.append({"витрина": имя, "изменён": _время(ф).isoformat()})
    else:
        исход, пояснение = "НЕ ИЗМЕРЕНО", f"каталога витрин {фронт} нет"

    отставшие = []
    if исход == "ИСПРАВНО" and когда_прогон is not None:
        порог = когда_прогон - dt.timedelta(hours=2)
        отставшие = [в for в in витрины
                     if dt.datetime.fromisoformat(в["изменён"]) < порог]
        if отставшие:
            исход = "ПРОГОН ПРОШЁЛ, ВИТРИНЫ СТАРЫЕ"
            пояснение = (f"отчёт есть, но {len(отставшие)} из {len(витрины)}"
                         f" витрин не обновлялись к прогону")

    место = shutil.disk_usage("/")

    итог = {
        "исход": исход,
        "почему": пояснение,
        "прогон": когда_прогон.isoformat() if когда_прогон else None,
        "витрин": len(витрины),
        "перечень_витрин_откуда": откуда_перечень,
        "отставших": [в["витрина"] for в in отставшие],
        "витрины": витрины,
        "копии": {"файлов": файлов, "гиб": round(байт / 2**30, 2),
                  "суточных_прогонов": len(по_датам),
                  "гиб_в_сутки": round(
                      sum(по_датам.values()) / 2**30 / len(по_датам), 2)
                  if по_датам else None},
        "свободно_гиб": round(место.free / 2**30, 2),
    }
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
        return 0 if исход == "ИСПРАВНО" else (2 if исход == "НЕ ИЗМЕРЕНО" else 1)

    print(f"исход: {исход}")
    print(f"   почему: {пояснение}")
    print(f"   прогон: {итог['прогон'] or '—'}")
    print(f"   витрин этого издателя: {len(витрины)} ({откуда_перечень})"
          f"{'; отстали: ' + ', '.join(итог['отставших']) if отставшие else ''}")
    for в in витрины:
        print(f"      {в['витрина']:14} каталог от {в['изменён'][:16]}")
    к = итог["копии"]
    в_сутки = f", ~{к['гиб_в_сутки']} ГиБ в сутки" if к["гиб_в_сутки"] else ""
    print(f"   копии перед публикацией: {к['гиб']} ГиБ, файлов {к['файлов']},"
          f" суточных прогонов {к['суточных_прогонов']}{в_сутки}")
    print(f"   свободно на хосте: {итог['свободно_гиб']} ГиБ")
    if исход == "ПРОГОН УПАЛ" and "ENOSPC" in пояснение:
        print("   что это значит: прогон падает на снятии копии ПЕРЕД записью,"
              " поэтому витрины остаются на прежнем каталоге. Срок хранения"
              " копий и порядок шагов — docs/OWNER_BLOCK_K2_AND_DISK_20261023.md.")
    return 0 if исход == "ИСПРАВНО" else (2 if исход == "НЕ ИЗМЕРЕНО" else 1)


if __name__ == "__main__":
    sys.exit(главное())
