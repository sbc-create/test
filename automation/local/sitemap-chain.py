#!/usr/bin/env python3
"""Цепочка индексации: robots.txt → sitemap.xml → вложенные карты.

Повод. Карта сайта проверялась по коду ответа ОДНОГО адреса `/sitemap.xml`, а
индекс карт ссылается на вложенные файлы, и отказ живёт именно там: на
yummyani7.site и yummyani7.info индекс отвечает 200 за 0.1 с, а
`/sitemap/titles.xml` — 504 ровно через 30 с. Для поискового робота это
означает, что все тайтлы недоступны, а проверка «карта отдаёт 200» при этом
зелёная.

Проверяется ровно то, что обходит робот:

1. `robots.txt` — код и объявленные в нём карты (`Sitemap:`);
2. `/sitemap.xml` — код; если это `sitemapindex`, берутся адреса вложенных;
3. каждая вложенная карта — код, время ответа и число адресов в ней.

Ноль адресов в карте, которая ответила 200, называется отдельно: пустая карта
не является ошибкой доставки, но и не является рабочей картой.

Домены берутся из реестра ячеек. Имена из RFC 6761 (`.localhost`, `.test`,
`.invalid`, `.example`) не опрашиваются: они не разрешаются публично, и их
молчание — свойство имени, а не состояние витрины.

Только чтение.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1].parent
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ИСПЫТАТЕЛЬНЫЕ = (".localhost", ".test", ".invalid", ".example")

#: Сколько вложенных карт опрашивать у одного домена. Предел нужен: индекс
#: может перечислять сотни файлов, а задача — найти отказ, не обойти всё.
ПРЕДЕЛ_ВЛОЖЕННЫХ = 10

#: Секунды, после которых успешный ответ считается «на грани». Число не
#: округление: `proxy_read_timeout` nginx по умолчанию 30 с, и карта, которой
#: нужно 20 с и больше, выходит за него при первом же замедлении источника.
ПОРОГ_НА_ГРАНИ = 20.0


def домены(путь: Path) -> list[str]:
    try:
        документ = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        print(f"реестр ячеек не прочитан ({путь}): {сбой}", file=sys.stderr)
        return []
    итог = []
    for ячейка in документ.get("cells") or []:
        домен = ячейка.get("domain") or ""
        if домен and not домен.endswith(ИСПЫТАТЕЛЬНЫЕ):
            итог.append(домен)
    return итог


#: Код выхода curl, означающий «имя не разрешилось». Отличать его обязательно:
#: домена, которого нет в DNS, не существует для робота, и объявлять у него
#: сломанную карту — ложная тревога на четырёх зарегистрированных записях.
CURL_НЕТ_ИМЕНИ = 6
#: Истёк предел ожидания. Для карты это ЗНАЧИМЫЙ исход, а не «не измерено»:
#: робот ждёт не дольше, чем сервер отвечает.
CURL_ТАЙМАУТ = 28


def запрос(адрес: str, таймаут: int) -> tuple[str, float, str]:
    """(код, секунды, тело). Код «000» — ответа не было вовсе.

    Тело и код берутся ОДНИМ запросом: второй запрос мог бы попасть в другое
    состояние, и тогда код относился бы к одному ответу, а содержимое к
    другому. Особые значения кода: `dns` — имя не разрешилось,
    `таймаут` — предел ожидания истёк.
    """
    итог = subprocess.run(
        ["curl", "-sS", "-w", "\n%{http_code} %{time_total}",
         "--max-time", str(таймаут), адрес],
        capture_output=True, text=True)
    вывод = итог.stdout or ""
    тело, _, хвост = вывод.rpartition("\n")
    части = хвост.split()
    код = части[0] if части else "000"
    try:
        секунды = float(части[1]) if len(части) > 1 else -1.0
    except ValueError:
        секунды = -1.0
    if итог.returncode == CURL_НЕТ_ИМЕНИ:
        код = "dns"
    elif итог.returncode == CURL_ТАЙМАУТ:
        код = "таймаут"
    return код, секунды, тело


def карты_из_robots(тело: str) -> list[str]:
    return re.findall(r"(?im)^\s*Sitemap:\s*(\S+)\s*$", тело)


def адреса_карты(тело: str) -> tuple[bool, list[str]]:
    """(это индекс карт, адреса внутри).

    Индекс и обычная карта различаются корневым элементом, и путать их нельзя:
    у индекса `<loc>` — это другие КАРТЫ, у карты — страницы сайта.
    """
    индекс = "<sitemapindex" in тело
    return индекс, re.findall(r"<loc>\s*([^<\s]+)\s*</loc>", тело)


def проверить(домен: str, таймаут: int) -> dict:
    итог: dict = {"домен": домен, "вложенные": [], "замечания": []}
    код, _сек, тело = запрос(f"https://{домен}/robots.txt", таймаут)
    итог["robots"] = код
    итог["карты_в_robots"] = карты_из_robots(тело) if код == "200" else []
    if код == "dns":
        # Домена нет в DNS: для робота он не существует. Это состояние
        # ЗАПИСИ РЕЕСТРА, а не поломка карты, и замечанием не считается —
        # иначе четыре незапущенных домена навсегда красят итог красным, и
        # вместе с ними утонет настоящий отказ.
        итог["sitemap"] = "dns"
        итог["нет_dns"] = True
        return итог

    код, сек, тело = запрос(f"https://{домен}/sitemap.xml", таймаут)
    итог["sitemap"] = код
    итог["sitemap_сек"] = сек
    if код != "200":
        итог["замечания"].append(f"/sitemap.xml → {код} за {сек:.1f} с")
        return итог
    индекс, адреса = адреса_карты(тело)
    итог["индекс"] = индекс
    if not индекс:
        итог["адресов_в_карте"] = len(адреса)
        if not адреса:
            итог["замечания"].append("карта ответила 200 и пуста")
        return итог
    for адрес in адреса[:ПРЕДЕЛ_ВЛОЖЕННЫХ]:
        к, с, т = запрос(адрес, таймаут)
        _виндекс, внутри = адреса_карты(т)
        запись = {"адрес": адрес, "код": к, "сек": с, "адресов": len(внутри)}
        итог["вложенные"].append(запись)
        имя = адрес.rsplit("/", 1)[-1]
        if к != "200":
            итог["замечания"].append(f"{имя} → {к} за {с:.1f} с")
        elif not внутри:
            итог["замечания"].append(f"{имя} → 200 и пуста")
        elif с >= ПОРОГ_НА_ГРАНИ:
            # Успех у самой границы — тоже находка, и она дороже отказа:
            # измерено 12.10, `/sitemap/titles.xml` на yummyani7.site отдал
            # 504 ровно через 30 с (предел nginx), а через несколько минут —
            # 200 за меньшее время. Проверка, глядящая только на код,
            # объявила бы карту рабочей и пропустила перемежающийся отказ.
            итог["замечания"].append(
                f"{имя} → 200, но {с:.0f} с: у предела nginx в 30 с")
    if len(адреса) > ПРЕДЕЛ_ВЛОЖЕННЫХ:
        итог["замечания"].append(
            f"вложенных карт {len(адреса)}, опрошено {ПРЕДЕЛ_ВЛОЖЕННЫХ}")
    return итог


def разбор(аргв=None):
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--registry", type=Path, default=РЕЕСТР)
    р.add_argument("--domain", action="append", default=[],
                   help="проверить только эти домены (можно повторять)")
    р.add_argument("--timeout", type=int, default=45,
                   help="предел одного запроса в секундах")
    р.add_argument("--json", action="store_true")
    return р.parse_args(аргв)


def главное(аргв=None) -> int:
    опции = разбор(аргв)
    список = опции.domain or домены(опции.registry)
    if not список:
        return 2
    итоги = [проверить(д, опции.timeout) for д in список]

    if опции.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=2))
    else:
        print(f"{'домен':24} {'robots':>7} {'sitemap':>8} {'вложенных':>9} "
              f"{'адресов':>8} {'медленн.':>8}  замечания")
        for и in итоги:
            адресов = sum(в["адресов"] for в in и["вложенные"]) \
                or и.get("адресов_в_карте", 0)
            самая = max((в["сек"] for в in и["вложенные"]), default=-1.0)
            медленно = f"{самая:.0f} с" if самая >= 0 else "—"
            print(f"{и['домен']:24} {и['robots']:>7} {и['sitemap']:>8} "
                  f"{len(и['вложенные']):>9} {адресов:>8} {медленно:>8}  "
                  + ("; ".join(и["замечания"]) if и["замечания"]
                     else "нет DNS" if и.get("нет_dns") else "—"))
        с_замечаниями = [и for и in итоги if и["замечания"]]
        без_dns = [и for и in итоги if и.get("нет_dns")]
        print(f"\nдоменов с замечаниями: {len(с_замечаниями)} из {len(итоги)}"
              + (f"; без DNS (не опрошены): {len(без_dns)}" if без_dns else ""))

    # Ненулевой код — когда хоть одна цепочка сломана. Иначе проверка, которая
    # не умеет провалиться, доверия не несёт (решение D205).
    return 1 if any(и["замечания"] for и in итоги) else 0


if __name__ == "__main__":
    raise SystemExit(главное())
