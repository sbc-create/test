#!/usr/bin/env python3
"""Откуда витрина печатает оставшуюся формулировку: файл и строка.

Зачем отдельно от сверки публичных страниц. Та отвечает «на домене осталось N
формулировок», и этого мало: правка идёт в файл, а файлов у витрины десятки, и
один и тот же текст в семействе живёт в разных слоях.

Урок, оплаченный дважды. Сессия витрины `1lordserials1.online` показала: после
замены текста в `src/` формулировки остались на живой главной, потому что
печатает их НАЛОЖЕНИЕ — оно переопределяет `главная()` целиком. Её же уточнение
важнее первого вывода: смотреть надо не на наличие каталога `overlay/`, а на
то, переопределён ли КОНКРЕТНЫЙ метод. У той витрины правка ядра до главной не
доехала, а до подвала доехала — `_подвал` наложение не трогает.

Поэтому инструмент ищет не каталог, а файл и строку, и делает это по
СКЛЕЕННОМУ исходнику: фраза бывает свёрстана переносом строковых литералов — на
странице печатается целиком, поиском подстрокой не находится. Именно на этом
молчала доставляемая проверка `checks/public_wording.py`.

Исходов три, и правило «переопределён → мёртвая» неверно. Предостережение
сессии линии шаблона, проверенное ею на живой странице: в `lords02_view.py`
`super()` встречается шесть раз, и только `главная` обходится без него.
Остальные пять — обёртки, и текст ядра внутри них ЖИВОЙ: «Смотреть онлайн»,
«Сезон», «Страна» есть только в ядре и рендерятся через `super().тайтл`.
Поэтому различается:

* переопределение БЕЗ `super()` — ветка ядра мертва;
* переопределение С `super()` — текст ядра живой;
* **перезапись обёрткой** (слой берёт вывод ядра и подменяет в нём часть)
  статическим разбором НЕ ловится — только сравнением с живой страницей. Две
  ошибки в этой задаче — чужая привязка по `grep` и мой вывод «наполовину» —
  поймались именно вторым измерением, а не чтением кода.

Формулировки берутся из измерения публичных страниц
(`automation/local/editorial-public-state.py`), а не придумываются.

Ничего не меняет: только читает файлы выложенного выпуска.

    python3 automation/local/wording-origin.py --release /srv/lordserial33-biz/current \\
        --domain lordserial33.biz
    python3 automation/local/wording-origin.py --release <путь> --phrase "текст"
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИЗМЕРЕНИЕ = КОРЕНЬ / "docs/verification/editorial-public-state-20261015.json"

_СКЛЕЙКА = re.compile(r"""(?:"\s*\+?\s*")|(?:'\s*\+?\s*')""")


def склеенный(текст: str) -> str:
    """Исходник в виде, в котором фраза видна так же, как на странице."""
    return re.sub(r"\s+", " ", _СКЛЕЙКА.sub("", текст))


def цепочка_области(строки: list[str], номер: int) -> list[tuple[int, str, str]]:
    """Вложенность `class`/`def` над строкой: от внешнего к внутреннему.

    Считается по отступам: вверх от строки берётся каждое объявление с
    отступом МЕНЬШЕ уже найденного. Так находится настоящий метод, а не
    случайный `def`, оказавшийся выше таблицы уровня модуля.
    """
    путь: list[tuple[int, str, str]] = []
    отступ: int | None = None
    for i in range(номер, -1, -1):
        м = re.match(r"(\s*)(class|async def|def)\s+([^\s(:]+)", строки[i])
        if not м:
            continue
        от = len(м.group(1))
        if отступ is None or от < отступ:
            отступ = от
            путь.append((i + 1, "class" if м.group(2) == "class" else "def",
                         м.group(3)))
        if от == 0:
            break
    return list(reversed(путь))


def ближайшая_функция(строки: list[str], номер: int) -> str:
    """Короткая подпись области: класс и метод, если они есть."""
    путь = цепочка_области(строки, номер)
    if not путь:
        return "(вне функции)"
    return " -> ".join(f"{вид} {имя}@{стр}" for стр, вид, имя in путь)


def классы(файлы) -> dict[str, tuple[Path, int, list[str], str]]:
    """Все классы выпуска: имя -> (файл, строка, базы, исходник файла).

    Базы нужны, чтобы различить ПЕРЕОПРЕДЕЛЕНИЕ и одноимённый метод соседнего
    вида. В ядре семейства `главная` определена у пяти параллельных классов
    (`Вид`, `ВидЛордс`, `ВидЗона`, `ВидАнимедиа`, `Обработчик`), и без разбора
    баз инструмент пометил живую строку пятью «мёртвыми» — ошибка обратного
    знака, хуже отсутствия предупреждения.
    """
    итог: dict[str, tuple[Path, int, list[str], str]] = {}
    for ф in файлы:
        исходник = ф.read_text(encoding="utf-8", errors="replace")
        for n, с in enumerate(исходник.splitlines(), 1):
            м = re.match(r"\s*class\s+([A-Za-zА-Яа-яЁё_][\w]*)\s*(\(([^)]*)\))?",
                         с)
            if not м:
                continue
            базы = [б.strip().split(".")[-1]
                    for б in (м.group(3) or "").split(",") if б.strip()]
            итог[м.group(1)] = (ф, n, базы, исходник)
    return итог


def наследники(карта: dict, предок: str) -> list[str]:
    """Классы, которые наследуют `предок` прямо или через цепочку."""
    итог = []
    for имя, (_, _, базы, _) in карта.items():
        видел = set()
        очередь = list(базы)
        while очередь:
            б = очередь.pop()
            if б in видел:
                continue
            видел.add(б)
            if б == предок:
                итог.append(имя)
                break
            если_есть = карта.get(б)
            if если_есть:
                очередь.extend(если_есть[2])
    return итог


def переопределения(файлы, свой: Path, метод: str,
                    свой_класс: str) -> list[str]:
    """Где метод переопределён У НАСЛЕДНИКА и вызывается ли там `super()`.

    Вердикта инструмент не выдаёт: какой именно вид создаёт рантайм витрины,
    статически не видно. Называется факт — «наследник переопределяет этот метод
    и super() не вызывает», — и этого достаточно, чтобы не отправить правщика
    по мёртвому адресу и не объявить мёртвой живую строку.
    """
    if not свой_класс:
        return []
    карта = классы(файлы)
    найдено: list[str] = []
    for имя in наследники(карта, свой_класс):
        ф, строка_класса, _, исходник = карта[имя]
        строки = исходник.splitlines()
        for n, с in enumerate(строки, 1):
            if not re.match(r"\s+(?:async\s+)?def\s+" + re.escape(метод)
                            + r"\s*\(", с):
                continue
            # Метод должен принадлежать именно этому классу, а не соседнему в
            # том же файле: берём класс по области видимости строки.
            принадлежит = ""
            for стр, вид, имя_обл in reversed(цепочка_области(строки, n - 1)):
                if вид == "class":
                    принадлежит = имя_обл
                    break
            if принадлежит != имя:
                continue
            зовёт_super = f"super().{метод}" in исходник
            найдено.append(
                f"{ф.name}:{n} ({имя}@{строка_класса})"
                + ("" if зовёт_super else " БЕЗ super()"))
    return найдено


def фразы_домена(домен: str) -> list[str]:
    if not ИЗМЕРЕНИЕ.is_file():
        print(f"нет измерения {ИЗМЕРЕНИЕ}: сначала прогоните "
              "automation/local/editorial-public-state.py", file=sys.stderr)
        return []
    д = json.loads(ИЗМЕРЕНИЕ.read_text(encoding="utf-8"))
    return list((д.get("с_остатками") or {}).get(домен) or [])


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--release", type=Path, required=True,
                   help="каталог выложенного выпуска витрины")
    р.add_argument("--domain", default="",
                   help="домен: формулировки берутся из измерения страниц")
    р.add_argument("--phrase", action="append", default=[],
                   help="формулировка явно (можно несколько раз)")
    опции = р.parse_args(аргв)

    фразы = list(опции.phrase) or фразы_домена(опции.domain)
    if not фразы:
        print("нечего искать: ни --phrase, ни остатков по домену в измерении",
              file=sys.stderr)
        return 2
    if not опции.release.is_dir():
        print(f"нет каталога выпуска {опции.release}", file=sys.stderr)
        return 2

    файлы = sorted(p for каталог in ("src", "overlay", "template")
                   for p in (опции.release / каталог).rglob("*.py")
                   if (опции.release / каталог).is_dir()
                   and "__pycache__" not in str(p))
    print(f"выпуск: {опции.release}")
    print(f"файлов: {len(файлы)}; каталоги: "
          f"{sorted({p.parent.name for p in файлы})}")

    не_найдено = 0
    for фраза in фразы:
        найдено: list[tuple[str, int, str]] = []
        for ф in файлы:
            исходник = ф.read_text(encoding="utf-8", errors="replace")
            строки = исходник.splitlines()
            попал = False
            for n, с in enumerate(строки):
                if фраза in с:
                    найдено.append((str(ф.relative_to(опции.release)), n + 1,
                                    ближайшая_функция(строки, n)))
                    попал = True
            if not попал and фраза in склеенный(исходник):
                найдено.append((str(ф.relative_to(опции.release)), 0,
                                "свёрстана переносом литералов"))
        print(f"\n«{фраза[:70]}»")
        if not найдено:
            не_найдено += 1
            print("   в файлах выпуска НЕ найдена: приходит из закреплённого "
                  "артефакта либо собирается из частей — правка идёт "
                  "переходником")
        for имя, строка, функция in найдено:
            где = f"строка {строка}" if строка else "перенос литералов"
            print(f"   {имя}: {где}, область {функция}")
            # Метод, внутри которого лежит строка, мог быть переопределён
            # слоем витрины — тогда правка по этому адресу будет мёртвой.
            # Переопределять можно МЕТОД, то есть `def` внутри класса.
            # Функция уровня модуля с тем же именем в другом файле — не
            # переопределение, и предупреждать о ней значит шуметь: первый
            # прогон так пожаловался на `_оценка@76`, у которой класса нет.
            метод = ""
            свой_класс = ""
            for часть in функция.split(" -> "):
                if часть.startswith("class "):
                    свой_класс = часть[6:].split("@")[0]
                elif часть.startswith("def ") and свой_класс and not метод:
                    метод = часть[4:].split("@")[0]
            if метод:
                свой = опции.release / имя
                чужие = переопределения(файлы, свой, метод, свой_класс)
                for место in чужие:
                    if "БЕЗ super()" in место:
                        print(f"      МЁРТВАЯ, если исполняется слой: метод "
                              f"{метод} переопределён в {место} — вывод ядра "
                              f"там не используется вовсе")
                    else:
                        print(f"      живая: метод {метод} переопределён в "
                              f"{место}, но super() вызывается — слой "
                              f"дорабатывает вывод ядра. Перезапись именно "
                              f"этого текста обёрткой видна только на живой "
                              f"странице")

    print(f"\nформулировок: {len(фразы)}; без найденного места: {не_найдено}")
    return 1 if не_найдено else 0


if __name__ == "__main__":
    raise SystemExit(главное())
