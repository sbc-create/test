#!/usr/bin/env python3
"""Расход токенов по стенограммам Claude Code: агрегат, а не чтение историй.

ЗАЧЕМ ИМЕННО АГРЕГАТОР. Полные истории чатов занимают 2,2 ГиБ; загружать их в
контекст, чтобы узнать расход, — это и есть та трата, которую мы ищем. Скрипт
читает файлы потоком, берёт ТОЛЬКО метаданные обращения (`message.usage`,
модель, время, сеанс, признак подагента, версию, вид входа) и печатает свод.
Содержимое сообщений не читается и никуда не попадает.

Что считается и почему раздельно:

* **входные, выходные, запись кеша и чтение кеша** — четыре разные категории с
  разной ценой; сумма «всего токенов» без разбивки вводит в заблуждение, потому
  что чтение кеша в агентной работе обычно на порядок больше всего остального;
* **подагенты** (`isSidechain: true`) — отдельная строка: их расход легко
  принять за расход главного сеанса;
* **обращения с ошибкой API** (`isApiErrorMessage`) — отдельно: попытка, не
  давшая результата, всё равно могла стоить входных токенов;
* **двойной счёт** снимается по `requestId`, и это не придирка: ОДНО обращение
  к API записывается в стенограмму 2–3 строками — по блоку содержимого
  (рассуждение, текст, вызов инструмента), — и КАЖДАЯ строка несёт полный
  `usage` того же обращения. Проверено на выборке: у `requestId` с тремя
  строками все три дают одинаковые `вх 2 / вых 277 / запись 28 594 / чтение
  10 834`. Счёт по строкам завышал итог примерно в 1,8 раза. Строки без
  `requestId` (их мало) считаются по `uuid`, и их число печатается отдельно.

Чего скрипт НЕ знает и не выдумывает: расхода аккаунта за пределами этой
машины, цены в деньгах и расхода у другого провайдера (Qwen). Эти величины
печатаются как «не измерено».

    python3 automation/local/token-spend-audit.py --days 7 --json out.json
"""
from __future__ import annotations

import argparse
import collections
import datetime as dt
import glob
import json
import os
import pathlib
import sys

КОРЕНЬ_СТЕНОГРАММ = "/home/claude/.claude/projects/*/*.jsonl"


def пусто() -> dict:
    return {"обращений": 0, "входные": 0, "выходные": 0, "запись_кеша": 0,
            "чтение_кеша": 0, "поиск": 0, "выборка": 0, "ошибки": 0}


def прибавить(куда: dict, сколько: dict) -> None:
    for к, в in сколько.items():
        куда[к] = куда.get(к, 0) + в


def разобрать(строка: str) -> dict | None:
    """Метаданные одного обращения или None, если строка не про расход."""
    try:
        з = json.loads(строка)
    except ValueError:
        return None
    м = з.get("message") or {}
    u = м.get("usage")
    if not isinstance(u, dict):
        return None
    вх = u.get("input_tokens") or 0
    вых = u.get("output_tokens") or 0
    зк = u.get("cache_creation_input_tokens") or 0
    чк = u.get("cache_read_input_tokens") or 0
    if not (вх or вых or зк or чк):
        return None          # синтетические строки без расхода
    инстр = u.get("server_tool_use") or {}
    return {
        "uuid": з.get("uuid"),
        "requestId": з.get("requestId"),
        "время": з.get("timestamp"),
        "сеанс": з.get("sessionId"),
        "проект": pathlib.Path(з.get("cwd") or "").name or "—",
        "модель": м.get("model") or "—",
        "подагент": bool(з.get("isSidechain")),
        "версия": з.get("version") or "—",
        "вход": з.get("entrypoint") or "—",
        "усилие": з.get("perTurnEffort") or "—",
        "ошибка": bool(з.get("isApiErrorMessage")),
        "числа": {"обращений": 1, "входные": вх, "выходные": вых,
                  "запись_кеша": зк, "чтение_кеша": чк,
                  "поиск": инстр.get("web_search_requests") or 0,
                  "выборка": инстр.get("web_fetch_requests") or 0,
                  "ошибки": 1 if з.get("isApiErrorMessage") else 0},
    }


def собрать(шаблон: str, с: dt.datetime, по: dt.datetime) -> dict:
    видено: set[str] = set()
    повторов_запроса = 0
    своды = {
        "всего": пусто(), "по_дням": collections.defaultdict(пусто),
        "по_модели": collections.defaultdict(пусто),
        "по_проекту": collections.defaultdict(пусто),
        "по_сеансу": collections.defaultdict(пусто),
        "подагенты": пусто(), "главные": пусто(),
        "по_усилию": collections.defaultdict(пусто),
    }
    версии: collections.Counter = collections.Counter()
    входы: collections.Counter = collections.Counter()
    окна = {"сеансов": set(), "файлов": 0, "строк_с_расходом": 0,
            "вне_окна": 0, "без_времени": 0, "без_requestId": 0}
    for путь in sorted(glob.glob(шаблон)):
        if not os.path.isfile(путь):
            continue
        окна["файлов"] += 1
        with open(путь, encoding="utf-8", errors="replace") as ф:
            for строка in ф:
                if '"usage"' not in строка:
                    continue
                з = разобрать(строка)
                if з is None:
                    continue
                т = з["время"]
                if not т:
                    окна["без_времени"] += 1
                    continue
                try:
                    когда = dt.datetime.fromisoformat(т.replace("Z", "+00:00"))
                except ValueError:
                    окна["без_времени"] += 1
                    continue
                if not (с <= когда <= по):
                    окна["вне_окна"] += 1
                    continue
                ключ = з["requestId"] or f"uuid:{з['uuid']}"
                if ключ in видено:
                    повторов_запроса += 1
                    continue          # тот же запрос, другой блок содержимого
                видено.add(ключ)
                if not з["requestId"]:
                    окна["без_requestId"] = окна.get("без_requestId", 0) + 1
                окна["строк_с_расходом"] += 1
                окна["сеансов"].add(з["сеанс"])
                версии[з["версия"]] += 1
                входы[з["вход"]] += 1
                ч = з["числа"]
                прибавить(своды["всего"], ч)
                прибавить(своды["по_дням"][когда.strftime("%Y-%m-%d")], ч)
                прибавить(своды["по_модели"][з["модель"]], ч)
                прибавить(своды["по_проекту"][з["проект"]], ч)
                прибавить(своды["по_сеансу"][з["сеанс"]], ч)
                прибавить(своды["по_усилию"][з["усилие"]], ч)
                прибавить(своды["подагенты" if з["подагент"] else "главные"], ч)
    окна["сеансов"] = len(окна["сеансов"])
    окна["повторов_requestId"] = повторов_запроса
    return {"своды": своды, "охват": окна, "версии": dict(версии),
            "входы": dict(входы)}


def печать(итог: dict, заголовок: str, верх: int = 12) -> None:
    с = итог["своды"]
    в = с["всего"]
    print(f"\n=== {заголовок}")
    o = итог["охват"]
    print(f"охват: файлов {o['файлов']}, ОБРАЩЕНИЙ (по requestId) {o['строк_с_расходом']},"
          f" сеансов {o['сеансов']}, вне окна {o['вне_окна']},"
          f" без времени {o['без_времени']}")
    print(f"      снято как повторные блоки одного обращения: {o['повторов_requestId']}"
          f"; строк без requestId (считаны по uuid): {o['без_requestId']}")
    print(f"версии Claude Code: {итог['версии']}")
    print(f"виды входа: {итог['входы']}")
    print(f"\nВСЕГО: обращений {в['обращений']}, входных {в['входные']:,},"
          f" выходных {в['выходные']:,}, запись кеша {в['запись_кеша']:,},"
          f" чтение кеша {в['чтение_кеша']:,}, ошибок API {в['ошибки']}")
    for имя, ключ in (("по моделям", "по_модели"), ("по проектам", "по_проекту"),
                      ("по усилию", "по_усилию")):
        print(f"\n{имя}:")
        строки = sorted(с[ключ].items(),
                        key=lambda п: -(п[1]["входные"] + п[1]["выходные"]
                                        + п[1]["запись_кеша"]))
        for к, зн in строки[:верх]:
            print(f"   {str(к)[:38]:38} обращений {зн['обращений']:5}"
                  f" вх {зн['входные']:>10,} вых {зн['выходные']:>8,}"
                  f" зап.кеша {зн['запись_кеша']:>11,} чт.кеша {зн['чтение_кеша']:>13,}")
    print("\nглавные сеансы против подагентов:")
    for имя in ("главные", "подагенты"):
        зн = с[имя]
        print(f"   {имя:12} обращений {зн['обращений']:5} вх {зн['входные']:>10,}"
              f" вых {зн['выходные']:>8,} зап.кеша {зн['запись_кеша']:>11,}"
              f" чт.кеша {зн['чтение_кеша']:>13,}")
    print("\nпо дням:")
    for д, зн in sorted(с["по_дням"].items()):
        print(f"   {д} обращений {зн['обращений']:5} вх {зн['входные']:>10,}"
              f" вых {зн['выходные']:>8,} зап.кеша {зн['запись_кеша']:>11,}"
              f" чт.кеша {зн['чтение_кеша']:>13,} ошибок {зн['ошибки']:4}")
    print("\nсамые дорогие сеансы (по сумме входных, выходных и записи кеша):")
    строки = sorted(с["по_сеансу"].items(),
                    key=lambda п: -(п[1]["входные"] + п[1]["выходные"] + п[1]["запись_кеша"]))
    for к, зн in строки[:верх]:
        print(f"   {str(к)[:36]:36} обращений {зн['обращений']:5}"
              f" вх {зн['входные']:>10,} вых {зн['выходные']:>8,}"
              f" зап.кеша {зн['запись_кеша']:>11,} чт.кеша {зн['чтение_кеша']:>13,}")


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--days", type=float, default=7.0)
    р.add_argument("--also-hours", type=float, default=24.0,
                   help="второе, короткое окно — печатается отдельно")
    р.add_argument("--pattern", default=КОРЕНЬ_СТЕНОГРАММ)
    р.add_argument("--json", type=pathlib.Path)
    а = р.parse_args(аргв)
    по = dt.datetime.now(dt.timezone.utc)
    длинное = собрать(а.pattern, по - dt.timedelta(days=а.days), по)
    с_ = по - dt.timedelta(days=а.days)
    печать(длинное, f"окно {а.days:g} сут: {с_.isoformat()} … {по.isoformat()}")
    короткое = собрать(а.pattern, по - dt.timedelta(hours=а.also_hours), по)
    с2 = по - dt.timedelta(hours=а.also_hours)
    печать(короткое, f"окно {а.also_hours:g} ч: {с2.isoformat()} … {по.isoformat()}")
    print("\nЧЕГО ЭТОТ СЧЁТ НЕ ГОВОРИТ: расхода аккаунта за пределами этой машины"
          " (локальные стенограммы — не весь аккаунт), цены в деньгах и расхода"
          " Qwen у другого провайдера. Это НЕ ИЗМЕРЕНО здесь и помечено отдельно.")
    if а.json:
        а.json.parent.mkdir(parents=True, exist_ok=True)
        def прост(о):
            if isinstance(о, dict):
                return {str(к): прост(в) for к, в in о.items()}
            if isinstance(о, set):
                return len(о)
            return о
        а.json.write_text(json.dumps({"окно_суток": прост(длинное),
                                      "окно_часов": прост(короткое)},
                                     ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"\nсвод записан: {а.json}")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
