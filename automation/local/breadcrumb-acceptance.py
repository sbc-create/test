#!/usr/bin/env python3
"""Приёмка крошек на живых витринах: разметка против того, что видно глазами.

Что проверяется и почему именно так. `BreadcrumbList` в разметке — обещание
поисковику о том, какой путь видит человек. Дефект, ради которого эта приёмка
написана, выглядит безобидно: цепочка строится не из видимых крошек, а из
заголовка, и в разметке появляется звено, которого на странице НЕТ. Снаружи
страница при этом исправна, поэтому поймать это можно только сверкой двух
источников на ОДНОЙ странице.

Признаки, каждый отдельно:

1. у страницы есть видимые крошки;
2. у страницы есть `BreadcrumbList` в JSON-LD;
3. имена звеньев разметки совпадают с видимыми крошками — по составу И по
   порядку. Лишнее звено в разметке и есть «ложная цепочка»;
4. последнее звено — это сама страница (её заголовок), а не раздел.

Домены берутся ТОЛЬКО из реестра ячеек: придумывать адреса запрещено. Адреса
карточек берутся обходом каталога, а не угадыванием.

«Не измерено» (страница не ответила, каталог пуст) никогда не считается
расхождением: это факт о приёмке, а не о витрине.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import ssl
import sys
import urllib.error
import urllib.request
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
ПРЕДЕЛ_С = 30  # столько же держит nginx (proxy_read_timeout 30s)

_JSONLD = re.compile(
    r'<script[^>]+type="application/ld\+json"[^>]*>(.*?)</script>', re.S | re.I)
#: Контейнер крошек ищется и по классу, и по СЕМАНТИЧЕСКОЙ метке. Только по
#: классу его найти нельзя, и это измерено: у Animedia он называется
#: `<nav class="zcr" aria-label="Хлебные крошки">` — в классе ни «crumb», ни
#: «крошк». Первая редакция этой приёмки из-за этого объявила «видимых крошек
#: нет» на витрине, где они есть, и чуть не обвинила исправную выкладку.
_КРОШКИ_БЛОК = re.compile(
    r'<(nav|ol|ul|div)[^>]*(?:(?:class|id)="[^"]*(?:breadcrumb|crumbs?)[^"]*"'
    r'|aria-label="[^"]*(?:крошк|breadcrumb)[^"]*")[^>]*>(.*?)</\1>',
    re.S | re.I)
_ЗВЕНО = re.compile(r"<(?:a|span|li)[^>]*>(.*?)</(?:a|span|li)>", re.S | re.I)
_ТЕГИ = re.compile(r"<[^>]+>")
#: Виды адреса карточки — ПО НАБЛЮДЕНИЮ на живых витринах, а не по догадке:
#: `/title/` у Lords, Zona, AnimeGo и Animedia, `/anime/` у Yummy (48 таких
#: ссылок в её каталоге). Пока вида `/anime/` здесь не было, пять витрин Yummy
#: попадали в «не измерено» — и выглядело это как факт о витринах.
_ССЫЛКА_КАРТОЧКИ = re.compile(r'href="(/(?:title|catalog|anime)/[^"/]+/?)"')


def текст(кусок: str) -> str:
    return html.unescape(_ТЕГИ.sub(" ", кусок)).replace("\xa0", " ").strip()


class _Перенаправления(urllib.request.HTTPRedirectHandler):
    """308 на Python 3.10 не следуется штатно — а сеть его отдаёт.

    Измерено: `https://yummyani.org/catalog/` отвечает 308, и без этого
    обработчика пять витрин Yummy попадали в «не измерено» по причине внутри
    приёмки, а не на витрине. Хуже всего здесь то, что выглядело это как факт
    о сайте.
    """

    def http_error_308(self, req, fp, code, msg, headers):  # noqa: N802
        return self.http_error_307(req, fp, 307, msg, headers)


_ОТКРЫВАТЕЛЬ = urllib.request.build_opener(_Перенаправления())


def достать(url: str) -> tuple[int | None, str, str]:
    """(код, тело, причина). Причина непустая — значит не измерено."""
    запрос = urllib.request.Request(url, headers={
        "User-Agent": "site-factory-acceptance/1.0 (breadcrumbs)"})
    ssl.create_default_context()
    try:
        with _ОТКРЫВАТЕЛЬ.open(запрос, timeout=ПРЕДЕЛ_С) as ответ:
            return ответ.status, ответ.read().decode("utf-8", "replace"), ""
    except urllib.error.HTTPError as сбой:
        return сбой.code, "", f"HTTP {сбой.code}"
    except Exception as сбой:  # noqa: BLE001 — сеть: причина важнее типа
        return None, "", f"{type(сбой).__name__}: {сбой}"


def видимые_крошки(тело: str) -> tuple[list[str], str]:
    """(звенья в элементах, весь видимый текст контейнера).

    Текст нужен отдельно, и это измерено: последнее звено — сама страница — у
    Lords и Zona выводится ОБЫЧНЫМ ТЕКСТОМ без обёртки (ссылкой быть ему
    незачем, это текущая страница). Первая редакция искала только элементы,
    поэтому «Jamai 2.0» в видимых не находила и объявляла ложной цепочкой
    исправную разметку на семи витринах.
    """
    блок = _КРОШКИ_БЛОК.search(тело)
    if not блок:
        return [], ""
    звенья = [текст(к) for к in _ЗВЕНО.findall(блок.group(2))]
    звенья = [з for з in звенья if з and з not in ("/", "›", "»", "—", "-", "|")]
    весь = re.sub(r"\s+", " ", текст(блок.group(2)))
    return звенья, весь


def цепочки_разметки(тело: str) -> list[list[str]]:
    итог = []
    for кусок in _JSONLD.findall(тело):
        try:
            данные = json.loads(html.unescape(кусок).strip())
        except ValueError:
            continue
        for узел in (данные if isinstance(данные, list) else [данные]):
            if not isinstance(узел, dict):
                continue
            графы = узел.get("@graph") if isinstance(узел.get("@graph"), list) else [узел]
            for г in графы:
                if isinstance(г, dict) and г.get("@type") == "BreadcrumbList":
                    звенья = sorted(г.get("itemListElement") or [],
                                    key=lambda э: э.get("position", 0))
                    итог.append([str(э.get("name", "")).strip() for э in звенья])
    return итог


def карточка(домен: str) -> tuple[str, str]:
    """(адрес карточки, причина). Адрес берётся обходом, а не угадыванием."""
    for раздел in ("/catalog/", "/"):
        код, тело, причина = достать(f"https://{домен}{раздел}")
        if код != 200:
            continue
        ссылки = []
        for с in _ССЫЛКА_КАРТОЧКИ.findall(тело):
            # Два непустых сегмента — раздел и слаг. Считать СИМВОЛЫ «/» здесь
            # нельзя: у Yummy ссылки идут без завершающего слеша, и фильтр по
            # числу символов отбрасывал все 48 найденных карточек.
            сегменты = [к for к in с.split("/") if к]
            if с not in ссылки and len(сегменты) == 2:
                ссылки.append(с)
        if ссылки:
            # Карточка предпочтительнее раздела: у неё цепочка длиннее и
            # последнее звено — собственное название, то есть именно там и
            # живёт дефект «звено из заголовка». `/catalog/<раздел>` берётся
            # только если карточек не нашлось.
            карточки = [с for с in ссылки
                        if с.split("/")[1] in ("title", "anime")]
            return f"https://{домен}{(карточки or ссылки)[0]}", ""
    return "", причина or "ни каталог, ни главная не дали ссылок на карточки"


def проверить(домен: str) -> tuple[str, str]:
    """(знак, подробно). Знак: ок / НЕТ / — (не измерено)."""
    адрес, причина = карточка(домен)
    if not адрес:
        return "—  ", f"карточку не нашли: {причина}"
    код, тело, причина = достать(адрес)
    if код != 200 or not тело:
        return "—  ", f"{адрес} не ответила: {причина or код}"

    видимые, видимый_текст = видимые_крошки(тело)
    цепочки = цепочки_разметки(тело)
    # Печатается ПУТЬ, а не слаг: по одному слагу я сам проверил не тот адрес
    # (`/catalog/<слаг>/` вместо `/title/<слаг>/`) и получил 404, приняв его за
    # отсутствие разметки.
    хвост = адрес.split("//", 1)[-1].split("/", 1)[-1]
    if not цепочки and not видимые:
        # Главное решение этой приёмки. Пустая страница без крошек — не
        # дефект, а ПРАВИЛЬНЫЙ исход правила «только из видимых крошек»:
        # выдумывать цепочку из заголовка запрещено, поэтому там, где крошек
        # не видно, разметки быть и не должно. Первая редакция считала это
        # расхождением и обвиняла исправную выкладку.
        return "ок ", f"{хвост}: крошек нет ни в разметке, ни на странице — выдумывать нечего"
    if not цепочки:
        # Видимые крошки без разметки — упущенная разметка, а не ложь. Это
        # замечание: страница не обманывает, она просто не рассказывает.
        return "зам", (f"{хвост}: видимые крошки есть ({' › '.join(видимые)}), "
                       "а BreadcrumbList нет — разметка упущена, лжи нет")
    if not видимые:
        return "НЕТ", (f"{хвост}: разметка есть ({' › '.join(цепочки[0])}), "
                       "а видимых крошек на странице нет — это и есть ложная цепочка")

    разметка = цепочки[0]
    # Сверка по ВИДИМОМУ ТЕКСТУ контейнера, а не по списку элементов: звено
    # может быть и ссылкой, и простым текстом, а обещание разметки — про то,
    # что человек это на странице видит.
    лишние = [з for з in разметка if з and з not in видимый_текст]
    if лишние:
        return "НЕТ", (f"{хвост}: в разметке звенья, которых на странице нет: "
                       f"{лишние}; видно «{видимый_текст}»")
    место, по_порядку = -1, True
    for з in разметка:
        где = видимый_текст.find(з, место + 1)
        if где <= место:
            по_порядку = False
            break
        место = где
    if not по_порядку:
        return "НЕТ", (f"{хвост}: порядок звеньев разошёлся — разметка "
                       f"{' › '.join(разметка)}, видно «{видимый_текст}»")
    if len(цепочки) > 1:
        return "НЕТ", f"{хвост}: BreadcrumbList на странице {len(цепочки)}, а не один"
    return "ок ", f"{хвост}: {len(разметка)} звена, {' › '.join(разметка)}"


def домены(реестр: Path, только: list[str]) -> list[tuple[str, str]]:
    данные = json.loads(реестр.read_text(encoding="utf-8"))
    итог = []
    for я in данные.get("cells", []):
        if только and я.get("site_id") not in только:
            continue
        if я.get("domain"):
            итог.append((я["site_id"], я["domain"]))
    return sorted(итог)


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--registry", type=Path, default=РЕЕСТР)
    р.add_argument("--site", action="append", default=[],
                   help="site_id из реестра; можно несколько")
    опции = р.parse_args(аргв)

    цели = домены(опции.registry, опции.site)
    if not цели:
        print("в реестре нет таких ячеек — адреса не придумываются",
              file=sys.stderr)
        return 2

    расхождений = не_измерено = замечаний = 0
    for site_id, домен in цели:
        знак, подробно = проверить(домен)
        расхождений += знак == "НЕТ"
        не_измерено += знак == "—  "
        замечаний += знак == "зам"
        print(f"   [{знак}] {site_id:12} {домен:18} {подробно}")

    print(f"\nвитрин: {len(цели)}; расхождений: {расхождений}; "
          f"замечаний: {замечаний}; не измерено: {не_измерено}")
    if не_измерено:
        print("«не измерено» в расхождения не идёт: это факт о приёмке, "
              "а не о витрине.")
    return 1 if расхождений else 0


if __name__ == "__main__":
    raise SystemExit(главное())
