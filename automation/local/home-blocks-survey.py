#!/usr/bin/env python3
"""Порядок блоков живой главной и пересечения между ними — числом.

ЗАЧЕМ. Правило `docs/HOME_BLOCK_ORDER.md` требует перед правкой главной
проверить назначение блока, его приоритет, пересечение с соседями и поведение
при РЕАЛЬНОМ числе элементов. Первые два — суждение, их формулирует человек.
Последние два измеряются, и измеряет их этот инструмент.

ЧТО СЧИТАЕТ.

* порядок заголовков H2 в документе и смещение каждого в байтах — так видно,
  на каком байте начинается блок, за которым пришёл посетитель;
* число карточек произведений в каждом блоке;
* пересечение каждой пары блоков как доля общих работ к МЕНЬШЕМУ из двух:
  доля к большему прятала бы повтор маленького блока в большом.

ЧЕГО НЕ ДЕЛАЕТ. Не решает, какой блок важнее, и не предлагает порядок:
назначение блока в разметке не записано. Недостижимая витрина даёт «НЕ
ИЗМЕРЕНО» с причиной, а не ноль: ноль здесь означал бы «блоков нет».

    python3 automation/local/home-blocks-survey.py --url https://animedia.icu/
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.error
import urllib.request

#: Витрина `animedia.icu` считает непомеченные автоматические запросы роботами
#: и отвечает им 503 — это её защита, а не сбой. Префикс `factory-` выводит
#: наши пробы из-под предела (MOD-207), и подменять его на браузерный нельзя:
#: мы не браузер.
АГЕНТ = "factory-home-blocks-survey"
ПОРОГ_РАЗГОВОРА = 0.30
ПОРОГ_ДЕФЕКТА = 0.80


def загрузить(адрес: str, таймаут: float = 30.0) -> tuple[str, str]:
    """Возвращает (html, причина). Непустая причина означает НЕ ИЗМЕРЕНО."""
    зпр = urllib.request.Request(адрес, headers={"User-Agent": АГЕНТ})
    try:
        with urllib.request.urlopen(зпр, timeout=таймаут) as ответ:
            if ответ.status != 200:
                return "", f"код {ответ.status}"
            return ответ.read().decode("utf-8", "replace"), ""
    except urllib.error.HTTPError as сбой:
        return "", f"код {сбой.code}"
    except (urllib.error.URLError, TimeoutError, OSError) as сбой:
        return "", f"{type(сбой).__name__}: {сбой}"


def блоки(html_текст: str) -> list[dict]:
    """Блоки главной: заголовок, смещение и слаги работ внутри.

    Границей блока служит следующий H2, а не конец разметки секции: у главной
    блоки собираются разными методами и общей обёртки у них нет. Для порядка и
    пересечений этого достаточно, и это честнее, чем угадывать вложенность.
    """
    заголовки = [(м.start(), re.sub(r"<[^>]+>", "", м.group(1)).strip())
                 for м in re.finditer(r"<h2[^>]*>(.*?)</h2>", html_текст, re.S)]
    if not заголовки:
        return []
    границы = заголовки + [(len(html_текст), "")]
    итог = []
    for i in range(len(заголовки)):
        кусок = html_текст[границы[i][0]:границы[i + 1][0]]
        слаги = list(dict.fromkeys(re.findall(r"/title/([a-z0-9\-]+)/", кусок)))
        ключи = list(dict.fromkeys(re.findall(r'data-block-key="([^"]+)"', кусок)))
        итог.append({"заголовок": заголовки[i][1], "смещение": заголовки[i][0],
                     "работ": len(слаги), "слаги": слаги, "ключи": ключи})
    return итог


def пересечения(список: list[dict]) -> list[dict]:
    найдено = []
    for i, а in enumerate(список):
        for б in список[i + 1:]:
            if not а["слаги"] or not б["слаги"]:
                continue
            общие = set(а["слаги"]) & set(б["слаги"])
            if not общие:
                continue
            доля = len(общие) / min(len(а["слаги"]), len(б["слаги"]))
            if доля < ПОРОГ_РАЗГОВОРА:
                continue
            найдено.append({
                "первый": а["заголовок"], "второй": б["заголовок"],
                "общих": len(общие), "доля": round(доля, 3),
                "исход": "дефект" if доля >= ПОРОГ_ДЕФЕКТА else "разговор",
            })
    return sorted(найдено, key=lambda з: -з["доля"])


def главная(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--url", required=True)
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    html_текст, причина = загрузить(а.url)
    if причина:
        итог = {"url": а.url, "исход": "НЕ ИЗМЕРЕНО", "причина": причина}
        print(json.dumps(итог, ensure_ascii=False, indent=1) if а.json
              else f"НЕ ИЗМЕРЕНО {а.url}: {причина}")
        return 2
    список = блоки(html_текст)
    пары = пересечения(список)
    итог = {"url": а.url, "исход": "измерено", "байт": len(html_текст),
            "блоков": len(список),
            "блоки": [{к: з[к] for к in ("заголовок", "смещение", "работ", "ключи")}
                      for з in список],
            "пересечения": пары}
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
        return 1 if any(п["исход"] == "дефект" for п in пары) else 0
    print(f"{а.url} — байт {len(html_текст)}, блоков {len(список)}")
    for з in список:
        ключи = (" [" + ", ".join(з["ключи"]) + "]") if з["ключи"] else ""
        print(f"  {з['смещение']:8d}  работ {з['работ']:4d}  {з['заголовок']}{ключи}")
    if not пары:
        print("пересечений от 30% нет")
    for п in пары:
        print(f"  {п['исход']:9s} {п['доля']:.0%} ({п['общих']}): "
              f"«{п['первый']}» и «{п['второй']}»")
    return 1 if any(п["исход"] == "дефект" for п in пары) else 0


if __name__ == "__main__":
    sys.exit(главная())
