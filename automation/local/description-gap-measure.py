#!/usr/bin/env python3
"""Пробел описаний в доставленном каталоге: доля, состав и чем его можно закрыть.

Только чтение снимков данных витрин (`<data>/*-details.json`) и публичных
страниц. Ничего не пишет.

ЗАЧЕМ. MOD-56 (P1) держится на числе «около четверти каталога без описания»,
измеренном 16.10 с двух сторон. Решение между «наполнить» и «убрать из
индексации» названо нетехническим и ждёт владельца. Этот проход отвечает на
три вопроса, без которых выбор делается на ощупь:

1. **растёт ли пробел** — доля и абсолютное число в СВЕЖЕМ снимке;
2. **чем он закрывается без выдумывания** — у скольких записей без описания
   есть собственные факты поставщика (жанры, год, оригинальное название,
   оценки): такой записи можно дать страницу с фактами, не придумав ни слова;
3. **кого затронет исключение из индексации** — сколько записей без описания
   играбельны и сколько добавлены в последние месяцы. Исключить свежую
   играбельную запись дороже, чем старую неигравшую.

Порог «описание есть» — ``ПОРОГ_ОПИСАНИЯ`` знаков. Он назван, а не угадан:
пустая строка, одно слово и обрывок в десяток знаков описанием не являются, а
медиана непустых описаний в снимке Lords 21.10 — 335 знаков.

    python3 automation/local/description-gap-measure.py
    python3 automation/local/description-gap-measure.py --snapshot <путь> --json

Коды: 0 — пробела нет; 1 — есть; 2 — ни один снимок не прочитан.
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import statistics
import sys

#: Короче этого — не описание. 40 знаков это примерно пять слов.
ПОРОГ_ОПИСАНИЯ = 40

#: Снимки, которые проход читает по умолчанию. Один снимок обслуживает
#: несколько витрин: каталог фильмов общий у Lords и Zona, каталог аниме — у
#: Animedia и AnimeGo, поэтому семейства названы вместе с домéном снимка.
СНИМКИ = {
    "фильмы и сериалы (Lords, Zona)":
        "/srv/lordserial33-biz/data/lords-02-details.json",
    "аниме (Animedia, AnimeGo)":
        "/srv/animedia-space/data/animedia-02-details.json",
}

#: Факты поставщика, которыми страницу можно наполнить, ничего не придумывая.
ФАКТЫ = ("genres", "year", "original_name", "imdb_rating", "ratings_by_source",
         "type", "sources", "poster_url")


def описание_есть(запись: dict) -> bool:
    return len((запись.get("description") or "").strip()) >= ПОРОГ_ОПИСАНИЯ


def факты_записи(запись: dict) -> set[str]:
    """Какие из названных фактов у записи действительно есть."""
    найдено = set()
    for поле in ФАКТЫ:
        значение = запись.get(поле)
        if isinstance(значение, (list, tuple, dict)):
            if значение:
                найдено.add(поле)
        elif isinstance(значение, str):
            if значение.strip():
                найдено.add(поле)
        elif значение:
            найдено.add(поле)
    return найдено


def разобрать(снимок: dict, *, каталог: dict | None = None) -> dict:
    """Замер по одному снимку подробностей. Чистая функция."""
    подробности = снимок.get("details") or {}
    if not подробности:
        return {"ошибка": "в снимке нет поля details"}
    по_слагу = {з.get("slug"): з
                for з in ((каталог or {}).get("items") or [])}

    без_описания = []
    длины = []
    for ключ, з in подробности.items():
        if описание_есть(з):
            длины.append(len((з["description"] or "").strip()))
        else:
            без_описания.append((ключ, з))

    всего = len(подробности)
    факты = collections.Counter()
    бедных = 0
    играбельных = 0
    по_месяцам = collections.Counter()
    for ключ, з in без_описания:
        свои = факты_записи(з)
        for поле in свои:
            факты[поле] += 1
        if not (свои & {"genres", "imdb_rating", "ratings_by_source"}):
            бедных += 1
        if з.get("playable"):
            играбельных += 1
        дата = ((по_слагу.get(ключ) or {}).get("published_at") or "")[:7]
        if дата:
            по_месяцам[дата] += 1

    return {
        "записей": всего,
        "без_описания": len(без_описания),
        "доля_без_описания": round(len(без_описания) / всего * 100, 1),
        "длина_описания_медиана": (
            round(statistics.median(длины)) if длины else 0),
        "факты_у_записей_без_описания": dict(факты.most_common()),
        "без_описания_и_без_фактов": бедных,
        "играбельных_без_описания": играбельных,
        "добавлены_по_месяцам": dict(sorted(по_месяцам.items(),
                                            reverse=True)[:6]),
        "собран": снимок.get("catalog_built_at") or "—",
    }


def прочитать(путь: str) -> dict:
    try:
        with open(путь, encoding="utf-8") as ф:
            return json.load(ф)
    except (OSError, json.JSONDecodeError):
        return {}


def каталог_рядом(путь_подробностей: str) -> dict:
    """Снимок каталога того же семейства — для даты добавления записи."""
    основа = путь_подробностей.rsplit("-details.json", 1)[0]
    for кандидат in (f"{основа}-catalog.json",
                     *glob.glob(f"{основа.rsplit('/', 1)[0]}/*-catalog.json")):
        d = прочитать(кандидат)
        if d.get("items"):
            return d
    return {}


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--snapshot", action="append", default=[])
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    задания = ([(п, п) for п in а.snapshot] if а.snapshot
               else list(СНИМКИ.items()))
    итоги = []
    for имя, путь in задания:
        снимок = прочитать(путь)
        if not снимок:
            итоги.append({"каталог": имя, "путь": путь,
                          "ошибка": "снимок не прочитан"})
            continue
        замер = разобрать(снимок, каталог=каталог_рядом(путь))
        замер.update({"каталог": имя, "путь": путь})
        итоги.append(замер)

    if а.json:
        print(json.dumps({"снимков": len(итоги), "каталоги": итоги},
                         ensure_ascii=False, indent=2))
    else:
        for и in итоги:
            print(f"\n=== {и['каталог']}")
            if и.get("ошибка"):
                print(f"   НЕ ИЗМЕРЕНО: {и['ошибка']} ({и['путь']})")
                continue
            print(f"   снимок собран {и['собран']}, записей {и['записей']}")
            print(f"   без описания (короче {ПОРОГ_ОПИСАНИЯ} знаков):"
                  f" {и['без_описания']} ({и['доля_без_описания']} %);"
                  f" медиана непустого описания"
                  f" {и['длина_описания_медиана']} знаков")
            print(f"   из них играбельны: {и['играбельных_без_описания']}")
            print(f"   ни жанров, ни оценок: {и['без_описания_и_без_фактов']}"
                  f" — остальным страницу можно наполнить фактами поставщика,"
                  f" ничего не придумывая")
            for поле, с in и["факты_у_записей_без_описания"].items():
                доля = с / max(и["без_описания"], 1) * 100
                print(f"      {поле:22} {с:7} ({доля:5.1f} %)")
            if и["добавлены_по_месяцам"]:
                print("   добавлены в каталог:",
                      ", ".join(f"{м} — {с}"
                                for м, с in и["добавлены_по_месяцам"].items()))

    if all(и.get("ошибка") for и in итоги):
        return 2
    return 1 if any(и.get("без_описания") for и in итоги) else 0


if __name__ == "__main__":
    sys.exit(main())
