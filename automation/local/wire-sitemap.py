def подключить_адаптер(репо: pathlib.Path, витрина: pathlib.Path,
                       разделы: list[str], ядро: pathlib.Path
                       ) -> tuple[list[str], dict[pathlib.Path, bytes]]:
    """Подключить карту витрине на ОБЩЕМ ядре. Ядро остаётся неприкосновенным.

    Возвращает `(перечень правок, что записать)`. Запись отложена, чтобы
    `--dry-run` действительно ничего не менял, а не менял половину.
    """
    сделано: list[str] = []
    записать: dict[pathlib.Path, bytes] = {}
    текст_ядра = ядро.read_text(encoding="utf-8")
    # Ядро обязано УЖЕ уметь отдавать карту. Не умеет — подключать нечего, и
    # это задача производителя ядра, а не этого репозитория.
    чего_нет = ("SITEMAP_DIR" if ОБЪЯВЛЕНИЕ not in текст_ядра
                else "маршрута /sitemap.xml" if "/sitemap.xml" not in текст_ядра
                else "")
    if чего_нет:
        raise ОтказИнструмента(
            f"{репо.name}: ядро {ядро.name} не умеет отдавать карту — нет "
            f"{чего_нет}. Это задача производителя ядра: править его в "
            "репозитории сайта запрещено замком версий "
            "(verified_against: git)")

    т = витрина.read_text(encoding="utf-8")
    if "lords_sitemap_layer" in т:
        return сделано, записать
    if "def main() -> int:" not in т:
        raise ОтказИнструмента(
            f"{репо.name}: в лаунчере {витрина.name} нет main() — точки "
            "подключения нет, вслепую не правлю")
    блок = АДАПТЕР_РАЗДЕЛЫ.format(разделы=", ".join(f'"{р}"' for р in разделы))
    т = т.replace("def main() -> int:", блок + "def main() -> int:", 1)
    # Запуск — ПОСЛЕ слоёв и ПЕРЕД `return ядро.main()`: сервер стартует в
    # `main()` ядра, и завести сборщик после него уже нельзя.
    if "    return ядро.main()" not in т:
        raise ОтказИнструмента(
            f"{репо.name}: в лаунчере нет возврата `return ядро.main()` — "
            "места для запуска сборщика не нашлось")
    т = т.replace("    return ядро.main()", АДАПТЕР_ЗАПУСК + "    return ядро.main()", 1)
    записать[витрина] = т.encode("utf-8")
    сделано.append(f"{витрина.name}: разделы объявлены, сборщик заводится слоем")

    слой = (ШАБЛОН / "lords_sitemap_layer.py").read_bytes()
    цель = репо / "src" / "lords_sitemap_layer.py"
    if (цель.read_bytes() if цель.is_file() else b"") != слой:
        записать[цель] = слой
        сделано.append("lords_sitemap_layer.py: общий слой семейства из шаблона")

    режим = репо / "src" / "indexing_mode.py"
    if режим.is_file():
        тр = режим.read_text(encoding="utf-8")
        if "lords_sitemap_layer" not in тр:
            if "    if sitemap:" not in тр:
                raise ОтказИнструмента(
                    f"{репо.name}: в indexing_mode.robots_txt нет ветки "
                    "sitemap — ссылку вслепую не ставлю")
            тр = тр.replace("    if sitemap:",
                            ССЫЛКА_В_ROBOTS + "    if sitemap:", 1)
            записать[режим] = тр.encode("utf-8")
            сделано.append("indexing_mode.py: Sitemap: только при готовой карте")
    return сделано, записать


def разделы_блок(разделы: list[str]) -> str:
    строки = ", ".join(f'"{р}"' for р in разделы)
    return f'''
#: Разделы, попадающие в карту сайта. Перечень ЯВНЫЙ и ИЗМЕРЕННЫЙ: в карту
#: идёт только то, что витрина действительно отдаёт кодом 200. У сайтов
#: семейства наборы РАЗНЫЕ — у одного есть `/anime/` и `/dorama/`, у другого
#: те же адреса отвечают 404, — поэтому раздел по аналогии не добавляется.
РАЗДЕЛЫ_КАРТЫ = ({строки},)
'''


def главная(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo", required=True)
    p.add_argument("--sections", nargs="+", required=True,
                   help="разделы ЭТОГО сайта, проверенные ответом 200")
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args(argv)

    репо = pathlib.Path(args.repo)
    if not (репо / "config" / "site.json").is_file():
        print(f"{репо}: не похоже на репозиторий сайта", file=sys.stderr)
        return 2
    cfg = (репо / "config" / "site.json").read_text(encoding="utf-8")
    точка = re.search(r'"entrypoint"\s*:\s*"([^"]+)"', cfg)
    if not точка:
        print("в config/site.json нет entrypoint", file=sys.stderr)
        return 2
    витрина = репо / "src" / точка.group(1)
    лаунчер = репо / "run.py"
    if not витрина.is_file():
        print(f"нет витрины {витрина}", file=sys.stderr)
        return 2

    сделано: list[str] = []
    отложено: dict[pathlib.Path, bytes] = {}
    т = витрина.read_text(encoding="utf-8")
    if "запустить_карту" in т or "lords_sitemap_layer" in т:
        print(f"{репо.name}: карта уже подключена — ничего не меняю")
        return 0
    # АДАПТЕР НАД ОБЩИМ ЯДРОМ — отдельный случай, и правка ядра здесь
    # запрещена правилами самого репозитория: `src/lords-frontend.py` совпадает
    # с ядром соседа байт в байт и закреплён в `pins.lock.json` с
    # происхождением `verified_against: git`; его `AGENTS.md` требует менять
    # ядро отдельной задачей и отдельным коммитом производителя. Измерено
    # 2026-10-04: так устроены lordfilm47.space и lordserial33.biz, а
    # lordserials22.info, 1lordserials1.online, zonafilm.space и
    # zonafilm12.site — монолиты, где точка входа и есть рантайм.
    ядро = репо / "src" / "lords-frontend.py"
    адаптер = (ОБЪЯВЛЕНИЕ not in т and ядро.is_file() and витрина != ядро
               and ОБЪЯВЛЕНИЕ in ядро.read_text(encoding="utf-8"))
    if адаптер:
        # Прежде инструмент здесь отказывал ЦЕЛИКОМ, и отказ был слишком
        # широким: ядро уже умеет ОТДАВАТЬ карту (маршрут и `SITEMAP_DIR` в
        # нём есть), а не хватало ровно того, что лежит в файлах САМОГО САЙТА
        # — сборщика, перечня разделов, переменной каталога и ссылки в
        # robots.txt. Измерено 2026-10-04 на выложенном lordserial33.biz:
        # `/sitemap.xml` отдавал 404 молча, потому что файлы никто не писал.
        print(f"{репо.name}: точка входа {витрина.name} — АДАПТЕР над общим "
              f"ядром {ядро.name}; ядро не правится, подключение идёт слоем "
              "в файлах сайта")
        try:
            правки, отложено = подключить_адаптер(репо, витрина, args.sections,
                                                  ядро)
        except ОтказИнструмента as отказ:
            print(str(отказ), file=sys.stderr)
            return 4
        if not правки:
            print(f"{репо.name}: карта уже подключена слоем — ничего не меняю")
            return 0
        сделано += правки
    else:
        for якорь, что in ((ОБЪЯВЛЕНИЕ, "SITEMAP_DIR"), (МАРШРУТ_СТАРЫЙ, "маршрут карты"),
                           (ROBOTS_СТАРЫЙ, "_тело_robots"),
                           (ЗАГОЛОВОК_СТАРЫЙ, "отдача заголовка")):
            if якорь not in т:
                print(f"{репо.name}: нет точки вставки «{что}» — правка не "
                      "применяется вслепую", file=sys.stderr)
                return 3
        т = т.replace(ОБЪЯВЛЕНИЕ, ОБЪЯВЛЕНИЕ + ДОМЕН_КАРТЫ + разделы_блок(args.sections), 1)
        т = т.replace(МАРШРУТ_СТАРЫЙ, МАРШРУТ_НОВЫЙ, 1)
        т = т.replace(ROBOTS_СТАРЫЙ, ПО_ПУТИ.strip("\n") + "\n\n\n" + ROBOTS_НОВЫЙ, 1)
        т = т.replace(ЗАГОЛОВОК_СТАРЫЙ, ЗАГОЛОВОК_НОВЫЙ, 1)
        м = re.search(r"^(    import time as _time\n)", т, re.M)
        if not м:
            print(f"{репо.name}: нет точки запуска в main()", file=sys.stderr)
            return 3
        т = т[:м.start(1)] + ЗАПУСК + т[м.start(1):]
        отложено[витрина] = т.encode("utf-8")
        сделано.append(
            f"{витрина.name}: разделы, robots, маршрут, заголовок по пути, запуск")

    # КАТАЛОГ КАРТЫ: два законных способа, и выбирается тот, который у сайта
    # есть. У части лаунчеров есть функция дополнений — там правило выводится
    # из `--data-dir`. У остальных (193 строки против 236) переменные
    # объявляет `config/site.json: environment`, а `<data>` подставляет
    # `environment()`. Результат один; подменять одну форму другой незачем.
    л = лаунчер.read_text(encoding="utf-8")
    правка_лаунчера = None
    правка_пакета = False
    уже_есть = "LORDS_SITEMAP_DIR" in л or "LORDS_SITEMAP_DIR" in cfg
    if not уже_есть:
        if "def дополнения(config: dict) -> dict:" in л:
            якорь = '    доп["LORDS_INDEXING_RELEASE_PERMITS_OPEN"] = ('
            if якорь not in л:
                print(f"{репо.name}: в лаунчере есть дополнения, но нет якоря "
                      "режима индексации — вслепую не правлю", file=sys.stderr)
                return 3
            правка_лаунчера = л.replace(
                "def дополнения(config: dict) -> dict:",
                "def дополнения(config: dict, данные: Path | None = None) -> dict:", 1)
            правка_лаунчера = правка_лаунчера.replace(якорь, '''    # Каталог карты сайта выводится из каталога ДАННЫХ, а не объявляется в
    # пакете: правило одно на все сайты семейства, и забыть его при заведении
    # следующего сайта нечем. Писать туда вправе только сама витрина — это
    # единственный путь, открытый её юнитом на запись.
    if данные is not None:
        доп["LORDS_SITEMAP_DIR"] = str(данные / "sitemap")

''' + якорь, 1)
            правка_лаунчера = правка_лаунчера.replace(
                "    env.update(дополнения(config))",
                "    env.update(дополнения(config, data))", 1)
            сделано.append("run.py: LORDS_SITEMAP_DIR из --data-dir")
        elif '"environment"' in cfg:
            правка_пакета = True
            сделано.append("config/site.json: LORDS_SITEMAP_DIR = <data>/sitemap")
        else:
            print(f"{репо.name}: ни функции дополнений в лаунчере, ни раздела "
                  "environment в пакете — подключать нечем", file=sys.stderr)
            return 3

    общий = (ШАБЛОН / "seo_layer.py").read_bytes()
    цель = репо / "src" / "seo_layer.py"
    # Модуля может не быть вовсе — тогда он доставляется, а не считается
    # препятствием: сборщик карты живёт именно в нём, и файл у семейства один.
    прежний = цель.read_bytes() if цель.is_file() else b""
    if прежний != общий:
        # ДОСТАВКА ИДЁТ ТОЙ ЖЕ ПАЧКОЙ, что остальные правки. Прежде она стояла
        # отдельной строкой после них, и первый же отказ на ней (файл помечен
        # только для чтения — `-r--r--r--`, так защищены копии общих модулей)
        # оставил репозиторий в половине правок: лаунчер уже звал слой, а
        # сборщика в модуле не было. Половина правок хуже ни одной.
        отложено[цель] = общий
        сделано.append("seo_layer.py: общий модуль семейства из шаблона"
                       + ("" if прежний else " (прежде отсутствовал)"))

    print(f"{репо.name}: разделы {' '.join(args.sections)}")
    for строка in сделано:
        print("   ", строка)
    if args.dry_run:
        print("сухой прогон: файлы не менялись")
        return 0
    # Все правки файлов сайта — одной пачкой: половина применённых правок
    # хуже ни одной, потому что витрина тогда ссылается на то, чего нет.
    #
    # Сначала проверяется ЗАПИСЫВАЕМОСТЬ всех целей и только потом пишется
    # первая: копии общих модулей помечены `-r--r--r--`, и отказ на последнем
    # файле уже однажды оставил репозиторий в половине правок.
    непишущиеся = [str(п) for п in отложено
                   if п.exists() and not os.access(п, os.W_OK)]
    if непишущиеся:
        print(f"{репо.name}: файлы помечены только для чтения: "
              + ", ".join(непишущиеся)
              + ". Это копии ОБЩИХ модулей семейства; их обновление — "
              "доставка уже сделанной общей правки (AGENTS.md, п. 3) и "
              "требует снятия отметки осознанно:\n   chmod u+w "
              + " ".join(непишущиеся), file=sys.stderr)
        return 5
    for путь, байты in отложено.items():
        путь.write_bytes(байты)
    if правка_лаунчера is not None:
        лаунчер.write_text(правка_лаунчера, encoding="utf-8")
    if правка_пакета:
        import json as _json

        путь_пакета = репо / "config" / "site.json"
        данные = _json.loads(путь_пакета.read_text(encoding="utf-8"))
        данные.setdefault("environment", {})["LORDS_SITEMAP_DIR"] = "<data>/sitemap"
        путь_пакета.write_text(
            _json.dumps(данные, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
    цель.write_bytes(общий)
    print("дальше обязателен прогон checks/run.sh в этом репозитории")
    return 0


