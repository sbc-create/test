class ОтказИнструмента(RuntimeError):
    """Инструмент остановился с названной причиной. Вслепую он не правит."""


def куда_общий_модуль(репо: pathlib.Path) -> pathlib.Path:
    """Куда класть общий `seo_layer`: туда, откуда его ИМПОРТИРУЕТ рантайм.

    У монолитов и адаптеров в `src/` это `src/seo_layer.py`. У витрины на
    ЗАКРЕПЛЁННОМ артефакте (`config/runtime.json: release_dir`) рантайм лежит в
    `template/<релиз>/`, и этот каталог стоит ПЕРВЫМ в `sys.path` — копия,
    положенная в `src/`, не импортировалась бы никогда, а витрина продолжала бы
    брать прежний модуль без сборщика. Сам артефакт при этом не трогается:
    `pins.lock.json` закрепляет отпечаток только `lords-frontend.py`.
    """
    runtime = репо / "config" / "runtime.json"
    if runtime.is_file():
        try:
            каталог = json.loads(runtime.read_text(encoding="utf-8")).get("release_dir")
        except ValueError:
            каталог = None
        if каталог:
            рядом = репо / "template" / str(каталог) / "seo_layer.py"
            if рядом.is_file():
                return рядом
    return репо / "src" / "seo_layer.py"


