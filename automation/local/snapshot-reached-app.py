#!/usr/bin/env python3
"""Доехал ли снимок каталога ДО ПРИЛОЖЕНИЯ, а не просто лёг на диск.

    python3 automation/local/snapshot-reached-app.py            # все ячейки узла
    python3 automation/local/snapshot-reached-app.py lords-05 …  # выбранные

Зачем. «Файл доставлен» и «витрина его загрузила» — разные утверждения, и
между ними помещается дефект, который не виден ничем другим. Опись ячеек
объявляет режим перезагрузки: при `restart` установка каталога перезапускает
юнит (`factory/cell/runtime.py`: `нужен_перезапуск = (reload != "mtime")`), при
`mtime` — не перезапускает, рассчитывая, что рантайм перечитает сам. Измерено
2026-10-18 линией шаблонов: `mtime` объявлен у тринадцати ячеек из двадцати
одной, а ядро по mtime НЕ перечитывает — `Подробности.mtime` ставится один раз
и ни с чем не сравнивается. Перечитывание существует только наложением
отдельного сайта (`lords_snapshot_reload.py` у lordserials22.info; причина в
его шапке — замер 2026-10-06, 502 у nginx четыре раза в час от перезапусков).

Что сравнивается, и оба факта читаются, ничего не меняя:

  ЗАГРУЖЕНО   `catalog_revision` из подробного `/healthz` по петле, а если
              его там нет — заголовок `X-Catalog-Revision` обычного ответа:
              рантайм Zona отдаёт его всегда (измерено 2026-10-18);
  НА ДИСКЕ    `revision` из файла по пути `catalog_path` того же ответа, а
              если путь не назван — по `runtime.data_dir` описи ячеек.

Расхождение означает «снимок лежит, приложение его не видит». Совпадение
означает ровно совпадение: доставка могла просто не приносить нового снимка.
Поэтому печатается и время запуска процесса — если он старше файла, значит
перечитывание РАБОТАЕТ, а если младше, совпадение объясняется перезапуском.

Ячейка, у которой не нашлось НИ ОДНОГО из двух путей, помечается «НЕ ИЗМЕРЕНО»
и считается в отдельную графу: отсутствие способа спросить — это пробел
наблюдаемости (MOD-80), а не исправность. Два пути здесь именно потому, что с
одним инструмент назвал неизмеримыми пять ячеек, а неизмеримых оказалось две:
у трёх Zona ревизия спрашивается заголовком.

Только чтение. Значения путей печатаются: это внутренний инструмент, он
ходит по петле и в отчёт для владельца не идёт.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
import subprocess
import sys

КАТАЛОГ_ЯЧЕЕК = pathlib.Path("/etc/nginx/cells")
ЮТС = dt.timezone.utc


def порт_ячейки(имя: str) -> str:
    файл = КАТАЛОГ_ЯЧЕЕК / f"{имя}.upstream"
    try:
        т = файл.read_text(encoding="utf-8")
    except OSError:
        return ""
    м = re.search(r"server\s+127\.0\.0\.1:(\d+)", т)
    return м.group(1) if м else ""


def все_ячейки() -> list[str]:
    try:
        файлы = sorted(КАТАЛОГ_ЯЧЕЕК.glob("*.upstream"))
    except OSError:
        return []
    return [ф.stem for ф in файлы]


def заголовки_ответа(порт: str, таймаут: int) -> dict:
    """Заголовки обычного ответа витрины по петле.

    Второй путь измерения, и появился он не из симметрии. Линия Zona измерила
    2026-10-18, что её рантайм отдаёт `X-Catalog-Revision` на КАЖДЫЙ ответ, и
    это ревизия ЗАГРУЖЕННОГО снимка, а не содержимое файла. Проверено отсюда
    независимо тем же днём: у zona-01/02/03 заголовок и файл совпадают
    (`ab5cd6f7b28853719bd65890edcce39a`, файл от 04:05Z).

    Без этого пути инструмент объявлял «НЕ ИЗМЕРЕНО» там, где измерить можно —
    просто не тем эндпоинтом. Такой вывод хуже пробела: он указывает на риск,
    которого нет, и прячет пробел там, где он настоящий.
    """
    г = subprocess.run(["curl", "-fsS", "-D", "-", "-o", "/dev/null",
                        "--max-time", str(таймаут),
                        f"http://127.0.0.1:{порт}/"],
                       capture_output=True, text=True)
    з: dict = {}
    for с in (г.stdout or "").splitlines():
        if ":" in с:
            к, _, v = с.partition(":")
            з[к.strip().lower()] = v.strip()
    return з


def путь_по_данным(имя: str) -> str:
    """Файл каталога по описи ячеек, когда ответ его не называет.

    Заголовок отдаёт ревизию, но не путь, поэтому путь берётся из
    `config/site-cells.json`: `runtime.data_dir` и файл `<site_id>-catalog.json`
    в нём — то же имя, которое кладёт доставка (`factory/cell/runtime.py`).
    Выдумывать путь нельзя: ошибка в нём дала бы ложное «РАСХОЖДЕНИЕ».
    Файла нет — возвращается пусто, и ячейка честно останется неизмеренной.
    """
    реестр = (pathlib.Path(__file__).resolve().parents[2] / "config"
              / "site-cells.json")
    try:
        документ = json.loads(реестр.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    ячейки = документ.get("cells") or []
    ячейки = list(ячейки.values()) if isinstance(ячейки, dict) else ячейки
    for я in ячейки:
        if str(я.get("site_id") or "") != имя:
            continue
        каталог = str((я.get("runtime") or {}).get("data_dir") or "")
        if not каталог:
            return ""
        путь = pathlib.Path(каталог) / f"{имя}-catalog.json"
        return str(путь) if путь.is_file() else ""
    return ""


def ответ_healthz(порт: str, таймаут: int) -> dict:
    г = subprocess.run(["curl", "-fsS", "--max-time", str(таймаут),
                        f"http://127.0.0.1:{порт}/healthz"],
                       capture_output=True, text=True)
    if г.returncode != 0:
        return {}
    try:
        return json.loads(г.stdout or "")
    except ValueError:
        return {}


def ревизия_файла(путь: str) -> tuple[str, str]:
    """(revision, когда файл записан) или ("", причина).

    Ревизия может лежать и в начале файла, и в конце: порядок ключей у разных
    издателей разный. Сперва дешёвые края, и только если не нашлось — полный
    проход. Файл крупный (20 МиБ), но это делается раз на ячейку.
    """
    if not путь:
        return ("", "путь не назван")
    п = pathlib.Path(путь)
    if not п.is_file():
        return ("", "файла нет")
    образец = re.compile(r'"revision"\s*:\s*"([^"]+)"')
    try:
        with п.open("rb") as ф:
            м = образец.search(ф.read(8192).decode("utf-8", "replace"))
            if not м:
                ф.seek(max(0, п.stat().st_size - 8192))
                м = образец.search(ф.read().decode("utf-8", "replace"))
            if not м:
                ф.seek(0)
                м = образец.search(ф.read().decode("utf-8", "replace"))
    except OSError as пр:
        return ("", f"не читается: {пр}")
    if not м:
        return ("", "в файле нет revision")
    когда = dt.datetime.fromtimestamp(п.stat().st_mtime, ЮТС)
    return (м.group(1), f"{когда:%Y-%m-%d %H:%M}Z")


def разобрать_время(значение: str):
    try:
        return dt.datetime.fromisoformat((значение or "").replace("Z", "+00:00"))
    except ValueError:
        return None


def проверить(имя: str, таймаут: int) -> dict:
    порт = порт_ячейки(имя)
    if not порт:
        return {"ячейка": имя, "вывод": "upstream не прочитан"}
    отв = ответ_healthz(порт, таймаут)
    загружено = str(отв.get("catalog_revision") or "")
    путь_каталога = str(отв.get("catalog_path") or "")
    откуда = "healthz"
    if not загружено:
        # Второй путь, прежде чем сдаваться: заголовок обычного ответа. Так
        # измеряется Zona — её рантайм отдаёт X-Catalog-Revision всегда.
        загружено = заголовки_ответа(порт, таймаут).get("x-catalog-revision", "")
        откуда = "заголовок ответа"
    if not загружено:
        если_пусто = ("healthz не ответил или не JSON" if not отв
                      else "в healthz есть "
                           + (", ".join(sorted(отв)[:5]) or "ответ пуст"))
        return {"ячейка": имя, "порт": порт,
                "вывод": f"НЕ ИЗМЕРЕНО: ни catalog_revision, ни "
                         f"X-Catalog-Revision; {если_пусто}"}
    if not путь_каталога:
        путь_каталога = путь_по_данным(имя)
    на_диске, когда = ревизия_файла(путь_каталога)
    if not на_диске:
        return {"ячейка": имя, "порт": порт,
                "вывод": f"НЕ ИЗМЕРЕНО: {когда}"}
    запуск = разобрать_время(str(отв.get("process_start_time") or ""))
    файл_время = разобрать_время(когда.replace("Z", "+00:00").replace(" ", "T"))
    совпало = загружено[:32] == на_диске[:32]
    если = "перезапуск" if (запуск and файл_время and запуск > файл_время) else \
        "процесс старше файла" if (запуск and файл_время) else "время запуска неизвестно"
    return {"ячейка": имя, "порт": порт, "загружено": загружено[:32],
            "на_диске": на_диске[:32], "файл": когда,
            "объяснение": если if откуда == "healthz" else f"{если}, {откуда}",
            "вывод": "снимок у приложения" if совпало else
                     "РАСХОЖДЕНИЕ: снимок лежит, приложение его не видит"}


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("cells", nargs="*")
    р.add_argument("--timeout", type=int, default=8)
    а = р.parse_args(аргв)
    список = а.cells or все_ячейки()
    if not список:
        print(f"ячеек не найдено ({КАТАЛОГ_ЯЧЕЕК})", file=sys.stderr)
        return 2
    расхождений = неизмеримых = 0
    print(f"{'ячейка':14} {'порт':5} {'файл записан':18} {'почему так':22} вывод")
    for имя in список:
        и = проверить(имя, а.timeout)
        if и["вывод"].startswith("РАСХОЖДЕНИЕ"):
            расхождений += 1
        elif "НЕ ИЗМЕРЕНО" in и["вывод"] or "не ответил" in и["вывод"] \
                or "не прочитан" in и["вывод"]:
            неизмеримых += 1
        print(f"{и['ячейка']:14} {и.get('порт', '—'):5} "
              f"{и.get('файл', '—'):18} {и.get('объяснение', '—'):22} "
              f"{и['вывод']}")
    print(f"\nснимок лежит, но приложение его не видит: {расхождений}")
    print(f"измерить нельзя (ни catalog_revision в /healthz, ни заголовка "
          f"X-Catalog-Revision): {неизмеримых} — это пробел наблюдаемости, "
          f"а не исправность (MOD-80)")
    print("Совпадение ревизий само по себе не доказывает перечитывания: "
          "смотрите графу «почему так» — при «перезапуск» совпадение "
          "объясняется им.")
    return 1 if расхождений else 0


if __name__ == "__main__":
    raise SystemExit(главная())
