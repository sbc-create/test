#!/usr/bin/env python3
"""Доехал ли снимок каталога ДО ПРИЛОЖЕНИЯ, а не просто лёг на диск.

    python3 automation/local/snapshot-reached-app.py            # все ячейки узла
    python3 automation/local/snapshot-reached-app.py lords-05 …  # выбранные

Зачем. «Файл доставлен» и «витрина его загрузила» — разные утверждения, и
между ними помещается дефект, который не виден ничем другим. Опись ячеек
объявляет режим перезагрузки: при `restart` установка каталога перезапускает
юнит (`factory/cell/runtime.py`: `нужен_перезапуск = (reload != "mtime")`), при
`mtime` — не перезапускает, рассчитывая, что рантайм перечитает сам.

ПЕРЕЧИТЫВАЕТ ЛИ ЯДРО — вопрос поставлен неверно, и это выяснилось измерением
2026-10-18. Ядро шаблона по mtime не перечитывает, это так; но витрины
исполняют НЕ ядро, а наложение сайта, и перечитывание живёт в нём. Проверять
надо `/proc/<pid>/cmdline`, а не раскладку, которую ожидаешь увидеть:

  lords-03 запускает `releases/<выпуск>/overlay/main.py`, наложение несёт
  `overlay/freshness.py` (следит за `(st_mtime_ns, size)` обоих файлов), и по
  её `/__site` видно `reloads_since_start: 3`, `last_reload_at
  2026-10-18T04:06:03Z`, `newness.counts.new_title: 410` — ровно разница
  журнала выпусков (65 749 → 66 159). Процесс при этом живёт с 2026-10-15
  20:25 (сверено `process_start_time` и полем 22 `/proc/<pid>/stat`).

  Zona измеряет то же у себя журналом: один и тот же pid до и после строки
  «согласование: снимок сменился», 65 749 → 66 159, у всех трёх ячеек.

На этом же измерении нашёлся дефект, которого не искали: наложение lords-03
держит новое поколение в своём поле и НЕ присваивает его классовому
`Обработчик.данные`, а сборщик карты сайта в ядре смотрит именно на него —
поэтому карта 1lordserials1.online не менялась с 2026-10-15, тогда как у
остальных одиннадцати витрин сети она сегодняшняя или вчерашняя (MOD-81,
`automation/local/sitemap-freshness-sweep.py`).

Отсюда правило для этого инструмента: он спрашивает витрину и печатает
измеренное, а объяснять «перечитывает/не перечитывает» по коду не берётся —
ровно потому, что дважды за день такое объяснение оказалось сделанным по
файлу, который процесс не исполняет.

Что сравнивается, и оба факта читаются, ничего не меняя:

  ЗАГРУЖЕНО   `catalog_revision` из подробного `/healthz` по петле, а если
              его там нет — заголовок `X-Catalog-Revision` обычного ответа:
              рантайм Zona отдаёт его всегда (измерено 2026-10-18);
  НА ДИСКЕ    `revision` из файла по пути `catalog_path` того же ответа, а
              если путь не назван — по `runtime.data_dir` описи ячеек.

Расхождение означает «снимок лежит, приложение его не видит». Совпадение
означает ровно совпадение, и ни при какой графе «почему так» оно не
доказывает перечитывания: если процесс моложе файла — оно объясняется
перезапуском; если старше — тем, что доставка перезаписывает файл и с
неизменной ревизией (конвейер прямо пишет `skipped: «вход не изменился»`).
Для доказательства нужна ревизия, менявшаяся ПОСЛЕ запуска процесса, а
журнала ревизий по суткам здесь нет.

Отдельно проверяются ещё два вопроса, оба чтением файлов: совпадает ли
объявленный в реестре `runtime.data_dir` с тем, что передаёт включённый юнит
(доставка берёт путь из реестра, и расхождение делает выпуск безрезультатным
молча), и не приходит ли содержимое витрины от верхового приложения — тогда
возраст снимка о свежести содержимого не говорит вовсе.

Ячейка, у которой не нашлось НИ ОДНОГО из двух путей, помечается «НЕ ИЗМЕРЕНО»
и считается в отдельную графу: отсутствие способа спросить — это пробел
наблюдаемости (MOD-80), а не исправность. Два пути здесь именно потому, что с
одним инструмент назвал неизмеримыми пять ячеек, а неизмеримых оказалось две:
у трёх Zona ревизия спрашивается заголовком.

Только чтение. Значения путей печатаются: это внутренний инструмент, он
ходит по петле и в отчёт для владельца не идёт.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
import subprocess
import sys

КАТАЛОГ_ЯЧЕЕК = pathlib.Path("/etc/nginx/cells")
#: Где лежат юниты и что означает «включён». Константами — чтобы проверка
#: могла подставить свои каталоги, не трогая системные.
КАТАЛОГИ_ЮНИТОВ = (pathlib.Path("/etc/systemd/system"),
                   pathlib.Path("/lib/systemd/system"))
ВКЛЮЧЁННЫЕ = pathlib.Path("/etc/systemd/system/multi-user.target.wants")
ЮТС = dt.timezone.utc


def порт_ячейки(имя: str) -> str:
    файл = КАТАЛОГ_ЯЧЕЕК / f"{имя}.upstream"
    try:
        т = файл.read_text(encoding="utf-8")
    except OSError:
        return ""
    м = re.search(r"server\s+127\.0\.0\.1:(\d+)", т)
    return м.group(1) if м else ""


def все_ячейки() -> list[str]:
    try:
        файлы = sorted(КАТАЛОГ_ЯЧЕЕК.glob("*.upstream"))
    except OSError:
        return []
    return [ф.stem for ф in файлы]


def заголовки_ответа(порт: str, таймаут: int) -> dict:
    """Заголовки обычного ответа витрины по петле.

    Второй путь измерения, и появился он не из симметрии. Линия Zona измерила
    2026-10-18, что её рантайм отдаёт `X-Catalog-Revision` на КАЖДЫЙ ответ, и
    это ревизия ЗАГРУЖЕННОГО снимка, а не содержимое файла. Проверено отсюда
    независимо тем же днём: у zona-01/02/03 заголовок и файл совпадают
    (`ab5cd6f7b28853719bd65890edcce39a`, файл от 04:05Z).

    Без этого пути инструмент объявлял «НЕ ИЗМЕРЕНО» там, где измерить можно —
    просто не тем эндпоинтом. Такой вывод хуже пробела: он указывает на риск,
    которого нет, и прячет пробел там, где он настоящий.
    """
    г = subprocess.run(["curl", "-fsS", "-D", "-", "-o", "/dev/null",
                        "--max-time", str(таймаут),
                        f"http://127.0.0.1:{порт}/"],
                       capture_output=True, text=True)
    з: dict = {}
    for с in (г.stdout or "").splitlines():
        if ":" in с:
            к, _, v = с.partition(":")
            з[к.strip().lower()] = v.strip()
    return з


def путь_по_данным(имя: str) -> str:
    """Файл каталога по описи ячеек, когда ответ его не называет.

    Заголовок отдаёт ревизию, но не путь, поэтому путь берётся из
    `config/site-cells.json`: `runtime.data_dir` и файл `<site_id>-catalog.json`
    в нём — то же имя, которое кладёт доставка (`factory/cell/runtime.py`).
    Выдумывать путь нельзя: ошибка в нём дала бы ложное «РАСХОЖДЕНИЕ».
    Файла нет — возвращается пусто, и ячейка честно останется неизмеренной.
    """
    каталог = str((запись_ячейки(имя).get("runtime") or {}).get("data_dir") or "")
    if not каталог:
        return ""
    путь = pathlib.Path(каталог) / f"{имя}-catalog.json"
    return str(путь) if путь.is_file() else ""


def ответ_healthz(порт: str, таймаут: int) -> dict:
    г = subprocess.run(["curl", "-fsS", "--max-time", str(таймаут),
                        f"http://127.0.0.1:{порт}/healthz"],
                       capture_output=True, text=True)
    if г.returncode != 0:
        return {}
    try:
        return json.loads(г.stdout or "")
    except ValueError:
        return {}


def ревизия_файла(путь: str) -> tuple[str, str]:
    """(revision, когда файл записан) или ("", причина).

    Ревизия может лежать и в начале файла, и в конце: порядок ключей у разных
    издателей разный. Сперва дешёвые края, и только если не нашлось — полный
    проход. Файл крупный (20 МиБ), но это делается раз на ячейку.
    """
    if not путь:
        return ("", "путь не назван")
    п = pathlib.Path(путь)
    if not п.is_file():
        return ("", "файла нет")
    образец = re.compile(r'"revision"\s*:\s*"([^"]+)"')
    try:
        with п.open("rb") as ф:
            м = образец.search(ф.read(8192).decode("utf-8", "replace"))
            if not м:
                ф.seek(max(0, п.stat().st_size - 8192))
                м = образец.search(ф.read().decode("utf-8", "replace"))
            if not м:
                ф.seek(0)
                м = образец.search(ф.read().decode("utf-8", "replace"))
    except OSError as пр:
        return ("", f"не читается: {пр}")
    if not м:
        return ("", "в файле нет revision")
    когда = dt.datetime.fromtimestamp(п.stat().st_mtime, ЮТС)
    return (м.group(1), f"{когда:%Y-%m-%d %H:%M}Z")


def запись_ячейки(имя: str) -> dict:
    реестр = (pathlib.Path(__file__).resolve().parents[2] / "config"
              / "site-cells.json")
    try:
        документ = json.loads(реестр.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    ячейки = документ.get("cells") or []
    ячейки = list(ячейки.values()) if isinstance(ячейки, dict) else ячейки
    for я in ячейки:
        if str(я.get("site_id") or "") == имя:
            return я
    return {}


def сверка_объявления(имя: str) -> str:
    """Совпадает ли объявленный `runtime.data_dir` с тем, что передаёт юнит.

    Это третий вопрос инструмента, и он о другом молчании. Доставка берёт путь
    ИЗ РЕЕСТРА (`factory/cell/delivery.py`: `каталог_данных` читает
    `runtime.data_dir`). Если объявление расходится с юнитом, доставка положит
    снимок туда, откуда витрина не читает, и сделает это молча: отчёт
    доставки успешен, файл появился, витрина не изменилась. Так уже было —
    zona-02, измерено 2026-10-08 (издатель клал в `/srv/lords/.frontend/...`,
    витрина читала `/srv/zonafilm-cc/data`, разница 6791 произведение);
    исправлено операцией `factory cell relocate-data`.

    Читаются только файлы: сам юнит и ссылка `multi-user.target.wants`,
    которая и означает «включён». Состояние менеджера здесь не спрашивается —
    `systemctl` вне профиля, и менять профиль под задачу нельзя.
    """
    запись = запись_ячейки(имя)
    р = запись.get("runtime") or {}
    объявлено = str(р.get("data_dir") or "")
    юнит = str(р.get("unit") or "")
    if not юнит:
        return "юнит не назван в реестре"
    текст = ""
    for каталог in КАТАЛОГИ_ЮНИТОВ:
        файл = каталог / юнит
        if файл.is_file():
            try:
                текст = файл.read_text(encoding="utf-8")
            except OSError:
                текст = ""
            break
    if not текст:
        return f"юнит не прочитан ({юнит})"
    м = re.search(r"--data-dir[=\s]+(\S+)", текст)
    if not м:
        return "юнит не передаёт --data-dir"
    у_юнита = м.group(1).strip('"\'')
    включён = (ВКЛЮЧЁННЫЕ / юнит).exists()
    если_выключен = "" if включён else "; юнит НЕ включён"
    if объявлено.rstrip("/") != у_юнита.rstrip("/"):
        return (f"РАСХОЖДЕНИЕ ОБЪЯВЛЕНИЯ: реестр {объявлено or '—'}, "
                f"юнит {у_юнита}{если_выключен}")
    return f"совпадает{если_выключен}"


def содержимое_с_верха(имя: str) -> str:
    """Берёт ли витрина содержимое от ВЕРХОВОГО приложения, а не из снимка.

    Четвёртый вопрос, и без него инструмент судил бы не о том. У семейства
    yummy `LORDS_LEGACY_UPSTREAM` в `config/site.json` указывает на
    приложение Next.js этого домена, и список произведений приходит оттуда;
    снимок каталога остаётся проверкой «есть чем стартовать» (fail-closed) и
    источником содержимого НЕ является.

    Измерено 2026-10-18: у yummy-site/org/biz снимок от 2026-09-10 — 38 суток,
    а публичная главная yummyani.site отдаёт материалы с датой 2026-10-18,
    то есть сегодняшние. Вывод «содержимое устарело на 38 суток» по возрасту
    файла был бы неверен, и я его почти сделал.

    Возвращается адрес верхового приложения или пусто. Файл конфигурации
    только читается.
    """
    запись = запись_ячейки(имя)
    р = запись.get("runtime") or {}
    приложение = str(р.get("app_dir") or "")
    корень = (pathlib.Path(приложение).parent if приложение
              else pathlib.Path("/srv") / str(р.get("account") or имя))
    файл = корень / "current" / "config" / "site.json"
    try:
        документ = json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    среда = документ.get("environment") or {}
    return str(среда.get("LORDS_LEGACY_UPSTREAM") or "")


def разобрать_время(значение: str):
    try:
        return dt.datetime.fromisoformat((значение or "").replace("Z", "+00:00"))
    except ValueError:
        return None


def проверить(имя: str, таймаут: int) -> dict:
    порт = порт_ячейки(имя)
    объявление = сверка_объявления(имя)
    верх = содержимое_с_верха(имя)
    если_верх = (f"; содержимое идёт от верхового приложения {верх}, снимок "
                 f"источником содержимого не является" if верх else "")
    if not порт:
        return {"ячейка": имя, "объявление": объявление,
                "вывод": "upstream не прочитан"}
    отв = ответ_healthz(порт, таймаут)
    загружено = str(отв.get("catalog_revision") or "")
    путь_каталога = str(отв.get("catalog_path") or "")
    откуда = "healthz"
    if not загружено:
        # Второй путь, прежде чем сдаваться: заголовок обычного ответа. Так
        # измеряется Zona — её рантайм отдаёт X-Catalog-Revision всегда.
        загружено = заголовки_ответа(порт, таймаут).get("x-catalog-revision", "")
        откуда = "заголовок ответа"
    if not загружено:
        если_пусто = ("healthz не ответил или не JSON" if not отв
                      else "в healthz есть "
                           + (", ".join(sorted(отв)[:5]) or "ответ пуст"))
        return {"ячейка": имя, "порт": порт, "объявление": объявление,
                "верх": верх,
                "вывод": f"НЕ ИЗМЕРЕНО: ни catalog_revision, ни "
                         f"X-Catalog-Revision; {если_пусто}{если_верх}"}
    if not путь_каталога:
        путь_каталога = путь_по_данным(имя)
    на_диске, когда = ревизия_файла(путь_каталога)
    if not на_диске:
        return {"ячейка": имя, "порт": порт, "объявление": объявление,
                "вывод": f"НЕ ИЗМЕРЕНО: {когда}"}
    запуск = разобрать_время(str(отв.get("process_start_time") or ""))
    файл_время = разобрать_время(когда.replace("Z", "+00:00").replace(" ", "T"))
    совпало = загружено[:32] == на_диске[:32]
    # Три исхода, и ни один не называется «перечитывание работает».
    #
    # Процесс МОЛОЖЕ файла — совпадение объясняется перезапуском.
    #
    # Процесс СТАРШЕ файла — звучит как доказательство, но им не является, и
    # это измеренная поправка, а не осторожность. Доставка перезаписывает файл
    # каждые сутки, даже когда содержимое то же: конвейер прямо пишет
    # `skipped: "вход не изменился"` при совпавшем digest (измерено 2026-10-18
    # на animedia-01/02, вход не менялся с 2026-09-07). Значит mtime новый, а
    # ревизия старая — та самая, которую процесс загрузил при старте. Чтобы
    # доказать перечитывание, нужно знать, что ревизия МЕНЯЛАСЬ после запуска
    # процесса; журнала ревизий по суткам здесь нет, поэтому инструмент этого
    # и не утверждает.
    если = ("перезапуск" if (запуск and файл_время and запуск > файл_время)
            else "процесс старше файла" if (запуск and файл_время)
            else "время запуска неизвестно")
    return {"ячейка": имя, "порт": порт, "загружено": загружено[:32],
            "на_диске": на_диске[:32], "файл": когда, "объявление": объявление,
            "верх": верх,
            "объяснение": если if откуда == "healthz" else f"{если}, {откуда}",
            "вывод": "снимок у приложения" if совпало else
                     "РАСХОЖДЕНИЕ: снимок лежит, приложение его не видит"}


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("cells", nargs="*")
    р.add_argument("--timeout", type=int, default=8)
    а = р.parse_args(аргв)
    список = а.cells or все_ячейки()
    if not список:
        print(f"ячеек не найдено ({КАТАЛОГ_ЯЧЕЕК})", file=sys.stderr)
        return 2
    расхождений = неизмеримых = объявлений = с_верха = 0
    необъявленных = 0
    print(f"{'ячейка':14} {'порт':5} {'файл записан':18} {'почему так':22} вывод")
    for имя in список:
        и = проверить(имя, а.timeout)
        if и["вывод"].startswith("РАСХОЖДЕНИЕ"):
            расхождений += 1
        elif "НЕ ИЗМЕРЕНО" in и["вывод"] or "не ответил" in и["вывод"] \
                or "не прочитан" in и["вывод"]:
            неизмеримых += 1
        объявление_и = str(и.get("объявление", ""))
        if объявление_и.startswith("РАСХОЖДЕНИЕ"):
            объявлений += 1
        elif объявление_и and not объявление_и.startswith("совпадает"):
            # Юнит не назван в реестре, не прочитан или не передаёт
            # `--data-dir`: сверить объявление НЕЧЕМ. Молчание тут
            # недопустимо — оно читалось бы как «совпадает», и ячейка без
            # записи о юните выглядела бы проверенной.
            необъявленных += 1
        print(f"{и['ячейка']:14} {и.get('порт', '—'):5} "
              f"{и.get('файл', '—'):18} {и.get('объяснение', '—'):22} "
              f"{и['вывод']}")
