#!/usr/bin/env python3
"""Приоритет загрузки обложек ПО МЕСТУ НА ЭКРАНЕ, а не по порядку в разметке.

ЗАЧЕМ. Обложка первой карточки — кандидат LCP на всех шаблонах сети. Если она
`loading="lazy"`, браузер начинает её искать только после разметки; если ей
вдобавок поставлен `fetchpriority="low"`, он сознательно отдаёт полосу другим.
Признак «срочность кому-то выдана» этого не покажет: срочность может достаться
карточкам НИЖЕ сгиба, и тогда она не ускоряет первый экран, а замедляет его.

ЧТО ИЗМЕРЯЕТСЯ. Для каждой `img[data-poster]` берутся место на странице
(`getBoundingClientRect().top` + прокрутка), фактический размер отрисовки,
`loading` и `fetchpriority`. Сгиб — высота окна. Дальше считается, сколько
обложек попадает в первый экран и что им назначено.

ИСХОДЫ.

* ``ПРИОРИТЕТ ВЕРНЫЙ`` — первая обложка первого экрана не отложена, и ни одной
  обложке первого экрана не назначен низкий приоритет;
* ``ПРИОРИТЕТ ИНВЕРТИРОВАН`` — срочность выдана обложкам, которых на первом
  экране НЕ ВИДНО, а видимым стоит отсрочка или низкий приоритет. Худший из
  исходов: полоса потрачена на то, чего не видно;
* ``СРОЧНОСТИ НЕТ`` — отсрочка у всех обложек, срочность не выдана никому;
* ``НЕ ИЗМЕРЕНО`` — различающий контроль не прошёл (см. ниже) или страница
  не открылась.

РАЗЛИЧАЮЩИЙ КОНТРОЛЬ. Вывод «на первом экране всё отложено» ничего не стоит,
если инструмент не умеет отличать первый экран от остальной страницы: при
сломанном замере все `top` равны нулю, и любая страница выглядит одинаково.
Поэтому требуется, чтобы нашлась хотя бы одна ВИДИМАЯ обложка и хотя бы одна
невидимая. Страница, которая целиком короче окна, честно получает
``НЕ ИЗМЕРЕНО`` с причиной, а не приговор.

ПОЧЕМУ НЕ ПО ВЕРТИКАЛИ. Первый замер 23.10 отобрал первый экран по одному
`top` и нашёл «56 обложек выше сгиба» в окне 390×844 — столько туда не
влезает. Плитки горизонтальной карусели имеют одинаковый `top` и уезжают за
правый край: по вертикали они на первом экране, а посетитель их не видит.
Поэтому отбор идёт по пересечению с окном по ОБЕИМ осям.

Счётчики не получают технических просмотров: перехват ставится на контекст
до первого перехода (counter_guard.py, требование владельца 23.10).

    python3 automation/local/poster-priority-probe.py --url https://… [--json]
    python3 automation/local/poster-priority-probe.py --url … --desktop
"""
from __future__ import annotations

import argparse
import glob
import importlib.util
import json
import os
import pathlib
import sys

ХРОМ_ШАБЛОН = os.path.expanduser(
    "~/.cache/ms-playwright/chromium*/chrome-linux*/chrome")

#: Телефон 390×844 (iPhone 12/13/14) и настольное окно 1440×900. Высота здесь
#: ЗНАЧИМА, в отличие от замера перелива: именно она задаёт сгиб.
ОКНО_ТЕЛЕФОНА = (390, 844, 3, True)
ОКНО_НАСТОЛЬНОЕ = (1440, 900, 1, False)

ЗАМЕР_JS = """() => {
  const сгиб = window.innerHeight;
  const край = window.innerWidth;
  const обложки = [...document.querySelectorAll('img[data-poster]')];
  return {
    сгиб,
    край,
    высота_документа: document.documentElement.scrollHeight,
    обложки: обложки.map((и, н) => {
      const r = и.getBoundingClientRect();
      return {
        н,
        верх: Math.round(r.top + window.scrollY),
        слева: Math.round(r.left),
        отрисовка_px: Math.round(r.width),
        // Первый экран — пересечение с окном по ОБЕИМ осям. Плитки
        // горизонтальной карусели имеют тот же `top`, но уезжают за правый
        // край: по вертикали они «выше сгиба», а посетитель их не видит.
        видно: r.right > 0 && r.left < край && r.top < сгиб && r.bottom > 0,
        класс: и.className || '',
        loading: и.getAttribute('loading') || 'НЕТ',
        fetchpriority: и.getAttribute('fetchpriority') || 'НЕТ',
        адрес: (и.currentSrc || и.src || '').slice(-80),
      };
    }),
  };
}"""


def _запрет_счётчиков(цель):
    п = pathlib.Path(__file__).resolve().parent / "counter_guard.py"
    с = importlib.util.spec_from_file_location("counter_guard", п)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м.запретить_счётчики(цель)


def исход(замер: dict) -> dict:
    """Исход по одному замеру. Чистая функция: браузер здесь не нужен."""
    if замер.get("ошибка"):
        return {"исход": "НЕ ИЗМЕРЕНО", "почему": замер["ошибка"]}
    обложки = замер.get("обложки") or []
    сгиб = замер.get("сгиб") or 0
    if not обложки:
        return {"исход": "НЕ ИЗМЕРЕНО",
                "почему": "обложек с data-poster на странице нет"}
    выше = [о for о in обложки if о.get("видно")]
    ниже = [о for о in обложки if not о.get("видно")]
    if not выше or not ниже:
        return {"исход": "НЕ ИЗМЕРЕНО",
                "почему": "различающий контроль не прошёл: обложек ВИДНО на"
                          f" первом экране {len(выше)}, не видно {len(ниже)}"
                          " — первый экран от остальной страницы этим"
                          " замером не отличить"}
    срочные_ниже = [о["н"] for о in ниже if о["loading"] == "eager"]
    отложенные_выше = [о["н"] for о in выше if о["loading"] == "lazy"]
    низкие_выше = [о["н"] for о in выше if о["fetchpriority"] == "low"]
    общий = {
        "обложек": len(обложки),
        "сгиб_px": сгиб,
        "видно_на_первом_экране": len(выше),
        "не_видно": len(ниже),
        "срочные_невидимые": срочные_ниже[:10],
        "отложенные_видимые": отложенные_выше[:10],
        "низкий_приоритет_видимые": низкие_выше[:10],
        "первая_видимая": {к: выше[0][к] for к in
                           ("н", "верх", "слева", "отрисовка_px",
                            "loading", "fetchpriority", "адрес")},
    }
    if срочные_ниже and (отложенные_выше or низкие_выше):
        общий["исход"] = "ПРИОРИТЕТ ИНВЕРТИРОВАН"
        общий["почему"] = (
            f"срочность выдана {len(срочные_ниже)} обложкам, которых на"
            f" первом экране НЕ ВИДНО, а из {len(выше)} видимых отложено"
            f" {len(отложенные_выше)} и понижено {len(низкие_выше)}")
    elif not any(о["loading"] == "eager" for о in обложки):
        общий["исход"] = "СРОЧНОСТИ НЕТ"
        общий["почему"] = (f"все {len(обложки)} обложек отложены,"
                           " срочность не выдана никому")
    elif отложенные_выше or низкие_выше:
        общий["исход"] = "ПРИОРИТЕТ НЕПОЛНЫЙ"
        общий["почему"] = (f"на первом экране отложено {len(отложенные_выше)}"
                           f" и понижено {len(низкие_выше)} из {len(выше)}")
    else:
        общий["исход"] = "ПРИОРИТЕТ ВЕРНЫЙ"
        общий["почему"] = (f"первая обложка первого экрана не отложена,"
                           f" низкого приоритета выше сгиба нет")
    return общий


def замерить(адрес: str, окно=ОКНО_ТЕЛЕФОНА) -> dict:
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return {"адрес": адрес, "ошибка": "playwright не установлен"}
    кандидаты = sorted(glob.glob(ХРОМ_ШАБЛОН))
    if not кандидаты:
        return {"адрес": адрес, "ошибка": "Chromium playwright не найден"}
    ширина, высота, плотность, телефон = окно
    with sync_playwright() as p:
        браузер = p.chromium.launch(
            executable_path=кандидаты[-1],
            args=["--no-sandbox", "--disable-dev-shm-usage"])
        контекст = браузер.new_context(
            viewport={"width": ширина, "height": высота},
            device_scale_factor=плотность,
            is_mobile=телефон, has_touch=телефон,
            user_agent=("Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X)"
                        " AppleWebKit/605.1.15 (KHTML, like Gecko)"
                        " Version/17.0 Mobile/15E148 Safari/604.1")
            if телефон else
            ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36"
             " (KHTML, like Gecko) Chrome/120.0 Safari/537.36"))
        перехвачено = _запрет_счётчиков(контекст)
        страница = контекст.new_page()
        try:
            try:
                ответ = страница.goto(адрес, wait_until="load", timeout=45000)
            except Exception as сбой:  # noqa: BLE001
                return {"адрес": адрес,
                        "ошибка": f"навигация не завершилась:"
                                  f" {type(сбой).__name__}: {str(сбой)[:80]}"}
            страница.wait_for_timeout(2000)
            замер = страница.evaluate(ЗАМЕР_JS)
            замер["адрес"] = адрес
            замер["код"] = ответ.status if ответ else 0
            замер["окно"] = f"{ширина}x{высота}@{плотность}"
            замер["счётчиков_перехвачено"] = len(перехвачено)
            return замер
        finally:
            браузер.close()


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--url", action="append", default=[], required=True)
    р.add_argument("--desktop", action="store_true",
                   help="настольное окно 1440x900 вместо телефона")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    окно = ОКНО_НАСТОЛЬНОЕ if а.desktop else ОКНО_ТЕЛЕФОНА
    итоги = []
    for адрес in а.url:
        замер = замерить(адрес, окно)
        строка = {"адрес": адрес,
                  "окно": замер.get("окно", f"{окно[0]}x{окно[1]}@{окно[2]}"),
                  "код": замер.get("код"),
                  "счётчиков_перехвачено": замер.get("счётчиков_перехвачено"),
                  **исход(замер)}
        итоги.append(строка)
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
    else:
        for с in итоги:
            print("=" * 72)
            print(f"{с['адрес']}  окно {с['окно']}  код {с.get('код')}"
                  f"  счётчиков перехвачено {с.get('счётчиков_перехвачено')}")
            print(f"  ИСХОД: {с['исход']}")
            print(f"  {с['почему']}")
            if "первая_видимая" in с:
                п = с["первая_видимая"]
                print(f"  первая ВИДИМАЯ обложка: #{п['н']}"
                      f" верх {п['верх']} px, слева {п['слева']} px,"
                      f" отрисовка {п['отрисовка_px']} px,"
                      f" loading={п['loading']} fetchpriority={п['fetchpriority']}")
                print(f"     {п['адрес']}")
            if с.get("срочные_невидимые"):
                print(f"  срочность у обложек, которых не видно: "
                      f"{с['срочные_невидимые']}")
    плохие = sum(1 for с in итоги if с["исход"] in
                 ("ПРИОРИТЕТ ИНВЕРТИРОВАН", "СРОЧНОСТИ НЕТ",
                  "ПРИОРИТЕТ НЕПОЛНЫЙ"))
    # Метка завершения идёт в stderr: при --json stdout должен остаться
    # разбираемым JSON. Первая версия печатала её в stdout, и файл
    # доказательства не читался как JSON — «Extra data».
    print(f"ЗАВЕРШЕНО: страниц {len(итоги)}, с дефектом приоритета"
          f" {плохие}", file=sys.stderr)
    return 1 if плохие else 0


if __name__ == "__main__":
    sys.exit(main())
