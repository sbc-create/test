#!/usr/bin/env python3
"""Страница за последней страницей листалки: есть ли у выдачи дно.

Что это измеряет и почему это не любопытство. Листалка объявляет конечное число
страниц, но номер приходит из адреса. Если `?page=99999` отвечает 200,
индексируется и несёт canonical на себя, у сайта появляется **неограниченное
индексируемое пространство**: обходчик тратит бюджет на страницы, которых нет, а
в выдачу попадают пустые адреса. Это тот же класс, что пустая индексируемая
страница каталога, только без дна.

Три вопроса на каждом разделе, и каждый проверяется отдельно:

* `?page=<за пределом>` — код, режим индексации, canonical, есть ли карточки;
* `?page=1` — дубль первой страницы (канонически это адрес без номера);
* `?page=<мусор>` — нераспознанный номер не должен выглядеть страницей.

Инструмент только читает публичные страницы. Ничего не публикует и не меняет.

    python3 automation/local/pager-bounds-probe.py lordfilm47.space
    python3 automation/local/pager-bounds-probe.py --all
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

ПАСПОРТ = Path("/home/claude/wt-portable-site-cell-01/config/site-cells.json")
#: Раздел, который есть у всех семейств. Проверяется и каталог, и раздел вида:
#: у них разные вызывающие стороны листалки, и вести себя они могут по-разному.
РАЗДЕЛЫ = ("/catalog/", "/movies/")
#: Номер за пределом любой разумной выдачи. Не «очень большой», а именно за
#: пределом: 99999 страниц по 24 записи — 2.4 млн записей, которых нет ни у
#: одной витрины сети (крупнейший каталог — 62 978).
ЗА_ПРЕДЕЛОМ = 99999


def достать(url: str, таймаут: int = 45) -> tuple[str, str, dict[str, str]]:
    """Код последнего ответа, тело и заголовки. Переходы следуются."""
    with tempfile.NamedTemporaryFile(prefix="pager-head-", suffix=".txt") as ф, \
            tempfile.NamedTemporaryFile(prefix="pager-body-", suffix=".bin") as б:
        г = subprocess.run(
            ["curl", "-sS", "-L", "--max-time", str(таймаут), "-D", ф.name,
             "-o", б.name, "-w", "%{url_effective}", url],
            capture_output=True, text=True)
        голова = Path(ф.name).read_text(encoding="utf-8", errors="replace")
        тело = Path(б.name).read_text(encoding="utf-8", errors="replace")
    блоки = re.split(r"(?m)^(?=HTTP/)", голова)
    последний = блоки[-1] if блоки else голова
    код, заг = "", {}
    for с in последний.splitlines():
        if с.lower().startswith("http/"):
            части = с.split()
            код = части[1] if len(части) > 1 else ""
        elif ":" in с:
            к, _, з = с.partition(":")
            заг[к.strip().lower()] = з.strip()
    заг["итоговый-адрес"] = (г.stdout or "").strip() or url
    if г.returncode != 0 and not код:
        заг["ошибка-curl"] = f"curl={г.returncode}: {(г.stderr or '').strip()[:120]}"
    return код, тело, заг


def режим(тело: str, заг: dict[str, str]) -> str:
    """Режим индексации страницы: заголовок сильнее, meta — тоже факт."""
    части = []
    if заг.get("x-robots-tag"):
        части.append(f"X-Robots-Tag: {заг['x-robots-tag']}")
    м = re.search(r'<meta[^>]+name=["\']robots["\'][^>]*content=["\']([^"\']+)',
                  тело, re.I)
    if м:
        части.append(f"meta: {м.group(1)}")
    return "; ".join(части) or "режим не объявлен"


def canonical(тело: str) -> str:
    м = re.search(r'<link[^>]+rel=["\']canonical["\'][^>]*href=["\']([^"\']+)',
                  тело, re.I)
    return м.group(1) if м else ""


#: Формы адреса карточки по семействам. Формы ДВЕ, и это измерено, а не
#: предположено: Lords/Zona/AnimeGo/Animedia — `/title/<slug>`, Yummy —
#: `/anime/<slug>`. Признак, знающий одну форму, печатает ноль про страницу с
#: двумя десятками карточек.
ФОРМЫ_КАРТОЧКИ = ("/title/", "/anime/")


def карточек(тело: str) -> tuple[int, str] | None:
    """(сколько, форма) или None, если ни одна известная форма не встретилась.

    None — это НЕ ноль. Ноль утверждает «страница без содержимого»; None
    говорит «мерить нечем, форма адреса не распознана». Разница решает, можно
    ли вообще делать вывод, и выдавать второе за первое нельзя.
    """
    for форма in ФОРМЫ_КАРТОЧКИ:
        найдено = set(re.findall(
            r'href="(' + re.escape(форма) + r'[^"#?]+)"', тело))
        if найдено:
            return len(найдено), форма
    return None


def индексируется(режим_строкой: str) -> bool:
    return "noindex" not in режим_строкой.lower()


def проверить(домен: str, раздел: str) -> list[str]:
    замечания: list[str] = []
    база = f"https://{домен}{раздел}"

    # Сначала сам раздел. Без этого ОТСУТСТВИЕ раздела читается как исправная
    # листалка: `?page=99999` отдаёт 404 и там, где раздела нет вовсе.
    # Измерено 13.10 на yummyani.site: первый прогон зачёл ей `/movies/`
    # чистым, а такого раздела у семейства нет.
    код0, тело0, заг0 = достать(база, таймаут=30)
    if код0 != "200":
        причина = заг0.get("ошибка-curl") or f"код {код0 or 'пустой'}"
        print(f"   раздела нет: {база} отвечает {причина} — листалка "
              "НЕ ИЗМЕРЕНА")
        return замечания
    первая = карточек(тело0)
    if первая is None:
        print(f"   раздел отвечает 200, но форма адреса карточки не распознана "
              f"(известны {', '.join(ФОРМЫ_КАРТОЧКИ)}) — листалка НЕ ИЗМЕРЕНА")
        замечания.append(
            f"{домен}{раздел}: форма адреса карточки не распознана — "
            "инструмент не умеет мерить эту витрину, и ноль карточек здесь "
            "означал бы не пустую страницу, а слепой признак")
        return замечания
    на_первой, форма = первая
    print(f"   раздел есть: код 200, карточек на первой странице {на_первой} "
          f"(форма {форма})")

    код, тело, заг = достать(f"{база}?page={ЗА_ПРЕДЕЛОМ}")
    if заг.get("ошибка-curl"):
        print(f"   page={ЗА_ПРЕДЕЛОМ}: НЕ ИЗМЕРЕНО — {заг['ошибка-curl']}")
        return замечания
    р = режим(тело, заг)
    кан = canonical(тело)
    найдено = карточек(тело)
    карт = найдено[0] if найдено else 0
    print(f"   page={ЗА_ПРЕДЕЛОМ}: код {код}, карточек {карт}, {р}")
    print(f"      canonical: {кан or '—'}")
    if код == "200":
        if индексируется(р) and карт == 0:
            замечания.append(
                f"{домен}{раздел}?page={ЗА_ПРЕДЕЛОМ}: код 200, карточек 0, "
                f"индексируется ({р}) — страница за пределом выдачи выглядит "
                "страницей: неограниченное индексируемое пространство")
        elif карт == 0:
            print("      (200 без карточек, но noindex — в индекс не попадёт)")
        else:
            замечания.append(
                f"{домен}{раздел}?page={ЗА_ПРЕДЕЛОМ}: код 200 и карточек "
                f"{карт} — номер за пределом выдачи отдаёт содержимое")
    # Канонический адрес страницы за пределом не должен указывать на себя.
    if код == "200" and кан and f"page={ЗА_ПРЕДЕЛОМ}" in кан:
        замечания.append(
            f"{домен}{раздел}?page={ЗА_ПРЕДЕЛОМ}: canonical указывает на себя "
            f"({кан}) — страница объявляет себя канонической")

    код1, тело1, заг1 = достать(f"{база}?page=1")
    итог1 = заг1.get("итоговый-адрес", "")
    пусто_в_адресе = urlsplit(итог1).query == ""
    print(f"   page=1:    код {код1}, итоговый адрес {итог1}")
    if код1 == "200" and not пусто_в_адресе:
        р1 = режим(тело1, заг1)
        кан1 = canonical(тело1)
        if индексируется(р1) and "page=1" in кан1:
            замечания.append(
                f"{домен}{раздел}?page=1: код 200, индексируется, canonical на "
                f"себя ({кан1}) — дубль первой страницы раздела")
        elif кан1 and "page=1" not in кан1:
            print(f"      (page=1 не переадресован, но canonical ведёт на "
                  f"{кан1} — дубль снят каноническим адресом, не переходом)")
        else:
            замечания.append(
                f"{домен}{раздел}?page=1: код 200, {р1}, canonical "
                f"{кан1 or 'нет'} — дубль первой страницы ничем не снят")

    код2, тело2, заг2 = достать(f"{база}?page=не-число")
    р2 = режим(тело2, заг2)
    найдено2 = карточек(тело2)
    карт2 = найдено2[0] if найдено2 else 0
    print(f"   page=мусор: код {код2}, карточек {карт2}, {р2}")
    if код2 == "200" and индексируется(р2):
        замечания.append(
            f"{домен}{раздел}?page=не-число: код 200 и индексируется "
            f"({р2}) — нераспознанный номер страницы выглядит страницей")
    return замечания


def домены() -> list[str]:
    if not ПАСПОРТ.is_file():
        return []
    ячейки = json.loads(ПАСПОРТ.read_text(encoding="utf-8")).get("cells") or []
    итог = []
    for я in ячейки:
        д = str(я.get("domain") or "")
        # Зарезервированные имена из RFC 6761 — не витрины сети.
        if not д or д.endswith((".test", ".localhost")):
            continue
        итог.append(д)
    return итог


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("домены", nargs="*", help="домены витрин")
    р.add_argument("--all", action="store_true", help="все витрины из паспорта")
    а = р.parse_args()

    цели = а.домены or (домены() if а.all else [])
    if not цели:
        print("не названо ни одной витрины: домен аргументом или --all")
        return 2

    все: list[str] = []
    недоступны: list[str] = []
    for домен in цели:
        print(f"\n=== {домен}")
        код, _, заг = достать(f"https://{домен}/", таймаут=25)
        if код != "200":
            причина = заг.get("ошибка-curl") or f"код {код or 'пустой'}"
            print(f"   витрина не отвечает: {причина} — разделы НЕ ИЗМЕРЕНЫ")
            недоступны.append(f"{домен} ({причина})")
            continue
        for раздел in РАЗДЕЛЫ:
            print(f"  {раздел}")
            все.extend(проверить(домен, раздел))

    print(f"\n{'=' * 60}\nзамечаний: {len(все)}")
    for з in все:
        print(f"  • {з}")
    if недоступны:
        print(f"\nне измерено (витрина не ответила): {len(недоступны)}")
        for н in недоступны:
            print(f"  • {н}")
    return 1 if все else 0


if __name__ == "__main__":
    sys.exit(main())
