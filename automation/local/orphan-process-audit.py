#!/usr/bin/env python3
"""Перепись процессов витрин: кто обслуживает сеть, а кто остался от проб.

Только чтение `/proc` и конфигураций nginx. Ничего не останавливает и не
меняет: инструмент даёт ОСНОВАНИЕ для решения, а решение — отдельный шаг.

Почему именно так считается
---------------------------

Первая попытка этой переписи 2026-10-11 определяла порт процесса по его
сокетам (`/proc/<pid>/fd` + `/proc/net/tcp`) и записала в сироты ПОЛОВИНУ
боевых витрин: каталог `fd` читается не для всех процессов, и «порт не найден»
было истолковано как «порт не слушается». Это ровно та ошибка, из-за которой
можно остановить работающий сайт.

Поэтому признак строится на двух независимых источниках, каждый из которых
читается для любого процесса:

* **порт из командной строки** (`--port N`) — эти серверы всегда получают его
  аргументом; сверяется с портами, объявленными в конфигурации nginx;
* **cgroup**: боевая витрина живёт в своём `*.service`, проба — в сеансовой
  области (`session-*.scope`) или вообще без юнита.

Сиротой считается процесс, у которого порт НЕ объявлен в nginx **и** который не
принадлежит службе. Несовпадение двух признаков — не вывод, а повод разбираться
руками: такой процесс помечается `спорно` и в список на остановку не попадает.

    python3 automation/local/orphan-process-audit.py            # перепись
    python3 automation/local/orphan-process-audit.py --json     # машинный вид
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ПРОЦ = Path("/proc")
NGINX = Path("/etc/nginx")
ТАКТ = 100.0


def порты_nginx() -> dict[int, list[str]]:
    """Порт петли → файлы конфигурации, где он объявлен."""
    итог: dict[int, list[str]] = {}
    if not NGINX.is_dir():
        return итог
    for путь in NGINX.rglob("*"):
        if not путь.is_file():
            continue
        try:
            текст = путь.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for м in re.finditer(r"127\.0\.0\.1:(\d+)", текст):
            итог.setdefault(int(м.group(1)), []).append(путь.name)
    return итог


def _поле(текст: str, имя: str, по_умолчанию: str = "") -> str:
    м = re.search(rf"^{имя}:\s+(\S+)", текст, re.M)
    return м.group(1) if м else по_умолчанию


#: Признаки ЧУЖОГО КОНТУРА в cgroup: процесс живёт в контейнере или в
#: системной области, то есть к пробным копиям витрин отношения не имеет и
#: судить о нём по портам nginx бессмысленно.
ЧУЖОЙ_КОНТУР = ("docker-", "containerd", "system.slice", "kubepods")


def чужой_контур(pid: int, группа: str) -> str:
    """Почему процесс не наш — или пустая строка, если наш.

    Поймано 2026-10-11: `uvicorn seo_engine.app` на порту 8000 был записан в
    сироты, хотя живёт в Docker-контейнере (`system.slice/docker-…scope`,
    родитель `containerd-shim`, `exe` и `environ` недоступны). Порт его не
    объявлен в nginx и cgroup не кончается на `.service`, поэтому по прежним
    признакам он выглядел пробной копией витрины — а остановка убила бы процесс
    в чужом контуре. Ни одна сессия его не запускала: ни SEO, ни эта.
    """
    for признак in ЧУЖОЙ_КОНТУР:
        if признак in группа:
            return f"cgroup содержит {признак!r}"
    return ""


def наш(pid: int, uid: int) -> str:
    """Можем ли мы судить о процессе как о своём — иначе причина, почему нет.

    Недоступный `exe` или чужой владелец означают другое пространство имён или
    другую учётную запись. Такой процесс в сироты не записывается: это не вывод
    о нём, а признание, что судить нечем. Боевые витрины на этом хосте работают
    под uid 984 — они определяются по nginx и службе, а не по владельцу, и в
    сироты не попадают по другой причине.
    """
    if uid != os.getuid():
        return f"владелец uid {uid}, не наш"
    try:
        (ПРОЦ / str(pid) / "exe").readlink()
    except OSError:
        return "exe не читается: другое пространство имён"
    return ""


def процесс(pid: int, загрузка: float) -> dict | None:
    место = ПРОЦ / str(pid)
    try:
        команда = (место / "cmdline").read_bytes().decode("utf-8", "replace")
        состояние = (место / "status").read_text()
        стат = (место / "stat").read_text().rsplit(") ", 1)[1].split()
    except (OSError, IndexError):
        return None
    if "--port" not in команда:
        return None
    части = команда.split("\0")
    порт = None
    for i, ч in enumerate(части):
        if ч == "--port" and i + 1 < len(части):
            порт = int(части[i + 1]) if части[i + 1].isdigit() else None
    try:
        группа = (место / "cgroup").read_text().strip().rsplit("/", 1)[-1]
    except OSError:
        группа = ""
    return {
        "pid": pid,
        "ppid": int(_поле(состояние, "PPid", "0")),
        "uid": int(_поле(состояние, "Uid", "0")),
        "rss_mib": int(_поле(состояние, "VmRSS", "0").rstrip()) // 1024
        if _поле(состояние, "VmRSS") else 0,
        "age_h": round((загрузка - float(стат[19]) / ТАКТ) / 3600, 1),
        "port": порт,
        "cgroup": группа,
        "cmd": команда.replace("\0", " ").strip(),
    }


def собрать() -> tuple[list[dict], dict[int, list[str]]]:
    объявленные = порты_nginx()
    загрузка = float((ПРОЦ / "uptime").read_text().split()[0])
    найдено = []
    for запись in ПРОЦ.iterdir():
        if not запись.name.isdigit():
            continue
        п = процесс(int(запись.name), загрузка)
        if not п:
            continue
        в_nginx = п["port"] in объявленные
        служба = bool(re.search(r"\.service$", п["cgroup"]))
        чужой = чужой_контур(п["pid"], п["cgroup"])
        if чужой:
            # Чужой контур проверяется ПЕРВЫМ: иначе контейнерный процесс с
            # портом вне nginx выглядит пробной копией витрины.
            п["вид"] = "чужой контур"
            п["почему"] = чужой
        elif в_nginx and служба:
            п["вид"] = "обслуживает"
        elif not в_nginx and not служба:
            не_наш = наш(п["pid"], п["uid"])
            if не_наш:
                # Судить нечем — в сироты не записывается.
                п["вид"] = "спорно"
                п["почему"] = не_наш
            else:
                п["вид"] = "сирота"
        else:
            # Признаки расходятся: это не вывод, а повод смотреть руками.
            п["вид"] = "спорно"
        п["in_nginx"] = в_nginx
        п["service"] = служба
        п.setdefault("почему", "")
        найдено.append(п)
    return sorted(найдено, key=lambda п: (п["вид"], -п["rss_mib"])), объявленные



def сессии_агента() -> list[dict]:
    """Процессы `claude` с их памятью и возрастом, от старых к новым.

    Зачем отдельно от сирот. Признак сироты у витрин построен на двух
    независимых источниках и однажды уже ошибался опасным образом — записал в
    сироты половину боевых витрин. Сессии агента под этот признак не подходят
    вовсе: у них нет порта, нет юнита и нет места в конфигурации nginx, то
    есть по всем трём меркам они «сироты», а остановить их значило бы прервать
    чью-то работу. Поэтому они только СООБЩАЮТСЯ.
    """
    # Такт берётся у системы, а не из постоянной: значение 100 верно почти
    # везде, но «почти» в измерении возраста процесса ни к чему.
    тиков = os.sysconf("SC_CLK_TCK")
    try:
        загрузка = float((ПРОЦ / "uptime").read_text().split()[0])
    except OSError:
        return []
    свои = os.getpid()
    итог: list[dict] = []
    for каталог in ПРОЦ.iterdir():
        if not каталог.name.isdigit() or int(каталог.name) == свои:
            continue
        try:
            строка = командная_строка(каталог)
        except OSError:
            continue
        if not строка:
            continue
        имя = строка.split()[0].rsplit("/", 1)[-1]
        # Ровно исполняемый файл `claude`, а не любое упоминание слова: иначе
        # в перечень попал бы и этот самый инструмент, и grep по слову.
        if имя != "claude":
            continue
        try:
            страниц = int(каталог.joinpath("statm").read_text().split()[1])
            поля = каталог.joinpath("stat").read_text().rsplit(")", 1)[1].split()
            возраст = (загрузка - int(поля[19]) / тиков) / 3600
        except (OSError, IndexError, ValueError):
            continue
        итог.append({"pid": каталог.name,
                     "rss_mib": страниц * 4096 // (1024 * 1024),
                     "age_h": возраст, "cmd": строка})
    return sorted(итог, key=lambda с: -с["age_h"])


def командная_строка(каталог: Path) -> str:
    сырое = каталог.joinpath("cmdline").read_bytes()
    return сырое.replace(b"\0", b" ").decode("utf-8", "replace").strip()

def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="перепись процессов витрин")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    процессы, объявленные = собрать()
    память = (ПРОЦ / "meminfo").read_text()
    доступно = int(_поле(память, "MemAvailable")) // 1024
    своп = int(_поле(память, "SwapTotal")) // 1024
    сироты = [п for п in процессы if п["вид"] == "сирота"]
    спорные = [п for п in процессы if п["вид"] == "спорно"]
    чужие = [п for п in процессы if п["вид"] == "чужой контур"]
    свод = {
        "mem_available_mib": доступно,
        "swap_total_mib": своп,
        "editor_threshold_mib": 2048,
        "editor_can_start": доступно >= 2048,
        "orphan_count": len(сироты),
        "orphan_rss_mib": sum(п["rss_mib"] for п in сироты),
        "disputed_count": len(спорные),
        "foreign_count": len(чужие),
        "processes": процессы,
    }
    if а.json:
        print(json.dumps(свод, ensure_ascii=False, indent=2))
        return 0
    print(f"{'pid':>8} {'вид':12} {'RSS':>6} {'порт':>6} {'в nginx':>8} "
          f"{'служба':>7} {'возраст':>8}  команда")
    for п in процессы:
        print(f"{п['pid']:>8} {п['вид']:12} {п['rss_mib']:>6} "
              f"{str(п['port'] or '—'):>6} {'да' if п['in_nginx'] else 'нет':>8} "
              f"{'да' if п['service'] else 'нет':>7} {п['age_h']:>7} ч  "
              f"{п['cmd'][:78]}")
    print(f"\nMemAvailable {доступно} МиБ, swap {своп} МиБ; порог редактора "
          f"2048 МиБ — {'хватает' if доступно >= 2048 else 'НЕ хватает'}")
    print(f"сирот: {len(сироты)}, их память: {свод['orphan_rss_mib']} МиБ; "
          f"спорных: {len(спорные)}; в чужом контуре: {len(чужие)}")
    for п in чужие:
        print(f"   чужой контур {п['pid']} порт {п['port']}: {п['почему']} — "
              f"{п['cmd'][:60]}")
    if спорные:
        print("спорные в список на остановку НЕ входят — разбирать руками:")
        for п in спорные:
            print(f"   {п['pid']} порт {п['port']} в nginx "
                  f"{'да' if п['in_nginx'] else 'нет'}, служба "
                  f"{'да' if п['service'] else 'нет'}: {п['cmd'][:70]}")

    сессии = сессии_агента()
    if сессии:
        всего = sum(с["rss_mib"] for с in сессии)
        print(f"\nсессии агента: {len(сессии)}, памяти {всего} МиБ "
              f"(для сравнения, сирот витрин — {свод['orphan_rss_mib']} МиБ)")
        print("   В СПИСОК НА ОСТАНОВКУ НЕ ВХОДЯТ НИ ПРИ КАКИХ УСЛОВИЯХ: это "
              "может быть незавершённая работа, решение — владельца.")
        for с in сессии[:8]:
            print(f"   {с['pid']:>8} {с['rss_mib']:>5} МиБ "
                  f"{с['age_h']:>7.1f} ч  {с['cmd'][:60]}")
        if len(сессии) > 8:
            print(f"   … и ещё {len(сессии) - 8}")
        старые = [с for с in сессии if с["age_h"] >= 168]
        if старые:
            освободится = sum(с["rss_mib"] for с in старые)
            print(f"   старше недели: {len(старые)}, памяти {освободится} МиБ "
                  f"— это и есть запас до порога ворот редактора")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
