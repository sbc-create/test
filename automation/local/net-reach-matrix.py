#!/usr/bin/env python3
"""Чем именно недостижим адрес: маршрутом, портом или семейством адресов.

Дополняет трассировку (`net-path-probe.py`, линия SEO, коммит 52c7c8e): та
отвечает, ГДЕ теряется путь, эта — ЧТО теряется. Разница не умозрительная, и
26.10.2026 она перевернула вывод по B023: до 87.250.250.242 порт 80
соединяется за 34–38 мс, порт 53 отвечает RST, а 443 молча отбрасывается —
значит маршрут есть, и «чёрная дыра маршрута» была неверной формулировкой.
У провайдера «нет маршрута» и «теряется 443» — два разных исправления.

Что проверяется и почему именно так:

* **несколько адресов одного префикса** — отличить одиночный адрес от
  префикса целиком;
* **несколько портов одного адреса** — если молчат ВСЕ, маршрута может не
  быть; если часть отвечает (хоть RST), маршрут есть и дело в фильтре;
* **контрольные адреса**, которые обязаны отвечать, — иначе «всё молчит»
  объясняется нашей же сетью, а не чужой;
* **IPv6 тех же служб** — снимает подозрение на семейство адресов.

RST (`Connection refused`) здесь ЦЕННЕЕ соединения: он доказывает, что пакет
дошёл до хоста и ответ вернулся, даже если порт закрыт.

Ничего не отправляется, кроме попытки рукопожатия: ни байта данных
приложения, ни токенов.

    python3 automation/local/net-reach-matrix.py            # набор B023
    python3 automation/local/net-reach-matrix.py --json
"""
from __future__ import annotations

import argparse
import json
import socket
import time

#: Проверяемый набор. Адреса получены разрешением имён, а не придуманы:
#: api.webmaster.yandex.net → 213.180.193.61 / 2a02:6b8::2:61,
#: api-metrika.yandex.net → 213.180.204.242 и 87.250.251.47 / 2a02:6b8::2a3.
НАБОР = (
    ("213.180.193.61", "213.180.193.0/24", "api.webmaster.yandex.net", "цель"),
    ("213.180.193.1", "213.180.193.0/24", "тот же префикс", "цель"),
    ("213.180.193.3", "213.180.193.0/24", "тот же префикс", "цель"),
    ("87.250.250.242", "87.250.250.0/24", "ya.ru", "цель"),
    ("213.180.204.242", "213.180.204.0/24", "api-metrika.yandex.net", "контроль"),
    ("87.250.251.47", "87.250.251.0/24", "api-metrika.yandex.net", "контроль"),
)
ПОРТЫ = (80, 443, 22, 53)
НАБОР6 = (("2a02:6b8::2:61", "api.webmaster.yandex.net", "цель"),
          ("2a02:6b8::2a3", "api-metrika.yandex.net", "контроль"))


def проба(адрес: str, порт: int, *, v6: bool = False, ждать: float = 6.0) -> str:
    семейство = socket.AF_INET6 if v6 else socket.AF_INET
    s = socket.socket(семейство, socket.SOCK_STREAM)
    s.settimeout(ждать)
    начало = time.time()
    try:
        s.connect((адрес, порт))
        return f"connected {int((time.time() - начало) * 1000)}мс"
    except socket.timeout:
        return "timeout"
    except OSError as ош:
        return (ош.strerror or str(ош))[:40]
    finally:
        s.close()


def снять() -> dict:
    итог = {"at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "ipv4": [], "ipv6": []}
    for адрес, префикс, что, роль in НАБОР:
        итог["ipv4"].append({"адрес": адрес, "префикс": префикс, "что": что, "роль": роль,
                             "порты": {str(п): проба(адрес, п) for п in ПОРТЫ}})
    for адрес, что, роль in НАБОР6:
        итог["ipv6"].append({"адрес": адрес, "что": что, "роль": роль,
                             "tcp443": проба(адрес, 443, v6=True)})
    # Вывод считается, а не пишется руками: он и есть то, что пойдёт в заявку.
    выводы = []
    for з in итог["ipv4"]:
        ответили = [п for п, р in з["порты"].items() if р != "timeout"]
        if з["роль"] == "цель" and ответили:
            выводы.append(f"{з['адрес']}: маршрут ЕСТЬ (отвечают порты {', '.join(ответили)}), "
                          "теряются только остальные — это фильтр по порту, не отсутствие маршрута")
        elif з["роль"] == "цель":
            выводы.append(f"{з['адрес']}: молчат все проверенные порты — ни SYN-ACK, ни RST, ни ICMP")
        elif not ответили:
            выводы.append(f"ВНИМАНИЕ: контрольный {з['адрес']} тоже молчит — "
                          "проверь собственную сеть прежде, чем винить чужую")
    for з in итог["ipv6"]:
        if з["роль"] == "контроль" and з["tcp443"].startswith("connected"):
            выводы.append("IPv6 у машины работает (контрольный адрес соединяется), "
                          "значит семейство адресов симптом не объясняет")
    итог["выводы"] = выводы
    return итог


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--json", action="store_true", help="только JSON, без таблицы")
    а = р.parse_args()
    итог = снять()
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=1))
        return 0
    print(f"снято {итог['at']}")
    for з in итог["ipv4"]:
        порты = " ".join(f"{п}:{р_}" for п, р_ in з["порты"].items())
        print(f"  [{з['роль']:8}] {з['префикс']:18} {з['адрес']:16} {порты}")
    for з in итог["ipv6"]:
        print(f"  [{з['роль']:8}] IPv6              {з['адрес']:16} 443:{з['tcp443']}")
    for в in итог["выводы"]:
        print(f"  → {в}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
