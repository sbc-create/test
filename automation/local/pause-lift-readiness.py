#!/usr/bin/env python3
"""Можно ли ПРЯМО СЕЙЧАС пробовать снятие паузы публикаций (B004).

Зачем отдельный, очень узкий инструмент. 12.10 пробная публикация на
`zonafilm.space` была сделана, когда мост исполнял ЕЩЁ СТАРЫЙ код: правка
авторства лежала в дереве службы, но процесс её не загрузил. Сверка
предсказуемо дала «подменено авторство: 3», витрину вернули в `PAUSED_PUBLISH`,
и попытка стоила живой публикации и возврата блокера.

Отличить «правка лежит» от «правка исполняется» нельзя ни чтением файла, ни
временем коммита — только стадией «загружено процессом». Эта стадия уже
измеряется единым видом состояния доставки, и здесь она НЕ переписывается
заново: `delivery-state.py` импортируется, и ответ берётся из него. Второе
определение той же стадии разошлось бы с первым молча (та же причина, что в
D207 про две цифры артефакта).

Вопрос один и ответ один: `ГОТОВО` или `НЕ ГОТОВО` с названной причиной и
следующим шагом. Инструмент только читает.

    python3 automation/local/pause-lift-readiness.py
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

РЯДОМ = Path(__file__).resolve().parent
#: Компонент, от которого зависит сохранность авторства при публикации.
КЛЮЧ = "editorial"


def загрузить_вид(путь: Path | None = None):
    """Единый вид состояния доставки. Импорт, а не копия его логики.

    Путь нужен параметром: иначе исход «ГОТОВО» нечем проверить, а проверка,
    которая не может пройти, так же бесполезна, как та, что не может
    провалиться.
    """
    путь = путь or РЯДОМ / "delivery-state.py"
    if not путь.is_file():
        return None, f"нет {путь}"
    спец = importlib.util.spec_from_file_location("delivery_state", путь)
    модуль = importlib.util.module_from_spec(спец)
    # Модуль регистрируется в sys.modules ДО исполнения тела: `dataclasses`
    # при разборе класса делает `sys.modules.get(cls.__module__).__dict__`, и
    # без регистрации падает с AttributeError на NoneType. Измерено 13.10 на
    # `delivery-state.py`; та же поломка описана SEO-сессией у ядра
    # `lordserials22-info`.
    sys.modules.setdefault("delivery_state", модуль)
    try:
        спец.loader.exec_module(модуль)
    except Exception as exc:                            # noqa: BLE001
        sys.modules.pop("delivery_state", None)
        return None, f"{type(exc).__name__}: {exc}"
    return модуль, ""


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--component", default=КЛЮЧ,
                   help="ключ компонента в delivery-state.py")
    р.add_argument("--view", type=Path, default=None,
                   help="путь к единому виду состояния доставки (для стенда)")
    а = р.parse_args()

    вид, беда = загрузить_вид(а.view)
    if вид is None:
        print(f"состояние доставки НЕ ИЗМЕРЕНО: {беда}")
        print("вывод о готовности не делается")
        return 2

    компоненты = {к.ключ: к for к in вид.СОСТАВ}
    к = компоненты.get(а.component)
    if к is None:
        print(f"компонента {а.component!r} в едином виде нет; известны: "
              f"{sorted(компоненты)}")
        return 2

    итог = вид.разобрать(к)
    print(f"компонент: {к.ключ} — {к.имя}")
    for стадия in ("подготовлено", "установлено", "загружено", "проверено"):
        если, почему = итог.get(стадия, (вид.НЕ_ИЗМЕРЕНО, "стадия не разобрана"))
        метка = ("[+]" if если == вид.ДА
                 else "[x]" if если == вид.НЕТ else "[?]")
        print(f"   {метка} {стадия:13} {если:12} {почему}")

    подготовлено = итог.get("подготовлено", ("", ""))[0]
    установлено = итог.get("установлено", ("", ""))[0]
    загружено = итог.get("загружено", ("", ""))[0]

    print()
    if загружено == вид.ДА:
        print("ГОТОВО: процесс исполняет исправленный код.")
        print("Порядок дальше (мой, без владельца):")
        print("  1) снимок накладки:  python3 automation/local/"
              "editorial-overlay-before-after.py --repo zonafilm-space --snapshot")
        print("  2) SEO-сессия снимает паузу с ОДНОЙ витрины и даёт редактору "
              "один цикл")
        print("  3) сверка:           python3 automation/local/"
              "editorial-overlay-before-after.py --repo zonafilm-space --compare")
        print("  4) код 0 → снятие паузы по этой витрине; код 1 → витрина "
              "остаётся в PAUSED_PUBLISH, и это НЕ повод повторять")
        return 0

    print("НЕ ГОТОВО — пробную публикацию начинать нельзя.")
    if установлено != вид.ДА:
        print(f"   причина: стадия «установлено» = {установлено!r}; "
              "нужен шаг 2 владельца (install-cell-executor.sh)")
    elif загружено == вид.НЕТ:
        print(f"   причина: {итог['загружено'][1]}")
        print("   нужен шаг 1 владельца: sudo systemctl restart "
              "site-factory-mcp.service")
    else:
        print(f"   причина: стадия «загружено» = {загружено!r} — "
              f"{итог['загружено'][1]}")
    if подготовлено != вид.ДА:
        print(f"   и отдельно: стадия «подготовлено» = {подготовлено!r} — "
              "правки нет даже в дереве службы")
    print("\n   Почему это важно: 12.10 публикацию начали в этом же состоянии, "
          "сверка дала «подменено авторство: 3», витрину вернули в "
          "PAUSED_PUBLISH. Повтор в том же состоянии даст тот же исход.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
