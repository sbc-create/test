#!/usr/bin/env python3
"""Какие выборки каталога витрина объявляет своими страницами. Только чтение.

Повод, измеренный 21.10 на `animedia.space`: раздел `/movies/` и выборка
`/catalog/?type=movie` отдают ОДИН И ТОТ ЖЕ набор карточек (58 из 58), оба
`index, follow`, и каждый объявляет каноническим СЕБЯ. То есть у одного списка
два индексируемых адреса, и они конкурируют между собой. То же у `/series/` и
`?type=tv` (48 из 48). У соседей по сети те же выборки закрыты: `an1mego.site`
и `zonafilm.space` отдают `?type=…` с `noindex, follow`.

Причина — в коде, а не в настройке. У AnimeGo есть правило
`_выборка_каталога_не_на_себя` («своя страница — только каталог без условий и
ОДИНОЧНЫЙ жанр, год или страна; тип, серии, статус, сортировка и сочетания —
выборки»), и в установленном `animedia-frontend.py` такого правила НЕТ вовсе.
Работает только более узкое `_выборка_без_страницы`, закрывающее сортировку, —
и ровно сортировка у animedia действительно `noindex`.

Что печатается по каждой форме выборки:

* `ПАРА-ДУБЛЬ` — у раздела и у выборки одинаковый набор карточек, оба
  индексируются, и каждый канонизирует себя;
* `выборка индексируется` — сочетание фасетов или фасет без своей посадочной
  объявляет себя своей страницей;
* `ДУБЛЬ КАТАЛОГА` — одиночный фасет, у которого набор карточек и `h1`
  совпадают с каталогом без условий (так ведёт себя `?genre=anime` там, где
  жанр «аниме» стоит у всех записей);
* `не измерено` — у выборки ноль карточек: значения может не быть на этой
  витрине, и ответ тогда — свойство выбранного значения, а не правила.

ЗНАЧЕНИЯ ФАСЕТОВ БЕРУТСЯ СО САМОЙ ВИТРИНЫ. Первая редакция этой проверки
подставляла `genre=драма` и `country=япония`: у половины витрин таких значений
нет, страницы выходили пустыми, и «noindex» читался как правило, хотя был
свойством моего выбора. Это та же ошибка, что ловит `facet-pages-check.py` на
транслитерации жанров.

    python3 automation/local/catalog-selection-indexability.py animedia.space
    python3 automation/local/catalog-selection-indexability.py --all --json
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import urllib.parse

#: Встроенный контроль — ПО ОДНОЙ ФОРМЕ, а не по витрине целиком. На этих
#: витринах выборка `?type=` закрыта (`noindex, follow`), и находка `ПАРА-ДУБЛЬ`
#: у них означала бы, что признак пары меряет не правило. Называть их
#: «эталонными во всём» нельзя: у `zonafilm.space` индексируется `?kind=`, и
#: это отдельный вопрос, а не доказательство исправности.
КОНТРОЛЬНЫЕ = ("an1mego.site", "zonafilm.space")
ПО_УМОЛЧАНИЮ = ("animedia.space", "animedia.icu") + КОНТРОЛЬНЫЕ
#: Раздел → фасет, который его дублирует. Взято из маршрутов витрин
#: (`МАРШРУТЫ_ТИПА` у AnimeGo), а не придумано.
ПАРЫ_РАЗДЕЛОВ = (("/movies/", "type=movie"), ("/series/", "type=tv"))
#: Ключи, у которых по сетевому правилу МОЖЕТ быть своя страница.
СВОИ_СТРАНИЦЫ = ("genre", "year", "country")


def достать(адрес: str, таймаут: int = 40) -> str:
    try:
        г = subprocess.run(["curl", "-sSL", "--max-time", str(таймаут), адрес],
                           capture_output=True, text=True, timeout=таймаут + 20)
    except subprocess.TimeoutExpired:
        return ""
    return г.stdout or ""


def разобрать(тело: str) -> dict:
    def один(шаблон: str) -> str:
        м = re.search(шаблон, тело, re.S)
        return м.group(1).strip() if м else ""
    return {
        "карточки": set(re.findall(r'href="(/title/[^"#?]+/)"', тело)),
        "robots": один(r'name="robots" content="([^"]*)"'),
        "canonical": один(r'rel="canonical" href="([^"]*)"'),
        "h1": re.sub(r"<[^>]+>", "", один(r"<h1[^>]*>(.*?)</h1>"))[:60],
        "title": один(r"<title[^>]*>(.*?)</title>")[:70],
    }


def индексируется(с: dict) -> bool:
    return с["robots"].lower().startswith("index")


def канон_на_себя(с: dict, адрес: str) -> bool:
    """Канон указывает на тот же адрес с тем же запросом."""
    if not с["canonical"]:
        return False
    а = urllib.parse.urlsplit(с["canonical"])
    б = urllib.parse.urlsplit(адрес)
    return (а.path.rstrip("/") == б.path.rstrip("/")
            and urllib.parse.parse_qs(а.query) == urllib.parse.parse_qs(б.query))


def фасеты_витрины(тело: str) -> dict[str, str]:
    """`{ключ: запрос}` из одиночных фасетных ссылок САМОЙ витрины."""
    найдено: dict[str, str] = {}
    for ссылка in re.findall(r'href="(/catalog/\?[^"]+)"', тело):
        пары = urllib.parse.parse_qsl(urllib.parse.urlsplit(ссылка).query)
        if len(пары) == 1:
            найдено.setdefault(пары[0][0], urllib.parse.urlsplit(ссылка).query)
    return найдено


def проверить(домен: str) -> dict:
    итог: dict = {"домен": домен, "формы": [], "находки": []}
    корень = f"https://{домен}"
    тело = достать(f"{корень}/catalog/")
    if not тело:
        итог["находки"].append("каталог не прочитан — НЕ ИЗМЕРЕНО")
        итог["измерено"] = False
        return итог
    база = разобрать(тело)
    итог["измерено"] = True
    итог["фасеты"] = sorted(фасеты_витрины(тело))
    итог["формы"].append({"форма": "каталог без условий", "путь": "/catalog/",
                          "robots": база["robots"], "карточек": len(база["карточки"]),
                          "h1": база["h1"], "итог": "основа"})

    # --- раздел против выборки, которая его дублирует -------------------------
    for раздел, запрос in ПАРЫ_РАЗДЕЛОВ:
        с_раздел = разобрать(достать(f"{корень}{раздел}"))
        путь_выборки = f"/catalog/?{запрос}"
        с_выборка = разобрать(достать(f"{корень}{путь_выборки}"))
        if not с_раздел["карточки"] or not с_выборка["карточки"]:
            состояние = "не измерено"
        elif (с_раздел["карточки"] == с_выборка["карточки"]
                and индексируется(с_раздел) and индексируется(с_выборка)
                and канон_на_себя(с_раздел, раздел)
                and канон_на_себя(с_выборка, путь_выборки)):
            состояние = "ПАРА-ДУБЛЬ"
        else:
            состояние = "ок"
        итог["формы"].append({
            "форма": f"раздел {раздел} против ?{запрос}",
            "путь": путь_выборки,
            "robots": f"{с_раздел['robots']} / {с_выборка['robots']}",
            "карточек": f"{len(с_раздел['карточки'])}={len(с_выборка['карточки'])}",
            "h1": f"{с_раздел['h1']} | {с_выборка['h1']}",
            "итог": состояние})
        if состояние == "ПАРА-ДУБЛЬ":
            итог["находки"].append(
                f"{раздел} и /catalog/?{запрос}: один набор"
                f" ({len(с_раздел['карточки'])} карточек), оба индексируются,"
                f" каждый канонизирует себя")

    # --- одиночные фасеты витрины и одно сочетание ---------------------------
    фасеты = фасеты_витрины(тело)
    for ключ, запрос in sorted(фасеты.items()):
        if ключ in ("page", "view", "exclude"):
            continue
        путь = f"/catalog/?{запрос}"
        с = разобрать(достать(f"{корень}{путь}"))
        if not с["карточки"]:
            состояние = "не измерено"
        elif not индексируется(с):
            состояние = "закрыт"
        elif (с["карточки"] == база["карточки"] and с["h1"] == база["h1"]):
            состояние = "ДУБЛЬ КАТАЛОГА"
        elif ключ in СВОИ_СТРАНИЦЫ:
            состояние = "своя страница (по правилу сети допустимо)"
        else:
            состояние = "выборка индексируется"
        итог["формы"].append({"форма": f"одиночный {ключ}", "путь": путь,
                              "robots": с["robots"], "карточек": len(с["карточки"]),
                              "h1": с["h1"], "итог": состояние})
        if состояние == "ДУБЛЬ КАТАЛОГА":
            итог["находки"].append(
                f"/catalog/?{запрос}: набор и h1 совпадают с каталогом без"
                f" условий — индексируемый дубль каталога")
        elif состояние == "выборка индексируется":
            итог["находки"].append(
                f"/catalog/?{запрос}: выборка объявляет себя своей страницей"
                f" (в сети такие закрыты)")

    пара = [з for к, з in sorted(фасеты.items()) if к in СВОИ_СТРАНИЦЫ][:2]
    if len(пара) == 2:
        путь = f"/catalog/?{'&'.join(пара)}"
        с = разобрать(достать(f"{корень}{путь}"))
        if not с["карточки"]:
            состояние = "не измерено"
        elif индексируется(с):
            состояние = "выборка индексируется"
            итог["находки"].append(
                f"{путь}: сочетание двух фасетов индексируется")
        else:
            состояние = "закрыт"
        итог["формы"].append({"форма": "сочетание двух фасетов", "путь": путь,
                              "robots": с["robots"], "карточек": len(с["карточки"]),
                              "h1": с["h1"], "итог": состояние})
    return итог


def напечатать(итог: dict) -> None:
    if not итог.get("измерено"):
        print(f"[не изм.] {итог['домен']}: {'; '.join(итог['находки'])}")
        return
    метка = "НЕТ" if итог["находки"] else "ок "
    print(f"[{метка}] {итог['домен']}: находок {len(итог['находки'])},"
          f" фасетов на странице {len(итог.get('фасеты', []))}")
    for ф in итог["формы"]:
        print(f"       {ф['форма']:34} {str(ф['robots'])[:30]:<30}"
              f" карточек {str(ф['карточек']):>7} | {ф['итог']}")


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("домены", nargs="*")
    р.add_argument("--all", action="store_true")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)
    домены = а.домены or (list(ПО_УМОЛЧАНИЮ) if а.all else [])
    if not домены:
        print("не названо ни одной витрины: домен или --all")
        return 2
    итоги = [проверить(д) for д in домены]
    if а.json:
        print(json.dumps(итоги, ensure_ascii=False, indent=1))
        return 1 if any(и["находки"] for и in итоги) else 0
    for и in итоги:
        напечатать(и)
    с_находками = [и["домен"] for и in итоги if и["находки"]]
    print(f"\nвитрин проверено {len(итоги)}, с находками {len(с_находками)}"
          f"{': ' + ', '.join(с_находками) if с_находками else ''}")
    контроль = [и for и in итоги if и["домен"] in КОНТРОЛЬНЫЕ and и.get("измерено")]
    if контроль:
        # Контроль узкий НАМЕРЕННО: он про форму «раздел против ?type=», а не
        # про витрину целиком. Первая редакция объявляла контроль непройденным
        # из-за находки по ДРУГОЙ форме (`?kind=` у zonafilm.space) — то есть
        # считала свойством признака то, что было отдельным вопросом.
        пары = [и["домен"] for и in контроль
                if any(ф["итог"] == "ПАРА-ДУБЛЬ" for ф in и["формы"])]
        print("различающий контроль (только форма «раздел против ?type=»):"
              + (" у контрольных витрин пары-дубля нет — признак различает"
                 if not пары
                 else f" ПАРА-ДУБЛЬ найден и у {', '.join(пары)};"
                      f" признак меряет не правило"))
        прочее = {и["домен"]: [ф["форма"] for ф in и["формы"]
                               if ф["итог"] == "выборка индексируется"]
                  for и in контроль}
        for д, формы in прочее.items():
            if формы:
                print(f"   отдельным вопросом у {д}: {', '.join(формы)}"
                      f" — это НЕ часть контроля и выводов о признаке не даёт")
    return 1 if с_находками else 0


if __name__ == "__main__":
    sys.exit(main())
