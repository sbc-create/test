#!/usr/bin/env python3
"""Отчёт владельцу в 10:00, 18:00 и 22:00 Europe/Moscow. Формирование и запись.

Задание владельца задаёт расписание, содержание и формат. Здесь всё это
собирается из ИЗМЕРЕННОГО состояния проекта, а не из памяти сессии:

* охват работы и выпавшие домены — `automation/local/cycle-coverage.py`;
* работа и следующий шаг по каждому домену — очереди
  `config/domain-queues/<домен>.json`;
* что завершено за период — журнал git с времени предыдущего отчёта;
* проблемы — реестр `config/seo-module-defects.json`;
* обучение — `config/learning-queue.json`.

ПОЧЕМУ ПЕРИОД СЧИТАЕТСЯ ОТ ПРЕДЫДУЩЕГО ОТЧЁТА, А НЕ ОТ ПОЛУНОЧИ. Задание
требует: «Каждый отчёт охватывает период после предыдущего. Уже описанные
результаты повторно не засчитывай». Поэтому срез берётся из состояния
(`var/owner-reports/state.json`), а при первом запуске — от последнего
отчёта в `docs/reports/`, и только если нет и его — за 12 часов.

ДОСТАВКА И ЗАПИСЬ — РАЗНОЕ. Файл записан не значит доставлен. Состояние
хранит оба факта раздельно, повторы ограничены, а отчёт того же слота второй
раз не отправляется (защита от дублирования).

    python3 automation/local/owner-report.py --slot 10:00
    python3 automation/local/owner-report.py --slot auto --dry-run
    python3 automation/local/owner-report.py --status

Коды: 0 — отчёт собран (и доставлен, если канал настроен); 3 — отчёт собран,
доставка не настроена; 4 — этот слот уже отправлен.
"""
