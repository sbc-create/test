#: Порядок уровней для сортировки существенных проблем.
ПОРЯДОК_УРОВНЕЙ = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
#: Сколько проблем печатать в короткой сводке. Предел про читаемость, и он
#: НАЗЫВАЕТСЯ в самом отчёте: иначе обрезанный перечень выглядит полным.
СКОЛЬКО_ПРОБЛЕМ = 8


def существенные(реестр: list[dict], оч: list[dict],
                 с_какого: str) -> list[dict]:
    """Недостатки, упомянутые задачами, которые завели или изменили за период.

    Критерий выводимый, а не список на память. Прежде здесь стояли три
    захардкоженных идентификатора, и отчёт напечатал бы их и через месяц —
    при том что за эту смену нашлись ещё четыре. Обрезанный перечень,
    выглядящий полным, — это та же ложь, что «проверено» без запуска.
    """
    тронутые: set[str] = set()
    for о in оч:
        for з in о.get("tasks") or []:
            когда = str(з.get("updated") or з.get("created") or "")
            if когда and когда >= с_какого and з.get("defect"):
                тронутые.add(з["defect"])
    найдено = [з for з in реестр if з["id"] in тронутые]
    найдено.sort(key=lambda з: (ПОРЯДОК_УРОВНЕЙ.get(з.get("priority"), 9),
                                з["id"]))
    return найдено


