def переписать(текст: str) -> str:
    # Проверяется ПЕРВЫМ: иначе уже исправленный файл отвергался бы с
    # сообщением про якорь, и читатель искал бы несуществующее расхождение.
    if "превью_с_постерами" in текст:
        raise SystemExit("в установленном файле правка УЖЕ есть — патч не нужен")
    if текст.count(СРЕЗ_БЫЛО) != 1:
        raise SystemExit(
            f"якорь среза встречается {текст.count(СРЕЗ_БЫЛО)} раз вместо"
            " одного: установленный файл изменился. Патч собирать заново, а не"
            " подгонять по похожим местам.")
    if текст.count(ЯКОРЬ_ФУНКЦИИ) != 1:
        raise SystemExit("не найдено место для новой функции (`def разрешить`)")
    итог = текст.replace(ЯКОРЬ_ФУНКЦИИ, ФУНКЦИЯ + "\ndef разрешить(", 1)
    return итог.replace(СРЕЗ_БЫЛО, СРЕЗ_СТАЛО, 1)


def _загрузить(файл: Path, имя: str):
    спец = importlib.util.spec_from_file_location(имя, файл)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


def _снимок(м):
    """Снимок с ОДНОЙ записью без постера, и она самая свежая и с высшей оценкой.

    Так устроено нарочно: такая запись обязана исчезнуть из превью полки по
    ОЦЕНКЕ и обязана остаться ПЕРВОЙ в полке новизны. Признак, у которого
    запись лежит в середине, оба этих случая пропустил бы.
    """
    сегодня = dt.date.today()
    записи, подробности = [], {}
    for н in range(30):
        слаг = f"z{н:02d}"
        дата = (сегодня - dt.timedelta(days=н + 1)).isoformat()
        # Половина записей — сериалы, у всех есть жанры: иначе полки
        # сериалов и жанров остаются пустыми, и сравнение «до/после» на двух
        # пустых списках сходится ложно.
        вид = "Фильм" if н % 2 == 0 else "Сериал"
        записи.append({"slug": слаг, "title": f"Запись {н}",
                       "poster": "" if н == 0 else f"/p/{слаг}.webp",
                       "kind": вид, "year": сегодня.year,
                       "published_at": f"{дата}T00:00:00Z",
                       "release_at": f"{дата}T00:00:00Z",
                       "premiere_date": f"{дата}T00:00:00Z"})
        подробности[слаг] = {
            "imdb_rating": 9.9 - н * 0.01,
            "poster_url": "" if н == 0 else f"/p/{слаг}.webp",
            "genres": ["комедия", "драма", "триллер", "аниме"],
            "genre_codes": ["comedy", "drama", "thriller", "animation"],
            "premiere_date": f"{дата}T00:00:00Z"}
    return м.Снимок(items=записи, подробности=подробности, revision="проба")


def _слаг(к) -> str:
    return str((getattr(к, "raw", None) or {}).get("slug") or "")


def _превью(м, спец, предел: int) -> list[str] | str:
    """Слаги превью полки, либо строка причины, если полку не собрать.

    Причина возвращается ТЕКСТОМ, а не пустым списком: пустая полка и
    несобравшаяся полка — разные вещи, и сравнение «до/после» на двух пустых
    списках сошлось бы ложно.
    """
    try:
        к = м.разрешить(спец.collection_key, _снимок(м), "zona", предел=предел)
    except Exception as ош:  # noqa: BLE001 — причина нужна в отчёте
        return f"НЕ СОБРАНА: {type(ош).__name__}: {ош}"
    return [_слаг(з) for з in (к.items if к else [])]


def репетиция(было_файл: Path, стало_файл: Path) -> list[str]:  # noqa: C901
    """Сравнение ДО и ПОСЛЕ по КАЖДОЙ полке семейства zona.

    Полка по оценке обязана потерять заглушку; любая другая полка обязана
    остаться ПОБУКВЕННО той же. Второе и есть проверка «порядок новинок по
    дате сохранён»: она не про монотонность дат, а про тождество списка.
    """
    # Соседние модули выпуска (`genre_aliases` и прочие) лежат рядом с
    # работающим файлом: без них полки по жанру падают на импорте, и
    # репетиция молча пропустила бы их.
    sys.path.insert(0, str(было_файл.resolve().parent))
    было = _загрузить(было_файл, "collection_contract_до")
    стало = _загрузить(стало_файл, "collection_contract_после")
    итог = []
    полок = 0
    пустых: list[str] = []
    недоступных: list[str] = []
    for спец in стало.спецификации("zona"):
        предел = спец.card_limit or 24
        а = _превью(было, спец, предел)
        б = _превью(стало, спец, предел)
        поле = (спец.sort_spec or {}).get("field")
        полок += 1
        if not getattr(спец, "доступна", True):
            итог.append(f"полка «{спец.title}» ({спец.collection_key}):"
                        f" объявлена НЕДОСТУПНОЙ самим контрактом — пустота"
                        f" здесь задумана, а не пробел замера")
            недоступных.append(спец.collection_key)
            continue
        if isinstance(а, str) or isinstance(б, str):
            итог.append(f"полка «{спец.title}» ({спец.collection_key}):"
                        f" НЕ ИЗМЕРЕНА")
            итог.append(f"   до: {а if isinstance(а, str) else 'собрана'};"
                        f" после: {б if isinstance(б, str) else 'собрана'}")
            continue
        if поле == "rating":
            заглушки_до = [с for с in а if с == "z00"]
            заглушки_после = [с for с in б if с == "z00"]
            итог.append(
                f"полка по ОЦЕНКЕ «{спец.title}» ({спец.collection_key}):"
                f" карточек {len(а)} → {len(б)},"
                f" заглушек {len(заглушки_до)} → {len(заглушки_после)}")
            итог.append("   ок: заглушка из превью ушла" if not заглушки_после
                        else "   ПРОВАЛ: заглушка в превью осталась")
            итог.append("   ок: полка не стала короче"
                        if len(б) == len(а)
                        else f"   ПРОВАЛ: было {len(а)}, стало {len(б)}")
        else:
            итог.append(f"полка «{спец.title}» ({спец.collection_key},"
                        f" сортировка {поле!r}): карточек {len(б)}")
            if а != б:
                итог.append(f"   ПРОВАЛ: список изменился: было {а[:4]},"
                            f" стало {б[:4]}")
            elif not б:
                # Ноль против нуля сходится всегда, и выводом это не является.
                итог.append("   СРАВНЕНИЕ НЕИНФОРМАТИВНО: полка пуста на"
                            " синтетическом снимке (её фильтр он не наполняет)")
                пустых.append(спец.collection_key)
            else:
                итог.append("   ок: список ПОБУКВЕННО тот же, что до патча")
    # Полная страница подборки — поверхность каталога, из неё терять нельзя.
    for спец in стало.спецификации("zona"):
        if (спец.sort_spec or {}).get("field") != "rating":
            continue
        к = стало.разрешить(спец.collection_key, _снимок(стало), "zona",
                            страница=1)
        есть = any(_слаг(з) == "z00" for з in (к.items if к else []))
        итог.append(f"полная страница «{спец.title}»:"
                    + ("   ок: запись без постера на месте" if есть
                       else "   ПРОВАЛ: запись без постера потеряна"))
    итог.append(
        f"полок семейства zona: {полок}; недоступны по контракту"
        f" {len(недоступных)}; сравнение информативно у"
        f" {полок - len(пустых) - len(недоступных)}")
    if пустых:
        итог.append(f"   пустые на синтетическом снимке (вывода не несут):"
                    f" {', '.join(пустых)}")
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--source", default=str(УСТАНОВЛЕНО))
    р.add_argument("--verify", action="store_true")
    р.add_argument("--allow-stale", action="store_true")
    а = р.parse_args(аргв)

    исходный = Path(а.source)
    if not исходный.is_file():
        print(f"НЕ СОБРАНО: нет установленного файла {исходный}")
        return 2
    if any(л in str(исходный) for л in ЛОВУШКИ) and not а.allow_stale:
        print(f"НЕ СОБРАНО: {исходный} — не обслуживаемое витриной дерево."
              f" Работающий файл берётся через `current`"
              f" ({УСТАНОВЛЕНО}). Если это нарочно, добавьте --allow-stale.")
        return 2
    настоящий = исходный.resolve()
    print(f"работающий выпуск: {настоящий.parent.parent.name}")
    было = исходный.read_text(encoding="utf-8")
    стало = переписать(было)
    патч = "".join(difflib.unified_diff(
        было.splitlines(keepends=True), стало.splitlines(keepends=True),
        fromfile="a/src/collection_contract.py",
        tofile="b/src/collection_contract.py"))
    ПАТЧ.parent.mkdir(parents=True, exist_ok=True)
    ПАТЧ.write_text(патч, encoding="utf-8")
    print(f"патч: {ПАТЧ} ({len(патч.splitlines())} строк)")
    print(f"установленный файл: {исходный}"
          f" ({исходный.stat().st_size} Б)")

    if not а.verify:
        return 0

    провалов = 0
    with tempfile.TemporaryDirectory() as врем:
        врем = Path(врем)
        к = врем / "collection_contract.py"
        к.write_text(стало, encoding="utf-8")
        try:
            py_compile.compile(str(к), doraise=True)
        except py_compile.PyCompileError as ош:
            print(f"ПРОВЕРКА НЕ ПРОЙДЕНА: не компилируется: {ош}")
            return 1
        print("исправленный файл компилируется")

        проба = врем / "проба"
        (проба / "src").mkdir(parents=True)
        shutil.copy(исходный, проба / "src/collection_contract.py")
        г = subprocess.run(["patch", "-p1", "--dry-run", "-i", str(ПАТЧ)],
                           cwd=проба, capture_output=True, text=True)
        print((г.stdout or г.stderr).strip())
        if г.returncode != 0:
            print("ПРОВЕРКА НЕ ПРОЙДЕНА: патч не прикладывается")
            return 1
        print("патч прикладывается к установленному файлу (--dry-run)")

        print("\nрепетиция: ДО (работающий файл) против ПОСЛЕ (с патчем)")
        for строка in репетиция(исходный, к):
            print(f"   {строка}")
            провалов += 1 if "ПРОВАЛ" in строка else 0
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(главное())
