#!/usr/bin/env python3
"""Точечный патч «полка без карточки-заглушки» для УСТАНОВЛЕННОГО контракта.

Зачем патч, а не файл. Установленный `collection_contract.py` витрины
(`/srv/zonafilm-space/app/src/collection_contract.py`, 35 269 Б) и файл ветки
(`automation/host/collection_contract.py`, 48 056 Б) расходятся на 12 КБ, и у
установленного СВОИ спецификации подборок zona: окно новизны `recent_days: 90`
у обеих полок и свои заголовки. Живые описания на витрине говорят «за последние
90 дней», то есть установлена первая. Отдать файл целиком значит сменить окна с
90 на 14/30 и переписать заголовки заодно с правкой постеров — ровно та
ловушка, которую линия ячейки поймала в блоке по Yummy: подвижный носитель
несёт оба изменения.

Патч несёт РОВНО две вещи:

1. функцию `превью_с_постерами` — первые `предел` записей, предпочитая те, у
   которых есть постер, с добором остатка, чтобы полка не стала короче;
2. одну строку выбора куска в `разрешить`, и то ТОЛЬКО для полок,
   отсортированных по ОЦЕНКЕ (`sort_spec.field == "rating"`). У полки новизны
   отбор переставил бы порядок по дате, то есть сломал бы её смысл.

Чего патч НЕ делает: не меняет окна подборок (90 дней остаются), заголовки,
описания, выборки, полные страницы подборок и порядок новинок по дате.

    python3 automation/local/prepare-shelf-posters-patch.py --verify
"""
from __future__ import annotations

import argparse
import datetime as dt
import difflib
import importlib.util
import py_compile
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
УСТАНОВЛЕНО = Path("/srv/zonafilm-space/app/src/collection_contract.py")
ПАТЧ = КОРЕНЬ / "docs" / "handoff" / "shelf-posters-collection-contract.patch"

ФУНКЦИЯ = '''

def превью_с_постерами(набор: list[dict], предел: int) -> list[dict]:
    """Первые `предел` записей, предпочитая те, у которых ЕСТЬ постер.

    Полка — визуальное обещание: карточка-заглушка на главной читается
    посетителем как сломанный сайт. Измерено 20.10 на zonafilm.space: в полке
    «Высокие оценки недели» шесть карточек из 24 шли заглушкой, и страница
    произведения показывает заглушку тоже — то есть постера у записи нет вовсе,
    и это пробел ДАННЫХ, который правится отдельно.

    Почему это не обеднит полку, и это измерено: в каталоге zona-01 без постера
    841 запись из 67 681 (1.24 %), среди записей с оценкой не ниже порога
    высокой — 117 из 8 406 (1.39 %). Кандидатов на полку из 24 карточек
    остаётся 8 289.

    Чего функция НЕ делает:

    * не выбрасывает записи из ПОЛНОЙ страницы подборки — та поверхность
      каталога, и терять в ней высокую оценку из-за картинки нельзя;
    * не оставляет полку короче: при нехватке постеров остаток добирается
      записями без них. Пустая полка хуже заглушки;
    * не меняет порядок внутри каждой из двух групп.
    """
    если_есть = [з for з in набор if str(з.get("poster") or "").strip()]
    if len(если_есть) >= предел:
        return если_есть[:предел]
    без = [з for з in набор if not str(з.get("poster") or "").strip()]
    return (если_есть + без)[:предел]

'''

СРЕЗ_БЫЛО = """    всего = len(набор)
    if предел is not None:
        кусок = набор[:предел]
        номер = 1"""

СРЕЗ_СТАЛО = """    всего = len(набор)
    if предел is not None:
        # Отбор «с постером сначала» применяется ТОЛЬКО к полкам,
        # отсортированным по ОЦЕНКЕ. У полки новизны он переставил бы порядок
        # по дате, то есть сломал бы её смысл: «новое первым» важнее, чем «с
        # картинкой первым». На lordserial33.biz все карточки без постера лежат
        # именно в сериальных полках новизны, и для них это отдельное решение.
        по_оценке = (спец.sort_spec or {}).get("field") == "rating"
        кусок = (превью_с_постерами(набор, предел) if по_оценке
                 else набор[:предел])
        номер = 1"""

ЯКОРЬ_ФУНКЦИИ = "\n\ndef разрешить("


def переписать(текст: str) -> str:
    if текст.count(СРЕЗ_БЫЛО) != 1:
        raise SystemExit(
            f"якорь среза встречается {текст.count(СРЕЗ_БЫЛО)} раз вместо"
            " одного: установленный файл изменился. Патч собирать заново, а не"
            " подгонять по похожим местам.")
    if текст.count(ЯКОРЬ_ФУНКЦИИ) != 1:
        raise SystemExit("не найдено место для новой функции (`def разрешить`)")
    if "превью_с_постерами" in текст:
        raise SystemExit("в установленном файле правка УЖЕ есть — патч не нужен")
    итог = текст.replace(ЯКОРЬ_ФУНКЦИИ, ФУНКЦИЯ + "\ndef разрешить(", 1)
    return итог.replace(СРЕЗ_БЫЛО, СРЕЗ_СТАЛО, 1)


def репетиция(файл: Path) -> list[str]:
    """Поведение исправленного файла на синтетическом снимке. Только проверка.

    Два вопроса, и оба обязаны отвечать по-разному, иначе проверка ничего не
    различает: полка по ОЦЕНКЕ обходит запись без постера, а полка новизны
    сохраняет порядок по дате.
    """
    спец_имя = "collection_contract_патч"
    спец = importlib.util.spec_from_file_location(спец_имя, файл)
    м = importlib.util.module_from_spec(спец)
    sys.modules[спец_имя] = м
    спец.loader.exec_module(м)

    итог = []
    записи = []
    подробности = {}
    # Даты — в ПРОШЛОМ и внутри окна новизны: будущие записи полка новизны
    # отбрасывает фильтром, и проверка порядка тогда ничего не различает.
    # Это выяснилось подменой: отбор, применённый ко ВСЕМ полкам, проверку
    # порядка не ронял, потому что переставляемой записи в полке не было.
    сегодня = dt.date.today()
    for н in range(30):
        слаг = f"z{н:02d}"
        дата = (сегодня - dt.timedelta(days=н + 1)).isoformat()
        # Запись БЕЗ постера — самая свежая: если отбор применить к полке
        # новизны, она уедет в конец, и порядок по дате сломается заметно.
        записи.append({"slug": слаг, "title": f"Запись {н}",
                       "poster": "" if н == 0 else f"/p/{слаг}.webp",
                       "kind": "Фильм", "year": сегодня.year,
                       "published_at": f"{дата}T00:00:00Z"})
        подробности[слаг] = {"imdb_rating": 9.9 - н * 0.01,
                             "poster_url": "" if н == 0 else f"/p/{слаг}.webp"}
    снимок = м.Снимок(items=записи, подробности=подробности, revision="проба")

    по_оценке = None
    по_новизне = None
    for с in м.спецификации("zona"):
        поле = (с.sort_spec or {}).get("field")
        if поле == "rating" and по_оценке is None:
            по_оценке = с
        if поле in ("published_at", "date", "recent") and по_новизне is None:
            по_новизне = с
    if по_оценке is None:
        итог.append("ПРОВАЛ: у семейства zona не нашлось полки по оценке")
        return итог

    def слаг(к) -> str:
        return str((getattr(к, "raw", None) or {}).get("slug") or "")

    полка = м.разрешить(по_оценке.collection_key, снимок, "zona", предел=24)
    слаги = [слаг(з) for з in полка.items]
    без_постера = [слаг(з) for з in полка.items
                   if not str(getattr(з, "poster", "") or "").strip()]
    итог.append(f"полка по оценке «{по_оценке.title}»: карточек {len(слаги)},"
                f" без постера {len(без_постера)}")
    итог.append("ок: заглушка в превью не попала" if not без_постера
                else f"ПРОВАЛ: в превью заглушки {без_постера}")
    итог.append("ок: полка не стала короче" if len(слаги) == 24
                else f"ПРОВАЛ: карточек {len(слаги)} вместо 24")

    полная = м.разрешить(по_оценке.collection_key, снимок, "zona", страница=1)
    итог.append("ок: полная страница запись без постера не потеряла"
                if any(слаг(з) == "z00" for з in полная.items)
                else "ПРОВАЛ: полная страница потеряла запись без постера")

    if по_новизне is not None:
        новизна = м.разрешить(по_новизне.collection_key, снимок, "zona",
                              предел=16)
        даты = [str((getattr(з, "raw", None) or {}).get("published_at") or "")
                for з in новизна.items]
        итог.append(f"полка новизны «{по_новизне.title}»: карточек"
                    f" {len(новизна.items)}")
        первый = слаг(новизна.items[0]) if новизна.items else ""
        итог.append("ок: порядок новизны по дате сохранён"
                    if даты == sorted(даты, reverse=True)
                    else f"ПРОВАЛ: порядок новизны переставлен: {даты[:4]}")
        итог.append("ок: самая свежая запись осталась первой, хотя она без"
                    " постера" if первый == "z00"
                    else f"ПРОВАЛ: первой в полке новизны стала {первый!r},"
                         " а не самая свежая z00")
    else:
        итог.append("не измерено: полка новизны у семейства zona не найдена")
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--source", default=str(УСТАНОВЛЕНО))
    р.add_argument("--verify", action="store_true")
    а = р.parse_args(аргв)

    исходный = Path(а.source)
    if not исходный.is_file():
        print(f"НЕ СОБРАНО: нет установленного файла {исходный}")
        return 2
    было = исходный.read_text(encoding="utf-8")
    стало = переписать(было)
    патч = "".join(difflib.unified_diff(
        было.splitlines(keepends=True), стало.splitlines(keepends=True),
        fromfile="a/src/collection_contract.py",
        tofile="b/src/collection_contract.py"))
    ПАТЧ.parent.mkdir(parents=True, exist_ok=True)
    ПАТЧ.write_text(патч, encoding="utf-8")
    print(f"патч: {ПАТЧ} ({len(патч.splitlines())} строк)")
    print(f"установленный файл: {исходный}"
          f" ({исходный.stat().st_size} Б)")

    if not а.verify:
        return 0

    провалов = 0
    with tempfile.TemporaryDirectory() as врем:
        врем = Path(врем)
        к = врем / "collection_contract.py"
        к.write_text(стало, encoding="utf-8")
        try:
            py_compile.compile(str(к), doraise=True)
        except py_compile.PyCompileError as ош:
            print(f"ПРОВЕРКА НЕ ПРОЙДЕНА: не компилируется: {ош}")
            return 1
        print("исправленный файл компилируется")

        проба = врем / "проба"
        (проба / "src").mkdir(parents=True)
        shutil.copy(исходный, проба / "src/collection_contract.py")
        г = subprocess.run(["patch", "-p1", "--dry-run", "-i", str(ПАТЧ)],
                           cwd=проба, capture_output=True, text=True)
        print((г.stdout or г.stderr).strip())
        if г.returncode != 0:
            print("ПРОВЕРКА НЕ ПРОЙДЕНА: патч не прикладывается")
            return 1
        print("патч прикладывается к установленному файлу (--dry-run)")

        print("\nрепетиция на исправленном файле:")
        for строка in репетиция(к):
            print(f"   {строка}")
            провалов += 1 if "ПРОВАЛ" in строка else 0
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(главное())
