#!/usr/bin/env python3
"""Точные дубли изображений: группировка по размеру, затем контрольные суммы.

Только чтение. Ничего не удаляет и не предлагает удалять без разбора
назначения.

ПОЧЕМУ ИМЕННО ТАК, А НЕ ПО ИМЕНАМ. Разные имена не означают разные картинки, а
одинаковые — не означают одинаковые. Поэтому: сначала файлы группируются по
ТОЧНОМУ размеру (разный размер — заведомо разное содержимое, и хеш считать не
нужно), затем внутри каждой группы считается sha256. Это даёт точные дубли, а
не похожие.

ЧТО ИНСТРУМЕНТ РАЗЛИЧАЕТ, и без этого число «освобождаемого» было бы ложным:

* ОДИН ФАЙЛ, ВИДИМЫЙ ДВАЖДЫ. Жёсткая ссылка и один и тот же файл, найденный по
  двум путям, занимают место ОДИН раз. Считаются по паре (устройство, inode) —
  повторное вхождение в объём не идёт, а печатается отдельной строкой.
* НАЗНАЧЕНИЕ КОПИИ. Копия в каталоге релиза, в резервной копии, в выгрузке
  доказательств и в кеше — разные вещи с разными владельцами. Резервная копия
  НЕ становится ненужной из-за совпадения содержимого; доказательство,
  на которое ссылается записанная проверка, — тоже.
* ИСХОДНИК И УМЕНЬШЕННУЮ ВЕРСИЮ. Они не точные дубли по определению (разные
  байты), поэтому в этот счёт не попадают вовсе. Их разбирает
  `poster-delivery-audit.py`.

«Освобождаемое» печатается двумя числами: арифметическое (все лишние копии) и
РЕАЛИСТИЧНОЕ (только копии, у которых назначение допускает удаление). Второе
всегда меньше, и именно оно годится для решения.

    python3 automation/local/image-duplicate-census.py --list файл.tsv
    python3 automation/local/image-duplicate-census.py --root /srv --csv out.csv

Коды: 0 — дублей нет, 1 — дубли найдены, 2 — измерять нечего.
"""
from __future__ import annotations

import argparse
import collections
import csv
import hashlib
import os
import pathlib
import sys

РАСШИРЕНИЯ = (".webp", ".jpg", ".jpeg", ".png", ".avif", ".gif")

#: Назначение пути. Порядок важен: первое совпадение и есть ответ.
#: Поле «можно ли удалять» — не моё решение, а признак того, чьё оно.
НАЗНАЧЕНИЯ = (
    ("резервная копия", ("/backups/", "/backup-", "publish-backups",
                         ".before.", ".bak", "/perf01-backups/",
                         "/arc010-backups/")),
    ("доказательство проверки", ("/artifacts/evidence/", "/docs/verification/",
                                 "/report/", "/reports/")),
    ("каталог релиза", ("/releases/",)),
    ("кеш", ("/cache/", "/.next/", "/__pycache__/")),
    ("рабочая копия сессии", ("/wt-", "/var/worktrees/")),
    ("данные витрины", ("/data/", "/.frontend/")),
    ("инструментарий", ("/lords-tooling/", "/site-factory/repo/")),
)
#: Назначения, у которых удаление лишней копии НЕ освобождает ничего по
#: существу: копия и есть смысл объекта либо на неё ссылается запись.
НЕЛЬЗЯ_СЧИТАТЬ_ОСВОБОЖДАЕМЫМ = ("резервная копия", "доказательство проверки")

#: Кеш резолва симлинка `current`: он читается один раз на сайт.
_ТЕКУЩИЕ: dict[str, str] = {}


def текущий_релиз(путь: str) -> str | None:
    """Куда указывает `current` того сайта, которому принадлежит путь."""
    части = путь.split("/releases/")
    if len(части) != 2:
        return None
    корень = части[0]
    if корень not in _ТЕКУЩИЕ:
        try:
            _ТЕКУЩИЕ[корень] = os.path.realpath(
                os.path.join(корень, "current"))
        except OSError:
            _ТЕКУЩИЕ[корень] = ""
    return _ТЕКУЩИЕ[корень] or None


def удаление_допустимо(путь: str, цель: str) -> tuple[bool, str]:
    """Можно ли удалить ЭТУ копию, ничего не потеряв. С названной причиной.

    Хранить надо не «первую по алфавиту», а ту, которую нельзя удалять: иначе
    в группе «живой файл + резервная копия» лишним оказывается живой файл.
    """
    if цель == "резервная копия":
        return False, "резервная копия не становится ненужной от совпадения"
    текущий = текущий_релиз(путь)
    if текущий and путь.startswith(текущий + "/"):
        return False, "каталог ТЕКУЩЕГО релиза — его отдаёт витрина"
    if "/releases/" in путь:
        return True, "каталог прежнего релиза"
    if "/wt-" in путь or "/var/worktrees/" in путь:
        return True, "рабочая копия сессии"
    if цель == "доказательство проверки":
        return False, "на копию может ссылаться записанная проверка"
    return False, "назначение не допускает удаления без разбора"


def назначение(путь: str) -> str:
    for имя, признаки in НАЗНАЧЕНИЯ:
        if any(п in путь for п in признаки):
            return имя
    return "прочее"


def сумма(путь: str, блок: int = 1 << 20) -> str | None:
    х = hashlib.sha256()
    try:
        with open(путь, "rb") as ф:
            while True:
                кусок = ф.read(блок)
                if not кусок:
                    break
                х.update(кусок)
    except OSError:
        return None
    return х.hexdigest()


def собрать(корни: list[str], перечень: str | None) -> list[tuple[int, str]]:
    итог: list[tuple[int, str]] = []
    if перечень:
        for с in pathlib.Path(перечень).read_text(encoding="utf-8",
                                                  errors="replace").splitlines():
            if "\t" not in с:
                continue
            размер, путь = с.split("\t", 1)
            try:
                итог.append((int(размер), путь))
            except ValueError:
                continue
        return итог
    for корень in корни:
        for каталог, _, файлы in os.walk(корень, onerror=lambda _: None):
            for имя in файлы:
                if not имя.lower().endswith(РАСШИРЕНИЯ):
                    continue
                путь = os.path.join(каталог, имя)
                try:
                    итог.append((os.path.getsize(путь), путь))
                except OSError:
                    continue
    return итог


def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--root", action="append", default=[])
    р.add_argument("--list", dest="перечень", default=None)
    р.add_argument("--min-size", type=int, default=1024)
    р.add_argument("--csv", default="")
    а = р.parse_args(аргв)

    файлы = [(р_, п) for р_, п in собрать(а.root, а.перечень) if р_ >= а.min_size]
    if not файлы:
        print("НЕ ИЗМЕРЕНО: ни одного файла не найдено")
        return 2

    по_размеру: dict[int, list[str]] = collections.defaultdict(list)
    for размер, путь in файлы:
        по_размеру[размер].append(путь)

    кандидаты = {р_: пути for р_, пути in по_размеру.items() if len(пути) > 1}
    одиночек = len(файлы) - sum(len(п) for п in кандидаты.values())
    байт_всего = sum(р_ for р_, _ in файлы)

    видимые_inode: set[tuple[int, int]] = set()
    группы: dict[str, list[str]] = collections.defaultdict(list)
    тот_же_файл = 0
    тот_же_файл_байт = 0
    посчитано_сумм = 0
    for размер, пути in кандидаты.items():
        for путь in пути:
            try:
                с = os.stat(путь)
            except OSError:
                continue
            ключ_inode = (с.st_dev, с.st_ino)
            if ключ_inode in видимые_inode:
                тот_же_файл += 1
                тот_же_файл_байт += размер
                continue
            видимые_inode.add(ключ_inode)
            х = сумма(путь)
            посчитано_сумм += 1
            if х:
                группы[f"{размер}:{х}"].append(путь)

    дубли = {к: п for к, п in группы.items() if len(п) > 1}
    уникальных_байт = 0
    лишних_байт = 0
    лишних_файлов = 0
    по_назначению = collections.Counter()
    байт_назначения = collections.Counter()
    остаётся_файлов = collections.Counter()
    остаётся_байт = collections.Counter()
    причины_сохранения = collections.Counter()
    строки = []
    for ключ, пути in sorted(дубли.items(),
                             key=lambda кп: -int(кп[0].split(":")[0]) * len(кп[1])):
        размер = int(ключ.split(":")[0])
        уникальных_байт += размер
        пути = sorted(пути)
        решения = [(п_, назначение(п_), *удаление_допустимо(п_, назначение(п_)))
                   for п_ in пути]
        #: Хотя бы одна копия остаётся всегда. Если удалить допустимо ВСЕ, одна
        #: из них всё равно сохраняется — произвольная, и это сказано вслух.
        допустимых = [р for р in решения if р[2]]
        оставить_принудительно = (допустимых[0][0]
                                  if len(допустимых) == len(решения) else None)
        for путь, цель, можно, почему in решения:
            лишняя = можно and путь != оставить_принудительно
            if лишняя:
                лишних_байт += размер
                лишних_файлов += 1
                по_назначению[цель] += 1
                байт_назначения[цель] += размер
            else:
                остаётся_файлов[цель] += 1
                остаётся_байт[цель] += размер
                причины_сохранения[
                    "одна копия сохраняется всегда, даже если удалить можно все"
                    if можно else почему] += размер
            строки.append({"сумма": ключ.split(":")[1][:16], "размер": размер,
                           "копия": "лишняя" if лишняя else "оставить",
                           "назначение": цель, "удаление": почему,
                           "путь": путь})

    реалистично = лишних_байт

    print(f"файлов изображений: {len(файлы)}, объём {байт_всего/2**30:.2f} ГиБ")
    print(f"  заведомо уникальны по размеру (хеш не нужен): {одиночек}")
    print(f"  кандидатов в группах одинакового размера:"
          f" {sum(len(п) for п in кандидаты.values())}; сумм посчитано"
          f" {посчитано_сумм}")
    print(f"  ОДИН файл, видимый дважды (жёсткая ссылка или повтор пути):"
          f" {тот_же_файл} вхождений, {тот_же_файл_байт/2**20:.1f} МиБ —"
          f" в объём не считается")
    все_копии_байт = sum(int(к.split(":")[0]) * (len(п) - 1)
                         for к, п in дубли.items())
    print(f"\nгрупп точных дублей: {len(дубли)}")
    print(f"  объём уникальных изображений в этих группах:"
          f" {уникальных_байт/2**20:.1f} МиБ")
    print(f"  объём ВСЕХ дополнительных одинаковых копий:"
          f" {все_копии_байт/2**30:.2f} ГиБ")
    print(f"  из них УДАЛИТЬ ДОПУСТИМО: {лишних_байт/2**30:.2f} ГиБ"
          f" ({лишних_файлов} файлов)")
    print(f"\n{'допустимо МиБ':>13} {'файлов':>7} {'остаётся МиБ':>13}"
          f" {'файлов':>7}  назначение")
    for ц in sorted(set(байт_назначения) | set(остаётся_байт),
                    key=lambda к: -(байт_назначения[к] + остаётся_байт[к])):
        print(f"{байт_назначения[ц]/2**20:13.1f} {по_назначению[ц]:7}"
              f" {остаётся_байт[ц]/2**20:13.1f} {остаётся_файлов[ц]:7}  {ц}")
    if причины_сохранения:
        print("\nпочему копии остаются (объём, который НЕ освобождается):")
        for почему, б in причины_сохранения.most_common():
            print(f"  {б/2**20:9.1f} МиБ  {почему}")
    print(f"\nарифметически лишнее (все дополнительные копии):"
          f" {все_копии_байт/2**30:.2f} ГиБ")
    print(f"РЕАЛИСТИЧНО освобождаемое: {реалистично/2**30:.2f} ГиБ."
          f" Правило: удалить допустимо копию в ПРЕЖНЕМ каталоге релиза или в"
          f" рабочей копии сессии, если это не резервная копия; из каждой"
          f" группы одна копия сохраняется всегда. Решает МЕСТО, а не"
          f" назначение: снимок приёмки, лежащий в прежнем релизе, удалить"
          f" допустимо, а тот же снимок в текущем релизе — нет.")
    if а.csv:
        with open(а.csv, "w", newline="", encoding="utf-8") as ф:
            п = csv.DictWriter(ф, fieldnames=["сумма", "размер", "копия",
                                              "назначение", "удаление", "путь"])
            п.writeheader()
            for с in строки:
                п.writerow(с)
        print(f"CSV: {а.csv} — строк {len(строки)}")
    return 1 if дубли else 0


if __name__ == "__main__":
    sys.exit(главное())
