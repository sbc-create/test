#!/usr/bin/env python3
"""Доставить отправку целей Метрики в рантайм витрин — ТОЛЬКО недостающие куски.

Зачем не целиком. У витрин рантайм — это шаблон ПЛЮС правки самой ячейки
(у партии K2, например, правка нажимаемой цели по WCAG 2.5.8, которая живёт в
ячейке по решению D212а). Положить поверх текущий файл шаблона значило бы
стереть их и привезти заодно всё, что в шаблоне менялось по другим поводам.
Поэтому едут три точные вставки, те же, что в шаблоне:

1. скрипт отправки целей рядом с тегом Метрики (закрытый список имён, без
   параметров — поисковая фраза и текст комментария в отчёт попасть не могут);
2. `player_ready` и `player_error` из единственной воронки состояний плеера;
3. `player_start` при создании элемента плеера.

Куски берутся ИЗ ШАБЛОНА (`automation/host/lords-frontend.py`), а не
переписываются здесь: вторая копия того же кода разошлась бы с первой на
первой же правке. Если шаблон изменится так, что кусок перестанет находиться,
инструмент ОТКАЖЕТСЯ, а не наложит половину.

Ничего не выкладывает: правит рабочие копии витрин. Выпуск — отдельный шаг их
линий.

    python3 automation/local/deliver-metrika-goals.py --dry-run lords-10 lords-11
    python3 automation/local/deliver-metrika-goals.py lords-10
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ШАБЛОН = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"

#: Якорь → что должно оказаться на его месте. Правая часть ВЫНИМАЕТСЯ из
#: шаблона по якорям, чтобы копии кода не существовало.
#: Якорь тега включает ЗАКРЫВАЮЩУЮ кавычку литерала и строку закрытия вызова.
#: Без них вставка попадала ВНУТРЬ строки, и файл перестал разбираться.
#: Инструмент это поймал сам и вернул копию — но якорь, обрывающийся на
#: полуслове, проверять нечем, поэтому здесь он полный.
ЯКОРЬ_ТЕГА = (
    "'style=\"position:absolute;left:-9999px\" alt=\"\"></div></noscript>'\n"
    "    )"
)
ВСТАВКА_ТЕГА = (
    "'style=\"position:absolute;left:-9999px\" alt=\"\"></div></noscript>'\n"
    "        + цели_метрики(н)\n    )"
)
ЯКОРЬ_ВОРОНКИ = " function state(k,t,p){\n  if(отказ&&k==='ok') return;"
ЯКОРЬ_ЭЛЕМЕНТА = "  host.appendChild(n);\n  bind(n, ++token);"


def куски_шаблона() -> dict[str, str]:
    """Три вставки, вынутые из шаблона. Отказ, если шаблон не тот."""
    t = ШАБЛОН.read_text(encoding="utf-8")

    # 1. Скрипт целей: функция цели_метрики целиком + её вызов у тега.
    м = re.search(r"(?ms)^def цели_метрики\(номер: str\) -> str:.*?\n(?=\n\n#|\n\n[^ \n])", t)
    if not м:
        raise SystemExit("в шаблоне нет функции цели_метрики — состав изменился")
    функция = м.group(0).rstrip() + "\n"
    список = re.search(r"(?ms)^ЦЕЛИ_МЕТРИКИ = \(.*?^\)\n", t)
    if not список:
        raise SystemExit("в шаблоне нет списка ЦЕЛИ_МЕТРИКИ")

    # 2 и 3: вставки в скрипт плеера — берём из шаблона по якорям.
    и = t.index(ЯКОРЬ_ВОРОНКИ)
    хвост = t[и + len(ЯКОРЬ_ВОРОНКИ):]
    воронка = хвост[:хвост.index("\n  /* Hard failures")]
    if "__sfGoalOnce" not in воронка:
        raise SystemExit("в шаблоне нет целей плеера в воронке состояний")

    и2 = t.index(ЯКОРЬ_ЭЛЕМЕНТА[:len("  host.appendChild(n);")])
    кусок2 = t[и2:и2 + 700]
    м2 = re.search(r"(?s)(  /\* player_start.*?\n  bind\(n, \+\+token\);)", кусок2)
    if not м2:
        raise SystemExit("в шаблоне нет player_start при создании элемента")

    return {
        "объявления": список.group(0) + "\n" + функция,
        "воронка": воронка,
        "элемент": м2.group(1),
    }


def правка(текст: str, куски: dict[str, str]) -> tuple[str, list[str]]:
    """Три вставки НЕЗАВИСИМО: отсутствие одного якоря не отменяет остальные.

    Измерено 15.10 по рабочим копиям витрин: у `lordfilm47.space` и
    `lordserials22.info` все три якоря на месте; у `zonafilm12.site` есть
    только якорь тега — её блок плеера другой; у `animedia.icu` нет ни одного,
    у неё свой рантайм (`animedia-frontend.py`). Единый отказ на первом
    отсутствующем якоре означал бы, что витрина с другим плеером не получает
    даже целей посещения, хотя они от плеера не зависят.

    Что НЕ делается: якорь не угадывается и не ищется «похожий». Отсутствие
    называется строкой отчёта, и решение — за линией витрины.
    """
    шаги: list[str] = []
    if "__sfGoal" in текст:
        return текст, ["уже есть: цели в этой копии доставлены"]

    # 1. Вызов у тега и объявления. Без этого куска остальные бессмысленны:
    #    __sfGoalOnce объявляется именно здесь.
    if текст.count(ЯКОРЬ_ТЕГА) != 1:
        return текст, ["[x] якоря тега Метрики нет (или он не один) — "
                       "цели не доставлены вовсе: точка отправки объявляется "
                       "рядом с тегом"]
    текст = текст.replace(ЯКОРЬ_ТЕГА, ВСТАВКА_ТЕГА, 1)
    j = текст.index(ВСТАВКА_ТЕГА) + len(ВСТАВКА_ТЕГА)
    текст = текст[:j] + "\n\n\n" + куски["объявления"] + текст[j:]
    шаги.append("цели посещения: тег, список и функция отправки")

    # 2. Воронка состояний плеера.
    if текст.count(ЯКОРЬ_ВОРОНКИ) == 1:
        текст = текст.replace(ЯКОРЬ_ВОРОНКИ, ЯКОРЬ_ВОРОНКИ + куски["воронка"], 1)
        шаги.append("player_ready и player_error из воронки состояний")
    else:
        шаги.append("[!] воронки состояний плеера нет — player_ready и "
                    "player_error не доставлены, у этой витрины свой плеер")

    # 3. Создание элемента плеера.
    if текст.count(ЯКОРЬ_ЭЛЕМЕНТА) == 1:
        текст = текст.replace(ЯКОРЬ_ЭЛЕМЕНТА, куски["элемент"], 1)
        шаги.append("player_start при создании элемента")
    else:
        шаги.append("[!] создания элемента плеера нет — player_start не "
                    "доставлен")
    return текст, шаги


ПРИМЕЧАНИЕ = (
    "Отправка целей Метрики (MOD-38): рантайм семейства не содержал ни одного "
    "reachGoal, и у витрин счётчик считал визиты без единого события. Правка "
    "живёт в ячейке по тому же правилу, что правка нажимаемой цели: семейный "
    "рантайм — отдельный выпуск."
)


def закрепить(проект: Path, файл: Path) -> None:
    """Обновить `pins.lock.json` под новый файл рантайма.

    Иначе проверка `pins-match-sources` законно падает: в проекте лежит код,
    которого замок не знает. Прежний `base_sha256` и прежнее примечание
    сохраняются — у этой витрины уже есть своя правка рантайма, и затереть
    память о ней значило бы потерять её объяснение.
    """
    import hashlib
    import json

    замок = проект / "pins.lock.json"
    д = json.loads(замок.read_text(encoding="utf-8"))
    запись = (д.get("files") or {}).get("lords-frontend.py")
    if запись is None:
        raise SystemExit(f"{проект.name}: в замке нет записи о рантайме")
    запись["sha256"] = hashlib.sha256(файл.read_bytes()).hexdigest()
    запись["bytes"] = файл.stat().st_size
    запись["verified_against"] = "правка ячейки поверх git"
    прежнее = (запись.get("note") or "").strip()
    if ПРИМЕЧАНИЕ not in прежнее:
        запись["note"] = (прежнее + " " if прежнее else "") + ПРИМЕЧАНИЕ
    замок.write_text(json.dumps(д, ensure_ascii=False, indent=1) + "\n",
                     encoding="utf-8")


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("sites", nargs="*", help="site_id витрин в var/new-sites")
    р.add_argument("--repo", action="append", default=[], type=Path,
                   help="путь к рабочей копии витрины (для действующих "
                        "витрин, чьи копии лежат вне var/new-sites). Линия "
                        "витрины запускает инструмент на СВОЕЙ копии сама: "
                        "чужую рабочую копию эта сессия не правит")
    р.add_argument("--dry-run", action="store_true")
    опции = р.parse_args(аргв)
    if not опции.sites and not опции.repo:
        р.error("нужен хотя бы один site_id или --repo")

    куски = куски_шаблона()
    print(f"из шаблона взято: объявлений {len(куски['объявления'])} байт, "
          f"воронка {len(куски['воронка'])}, элемент {len(куски['элемент'])}")

    плохо = 0
    цели_правки = [(s, КОРЕНЬ / "var" / "new-sites" / s) for s in опции.sites]
    цели_правки += [(п.name, п) for п in опции.repo]
    for site, проект in цели_правки:
        файл = проект / "src" / "lords-frontend.py"
        if not файл.is_file():
            print(f"[x] {site}: нет {файл}")
            плохо += 1
            continue
        было = файл.read_text(encoding="utf-8")
        стало, шаги = правка(было, куски)
        if опции.dry_run:
            print(f"{site}: {'; '.join(шаги)} (сухой прогон, {len(было)} -> "
                  f"{len(стало)} байт)")
            continue
        if стало == было:
            print(f"{site}: {'; '.join(шаги)}")
            continue
        файл.write_text(стало, encoding="utf-8")
        г = subprocess.run([sys.executable, "-c",
                            "import ast,sys;ast.parse(open(sys.argv[1],encoding='utf-8').read())",
                            str(файл)], capture_output=True, text=True)
        if г.returncode != 0:
            файл.write_text(было, encoding="utf-8")
            print(f"[x] {site}: после правки файл не разбирается, возвращён: "
                  f"{(г.stderr or '')[:200]}")
            плохо += 1
            continue
        закрепить(проект, файл)
        шаги.append("замок версий обновлён")
        print(f"{site}: {'; '.join(шаги)}; {len(было)} -> {len(стало)} байт, "
              "разбор прошёл")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(главное())
