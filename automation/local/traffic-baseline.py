#!/usr/bin/env python3
"""Исходные данные по посещаемости каждой витрины: люди, поиск, расстояние до цели.

Зачем. Цель владельца названа в людях из поиска («настоящие посещения»), а
выгрузка кабинета отвечает четырьмя разными числами: визиты и посетители за
период, суточный ряд с разделением People/Robots и суточный ряд по источникам
с разделением поисковиков. Складывать их в одно «посещаемость» — как раз та
ошибка, из-за которой прошлый недельный отчёт пришлось пересчитывать.

Поэтому здесь по каждому домену печатается раздельно:

* `люди/сутки` — медиана и максимум суточных People за период (роботы отдельно);
* `поиск/сутки` — то же по источнику «Search engine traffic», с разбивкой
  Яндекс/Google;
* `сегодня` — незакрытые сутки, помечены как неполные: сравнивать их с полными
  нельзя;
* `до цели` — сколько людей из поиска в сутки не хватает до порога (по
  умолчанию 5000).

Источник один: `var/analytics/cabinet-latest.json`, выгрузка кабинета Метрики
(только чтение). Чего в выгрузке нет — печатается причиной, а не нулём:
домен без счётчика, выключенный счётчик, недоступный источник. Показатели
Вебмастера (`popular_queries`, `pages_in_search`) в выгрузке есть, но не
измерены — запросы и позиции здесь поэтому не печатаются вовсе, чтобы отчёт не
выглядел полнее, чем он есть.

    python3 automation/local/traffic-baseline.py
    python3 automation/local/traffic-baseline.py --goal 5000 --json
    python3 automation/local/traffic-baseline.py --domain yummyani.site

Коды: 0 — хотя бы один домен измерен; 2 — не измерено ничего (выгрузки нет).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import statistics
import sys

ВЫГРУЗКА = pathlib.Path(
    "/home/claude/wt-portable-site-cell-01/var/analytics/cabinet-latest.json")
ПОРОГ = 5000
ПОИСК = "organic"


def _мера(домен: dict, ключ: str) -> dict | None:
    for м in домен.get("measurements") or []:
        if м.get("key") == ключ:
            return м
    return None


def _ряд_людей(значение) -> tuple[dict[str, float], dict[str, float]]:
    """(People по суткам, Robots по суткам) из `daily_users`."""
    люди, роботы = {}, {}
    for стр in значение or []:
        изм = стр.get("dimensions") or []
        мет = стр.get("metrics") or []
        if len(изм) < 2 or not мет:
            continue
        день = str((изм[0] or {}).get("name") or "")
        кто = str((изм[1] or {}).get("id") or "")
        куда = роботы if кто == "yes" else люди
        куда[день] = куда.get(день, 0.0) + float(мет[0] or 0)
    return люди, роботы


def _ряд_поиска(значение) -> tuple[dict[str, float], dict[str, float]]:
    """(поиск по суткам, поиск по суткам только Яндекс) из `daily_search`."""
    поиск, яндекс = {}, {}
    for стр in значение or []:
        изм = стр.get("dimensions") or []
        мет = стр.get("metrics") or []
        if len(изм) < 2 or not мет:
            continue
        день = str((изм[0] or {}).get("name") or "")
        источник = str((изм[1] or {}).get("id") or "")
        if источник != ПОИСК:
            continue
        сколько = float(мет[0] or 0)
        поиск[день] = поиск.get(день, 0.0) + сколько
        движок = str((изм[2] or {}).get("id") or "") if len(изм) > 2 else ""
        if движок == "yandex":
            яндекс[день] = яндекс.get(день, 0.0) + сколько
    return поиск, яндекс


#: Браузеры, которые НЕ являются человеческим просмотром. Перечень повторяет
#: `automation/local/traffic-segments.py` намеренно: каждый инструмент обязан
#: работать сам по себе, а список короткий и закрытый.
АВТОМАТИЗАЦИЯ = {
    "phantomjs", "puppeteer", "playwright", "selenium", "chrome-lighthouse",
    "curl", "wget", "python-requests", "go-http-client", "scrapy",
}


def автоматизация(браузер: str) -> bool:
    б = браузер.strip().lower()
    return "headless" in б or any(з in б for з in АВТОМАТИЗАЦИЯ)


def профиль_суток(значение) -> dict[str, dict[str, float]]:
    """{дата: {"всего": визиты, "чистые": визиты}} из daily_traffic_profile.

    Профиль несёт браузер и флаг робота, поэтому по нему можно отделить
    автоматические визиты. Суточный ряд посетителей (`daily_users`) этого не
    умеет: в нём есть только People/Robots, а Метрика признала People три
    четверти автоматики.
    """
    итог: dict[str, dict[str, float]] = {}
    for стр in значение or []:
        изм = [str((и or {}).get("name") or "") for и in стр.get("dimensions") or []]
        мет = стр.get("metrics") or []
        if len(изм) < 5 or not мет:
            continue
        дата, браузер, робот = изм[0], изм[3], изм[4]
        визиты = float(мет[0] or 0)
        день = итог.setdefault(дата, {"всего": 0.0, "чистые": 0.0})
        день["всего"] += визиты
        if робот != "Robots" and not автоматизация(браузер):
            день["чистые"] += визиты
    return итог


def _медиана(ряд: dict, дни: list[str]) -> float:
    значения = [ряд.get(д, 0.0) for д in дни]
    return statistics.median(значения) if значения else 0.0


def _макс(ряд: dict, дни: list[str]) -> float:
    значения = [ряд.get(д, 0.0) for д in дни]
    return max(значения) if значения else 0.0


def разобрать(домен: dict, порог: int, окно: int = 7) -> dict:
    итог = {"домен": домен.get("domain"), "счётчик": домен.get("counter_id"),
            "измерено": False, "почему": ""}
    м = _мера(домен, "daily_users")
    if м is None:
        итог["почему"] = "в выгрузке нет суточного ряда посетителей"
        return итог
    if not м.get("measured"):
        итог["почему"] = (f"{м.get('state') or 'не измерено'}"
                          f"{': ' + str(м.get('reason')) if м.get('reason') else ''}")
        return итог
    люди, роботы = _ряд_людей(м.get("value"))
    поиск_м = _мера(домен, "daily_search")
    поиск, яндекс = _ряд_поиска((поиск_м or {}).get("value")) if (
        поиск_м and поиск_м.get("measured")) else ({}, {})
    сег = _мера(домен, "today_users")
    сег_люди, _ = _ряд_людей((сег or {}).get("value")) if (
        сег and сег.get("measured")) else ({}, {})
    сег_п = _мера(домен, "today_search")
    сег_поиск, _ = _ряд_поиска((сег_п or {}).get("value")) if (
        сег_п and сег_п.get("measured")) else ({}, {})

    # Ряд берётся по тем суткам, которые в выгрузке ЕСТЬ, а не по заявленному
    # периоду: заголовок говорит «7daysAgo..yesterday», а суточный ряд приходит
    # длиннее (19.10: 14 суток). Считать медиану по заявленному, а печатать по
    # пришедшему — это и есть сравнение неравных периодов, из-за которого
    # прошлый недельный отчёт пришлось пересчитывать.
    все_дни = sorted(люди)
    дни = все_дни[-окно:] if окно and окно > 0 else все_дни
    итог.update({
        "измерено": True,
        "дней": len(дни),
        "дней_в_выгрузке": len(все_дни),
        "период": f"{дни[0]}..{дни[-1]}" if дни else "",
        "период_выгрузки": f"{все_дни[0]}..{все_дни[-1]}" if все_дни else "",
        "люди_медиана": _медиана(люди, дни),
        "люди_макс": _макс(люди, дни),
        "роботы_медиана": _медиана(роботы, дни),
        "поиск_медиана": _медиана(поиск, дни),
        "поиск_макс": _макс(поиск, дни),
        "поиск_яндекс_медиана": _медиана(яндекс, дни),
        "поиск_измерен": bool(поиск_м and поиск_м.get("measured")),
        "сегодня_люди": sum(сег_люди.values()),
        "сегодня_поиск": sum(сег_поиск.values()),
        "ряд_людей": {д: люди[д] for д in дни},
        "ряд_поиска": {д: поиск.get(д, 0.0) for д in дни},
    })
    профиль_м = _мера(домен, "daily_traffic_profile")
    профиль = (профиль_суток(профиль_м.get("value"))
               if профиль_м and профиль_м.get("measured") else {})
    if профиль:
        дни_п = [д for д in дни if д in профиль]
        всего = {д: профиль[д]["всего"] for д in дни_п}
        чистые = {д: профиль[д]["чистые"] for д in дни_п}
        итог["чистые_медиана"] = _медиана(чистые, дни_п)
        итог["визиты_медиана"] = _медиана(всего, дни_п)
        сумма_всего = sum(всего.values())
        итог["доля_автоматики"] = (
            round(100 * (сумма_всего - sum(чистые.values())) / сумма_всего, 1)
            if сумма_всего else 0.0)
    else:
        итог["чистые_медиана"] = None
        итог["визиты_медиана"] = None
        итог["доля_автоматики"] = None
    итог["до_цели"] = max(0.0, порог - итог["поиск_медиана"])
    итог["дней_выше_цели"] = sum(1 for д in дни if поиск.get(д, 0.0) >= порог)
    return итог


def main(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="исходные данные посещаемости по витринам")
    р.add_argument("--file", default=str(ВЫГРУЗКА))
    р.add_argument("--goal", type=int, default=ПОРОГ,
                   help="порог людей из поиска в сутки (по умолчанию 5000)")
    р.add_argument("--days", type=int, default=7,
                   help="сколько последних полных суток берётся в расчёт (0 — все)")
    р.add_argument("--domain", action="append", default=[])
    р.add_argument("--json", action="store_true")
    дов = р.parse_args(аргв)

    п = pathlib.Path(дов.file)
    try:
        выгрузка = json.loads(п.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        print(f"НЕ ИЗМЕРЕНО: выгрузка кабинета не прочитана ({сбой})")
        return 2

    домены = [д for д in выгрузка.get("domains") or []
              if not дов.domain or д.get("domain") in дов.domain]
    итоги = [разобрать(д, дов.goal, дов.days) for д in домены]
    измерены = [и for и in итоги if и["измерено"]]
    измерены.sort(key=lambda и: и["поиск_медиана"], reverse=True)

    if дов.json:
        print(json.dumps({"собрано": выгрузка.get("collected_at"),
                          "период": выгрузка.get("period"),
                          "порог": дов.goal, "домены": итоги},
                         ensure_ascii=False, indent=2))
        return 0 if измерены else 2

    print(f"выгрузка кабинета Метрики: собрано {выгрузка.get('collected_at')};"
          f" порог {дов.goal} людей из поиска в сутки")
    if измерены:
        о = измерены[0]
        print(f"расчёт по {о['дней']} последним полным суткам ({о['период']});"
              f" в выгрузке суток {о['дней_в_выгрузке']} ({о['период_выгрузки']}),"
              f" а заголовок выгрузки заявляет {выгрузка.get('period')}"
              " — считаем по пришедшим суткам, а не по заявленным")
    print()
    print(f"{'домен':24} {'люди*':>9} {'чистые**':>11} {'автом.':>7}"
          f" {'поиск/сут':>10} {'из них Я':>9} {'дней≥цели':>10} {'до цели':>8}")
    for и in измерены:
        отметка = "" if и["поиск_измерен"] else "  [поиск не измерен]"
        чистые = ("—" if и.get("чистые_медиана") is None
                  else f"{и['чистые_медиана']:.0f}")
        авто = ("—" if и.get("доля_автоматики") is None
                else f"{и['доля_автоматики']:.0f}%")
        # Витрина, где автоматика больше пятой части визитов, помечается: её
        # «люди/сут» читать без очистки нельзя.
        если_шум = (и.get("доля_автоматики") or 0) >= 20
        print(f"{и['домен']:24} {и['люди_медиана']:9.0f} {чистые:>11} {авто:>7}"
              f" {и['поиск_медиана']:10.0f} {и['поиск_яндекс_медиана']:9.0f}"
              f" {и['дней_выше_цели']:10d} {и['до_цели']:8.0f}"
              f"{'  ← автоматика искажает «людей»' if если_шум else ''}{отметка}")
    for и in итоги:
        if not и["измерено"]:
            print(f"{и['домен']:24} НЕ ИЗМЕРЕНО — {и['почему']}")

    print()
    всего_поиск = sum(и["поиск_медиана"] for и in измерены)
    достигли = [и["домен"] for и in измерены if и["поиск_медиана"] >= дов.goal]
    print(f"домены: измерено {len(измерены)} из {len(итоги)};"
          f" суммарно людей из поиска в сутки (медианы) {всего_поиск:.0f}")
    print(f"порог {дов.goal} держат: {', '.join(достигли) if достигли else 'ни одна витрина'}")
    print("* «люди» — ПОСЕТИТЕЛИ (People) из суточного ряда Метрики; ** «чистые» —"
          " ВИЗИТЫ из профиля трафика без роботов и автоматики. Это разные"
          " величины, и сравнивать их между собой нельзя — каждая сравнивается"
          " сама с собой по суткам.")
    print("Колонка «люди» — это People из суточного ряда Метрики, и она ВКЛЮЧАЕТ"
          " автоматику: 19.10 на yummyani.site People числились 53 472 визита"
          " HeadlessChrome. Колонка «чистые/сут» считается по профилю трафика"
          " (браузер и флаг робота) и автоматику исключает.")
    print("Запросы и позиции здесь не печатаются: показатели Вебмастера в выгрузке"
          " не измерены (доступ к host-api закрыт выше нас), и подставлять их нечем.")
    return 0 if измерены else 2


if __name__ == "__main__":
    sys.exit(main())
