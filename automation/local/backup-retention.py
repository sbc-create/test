#!/usr/bin/env python3
"""Срок хранения суточных копий публикатора: план и, по решению владельца, уборка.

Зачем инструмент, а не команда `find -mtime`. Время изменения у этих файлов —
НЕ время копирования: копии делаются `shutil.copy2`, который сохраняет время
исходного файла. Из-за этого `find -mtime` удалил бы не то, а проверка «есть
ли сегодняшняя копия» по времени изменения однажды уже дала у меня ложное
«сегодняшнего бэкапа нет» (копии прогона `daily-20261016T033001Z` лежали на
месте, все 26, со временем 15.10). Надёжный ключ даты — `run_id` в имени
файла, и считает здесь только он.

Что инструмент делает: группирует файлы по дате прогона из имени
(`*.before.daily-YYYYMMDDT…`), оставляет N самых свежих ДАТ и показывает, что
освободится. Чего не делает: не трогает `/srv/backups` (защищённые архивы),
не трогает файлы без `run_id` в имени (происхождение неизвестно — удалять
нечего понятного), не удаляет ничего без `--apply` и отказывается оставить
меньше трёх дат.

Решение о сроке хранения — владельца: это суточные снимки постоянных данных
сайта, и выпуск их только читает (`docs/RUNTIME_DATA_OWNERSHIP.md`).

    python3 automation/local/backup-retention.py --keep-days 7
    python3 automation/local/backup-retention.py --keep-days 7 --apply
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
import os
import re
import sys
from pathlib import Path

ОТЧЁТЫ = Path("/srv/site-factory/repo/var/lords/publish-reports")
#: Сколько полных пар (каталог + подробности) обязано остаться у КАЖДОЙ
#: витрины. Решение владельца от 2026-10-16: не меньше двух.
МИНИМУМ_ПАР = 2

КАТАЛОГ = Path("/srv/site-factory/repo/var/lords/publish-backups")
#: Имя копии: `<витрина>-<вид>.json.before.daily-<дата>T<время>Z`.
ОБРАЗЕЦ = re.compile(r"\.before\.daily-(\d{8})T\d{6}Z$")
МИНИМУМ_ДАТ = 3


def собрать(каталог: Path) -> tuple[dict[str, list[Path]], list[Path]]:
    по_дате: dict[str, list[Path]] = collections.defaultdict(list)
    прочие: list[Path] = []
    for ф in sorted(каталог.iterdir()):
        if not ф.is_file():
            continue
        м = ОБРАЗЕЦ.search(ф.name)
        if м:
            по_дате[м.group(1)].append(ф)
        else:
            прочие.append(ф)
    return dict(по_дате), прочие


def объём(файлы: list[Path]) -> int:
    итог = 0
    for ф in файлы:
        try:
            итог += ф.stat().st_size
        except OSError:
            pass
    return итог


#: Имя копии: `<витрина>-<вид>.json.before.daily-…`, где вид — `catalog` или
#: `details`. Восстановление витрины требует ПАРЫ: каталог без подробностей
#: (и наоборот) даёт несогласованное состояние, поэтому считаются пары, а не
#: файлы.
ВИТРИНА = re.compile(r"^(.+)-(catalog|details)\.json\.before\.daily-"
                     r"(\d{8}T\d{6}Z)$")


def пары(файлы: list[Path]) -> dict[str, dict[str, dict[str, Path]]]:
    """{витрина: {прогон: {вид: файл}}} — для счёта полных пар."""
    итог: dict[str, dict[str, dict[str, Path]]] = {}
    for ф in файлы:
        м = ВИТРИНА.match(ф.name)
        if not м:
            continue
        витрина, вид, прогон = м.group(1), м.group(2), м.group(3)
        итог.setdefault(витрина, {}).setdefault(прогон, {})[вид] = ф
    return итог


def полные(прогоны: dict[str, dict[str, Path]]) -> list[str]:
    """Прогоны, где есть и каталог, и подробности."""
    return sorted((п for п, виды in прогоны.items()
                   if {"catalog", "details"} <= set(виды)), reverse=True)


def пригодна(ф: Path, отчёты: Path) -> tuple[bool, str]:
    """Пригодна ли копия для восстановления — проверкой, а не наличием файла.

    Наличие файла доказательством восстановления не считается (правило
    инфраструктуры). Поэтому: файл непустой, читается как JSON и его sha256
    совпадает с записью в отчёте того прогона, если отчёт есть.
    """
    try:
        данные = ф.read_bytes()
    except OSError as сбой:
        return False, f"не читается: {сбой}"
    if not данные:
        return False, "файл пуст"
    try:
        json.loads(данные.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as сбой:
        return False, f"не разбирается как JSON: {сбой}"
    м = ВИТРИНА.match(ф.name)
    if not м:
        return True, f"{len(данные)} Б, JSON читается (отчёт не сверялся)"
    отчёт = отчёты / f"daily-{м.group(3)}.json"
    if not отчёт.is_file():
        return True, f"{len(данные)} Б, JSON читается (отчёта прогона нет)"
    try:
        о = json.loads(отчёт.read_text(encoding="utf-8"))
    except (OSError, ValueError) as сбой:
        return True, f"{len(данные)} Б, JSON читается (отчёт не разобран: {сбой})"
    ожидание = None
    for зн in (о.get("before_images") or {}).values():
        if зн.get("backup") == str(ф):
            ожидание = зн.get("sha256")
            break
    if not ожидание:
        return True, f"{len(данные)} Б, JSON читается (в отчёте не назван)"
    факт = hashlib.sha256(данные).hexdigest()
    if факт != ожидание:
        return False, "sha256 расходится с отчётом прогона"
    return True, f"{len(данные)} Б, sha256 сошёлся с отчётом"


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--keep-days", type=int, required=True,
                   help="сколько самых свежих ДАТ прогонов оставить")
    р.add_argument("--apply", action="store_true",
                   help="удалить; без него только план")
    р.add_argument("--dir", default=str(КАТАЛОГ), help="каталог копий")
    опции = р.parse_args(аргв)

    каталог = Path(опции.dir)
    if not каталог.is_dir():
        raise SystemExit(f"каталога нет: {каталог}")
    if опции.keep_days < МИНИМУМ_ДАТ:
        raise SystemExit(f"оставить меньше {МИНИМУМ_ДАТ} дат нельзя: точки "
                         "восстановления нужны не в единственном числе")

    по_дате, прочие = собрать(каталог)
    даты = sorted(по_дате)
    if not даты:
        raise SystemExit(f"в {каталог} нет файлов с датой прогона в имени — "
                         "удалять по дате нечего")
    оставить = даты[-опции.keep_days:]
    удалить = даты[:-опции.keep_days] if len(даты) > опции.keep_days else []

    всего = объём([ф for с in по_дате.values() for ф in с]) + объём(прочие)
    освободится = объём([ф for д in удалить for ф in по_дате[д]])
    print(f"каталог: {каталог}")
    print(f"  всего: {всего / 2**30:.2f} ГиБ; дат прогонов: {len(даты)} "
          f"({даты[0]} → {даты[-1]})")
    print(f"  файлов без даты в имени: {len(прочие)} "
          f"({объём(прочие) / 2**30:.2f} ГиБ) — не трогаются")
    print(f"  оставить дат: {len(оставить)} "
          f"({оставить[0]} → {оставить[-1]})")
    print(f"  удалить дат: {len(удалить)}"
          + (f" ({удалить[0]} → {удалить[-1]})" if удалить else ""))
    print(f"  освободится: {освободится / 2**30:.2f} ГиБ "
          f"({sum(len(по_дате[д]) for д in удалить)} файлов)")
    статистика = os.statvfs(каталог)
    свободно = статистика.f_bavail * статистика.f_frsize
    print(f"  свободно сейчас: {свободно / 2**30:.2f} ГиБ; станет около "
          f"{(свободно + освободится) / 2**30:.2f} ГиБ")

    if not удалить:
        print("удалять нечего: дат не больше, чем просили оставить")
        return 0

    # --- Условия владельца проверяются ДО удаления, по витринам ------------
    остающиеся = [ф for д in оставить for ф in по_дате[д]]
    по_витринам = пары(остающиеся)
    print(f"\nвитрин в остающихся копиях: {len(по_витринам)}; "
          f"условие — не меньше {МИНИМУМ_ПАР} полных пар "
          "(каталог + подробности) у каждой")
    отказ = []
    проверено = 0
    for витрина, прогоны in sorted(по_витринам.items()):
        целые = полные(прогоны)
        if len(целые) < МИНИМУМ_ПАР:
            отказ.append(f"{витрина}: полных пар {len(целые)}, нужно "
                         f"{МИНИМУМ_ПАР}")
            continue
        # Свежая копия обязана быть ПРИГОДНОЙ, а не просто лежать.
        свежий = целые[0]
        for вид in ("catalog", "details"):
            ок, пояснение = пригодна(прогоны[свежий][вид], ОТЧЁТЫ)
            проверено += 1
            if not ок:
                отказ.append(f"{витрина} {свежий} {вид}: {пояснение}")
            elif витрина == sorted(по_витринам)[0]:
                print(f"   пример проверки: {витрина} {вид} — {пояснение}")
    print(f"   витрин с достаточным числом пар: "
          f"{len(по_витринам) - len({о.split(':')[0] for о in отказ})}; "
          f"проверено свежих копий: {проверено}")
    if отказ:
        print("\nУДАЛЕНИЕ НЕ ВЫПОЛНЯЕТСЯ — условия владельца не соблюдены:")
        for строка in отказ[:12]:
            print(f"   {строка}")
        return 2

    # Полный список удаляемого — до удаления и в том же выводе.
    print("\nточный список удаляемого (по прогонам):")
    for д in удалить:
        файлы = по_дате[д]
        print(f"   {д}: файлов {len(файлы)}, "
              f"{объём(файлы) / 2**20:.0f} МиБ")
    витрины_удаляемых = sorted(пары([ф for д in удалить for ф in по_дате[д]]))
    print(f"   витрин затронуто: {len(витрины_удаляемых)} "
          f"({', '.join(витрины_удаляемых[:6])}…)")

    if not опции.apply:
        print("\nэто план; для уборки — тот же вызов с --apply")
        return 0

    удалено = 0
    ошибок = 0
    снято = 0
    было_свободно = os.statvfs(каталог).f_bavail * os.statvfs(каталог).f_frsize
    for д in удалить:
        for ф in по_дате[д]:
            try:
                размер = ф.stat().st_size
                ф.unlink()
                удалено += 1
                снято += размер
            except OSError as сбой:
                ошибок += 1
                print(f"   не удалён {ф.name}: {сбой}", file=sys.stderr)
    статистика = os.statvfs(каталог)
    стало = статистика.f_bavail * статистика.f_frsize
    print(f"удалено файлов: {удалено}; ошибок: {ошибок}")
    print(f"снято с диска: {снято / 2**30:.2f} ГиБ "
          f"(сумма размеров удалённых файлов)")
    print(f"свободно было {было_свободно / 2**30:.2f} ГиБ, стало "
          f"{стало / 2**30:.2f} ГиБ — прирост "
          f"{(стало - было_свободно) / 2**30:.2f} ГиБ")
    return 0 if ошибок == 0 else 2


if __name__ == "__main__":
    raise SystemExit(главное())
