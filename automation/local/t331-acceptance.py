#!/usr/bin/env python3
"""Приёмка T331: что браузер выбрал на шести окнах и сколько это весит.

T331 добавила `srcset` с закрытым набором ширин и `sizes` у обложек
`animedia.icu`. Приёмка отвечает на четыре вопроса, и ни один из них не
решается по объявленному в разметке размеру:

1. СТАЛО ЛИ ЛЕГЧЕ. Сравнение идёт по ПЕРЕСЕЧЕНИЮ обложек: один и тот же
   постер (по его UUID) есть и на канарейке, и на контроле
   `animedia.space`, где `srcset` нет. Разные витрины показывают разные
   произведения, поэтому сумма по всей странице сравнивала бы наборы, а не
   доставку.
2. НЕ РАСТЯНУТО ЛИ. Истинная ширина файла меньше, чем ширина отрисовки,
   умноженная на плотность экрана, — это потеря чёткости, а не экономия.
   Истинная ширина берётся из самого файла: `naturalWidth` при `srcset` с
   дескриптором `w` приведён к `sizes` и для этого не годится.
3. НЕ ВЗЯТО ЛИ ЛИШНЕЕ. Файл шире нужного больше чем на запас — это
   оплаченные и не показанные пиксели.
4. ПОМЕНЯЛСЯ ЛИ КОНТРОЛЬ. Системная установка Pillow 23.10 задела весь узел,
   поэтому неизменность контроля надо показать, а не предположить.

    python3 automation/local/t331-acceptance.py \
        --after artifacts/evidence/posters/t331-windows-six-after-20261023.json \
        --before artifacts/evidence/posters/animedia-windows-six-20261023.json
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import statistics
import sys

КАНАРЕЙКА = "animedia.icu"
КОНТРОЛЬ = "animedia.space"

#: Запас к нужному. 1.0 — ровно столько пикселей, сколько показывает экран.
#: Выше 1.1 начинается оплаченное и не показанное; ниже 1.0 — растяжение.
ЗАПАС_ЛИШНЕГО = 1.1

UUID = re.compile(r"([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})")


def ключ_постера(адрес: str) -> str | None:
    м = UUID.search(адрес or "")
    return м.group(1) if м else None


def загрузить(путь: pathlib.Path, *, только_выбранные: bool = True
              ) -> list[dict]:
    """Строки замера. По умолчанию — ТОЛЬКО те, где браузер действительно
    выбрал источник.

    У отложенной картинки, до которой прокрутка не дошла, `currentSrc` пуст,
    и прежний замер подставлял `src` — то есть разметку. 23.10 из-за этого
    экономия веса была приписана кандидатам `srcset`, хотя для таких строк
    сравнивались обычный адрес канарейки (после T330 ограничен 480 px) и
    обычный адрес контроля (исходник). Старые выгрузки поля `выбрано` не
    имеют: для них фильтр не применяется, и об этом печатается строка.
    """
    строки = [с for с in json.loads(путь.read_text("utf-8"))
              if "показ_ш" in с]
    если_есть = [с for с in строки if "выбрано" in с]
    if not если_есть:
        print("ВНИМАНИЕ: в выгрузке %s нет поля «выбрано» — отличить выбор"
              " браузера от разметки невозможно, числа по ней смешивают"
              " T330 и срочность" % путь.name)
        return строки
    if not только_выбранные:
        return строки
    выбранные = [с for с in строки if с.get("выбрано")]
    print("строк в замере %d, из них с настоящим выбором браузера %d"
          " (остальные — отложенные картинки, до которых прокрутка не дошла)"
          % (len(строки), len(выбранные)))
    return выбранные


def сводка_доставки(строки: list[dict]) -> None:
    print("=" * 78)
    print("1. ЧТО ПРИШЛО НА КАЖДОМ ОКНЕ (истинные пиксели файла)")
    print("%-16s %-9s %-6s %5s %7s %8s %8s %8s"
          % ("домен", "страница", "окно", "обл", "нужно", "истинная",
             "медиана", "вес КиБ"))
    for домен in (КАНАРЕЙКА, КОНТРОЛЬ):
        for страница in ("главная", "каталог", "карточка"):
            for окно in (390, 700, 768, 1024, 1280, 1440):
                свои = [с for с in строки
                        if с["домен"] == домен and с["страница"] == страница
                        and с["окно"] == окно and с.get("истинная_ш")]
                if not свои:
                    continue
                нужно = statistics.median(с["нужно_px"] for с in свои)
                истинные = [с["истинная_ш"] for с in свои]
                вес = sum(с.get("байт_файла") or 0 for с in свои) / 1024
                print("%-16s %-9s %-6s %5d %7.0f %8d %8.0f %8.0f"
                      % (домен, страница, окно, len(свои), нужно,
                         max(истинные), statistics.median(истинные), вес))


def сравнение_по_пересечению(строки: list[dict]) -> int:
    print("=" * 78)
    print("2. ПЕРЕСЕЧЕНИЕ: один и тот же постер на канарейке и на контроле")
    потяжелело_всего = 0
    for страница in ("главная", "каталог", "карточка"):
        for окно in (390, 700, 768, 1024, 1280, 1440):
            к = {ключ_постера(с["адрес"]): с for с in строки
                 if с["домен"] == КАНАРЕЙКА and с["страница"] == страница
                 and с["окно"] == окно and с.get("байт_файла")}
            ц = {ключ_постера(с["адрес"]): с for с in строки
                 if с["домен"] == КОНТРОЛЬ and с["страница"] == страница
                 and с["окно"] == окно and с.get("байт_файла")}
            общие = sorted(set(к) & set(ц) - {None})
            if not общие:
                continue
            легче = [п for п in общие
                     if к[п]["байт_файла"] < ц[п]["байт_файла"]]
            тяжелее = [п for п in общие
                       if к[п]["байт_файла"] > ц[п]["байт_файла"]]
            равно = len(общие) - len(легче) - len(тяжелее)
            было = sum(ц[п]["байт_файла"] for п in общие)
            стало = sum(к[п]["байт_файла"] for п in общие)
            потяжелело_всего += len(тяжелее)
            print("%-9s окно %-5s общих %3d  легче %3d  так же %3d"
                  "  ТЯЖЕЛЕЕ %2d   %7.0f → %7.0f КиБ  %+6.1f%%"
                  % (страница, окно, len(общие), len(легче), равно,
                     len(тяжелее), было / 1024, стало / 1024,
                     (стало - было) * 100.0 / было if было else 0))
            for п in тяжелее[:3]:
                print("     ПОТЯЖЕЛЕЛО %s: %d → %d Б (%d px → %d px)"
                      % (п[:8], ц[п]["байт_файла"], к[п]["байт_файла"],
                         ц[п]["истинная_ш"] or 0, к[п]["истинная_ш"] or 0))
    return потяжелело_всего


def растяжение_и_лишнее(строки: list[dict]) -> list[str]:
    """Растяжение канарейки против контроля ПО ПЕРЕСЕЧЕНИЮ постеров.

    Требовать ноль нельзя: растяжение есть и на контроле, потому что у части
    постеров исходник сам меньше нужного — это предел поставщика, а не
    доставки. Сравнивать по всему набору тоже нельзя: наборы произведений у
    витрин разные. Первая версия этой проверки сравнивала наборы и назвала
    хуже контроля карточку на окнах 390 и 768 (2 из 25 против 1 из 25);
    на пересечении там 0 против 0 — разница была разницей наборов.
    """
    print("=" * 78)
    print("3. РАСТЯЖЕНИЕ ПО ПЕРЕСЕЧЕНИЮ (файл уже, чем ширина показа × DPR)")
    print("%-9s %-6s %6s  %-14s %-14s %s"
          % ("страница", "окно", "общих", "канарейка", "контроль", "вердикт"))
    хуже = []
    for страница in ("главная", "каталог", "карточка"):
        for окно in (390, 700, 768, 1024, 1280, 1440):
            def карта(домен):
                итог = {}
                for с in строки:
                    if (с["домен"] == домен and с["страница"] == страница
                            and с["окно"] == окно and с.get("истинная_ш")):
                        ключ = ключ_постера(с["адрес"])
                        if ключ:
                            итог[ключ] = с
                return итог

            к, ц = карта(КАНАРЕЙКА), карта(КОНТРОЛЬ)
            общие = sorted(set(к) & set(ц))
            if not общие:
                continue
            кр = sum(1 for п in общие
                     if к[п]["истинная_ш"] < к[п]["нужно_px"])
            цр = sum(1 for п in общие
                     if ц[п]["истинная_ш"] < ц[п]["нужно_px"])
            кл = sum(1 for п in общие
                     if к[п]["истинная_ш"] > к[п]["нужно_px"] * ЗАПАС_ЛИШНЕГО)
            цл = sum(1 for п in общие
                     if ц[п]["истинная_ш"] > ц[п]["нужно_px"] * ЗАПАС_ЛИШНЕГО)
            плохо = кр > цр
            if плохо:
                хуже.append("%s окно %s: растянуто %d из %d против %d"
                            % (страница, окно, кр, len(общие), цр))
            print("%-9s %-6s %6d  растянуто %-4d растянуто %-4d %s"
                  "   (лишнее %d против %d)"
                  % (страница, окно, len(общие), кр, цр,
                     "ХУЖЕ КОНТРОЛЯ" if плохо
                     else ("лучше" if кр < цр else "так же"), кл, цл))
    return хуже


def контроль_без_уменьшения(строки: list[dict]) -> bool:
    """Решающий признак неизменности контроля.

    Системная установка Pillow 23.10 задела весь узел, и неизменность
    контроля надо показать. Сравнение распределений ширины для этого не
    годится: прежний замер хранил ширину только у обложек, успевших
    загрузиться (38 значений против 117 сейчас), и дал бы «изменился» на
    разнице охвата. Признак прямой: если уменьшение включилось бы и на
    контроле, ни один файл там не был бы шире предела T330 — 480 px.
    """
    print("=" * 78)
    print("4. КОНТРОЛЬ: включилось ли уменьшение на animedia.space")
    ц = [с for с in строки
         if с["домен"] == КОНТРОЛЬ and с.get("истинная_ш")]
    шире_предела = [с for с in ц if с["истинная_ш"] > 480]
    ровно_предел = [с for с in ц if с["истинная_ш"] == 480]
    макс = max((с["истинная_ш"] for с in ц), default=0)
    print("   обложек %d, шире предела T330 (480 px): %d, ровно 480: %d,"
          " максимум %d px"
          % (len(ц), len(шире_предела), len(ровно_предел), макс))
    цело = bool(шире_предела)
    print("   %s" % ("контроль отдаёт исходники — уменьшение на нём НЕ"
                     " включилось" if цело else
                     "ВНИМАНИЕ: ни одного файла шире 480 px — уменьшение"
                     " могло включиться и на контроле"))
    print("   прямое сравнение адресов до/после на контроле уже записано:"
          " artifacts/evidence/posters/t330-acceptance-20261023.txt"
          " (0 уменьшено, 0 потяжелело, 1.15 → 1.15 МиБ)")
    return цело


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--after", required=True)
    р.add_argument("--before", required=True)
    а = р.parse_args(аргв)
    после = загрузить(pathlib.Path(а.after))
    до = загрузить(pathlib.Path(а.before))
    print("замеров после %d, до %d" % (len(после), len(до)))
    сводка_доставки(после)
    потяжелело = сравнение_по_пересечению(после)
    хуже = растяжение_и_лишнее(после)
    контроль_цел = контроль_без_уменьшения(после)
    print("=" * 78)
    print("ИТОГ ПРИЁМКИ")
    print("  потяжелевших в пересечении: %d — %s"
          % (потяжелело, "условие выполнено" if not потяжелело
             else "УСЛОВИЕ НАРУШЕНО"))
    print("  разрезов, где канарейка растягивает ХУЖЕ контроля: %d — %s"
          % (len(хуже), "условие выполнено" if not хуже
             else "УСЛОВИЕ НАРУШЕНО"))
    for строка in хуже:
        print("     " + строка)
    print("  контроль: %s"
          % ("уменьшение не включилось" if контроль_цел
             else "МОГЛО ИЗМЕНИТЬСЯ, сравнение с ним требует оговорки"))
    годно = not потяжелело and not хуже and контроль_цел
    print("ЗАВЕРШЕНО: приёмка %s" % ("ПРОЙДЕНА" if годно else "НЕ ПРОЙДЕНА"),
          file=sys.stderr)
    return 0 if годно else 1


if __name__ == "__main__":
    sys.exit(main())
