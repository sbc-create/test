#!/usr/bin/env python3
"""Готовы ли ИЗМЕРЕНИЯ домена: один ответ на три системы, три состояния каждая.

Зачем ещё один инструмент, когда есть `analytics-freshness.py`,
`analytics-schedule-proof.py` и манифест Topvisor. Каждый из них отвечает на
свой вопрос и отвечает хорошо, но ни один не отвечает на тот, который задаёт
владелец перед приёмкой домена: «можно ли по этому домену что-то утверждать?»
Пока ответ собирается глазами из трёх мест, он собирается не каждый раз.

Поэтому здесь НЕТ ни нового реестра, ни новой очереди: состав домéнов берётся
из паспортов ячеек, конфигурация — из `config/analytics.json` и манифеста
Topvisor, расписание — из юнитов systemd и их метки времени, данные — из
артефактов сбора. Логика окна таймера и различимости статусов не
переписывается: она импортируется из тех же двух инструментов.

Три состояния на каждую систему различаются намеренно, потому что их
постоянно путают:

  НАСТРОЕНО       объект заведён (счётчик, хост, проект) — но это ещё не данные
  ДАННЫЕ ЕСТЬ     в последнем сборе по этому домену есть измеренное значение
  РАСПИСАНИЕ      следующий штатный сбор подтверждён не ручным прогоном

«Проект создан» в состояние «данные есть» не превращается ни при каких
условиях: именно эта подмена однажды дала отчёт о домене, которого не было в
сборе вовсе.

Недоступный источник (каталог артефактов в другом рабочем дереве, закрытый
каталог) печатается как НЕ ИЗМЕРЕНО с причиной, а не как «нет»: это разные
утверждения, и второе врёт.

    python3 automation/local/measurement-readiness.py
    python3 automation/local/measurement-readiness.py --domain lordserial33.biz
    python3 automation/local/measurement-readiness.py --json
"""
from __future__ import annotations

import argparse
import datetime as _dt
import importlib.util
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))

РЕЕСТР_ЯЧЕЕК = КОРЕНЬ / "config" / "site-cells.json"
РЕЕСТР_АНАЛИТИКИ = КОРЕНЬ / "config" / "analytics.json"
#: Артефакты сбора пишет служба из своего рабочего дерева (MOD-198), поэтому
#: путь задаётся, а не угадывается; отсутствие каталога — причина, не ноль.
АРТЕФАКТЫ = pathlib.Path("/home/claude/wt-portable-site-cell-01/artifacts/analytics")
ЮНИТЫ = pathlib.Path("/etc/systemd/system")
МЕТКИ = pathlib.Path("/var/lib/systemd/timers")

НЕТ_ДАННЫХ = "НЕ ИЗМЕРЕНО"


def _модуль(имя: str):
    путь = КОРЕНЬ / "automation" / "local" / f"{имя}.py"
    сп = importlib.util.spec_from_file_location(имя.replace("-", "_"), путь)
    м = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(м)
    return м


def домены() -> list[dict]:
    """Публичные домены из паспортов: состав берётся там, где он уже есть."""
    данные = json.loads(РЕЕСТР_ЯЧЕЕК.read_text(encoding="utf-8"))
    итог = []
    for я in данные.get("cells") or []:
        домен = str(я.get("domain") or "")
        if not домен or домен.endswith((".test", ".localhost", ".invalid")):
            continue
        if (я.get("withdrawal") or {}).get("withdrawn"):
            continue
        итог.append(я)
    return sorted(итог, key=lambda я: я["domain"])


def запись_аналитики(домен: str) -> dict | None:
    try:
        данные = json.loads(РЕЕСТР_АНАЛИТИКИ.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    for з in данные.get("properties") or []:
        if з.get("domain") == домен:
            return з
    return None


def последний_сбор(каталог: pathlib.Path) -> tuple[dict | None, str]:
    """Самый свежий артефакт сбора и причина, если его нет."""
    if not каталог.is_dir():
        return None, f"каталог артефактов недоступен: {каталог}"
    файлы = sorted(каталог.glob("analytics-*.json"))
    if not файлы:
        return None, f"в {каталог} нет артефактов сбора"
    последний = файлы[-1]
    try:
        return json.loads(последний.read_text(encoding="utf-8")), последний.name
    except (OSError, ValueError) as ош:
        return None, f"{последний.name} не читается: {type(ош).__name__}"


#: Показатели, без которых утверждать о домене нечего. Перечень короткий
#: намеренно: «18 из 23 измерено» звучит хорошо и при этом может не содержать
#: ни одного показателя, по которому судят о трафике.
ОПОРНЫЕ = ("visitors", "visits", "pageviews")


def измерено_по_домену(сбор: dict | None, домен: str) -> tuple[str, str]:
    """Есть ли в сборе измеренное значение по этому домену.

    Форма артефакта прочитана, а не угадана: `domains[].measurements` — это
    СПИСОК записей с полями `key`, `measured`, `value`, `reason`. Первая
    редакция этой функции искала вложенные словари в самой записи домена и
    печатала «в записи домена нет измерений» там, где измерено 18 из 23, —
    то есть сама давала ложный пробел. Проверено на рабочем артефакте.
    """
    if not сбор:
        return НЕТ_ДАННЫХ, "сбора нет"
    for з in сбор.get("domains") or сбор.get("sites") or []:
        if з.get("domain") != домен:
            continue
        изм = з.get("measurements")
        if isinstance(изм, list):
            по_ключу = {и.get("key"): и for и in изм if isinstance(и, dict)}
        elif isinstance(изм, dict):
            по_ключу = изм
        else:
            по_ключу = {к: v for к, v in з.items()
                        if isinstance(v, dict) and "measured" in v}
        if not по_ключу:
            return НЕТ_ДАННЫХ, "в записи домена нет измерений"
        опора = [к for к in ОПОРНЫЕ if (по_ключу.get(к) or {}).get("measured")]
        всего = len(по_ключу)
        есть = sum(1 for v in по_ключу.values() if v.get("measured"))
        if опора:
            значения = ", ".join(
                f"{к}={по_ключу[к].get('value')}" for к in опора)
            return "ДАННЫЕ ЕСТЬ", f"{значения}; измерено {есть} из {всего}"
        причины = [f"{к}: {str((по_ключу.get(к) or {}).get('reason') or 'нет записи')[:40]}"
                   for к in ОПОРНЫЕ]
        return НЕТ_ДАННЫХ, (f"измерено {есть} из {всего}, но ни одного опорного "
                            f"показателя: {'; '.join(причины)}")
    return НЕТ_ДАННЫХ, "домена нет в сборе — это и есть пробел, а не ноль"


def расписание(юнит: str) -> tuple[str, str]:
    """Подтверждено ли следующее штатное срабатывание таймера."""
    файл = ЮНИТЫ / юнит
    if not файл.is_file():
        return НЕТ_ДАННЫХ, f"юнита {юнит} нет"
    включён = (ЮНИТЫ / "timers.target.wants" / юнит).exists()
    метка = МЕТКИ / f"stamp-{юнит}"
    когда = None
    if метка.exists():
        когда = _dt.datetime.fromtimestamp(метка.stat().st_mtime, _dt.timezone.utc)
    if not включён:
        return НЕТ_ДАННЫХ, f"{юнит} не включён (symlink в timers.target.wants отсутствует)"
    if когда is None:
        return "РАСПИСАНИЕ", f"{юнит} включён, срабатываний ещё не было"
    часов = (_dt.datetime.now(_dt.timezone.utc) - когда).total_seconds() / 3600
    return "РАСПИСАНИЕ", f"{юнит} включён, последнее срабатывание {когда:%Y-%m-%d %H:%MZ} ({часов:.0f} ч назад)"


#: Дерево, из которого работает служба сбора: там же лежит и её манифест.
ДЕРЕВО_СЛУЖБЫ = pathlib.Path("/home/claude/wt-portable-site-cell-01")


def _проект_topvisor(домен: str, дерево: pathlib.Path):
    """Проект Topvisor по домену из манифеста НАЗВАННОГО дерева."""
    путь = дерево / "factory" / "topvisor" / "manifest.py"
    if not путь.is_file():
        return None, f"манифеста нет по пути {путь}"
    # Два условия, без которых модуль из ЧУЖОГО дерева не загружается, и оба
    # выяснены измерением, а не догадкой:
    #   * корень того дерева должен стоять в sys.path первым — манифест
    #     импортирует `factory.contact`, и без этого подхватился бы мой;
    #   * модуль обязан попасть в sys.modules ДО exec_module — иначе
    #     `@dataclass` внутри него падает с `AttributeError: 'NoneType'
    #     object has no attribute '__dict__'` (dataclasses ищет модуль класса
    #     в sys.modules). Проверено на манифесте линии SEO.
    имя = "topvisor_manifest_внешний"
    прежний_путь = list(sys.path)
    прежний_модуль = sys.modules.get(имя)
    try:
        sys.path.insert(0, str(дерево))
        сп = importlib.util.spec_from_file_location(имя, путь)
        м = importlib.util.module_from_spec(сп)
        sys.modules[имя] = м
        сп.loader.exec_module(м)
        return м.by_domain(домен), ""
    except Exception as ош:  # noqa: BLE001 — причина важнее типа
        return None, f"манифест {путь} не прочитан: {type(ош).__name__}: {ош}"
    finally:
        sys.path[:] = прежний_путь
        if прежний_модуль is None:
            sys.modules.pop(имя, None)
        else:
            sys.modules[имя] = прежний_модуль


def по_домену(я: dict, сбор: dict | None, пояснение: str,
              дерево_манифеста: pathlib.Path = ДЕРЕВО_СЛУЖБЫ) -> dict:
    домен = я["domain"]
    итог = {"домен": домен, "site_id": я["site_id"], "статус_ячейки": я.get("status"),
            "системы": {}}

    # --- Метрика -----------------------------------------------------------
    з = запись_аналитики(домен)
    if з is None:
        метрика = {"настроено": НЕТ_ДАННЫХ,
                   "почему": "домена нет в config/analytics.json — счётчика ему не создадут"}
    elif з.get("counter_id"):
        метрика = {"настроено": "НАСТРОЕНО",
                   "почему": f"счётчик {з['counter_id']}, состояние {з.get('counter_state')}, "
                             f"вебвизор {'вкл' if з.get('webvisor') else 'выкл'}"}
    else:
        метрика = {"настроено": НЕТ_ДАННЫХ,
                   "почему": f"объявлен ({з.get('counter_state')}), счётчика нет — "
                             "это вход владельца, а не ошибка сбора"}
    данные, причина = измерено_по_домену(сбор, домен)
    метрика["данные"] = данные
    метрика["данные_почему"] = f"{причина} ({пояснение})"
    метрика["расписание"], метрика["расписание_почему"] = расписание("analytics-cabinet.timer")
    итог["системы"]["метрика"] = метрика

    # --- Вебмастер ---------------------------------------------------------
    # Два поля про разное, и путать их нельзя: `verification_status` — ответ
    # ЯНДЕКСА о правах, `enabled` — наше решение собирать по этому домену.
    # Первая редакция требовала оба и печатала «состояние прав VERIFIED» рядом
    # с отказом — у animedia.icu права подтверждены, а сбор у нас выключен.
    вм = (з or {}).get("webmaster") or {}
    if з is None:
        состояние = (НЕТ_ДАННЫХ, "записи домена нет вовсе")
    elif вм.get("verification_status") == "VERIFIED" and вм.get("host_id"):
        хвост = ("" if вм.get("enabled") else
                 "; сбор по домену у нас ВЫКЛЮЧЕН (enabled: false) — это наше решение, не отказ сервиса")
        состояние = ("НАСТРОЕНО",
                     f"host_id {вм.get('host_id')}, права VERIFIED, "
                     f"sitemap отправлен: {'да' if вм.get('sitemap_submitted') else 'нет'}{хвост}")
    else:
        состояние = (НЕТ_ДАННЫХ,
                     f"права: {вм.get('verification_status', 'нет поля')}, "
                     f"host_id: {вм.get('host_id') or 'нет'}")
    # Вебмастер опрашивает суточный сбор кабинета (`analytics_collect`:
    # WEBMASTER_RESOURCES), а не отдельный юнит. Первая редакция искала
    # `webmaster-inventory.timer` и печатала «таймера нет» — это ручной опрос,
    # у него таймера и не должно быть. Поправку дала линия SEO, проверено:
    # в последнем cabinet-latest.json 75 измерений Вебмастера с причиной
    # «сеть недоступна (URLError)», то есть расписание работает, а данных нет
    # из-за B023. Разница существенная: «нет расписания» требует завести
    # таймер, «нет данных» — снять сетевое ограничение.
    расп_вм = расписание("analytics-cabinet.timer")
    итог["системы"]["вебмастер"] = {
        "настроено": состояние[0], "почему": состояние[1],
        "данные": НЕТ_ДАННЫХ,
        "данные_почему": "сеть до api.webmaster.yandex.net закрыта вне наших машин "
                         "(B023, измерено 26.10 на двух узлах) — поисковые данные недоступны",
        "расписание": расп_вм[0], "расписание_почему": расп_вм[1],
    }

    # --- Topvisor ----------------------------------------------------------
    # Манифест Topvisor читается ИЗ НАЗВАННОГО ДЕРЕВА и дерево печатается.
    # Причина измерена 26.10: служба сбора работает из рабочей копии линии SEO
    # (MOD-198), и состав проектов там ДРУГОЙ — animedia.icu в их манифесте
    # есть, в моей ветви нет. Инструмент, читающий артефакты из одного дерева,
    # а конфигурацию из другого, печатает смесь двух состояний и называет
    # пробелом то, чего в работающей системе нет.
    проект, ош_текст = _проект_topvisor(домен, дерево_манифеста)
    if проект is None:
        тв = {"настроено": НЕТ_ДАННЫХ,
              "почему": ош_текст or "домена нет в манифесте Topvisor — "
                                    "он не попадёт ни в план, ни в отчёт"}
    else:
        запросов = sum(len(г.keywords) for г in проект.groups)
        тв = {"настроено": "НАСТРОЕНО",
              "почему": f"проект описан: {len(проект.groups)} групп, {запросов} запросов, "
                        f"счётчик Метрики {проект.metrika_counter or 'не связан'}"}
    тв["данные"] = НЕТ_ДАННЫХ
    тв["данные_почему"] = ("съём позиций не включён: поисковики проектам не назначены, "
                           "бюджет 0 — значит позиций нет, а не «позиции нулевые»")
    тв["расписание"], тв["расписание_почему"] = расписание("topvisor-check.timer")
    итог["системы"]["topvisor"] = тв

    готово = all(с.get("настроено") == "НАСТРОЕНО" and с.get("данные") == "ДАННЫЕ ЕСТЬ"
                 for с in итог["системы"].values())
    итог["готовность"] = "ГОТОВО" if готово else "НЕ ГОТОВО"
    return итог


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[],
                   help="проверить только эти домены")
    р.add_argument("--artifacts", type=pathlib.Path, default=АРТЕФАКТЫ)
    р.add_argument("--manifest-tree", type=pathlib.Path, default=ДЕРЕВО_СЛУЖБЫ,
                   help="дерево, из которого читать манифест Topvisor "
                        "(по умолчанию — дерево работающей службы сбора)")
    р.add_argument("--json", action="store_true")
    а = р.parse_args(аргв)

    сбор, пояснение = последний_сбор(а.artifacts)
    записи = [я for я in домены() if not а.domain or я["domain"] in а.domain]
    итоги = [по_домену(я, сбор, пояснение, а.manifest_tree) for я in записи]

    if а.json:
        print(json.dumps({"artifacts": str(а.artifacts), "сбор": пояснение,
                          "manifest_tree": str(а.manifest_tree),
                          "домены": итоги}, ensure_ascii=False, indent=1))
    else:
        print(f"артефакты сбора: {пояснение}")
        print(f"манифест Topvisor прочитан из: {а.manifest_tree}")
        print(f"{'домен':24} {'ячейка':12} метрика / вебмастер / topvisor")
        for и in итоги:
            кратко = " | ".join(
                f"{имя}: {с['настроено'][:9]}/{с['данные'][:11]}/{с['расписание'][:10]}"
                for имя, с in и["системы"].items())
            print(f"{и['домен']:24} {и['статус_ячейки'] or '?':12} {и['готовность']:9} {кратко}")
        не_готовы = [и for и in итоги if и["готовность"] != "ГОТОВО"]
        print(f"\nдомéнов {len(итоги)}, готовы {len(итоги) - len(не_готовы)}")
        for и in не_готовы[:40]:
            for имя, с in и["системы"].items():
                for поле, почему in (("настроено", "почему"),
                                     ("данные", "данные_почему"),
                                     ("расписание", "расписание_почему")):
                    if с[поле] != ("НАСТРОЕНО" if поле == "настроено" else
                                   "ДАННЫЕ ЕСТЬ" if поле == "данные" else "РАСПИСАНИЕ"):
                        print(f"  {и['домен']:22} {имя:10} {поле:11} {с[почему][:110]}")
    # Ненулевой код — когда хоть один домен не готов: это ворота, а не отчёт.
    return 0 if all(и["готовность"] == "ГОТОВО" for и in итоги) else 3


if __name__ == "__main__":
    raise SystemExit(главная())
