def домены() -> list[dict]:
    """Публичные домены из паспортов: состав берётся там, где он уже есть."""
    данные = json.loads(РЕЕСТР_ЯЧЕЕК.read_text(encoding="utf-8"))
    итог = []
    for я in данные.get("cells") or []:
        домен = str(я.get("domain") or "")
        if not домен or домен.endswith((".test", ".localhost", ".invalid")):
            continue
        if (я.get("withdrawal") or {}).get("withdrawn"):
            continue
        итог.append(я)
    return sorted(итог, key=lambda я: я["domain"])


def запись_аналитики(домен: str) -> dict | None:
    try:
        данные = json.loads(РЕЕСТР_АНАЛИТИКИ.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    for з in данные.get("properties") or []:
        if з.get("domain") == домен:
            return з
    return None


def последний_сбор(каталог: pathlib.Path) -> tuple[dict | None, str]:
    """Самый свежий артефакт сбора и причина, если его нет."""
    if not каталог.is_dir():
        return None, f"каталог артефактов недоступен: {каталог}"
    файлы = sorted(каталог.glob("analytics-*.json"))
    if not файлы:
        return None, f"в {каталог} нет артефактов сбора"
