#: Окно, в которое поставщик вообще ПОЗВОЛЯЕТ запускать проверки позиций в
#: Яндексе. Прочитано 2026-10-26 в справке Topvisor
#: (topvisor.com/ru/support/rankings/se/ и /rankings/): «Проверки в Яндекс
#: Search API частично возобновлены. Запустить их можно и вручную, и
#: автоматически в период с 20:00 по 05:59 по московскому времени. Для
#: проверок, запущенных между 20:00 и 23:59, данные будут доступны в проектах
#: не ранее полуночи».
#:
#: Зачем проверять. Таймер, поставленный на дневной час, не отказывает громко:
#: он просто не соберёт позиций, и готовность будет выглядеть как «съём
#: настроен». Границы в UTC, потому что OnCalendar у наших юнитов в UTC.
ОКНО_ЯНДЕКС_НАЧАЛО_UTC = 17          # 20:00 МСК
ОКНО_ЯНДЕКС_КОНЕЦ_UTC = 3            # 05:59 МСК, то есть до 03:00 UTC включительно по часу


def окно_съёма_позиций(текст_юнита: str) -> tuple[str, str]:
    """Попадает ли расписание юнита в окно поставщика. Три исхода, не два.

    ПРИМЕНЯЕТСЯ ТОЛЬКО К СЪЁМУ ПОЗИЦИЙ. Окно ограничивает запуск проверок в
    Яндекс Search API, а не любую работу с Topvisor: `topvisor-measure`
    (настройки, история позиций, цена) читает уже собранные данные, и его
    дневное расписание дефектом не является. Применить окно к нему значило бы
    выдать ложный запрет.
    """
    часы = re.findall(r"OnCalendar=.*?(\d{2}):(\d{2}):\d{2}\s*UTC", текст_юнита)
    if not часы:
        return НЕТ_ДАННЫХ, "в юните нет OnCalendar в UTC — окно проверить нечем"
    внутри, снаружи = [], []
    for ч, м in часы:
        час = int(ч)
        (внутри if (час >= ОКНО_ЯНДЕКС_НАЧАЛО_UTC or час < ОКНО_ЯНДЕКС_КОНЕЦ_UTC)
         else снаружи).append(f"{ч}:{м} UTC")
    if снаружи and not внутри:
        return "НЕТ", (f"расписание {', '.join(снаружи)} ВНЕ окна поставщика "
                       f"(20:00–05:59 МСК = {ОКНО_ЯНДЕКС_НАЧАЛО_UTC}:00–0"
                       f"{ОКНО_ЯНДЕКС_КОНЕЦ_UTC}:00 UTC): проверки позиций "
                       "в Яндексе в это время не запускаются")
    if снаружи:
        return "ЧАСТИЧНО", (f"в окне {', '.join(внутри)}; вне окна "
                            f"{', '.join(снаружи)} — эти запуски позиций не дадут")
    return "ДА", (f"расписание {', '.join(внутри)} внутри окна поставщика "
                  "(20:00–05:59 МСК); данные по запускам 20:00–23:59 МСК "
                  "появляются не ранее полуночи")


def _topvisor_снимок(каталог: pathlib.Path) -> dict:
    """Здоровье прогона, строки по домéнам и тревога — как их записала служба."""
    итог = {"здоровье": None, "строки": {}, "тревога": None, "расхождение": None,
            "почему_нет": ""}
    if not каталог.is_dir():
        итог["почему_нет"] = f"каталога состояния {каталог} нет"
        return итог
    try:
        итог["здоровье"] = json.loads((каталог / "health.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        итог["почему_нет"] = f"health.json не читается: {ош}"
    try:
        матрица = json.loads((каталог / "mapping-matrix.json").read_text(encoding="utf-8"))
        строки = матрица.get("rows") or []
        итог["строки"] = {с.get("canonical_domain"): с for с in строки if с.get("canonical_domain")}
        # Две меры одного предмета: сводка и сами строки. Расхождение
        # объясняется ДО выбора числа — иначе в отчёт попадёт то из двух,
        # которое удобнее (класс 47 в docs/RECURRING_FAILURES.md).
        сводка = (матрица.get("mapping_summary") or {}).get("MAPPED_EXACT_COUNT")
        точных = sum(1 for с in строки if с.get("mapping_state") == "MATCHED_EXACT")
        if сводка is not None and сводка != точных:
            итог["расхождение"] = (
                f"сводка матрицы говорит MAPPED_EXACT_COUNT={сводка}, а строк с "
                f"mapping_state=MATCHED_EXACT ровно {точных}; разницу даёт "
                "ZERO_QUERIES — проект есть, запросов нет. Для готовности "
                "измерений это разные состояния, поэтому берётся строка домена, "
                "а не сводка")
    except (OSError, ValueError) as ош:
        итог["почему_нет"] = (итог["почему_нет"] + "; " if итог["почему_нет"] else "") + \
            f"mapping-matrix.json не читается: {ош}"
    try:
        тревога = json.loads((каталог / "alert.json").read_text(encoding="utf-8"))
        итог["тревога"] = тревога if тревога.get("active") else None
    except (OSError, ValueError):
        pass
    return итог


def _проект_topvisor(домен: str, дерево: pathlib.Path):
    """Проект Topvisor по домену из манифеста НАЗВАННОГО дерева."""
    путь = дерево / "factory" / "topvisor" / "manifest.py"
    if not путь.is_file():
        return None, f"манифеста нет по пути {путь}"
    # Два условия, без которых модуль из ЧУЖОГО дерева не загружается, и оба
    # выяснены измерением, а не догадкой:
    #   * корень того дерева должен стоять в sys.path первым — манифест
    #     импортирует `factory.contact`, и без этого подхватился бы мой;
    #   * модуль обязан попасть в sys.modules ДО exec_module — иначе
    #     `@dataclass` внутри него падает с `AttributeError: 'NoneType'
    #     object has no attribute '__dict__'` (dataclasses ищет модуль класса
    #     в sys.modules). Проверено на манифесте линии SEO.
    имя = "topvisor_manifest_внешний"
    прежний_путь = list(sys.path)
    прежний_модуль = sys.modules.get(имя)
    try:
        sys.path.insert(0, str(дерево))
        сп = importlib.util.spec_from_file_location(имя, путь)
        м = importlib.util.module_from_spec(сп)
        sys.modules[имя] = м
        сп.loader.exec_module(м)
        return м.by_domain(домен), ""
    except Exception as ош:  # noqa: BLE001 — причина важнее типа
        return None, f"манифест {путь} не прочитан: {type(ош).__name__}: {ош}"
    finally:
        sys.path[:] = прежний_путь
        if прежний_модуль is None:
            sys.modules.pop(имя, None)
        else:
            sys.modules[имя] = прежний_модуль


def по_домену(я: dict, сбор: dict | None, пояснение: str,
              дерево_манифеста: pathlib.Path = ДЕРЕВО_СЛУЖБЫ,
              снимок_topvisor: dict | None = None) -> dict:
    домен = я["domain"]
    итог = {"домен": домен, "site_id": я["site_id"], "статус_ячейки": я.get("status"),
            "системы": {}}

    # --- Метрика -----------------------------------------------------------
    з = запись_аналитики(домен)
    if з is None:
        метрика = {"настроено": НЕТ_ДАННЫХ,
                   "почему": "домена нет в config/analytics.json — счётчика ему не создадут"}
    elif з.get("counter_id"):
        метрика = {"настроено": "НАСТРОЕНО",
                   "почему": f"счётчик {з['counter_id']}, состояние {з.get('counter_state')}, "
                             f"вебвизор {'вкл' if з.get('webvisor') else 'выкл'}"}
    else:
        метрика = {"настроено": НЕТ_ДАННЫХ,
                   "почему": f"объявлен ({з.get('counter_state')}), счётчика нет — "
                             "это вход владельца, а не ошибка сбора"}
    данные, причина = измерено_по_домену(сбор, домен)
    метрика["данные"] = данные
    метрика["данные_почему"] = f"{причина} ({пояснение})"
    метрика["расписание"], метрика["расписание_почему"] = расписание("analytics-cabinet.timer")
    итог["системы"]["метрика"] = метрика

    # --- Вебмастер ---------------------------------------------------------
    # Два поля про разное, и путать их нельзя: `verification_status` — ответ
    # ЯНДЕКСА о правах, `enabled` — наше решение собирать по этому домену.
    # Первая редакция требовала оба и печатала «состояние прав VERIFIED» рядом
    # с отказом — у animedia.icu права подтверждены, а сбор у нас выключен.
    вм = (з or {}).get("webmaster") or {}
    if з is None:
        состояние = (НЕТ_ДАННЫХ, "записи домена нет вовсе")
    elif вм.get("verification_status") == "VERIFIED" and вм.get("host_id"):
        хвост = ("" if вм.get("enabled") else
                 "; сбор по домену у нас ВЫКЛЮЧЕН (enabled: false) — это наше решение, не отказ сервиса")
        состояние = ("НАСТРОЕНО",
                     f"host_id {вм.get('host_id')}, права VERIFIED, "
                     f"sitemap отправлен: {'да' if вм.get('sitemap_submitted') else 'нет'}{хвост}")
    else:
        состояние = (НЕТ_ДАННЫХ,
                     f"права: {вм.get('verification_status', 'нет поля')}, "
                     f"host_id: {вм.get('host_id') or 'нет'}")
    # Вебмастер опрашивает суточный сбор кабинета (`analytics_collect`:
    # WEBMASTER_RESOURCES), а не отдельный юнит. Первая редакция искала
    # `webmaster-inventory.timer` и печатала «таймера нет» — это ручной опрос,
    # у него таймера и не должно быть. Поправку дала линия SEO, проверено:
    # в последнем cabinet-latest.json 75 измерений Вебмастера с причиной
    # «сеть недоступна (URLError)», то есть расписание работает, а данных нет
    # из-за B023. Разница существенная: «нет расписания» требует завести
    # таймер, «нет данных» — снять сетевое ограничение.
    расп_вм = расписание("analytics-cabinet.timer")
    итог["системы"]["вебмастер"] = {
        "настроено": состояние[0], "почему": состояние[1],
        "данные": НЕТ_ДАННЫХ,
        "данные_почему": "сеть до api.webmaster.yandex.net закрыта вне наших машин "
                         "(B023, измерено 26.10 на двух узлах) — поисковые данные недоступны",
        "расписание": расп_вм[0], "расписание_почему": расп_вм[1],
    }

    # --- Topvisor ----------------------------------------------------------
    # Манифест Topvisor читается ИЗ НАЗВАННОГО ДЕРЕВА и дерево печатается.
    # Причина измерена 26.10: служба сбора работает из рабочей копии линии SEO
    # (MOD-198), и состав проектов там ДРУГОЙ — animedia.icu в их манифесте
    # есть, в моей ветви нет. Инструмент, читающий артефакты из одного дерева,
    # а конфигурацию из другого, печатает смесь двух состояний и называет
    # пробелом то, чего в работающей системе нет.
    проект, ош_текст = _проект_topvisor(домен, дерево_манифеста)
    if проект is None:
        тв = {"настроено": НЕТ_ДАННЫХ,
              "почему": ош_текст or "домена нет в манифесте Topvisor — "
                                    "он не попадёт ни в план, ни в отчёт"}
    else:
        запросов = sum(len(г.keywords) for г in проект.groups)
        тв = {"настроено": "НАСТРОЕНО",
              "почему": f"проект описан: {len(проект.groups)} групп, {запросов} запросов, "
                        f"счётчик Метрики {проект.metrika_counter or 'не связан'}"}
    снимок = снимок_topvisor if снимок_topvisor is not None else {}
    строка = (снимок.get("строки") or {}).get(домен)
    здоровье = снимок.get("здоровье") or {}
    if строка:
        тв["настроено"] = {"MATCHED_EXACT": "НАСТРОЕНО"}.get(
            строка.get("mapping_state"), НЕТ_ДАННЫХ)
        тв["почему"] = (f"строка матрицы: {строка.get('mapping_state')}, проект "
                        f"{строка.get('topvisor_project_id') or 'нет'}, запросов "
                        f"{строка.get('query_count')}, блокеры: "
                        f"{строка.get('blocker') or 'нет'}; следующее безопасное "
                        f"действие — {строка.get('next_safe_action')}")
    elif снимок.get("строки"):
        # Манифест и матрица отвечают на РАЗНЫЕ вопросы: манифест — что мы
        # собирались заводить, матрица — что у поставщика есть. Потерять
        # первое значит перестать различать «описан, но не создан» и «не
        # описан вовсе», а это разные шаги владельца.
        тв["настроено"] = НЕТ_ДАННЫХ
        тв["почему"] = (f"по нашему манифесту: {тв['почему']}. У поставщика строки "
                        f"нет: домена в матрице сопоставления ({len(снимок['строки'])} "
                        "строк) не оказалось — проект не создан")
    тв["данные"] = НЕТ_ДАННЫХ
    если_цена = здоровье.get("SYNC_COST_STATE")
    тв["данные_почему"] = (
        f"снято только ЧТЕНИЕ инвентаря: source={здоровье.get('source')}, "
        f"вызовов {здоровье.get('read_only_call_count')}, прогон "
        f"{здоровье.get('last_success_at')}, состояние стоимости {если_цена} "
        f"({здоровье.get('SYNC_RUN_COST_RUB')} ₽). Позиции этим не снимаются: "
        f"платная пригодность домена — "
        f"{(строка or {}).get('paid_eligibility', 'строки нет')}"
        if здоровье else (снимок.get("почему_нет") or "состояние инвентаря не прочитано"))
    _, почему_позиций = расписание("topvisor-check.timer")
    # Окно поставщика проверяется у ПОДГОТОВЛЕННОГО юнита съёма позиций: он
    # ещё не установлен, но расписание в нём уже задано, и ошибка в часе
    # обнаружится сейчас, а не после установки.
    подготовленный = pathlib.Path(
        "/home/claude/wt-portable-site-cell-01/automation/host/topvisor-collect.timer")
    if подготовленный.is_file():
        исход_окна, почему_окна = окно_съёма_позиций(
            подготовленный.read_text(encoding="utf-8", errors="replace"))
        почему_позиций += f". Окно поставщика у подготовленного юнита: {исход_окна} — {почему_окна}"
    тв["расписание"] = НЕТ_ДАННЫХ
    тв["расписание_почему"] = (
        f"съём позиций: {почему_позиций}. Инвентарь при этом идёт по расписанию: "
        f"timer_deployed={здоровье.get('timer_deployed')}, подряд удачных "
        f"{здоровье.get('consecutive_successes')}, свежесть "
        f"{здоровье.get('freshness_hours')} ч, stale={здоровье.get('stale')}"
        if здоровье else f"съём позиций: {почему_позиций}; инвентарь не измерен")
    if снимок.get("тревога"):
        тв["расписание_почему"] += (
            "; ТРЕВОГА инвентаря активна: "
            + ", ".join(снимок["тревога"].get("reasons") or []))
    итог["системы"]["topvisor"] = тв

    готово = all(с.get("настроено") == "НАСТРОЕНО" and с.get("данные") == "ДАННЫЕ ЕСТЬ"
                 for с in итог["системы"].values())
    итог["готовность"] = "ГОТОВО" if готово else "НЕ ГОТОВО"
    return итог


def главная(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", action="append", default=[],
                   help="проверить только эти домены")
    р.add_argument("--artifacts", type=pathlib.Path, default=АРТЕФАКТЫ)
    р.add_argument("--manifest-tree", type=pathlib.Path, default=ДЕРЕВО_СЛУЖБЫ,
                   help="дерево, из которого читать манифест Topvisor "
                        "(по умолчанию — дерево работающей службы сбора)")
    р.add_argument("--json", action="store_true")
    р.add_argument("--topvisor-state", type=pathlib.Path, default=ТОПВИЗОР_СОСТОЯНИЕ,
                   help="каталог состояния инвентаря Topvisor (его пишет служба)")
    а = р.parse_args(аргв)

    сбор, пояснение = последний_сбор(а.artifacts)
    записи = [я for я in домены() if not а.domain or я["domain"] in а.domain]
    снимок = _topvisor_снимок(а.topvisor_state)
    if снимок.get("расхождение"):
        # В stderr, а не в stdout: иначе строка попадает в начало выгрузки
        # --json и делает её нечитаемой. Своя же печать сломала свой же файл
        # доказательства 26.10.
        print("РАСХОЖДЕНИЕ в данных Topvisor:", снимок["расхождение"], file=sys.stderr)
    итоги = [по_домену(я, сбор, пояснение, а.manifest_tree, снимок) for я in записи]

    if а.json:
        print(json.dumps({"artifacts": str(а.artifacts), "сбор": пояснение,
                          "manifest_tree": str(а.manifest_tree),
                          "домены": итоги}, ensure_ascii=False, indent=1))
    else:
        print(f"артефакты сбора: {пояснение}")
        print(f"манифест Topvisor прочитан из: {а.manifest_tree}")
        print(f"{'домен':24} {'ячейка':12} метрика / вебмастер / topvisor")
        for и in итоги:
            кратко = " | ".join(
                f"{имя}: {с['настроено'][:9]}/{с['данные'][:11]}/{с['расписание'][:10]}"
                for имя, с in и["системы"].items())
            print(f"{и['домен']:24} {и['статус_ячейки'] or '?':12} {и['готовность']:9} {кратко}")
        не_готовы = [и for и in итоги if и["готовность"] != "ГОТОВО"]
        print(f"\nдомéнов {len(итоги)}, готовы {len(итоги) - len(не_готовы)}")
        for и in не_готовы[:40]:
            for имя, с in и["системы"].items():
                for поле, почему in (("настроено", "почему"),
                                     ("данные", "данные_почему"),
                                     ("расписание", "расписание_почему")):
                    if с[поле] != ("НАСТРОЕНО" if поле == "настроено" else
                                   "ДАННЫЕ ЕСТЬ" if поле == "данные" else "РАСПИСАНИЕ"):
                        print(f"  {и['домен']:22} {имя:10} {поле:11} {с[почему][:110]}")
    # Ненулевой код — когда хоть один домен не готов: это ворота, а не отчёт.
    return 0 if all(и["готовность"] == "ГОТОВО" for и in итоги) else 3


if __name__ == "__main__":
    raise SystemExit(главная())
