#!/usr/bin/env python3
"""Доставка между ветвями: чья копия файла устарела, а чья своя.

Зачем. За один день трижды повторился один класс ошибки: проверка зелёная в
МОЕЙ ветви и красная в дереве службы, где файл работает.

1. реестр защищённых полей доставлен БЕЗ своей схемы и строки сопоставления —
   поймал полный прогон SEO-сессии, не я;
2. инвариант в проверке запрета индексации жил в моём коммите и в дерево
   службы не приходил — проверка там падала на старой половине;
3. шаблоны проверок витрин копировались из моих коммитов прямо в ячейки, минуя
   дерево службы, из-за чего договор `deploy_request` не держался.

Общая причина не в забывчивости: «моя ветвь зелена» и «там, где исполняется,
зелено» — РАЗНЫЕ утверждения, а отличать их было нечем.

Что отвечает инструмент. Для файлов, которые есть в ОБЕИХ ветвях и
различаются, он говорит, чья копия устарела, и говорит это по git, а не по
датам:

* **их копия — мой прежний коммит** → доставить мою, конфликта нет;
* **их копия не совпадает ни с одним моим коммитом** → у них своя работа,
  копировать целиком НЕЛЬЗЯ (так я чуть не затёр чужую строку в валидаторе);
* файлы, которых нет у одной из сторон, выводятся отдельно: это не
  расхождение, а разный состав ветвей.

Ничего не копирует и не меняет.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

МОЁ = Path(__file__).resolve().parents[2]
СЛУЖБА = Path("/home/claude/wt-portable-site-cell-01")
#: Сколько коммитов назад искать совпадение. Предел — чтобы ожидание было
#: ограниченным, а не «пока не найдётся» (D205).
ГЛУБИНА = 60


def цифра(данные: bytes) -> str:
    return hashlib.sha256(данные).hexdigest()


def из_коммита(корень: Path, sha: str, путь: str) -> bytes | None:
    готово = subprocess.run(["git", "show", f"{sha}:{путь}"],
                            capture_output=True, cwd=корень, timeout=120)
    return готово.stdout if готово.returncode == 0 else None


def коммиты(корень: Path, путь: str, предел: int) -> list[str]:
    """Последние коммиты, которые касались пути. Предел ограничен числом."""
    готово = subprocess.run(
        ["git", "log", f"-{предел}", "--format=%H", "--", путь],
        capture_output=True, text=True, cwd=корень, timeout=120)
    return [с for с in готово.stdout.split() if с]


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--mine", type=Path, default=МОЁ)
    р.add_argument("--theirs", type=Path, default=СЛУЖБА)
    р.add_argument("--subdir", action="append", default=[],
                   help="какие каталоги сверять, например tests/unit")
    р.add_argument("--depth", type=int, default=ГЛУБИНА)
    опции = р.parse_args(аргв)

    каталоги = опции.subdir or ["tests/unit", "schemas", "scripts",
                                "factory/cell/site_checks"]
    устарели: list[tuple[str, str]] = []
    своя_работа: list[str] = []
    совпали = только_у_меня = только_у_них = 0

    for каталог in каталоги:
        мой_к, их_к = опции.mine / каталог, опции.theirs / каталог
        if not (мой_к.is_dir() and их_к.is_dir()):
            print(f"   [—  ] {каталог}: нет в одной из ветвей")
            continue
        мои = {п.name for п in мой_к.iterdir() if п.is_file()}
        их = {п.name for п in их_к.iterdir() if п.is_file()}
        только_у_меня += len(мои - их)
        только_у_них += len(их - мои)
        for имя in sorted(мои & их):
            путь = f"{каталог}/{имя}"
            моё = (опции.mine / путь).read_bytes()
            ихнее = (опции.theirs / путь).read_bytes()
            if моё == ихнее:
                совпали += 1
                continue
            цель = цифра(ихнее)
            нашлось = ""
            for sha in коммиты(опции.mine, путь, опции.depth):
                из = из_коммита(опции.mine, sha, путь)
                if из is not None and цифра(из) == цель:
                    нашлось = sha[:12]
                    break
            if нашлось:
                устарели.append((путь, нашлось))
            else:
                своя_работа.append(путь)

    print(f"сверено каталогов: {len(каталоги)}; файлов совпало {совпали}")
    if устарели:
        print(f"\nих копия УСТАРЕЛА — моя версия не доставлена ({len(устарели)}):")
        for путь, sha in устарели:
            print(f"   {путь}  (их копия = мой коммит {sha})")
        print("   доставить можно целиком: своей работы у них в этих файлах нет")
    if своя_работа:
        print(f"\nу них СВОЯ работа — целиком копировать нельзя "
              f"({len(своя_работа)}):")
        for путь in своя_работа:
            print(f"   {путь}")
        print("   переносить построчно: именно так я чуть не затёр чужую "
              "строку в validate_registries.py")
    print(f"\nтолько в моей ветви: {только_у_меня}; только у них: "
          f"{только_у_них} — это разный состав ветвей, не расхождение")
    return 1 if устарели else 0


if __name__ == "__main__":
    raise SystemExit(главное())
