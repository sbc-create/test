#!/usr/bin/env python3
"""Раскладка страницы редакционной подборки: сколько карточек в ряду и чем занят экран.

ПОВОД — поручение владельца 27.10 после отказа визуальной приёмки
`https://animedia.icu/collection/letniy-sezon-2026-celikom/`: «огромный
одиночный постер слева, пустое пространство справа и название произведения
далеко внизу».

ПОЧЕМУ ПРЕЖНИЕ ПРОВЕРКИ ЭТОГО НЕ ЛОВИЛИ. `collections-acceptance.py` меряет
схему, живые факты и неповторяемость — и прямо говорит, что раскладку не
меряет. `home-acceptance.py` меряет ГЛАВНУЮ. Приёмка линии SEO сверяла состав,
порядок и пояснения со файлом. Ни одна не спрашивала, сколько карточек в ряду
и есть ли у страницы оформление вовсе: страница с одной колонкой отдаёт 200,
её состав верен, ссылки работают, картинки не биты — по всем прежним признакам
она «в порядке».

ЧТО МЕРЯЕТ ЭТА ПРОВЕРКА — факты раскладки, снятые у браузера:

* `карточек в ряду` — по группировке карточек с одинаковым `offsetTop`; это
  прямой ответ на «одна колонка вместо четырёх»;
* `рамка постера` — ширина, высота и отношение; постер шире трети экрана на
  компьютере означает, что рамки нет;
* `название ниже постера на` — расстояние в пикселях от низа постера до
  названия; «название далеко внизу» становится числом;
* `ширина содержимого` против ширины окна — «пустое пространство справа»;
* `горизонтальная прокрутка` и `перенос текста за рамку`.

ЧЕГО НЕ МЕРЯЕТ: красоту, цвета, шрифты. Это не замена взгляду человека на
снимок — снимки она делает и путь к ним печатает.

    python3 automation/local/collection-visual-check.py --url <адрес> [--out-json f]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))
#: Имя пробы. Запрос без имени попадает в класс `other_bot` и получает 503
#: после 30 обращений в минуту (MOD-175/MOD-204) — замер показал бы предел,
#: а не страницу.
АГЕНТ = "factory-collection-visual"
#: Ширины из поручения владельца 27.10: телефон, ноутбук, широкий монитор.
ШИРИНЫ = ((390, 844, True, 3), (1440, 900, False, 2), (1920, 1080, False, 1))
#: Сколько карточек в ряду считается нормой. Меньше — дефект раскладки.
НОРМА_В_РЯДУ = {390: 2, 1440: 4, 1920: 4}
#: Доля окна, шире которой постер на компьютере означает отсутствие рамки.
ДОЛЯ_ПОСТЕРА = 0.34
#: Насколько содержимое может быть уже окна, прежде чем это «пустота справа».
#: 1920 с ограничением 1420 даёт 0.74 — это рамка оригинала, а не дефект.
МИН_ДОЛЯ_СОДЕРЖИМОГО = 0.60

ОСМОТР = """() => {
  // ПРЯМЫЕ дети сетки, а не любые потомки: `.col__i` и вложенная в неё `.c`
  // имеют один и тот же `offsetTop`, и запрос по потомкам считал бы каждую
  // карточку дважды — «2 в ряду» означало бы одну. Ровно так первая редакция
  // этой проверки и соврала на ширине 390.
  const сетка0 = document.querySelector('.col__grid');
  const карточки = сетка0 ? [...сетка0.children] : [];
  const ряды = {};
  for (const к of карточки) {
      const t = Math.round(к.getBoundingClientRect().top + window.scrollY);
      ряды[t] = (ряды[t] || 0) + 1;
  }
  const вряду = Object.values(ряды);
  const сетка = сетка0;
  const первая = карточки[0] || null;
  const постер = первая ? первая.querySelector('.c__p, .zcl__p') : null;
  const имя = первая ? первая.querySelector('.c__t, .zcl__t') : null;
  const карт = постер ? постер.querySelector('img') : null;
  const пояснение = первая ? первая.querySelector('.col__why') : null;
  const корпус = document.querySelector('.sec, .zwrap, main') || document.body;
  const пр = (э) => э ? э.getBoundingClientRect() : null;
  const рп = пр(постер), ри = пр(имя), рк = пр(корпус);
  return {
    'карточек всего': карточки.length,
    'карточек в ряду': вряду.length ? Math.max(...вряду) : 0,
    'рядов': вряду.length,
    'сетка найдена': !!сетка,
    'display сетки': сетка ? getComputedStyle(сетка).display : null,
    'колонок в сетке': сетка
        ? getComputedStyle(сетка).gridTemplateColumns.split(' ').filter(Boolean).length : 0,
    'рамка постера': рп ? [Math.round(рп.width), Math.round(рп.height)] : null,
    'отношение рамки': рп && рп.height
        ? Math.round((рп.width / рп.height) * 100) / 100 : null,
    'доля постера от окна': рп
        ? Math.round((рп.width / window.innerWidth) * 100) / 100 : null,
    'картинка натурально': карт ? [карт.naturalWidth, карт.naturalHeight] : null,
    'object-fit': карт ? getComputedStyle(карт).objectFit : null,
    'название ниже постера на': (рп && ри) ? Math.round(ри.top - рп.bottom) : null,
    'пояснение есть': !!пояснение,
    'ширина содержимого': рк ? Math.round(рк.width) : null,
    'доля содержимого от окна': рк
        ? Math.round((рк.width / window.innerWidth) * 100) / 100 : null,
    'горизонтальная прокрутка':
        document.documentElement.scrollWidth - window.innerWidth,
    'высота страницы': document.documentElement.scrollHeight,
    // Виден ли верх первой карточки в первом экране. Считается в CSS-пикселях
    // от верха документа: по снимку это определить нельзя — снимок отдан в
    // физических пикселях, и при DPR 3 высота 2532 соответствует 844 CSS.
    // Ровно на этом я и ошибся, прочитав снимок как разметку.
    'верх первой карточки': первая
        ? Math.round(первая.getBoundingClientRect().top + window.scrollY) : null,
    'высота окна': window.innerHeight,
    'карточка в первом экране': первая
        ? (первая.getBoundingClientRect().top + window.scrollY) < window.innerHeight
        : null,
    // Критерий линии SEO: на телефоне первый ряд ПОСТЕРОВ виден целиком, то
    // есть низ рамки первого постера выше нижнего края окна. «Видно верх
    // карточки» этого не означает: до правки низ ряда стоял на 871 при окне
    // 844, и в экран попадала примерно четверть постера.
    'низ первого ряда': (первая && рп)
        ? Math.round(первая.getBoundingClientRect().top + window.scrollY
                     + рп.height) : null,
    'перенос за рамку': карточки.filter(
        к => к.scrollWidth > к.clientWidth + 1).length,
  };
}"""


def беда_прохода(и: dict, ширина: int) -> list:
    """Что считается дефектом раскладки. Отдельной функцией — чтобы «0 бед»
    было проверяемо без браузера."""
    причины = []
    if и.get("беда"):
        return [str(и["беда"])]
    если_карточек = и.get("карточек всего") or 0
    if не_измерено(и):
        return []
    if если_карточек == 0:
        return ["карточек на странице нет — страница не разобрана"]
    норма = НОРМА_В_РЯДУ.get(ширина, 2)
    в_ряду = и.get("карточек в ряду") or 0
    if в_ряду < норма:
        причины.append(f"в ряду {в_ряду} карточек, норма {норма}")
    if (и.get("горизонтальная прокрутка") or 0) > 0:
        причины.append(f"горизонтальная прокрутка {и['горизонтальная прокрутка']} px")
    доля = и.get("доля постера от окна")
    if ширина >= 1024 and доля is not None and доля > ДОЛЯ_ПОСТЕРА:
        причины.append(f"постер занимает {доля} окна — рамки нет")
    содержимое = и.get("доля содержимого от окна")
    if содержимое is not None and содержимое < МИН_ДОЛЯ_СОДЕРЖИМОГО:
        причины.append(f"содержимое занимает {содержимое} окна — пустота справа")
    отступ = и.get("название ниже постера на")
    if отступ is not None and отступ > 40:
        причины.append(f"название на {отступ} px ниже постера")
    низ = и.get("низ первого ряда")
    окно = и.get("высота окна")
    if ширина <= 600 and низ and окно and низ > окно:
        причины.append(f"первый ряд постеров не помещается в экран: "
                       f"низ {низ} при окне {окно}")
    if и.get("перенос за рамку"):
        причины.append(f"текст выходит за рамку в {и['перенос за рамку']} карточках")
    if not и.get("пояснение есть"):
        причины.append("нет редакционного пояснения у первой карточки")
    return причины


def не_измерено(и: dict) -> bool:
    return и.get("карточек всего") is None


def пройти(браузер, адрес: str, размер, снимки: pathlib.Path,
           полные: bool = False) -> dict:
    ш, в, моб, dsf = размер
    итог = {"ширина": ш}
    контекст = браузер.new_context(viewport={"width": ш, "height": в},
                                   is_mobile=моб, has_touch=моб,
                                   device_scale_factor=dsf,
                                   user_agent=АГЕНТ, color_scheme="light")
    # Технический прогон не попадает в статистику людей.
    контекст.route("**mc.yandex.*/**", lambda м: м.abort())
    с = контекст.new_page()
    с.route("**mc.yandex.*/**", lambda м: м.abort())
    try:
        с.goto(адрес, wait_until="load", timeout=90000)
        с.wait_for_timeout(2500)
        итог.update(с.evaluate(ОСМОТР))
        снимки.mkdir(parents=True, exist_ok=True)
        имя = адрес.rstrip("/").rsplit("/", 1)[-1] or "подборка"
        файл = снимки / f"{имя}-{ш}.png"
        с.screenshot(path=str(файл), full_page=False)
        итог["снимок"] = str(файл)
        # Полностраничный снимок — по требованию. Измерено: прогон по
        # восемнадцати страницам на трёх ширинах даёт 136 МБ одних только
        # полных снимков против 72 МБ экранных, а приёмку решает первый
        # экран. Без флага они не делаются вовсе.
        if полные:
            полный = снимки / f"{имя}-{ш}-целиком.png"
            с.screenshot(path=str(полный), full_page=True)
            итог["снимок целиком"] = str(полный)
    except Exception as сбой:  # noqa: BLE001 — любой отказ это отказ приёмки
        итог["беда"] = f"{type(сбой).__name__}: {str(сбой)[:200]}"
    finally:
        контекст.close()
    return итог


def главная(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--url", required=True, action="append",
                   help="адрес страницы подборки (можно повторять)")
    р.add_argument("--out", default=None, help="каталог для снимков")
    р.add_argument("--out-json", default="")
    р.add_argument("--full-page", action="store_true",
                   help="делать ещё и полностраничные снимки: на прогоне по "
                        "парку это 136 МБ против 72, а приёмку решает первый "
                        "экран")
    а = р.parse_args(аргв)
    снимки = pathlib.Path(а.out or (КОРЕНЬ / "artifacts" / "evidence"
                                    / "collection-visual"))
    from factory.seo.render_check import chromium_path
    from playwright.sync_api import sync_playwright

    путь = chromium_path()
    пуск = {"headless": True}
    if путь:
        пуск["executable_path"] = путь
    итоги = []
    with sync_playwright() as pw:
        бр = pw.chromium.launch(**пуск)
        try:
            for адрес in а.url:
                for размер in ШИРИНЫ:
                    и = пройти(бр, адрес, размер, снимки, а.full_page)
                    и["адрес"] = адрес
                    итоги.append(и)
        finally:
            бр.close()
    бед = 0
    for и in итоги:
        причины = беда_прохода(и, и["ширина"])
        if не_измерено(и) and not причины:
            print(f"{и['адрес']} @{и['ширина']}  НЕ ИЗМЕРЕНО: {и.get('беда')}")
            continue
        бед += bool(причины)
        метка = "ок    " if not причины else "ДЕФЕКТ"
        print(f"{и['адрес']} @{и['ширина']}  {метка} "
              f"в ряду {и.get('карточек в ряду')}/{НОРМА_В_РЯДУ.get(и['ширина'])} "
              f"| рамка {и.get('рамка постера')} отн. {и.get('отношение рамки')} "
              f"| содержимое {и.get('доля содержимого от окна')} "
              f"| прокрутка {и.get('горизонтальная прокрутка')}")
        for причина in причины:
            print(f"{'':<8}— {причина}")
        if и.get("снимок"):
            print(f"{'':<8}снимок: {и['снимок']}")
    print(f"\nпроходов с дефектом: {бед} из {len(итоги)}")
    if а.out_json:
        pathlib.Path(а.out_json).write_text(
            json.dumps(итоги, ensure_ascii=False, indent=1) + "\n",
            encoding="utf-8")
        print(f"отчёт: {а.out_json}")
    return 1 if бед else 0


if __name__ == "__main__":
    raise SystemExit(главная())
