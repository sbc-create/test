#!/usr/bin/env python3
"""Защита от повторения дефектов карты сайта: сверка с эталонным снимком.

Зачем отдельный инструмент, когда карту уже проверяют пять соседних. Те
отвечают на вопросы о ТЕКУЩЕМ ответе: отдаётся ли карта (`sitemap-chain`),
согласован ли индекс с содержимым (`sitemap-index-audit`), правильные ли даты
(`sitemap-lastmod-check`), сдвинулась ли карта вообще
(`sitemap-freshness-sweep`), хватает ли адресов против объявленных записей
(`sitemap-completeness`). Ни один не умеет сказать «вчера этот адрес в карте
был, сегодня его нет»: у них нет памяти. Ровно это и требуется защитой от
повторения MOD-103 и MOD-106.

Проверки одного прохода, без эталона:

1. ОБРЫВ ЧАСТИ. Часть, в которой РОВНО 50 000 адресов, обязана иметь
   продолжение в индексе. Предел sitemaps.org — 50 000, поэтому ровно предел
   это признак обрыва, а не полноты. Повод назван: 20.10 на yummyani.biz я
   прочитал первую часть из трёх, увидел 50 000 и занизил разрыв в 2.5 раза
   (48 576 против 121 877). Признак обрыва здесь стал проверкой, а не
   наблюдением;

2. СООТВЕТСТВИЕ СЕЗОНОВ. Номер сезона в адресе серии обязан встречаться среди
   адресов сезонов этой же работы. Работа, у которой адресов сезонов в карте
   нет вовсе, даёт «не измерено», а НЕ провал: отсутствие части — это другой
   дефект, и подменять им проверку соответствия нельзя.

Проверки против эталонного снимка (`--baseline`):

3. ПОТЕРЯ АДРЕСОВ. Адрес, который был в снимке и исчез из карты. Провал с
   числом и примерами. Это главный признак: исправление покрытия обязано
   адреса ДОБАВЛЯТЬ, и любая правка, которая их убирает, ловится здесь;

4. ИСЧЕЗНУВШАЯ ЧАСТЬ. Часть, объявленная индексом в снимке и отсутствующая
   сейчас. Отдельно от потери адресов, потому что причина другая: не состав
   каталога, а состав индекса;

5. СЖАТИЕ ЧАСТИ. Часть, в которой адресов стало МЕНЬШЕ. Рост частью не
   проверяется и провалом не считается — карта имеет право расти; печатается
   наблюдением.

Названные адреса (`--expect ФАЙЛ`): перечень адресов, каждый из которых обязан
быть в карте. Так проверяется «новая серия появилась в карте»: наблюдение
называет конкретный адрес новой серии, а инструмент отвечает да или нет.
Выдумывать ожидаемые адреса сам инструмент не умеет и не должен.

Код возврата: 0 — провалов нет, 1 — есть провалы, 2 — измерить не удалось.
«Не удалось» и «всё хорошо» никогда не сливаются в один код.

    python3 automation/local/sitemap-regression-guard.py --domain yummyani.site
    python3 automation/local/sitemap-regression-guard.py --domain yummyani.site \
        --snapshot var/sitemap-guard/site-20261020.json
    python3 automation/local/sitemap-regression-guard.py --domain yummyani.site \
        --baseline var/sitemap-guard/site-20261020.json
    python3 automation/local/sitemap-regression-guard.py --domain yummyani.site \
        --expect var/sitemap-guard/new-episodes.txt
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

АГЕНТ = "factory-sitemap-regression-guard"

ПРЕДЕЛ_ЧАСТИ = 50_000
ПРИМЕРОВ = 5

# Печатается при ЛЮБОМ исходе, и это не вежливость. Измерено 20.10: на
# yummyani.site инструмент даёт «провалов нет» на карте, в которой адресов
# серий 1 424 вместо порядка 123 000 — то есть занижение в 86 раз он не видит и
# видеть не должен. Его вопрос — «что пропало по сравнению со снимком», а не
# «полна ли карта». Без этой строки ноль читался бы как «карта в порядке», и
# тогда инструмент защиты сам стал бы источником ложного спокойствия.
ЧЕГО_НЕ_ОТВЕЧАЕТ = (
    "\nчего этот инструмент НЕ отвечает: полна ли карта относительно каталога."
    "\n   ноль провалов здесь означает «по сравнению со снимком ничего не"
    " потеряно»,"
    "\n   а не «все страницы каталога в карте». Полнота — "
    "sitemap-completeness.py,"
    "\n   даты — sitemap-lastmod-check.py, согласованность индекса — "
    "sitemap-index-audit.py")


def взять(url: str, таймаут: int = 180) -> str:
    г = subprocess.run(["curl", "-A", АГЕНТ, "-sS", "--max-time", str(таймаут), url],
                       capture_output=True, text=True)
    return г.stdout or ""


def адреса(xml: str) -> list[str]:
    return [a.strip() for a in re.findall(r"<loc>(.*?)</loc>", xml, re.S)]


def имя_части(url: str) -> str:
    """Имя части из её адреса, для любой формы, принятой в сети.

    Две формы существуют одновременно, и это измерено: Yummy отдаёт
    `/sitemap/episodes-2.xml`, а Lords, Zona и Animedia — `/sitemap-1.xml`.
    Прежняя версия знала только первую, возвращала для второй ВЕСЬ адрес, и
    проход затем собирал из него `https://домен/sitemap/<весь адрес>.xml` и
    получал 404. Итог был ложным провалом «часть не ответила» на витрине,
    у которой карта исправна и отдаёт 8 233 адреса.
    """
    м = re.search(r"/sitemap/([^/]+)\.xml", url)
    if м:
        return м.group(1)
    м = re.search(r"/([^/]+)\.xml$", url)
    return м.group(1) if м else url


def следующая(имя: str) -> str:
    """`episodes` → `episodes-2`, `episodes-2` → `episodes-3`."""
    м = re.match(r"^(.*?)-(\d+)$", имя)
    if м:
        return f"{м.group(1)}-{int(м.group(2)) + 1}"
    return f"{имя}-2"


def снять(домен: str, *, загрузчик=None) -> dict:
    """Снимок карты: части индекса и множества адресов в каждой.

    Пустой индекс отличается от недоступного: `ok` ложно только когда карта не
    ответила вовсе, потому что «карта пуста» и «карту не смогли прочитать» —
    разные исходы, и один не должен выдавать себя за другой.

    Загрузчик разрешается в момент ВЫЗОВА, а не в объявлении. Значение по
    умолчанию `загрузчик=взять` связало бы исходную функцию навсегда: подмена
    `взять` перестала бы действовать, и проверки молча ушли бы в сеть вместо
    подменённого ответа. Это не предположение — именно так и вышло при первом
    прогоне: четыре проверки повисли на реальном запросе к несуществующему
    домену.
    """
    загрузить = загрузчик or взять
    индекс = загрузить(f"https://{домен}/sitemap.xml")
    if not индекс.strip():
        return {"domain": домен, "ok": False,
                "почему": "индекс карты не ответил", "parts": {}}
    # Адрес части берётся ИЗ ИНДЕКСА как есть и не собирается из имени: формы
    # в сети разные (`/sitemap/episodes-2.xml` у Yummy, `/sitemap-1.xml` у
    # остальных), и сборка по одной из них давала ложный провал на другой.
    по_адресу = [(имя_части(у), у) for у in адреса(индекс)]
    снимок: dict = {"domain": домен, "ok": True,
                    "order": [и for и, _ in по_адресу], "parts": {}}
    for имя, адрес in по_адресу:
        тело = загрузить(адрес)
        if not тело.strip():
            снимок["parts"][имя] = {"ok": False, "urls": [], "url": адрес}
            continue
        снимок["parts"][имя] = {"ok": True, "url": адрес,
                                "urls": sorted(set(адреса(тело)))}
    return снимок


# --- проверки одного прохода --------------------------------------------------

def обрыв_частей(снимок: dict) -> list[str]:
    """Часть ровно на пределе без продолжения в индексе — провал."""
    беды = []
    объявлены = set(снимок.get("order") or [])
    for имя, часть in снимок["parts"].items():
        if not часть.get("ok"):
            беды.append(f"{имя}: часть не ответила")
            continue
        сколько = len(часть["urls"])
        if сколько == ПРЕДЕЛ_ЧАСТИ and следующая(имя) not in объявлены:
            беды.append(f"{имя}: ровно {ПРЕДЕЛ_ЧАСТИ} адресов, а продолжения"
                        f" {следующая(имя)} в индексе нет — это признак обрыва,"
                        f" а не полноты")
        elif сколько > ПРЕДЕЛ_ЧАСТИ:
            беды.append(f"{имя}: {сколько} адресов — выше предела"
                        f" {ПРЕДЕЛ_ЧАСТИ}")
    return беды


def _работа_и_сезон(url: str) -> tuple[str, str] | None:
    м = re.search(r"/anime/([^/]+)/season/(\d+)", url)
    return (м.group(1), м.group(2)) if м else None


def _работа_и_сезон_серии(url: str) -> tuple[str, str] | None:
    м = re.search(r"/anime/([^/]+)/season/(\d+)/episode/", url)
    return (м.group(1), м.group(2)) if м else None


def пропуски_сезонов(сезоны: dict[str, set[str]]) -> list[str]:
    """Работы, у которых внутри нумерации сезонов ДЫРА: есть 1 и 3, нет 2.

    Почему признак именно такой, а не «минимальный сезон не 1». Второе ошибкой
    НЕ является, и это измерено 20.10: на yummyani.biz таких работ 1 114, и это
    слаги вида `agressivnaya-retsuko-ona-2`, `7-semyan-vtoroy-sezon`,
    `a3-osen-i-zima` — сезон вынесен в ОТДЕЛЬНУЮ запись каталога, и внутренний
    номер 2 там законен. Ужесточение до «слаг без номера» тоже не спасает:
    `a3-osen-i-zima` и `akb0048-sleduyuschaya-stadiya` — названные продолжения
    без цифры, и их 350.

    Дыра однозначна при любом устройстве слагов: если у одной работы есть
    сезоны 1 и 3, а второго нет, значит сезон 2 в карту не попал. Измерено на
    yummyani.biz: 19 работ, среди них `akvarion` (есть 1 и 3),
    `mobilnyy-voin-gandam-pokolenie` (есть 1 и 6, нет 2-5),
    `istrebitel-demonov-na-trenirovku-stolpov-2024` (есть 1 и 4, нет 2 и 3).
    """
    итог = []
    for работа, номера in sorted(сезоны.items()):
        числа = sorted(int(н) for н in номера)
        if len(числа) < 2:
            continue
        пропуск = sorted(set(range(числа[0], числа[-1] + 1)) - set(числа))
        if пропуск:
            итог.append(f"{работа}: есть {числа}, не хватает {пропуск}")
    return итог


def соответствие_сезонов(снимок: dict) -> tuple[list[str], list[str]]:
    """(провалы, наблюдения). Сезон серии обязан быть среди сезонов работы.

    Работа без адресов сезонов в карте даёт наблюдение «не измерено», а не
    провал: отсутствие части — отдельный дефект, и подменять им эту проверку
    значит получить проверку, которая падает не на том, что проверяет.
    """
    сезоны: dict[str, set[str]] = {}
    for url in снимок["parts"].get("seasons", {}).get("urls", []):
        п = _работа_и_сезон(url)
        if п:
            сезоны.setdefault(п[0], set()).add(п[1])

    чужие: list[str] = []
    без_сезонов: set[str] = set()
    всего = 0
    for имя, часть in снимок["parts"].items():
        if not имя.startswith("episodes"):
            continue
        for url in часть.get("urls", []):
            п = _работа_и_сезон_серии(url)
            if not п:
                continue
            всего += 1
            работа, сезон = п
            if работа not in сезоны:
                без_сезонов.add(работа)
            elif сезон not in сезоны[работа]:
                чужие.append(f"{url} — сезона {сезон} у работы {работа}"
                             f" в карте нет (есть"
                             f" {sorted(сезоны[работа])})")

    провалы = []
    if чужие:
        провалы.append(f"серий в несуществующем сезоне: {len(чужие)}"
                       f" из {всего}; примеры: "
                       + "; ".join(чужие[:ПРИМЕРОВ]))
    дыры = пропуски_сезонов(сезоны)
    if дыры:
        провалы.append(f"работ с ДЫРОЙ в нумерации сезонов: {len(дыры)};"
                       f" примеры: " + "; ".join(дыры[:ПРИМЕРОВ]))
    наблюдения = []
    if без_сезонов:
        наблюдения.append(f"работ, у которых серии есть, а адресов сезонов в"
                          f" карте нет: {len(без_сезонов)} — соответствие по"
                          f" ним НЕ ИЗМЕРЕНО"
                          f" ({', '.join(sorted(без_сезонов)[:ПРИМЕРОВ])})")
    if not всего:
        наблюдения.append("адресов серий с номером сезона в карте нет —"
                          " соответствие сезонов НЕ ИЗМЕРЕНО")
    return провалы, наблюдения


# --- проверки против эталона ---------------------------------------------------

def сверить_с_эталоном(снимок: dict, эталон: dict) -> tuple[list[str], list[str]]:
    """(провалы, наблюдения): потеря адресов, исчезнувшая часть, сжатие."""
    провалы: list[str] = []
    наблюдения: list[str] = []

    было_частей = set(эталон.get("parts", {}))
    стало_частей = set(снимок.get("parts", {}))
    пропали = sorted(было_частей - стало_частей)
    if пропали:
        провалы.append(f"части исчезли из индекса: {', '.join(пропали)}")
    новые = sorted(стало_частей - было_частей)
    if новые:
        наблюдения.append(f"новые части: {', '.join(новые)}")

    было_всех: set[str] = set()
    for часть in эталон.get("parts", {}).values():
        было_всех |= set(часть.get("urls", []))
    стало_всех: set[str] = set()
    for часть in снимок.get("parts", {}).values():
        стало_всех |= set(часть.get("urls", []))

    потеряно = sorted(было_всех - стало_всех)
    if потеряно:
        провалы.append(f"адресов потеряно: {len(потеряно)} из"
                       f" {len(было_всех)}; примеры: "
                       + "; ".join(потеряно[:ПРИМЕРОВ]))
    добавлено = len(стало_всех - было_всех)
    if добавлено:
        наблюдения.append(f"адресов добавилось: {добавлено}")

    for имя in sorted(было_частей & стало_частей):
        было = len(эталон["parts"][имя].get("urls", []))
        стало = len(снимок["parts"][имя].get("urls", []))
        if стало < было:
            провалы.append(f"{имя}: адресов стало меньше — было {было},"
                           f" стало {стало}")
        elif стало > было:
            наблюдения.append(f"{имя}: было {было}, стало {стало}")
    return провалы, наблюдения


def названные_адреса(снимок: dict, ожидаемые: list[str]) -> list[str]:
    """Перечисленные адреса обязаны быть в карте. Пустой перечень — не успех."""
    if not ожидаемые:
        return []
    есть: set[str] = set()
    for часть in снимок.get("parts", {}).values():
        есть |= set(часть.get("urls", []))
    нет = [у for у in ожидаемые if у not in есть]
    if нет:
        return [f"названных адресов нет в карте: {len(нет)} из"
                f" {len(ожидаемые)}; примеры: " + "; ".join(нет[:ПРИМЕРОВ])]
    return []


# --- печать --------------------------------------------------------------------

def главное(аргв: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--domain", required=True)
    р.add_argument("--snapshot", help="куда записать снимок")
    р.add_argument("--baseline", help="снимок, с которым сверять")
    р.add_argument("--expect", help="файл с адресами, которые обязаны быть")
    а = р.parse_args(аргв)

    снимок = снять(а.domain)
    if not снимок.get("ok"):
        print(f"витрина {а.domain}: НЕ ИЗМЕРЕНО — {снимок.get('почему')}")
        return 2

    if а.snapshot:
        п = Path(а.snapshot)
        п.parent.mkdir(parents=True, exist_ok=True)
        п.write_text(json.dumps(снимок, ensure_ascii=False), encoding="utf-8")
        print(f"снимок записан: {п}")

    провалы: list[str] = []
    наблюдения: list[str] = []

    print(f"витрина {а.domain}, частей в индексе: {len(снимок['parts'])}")
    for имя in снимок.get("order") or sorted(снимок["parts"]):
        часть = снимок["parts"].get(имя, {})
        состояние = (f"адресов {len(часть.get('urls', []))}"
                     if часть.get("ok") else "НЕ ОТВЕТИЛА")
        print(f"   {имя}: {состояние}")

    провалы += обрыв_частей(снимок)
    п_сезоны, н_сезоны = соответствие_сезонов(снимок)
    провалы += п_сезоны
    наблюдения += н_сезоны

    if а.baseline:
        путь = Path(а.baseline)
        if not путь.exists():
            print(f"\nэталон {путь} не найден — сверка НЕ ИЗМЕРЕНА")
            return 2
        эталон = json.loads(путь.read_text(encoding="utf-8"))
        п_э, н_э = сверить_с_эталоном(снимок, эталон)
        провалы += п_э
        наблюдения += н_э

    if а.expect:
        путь = Path(а.expect)
        if not путь.exists():
            print(f"\nперечень {путь} не найден — проверка НЕ ИЗМЕРЕНА")
            return 2
        ожидаемые = [с.strip() for с
                     in путь.read_text(encoding="utf-8").splitlines()
                     if с.strip() and not с.startswith("#")]
        if not ожидаемые:
            print(f"\nперечень {путь} пуст — проверка НЕ ИЗМЕРЕНА,"
                  f" пустой перечень успехом не является")
            return 2
        провалы += названные_адреса(снимок, ожидаемые)

    if наблюдения:
        print("\nнаблюдения:")
        for н in наблюдения:
            print(f"   {н}")
    if провалы:
        print("\nПРОВАЛЫ:")
        for п in провалы:
            print(f"   {п}")
        print(f"\nпровалов: {len(провалы)}")
        print(ЧЕГО_НЕ_ОТВЕЧАЕТ)
        return 1
    print("\nпровалов нет")
    print(ЧЕГО_НЕ_ОТВЕЧАЕТ)
    return 0


if __name__ == "__main__":
    sys.exit(главное())
