#!/usr/bin/env python3
"""Стандарт версии шаблона: чем собран релиз и чем его воспроизвести.

Манифесты витрин отвечали на вопрос «какая ревизия» и молчали обо всём
остальном. Из-за этого нельзя было ответить на простые вопросы: та ли это
версия шаблона, что на соседней витрине; собран ли релиз из того же артефакта;
какому поколению барьера он принадлежит. Каждый раз ответ добывался чтением
чужих логов.

Здесь перечислено то, без чего релиз не описан. Поле, которое нечем заполнить,
остаётся пустым со статусом, а не заполняется правдоподобным значением.
"""

from __future__ import annotations

import re

#: Поля, без которых релиз не воспроизводим и не сравним с соседним.
ОБЯЗАТЕЛЬНЫЕ = (
    "template_name",          # семейство и облик, а не идентификатор стенда
    "template_semver",        # человекочитаемая версия облика
    "template_revision",      # полный SHA, а не сокращение
    "template_digest",        # отпечаток набора файлов шаблона
    "artifact_sha256",        # отпечаток неизменяемого архива
    "content_snapshot_sha256",
    "content_snapshot_at_utc",
    "site_config_sha256",
    "generation",             # поколение барьера, которому принадлежит релиз
    "built_at_utc",
    "build_duration_seconds",
    "release_id",
    "previous_release_id",
    "rollback_release_id",
)

SEMVER = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")
ХЕКС40 = re.compile(r"^[0-9a-f]{40}$")
ХЕКС64 = re.compile(r"^[0-9a-f]{64}$")


def нарушения(манифест: dict) -> list[str]:
    """Чего не хватает или что записано не в том виде. Пусто — описан полностью."""
    беды: list[str] = []
    for поле in ОБЯЗАТЕЛЬНЫЕ:
        if поле not in манифест:
            беды.append(f"нет поля {поле}")
    if беды:
        return беды

    if not str(манифест["template_name"]).strip():
        беды.append("имя шаблона пусто")
    if not SEMVER.match(str(манифест["template_semver"])):
        беды.append(f"версия шаблона не SemVer: {манифест['template_semver']!r}")
    if not ХЕКС40.match(str(манифест["template_revision"])):
        беды.append("ревизия шаблона не полный SHA")
    for поле in ("template_digest", "artifact_sha256", "content_snapshot_sha256",
                 "site_config_sha256"):
        if not ХЕКС64.match(str(манифест[поле])):
            беды.append(f"{поле} не sha256")
    поколение = манифест["generation"]
    if not isinstance(поколение, int) or isinstance(поколение, bool) or поколение < 1:
        беды.append(f"поколение негодно: {поколение!r}")
    длительность = манифест["build_duration_seconds"]
    if not isinstance(длительность, (int, float)) or длительность < 0:
        беды.append(f"длительность сборки негодна: {длительность!r}")
    # Цель отката пуста только у первого релиза витрины: у релиза, за которым
    # есть история, пустая цель — это отказ от отката, а не его отсутствие.
    if манифест["previous_release_id"] and not манифест["rollback_release_id"]:
        беды.append("цель отката пуста при существующем предыдущем релизе")
    return беды


__all__ = ["ОБЯЗАТЕЛЬНЫЕ", "нарушения"]
