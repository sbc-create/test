#!/usr/bin/env python3
"""Zona: нераспознанный или пустой фильтр выдачи — 404, без canonical. Перенос по якорям.

knowledge/SEO_KNOWLEDGE_PACK.md §3 п.3–4: неизвестные ключи и значения
запрещены; пустые категории, теги и фильтры не публикуются как indexable 200.
Замер 12.10 (automation/local/empty-facet-audit.py): /catalog/?genre=<нет такого>,
/year/1066/, /catalog/?year=1066 у трёх Zona — 200, index, canonical на себя,
H1 «Некорректный фильтр». Вид уже знал, что фильтр не распознан, и звал
оболочку с код=400, но маршрут отдавал ответ всегда с 200.

Правка: вид кладёт код ответа в `_код_ответа` (нераспознанный фильтр и фильтр
с условиями, под которые не попала ни одна запись, — 404; голый пустой раздел
не трогается: пустота снимка — состояние данных, а не фильтра); оболочка
получает этот код и не ставит canonical; маршрут списка отдаёт ответ с ним.

Нет якоря или он не единственный — отказ ДО записи. Повтор ничего не меняет.

    python3 automation/host/apply-empty-filter-404.py [--check] <lords-frontend.py> […]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

МЕТКА = "def _отдать_вид(self"
ЯКОРЯ = [
    ('''            return self.оболочка(тело, f"Некорректный фильтр — {self.имя}",
                                 разд + "/", код=400)
''',
     '''            # Нераспознанный фильтр — не страница (SEO_KNOWLEDGE_PACK §3 п.3–4).
            self._код_ответа = 404
            return self.оболочка(тело, f"Некорректный фильтр — {self.имя}",
                                 разд + "/", код=404)
'''),
    ('''        elif есть_условия:
            сетка = ('<div class="zempty"><b>Ничего не подошло</b>'
''',
     '''        elif есть_условия:
            # Фильтр, под который не попала ни одна запись, — пустая выборка, а
            # не страница: 404 и без canonical (SEO_KNOWLEDGE_PACK §3 п.4).
            self._код_ответа = 404
            сетка = ('<div class="zempty"><b>Ничего не подошло</b>'
'''),
    ('''    def _переход(self, цель: str):
''',
     '''    def _отдать_вид(self, в, тело: str):
        """Отдать страницу вида с кодом, который вид назначил сам (404 пустого фильтра).

        Код снимается с вида после отдачи: вид, переживший запрос, не должен
        отдать следующую страницу с чужим кодом.
        """
        код = getattr(в, "_код_ответа", 200)
        в.__dict__.pop("_код_ответа", None)
        return self._отдать(тело.encode("utf-8"), код=код)

    def _переход(self, цель: str):
'''),
]
ОТДАЧА = re.compile(r'self\._отдать\(в\.список\(([^\n]*?)\)\.encode\("utf-8"\)\)')
#: Последний вызов оболочки в списке Zona: описание у сборок разное
#: («на {имя}» / «на витрине {имя}»), поэтому якорь — по форме, а не по тексту.
ОБОЛОЧКА_СПИСКА = re.compile(
    r'(        return self\.оболочка\(тело, f"\{титул\}\{хвост\} — \{self\.имя\}", адрес,\n'
    r'\s+актив=актив,\n\s+описание=f"[^"\n]*",\n\s+сверху="")\)')


def привести(текст: str) -> tuple[str, int]:
    if МЕТКА in текст:
        return текст, 0
    for было, _ in ЯКОРЯ:
        if текст.count(было) != 1:
            raise ValueError(f"якорь найден не ровно один раз: {было.strip().splitlines()[0][:60]}")
    if len(ОБОЛОЧКА_СПИСКА.findall(текст)) != 1:
        raise ValueError("последний вызов оболочки списка найден не ровно один раз")
    for было, стало in ЯКОРЯ:
        текст = текст.replace(было, стало)
    текст = ОБОЛОЧКА_СПИСКА.sub(r'\1, код=getattr(self, "_код_ответа", 200))', текст)
    текст, n = ОТДАЧА.subn(r"self._отдать_вид(в, в.список(\1))", текст)
    if n == 0:
        raise ValueError("маршрутов списка не найдено")
    return текст, n


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("files", nargs="+")
    a = ap.parse_args(argv)
    код = 0
    for имя in a.files:
        путь = Path(имя)
        текст = путь.read_text(encoding="utf-8")
        try:
            новый, n = привести(текст)
        except ValueError as exc:
            print(f"{имя}: ОТКАЗ — {exc}")
            код = 2
            continue
        if a.check:
            print(f"{имя}: {'приведён' if новый == текст else 'не приведён'}")
            код = код or (0 if новый == текст else 1)
            continue
        if новый != текст:
            путь.write_text(новый, encoding="utf-8")
        print(f"{имя}: маршрутов списка переведено {n}")
    return код


if __name__ == "__main__":
    sys.exit(main())
