#!/usr/bin/env python3
"""srcset объявляет только те ширины, которые источник действительно отдаёт.

ПОВОД (MOD-214), измеренный 27.10 прямым запросом тринадцати обложек ленты
главной `animedia.icu` по трём ширинам кандидатов: `?w=160` отдаёт 160 у всех
тринадцати, `?w=240` — 240 у всех, а `?w=480` — только у десяти; у трёх
возвращается 424, 317 и 443 пикселя.

ИСТОЧНИК ВЕДЁТ СЕБЯ ПРАВИЛЬНО: он не увеличивает картинку. Растягиваем МЫ —
`_srcset_постера` объявляет дескрипторы `160w/240w/320w/480w` одинаково для
каждой обложки, не зная настоящей ширины оригинала. Браузер дескриптору
верит, берёт кандидата, получает файл уже обещанного и тянет его до слота.

ПОЧЕМУ ИЗМЕРЕНИЕ ПРИ ПОЛУЧЕНИИ, А НЕ ПРИ ОТРИСОВКЕ. Признака ширины в снимке
каталога нет — проверено перебором полей записи: из относящихся к обложке там
только `poster_url` и `poster_source`. Значит ширину надо измерить самим. Но
измерять на каждый просмотр страницы значило бы грузить и декодировать
обложки ради разметки. Поэтому ширина снимается ОДИН раз — там, где картинка
и так получена и декодирована, — и остаётся в памяти процесса рядом с самим
кэшем обложек.

ЧТО ДЕЛАЕТ.
  * `_ПОСТЕР_РАЗМЕР`: ключ обложки → (время, настоящая ширина оригинала).
  * В пути получения ширина снимается с СЫРЫХ байтов источника, до любого
    уменьшения: после уменьшения это уже не ширина оригинала.
  * `_srcset_постера` объявляет кандидатов строго меньше настоящей ширины и
    добавляет один дескриптор на саму настоящую ширину.

ЧЕГО НЕ ДЕЛАЕТ. Не обещает правды до первого получения обложки: пока ширина
не измерена, поведение прежнее. Это честная граница, а не недоделка —
разметка страницы готовится раньше, чем браузер попросит картинку.

    python3 automation/host/apply-poster-truewidth-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

ПАМЯТЬ_БЫЛО = '''_ПОСТЕР_КЭШ: dict[str | tuple[str, int], tuple[float, bytes, str]] = {}'''
ПАМЯТЬ_СТАЛО = '''_ПОСТЕР_КЭШ: dict[str | tuple[str, int], tuple[float, bytes, str]] = {}
#: Ключ обложки → (время замера, настоящая ширина оригинала в пикселях).
#: Заполняется при ПОЛУЧЕНИИ обложки, один раз на обложку, и живёт рядом с
#: самим кэшем картинок. Нужна затем, чтобы srcset не объявлял ширины,
#: которых источник не отдаёт: он не увеличивает картинку, и дескриптор
#: `480w` у оригинала шириной 317 — это обещание, за которое платит зритель
#: растянутой обложкой (MOD-214).
_ПОСТЕР_РАЗМЕР: dict[str, tuple[float, int]] = {}


def _ширина_оригинала(данные: bytes, тип: str) -> int | None:
    """Ширина картинки по её заголовку. None — измерить не удалось.

    Pillow читает размер из заголовка, не декодируя всё изображение, поэтому
    замер дёшев. Отсутствие Pillow, битые байты и анимация — не повод
    выдумать число: возвращается None, и дескрипторы остаются прежними.
    """
    if тип not in ("image/webp", "image/jpeg", "image/png"):
        return None
    try:
        import io

        from PIL import Image

        with Image.open(io.BytesIO(данные)) as им:
            ш = int(им.size[0])
        return ш if ш > 0 else None
    except Exception:  # noqa: BLE001
        return None'''

ЗАМЕР_БЫЛО = '''        исходник, тип_исходника = данные, тип
        данные, тип = _уменьшить_постер(данные, тип)'''
ЗАМЕР_СТАЛО = '''        исходник, тип_исходника = данные, тип
        # Ширина снимается с СЫРЫХ байтов источника, до любого уменьшения:
        # после него это уже не ширина оригинала, а наша собственная.
        _настоящая = _ширина_оригинала(исходник, тип_исходника)
        if _настоящая:
            _ПОСТЕР_РАЗМЕР[ключ] = (сейчас, _настоящая)
            if len(_ПОСТЕР_РАЗМЕР) > 8192:
                for _у, _ in sorted(_ПОСТЕР_РАЗМЕР.items(),
                                    key=lambda п: п[1][0])[:2048]:
                    _ПОСТЕР_РАЗМЕР.pop(_у, None)
        данные, тип = _уменьшить_постер(данные, тип)'''

SRCSET_БЫЛО = '''    кандидаты = ", ".join(
        [f"{а}?w={w} {w}w" for w in ПОСТЕР_ШИРИНЫ if w < ПОСТЕР_МАКС_ШИРИНА]
        + [f"{а} {ПОСТЕР_МАКС_ШИРИНА}w"]
        + [f"{а}?w={w} {w}w" for w in ПОСТЕР_ШИРИНЫ
           if шире and w > ПОСТЕР_МАКС_ШИРИНА])'''
SRCSET_СТАЛО = '''    # Настоящая ширина оригинала, если обложку уже получали. Пока не
    # получали — поведение прежнее: разметка готовится раньше, чем браузер
    # попросит картинку, и выдумывать здесь нечего.
    _измерено = _ПОСТЕР_РАЗМЕР.get(_постер_безопасный_ключ(адрес[len("/poster/"):]) or "")
    настоящая = _измерено[1] if _измерено else None
    if настоящая:
        # Объявляется только то, что источник отдаёт. Кандидаты шире
        # оригинала не предлагаются вовсе, а сам оригинал объявляется своей
        # шириной, а не предельной: дескриптор `480w` у файла шириной 317 —
        # это обещание, за которое платит зритель растянутой обложкой.
        потолок = min(настоящая, ПОСТЕР_МАКС_ШИРИНА if not шире else настоящая)
        мельче = [w for w in ПОСТЕР_ШИРИНЫ if w < потолок]
        кандидаты = ", ".join([f"{а}?w={w} {w}w" for w in мельче]
                              + [f"{а} {потолок}w"])
    else:
        кандидаты = ", ".join(
            [f"{а}?w={w} {w}w" for w in ПОСТЕР_ШИРИНЫ if w < ПОСТЕР_МАКС_ШИРИНА]
            + [f"{а} {ПОСТЕР_МАКС_ШИРИНА}w"]
            + [f"{а}?w={w} {w}w" for w in ПОСТЕР_ШИРИНЫ
               if шире and w > ПОСТЕР_МАКС_ШИРИНА])'''

ТРЕБОВАНИЕ = "_ПОСТЕР_КЭШ"
ПАРЫ = (
    ("память о настоящей ширине", ПАМЯТЬ_БЫЛО, ПАМЯТЬ_СТАЛО,
     "_ПОСТЕР_РАЗМЕР: dict", ТРЕБОВАНИЕ),
    ("замер при получении", ЗАМЕР_БЫЛО, ЗАМЕР_СТАЛО,
     "_настоящая = _ширина_оригинала(исходник", ТРЕБОВАНИЕ),
    ("srcset по настоящей ширине", SRCSET_БЫЛО, SRCSET_СТАЛО,
     "потолок = min(настоящая", ТРЕБОВАНИЕ),
)


def уместна(пара: tuple, текст: str) -> bool:
    _, было, _, признак, требование = пара
    if признак in текст:
        return True
    if требование not in текст:
        return False
    return было in текст


def остатки(текст: str) -> list:
    return [f"нет: {п[0]}" for п in ПАРЫ if уместна(п, текст) and п[3] not in текст]


def применить(текст: str) -> tuple[str, list]:
    журнал, затронуто = [], 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if требование not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
        затронуто += 1
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if not [п for п in ПАРЫ if уместна(п, исходный)]:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
