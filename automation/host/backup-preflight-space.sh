#!/usr/bin/env bash
# Хватит ли места ДО СБОРА staging — политика на числах, без обращения к диску.
#
# Повод, измеренный 13.10. Прежняя проверка (`backup-space-precheck.sh`) стоит
# ПОСЛЕ сбора: она берёт `du` уже собранного staging. То есть она защищает
# упаковку и распаковку, но не сам сбор — а именно сбор и заполнил раздел:
# rsync `$REPO/var/` в `/tmp/tmp.7AGWgdx5OP/stage/factory-var/` довёл
# `/dev/vda1` (204 ГиБ) до 424 МиБ свободного.
#
# Второй повод — моя собственная ошибка в оценке. Я считал «нужно
# 3,6 × staging», подставляя за staging размер СЖАТОГО архива (3,10 ГиБ), и
# получал 11,16 ГиБ. Источники в несжатом виде весят 27,00 ГиБ: `$REPO/var/`
# 25,10 (из них `var/lords/publish-backups` — 23,15 ГиБ в 588 файлах,
# суточные копии `*-details.json` по ~110 МиБ), `/srv/sites/` 1,91. Сжатие
# ~8,7×, и нижняя граница была выдана за величину.
#
# Пиковое потребление по этапам, если staging удаляется сразу после упаковки
# (так и сделано в сценарии):
#
#   сбор:            S
#   манифест:        S                     (суммы считаются по staging)
#   упаковка:        S + A                 (A — архив)
#   удаление stage:  A
#   восстановление:  A + S                 (распаковка рядом)
#   git bundle:      + B во временном каталоге
#
# Пик = S + A + B. Без удаления staging пик был бы 2S + A + B.
#
# Нужно, с запасом MARGIN_PCT и резервом RESERVE_KB для работающих сайтов:
#
#   need = S + A + B + запас + резерв
#
# Все числа приходят аргументами: политику можно прогнать, не заполняя диск.
#
# Аргументы, в килобайтах:
#   $1 — суммарный размер ИСТОЧНИКОВ сбора (несжатый)
#   $2 — оценка архива (0 — считать по S и коэффициенту сжатия по умолчанию)
#   $3 — оценка git bundle (0 — не учитывать)
#   $4 — свободно на разделе
#   $5 — резерв для работающих сайтов (0 — взять по умолчанию)
set -uo pipefail

SOURCES_KB="${1:?нужен размер источников в КБ}"
ARCHIVE_KB="${2:-0}"
BUNDLE_KB="${3:-0}"
AVAIL_KB="${4:?нужно свободное место в КБ}"
RESERVE_KB="${5:-0}"

MARGIN_PCT="${SITE_FACTORY_BACKUP_SPACE_MARGIN_PCT:-20}"
#: Резерв для работающих сайтов. Раздел общий: на нём живут и витрины, и их
#: данные, и журналы. Бэкап не вправе занимать последние гигабайты — иначе
#: падает не бэкап, а сайты.
RESERVE_DEFAULT_KB="${SITE_FACTORY_BACKUP_RESERVE_KB:-5242880}"   # 5 ГиБ
#: Коэффициент сжатия по умолчанию. Берётся ОСТОРОЖНО (вдвое), а не по
#: измеренным 8,7×: на других данных сжатие хуже, и ошибаться надо в сторону
#: отказа, а не в сторону заполненного диска.
COMPRESS_DIV="${SITE_FACTORY_BACKUP_COMPRESS_DIV:-2}"

[ "$RESERVE_KB" -gt 0 ] 2>/dev/null || RESERVE_KB="$RESERVE_DEFAULT_KB"
[ "$ARCHIVE_KB" -gt 0 ] 2>/dev/null || ARCHIVE_KB=$(( SOURCES_KB / COMPRESS_DIV ))

with_margin() { echo $(( $1 + $1 * MARGIN_PCT / 100 )); }
human() { awk -v kb="$1" 'BEGIN{printf "%.2f GiB", kb/1048576}'; }

PEAK_KB=$(( SOURCES_KB + ARCHIVE_KB + BUNDLE_KB ))
NEED_KB=$(( $(with_margin "$PEAK_KB") + RESERVE_KB ))

printf 'источники %s; архив (оценка) %s; bundle %s\n' \
  "$(human "$SOURCES_KB")" "$(human "$ARCHIVE_KB")" "$(human "$BUNDLE_KB")"
printf 'пик этапов %s; запас %s%%; резерв сайтам %s; нужно %s; свободно %s\n' \
  "$(human "$PEAK_KB")" "$MARGIN_PCT" "$(human "$RESERVE_KB")" \
  "$(human "$NEED_KB")" "$(human "$AVAIL_KB")"

if [ "$AVAIL_KB" -lt "$NEED_KB" ]; then
  echo "недостаточно места ДО СБОРА: нужно $(human "$NEED_KB") (пик этапов $(human "$PEAK_KB") + запас ${MARGIN_PCT}% + резерв сайтам $(human "$RESERVE_KB")), свободно $(human "$AVAIL_KB"). Сбор не начинался, предыдущие копии целы" >&2
  exit 1
fi
echo "места достаточно: сбор можно начинать"
exit 0
