#!/usr/bin/env bash
# Удержание копий баз витрин: сколько наборов хранить и какие не трогать никогда.
#
# Зачем отдельным скриптом. Сам `deploy/staging/backup.sh` живёт в репозитории
# сайта и удержания не имеет: каждый прогон создаёт новый каталог, старые не
# удаляются. Пока копии снимались только при выкатке, наборов накопилось шесть —
# незаметно. Ежедневный таймер сделает рост постоянным, а этот диск уже ломался
# ровно на неограниченном росте бэкапов: 2026-09-03 host-бэкап упал с
# `No space left on device`.
#
# Дописывать удаление файлов в чужой скрипт мимоходом нельзя, поэтому удержание
# вынесено сюда и вызывается таймером после копирования. Скрипт сайта остаётся
# нетронутым и продолжает делать ровно то, что делал.
#
# Три предохранителя, каждый нужен:
#
#   * набор, на который указывает `latest`, не удаляется никогда — именно его
#     возьмёт откат, и удалить его значило бы оставить откат без данных;
#   * ниже пола наборов не опускаемся, сколько бы ни просили;
#   * удаляются только каталоги, чьё имя выглядит как метка времени, — случайный
#     файл рядом не должен исчезнуть из-за правила, которое про него ничего не знает.
set -uo pipefail

ROOT="${1:-${SITE_BACKUP_ROOT:-/srv/backups/yummyani-staging}}"
KEEP="${SITE_BACKUP_KEEP:-14}"
KEEP_FLOOR="${SITE_BACKUP_KEEP_FLOOR:-3}"

[ -d "$ROOT" ] || { echo "удержание: каталог $ROOT не существует" >&2; exit 0; }

# На что указывает latest — этот набор неприкосновенен.
protected=""
if [ -L "$ROOT/latest" ]; then
  protected="$(basename "$(readlink "$ROOT/latest")")"
fi

# Наборы — только каталоги вида 20260903T032419Z, от старых к новым.
mapfile -t sets < <(
  find "$ROOT" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' 2>/dev/null |
    grep -E '^[0-9]{8}T[0-9]{6}Z$' | sort
)

total=${#sets[@]}
if [ "$total" -le "$KEEP" ] || [ "$total" -le "$KEEP_FLOOR" ]; then
  echo "удержание: наборов $total при пороге $KEEP — удалять нечего"
  exit 0
fi

drop=$(( total - KEEP ))
[ $(( total - drop )) -lt "$KEEP_FLOOR" ] && drop=$(( total - KEEP_FLOOR ))

removed=0
for (( i = 0; i < drop; i++ )); do
  name="${sets[$i]}"
  if [ "$name" = "$protected" ]; then
    echo "удержание: $name пропущен — на него указывает latest"
    continue
  fi
  rm -rf "${ROOT:?}/${name:?}"
  echo "удержание: удалён набор $name"
  removed=$(( removed + 1 ))
done

echo "удержание: было $total, удалено $removed, осталось $(( total - removed ))"
