def прочитать(путь: Path, умолчание):
    try:
        return json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return умолчание


def записать_атомарно(путь: Path, данные, *, режим: int = 0o644) -> None:
    """Запись через временный файл рядом и переименование.

    Витрина перечитывает эти файлы на лету. Запись на месте означала бы, что
    перечитывание, случившееся в середине записи, придёт на обрезанный JSON.
    """
    путь.parent.mkdir(parents=True, exist_ok=True)
    с, врем = tempfile.mkstemp(dir=str(путь.parent), prefix=путь.name, suffix=".tmp")
    try:
        with os.fdopen(с, "w", encoding="utf-8") as ф:
            json.dump(данные, ф, ensure_ascii=False)
        os.chmod(врем, режим)
        os.replace(врем, путь)
    except BaseException:
        Path(врем).unlink(missing_ok=True)
        raise


def достать(url: str) -> str:
    зпр = urllib.request.Request(url, headers={"User-Agent": АГЕНТ})
    with urllib.request.urlopen(зпр, timeout=ТАЙМАУТ) as отв:
        сырое = отв.read()
    return сырое.decode("utf-8", "replace")


