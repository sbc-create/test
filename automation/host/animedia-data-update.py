#: Источник недельного расписания эфира.
#:
#: Витрина-оригинал объявляет ТОЛЬКО текущий день («Сегодня выйдет»), и
#: накопление по одному дню давало заполненную среду при нулях в остальных
#: шести — ровно то, что увидел владелец. Неделю целиком оттуда не получить:
#: страницы с сеткой по дням у оригинала нет, /daily/ её не содержит, и
#: страница тайтла даты следующей серии не несёт. Это проверено запросами, а
#: не предположено.
#:
#: Shikimori закрыт DDoS-Guard (403 на api/calendar), Jikan не отвечает (504).
#: AniList отдаёт настоящее расписание эфира на произвольное окно вместе с
#: номером серии, временем в UTC и идентификатором MyAnimeList — по нему
#: события и связываются с нашим каталогом: у 5253 незавершённых записей mal-id
#: есть.
#:
#: ВАЖНО о смысле времени. `airingAt` — это время ЭФИРА, а не время появления
#: серии на нашем сайте. Второе живёт в реестре событий и подписано
#: «Добавлено». Подменять одно другим нельзя: это разные события, и у них
#: разное время.
АНИЛИСТ = "https://graphql.anilist.co"
АНИЛИСТ_ЗАПРОС = """query ($f:Int,$t:Int,$p:Int){
  Page(page:$p, perPage:50){
    pageInfo{ hasNextPage }
    airingSchedules(airingAt_greater:$f, airingAt_lesser:$t, sort:TIME){
      episode airingAt
      media{ idMal title{ romaji } status }
    }
  }
}"""
#: Сколько страниц источника забирать максимум. Неделя укладывается в две-три;
#: предел стоит, чтобы сбой пагинации не превратился в бесконечный обход.
АНИЛИСТ_ПРЕДЕЛ_СТРАНИЦ = 20


def _анилист_неделя(начало: int, конец: int) -> list[dict]:
    """События эфира за окно. Бросает исключение, если источник недоступен."""
    собрано: list[dict] = []
    for страница in range(1, АНИЛИСТ_ПРЕДЕЛ_СТРАНИЦ + 1):
        тело = json.dumps({"query": АНИЛИСТ_ЗАПРОС,
                           "variables": {"f": начало, "t": конец, "p": страница}})
        зпр = urllib.request.Request(
            АНИЛИСТ, data=тело.encode("utf-8"),
            headers={"Content-Type": "application/json",
                     "Accept": "application/json", "User-Agent": АГЕНТ})
        with urllib.request.urlopen(зпр, timeout=ТАЙМАУТ) as отв:
            ответ = json.loads(отв.read().decode("utf-8", "replace"))
        if ответ.get("errors"):
            raise ValueError(str(ответ["errors"])[:200])
        стр = (ответ.get("data") or {}).get("Page") or {}
        собрано += [с for с in (стр.get("airingSchedules") or []) if isinstance(с, dict)]
        if not ((стр.get("pageInfo") or {}).get("hasNextPage")):
            break
        time.sleep(0.8)
    return собрано


def шаг_расписания(данные: Path, указатель: Указатель) -> dict:
    """Недельное расписание эфира.

    Окно — от начала сегодняшнего дня по Москве и семь суток вперёд. Оно
    перезабирается целиком на каждом запуске, а не дополняется: перенос и
    отмена серии видны только так. Дописывание к прежнему набору оставило бы
    на экране отменённый показ навсегда.

    Три состояния дня различаются и хранятся явно:

    * день попал в успешно загруженное окно и событий в нём нет — это
      «релизов нет», настоящий ответ;
    * день в окно не попал или окно ещё не загружалось — «данных нет»;
    * источник отказал — прежнее расписание остаётся на месте и помечается
      устаревшим.

    Последнее важно отдельно: пустой экран при сбое источника хуже вчерашнего
    расписания, а ложный ноль хуже пустого экрана.
    """
    путь = данные / f"{САЙТ}-schedule.json"
    прежнее = прочитать(путь, {}) or {}

    сегодня = сейчас()
    начало_дня = сегодня.replace(hour=0, minute=0, second=0, microsecond=0)
    конец_окна = начало_дня + timedelta(days=7)
    try:
        сырое = _анилист_неделя(int(начало_дня.timestamp()),
                                int(конец_окна.timestamp()))
    except Exception as ош:  # noqa: BLE001 — источник вне нашего контроля
        журнал(f"расписание: источник недоступен ({type(ош).__name__}: "
               f"{str(ош)[:120]}) — оставляю прежнее")
        if прежнее:
            прежнее["stale"] = True
            прежнее["last_error"] = f"{type(ош).__name__}"
            прежнее["checked_at"] = отметка(сегодня)
            записать_атомарно(путь, прежнее)
        return {"обновлено": False, "сбой": True, "причина": type(ош).__name__,
                "событий": len((прежнее or {}).get("events") or []),
                "устарело": bool(прежнее)}

    по_mal = {}
    for ид, з in указатель.записи.items():
        m = str(з.get("mal") or "").strip()
        if m:
            по_mal.setdefault(m, з)

    события, видели = [], set()
    совпало = 0
    for с in сырое:
        медиа = с.get("media") or {}
        mal = str(медиа.get("idMal") or "").strip()
        запись = по_mal.get(mal)
        if запись is None:
            continue
        try:
            когда = datetime.fromtimestamp(int(с.get("airingAt") or 0), ЗОНА)
        except (TypeError, ValueError, OSError):
            continue
        эпизод = int(с.get("episode") or 0)
        ключ = f"{запись['content_id']}:{эпизод}:{int(с['airingAt'])}"
        if ключ in видели:
            continue
        видели.add(ключ)
        совпало += 1
        события.append({
            "content_id": запись["content_id"],
            "slug": запись["slug"],
            "title": запись["title"],
            "mal_id": mal,
            "episode": эпизод,
            "airing_at": когда.isoformat(timespec="seconds"),
            "date": когда.strftime("%Y-%m-%d"),
            "weekday": когда.weekday(),
            "time_local": когда.strftime("%H:%M"),
            "source": "anilist",
            "timestamp_semantics": "broadcast",
        })
    события.sort(key=lambda з: (з["airing_at"], з["title"]))

    # Дни, о которых источник действительно ответил. Пустой день внутри окна —
    # это «релизов нет», а день вне окна — «данных нет»; без явного списка
    # отличить одно от другого нельзя.
    покрытые = [(начало_дня + timedelta(days=н)).strftime("%Y-%m-%d")
                for н in range(7)]

    записать_атомарно(путь, {
        "schema_version": 2,
        "site_id": САЙТ,
        "timezone": ЗОНА_ИМЯ,
        "generated_at": отметка(сегодня),
        "checked_at": отметка(сегодня),
        "stale": False,
        "last_error": None,
        "source": {
            "kind": "anilist-airing", "url": АНИЛИСТ,
            "match_key": "external_ids.mal",
            "note": ("время эфира, а не время появления серии на сайте; "
                     "окно перезабирается целиком, поэтому переносы и отмены "
                     "видны"),
        },
        "window": {"start": отметка(начало_дня), "end": отметка(конец_окна)},
        "covered_days": покрытые,
        "seen": len(сырое),
        "matched": совпало,
        "events": события,
    })
    по_дням: dict[str, int] = {}
    for с in события:
        по_дням[с["date"]] = по_дням.get(с["date"], 0) + 1
    return {"обновлено": True, "получено": len(сырое), "наших": совпало,
            "дней с релизами": len(по_дням), "окно": покрытые[0] + ".." + покрытые[-1]}


