def _разбор_карусели(страница: str) -> list[str]:
    край = страница.find("Новые серии аниме")
    кусок = страница[:край] if край > 0 else страница
    названия = []
    for _href, сырое in re.findall(
            r'<a href="(/[^"]+)" class="poster__link">\s*<h3[^>]*>(.*?)</h3>',
            кусок, re.S):
        имя = _html.unescape(re.sub(r"<[^>]+>", "", сырое)).strip()
        if имя:
            названия.append(имя)
    return названия


def _просмотры(данные: Path) -> dict:
    return прочитать(данные / f"{САЙТ}-views.json", {}) or {}


def шаг_популярности(данные: Path, указатель: Указатель, *,
                     порог_своих: int) -> dict:
    """Снимок «Популярного».

    Источник выбирается по убыванию доказанности:

    1. собственная статистика запусков плеера, когда её набралось достаточно,
       — это популярность нашего сайта, измеренная на нём;
    2. иначе редакционный отбор витрины-оригинала, сопоставленный с нашими
       постоянными идентификаторами.

    Во втором случае переносится ТОЛЬКО порядок. Чужие счётчики просмотров не
    копируются и за нашу статистику не выдаются: в снимке прямо записано, чей
    это отбор, когда он получен и что счётчиков в нём нет.
    """
    путь = данные / f"{САЙТ}-popular.json"
    прежний = прочитать(путь, None)

    свои = _просмотры(данные)
    счёт = {k: int(v or 0) for k, v in (свои.get("by_content_id") or {}).items()}
    достаточно = sum(счёт.values()) >= порог_своих and len(счёт) >= 8
    if достаточно:
        порядок = [ид for ид, _ in sorted(счёт.items(), key=lambda п: (-п[1], п[0]))
                   if ид in указатель.записи][:24]
        источник = {"kind": "own-playback", "url": "", "fetched_at": отметка(),
                    "note": "порядок по числу запусков плеера на этом сайте"}
        алгоритм = "own-playback-count/1.0"
    else:
        try:
            страница = достать(ОРИГИНАЛ)
        except (urllib.error.URLError, OSError, ValueError) as ош:
            журнал(f"популярность: источник недоступен ({type(ош).__name__}) — "
                   "оставляю прежний снимок")
            return {"обновлено": False, "сбой": True, "причина": type(ош).__name__,
                    "позиций": len((прежний or {}).get("ordered_title_ids") or [])}
        названия = _разбор_карусели(страница)
        порядок, пропущено = [], []
        for имя in названия:
            з = указатель.найти(имя)
            if з is None:
                пропущено.append(имя)
                continue
            if з["content_id"] not in порядок:
                порядок.append(з["content_id"])
        источник = {
            "kind": "origin-editorial", "url": ОРИГИНАЛ, "fetched_at": отметка(),
            "positions_seen": len(названия), "positions_matched": len(порядок),
            "unmatched": пропущено[:20],
            "note": ("перенесён только порядок отбора оригинала; счётчики "
                     "просмотров оригинала не копируются и статистикой этого "
                     "сайта не являются"),
        }
        алгоритм = "origin-editorial-order/1.0"

    if len(порядок) < 4:
        журнал(f"популярность: сопоставлено {len(порядок)} позиций — "
               "меньше четырёх, оставляю прежний снимок")
        return {"обновлено": False, "причина": "мало совпадений",
                "позиций": len((прежний or {}).get("ordered_title_ids") or [])}

    начало = сейчас().replace(hour=0, minute=0, second=0, microsecond=0)
    год, неделя, _ = начало.isocalendar()
    отпечаток = hashlib.sha256(
        ("|".join(порядок) + алгоритм).encode("utf-8")).hexdigest()
    снимок = {
        "schema_version": 1,
        "site_id": САЙТ,
        "week_id": f"{год}-W{неделя:02d}",
        "timezone": ЗОНА_ИМЯ,
        "window_start": отметка(начало - timedelta(days=7)),
        "window_end": отметка(начало),
        "valid_from": отметка(),
        "valid_to": отметка(сейчас() + timedelta(days=2)),
        "algorithm_version": алгоритм,
        "algorithm_parameters_digest": hashlib.sha256(
            алгоритм.encode("utf-8")).hexdigest()[:16],
        "input_revision": отпечаток[:16],
        "cutoff_at": отметка(),
        "ordered_title_ids": порядок,
        "eligibility_policy": "в ленту берутся записи нашего каталога с постером",
        "playable_policy": "доступность серий не требуется для промоблока",
        "tie_breaker": "порядок источника",
        "snapshot_revision": отпечаток[:16],
        "generated_at": отметка(),
        "digest": отпечаток,
        "provenance": источник,
    }
    # Порядок не изменился — файл не трогаем: лишняя запись заставила бы
    # витрину перечитывать снимок впустую.
    if прежний and прежний.get("digest") == отпечаток:
        return {"обновлено": False, "причина": "порядок не изменился",
                "позиций": len(порядок), "источник": источник["kind"]}
    записать_атомарно(путь, снимок)
    return {"обновлено": True, "позиций": len(порядок),
            "источник": источник["kind"],
            "не сопоставлено": len(источник.get("unmatched") or [])}


