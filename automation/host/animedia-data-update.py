def _целое(значение) -> int | None:
    """Число из ответа источника. Не число — это отсутствие, а не ноль.

    Ноль по умолчанию здесь опасен: он означал бы «серий не осталось» и
    убрал бы уже работавшие ссылки на серии.
    """
    try:
        return int(значение)
    except (TypeError, ValueError):
        return None


def _токен_поставщика() -> str:
    """Токен из credential systemd. Наружу не возвращается ничего, кроме него.

    Значение не печатается и не попадает ни в журнал, ни в отчёт: его
    единственный потребитель — заголовок запроса.
    """
    каталог = os.environ.get("CREDENTIALS_DIRECTORY")
    if not каталог:
        return ""
    путь = Path(каталог) / os.environ.get(
        "ANIMEDIA_PROVIDER_TOKEN_CREDENTIAL", ТОКЕН_CREDENTIAL)
    if not путь.is_file():
        return ""
    return путь.read_text(encoding="utf-8").strip()


#: Предел частоты из контракта поставщика (`knowledge/cdnvideohub/
#: content-api.yaml`, `limits.min_interval_ms`). Замер показал, что без
#: выдержки запросы уходят раз в 194 мс — быстрее, чем разрешено. Ходить
#: быстрее объявленного предела значит напрашиваться на 429 и портить выдачу
#: соседним потребителям того же ключа.
ИНТЕРВАЛ_МС = 250

#: Повтор по кодам из того же контракта. Разовый 429 или 502 — это не
#: «серия не вышла»: пропустив его молча, витрина ждала бы следующего круга.
ПОВТОРЯТЬ_КОДЫ = (429, 500, 502, 503, 504)
ПОВТОРОВ = 3

_последний_запрос = [0.0]


def _выдержать_интервал() -> None:
    прошло = (time.monotonic() - _последний_запрос[0]) * 1000
    if прошло < ИНТЕРВАЛ_МС:
        time.sleep((ИНТЕРВАЛ_МС - прошло) / 1000)
    _последний_запрос[0] = time.monotonic()


def _спросить_поставщика(ид: str, токен: str) -> dict:
    """Один запрос к поставщику с выдержкой и повтором по контракту."""
    последняя = None
    for попытка in range(ПОВТОРОВ):
        _выдержать_интервал()
        запрос = urllib.request.Request(
            f"{ПОСТАВЩИК}titles/{ид}",
            headers={"Authorization": "Bearer " + токен,
                     "Accept": "application/json", "User-Agent": АГЕНТ})
        try:
            with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ) as ответ:
                тело = json.loads(ответ.read().decode("utf-8", "replace"))
            return тело.get("data") or тело
        except urllib.error.HTTPError as ош:
            последняя = ош
            if ош.code not in ПОВТОРЯТЬ_КОДЫ or попытка == ПОВТОРОВ - 1:
                raise
            # Retry-After от источника уважается: он знает свою нагрузку
            # лучше, чем наша формула отката.
            пауза = 0.0
            заголовок = (ош.headers or {}).get("Retry-After")
            if заголовок:
                try:
                    пауза = min(float(заголовок), 5.0)
                except (TypeError, ValueError):
                    пауза = 1.0
            time.sleep(пауза or min(2 ** попытка, 5))
        except (urllib.error.URLError, TimeoutError, ValueError) as ош:
            последняя = ош
            if попытка == ПОВТОРОВ - 1:
                raise
            time.sleep(min(2 ** попытка, 5))
    raise последняя if последняя else RuntimeError("поставщик не ответил")


def _путь_наложения(данные: Path) -> Path:
    return данные / f"{САЙТ}-freshness-overlay.json"


def _разобрать_запись(значение) -> dict | None:
    """Запись наложения. Терпит и старую форму — голое число.

    На боевом сайте наложение уже лежит в прежней форме `{"1": 23}`.
    Отбрасывать его при обновлении нельзя: это ровно те подтверждённые
    серии, ради которых наложение и заводилось.
    """
    if isinstance(значение, dict):
        сколько = _целое(значение.get("avail"))
        if сколько is None:
            return None
        return {"avail": сколько,
                "source": str(значение.get("source") or "provider-api"),
                "checked_at": значение.get("checked_at") or ""}
    сколько = _целое(значение)
    if сколько is None:
        return None
    return {"avail": сколько, "source": "provider-api", "checked_at": ""}


def _наложить_на_снимок(данные: Path, снимок: dict) -> int:
    """Наложить подтверждённые числа на ещё не записанный снимок.

    Возвращает, сколько сезонов поправлено. Файл снимка не читает и не
    пишет: он в этот момент готовится к записи вызывающей стороной.
    """
    записи = (прочитать(_путь_наложения(данные), {}) or {}).get("titles") or {}
    if not записи:
        return 0
    подробности = (снимок.get("details") or {}) if isinstance(снимок, dict) else {}
    if not подробности:
        return 0
    по_ид = {str(з.get("id")): з for з in подробности.values() if з.get("id")}
    поправлено = 0
    for ид, сезоны in записи.items():
        запись = по_ид.get(str(ид))
        if запись is None:
            continue
        for номер, сырое in (сезоны or {}).items():
            подтверждение = _разобрать_запись(сырое)
            if подтверждение is None:
                continue
            for сезон in (запись.get("seasons") or []):
                if str(сезон.get("n")) != str(номер):
                    continue
                if (_целое(сезон.get("avail")) or 0) >= подтверждение["avail"]:
                    break
                сезон["avail"] = подтверждение["avail"]
                сезон["eps"] = max(_целое(сезон.get("eps")) or 0,
                                   подтверждение["avail"])
                поправлено += 1
                break
    return поправлено


def применить_наложение(данные: Path) -> dict:
    """Вернуть в снимок подтверждённые поставщиком числа серий.

    ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Доставка каталога перезаписывает снимок
    подробностей целиком, и поправка, сделанная опросом, живёт только до
    следующей доставки. А опрос идёт по кругу: тайтл, которого в этом круге
    ещё не коснулись, откатывается к старому числу серий. Наблюдалось на
    боевом сайте: «Моя судьба злодея» поднималась до 23 серий и падала
    обратно до 9, ссылки на серии 10-23 снова отвечали 404.

    Наложение — это память о том, что поставщик УЖЕ подтвердил, с указанием
    ОТКУДА и КОГДА. Оно применяется после каждой доставки, поэтому число
    серий не скачет между прогонами, а список серий, карточка и «Новые
    серии» остаются согласованы.

    ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Это не правило «число только растёт». Отзыв прав и
    снятие потока — настоящие события, и держать ссылку на снятую серию
    хуже, чем показать меньшее число: посетитель получает страницу, на
    которой нечего смотреть. Поэтому понижение принимается — но только от
    ПРЯМОГО ответа поставщика (`шаг_свежести`), а не от доставленного
    снимка. Доставленный снимок бывает старше нашего опроса, и принимать
    его понижение значило бы откатывать то, что мы только что подтвердили.

    Запись выбывает из наложения, когда доставленный каталог её догнал:
    дальше источник снова авторитет, и держать копию незачем.
    """
    итог = {"наложено": 0, "снято": 0}
    путь = _путь_наложения(данные)
    наложение = прочитать(путь, {}) or {}
    записи = наложение.get("titles") or {}
    if not записи:
        return итог

    файл = данные / f"{САЙТ}-details.json"
    снимок = прочитать(файл, {})
    подробности = (снимок.get("details") or {}) if isinstance(снимок, dict) else {}
    if not подробности:
        return итог

    по_ид = {}
    for slug, запись in подробности.items():
        ид = запись.get("id")
        if ид:
            по_ид[str(ид)] = запись

    изменено = False
    осталось = {}
    for ид, сезоны in записи.items():
        запись = по_ид.get(str(ид))
        if запись is None:
            осталось[ид] = сезоны          # тайтл временно не в снимке
            continue
        держим = {}
        for номер, сырое in (сезоны or {}).items():
            подтверждение = _разобрать_запись(сырое)
            if подтверждение is None:
                continue
            for сезон in (запись.get("seasons") or []):
                if str(сезон.get("n")) != str(номер):
                    continue
                текущее = _целое(сезон.get("avail")) or 0
                if текущее >= подтверждение["avail"]:
                    итог["снято"] += 1      # источник догнал
                    break
                сезон["avail"] = подтверждение["avail"]
                сезон["eps"] = max(_целое(сезон.get("eps")) or 0,
                                   подтверждение["avail"])
                держим[номер] = подтверждение
                итог["наложено"] += 1
                изменено = True
                break
        if держим:
            осталось[ид] = держим
    if изменено:
        снимок["details"] = подробности
        записать_атомарно(файл, снимок)
    if осталось != записи:
        записать_атомарно(путь, {"schema_version": 2, "site": САЙТ,
                                 "titles": осталось, "обновлено_в": отметка()})
    return итог


def _запомнить_в_наложении(данные: Path, ид: str, сезон: str, значение: int,
                           *, понижение: bool = False) -> None:
    """Запомнить подтверждённое поставщиком число серий.

    `понижение=True` означает, что поставщик В ПРЯМОМ ОТВЕТЕ назвал меньшее
    число, чем мы держали: поток снят или права отозваны. Такое принимается,
    иначе витрина вечно показывала бы ссылки на серии, которых нет. Понижение
    от доставленного снимка сюда не попадает вовсе — его приносит только
    `шаг_свежести`.
    """
    путь = _путь_наложения(данные)
    наложение = прочитать(путь, {}) or {}
    записи = наложение.get("titles") or {}
    сезоны = записи.setdefault(str(ид), {})
    прежнее = _разобрать_запись(сезоны.get(str(сезон)))
    if прежнее is not None and not понижение and значение <= прежнее["avail"]:
        return
    сезоны[str(сезон)] = {"avail": значение, "source": "provider-api",
                          "checked_at": отметка()}
    записать_атомарно(путь, {"schema_version": 2, "site": САЙТ,
                             "titles": записи, "обновлено_в": отметка()})


def шаг_свежести(данные: Path, указатель: "Указатель") -> dict:
    """Спросить поставщика о сериалах по кругу и поправить число серий.

    ЗАЧЕМ. Число вышедших серий приезжает в `avail` из
    `available_episodes_count` общего кэша подробностей. У кэша TTL семь
    суток при бюджете 6000 записей в сутки на 53688 — примерно раз в девять
    суток на запись. Серия, вышедшая сегодня, попадала на витрину через
    неделю с лишним, и ошибки при этом не возникало нигде.

    ПОЧЕМУ ПО КРУГУ, А НЕ «ТОЛЬКО ПРОДОЛЖАЮЩИЕСЯ». Поставщик поднимает
    `available_episodes_count` и `episodes_count` ВМЕСТЕ. Поэтому выросший
    сезон в нашем устаревшем снимке выглядит завершённым: доступно равно
    заявленному, и отбор «доступно меньше заявленного» его не видит.
    Измерено: «Моя судьба злодея» стояла на 9 сериях при 23 у поставщика,
    «Клеватесс 2» — на 11 при 12. Обе записи в наборе продолжающихся не
    значились.

    ПОЧЕМУ НЕ ИНКРЕМЕНТАЛЬНО. У API есть `updated_since`, но он опирается на
    `updated_at`, а тот при выходе серии НЕ меняется: у «Моей судьбы
    злодея» серии выросли с 9 до 23 после 22 сентября, а `updated_at`
    остался 2026-09-10. Событий источник не отдаёт. Значит — ограниченный
    частый опрос с сохранением позиции.

    ПОРЯДОК. Сначала те, у кого доступно меньше заявленного: у них серия
    ожидается со дня на день. Затем — круг по остальным сериалам с того
    места, где остановился прошлый прогон. Позиция хранится между
    запусками, поэтому полный круг проходится за предсказуемое время, а не
    зависит от удачи.

    ЧТО ЗАПИСЫВАЕТСЯ. Только `avail` и только вверх: уменьшение — это отзыв
    прав или сбой выдачи, и снимать уже работавшую ссылку по одному ответу
    нельзя. Событие о новой серии здесь НЕ пишется — его делает обычное
    сравнение снимков, поэтому у восстановленной серии тот же ключ, порядок
    и семантика времени, что у обычной.
    """
    итог: dict = {"опрошено": 0, "обновлено": 0, "тайтлов": [],
                  "источник": ПОСТАВЩИК}
    токен = _токен_поставщика()
    if not токен:
        итог["пропущено"] = "нет credential с токеном поставщика"
        return итог

    путь = данные / f"{САЙТ}-details.json"
    снимок = прочитать(путь, {})
    подробности = (снимок.get("details") or {}) if isinstance(снимок, dict) else {}
    if not подробности:
        итог["пропущено"] = "нет снимка подробностей"
        return итог

    # Все сериалы витрины, в устойчивом порядке: круг обязан быть
    # воспроизводимым, иначе «позиция» ничего не гарантирует.
    сериалы, срочные = [], []
    for slug in sorted(подробности):
        запись = подробности[slug]
        ид = запись.get("id")
        сезоны = запись.get("seasons") or []
        if not ид or not сезоны:
            continue
        сериалы.append((slug, ид))
        for сезон in сезоны:
            доступно = _целое(сезон.get("avail"))
            всего = _целое(сезон.get("eps"))
            if доступно and всего and доступно < всего:
                срочные.append((slug, ид))
                break

    путь_позиции = данные / f"{САЙТ}-freshness-state.json"
    состояние = прочитать(путь_позиции, {}) or {}
    позиция = int(состояние.get("позиция") or 0)
    if позиция >= len(сериалы):
        позиция = 0

    срочные_ключи = {к for к in срочные}
    # Круг начинается с сохранённой позиции и заворачивается. Срочные из
    # него исключаются: они уже в очереди впереди и второй запрос не нужен.
    круг = [п for п in (сериалы[позиция:] + сериалы[:позиция])
            if п not in срочные_ключи]
    очередь = срочные + круг[:max(0, ПРЕДЕЛ_ОПРОСА - len(срочные))]

    итог["сериалов"] = len(сериалы)
    итог["срочных"] = len(срочные)
    итог["позиция_с"] = позиция

    изменено = False
    отказов = 0
    пройдено_круга = 0
    for slug, ид in очередь:
        итог["опрошено"] += 1
        if (slug, ид) not in срочные_ключи:
            пройдено_круга += 1
        try:
            ответ = _спросить_поставщика(ид, токен)
        except Exception:  # noqa: BLE001 — один тайтл не роняет прогон
            отказов += 1
            continue
        у_поставщика = {str(с.get("number")): с
                        for с in (ответ.get("seasons") or [])}
        запись = подробности.get(slug) or {}
        for сезон in (запись.get("seasons") or []):
            их = у_поставщика.get(str(сезон.get("n")))
            if not их:
                continue
            стало = _целое(их.get("available_episodes_count"))
            было = _целое(сезон.get("avail"))
            if стало is None or было is None or стало == было:
                continue
            объявлено = _целое(их.get("episodes_count")) or стало
            if стало < было:
                # Поставщик в ПРЯМОМ ответе назвал меньше, чем мы держим.
                # Это снятие потока или отзыв прав, а не устаревший снимок:
                # снимок сюда не попадает вовсе. Держать ссылку на снятую
                # серию хуже, чем показать меньшее число — посетитель иначе
                # получает страницу, на которой нечего смотреть.
                сезон["avail"] = стало
                _запомнить_в_наложении(данные, ид, str(сезон.get("n")), стало,
                                       понижение=True)
                изменено = True
                итог["снято"] = итог.get("снято", 0) + 1
                итог["тайтлов"].append(
                    {"slug": slug, "сезон": сезон.get("n"), "было": было,
                     "стало": стало, "отзыв": True})
                continue
            сезон["avail"] = стало
            сезон["eps"] = max(_целое(сезон.get("eps")) or 0, объявлено, стало)
            изменено = True
            итог["обновлено"] += 1
            _запомнить_в_наложении(данные, ид, str(сезон.get("n")), стало)
            итог["тайтлов"].append(
                {"slug": slug, "сезон": сезон.get("n"), "было": было,
                 "стало": стало})

    итог["отказов"] = отказов
    if отказов and отказов == итог["опрошено"]:
        итог["сбой"] = True
        итог["причина"] = "поставщик не ответил ни разу"
        return итог

    if изменено:
        снимок["details"] = подробности
        записать_атомарно(путь, снимок)

    # УСПЕВАЕТ ЛИ ОБЩИЙ ПРОИЗВОДИТЕЛЬ.
    #
    # Свой опрос на каждой витрине — это одни и те же запросы к поставщику,
    # умноженные на число витрин. Терпимо как временная мера, пока общий
    # производитель перечитывает подробности раз в девять суток, но не как
    # устройство. Здесь копится ответ на вопрос «можно ли круг убавить»:
    # сколько полных кругов подряд опрос не нашёл ничего, чего бы уже не
    # было в доставленном каталоге. Решение принимает владелец по этому
    # числу, а не по ощущению.
    кругов_пусто = int(состояние.get("кругов_без_находок") or 0)
    завершён_круг = False
    новая_позиция = (позиция + пройдено_круга) % max(1, len(сериалы))
    if новая_позиция < позиция:
        завершён_круг = True
        кругов_пусто = 0 if состояние.get("находки_в_круге") else кругов_пусто + 1
    находки_в_круге = (0 if завершён_круг else
                       int(состояние.get("находки_в_круге") or 0)) + итог["обновлено"]
    итог["кругов_без_находок"] = кругов_пусто
    итог["производитель_успевает"] = bool(кругов_пусто >= 2)
    прогонов_на_круг = max(1, -(-len(сериалы) // max(1, ПРЕДЕЛ_ОПРОСА)))
    записать_атомарно(путь_позиции, {
        "позиция": новая_позиция, "сериалов": len(сериалы),
        "обновлено_в": отметка(),
        "прогонов_на_полный_круг": прогонов_на_круг,
        "находки_в_круге": находки_в_круге,
        "кругов_без_находок": кругов_пусто,
    })
    итог["позиция_по"] = новая_позиция
    итог["прогонов_на_полный_круг"] = прогонов_на_круг
    итог["последний_успешный_опрос"] = отметка()
    return итог


def шаг_серий(данные: Path, указатель: Указатель) -> dict:
    """Реестр «появилась новая серия» по сравнению соседних состояний.

    Состояние хранится по постоянным идентификаторам. Событие получает
    устойчивый `event_id`; повторная обработка того же снимка его не
    дублирует и записанное время не меняет.

    Первый запуск событий НЕ публикует: иначе весь каталог разом объявился бы
    вышедшим сегодня. Он только запоминает, что видит.
    """
    путь_состояния = данные / f"{САЙТ}-episode-state.json"
    путь_событий = данные / f"{САЙТ}-episode-events.json"
    состояние = прочитать(путь_состояния, {}) or {}
    реестр = прочитать(путь_событий, {}) or {}

    было = состояние.get("by_content_id")
    первый = not isinstance(было, dict) or not было
    перенос = False
    if первый and isinstance(состояние.get("seasons"), dict):
        # Прежнее состояние хранилось по адресу. Переносим его под постоянный
        # ключ один раз и БЕЗ событий: смена ключа — не выход серии.
        было = {}
        for slug, сезоны in состояние["seasons"].items():
            ид = указатель.по_slug.get(slug)
            if ид:
                было[ид] = сезоны
        первый = not было
        перенос = bool(было)

    стало = {ид: з["seasons"] for ид, з in указатель.записи.items() if з["seasons"]}
    события = [с for с in (реестр.get("events") or []) if isinstance(с, dict)]
    известные = {str(с.get("event_id") or "") for с in события}
    новые = []

    if not первый:
        момент = отметка()
        for ид, сезоны in стало.items():
            прежние = (было or {}).get(ид) or {}
            if not прежние:
                # Новый тайтл — это событие каталога, а не выхода серии.
                continue
            запись = указатель.записи.get(ид) or {}
            for номер, пара in сезоны.items():
                доступно, всего = (list(пара) + [0, 0])[:2]
                раньше = (list(прежние.get(номер) or [0, 0]) + [0, 0])[0]
                if доступно <= раньше:
                    continue
                # Серии нумеруются подряд: рост «доступно» с 15 до 16 означает
                # именно шестнадцатую. Если их прибавилось несколько, событием
                # становится каждая — так номер остаётся номером серии.
                for эп in range(раньше + 1, доступно + 1):
                    ид_события = f"{ид}:s{номер}:e{эп}"
                    if ид_события in известные:
                        continue
                    известные.add(ид_события)
                    новые.append({
                        "event_id": ид_события,
                        "content_id": ид,
                        "slug": запись.get("slug") or "",
                        "title": запись.get("title") or "",
                        "url": f"/title/{запись.get('slug')}/season-{номер}/episode-{эп}/",
                        "season": int(номер),
                        "episode": эп,
                        "episode_from": раньше,
                        "episode_to": доступно,
                        "episodes_total": всего,
                        # Это момент, когда серия стала доступна НА НАШЕМ САЙТЕ,
                        # а не эфирная дата выхода. Так она и подписана.
                        "first_seen_at": момент,
                        "episode_published_at": момент,
                        "timestamp_semantics": "appeared_on_site",
                        "detected_by": "snapshot-diff",
                    })

    if новые:
        события = новые + события
    события.sort(key=lambda с: (str(с.get("first_seen_at") or ""),
                                str(с.get("event_id") or "")), reverse=True)
    записать_атомарно(путь_событий, {
        "schema_version": 2,
        "site": САЙТ,
        "timezone": ЗОНА_ИМЯ,
        "source": "snapshot-diff",
        "timestamp_semantics": "appeared_on_site",
        "updated_at": отметка(),
        "first_run_seeded": bool(первый),
        "titles_tracked": len(стало),
        "events": события[:ПРЕДЕЛ_СОБЫТИЙ],
    })
    записать_атомарно(путь_состояния, {
        "schema_version": 2,
        "site": САЙТ,
        "updated_at": отметка(),
        "key": "content_id",
        "by_content_id": стало,
    })
    return {"новых событий": len(новые), "всего событий": len(события[:ПРЕДЕЛ_СОБЫТИЙ]),
            "первый запуск": первый, "перенос ключа": перенос,
            "тайтлов под наблюдением": len(стало)}


