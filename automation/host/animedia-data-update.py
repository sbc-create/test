def файлы_каталога() -> tuple[tuple[str, str | None], ...]:
    """Снимки, которые переносятся, — с именем витрины в имени файла.

    Считается вызовом, а не константой на импорте: имя витрины известно
    только после разбора аргументов, а константа зафиксировала бы пустое.
    """
    return (
        (f"{САЙТ}-catalog.json", "items"),
        (f"{САЙТ}-details.json", "details"),
        (f"{САЙТ}-ratings-top.json", None),
    )


def шаг_каталога(источник: Path, данные: Path) -> dict:
    """Перенос снимков из общего места в каталог данных сайта."""
    итог = {"обновлено": [], "без изменений": [], "отклонено": []}
    for имя, поле in файлы_каталога():
        откуда, куда = источник / имя, данные / имя
        if not откуда.is_file():
            итог["отклонено"].append(f"{имя}: нет в источнике")
            continue
        try:
            сырое = откуда.read_text(encoding="utf-8")
            новое = json.loads(сырое)
        except (OSError, ValueError) as ош:
            итог["отклонено"].append(f"{имя}: {type(ош).__name__}")
            continue
        # Обвал набора — признак порчи источника. Прежний файл остаётся.
        if поле:
            было = прочитать(куда, {})
            сколько_было = len((было or {}).get(поле) or [])
            сколько_стало = len((новое or {}).get(поле) or [])
            if сколько_стало == 0:
                итог["отклонено"].append(f"{имя}: пустой набор")
                continue
            if сколько_было and сколько_стало < сколько_было * (1 - ДОПУСК_ОБВАЛА):
                итог["отклонено"].append(
                    f"{имя}: {сколько_стало} вместо {сколько_было} — обвал источника")
                continue
        if куда.is_file() and куда.read_bytes() == откуда.read_bytes():
            итог["без изменений"].append(имя)
            continue
        # Подтверждённые числа серий возвращаются в снимок ДО записи, а не
        # после неё. Иначе между доставкой и наложением остаётся окно, в
        # котором на диске лежат прежние числа: витрина перечитывает снимок
        # по времени изменения файла и может попасть ровно в него — список
        # серий на минуту укоротится, а ссылки на последние серии ответят
        # 404. Одна запись вместо двух это окно закрывает.
        if поле == "details":
            итог["наложено"] = _наложить_на_снимок(данные, новое)
        записать_атомарно(куда, новое)
        итог["обновлено"].append(имя)
    return итог


