def свежесть_цепочки(данные: Path, источник: Path, итог: dict) -> dict:
    """Возраст каждого звена: источник → доставка → реестр → показ.

    ЗАЧЕМ ОТДЕЛЬНО ОТ СЧЁТЧИКА ПРОБЛЕМ. Зелёный таймер и «0 новых событий»
    не означают, что новых серий нет: ровно так выглядела витрина, стоявшая
    на тринадцати событиях, пока у поставщика выходили серии. Отсутствие
    новых выпусков — не ошибка, а вот подтверждённое обновление источника,
    не дошедшее до витрины, — ошибка. Различить их можно только по
    возрасту звеньев, и здесь он записывается числами.

    Поле `повод_проверить` поднимается не по «нулю новых», а по разрыву:
    источник обновился, а доставленная версия старше.
    """
    сейчас = datetime.now(ЗОНА)

    def возраст(путь: Path):
        if not путь.is_file():
            return None
        м = datetime.fromtimestamp(путь.stat().st_mtime, ЗОНА)
        return {"в": м.isoformat(timespec="seconds"),
                "часов": round((сейчас - м).total_seconds() / 3600, 1)}

    события = прочитать(данные / f"{САЙТ}-episode-events.json", {}) or {}
    список = [с for с in (события.get("events") or []) if isinstance(с, dict)]
    последнее = None
    if список:
        свежайшее = max(список, key=lambda с: str(с.get("first_seen_at") or ""))
        последнее = {"first_seen_at": свежайшее.get("first_seen_at"),
                     "slug": свежайшее.get("slug"),
                     "season": свежайшее.get("season"),
                     "episode": свежайшее.get("episode")}

    # Срок доставки: за сколько изменение у поставщика ГАРАНТИРОВАННО
    # доходит до витрины. Это длина полного круга опроса — не средняя, а
    # верхняя граница: тайтл, которого только что коснулись, будет
    # переспрошен ровно через круг. Событий источник не отдаёт, а
    # `updated_since` при выходе серии не срабатывает, поэтому короче круга
    # обещать нечего, и обещать не надо.
    позиция = прочитать(данные / f"{САЙТ}-freshness-state.json", {}) or {}
    прогонов = int(позиция.get("прогонов_на_полный_круг") or 0)
    период_мин = int(os.environ.get("ANIMEDIA_UPDATE_PERIOD_MINUTES", "10"))
    срок_часов = round(прогонов * период_мин / 60, 1) if прогонов else None

    цепочка = {
        "срок_доставки_часов": срок_часов,
        "круг_прогонов": прогонов or None,
        "позиция_круга": позиция.get("позиция"),
        "источник_каталога": возраст(источник / f"{САЙТ}-catalog.json"),
        "доставлено_на_сайт": возраст(данные / f"{САЙТ}-catalog.json"),
        "реестр_событий": возраст(данные / f"{САЙТ}-episode-events.json"),
        "событий_всего": len(список),
        "последнее_событие": последнее,
        "опрос_поставщика": (итог.get("freshness") or {}).get(
            "последний_успешный_опрос"),
        "продолжающихся": (итог.get("freshness") or {}).get("продолжающихся"),
    }

    # Разрыв доставки: источник новее того, что лежит у витрины. Это и есть
    # случай, который «0 новых событий» скрывает.
    ист = цепочка["источник_каталога"]
    дост = цепочка["доставлено_на_сайт"]
    if ист and дост and ист["в"] > дост["в"]:
        цепочка["застряло"] = "доставка каталога"
        цепочка["повод_проверить"] = (
            f"источник обновлён {ист['в']}, а у витрины версия {дост['в']}")

    # Круг обязан проворачиваться. Если позиция не двигалась дольше двух
    # кругов, опрос стоит — и это ошибка с названным этапом, а не тишина.
    свеж = итог.get("freshness") or {}
    if свеж.get("пропущено"):
        цепочка["застряло"] = "опрос поставщика"
        цепочка["повод_проверить"] = str(свеж["пропущено"])
    elif свеж.get("сбой"):
        цепочка["застряло"] = "опрос поставщика"
        цепочка["повод_проверить"] = str(свеж.get("причина") or "отказ источника")
    elif прогонов and позиция.get("обновлено_в"):
        try:
            тогда = datetime.fromisoformat(str(позиция["обновлено_в"]))
            простой = (сейчас - тогда).total_seconds() / 60
            if простой > 2 * прогонов * период_мин:
                цепочка["застряло"] = "круг опроса"
                цепочка["повод_проверить"] = (
                    f"позиция круга не двигалась {простой:.0f} мин "
                    f"при круге в {прогонов * период_мин} мин")
        except (TypeError, ValueError):
            pass
    return цепочка


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="обновление данных витрины семейства animedia")
    parser.add_argument("--site", required=True,
                        help="идентификатор витрины, например animedia-02; "
                             "им же названы файлы снимков")
    parser.add_argument("--domain", required=True,
                        help="канонический домен витрины; попадает в отчёты")
    parser.add_argument("--data-dir", required=True,
                        help="каталог данных ЭТОЙ витрины — единственное "
                             "место записи")
    parser.add_argument("--source-dir", default=ИСТОЧНИК_ПО_УМОЛЧАНИЮ)
    parser.add_argument("--only", action="append", default=[],
                        choices=["catalog", "freshness", "episodes", "popular", "schedule"],
                        help="выполнить только указанные шаги")
    parser.add_argument("--own-views-threshold", type=int, default=500,
                        help="сколько запусков плеера нужно, чтобы перейти "
                             "на собственную статистику популярности")
    parser.add_argument("--dry-run", action="store_true",
                        help="ничего не писать; показать, что было бы сделано")
    а = parser.parse_args(argv)

    global САЙТ, ДОМЕН
    САЙТ = а.site
    ДОМЕН = а.domain

    данные = Path(а.data_dir).resolve()
    источник = Path(а.source_dir).resolve()
    шаги = а.only or ["catalog", "freshness", "episodes", "popular", "schedule"]
    if not данные.is_dir():
        журнал(f"нет каталога данных {данные}")
        return 2

    if а.dry_run:
        глобально = globals()
        глобально["записать_атомарно"] = lambda *a, **k: журнал(
            "[сухой прогон] запись пропущена:", a[0] if a else "")

    итог: dict = {"site": САЙТ, "started_at": отметка()}
    беды = 0

    if "catalog" in шаги:
        try:
            итог["catalog"] = шаг_каталога(источник, данные)
            журнал("каталог:", итог["catalog"])
            if итог["catalog"]["отклонено"]:
                беды += 1
        except Exception as ош:  # noqa: BLE001 — шаг не должен ронять остальные
            итог["catalog"] = {"ошибка": f"{type(ош).__name__}: {ош}"}
            журнал("каталог: ОШИБКА", ош)
            беды += 1

    # Указатель строится ПОСЛЕ доставки: события считаются по тем данным,
    # которые витрина и увидит.
    каталог = прочитать(данные / f"{САЙТ}-catalog.json", {})
    подробности = прочитать(данные / f"{САЙТ}-details.json", {})
    указатель = Указатель(каталог, подробности)
    итог["catalog_items"] = len(указатель.записи)
    if not указатель.записи:
        журнал("каталог пуст — остальные шаги пропущены, прежние данные на месте")
        итог["finished_at"] = отметка()
        return 1

    # Доставка перезаписала снимок целиком — возвращаем в него уже
    # подтверждённые поставщиком числа серий, пока круг опроса до них не
    # дошёл. Иначе список серий скачет между прогонами.
    if "catalog" in шаги:
        итог["overlay"] = применить_наложение(данные)
        журнал("overlay:", итог["overlay"])
        if итог["overlay"]["наложено"]:
            подробности = прочитать(данные / f"{САЙТ}-details.json", {})
            указатель = Указатель(каталог, подробности)

    for имя, шаг in (("freshness", lambda: шаг_свежести(данные, указатель)),
                     ("episodes", lambda: шаг_серий(данные, указатель)),
                     ("popular", lambda: шаг_популярности(
                         данные, указатель, порог_своих=а.own_views_threshold)),
                     ("schedule", lambda: шаг_расписания(данные, указатель))):
        if имя not in шаги:
            continue
        try:
            итог[имя] = шаг()
            журнал(f"{имя}:", итог[имя])
            if имя == "freshness" and итог[имя].get("обновлено"):
                # Снимок изменён этим шагом: сравнение серий обязано идти по
                # новым данным, иначе новая серия будет замечена только
                # следующим прогоном.
                подробности = прочитать(данные / f"{САЙТ}-details.json", {})
                указатель = Указатель(каталог, подробности)
            # Недоступный источник — не исключение, шаг с ним справляется и
            # оставляет прежние данные. Но молча считать такой прогон
            # безупречным нельзя: постоянно лежащий источник тогда ничем не
            # отличался бы от исправного, и расписание тихо старело бы.
            #
            # Считается именно СБОЙ, а не всякое «обновлено: False». «Порядок
            # не изменился» и «мало совпадений» — штатные исходы, при которых
            # писать файл незачем; объявлять их проблемами значит приучить
            # смотреть на счётчик, который всегда не ноль.
            if isinstance(итог[имя], dict) and итог[имя].get("сбой"):
                беды += 1
        except Exception as ош:  # noqa: BLE001
            итог[имя] = {"ошибка": f"{type(ош).__name__}: {ош}"}
            журнал(f"{имя}: ОШИБКА", ош)
            беды += 1

    итог["freshness_chain"] = свежесть_цепочки(данные, источник, итог)
    итог["finished_at"] = отметка()
    итог["problems"] = беды
    if not а.dry_run:
        записать_атомарно(данные / f"{САЙТ}-update-state.json", итог)
    журнал("готово, проблем:", беды)
    return 0 if беды == 0 else 1


