def нормализовать(строка: str) -> str:
    строка = _html.unescape(строка or "").lower().replace("ё", "е")
    строка = re.sub(r"[^0-9a-zа-я]+", " ", строка)
    return " ".join(строка.split())


class Указатель:
    """Наш каталог, разложенный для поиска по названию.

    Ключ записи — её постоянный идентификатор (`details[<slug>].id`), а не
    адрес: адрес меняется при переименовании, и привязка к нему осиротела бы
    при первом же переименовании тайтла.
    """

    def __init__(self, каталог: dict, подробности: dict) -> None:
        детали = (подробности or {}).get("details") or {}
        self.записи: dict[str, dict] = {}
        self.по_названию: dict[str, str] = {}
        self.по_slug: dict[str, str] = {}
        for з in (каталог or {}).get("items") or []:
            slug = str(з.get("slug") or "")
            if not slug:
                continue
            д = детали.get(slug) or {}
            ид = str(д.get("id") or "").strip() or slug
            сезоны = {}
            for с in (д.get("seasons") or []):
                if not isinstance(с, dict):
                    continue
                try:
                    сезоны[str(int(с.get("n") or 0))] = [
                        int(с.get("avail") or 0), int(с.get("eps") or 0)]
                except (TypeError, ValueError):
                    continue
            внешние = д.get("external_ids") or {}
            self.записи[ид] = {
                "content_id": ид, "slug": slug,
                "title": з.get("title") or slug,
                "url": з.get("url") or f"/title/{slug}/",
                "poster": з.get("poster") or "",
                "seasons": сезоны,
                # Ключ связывания с расписанием эфира: у источника расписания
                # свои идентификаторы, общий с нами — только MyAnimeList.
                "mal": str(внешние.get("mal") or внешние.get("myanimelist") or "").strip(),
            }
            self.по_slug[slug] = ид
            for имя in (з.get("title"), д.get("original_name"),
                        д.get("original_title"), д.get("name")):
                ключ = нормализовать(имя or "")
                if ключ:
                    self.по_названию.setdefault(ключ, ид)

    def найти(self, название: str) -> dict | None:
        """Запись по названию. Точное совпадение, затем совпадение слов.

        Нечёткий поиск ограничен полным совпадением множества слов: «Боевой
        континент 2» и «Боевой континент» — разные произведения, и склеить их
        расстоянием редактирования значило бы подписать одну карточку именем
        другой.
        """
        ключ = нормализовать(название)
        if not ключ:
            return None
        ид = self.по_названию.get(ключ)
        if ид:
            return self.записи.get(ид)
        слова = set(ключ.split())
        if len(слова) < 2:
            return None
        for кандидат, ид in self.по_названию.items():
            if set(кандидат.split()) == слова:
                return self.записи.get(ид)
        return None


