#!/usr/bin/env python3
"""Регулярное обновление данных animedia.space.

Зачем отдельный обработчик. Каталог и подробности этого сайта производит общий
конвейер (`nova-catalog-refresh.timer` → `/srv/lords/.frontend/animedia-02-*.json`)
и обновляет их каждые пять минут. Но в каталог данных САЙТА
(`/srv/animedia-space/data`) их с момента выделения никто не переносил: файлы
там застыли на моменте миграции. Витрина при этом умеет перечитывать снимок на
лету — значит, не хватало ровно доставки.

Что делает этот обработчик и в каком порядке:

1. **каталог** — переносит снимок каталога и подробностей из общего места в
   каталог данных сайта, атомарно и с проверкой: битый или внезапно
   обвалившийся снимок не ставится, остаётся прежний;
2. **серии** — ведёт реестр событий «появилась новая серия», сравнивая
   предыдущее состояние с новым по ПОСТОЯННЫМ идентификаторам записей;
3. **популярность** — обновляет снимок «Популярного»;
4. **расписание** — копит наблюдения об ожидаемом выходе серий.

Общие правила, которые здесь не обсуждаются:

* каталог данных сайта — единственное место записи; `site-data` (комментарии,
  голоса, списки) не трогается вовсе;
* любой сбой источника оставляет прежние данные на месте: пустая витрина
  хуже вчерашней;
* первый запуск не публикует весь каталог как «новые серии»: он только
  запоминает состояние;
* повторная обработка того же снимка не создаёт дублей и не меняет уже
  записанное время события.
"""
from __future__ import annotations

import argparse
import hashlib
import html as _html
import json
import os
import re
import sys
import tempfile
import time
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path

#: Витрина, которую обслуживает запуск. Значения по умолчанию нет намеренно:
#: обработчик шаблонный, и подставленное «обычно это animedia-02» означало бы,
#: что новый сайт молча обновляет чужие файлы в общем каталоге данных. Оба
#: значения приходят аргументами запуска и проставляются в `main`.
САЙТ = ""
ДОМЕН = ""
ЗОНА = timezone(timedelta(hours=3))
ЗОНА_ИМЯ = "Europe/Moscow"

ИСТОЧНИК_ПО_УМОЛЧАНИЮ = "/srv/lords/.frontend"

#: Обвал каталога больше чем на эту долю — признак порчи источника, а не
#: правки ассортимента. Поставщик вправе убрать часть записей; каталог,
#: похудевший на треть за пять минут, допуском не объясняется.
ДОПУСК_ОБВАЛА = 0.10

#: Сколько событий о сериях держать в реестре.
ПРЕДЕЛ_СОБЫТИЙ = 400

#: Откуда берётся стартовая подборка популярности и наблюдения расписания.
#: Это витрина-оригинал: её редакционный отбор и её же объявления о времени
#: выхода. Чужие счётчики просмотров сюда не переносятся — только порядок и
#: время, и оба помечены источником.
#: Первичный источник каталога. Общий конвейер перечитывает подробности
#: тайтла раз в семь суток (TTL кэша) при бюджете 6000 записей на 53688, то
#: есть примерно раз в девять суток на запись. Для описания и постера это
#: нормально, а для числа ВЫШЕДШИХ серий — нет: новая серия становится видна
#: витрине через неделю с лишним, и «Новые серии» стоят при исправном таймере
#: и нулевых ошибках. Поэтому продолжающиеся тайтлы витрина спрашивает у
#: поставщика сама — их немного, и запрос на прогон ограничен.
ПОСТАВЩИК = "https://public-api.cdnvideohub.com/api/v1/"

#: Сколько тайтлов спрашивать за один прогон.
#:
#: Опрашивать приходится ВСЕ сериалы по кругу, а не только те, у кого
#: доступно меньше заявленного. Измерено на двух тайтлах: поставщик
#: поднимает `available_episodes_count` и `episodes_count` ВМЕСТЕ, поэтому
#: выросший сезон выглядит завершённым и в набор «продолжающихся» не
#: попадает. «Моя судьба злодея» простояла на 9 сериях, пока у поставщика
#: стало 23; «Клеватесс 2» — на 11 против 12.
#:
#: Инкрементальный отбор тут не работает: `updated_since` опирается на
#: `updated_at`, а он при выходе серии НЕ меняется. Замер: у «Моей судьбы
#: злодея» серии выросли с 9 до 23 после 22 сентября, а `updated_at` так и
#: остался 2026-09-10. Поэтому — ограниченный частый опрос по кругу с
#: сохранением позиции, как и разрешено при отсутствии событий у источника.
#:
#: Размер выбран замером и пределом юнита, а не округлением.
#:
#: Замер с обязательной выдержкой 250 мс (`limits.min_interval_ms` контракта
#: поставщика): 260 мс на запрос, полный круг по 5513 сериалам витрины —
#: 1436 с чистых запросов. Предел юнита TimeoutStartSec=600 с, и в него же
#: должны уложиться доставка каталога, расписание и популярность — на них
#: отложено около минуты. Остаётся порядка 400 с, то есть примерно 1500
#: запросов с запасом на повторы.
#:
#: Полный круг при этом — четыре прогона десятиминутного таймера, то есть
#: 40 минут: верхняя граница появления новой серии на витрине.
#:
#: Чаще запускать таймер не стал намеренно: тот же ключ поставщика уже несёт
#: круг общего производителя, и удваивать нагрузку ради вдвое более короткой
#: границы — плохой размен.
ПРЕДЕЛ_ОПРОСА = 1500

#: Имя credential systemd с токеном поставщика. Значение не печатается и в
#: отчёт не попадает: его единственный потребитель — заголовок запроса.
ТОКЕН_CREDENTIAL = "cdnvideohub_api_token"

ОРИГИНАЛ = "https://amd.online/"
АГЕНТ = "Mozilla/5.0 (X11; Linux x86_64) animedia.space-updater/1.0"
ТАЙМАУТ = 45


def журнал(*ч) -> None:
    print(f"[{САЙТ or 'animedia'}-update]", *ч, flush=True)


def сейчас() -> datetime:
    return datetime.now(ЗОНА)


def отметка(dt: datetime | None = None) -> str:
    return (dt or сейчас()).isoformat(timespec="seconds")


