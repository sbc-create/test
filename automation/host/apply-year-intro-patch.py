#!/usr/bin/env python3
"""Вступление у страницы фильтра года: `/catalog/?year=…` (T339, п. 3).

ПОВОД. Страница отдаёт 200, `index`, canonical на себя и собственный H1
«Аниме 2026 года», но своего вступления у неё нет: под заголовком сразу
служебная строка «Найдено N · страница 1 из …». Посетителю не сказано ни что
это за выборка, ни куда идти за тем, чего в ней нет.

ЧТО ДЕЛАЕТ. Добавляет одну строку под счётчиком, и только на странице, где
выбран ГОД и больше ничего: при сузившем выборку жанре или типе фраза о
составе описывала бы не то, что на экране.

ЧТО В НЕЙ ИЗМЕРЕНО, А НЕ ОБЪЯВЛЕНО. Число названий — длина выборки. Число
сериалов и фильмов — счёт по полю `type` той же выборки. Про дунхуа строка
НЕ говорит ничего: признак страны лежит в подробностях, а не в каталоге, и
тащить их чтение в выдачу ради одной фразы — цена, несоразмерная пользе
(согласовано с линией SEO 27.10).

ССЫЛКА НА ПОДБОРКУ СЕЗОНА — ТОЛЬКО ПРИ СОВПАДЕНИИ ГОДА. Подборка летнего
сезона существует для одного года. Поставить ссылку на неё на странице любого
другого года значило бы написать неправду, которая появится сама собой через
год. Поэтому ссылка ставится, лишь когда среди редакционных подборок есть та,
в ключе или заголовке которой стоит ровно запрошенный год.

    python3 automation/host/apply-year-intro-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

МЕТОД_БЫЛО = '''    def _блок_сейчас_выходит(self, *, сбоку: bool = False) -> str:'''
МЕТОД_СТАЛО = '''    def _вступление_года(self, выбрано: dict, набор: list) -> str:
        """Строка о выборке года: что это и куда идти дальше.

        Показывается, только когда выбран ГОД и ничего больше. При жанре или
        типе та же фраза описывала бы не ту выборку, что на экране.

        Все числа — счёт по этой же выборке. Про дунхуа не говорится: признак
        страны живёт в подробностях, а не в каталоге, и ради одной фразы их
        чтение в выдачу не тянется.
        """
        год = str(выбрано.get("year") or "").strip()
        сузили = [к for к in ("genre", "type", "country", "kind")
                  if выбрано.get(к)]
        if not год.isdigit() or сузили or not набор:
            return ""
        # Состава «S сериалов и M фильмов» здесь НЕТ, и это не упущение.
        # Записи каталога не несут поля `type` вовсе: у всех 8746 есть только
        # `kind`, и он у всех один — «Аниме». Вид работы живёт в подробностях,
        # ровно как и страна, ради которой мы уже отказались говорить про
        # дунхуа. Тянуть чтение подробностей в выдачу ради одной фразы —
        # несоразмерная цена, и решение по стране было тем же.
        #
        # Первая версия считала здесь `type` по записям каталога, всегда
        # получала нули и молча роняла половину согласованной фразы. Тесты
        # этого не поймали, потому что я кормил их выдуманными записями с
        # полем, которого в снимке нет.
        начало = (f"Аниме {html.escape(год)} года на сайте: {len(набор)} "
                  f"{склонение_записей(len(набор))}.")
        хвост = [' Что выходит сейчас — в <a href="/schedule/">расписании '
                 'онгоингов</a>.']
        # Подборка сезона — только своего года. Иначе через год эта ссылка
        # станет ложью сама собой, без единой правки.
        своя = next((п for п in РУЧНЫЕ_ПОДБОРКИ.values()
                     if год in п.key or год in п.title), None) if РУЧНЫЕ_ПОДБОРКИ else None
        if своя is not None:
            хвост.append(f' Законченные — в подборке '
                         f'<a href="{html.escape(своя.canonical_path)}">'
                         f'{html.escape(своя.title)}</a>.')
        return (f'<p class="zsub" data-year-intro="{html.escape(год)}">'
                f'{начало}{"".join(хвост)}</p>')

    def _блок_сейчас_выходит(self, *, сбоку: bool = False) -> str:'''

ВСТАВКА_БЫЛО = '''            f'<p class="zsub" data-b11-count="1">Найдено {len(набор)} · {pages_label}</p>'
            + фильтры'''
ВСТАВКА_СТАЛО = '''            f'<p class="zsub" data-b11-count="1">Найдено {len(набор)} · {pages_label}</p>'
            + self._вступление_года(выбрано, набор)
            + фильтры'''

ТРЕБОВАНИЕ = "def _блок_сейчас_выходит"
ПАРЫ = (
    ("метод вступления года", МЕТОД_БЫЛО, МЕТОД_СТАЛО,
     "def _вступление_года", ТРЕБОВАНИЕ),
    ("вступление встаёт под счётчиком", ВСТАВКА_БЫЛО, ВСТАВКА_СТАЛО,
     "+ self._вступление_года(выбрано, набор)", "data-b11-count"),
)


def уместна(пара: tuple, текст: str) -> bool:
    _, было, _, признак, требование = пара
    if признак in текст:
        return True
    if требование not in текст:
        return False
    return было in текст


def остатки(текст: str) -> list:
    return [f"нет: {п[0]}" for п in ПАРЫ if уместна(п, текст) and п[3] not in текст]


def применить(текст: str) -> tuple[str, list]:
    журнал, затронуто = [], 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if требование not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
        затронуто += 1
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if not [п for п in ПАРЫ if уместна(п, исходный)]:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
