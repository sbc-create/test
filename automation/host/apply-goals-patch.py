#!/usr/bin/env python3
"""Отправка целей Метрики на линии Zona. Перенос по якорям.

Измерено 27.10 на живых адресах: счётчик на страницах ЕСТЬ
(`112582938` у zonafilm.space, `113109081` у zonafilm12.site), `mc.yandex`
загружается — а ни одного `reachGoal` в разметке нет. То есть нули в отчёте о
целях означают «событие не отправлялось», а не «зритель так себя ведёт».
Поведением пользователей такие нули считать нельзя.

Переносится ТОТ ЖЕ закрытый список целей, что в каноне, и тем же способом:
единственная точка отправки `window.__sfGoal(имя)` без третьего аргумента —
вызов «с данными» написать нечем, поэтому поисковая фраза или ключ подборки в
отчёт попасть не могут.

Куда встаёт. В `тег_метрики()` — одно место на все четыре оболочки, которые его
вызывают: правка в четырёх местах разошлась бы. В скрипт плеера — на уже
существующие точки этой линии: запрос показа (`requested`), готовность
(`state('ready')`), подтверждённое воспроизведение (`confirmPlaying`) и отказ
(`nextOrFail`).

Чего инструмент НЕ делает: не создаёт цели в кабинете (это операция владельца с
токеном), не добавляет параметров к целям, не меняет счётчик и не включает
вебвизор.

    python3 automation/host/apply-goals-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

#: Тот же закрытый список, что в каноне. Имя вне списка не отправляется.
ЦЕЛИ = ("title_view", "search", "filter_apply", "season_select",
        "episode_select", "player_start", "player_ready", "player_error")

ПОМОЩНИК = '''

#: Закрытый список целей — тот же, что в каноническом рантайме. Имя вне списка
#: не отправляется: опечатка в вызове не должна заводить в кабинете
#: цель-призрак, которой нет в реестре аналитики.
ЦЕЛИ_МЕТРИКИ = (
    "title_view",       # открыта страница произведения
    "search",           # поисковый запрос отправлен (сама фраза не передаётся)
    "filter_apply",     # применён фильтр каталога (значения не передаются)
    "season_select",    # выбран сезон
    "episode_select",   # выбрана серия
    "player_start",     # площадка запросила воспроизведение
    "player_ready",     # плеер поднялся
    "player_error",     # запуск не состоялся
)


def цели_метрики(номер: str) -> str:
    """Отправка целей. Ни одного параметра — только имя из закрытого списка.

    Почему параметров нет вовсе. Метрика позволяет передать с целью
    произвольные данные, и один такой вызов из обработчика поиска вынес бы
    поисковую фразу в отчёт. Единственная точка отправки — `window.__sfGoal`,
    и третьего аргумента у неё не существует.

    Почему тип страницы определяется по адресу, а не по разметке: маршруты
    витрины свои и стабильные, а метку в разметку пришлось бы добавить в
    четыре оболочки — четыре места, где легко разойтись.
    """
    имена = ",".join(f'"{и}"' for и in ЦЕЛИ_МЕТРИКИ)
    return (
        "<script>(function(){"
        "if(window.__sfGoal){return;}"
        f"var C={номер},L=[{имена}],S={{}};"
        "function g(n){try{"
        "if(L.indexOf(n)<0){return;}"
        "if(typeof window.ym!=='function'){return;}"
        "window.ym(C,'reachGoal',n);"
        "}catch(e){}}"
        "window.__sfGoal=g;"
        "window.__sfGoalOnce=function(n){if(S[n]){return;}S[n]=1;g(n);};"
        "var p=location.pathname||'';"
        "if(/^\\\\/title\\\\//.test(p)){window.__sfGoalOnce('title_view');}"
        "document.addEventListener('submit',function(e){"
        "var f=e&&e.target; if(!f||!f.getAttribute){return;}"
        "var a=f.getAttribute('action')||'';"
        "if(f.getAttribute('role')==='search'||/\\\\/search\\\\//.test(a)){g('search');}"
        "},true);"
        "document.addEventListener('click',function(e){"
        "var n=e&&e.target,a=null;"
        "while(n&&n!==document){if(n.tagName==='A'&&n.getAttribute('href')){a=n;break;}n=n.parentNode;}"
        "if(!a){return;}"
        "var h=a.getAttribute('href')||'';"
        "if(/\\\\/season-\\\\d+\\\\/episode-\\\\d+\\\\/?$/.test(h)){g('episode_select');}"
        "else if(/\\\\/season-\\\\d+\\\\/?$/.test(h)){g('season_select');}"
        "},true);"
        "})();</script>"
    )
'''
ЯКОРЬ_ПОМОЩНИКА = "\ndef тег_метрики() -> str:"

ТЕГ_БЫЛО = """        f'<noscript><div><img src="https://mc.yandex.ru/watch/{н}" '
        'style="position:absolute;left:-9999px" alt=""></div></noscript>'
    )"""
ТЕГ_СТАЛО = """        f'<noscript><div><img src="https://mc.yandex.ru/watch/{н}" '
        'style="position:absolute;left:-9999px" alt=""></div></noscript>'
        # Отправка целей идёт ЗДЕСЬ, а не в четырёх оболочках: у тега метрики
        # один вызов на каждую из них, и правка в четырёх местах разошлась бы.
        + цели_метрики(н)
    )"""

ЗАПРОС_БЫЛО = "   requested=true;"
ЗАПРОС_СТАЛО = """   requested=true;
   /* «Площадка запросила показ» — та же формулировка, что у канона и Yummy,
      чтобы одна цель не значила на разных витринах разное. */
   try{ if(window.__sfGoalOnce){ window.__sfGoalOnce('player_start'); } }catch(e){}"""

#: Готовность у этой линии приходит ТРЕМЯ ветвями событий провайдера, и две из
#: них начинаются с `else if`. Поэтому якорь — ВНУТРЕННИЙ фрагмент, общий для
#: всех трёх, и заменяется он во всех: якорь по началу строки поймал бы одну,
#: и две ветви остались бы без события молча.
ГОТОВ_БЫЛО = "readyAt=Date.now(); state('ready'); }"
ГОТОВ_СТАЛО = ("readyAt=Date.now(); state('ready');\n"
               "    try{ if(window.__sfGoalOnce){ "
               "window.__sfGoalOnce('player_ready'); } }catch(e){} }")

ОТКАЗ_БЫЛО = " function nextOrFail(reason){"
ОТКАЗ_СТАЛО = """ function nextOrFail(reason){
  try{ if(window.__sfGoalOnce){ window.__sfGoalOnce('player_error'); } }catch(e){}"""

ПАРЫ = (
    ("помощник целей", ЯКОРЬ_ПОМОЩНИКА, ПОМОЩНИК + ЯКОРЬ_ПОМОЩНИКА,
     "def цели_метрики(номер: str)"),
    ("отправка в теге метрики", ТЕГ_БЫЛО, ТЕГ_СТАЛО, "+ цели_метрики(н)"),
    ("цель player_start", ЗАПРОС_БЫЛО, ЗАПРОС_СТАЛО, "__sfGoalOnce('player_start')"),
    ("цель player_ready", ГОТОВ_БЫЛО, ГОТОВ_СТАЛО, "ПРОВЕРЯЕТСЯ_ЧИСЛОМ"),
    ("цель player_error", ОТКАЗ_БЫЛО, ОТКАЗ_СТАЛО, "__sfGoalOnce('player_error')"),
)


def остатки(текст: str) -> list:
    плохо = [f"нет: {имя}" for имя, _, _, признак in ПАРЫ
             if признак != "ПРОВЕРЯЕТСЯ_ЧИСЛОМ" and признак not in текст]
    # Готовность проверяется ЧИСЛОМ: одно вхождение означает, что две ветви
    # событий провайдера остались без события.
    сколько = текст.count("__sfGoalOnce('player_ready')")
    if сколько < 3:
        плохо.append(f"цель player_ready стоит на {сколько} ветвях из трёх")
    return плохо


def применить(текст: str) -> tuple[str, list]:
    if "СЧЁТЧИК_МЕТРИКИ" not in текст or "def тег_метрики" not in текст:
        raise SystemExit("ОТКАЗ: в файле нет тега метрики этой линии")
    # Раннего выхода «всё уже стоит» здесь нет намеренно: он не видел
    # недоделанной готовности — помощник стоял, а событие уходило с одной
    # ветви из трёх. Состояние каждой правки проверяется своим признаком.
    журнал = []
    for имя, было, стало, признак in ПАРЫ:
        уже = (текст.count("__sfGoalOnce('player_ready')") >= 3
               if признак == "ПРОВЕРЯЕТСЯ_ЧИСЛОМ" else признак in текст)
        if уже:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        # Цель готовности встречается трижды (три ветви событий провайдера) —
        # ставится во все, иначе часть путей останется без события.
        сколько = текст.count(было) if имя == "цель player_ready" else 1
        if имя == "цель player_ready":
            # Считается ИТОГ: ненайденные ветви плюс уже отмеченные. Иначе
            # повторный прогон на файле, где часть ветвей уже отмечена,
            # отказывал бы на своей же работе.
            итого = сколько + текст.count("__sfGoalOnce('player_ready')")
            if итого < 3:
                raise SystemExit("ОТКАЗ: ветвей готовности всего "
                                 f"{итого}, а их у этой линии три — часть "
                                 "путей осталась бы без события")
        текст = текст.replace(было, стало, сколько)
        журнал.append(f"применено{f' ×{сколько}' if сколько > 1 else ''}: {имя}")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        п = остатки(новый)
        if п:
            print(f"ОТКАЗ: после правки остались признаки непривёденности: {п}",
                  file=sys.stderr)
            return 1
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
