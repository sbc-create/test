# --- Top: настоящая оценка с провенансом ------------------------------------
#
# Голосов источник не отдаёт ни для одной записи (`votes` пуст во всех 14 598
# строках), поэтому байесовское сглаживание по голосам применить не к чему.
# Подменять отсутствующие голоса числом нельзя: сглаживание с выдуманным весом
# — это выдуманный порядок. Вместо этого:
#   * значение берётся у провайдера как есть и подписывается им;
#   * разные провайдеры НЕ сводятся в одно безымянное число;
#   * порядок задаётся по выбранному провайдеру, при равенстве — по числу
#     доступных провайдеров, затем по году, затем по entity_id: устойчиво и
#     воспроизводимо;
#   * отсутствие голосов named честно, а не скрывается.
ПОРЯДОК_ПРОВАЙДЕРОВ = ("imdb", "kp")


def топ(соед, предел: int = 100, провайдер: str = "imdb") -> dict:
    строки = соед.execute(
        """
        SELECT e.entity_id, e.canonical_path, e.title_ru, e.title_original,
               e.poster_path, e.year, e.kind,
               r.provider, r.value, r.scale, r.votes
          FROM entity e
          JOIN external_rating r ON r.entity_id = e.entity_id
         WHERE r.value IS NOT NULL AND r.status = 'OK'
               AND e.canonical_path IS NOT NULL AND e.canonical_path != ''
        """).fetchall()
    по_сущности: dict[str, dict] = {}
    for с in строки:
        з = по_сущности.setdefault(с["entity_id"], {
            "entityId": с["entity_id"], "canonicalPath": с["canonical_path"],
            "title": с["title_ru"] or с["title_original"] or "",
            "poster": с["poster_path"], "year": с["year"], "kind": с["kind"],
            "ratings": []})
        з["ratings"].append({"provider": с["provider"], "value": с["value"],
                             "scale": с["scale"], "votes": с["votes"]})

    def ключ(з: dict):
        свой = next((р for р in з["ratings"] if р["provider"] == провайдер), None)
        значение = свой["value"] if свой else -1.0
        return (-значение, -len(з["ratings"]), -(з["year"] or 0), з["entityId"])

    годные = [з for з in по_сущности.values()
              if any(р["provider"] == провайдер for р in з["ratings"])]
    годные.sort(key=ключ)
    отобрано = годные[:предел]
    for место, з in enumerate(отобрано, 1):
        з["rank"] = место
    хватило = len(годные) >= предел
    return {
        "contract": КОНТРАКТ,
        "surface": "топ",
        "provider": провайдер,
        "available": len(годные),
        "requested": предел,
        "enough": хватило,
        "title": f"Топ-{предел}" if хватило else f"Лучшие {len(отобрано)}",
        "votes_note": ("источник не отдаёт число голосов ни для одной записи, "
                       "поэтому сглаживание по голосам не применяется и порог "
                       "достоверности не объявляется"),
        "order_note": ("порядок: оценка выбранного провайдера, затем число "
                       "провайдеров, затем год, затем идентификатор — "
                       "детерминированно и воспроизводимо"),
        "items": отобрано,
    }


def подпись_рейтингов(р: list[dict]) -> str:
    """Каждая оценка со своим провайдером и шкалой. Никакого общего числа."""
    if not р:
        return ""
    части = []
    for о in sorted(р, key=lambda x: ПОРЯДОК_ПРОВАЙДЕРОВ.index(x["provider"])
                    if x["provider"] in ПОРЯДОК_ПРОВАЙДЕРОВ else 9):
        имя = {"imdb": "IMDb", "kp": "Кинопоиск"}.get(о["provider"], о["provider"])
        голоса = f", голосов {о['votes']}" if о.get("votes") else ", голосов нет данных"
        части.append(
            f'<span class="sf-rate" title="{html.escape(имя)}{html.escape(голоса)}">'
            f'<b>{о["value"]:.1f}</b><small>/{о["scale"]:.0f} {html.escape(имя)}</small></span>')
    return '<span class="sf-rates">' + "".join(части) + "</span>"
