#!/usr/bin/env python3
"""Первый ряд постеров подборки виден на телефоне целиком.

ПОВОД — измерено 27.10 на живой странице после исправления сетки: на 390×844
верх первой карточки стоит на 613, высота рамки постера 258, то есть нижний
край первого ряда уходит на 871 при окне 844 — не хватает 27 пикселей. Сверху
при этом дважды стоит название подборки: в крошках (последним звеном, полным
текстом) и в H1.

Решение линии SEO, принятое на ВЕРНЫХ числах (первая оценка была моей ошибкой
чтения снимка — он отдан в физических пикселях при DPR 3): убрать с телефона
повтор названия в крошках. Вступление НЕ обрезается: оно объясняет читателю,
зачем смотреть, и это требование поручения владельца.

ЧТО ДЕЛАЕТ.

1. `крошки` оборачивает ТЕКУЩУЮ страницу в `<span class="zcr__cur">` вместе с
   её разделителем. Раньше это был голый текстовый узел: убрать его с узкого
   экрана было нечем, а если убрать только текст — остался бы висящий слеш.
   Видимый текст не меняется ни на знак.
2. `ручная_подборка` помечает свою цепочку классом `zcr--coll`, а свою секцию
   — классом `sec--coll`. Это даёт правилам точную область: крошки общие для
   всех страниц витрины, и прятать последнее звено ВЕЗДЕ правка не должна.
3. Правило прячет повтор только на узком экране и только на странице
   подборки.

ЧЕГО НЕ ДЕЛАЕТ. Разметку JSON-LD не трогает: в ней цепочка остаётся полной,
скрыт только видимый повтор. Кегль H1 не меняет — линия SEO назвала это «по
желанию, если первого не хватит», а первого хватает с запасом.

    python3 automation/host/apply-collection-firstscreen-patch.py [--check] <файл>…
"""
