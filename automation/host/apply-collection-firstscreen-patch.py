def _разобрать(пара):
    """(имя, было, стало, признак, необязательная)."""
    имя, было, стало, признак = пара[:4]
    return имя, было, стало, признак, (len(пара) > 4 and pair_необязательна(пара))


def pair_необязательна(пара) -> bool:
    return bool(пара[4])


def _применима(текст: str, было) -> bool:
    варианты = было if isinstance(было, tuple) else (было,)
    return any(в in текст for в in варианты)


def остатки(текст: str) -> list:
    плохо = []
    for пара in ПАРЫ:
        имя, было, _, признак, необязательная = _разобрать(пара)
        if признак in текст:
            continue
        if необязательная and not _применима(текст, было):
            continue
        плохо.append(f"нет: {имя}")
    return плохо


def применить(текст: str) -> tuple[str, list]:
    if "def ручная_подборка" not in текст or "СТИЛЬ_ПОДБОРКИ" not in текст:
        raise SystemExit("ОТКАЗ: в файле нет построителя `ручная_подборка` "
                         "или оформления подборки — сначала применяется "
                         "apply-collection-grid-patch.py")
    журнал = []
    for пара in ПАРЫ:
        имя, было, стало, признак, необязательная = _разобрать(пара)
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if необязательная and not _применима(текст, было):
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        варианты = было if isinstance(было, tuple) else (было,)
        замены = стало if isinstance(стало, tuple) else (стало,)
        подошёл = next((н for н, в in enumerate(варианты) if в in текст), None)
        if подошёл is None:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден ни в одном из "
                             f"{len(варианты)} вариантов — рантайм разошёлся "
                             "с разобранным образцом")
        текст = текст.replace(варианты[подошёл], замены[подошёл], 1)
        журнал.append(f"применено: {имя}"
                      + (f" (вариант {подошёл + 1})" if len(варианты) > 1 else ""))
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if "def ручная_подборка" not in исходный:
                print(f"не этой линии (нет построителя подборки) {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
