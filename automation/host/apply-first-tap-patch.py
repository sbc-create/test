#!/usr/bin/env python3
"""T338 на линии Zona: первое нажатие доводит до воспроизведения. По якорям.

Причина установлена измерением 27.10, а не предположением. Без нажатия
состояние плеера остаётся `resolving` и медиа не появляется даже через двадцать
секунд — значит разрешение источника запускает ИМЕННО нажатие. После него
состояние доходит до `ready`, но воспроизведение не начинается: нужно второе
нажатие. Независимая приёмка линии SEO даёт то же с другой стороны: 12 прогонов
из 12 (телефон и компьютер) — только со второго нажатия, и от первого до
`currentTime >= 1` проходит 7–10 секунд.

Жест у нас УЖЕ есть, и мы его теряем. Правка запоминает желание и применяет его
к медиа, как только оно появилось.

Почему отдельный инструмент, а не тот же, что носит подборки. Клиентский скрипт
плеера у этой линии СВОЙ: 231 строка против 306 у канона, свои имена
(`requested`, `adActive`, `armPlayTimers`), и он слушает события провайдера
через postMessage. Якоря канона здесь не находятся вовсе, а общий инструмент с
двумя наборами якорей скрывал бы это различие вместо того, чтобы его назвать.

Чего правка НЕ делает: не меняет этапы плеера, не трогает цели, не запускает
показ во время рекламного ролика (`adActive`) и не спорит с тем, кто поставил
на паузу сам.

    python3 automation/host/apply-first-tap-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ПЕРЕМЕННЫЕ_БЫЛО = " var requested=false, adActive=false, playTimers=[];"
ПЕРЕМЕННЫЕ_СТАЛО = (
    " var requested=false, adActive=false, playTimers=[];\n"
    " /* T338: желание зрителя, записанное ПЕРВЫМ нажатием по рамке. Оно\n"
    "    тратится на разрешение источника и дальше не продолжается — измерено\n"
    "    27.10 на живых витринах. Здесь оно запоминается и применяется к медиа,\n"
    "    как только медиа появилось. */\n"
    " var хотел_играть=false, пуск_сделан='';")

МЕДИА_БЫЛО = """   var v=root.querySelector('video');
   if(v && !v.__zonaBound){"""
МЕДИА_СТАЛО = """   var v=root.querySelector('video');
   /* Донести желание зрителя до появившегося медиа. Условия узкие намеренно:
      только если зритель нажал, не во время рекламного ролика, только пока
      ничего не играло и только один раз на эту попытку — иначе мы боролись бы
      с тем, кто поставил на паузу сам. */
   var метка=myGen+'/'+myAttempt;
   if(v && хотел_играть && !adActive && пуск_сделан!==метка
      && v.paused && (v.currentTime||0)<0.25){
    пуск_сделан=метка;
    try{
     var обещание=v.play();
     if(обещание && обещание.catch){ обещание.catch(function(){ нажать_пуск(root); }); }
    }catch(e){ нажать_пуск(root); }
   }
   if(v && !v.__zonaBound){"""

ЗАПАС_БЫЛО = " function armPlayTimers(myGen, myAttempt){"
ЗАПАС_СТАЛО = (
    " /* Запас, если `play()` отклонён политикой автозапуска: нажать кнопку\n"
    "    пуска САМОГО провайдера. Ищется по его разметке в теневом дереве; не\n"
    "    найдена — ничего не делаем и ничего не обещаем. */\n"
    " function нажать_пуск(root){\n"
    "  try{\n"
    "   var корни=[root], i=0;\n"
    "   while(i<корни.length){\n"
    "    var r=корни[i++]; if(!r) continue;\n"
    "    var b=r.querySelector('.playButton,[aria-label=\"Смотреть\"],[aria-label=\"Play\"]');\n"
    "    if(b){ b.click(); return true; }\n"
    "    var все=r.querySelectorAll('*');\n"
    "    for(var j=0;j<все.length;j++){ if(все[j].shadowRoot) корни.push(все[j].shadowRoot); }\n"
    "   }\n"
    "  }catch(e){}\n"
    "  return false;\n"
    " }\n"
    " function armPlayTimers(myGen, myAttempt){")

ЖЕСТ_БЫЛО = " var first=el();\n if(first){"
ЖЕСТ_СТАЛО = (
    " /* Нажатие по рамке плеера — это и есть «хочу смотреть». Слушатель стоит\n"
    "    на рамке, а не на документе: щелчок по описанию или по меню желанием\n"
    "    смотреть не является. `capture` нужен, чтобы жест был записан и когда\n"
    "    его съедает разметка провайдера внутри. */\n"
    " f.addEventListener('click', function(){ хотел_играть=true; }, true);\n"
    " f.addEventListener('touchstart', function(){ хотел_играть=true; },\n"
    "                    {capture:true, passive:true});\n"
    " var first=el();\n if(first){")

ПАРЫ = (
    ("желание зрителя", ПЕРЕМЕННЫЕ_БЫЛО, ПЕРЕМЕННЫЕ_СТАЛО, "var хотел_играть=false"),
    ("запас по кнопке провайдера", ЗАПАС_БЫЛО, ЗАПАС_СТАЛО, "function нажать_пуск(root)"),
    ("применение желания к медиа", МЕДИА_БЫЛО, МЕДИА_СТАЛО, "пуск_сделан!==метка"),
    ("запись жеста на рамке", ЖЕСТ_БЫЛО, ЖЕСТ_СТАЛО,
     "function(){ хотел_играть=true; }, true)"),
)


def остатки(текст: str) -> list:
    плохо = []
    for имя, _, _, признак in ПАРЫ:
        if признак not in текст:
            плохо.append(f"нет: {имя}")
    return плохо


def применить(текст: str) -> tuple[str, list]:
    if "СКРИПТ_ПЛЕЕРА_КЛИЕНТ" not in текст:
        raise SystemExit("ОТКАЗ: в файле нет клиентского скрипта плеера")
    if "function armPlayTimers" not in текст:
        raise SystemExit("ОТКАЗ: это не скрипт линии Zona — нет armPlayTimers. "
                         "У канона своя правка, она уже внесена")
    журнал = []
    for имя, было, стало, признак in ПАРЫ:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — скрипт плеера "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        п = остатки(новый)
        if п:
            print(f"ОТКАЗ: после правки остались признаки непривёденности: {п}",
                  file=sys.stderr)
            return 1
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
