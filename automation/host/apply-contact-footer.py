"""Контакт обратной связи в общем подвале витрины. Перенос по якорям.

Владелец подтвердил один адрес на всю сеть, и он обязан быть виден посетителю
на каждой странице, а не только на отдельной странице «Контакты». Адрес живёт в
`config/site.json` витрины ключом `contact_email`, `run.py` выставляет его
переменной `SITE_CONTACT_EMAIL`, рантайм читает переменную. Так значение едет в
артефакте выпуска и переживает и выкладку, и суточную доставку каталога: ни то,
ни другое `config/` не переписывает.

Почему инструмент, а не правка руками. Семейств четыре, витрин полтора десятка,
и подвал у каждого семейства свой. Правка руками означает четырнадцать шансов
ошибиться и ноль способов доказать, что нигде не забыли. Здесь как в
`apply-episode-availability-patch.py`: якоря обязательные, несовпадение — отказ
ДО записи, `--check` отвечает на вопрос «приведён ли файл» одним словом.

Что добавляется:

  * функция `_контакт_подвала()` — одна на файл, отдаёт готовую строку или
    пустоту, если адрес не задан. Пустота здесь законна: выдумывать адрес
    нельзя, а показывать «Обратная связь:» без адреса — хуже, чем не показывать;
  * вызов этой функции в подвале семейства;
  * стиль `.sf-contact` рядом с остальными правилами подвала.

Чего инструмент НЕ делает: не трогает оформление за пределами добавленной
строки, не меняет разделы, счётчики, плеер, режим индексации и адреса страниц.

    python3 automation/host/apply-contact-footer.py [--check] <файл> [<файл>…]
"""
