"""Память на снимок для дорогих чистых вычислений общего ядра семейства lords.

Файл семейства: в репозиторий сайта приезжает копией (как
lords_service_robots.py) и подключается адаптером точки входа сайта —
`lords_perf_memo.установить(ядро)`. Ядро не правится: его байты закреплены
замком сайта (AGENTS.md, п. 3).

Причина — замер 2026-10-05, docs/PERF_NETWORK_AUDIT_20261005.md (окно
«СКОРОСТЬ — СЕТЬ САЙТОВ»). Профили копий выпусков на копиях данных
(54–57 тыс. записей) показали, что на КАЖДОМ запросе заново обходится весь
каталог, хотя ответ зависит только от снимка:

  главная         подборки: КОЛЛЕКЦИИ.разрешить × 6 — 1,2–2,6 с;
                  `новинки_с_источником` — до 0,87 с
  /new/, каталог  `отбор` — 0,1–0,9 с
  /collections/   выборки и разрешение подборок — 1,6–3,4 с
  карточка        `похожие_с_мета`: 200–250 тыс. вызовов `транслит` и
                  `нормализовать` над жанрами и странами соседей — 1,5–4,4 с

Каждый путь запоминается на ТЕКУЩИЙ объект снимка. Смена снимка — доставка
каталога или перестройка — создаёт новые объекты, и память очищается целиком:
прежний каталог не удерживается и под новым не выдаётся. Срок годности
(5 мин) ограничивает правки согласования серий, которые идут на месте, не
меняя объект снимка.

`нормализовать` и `транслит` — чистые функции строки; память по самой строке
не меняет ни одного ответа.

Ни одна функция ядра не переписана: обёртка вызывает ту же функцию с теми же
аргументами и отдаёт её результат копией. Ставится только то, что в данном
варианте ядра есть; перечень печатается в журнал при запуске.
"""

from __future__ import annotations

import copy
import dataclasses
import functools
import json
import os
import threading
import time
from collections import OrderedDict

ИМЯ_ПРАВКИ = "память на снимок"

СРОК_С = float(os.environ.get("LORDS_MEMO_TTL", "300"))
ПРЕДЕЛ = int(os.environ.get("LORDS_MEMO_MAX", "96"))


def отпечаток(*объекты) -> tuple:
    """Тождество снимка: объект плюс его метки времени и ревизии.

    Одного `id` мало: после сборки мусора адрес может достаться новому
    объекту. Метки mtime/revision различают такие случаи.
    """
    return tuple((id(о), getattr(о, "mtime", None), getattr(о, "revision", None),
                  getattr(о, "data_revision", None)) for о in объекты)


class Память:
    """LRU со сроком годности, привязанное к одному снимку за раз."""

    def __init__(self, имя: str, срок: float = СРОК_С, предел: int = ПРЕДЕЛ):
        self.имя = имя
        self.срок = срок
        self.предел = предел
        self._замок = threading.Lock()
        self._записи: OrderedDict = OrderedDict()
        self._снимок = None
        self.попаданий = 0
        self.промахов = 0
        self.сбросов = 0

    def получить(self, снимок, ключ, вычислить):
        сейчас = time.monotonic()
        with self._замок:
            if снимок != self._снимок:
                if self._снимок is not None:
                    self.сбросов += 1
                self._записи.clear()
                self._снимок = снимок
            запись = self._записи.get(ключ)
            if запись is not None and сейчас - запись[0] < self.срок:
                self._записи.move_to_end(ключ)
                self.попаданий += 1
                return запись[1]
        значение = вычислить()
        with self._замок:
            self.промахов += 1
            # Пока считали, снимок мог смениться: результат прежнего снимка под
            # новым не кладётся.
            if снимок == self._снимок:
                self._записи[ключ] = (сейчас, значение)
                self._записи.move_to_end(ключ)
                while len(self._записи) > self.предел:
                    self._записи.popitem(last=False)
        return значение

    def свод(self) -> dict:
        return {"память": self.имя, "записей": len(self._записи), "попаданий": self.попаданий,
                "промахов": self.промахов, "сбросов": self.сбросов}

    def сбросить(self) -> None:
        with self._замок:
            if self._записи:
                self.сбросов += 1
            self._записи.clear()


ПАМЯТИ: dict = {}


def _ключ_запроса(зпр: dict) -> tuple:
    """Все параметры запроса, кроме номера страницы.

    Надмножество того, что читает `отбор` любого варианта шаблона: лишний
    параметр дробит память, но не может выдать чужой ответ.
    """
    return tuple(sorted((str(к), tuple(map(str, в)) if isinstance(в, (list, tuple)) else str(в))
                        for к, в in (зпр or {}).items() if к != "page"))


def установить(рантайм) -> str:
    """Поставить память поверх модуля рантайма. Повтор — не второй слой.

    Ставится только то, что в этом варианте шаблона есть; перечень
    поставленного возвращается и печатается в журнал при запуске.
    """
    if getattr(рантайм, "_память_на_снимок", None):
        return f"{ИМЯ_ПРАВКИ}: уже стоит"
    поставлено = []

    исходный_отбор = getattr(рантайм, "отбор", None)
    if callable(исходный_отбор):
        память = ПАМЯТИ["отбор"] = Память("отбор")

        def отбор(данные, индекс, зпр, раздел, *а, **кв):
            подробности = а[0] if а else кв.get("подробности")
            набор, выбрано = память.получить(
                отпечаток(данные, индекс, подробности),
                (раздел, _ключ_запроса(зпр), len(а), tuple(sorted(кв))),
                lambda: исходный_отбор(данные, индекс, зпр, раздел, *а, **кв))
            return list(набор), dict(выбрано)

        рантайм.отбор = отбор
        поставлено.append("отбор")

    исходные_новинки = getattr(рантайм, "новинки_с_источником", None)
    if callable(исходные_новинки):
        память_н = ПАМЯТИ["новинки"] = Память("новинки")

        def новинки_с_источником(данные, подробности, *а, **кв):
            return list(память_н.получить(
                отпечаток(данные, подробности), (а, tuple(sorted(кв.items()))),
                lambda: исходные_новинки(данные, подробности, *а, **кв)))

        рантайм.новинки_с_источником = новинки_с_источником
        поставлено.append("новинки_с_источником")

    коллекции = getattr(рантайм, "КОЛЛЕКЦИИ", None)
    if коллекции is not None and isinstance(getattr(коллекции, "ВЫБОРКИ", None), dict):
        память_в = ПАМЯТИ["выборки"] = Память("выборки")
        for имя, исходная in list(коллекции.ВЫБОРКИ.items()):
            def выборка(снимок, фильтр, _имя=имя, _исходная=исходная):
                # Окно «за N дней» и «текущий год» в части выборок считаются
                # от часов машины: дата входит в ключ.
                ключ = (_имя, json.dumps(фильтр, sort_keys=True, ensure_ascii=False, default=str),
                        time.strftime("%Y-%m-%d", time.gmtime()),
                        os.environ.get("LORDS_CLOCK_ISO") or "")
                return list(память_в.получить(отпечаток(снимок), ключ,
                                              lambda: _исходная(снимок, фильтр)))
            коллекции.ВЫБОРКИ[имя] = выборка
        поставлено.append("выборки подборок")

    # Разрешение подборки целиком. В этом варианте контракта основная работа
    # идёт ПОСЛЕ выборки — порог оценки, окно новизны через `новинка` по всему
    # набору, сортировка по объявленному полю: 1,8 с на главной даже при
    # запомненных выборках. Результат — функция снимка, ключа и страницы;
    # метка `generated_at` ставится заново на каждый вызов, как и без памяти.
    исходное_разрешить = getattr(коллекции, "разрешить", None) if коллекции is not None else None
    if callable(исходное_разрешить):
        память_р = ПАМЯТИ["разрешить"] = Память("разрешить", предел=256)
        сейчас = getattr(коллекции, "_сейчас", None)

        def разрешить(ключ, снимок, семейство, **кв):
            итог = память_р.получить(
                отпечаток(снимок),
                (ключ, семейство, tuple(sorted(кв.items())),
                 time.strftime("%Y-%m-%d", time.gmtime()), os.environ.get("LORDS_CLOCK_ISO") or ""),
                lambda: исходное_разрешить(ключ, снимок, семейство, **кв))
            if итог is None or not dataclasses.is_dataclass(итог):
                return итог
            замена = {"items": list(итог.items), "filter_spec": dict(итог.filter_spec),
                      "sort_spec": dict(итог.sort_spec)}
            if callable(сейчас) and hasattr(итог, "generated_at"):
                замена["generated_at"] = сейчас()
            return dataclasses.replace(итог, **замена)

        коллекции.разрешить = разрешить
        поставлено.append("разрешение подборок")

    вид = getattr(рантайм, "Вид", None)
    if вид is not None:
        # Похожие переопределяются в наследниках (ВидАнимедиа.похожие), поэтому
        # оборачивается каждый класс семейства, где метод объявлен сам.
        классы = [к for к in vars(рантайм).values()
                  if isinstance(к, type) and issubclass(к, вид)]
        for класс in классы:
            for метод, копия in (("похожие_с_мета", lambda р: (list(р[0]), dict(р[1]))),
                                 ("похожие", list)):
                исходный = класс.__dict__.get(метод)
                if not callable(исходный):
                    continue
                ключ_памяти = f"{класс.__name__}.{метод}"
                память_п = ПАМЯТИ[ключ_памяти] = Память(ключ_памяти, предел=2048)

                def обёртка(self, запись, деталь, *а, _и=исходный, _п=память_п, _к=копия, **кв):
                    # Метод может оставлять состояние на экземпляре
                    # (ВидАнимедиа.похожие пишет self._rec_meta, и страница
                    # читает его для атрибутов блока). Изменённые атрибуты
                    # запоминаются вместе с результатом и восстанавливаются
                    # при попадании — иначе ответ из памяти терял бы их.
                    def вычислить():
                        до = dict(vars(self))
                        итог = _и(self, запись, деталь, *а, **кв)
                        след = {к: в for к, в in vars(self).items()
                                if к not in до or до[к] is not в}
                        return итог, copy.deepcopy(след)

                    итог, след = _п.получить(
                        отпечаток(self.д, self.п), (запись.get("slug"), а, tuple(sorted(кв.items()))),
                        вычислить)
                    for к, в in след.items():
                        setattr(self, к, copy.deepcopy(в))
                    return _к(итог)

                setattr(класс, метод, обёртка)
                поставлено.append(ключ_памяти)

    for имя in ("нормализовать", "транслит"):
        исходная = getattr(рантайм, имя, None)
        if callable(исходная) and not hasattr(исходная, "cache_info"):
            setattr(рантайм, имя, functools.lru_cache(maxsize=1 << 16)(исходная))
            поставлено.append(имя)

    # Новые серии не ждут срока годности. Поток согласования серий правит
    # доступные номера НА МЕСТЕ, не меняя объект снимка, и пишет итог прохода в
    # наложение `<снимок>.nums.json`. Ровно в этот момент память сбрасывается
    # целиком. Срок годности остаётся страховкой на случай записи мимо метода.
    try:
        import episode_sync as согласование  # тот же модуль, что запускает рантайм
    except ImportError:
        согласование = None
    класс = getattr(согласование, "Согласование", None)
    исходное_сохранение = getattr(класс, "_сохранить_наложение", None)
    if callable(исходное_сохранение) and not getattr(исходное_сохранение, "_сбрасывает_память", False):
        def _сохранить_наложение(self, *а, **кв):
            итог = исходное_сохранение(self, *а, **кв)
            сбросить_всё()
            return итог
        _сохранить_наложение._сбрасывает_память = True
        класс._сохранить_наложение = _сохранить_наложение
        поставлено.append("сброс при записи согласования серий")

    рантайм._память_на_снимок = поставлено
    return f"{ИМЯ_ПРАВКИ}: {', '.join(поставлено) or 'нечего ставить'}"


def сбросить_всё() -> None:
    """Сбросить всю память: вызывается после записи согласования серий."""
    for п in ПАМЯТИ.values():
        п.сбросить()


def свод() -> list:
    return [п.свод() for п in ПАМЯТИ.values()]
