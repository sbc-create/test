#!/usr/bin/env python3
"""Сборка `description` каталожных страниц по доменам.

Зачем. Семь живых доменов Lords/Zona предъявляют поиску один и тот же
каталог (~66 тыс. страниц у каждого), и `description` у них совпадает
дословно: он берётся прямо из поля поставщика. Редакционная правка эту
задачу не закрывает по масштабу — конвейер даёт около 25 правок в сутки на
всю сеть, то есть покрытие одного домена заняло бы годы. Здесь — код,
который различает домены отбором и порядком ОДНИХ И ТЕХ ЖЕ подтверждённых
фактов, и заодно даёт описание тем страницам, у которых его нет вовсе
(27,5 % записей, около 18 тыс. адресов на домен).

Правило задано SEO: `reports/SEO-PREFLIGHT-20261002/RULE-DESCRIPTION-ASSEMBLY.md`
(коммит `c7d745f`). Здесь оно исполняется, а не переизобретается. Главное из
него, и почему именно так:

* **Ничего не придумывать.** Только перестановка и отбор полей записи.
  Оценочных слов в сборке нет ни одного, и добавить их нельзя — словаря нет.
* **Сборка по непустым фрагментам, а не шаблон с пропусками.** Пустое поле
  не оставляет ни связки, ни запятой, ни тире: обрубок невозможен ПО
  ПОСТРОЕНИЮ, а не отлавливается проверкой после.
* **Минимум два фрагмента опорного слоя**, иначе поле не выставляется
  вовсе. Пустое описание поисковик соберёт из текста страницы, а обрубок
  покажет как есть.
* **Опорный слой — только поля, заполненные у ≥ 70 % записей** (измерено:
  type и name 100 %, genres и year 96 %, original_name 92 %, imdb 85 %,
  description 72 %, countries 71 %). Число сезонов, дата премьеры, озвучка и
  длительность заполнены у 1–21 % и попадают только в добавку, которая при
  отсутствии исчезает вместе со своей связкой.
* **Редакционный текст не трогается.** Запись с пометкой `_edited` проходит
  насквозь: правку писал редактор, и подклеивать к ней доменный фрагмент
  значило бы править редакционный текст.

Что модуль НЕ делает: не пишет редакционные тексты посадочных и подборок
(там пишет редактор), не меняет данные витрины, не обрезает слово посередине
и не ставит многоточие вместо фразы.
"""
from __future__ import annotations

import re
from typing import Any, Iterable

#: Цель длины из правила (§3.4). Верхняя граница жёсткая, нижняя —
#: условие «не обрубок»: короче 60 знаков описание не выставляется.
ДЛИНА_МАКС = 160
ДЛИНА_МИН = 60

РАЗДЕЛИТЕЛЬ = " · "

#: Русские названия типов. Это перевод подтверждённого поля, а не домысел:
#: других значений у поставщика нет (измерено: movie и tv).
ТИПЫ = {
    "movie": "фильм",
    "tv": "сериал",
    "tv_series": "сериал",
    "series": "сериал",
    "anime": "аниме",
    "ova": "OVA",
    "ona": "ONA",
    "special": "спешл",
}


#: Пометки отсутствия: выглядят как значение, значением не являются. У
#: источников со статусами (`external_rating.status = ABSENT` в read-модели
#: Yummy — 14 161 строка из 14 598) такая пометка приходит В САМОМ ПОЛЕ, и
#: сборщик, отличающий только пустую строку от непустой, вывел бы её в
#: публичное описание словом «ABSENT».
ПОМЕТКИ_ОТСУТСТВИЯ = {
    "absent", "unknown", "n/a", "na", "none", "null", "nil", "nan",
    "undefined", "pending", "error", "failed", "-", "—", "–", "0000-00-00",
}


def _текст(значение: Any) -> str:
    if значение in (None, "", [], {}):
        return ""
    текст = str(значение).strip()
    return "" if текст.lower() in ПОМЕТКИ_ОТСУТСТВИЯ else текст


#: Ярлыки отбора каталога, которые жанром не являются. Витрины уже держат
#: этот список у себя (в ячейке — `_ТЕХНИЧЕСКИЕ_ЖАНРЫ`); сборщик о нём не
#: знал и выносил «западный контент» в публичную строку на 59 % страниц.
#: Это внутренняя лексика каталога, и в публичном тексте её быть не должно.
НЕ_ЖАНРЫ = {
    "западный контент",
    "азиатский контент",
    "контент",
    "прочее",
    "другое",
}


def _жанры(значение: Any, сколько: int) -> list[str]:
    """Жанры без служебных ярлыков отбора, не более `сколько`."""
    отобранные = []
    for ж in _список(значение, 50):
        if ж.strip().lower().replace("ё", "е") in НЕ_ЖАНРЫ:
            continue
        отобранные.append(ж)
        if len(отобранные) == сколько:
            break
    return отобранные


def _список(значение: Any, сколько: int) -> list[str]:
    if not isinstance(значение, (list, tuple)):
        значение = [значение] if значение else []
    чистые = [_текст(э) for э in значение]
    return [э for э in чистые if э][:сколько]


def _оценка(значение: Any) -> str:
    if not _текст(значение):
        return ""
    try:
        ч = float(значение)
    except (TypeError, ValueError):
        return ""
    if ч <= 0:
        return ""
    return f"{ч:.1f}".replace(".", ",")


def _тип(запись: dict, деталь: dict) -> str:
    сырой = _текст(деталь.get("type")) or _текст(запись.get("type"))
    if сырой:
        по_словарю = ТИПЫ.get(сырой.lower())
        if по_словарю:
            return по_словарю
        # Поставщик иногда отдаёт уже по-русски («Сериал»): берём как есть,
        # но в нижнем регистре — регистр ставит сборка, а не данные.
        if re.fullmatch(r"[А-Яа-яЁё][А-Яа-яЁё\s-]*", сырой):
            return сырой.lower()
    вид = _текст(запись.get("kind"))
    return вид.lower() if вид else ""


def _год(запись: dict, деталь: dict) -> str:
    for источник in (деталь.get("year"), запись.get("year")):
        т = _текст(источник)
        м = re.search(r"(19|20)\d{2}", т)
        if м:
            return м.group(0)
    return ""


def _сезонов(деталь: dict) -> str:
    сезоны = деталь.get("seasons")
    число = len(сезоны) if isinstance(сезоны, (list, tuple)) else 0
    if not число:
        return ""
    остаток10, остаток100 = число % 10, число % 100
    if остаток10 == 1 and остаток100 != 11:
        слово = "сезон"
    elif остаток10 in (2, 3, 4) and остаток100 not in (12, 13, 14):
        слово = "сезона"
    else:
        слово = "сезонов"
    return f"{число} {слово}"


МЕСЯЦЫ = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
          "августа", "сентября", "октября", "ноября", "декабря")


def _премьера(деталь: dict) -> str:
    """Дата премьеры словами. Только из поля, без домыслов о точности."""
    сырое = _текст(деталь.get("premiere_date"))
    м = re.fullmatch(r"((?:19|20)\d{2})-(\d{2})-(\d{2})", сырое)
    if not м:
        return ""
    год, месяц, день = м.group(1), int(м.group(2)), int(м.group(3))
    if not 1 <= месяц <= 12 or not 1 <= день <= 31:
        return ""
    return f"премьера {день} {МЕСЯЦЫ[месяц - 1]} {год}"


def _озвучка(деталь: dict) -> str:
    """Не более двух студий озвучки: перечисление превращается в мусор."""
    студии = _список(деталь.get("voice_studios"), 2)
    return f"озвучка {', '.join(студии)}" if студии else ""


def _длительность(деталь: dict) -> str:
    """Длительность минутами. Поставщик отдаёт число минут."""
    сырое = деталь.get("duration")
    try:
        минут = int(сырое)
    except (TypeError, ValueError):
        return ""
    if минут <= 0 or минут > 1000:
        return ""
    return f"{минут} мин"


# --- фрагменты -------------------------------------------------------------
# Каждый фрагмент либо собирается целиком, либо возвращает пустую строку.
# Промежуточных состояний нет: именно поэтому обрубок невозможен.

def _фрагменты(запись: dict, деталь: dict) -> dict[str, str]:
    тип = _тип(запись, деталь)
    год = _год(запись, деталь)
    жанры = _жанры(деталь.get("genres") or запись.get("genres"), 2)
    страны = _список(деталь.get("countries") or запись.get("countries"), 2)
    imdb = _оценка(деталь.get("imdb_rating"))
    kp = _оценка(деталь.get("kinopoisk_rating"))
    ориг = _текст(деталь.get("original_name") or запись.get("original_name"))

    ф: dict[str, str] = {
        "type": тип,
        "year": f"{год} год" if год else "",
        "genres": ", ".join(жанры),
        "countries": ", ".join(страны),
        "imdb": f"IMDb {imdb}" if imdb else "",
        "original_name": f"в оригинале {ориг}" if ориг else "",
        "seasons": _сезонов(деталь),
        "kinopoisk": f"Кинопоиск {kp}" if kp else "",
        "premiere_date": _премьера(деталь),
        "voice_studios": _озвучка(деталь),
        "duration": _длительность(деталь),
    }
    # Составные фрагменты собираются из уже готовых частей и исчезают
    # целиком, если не хватает любой из них.
    ф["type_year"] = f"{тип} {год} года" if тип and год else ""
    ф["type_genres"] = f"{тип}, {ф['genres']}" if тип and ф["genres"] else ""
    ф["year_genres"] = f"{год}, {ф['genres']}" if год and ф["genres"] else ""
    ф["countries_year"] = (f"{ф['countries']}, {год}"
                           if ф["countries"] and год else "")
    return ф

#: Поля опорного слоя (заполнены у ≥ 70 % записей). Правило разрешает строить
#: обязательную часть описания только из них.
ОПОРНЫЕ = ("type", "year", "genres", "countries", "imdb", "original_name",
           "type_year", "type_genres", "year_genres", "countries_year")

#: Необязательный слой: допускается не более одного такого фрагмента, и
#: только как добавка в конце.
ДОБАВКИ = ("seasons", "kinopoisk", "premiere_date", "voice_studios",
           "duration")


class Профиль:
    """Три параметра различия домена: ведущий фрагмент, порядок, добавка.

    Ни один домен не получает факта, которого нет у других: это
    перестановка, а не разный каталог.
    """

    __slots__ = ("ведущий", "порядок", "добавка", "позиция", "исключает")

    def __init__(self, ведущий: str, порядок: Iterable[str],
                 добавка: str | None = None, позиция: str = "спереди",
                 исключает: str | None = None) -> None:
        if ведущий not in ОПОРНЫЕ:
            raise ValueError(f"ведущий фрагмент не из опорного слоя: {ведущий}")
        лишние = [п for п in порядок if п not in ОПОРНЫЕ]
        if лишние:
            raise ValueError(f"порядок содержит не опорные фрагменты: {лишние}")
        if добавка is not None and добавка not in ДОБАВКИ:
            raise ValueError(f"добавка не из необязательного слоя: {добавка}")
        if позиция not in ("спереди", "сзади"):
            raise ValueError(f"позиция доменного фрагмента: {позиция}")
        self.ведущий = ведущий
        self.порядок = tuple(порядок)
        self.добавка = добавка
        self.позиция = позиция
        # Отбор — третий разрешённый правилом рычаг различия (§5: «отбор,
        # порядок и подача»). Витрина сознательно НЕ показывает один из
        # опорных фрагментов. Это нужно на бедных записях: когда непустых
        # фрагментов два-три, одним порядком семь доменов не развести —
        # измерено на выборке, два домена давали дословно одну строку.
        if исключает is not None and исключает not in ОПОРНЫЕ:
            raise ValueError(f"исключение не из опорного слоя: {исключает}")
        if исключает is not None and исключает == ведущий:
            raise ValueError("нельзя исключать собственный ведущий фрагмент")
        self.исключает = исключает


#: Семь живых домена — семь сочетаний. Таблица лежит в шаблоне, а не в данных
#: витрины: это параметр выпуска, и расхождение между копиями тогда видно
#: обычным сравнением файлов.
ПРОФИЛИ: dict[str, Профиль] = {
    # Различие держится на ТРЁХ вещах одновременно: какой составной фрагмент
    # упаковывает одни и те же факты («фильм 1980 года» против «Фильм, аниме,
    # боевик» против «1980, аниме, боевик»), в каком порядке идут остальные и
    # с какой стороны доменная часть приклеивается к тексту поставщика.
    # Только порядка не хватает: измерено на выборке — у записей без страны и
    # без оценки два домена с похожим порядком давали дословно одну строку.
    "lordserials22.info": Профиль(
        "type_year", ("genres", "countries", "imdb", "original_name"),
        "premiere_date", "спереди"),
    "lordfilm47.space": Профиль(
        "type_genres", ("year", "imdb", "countries", "original_name"),
        "duration", "спереди"),
    "lordserial33.biz": Профиль(
        "countries_year", ("type", "genres", "imdb", "original_name"),
        "voice_studios", "сзади"),
    "1lordserials1.online": Профиль(
        "imdb", ("year_genres", "type", "original_name", "countries"),
        "seasons", "сзади"),
    # genres перед type_year: при пустом оригинальном названии прежний
    # порядок совпадал с lordserials22.info дословно.
    "zonafilm12.site": Профиль(
        "original_name", ("genres", "type_year", "countries", "imdb"),
        "kinopoisk", "спереди"),
    # Сторона «спереди», а не «сзади»: у lordserial33.biz тоже «сзади», и
    # после отсева служебных ярлыков из жанров у записей без страны обе
    # витрины давали дословно одну строку (измерено: 3 совпадения на 2752
    # страницах). Сторона приклейки — такой же разрешённый рычаг различия,
    # как порядок.
    "zonafilm.cc": Профиль(
        "genres", ("countries_year", "imdb", "original_name", "type"),
        None, "спереди"),
    # original_name перед type: при пустой стране прежний порядок совпадал
    # с 1lordserials1.online, у которого пуста оценка.
    "zonafilm.space": Профиль(
        "year_genres", ("countries", "original_name", "type", "imdb"),
        "seasons", "спереди"),
}

#: Домен без профиля различия не получает: сборка для него работает только
#: там, где описания нет вовсе (случай В), и в нейтральном порядке.
ПО_УМОЛЧАНИЮ = Профиль("type_year", ("genres", "countries", "imdb",
                                     "original_name"))

#: Тот же профиль, найденный по идентификатору витрины. Нужен потому, что
#: переменной окружения с доменом есть не у всех витрин (измерено по рабочим
#: копиям: у lordfilm47-space и lordserial33-biz её нет вовсе), а
#: `config/site.json` с полями `domain` и `site_id` есть у каждой. Витрина
#: опознаётся по любому из двух, и доставка не зависит от того, какие
#: переменные завела линия.
ПО_ИДЕНТИФИКАТОРУ: dict[str, str] = {
    "lords-05": "lordserials22.info",
    "lords-01": "lordfilm47.space",
    "lords-02": "lordserial33.biz",
    "lords-03": "1lordserials1.online",
    "zona-03": "zonafilm12.site",
    "zona-02": "zonafilm.cc",
    "zona-01": "zonafilm.space",
}


def _ключ(что: str) -> str:
    """Домен или идентификатор витрины — к имени домена из таблицы профилей."""
    значение = (что or "").strip().lower()
    if not значение:
        return ""
    если_домен = значение.split(":")[0].removeprefix("www.")
    if если_домен in ПРОФИЛИ:
        return если_домен
    return ПО_ИДЕНТИФИКАТОРУ.get(значение, если_домен)


def профиль(хост: str) -> Профиль:
    return ПРОФИЛИ.get(_ключ(хост)) or ПО_УМОЛЧАНИЮ


def различается(хост: str) -> bool:
    """Задан ли для витрины свой профиль. Без него различия не обещаем."""
    return _ключ(хост) in ПРОФИЛИ


def _собрать_фразу(ф: dict[str, str], п: Профиль) -> tuple[str, int]:
    """Фраза из непустых фрагментов и их число. Пустые исчезают бесследно."""
    выбранные: list[str] = []
    использовано: set[str] = set()

    def добавить(имя: str) -> None:
        if п.исключает and имя == п.исключает:
            return
        значение = ф.get(имя) or ""
        if not значение:
            return
        # Один и тот же факт дважды не ставим: составной фрагмент уже несёт
        # свои части (type_year включает и тип, и год).
        части = set(имя.split("_"))
        if части & использовано:
            return
        использовано.update(части)
        if значение not in выбранные:
            выбранные.append(значение)

    добавить(п.ведущий)
    for имя in п.порядок:
        добавить(имя)
    опорных = len(выбранные)
    if п.добавка:
        добавить(п.добавка)

    фраза = РАЗДЕЛИТЕЛЬ.join(выбранные)
    if фраза:
        фраза = фраза[0].upper() + фраза[1:]
    return фраза, опорных


def _подрезать(текст: str, предел: int, *, оборвать_знаком: bool = False) -> str:
    """Обрезка по границе предложения, иначе слова. Никогда посередине.

    `оборвать_знаком` ставит многоточие в месте обрыва. Это нужно, когда за
    обрезанным текстом поставщика в строке идут ещё фрагменты: иначе
    «…содержащую гораздо · IMDb 6,4» читается как сломанная фраза без всякого
    признака обрыва (измерено линией 1lordserials1.online: 1036 строк из
    2724). Правило «не кончается многоточием» относится к концу готовой
    строки и здесь не нарушается.
    """
    текст = re.sub(r"\s+", " ", текст).strip()
    if len(текст) <= предел:
        return текст
    знак_обрыва = "…" if оборвать_знаком else ""
    # Место под знак обрыва вычитается из предела заранее: иначе готовая
    # строка оказывается на один знак длиннее предела (измерено: 210 строк по
    # 161 знаку из 12 541).
    окно = текст[:предел + 1 - len(знак_обрыва)]
    for знак in (". ", "! ", "? "):
        место = окно.rfind(знак)
        # Многоточие поставщика концом предложения не считается: обрезка по
        # нему оставляла «…дружелюбная...», то есть обрыв с многоточием.
        while место >= 0 and окно[max(0, место - 1):место] == ".":
            место = окно.rfind(знак, 0, место)
        if место >= ДЛИНА_МИН:
            # Обрезка по концу предложения — законченная фраза, знак обрыва
            # ей не нужен даже в середине строки.
            return окно[:место + 1].strip()
    место = окно.rfind(" ")
    if место < ДЛИНА_МИН:
        return ""
    обрезанный = _без_висящей_связки(окно[:место])
    if обрезанный and знак_обрыва and len(обрезанный) < len(текст):
        return обрезанный + знак_обрыва
    return обрезанный


#: Знаки, на которых обрезанная фраза не имеет права заканчиваться. Проверка
#: нашла это на выборке: обрезка по границе слова оставляла «…Глория -» и
#: «…юноша,» — формально не посередине слова, а читается как обрыв.
ВИСЯЧИЕ = " ,;:·-—–"


def _без_висящей_связки(текст: str) -> str:
    """Снять висящую связку и многоточие поставщика в месте обрыва.

    Многоточие снимается именно в конце обрезанной строки: точка как конец
    предложения законна, а «…дружелюбная...» — обрыв. Измерено на выборке.
    """
    обрезанный = текст.rstrip(ВИСЯЧИЕ)
    обрезанный = re.sub(r"(\.\.\.|…)\s*$", "", обрезанный).rstrip(ВИСЯЧИЕ)
    return обрезанный if len(обрезанный) >= ДЛИНА_МИН else ""


#: Разделители, которыми поставщик отделяет название в начале текста.
ПОСЛЕ_ЗАГОЛОВКА = (" — ", " – ", " - ", ": ", ". ", ", ")


#: Кавычки, в которые поставщик берёт название в начале текста.
КАВЫЧКИ = "«»\"'„“”‚‘’"


def _снять_заголовок(текст: str, имя: str) -> str:
    """Убрать название в начале текста поставщика вместе с его разделителем.

    Правило §3.5 запрещает описанию начинаться с заголовка: в выдаче это
    повтор `<title>`. Снимается только РОВНО название и ровно один
    разделитель, и только если остаток сам по себе осмысленной длины —
    иначе текст поставщика остаётся как есть.
    """
    if not имя:
        return текст
    # Название может стоять в кавычках: «Имя» — … Кавычки снимаются с начала
    # обеих строк, иначе совпадение не находится вовсе (измерено линией
    # 1lordserials1.online: 10 строк из 1815 начинались с заголовка).
    без_кавычек = текст.lstrip(КАВЫЧКИ)
    чистое_имя = имя.strip(КАВЫЧКИ)
    if not без_кавычек.lower().startswith(чистое_имя.lower()):
        return текст
    остаток = без_кавычек[len(чистое_имя):]
    for р in ПОСЛЕ_ЗАГОЛОВКА:
        if остаток.startswith(р):
            очищенный = остаток[len(р):].strip()
            break
    else:
        # Разделителя из списка нет: снимается НЕ БОЛЕЕ трёх знаков пунктуации
        # и пробелов. Больше снимать нельзя — это уже правка текста.
        снято = остаток[:3]
        if снято and all(с in " —–-:;,.»\"'()" for с in снято):
            очищенный = остаток[3:].strip()
        else:
            return текст
    if len(очищенный) < ДЛИНА_МИН:
        return текст
    return очищенный[0].upper() + очищенный[1:]


def _без_многоточия(строка: str) -> str:
    """Готовая строка не заканчивается многоточием — чьим бы оно ни было.

    Измерено на полном прогоне: у части записей многоточие стоит в самом
    тексте поставщика, обрезка тут не виновата, но в выдаче строка читается
    как обрыв. Точка как конец предложения остаётся.
    """
    return re.sub(r"(\.\.\.|…)\s*$", "", строка).rstrip(ВИСЯЧИЕ)


def описание(запись: dict, деталь: dict, хост: str) -> str:
    """Готовая строка для `<meta name="description">` или пустая.

    Пустая строка — законный ответ: вызывающий код тогда не выставляет тег
    вовсе, и это лучше обрубка (правило §4, случай В).
    """
    запись = запись or {}
    деталь = деталь or {}
    п = профиль(хост)
    поставщик = _текст(деталь.get("description")) or _текст(
        деталь.get("short_description"))

    # Редакционный текст проходит насквозь: его писал редактор.
    if деталь.get("_edited") and поставщик:
        return _без_многоточия(_подрезать(поставщик, ДЛИНА_МАКС))

    ф = _фрагменты(запись, деталь)
    фраза, опорных = _собрать_фразу(ф, п)

    # Случай Б: текст поставщика есть. Доменный фрагмент ДОБАВЛЯЕТСЯ, текст
    # не переписывается; если после добавки на текст не остаётся осмысленного
    # места, добавка не ставится.
    if поставщик:
        # Ведущий фрагмент — первый НЕПУСТОЙ по порядку профиля. Измерено:
        # если брать только названный ведущий, у записей без оценки или без
        # оригинального названия добавка исчезает целиком, и два домена
        # отдают один и тот же текст поставщика — различие пропадает ровно
        # там, где оно и нужно.
        # Берутся ДВА первых непустых фрагмента по порядку профиля. Одного
        # мало: измерено на выборке — у записи без страны и без оценки
        # «первый непустой» у двух витрин оказывался одним и тем же
        # фрагментом, и при одинаковой позиции тексты совпадали дословно.
        части: list[str] = []
        занято: set[str] = set()
        for имя in (п.ведущий, *п.порядок):
            if п.исключает and имя == п.исключает:
                continue
            значение = ф.get(имя)
            if not значение:
                continue
            факты = set(имя.split("_"))
            if факты & занято:
                continue
            занято.update(факты)
            части.append(значение)
            if len(части) == 2:
                break
        if not части or not различается(хост):
            return _без_многоточия(_подрезать(поставщик, ДЛИНА_МАКС))
        # Доменная часть сжимается, а не отбрасывается: сначала два фрагмента,
        # потом один. Отбросив её, две витрины вернули бы один и тот же голый
        # текст поставщика — измерено на полном прогоне, именно так и было у
        # записей с длинным оригинальным названием.
        ведущий, хвост = "", ""
        for сколько in (2, 1):
            кандидат = РАЗДЕЛИТЕЛЬ.join(части[:сколько])
            if not кандидат:
                continue
            кандидат = кандидат[0].upper() + кандидат[1:]
            запас = ДЛИНА_МАКС - len(кандидат) - len(РАЗДЕЛИТЕЛЬ)
            если_хвост = (_подрезать(поставщик, запас, оборвать_знаком=True)
                          if запас >= ДЛИНА_МИН else "")
            if если_хвост:
                ведущий, хвост = кандидат, если_хвост
                break
        if not хвост:
            return _без_многоточия(_подрезать(поставщик, ДЛИНА_МАКС))
        # Заголовок не открывает описание (правило §3.5). Если текст
        # поставщика начинается с названия, доменный фрагмент встаёт впереди
        # независимо от позиции профиля: различие при этом сохраняется —
        # ведущие фрагменты у семи витрин разные.
        имя_записи = (_текст(деталь.get("name")) or _текст(запись.get("title"))
                      or _текст(запись.get("name")))
        хвост = _снять_заголовок(хвост, имя_записи)
        впереди = п.позиция == "спереди" or bool(
            имя_записи and хвост.lower().startswith(имя_записи.lower()))
        порядок = ((ведущий, хвост) if впереди else (хвост, ведущий))
        return _без_многоточия(РАЗДЕЛИТЕЛЬ.join(порядок))

    # Случай В: описания нет. Собирается целиком, и только при двух и более
    # фрагментах опорного слоя и достаточной длине.
    if опорных < 2 or len(фраза) < ДЛИНА_МИН:
        return ""
    return _без_многоточия(_подрезать(фраза, ДЛИНА_МАКС))
