#!/usr/bin/env python3
"""Счётчики памяти витрины ОДНОЙ командой — и причина промаха названа.

Зачем файл в репозитории, а не скрипт в сессии. Сводка `/__load` отдаёт по
каждой памяти шесть чисел, и по ним решается, что лечить: срок, предел или
ключ. Разбирать их глазами в JSON — ровно тот случай, когда измерение есть, а
вывода нет. Здесь разбор записан один раз и доступен любому, у кого есть адрес
витрины.

Что значат столбцы (их ведёт `src/perf_memo.py` витрины):

    записей/предел   сколько записей держит память и сколько ей позволено;
                     равенство — признак, что предел мешает;
    попаданий        ответ выдан из памяти;
    промахов         ответ пришлось собирать; делится на причины ниже;
    устарело         запись БЫЛА и вышла за срок → лечится сроком;
    вытеснено        запись выбил предел → лечится пределом или ключом;
    вернувшихся      промах по ключу, который раньше вытеснили. Это и есть
                     ответ на вопрос «дал бы больший предел попадания»:
                     вытеснений много, а возвратов мало — предел поднимать
                     незачем (измерено 30.10 на каталоге: 3145 против 12);
    сбросов          память погашена целиком: сменился снимок либо прошла
                     запись согласования серий.

Запуск:

    python3 memo-stats.py animedia.icu
    python3 memo-stats.py animedia.icu --json   # для дальнейшей обработки

Только чтение: `/__load` отдаёт служебный JSON с `noindex` и `no-store`, личных
данных в нём нет (сторожат `checks/load_stats.py` и `checks/load_bot_names.py`
витрины).
"""
from __future__ import annotations

import json
import sys
import urllib.error
import urllib.request

ЗАГОЛОВКИ = {"User-Agent": "Mozilla/5.0 (memo-stats)"}
СТОЛБЦЫ = (("записей", 8), ("предел", 7), ("попаданий", 10), ("промахов", 9),
           ("устарело", 9), ("вытеснено", 10), ("вернувшихся", 12), ("сбросов", 8))


#: Где искать счётчики. Сводка нагрузки `/__load` есть не у всех витрин
#: семейства (T325 стоит у animedia.icu), а служебная `/__template_version` —
#: у всех. Инструмент обязан читать обе: иначе «счётчиков нет» означало бы
#: «витрина не показывает сводку нагрузки», а это другое утверждение.
ИСТОЧНИКИ = ("/__load", "/__template_version")


def забрать(домен: str) -> tuple[dict, str]:
    """Сводка и путь, с которого она взята. Пробуются оба источника по порядку."""
    адрес = домен if домен.startswith("http") else f"https://{домен}"
    # Причина по КАЖДОМУ источнику, а не только последняя: «308 с /__load»
    # и «в /__template_version нет счётчиков» — разные утверждения, и
    # склеивать их в одно значит прятать второе.
    причины = []
    for путь in ИСТОЧНИКИ:
        try:
            запрос = urllib.request.Request(f"{адрес}{путь}", headers=ЗАГОЛОВКИ)
            с = urllib.request.urlopen(запрос, timeout=60)
            сводка = json.loads(с.read().decode("utf-8", "replace"))
        except (urllib.error.URLError, OSError, ValueError) as ош:
            причины.append(f"{путь}: {type(ош).__name__}: {ош}")
            continue
        if строки_памяти(сводка):
            return сводка, путь
        причины.append(f"{путь}: ответ получен, счётчиков памяти в нём нет")
    raise ValueError("счётчики не получены — " + "; ".join(причины))


def строки_памяти(сводка: dict) -> list:
    """Перечень памятей из сводки; пустой — витрина их не показывает."""
    память = сводка.get("память")
    return list(память) if isinstance(память, list) else []


def доля_попаданий(запись: dict) -> str:
    всего = int(запись.get("попаданий", 0) or 0) + int(запись.get("промахов", 0) or 0)
    if not всего:
        return "—"
    return f"{100 * int(запись.get('попаданий', 0) or 0) / всего:.0f}%"


#: Доля возвратов среди вытеснений, ниже которой поднимать предел бессмысленно.
#: Выбрана не на глаз: 30.10 у памяти каталога было 3145 вытеснений и 12
#: возвратов (0,4%) — поднятие предела дало бы единицы попаданий и десятки
#: мегабайт памяти впустую. У памяти главной в тех же условиях возвраты шли
#: вместе с вытеснениями и предел действительно мешал.
ПОРОГ_ВОЗВРАТОВ = 0.05


def главная_причина(запись: dict) -> str:
    """Что лечить: срок, предел или ничего. Называется по числам, не по вкусу."""
    устарело = int(запись.get("устарело", 0) or 0)
    вытеснено = int(запись.get("вытеснено", 0) or 0)
    вернувшихся = int(запись.get("вернувшихся", 0) or 0)
    if вытеснено:
        доля = вернувшихся / вытеснено
        if доля >= ПОРОГ_ВОЗВРАТОВ:
            return (f"предел: вытесненные ключи спрашивают снова "
                    f"({вернувшихся} из {вытеснено})")
        return (f"предел мешает, но возвратов мало ({вернувшихся} из {вытеснено}) — "
                "поднимать незачем")
    if устарело:
        return "срок"
    return "—"


def напечатать(домен: str, сводка: dict, источник: str = "") -> int:
    записи = строки_памяти(сводка)
    группы = (сводка.get("totals") or {}).get("by_path_group") or {}
    окно = сводка.get("window_minutes")
    голова = f"{домен} | источник {источник or '—'}"
    if окно:
        голова += f" | окно {окно} мин на {сводка.get('generated_at')}"
    else:
        # У `/__template_version` окна нет: это состояние процесса, а не сводка
        # за период. Писать «окно None» значило бы придумать величину.
        голова += " | сводки за период нет (состояние процесса)"
    print(голова)
    for имя in ("home", "catalog"):
        г = группы.get(имя) or {}
        счёт = int(г.get("count", 0) or 0)
        if счёт:
            print(f"  {имя}: {счёт} запросов, средние {int(г.get('sum_ms', 0)) // счёт} мс, "
                  f"max {г.get('max_ms')}")
    if not записи:
        print("  счётчиков памяти в сводке нет: витрина их не показывает")
        return 2
    голова = "  " + f"{'память':<34}" + "".join(f"{и:>{ш}}" for и, ш in СТОЛБЦЫ)
    print(голова + f"{'доля':>7}  причина")
    for з in записи:
        строка = "  " + f"{str(з.get('память', '?')):<34}"
        строка += "".join(f"{з.get(и, 0):>{ш}}" for и, ш in СТОЛБЦЫ)
        print(строка + f"{доля_попаданий(з):>7}  {главная_причина(з)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    а = list(sys.argv[1:] if argv is None else argv)
    if not а:
        print("нужен домен: python3 memo-stats.py animedia.icu", file=sys.stderr)
        return 2
    домен = а[0]
    try:
        сводка, источник = забрать(домен)
    except (urllib.error.URLError, OSError, ValueError) as ош:
        print(f"сводка не получена: {type(ош).__name__}: {ош}", file=sys.stderr)
        return 2
    if "--json" in а:
        print(json.dumps(строки_памяти(сводка), ensure_ascii=False, indent=1))
        return 0 if строки_памяти(сводка) else 2
    return напечатать(домен, сводка, источник)


if __name__ == "__main__":
    raise SystemExit(main())
