"""Перечитывание снимка витрины семейства lords на месте, без перезапуска.

Файл семейства: в репозиторий сайта приезжает копией рядом с ядром и
подключается из `main()` ядра вставкой шаблона (automation/host/
apply-snapshot-reload-hook-patch.py) — так же, как память на снимок.

Причина — замер 2026-10-06 (docs/PERF_NETWORK_AUDIT_20261005.md, окно
«СКОРОСТЬ — СЕТЬ САЙТОВ»). Ядро читает каталог и подробности ОДИН раз в
`main()`. Поэтому служба согласования серий lordserials22.info, переписав
снимок подробностей, ставит отметку `.episode-refresh-restart`, и её
`ExecStartPost` делает `systemctl try-restart` витрины. На копии выпуска
d38dcbb под одним посетителем (запрос раз в 0,5 с) это 11 отказов соединения
подряд и 10,6 с без ответа, после подъёма — первые ответы до 3 с, пока память
пустая. На живом сайте те же секунды — 502 у nginx, четыре раза в час.

Что делает модуль. Фоновый поток раз в `LORDS_SNAPSHOT_RELOAD_SEC` (10 с)
сравнивает (mtime_ns, size) файлов каталога и подробностей с прочитанными.
Изменение принимается, когда метка одинакова две проверки подряд (файл
дописан). Новый снимок строится ТЕМИ ЖЕ конструкторами ядра (`Данные`,
`Подробности`, `построить_индекс`) в фоне, пока старый отвечает; затем
обработчику подменяются три ссылки. Запрос, начатый на прежнем снимке,
доотвечает на нём.

Что модуль НЕ делает:
* не отдаёт пустоту вместо данных: если новый файл не читается или в нём
  нет записей, а в прежнем были, — остаётся прежний снимок, отказ называется
  в журнале, попытка повторяется при следующем изменении файла;
* не пишет ни в один файл данных: только читает;
* не держит устаревшее: память на снимок (lords_perf_memo) ключуется по
  объектам снимка и сбрасывается здесь же явно; поток согласования серий
  берёт объект подробностей у обработчика каждый проход и после подмены
  правит новый.

Наличие модуля объявляется ядру атрибутом `ПЕРЕЧИТЫВАНИЕ_СНИМКА`; инструмент
согласования серий по нему перестаёт просить перезапуск.
"""

from __future__ import annotations

import os
import sys
import threading
import time
import urllib.request

ИМЯ_ПРАВКИ = "перечитывание снимка на месте"
ПАУЗА_С = float(os.environ.get("LORDS_SNAPSHOT_RELOAD_SEC", "10"))
#: Что прогреть после подмены: первые посетители иначе платят полный расчёт.
ПРОГРЕВ = ("/", "/collections/")


def метка(путь: str):
    """(mtime_ns, size) файла; None — файла нет или он недоступен."""
    try:
        с = os.stat(путь)
    except OSError:
        return None
    return (с.st_mtime_ns, с.st_size)


def _порт() -> int | None:
    """Порт витрины из её же командной строки (`--port N`)."""
    арг = sys.argv
    for i, а in enumerate(арг):
        if а == "--port" and i + 1 < len(арг):
            try:
                return int(арг[i + 1])
            except ValueError:
                return None
        if а.startswith("--port="):
            try:
                return int(а.split("=", 1)[1])
            except ValueError:
                return None
    return None


class Перечитывание:
    def __init__(self, ядро, пауза: float = ПАУЗА_С) -> None:
        self.ядро = ядро
        self.пауза = пауза
        self.файлы = {"каталог": str(getattr(ядро, "КАТАЛОГ_ФАЙЛ", "") or ""),
                      "подробности": str(getattr(ядро, "ПОДРОБНОСТИ_ФАЙЛ", "") or "")}
        self.прочитано = {и: метка(п) for и, п in self.файлы.items()}
        self.ждёт = None
        self.перечитываний = 0
        self.отказов = 0
        self.последнее = ""
        self.последняя_проверка = ""
        self.последний_отказ = ""
        self._замок = threading.Lock()

    def сейчас(self) -> dict:
        return {и: метка(п) for и, п in self.файлы.items() if п}

    def проверить(self) -> bool:
        """Один шаг наблюдения. True — снимок подменён."""
        self.последняя_проверка = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        текущие = self.сейчас()
        изменились = {и for и, м in текущие.items() if м != self.прочитано.get(и) and м is not None}
        if not изменились:
            self.ждёт = None
            return False
        # Дописан ли файл: та же метка две проверки подряд.
        if self.ждёт != текущие:
            self.ждёт = текущие
            return False
        self.ждёт = None
        return self.перечитать(изменились, текущие)

    def перечитать(self, изменились: set, метки: dict) -> bool:
        я = self.ядро
        обр = я.Обработчик
        t = time.monotonic()
        with self._замок:
            try:
                данные = я.Данные(я.КАТАЛОГ_ФАЙЛ) if "каталог" in изменились else обр.данные
                подробности = (я.Подробности(я.ПОДРОБНОСТИ_ФАЙЛ) if "подробности" in изменились
                               else обр.подробности)
                if not getattr(данные, "items", None) and getattr(обр.данные, "items", None):
                    raise ValueError("в новом каталоге нет записей")
                if not getattr(подробности, "записи", None) and getattr(обр.подробности, "записи", None):
                    raise ValueError("в новых подробностях нет записей")
                индекс = я.построить_индекс(данные, подробности)
            except Exception as ош:  # noqa: BLE001 — витрина остаётся на прежнем снимке
                self.отказов += 1
                self.последний_отказ = f"{sorted(изменились)}: {ош!r}"[:300]
                # Метка запоминается: тот же испорченный файл не перечитывается
                # каждые 10 с; следующее изменение файла — новая попытка.
                self.прочитано.update(метки)
                print(f"[nova] перечитывание снимка отказало, остаётся прежний: {self.последний_отказ}",
                      flush=True)
                return False
            обр.данные = данные
            обр.подробности = подробности
            обр.индекс = индекс
            self.прочитано.update(метки)
            self.перечитываний += 1
            self.последнее = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        память = sys.modules.get("lords_perf_memo")
        if память is not None and hasattr(память, "сбросить_всё"):
            память.сбросить_всё()
        print(f"[nova] снимок перечитан на месте ({', '.join(sorted(изменились))}) за "
              f"{time.monotonic() - t:.1f} с: тайтлов {len(данные.items)}, "
              f"подробностей {getattr(подробности, 'покрытие', 0)}", flush=True)
        self.прогреть()
        return True

    def прогреть(self) -> None:
        порт = _порт()
        if not порт:
            return
        for путь in ПРОГРЕВ:
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{порт}{путь}", timeout=120) as о:
                    о.read()
            except Exception:  # noqa: BLE001 — прогрев необязателен
                pass

    def свод(self) -> dict:
        return {"перечитываний": self.перечитываний, "отказов": self.отказов,
                "последнее": self.последнее, "последняя_проверка": self.последняя_проверка,
                "последний_отказ": self.последний_отказ, "пауза_с": self.пауза}

    def цикл(self) -> None:
        while True:
            time.sleep(self.пауза)
            try:
                self.проверить()
            except Exception as ош:  # noqa: BLE001 — фон не роняет витрину
                print(f"[nova] наблюдение за снимком отказало: {ош!r}", flush=True)


def установить(ядро) -> str:
    """Завести наблюдение. Возвращает строку для журнала."""
    нет = [и for и in ("Обработчик", "Данные", "Подробности", "построить_индекс",
                       "КАТАЛОГ_ФАЙЛ", "ПОДРОБНОСТИ_ФАЙЛ") if not hasattr(ядро, и)]
    if нет:
        return f"{ИМЯ_ПРАВКИ}: не заведено, в ядре нет {', '.join(нет)}"
    if getattr(ядро, "ПЕРЕЧИТЫВАНИЕ_СНИМКА", None) is not None:
        return f"{ИМЯ_ПРАВКИ}: уже заведено"
    п = Перечитывание(ядро)
    ядро.ПЕРЕЧИТЫВАНИЕ_СНИМКА = п
    дополнительно = _связать_с_согласованием(ядро, п)
    threading.Thread(target=п.цикл, name="lords-snapshot-reload", daemon=True).start()
    return (f"{ИМЯ_ПРАВКИ}: каждые {п.пауза:g} с ({', '.join(и for и, ф in п.файлы.items() if ф)})"
            + (f"; {дополнительно}" if дополнительно else ""))


def _связать_с_согласованием(ядро, п: Перечитывание) -> str:
    """Проход согласования, начатый на прежнем объекте, не теряется.

    Новый объект подробностей при постройке накладывает файл `.nums.json` —
    но проход, шедший во время подмены, правил ПРЕЖНИЙ объект и запишет файл
    позже. Поэтому после каждой записи наложения, если с прошлой записи снимок
    подменялся, то же наложение переносится на текущий объект. Перенос
    идемпотентен (`episode_sync.наложить` ставит перечни, а не добавляет).
    """
    try:
        import episode_sync as согласование
    except ImportError:
        return ""
    класс = getattr(согласование, "Согласование", None)
    исходное = getattr(класс, "_сохранить_наложение", None)
    наложить = getattr(согласование, "наложить", None)
    if not callable(исходное) or not callable(наложить) or getattr(исходное, "_переносит_на_новый_снимок", False):
        return ""
    виденные = {"n": п.перечитываний}

    def _сохранить_наложение(self, *а, **кв):
        итог = исходное(self, *а, **кв)
        if п.перечитываний != виденные["n"]:
            виденные["n"] = п.перечитываний
            текущие = getattr(getattr(ядро, "Обработчик", None), "подробности", None)
            записи = getattr(текущие, "записи", None)
            if isinstance(записи, dict):
                наложить(записи, getattr(self, "наложение", {}) or {})
                память = sys.modules.get("lords_perf_memo")
                if память is not None and hasattr(память, "сбросить_всё"):
                    память.сбросить_всё()
        return итог

    _сохранить_наложение._переносит_на_новый_снимок = True
    for имя in ("_сбрасывает_память",):
        if getattr(исходное, имя, False):
            setattr(_сохранить_наложение, имя, True)
    класс._сохранить_наложение = _сохранить_наложение
    return "проход согласования переносится на новый снимок"
