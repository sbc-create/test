#!/usr/bin/env python3
"""MOD-220: снимок берётся из настройки, а «не измерено» отдаёт код 2, не 0.

    python3 automation/host/apply-indexing-switch-datadir-patch.py \
        --repo var/site-repos/lordserials22-info [--check] [--dry-run]

Что измерено
------------

`checks/indexing_live_switch.py` строит путь к снимкам как
`/srv/<имя репозитория>/data`. У `1lordserials1.online` настоящий каталог
называется `/srv/site-1lordserials1-online`, снимка по построенному пути нет,
проверка печатает «НЕ ИЗМЕРЕНО: снимков нет» и выходит с кодом **0**. Для
вызывающего это зелёный результат, хотя не проверено ничего: решение
принимает код выхода, а не текст.

Дефект был ИЗВЕСТЕН и записан в самом файле. Комментарий над построением пути
говорит дословно: «Рабочая копия с другим именем каталога прежде молча уходила
в «пропущено» с rc=0, и run.sh засчитывал шаг как PASS (T065, 14.10)». Путь
тогда дополнили переменными окружения, а код выхода оставили нулевым — то
есть исправили повод, а не последствие.

Образец различения исходов у семейства уже есть: `checks/www_redirect.py`
отдаёт на отсутствие снимка код 2 и объявляет это в своём заголовке.

Что делает инструмент
---------------------

1. берёт адрес снимка ИЗ НАСТРОЙКИ витрины — `deployment.data_dir`, который
   уже объявлен в `config/site.json` (у `lordserials22.info` это
   `/srv/lordserials22-info/data`, у `1lordserials1.online` — `<root>/data`
   при `root: /srv/site-1lordserials1-online`, и `<root>` раскрывается). К
   порядку добавляется `LORDS_DATA` и каталог по домену, как у
   `www_redirect.py`; каталог по имени репозитория остаётся последним и
   применяется лишь когда не нашлось ничего другого;
2. меняет `raise SystemExit(0)` на `raise SystemExit(2)` в ветке «снимков
   нет» и правит объявление кодов выхода в заголовке файла;
3. **оборачивает вызов в `checks/run.sh`** тем же видом, что у `www-redirect`
   и ещё семи проверок семейства: `rc=$?; [ "$rc" -eq 2 ] && exit 0`.

Третий пункт — поправка от владельца общего кода 28.10, и он по делу. Раннер
семейства считает любой нулевой код успехом, а любой НЕнулевой — провалом:
правка кода выхода без правки вызывающего красила бы шаг на каждом раннере
без снимков, включая CI, где их «нет и быть не должно» (так сказано в
заголовке самой проверки). Отсюда общее правило: инструмент, меняющий код
выхода проверки, обязан проверять строку её вызова так же, как якоря в
исходнике.

Якоря обязаны найтись ровно один раз, иначе отказ без правки файлов.

Чего инструмент НЕ делает: не трогает ни один снимок, ни одну постоянную
запись витрины и ни одно правило индексации; не меняет саму проверку режима
по существу — только адрес данных и код выхода «не измерено».
"""
from __future__ import annotations

import argparse
import pathlib
import sys

ФАЙЛ = "checks/indexing_live_switch.py"

ЯКОРЬ_ПУТИ = '''# Снимок: LORDS_FIXTURE_DIR, затем SITE_DATA_DIR, затем каталог ячейки по имени
# репозитория. Рабочая копия с другим именем каталога прежде молча уходила в
# «пропущено» с rc=0, и run.sh засчитывал шаг как PASS (T065, 14.10).
ЖИВЫЕ = Path(os.environ.get("LORDS_FIXTURE_DIR") or os.environ.get("SITE_DATA_DIR")
             or f"/srv/{КОРЕНЬ.name}/data")'''

ЗАМЕНА_ПУТИ = '''# Снимок: окружение, затем АДРЕС ИЗ НАСТРОЙКИ витрины, затем каталог по домену
# и лишь в последнюю очередь по имени репозитория.
#
# Имя репозитория адресом данных не является: у 1lordserials1.online каталог
# называется /srv/site-1lordserials1-online, и построенный путь не существовал.
# Прежде это молча уходило в «пропущено» с rc=0, и вызывающий засчитывал шаг
# как PASS (T065, 14.10; MOD-220, 28.10). Настоящий адрес объявлен в этой же
# настройке — deployment.data_dir, — и брать его оттуда надёжнее любой догадки
# по имени.
def _каталог_из_настройки(настройка: dict) -> str:
    развёртка = настройка.get("deployment") or {}
    адрес = str(развёртка.get("data_dir") or "")
    корень = str(развёртка.get("root") or "")
    if "<root>" in адрес:
        адрес = адрес.replace("<root>", корень) if корень else ""
    return адрес if адрес.startswith("/") else ""


_НАЗВАН = (os.environ.get("LORDS_FIXTURE_DIR") or os.environ.get("SITE_DATA_DIR")
           or os.environ.get("LORDS_DATA") or "")
if _НАЗВАН:
    # Каталог назвал вызывающий — догадкой его не подменяем: иначе в причине
    # окажется путь, которого никто не просил.
    ЖИВЫЕ = Path(_НАЗВАН)
else:
    ЖИВЫЕ = Path(_каталог_из_настройки(НАСТРОЙКА)
                 or f"/srv/{ДОМЕН.replace('.', '-')}/data")
    if not ЖИВЫЕ.is_dir():
        ЖИВЫЕ = Path(f"/srv/{КОРЕНЬ.name}/data")'''

ЯКОРЬ_КОДА = '''    print(f"НЕ ИЗМЕРЕНО: снимков нет в {ЖИВЫЕ} — переключение режима на витрине не проверено")
    raise SystemExit(0)'''

ЗАМЕНА_КОДА = '''    # Код 2, а не 0: «не измерено» не является «проверено и норма». Решение
    # принимает код выхода, а не текст вывода (MOD-220).
    print(f"НЕ ИЗМЕРЕНО: снимков нет в {ЖИВЫЕ} — переключение режима на витрине не проверено")
    raise SystemExit(2)'''

ЯКОРЬ_ЗАГОЛОВКА = "ссылками на боевые снимки (только чтение). Живого сайта проверка не касается:"
ЗАМЕНА_ЗАГОЛОВКА = ("ссылками на боевые снимки (только чтение). Живого сайта проверка не касается:\n"
                    "Коды выхода: 0 — норма, 1 — дефект, 2 — не измерено (снимков нет).")

ПАРЫ = ((ЯКОРЬ_ПУТИ, ЗАМЕНА_ПУТИ, "адрес снимка по домену"),
        (ЯКОРЬ_КОДА, ЗАМЕНА_КОДА, "код выхода «не измерено» = 2"),
        (ЯКОРЬ_ЗАГОЛОВКА, ЗАМЕНА_ЗАГОЛОВКА, "объявление кодов выхода в заголовке"))

РАННЕР = "checks/run.sh"
#: Вызов без обёртки: раннер считает код 2 провалом.
ЯКОРЬ_ВЫЗОВА = 'python3 checks/indexing_live_switch.py'
ОБЁРТКА = ('bash -c \'python3 checks/indexing_live_switch.py; rc=$?; '
           '[ "$rc" -eq 2 ] && exit 0; exit "$rc"\'')


def _правка_раннера(репо: pathlib.Path, писать: bool) -> tuple[str, str]:
    """Вызов проверки в run.sh обязан пропускать код 2, иначе шаг краснеет."""
    f = репо / РАННЕР
    if not f.is_file():
        return "refuse", f"нет {f}"
    текст = f.read_text(encoding="utf-8")
    if ОБЁРТКА in текст:
        return "skip", "вызов уже обёрнут"
    строки = [с for с in текст.splitlines()
              if ЯКОРЬ_ВЫЗОВА in с and с.lstrip().startswith("check ")]
    if len(строки) != 1:
        return "refuse", (f"строк вызова проверки в {РАННЕР} найдено "
                          f"{len(строки)}, ожидалась 1")
    строка = строки[0]
    if "rc=$?" in строка:
        return "skip", "вызов уже пропускает код 2 своим способом"
    if not писать:
        return "ok", f"вызов в {РАННЕР} будет обёрнут пропуском кода 2"
    f.write_text(текст.replace(строка, строка.replace(ЯКОРЬ_ВЫЗОВА, ОБЁРТКА, 1), 1),
                 encoding="utf-8")
    return "ok", f"вызов в {РАННЕР} обёрнут пропуском кода 2"


def применить(репо: pathlib.Path, писать: bool) -> tuple[str, str]:
    f = репо / ФАЙЛ
    if not f.is_file():
        return "refuse", f"нет {f}"
    текст = f.read_text(encoding="utf-8")
    исход_р, пояснение_р = _правка_раннера(репо, писать)
    if исход_р == "refuse":
        return "refuse", f"вызывающий: {пояснение_р}"
    if all(з in текст for _, з, _ in ПАРЫ):
        if исход_р == "ok":
            return "ok", пояснение_р
        return "skip", "правка уже стоит, вызывающий тоже"
    сделаем = []
    новый = текст
    for якорь, замена, что in ПАРЫ:
        if замена in новый:
            continue
        n = новый.count(якорь)
        if n != 1:
            return "refuse", f"якорь «{что}» найден {n} раз(а), ожидался 1"
        новый = новый.replace(якорь, замена, 1)
        сделаем.append(что)
    if not писать:
        if исход_р == "ok":
            сделаем.append(пояснение_р)
        return "ok", "будет исправлено: " + ", ".join(сделаем)
    f.write_text(новый, encoding="utf-8")
    if исход_р == "ok":
        сделаем.append(пояснение_р)
    return "ok", "исправлено: " + ", ".join(сделаем)


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--repo", required=True)
    р.add_argument("--check", action="store_true")
    р.add_argument("--dry-run", action="store_true")
    а = р.parse_args()
    репо = pathlib.Path(а.repo).resolve()
    исход, пояснение = применить(репо, писать=not (а.check or а.dry_run))
    print(f"[{исход}] {репо.name}: {пояснение}")
    if исход == "refuse":
        return 2
    if а.check:
        return 1 if исход == "ok" else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
