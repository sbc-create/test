def уместна(пара: tuple, текст: str) -> bool:
    """Относится ли пара к этому файлу вовсе.

    Два условия, и оба обязательны. Первое — требование пары к файлу
    (`ТРЕБУЕТ_ЛЕНТЫ` и подобные): без него похожий файл другой линии принял бы
    чужую правку. Второе — в файле есть либо якорь пары, либо её признак:
    иначе это не «другая линия», а разошедшийся рантайм, и тогда нужен отказ,
    а не молчание.
    """
    _, было, _, признак, требование = пара
    if требование and требование not in текст:
        return False
    return было in текст or признак in текст


def остатки(текст: str) -> list:
    return [f"нет: {п[0]}" for п in ПАРЫ
            if уместна(п, текст) and п[3] not in текст]


def применить(текст: str) -> tuple[str, list]:
    journal: list[str] = []
    затронуто = 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if требование and требование not in текст:
            journal.append(f"не относится к этой линии: {имя}")
            continue
        if признак in текст:
            journal.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if было not in текст:
            # Требование файла выполнено, а якоря нет — это разошедшийся
            # рантайм, и писать в него нельзя: отказ ДО единой правки.
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        journal.append(f"применено: {имя}")
        затронуто += 1
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, journal


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        уместных = [п for п in ПАРЫ if уместна(п, исходный)]
        if а.check:
            if not уместных:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, journal = применить(исходный)
        print(f"== {путь}")
        for строка in journal:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


