#!/usr/bin/env python3
"""`/schedule/` называет себя страницей онгоингов (T339, п. 2).

ПОВОД. Линия SEO предложила завести подборку «Онгоинги сезона» и сама же от
неё отказалась, измерив: признаку «серия в расписании недели и новая серия на
сайте» отвечают 73 названия, и ВСЕ 73 уже есть на `/schedule/`. Заводить
подборку значило бы создать третий адрес с той же выдачей — ровно тот дубль,
который в этот же день убран у «Этого года». Вместо подборки страница
расписания называет себя тем, чем является.

ЧТО ДЕЛАЕТ.
  * H1 «Онгоинги {сезон} {год}: расписание серий» — сезон считается из даты,
    а не объявляется: январь–март зима, апрель–июнь весна, июль–сентябрь
    лето, октябрь–декабрь осень. Время — московское, тем же `АНИМЕДИА_TZ`,
    которым витрина уже считает «сегодня».
  * Вступление и description, называющие, что на странице.
  * Пункт меню «Расписание» переименован в «Онгоинги». Именно переименован, а
    не добавлен рядом: второй пункт на тот же адрес — это две ссылки на одно
    место в одном меню.

ЧЕГО НЕ ДЕЛАЕТ. Не трогает ветку «данных ещё нет»: там страница честно
говорит «Расписание уточняется», и называть её «Онгоингами сезона» значило бы
обещать состав, которого в этот момент нет.

    python3 automation/host/apply-schedule-ongoing-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

СЕЗОН_БЫЛО = '''АНИМЕДИА_TZ = timezone(timedelta(hours=3))'''
СЕЗОН_СТАЛО = '''АНИМЕДИА_TZ = timezone(timedelta(hours=3))


def _сезон_и_год(сейчас=None) -> tuple:
    """Сезон и год по дате, московское время: («лето», 2026).

    Сезон СЧИТАЕТСЯ, а не объявляется в настройках: объявленный пришлось бы
    кому-то вовремя менять, и однажды он бы отстал. Границы — календарные
    кварталы, как их называет линия SEO: январь–март зима, апрель–июнь весна,
    июль–сентябрь лето, октябрь–декабрь осень.
    """
    когда = сейчас or datetime.now(АНИМЕДИА_TZ)
    # Двенадцать имён по числу месяцев, индекс — `month - 1`. Первая версия
    # этого ряда несла два зимних месяца вместо трёх, и весь ряд был сдвинут:
    # март становился весной, июнь летом, сентябрь осенью. Поймали тесты по
    # каждому месяцу, а не по сегодняшней дате — на живой странице такая
    # ошибка означала бы три месяца неверного сезона в H1.
    имена = ("зима", "зима", "зима", "весна", "весна", "весна",
             "лето", "лето", "лето", "осень", "осень", "осень")
    return имена[когда.month - 1], когда.year'''

ЗАГОЛОВОК_БЫЛО = '''            f'<h1 class="zh">Расписание</h1>'
            f'<p class="zsub">Время выхода новых серий. '
            f'Время московское (UTC+3).</p>' '''.rstrip() + "\n"
ЗАГОЛОВОК_СТАЛО = '''            f'<h1 class="zh">Онгоинги {_сезон_и_год()[0]} {_сезон_и_год()[1]}: '
            f'расписание серий</h1>'
            f'<p class="zsub">Аниме и дунхуа, у которых сейчас выходят новые '
            f'серии, — по дням недели. Время московское; если серия уже есть '
            f'на сайте, это отмечено.</p>'
'''

ОПИСАНИЕ_БЫЛО = '''                             описание=(f"Расписание выхода новых серий аниме на {self.имя}: "
                                       f"{показано} {_по_числу(показано, 'выход', 'выхода', 'выходов')} "
                                       f"на неделе по дням, время московское (UTC+3)."))'''
ОПИСАНИЕ_СТАЛО = '''                             описание=(f"Онгоинги {_сезон_и_год()[0]} {_сезон_и_год()[1]} "
                                       f"на {self.имя}: {показано} "
                                       f"{_по_числу(показано, 'выход', 'выхода', 'выходов')} "
                                       f"на неделе по дням, время московское (UTC+3)."))'''

ПАРЫ_МЕНЮ = (
    ('("/schedule/", "Расписание")]', '("/schedule/", "Онгоинги")]'),
    ('("/schedule/", "Расписание"),', '("/schedule/", "Онгоинги"),'),
    ('("/schedule/", "Расписание"))', '("/schedule/", "Онгоинги"))'),
)

ТРЕБУЕТ_РАНТАЙМА = "АНИМЕДИА_TZ = timezone"
ТРЕБУЕТ_СТРАНИЦЫ = 'data-b04="weekly"'
ПАРЫ = (
    ("сезон по дате", СЕЗОН_БЫЛО, СЕЗОН_СТАЛО, "def _сезон_и_год", ТРЕБУЕТ_РАНТАЙМА),
    ("заголовок онгоингов", ЗАГОЛОВОК_БЫЛО, ЗАГОЛОВОК_СТАЛО,
     "Онгоинги {_сезон_и_год()[0]}", ТРЕБУЕТ_СТРАНИЦЫ),
    ("описание онгоингов", ОПИСАНИЕ_БЫЛО, ОПИСАНИЕ_СТАЛО,
     'описание=(f"Онгоинги ', ТРЕБУЕТ_СТРАНИЦЫ),
)


def _меню(текст: str) -> tuple:
    """Переименование пункта меню во всех трёх перечнях сразу."""
    сделано = 0
    for было, стало in ПАРЫ_МЕНЮ:
        if было in текст:
            сделано += текст.count(было)
            текст = текст.replace(было, стало)
    return текст, сделано


def уместна(пара: tuple, текст: str) -> bool:
    _, было, _, признак, требование = пара
    if признак in текст:
        return True
    if требование not in текст:
        return False
    return было in текст


def остатки(текст: str) -> list:
    п = [f"нет: {п[0]}" for п in ПАРЫ if уместна(п, текст) and п[3] not in текст]
    if ТРЕБУЕТ_РАНТАЙМА in текст and '("/schedule/", "Расписание"' in текст:
        п.append("нет: пункт меню «Онгоинги»")
    return п


def применить(текст: str) -> tuple[str, list]:
    журнал, затронуто = [], 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if требование not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
        затронуто += 1
    if ТРЕБУЕТ_РАНТАЙМА in текст:
        текст, сделано = _меню(текст)
        журнал.append(f"пункт меню «Онгоинги»: переименований {сделано}")
        затронуто += bool(сделано)
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if ТРЕБУЕТ_РАНТАЙМА not in исходный and ТРЕБУЕТ_СТРАНИЦЫ not in исходный:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
