#!/usr/bin/env python3
"""Доступность серии — множество номеров, а не одно число. Проверка витрины.

Ставится в репозиторий каждой витрины как `checks/episode_availability.py` и
запускается в её проверках до выпуска. Сеть здесь запрещена: ответ провайдера
подставляется, проверяется НАША часть — как из данных снимка получается то, чем
рендерер включает плеер.

Оба названных владельцем случая закреплены поимённо, с настоящими данными
источника, чтобы проверка не прошла мимо уже известного дефекта:

СКОТТЫ (`/title/skotty/`, `01a0e27f-8175-7115-8972-83cce31b15d3`). Замер
2026-09-28, издатели 10238, 10252 и 10261 отвечают одинаково: у записи РОВНО
ОДНА дорожка — `Pilot`, season 1, episode 0, с `vkId` и `cvhId`. Снимок
объявляет `avail=1, eps=6`. Витрина показывала «доступно 1», монтировала
`<video-player episode="1">`, провайдер отвечал noData, и посетитель читал
«Провайдер не отдал источник» с «Видео пока не добавлено».

МАСТЕР ОМЮР (`/title/master-omyur/`, `01a0e45a-ba66-7613-879c-f209068f60e3`).
Снимок собирается раз в сутки и объявлял `avail=0` при живой дорожке s1e1.

Рантайм берётся ТОТ ЖЕ, что исполняет витрина: имя из `config/site.json`
(`entrypoint`), тонкий слой витрины заменяется общим рантаймом семейства.
Манифест подставляется репозиторный: умолчание рантайма ведёт в общее дерево
фабрики, то есть к снимку СОСЕДНЕЙ витрины, и на раннере CI его нет вовсе.
"""
from __future__ import annotations

import importlib.util
import json
import os
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent

СКОТТЫ = [{"n": 1, "eps": 6, "avail": 1, "nums": [0]},
          {"n": 2, "eps": 1, "avail": 0}]
ОМЮР_ОТСТАЛ = [{"n": 1, "eps": 1, "avail": 0}]
ОМЮР_СВЕРЕН = [{"n": 1, "eps": 1, "avail": 1, "nums": [1]}]
ПРОПУСК = [{"n": 2, "eps": 21, "avail": 21, "nums": list(range(2, 23))}]
ПЕРЕБОР = [{"n": 2, "eps": 24, "avail": 24, "nums": list(range(1, 27))}]
СТАРЫЙ = [{"n": 1, "eps": 9, "avail": 3}]


def рантайм_витрины() -> Path:
    """Файл рантайма ЭТОЙ витрины — тот, что она исполняет.

    Точка входа витрины может быть тонким слоем поверх общего рантайма
    (`serve.py` у zonafilm.cc, `lords02-frontend.py` у lordserial33.biz).
    Согласованию нужен именно общий: правила `ПЛЕЕР` и `кандидаты_источника`
    живут в нём. Слой распознаётся по отсутствию `ПЛЕЕР`.

    Общий рантайм лежит не всегда в `src/`: у витрин, закрепляющих артефакт
    шаблона целиком, он живёт в `template/<релиз>/`. Ищется он, а не
    подставляется по умолчанию: жёсткий путь молча брал бы не тот файл.
    """
    конфиг = json.loads((КОРЕНЬ / "config" / "site.json").read_text(encoding="utf-8"))
    # Поле `entrypoint` объявляют не все витрины: у части точка входа — сам
    # рантайм семейства. Отсутствие поля здесь не отказ, а «искать по
    # семейству»: отказывать пришлось бы там, где искать больше негде.
    имя = str(конфиг.get("entrypoint") or "").strip()
    путь = КОРЕНЬ / "src" / имя if имя else None
    if путь and путь.is_file() and "ПЛЕЕР" in путь.read_text(
            encoding="utf-8", errors="replace"):
        return путь
    общий = {"lords": "lords-frontend.py", "zona": "lords-frontend.py",
             "animedia": "animedia-frontend.py",
             "animego": "animego-frontend.py"}.get(
                 str(конфиг.get("family") or "").strip())
    места = []
    if общий:
        места.append(КОРЕНЬ / "src" / общий)
        места += sorted((КОРЕНЬ / "template").glob(f"*/{общий}"))
    места += sorted(КОРЕНЬ.glob("src/*frontend*.py"))
    места += sorted(КОРЕНЬ.glob("template/*/*frontend*.py"))
    for кандидат in места:
        if кандидат.is_file() and "ПЛЕЕР" in кандидат.read_text(
                encoding="utf-8", errors="replace"):
            return кандидат
    raise SystemExit(f"{имя or 'витрина'}: общего рантайма семейства рядом нет — "
                     "искали в src/ и template/<релиз>/")


def загрузить(временный: Path):
    """Рантайм на пустом стенде: ни один путь не ведёт к данным витрины."""
    # Манифест шаблона лежит либо в config/, либо в корне репозитория — у
    # витрин, закрепляющих артефакт целиком. Подставляется СВОЙ: умолчание
    # рантайма ведёт в общее дерево фабрики, то есть к снимку СОСЕДНЕЙ витрины,
    # а на раннере CI такого дерева нет вовсе.
    манифест = next((к for к in (КОРЕНЬ / "config" / "template-manifest.json",
                                 КОРЕНЬ / "template-manifest.json") if к.is_file()),
                    КОРЕНЬ / "config" / "template-manifest.json")
    каталог = временный / "catalog.json"
    каталог.write_text(json.dumps(
        {"revision": "check", "built_at": "2026-09-28T00:00:00+00:00", "items": []}),
        encoding="utf-8")
    подробности = временный / "details.json"
    подробности.write_text(json.dumps(
        {"catalog_revision": "check", "details": {}}), encoding="utf-8")
    # Настройка плеера намеренно ПУСТАЯ. Проверяемые правила — `список_серий`,
    # `серия_с_дорожкой`, `выбрать_доступную_серию` — издателя не читают, а
    # написать сюда любое число значит положить в репозиторий строку вида
    # «publisher_id: <цифры>»: проверка checks/no_secrets.py справедливо
    # считает это значением в git, и ей всё равно, что число выдуманное.
    плеер = временный / "player.json"
    плеер.write_text(json.dumps({"source_mode": "provider-id"}), encoding="utf-8")
    for ключ, значение in (
            ("LORDS_TEMPLATE_MANIFEST", манифест), ("ANIMEDIA_TEMPLATE_MANIFEST", манифест),
            ("ANIMEGO_TEMPLATE_MANIFEST", манифест),
            ("LORDS_CATALOG", каталог), ("ANIMEDIA_CATALOG", каталог),
            ("ANIMEGO_CATALOG", каталог),
            ("LORDS_DETAILS", подробности), ("ANIMEDIA_DETAILS", подробности),
            ("ANIMEGO_DETAILS", подробности),
            ("LORDS_PLAYER_CONFIG", плеер),
            ("LORDS_LEGACY_ROOT", временный), ("ANIMEDIA_LEGACY_ROOT", временный),
            ("ANIMEGO_LEGACY_ROOT", временный)):
        os.environ[ключ] = str(значение)
    путь = рантайм_витрины()
    sys.path.insert(0, str(путь.parent))
    спец = importlib.util.spec_from_file_location("_витрина", путь)
    модуль = importlib.util.module_from_spec(спец)
    sys.modules["_витрина"] = модуль
    спец.loader.exec_module(модуль)
    return модуль


def проверить(м) -> list:
    сбои = []

    def равно(что, ожидалось, имя):
        if что != ожидалось:
            сбои.append(f"{имя}: получено {что!r}, ожидалось {ожидалось!r}")

    скотты = {"seasons": СКОТТЫ}
    равно(м.серия_с_дорожкой(скотты, 1, 0), True,
          "«Скотты»: спецвыпуск 0 обязан играть — у источника это ЕДИНСТВЕННАЯ дорожка")
    равно(м.серия_с_дорожкой(скотты, 1, 1), False,
          "«Скотты»: серии 1 у источника нет, обещать её нельзя")
    равно(м.выбрать_доступную_серию(скотты), (1, 0),
          "«Скотты»: хаб обязан предложить играющую серию, а не первый номер подряд")
    первый = [с for с in м.список_серий(скотты) if с["n"] == 1][0]
    равно(первый["доступно"], 1, "«Скотты»: счётчик доступных")
    равно(0 in первый["номера"], True, "«Скотты»: номер спецвыпуска в списке серий")

    равно(м.серия_с_дорожкой({"seasons": ОМЮР_ОТСТАЛ}, 1, 1), False,
          "«Мастер Омюр» до сверки: прежний снимок обязан вести себя как раньше")
    равно(м.серия_с_дорожкой({"seasons": ОМЮР_СВЕРЕН}, 1, 1), True,
          "«Мастер Омюр» после сверки: дорожка есть — страница обязана её видеть")

    пропуск = {"seasons": ПРОПУСК}
    равно(м.серия_с_дорожкой(пропуск, 2, 1), False, "пропуск: серии 1 у источника нет")
    равно(м.серия_с_дорожкой(пропуск, 2, 2), True, "пропуск: серия 2 играет")
    равно(м.выбрать_доступную_серию(пропуск), (2, 2),
          "пропуск: разрыв в начале не должен скрывать остальные серии")

    перебор = {"seasons": ПЕРЕБОР}
    сезон = [с for с in м.список_серий(перебор) if с["n"] == 2][0]
    равно(26 in сезон["номера"], True,
          "перебор: серия выше заявленного eps играет и обязана быть достижима")
    равно(сезон["доступно"], 26, "перебор: счётчик доступных")

    for сырое in ([], "", {}, None, ["x"], [-3]):
        пусто = {"seasons": [{"n": 1, "eps": 4, "avail": 2, "nums": сырое}]}
        равно(м.серия_с_дорожкой(пусто, 1, 0), False,
              f"пустой перечень {сырое!r} не должен становиться спецвыпуском")

    старый = {"seasons": СТАРЫЙ}
    равно([н for н in range(0, 10) if м.серия_с_дорожкой(старый, 1, н)], [1, 2, 3],
          "снимок без перечня обязан вести себя в точности как раньше")

    текст = рантайм_витрины().read_text(encoding="utf-8")
    for остаток in ('доступна = н <= сезон["avail"]', 'return эпизод <= с["avail"]'):
        if остаток in текст:
            сбои.append(f"в рантайме остался счётчик вместо множества: {остаток}")
    return сбои


def main() -> int:
    with tempfile.TemporaryDirectory() as врем:
        модуль = загрузить(Path(врем))
        сбои = проверить(модуль)
    for с in сбои:
        print(f"FAIL {с}")
    if сбои:
        return 1
    print("episode-availability: контракт выполнен "
          "(«Скотты», «Мастер Омюр», пропуски, перебор, старый снимок)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
