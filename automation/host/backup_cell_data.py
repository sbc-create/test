#!/usr/bin/env python3
"""Что из данных ячеек обязано попасть в бэкап хоста — план сбора, не сам сбор.

Повод. Измерено 2026-10-13: `site-factory-backup.sh` собирает `/srv/sites/`,
`/etc/site-factory/`, `/etc/nginx/sites-available/`, `var/` фабрики и
шифрованное хранилище Secret Hub. Каталоги данных ЯЧЕЕК живут по другому пути —
`/srv/<учётная запись>/data` — и в сбор не входили ни у одной из 28 ячеек,
включая работающие с августа. Пользовательские данные витрины — оценки,
комментарии, опубликованные правки редактора — восстановить было бы нечем.

Почему не «весь каталог данных». Тоже измерено: каталоги данных ячеек весят
1,81 ГиБ, а невосстановимая их часть — 25,74 МиБ, то есть 1,39 %. Остальное —
снимок каталога и подробности, которые заново положит производитель
(`delivered` в контракте данных витрины). Класть 1,8 ГиБ в каждый суточный
архив на диск, где свободно 7,8 ГиБ, значило бы променять надёжность на
копирование того, что и так воспроизводится.

Что берётся и откуда. Список берётся из КОНТРАКТА ДАННЫХ самой витрины
(`config/site.json: data_contract.user_writable`), а не из списка имён,
выписанного здесь: витрина, добавленная завтра, не должна снова оказаться без
копии. Там, где контракт не объявлен, каталог берётся целиком МИНУС
поставляемые файлы, и об этом печатается строка `УНКОНТРАКТ`: молчаливый
пропуск — ровно то, из-за чего пробел и возник.

Безопасность плана. Элемент контракта — это содержимое файла в репозитории
витрины, то есть вход, которому доверять нельзя. Любой элемент, уводящий за
пределы каталога данных (`..`, абсолютный путь, символическая ссылка наружу),
в план не попадает: он печатается строкой `ОТКАЗ` и останавливает прогон
бэкапа, а не исключается молча.

Вывод — TSV, по строке на элемент сбора:

    <site_id>\t<каталог данных>\t<элемент>

где `<элемент>` — имя внутри каталога данных либо `*` для режима «весь каталог
минус поставляемое». Диагностика идёт в stderr и в план не попадает.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]

#: Реестр ячеек, которым пользуется ХОСТ. Это корневая копия привилегированного
#: исполнителя (`site-cell-executor.service`, WorkingDirectory
#: /usr/local/lib/site-factory-cell): именно из неё он берёт размещение витрин.
#: Рабочая копия репозитория сюда не годится — измерено 2026-10-13: в
#: /srv/site-factory/repo нет ни config/site-cells.json, ни factory/cell вовсе,
#: это более старый checkout. Поэтому и пакет factory здесь НЕ импортируется:
#: сценарий бэкапа запускается из той самой старой копии, и импорт упал бы
#: ModuleNotFoundError — проверено.
РЕЕСТР_ХОСТА = Path("/usr/local/lib/site-factory-cell/config/site-cells.json")

#: Что заведомо поставляется заново и копировать его незачем. Берётся из
#: контракта витрины, когда он есть; эти образцы — для витрин без контракта.
ПОСТАВЛЯЕМОЕ = ("*-catalog.json", "*-details.json", "*-details.nums.json")


class ПланОтвергнут(RuntimeError):
    """Элемент контракта уводит за пределы каталога данных."""


def _внутри(корень: Path, элемент: str) -> bool:
    """Остаётся ли элемент внутри каталога данных.

    Проверяется БЕЗ обращения к файловой системе: план строится и там, где
    каталога ещё нет (новая витрина до активации), и отсутствие файла не
    должно превращаться в разрешение.
    """
    if not элемент or элемент.startswith(("/", "~")):
        return False
    путь = (корень / элемент)
    try:
        путь.relative_to(корень)
    except ValueError:
        return False
    # `..` внутри строки ловится до нормализации: `a/../../etc` даёт корень,
    # которому relative_to уже не возразит.
    return ".." not in Path(элемент).parts


#: Куда установщик записал основание для относительных `repo.path`. Файл лежит
#: рядом с корневой копией реестра и читается всеми (0644), а правило — то же,
#: что у `factory.cell.registry.корень_репозиториев`. Без него относительные
#: пути разрешались бы от места ЭТОГО файла, то есть от более старой рабочей
#: копии: измерено 2026-10-13 — контракты не находились у 20 витрин из 28, и
#: план вырождался в «весь каталог минус поставляемое».
ОТМЕТКА_УСТАНОВКИ = РЕЕСТР_ХОСТА.parent.parent / "cell-install.json"


def корень_репозиториев_для(реестр: Path) -> Path:
    """Основание для относительных `repo.path` рядом с этим реестром."""
    отметка = реестр.parent.parent / "cell-install.json"
    for кандидат in (отметка, ОТМЕТКА_УСТАНОВКИ):
        if not кандидат.is_file():
            continue
        try:
            значение = json.loads(кандидат.read_text(encoding="utf-8")).get(
                "site_repos_root")
        except (OSError, ValueError):
            continue
        if значение:
            return Path(значение)
    return КОРЕНЬ


def выбрать_реестр(реестр: Path | None = None) -> Path:
    """Какой реестр читать. Явный путь важнее, корневая копия важнее рабочей."""
    if реестр is not None:
        return реестр
    if РЕЕСТР_ХОСТА.is_file():
        return РЕЕСТР_ХОСТА
    return КОРЕНЬ / "config" / "site-cells.json"


def _ячейки(реестр: Path) -> list[dict]:
    """Записи реестра. Нечитаемый реестр — ОТКАЗ, а не пустой план.

    Пустой план здесь опаснее исключения: бэкап прошёл бы успешно и без данных
    ячеек, то есть вернул бы ровно тот пробел, который и закрывается.
    """
    try:
        данные = json.loads(реестр.read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        raise ПланОтвергнут(
            f"реестр ячеек {реестр} не прочитан ({type(ош).__name__}): план сбора "
            "не строится, и пустым он быть не вправе") from None
    ячейки = данные.get("cells") or данные.get("sites") or []
    if isinstance(ячейки, dict):
        ячейки = list(ячейки.values())
    if not ячейки:
        raise ПланОтвергнут(f"в реестре {реестр} нет ни одной ячейки")
    return ячейки


def план(реестр: Path | None = None, *, корень: Path | None = None,
         шум=sys.stderr) -> list[tuple[str, str, str]]:
    """Строки плана сбора. Контракт витрины — источник, не этот файл."""
    путь_реестра = выбрать_реестр(реестр)
    корень_репозиториев = корень or корень_репозиториев_для(путь_реестра)
    итог: list[tuple[str, str, str]] = []
    for запись in _ячейки(путь_реестра):
        site_id = str(запись.get("site_id") or "").strip()
        if not site_id:
            print("ПРОПУСК\t(без site_id)\tзапись реестра без идентификатора",
                  file=шум)
            continue
        рв = запись.get("runtime") or {}
        каталог = str(рв.get("data_dir") or "").strip()
        if not каталог:
            print(f"ПРОПУСК\t{site_id}\tкаталог данных в реестре не записан",
                  file=шум)
            continue
        путь_репо = str((запись.get("repo") or {}).get("path") or "").strip()
        файл = None
        if путь_репо:
            п = Path(путь_репо)
            файл = (п if п.is_absolute() else корень_репозиториев / п) / "config" / "site.json"
        контракт: list[str] = []
        if файл is not None and файл.is_file():
            try:
                данные = json.loads(файл.read_text(encoding="utf-8"))
            except (OSError, ValueError) as ош:
                print(f"УНКОНТРАКТ\t{site_id}\tconfig/site.json не читается: "
                      f"{type(ош).__name__}", file=шум)
                данные = {}
            контракт = list((данные.get("data_contract") or {}).get("user_writable") or [])
        if not контракт:
            print(f"УНКОНТРАКТ\t{site_id}\tконтракт данных не объявлен: "
                  f"каталог берётся целиком минус поставляемое", file=шум)
            итог.append((site_id, каталог, "*"))
            continue
        for шаблон in контракт:
            элемент = шаблон.format(site=site_id)
            if not _внутри(Path(каталог), элемент):
                raise ПланОтвергнут(
                    f"{site_id}: элемент контракта {элемент!r} уводит за "
                    f"пределы {каталог} — план сбора не строится")
            итог.append((site_id, каталог, элемент))
    return итог


def main() -> int:
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--registry", help="путь к реестру ячеек (по умолчанию — штатный)")
    р.add_argument("--check", action="store_true",
                   help="только сводка, без TSV: сколько витрин и элементов")
    а = р.parse_args()
    try:
        строки = план(Path(а.registry) if а.registry else None)
    except ПланОтвергнут as ош:
        print(f"ОТКАЗ: {ош}", file=sys.stderr)
        return 2
    if а.check:
        витрин = len({с for с, _, _ in строки})
        целиком = sum(1 for _, _, э in строки if э == "*")
        print(f"витрин в плане: {витрин}; элементов: {len(строки)}; "
              f"из них «весь каталог минус поставляемое»: {целиком}")
        return 0
    for site_id, каталог, элемент in строки:
        print(f"{site_id}\t{каталог}\t{элемент}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
