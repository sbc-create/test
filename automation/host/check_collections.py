#!/usr/bin/env python3
"""Подборки витрины отвечают требованиям — проверкой ВЫПУСКА, а не памятью.

Повод названо прямо. Требование к подборкам записано в `AGENTS.md` каждого
нового сайта и в схеме `site-collections`, но ШТАТНЫЙ ВЫПУСК их не проверял:
`checks/run.sh` о подборках не знал, и команда приёмки в AGENTS.md сама по себе
этого не подтверждает — её надо было вспомнить и запустить руками. Проверка,
которую надо помнить, рано или поздно не запускается.

Что проверяется здесь (без сети, поэтому годится и для CI):

* файл подборок витрины — `config/collections.json`;
* он отвечает схеме `config/site-collections.schema.json`, закреплённой в
  `pins.lock.json` вместе с рантаймом: у каждой подборки потребность читателя,
  принцип отбора, раздел-владелец, устойчивый ключ, порядок, постоянные `id`
  работ и ОБОСНОВАННОЕ решение об индексации.

Чего здесь НЕТ, и это сказано вслух:

* живых фактов (отвечает ли адрес работы, индексируется ли, есть ли постер и
  плеер). Они требуют сети и свежего каталога, их снимает
  `automation/local/collections-acceptance.py` при выпуске;
* неповторяемости по сети: здесь лежит файл ОДНОЙ витрины, и сравнивать не с
  чем. Это тоже делает инструмент фабрики, который видит все витрины;
* мобильного сценария «увидеть → выбрать → открыть → начать просмотр»: он
  измеряется событиями аналитики, а не разметкой.

Витрина, которая подборок не объявляет, проверку не проваливает: она отвечает
ПРОПУЩЕНО с причиной. Молча пройти нельзя — `checks/run.sh` считает пропуски
отдельной строкой, и «не измерено» не сливается с «проверено».
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ФАЙЛ = КОРЕНЬ / "config" / "collections.json"
СХЕМА = КОРЕНЬ / "config" / "site-collections.schema.json"
#: Команда, которая снимает то, чего эта проверка не умеет. Печатается всегда:
#: отчёт обязан называть границу своей проверки, а не молчать о ней.
ЖИВАЯ_ПРИЁМКА = ("python3 automation/local/collections-acceptance.py "
                 "<файл подборок> --sample 2")


def нарушения(данные: dict, схема_путь: Path = СХЕМА) -> list:
    """Нарушения схемы. Пустой список означает «файл отвечает требованиям»."""
    import jsonschema

    схема = json.loads(схема_путь.read_text(encoding="utf-8"))
    итог = []
    for e in jsonschema.Draft202012Validator(схема).iter_errors(данные):
        путь = "/".join(str(ч) for ч in e.path) or "(корень)"
        итог.append(f"{путь}: {e.message}")
    return итог


def главная(аргв=None) -> int:
    файл = Path(аргв[0]) if аргв else ФАЙЛ
    if not файл.is_file():
        print(f"ПРОПУЩЕНО: НЕ ИЗМЕРЕНО — файла подборок {файл.name} нет, "
              f"витрина их не объявляет")
        return 0
    if not СХЕМА.is_file():
        print(f"ПРОПУЩЕНО: НЕ ИЗМЕРЕНО — схемы {СХЕМА.name} нет в проекте, "
              f"сверять нечем (она закрепляется вместе с рантаймом)")
        return 0
    try:
        данные = json.loads(файл.read_text(encoding="utf-8"))
    except ValueError as ош:
        print(f"ОТКАЗ: {файл.name} не разбирается как JSON: {ош}", file=sys.stderr)
        return 1
    плохо = нарушения(данные)
    подборок = len(данные.get("collections") or [])
    if плохо:
        print(f"ОТКАЗ: подборок {подборок}, нарушений схемы {len(плохо)}:",
              file=sys.stderr)
        for строка in плохо[:20]:
            print(f"  {строка}", file=sys.stderr)
        return 1
    print(f"подборок {подборок}, нарушений схемы 0")
    print(f"живые факты и неповторяемость здесь НЕ измеряются: {ЖИВАЯ_ПРИЁМКА}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главная(sys.argv[1:]))
