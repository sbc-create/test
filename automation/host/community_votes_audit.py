#!/usr/bin/env python3
"""Пересчитать голоса витрины и найти дубли. Ничего не меняет.

Запускается под тем пользователем, которому принадлежит хранилище (обычно
root или сервисный пользователь витрины): файл закрыт 0600, и это правильно.

Что считается дублем. В схеме `votes` — это словарь «голосующий → оценка», то
есть на одного голосующего структурно приходится ровно одна запись, и дубль в
привычном смысле невозможен. Возможны два других случая, и оба ищутся здесь:

  * одна и та же тема лежит и под постоянным ключом, и под адресом — след
    незавершённого переноса. Голоса в этих записях складывать нельзя: это
    разные наборы, и у одного человека могут быть записи в обеих;
  * оценка вне шкалы 1–10 — такие значения не участвуют в среднем, и если их
    много, среднее на странице не сойдётся с ожиданием.

Удалять и сливать этот скрипт не умеет намеренно: сначала происхождение, потом
резервная копия, и только потом миграция.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

UUID = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"использование: {argv[0]} <путь к animedia-community.json>",
              file=sys.stderr)
        return 2
    путь = Path(argv[1])
    try:
        данные = json.loads(путь.read_text(encoding="utf-8"))
    except OSError as e:
        print(f"REFUSED: не прочитать {путь}: {e}", file=sys.stderr)
        return 1
    except ValueError as e:
        print(f"REFUSED: {путь} не разбирается как JSON: {e}", file=sys.stderr)
        return 1

    titles = данные.get("titles") or {}
    print(f"файл          : {путь}")
    print(f"формат        : schema_version={данные.get('schema_version')}")
    print(f"витрина       : {данные.get('site_id') or '(не указана)'}")
    print(f"тем           : {len(titles)}")

    постоянные = {k for k in titles if UUID.match(k)}
    адреса = {k for k in titles if not UUID.match(k)}
    print(f"под постоянным ключом : {len(постоянные)}")
    print(f"под адресом           : {len(адреса)}")

    проблемы = 0

    # 1. незавершённый перенос: и адрес, и постоянный ключ у одной темы
    парные = []
    for ключ in адреса:
        for пост in постоянные:
            если = titles[пост].get("migrated_from_slug")
            if если == ключ:
                парные.append((ключ, пост))
    if парные:
        проблемы += len(парные)
        print("\nНЕЗАВЕРШЁННЫЙ ПЕРЕНОС — одна тема лежит дважды:")
        for адрес, пост in парные:
            га = len((titles[адрес].get("votes") or {}))
            гп = len((titles[пост].get("votes") or {}))
            print(f"  {адрес}: {га} голос(ов)  <->  {пост}: {гп} голос(ов)")
        print("  Складывать нельзя: у одного человека могут быть записи в обеих.")
        print("  Порядок: резервная копия -> разбор пересечения -> миграция.")

    # 2. оценки вне шкалы
    вне = []
    всего_голосов = 0
    for тема, запись in titles.items():
        голоса = (запись.get("votes") or {})
        всего_голосов += len(голоса)
        for кто, значение in голоса.items():
            try:
                v = int(значение)
            except (TypeError, ValueError):
                вне.append((тема, кто, значение))
                continue
            if not 1 <= v <= 10:
                вне.append((тема, кто, значение))
    print(f"\nвсего записей голосов : {всего_голосов}")
    if вне:
        проблемы += len(вне)
        print(f"ОЦЕНКИ ВНЕ ШКАЛЫ 1–10 : {len(вне)}")
        for тема, кто, значение in вне[:20]:
            print(f"  {тема} / {кто[:12]}… = {значение!r}")
    else:
        print("оценок вне шкалы      : нет")

    # 3. структурный дубль голосующего внутри темы невозможен — подтвердить
    print("дублей голосующего    : невозможны структурно "
          "(votes — словарь «голосующий → оценка»)")

    print(f"\nAUDIT={'CLEAN' if проблемы == 0 else 'ISSUES'} problems={проблемы}")
    return 0 if проблемы == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
