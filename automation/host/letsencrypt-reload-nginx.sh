#!/usr/bin/env bash
# Хук продления: перечитать сертификаты в nginx после обновления.
#
# Ставится в /etc/letsencrypt/renewal-hooks/deploy/ на узле витрин.
#
# Зачем он нужен. Выпуск идёт способом `--webroot`, то есть certbot сам nginx
# не трогает: он кладёт новые файлы и завершается успешно. Работающий nginx при
# этом продолжает держать в памяти ПРЕЖНИЙ сертификат — до перезагрузки
# конфигурации. Продление поэтому проходит «успешно» и ничего не меняет для
# посетителя, а через 90 суток сайт отдаёт просроченный сертификат. Измерено на
# k2-zomro-01 2026-10-15: certbot 2.9.0 стоит, `certbot.timer` включён
# (следующий запуск был назначен на 16:28 UTC), а каталога
# /etc/letsencrypt/renewal-hooks/deploy/ нет вовсе — то есть перезагружать
# nginx после продления некому.
#
# Почему проверка перед перезагрузкой. Если конфигурация в этот момент
# сломана (например, кто-то оставил блок со ссылкой на несуществующий файл),
# `systemctl reload` оставит nginx работать на старой конфигурации, а хук
# завершится «успешно». Отказ обязан быть громким: он попадёт в журнал
# certbot.service, по которому и видно, продлилось ли на самом деле.
#
# Имена переменных только ASCII: кириллица в именах переменных оболочки падает
# в работе, а `bash -n` её пропускает.
set -uo pipefail

stamp="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
domains="${RENEWED_DOMAINS:-не названы certbot}"

echo "$stamp letsencrypt deploy-hook: продлено для $domains"

if ! nginx -t 2>&1; then
  echo "$stamp ОТКАЗ: nginx -t не проходит — конфигурацию не перезагружаю." >&2
  echo "Новые файлы сертификата на диске есть, но посетителю всё ещё отдаётся" >&2
  echo "прежний. Разберите вывод nginx -t выше и перезагрузите вручную." >&2
  exit 1
fi

if systemctl reload nginx; then
  echo "$stamp nginx перечитал конфигурацию: новый сертификат в работе"
else
  echo "$stamp ОТКАЗ: systemctl reload nginx не выполнился" >&2
  exit 1
fi
