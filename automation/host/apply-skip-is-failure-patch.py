#!/usr/bin/env python3
"""MOD-221: на площадке «ничего не измерено» — провал, а не печатная строка.

    python3 automation/host/apply-skip-is-failure-patch.py \
        --repo var/site-repos/<витрина> [--check] [--dry-run]

Что измерено
------------

Замер 28.10 по `checks/run.sh` всех пятнадцати действующих витрин. Раннер
«ничего не измерено» ЗАМЕЧАЕТ: при коде 0 ищет в выводе проверки
«ПРОПУЩЕНО|ограничение окружения|НЕ ИЗМЕРЕНО|не измерено», печатает
«ПРОПУЩЕНО N из M» и приписку «эти проверки исполнились, но измерить не
смогли — итог о них не говорит ничего».

Но блок `if [ "$skipped" -gt 0 ]` не ставит `fail=1` **ни на одной** из
пятнадцати: прогон всё равно заканчивается нулём, и ворота выпуска, читающие
код выхода `run.sh`, проходят. В парке 50 проверок печатают «НЕ ИЗМЕРЕНО» с
кодом 0 и 52 строят адрес данных из имени каталога репозитория (MOD-220).

Правило (решение линии SEO 28.10)
---------------------------------

* на ПЛОЩАДКЕ, где снимки обязаны быть, `ПРОПУЩЕНО N > 0` — провал;
* на раннере БЕЗ снимков пропуск остаётся пропуском с причиной в выводе.

Площадка отличается от раннера признаком `STAND`, который раннер уже
использует в сверке числа исполнившихся проверок. Новой переменной не
вводится: своя переменная означала бы второй источник правды о том, где идёт
прогон.

Почему нельзя валить везде
--------------------------

Пропуск на раннере без снимков законен: боевых снимков там «нет и быть не
должно» — так сказано в заголовках самих проверок, и восемь проверок
семейства нарочно обёрнуты «код 2 → 0» именно поэтому. Валить без разделения
остановило бы все выпуски.

Чего инструмент не делает
-------------------------

* не правит ни одной проверки и ни одного снимка;
* не вводит новых переменных окружения;
* **отказывает**, если у раннера нет сторожа пропусков вовсе: у
  `yummyani7.info` и `yummyani7.site` `run.sh` в 33 строки без счёта
  пропусков, без поиска текста и без сверки числа исполнившихся проверок.
  Там нужен не этот патч, а сам сторож — отдельная находка, и подменять её
  молчаливым «нечего делать» нельзя.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

ФАЙЛ = "checks/run.sh"

ЯКОРЬ = '''if [ "$skipped" -gt 0 ]; then
  say "checks-measured" "ПРОПУЩЕНО $skipped из $ran"
  printf '    | эти проверки исполнились, но измерить не смогли — итог о них не говорит ничего\\n'
else'''

ЗАМЕНА = '''if [ "$skipped" -gt 0 ]; then
  say "checks-measured" "ПРОПУЩЕНО $skipped из $ran"
  printf '    | эти проверки исполнились, но измерить не смогли — итог о них не говорит ничего\\n'
  # MOD-221: на ПЛОЩАДКЕ пропуск — провал. Снимки здесь обязаны быть, и
  # «ничего не измерено» означает, что ворота выпуска ничего не проверили.
  # На раннере без снимков (STAND не задан) пропуск остаётся пропуском:
  # боевых снимков там нет и быть не должно.
  if [ -n "${STAND:-}" ]; then
    printf '    | STAND задан: снимки обязаны быть, пропуск считается провалом\\n'
    fail=1
  fi
else'''

ПРИЗНАКИ_СТОРОЖА = ('skipped=0', 'НЕ ИЗМЕРЕНО', 'checks-all-ran')


def применить(репо: pathlib.Path, писать: bool) -> tuple[str, str]:
    f = репо / ФАЙЛ
    if not f.is_file():
        return "refuse", f"нет {f}"
    текст = f.read_text(encoding="utf-8")
    нет_признаков = [п for п in ПРИЗНАКИ_СТОРОЖА if п not in текст]
    if нет_признаков:
        return "refuse", ("у раннера нет сторожа пропусков: отсутствуют "
                          f"{', '.join(нет_признаков)}. Здесь нужен сам сторож, "
                          "а не это правило — отдельная находка")
    if 'fail=1' in ЗАМЕНА and ЗАМЕНА in текст:
        return "skip", "правило уже стоит"
    n = текст.count(ЯКОРЬ)
    if n != 1:
        return "refuse", (f"якорь блока пропусков найден {n} раз(а), ожидался 1 — "
                          "раннер отличается от семейного образца")
    if not писать:
        return "ok", "блок пропусков будет валить прогон при заданном STAND"
    f.write_text(текст.replace(ЯКОРЬ, ЗАМЕНА, 1), encoding="utf-8")
    return "ok", "блок пропусков валит прогон при заданном STAND"


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--repo", action="append", required=True)
    р.add_argument("--check", action="store_true")
    р.add_argument("--dry-run", action="store_true")
    а = р.parse_args()
    отказы = правок = 0
    for путь in а.repo:
        репо = pathlib.Path(путь).resolve()
        исход, пояснение = применить(репо, писать=not (а.check or а.dry_run))
        print(f"[{исход:6s}] {репо.name}: {пояснение}")
        if исход == "refuse":
            отказы += 1
        elif исход == "ok":
            правок += 1
    if отказы:
        return 2
    if а.check:
        return 1 if правок else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
