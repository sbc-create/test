#!/usr/bin/env python3
"""MOD-221: где снимки есть, «ничего не измерено» — провал, а не строка в выводе.

    python3 automation/host/apply-skip-is-failure-patch.py \
        --repo var/site-repos/<витрина> [--check] [--dry-run]

Что измерено
------------

Замер 28.10 по `checks/run.sh` всех пятнадцати действующих витрин. Раннер
«ничего не измерено» ЗАМЕЧАЕТ: при коде 0 ищет в выводе проверки
«ПРОПУЩЕНО|ограничение окружения|НЕ ИЗМЕРЕНО|не измерено», печатает
«ПРОПУЩЕНО N из M» и приписку «эти проверки исполнились, но измерить не
смогли — итог о них не говорит ничего».

Но блок `if [ "$skipped" -gt 0 ]` не ставит `fail=1` ни на одной из
пятнадцати: прогон кончается нулём, и ворота выпуска, читающие код выхода
`run.sh`, проходят. В парке 50 проверок печатают «НЕ ИЗМЕРЕНО» с кодом 0 и 52
строят адрес данных из имени каталога репозитория (MOD-220).

Почему признак — не флаг
------------------------

Первая версия правила опиралась на переменную `STAND`. Владелец общего кода
проверила и нашла, что правило было бы МЁРТВЫМ, и я это подтвердил своим
замером: `STAND=` не задаёт НИКТО — ноль совпадений по всем `deploy/*.sh`, по
`factory/` и по `automation/`; `deploy/activate.sh` zona-02 запускает набор как
`( cd "$RELEASE" && SITE_ROOT= bash checks/run.sh )`, а Lords — как
`"$project/checks/run.sh"`, и ни один не задаёт ни `STAND`, ни
`SITE_DATA_DIR`. Правило на флаге, которого никто не ставит, — видимость
защиты: ровно тот класс, который я сам назвал для `yummyani7`.

Поэтому признак — ФАКТ наличия снимков. Раннер спрашивает каталог у
`checks/_snapshot_dir.py`, который ищет его тем же порядком, что проверки
(окружение → `deployment.data_dir` настройки с раскрытием `<root>` → каталог
по домену; имя каталога репозитория адресом данных не считается, MOD-220).
Снимки на месте — пропуск провал. Снимков нет — пропуск остаётся пропуском, и
на раннере CI правило мягкое само собой, без всякой настройки.

`STAND` сохраняется как дополнительный повод: задали вручную — правило тоже
действует.

Чего инструмент не делает: не правит ни одной проверки, ни одного снимка, ни
`activate.sh`; не вводит новых переменных окружения; **отказывает**, если у
раннера нет сторожа пропусков вовсе (у `yummyani7.info` и `yummyani7.site`
`run.sh` в 33 строки — там нужен сам сторож, а не правило о нём, MOD-222).
"""
from __future__ import annotations

import argparse
import pathlib
import shutil
import sys

ФАЙЛ = "checks/run.sh"
РЕЗОЛВЕР = "checks/_snapshot_dir.py"
ИСТОЧНИК_РЕЗОЛВЕРА = (pathlib.Path(__file__).resolve().parent
                      / "lords-checks" / "_snapshot_dir.py")

ЯКОРЬ = '''if [ "$skipped" -gt 0 ]; then
  say "checks-measured" "ПРОПУЩЕНО $skipped из $ran"
  printf '    | эти проверки исполнились, но измерить не смогли — итог о них не говорит ничего\\n'
else'''

ЗАМЕНА = '''if [ "$skipped" -gt 0 ]; then
  say "checks-measured" "ПРОПУЩЕНО $skipped из $ran"
  printf '    | эти проверки исполнились, но измерить не смогли — итог о них не говорит ничего\\n'
  # MOD-221: где снимки ЕСТЬ, пропуск — провал: «ничего не измерено» означает,
  # что ворота выпуска ничего не проверили. Признак — не флаг, а факт: STAND
  # не задаёт никто (измерено 28.10 по deploy/*.sh, factory/ и automation/),
  # и правило на таком флаге было бы мёртвым. Каталог ищет
  # checks/_snapshot_dir.py тем же порядком, что проверки. Имя переменной
  # ASCII: в наборе витрины есть своя проверка shell-ascii-names, и
  # «_снимки=» bash разобрал бы как команду (измерено: код 127).
  snap_dir="$(python3 checks/_snapshot_dir.py 2>/dev/null || true)"
  if [ -n "$snap_dir" ]; then
    printf '    | снимки на месте (%s): пропуск считается провалом\\n' "$snap_dir"
    fail=1
  elif [ -n "${STAND:-}" ]; then
    printf '    | STAND задан: пропуск считается провалом\\n'
    fail=1
  else
    printf '    | снимков нет и STAND не задан: пропуск остаётся пропуском\\n'
  fi
else'''

ПРИЗНАКИ_СТОРОЖА = ("skipped=0", "НЕ ИЗМЕРЕНО", "checks-all-ran")


def применить(репо: pathlib.Path, писать: bool) -> tuple[str, str]:
    if not ИСТОЧНИК_РЕЗОЛВЕРА.is_file():
        return "refuse", f"нет источника резолвера {ИСТОЧНИК_РЕЗОЛВЕРА}"
    f = репо / ФАЙЛ
    if not f.is_file():
        return "refuse", f"нет {f}"
    текст = f.read_text(encoding="utf-8")
    нет_признаков = [п for п in ПРИЗНАКИ_СТОРОЖА if п not in текст]
    if нет_признаков:
        return "refuse", ("у раннера нет сторожа пропусков: отсутствуют "
                          f"{', '.join(нет_признаков)}. Здесь нужен сам сторож, "
                          "а не это правило — MOD-222")

    цель_резолвера = репо / РЕЗОЛВЕР
    резолвер_на_месте = (цель_резолвера.is_file()
                         and цель_резолвера.read_bytes()
                         == ИСТОЧНИК_РЕЗОЛВЕРА.read_bytes())
    правило_на_месте = ЗАМЕНА in текст
    if резолвер_на_месте and правило_на_месте:
        return "skip", "правило и резолвер уже стоят"

    if not правило_на_месте:
        n = текст.count(ЯКОРЬ)
        if n != 1:
            return "refuse", (f"якорь блока пропусков найден {n} раз(а), "
                              "ожидался 1 — раннер отличается от образца")

    что = []
    if not резолвер_на_месте:
        что.append(РЕЗОЛВЕР)
    if not правило_на_месте:
        что.append("правило в " + ФАЙЛ)
    if not писать:
        return "ok", ("будет сделано: " + ", ".join(что)
                      + "; пропуск станет провалом там, где снимки есть")

    if not резолвер_на_месте:
        shutil.copyfile(ИСТОЧНИК_РЕЗОЛВЕРА, цель_резолвера)
    if not правило_на_месте:
        f.write_text(текст.replace(ЯКОРЬ, ЗАМЕНА, 1), encoding="utf-8")
    return "ok", ("сделано: " + ", ".join(что)
                  + "; пропуск стал провалом там, где снимки есть")


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--repo", action="append", required=True)
    р.add_argument("--check", action="store_true")
    р.add_argument("--dry-run", action="store_true")
    а = р.parse_args()
    отказы = правок = 0
    for путь in а.repo:
        репо = pathlib.Path(путь).resolve()
        исход, пояснение = применить(репо, писать=not (а.check or а.dry_run))
        print(f"[{исход:6s}] {репо.name}: {пояснение}")
        if исход == "refuse":
            отказы += 1
        elif исход == "ok":
            правок += 1
    if отказы:
        return 2
    if а.check:
        return 1 if правок else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
