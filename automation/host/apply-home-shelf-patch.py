#!/usr/bin/env python3
"""Полка главной из редакционной подборки вместо каталожной выборки по дате.

ПОВОД, измеренный 27.10 на живой главной `animedia.icu` инструментом
`automation/local/home-blocks-survey.py`: «Аниме-фильмы» и «Новые аниме на
сайте» совпадали на 92% (11 работ из 12), «Короткие сериалы» и «Новые» — на
50% (6 из 12). Это не совпадение вкусов: у каталожных спецификаций
`anime_movies` и `short_series` порядок `published_at desc` — ровно та же
величина, по которой строится нижняя сетка каталога. Три блока отвечали на
один и тот же вопрос «что недавно появилось», и два из них были лишними.

ЧТО ДЕЛАЕТ. Вводит поле `home_shelf` у ручной подборки — по образцу уже
работающего `home_rail`. Подборка, помеченная ключом полки, становится
ИСТОЧНИКОМ состава этой полки: первые её работы в объявленном редакцией
порядке, заголовок — её собственный, ссылка «все» — на её страницу.
Каталожная выборка остаётся запасным путём: витрина без такой пометки
собирает главную как прежде.

ПОЧЕМУ ЗАГОЛОВОК БЕРЁТСЯ У ПОДБОРКИ, а не задаётся отдельно. Сегодня же
разбирался случай, когда полка и её полная страница назывались по-разному
(«Сериалы с сериями» против раздела): два имени одного и того же расходятся
при первой же правке. Имя одно — то, которое дала подборке редакция.

ЧЕГО НЕ ДЕЛАЕТ. Не трогает каталожные страницы `/collection/anime_movies/` и
`/collection/short_series/`: они остаются выборками каталога и отвечают за
себя. Не меняет порядок блоков главной. Не правит состав — состав
принадлежит линии, которая его собирает.

    python3 automation/host/apply-home-shelf-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

# --- контракт: поле у ручной подборки ---------------------------------------

ПОЛЕ_БЫЛО = '''    #: Дата последнего пересмотра состава (YYYY-MM-DD): у промежуточной
    #: подборки она обязана быть видна читателю.
    updated: str = ""'''
ПОЛЕ_СТАЛО = '''    #: Ключ полки главной, состав которой берётся из ЭТОЙ подборки вместо
    #: каталожной выборки. Поле по образцу `home_rail` и так же
    #: необязательное. Повод измерен 27.10: каталожные полки «Аниме-фильмы» и
    #: «Короткие сериалы» повторяли нижнюю сетку «Новые аниме на сайте» на 92%
    #: и 50%, потому что у всех трёх порядок `published_at desc`. Подборка с
    #: этой пометкой отвечает на свой вопрос, а не повторяет свежесть каталога.
    home_shelf: str = ""
    #: Дата последнего пересмотра состава (YYYY-MM-DD): у промежуточной
    #: подборки она обязана быть видна читателю.
    updated: str = ""'''

РАЗБОР_БЫЛО = '''            home_rail=bool(с.get("home_rail")),'''
РАЗБОР_СТАЛО = '''            home_rail=bool(с.get("home_rail")),
            home_shelf=str(с.get("home_shelf") or ""),'''

# --- рантайм: источник состава полки ----------------------------------------

ПОЛКА_БЫЛО = '''                коллекция = КОЛЛЕКЦИИ.разрешить(ключ, снимок, СЕМЕЙСТВО, предел=48)
                if коллекция is None or not коллекция.items:
                    continue'''
ПОЛКА_СТАЛО = '''                # Полка из редакционной подборки, если такая помечена этим
                # ключом. Измерено 27.10: каталожная «Аниме-фильмы» совпадала
                # с нижней сеткой «Новые аниме на сайте» на 92% (11 работ из
                # 12), «Короткие сериалы» — на 50%. Причина одна: у всех трёх
                # порядок `published_at desc`. Состав, собранный редакцией,
                # отвечает на свой вопрос, а не повторяет свежесть каталога.
                #
                # Заголовок и ссылка «все» берутся у подборки: два имени
                # одного и того же расходятся при первой правке, и сегодня же
                # такой случай разбирался отдельно.
                ручная = next((п for п in РУЧНЫЕ_ПОДБОРКИ.values()
                               if getattr(п, "home_shelf", "") == ключ), None)
                if ручная is not None:
                    состав_полки = КОЛЛЕКЦИИ.разрешить_ручную(ручная, снимок)
                    записи = [с.get("запись") for с in состав_полки.get("works") or []]
                    записи = [з for з in записи if з]
                    if записи:
                        ленты.append((ключ.replace("_", "-"), ручная.title,
                                      ручная.canonical_path, записи[:48], ""))
                        continue
                    # Пустой состав — не повод подставить каталожную выборку:
                    # редакция объявила эту полку своей, и молчаливая подмена
                    # выдала бы выборку по дате за её решение.
                    continue
                коллекция = КОЛЛЕКЦИИ.разрешить(ключ, снимок, СЕМЕЙСТВО, предел=48)
                if коллекция is None or not коллекция.items:
                    continue'''

#: имя, было, стало, признак применённости, требование к файлу
ТРЕБУЕТ_КОНТРАКТА = "class РучнаяПодборка"
ТРЕБУЕТ_ГЛАВНОЙ = "КОЛЛЕКЦИИ.разрешить(ключ, снимок, СЕМЕЙСТВО"
ПАРЫ = (
    ("поле home_shelf", ПОЛЕ_БЫЛО, ПОЛЕ_СТАЛО, "home_shelf: str = \"\"",
     ТРЕБУЕТ_КОНТРАКТА),
    ("разбор home_shelf", РАЗБОР_БЫЛО, РАЗБОР_СТАЛО,
     'home_shelf=str(с.get("home_shelf") or "")', ТРЕБУЕТ_КОНТРАКТА),
    ("полка из подборки", ПОЛКА_БЫЛО, ПОЛКА_СТАЛО,
     'getattr(п, "home_shelf", "") == ключ', ТРЕБУЕТ_ГЛАВНОЙ),
)


def уместна(пара: tuple, текст: str) -> bool:
    _, было, _, признак, требование = пара
    if требование not in текст:
        return False
    return было in текст or признак in текст


def остатки(текст: str) -> list:
    return [f"нет: {п[0]}" for п in ПАРЫ if уместна(п, текст) and п[3] not in текст]


def применить(текст: str) -> tuple[str, list]:
    журнал, затронуто = [], 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if требование not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
        затронуто += 1
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if not [п for п in ПАРЫ if уместна(п, исходный)]:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
