"""ОБЩИЙ ИСТОЧНИК читателя режима индексации для семейства Lords/Zona.

Источник шаблона, а не копия сайта: новый сайт получает его через
`factory.cell.newsite`, существующий — обычным выпуском.

Модуль перенесён из `var/site-repos/animedia-space/src/indexing_mode.py`, где
он выпущен и проверен перечислением fail-closed случаев и отдачей настоящей
витрины в обоих режимах. Смысл не менялся; отличие одно — имена переменных
окружения семейства (`LORDS_INDEXING_ROOT`, `LORDS_INDEXING_TTL`) с
совместимостью по прежним именам Animedia, чтобы один и тот же модуль годился
обоим семействам и не разошёлся на две реализации.

Главное свойство, ради которого он здесь: ЗАКРЫТО ПО УМОЛЧАНИЮ. Домены этого
семейства сейчас закрыты, и подключение читателя обязано оставить их
закрытыми — иначе выпуск сам изменил бы режим действующего домена, чего делать
нельзя.
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path

ОТКРЫТ = "OPEN"
ЗАКРЫТ = "CLOSED"

#: Корень файлов состояния. Один файл на домен, имя файла — сам домен: так
#: запись одного сайта физически не может задеть другой.
КОРЕНЬ = os.environ.get("LORDS_INDEXING_ROOT",
                   os.environ.get("ANIMEDIA_INDEXING_ROOT",
                                  "/srv/sites/indexing"))

СХЕМА = 1

#: Как часто переспрашивать файл. Режим нужен каждой странице, а `stat` на
#: запрос — лишняя системная работа там, где значение меняется раз в месяцы.
#: Пять секунд: задержка переключения незаметна, стоимость нулевая.
ОКНО_КЭША_С = float(os.environ.get("LORDS_INDEXING_TTL",
                               os.environ.get("ANIMEDIA_INDEXING_TTL", "5")))

_кэш: dict = {"до": 0.0, "примета": None, "решение": None}


def путь(домен: str, *, корень: str | os.PathLike[str] | None = None) -> Path:
    return Path(корень or КОРЕНЬ) / f"{домен}.json"


def _примета(п: Path) -> tuple:
    try:
        с = п.stat()
    except OSError:
        return ("нет",)
    return (с.st_mtime_ns, с.st_size)


def _прочитать(п: Path) -> tuple[dict | None, str]:
    try:
        сырое = json.loads(п.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None, f"файла состояния нет: {п}"
    except OSError as ош:
        return None, f"файл состояния не читается: {type(ош).__name__}"
    except ValueError:
        return None, "файл состояния не разбирается как JSON"
    if not isinstance(сырое, dict):
        return None, "файл состояния не объект"
    return сырое, ""


def решить(домен: str, *, разрешено_выпуском, корень=None) -> tuple[str, str]:
    """(режим, причина). Причина пуста только у открытого режима.

    `разрешено_выпуском` приходит из `config/site.json` выпуска. Тип проверяется
    строго: разрешением считается булево `True` и ничего больше.
    """
    if not домен:
        return ЗАКРЫТ, "домен витрины неизвестен: решать не о чем"
    if разрешено_выпуском is not True:
        return ЗАКРЫТ, (
            "выпуск не разрешает открытие: config/site.json "
            f"indexing.release_permits_open = {разрешено_выпуском!r}, "
            "а разрешением считается только булево true")
    п = путь(домен, корень=корень)
    сырое, беда = _прочитать(п)
    if сырое is None:
        return ЗАКРЫТ, беда
    if int(сырое.get("schema_version") or 0) != СХЕМА:
        return ЗАКРЫТ, (
            f"версия схемы файла состояния {сырое.get('schema_version')!r}, "
            f"ожидается {СХЕМА}")
    чей = str(сырое.get("site") or "").strip().lower()
    if чей != домен.strip().lower():
        return ЗАКРЫТ, (
            f"файл состояния принадлежит сайту {чей!r}, а читает его {домен!r}: "
            "чужое состояние не применяется")
    состояние = str(сырое.get("desired_state") or "").strip().upper()
    if состояние == ОТКРЫТ:
        return ОТКРЫТ, ""
    if состояние == ЗАКРЫТ:
        return ЗАКРЫТ, "файл состояния: CLOSED"
    return ЗАКРЫТ, (
        f"неизвестное desired_state {сырое.get('desired_state')!r}: "
        "открывает только строка OPEN")


def режим(домен: str, *, разрешено_выпуском, корень=None) -> tuple[str, str]:
    """То же, что `решить`, но с коротким кэшем по времени файла."""
    сейчас = time.monotonic()
    п = путь(домен, корень=корень)
    примета = _примета(п)
    годен = (_кэш["решение"] is not None
             and сейчас < _кэш["до"]
             and _кэш["примета"] == примета)
    if годен:
        return _кэш["решение"]
    решение = решить(домен, разрешено_выпуском=разрешено_выпуском, корень=корень)
    _кэш.update({"до": сейчас + ОКНО_КЭША_С, "примета": примета,
                 "решение": решение})
    return решение


def сбросить_кэш() -> None:
    """Для проверок: следующий вопрос пойдёт на диск."""
    _кэш.update({"до": 0.0, "примета": None, "решение": None})


# --------------------------------------------------------------- сигналы

#: Значение `<meta name="robots">` и `X-Robots-Tag` в каждом из режимов.
МЕТА = {ОТКРЫТ: "index, follow", ЗАКРЫТ: "noindex, nofollow"}

#: Тело `/robots.txt`. В открытом режиме обход разрешён целиком, кроме
#: служебных путей: они закрыты НАМЕРЕННО и открытием сайта не затрагиваются.
#: `/poster/` — картинки витрины, их обход стоит ей дорого и смысла не имеет;
#: `/api/` и `/healthz` — служебные ответы; маркер Яндекс.Вебмастера — файл
#: подтверждения прав, а не страница.
СЛУЖЕБНЫЕ_ЗАПРЕТЫ = ("/poster/", "/api/", "/healthz", "/__")

ЗАКРЫТЫЙ_ROBOTS = "User-agent: *\nDisallow: /\n"


def robots_txt(состояние: str, *, sitemap: str = "") -> str:
    if состояние != ОТКРЫТ:
        return ЗАКРЫТЫЙ_ROBOTS
    строки = ["User-agent: *"]
    строки += [f"Disallow: {п}" for п in СЛУЖЕБНЫЕ_ЗАПРЕТЫ]
    строки.append("Allow: /")
    if sitemap:
        строки.append(f"Sitemap: {sitemap}")
    return "\n".join(строки) + "\n"
