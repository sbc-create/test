#!/usr/bin/env python3
"""Фоновое согласование доступности серий со свежим ответом провайдера.

Живёт рядом с рантаймом витрины и запускается им одним потоком. Ни в одном
пути запроса страницы согласование не участвует: синхронный вызов провайдера
при отрисовке означал бы, что страница ждёт чужую службу — соседняя витрина
ровно на этом и легла.

Зачем оно нужно
---------------

Снимок подробностей собирает суточный конвейер, и у сезона в нём ОДНО число
`avail` — «сколько серий доступно». Страница раньше читала его как «номер
последней доступной». Пока нумерация идёт подряд с единицы, два числа
совпадают; на спецвыпуске с номером 0 и на пропусках они расходятся:

* `/title/skotty/` («Скотты», `01a0e27f-8175-7115-8972-83cce31b15d3`): у
  провайдера РОВНО ОДНА дорожка — season 1, episode 0. Снимок объявлял
  `avail=1, eps=6`, витрина монтировала `<video-player episode="1">`, и
  провайдер отвечал на неё noData;
* `/title/master-omyur/` («Мастер Омюр»): снимок объявлял `avail=0` при живой
  дорожке s1e1 — данные просто отстали на сутки.

Поэтому сюда записывается ПЕРЕЧЕНЬ номеров `nums` — то, что рендерер читает
через `доступные_номера`. Поле `avail` не трогается: им владеет конвейер, и
править его отсюда значило бы спорить с доставкой каждый день.

Что отличает подтверждённое отсутствие от неудачи запроса
---------------------------------------------------------

`nums` записывается ТОЛЬКО для сезонов, которые провайдер вернул непустыми.

* провайдер не ответил (сеть, таймаут, 5xx) — не записывается ничего, прежнее
  состояние остаётся;
* провайдер ответил, но этого сезона в ответе нет — сезон не трогается: это
  либо расхождение нумерации, либо неполный ответ, и доказательством
  отсутствия он не является;
* провайдер ответил непустым перечнем — он и записывается целиком, в том числе
  когда дорожек стало МЕНЬШЕ. Метод отдаёт список без постраничности
  (проверено на «Ван-Пис», 3541 дорожка), поэтому непустой ответ по сезону —
  полное описание сезона, а не его начало.

Отметка `nums_at` говорит, КОГДА перечень получен. Без неё «ещё не спрашивали»
и «спрашивали, дорожек нет» выглядели бы одинаково.

Нагрузка
--------

Круг идёт по ВСЕМ сериалам каталога, а не только по растущим: у записи с полным
`avail` ложным может оказаться само обещание, как у «Скоттов». Порядок
трёхслойный — сначала полный недобор, затем растущие, затем остальные, — и
позиция круга лежит на диске: без неё первые сорок записей спрашивались бы
каждые пятнадцать минут, а пятьсот третья — никогда.

Бюджет по умолчанию — 40 записей раз в 15 минут, около 3800 запросов в сутки с
витрины. Полный круг по 20 556 сериалам — примерно пять с половиной суток. Это
оценка, а не догадка: витрин с одним каталогом восемь, и суммарная частота по
семейству держится около трети запроса в секунду.
"""
from __future__ import annotations

import json
import os
import threading
import time
import urllib.parse
import urllib.request
from pathlib import Path

#: Тот же адрес, который открывает SDK провайдера на странице у посетителя.
#: Другого источника правды о наличии дорожки у витрины нет.
ПЛЕЙЛИСТ = "https://plapi.cdnvideohub.com/api/v1/player/sv/playlist"

ЗА_ПРОХОД = int(os.environ.get("LORDS_AVAIL_BATCH", "40"))
ПАУЗА_С = int(os.environ.get("LORDS_AVAIL_PERIOD", "900"))
ТАЙМАУТ_С = float(os.environ.get("LORDS_AVAIL_TIMEOUT", "12"))
#: Пауза между записями внутри прохода. Ровно она и держит частоту.
ШАГ_С = float(os.environ.get("LORDS_AVAIL_STEP", "1.0"))
#: Сколько запасных кандидатов спрашивать. Столько же перебирает страница.
ЗАПАСНЫХ = 3


def _плейлист(издатель: str, агрегатор: str, ид: str, домен: str) -> dict | None:
    """Ответ источника по одной записи. Отказ — None, а не исключение."""
    if not (издатель and ид and агрегатор):
        return None
    адрес = f"{ПЛЕЙЛИСТ}?" + urllib.parse.urlencode(
        {"pub": издатель, "id": ид, "aggr": агрегатор})
    запрос = urllib.request.Request(адрес, headers={
        "Accept": "application/json",
        "Origin": f"https://{домен}",
        "x-origin": f"https://{домен}",
        "Referer": f"https://{домен}/",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ_С) as ответ:
            return json.loads(ответ.read(8_000_000).decode("utf-8", "replace"))
    except Exception:  # noqa: BLE001 — недоступность источника не роняет витрину
        return None


def серии_по_сезонам(ответ: dict) -> dict:
    """Номера серий с НАСТОЯЩЕЙ дорожкой, по сезонам.

    Дорожкой считается запись с идентификатором потока, а не заготовка с одним
    названием: пустая позиция означает «озвучка заявлена», а не «включается».
    Ноль — допустимый номер серии, и отбрасывать его здесь нельзя: у «Скоттов»
    это единственная дорожка записи.
    """
    по_сезонам: dict[int, set] = {}
    for д in (ответ.get("items") or []):
        if not isinstance(д, dict):
            continue
        if not (str(д.get("cvhId") or "").strip() or str(д.get("vkId") or "").strip()):
            continue
        try:
            с, э = int(д.get("season") or 0), int(д.get("episode"))
        except (TypeError, ValueError):
            continue
        if с >= 1 and э >= 0:
            по_сезонам.setdefault(с, set()).add(э)
    return по_сезонам


def согласовать(деталь: dict, найдено: dict, отметка: str) -> bool:
    """Записать перечень номеров в сезоны, которые провайдер вернул непустыми."""
    изменилось = False
    for сезон in (деталь.get("seasons") or []):
        if not isinstance(сезон, dict):
            continue
        номера = найдено.get(int(сезон.get("n") or 0))
        if not номера:
            continue
        новое = sorted(номера)
        if сезон.get("nums") != новое:
            сезон["nums"] = новое
            изменилось = True
        сезон["nums_at"] = отметка
    return изменилось


def очередь(записи: dict) -> list:
    """Кого спрашивать и в каком порядке. Порядок словаря здесь не годится.

    Первыми — записи с ПОЛНЫМ недобором: у них витрина не показывает ничего,
    хотя сезон заявлен, и это и есть жалоба посетителя. Затем растущие. Затем
    остальные сериалы: у записи с полным `avail` ложным бывает само обещание.
    Внутри групп по алфавиту, чтобы проход был воспроизводим.
    """
    полные, растущие, прочие = [], [], []
    for слаг, деталь in sorted((записи or {}).items()):
        if not isinstance(деталь, dict):
            continue
        сезоны = [с for с in (деталь.get("seasons") or []) if isinstance(с, dict)]
        сезоны = [с for с in сезоны if int(с.get("eps") or 0) >= 1]
        if not сезоны:
            continue
        недобор = [с for с in сезоны
                   if int(с.get("avail") or 0) < int(с.get("eps") or 0)]
        if недобор and any(int(с.get("avail") or 0) == 0 for с in недобор):
            полные.append(слаг)
        elif недобор:
            растущие.append(слаг)
        else:
            прочие.append(слаг)
    return полные + растущие + прочие


class Согласование:
    """Один проход, позиция круга и запись снимка."""

    def __init__(self, рантайм, *, домен: str, каталог_позиции: Path) -> None:
        self.рантайм = рантайм
        self.домен = домен
        self.позиция_файл = каталог_позиции
        self.позиция = self._прочитать_позицию()

    def _прочитать_позицию(self) -> str:
        try:
            return str(json.loads(self.позиция_файл.read_text(
                encoding="utf-8")).get("после") or "")
        except (OSError, ValueError):
            return ""

    def _записать_позицию(self) -> None:
        try:
            врем = self.позиция_файл.with_suffix(".tmp")
            врем.write_text(json.dumps(
                {"после": self.позиция,
                 "в": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())},
                ensure_ascii=False), encoding="utf-8")
            os.replace(врем, self.позиция_файл)
        except OSError:
            pass

    def проход(self, подробности) -> dict:
        издатель = str(self.рантайм.ПЛЕЕР.get("publisher_id") or "")
        записи = подробности.записи or {}
        список = очередь(записи)
        if not список or not издатель:
            return {"кандидатов": 0, "спрошено": 0, "согласовано": 0,
                    "записано": False}
        начало = (список.index(self.позиция) + 1
                  if self.позиция in список else 0)
        кольцо = список[начало:] + список[:начало]
        отметка = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        спрошено = согласовано = отказов = 0
        for слаг in кольцо[:ЗА_ПРОХОД]:
            деталь = записи.get(слаг)
            if not isinstance(деталь, dict):
                continue
            self.позиция = слаг
            спрошено += 1
            найдено: dict[int, set] = {}
            for агрегатор, ид in self.рантайм.кандидаты_источника(деталь)[:ЗАПАСНЫХ + 1]:
                ответ = _плейлист(издатель, агрегатор, ид, self.домен)
                if ответ is None:
                    отказов += 1
                    continue
                найдено = серии_по_сезонам(ответ)
                if найдено:
                    break
            if найдено and согласовать(деталь, найдено, отметка):
                согласовано += 1
            time.sleep(ШАГ_С)
        записано = self._сохранить(подробности) if согласовано else False
        self._записать_позицию()
        return {"кандидатов": len(список), "спрошено": спрошено,
                "согласовано": согласовано, "отказов_запроса": отказов,
                "записано": записано, "позиция": self.позиция}

    def _сохранить(self, подробности) -> bool:
        """Запись через временный файл. Свежую доставку не затираем."""
        путь = getattr(подробности, "path", "") or ""
        if not путь:
            return False
        цель = Path(путь)
        try:
            # Файл перечитывается ПЕРЕД записью: доставка могла привезти новый
            # снимок, пока шёл проход. Писать свой словарь поверх, не
            # посмотрев, значило бы вернуть на сайт данные, которые только что
            # заменили.
            if цель.stat().st_mtime > (getattr(подробности, "mtime", 0.0) or 0.0):
                return False
            сырое = json.loads(цель.read_text(encoding="utf-8"))
            сырое["details"] = подробности.записи
            врем = цель.with_suffix(цель.suffix + ".nums.tmp")
            врем.write_text(json.dumps(сырое, ensure_ascii=False), encoding="utf-8")
            os.replace(врем, цель)
            подробности.mtime = цель.stat().st_mtime
            return True
        except (OSError, ValueError):
            return False


def _цикл(рантайм, домен: str, позиция: Path) -> None:
    time.sleep(20)                      # дать витрине подняться и ответить
    согласование = Согласование(рантайм, домен=домен, каталог_позиции=позиция)
    прежний = None
    while True:
        try:
            подробности = getattr(рантайм.Обработчик, "подробности", None)
            if подробности is None:
                time.sleep(ПАУЗА_С)
                continue
            # Объект берётся у обработчика КАЖДЫЙ проход: витрина подменяет его
            # целиком при новом снимке, и поток с прежней ссылкой правил бы
            # отсоединённый словарь, а потом записал его поверх свежего.
            метка = id(подробности)
            if прежний is not None and метка != прежний:
                print("[nova] согласование: снимок сменился", flush=True)
            прежний = метка
            итог = согласование.проход(подробности)
            if итог.get("согласовано"):
                print(f"[nova] согласование доступности: {итог}", flush=True)
        except Exception as ош:  # noqa: BLE001 — фон не роняет витрину
            print(f"[nova] согласование отказало: {ош!r}", flush=True)
        time.sleep(ПАУЗА_С)


def запустить(рантайм) -> bool:
    """Завести поток согласования. False — если заводить нечего или нечем.

    Условия жёсткие намеренно: без канонического домена запрос уйдёт с чужим
    Origin, без publisher спрашивать нечем, а в режиме `external-ids` страница
    знает единственный ключ, и спрашивать по остальным значило бы судить о
    доступности по источнику, которого на странице не будет.
    """
    домен = (os.environ.get("LORDS_SITE_HOST")
             or os.environ.get("ANIMEDIA_SITE_HOST")
             or os.environ.get("ANIMEGO_SITE_HOST") or "").strip()
    плеер = getattr(рантайм, "ПЛЕЕР", {}) or {}
    if not домен or not плеер.get("publisher_id"):
        return False
    if плеер.get("source_mode") != "provider-id":
        return False
    подробности = getattr(рантайм.Обработчик, "подробности", None)
    путь = Path(getattr(подробности, "path", "") or "")
    if not путь.name:
        return False
    позиция = путь.with_name(f".{путь.stem}-avail-ring.json")
    threading.Thread(target=_цикл, args=(рантайм, домен, позиция),
                     name="avail-sync", daemon=True).start()
    return True
