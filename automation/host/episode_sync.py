#!/usr/bin/env python3
"""Фоновое согласование доступности серий со свежим ответом провайдера.

Живёт рядом с рантаймом витрины и запускается им одним потоком. Ни в одном
пути запроса страницы согласование не участвует: синхронный вызов провайдера
при отрисовке означал бы, что страница ждёт чужую службу.

Зачем оно нужно
---------------

Снимок подробностей собирает суточный конвейер, и у сезона в нём ОДНО число
`avail` — «сколько серий доступно». Страница раньше читала его как «номер
последней доступной». Пока нумерация идёт подряд с единицы, два числа
совпадают; на спецвыпуске с номером 0 и на пропусках они расходятся:

* `/title/skotty/` («Скотты», `01a0e27f-8175-7115-8972-83cce31b15d3`): у
  провайдера РОВНО ОДНА дорожка — season 1, episode 0. Снимок объявлял
  `avail=1, eps=6`, витрина монтировала `<video-player episode="1">`, и
  провайдер отвечал на неё noData;
* `/title/master-omyur/` («Мастер Омюр»): снимок объявлял `avail=0` при живой
  дорожке s1e1 — данные просто отстали на сутки.

Куда пишется результат
----------------------

В ОТДЕЛЬНЫЙ файл `<site>-details.nums.json` рядом со снимком, а не в сам
снимок. Это не деталь реализации, а исправление отдельного дефекта.

Измерено 2026-09-29: суточная доставка привозит снимок производителя, в
котором `nums` нет вовсе (проверено — ноль сезонов с перечнем), и заменяет им
файл ячейки целиком. Всё, что согласование восстановило за сутки, стиралось
каждую ночь, и круг начинался заново: у lords-05 после доставки 03:17Z от
132 сезонов с перечнем не осталось ни одного, а `/title/boec-baki/` снова
отвечал 404 на серию, которая накануне играла.

Наложение принадлежит ЯЧЕЙКЕ, снимок — конвейеру. Доставка заменяет снимок и
наложения не касается; рантайм накладывает его при чтении снимка. Побочно
исчезла и вторая беда: перезапись 76-мегабайтного файла каждые пятнадцать
минут, из-за которой проверка «файл новее нашего чтения» после доставки
запрещала запись НАВСЕГДА — до перезапуска службы.

Что отличает подтверждённое отсутствие от неудачи запроса
---------------------------------------------------------

`nums` записывается ТОЛЬКО для сезонов, которые провайдер вернул непустыми.

* провайдер не ответил (сеть, таймаут, 5xx) — не записывается ничего, прежнее
  состояние остаётся;
* провайдер ответил, но этого сезона в ответе нет — сезон не трогается: это
  либо расхождение нумерации, либо неполный ответ, и доказательством
  отсутствия он не является;
* провайдер ответил непустым перечнем — он и записывается целиком, в том числе
  когда дорожек стало МЕНЬШЕ. Метод отдаёт список без постраничности
  (проверено на «Ван-Пис», 3541 дорожка), поэтому непустой ответ по сезону —
  полное описание сезона, а не его начало.

Отметка `at` говорит, КОГДА перечень получен. Без неё «ещё не спрашивали» и
«спрашивали, дорожек нет» выглядели бы одинаково.

Очередь: почему не один круг
----------------------------

Один общий круг по двадцати тысячам сериалов при бюджете 40 записей в
пятнадцать минут идёт пять с половиной суток. Для новой серии онгоинга это не
срок: она выходит сегодня, а витрина узнаёт о ней через неделю.

Поэтому очередь слоями, и каждый слой отвечает на свой вопрос:

  0. названные        — записи из жалоб владельца (`LORDS_AVAIL_URGENT`).
                        Спрашиваются каждый проход: суточная доставка
                        возвращает снимок без перечня, и без этого слоя
                        названная запись ждала бы полного круга.
  1. изменённые       — состав сезонов РАЗОШЁЛСЯ с тем, что согласование
                        видело в прошлый раз (`eps` или `avail` другие).
                        Конвейер меняет эти числа именно тогда, когда у
                        произведения что-то произошло, — это самый точный
                        локальный признак «здесь появилась серия».
  2. онгоинги         — сезон с недобором у свежего произведения (год не
                        старше прошлого). Тут серии выходят прямо сейчас.
  3. растущие прочие  — остальной недобор.
  4. полный обход     — все сериалы подряд, курсором. Нужен потому, что у
                        записи с ПОЛНЫМ `avail` ложным бывает само обещание:
                        так было у «Скоттов», и никакой признак недобора её
                        бы не выдал.

Слои 0–3 не съедают обход целиком: доля слоя 4 в каждом проходе гарантирована
(`LORDS_AVAIL_SWEEP_SHARE`, по умолчанию пятая часть бюджета). Иначе хвост
каталога не спрашивался бы никогда.

Задержка измеряется, а не обещается: у каждой записи, чей состав изменился,
считается `лаг` — сколько прошло от сборки снимка до того, как согласование
её спросило. Значения пишутся в отчёт `<site>-episode-sync.json`.

Нагрузка
--------

Бюджет по умолчанию — 40 записей раз в 15 минут, около 3800 запросов в сутки с
витрины. Витрин девять, поставщик у них один; суммарно это около 0.4 запроса в
секунду. Слои 1–3 обычно короткие (десятки записей), поэтому основной расход —
это тот же полный обход, только теперь он идёт ПОСЛЕ срочного, а не вместо.
"""
from __future__ import annotations

import json
import os
import threading
import time
import urllib.parse
import urllib.request
from pathlib import Path

#: Тот же адрес, который открывает SDK провайдера на странице у посетителя.
ПЛЕЙЛИСТ = "https://plapi.cdnvideohub.com/api/v1/player/sv/playlist"

ЗА_ПРОХОД = int(os.environ.get("LORDS_AVAIL_BATCH", "40"))
ПАУЗА_С = int(os.environ.get("LORDS_AVAIL_PERIOD", "900"))
ТАЙМАУТ_С = float(os.environ.get("LORDS_AVAIL_TIMEOUT", "12"))
#: Пауза между записями внутри прохода. Ровно она и держит частоту.
ШАГ_С = float(os.environ.get("LORDS_AVAIL_STEP", "1.0"))
#: Сколько запасных кандидатов спрашивать. Столько же перебирает страница.
ЗАПАСНЫХ = 3
#: Доли прохода по слоям. Замерено на живом каталоге lords-02 2026-09-29:
#: онгоингов 257, растущих 387, прочих 20 140. При бюджете 40 записей в
#: пятнадцать минут это даёт круг по онгоингам примерно за четыре часа, по
#: растущим — за двенадцать, полный обход — за тринадцать суток.
#:
#: Слой «изменённые» доли не имеет и берётся ЦЕЛИКОМ: его наполняет суточная
#: доставка, он короткий, и именно он отвечает за своевременность — запись,
#: у которой конвейер сдвинул `eps`/`avail`, спрашивается в ближайшем проходе,
#: то есть не позже пятнадцати минут после доставки.
ДОЛЯ_ОНГОИНГОВ = float(os.environ.get("LORDS_AVAIL_ONGOING_SHARE", "0.4"))
ДОЛЯ_РАСТУЩИХ = float(os.environ.get("LORDS_AVAIL_GROWING_SHARE", "0.2"))
ДОЛЯ_ОБХОДА = float(os.environ.get("LORDS_AVAIL_SWEEP_SHARE", "0.4"))
#: Схема файла наложения. Меняется вместе с его разбором.
СХЕМА_НАЛОЖЕНИЯ = "nova.episode-nums/1"


# --------------------------------------------------------------- наложение

def путь_наложения(снимок: Path) -> Path:
    """`<site>-details.json` → `<site>-details.nums.json`, рядом."""
    return снимок.with_suffix(".nums.json")


def прочитать_наложение(путь: Path) -> dict:
    try:
        d = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(d, dict) or d.get("schema") != СХЕМА_НАЛОЖЕНИЯ:
        return {}
    записи = d.get("records")
    return записи if isinstance(записи, dict) else {}


def наложить(записи: dict, наложение: dict) -> int:
    """Перенести перечни из наложения в записи снимка. Возвращает счёт сезонов.

    Накладывается только то, что есть и там и там: слаг из наложения, которого
    в снимке больше нет, не воскрешается, а сезон, которого у записи нет, не
    заводится. Наложение — память ячейки о ПРОВЕРЕННОМ, а не второй каталог.
    """
    легло = 0
    for слаг, запись in (наложение or {}).items():
        деталь = записи.get(слаг)
        if not isinstance(деталь, dict):
            continue
        сезоны = {str(с.get("n")): с for с in (деталь.get("seasons") or [])
                  if isinstance(с, dict)}
        добавлено = False
        for номер, данные in ((запись or {}).get("seasons") or {}).items():
            if not isinstance(данные, dict):
                continue
            перечень = данные.get("nums")
            if not isinstance(перечень, list) or not перечень:
                continue
            номера = sorted({int(н) for н in перечень
                             if isinstance(н, int) or str(н).lstrip("-").isdigit()})
            сезон = сезоны.get(str(номер))
            if сезон is None:
                # Сезон, которого в снимке конвейера нет вовсе. Заводится
                # только там, где согласование однажды уже установило, что
                # нумерация сходится (`from: player`), — иначе на витрине
                # появился бы сезон-двойник с чужими номерами.
                if данные.get("from") != "player":
                    continue
                try:
                    н = int(номер)
                except (TypeError, ValueError):
                    continue
                сезон = {"n": н, "eps": int(данные.get("eps") or max(номера) or 1),
                         "avail": 0, "from": "player"}
                деталь.setdefault("seasons", []).append(сезон)
                сезоны[str(номер)] = сезон
                добавлено = True
            сезон["nums"] = номера
            сезон["nums_at"] = данные.get("at") or ""
            легло += 1
        if добавлено:
            деталь["seasons"].sort(key=lambda с: int(с.get("n") or 0))
    return легло


# ------------------------------------------------------------- сам провайдер

def _плейлист(издатель: str, агрегатор: str, ид: str, домен: str) -> dict | None:
    """Ответ источника по одной записи. Отказ — None, а не исключение."""
    if not (издатель and ид and агрегатор):
        return None
    адрес = f"{ПЛЕЙЛИСТ}?" + urllib.parse.urlencode(
        {"pub": издатель, "id": ид, "aggr": агрегатор})
    запрос = urllib.request.Request(адрес, headers={
        "Accept": "application/json",
        "Origin": f"https://{домен}",
        "x-origin": f"https://{домен}",
        "Referer": f"https://{домен}/",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=ТАЙМАУТ_С) as ответ:
            return json.loads(ответ.read(8_000_000).decode("utf-8", "replace"))
    except Exception:  # noqa: BLE001 — недоступность источника не роняет витрину
        return None


def серии_по_сезонам(ответ: dict) -> dict:
    """Номера серий с НАСТОЯЩЕЙ дорожкой, по сезонам.

    Дорожкой считается запись с идентификатором потока, а не заготовка с одним
    названием. Ноль — допустимый номер: у «Скоттов» это единственная дорожка.
    """
    по_сезонам: dict[int, set] = {}
    for д in (ответ.get("items") or []):
        if not isinstance(д, dict):
            continue
        if not (str(д.get("cvhId") or "").strip() or str(д.get("vkId") or "").strip()):
            continue
        try:
            с, э = int(д.get("season") or 0), int(д.get("episode"))
        except (TypeError, ValueError):
            continue
        if с >= 1 and э >= 0:
            по_сезонам.setdefault(с, set()).add(э)
    return по_сезонам


#: Больше стольких сезонов из плейлиста за раз не заводится. Предохранитель от
#: записи с невменяемой нумерацией, а не правило отбора.
ПРЕДЕЛ_НОВЫХ_СЕЗОНОВ = 20


def нумерация_сходится(деталь: dict, найдено: dict) -> bool:
    """Согласна ли нумерация сезонов снимка с нумерацией плейлиста.

    Два конца одного источника отвечают по-разному, и это измерено
    2026-09-29:

      `boec-baki`   detail API объявляет 2 сезона (24, 24), плейлист отдаёт
                    восемь: 1, 2, 3, 5, 6, 7, 8, 9. Объявленные совпадают —
                    s1 24 серии и там и там, s2 объявлен пустым. Нумерация
                    сходится, и шесть сезонов просто потеряны.

      `avatar-korolya-2` detail API объявляет 4 сезона (12, 12, 17, 3),
                    плейлист — пять (12, 12, 12, 12, 17). Семнадцать серий
                    лежат у плейлиста в пятом сезоне, а снимок называет их
                    третьим. Это СДВИГ нумерации: завести «пятый сезон» здесь
                    значило бы показать то же самое дважды.

    Признак сдвига: у объявленного сезона плейлист знает МЕНЬШЕ серий, чем
    снимок уже объявил доступными. Тогда добавлять нельзя ничего — ни один
    номер сезона не значит того же, что у снимка.
    """
    общие = 0
    for сезон in (деталь.get("seasons") or []):
        if not isinstance(сезон, dict):
            continue
        номер = int(сезон.get("n") or 0)
        если_есть = найдено.get(номер)
        if not если_есть:
            continue
        общие += 1
        if len({н for н in если_есть if н >= 1}) < int(сезон.get("avail") or 0):
            return False
    return общие > 0


def согласовать(деталь: dict, найдено: dict, отметка: str) -> bool:
    """Записать перечень номеров в сезоны, которые провайдер вернул непустыми.

    Сезон, которого в снимке НЕТ, заводится — но только когда нумерация
    сходится (см. `нумерация_сходится`). Число серий такого сезона не
    выдумывается: это наибольший номер, подтверждённый дорожкой.
    """
    изменилось = False
    объявленные = set()
    for сезон in (деталь.get("seasons") or []):
        if not isinstance(сезон, dict):
            continue
        объявленные.add(int(сезон.get("n") or 0))
        номера = найдено.get(int(сезон.get("n") or 0))
        if not номера:
            continue
        новое = sorted(номера)
        if сезон.get("nums") != новое:
            сезон["nums"] = новое
            изменилось = True
        сезон["nums_at"] = отметка

    новые = [н for н in sorted(найдено) if н not in объявленные and найдено[н]]
    if новые and len(новые) <= ПРЕДЕЛ_НОВЫХ_СЕЗОНОВ and нумерация_сходится(деталь, найдено):
        for номер in новые:
            номера = sorted(найдено[номер])
            деталь.setdefault("seasons", []).append({
                "n": номер, "eps": max(номера) or len(номера), "avail": 0,
                "nums": номера, "nums_at": отметка, "from": "player",
            })
            изменилось = True
        деталь["seasons"].sort(key=lambda с: int(с.get("n") or 0))
    return изменилось


# ------------------------------------------------------------------ очередь

def срочные() -> list:
    """Слаги, которые спрашиваются ПЕРВЫМИ на каждом проходе.

    Суточная доставка каждый раз привозит снимок производителя, и запись, на
    которую владелец уже пожаловался, обязана выправиться в первые минуты, а
    не когда до неё дойдёт обход. Список объявлен витриной, короткий и
    поимённый: это не второй каталог и не правило отбора.
    """
    сырое = os.environ.get("LORDS_AVAIL_URGENT", "")
    return [с.strip() for с in сырое.split(",") if с.strip()]


def _состав(деталь: dict) -> list:
    """Отпечаток состава сезонов: по нему видно, что конвейер что-то поменял."""
    итог = []
    for с in (деталь.get("seasons") or []):
        if not isinstance(с, dict):
            continue
        try:
            итог.append([int(с.get("n") or 0), int(с.get("eps") or 0),
                         int(с.get("avail") or 0)])
        except (TypeError, ValueError):
            continue
    return итог


def слои(записи: dict, наложение: dict, свежее_года: int) -> dict:
    """Разложить каталог по слоям приоритета. Порядок внутри слоя — алфавит."""
    изменённые, онгоинги, растущие, прочие = [], [], [], []
    for слаг, деталь in sorted((записи or {}).items()):
        if not isinstance(деталь, dict):
            continue
        сезоны = [с for с in (деталь.get("seasons") or [])
                  if isinstance(с, dict) and int(с.get("eps") or 0) >= 1]
        if not сезоны:
            continue
        помнили = (наложение or {}).get(слаг) or {}
        if помнили and помнили.get("shape") != _состав(деталь):
            изменённые.append(слаг)
            continue
        недобор = any(int(с.get("avail") or 0) < int(с.get("eps") or 0) for с in сезоны)
        if not недобор:
            прочие.append(слаг)
            continue
        try:
            год = int(деталь.get("year") or 0)
        except (TypeError, ValueError):
            год = 0
        (онгоинги if год >= свежее_года else растущие).append(слаг)
    # Внутри слоя первыми идут ДАВНО НЕ ПРОВЕРЕННЫЕ. Без этого слой без
    # курсора при небольшом бюджете переспрашивал бы свою же голову каждые
    # пятнадцать минут, а хвост слоя не дожидался бы никогда: проверено —
    # второй проход возвращался к той же записи.
    #
    # Полный обход этим не сортируется: у него есть курсор, и алфавит делает
    # его позицию называемой.
    def давность(слаг):
        return ((наложение or {}).get(слаг) or {}).get("checked_at") or ""

    for слой in (изменённые, онгоинги, растущие):
        слой.sort(key=lambda с: (давность(с), с))
    return {"изменённые": изменённые, "онгоинги": онгоинги,
            "растущие": растущие, "прочие": прочие}


def набрать(слоёв: dict, позиция: str, бюджет: int, вперёд: list) -> tuple:
    """Что спросить в этом проходе и где остановился полный обход.

    Слои 0–3 идут первыми, но долю полного обхода они не съедают: иначе хвост
    каталога не спрашивался бы никогда, а именно там пряталась ложь «Скоттов».
    """
    кольцо = слоёв.get("прочие") or []
    список = list(вперёд)

    def добрать(имя, сколько):
        взято = 0
        for слаг in слоёв.get(имя) or []:
            if взято >= сколько:
                break
            if слаг not in список:
                список.append(слаг)
                взято += 1
        return взято

    # Изменившийся состав берётся ЦЕЛИКОМ и первым: его наполняет доставка,
    # он короткий, и он же отвечает за своевременность. Ограничение — сам
    # бюджет, чтобы патологическая доставка не съела проход без остатка.
    добрать("изменённые", бюджет)
    свободно = max(0, бюджет - (len(список) - len(вперёд)))
    добрать("онгоинги", min(свободно, max(1, int(бюджет * ДОЛЯ_ОНГОИНГОВ))))
    свободно = max(0, бюджет - (len(список) - len(вперёд)))
    добрать("растущие", min(свободно, max(1, int(бюджет * ДОЛЯ_РАСТУЩИХ))))

    # Полный обход. Доля у него СВОЯ и не отдаётся приоритетным слоям: хвост
    # каталога обязан спрашиваться, именно там пряталась ложь «Скоттов».
    осталось = max(0, бюджет - (len(список) - len(вперёд)))
    начало = (кольцо.index(позиция) + 1) if позиция in кольцо else 0
    свёрнутое = кольцо[начало:] + кольцо[:начало]
    взято = [с for с in свёрнутое[:осталось] if с not in список]
    список += взято
    новая_позиция = взято[-1] if взято else позиция

    # Обход оказался короче своей доли — остаток дослуживает приоритетным
    # слоям. Пустой проход при непустой очереди — потерянные пятнадцать минут.
    if len(список) - len(вперёд) < бюджет:
        for имя in ("онгоинги", "растущие"):
            добрать(имя, бюджет - (len(список) - len(вперёд)))
    return список, новая_позиция


# ------------------------------------------------------------- согласование

class Согласование:
    """Один проход, позиция обхода и наложение."""

    def __init__(self, рантайм, *, домен: str, снимок: Path) -> None:
        self.рантайм = рантайм
        self.домен = домен
        self.снимок = снимок
        self.наложение_путь = путь_наложения(снимок)
        self.позиция_файл = снимок.with_name(f".{снимок.stem}-avail-ring.json")
        self.наложение = прочитать_наложение(self.наложение_путь)
        self.позиция = self._прочитать_позицию()

    def _прочитать_позицию(self) -> str:
        try:
            return str(json.loads(self.позиция_файл.read_text(
                encoding="utf-8")).get("после") or "")
        except (OSError, ValueError):
            return ""

    def _записать(self, путь: Path, данные) -> bool:
        try:
            врем = путь.with_suffix(путь.suffix + ".tmp")
            врем.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
            os.replace(врем, путь)
            return True
        except OSError:
            return False

    def _сохранить_наложение(self, ревизия: str) -> bool:
        return self._записать(self.наложение_путь, {
            "schema": СХЕМА_НАЛОЖЕНИЯ,
            "note": ("Память ЯЧЕЙКИ о проверенных номерах серий. Снимок "
                     "принадлежит конвейеру и заменяется доставкой целиком; "
                     "этот файл доставка не трогает, и рантайм накладывает его "
                     "при чтении снимка. Удаление файла не ломает витрину — она "
                     "вернётся к числу `avail` из снимка и заново наберёт "
                     "перечни."),
            "site_id": os.environ.get("LORDS_SITE_ID", ""),
            "catalog_revision": ревизия,
            "updated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "records": self.наложение,
        })

    def проход(self, подробности) -> dict:
        издатель = str(self.рантайм.ПЛЕЕР.get("publisher_id") or "")
        записи = подробности.записи or {}
        if not записи or not издатель:
            return {"спрошено": 0, "согласовано": 0, "записано": False}

        год = time.gmtime().tm_year - 1
        разложено = слои(записи, self.наложение, год)
        вперёд = [с for с in срочные()[:8] if с in записи]
        список, позиция = набрать(разложено, self.позиция, ЗА_ПРОХОД, вперёд)

        собран = getattr(подробности, "catalog_built_at", "") or ""
        отметка = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        спрошено = согласовано = отказов = 0
        лаги = []
        for слаг in список:
            деталь = записи.get(слаг)
            if not isinstance(деталь, dict):
                continue
            спрошено += 1
            найдено: dict[int, set] = {}
            for агрегатор, ид in self.рантайм.кандидаты_источника(деталь)[:ЗАПАСНЫХ + 1]:
                ответ = _плейлист(издатель, агрегатор, ид, self.домен)
                if ответ is None:
                    отказов += 1
                    continue
                найдено = серии_по_сезонам(ответ)
                if найдено:
                    break
            if слаг in (разложено.get("изменённые") or ()):
                лаги.append(_лаг(собран))
            if найдено:
                поменялось = согласовать(деталь, найдено, отметка)
                # Запоминается ВСЕГДА, когда провайдер ответил, а не только при
                # изменении: отпечаток состава нужен, чтобы в следующий раз
                # отличить «конвейер что-то поменял» от «всё как было».
                self._запомнить(слаг, деталь, отметка)
                согласовано += int(поменялось)
            time.sleep(ШАГ_С)

        self.позиция = позиция
        ревизия = getattr(подробности, "catalog_revision", "") or ""
        записано = self._сохранить_наложение(ревизия) if спрошено else False
        self._записать(self.позиция_файл, {
            "после": self.позиция,
            "в": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())})
        return {
            "спрошено": спрошено, "согласовано": согласовано,
            "отказов_запроса": отказов, "записано": записано,
            "позиция": self.позиция,
            "слои": {к: len(v) for к, v in разложено.items()},
            "лаг_изменённых_с": лаги,
        }

    def _запомнить(self, слаг: str, деталь: dict, отметка: str) -> None:
        сезоны = {}
        for с in (деталь.get("seasons") or []):
            if not isinstance(с, dict) or not с.get("nums"):
                continue
            данные = {"nums": list(с["nums"]), "at": отметка}
            # Происхождение сезона переносится в наложение: доставка привезёт
            # снимок без него, и восстановить его можно только зная, что он
            # взят у плеера, а не выдуман.
            if с.get("from") == "player":
                данные["from"] = "player"
                данные["eps"] = int(с.get("eps") or 0)
            сезоны[str(с.get("n"))] = данные
        запись = {"shape": _состав(деталь), "checked_at": отметка}
        if сезоны:
            запись["seasons"] = сезоны
        self.наложение[слаг] = запись


def _лаг(собран: str) -> int:
    """Сколько секунд прошло от сборки снимка до этого вопроса провайдеру."""
    try:
        т = time.strptime(собран, "%Y-%m-%dT%H:%M:%SZ")
    except (TypeError, ValueError):
        return -1
    return max(0, int(time.time() - time.mktime(т) + time.timezone))


def _цикл(рантайм, домен: str, снимок: Path, отчёт: Path) -> None:
    time.sleep(20)                      # дать витрине подняться и ответить
    согласование = Согласование(рантайм, домен=домен, снимок=снимок)
    прежний = None
    while True:
        try:
            подробности = getattr(рантайм.Обработчик, "подробности", None)
            if подробности is None:
                time.sleep(ПАУЗА_С)
                continue
            # Объект берётся у обработчика КАЖДЫЙ проход: витрина подменяет его
            # целиком при новом снимке, и поток с прежней ссылкой правил бы
            # отсоединённый словарь.
            метка = id(подробности)
            if прежний is not None and метка != прежний:
                print("[nova] согласование: снимок сменился", flush=True)
            прежний = метка
            итог = согласование.проход(подробности)
            итог["в"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            согласование._записать(отчёт, итог)
            if итог.get("согласовано"):
                print(f"[nova] согласование доступности: {итог}", flush=True)
        except Exception as ош:  # noqa: BLE001 — фон не роняет витрину
            print(f"[nova] согласование отказало: {ош!r}", flush=True)
        time.sleep(ПАУЗА_С)


def запустить(рантайм) -> bool:
    """Завести поток согласования. False — если заводить нечего или нечем.

    Условия жёсткие намеренно: без канонического домена запрос уйдёт с чужим
    Origin, без publisher спрашивать нечем, а в режиме `external-ids` страница
    знает единственный ключ, и спрашивать по остальным значило бы судить о
    доступности по источнику, которого на странице не будет.
    """
    домен = (os.environ.get("LORDS_SITE_HOST")
             or os.environ.get("ANIMEDIA_SITE_HOST")
             or os.environ.get("ANIMEGO_SITE_HOST") or "").strip()
    плеер = getattr(рантайм, "ПЛЕЕР", {}) or {}
    if not домен or not плеер.get("publisher_id"):
        return False
    if плеер.get("source_mode") != "provider-id":
        return False
    подробности = getattr(рантайм.Обработчик, "подробности", None)
    путь = Path(getattr(подробности, "path", "") or "")
    if not путь.name:
        return False
    отчёт = путь.with_name(f"{путь.stem.replace('-details', '')}-episode-sync.json")
    threading.Thread(target=_цикл, args=(рантайм, домен, путь, отчёт),
                     name="avail-sync", daemon=True).start()
    return True
