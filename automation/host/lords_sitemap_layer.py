#!/usr/bin/env python3
"""Карта сайта для витрин семейства на ОБЩЕМ ядре — слоем, а не правкой ядра.

Зачем отдельный модуль
----------------------

У семейства две формы рантайма, и подключение карты у них разное:

* МОНОЛИТ (`lordserials22.info`, `1lordserials1.online`, `zonafilm.space`,
  `zonafilm12.site`) — точка входа и есть рантайм, и правки вносятся прямо в
  неё инструментом `automation/local/wire-sitemap.py`;
* АДАПТЕР над общим ядром (`lordserial33.biz`, `lordfilm47.space`) —
  `src/lords-frontend.py` совпадает с ядром соседа байт в байт, закреплён в
  `pins.lock.json` с происхождением `verified_against: git`, помечен только
  для чтения, и `AGENTS.md` (п. 3) требует менять его отдельной задачей
  отдельным коммитом производителя.

Измерено 2026-10-04 на выложенном lordserial33.biz: маршрут `/sitemap.xml` в
ядре ЕСТЬ и читает `SITEMAP_DIR`, но файлы туда никто не пишет — сборщика не
запускал никто, `LORDS_SITEMAP_DIR` не задан, и домен отдавал 404 молча. То
есть не хватало ровно того, что лежит в файлах САМОГО САЙТА.

Что делает этот слой

1. объявляет ядру разделы ЭТОГО сайта (`РАЗДЕЛЫ_КАРТЫ`) — теми же точками
   расширения, которыми пользуются `lords02_view` и `lords02_editorial`;
2. заводит общий сборщик `seo_layer.запустить_карту` с ядром в роли рантайма:
   сборщику от рантайма нужны снимок каталога, режим индексации и разделы, и
   всё это у ядра есть;
3. даёт `ссылка_на_карту()` для `robots.txt`: ссылка ставится ТОЛЬКО при
   открытом режиме, заданном каталоге и существующем файле карты — `Sitemap:`
   на адрес, отвечающий 404, обходчик запомнит именно таким.

Чего слой НЕ делает: не трогает ядро, не выдумывает разделы (их передаёт
лаунчер измеренным перечнем) и не молчит об отказе — причина называется в
журнале запуска.
"""
from __future__ import annotations

import os
import pathlib

#: Что поставлено. Хранится здесь, чтобы диагностика могла спросить состояние,
#: не заводя второй сборщик.
ПОДКЛЮЧЕНО: dict = {"attached": False, "reason": "слой не подключался"}


def каталог_карты() -> str:
    return os.environ.get("LORDS_SITEMAP_DIR", "").strip()


def домен_карты() -> str:
    return (os.environ.get("LORDS_SITE_HOST")
            or os.environ.get("LORDS_INDEXING_SITE")
            or os.environ.get("LORDS_SITE_DOMAIN") or "").strip()


def ссылка_на_карту(состояние: str) -> str:
    """Адрес карты для `robots.txt` или пустая строка. Три условия, все нужны."""
    if (состояние or "").strip().upper() != "OPEN":
        return ""
    каталог, хост = каталог_карты(), домен_карты()
    if not каталог or not хост:
        return ""
    try:
        if not (pathlib.Path(каталог) / "sitemap.xml").is_file():
            return ""
    except OSError:
        return ""
    return f"https://{хост}/sitemap.xml"


def состояние() -> dict:
    """Машинно читаемый ответ «почему карты нет»."""
    итог = dict(ПОДКЛЮЧЕНО)
    итог["dir"] = каталог_карты()
    итог["host"] = домен_карты()
    return итог


def подключить(ядро, разделы) -> bool:
    """Объявить разделы ядру и завести сборщик. False — с названной причиной."""
    global ПОДКЛЮЧЕНО

    перечень = tuple(str(р) for р in (разделы or ()) if str(р).startswith("/"))
    if not перечень:
        ПОДКЛЮЧЕНО = {"attached": False,
                      "reason": "перечень разделов пуст: карта из одной главной "
                                "страницы пользы не несёт, а догадываться о "
                                "разделах нельзя"}
        print(f"[nova] карта сайта не заводится: {ПОДКЛЮЧЕНО['reason']}", flush=True)
        return False
    # Разделы объявляются ЯДРУ: сборщик спрашивает их у рантайма, а рантайм
    # здесь чужой и о разделах этого сайта знать не может.
    setattr(ядро, "РАЗДЕЛЫ_КАРТЫ", перечень)
    try:
        import seo_layer
    except ImportError:
        ПОДКЛЮЧЕНО = {"attached": False,
                      "reason": "модуля seo_layer нет: сборщик живёт в нём"}
        print(f"[nova] карта сайта не заводится: {ПОДКЛЮЧЕНО['reason']}", flush=True)
        return False
    if not hasattr(seo_layer, "запустить_карту"):
        ПОДКЛЮЧЕНО = {"attached": False,
                      "reason": "выпуск несёт прежнюю версию seo_layer: в ней нет "
                                "запустить_карту"}
        print(f"[nova] карта сайта не заводится: {ПОДКЛЮЧЕНО['reason']}", flush=True)
        return False
    заведено = bool(seo_layer.запустить_карту(ядро))
    ПОДКЛЮЧЕНО = {"attached": заведено, "sections": list(перечень),
                  "reason": "" if заведено else "сборщик назвал причину отказа выше"}
    print(f"[nova] карта сайта: {состояние()}", flush=True)
    return заведено
