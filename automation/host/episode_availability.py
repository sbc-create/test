def рендерер(путь: Path | None = None):
    """Закреплённый рантайм как модуль. Источник истины о правилах страницы.

    Импортируется по пути, а не по имени: в имени файла дефис, и обычный
    `import` его не возьмёт. Копия правил здесь не заводится намеренно —
    разойдясь с рендерером, она пополняла бы доступность записи, которую
    страница всё равно не играет.

    Манифест шаблона подставляется свой, репозиторный: рантайм читает его при
    импорте и без него отказывает (`SystemExit`), а его умолчание ведёт в
    общее дерево фабрики `/srv/lords/.frontend`. На раннере CI такого дерева
    нет, и проверка падала не на правиле, а на чужом пути; на боевой машине
    умолчание указывало бы на снимок СОСЕДНЕЙ витрины. Значение то же, что
    ставит `run.py` из `config/site.json`.
    """
    манифест = str(КОРЕНЬ / "config" / "template-manifest.json")
    for имя in ("LORDS_TEMPLATE_MANIFEST", "ANIMEDIA_TEMPLATE_MANIFEST",
                "ANIMEGO_TEMPLATE_MANIFEST"):
        os.environ.setdefault(имя, манифест)
    путь = путь or рантайм_витрины()
    спец = importlib.util.spec_from_file_location("_lords_runtime", путь)
    модуль = importlib.util.module_from_spec(спец)
    sys.modules["_lords_runtime"] = модуль
    спец.loader.exec_module(модуль)
    return модуль


def рантайм_витрины() -> Path:
    """Файл рантайма ЭТОЙ витрины: имя берётся из её собственного объявления.

    Семейств четыре (lords, zona, animedia, animego), и файл рантайма у них
    называется по-разному. Имя объявлено в `config/site.json` полем
    `entrypoint` — тем же, которым его запускает `run.py`. Угадывать по
    умолчанию `lords-frontend.py` нельзя: у витрины AnimeGo такого файла нет,
    и инструмент молча спрашивал бы провайдера порядком кандидатов, которого
    на её странице не будет.

    Точка входа витрины может быть тонким слоем поверх общего рантайма
    (`lords02-frontend.py` у lordserial33.biz). Согласованию нужен именно
    общий: правила `кандидаты_источника` и `ПЛЕЕР` живут в нём, а слой их не
    переопределяет. Поэтому слой распознаётся по отсутствию `ПЛЕЕР` и
    заменяется соседним общим файлом семейства.
    """
    конфиг = json.loads((КОРЕНЬ / "config" / "site.json").read_text(encoding="utf-8"))
    имя = str(конфиг.get("entrypoint") or "").strip()
    if not имя:
        raise SystemExit("config/site.json не объявляет entrypoint: "
                         "какой рантайм спрашивать — неизвестно")
    путь = КОРЕНЬ / "src" / имя
    if not путь.is_file():
        raise SystemExit(f"нет рантайма витрины {путь}")
    if "ПЛЕЕР" not in путь.read_text(encoding="utf-8", errors="replace"):
        семейство = str(конфиг.get("family") or "").strip()
        общий = {"lords": "lords-frontend.py", "zona": "lords-frontend.py",
                 "animedia": "animedia-frontend.py",
                 "animego": "animego-frontend.py"}.get(семейство)
        if общий and (КОРЕНЬ / "src" / общий).is_file():
            return КОРЕНЬ / "src" / общий
        raise SystemExit(f"{имя} — слой витрины без правил плеера, "
                         f"а общего рантайма семейства «{семейство}» рядом нет")
    return путь


def кандидаты_страницы(модуль, деталь: dict) -> list:
    """Те же кандидаты и в том же порядке, что уйдут в `data-src-candidates`.

    Ветка по режиму повторяет `разметка_плеера`, а не угадывает его: в режиме
    `external-ids` страница знает единственный ключ `kp`, и спрашивать по
    `mdl` или по собственному UUID провайдера значило бы судить о доступности
    по источнику, которого на странице не будет. Для ПОНИЖЕНИЯ это разница
    между «снял обещание» и «снял работающие серии».
    """
    if модуль.ПЛЕЕР.get("source_mode") == "provider-id":
        return модуль.кандидаты_источника(деталь)
    агрегатор, ид = модуль.источник_плеера(деталь)
    return [(агрегатор, ид)] if агрегатор and ид else []


def свернуть(текст: str) -> str:
    """Название без регистра, пунктуации и диакритики — для сверки сущности."""
    т = unicodedata.normalize("NFKD", str(текст or "")).lower()
    т = "".join(с for с in т if not unicodedata.combining(с))
    return re.sub(r"[^0-9a-zа-я]+", "", т)


def имя_записи(деталь: dict) -> str:
    """Название из снимка для сверки сущности.

    Поле `name` есть у всех 53 908 записей боевого снимка (замер 2026-09-28);
    `original_name` — запасное. Пусто — сверять нечем, и запись пропускается:
    «не с чем сравнить» не то же самое, что «совпало».
    """
    for поле in ("name", "title", "original_name", "original_title"):
        значение = str(деталь.get(поле) or "").strip()
        if значение:
            return значение
    return ""


def подряд_от_первой(номера) -> int:
    """Длина непрерывного ряда от первой серии. {1,3} — это одна, а не две."""
    есть = {int(н) for н in номера}
    сколько = 0
    while сколько + 1 in есть:
        сколько += 1
    return сколько


def есть_поток(дорожка: dict) -> bool:
    """Несёт ли дорожка ПОТОК, а не только номер.

    Провайдер отдаёт в плейлисте и заготовки: запись серии заведена, а
    `cvhId` и `vkId` пусты — играть нечего. Признак взят из контракта,
    которым пользуется и сверка источника фабрики
    (`automation/host/nova-source-verify.py`), а не выдуман здесь.

    Наблюдалось на `/title/luchshee-lekarstvo/` (kp 10644882, проверено
    2026-09-28 в 15:11Z): тринадцать серий первого сезона в плейлисте, у всех
    `cvhId` и `vkId` пустые. Инструмент поднял `avail` до 13, страница
    смонтировала `<video-player>`, и все три проверенные серии повисли на
    таймауте. Честное «дорожки ещё нет» тут лучше вертящегося колеса: считать
    заготовку доступностью — та же ошибка, что считать счёт номером.
    """
    if not isinstance(дорожка, dict):
        return False
    return bool(str(дорожка.get("cvhId") or "").strip()
                or str(дорожка.get("vkId") or "").strip())


def серии_по_сезонам(ответ: dict) -> tuple:
    """Ответ плейлиста → ({сезон: множество номеров}, сколько дорожек пропущено).

    Дорожек на одну серию бывает несколько (озвучки, субтитры): для
    доступности важно, что серия есть хоть в одной С ПОТОКОМ, поэтому номера
    складываются в множество, а не считаются штуками. Номер 0 сохраняется —
    именно он отличает спецвыпуск от первой серии. Дорожки без разборного
    номера сезона и заготовки без потока считаются отдельно: молча терять их
    нельзя, иначе слепое пятно инструмента не видно в отчёте.
    """
    итог: dict = {}
    пропущено = 0
    for запись in (ответ.get("items") or []):
        if not isinstance(запись, dict):
            пропущено += 1
            continue
        try:
            сезон = int(запись.get("season") or 0)
            серия = int(запись.get("episode"))
        except (TypeError, ValueError):
            пропущено += 1
            continue
        if сезон < 1 or серия < 0:
            пропущено += 1
            continue
        # Сезон, который провайдер НАЗВАЛ, заводится всегда — даже если все его
        # дорожки оказались заготовками. Пустое множество и отсутствие сезона
        # значат разное: первое — «сезон есть, играть нечего» (понижение
        # разрешено), второе — «провайдер о нём не сказал» (не трогаем).
        # Без этого различия ошибочно поднятая заготовка не опускалась обратно:
        # сезон исчезал из ответа целиком и попадал под правило «не трогаем».
        номера = итог.setdefault(сезон, set())
        if not есть_поток(запись):
            пропущено += 1
            continue
        номера.add(серия)
    return итог, пропущено


def спланировать(сезоны: list, по_сезонам: dict) -> dict:
    """Что следует сделать с сезонами записи. Ничего не меняет.

    `сезоны` — список сезонов снимка. Возвращает
    {'changes': [...], 'overstated': [...], 'eps_behind': [...]}.

    Целевое состояние сезона — пара «`avail`, `nums`»:

      `avail` остаётся длиной непрерывного ряда от первой серии. Это значение
      читает рантайм, который про `nums` не знает, и оно обязано быть
      осторожным: обещать по нему больше, чем играется, значит вернуть тот
      самый доломанный плеер.

      `nums` — поимённый перечень доступных номеров — выставляется ТОЛЬКО
      когда перечень отличается от простого отрезка «с первой по avail».
      Спецвыпуск с номером 0, пропуски в нумерации и сезон, начинающийся со
      второй серии, одним числом не описываются; всё остальное описывается, и
      возить перечень для каждого из двадцати тысяч сериалов значило бы
      раздуть снимок ради записи того, что и так известно.
    """
    итог = {"changes": [], "overstated": [], "eps_behind": []}
    for сезон in сезоны:
        try:
            номер = int(сезон.get("n") or 0)
            было = int(сезон.get("avail") or 0)
            всего = int(сезон.get("eps") or 0)
        except (TypeError, ValueError):
            continue
        if номер < 1 or всего < 1:
            continue
        у_источника = по_сезонам.get(номер)
        if у_источника is None:
            continue
        ряд = подряд_от_первой(у_источника)
        адресуемые = {н for н in у_источника if н >= 1}
        # В снимок идут номера в пределах объявленного состава сезона и
        # спецвыпуски: поднимать `eps` — не наше дело.
        номера = sorted({н for н in у_источника if н < 1 or н <= всего})
        цель = min(ряд, всего)
        перечень = None if номера == list(range(1, цель + 1)) else номера
        прежний = сезон.get("nums")
        прежний = sorted(прежний) if isinstance(прежний, (list, tuple)) else None

        if цель != было or перечень != прежний:
            направление = ("raise" if цель > было
                           else "lower" if цель < было else "nums")
            правка = {"season": номер, "from": было, "to": цель,
                      "prefix": ряд, "eps": всего, "direction": направление}
            if перечень is not None or прежний is not None:
                правка["nums"] = перечень
                правка["nums_from"] = прежний
            итог["changes"].append(правка)
        elif было > ряд:
            итог["overstated"].append(
                {"season": номер, "avail": было, "prefix": ряд,
                 "source_count": len(адресуемые),
                 "source_max": max(адресуемые) if адресуемые else 0})
        if адресуемые and max(адресуемые) > всего:
            итог["eps_behind"].append(
                {"season": номер, "eps": всего, "source_max": max(адресуемые),
                 "source_count": len(адресуемые)})
    return итог


def применить_план(деталь: dict, правки: list) -> list:
    """Наложить правки на запись СВЕЖЕГО снимка, перепроверив основания.

    Между опросом и записью снимок мог смениться доставкой конвейера. Потолок
    и перечень пересчитываются по НОВОМУ составу сезона, и правка ложится
    только если она всё ещё что-то меняет. Иначе отбрасывается, а не
    навязывается.
    """
    легло = []
    по_номеру = {}
    for сезон in (деталь.get("seasons") or []):
        try:
            по_номеру[int(сезон.get("n") or 0)] = сезон
        except (TypeError, ValueError):
            continue
    for правка in правки:
        сезон = по_номеру.get(правка["season"])
        if сезон is None:
            continue
        try:
            текущее = int(сезон.get("avail") or 0)
            всего = int(сезон.get("eps") or 0)
        except (TypeError, ValueError):
            continue
        if всего < 1:
            continue
        цель = min(int(правка.get("prefix") or 0), всего)
        if "nums" in правка:
            перечень = правка["nums"]
            if перечень is not None:
                перечень = [н for н in перечень if н < 1 or н <= всего]
                if перечень == list(range(1, цель + 1)):
                    перечень = None
        else:
            перечень = сезон.get("nums")
            перечень = (sorted(перечень)
                        if isinstance(перечень, (list, tuple)) else None)
        прежний = сезон.get("nums")
        прежний = sorted(прежний) if isinstance(прежний, (list, tuple)) else None
        if цель == текущее and перечень == прежний:
            continue
        if перечень is None:
            сезон.pop("nums", None)
        else:
            сезон["nums"] = перечень
        сезон["avail"] = цель
        легло.append(dict(правка, to=цель, nums=перечень,
                          applied_from=текущее, applied_eps=всего))
    return легло


def растущая(деталь: dict) -> bool:
    """Есть ли сезон, которому по снимку есть куда расти (`avail < eps`)."""
    for сезон in (деталь.get("seasons") or []):
        try:
            if int(сезон.get("avail") or 0) < int(сезон.get("eps") or 0):
                return True
        except (TypeError, ValueError):
            continue
    return False


def сериал(деталь: dict) -> bool:
    """Есть ли у записи хоть один объявленный сезон с сериями."""
    for сезон in (деталь.get("seasons") or []):
        try:
            if int(сезон.get("eps") or 0) >= 1:
                return True
        except (TypeError, ValueError):
            continue
    return False


def кандидаты(детали: dict, модуль, свежее_года: int) -> tuple:
    """(растущие, прочие). Спрашивать имеет смысл любой сериал.

    Сузить отбор до растущих нельзя: у «Скоттов» `avail` равен `eps`, и ложным
    было само обещание. Но растущие идут первыми — именно там появляется новая
    серия, и внутри них свежие по году впереди остальных.
    """
    растущие, прочие = [], []
    for слаг in sorted(детали):
        деталь = детали[слаг]
        if not isinstance(деталь, dict) or not сериал(деталь):
            continue
        if not кандидаты_страницы(модуль, деталь):
            continue
        if растущая(деталь):
            try:
                год = int(деталь.get("year") or 0)
            except (TypeError, ValueError):
                год = 0
            растущие.append((0 if год >= свежее_года else 1, слаг))
        else:
            прочие.append(слаг)
    растущие.sort()
    return [с for _, с in растущие], прочие


def отрезок(кольцо: list, после: str, сколько: int) -> list:
    """Следующий отрезок кругового обхода. Позиция — слаг, а не номер.

    Номер указывал бы каждый раз на другую запись: каталог между прогонами
    растёт и уменьшается. При устойчивом порядке слаг переживает и это.
    """
    if not кольцо or сколько <= 0:
        return []
    начало = 0
    if после and после in кольцо:
        начало = кольцо.index(после) + 1
    elif после:
        начало = next((i for i, с in enumerate(кольцо) if с > после), 0)
    if начало >= len(кольцо):
        начало = 0
    взято = кольцо[начало:начало + сколько]
    if len(взято) < сколько:
        взято += кольцо[:min(сколько - len(взято), len(кольцо) - len(взято))]
    return взято


#: Сколько записей держится под наблюдением. Список не растёт без предела:
#: он существует ради тех, кого конвейер систематически отдаёт неверно, а не
#: ради истории всех правок.
ПРЕДЕЛ_НАБЛЮДЕНИЯ = 500


def список_наблюдения(прошлый_отчёт: dict, свежие: list) -> list:
    """Кого держим под наблюдением: свежие правки впереди прежних.

    Список ОБЯЗАН переживать прогоны, в которых ничего не менялось. Первая
    редакция брала срочных из `changed` последнего отчёта, и этого хватало
    ровно до первого спокойного прогона: он перезаписывал отчёт пустым
    списком, и наутро, после доставки, «Мастер Омюр» снова ждал бы общего
    обхода — то есть несколько суток. Один спокойный прогон стирал всю память
    инструмента.
    """
    видели, итог = set(), []
    for слаг in list(свежие) + list(прошлый_отчёт.get("watchlist") or []):
        слаг = str(слаг or "")
        if слаг and слаг not in видели:
            видели.add(слаг)
            итог.append(слаг)
    return итог[:ПРЕДЕЛ_НАБЛЮДЕНИЯ]


def срочные(прошлый_отчёт: dict, ревизия: str) -> list:
    """Очередь на доспрос после доставки каталога. Живёт между прогонами.

    Суточная доставка возвращает снимку прежние числа, и «Мастер Омюр» со
    «Скоттами» назавтра снова были бы сломаны — до тех пор, пока до них не
    дойдёт обход длиной в несколько суток. Признак доставки — смена ревизии
    каталога; кого спрашивать, берётся из списка наблюдения.

    Очередь ОБЯЗАНА переживать прогоны. Первая редакция выводила срочных прямо
    из наблюдения при каждом запуске, и это работало ровно один раз: первый же
    прогон записывал в отчёт НОВУЮ ревизию, следующий видел её совпадающей и
    возвращал пустой список. Наблюдение в семьдесят четыре записи при бюджете
    прогона в полсотни доспрашивалось на четверть, а остальные три четверти —
    включая обе записи из жалобы — не доспрашивались никогда. Поэтому остаток
    очереди хранится в отчёте и вычерпывается прогон за прогоном.
    """
    if not isinstance(прошлый_отчёт, dict):
        return []
    прежняя = str(прошлый_отчёт.get("catalog_revision") or "")
    if прежняя and прежняя != ревизия:
        наблюдение = прошлый_отчёт.get("watchlist")
        if наблюдение is None:
            # Отчёт прежней редакции: списка наблюдения нет, но правки есть.
            наблюдение = [з.get("slug") for з in (прошлый_отчёт.get("changed") or [])]
            наблюдение += [з.get("slug") for з in (прошлый_отчёт.get("overstated") or [])]
    else:
        наблюдение = прошлый_отчёт.get("urgent_pending") or []
    видели, итог = set(), []
    for слаг in наблюдение:
        слаг = str(слаг or "")
        if слаг and слаг not in видели:
            видели.add(слаг)
            итог.append(слаг)
    return итог


class Ограничитель:
    """Не больше N запросов в секунду. Витрины живые, нагрузочных проб нет."""

    def __init__(self, в_секунду: float) -> None:
        self._шаг = 1.0 / max(в_секунду, 0.1)
        self._следующий = 0.0

    def ждать(self) -> None:
        сейчас = time.monotonic()
        если = max(сейчас, self._следующий)
        self._следующий = если + self._шаг
        if если > сейчас:
            time.sleep(если - сейчас)


def спросить(pub: str, домен: str, агрегатор: str, ид: str,
             огр: Ограничитель, попыток: int = 3, таймаут: int = 30) -> dict:
    """Один вопрос провайдеру о плейлисте записи.

    204 и пустое тело — это «такого контента нет», а не сбой: без отдельной
    ветки пустой ответ ронял бы разбор JSON, и непокрытая запись пряталась бы
    среди сетевых ошибок. Подписанные ссылки и рекламные поля ответа наружу не
    выносятся: отсюда уходит только состав серий и название.
    """
    запрос_строка = urllib.parse.urlencode({"pub": pub, "id": ид, "aggr": агрегатор})
    адрес = f"{ПЛЕЙЛИСТ}?{запрос_строка}"
    заголовки = {"Accept": "application/json", "Origin": f"https://{домен}",
                 "x-origin": f"https://{домен}", "Referer": f"https://{домен}/"}
    задержка = 1.0
    for попытка in range(попыток):
        огр.ждать()
        try:
            запрос = urllib.request.Request(адрес, headers=заголовки)
            with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
                тело = ответ.read().decode("utf-8", "replace")
                код = ответ.status
            if код == 204 or not тело.strip():
                return {"http": 204, "payload": {}}
            разобрано = json.loads(тело)
            if not isinstance(разобрано, dict):
                return {"http": 200, "payload": {}}
            # Ответ провайдера не правится: своё поле рядом, а не внутри.
            return {"http": 200, "payload": разобрано}
        except urllib.error.HTTPError as ош:
            if ош.code in (429, 500, 502, 503, 504) and попытка + 1 < попыток:
                time.sleep(задержка)
                задержка *= 2
                continue
            return {"http": ош.code, "payload": {}}
        except Exception as ош:  # сеть, таймаут, битый JSON
            if попытка + 1 < попыток:
                time.sleep(задержка)
                задержка *= 2
                continue
            return {"http": -1, "payload": {}, "error": str(ош)[:120]}
    return {"http": -1, "payload": {}}


def прочитать_json(путь: Path, умолчание):
    try:
        return json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return умолчание


def отпечаток(путь: Path):
    """Чем файл опознаётся между чтением и записью. Нет файла — None."""
    try:
        с = путь.stat()
    except OSError:
        return None
    return (с.st_dev, с.st_ino, с.st_mtime_ns, с.st_size)


def записать_атомарно(путь: Path, текст: str, ожидаемый=None) -> bool:
    """Подмена целиком, если файл не сменился под нами.

    `os.replace` делает атомарной ЗАПИСЬ, но не защищает от потерянного
    обновления: конвейер мог положить новое поколение каталога, пока шёл
    опрос. Поэтому отпечаток сверяется у самой подмены, и при расхождении
    запись отменяется — доставка конвейера свежее нашей копии по определению,
    и затирать её значило бы откатить витрину на сутки назад.

    Временный файл снимается в любом исходе: 76 МБ мусора при каждом отказе
    забили бы том за сутки и увели бы за собой сам сайт.
    """
    врем = путь.with_suffix(путь.suffix + f".{os.getpid()}.tmp")
    try:
        with open(врем, "w", encoding="utf-8") as ф:
            ф.write(текст)
            ф.flush()
            os.fsync(ф.fileno())
        if ожидаемый is not None and отпечаток(путь) != ожидаемый:
            return False
        os.replace(врем, путь)
        return True
    finally:
        try:
            if врем.exists():
                врем.unlink()
        except OSError:
            pass


def опросить(*, слаги: list, детали: dict, модуль, издатель: str, домен: str,
             огр: Ограничитель, спрашивать, предел_секунд: float) -> dict:
    """Спросить провайдера и составить план правок. Снимок не меняется."""
    начало = time.monotonic()
    итог = {"asked": 0, "planned": [], "overstated": [], "eps_behind": [],
            "entity_mismatch": [], "no_content": [], "http_error": [],
            "no_name": [], "unplaced_tracks": 0, "answers": [],
            "stopped_early": False}
    for слаг in слаги:
        if time.monotonic() - начало > предел_секунд:
            итог["stopped_early"] = True
            break
        деталь = детали.get(слаг)
        if not isinstance(деталь, dict):
            итог["http_error"].append({"slug": слаг, "note": "записи нет в снимке"})
            continue
        источники = кандидаты_страницы(модуль, деталь)
        if not источники:
            итог["http_error"].append({"slug": слаг, "note": "у записи нет источника"})
            continue
        имя_с = свернуть(имя_записи(деталь))
        if not имя_с:
            # Сверять сущность нечем. «Не с чем сравнить» — не «совпало».
            итог["no_name"].append({"slug": слаг})
            continue

        агрегатор, ид = источники[0]
        когда = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        ответ = спрашивать(издатель, домен, агрегатор, ид, огр)
        итог["asked"] += 1
        тело = ответ.get("payload") or {}
        итог["answers"].append(
            {"slug": слаг, "aggregator": агрегатор, "id": ид, "asked_at": когда,
             "http": ответ.get("http"), "title_name": тело.get("titleName"),
             "tracks": len(тело.get("items") or [])})

        if ответ.get("http") == 204:
            итог["no_content"].append({"slug": слаг, "id": ид,
                                       "aggregator": агрегатор, "asked_at": когда})
            continue
        if ответ.get("http") != 200:
            итог["http_error"].append({"slug": слаг, "http": ответ.get("http"),
                                       "aggregator": агрегатор})
            continue
        имя_и = свернуть(тело.get("titleName"))
        if имя_и and имя_и != имя_с:
            итог["entity_mismatch"].append(
                {"slug": слаг, "id": ид, "aggregator": агрегатор,
                 "source_title": тело.get("titleName"),
                 "snapshot_title": имя_записи(деталь)})
            continue

        по_сезонам, пропущено = серии_по_сезонам(тело)
        итог["unplaced_tracks"] += пропущено
        план = спланировать(деталь.get("seasons") or [], по_сезонам)

        if any(п["direction"] == "lower" for п in план["changes"]):
            # Страница отдаёт браузеру ВЕСЬ список кандидатов и перебирает его.
            # Понижать по ответу первого значило бы снять серии, которые
            # играются со второго.
            for запасной, зап_ид in источники[1:1 + ЗАПАСНЫХ_ПЕРЕД_ПОНИЖЕНИЕМ]:
                доп = спрашивать(издатель, домен, запасной, зап_ид, огр)
                итог["asked"] += 1
                доп_тело = доп.get("payload") or {}
                if доп.get("http") != 200:
                    continue
                доп_имя = свернуть(доп_тело.get("titleName"))
                if доп_имя and доп_имя != имя_с:
                    continue
                доп_сезоны, доп_пропущено = серии_по_сезонам(доп_тело)
                итог["unplaced_tracks"] += доп_пропущено
                for номер, номера in доп_сезоны.items():
                    по_сезонам.setdefault(номер, set()).update(номера)
            план = спланировать(деталь.get("seasons") or [], по_сезонам)

        if план["changes"]:
            итог["planned"].append({"slug": слаг, "id": ид,
                                    "aggregator": агрегатор,
                                    "seasons": план["changes"]})
        for имя in ("overstated", "eps_behind"):
            for запись in план[имя]:
                итог[имя].append(dict(запись, slug=слаг))
    return итог


def выполнить(*, каталог_данных: Path, site_id: str, домен: str, издатель: str,
              бюджет: int, доля_срочных: float, свежее_года: int, rps: float,
              применить: bool, предел_секунд: float = 540.0,
              только: list | None = None, модуль=None, спрашивать=None) -> dict:
    """Один прогон: отбор, опрос, наложение на свежий снимок, отчёт."""
    модуль = модуль or рендерер()
    спрашивать = спрашивать or спросить
    снимок_путь = каталог_данных / f"{site_id}-details.json"
    позиции_путь = каталог_данных / f".{site_id}-episode-ring.json"
    отчёт_путь = каталог_данных / f"{site_id}-episode-availability.json"

    снимок = прочитать_json(снимок_путь, None)
    if not isinstance(снимок, dict) or not isinstance(снимок.get("details"), dict):
        return {"status": "NO_SNAPSHOT", "path": str(снимок_путь)}
    детали = снимок["details"]
    ревизия = str(снимок.get("catalog_revision") or "")
    позиции = прочитать_json(позиции_путь, {}) or {}
    прошлый = прочитать_json(отчёт_путь, {}) or {}

    if только:
        очередь, растут, прочие = list(только), [], []
        срочный_список, остаток_срочных = [], []
    else:
        растут, прочие = кандидаты(детали, модуль, свежее_года)
        срочный_список = [с for с in срочные(прошлый, ревизия) if с in детали]
        # Срочным отдаётся весь бюджет: это записи, про которые уже известно,
        # что конвейер отдаёт их неверно. Обход подождёт прогон.
        взять_срочных = min(len(срочный_список),
                            max(int(бюджет * доля_срочных), бюджет))
        очередь = срочный_список[:взять_срочных]
        остаток_срочных = срочный_список[взять_срочных:]
        осталось = бюджет - len(очередь)
        # Растущим отдаётся большая часть остатка: новая серия появляется там.
        из_растущих = отрезок(растут, str(позиции.get("growing") or ""),
                              min(len(растут), int(осталось * 0.75)))
        очередь += [с for с in из_растущих if с not in set(очередь)]
        очередь += [с for с in отрезок(прочие, str(позиции.get("rest") or ""),
                                       бюджет - len(очередь))
                    if с not in set(очередь)]

    начато = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    итог = опросить(слаги=очередь, детали=детали, модуль=модуль,
                    издатель=издатель, домен=домен, огр=Ограничитель(rps),
                    спрашивать=спрашивать, предел_секунд=предел_секунд)

    отчёт = {
        "status": "OK", "site_id": site_id, "mode": "only" if только else "ring",
        "started_at": начато,
        "catalog_built_at": str(снимок.get("catalog_built_at") or ""),
        "catalog_revision": ревизия,
        "queue": {"urgent": len(срочный_список), "urgent_left": len(остаток_срочных),
                  "growing": len(растут), "rest": len(прочие),
                  "asked_slugs": len(очередь)},
        "snapshot_changed": False, "write_skipped_stale": False,
    }
    отчёт.update({к: итог[к] for к in
                  ("asked", "overstated", "eps_behind", "entity_mismatch",
                   "no_content", "http_error", "no_name", "unplaced_tracks",
                   "answers", "stopped_early")})
    отчёт["changed"] = []
    отчёт["watchlist"] = []
    отчёт["urgent_pending"] = остаток_срочных

    # Большая копия больше не нужна: правки лягут на свежее чтение.
    план = итог["planned"]
    del снимок, детали
    gc.collect()

    if применить:
        if not только:
            позиции_новые = dict(позиции)
            в_растущих = [с for с in очередь if с in set(растут)]
            в_прочих = [с for с in очередь if с in set(прочие)]
            if в_растущих:
                позиции_новые["growing"] = в_растущих[-1]
            if в_прочих:
                позиции_новые["rest"] = в_прочих[-1]
            позиции_новые["at"] = начато
            записать_атомарно(позиции_путь, json.dumps(
                позиции_новые, ensure_ascii=False, indent=2) + "\n")
        if план:
            отчёт.update(наложить(снимок_путь, план))
        # Список наблюдения дополняется ДО записи отчёта и переживает прогоны,
        # в которых ничего не менялось: иначе один спокойный прогон стёр бы
        # память, и после доставки записи ждали бы общего обхода.
        отчёт["watchlist"] = список_наблюдения(
            прошлый, [з["slug"] for з in отчёт["changed"]]
            + [з["slug"] for з in отчёт["overstated"]]
            + [з["slug"] for з in план])
        записать_атомарно(отчёт_путь,
                          json.dumps(отчёт, ensure_ascii=False, indent=2) + "\n")
        if отчёт["snapshot_changed"]:
            (каталог_данных / ОТМЕТКА_ПЕРЕЗАПУСКА).write_text(
                начато + "\n", encoding="utf-8")
    else:
        отчёт["changed"] = план
        отчёт["watchlist"] = список_наблюдения(
            прошлый, [з["slug"] for з in план]
            + [з["slug"] for з in отчёт["overstated"]])
    отчёт["finished_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    return отчёт


def наложить(снимок_путь: Path, план: list) -> dict:
    """Перечитать снимок и наложить план, если файл не сменился под нами."""
    метка = отпечаток(снимок_путь)
    свежий = прочитать_json(снимок_путь, None)
    if not isinstance(свежий, dict) or not isinstance(свежий.get("details"), dict):
        return {"changed": [], "write_skipped_stale": True}
    детали = свежий["details"]
    легло = []
    for запись in план:
        деталь = детали.get(запись["slug"])
        if not isinstance(деталь, dict):
            continue
        правки = применить_план(деталь, запись["seasons"])
        if правки:
            легло.append(dict(запись, seasons=правки))
    if not легло:
        return {"changed": [], "write_skipped_stale": False}
    текст = json.dumps(свежий, ensure_ascii=False, sort_keys=True)
    del свежий, детали
    gc.collect()
    try:
        записалось = записать_атомарно(снимок_путь, текст, ожидаемый=метка)
    except OSError as ош:
        return {"changed": [], "write_skipped_stale": True,
                "write_error": f"{type(ош).__name__}: {str(ош)[:120]}"}
    if not записалось:
        return {"changed": [], "write_skipped_stale": True}
    return {"changed": легло, "snapshot_changed": True,
            "write_skipped_stale": False}


def настройки() -> dict:
    """Домен и издатель — из объявлений сайта, а не из аргументов запуска.

    Значение издателя живёт вне Git и приезжает файлом; путь к нему объявлен
    там же, где его объявляет рантайм. Наружу оно не печатается.
    """
    конфиг = json.loads((КОРЕНЬ / "config" / "site.json").read_text(encoding="utf-8"))
    путь = os.environ.get("LORDS_PLAYER_CONFIG") or str(КОРЕНЬ / "config" / "player.json")
    плеер = прочитать_json(Path(путь), {}) or {}
    издатель = str(плеер.get("publisher_id") or "").strip()
    ожидается = str(конфиг.get("publisher_id_expected") or "").strip()
    if ожидается and издатель and издатель != ожидается:
        raise SystemExit("publisher_id из файла плеера не совпал с объявленным "
                         "в config/site.json: спрашивать провайдера чужим "
                         "идентификатором нельзя")
    return {"site_id": конфиг["site_id"], "домен": конфиг["domain"],
            "издатель": издатель}


def main(argv=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--data-dir", required=True)
    р.add_argument("--budget", type=int, default=48,
                   help="сколько записей спрашивать за прогон")
    р.add_argument("--urgent-share", type=float, default=0.5,
                   help="доля бюджета срочным после смены ревизии каталога")
    р.add_argument("--fresh-since", type=int, default=0,
                   help="год, с которого сериал считается свежим; 0 — прошлый")
    р.add_argument("--rps", type=float, default=1.5)
    р.add_argument("--deadline", type=float, default=540.0,
                   help="предел прогона в секундах; дальше пишем что успели")
    р.add_argument("--dry-run", action="store_true",
                   help="спросить и показать, ничего не записывая")
    р.add_argument("--only", default="",
                   help="слаги через запятую: спросить только их, без кольца")
    args = р.parse_args(argv)

    настройка = настройки()
    if not настройка["издатель"]:
        print("нет publisher_id: спрашивать провайдера нечем", file=sys.stderr)
        return 78
    отчёт = выполнить(
        каталог_данных=Path(args.data_dir), site_id=настройка["site_id"],
        домен=настройка["домен"], издатель=настройка["издатель"],
        бюджет=args.budget, доля_срочных=args.urgent_share,
        свежее_года=args.fresh_since or (time.gmtime().tm_year - 1),
        rps=args.rps, применить=not args.dry_run, предел_секунд=args.deadline,
        только=[с.strip() for с in args.only.split(",") if с.strip()] or None)
    print(json.dumps(отчёт, ensure_ascii=False, indent=2))
    return 0 if отчёт.get("status") == "OK" else 1


if __name__ == "__main__":
    raise SystemExit(main())
