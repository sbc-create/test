#!/usr/bin/env python3
"""Согласование `seasons[].avail` снимка ячейки со свежим ответом провайдера.

Что гасит плеер
---------------

Плеер на странице серии включает одно условие рендерера — `серия_с_дорожкой`:
номер серии обязан попасть в `seasons[].avail` снимка подробностей. Число это
на странице не вычисляется, оно приезжает снимком, а снимок собирается раз в
сутки. Отсюда два разных отказа, и оба наблюдались на живых витринах.

ОТСТАВАНИЕ. `/title/master-omyur/` (Мастер Омюр,
`01a0e45a-ba66-7613-879c-f209068f60e3`): снимок собран 2026-09-28 в 03:18Z,
подробности спрошены у источника в 03:48Z и честно ответили `available=0`.
Озвучки первой серии источник завёл в 09:11:56Z (субтитры) и 10:18:19Z
(многоголосый) — уже после снимка. В 13:49Z плейлист отдавал по этой записи
две дорожки на s1e1, а витрина продолжала отвечать «Дорожки этой серии ещё
нет»: до следующей суточной сборки оставалось четырнадцать часов.

Между сборками источник у этой витрины не спрашивает никто. Частый опрос,
которому `nova-daily-refresh.sh` отдал урезанный бюджет подробностей
(6000 → 500 записей в сутки), в контуре отсутствует: юнита `nova-episode-poll`
нет ни в systemd, ни в репозитории фабрики — только ссылка на него в
комментарии.

СЧЁТ ВМЕСТО НОМЕРА. `/title/skotty/` (Скотты,
`01a0e27f-8175-7115-8972-83cce31b15d3`): снимок объявляет `avail=1, eps=6`,
хаб выбирает первую серию, рендерер поднимает `<video-player episode="1">`,
а у провайдера по этой записи ровно одна дорожка — `Pilot`, **season 1,
episode 0**. Проверено 2026-09-28 в 14:05Z. Серии с номером 1 у источника
нет, и провайдер отвечает noData; страница показывает «Провайдер не отдал
источник» при карточке «доступно 1».

Причина не в опоздании, а в несовпадении смыслов. Источник отдаёт
`available_episodes_count` — СКОЛЬКО серий доступно. Рендерер читает `avail`
как НОМЕР последней доступной: `серия_с_дорожкой` = `эпизод <= avail`. Пока
нумерация начинается с единицы и идёт подряд, эти два числа совпадают; на
спецвыпуске с номером 0 и на сериале с пропусками — расходятся, и витрина
обещает серию, которой у провайдера нет.

Чем это лечится здесь
---------------------

Спрашивается ТОТ ЖЕ плейлист, который откроет браузер посетителя, и теми же
идентификаторами, что поставит на страницу рендерер: и порядок кандидатов, и
зависимость от `source_mode` берутся из его собственных функций, а не из
второй копии правила.

`avail` приводится к ДЛИНЕ НЕПРЕРЫВНОГО РЯДА ОТ ПЕРВОЙ СЕРИИ — ровно к тому,
что означает это поле для рендерера. Из {1,2,3} выходит 3, из {1,3} — 1, из
{0} — ноль.

ПОВЫШЕНИЕ разрешено всегда, когда ряд длиннее записанного (но не выше
объявленного `eps`: состав сезона ведёт конвейер).

ПОНИЖЕНИЕ разрешено ровно в одном случае: провайдер вернул сезон, и в нём НЕТ
НИ ОДНОЙ серии с номером от единицы. Это случай «Скоттов»: витрина обещает
просмотр, а отдать нечего. Перед понижением спрашиваются и ОСТАЛЬНЫЕ кандидаты
записи — страница отдаёт их браузеру списком и перебирает по очереди, поэтому
понижать по ответу одного значило бы снять серии, которые играются со второго.

Никакой другой формы понижения здесь нет, и это не осторожность ради
осторожности. У «Санта-Барбары» (`0199157a-45a5-720e-8cb2-3e40a5c5af1b`)
провайдер отдаёт 1776 дорожек с номерами от 1 до 2043, непрерывный ряд от
первой обрывается на 92-й, а в снимке стоит 1776. Понижать по длине ряда
значило бы снять со страницы 1684 серии, которые у источника есть. Такие
расхождения попадают в отчёт полем `overstated` и чинятся не здесь: одно число
не может описать множество с пропусками, и это дефект контракта, а не снимка.

Сезон, которого в ответе провайдера нет вовсе, не трогается ни в какую
сторону: это либо расхождение нумерации, либо неполный ответ, и доказательством
отсутствия он не является.

Порядок опроса
--------------

Кандидатов — все сериалы каталога (двадцать тысяч записей): у записи с полным
`avail` ложным может оказаться само обещание, как у «Скоттов», поэтому сузить
отбор до растущих нельзя. Круг по всем при бюджете прогона в полсотни идёт
несколько суток, и одного круга мало. Поэтому очередь трёхслойная:

  срочные — слаги, которые прошлый прогон уже правил или пометил спорными,
            спрашиваются первыми, как только сменилась ревизия каталога:
            суточная доставка возвращает прежние числа, и именно эти записи
            обязаны выправиться в ближайшие минуты, а не когда до них дойдёт
            круг;
  растущие — сезоны с `avail < eps`, где серия может появиться;
  прочие   — остальные сериалы, медленным обходом.

Чего инструмент не делает
-------------------------

Не поднимает `eps`, не трогает каталог, оценки, комментарии, разметку,
пользовательские данные, соседние сайты и общий шаблон. Не перезапускает
службу — прав на это у него нет; изменив снимок, он оставляет отметку, а
перезапуск делает привилегированная сторона юнита. Вторым производителем
снимка не становится: правки накладываются на СВЕЖЕ ПЕРЕЧИТАННЫЙ файл, и если
конвейер положил новое поколение, пока шёл опрос, запись отменяется целиком —
доставка конвейера всегда старше не бывает.
"""
