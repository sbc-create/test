def остатки_animedia(текст: str) -> list:
    return [f"нет: {имя}" for имя, _, _, признак in AM_ПАРЫ if признак not in текст]


def применить_animedia(текст: str) -> tuple:
    """Перенос на линию Animedia. Своим набором якорей, без подгонки."""
    журнал = []
    for имя, было, стало, признак in AM_ПАРЫ:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
    return текст, журнал


def остатки(текст: str) -> list:
    """Чего не хватает, чтобы перенос считался выполненным."""
    плохо = []
    if "РУЧНЫЕ_ПОДБОРКИ" not in текст:
        плохо.append("нет загрузки файла подборок")
    if "if ключ in ЗАКРЫТЫЕ_ПОДБОРКИ:" not in текст:
        плохо.append("закрытая подборка не закрывается на своём пути")
    if "[a-z0-9_-]{1,60}" not in текст:
        плохо.append("маршрут коллекции не принимает дефис")
    if "def ручная_подборка" not in текст:
        плохо.append("нет страницы ручной подборки")
    if "ручная = РУЧНЫЕ_ПОДБОРКИ.get(ключ)" not in текст:
        плохо.append("маршрут не решает ручную подборку")
    if текст.count("подборка_ред in РУЧНЫЕ_ПОДБОРКИ.values()") < 2:
        плохо.append("ссылок на подборку нет и в полосе главной, и в хабе")
    if "self._полоса_подборок_раздела(разд, стр)" not in текст:
        плохо.append("с раздела-владельца на подборку не ведёт ничего")
    # Одно вхождение остаётся законно: легаси-оболочка `оболочка(тело, титул,
    # д, актив)` пути не получает, и подставить его ей нечем. Больше одного —
    # значит оболочка страницы считает директиву мимо пути.
    лишние = текст.count(МЕТА_БЫЛО)
    if лишние > 1:
        плохо.append(f"мета robots считается без пути в {лишние} оболочках")
    if ".col__why{" not in текст:
        плохо.append("нет стиля пояснения карточки")
    return плохо


def применить(текст: str) -> tuple[str, list]:
    журнал = []
    # Линия Animedia опознаётся по единственному сборщику карточек коллекций.
    # Её проверяем ПЕРВОЙ: у её оболочки тоже есть `индексируема`, и общее
    # условие ниже приняло бы её за канон.
    if "def _карточки_коллекций(self)" in текст:
        return применить_animedia(текст)
    # Канонический рантайм опознаётся вторым: у него механизм уже есть, и
    # отказ обязан назвать именно это, а не «файл не той линии». Иначе
    # оператор пойдёт искать несуществующую беду в каноне.
    if "индексируема" in текст or "_схемы_страницы" in текст:
        raise SystemExit("ОТКАЗ: это канонический рантайм (у его оболочки есть "
                         "`индексируема`), механизм в нём уже принят — у него "
                         "свой путь переноса")
    if "_ld_json_scripts" not in текст:
        raise SystemExit("ОТКАЗ: это не рантайм линии Zona — нет "
                         "_ld_json_scripts, принимающего список схем")

    пары = [
        ("загрузка файла подборок", ЯКОРЬ_ЗАГРУЗКИ, ЗАГРУЗКА + ЯКОРЬ_ЗАГРУЗКИ,
         "РУЧНЫЕ_ПОДБОРКИ"),
        ("закрытая подборка на своём пути", РОБОТЫ_БЫЛО, РОБОТЫ_СТАЛО,
         "if ключ in ЗАКРЫТЫЕ_ПОДБОРКИ:"),
        ("маршрут принимает дефис", МАРШРУТ_БЫЛО, МАРШРУТ_СТАЛО,
         "[a-z0-9_-]{1,60}"),
        ("ветвь ручной подборки", ВЕТВЬ_БЫЛО, ВЕТВЬ_СТАЛО,
         "ручная = РУЧНЫЕ_ПОДБОРКИ.get(ключ)"),
        ("страница ручной подборки", ЯКОРЬ_СТРАНИЦЫ, СТРАНИЦА + ЯКОРЬ_СТРАНИЦЫ,
         "def ручная_подборка"),
        ("полоса главной", ПОЛОСА_БЫЛО, ПОЛОСА_СТАЛО, "подборка_ред in РУЧНЫЕ_ПОДБОРКИ"),
        ("хаб подборок", ХАБ_БЫЛО, ХАБ_СТАЛО, "подборка_ред.viewer_request"),
        ("полоса раздела", ЯКОРЬ_ПОЛОСЫ_РАЗДЕЛА,
         ПОЛОСА_РАЗДЕЛА + ЯКОРЬ_ПОЛОСЫ_РАЗДЕЛА, "def _полоса_подборок_раздела"),
        ("вызов полосы раздела", РАЗДЕЛ_БЫЛО, РАЗДЕЛ_СТАЛО,
         "self._полоса_подборок_раздела(разд, стр)"),
        ("стиль пояснения", ЯКОРЬ_СТИЛЯ, СТИЛЬ + ЯКОРЬ_СТИЛЯ, ".col__why{"),
    ]
    for имя, было, стало, признак in пары:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")

    # Мета-тег во ВСЕХ оболочках, у которых есть `путь`. Легаси-оболочка без
    # пути остаётся как была: подставить ей путь нечем, и выдумывать нельзя.
    сколько = текст.count(МЕТА_БЫЛО)
    if сколько:
        заменено = 0
        куски = текст.split(МЕТА_БЫЛО)
        собрано = [куски[0]]
        for кусок in куски[1:]:
            # Легаси-оболочка опознаётся по подписи без `путь` перед тегом.
            предыдущий = собрано[-1]
            можно = "def оболочка(тело: str, титул: str, д: Данные" not in \
                предыдущий[-1200:]
            собрано.append((МЕТА_СТАЛО if можно else МЕТА_БЫЛО) + кусок)
            заменено += int(можно)
        текст = "".join(собрано)
        журнал.append(f"применено ×{заменено}: мета robots считается по пути")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true",
                   help="только сказать, приведён ли файл; ничего не писать")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        контракт = ЯКОРЬ_КОНТРАКТА in исходный and "class Снимок:" in исходный
        if а.check:
            if контракт:
                п = остатки_контракта(исходный)
            elif "def _карточки_коллекций(self)" in исходный:
                п = остатки_animedia(исходный)
            else:
                п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = (применить_контракт(исходный) if контракт
                         else применить(исходный))
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        п = (остатки_контракта(новый) if контракт else
             остатки_animedia(новый)
             if "def _карточки_коллекций(self)" in новый else остатки(новый))
        if п:
            print(f"ОТКАЗ: после правки остались признаки непривёденности: {п}",
                  file=sys.stderr)
            return 1
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
