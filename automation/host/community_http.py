            f'<form method="post" action="/community/comment/decide" '
            f'class="cm__act">{общее}'
            f'<button class="cm__btn cm__btn--q" name="decision" '
            f'value="{МОДУЛЬ.СТАТУС_ОДОБРЕН}">Одобрить</button> '
