def блок(вид, запись: dict, деталь: dict) -> str:
    """Раздел «Оценка зрителей» и подблок «Комментарии» страницы произведения."""
    if МОДУЛЬ is None:
        return _выключено("модуль сообщества не подключён к сборке")
    х = хранилище()
    if х is None:
        return _выключено("путь к хранилищу не задан")
    if not х.доступно:
        return _выключено(х.причина or "хранилище недоступно")
    ключ = тема(запись, деталь)
    if not ключ:
        return _выключено("у записи нет постоянного идентификатора")
    обработчик = getattr(вид, "обработчик", None)
    посетитель = ключ_посетителя(обработчик) if обработчик is not None else ""
    я_модератор = модератор(обработчик) if обработчик is not None else False
    slug = запись["slug"]
    try:
        с = х.состояние(ключ, посетитель, модератор=я_модератор, slug=slug)
    except (OSError, ValueError, RuntimeError) as ош:
        return _выключено(f"{type(ош).__name__}: {ош}")

    токен = csrf(обработчик) if обработчик is not None else ""
    назад = f"/title/{slug}/"
    скрытые = (
        f'<input type="hidden" name="subject" value="{html.escape(ключ, quote=True)}">'
        f'<input type="hidden" name="slug" value="{html.escape(slug, quote=True)}">'
        f'<input type="hidden" name="back" value="{html.escape(назад, quote=True)}">'
        f'<input type="hidden" name="csrf" value="{html.escape(токен, quote=True)}">')

    зпр = getattr(вид, "запрос", None) or {}
    черновик = взять_черновик(обработчик)
    лента = "".join(_сообщение_ленты(к, скрытые, я_модератор) for к in с.комментарии)
    очередь = ""
    if я_модератор and с.ожидающие:
        строки = "".join(_сообщение_ленты(к, скрытые, True) for к in с.ожидающие)
        очередь = (f'<div class="cmt__mod"><h4 class="cmt__modh">На модерации '
                   f'({с.всего_на_модерации})</h4>'
                   f'<ul class="cm__l">{строки}</ul></div>')
    лента_html = (f'<ul class="cm__l">{лента}</ul>' if лента else
                  '<p class="cmt__empty">Сообщений пока нет. Ваше станет первым.</p>')
    видимых = len(с.комментарии)
    счётчик = f'<span class="cmt__n">{видимых}</span>' if видимых else ""

    return (
        f'<section class="cm" id="community" data-community="on" '
        f'data-community-votes="{int(с.голосов)}" '
        f'data-community-comments="{видимых}" '
        f'data-community-pending="{int(с.всего_на_модерации)}">'
        f"{ЗВЕЗДА_SVG}"
        "<h2>Оценка зрителей</h2>"
        '<p class="cm__sub">Это оценка посетителей сайта. '
        "Оценки IMDb и Кинопоиска показаны отдельно, выше: это разные величины.</p>"
        f"{_сообщение(зпр, 'vote')}"
        f"{_форма_оценки(с, скрытые)}"
        f'<div class="cmt" id="comments">'
        f'<h3 class="cmt__h">Комментарии{счётчик}</h3>'
        f"{_сообщение(зпр, 'comment')}"
        f"{_форма_комментария(скрытые, черновик)}"
        f"{лента_html}{очередь}"
        "</div>"
        "</section>")


def очередь_модерации(обработчик) -> tuple[bool, str]:
    """Сводная очередь модерации. Доступ проверяется СЕРВЕРОМ.

    Возвращает (доступно, html). Отказ не объясняет, чем именно ключ не подошёл.
    """
    if not модератор(обработчик):
        return False, ""
    х = хранилище()
    if х is None or not х.доступно:
        return True, '<p class="cmt__empty">Хранилище недоступно.</p>'
    строки = []
    for запись in х.очередь_модерации():
        тема_ = html.escape(str(запись.get("subject") or ""))
        slug = html.escape(str(запись.get("slug") or ""), quote=True)
        сообщений = int(запись.get("pending") or 0)
        строки.append(
            f'<li class="cm__i"><a href="/title/{slug}/#comments">{тема_}</a>'
            f' — {сообщений} {_склонение(сообщений, "сообщение", "сообщения", "сообщений")}'
            "</li>")
    if not строки:
        return True, '<p class="cmt__empty">Очередь пуста.</p>'
    return True, f'<ul class="cm__l">{"".join(строки)}</ul>'


#: Скрипт звёзд. Добавляет ровно две вещи, которых CSS дать не может:
#: предпросмотр при наведении в браузерах без `:has()` и текст подписи.
#:
#: Голос отсюда НЕ отправляется — ни при наведении, ни при выборе звезды.
#: Отправка остаётся за кнопкой, и это проверяется отдельно. Скрипт ничего не
#: перерисовывает за пределами группы звёзд, поэтому плеер он не трогает.
СКРИПТ_ЗВЁЗД = (
    "(function(){"
    "function поле(э){return э.closest('[data-rating-stars]');}"
    "function значение(г){var в=г.querySelector('input:checked');"
    "return в?parseInt(в.value,10):0;}"
    "document.addEventListener('mouseover',function(e){"
    "var s=e.target.closest?e.target.closest('.rt__s'):null;if(!s)return;"
    "var г=поле(s);if(!г||г.classList.contains('rt__stars--static'))return;"
    "var в=г.querySelectorAll('.rt__s'),n=0;"
    "for(var i=0;i<в.length;i++){if(в[i]===s){n=i+1;break;}}"
    "г.setAttribute('data-hover',n);});"
    "document.addEventListener('mouseout',function(e){"
    "var s=e.target.closest?e.target.closest('.rt__s'):null;if(!s)return;"
    "var г=поле(s);if(г&&!г.contains(e.relatedTarget))г.removeAttribute('data-hover');});"
    "document.addEventListener('change',function(e){"
    "var в=e.target;if(!в.classList||!в.classList.contains('rt__r'))return;"
    "var г=поле(в);if(!г)return;var n=значение(г);"
    "г.setAttribute('data-value',n);"
    "var ф=г.closest('form');if(!ф)return;"
    "var о=ф.querySelector('[data-rating-out]');"
    "if(о)о.textContent=n?'Ваша оценка: '+n+' из 10':'Ваша оценка: не выбрана';"
    "});"
    "})();"
)
