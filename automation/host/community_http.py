def _склонение(n: int, один: str, два: str, много: str) -> str:
    n = abs(int(n)) % 100
    if 11 <= n <= 14:
        return много
    n %= 10
    if n == 1:
        return один
    if 2 <= n <= 4:
        return два
    return много


def _сообщение(зпр: dict, для: str = "") -> str:
    """Строка об исходе действия, рядом с ТОЙ формой, которая его вызвала.

    Общая строка наверху раздела заставляла бы искать, к чему она относится.
    """
    код = (зпр.get("community") or [""])[0] if зпр else ""
    if not код:
        return ""
    источник = (зпр.get("from") or [""])[0] if зпр else ""
    if для and источник and источник != для:
        return ""
    if для and not источник and для != "vote":
        # Старая ссылка без пометки источника: показываем у оценки, как было.
        return ""
    if код == "error":
        почему = (зпр.get("why") or [""])[0]
        текст = почему or "Действие не выполнено."
        return f'<p class="cm__msg cm__msg--err">{html.escape(текст)}</p>'
    вид, текст = СООБЩЕНИЯ.get(код, ("err", "Действие не выполнено."))
    return f'<p class="cm__msg cm__msg--{вид}">{html.escape(текст)}</p>'


