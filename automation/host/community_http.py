def _звёзды(значение: int, только_показ: bool) -> str:
    """Десять звёзд шкалы 1–10.

    Радиокнопки выбраны не случайно — это единственный способ получить выбор
    мышью, касанием И клавиатурой без единой строки скрипта: стрелки
    переключают группу, пробел выбирает, `Tab` входит и выходит.

    Голос отсюда НЕ уходит: `<input>` ничего не отправляет сам, отправку делает
    кнопка формы. Это и требование владельца, и защита от случайного касания
    на телефоне.
    """
    части = []
    for n in range(1, МОДУЛЬ.ОЦЕНКА_МАКС + 1):
        значок = ('<svg class="rt__i" aria-hidden="true" focusable="false">'
                  '<use href="#cm-star"></use></svg>')
        if только_показ:
            части.append(f'<span class="rt__s">{значок}</span>')
            continue
        отмечено = " checked" if n == значение else ""
        части.append(
            f'<label class="rt__s">'
            f'<input class="rt__r" type="radio" name="value" value="{n}" '
            f'required{отмечено}>'
            f'{значок}<span class="vh">{n} из 10</span></label>')
    состояние = f' data-value="{значение}"' if значение else ""
    вид = " rt__stars--static" if только_показ else ""
    return (f'<div class="rt__stars{вид}"{состояние} data-rating-stars>'
            + "".join(части) + "</div>")


def _оценка_зрителей(с) -> str:
    """Среднее зрителей и число голосов — рядом со звёздами.

    Показывается СОБСТВЕННОЕ среднее, а не смешанная величина: внешние IMDb и
    КП живут отдельным блоком, и подмешивать их в строку с подписью «Оценка
    зрителей» значило бы называть чужое число своим.
    """
    if not с.голосов or с.средняя is None:
        return ('<p class="rt__avg rt__avg--none" data-community-votes="0">'
                "Пока нет оценок</p>")
    среднее = f"{с.средняя:.1f}".replace(".", ",")
    голосов = int(с.голосов)
    слово = _склонение(голосов, "голос", "голоса", "голосов")
    return (
        f'<p class="rt__avg" data-community-score="{html.escape(среднее, quote=True)}" '
        f'data-community-votes="{голосов}">'
        f'<span class="rt__avgv">{html.escape(среднее)}</span>'
        f'<span class="rt__avgs">из 10</span>'
        f'<span class="rt__avgn">{голосов}&nbsp;{слово}</span></p>')


def _форма_оценки(с, скрытые: str) -> str:
    """Блок «Оценка зрителей»: среднее, звёзды и подтверждение.

    Правило голосования принадлежит модулю: первая сохранённая оценка
    окончательна (`ГолосЗакреплён`), повторная отправка того же числа ничего не
    меняет. Поэтому проголосовавшему показывается результат, а не форма, и
    нигде не обещано, что оценку можно поменять. Нарисовать форму смены и
    «поддержать» её на клиенте было бы имитацией: сервер всё равно откажет.
    """
    if с.мой_голос:
        мой = int(с.мой_голос)
        return (
            f'<div class="rt" data-rating="done">'
            f'{_оценка_зрителей(с)}'
            f'{_звёзды(мой, True)}'
            f'<p class="rt__done" data-my-vote="{мой}">Вы оценили: '
            f"<b>{мой}</b> из 10</p>"
            f'<p class="rt__hint">Оценка ставится один раз и не меняется.</p>'
            "</div>")
    return (
        '<div class="rt" data-rating="form">'
        f"{_оценка_зрителей(с)}"
        '<form class="rt__f" method="post" action="/community/vote" '
        'data-community-form="vote">'
        f"{скрытые}"
        '<fieldset class="rt__set">'
        '<legend class="rt__lg">Ваша оценка</legend>'
        f"{_звёзды(0, False)}"
        '<output class="rt__out" data-rating-out>Ваша оценка: не выбрана</output>'
        "</fieldset>"
        '<button class="cm__btn rt__go" type="submit">Оценить</button>'
        '<p class="rt__hint">Оценка ставится один раз и не меняется. '
        "Голос сохраняется только по кнопке.</p>"
        "</form></div>")


def _значок_статуса(статус: str, моё: bool) -> str:
    """Подпись о состоянии сообщения.

    Формулировка для автора и для постороннего разная намеренно. Автор видит
    своё ожидающее сообщение в ленте — иначе он решит, что отправка не
    сработала, и напишет ещё раз, — и ему важно знать, что остальные его пока
    не видят.
    """
    if статус == МОДУЛЬ.СТАТУС_ОЖИДАЕТ:
        if моё:
            return ('<span class="cm__st cm__st--pending">'
                    "На проверке — видно только вам</span>")
        return '<span class="cm__st cm__st--pending">Ожидает проверки</span>'
    if статус == МОДУЛЬ.СТАТУС_ОТКЛОНЁН:
        return '<span class="cm__st cm__st--rejected">Отклонено</span>'
    return ""


def _дата(создано: str) -> str:
    """Дата сообщения по Москве. В хранилище время в UTC с суффиксом Z."""
    if not создано:
        return ""
    видимая = создано[:10]
    try:
        когда = datetime.datetime.strptime(создано[:19], "%Y-%m-%dT%H:%M:%S")
        когда = когда.replace(tzinfo=datetime.timezone.utc).astimezone(МОСКВА)
        видимая = когда.strftime("%d.%m.%Y, %H:%M")
    except (ValueError, TypeError):
        pass
    return (f'<time class="cm__dt" datetime="{html.escape(создано, quote=True)}">'
            f"{html.escape(видимая)}</time>")


def _сообщение_ленты(к: dict, скрытые: str, я_модератор: bool) -> str:
    статус = str(к.get("status") or МОДУЛЬ.СТАТУС_ПО_УМОЛЧАНИЮ)
    моё = bool(к.get("моё"))
    значок = _значок_статуса(статус, моё)
    ид = html.escape(str(к.get("id") or ""), quote=True)
    классы = ["cm__i"]
    if str(к.get("parent_id") or ""):
        классы.append("cm__i--reply")
    if статус == МОДУЛЬ.СТАТУС_ОЖИДАЕТ:
        классы.append("cm__i--pending")
    действия = ""
    if моё or я_модератор:
        общее = f'{скрытые}<input type="hidden" name="id" value="{ид}">'
        действия = (
            f'<form method="post" action="/community/comment/delete" '
            f'class="cm__act">{общее}'
            f'<button class="cm__btn cm__btn--q" type="submit">Удалить</button></form>')
    решение = ""
    if я_модератор and статус != МОДУЛЬ.СТАТУС_ОДОБРЕН:
        общее = f'{скрытые}<input type="hidden" name="id" value="{ид}">'
