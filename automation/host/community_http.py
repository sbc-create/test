"""Обвязка HTTP канонического модуля сообщества — одна на семейство.

Что здесь есть и чего здесь нет
-------------------------------

Здесь НЕТ собственного хранилища оценок и комментариев, собственных правил
модерации и собственной защиты от заливки. Всё это написано один раз — в
каноническом модуле `community.py` (выпуск `20260923T190000Z-community-2-2-12`,
sha256 закреплён в `pins.lock.json` витрины). Вторая реализация тех же правил
разошлась бы с первой на первой же правке.

Здесь ЕСТЬ обвязка HTTP: формы, токен двойной отправки, кука посетителя,
маршруты `/community/*`, разметка раздела и страница модерации.

Почему она появилась именно здесь. У Animedia обвязка живёт ВНУТРИ
`animedia-frontend.py` — около 390 строк, — и семейству Lords недоступна.
Поэтому lords-02 и lords-03 воспроизвели один и тот же контракт дословно и по
отдельности: две копии одной обвязки, которые обязаны расходиться. Третьего
воспроизведения не будет: модуль вынесен в общий рантайм и настраивается
параметрами, а не копированием.

Что настраивается витриной (`Настройка`)
----------------------------------------

Имя куки посетителя, имя куки модератора, соль токена и имя переменной с
ключом модератора. Именно этот набор назван в заявках обоих сайтов
(lords-02 `docs/ЗАЯВКА-СООБЩЕСТВО.md` п. 2, lords-03 то же) как то, что должно
параметризоваться. Имена у каждой витрины СВОИ: одна кука на два домена
означала бы один голос на два сайта.

Контракт, который НЕ настраивается
-----------------------------------

Адреса `/community/*`, способ вывода токена из куки посетителя, ответ
перенаправлением `303 …?community=ok`, вызовы хранилища и трактовка модератора
(ключ из окружения; пустой ключ означает «модератора нет», а не «модератор
любой»). Он совпадает с контрактом Animedia дословно — в этом и смысл.

Правила голосования и модерации не переопределяются
----------------------------------------------------

Первая сохранённая оценка окончательна, новое сообщение ждёт разбора, ответы
ровно на один уровень, интервал между сообщениями — всё это решает модуль.
В частности, «изменить свой голос» модуль НЕ поддерживает намеренно
(`ГолосЗакреплён`). Интерфейс отражает это честно: проголосовавшему
показывается его оценка и подпись «ставится один раз и не меняется», а формы
смены нет. Имитировать смену на клиенте нельзя: сервер всё равно откажет, и
посетитель увидит другое число, чем сохранено.

Ключ темы
---------

Тема — ПОСТОЯННЫЙ идентификатор произведения (`details[slug]["id"]`), а не
адрес: slug меняется правкой названия, и вместе с ним уехали бы все оценки.
Адрес передаётся рядом, потому что модуль умеет переносить записи, заведённые
под ним.

Чего не хватает в общем модуле (передано владельцу)
----------------------------------------------------

`community_ratings_overlay.py` знает пространства `animedia` и `yummy` и не
знает `lords`. Поэтому проекция внешних оценок сообщества на витринах Lords не
показывается — и не подделывается. Заявка — `docs/handoff/`.
"""
from __future__ import annotations

import datetime
import hashlib
import html
import json
import os
import secrets
from dataclasses import dataclass
from urllib.parse import quote, unquote

#: Проставляются при подключении к рантайму.
ЯДРО = None
МОДУЛЬ = None

#: Даты сообщений показываются по Москве: витрины русскоязычные, и «вчера в
#: 23:40» по Гринвичу читается как позавчера.
МОСКВА = datetime.timezone(datetime.timedelta(hours=3))

#: Черновик несохранённого сообщения. Отправка отвечает перенаправлением (303),
#: иначе обновление страницы отправляло бы сообщение второй раз, — но при
#: отказе вместе с ответом пропадал и набранный текст. Кука живёт пять минут,
#: читается один раз и тут же гасится: это не хранилище, а перенос через один
#: редирект.
ЖИЗНЬ_ЧЕРНОВИКА = 300

СООБЩЕНИЯ = {
    "ok": ("ok", "Принято."),
    "csrf": ("err", "Форма устарела: обновите страницу и повторите."),
    "unavailable": ("err", "Раздел сообщества сейчас недоступен: "
                           "хранилище не отвечает."),
    "forbidden": ("err", "Это действие доступно только модератору."),
}


@dataclass(frozen=True)
class Настройка:
    """То, что у каждой витрины своё. Всё остальное — контракт."""

    site_id: str
    кука_посетителя: str
    кука_модератора: str
    кука_черновика: str
    соль_csrf: str
    ключ_модератора_env: str
    путь_env: str

    @classmethod
    def для(cls, site_id: str, домен: str) -> "Настройка":
        """Имена выводятся из site_id, а не задаются вручную.

        Забытая правка одного из четырёх имён при заведении следующего сайта
        означала бы общую куку на два домена, то есть один голос на две
        витрины. Выводить их из site_id дешевле, чем помнить.
        """
        краткий = site_id.replace("-", "_")
        верхний = краткий.upper()
        return cls(
            site_id=site_id,
            кука_посетителя=f"{краткий}_v",
            кука_модератора=f"{краткий}_mod",
            кука_черновика=f"{краткий}_draft",
            # Домен в соли намеренно: токен одной витрины не должен подходить
            # к форме другой.
            соль_csrf=f"{домен or site_id}-community-csrf/1:",
            ключ_модератора_env=f"{верхний}_COMMUNITY_MODERATOR_KEY",
            путь_env=f"{верхний}_COMMUNITY",
        )


НАСТРОЙКА: Настройка | None = None
_ХРАНИЛИЩЕ = {"значение": None, "открыто": False}


def подключить(ядро, настройка: Настройка) -> None:
    """Связать обвязку с рантаймом витрины и её настройкой."""
    global ЯДРО, МОДУЛЬ, НАСТРОЙКА
    ЯДРО = ядро
    НАСТРОЙКА = настройка
    try:
        import community as М
    except ImportError:
        # Модуль приезжает в ячейку отдельным выпуском и закрепляется по
        # версии. Его отсутствие — законное состояние сборки, а не авария:
        # раздел покажется выключенным и скажет, чего не хватает.
        М = None
    МОДУЛЬ = М
    _ХРАНИЛИЩЕ["значение"] = None
    _ХРАНИЛИЩЕ["открыто"] = False


def подключён() -> bool:
    return МОДУЛЬ is not None and НАСТРОЙКА is not None


def путь_хранилища() -> str:
    """Файл сообщества рядом с данными витрины, а не в дереве кода."""
    if НАСТРОЙКА is None:
        return ""
    явный = os.environ.get(НАСТРОЙКА.путь_env, "").strip()
    if явный:
        return явный
    return (ЯДРО._рядом_с_каталогом("{site}-community.json") if ЯДРО else "") or ""


def хранилище():
    """Хранилище витрины или None. Открывается один раз на процесс."""
    if _ХРАНИЛИЩЕ["открыто"]:
        return _ХРАНИЛИЩЕ["значение"]
    _ХРАНИЛИЩЕ["открыто"] = True
    if МОДУЛЬ is None or НАСТРОЙКА is None:
        return None
    путь = путь_хранилища()
    if not путь:
        return None
    # Идентификатор КОНКРЕТНОГО сайта, не семейства: чужие записи этот файл не
    # обслуживает, и модуль это проверяет сам, изнутри базы.
    _ХРАНИЛИЩЕ["значение"] = МОДУЛЬ.открыть(путь, витрина=НАСТРОЙКА.site_id)
    return _ХРАНИЛИЩЕ["значение"]


def тема(запись: dict, деталь: dict) -> str:
    """Ключ темы — постоянный идентификатор, а не адрес.

    Slug меняется правкой названия; будь он ключом, вместе с ним уехали бы все
    оценки и комментарии произведения.
    """
    ид = str((деталь or {}).get("id") or "").strip()
    return ид or str((запись or {}).get("slug") or "").strip()


def внешние_для_базы(деталь: dict) -> dict:
    """Внешние оценки для выбора базы расчёта.

    Оценка зрителей витрины в базу не входит: иначе их мнение вошло бы в
    формулу дважды — и базой, и голосами.
    """
    итог = {}
    источники = getattr(ЯДРО, "оценки_по_источникам", None)
    if источники is None:
        return итог
    for о in источники(деталь or {}):
        if о.get("пользовательская"):
            continue
        итог[о["ключ"]] = {"value": о["значение"], "scale": о["шкала"]}
    return итог


# --- сторона обработчика ----------------------------------------------------


def _кука(обработчик, имя: str) -> str:
    сырое = (getattr(обработчик, "headers", None) or {}).get("Cookie") or ""
    for кусок in сырое.split(";"):
        ключ, _, значение = кусок.strip().partition("=")
        if ключ == имя and значение:
            return значение
    return ""


def подготовить_посетителя(обработчик) -> None:
    """Ключ посетителя на этот запрос; если куки нет — выдать новую."""
    if НАСТРОЙКА is None:
        return
    кука = _кука(обработчик, НАСТРОЙКА.кука_посетителя)[:128]
    обработчик._новая_кука = ""
    if not кука:
        кука = secrets.token_urlsafe(16)
        обработчик._новая_кука = кука
    обработчик._куки_посетителя = кука


def заголовок_куки(обработчик) -> str:
    """Значение `Set-Cookie`, если куку выдали в этом ответе.

    Кука выдаётся на ЛЮБОМ ответе, а не только на перенаправлении: иначе
    посетитель, пришедший сразу на страницу произведения, получал форму с
    пустым токеном и первая отправка отбивалась как подделка.
    """
    новая = getattr(обработчик, "_новая_кука", "")
    if not новая or НАСТРОЙКА is None:
        return ""
    return (f"{НАСТРОЙКА.кука_посетителя}={новая}; Path=/; Max-Age=31536000; "
            "SameSite=Lax; HttpOnly")


def ключ_посетителя(обработчик) -> str:
    return getattr(обработчик, "_куки_посетителя", "") or ""


def добавить_куку(обработчик, значение: str) -> None:
    if обработчик is None:
        return
    список = getattr(обработчик, "_доп_куки", None)
    if список is None:
        список = []
        обработчик._доп_куки = список
    список.append(значение)


def запомнить_черновик(обработчик, имя: str, текст: str) -> None:
    """Сохранить несохранённое сообщение до следующей отрисовки страницы.

    Только при ОТКАЗЕ: после успеха черновик не нужен, а лишняя кука с текстом
    посетителя — лишний след.
    """
    if НАСТРОЙКА is None:
        return
    полезное = json.dumps({"n": (имя or "")[:40], "t": (текст or "")[:2000]},
                          ensure_ascii=False, separators=(",", ":"))
    упаковано = quote(полезное, safe="")
    if len(упаковано) > 3500:          # заголовок ответа не резиновый
        упаковано = quote(json.dumps({"n": (имя or "")[:40], "t": (текст or "")[:900]},
                                     ensure_ascii=False, separators=(",", ":")), safe="")
    добавить_куку(обработчик,
                  f"{НАСТРОЙКА.кука_черновика}={упаковано}; Path=/; "
                  f"Max-Age={ЖИЗНЬ_ЧЕРНОВИКА}; SameSite=Lax")


def взять_черновик(обработчик) -> dict:
    """Прочитать черновик и погасить куку: он одноразовый."""
    if обработчик is None or НАСТРОЙКА is None:
        return {}
    сырое = _кука(обработчик, НАСТРОЙКА.кука_черновика)
    if not сырое:
        return {}
    добавить_куку(обработчик,
                  f"{НАСТРОЙКА.кука_черновика}=; Path=/; Max-Age=0; SameSite=Lax")
    try:
        данные = json.loads(unquote(сырое))
    except ValueError:
        return {}
    if not isinstance(данные, dict):
        return {}
    return {"имя": str(данные.get("n") or "")[:40],
            "текст": str(данные.get("t") or "")[:2000]}


def csrf(обработчик) -> str:
    """Токен двойной отправки, выведенный из куки посетителя.

    Куку нельзя прочитать со стороннего сайта (HttpOnly), значит нельзя и
    вычислить токен. `SameSite=Lax` чужую форму и так не пустит, но одна
    защита — это ноль защит, если она отключится.
    """
    кука = getattr(обработчик, "_куки_посетителя", "") or ""
    if not кука or НАСТРОЙКА is None:
        return ""
    return hashlib.sha256(
        (НАСТРОЙКА.соль_csrf + кука).encode("utf-8")).hexdigest()[:32]


def _совпало(свой: str, чужой: str) -> bool:
    """Сравнение за постоянное время, устойчивое к не-ASCII.

    `secrets.compare_digest` на строках требует ASCII и бросает `TypeError` на
    кириллице. И присланный токен, и значение куки приходят из-под управления
    клиента: один небуквенный байт превращал бы страницу произведения в 500 —
    управляемый извне отказ. Поэтому сравниваются байты.

    Тот же дефект назван владельцу общего модуля по адресу
    `animedia-frontend.py` (`_csrf_совпал`, `_модератор`): там сравнение
    выполняется на строках.
    """
    if not свой or not чужой:
        return False
    return secrets.compare_digest(str(свой).encode("utf-8"),
                                  str(чужой).encode("utf-8"))


def csrf_совпал(обработчик, присланный: str) -> bool:
    return _совпало(csrf(обработчик), присланный)


def модератор(обработчик) -> bool:
    """Модератор — тот, кто предъявил ключ из окружения.

    Проверяется НА СЕРВЕРЕ и на каждом запросе. Пустой ключ означает, что
    модератора на этой витрине нет вовсе, а не что им является любой
    посетитель.
    """
    if НАСТРОЙКА is None or обработчик is None:
        return False
    ключ = os.environ.get(НАСТРОЙКА.ключ_модератора_env, "")
    if not ключ:
        return False
    предъявлено = _кука(обработчик, НАСТРОЙКА.кука_модератора)[:128]
    return _совпало(ключ, предъявлено)


def _откуда(путь: str) -> str:
    """Какая форма ответила. Нужно, чтобы показать сообщение рядом с ней."""
    return "comment" if путь.startswith("/community/comment") else "vote"


