#!/usr/bin/env bash
#
# Создать подготовительный каталог редакторских правок. Запускает ВЛАДЕЛЕЦ.
#
# Зачем нужен отдельный запуск от root
# ------------------------------------
#
# Механизм редакторских правок собран с двух сторон и ни разу не работал.
# На стороне витрины читатель выпущен: `/srv/zonafilm-space/current/src/
# editorial_overlay.py` отдаёт `/__editorial_status` и накладывает правки при
# показе страницы. На стороне управляющего слоя есть и подготовка
# (`factory/cell/editorial_store.py`), и операция очереди `editorial`, и её
# ветка в исполнителе (`применить_правки`).
#
# Не хватает ровно одного: каталога `/var/lib/site-cells/editorial`. Он лежит
# внутри `/var/lib/site-cells`, который принадлежит root с правами 755, и
# создать его учётная запись `claude` не может — измерено, PermissionError.
# Поэтому механизм никогда не запускался: в каталоге результатов 257 заявок, из
# них editorial — ни одной.
#
# Почему каталог не создаётся самим инструментом. Потому что он должен быть
# доступен на запись подающей стороне и на чтение исполнителю, а права на
# каталог внутри root-овского дерева выдаёт только root. Молча обойти это,
# подложив каталог в другое место, нельзя: исполнитель читает подготовленное по
# пути, который выводит САМ из `site_id` (схема заявки закрыта, путей в ней
# нет), и расхождение сторон означало бы отказ «подготовленных правок нет».
#
# Что скрипт делает
# -----------------
#
#   1. проверяет, что дерево очереди на месте и выглядит как ожидается;
#   2. создаёт каталог, если его нет (повторный запуск ничего не меняет);
#   3. ставит владельца `claude:root` и права 0730 — те же, что у `requests`:
#      подающая сторона пишет, исполнитель читает, посторонние не видят;
#   4. печатает фактическое состояние и проверяет запись от имени claude.
#
# Чего НЕ делает: не трогает сами заявки, результаты, замки и состояние, не
# ставит и не перезапускает службы, не меняет ни одного сайта.
#
# Запуск:   sudo bash automation/host/apply-editorial-staging-root.sh
#
set -euo pipefail

QUEUE_ROOT=/var/lib/site-cells
STAGING="${QUEUE_ROOT}/editorial"
OWNER=claude
GROUP=root
MODE=0730

if [ "$(id -u)" != "0" ]; then
  echo "нужен root: sudo bash $0" >&2
  exit 1
fi

if [ ! -d "${QUEUE_ROOT}" ]; then
  echo "ОТКАЗ: ${QUEUE_ROOT} нет — очередь выпуска не установлена на этом хосте" >&2
  exit 2
fi
if [ ! -d "${QUEUE_ROOT}/requests" ] || [ ! -d "${QUEUE_ROOT}/results" ]; then
  echo "ОТКАЗ: в ${QUEUE_ROOT} нет requests/ или results/ — это не дерево очереди" >&2
  exit 2
fi
if ! id -u "${OWNER}" >/dev/null 2>&1; then
  echo "ОТКАЗ: учётной записи ${OWNER} на хосте нет" >&2
  exit 2
fi

echo "== до =="
ls -ld "${QUEUE_ROOT}" "${QUEUE_ROOT}/requests" "${STAGING}" 2>&1 || true

if [ -d "${STAGING}" ]; then
  echo "каталог уже есть — меняю только владельца и права"
else
  mkdir -p "${STAGING}"
  echo "каталог создан: ${STAGING}"
fi
chown "${OWNER}:${GROUP}" "${STAGING}"
chmod "${MODE}" "${STAGING}"

echo "== после =="
ls -ld "${STAGING}"

# Проверка не «файл создан», а «подающая сторона действительно пишет».
PROBE="${STAGING}/.write-probe-$$.json"
if sudo -u "${OWNER}" /bin/sh -c "printf '{}' > '${PROBE}'" 2>/dev/null; then
  rm -f "${PROBE}"
  echo "ПРОВЕРЕНО: ${OWNER} пишет в ${STAGING}"
else
  echo "ОТКАЗ: ${OWNER} в ${STAGING} писать не может — права не подействовали" >&2
  exit 3
fi

# Исполнитель работает от root и читает каталог сам; отдельной проверки чтения
# не требуется — у root она безусловна. Проверяется то, что могло не выйти.

cat <<'NEXT'

Готово. Дальше — на стороне claude, без root:

  cd /home/claude/wt-portable-site-cell-01
  python3 -m factory.qwen sites | grep zonafilm.space

Состояние передачи zonafilm.space должно стать managed. После этого правки
идут штатным путём: python3 -m factory.qwen publish --site zonafilm.space ...
NEXT
