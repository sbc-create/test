def применить(текст: str) -> tuple[str, list]:
    журнал = []
    for имя, признак, пары, обязательно in ПРЕОБРАЗОВАНИЯ:
        if признак and признак in текст:
            журнал.append(f"пропущено (уже применено): {имя}")
            continue
        сделано = 0
        for было, стало in пары:
            if было in текст:
                сделано += текст.count(было)
                текст = текст.replace(было, стало)
        if сделано:
            журнал.append(f"применено ×{сделано}: {имя}")
        elif обязательно:
            raise SystemExit(f"ОТКАЗ: якорь не найден — «{имя}». "
                             "Рантайм разошёлся с разобранным образцом; "
                             "вслепую править нельзя.")
        else:
            журнал.append(f"нечего менять: {имя}")
    return текст, журнал


def main(argv=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true",
                   help="ничего не писать; ненулевой код, если контракт не выполнен")
    args = р.parse_args(argv)

    плохо = 0
    for имя in args.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if args.check:
            остатки = [о for о in ОСТАТКИ if о in исходный]
            ok = ("def доступные_номера(сезон: dict) -> set:" in исходный
                  and not остатки)
            print(f"{'ок    ' if ok else 'НЕ ПРИВЕДЁН'} {путь}"
                  + (f"  остатки: {остатки}" if остатки else ""))
            плохо += 0 if ok else 1
            continue
        новый, журнал = применить(исходный)
        остатки = [о for о in ОСТАТКИ if о in новый]
        if остатки:
            raise SystemExit(f"{путь}: после правки остались счётчики {остатки}")
        compile(новый, str(путь), "exec")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main())
