#!/usr/bin/env python3
"""Миниатюры постеров под показ — перенос рабочего механизма Animedia на Zona.

Повод измеренный. У `animedia.icu` обложки идут своим адресом `/poster/<ключ>`
с закрытым набором ширин (`?w=160|240|320|720`), уменьшением на стороне
витрины и `srcset`/`sizes` в разметке: браузер берёт файл под свой размер и
плотность экрана. У линии Zona этого нет — постер подставляется ПРЯМОЙ ссылкой
на источник, то есть в карточку 148 px уезжает оригинал. Поручение владельца
27.10: «подбери размер загружаемых миниатюр под отображение и плотность
экрана; не растягивай изображения шириной 100 пикселей и не возвращай тяжёлые
оригиналы повсеместно».

Что переносится (тем же текстом, что работает у Animedia):

* закрытый набор ширин и предел `ПОСТЕР_МАКС_ШИРИНА` из окружения;
* `_уменьшить_постер` — уменьшение и обрезка горизонтального кадра по центру;
  без Pillow, при ошибке, анимации или если результат не меньше — исходные
  байты без изменений;
* `_ширина_постера` — разбор `?w=N` ровно из набора;
* `_набор_постера` — `srcset`/`sizes` для разметки;
* `отдать_постер` принимает строку запроса и держит вариант по (ключ, ширина);
* обложки Zona идут СВОИМ адресом: источник отдаёт оригинал и отказывает в
  hotlink части запросов, а уменьшить чужой файл нельзя.

Pillow проверен для учётной записи витрины ДО переноса: `PIL 9.0.1`,
`automation/local/service-image-support-check.py --user zonafilm-space`.

    python3 automation/host/apply-poster-sizes-patch.py [--check] <файл>…
"""
