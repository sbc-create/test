def остатки(текст: str) -> list:
    плохо = [f"нет: {имя}" for имя, _, _, признак in ПАРЫ if признак not in текст]
    if "dict[str | tuple[str, int]" not in текст:
        плохо.append("тип памяти обложек не знает варианта по ширине")
    return плохо


def применить(текст: str) -> tuple[str, list]:
    if "def отдать_постер" not in текст or "ВНЕШНИЙ_ПОСТЕР" not in текст:
        raise SystemExit("ОТКАЗ: в файле нет прокси обложек этой линии")
    if "ПОСТЕР_ШИРИНЫ" in текст and "def _уменьшить_постер" in текст:
        return текст, ["пропущено (уже стоит): весь перенос"]
    журнал = []
    for имя, было, стало, признак in ПАРЫ:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        # Объявления памяти и адреса постера в этом рантайме продублированы:
        # правится КАЖДОЕ, иначе действует последнее — незаменённое.
        сколько = текст.count(было) if имя == "обложки своим адресом" else 1
        текст = текст.replace(было, стало, сколько)
        журнал.append(f"применено{'' if сколько == 1 else f' ×{сколько}'}: {имя}")
    # Тип памяти: оба объявления, иначе проверка типов спорит с ключом-парой.
    if ТИП_КЭША_БЫЛО in текст:
        сколько = текст.count(ТИП_КЭША_БЫЛО)
        текст = текст.replace(ТИП_КЭША_БЫЛО, ТИП_КЭША_СТАЛО, сколько)
        журнал.append(f"применено ×{сколько}: тип памяти обложек")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        п = остатки(новый)
        if п:
            print(f"ОТКАЗ: после правки остались признаки непривёденности: {п}",
                  file=sys.stderr)
            return 1
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
