def линия(текст: str):
    """Какой набор пар относится к файлу. Определяется по якорям, не по имени.

    AnimeGo проверяется ПЕРВЫМ: её рантайм унаследовал таблицу настроек
    Animedia целиком, и по одному этому признаку был бы принят за неё. Главную
    он собирает своим способом — сезонной лентой с собственным заголовком, —
    и правка Animedia тронула бы код, который эта витрина на главной не
    отдаёт.
    """
    if "АНИМЕГО_СЕЗОНЫ" in текст and 'class="ag-h1"' in текст:
        return "animego", ПАРЫ_АНИМЕГО
    if "def _сетка_коллекций" in текст and 'data-collection-key="{html.escape(к["key"])}"' in текст:
        return "animedia", ПАРЫ_АНИМЕДИА
    # Animedia Space: таблица настроек домена та же, а сетку визиток она
    # собирает своим выражением ключа — поэтому якорь ключа блока у неё свой,
    # а правки заголовка общие с ICU.
    if ('data-collection-key="{html.escape(str(к.get("key") or ""))}"' in текст
            and "АНИМЕДИА_ДОМЕНЫ" in текст):
        return "animedia-space", ПАРЫ_АНИМЕДИА_SPACE
    if 'class="zr1" aria-labelledby="zr1-h"' in текст:
        return "zona", ПАРЫ_ЗОНА
    return "", ()


def остатки(текст: str) -> list:
    имя_линии, пары = линия(текст)
    if not пары:
        return []
    return [f"нет: {имя}" for имя, _, _, признак in пары if признак not in текст]


def применить(текст: str) -> tuple[str, list]:
    имя_линии, пары = линия(текст)
    if not пары:
        raise SystemExit("ОТКАЗ: не этой линии (нет своих якорей) — "
                         "ни сетки визиток Animedia, ни полки Zona")
    журнал = [f"линия: {имя_линии}"]
    for имя, было, стало, признак in пары:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            имя_линии, пары = линия(исходный)
            if not пары:
                print(f"не этой линии (нет своих якорей) {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
