#!/usr/bin/env python3
"""MOD-202 в рантайм витрины, который ушёл вперёд канона. Перенос по якорям.

Зачем инструмент, а не продвижение пина. У трёх действующих витрин семейства
(lords-02 lordserial33.biz, lords-03 1lordserials1.online, lords-05
lordserials22.info) копия рантайма несёт 18, 21 и 32 имени, которых в
каноническом слое нет: собственный слой вида, закрытие индекса, поиск по сайту,
подборки. Продвижение закреплённой версии стёрло бы эту работу с работающих
сайтов — измерено 26.10 `promote-cell-pins.py`, и он на них отказывает. Значит
общая правка приезжает к ним ПО ЯКОРЯМ, как `apply-contact-footer.py` и
`apply-episode-availability-patch.py`: якоря обязательные, несовпадение — отказ
ДО записи, `--check` отвечает одним словом.

Что добавляется (это и есть MOD-202 целиком):

  * помощник `подпись_серии_в_крошках` — последнее звено цепочки называет
    серию, а не повторяет сезон («1 сезон → 1 сезон, 1 серия»);
  * звено СЕЗОНА с адресом в цепочке страницы серии: без него страница сезона
    индексируется, не имея ни одной входящей внутренней ссылки, а цепочка
    обещает поисковику уровень URL, которого на сайте нет;
  * `BreadcrumbList` там, где крошки уже видны. Измерено отрисовкой артефакта
    26.10: на странице серии стоял единственный блок разметки TVEpisode, а
    цепочки в разметке не было вовсе — `schema_крошек` звалась только на
    странице сезона, и слот `разметка` принимал ровно ОДНУ схему.

Чего инструмент НЕ делает: не трогает оформление, разделы, плеер, счётчики,
режим индексации, адреса страниц и данные.

    python3 automation/host/apply-season-crumbs-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ПОМОЩНИК_ПОДПИСИ = '''

def подпись_серии_в_крошках(эпизод: int) -> str:
    """Последнее звено цепочки: только серия, без повтора сезона.

    Звено сезона в цепочке уже есть и ведёт на свою страницу, поэтому длинная
    подпись дала бы «1 сезон → 1 сезон, 1 серия». Спецвыпуск называется
    спецвыпуском: номер 0 сам по себе читателю ничего не говорит.
    """
    if int(эпизод) == СПЕЦВЫПУСК:
        return f"спецвыпуск — серия {int(эпизод)}"
    return f"{int(эпизод)} серия"
'''

ЦЕПОЧКА_БЫЛО = '''        звенья = [("/", self.имя), ("/catalog/?kind=Сериал", "Сериалы"),
                  (f"/title/{запись['slug']}/", имя),
                  ("", подпись_сезон_серия(сезон, эпизод))]'''
ЦЕПОЧКА_СТАЛО = '''        # Цепочка повторяет путь URL ЦЕЛИКОМ, включая уровень сезона: без
        # звена сезона его страница индексируется, не имея ни одной входящей
        # внутренней ссылки (измерено 26.10 на 1lordserials1.online), а
        # цепочка обещает поисковику уровень, которого на сайте нет.
        звенья = [("/", self.имя), ("/catalog/?kind=Сериал", "Сериалы"),
                  (f"/title/{запись['slug']}/", имя),
                  (self.адрес_сезона(запись["slug"], сезон), f"{сезон} сезон"),
                  ("", подпись_серии_в_крошках(эпизод))]'''

СЛОТ_БЫЛО = '''                        for р in ([разметка] if разметка else []))'''
СЛОТ_СТАЛО = '''                        for р in _схемы_страницы(разметка))'''

ПОМОЩНИК_СХЕМ = '''

def _схемы_страницы(разметка) -> list:
    """Схемы страницы: одна строка или несколько — в порядке передачи.

    Слот был рассчитан на ОДНУ схему, и страница серии отдавала только
    TVEpisode: `BreadcrumbList` не выходил вовсе. Пустые значения
    отбрасываются — пустой `<script>` в голове страницы это мусор.
    """
    if not разметка:
        return []
    if isinstance(разметка, str):
        return [разметка]
    return [р for р in разметка if р]
'''

#: Вызовы оболочки, где крошки уже видны, а разметки цепочки нет.
ВЫЗОВЫ = [
    ("            описание=краткое, разметка=разметка, крошки=self.крошки(звенья),",
     "            описание=краткое,\n"
     "            # Крошки идут и РАЗМЕТКОЙ: иерархию робот читает из\n"
     "            # BreadcrumbList, а не из видимой строки.\n"
     "            разметка=(разметка, self.schema_крошек(звенья)),\n"
     "            крошки=self.крошки(звенья),"),
    ("            разметка=разметка, крошки=self.крошки(звенья),",
     "            разметка=(разметка, self.schema_крошек(звенья)),\n"
     "            крошки=self.крошки(звенья),"),
]

ЯКОРЯ_ПОМОЩНИКА = ("\nclass Вид", "\nclass Обработчик")


def слой_владеет_крошками(путь: Path) -> bool:
    """Строит ли BreadcrumbList уже SEO-слой этой витрины — из ВИДИМЫХ крошек.

    Измерено 26.10 и это решило половину правки. У витрин lords-02/03/05 рядом
    лежит свой `seo_layer.py` с функцией `крошки_со_страницы`: слой читает
    видимую строку крошек каждого ответа и ставит BreadcrumbList сам, пропуская
    страницу, где разметка уже есть. В КАНОНИЧЕСКОМ `seo_layer.py` этой функции
    нет вовсе — ответ канонической витрины несёт только WebSite и TVEpisode
    (проверено прогоном `обогатить` на сохранённой странице серии).

    Значит для таких витрин разметку добавлять НЕ НАДО: у общего компонента один
    ответственный, и здесь это их слой. Им нужна только видимая цепочка с
    уровнем сезона — а её даёт первая половина правки.
    """
    слой = путь.parent / "seo_layer.py"
    if not слой.is_file():
        return False
    return "def крошки_со_страницы" in слой.read_text(encoding="utf-8")


def остатки(текст: str, путь: Path | None = None) -> list:
    """Чего в файле не хватает, чтобы правка считалась приведённой."""
    плохо = []
    свой_слой = bool(путь) and слой_владеет_крошками(путь)
    if "подпись_серии_в_крошках" not in текст:
        плохо.append("нет помощника подпись_серии_в_крошках")
    if "подпись_сезон_серия(сезон, эпизод))]" in текст:
        плохо.append("цепочка серии без звена сезона")
    if not свой_слой:
        if "_схемы_страницы" not in текст:
            плохо.append("слот разметки принимает одну схему")
        без_разметки = текст.count("разметка=разметка, крошки=self.крошки(звенья)")
        if без_разметки:
            плохо.append(f"вызовов с крошками без BreadcrumbList: {без_разметки}")
    return плохо


def применить(текст: str, путь: Path | None = None) -> tuple[str, list]:
    журнал = []
    свой_слой = bool(путь) and слой_владеет_крошками(путь)
    if "подпись_серии_в_крошках" in текст:
        журнал.append("пропущено (уже стоит): помощник подписи")
    else:
        якорь = next((я for я in ЯКОРЯ_ПОМОЩНИКА if я in текст), None)
        if якорь is None:
            raise SystemExit("ОТКАЗ: некуда поставить помощник подписи — ни одного "
                             f"из якорей {ЯКОРЯ_ПОМОЩНИКА} в файле нет")
        текст = текст.replace(якорь, ПОМОЩНИК_ПОДПИСИ + якорь, 1)
        журнал.append("применено: помощник подпись_серии_в_крошках")

    цепочек = текст.count(ЦЕПОЧКА_БЫЛО)
    if цепочек:
        текст = текст.replace(ЦЕПОЧКА_БЫЛО, ЦЕПОЧКА_СТАЛО)
        журнал.append(f"применено ×{цепочек}: звено сезона в цепочке серии")
    elif "подпись_серии_в_крошках(эпизод))]" in текст:
        журнал.append("пропущено (уже стоит): звено сезона")
    else:
        raise SystemExit("ОТКАЗ: цепочки серии разобранного вида в файле нет — "
                         "вслепую править нельзя")

    if свой_слой:
        журнал.append("пропущено (владеет SEO-слой витрины): BreadcrumbList — "
                      "его ставит seo_layer.крошки_со_страницы из видимой цепочки")
        return текст, журнал
    if "_схемы_страницы" in текст:
        журнал.append("пропущено (уже стоит): помощник схем")
    else:
        якорь = next((я for я in ЯКОРЯ_ПОМОЩНИКА if я in текст), None)
        текст = текст.replace(якорь, ПОМОЩНИК_СХЕМ + якорь, 1)
        журнал.append("применено: помощник _схемы_страницы")
    слотов = текст.count(СЛОТ_БЫЛО)
    if слотов:
        текст = текст.replace(СЛОТ_БЫЛО, СЛОТ_СТАЛО)
        журнал.append(f"применено ×{слотов}: слот разметки принимает несколько схем")
    elif "_схемы_страницы(разметка)" in текст:
        журнал.append("пропущено (уже стоит): слот разметки")
    else:
        raise SystemExit("ОТКАЗ: слота разметки разобранного вида в файле нет")

    всего = 0
    for было, стало in ВЫЗОВЫ:
        сколько = текст.count(было)
        if сколько:
            текст = текст.replace(было, стало)
            всего += сколько
    if всего:
        журнал.append(f"применено ×{всего}: BreadcrumbList на страницах с крошками")
    elif "self.schema_крошек(звенья))" in текст:
        журнал.append("пропущено (уже стоит): BreadcrumbList на страницах")
    else:
        raise SystemExit("ОТКАЗ: вызовов оболочки с крошками разобранного вида нет")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true",
                   help="только сказать, приведён ли файл; ничего не писать")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            п = остатки(исходный, путь)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный, путь)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        п = остатки(новый, путь)
        if п:
            print(f"ОТКАЗ: после правки остались признаки непривёденности: {п}",
                  file=sys.stderr)
            return 1
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
