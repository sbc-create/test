#!/usr/bin/env python3
"""Здоровье конвейера контента: кто обещан, кто установлен, что свежо.

Повод. Бюджет ночного обновления подробностей снижен с 6000 до 500 записей в
сутки — осознанно, потому что работу «быстро замечать новые серии» передали
частому опросу `nova-episode-poll`. Опрос на хосте не установили. Снаружи всё
выглядело работающим: таймер доставки тикает каждые 10 минут, отчёт доставки
пишет «unchanged», страница отдаёт HTTP 200 — а новая серия не появлялась
пятнадцать суток, ровно столько нужно бюджету в 500 записей на 7497 тайтлов.

Проверяется то, чего не видно ни по одному из этих признаков:

* компонент, на который ссылается другой компонент, установлен на хосте;
* таймеры, от которых зависит свежесть, существуют;
* снимки производителя не старше порога;
* доставленная копия совпадает с источником (иначе доставка молча отстаёт).

Только чтение. Ничего не устанавливает и не запускает: инструмент отвечает на
вопрос «почему не обновляется», а решение принимает человек.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЮНИТЫ = Path("/etc/systemd/system")
ИСТОЧНИК = Path("/srv/lords/.frontend")

#: Путь к установленному дереву фабрики: ночное обновление живёт там, а не в
#: этой рабочей ветке. Проверка в ветке нашла бы «не упомянут» и тем самым
#: скрыла бы настоящее расхождение.
ФАБРИКА = Path("/srv/site-factory/repo")

#: Кто на кого ссылается. Пара «упоминающий → упоминаемый юнит»: если первый
#: объявляет, что работу делает второй, второй обязан быть установлен.
ЗАВИСИМОСТИ = (
    (
        "automation/host/nova-daily-refresh.sh",
        "nova-episode-poll",
        "ночное обновление снизило бюджет подробностей, передав работу частому опросу",
    ),
)

#: Сколько часов снимок считается свежим. Производитель работает раз в сутки,
#: поэтому порог — сутки с запасом на длительность прогона.
ПОРОГ_ЧАСОВ = 30


def _возраст_часов(п: Path) -> float:
    return (time.time() - п.stat().st_mtime) / 3600.0


def _цифра(п: Path) -> str:
    h = hashlib.sha256()
    with п.open("rb") as f:
        for кусок in iter(lambda: f.read(1 << 20), b""):
            h.update(кусок)
    return h.hexdigest()[:16]


def проверить_зависимости() -> list[dict]:
    итог = []
    for источник, юнит, зачем in ЗАВИСИМОСТИ:
        путь = ФАБРИКА / источник
        если_есть = путь.is_file() and юнит in путь.read_text(encoding="utf-8", errors="replace")
        служба = (ЮНИТЫ / f"{юнит}.service").exists()
        таймер = (ЮНИТЫ / f"{юнит}.timer").exists()
        итог.append(
            {
                "источник": источник,
                "компонент": юнит,
                "зачем": зачем,
                "упомянут": если_есть,
                "служба_установлена": служба,
                "таймер_установлен": таймер,
                "состояние": "ок"
                if (служба and таймер)
                else ("НЕ УСТАНОВЛЕН" if если_есть else "не упомянут"),
            }
        )
    return итог


def сверить_доставку(пары: list[tuple[Path, Path]]) -> list[dict]:
    итог = []
    for источник, копия in пары:
        запись = {"источник": str(источник), "копия": str(копия)}
        if not источник.is_file() or not копия.is_file():
            запись["состояние"] = "НЕТ ФАЙЛА"
        else:
            а, б = _цифра(источник), _цифра(копия)
            запись["состояние"] = "совпадает" if а == б else "РАСХОДИТСЯ"
            запись["возраст_источника_ч"] = round(_возраст_часов(источник), 1)
            запись["возраст_копии_ч"] = round(_возраст_часов(копия), 1)
        итог.append(запись)
    return итог


def main(argv: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("--json", action="store_true")
    а = р.parse_args(argv)

    зависимости = проверить_зависимости()
    пары = []
    for копия in sorted(Path("/srv").glob("*/data/*-catalog.json")):
        # Имя источника выводится из отчёта доставки площадки: он называет,
        # какой снимок заимствован. Без отчёта пара не строится — догадка тут
        # была бы хуже отсутствия строки.
        состояние = копия.parent / копия.name.replace("-catalog.json", "-update-state.json")
        if not состояние.is_file():
            continue
        try:
            д = json.loads(состояние.read_text(encoding="utf-8"))
        except ValueError:
            continue
        исходный = д.get("source_site")
        if исходный:
            пары.append((ИСТОЧНИК / f"{исходный}-catalog.json", копия))

    доставка = сверить_доставку(пары)
    свежесть = []
    for п in sorted(ИСТОЧНИК.glob("*-catalog.json")):
        свежесть.append(
            {
                "снимок": п.name,
                "возраст_ч": round(_возраст_часов(п), 1),
                "состояние": "ок" if _возраст_часов(п) <= ПОРОГ_ЧАСОВ else "УСТАРЕЛ",
            }
        )

    документ = {"зависимости": зависимости, "снимки_производителя": свежесть, "доставка": доставка}
    if а.json:
        print(json.dumps(документ, ensure_ascii=False, indent=2))
        return 0
    print("=== компоненты, на которые ссылаются другие ===")
    for з in зависимости:
        print(f"  {з['компонент']:22} {з['состояние']}")
        if з["состояние"] == "НЕ УСТАНОВЛЕН":
            print(f"      {з['зачем']}")
            print(f"      упомянут в {з['источник']}, службы и таймера на хосте нет")
    print("\n=== снимки производителя ===")
    for с in свежесть:
        print(f"  {с['снимок']:34} {с['возраст_ч']:6} ч  {с['состояние']}")
    print("\n=== доставка на площадки ===")
    for д in доставка:
        строка = f"  {Path(д['копия']).parts[2]:22} {д['состояние']}"
        if "возраст_копии_ч" in д:
            строка += f"  копия {д['возраст_копии_ч']} ч, источник {д['возраст_источника_ч']} ч"
        print(строка)
    плохо = [з for з in зависимости if з["состояние"] == "НЕ УСТАНОВЛЕН"]
    плохо += [с for с in свежесть if с["состояние"] != "ок"]
    плохо += [д for д in доставка if д["состояние"] not in ("совпадает",)]
    print(f"\nнездоровых пунктов: {len(плохо)}")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main())
