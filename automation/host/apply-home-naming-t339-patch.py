#!/usr/bin/env python3
"""Нижний заголовок главной и дубль раздела «Этого года».

ДВЕ ПРАВКИ, у каждой свой измеренный повод.

1. НИЖНИЙ ЗАГОЛОВОК. SEO-блок главной брал заголовок из `title_home`, то есть
   из той же строки, что и `<title>` страницы. Поле `seo_home_title` было
   ОБЪЯВЛЕНО в таблице доменов и не использовалось нигде — ровно тот же класс,
   что сегодня уже чинился у поля `h1`: объявлено и забыто. Теперь блок берёт
   своё поле, а `<title>` остаётся при своём.

2. ДУБЛЬ РАЗДЕЛА. `/collection/current_season/` и `/catalog/?year=2026` —
   одна и та же выдача. Измерено запросом обеих страниц 27.10: у обеих
   счётчик 315 названий, обе `index`, у обеих canonical на себя, и все 24
   карточки первой страницы раздела совпадают с первыми 24 карточками
   каталога В ТОМ ЖЕ ПОРЯДКЕ. Причина в самой спецификации: отбор
   `{"year": "max"}` с порядком `published_at desc` — это и есть фильтр года
   каталога, пересказанный вторым адресом.

   Убирается сама подборка, а не её оформление, — по уже принятому в этом же
   файле образцу «С видео». Прятать раздел разметкой значило бы оставить в
   контракте то, чего не должно быть. Проверено, что удалённый ключ отдаёт
   чистый 404: `/collection/video_available/` после прошлого такого удаления
   отвечает 404, а не 500 и не пустым 200.

ЧЕГО НЕ ДЕЛАЕТ. Не трогает `/catalog/?year=...`: страница остаётся, у неё
свой H1 «Аниме 2026 года», и она — та, что остаётся. Не меняет `<title>`
главной. Не применяется к рантайму выведенной из работы витрины: правка
лежит в шаблоне и ждёт решения владельца о замене.

    python3 automation/host/apply-home-naming-t339-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

ЗАГОЛОВОК_БЫЛО = '''        куски.append(self.seo_блок(заголовок=домен["title_home"],
                                   текст=домен["seo_home"]))'''
ЗАГОЛОВОК_СТАЛО = '''        # Заголовок нижнего блока — СВОЁ поле, а не `title_home`. Поле
        # `seo_home_title` было объявлено в таблице доменов и не
        # использовалось нигде: тот же класс, что у поля `h1`, починенного в
        # этот же день. Пока блок брал `title_home`, нижний заголовок
        # повторял <title> страницы слово в слово.
        куски.append(self.seo_блок(
            заголовок=домен.get("seo_home_title") or домен["title_home"],
            текст=домен["seo_home"]))'''

ИМЯ_БЫЛО = '''        "seo_home_title": "Чем полезен Animedia ICU",'''
ИМЯ_СТАЛО = '''        # Заголовок нижнего блока называет предмет витрины теми же словами,
        # какими назван её каталог: аниме-сериалы, аниме-фильмы и дунхуа
        # (линия SEO, 27.10). «Чем полезен Animedia ICU» говорило о нас, а не
        # о том, что здесь можно посмотреть.
        "seo_home_title": "Animedia ICU — аниме-сериалы, аниме-фильмы и дунхуа",'''

ДУБЛЬ_БЫЛО = '''        _спец("current_season", семейство, "Этого года",
              "Названия самого свежего года, представленного в каталоге.",
              "catalog", {"year": "max"}, {"field": "published_at", "order": "desc"},
              "year", "/collection/current_season/"),
'''
ДУБЛЬ_СТАЛО = '''        # «Этого года» здесь больше нет. Отбор `{"year": "max"}` с порядком
        # `published_at desc` — это фильтр года каталога, пересказанный вторым
        # адресом. Измерено 27.10 запросом обеих страниц: у
        # /collection/current_season/ и /catalog/?year=2026 счётчик одинаков
        # (315 названий), обе index, у обеих canonical на себя, и все 24
        # карточки первой страницы совпадают в том же порядке.
        # Убрана сама подборка, а не её оформление, — как и «С видео» выше:
        # остаётся та страница, у которой есть собственный заголовок
        # («Аниме 2026 года»), а не служебное описание фильтра.
'''

#: имя, было, стало, признак применённости, требование к файлу
ТРЕБУЕТ_ГЛАВНОЙ = "self.seo_блок(заголовок="
ТРЕБУЕТ_ТАБЛИЦЫ = '"seo_home_title"'
ТРЕБУЕТ_КОНТРАКТА = '_спец("current_season"'
ПАРЫ = (
    ("нижний заголовок из своего поля", ЗАГОЛОВОК_БЫЛО, ЗАГОЛОВОК_СТАЛО,
     'домен.get("seo_home_title")', ТРЕБУЕТ_ГЛАВНОЙ),
    ("имя нижнего заголовка", ИМЯ_БЫЛО, ИМЯ_СТАЛО,
     '"seo_home_title": "Animedia ICU — аниме-сериалы', ТРЕБУЕТ_ТАБЛИЦЫ),
    ("дубль «Этого года» убран", ДУБЛЬ_БЫЛО, ДУБЛЬ_СТАЛО,
     "«Этого года» здесь больше нет", ТРЕБУЕТ_КОНТРАКТА),
)


def уместна(пара: tuple, текст: str) -> bool:
    """Относится ли пара к этому файлу.

    Признак применённости считается принадлежностью НАРАВНЕ с требованием.
    Первая версия проверяла только требование, и после удаления раздела
    «Этого года» требование (`_спец("current_season"`) исчезало вместе с ним:
    приведённый файл начинал отчитываться как «не этой линии» вместо «ок».
    Пара, которая удаляет свой же якорь, обязана опознаваться по следу,
    который оставила.
    """
    _, было, _, признак, требование = пара
    if признак in текст:
        return True
    if требование not in текст:
        return False
    return было in текст


def остатки(текст: str) -> list:
    return [f"нет: {п[0]}" for п in ПАРЫ if уместна(п, текст) and п[3] not in текст]


def применить(текст: str) -> tuple[str, list]:
    журнал, затронуто = [], 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if требование not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
        затронуто += 1
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if not [п for п in ПАРЫ if уместна(п, исходный)]:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
