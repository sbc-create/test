#!/usr/bin/env python3
"""План обновления установленного исполнителя: что изменится и от какой версии.

Зачем отдельный шаг перед установкой. Состав обновления — не список по памяти,
а разница между установленной копией и деревом службы СЕЙЧАС. Дерево службы
при этом живое: пока пакет ждёт владельца, туда приходят новые коммиты, и
состав меняется. За один вечер 12.10 он вырос с 10 файлов до 12.

Поэтому план ЗАКРЕПЛЯЕТСЯ: архитектор называет цифру состава, а этот сценарий
перед установкой сверяет её с деревом. Разошлось — отказ с названной причиной и
НОВЫМ составом, а не тихая установка чего-то другого.

Закрепляется именно состав, а не коммит. Коммит целиком не годится: в дереве
службы ночью идёт работа в `seo_operator/` и `automation/`, которую установщик
не копирует вовсе, и пин по коммиту отказывал бы на безвредном. Цифра состава —
хеши деревьев ровно копируемых каталогов.

Ничего не меняет: только читает и печатает. Запускать можно без root; под
root дополнительно читаются файлы установленной копии с правами 0600.

    python3 automation/host/executor-update-plan.py --expect d2f28e99cbdb
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

СЛУЖБА = Path("/home/claude/wt-portable-site-cell-01")
УСТАНОВЛЕНО = Path("/usr/local/lib/site-factory-cell")
#: Что установщик кладёт в корневую копию. Перечень НЕ по памяти: он равен
#: строкам `cp -a "$SRC_ROOT/<каталог>"` установщика, и это равенство держит
#: `tests/unit/test_executor_update_plan.py`. Прежняя редакция добавляла сюда
#: `scripts`, которого установщик не копирует вовсе, — и состав обновления
#: завышался на 7 файлов, которые на машину не попадут.
КАТАЛОГИ = ("factory", "schemas", "config")


def каталоги_установщика(установщик: Path) -> tuple[str, ...]:
    """Каталоги, которые установщик фактически копирует."""
    образец = re.compile(r'cp -a "\$SRC_ROOT/([A-Za-z0-9_]+)"')
    текст = установщик.read_text(encoding="utf-8")
    видели: list[str] = []
    for имя in образец.findall(текст):
        if имя not in видели:
            видели.append(имя)
    return tuple(видели)


def сумма(п: Path) -> str:
    return hashlib.sha256(п.read_bytes()).hexdigest()


def git(корень: Path, *арг: str) -> str | None:
    """Ответ git, либо None если git ОТКАЗАЛ.

    Разница существенная: пустой ответ значит «правок нет», а отказ — «спросить
    не удалось», и склеивать их нельзя. Под sudo в рабочем каталоге другой
    учётной записи git отказывает про владельца (`dubious ownership`), и при
    склейке проверка версии у владельца пропускалась бы молча.
    """
    готово = subprocess.run(["git", "-C", str(корень), *арг],
                            capture_output=True, text=True, timeout=120)
    return готово.stdout.strip() if готово.returncode == 0 else None


def цифра_состава(корень: Path) -> str | None:
    """Короткая цифра деревьев копируемых каталогов, либо None если git отказал.

    Закрепляет РОВНО устанавливаемое содержимое. Коммит в `seo_operator/` или
    `automation/` её не меняет, потому что установщик этих каталогов не копирует;
    правка в `factory/`, `schemas/` или `config/` меняет.
    """
    части: list[str] = []
    for каталог in КАТАЛОГИ:
        дерево = git(корень, "rev-parse", f"HEAD:{каталог}")
        if not дерево:
            return None
        части.append(f"{каталог}:{дерево}")
    слепок = "\n".join(части).encode("utf-8")
    return hashlib.sha256(слепок).hexdigest()[:12]


def главное(аргв=None) -> int:
    р = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--expect", default="",
                   help="цифра СОСТАВА, на которой он закреплён (не коммит: "
                        "коммит вне копируемых каталогов состав не меняет)")
    р.add_argument("--service", type=Path, default=СЛУЖБА)
    р.add_argument("--installed", type=Path, default=УСТАНОВЛЕНО)
    опции = р.parse_args(аргв)

    голова = git(опции.service, "rev-parse", "--short=12", "HEAD")
    ветвь = git(опции.service, "rev-parse", "--abbrev-ref", "HEAD")
    грязно = git(опции.service, "status", "--porcelain")
    # Грязь важна не везде. Коммит описывает устанавливаемое содержимое только
    # если в КОПИРУЕМЫХ каталогах нет незакоммиченных правок: правка в
    # `automation/` или `docs/` на корневую копию не попадает вовсе и пин не
    # ломает, а правка в `factory/` ломает — состав тогда закреплён не коммитом,
    # а чьей-то несохранённой работой, которая к установке успеет измениться.
    ответ_грязи = git(опции.service, "status", "--porcelain", "--", *КАТАЛОГИ)
    грязно_в_составе = [
        с for с in (ответ_грязи or "").splitlines()
        # Кеш питона исходников не меняет и в состав не входит. Отказ по нему
        # был бы отказом по безвредному — а проверку, отказывающую зря,
        # перестают читать, и она пропустит настоящую грязь.
        if "__pycache__" not in с
    ]
    цифра = цифра_состава(опции.service)
    немой = голова is None or грязно is None or цифра is None
    print(f"дерево службы: {опции.service}")
    print(f"   ветвь {ветвь or '—'}, коммит {голова or '—'}")
    print(f"   цифра состава: {цифра or '—'}  "
          f"(деревья {', '.join(КАТАЛОГИ)})")
    if немой:
        print("   git отказал: версию дерева установить не удалось")
    elif грязно:
        print(f"   незакоммиченных файлов всего: {len(грязно.splitlines())}")
    if грязно_в_составе:
        print(f"   из них в копируемых каталогах: {len(грязно_в_составе)} "
              "(кеш питона не считается)")
        for строка in грязно_в_составе[:8]:
            print(f"      {строка}")

    к_обновлению: list[tuple[str, str, str]] = []
    новые: list[str] = []
    недоступны: list[str] = []
    сверено = 0
    for каталог in КАТАЛОГИ:
        корень = опции.service / каталог
        if not корень.is_dir():
            continue
        for файл in sorted(корень.rglob("*")):
            if not файл.is_file() or "__pycache__" in файл.parts:
                continue
            отн = файл.relative_to(опции.service).as_posix()
            цель = опции.installed / отн
            сверено += 1
            if not цель.is_file():
                новые.append(отн)
                continue
            try:
                сейчас = сумма(цель)
            except PermissionError:
                # 0600 под root: содержимое не прочитать. Это предел
                # измерения, а НЕ «совпадает» — разница существенная.
                недоступны.append(отн)
                continue
            станет = сумма(файл)
            if станет != сейчас:
                к_обновлению.append((отн, сейчас[:16], станет[:16]))

    print(f"   сверено файлов: {сверено}")
    print(f"\nбудет обновлено файлов: {len(к_обновлению)}")
    for отн, сейчас, станет in к_обновлению:
        print(f"   {отн}")
        print(f"      {сейчас}… → {станет}…")
    if новые:
        print(f"\nбудет добавлено файлов: {len(новые)}")
        for отн in новые[:10]:
            print(f"   {отн}")
        if len(новые) > 10:
            print(f"   … и ещё {len(новые) - 10}")
    if недоступны:
        print(f"\nне прочитаны этой учётной записью (0600 root): "
              f"{len(недоступны)}")
        print("   это предел измерения, а не «совпадает»")
        for отн in недоступны[:4]:
            print(f"   {отн}")
        if len(недоступны) > 4:
            print(f"   … и ещё {len(недоступны) - 4}")

    if опции.expect and немой:
        print("\nОТКАЗ: git в дереве службы не отвечает, версию подтвердить "
              "нечем. Закрепить состав, не зная версии, нельзя.",
              file=sys.stderr)
        print("Под sudo это обычно `dubious ownership`: запустите план от той "
              "учётной записи, которой принадлежит рабочий каталог.",
              file=sys.stderr)
        return 1
    if опции.expect and грязно_в_составе:
        print("\nОТКАЗ: в копируемых каталогах есть незакоммиченные правки — "
              f"коммит {голова} устанавливаемое содержимое НЕ описывает.",
              file=sys.stderr)
        print("Либо правки коммитятся и состав закрепляется заново, либо "
              "установку не начинайте.", file=sys.stderr)
        return 1
    if опции.expect and цифра != опции.expect:
        print(f"\nОТКАЗ: состав закреплён цифрой {опции.expect}, "
              f"а у дерева {цифра}.", file=sys.stderr)
        print("Состав выше — НОВЫЙ и архитектором не подтверждён. "
              "Установку не начинайте: пришлите этот вывод.", file=sys.stderr)
        return 1
    if опции.expect:
        print(f"\nсостав совпадает с закреплённым ({опции.expect}): "
              f"подтверждён, установку можно начинать. "
              f"Коммит дерева при этом {голова} — он мог измениться вне "
              "копируемых каталогов, и это пин не ломает.")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
