#!/usr/bin/env python3
"""Две цели о рекомендательных блоках: показ блока и переход из него в карточку.

ПОВОД. Линия SEO 27.10: владелец будет оценивать эффект по показам блоков,
переходам из блока в карточку и подтверждённым запускам просмотра. Показов
блоков не измеряет ни одна цель — в Метрику уходят только `title_view` и
события плеера, поэтому «блок показали, но из него не переходят» и «блок никто
не видел» сейчас неразличимы.

ЧТО ДЕЛАЕТ. Добавляет в закрытый список две цели и отправляет их из
ЕДИНСТВЕННОЙ точки `window.__sfGoal`, без третьего аргумента:

* `block_view` — рекомендательный блок попал в экран не меньше чем наполовину;
  одна отправка на загрузку страницы (защёлка), иначе прокрутка туда-сюда
  накрутила бы показы;
* `block_click` — нажата карточка внутри такого блока; защёлки нет, это
  навигационное событие.

ЧЕГО НЕ ДЕЛАЕТ И ПОЧЕМУ. Ключ подборки В ЦЕЛЬ НЕ ПЕРЕДАЁТСЯ. Третьего
аргумента у точки отправки не существует по устройству: именно это не даёт
поисковой фразе уехать в отчёт, и ради удобства разбивки по блокам ломать это
нельзя. Разбивка берётся с другой стороны — из просмотров `/collection/<key>/`
в том же отчёте: переход из блока ведёт ровно туда. Ключ блока остаётся в
разметке (`data-block-key`) для проверок и приёмки.

    python3 automation/host/apply-block-goals-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

СПИСОК_БЫЛО = '''    "player_error",     # запуск не состоялся
)'''
СПИСОК_СТАЛО = '''    "player_error",     # запуск не состоялся
    "block_view",       # рекомендательный блок показан (ключ блока не передаётся)
    "block_click",      # из рекомендательного блока перешли в карточку
)'''

ТОЧКА_БЫЛО = '''        "if(/\\\\/season-\\\\d+\\\\/episode-\\\\d+\\\\/?$/.test(h)){g('episode_select');}"
        "else if(/\\\\/season-\\\\d+\\\\/?$/.test(h)){g('season_select');}"
        "},true);"
        "})();</script>"'''
ТОЧКА_СТАЛО = '''        "if(/\\\\/season-\\\\d+\\\\/episode-\\\\d+\\\\/?$/.test(h)){g('episode_select');}"
        "else if(/\\\\/season-\\\\d+\\\\/?$/.test(h)){g('season_select');}"
        # Переход ИЗ рекомендательного блока: ключ блока остаётся в разметке,
        # в цель он не уходит — третьего аргумента у точки отправки нет.
        "var b=a.closest&&a.closest('[data-block-key]');"
        "if(b){g('block_click');}"
        "},true);"
        # Показ блока: половина высоты в экране. Одна отправка на загрузку
        # страницы, иначе прокрутка туда-сюда накрутила бы показы.
        "function начать(){try{if(!window.IntersectionObserver){return;}"
        "var o=new IntersectionObserver(function(es){"
        "for(var i=0;i<es.length;i++){if(es[i].isIntersecting){"
        "window.__sfGoalOnce('block_view');o.disconnect();return;}}},"
        "{threshold:0.5});"
        "var бл=document.querySelectorAll('[data-block-key]');"
        "if(!бл.length){return;}"
        "for(var j=0;j<бл.length;j++){o.observe(бл[j]);}"
        "}catch(e){}}"
        # Скрипт стоит в head и исполняется ДО разбора body: в этот момент
        # блоков в документе ещё нет, и наблюдать нечего. Поэтому установка
        # откладывается до готовности разметки.
        "if(document.readyState==='loading'){"
        "document.addEventListener('DOMContentLoaded',начать);}else{начать();}"
        "})();</script>"'''

ПАРЫ = (
    ("две цели в закрытом списке", СПИСОК_БЫЛО, СПИСОК_СТАЛО, '"block_view",'),
    ("отправка показа и перехода", ТОЧКА_БЫЛО, ТОЧКА_СТАЛО, "g('block_click')"),
)


def остатки(текст: str) -> list:
    плохо = [f"нет: {имя}" for имя, _, _, признак in ПАРЫ if признак not in текст]
    # Ключ блока обязан стоять ТАМ, ГДЕ БЛОК ЕСТЬ: без него наблюдателю нечего
    # наблюдать, и цель молчала бы при исправном коде. В рантайме, куда
    # рекомендательные блоки ещё не перенесены (канон), требовать ключ не за
    # что — цели там объявлены, чтобы новые витрины рождались с ними.
    есть_блоки = ("def _полка_главной" in текст
                  or "def визитка_подборки" in текст
                  or "def _блок_анонсов" in текст)
    if есть_блоки and 'data-block-key=' not in текст:
        плохо.append("блоки есть, а ключа в разметке нет (data-block-key)")
    return плохо


def применить(текст: str) -> tuple[str, list]:
    if "ЦЕЛИ_МЕТРИКИ" not in текст or "def цели_метрики" not in текст:
        raise SystemExit("ОТКАЗ: в файле нет отправки целей этой линии — "
                         "сначала переносится она (apply-goals-patch.py)")
    журнал = []
    for имя, было, стало, признак in ПАРЫ:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
