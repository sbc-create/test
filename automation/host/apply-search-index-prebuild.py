#!/usr/bin/env python3
"""Zona: указатель поиска строится при запуске, до приёма запросов. Перенос по якорям.

Замер 12.10: после выкладки zonafilm12.site первые /search/?q=… отдавали 504 через
30,0 с (proxy_read_timeout nginx), затем 200 за 2,2 с. Механизм (разбор
Архитектора по коду): указатель поиска ленивый, а построить_индекс при запуске
зовёт данные.сбросить_указатель() — значит его собирал синхронно ПЕРВЫЙ поисковый
запрос. Фоновая пересборка каталога эту цену уже знает и строит указатель до
подмены («посетитель ждал 7-8 с вместо десятков миллисекунд»); путь запуска —
нет. Правка: тот же вызов _построить_указатель() в main() после построить_индекс
и до ThreadingHTTPServer. Готовность (/healthz) наступает после сборки; исполнитель
ждёт до 600 с, сборка — секунды. Ошибка сборки не роняет запуск: ленивый путь
остаётся запасным.

Нет якоря или он не единственный — отказ ДО записи. Повтор ничего не меняет.

    python3 automation/host/apply-search-index-prebuild.py [--check] <lords-frontend.py> […]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

МЕТКА = "# Указатель поиска — до приёма запросов (apply-search-index-prebuild)."
ЯКОРЬ = '''    Обработчик.индекс = построить_индекс(Обработчик.данные, Обработчик.подробности)
    сервер = ThreadingHTTPServer((args.host, args.port), Обработчик)
'''
ЗАМЕНА = '''    Обработчик.индекс = построить_индекс(Обработчик.данные, Обработчик.подробности)
    ''' + МЕТКА + '''
    # Ленивый указатель собирал первый поисковый запрос после запуска, синхронно:
    # 504 через 30 с у первых посетителей после выкладки (замер 12.10). Фоновая
    # пересборка строит его до подмены — запуск теперь тоже.
    try:
        Обработчик.данные._построить_указатель()
    except Exception:  # noqa: BLE001 — указатель не обязателен для показа: ленивый путь остаётся
        pass
    сервер = ThreadingHTTPServer((args.host, args.port), Обработчик)
'''


def привести(текст: str) -> tuple[str, int]:
    if МЕТКА in текст:
        return текст, 0
    if текст.count(ЯКОРЬ) != 1:
        raise ValueError("якорь запуска найден не ровно один раз")
    if "def _построить_указатель(" not in текст:
        raise ValueError("в рантайме нет _построить_указатель — строить нечего")
    return текст.replace(ЯКОРЬ, ЗАМЕНА), 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("files", nargs="+")
    a = ap.parse_args(argv)
    код = 0
    for имя in a.files:
        путь = Path(имя)
        текст = путь.read_text(encoding="utf-8")
        try:
            новый, n = привести(текст)
        except ValueError as exc:
            print(f"{имя}: ОТКАЗ — {exc}")
            код = 2
            continue
        if a.check:
            print(f"{имя}: {'приведён' if новый == текст else 'не приведён'}")
            код = код or (0 if новый == текст else 1)
            continue
        if новый != текст:
            путь.write_text(новый, encoding="utf-8")
        print(f"{имя}: приведён")
    return код


if __name__ == "__main__":
    sys.exit(main())
