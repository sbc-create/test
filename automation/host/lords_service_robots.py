#!/usr/bin/env python3
"""Запрет индексации СЛУЖЕБНЫХ путей в ответе самого приложения — слоем.

Зачем слой
----------

У витрин-МОНОЛИТОВ значение `X-Robots-Tag` считает `мета_роботов_пути(путь)`:
служебные адреса (`/poster/`, `/api/`, `/healthz`, `/__…`) закрыты всегда,
независимо от режима сайта. У витрин на ОБЩЕМ ЯДРЕ такой функции нет: ядро
отдаёт `мета_роботов()` без пути, а править ядро в репозитории сайта запрещено
его же правилами (замок версий, `verified_against: git`, AGENTS.md п. 3).

Цена измерена 2026-10-05 на только что открытом lordserial33.biz и на давно
открытом lordfilm47.space: `/healthz` отдавал ДВА заголовка — `index, follow`
от приложения и `noindex, nofollow` от nginx. Запрет держался только на слое
nginx, а ответ противоречил сам себе. Полагаться на разрешение конфликта
нельзя: запрет служебного пути обязан стоять там, где этот путь и отдаётся.

Что делает слой

Обёртывает `send_header` обработчика ядра: если отдаётся `X-Robots-Tag` и
текущий путь служебный, значение заменяется на `noindex, nofollow`. Обёртка, а
не подмена: исходный метод вызывается всегда, и на обычных страницах ответ
совпадает с прежним байт в байт.

Перечень служебных путей берётся из `indexing_mode.СЛУЖЕБНЫЕ_ЗАПРЕТЫ` — того
же, из которого собираются `robots.txt` и карта запретов nginx. Своя копия
перечня разошлась бы с ними молча.

Чего слой НЕ делает: не трогает ядро, не меняет режим сайта, не решает за
nginx и не молчит об отказе — причина называется в журнале запуска.
"""
from __future__ import annotations

ЗАПРЕТ = "noindex, nofollow"

#: Умолчание на случай, когда модуль режима недоступен. Служебные пути
#: закрыты и тогда: отсутствие перечня не повод открыть их.
ПО_УМОЛЧАНИЮ = ("/poster/", "/api/", "/healthz", "/__")

ПОДКЛЮЧЕНО: dict = {"attached": False, "reason": "слой не подключался"}


def служебные() -> tuple[str, ...]:
    try:
        import indexing_mode
        перечень = tuple(indexing_mode.СЛУЖЕБНЫЕ_ЗАПРЕТЫ)
    except Exception:  # noqa: BLE001 — без модуля служебные всё равно закрыты
        return ПО_УМОЛЧАНИЮ
    return перечень or ПО_УМОЛЧАНИЮ


def это_служебный(путь: str, перечень: tuple[str, ...]) -> bool:
    п = (путь or "/").split("?", 1)[0]
    return any(п.startswith(с) for с in перечень)


def состояние() -> dict:
    return dict(ПОДКЛЮЧЕНО)


def подключить(ядро) -> bool:
    """Поставить слой. False — с названной причиной."""
    global ПОДКЛЮЧЕНО

    обработчик = getattr(ядро, "Обработчик", None)
    if обработчик is None:
        ПОДКЛЮЧЕНО = {"attached": False,
                      "reason": "в ядре нет класса Обработчик: подменять нечего"}
        print(f"[nova] запрет служебных путей не подключён: "
              f"{ПОДКЛЮЧЕНО['reason']}", flush=True)
        return False
    if getattr(обработчик, "_служебные_закрыты", False):
        ПОДКЛЮЧЕНО = {"attached": True, "reason": "слой уже стоял"}
        return True

    перечень = служебные()
    исходный = обработчик.send_header

    def send_header(self, имя, значение):
        if (имя or "").lower() == "x-robots-tag" and это_служебный(
                getattr(self, "path", "/"), перечень):
            значение = ЗАПРЕТ
        return исходный(self, имя, значение)

    обработчик.send_header = send_header
    обработчик._служебные_закрыты = True
    ПОДКЛЮЧЕНО = {"attached": True, "paths": list(перечень), "reason": ""}
    print(f"[nova] запрет служебных путей: {ПОДКЛЮЧЕНО}", flush=True)
    return True
