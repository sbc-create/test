#!/usr/bin/env python3
"""Поля над сеткой подборки на телефоне: отдать первому ряду несколько пикселей.

ПОВОД — измерено 27.10 сразу после расширения состава с пяти работ до
девятнадцати: вступление выросло с 211 до 265 знаков, на телефоне это одна
лишняя строка, верх первой карточки уехал с 563 на 594, и низ первого ряда
стал 852 при окне 844. Критерий линии SEO («первый ряд постеров виден
целиком») перестал выполняться на восемь пикселей.

ЧТО ДЕЛАЕТ. Только на узком экране и только на странице подборки поджимает
вертикальный ритм НАД сеткой: нижние поля вступления, справки об источниках и
строки о пересмотре состава. Текст не сокращается и не обрезается — это
требование поручения владельца, и линия SEO его подтвердила.

ЧЕГО НЕ ДЕЛАЕТ И ПОЧЕМУ ЭТО ВАЖНО ЗНАТЬ. Правка НЕ гарантирует критерий при
любом тексте: каждая лишняя строка вступления на телефоне стоит около 21
пикселя, и достаточно длинное вступление снова уведёт ряд за край. CSS не
может отвечать за длину чужого текста. Поэтому здесь не «починено навсегда», а
«возвращён запас», и величина запаса названа числом в отчёте.

    python3 automation/host/apply-collection-lead-gap-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

БЫЛО = '''/* Вступление и служебные строки — по ширине чтения, а не во всю рамку. */'''
СТАЛО = '''/* Телефон: вертикальный ритм над сеткой поджат, чтобы первый ряд постеров
   помещался в экран. Измерено после расширения состава до девятнадцати работ:
   вступление выросло на строку, низ ряда стал 852 при окне 844. Текст при
   этом НЕ сокращается — он объясняет читателю, зачем смотреть.
   Оговорка, которую нельзя терять: это возвращает запас, а не гарантирует
   критерий при любом тексте — каждая лишняя строка вступления стоит около
   21 пикселя. */
@media (max-width:599px){
  .sec--coll .claim{margin-bottom:10px}
  .sec--coll .col__src{margin-bottom:8px}
  .sec--coll .col__upd{margin-bottom:8px}
  .col__grid{gap:16px 12px}
}
/* Вступление и служебные строки — по ширине чтения, а не во всю рамку. */'''

ПАРЫ = (
    ("ритм над сеткой на телефоне", БЫЛО, СТАЛО, ".sec--coll .claim{margin-bottom"),
)


def остатки(текст: str) -> list:
    return [f"нет: {имя}" for имя, _, _, признак in ПАРЫ if признак not in текст]


def применить(текст: str) -> tuple[str, list]:
    if "СТИЛЬ_ПОДБОРКИ" not in текст:
        raise SystemExit("ОТКАЗ: в файле нет оформления подборки — сначала "
                         "применяется apply-collection-grid-patch.py")
    журнал = []
    for имя, было, стало, признак in ПАРЫ:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        if было not in текст:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден — рантайм "
                             "разошёлся с разобранным образцом")
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if "СТИЛЬ_ПОДБОРКИ" not in исходный:
                print(f"не этой линии (нет оформления подборки) {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
