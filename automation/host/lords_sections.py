"""Разделы семейства Lords: по каким признакам запись попадает в раздел.

Почему это отдельный модуль
---------------------------

До этой правки рантайм отбирал раздел одним условием — `kind == "Сериал"` или
`kind == "Фильм"`. Этого недостаточно: в снимке каталога `kind` выводится из
`type` бокового файла, а `type=tv` одинаково стоит у британской драмы, у
корейской дорамы и у китайского дунхуа. Замер lords-02 на снимке 2026-09-23
(53 688 записей): из 17 664 записей с `kind="Сериал"` игровых сериалов 7 730,
дорам 6 693, аниме и дунхуа 3 241. То есть главная «сериалов» на 59 % состояла
из того, чего владелец там не заказывал.

Дефект общий для семейства: условие живёт в ядре, и болеют им все витрины.
lords-02 и lords-03 закрыли его у себя по отдельности — здесь одна реализация
на всех.

Что считается признаком
-----------------------

Только нормализованные жанры бокового файла и `type`. Страна и название
признаком не являются:

* «Япония» стоит и у дорамы, и у аниме — страна не разделяет их;
* название ничего не доказывает вовсе, и первое же исключение это покажет.

Жанр «драма» не означает «дорама»: в словаре снимка это два разных значения
(«драма» — 22 404 записи, «дорама» — 9 588). Спутать их значило бы увести
каждую пятую запись каталога не в тот раздел.

Аниме и дунхуа
--------------

Прямые признаки — жанры «аниме» и «дунхуа». К ним добавлены демографические
пометки аниме («сёнен», «сэйнэн», «сёдзё», «дзёсей») и жанры, за пределами
аниме не встречающиеся («меха», «этти», «гарем»): на снимке lords-02 они
добавляют ровно три записи, и все три действительно аниме, у которых прямой
пометки в источнике не оказалось.

«Уся» в этот список НЕ входит, хотя и выглядит похоже: на снимке 202 записи с
этим жанром, и подавляющее большинство — живые китайские costume-дорамы. По
одному «уся» запись уехала бы из дорам в аниме.

Прочая анимация остаётся отдельным разделом: «мультфильм» без признаков аниме
— это «Мультфильмы», а не «Аниме».

Порядок отбора
--------------

Раздел, доступность и снятие дублей считаются ДО сортировки, предела и
пагинации. Срезать хвост после `[:12]` значит показать двенадцать
неподходящих записей и ноль подходящих — ровно то, что делал `взять` в ядре.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any, Callable, Iterable

#: Ключи разделов. Значение — часть публичного адреса, и менять его нельзя без
#: переноса ссылок.
ФИЛЬМЫ = "movies"
СЕРИАЛЫ = "series"
АНИМАЦИЯ = "animation"
АНИМЕ = "anime"
ДОРАМЫ = "dorama"

#: Все разделы семейства. Профиль вправе показывать не все — но считаются они
#: одинаково у всех, иначе «Сериалы» на двух витринах означали бы разное.
ВСЕ_РАЗДЕЛЫ: tuple[str, ...] = (ФИЛЬМЫ, СЕРИАЛЫ, АНИМАЦИЯ, АНИМЕ, ДОРАМЫ)

ПОДПИСИ: dict[str, str] = {
    ФИЛЬМЫ: "Фильмы",
    СЕРИАЛЫ: "Сериалы",
    АНИМАЦИЯ: "Мультфильмы",
    АНИМЕ: "Аниме",
    ДОРАМЫ: "Дорамы",
}

АДРЕСА: dict[str, str] = {к: f"/{к}/" for к in ВСЕ_РАЗДЕЛЫ}

#: Прежнее значение поля `kind`, которым раздел назывался до нормализации.
#: Нужно там, где адрес и подпись обязаны остаться прежними (`?kind=Фильм`).
ПРЕЖНИЙ_ВИД: dict[str, str] = {
    ФИЛЬМЫ: "Фильм",
    СЕРИАЛЫ: "Сериал",
    АНИМАЦИЯ: "Мультфильм",
}

#: Разделы, где запись — сериал по своей природе: у неё уместны сезон и серии.
СЕРИАЛЬНЫЕ: frozenset[str] = frozenset({СЕРИАЛЫ, ДОРАМЫ, АНИМЕ})

#: Разделы, которые НЕ попадают на главную профиля Lords только из-за общего
#: типа «Сериал». Они существуют как собственные разделы — и только там.
НЕ_НА_ГЛАВНОЙ_LORDS: frozenset[str] = frozenset({АНИМЕ, ДОРАМЫ, АНИМАЦИЯ})

#: Прямые пометки аниме и китайской анимации в словаре снимка.
ЖАНРЫ_АНИМЕ: frozenset[str] = frozenset({"аниме", "дунхуа", "донхуа"})

#: Пометки, которые за пределами аниме не встречаются. «Уся» сюда не входит
#: намеренно — см. документацию модуля.
ЖАНРЫ_АНИМЕ_КОСВЕННЫЕ: frozenset[str] = frozenset({
    "сенен", "сэйнэн", "седзе", "дзесей", "меха", "этти", "гарем",
})

ЖАНР_АНИМАЦИИ = "мультфильм"
ЖАНР_ДОРАМЫ = "дорама"

#: Поимённые исправления источника. Путь задаёт витрина; отсутствие файла —
#: законное состояние, а не отказ.
ПЕРЕМЕННАЯ_ИСПРАВЛЕНИЙ = "LORDS_CLASSIFICATION_OVERRIDES"


def нормализовать_жанр(значение: Any) -> str:
    """Жанр в сравнимом виде: регистр снят, «ё» сведена к «е».

    В снимке соседствуют «Молодёжное» и «молодёжное», «сёнен» и «сенен».
    Сравнение сырых строк пропустило бы половину пометок, а разбираться, какая
    из форм «правильная», незачем: для отбора важна только их одинаковость.
    """
    if not значение:
        return ""
    return str(значение).strip().casefold().replace("ё", "е")


def _жанры(деталь: dict | None) -> set[str]:
    return {нормализовать_жанр(г) for г in ((деталь or {}).get("genres") or []) if г}


def аниме_или_дунхуа(деталь: dict | None) -> bool:
    """Аниме и дунхуа по нормализованным признакам, а не по стране и названию."""
    жанры = _жанры(деталь)
    return bool(жанры & ЖАНРЫ_АНИМЕ) or bool(жанры & ЖАНРЫ_АНИМЕ_КОСВЕННЫЕ)


def _сериал_по_виду(запись: dict, деталь: dict | None) -> bool:
    """Сериал ли это. `type` бокового файла точнее, `kind` — запасной путь.

    Бокового файла может не быть вовсе (законное состояние рантайма), и тогда
    отбор обязан продолжать работать на полях снимка, а не обнулять раздел.
    """
    тип = str((деталь or {}).get("type") or "").strip().casefold()
    if тип == "tv":
        return True
    if тип == "movie":
        return False
    return str(запись.get("kind") or "") in ("Сериал", "Мультфильм")


def загрузить_исправления(путь: str | os.PathLike | None = None) -> dict[str, str]:
    """Поимённые исправления источника по СТАБИЛЬНОМУ идентификатору записи.

    Снимок иногда не передаёт признака, по которому запись вообще можно
    отнести к анимации: у «LEGO City» в жанрах нет ни «мультфильм», ни
    «анимация», ни идентификатора аниме-базы. Витрина в таком случае честно
    относит запись к сериалам — и ошибается вслед за источником.

    Классифицировать по названию нельзя. Поэтому исправление адресуется
    идентификатором, с записанным основанием, и живёт ровно до починки
    источника.
    """
    выбор = путь or os.environ.get(ПЕРЕМЕННАЯ_ИСПРАВЛЕНИЙ)
    if not выбор:
        return {}
    try:
        сырое = json.loads(Path(выбор).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        # Падать из-за необязательного файла значило бы менять «одна запись не
        # в том разделе» на «сайта нет».
        return {}
    готово: dict[str, str] = {}
    for запись in сырое.get("overrides") or []:
        ид = str(запись.get("id") or "").strip()
        раздел_ = str(запись.get("section") or "").strip()
        if ид and раздел_ in ВСЕ_РАЗДЕЛЫ:
            готово[ид] = раздел_
    return готово


def раздел(запись: dict, деталь: dict | None,
           исправления: dict[str, str] | None = None) -> str:
    """Единственный раздел записи. Одна запись — один раздел, без пересечений.

    Порядок проверок и есть правило приоритета: поимённое исправление сильнее
    всего, дальше аниме сильнее анимации, анимация сильнее дорамы, дорама
    сильнее деления «сериал/фильм». Иначе запись с пометками «дорама» и
    «сёнен» попала бы сразу в два раздела, а один тайтл в двух лентах главной
    — это повтор.
    """
    деталь = деталь or {}
    if исправления:
        ид = str(деталь.get("id") or "").strip()
        если = исправления.get(ид) if ид else None
        if если:
            return если
    if аниме_или_дунхуа(деталь):
        return АНИМЕ
    жанры = _жанры(деталь)
    if ЖАНР_АНИМАЦИИ in жанры:
        return АНИМАЦИЯ
    if ЖАНР_ДОРАМЫ in жанры:
        return ДОРАМЫ
    return СЕРИАЛЫ if _сериал_по_виду(запись, деталь) else ФИЛЬМЫ


class Разделы:
    """Раздел каждой записи, посчитанный один раз на поколение снимка.

    Главная строит несколько лент, каждая — проход по снимку. Считать раздел
    на каждой карточке значило бы разбирать жанры пятьдесят три тысячи раз на
    запрос; здесь это делается однажды, а дальше берётся из словаря.

    Ключ словаря — `slug`, он же ключ снимка. Пересчёт происходит вместе со
    сменой поколения каталога, а не по таймеру: поколений снимка больше
    одного, и кэш «раз на процесс» отдал бы вчерашний разбор.
    """

    def __init__(self, данные: Any, подробности: Any,
                 исправления: dict[str, str] | None = None) -> None:
        получить = getattr(подробности, "get", None)
        self.исправления = исправления if исправления is not None else загрузить_исправления()
        self.по_slug: dict[str, str] = {}
        self.по_разделу: dict[str, list] = {к: [] for к in ВСЕ_РАЗДЕЛЫ}
        self.revision = str(getattr(данные, "revision", "") or "")
        for запись in getattr(данные, "items", ()) or ():
            slug = запись.get("slug")
            if not slug:
                continue
            деталь = получить(slug) if получить else {}
            ключ = раздел(запись, деталь, self.исправления)
            self.по_slug[slug] = ключ
            self.по_разделу.setdefault(ключ, []).append(запись)

    def ключ(self, запись: dict) -> str:
        return self.по_slug.get(запись.get("slug") or "", ФИЛЬМЫ)

    def записи(self, ключ: str) -> list:
        """Записи раздела в порядке снимка. Сортировка и предел — выше по стеку."""
        return self.по_разделу.get(ключ) or []

    def сериальный(self, запись: dict) -> bool:
        return self.ключ(запись) in СЕРИАЛЬНЫЕ

    def отфильтровать(self, набор: Iterable[dict], ключ: str) -> list:
        """Отбор по разделу ДО сортировки, предела и пагинации."""
        return [з for з in набор if self.по_slug.get(з.get("slug") or "") == ключ]

    def счёт(self) -> dict[str, int]:
        return {к: len(v) for к, v in self.по_разделу.items()}


def набрать(голова: Iterable[dict], сколько: int, *,
            подходит: Callable[[dict], bool] | None = None,
            занято: set[str] | None = None,
            добор: Iterable[dict] | None = None) -> list[dict]:
    """Набрать полку: отбор и снятие дублей ДО предела, с добором.

    Чем это отличается от прежнего `взять(набор, 12)` в ядре. Тот брал первые
    N из уже готового списка и не добирал: если из двенадцати кандидатов три
    оказались аниме, полка «кино» показывала девять карточек и молчала об
    этом. Здесь порядок обратный и единственно правильный — сначала категория,
    доступность и снятие дублей, и только потом предел. Не хватило в голове
    списка — добираем следующие подходящие из `добор`.

    Чего функция не делает: не выдумывает записей и не размножает карточки.
    Если подходящих в каталоге действительно меньше, полка вернёт столько,
    сколько есть, — а раскладка покажет фактическое число.
    """
    занято = занято if занято is not None else set()
    итог: list[dict] = []

    def _пройти(источник: Iterable[dict]) -> None:
        for з in источник:
            if len(итог) >= сколько:
                return
            slug = з.get("slug")
            if not slug or slug in занято:
                continue
            if подходит is not None and not подходит(з):
                continue
            занято.add(slug)
            итог.append(з)

    _пройти(голова)
    if len(итог) < сколько and добор is not None:
        _пройти(добор)
    return итог


