#!/usr/bin/env python3
"""<title> тайтла различим среди одноимённых записей каталога (T029). Перенос по якорям.

Замер 13.10: в общем каталоге Lords/Zona 3 952 названия повторяются (10 576
записей) — «Мастер кунг-фу» 2004 и 2012 отдавали одинаковый <title>. При
повторе названия в <title> добавляется год; совпал и год — ещё оригинальное
название. Уникальные названия не меняются, H1 и разметка не трогаются.
В репозиториях Zona с исходником ядра правка внесена коммитами
(zonafilm-space aae36bf, zonafilm12-site ad59758); этот инструмент — для
общего источника automation/host/lords-frontend.py и ядер ячеек Lords.

Якоря: `def запрос_строкой(` (перед ним встаёт функция) и строка заголовка
страницы тайтла `тело, f"{имя} — смотреть онлайн — {self.имя}", путь,` (хотя бы
одна). Нет якоря — отказ ДО записи. Повторный запуск ничего не меняет.

    python3 automation/host/apply-title-disambig.py [--check] <файл> [<файл>…]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

МЕТКА = "#: Индекс повторяющихся названий на снимок каталога (apply-title-disambig)"
ЯКОРЬ_ФУНКЦИИ = "def запрос_строкой("
СТРОКА = 'тело, f"{имя} — смотреть онлайн — {self.имя}", путь,'
НОВАЯ = 'тело, f"{различимое_название(имя, запись, деталь, self.д.items)} — смотреть онлайн — {self.имя}", путь,'
ФУНКЦИЯ = МЕТКА + '''
#: Ключ — id списка записей: перечитанный снимок даёт новый список и индекс.
_ПОВТОРЫ_НАЗВАНИЙ: dict = {}


def различимое_название(имя: str, запись: dict, деталь: dict, записи: list) -> str:
    """Название для <title>, различимое среди одноимённых записей каталога (T029).

    Год — только при повторе названия; совпал и год — ещё оригинальное
    название, если оно есть и отличается. Ничего сверх полей снимка.
    """
    ключ = id(записи)
    индекс = _ПОВТОРЫ_НАЗВАНИЙ.get(ключ)
    if индекс is None:
        по_имени: dict = {}
        по_имени_году: dict = {}
        for з in записи:
            н = str(з.get("title") or "").strip().lower()
            по_имени[н] = по_имени.get(н, 0) + 1
            по_имени_году[(н, з.get("year"))] = по_имени_году.get((н, з.get("year")), 0) + 1
        индекс = (по_имени, по_имени_году)
        _ПОВТОРЫ_НАЗВАНИЙ.clear()
        _ПОВТОРЫ_НАЗВАНИЙ[ключ] = индекс
    по_имени, по_имени_году = индекс
    н = str(имя or "").strip().lower()
    год = запись.get("year")
    if по_имени.get(н, 0) < 2 or not год:
        return имя
    if по_имени_году.get((н, год), 0) < 2:
        return f"{имя} ({год})"
    оригинал = str((деталь or {}).get("original_name") or "").strip()
    if оригинал and оригинал.lower() != н:
        return f"{имя} ({оригинал}, {год})"
    return f"{имя} ({год})"


'''


def привести(текст: str) -> tuple[str, int]:
    if МЕТКА in текст:
        return текст, 0
    if текст.count(ЯКОРЬ_ФУНКЦИИ) != 1:
        raise SystemExit(f"якорь «{ЯКОРЬ_ФУНКЦИИ}» найден {текст.count(ЯКОРЬ_ФУНКЦИИ)} раз(а) — файл не тронут")
    n = текст.count(СТРОКА)
    if not n:
        raise SystemExit("строка заголовка страницы тайтла не найдена — файл не тронут")
    текст = текст.replace(ЯКОРЬ_ФУНКЦИИ, ФУНКЦИЯ + ЯКОРЬ_ФУНКЦИИ, 1).replace(СТРОКА, НОВАЯ)
    return текст, n


def main() -> int:
    п = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    п.add_argument("--check", action="store_true")
    п.add_argument("файлы", nargs="+")
    а = п.parse_args()
    плохо = 0
    for имя in а.файлы:
        путь = Path(имя)
        текст = путь.read_text(encoding="utf-8")
        if а.check:
            ок = МЕТКА in текст
            print(f"{имя}: {'приведён' if ок else 'НЕ приведён'}")
            плохо += 0 if ок else 1
            continue
        новый, n = привести(текст)
        if n:
            путь.write_text(новый, encoding="utf-8")
        print(f"{имя}: {'приведён, заголовков ' + str(n) if n else 'уже приведён'}")
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
