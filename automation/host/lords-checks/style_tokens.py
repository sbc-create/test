"""В готовой таблице стилей не остаётся нераскрытых имён токенов.

Дефект, из-за которого проверка написана. В листе Lords стояло
`background:@ALT@`, а токена `alt` в наборе семейства нет: подстановка
заменяет только объявленные имена, остальное уезжает в страницу как есть.
Браузер отбрасывает такое объявление целиком — у рамки превью подборки не
было подложки, и постер с прозрачными краями висел на просвет. В исходнике
это неотличимо от рабочего правила: `@ALT@` выглядит точно так же, как
`@INK@`. Разница видна только ПОСЛЕ подстановки, то есть в готовом CSS.

Проверяется каждая палитра семейства: профиль выбирает свой набор токенов, и
имя, объявленное в одном наборе, в другом может отсутствовать.

Переносимость: подстановка ищется по ЦЕЛИ, а не по имени
--------------------------------------------------------

Первая версия звала `РАНТАЙМ._переменными` по имени. Замер 28.10 показал, что
имя у витрин разное: у `lordserials22.info` — `_переменными`, у
`lordserial33.biz` и `1lordserials1.online` — `_подставить`. Цель одна:
подставить набор токенов в лист. Поэтому функция выбирается перебором
известных имён и ПРОВЕРЯЕТСЯ поведением — подстановка объявленного токена
обязана убрать его имя из листа. Ни одной подходящей не нашлось — исход «не
измерено» с названной причиной, а не ложный зелёный.

Коды выхода: 0 — норма, 1 — дефект, 2 — не измерено.
"""
import importlib.util
import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
os.environ.setdefault("LORDS_TEMPLATE_MANIFEST",
                      str(КОРЕНЬ / "config" / "template-manifest.json"))
sys.path.insert(0, str(КОРЕНЬ / "src"))

try:
    спец = importlib.util.spec_from_file_location(
        "_runtime", КОРЕНЬ / "src" / "lords-frontend.py")
    РАНТАЙМ = importlib.util.module_from_spec(спец)
    sys.modules["_runtime"] = РАНТАЙМ
    спец.loader.exec_module(РАНТАЙМ)
except Exception as сбой:  # noqa: BLE001
    print(f"НЕ ИЗМЕРЕНО: рантайм витрины не загружается: {сбой!r}")
    sys.exit(2)

ИМЯ_ТОКЕНА = re.compile(r"@([A-Z0-9_]{2,16})@")

#: Известные имена подстановки. Перечень, а не догадка: оба имени измерены.
ИМЕНА_ПОДСТАНОВКИ = ("_переменными", "_подставить")

#: Листы, которые витрина отдаёт браузеру, и наборы, с которыми их подставляют.
ЛИСТЫ = [имя for имя in dir(РАНТАЙМ)
         if ("СТИЛЬ" in имя or "ЛИСТ" in имя)
         and isinstance(getattr(РАНТАЙМ, имя), str)]
НАБОРЫ = {имя: getattr(РАНТАЙМ, имя) for имя in dir(РАНТАЙМ)
          if имя.startswith("ЛОРДС_ТОКЕНЫ")
          and isinstance(getattr(РАНТАЙМ, имя), dict)}

if not ЛИСТЫ or not НАБОРЫ:
    print("НЕ ИЗМЕРЕНО: не нашлось ни листа стилей, ни набора токенов — "
          "проверка не может ничего подтвердить")
    sys.exit(2)


def _выбрать_подстановку():
    """Функция, которая подставляет набор в лист. Выбирается по поведению."""
    образец_набор = next(iter(НАБОРЫ.values()))
    ключ = next((к for к in образец_набор if isinstance(к, str) and к), None)
    if ключ is None:
        return None, "в наборе токенов нет ни одного имени"
    проба = f"a{{color:@{ключ.upper()}@}}"
    причины = []
    for имя in ИМЕНА_ПОДСТАНОВКИ:
        ф = getattr(РАНТАЙМ, имя, None)
        if ф is None or not callable(ф):
            причины.append(f"{имя}: нет")
            continue
        try:
            готово = ф(проба, образец_набор)
        except Exception as сбой:  # noqa: BLE001
            причины.append(f"{имя}: падает ({type(сбой).__name__})")
            continue
        if f"@{ключ.upper()}@" in str(готово):
            причины.append(f"{имя}: имя токена не раскрыла")
            continue
        return ф, имя
    return None, "; ".join(причины)


подстановка, пояснение = _выбрать_подстановку()
if подстановка is None:
    print(f"НЕ ИЗМЕРЕНО: подстановки токенов не нашлось — {пояснение}")
    sys.exit(2)

плохо = []
for имя_листа in sorted(ЛИСТЫ):
    лист = getattr(РАНТАЙМ, имя_листа)
    if "@" not in лист:
        continue
    # Лист Lords отдаётся только с палитрами Lords. Нераскрытое имя в ЧУЖОМ
    # листе (Zona, Animedia) этой витрины не касается: его подставляют своим
    # набором, и судить о нём здесь нельзя.
    if not имя_листа.startswith("ЛОРДС"):
        continue
    for имя_набора, набор in sorted(НАБОРЫ.items()):
        готово = подстановка(лист, набор)
        осталось = sorted(set(ИМЯ_ТОКЕНА.findall(готово)))
        if осталось:
            плохо.append(f"{имя_листа} + {имя_набора}: не раскрыты {осталось}")

if плохо:
    print("в готовой таблице стилей остались нераскрытые токены:",
          *плохо, sep="\n  ", file=sys.stderr)
    sys.exit(1)
лордс = [л for л in ЛИСТЫ if л.startswith("ЛОРДС")]
print(f"листы стилей Lords раскрываются полностью "
      f"({len(лордс)} листа × {len(НАБОРЫ)} палитр, подстановка «{пояснение}»)")
