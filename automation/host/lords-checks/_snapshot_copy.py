#!/usr/bin/env python3
"""Рабочая копия каталога данных для проверки, поднимающей витрину (MOD-224).

Зачем отдельный помощник, а не цикл в каждой проверке
-----------------------------------------------------

Проверки, поднимающие витрину на копии снимка, копировали каталог данных
целиком. Измерено 28.10 по парку: таких проверок 65, и у витрин с живыми
данными посетителей часть файлов имеет права 600 и принадлежит учётной записи
витрины — журнал правок редактора, хранилище оценок и комментариев. Закрытость
этих файлов ПРАВИЛЬНА: это постоянные данные (`docs/RUNTIME_DATA_OWNERSHIP.md`).
Проверке они не нужны — ей нужен снимок каталога, — но копирование всего
подряд роняло её с `PermissionError`.

Счёт по витринам: у `zonafilm.cc` и `lordserials22.info` закрытых файлов НОЛЬ
(поэтому проверки там и проходили), у `1lordserials1.online` один, у
`lordserial33.biz` два. То есть проверка работала ровно там, где живых данных
посетителей ещё нет, и ломалась там, где они есть.

Один помощник, а не 65 правок по месту: правило «что копировать, что
подключать ссылкой, что пропускать» — один факт о витрине, и 65 его копий
разойдутся, как уже разошлись имена подстановки токенов (MOD-216), имена
проводки режима индексации (MOD-219) и адрес каталога данных (MOD-220).

Правила копирования
-------------------

* каталоги и файлы больше порога — ССЫЛКОЙ: снимок каталога у zonafilm.cc
  занимает 21 и 92 МиБ, копировать его на каждый прогон незачем, и он только
  читается;
* остальные — копией: витрина может писать в свою копию, и портить боевой
  файл нельзя;
* нечитаемые — ПРОПУСКАЮТСЯ, и их имена возвращаются вызывающему, чтобы он
  назвал пропуск в своём выводе. Молча пропускать нельзя: проверка должна
  иметь возможность сказать, чего она не видела;
* имена из `пропускать` не берутся вовсе. Это НЕ украшение: по парку есть
  проверки, которые намеренно исключают карту сайта и файлы `*.lock`
  (`hub_description.py`, `sitemap_wired.py` у zonafilm12.site и
  zonafilm.space). Помощник без такого списка подставлялся бы вместо их
  цикла и МЕНЯЛ их поведение — начал бы копировать то, что они исключают по
  своей причине. Замена общим кодом не вправе менять смысл проверки.
"""
from __future__ import annotations

import fnmatch
import pathlib
import shutil

#: Больше этого — ссылкой, а не копией.
ПОРОГ_СВЯЗИ = 4 << 20


def подготовить(откуда: pathlib.Path, куда: pathlib.Path,
                пропускать: tuple = ()) -> list[str]:
    """Собрать рабочую копию каталога данных. Возвращает пропущенные имена.

    `пропускать` — образцы имён в духе `shutil.ignore_patterns`: «sitemap»,
    «*.lock». Пропущенное по образцу в возвращаемый список НЕ попадает: это
    решение вызывающего, а не неудача чтения, и смешивать их значило бы
    сообщать о пропуске там, где его не было.
    """
    куда.mkdir(parents=True, exist_ok=True)
    пропущено: list[str] = []
    for ф in sorted(откуда.iterdir()):
        if any(fnmatch.fnmatch(ф.name, о) for о in пропускать):
            continue
        цель = куда / ф.name
        try:
            if ф.is_dir() or ф.stat().st_size > ПОРОГ_СВЯЗИ:
                цель.symlink_to(ф)
            else:
                shutil.copyfile(ф, цель)
        except (PermissionError, OSError):
            пропущено.append(ф.name)
    return пропущено


def строка_пропуска(пропущено: list[str], сколько: int = 4) -> str:
    """Строка для вывода проверки или пустая строка."""
    if not пропущено:
        return ""
    хвост = ", ".join(пропущено[:сколько])
    ещё = f" и ещё {len(пропущено) - сколько}" if len(пропущено) > сколько else ""
    return f"    | не читаются и пропущены: {хвост}{ещё}"
