#!/usr/bin/env python3
"""Справка об источниках подборки — отдельной строкой, а не внутри вступления.

ПОВОД — поручение владельца 27.10, пункт 3: «Сведения о внутренней сверке
вынеси из основного описания в справку об источниках, если она нужна
читателю». Во вступлении летнего сезона стояло «число сверено с Shikimori», у
Netflix — «Принадлежность Netflix подтверждена по источнику, а не по
названию». Это описание НАШЕЙ работы, а не ответ на вопрос «зачем мне это
смотреть», и оно занимало место в первом абзаце.

ЧТО ДЕЛАЕТ. Добавляет подборке необязательное поле `sources_note` и строку
`<p class="col__src">` под вступлением. Поле необязательное, и это важно:
подборка без него собирается как прежде, а строка не рисуется вовсе —
пустая справка об источниках хуже её отсутствия.

ЧЕГО НЕ ДЕЛАЕТ. Текстов не сочиняет и из вступления ничего не переносит
сам: и `intro`, и `sources_note` приходят из файла подборок, который готовит
линия SEO. Механизм только даёт им разные места на странице.

    python3 automation/host/apply-sources-note-patch.py [--check] <файл>…

Применяется к двум видам файлов — `collection_contract.py` (поле) и рантайму
витрины (отрисовка). Линия определяется по якорям.
"""
from __future__ import annotations

import argparse
from pathlib import Path

#: Якорь — поле `works`, а не соседние `home_rail`/`updated`: их комментарии у
#: витрин расходятся дословно, а в КАНОНИЧЕСКОМ контракте этих полей нет вовсе
#: (он отстал от витрин — отдельная находка 27.10). `works` есть во всех
#: четырёх копиях ровно по одному разу.
КОНТРАКТ_ПОЛЕ_БЫЛО = '''    works: tuple = ()'''
КОНТРАКТ_ПОЛЕ_СТАЛО = '''    works: tuple = ()
    #: Справка об источниках: откуда взяты сведения о составе. Необязательное
    #: поле, и место у него отдельное — мелкой строкой под вступлением.
    #: Во вступлении таким сведениям не место: оно отвечает читателю, зачем
    #: смотреть, а не рассказывает, как мы сверялись (поручение владельца
    #: 27.10). Пустое поле строки не рисует: пустая справка хуже её
    #: отсутствия.
    sources_note: str = ""'''

КОНТРАКТ_РАЗБОР_БЫЛО = '''            works=tuple(sorted(работы, key=lambda р: р.order))))'''
КОНТРАКТ_РАЗБОР_СТАЛО = '''            sources_note=str(с.get("sources_note") or ""),
            works=tuple(sorted(работы, key=lambda р: р.order))))'''

РАНТАЙМ_БЫЛО = '''        тело = (f'<section class="sec"><div class="sec__h">'
                f"<h1>{html.escape(подборка.title)}</h1>"
                f'<a href="/collections/">Все подборки →</a></div>'
                f'<p class="claim">{html.escape(подборка.intro)}</p>'
                f"{обновлено}{сетка}{потери}</section>")'''
РАНТАЙМ_СТАЛО = '''        # Справка об источниках — отдельная мелкая строка под вступлением, а
        # не часть его. Вступление отвечает читателю, зачем смотреть; откуда
        # взяты сведения — справка (поручение владельца 27.10). Поля нет —
        # строки нет: пустая справка хуже её отсутствия.
        справка = ""
        если_справка = getattr(подборка, "sources_note", "")
        if если_справка:
            справка = (f'<p class="col__src">'
                       f'{html.escape(если_справка)}</p>')
        тело = (f'<section class="sec"><div class="sec__h">'
                f"<h1>{html.escape(подборка.title)}</h1>"
                f'<a href="/collections/">Все подборки →</a></div>'
                f'<p class="claim">{html.escape(подборка.intro)}</p>'
                f"{справка}{обновлено}{сетка}{потери}</section>")'''

ПАРЫ_КОНТРАКТ = (
    ("поле sources_note", КОНТРАКТ_ПОЛЕ_БЫЛО, КОНТРАКТ_ПОЛЕ_СТАЛО,
     "sources_note: str = \"\""),
    ("разбор sources_note", КОНТРАКТ_РАЗБОР_БЫЛО, КОНТРАКТ_РАЗБОР_СТАЛО,
     'sources_note=str(с.get("sources_note") or "")'),
)
#: У канонического рантайма тело подборки короче: поля `updated` в нём нет,
#: и строки `{обновлено}` тоже (канон отстал от витрин — находка 27.10).
#: Поэтому якорей ДВА, и применяется тот, который в файле есть; если нет ни
#: одного — отказ, а не запись наугад.
РАНТАЙМ_БЫЛО_КАНОН = РАНТАЙМ_БЫЛО.replace("{обновлено}", "")
РАНТАЙМ_СТАЛО_КАНОН = РАНТАЙМ_СТАЛО.replace("{обновлено}", "")

ПАРЫ_РАНТАЙМ = (
    ("справка об источниках под вступлением",
     (РАНТАЙМ_БЫЛО, РАНТАЙМ_БЫЛО_КАНОН),
     (РАНТАЙМ_СТАЛО, РАНТАЙМ_СТАЛО_КАНОН),
     'class="col__src"'),
)


def линия(текст: str):
    if "class РучнаяПодборка" in текст:
        return "контракт", ПАРЫ_КОНТРАКТ
    if "def ручная_подборка" in текст:
        return "рантайм", ПАРЫ_РАНТАЙМ
    return "", ()


def остатки(текст: str) -> list:
    _, пары = линия(текст)
    return [f"нет: {имя}" for имя, _, _, признак in пары if признак not in текст]


def применить(текст: str) -> tuple[str, list]:
    имя_линии, пары = линия(текст)
    if not пары:
        raise SystemExit("ОТКАЗ: не этой линии — ни контракта подборок, "
                         "ни построителя `ручная_подборка`")
    журнал = [f"линия: {имя_линии}"]
    for имя, было, стало, признак in пары:
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            continue
        # Якорь может быть один или несколько: у канона тело подборки короче.
        варианты = было if isinstance(было, tuple) else (было,)
        замены = стало if isinstance(стало, tuple) else (стало,)
        подошёл = next((н for н, в in enumerate(варианты) if в in текст), None)
        if подошёл is None:
            raise SystemExit(f"ОТКАЗ: якорь «{имя}» не найден ни в одном из "
                             f"{len(варианты)} вариантов — файл разошёлся с "
                             "разобранным образцом")
        текст = текст.replace(варианты[подошёл], замены[подошёл], 1)
        журнал.append(f"применено: {имя}"
                      + (f" (вариант {подошёл + 1})" if len(варианты) > 1 else ""))
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            имя_линии, пары = линия(исходный)
            if not пары:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
