#!/usr/bin/env python3
"""MOD-227: «снимок есть, случая нет» переводится с кода 2 на код 0.

    python3 automation/host/apply-no-case-code.py \
        --repo var/site-repos/zonafilm-cc [--only <проверка>] [--dry-run]

Зачем
-----

Договор проверки разведён на четыре состояния (`docs/ANALYSIS_ORDER.md`):
снимка нет — код 2 и «НЕ ИЗМЕРЕНО» (пропуск, и правило MOD-221 его валит);
снимок есть, а проверяемого случая в нём сегодня нет — код 0 и «НЕТ СЛУЧАЯ»
(состояние данных, выпуск не падает).

Измерено 28.10: мест второго вида 44 в девяти витринах, и все они сегодня
отдают код 2. У zonafilm.cc, где правило MOD-221 уже стоит, таких мест три в
двух файлах — значит в день, когда в снимке не окажется страны из многих
записей или непустого раздела, прогон набора упадёт НЕ ПО ДЕЛУ. Полный прогон
на снимке 28.10 дал 80 проверок и 0 пропусков (замер линии ячейки), то есть
риск скрытый и сегодня не срабатывает.

Что делает
----------

1. Кладёт рядом с помощником `не_измерено` его брата `нет_случая`: тот же вид
   строки, но «НЕТ СЛУЧАЯ» и код 0. Строка выбрана так, чтобы не попадать под
   образец раннера `ПРОПУЩЕНО|ограничение окружения|НЕ ИЗМЕРЕНО|не измерено`.
2. Переводит ПЕРЕЧИСЛЕННЫЕ места на новый помощник. Перечень берётся из
   замера (`--places`), а не угадывается по тексту: «в снимке нет
   подробностей» бывает и настоящим «не измерено».

Ворота
------

Правка идёт на временной копии, и там проверяется ТРИ вещи:

1. файл разбирается, и новый помощник в нём есть;
2. новый помощник ведёт себя как обещано: отдельный прогон печатает «НЕТ
   СЛУЧАЯ» и выходит кодом 0. Это проверка НОВОГО поведения, а не наличия
   строки;
3. сама проверка на витрине по-прежнему даёт свой прежний код (0, 1 или 2) —
   то есть перевод не изменил её ответа на сегодняшних данных.

Чего ворота НЕ доказывают, и это сказано прямо: они не проверяют, что ветка
«нет случая» действительно сработает, когда случай исчезнет. Для этого нужен
снимок без случая — мутация следующего шага, отдельно для каждого места.
"""
from __future__ import annotations

import argparse
import ast
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

ЯКОРЬ_ПОМОЩНИКА = '''def не_измерено(причина: str) -> None:
    print(f"НЕ ИЗМЕРЕНО: {причина}")
    sys.exit(2)'''

БРАТ = '''


def нет_случая(причина: str) -> None:
    """Снимок есть, а проверяемого случая в нём сегодня нет (MOD-227).

    Код 0 и строка «НЕТ СЛУЧАЯ»: проверка исполнилась на живых данных, и
    утверждать ей нечего. Это состояние ДАННЫХ, а не неисправность, поэтому
    пропуском оно не считается — иначе правило «пропуск считается провалом»
    запретило бы выпуск в обычный день. Строка намеренно не попадает под
    образец раннера «ПРОПУЩЕНО|ограничение окружения|НЕ ИЗМЕРЕНО|не измерено».
    """
    print(f"НЕТ СЛУЧАЯ: {причина} — проверка исполнилась, утверждать нечего")
    sys.exit(0)'''

ПРОБА = '''import sys


def нет_случая(причина):
    print(f"НЕТ СЛУЧАЯ: {причина} — проверка исполнилась, утверждать нечего")
    sys.exit(0)


нет_случая("проба ворот")
'''


def _места(путь: pathlib.Path, витрина: str, только: str | None) -> list[dict]:
    записи = json.loads(путь.read_text(encoding="utf-8"))
    итог = [з for з in записи if з["витрина"] == витрина
            and з["как"] == "не_измерено()"]
    if только:
        итог = [з for з in итог if з["файл"] == f"{только}.py"]
    return итог


def _правка(файл: pathlib.Path, тексты: list[str]) -> tuple[bool, str]:
    текст = файл.read_text(encoding="utf-8")
    if "def нет_случая(" in текст:
        return False, "уже"
    if текст.count(ЯКОРЬ_ПОМОЩНИКА) != 1:
        return False, "помощника `не_измерено` известного вида нет"
    новый = текст.replace(ЯКОРЬ_ПОМОЩНИКА, ЯКОРЬ_ПОМОЩНИКА + БРАТ, 1)
    переведено = 0
    for т in тексты:
        вызов = f'не_измерено("{т}")'
        if новый.count(вызов) == 1:
            новый = новый.replace(вызов, f'нет_случая("{т}")', 1)
            переведено += 1
            continue
        вызов_ф = f'не_измерено(f"{т}")'
        if новый.count(вызов_ф) == 1:
            новый = новый.replace(вызов_ф, f'нет_случая(f"{т}")', 1)
            переведено += 1
    if not переведено:
        return False, "ни одно место перечня не нашлось дословно"
    try:
        ast.parse(новый)
    except SyntaxError as сбой:
        return False, f"правка дала бы SyntaxError: {сбой.msg} (строка {сбой.lineno})"
    файл.write_text(новый, encoding="utf-8")
    return True, f"переведено мест: {переведено}"


def _проба_помощника(врем: pathlib.Path) -> str:
    """Новый помощник обязан печатать «НЕТ СЛУЧАЯ» и выходить кодом 0."""
    проба = врем / "proba.py"
    проба.write_text(ПРОБА, encoding="utf-8")
    готово = subprocess.run([sys.executable, str(проба)],  # noqa: S603
                            capture_output=True, text=True, timeout=60)
    вывод = (готово.stdout or "") + (готово.stderr or "")
    if готово.returncode != 0:
        return f"проба помощника: код {готово.returncode}, ожидался 0"
    if "НЕТ СЛУЧАЯ" not in вывод:
        return f"проба помощника: в выводе нет «НЕТ СЛУЧАЯ» ({вывод.strip()[:80]})"
    if "НЕ ИЗМЕРЕНО" in вывод:
        return "проба помощника: вывод содержит «НЕ ИЗМЕРЕНО» — раннер счёл бы пропуском"
    return ""


def применить(репо: pathlib.Path, перечень: pathlib.Path, только: str | None,
             писать: bool) -> tuple[str, str]:
    места = _места(перечень, репо.name, только)
    if not места:
        return "skip", f"в перечне нет мест вида `не_измерено()` для {репо.name}"
    по_файлам: dict[str, list[str]] = {}
    for з in места:
        по_файлам.setdefault(з["файл"], []).append(з["текст"])
    врем = pathlib.Path(tempfile.mkdtemp(prefix="no-case-"))
    try:
        копия = врем / "repo"
        shutil.copytree(репо, копия, symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__", ".git",
                                                      "var", "artifacts"))
        беда = _проба_помощника(врем)
        if беда:
            return "refuse", беда
        отчёты, отказы = [], []
        for имя, тексты in sorted(по_файлам.items()):
            надо, причина = _правка(копия / "checks" / имя, тексты)
            if надо:
                отчёты.append(f"{имя}: {причина}")
            elif причина != "уже":
                отказы.append(f"{имя}: {причина}")
        if отказы:
            return "refuse", "; ".join(отказы)
        if not отчёты:
            return "skip", "все места уже переведены"
        for имя in sorted(по_файлам):
            готово = subprocess.run(  # noqa: S603
                [sys.executable, f"checks/{имя}"], cwd=копия,
                capture_output=True, text=True, timeout=900)
            if готово.returncode not in (0, 1, 2):
                хвост = ((готово.stdout or "") + (готово.stderr or "")).strip()
                return "refuse", (f"{имя}: код {готово.returncode} — "
                                  f"{хвост.splitlines()[-1][:120] if хвост else 'без вывода'}")
    finally:
        shutil.rmtree(врем, ignore_errors=True)
    if not писать:
        return "ok", "ворота пройдены на копии: " + "; ".join(отчёты)
    for имя, тексты in sorted(по_файлам.items()):
        надо, причина = _правка(репо / "checks" / имя, тексты)
        if not надо and причина != "уже":
            return "refuse", f"правка витрины не прошла: {имя}: {причина}"
    return "ok", "доставлено: " + "; ".join(отчёты)


def main() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--repo", required=True)
    р.add_argument("--places", default="/tmp/claude-1001/"
                   "-home-claude-wt-nova-publish-memory-02/"
                   "c1416a86-4527-43b4-94e6-35e0f08a27d0/scratchpad/"
                   "места_нет_случая.json")
    р.add_argument("--only")
    р.add_argument("--check", action="store_true")
    р.add_argument("--dry-run", action="store_true")
    а = р.parse_args()
    репо = pathlib.Path(а.repo).resolve()
    перечень = pathlib.Path(а.places)
    if not перечень.is_file():
        print(f"НЕ ИЗМЕРЕНО: нет перечня мест {перечень}")
        return 2
    исход, пояснение = применить(репо, перечень, а.only,
                                 писать=not (а.check or а.dry_run))
    print(f"[{исход:6s}] {репо.name}: {пояснение}")
    return 2 if исход == "refuse" else 0


if __name__ == "__main__":
    sys.exit(main())
