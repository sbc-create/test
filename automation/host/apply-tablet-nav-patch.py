#!/usr/bin/env python3
"""Шапка `zonafilm12.site` на планшетных ширинах: до меню можно добраться.

ПОВОД И ЗАМЕР. Приёмка 27.10 сообщила об обрезанной строке меню на 768 и
1024. Собственный замер оказался шире и жёстче — на живых витринах, ширины в
CSS-пикселях:

    zonafilm12.site  768   меню требует 688, влезает 409, за краем «Подборки»
                           и «Каталог», кнопки меню НЕТ
    zonafilm12.site  1024  требует 688, влезает 591
    zonafilm12.site  1280  требует 778, влезает 716
    zonafilm12.site  1440  помещается
    zonafilm.space   768 и 1024  меню — ящик, кнопка меню видна
    zonafilm.space   1280 и 1440 строкой, помещается

То есть на 768 два пункта меню физически недостижимы: они за краем шапки, и
кнопки, которой список открывается, в этой полосе нет.

ПРИЗНАЮ ПРЕЖНЮЮ ОШИБКУ. Разбирая 27.10 шапку этой витрины, я написал, что
строка меню с 768px — «другое решение, а не дефект», и на этом основании не
стал переносить сюда проверку `checks/header_fit.py`. Замер это опроверг:
решение, из которого нельзя попасть в «Каталог», решением не является.
Проверка оказалась переносимой, и переносить её следовало сразу.

ЧТО ДЕЛАЕТ. Двигает границу ящика меню с 767 на 1279 и оставляет кнопку меню
видимой до 1279 — ровно так, как у соседней витрины той же линии, где эта
полоса ширин работает. Разметка ящика у витрины своя и не трогается: меняются
только две границы.

    python3 automation/host/apply-tablet-nav-patch.py [--check] <файл>…
"""
from __future__ import annotations

import argparse
from pathlib import Path

ЯЩИК_БЫЛО = '@media(max-width:767px){\n.zhd__s--bar{display:none}\n.zhd__n{'
ЯЩИК_СТАЛО = (
    '/* Граница ящика меню — 1279, а не 767. На 768–1279 восемь пунктов рядом\n'
    '   с логотипом и поиском не помещаются: замер 27.10 на живой витрине —\n'
    '   меню требует 688 px при 409 доступных на 768, и «Подборки» с\n'
    '   «Каталогом» уходят за край шапки без кнопки, которой их можно\n'
    '   открыть. У соседней витрины той же линии эта полоса ширин давно\n'
    '   работает ящиком. */\n'
    '@media(max-width:1279px){\n.zhd__s--bar{display:none}\n.zhd__n{')

КНОПКИ_БЫЛО = '@media(min-width:768px){.zhd__searchbtn,.zhd__menu{display:none;margin-left:0}}\n'
КНОПКИ_СТАЛО = (
    '/* Кнопки шапки прячутся с 1280, а не с 768: до этой ширины меню — ящик,\n'
    '   и без кнопки он недостижим. */\n'
    '@media(min-width:1280px){.zhd__searchbtn,.zhd__menu{display:none;margin-left:0}}\n')

ТРЕБОВАНИЕ = ".zhd__n{"
#: Соседняя витрина той же линии добивается того же ДРУГИМ правилом: прячет
#: обе кнопки с 768 и тут же возвращает кнопку меню на 768–1279. Её файл
#: здоров, и пара к нему не относится — иначе проверка звала бы чинить
#: работающее.
ИНАЧЕ_РЕШЕНО = "@media(min-width:768px) and (max-width:1279px){.zhd__menu{display:inline-flex"
ПАРЫ = (
    ("ящик меню до 1279px", ЯЩИК_БЫЛО, ЯЩИК_СТАЛО,
     "@media(max-width:1279px){\n.zhd__s--bar{display:none}", ТРЕБОВАНИЕ),
    ("кнопки шапки до 1280px", КНОПКИ_БЫЛО, КНОПКИ_СТАЛО,
     "@media(min-width:1280px){.zhd__searchbtn,.zhd__menu{display:none",
     ТРЕБОВАНИЕ),
)
#: Пары, которые не относятся к файлу, уже решившему задачу иначе.
НЕ_ПРИМЕНЯТЬ_ЕСЛИ = (
    ("кнопки шапки до 1280px", ИНАЧЕ_РЕШЕНО),
)


def уместна(пара: tuple, текст: str) -> bool:
    имя, было, _, признак, требование = пара
    for чьё, кусок in НЕ_ПРИМЕНЯТЬ_ЕСЛИ:
        if чьё == имя and кусок in текст:
            return False
    if признак in текст:
        return True
    if требование not in текст:
        return False
    return было in текст


def остатки(текст: str) -> list:
    return [f"нет: {п[0]}" for п in ПАРЫ if уместна(п, текст) and п[3] not in текст]


def применить(текст: str) -> tuple[str, list]:
    журнал, затронуто = [], 0
    for пара in ПАРЫ:
        имя, было, стало, признак, требование = пара
        if признак in текст:
            журнал.append(f"пропущено (уже стоит): {имя}")
            затронуто += 1
            continue
        if требование not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        if было not in текст:
            журнал.append(f"не относится к этой линии: {имя}")
            continue
        текст = текст.replace(было, стало, 1)
        журнал.append(f"применено: {имя}")
        затронуто += 1
    if not затронуто:
        raise SystemExit("ОТКАЗ: ни одна пара к файлу не относится — "
                         "передан не тот файл")
    return текст, журнал


def main(аргв=None) -> int:
    р = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    р.add_argument("файлы", nargs="+")
    р.add_argument("--check", action="store_true")
    а = р.parse_args(аргв)
    плохих = 0
    for имя in а.файлы:
        путь = Path(имя)
        исходный = путь.read_text(encoding="utf-8")
        if а.check:
            if not [п for п in ПАРЫ if уместна(п, исходный)]:
                print(f"не этой линии {путь}")
                continue
            п = остатки(исходный)
            print(("ок     " if not п else "НЕ ПРИВЕДЁН ") + str(путь)
                  + ("" if not п else f"  остатки: {п}"))
            плохих += bool(п)
            continue
        новый, журнал = применить(исходный)
        print(f"== {путь}")
        for строка in журнал:
            print(f"   {строка}")
        if новый != исходный:
            путь.write_text(новый, encoding="utf-8")
    return 1 if плохих else 0


if __name__ == "__main__":
    raise SystemExit(main())
