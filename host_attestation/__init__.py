"""Host-контур: проверки, которые имеют смысл только на живом control host.

Почему отдельный пакет, а не каталог внутри `tests/`.

`pytest tests/` — герметичный прогон. Он обязан давать один и тот же ответ в
любом клоне репозитория: на ноутбуке, в контейнере CI и на боевом хосте. Всё,
что здесь собрано, этим свойством не обладает и обладать не может — оно
измеряет конкретную работающую машину.

Держать такие проверки внутри `tests/` можно было только двумя способами, и оба
плохи. Оставить как есть — и обязательная проверка PR краснеет из-за того, что
у раннера нет `/srv/site-factory`. Пометить `skip` — и «не проверяли» станет
неотличимо от «проверили, всё хорошо», ровно для тех фактов, где эта разница
дороже всего.

Поэтому они вынесены сюда и запускаются явно: `bin/host-attest`. Итог прогона —
не «зелено/красно» в чужом отчёте, а машиночитаемое свидетельство, привязанное
к candidate SHA, без которого `factory deploy --environment production` не
выпускает релиз (`factory.site_engine.attestation.gate`).

Этот пакет намеренно не содержит ни одного файла `test_*.py`: `testpaths` в
pytest.ini указывает на `tests`, и попасть в обычную коллекцию отсюда нечему.
"""
