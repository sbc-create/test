"""Итог проверки 161 доступного внутреннего запроса: автоматический исход + ручная сверка (перекрывает автомат)."""
import collections, json, sys
S = sys.argv[1]
R = json.load(open(S + "/zcc/search-landing.json"))
ABSENT = {"спецы", "жить заново", "невский", "географ глобус пропил", "слово пацана кровь на асфальте", "слово пацаслово пацана", "холоп 3", "атака титанов",
          "папины дочки", "вышка", "холодные берега", "кровавая барыня", "топи", "ничего не случается дважды", "обсессия", "киберкраш", "гнев улья",
          "твоё сердце будет разбито", "балтийское море", "самый лучший день", "далекий город  2 сезон", "трёшка", "темные начала", "жизнб по вызову",
          "айда", "диана астер", "тихий океан", "стерлинг поинт"}
SEARCH_ERR = {"дневники вампиров": "окончание множественного числа не находит «Дневники вампира»",
              "брильянтовый полицейский": "опечатка в одну букву — 0 результатов при «Бриллиантовый полицейский» в каталоге",
              "призраки комнаты 203": "одно слово не совпало — 0 результатов при «Призраки квартиры 203»",
              "отчаянные домохозяйки": "в каталоге «Отчаянные домохозяева», общепринятое название не находит",
              "властелинт колнц": "опечатки — посторонние 15 результатов, «Властелин колец» в каталоге",
              "мылодрамма": "опечатка жанра — 0 результатов, жанр «мелодрама» есть"}
RANK = {"трасса 60": "точное «Трасса 60» на 5-м месте после «Трасса 65/15/318»",
        "тачки": "«Тачки» (2006) на 4-м после «Тачки на дороге», «Тачки 3», «Тачки 2»",
        "форсаж 7": "точное «Форсаж 7» на 9-м месте",
        "гарри поттер": "8 основных фильмов на 5–12-м месте после 4 побочных"}
UNCLEAR = {"острова о", "элвин из", "lbuuth", "фаfбюро", "648965", "аг целител", "олдску", "недетское кино", "2 брак сериал"}
out = []
for r in R:
    k = r["q"].lower().strip()
    if k in SEARCH_ERR: v, why = "ошибка поиска", SEARCH_ERR[k]
    elif k in RANK: v, why = "ранжирование", RANK[k]
    elif k in ABSENT: v, why = "нет в каталоге", "проверено поиском по вхождению в каталоге zona-02"
    elif k in UNCLEAR: v, why = "смысл не установлен", "обрывок, раскладка или набор символов"
    elif r["verdict"] == "ok": v, why = "найдено", f"нужное на {r['pos']}-м месте" + ("" if (r["card"] or {}).get("player") else ", плеера нет")
    else: v, why = r["verdict"], "автомат"
    out.append({**r, "manual": v, "why": why})
json.dump(out, open(S + "/zcc/search-final.json", "w"), ensure_ascii=False, indent=1)
c = collections.Counter(); cv = collections.Counter()
for r in out: c[r["manual"]] += 1; cv[r["manual"]] += r["visits"]
print("запросов", len(out), "визитов", sum(r["visits"] for r in out)); print(dict(c)); print(dict(cv))
print("карточки найденных: все 200 и с плеером:", all((r["card"] or {}).get("status") == 200 and (r["card"] or {}).get("player") for r in out if r["manual"] == "найдено"))
