#!/usr/bin/env python3
"""Фактически отображаемые карточки блоков новинок, а не результат функции."""
import re
import sys
import urllib.error
import urllib.request
from datetime import date

БАЗА = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:9190"
СЕГОДНЯ = date.today()
ГРАНИЦА_ГОД = (СЕГОДНЯ.replace(year=СЕГОДНЯ.year - 1)).year
итог = []

def get(путь):
    import urllib.parse
    адрес = БАЗА + urllib.parse.quote(путь, safe="/?=&#")
    try:
        with urllib.request.urlopen(адрес, timeout=30) as о:
            return о.status, о.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", "replace")

def слаги(html_кусок):
    return re.findall(r'href="/title/([a-z0-9-]+)/"', html_кусок)

def вид(slug):
    if slug.startswith("arh-"):  return "архив"
    if slug.startswith("bud-"):  return "будущее"
    if slug.startswith("nog-"):  return "без года"
    if slug.startswith("ser-old-"): return "старый сериал"
    return "свежее"

def проверка(имя, ок, подр=""):
    итог.append((имя, "PASS" if ок else "FAIL", подр))

# --- 1. главная: ТОЛЬКО блоки, обещающие новизну ----------------------------
# Полки жанров и «популярное» архив показывать вправе: новизну они не обещают.
# Проверяются блоки, чей заголовок её обещает, — иначе проверка либо врёт на
# жанровых полках, либо не замечает дефект в полках новинок.
СЛОВА_НОВИЗНЫ = ("новинк", "новые", "новое", "недавн", "свеж", "обновлен", "вышл", "вышел")
код, главная = get("/")
проверка("главная отвечает 200", код == 200)
блоков, чужие_всего, подробно = 0, 0, []
for кусок in re.split(r"<h[23][^>]*>", главная)[1:]:
    # Заголовок полки может быть завёрнут в ссылку: у Lords это
    # `<h2><a href="/new/">…</a></h2>`. Без снятия тегов проверка находила
    # ноль блоков новизны и проходила ни на чём.
    сырой = кусок.split("</h", 1)[0]
    заголовок = re.sub(r"<[^>]+>", " ", сырой).strip()
    карточки = слаги(кусок)
    if not карточки or not any(w in заголовок.lower() for w in СЛОВА_НОВИЗНЫ):
        continue
    блоков += 1
    чужие_блока = [s for s in карточки if вид(s) != "свежее"]
    чужие_всего += len(чужие_блока)
    if чужие_блока:
        подробно.append(f"«{заголовок[:30]}»: {len(чужие_блока)} из {len(карточки)}")
# Отсутствие полки новинок на главной — решение раскладки, а не дефект: у
# Zona в раскладке 1.1 главная состоит из «Кино», «Сериалов» и «Анимации», а
# новизну ведёт раздел /new/. Поэтому число блоков сообщается, а требование
# предъявляется к их СОДЕРЖИМОМУ и к разделу новинок, который обязателен.
итог.append(("блоков новизны на главной", "ИЗВЕСТНО", str(блоков)))
проверка("в блоках новинок главной нет архива, будущего и записей без года",
         чужие_всего == 0, "; ".join(подробно) or f"проверено блоков {блоков}")

# --- 2. раздел новинок ------------------------------------------------------
код, новое = get("/new/")
проверка("раздел новинок отвечает 200", код == 200)
к_новинок = слаги(новое)
чужие2 = sorted({s for s in к_новинок if вид(s) != "свежее"})
проверка("в разделе новинок только вышедшее в окне",
         not чужие2, f"карточек {len(к_новинок)}, чужих {len(чужие2)}: {чужие2[:6]}")
проверка("раздел новинок не пуст", len(к_новинок) > 0, f"{len(к_новинок)} карточек")

# --- 3. вторая страница листалки -------------------------------------------
код2, стр2 = get("/new/?page=2")
if код2 == 200:
    к2 = слаги(стр2)
    чужие3 = sorted({s for s in к2 if вид(s) != "свежее"})
    проверка("вторая страница подчиняется тому же правилу",
             not чужие3, f"карточек {len(к2)}, чужих {len(чужие3)}: {чужие3[:6]}")
else:
    проверка("вторая страница подчиняется тому же правилу", True,
             f"страницы 2 нет (HTTP {код2}) — новинок меньше страницы, архивом не добрано")

# --- 4. год на карточках новинок -------------------------------------------
годы = [int(г) for г in re.findall(r'class="c__y"[^>]*>(\d{4})', новое)]
стар = [г for г in годы if г < ГРАНИЦА_ГОД]
проверка("на карточках раздела нет годов старше окна",
         not стар, f"годов на карточках {len(годы)}, старых {len(стар)}: {sorted(set(стар))[:6]}")

# --- 5. каталог архив СОХРАНИЛ ---------------------------------------------
код, каталог = get("/catalog/")
все_стр = каталог
есть_архив = any(вид(s) == "архив" for s in слаги(все_стр))
проверка("архив остался в каталоге, а не удалён из базы", есть_архив)

# --- 6. поиск находит архив -------------------------------------------------
код, поиск = get("/search/?q=Архивный")
проверка("поиск находит архивное произведение",
         код == 200 and "Архивный" in поиск)

print(f"{'проверка':<58}{'итог':<8}подробность")
print("-" * 110)
плохо = 0
for имя, статус, подр in итог:
    if статус == "FAIL":
        плохо += 1
    print(f"{имя:<58}{статус:<8}{подр}")
print("-" * 110)
print(f"всего {len(итог)}, провалов {плохо}")
sys.exit(1 if плохо else 0)
