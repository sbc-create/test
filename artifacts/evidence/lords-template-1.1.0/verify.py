#!/usr/bin/env python3
"""Приёмка нового экземпляра по адресу. Печатает таблицу и код возврата."""
import json, re, sys, urllib.request, urllib.parse, urllib.error

БАЗА = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:9190"
итог, провалы = [], []

def взять(путь, куки=""):
    # Адрес кодируется: в запросе поиска стоит кириллица, и http.client
    # требует ASCII в строке запроса.
    безопасный = urllib.parse.quote(путь, safe="/?=&#")
    зпр = urllib.request.Request(БАЗА + безопасный,
                                 headers={"Cookie": куки} if куки else {})
    try:
        with urllib.request.urlopen(зпр, timeout=30) as о:
            return о.status, о.read().decode("utf-8", "replace"), dict(о.headers)
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", "replace"), dict(e.headers)

def проверка(имя, условие, подробность=""):
    итог.append((имя, "PASS" if условие else "FAIL", подробность))
    if not условие:
        провалы.append(f"{имя}: {подробность}")

def слаги(html):
    return re.findall(r'href="/title/([a-z0-9-]+)/"', html)

ПОЛКА = re.compile(r'<section class="sec-rail"(?![^>]*data-collections)(.*?)</section>', re.S)

# --- 1. основные поверхности ------------------------------------------------
for путь, имя in (("/", "главная"), ("/catalog/", "каталог"), ("/movies/", "фильмы"),
                  ("/series/", "сериалы"), ("/anime/", "аниме"), ("/dorama/", "дорамы"),
                  ("/animation/", "мультфильмы"), ("/new/", "новое"),
                  ("/collections/", "подборки"), ("/search/?q=Фильм", "поиск"),
                  ("/title/kino-000/", "карточка"), ("/healthz", "healthz")):
    код, тело, _ = взять(путь)
    проверка(f"{имя} отвечает 200", код == 200, f"код {код}")

# --- 2. главная: разделы и заполнение ---------------------------------------
_, главная, _ = взять("/")
полки = ПОЛКА.findall(главная)
проверка("полки на главной есть", bool(полки), f"{len(полки)} полок")
чужие = {s for п in полки for s in слаги(п) if s.startswith(("anime-","dorama-","mult-"))}
проверка("на полках нет аниме/дорам/мультфильмов", not чужие, str(sorted(чужие)[:5]))
на_полках = [s for п in полки for s in слаги(п)]
проверка("на полках нет повторов", len(на_полках) == len(set(на_полках)),
         str([s for s in на_полках if на_полках.count(s) > 1][:5]))
размеры = [int(n) for n in re.findall(r'data-shelf-size="(\d+)"', главная)]
проверка("первая полка заполнена рядом 14", размеры and размеры[0] == 14, str(размеры))
проверка("полки помечены как компактные", 'data-rows="full"' in главная.split("</style>")[-1])

# --- 3. разделы содержат только своё ----------------------------------------
для = {"/anime/": "anime-", "/dorama/": "dorama-", "/animation/": "mult-",
       "/movies/": "kino-", "/series/": "serial-"}
for путь, префикс in для.items():
    _, тело, _ = взять(путь)
    найдено = set(слаги(тело))
    чужое = {s for s in найдено if not s.startswith(префикс)}
    проверка(f"{путь} только своё", not чужое, str(sorted(чужое)[:5]))
    проверка(f"{путь} непуст", bool(найдено), str(len(найдено)))

# --- 4. подборки: карточка равна странице -----------------------------------
_, хаб, _ = взять("/collections/")
карточки = re.findall(r'data-collection="([a-z_]+)" data-collection-total="(\d+)"'
                      r' data-collection-previews="(\d+)"', хаб)
проверка("карточки подборок есть", bool(карточки), str(len(карточки)))
for ключ, всего, превью in карточки:
    код, стр, _ = взять(f"/collection/{ключ}/")
    проверка(f"подборка {ключ} открывается", код == 200, f"код {код}")
    проверка(f"подборка {ключ}: превью 1..4", 0 < int(превью) <= 4, превью)
проверка("в превью есть названия", 'class="hub__n"' in хаб)
проверка("в превью есть постеры", хаб.count("<img") >= 4, str(хаб.count("<img")))

# --- 5. темы и постеры ------------------------------------------------------
проверка("переключатель темы есть", "data-theme-toggle" in главная)
стиль = главная.split("<style>",1)[1].split("</style>",1)[0]
проверка("тёмная палитра объявлена", ':root[data-theme="dark"]' in стиль)
проверка("color-scheme объявлен", "color-scheme:dark" in стиль)
постеры = re.findall(r'<img[^>]*data-poster[^>]*>', главная)
срочные = [и for и in постеры if 'fetchpriority="high"' in и]
проверка("первый экран грузится сразу", 0 < len(срочные) <= 4, str(len(срочные)))
проверка("нижние блоки отложены", any('loading="lazy"' in и for и in постеры))

# --- 6. карточка произведения, плеер, смена серии ---------------------------
# serial-001: avail=8 из eps=12 — есть и доступные, и заявленные серии.
_, карточка, _ = взять("/title/serial-001/")
проверка("плеер на карточке", 'data-player' in карточка)
проверка("серии на карточке", 'class="eps"' in карточка or "Серии" in карточка)
проверка("недоступная серия не ссылка", '<span data-off' in карточка)
код, серия, _ = взять("/title/serial-001/season-1/episode-2/")
проверка("серия 2 открывается", код == 200, f"код {код}")
проверка("в серии есть плеер", 'data-player' in серия)
код, серия3, _ = взять("/title/serial-001/season-1/episode-3/")
проверка("смена серии работает", код == 200 and серия3 != серия, f"код {код}")

# --- 7. сообщество ----------------------------------------------------------
проверка("раздел сообщества на карточке", 'id="community"' in карточка)
проверка("десять звёзд", карточка.count('name="value"') == 10,
         str(карточка.count('name="value"')))
проверка("форма комментария", 'action="/community/comment"' in карточка)
проверка("оценка кнопкой, не выбором", 'type="submit"' in карточка)

# --- 8. каталог не прячет обещанное -----------------------------------------
_, каталог, _ = взять("/catalog/")
сетки = re.findall(r'<div class="grid[^"]*"[^>]*>', каталог.split("</style>")[-1])
проверка("сетка каталога без пометки", not [с for с in сетки if 'data-rows="full"' in с],
         str(сетки[:1]))

print(f"{'проверка':<44} итог")
print("-" * 60)
for имя, статус, подр in итог:
    хвост = f"  {подр}" if статус == "FAIL" and подр else ""
    print(f"{имя:<44} {статус}{хвост}")
print("-" * 60)
print(f"всего {len(итог)}, провалов {len(провалы)}")
sys.exit(1 if провалы else 0)
