#!/usr/bin/env python3
"""Проверка перенесённого поведения на живом проверочном экземпляре.

Смотрит на СОБРАННУЮ разметку настоящего рантайма и на настоящий снимок
каталога (7446 записей, 100 мест топа), а не на строки в исходнике.
"""
import json, re, sys, urllib.request
БАЗА = "http://127.0.0.1:9310"
ок, плохо = [], []

def дай(путь):
    with urllib.request.urlopen(БАЗА + путь, timeout=60) as о:
        return о.read().decode("utf-8", "replace")

def проверить(имя, условие, подробно=""):
    (ок if условие else плохо).append(f"{имя}{(' — ' + подробно) if подробно else ''}")

# --- 1. ТОП-100 -------------------------------------------------------------
топ = дай("/top/")
ранги = [int(n) for n in re.findall(r'<a class="zt"[^>]*data-rank="(\d+)"', топ)]
адреса = re.findall(r'<a class="zt"[^>]*href="(/title/[^"]+)"', топ)
проверить("1 ТОП: сто мест", len(ранги) == 100, f"мест {len(ранги)}")
проверить("1 ТОП: нумерация 1..100", ранги == list(range(1, 101)))
проверить("1 ТОП: сто разных произведений", len(set(адреса)) == 100, f"разных {len(set(адреса))}")
проверить("1 ТОП: порядок назван на странице", 'data-top-order="summary-score"' in топ)
проверить("1 ТОП: заголовок называет число", "Топ-100" in топ)
топ2 = дай("/top/")
проверить("1 ТОП: порядок воспроизводится",
          re.findall(r'data-rank="\d+"[^>]*href="(/title/[^"]+)"', топ)
          == re.findall(r'data-rank="\d+"[^>]*href="(/title/[^"]+)"', топ2))
свежее = дай("/top/?by=fresh")
пусто = 'data-top-state="empty"' in свежее
проверить("1 ТОП: нехватка названа числом и причиной",
          пусто or ('data-top-full="0"' in свежее and "Мест в списке" in свежее),
          "срез пуст — нехватку называть нечем" if пусто else "")
голоса = дай("/top/?by=votes")
проверить("1 ТОП: пустой срез объявлен пустым, а не коротким",
          'data-top-state="empty"' in голоса or 'data-top-full' in голоса)

# --- 2-3. постеры -----------------------------------------------------------
главная = дай("/")
каталог = дай("/catalog/")
for имя, стр in (("главная", главная), ("каталог", каталог), ("топ", топ)):
    проверить(f"3 {имя}: пустого src нет", 'src=""' not in стр)
_high = каталог.count('fetchpriority="high"')
_eager = каталог.count('loading="eager"')
проверить("2 каталог: первый экран не ленивый", _high == 4, f"high={_high}")
проверить("2 каталог: срочных ровно двенадцать", _eager == 12, f"eager={_eager}")
проверить("2 каталог: остальные лениво", 'loading="lazy"' in каталог)

# --- 4. фильтры -------------------------------------------------------------
панели = re.findall(r'<details class="afilt__dd"[^>]*>', каталог)
проверить("4 фильтры: панели есть", len(панели) >= 5, f"панелей {len(панели)}")
проверить("4 фильтры: ни одна не раскрыта", not any(" open" in п for п in панели))
проверить("4 фильтры: aria-expanded объявлен", 'aria-expanded="false"' in каталог)
проверить("4 фильтры: скрипт на странице", "закрытьВсе" in каталог and "Escape" in каталог)
с_фильтром = дай("/catalog/?year=2024")
проверить("4 фильтры: применённое помечено", 'data-afilt-chosen="1"' in с_фильтром)
годы = set(re.findall(r'<span class="zt__m">[^<]*?(\d{4})</span>', с_фильтром))
проверить("4 фильтры: отбор применён к набору", годы <= {"2024"}, str(годы))

# --- 5. страница серии ------------------------------------------------------
первый = re.search(r'href="(/title/[^"/]+)/"', каталог).group(1)
slug = первый.rsplit("/", 1)[-1]
тайтл = дай(f"/title/{slug}/")
проверить("5 тайтл: открывается", "<h1" in тайтл)
сер = re.search(rf'href="(/title/{re.escape(slug)}/season-\d+/episode-\d+/)"', тайтл)
if сер is None:
    # берём первый сериал из каталога
    for кандидат in re.findall(r'href="(/title/[^"/]+)/"', каталог)[:60]:
        стр = дай(кандидат + "/")
        м = re.search(r'href="(/title/[^"]+/season-\d+/episode-\d+/)"', стр)
        if м:
            сер = м
            slug = кандидат.rsplit("/", 1)[-1]
            break
адрес_серии = сер.group(1)
серия = дай(адрес_серии)
номер = re.search(r"episode-(\d+)/$", адрес_серии).group(1)
сезон = re.search(r"season-(\d+)/", адрес_серии).group(1)
проверить("5 серия: карточка произведения есть", 'data-episode-context="1"' in серия)
проверить("5 серия: постер в карточке", 'class="zhead__img"' in серия)
проверить("5 серия: факты каталога", 'data-episode-facts="1"' in серия)
проверить("5 серия: описание произведения", 'data-episode-desc="title"' in серия)
проверить("5 серия: оценка подписана произведением",
          "Рейтинг произведения" in серия and 'data-episode-rating="title"' in серия)
проверить("5 серия: голосование подписано областью", "Оценка произведения" in серия)
проверить("5 серия: карточка ниже плеера",
          серия.index('data-b08="player"') < серия.index('data-episode-context="1"'))
проверить("5 серия: данные серии свои", f"{сезон} сезон, {номер} серия" in серия)
мета = re.search(r'<meta name="description" content="([^"]*)"', серия).group(1)
проверить("5 серия: мета-описание из фактов серии",
          f"{сезон} сезон, {номер} серия" in мета, мета[:90])
проверить("5 серия: переход между сериями есть", "zepnav" in серия)

# --- 6. подборки ------------------------------------------------------------
хаб = дай("/collections/")
проверить("6 подборки: «По контуру» не показывается", "По контуру" not in хаб)
проверить("6 подборки: порядок назван по-человечески", "В порядке разделов" in хаб)
недавние = дай("/collection/recently_added/")
всего_недавних = re.search(r'data-collection-total="(\d+)"', недавние) \
    or re.search(r"Всего (\d+)", недавние) or re.search(r"(\d+) запис", недавние)
проверить("6 подборки: паспорт подборки на странице", 'data-collection-rule="1"' in недавние)
каталог_всего = 7446
n = int(всего_недавних.group(1)) if всего_недавних else -1
проверить("6 «Недавно добавленные» — не весь каталог", 0 < n < каталог_всего, f"в подборке {n}")
года = дай("/collection/current_season/")
проверить("6 «Этого года» открывается", "<h1" in года)

# --- 14. карточки подборок --------------------------------------------------
for имя, стр in (("главная", главная), ("раздел", хаб)):
    карточки = re.findall(r'<article class="zhub__c.*?</article>', стр, re.S)
    проверить(f"14 {имя}: карточки подборок есть", bool(карточки), f"{len(карточки)}")
    тексты = [к for к in карточки if 'data-collection-preview="0"' in к]
    проверить(f"14 {имя}: текстовых плиток нет", not тексты, f"{len(тексты)}")
    for к in карточки:
        постеры = re.findall(r'<img class="zhub__img" src="([^"]*)"', к)
        ключ = re.search(r'data-collection-key="([^"]*)"', к).group(1)
        проверить(f"14 {имя}/{ключ}: обложки непустые", all(постеры) if постеры else True)
        проверить(f"14 {имя}/{ключ}: обложки не повторяются",
                  len(постеры) == len(set(постеры)), str(len(постеры)))
        подписи = re.findall(r'<span class="zhub__n">([^<]+)</span>', к)
        проверить(f"14 {имя}/{ключ}: подпись у каждой обложки",
                  len(подписи) == len(постеры), f"{len(подписи)}/{len(постеры)}")
        размеры = set(re.findall(r'zhub__img"[^>]*width="(\d+)" height="(\d+)"', к))
        проверить(f"14 {имя}/{ключ}: одинаковые пропорции",
                  размеры in ({("120", "180")}, set()), str(размеры))
        глубина, предел = 0, True
        for тег in re.findall(r"</?a\b", к):
            глубина += 1 if тег == "<a" else -1
            предел = предел and глубина in (0, 1)
        проверить(f"14 {имя}/{ключ}: вложенных ссылок нет", предел and глубина == 0)
        ссылка = re.search(r'<a class="zhub__t" href="([^"]+)"', к)
        проверить(f"14 {имя}/{ключ}: название ведёт в подборку",
                  bool(ссылка) and ссылка.group(1).startswith("/collection/"))
    колонок = re.search(r'zhub--cols-(\d+)', стр)
    проверить(f"14 {имя}: колонок не больше карточек",
              bool(колонок) and int(колонок.group(1)) <= max(1, len(карточки)))

# каждая ссылка превью открывается
адреса_превью = re.findall(r'<a class="zhub__l" href="([^"]+)"', главная)
битых = []
for а in dict.fromkeys(адреса_превью):
    try:
        дай(а)
    except Exception as ош:
        битых.append(f"{а}: {ош}")
проверить("14 главная: все ссылки превью открываются", not битых, "; ".join(битых[:3]))

# --- 7-9. лента «Новые серии» на живом реестре ------------------------------
лента_блок = re.search(r'data-b03="populated".*?</section>', главная, re.S)
проверить("7 лента: блок заполнен реестром", bool(лента_блок))
if лента_блок:
    т = лента_блок.group(0)
    проверить("7 лента: источник — сравнение снимков",
              'data-episode-feed-source="snapshot-diff"' in т)
    строки = re.findall(
        r'<a class="aeps__row"[^>]*href="([^"]+)"[^>]*data-event-id="([^"]*)"'
        r'[^>]*data-event-kind="[^"]*"[^>]*data-episode-number="(\d+)"'
        r'[^>]*data-appeared-at="([^"]*)"', т)
    проверить("8 лента: карточки есть", len(строки) >= 10, f"карточек {len(строки)}")
    адреса_л = [а for а, _, _, _ in строки]
    тайтлы = {а.split("/season-")[0] for а in адреса_л}
    проверить("8 лента: одно произведение — одна карточка",
              len(тайтлы) == len(адреса_л), f"{len(тайтлы)} тайтлов на {len(адреса_л)} карточек")
    несовпало = [(а, н) for а, _, н, _ in строки
                 if not а.endswith(f"/episode-{н}/")]
    проверить("9 лента: номер на карточке совпадает с адресом",
              not несовпало, str(несовпало[:2]))
    битые = []
    for а in dict.fromkeys(адреса_л):
        try:
            стр = дай(а)
            if "zempty" in стр and "Серия недоступна" in стр:
                битые.append(а)
        except Exception as ош:
            битые.append(f"{а}: {ош}")
    проверить("9 лента: каждая карточка ведёт на доступную серию",
              not битые, "; ".join(str(б) for б in битые[:3]))
    проверить("7 лента: подпись времени — «Появилось на сайте»",
              "Появилось на сайте" in т)
    проверить("13 лента: ссылка названа по разделу, куда ведёт",
              "Весь раздел" not in т and "Недавно добавленные в каталог" in т)
    # Страницы ленты — панели одной разметки: переключение идёт на месте, без
    # перезагрузки. Поэтому уникальность проверяется ПО ПАНЕЛЯМ, а не по
    # ответам: пять ответов с одной и той же разметкой — это не повтор.
    панели = re.findall(r'<div class="aeps" data-eps-panel="(\d+)"(.*?)</div>', т, re.S)
    все = []
    for номер, тело in панели:
        все += re.findall(r'<a class="aeps__row"[^>]*href="([^"]+)"', тело)
    проверить("8 лента: между страницами карточки не повторяются",
              len(все) == len(set(все)), f"{len(все)} карточек, {len(set(все))} разных")
    проверить("8 лента: страниц столько, сколько объявлено",
              len(панели) == int(re.search(r'data-eps-pages="(\d+)"', т).group(1)),
              f"панелей {len(панели)}")
    видимых = [н for н, тело in панели if "hidden" not in тело[:40]]
    проверить("8 лента: открыта ровно одна страница", len(видимых) == 1, str(видимых))
    # И выбор страницы уезжает в адрес: ссылки листалки настоящие.
    for стр_н in (2, 5):
        ответ = дай(f"/?eps={стр_н}")
        бл = re.search(r'data-b03="populated".*?</section>', ответ, re.S)
        проверить(f"8 лента: /?eps={стр_н} открывает свою страницу",
                  bool(бл) and f'data-eps-current="{стр_н}"' in бл.group(0))

print(f"\nОК: {len(ок)}   ПЛОХО: {len(плохо)}")
for с in плохо:
    print("  ✗", с)
sys.exit(1 if плохо else 0)
