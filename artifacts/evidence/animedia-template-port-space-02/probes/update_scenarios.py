#!/usr/bin/env python3
"""Сценарии обновления каталога на проверочном экземпляре.

Данные свои: копия боевого снимка в собственном каталоге. Живые файлы витрин
не читаются на запись и не трогаются вовсе.
"""
import copy, hashlib, importlib.util, json, sys
from pathlib import Path

V = Path(sys.argv[1])
ДАННЫЕ = V / "data"
РЕЛИЗ = sorted((V / "releases").iterdir())[-1]
import os as _os
_БАЗА = _os.environ.get("ANIMEDIA_PROBE_BASE", "http://127.0.0.1:9310")
САЙТ = _os.environ.get("ANIMEDIA_PROBE_SITE", "animedia-verify")

спец = importlib.util.spec_from_file_location("upd", РЕЛИЗ / "animedia-data-update.py")
upd = importlib.util.module_from_spec(спец); sys.modules["upd"] = спец.name and upd
спец.loader.exec_module(upd)
upd.САЙТ = САЙТ

# Сценарии ВСЕГДА начинаются с эталонного снимка, а не с того, что оставил
# прошлый прогон. Иначе лог одного запуска не воспроизводится вторым, а
# невоспроизводимый лог доказательством не является: именно на этом первый
# вариант этой проверки и попался — второй прогон не нашёл тайтла с
# отставанием, потому что первый его уже поднял.
эталон_к = ДАННЫЕ / f"{САЙТ}-catalog.orig.json"
эталон_п = ДАННЫЕ / f"{САЙТ}-details.orig.json"
assert эталон_к.is_file() and эталон_п.is_file(), "нет эталонного снимка"
каталог = json.loads(эталон_к.read_text(encoding="utf-8"))
подробности0 = json.loads(эталон_п.read_text(encoding="utf-8"))
(ДАННЫЕ / f"{САЙТ}-catalog.json").write_text(json.dumps(каталог), encoding="utf-8")
(ДАННЫЕ / f"{САЙТ}-details.json").write_text(json.dumps(подробности0), encoding="utf-8")

def дождаться_снимка(каталог_файл, метка: str, таймаут: float = 90.0) -> bool:
    """Подождать, пока ВИТРИНА перечитает снимок.

    Ждать приходится по `catalog_revision` из `/healthz`: только это поле
    берётся из ЗАГРУЖЕННОГО объекта каталога. Соседнее `details_digest`
    считается по файлу НА ДИСКЕ в момент запроса, поэтому совпадает сразу
    после записи и о состоянии витрины не говорит ничего. Первая версия этой
    проверки ждала именно его, проходила мгновенно и пропускала следующий шаг
    к прежнему снимку — тот честно находил события выше прежней доступности и
    объявлял дефектом спешку самой проверки.

    Перечитывание запускает смена mtime/размера любого из двух снимков, но
    сравнить «перечитала ли» можно только по ревизии каталога — поэтому она и
    меняется вместе с подробностями.
    """
    import json as _json, time, urllib.request
    кат = _json.loads(Path(каталог_файл).read_text(encoding="utf-8"))
    кат["revision"] = метка
    Path(каталог_файл).write_text(_json.dumps(кат), encoding="utf-8")
    край = time.time() + таймаут
    while time.time() < край:
        try:
            with urllib.request.urlopen(_БАЗА + "/healthz", timeout=10) as о:
                if _json.loads(о.read()).get("catalog_revision") == метка:
                    return True
        except Exception:
            pass
        time.sleep(2)
    return False


ок, плохо = [], []
def п(имя, условие, подробно=""):
    (ок if условие else плохо).append(f"{имя}{(' — ' + подробно) if подробно else ''}")

def прогон(подробности):
    return upd.шаг_серий(ДАННЫЕ, upd.Указатель(каталог, подробности))

def реестр():
    return json.loads((ДАННЫЕ / f"{САЙТ}-episode-events.json").read_text(encoding="utf-8"))

def состояние():
    return json.loads((ДАННЫЕ / f"{САЙТ}-episode-state.json").read_text(encoding="utf-8"))

# B. доставка подняла доступность у 60 сериалов, у одного — пачкой на сотни
# ОТСТАВАНИЕ СОЗДАЁТСЯ ЯВНО. В сегодняшнем боевом снимке ни один тайтл не
# отстаёт на сотню серий: как раз потому, что доставка и опрос давно догнали
# каталог. Сценарий воспроизводит измеренную ситуацию — круговой опрос дошёл до
# тайтла, чей снимок отстал на сотни серий, — и делает это честно: сначала
# «до» опускается в засеянном состоянии, потом «после» приносит пачку.
пачка_slug = None
for slug, д in подробности0.get("details", {}).items():
    сез = [с for с in (д.get("seasons") or []) if isinstance(с, dict)]
    if сез and int(сез[0].get("eps") or 0) >= 150 and int(сез[0].get("avail") or 0) > 0:
        пачка_slug = slug
        break
assert пачка_slug, "в снимке нет сериала на 150+ серий"
пачка_до = int(подробности0["details"][пачка_slug]["seasons"][0]["eps"])
пачка_от = 11
# «До»: у этого тайтла доступно десять серий. Именно так выглядит отставший
# снимок, который прежнее правило разворачивало в сотню событий.
подробности0 = copy.deepcopy(подробности0)
подробности0["details"][пачка_slug]["seasons"][0]["avail"] = 10

подробности1 = copy.deepcopy(подробности0)
подняли = []
подробности1["details"][пачка_slug]["seasons"][0]["avail"] = пачка_до
for slug, д in подробности1.get("details", {}).items():
    if slug == пачка_slug:
        continue
    сез = [с for с in (д.get("seasons") or []) if isinstance(с, dict)
           and int(с.get("avail") or 0) > 0]
    if not сез or len(подняли) >= 60:
        continue
    с = сез[0]
    с["avail"] = int(с["avail"]) + 1
    с["eps"] = max(int(с.get("eps") or 0), int(с["avail"]))
    подняли.append(slug)
# A. первый запуск — засев без событий
(ДАННЫЕ / f"{САЙТ}-episode-state.json").unlink(missing_ok=True)
(ДАННЫЕ / f"{САЙТ}-episode-events.json").write_text(
    json.dumps({"events": []}), encoding="utf-8")
a = прогон(подробности0)
п("A засев: событий нет", a["новых событий"] == 0, str(a))
п("A засев: схема состояния 3", состояние()["schema_version"] == 3)
п("A засев: рубеж заполнен", bool(состояние().get("high_water")))

b = прогон(подробности1)
ожидалось = len(подняли) + 1
п("B доставка: событий столько же, сколько поднятых тайтлов",
  b["новых событий"] == ожидалось,
  f'{b["новых событий"]} при ожидаемых {ожидалось} '
  f'(60 по одной серии + пачка {пачка_от}..{пачка_до})')
события = реестр()["events"]
по_тайтлу = {}
for с in события:
    по_тайтлу.setdefault(с["content_id"], []).append(с)
п("B пачка: одна доставка — одно событие на тайтл",
  max(len(v) for v in по_тайтлу.values()) == 1,
  f'максимум {max(len(v) for v in по_тайтлу.values())} событий на тайтл')
пачка = [с for с in события if с.get("episode_to") == пачка_до
         and с.get("episode_from") == пачка_от]
п("B пачка: сто с лишним серий приехали ОДНИМ событием", len(пачка) == 1,
  f"событий с этим диапазоном {len(пачка)}")
if пачка:
    п("B пачка: номер события — самая свежая серия пачки",
      пачка[0]["episode"] == пачка_до and пачка[0]["episodes_added"] >= 100,
      f'номер {пачка[0]["episode"]}, приехало {пачка[0]["episodes_added"]}')
    п("B пачка: адрес ведёт на названную серию",
      пачка[0]["url"].endswith(f'/episode-{пачка_до}/'), пачка[0]["url"])

# C. повторная доставка того же снимка — ни одного нового события
время_до = {с["event_id"]: с["first_seen_at"] for с in события}
c = прогон(подробности1)
п("C повторная доставка: новых событий нет", c["новых событий"] == 0, str(c))
п("C повторная доставка: история цела", len(реестр()["events"]) == len(события))
п("C повторная доставка: время событий не переписано",
  {с["event_id"]: с["first_seen_at"] for с in реестр()["events"]} == время_до)

# D. восстановление СТАРОГО снимка и возврат
d1 = прогон(подробности0)
п("D просадка каталога: событий нет", d1["новых событий"] == 0, str(d1))
d2 = прогон(подробности1)
п("D возврат к прежнему уровню: ложной новинки нет", d2["новых событий"] == 0, str(d2))
п("D история после просадки и возврата цела", len(реестр()["events"]) == len(события))

# E. новая озвучка / постер / оценка — не новинка
подробности2 = copy.deepcopy(подробности1)
for slug, д in list(подробности2.get("details", {}).items())[:200]:
    д["poster"] = "/сменили.webp"
    д["voice"] = "Другая студия"
    д["kinopoisk_rating"] = 9.9
e = прогон(подробности2)
п("E озвучка/постер/оценка: не новинка", e["новых событий"] == 0, str(e))

# F. настоящая новая серия — событие есть
подробности3 = copy.deepcopy(подробности1)
цель = подняли[0]
подробности3["details"][цель]["seasons"][0]["avail"] += 1
подробности3["details"][цель]["seasons"][0]["eps"] = max(
    подробности3["details"][цель]["seasons"][0]["eps"],
    подробности3["details"][цель]["seasons"][0]["avail"])
f = прогон(подробности3)
п("F настоящая новая серия: событие заведено", f["новых событий"] == 1, str(f))

# G. подрезка держит число тайтлов
п("G реестр помнит число тайтлов",
  реестр().get("titles_in_history") == len({с["content_id"] for с in реестр()["events"]}),
  str(реестр().get("titles_in_history")))
п("G предел реестра поднят", реестр().get("events_limit") == 1200)
п("G предел тайтлов объявлен", реестр().get("titles_limit") == 400)

# Оставляем на диске снимок с поднятой доступностью — витрина будет его читать.
# И ЖДЁМ, пока она его действительно перечитает: иначе следующий шаг спросит
# страницу у прежнего снимка.
(ДАННЫЕ / f"{САЙТ}-details.json").write_text(json.dumps(подробности3), encoding="utf-8")
метка = "port02-" + hashlib.sha256(
    json.dumps(подробности3, sort_keys=True).encode()).hexdigest()
п("H витрина перечитала итоговый снимок",
  дождаться_снимка(ДАННЫЕ / f"{САЙТ}-catalog.json", метка),
  f"ждали ревизию {метка[:20]}")
print(f"\nОК: {len(ок)}   ПЛОХО: {len(плохо)}")
for с in ок: print("  ·", с)
for с in плохо: print("  ✗", с)
sys.exit(1 if плохо else 0)
