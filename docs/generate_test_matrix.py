import re
from pathlib import Path

ФАЙЛЫ = [
    ("test_control_api.py", "Control API: конвейер записи"),
    ("test_api_http_transport.py", "Транспорт HTTP"),
    ("test_routing_guard.py", "Маршрутизация между слоями"),
    ("test_admin.py", "Админка: приложение"),
    ("test_admin_http.py", "Админка: подача и заголовки"),
    ("test_metrics.py", "Метрики"),
    ("test_compat.py", "Контракт CMS"),
    ("test_blast_radius.py", "Изоляция и радиус поражения"),
    ("test_site_engine_openapi.py", "Сверка описания с поведением"),
]

строки = [
    "# Матрица тестов управляющего слоя",
    "",
    "Порождена из файлов набора, а не составлена по памяти: список, ведомый",
    "отдельно от тестов, отстаёт при первом же добавлении.",
    "",
    "Пересоздать: `python docs/generate_test_matrix.py` из корня репозитория.",
    "",
]
всего = 0
таблица = ["| Область | Файл | Проверок |", "|---|---|---|"]
разделы = []
for имя, область in ФАЙЛЫ:
    путь = Path("tests/unit") / имя
    if not путь.exists():
        continue
    текст = путь.read_text(encoding="utf-8")
    # Методы внутри классов тоже считаются: без отступа в шаблоне файл со
    # сгруппированными проверками показал бы ноль.
    тесты = re.findall(r"^\s*def (test_[^\(]+)\(", текст, re.M)
    параметры = len(re.findall(r"@pytest\.mark\.parametrize", текст))
    всего += len(тесты)
    наборы = f" (+{параметры} с наборами)" if параметры else ""
    таблица.append(f"| {область} | `{имя}` | {len(тесты)}{наборы} |")
    пункты = "\n".join(
        "- " + t.replace("_", " ").capitalize() for t in тесты
    )
    разделы.append(f"## {область}\n\nФайл `tests/unit/{имя}`.\n\n{пункты}\n")

строки += таблица
строки += ["", f"**Всего в матрице: {всего} проверок.**", ""]
строки += [
    "## Что эти проверки специально не покрывают",
    "",
    "- Отказ контейнера витрины и восстановление из резервной копии: обе операции",
    "  затрагивают общий стенд, которым пользуются другие потоки.",
    "- Нагрузочное поведение транспорта: пределы измерялись только на корректность отказа.",
    "- Свежесть контента и полнота каталога: измеряются читающими маршрутами и",
    "  функциональной проверкой каталога, а не счётчиками процесса.",
    "",
    "## Уроки набора",
    "",
    "Четыре дефекта нашли сквозные проверки, а не модульные, — и все четыре",
    "проходили модульные тесты:",
    "",
    "1. Подделанный CSRF с кириллицей давал 500 вместо 403: `compare_digest` со",
    "   строками бросает `TypeError` на не-ASCII, а тест подставлял ASCII.",
    "2. `/api/v1/metrics` отвечал 404: перечень управляющих маршрутов в транспорте",
    "   вёлся литералом; сверка описания вызывает `ControlApi` напрямую, минуя транспорт.",
    "3. Витрина с нечитаемым профилем управлялась как исправная: испорченный JSON",
    "   превращался в пустой словарь, а тот означает «контракт не объявлен».",
    "4. Объявление контракта в профилях сломало ворота качества: схема запрещает",
    "   лишние свойства, а поле не было в ней объявлено.",
    "",
    "Общее у всех четырёх: проверялось верное свойство, но на данных или на слое,",
    "где дефект не проявляется.",
    "",
]
строки += разделы
Path("docs/TEST_MATRIX.md").write_text("\n".join(строки), encoding="utf-8")
print("матрица тестов записана, проверок:", всего)
