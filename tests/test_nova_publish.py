def test_адрес_не_переезжает_между_прогонами():
    """Slug закреплён за произведением: страница не меняет адрес."""
    реестр = np.РеестрСлагов()
    записи = [_запись("id-a", "Ночной дозор")]
    первый = собрать(записи, реестр=реестр)[0]["items"][0]["slug"]
    # У поставщика сменилось название — адрес обязан остаться прежним.
    второй = собрать([_запись("id-a", "Ночной дозор. Перезапуск")],
                     реестр=реестр)[0]["items"][0]["slug"]
    assert первый == второй


def test_столкновение_слагов_разводится():
    """Одинаковые названия — разные адреса, а не одно чужое произведение."""
    реестр = np.РеестрСлагов()
    каталог, подробности, _ = собрать(
        [_запись("id-1", "Мышеловка"), _запись("id-2", "Мышеловка")],
        реестр=реестр)
    слаги = [з["slug"] for з in каталог["items"]]
    assert len(set(слаги)) == 2
    assert len({з["id"] for з in подробности["details"].values()}) == 2


def test_реестр_переживает_перезагрузку(tmp_path):
    реестр = np.РеестрСлагов()
    записи = [_запись(f"id-{n}", f"Имя {n}") for n in range(5)]
    было = {з["slug"]: з for з in собрать(записи, реестр=реестр)[0]["items"]}
    путь = tmp_path / "ledger.json"
    реестр.сохранить(путь)
    снова = np.РеестрСлагов.загрузить(путь)
    стало = {з["slug"]: з for з in собрать(записи, реестр=снова)[0]["items"]}
    assert set(было) == set(стало)


def test_засеянные_привязки_сильнее_генерации():
    """Живые адреса витрины не переименовываются при переходе на снимок."""
    реестр = np.РеестрСлагов()
    реестр.засеять({"id-a": "istoricheskiy-adres"})
    каталог, _, _ = собрать([_запись("id-a", "Совсем другое название")],
                            реестр=реестр)
    assert каталог["items"][0]["slug"] == "istoricheskiy-adres"
    assert каталог["items"][0]["url"] == "/title/istoricheskiy-adres/"


def test_название_без_пригодных_символов_получает_адрес():
    реестр = np.РеестрСлагов()
    каталог, _, _ = собрать([_запись("id-x", "日本語のタイトル")], реестр=реестр)
    слаг = каталог["items"][0]["slug"]
    assert слаг and " " not in слаг
    assert каталог["items"][0]["url"] == f"/title/{слаг}/"


