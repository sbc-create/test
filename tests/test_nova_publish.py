def test_оценки_не_перепутаны_и_не_выдуманы():
    _, подробности, _ = собрать([
        _запись("id-kp", "Только КП", kp=7.5),
        _запись("id-im", "Только IMDb", imdb=6.1),
        _запись("id-both", "Обе", kp=8.2, imdb=5.4),
        _запись("id-none", "Без оценок"),
    ])
    по_ид = {з["id"]: з for з in подробности["details"].values()}
    assert по_ид["id-kp"]["kinopoisk_rating"] == 7.5
    assert по_ид["id-kp"].get("imdb_rating") is None
    assert по_ид["id-im"]["imdb_rating"] == 6.1
    assert по_ид["id-im"].get("kinopoisk_rating") is None
    assert по_ид["id-both"]["kinopoisk_rating"] == 8.2
    assert по_ид["id-both"]["imdb_rating"] == 5.4
    assert по_ид["id-none"].get("kinopoisk_rating") is None
    assert по_ид["id-none"].get("imdb_rating") is None


def test_пустое_не_затирает_известное():
    прежние = {"film": {"id": "id-a", "description": "Прежнее описание, "
                        "достаточно длинное чтобы считаться описанием.",
                        "crew": [{"name": "Режиссёр", "role": "director"}]}}
    реестр = np.РеестрСлагов()
    реестр.засеять({"id-a": "film"})
    _, подробности, _ = собрать([_запись("id-a", "Фильм")], реестр=реестр,
                                прежние=прежние)
    з = подробности["details"]["film"]
    assert з["description"].startswith("Прежнее описание")
    assert з["crew"] == [{"name": "Режиссёр", "role": "director"}]


