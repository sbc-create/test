"""Проверки канонической публикации каталога витрин Nova.

Проверяется то, чем этот контур отличается от предыдущего: обе витрины
собираются из одного снимка и обязаны получить один и тот же набор
произведений, адреса не переезжают между прогонами, а отказ источника не
имеет права стать пустым сайтом.

Случаи здесь — не гипотезы. Каждый соответствует уже наблюдавшемуся способу
испортить витрину: каталог, собранный обходом собственного релиза и потому
отставший в четырнадцать раз; сырая форма сезонов, уронившая публичные
страницы в 502 при верных значениях; пустой ответ источника.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from factory.lords import nova_publish as np


def _запись(ид, имя, *, kp=None, imdb=None, тип="movie", year=2024,
            poster="https://poster.example/p.webp", created="2026-01-01T00:00:00Z"):
    з = {"external_id": ид, "name": имя, "type": тип, "year": year,
         "poster_url": poster, "created_at": created,
         "external_ids": {"kinopoisk": f"kp-{ид}"}}
    if kp is not None:
        з["kinopoisk_rating"] = kp
    if imdb is not None:
        з["imdb_rating"] = imdb
    return з


def снимок(записи) -> np.Снимок:
    return np.Снимок(записи={str(з["external_id"]): з for з in записи},
                     получен="2026-09-14T00:00:00Z",
                     отпечаток="test-" + str(len(записи)))


def собрать(записи, *, site="lords-01", реестр=None, детали=None, прежние=None):
    детали = детали or {}
    реестр = реестр or np.РеестрСлагов()
    return np.собрать_сайт(
        снимок=снимок(записи), реестр=реестр, детали_кэш=Path("/nonexistent"),
        site_id=site, прежние_подробности=прежние or {},
        читатель=lambda _к, ид: детали.get(ид))


# ----------------------------------------------------------------------
#  Один снимок — один каталог на обеих витринах
# ----------------------------------------------------------------------

def test_витрины_получают_один_набор():
    """Равенство наборов — следствие устройства, а не последующей сверки.

    Прежде каталог витрины собирался обходом её собственного релиза: Lords
    перерисовывался и дорос до 52 683 записей, релиз Zona стоял с 10 сентября
    и держал её на 3 868. Один поставщик, одна база, разница в четырнадцать
    раз — и ни одной ошибки: обе витрины отвечали 200.
    """
    записи = [_запись(f"id-{n}", f"Фильм {n}") for n in range(20)]
    реестр = np.РеестрСлагов()
    л_кат, л_под, _ = собрать(записи, site="lords-01", реестр=реестр)
    з_кат, з_под, _ = собрать(записи, site="zona-01", реестр=реестр)
    лид = {з["id"] for з in л_под["details"].values()}
    зид = {з["id"] for з in з_под["details"].values()}
    assert лид == зид
    assert np.контрольная_сумма(лид) == np.контрольная_сумма(зид)
    assert л_кат["count"] == з_кат["count"] == 20


def test_контрольная_сумма_ловит_расхождение():
    """Совпадение количеств ничего не доказывает — сверяется множество."""
    a = np.контрольная_сумма(["id-1", "id-2", "id-3"])
    b = np.контрольная_сумма(["id-1", "id-2", "id-4"])
    assert a != b
    assert a == np.контрольная_сумма(["id-3", "id-1", "id-2", "id-1"])


