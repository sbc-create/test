СЕЗОН_ПОСТАВЩИКА = {"number": "2", "episodes_count": 12,
                    "available_episodes_count": 5, "name": "Сезон 2"}
СЕЗОН_ВИТРИНЫ = {"n": 2, "eps": 12, "avail": 5}


def test_сезоны_приводятся_к_форме_витрины():
    """Сырая форма поставщика однажды уронила публичные страницы в 502.

    Значения были верные, форма чужая: шаблон берёт `сезон["n"]` по индексу.
    """
    _, подробности, _ = собрать(
        [_запись("id-s", "Сериал", тип="tv")],
        детали={"id-s": {"id": "id-s", "seasons": [СЕЗОН_ПОСТАВЩИКА]}})
    assert подробности["details"]["serial"]["seasons"] == [СЕЗОН_ВИТРИНЫ] \
        if "serial" in подробности["details"] else True
    (з,) = подробности["details"].values()
    assert з["seasons"] == [СЕЗОН_ВИТРИНЫ]


def test_приведение_сезонов_идемпотентно():
    assert np.сезоны_рендерера([СЕЗОН_ВИТРИНЫ]) == [СЕЗОН_ВИТРИНЫ]
    assert np.сезоны_рендерера(np.сезоны_рендерера([СЕЗОН_ПОСТАВЩИКА])) \
        == [СЕЗОН_ВИТРИНЫ]
    assert np.сезоны_рендерера([{"episodes_count": 5}]) == []
    assert np.сезоны_рендерера("не список") == []


def test_валидатор_контракта():
    assert np.проверить_контракт_рендерера(
        {"a": {"seasons": [СЕЗОН_ПОСТАВЩИКА]}})[0]["field"] == "seasons"
    assert np.проверить_контракт_рендерера(
        {"a": {"crew": [{"role": "director"}]}})[0]["field"] == "crew"
    assert np.проверить_контракт_рендерера({"a": {"seasons": [СЕЗОН_ВИТРИНЫ]}}) == []


