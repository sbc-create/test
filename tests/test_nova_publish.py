def test_пустой_снимок_отклоняется(tmp_path):
    путь = tmp_path / "snap.json"
    путь.write_text(json.dumps({"items": []}), encoding="utf-8")
    with pytest.raises(np.PublishError, match="пуст"):
        np.загрузить_снимок(путь)


def test_запись_без_идентификатора_отклоняется(tmp_path):
    путь = tmp_path / "snap.json"
    путь.write_text(json.dumps({"items": [{"name": "Без ид"}]}), encoding="utf-8")
    with pytest.raises(np.PublishError, match="без канонического"):
        np.загрузить_снимок(путь)


