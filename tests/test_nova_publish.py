def test_знаменатель_покрытия_не_уменьшается():
    """Порог нельзя пройти, выкинув записи без оценки из знаменателя."""
    детали = {"a": {"kinopoisk_rating": 7.0}, "b": {}, "c": {}, "d": {}}
    п = np.покрытие(детали)
    assert п["published"] == 4
    assert п["kp"] == 1
    assert п["kp_pct"] == 25.0


def test_причина_отсутствия_поимённая():
    """Код причины ставится по записи, а не разом на весь остаток."""
    сн = снимок([
        {"external_id": "id-1", "name": "С внешним ид",
         "external_ids": {"kinopoisk": "123"}},
        {"external_id": "id-2", "name": "Без внешнего ид", "external_ids": {}},
    ])
    детали = {"a": {"id": "id-1"}, "b": {"id": "id-2"}}
    п = np.причины_отсутствия(детали, сн)
    assert п["kinopoisk"][np.НЕТ_У_ИСТОЧНИКА] == 1
    assert п["kinopoisk"][np.НЕТ_ВНЕШНЕГО_ИД] == 1


def test_оценка_ноль_не_считается_оценкой():
    """Ноль, пустая строка и None — не оценка, а её отсутствие."""
    детали = {"a": {"kinopoisk_rating": 0}, "b": {"kinopoisk_rating": ""},
              "c": {"kinopoisk_rating": None}, "d": {"kinopoisk_rating": 7.0}}
    assert np.покрытие(детали)["kp"] == 1
