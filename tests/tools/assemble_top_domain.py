#!/usr/bin/env python3
"""Сборка домена из плоских модулей верхнего уровня в пакет `factory/<домен>`.

Отличается от `assemble_domain.py` только местом: тот собирает внутри движка,
этот — рядом с ним. Домены, живущие вне движка, собирать внутрь него нельзя:
это была бы неправда о том, где они есть, и она вернула бы зависимости,
которые в этом же этапе разрывались.

Приём тот же и по тем же причинам: `git mv` сохраняет историю файла, ленивый
интерфейс не даёт пакету втянуть свои модули при импорте самого пакета,
псевдоним вместо копии сохраняет подменяемость приватных имён.
"""
from __future__ import annotations

import pathlib
import subprocess
import sys

КОРЕНЬ = pathlib.Path("/home/claude/wt-prod-25")
ПАКЕТ_ФАБРИКИ = КОРЕНЬ / "factory"

ИНИТ = '''"""Домен {домен}: {назначение}

Интерфейс ленивый: пакет с немедленным реэкспортом втягивает свои модули в
момент импорта самого пакета, и связь, безобидная между плоскими модулями,
превращается в кольцо.
"""
from __future__ import annotations

import importlib
from typing import Any

_МОДУЛИ = (
{перечень}
)


def __getattr__(имя: str) -> Any:
    if имя in _МОДУЛИ:
        return importlib.import_module(f"{{__name__}}.{{имя}}")
    raise AttributeError(
        f"домен {домен} не отдаёт «{{имя}}»: возьмите его у нужного модуля")


def __dir__() -> list[str]:
    return sorted(_МОДУЛИ)
'''

ОБЁРТКА = '''"""Совместимость: модуль переехал в домен {домен}.

Псевдоним, а не копия: прежнее имя указывает на тот же объект модуля.

Обёртка временная: снять её можно, когда последний потребитель перейдёт на
`factory.{домен}.{имя}`, и не раньше.
"""
from __future__ import annotations

import sys

from factory.{домен} import {имя} as _модуль

sys.modules[__name__] = _модуль
'''

НАЗНАЧЕНИЯ = {
    "job_runtime": "очередь, замки, состояние заданий и запросы недостающего.",
}


def собрать(домен: str, модули: list[str]) -> None:
    пакет = ПАКЕТ_ФАБРИКИ / домен
    времянка = ПАКЕТ_ФАБРИКИ / f"{домен}_pkg"
    времянка.mkdir(exist_ok=True)
    перенесено = []
    for имя in модули:
        исток = ПАКЕТ_ФАБРИКИ / f"{имя}.py"
        if not исток.is_file():
            print(f"  пропуск: {имя}.py нет")
            continue
        subprocess.run(["git", "-C", str(КОРЕНЬ), "mv", str(исток),
                        str(времянка / f"{имя}.py")], check=True)
        перенесено.append(имя)
    subprocess.run(["git", "-C", str(КОРЕНЬ), "mv", str(времянка), str(пакет)],
                   check=True)

    перечень = "\n".join(f'    "{м}",' for м in перенесено)
    (пакет / "__init__.py").write_text(
        ИНИТ.format(домен=домен, назначение=НАЗНАЧЕНИЯ.get(домен, ""),
                    перечень=перечень), encoding="utf-8")
    for имя in перенесено:
        (ПАКЕТ_ФАБРИКИ / f"{имя}.py").write_text(
            ОБЁРТКА.format(домен=домен, имя=имя), encoding="utf-8")
    print(f"домен {домен}: перенесено {len(перенесено)}")


if __name__ == "__main__":
    собрать(sys.argv[1], sys.argv[2:])
