#!/usr/bin/env python3
"""Почему упала браузерная приёмка: дефект страниц или исчезнувший стенд.

Зачем это нужно. Стенд пилота — встроенный PHP-сервер, запущенный деплоем и
никем не присматриваемый. Если он исчезает посреди прогона, КАЖДАЯ следующая
проверка падает с `net::ERR_CONNECTION_REFUSED`, и отчёт выглядит так, будто
сайт разом потерял доступность с клавиатуры, альтернативы у картинок и
горизонтальную прокрутку.

Измерено 2026-10-14: в полном прогоне 27 проверок прошли, 17 упали именно так,
журнал сервера оборвался без единой строки об ошибке (SIGKILL строк не
оставляет), а тот же прогон в одиночку дал 44 passed. Параллельно шли пять
браузерных проверок и пересоздание контейнеров — то есть причиной была
соседняя нагрузка, а не страницы.

Этот разбор НИЧЕГО не исправляет и не превращает падение в успех: шаг остаётся
FAIL. Он только называет причину, чтобы её не искали в вёрстке. Повтор как
способ получить зелёный статус здесь запрещён намеренно (`retries: 0` в
`playwright.config.js`): нестабильность страницы повтором скрывается.
"""
from __future__ import annotations

import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ОТЧЁТ = КОРЕНЬ / "artifacts" / "qa" / "pilot-local" / "playwright-report.json"
ПРИЗНАК = "ERR_CONNECTION_REFUSED"


def стенд_отвечает(адрес: str) -> bool:
    """Жив ли стенд. Ответ 401 — тоже ответ: стенд закрыт Basic-учётными данными.

    Первая редакция считала «не отвечает» любое исключение, и живой стенд,
    честно отдающий 401 без заголовка авторизации, объявлялся исчезнувшим —
    разбор получался противоположным истине. Мёртвым стенд делает только
    отказ соединения.
    """
    try:
        with urllib.request.urlopen(адрес, timeout=10) as о:
            return о.status < 500
    except urllib.error.HTTPError as ош:
        return ош.code < 500
    except (urllib.error.URLError, OSError):
        return False


def падения(отчёт: Path) -> tuple[int, int]:
    """Сколько падений всего и сколько из них — «соединение отвергнуто»."""
    try:
        данные = json.loads(отчёт.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return (0, 0)
    всего = отвергнуто = 0
    очередь = list(данные.get("suites") or [])
    while очередь:
        узел = очередь.pop()
        очередь.extend(узел.get("suites") or [])
        for тест in узел.get("specs") or []:
            for прогон in тест.get("tests") or []:
                for попытка in прогон.get("results") or []:
                    if попытка.get("status") in ("passed", "skipped"):
                        continue
                    всего += 1
                    текст = json.dumps(попытка.get("errors") or попытка.get("error") or "",
                                       ensure_ascii=False)
                    if ПРИЗНАК in текст:
                        отвергнуто += 1
    return (всего, отвергнуто)


def main() -> int:
    адрес = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8082"
    жив = стенд_отвечает(адрес)
    всего, отвергнуто = падения(ОТЧЁТ)
    print(f"   разбор приёмки: падений {всего}, из них «соединение отвергнуто» "
          f"{отвергнуто}; стенд сейчас {'отвечает' if жив else 'НЕ отвечает'}")
    if всего and отвергнуто == всего:
        print("   причина НЕ в страницах: стенд исчез во время прогона. Повторить "
              "приёмку без соседней нагрузки (браузерные проверки, пересборка "
              "контейнеров) и сравнить. Шаг остаётся FAIL до такого повтора.")
    elif отвергнуто:
        print("   часть падений — исчезнувший стенд, часть нет: разбирать по "
              "отдельности, общий вывод о страницах делать нельзя.")
    elif всего:
        print("   доступность стенда тут не при чём: падения относятся к страницам.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
