#!/usr/bin/env python3
"""Указатель инструментов приёмки: собирается из них самих.

Пятьдесят шесть сценариев в одном каталоге, и ни одного способа узнать, какой
из них отвечает на нужный вопрос. Оператор, которому надо выяснить, исчерпан ли
источник оценок или во что упирается задержка поиска, инструмент не найдёт —
и напишет свой, шестьдесят седьмой.

Указатель написан не руками намеренно. Список, который ведут отдельно от того,
что он описывает, расходится с ним на первой же правке — сегодня это уже
встретилось дважды: настройка навигации, которую никто не читает, и заявление
о совпадении выдачи, которое шире правды. Здесь первая содержательная строка
берётся из самого файла, а проверка следит, чтобы указатель не отстал.
"""
from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
ФАЙЛ = КОРЕНЬ / "INDEX.md"
РАСШИРЕНИЯ = (".py", ".sh", ".js")

#: Строки, которые описанием не являются: оболочка файла, а не его смысл.
ШЕЛУХА = re.compile(
    r'^\s*(?:#!.*|/\*+|\*+/|"""|\'\'\'|#\s*-*\s*$|\*\s*$|from\s|import\s)?\s*$')


def описание(путь: pathlib.Path) -> str:
    """Первая строка, которая говорит, что сценарий делает.

    Строка запуска описанием не является: «/usr/bin/env node» не сообщает о
    сценарии ничего, кроме того, чем его запускают.
    """
    try:
        строки = путь.read_text(encoding="utf-8").splitlines()[:12]
    except (OSError, UnicodeDecodeError):
        return ""
    for строка in строки:
        чистая = строка.strip()
        if чистая.startswith("#!"):
            continue
        for приставка in ("/**", "*/", "//", "* ", "*", "#", '"""', "'''"):
            if чистая.startswith(приставка):
                чистая = чистая[len(приставка):].strip()
                break
        # Закрывающие кавычки однострочной докстроки в описание не входят.
        for хвост in ('"""', "'''"):
            if чистая.endswith(хвост):
                чистая = чистая[: -len(хвост)].strip()
        if not чистая:
            continue
        if чистая.startswith(("from ", "import ", "set -", "cd ", "PYEOF")):
            continue
        if len(чистая) < 12:
            continue
        return чистая.rstrip(".")
    return ""


def инструменты() -> list[tuple[str, str]]:
    итог = []
    for путь in sorted(КОРЕНЬ.iterdir()):
        if путь.is_dir() or путь.suffix not in РАСШИРЕНИЯ or путь.name == ФАЙЛ.name:
            continue
        итог.append((путь.name, описание(путь)))
    return итог


def собрать() -> str:
    строки = [
        "# Инструменты приёмки",
        "",
        "Собирается из самих сценариев: `python3 tests/tools/tools_index.py --write`.",
        "Правка этого файла руками бессмысленна — описание берётся из первой",
        "содержательной строки инструмента, и проверка сверяет их.",
        "",
        "| инструмент | что делает |",
        "|---|---|",
    ]
    for имя, что in инструменты():
        строки.append(f"| `{имя}` | {что or '—'} |")
    строки.append("")
    return "\n".join(строки)


if __name__ == "__main__":
    текст = собрать()
    if "--write" in sys.argv:
        ФАЙЛ.write_text(текст, encoding="utf-8")
        print(f"записано: {ФАЙЛ} ({len(инструменты())} инструментов)")
    else:
        print(текст)
