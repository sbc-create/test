#!/usr/bin/env python3
"""Локальные инструкции по доменам — собираются из реестра, а не пишутся рядом.

Инструкция, которую ведут отдельно от того, что она описывает, расходится с
ней на первой правке. В этом контуре так уже случалось дважды: настройка
навигации, которую не читал никто, и отпечаток шаблона, отвечавший не на тот
вопрос. Поэтому текст здесь производный, а проверка следит, чтобы он не отстал.
"""
from __future__ import annotations

import pathlib
import sys

import yaml

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "domains.yaml"
КУДА = КОРЕНЬ / "docs" / "domains"


def инструкция(домен: dict) -> str:
    строки = [
        f"# Домен `{домен['id']}`",
        "",
        "> Собирается из `config/domains.yaml`.",
        "> Правка этого файла руками бессмысленна: проверка сверит его с реестром.",
        "",
        "## Назначение",
        "",
        домен["purpose"].strip(),
        "",
        "## Что держит",
        "",
    ]
    строки += [f"* `{в}`" for в in домен.get("owns") or []]
    строки += ["", "## Разрешённые пути", ""]
    строки += [f"* `{п}`" for п in домен["paths"]]
    строки += ["", "## Публичный интерфейс", "",
               "Снаружи домена берут только это. Всё остальное — устройство,",
               "и гейт границ проверяет именно это разделение.", ""]
    строки += [f"* `{и}`" for и in домен.get("public_interface") or []]
    строки += ["", "## Запрещённые зависимости", ""]
    запреты = домен.get("forbidden") or []
    строки += ([f"* `{з}`" for з in запреты] if запреты
               else ["Не объявлено."])
    строки += [
        "",
        "## Как проверить",
        "",
        "```",
        домен["check"],
        "```",
        "",
        "## Как откатить",
        "",
        домен["rollback"].strip(),
        "",
    ]
    return "\n".join(строки)


def собрать() -> dict[str, str]:
    реестр = yaml.safe_load(РЕЕСТР.read_text(encoding="utf-8"))
    return {д["id"]: инструкция(д) for д in реестр["domains"]}


if __name__ == "__main__":
    КУДА.mkdir(parents=True, exist_ok=True)
    собранное = собрать()
    if "--write" in sys.argv:
        for ид, текст in собранное.items():
            (КУДА / f"{ид}.md").write_text(текст, encoding="utf-8")
        print(f"записано инструкций: {len(собранное)} в {КУДА.relative_to(КОРЕНЬ)}")
    else:
        print(f"инструкций собрано: {len(собранное)}")
