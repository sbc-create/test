#!/usr/bin/env python3
"""Сборка домена в пакет: приём, отработанный на пяти доменах.

Порядок один и тот же, и каждый шаг отвечает за свою беду:

* `git mv` сохраняет историю файла — иначе перенос выглядит как удаление и
  создание, и `git log` перестаёт находить, почему строка такая;
* ленивый интерфейс не даёт пакету втянуть свои модули при импорте самого
  пакета: связь, безобидная между плоскими модулями, там замыкается в кольцо;
* псевдоним вместо копии сохраняет подменяемость приватных имён — копия
  отличается от модуля ровно тем, что подменять в ней нечего.

Запускается как `assemble.py <домен> <модуль> [<модуль> ...]`.
"""
from __future__ import annotations

import pathlib
import subprocess
import sys

КОРЕНЬ = pathlib.Path("/home/claude/wt-prod-25")
ДВИЖОК = КОРЕНЬ / "factory" / "site_engine"

ИНИТ = '''"""Домен {домен}: {назначение}

Интерфейс ленивый: пакет с немедленным реэкспортом втягивает свои модули в
момент импорта самого пакета, и связь, безобидная между плоскими модулями,
превращается в кольцо. Ленивое разрешение откладывает импорт до первого
обращения, когда инициализация уже закончена.
"""
from __future__ import annotations

import importlib
from typing import Any

_МОДУЛИ = (
{перечень}
)


def __getattr__(имя: str) -> Any:
    if имя in _МОДУЛИ:
        return importlib.import_module(f"{{__name__}}.{{имя}}")
    raise AttributeError(
        f"домен {домен} не отдаёт «{{имя}}»: возьмите его у нужного модуля")


def __dir__() -> list[str]:
    return sorted(_МОДУЛИ)
'''

ОБЁРТКА = '''"""Совместимость: модуль переехал в домен {домен}.

Псевдоним, а не копия: прежнее имя указывает на тот же объект модуля.

Обёртка временная: снять её можно, когда последний потребитель перейдёт на
`factory.site_engine.{домен}.{имя}`, и не раньше.
"""
from __future__ import annotations

import sys

from factory.site_engine.{домен} import {имя} as _модуль

sys.modules[__name__] = _модуль
'''

НАЗНАЧЕНИЯ = {
    "fleet": "какие витрины есть, чем они являются и в каком они состоянии.",
    "releases": "как построенное становится выложенным.",
    "job_runtime": "очередь, исполнитель, таймеры и повторы.",
    "insights": "наблюдения о происходящем: аналитика, SEO, журнал действий.",
}


def собрать(домен: str, модули: list[str]) -> None:
    пакет = ДВИЖОК / домен
    времянка = ДВИЖОК / f"{домен}_pkg"
    времянка.mkdir(exist_ok=True)
    перенесено = []
    for имя in модули:
        исток = ДВИЖОК / f"{имя}.py"
        if not исток.is_file():
            print(f"  пропуск: {имя}.py нет")
            continue
        subprocess.run(["git", "-C", str(КОРЕНЬ), "mv", str(исток),
                        str(времянка / f"{имя}.py")], check=True)
        перенесено.append(имя)
    subprocess.run(["git", "-C", str(КОРЕНЬ), "mv", str(времянка), str(пакет)],
                   check=True)

    перечень = "\n".join(f'    "{м}",' for м in перенесено)
    (пакет / "__init__.py").write_text(
        ИНИТ.format(домен=домен, назначение=НАЗНАЧЕНИЯ.get(домен, ""),
                    перечень=перечень),
        encoding="utf-8")
    for имя in перенесено:
        (ДВИЖОК / f"{имя}.py").write_text(
            ОБЁРТКА.format(домен=домен, имя=имя), encoding="utf-8")
    print(f"домен {домен}: перенесено {len(перенесено)}, псевдонимов "
          f"{len(перенесено)}")


if __name__ == "__main__":
    собрать(sys.argv[1], sys.argv[2:])
