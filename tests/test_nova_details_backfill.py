def _запись(ид, имя, слаг, *, kp=None, imdb=None, poster=None, year=2024,
            тип="movie", playback=None, external_ids=None):
    з = {"external_id": ид, "name": имя, "type": тип, "year": year,
         "external_ids": external_ids if external_ids is not None
                         else {"kinopoisk": f"kp-{ид}"}}
    if kp is not None:
        з["kinopoisk_rating"] = kp
    if imdb is not None:
        з["imdb_rating"] = imdb
    if poster is not None:
        з["poster_url"] = poster
    if playback is not None:
        з["playback"] = playback
    return з


def песочница(tmp_path: Path, *, site="lords-01", каталог=None, поставщик=None,
              карта=None, детали=None, прежний=None, revision="rev-1"):
    """Собрать раскладку production внутри tmp и вернуть профиль."""
    корень = tmp_path / "sandbox"
    профиль = bf.переукоренить(bf.ПРОФИЛИ[site], корень)
    for путь in (профиль.каталог, профиль.источник, профиль.карта, профиль.цель):
        путь.parent.mkdir(parents=True, exist_ok=True)
    профиль.детали.mkdir(parents=True, exist_ok=True)

    профиль.каталог.write_text(json.dumps(
        {"revision": revision, "builtAt": "2026-09-14T00:00:00Z",
         "count": len(каталог or []), "items": каталог or []},
        ensure_ascii=False), encoding="utf-8")
    профиль.источник.write_text(json.dumps(
        {"items": поставщик or []}, ensure_ascii=False), encoding="utf-8")
    профиль.карта.write_text(json.dumps(
        карта or {}, ensure_ascii=False), encoding="utf-8")
    for ид, деталь in (детали or {}).items():
        (профиль.детали / f"{ид}.json").write_text(
            json.dumps({"detail": деталь}, ensure_ascii=False), encoding="utf-8")
    if прежний is not None:
        профиль.цель.write_text(json.dumps(
            {"source": "detail-cache", "details_total": len(прежний),
             "details": прежний}, ensure_ascii=False), encoding="utf-8")
    return профиль


def прогнать(профиль, tmp_path, *, применить=False, **kw):
    return bf.выполнить(профиль=профиль, применить=применить,
                        копии=tmp_path / "backups", run_id="t-1",
                        с_рекомендациями=kw.pop("с_рекомендациями", False), **kw)


def детали_из(профиль):
    return json.loads(профиль.цель.read_text(encoding="utf-8"))["details"]


