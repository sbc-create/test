def test_ожидаемый_sha256_предсказывает_файл(tmp_path):
    """Сухой прогон обещает хэш тех байтов, которые лягут в файл.

    Обещание, которое нельзя сверить, — не обещание: если обещать хэш
    канонической формы, совпадения с файлом не будет никогда, и проверка
    после записи выродится в формальность.
    """
    каталог = [{"slug": f"s{n}"} for n in range(4)]
    поставщик = [_запись(f"id-{n}", f"Имя {n}", f"s{n}", kp=6.0 + n)
                 for n in range(4)]
    карта = {f"id-{n}": {"slug": f"s{n}"} for n in range(4)}
    п = песочница(tmp_path, каталог=каталог, поставщик=поставщик, карта=карта)
    сухой = прогнать(п, tmp_path, применить=False)
    assert not п.цель.exists()
    боевой = прогнать(п, tmp_path, применить=True)
    import hashlib
    фактический = hashlib.sha256(п.цель.read_bytes()).hexdigest()
    assert сухой["expected_sha256"] == фактический
    assert боевой["written_sha256"] == фактический


