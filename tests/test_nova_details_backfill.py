def test_одновременный_прогон_не_идёт(tmp_path):
    п = песочница(
        tmp_path,
        каталог=[{"slug": "alpha"}],
        поставщик=[_запись("id-a", "Альфа", "alpha", kp=7.0)],
        карта={"id-a": {"slug": "alpha"}})
    копии = tmp_path / "backups"
    копии.mkdir(parents=True, exist_ok=True)
    замок = копии / "lords-01.lock"
    with open(замок, "w") as держим:
        fcntl.flock(держим, fcntl.LOCK_EX | fcntl.LOCK_NB)
        with pytest.raises(bf.ContractViolation, match="прогон уже идёт"):
            bf.выполнить(профиль=п, применить=True, копии=копии,
                         run_id="t-2", с_рекомендациями=False)
    assert not п.цель.exists()


def test_обрыв_записи_не_портит_цель(tmp_path, monkeypatch):
    """Оборванный прогон оставляет прежний файл целым, а не половину нового."""
    было = {"alpha": {"id": "id-a", "kinopoisk_rating": 9.9}}
    п = песочница(
        tmp_path,
        каталог=[{"slug": "alpha"}],
        поставщик=[_запись("id-a", "Альфа", "alpha", kp=7.0)],
        карта={"id-a": {"slug": "alpha"}},
        прежний=было)
    целое = п.цель.read_bytes()

    def падение(*_a, **_kw):
        raise OSError("обрыв на подмене")

    monkeypatch.setattr(bf.os, "replace", падение)
    with pytest.raises(OSError):
        прогнать(п, tmp_path, применить=True)
    assert п.цель.read_bytes() == целое
    assert json.loads(п.цель.read_text(encoding="utf-8"))["details"] == было

    # Повтор после обрыва проходит целиком: состояние не «наполовину
    # применено», а ровно то, что даёт источник. Значение источника заменяет
    # прежнее — это обновление, а не потеря: правило защищает непустое от
    # обнуления, а не от более свежего значения.
    monkeypatch.undo()
    прогнать(п, tmp_path, применить=True)
