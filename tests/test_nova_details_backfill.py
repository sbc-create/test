# Этот раздел появился после боевого отказа: боковой файл записался целиком
# и с правильными значениями, а публичные страницы начали отдавать 502.
# Рендерер обращается к `сезон["n"]` без `get`, а проекция проносила сырую
# форму поставщика. Значения были верные — форма чужая.

СЕЗОН_ПОСТАВЩИКА = {"number": "2", "episodes_count": 12,
                    "available_episodes_count": 5, "name": "Сезон 2"}
СЕЗОН_ВИТРИНЫ = {"n": 2, "eps": 12, "avail": 5}


def test_сезоны_приводятся_к_форме_витрины(tmp_path):
    """Сырая форма поставщика не доходит до рендерера."""
    п = песочница(
        tmp_path,
        каталог=[{"slug": "serial"}],
        поставщик=[_запись("id-s", "Сериал", "serial", тип="series", kp=7.0)],
        карта={"id-s": {"slug": "serial"}},
        детали={"id-s": {"id": "id-s", "seasons": [СЕЗОН_ПОСТАВЩИКА]}})
    прогнать(п, tmp_path, применить=True)
    сезоны = детали_из(п)["serial"]["seasons"]
    assert сезоны == [СЕЗОН_ВИТРИНЫ]
    # Ровно те ключи, к которым шаблон обращается по индексу.
    assert set(сезоны[0]) == {"n", "eps", "avail"}


