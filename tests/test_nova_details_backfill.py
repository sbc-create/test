"""Проверки backfill'а бокового файла витрин Nova.

Проверяется поведение на границах, а не счастливый путь: именно на границах
инструмент, который пишет в production, обходится дорого. Каждый случай здесь
соответствует способу испортить витрину, который уже наблюдался или возможен
по построению: пустое вместо значения, чужая сущность под знакомым адресом,
исчезнувший каталог из-за неполного кэша, два прогона сразу.

Песочница повторяет production-раскладку целиком: тот же профиль, те же
проверки. Отдельный «тестовый режим» проверял бы не то, что работает.
"""
from __future__ import annotations

import fcntl
import importlib.util
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
_спец = importlib.util.spec_from_file_location(
    "nova_details_backfill",
    КОРЕНЬ / "automation" / "host" / "nova-details-backfill.py")
bf = importlib.util.module_from_spec(_спец)
# Модуль регистрируется до исполнения: @dataclass ищет владельца класса в
# sys.modules, и без этой строки разбор аннотаций падает на пустом модуле.
sys.modules["nova_details_backfill"] = bf
_спец.loader.exec_module(bf)


