def test_отсутствие_оценки_не_ломает_страницу(зона):
    полное = запросить(зона, "/title/bez-ocenki/").тело
    тело = разметка(полное)
    assert "Оценок пока нет" in тело
    assert len(re.findall(r"<h1\b", тело)) == 1
    # Оценки СОБСТВЕННО произведения размечены `rbs__i`; `zt__ri` — это оценки
    # на карточках блока «Смотрите также», они принадлежат другим тайтлам.
    # Искать `data-source` по всей странице значило бы считать чужую оценку
    # своей, а искать по всему документу — находить имя класса в таблице
    # стилей вместо элемента.
    assert "rbs__i" not in тело, "у произведения без оценок отрисована оценка"
    assert 'class="rbs rbs--none"' in тело


