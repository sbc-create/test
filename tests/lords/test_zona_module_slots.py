"""Zona: точки подключения общих модулей — оценок и комментариев.

Задание требует не подключать модули, а подтвердить готовность: есть ли на
витрине место, куда общий модуль сможет встать, и не ломает ли это место
страницу, пока модуль не подключён.

Проверяется ровно это. Кода модулей здесь нет и не появится: копия чужой
разметки в шаблоне — то самое, что задание запрещает.
"""
from __future__ import annotations

import re
import tempfile
from pathlib import Path

import pytest

from tests.lords.zona_kit import поднять, запросить


@pytest.fixture(scope="module")
def зона():
    return поднять(Path(tempfile.mkdtemp()), имя_модуля="nova_zona_slots")


def разметка(тело: str) -> str:
    без = re.sub(r"<style\b.*?</style>", "", тело, flags=re.S)
    return re.sub(r"<script\b.*?</script>", "", без, flags=re.S)


# --------------------------------------------------------------------------
# Комментарии: точка есть, но модуль не подключён
# --------------------------------------------------------------------------

def test_точка_комментариев_объявлена_на_странице_тайтла(зона):
    тело = разметка(запросить(зона, "/title/svezhiy/").тело)
    m = re.search(r'<section class="zcomments"[^>]*>', тело)
    assert m, "на странице произведения нет точки подключения комментариев"
    тег = m.group(0)
    assert 'id="comments"' in тег, "нет якоря для прямой ссылки"
    assert 'data-comments="0"' in тег, "не объявлено, что комментариев нет"
    assert 'data-comments-space="zona"' in тег, "не объявлено пространство"
    assert 'data-comments-subject="svezhiy"' in тег, (
        "точка не называет предмет обсуждения — модулю не к чему привязаться")


def test_точка_комментариев_скрыта_пока_модуль_не_подключён(зона):
    тег = re.search(r'<section class="zcomments"[^>]*>',
                    разметка(запросить(зона, "/title/svezhiy/").тело)).group(0)
    assert " hidden" in тег, "пустая секция осталась в потоке страницы"
    assert 'aria-hidden="true"' in тег, "пустая секция осталась в дереве доступности"


def test_точка_комментариев_пуста(зона):
    """Отрицательный тест: кода модуля в шаблоне быть не должно."""
    тело = разметка(запросить(зона, "/title/svezhiy/").тело)
    m = re.search(r'<section class="zcomments".*?</section>', тело, re.S)
    assert m, "секции нет"
    внутри = re.sub(r"<[^>]+>", "", m.group(0)).strip()
    assert внутри == "", f"внутри точки подключения что-то есть: {внутри[:60]!r}"
    assert "Комментари" not in тело, (
        "в шаблон попал текст модуля комментариев — это раскатка, а не точка")


def test_точка_комментариев_не_ломает_число_h1(зона):
    тело = запросить(зона, "/title/svezhiy/").тело
    assert len(re.findall(r"<h1\b", тело)) == 1


def test_точка_комментариев_не_протекла_к_соседу(tmp_path):
    """`ВидАнимедиа` наследует `тайтл`: объявление Zona не должно быть у него."""
    аним = поднять(tmp_path, family="animedia", design="1.2.1",
                   имя_модуля="nova_animedia_slots")
    тело = запросить(аним, "/title/svezhiy/").тело
    assert 'class="zcomments"' not in тело
    assert 'data-comments-space="zona"' not in тело


