def test_точка_оценок_на_странице_тайтла(зона):
    тело = запросить(зона, "/title/svezhiy/").тело
    assert 'data-source="kp"' in тело and 'data-source="imdb"' in тело
    assert "из 10" in тело, "шкала не названа"


def test_отсутствие_оценки_не_ломает_страницу(зона):
    полное = запросить(зона, "/title/bez-ocenki/").тело
    тело = разметка(полное)
    assert "Оценок пока нет" in тело
    assert len(re.findall(r"<h1\b", тело)) == 1
    # Оценки СОБСТВЕННО произведения размечены `rbs__i`; `zt__ri` — это оценки
    # на карточках блока «Смотрите также», они принадлежат другим тайтлам.
    # Искать `data-source` по всей странице значило бы считать чужую оценку
    # своей, а искать по всему документу — находить имя класса в таблице
    # стилей вместо элемента.
    assert "rbs__i" not in тело, "у произведения без оценок отрисована оценка"
    assert 'class="rbs rbs--none"' in тело


def test_точка_оценок_на_карточке(зона):
    тело = запросить(зона, "/catalog/").тело
    карточки = re.findall(r'<a class="zt"[^>]*>', тело)
    assert карточки, "карточек нет"
    assert all("data-rating=" in к for к in карточки), (
        "не у каждой карточки объявлено состояние оценки")


def test_ноль_не_выдаётся_за_оценку(зона):
    """Отрицательный тест: пустая оценка и оценка 0 — разные утверждения."""
    тело = запросить(зона, "/title/nol-ocenka/").тело
    assert "Оценок пока нет" in тело
    assert ">0<" not in тело.replace(" ", "")


def test_источник_не_выводится_громоздко(зона):
    """Подпись источника — короткая метка, а не предложение."""
    тело = запросить(зона, "/title/svezhiy/").тело
    метки = re.findall(r'<span class="rbs__s"[^>]*>([^<]*)</span>', тело)
    assert метки, "подписи источников не найдены"
    for м in метки:
        assert len(м) <= 12, f"громоздкая подпись источника: {м!r}"
