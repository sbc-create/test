def test_точка_не_монтируется_без_постоянного_идентификатора(tmp_path):
    """Fail-closed: без постоянного id точки быть не должно.

    Смонтировать обсуждение на slug значит завести данные под ключом-адресом.
    Переименование тайтла осиротит их, и придётся мигрировать то, чего можно
    было не создавать. Отсутствие точки честнее неверного ключа.
    """
    from tests.lords.zona_kit import ПОДРОБНОСТИ
    безымянные = {слаг: {к: з for к, з in деталь.items() if к != "id"}
                  for слаг, деталь in ПОДРОБНОСТИ.items()}
    стенд = поднять(tmp_path, имя_модуля="nova_zona_slots_noid",
                    подробности=безымянные)
    ответ = запросить(стенд, "/title/svezhiy/")
    assert ответ.статус == 200, "страница обязана остаться рабочей и без точки"
    assert 'class="zcomments"' not in разметка(ответ.тело), (
        "точка смонтирована на записи без постоянного идентификатора")


def test_пространство_комментариев_различает_витрины_одного_семейства(tmp_path):
    """Изоляция: у zona-01 и zona-02 разные пространства.

    Обе витрины — семейство `zona` (zonafilm.space и zonafilm.cc). Ключ на
    семействе показал бы комментарии одного публичного сайта на другом.
    """
    вторая = поднять(tmp_path, имя_модуля="nova_zona_slots_site2", site="zona-02")
    тег = re.search(r'<section class="zcomments"[^>]*>',
                    разметка(запросить(вторая, "/title/svezhiy/").тело)).group(0)
    assert 'data-comments-space="zona-02"' in тег, (
        "вторая витрина того же семейства получила чужое пространство")
    assert 'data-comments-space="zona"' not in тег, (
        "пространство осталось на семействе — комментарии смешались бы между сайтами")
