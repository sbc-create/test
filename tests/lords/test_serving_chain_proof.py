"""Что доказывает «цепочка обслуживания доказана».

Тот же разбор, что и у отката, только на другом инструменте. Прежде круг
считался замкнутым лишь при `executable_sha256 == manifest.artifact_sha256` —
отпечаток ФАЙЛА против отпечатка РЕЛИЗА. Исполняемый файл в парке один на все
витрины, манифест — свой у каждой, ветку отрисовки выбирает манифест. Стоило
соседней витрине уехать вперёд, как общий файл законно принадлежал другой
сборке, и сухой прогон Zona получал MISMATCH на полностью исправной цепочке.

Условий стало не меньше, а больше: три объявленных поля вместо двух, плюс путь
исполняемого файла и активность юнита. Расхождение общего файла с манифестом
теперь названо отдельным полем, а не спрятано в вердикт.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСХОДНИК = КОРЕНЬ / "scripts" / "prove_serving_chain.py"

ОБЩИЙ = "/srv/lords/.frontend/lords-frontend.py"
СБОРКА_КАНДИДАТА = "a51dade469321e3078b8a7eee124e5ac936f286a33c28f327368bfbfabb85346"
СБОРКА_БАЗЫ = "9229879ee5ab04eb68a59a98d9aeb1c6e3b745de7125c984756787790b0d6bbd"


@pytest.fixture(scope="module")
def доказатель():
    спец = importlib.util.spec_from_file_location("prove_chain", ИСХОДНИК)
    модуль = importlib.util.module_from_spec(спец)
    sys.modules["prove_chain"] = модуль
    спец.loader.exec_module(модуль)
    return модуль


def цепь_zona(**правки) -> dict:
    """Боевая форма: общий файл — сборка Lords, витрина объявляет свой релиз."""
    основа = {
        "domain": "zonafilm.space",
        "executable": ОБЩИЙ,
        "executable_sha256": СБОРКА_КАНДИДАТА,
        "manifest": {"design_version": "1.0.2",
                     "build_id": "20260910T124530Z-a1691c56-nova",
                     "artifact_sha256": СБОРКА_БАЗЫ},
        "unit_state": {"ActiveState": "active", "MainPID": "3753972"},
        "served": {"ok": True, "headers": {"artifact": СБОРКА_БАЗЫ,
                                           "build": "20260910T124530Z-a1691c56-nova",
                                           "version": "1.0.2"}},
    }
    основа.update(правки)
    return основа


class TestБоевойСлучай:
    def test_общий_файл_другой_сборки_не_ломает_доказательство(self, доказатель):
        замкнулся, невыполненные = доказатель.замыкание(цепь_zona())
        assert замкнулся is True, невыполненные
        assert невыполненные == []

    def test_расхождение_файла_и_манифеста_названо_а_не_спрятано(self, доказатель):
        текст = ИСХОДНИК.read_text(encoding="utf-8")
        assert "executable_is_manifest_build" in текст
        assert "shared_executable_note" in текст


class TestНастоящиеРасхожденияОстаютсяКрасными:
    def _провал(self, доказатель, цепь, ожидаемое):
        замкнулся, невыполненные = доказатель.замыкание(цепь)
        assert замкнулся is False
        assert ожидаемое in невыполненные, невыполненные

    def test_отданный_артефакт_не_из_манифеста_юнита(self, доказатель):
        цепь = цепь_zona()
        цепь["served"]["headers"]["artifact"] = "f" * 64
        self._провал(доказатель, цепь, "отданный артефакт = манифест юнита")

    def test_отданная_сборка_не_из_манифеста_юнита(self, доказатель):
        цепь = цепь_zona()
        цепь["served"]["headers"]["build"] = "20260101T000000Z-подмена"
        self._провал(доказатель, цепь, "отданная сборка = манифест юнита")

    def test_отданная_версия_не_из_манифеста_юнита(self, доказатель):
        """Условие, которого прежде не было вовсе."""
        цепь = цепь_zona()
        цепь["served"]["headers"]["version"] = "1.1.0"
        self._провал(доказатель, цепь, "отданная версия = манифест юнита")

    def test_юнит_исполняет_посторонний_файл(self, доказатель):
        self._провал(доказатель, цепь_zona(executable="/tmp/чужой-frontend.py"),
                     "юнит исполняет общий артефакт парка")

    def test_юнит_не_активен(self, доказатель):
        self._провал(доказатель, цепь_zona(unit_state={"ActiveState": "failed"}),
                     "юнит активен")

    def test_домен_не_ответил(self, доказатель):
        цепь = цепь_zona()
        цепь["served"] = {"ok": False, "headers": {}}
        замкнулся, невыполненные = доказатель.замыкание(цепь)
        assert замкнулся is False
        assert "домен ответил" in невыполненные

    def test_пустая_цепочка_не_доказательство(self, доказатель):
        замкнулся, невыполненные = доказатель.замыкание({})
        assert замкнулся is False
        assert len(невыполненные) == 6


class TestПравилоНеОслаблено:
    def test_отпечаток_файла_не_сверяется_с_релизом(self, доказатель):
        """Убранное условие не имеет права вернуться в правило."""
        import inspect
        текст = inspect.getsource(доказатель.замыкание)
        тело = текст[текст.index("манифест = цепь.get"):]
        assert "executable_sha256" not in тело

    def test_условий_стало_больше(self, доказатель):
        _, невыполненные = доказатель.замыкание({})
        assert len(невыполненные) == 6, "прежде проверялись три условия"

    def test_вердикт_требует_всех_условий(self, доказатель):
        for поле in ("отданный артефакт = манифест юнита",
                     "отданная сборка = манифест юнита",
                     "отданная версия = манифест юнита",
                     "юнит исполняет общий артефакт парка",
                     "юнит активен",
                     "домен ответил"):
            _, все = доказатель.замыкание({})
            assert поле in все
