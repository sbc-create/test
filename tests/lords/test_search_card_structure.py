"""Карточка в выдаче поиска — та же карточка, что в каталоге.

Прежде клиентский код строил её без блока постера: в каталоге карточка имела
рамку 2:3, в поиске — нет. Отличалась геометрия, отличалась сетка, а проверка
пропорции постера на странице поиска не находила элемента и числилась «нет
элемента» — то есть дефект прятался в графе, которая выглядит безобидно.

Изображения в выдаче нет и взяться ему неоткуда: указатель поиска не хранит
адрес постера. Поэтому рисуется состояние «без изображения», а не выдуманная
картинка.
"""
from __future__ import annotations

import pathlib
import re

import pytest

from factory.lords import render as render_mod

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


@pytest.fixture(scope="module")
def клиентский_код() -> str:
    """Тело скрипта витрины из исходника, а не из собранного дерева.

    Собранное дерево может быть старым; исходник — то, что поедет дальше.
    """
    т = (КОРЕНЬ / "factory" / "lords" / "render.py").read_text("utf-8")
    начало = т.find("function render(query)")
    assert начало > 0, "функция отрисовки выдачи поиска не найдена"
    конец = т.find("function ensure(query)", начало)
    assert конец > начало
    return т[начало:конец]


class TestСтруктураКарточкиПоиска:
    def test_блок_постера_есть(self, клиентский_код):
        assert "card__poster" in клиентский_код, (
            "карточка поиска снова строится без блока постера: её геометрия "
            "разойдётся с каталогом, а проверка пропорции не найдёт элемента")

    def test_заглушка_вместо_изображения(self, клиентский_код):
        assert "card__poster-empty" in клиентский_код

    def test_изображение_не_выдумывается(self, клиентский_код):
        """Тега img быть не должно: адреса постера в указателе нет."""
        assert "<img" not in клиентский_код

    def test_адрес_экранируется(self, клиентский_код):
        assert "encodeURIComponent" in клиентский_код

    def test_буква_заглушки_очищается(self, клиентский_код):
        assert re.search(r"replace\(/\[<>&\]/g", клиентский_код), (
            "содержимое заглушки попадает в разметку без очистки")


class TestУказательПоискаНеРаспух:
    """Вес указателя — часть быстродействия, и он не должен расти молча."""

    def test_поля_указателя_прежние(self):
        т = (КОРЕНЬ / "factory" / "lords" / "render.py").read_text("utf-8")
        начало = т.find("def _search_index")
        if начало < 0:
            pytest.skip("сборщик указателя поиска не найден по имени")
        кусок = т[начало:начало + 2000]
        assert '"poster"' not in кусок, (
            "в указатель добавлен адрес постера: это +1,9 МиБ к 5,1 МиБ и "
            "решение владельца о весе страницы, а не правка вёрстки")
