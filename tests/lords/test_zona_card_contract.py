"""Zona: карточка каталога — название, метаданные и настоящая оценка.

Что измерено на стенде до правки (`/catalog/`, 16 карточек):

* `tolko-shiki` несёт настоящую оценку Shikimori 8.2 с 340 голосами. Страница
  произведения её показывает, карточка — нет: карточка читала только
  `kinopoisk_rating` и `imdb_rating` напрямую, мимо разбора
  `ratings_by_source`. То есть витрина скрывала оценку, которая у неё есть.
* Карточка и страница произведения печатали число по-разному: «IMDb 7.8» без
  шкалы против «IMDb 7.8 из 10». Один и тот же факт в двух видах.
* «Нет оценки» и «оценка есть, но не показана» выглядели одинаково — пусто.
  Машинная проверка не могла отличить честное отсутствие от потерянного
  значения.

Правится общая причина: карточка берёт оценки из того же разбора, что и
страница произведения. Отдельного «ещё одного места, где читаются оценки»
больше нет.
"""
from __future__ import annotations

import html
import re
import tempfile
from pathlib import Path

import pytest

from tests.lords.zona_kit import ЗАПИСИ, ПОДРОБНОСТИ, поднять, запросить


@pytest.fixture(scope="module")
def зона():
    return поднять(Path(tempfile.mkdtemp()), имя_модуля="nova_zona_card_contract")


def карточки(тело: str) -> list[str]:
    return re.findall(r'<a class="zt"[^>]*>.*?</a>', тело, re.S)


def слаг(карточка: str) -> str:
    m = re.search(r'href="/title/([^/]+)/"', карточка)
    return m.group(1) if m else ""


def карточка_по_слагу(зона, путь: str, slug: str) -> str:
    о = запросить(зона, путь)
    assert о.статус == 200
    for к in карточки(о.тело):
        if слаг(к) == slug:
            return к
    raise AssertionError(f"карточка {slug} не найдена на {путь}")


# --------------------------------------------------------------------------
# Название и ссылка
# --------------------------------------------------------------------------

def test_у_каждой_карточки_есть_видимое_название(зона):
    о = запросить(зона, "/catalog/")
    набор = карточки(о.тело)
    assert набор, "каталог отдан без карточек"
    пустые = []
    for к in набор:
        m = re.search(r'<span class="zt__t"[^>]*>(.*?)</span>', к, re.S)
        if not m or not m.group(1).strip():
            пустые.append(слаг(к))
    assert пустые == [], f"карточки без названия: {пустые}"


def test_длинное_название_обрезается_объявленно_и_остаётся_целиком(зона):
    к = карточка_по_слагу(зона, "/catalog/", "dlinnoe")
    полное = next(з["title"] for з in ЗАПИСИ if з["slug"] == "dlinnoe")
    assert 'data-clamp-allowed="2"' in к, "обрезка не объявлена — не отличить от дефекта"
    assert f'title="{html.escape(полное)}"' in к
    assert f'aria-label="{html.escape(полное)}"' in к


def test_каждая_карточка_ведёт_на_существующий_маршрут(зона):
    о = запросить(зона, "/catalog/")
    for к in карточки(о.тело):
        s = слаг(к)
        assert s, f"карточка без адреса: {к[:120]}"
        ответ = запросить(зона, f"/title/{s}/")
        assert ответ.статус == 200, f"карточка ведёт в {ответ.статус}: /title/{s}/"


def test_карточка_несёт_год_и_вид(зона):
    к = карточка_по_слагу(зона, "/catalog/", "svezhiy")
    мета = " ".join(re.findall(r'<span class="zt__m">(.*?)</span>', к, re.S))
    assert "2026" in мета, f"год не показан: {мета!r}"


def test_карточка_без_постера_не_ломает_разметку(зона):
    к = карточка_по_слагу(зона, "/catalog/", "bez-postera")
    assert "zt__none" in к or "<img" in к, (
        "нет ни постера, ни объявленной заглушки — пустая кликабельная зона")


# --------------------------------------------------------------------------
# Оценки: тот же источник правды, что и у страницы произведения
# --------------------------------------------------------------------------

def значение_оценки(разметка: str, источник: str) -> str | None:
    """Число оценки источника — на карточке (`zt__rn`) или на странице (`rbs__n`)."""
    m = re.search(r'data-source="%s"[^>]*>.*?<span class="(?:zt__rn|rbs__n)"[^>]*>([0-9.]+)'
                  % re.escape(источник), разметка, re.S)
    return m.group(1) if m else None


def test_оценка_shikimori_видна_на_карточке(зона):
    """Оценка, которая есть у витрины, не должна пропадать на карточке."""
    к = карточка_по_слагу(зона, "/catalog/", "tolko-shiki")
    assert 'data-source="shikimori"' in к, (
        "Shikimori 8.2 есть в данных и показана на странице произведения, "
        "но карточка её скрывает")
    assert значение_оценки(к, "shikimori") == "8.2"


def test_формат_числа_совпадает_с_страницей_произведения(зона):
    к = карточка_по_слагу(зона, "/catalog/", "svezhiy")
    страница = запросить(зона, "/title/svezhiy/").тело
    for источник in ("kp", "imdb"):
        на_карточке = значение_оценки(к, источник)
        на_странице = значение_оценки(страница, источник)
        assert на_карточке == на_странице != None, (
            f"{источник}: карточка {на_карточке!r} ≠ страница {на_странице!r}")


def test_шкала_названа_и_на_карточке(зона):
    к = карточка_по_слагу(зона, "/catalog/", "svezhiy")
    assert "из 10" in к, "число без шкалы вслух не значит ничего"


def test_ноль_не_показывается_как_оценка(зона):
    """Отрицательный тест: 0 — это не оценка, а отсутствие оценки."""
    к = карточка_по_слагу(зона, "/catalog/", "nol-ocenka")
    assert "data-source=" not in к, f"ноль показан как оценка: {к[:200]}"
    assert 'data-rating="none"' in к


def test_отсутствие_оценки_объявлено_машиночитаемо(зона):
    """«Нет оценки» и «оценка потеряна вёрсткой» обязаны различаться."""
    к = карточка_по_слагу(зона, "/catalog/", "bez-ocenki")
    assert 'data-rating="none"' in к
    assert "data-source=" not in к


def test_карточка_с_оценкой_объявляет_значение(зона):
    к = карточка_по_слагу(зона, "/catalog/", "tolko-imdb")
    assert 'data-rating="5.5"' in к, "значение не объявлено машиночитаемо"


def test_недоступный_разбор_оценок_не_роняет_страницу(зона, monkeypatch):
    """Graceful degradation: сломанный источник оценок не уносит каталог."""
    def взрыв(_деталь):
        raise RuntimeError("источник оценок недоступен")

    monkeypatch.setattr(зона, "оценки_по_источникам", взрыв)
    о = запросить(зона, "/catalog/")
    assert о.статус == 200, "каталог упал вместе с оценками"
    assert 'data-testid="title-card"' in о.тело
    assert 'data-rating="unavailable"' in о.тело, (
        "деградация не объявлена: не отличить от «оценок нет»")


