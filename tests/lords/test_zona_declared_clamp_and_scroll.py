"""Обрезка текста и внутренняя прокрутка объявляются, а не подразумеваются.

Живая адаптивная матрица B18 насчитала 102 обрезанных заголовка карточек и 7
внутренних прокруток и на этом не прошла. Разбор показал, что почти всё это —
замысел: заголовок карточки намеренно обрезается второй строкой, а ленты,
плашки жанров и панель фильтров намеренно прокручиваются вбок.

Отсюда дефект не в вёрстке, а в том, что замысел нигде не записан. Машинный
аудит не умеет отличить задуманную обрезку от заголовка, съеденного чужим
`overflow: hidden`, и честно считает нарушением и то, и другое. Пока это так,
матрица будет краснеть на исправной вёрстке и зеленеть на сломанной.

Здесь замысел объявлен разметкой: `data-clamp-allowed` на обрезаемом тексте и
`data-scroller` на намеренном скроллере. Тесты держат два условия.

Первое: объявление не бывает пустым обещанием — обрезать текст можно только
если он целиком остаётся доступен (`title` и `aria-label` карточки). Иначе
объявление превращалось бы в способ заглушить аудит.

Второе: объявление обязано быть у каждой обрезаемой карточки, а не у той,
которую вспомнили. Незакрытая карточка снова даст ложное нарушение.
"""

from __future__ import annotations

import html
import re

import pytest

from tests.lords.test_nova_frontend_families import запросить
from tests.lords.test_zona_pass4 import _поднять

МАРШРУТЫ = ("/", "/catalog/", "/new/", "/movies/", "/series/")


@pytest.fixture(scope="module")
def зона(tmp_path_factory):
    return _поднять(tmp_path_factory.mktemp("zona-declared"))


#: Классы заголовков, которые вёрстка обрезает по числу строк. Взяты из
#: таблицы стилей: `-webkit-line-clamp` стоит ровно на них. Семейства карточек
#: разные — на главной поступления идут строками, в каталоге плитками, — и
#: правило объявления обязано держать оба, иначе закрытым окажется то, что
#: вспомнили, а не то, что обрезается.
ОБРЕЗАЕМЫЕ = ("zt__t", "zadded__t")


def карточки(тело: str) -> list[str]:
    """Карточки произведений всех семейств, вместе с их ссылкой-обёрткой."""
    return re.findall(r'<a class="(?:zt|zadded__row)(?:[ "])[^>]*>.*?</a>',
                      тело, re.S)


@pytest.mark.parametrize("путь", МАРШРУТЫ)
def test_каждый_обрезаемый_заголовок_объявлен(зона, путь):
    о = запросить(зона, путь)
    assert о.статус == 200
    найдено = карточки(о.тело)
    assert найдено, f"на {путь} нет карточек"
    for карточка in найдено:
        заголовки = [
            атрибуты
            for класс in ОБРЕЗАЕМЫЕ
            for атрибуты in re.findall(rf'<(?:span|p) class="{класс}"([^>]*)>', карточка)
        ]
        assert заголовки, f"карточка без заголовка на {путь}: {карточка[:200]}"
        for атрибуты in заголовки:
            assert "data-clamp-allowed=" in атрибуты, (
                f"обрезаемый заголовок без объявления на {путь}")


@pytest.mark.parametrize("путь", МАРШРУТЫ)
def test_объявленная_обрезка_оставляет_полный_текст(зона, путь):
    """Обрезать можно только то, что целиком доступно рядом."""
    о = запросить(зона, путь)
    for карточка in карточки(о.тело):
        видимый = None
        for класс in ОБРЕЗАЕМЫЕ:
            видимый = re.search(
                rf'<(?:span|p) class="{класс}"[^>]*>([^<]*)</(?:span|p)>', карточка)
            if видимый:
                break
        assert видимый, f"не разобрать заголовок карточки на {путь}"
        текст = html.unescape(видимый.group(1))

        подсказка = re.search(r'<a class="[^"]*"[^>]*\btitle="([^"]*)"', карточка)
        имя = re.search(r'<a class="[^"]*"[^>]*\baria-label="([^"]*)"', карточка)
        assert подсказка, f"карточка без title на {путь}"
        assert имя, f"карточка без aria-label на {путь}"
        assert html.unescape(подсказка.group(1)) == текст
        assert html.unescape(имя.group(1)) == текст
        assert текст.strip(), f"пустое доступное имя карточки на {путь}"


def test_намеренные_скроллеры_объявлены(зона):
    """Лента, плашки жанров и фильтры прокручиваются по замыслу — и говорят это."""
    главная = запросить(зона, "/").тело
    каталог = запросить(зона, "/catalog/").тело

    if 'class="zrl__vp"' in главная:
        for атрибуты in re.findall(r'<div class="zrl__vp"([^>]*)>', главная):
            assert 'data-scroller="rail"' in атрибуты
    if 'class="zgenres__nav"' in главная:
        for атрибуты in re.findall(r'<nav class="zgenres__nav"([^>]*)>', главная):
            assert 'data-scroller="chips"' in атрибуты
    if 'class="zfilt-bar"' in каталог:
        for атрибуты in re.findall(r'<div class="zfilt-bar"([^>]*)>', каталог):
            assert 'data-scroller="filters"' in атрибуты


def test_объявление_не_прячет_настоящую_обрезку_метаданных(зона):
    """Дата, время и номер серии обрезаться не имеют права даже объявленно.

    Контракт разрешает clamp только заголовку карточки. Если объявление
    появится на метаданных, оно превратится в способ узаконить именно тот
    дефект, ради которого всё это заводилось.
    """
    for путь in МАРШРУТЫ:
        тело = запросить(зона, путь).тело
        for карточка in карточки(тело):
            for атрибуты in re.findall(r'<span class="zt__m"([^>]*)>', карточка):
                assert "data-clamp-allowed=" not in атрибуты, (
                    f"обрезка объявлена на метаданных карточки ({путь})")
