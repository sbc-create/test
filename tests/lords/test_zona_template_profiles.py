def разметка(тело: str) -> str:
    """Тело без <style> и <script>: имена классов живут и в CSS, и поиск по
    всему документу находит правило, а не элемент."""
    без = re.sub(r"<style\b.*?</style>", "", тело, flags=re.S)
    return re.sub(r"<script\b.*?</script>", "", без, flags=re.S)


def состав(тело: str) -> list[str]:
    """Последовательность блоков главной — отпечаток структуры шаблона."""
    т = разметка(тело)
    порядок = []
    for m in re.finditer(r'<section class="([a-z_\- ]+)"[^>]*>', т):
        класс = m.group(1).split()[0]
        подпись = класс
        if класс == "zsec":
            заголовок = re.search(r"<h2[^>]*>(.*?)</h2>",
                                  т[m.start():m.start() + 1500], re.S)
            подпись = (f"zsec:{re.sub(r'<[^>]+>', '', заголовок.group(1)).strip()[:22]}"
                       if заголовок else "zsec")
        порядок.append(подпись)
    return порядок


