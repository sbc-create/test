def test_все_шаблоны_поднимаются(витрины):
    for имя, м in витрины.items():
        о = запросить(м, "/")
        assert о.статус == 200, f"{имя}: главная {о.статус}"
        assert f'data-template-profile="{имя}"' in о.тело, (
            f"{имя}: шаблон не объявлен в разметке — на снимке не отличить, "
            "какой именно шаблон снят")


def test_ни_одна_пара_шаблонов_не_совпадает(витрины):
    отпечатки = {имя: состав(запросить(м, "/").тело) for имя, м in витрины.items()}
    повторы = []
    имена = sorted(отпечатки)
    for i, a in enumerate(имена):
        for b in имена[i + 1:]:
            if отпечатки[a] == отпечатки[b]:
                повторы.append((a, b))
    assert повторы == [], f"шаблоны неразличимы по структуре: {повторы}"


def test_различие_не_сводится_к_цвету(витрины):
    """Отрицательный тест: перекраска шаблоном не считается."""
    базовый = состав(запросить(витрины["classic"], "/").тело)
    отличий = 0
    for имя, м in витрины.items():
        if имя == "classic":
            continue
        текущий = состав(запросить(м, "/").тело)
        assert текущий != базовый, f"{имя} повторяет classic"
        if set(текущий) != set(базовый) or текущий != базовый:
            отличий += 1
    assert отличий == len(ШАБЛОНЫ) - 1


def test_герой_подаётся_тремя_разными_способами(витрины):
    слайдер = запросить(витрины["classic"], "/").тело
    один = запросить(витрины["catalog-first"], "/").тело
    лид = запросить(витрины["discovery"], "/").тело
    assert слайдер.count("data-zhero-slide") > один.count("data-zhero-slide") > 0 \
        or "zhero--slider" in один
    assert "data-zhero-prev" in слайдер, "у слайдерного шаблона нет органов"
    assert "data-zhero-prev" not in один, (
        "шаблон с одним кадром не должен показывать мёртвые органы управления")
    assert "zhero--compact" in лид, "шаблон без кадра героя не отдал компактный лид"


def test_неделя_подаётся_вкладками_и_лентами(витрины):
    вкладки = разметка(запросить(витрины["classic"], "/").тело)
    ленты = разметка(запросить(витрины["rail-dense"], "/").тело)
    assert "zwpop__tabs" in вкладки
    assert "zwpop__tabs" not in ленты, "ленточный шаблон оставил вкладки"
    assert "Фильмы недели" in ленты and "Сериалы недели" in ленты


def test_поступления_списком_и_лентой(витрины):
    списком = разметка(запросить(витрины["classic"], "/").тело)
    лентой = разметка(запросить(витрины["rail-dense"], "/").тело)
    assert "zadded__list" in списком
    assert "zadded__list" not in лентой
    assert "Новое в каталоге" in лентой, "лента поступлений потеряла заголовок"


def _много_записей(сколько: int = 90):
    """Набор, которого хватает на все блоки сразу.

    В основном наборе шестнадцать записей, и недельные полки с поступлениями
    выбирают их целиком: плотной сетке честно ничего не остаётся, и блок
    исчезает. Это верное поведение, но проверять на нём наличие сетки —
    проверять нехватку данных, а не шаблон.
    """
    записи, подробности = [], {}
    for i in range(сколько):
        slug = f"zapis-{i:03d}"
        записи.append({
            "slug": slug, "title": f"Запись {i:03d}",
            "kind": ("Фильм", "Сериал", "Мультфильм")[i % 3],
            "year": 2000 + (i % 26),
            "poster": f"https://poster.example/{slug}.webp",
            "url": f"/title/{slug}/",
            "published_at": f"2026-09-{1 + i % 20:02d}T00:00:00Z",
            "published_at_estimated": False,
        })
        подробности[slug] = {
            "description": f"Описание {i}.", "genres": ["драма"], "countries": ["США"],
            "playable": True, "imdb_rating": 5 + (i % 5),
            "sources": [{"provider": "kp", "source_id": str(i),
                         "availability_status": "available"}],
            "external_ids": {"kp": str(i)},
        }
    weekly = {"week_id": "2026-W38", "digest": "d", "shelves": {
        "pop-films": [f"zapis-{i:03d}" for i in range(0, 12)],
        "pop-series": [f"zapis-{i:03d}" for i in range(12, 24)],
        "pop-anim": [f"zapis-{i:03d}" for i in range(24, 36)]}}
    return записи, подробности, weekly


@pytest.mark.parametrize("имя", ["catalog-first", "discovery", "rail-dense",
                                 "grid-lead"])
def test_плотная_сетка_появляется_где_объявлена(tmp_path, имя):
    записи, подробности, weekly = _много_записей()
    м = поднять(tmp_path, profile=имя, записи=записи, подробности=подробности,
                weekly=weekly, имя_модуля=f"nova_zona_grid_{имя.replace('-', '_')}")
    тело = разметка(запросить(м, "/").тело)
    assert "zfresh-h" in тело, f"{имя}: объявленной сетки новинок нет"
    сетка = re.search(r'<div class="zg">(.*?)</div>\s*</section>', тело, re.S)
    assert сетка, f"{имя}: сетка объявлена, но не отрисована"
    карточек = len(re.findall(r'data-testid="title-card"', сетка.group(1)))
    объявлено = м.ЗОНА_ШАБЛОНЫ[имя]["свежие"]
    assert карточек == объявлено, (
        f"{имя}: объявлено {объявлено} карточек, отрисовано {карточек}")


