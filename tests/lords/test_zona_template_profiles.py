def test_классический_шаблон_это_сегодняшняя_витрина(tmp_path):
    """Отсутствие поля в манифесте обязано дать ровно то, что было."""
    без_поля = поднять(tmp_path, имя_модуля="nova_zona_tpl_default")
    явно = поднять(tmp_path, profile="classic", имя_модуля="nova_zona_tpl_explicit")
    for путь in ("/", "/catalog/", "/title/svezhiy/"):
        a = запросить(без_поля, путь).тело
        b = запросить(явно, путь).тело
        assert a == b, f"{путь}: умолчание разошлось с classic"


def test_неизвестный_шаблон_не_подменяет_витрину_молча(tmp_path):
    """Отрицательный тест: опечатка в манифесте не должна пройти тихо."""
    поток = io.StringIO()
    with redirect_stderr(поток):
        м = поднять(tmp_path, profile="takogo-net",
                    имя_модуля="nova_zona_tpl_unknown")
    сказано = поток.getvalue()
    assert "takogo-net" in сказано, "неизвестный шаблон прошёл без диагностики"
    assert м.ЗОНА_ШАБЛОН == "classic"
    assert запросить(м, "/").статус == 200


def test_объявления_шаблонов_полны():
    """Шаблон без состава или без описания выбирать вслепую нельзя."""
    текст = ИСХОДНИК.read_text(encoding="utf-8")
    assert "ЗОНА_ШАБЛОНЫ = {" in текст
    from tests.lords.zona_kit import поднять as _п  # локально: нужен модуль
    м = _п(Path(tempfile.mkdtemp()), имя_модуля="nova_zona_tpl_meta")
    for имя, шаблон in м.ЗОНА_ШАБЛОНЫ.items():
        for поле in ("имя", "описание", "герой", "недельный", "новое", "свежие",
                     "порядок"):
            assert поле in шаблон, f"{имя}: нет поля {поле}"
        assert шаблон["порядок"], f"{имя}: пустой состав"
        assert шаблон["порядок"][-1] == "seo", f"{имя}: текстовый блок не последний"
        assert len(set(шаблон["порядок"])) == len(шаблон["порядок"]), (
            f"{имя}: блок объявлен дважды")
        assert шаблон["герой"] in ("slider", "single", "compact")
        assert шаблон["недельный"] in ("tabs", "stacked")
        assert шаблон["новое"] in ("list", "rail")
