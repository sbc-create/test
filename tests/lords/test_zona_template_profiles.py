@pytest.mark.parametrize("имя", ШАБЛОНЫ)
def test_нет_пустых_секций(витрины, имя):
    тело = запросить(витрины[имя], "/").тело
    for секция in re.findall(r'<section class="[^"]*"[^>]*>(.*?)</section>', тело, re.S):
        заголовок = re.search(r"<h[12][^>]*>(.*?)</h[12]>", секция, re.S)
        if not заголовок:
            continue
        остальное = секция.replace(заголовок.group(0), "")
        assert re.sub(r"<[^>]+>", "", остальное).strip() or "<a" in остальное, (
            f"{имя}: секция «{заголовок.group(1)[:30]}» пуста")


