ШАБЛОНЫ = ["classic", "catalog-first", "editorial", "discovery",
           "rail-dense", "grid-lead"]


@pytest.fixture(scope="module")
def витрины(tmp_path_factory):
    корень = tmp_path_factory.mktemp("profiles")
    собрано = {}
    for имя in ШАБЛОНЫ:
        собрано[имя] = поднять(корень, profile=имя,
                               имя_модуля=f"nova_zona_tpl_{имя.replace('-', '_')}")
    return собрано


def разметка(тело: str) -> str:
    """Тело без <style> и <script>: имена классов живут и в CSS, и поиск по
    всему документу находит правило, а не элемент."""
    без = re.sub(r"<style\b.*?</style>", "", тело, flags=re.S)
    return re.sub(r"<script\b.*?</script>", "", без, flags=re.S)


def состав(тело: str) -> list[str]:
    """Последовательность блоков главной — отпечаток структуры шаблона."""
    порядок = []
    for m in re.finditer(r'<section class="([a-z_\- ]+)"[^>]*>', тело):
        класс = m.group(1).split()[0]
        подпись = класс
        if класс == "zsec":
            заголовок = re.search(r'<h2[^>]*>(.*?)</h2>',
                                  тело[m.start():m.start() + 1200], re.S)
            подпись = f"zsec:{re.sub(r'<[^>]+>', '', заголовок.group(1)).strip()[:20]}" \
                if заголовок else "zsec"
        порядок.append(подпись)
    return порядок


