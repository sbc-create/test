"""Zona: шаблоны витрины — структурные различия при едином контракте.

Требование ночного задания: шаблоны обязаны отличаться СТРУКТУРНО (композиция,
навигация, ритм, тип сетки, расположение героя), а функциональные и
доступностные свойства у всех обязаны быть одни. Пятьдесят перекрасок одного
шаблона выбором не являются.

Поэтому здесь проверяются обе половины:

* каждый шаблон даёт СВОЙ состав и порядок блоков — ни одна пара не совпадает;
* на каждом шаблоне держится общий контракт: ровно один H1, живые органы
  управления слайдера, отсутствие пустых секций и дублей DOM-id, честный 404.

Отдельно закреплено, что `classic` — это ровно сегодняшняя витрина: шаблон,
объявленный по умолчанию, не имеет права незаметно сменить вид production.
"""
