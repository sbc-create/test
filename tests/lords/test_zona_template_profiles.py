def _класс_сетки(тело: str) -> str:
    m = re.search(r'<div class="(zg[^"]*)"', разметка(тело))
    return m.group(1) if m else ""


def test_ни_одна_пара_витрин_не_совпадает(страницы_шаблонов, каталоги_шаблонов):
    """Различие обязано доходить до разметки, а не оставаться в таблице.

    Отпечаток снимается с двух страниц: тип сетки виден на каталоге, а состав
    и подача героя — на главной. По одной главной шаблоны, отличающиеся только
    сеткой, были бы неразличимы, и проверка молчала бы о настоящем совпадении
    ровно так же, как о мнимом.
    """
    отпечатки = {}
    for имя, о in страницы_шаблонов.items():
        тело = о.тело.replace(f'data-template-profile="{имя}"', "")
        ключ = (tuple(состав(о.тело)), _класс_сетки(о.тело),
                _класс_сетки(каталоги_шаблонов[имя].тело),
                "zhero--full" in разметка(о.тело),
                len(re.findall(r"data-zhero-slide[ =>]", разметка(о.тело))),
                len(тело) // 64)
        отпечатки.setdefault(ключ, []).append(имя)
    повторы = {к: v for к, v in отпечатки.items() if len(v) > 1}
    assert повторы == {}, f"витрины неразличимы: {sorted(повторы.values())}"


