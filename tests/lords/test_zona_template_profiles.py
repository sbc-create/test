def test_нет_пустых_секций_ни_на_одном_шаблоне(страницы_шаблонов):
    плохие = []
    for имя, о in страницы_шаблонов.items():
        for секция in re.findall(r'<section class="[^"]*"[^>]*>(.*?)</section>',
                                 разметка(о.тело), re.S):
            заголовок = re.search(r"<h[12][^>]*>(.*?)</h[12]>", секция, re.S)
            if not заголовок:
                continue
            остальное = секция.replace(заголовок.group(0), "")
