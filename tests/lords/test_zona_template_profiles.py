def test_шаблон_по_умолчанию_это_сегодняшняя_витрина(tmp_path):
    """Отсутствие поля в манифесте обязано дать ровно то, что было."""
    без_поля = поднять(tmp_path, имя_модуля="nova_zona_tpl_default")
    явно = поднять(tmp_path, profile="T001", имя_модуля="nova_zona_tpl_explicit")
    for путь in ("/", "/catalog/", "/title/svezhiy/"):
        assert запросить(без_поля, путь).тело == запросить(явно, путь).тело, путь


def test_прежние_имена_шаблонов_остались_рабочими(tmp_path, реестр):
    """Манифест, написанный до T-нумерации, не должен сменить шаблон молча."""
    for старое, новое in реестр.ЗОНА_ШАБЛОН_АЛИАСЫ.items():
        м = поднять(tmp_path, profile=старое,
                    имя_модуля=f"nova_zona_alias_{старое.replace('-', '_')}")
        assert м.ЗОНА_ШАБЛОН == новое, f"{старое} → {м.ЗОНА_ШАБЛОН}, ждали {новое}"


def test_неизвестный_шаблон_не_подменяет_витрину_молча(tmp_path):
    """Отрицательный тест: опечатка в манифесте не должна пройти тихо."""
    поток = io.StringIO()
    with redirect_stderr(поток):
        м = поднять(tmp_path, profile="T999", имя_модуля="nova_zona_tpl_unknown")
    сказано = поток.getvalue()
    assert "T999" in сказано, "неизвестный шаблон прошёл без диагностики"
    assert м.ЗОНА_ШАБЛОН == "T001"
    assert запросить(м, "/").статус == 200


def test_таблица_лежит_в_исходнике_витрины():
    """Объявления обязаны жить рядом с отрисовкой, а не в отдельном файле."""
    текст = ИСХОДНИК.read_text(encoding="utf-8")
    assert "ЗОНА_ТАБЛИЦА_ШАБЛОНОВ = (" in текст
    assert текст.count('("T0') >= ШАБЛОНОВ_ОЖИДАЕТСЯ
