"""Горизонтальная карточка серии: подпись не делит строку с полосой оценок.

Дефект измерен 2026-09-21 на живой витрине lordserial33.biz при 320 px.
`.c--episode` была рядом (`flex-direction: row`), и полоса оценок `.c__r`
вставала ТРЕТЬИМ элементом строки. Она отбирала у подписи 63–78 px: карточки
без оценки получали подпись 194 px, карточки с оценкой — 116. В худшем случае
`<time class="c__added">добавлен 2026-09-18</time>` ужимался до 26 px при
нужных 64 и обрезался.

Это прямое нарушение контракта: обязательная дата обязана читаться целиком.
Причём обрезалась она избирательно — только у тайтлов с оценкой, из-за чего
дефект и не попадался на глаза.

Набор закрепляет раскладку: миниатюра слева, подпись и полоса — справа, друг
под другом, и ширина подписи не зависит от наличия оценки.
"""

from __future__ import annotations

import pathlib
import re

import pytest

ВИТРИНА = pathlib.Path(__file__).resolve().parents[2] / "automation" / "host" / "lords-frontend.py"


@pytest.fixture(scope="module")
def стили() -> str:
    return ВИТРИНА.read_text(encoding="utf-8")


def правило(стили: str, селектор: str) -> str:
    """Тело базового правила селектора (вне media-запросов)."""
    совпадение = re.search(rf"(?<!\w){re.escape(селектор)}\{{([^}}]*)\}}", стили)
    return совпадение.group(1) if совпадение else ""


def test_episode_card_is_grid_not_row(стили):
    тело = правило(стили, ".c--episode")
    assert тело, "правило .c--episode не найдено"
    assert "display:grid" in тело, (
        "карточка снова раскладывается рядом; полоса оценок опять станет третьим "
        "элементом строки и отнимет ширину у подписи"
    )
    assert "flex-direction:row" not in тело


def test_caption_and_bar_are_stacked_beside_thumbnail(стили):
    тело = правило(стили, ".c--episode")
    области = re.search(r"grid-template-areas:([^;]+);", тело)
    assert области, "в .c--episode не объявлены grid-template-areas"
    текст = области.group(1).replace('"', " ").split()
    # Две строки по две ячейки: миниатюра тянется на обе, подпись над полосой.
    assert текст == ["thumb", "cap", "thumb", "bar"], f"неожиданная раскладка: {текст}"

    assert "grid-area:thumb" in правило(стили, ".c--episode .c__p")
    assert "grid-area:cap" in правило(стили, ".c--episode .c__cap")
    assert "grid-area:bar" in правило(стили, ".c--episode .c__r")


def test_caption_column_can_shrink_to_zero(стили):
    """minmax(0,1fr) обязателен: без него длинное слово распирает колонку."""
    тело = правило(стили, ".c--episode")
    колонки = re.search(r"grid-template-columns:([^;]+);?", тело)
    assert колонки and "minmax(0,1fr)" in колонки.group(1).replace(" ", ""), (
        f"колонка подписи должна быть minmax(0,1fr), получено: {колонки.group(1) if колонки else 'нет'}"
    )


@pytest.mark.parametrize("точка,ширина", [(1199, "104px"), (767, "96px")])
def test_thumbnail_column_follows_breakpoint(стили, точка, ширина):
    """Ширина колонки миниатюры обязана меняться вместе с самой миниатюрой.

    Иначе на узких экранах колонка остаётся 112 px, миниатюра ужимается до 96,
    и между ними появляется пустая полоса в 16 px.
    """
    # Блоков с одной и той же точкой перелома в файле несколько, и первый из
    # них к карточке отношения не имеет. Берётся тот, где карточка упомянута.
    блоки = [
        совпадение.group(1)
        for совпадение in re.finditer(rf"@media\(max-width:{точка}px\)\{{(.*?)\}}\}}", стили, re.S)
    ]
    подходящие = [б for б in блоки if ".c--episode" in б]
    assert подходящие, f"среди {len(блоки)} блоков max-width:{точка}px нет ни одного с .c--episode"
    # Закрывающая скобка последнего правила съедена ограничителем блока `}}`:
    # без неё разбор деклараций не находит конца последнего правила.
    тело = подходящие[0] + "}"
    объявления = re.findall(r"\.c--episode\{([^}]*)\}", тело)
    колонки = [d for d in объявления if "grid-template-columns" in d]
    assert колонки, f"на {точка}px не переобъявлена колонка миниатюры"
    assert ширина in колонки[0], f"на {точка}px ожидалась колонка {ширина}: {колонки[0]}"
    assert ширина in тело, f"на {точка}px не задана ширина самой миниатюры {ширина}"


def test_added_date_has_no_ellipsis_rule(стили):
    """У обязательной даты не должно быть ни обрезки, ни многоточия."""
    тело = правило(стили, ".c__added")
    assert тело, "правило .c__added не найдено"
    assert "text-overflow" not in тело
    assert "overflow:hidden" not in тело
    assert "line-clamp" not in тело
