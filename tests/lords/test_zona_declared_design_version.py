def test_незнакомая_версия_не_поднимает_zona_молча(tmp_path):
    """Отрицательный тест: Zona не имеет права подняться на чужом релизе.

    Запасной путь Zona ведёт в `/srv/lords/zona-01/current/site`, где лежит 19
    страниц произведений из 53 573. Витрина при этом отвечает 200 и выглядит
    живой — то есть молчаливый провал неотличим от исправной работы. Отказ
    старта виден в журнале юнита и чинится одним полем манифеста.
    """
    поток = io.StringIO()
    with redirect_stderr(поток), pytest.raises(SystemExit) as отказ:
        поднять(tmp_path, design="9.9.9", имя_модуля="nova_zona_unknown_version")
    сказано = f"{отказ.value}\n{поток.getvalue()}"
    assert "9.9.9" in сказано, (
        "неизвестная версия оформления прошла без единой строки диагностики")
    assert "zona" in сказано
    assert "design_version" in сказано, "отказ не называет, чем он чинится"


def test_незнакомая_версия_у_соседа_ведёт_себя_как_прежде(tmp_path):
    """Способ отказа соседей не меняется — добавлена только диагностика."""
    поток = io.StringIO()
