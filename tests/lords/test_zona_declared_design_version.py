"""Zona: витрина обязана исполнять то оформление, которое объявила манифестом.

Дефект, найденный измерением 2026-09-21 вечером, а не чтением кода.

Боевой манифест `/srv/lords/.frontend/template-manifest-zona-01.json` объявляет
`design_version: "1.3.0"`. Подготовленный к рестарту артефакт знал только
`1.1.0`, `1.2.0` и `1.2.1`. Незнакомая версия не отвергалась — она молча
выключала `ОФОРМЛЕНИЕ_НОВОЕ`, и витрина проваливалась в старый статический
релиз. Измерено на стенде с теми же байтами:

| версия | `/` | `/catalog/` | `/title/…/` |
| --- | --- | --- | --- |
| 1.2.0 | 50 КБ, слайдер есть | карточки есть | 200 |
| 1.3.0 | 10 КБ, слайдера нет | карточек нет | **404** |

То есть одна команда владельца `systemctl restart nova-zona-01.service` не
включила бы слайдер, а сняла бы витрину целиком. Отчёт прошлого этапа этого не
видел, потому что проверял стенд на `1.2.0`, а боевой манифест — на `1.3.0`.

Здесь проверяется свойство, а не строка: **любая** версия, объявленная
манифестом Zona, либо исполняется, либо громко отвергается на старте. Молчаливый
провал в чужой релиз — худший из трёх исходов, потому что выглядит как рабочая
витрина.
"""
from __future__ import annotations

import io
import json
import re
from contextlib import redirect_stderr
from pathlib import Path

import pytest

from tests.lords.zona_kit import ЖИВАЯ_ВЕРСИЯ_ZONA, ИСХОДНИК, поднять, запросить

#: Манифест боевой витрины. Его читает не тест, а сама витрина при старте;
#: здесь он нужен, чтобы ожидание бралось из production, а не из константы.
ЖИВОЙ_МАНИФЕСТ = Path("/srv/lords/.frontend/template-manifest-zona-01.json")


def _версия_живого_манифеста() -> str | None:
    try:
        return json.loads(ЖИВОЙ_МАНИФЕСТ.read_text(encoding="utf-8"))["design_version"]
    except (OSError, ValueError, KeyError):
        return None


def test_версия_живого_манифеста_известна_артефакту():
    """Артефакт обязан знать версию, которую объявляет боевая витрина."""
    текст = ИСХОДНИК.read_text(encoding="utf-8")
    m = re.search(r"ОФОРМЛЕНИЕ_ВЕРСИИ = \{([^}]*)\}", текст)
    assert m, "набор ОФОРМЛЕНИЕ_ВЕРСИИ не найден"
    известные = set(re.findall(r'"(\d+\.\d+\.\d+)"', текст))
    assert ЖИВАЯ_ВЕРСИЯ_ZONA in известные, (
        f"артефакт не знает версию {ЖИВАЯ_ВЕРСИЯ_ZONA}, объявленную манифестом "
        "zona-01: рестарт выключит новое оформление целиком")


@pytest.mark.skipif(_версия_живого_манифеста() is None,
                    reason="боевой манифест недоступен из этого окружения")
def test_ожидание_совпадает_с_боевым_манифестом():
    """Константа набора не должна разойтись с тем, что объявлено в production."""
    assert _версия_живого_манифеста() == ЖИВАЯ_ВЕРСИЯ_ZONA


def test_главная_объявленной_версии_несёт_слайдер(tmp_path):
    м = поднять(tmp_path, design=ЖИВАЯ_ВЕРСИЯ_ZONA)
    о = запросить(м, "/")
    assert о.статус == 200
    assert "data-zhero-slider" in о.тело, (
        "на объявленной версии главная отдана без слайдера — витрина "
        "провалилась в прежнюю ветку")
    assert о.тело.count('data-template-version="%s"' % ЖИВАЯ_ВЕРСИЯ_ZONA) == 1


