def test_новая_версия_это_регистрация_а_не_смена_оформления(tmp_path):
    """1.3.0 обязана отдавать то же, что 1.2.0, кроме объявленной версии.

    Иначе «добавили версию в набор» тихо означало бы «сменили вид витрины»,
    и проверять пришлось бы не регистрацию, а новый дизайн.
    """
    было = поднять(tmp_path, design="1.2.0", имя_модуля="nova_zona_reg_120")
    стало = поднять(tmp_path, design=ЖИВАЯ_ВЕРСИЯ_ZONA, имя_модуля="nova_zona_reg_130")
    for путь in ("/", "/catalog/", "/new/", "/title/svezhiy/"):
        a = запросить(было, путь).тело
        b = запросить(стало, путь).тело
        # Объявленная версия обязана отличаться — она и есть предмет правки.
        # Всё остальное обязано совпасть, поэтому обе версии сводятся к «@».
        def нормализовать(т: str) -> str:
            return т.replace("1.2.0", "@").replace(ЖИВАЯ_ВЕРСИЯ_ZONA, "@")

        assert нормализовать(a) == нормализовать(b), (
            f"{путь}: 1.3.0 отдаёт не то же, что 1.2.0 — это смена оформления, "
            "а не регистрация версии")


def test_известные_версии_не_ломают_соседей(tmp_path):
    """Lords на 1.1.0 и Animedia на своей версии не должны зависеть от Zona."""
    лордс = поднять(tmp_path, design="1.1.0", family="lords",
                    имя_модуля="nova_lords_1_1_0")
    assert лордс.ОФОРМЛЕНИЕ_НОВОЕ is True
    assert лордс.ОФОРМЛЕНИЕ_ПЕРЕРАБОТАННОЕ is False, (
        "переработанное оформление Zona протекло в Lords")
    аним = поднять(tmp_path, design="1.2.1", family="animedia",
                   имя_модуля="nova_animedia_1_2_1")
    assert аним.ОФОРМЛЕНИЕ_ПЕРЕРАБОТАННОЕ is True
    assert ЖИВАЯ_ВЕРСИЯ_ZONA not in аним.ПЕРЕРАБОТАНО_С["animedia"], (
        "версия Zona добавлена в набор Animedia — это смена оформления соседа")
