"""Оснастка замера измеряет архетипы, а не соседние страницы.

Два слота указывали не туда, и обнаружилось это не сразу: указатель жанров и
страница поиска без запроса просто не содержат карточек, поэтому проверка
пропорции постера не находила элемента и двадцать одна строка матрицы
числилась «нет элемента». Пустая графа выглядит безобиднее красной, и именно
поэтому ошибку было легко не заметить.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ОСНАСТКА = КОРЕНЬ / "scripts" / "measure_template.cjs"


def текст() -> str:
    return ОСНАСТКА.read_text("utf-8")


class TestМаршрутыСлотов:
    def test_жанровый_слот_не_указывает_на_указатель_жанров(self):
        т = текст()
        assert "['genres', null]" in т, (
            "слот жанрового каталога снова задан явным адресом: указатель "
            "жанров карточек не содержит, и слот перестанет их измерять")
        assert "первыйЖанр" in т

    def test_слаг_жанра_не_вписан_в_оснастку(self):
        """Вписанный слаг переживёт удаление жанра и начнёт измерять 404."""
        т = текст()
        подозрительные = re.findall(r"'/genres/[a-z0-9-]+/'", т)
        assert подозрительные == [], подозрительные

    def test_поиск_измеряется_с_запросом(self):
        т = текст()
        assert "'/search/?q='" in т or "/search/?q=" in т, (
            "слот выдачи поиска снова измеряет страницу без запроса — то есть "
            "пустое состояние вместо выдачи")

    def test_маршруты_записываются_в_замер(self):
        """Без записи маршрутов нельзя проверить, что измерялось."""
        assert "routes: Object.fromEntries(PAGES)" in текст()

    def test_отсутствие_жанра_роняет_замер(self):
        assert "нет ни одной ссылки на жанр" in текст(), (
            "оснастка обязана отказать, а не молча измерить пустую страницу")
