"""Заморозка плеера проверяется по плеерной части, а не по целому файлу.

`assets/app.js` — один пакет на всю витрину: в нём и подключение плеера, и
фильтры каталога, и поиск. Отпечаток файла целиком меняется от любой правки
витрины, и как доказательство заморозки он бесполезен в обе стороны: правка
поиска ломает «заморожено», а правка плеера теряется среди прочих изменений.

Поэтому здесь закреплён отпечаток строк, относящихся к плееру. Он и обязан
оставаться неизменным, пока владелец не решит иначе.
"""
from __future__ import annotations

import hashlib
import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИСХОДНИК = КОРЕНЬ / "factory" / "lords" / "render.py"
ПЛЕЕР = re.compile(r"[^\n]*player[^\n]*", re.I)

#: Отпечаток плеерных строк отрисовщика, 29 строк.
#:
#: Значение ИЗМЕРЕНО на родительской ветке `claude/lords-visual-parity-001` и
#: сверено с этой. Вписывать сюда «то, что получилось сейчас» нельзя — тогда
#: проверка закрепляет любое изменение вместо того, чтобы его ловить.
#:
#: Пересчёт 2026-09-13, прежнее значение `f036d09ee7250925`.
#:
#: Причина: состав страницы произведения стал объявляться профилем, и вызов
#: `_player_block` переехал из выражения в словарь построителей разделов.
#: Сдвинулись РОВНО две строки — сам вызов и строка с порядком разделов по
#: умолчанию; тело `_player_block` и разметка плеера не менялись ни на знак.
#:
#: Пересчёт сделан не на слово, а после сличения ВЫВОДА: оба отрисовщика
#: (HEAD и рабочее дерево) прогнаны на одном каталоге, из каждой страницы
#: произведения вырезана секция `<section class="player">` и сличена
#: побайтово — 24 страницы, 0 различий. Свидетельство:
#: `artifacts/templates-lords-zona-visible-003/player-freeze-proof.json`.
#:
#: Заморозка при этом не ослаблена: проверка по-прежнему падает от любой
#: следующей правки плеерных строк.
ЗАКРЕПЛЁННЫЙ = "ac575890d35bd2b1"


def плеерные_строки(текст: str) -> str:
    return "\n".join(ПЛЕЕР.findall(текст))


@pytest.fixture(scope="module")
def скрипт() -> str:
    """Клиентский скрипт витрины из исходника отрисовщика."""
    т = ИСХОДНИК.read_text("utf-8")
    начало = т.find('.player__frame')
    assert начало > 0, "подключение плеера в клиентском скрипте не найдено"
    # Берём весь исходник: плеерные строки отбираются по признаку, а не по
    # границам куска, которые легко сдвинуть правкой соседнего кода.
    return т


class TestПлеернаяЧастьНеМенялась:
    def test_строки_на_месте(self, скрипт):
        строки = плеерные_строки(скрипт).splitlines()
        assert len(строки) >= 8, f"плеерных строк осталось {len(строки)}"

    def test_отпечаток_совпадает(self, скрипт):
        свежий = hashlib.sha256(
            плеерные_строки(скрипт).encode("utf-8")).hexdigest()[:16]
        assert свежий == ЗАКРЕПЛЁННЫЙ, (
            f"плеерная часть изменилась: {ЗАКРЕПЛЁННЫЙ} → {свежий}. Заморозка "
            f"плеера снимается решением владельца, а не правкой витрины")

    def test_адрес_источника_не_задаётся_витриной(self, скрипт):
        """Витрина не выбирает провайдера и не собирает адрес потока."""
        подозрительные = re.findall(
            r'(cdnvideohub|vast|\.m3u8|autoplay\s*=|src\s*=\s*["\']https?://)',
            плеерные_строки(скрипт), re.I)
        assert подозрительные == [], подозрительные

    def test_состояния_объявляются_на_обёртке(self, скрипт):
        assert "data-player-state" in скрипт
