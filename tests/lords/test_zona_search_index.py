def _выдача(данные, q: str) -> list[str]:
    return [з.get("slug") or з.get("url") for з in данные.искать(q)]


def test_указатель_даёт_ту_же_выдачу_что_перебор(tmp_path):
    """Отбор кандидатов шире совпадения: ни одна запись не теряется."""
    mod, каталог = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(каталог))

    for q in ЗАПРОСЫ:
        данные.указатель_включён = False
        эталон = _выдача(данные, q)
        данные.указатель_включён = True
        быстро = _выдача(данные, q)
        assert быстро == эталон, f"выдача разошлась на запросе {q!r}"


def test_указатель_не_перебирает_весь_каталог(tmp_path):
    """Дефект P0: запрос не имеет права касаться каждой записи каталога."""
    mod, каталог = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(каталог))

    данные.искать("матрица")
    статистика = данные.статистика_поиска
    assert статистика["всего"] == len(КАТАЛОГ)
    assert статистика["полный_перебор"] is False
    assert статистика["кандидатов"] < статистика["всего"], (
        "запрос «матрица» отобрал весь каталог — отбор не работает")


def test_одиночное_короткое_слово_тоже_отбирается(tmp_path):
    """«я» и «up» короче куска, но ищутся по началам форм, а не перебором."""
    mod, каталог = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(каталог))

    for q in ("я", "up", "о"):
        данные.искать(q)
        assert данные.статистика_поиска["полный_перебор"] is False, (
            f"запрос {q!r} ушёл в полный перебор")


def test_несколько_коротких_слов_честно_переходят_на_перебор(tmp_path):
    """Когда сузить нечем, перебор признаётся явно, а не маскируется.

    В многословном запросе ярус 7 ищет слово подстрокой где угодно, и для
    слова короче куска отбор шире совпадения построить нечем. Молчаливое
    сужение здесь вырезало бы записи из выдачи, поэтому выбран честный
    перебор: он медленный, но такие запросы редки.
    """
    mod, каталог = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(каталог))

    данные.искать("я и он")
    assert данные.статистика_поиска["полный_перебор"] is True


def test_короткое_слово_не_мешает_отбору_по_длинному(tmp_path):
    """«бункер я» обязан сужаться по «бункер», а не падать в перебор."""
    mod, каталог = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(каталог))

    данные.искать("бункер я")
    assert данные.статистика_поиска["полный_перебор"] is False
    assert данные.статистика_поиска["кандидатов"] < len(КАТАЛОГ)


def test_записи_с_короткими_словами_не_теряются(tmp_path):
    """«Я и Он» состоит из слов короче куска и обязано находиться."""
    mod, каталог = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(каталог))

    assert "ya-i-on" in _выдача(данные, "я и он")
    assert "up" in _выдача(данные, "up")


def test_формы_и_фразы_считаются_один_раз_при_загрузке(tmp_path):
    """Пересчёт форм на каждом запросе — вторая половина дефекта P0."""
