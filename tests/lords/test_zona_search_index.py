"""Указатель поиска витрины: та же выдача, но без перебора всего каталога.

Дефект P0-SEARCH-FULL-SCAN: `искать()` сравнивал запрос с каждой записью и
пересчитывал формы названия на каждом запросе. На живом каталоге в 53 573
записи это 2.9 s медианы и 5.3 s p95 в изоляции, 8.4 s на живом маршруте.

Ускорение здесь опасно ровно одним способом: отбор кандидатов, который уже́е
совпадения, молча теряет записи. Пользователь видит не «медленно», а «не
найдено», и это хуже. Поэтому главный тест — не про скорость, а про
эквивалентность: выдача с указателем обязана совпадать с выдачей перебора
на каждом запросе батареи, включая запросы, которые ничего не находят.
"""

from __future__ import annotations

import importlib.util
import json
import os
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСХОДНИК = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"
ЖИВОЙ_КАТАЛОГ = Path("/srv/lords/.frontend/zona-01-catalog.json")


def _модуль(tmp_path: Path, items: list[dict]):
    каталог = tmp_path / "zona-01-catalog.json"
    каталог.write_text(
        json.dumps({"items": items, "revision": "test", "builtAt": "2026-09-21T00:00:00Z"}),
        encoding="utf-8",
    )
    env = dict(os.environ)
    os.environ["LORDS_CATALOG"] = str(каталог)
    имя = f"lf_search_index_{tmp_path.name}"
    spec = importlib.util.spec_from_file_location(имя, ИСХОДНИК)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[имя] = mod
    try:
        spec.loader.exec_module(mod)
    finally:
        os.environ.clear()
        os.environ.update(env)
    return mod, каталог


def _запись(slug: str, title: str, year: int, **доп) -> dict:
    з = {
        "slug": slug,
        "title": title,
        "kind": "Фильм",
        "year": year,
        "poster": f"https://p/{slug}.webp",
        "url": f"/title/{slug}/",
        "published_at": "2026-09-01T00:00:00Z",
    }
    з.update(доп)
    return з


#: Каталог собран из случаев, на которых отбор кандидатов ломается, если его
