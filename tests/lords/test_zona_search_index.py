@pytest.mark.skipif(not ЖИВОЙ_КАТАЛОГ.exists(), reason="живой каталог недоступен")
def test_живой_каталог_держит_бюджет_и_не_теряет_выдачу(tmp_path):
    """Бюджет контракта: тёплый p95 ≤ 1.0 s. Проверяется на живом каталоге."""
    import statistics
    import time

    mod, _ = _модуль(tmp_path, КАТАЛОГ)
    данные = mod.Данные(str(ЖИВОЙ_КАТАЛОГ))

    проверочные = ["матрица", "matrix", "vfnhbwf", "звездные войны",
                   "бункер 1-3 сезон", "наруто", "naruto", "zzznothing"]

    for q in проверочные:
        данные.указатель_включён = False
        эталон = _выдача(данные, q)
        данные.указатель_включён = True
        assert _выдача(данные, q) == эталон, f"живая выдача разошлась на {q!r}"

    времена = []
    for q in проверочные:
        данные.искать(q)  # прогрев
        начало = time.perf_counter()
        данные.искать(q)
        времена.append((time.perf_counter() - начало) * 1000)

    времена.sort()
    p95 = времена[min(len(времена) - 1, int(len(времена) * 0.95))]
    assert p95 <= 1000, f"тёплый p95 {p95:.0f} ms превышает бюджет 1000 ms"
