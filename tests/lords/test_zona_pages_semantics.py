import tempfile
from pathlib import Path

import pytest

from tests.lords.zona_kit import поднять, запросить

#: Маршрут → ожидаемый ответ. Список закрывает раздел 9 ночного задания.
МАРШРУТЫ = [
    ("/", 200),
    ("/catalog/", 200),
    ("/new/", 200),
    ("/new/?mode=added", 200),
    ("/movies/", 200),
    ("/series/", 200),
    ("/animation/", 200),
    ("/search/?q=свежий", 200),
    ("/search/?q=zzzzzzzzzz", 200),
    ("/search/", 200),
    ("/title/svezhiy/", 200),
    ("/title/serial-s-sezonami/", 200),
    ("/title/serial-s-sezonami/season-1/", 200),
    ("/title/serial-s-sezonami/season-1/episode-1/", 200),
    ("/collections/", 200),
    ("/title/takogo-net/", 404),
    ("/sovsem-drugoy-put/", 404),
    ("/title/serial-s-sezonami/season-9/", 404),
]


@pytest.fixture(scope="module")
def зона():
    return поднять(Path(tempfile.mkdtemp()), имя_модуля="nova_zona_pages")


@pytest.fixture(scope="module")
def страницы(зона):
    return {путь: запросить(зона, путь) for путь, _ in МАРШРУТЫ}


@pytest.mark.parametrize("путь,код", МАРШРУТЫ)
def test_маршрут_отвечает_ожидаемым_кодом(страницы, путь, код):
    assert страницы[путь].статус == код


@pytest.mark.parametrize("путь,код", МАРШРУТЫ)
def test_ровно_один_h1(страницы, путь, код):
    тело = страницы[путь].тело
    h1 = re.findall(r"<h1\b[^>]*>(.*?)</h1>", тело, re.S)
    assert len(h1) == 1, f"{путь}: H1 = {len(h1)}"
    текст = re.sub(r"<[^>]+>", "", h1[0]).strip()
    assert текст, f"{путь}: H1 пустой — заголовок ради теста, а не ради смысла"


@pytest.mark.parametrize("путь,код", МАРШРУТЫ)
def test_порядок_заголовков_не_прыгает(страницы, путь, код):
    """h3 без h2 над ним — сломанная иерархия, а не оформление."""
    уровни = [int(u) for u in re.findall(r"<h([1-6])\b", страницы[путь].тело)]
    предыдущий = 0
    for у in уровни:
        assert у <= предыдущий + 1 or предыдущий == 0, (
            f"{путь}: уровень h{у} после h{предыдущий}")
        предыдущий = у


