def test_кадр_плеера_не_лежит_в_исходном_html(зона):
    тело = запросить(зона, "/title/svezhiy/").тело
    assert "<iframe" not in тело, "тяжёлый кадр отдан до действия пользователя"
    assert 'data-player-contract="cdnvideohub-player-v1"' in тело
    assert 'data-state=' in тело, "состояние плеера не объявлено"


def test_скрипт_провайдера_не_блокирует_отрисовку(зона):
    тело = запросить(зона, "/title/svezhiy/").тело
    внешние = re.findall(r"<script[^>]*src=\"https?://[^\"]+\"[^>]*>", тело)
    assert внешние, "скрипт плеера пропал"
    for тег in внешние:
        assert " async" in тег or " defer" in тег, f"блокирующий скрипт: {тег}"


def test_без_javascript_страница_объясняет_а_не_молчит(зона):
    тело = запросить(зона, "/title/svezhiy/").тело
    assert "<noscript>" in тело and "JavaScript" in тело


