#: Страницы, на которых крошки есть по замыслу. Списочные страницы Zona
#: (каталог, разделы видов, новинки, поиск) — верхний уровень: там крошка
#: повторяла бы заголовок и ничего не добавляла. Дорисовывать её «ради
#: единообразия» значило бы придумать элемент, которого в оформлении нет.
С_КРОШКАМИ = {
    "/title/svezhiy/": ["/", "/movies/"],
    "/title/serial-s-sezonami/": ["/", "/series/"],
    "/title/serial-s-sezonami/season-1/": ["/", "/series/", "/title/serial-s-sezonami/"],
    "/title/serial-s-sezonami/season-1/episode-1/":
        ["/", "/series/", "/title/serial-s-sezonami/"],
}


@pytest.mark.parametrize("путь", sorted(С_КРОШКАМИ))
def test_крошки_соответствуют_маршруту(страницы, путь):
    тело = страницы[путь].тело
    m = re.search(r'<nav class="zcr"[^>]*>(.*?)</nav>', тело, re.S)
    assert m, f"{путь}: нет хлебных крошек"
    адреса = re.findall(r'<a[^>]*href="([^"]*)"', m.group(1))
    assert адреса == С_КРОШКАМИ[путь], (
        f"{путь}: крошки ведут не по маршруту: {адреса}")
    хвост = re.sub(r"<[^>]+>", "", m.group(1).rsplit("/", 1)[-1]).strip()
    assert хвост, f"{путь}: последняя крошка пуста"
    assert f'href="{путь}"' not in m.group(1), (
        f"{путь}: текущая страница выдана ссылкой на саму себя")


@pytest.mark.parametrize("путь", ["/catalog/", "/movies/", "/search/?q=свежий"])
def test_списочные_страницы_живут_без_крошек_осознанно(страницы, путь):
    """Отсутствие крошек здесь — замысел, и он закреплён, а не случаен."""
    тело = страницы[путь].тело
    assert '<nav class="zcr"' not in тело
    assert len(re.findall(r"<h1\b", тело)) == 1, "тогда заголовок обязан быть один"


@pytest.mark.parametrize("путь,код", МАРШРУТЫ)
def test_нет_мёртвых_целей_в_ссылках(страницы, путь, код):
    тело = страницы[путь].тело
    плохие = re.findall(r'href="(javascript:[^"]*|)"', тело)
    assert плохие == [], f"{путь}: мёртвые цели {плохие[:3]}"


def test_страница_произведения_несёт_описание_и_метаданные(зона):
    о = запросить(зона, "/title/svezhiy/")
    тело = о.тело
    assert "Свежий." in тело, "описание из источника не показано"
    assert "2026" in тело
    assert 'data-source="kp"' in тело and 'data-source="imdb"' in тело


def test_описание_не_обрезано_многоточием_в_середине(зона):
    """Обрезанный обязательный текст не короче — он неверен."""
    тело = запросить(зона, "/title/svezhiy/").тело
    m = re.search(r'<p[^>]*class="[^"]*z(?:desc|t__d)[^"]*"[^>]*>(.*?)</p>', тело, re.S)
    if m:
        assert "…" not in m.group(1) or "data-clamp-allowed" in m.group(0)


def test_страница_без_описания_не_даёт_пустой_секции(зона):
    """У `tolko-kp` описания нет — секция обязана исчезнуть, а не пустовать."""
    тело = запросить(зона, "/title/tolko-kp/").тело
    assert "Описание" not in тело or re.search(r"Описание.{0,120}\S", тело, re.S)


