@pytest.mark.parametrize("путь,код", МАРШРУТЫ)
def test_индексируемость_не_изменилась(страницы, путь, код):
    тело = страницы[путь].тело
    m = re.search(r'<meta name="robots" content="([^"]*)"', тело)
    assert m, f"{путь}: объявление robots пропало"
    assert m.group(1) == "noindex, nofollow", f"{путь}: robots = {m.group(1)!r}"
