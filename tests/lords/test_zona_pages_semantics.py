"""Zona: маршруты, заголовки и семантика страниц.

Закрепляется то, что измерено на стенде: главная, каталог, новинки в обоих
режимах, три раздела видов, поиск с результатом и пустой, страница
произведения, сезон, эпизод, подборки и настоящий 404.

Отдельно — плеер. Его контракт провайдерский (`cdnvideohub-player-v1`), и
менять его здесь не задача: проверяется, что он не стартует сам, не тащит
кадр в исходный HTML и не блокирует отрисовку.
"""
from __future__ import annotations

