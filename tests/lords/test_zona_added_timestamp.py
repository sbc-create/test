"""Время поступления показывается целиком.

Регрессия из списка владельца: «Время и даты обрезались до вида
`Добавлено 20.09...`; пользователь не видел часы и полную дату». Дефект
числился закрытым, но на главной всё ещё выводилось `Добавлено 28.09.2026, 00`.

Причина оказалась не в вёрстке и не в `overflow`, а в строке формата:
`"%d.%m.%Y, %H"` — токена минут в ней просто нет. Обрезка произошла до CSS,
поэтому ни одна визуальная проверка её и не поймала: элемент не переполнен,
в нём честно лежит неполный текст.

Второй случай — дата без времени. Она приходила сырой ISO-строкой и выводилась
как `Добавлено 2026-09-28` рядом с `28.09.2026` из соседней строки. Два формата
даты в одном списке — это не мелочь оформления: читатель перестаёт понимать,
что перед ним одно и то же поле.
"""

from __future__ import annotations

import re

import pytest

from tests.lords.test_nova_frontend_families import запросить
from tests.lords.test_zona_pass4 import _поднять


@pytest.fixture(scope="module")
def зона(tmp_path_factory):
    return _поднять(tmp_path_factory.mktemp("zona-added-ts"))


def метки(тело: str) -> list[str]:
    return re.findall(r'<span class="zadded__when">([^<]*)</span>', тело)


def test_время_поступления_показано_с_минутами(зона):
    о = запросить(зона, "/")
    assert о.статус == 200
    найдено = метки(о.тело)
    assert найдено, "на главной нет блока поступлений"

    for метка in найдено:
        assert not метка.rstrip().endswith("…"), f"метка обрезана: {метка!r}"
        совпало = re.fullmatch(
            r"Добавлено \d{2}\.\d{2}\.\d{4}(?:, \d{2}:\d{2})?", метка.strip())
        assert совпало, f"неожиданный формат метки: {метка!r}"


def test_ни_одна_метка_не_обрывается_на_часах(зона):
    """`28.09.2026, 00` — это не время, а обрубок времени."""
    for метка in метки(запросить(зона, "/").тело):
        assert not re.search(r", \d{2}$", метка.strip()), (
            f"у метки отрезаны минуты: {метка!r}")


def test_дата_без_времени_в_том_же_формате(зона):
    """ISO-строка не протекает в интерфейс рядом с точечным форматом."""
    for метка in метки(запросить(зона, "/").тело):
        assert not re.search(r"\d{4}-\d{2}-\d{2}", метка), (
            f"сырая ISO-дата в интерфейсе: {метка!r}")
