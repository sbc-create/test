"""Zona: порядок дат, разрыв равенства и границы страниц.

Проверяются свойства выдачи, а не внутреннее устройство сортировки:

* даты идут по убыванию, самая новая — первой;
* пустая и испорченная дата не всплывают наверх;
* равные даты разводятся устойчиво: два одинаковых запроса дают один порядок;
* пагинация не теряет и не дублирует записи;
* один тайтл не повторяется внутри одной выдачи.

Набор данных намеренно грязный: пустая дата, две равные даты, строка
«20-09-2026» вместо ISO. Чистый набор доказал бы только то, что код работает
на чистом наборе.
"""
from __future__ import annotations

import re
import tempfile
from pathlib import Path

import pytest

from tests.lords.zona_kit import ЗАПИСИ, поднять, запросить


@pytest.fixture(scope="module")
def зона():
    return поднять(Path(tempfile.mkdtemp()), имя_модуля="nova_zona_sorting")


def сетка(тело: str) -> list[str]:
    """Слаги карточек основной сетки в порядке выдачи, без повторов навигации."""
    внутри = re.search(r'<div class="zg">(.*?)</div>\s*(?:<nav|</div>)', тело, re.S)
    кусок = внутри.group(1) if внутри else тело
    порядок, видели = [], set()
    for s in re.findall(r'<a class="zt"[^>]*href="/title/([^/]+)/"', кусок):
        if s not in видели:
            видели.add(s)
            порядок.append(s)
    return порядок


ДАТЫ = {з["slug"]: з.get("published_at") or "" for з in ЗАПИСИ}
ВАЛИДНАЯ = re.compile(r"^\d{4}-\d{2}-\d{2}")


# --------------------------------------------------------------------------
# Порядок
# --------------------------------------------------------------------------

def test_даты_идут_по_убыванию(зона):
    порядок = сетка(запросить(зона, "/new/?mode=added").тело)
    даты = [ДАТЫ[s] for s in порядок if ВАЛИДНАЯ.match(ДАТЫ.get(s, ""))]
    assert даты == sorted(даты, reverse=True), (
        f"порядок дат нарушен: {list(zip(порядок, даты))}")


def test_самая_новая_дата_первой(зона):
    порядок = сетка(запросить(зона, "/new/?mode=added").тело)
    assert порядок[0] == "samyy-svezhiy", (
        f"наверху не самая свежая запись, а {порядок[0]}")


def test_пустая_дата_не_всплывает_наверх(зона):
    """Отрицательный тест: запись без даты не имеет права быть первой."""
    порядок = сетка(запросить(зона, "/new/?mode=added").тело)
    if "kadr-null-date" in порядок:
        валидные = [s for s in порядок if ВАЛИДНАЯ.match(ДАТЫ.get(s, ""))]
        assert порядок.index("kadr-null-date") > порядок.index(валидные[-1]), (
            "запись без даты оказалась среди датированных")


def test_испорченная_дата_не_всплывает_наверх(зона):
    """Отрицательный тест: «20-09-2026» не должна читаться как свежайшая."""
    порядок = сетка(запросить(зона, "/new/?mode=added").тело)
    if "bitaya-data" in порядок:
        assert порядок.index("bitaya-data") > порядок.index("samyy-svezhiy")
        assert порядок[0] != "bitaya-data"


def test_равные_даты_разводятся_устойчиво(зона):
    """Одинаковые даты — не повод менять порядок между запросами."""
    равные = [s for s, d in ДАТЫ.items() if d == "2026-09-18T08:00:00Z"]
    assert len(равные) >= 2, "в наборе нет пары равных дат — проверять нечего"
    первый = сетка(запросить(зона, "/new/?mode=added").тело)
    второй = сетка(запросить(зона, "/new/?mode=added").тело)
    assert первый == второй, "два одинаковых запроса дали разный порядок"
    пара = [s for s in первый if s in равные]
    assert len(пара) == len(равные), "запись с равной датой потеряна"


def test_порядок_каталога_воспроизводим(зона):
    a = сетка(запросить(зона, "/catalog/").тело)
    b = сетка(запросить(зона, "/catalog/").тело)
    assert a == b and a, "порядок каталога не воспроизводится"


def test_серверная_сортировка_совпадает_с_объявленной(зона):
    """Селектор сортировки обязан объявлять тот порядок, который отдан."""
    о = запросить(зона, "/catalog/?sort=recently_added")
    assert о.статус == 200
    assert 'data-testid="catalog-sort"' in о.тело
    выбран = re.search(r'<option value="[^"]*sort=recently_added"[^>]*selected', о.тело)
    assert выбран, "выбранная сортировка не отмечена в разметке"
    порядок = сетка(о.тело)
    даты = [ДАТЫ[s] for s in порядок if ВАЛИДНАЯ.match(ДАТЫ.get(s, ""))]
    assert даты == sorted(даты, reverse=True)


