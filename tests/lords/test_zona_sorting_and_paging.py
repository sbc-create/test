def test_ни_одна_секция_не_осталась_пустой(зона):
    """Отрицательный тест: заголовок без содержимого хуже отсутствия блока."""
    for путь in ("/", "/catalog/", "/movies/", "/new/?mode=added"):
        тело = запросить(зона, путь).тело
        for секция in re.findall(r'<section class="[^"]*"[^>]*>(.*?)</section>', тело, re.S):
            заголовок = re.search(r'<h2[^>]*>(.*?)</h2>', секция, re.S)
            if not заголовок:
                continue
            остальное = секция.replace(заголовок.group(0), "")
            содержимое = re.sub(r"<[^>]+>", "", остальное).strip()
            ссылки = re.findall(r"<a\b", остальное)
            assert содержимое or ссылки, (
                f"{путь}: секция «{заголовок.group(1)[:40]}» без содержимого")


def test_нет_пустых_кликабельных_ячеек(зона):
    """Ссылка без текста и без картинки — кликабельная пустота."""
    for путь in ("/", "/catalog/", "/new/?mode=added"):
        тело = запросить(зона, путь).тело
        for ссылка in re.findall(r"<a\b[^>]*>(.*?)</a>", тело, re.S):
            текст = re.sub(r"<[^>]+>", "", ссылка).strip()
            if текст or "<img" in ссылка or "svg" in ссылка:
                continue
            assert "aria-label=" in ссылка or "zhero__dot" in ссылка, (
                f"{путь}: пустая кликабельная зона: {ссылка[:120]}")


def test_главная_не_повторяет_один_тайтл_в_разных_лентах(зона):
    """Одна выборка под тремя заголовками — дефект, видимый зрителю."""
    тело = запросить(зона, "/").тело
    ленты = re.findall(r'<div class="zrl__track">(.*?)</div></div>', тело, re.S)
    assert ленты, "на главной нет ни одной ленты"
    занято = []
    for лента in ленты:
        занято += re.findall(r'href="/title/([^/]+)/"', лента)
    повторы = sorted({s for s in занято if занято.count(s) > 1})
    assert повторы == [], f"один тайтл в нескольких лентах главной: {повторы}"
