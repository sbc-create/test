"""B14A: матрица пустых и деградированных состояний.

Блок оставался незакрытым с прошлого прогона: в owner packet он записан как
«B14A empty/degraded matrix incomplete». Сами состояния витрина рисует давно,
и рисует по-разному — «Подборок пока нет» против «Подборки недоступны». Не
было проверки, которая удерживает это различие.

Различие — не оформление. Пустой раздел говорит «здесь правда ничего нет»,
недоступный источник говорит «мы не знаем, что здесь», а отклонённый параметр
говорит «условие не применено». Читатель принимает по ним разные решения:
уйти, вернуться позже или исправить запрос. Слить их в одно «Ничего не
найдено» — значит соврать в двух случаях из трёх.

Матрица держит четыре условия на каждое состояние: верный код ответа,
узнаваемый текст, выход навигацией и — главное — что три вида состояний
не совпадают друг с другом дословно.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

import pytest

from tests.lords.test_nova_frontend_families import запросить
from tests.lords.test_zona_pass4 import _поднять

#: Виды состояний. Их нельзя путать между собой — в этом весь смысл блока.
ЧЕСТНО_ПУСТО = "HONEST_EMPTY"
ИСТОЧНИК_НЕДОСТУПЕН = "SOURCE_UNAVAILABLE"
ВВОД_ОТКЛОНЁН = "REJECTED_INPUT"
НЕТ_СТРАНИЦЫ = "NOT_FOUND"
ПРИГЛАШЕНИЕ = "PROMPT"

ЭВИДЕНС = Path("artifacts/evidence/cursor-work-reconciliation-01/B14A_MATRIX.json")


@pytest.fixture(scope="module")
def зона(tmp_path_factory):
    return _поднять(tmp_path_factory.mktemp("zona-b14a"))


@pytest.fixture(scope="module")
def пустая(tmp_path_factory):
    """Витрина с по-настоящему пустым снимком каталога.

    `_поднять(n=0)` не даёт пустоты: фикстура всегда дописывает две служебные
    записи-ловушки. Для этого блока нужен именно пустой снимок — иначе
    проверяется не пустота, а каталог из двух записей.
    """
    import importlib.util
    import json
    import os
    import sys

    from tests.lords.test_zona_pass4 import ИСХОДНИК

    корень = tmp_path_factory.mktemp("zona-b14a-empty") / "zona-01"
    корень.mkdir(parents=True, exist_ok=True)
    (корень / "zona-01-catalog.json").write_text(
        json.dumps({"items": [], "revision": "empty", "count": 0,
                    "builtAt": "2026-09-19T00:00:00Z"}), encoding="utf-8")
    (корень / "zona-01-details.json").write_text("{}", encoding="utf-8")
    манифест = корень / "manifest.json"
    манифест.write_text(json.dumps({
        "schema_version": 1, "template_family": "zona",
        "design_version": "1.2.0", "source_commit": "0" * 40,
        "build_id": "B14A-EMPTY", "artifact_sha256": "0" * 64,
        "profile": "zona-test", "built_at": "2026-09-19T00:00:00Z",
    }), encoding="utf-8")

    старое = dict(os.environ)
    os.environ["LORDS_TEMPLATE_MANIFEST"] = str(манифест)
    os.environ["LORDS_CATALOG"] = str(корень / "zona-01-catalog.json")
    os.environ["LORDS_DETAILS"] = str(корень / "zona-01-details.json")
    os.environ["LORDS_SITE_NAME"] = "Zona B14A"
    os.environ["LORDS_CLOCK_ISO"] = "2026-09-19T12:00:00Z"
    try:
        имя = "nova_zona_b14a_empty"
        спец = importlib.util.spec_from_file_location(имя, ИСХОДНИК)
        модуль = importlib.util.module_from_spec(спец)
        sys.modules[имя] = модуль
        спец.loader.exec_module(модуль)
    finally:
        os.environ.clear()
        os.environ.update(старое)
    модуль.Обработчик.данные = модуль.Данные(str(корень / "zona-01-catalog.json"))
