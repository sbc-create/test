def текст(тело: str) -> str:
    без_тегов = re.sub(r"<[^>]+>", " ", тело)
    return re.sub(r"\s+", " ", без_тегов).strip()


def состояние(тело: str) -> str | None:
    """Заголовок пустого состояния, как его видит читатель."""
    м = re.search(r'<div class="z?empty"><b>([^<]+)</b>', тело)
    if м:
        return м.group(1).strip()
    м = re.search(r'<h1[^>]*id="catalog-h1">([^<]+)</h1>', тело)
    return м.group(1).strip() if м else None


СЛУЧАИ = [
    # (имя, путь, ожидаемый код, вид состояния)
    ("нераспознанный фильтр", "/catalog/?genre=no-such-genre", 200, ВВОД_ОТКЛОНЁН),
    ("номер страницы не число", "/catalog/?page=0", 400, ВВОД_ОТКЛОНЁН),
    ("страница за пределами", "/catalog/?page=9999", 404, НЕТ_СТРАНИЦЫ),
    ("страницы нет", "/no-such-page/", 404, НЕТ_СТРАНИЦЫ),
    ("поиск без запроса", "/search/", 200, ПРИГЛАШЕНИЕ),
    ("поиск без совпадений", "/search/?q=zzznothingatall", 200, ЧЕСТНО_ПУСТО),
]


@pytest.mark.parametrize("имя,путь,код,вид", СЛУЧАИ)
def test_состояние_отвечает_верным_кодом(зона, имя, путь, код, вид):
    """Soft-404 запрещён: «ничего нет» и «страницы нет» — разные ответы."""
    о = запросить(зона, путь)
    assert о.статус == код, f"{имя}: ожидался {код}, получен {о.статус}"


@pytest.mark.parametrize("имя,путь,код,вид", СЛУЧАИ)
def test_из_любого_состояния_есть_выход(зона, имя, путь, код, вид):
    """Страница ошибки без ссылки наружу — тупик, даже когда код верный."""
    о = запросить(зона, путь)
    assert re.search(r'href="/(catalog|search|new)/"', о.тело), (
        f"{имя}: из состояния некуда уйти")


@pytest.mark.parametrize("имя,путь,код,вид", [с for с in СЛУЧАИ if с[2] == 200])
def test_пустое_состояние_объясняет_себя_и_даёт_выход(зона, имя, путь, код, вид):
    о = запросить(зона, путь)
    видно = текст(о.тело)
    заголовок = состояние(о.тело)
    assert заголовок, f"{имя}: состояние без заголовка"
    assert len(видно) > 120, f"{имя}: страница пуста и ничего не объясняет"
    # Выход: ссылка в каталог или на сам раздел без условий.
    assert re.search(r'href="/(catalog|search|new)/"', о.тело), (
        f"{имя}: из состояния некуда уйти")


def test_отклонённый_ввод_не_выдаёт_себя_за_пустоту(зона):
    """«Фильтр не распознан» и «ничего не подошло» — разные сообщения.

    Слияние этих двух состояний — самая дорогая ошибка блока: пользователь
    решает, что в каталоге пусто, хотя на деле его условие не применили.
    """
    отклонён = состояние(запросить(зона, "/catalog/?genre=no-such-genre").тело)
    пусто = состояние(запросить(зона, "/search/?q=zzznothingatall").тело)
    assert отклонён and пусто
    assert отклонён != пусто, f"состояния совпали дословно: {отклонён!r}"
    assert "не распознан" in текст(
        запросить(зона, "/catalog/?genre=no-such-genre").тело).lower()


def test_недоступный_источник_не_выдаёт_себя_за_пустоту(зона, monkeypatch):
    """«Подборки недоступны» ≠ «Подборок пока нет».

    Первое — мы не знаем, что там. Второе — мы знаем, и там пусто. Разница в
    том, стоит ли читателю возвращаться позже.
    """
    пусто = состояние(запросить(зона, "/collections/").тело)

    monkeypatch.setattr(зона, "КОЛЛЕКЦИИ", None)
    недоступно = состояние(запросить(зона, "/collections/").тело)

    assert недоступно, "недоступный источник ничего не сказал"
    assert недоступно != пусто, (
        f"недоступность неотличима от пустоты: {недоступно!r}")
    assert "недоступ" in недоступно.lower()


def test_пустой_каталог_честен_а_не_молчалив(пустая):
    """Пустой снимок не даёт ни 404, ни пустого белого листа.

    Пустой каталог — законное состояние витрины: снимок может не приехать.
    Отвечать на него 404 значило бы объявить раздел несуществующим, а отдавать
    страницу без объяснения — оставить читателя гадать, что сломалось.
    """
    о = запросить(пустая, "/catalog/")
    assert о.статус == 200
    видно = текст(о.тело)
    assert len(видно) > 120
    заголовок = состояние(о.тело)
    assert заголовок, "пустой каталог не объяснил себя"
    assert "пуст" in заголовок.lower() or "нет" in заголовок.lower(), (
        f"состояние пустого каталога не читается как пустота: {заголовок!r}")
    assert re.search(r'href="/(catalog|search|new)/"', о.тело)


def test_матрица_записана_в_evidence(зона, пустая, monkeypatch):
    """Матрица — это документ приёмки, а не разовый вывод в консоль."""
    строки = []
    for имя, путь, код, вид in СЛУЧАИ:
        о = запросить(зона, путь)
        строки.append({
            "случай": имя,
            "путь": путь,
            "вид": вид,
            "код_ожидаемый": код,
            "код_фактический": о.статус,
            "заголовок_состояния": состояние(о.тело),
            "есть_выход": bool(re.search(r'href="/(catalog|search|new)/"', о.тело)),
        })

    о = запросить(пустая, "/catalog/")
    строки.append({
        "случай": "пустой снимок каталога", "путь": "/catalog/", "вид": ЧЕСТНО_ПУСТО,
        "код_ожидаемый": 200, "код_фактический": о.статус,
        "заголовок_состояния": состояние(о.тело),
        "есть_выход": bool(re.search(r'href="/(catalog|search|new)/"', о.тело)),
    })

    пусто_подборки = состояние(запросить(зона, "/collections/").тело)
    monkeypatch.setattr(зона, "КОЛЛЕКЦИИ", None)
    строки.append({
        "случай": "контракт подборок не передан", "путь": "/collections/",
        "вид": ИСТОЧНИК_НЕДОСТУПЕН, "код_ожидаемый": 200,
        "код_фактический": запросить(зона, "/collections/").статус,
        "заголовок_состояния": состояние(запросить(зона, "/collections/").тело),
        "есть_выход": True,
        "отличается_от_пустоты": пусто_подборки,
    })

    заголовки = [с["заголовок_состояния"] for с in строки if с["заголовок_состояния"]]
    документ = {
        "block": "B14A",
        "что_проверено": "коды ответов, узнаваемость состояний, выход навигацией",
        "SOFT_404_COUNT": sum(
            1 for с in строки
            if с["вид"] == НЕТ_СТРАНИЦЫ and с["код_фактический"] != 404),
        "СОСТОЯНИЙ_ВСЕГО": len(строки),
        "РАЗЛИЧИМЫХ_ЗАГОЛОВКОВ": len(set(заголовки)),
        "КОДЫ_СОВПАЛИ": all(
            с["код_ожидаемый"] == с["код_фактический"] for с in строки),
        "строки": строки,
    }
    assert документ["SOFT_404_COUNT"] == 0
    assert документ["КОДЫ_СОВПАЛИ"]

    if os.access(".", os.W_OK):
        ЭВИДЕНС.parent.mkdir(parents=True, exist_ok=True)
        ЭВИДЕНС.write_text(
            json.dumps(документ, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
