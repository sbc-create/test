"""Сезоны и серии: полнота, порядок и честность состояния просмотра.

Проверяется то, что действительно можно проверить на кандидате. Серии на
странице перечислены, но **не адресуемы**: у них нет ни ссылок, ни отдельных
адресов. Значит требования вида «URL, canonical и активная серия
соответствуют запрошенному эпизоду» на этом кандидате не выполнимы и не
объявляются выполненными — это записано отдельно, а не спрятано.

Что проверяется здесь: ни одна серия не потеряна, номера идут подряд и не
подменяются порядковым номером кнопки, сезоны пронумерованы подряд, а
отсутствие источника просмотра выражено честным состоянием.
"""
from __future__ import annotations

import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
КАНДИДАТ = КОРЕНЬ / "var" / "lords-candidate"

СЕЗОН = re.compile(r"<summary>Сезон (\d+) · (\d+) сери[йя]</summary>")
СЕРИЯ = re.compile(r'<li class="episode"><span>Серия (\d+)</span></li>')
ПЛЕЕР = re.compile(r'class="player__frame"')
ИСТОЧНИК = re.compile(
    r'(<iframe[^>]+src="|<video\b|<video-player\b|\.m3u8|\.mp4)', re.I)
НЕДОСТУПНО = re.compile(r"временно недоступн", re.I)
СМОТРЕТЬ = re.compile(r">\s*смотреть\b", re.I)


@pytest.fixture(scope="module", autouse=True)
def кандидат_есть():
    if not (КАНДИДАТ / "route-map.json").is_file():
        pytest.skip(f"кандидата нет: {КАНДИДАТ}")


def страница(слаг: str) -> str:
    п = КАНДИДАТ / "title" / слаг / "index.html"
    if not п.is_file():
        pytest.skip(f"страницы нет: {слаг}")
    return п.read_text("utf-8", "replace")


class TestНиОднаСерияНеПотеряна:
    """Сериал с 1212 сериями в одном сезоне — граничный случай каталога."""

    СЛАГ = "detektiv-konan"

    def test_отрисованы_все_серии(self):
        т = страница(self.СЛАГ)
        сезоны = СЕЗОН.findall(т)
        серии = СЕРИЯ.findall(т)
        assert сезоны, "блок сезонов не найден"
        объявлено = sum(int(n) for _, n in сезоны)
        assert len(серии) == объявлено, (
            f"объявлено {объявлено} серий, отрисовано {len(серии)}: список "
            f"усечён, и зритель не доберётся до хвоста")

    def test_нет_усечения_на_ста(self):
        """Известный дефект соседнего семейства: селектор обрывался на 100."""
        серии = [int(n) for n in СЕРИЯ.findall(страница(self.СЛАГ))]
        assert len(серии) > 100
        assert max(серии) > 210

    def test_граничные_номера_на_месте(self):
        серии = {int(n) for n in СЕРИЯ.findall(страница(self.СЛАГ))}
        отсутствуют = [н for н in (99, 100, 101, 210) if н not in серии]
        assert отсутствуют == [], f"нет серий: {отсутствуют}"

    def test_номер_серии_не_подменяется_порядком_кнопки(self):
        """Номер обязан быть номером серии, а не позицией в списке."""
        серии = [int(n) for n in СЕРИЯ.findall(страница(self.СЛАГ))]
        assert серии == sorted(серии), "порядок серий нарушен"
        assert len(серии) == len(set(серии)), "номера серий повторяются"
        # Позиция и номер совпадают только если нумерация сплошная с единицы;
        # проверяем именно это свойство явно, а не предполагаем его.
        assert серии[0] == 1
        assert серии[210 - 1] == 210


class TestСезоныПронумерованыПодряд:
    СЛАГ = "pokemon-sovremennoe-pokolenie"

    def test_пятый_сезон_существует(self):
        сезоны = dict(СЕЗОН.findall(страница(self.СЛАГ)))
        assert "5" in сезоны, f"сезоны: {sorted(сезоны, key=int)[:10]}"
        assert int(сезоны["5"]) > 0

    def test_номера_сезонов_без_пропусков(self):
        номера = [int(n) for n, _ in СЕЗОН.findall(страница(self.СЛАГ))]
        assert номера == list(range(1, len(номера) + 1)), номера[:12]

    def test_сумма_серий_совпадает_с_отрисованными(self):
        т = страница(self.СЛАГ)
        объявлено = sum(int(n) for _, n in СЕЗОН.findall(т))
        assert len(СЕРИЯ.findall(т)) == объявлено


class TestЧестноеСостояниеПросмотра:
    """Обещание просмотра без источника — худший вид неправды на витрине."""

    @pytest.fixture(scope="class")
    def образцы(self):
        каталог = КАНДИДАТ / "title"
        имена = sorted(x.name for x in каталог.iterdir() if x.is_dir())
        шаг = max(1, len(имена) // 60)
        return [(и, (каталог / и / "index.html").read_text("utf-8", "replace"))
                for и in имена[::шаг][:60]]

    def test_без_источника_нет_обещания_смотреть(self, образцы):
        лгут = []
        for слаг, т in образцы:
            if ИСТОЧНИК.search(т):
                continue
            if СМОТРЕТЬ.search(т) and not НЕДОСТУПНО.search(т):
                лгут.append(слаг)
        assert лгут == [], f"кнопка обещает просмотр без источника: {лгут[:5]}"

    def test_область_плеера_объявлена_всегда(self, образцы):
        без = [с for с, т in образцы if not ПЛЕЕР.search(т)]
        assert без == [], f"страницы без области плеера: {без[:5]}"

    def test_отсутствие_источника_названо(self, образцы):
        молчат = []
        for слаг, т in образцы:
            if not ИСТОЧНИК.search(т) and not НЕДОСТУПНО.search(т):
                молчат.append(слаг)
        assert молчат == [], (
            f"источника нет, и страница об этом молчит: {молчат[:5]}")


class TestСерииПокаНеАдресуемы:
    """Факт, который нельзя прятать: у серий нет собственных адресов.

    Пока их нет, требования к URL, canonical и активной серии на кандидате
    невыполнимы, и объявлять их выполненными нельзя. Тест закрепляет факт,
    чтобы его нельзя было потерять из виду при следующей правке.
    """

    def test_у_серий_нет_ссылок(self):
        т = страница("detektiv-konan")
        блок = re.search(r'<section class="seasons">.*?</section>', т, re.S)
        assert блок, "блок сезонов не найден"
        ссылки = re.findall(r"<a\b", блок.group(0))
        assert ссылки == [], (
            "у серий появились ссылки: требования к адресу серии стали "
            "выполнимы, и проверки нужно расширить, а не оставлять как есть")
