"""Zona: слайдер, кадрирование и полная дата «Добавлено».

Три дефекта, найденные измерением живой витрины 2026-09-21:

1. Правая половина слайдера выглядела пустой, а текст пропадал. Ряд `.zhero`
   держался на `min-height`/`max-height`, поэтому ПОРТРЕТНЫЙ постер задавал ему
   свою природную высоту: при колонке 632px картинка 500×741 требовала 937px.
   `max-height:390px` не сжимал ряд, а обрезал его; тело справа центрировалось
   по 937px и уезжало под обрез.

2. Полка не добиралась до правого края. Ширина карточки считается делением
   контейнера на N карточек и N-1 промежутков, но `gap` полки был 12px, а
   расчёт делил по `--z-gap:14px`; сверх того `.zt` нёс потолок
   `--z-card-max:180px`, обрезавший расчётную основу 186.3px. Семь карточек
   занимали 1332px из 1376 — справа оставалась мёртвая полоса 44px.

3. Дата обрезалась многоточием на середине времени: «Добавлено 20.09.2026, 11»
   вместо «…, 11:49». Обрезанная дата не короче — она неверна: выглядит как
   время без минут.

Проверяется CSS-контракт стиля Zona. Геометрия в браузере снимается отдельным
прогоном (`artifacts/evidence/zona-slider-01/`): держать Chromium в модульных
тестах дорого, а подменять измерение утверждением — нечестно.
"""

from __future__ import annotations

import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИСХОДНИК = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"


@pytest.fixture(scope="module")
def зона_стиль() -> str:
    """Тело ЗОНА_СТИЛЬ — стиль именно витрины Zona, не Animedia и не Lords."""
    текст = ИСХОДНИК.read_text(encoding="utf-8")
    m = re.search(r'^ЗОНА_СТИЛЬ = """(.*?)^"""', текст, re.S | re.M)
    assert m, "блок ЗОНА_СТИЛЬ не найден"
    return m.group(1)


#: Блок @media целиком, вместе с вложенными правилами.
_MEDIA = re.compile(r"@media\([^)]*\)\{(?:[^{}]|\{[^{}]*\})*\}", re.S)


def _без_медиа(css: str) -> str:
    """Стиль без @media: базовые правила ищутся отдельно от переопределений.

    Иначе поиск «последнего правила» находил бы узкоэкранный override и
    проверял не то правило, которое действует по умолчанию.
    """
    return _MEDIA.sub("", css)


def _правило(css: str, селектор: str) -> str:
    """Тело БАЗОВОГО правила для точного селектора (вне @media)."""
    найдено = re.findall(
        r"(?:^|\})\s*" + re.escape(селектор) + r"\s*\{([^}]*)\}",
        _без_медиа(css), re.S | re.M
    )
    assert найдено, f"базовое правило {селектор} не найдено"
    return найдено[-1].replace("\n", "")


# --------------------------------------------------------------------------
# 1. Слайдер: высота ряда задана, правая половина не пустует
# --------------------------------------------------------------------------


def test_ряд_слайдера_имеет_заданную_высоту(зона_стиль: str) -> None:
    """Без определённой высоты портретный постер растягивает ряд под себя."""
    m = re.search(
        r"@media\(min-width:900px\)\{\.zhero\{([^}]*)\}", зона_стиль, re.S
    )
    assert m, "нет десктопного правила .zhero"
    тело = m.group(1).replace("\n", "")
    assert "height:clamp(" in тело, (
        "высота ряда не задана: max-height только обрезает, но не сжимает — "
        "ряд снова будет расти под природную пропорцию постера"
    )
    assert "min-height:0" in тело
    assert "max-height:none" in тело


def test_медиа_слайдера_не_диктует_высоту(зона_стиль: str) -> None:
    m = re.search(
        r"@media\(min-width:900px\)\{\.zhero__media\{([^}]*)\}", зона_стиль, re.S
    )
    assert m, "нет десктопного правила .zhero__media"
    тело = m.group(1).replace("\n", "")
    assert "height:100%" in тело, "медиа обязана занимать высоту ряда, а не задавать её"
    assert "min-height:100%" not in тело, (
        "min-height:100% возвращает прежний дефект: высота определяется картинкой"
    )


def test_кадрирование_смещено_к_верхней_трети(зона_стиль: str) -> None:
    """У постеров название и лица сверху; центр по умолчанию показывал торс."""
    тело = _правило(зона_стиль, ".zhero__media img")
    assert "object-fit:cover" in тело
    m = re.search(r"object-position:\s*50%\s*(\d+)%", тело)
    assert m, f"object-position не задан: {тело}"
    доля = int(m.group(1))
    assert 15 <= доля <= 40, (
        f"точка кадрирования {доля}% вне верхней трети: 50% вернёт обрез по торсу"
    )


# --------------------------------------------------------------------------
# 2. Полка: точная подгонка без мёртвой полосы справа
# --------------------------------------------------------------------------


def test_полка_и_расчёт_берут_один_промежуток(зона_стиль: str) -> None:
    """`gap` и делитель основы обязаны читать одну переменную."""
    тело = _правило(зона_стиль, ".zwpop .zrl__track")
    assert "--z-gap:12px" in тело, (
        "полка задаёт gap числом, а основа делится по --z-gap — подгонка не сойдётся"
    )
    assert "gap:var(--z-gap)" in тело


def test_потолок_ширины_снят_для_карточек_полки(зона_стиль: str) -> None:
    """На полке ширина карточки — результат деления, а не потолок."""
    тело = _правило(зона_стиль, ".zrl__track")
    assert "--z-card-max:none" in тело, (
        ".zt несёт max-width:var(--z-card-max) и по каскаду перебивает основу; "
        "потолок обязан сниматься на полке"
    )


def test_карточки_полки_без_собственного_потолка(зона_стиль: str) -> None:
    тело = _правило(зона_стиль, ".zrl__track>*")
    assert "max-width:none" in тело
    assert "--z-card-max" not in тело or "max-width:var(--z-card-max)" not in тело


@pytest.mark.parametrize(
    "ширина,карточек,делитель",
    [(390, 2, 1), (768, 4, 3), (1440, 7, 6), (1920, 8, 7)],
)
def test_основа_делит_контейнер_нацело(
    зона_стиль: str, ширина: int, карточек: int, делитель: int
) -> None:
    """N карточек и N-1 промежутков обязаны складываться ровно в ширину."""
    if ширина == 390:
        m = re.search(r"\.zrl__track>\*\{flex:0 0 calc\(\(100cqw - (.+?)\)\s*/\s*(\d+)\)", зона_стиль)
    else:
        m = re.search(
            rf"@media\(min-width:{ширина}px\)\{{\.zrl__track>\*\{{flex:0 0 "
            rf"calc\(\(100cqw - (.+?)\)\s*/\s*(\d+)\)",
            зона_стиль,
        )
    assert m, f"нет правила основы для {ширина}px"
    вычитаемое, n = m.group(1), int(m.group(2))
    assert n == карточек, f"на {ширина}px ожидалось {карточек} карточек, в правиле {n}"
    множитель = re.match(r"(\d+)\s*\*", вычитаемое.strip())
    факт = int(множитель.group(1)) if множитель else 1
    assert факт == делитель, (
        f"на {ширина}px вычитается {факт} промежутков, а между {карточек} "
        f"карточками их {делитель} — остаток уйдёт в пустоту справа"
    )


