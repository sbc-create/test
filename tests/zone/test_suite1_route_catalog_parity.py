class TestРантайм:
    def test_прямой_переход_по_карточке(self, зона):
        цель = sorted(зона["цели"])[0]
        ответ = запрос(зона["сайт"], цель)
        assert ответ["code"] == 200, цель

    def test_жёсткое_обновление_даёт_тот_же_ответ(self, зона):
        цель = sorted(зона["цели"])[0]
        обычный = запрос(зона["сайт"], цель)
        жёсткий = запрос(зона["сайт"], цель,
                         заголовки={"HTTP_CACHE_CONTROL": "no-cache",
                                    "HTTP_PRAGMA": "no-cache"})
        assert жёсткий["code"] == обычный["code"] == 200
        assert жёсткий["body"] == обычный["body"]

    def test_карточка_ведёт_на_ту_же_сущность(self, зона):
        """200 мало: страница обязана быть страницей ИМЕННО этой сущности."""
        несовпадений = []
        for цель in sorted(зона["цели"])[:25]:
            ответ = запрос(зона["сайт"], цель)
            if ответ["code"] != 200:
                несовпадений.append((цель, ответ["code"]))
                continue
            слаг = um.слаг_из_маршрута(цель)
            тело = ответ["body"].decode("utf-8", "replace")
            if f'"{цель}"' not in тело and слаг not in тело:
                несовпадений.append((цель, "сущность не найдена в теле"))
        assert несовпадений == [], несовпадений

    def test_неизвестная_сущность_даёт_настоящий_404(self, зона):
        ответ = запрос(зона["сайт"], "/title/net-takoy-sushnosti-9999/")
        assert ответ["code"] == 404, "несуществующее обязано отвечать 404"
        assert b"<html" in ответ["body"].lower() or ответ["body"] == b""

    def test_ложных_200_нет(self, зона):
        """Ни один несуществующий адрес не отвечает успехом."""
        ложные = []
        for хвост in ("net-1", "net-2", "../etc", "%2e%2e/passwd"):
            ответ = запрос(зона["сайт"], f"/title/{хвост}/")
            if ответ["code"] == 200:
                ложные.append(хвост)
        assert ложные == []

    def test_нормализация_даёт_один_переход(self, зона):
        """Повторный слэш и верхний регистр исправляются одним 308."""
        цель = sorted(зона["цели"])[0]
        кривой = "/TITLE/" + цель[len("/title/"):]
        ответ = запрос(зона["сайт"], кривой)
        assert ответ["code"] in (301, 308), ответ["code"]
        куда = ответ["headers"].get("Location")
        assert куда == цель, куда
        второй = запрос(зона["сайт"], куда)
        assert второй["code"] == 200, "второй переход обязан завершать цепочку"

    def test_циклов_перенаправления_нет(self, зона):
        цель = sorted(зона["цели"])[0]
        путь, посещённые = "/TITLE/" + цель[len("/title/"):], []
        for _ in range(5):
            ответ = запрос(зона["сайт"], путь)
            if ответ["code"] not in (301, 308):
                break
            путь = ответ["headers"]["Location"]
            assert путь not in посещённые, f"цикл: {путь}"
            посещённые.append(путь)
        assert len(посещённые) <= 1, "перенаправление длиннее одного перехода"


