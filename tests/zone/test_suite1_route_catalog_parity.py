# Общая первопричина: тот же callsite ломает и чинит все три витрины
# =============================================================================

class TestОбщаяПервопричина:
    @pytest.mark.parametrize("пакет", sorted(set(ПАКЕТЫ.values())))
    def test_частичная_сборка_согласована_после_исправления(self, пакет):
        каталог = fx.build_catalog()
        выборка = frozenset(sorted(t.slug for t in каталог.titles)[:5])
        _, сайт = собрать(пакет, выборка=выборка)
        п = um.паритет(цели_карточек(сайт), карта_сайта(сайт))
        assert п.orphan_targets == (), (
            f"{пакет}: осиротевших {len(п.orphan_targets)}")

    @pytest.mark.parametrize("пакет", sorted(set(ПАКЕТЫ.values())))
    def test_без_исправления_рассогласование_воспроизводится(self, пакет):
        """Тот же callsite без ограничения ломает любую из витрин."""
        пакет_данные = _пакет(пакет)
        assert пакет_данные is not None
        каталог = fx.build_catalog()
        выборка = frozenset(sorted(t.slug for t in каталог.titles)[:5])
        сайт = render_mod.render_site(
            пакет_данные, catalog=каталог, environ={}, publisher_id="1",
            only_title_slugs=выборка, restrict_cards_to_rendered=False)
        п = um.паритет(цели_карточек(сайт), карта_сайта(сайт))
        assert п.orphan_targets != (), (
            "без ограничения рассогласование обязано воспроизводиться — "
            "иначе доказывать нечего")
