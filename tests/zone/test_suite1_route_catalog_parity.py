"""SUITE_1 — паритет каталога, карточек, перечня маршрутов и рантайма.

Цепочка проверяется целиком и на одном и том же собранном сайте: разорви её
на части — и каждое звено окажется исправным, а витрина продолжит вести в
никуда. Рантайм здесь настоящий: тот же WSGI-раздатчик, что стоит на витрине.
"""
from __future__ import annotations

import re

import pytest

from factory.lords import fixtures as fx
from factory.lords import preview as preview_mod
from factory.lords import render as render_mod
from factory.lords import serve as serve_mod
from factory.lords import urlmap as um

ССЫЛКА = re.compile(r'href="(/title/[a-z0-9\-/]*)"')
#: Имена берутся из PRODUCTS сборщика, а не придумываются по домену.
ПАКЕТЫ = {"zona-01": "zona-cinema-preview", "animedia-01": "animedia-preview",
          "animedia-02": "animedia-preview"}


def _пакет(имя: str):
    try:
        return preview_mod._package(имя)[0]
    except Exception:                      # пакета нет — это факт, а не пропуск
        return None


def собрать(пакет_имя: str, *, выборка=None):
    пакет = _пакет(пакет_имя)
    assert пакет is not None, f"пакет {пакет_имя} не найден"
    каталог = fx.build_catalog()
    сайт = render_mod.render_site(
        пакет, catalog=каталог, environ={}, publisher_id="1",
        only_title_slugs=выборка, restrict_cards_to_rendered=выборка is not None)
    return каталог, сайт


def цели_карточек(сайт) -> set[str]:
    цели = set()
    for страница in сайт.pages.values():
        тело = страница.body
        if isinstance(тело, bytes):
            тело = тело.decode("utf-8", "replace")
        for сырой in ССЫЛКА.findall(тело):
            цели.add(um.нормализовать(сырой))
    return цели


def опубликованные(каталог, сайт) -> set[str]:
    """Сущности, которые ЭТА витрина публикует.

    Не весь каталог: часть типов на витрине выключена планом, и их отсутствие
    маршрутом не является нарушением. Перечень берётся оттуда же, откуда его
    берёт рендер, — иначе проверка меряла бы другой набор.
    """
    from factory.lords import content_types as ct
    виды = [к for к in ct.active_types(сайт.plan.type_states)
            if к in render_mod.TYPE_LABELS]
    return {t.slug for t in каталог.of_types(виды)}


def карта_сайта(сайт) -> um.Карта:
    слаги = {um.слаг_из_маршрута(а) for а in сайт.pages}
    return um.построить({с for с in слаги if с})


def запрос(сайт, путь: str, *, заголовки=None):
    """Настоящий WSGI-запрос к тому же раздатчику, что и на витрине."""
    приложение = serve_mod.Application(сайт)
    записано = {}

    def начать(статус, заголовки_ответа, exc_info=None):
        записано["status"] = статус
        записано["headers"] = dict(заголовки_ответа)

    окружение = {"PATH_INFO": путь, "REQUEST_METHOD": "GET",
                 "QUERY_STRING": ""}
    окружение.update(заголовки or {})
    тело = b"".join(приложение(окружение, начать))
    записано["body"] = тело
    записано["code"] = int(записано["status"].split()[0])
    return записано


@pytest.fixture(scope="module")
def зона():
    каталог, сайт = собрать(ПАКЕТЫ["zona-01"])
    return {"каталог": каталог, "сайт": сайт, "карта": карта_сайта(сайт),
            "цели": цели_карточек(сайт),
            "опубликованные": опубликованные(каталог, сайт)}


