class TestПаритет:
    def test_каждая_карточка_имеет_маршрут(self, зона):
        п = um.паритет(зона["цели"], зона["карта"])
        assert п.orphan_targets == (), (
            f"карточек без маршрута: {len(п.orphan_targets)}")

    def test_каждая_опубликованная_сущность_имеет_маршрут(self, зона):
        отсутствуют = зона["опубликованные"] - зона["карта"].слаги
        assert отсутствуют == set(), f"без маршрута: {sorted(отсутствуют)[:5]}"

    def test_коллизий_маршрутов_нет(self, зона):
        адреса = [а for _, а in зона["карта"].routes]
        assert len(адреса) == len(set(адреса))

    def test_одна_сущность_один_маршрут(self, зона):
        слаги = [с for с, _ in зона["карта"].routes]
        assert len(слаги) == len(set(слаги))

    def test_домен_не_входит_в_идентичность(self, зона):
        for _, адрес in зона["карта"].routes:
            assert адрес.startswith("/title/")
            assert "://" not in адрес and "." not in адрес.strip("/").split("/")[0]

    def test_карта_детерминирована(self, зона):
        повтор = um.построить(зона["карта"].слаги)
        assert повтор.отпечаток == зона["карта"].отпечаток
        assert повтор.routes == зона["карта"].routes


