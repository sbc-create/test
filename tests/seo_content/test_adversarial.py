# Найденные и закрытые обходы:
#
# 1. Числительные словами проходили мимо всех числовых ворот — добавлен
#    разбор `numerals.py` и подстановка цифр перед числовыми проверками.
# 2. «106 серия» считалось количеством, а не номером — разбор по форме
#    существительного при данном числительном.
# 3. Обещание просмотра формами «плеер доступен», «серии выложены», «лежит
#    на витрине» не ловилось — список оборотов расширен.
# 4. Перефразированные штампы («сюжет захватывает», «на одном дыхании») не
#    ловились — список расширен, полнота не заявляется.
# 5. Мягкие призывы («начните просмотр сегодня», «убедитесь сами») проходили
#    как описание — добавлены в рекламные обороты.
# 6. Отставший номер, написанный прописью, не находился — сканирование
#    поверхностей переведено на текст с подставленными цифрами.


class TestЛожныеСрабатыванияКоторыеБылиИсправлены:
    """Обратная сторона ужесточения: проверка не должна ругаться на верное.

    Каждый случай здесь однажды срабатывал ложно и привёл к правке. Без них
    ужесточение выглядело бы улучшением, а на деле ломало бы правильные
    тексты.
    """

    ТЕЛО_СЕЗОНА = ("Сезон 4 «Тихая гавань» — продолжение первого сезона без "
                   "перерыва в хронологии. В сезоне 24 серии.")

    def test_ссылка_на_другой_сезон_не_опровергается(self):
        from factory.seo_content.testing import пакет_сезона
        отчёт = extract_and_verify(пакет_сезона(4),
                                   {"body_description": self.ТЕЛО_СЕЗОНА})
        assert отчёт.contradicted == [], [c.detail for c in отчёт.contradicted]

    def test_ссылка_на_другой_сезон_в_тексте_не_устаревший_номер(self):
        from factory.seo_content.testing import пакет_сезона
        p = пакет_сезона(4)
        беды = ID.stale_number_scan(
            {"body_description": "продолжение первого сезона"},
            episode_number=None, season_number=4,
            fact_texts=[str(ф.value) for ф in p.facts])
        assert беды == []

    def test_но_в_заголовке_чужой_номер_остаётся_ошибкой(self):
        from factory.seo_content.testing import пакет_сезона
        p = пакет_сезона(4)
        беды = ID.stale_number_scan(
            {"meta_title": "Тихая гавань, сезон 1"},
            episode_number=None, season_number=4,
            fact_texts=[str(ф.value) for ф in p.facts])
        assert беды, "заголовок опознаёт страницу — чужой номер здесь ошибка"

    def test_общее_длинное_название_не_считается_заимствованием(self):
        длинное = ("Обратный отсчёт в Кимже: полная хроника второй навигации "
                   "и всего, что за ней последовало")
        а = (f"«{длинное}» — сериал 2019 года производства России. В центре "
             f"истории — смотритель маяка.")
        б = (f"«{длинное}» — фильм 2024 года производства Канады. Главное "
             f"действующее лицо — инженер водоканала.")
        корпус = [CorpusEntry("e0", "seo-test-0002", "title", "t0", б,
                              names=(длинное,))]
        о = NearDuplicateDetector(корпус).check(
            а, site_id="seo-test-0001", entity_id="t1", names=(длинное,),
            allowed_titles=(длинное,))
        assert not о.blocked, о.to_dict()

    def test_порядковое_числительное_не_становится_количеством(self):
        """«Первого сезона» — это номер, а не «одного сезона»."""
        assert "1-го" in NUM.в_цифрах("продолжение первого сезона")
        assert NUM.в_цифрах("в две тысячи четырнадцатом году") == \
            "в 2014 году"


class TestНазваниеНеЯвляетсяУтверждением:
    """Личность страницы — не факт о ней.

    Произведение «2012» не заявляет год выпуска, «Драма» — жанр, «Россия» —
    страну производства. До правки каждое из трёх опровергало собственный
    факт, и черновик отклонялся на совершенно верном тексте.
    """

    @pytest.mark.parametrize("название,путь,значение,тип", [
        ("2012", "/year", 2009, "year"),
        ("Драма", "/genres", ["комедия"], "genre"),
        ("Россия", "/countries", ["Франция"], "country"),
    ])
    def test_название_не_опровергает_факт(self, название, путь, значение, тип):
        p = заменить_факт(заменить_факт(пакет_тайтла(),
                                        "/canonical_title_ru", название),
                          путь, значение)
        тексты = {
            "meta_title": f"{название} (2009) — сериал",
            "meta_description": f"{название} — сериал 2009 года.",
            "h1_recommendation": название,
            "body_description": f"«{название}» — сериал 2009 года.",
        }
        отчёт = extract_and_verify(p, тексты)
        assert [c for c in отчёт.contradicted if c.claim_type == тип] == []

    def test_но_настоящая_подмена_ловится_по_прежнему(self):
        отчёт = extract_and_verify(
            пакет_тайтла(),
            {"body_description": "«Тихая гавань» — сериал 2014 года "
                                 "производства Японии, жанр комедия."})
        типы = {c.claim_type for c in отчёт.contradicted}
        assert {"year", "country", "genre"} <= типы, типы

    def test_жанр_названный_после_имени_остаётся_утверждением(self):
        """Замена привязана к началу строки: дальше по тексту слово снова
        значит то, что значит."""
        p = заменить_факт(заменить_факт(пакет_тайтла(),
                                        "/canonical_title_ru", "Драма"),
                          "/genres", ["комедия"])
        отчёт = extract_and_verify(
            p, {"meta_description": "Драма — сериал 2019 года. Жанры: драма."})
        assert [c for c in отчёт.contradicted if c.claim_type == "genre"]
