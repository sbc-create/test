class TestЧислаСловами:
    """Числовые ворота смотрели только на цифры."""

    @pytest.mark.parametrize("текст,ожидание", [
        ("Сериал снят в две тысячи четырнадцатом году.", 2014),
        ("Премьера в тысяча девятьсот девяносто девятом году.", 1999),
        ("У сериала семь сезонов.", 7),
        ("Сто шестая серия завершает сезон.", 106),
        ("Сорок девятая серия вышла позже.", 49),
        ("Двадцать первый сезон снимали дольше.", 21),
    ])
    def test_число_читается(self, текст, ожидание):
        значения = [з for з, *_ in NUM.читать(текст)]
        assert ожидание in значения, значения

    @pytest.mark.parametrize("текст", [
        "Стоит посмотреть эту работу.",
        "Семья героя живёт в посёлке.",
        "Трио музыкантов выступает в финале.",
        "Он стал свидетелем событий.",
        "Стая птиц поднимается над водой.",
        "Сотовая связь в посёлке не работает.",
    ])
    def test_обычное_слово_числом_не_становится(self, текст):
        assert list(NUM.читать(текст)) == []

    def test_подменённый_словами_год_опровергается(self):
        отчёт = extract_and_verify(
            пакет_тайтла(),
            {"body_description": "Сериал снят в две тысячи четырнадцатом году."})
        assert [c for c in отчёт.contradicted if c.claim_type == "year"]

    def test_верный_год_словами_подтверждается(self):
        отчёт = extract_and_verify(
            пакет_тайтла(),
            {"body_description": "Сериал снят в две тысячи девятнадцатом году."})
        assert not отчёт.contradicted

    def test_подменённый_словами_номер_серии_опровергается(self):
        отчёт = extract_and_verify(
            пакет_серии(),
            {"body_description": "Сто шестая серия завершает сезон."})
        assert [c for c in отчёт.contradicted
                if c.claim_type == "episode_number"]

    def test_отставший_номер_прописью_ловится(self):
        беды = ID.stale_number_scan({"meta_title": "Сто шестая серия"},
                                    episode_number=100, season_number=None)
        assert беды


class TestКоличествоИлиНомер:
    """«106 серия» — номер, «210 серий» — количество. Решает форма слова."""

    @pytest.mark.parametrize("текст,тип", [
        ("В сезоне 210 серий.", "episode_count"),
        ("Всего 24 серии.", "episode_count"),
        ("106 серия завершает сезон.", "episode_number"),
        ("100 серия завершает сезон.", "episode_number"),
    ])
    def test_разбор_по_форме_слова(self, текст, тип):
        отчёт = extract_and_verify(пакет_серии(), {"body_description": текст})
        типы = {c.claim_type for c in отчёт.claims}
        assert тип in типы, типы


