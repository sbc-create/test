class TestПерефразированныеШтампы:
    ФОРМЫ = [
        "Сюжет захватывает и не отпускает до финала.",
        "Работа не оставит зрителя безразличным.",
        "Смотрится на одном дыхании.",
        "Эта история покорит сердца зрителей.",
        "Лучшее в своём жанре.",
        "Нельзя пропустить.",
    ]

    @pytest.mark.parametrize("фраза", ФОРМЫ)
    def test_штамп_ловится(self, фраза):
        о = LanguageValidator().validate(фраза)
        assert о.cliches, [i.code for i in о.issues]

    ПРИЗЫВЫ = [
        "Начните просмотр прямо сегодня.",
        "Убедитесь сами.",
        "Добавьте в закладки.",
        "Поделитесь с друзьями.",
        "Вас ждёт долгая история.",
    ]

    @pytest.mark.parametrize("фраза", ПРИЗЫВЫ)
    def test_призыв_ловится(self, фраза):
        о = LanguageValidator().validate(фраза)
        assert [i for i in о.issues if i.code == "ADVERTISING_TONE"], фраза

    @pytest.mark.parametrize("фраза", [
        "Действие происходит в посёлке на двести дворов.",
        "В сезоне двенадцать серий, статус выхода — завершён.",
        "Первоисточник — повесть того же автора.",
        "Отличительная черта — весь сезон снят одним оператором.",
    ])
    def test_обычное_описание_не_объявляется_штампом(self, фраза):
        о = LanguageValidator().validate(фраза)
        assert о.cliches == []
        assert [i for i in о.issues if i.code == "ADVERTISING_TONE"] == []


class TestПопыткиОбойтиПроверкуДублей:
    ОРИГИНАЛ = ("«Тихая гавань» — сериал 2019 года производства России. "
                "В центре истории — смотритель маяка Вера Ильина; действие "
                "происходит на острове с одним причалом. Заявленные жанры — "
                "драма и детектив.")

    def корпус(self, текст):
        return [CorpusEntry("e0", "seo-test-0002", "title", "t0", текст,
                            names=("Тихая гавань",))]

    def проверить(self, текст, корпус, names=("Тихая гавань",)):
        return NearDuplicateDetector(корпус).check(
            текст, site_id="seo-test-0001", entity_id="title-0001",
            names=names, allowed_titles=names)

    def test_вставка_слова_каждые_десять_слов_не_спасает(self):
        """Цепочка из двенадцати слов рвётся, но пятиграммы остаются."""
        слова = self.ОРИГИНАЛ.split()
        разбавленный = " ".join(
            (с + " притом") if i and i % 9 == 0 else с
            for i, с in enumerate(слова))
        о = self.проверить(разбавленный, self.корпус(self.ОРИГИНАЛ))
        assert о.blocked or о.review_required, о.to_dict()

    def test_перестановка_предложений_не_спасает(self):
        предложения = [с.strip() for с in self.ОРИГИНАЛ.split(".") if с.strip()]
        переставленный = ". ".join(reversed(предложения)) + "."
        о = self.проверить(переставленный, self.корпус(self.ОРИГИНАЛ))
        assert о.blocked or о.review_required

    def test_смена_регистра_и_пунктуации_не_спасает(self):
        о = self.проверить(self.ОРИГИНАЛ.upper().replace("—", "-"),
                           self.корпус(self.ОРИГИНАЛ))
        assert о.blocked

    def test_подмена_названия_и_чисел_не_спасает(self):
        чужой = (self.ОРИГИНАЛ.replace("Тихая гавань", "Медный ключ")
                 .replace("2019", "2021"))
        о = self.проверить(чужой, self.корпус(self.ОРИГИНАЛ),
                           names=("Медный ключ",))
        assert о.cross_site_template_copies == 1 or о.blocked


