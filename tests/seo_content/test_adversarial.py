"""Попытки обойти собственные проверки.

Набор написан в обратную сторону: не «проверим, что хорошее проходит», а
«попробуем протащить плохое». Каждый случай здесь когда-то проходил, и
каждый привёл к правке кода — список найденных обходов в конце файла.

Полноты этот набор не даёт и не заявляет. Регулярное выражение никогда не
опишет «штамп» или «обещание просмотра» целиком; оно закрывает наблюдаемые
формы. Ценность набора в том, что закрытая форма больше не открывается.
"""
from __future__ import annotations

import pytest

from factory.seo_content import identity as ID
