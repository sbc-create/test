def _факт(fact_id: str, путь: str, значение, *, source_id="src-catalog",
          provider="internal_catalog", confidence=1.0,
          conflict_status="NONE", лицензия="internal"):
    return {"fact_id": fact_id, "source_id": source_id, "provider": provider,
            "retrieved_at": ВРЕМЯ,
            "snapshot_hash": hashlib.sha256(
                f"{source_id}|{путь}|{значение}".encode()).hexdigest()[:32],
            "field_path": путь, "value": значение, "confidence": confidence,
            "conflict_status": conflict_status, "source_license": лицензия}


#: Счётчик вариантов. Индексировать пулы номером сущности нельзя: номера
#: разных групп (тайтлы 1…45, сезоны 200…, отрицательные 900…) совпадают по
#: остатку от длины пула, и два разных случая получают одну и ту же завязку —
#: а значит и одинаковое предложение в тексте. Проверка дублей это честно
#: ловит, но ловит она дефект набора, а не контура.
_ВАРИАНТ = [0]


def вариант() -> int:
    _ВАРИАНТ[0] += 1
    return _ВАРИАНТ[0]


def из_пула(пул: list, в: int, шаг: int = 1):
    """Элемент пула по номеру варианта, без периода длиной в пул.

    Простое `в % len(пул)` даёт совпадение у любых двух вариантов,
    отличающихся на длину пула: сорок девятый случай получает ту же завязку и
    то же место, что первый, — и предложение повторяется слово в слово.
    Добавка `в // len(пул)` сдвигает выбор на каждом обороте, поэтому пара
    (герой, место) не повторяется, пока не исчерпаны оба пула.
    """
    n = len(пул)
    return пул[(в * шаг + в // n) % n]


def _название(i: int, пул: list[str]) -> str:
    return пул[i % len(пул)]


def факты_тайтла(i: int, *, пул: list[str], полнота: str = "full",
                 в: int | None = None) -> list[dict]:
    """Набор фактов о произведении. `полнота` управляет тем, чего не хватает.

    `в` — номер варианта: по нему выбираются завязка, место и герой. Он
    сквозной по всему набору, поэтому два случая не получают одинаковых
    предложений.
    """
    в = вариант() if в is None else в
    тип = ТИПЫ[i % len(ТИПЫ)]
    сериальный = тип in ("series", "anime", "cartoon", "ova")
    название = _название(i, пул)
    герой, актриса = из_пула(ИМЕНА, в, 7)
    факты = [
        _факт("f-title", "/canonical_title_ru", название),
        _факт("f-type", "/work_type", тип),
        _факт("f-country", "/countries", СТРАНЫ[i % len(СТРАНЫ)]),
        _факт("f-genre", "/genres", из_пула(ЖАНРЫ, в, 7)),
        _факт("f-age", "/age_rating", ВОЗРАСТ[i % len(ВОЗРАСТ)]),
        _факт("f-status", "/release_status", СТАТУСЫ[i % len(СТАТУСЫ)]),
        _факт("f-video", "/video_availability",
              ["AVAILABLE", "UNAVAILABLE", "UNKNOWN"][i % 3]),
        _факт("f-studio", "/studio", из_пула(СТУДИИ, в, 3)),
        _факт("f-spoiler", "/spoiler_level", "PREMISE"),
    ]
    if полнота != "no_year":
        факты.append(_факт("f-year", "/year", 2008 + (i % 18)))
    if полнота != "no_synopsis":
        факты += [
            _факт("f-subject", "/premise_subject",
                  f"{из_пула(СУБЪЕКТЫ, в)} {герой}"),
            _факт("f-setting", "/setting", из_пула(МЕСТА, в, 5)),
            _факт("f-conflict", "/premise_conflict",
                  из_пула(КОНФЛИКТЫ, в, 11) + ", "
                  + из_пула(ПОСЛЕДСТВИЯ, в, 13)),
            _факт("f-chars", "/characters",
                  [{"name": герой, "actor": актриса}]),
        ]
    if сериальный:
        сезонов = 1 + (i % 4)
        серий = [8, 10, 12, 13, 16, 20, 24][i % 7]
        факты += [_факт("f-seasons", "/season_count", сезонов),
                  _факт("f-declared", "/declared_episode_count", серий),
                  _факт("f-actual", "/actual_episode_count", серий)]
    первоисточник = из_пула(ПЕРВОИСТОЧНИКИ, в, 5)
    if первоисточник:
        факты.append(_факт("f-source", "/source_material", первоисточник))
    особенность = из_пула(ОСОБЕННОСТИ, в, 5)
    if особенность:
        факты.append(_факт("f-feature", "/distinctive_feature", особенность))
    видели = {ф["field_path"] for ф in факты}
    assert len(видели) == len(факты), "два факта об одном поле в наборе"
    return факты


def заменить(факты: list[dict], новый: dict) -> list[dict]:
    """Положить факт, вытеснив прежний с тем же полем.

    Без вытеснения получился бы пакет с двумя фактами об одном поле и
    одинаковым `fact_id` — состояние, которое конструктор пакета отвергает, и
    правильно делает.
    """
    остальные = [ф for ф in факты if ф["field_path"] != новый["field_path"]]
    return остальные + [новый]


def случай(case_id, kind, tags, событие, маршрут, ожидание, *,
           site=None, note=None) -> dict:
    с = {"case_id": case_id, "kind": kind, "tags": tags, "event": событие,
         "route": маршрут, "expect": ожидание,
         "site": site or {"site_id": событие["site_id"],
                          "site_url": f"https://{событие['site_id']}.invalid",
                          "own_angle": "разбор устройства произведения",
                          "same_catalog": False, "sibling_sites": []}}
    if note:
        с["note"] = note
    return с


def маршрут_тайтла(slug: str, entity_id: str) -> dict:
    return {"url": f"/title/{slug}/", "resolved_entity_id": entity_id,
            "canonical": f"/title/{slug}/",
            "breadcrumbs": ["Главная", "Каталог", slug]}


def slug(i: int, префикс: str = "t") -> str:
    return f"{префикс}-{i:04d}"


