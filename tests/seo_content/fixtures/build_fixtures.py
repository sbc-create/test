def дубли(пул: list[str]) -> list[dict]:
    """Первоисточник и две его копии на соседних витринах.

    Первый случай — законный: он ни на что не похож и обязан пройти. Второй —
    побайтовая копия на другой витрине. Третий — та же копия с подменённым
    названием: ровно тот способ «уникализации», ради которого и заведено
    маскирование имён.
    """
    # Вариант заведомо не используется остальным набором: иначе копия
    # столкнулась бы с посторонним случаем раньше, чем со своим оригиналом, и
    # проверка измеряла бы не то.
    базовые = факты_тайтла(3, пул=пул, в=10_000)
    случаи = []

    eid = "title-dup-origin"
    случаи.append(случай(
        "dup-origin", "negative", ["duplicate", "origin"],
        {"event_type": "title.created", "event_id": "ev-dup-origin",
         "site_id": "seo-test-0002", "entity_id": eid, "title_id": eid,
         "locale": "ru", "facts": базовые},
        маршрут_тайтла("dup-origin", eid),
        {"status_in": ["PASSED"]},
        site={"site_id": "seo-test-0002",
              "site_url": "https://seo-test-0002.invalid",
              "own_angle": "разбор устройства произведения",
              "same_catalog": False, "sibling_sites": []},
        note="оригинал: с ним и будут сравниваться копии"))

    eid = "title-dup-exact"
    случаи.append(случай(
        "dup-crosssite-exact", "negative", ["duplicate", "exact_duplicate"],
        {"event_type": "title.created", "event_id": "ev-dup-exact",
         "site_id": "seo-test-0003", "entity_id": eid, "title_id": eid,
         "locale": "ru", "facts": базовые},
        маршрут_тайтла("dup-exact", eid),
        {"status_in": ["REJECTED"], "reason_contains": ["DUPLICATE"]},
        site={"site_id": "seo-test-0003",
              "site_url": "https://seo-test-0003.invalid",
              "own_angle": "разбор устройства произведения",
              "same_catalog": False, "sibling_sites": []},
        note="тот же пакет фактов на соседней витрине даёт тот же текст"))

    переименованные = заменить(
        базовые, _факт("f-title", "/canonical_title_ru", "Медный ключ"))
    eid = "title-dup-renamed"
    случаи.append(случай(
        "dup-crosssite-renamed", "negative",
        ["duplicate", "paraphrased_duplicate"],
        {"event_type": "title.created", "event_id": "ev-dup-renamed",
         "site_id": "seo-test-0004", "entity_id": eid, "title_id": eid,
         "locale": "ru", "facts": переименованные},
        маршрут_тайтла("dup-renamed", eid),
        {"status_in": ["REJECTED"], "reason_contains": ["DUPLICATE"]},
        site={"site_id": "seo-test-0004",
              "site_url": "https://seo-test-0004.invalid",
              "own_angle": "разбор устройства произведения",
              "same_catalog": False, "sibling_sites": []},
        note="та же болванка с подставленным названием"))
    return случаи


def собрать(пул: list[str], сайт: str, *, тайтлов: int, сезонов: int,
            серий: int, с_отрицательными: bool) -> list[dict]:
    корпус: list[dict] = []
    корпус += тайтлы(пул, сайт, 1, тайтлов)
    корпус += сезоны(пул, сайт, 200, сезонов)
    корпус += серии(пул, сайт, 400, серий)
    if с_отрицательными:
        корпус += отрицательные(пул, сайт)
        корпус += трудные_случаи(пул, сайт)
        корпус += бедные_серии(пул, сайт)
        корпус += дубли(пул)
    return корпус


