def тайтлы(пул: list[str], сайт: str, начало: int, сколько: int) -> list[dict]:
    случаи = []
    for k in range(сколько):
        i = начало + k
        eid = f"title-{i:04d}"
        событие = {"event_type": "title.created", "event_id": f"ev-t-{i:04d}",
                   "site_id": сайт, "entity_id": eid, "title_id": eid,
                   "locale": "ru", "facts": факты_тайтла(i, пул=пул)}
        случаи.append(случай(
            f"title-{i:04d}", "title", ["title", ТИПЫ[i % len(ТИПЫ)]], событие,
            маршрут_тайтла(slug(i), eid),
            # Исход обычного случая зависит от корпуса: два произведения с
            # одинаковыми жанрами, счётчиками и статусом дают совпадающую
            # цепочку слов, и проверка дублей останавливает второе — она для
            # того и есть. Поэтому здесь проверяются свойства, не зависящие
            # от места в очереди, а отказ по дублю объявлен допустимым и
            # считается отдельно.
            {"status_in": ["PASSED"], "allow_duplicate_rejection": True,
             "no_contradicted": True, "no_unsupported_material": True,
             "identity_ok": True}))
    return случаи


