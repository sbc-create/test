"""Устаревшая ревизия и конкурирующее обновление редакционных правок.

Повод. Проверки сквозного круга (`test_editorial_publish_cycle.py`) замыкают
круг публикаций, но их фикстура ПОДМЕНЯЕТ сторож чужой правки
(`_чужая_правка` → пустая строка). То есть путь «кто-то записал новее» не
исполняется в них ни разу, и требование «обработка устаревшей ревизии и
конкурирующего обновления» остаётся непроверенным.

Здесь сторож работает по-настоящему. Проверяется четыре положения, и каждое —
отдельная причина отказа или отдельный способ потерять данные:

1. **файл новее нашей доставки** — отказ с НАЗВАННОЙ причиной, и живой файл
   не тронут. Молчаливая перезапись здесь и была бы потерей;
2. **файл есть, а мы ничего не доставляли** — тоже отказ: это чужая правка
   целиком, и затирать её слепо нельзя;
3. **файл исчез, хотя мы доставляли** — отказ, потому что исчезновение это
   событие, а не разрешение писать с нуля;
4. **чужое поле, появившееся ПОСЛЕ сверки** — попадает в состав, а не
   теряется: состав читает живой файл после сторожа, и это свойство порядка
   вызовов стоит закрепить тестом, иначе перестановка строк его сломает молча.

Плюс два требования, которые легко спутать с первыми: пропущенное в правке
поле не превращается в пустое значение, и повторное применение одного набора
не создаёт дублей.

Данные изолированы: временный каталог, подставной сайт. Ни одной записи в
постоянные данные витрин.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))

from factory.cell import editorial_store  # noqa: E402
from factory.qwen import editorial, registry  # noqa: E402

СЛАГ = "silsila-badalte-rishton-ka"
НАЗВАНИЕ = "История наших отношений"
ОРИГИНАЛ = "Silsila Badalte Rishton Ka"


class Сайт:
    site_id = "zona-01"
    domain = "zonafilm.space"
    adapter = "lords"
    account = "zonafilm-space"


def живой_файл(путь: Path, правки: dict) -> None:
    путь.write_text(json.dumps({
        "schema_version": 1, "site_id": "zona-01", "overrides": правки,
    }, ensure_ascii=False), encoding="utf-8")


def запомнить_доставку(каталог: Path, живой: Path) -> None:
    """Записать, что ИМЕННО ЭТОТ файл доставляли мы."""
    (каталог / editorial.ДОСТАВЛЕНО).write_text(json.dumps({
        "file_digest": editorial._цифра_файла(живой),
    }, ensure_ascii=False), encoding="utf-8")


@pytest.fixture()
def стенд(tmp_path, monkeypatch):
    живой = tmp_path / "editorial-overrides.json"
    живой_файл(живой, {
        СЛАГ: {"fields": {"name": НАЗВАНИЕ, "original_name": ОРИГИНАЛ},
               "actor": "zona-01/posters-titles/run-7",
               "reason": "решение D200"},
    })
    monkeypatch.setattr(registry, "путь_доставки", lambda s: str(живой))
    monkeypatch.setattr(registry, "механизм", lambda s: "editorial-queue")
    monkeypatch.setattr(editorial, "_каталог", lambda s: tmp_path)
    monkeypatch.setattr(editorial, "_записать_атомарно", lambda *а, **к: None)
    # Сторож НЕ подменяется: ради него этот файл и существует.
    return живой, tmp_path, monkeypatch


def опубликовать(стенд, записи, *, перед_составом=None):
    """Публикация описаний; `перед_составом` имитирует гонку."""
    живой, каталог, monkeypatch = стенд
    поданное: dict = {}
    настоящие_живые = editorial._живые_правки

    def живые(s):
        if перед_составом is not None:
            перед_составом()
        return настоящие_живые(s)

    def подача(s, правки, *, author, reason):
        поданное["правки"] = правки
        живой.write_text(json.dumps(
            editorial_store.собрать("zona-01", правки, actor="executor/проба",
                                    reason="проба"),
            ensure_ascii=False), encoding="utf-8")
        return {"request_id": "zona-01-edit-проба"}

    monkeypatch.setattr(editorial, "_живые_правки", живые)
    monkeypatch.setattr(editorial, "_подать_правки", подача)
    editorial._доставить(Сайт(), записи, записи, поколение="g-1",
                         author="editor/проба", reason="описание")
    return поданное.get("правки")


def состояние(живой: Path) -> dict:
    return (json.loads(живой.read_text(encoding="utf-8"))
            .get("overrides") or {})


# --- сторож устаревшей ревизии -------------------------------------------

def test_файл_новее_нашей_доставки_отказ_с_причиной(стенд):
    """Кто-то записал новее — отказ, и живой файл не тронут."""
    живой, каталог, _м = стенд
    запомнить_доставку(каталог, живой)
    # Чужая правка ПОСЛЕ нашей доставки: отпечаток разошёлся.
    живой_файл(живой, {
        СЛАГ: {"fields": {"name": "Чужое название"}, "actor": "кто-то"},
    })
    до = живой.read_text(encoding="utf-8")

    with pytest.raises(Exception) as сбой:
        опубликовать(стенд, [{"slug": СЛАГ, "body": "Новое описание."}])
    текст = str(сбой.value)
    assert "кто-то записал новее" in текст, текст
    assert живой.read_text(encoding="utf-8") == до, "живой файл изменён"


def test_чужой_файл_без_нашей_доставки_отказ(стенд):
    """Файл есть, а мы не доставляли: затирать слепо нельзя."""
    живой, _к, _м = стенд
    до = живой.read_text(encoding="utf-8")
    with pytest.raises(Exception) as сбой:
        опубликовать(стенд, [{"slug": СЛАГ, "body": "Новое описание."}])
    assert "которого мы не доставляли" in str(сбой.value)
    assert живой.read_text(encoding="utf-8") == до


def test_исчезновение_файла_это_событие_а_не_разрешение(стенд):
    """Файл исчез, хотя мы доставляли — отказ, а не запись с нуля."""
    живой, каталог, _м = стенд
    запомнить_доставку(каталог, живой)
    живой.unlink()
    with pytest.raises(Exception) as сбой:
        опубликовать(стенд, [{"slug": СЛАГ, "body": "Новое описание."}])
    assert "исчез" in str(сбой.value)
    assert not живой.exists(), "файл создан там, где его убрали"


def test_совпадающий_отпечаток_публикацию_пропускает(стенд):
    """Наша же доставка — пишем поверх своего, и название переживает."""
    живой, каталог, _м = стенд
    запомнить_доставку(каталог, живой)
    правки = опубликовать(стенд, [{"slug": СЛАГ, "body": "Новое описание."}])
    assert правки is not None
    запись = состояние(живой)[СЛАГ]["fields"]
    assert запись["name"] == НАЗВАНИЕ
    assert запись["original_name"] == ОРИГИНАЛ
    assert запись["description"] == "Новое описание."


# --- конкурирующее обновление --------------------------------------------

def test_чужое_поле_появившееся_после_сверки_попадает_в_состав(стенд):
    """Состав читает живой файл ПОСЛЕ сторожа — и это свойство порядка.

    Если строки переставить (состав до сторожа), чужое поле потеряется молча.
    Тест закрепляет порядок вызовов, а не их написание.
    """
    живой, каталог, _м = стенд
    запомнить_доставку(каталог, живой)

    def гонка():
        текущее = состояние(живой)
        текущее.setdefault("dorohedoro-2-2", {
            "fields": {"poster_url": "/posters/dorohedoro.jpg"},
            "actor": "другая-сессия", "reason": "постер"})
        живой_файл(живой, текущее)

    правки = опубликовать(стенд, [{"slug": СЛАГ, "body": "Описание."}],
                          перед_составом=гонка)
    assert "dorohedoro-2-2" in правки, (
        "чужая запись, появившаяся после сверки, потеряна")
    assert (правки["dorohedoro-2-2"]["fields"]["poster_url"]
            == "/posters/dorohedoro.jpg")
    assert правки[СЛАГ]["fields"]["name"] == НАЗВАНИЕ


# --- частичное обновление и повторы --------------------------------------

def test_пропущенное_поле_не_становится_пустым(стенд):
    """В правке только описание — название остаётся значением, не ''."""
    живой, каталог, _м = стенд
    запомнить_доставку(каталог, живой)
    правки = опубликовать(стенд, [{"slug": СЛАГ, "body": "Описание."}])
    поля = правки[СЛАГ]["fields"]
    assert поля["name"] == НАЗВАНИЕ
    assert поля["name"] != ""
    assert "original_name" in поля and поля["original_name"] == ОРИГИНАЛ


def test_пустое_значение_в_живом_файле_не_переносится(стенд):
    """Пустая строка — отсутствие значения, а не значение.

    Иначе пустое поле поехало бы в состав и закрепилось как «название есть и
    оно пустое», что хуже отсутствия записи.
    """
    живой, каталог, _м = стенд
    живой_файл(живой, {
        СЛАГ: {"fields": {"name": "", "original_name": ОРИГИНАЛ},
               "actor": "кто-то", "reason": "проба"},
    })
    запомнить_доставку(каталог, живой)
    правки = опубликовать(стенд, [{"slug": СЛАГ, "body": "Описание."}])
    поля = правки[СЛАГ]["fields"]
    assert "name" not in поля or поля["name"] != ""
    assert поля["original_name"] == ОРИГИНАЛ


def test_повторное_применение_не_создаёт_дублей(стенд):
    """Тот же набор дважды — одна запись, то же содержимое."""
    живой, каталог, _м = стенд
    запомнить_доставку(каталог, живой)
    опубликовать(стенд, [{"slug": СЛАГ, "body": "Описание."}])
    запомнить_доставку(каталог, живой)
    правки = опубликовать(стенд, [{"slug": СЛАГ, "body": "Описание."}])
    записи = состояние(живой)
    assert len([к for к in записи if к == СЛАГ]) == 1
    assert list(правки).count(СЛАГ) == 1
    assert записи[СЛАГ]["fields"]["name"] == НАЗВАНИЕ
    assert записи[СЛАГ]["fields"]["description"] == "Описание."


def test_сторож_не_подменён_в_этом_наборе():
    """Страховка от повторения той же ошибки: сторож здесь настоящий.

    В наборе сквозного круга он подменён пустой строкой, и именно поэтому
    путь устаревшей ревизии там не исполнялся. Если кто-нибудь подменит его и
    здесь, этот тест упадёт.
    """
    источник = Path(__file__).read_text(encoding="utf-8")
    # Искомое собирается из частей НАМЕРЕННО: иначе проверка нашла бы саму
    # себя — первая редакция так и упала, потому что её же условие содержало
    # искомую строку целиком.
    имя = "_чужая" + "_правка"
    подмена = f'setattr(editorial, "{имя}"'
    assert подмена not in источник, (
        "сторож чужой правки подменён в наборе, который существует ради "
        "его настоящего прогона")
    # И он действительно вызывается в проверяемом коде.
    из_службы = (КОРЕНЬ / "factory" / "qwen" / "editorial.py").read_text(
        encoding="utf-8")
    assert f"беда = {имя}(s)" in из_службы
