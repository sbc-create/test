"""Сборка состава накладки: авторство переходит только у записей этой публикации.

Дефект, измеренный 12.10 в 22:47Z на `zonafilm.space` первой весомой сверкой
накладки. Публикация описания одного тайтла переписала `actor` и `reason` у
ТРЁХ записей, которых не касалась: у всех стало
`editor/claude-auto/run-20261012T224004Z` и причина «SEO-описание тайтла
ura-mechte-…», хотя записи описывают Дорохедоро, Ледяную стену и Agar Tum Na
Hote. Тексты описаний при этом байт в байт прежние — терялось именно
происхождение.

Причина была в двух местах одновременно: подсев из живого файла брал только
поля КРОМЕ `description` (значит записи с одним описанием сохранять было
нечем), а снятие авторства шло по `все` — то есть по всей прежней истории, а не
по записям этого вызова.

Почему этого не поймала ни одна из 21 проверки редакционного цикла: сборка жила
внутри `_доставить`, рядом с выбором механизма и записью журнала, и проверить её
можно было только полным прогоном публикации. Теперь она чистая функция.
"""
from __future__ import annotations

import pathlib

from factory.qwen import editorial


ЖИВЫЕ = {
    "дорохедоро": {"fields": {"description": "описание Дорохедоро"},
                   "actor": "editor/claude-auto/run-20261011T125537Z",
                   "reason": "SEO-описание тайтла dorohedoro-2-2"},
    "ледяная-стена": {"fields": {"description": "описание Ледяной стены"},
                      "actor": "editor/claude-auto/run-20261011T125537Z",
                      "reason": "SEO-описание тайтла ledyanaya-stena"},
    "silsila": {"fields": {"name": "История наших отношений"},
                "actor": "architect/claude-restore/run-20261011T170500Z",
                "reason": "восстановление решения D200"},
}


def test_авторство_прежних_записей_сохраняется():
    """Главная проверка: ровно тот случай, который сломался на живой витрине."""
    состав = editorial.состав_правок(
        ЖИВЫЕ,
        [{"slug": "ura-mechte", "body": "новое описание"}],
        [{"slug": "дорохедоро", "body": "описание Дорохедоро"},
         {"slug": "ледяная-стена", "body": "описание Ледяной стены"},
         {"slug": "ura-mechte", "body": "новое описание"}],
    )
    for ключ in ("дорохедоро", "ледяная-стена"):
        assert состав[ключ]["actor"] == \
            "editor/claude-auto/run-20261011T125537Z", состав[ключ]
    assert состав["дорохедоро"]["reason"] == \
        "SEO-описание тайтла dorohedoro-2-2", состав["дорохедоро"]


def test_авторство_записи_этой_публикации_не_наследуется():
    """Обратная сторона: свою правку надо записать как свою.

    Без этой проверки предыдущая прошла бы и у сборки, которая НИКОГДА не
    передаёт авторство публикующему — а тогда журнал врал бы в другую сторону.
    """
    состав = editorial.состав_правок(
        ЖИВЫЕ,
        [{"slug": "дорохедоро", "body": "ПЕРЕписанное описание"}],
        [{"slug": "дорохедоро", "body": "ПЕРЕписанное описание"}],
    )
    assert "actor" not in состав["дорохедоро"], состав["дорохедоро"]
    assert "reason" not in состав["дорохедоро"], состав["дорохедоро"]


def test_чужое_ручное_поле_и_его_авторство_целы():
    """Поле, которого редактор не ведёт, публикация не трогает вовсе."""
    состав = editorial.состав_правок(
        ЖИВЫЕ,
        [{"slug": "ura-mechte", "body": "новое описание"}],
        [{"slug": "ura-mechte", "body": "новое описание"}],
    )
    assert состав["silsila"]["fields"] == {"name": "История наших отношений"}
    assert состав["silsila"]["actor"] == \
        "architect/claude-restore/run-20261011T170500Z"


def test_записи_с_одним_описанием_переносятся_из_живого_файла():
    """Прежняя редакция их не переносила — и сохранять авторство было нечем.

    Если запись не попала в состав из живого файла, она пересоздаётся из
    списка публикаций, где авторства нет вовсе.
    """
    состав = editorial.состав_правок(ЖИВЫЕ, [], [])
    assert set(состав) == {"дорохедоро", "ледяная-стена", "silsila"}, состав
    assert состав["ледяная-стена"]["fields"]["description"] == \
        "описание Ледяной стены"


def test_описание_из_публикации_перекрывает_живое():
    """Новый текст должен попасть в состав, иначе публикация бессмысленна."""
    состав = editorial.состав_правок(
        ЖИВЫЕ,
        [{"slug": "дорохедоро", "body": "свежее описание"}],
        [{"slug": "дорохедоро", "body": "свежее описание"}],
    )
    assert состав["дорохедоро"]["fields"]["description"] == "свежее описание"


def test_пустое_значение_в_живом_файле_не_переносится():
    """Пустая строка — не правка, и переносить её значит плодить пустые записи."""
    состав = editorial.состав_правок(
        {"пусто": {"fields": {"description": ""}, "actor": "кто-то"}}, [], [])
    assert состав == {}, состав


def test_запись_без_ключа_или_текста_пропускается():
    состав = editorial.состав_правок(
        {}, [], [{"slug": "", "body": "есть текст"},
                 {"slug": "есть-ключ", "body": "   "}])
    assert состав == {}, состав


def test_ключ_берётся_из_title_id_когда_он_есть():
    """У семейств с источником фактов ключ — `title_id`, а не слаг."""
    состав = editorial.состав_правок(
        {}, [{"title_id": "t-1", "slug": "слаг", "body": "текст"}],
        [{"title_id": "t-1", "slug": "слаг", "body": "текст"}])
    assert set(состав) == {"t-1"}, состав


def test_пустые_входные_данные_не_роняют_сборку():
    """Чистая функция обязана переносить отсутствие данных, а не падать."""
    assert editorial.состав_правок({}, [], []) == {}
    assert editorial.состав_правок(None, None, None) == {}


# --------------------------------------------------------------- путь снятия
#
# Снятие — это доставка состава БЕЗ одной записи. Прежняя редакция собирала
# этот состав из одних описаний и без авторства, поэтому `собрать` подставляла
# каждой оставшейся записи актора и причину ЭТОГО снятия. В публикации тот же
# дефект измерен 12.10 в 22:47Z на zonafilm.space и исправлен; в снятии он
# дожил до разбора 18.10, потому что путь не был покрыт проверкой.
#
# Снятие ничего не пишет от своего имени, поэтому `новые` для него пусты: нет
# записи, у которой авторство должно перейти к снимающему.


def test_снятие_сохраняет_авторство_оставшихся():
    """Главная проверка пути снятия."""
    остальные = [{"slug": "дорохедоро", "body": "описание Дорохедоро"},
                 {"slug": "ледяная-стена", "body": "описание Ледяной стены"}]
    живые = {к: з for к, з in ЖИВЫЕ.items() if к in {"дорохедоро", "ледяная-стена"}}
    состав = editorial.состав_правок(живые, [], остальные)
    assert set(состав) == {"дорохедоро", "ледяная-стена"}
    for ключ in состав:
        assert состав[ключ]["actor"] == \
            "editor/claude-auto/run-20261011T125537Z", состав[ключ]
        assert состав[ключ]["reason"].startswith("SEO-описание"), состав[ключ]


def test_снятие_не_присваивает_авторство_снимающему():
    """Отрицательный контроль: `новые` пусты, значит переклеймить нечего."""
    состав = editorial.состав_правок(
        {"дорохедоро": {"fields": {"description": "старое"},
                        "actor": "editor/claude-auto/run-A",
                        "reason": "SEO-описание тайтла dorohedoro-2-2"}},
        [],
        [{"slug": "дорохедоро", "body": "старое"}],
    )
    assert состав["дорохедоро"]["actor"] == "editor/claude-auto/run-A"


def test_снятая_запись_в_состав_не_попадает():
    """Смысл снятия: записи больше нет в составе, а соседи целы."""
    живые = {к: з for к, з in ЖИВЫЕ.items() if к != "ura-mechte"}
    остальные = [{"slug": "дорохедоро", "body": "описание Дорохедоро"}]
    состав = editorial.состав_правок(
        {к: з for к, з in живые.items() if к == "дорохедоро"}, [], остальные)
    assert "ura-mechte" not in состав
    assert состав["дорохедоро"]["fields"]["description"] == "описание Дорохедоро"


def test_снятие_сохраняет_чужие_поля_оставшихся():
    """`name` внесла другая сессия — снятие описания её не касается."""
    живые = {"silsila": ЖИВЫЕ["silsila"]}
    состав = editorial.состав_правок(живые, [], [])
    assert состав["silsila"]["fields"] == {"name": "История наших отношений"}
    assert состав["silsila"]["actor"] == \
        "architect/claude-restore/run-20261011T170500Z"


def test_ветка_снятия_использует_общую_сборку():
    """Два пути с одной задачей обязаны идти одной сборкой.

    Иначе следующая правка состава снова починит только один из них — так и
    вышло 12.10 с публикацией и 18.10 со снятием.
    """
    источник = pathlib.Path(editorial.__file__).read_text(encoding="utf-8")
    начало = источник.index('def _снять_доставку')
    ветка = источник[начало:источник.index("def _доставить", начало)]
    assert "состав_правок(живые, [], остальные)" in ветка
    assert '"fields": {"description": str(i.get("body") or "")}' not in ветка
