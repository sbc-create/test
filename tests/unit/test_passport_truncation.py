"""Паспорт домена не выдаёт обрезанное доказательство за целое.

Повод измеренный, 22.10. Доказательство MOD-81 в очереди
`1lordserials1.online` пополнилось измерением, сборщик паспортов срезал его на
160 символах без всякой отметки, и клетка таблицы кончилась словом
«ПЕРЕМЕРЕНО» — читается как законченное утверждение, которым оно не является.
Паспорт — уровень 3 базы знаний: его читает исполнитель и по этой клетке
решает, что с задачей делать. Молчаливая обрезка здесь — своя мера, которая
врёт (класс 9 `docs/RECURRING_FAILURES.md`), и закрывается она проверкой, а не
аккуратностью.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]

_сп = importlib.util.spec_from_file_location(
    "make_passports", КОРЕНЬ / "automation" / "local" / "make-passports.py")
паспорта = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(паспорта)


def test_короткое_доказательство_не_трогается():
    """Отметка на целом тексте была бы ложью в другую сторону."""
    т = "770 индексируемых страниц вне карты, число устойчиво"
    assert паспорта.укоротить(т) == т
    assert "…" not in паспорта.укоротить(т)


def test_длинное_доказательство_помечено_и_число_названо():
    т = "а" * 400
    и = паспорта.укоротить(т)
    assert "…" in и
    assert "ещё " in и
    assert "в очереди домена" in и


def test_отметка_называет_сколько_недосказано():
    """Число — не украшение: по нему видно, целое там утверждение или треть."""
    т = "слово " * 100            # 600 символов
    и = паспорта.укоротить(т, предел=100)
    хвост = и.split("(ещё ")[1]
    осталось = int(хвост.split(" ")[0])
    видно = len(и.split(" … ")[0])
    assert осталось > 0
    assert видно + осталось == len(" ".join(т.split()))


def test_рез_идёт_по_границе_слова():
    """Обрубленное слово читается как опечатка, а не как обрезка."""
    и = паспорта.укоротить("перемерено " * 40, предел=50)
    видимое = и.split(" … ")[0]
    assert not видимое.endswith("перемер")
    assert видимое.split(" ")[-1] == "перемерено"


def test_перевод_строки_не_ломает_клетку_таблицы():
    """Клетка Markdown одна строка: перевод внутри разорвал бы таблицу."""
    и = паспорта.укоротить("первая строка\nвторая строка")
    assert "\n" not in и
    assert "первая строка вторая строка" == и


def test_граница_предела_точно():
    """Ровно предел — целое; предел плюс один — уже с отметкой."""
    assert паспорта.укоротить("я" * 160) == "я" * 160
    assert "…" in паспорта.укоротить("я" * 161)


def test_настоящее_доказательство_mod81_не_обрывается_на_слове_перемерено():
    """Тот самый случай, ради которого проверка написана."""
    т = ("770 индексируемых страниц вне карты, число устойчиво; страницы к"
         " приёму трафика готовы (проверено с контролем). Патч проверен на"
         " УСТАНОВЛЕННОМ файле. ПЕРЕМЕРЕНО 22.10: пробел закрыт, причина"
         " НЕ закрыта, и это перезапуск, а не исправление")
    и = паспорта.укоротить(т)
    assert not и.rstrip().endswith("ПЕРЕМЕРЕНО")
    assert "…" in и and "ещё " in и
