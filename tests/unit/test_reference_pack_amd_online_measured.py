"""Пакет amd-online несёт замеры, а не описание замеров.

Пакет существовал черновиком с пустыми токенами: доступ к референсу отклонялся
профилем, и записать туда было нечего. Пустой файл тогда был честнее
заполненного. После открытия доступа появилась обратная опасность — заполнить
токены правдоподобными числами и объявить пакет готовым.

Поэтому здесь проверяется не наличие полей, а их происхождение: у каждого
токена есть единица, поверхность, ширина, метод, ссылка на доказательство и
допуск; доказательство разрешается в существующий файл; плейсхолдеров нет.

Отдельно закреплено то, что пакет пока НЕ сертифицирован: диапазоны
совместимости остаются `pending`, а утверждённого алгоритма визуального
сравнения в репозитории нет. Оба факта обязаны быть видимыми, а не
подразумеваемыми: именно их незаметность превращает черновик в «почти готовый»
пакет, на который потом ссылаются как на эталон.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from datetime import datetime
from pathlib import Path

import pytest
import yaml

from factory.paths import PATHS

ПАКЕТ = PATHS.root / "docs" / "reference-packs" / "amd-online"
ТОКЕНЫ = ПАКЕТ / "VISUAL_TOKENS.yaml"
МАНИФЕСТ = ПАКЕТ / "TemplateManifest.yaml"
ИСКЛЮЧЕНИЯ = ПАКЕТ / "EXCLUSIONS.yaml"
ПЛАН = PATHS.root / "config" / "reference-packs" / "reference-pack.amd-online.json"
ДОКАЗАТЕЛЬСТВА = PATHS.root / "artifacts" / "reference-pack-amd-online-01" / "capture-colors"

#: Ширины, обязательные для матрицы снимков.
ШИРИНЫ = {390, 768, 1440}

#: Поверхности, снятые с самого референса.
ПОВЕРХНОСТИ = {"home", "catalog", "collection_hub", "title", "not_found"}

#: Значения, которыми заполняют поле, когда измерить не смогли.
ЗАГЛУШКИ = {"", "TODO", "todo", "pending", "unknown", "n/a", "N/A", "-", "0", None}

#: Цветовые элементы, которых требует компонент `colors` visual-scoring/1.0.0.
ЦВЕТОВЫЕ_ЭЛЕМЕНТЫ = (
    "color_page_background",
    "surface_header_background",
    "surface_card_background",
    "color_text_primary",
    "color_text_secondary",
    "color_accent_background",
    "color_link",
    "color_link_hover",
    "color_border_default",
    "color_focus_ring",
)

#: Нормализованный цвет: только #rrggbb строчными. Название цвета, «rgb(...)»
#: и сокращённая запись сравнимы лишь после преобразования, а преобразование
#: на стороне проверяющего — это лишняя возможность разойтись.
HEX = re.compile(r"^#[0-9a-f]{6}$")

SHA256 = re.compile(r"^[0-9a-f]{64}$")


def цветовые(токены: dict) -> list[dict]:
    return [т for т in токены["tokens"] if т.get("unit") == "hex"]


def ячейка(т: dict) -> tuple:
    return (т["surface"], т["viewport"])


def проблемы_цветового_токена(т: dict) -> list[str]:
    """Что не так с цветовым токеном. Пустой список — токен пригоден к сравнению.

    Функция общая для положительной и отрицательной проверки намеренно: иначе
    негативный тест доказывал бы работоспособность другого кода, чем тот,
    которым проверяется настоящий пакет.
    """
    беды = []
    for поле in ("name", "value", "unit", "surface", "viewport", "method",
                 "evidence", "tolerance", "status", "measured_at_utc", "screenshot_sha256"):
        if not str(т.get(поле, "")).strip():
            беды.append(f"нет поля {поле}")
    if беды:
        return беды
    if not HEX.match(str(т["value"])):
        беды.append(f"значение {т['value']!r} не нормализовано к #rrggbb")
    if т["unit"] != "hex":
        беды.append(f"единица {т['unit']!r} не цветовая")
    if т["surface"] not in ПОВЕРХНОСТИ:
        беды.append(f"поверхность {т['surface']!r} вне матрицы")
    if т["viewport"] not in ШИРИНЫ:
        беды.append(f"ширина {т['viewport']!r} вне матрицы")
    if not SHA256.match(str(т["screenshot_sha256"])):
        беды.append("дайджест снимка не sha256")
    ссылка = str(т["evidence"]).split("#")[0]
    if not ссылка.startswith("artifacts/reference-pack-amd-online-01/capture-colors/"):
        беды.append(f"доказательство вне каталога цветового прогона: {ссылка}")
    if not ссылка.endswith(".json"):
        беды.append(f"доказательство не файл замеров: {ссылка}")
    if f"/tokens/{т['name']}" not in str(т["evidence"]):
        беды.append("ссылка на доказательство не указывает на этот токен")
    try:
        datetime.fromisoformat(str(т["measured_at_utc"]).replace("Z", "+00:00"))
    except ValueError:
        беды.append(f"время замера не разбирается: {т['measured_at_utc']!r}")
    else:
        if not str(т["measured_at_utc"]).endswith("Z"):
            беды.append("время замера не в UTC")
    return беды


def ячейки_без_цвета(токены: list[dict]) -> set:
    """Ячейки surface×viewport, в которых компонент цвета пуст.

    Пустая ячейка — не мелочь: по правилу visual-scoring компонент без единого
    эталонного токена не перераспределяется и не обнуляется молча, а снижает
    полноту evidence и блокирует сертификацию.
    """
    занятые = {ячейка(т) for т in токены if т.get("unit") == "hex"}
    return {(п, ш) for п in ПОВЕРХНОСТИ for ш in ШИРИНЫ} - занятые


def дайджест_исключений(исключения: list[dict]) -> str:
    """Дайджест состава списка исключений по правилу visual-scoring."""
    канон = sorted(json.dumps(и, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
                   for и in исключения)
    return "sha256:" + hashlib.sha256(("[" + ",".join(канон) + "]").encode("utf-8")).hexdigest()


def контракт() -> dict | None:
    """Контракт visual-scoring, если он есть в дереве или указан переменной.

    Контракт живёт в отдельной ветке (PR #81) и в эту не входит. Тест обязан
    честно пропускаться, а не выдумывать веса и пороги: сверять пакет с
    придуманным контрактом хуже, чем не сверять вовсе.
    """
    указан = os.environ.get("FACTORY_VISUAL_SCORING_CONTRACT")
    путь = Path(указан) if указан else (
        PATHS.root / "contracts" / "visual-scoring" / "1.0.0" / "scoring-contract.json")
    if not путь.is_file():
        return None
    return json.loads(путь.read_text(encoding="utf-8"))


def компонент(имя: str, правило: dict) -> str:
    """Компонент токена по правилам самого контракта: первое совпадение."""
    for запись in правило["component_assignment"]["order"]:
        for шаблон in запись["name_patterns"]:
            if re.match(шаблон, имя):
                return запись["component"]
    return "UNASSIGNED"


