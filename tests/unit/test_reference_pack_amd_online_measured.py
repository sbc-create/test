def test_цвет_измерен_в_каждой_ячейке(токены):
    """Компонент цвета обязан иметь эталонный токен в каждой ячейке.

    Иначе кандидат получает ноль за то, чего эталон не измерил, а полнота
    evidence падает ниже 100 и блокирует проверку целиком.
    """
    пусто = ячейки_без_цвета(токены["tokens"])
    assert not пусто, f"цвет не измерен в ячейках: {sorted(пусто)}"
    assert len(цветовые(токены)) >= 100, "цветовых замеров слишком мало для пятнадцати ячеек"


def test_у_каждого_цвета_есть_происхождение(токены):
    """Цвет без метода, доказательства, времени и снимка — это подбор на глаз."""
    беды = {т["name"] + "@" + str(ячейка(т)): проблемы_цветового_токена(т)
            for т in цветовые(токены) if проблемы_цветового_токена(т)}
    assert not беды, f"цветовые токены без происхождения: {list(беды.items())[:3]}"


def test_цветовые_имена_из_объявленного_набора(токены):
    """Имя токена определяет его компонент: произвольное имя уходит в UNASSIGNED."""
    лишние = {т["name"] for т in цветовые(токены)} - set(ЦВЕТОВЫЕ_ЭЛЕМЕНТЫ)
    assert not лишние, f"цветовые токены с неизвестными именами: {sorted(лишние)}"


def test_дайджест_цветового_снимка_записан_для_каждой_ячейки(токены):
    """Снимок цветового прогона сверяется отдельно от геометрического."""
