def test_нестабильное_записано_нестабильным(исключения, токены):
    """Расхождение между проходами — не исключение и не среднее.

    Значение, которое два прохода не подтвердили, не попадает в токены, но и не
    объявляется отсутствующим у эталона: отсутствие и неустойчивость — разные
    утверждения, и путать их нельзя.
    """
    for запись in исключения["unstable_measurements"]:
        assert len(set(запись["observed"])) > 1, "в расхождении обязано быть больше одного значения"
