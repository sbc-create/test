def test_исключения_объявлены_с_причиной_и_provenance(исключения):
    """Исключение без причины и доказательства — это не исключение, а изъятие."""
    assert исключения["declared_before_candidate_comparison"] is True
    for и in исключения["exclusions"]:
        assert set(и) == {"scope", "reason", "provenance", "declared_at"}, (
            f"неожиданный состав полей исключения: {sorted(и)}")
        for поле, значение in и.items():
            assert str(значение).strip(), f"{и['scope']}: пустое поле {поле}"


def test_компонент_colors_не_исключён(исключения, токены):
    """Исключить компонент целиком — значит отменить проверку, а не пройти её.

    Поле `component` перераспределило бы вес цвета на остальные компоненты.
    Пакет обязан не иметь такого поля ни в одном исключении и при этом нести
    цветовые токены во всех ячейках.
    """
    assert исключения["excluded_components"] == []
    for и in исключения["exclusions"]:
        assert "component" not in и, f"исключён компонент целиком: {и}"
        assert "component=" not in str(и["scope"]).lower(), (
            f"исключение объявлено на уровне компонента: {и['scope']}")
    assert not ячейки_без_цвета(токены["tokens"])


def test_исключение_объявлено_только_для_отсутствующего(исключения, токены):
    """Исключать разрешено то, чего у эталона нет, а не то, что неудобно.

    Если для пары «поверхность + элемент» объявлено исключение, токена с таким
    именем на этой поверхности быть не должно — иначе исключение скрывает
    измеренное значение.
    """
    имена = {(т["surface"], т["name"]) for т in цветовые(токены)}
    разобрано = 0
    for и in исключения["exclusions"]:
        область = dict(
            часть.split("=", 1) for часть in
            [ч.strip() for ч in str(и["scope"]).split(";")] if "=" in часть)
        if "element" not in область:
            continue
        разобрано += 1
        ключ = (область["surface"], область["element"])
        assert ключ not in имена, (
            f"{ключ}: элемент исключён, но токен для него в пакете есть")
        assert область["element"] in ЦВЕТОВЫЕ_ЭЛЕМЕНТЫ
    assert разобрано == 4, "ожидались ровно четыре узких цветовых исключения"


