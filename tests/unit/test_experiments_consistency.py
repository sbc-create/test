"""Согласование реестра опытов и замок на неполном реестре.

ПОВОД ИЗМЕРЕННЫЙ, 24.10, и он почти стоил двух опытов. Реестр опытов
разошёлся между рабочими копиями: 2 записи против 8. По неполной копии был
предложен порядок снятия паузы публикации на витринах Lords — а все четыре
витрины Lords оказались канарейкой либо контролем двух действующих опытов с
оценкой 28.10. Поймала это соседняя линия, у которой копия полная.

Проверяется три разных свойства, и путать их нельзя:

1. Объединение не теряет записей и НЕ разрешает конфликт молча.
2. Неполный реестр ЗАПРЕЩАЕТ менять экспериментальную группу (замок умеет и
   запретить, и разрешить — иначе он бесполезен).
3. Запрет АДРЕСЕН: домен вне опытов остаётся свободным, а контроль, названный
   диапазоном ячеек, находится.

Сеть и чужие копии не нужны: пути подставляются.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


def _модуль(имя: str, файл: str):
    п = КОРЕНЬ / "automation" / "local" / файл
    с = importlib.util.spec_from_file_location(имя, п)
    м = importlib.util.module_from_spec(с)
    assert с.loader is not None
    с.loader.exec_module(м)
    return м


СЛИЯНИЕ = _модуль("experiments_merge", "experiments-merge.py")
ЗАМОК = _модуль("experiments_gate", "experiments-consistency-gate.py")

П_А = pathlib.Path("/дом/копия-а/config/experiments.json")
П_Б = pathlib.Path("/дом/копия-б/config/experiments.json")


def _р(**kw) -> dict:
    о = {"experiment_id": "exp-x", "site_id": "cell-01",
         "hypothesis": "г", "primary_metric": "м", "phase": "canary"}
    о.update(kw)
    return о


# --- объединение ------------------------------------------------------------

def test_объединение_не_теряет_запись_своей_копии():
    """Замена копии копией уничтожила бы exp-poster-priority-first-screen."""
    а = {"experiments": [_р(experiment_id="только-у-владельца")]}
    б = {"experiments": [_р(experiment_id="только-у-меня")]}
    слитые, конфликты = СЛИЯНИЕ.объединить([(П_А, а), (П_Б, б)])
    assert sorted(слитые) == ["только-у-владельца", "только-у-меня"]
    assert конфликты == []


def test_конфликт_поля_не_разрешается_молча():
    """Разошлись РЕШЕНИЯ по опыту — это решает не инструмент."""
    а = {"experiments": [_р(phase="canary")]}
    б = {"experiments": [_р(phase="kept")]}
    _, конфликты = СЛИЯНИЕ.объединить([(П_А, а), (П_Б, б)])
    assert len(конфликты) == 1, конфликты
    assert "phase" in конфликты[0]
    assert "canary" in конфликты[0] and "kept" in конфликты[0]


def test_вердикт_и_история_не_затираются_пустым():
    """Пустое поле одной копии не стирает заполненное в другой."""
    а = {"experiments": [_р(verdict="keep", evidence="замер от 20.10")]}
    б = {"experiments": [_р(verdict="", evidence="")]}
    слитые, конфликты = СЛИЯНИЕ.объединить([(П_А, а), (П_Б, б)])
    assert конфликты == []
    assert слитые["exp-x"]["verdict"] == "keep"
    assert слитые["exp-x"]["evidence"] == "замер от 20.10"


def test_дополнение_пустого_поля_конфликтом_не_считается():
    а = {"experiments": [_р()]}
    б = {"experiments": [_р(verdict="continue")]}
    слитые, конфликты = СЛИЯНИЕ.объединить([(П_А, а), (П_Б, б)])
    assert конфликты == []
    assert слитые["exp-x"]["verdict"] == "continue"


def test_своё_поле_для_следов_не_вводится():
    """Схема реестра объявляет additionalProperties: false.

    Ослаблять схему ради удобства согласования нельзя — след идёт в
    `evidence`, где и место происхождению записи.
    """
    с = json.loads((КОРЕНЬ / "schemas" / "experiment-registry.schema.json")
                   .read_text(encoding="utf-8"))
    поля = с["properties"]["experiments"]["items"]
    assert поля["additionalProperties"] is False
    помечено = СЛИЯНИЕ.след(_р(), "копии-б")
    assert set(помечено) <= set(поля["properties"]), set(помечено)
    assert "согласовано" in помечено["evidence"]


def test_след_не_дублируется_при_повторном_согласовании():
    один = СЛИЯНИЕ.след(_р(evidence="замер"), "копии-б")
    два = СЛИЯНИЕ.след(один, "копии-б")
    assert один["evidence"] == два["evidence"]


# --- замок ------------------------------------------------------------------

def test_контроль_названный_диапазоном_ячеек_находится():
    """«контроль — прочие тайтлы lords-05 и lords-01..03».

    Без разбора диапазона замок не увидел бы, что lordserial33.biz (lords-02)
    — контроль, и сказал бы про домен меньше, чем записано. Недообнаружение
    здесь опаснее ложной тревоги: по нему публикуют на контроле.
    """
    найдено = ЗАМОК.ячейки_из_текста(
        "lordserials22.info: 5 283 из 64 508 тайтлов; контроль — прочие тайтлы"
        " lords-05 и lords-01..03")
    assert {"lords-01", "lords-02", "lords-03", "lords-05"} <= найдено, найдено


def test_диапазон_не_захватывает_лишние_ячейки():
    """Отрицательный контроль: lords-01..03 — это не lords-04 и не lords-10."""
    найдено = ЗАМОК.ячейки_из_текста("контроль — lords-01..03")
    assert "lords-04" not in найдено
    assert "lords-10" not in найдено


def test_ограничение_берётся_словами_опыта_а_не_выдумывается():
    """Замок не вправе запрещать шире, чем записано в опыте.

    У exp-country-links-cards записано «разделы стран … не менять» — это не то
    же самое, что «ничего не публиковать на домене». Запрет шире нужного
    останавливает работу там, где опыт её не трогает, и его начинают обходить.
    """
    з = _р(applicability=("выпущено на четырёх сайтах сразу. Контроля внутри"
                          " семейства нет; сравнение — до/после. До оценки"
                          " разделы стран (адреса, карта, тексты) на этих"
                          " сайтах не менять."))
    огр = ЗАМОК.ограничение(з)
    assert "разделы стран" in огр, огр
    assert "не менять" in огр
    assert ЗАМОК.ограничение(_р(applicability="просто описание выборки")) == ""


def test_завершённый_опыт_домен_не_занимает():
    """Фаза kept или rolled_back — измерение окончено, ограничение снято."""
    assert "kept" not in ЗАМОК.ДЕЙСТВУЮТ
    assert "rolled_back" not in ЗАМОК.ДЕЙСТВУЮТ
    assert "canary" in ЗАМОК.ДЕЙСТВУЮТ and "observing" in ЗАМОК.ДЕЙСТВУЮТ


def test_замок_запрещает_на_неполном_реестре(monkeypatch):
    """Главное свойство: неполнота — запрет, а не замечание."""
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "копии", lambda: [П_А, П_Б])
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "прочитать",
                        lambda п: {"experiments": [_р()]} if п == П_А
                        else {"experiments": []})
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "собрать",
                        lambda: ({"experiments": [_р()]}, [], [П_А, П_Б]))
    согл, беда, копий = ЗАМОК.согласованность()
    assert согл is False
    assert копий == 2
    assert any("не хватает записей" in б for б in беда), беда


def test_замок_разрешает_на_согласованном_реестре(monkeypatch):
    """Отрицательный контроль: замок обязан уметь и разрешить."""
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "копии", lambda: [П_А, П_Б])
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "прочитать",
                        lambda п: {"experiments": [_р()]})
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "собрать",
                        lambda: ({"experiments": [_р()]}, [], [П_А, П_Б]))
    согл, беда, копий = ЗАМОК.согласованность()
    assert согл is True, беда
    assert беда == []


def test_одна_копия_это_не_измерено_а_не_разрешение(monkeypatch):
    """Копия одна — сверять нечем; это НЕ повод разрешить."""
    monkeypatch.setattr(ЗАМОК.СЛИЯНИЕ, "копии", lambda: [П_А])
    согл, беда, копий = ЗАМОК.согласованность()
    assert согл is False
    assert копий == 1
    assert ЗАМОК.главное(["--gate"]) == 2
