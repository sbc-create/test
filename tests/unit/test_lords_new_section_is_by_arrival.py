"""Раздел «Новинки» обязан показывать новое, а не повторять каталог.

Текст профиля обещает зрителю вполне определённое: «лента поступлений в том
порядке, в каком они появились в каталоге», «порядок задаёт дата появления, а
не популярность и не оценка, поэтому список меняется каждый день и не
повторяет каталог».

Раздел при этом получал тот же список, что и каталог, и ту же сортировку — по
году выпуска и названию. То есть повторял каталог в точности, ровно то, чего
обещание отрицает. Фильм 2026 года, добавленный полгода назад, стоял выше
вчерашнего поступления 2019-го, а первая страница показывала записи,
появившиеся раньше всех остальных на странице.

Порядок ленты в рендерере был давно — `_by_arrival`, — и применялся к блоку
главной. Разделу он не доставался.

Отдельно о разбиении. Блоки годов группируют страницы по году выпуска; для
ленты поступлений это бессмысленно — она упорядочена по другой величине, и
блоки просто пересобрали бы её обратно в каталог. Лента режется сплошным
срезом.
"""

from __future__ import annotations

import re

import pytest

from factory.lords import fixtures as fx, preview as preview_mod
from factory.lords import render as render_mod

СЛОЙ = "lords-02"  # единственный профиль, объявляющий раздел новинок


@pytest.fixture(scope="module")
def страницы():
    catalog = fx.build_catalog()
    package, _ = preview_mod._package(СЛОЙ)
    return render_mod.render_site(package, catalog=catalog, environ={}).pages


def _слаги(html: str) -> list[str]:
    return re.findall(r'card__title" href="/title/([^/]+)/', html)


class TestПорядокЛенты:
    def test_первая_страница_показывает_самые_свежие_поступления(self, страницы):
        catalog = fx.build_catalog()
        по_слагу = {t.slug: t.created_at for t in catalog.titles}
        видимые = _слаги(страницы["/new/"].body)
        assert видимые, "раздел новинок пуст"
        даты = [по_слагу[s] for s in видимые if по_слагу.get(s)]
        assert даты == sorted(даты, reverse=True), (
            "лента упорядочена не по дате появления: "
            f"{даты[:4]}"
        )
        самая_свежая = max(d for d in по_слагу.values() if d)
        assert даты[0] == самая_свежая, (
            f"вверху ленты {даты[0]}, а самое свежее поступление — {самая_свежая}"
        )

    def test_лента_не_повторяет_каталог(self, страницы):
        assert _слаги(страницы["/new/"].body) != _слаги(страницы["/catalog/"].body), (
            "раздел новинок показывает то же и в том же порядке, что каталог"
        )


class TestРазбиениеЛенты:
    def test_страницы_ленты_заполнены(self, страницы):
        """Блоки годов резали ленту на страницы по три-пять записей."""
        листы = sorted(k for k in страницы if k.startswith("/new/"))
        размеры = [len(_слаги(страницы[k].body)) for k in листы]
        assert размеры, "раздел новинок не отрисован"
        # Все страницы, кроме последней, обязаны быть полными.
        assert len(set(размеры[:-1])) <= 1, f"страницы ленты разной величины: {размеры}"
        if len(размеры) > 1:
            assert размеры[0] > 5, f"на странице ленты {размеры[0]} записей"

    def test_ни_одна_запись_не_потерялась_и_не_повторилась(self, страницы):
        листы = sorted(k for k in страницы if k.startswith("/new/"))
        все = [s for k in листы for s in _слаги(страницы[k].body)]
        assert len(все) == len(set(все)), "запись встречается на двух страницах ленты"
