"""REQ-SEO-SITEMAP-MOVES: «даты в карте верны» и «карта сдвинулась» — разное.

Проверка дат (`sitemap-lastmod-check.py`) полностью исправна на карте, которая
не обновляется: границы соблюдены, подстановки нет, устойчивость при
перезапуске есть — просто все даты трёхдневной давности. Между этими двумя
утверждениями помещается дефект, который не виден ничем другим.

Измерено 2026-10-18: у одиннадцати витрин сети самый свежий `lastmod`
сегодняшний или вчерашний, у 1lordserials1.online — 2026-10-15, при выросшем
каталоге (65 749 → 66 159 позиций по журналу выпусков).

Здесь проверяется ровно то, что делает вывод осмысленным: отставание меряется
ОТНОСИТЕЛЬНО сети, а не относительно «сегодня». Иначе общая задержка доставки
по всем витринам выглядела бы дефектом каждой из них по отдельности — другая
причина, другой владелец, и двенадцать ложных находок вместо одной верной.
"""
from __future__ import annotations

import datetime as dt
import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "sitemap-freshness-sweep.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("sitemap_freshness", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()
СЕГОДНЯ = dt.date(2026, 10, 18)


def _прогон(карты: dict, monkeypatch, домены: list[str]) -> tuple[int, str]:
    """Прогон главной с подменёнными картами: {домен: [даты] | причина}."""
    def даты_карты(домен, ящик, таймаут):
        значение = карты.get(домен)
        if isinstance(значение, str):
            return ([], значение)
        return (list(значение or []), "" if значение else "в карте нет lastmod")
    monkeypatch.setattr(МОД, "даты_карты", даты_карты)
    import io
    import contextlib
    вывод = io.StringIO()
    with contextlib.redirect_stdout(вывод), contextlib.redirect_stderr(вывод):
        код = МОД.главная([*домены, "--today", СЕГОДНЯ.isoformat()])
    return (код, вывод.getvalue())


def test_отставшая_витрина_названа_и_даёт_ненулевой_код(monkeypatch):
    код, вывод = _прогон({
        "1lordserials1.online": ["2026-10-14", "2026-10-15"],
        "lordfilm47.space": ["2026-10-18"],
        "animeg0.site": ["2026-10-17"],
    }, monkeypatch, ["1lordserials1.online", "lordfilm47.space",
                     "animeg0.site"])
    assert код == 1
    assert "ОТСТАЛА НА 3 сут" in вывод
    assert "1lordserials1.online" in вывод.split("карта не сдвинулась")[1]


def test_общая_задержка_сети_не_считается_находкой(monkeypatch):
    """Главное условие вывода, и без него было бы двенадцать ложных находок.

    Если доставка задержалась у всех, карта у всех отстала одинаково. Это
    задержка доставки — другая причина и другой владелец, а не дефект витрины.
    """
    код, вывод = _прогон({
        "lordfilm47.space": ["2026-10-14"],
        "lordserial33.biz": ["2026-10-14"],
        "zonafilm.cc": ["2026-10-14"],
    }, monkeypatch, ["lordfilm47.space", "lordserial33.biz", "zonafilm.cc"])
    assert код == 0
    assert "карта не сдвинулась вслед за каталогом: 0" in вывод
    assert "отстаёт на 4 сут" in вывод, (
        "мера общей задержки обязана быть напечатана, иначе ноль находок "
        "выглядел бы как исправность")


def test_сутки_отставания_не_находка(monkeypatch):
    """Шаг суточной доставки — не дефект; порог ровно на этом и стоит."""
    код, вывод = _прогон({
        "animeg0.site": ["2026-10-17"],
        "zonafilm.cc": ["2026-10-18"],
    }, monkeypatch, ["animeg0.site", "zonafilm.cc"])
    assert код == 0
    assert "ОТСТАЛА" not in вывод


def test_непрочитанная_карта_это_пробел_а_не_исправность(monkeypatch):
    код, вывод = _прогон({
        "lordfilm47.space": ["2026-10-18"],
        "закрытый.site": "карта не получена",
    }, monkeypatch, ["lordfilm47.space", "закрытый.site"])
    assert "НЕ ИЗМЕРЕНО" in вывод
    assert "не измерено: закрытый.site" in вывод
    assert "пробел, а не" in вывод
    assert код == 0, "пробел измерения сам по себе не является находкой"


def test_ни_одной_измеренной_карты_это_код_два(monkeypatch):
    код, вывод = _прогон({"a.site": "карта не получена"}, monkeypatch,
                         ["a.site"])
    assert код == 2, "нечего сравнивать — это не «находок нет»"


def test_отставание_считается_по_самой_свежей_дате():
    """Карта содержит тысячи дат; важна самая свежая, а не первая."""
    даты = ["2026-01-01", "2026-10-15", "2025-07-17"]
    assert МОД.отставание(даты, СЕГОДНЯ) == 3
    assert МОД.отставание(["2026-10-18"], СЕГОДНЯ) == 0


def test_перечень_сети_не_придумывается_инструментом():
    """Домен, которого нет в перечне, называется аргументом.

    Расширять список доменов по своей инициативе запрещено (CLOSED_WORLD), и
    инструмент это соблюдает: перечень закрыт, остальное — через аргументы.
    """
    тело = ПУТЬ.read_text(encoding="utf-8")
    assert "не расширяется по инициативе" in тело
    assert len(МОД.СЕТЬ) == 17
    assert len(set(МОД.СЕТЬ)) == len(МОД.СЕТЬ), "домен назван дважды"
    # Семейство yummy внесено 2026-10-18 после замера: его карты собирает
    # собственный рантайм, и шаг сборки сначала измерен (четыре витрины из
    # пяти — сегодняшние), а потом внесён. Условие проверки прежнее: домен
    # попадает в перечень ИЗМЕРЕНИЕМ, а не по аналогии с соседом.
    assert "ПОСЛЕ замера, а не по аналогии" in тело
    assert "yummyani.site" in МОД.СЕТЬ
