"""Проверки инструмента ворот: выдача отличается от отказа и от невыполнения.

ПОВОД. 24.10 отчёт к 10:00 МСК не вышел. Причина не в данных: ночная работа шла
ВНУТРИ хода сессии, и когда ход закончился в 02:31Z, ворота 03:30Z, 05:15Z и
05:30Z никто не открыл. Продолжение было записано документом — контрольной
точкой с командами и часами, — а документ по времени не срабатывает.

Этот инструмент делает исполняемым то, что было обещанием. Проверки закрепляют
три различимых исхода, потому что путать их и значит повторить ту же ошибку:
выдача состоялась и всё чисто (0), выдача состоялась и есть ОТКАЗ ворот (1),
выдача НЕ состоялась — у каких-то ворот нет исхода (2).
"""
import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ФАЙЛ = КОРЕНЬ / "automation/local/night-gates-run.py"


@pytest.fixture(scope="module")
def модуль():
    с = importlib.util.spec_from_file_location("night_gates", ФАЙЛ)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


def test_инструмент_существует_и_разбирается(модуль):
    assert ФАЙЛ.is_file()
    assert hasattr(модуль, "main") and hasattr(модуль, "прогон")


def test_три_исхода_названы_раздельно():
    """0 — чисто, 1 — отказ ворот, 2 — выдача не состоялась."""
    т = ФАЙЛ.read_text("utf-8")
    assert "ВЫДАЧА ПОЛНАЯ: все ворота открыты без отказов" in т
    assert "ВЫДАЧА ПОЛНАЯ, но есть отказы" in т
    assert "ВЫДАЧА НЕПОЛНАЯ" in т
    # Невыполнение проверяется ДО отказов: иначе отказ скрыл бы отсутствие
    # исхода, и «не измерено» прочиталось бы как результат.
    assert т.index("ВЫДАЧА НЕПОЛНАЯ") < т.index("ВЫДАЧА ПОЛНАЯ, но есть отказы")


def test_отказ_ворот_не_называется_сбоем_инструмента(модуль):
    """Код 1 — это РЕЗУЛЬТАТ ворот, а не поломка: различие записано в коде."""
    т = ФАЙЛ.read_text("utf-8")
    assert "это РЕЗУЛЬТАТ, а не сбой инструмента" in т


def test_невыполненные_ворота_дают_код_2(модуль):
    """Шаг без кода выхода обязан вести к коду 2, а не к успеху."""
    т = ФАЙЛ.read_text("utf-8")
    assert 'невыполненные = [ш for ш in шаги if ш["код"] is None]' in т
    assert "return 2" in т


def test_инструмент_ничего_не_выпускает(модуль):
    """По расписанию можно запускать только то, что не меняет витрины."""
    т = ФАЙЛ.read_text("utf-8")
    for запрещённое in ("factory deploy", "--apply", "git push", "rollback"):
        assert запрещённое not in т, (
            f"инструмент ворот не должен содержать {запрещённое!r}:"
            " по расписанию запускается только чтение")
    assert "Только чтение и замеры" in т


def test_прогон_переживает_отсутствие_инструмента(модуль):
    """Нет команды — это «не выполнено», а не падение всего прогона."""
    итог = модуль.прогон("несуществующий", ["/nonexistent/binary-xyz"], 5)
    assert итог["код"] is None
    assert "инструмента нет" in " ".join(итог["хвост"])


def test_прогон_переживает_превышение_предела(модуль):
    итог = модуль.прогон("долгий", ["python3", "-c",
                                    "import time; time.sleep(5)"], 1)
    assert итог["код"] is None
    assert "превышен предел" in " ".join(итог["хвост"])


def test_ворота_выгрузки_различают_свежесть_и_отсутствие(модуль):
    итог = модуль.ворота_выгрузки()
    assert итог["имя"] == "свежая выгрузка кабинета"
    assert итог["код"] in (0, 1, None)
    хвост = " ".join(итог["хвост"])
    assert ("свежая" in хвост or "УСТАРЕЛА" in хвост
            or "НЕ ИЗМЕРЕНО" in хвост)
