"""Документ владельцу не расходится с измеренным и не зовёт к отменённому.

Два способа, которыми owner-facing документ становится ложным.

Первый — расхождение чисел. Документ пишется руками, готовность считается
рубрикой, и через несколько циклов они говорят разное. Владелец читает
документ, а не рубрику.

Второй — пережившая себя инструкция. Прежняя редакция объясняла, как открыть
локальные витрины через туннель. Порядок приёмки изменён: локальные сборки
приёмкой продукта не являются, витрины остановлены. Документ, зовущий сделать
отменённое, хуже отсутствующего — по нему действуют.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "templates" / "OWNER-STATUS.md"
READINESS = ROOT / "artifacts" / "evidence" / "products" / "product-readiness.json"

sys.path.insert(0, str(ROOT / "scripts"))

ПРОДУКТЫ = ("zona-cinema", "animedia-portal", "basis-video", "yummy")

#: Состояние приёмки → как оно обязано читаться в документе владельца.
#: Берётся из рубрики, а не повторяется здесь: два словаря одного и того же
#: разошлись бы молча, и разошёлся бы именно тот, что реже открывают.
from product_readiness import ЖДЁТ as СОСТОЯНИЯ  # noqa: E402


@pytest.fixture(scope="module")
def текст() -> str:
    return DOC.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def рубрика() -> dict:
    return json.loads(READINESS.read_text(encoding="utf-8"))


#: Заголовок таблицы готовности. Привязка к нему обязательна: в документе
#: несколько таблиц начинаются со столбца «Продукт», и поиск по первой строке
#: с именем продукта возвращал строку таблицы «что прислать» — тест падал на
#: верном документе, а это худший вид проверки.
ЗАГОЛОВОК = "| Продукт | Готовность продукта |"


def _таблица_готовности(текст: str) -> list[str]:
    строки = текст.splitlines()
    начало = next(i for i, s in enumerate(строки) if s.startswith(ЗАГОЛОВОК))
    конец = next(i for i in range(начало + 2, len(строки)) if not строки[i].startswith("|"))
    return строки[начало + 2:конец]


def _строка_продукта(текст: str, продукт: str) -> str:
    for строка in _таблица_готовности(текст):
        if строка.startswith(f"| {продукт} |"):
            return строка
    raise AssertionError(f"в таблице готовности нет строки {продукт}")


class TestЧислаСовпадаютСИзмеренным:
    @pytest.mark.parametrize("продукт", ПРОДУКТЫ)
    def test_готовность_продукта(self, текст, рубрика, продукт):
        измерено = рубрика["products"][продукт]["product_readiness"]
        строка = _строка_продукта(текст, продукт)
        if измерено is None:
            assert "не измерено" in строка, f"{продукт}: ноль вместо «не измерено»"
        else:
            assert f"{измерено} %" in строка, f"{продукт}: в документе не {измерено} %"

    @pytest.mark.parametrize("продукт", ПРОДУКТЫ)
    def test_готовность_интеграции(self, текст, рубрика, продукт):
        измерено = рубрика["products"][продукт]["integration_readiness"]
        assert f"{измерено} %" in _строка_продукта(текст, продукт), продукт

    @pytest.mark.parametrize("продукт", ПРОДУКТЫ)
    def test_приёмка_названа_измеренным_состоянием(self, текст, рубрика, продукт):
        """Ячейка обязана повторять измеренное состояние, а не одну строку.

        Первая редакция требовала дословного «ждёт адреса». Как только владелец
        передал адреса, состояний стало несколько — имя не найдено, нет HTTPS,
        ждёт DNS, — и проверка упала на верном документе. Это не поломка
        документа, а слишком узкая проверка: сверять надо с рубрикой.
        """
        assert рубрика["products"][продукт]["live_acceptance"] is None, (
            f"{продукт}: приёмка выдана числом, хотя не проводилась")
        состояние = рубрика["products"][продукт]["live_state"]
        ожидаемое = СОСТОЯНИЯ.get(состояние)
        assert ожидаемое, f"{продукт}: состояние {состояние} не названо по-русски"
        assert ожидаемое in _строка_продукта(текст, продукт), (
            f"{продукт}: в документе не сказано «{ожидаемое}»")

    def test_ни_одно_состояние_адреса_не_названо_отказом(self, текст, рубрика):
        """DNS, TLS и чужая страница описывают адрес, а не витрину."""
        for продукт in ПРОДУКТЫ:
            строка = _строка_продукта(текст, продукт).lower()
            assert "провал" not in строка and "failed" not in строка, продукт

    def test_средние_совпадают(self, текст, рубрика):
        assert f"**{рубрика['average_product']} %**" in текст
        assert f"**{рубрика['average_integration']} %**" in текст


class TestОтменённогоНеПредлагается:
    def test_нет_призыва_открывать_локальные_витрины(self, текст):
        призывы = re.findall(r"http://127\.0\.0\.1|localhost:\d|ssh -N -L", текст)
        assert призывы == [], f"документ зовёт к отменённому порядку: {призывы}"

    def test_приёмка_названа_боевой(self, текст):
        assert "Приёмка идёт на действующих сайтах" in текст

    def test_названо_что_нужно_от_владельца(self, текст):
        assert "owner.live_urls" in текст
        for продукт in ПРОДУКТЫ:
            assert продукт in текст, продукт


