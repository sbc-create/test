# --- число серий: объявленное против видимого --------------------------------
#
# Повод (19.10): правило требовало, чтобы `numberOfEpisodes` совпадало с ОДНИМ
# из видимых чисел, и на многосезонной карточке это давало ложное замечание:
# разметка объявляет СУММУ по сезонам (41), а страница показывает сезоны
# по отдельности (35, 3, 3). Четыре из четырёх замечаний живого прогона по сети
# были такими. Сумма по сезонам — законное значение numberOfEpisodes для
# TVSeries, поэтому она принимается; расхождение и с числами, и с суммой
# остаётся замечанием.

def test_объявленное_равно_видимому_числу():
    assert МОД.серии_согласованы(12, ["12"]) is True


def test_объявленное_равно_сумме_по_сезонам():
    """Ровно случай animedia: 35 + 3 + 3 = 41."""
    assert МОД.серии_согласованы(41, ["35", "3", "3"]) is True


def test_объявлено_больше_чем_показано():
    """Отрицательный контроль: настоящее расхождение остаётся замечанием."""
    assert МОД.серии_согласованы(127, ["72", "0", "50"]) is False


def test_без_видимых_чисел_не_замечание():
    """Нечего сравнивать — не повод объявлять расхождение."""
    assert МОД.серии_согласованы(41, []) is True


def test_нечисловые_видимые_значения_не_ломают_правило():
    assert МОД.серии_согласованы(41, ["много", "35", "3", "3"]) is True


def test_объявлено_нечислом_сравнение_не_проводится():
    assert МОД.серии_согласованы("много", ["12"]) is True


# --- откуда брать видимое число серий ----------------------------------------
#
# Второй повод того же дня: после исправления суммы осталось одно замечание,
# и оно тоже оказалось ложным. Страница показывает «Сезон 1 · 72 серии ·
# доступно 0 Серии 1–50», текст приводится к нижнему регистру, и шаблон
# `(\d+)\s*сер` ловил «доступно 0 серии» как «0 серий». Сумма становилась 177
# вместо фактических 72+19+12+12+12 = 127, то есть ровно объявленного числа.
#
# Поэтому число сезона читается там, где витрина его печатает: после «сезон N ·».

def test_числа_серий_берутся_из_строки_сезона():
    текст = ("серии сезон 1 · 72 серии · доступно 0 серии 1–50 "
             "сезон 2 · 19 серий 1 2 3 сезон 3 · 12 серий · доступно 0")
    assert МОД.видимые_серии(текст) == [72, 19, 12]


def test_доступно_ноль_числом_серий_не_считается():
    """Отрицательный контроль ровно на пойманную ошибку."""
    текст = "сезон 1 · 72 серии · доступно 0 серии 1–50"
    assert МОД.видимые_серии(текст) == [72]


def test_страница_без_сезонов_даёт_пустой_список():
    assert МОД.видимые_серии("описание без чисел и сезонов") == []


def test_согласованность_считается_по_строкам_сезонов():
    текст = ("сезон 1 · 72 серии · доступно 0 серии 1–50 сезон 2 · 19 серий "
             "сезон 3 · 12 серий сезон 4 · 12 серий сезон 5 · 12 серий")
    видимые = МОД.видимые_серии(текст)
    assert sum(видимые) == 127
    assert МОД.серии_согласованы(127, [str(ч) for ч in видимые]) is True
