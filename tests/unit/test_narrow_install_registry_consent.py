"""Согласие владельца на расхождение реестра: названное, с основанием, разовое.

Узкая установка (`automation/host/install-executor-narrow.sh`, шаг 4) отказывает,
если корневая копия реестра содержит разрешения владельца (`indexing`,
`owner_consent`, `release`), которых в пакете нет: установка перезаписала бы их
молча. Отказ правильный, но без выхода он останавливает выпуск насовсем.

Измерено 2026-10-09: установленная копия (08:10:10Z) держит
`animedia-02.release.hold = true`, пакет — `false` со записью `hold_history`,
в которой лежит основание снятия. Это РАЗНИЦА НАШЕЙ РАБОТЫ, а не потеря
разрешения, и решает её владелец.

Поэтому ключ согласия:

* называет ячейку, поле и ОБА значения (короткими отпечатками) — «принять все
  расхождения» нельзя, иначе согласие перестаёт быть решением;
* привязан к измеренной паре: вчерашняя команда не примет сегодняшнее другое
  расхождение, и это важнее удобства — состояние меняется между запусками;
* для `release` требует записанного основания (`hold_history[].evidence`):
  снятие удержания без основания не принимается даже с согласием, иначе причина
  исчезает вместе с прежним значением.

Проверки гоняют тот же код, что исполняет установка: блок извлекается из
скрипта. Копия логики в тесте проверяла бы копию.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
import subprocess
import sys

import pytest

СКРИПТ = (pathlib.Path(__file__).resolve().parents[2]
          / "automation" / "host" / "install-executor-narrow.sh")

УДЕРЖАНИЕ = {"hold": True, "hold_reason": "отдельная визуальная задача",
             "branch": None}
СНЯТО = {"hold": False, "hold_reason": None, "branch": None,
         "hold_history": [{"reason": "отдельная визуальная задача",
                           "lifted_at": "2026-10-09",
                           "lifted_by": "cell/wt-portable-site-cell-01",
                           "evidence": "ветка позади живого выпуска; ведущая "
                                       "сессия подтвердила отсутствие работы"}]}
СНЯТО_БЕЗ_ОСНОВАНИЯ = {"hold": False, "hold_reason": None, "branch": None}


@pytest.fixture(scope="module")
def блок() -> str:
    """Шаг 4 целиком, как его запускает установка."""
    текст = СКРИПТ.read_text(encoding="utf-8")
    м = re.search(r"<<'PYKEEP'[^\n]*\n(.*?)\nPYKEEP\n", текст, re.S)
    assert м, "в скрипте не найден блок PYKEEP: шаг 4 переписан, тест устарел"
    return м.group(1)


def отпечаток(значение) -> str:
    сырое = json.dumps(значение, ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(сырое.encode("utf-8")).hexdigest()[:12]


def _реестр(путь: pathlib.Path, ячейки: dict[str, dict]) -> pathlib.Path:
    путь.write_text(json.dumps(
        {"cells": [{"site_id": с, **п} for с, п in ячейки.items()]},
        ensure_ascii=False), encoding="utf-8")
    return путь


def запустить(блок: str, tmp_path, установлено: dict, пакет: dict,
              согласие: str = "") -> tuple[int, str]:
    было = _реестр(tmp_path / "installed.json", установлено)
    стало = _реестр(tmp_path / "package.json", пакет)
    из = subprocess.run([sys.executable, "-c", блок, str(было), str(стало), согласие],
                        capture_output=True, text=True)
    return из.returncode, из.stdout + из.stderr


def test_без_расхождений_проходит(блок, tmp_path):
    ячейки = {"animedia-02": {"release": УДЕРЖАНИЕ}}
    код, вывод = запустить(блок, tmp_path, ячейки, ячейки)
    assert код == 0, вывод
    assert "расхождений: 0" in вывод


def test_расхождение_без_согласия_отказ_и_готовый_ключ(блок, tmp_path):
    """Отказ обязан печатать, ЧЕМ его снять: иначе выпуск встаёт насовсем."""
    код, вывод = запустить(блок, tmp_path,
                           {"animedia-02": {"release": УДЕРЖАНИЕ}},
                           {"animedia-02": {"release": СНЯТО}})
    assert код == 1
    ключ = f"animedia-02.release={отпечаток(УДЕРЖАНИЕ)}->{отпечаток(СНЯТО)}"
    assert f"--accept-registry-change {ключ}" in вывод, вывод
    # Оба значения названы: решение принимается по ним, а не по слову «расхождение».
    assert '"hold": true' in вывод and '"hold": false' in вывод


def test_названное_согласие_принимается_и_печатает_основание(блок, tmp_path):
    ключ = f"animedia-02.release={отпечаток(УДЕРЖАНИЕ)}->{отпечаток(СНЯТО)}"
    код, вывод = запустить(блок, tmp_path,
                           {"animedia-02": {"release": УДЕРЖАНИЕ}},
                           {"animedia-02": {"release": СНЯТО}}, ключ)
    assert код == 0, вывод
    assert "принято владельцем" in вывод and "принято владельцем: 1" in вывод
    assert "ветка позади живого выпуска" in вывод, "основание обязано быть в журнале"


def test_согласие_на_другую_пару_не_работает(блок, tmp_path):
    """Команда вчерашнего дня не принимает сегодняшнее другое расхождение."""
    чужой = f"animedia-02.release={отпечаток(УДЕРЖАНИЕ)}->{отпечаток({'hold': False})}"
    код, вывод = запустить(блок, tmp_path,
                           {"animedia-02": {"release": УДЕРЖАНИЕ}},
                           {"animedia-02": {"release": СНЯТО}}, чужой)
    assert код == 1, вывод
    assert "--accept-registry-change" in вывод


def test_снятие_удержания_без_основания_не_принимается(блок, tmp_path):
    """Иначе причина удержания исчезает вместе с прежним значением."""
    ключ = (f"animedia-02.release={отпечаток(УДЕРЖАНИЕ)}"
            f"->{отпечаток(СНЯТО_БЕЗ_ОСНОВАНИЯ)}")
    код, вывод = запустить(блок, tmp_path,
                           {"animedia-02": {"release": УДЕРЖАНИЕ}},
                           {"animedia-02": {"release": СНЯТО_БЕЗ_ОСНОВАНИЯ}}, ключ)
    assert код == 1, вывод
    assert "hold_history" in вывод and "основания" in вывод


def test_наложение_удержания_основания_не_требует(блок, tmp_path):
    """Ставить удержание — безопасная сторона: выпуск останавливается, а не идёт."""
    ключ = f"animedia-02.release={отпечаток(СНЯТО_БЕЗ_ОСНОВАНИЯ)}->{отпечаток(УДЕРЖАНИЕ)}"
    код, вывод = запустить(блок, tmp_path,
                           {"animedia-02": {"release": СНЯТО_БЕЗ_ОСНОВАНИЯ}},
                           {"animedia-02": {"release": УДЕРЖАНИЕ}}, ключ)
    assert код == 0, вывод


def test_исчезнувшая_ячейка_не_принимается_никаким_ключом(блок, tmp_path):
    """Ячейки нет в пакете — установка потеряла бы её разрешения целиком."""
    код, вывод = запустить(блок, tmp_path,
                           {"animedia-02": {"release": УДЕРЖАНИЕ}},
                           {"animedia-01": {"release": УДЕРЖАНИЕ}}, "*")
    assert код == 1, вывод
    assert "ячейки нет в пакете" in вывод


def test_согласие_на_одно_поле_не_распространяется_на_другое(блок, tmp_path):
    режим_было = {"mode": "closed"}
    режим_стало = {"mode": "open"}
    ключ = f"animedia-02.release={отпечаток(УДЕРЖАНИЕ)}->{отпечаток(СНЯТО)}"
    код, вывод = запустить(
        блок, tmp_path,
        {"animedia-02": {"release": УДЕРЖАНИЕ, "indexing": режим_было}},
        {"animedia-02": {"release": СНЯТО, "indexing": режим_стало}}, ключ)
    assert код == 1, вывод
    assert "animedia-02.indexing" in вывод
