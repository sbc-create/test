"""Отчёт шага подробностей обязан быть сериализуемым целиком.

Измерено на живом прогоне 2026-10-09T03:57:43Z: суточное обновление каталога
остановилось записью отчёта —

    TypeError: Object of type EnrichmentReport is not JSON serializable

— потому что в отчёт кладётся сам объект `EnrichmentReport`, а не его разбор.
Следствие было сетевым: снимки каталога не пересобрались НИ У ОДНОЙ витрины,
источники остались от 2026-10-08, и внешне это выглядело как «данные просто не
пришли». Ни один отказ при этом не назывался — шаг писал исключение в свой
журнал, а дальше прогон не доходил до публикации.

Тест держит два утверждения:

* у `EnrichmentReport` есть `as_dict`, и он остаётся источником формы отчёта:
  ручное перечисление полей разошлось бы с ним при первом же новом поле;
* собранный отчёт сериализуется `json.dumps` без `default=`, то есть ровно
  так, как его пишет шаг.
"""

from __future__ import annotations

import json
import pathlib
import re

from factory.lords.detail_enrichment import EnrichmentReport

СКРИПТ = (pathlib.Path(__file__).resolve().parents[2]
          / "automation" / "host" / "nova-detail-backfill.py")


def test_отчёт_обогащения_умеет_разбираться():
    отчёт = EnrichmentReport()
    разбор = отчёт.as_dict()
    assert isinstance(разбор, dict)
    # Сериализуется без помощников: именно так его пишет шаг.
    json.dumps(разбор, ensure_ascii=False)


def test_ни_один_отчёт_обогащения_не_уходит_объектом():
    """Везде, где в итог кладётся отчёт обогащения, стоит РАЗБОР.

    Проверяются ВСЕ вхождения, а не первое: падение случилось именно там, где
    объект остался незамеченным среди соседних разобранных полей.
    """
    т = СКРИПТ.read_text(encoding="utf-8")
    сырые = []
    for м in re.finditer(r'"report":\s*([^\n,}]+)', т):
        выражение = м.group(1).strip()
        # Имя переменной отчёта без разбора — это тот самый случай.
        if re.fullmatch(r"отчёт[\w_]*", выражение):
            сырые.append(выражение)
    assert not сырые, (
        f"в отчёт кладутся объекты без разбора: {сырые}. "
        "EnrichmentReport в json.dumps не уходит — на этом остановилось "
        "суточное обновление каталога 2026-10-09")
    assert "отчёт_идущих.as_dict()" in т, (
        "отчёт продолжающихся обязан попадать разбором: именно он уронил "
        "прогон 2026-10-09T03:57:43Z")


def test_сам_объект_сериализацию_не_проходит():
    """Сторож осмыслен: без разбора `json.dumps` действительно падает."""
    import pytest

    with pytest.raises(TypeError, match="EnrichmentReport"):
        json.dumps({"report": EnrichmentReport()})


def test_собранный_отчёт_шага_сериализуется():
    """Форма отчёта шага — такая же вложенность, как в нём самом."""
    итог = {
        "started_at": "2026-10-09T03:31:24Z",
        "ongoing": {"count": 900, "ttl": 21600,
                    "report": EnrichmentReport().as_dict()},
        "hot": {"since_year": 2024, "count": 600},
        "ring": {"budget": 600, "ttl": 86400},
    }
    # Без `default=`: шаг пишет отчёт именно так.
    строка = json.dumps(итог, ensure_ascii=False, indent=2)
    assert "report" in json.loads(строка)["ongoing"]
