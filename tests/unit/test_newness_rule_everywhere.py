def test_в_шаблонах_не_осталось_сортировки_новинок_по_дате_правки():
    """Сквозной запрет по всем файлам обоих стеков."""
    виновные = []
    файлы = list(NEXT.rglob("*.ts")) + list(NEXT.rglob("*.tsx")) + [
        ХОСТ / "lords-frontend.py", ХОСТ / "collection_contract.py"]
    for ф in файлы:
        if ф.name == "newness.ts" or not ф.is_file():
            continue
        текст = ф.read_text(encoding="utf-8")
        for поле in ПОЛЯ_ЗАГРУЗКИ:
            for строка in текст.splitlines():
                if f"-{поле}" in строка and "sort" in строка.lower():
                    виновные.append(f"{ф.relative_to(КОРЕНЬ)}: {строка.strip()[:90]}")
    assert not виновные, "новинки упорядочены по дате правки:\n  " + "\n  ".join(виновные)


# --- версия выпуска не должна переключать поколение оформления ---------------

def test_версия_шаблона_не_включает_переработанное_оформление_других_семейств():
    """Номер версии в рантайме служит ещё и переключателем оформления.

    `ОФОРМЛЕНИЕ_ПЕРЕРАБОТАННОЕ = ВЕРСИЯ in ПЕРЕРАБОТАНО_С[СЕМЕЙСТВО]`: для
    zona и animedia значения 1.2.0/1.2.1/1.2.2 включают ДРУГОЙ класс вида.
    Поймано предпросмотром: выпуск правила новинок номером 1.2.0 переключил
    оформление animedia, и витрина перестала отдавать карточки вовсе.

    Поэтому версия шаблона Lords не вправе совпадать с номером, который для
    другого семейства означает смену поколения оформления, — пока эти два
    смысла живут в одной строке.
    """
    import json

    версия = json.loads(
        (КОРЕНЬ / "status" / "lords-template-version.json").read_text(encoding="utf-8")
    )["version"]
    текст = (ХОСТ / "lords-frontend.py").read_text(encoding="utf-8")
    кусок = текст[текст.index("ПЕРЕРАБОТАНО_С = {"):]
    кусок = кусок[:кусок.index("}\n")]
    переключатели = set(re.findall(r'ОФОРМЛЕНИЕ_1_2[_0-9]*', кусок))
    значения = {
        имя: re.search(rf"^{имя} = \"([^\"]+)\"", текст, re.M).group(1)
        for имя in переключатели
    }
    assert версия not in значения.values(), (
        f"версия шаблона {версия} совпадает с переключателем поколения "
        f"оформления ({значения}): выпуск Lords переключит оформление другого "
        f"семейства заодно. Возьмите номер, которого в этом перечне нет, либо "
        f"разведите два смысла по разным полям.")

def test_версия_шаблона_опознаётся_рантаймом():
    """Версия, которой нет в перечне оформления, откатывает витрину молча.

    `ОФОРМЛЕНИЕ_НОВОЕ = ВЕРСИЯ in ОФОРМЛЕНИЕ_ВЕРСИИ` — это ПЕРЕЧЕНЬ, а не
    сравнение. Выпуск 1.1.1 без строки в перечне отдавал страницы прежней
    раскладкой, и правило новинок до раздела не доходило: предпросмотр показал
    60 архивных карточек из 60. Снаружи это выглядит как «правило не работает»,
    хотя правило на месте, а до него не доходит управление.
    """
    import json

    версия = json.loads(
        (КОРЕНЬ / "status" / "lords-template-version.json").read_text(encoding="utf-8")
    )["version"]
    текст = (ХОСТ / "lords-frontend.py").read_text(encoding="utf-8")
    кусок = текст[текст.index("ОФОРМЛЕНИЕ_ВЕРСИИ = {"):]
    кусок = кусок[:кусок.index("}")]
    имена = re.findall(r"ОФОРМЛЕНИЕ_1[_0-9]*", кусок)
    значения = {
        re.search(rf'^{имя} = "([^"]+)"', текст, re.M).group(1) for имя in имена
    }
    assert версия in значения, (
        f"версия шаблона {версия} не объявлена в ОФОРМЛЕНИЕ_ВЕРСИИ ({sorted(значения)}): "
        f"витрина откатится к прежней раскладке целиком, и правило новинок до "
        f"страниц не дойдёт")
