"""Правило новинок действует во ВСЕХ шаблонах фабрики, а не в одном Lords.

Дефект был общим: блоки новинок отбирались по дате попадания записи в нашу
базу. В рантайме семейств это `published_at` снимка, в Next-шаблоне —
сортировка `-updatedAt`. Исправление в одном стеке исправлением фабрики не
является, поэтому проверка смотрит на ВСЕ стеки шаблонов разом и падает, если
появится новый с тем же дефектом.

Проверка исходного текста, а не поведения, выбрана осознанно: стеки написаны
на разных языках и поднимаются по-разному (Next-шаблон требует установленных
зависимостей и базы), а запрет обязан действовать в обязательном прогоне, где
ни того, ни другого нет. Поведение каждого стека проверяется отдельно:
`test_lords_newness_rule.py` и предпросмотры экземпляров.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ХОСТ = КОРЕНЬ / "automation" / "host"
NEXT = КОРЕНЬ / "blueprints" / "payload-next-multisite" / "app" / "src"

#: Поля, которые говорят о НАШЕЙ базе, а не о выходе произведения.
ПОЛЯ_ЗАГРУЗКИ = ("updatedAt", "createdAt")


def test_все_стеки_шаблонов_известны_проверке():
    """Новый стек шаблонов не должен появиться мимо этого правила."""
    стеки = sorted(p.name for p in (КОРЕНЬ / "blueprints").iterdir() if p.is_dir())
    assert стеки == ["dle20", "lords", "payload-next-multisite"], (
        f"состав стеков шаблонов изменился: {стеки}. Новый стек обязан либо "
        f"получить правило новинок, либо быть назван здесь как не имеющий "
        f"блоков новинок — молча он пройти не может.")


