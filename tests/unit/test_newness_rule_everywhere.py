def test_next_шаблон_не_сортирует_новинки_по_дате_правки():
    """`-updatedAt` как умолчание выдачи тайтлов — это и был дефект."""
    текст = (NEXT / "lib" / "content.ts").read_text(encoding="utf-8")
    тело = текст[текст.index("export const listTenantTitles"):]
    тело = тело[:тело.index("export const getTenantTitle")]
    for поле in ПОЛЯ_ЗАГРУЗКИ:
        assert f"'-{поле}'" not in тело, (
            f"выдача тайтлов упорядочена по {поле} — это время правки записи в "
            f"нашей базе, а не дата выхода")
    assert "freshOnly" in тело, "у выдачи тайтлов нет отбора новинок"
    assert "freshTitlesWhere" in тело, "отбор новинок не применяется в запросе"


