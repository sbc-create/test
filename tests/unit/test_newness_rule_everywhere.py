def test_раздел_новинок_отбирает_до_предела():
    """`/new` обязан применить правило ДО сортировки и среза."""
    текст = (ХОСТ / "lords-frontend.py").read_text(encoding="utf-8")
    кусок = текст[текст.index('if раздел == "/new":'):]
