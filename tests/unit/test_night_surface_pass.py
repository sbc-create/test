"""Проход по поверхности: как складываются исходы пяти мер в один код.

Главное требование: НЕ ИЗМЕРЕНО весит больше найденного дефекта. Дефект —
ответ о сети, неизмеренное — вопрос к самому проходу, и смешивать их нельзя.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "night-surface-pass.py"

спец = importlib.util.spec_from_file_location("night_surface_pass", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


@pytest.mark.parametrize("код,ожидание", [
    (0, "чисто"), (1, "найден дефект"), (2, "НЕ ИЗМЕРЕНО"),
    (3, "СБОЙ"), (127, "СБОЙ"), (-9, "СБОЙ")])
def test_код_меры_читается_однозначно(код, ожидание):
    assert модуль.исход_по_коду(код) == ожидание


def test_всё_чисто_даёт_ноль():
    assert модуль.итоговый_код({"a": модуль.ЧИСТО, "b": модуль.ЧИСТО}) == 0


def test_дефект_даёт_единицу():
    assert модуль.итоговый_код({"a": модуль.ЧИСТО, "b": модуль.ДЕФЕКТ}) == 1


def test_неизмеренное_перевешивает_дефект():
    # Иначе проход с одной сломанной мерой выглядел бы как обычная находка.
    assert модуль.итоговый_код(
        {"a": модуль.ДЕФЕКТ, "b": модуль.НЕ_ИЗМЕРЕНО}) == 2


def test_сбой_меры_тоже_перевешивает():
    assert модуль.итоговый_код({"a": модуль.ДЕФЕКТ, "b": модуль.СБОЙ}) == 2


def test_пустой_набор_не_выдаётся_за_чистый():
    # Ни одной меры не запущено — это не «всё хорошо».
    assert модуль.итоговый_код({}) == 2


def test_все_меры_названы_существующими_скриптами():
    for имя, (скрипт, _, предел) in модуль.МЕРЫ.items():
        файл = КОРЕНЬ / "automation" / "local" / скрипт
        assert файл.is_file(), f"{имя}: нет {скрипт}"
        assert предел > 0


def test_у_каждой_меры_есть_json():
    # Без `--json` вывод не артефакт, и сводка потеряет данные.
    for имя, (_, аргументы, _) in модуль.МЕРЫ.items():
        assert "--json" in аргументы, имя


def test_пределы_не_меньше_измеренной_длительности():
    # Мобильная отрисовка поднимает браузер на десять страниц — самая долгая.
    assert модуль.МЕРЫ["mobile"][2] >= 600
    assert модуль.МЕРЫ["css"][2] >= 120


def test_имена_мер_совпадают_с_выбором_на_входе():
    # `--only` принимает ровно те имена, что есть в таблице мер.
    assert set(модуль.МЕРЫ) == {"robots", "mobile", "sitemap", "css",
                                "descriptions", "episodes"}


def test_у_меры_серий_предел_выше_остальных():
    # Она читает три части карты по 50 000 адресов и открывает страницы работ
    # по одной: на 21.10 это 24 работы и около шести минут.
    assert модуль.МЕРЫ["episodes"][2] >= 900
    assert модуль.МЕРЫ["episodes"][2] > модуль.МЕРЫ["mobile"][2]
