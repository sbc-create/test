"""Разрыв до цели считается по РЕАЛЬНЫМ визитам, а не «без роботов Метрики».

Повод измеренный, 23.10. Цель владельца — 5 000 реальных визитов в сутки.
`traffic-gap.py` брал суточный ряд `daily_users`, у которого единственная
размерность `ym:s:isRobot`: он снимает только то, что роботом назвала сама
Метрика. Автоматизацию она роботом не называет, и на yummyani.site это
53 492 визита за 14 суток (HeadlessChrome, отказы 97,9 %, время 2,1 с).
Инструмент объявлял 6 538,5 визита в сутки и «цель достигнута», тогда как
реальных было 2 717,6 — то есть разрыв 2 282, а не ноль.

Проверки опровержимы: если исключение автоматизации убрать, обе падают.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


def _модуль(имя: str, файл: str):
    путь = КОРЕНЬ / "automation" / "local" / файл
    спец = importlib.util.spec_from_file_location(имя, путь)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


РАЗРЫВ = _модуль("traffic_gap", "traffic-gap.py")


def _строка(дата: str, браузер: str, робот: str, визиты: float) -> dict:
    """Строка профиля в том же виде, в каком её отдаёт кабинет."""
    return {
        "dimensions": [{"name": дата}, {"name": "Direct traffic"},
                       {"name": "PC"}, {"name": браузер}, {"name": робот}],
        "metrics": [визиты, 50.0, 1.2, 100.0],
    }


ПРОФИЛЬ = {"value": [
    _строка("2026-10-20", "Yandex Browser", "People", 100.0),
    _строка("2026-10-20", "HeadlessChrome", "People", 900.0),
    _строка("2026-10-20", "Chrome Mobile", "Robots", 300.0),
    _строка("2026-10-21", "Opera", "People", 200.0),
    _строка("2026-10-21", "Chrome Headless", "People", 700.0),
]}


def test_автоматизация_в_реальные_визиты_не_попадает():
    реальные, исключённые = РАЗРЫВ.ряд_без_автоматизации(ПРОФИЛЬ)
    assert реальные == {"2026-10-20": 100.0, "2026-10-21": 200.0}, реальные
    assert исключённые == {"2026-10-20": 1200.0, "2026-10-21": 700.0}, (
        исключённые)


def test_порядок_слов_в_названии_браузера_не_спасает_автоматизацию():
    """«Chrome Headless» и «HeadlessChrome» — одно и то же.

    Отдельной проверкой потому, что перечень с одним написанием пропустил бы
    второй вариант, а признак «headless» в названии ловит оба.
    """
    реальные, _ = РАЗРЫВ.ряд_без_автоматизации(
        {"value": [_строка("2026-10-21", "Chrome Headless", "People", 700.0)]})
    assert реальные == {}, реальные


def test_ряд_без_профиля_не_подменяется_рядом_без_роботов():
    """Нет профиля по суткам — домен идёт как НЕ ИЗМЕРЕННЫЙ.

    Подмена показала бы цель достигнутой там, где она не достигнута: ряд
    `daily_users` автоматизацию не отделяет.
    """
    люди, _ = РАЗРЫВ.ряд_без_автоматизации({})
    assert люди == {}


def test_закрытый_список_автоматизации_назван_и_не_пуст():
    """«Автоматизация» без перечня — догадка, а не замер.

    Список живёт в traffic-segments.py, и разрыв берёт его оттуда, а не
    держит вторую копию: две копии разошлись бы, и «реальные визиты» у двух
    инструментов стали бы разными числами с одним названием.
    """
    сегм = РАЗРЫВ._сегменты_модуль()
    assert len(сегм.АВТОМАТИЗАЦИЯ) >= 5
    assert "headlesschrome" in сегм.АВТОМАТИЗАЦИЯ
    assert сегм.автоматизация("HeadlessChrome") is True
    assert сегм.автоматизация("Yandex Browser") is False
