"""Режим подхвата в реестре обязан соответствовать тому, что умеет рантайм.

`factory/cell/runtime.py` отвечает производителю содержимого:

    нужен_перезапуск = (reload != "mtime")

То есть ячейка, объявившая `mtime`, говорит доставке: «перезапуск не нужен, я
перечитаю снимок сама». Если рантайм этого не умеет, новый снимок ляжет на
диск и не будет загружен НИКОГДА — витрина продолжит отдавать прежний каталог,
не падая и ничего не сообщая.

Это ровно тот дефект, против которого построено доказательство обновления
содержимого: файл на диске обновления сайта не доказывает. Здесь он проверяется
с другой стороны — со стороны объявления.

Ядро шаблона по mtime НЕ перечитывает: `Подробности.mtime` ставится один раз
при загрузке и нигде не сравнивается, он нужен согласованию доступности. Своё
перечитывание есть только у наложений отдельных сайтов (`overlay/freshness.py`
у 1lordserials1.online), и в ядро оно не переносилось — причина и цена в
`docs/LORDS_TEMPLATE_ROLLOUT.md`.

Значит ячейка, которая исполняет ТОЛЬКО шаблон, обязана объявлять `restart`.
`factory/cell/newsite.py` так и пишет. Проверка ловит случай, когда объявление
переставили в `mtime` после создания.
"""
from __future__ import annotations

import json
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
РАНТАЙМ = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"

#: Ячейки, у которых перечитывание даёт СВОЙ слой поверх шаблона. Для них
#: `mtime` — правда, и перечень именно поимённый: «кажется, у него есть
#: наложение» режимом доставки управлять не может.
#:
#: lords-05 попал сюда не по предположению, а по измерению: в выпущенном
#: релизе (`/srv/lordserials22-info/current/src/`) лежит
#: `lords_snapshot_reload.py`, и загруженная ревизия у него сегодняшняя при
#: процессе, запущенном двое суток назад. Я сначала ошибочно перевёл его в
#: `restart` — для выпущенной витрины с этим наложением перезапуск не лишний, а
#: вреден: он замерен и давал 502 у nginx четыре раза в час.
С_НАЛОЖЕНИЕМ = frozenset({"lords-01", "lords-02", "lords-03", "lords-05"})


def _ядро_перечитывает() -> bool:
    """Умеет ли ядро шаблона перечитывать снимок без перезапуска."""
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    # Перечитывание — это СРАВНЕНИЕ сохранённого mtime с текущим. Одно
    # присваивание при загрузке перечитыванием не является.
    return "self.mtime !=" in текст or "self.mtime <" in текст or "!= self.mtime" in текст


def test_ядро_шаблона_по_mtime_не_перечитывает():
    """Фиксирует предпосылку. Если ядро научится — проверку ниже надо снять."""
    assert not _ядро_перечитывает(), (
        "ядро научилось перечитывать снимок по mtime — тогда объявление "
        "`reload: mtime` стало правдой и проверку ниже нужно пересмотреть")


def test_ячейка_без_наложения_не_объявляет_mtime():
    if _ядро_перечитывает():
        return
    реестр = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    лгут = []
    for ячейка in реестр["cells"]:
        site = str(ячейка.get("site_id") or "")
        семейство = ((ячейка.get("template") or {}).get("family")
                     or (ячейка.get("template") or {}).get("template_id") or "")
        if not str(семейство).startswith("lords"):
            continue
        if site in С_НАЛОЖЕНИЕМ:
            continue
        если = (ячейка.get("runtime") or {}).get("reload")
        if если == "mtime":
            лгут.append(f"{site} ({ячейка.get('domain')})")
    assert not лгут, (
        "ячейки объявляют `reload: mtime`, но исполняют только шаблон, а он по "
        f"mtime не перечитывает: {лгут}. Доставка пропустит перезапуск, новый "
        "снимок ляжет на диск и не будет загружен никогда — витрина навсегда "
        "останется на прежнем каталоге, не падая и ничего не сообщая. "
        "Либо `restart` в реестре, либо перечитывание в ядре.")


def test_newsite_объявляет_перезапуск():
    """Генератор обязан писать то, что шаблон умеет."""
    текст = (КОРЕНЬ / "factory" / "cell" / "newsite.py").read_text(encoding="utf-8")
    assert '"reload": "restart"' in текст, (
        "newsite перестал объявлять перезапуск: новый сайт получит обещание "
        "подхвата, которого шаблон не исполняет")
