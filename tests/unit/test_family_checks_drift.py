"""Наборы проверок у родственных ячеек: три разряда, которые легко слить в один.

Инструмент написан после регрессии 12.10 на `an1mego.site`: правка снесла со
страниц «Тип», «Эпизоды», «Статус», а поймала её проверка `data_chain`, которой
у `an1mego` НЕТ, зато есть у `an1meg0`. На витрине, куда правка пошла, защиты не
было.

Здесь закреплены именно разряды, потому что каждый неверный разряд я успел
сделать и откатить:

* первая редакция объявляла дефектом любое отсутствие шаблонной проверки и дала
  69 «потерь» — но набор шаблонов фабрики не универсальная основа, ячейки несут
  относящееся к ним подмножество;
* вторая объявила потерей `no_secrets` у `zonafilm-cc` — вывод, звучащий как
  дыра в безопасности. Фактически там есть `no_data_or_secrets`: защита не
  отсутствует, она слабее, и это другой вывод и другая работа.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "family-checks-drift.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("family_checks_drift",
                                                  ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    sys.modules["family_checks_drift"] = м
    спец.loader.exec_module(м)
    return м


фд = _модуль()
ШАБЛОН = {"compiles", "no_secrets", "entrypoint_present", "verify_pins"}


# ------------------------------------------------------------------- разряды
def test_проверка_с_меткой_ячейки_расходится_ожидаемо():
    """`lords02_history` писалась для одной витрины — расхождение нормально."""
    assert фд.разряд("lords02_history", ШАБЛОН) == фд.СВОЯ_ПРОВЕРКА
    assert фд.разряд("zona03_feeds", ШАБЛОН) == фд.СВОЯ_ПРОВЕРКА


def test_шаблонность_это_мера_тяжести_а_не_разряд():
    """Разряд один, а пометка про шаблон добавляется к нему.

    Отдельный разряд «потеря шаблона» и дал первую неверную редакцию: он
    объявлял дефектом то, чем семейство просто не пользуется.
    """
    свой = фд.разряд("compiles", ШАБЛОН)
    чужой = фд.разряд("ratings_visible", ШАБЛОН)
    assert свой.startswith(фд.БЕЗ_ЗАЩИТЫ) and "шаблон фабрики" in свой
    assert чужой == фд.БЕЗ_ЗАЩИТЫ


# -------------------------------------------------------------- переименование
def test_переименованная_проверка_находится():
    """`no_secrets` и `no_data_or_secrets` — одна забота под двумя именами.

    Объявить первое потерянным значит отправить владельца искать дыру в
    безопасности там, где её нет.
    """
    свои = {"no_data_or_secrets", "contact_email", "home_h1"}
    assert фд.похожая("no_secrets", свои) == "no_data_or_secrets"


def test_служебные_слова_в_сходство_не_идут():
    """Иначе по `no` и `check` совпало бы всё со всем.

    `no_secrets` и `no_floating_pins` делят только слово `no`, и считать их
    одной заботой нельзя.
    """
    assert фд.похожая("no_secrets", {"no_floating_pins"}) == ""
    assert фд.слова("no_check_present") == set()


def test_общее_значимое_слово_даёт_сходство():
    assert фд.похожая("verify_pins", {"no_floating_pins"}) == "no_floating_pins"


def test_ничего_похожего_это_пустая_строка():
    assert фд.похожая("compiles", {"contact_email", "home_h1"}) == ""


# --------------------------------------------------------------- наборы ячеек
def test_набор_читается_из_каталога_проверок(tmp_path):
    ячейка = tmp_path / "ячейка"
    (ячейка / "checks").mkdir(parents=True)
    (ячейка / "checks" / "compiles.py").write_text("", encoding="utf-8")
    (ячейка / "checks" / "__init__.py").write_text("", encoding="utf-8")
    (ячейка / "checks" / "run.sh").write_text("", encoding="utf-8")
    # `__init__` и не-питон в набор не идут: это не проверки.
    assert фд.набор(ячейка) == {"compiles"}


def test_без_каталога_проверок_это_none(tmp_path):
    """None отличается от пустого набора: ячейку не измеряли, а не «пусто»."""
    ячейка = tmp_path / "без-проверок"
    ячейка.mkdir()
    assert фд.набор(ячейка) is None


def test_без_шаблонов_инструмент_отказывает(tmp_path, capsys):
    """Сравнивать с пустым шаблоном нельзя: всё стало бы «не шаблонным»."""
    код = фд.главное(["--templates", str(tmp_path / "нет"),
                      "--repos", str(tmp_path)])
    assert код == 2
    assert "предел измерения" in capsys.readouterr().err


def test_живой_прогон_называет_адресно():
    """На настоящих ячейках вывод обязан называть, У КОГО проверки нет."""
    if not фд.ЯЧЕЙКИ.is_dir():
        import pytest
        pytest.skip("рабочих копий ячеек на машине нет")
    import io
    from contextlib import redirect_stdout
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        код = фд.главное([])
    вывод = буфер.getvalue()
    assert код in (0, 1, 3), код
    assert "нет у:" in вывод, вывод
    # Предел измерения обязан быть назван, а не умолчан.
    assert "сравнение идёт по ИМЕНАМ" in вывод
