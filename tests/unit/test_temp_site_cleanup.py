"""Уборка остатков не трогает временные сайты ЖИВОГО параллельного прогона.

Повод доказан детерминированно 22.10, а не выведен из рассуждения: создан
`sites/tmp-proof11`, запущен посторонний короткий прогон
(`pytest tests/unit/test_domain_queues.py`) — каталог удалён. Прежняя уборка
сносила ВСЕ `sites/tmp-*` при старте любого процесса pytest, то есть любой
второй прогон отнимал у первого его данные.

Этим и объяснялся единственный провал полного прогона 22.10:
`test_authorization.py::test_staging_success_is_not_production_permission`
получил `BLOCKED_INPUT` вместо `BUILT`. В одиночку тест проходит — и это не
«мигание»: причина названа, воспроизводится и закрыта условием по возрасту.

Уборка нужна по-прежнему: после SIGTERM фикстура временного сайта свою уборку
не выполняет, а нулевой `package.yaml` валит посторонние тесты сообщением про
NoneType. Поэтому проверяется именно ГРАНИЦА: остывшее сносится, живое нет.
"""
from __future__ import annotations

import importlib.util
import pathlib

# `conftest.py` лежит в tests/, а при `--import-mode=importlib` этот каталог в
# sys.path не попадает. Загружаем файл по пути: проверяется ИМЕННО та уборка,
# которая работает в прогоне, а не её копия.
_КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "factory_conftest", _КОРЕНЬ / "tests" / "conftest.py")
conftest = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(conftest)


#: Опорное «сейчас» задаётся явно и НЕ берётся из часов внутри проверки.
#: Иначе между созданием каталога и сравнением проходят миллисекунды, и
#: граничный случай решается не условием, а скоростью машины — это уже
#: подводило (класс 10 `docs/RECURRING_FAILURES.md`: проверка зависит от часа
#: запуска).
СЕЙЧАС = 1_800_000_000.0


def _каталог(tmp_path: pathlib.Path, имя: str, возраст_с: float,
             сейчас: float = СЕЙЧАС):
    import os
    п = tmp_path / имя
    п.mkdir()
    когда = сейчас - возраст_с
    os.utime(п, (когда, когда))
    return п


def test_живой_каталог_не_сносится(tmp_path):
    """Созданный секунду назад каталог принадлежит идущему прогону."""
    живой = _каталог(tmp_path, "tmp-живой", 1.0)
    assert conftest._остывшие_остатки([живой], СЕЙЧАС) == []


def test_остывший_каталог_сносится(tmp_path):
    труп = _каталог(tmp_path, "tmp-труп", conftest.ОСТЫЛ_ЧЕРЕЗ_С + 60)
    assert conftest._остывшие_остатки([труп], СЕЙЧАС) == [труп]


def test_граница_возраста_точная(tmp_path):
    ровно = _каталог(tmp_path, "tmp-ровно", conftest.ОСТЫЛ_ЧЕРЕЗ_С)
    чуть_моложе = _каталог(tmp_path, "tmp-моложе",
                           conftest.ОСТЫЛ_ЧЕРЕЗ_С - 5)
    остывшие = conftest._остывшие_остатки([ровно, чуть_моложе], СЕЙЧАС)
    assert ровно in остывшие
    assert чуть_моложе not in остывшие


def test_порог_больше_длительности_полного_прогона():
    """Полный прогон идёт около 15 минут; порог обязан быть больше.

    Иначе уборка снесёт каталог прогона, который ещё идёт, — то есть вернёт
    ровно ту ошибку, ради которой проверка написана.
    """
    assert conftest.ОСТЫЛ_ЧЕРЕЗ_С >= 1200


def test_исчезнувший_каталог_не_ломает_уборку(tmp_path):
    """Параллельный прогон мог убрать его сам между glob и stat."""
    нет_такого = tmp_path / "tmp-исчез"
    assert conftest._остывшие_остатки([нет_такого], СЕЙЧАС) == []


def test_пустой_список_допустим():
    assert conftest._остывшие_остатки([], СЕЙЧАС) == []


def test_несколько_каталогов_разбираются_порознь(tmp_path):
    """Один остывший не тянет за собой живых — и наоборот."""
    живой = _каталог(tmp_path, "tmp-a", 2.0)
    труп = _каталог(tmp_path, "tmp-b", conftest.ОСТЫЛ_ЧЕРЕЗ_С * 2)
    ещё_живой = _каталог(tmp_path, "tmp-c", 30.0)
    остывшие = conftest._остывшие_остатки([живой, труп, ещё_живой],
                                          СЕЙЧАС)
    assert остывшие == [труп]
