def test_первый_экран_грузится_сразу_а_нижние_блоки_нет(страница):
    посл = re.findall(r'<img[^>]*data-poster[^>]*>', страница)
    assert len(посл) > 4, "постеров на главной слишком мало для проверки"
    срочные = [и for и in посл if 'fetchpriority="high"' in и]
    отложенные = [и for и in посл if 'loading="lazy"' in и]
    assert срочные, "первый экран ждёт отсрочки"
    assert len(срочные) <= 4, (
        f"высокий приоритет у {len(срочные)} постеров — он отбирает полосу "
        "у того же первого экрана")
    assert отложенные, "нижние блоки получили высокий приоритет"
    assert not [и for и in срочные if 'loading="lazy"' in и]


def test_отсутствующий_постер_не_даёт_битого_img(модуль, tmp_path, monkeypatch):
    с = h.Стенд(tmp_path)
    записи = [h.запись(f"t{i}", title=f"Тайтл {i}", poster="") for i in range(6)]
    с.записать_каталог(записи)
    с.записать_подробности([h.подробность(з["slug"]) for з in записи])
    с.записать_плеер()
    м = h.загрузить(с, monkeypatch)
    try:
        страница = h.вид(м).главная()
        сетка = страница.split('data-card-grid', 1)[1].split("</div>", 1)[0]
        assert "<img" not in сетка
        assert 'class="c__none"' in сетка, "места под постер нет — раскладка прыгнет"
    finally:
        h.выгрузить(м)


