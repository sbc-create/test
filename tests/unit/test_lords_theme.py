def test_в_карточке_видно_название_и_подпись_источника_оценки(страница):
    assert 'class="c__t"' in страница, "название карточки не выведено текстом"
    # Оценка выводится только с именем источника: «7.8» без подписи не
    # говорит, чья это оценка, и на витрине уже выдавалась за зрительскую.
    подписи = re.findall(r'<span class="c__(?:kp|imdb)">(КП|IMDb)<i>', страница)
    for подпись in подписи:
        assert подпись in ("КП", "IMDb")
