"""Две темы, сохранение выбора, читаемость каждой пары и приоритет постеров.

Переключатель когда-то существовал и был убран, и в рантайме это записано как
решение: «светлая ветка задавала только часть переменных, и именно из неё
выходил нечитаемый текст». Причина была не в переключателе, а в том, что
палитра подставлялась в таблицу стилей ЛИТЕРАЛАМИ: вторая тема требовала
перечислить каждую поверхность вручную — что и пришлось сделать двум сайтам по
отдельности.

С переменными `:root` обе палитры объявлены целиком, и читаемость проверяется
числом, а не на глаз. Формула контраста — WCAG 2.1:

    (L_светлее + 0.05) / (L_темнее + 0.05),

где L — относительная яркость sRGB. Порог 4.5:1 — обычный текст AA.
"""
from __future__ import annotations

import re

import lords_runtime_harness as h
import pytest

# --- контраст ---------------------------------------------------------------

def _яркость(цвет: str) -> float:
    ц = цвет.lstrip("#")
    каналы = [int(ц[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    линейные = [к / 12.92 if к <= 0.04045 else ((к + 0.055) / 1.055) ** 2.4
                for к in каналы]
    return 0.2126 * линейные[0] + 0.7152 * линейные[1] + 0.0722 * линейные[2]


def контраст(a: str, b: str) -> float:
    ya, yb = _яркость(a), _яркость(b)
    светлее, темнее = max(ya, yb), min(ya, yb)
    return (светлее + 0.05) / (темнее + 0.05)


#: Пары «текст на поверхности», которые обязаны читаться в каждой теме.
#: Именно они и отказали в прошлый раз, поэтому перечислены поимённо.
ПАРЫ_ТЕКСТА = (
    ("ink", "sheet"), ("ink", "card"),
    ("dim", "card"), ("mute", "card"),
    ("accdk", "card"), ("accdk", "sheet"),
    ("onbar", "bar"),
)
#: Акцент как ЗАЛИВКА — другая роль: белый текст поверх него.
ПАРЫ_ЗАЛИВКИ = (("#ffffff", "acc"),)

ПОРОГ = 4.5


@pytest.fixture(scope="module")
def модуль(tmp_path_factory):
    каталог = tmp_path_factory.mktemp("тема")
    с = h.Стенд(каталог)
    записи = [h.запись(f"t{i:02d}", title=f"Тайтл {i}") for i in range(30)]
    с.записать_каталог(записи)
    с.записать_подробности([h.подробность(з["slug"]) for з in записи])
    с.записать_плеер()

    class МП:
        def setenv(self, к, з):
            import os
            os.environ[к] = з

        def syspath_prepend(self, п):
            import sys
            sys.path.insert(0, п)

        def setattr(self, *а, **к):
            pass

    м = h.загрузить(с, МП())
    yield м
    h.выгрузить(м)


@pytest.mark.parametrize("профиль", ["lords-general", "lords-new", "lords-curated"])
def test_обе_темы_читаются_в_каждом_профиле(модуль, профиль):
    """Различие профилей сохраняется, а читаемость — общая для всех."""
    светлые = {
        "lords-general": модуль.ЛОРДС_ТОКЕНЫ,
        "lords-new": модуль.ЛОРДС_ТОКЕНЫ_SERIES,
        "lords-curated": модуль.ЛОРДС_ТОКЕНЫ_CURATED,
    }[профиль]
    тёмные = модуль._тёмные_для(светлые)
    провалы = []
    for палитра, имя in ((светлые, "светлая"), (тёмные, "тёмная")):
        for текст, фон in ПАРЫ_ТЕКСТА:
            к = контраст(палитра[текст], палитра[фон])
            if к < ПОРОГ:
                провалы.append(f"{имя}: {текст} на {фон} = {к:.2f} при пороге {ПОРОГ}")
        for текст, фон in ПАРЫ_ЗАЛИВКИ:
            к = контраст(текст, палитра[фон])
            if к < ПОРОГ:
                провалы.append(f"{имя}: {текст} на {фон} = {к:.2f} при пороге {ПОРОГ}")
    assert not провалы, "\n  ".join(["нечитаемые пары:"] + провалы)


def test_акцент_как_текст_и_как_заливка_разведены(модуль):
    """Проверка «от обратного».

    Если бы тёмная тема взяла `accdk` из светлой, ссылка на тёмной карточке
    дала бы 2.31:1. Проверка обязана падать именно на этом.
    """
    тёмные = модуль._тёмные_для(модуль.ЛОРДС_ТОКЕНЫ)
    плохо = контраст(модуль.ЛОРДС_ТОКЕНЫ["accdk"], тёмные["card"])
    assert плохо < ПОРОГ, "исходные данные проверки устарели"
    хорошо = контраст(тёмные["accdk"], тёмные["card"])
    assert хорошо >= ПОРОГ


# --- объявление тем в таблице стилей ----------------------------------------

@pytest.fixture()
def страница(модуль):
    return h.вид(модуль).главная()


def test_обе_палитры_объявлены_переменными(модуль, страница):
    стиль = страница.split("<style>", 1)[1].split("</style>", 1)[0]
    assert ":root{color-scheme:light;" in стиль
    assert ':root[data-theme="dark"]{color-scheme:dark;' in стиль
    assert '@media (prefers-color-scheme: dark){:root:not([data-theme="light"])' in стиль
    assert ':root[data-theme="light"]{color-scheme:light;' in стиль


def test_литеральных_цветов_палитры_в_правилах_не_осталось(модуль, страница):
    """Значение объявляется один раз — в `:root`.

    Пока оно подставлялось в каждое правило, вторая тема требовала второй
    копии всей таблицы стилей.
    """
    стиль = страница.split("<style>", 1)[1].split("</style>", 1)[0]
    # Отрезаем ВСЕ объявления `:root`: литералы живут там по определению,
    # проверяем именно правила ниже.
    тело = стиль.split(':root[data-theme="light"]', 1)[1].split("}\n", 1)[1]
    for имя in ("ink", "sheet", "card", "accdk", "bar"):
        значение = модуль.ЛОРДС_ТОКЕНЫ[имя]
        assert значение.lower() not in тело.lower(), (
            f"цвет {имя}={значение} подставлен литералом, а не переменной")


def test_нативные_элементы_следуют_теме(модуль, страница):
    """`color-scheme` решает прокрутку и `select`, но не поле ввода."""
    стиль = страница.split("<style>", 1)[1].split("</style>", 1)[0]
    assert "color-scheme:dark" in стиль
    assert re.search(r"input,textarea,select\{[^}]*color:var\(--t-ink\)", стиль), (
        "поле комментария и оценки останется светлым на тёмной теме")
    assert "::placeholder" in стиль


def test_переключатель_есть_и_объявляет_своё_состояние(страница):
    assert "data-theme-toggle" in страница
    assert 'aria-pressed="false"' in страница
    assert "Сменить оформление" in страница


def test_выбор_сохраняется_и_общий_для_вкладок(модуль, страница):
    скрипт = страница.split("<script>", 1)[1].split("</script>", 1)[0]
    assert "localStorage.setItem" in скрипт
    assert "localStorage.getItem" in скрипт
    assert "'storage'" in скрипт, "выбор темы обязан быть общим для вкладок сайта"
    assert "prefers-color-scheme" in скрипт, (
        "пока выбор не сделан, действует системная тема")


