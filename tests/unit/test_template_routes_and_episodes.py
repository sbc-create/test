"""Семантика трёх легаси-маршрутов и длина списка серий.

Две задачи, решённые здесь, объединены одним свойством: обе проверяются только
собранной страницей, а не чтением кода.

1. `/catalog/`, `/new/` и `/collections/` отдавали одно и то же. Причина не в
   заголовках: каталог уже хранится отсортированным по `published_at`, поэтому
   пересортировка «новинок» была пустой операцией, а «подборки» вообще не имели
   собственной выборки. Отличать их подписью — это выдавать один документ за
   три; здесь проверяется именно payload.

2. Список серий у «Детектива Конана» — 1212 кнопок. Без ограничения высоты он
   растягивал страницу на десятки тысяч пикселей, и всё, что ниже, становилось
   недостижимым. Обрезать список нельзя: 1212-я серия обязана оставаться
   доступной. Поэтому проверяется одновременно и высота контейнера, и то, что
   ни одна ссылка не потерялась.

Артефакт подключает `seo_layer`, который живёт рядом с ним на хосте и в
репозиторий не входит; здесь подставляется заглушка ровно с той единственной
функцией, которую рендерер вызывает, — и вызывается она в самом рендерере под
`try/except`, то есть на результат страницы не влияет.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
import types

import pytest

from factory.paths import PATHS

ARTIFACT = PATHS.root / "automation/host/lords-frontend.py"

#: Тайтл с длинным сериалом. Столько серий у «Детектива Конана» в снимке.
СЕРИЙ = 1212


def _заглушка_seo():
    """Минимальная замена host-only модуля: сквозной проход тела ответа."""
    модуль = types.ModuleType("seo_layer")
    модуль.обогатить = lambda тело, тип, **кв: тело
    return модуль


@pytest.fixture(scope="module")
def витрина(tmp_path_factory):
    """Собранная витрина Animedia на маленьком детерминированном снимке."""
    корень = tmp_path_factory.mktemp("animedia")

    записи = []
    for i in range(60):
        записи.append({
            "slug": f"t{i:03d}",
            "title": f"Тайтл {i:03d}",
            "kind": "Сериал" if i % 2 else "Аниме",
            "year": 2020 + (i % 6),
            "poster": f"https://poster.example/{i}.webp",
            # Свежесть убывает с индексом: снимок уже отсортирован так же, как
            # боевой, — иначе «новинки» совпали бы с каталогом случайно.
            "published_at": f"2026-09-{(30 - i % 28):02d}T00:00:00Z",
            # Адрес карточки — тот же вид, что в боевом снимке: витрина
            # ссылается именно этим полем.
            "url": f"/title/t{i:03d}/",
        })
    каталог = корень / "catalog.json"
    каталог.write_text(json.dumps({"items": записи}), encoding="utf-8")

    подробности = корень / "details.json"
    подробности.write_text(json.dumps({
        "source": "fixture",
        "details_total": 1,
        "details": {"t001": {"seasons": [{"n": 1, "eps": СЕРИЙ, "avail": СЕРИЙ}]}},
    }), encoding="utf-8")

    манифест = корень / "manifest.json"
    манифест.write_text(json.dumps({
        "schema_version": 1, "template_family": "animedia", "design_version": "1.2.0",
        "source_commit": "0" * 40, "build_id": "test", "artifact_sha256": "0" * 64,
        "profile": "animedia-test", "built_at": "2026-09-16T00:00:00Z",
    }), encoding="utf-8")

    старое = sys.modules.get("seo_layer")
    sys.modules["seo_layer"] = _заглушка_seo()
    # Контракт коллекций артефакт ищет рядом с собой: на хосте туда кладут его
    # копию. Здесь подставляется канонический экземпляр из `factory/lords`, а
    # не вторая реализация — иначе проверялась бы не та витрина.
    путь_контракта = str(PATHS.root / "factory" / "lords")
    добавлен = путь_контракта not in sys.path
    if добавлен:
        sys.path.insert(0, путь_контракта)
    import os
    прежние = {к: os.environ.get(к) for к in
               ("LORDS_TEMPLATE_MANIFEST", "LORDS_CATALOG", "LORDS_DETAILS", "LORDS_SITE_NAME")}
    os.environ.update({
        "LORDS_TEMPLATE_MANIFEST": str(манифест),
        "LORDS_CATALOG": str(каталог),
        "LORDS_DETAILS": str(подробности),
        "LORDS_SITE_NAME": "Animedia",
    })
    try:
        спец = importlib.util.spec_from_file_location("nova_routes_probe", ARTIFACT)
        модуль = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(модуль)
    except SystemExit as ош:  # pragma: no cover
        pytest.skip(f"артефакт не поднимается: {ош}")
    finally:
        for к, з in прежние.items():
            if з is None:
                os.environ.pop(к, None)
            else:
                os.environ[к] = з
        if старое is None:
            sys.modules.pop("seo_layer", None)
        else:
            sys.modules["seo_layer"] = старое
        if добавлен and путь_контракта in sys.path:
            sys.path.remove(путь_контракта)

    assert модуль.КОЛЛЕКЦИИ is not None, (
        "контракт коллекций не подключился — проверялась бы витрина без коллекций")

    д = модуль.Данные(str(каталог))
    п = модуль.Подробности(str(подробности))
    индекс = модуль.построить_индекс(д, п)
    описание = модуль.СЕМЕЙСТВА_1_1["animedia"]
    класс = модуль.ВИДЫ_1_1["animedia"]
    return модуль, класс(описание, д, п, индекс, "Animedia")


def _тайтлы(html_текст: str) -> list[str]:
    return re.findall(r'href="(/title/[^"]+)"', html_текст)


def _отпечаток(html_текст: str) -> tuple:
    """Состав и порядок карточек страницы — то, что отличает документ."""
    return tuple(_тайтлы(html_текст))


