def test_каталог_новинки_и_подборки_отдают_разное(витрина):
    """Ноль пар-дублей из трёх. Сравнивается payload, а не заголовок."""
    _, вид = витрина
    страницы = {
        "/catalog": вид.список("/catalog", {}),
        "/new": вид.список("/new", {}),
        "/collections": вид.список("/collections", {}),
    }
    отпечатки = {имя: _отпечаток(текст) for имя, текст in страницы.items()}
    пары = [(а, б) for а in отпечатки for б in отпечатки if а < б
            and отпечатки[а] == отпечатки[б]]
    assert not пары, (
        f"маршруты отдают одинаковый набор и порядок карточек: {пары}. "
        f"Замена заголовка дублем быть не перестаёт")


def test_новинки_отсортированы_по_свежести_публикации(витрина):
    """«Новинки» — это дата публикации, а не порядок хранения каталога."""
    модуль, вид = витрина
    набор, _ = модуль.отбор(вид.д, вид.индекс, {}, "/new")
    даты = [з.get("published_at") or "" for з in набор]
    assert даты == sorted(даты, reverse=True), "новинки обязаны идти от свежих к старым"


def test_каталог_не_повторяет_порядок_новинок(витрина):
    """У полного каталога собственный устойчивый порядок."""
    модуль, вид = витрина
    каталог, _ = модуль.отбор(вид.д, вид.индекс, {}, "/catalog")
    новинки, _ = модуль.отбор(вид.д, вид.индекс, {}, "/new")
    assert [з["slug"] for з in каталог] != [з["slug"] for з in новинки], (
        "каталог и новинки обязаны отличаться порядком, иначе это один документ")


def test_подборки_ведут_в_коллекции_а_не_в_каталог(витрина):
    """`/collections/` — перечень коллекций, а не ещё одна сетка тайтлов."""
    _, вид = витрина
    страница = вид.список("/collections", {})
    ссылки = set(re.findall(r'href="(/collection/[a-z0-9_]+/)"', страница))
    assert ссылки, "на хабе подборок нет ни одной ссылки на коллекцию"

    # Проверяется тело хаба, а не вся страница: ссылка на каталог в общей
    # навигации законна и есть на каждой странице витрины.
    #
    # Сетка хаба несёт маркеры блока (у Animedia это `data-b13="hub"` из B13),
    # поэтому селектор допускает атрибуты. Требование от этого не слабеет: тело
    # хаба по-прежнему обязано существовать, по-прежнему не должно уводить в
    # общий каталог и по-прежнему не может быть сеткой тайтлов.
    хаб = re.search(r'<div class="zhub"[^>]*>.*?</div>\s*</div>', страница, re.S)
    assert хаб, "тело хаба не найдено"
    assert 'href="/catalog/"' not in хаб.group(0), (
        "карточки хаба не должны уводить в общий каталог")
    assert re.search(r'<div class="zg"[^>]*>', хаб.group(0)) is None, (
        "хаб обязан быть перечнем коллекций, а не сеткой тайтлов")


def test_у_каждой_страницы_свои_заголовок_и_canonical(витрина):
    """Подпись обязана соответствовать документу, хотя одной её и недостаточно."""
    _, вид = витрина
    for раздел, кусок in (("/catalog", "/catalog/"), ("/new", "/new/"),
                          ("/collections", "/collections/")):
        страница = вид.список(раздел, {})
        canonical = re.search(r'<link rel="canonical" href="([^"]+)"', страница)
        assert canonical, f"{раздел}: нет canonical"
        assert canonical.group(1).endswith(кусок), (
            f"{раздел}: canonical ведёт на {canonical.group(1)}")


