def test_все_серии_остаются_в_разметке(витрина):
    """1212 из 1212: ограничение высоты не имеет права терять ссылки."""
    _, вид = витрина
    страница = вид.тайтл(вид.запись("t001"), вид.деталь("t001"))
    номера = [int(н) for н in re.findall(r'/season-1/episode-(\d+)/', страница)]
    assert len(номера) == СЕРИЙ, f"серий в разметке {len(номера)}, ожидалось {СЕРИЙ}"
    assert len(set(номера)) == СЕРИЙ, "номера серий повторяются"
    assert min(номера) == 1 and max(номера) == СЕРИЙ
    assert номера == sorted(номера), "исходный порядок серий изменён"


def test_контейнер_серий_ограничен_по_высоте(витрина):
    """У списка есть предел высоты и собственная прокрутка.

    Проверяются обе ветки оформления: мобильная в долях экрана, десктопная в
    пикселях. Без предела страница «Детектива Конана» вырастает до десятков
    тысяч пикселей, и всё, что ниже списка, посетителю недоступно.
    """
    модуль, _ = витрина
    css = модуль._подставить(модуль.АНИМЕДИА_СТИЛЬ, модуль.АНИМЕДИА_ТОКЕНЫ)
    без_комментариев = re.sub(r"/\*.*?\*/", "", css, flags=re.S)

    правила = [тело.replace(" ", "").replace("\n", "")
               for сел, тело in re.findall(r"([^{}]+)\{([^}]*)\}", без_комментариев)
               if ".zeps" in {с.strip() for с in сел.split(",")}]
    assert правила, "у списка серий нет собственного правила"

    базовое = правила[0]
    assert "overflow-y:auto" in базовое, "без прокрутки ограничение высоты прячет серии"
    assert "max-height:" in базовое, "у списка серий нет предела высоты"

    предел = re.search(r"max-height:([0-9.]+)(vh|px)", базовое)
    assert предел, f"предел высоты не разобран: {базовое[:120]}"
    величина, единица = float(предел.group(1)), предел.group(2)
    if единица == "vh":
        assert величина <= 70, f"мобильный предел {величина}vh выше 70vh"
    else:
        assert величина <= 720, f"предел {величина}px выше 720px"

    # Десктопная ветка объявляется отдельно и тоже обязана быть ограниченной.
    десктоп = re.search(r"@media\(min-width:768px\)\{\.zeps\{([^}]*)\}", без_комментариев)
    if десктоп:
        предел_д = re.search(r"max-height:([0-9.]+)(vh|px)", десктоп.group(1).replace(" ", ""))
        assert предел_д, "в десктопной ветке нет предела высоты"
        зд, ед = float(предел_д.group(1)), предел_д.group(2)
        assert (зд <= 70 if ед == "vh" else зд <= 720), f"десктопный предел {зд}{ед} слишком велик"
