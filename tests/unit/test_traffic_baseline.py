def test_json_содержит_окно_и_порог(tmp_path, capsys):
    файл = tmp_path / "cabinet.json"
    файл.write_text(json.dumps({"collected_at": "2026-10-19T00:00:00Z",
                                "period": {"date1": "7daysAgo"},
                                "domains": [_домен([("2026-10-18", 10.0)])]}),
                    encoding="utf-8")
    assert ИНСТР.main(["--file", str(файл), "--json", "--goal", "77"]) == 0
    д = json.loads(capsys.readouterr().out)
    assert д["порог"] == 77 and д["домены"][0]["измерено"] is True

