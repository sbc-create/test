"""REQ-TRAFFIC-BASELINE: исходные данные посещаемости считаются раздельно.

Цель владельца названа в людях из поиска. В выгрузке кабинета четыре разных
числа (визиты за период, посетители за период, суточный ряд People/Robots,
суточный ряд по источникам), и смешение их — ровно та ошибка, из-за которой
прошлый недельный отчёт пришлось пересчитывать. Здесь закрепляется, что:

* люди, роботы и поиск не складываются;
* окно расчёта берётся по ПРИШЕДШИМ суткам, а не по заявленному периоду;
* «нет счётчика» и «источник недоступен» дают причину, а не ноль.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/traffic-baseline.py"
_спец = importlib.util.spec_from_file_location("traffic_baseline", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)


def _сутки_людей(день: str, люди: float, роботы: float = 0.0) -> list[dict]:
    стр = [{"dimensions": [{"name": день}, {"name": "People", "id": "no"}],
            "metrics": [люди, люди]}]
    if роботы:
        стр.append({"dimensions": [{"name": день}, {"name": "Robots", "id": "yes"}],
                    "metrics": [роботы, роботы]})
    return стр


def _сутки_поиска(день: str, яндекс: float = 0.0, прямой: float = 0.0,
                  гугл: float = 0.0) -> list[dict]:
    стр = []
    if яндекс:
        стр.append({"dimensions": [{"name": день},
                                   {"name": "Search engine traffic", "id": "organic"},
                                   {"name": "Yandex", "id": "yandex"}],
                    "metrics": [яндекс, яндекс]})
    if гугл:
        стр.append({"dimensions": [{"name": день},
                                   {"name": "Search engine traffic", "id": "organic"},
                                   {"name": "Google", "id": "google"}],
                    "metrics": [гугл, гугл]})
    if прямой:
        стр.append({"dimensions": [{"name": день},
                                   {"name": "Direct traffic", "id": "direct"},
                                   {"name": None, "id": None}],
                    "metrics": [прямой, прямой]})
    return стр


def _домен(дни: list[tuple], поиск: list[tuple] = (), **прочее) -> dict:
    люди, строки_поиска = [], []
    for день, л, *р in дни:
        люди += _сутки_людей(день, л, р[0] if р else 0.0)
    for день, я, *р in поиск:
        строки_поиска += _сутки_поиска(день, я, р[0] if р else 0.0,
                                       р[1] if len(р) > 1 else 0.0)
    д = {"domain": "x.test", "counter_id": 1, "measurements": [
        {"key": "daily_users", "measured": True, "value": люди},
        {"key": "daily_search", "measured": True, "value": строки_поиска},
    ]}
    д.update(прочее)
    return д


def test_люди_и_роботы_не_складываются():
    итог = ИНСТР.разобрать(_домен([("2026-10-18", 100.0, 900.0)]), 5000)
    assert итог["люди_медиана"] == 100.0
    assert итог["роботы_медиана"] == 900.0


def test_прямой_заход_поиском_не_считается():
    """Скачок непоискового трафика не вправе выглядеть ростом из поиска."""
    итог = ИНСТР.разобрать(
        _домен([("2026-10-18", 20000.0)], [("2026-10-18", 700.0, 19000.0)]), 5000)
    assert итог["поиск_медиана"] == 700.0
    assert итог["люди_медиана"] == 20000.0


def test_гугл_входит_в_поиск_но_не_в_яндекс():
    итог = ИНСТР.разобрать(
        _домен([("2026-10-18", 50.0)], [("2026-10-18", 30.0, 0.0, 20.0)]), 5000)
    assert итог["поиск_медиана"] == 50.0
    assert итог["поиск_яндекс_медиана"] == 30.0


def test_окно_считается_по_последним_суткам():
    дни = [(f"2026-10-{д:02d}", float(д)) for д in range(5, 19)]
    итог = ИНСТР.разобрать(_домен(дни), 5000, окно=7)
    assert итог["дней"] == 7 and итог["период"] == "2026-10-12..2026-10-18"
    assert итог["дней_в_выгрузке"] == 14
    assert итог["люди_медиана"] == 15.0


def test_окно_ноль_берёт_все_сутки():
    дни = [(f"2026-10-{д:02d}", float(д)) for д in range(5, 19)]
    итог = ИНСТР.разобрать(_домен(дни), 5000, окно=0)
    assert итог["дней"] == 14 and итог["люди_медиана"] == 11.5


def test_дни_выше_цели_считаются():
    дни = [("2026-10-17", 9000.0), ("2026-10-18", 9000.0)]
    поиск = [("2026-10-17", 6000.0), ("2026-10-18", 4000.0)]
    итог = ИНСТР.разобрать(_домен(дни, поиск), 5000)
    assert итог["дней_выше_цели"] == 1
    assert итог["до_цели"] == 0.0  # медиана 5000 ровно порог


def test_нет_счётчика_даёт_причину():
    д = {"domain": "y.test", "measurements": [
        {"key": "daily_users", "measured": False,
         "state": "НЕ_НАСТРОЕНО", "reason": "счётчик Метрики не создан"}]}
    итог = ИНСТР.разобрать(д, 5000)
    assert итог["измерено"] is False
    assert "счётчик" in итог["почему"]


def test_поиск_не_измерен_не_превращается_в_ноль_молча():
    д = _домен([("2026-10-18", 100.0)])
    д["measurements"][1] = {"key": "daily_search", "measured": False,
                            "state": "ИСТОЧНИК_НЕДОСТУПЕН"}
    итог = ИНСТР.разобрать(д, 5000)
    assert итог["измерено"] is True
    assert итог["поиск_измерен"] is False


