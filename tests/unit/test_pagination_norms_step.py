def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    """Подставные ответы: адрес → (код, тело, итоговый адрес)."""

    def __init__(self, таблица: dict):
        self.таблица = таблица

    def __call__(self, url: str, таймаут: int = 45):
        код, тело, итоговый = self.таблица.get(
            url, ("404", ПУСТО, url))
        return код, тело, {"итоговый-адрес": итоговый}


def прогнать(таблица: dict) -> list[tuple[str, bool, str]]:
    м = _модуль()
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_пагинации("x.test", lambda имя, ок, подробно: шаги.append(
        (имя, ок, подробно)))
    return шаги


