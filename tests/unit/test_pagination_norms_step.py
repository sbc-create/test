def test_в_списке_стоят_домены_измеренные_как_соблюдающие():
    """Список — не пожелание: туда входит только то, что замерено.

    На 2026-10-11 это вся семья Yummy. Если домен попал в список без
    измерения, приёмка начнёт падать и укажет на него сама.
    """
    м = _модуль()
    # Карта растёт по одной витрине за выкладку, и каждое пополнение проходит
    # через эту проверку: правка карты без правки проверки не пройдёт, то есть
