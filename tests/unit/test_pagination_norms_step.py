def test_в_строгом_списке_редиректа_стоят_измеренные_разделы():
    """Строгость п.2 — по разделу, а не по домену.

    Домен целиком строгим быть не может — и доказано это не рассуждением, а
    ошибкой: 11.10 строгость стояла домену, и на фасетах Zona приёмка выдала
    «РЕГРЕСС: редирект пропал» о поверхности, где путевой маршрут параметр
    `page` не разбирал вовсе и редиректа никогда не делал. Правка выложена
    (7da8a06f, e0b8dd4f) и фасеты Zona в строгие внесены — но карта осталась
    по разделам, потому что причина никуда не делась: разные поверхности
    одной витрины обслуживаются разным кодом.
    """
    м = _модуль()
    assert isinstance(м.ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО, dict)
    # Полный проход по десяти поверхностям пройден всеми витринами Lords и
    # Zona, включая zonafilm.cc после build ae4b8c56f5f4-zona-02.
    for домен in ("lordserial33.biz", "zonafilm.space", "zonafilm12.site",
                  "zonafilm.cc"):
        разделы = м.ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО[домен]
        assert "/year/2024/" in разделы, домен
        assert "/country/rossiya/" in разделы, домен
    # Редирект `?page=1` на поверхности коллекций выполняют только Animedia:
    # у Lords и Zona маршрут коллекции отдаёт ответ мимо общего пути.
    for домен in ("animedia.icu", "animedia.space"):
        assert "/collection/" in м.ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО[домен], домен
    for домен in ("zonafilm.space", "zonafilm12.site", "zonafilm.cc",
                  "lordserial33.biz", "lordfilm47.space",
                  "1lordserials1.online", "lordserials22.info"):
        assert "/collection/" not in м.ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО[домен], домен
    # Каталог измерен у всех выложенных витрин.
    for домен in ("zonafilm.cc", "zonafilm12.site", "lordfilm47.space",
                  "1lordserials1.online", "lordserials22.info",
                  "animedia.icu", "animedia.space", "an1mego.site",
                  "animeg0.site", "an1meg0.site"):
        assert "/catalog/" in м.ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО[домен], домен
    # Строгость не ставится разделу, которого в замере не было. `/collection/`
    # разрешён отдельно — это признак поверхности, а не адрес из перечня.
    for домен, разделы in м.ПАГИНАЦИЯ_РЕДИРЕКТ_СТРОГО.items():
        лишние = set(разделы) - set(м.РАЗДЕЛЫ_ПАГИНАЦИИ) - {"/collection/"}
        assert not лишние, (домен, лишние)
        конкретные = [р for р in разделы
                      if р.startswith("/collection/") and р != "/collection/"]
        assert not конкретные, (домен, конкретные)


