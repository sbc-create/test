"""Шаг приёмки «нормы пагинации»: что считается расхождением, а что нет.

Повод. Правило `REQ-SEO-PAGINATION` до сих пор проверялось руками и по случаю —
так и нашлось, что AnimeGo отдаёт 200 с полным набором карточек на `?page=0`,
`?page=-1`, `?page=abc` и 200 с остатком на `?page=9999`. Теперь это мерится
регулярно, вместе с остальной приёмкой домена.

Разделение жёсткого и сообщающего здесь не вкусовое:

* **п.8** (номер за пределом и мусор) — жёстко: адрес, отдающий 200 с
  карточками, это готовый дубль раздела, и спорных случаев нет;
* **п.2** (`?page=1`) — жёстко только на случай canonical, указывающего на сам
  `?page=1`: это дубль. Отсутствие редиректа сообщается, но расхождением пока
  не считается — так сейчас у всей сети, кроме Zona;
* **п.3** (self-canonical у страниц 2+) — расхождение сети известно и записано
  решением D202, выпуск правки готовит SEO-сессия. Поэтому проверка падает
  только на НЕОЖИДАННОМ canonical: ни на себя, ни на раздел. Когда правка
  выйдет, достаточно убрать `известное_D202`, и проверка станет жёсткой.

Сеть мерится без сети: `достать` подменяется таблицей ответов.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

СТРАНИЦА_1 = ('<link rel="canonical" href="https://x.test/catalog/"/>'
              + "".join(f'<a href="/title/first-{i}">' for i in range(48)))
СТРАНИЦА_2_НА_СЕБЯ = ('<link rel="canonical" href="https://x.test/catalog/?page=2"/>'
                      + "".join(f'<a href="/title/second-{i}">' for i in range(48)))
СТРАНИЦА_2_НА_РАЗДЕЛ = ('<link rel="canonical" href="https://x.test/catalog/"/>'
                        + "".join(f'<a href="/title/second-{i}">' for i in range(48)))
СТРАНИЦА_2_ЧУЖОЙ = ('<link rel="canonical" href="https://другой.test/catalog/"/>'
                    + "".join(f'<a href="/title/second-{i}">' for i in range(48)))
ПУСТО = "<html></html>"


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    """Подставные ответы: адрес → (код, тело, итоговый адрес)."""

    def __init__(self, таблица: dict):
        self.таблица = таблица

    def __call__(self, url: str, таймаут: int = 45):
        код, тело, итоговый = self.таблица.get(
            url, ("404", ПУСТО, url))
        return код, тело, {"итоговый-адрес": итоговый}


def прогнать(таблица: dict) -> list[tuple[str, bool, str]]:
    м = _модуль()
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_пагинации("x.test", lambda имя, ок, подробно: шаги.append(
        (имя, ок, подробно)))
    return шаги


ОСНОВА = "https://x.test/catalog/"


def базовая_таблица(**замены) -> dict:
    таблица = {
        ОСНОВА: ("200", СТРАНИЦА_1, ОСНОВА),
        ОСНОВА + "?page=1": ("200", СТРАНИЦА_1, ОСНОВА + "?page=1"),
        ОСНОВА + "?page=2": ("200", СТРАНИЦА_2_НА_СЕБЯ, ОСНОВА + "?page=2"),
        ОСНОВА + "?page=9999": ("404", ПУСТО, ОСНОВА + "?page=9999"),
        ОСНОВА + "?page=0": ("404", ПУСТО, ОСНОВА + "?page=0"),
        ОСНОВА + "?page=-1": ("404", ПУСТО, ОСНОВА + "?page=-1"),
        ОСНОВА + "?page=abc": ("404", ПУСТО, ОСНОВА + "?page=abc"),
    }
    таблица.update(замены)
    return таблица


def найти(шаги, часть: str):
    (шаг,) = [ш for ш in шаги if часть in ш[0]]
    return шаг


def test_исправная_витрина_проходит_все_три_нормы():
    шаги = прогнать(базовая_таблица())
    assert all(ок for _имя, ок, _п in шаги), шаги
    assert "на себя" in найти(шаги, "canonical страницы 2")[2]


@pytest.mark.parametrize("проба", ["?page=0", "?page=-1", "?page=abc"])
def test_копия_первой_страницы_за_пределом_это_расхождение(проба):
    """Ровно то, что нашлось у AnimeGo."""
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + проба: ("200", СТРАНИЦА_1, ОСНОВА + проба)}))
    имя, ок, подробно = найти(шаги, "номер за пределом")
    assert ок is False, подробно
    assert "копия первой" in подробно


def test_остаток_за_пределом_тоже_расхождение():
    """`?page=9999` с любыми карточками — дубль раздела, а не «почти пусто»."""
    остаток = ('<link rel="canonical" href="https://x.test/catalog/"/>'
               + "".join(f'<a href="/title/rest-{i}">' for i in range(8)))
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + "?page=9999": ("200", остаток, ОСНОВА + "?page=9999")}))
    _имя, ок, подробно = найти(шаги, "номер за пределом")
    assert ок is False
    assert "с карточками" in подробно


def test_отказ_за_пределом_нормой_считается():
    for код in ("404", "400", "410"):
        шаги = прогнать(базовая_таблица(**{
            ОСНОВА + "?page=abc": (код, ПУСТО, ОСНОВА + "?page=abc")}))
        assert найти(шаги, "номер за пределом")[1] is True, код


def test_page1_с_canonical_на_себя_это_расхождение():
    """Иначе у первой страницы два канонических адреса — прямой дубль."""
    страница = ('<link rel="canonical" href="https://x.test/catalog/?page=1"/>'
                + "".join(f'<a href="/title/first-{i}">' for i in range(48)))
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + "?page=1": ("200", страница, ОСНОВА + "?page=1")}))
    _имя, ок, подробно = найти(шаги, "?page=1")
    assert ок is False, подробно


def test_редирект_page1_виден_по_итоговому_адресу():
    """`достать` следует переходам, поэтому код ответа редирект не покажет."""
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + "?page=1": ("200", СТРАНИЦА_1, ОСНОВА)}))
    _имя, ок, подробно = найти(шаги, "?page=1")
    assert ок is True
    assert "норма соблюдена" in подробно


def test_отсутствие_редиректа_сообщается_но_не_падает():
    шаги = прогнать(базовая_таблица())
    _имя, ок, подробно = найти(шаги, "?page=1")
    assert ок is True
    assert "норма просит редирект" in подробно


def test_canonical_страницы_2_на_раздел_известное_расхождение():
    """D202: сеть сейчас такая, и это не повод делать приёмку красной."""
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + "?page=2": ("200", СТРАНИЦА_2_НА_РАЗДЕЛ, ОСНОВА + "?page=2")}))
    _имя, ок, подробно = найти(шаги, "canonical страницы 2")
    assert ок is True
    assert "D202" in подробно


def test_неожиданный_canonical_страницы_2_падает():
    """Ни на себя, ни на раздел — это уже не известное расхождение."""
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + "?page=2": ("200", СТРАНИЦА_2_ЧУЖОЙ, ОСНОВА + "?page=2")}))
    _имя, ок, подробно = найти(шаги, "canonical страницы 2")
    assert ок is False, подробно
    assert "другой.test" in подробно


def test_без_раздела_нормы_не_применяются():
    шаги = прогнать({ОСНОВА: ("404", ПУСТО, ОСНОВА)})
    assert len(шаги) == 1
    assert шаги[0][1] is True
    assert "раздела у витрины нет" in шаги[0][2]


def test_без_второй_страницы_норма_п3_не_применяется():
    шаги = прогнать(базовая_таблица(**{
        ОСНОВА + "?page=2": ("404", ПУСТО, ОСНОВА + "?page=2")}))
    _имя, ок, подробно = найти(шаги, "canonical страницы 2")
    assert ок is True
    assert "второй страницы нет" in подробно
