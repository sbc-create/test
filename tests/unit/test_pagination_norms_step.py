def test_без_раздела_нормы_не_применяются():
    """По одной строке на раздел плюс строка про коллекцию.

    Разделы появлялись у витрин не одновременно, поэтому отсутствие раздела —
    такой же факт, как отсутствие каталога, и расхождением не считается.

    С коллекцией иначе, и разницу тест держит отдельно: отсутствие ссылок в
    ОТВЕТИВШЕМ хабе — факт о витрине (не расхождение), а неответивший хаб —
    факт об измерении (расхождение). Здесь таблица отдаёт 404 на всё, включая
    хаб, поэтому строка коллекции обязана сказать «не измерено».
    """
    шаги = прогнать({ОСНОВА: ("404", ПУСТО, ОСНОВА),
                     "https://x.test/collections/": ("404", ПУСТО,
                                                     "https://x.test/collections/")})
    # Перечень разделов плюс одна строка коллекции.
    assert len(шаги) == len(_модуль().РАЗДЕЛЫ_ПАГИНАЦИИ) + 1, шаги
    assert [и for и, _ок, _п in шаги][:2] == ["нормы пагинации [catalog]",
                                              "нормы пагинации [genre/drama]"]
    (строка,) = [ш for ш in шаги if "[коллекция]" in ш[0]]
    assert строка[1] is False, строка
    assert строка[2].startswith("не измерено")
    остальные = [ш for ш in шаги if "[коллекция]" not in ш[0]]
    assert all(ок for _и, ок, _п in остальные)
    assert all("раздела у витрины нет" in п for _и, _ок, п in остальные)


