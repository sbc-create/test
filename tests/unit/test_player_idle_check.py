"""Проверка «что видит посетитель, который не нажимал» существует и отделена.

Почему этот инструмент и этот тест появились
--------------------------------------------

`playback-check.py` щёлкает по кадру СРАЗУ и доказывает, что поток
декодируется. Сторож плеера в выложенном коде выходит из своих таймеров по
условию `playing`:

    setTimeout(function(){ if(... || playing) return; ... }, 25000)

То есть при начавшемся воспроизведении сторож безвреден, и проверка с
немедленным нажатием НЕ МОЖЕТ его увидеть — по построению. Измерено
2026-10-05 на живом `zonafilm.cc` (две карточки, одинаковая картина): без
единого нажатия на 25-й секунде плеер пересоздаётся, а на 50-й посетителю
показывается «Видео временно недоступно». Мои же замеры с нажатием в тот же
день отвечали «воспроизведение ИДЁТ» — и оба утверждения верны, потому что
измеряют разные пути.

Поэтому путей проверки два, и этот тест стережёт, что второй не выродится в
первый: инструмент не вправе нажимать, обязан судить по видимому посетителю и
обязан возвращать НЕнулевой код, когда отказ показан.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИНСТРУМЕНТ = КОРЕНЬ / "automation" / "local" / "player-idle-check.py"


def _текст() -> str:
    assert ИНСТРУМЕНТ.is_file(), f"нет {ИНСТРУМЕНТ}"
    return ИНСТРУМЕНТ.read_text(encoding="utf-8")


def test_инструмент_ничего_не_нажимает():
    """Нажатие превратило бы проверку в копию `playback-check.py`."""
    т = _текст()
    for запрет in (".click(", "dispatchEvent", "press("):
        assert запрет not in т, (
            f"инструмент взаимодействует со страницей ({запрет}): тогда он "
            "измеряет путь с нажатием, а сторож плеера из своих таймеров "
            "выходит по `playing` и снова станет невидим")


def test_судит_по_видимому_посетителю():
    т = _текст()
    assert "offsetParent" in т, (
        "видимость блока состояния не проверяется: скрытый блок есть в "
        "разметке всегда, и его наличие отказом не является")
    assert "data-state" in т and "data-player-state" in т
    assert "ОТКАЗНЫЕ" in т, "перечень отказных состояний не объявлен"


def test_отказ_даёт_ненулевой_код():
    """Инструмент, печатающий отказ и возвращающий 0, не ворота, а вывод."""
    т = _текст()
    м = re.search(r"if отказ:(.+?)return 3", т, re.S)
    assert м, "ветвь показанного отказа не возвращает 3"
    assert "ВЫВОД" in м.group(1)


def test_пересоздание_плеера_считается():
    """Пересоздание посреди ожидания — то, что сторож и делает."""
    т = _текст()
    assert "пересозданий" in т
    assert '"resolving"' in т and '"ready"' in т


def test_формы_адреса_совпадают_с_проверенной_таблицей():
    """Зашитый `/title/` не нашёл бы карточку у Yummy: там `/anime/<slug>`."""
    import importlib.util

    спец = importlib.util.spec_from_file_location("player_idle_check", ИНСТРУМЕНТ)
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
    except ImportError:
        # playwright на этой машине может быть недоступен — перечень форм
        # тогда читается из текста: он объявлен литералом.
        м = re.search(r"ПРЕФИКСЫ = \(([^)]*)\)", _текст())
        assert м, "перечень форм адреса не объявлен"
        формы_инструмента = tuple(re.findall(r'"([^"]+)"', м.group(1)))
    else:
        формы_инструмента = tuple(модуль.ПРЕФИКСЫ)

    from factory.qwen import registry

    формы = {ф.split("{", 1)[0] for ф in registry.ФОРМА_АДРЕСА.values()}
    for префикс in формы_инструмента:
        assert префикс in формы, (
            f"{префикс} нет среди проверенных форм {sorted(формы)}")
