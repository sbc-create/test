"""Вердикт готовности обязан возвращаться быстрее, чем клиент перестаёт ждать.

Повод измерен 2026-10-04 по журналу моста и воспроизведён замером. Qwen вызвал
`domain_indexing_readiness` с `site=lordfilm47.space` в 18:12 UTC — и сообщение
на этом закончилось: виден только вызов с аргументами, без результата и без
следующего шага. В журнале моста записи об этом вызове НЕТ ВОВСЕ, а строка
пишется по завершении: значит вызов не завершился.

Почему он не завершился: у инструмента `prove` по умолчанию было `True`, а этот
путь поднимает выложенный выпуск, чтобы доказать чтение конфигурации. Замеры:

    доказать=False   7.4 с
    доказать=True   53.2 с
    в журнале за день: 76, 78, 95, 153, 154, 159 секунд

Ни один коннектор столько не ждёт, и ответ в 5 КБ тут ни при чём: дело во
времени. Поэтому закреплены два свойства:

* по умолчанию вердикт БЫСТРЫЙ. Доказательство чтения конфигурации — явный
  запрос `prove: true`, и он назван в ответе, чтобы «не доказано» не выглядело
  «доказано»;
* у вызова есть БЮДЖЕТ времени. Превышение не висит и не рвёт соединение, а
  возвращает быстрый вердикт с названной причиной, почему доказательства нет.
"""
from __future__ import annotations

import time

import pytest

from factory.qwen import mcp


def test_по_умолчанию_доказательство_не_запрашивается(monkeypatch):
    вызовы = []

    def подделка(сайт, *, доказать=False):
        вызовы.append(доказать)
        return {"site": сайт, "status": "AWAITING_OWNER"}

    monkeypatch.setattr(mcp.indexing, "готовность", подделка)
    итог = mcp.инструмент_готовности_домена({"site": "t.example"})
    assert вызовы == [False], (
        "по умолчанию инструмент снова поднимает выпуск: это путь на 50-160 "
        "секунд, и клиент перестаёт ждать раньше")
    assert итог["verdict"]["status"] == "AWAITING_OWNER"
    assert "prove" in str(итог.get("proof")), итог.get("proof")


def test_явный_запрос_доказательства_работает(monkeypatch):
    вызовы = []
    monkeypatch.setattr(mcp.indexing, "готовность",
                        lambda сайт, *, доказать=False: вызовы.append(доказать)
                        or {"site": сайт, "status": "OPEN_CONFIRMED"})
    mcp.инструмент_готовности_домена({"site": "t.example", "prove": True})
    assert вызовы == [True]


def test_превышение_бюджета_возвращает_быстрый_вердикт(monkeypatch):
    """Долгое доказательство не вешает вызов и не рвёт соединение."""
    def медленно(сайт, *, доказать=False):
        if доказать:
            time.sleep(5)
            return {"site": сайт, "status": "OPEN_CONFIRMED", "proved": True}
        return {"site": сайт, "status": "AWAITING_OWNER"}

    monkeypatch.setattr(mcp.indexing, "готовность", медленно)
    monkeypatch.setattr(mcp, "БЮДЖЕТ_ДОКАЗАТЕЛЬСТВА_С", 1)
    н = time.monotonic()
    итог = mcp.инструмент_готовности_домена({"site": "t.example", "prove": True})
    прошло = time.monotonic() - н
    assert прошло < 4, f"вызов висел {прошло:.1f}с вместо бюджета"
    assert итог["verdict"]["status"] == "AWAITING_OWNER", итог
    assert "бюджет" in str(итог.get("proof")).lower(), итог.get("proof")
    assert итог["verdict"].get("proved") is None, (
        "вердикт выдан за доказанный, хотя доказательство не успело")


def test_ответ_называет_чего_в_нём_нет(monkeypatch):
    monkeypatch.setattr(mcp.indexing, "готовность",
                        lambda сайт, *, доказать=False: {"site": сайт,
                                                         "status": "AWAITING_OWNER"})
    итог = mcp.инструмент_готовности_домена({"site": "t.example"})
    текст = str(итог.get("proof"))
    assert "не поднимался" in текст or "не поднимался" in текст.lower(), текст
    assert "prove" in текст


def test_начало_вызова_журналируется():
    """Незавершённый вызов обязан оставлять след.

    Измерено 2026-10-04: вызов из чата не завершился, и в журнале моста не
    осталось ни одной строки — она писалась только по завершении. Отсутствие
    следа неотличимо от отсутствия вызова, и место обрыва приходилось
    устанавливать по времени старта службы.
    """
    import pathlib
    import re

    текст = pathlib.Path("factory/qwen/mcp.py").read_text(encoding="utf-8")
    участок = текст[текст.index('if метод == "tools/call":'):]
    участок = участок[:участок.index("except ОшибкаИнструмента")]
    assert re.search(r'записать_вызов\([^)]*исход="started"', участок, re.S), (
        "начало вызова не журналируется: незавершённый вызов снова не оставит "
        "следа")
    # И порядок: сначала след, потом работа.
    assert участок.index('исход="started"') < участок.index("полезное = вызвать")
