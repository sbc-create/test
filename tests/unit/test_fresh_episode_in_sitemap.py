def test_первый_результат_поиска_слагом_не_является():
    # Ровно эта ошибка дала «17 из 17 названы» и скрыла семь пропусков.
    кандидаты = [("magiya-vernuvshegosya-dolzhna-byt-osobennoy",
                  "Магия вернувшегося должна быть особенной"),
                 ("magiya-vernuvshegosya-dolzhna-byt-osobennoy-2",
                  "Магия вернувшегося должна быть особенной 2")]
    выбран = модуль.выбрать_слаг("Магия вернувшегося должна быть особенной 2",
                                 кандидаты)
    assert выбран == "magiya-vernuvshegosya-dolzhna-byt-osobennoy-2"


