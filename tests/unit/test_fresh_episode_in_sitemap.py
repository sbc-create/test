"""Новая серия против карты: отбор событий, опознание слага, исходы.

Главный тест — `test_первый_результат_поиска_слагом_не_является`: именно эта
ошибка дала ложный ответ «17 из 17 названы» и скрыла семь пропущенных серий.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "fresh-episode-in-sitemap.py"

спец = importlib.util.spec_from_file_location("fresh_episode", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


def событие(имя: str, когда: str, до: int, вид: str = "EPISODE_ADDED") -> str:
    return json.dumps({"name": имя, "observedAt": когда, "to": до,
                       "kind": вид}, ensure_ascii=False)


# --- отбор событий ---------------------------------------------------------

def test_по_работе_берётся_самое_позднее_событие():
    строки = [событие("Акварион", "2026-10-21T10:00:00Z", 2),
              событие("Акварион", "2026-10-21T18:00:00Z", 3),
              событие("Акварион", "2026-10-21T14:00:00Z", 5)]
    работы = модуль.последние_по_работе(строки, не_раньше="2026-10-20T00:00:00Z")
    assert len(работы) == 1
    assert работы[0]["to"] == 3  # то, что наблюдалось позже всех
    assert работы[0]["observedAt"] == "2026-10-21T18:00:00Z"


def test_старые_события_отбрасываются():
    строки = [событие("Старое", "2026-10-01T10:00:00Z", 4)]
    assert модуль.последние_по_работе(
        строки, не_раньше="2026-10-20T00:00:00Z") == []


def test_чужие_виды_событий_не_считаются():
    строки = [событие("Озвучка", "2026-10-21T10:00:00Z", 3, "VOICEOVER_ADDED"),
              событие("Создание", "2026-10-21T10:00:00Z", 1, "TITLE_CREATED")]
    assert модуль.последние_по_работе(
        строки, не_раньше="2026-10-20T00:00:00Z") == []


def test_событие_без_имени_или_без_номера_пропускается():
    строки = [json.dumps({"kind": "EPISODE_ADDED",
                          "observedAt": "2026-10-21T10:00:00Z", "to": 3}),
              json.dumps({"kind": "EPISODE_ADDED", "name": "Без номера",
                          "observedAt": "2026-10-21T10:00:00Z"})]
    assert модуль.последние_по_работе(
        строки, не_раньше="2026-10-20T00:00:00Z") == []


def test_битая_строка_журнала_не_валит_разбор():
    строки = ["{это не json", событие("Живое", "2026-10-21T10:00:00Z", 2)]
    работы = модуль.последние_по_работе(строки, не_раньше="2026-10-20T00:00:00Z")
    assert len(работы) == 1


# --- опознание слага -------------------------------------------------------

def test_первый_результат_поиска_слагом_не_является():
    # Ровно эта ошибка дала «17 из 17 названы» и скрыла семь пропусков.
    кандидаты = [("magiya-vernuvshegosya-dolzhna-byt-osobennoy",
                  "Магия вернувшегося должна быть особенной"),
                 ("magiya-vernuvshegosya-dolzhna-byt-osobennoy-2",
                  "Магия вернувшегося должна быть особенной 2")]
    выбран = модуль.выбрать_слаг("Магия вернувшегося должна быть особенной 2",
                                 кандидаты)
    assert выбран == "magiya-vernuvshegosya-dolzhna-byt-osobennoy-2"


def test_похожее_имя_слагом_не_становится():
    кандидаты = [("akvarion", "Акварион"), ("akvarion-logos", "Акварион: Логос")]
    assert модуль.выбрать_слаг("Акварион ТВ-2", кандидаты) == ""


def test_пробелы_по_краям_имени_не_мешают():
    assert модуль.выбрать_слаг(" Акварион ",
                               [("akvarion", "Акварион ")]) == "akvarion"


def test_пустой_список_кандидатов():
    assert модуль.выбрать_слаг("Акварион", []) == ""


def test_заголовок_страницы_не_найден_слагом_не_считается():
    assert модуль.выбрать_слаг("Акварион", [("akvarion", "")]) == ""


# --- исходы ----------------------------------------------------------------

def test_адрес_в_карте_названа():
    assert модуль.исход(True, 200) == модуль.НАЗВАНА


def test_страница_есть_адреса_нет_это_дефект():
    assert модуль.исход(False, 200) == модуль.НЕ_НАЗВАНА


@pytest.mark.parametrize("код", [404, 500, 0, 308])
def test_страницы_нет_это_не_пробел_карты(код):
    assert модуль.исход(False, код) == модуль.СТРАНИЦЫ_НЕТ


def test_вид_события_назван_одним_местом():
    # Чтобы добавление вида не разъехалось по файлу.
    assert модуль.ВИД_НОВОЙ_СЕРИИ == ("EPISODE_ADDED",)
