def _событие(имя, когда, серия=1):
    import json as _json
    return _json.dumps({"kind": "EPISODE_ADDED", "name": имя, "to": серия,
                        "observedAt": когда}, ensure_ascii=False)


def test_последние_по_работе_берёт_самое_позднее_событие():
    строки = [_событие("Работа", "2026-10-20T10:00:00Z", 5),
              _событие("Работа", "2026-10-21T10:00:00Z", 7)]
    работы = модуль.последние_по_работе(строки, не_раньше="2026-10-19T00:00:00Z")
    assert len(работы) == 1
    assert работы[0]["to"] == 7


def test_предел_режет_по_свежести_а_не_по_порядку_журнала(monkeypatch, tmp_path):
    """Расширение окна не должно молча выбрасывать свежие работы.

    Измерено 22.10: при `--hours 72` из перечня исчезла работа, наблюдённая
    21.10 в 17:42Z, и вместо неё вошли три работы от 19.10 — потому что
    `[:предел]` отрезал от несортированного набора (порядок словаря = порядок
    первого появления в журнале). Числа двух прогонов выглядели сравнимыми и
    сравнимыми не были.
    """
    журнал = tmp_path / "episode-state.jsonl"
    # В журнале СТАРЫЕ работы идут первыми — как в настоящем журнале.
    журнал.write_text("\n".join([
        _событие("Старая 1", "2026-10-19T10:00:00Z"),
        _событие("Старая 2", "2026-10-19T11:00:00Z"),
        _событие("Свежая", "2026-10-21T17:42:00Z"),
    ]), encoding="utf-8")

    monkeypatch.setattr(модуль, "адреса_серий", lambda домен: {"https://d/x"})
    monkeypatch.setattr(модуль, "_достать", lambda url, таймаут=40: "")
    monkeypatch.setattr(модуль, "_заголовок", lambda т: "")

    итог = модуль.проверить("d", журнал, часов=72, предел=1)
    assert итог["работ"] == 1
    assert итог["работ_всего_в_окне"] == 3
    assert итог["предел_достигнут"] is True
    # Взята должна быть САМАЯ СВЕЖАЯ, а не первая по журналу.
    assert итог["подробно"][0]["работа"] == "Свежая"


def test_предел_не_достигнут_значит_перечень_полон(monkeypatch, tmp_path):
    журнал = tmp_path / "episode-state.jsonl"
    журнал.write_text(_событие("Одна", "2026-10-21T10:00:00Z"),
                      encoding="utf-8")
    monkeypatch.setattr(модуль, "адреса_серий", lambda домен: {"https://d/x"})
    monkeypatch.setattr(модуль, "_достать", lambda url, таймаут=40: "")
    monkeypatch.setattr(модуль, "_заголовок", lambda т: "")
    итог = модуль.проверить("d", журнал, часов=72, предел=40)
    assert итог["работ"] == итог["работ_всего_в_окне"] == 1
    assert итог["предел_достигнут"] is False

