"""Проверки разделения «витрина не подставила» и «у записи нет изображения».

Это единственное содержательное свойство инструмента, и ошибиться в нём — то же
самое, что назвать состояние данных дефектом витрины. Один раз за смену я уже
приписал карточку не той полке и построил на этом ложную причинную связь,
поэтому полка тоже проверяется.

Отрицательные контроли, названные заранее:

* постеры ПОХОЖИХ работ ниже по странице не считаются изображением самого
  произведения: иначе у записи без постера «изображение есть» находилось бы
  всегда;
* непрочитанная страница произведения — «не измерено», а не «у записи нет»;
* страница без распознанного блока постера — тоже «не измерено», а не вывод.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "poster_coverage", КОРЕНЬ / "automation/local/poster-coverage.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

ПОХОЖИЕ = ('<section class="similar">'
           + "".join(f'<img src="https://poster.cdnvideohub.com/s{n}.webp">'
                     for n in range(6))
           + "</section>")


def _страница_записи(*, свой_постер: bool, имя="Facing Grizzlies"):
    блок = ('<div class="ztitle__poster">'
            + ('<img src="https://poster.cdnvideohub.com/own.webp">'
               if свой_постер
               else '<span class="zt__none" aria-hidden="true"><b>F</b></span>')
            + "</div>")
    # Похожие работы идут НИЖЕ h1 — ровно так, как на живой витрине.
    return f"<html><body>{блок}<h1>{имя}</h1>{ПОХОЖИЕ}</body></html>"


def test_у_записи_изображения_нет():
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=False))
    assert р["своих_изображений"] == 0
    assert р["заглушек"] >= 1
    assert "у записи изображения НЕТ" in р["чьё"]
    assert р["имя"] == "Facing Grizzlies"


def test_у_записи_изображение_есть():
    """Положительный контроль: инструмент умеет обвинить витрину."""
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=True))
    assert р["своих_изображений"] >= 1
    assert "не подставила витрина" in р["чьё"]


def test_постеры_похожих_работ_не_считаются():
    """Отрицательный контроль: шесть постеров ниже h1 не делают вывод «есть»."""
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=False))
    assert "у записи изображения НЕТ" in р["чьё"]


def test_непрочитанная_страница_не_вывод():
    assert "не_измерено" in ИНСТР.чьё_отсутствие("")


def test_страница_без_блока_постера_не_вывод():
    р = ИНСТР.чьё_отсутствие("<html><body><h1>Имя</h1></body></html>")
    assert "не измерено" in р["чьё"]


def test_имя_читается_из_h1():
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=False, имя="Тедди"))
    assert р["имя"] == "Тедди"


def test_хост_постеров_не_запрашивается():
    """Хост не в списке разрешённых: инструмент только ищет упоминания."""
    исходник = (КОРЕНЬ / "automation/local/poster-coverage.py").read_text(
        encoding="utf-8")
    # Единственные упоминания хоста — постоянная и её описание, запросов нет.
    assert 'urlopen' in исходник  # запросы к витринам есть
    строки = [с for с in исходник.splitlines()
              if ИНСТР.ХОСТ_ПОСТЕРОВ in с and "urlopen" in с]
    assert строки == []


# --- предел выборки: ноль означает ВСЕ карточки ------------------------------
#
# Повод измерен 20.10 на zonafilm.space. Зонд смотрел первые 24 карточки и
# напечатал «без изображения 1». Линия SEO независимо насчитала ШЕСТЬ по полке
# «Высокие оценки недели» — и права она: на главной карточек 64, и полка в
# первые 24 целиком не попадала. Предел занижал молча, а итог печатался без
# оговорки о выборке.

def test_ноль_означает_все_карточки():
    assert ИНСТР.ВСЕ_КАРТОЧКИ == 0


def test_умолчание_смотрит_все_карточки():
    import inspect
    подпись = inspect.signature(ИНСТР.по_домену)
    assert подпись.parameters["сколько"].default == ИНСТР.ВСЕ_КАРТОЧКИ


def test_ключ_cards_по_умолчанию_все():
    исходник = ИНСТР.ПУТЬ.read_text(encoding="utf-8") if hasattr(ИНСТР, "ПУТЬ") \
        else pathlib.Path(ИНСТР.__file__).read_text(encoding="utf-8")
    assert 'default=ВСЕ_КАРТОЧКИ' in исходник
    assert '0 — все' in исходник


def test_основание_правки_названо_числами():
    """«Предел занижал» — утверждение, и у него должно быть измерение."""
    исходник = pathlib.Path(ИНСТР.__file__).read_text(encoding="utf-8")
    текст = " ".join(исходник.split())
    assert "ДЕСЯТЬ" in текст or "десять" in текст
    assert "первых 24" in текст
    assert "Высокие оценки недели" in текст


# --- вторая форма заглушки: c__none у lords-02 -------------------------------
#
# Измерено 20.10 на lordserial33.biz: `/title/pervye-radosti/` отдаёт
# `<div class="tw__ps"><span class="c__none"><b>П</b></span></div>` сразу перед
# `<h1>` — букву-заглушку. Зная только `zt__none`, зонд отвечал «блок постера
# произведения не распознан» по восьми карточкам этой витрины. Вместе с
# пределом выборки два ограничения скрывали 21 карточку из 22 по семейству.

def test_обе_формы_заглушки_объявлены():
    assert "zt__none" in ИНСТР.ЗАГЛУШКИ
    assert "c__none" in ИНСТР.ЗАГЛУШКИ


def test_прежнее_имя_сохранено_для_соседей():
    """На `ЗАГЛУШКА` ссылаются проверки и соседние инструменты."""
    assert ИНСТР.ЗАГЛУШКА == "zt__none"


def test_буква_заглушка_lords02_считается_отсутствием():
    страница = (
        '<nav class="crumbs">x</nav><main><div class="tw">'
        '<div class="tw__ps"><span class="c__none" aria-hidden="true">'
        '<b>П</b></span></div><div><h1>Первые радости</h1></div></div></main>')
    итог = ИНСТР.чьё_отсутствие(страница)
    assert "изображения НЕТ" in итог["чьё"], итог


def test_постер_zona_формы_по_прежнему_распознаётся():
    """Положительный контроль: правка не ломает прежнюю форму."""
    страница = (
        '<div class="ztitle__poster">'
        f'<img src="https://{ИНСТР.ХОСТ_ПОСТЕРОВ}/a.webp">'
        '</div><h1>Название</h1>')
    итог = ИНСТР.чьё_отсутствие(страница)
    assert "изображения НЕТ" not in итог.get("чьё", ""), итог


def test_локальный_путь_постера_считается_изображением():
    """lords-02 отдаёт постеры локальным путём /poster/<uuid>.webp.

    Признак различающий: проверяется не отсутствие слов «изображения НЕТ» (так
    отвечает и третья ветка «мерить нечем»), а ИМЕННО исход «изображение ЕСТЬ».
    Без распознавания локального пути страница с заглушкой И локальным постером
    давала бы «изображения НЕТ».
    """
    страница = ('<div class="tw__ps"><span class="c__none"><b>И</b></span>'
                '<img src="/poster/abc.webp"></div><h1>Имя</h1>')
    итог = ИНСТР.чьё_отсутствие(страница)
    assert "изображение ЕСТЬ" in итог.get("чьё", ""), итог
