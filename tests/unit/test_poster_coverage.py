"""Проверки разделения «витрина не подставила» и «у записи нет изображения».

Это единственное содержательное свойство инструмента, и ошибиться в нём — то же
самое, что назвать состояние данных дефектом витрины. Один раз за смену я уже
приписал карточку не той полке и построил на этом ложную причинную связь,
поэтому полка тоже проверяется.

Отрицательные контроли, названные заранее:

* постеры ПОХОЖИХ работ ниже по странице не считаются изображением самого
  произведения: иначе у записи без постера «изображение есть» находилось бы
  всегда;
* непрочитанная страница произведения — «не измерено», а не «у записи нет»;
* страница без распознанного блока постера — тоже «не измерено», а не вывод.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "poster_coverage", КОРЕНЬ / "automation/local/poster-coverage.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

ПОХОЖИЕ = ('<section class="similar">'
           + "".join(f'<img src="https://poster.cdnvideohub.com/s{n}.webp">'
                     for n in range(6))
           + "</section>")


def _страница_записи(*, свой_постер: bool, имя="Facing Grizzlies"):
    блок = ('<div class="ztitle__poster">'
            + ('<img src="https://poster.cdnvideohub.com/own.webp">'
               if свой_постер
               else '<span class="zt__none" aria-hidden="true"><b>F</b></span>')
            + "</div>")
    # Похожие работы идут НИЖЕ h1 — ровно так, как на живой витрине.
    return f"<html><body>{блок}<h1>{имя}</h1>{ПОХОЖИЕ}</body></html>"


def test_у_записи_изображения_нет():
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=False))
    assert р["своих_изображений"] == 0
    assert р["заглушек"] >= 1
    assert "у записи изображения НЕТ" in р["чьё"]
    assert р["имя"] == "Facing Grizzlies"


def test_у_записи_изображение_есть():
    """Положительный контроль: инструмент умеет обвинить витрину."""
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=True))
    assert р["своих_изображений"] >= 1
    assert "не подставила витрина" in р["чьё"]


def test_постеры_похожих_работ_не_считаются():
    """Отрицательный контроль: шесть постеров ниже h1 не делают вывод «есть»."""
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=False))
    assert "у записи изображения НЕТ" in р["чьё"]


def test_непрочитанная_страница_не_вывод():
    assert "не_измерено" in ИНСТР.чьё_отсутствие("")


def test_страница_без_блока_постера_не_вывод():
    р = ИНСТР.чьё_отсутствие("<html><body><h1>Имя</h1></body></html>")
    assert "не измерено" in р["чьё"]


def test_имя_читается_из_h1():
    р = ИНСТР.чьё_отсутствие(_страница_записи(свой_постер=False, имя="Тедди"))
    assert р["имя"] == "Тедди"


def test_хост_постеров_не_запрашивается():
    """Хост не в списке разрешённых: инструмент только ищет упоминания."""
    исходник = (КОРЕНЬ / "automation/local/poster-coverage.py").read_text(
        encoding="utf-8")
    # Единственные упоминания хоста — постоянная и её описание, запросов нет.
    assert 'urlopen' in исходник  # запросы к витринам есть
    строки = [с for с in исходник.splitlines()
              if ИНСТР.ХОСТ_ПОСТЕРОВ in с and "urlopen" in с]
    assert строки == []
