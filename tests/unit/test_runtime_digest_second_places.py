"""Отпечаток рантайма записан не в одном месте — и каждое под проверкой.

Откуда взялась проверка
-----------------------

Сессия animedia.space сообщила 2026-09-30: после правки рантайма её
`checks/entrypoint_present.py` отказал, потому что в `pins.lock.json` осталось
прежним поле `runtime_artifact_sha256` — отдельное от `files[].sha256`. У неё
это случилось дважды. У меня в тот же день — трижды, в трёх разных полях:
`artifact_sha256` манифеста animego-03 (остановил установку), `template_sha256`
в замке zonafilm-cc, `runtime_artifact_sha256` в замке animedia-space. Каждый
раз я узнавал о существовании поля от УПАВШЕЙ проверки витрины, а не заранее.

Общая форма дефекта: отпечаток одного и того же файла записан в двух местах,
систематически сверяется одно, а второе поддерживается руками. Оно и стареет.

Что проверяется
---------------

Поля, которые описывают ТЕКУЩЕЕ содержимое репозитория, обязаны сходиться с
файлом, который описывают. Список полей закрытый и перечислен здесь поимённо:
новое поле такого рода придётся добавить сюда осознанно, и это лучше, чем
узнать о нём от упавшего выпуска.

Чего проверка НЕ делает
-----------------------

Она не сверяет `artifact_sha256` и `code_file_sha256` в манифестах шаблона тех
витрин, где эти поля — ЗАПИСЬ О ПРОШЛОЙ СБОРКЕ, а не о рабочем дереве. Признак
прямой: рядом стоят `build_id` и `source_commit` минувшего выпуска
(`20260921T134330Z-515fcf0-cardfix`, `zona-01-a0209877e1db`), в репозитории нет
инструмента, который штампует манифест при каждой правке, и ни одна проверка
витрины это поле не читает. Сверять такое с сегодняшним деревом — значит
сравнивать две разные величины; «исправление» такого расхождения было бы ровно
тем подгоном манифеста под содержимое, который владелец запретил отдельно.

У витрин AnimeGo те же поля означают обратное: их держит в согласии
`tools/stamp_manifest.py`, и `checks/manifest_and_entrypoint.py` их читает.
Второго места, о котором можно забыть, там нет — поэтому и здесь они не нужны.

Поля с суффиксом `previous_sha256` не сверяются никогда: это история, и
совпадение с сегодняшним файлом означало бы, что правки не было.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕПОЗИТОРИИ = КОРЕНЬ / "var" / "site-repos"


def _sha(путь: Path) -> str:
    return hashlib.sha256(путь.read_bytes()).hexdigest()


def _точка_входа(проект: Path) -> str:
    """Имя файла рантайма — из замка проекта, а не по догадке."""
    замок = проект / "pins.lock.json"
    if not замок.is_file():
        return ""
    try:
        данные = json.loads(замок.read_text(encoding="utf-8"))
    except ValueError:
        return ""
    return str((данные.get("pins") or {}).get("entrypoint") or "")


def _случаи():
    """Каждое РУКОТВОРНОЕ второе место: (витрина, поле, объявлено, файл).

    Поля перечислены поимённо. Их два, и оба найдены отказом проверки витрины
    уже после правки — ровно тот способ узнавать, который эта проверка и
    заменяет.
    """
    итог = []
    if not РЕПОЗИТОРИИ.is_dir():
        return итог
    for проект in sorted(РЕПОЗИТОРИИ.iterdir()):
        замок = проект / "pins.lock.json"
        if not замок.is_file():
            continue
        try:
            данные = json.loads(замок.read_text(encoding="utf-8"))
        except ValueError:
            continue

        # 1. Отпечаток артефакта рантайма рядом с files[] — второе место в
        #    ОДНОМ файле. Читает checks/entrypoint_present.py витрины.
        объявлено = данные.get("runtime_artifact_sha256")
        точка = _точка_входа(проект)
        if объявлено and точка:
            файл = проект / "src" / точка
            if файл.is_file():
                итог.append(pytest.param(
                    проект.name, "pins.lock.json:runtime_artifact_sha256",
                    объявлено, файл, id=f"{проект.name}-runtime_artifact_sha256"))

        # 2. Отпечаток вендоренного шаблона. Читает
        #    checks/pinned_template_sha.py витрины: у неё рантайм лежит не в
        #    src/, а в template/<версия>/.
        пины = данные.get("pins") or {}
        шаблон = пины.get("template_sha256")
        модуль = (пины.get("modules") or {}).get("runtime")
        if шаблон and модуль:
            файл = проект / "template" / модуль / "lords-frontend.py"
            if файл.is_file():
                итог.append(pytest.param(
                    проект.name, "pins.lock.json:pins.template_sha256",
                    шаблон, файл, id=f"{проект.name}-template_sha256"))
    return итог


СЛУЧАИ = _случаи()


def test_второе_место_вообще_нашлось():
    """Проверка обязана что-то проверять.

    Ноль случаев означал бы не «всё хорошо», а что поля переименовали или
    репозитории не на месте, — и тогда молчание было бы хуже отказа.
    """
    assert СЛУЧАИ, (
        "ни одного рукотворного второго места не найдено: либо перечень полей "
        "устарел, либо var/site-repos не на месте. Молчание здесь не успех.")


@pytest.mark.parametrize("витрина,поле,объявлено,файл", СЛУЧАИ)
def test_рукотворное_второе_место_сходится(витрина, поле, объявлено, файл):
    факт = _sha(файл)
    assert факт == объявлено, (
        f"{витрина}: {поле} объявляет {объявлено[:12]}, а {файл.name} имеет "
        f"{факт[:12]}. Это второе место записи одного и того же отпечатка: "
        "files[].sha256 сверяется систематически, а это поле поддерживается "
        "руками — и стареет первым. Обновите его тем же действием, что и замок.")


def test_история_не_сверяется_с_настоящим():
    """`previous_sha256` — история; совпадение означало бы отсутствие правки."""
    совпали = []
    if not РЕПОЗИТОРИИ.is_dir():
        pytest.skip("var/site-repos не на месте")
    for проект in sorted(РЕПОЗИТОРИИ.iterdir()):
        замок = проект / "pins.lock.json"
        if not замок.is_file():
            continue
        try:
            данные = json.loads(замок.read_text(encoding="utf-8"))
        except ValueError:
            continue
        for имя, мета in (данные.get("files") or {}).items():
            if not isinstance(мета, dict) or not мета.get("previous_sha256"):
                continue
            файл = проект / имя if (проект / имя).is_file() else проект / "src" / имя
            if файл.is_file() and _sha(файл) == мета["previous_sha256"]:
                совпали.append(f"{проект.name}:{имя}")
    assert not совпали, (
        "previous_sha256 совпал с текущим файлом: " + ", ".join(совпали)
        + ". Либо правку откатили, либо поле перестало быть историей.")
