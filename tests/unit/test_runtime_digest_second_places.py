"""Отпечаток, записанный рукой, обязан сходиться. Различитель — КТО ПИШЕТ.

Откуда взялась проверка
-----------------------

Сессия animedia.space сообщила 2026-09-30: после правки рантайма её
`checks/entrypoint_present.py` отказал, потому что в `pins.lock.json` осталось
прежним поле `runtime_artifact_sha256` — отдельное от `files[].sha256`. У неё
это второй раз. У меня в тот же день — трижды и в трёх разных полях:
`artifact_sha256` манифеста animego-03 (остановил установку 29.09),
`pins.template_sha256` в замке zonafilm-cc, `runtime_artifact_sha256` в замке
animedia-space. Каждый раз о существовании поля сообщала УПАВШАЯ проверка
витрины, а не эта.

Почему различитель именно «кто пишет»
-------------------------------------

Первая версия этой проверки держала закрытый список полей и отделяла «записи о
прошлом» признаком «ни одна проверка витрины это поле не читает». Сессия
animedia.space возразила, и возражение верное: «никто не читает» — признак
слабый, завтра кто-нибудь прочитает и получит цифру прошлого выпуска, не
заметив разницы. Надёжнее спросить, КТО ПИШЕТ:

* поле пишет инструмент сборки — значение ПРОИЗВОДНОЕ. Сверять закоммиченное с
  деревом бессмысленно по построению: оно и не обязано совпадать. В
  `tools/build_release.py` витрин это записано прямым текстом — «поле, которое
  надо помнить обновлять руками, однажды забывают обновить; вычисленное
  расходиться не умеет»;
* поле не пишет никто — значит его пишет человек. Дальше решает ВТОРОЙ вопрос:
  читает ли его хоть одна проверка витрины. Читает — поле ДЕЙСТВУЮЩЕЕ, оно
  обязано сходиться с тем, что описывает. Не читает — это ЗАПИСЬ: о прошлом
  выпуске, об одобрении владельца, о версии чужой зависимости.

Один «кто читает» был бы слабым признаком — возражение сессии animedia.space
верное: завтра кто-нибудь прочитает и получит цифру прошлого выпуска. Но вторым
шагом, после отсева производных, он работает, и это проверено на флоте. Иначе
рукотворными «вторыми местами» пришлось бы считать и `rollback_target_sha256`
(по имени — отпечаток ПРЕДЫДУЩЕГО артефакта), и `pinned_from.code_sha256` рядом
с `release` и `why`, и `dependencies.src/community.py.sha256` — версию модуля,
который приезжает отдельным выпуском и этому репозиторию не принадлежит.
Требовать от них совпадения с сегодняшним деревом значило бы требовать, чтобы
история равнялась настоящему.

Классификация поэтому не задаётся списком, а ВЫВОДИТСЯ из репозитория: новое
рукотворное поле попадёт под проверку само, а не после первого отказа выпуска.
Измерено на флоте: `artifact_sha256` пишет `build_release.py` в шестнадцати
репозиториях (у an1meg0-site ещё и `stamp_manifest.py` — там оно держится в
согласии с деревом), `code_file_sha256` пишет только `stamp_manifest.py`, а
`runtime_artifact_sha256` и `pins.template_sha256` не пишет никто.

Чего проверка не делает
-----------------------

`files[].sha256` здесь не сверяется: его систематически проверяет
`checks/verify_pins.py` каждой витрины. Поля `previous_sha256` — история, и
совпадение с текущим файлом означало бы, что правки не было; на это отдельная
проверка.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕПОЗИТОРИИ = КОРЕНЬ / "var" / "site-repos"

#: Где ищем записанные отпечатки.
ИСТОЧНИКИ = ("pins.lock.json", "config/template-manifest.json",
             "template-manifest.json", "site-manifest.json")

#: Чем описываемый файл находится по имени поля. Поле, которого здесь нет и
#: которое никто не пишет, — повод отказать, а не промолчать: это и есть «новое
#: рукотворное второе место», о котором иначе узнаёшь от упавшего выпуска.
def _файл_поля(проект: Path, поле: str, данные: dict) -> Path | None:
    пины = данные.get("pins") or {}
    точка = str(пины.get("entrypoint") or "")
    if поле == "runtime_artifact_sha256" and точка:
        return проект / "src" / точка
    if поле == "template_sha256":
        модуль = (пины.get("modules") or {}).get("runtime")
        if модуль:
            return проект / "template" / модуль / "lords-frontend.py"
    if поле == "indexing_core_registry_sha256":
        # Отпечаток ВНЕШНЕГО файла хоста, а не файла репозитория.
        return Path("/srv/lords/.frontend/indexing-core-registry.json")
    return None


def _файл_зависимости(проект: Path, адрес: str) -> Path | None:
    """`dependencies.<путь>.sha256` описывает файл `<путь>` этого репозитория.

    Так закреплён модуль сообщества: он приезжает отдельным выпуском, правится
    не здесь, и запись отвечает на вопрос «против какой его версии собрана
    витрина». Поле рукотворное и ДЕЙСТВУЮЩЕЕ — его читает `verify_pins.py`
    витрины, — поэтому сходиться обязано.
    """
    м = re.fullmatch(r"[^:]+:dependencies\.(.+)\.sha256", адрес)
    if not м:
        return None
    путь = проект / м.group(1)
    return путь if путь.is_file() else None

#: Расхождения, о которых известно и которые исправлять нельзя не разобравшись.
#:
#: `indexing_core_registry_sha256` у пяти витрин Yummy: поле записано рукой, его
#: не пишет ни один инструмент и не читает ни одна проверка, а описывает оно
#: ОБЩИЙ файл хоста `/srv/lords/.frontend/indexing-core-registry.json`, который
#: меняется сам по себе. Объявлено `a2ee4d13…`, фактически `dee29de9…`.
#:
#: Что это — застывшая запись «реестр на момент выделения ячейки» или
#: неисполняемое требование «реестр обязан быть таким» — по репозиторию не
#: устанавливается. Обновить значение молча значило бы закрепить сегодняшнее
#: состояние, не зная замысла; удалить — выбросить чужую запись. Поэтому
#: расхождение названо здесь и вынесено владельцу, а не «исправлено».
ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ = {
    ("yummyani-biz", "pins.lock.json:pins.indexing_core_registry_sha256"),
    ("yummyani-org", "pins.lock.json:pins.indexing_core_registry_sha256"),
    ("yummyani-site", "pins.lock.json:pins.indexing_core_registry_sha256"),
    ("yummyani7-info", "pins.lock.json:pins.indexing_core_registry_sha256"),
    ("yummyani7-site", "pins.lock.json:pins.indexing_core_registry_sha256"),
}


def _sha(путь: Path) -> str:
    return hashlib.sha256(путь.read_bytes()).hexdigest()


def _пишущие(проект: Path, поле: str) -> list[str]:
    """Инструменты репозитория, которые ЗАПИСЫВАЮТ это поле."""
    каталог = проект / "tools"
    if not каталог.is_dir():
        return []
    итог = []
    for файл in sorted(каталог.glob("*.py")):
        текст = файл.read_text(encoding="utf-8", errors="replace")
        if (re.search(rf'["\']{re.escape(поле)}["\']\s*:', текст)
                or re.search(rf'\[["\']{re.escape(поле)}["\']\]\s*=', текст)):
            итог.append(файл.name)
    return итог


def _читающие(проект: Path, поле: str) -> list[str]:
    """Проверки витрины, которые ЧИТАЮТ это поле.

    Читают — значит поле действующее: витрина сама не выпустится, если оно
    разошлось. Не читает никто — значит это запись, а не требование.
    """
    каталог = проект / "checks"
    if not каталог.is_dir():
        return []
    return [ф.name for ф in sorted(каталог.glob("*.py"))
            if поле in ф.read_text(encoding="utf-8", errors="replace")]


def _отпечатки(проект: Path):
    """Все записанные отпечатки проекта, кроме files[] и истории."""
    for имя in ИСТОЧНИКИ:
        файл = проект / имя
        if not файл.is_file():
            continue
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
        except ValueError:
            continue

        def обход(узел, путь=""):
            if not isinstance(узел, dict):
                return
            for ключ, значение in узел.items():
                полный = f"{путь}{ключ}"
                if isinstance(значение, str) and re.fullmatch(r"[0-9a-f]{64}", значение):
                    if полный.startswith("files.") or ключ.endswith("previous_sha256"):
                        continue
                    yield_список.append((имя, полный, ключ, значение, данные))
                else:
                    обход(значение, f"{полный}.")

        yield_список: list = []
        обход(данные)
        for э in yield_список:
            yield э


def _случаи():
    итог = []
    if not РЕПОЗИТОРИИ.is_dir():
        return итог
    for проект in sorted(РЕПОЗИТОРИИ.iterdir()):
        if not проект.is_dir():
            continue
        for источник, полный, ключ, значение, данные in _отпечатки(проект):
            итог.append(pytest.param(
                проект, f"{источник}:{полный}", ключ, значение, данные,
                id=f"{проект.name}-{полный}"))
    return итог


СЛУЧАИ = _случаи()


def test_отпечатки_вообще_нашлись():
    """Ноль случаев — это не «всё хорошо», а «проверка ничего не смотрит»."""
    assert СЛУЧАИ, ("ни одного записанного отпечатка не найдено: либо перечень "
                    "источников устарел, либо var/site-repos не на месте")


@pytest.mark.parametrize("проект,адрес,ключ,объявлено,данные", СЛУЧАИ)
def test_рукотворный_отпечаток_сходится(проект, адрес, ключ, объявлено, данные):
    if _пишущие(проект, ключ):
        # Производное значение: его вычисляет инструмент при сборке, и
        # закоммиченное с деревом сходиться не обязано.
        return
    if not _читающие(проект, ключ):
        # Запись, а не требование: о прошлом выпуске, об одобрении владельца,
        # о версии чужой зависимости. Сверять с сегодняшним деревом нечего.
        return
    файл = _файл_поля(проект, ключ, данные) or _файл_зависимости(проект, адрес)
    assert файл is not None, (
        f"{проект.name}: поле {адрес} не пишет ни один инструмент, но читает "
        f"{_читающие(проект, ключ)} — значит оно действующее и рукотворное, — "
        "а чем оно описывается, здесь не объявлено. Назовите файл в "
        "_файл_поля: такое поле стареет молча и валит выпуск после правки.")
    if not файл.is_file():
        pytest.skip(f"{проект.name}: {файл} недоступен на этой машине")
    факт = _sha(файл)
    if (проект.name, адрес) in ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ:
        assert факт != объявлено, (
            f"{проект.name}: {адрес} внезапно сошлось. Расхождение было "
            "известным и вынесено владельцу — уберите запись из "
            "ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ вместе с объяснением, что изменилось.")
        return
    assert факт == объявлено, (
        f"{проект.name}: {адрес} объявляет {объявлено[:12]}, а {файл.name} "
        f"имеет {факт[:12]}. Это поле не пишет ни один инструмент — оно "
        "рукотворное, и обновлять его надо тем же действием, что и замок.")


def test_перечень_известных_расхождений_не_растёт_молча():
    """Известное расхождение остаётся известным только пока оно названо."""
    живые = set()
    for проект, адрес, ключ, объявлено, данные in [
            (p.values[0], p.values[1], p.values[2], p.values[3], p.values[4])
            for p in СЛУЧАИ]:
        if _пишущие(проект, ключ) or not _читающие(проект, ключ):
            continue
        файл = _файл_поля(проект, ключ, данные) or _файл_зависимости(проект, адрес)
        if файл is None or not файл.is_file():
            continue
        if _sha(файл) != объявлено:
            живые.add((проект.name, адрес))
    новые = живые - ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ
    assert not новые, (
        "новое расхождение рукотворного отпечатка: " + ", ".join(sorted(map(str, новые)))
        + ". Либо приведите поле в согласие, либо внесите его в "
        "ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ с объяснением, почему исправлять нельзя.")


def test_история_не_сверяется_с_настоящим():
    """`previous_sha256` — история; совпадение означало бы отсутствие правки."""
    совпали = []
    if not РЕПОЗИТОРИИ.is_dir():
        pytest.skip("var/site-repos не на месте")
    for проект in sorted(РЕПОЗИТОРИИ.iterdir()):
        замок = проект / "pins.lock.json"
        if not замок.is_file():
            continue
        try:
            данные = json.loads(замок.read_text(encoding="utf-8"))
        except ValueError:
            continue
        for имя, мета in (данные.get("files") or {}).items():
            if not isinstance(мета, dict) or not мета.get("previous_sha256"):
                continue
            файл = проект / имя if (проект / имя).is_file() else проект / "src" / имя
            if файл.is_file() and _sha(файл) == мета["previous_sha256"]:
                совпали.append(f"{проект.name}:{имя}")
    assert not совпали, (
        "previous_sha256 совпал с текущим файлом: " + ", ".join(совпали)
        + ". Либо правку откатили, либо поле перестало быть историей.")
