# --- договор JSON, от которого зависит регулярный прогон ------------------

def test_json_несёт_ключи_на_которые_опирается_расписание():
    """С 27.10 шаг `editorial` плана `seo-regular-check` (05:25/11:25/17:25/
    23:25Z) вызывает этот инструмент с `--json` и читает из ответа
    `измерено` и `витрины[].{витрина, подборки|анонсы}.{исход, беды,
    ревизия каталога}`. Это договор между двумя линиями: сменить ключ молча
    значит сделать чужую проверку слепой, и она честно скажет «не измерено»,
    а дефект состава проедет мимо.
    """
    import json
    import subprocess
    import sys

    готово = subprocess.run(
        [sys.executable, str(ПУТЬ), "--json"],
        capture_output=True, text=True, timeout=600)
    assert готово.returncode in (0, 1), готово.stderr[-400:]
    ответ = json.loads(готово.stdout)
    assert "измерено" in ответ and ответ["измерено"]
    assert ответ.get("витрины"), ответ
    for витрина in ответ["витрины"]:
        assert "витрина" in витрина
        for раздел in ("подборки", "анонсы"):
            assert раздел in витрина, (витрина["витрина"], раздел)
            часть = витрина[раздел]
            assert "исход" in часть and "беды" in часть, часть
        assert "ревизия каталога" in витрина["подборки"], витрина["подборки"]


