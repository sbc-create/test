"""Регистрация ячейки в фабрике и её подключение к поставке данных — одно целое.

Почему проверка появилась. `zonafilm12.site` прошёл все этапы запуска — реестр,
репозиторий, CI, юнит, nginx, сертификат, publisher_id — и остановился на том,
что производитель каталога о нём не знает: его список витрин задан отдельно от
реестра ячеек. Снаружи это выглядело как готовый сайт, у которого «просто нет
данных», и обнаружилось только при первом выпуске.

Второго реестра здесь не появляется. Проверка сверяет ДВА уже существующих
источника: реестр ячеек фабрики и список витрин производителя. Расхождение —
отказ с именем сайта, а не общее «что-то не так».

Производитель живёт в рабочей копии `/srv/site-factory/repo`, а его файл не
закоммичен ни в одну ветку origin (проверено обходом 155 ветвей: самая полная
версия на 2.7 КБ меньше работающей). Поэтому путь читается из окружения, а
отсутствие файла даёт ПРОПУСК, а не падение: на машине без производителя эта
проверка ничего не знает и не должна притворяться, что знает.
"""
from __future__ import annotations

import ast
import json
import os
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПРОИЗВОДИТЕЛЬ = Path(os.environ.get(
    "NOVA_CATALOG_PUBLISHER",
    "/srv/site-factory/repo/automation/host/nova-catalog-publish.py"))


def витрины_производителя() -> list[str] | None:
    """Ключи ВИТРИНЫ, прочитанные разбором кода, а не импортом.

    Импорт потянул бы за собой всё окружение производителя и его сетевые
    зависимости; нам нужен один литерал.
    """
    if not ПРОИЗВОДИТЕЛЬ.is_file():
        return None
    try:
        дерево = ast.parse(ПРОИЗВОДИТЕЛЬ.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return None
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Assign):
            continue
        if not any(getattr(ц, "id", "") == "ВИТРИНЫ" for ц in узел.targets):
            continue
        if isinstance(узел.value, ast.Dict):
            return [к.value for к in узел.value.keys if isinstance(к, ast.Constant)]
    return None


def ячейки_на_поставке() -> list[dict]:
    """Ячейки, которым данные обязан доставлять конвейер, а не кто-то вручную."""
    данные = json.loads((КОРЕНЬ / "config" / "site-cells.json").read_text(encoding="utf-8"))
    итог = []
    for c in данные["cells"]:
        рв = c.get("runtime") or {}
        домен = c.get("domain") or ""
        if домен.endswith((".localhost", ".localhost.test", ".test")):
            continue
        if рв.get("managed_by") == "cell" and рв.get("data_owner") == "pipeline":
            итог.append(c)
    return итог


def test_есть_что_сверять() -> None:
    assert ячейки_на_поставке(), "ни одна ячейка не объявлена на поставке конвейером"


def готова_к_выпуску(c: dict) -> bool:
    """Свои входы витрины собраны: шаблон назначен и есть свой publisher_id.

    До этого записи в производителе от неё никто не ждёт: снимок был бы собран
    для домена, который ещё не выпускается. После — обязана быть, иначе домен
    пройдёт весь запуск и встанет без данных.
    """
    return bool((c.get("template") or {}).get("template_id")
                and (c.get("publisher") or {}).get("publisher_id"))


@pytest.mark.xfail(strict=True, reason=(
    "zona-03 ждёт одной записи в ВИТРИНЫ производителя. Патч подготовлен и "
    "проверен: automation/host/patches/zona-03-register-in-publisher.patch — "
    "контекст совпадает с работающим файлом, результат разбирается как Python, "
    "11 строк добавлено, 0 удалено. Применение требует прав владельца в "
    "/srv/site-factory/repo. strict=True: как только запись появится, проверка "
    "пройдёт неожиданно и этим потребует снять пометку."))
def test_производитель_знает_каждую_готовую_ячейку() -> None:
    """Иначе сайт проходит весь запуск и останавливается без данных."""
    список = витрины_производителя()
    if список is None:
        pytest.skip(f"производителя каталога нет по пути {ПРОИЗВОДИТЕЛЬ} — "
                    "сверять не с чем")
    пропущены = [c["site_id"] for c in ячейки_на_поставке()
                 if готова_к_выпуску(c) and c["site_id"] not in список]
    assert not пропущены, (
        "производитель каталога не знает ячейки: " + ", ".join(пропущены) +
        ". Такой сайт проходит все этапы запуска и падает на stage_snapshot: "
        "снимка для него никто не строит. Добавить запись в ВИТРИНЫ "
        f"{ПРОИЗВОДИТЕЛЬ}"
    )


def test_производитель_не_знает_лишних_ячеек() -> None:
    """Обратная сторона: витрина в производителе без записи в реестре.

    Такой снимок собирается и никуда не доставляется — работа впустую, которую
    никто не замечает, потому что ошибок нет.
    """
    список = витрины_производителя()
    if список is None:
        pytest.skip("производителя каталога нет — сверять не с чем")
    известные = {c["site_id"] for c in json.loads(
        (КОРЕНЬ / "config" / "site-cells.json").read_text(encoding="utf-8"))["cells"]}
    лишние = [s for s in список if s not in известные]
    assert not лишние, (
        "производитель строит каталог для витрин, которых нет в реестре ячеек: "
        + ", ".join(лишние))
