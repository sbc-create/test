"""Нестрогое сравнение идёт по словам запроса, а не по запросу целиком.

Дефект измерен на боевом lordfilm47.space 7 сентября 2026:

    «100 дней»  → 5 записей     «100 днеи» → 0     «100 днй» → 0
    «елкo» (латинская o) → 7    то есть одно слово с опечаткой находится

Причина была в том, что ОБА уровня меряли запрос целиком:

* `_score` сравнивал каждое СЛОВО названия со ВСЕЙ строкой запроса — слово
  «дней» не окажется на расстоянии 2 от строки «100 днеи», длины несопоставимы;
* `_fuzzy_candidates` отбирал словарные слова по расстоянию до всей строки
  запроса, поэтому для многословного запроса кандидатов не было вовсе.

Теперь многословный запрос разбирается по словам: кандидаты ищутся по каждому
слову, запись обязана ответить на КАЖДОЕ слово запроса, а оценкой становится
самое слабое из совпадений. Односложный запрос идёт прежним путём — там
менять было нечего.

Отдельно закреплено, что точный поиск не поехал: строгие совпадения обязаны
стоять выше любого нестрогого, иначе опечатка вытеснила бы точное название.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from factory.lords import search as search_mod  # noqa: E402

КАТАЛОГ = [
    {"slug": "100-dney", "name": "100 дней до прощания, дорогой", "original": ""},
    {"slug": "temnyy-rycar", "name": "Тёмный рыцарь", "original": "The Dark Knight"},
    {"slug": "zvezdnye-voyny", "name": "Звёздные войны", "original": "Star Wars"},
    {"slug": "matrica", "name": "Матрица", "original": "The Matrix"},
    {"slug": "vlastelin", "name": "Властелин колец", "original": "The Lord of the Rings"},
    {"slug": "voyna-mirov", "name": "Война миров", "original": "The War of the Worlds"},
]


def найти(query: str, limit: int = 10) -> list[str]:
    return [row["slug"] for row in search_mod.search(КАТАЛОГ, query, limit=limit)]


class TestОпечаткаВМногословномЗапросе:
    """То, чего не было. Каждый случай — с боевой витрины или её формы."""

    # Допуск — одна ошибка на слово (порог max(1, len//4), тот же, что у
    # односложного пути). Две ошибки в трёхбуквенном слове не поддержаны
    # намеренно: при таком допуске «100» нашло бы почти любое трёхбуквие.
    @pytest.mark.parametrize(
        "запрос",
        [
            "100 днеи",      # й → и в последнем слове
            "100 днй",       # выпала буква
            "100 днея",      # замена
        ],
    )
    def test_находится_несмотря_на_опечатку(self, запрос):
        assert "100-dney" in найти(запрос), f"«{запрос}» не нашёл запись"

    def test_перестановка_соседних_букв_это_одна_ошибка(self):
        assert "zvezdnye-voyny" in найти("звездные вонйы")

    def test_опечатка_в_первом_слове_тоже_считается(self):
        assert "vlastelin" in найти("власетлин колец")

    def test_опечатка_в_каждом_из_двух_слов(self):
        assert "temnyy-rycar" in найти("темнй рыцрь")


class TestЗапросДолженОтвечатьВесьЦеликом:
    """Нестрогость не должна находить всё подряд — правило модуля."""

    def test_лишнее_слово_запроса_отсекает_запись(self):
        # «матрица» есть, «колец» — нет ни в одной форме этой записи.
        assert "matrica" not in найти("матрица колец")

    def test_бессмыслица_не_находит_ничего(self):
        assert найти("зззззз ыыыыыы") == []

    def test_одно_слово_из_названия_плюс_мусор_не_проходит(self):
        assert "voyna-mirov" not in найти("война жжжжжж")


class TestТочныйПоискНеПоехал:
    """Главный риск правки: опечатка не должна вытеснять точное совпадение."""

    def test_точное_название_находится(self):
        assert найти("Матрица")[0] == "matrica"

    def test_точное_многословное_название_находится(self):
        assert найти("Властелин колец")[0] == "vlastelin"

    def test_точное_выше_нестрогого(self):
        порядок = найти("война миров")
        assert порядок[0] == "voyna-mirov"

    def test_начало_названия_находится(self):
        assert "vlastelin" in найти("властелин")

    def test_подстрока_находится(self):
        assert "100-dney" in найти("до прощания")

    def test_оригинальное_название_находится(self):
        assert "temnyy-rycar" in найти("The Dark Knight")

    def test_транслитерация_цела(self):
        assert "matrica" in найти("matrica")

    def test_чужая_раскладка_цела(self):
        assert "matrica" in найти("vfnhbwf")

    def test_е_вместо_ё_цело(self):
        assert "temnyy-rycar" in найти("темный рыцарь")

    def test_слишком_короткий_запрос_по_прежнему_не_обрабатывается(self):
        assert найти("я") == []


class TestОценкаНеПутаетСтрогоеСНестрогим:
    """На этом основан пропуск нестрогого прохода в `search`."""

    def test_нестрогая_оценка_не_превышает_потолка(self):
        значение = search_mod._score("100 дней до прощания дорогой", "100 днеи")
        assert 0 < значение <= search_mod.FUZZY_CEILING

    def test_строгая_оценка_не_ниже_пола(self):
        значение = search_mod._strict_score("100 дней до прощания дорогой", "100 дней")
        assert значение >= search_mod.STRICT_FLOOR
