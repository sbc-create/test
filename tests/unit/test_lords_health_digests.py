# `runtime_digest_match`: сравнивать сравнимое, а «не измерено» не называть
# несовпадением. Разбор — docs/BLOCKERS.md, HEALTHZ-DIGEST-SCOPE: поле
# сравнивало сумму ОДНОГО файла витрины с `artifact_sha256` манифеста ШАБЛОНА,
# то есть величины разной природы. У lords-02 (тонкая точка входа + общий
# рантайм 435 КБ) оно отвечало `false` на правильно выложенном коде, и владелец
# справедливо прочитал это как «исправление не применилось».
#
# Сравнимая величина у ячейки есть: `pins.lock.json` хранит сумму КАЖДОГО
# исходника отдельно, и её пишет сборщик, а не рука.


def _замок(путь, файл, сумма):
    путь.write_text(json.dumps({
        "schema_version": 1,
        "site_id": "lords-test",
        "files": {файл: {"sha256": сумма, "bytes": 1}},
    }, ensure_ascii=False), encoding="utf-8")


@pytest.fixture()
def стенд_с_замком(tmp_path, monkeypatch):
    """Стенд, которому назначен замок выпуска; сумму задаёт тест."""
    def собрать(сумма_для_файла):
        с = h.Стенд(tmp_path)
        с.записать_каталог([h.запись("a", title="Первый")])
        с.записать_подробности([h.подробность("a")])
        с.записать_плеер("10555")
        замок = tmp_path / "pins.lock.json"
        _замок(замок, h.ЯДРО.name, сумма_для_файла(h.ЯДРО))
        monkeypatch.setenv("LORDS_PINS_LOCK", str(замок))
        модуль = h.загрузить(с, monkeypatch)
        return с, модуль
    yield собрать


def test_сходимость_кода_считается_по_замку_выпуска(стенд_с_замком):
    """Сумма файла сверяется с суммой ТОГО ЖЕ файла, записанной сборщиком."""
    с, модуль = стенд_с_замком(lambda ф: _сумма(ф))
    тело = _тело_healthz(модуль, с)
    assert тело["runtime_digest_scope"] == "pins_lock", тело["runtime_digest_scope"]
    assert тело["runtime_digest_match"] is True, тело
    h.выгрузить(модуль)


def test_подменённый_файл_даёт_честное_несовпадение(стенд_с_замком):
    """Замок называет другую сумму — вот это и значит «код не тот»."""
    с, модуль = стенд_с_замком(lambda ф: "0" * 64)
    тело = _тело_healthz(модуль, с)
    assert тело["runtime_digest_scope"] == "pins_lock"
    assert тело["runtime_digest_match"] is False, тело
    h.выгрузить(модуль)


def test_без_сравнимой_величины_поле_не_врёт_про_несовпадение(tmp_path, monkeypatch):
    """Нечего сравнить — `null` и область `none`, а не `false`.

    Ровно эта разница и была ценой прежнего поля: ложный признак принимают за
    измерение и по нему отказывают в выкладке.
    """
    monkeypatch.setenv("LORDS_PINS_LOCK", str(tmp_path / "нет-такого-файла.json"))
    с = h.Стенд(tmp_path)
    с.записать_каталог([h.запись("a", title="Первый")])
    с.записать_подробности([h.подробность("a")])
    с.записать_плеер("10555")
    модуль = h.загрузить(с, monkeypatch)
    тело = _тело_healthz(модуль, с)
    assert тело["runtime_digest_match"] is None, тело["runtime_digest_match"]
    assert тело["runtime_digest_scope"] == "none"
    # Сумма исполняемого файла при этом обязана остаться: она — факт.
    assert тело["runtime_sha256"] == _сумма(h.ЯДРО)
    h.выгрузить(модуль)
