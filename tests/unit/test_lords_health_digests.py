"""Два диагностических поля `/healthz` относятся к файлам этой витрины.

Разбор lords-01 (`docs/STATE.md`, раздел 6.2). Ядро считало обе суммы по
общему каталогу фабрики:

    template_manifest_digest ← /srv/lords/.frontend/template-manifest-<site>.json
    player_config_digest     ← /srv/lords/.frontend/player-<site>.json

а витрина читает `LORDS_TEMPLATE_MANIFEST` и `LORDS_PLAYER_CONFIG`. У
выделенной ячейки первого файла нет вовсе — поле оставалось пустым, — а второй
существует и принадлежит ДРУГОЙ раскладке: сумма считалась по файлу, который
не исполняется. Совпавшая с соседом сумма выглядит как доказательство, и это
хуже пустоты.

Проверяется поведение, а не текст: суммы сверяются с фактическим содержимым
тех файлов, которые витрина открыла. Содержимое настройки плеера в ответ не
попадает — только сумма и путь.
"""
from __future__ import annotations

import hashlib
import json

import pytest

import lords_runtime_harness as h


@pytest.fixture()
def стенд(tmp_path, monkeypatch):
    с = h.Стенд(tmp_path)
    с.записать_каталог([h.запись("a", title="Первый"), h.запись("b", title="Второй")])
    с.записать_подробности([h.подробность("a"), h.подробность("b")])
    с.записать_плеер("10555")
    модуль = h.загрузить(с, monkeypatch)
    yield с, модуль
    h.выгрузить(модуль)


def _тело_healthz(модуль, с) -> dict:
    """Собрать ответ `/healthz`, не поднимая сокет.

    Обработчик — `BaseHTTPRequestHandler`; конструировать его целиком ради
    одного ответа дороже и хрупче, чем вызвать маршрут на подставном
    экземпляре. Поля, которые нас интересуют, считаются в самом обработчике.
    """
    класс = модуль.Обработчик
    экземпляр = класс.__new__(класс)
    экземпляр.данные = модуль.Данные(модуль.КАТАЛОГ_ФАЙЛ)
    экземпляр.подробности = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    экземпляр.индекс = модуль.построить_индекс(экземпляр.данные, экземпляр.подробности)
    экземпляр.path = "/healthz"
    экземпляр.server = type("С", (), {"started_at": ""})()
    экземпляр.headers = {}
    собрано = {}

    def _отдать(тело, тип, код=200, заголовки=None):
        собрано["тело"] = json.loads(тело.decode("utf-8"))
        return None

    экземпляр._отдать = _отдать
    экземпляр.do_GET()
    assert "тело" in собрано, "обработчик не ответил на /healthz"
    return собрано["тело"]


def _сумма(путь) -> str:
    return hashlib.sha256(путь.read_bytes()).hexdigest()


def test_сумма_манифеста_считается_по_манифесту_витрины(стенд):
    с, модуль = стенд
    тело = _тело_healthz(модуль, с)
    assert тело["template_manifest_path"] == str(с.манифест)
    assert тело["template_manifest_digest"] == _сумма(с.манифест)


def test_сумма_плеера_считается_по_настройке_витрины(стенд):
    с, модуль = стенд
    тело = _тело_healthz(модуль, с)
    assert тело["player_config_path"] == str(с.плеер)
    assert тело["player_config_digest"] == _сумма(с.плеер)


def test_сумма_плеера_следует_за_файлом_а_не_за_соглашением(стенд):
    """Смена содержимого файла обязана сменить сумму.

    Проверка «от обратного» к прежнему поведению: раньше сумма считалась по
    постороннему файлу и на правку настройки витрины не реагировала вовсе.
    """
    с, модуль = стенд
    было = _тело_healthz(модуль, с)["player_config_digest"]
    с.записать_плеер("10777")
    стало = _тело_healthz(модуль, с)["player_config_digest"]
    assert было != стало
    assert стало == _сумма(с.плеер)


def test_содержимое_настройки_плеера_в_ответ_не_попадает(стенд):
    """Publisher ID — настройка места, и в диагностике ему не место."""
    с, модуль = стенд
    тело = _тело_healthz(модуль, с)
    сырое = json.dumps(тело, ensure_ascii=False)
    assert "10555" not in сырое
    assert "publisher_id" not in сырое


def test_общий_путь_фабрики_больше_не_используется(стенд):
    """Ни одно из двух полей не смотрит в `/srv/lords/.frontend`."""
    с, модуль = стенд
    тело = _тело_healthz(модуль, с)
    for поле in ("template_manifest_path", "player_config_path"):
        assert not тело[поле].startswith("/srv/lords/.frontend"), поле
