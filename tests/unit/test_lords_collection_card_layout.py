"""REQ-LORDS-HUB-COMPACT: карточка подборки остаётся компактной сеткой превью.

Измерено 2026-10-17 на живой lordfilm.group: блок подборок показывал четыре
огромные карточки высотой 2673 px, внутри каждой превью стояли столбцом во всю
ширину (первое — 401×602 px), а четвёртая подборка уезжала в отдельный ряд с
пустотой справа.

Причина — вес селекторов, а не вёрстка: правило `.hub__c span` (класс плюс
элемент, вес 0,1,1) перебивало `.hub__g{display:grid}` (вес 0,1,0), и сетка
превью никогда не включалась. Вычисленный `display` у `.hub__g` был `block`
при объявленных `grid-template-columns: repeat(4, 1fr)`.

Проверка читает исходник темы: так она падает до выпуска. Она опровергаема —
возврат общего правила `.hub__c span` её ломает.
"""
from __future__ import annotations

import re
from pathlib import Path

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


#: Тот же текст без комментариев CSS. Без этой очистки селектор, перед которым
#: стоит пояснение, слипается с ним в одну строку, и точное сравнение с
#: `.hub__c span` не срабатывает: проверка молча пропускала возврат дефекта —
#: поймано негативным контролем при её написании.
БЕЗ_КОММЕНТАРИЕВ = re.sub(r"/\*.*?\*/", " ", ТЕКСТ, flags=re.S)


def _селекторы() -> list[str]:
    """Все селекторы правил файла, по одному на объявление."""
    итог = []
    for м in re.finditer(r"([^{}]+)\{([^}]*)\}", БЕЗ_КОММЕНТАРИЕВ):
        for с in м.group(1).split(","):
            # Перед селектором может стоять хвост предыдущего правила или
            # обычный текст файла; значим последний смысловой кусок строки.
            строка = " ".join(с.split())
            итог.append(строка.rsplit("}", 1)[-1].strip())
    return итог


def _правила(селектор: str) -> list[str]:
    образец = re.compile(re.escape(селектор) + r"\s*\{([^}]*)\}", re.S)
    return [" ".join(м.group(1).split()) for м in образец.finditer(ТЕКСТ)]


def test_общего_правила_для_любого_span_карточки_подборки_нет():
    """Корень дефекта: правило на каждый span внутри карточки.

    Такое правило перебивает объявления структурных элементов превью
    (`.hub__g`, `.hub__i`, `.hub__p`) — все они span'ы.
    """
    плохие = [с for с in _селекторы() if с == ".hub__c span"]
    assert not плохие, (
        "вернулось общее правило `.hub__c span`: оно перебьёт display:grid "
        "у .hub__g, и превью снова встанут столбцом во всю ширину")


def test_сетка_превью_объявлена_сеткой():
    правила = _правила(".hub__g")
    assert правила, "правило .hub__g не найдено — тема изменилась"
    assert any("display:grid" in п for п in правила)
    assert any("grid-template-columns:repeat(4,1fr)" in п.replace(" ", "")
               for п in правила)


def test_блок_подборок_не_оставляет_четвёртую_в_отдельном_ряду():
    """Подборок ровно четыре, значит широкий экран показывает четыре колонки."""
    широкие = re.findall(
        r"@media\(min-width:(\d+)px\)\{\.hub\{grid-template-columns:"
        r"repeat\((\d+),1fr\)\}\}", ТЕКСТ.replace(" ", ""))
    assert широкие, "медиазапросов для .hub не найдено"
    по_ширине = {int(ш): int(к) for ш, к in широкие}
    самый_широкий = max(по_ширине)
    assert по_ширине[самый_широкий] == 4, (
        f"на широком экране {по_ширине[самый_широкий]} колонок вместо четырёх")
    assert по_ширине[min(по_ширине)] == 2, "на среднем экране должно быть две"


def test_превью_подборки_ограничено_по_высоте():
    """Страховка: полноразмерный постер не задаёт высоту карточки."""
    правила = _правила(".hub__p")
    assert правила, "правило .hub__p не найдено"
    assert any("max-height" in п for п in правила), (
        "у превью подборки нет предела высоты")


def test_заглушка_уходит_когда_картинка_нарисована():
    """Буква обязана исчезать после загрузки — и только после неё."""
    assert "data-poster-loaded" in ТЕКСТ
    assert "СКРИПТ_ЗАГЛУШЕК" in ТЕКСТ
    # Пометка ставится только при ненулевой натуральной ширине: «событие
    # пришло» и «картинка есть» — разные вещи.
    # Конец константы — закрывающая скобка В НАЧАЛЕ СТРОКИ: первая же `)`
    # встречается внутри самого JavaScript, и обрезка по ней давала кусок в
    # полстроки (поймано этой же проверкой при её написании).
    кусок = ТЕКСТ.split("СКРИПТ_ЗАГЛУШЕК = (", 1)[1].split("\n)", 1)[0]
    assert "naturalWidth" in кусок
    скрывают = [с for с in _селекторы() if "data-poster-loaded" in с]
    assert len(скрывают) >= 3, (
        f"заглушка скрывается не у всех семейств карточек: {скрывают}")
