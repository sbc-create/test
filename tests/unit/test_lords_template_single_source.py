def test_у_поставляемого_отдельно_назван_выпуск(версия):
    for имя, выпуск in версия["delivered_separately"].items():
        assert выпуск and len(выпуск) > 8, f"{имя}: выпуск не назван"


# --- 5. закрепление ---------------------------------------------------------

def test_новый_сайт_закрепляет_ровно_то_что_получил(tmp_path, newsite):
    """Сквозная сверка: что скопировано — то и закреплено, по суммам.

    Это и есть та проверка, которой не хватало: расхождение кода шаблона и
    того, что получает новый сайт, обнаруживается здесь, а не через неделю на
    живом домене.
    """
    заказ = newsite.Заказ(site_id="lords-98", domain="lords98.example",
                          profile="lords-general", port=9198,
                          remote="https://github.com/sbc-create/site-lords98-example")
    куда = tmp_path / "site"
    реестр = tmp_path / "cells.json"
    реестр.write_text(json.dumps({"schema_version": "1.0", "cells": []}),
                      encoding="utf-8")
    # Дерево при разработке грязное; проверке состава это не мешает, а
    # происхождение честно помечается source_dirty.
    паспорт = newsite.создать(заказ, корень=КОРЕНЬ, куда=куда, реестр=реестр,
                              допустить_грязное=True)

    pins = json.loads((куда / "pins.lock.json").read_text(encoding="utf-8"))
    закреплены = {и: м for и, м in pins["files"].items() if м.get("sha256")}
    положены = sorted(p.name for p in (куда / "src").glob("*.py"))

    assert sorted(закреплены) == положены, (
        "закреплено не то, что положено в src/:\n"
        f"  закреплено: {sorted(закреплены)}\n  положено:   {положены}")

    for имя, мета in закреплены.items():
        свой = hashlib.sha256((куда / "src" / имя).read_bytes()).hexdigest()
        шаблон = hashlib.sha256((КОРЕНЬ / мета["repo_path"]).read_bytes()).hexdigest()
        assert свой == мета["sha256"], f"{имя}: замок не совпал с копией сайта"
        assert свой == шаблон, (
            f"{имя}: сайт получил не то, что лежит в шаблоне "
            f"({мета['repo_path']})")

    assert paспорт_версии(паспорт) == json.loads(
        ВЕРСИЯ_ФАЙЛ.read_text(encoding="utf-8"))["version"]
    манифест = json.loads((куда / "config" / "template-manifest.json").read_text(
        encoding="utf-8"))
    assert манифест["design_version"] == paспорт_версии(паспорт)
    assert манифест["template_origin"]["source_commit"] == pins["pins"]["source_commit"]
    # Грязное дерево не прячется: метка стоит в обоих местах.
    assert pins["pins"]["source_dirty"] == манифест["template_origin"]["source_dirty"]


def paспорт_версии(паспорт: dict) -> str:
    return паспорт["design_version"]
