def test_внимание_только_когда_затронутые_сутки_в_окне():
    """Предупреждение, которое горит всегда, перестают читать.

    Недосчитанными пришли РОВНО трое суток (11–13.10), остальные двадцать
    суток архива были полны с первого чтения. Поэтому «ВНИМАНИЕ» ставится
    тогда, когда эти сутки в окно попадают, а иначе остаётся оговорка.
    """
    # окно снимка 12.10 — это 05–11.10, в нём есть 11.10
    опасное = модуль.предупреждение_о_досчёте("2026-10-19", "2026-10-12")
    assert опасное.startswith("ВНИМАНИЕ")
    assert "ЗАВЫШЕН" in опасное

    # окна снимков 21.10 и 28.10 — это 14–20.10 и 21–27.10, затронутых нет
    спокойное = модуль.предупреждение_о_досчёте("2026-10-28", "2026-10-21")
    assert спокойное.startswith("Оговорка")
    assert "ЗАВЫШЕН" not in спокойное


def test_оговорка_всегда_называет_запись_и_меру():
    for сейчас, раньше in (("2026-10-19", "2026-10-12"),
                           ("2026-10-28", "2026-10-21")):
        т = модуль.предупреждение_о_досчёте(сейчас, раньше)
        assert "MOD-131" in т
        assert "metrika-day-settled.py" in т
        assert сейчас in т and раньше in т



# --- реальные визиты, а не «не робот по версии Метрики» --------------------

def _строка_профиля(дата: str, браузер: str, робот: str, визиты: float) -> dict:
    return {
        "dimensions": [{"name": дата}, {"name": "Direct traffic"},
                       {"name": "PC"}, {"name": браузер}, {"name": робот}],
        "metrics": [визиты, 50.0, 1.2, 100.0],
    }


def _домен(строки: list[dict], *, с_профилем: bool = True) -> dict:
    # `measured` обязателен: `измерение()` отдаёт значение только у снятой
    # меры, и фикстура без этого флага выглядит как неснятая.
    меры = [{"key": "daily_users", "measured": True, "value": [
        {"dimensions": [{"name": "2026-10-20"}, {"name": "People", "id": "no"}],
         "metrics": [9000.0, 9000.0]}]}]
    if с_профилем:
        меры.append({"key": "daily_traffic_profile", "measured": True,
                     "value": строки})
    return {"domain": "fixture-one.test", "measurements": меры}


def test_автоматизация_не_считается_людьми():
    """Повод измеренный, 23.10: прогон давал yummyani.site 10 156,9 «людей в
    сутки» и «3 из 7 суток выше цели», потому что ряд `daily_users` снимает
    только флаг робота Метрики. По профилю трафика у того же домена реальных
    визитов 2 517,1 в сутки и ни одних суток выше цели."""
    д = _домен([
        _строка_профиля("2026-10-20", "Yandex Browser", "People", 100.0),
        _строка_профиля("2026-10-20", "HeadlessChrome", "People", 9000.0),
    ])
    люди, роботы, дат = модуль.люди_и_роботы(д)
    assert (люди, роботы, дат) == (100.0, 9000.0, 1), (люди, роботы, дат)


def test_дни_на_цели_считаются_по_реальным_визитам():
    """Иначе один день автоматизации засчитывается как достигнутая цель."""
    д = _домен([
        _строка_профиля("2026-10-20", "Opera", "People", 400.0),
        _строка_профиля("2026-10-20", "HeadlessChrome", "People", 9000.0),
    ])
    на_цели, всего, по_дням = модуль.дни_на_цели(д, цель=5000)
    assert (на_цели, всего) == (0, 1), (на_цели, всего, по_дням)


def test_без_профиля_суток_домен_не_судится_по_цели():
    """Ряд `daily_users` автоматизацию не отделяет, поэтому подставлять его
    вместо реальных визитов нельзя: иначе цель объявлялась бы достигнутой по
    числу, в котором сидит автоматизация."""
    д = _домен([], с_профилем=False)
    assert модуль.люди_и_роботы(д) == (0.0, 0.0, 0)
    assert модуль.дни_на_цели(д)[:2] == (0, 0)
