"""Проверка завязки В ИСТОЧНИКЕ обычным кодом — до обращения к модели.

Повод измерен. Один разбор материала фоновым редактором стоит $0,154
(109 запусков, $224,79, 1 463 материала за 18–25.10), и 922 из этих разборов
кончились `SOURCES_MISSING` — модель читала записанный источник и не находила,
из чего писать. Тот же факт обычный код берёт одним запросом карточки.

Третий исход обязателен: источник, который НЕ ОТВЕТИЛ, — это «не измерено», а
не «завязки нет». Иначе сбой сети молча остановил бы редакционную работу, и
отчёт назвал бы остановку экономией.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/source-availability-precheck.py"
_спец = importlib.util.spec_from_file_location("source_precheck", _путь)
ПР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ПР)


def читатель(текст=None, причина=""):
    return lambda ид, таймаут: (текст, причина)


def test_описание_источника_даёт_завязку() -> None:
    исход, знаков, _ = ПР.завязка("21", читатель=читатель("с" * 300))
    assert исход == "ЗАВЯЗКА ЕСТЬ" and знаков == 300


def test_пустое_описание_это_отсутствие_завязки() -> None:
    исход, знаков, причина = ПР.завязка("21", читатель=читатель(""))
    assert исход == "ЗАВЯЗКИ НЕТ" and знаков == 0 and "0 знаков" in причина


def test_слишком_короткое_описание_пересказывать_нечем() -> None:
    исход, _, _ = ПР.завязка("21", читатель=читатель("с" * (ПР.ПОРОГ_ЗНАКОВ - 1)))
    assert исход == "ЗАВЯЗКИ НЕТ"


def test_порог_ровно_по_границе_принимается() -> None:
    исход, _, _ = ПР.завязка("21", читатель=читатель("с" * ПР.ПОРОГ_ЗНАКОВ))
    assert исход == "ЗАВЯЗКА ЕСТЬ"


def test_источник_не_ответил_это_не_измерено() -> None:
    """Сбой измерения кандидата НЕ снимает: иначе сеть останавливает работу."""
    исход, _, причина = ПР.завязка("21", читатель=читатель(None, "источник отказал: status 503"))
    assert исход == "НЕ ИЗМЕРЕНО" and "503" in причина


def test_источник_не_знает_идентификатора_это_отсутствие_завязки() -> None:
    """404 — источник ОТВЕТИЛ: записанный идентификатор ведёт в пустоту."""
    исход, _, _ = ПР.завязка("999999999", читатель=читатель(None, "источник отказал: status 404"))
    assert исход == "ЗАВЯЗКИ НЕТ"


def test_без_идентификатора_ничего_не_утверждается() -> None:
    исход, _, причина = ПР.завязка("")
    assert исход == "НЕ ИЗМЕРЕНО" and "идентификатора" in причина


@pytest.mark.parametrize("запись,ожидание", [
    ({"source_id": "2705"}, "2705"),
    ({"shikimori_id": 51009}, "51009"),
    ({"note": "см. https://shikimori.io/animes/1234 — карточка"}, "1234"),
    ({"film_args": ["7112704", "X", "X", "2009", "tv"]}, ""),
    ({}, ""),
])
def test_идентификатор_берётся_из_записи_или_примечания(запись, ожидание) -> None:
    assert ПР.ид_источника(запись) == ожидание


def test_карточка_читается_одним_запросом() -> None:
    """`card`, а не `shikimori`: полное чтение делает два обращения к источнику,
    и при сверке сотен записей это удваивает нагрузку на него впустую."""
    текст = _путь.read_text(encoding="utf-8")
    assert '"card", ид' in текст
    cli = (КОРЕНЬ / "automation/local/source_fetch.py").read_text(encoding="utf-8")
    assert '"card": shikimori_card' in cli, "команда card не объявлена в source_fetch.py"
