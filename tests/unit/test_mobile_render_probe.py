"""Признак мобильной отрисовки: что он обязан замечать и чего не вправе.

Два теста здесь главные.

`test_сломанный_замер_не_выдаётся_за_порядок` — без различающего контроля
«за край ничего не выходит» и «замер не работает» дают один и тот же ноль, и
ложное «в порядке» получилось бы на пустой странице.

`test_листаемая_полка_дефектом_не_считается` — проверка признака там, где
дефекта НЕТ: карусель полки намеренно уезжает за правый край, и первая
редакция признака (по `scrollWidth` и голым рамкам) пометила бы каждую
витрину сети.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "mobile-render-probe.py"

спец = importlib.util.spec_from_file_location("mobile_render_probe", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)

КОНТРОЛЬ_СРАБОТАЛ = {"замечен": True, "рост_scrollWidth_px": 0,
                     "справа_px": 2412}


def замер(**поля) -> dict:
    """Замер исправной страницы; аргументы перекрывают отдельные поля."""
    основа = {
        "окно_px": 390,
        "перелив_px": 0,
        "контроль_перелив_px": dict(КОНТРОЛЬ_СРАБОТАЛ),
        "за_краем": 0,
        "за_краем_свободных": 0,
        "свободные": [],
        "правее_всего_px": 0,
        "обрезает_документ": True,
        "карточек": 24,
        "ширина_карточки_px": 174,
        "карточек_в_ряду": 2,
        "точек_входа_в_меню": 9,
        "виновники": [],
    }
    основа.update(поля)
    return основа


def элемент(справа: int, *, рамка: str = "", класс: str = "shelf__row") -> dict:
    return {"тег": "div", "класс": класс, "ширина": 556, "справа": справа,
            "рамка": рамка}


def test_исправная_страница_в_порядке():
    assert модуль.исход(замер())["исход"] == модуль.ПОРЯДОК


def test_сломанный_замер_не_выдаётся_за_порядок():
    итог = модуль.исход(замер(
        контроль_перелив_px={"замечен": False, "рост_scrollWidth_px": 0,
                             "справа_px": 390}))
    assert итог["исход"] == модуль.НЕ_ИЗМЕРЕНО
    assert "контрольный блок" in итог["почему"]


def test_контроль_не_выполнялся_тоже_не_измерено():
    итог = модуль.исход({"окно_px": 390, "перелив_px": 0})
    assert итог["исход"] == модуль.НЕ_ИЗМЕРЕНО
    assert "контроль" in итог["почему"]


def test_контроль_по_scrollWidth_исходом_не_управляет():
    # Витрины сети обрезают документ по краю, и рост `scrollWidth` там равен
    # нулю при исправном замере. Если бы контроль судился по нему, все десять
    # страниц остались бы неизмеренными — ровно это и случилось 21.10.
    итог = модуль.исход(замер(контроль_перелив_px={
        "замечен": True, "рост_scrollWidth_px": 0, "справа_px": 2412}))
    assert итог["исход"] == модуль.ПОРЯДОК


def test_ошибка_навигации_не_дефект_витрины():
    итог = модуль.исход({"ошибка": "навигация не завершилась: TimeoutError"})
    assert итог["исход"] == модуль.НЕ_ИЗМЕРЕНО
    assert итог["дефекты"] == []


def test_окно_не_прочитано():
    assert модуль.исход(замер(окно_px=0))["исход"] == модуль.НЕ_ИЗМЕРЕНО


def test_листаемая_полка_дефектом_не_считается():
    # `overflow-x: auto` у родителя — это горизонтальный жест по замыслу.
    итог = модуль.исход(замер(за_краем=18, за_краем_свободных=0,
                              свободные=[], правее_всего_px=0))
    assert итог["исход"] == модуль.ПОРЯДОК


def test_выход_за_край_без_рамки_это_дефект():
    итог = модуль.исход(замер(
        за_краем=3, за_краем_свободных=1,
        свободные=[элемент(468, класс="title__meta")], правее_всего_px=468))
    assert итог["исход"] == модуль.ЗА_КРАЕМ
    assert итог["дефекты"][0]["виновники"][0]["класс"] == "title__meta"


def test_обрезанное_документом_содержимое_тот_же_дефект():
    # Прокрутки не будет, содержимое всё равно не видно.
    итог = модуль.исход(замер(
        за_краем_свободных=1, свободные=[элемент(520)], правее_всего_px=520,
        обрезает_документ=True, перелив_px=0))
    assert итог["исход"] == модуль.ЗА_КРАЕМ
    assert итог["дефекты"][0]["обрезано_документом"] is True


@pytest.mark.parametrize("справа", [394, 400, 406])
def test_мелкий_выход_за_край_не_дефект(справа):
    итог = модуль.исход(замер(за_краем_свободных=1,
                              свободные=[элемент(справа)],
                              правее_всего_px=справа))
    assert итог["исход"] == модуль.ПОРЯДОК


def test_семнадцать_пикселей_уже_дефект():
    итог = модуль.исход(замер(за_краем_свободных=1, свободные=[элемент(407)],
                              правее_всего_px=407))
    assert итог["исход"] == модуль.ЗА_КРАЕМ


def test_перелив_документа_отдельный_исход():
    итог = модуль.исход(замер(перелив_px=168, обрезает_документ=False))
    assert итог["исход"] == модуль.ПРОКРУТКА


@pytest.mark.parametrize("перелив", [1, 2, 3, 4])
def test_округление_переливом_не_считается(перелив):
    assert модуль.исход(замер(перелив_px=перелив))["исход"] == модуль.ПОРЯДОК


def test_карточка_шире_окна_отдельный_исход():
    итог = модуль.исход(замер(ширина_карточки_px=430))
    assert итог["исход"] == модуль.КАРТОЧКА_ШИРЕ
    assert итог["дефекты"][0]["окно_px"] == 390


def test_страница_без_карточек_по_карточке_не_судится():
    итог = модуль.исход(замер(карточек=0, ширина_карточки_px=0))
    assert итог["исход"] == модуль.ПОРЯДОК


def test_меню_недоступно():
    assert модуль.исход(замер(точек_входа_в_меню=0))["исход"] == модуль.МЕНЮ_НЕТ


def test_несколько_дефектов_дают_худший_и_перечисляются():
    итог = модуль.исход(замер(перелив_px=240, обрезает_документ=False,
                              за_краем_свободных=1, свободные=[элемент(900)],
                              правее_всего_px=900, ширина_карточки_px=520,
                              точек_входа_в_меню=0))
    assert итог["исход"] == модуль.ПРОКРУТКА
    assert len(итог["дефекты"]) == 4
    assert модуль.МЕНЮ_НЕТ in итог["почему"]
    assert модуль.ЗА_КРАЕМ in итог["почему"]


def test_вес_определён_для_каждого_исхода():
    исходы = {модуль.ПОРЯДОК, модуль.ПРОКРУТКА, модуль.ЗА_КРАЕМ,
              модуль.КАРТОЧКА_ШИРЕ, модуль.МЕНЮ_НЕТ, модуль.НЕ_ИЗМЕРЕНО}
    assert исходы == set(модуль.ВЕС)


def test_контрольный_блок_шире_любого_окна_телефона():
    assert модуль.КОНТРОЛЬНАЯ_ШИРИНА_PX > модуль.ОКНО_ТЕЛЕФОНА[0] * 4
    assert f"{модуль.КОНТРОЛЬНАЯ_ШИРИНА_PX}px" in модуль.КОНТРОЛЬ_JS


def test_контрольный_блок_за_собой_убирается():
    # Иначе следующий замер той же страницы мерил бы наш блок.
    assert "d.remove()" in модуль.КОНТРОЛЬ_JS


def test_замер_различает_листаемую_и_обрезающую_рамку():
    # Признак держится на этом различении, поэтому оба слова обязаны быть в
    # замере, а не появиться случайно в переводе.
    assert '"листается"' in модуль.ЗАМЕР_JS
    assert '"обрезано"' in модуль.ЗАМЕР_JS
    assert "overflowX" in модуль.ЗАМЕР_JS
