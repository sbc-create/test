"""Замена ядра витрины не вправе унести читатель режима индексации.

Что это предотвращает — случай 2026-10-05, почти случившийся
-------------------------------------------------------------

Я рекомендовал доставить сторож плеера zona-01 и zona-03 «через шаблон», то
есть подъёмом пина на коммит шаблона. Соседнее окно возразило и оказалось
право; проверено измерением:

    ядро сайта против ядра шаблона (7a49282):
      zonafilm.space   1 607 строк только у сайта, 290 только у шаблона
      zonafilm12.site  1 480 строк только у сайта, 289 только у шаблона

    ядро шаблона 7a49282 НЕ содержит:
      import indexing_mode, мета_роботов, LORDS_INDEXING_SITE,
      SITE_CONTACT_EMAIL
    и содержит ЗАШИТО:
      5 × <meta name="robots" content="noindex, nofollow">
      2 × send_header("X-Robots-Tag", "noindex, nofollow")

То есть подъём пина заменил бы ядро целиком и ЗАКРЫЛ БЫ ДЛЯ ИНДЕКСАЦИИ два
открытых production-домена — побочным следствием выката сторожа плеера.
Ошибку поймал человек-рецензент в переписке; ворот, которые поймали бы её
сами, не было. Теперь есть.

Инвариант: у витрины, чьё СЕМЕЙСТВО решает режим ФАЙЛОМ-читателем, этот
читатель обязан быть подключён в ядре рабочей копии, а зашитых запретов в
мете быть не должно. Любая замена ядра — пином, инструментом, переносом из
шаблона — обязана сначала провалить этот тест, а не производство.

Чего тест НЕ требует и почему:

* у семейства Yummy читатель не файл, а переменная контейнера и реестр ядра
  (`КОНТРАКТ_РЕЖИМА`: `container:`/`core-registry`) — требовать от его ядра
  файл-читатель значило бы проверять не тот механизм (D169);
* витрина без установленного выпуска (`/srv/<учётная запись>/current`) ещё не
  запущена, и режима у неё нет. Как только выпуск появится, тест начнёт
  требовать читатель сам — без правки перечней.
"""
from __future__ import annotations

import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ЗАШИТАЯ_МЕТА = 'content="noindex, nofollow">'

#: Сколько зашитых запретов в мете у точки входа ИЗМЕРЕНО 2026-10-05.
#:
#: Ноль — режим вычисляется целиком. Один у animego-04 — ветка постера (D180).
#: Два у Yummy — режим тела решает контейнер, ячейка вправе только
#: доужесточать (D169). Ядро шаблона несёт ПЯТЬ: любая замена ядра шаблонным
#: порог превысит.
ПОРОГ_ЗАШИТЫХ = {
    "animedia-01": 0,
    "animedia-02": 0,
    "animego-04": 1,
    "lords-01": 0,
    "lords-02": 0,
    "lords-03": 0,
    "lords-05": 0,
    "yummy-07": 2,
    "yummy-08": 2,
    "yummy-biz": 2,
    "yummy-org": 2,
    "yummy-site": 2,
    "zona-01": 0,
    "zona-03": 0,
}


#: Ячейки, которые ДОЛЖНЫ были попасть в проверку, но рабочей копии нет.
#:
#: Заполняется отбором и проверяется отдельно. Повод: 2026-10-05 соседняя
#: сессия прогнала эти ворота в своём worktree и получила 25 passed вместо 29.
#: Разница — две ячейки (`lords-02`, `animego-04`), рабочих копий которых в том
#: дереве просто нет. Ворота молча их пропустили, и прогон выглядел полным.
#: Отсутствующая копия и «нечего проверять» — разные вещи, и первая обязана
#: называться.
БЕЗ_КОПИИ: list[str] = []


def _ядра() -> list[tuple[str, pathlib.Path, str, pathlib.Path]]:
    """Ячейки, чей режим решает ФАЙЛ-читатель и которые уже выложены."""
    from factory.qwen import indexing, registry

    реестр = json.loads((КОРЕНЬ / "config" / "site-cells.json")
                        .read_text(encoding="utf-8"))
    по_домену = {s.domain: s for s in registry.собрать(опрашивать_сеть=False)}
    итог = []
    for я in реестр["cells"]:
        путь = (я.get("repo") or {}).get("path")
        if not путь:
            continue
        аккаунт = (я.get("runtime") or {}).get("account") or ""
        if not аккаунт or not pathlib.Path(f"/srv/{аккаунт}/current").exists():
            continue                      # ещё не выложена — режима нет
        кор = КОРЕНЬ / путь
        if not (кор / ".git").exists() or not (кор / "src").is_dir():
            # Витрина ВЫЛОЖЕНА, а копии здесь нет: проверить нечем, и молчать
            # об этом нельзя — иначе прогон в чужом дереве сертифицирует
            # меньше, чем кажется.
            if я["site_id"] in ПОРОГ_ЗАШИТЫХ:
                БЕЗ_КОПИИ.append(я["site_id"])
            continue
        s = по_домену.get(я.get("domain") or "")
        контракт = indexing.контракт(getattr(s, "adapter", "") or "",
                                     аккаунт=аккаунт)
        читатель = str(контракт.get("reader") or "")
        if not читатель or читатель.startswith("container:"):
            continue                      # режим решает не файл этого ядра
        точки = sorted((кор / "src").glob("*frontend*.py"))
        if точки:
            итог.append((я["site_id"], точки[0], читатель, кор))
    return итог


ЯДРА = _ядра()


def test_есть_что_проверять():
    if not ЯДРА and БЕЗ_КОПИИ:
        pytest.skip("рабочих копий витрин в этом дереве нет: "
                    f"проверить нечем ({len(БЕЗ_КОПИИ)} ячеек)")
    assert len(ЯДРА) >= 5, f"ядер с файловым читателем найдено {len(ЯДРА)}"


def test_прогон_покрывает_все_выложенные_витрины():
    """Неполный прогон не вправе выглядеть полным.

    Измерено 2026-10-05: те же ворота в чужом worktree дали 25 passed вместо
    29, потому что рабочих копий `lords-02` и `animego-04` в том дереве нет.
    Отбор их молча пропустил, и зелёный прогон сертифицировал двенадцать
    витрин из четырёхнадцати, ничем на это не указав.

    Поэтому: если копий нет НИ ОДНОЙ — это другое окружение, и проверка
    пропускается целиком с названной причиной. Если часть есть, а часть нет —
    отказ с перечнем: именно так выглядит частичное покрытие, выданное за
    полное.
    """
    if not ЯДРА:
        pytest.skip("рабочих копий витрин в этом дереве нет")
    assert not БЕЗ_КОПИИ, (
        "эти витрины ВЫЛОЖЕНЫ, но их рабочих копий в этом дереве нет, и ворота "
        f"их не проверили: {sorted(set(БЕЗ_КОПИИ))}. Прогон покрывает "
        f"{len(ЯДРА)} витрин из {len(ЯДРА) + len(set(БЕЗ_КОПИИ))}; "
        "прогоняйте в дереве, где копии есть, либо называйте неполноту прямо")


@pytest.mark.parametrize("site_id,ядро,читатель,репо", ЯДРА,
                         ids=[с for с, _, _, _ in ЯДРА])
def test_файл_читателя_режима_на_месте(site_id, ядро, читатель, репо):
    """Файл, который КОНТРАКТ семейства называет читателем, обязан быть."""
    файл = репо / читатель
    assert файл.is_file(), (
        f"{site_id}: контракт семейства называет читателем {читатель}, а файла "
        "нет. Если ядро только что заменено (пин, инструмент, перенос из "
        "шаблона) — замена унесла механизм режима")


@pytest.mark.parametrize("site_id,ядро,читатель,репо", ЯДРА,
                         ids=[с for с, _, _, _ in ЯДРА])
def test_точка_входа_не_набрала_зашитых_запретов(site_id, ядро, читатель, репо):
    """Число зашитых запретов в мете не РАСТЁТ молча.

    Порог не общий, а ИЗМЕРЕННЫЙ по каждой витрине 2026-10-05, и это не
    поблажка: у семейств законно разные числа. У animego-04 один — ветка
    постера, запрет там намеренный и от режима не зависит (D180). У Yummy два:
    режим тела страницы решает контейнер, а ячейка вправе только ДОужесточать
    (D169), поэтому её собственные зашитые меты на месте по построению.

    Защищает же порог от одного: ядро шаблона несёт ПЯТЬ зашитых мет и ни
    одного читателя. Замена ядра шаблонным увеличила бы число у любой витрины
    — и тест упадёт до выката, а не после. Законный рост порога меняется
    здесь, отдельной правкой с названной причиной.
    """
    т = ядро.read_text(encoding="utf-8")
    порог = ПОРОГ_ЗАШИТЫХ.get(site_id)
    assert порог is not None, (
        f"{site_id}: порог зашитых мет не измерен. Новая выложенная витрина — "
        "измерьте и впишите значение с причиной, а не оставляйте проверку "
        "без основания")
    сколько = т.count(ЗАШИТАЯ_МЕТА)
    assert сколько <= порог, (
        f"{site_id}: зашитых мет `noindex, nofollow` стало {сколько}, измерено "
        f"было {порог}. У ядра шаблона их пять: похоже, ядро сайта заменено "
        "шаблонным, и домен закрылся бы для индексации побочным следствием "
        "выката")
