"""Три исхода у адреса правки: мёртвая, живая через super(), вне класса.

Зачем проверка. Инструмент отвечает на вопрос «куда вносить правку», и у него
две возможные ошибки, причём вторая дороже первой:

* не предупредить о мёртвом адресе — правка выглядит сделанной, а текст
  остаётся на сайте (так вышло у `1lordserials1.online`: ядро правили, а
  `главная()` переопределена слоем без `super()`);
* объявить мёртвой ЖИВУЮ строку — правщик её пропустит, и зелёные проверки
  будут честными. Измерено сессией линии шаблона: в слое витрины `super()`
  вызывается у пяти методов из шести, и текст ядра внутри них рендерится
  («Смотреть онлайн», «Сезон», «Страна» есть только в ядре и видны на
  `/title/bunker/`).

Поэтому признак — не «метод переопределён», а «переопределён У НАСЛЕДНИКА и
`super()` не вызывается». Параллельные классы соседних семейств (в ядре
`главная` есть у пяти видов) предупреждения давать не должны: первая редакция
инструмента пометила так живую строку пятью «мёртвыми».
"""
from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИНСТРУМЕНТ = КОРЕНЬ / "automation" / "local" / "wording-origin.py"

ЯДРО = '''
class Вид:
    def главная(self):
        return "общий текст вида"


class ВидЛордс(Вид):
    def главная(self):
        return "описание из ядра по пометке источника"

    def тайтл(self):
        return "Смотреть онлайн из ядра"


class ВидЗона(Вид):
    def главная(self):
        return "совсем другое семейство"
'''

СЛОЙ_БЕЗ_SUPER = '''
class ВидЛордс02(ВидЛордс):
    def главная(self):
        return "свой текст слоя"

    def тайтл(self):
        return _дополнить(super().тайтл())
'''

СЛОЙ_ТОЛЬКО_ОБЁРТКА = '''
class ВидЛордс02(ВидЛордс):
    def тайтл(self):
        return _дополнить(super().тайтл())
'''

МОДУЛЬНАЯ = '''
def _оценка():
    return "Расследования и разгадки: сериалы с жанром «детектив» в источнике"
'''


@pytest.fixture(scope="module")
def инструмент():
    спец = importlib.util.spec_from_file_location("_происхождение", ИНСТРУМЕНТ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[спец.name] = м
    спец.loader.exec_module(м)
    return м


def выпуск(куда: Path, файлы: dict[str, str]) -> Path:
    (куда / "src").mkdir(parents=True)
    for имя, тело in файлы.items():
        (куда / "src" / имя).write_text(тело, encoding="utf-8")
    return куда


def прогон(релиз: Path, фраза: str) -> str:
    г = subprocess.run([sys.executable, str(ИНСТРУМЕНТ),
                        "--release", str(релиз), "--phrase", фраза],
                       capture_output=True, text=True, timeout=300)
    return (г.stdout or "") + (г.stderr or "")


def test_мёртвый_адрес_назван(tmp_path):
    """Наследник переопределяет метод без super() — ветка ядра мертва."""
    релиз = выпуск(tmp_path / "мёртвый",
                   {"ядро.py": ЯДРО, "слой.py": СЛОЙ_БЕЗ_SUPER})
    вывод = прогон(релиз, "описание из ядра по пометке источника")
    assert "ядро.py" in вывод, вывод
    assert "МЁРТВАЯ" in вывод, вывод
    assert "БЕЗ super()" in вывод
    assert "ВидЛордс02" in вывод


def test_живая_через_super_не_называется_мёртвой(tmp_path):
    """Ошибка обратного знака: объявить мёртвой живую строку дороже."""
    релиз = выпуск(tmp_path / "живой",
                   {"ядро.py": ЯДРО, "слой.py": СЛОЙ_ТОЛЬКО_ОБЁРТКА})
    вывод = прогон(релиз, "Смотреть онлайн из ядра")
    assert "ядро.py" in вывод, вывод
    assert "МЁРТВАЯ" not in вывод, вывод
    assert "живая" in вывод
    assert "только на живой странице" in вывод, (
        "ограничение не названо: перезапись обёрткой статически не ловится")


def test_параллельный_класс_предупреждения_не_даёт(tmp_path):
    """`главная` есть у пяти видов ядра — это не переопределение нашего."""
    релиз = выпуск(tmp_path / "параллельный",
                   {"ядро.py": ЯДРО, "слой.py": СЛОЙ_ТОЛЬКО_ОБЁРТКА})
    вывод = прогон(релиз, "совсем другое семейство")
    assert "ядро.py" in вывод, вывод
    assert "МЁРТВАЯ" not in вывод, вывод


def test_функция_уровня_модуля_не_переопределяется(tmp_path):
    """У функции вне класса переопределять нечего — предупреждать нечем."""
    релиз = выпуск(tmp_path / "модульная",
                   {"подборки.py": МОДУЛЬНАЯ, "ядро.py": ЯДРО})
    вывод = прогон(релиз, "сериалы с жанром «детектив» в источнике")
    assert "подборки.py" in вывод, вывод
    assert "МЁРТВАЯ" not in вывод and "живая:" not in вывод, вывод


def test_фраза_свёрстанная_переносом_находится(tmp_path):
    """Иначе инструмент повторил бы дыру доставляемой проверки."""
    релиз = выпуск(tmp_path / "перенос", {"слой.py": '''
def _о_каталоге():
    return (
        "Раздел записи определяется по жанрам и типу "
        "источника, а не по стране."
    )
'''})
    вывод = прогон(релиз, "по жанрам и типу источника, а не по стране")
    assert "слой.py" in вывод, вывод
    assert "перенос литералов" in вывод


def test_наследование_через_цепочку(инструмент, tmp_path):
    """Наследник наследника тоже переопределяет: цепочка транзитивна."""
    релиз = выпуск(tmp_path / "цепочка", {"ядро.py": ЯДРО, "слой.py": '''
class ВидЛордс02(ВидЛордс):
    pass


class ВидЛордс02Плюс(ВидЛордс02):
    def главная(self):
        return "самый нижний"
'''})
    файлы = sorted((релиз / "src").rglob("*.py"))
    карта = инструмент.классы(файлы)
    assert "ВидЛордс02Плюс" in инструмент.наследники(карта, "ВидЛордс"), (
        "цепочка наследования не прослежена — предупреждение не сработает "
        "там, где слой витрины наследует через промежуточный класс")


def test_формулировка_без_места_меняет_код(tmp_path):
    """«Не найдено» — отдельный исход: текст приходит из артефакта."""
    релиз = выпуск(tmp_path / "ненайдено", {"ядро.py": ЯДРО})
    г = subprocess.run([sys.executable, str(ИНСТРУМЕНТ),
                        "--release", str(релиз), "--phrase", "такого текста нет"],
                       capture_output=True, text=True, timeout=300)
    assert г.returncode == 1, г.stdout + г.stderr
    assert "НЕ найдена" in г.stdout
