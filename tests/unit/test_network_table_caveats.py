"""Оговорки под сводной таблицей сети: столбцы трафика СЫРЫЕ.

Повод измерен на себе 23.10: я прочитала у `yummyani.site` «люди/сут 10 099.6»
и приняла это за превышение порога владельца (5 000 реальных визитов в сутки).
Отчёт тут же это снял — у витрины измерено 53 472 визита HeadlessChrome,
отнесённых Метрикой к людям, — но сама таблица об этом молчала, то есть
предлагала читателю ровно ту ошибку, которую я и сделала.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

ИСТОЧНИК = (Path(__file__).resolve().parents[2]
            / "automation" / "local" / "network-table.py")


@pytest.fixture()
def м():
    спец = importlib.util.spec_from_file_location("network_table", ИСТОЧНИК)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def test_столбцы_трафика_объявлены_сырыми(м):
    т = "\n".join(м.оговорки("2026-10-18", ""))
    assert "СЫРЫЕ" in т
    assert "HeadlessChrome" in т
    assert "53 472" in т


def test_названо_где_считается_порог(м):
    """Иначе читатель сравнивает сырое число с порогом сам."""
    т = "\n".join(м.оговорки("2026-10-18", ""))
    assert "поисковая часть" in т
    assert "owner-report.py" in т


def test_дата_снимка_печатается_всегда(м):
    """Таблица охотно показывает старые числа как текущие."""
    т = "\n".join(м.оговорки("2026-10-18", ""))
    assert "2026-10-18" in т
    assert "НЕ сегодняшние" in т


def test_предупреждение_источника_доходит_до_читателя(м):
    т = "\n".join(м.оговорки("2026-10-23", "MOD-131: рост ЗАВЫШЕН"))
    assert "предупреждение источника: MOD-131: рост ЗАВЫШЕН" in т


def test_отсутствие_предупреждения_называется_прямо(м):
    """«Нет предупреждения» неотличимо от «всё в порядке», если молчать."""
    т = "\n".join(м.оговорки("2026-10-18", "   "))
    assert "ОТСУТСТВУЕТ в файле" in т
    assert "traffic-week-over-week.py" in т
