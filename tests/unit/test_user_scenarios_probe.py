"""REQ-UX-SEARCH-MEASURED: поиск проверяется словом из каталога ЭТОЙ витрины.

Проверка поиска молчала на пяти витринах из пятнадцати: «слово для запроса из
каталога не нашлось — не измерено». Подпись карточки у семейств лежит в разных
местах, а искалась одна форма — `title=` у ссылки, то есть только Lords.

Две ловушки на пути к измерению, обе встречены 2026-10-18 и обе проверяются
здесь:

1. `aria-label` берётся ТОЛЬКО со ссылки карточки. Без этого условия на
   zonafilm.cc берётся «Открыть» (подпись кнопки меню), а на yummyani.site —
   «главную» («вернуться на главную»): проверка отвечает на вопрос о поиске
   словом, которого в каталоге нет.
2. адрес поиска у семейств разный: `/search/?q=` у lords/zona/animego и
   `/search?q=` у yummy (со слэшем 308). Одна форма дала ложную находку
   «поиск пуст» там, где не тот адрес.

После исправления поиск измерен на всех пятнадцати витринах, сомнительных
сценариев 0.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "user-scenarios-probe.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("user_scenarios", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_подпись_из_атрибута_title():
    дом = '<a href="/title/dyshim/" title="Дышим ровно">карточка</a>'
    assert МОД.слово_для_поиска(дом) == ("Дышим", "title=")


def test_подпись_текстом_ссылки():
    дом = '<a class="c" href="/title/kopen/">Копэн и друзья</a>'
    слово, откуда = МОД.слово_для_поиска(дом)
    assert слово == "Копэн" and откуда == "текст ссылки"


def test_подпись_в_aria_label_карточки():
    """Так подписаны карточки Zona: `alt` постера пуст, подпись только здесь."""
    дом = ('<a class="zp" href="/title/grafinya-de-monsoro-2/" '
           'aria-label="Графиня де Монсоро"><span class="zp__img">'
           '<img src="p.webp" alt=""></span></a>')
    слово, откуда = МОД.слово_для_поиска(дом)
    assert слово == "Графиня" and откуда == "aria-label карточки"


def test_aria_label_не_карточки_не_берётся():
    """Отрицательный контроль к главной ловушке.

    «Открыть» (кнопка меню) и «главную» («вернуться на главную») — подписи
    управления, а не названия. Слово не из каталога превращает проверку поиска
    в проверку неизвестно чего, а при пустой выдаче — в ложную находку.
    """
    дом = ('<button aria-label="Открыть меню">≡</button>'
           '<a href="/" aria-label="Вернуться на главную">лого</a>')
    assert МОД.слово_для_поиска(дом) == ("", "")


def test_aria_label_карточки_в_дереве_next():
    """Страница yummy приходит сериализованным деревом с экранированием."""
    дом = ('{\\"href\\":\\"/anime/protivostoyanie-svyatogo\\",'
           '\\"className\\":\\"portal-season-cell\\",'
           '\\"aria-label\\":\\"Противостояние святого\\"}')
    слово, откуда = МОД.слово_для_поиска(дом)
    assert слово == "Противостояние"
    assert откуда == "aria-label карточки в дереве Next.js"


def test_слово_из_слага_последней_попыткой():
    """Законно для рантаймов lords и zona: индекс включает slug и транслит."""
    дом = '<a href="/title/grafinya-de-monsoro-2/"><img src="p.webp"></a>'
    слово, откуда = МОД.слово_для_поиска(дом)
    assert слово == "grafinya" and откуда == "слово из слага"


def test_пусто_значит_не_измерено():
    """Запрос наугад запрещён: «найдено 0» было бы неотличимо от поломки."""
    assert МОД.слово_для_поиска("<p>страница без карточек</p>") == ("", "")
    assert МОД.слово_для_поиска("") == ("", "")


def test_обе_формы_адреса_поиска_перебираются():
    тело = ПУТЬ.read_text(encoding="utf-8")
    assert 'for хвост in ("/search/?q=", "/search?q="):' in тело
    assert "308" in тело, "основание второй формы обязано стоять рядом"
    assert 'if код == "200":' in тело


def test_источник_слова_печатается_рядом_с_ответом():
    """Иначе «найдено 0» не отличить от «спросили не тем словом»."""
    тело = ПУТЬ.read_text(encoding="utf-8")
    assert "поиск «{слово}» ({откуда}, {хвост})" in тело
