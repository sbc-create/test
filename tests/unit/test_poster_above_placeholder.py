"""Постер рисуется ПОВЕРХ буквы-заглушки во всех темах витрин.

Повод измерен 2026-10-17: на девяти живых витринах (восемь K2 и
lordserials22.info) буква-заглушка была видна поверх загруженного постера.
Причина — в общей теме лент у `.zt__p img` не было ни `position`, ни
`z-index`, а `.zt__none` позиционирована: по правилам наложения
позиционированный элемент рисуется поверх непозиционированного независимо от
порядка в разметке.

Проверка смотрит в исходник темы, а не на живую страницу: так она падает до
выпуска, а не после. И она опровергаема — снятие `z-index` из темы её ломает.
"""
from __future__ import annotations

import re
from pathlib import Path

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _правила(селектор: str) -> list[str]:
    """Объявления для селектора в любом месте файла (темы лежат строками)."""
    итог = []
    образец = re.compile(re.escape(селектор) + r"\s*\{([^}]*)\}", re.S)
    for м in образец.finditer(ТЕКСТ):
        итог.append(" ".join(м.group(1).split()))
    return итог


def test_заглушка_позиционирована_а_значит_требует_подъёма_картинки():
    """Исходное условие дефекта: заглушка абсолютная. Если это перестанет быть
    так, проверка ниже потеряет смысл — и об этом надо узнать сразу."""
    правила = _правила(".zt__none")
    assert правила, "правило .zt__none не найдено — тема изменилась"
    assert any("position:absolute" in п for п in правила)


def test_картинка_карточки_поднята_над_заглушкой_во_всех_темах():
    правила = _правила(".zt__p img")
    assert правила, "правило .zt__p img не найдено — тема изменилась"
    без_подъёма = [п for п in правила
                   if "z-index" not in п
                   and "position:relative" not in п
                   and "position:absolute" not in п]
    assert not без_подъёма, (
        "в теме есть правило постера без position/z-index — буква-заглушка "
        f"будет видна поверх картинки: {без_подъёма}")


def test_правила_составного_селектора_тоже_подняты():
    """Темы, где постер адресуется через `.zt__p img,.zt__img`."""
    for селектор in (".zt__img",):
        for п in _правила(селектор):
            assert ("z-index" in п or "position:relative" in п
                    or "position:absolute" in п), (
                f"{селектор}: {п}")
