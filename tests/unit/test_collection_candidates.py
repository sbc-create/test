"""Цепочка кандидатов считается по снимку и не выдаёт недостающее за данные.

Повод — поручение владельца: «покажите короткую цепочку чисел: кандидаты →
соответствуют теме → доступны на сайте → включены» и «пять карточек в ряду не
означает пять произведений во всей подборке».

Главное свойство, которое здесь закрепляется: инструмент НЕ определяет сезон
эфира и статус выхода. В снимке их нет — есть год и дата появления на нашем
сайте. Признак, которого нет в данных, не должен появляться в выводе: иначе
подборка «летнего сезона» соберётся по дате публикации у нас, и это будет
выдумка, одетая в число.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "collection-candidates.py"


@pytest.fixture(scope="module")
def м():
    спец = importlib.util.spec_from_file_location("collection_candidates", ПУТЬ)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def _снимок():
    записи = [
        {"slug": "a", "title": "Полный первый сезон", "year": 2026, "poster": "p"},
        {"slug": "b", "title": "Серии не все", "year": 2026, "poster": "p"},
        {"slug": "c", "title": "Второй сезон", "year": 2026, "poster": "p"},
        {"slug": "d", "title": "Не воспроизводится", "year": 2026, "poster": "p"},
        {"slug": "e", "title": "Прошлый год", "year": 2025, "poster": "p"},
        {"slug": "f", "title": "Фильм", "year": 2026, "poster": "p"},
    ]
    подробности = {
        "a": {"id": "1", "type": "tv", "playable": True, "poster_url": "u",
              "seasons": [{"n": 1, "eps": 12, "avail": 12}]},
        "b": {"id": "2", "type": "tv", "playable": True, "poster_url": "u",
              "seasons": [{"n": 1, "eps": 13, "avail": 12}]},
        "c": {"id": "3", "type": "tv", "playable": True, "poster_url": "u",
              "seasons": [{"n": 2, "eps": 10, "avail": 10}]},
        "d": {"id": "4", "type": "tv", "playable": False, "poster_url": "u",
              "seasons": [{"n": 1, "eps": 10, "avail": 10}]},
        "e": {"id": "5", "type": "tv", "playable": True, "poster_url": "u",
              "seasons": [{"n": 1, "eps": 10, "avail": 10}]},
        "f": {"id": "6", "type": "movie", "playable": True, "poster_url": "u",
              "seasons": []},
    }
    return записи, подробности


def test_цепочка_отсеивает_по_шагам(м):
    записи, подробности = _снимок()
    шаги, годные = м.цепочка(записи, подробности, год=2026, вид="tv",
                             первый_сезон=True)
    числа = {имя: число for имя, число, _ in шаги}
    assert числа["всего в каталоге"] == 6
    assert числа["год 2026"] == 5
    assert числа["type=tv"] == 4
    assert числа["все серии доступны"] == 3
    assert числа["воспроизводится"] == 2
    assert числа["первый сезон"] == 1
    assert [з["slug"] for з in годные] == ["a"]


def test_каждый_шаг_называет_убыль(м):
    """Число без убыли не отвечает на вопрос «а куда делись остальные»."""
    записи, подробности = _снимок()
    шаги, _ = м.цепочка(записи, подробности, год=2026, вид="tv",
                        первый_сезон=True)
    убыли = [у for _, _, у in шаги[1:]]
    assert all(у.startswith("−") for у in убыли), убыли


def test_ноль_серий_полнотой_не_считается(м):
    """Иначе фильм без серий попал бы в «все серии доступны»."""
    assert м.полные_серии([]) is False
    assert м.полные_серии([{"n": 1, "eps": 0, "avail": 0}]) is False
    assert м.полные_серии([{"n": 1, "eps": 10, "avail": 10}]) is True
    assert м.полные_серии([{"n": 1, "eps": 10, "avail": 9}]) is False


def test_оценка_берётся_только_с_числом_голосов(м):
    """Оценка без голосов основанием не является: ровно на этом строится
    запрет «высокая оценка на малой выборке»."""
    записи, подробности = _снимок()
    подробности["a"]["ratings_by_source"] = {"imdb": {"rating": 9.9}}
    без = м.описать(записи[0], подробности)
    assert без["оценка"] is None, без["оценка"]
    подробности["a"]["ratings_by_source"] = {"imdb": {"rating": 7.2, "votes": 103}}
    с = м.описать(записи[0], подробности)
    assert с["оценка"]["голосов"] == 103


def test_сезон_эфира_не_выдумывается(м):
    """В снимке даты эфира нет. Инструмент не должен её ни выводить, ни
    подменять датой появления у нас — иначе «летний сезон» соберётся по
    публикации на нашем сайте."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "published_at" not in текст.split('"""', 2)[2], (
        "published_at не должен участвовать в отборе: это дата появления "
        "у нас, а не дата эфира")
    записи, подробности = _снимок()
    описание = м.описать(записи[0], подробности)
    assert "сезон эфира" not in описание and "статус" not in описание


def test_инструмент_только_читает(м):
    """Снимок витрины — постоянные данные: их правка запрещена правилом."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    for опасное in ("write_text(", "open(", "unlink(", "rmtree("):
        внутри = [с for с in текст.splitlines()
                  if опасное in с and "out_json" not in с and "--out-json" not in с]
        assert not внутри, (опасное, внутри[:3])
