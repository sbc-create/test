"""Публичный HTML витрины не несёт служебных строк.

На 2026-09-15 три домена Yummy отдавали посетителю и поиску строку вида

    Template: yummy 1.4.5 · cf558484

Сведения о сборке в публичном тексте не становятся безобидными оттого, что
набраны мелко: они просто перестают быть заметными нам, оставаясь заметными
снаружи. По той же причине из подвала убрано «тестовая витрина, закрыта от
индексации»: домен рабочий, называть его стендом — неправда, а состояние
индексации сообщают заголовок, robots.txt и мета-тег, а не подпись для людей.

Бейдж не удалён, а выключен по умолчанию: на стенде он полезен. Включается
переменной ``LORDS_TEMPLATE_BADGE=1``.

Сведения о сборке никуда не делись — их несут мета-теги ``site-factory-*`` и
атрибуты ``data-template-*``, которыми пользуется приёмка выкладки. Убран
ровно тот слой, который читает человек.
"""

from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ФРОНТ = КОРЕНЬ / "automation" / "host" / "yummy-frontend.py"

#: Строки, которых не должно быть в публичном HTML ни при каких условиях.
ЗАПРЕЩЁННЫЕ = (
    "тестовая витрина",
    "тестовый стенд",
    "SITE_LEGAL_NAME",
    "SITE_CONTACT_EMAIL",
    "будут опубликованы после заполнения",
    "сведения не выдумываются",
)


def _исходник() -> str:
    return ФРОНТ.read_text(encoding="utf-8")


def test_stand_wording_is_gone_from_the_renderer() -> None:
    исходник = _исходник()
    for фраза in ЗАПРЕЩЁННЫЕ:
        assert фраза not in исходник, (
            f"«{фраза}» попадает в публичный HTML рабочего домена"
        )


def test_build_badge_is_off_unless_asked_for() -> None:
    исходник = _исходник()
    assert 'ПОКАЗЫВАТЬ_БЕЙДЖ = os.environ.get("LORDS_TEMPLATE_BADGE", "") == "1"' in исходник, (
        "бейдж обязан быть выключен по умолчанию, а не включён по умолчанию"
    )


def test_every_badge_is_behind_the_flag() -> None:
    """Ни одна вставка бейджа не должна остаться безусловной.

    Их две и они в разных местах — подвал собственной страницы и вставка в
    ответ вышестоящего приложения. Выключить одну и забыть вторую — ровно тот
    исход, ради которого написана эта проверка.
    """
    исходник = _исходник()
    for номер, строка in enumerate(исходник.splitlines(), 1):
        if "Template:" not in строка or строка.lstrip().startswith("#"):
            continue
        окно = "\n".join(исходник.splitlines()[max(0, номер - 12) : номер])
        assert "ПОКАЗЫВАТЬ_БЕЙДЖ" in окно, (
            f"строка {номер}: бейдж собирается без проверки флага диагностики"
        )


def test_build_facts_are_still_available_to_acceptance() -> None:
    """Приёмка выкладки сверяет ревизию по мета-тегам — их трогать нельзя."""
    исходник = _исходник()
    assert "data-template-version" in исходник
    assert "data-template-family" in исходник
    assert "data-build-id" in исходник


def test_renderer_still_parses() -> None:
    import ast

    ast.parse(_исходник())


def test_footer_no_longer_claims_the_site_is_a_stand() -> None:
    исходник = _исходник()
    подвалы = re.findall(r'<footer[^>]*>.*?</footer>', исходник, re.S)
    assert подвалы, "подвал не найден: проверка потеряла предмет"
    for подвал in подвалы:
        assert "витрина" not in подвал or "тестовая" not in подвал
