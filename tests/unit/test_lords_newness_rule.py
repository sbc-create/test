"""Новинки — это недавно ВЫШЕДШЕЕ, а не недавно загруженное.

Дефект, который здесь закрыт, стоил дорого и был невидим изнутри кода:
блоки новинок отбирались по `published_at`, а `published_at` в снимке — дата
попадания записи в НАШУ базу. Массовая заливка архива ставит её всем записям
сразу, и витрина честно показывала «новинки», которых не выходило.

Замер на боевом снимке lords-01 (56 087 записей, 2026-10-01):

    окно  14 дней: 2 575 записей, после правила — 275
    окно  30 дней: 2 973 записи,  после правила — 500
    окно 365 дней: 17 885 записей, после правила — 5 401

В тридцатидневном окне лежал фильм 1960 года с `published_at` вчерашним.

Проверки ниже перечисляют ровно те случаи, из-за которых дефект возник, и
проверяют ПРАВИЛО, а не его вызов в одном месте: правило общее для всех
семейств и всех блоков.
"""
from __future__ import annotations

import importlib.util
import sys
from datetime import date, timedelta
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]


def _контракт():
    путь = КОРЕНЬ / "automation" / "host" / "collection_contract.py"
    спец = importlib.util.spec_from_file_location("collection_contract_нов", путь)
    мод = importlib.util.module_from_spec(спец)
    sys.modules["collection_contract_нов"] = мод
    спец.loader.exec_module(мод)
    return мод


КК = _контракт()
СЕГОДНЯ = date(2026, 10, 1)
ГРАНИЦА = КК.граница_новинок(сегодня=СЕГОДНЯ)


def запись(**поля):
    з = {"slug": "t", "title": "Т", "kind": "Фильм"}
    з.update(поля)
    return з


def test_граница_считается_от_сегодня_а_не_зашита():
    """Зашитый год перестаёт быть правдой 1 января."""
    исходник = (КОРЕНЬ / "automation" / "host" / "collection_contract.py").read_text(
        encoding="utf-8")
    кусок = исходник[исходник.index("ОКНО_НОВИНОК_ДНЕЙ ="):исходник.index("def год_выхода")]
    import re
    зашитые = re.findall(r"\b(19|20)\d{2}\b", кусок)
    assert not зашитые, f"в правиле новинок зашит год: {зашитые}"
    assert КК.граница_новинок(сегодня=date(2030, 3, 4)) == date(2029, 3, 4)
    assert КК.граница_новинок(30, сегодня=date(2030, 3, 4)) == date(2030, 2, 2)


def test_окно_по_умолчанию_365_дней():
    assert КК.ОКНО_НОВИНОК_ДНЕЙ == 365
    assert date(2025, 10, 1) == ГРАНИЦА


# --- причины дефекта, по одной ----------------------------------------------

def test_фильм_1960_года_импортированный_сегодня_не_новинка():
    """Главная причина: свежая загрузка выдавалась за свежий выход."""
    з = запись(year=1960, published_at="2026-09-30T20:59:03Z")
    assert КК.новинка(з, ГРАНИЦА, СЕГОДНЯ) is False
    assert КК.только_новинки([з], сегодня=СЕГОДНЯ) == []


def test_свежий_выпущенный_фильм_остаётся_новинкой():
    """Правило обязано не только отсекать, но и пропускать."""
    з = запись(year=2026, published_at="2026-09-30T20:59:03Z")
    assert КК.новинка(з, ГРАНИЦА, СЕГОДНЯ) is True


def test_повторный_импорт_не_возвращает_архив_в_новинки():
    """Та же запись, доставленная заново: дата загрузки свежая, год прежний."""
    было = запись(year=1998, published_at="2024-11-12T00:00:00Z")
    стало = dict(было, published_at="2026-10-01T03:30:00Z")
    assert КК.новинка(было, ГРАНИЦА, СЕГОДНЯ) is False
    assert КК.новинка(стало, ГРАНИЦА, СЕГОДНЯ) is False


@pytest.mark.parametrize("поле", ["poster", "description", "rating", "voice", "source"])
def test_правка_оформления_не_возвращает_старый_тайтл_в_новинки(поле):
    """Постер, описание, оценка, озвучка и источник к выходу не относятся."""
    старый = запись(year=2005, published_at="2026-10-01T00:00:00Z", **{поле: "новое"})
    assert КК.новинка(старый, ГРАНИЦА, СЕГОДНЯ) is False


def test_неизвестная_дата_не_становится_сегодняшней():
    """Без года запись остаётся в каталоге, но новинкой не объявляется."""
    без_года = запись(published_at="2026-09-30T00:00:00Z")
    без_загрузки = запись(year=2026)
    assert КК.новинка(без_года, ГРАНИЦА, СЕГОДНЯ) is False
    assert КК.новинка(без_загрузки, ГРАНИЦА, СЕГОДНЯ) is False
    assert КК.год_выхода(без_года) is None


def test_будущая_премьера_это_анонс_а_не_новинка():
    з = запись(year=2027, published_at="2026-09-30T00:00:00Z")
    assert КК.новинка(з, ГРАНИЦА, СЕГОДНЯ) is False
    assert КК.анонс(з, СЕГОДНЯ) is True
    assert КК.анонс(запись(year=2026), СЕГОДНЯ) is False


def test_год_из_мусора_не_принимается():
    """`year` строкой, булевым или вне диапазона — это отсутствие года."""
    for мусор in ("2026", True, 0, 12, 9999, None, 1869.0):
        assert КК.год_выхода(запись(year=мусор)) is None


# --- отбор идёт ДО предела и листалки ---------------------------------------

def _смесь(n=300):
    """Представительная смесь: архив, свежее и будущее вперемешку."""
    сделано = []
    for i in range(n):
        if i % 3 == 0:
            год = 1960 + (i % 50)
        elif i % 11 == 0:
            год = СЕГОДНЯ.year + 1
        else:
            год = СЕГОДНЯ.year - (i % 2)
        сделано.append(запись(
            slug=f"s{i:03d}", year=год,
            published_at=(СЕГОДНЯ - timedelta(days=i % 20)).isoformat() + "T00:00:00Z"))
    return сделано


def test_фильтрация_идёт_до_предела():
    """Срезав архив после предела, страница показала бы предел чужих карточек."""
    смесь = _смесь()
    предел = 12
    неверно = sorted(смесь, key=lambda з: з["published_at"], reverse=True)[:предел]
    верно = КК.только_новинки(смесь, сегодня=СЕГОДНЯ)[:предел]
    assert any(КК.новинка(з, ГРАНИЦА, СЕГОДНЯ) is False for з in неверно), (
        "смесь обязана содержать архив, иначе проверка пустая")
    assert len(верно) == предел
    assert all(КК.новинка(з, ГРАНИЦА, СЕГОДНЯ) for з in верно)


def test_следующая_страница_подчиняется_тому_же_правилу():
    """Листалка не обязана добирать архивом то, чего не хватило на первой."""
    отобрано = КК.только_новинки(_смесь(), сегодня=СЕГОДНЯ)
    страницы = [отобрано[i:i + 12] for i in range(0, len(отобрано), 12)]
    assert len(страницы) > 1, "смесь обязана давать больше одной страницы"
    for н, стр in enumerate(страницы, 1):
        чужие = [з["slug"] for з in стр if not КК.новинка(з, ГРАНИЦА, СЕГОДНЯ)]
        assert not чужие, f"на странице {н} архив: {чужие}"


def test_блок_не_добирается_архивом_при_нехватке():
    """Нехватка новинок — это короткий блок, а не длинный блок с архивом."""
    только_архив = [запись(slug=f"a{i}", year=1970 + i,
                           published_at=СЕГОДНЯ.isoformat() + "T00:00:00Z")
                    for i in range(50)]
    assert КК.только_новинки(только_архив, сегодня=СЕГОДНЯ) == []


# --- серии -------------------------------------------------------------------

def test_новая_серия_старого_сериала_не_делает_его_премьерой():
    """Возраст сериала оценивается по сезону, а не по факту новой серии.

    Сам сериал 2014 года премьерой не становится ни при какой свежести серий;
    место новой серии — в обновлениях, и попадает она туда только с
    подтверждённой датой эпизода.
    """
    сериал = запись(slug="s", kind="Сериал", year=2014,
                    published_at=СЕГОДНЯ.isoformat() + "T00:00:00Z")
    assert КК.новинка(сериал, ГРАНИЦА, СЕГОДНЯ) is False


def test_новая_озвучка_не_является_выходом_серии():
    """Озвучка, качество и повторная доставка — не событие выхода.

    Событием считается только эпизод с собственной датой; без неё блок
    остаётся пустым, а не наполняется тем, что под рукой.
    """
    снимок = КК.Снимок(
        items=[запись(slug="s", kind="Сериал", year=2014,
                      published_at=СЕГОДНЯ.isoformat() + "T00:00:00Z")],
        подробности={"s": {"seasons": [{"n": 1, "eps": 10, "avail": 10,
                                        "episodes": [{"n": 3, "voice": "новая озвучка"}]}]}},
    )
    assert снимок.эпизод_события() == []


def test_подтверждённая_новая_серия_становится_событием():
    снимок = КК.Снимок(
        items=[запись(slug="s", kind="Сериал", year=2014,
                      published_at=СЕГОДНЯ.isoformat() + "T00:00:00Z")],
        подробности={"s": {"seasons": [{"n": 9, "eps": 10, "avail": 10,
                                        "episodes": [{"n": 3, "published_at": "2026-09-29"}]}]}},
    )
    assert [з["slug"] for з in снимок.эпизод_события()] == ["s"]
