class TestЗапросОстаётсяВПоле:
    """Страница результатов с пустым полем стирает вопрос посетителя."""

    ШАПКА = ('<header><form><input class="portal-search-input" name="q" '
             'value="" placeholder="Поиск"/></form></header>')

    def test_значение_подставляется(self):
        о = СТР.подставить_запрос({"header": self.ШАПКА}, "воин")
        assert 'value="воин"' in о["header"]
        assert о["header"].count("value=") == 1

    def test_кавычки_экранируются(self):
        о = СТР.подставить_запрос({"header": self.ШАПКА}, 'а"б<в')
        assert 'value="а&quot;б&lt;в"' in о["header"]
        assert '<в"' not in о["header"]

    def test_самозакрывающийся_тег_остаётся_самозакрывающимся(self):
        о = СТР.подставить_запрос({"header": self.ШАПКА}, "мир")
        assert 'value="мир"/>' in о["header"]

    def test_пустой_запрос_шапку_не_трогает(self):
        о = СТР.подставить_запрос({"header": self.ШАПКА}, "")
        assert о["header"] == self.ШАПКА

    def test_исходная_оболочка_не_меняется(self):
        исходная = {"header": self.ШАПКА}
        СТР.подставить_запрос(исходная, "воин")
        assert исходная["header"] == self.ШАПКА


class TestКонтраст:
    """Цвет текста поверх акцента выбирается измерением, а не привычкой."""

    def test_белый_на_акценте_не_проходил_норму(self):
        # Ровно то значение, что измерил axe на 272 узлах страницы /top/.
        assert round(СТР.контраст("#ffffff", "#6d8cff"), 2) == 3.07

    def test_выбирается_цвет_с_большим_контрастом(self):
        for акцент in ("#6d8cff", "#ff5c8a", "#4dd0a0"):
            текст = СТР.текст_на(акцент)
            assert СТР.контраст(текст, акцент) >= 4.5, акцент

    def test_на_чёрном_фоне_текст_светлый(self):
        assert СТР.текст_на("#000000") == СТР.СВЕТЛЫЙ_ТЕКСТ

    def test_короткая_запись_цвета_понимается(self):
        assert СТР.светлота("#fff") == СТР.светлота("#ffffff")

    def test_непонятный_цвет_считается_тёмным(self):
        """Ошибка разбора не должна давать белое по белому."""
        assert СТР.текст_на("не цвет") == СТР.СВЕТЛЫЙ_ТЕКСТ

    def test_акценты_всех_трёх_профилей_проходят(self):
        варианты = _модуль("yummy_variants", "yummy_variants.py").ВАРИАНТЫ
        for домен, в in варианты.items():
            текст = СТР.текст_на(в["акцент"])
            assert СТР.контраст(текст, в["акцент"]) >= 4.5, домен

    def test_содержательный_текст_не_красится_акцентом(self):
        """Номер места и подпись оценки — текст, а не украшение."""
