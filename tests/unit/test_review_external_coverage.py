"""Файл внешней сверки имён принимается только за ПОЛНОЕ покрытие.

Повод измерен 25.10 04:2xZ. В `sources` черновика витрина записывает и СВОЮ
страницу, а текст черновика на ней уже стоит, поэтому сверка «подтверждала»
имена по тому самому тексту, который проверяла: на
`zonafilm12.site/bratya-gonschiki-lets-i-gou` оба имени (Тэцухиро, Коситы)
были подтверждены страницей самой витрины. Ворота рецензии при этом смотрели
только на пустой `not_found` — то есть принимали и такое подтверждение, и файл,
в котором отмеченного имени нет вовсе.

Отрицательные контроли названы заранее: полное внешнее покрытие по-прежнему
принимается, а падежная и письменная пометка в `confirmed` («Дунфану [основа
слова]», «Алисса (как «Alyssa»)») покрытием считается — иначе сверка перестала
бы работать там, где она и была нужна.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "review-materials-batch.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("review_materials_batch", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_полное_внешнее_покрытие_принимается():
    покрыто, непокрытые = МОД.внешне_покрыто(
        ["Итогами", "Акацуки"],
        {"confirmed": ["Итогами", "Акацуки"], "not_found": [],
         "own_network_only": []})
    assert покрыто and непокрытые == []


def test_имя_найденное_только_у_себя_покрытием_не_считается():
    покрыто, непокрытые = МОД.внешне_покрыто(
        ["Тэцухиро", "Коситы"],
        {"confirmed": [], "not_found": [], "own_network_only": ["Тэцухиро", "Коситы"]})
    assert not покрыто
    assert непокрытые == ["Тэцухиро", "Коситы"]


def test_частичное_эхо_тоже_не_покрытие():
    """Четыре внешних подтверждения не отвечают за два своих."""
    покрыто, непокрытые = МОД.внешне_покрыто(
        ["Итогами", "Акацуки", "Тартарус", "Лапс", "Гакуто", "Микумо"],
        {"confirmed": ["Итогами", "Акацуки", "Тартарус", "Лапс"],
         "not_found": [], "own_network_only": ["Гакуто", "Микумо"]})
    assert not покрыто
    assert непокрытые == ["Гакуто", "Микумо"]


def test_не_найденное_имя_остаётся_непокрытым():
    покрыто, непокрытые = МОД.внешне_покрыто(
        ["Алисса"], {"confirmed": [], "not_found": ["Алисса"],
                     "own_network_only": []})
    assert not покрыто and непокрытые == ["Алисса"]


def test_файл_без_отмеченного_имени_не_подтверждение():
    """«Ни одного не найдено» неотличимо от «все подтверждены» без этой проверки."""
    покрыто, непокрытые = МОД.внешне_покрыто(
        ["Гакуто", "Микумо"],
        {"confirmed": ["Итогами"], "not_found": [], "own_network_only": []})
    assert not покрыто
    assert непокрытые == ["Гакуто", "Микумо"]


def test_падежная_пометка_покрытием_считается():
    покрыто, непокрытые = МОД.внешне_покрыто(
        ["Дунфану"],
        {"confirmed": ["Дунфану [основа слова]"], "not_found": [],
         "own_network_only": []})
    assert покрыто and непокрытые == []


def test_пометка_письменности_покрытием_считается():
    покрыто, _ = МОД.внешне_покрыто(
        ["Алисса"],
        {"confirmed": ["Алисса (как «Alyssa»)"], "not_found": [],
         "own_network_only": []})
    assert покрыто


def test_старый_файл_сверки_без_нового_поля_не_ломает_ворота():
    """Файлы, снятые до 25.10, поля `own_network_only` не несут."""
    покрыто, _ = МОД.внешне_покрыто(
        ["Итогами"], {"confirmed": ["Итогами"], "not_found": []})
    assert покрыто


# --- жалоба ворот качества на год против года ИСТОЧНИКА ----------------------
#
# Измерено 25.10: снимок каталога у сезонов франшизы несёт год ПЕРВОГО сезона.
# `rukovodstvo-soten-demonov-4` — снимок 2020, Shikimori `animes/57995`
# `aired_on 2024-02-23`; `reyting-korolya-sunduk-s-sokrovischami-muzhestva` —
# снимок 2022, `animes/52657` `aired_on 2023-04-14`. Требование дописать такой
# год противоречит источнику, и редактор обязан его отклонить (MOD-178).


def test_жалоба_о_годе_снимается_когда_источник_называет_другой():
    остались, снятые = МОД.снять_жалобу_о_годе(
        ["в тексте нет года 2020 — он есть в снимке и его стоит назвать"],
        ["https://shikimori.io/animes/57995"],
        читатель=lambda и: ("2024", "https://shikimori.io/animes/57995", ""))
    assert остались == []
    assert len(снятые) == 1
    assert "называет 2024" in снятые[0]


def test_жалоба_остаётся_когда_источник_год_подтверждает():
    остались, снятые = МОД.снять_жалобу_о_годе(
        ["в тексте нет года 2024 — он есть в снимке и его стоит назвать"],
        ["https://shikimori.io/animes/57995"],
        читатель=lambda и: ("2024", "https://shikimori.io/animes/57995", ""))
    assert снятые == []
    assert "источник подтверждает" in остались[0]


def test_непрочитанный_источник_жалобу_не_снимает():
    """«Не проверено» — не повод снять требование."""
    остались, снятые = МОД.снять_жалобу_о_годе(
        ["в тексте нет года 2020 — он есть в снимке и его стоит назвать"],
        ["https://shikimori.io/animes/57995"],
        читатель=lambda и: ("", "https://shikimori.io/animes/57995", "API отказал"))
    assert снятые == []
    assert "не прочитан" in остались[0]


def test_прочие_беды_не_затрагиваются():
    остались, снятые = МОД.снять_жалобу_о_годе(
        ["текст короче 400 знаков", "в тексте нет года 2020 — он есть в снимке"],
        ["https://shikimori.io/animes/57995"],
        читатель=lambda и: ("2024", "https://shikimori.io/animes/57995", ""))
    assert остались == ["текст короче 400 знаков"]
    assert len(снятые) == 1


def test_источник_читается_один_раз_на_материал():
    вызовы = []

    def читатель(источники):
        вызовы.append(источники)
        return ("2024", "https://shikimori.io/animes/57995", "")

    МОД.снять_жалобу_о_годе(
        ["в тексте нет года 2020 — он есть в снимке",
         "в тексте нет года 2021 — он есть в снимке"],
        ["https://shikimori.io/animes/57995"], читатель=читатель)
    assert len(вызовы) == 1


def test_без_карточки_shikimori_год_не_измерим():
    год, адрес, причина = МОД.год_источника(["https://an1meg0.site/title/x/"])
    assert год == "" and адрес == ""
    assert "нет карточки Shikimori" in причина
