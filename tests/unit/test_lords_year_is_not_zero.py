"""Ноль в поле года — отсутствие данных, а не категория.

Правило в каталоге уже есть и записано у стран прямо: «Пустое значение —
отсутствие данных, а не категория». К годам его не применили, и следствие
видно на собранной витрине: раздел `/years/0/` с заголовком «Год выпуска: 0» и
404 записями.

Это утверждение, которого источник не делал. У 2 746 записей боевого каталога
года нет вовсе; адаптер ставит им ноль, и разметка страницы произведения такой
факт не печатает — а указатель годов печатает, и делает из отсутствия
отдельный год.

Найдено проверкой маршрутов предпросмотра, а не чтением: `/years/0/` отвечал
200 и выглядел обычным разделом.
"""

from __future__ import annotations

from factory.lords import fixtures as fx


class Запись:
    def __init__(self, year, slug="z"):
        self.slug = slug
        self.name = "Пример"
        self.content_type = "movies"
        self.year = year
        self.country_slug = ""
        self.country = ""
        self.genre_slugs = ()
        self.genres = ()
        self.seasons = ()


def каталог(*годы) -> fx.Catalog:
    return fx.Catalog(
        titles=tuple(Запись(y, f"z-{i}") for i, y in enumerate(годы)),
        collections=())


class TestГодНольНеСтановитсяРазделом:
    def test_ноль_не_попадает_в_указатель(self):
        годы = dict(каталог(2024, 0, 0, 2023).years())
        assert 0 not in годы, "ноль объявлен годом выпуска"

    def test_настоящие_годы_остаются(self):
        годы = dict(каталог(2024, 0, 2023).years())
        assert годы == {2024: 1, 2023: 1}

    def test_каталог_без_годов_даёт_пустой_указатель(self):
        assert каталог(0, 0, 0).years() == ()

    def test_отрицательный_год_тоже_отвергается(self):
        """Год до нашей эры в каталоге видеоматериалов — испорченное значение."""
        assert dict(каталог(-5, 2020).years()) == {2020: 1}

    def test_порядок_прежний(self):
        assert [y for y, _ in каталог(2019, 2024, 0, 2021).years()] == [2024, 2021, 2019]
