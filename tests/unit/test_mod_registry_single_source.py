"""Номера MOD не должны расходиться между линиями.

Поручение владельца 26.10: «сверь расхождение номеров MOD между линиями и общий
источник учёта». Измерено в тот же день: расхождения по СОДЕРЖАНИЮ нет — все 26
записей линии SEO совпадают с моими по заголовку, то есть их файл это префикс
моего. Опасность не в прошлом, а в будущем: файла нет в `main`, каждая ветвь
растит свою копию, и две линии легко заведут два РАЗНЫХ MOD-199.

Проверка ловит именно это: общий номер с разным заголовком. Она же объясняет,
откуда брать следующий номер, если копии разной полноты.
"""
from __future__ import annotations

import json
import pathlib
import subprocess

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "seo-module-defects.json"
#: Рабочие копии других линий, где может лежать своя копия реестра.
ЧУЖИЕ_КОПИИ = ("/home/claude/wt-portable-site-cell-01",)
#: Номер снят как дубль 21.10 (MOD-55 и MOD-71 измерили то же раньше).
#: Пропуск намеренный: переиспользовать номер нельзя, он уже назван в отчётах.
СНЯТЫЕ = {126}


def _записи(текст: str) -> dict[str, str]:
    return {з["id"]: з.get("title", "") for з in json.loads(текст)["defects"]}


def мои() -> dict[str, str]:
    return _записи(РЕЕСТР.read_text(encoding="utf-8"))


def test_номера_уникальны_и_без_случайных_пропусков():
    записи = мои()
    номера = sorted(int(i.split("-")[1]) for i in записи)
    assert len(номера) == len(set(номера)), "повторяющиеся номера"
    пропуски = {n for n in range(1, номера[-1]) if n not in номера}
    assert пропуски == СНЯТЫЕ, (
        f"пропуски {sorted(пропуски)} не объяснены: снятый номер перечисляется "
        "в СНЯТЫЕ с причиной, иначе непонятно, свободен он или потерян")


@pytest.mark.parametrize("копия", ЧУЖИЕ_КОПИИ)
def test_общие_номера_не_расходятся_по_содержанию(копия):
    путь = pathlib.Path(копия)
    if not путь.is_dir():
        pytest.skip(f"копии {копия} нет на этой машине")
    г = subprocess.run(["git", "-C", копия, "show", "HEAD:config/seo-module-defects.json"],
                       capture_output=True, text=True)
    if г.returncode:
        pytest.skip(f"в {копия} нет реестра в HEAD")
    их, свои = _записи(г.stdout), мои()
    общие = sorted(set(их) & set(свои))
    расходятся = [i for i in общие if их[i] != свои[i]]
    assert not расходятся, (
        "один номер с разными заголовками в двух линиях: "
        + "; ".join(f"{i}: «{свои[i][:40]}» против «{их[i][:40]}»" for i in расходятся[:3]))


@pytest.mark.parametrize("копия", ЧУЖИЕ_КОПИИ)
def test_следующий_номер_берётся_от_полной_копии(копия):
    """Если копии разной полноты, следующий номер — от САМОЙ ПОЛНОЙ.

    Иначе линия с отстающей копией выдаст номер, который уже занят у другой.
    """
    путь = pathlib.Path(копия)
    if not путь.is_dir():
        pytest.skip(f"копии {копия} нет")
    г = subprocess.run(["git", "-C", копия, "show", "HEAD:config/seo-module-defects.json"],
                       capture_output=True, text=True)
    if г.returncode:
        pytest.skip("реестра в HEAD чужой копии нет")
    их, свои = _записи(г.stdout), мои()
    макс_их = max(int(i.split("-")[1]) for i in их)
    макс_свой = max(int(i.split("-")[1]) for i in свои)
    assert макс_свой >= макс_их, (
        "чужая копия полнее моей: следующий номер нужно брать от неё, "
        f"у них MOD-{макс_их:03d}, у меня MOD-{макс_свой:03d}")
    assert set(их) <= set(свои), (
        "в чужой копии есть номера, которых нет у меня: "
        f"{sorted(set(их) - set(свои))}")
