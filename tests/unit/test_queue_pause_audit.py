def test_остаток_после_разрешения_ссылок_осмыслен():
    """Главное измерение правки: неопознанных видов в живых очередях больше нет."""
    источники = инс.источники_ссылок(КОРЕНЬ / "docs")
    канарейки = инс.опыты_по_домену()
    неопознанные = []
    for файл in sorted((КОРЕНЬ / "config" / "domain-queues").glob("*.json")):
        данные = json.loads(файл.read_text(encoding="utf-8"))
        for задача in данные.get("tasks") or []:
            текст = str(задача.get("blocked_by") or "")
            if not текст:
                continue
            вид = инс.вид_заморозки(текст, источники=источники, канарейки=канарейки)
            if вид == "не определён":
                неопознанные.append((данные.get("domain") or файл.stem, задача.get("id")))
    assert not неопознанные, f"вид заморозки не определён: {неопознанные}"
