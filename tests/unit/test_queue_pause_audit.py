def test_чужой_вердикт_требует_метки_и_домена():
    ладно, вид, почему = _пров(
        "ждёт приёмки канарейки T317 на zonafilm12.site: переносить до вердикта нельзя")
    assert ладно and вид == "чужой_вердикт" and "T317" in почему and "zonafilm12.site" in почему
    плохо, вид2, почему2 = _пров("ждёт приёмки канарейки T317: вердикта пока нет")
