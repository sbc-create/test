# --- Ссылка разрешается раньше даты (найдено на 30 заморозках Yummy) ---------

def _ист(tmp_path, *, номера=("B037",), документы=("OWNER_BLOCK_SAMPLE.md",)):
    """Поддельные документы: ссылка подтверждается ИСТОЧНИКОМ, а не образцом."""
    каталог = tmp_path / "docs"
    каталог.mkdir()
    (каталог / "BLOCKERS.md").write_text(
        "\n".join(f"### {н}: препятствие" for н in номера), encoding="utf-8")
    for д in документы:
        (каталог / д).write_text("блок владельца\n", encoding="utf-8")
    return инс.источники_ссылок(каталог)


def test_документ_владельца_сильнее_попутной_даты(tmp_path):
    """Корень дефекта: вход владельца считался СЛОВЕСНЫМ видом и стоял после даты.

    Текст Yummy называет блокер и документ владельца, а дата 23.10 в нём — о
    чужой правке на оценке. Прежний порядок звал такую заморозку
    «просроченной» и требовал продлить дату, хотя продлевать нечего: ждут
    названного входа владельца.
    """
    текст = ("сборка и образ Yummy недоступны (B037): выпуск через владельца; "
             "правки B031 и B033 стоят на оценке 23.10 — см. OWNER_BLOCK_SAMPLE.md")
    источники = _ист(tmp_path)
    assert инс.вид_заморозки(текст, источники=источники) == "вход_владельца"
    ладно, вид, почему = инс.проверить(текст, реестр=set(), журнал={},
                                       сегодня=СЕГОДНЯ, источники=источники)
    assert ладно and вид == "вход_владельца"
    assert "OWNER_BLOCK_SAMPLE.md" in почему


def test_ненайденная_ссылка_не_подтверждение(tmp_path):
    """Номер, которого нет ни в одном документе, ничего не подтверждает."""
    текст = "решение владельца по B999: такого блокера нет ни в одном документе"
    источники = _ист(tmp_path)
    assert инс.названные_ссылки(текст, источники) == []
    _, вид, почему = инс.проверить(текст, реестр=set(), журнал={},
                                   сегодня=СЕГОДНЯ, источники=источники)
    assert вид == "вход_владельца" and "без проверяемой ссылки" in почему


def test_номер_блокера_без_слов_владельца_это_ограничение(tmp_path):
    """Вид берётся из самой ссылки: номер — ограничение, OWNER_* — владелец."""
    текст = "по Яндексу различить нечем: журнала обхода нет, Вебмастера нет (B037)"
    источники = _ист(tmp_path)
