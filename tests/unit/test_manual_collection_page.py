"""Страница редакционной подборки — ОТРИСОВКОЙ, а не чтением шаблона.

Требование владельца к поставке подборок: `/collection/<key>/` отдаёт 200,
несёт заголовок, вступление, порядок и пояснение к каждой карточке ровно как в
файле; индексация — по решению из файла; при обновлении каталога исчезнувший
`id` не подменяется, а помечается.
"""
from __future__ import annotations

import json
import pathlib
import re

import pytest

import lords_runtime_harness as оснастка


def _подборка(ключ: str, работы: list, *, открыта: bool = True) -> dict:
    return {
        "key": ключ,
        "title": "Триллеры на вечер",
        "viewer_request": "посмотреть напряжённое кино на один вечер",
        "intro": "Три фильма с закрытой историей: каждый заканчивается в тот же "
                 "вечер, продолжения искать не нужно.",
        "section": "/movies/",
        "indexing": {"open": открыта,
                     "reason": "у каждой работы своё пояснение, страница несёт "
                               "собственную пользу"},
        "items": работы,
    }


def _работа(н: int, идент: str, слаг: str) -> dict:
    return {"order": н, "id": идент, "slug": слаг,
            "url": f"https://proba.invalid/title/{слаг}/",
            "name": f"Проба {н}", "year": 2024,
            "reason": f"причина номер {н}", "checked": "2026-10-26"}


def _стенд(tmp_path, monkeypatch, *, работы_файла, записи, подробности,
           открыта=True, ключ="trillery-na-vecher-2026"):
    с = оснастка.Стенд(tmp_path, site_id="lords-подборки")
    с.записать_каталог(записи)
    с.записать_подробности(подробности)
    с.записать_плеер()
    файл = tmp_path / "config" / "collections.json"
    файл.write_text(json.dumps({
        "schema": "proba.invalid.collections/1", "site": "proba.invalid",
        "site_id": "lords-подборки", "prepared_at": "2026-10-26T00:00:00Z",
        "status": "PREPARED_NOT_RELEASED", "key": "проба-20261026",
        "direction_rule": "подборки по направлению витрины и разделу-владельцу",
        "collections": [_подборка(ключ, работы_файла, открыта=открыта)],
    }, ensure_ascii=False), encoding="utf-8")
    monkeypatch.setenv("LORDS_COLLECTIONS", str(файл))
    модуль = оснастка.загрузить(с, monkeypatch)
    return модуль, оснастка.вид(модуль)


def _три_записи():
    записи = [оснастка.запись(f"proba-{н}", title=f"Проба {н}", kind="Фильм")
              for н in (1, 2, 3)]
    подробности = []
    for н in (1, 2, 3):
        д = оснастка.подробность(f"proba-{н}", type_="movie")
        д["id"] = f"catalog-{н:04d}"
        подробности.append(д)
    return записи, подробности


def test_подборка_объявлена_и_нашлась(tmp_path, monkeypatch):
    записи, подробности = _три_записи()
    работы = [_работа(н, f"catalog-{н:04d}", f"proba-{н}") for н in (1, 2, 3)]
    модуль, _ = _стенд(tmp_path, monkeypatch, работы_файла=работы,
                       записи=записи, подробности=подробности)
    try:
        assert "trillery-na-vecher-2026" in модуль.РУЧНЫЕ_ПОДБОРКИ
    finally:
        оснастка.выгрузить(модуль)


def test_страница_несёт_заголовок_вступление_и_пояснения(tmp_path, monkeypatch):
    записи, подробности = _три_записи()
    работы = [_работа(н, f"catalog-{н:04d}", f"proba-{н}") for н in (1, 2, 3)]
    модуль, вид = _стенд(tmp_path, monkeypatch, работы_файла=работы,
                         записи=записи, подробности=подробности)
    try:
        подборка = модуль.РУЧНЫЕ_ПОДБОРКИ["trillery-na-vecher-2026"]
        состав = модуль.КОЛЛЕКЦИИ.разрешить_ручную(
            подборка, модуль.Снимок.получить(вид.д, вид.п))
        страница = вид.ручная_подборка(подборка, состав)
        assert "<h1>Триллеры на вечер</h1>" in страница
        assert "продолжения искать не нужно" in страница
        for н in (1, 2, 3):
            assert f"причина номер {н}" in страница
        # Порядок пояснений — тот же, что в файле.
        места = [страница.index(f"причина номер {н}") for н in (1, 2, 3)]
        assert места == sorted(места)
    finally:
        оснастка.выгрузить(модуль)


