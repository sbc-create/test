"""REQ-SEO-VISIBILITY-BREADTH: ширина видимости считается в произведениях.

Повод (19.10): вывод «хвост сжался с 133 до 45 путей» опирался на путь как на
единицу. Путь — плохая единица: сериал с десятью сериями даёт десять путей, и
то же сжатие можно получить, потеряв три сериала. Пересчёт в произведения дал
другую картину (84 → 32) и другую цену (571 визит из 14 417, 3.96 %), после
чего собственный утренний вывод пришлось сузить.

Второй повод — возражение «меньше строк в выгрузке» ≠ «меньше видимости»:
выгрузка отдаёт ТОП строк. Поэтому инструмент обязан печатать число строк по
каждому домену файла, и проверка на это есть ниже.

Отрицательные контроли обязательны: инструмент, который на одинаковых срезах
не отвечает «изменений нет», не измеряет ничего.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/search-visibility-breadth.py"
_спец = importlib.util.spec_from_file_location("search_visibility_breadth", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)


def _выгрузка(путь: pathlib.Path, домены: dict, *, измерено=True) -> pathlib.Path:
    """Выгрузка кабинета в её фактической форме: domains — список."""
    спис = []
    for домен, строки in домены.items():
        спис.append({
            "domain": домен,
            "measurements": [{
                "key": "search_landing_pages",
                "measured": измерено,
                "value": [{"dimensions": [{"name": п}], "metrics": [в]}
                          for п, в in строки.items()] if измерено else "не измерено",
            }],
        })
    путь.write_text(json.dumps({"domains": спис}, ensure_ascii=False),
                    encoding="utf-8")
    return путь


# --- единица измерения --------------------------------------------------------

@pytest.mark.parametrize("путь, ожидается", [
    ("/anime/jojo/season/7/episode/4", "jojo"),
    ("/title/skotty/", "skotty"),
    ("/anime/jojo", "jojo"),
    ("/", ""),
    ("/catalog", ""),
    ("/catalog/ongoing", ""),
    ("/anime/", ""),
    ("/anime", ""),
    ("", ""),
])
def test_произведение_узнаётся_по_адресу(путь, ожидается):
    assert ИНСТР.тайтл(путь) == ожидается


def test_серии_одного_сериала_это_одно_произведение():
    """Ровно та ошибка, из-за которой единицу пришлось сменить."""
    ш = ИНСТР.ширина({f"/anime/jojo/season/7/episode/{н}": 100 for н in range(1, 11)})
    assert ш["путей"] == 10
    assert ш["произведений"] == 1
    assert ш["доля_крупнейшего"] == pytest.approx(100.0)


def test_главная_в_ширину_не_входит_но_в_визиты_входит():
    ш = ИНСТР.ширина({"/": 3708, "/anime/jojo/season/7/episode/4": 2843})
    assert ш["произведений"] == 1
    assert ш["визитов"] == 6551
    assert ш["доля_крупнейшего"] == pytest.approx(2843 / 6551 * 100)


def test_порог_десяти_входов():
    ш = ИНСТР.ширина({"/anime/a": 10, "/anime/b": 9, "/anime/c": 11})
    assert ш["произведений"] == 3 and ш["с_десятью"] == 2


def test_пустой_срез_не_делит_на_ноль():
    ш = ИНСТР.ширина({})
    assert ш["визитов"] == 0 and ш["доля_крупнейшего"] == 0.0


# --- сравнение ----------------------------------------------------------------

def test_цена_ушедших_в_процентах_визитов():
    было = {"/anime/a": 9000, "/anime/b": 500, "/anime/c": 500}
    стало = {"/anime/a": 6000}
    с = ИНСТР.сравнить(было, стало)
    assert set(с["ушли"]) == {"b", "c"}
    assert с["цена_ушедших_%"] == pytest.approx(10.0)
    assert с["было"]["произведений"] == 3 and с["стало"]["произведений"] == 1


def test_одинаковые_срезы_дают_отсутствие_изменений():
    """Отрицательный контроль."""
    срез = {"/anime/a": 100, "/": 50}
    с = ИНСТР.сравнить(срез, dict(срез))
    assert с["ушли"] == {} and с["пришли"] == {}
    assert с["цена_ушедших_%"] == 0.0


def test_рост_не_объявляется_потерей():
    с = ИНСТР.сравнить({"/anime/a": 10}, {"/anime/a": 20, "/anime/b": 5})
    assert с["ушли"] == {} and set(с["пришли"]) == {"b"}


# --- «не измерено» ------------------------------------------------------------

def test_домена_в_выгрузке_нет_не_измерено(tmp_path):
    ф = _выгрузка(tmp_path / "в.json", {"yummyani.site": {"/anime/a": 5}})
    assert ИНСТР.срез(ф, "нет-такого.test") is None


def test_срез_не_измерен_это_не_ноль(tmp_path):
    ф = _выгрузка(tmp_path / "в.json", {"x.test": {"/anime/a": 5}}, измерено=False)
    assert ИНСТР.срез(ф, "x.test") is None


def test_битый_файл_не_измерено(tmp_path):
    п = tmp_path / "битый.json"
    п.write_text("{не json", encoding="utf-8")
    assert ИНСТР.срез(п, "x.test") is None


def test_файла_нет_не_измерено(tmp_path):
    assert ИНСТР.срез(tmp_path / "нет.json", "x.test") is None


def test_код_2_когда_не_измерено_ничего(tmp_path, capsys):
    ф = _выгрузка(tmp_path / "в.json", {"x.test": {"/anime/a": 5}})
    код = ИНСТР.main(["--before", str(ф), "--after", str(ф),
                      "--domain", "нет-такого.test"])
    assert код == 2
    assert "НЕ ИЗМЕРЕНО" in capsys.readouterr().out


# --- предел выгрузки ----------------------------------------------------------

def test_строки_по_доменам_печатаются(tmp_path, capsys):
    """Без этих чисел «стало меньше строк» нельзя отличить от предела ТОПа."""
    ф = _выгрузка(tmp_path / "в.json", {
        "a.test": {f"/anime/t{н}": 1 for н in range(5)},
        "b.test": {f"/anime/t{н}": 1 for н in range(5)},
    })
    ИНСТР.main(["--before", str(ф), "--after", str(ф), "--domain", "a.test"])
    вывод = capsys.readouterr().out
    assert "строк по домéнам" in вывод
    assert "проверь предел выгрузки" in вывод, (
        "два домена с одинаковым максимумом — повод предупредить читателя")


def test_один_максимум_предупреждения_не_даёт(tmp_path, capsys):
    """Отрицательный контроль к предупреждению о пределе."""
    ф = _выгрузка(tmp_path / "в.json", {
        "a.test": {f"/anime/t{н}": 1 for н in range(7)},
        "b.test": {f"/anime/t{н}": 1 for н in range(3)},
    })
    ИНСТР.main(["--before", str(ф), "--after", str(ф), "--domain", "a.test"])
    assert "проверь предел выгрузки" not in capsys.readouterr().out


