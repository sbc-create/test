def test_живые_выгрузки_читаются(capsys):
    """На этом хосте обе выгрузки есть; измеряется хотя бы один домен."""
    код = ИНСТР.main([])
    вывод = capsys.readouterr().out
    assert код in (0, 1), вывод
    assert "yummyani.site" in вывод
