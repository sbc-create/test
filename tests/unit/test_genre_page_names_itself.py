"""REQ-CELL-GENRE-LANDING: страница жанра называет жанр и канонизируется на себя.

Измерено 2026-10-18 на `lordserial.su` и `lordfilm.group`:

    /genre/boevik/   title «Каталог — lordserial.su»
                     h1 «Каталог»
                     canonical https://lordserial.su/catalog/
                     description «…11830 записей»  ← отбор РАБОТАЕТ
    /catalog/        title «Каталог — lordserial.su», 66 159 записей

То есть страница отдавала отобранный каталог (11 830 из 66 159), но объявляла
себя копией полного каталога и нигде не называла жанр. С главной на такие
страницы ведут 12 ссылок, из `/genres/` — 8.

Это было расхождение кода с его же объявленным замыслом: в маршруте стоит
комментарий «Канон жанра для Lords — path /genre/<code>/», а четвёртый довод
`_отдать_список` использовался ТОЛЬКО для страницы 404 — настоящий путь до
сборки страницы не доходил.

Соседние семейства так себя не ведут: `animedia.icu` и `zonafilm12.site`
отдают свой title, свой h1 («Боевик аниме», «Детектив аниме») и canonical на
себя. Образец взят у них.
"""
from __future__ import annotations

from pathlib import Path

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _список_лордс() -> str:
    """Тело `список` у вида Lords — того, что обслуживает `/genre/<code>/`."""
    начало = ТЕКСТ.index("class ВидЛордс(Вид):")
    кусок = ТЕКСТ[начало:ТЕКСТ.index("class ВидЗона(Вид):", начало)]
    и = кусок.index("    def список(self, разд: str, зпр: dict) -> str:")
    return кусок[и:кусок.index("\n    def ", и + 10)]


def test_имя_жанра_берётся_из_индекса_а_не_придумывается():
    тело = _список_лордс()
    assert 'self.индекс.get("genre_names")' in тело, (
        "имя жанра должно приходить из того же индекса, что наполняет фильтр")
    # Отрицательный контроль: нет имени — страница остаётся прежней.
    assert "if жанр_имя:" in тело, (
        "без имени жанра заголовок обязан остаться прежним, а не собираться "
        "из кода жанра")


def test_заголовок_страницы_жанра_называет_жанр():
    тело = _список_лордс()
    assert "титул = жанр_имя" in тело


def test_канон_страницы_жанра_путь_жанра():
    тело = _список_лордс()
    assert 'f"/genre/{жанр_код}/"' in тело
    assert "канон_пути" in тело


def test_комбинации_фильтров_не_склеиваются_с_жанром():
    """Главная осторожность правки.

    `?genre=X&year=Y&page=3` — другая страница, и объявлять её каноном жанра
    значило бы склеить разные страницы в одну. Поэтому условий три: жанр
    единственный выбранный фильтр, имя жанра известно, страница первая.
    """
    тело = _список_лордс()
    assert "прочие_фильтры" in тело
    assert 'к not in ("genre", "page")' in тело
    assert "not прочие_фильтры and стр == 1" in тело


def test_активный_пункт_меню_остался_каталогом():
    """Отрицательный контроль: канон сменился, а навигация — нет.

    Если бы `актив` поехал за каноном, в меню перестал бы подсвечиваться
    каталог, и правка канона потащила бы за собой правку вида.
    """
    тело = _список_лордс()
    assert 'актив=разд + "/"' in тело


def test_маршрут_жанра_по_прежнему_отдаёт_отбор_а_не_переход():
    """Для Lords путь жанра — своя страница, а не redirect на фильтр.

    У семейств Zona и Animedia наоборот: `/genre/<code>/` переводит на
    `/catalog/?genre=<code>`. Эта разница сознательная, и ломать её правкой
    канона нельзя.
    """
    маршрут = ТЕКСТ[ТЕКСТ.index("жанр = self.МАРШРУТ_ЖАНРА.match(путь)"):]
    маршрут = маршрут[:маршрут.index("совпало = self.МАРШРУТ_ТАЙТЛА")]
    assert 'if СЕМЕЙСТВО == "lords":' in маршрут
    assert "_отдать_список(в, \"/catalog\", зпр, путь)" in маршрут
    assert 'self._переход(f"/catalog/?genre={код}")' in маршрут


def test_имя_жанра_начинается_с_заглавной():
    """Приёмка выпуска показала «боевик — lordserial.su» в title и h1.

    В индексе имена жанров лежат строчными. Регистр первой буквы в начале
    заголовка — типографика, а не правка данных: само имя не меняется ни на
    одну букву, и «боевые искусства» станет «Боевые искусства», а не
    придуманным сокращением.
    """
    тело = _список_лордс()
    assert "жанр_имя[:1].upper() + жанр_имя[1:]" in тело
    # Отрицательный контроль: имя не должно переписываться целиком.
    assert ".title()" not in тело, (
        "`.title()` сломал бы многословные имена: «Боевые Искусства»")
