"""Поведение плана обновления исполнителя.

План отвечает на один вопрос: что именно изменится в корневой копии и от какой
версии. Каждая проверка здесь ломает одно его утверждение и требует, чтобы план
это заметил. Проверка, которая не умеет падать, доверия не несёт (D205).

Стенд одноразовый: временное «дерево службы» под git и временная «установленная
копия». Живая машина не задействована — иначе тест зависел бы от того, что в эту
минуту делает служба.
"""
from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "host" / "executor-update-plan.py"
УСТАНОВЩИК = КОРЕНЬ / "automation" / "host" / "install-cell-executor.sh"


def _модуль():
    спец = importlib.util.spec_from_file_location("executor_update_plan",
                                                  СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


план = _модуль()


def _git(корень: Path, *арг: str) -> None:
    subprocess.run(["git", "-C", str(корень), *арг], check=True,
                   capture_output=True, text=True, timeout=120)


def _стенд(tmp_path: Path) -> tuple[Path, Path]:
    """Дерево службы под git плюс установленная копия, различающиеся одним файлом."""
    дерево = tmp_path / "service"
    (дерево / "factory" / "cell").mkdir(parents=True)
    (дерево / "config").mkdir()
    (дерево / "schemas").mkdir()
    (дерево / "factory" / "cell" / "executor.py").write_text("версия 2\n",
                                                            encoding="utf-8")
    (дерево / "config" / "site.json").write_text("{}\n", encoding="utf-8")
    (дерево / "schemas" / "новая.schema.json").write_text("{}\n",
                                                          encoding="utf-8")
    _git(дерево, "init", "-q")
    _git(дерево, "config", "user.email", "т@т")
    _git(дерево, "config", "user.name", "т")
    _git(дерево, "add", "-A")
    _git(дерево, "commit", "-q", "-m", "основа")

    установлено = tmp_path / "installed"
    (установлено / "factory" / "cell").mkdir(parents=True)
    (установлено / "config").mkdir()
    (установлено / "factory" / "cell" / "executor.py").write_text(
        "версия 1\n", encoding="utf-8")
    (установлено / "config" / "site.json").write_text("{}\n", encoding="utf-8")
    return дерево, установлено


def _голова(дерево: Path) -> str:
    return subprocess.run(["git", "-C", str(дерево), "rev-parse",
                           "--short=12", "HEAD"], capture_output=True,
                          text=True, timeout=120).stdout.strip()


def _прогон(дерево: Path, установлено: Path, ожидать: str = "") -> tuple[int, str]:
    арг = ["--service", str(дерево), "--installed", str(установлено)]
    if ожидать:
        арг += ["--expect", ожидать]
    готово = subprocess.run([sys.executable, str(СЦЕНАРИЙ), *арг],
                            capture_output=True, text=True, timeout=300)
    return готово.returncode, готово.stdout + готово.stderr


def test_перечень_каталогов_равен_строкам_установщика():
    """Перечень по памяти уже один раз завысил состав на 7 файлов.

    Он включал `scripts`, которого установщик не копирует вовсе. Поэтому
    перечень держится не комментарием, а равенством фактическим строкам
    копирования: разойдётся снова — тест упадёт здесь, а не на машине.
    """
    фактические = план.каталоги_установщика(УСТАНОВЩИК)
    assert фактические, "в установщике не нашлось ни одной строки cp -a $SRC_ROOT/..."
    assert план.КАТАЛОГИ == фактические, (
        f"план копирует {план.КАТАЛОГИ}, установщик — {фактические}")


def test_состав_называет_обновляемое_и_добавляемое_отдельно(tmp_path):
    дерево, установлено = _стенд(tmp_path)
    код, вывод = _прогон(дерево, установлено)
    assert код == 0, вывод
    assert "будет обновлено файлов: 1" in вывод, вывод
    assert "factory/cell/executor.py" in вывод
    # Новый файл — это не обновление: без отдельного счёта «добавится схема»
    # выглядело бы как «ничего не меняется».
    assert "будет добавлено файлов: 1" in вывод, вывод
    assert "schemas/новая.schema.json" in вывод


def test_чужой_коммит_останавливает_установку(tmp_path):
    дерево, установлено = _стенд(tmp_path)
    код, вывод = _прогон(дерево, установлено, ожидать="0000000beef0")
    assert код == 1, вывод
    assert "ОТКАЗ" in вывод
    assert "не подтверждён" in вывод or "НОВЫЙ" in вывод


def test_свой_коммит_разрешает_установку(tmp_path):
    дерево, установлено = _стенд(tmp_path)
    код, вывод = _прогон(дерево, установлено, ожидать=_голова(дерево))
    assert код == 0, вывод
    assert "версия совпадает с закреплённой" in вывод


def test_незакоммиченная_правка_в_составе_останавливает(tmp_path):
    """Коммит тот же, а содержимое уже другое — пин по коммиту тут лжёт."""
    дерево, установлено = _стенд(tmp_path)
    голова = _голова(дерево)
    (дерево / "factory" / "cell" / "executor.py").write_text(
        "версия 3, никем не сохранённая\n", encoding="utf-8")
    код, вывод = _прогон(дерево, установлено, ожидать=голова)
    assert код == 1, вывод
    assert "незакоммиченные правки" in вывод
    assert "НЕ описывает" in вывод


def test_правка_вне_состава_установку_не_останавливает(tmp_path):
    """Правка в `docs/` в корневую копию не попадает — повод для отказа ложный."""
    дерево, установлено = _стенд(tmp_path)
    голова = _голова(дерево)
    (дерево / "docs").mkdir()
    (дерево / "docs" / "заметка.md").write_text("черновик\n", encoding="utf-8")
    код, вывод = _прогон(дерево, установлено, ожидать=голова)
    assert код == 0, вывод
    assert "версия совпадает с закреплённой" in вывод


@pytest.mark.skipif(os.geteuid() == 0,
                    reason="под root права 000 не мешают чтению")
def test_непрочитанный_файл_назван_пределом_а_не_совпадением(tmp_path):
    """Самый опасный исход: файл не сверён, а отчёт выглядит как «совпадает»."""
    дерево, установлено = _стенд(tmp_path)
    цель = установлено / "config" / "site.json"
    цель.chmod(0o000)
    try:
        код, вывод = _прогон(дерево, установлено)
    finally:
        цель.chmod(0o644)
    assert код == 0, вывод
    assert "не прочитаны этой учётной записью" in вывод, вывод
    assert "предел измерения" in вывод
    assert "config/site.json" in вывод
    # И этот файл не должен попасть в «будет обновлено»: про него ничего не
    # известно, а не «известно, что изменится».
    обновляемые = вывод.split("будет обновлено файлов:")[1]
    обновляемые = обновляемые.split("не прочитаны")[0]
    assert "config/site.json" not in обновляемые, обновляемые


def test_кеш_питона_в_состав_не_попадает(tmp_path):
    дерево, установлено = _стенд(tmp_path)
    кеш = дерево / "factory" / "cell" / "__pycache__"
    кеш.mkdir()
    (кеш / "executor.cpython-310.pyc").write_bytes(b"\x00\x01")
    голова = _голова(дерево)
    код, вывод = _прогон(дерево, установлено, ожидать=голова)
    # Кеш — грязь в копируемом каталоге, но исходников он не меняет: отказывать
    # по нему значит приучить владельца обходить проверку.
    assert код == 0, вывод
    состав = вывод.split("сверено файлов:")[1]
    assert "__pycache__" not in состав, состав


def test_немой_git_не_выглядит_подтверждённой_версией(tmp_path):
    """Отказ git и «правок нет» склеивать нельзя — иначе пин молча пропускается.

    Исход опасен тем, что срабатывал бы именно у владельца: под sudo в рабочем
    каталоге другой учётной записи git отказывает про владельца каталога, а у
    автора плана проверка при этом проходила.
    """
    _, установлено = _стенд(tmp_path)
    не_репозиторий = tmp_path / "просто-каталог"
    (не_репозиторий / "factory").mkdir(parents=True)
    (не_репозиторий / "factory" / "executor.py").write_text("x\n",
                                                            encoding="utf-8")
    код, вывод = _прогон(не_репозиторий, установлено, ожидать="d2f28e99cbdb")
    assert код == 1, вывод
    assert "git" in вывод and "ОТКАЗ" in вывод
    assert "не зная версии" in вывод


def test_без_закрепления_немой_git_работу_не_останавливает(tmp_path):
    """Показать состав можно и без git: пин требуется только когда он назван."""
    _, установлено = _стенд(tmp_path)
    не_репозиторий = tmp_path / "просто-каталог-2"
    (не_репозиторий / "factory").mkdir(parents=True)
    (не_репозиторий / "factory" / "executor.py").write_text("x\n",
                                                            encoding="utf-8")
    код, вывод = _прогон(не_репозиторий, установлено)
    assert код == 0, вывод
    assert "git отказал" in вывод
