"""REQ-TENANT-ISOLATION: список проверяемых маршрутов берётся из договора.

Список маршрутов, написанный руками, стареет молча. Слияние ветки связей SEO
добавило `/api/v1/seo-bindings/{siteId}` — маршрут с витриной в адресе, которого
в проверке тенанта не было. Никакой тест этого не заметил: перечень путей в
`TestПривязанныйНеВидитСоседа` перечисляет то, о чём вспомнили.

Здесь перечень берётся из самого договора — таблицы OpenAPI. Новый маршрут с
`{siteId}` попадает под проверку в тот же момент, когда объявляется, а не тогда,
когда о нём вспомнят.
"""

from __future__ import annotations

import pytest

from factory.site_engine.api import openapi

from .test_tenant_isolation import H_МЕСТНЫЙ, ЧУЖОЙ, api, sandbox  # noqa: F401

#: Маршруты, которым витрина в адресе не принадлежит: она там значит другое.
#: Каждое исключение названо поимённо — молчаливое исключение и есть дыра.
НЕ_О_ВИТРИНЕ: dict[str, str] = {}


def _маршруты_с_витриной() -> list[tuple[str, str]]:
    найденные = []
    for путь, о in openapi.ЗАПИСЬ.items():
        if "{siteId}" not in путь or путь in НЕ_О_ВИТРИНЕ:
            continue
        if str(о.get("method", "")).lower() != "get":
            # Запись проверяется отдельно: у неё, кроме адреса, есть тело.
            continue
        найденные.append((путь, о.get("scope") or "read"))
    return sorted(найденные)


МАРШРУТЫ = _маршруты_с_витриной()


def test_договор_вообще_называет_такие_маршруты():
    assert МАРШРУТЫ, "в договоре нет ни одного читающего маршрута с витриной в адресе"


@pytest.mark.parametrize("путь,область", МАРШРУТЫ)
def test_каждый_маршрут_с_витриной_отклоняет_чужую(api, путь, область):  # noqa: F811
    адрес = путь.replace("{siteId}", ЧУЖОЙ)
    ответ = api.handle("GET", адрес, headers=H_МЕСТНЫЙ, body=None)
    assert ответ.status == 403, (
        f"{адрес}: привязанный обращающийся получил {ответ.status} вместо 403. "
        "Маршрут объявлен в договоре с витриной в адресе, но проверкой тенанта "
        "не охвачен"
    )
    assert ((ответ.body or {}).get("error") or {}).get("code") == "cross_tenant"
