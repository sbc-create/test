"""Поиск сети за две недели: что здесь нельзя смешивать.

Три ошибки, против которых написаны эти проверки, — не выдуманные:

* **поиск из общего разреза.** В первой редакции расчёта 22.10 столбец
  «поиск» брался из `по_источнику` `traffic-segments.py`, а он считается по
  ВСЕМ строкам профиля, включая роботов и автоматизацию. У `yummyani.site`
  это дало бы 16 220 → 11 266 вместо очищенных 16 194 → 11 257, а у витрины
  с большой долей headless разница была бы кратной.
* **делитель среднесуточного.** Метрика не отдаёт нулевых строк, поэтому у
  домена с тремя пустыми сутками деление на «сутки со строками» завышает
  среднее почти вдвое. Делитель — календарная длина окна.
* **прирост от нуля.** `0 → 30` процентами не выражается, и выдавать это за
  рост нельзя.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "network-search-two-weeks.py"

спец = importlib.util.spec_from_file_location("network_search_two_weeks", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)

ПОИСК = "Search engine traffic"
ПРЯМОЙ = "Direct traffic"


def _стр(дата, визиты, *, источник=ПОИСК, браузер="Chrome", робот="People"):
    return {"dimensions": [{"name": дата}, {"name": источник},
                           {"name": "desktop"}, {"name": браузер},
                           {"name": робот}],
            "metrics": [визиты, 0.0, 1.0, 10.0]}


def _выгрузка(строки, домен="d.test"):
    return {"collected_at": "2026-10-19T05:11:55Z", "domains": [{
        "domain": домен,
        "measurements": [{"key": "daily_traffic_profile", "measured": True,
                          "value": строки}]}]}


# --- признак поиска --------------------------------------------------------

def test_поиск_узнаётся_по_названию_источника():
    assert модуль.поиск("Search engine traffic")
    assert модуль.поиск("переход из поисковой системы")
    assert not модуль.поиск("Direct traffic")
    assert not модуль.поиск("Internal traffic")


# --- очищенный срез --------------------------------------------------------

def test_headless_не_попадает_в_очищенный_поиск():
    строки = модуль.ТС.строки([
        _стр("2026-10-12", 100.0, браузер="HeadlessChrome"),
        _стр("2026-10-12", 7.0),
    ])
    весь = модуль.числа(строки, "2026-10-12", "2026-10-18")
    assert весь["поиск_весь"] == 107.0
    assert весь["поиск_очищенный"] == 7.0


def test_робот_метрики_не_попадает_в_очищенный():
    строки = модуль.ТС.строки([
        _стр("2026-10-12", 50.0, робот="Robots"),
        _стр("2026-10-12", 5.0),
    ])
    итог = модуль.числа(строки, "2026-10-12", "2026-10-18")
    assert итог["визиты_весь"] == 55.0
    assert итог["визиты_без_роботов"] == 5.0
    assert итог["визиты_очищенные"] == 5.0


def test_прямые_визиты_в_поиск_не_идут():
    строки = модуль.ТС.строки([
        _стр("2026-10-12", 9.0, источник=ПРЯМОЙ),
        _стр("2026-10-13", 4.0),
    ])
    итог = модуль.числа(строки, "2026-10-12", "2026-10-18")
    assert итог["визиты_очищенные"] == 13.0
    assert итог["поиск_очищенный"] == 4.0


def test_сутки_вне_окна_не_считаются():
    строки = модуль.ТС.строки([
        _стр("2026-10-11", 100.0),
        _стр("2026-10-12", 1.0),
    ])
    н1 = модуль.числа(строки, "2026-10-05", "2026-10-11")
    н2 = модуль.числа(строки, "2026-10-12", "2026-10-18")
    assert н1["поиск_очищенный"] == 100.0
    assert н2["поиск_очищенный"] == 1.0


# --- делитель и прирост ----------------------------------------------------

def test_делитель_это_календарная_длина_окна():
    assert модуль.длина_окна("2026-10-12", "2026-10-18") == 7
    assert модуль.длина_окна("2026-10-12", "2026-10-12") == 1


def test_среднесуточное_делится_на_семь_а_не_на_сутки_со_строками():
    # Двое суток со строками из семи: деление на 2 завысило бы среднее в 3.5 раза.
    выгрузка = _выгрузка([_стр("2026-10-12", 70.0), _стр("2026-10-13", 70.0)])
    строка = модуль.разобрать(выгрузка, ("2026-10-05", "2026-10-11"),
                              ("2026-10-12", "2026-10-18"))[0]
    assert строка["делитель_суток"] == 7
    assert строка["суток_со_строками_н2"] == 2
    assert строка["очищенного_поиска_в_сутки"] == pytest.approx(20.0)


def test_прирост_от_нуля_не_выражается_процентами():
    assert модуль.прирост(0.0, 30.0) is None
    assert модуль.прирост(10.0, 20.0) == pytest.approx(100.0)
    assert модуль.прирост(20.0, 10.0) == pytest.approx(-50.0)


# --- неизмеренное ----------------------------------------------------------

def test_домен_без_разреза_не_становится_нулём():
    выгрузка = {"domains": [{"domain": "d.test", "measurements": [
        {"key": "visits", "measured": True, "value": 5}]}]}
    строка = модуль.разобрать(выгрузка, ("2026-10-05", "2026-10-11"),
                              ("2026-10-12", "2026-10-18"))[0]
    assert строка["измерено"] is False
    assert "daily_traffic_profile" in строка["почему"]


def test_неизмеренный_разрез_называет_причину_кабинета():
    выгрузка = {"domains": [{"domain": "d.test", "measurements": [
        {"key": "daily_traffic_profile", "measured": False,
         "reason": "счётчик Метрики не создан"}]}]}
    строка = модуль.разобрать(выгрузка, ("2026-10-05", "2026-10-11"),
                              ("2026-10-12", "2026-10-18"))[0]
    assert строка["измерено"] is False
    assert строка["почему"] == "счётчик Метрики не создан"


def test_неизмеренные_домены_не_входят_в_сумму_сети():
    строки = [
        {"домен": "a", "измерено": True,
         "неделя1": {"визиты_очищенные": 10.0, "поиск_очищенный": 8.0},
         "неделя2": {"визиты_очищенные": 20.0, "поиск_очищенный": 16.0}},
        {"домен": "b", "измерено": False, "почему": "счётчика нет"},
    ]
    сеть = модуль.свод(строки)
    assert сеть["доменов"] == 1
    assert сеть["поиск_н1"] == 8.0
    assert сеть["прирост_поиска"] == pytest.approx(100.0)


def test_исключение_домена_из_суммы_работает():
    строки = [
        {"домен": "a", "измерено": True,
         "неделя1": {"визиты_очищенные": 10.0, "поиск_очищенный": 8.0},
         "неделя2": {"визиты_очищенные": 20.0, "поиск_очищенный": 16.0}},
        {"домен": "большой", "измерено": True,
         "неделя1": {"визиты_очищенные": 1000.0, "поиск_очищенный": 900.0},
         "неделя2": {"визиты_очищенные": 500.0, "поиск_очищенный": 400.0}},
    ]
    assert модуль.свод(строки)["прирост_поиска"] < 0
    без = модуль.свод(строки, кроме="большой")
    assert без["доменов"] == 1
    assert без["прирост_поиска"] == pytest.approx(100.0)


def test_пустой_набор_доменов_не_выдаётся_за_ноль():
    assert модуль.свод([])["доменов"] == 0
