"""Вердикт load-stats не зависит от того, когда тикнули настенные часы.

ПОВОД, измеренный 27.10: три прогона `checks/run.sh` подряд при НЕИЗМЕННОМ
коде проверки дали PASS, FAIL и снова PASS. Текст провала — «окно:
window_minutes 60, минут 2 вместо 60/1».

ПРИЧИНА, установленная чтением рантайма, а не предположенная. Корзины сводки
ключуются по настенным минутам: `minute` считается из epoch-минут. Проверка
требовала РОВНО одну корзину, поэтому события, легшие по разные стороны смены
минуты, давали две и провал. Поначалу я записал причиной «время работы
стенда» — это была догадка, и она неверна.

ПОЧЕМУ ТЕСТ НА ФУНКЦИИ, А НЕ НА ЖИВОМ ПРОГОНЕ. Случай «события по разные
стороны минуты» в живом прогоне по заказу не воспроизвести: он случается
примерно раз в несколько десятков запусков. Прогон, прошедший один раз,
ничего не доказывает — прежняя проверка тоже проходила.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПРОВЕРКА = (КОРЕНЬ / "var" / "site-repos" / "animedia-icu" / "checks"
            / "load_stats.py")


@pytest.fixture(scope="module")
def счётчики():
    if not ПРОВЕРКА.is_file():
        pytest.skip("проверки витрины нет в дереве")
    спец = importlib.util.spec_from_file_location("load_stats_mod", ПРОВЕРКА)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль.счётчики_окна


БОТ = ("yandexbot", "title_episode", "2xx")
БРАУЗЕР = ("browser", "catalog", "503")


def _корзина(минута: str, пары):
    return {"minute": минута,
            "by_key": [{"client": к, "path_group": г, "status": о, "count": n}
                       for (к, г, о), n in пары]}


def test_одна_минута(счётчики):
    итог = счётчики([_корзина("2026-10-27T21:40Z", [(БОТ, 1), (БРАУЗЕР, 1)])])
    assert итог[БОТ] == 1 and итог[БРАУЗЕР] == 1


def test_события_по_разные_стороны_минуты(счётчики):
    """Тот самый случай, на котором прежнее условие валилось: две корзины.

    Событий столько же, просто часы тикнули между ними. Вердикт обязан быть
    тем же — иначе проверка говорит о времени суток, а не о витрине.
    """
    итог = счётчики([_корзина("2026-10-27T21:40Z", [(БОТ, 1)]),
                     _корзина("2026-10-27T21:41Z", [(БРАУЗЕР, 1)])])
    assert итог[БОТ] == 1 and итог[БРАУЗЕР] == 1


def test_много_минут_не_меняют_итога(счётчики):
    """Окно в час: корзин может быть и шестьдесят."""
    корзины = [_корзина(f"2026-10-27T{21}:{м:02d}Z", []) for м in range(10)]
    корзины.append(_корзина("2026-10-27T21:59Z", [(БОТ, 1), (БРАУЗЕР, 1)]))
    итог = счётчики(корзины)
    assert итог[БОТ] == 1 and итог[БРАУЗЕР] == 1


def test_пропавшее_событие_видно(счётчики):
    """Условие обязано остаться способным провалиться: иначе смягчение
    превратилось бы в отключение."""
    итог = счётчики([_корзина("2026-10-27T21:40Z", [(БОТ, 1)])])
    assert итог.get(БРАУЗЕР) is None


def test_лишнее_событие_видно(счётчики):
    """Два учёта одного события — тоже дефект, и он не должен раствориться
    в суммировании."""
    итог = счётчики([_корзина("2026-10-27T21:40Z", [(БОТ, 1)]),
                     _корзина("2026-10-27T21:41Z", [(БОТ, 1)])])
    assert итог[БОТ] == 2


def test_пустое_окно(счётчики):
    assert счётчики([]) == {}
    assert счётчики(None) == {}
