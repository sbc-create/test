"""Витрина не показывает оценку по десятку голосов даже из старого снимка.

Порог стоит в сборщике недельного снимка, но снимок пересобирается раз в
неделю расписанием владельца. Без проверки ПРИ ЧТЕНИИ выложенный блок до
следующей пересборки продолжал бы показывать 8.5 по четырнадцати оценкам —
исправление осталось бы на бумаге.
"""
from __future__ import annotations

import ast
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМЫ = (
    КОРЕНЬ / "var" / "site-repos" / "zonafilm-space" / "src" / "lords-frontend.py",
    КОРЕНЬ / "var" / "site-repos" / "zonafilm12-site" / "src" / "lords-frontend.py",
)


def _механизм(путь: pathlib.Path) -> dict:
    """Функции полки из рантайма — исполнением нужных кусков, без запуска витрины."""
    текст = путь.read_text(encoding="utf-8")
    дерево = ast.parse(текст)
    строки = текст.splitlines()
    куски = []
    for узел in дерево.body:
        имя = getattr(узел, "name", None)
        цели = [ц.id for ц in getattr(узел, "targets", [])
                if isinstance(ц, ast.Name)]
        if имя in ("_из_weekly_полки", "_оценок_у_записи") or \
                "ПОЛКА_МИН_ОЦЕНОК" in цели:
            куски.append("\n".join(строки[узел.lineno - 1:узел.end_lineno]))
    область = {"os": __import__("os"), "__name__": "полка"}
    exec(compile("\n\n".join(куски), str(путь), "exec"), область)  # noqa: S102
    assert "_из_weekly_полки" in область, путь
    return область


class Данные:
    """Снимок каталога: у него НЕТ поля подробностей — они лежат отдельно.

    Прежняя подделка данных имела такое поле, и проверка не поймала, что
    фильтр молчит: на живой главной остались 8.5 при четырнадцати оценках.
    """

    def __init__(self, записи):
        self.items = записи


class Подробности:
    def __init__(self, записи):
        self.записи = записи


@pytest.fixture(params=РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def м(request):
    return _механизм(request.param)


def _снимок(слаги):
    return {"shelves": {"pop-films": list(слаги)}, "reserves": {}}


def test_мало_оценок_не_показывается(м):
    записи = [{"slug": "malo", "kind": "Фильм"}, {"slug": "mnogo", "kind": "Фильм"}]
    подробности = {
        "malo": {"ratings_by_source": {"imdb": {"votes": 14}}},
        "mnogo": {"ratings_by_source": {"imdb": {"votes": 120_000}}},
    }
    итог = м["_из_weekly_полки"](Данные(записи), _снимок(["malo", "mnogo"]),
                                 "pop-films", подробности=Подробности(подробности))
    assert [з["slug"] for з in итог] == ["mnogo"], итог


def test_без_числа_оценок_не_показывается(м):
    записи = [{"slug": "bez", "kind": "Фильм"}]
    подробности = {"bez": {"ratings_by_source": {}}}
    итог = м["_из_weekly_полки"](Данные(записи), _снимок(["bez"]), "pop-films",
                                 подробности=Подробности(подробности))
    assert итог == [], итог


def test_без_подробностей_полка_не_обрезается(м):
    """Нет подробностей — проверить нечем, и витрина не делает вид, что
    проверила: полка остаётся как в снимке."""
    записи = [{"slug": "x", "kind": "Фильм"}]
    итог = м["_из_weekly_полки"](Данные(записи), _снимок(["x"]), "pop-films",
                                 подробности=Подробности({}))
    assert [з["slug"] for з in итог] == ["x"], итог


def test_порог_общий_со_сборщиком(м):
    assert м["ПОЛКА_МИН_ОЦЕНОК"] >= 1000


def test_почти_пустая_вкладка_не_показывается():
    """После порога в полке может остаться одна-две работы. Блок из двух
    карточек под заголовком выглядит сломанным, а добивать его случайными
    карточками запрещено — значит остаётся не показывать."""
    for путь in РАНТАЙМЫ:
        т = путь.read_text(encoding="utf-8")
        assert "ПОЛКА_МИНИМУМ = 4" in т, путь
        assert "if len(т[2] or ()) >= self.ПОЛКА_МИНИМУМ" in т, путь


def test_ширины_обложек_прогреваются_до_первого_посетителя():
    """Ширина узнаётся лениво: без прогрева первый посетитель после выпуска
    получает прежний srcset, и честным он станет только для следующих."""
    for путь in РАНТАЙМЫ:
        т = путь.read_text(encoding="utf-8")
        assert "def прогреть_ширины_обложек" in т, путь
        assert 'name="poster-widths"' in т, путь
        # Прогрев идёт фоном и не задерживает отдачу страниц.
        assert "daemon=True" in т.split("poster-widths")[1][:200], путь


def test_главная_передаёт_подробности_в_полку():
    """Фильтр не может сработать, если подробности не дошли: именно так он и
    молчал 27.10 — брал их у снимка каталога, где их нет."""
    for путь in РАНТАЙМЫ:
        т = путь.read_text(encoding="utf-8")
        assert т.count("подробности=self.п") >= 3, (путь, т.count("подробности=self.п"))
        # Прежнее чтение подробностей у снимка каталога не должно вернуться.
        # Упоминание в комментарии законно — ищем именно вызов.
        код = "\n".join(с for с in т.splitlines() if not с.lstrip().startswith("#"))
        assert 'getattr(данные, "подробности"' not in код, путь
