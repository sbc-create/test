def test_код_3_когда_дубли_есть(monkeypatch, capsys):
    страницы = {
        "/": _главная(["a", "b"]),
        "/collection/a": _страница([f"/title/t{n}/" for n in range(10)], h1="A"),
        "/collection/b": _страница([f"/title/t{n}/" for n in range(9)]
                                   + ["/title/z/"], h1="Б"),
    }
    monkeypatch.setattr(ИНСТР, "добыть", _загрузчик(страницы))
    assert ИНСТР.main(["x.site"]) == 3
    вывод = capsys.readouterr().out
    assert "ПОЧТИ ОДНО И ТО ЖЕ" in вывод
    assert "robots index, follow" in вывод


def test_код_0_когда_дублей_нет(monkeypatch, capsys):
    страницы = {
        "/": _главная(["a", "b"]),
        "/collection/a": _страница([f"/title/t{n}/" for n in range(10)], h1="A"),
        "/collection/b": _страница([f"/title/u{n}/" for n in range(10)], h1="Б"),
    }
    monkeypatch.setattr(ИНСТР, "добыть", _загрузчик(страницы))
    assert ИНСТР.main(["x.site"]) == 0
    assert "высоким пересечением нет" in capsys.readouterr().out


def test_код_2_когда_подборок_нет(monkeypatch, capsys):
    monkeypatch.setattr(ИНСТР, "добыть", _загрузчик({"/": "<html></html>"}))
    assert ИНСТР.main(["x.site"]) == 2
    вывод = capsys.readouterr().out
    assert "НЕ ИЗМЕРЕНО" in вывод
    assert "ПОЧТИ ОДНО И ТО ЖЕ" not in вывод


