# --- источник перечня -------------------------------------------------------
#
# Полка главной — ПОДМНОЖЕСТВО: измерено 20.10 на zonafilm12.site, где на
# главной 8 подборок, а в разделе /collections/ их 12. Вывод по восьми говорил
# бы о витрине меньше, чем кажется, поэтому источник выбирается явно.

def test_перечень_можно_взять_из_раздела():
    страницы = {
        "/": _главная(["a"]),
        "/collections": _главная(["a", "b", "c"]),
        "/collection/a": _страница(["/title/t1/"]),
        "/collection/b": _страница(["/title/t2/"]),
        "/collection/c": _страница(["/title/t3/"]),
    }
    з = _загрузчик(страницы)
    с_главной = ИНСТР.собрать("x.site", з)
    из_раздела = ИНСТР.собрать("x.site", з, из_индекса=True)
    assert с_главной["ключи"] == ["a"]
    assert из_раздела["ключи"] == ["a", "b", "c"]


def test_пустой_раздел_называет_где_искали():
    з = _загрузчик({"/": _главная(["a"]), "/collections": "<html></html>"})
    итог = ИНСТР.собрать("x.site", з, из_индекса=True)
    assert "в разделе /collections/" in итог["не_измерено"]
