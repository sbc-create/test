"""Проверки измерения пересечения подборок.

Инструмент отвечает на вопрос «чем подборка отличается от соседней», и вывод
«почти одно и то же» принимается только от проверки, которая умеет ответить
«различаются». Поэтому отрицательный контроль здесь обязателен и стоит рядом с
положительным.

Отрицательные контроли, названные заранее:

* наборы с малым пересечением НЕ помечаются — иначе дублем была бы любая пара;
* доля считается от МЕНЬШЕГО набора: иначе короткая подборка, целиком входящая
  в длинную, давала бы маленькую долю и пряталась;
* непрочитанная страница — НЕ пустой набор: пустой пересекался бы с чем угодно
  на ноль процентов и читался бы как «различаются»;
* отсутствие ссылок на подборки на главной — отдельный исход с кодом 2
  (измерено 20.10 на zonafilm.cc: там другая главная), а не «дублей нет».

Сеть не используется: загрузчик передаётся параметром.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "collections_overlap", КОРЕНЬ / "automation/local/collections-overlap.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)


def _страница(пути, *, h1="Подборка", страниц=10, роботы="index, follow"):
    ссылки = "".join(f'<a href="{п}">x</a>' for п in пути)
    return (f'<html><head><meta name="robots" content="{роботы}"></head>'
            f'<body><h1>{h1}</h1>{ссылки}'
            f'<nav>страница 1 из {страниц}</nav></body></html>')


def _главная(ключи):
    ссылки = "".join(f'<a href="/collection/{к}/">x</a>' for к in ключи)
    return f"<html><body>{ссылки}</body></html>"


def _загрузчик(страницы: dict):
    """Отдаёт тело по ТОЧНОМУ пути. Неизвестный путь — пустая строка."""
    def добыть(адрес: str) -> str:
        путь = "/" + адрес.split("/", 3)[3] if адрес.count("/") > 2 else "/"
        return страницы.get(путь.rstrip("/") or "/", "")
    return добыть


# --- положительный и отрицательный контроль пересечения -----------------------

def test_почти_одинаковые_наборы_помечаются():
    наборы = {"a": {f"/title/t{n}/" for n in range(10)},
              "b": {f"/title/t{n}/" for n in range(9)} | {"/title/z/"}}
    пары = ИНСТР.пересечения(наборы)
    assert len(пары) == 1
    assert пары[0]["общих"] == 9 and пары[0]["меньший"] == 10
    assert пары[0]["почти_одно"] is True


def test_различные_наборы_не_помечаются():
    """Отрицательный контроль: инструмент умеет отвечать «различаются»."""
    наборы = {"a": {f"/title/t{n}/" for n in range(10)},
              "b": {f"/title/u{n}/" for n in range(10)}}
    пары = ИНСТР.пересечения(наборы)
    assert пары[0]["общих"] == 0
    assert пары[0]["почти_одно"] is False


def test_пара_на_пороге_считается_дублем():
    наборы = {"a": {f"/title/t{n}/" for n in range(10)},
              "b": {f"/title/t{n}/" for n in range(7)} | {"/title/z/",
                                                          "/title/y/",
                                                          "/title/w/"}}
    пара = ИНСТР.пересечения(наборы)[0]
    assert pytest_approx(пара["доля"], 0.70)
    assert пара["почти_одно"] is True


def pytest_approx(значение, цель, допуск=1e-9):
    return abs(значение - цель) < допуск


def test_доля_от_меньшего_набора():
    """Короткая подборка целиком внутри длинной — это 100 %, а не 5 %."""
    наборы = {"длинная": {f"/title/t{n}/" for n in range(100)},
              "короткая": {f"/title/t{n}/" for n in range(5)}}
    пара = ИНСТР.пересечения(наборы)[0]
    assert пара["меньший"] == 5
    assert пара["доля"] == 1.0
    assert пара["почти_одно"] is True


def test_пустой_набор_пары_не_даёт():
    наборы = {"a": {f"/title/t{n}/" for n in range(5)}, "b": set()}
    assert ИНСТР.пересечения(наборы) == []


def test_порог_можно_поднять():
    наборы = {"a": {f"/title/t{n}/" for n in range(10)},
              "b": {f"/title/t{n}/" for n in range(8)} | {"/title/z/",
                                                          "/title/y/"}}
    assert ИНСТР.пересечения(наборы, порог=0.70)[0]["почти_одно"] is True
    assert ИНСТР.пересечения(наборы, порог=0.90)[0]["почти_одно"] is False


# --- разбор страницы ----------------------------------------------------------

def test_разбор_читает_подписи():
    р = ИНСТР.разобрать(_страница(["/title/a/", "/title/b/"], h1="Высокие оценки",
                                  страниц=969, роботы="index, follow"))
    assert р["пути"] == {"/title/a/", "/title/b/"}
    assert р["имя"] == "Высокие оценки"
    assert р["страниц"] == "969"
    assert р["роботы"] == "index, follow"


def test_разбор_без_подписей_не_выдумывает():
    р = ИНСТР.разобрать("<html><body></body></html>")
    assert р["пути"] == set()
    assert р["имя"] == "—" and р["страниц"] == "?" and р["роботы"] == "?"


def test_адреса_с_параметрами_и_якорями_не_берутся():
    р = ИНСТР.разобрать(_страница(["/title/a/", "/title/a/?page=2",
                                   "/title/a/#top"]))
    assert р["пути"] == {"/title/a/"}


def test_ключи_подборок_без_повторов():
    assert ИНСТР.ключи_подборок(_главная(["a", "b", "a"])) == ["a", "b"]


# --- сбор по домену: непрочитанное не становится пустым -----------------------

def test_непрочитанная_подборка_не_пустой_набор():
    страницы = {"/": _главная(["a", "b"]),
                "/collection/a": _страница([f"/title/t{n}/" for n in range(10)])}
    итог = ИНСТР.собрать("x.site", _загрузчик(страницы))
    assert итог["непрочитанные"] == ["b"]
    assert "b" not in итог["наборы"]


def test_без_ссылок_на_подборки_это_не_измерено():
    итог = ИНСТР.собрать("x.site", _загрузчик({"/": "<html></html>"}))
    assert итог["не_измерено"] == "на главной нет ссылок на подборки"


