def _ячейка(tmp_path: pathlib.Path, каталог: list[dict], детали: dict) -> pathlib.Path:
    д = tmp_path / "data"
    д.mkdir(parents=True, exist_ok=True)
    (д / "x-01-catalog.json").write_text(
        json.dumps({"items": каталог}, ensure_ascii=False), encoding="utf-8")
    (д / "x-01-details.json").write_text(
        json.dumps({"details": детали}, ensure_ascii=False), encoding="utf-8")
    return д


def test_год_и_дата_каталога_не_смешиваются(tmp_path):
    """Фильм 1932 года, добавленный вчера, — не новинка."""
    д = _ячейка(tmp_path,
                [{"slug": "old", "year": "1932", "kind": "Фильм",
                  "published_at": "2026-10-18T20:59:02Z",
                  "published_at_estimated": False}],
                {"old": {"type": "movie", "playable": True, "seasons": None,
                         "sources": [{"availability_status": "available"}]}})
    кат, дет = ИНСТР.данные_ячейки(д)
    с = ИНСТР.сведения({"слаг": "old"}, кат, дет, СЕГОДНЯ)
    assert с["год"] == "1932"
    assert с["возраст_лет"] == 94
    assert с["в_каталоге_с"] == "2026-10-18"
    assert с["дней_в_каталоге"] == 1
    assert с["серий_доступно"] == 1, "у фильма доступность — playable и источник"


