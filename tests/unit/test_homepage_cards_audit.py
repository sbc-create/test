def _проверить_на_странице(страница: str, *, сколько: int = 24) -> dict:
    """Прогон `проверить` на готовом теле страницы, без обращения к сети."""
    прежний = ИНСТР.добыть
    ИНСТР.добыть = lambda url, **к: страница
    try:
        return ИНСТР.проверить("проба.ru", None, сколько, СЕГОДНЯ)
    finally:
        ИНСТР.добыть = прежний


def test_замечание_о_заглушках_называет_охват():
    """Иначе «карточек без изображения: 1» читается как «на витрине одна».

    Измерено 20.10 на zonafilm.space: из первых 24 карточек заглушка одна, а
    на всей главной их семь. Проход разбирает первые карточки по замыслу,
    поэтому охват обязан стоять в самом замечании.
    """
    страница = (
        '<html><body><div class="shelf"><h2>Полка</h2>'
        '<a class="c" href="/title/bez-kartinki/" title="Без картинки">'
        '<span class="c__p"><span class="c__none"><b>Б</b></span></span></a>'
        '<a class="c" href="/title/s-kartinkoy/" title="С картинкой">'
        '<span class="c__p"><img src="/poster/x.webp" alt=""></span></a>'
        '</div></body></html>')
