"""REQ-HOME-CARDS-AUDIT: ревизия первых карточек главной различает три даты.

Задание владельца 19.10: «Различай год произведения, дату появления в каталоге
и дату фактического выхода новой серии». Инструмент
`automation/local/homepage-cards-audit.py` обязан держать их раздельно, иначе
вывод «на главной много старых тайтлов» нечем подтвердить и нечем опровергнуть.

Два признака в этом инструменте уже были неверными, и оба закреплены ниже:

1. доступность считалась суммой `avail` по сезонам, а у фильма `seasons` равен
   `null` — первый живой замер объявил «24 карточки без доступных серий» на
   полке фильмов, где всё исправно;
2. подробности ячейки читались из первого файла по маске `*details*.json`, а им
   оказался служебный `.zona-02-details-avail-ring.json` без ключа `details` —
   все карточки печатались как «0/0 серий».

Дата фактического выхода новой серии в данных ячейки ОТСУТСТВУЕТ: `seasons`
несут только `avail` и `eps`. Инструмент поэтому её не выдумывает, и проверка
ниже это закрепляет.
"""
from __future__ import annotations

