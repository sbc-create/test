КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/homepage-cards-audit.py"
_спец = importlib.util.spec_from_file_location("homepage_cards_audit", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)

СЕГОДНЯ = dt.date(2026, 10, 19)


def _страница(полки: list[tuple[str, list[str]]], *, атрибуты: str = "") -> str:
    куски = ["<html><body>"]
    for заголовок, пути in полки:
        куски.append(f'<section{атрибуты}><h2>{заголовок}</h2>')
        for п in пути:
            куски.append(f'<a class="c" href="{п}">'
                         f'<img src="https://poster.test/{п.strip("/")}.webp">'
                         f'<h3>Карточка</h3></a>')
        куски.append("</section>")
    куски.append("</body></html>")
    return "".join(куски)


# --- блоки --------------------------------------------------------------------

def test_полки_и_карточки_под_ними():
    тело = _страница([("Новые фильмы", ["/title/a/", "/title/b/"]),
                      ("Подборки", [])])
    полки = ИНСТР.блоки(тело)
    assert [п["заголовок"] for п in полки] == ["Новые фильмы", "Подборки"]
    assert полки[0]["карточек"] == 2 and полки[1]["карточек"] == 0


def test_карточка_знает_свою_полку():
    тело = _страница([("Новые фильмы", ["/title/a/"]),
                      ("Высокие оценки", ["/title/b/"])])
    карточки = ИНСТР.карточки_по_порядку(тело)
    assert [(к["слаг"], к["блок"]) for к in карточки] == [
        ("a", "Новые фильмы"), ("b", "Высокие оценки")]


def test_повтор_между_полками_виден():
    тело = _страница([("Новые фильмы", ["/title/a/"]),
                      ("Высокие оценки", ["/title/a/", "/title/b/"])])
    карточки = {к["слаг"]: к for к in ИНСТР.карточки_по_порядку(тело)}
    assert карточки["a"]["в_блоках"] == 2
    assert карточки["b"]["в_блоках"] == 1


def test_карточек_берётся_ровно_запрошенное_число():
    тело = _страница([("Полка", [f"/title/t{н}/" for н in range(40)])])
    assert len(ИНСТР.карточки_по_порядку(тело, 24)) == 24


