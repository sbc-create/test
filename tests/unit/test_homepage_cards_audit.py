def test_служебный_файл_подробностей_пропускается(tmp_path):
    """Ровно пойманная ошибка: разбор обрывался на служебном кольце."""
    д = tmp_path / "data"
    д.mkdir(parents=True)
    (д / "x-01-catalog.json").write_text(
        json.dumps({"items": [{"slug": "a", "year": "2020"}]}), encoding="utf-8")
    (д / ".x-01-details-avail-ring.json").write_text(
        json.dumps({"ring": [1, 2, 3]}), encoding="utf-8")
    (д / "x-01-details.nums.json").write_text(json.dumps({"nums": 1}),
                                              encoding="utf-8")
    (д / "x-01-details.json").write_text(
        json.dumps({"details": {"a": {"type": "movie", "playable": True,
                                      "sources": [{"availability_status": "available"}]}}}),
        encoding="utf-8")
    кат, дет = ИНСТР.данные_ячейки(д)
    assert len(кат) == 1
    assert "a" in дет, "подробности обязаны прочитаться, а не оборваться на служебном файле"


