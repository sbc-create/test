# --- текстовый раздел «О каталоге» не пустая полка ---------------------------
#
# Повод: ревизия давала замечание «пустые полки: О каталоге» на четырёх
# витринах Lords. Блок собирается ОТДЕЛЬНО от полок — доказательство в коде
# витрины: `тело = intro + _склеить(полосы) + bottom`, где `bottom` это
# `<section class="sec"><h2>О каталоге</h2><p>…</p></section>`. Карточек в нём
# не бывает ни при каком наборе данных.
