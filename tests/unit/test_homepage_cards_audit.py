# --- приёмочные пороги (критерий T276) ---------------------------------------
#
# Публикатор умеет только status/contains/absent и медиану не посчитает,
# поэтому числовой критерий проверяется этой командой: медиана года первых
# карточек не ниже порога, карточек старше десяти лет не больше допустимого,
# размеры полок не изменились. Последнее — отрицательный контроль правки
# порядка: она меняет СОСТАВ, а не размеры.

def _свод(медиана, старше, полки):
    return {"карточек": 24, "медиана_года": медиана, "старше_порога": старше,
            "годов_известно": 24, "размеры_полок": полки}


def test_приёмка_проходит_на_ожидаемых_числах():
    нарушено = ИНСТР.приёмка(_свод(2026, 0, [24, 12, 12, 9]),
                             медиана=2025, старше=0, полки=[24, 12, 12, 9])
    assert нарушено == []


def test_старая_медиана_приёмку_валит():
    нарушено = ИНСТР.приёмка(_свод(1979, 23, [24, 12, 12, 9]),
                             медиана=2025, старше=0, полки=[24, 12, 12, 9])
    assert any("медиана года 1979" in н for н in нарушено)
    assert any("старше" in н for н in нарушено)


def test_изменившийся_размер_полки_валит_приёмку():
    """Отрицательный контроль: правка порядка не имеет права сократить полку."""
    нарушено = ИНСТР.приёмка(_свод(2026, 0, [18, 12, 12, 9]),
                             медиана=2025, старше=0, полки=[24, 12, 12, 9])
    assert any("размеры полок" in н for н in нарушено)


def test_неизмеренная_медиана_приёмкой_не_считается():
    """«Не измерено» не проходит порог: приёмка по неизвестному — подгонка."""
    нарушено = ИНСТР.приёмка(_свод(None, 0, [24, 12, 12, 9]), медиана=2025)
    assert нарушено and "НЕ ИЗМЕРЕНА" in нарушено[0]


def test_без_порогов_приёмка_молчит():
    assert ИНСТР.приёмка(_свод(1900, 24, [1])) == []


def test_лишние_полки_за_пределами_ожидания_не_мешают():
    """Сравниваются только первые полки: остальные — дело витрины."""
    нарушено = ИНСТР.приёмка(_свод(2026, 0, [24, 12, 12, 9, 6, 12]),
                             медиана=2025, старше=0, полки=[24, 12, 12, 9])
    assert нарушено == []
