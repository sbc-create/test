"""Граница герметичного прогона: `pytest tests/` не обращается к живому флоту.

Зачем это тест, а не обещание в документе.

Разделение контуров держится ровно до первой правки, которая «всего один раз»
заглянет в `/srv/site-factory` или на канонический порт. Заметить такую правку
по обычному прогону нельзя: на машине, где флот есть, она проходит зелёной —
именно поэтому она туда и попадает. Краснеет она только у раннера, то есть
после push, и выглядит как «CI сломался», а не как «тест вышел за границу».

Поэтому граница проверяется здесь, разбором кода самих тестов. Проверка
статическая и намеренно грубая: она смотрит на строковые константы в коде и
ничего не запускает. Комментарии и docstring из разбора выпадают сами — их в
AST нет, — и это правильно: рассказывать о каноническом пути можно, ходить по
нему в герметичном прогоне нельзя.

Границы применения. Проверяются файлы `test_*.py` — те, что pytest собирает по
`python_files`. Вспомогательные скрипты вроде `tests/audit/run_tests.py`
запускаются вручную на хосте, к обязательной проверке PR отношения не имеют и
под это правило не попадают.
"""
from __future__ import annotations

import ast
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
НАБОРЫ = КОРЕНЬ / "tests"

#: Каталоги ДАННЫХ живого флота. Обращение к ним из герметичного прогона и есть
#: та ошибка, ради которой файл написан.
#:
#: `/srv/site-factory/repo` в список не входит намеренно: это рабочая копия
#: репозитория, и тесты юнит-файлов законно утверждают, что служба запускается
#: именно оттуда. Запрещено не упоминание `/srv`, а чтение боевых данных.
КОРНИ_ФЛОТА = (
    "/srv/site-factory/audit-ledger",
    "/srv/site-factory/registry-core",
    "/srv/site-factory/changeset-store",
    "/srv/site-factory/control-plane-contracts",
    "/srv/site-factory/control-api",
    "/srv/site-factory/audit-evidence",
)

#: Канонические слушатели боевого контура. Тест, который на них ходит, либо
#: пишет в историю системы, либо падает на `Connection refused` у раннера.
КАНОНИЧЕСКИЕ_АДРЕСА = ("127.0.0.1:8790", "127.0.0.1:8795",
                       "localhost:8790", "localhost:8795")


#: Сам сторож из проверки исключён: перечни запрещённых путей и адресов лежат
#: здесь же, и иначе правило срабатывало бы на собственном тексте. Тот же приём,
#: что у `test_34_внешние_провайдеры_не_вызывались`, и по той же причине.
СТОРОЖ = Path(__file__).resolve()


def файлы_наборов() -> list[Path]:
    return sorted(p for p in НАБОРЫ.rglob("test_*.py")
                  if p.is_file() and p.resolve() != СТОРОЖ)


def строки_кода(файл: Path) -> list[tuple[int, str]]:
    """Строковые константы ИЗ КОДА: docstring-и исключены.

    Docstring — это Expr-узел со строкой, стоящий первым в модуле, классе или
    функции. Именно так отличается «тест рассказывает про канонический путь» от
    «тест по нему ходит».
    """
    дерево = ast.parse(файл.read_text(encoding="utf-8"), filename=str(файл))
    документация: set[int] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Module | ast.ClassDef | ast.FunctionDef
                             | ast.AsyncFunctionDef):
            тело = getattr(узел, "body", None)
            if (тело and isinstance(тело[0], ast.Expr)
                    and isinstance(тело[0].value, ast.Constant)
                    and isinstance(тело[0].value.value, str)):
                документация.add(id(тело[0].value))
    найдено = []
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Constant) and isinstance(узел.value, str)
                and id(узел) not in документация):
            найдено.append((узел.lineno, узел.value))
    return найдено


@pytest.mark.parametrize("файл", файлы_наборов(),
                         ids=lambda p: str(p.relative_to(КОРЕНЬ)))
def test_набор_не_читает_данные_живого_флота(файл: Path):
    """Данные флота приходят из обвязки прогона, а не из каталогов машины."""
    нарушения = [
        f"{файл.relative_to(КОРЕНЬ)}:{строка}: {корень}"
        for строка, значение in строки_кода(файл)
        for корень in КОРНИ_ФЛОТА if корень in значение]
    assert not нарушения, (
        "герметичный прогон обращается к данным живого флота — такие проверки "
        "место в host-контуре (bin/host-attest):\n" + "\n".join(нарушения))


@pytest.mark.parametrize("файл", файлы_наборов(),
                         ids=lambda p: str(p.relative_to(КОРЕНЬ)))
def test_набор_не_ходит_на_канонические_порты(файл: Path):
    """Порт выбирает ядро; фиксированный номер — это чужая работающая служба."""
    нарушения = [
        f"{файл.relative_to(КОРЕНЬ)}:{строка}: {адрес}"
        for строка, значение in строки_кода(файл)
        for адрес in КАНОНИЧЕСКИЕ_АДРЕСА if адрес in значение]
    assert not нарушения, (
        "герметичный прогон обращается к каноническому слушателю:\n"
        + "\n".join(нарушения))


def _правит_окружение_на_уровне_модуля(дерево: ast.Module) -> list[int]:
    """Строки, где `os.environ` правится в теле модуля, а не внутри функции."""
    строки = []
    for узел in дерево.body:
        for внутри in ast.walk(узел):
            if (isinstance(внутри, ast.Call)
                    and isinstance(внутри.func, ast.Attribute)
                    and внутри.func.attr in ("update", "setdefault", "pop")
                    and isinstance(внутри.func.value, ast.Attribute)
                    and внутри.func.value.attr == "environ"):
                строки.append(внутри.lineno)
            if isinstance(внутри, ast.Subscript) and isinstance(
                    внутри.value, ast.Attribute) and внутри.value.attr == "environ":
                родитель = узел
                if isinstance(родитель, ast.Assign | ast.AugAssign | ast.AnnAssign):
                    строки.append(внутри.lineno)
    return sorted(set(строки))


@pytest.mark.parametrize(
    "файл", sorted(НАБОРЫ.rglob("conftest.py")),
    ids=lambda p: str(p.relative_to(КОРЕНЬ)))
def test_conftest_не_оставляет_окружение_чужим_наборам(файл: Path):
    """Правка `os.environ` на уровне модуля обязана иметь парное снятие.

    Дефект, ради которого проверка написана, стоил половины разбора этого PR.
    `tests/audit/conftest.py` направлял набор на эфемерный экземпляр правкой
    `os.environ` — это верно и необходимо: тестовые модули читают пути при
    импорте, и фикстура уже опоздала бы. Но правка оставалась до конца процесса
    и доставалась каждому набору, собранному позже: `/api/v1/sites` читал
    `REGISTRY_DB` прогона вместо профилей репозитория, и `test_admin_http`
    падал — только в полном прогоне и только из-за соседнего каталога.

    Всё это время утечка существовала и ничем себя не проявляла: запрос к
    неполному реестру прогона падал, API молча откатывался к профилям. Стоило
    реестру прогона стать полнее — и дефект проявился в постороннем наборе.

    Поэтому требование простое: кто правит окружение в теле conftest, тот
    обязан объявить `pytest_runtest_teardown`. Хук вызывается только для
    элементов своего каталога, и после последнего из них правка снимается.
    """
    дерево = ast.parse(файл.read_text(encoding="utf-8"), filename=str(файл))
    правки = _правит_окружение_на_уровне_модуля(дерево)
    if not правки:
        return
    снятие = {узел.name for узел in дерево.body
              if isinstance(узел, ast.FunctionDef | ast.AsyncFunctionDef)}
    assert "pytest_runtest_teardown" in снятие, (
        f"{файл.relative_to(КОРЕНЬ)}: окружение правится в строках {правки}, "
        "но снятия нет — правка достанется каждому набору, собранному позже")


def test_host_контур_не_попадает_в_обычную_коллекцию():
    """`pytest tests/` не должен собирать ни одной host-проверки.

    Иначе разделение существует только на словах: файл `test_*.py`, положенный
    в host-пакет, вернулся бы в обязательную проверку PR со всеми своими
    требованиями к живой машине.
    """
    host = КОРЕНЬ / "host_attestation"
    assert host.is_dir(), "host-контур на месте"
    собираемые = sorted(p.name for p in host.rglob("test_*.py"))
    assert собираемые == [], (
        f"в host-контуре лежат файлы, которые pytest соберёт: {собираемые}")


def test_host_контур_не_импортируется_наборами():
    """Обратная зависимость: герметичный прогон не тянет host-проверки.

    Импорт сам по себе безвреден — `host_attestation.checks` при импорте ничего
    не измеряет, и `tests/unit/test_host_attestation_contract.py` его законно
    импортирует. Проверяется другое: что ВЫПОЛНЕНИЕ проверок из наборов никто
    не вызывает. Вызов `выполнить_все()` в герметичном прогоне означал бы поход
    на живой хост под видом обычного теста.
    """
    вызовы = []
    for файл in файлы_наборов():
        дерево = ast.parse(файл.read_text(encoding="utf-8"), filename=str(файл))
        for узел in ast.walk(дерево):
            if isinstance(узел, ast.Call):
                имя = узел.func
                название = (имя.attr if isinstance(имя, ast.Attribute)
                            else getattr(имя, "id", ""))
                if название == "выполнить_все":
                    вызовы.append(f"{файл.relative_to(КОРЕНЬ)}:{узел.lineno}")
    assert not вызовы, (
        "герметичный прогон запускает host-проверки: " + ", ".join(вызовы))
