"""Скрипт плеера обязан быть разбираемым JavaScript.

Повод. 15.10 в этот скрипт вставлены две строки — отправка целей Метрики из
воронки его состояний и из создания элемента (MOD-38). Опечатка в этом месте
не ловится ничем из существующего: разбор python видит обычную строку, а
проверки плеера работают с другим рендерером (`factory.render`), а не с
host-рантаймом. Падает такая опечатка в браузере у посетителя, и падает
воспроизведение на ВСЕХ витринах семейства сразу — скрипт один.

Поэтому скрипт берётся из рантайма как есть и проверяется `node --check`.
Проверка не о целях: она о том, что большой кусок клиентского кода, который
правят руками, остаётся разбираемым.
"""
from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
РАНТАЙМ = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"

pytestmark = pytest.mark.skipif(shutil.which("node") is None,
                                reason="node на машине нет — разобрать скрипт нечем")


def _литерал(имя: str) -> str:
    """Значение строковой константы рантайма без импорта всего модуля.

    Рантайм целиком требует каталога витрины, манифеста и плеера. Здесь нужна
    одна константа, поэтому её объявление вычисляется отдельно — вместе с
    подстановками, если это f-строка.
    """
    исходник = РАНТАЙМ.read_text(encoding="utf-8")
    м = re.search(rf'(?ms)^{имя}\s*=\s*(f?""".*?""")', исходник)
    assert м, f"в рантайме нет константы {имя}"
    прост: dict = {"СКРИПТ_ПЛЕЕРА": "https://example.invalid/player.js"}
    return eval(м.group(1), prost_globals(прост))  # noqa: S307 — свой же исходник


def prost_globals(прост: dict) -> dict:
    прост.setdefault("__builtins__", {})
    return прост


@pytest.mark.parametrize("имя", ["СКРИПТ_ПЛЕЕРА_КЛИЕНТ"])
def test_скрипт_разбирается_как_javascript(имя, tmp_path):
    тело = _литерал(имя)
    assert len(тело) > 2000, f"{имя}: подозрительно короткий скрипт"
    ф = tmp_path / f"{имя}.js"
    ф.write_text(тело, encoding="utf-8")
    г = subprocess.run(["node", "--check", str(ф)], capture_output=True,
                       text=True, timeout=120)
    assert г.returncode == 0, (
        f"{имя} не разбирается как JavaScript — воспроизведение сломается на "
        f"всех витринах семейства:\n{(г.stderr or '')[:800]}")


def test_цели_плеера_в_скрипте_есть_и_защищены_try():
    """Отправка цели не имеет права уронить плеер.

    Если `window.__sfGoalOnce` отсутствует (страница без счётчика) или Метрика
    не загрузилась, вызов обязан быть проглочен: плеер важнее отчёта.
    """
    тело = _литерал("СКРИПТ_ПЛЕЕРА_КЛИЕНТ")
    # Пояснения вырезаются: они объясняют правку и занимают сотни знаков, а
    # проверяется КОД. Первая редакция искала try в окне перед именем цели и
    # нашла там комментарий — то есть измеряла длину пояснения.
    код = re.sub(r"/\*.*?\*/", " ", тело, flags=re.S)
    assert "player_ready" in код and "player_error" in код
    assert "player_start" in код
    for цель in ("player_ready", "player_error", "player_start"):
        и = код.index(цель)
        до = код[:и]
        # Окно фиксированной длины не годится: условие перехода состояний
        # длинное и съедает его целиком. Проверяется структура — последний
        # открытый try перед вызовом ещё не закрыт.
        открыт = до.rfind("try{")
        закрыт = до.rfind("}catch")
        assert открыт >= 0 and открыт > закрыт, (
            f"вызов {цель} не внутри try — отказ Метрики уронил бы плеер")


def test_скрипт_не_зовёт_метрику_напрямую():
    """Только через общую точку: иначе появится вызов с параметрами.

    Приватность целей держится на том, что единственная точка отправки не
    принимает данных. Прямой `ym(...)` из скрипта плеера обошёл бы её.
    """
    тело = _литерал("СКРИПТ_ПЛЕЕРА_КЛИЕНТ")
    assert "reachGoal" not in тело, (
        "скрипт плеера зовёт Метрику напрямую — отправка обязана идти через "
        "window.__sfGoalOnce, у которой нет аргумента для данных")
    assert re.search(r"\bym\s*\(", тело) is None, "прямой вызов ym в скрипте плеера"
