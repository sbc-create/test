"""Заявленная, но недоступная серия не должна быть достижима.

Раньше она получала атрибут `data-off` и приглушённый цвет, оставаясь
`<a href>`. Мышью она выглядела неактивной — и этого хватало, чтобы дефект не
заметили. Клавиатурой, читалкой экрана, поисковым обходом и прямым адресом
страница открывалась и отвечала 200, показывая место, где смотреть нечего.

Замер соседней сессии на живой витрине: у одного тайтла 450 таких ссылок из
500, у другого 34 из 46.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ))

ЯДРО = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"
ТЕКСТ = ЯДРО.read_text(encoding="utf-8")


def test_недоступная_серия_не_ссылка():
    """`data-off` на теге `a` означает, что ссылка осталась нажимаемой."""
    for строка in ТЕКСТ.splitlines():
        голая = строка.strip()
        if голая.startswith("#"):
            continue
        assert not re.search(r"<a\s[^>]*data-off", голая), (
            f"недоступная серия остаётся ссылкой: {голая[:100]}")


def test_недоступная_серия_помечена_для_доступности():
    """Приглушённый цвет — не признак для читалки экрана."""
    assert ТЕКСТ.count('<span data-off aria-disabled="true"') == 3, (
        "три места — компактный список номеров, список «Серия N» и раскладка Zona")


def test_номер_серии_остаётся_видимым():
    """Иначе пропадает разница между «сезон из 12» и «вышло 12 из 46»."""
    куски = re.findall(r"<span data-off aria-disabled=\"true\"'\n\s*f?' title=\"[^\"]+\">([^<]+)</span>",
                       ТЕКСТ)
    assert куски, "не нашёл разметку недоступной серии"
    assert all("{н}" in к for к in куски), f"номер потерян: {куски}"


def test_стиль_гашения_не_привязан_к_ссылке():
    """Селектор `a[data-off]` перестал бы действовать на span."""
    assert ".eps [data-off]" in ТЕКСТ
    assert ".zeps [data-off]" in ТЕКСТ
    assert "a[data-off]" not in ТЕКСТ
