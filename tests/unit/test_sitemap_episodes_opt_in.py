"""REQ-SEO-SITEMAP-EPISODES: адреса серий в карте — по объявлению витрины.

MOD-79: карта семейства Lords не выпускает адресов серий. Бюджет измерен
2026-10-18 — у витрины семейства это 565 008 ДОСТУПНЫХ серий из 613 412
объявленных, то есть 631 167 адресов, 15 файлов карты вместо 3, 16.4 с сборки
вместо 1.9 и пик 189 МиБ вместо 29 в процессе витрины.

Отсюда три свойства, и каждое проверяется здесь, потому что без любого из них
правка была бы вредной:

* ВЫКЛЮЧЕНО ПО УМОЛЧАНИЮ. Общий файл слоя приезжает на чужие линии их обычным
  выпуском; включение по умолчанию было бы правкой за них и десятикратным
  ростом их карты без их замера;
* в карту идут только серии С ДОРОЖКОЙ. Страницы серий без источника закрыты
  `noindex, follow` правкой 18.10; подать их обходчику значило бы вести его на
  закрытые адреса. Разница измерена: `eps` объявляет 613 412, `avail` отдаёт
  565 008;
* нумерация берётся у `список_серий` витрины, а не придумывается.

Эта правка ПОДГОТОВЛЕНА и ни на одной витрине не включена: включение требует
замера пика памяти в живом процессе одной закрытой витрины K2 (порядок записан
в MOD-79).
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "host"
        / "seo_layer.py")


def _модуль():
    имя = "seo_layer_серии"
    спец = importlib.util.spec_from_file_location(имя, ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


МОД = _модуль()

ЗАПИСИ = [{"slug": "alpha", "url": "/title/alpha/", "updated_at": "2026-10-10"},
          {"slug": "beta", "url": "/title/beta/", "updated_at": ""}]

#: У `alpha` два сезона: в первом доступны 1–3 из девяти, во втором — только 1.
#: У `beta` подробностей нет вовсе.
ПОДРОБНОСТИ = {"alpha": {"seasons": {"1": {"n": 1, "eps": 9, "avail": 3},
                                     "2": {"n": 2, "eps": 4, "avail": 1}}}}


def _список_серий(деталь):
    """Подобие рантаймового `список_серий`: номера и доступные номера."""
    итог = []
    for ключ, сезон in sorted((деталь.get("seasons") or {}).items()):
        всего = int(сезон.get("eps") or 0)
        доступно = int(сезон.get("avail") or 0)
        итог.append({"n": int(сезон.get("n") or ключ),
                     "номера": list(range(1, всего + 1)),
                     "доступные": set(range(1, доступно + 1))})
    return итог


class _Обработчик:
    def __init__(self, данные, подробности):
        self.данные = данные
        self.подробности = подробности
        self.индекс = {}


class _Данные:
    def __init__(self, items):
        self.items = items
        self.years = ()


class _Подробности:
    def __init__(self, записи):
        self.записи = записи


class _Рантайм:
    def __init__(self, *, с_сериями, записи=ЗАПИСИ, подробности=ПОДРОБНОСТИ,
                 список=True):
        self.СЕМЕЙСТВО = "lords"
        self.Обработчик = _Обработчик(_Данные(записи),
                                      _Подробности(подробности))
        self.РАЗДЕЛЫ_КАРТЫ = ()
        if с_сериями:
            self.КАРТА_С_СЕРИЯМИ = True
        if список:
            self.список_серий = _список_серий


def _адреса(рантайм) -> list[str]:
    страницы, _ = МОД.адреса_карты(рантайм)
    return [с["url"] for с in страницы]


def test_по_умолчанию_серий_в_карте_нет():
    """Главное свойство: чужие линии получают файл слоя своим выпуском."""
    адреса = _адреса(_Рантайм(с_сериями=False))
    assert not [а for а in адреса if "/episode-" in а]
    assert "/title/alpha/" in адреса


def test_по_объявлению_серии_появляются():
    адреса = _адреса(_Рантайм(с_сериями=True))
    assert "/title/alpha/season-1/episode-1/" in адреса
    assert "/title/alpha/season-1/episode-3/" in адреса
    assert "/title/alpha/season-2/episode-1/" in адреса
    assert "/title/alpha/" in адреса, "карточки не должны исчезнуть"


def test_недоступные_серии_в_карту_не_идут():
    """Они закрыты `noindex, follow`: вести на них обходчика нельзя."""
    адреса = _адреса(_Рантайм(с_сериями=True))
    for закрытая in ("/title/alpha/season-1/episode-4/",
                     "/title/alpha/season-1/episode-9/",
                     "/title/alpha/season-2/episode-2/"):
        assert закрытая not in адреса
    assert len([а for а in адреса if "/episode-" in а]) == 4


def test_произведение_без_подробностей_не_даёт_адресов():
    адреса = _адреса(_Рантайм(с_сериями=True))
    assert not [а for а in адреса if а.startswith("/title/beta/season-")]


def test_у_адреса_серии_нет_даты_изменения():
    """Даты изменения у серии нет, а «сегодня» соврало бы обо всех сразу."""
    страницы, _ = МОД.адреса_карты(_Рантайм(с_сериями=True))
    серии = [с for с in страницы if "/episode-" in с["url"]]
    assert серии and all(not с["lastmod"] for с in серии)
    # Отрицательный контроль: у карточки дата осталась.
    карточка = next(с for с in страницы if с["url"] == "/title/alpha/")
    assert карточка["lastmod"] == "2026-10-10"


def test_без_список_серий_правка_молчит_а_не_падает():
    """Витрина старого выпуска объявления не несёт — карта собирается как была."""
    адреса = _адреса(_Рантайм(с_сериями=True, список=False))
    assert not [а for а in адреса if "/episode-" in а]
    assert "/title/alpha/" in адреса


def test_основание_и_бюджет_названы_рядом_с_правкой():
    тело = ПУТЬ.read_text(encoding="utf-8")
    assert "565 008" in тело and "613 412" in тело
    assert "MOD-79" in тело
    assert "приезжает на чужие линии их обычным выпуском" in тело


# --------------------------------------------------------- флаг у рантайма
#
# Включение — решение КАЖДОЙ витрины, и читается оно из окружения, а не стоит
# в коде: иначе включение означало бы выпуск общего рантайма на всю сеть.

РАНТАЙМ_ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
                  / "lords-frontend.py")


def _значение_флага(тело: str) -> str:
    начало = тело.index("КАРТА_С_СЕРИЯМИ =")
    return тело[начало:тело.index("\n\n", начало)]


def test_флаг_читается_из_окружения_и_выключен_по_умолчанию():
    тело = РАНТАЙМ_ШАБЛОН.read_text(encoding="utf-8")
    строка = _значение_флага(тело)
    assert 'os.environ.get("LORDS_SITEMAP_EPISODES", "")' in строка
    assert '("1", "true", "yes", "on")' in строка, (
        "перечень истинных значений обязан быть явным: иначе «0» или «off» "
        "включили бы правку")


def test_основание_выключенного_умолчания_названо_рядом():
    """Числа, а не осторожность: 565 008 серий, 15 файлов, пик 189 МиБ."""
    тело = РАНТАЙМ_ШАБЛОН.read_text(encoding="utf-8")
    где = тело.index("КАРТА_С_СЕРИЯМИ")
    рядом = тело[max(0, где - 1400):где + 200]
    assert "565 008" in рядом and "189 МиБ" in рядом
    assert "MOD-79" in рядом
    assert "за чужие линии" in рядом
