@нет_модуля
def test_записи_переживают_перезапуск_кода(витрина, monkeypatch):
    """Смена релиза не должна касаться голосов и комментариев."""
    с, модуль = витрина
    ch = модуль.СООБЩЕСТВО
    об = Обработчик(модуль)
    поля = dict(_скрытые(модуль, об), value="7")
    _post(модуль, об, "/community/vote", поля)
    ключ = ch.ключ_посетителя(об)

    # Новый процесс витрины: тот же каталог данных, заново загруженный код.
    h.выгрузить(модуль)
    sys.modules.pop("community_http", None)
    заново = h.загрузить(с, monkeypatch)
    try:
        состояние = заново.СООБЩЕСТВО.хранилище().состояние(
            поля["subject"], ключ, slug="t0")
        assert состояние.мой_голос == 7
        assert состояние.голосов == 1
    finally:
        h.выгрузить(заново)
