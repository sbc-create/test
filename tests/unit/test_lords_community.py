@нет_модуля
def test_закреплённый_голос_не_меняется_и_интерфейс_этого_не_обещает(витрина):
    """Контракт модуля: первая сохранённая оценка окончательна.

    Возможность смены нельзя имитировать на клиенте: сервер откажет, и
    посетитель увидит не то число, которое сохранено.
    """
    _, модуль = витрина
    ch = модуль.СООБЩЕСТВО
    об = Обработчик(модуль)
    поля = dict(_скрытые(модуль, об), value="9")
    _post(модуль, об, "/community/vote", поля)
    кука = f"{ch.НАСТРОЙКА.кука_посетителя}={ch.ключ_посетителя(об)}"

    второй = Обработчик(модуль, куки=кука)
    _post(модуль, второй, "/community/vote", dict(_скрытые(модуль, второй), value="2"))
    цель = второй.ответы[-1][1]
    assert "community=error" in цель, "смена закреплённого голоса прошла"

    состояние = ch.хранилище().состояние(поля["subject"], ch.ключ_посетителя(об),
                                         slug="t0")
    assert состояние.мой_голос == 9 and состояние.голосов == 1

    разметка = ch._форма_оценки(состояние, "")
    assert "не меняется" in разметка
    assert 'action="/community/vote"' not in разметка, (
        "проголосовавшему показана форма смены оценки, которой модуль не поддерживает")


