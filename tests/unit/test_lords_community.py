    """Витрина с подключённым модулем и своим хранилищем сообщества."""
    с = h.Стенд(tmp_path, site_id="lords-test")
    записи = [h.запись(f"t{i}", title=f"Тайтл {i}", kind="Фильм") for i in range(6)]
    с.записать_каталог(записи)
