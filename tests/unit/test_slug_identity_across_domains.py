"""Личность слага между витринами: чем различать двойников и чего не путать.

Главный тест — `test_разный_состав_это_дефект_даже_при_одном_названии`:
у двух произведений с одинаковым названием заголовок совпадает, и признак,
построенный на названии, объявил бы их одним. Различает только состав.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "slug-identity-across-domains.py"

спец = importlib.util.spec_from_file_location("slug_identity", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


# --- состав по странице ----------------------------------------------------

def test_состав_собирается_по_ссылкам_на_серии():
    тело = ('<a href="/anime/x/season/2/episode/1">1</a>'
            '<a href="/anime/x/season/2/episode/2">2</a>'
            '<a href="/anime/x/season/3/episode/1">1</a>')
    assert модуль.состав(тело, "x") == ((2, 2), (3, 1))


def test_повторяющиеся_ссылки_не_удваивают_счёт():
    тело = ('<a href="/anime/x/season/1/episode/5">a</a>'
            '<a href="/anime/x/season/1/episode/5">тот же адрес</a>')
    assert модуль.состав(тело, "x") == ((1, 1),)


def test_ссылки_чужого_слага_в_состав_не_идут():
    тело = ('<a href="/anime/x/season/1/episode/1">своя</a>'
            '<a href="/anime/y/season/9/episode/9">чужая</a>')
    assert модуль.состав(тело, "x") == ((1, 1),)


def test_страница_без_серий_даёт_пустой_состав():
    assert модуль.состав("<p>ничего</p>", "x") == ()


def test_слаг_с_особыми_знаками_не_ломает_разбор():
    тело = '<a href="/anime/x-2.0/season/1/episode/1">1</a>'
    assert модуль.состав(тело, "x-2.0") == ((1, 1),)


# --- сверка между витринами ------------------------------------------------

def test_один_и_тот_же_состав_везде():
    итог = модуль.сверить({"a": ((1, 12),), "b": ((1, 12),), "c": ((1, 12),)})
    assert итог["исход"] == модуль.ОДИН


def test_разный_состав_это_дефект_даже_при_одном_названии():
    # «Стесняшка»: сезон 2 у одних витрин, сезон 1 у других.
    итог = модуль.сверить({"site": ((2, 12),), "org": ((2, 12),),
                           "biz": ((1, 12),), "7site": ((1, 12),)})
    assert итог["исход"] == модуль.РАЗНЫЕ
    assert "2" in итог["почему"]


def test_адрес_не_у_всех_витрин_это_не_дефект_личности():
    итог = модуль.сверить({"a": ((1, 5),), "b": ((1, 5),), "c": None})
    assert итог["исход"] == модуль.НЕ_У_ВСЕХ
    assert итог["молчат"] == ["c"]


def test_никто_не_ответил_это_не_измерено():
    итог = модуль.сверить({"a": None, "b": None})
    assert итог["исход"] == модуль.НЕ_ИЗМЕРЕНО


def test_пустой_состав_у_всех_считается_совпадением():
    # Страница работы без ссылок на серии — не повод объявлять расхождение.
    итог = модуль.сверить({"a": (), "b": ()})
    assert итог["исход"] == модуль.ОДИН


def test_пустой_против_непустого_это_расхождение():
    итог = модуль.сверить({"a": (), "b": ((1, 3),)})
    assert итог["исход"] == модуль.РАЗНЫЕ


def test_семья_названа_полностью():
    assert модуль.СЕМЬЯ_YUMMY == ("yummyani.site", "yummyani.org",
                                  "yummyani.biz", "yummyani7.site",
                                  "yummyani7.info")
