"""Порядок рецензии и выпуска: мера для приёмки MOD-173.

Повод измеренный. 25.10 по журналам хранилищ: публикация идёт через 28–53
секунды после подготовки, а рецензия приходит через 18–1267 минут ПОСЛЕ
публикации. Из 52 публикаций за сутки рецензия стояла раньше выпуска у ОДНОЙ.
То есть утверждение «материалы рецензируются» верно, а «рецензия обязательна»
— нет, и различить их можно только порядком.

Три свойства закреплены здесь, и каждое ловит отдельную подмену:

* рецензия ПОСЛЕ выпуска не считается воротами (иначе след прочтения
  неотличим от обязательной проверки);
* берётся ПОСЛЕДНЯЯ публикация материала: при переиздании судить надо о той
  редакции, что стоит на странице, а не о первой;
* знаменатель — число ПУБЛИКАЦИЙ, а не рецензий: иначе «все рецензии вовремя»
  вышло бы и при одной рецензии на тысячу публикаций.
"""
from __future__ import annotations

import datetime as dt
import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "review-before-publish.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("review_before_publish", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def _соб(домен, слаг, оп, когда):
    return {"домен": домен, "slug": слаг, "op": оп, "at": когда}


def test_рецензия_раньше_выпуска_это_ворота():
    из = МОД.порядок([
        _соб("d", "s", "review", "2026-10-25T01:00:00Z"),
        _соб("d", "s", "publish", "2026-10-25T01:05:00Z"),
    ])
    assert [з["исход"] for з in из["строки"]] == ["рецензия раньше выпуска"]


def test_рецензия_позже_выпуска_это_след_а_не_ворота():
    из = МОД.порядок([
        _соб("d", "s", "publish", "2026-10-25T01:00:00Z"),
        _соб("d", "s", "review", "2026-10-25T01:30:00Z"),
    ])
    строка = из["строки"][0]
    assert строка["исход"] == "рецензия позже выпуска"
    assert строка["задержка_мин"] == 30.0


def test_публикация_без_рецензии_названа_отдельно():
    из = МОД.порядок([_соб("d", "s", "publish", "2026-10-25T01:00:00Z")])
    assert из["строки"][0]["исход"] == "рецензии нет вовсе"


def test_судят_по_последней_публикации():
    """Переиздание: мера берёт ту публикацию, что стоит на странице.

    Чего эта мера НЕ проверяет и что сказано прямо: относится ли прежняя
    рецензия к НОВОЙ редакции. Это проверяет сама операция рецензии —
    отпечатком тела. Здесь закреплено только одно: судят по последней
    публикации, а не по первой.
    """
    из = МОД.порядок([
        _соб("d", "s", "publish", "2026-10-20T01:00:00Z"),
        _соб("d", "s", "review", "2026-10-20T00:30:00Z"),
        _соб("d", "s", "publish", "2026-10-25T01:00:00Z"),
    ])
    assert len(из["строки"]) == 1
    assert из["строки"][0]["опубликован"] == "2026-10-25T01:00:00Z"


def test_рецензия_другого_материала_не_зачитывается():
    из = МОД.порядок([
        _соб("d", "s1", "publish", "2026-10-25T01:00:00Z"),
        _соб("d", "s2", "review", "2026-10-25T00:30:00Z"),
    ])
    assert из["строки"][0]["исход"] == "рецензии нет вовсе"


def test_рецензия_того_же_слага_на_другом_домене_не_зачитывается():
    """Один слаг живёт на нескольких витринах — это разные материалы."""
    из = МОД.порядок([
        _соб("d1", "s", "publish", "2026-10-25T01:00:00Z"),
        _соб("d2", "s", "review", "2026-10-25T00:30:00Z"),
    ])
    по_домену = {з["домен"]: з["исход"] for з in из["строки"]}
    assert по_домену["d1"] == "рецензии нет вовсе"


def test_окно_отсекает_прежние_публикации():
    с = dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=1)
    из = МОД.порядок([
        _соб("d", "старый", "publish", "2026-01-01T00:00:00Z"),
        _соб("d", "новый", "publish",
             dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")),
    ], с)
    assert [з["slug"] for з in из["строки"]] == ["новый"]


def test_строка_без_времени_не_ломает_меру():
    из = МОД.порядок([
        {"домен": "d", "slug": "s", "op": "publish", "at": "мусор"},
        _соб("d", "s2", "publish", "2026-10-25T01:00:00Z"),
    ])
    assert len(из["строки"]) == 1


def test_нет_журналов_это_не_измерено(capsys):
    код = МОД.главное(["--logs", "/нет/такого/*.jsonl"])
    assert код == 2
    assert "НЕ ИЗМЕРЕНО" in capsys.readouterr().err
