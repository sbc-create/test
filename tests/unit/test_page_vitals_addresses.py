"""Замер витали берёт адреса из ДАННЫХ витрины и различает произведения и серии.

Повод измеренный, 23.10: на страницах серий элемент LCP — текст (`H1`), а на
страницах произведений — обложка. Решение «работать над обложками» зависит от
того, какие страницы попали в выборку, поэтому путаница «произведение против
серии» тихо изменила бы вывод.

Второй повод: у Animedia серий в карте сайта нет вовсе (их включение —
решение витрины, MOD-79). Инструмент тогда берёт адреса серий со страницы
произведения, и это по-прежнему данные витрины, а не придуманный адрес.

Проверяется чистая функция определения вида по пути: сеть и браузер не нужны.
"""
from __future__ import annotations

import importlib.util
import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "page-vitals-probe.py"

_с = importlib.util.spec_from_file_location("page_vitals_probe", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(МОДУЛЬ)

#: Тот же признак, которым инструмент делит выборку в `main`.
ПРИЗНАК_СЕРИИ = r"/(season|episode)[-/]"


def вид(путь: str) -> str:
    return "серия" if re.search(ПРИЗНАК_СЕРИИ, путь) else "произведение"


def test_серии_двух_семейств_узнаются():
    """Lords и Animedia пишут серию как `/season-1/episode-2/`, Yummy — как
    `/season/1/episode/2`. Признак обязан ловить оба написания."""
    assert вид("https://animedia.icu/title/009-1/season-1/episode-1/") == "серия"
    assert вид("https://yummyani.site/anime/pokemon-1997/season/3") == "серия"
    assert вид("/title/x/season-12/episode-240/") == "серия"


def test_страница_произведения_не_путается_с_серией():
    assert вид("https://animedia.icu/title/009-1/") == "произведение"
    assert вид("https://yummyani.site/anime/korosiya-san-naemnik") == "произведение"
    # Слово «season» внутри слуга не делает страницу серией.
    assert вид("/title/seasons-of-love/") == "произведение"


def test_адрес_берётся_из_данных_витрины_а_не_придумывается():
    """Инструмент читает карту сайта и страницу произведения. Проверяю, что в
    его тексте нет готовых адресов страниц: придуманный адрес в CLOSED_WORLD
    запрещён, и один такой «пример» в коде стал бы источником замеров ни о
    чём."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    # Разрешено собирать адрес из домена и пути, но не хранить готовые
    # адреса страниц произведений или серий.
    подозрительные = re.findall(r"https://[a-z0-9.-]+/(?:title|anime)/[a-z0-9-]+",
                                текст)
    assert not подозрительные, подозрительные


def test_окно_телефона_объявлено_с_плотностью():
    """Решение об избытке зависит от произведения ширины на плотность, и
    замер без плотности отвечал бы на другой вопрос."""
    ширина, высота, плотность = МОДУЛЬ.ОКНО_ТЕЛЕФОНА
    assert (ширина, высота) == (390, 844)
    assert плотность == 3
