"""REQ-FLEET-LABELS: подробности витрины подписаны словами, а не именами полей.

В карточке стояли имена полей как есть, и читались они как названия того, что
показано. Одно из них читалось неверно и приводило к неверному решению:
`templateDigest` — это отпечаток артефакта, тарбола, собранного со всего дерева
ревизии. Любая правка теста или отчёта его меняет, не тронув ни одного
шаблонного файла; две одинаково отрисованные витрины показывают разное, и
оператор начинает выкат, который не изменит ни одной страницы.
"""

from __future__ import annotations

from factory.site_engine.admin import ui


def карточка(поля: dict) -> str:
    записи = [{"siteId": "s-1", "fields": поля}]
    return ui.control_center(записи, {}, flash=None, session_label="стенд", csrf="c")


class TestПодписи:
    def test_имена_полей_не_показываются_как_подписи(self):
        html = карточка({})
        for имя in ("templateDigest", "rendererRevision", "contentSnapshotId"):
            assert f"<dt>{имя}</dt>" not in html, f"поле {имя} подписано именем поля"

    def test_отпечаток_подписан_как_отпечаток_артефакта(self):
        html = карточка({})
        assert "Отпечаток артефакта шаблона" in html, (
            "подпись не говорит, что это отпечаток артефакта, — "
            "и читается как ответ на вопрос «чем отрисован сайт»")

    def test_подписаны_все_показываемые_поля(self):
        html = карточка({})
        for подпись in ui.ПОДПИСИ_ПОДРОБНОСТЕЙ.values():
            assert f"<dt>{подпись}</dt>" in html, f"подпись «{подпись}» не показана"

    def test_значение_поля_остаётся_на_своём_месте(self):
        поле = {"value": "abc123", "state": "CONNECTED",
                "source": "release-manifest", "observedAt": "", "reason": ""}
        html = карточка({"templateDigest": поле})
        assert "abc123" in html, "подпись подменила значение"
