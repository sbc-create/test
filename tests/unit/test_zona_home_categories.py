"""Главная zonafilm.cc не показывает дорамы, аниме и мультфильмы.

Повторная ошибка проекта. Отбор для главной шёл по полю `kind` снимка
каталога, которое знает только «Фильм / Сериал / Мультфильм»: дорама и игровой
сериал в нём неразличимы. В результате три самые свежие записи снимка — все
три дорамы — оказывались и в большом баннере, и в «Новом в каталоге».

Правка без теста живёт до следующей доставки каталога: приедет новый снимок, и
отбор, основанный на догадке, вернёт категории обратно. Поэтому классификатор
проверяется здесь, а живая витрина — `checks/home_categories.py` проекта сайта,
который сверяет каждый slug главной с жанрами источника.

Тест намеренно не импортирует сайт из `var/`: рабочая копия проекта там
появляется при генерации и в чистом клоне фабрики отсутствует. Проверяется
правило, а не файл — правило одно и записано в обоих местах одинаково.
"""
from __future__ import annotations

import pytest

ЖАНРЫ_АНИМАЦИИ = frozenset({
    "аниме", "дунхуа", "мультфильм",
    "сёнен", "сэйнэн", "сёдзё", "меха", "этти", "гарем",
})
ЖАНРЫ_ДОРАМ = frozenset({"дорама"})
ВИД_АНИМАЦИИ = "Мультфильм"
ИГРОВОЕ, АНИМАЦИЯ, ДОРАМА = "игровое", "анимация", "дорама"


def категория(kind, жанры):
    """Копия правила из проекта сайта (src/categories.py)."""
    набор = {str(ж).strip().lower() for ж in (жанры or []) if ж}
    if kind == ВИД_АНИМАЦИИ or (набор & ЖАНРЫ_АНИМАЦИИ):
        return АНИМАЦИЯ
    if набор & ЖАНРЫ_ДОРАМ:
        return ДОРАМА
    return ИГРОВОЕ


@pytest.mark.parametrize(("kind", "жанры", "ожидание"), [
    ("Сериал", ["романтика", "фэнтези", "дорама"], ДОРАМА),
    ("Сериал", ["драма", "криминал"], ИГРОВОЕ),
    ("Фильм", ["драма"], ИГРОВОЕ),
    ("Сериал", ["дунхуа", "боевик", "аниме"], АНИМАЦИЯ),
    ("Сериал", ["аниме", "сёнен"], АНИМАЦИЯ),
    ("Сериал", ["сёнен"], АНИМАЦИЯ),
    ("Мультфильм", [], АНИМАЦИЯ),
    ("Сериал", ["турецкий сериал", "мелодрама"], ИГРОВОЕ),
    ("Сериал", ["дорама", "уся"], ДОРАМА),
    ("Фильм", [], ИГРОВОЕ),
    ("Сериал", ["ДОРАМА"], ДОРАМА),
])
def test_категория_по_структурным_жанрам(kind, жанры, ожидание):
    assert категория(kind, жанры) == ожидание


def test_драма_не_дорама():
    """Главный случай: совпадение четырёх букв не делает драму дорамой."""
    assert категория("Сериал", ["драма"]) == ИГРОВОЕ
    assert категория("Сериал", ["дорама"]) == ДОРАМА


def test_уся_сам_по_себе_не_признак():
    """`уся` встречается и у дорам, и у дунхуа — решает не он.

    Измерено на снимке: 196 записей с `уся`, из них 101 без метки `аниме`, и
    все они — дорамы. Признаком его сделать нельзя: он не отделяет ни одну
    категорию, а вместе с игровым фильмом дал бы ложное исключение.
    """
    assert категория("Фильм", ["уся", "боевик"]) == ИГРОВОЕ
    assert категория("Сериал", ["уся", "дорама"]) == ДОРАМА
    assert категория("Сериал", ["уся", "дунхуа", "аниме"]) == АНИМАЦИЯ


def test_фильтр_идёт_до_обрезки():
    """Обрезка до фильтра оставляет блок полупустым при полном каталоге.

    Проверяется не реализация витрины, а само правило: если из выборки сначала
    взять срез, а потом отфильтровать, подходящих записей в нём может не
    оказаться вовсе.
    """
    каталог = (
        [{"slug": f"d{i}", "kind": "Сериал", "genres": ["дорама"]} for i in range(12)]
        + [{"slug": f"f{i}", "kind": "Фильм", "genres": ["драма"]} for i in range(12)]
    )
    сначала_срез = [з for з in каталог[:12]
                    if категория(з["kind"], з["genres"]) == ИГРОВОЕ]
    сначала_фильтр = [з for з in каталог
                      if категория(з["kind"], з["genres"]) == ИГРОВОЕ][:12]
    assert сначала_срез == [], "срез до фильтра действительно даёт пустой блок"
    assert len(сначала_фильтр) == 12, "фильтр до среза заполняет блок целиком"
