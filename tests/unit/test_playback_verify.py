    assert и["исход"] == ИНСТР.ИСТОЧНИК_ОТВЕТИЛ
    assert "показ не начался" in и["почему"]
    # Окно обязано быть названо: «показ не начался» без него читается как
    # «видео нет», а это другое утверждение.
    assert "за 90 с" in и["почему"]
    # Один отрицательный прогон вердиктом не является, и подпись это называет:
    # измерено 20.10 на /title/kiber-protokol/ — два прогона подряд с одним и
    # тем же окном 150 с дали «показ не начался» и «время дошло до 113.8 с».
