"""REQ-PLAYBACK-GRADED: «идёт» отделено от «загрузилось» и от рекламы.

Повод (19–20.10). Прежняя проверка считала показ начавшимся по наличию кадра
плеера и запросов к потоковому хосту, и на этом основании я дважды сделал
неверный вывод о карточках zonafilm12.site. Измерено 20.10 в браузере:

* `chya-eto-sobaka`: ДО нажатия основное видео (4 863 с) уже загружено —
  `readyState` 4, буфер 6.6 с — и стоит на паузе. После нажатия 31 секунду
  идут два рекламных ролика (21 с и 10 с, хост `ds.serving-sys.ru`), и только
  потом время основной дорожки начинает расти;
* `tom-i-cherri`: тот же `readyState` 4 и буфер, но за 60 секунд время
  выросло с 0.093 до 0.107 с — это дрожание, а не показ; `play()` при этом
  отказа не возвращает, плеер просто снова встаёт на паузу.

Отсюда правила, которые здесь и закрепляются: продвижение считается по ДВУМ
соседним замерам и по порогу, короткий ролик не выдаётся за фильм, а
загруженные данные без движения времени — отдельный исход, а не успех.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/playback-verify.py"
_спец = importlib.util.spec_from_file_location("playback_verify", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)


def _медиа(время, длительность, *, пауза=False, готовность=4, буфер=10.0,
           ошибка=None, источник="blob:https://player.test/x"):
    return {"время": время, "длительность": длительность, "пауза": пауза,
            "готовность": готовность, "сеть": 2, "буфер": буфер,
            "ошибка": ошибка, "источник": источник}


# --- основное видео -----------------------------------------------------------

def test_растущее_время_длинной_дорожки_это_показ():
    снимки = [[_медиа(0.1, 4863, пауза=True)],
              [_медиа(2.1, 4863)],
              [_медиа(7.2, 4863)]]
    и = ИНСТР.оценить(снимки)
    assert и["исход"] == ИНСТР.ОСНОВНОЕ_ИДЁТ
    assert "7.2" in и["почему"]


def test_загружено_но_стоит_это_не_показ():
    """Главный отрицательный контроль: ровно состояние `tom-i-cherri`."""
    снимки = [[_медиа(0.093, 7151, пауза=True)],
              [_медиа(0.100, 7151, пауза=True)],
              [_медиа(0.107, 7151, пауза=True)]]
    и = ИНСТР.оценить(снимки)
    assert и["исход"] == ИНСТР.ИСТОЧНИК_ОТВЕТИЛ
    assert "не продвигается" in и["почему"]


def test_предзагрузка_до_нажатия_показом_не_считается():
    """Состояние `chya-eto-sobaka` ДО нажатия: буфер есть, движения нет."""
    снимки = [[_медиа(0.134, 4863, пауза=True, буфер=6.6)]] * 3
    assert ИНСТР.оценить(снимки)["исход"] == ИНСТР.ИСТОЧНИК_ОТВЕТИЛ


def test_дрожание_времени_продвижением_не_считается():
    снимки = [[_медиа(0.09, 7151, пауза=True)],
              [_медиа(0.10, 7151, пауза=True)],
              [_медиа(0.11, 7151, пауза=True)]]
    assert ИНСТР.оценить(снимки)["исход"] != ИНСТР.ОСНОВНОЕ_ИДЁТ


def test_одного_замера_для_показа_мало():
    """Один замер не отличает идущее видео от остановленного на 30-й секунде."""
    assert ИНСТР.оценить([[_медиа(30.0, 4863)]])["исход"] != ИНСТР.ОСНОВНОЕ_ИДЁТ


# --- реклама ------------------------------------------------------------------

def test_идущий_короткий_ролик_это_реклама():
    снимки = [[_медиа(0.1, 4863, пауза=True), _медиа(2.4, 21, источник="https://ds.serving-sys.ru/a")],
              [_медиа(0.1, 4863, пауза=True), _медиа(7.4, 21, источник="https://ds.serving-sys.ru/a")]]
    и = ИНСТР.оценить(снимки)
    assert и["исход"] == ИНСТР.РЕКЛАМА_ИДЁТ
    assert "основное стоит" in и["почему"]


def test_идущее_основное_важнее_идущей_рекламы():
    """Если основное пошло, исход про него, а не про ролик."""
    снимки = [[_медиа(0.1, 4863, пауза=True), _медиа(2.0, 21)],
              [_медиа(5.0, 4863), _медиа(7.0, 21)]]
    assert ИНСТР.оценить(снимки)["исход"] == ИНСТР.ОСНОВНОЕ_ИДЁТ


def test_порог_длительности_назван_числом():
    assert ИНСТР.ДЛИННОЕ_ВИДЕО_С == 180
    assert ИНСТР.ШАГ_ПРОДВИЖЕНИЯ_С == 0.5


# --- отсутствие и ошибки ------------------------------------------------------

def test_без_медиаэлементов_плеера_нет():
    assert ИНСТР.оценить([[], [], []])["исход"] == ИНСТР.ПЛЕЕРА_НЕТ


def test_элемент_без_данных_это_плеер_загружен():
    снимки = [[_медиа(0, None, пауза=True, готовность=0, буфер=0)]] * 2
    assert ИНСТР.оценить(снимки)["исход"] == ИНСТР.ПЛЕЕР_ЗАГРУЖЕН


def test_ошибка_медиа_называется_кодом():
    снимки = [[_медиа(0, 4863, пауза=True, ошибка=4)]] * 2
    и = ИНСТР.оценить(снимки)
    assert и["исход"] == ИНСТР.ОШИБКА and "4" in и["почему"]


def test_недоступное_состояние_это_не_измерено():
    """Закрытый кадр — третий исход, а не «не идёт»."""
    и = ИНСТР.оценить(None)
    assert и["исход"] == ИНСТР.НЕ_ИЗМЕРЕНО


def test_отказ_play_превращается_в_ошибку():
    снимки = [[_медиа(0.1, 4863, пауза=True)]] * 2
    и = ИНСТР.оценить(снимки, отказ_play="NotAllowedError: gesture required")
    assert и["исход"] == ИНСТР.ОШИБКА and "NotAllowedError" in и["почему"]
