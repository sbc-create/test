# --- срыв по одному адресу не хоронит остальные -------------------------------
#
# Измерено 20.10: таймаут `Page.goto` на zonafilm.cc/title/40-dney-2/ вылетал из
# функции и обрывал весь список — две следующие карточки остались
# непроверенными. Навигация теперь отделена от замеров, и её срыв — «не
# измерено» ПО ЭТОМУ адресу.

def test_не_измеренный_адрес_не_прерывает_список(monkeypatch, capsys):
    исходы = {"a": ИНСТР.НЕ_ИЗМЕРЕНО, "b": ИНСТР.ОСНОВНОЕ_ИДЁТ}

    def проверить(адрес, **_):
        слаг = адрес.rstrip("/").rsplit("/", 1)[-1]
        return {"адрес": адрес, "исход": исходы[слаг], "код": 200,
                "нажатие": True, "замеров": 0 if слаг == "a" else 3,
                "почему": "навигация не завершилась" if слаг == "a" else ""}

    monkeypatch.setattr(ИНСТР, "проверить", проверить)
    код = ИНСТР.main(["--url", "https://x/title/a/", "--url", "https://x/title/b/"])
    вывод = capsys.readouterr().out
    assert "title/a" in вывод and "title/b" in вывод
    assert "навигация не завершилась" in вывод
    assert код == 2


def test_все_адреса_не_измерены_тоже_код_2(monkeypatch):
    monkeypatch.setattr(ИНСТР, "проверить", lambda адрес, **_: {
        "адрес": адрес, "исход": ИНСТР.НЕ_ИЗМЕРЕНО, "почему": "кадр не читается"})
    assert ИНСТР.main(["--url", "https://x/title/a/"]) == 2

