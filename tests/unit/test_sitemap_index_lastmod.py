"""Дата части в индексе карты берётся из СОДЕРЖИМОГО части.

Повод измерен 20.10 на 12 витринах сети (Lords 4, Zona 3, Animedia 2,
Animego 3): `<lastmod>` у вложенных карт не было ВОВСЕ. Обходчик читает
`/sitemap.xml` первым и по дате каждой части решает, перезапрашивать ли файл на
45 000 адресов; без даты решать нечем (MOD-111).

Отрицательные контроли, названные заранее, и каждый отвергает худшую правку:

* ВРЕМЯ СБОРКИ НЕ ПОДСТАВЛЯЕТСЯ. Это было бы хуже отсутствия даты: обходчик
  поверил бы, что часть обновилась, и перечитал бы 45 000 адресов, в которых
  ничего не изменилось. Дата берётся из записей внутри части;
* у части постарше дата законно СТАРАЯ и обязана остаться старой. Измерено:
  у Lords и Zona свежайшая запись во второй части от июня 2025 при первой от
  2026-10-20, потому что адреса делятся по порядку;
* если внутри части нет ни одной даты, `lastmod` НЕ ставится. Пустая дата и
  выдуманная «сегодня» обе врут, отсутствие честно;
* число адресов в частях и их состав правка не меняет.
"""
from __future__ import annotations

import importlib.util
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "host" / "seo_layer.py"
_с = importlib.util.spec_from_file_location("seo_layer_lastmod", ПУТЬ)
СЛОЙ = importlib.util.module_from_spec(_с)
sys.modules.setdefault("seo_layer", СЛОЙ)
_с.loader.exec_module(СЛОЙ)

NS = "{http://www.sitemaps.org/schemas/sitemap/0.9}"


def _собрать(страницы, разделы=()):
    файлы = dict(СЛОЙ.построить_sitemap("x.site", страницы, разделы))
    индекс = ET.fromstring(файлы["sitemap.xml"])
    итог = []
    for s in индекс.findall(f"{NS}sitemap"):
        loc = s.findtext(f"{NS}loc")
        lm = s.findtext(f"{NS}lastmod")
        итог.append((loc.rsplit("/", 1)[-1], lm))
    return файлы, итог


def test_дата_части_равна_максимуму_внутри():
    """Главный признак: прежде `lastmod` в индексе не было вовсе."""
    _, части = _собрать([
        {"url": "/title/a/", "lastmod": "2026-10-01"},
        {"url": "/title/b/", "lastmod": "2026-10-20"},
        {"url": "/title/c/", "lastmod": "2026-09-15"},
    ])
    assert части == [("sitemap-1.xml", "2026-10-20")], части


def test_старая_часть_остаётся_старой():
    """Отрицательный контроль: деление по порядку даёт старую вторую часть.

    Подстановка свежей даты второй части была бы ложью: у Lords и Zona
    свежайшая запись там от июня 2025, и это законно.
    """
    старые = [{"url": f"/title/old{н}/", "lastmod": "2025-06-11"}
              for н in range(СЛОЙ.ПРЕДЕЛ_URL)]
    новые = [{"url": "/title/new/", "lastmod": "2026-10-20"}]
    _, части = _собрать(старые + новые)
    assert len(части) == 2, части
    assert части[0][1] == "2025-06-11"
    assert части[1][1] == "2026-10-20"


def test_без_дат_внутри_lastmod_не_ставится():
    """Пустая дата и выдуманная «сегодня» обе врут; отсутствие честно."""
    _, части = _собрать([{"url": "/title/a/"}, {"url": "/title/b/"}])
    assert части == [("sitemap-1.xml", None)], части


def test_часть_с_одной_датой_её_и_получает():
    _, части = _собрать([{"url": "/title/a/"},
                         {"url": "/title/b/", "lastmod": "2026-07-04"}])
    assert части[0][1] == "2026-07-04"


def test_разделы_без_даты_не_обнуляют_дату_части():
    """Раздел добавляется с пустой датой — она не должна вытеснить настоящую."""
    _, части = _собрать([{"url": "/title/a/", "lastmod": "2026-10-20"}],
                        разделы=["/catalog/"])
    assert части[0][1] == "2026-10-20"


def test_состав_и_число_адресов_не_изменились():
    """Отрицательный контроль: правка индекса не трогает сами части."""
    страницы = [{"url": f"/title/t{н}/", "lastmod": "2026-10-20"}
                for н in range(5)]
    файлы, части = _собрать(страницы, разделы=["/catalog/", "/new/"])
    часть = ET.fromstring(файлы["sitemap-1.xml"])
    адреса = [u.findtext(f"{NS}loc") for u in часть.findall(f"{NS}url")]
    assert len(адреса) == 7, адреса
    assert адреса[0] == "https://x.site/catalog/"
    assert "https://x.site/title/t4/" in адреса


def test_пустой_набор_даёт_одну_часть_без_даты():
    файлы, части = _собрать([])
    assert части == [("sitemap-1.xml", None)]
    assert "sitemap-1.xml" in файлы


def test_в_индексе_нет_лишних_узлов():
    _, части = _собрать([{"url": "/title/a/", "lastmod": "2026-10-20"}])
    assert len(части) == 1
    индекс = ET.fromstring(dict(СЛОЙ.построить_sitemap(
        "x.site", [{"url": "/title/a/", "lastmod": "2026-10-20"}]))["sitemap.xml"])
    s = индекс.find(f"{NS}sitemap")
    assert [э.tag for э in s] == [f"{NS}loc", f"{NS}lastmod"]
