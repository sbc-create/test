    assert "стало < было" in тело
    assert "понижение=True" in тело
    # Наложение на снимок никогда не понижает: там только недостача.
    нач2 = текст.index("def _наложить_на_снимок")
    кон2 = текст.index("def применить_наложение")
    assert ">= подтверждение[\"avail\"]" in текст[нач2:кон2]


