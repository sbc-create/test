def test_понижение_принимается_только_от_прямого_ответа():
    """Дефект: снятие уже работавшей ссылки по УСТАРЕВШЕМУ снимку.

    Прежде здесь стояло безусловное «число только растёт». Это было неверным
    упрощением: отзыв прав и снятие потока — настоящие события, и ссылка на
    снятую серию ведёт на страницу, где нечего смотреть. Разделено по
    источнику: понижение от прямого ответа поставщика принимается,
    понижение от доставленного снимка — нет, потому что снимок бывает
    старше нашего опроса.
    """
    текст = ОБНОВЛЕНИЕ.read_text(encoding="utf-8")
    нач = текст.index("def шаг_свежести")
    кон = текст.index("def шаг_серий")
