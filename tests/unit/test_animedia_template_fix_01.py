# --- свежесть серий (ANIMEDIA-EPISODE-FRESHNESS-01) ---------------------------

ОБНОВЛЕНИЕ = ROOT / "automation/host/animedia-data-update.py"


def test_продолжающиеся_спрашиваются_у_первичного_источника():
    """Дефект: новая серия ждала недельный TTL общего кэша подробностей.

    Кэш подробностей живёт семь суток при бюджете 6000 записей в сутки на
    53688 — примерно раз в девять суток на запись. Блок «Новые серии» стоял
    при зелёном таймере и нуле ошибок.
    """
    текст = ОБНОВЛЕНИЕ.read_text(encoding="utf-8")
    assert "def шаг_свежести" in текст
    assert "public-api.cdnvideohub.com" in текст
    # Спрашиваются только продолжающиеся, и опрос ограничен.
    assert "ПРЕДЕЛ_ОПРОСА" in текст
    assert "freshness" in текст


def test_шаг_свежести_не_пишет_событий_сам():
    """Дефект: второй путь записи в реестр разошёлся бы с первым.

    Событие делает обычное сравнение снимков — тогда у восстановленной серии
    тот же ключ, порядок и семантика времени, что у обычной.
    """
    текст = ОБНОВЛЕНИЕ.read_text(encoding="utf-8")
    нач = текст.index("def шаг_свежести")
    кон = текст.index("def шаг_серий")
    тело = текст[нач:кон]
    for запрещено in ("episode-events", "event_id", "first_seen_at"):
        assert запрещено not in тело, запрещено


