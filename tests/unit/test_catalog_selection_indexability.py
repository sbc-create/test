def test_дубль_каталога_не_требует_совпадения_h1(сеть):
    """Моя ошибка признака: подпись различалась, и настоящий дубль проходил.

    Измерено 21.10: `/catalog/?genre=anime` на animedia отдаёт тот же набор,
    что каталог без условий (48 из 48 и 58 из 58 на второй странице), а `h1`
    у них разные — «Аниме» против «Весь каталог».
    """
    _база(сеть, фасеты=("genre=anime",), карточек=3)
    сеть["https://x.test/catalog/?genre=anime"] = страница(
        карточек=3, canonical="https://x.test/catalog/?genre=anime",
        h1="Аниме")
    сеть["https://x.test/catalog/?page=2"] = страница(карточек=2, первая=50)
    сеть["https://x.test/catalog/?genre=anime&page=2"] = страница(
        карточек=2, первая=50)
    итог = ИНС.проверить("x.test")
    формы = {ф["форма"]: ф["итог"] for ф in итог["формы"]}
    assert формы["одиночный genre"] == "ДУБЛЬ КАТАЛОГА"


def test_совпадение_только_первой_страницы_дублем_не_считается(сеть):
    """У преобладающего жанра первая страница может совпасть случайно."""
    _база(сеть, фасеты=("genre=drama",), карточек=3)
    сеть["https://x.test/catalog/?genre=drama"] = страница(
        карточек=3, canonical="https://x.test/catalog/?genre=drama", h1="Драма")
    сеть["https://x.test/catalog/?page=2"] = страница(карточек=2, первая=50)
    сеть["https://x.test/catalog/?genre=drama&page=2"] = страница(
        карточек=2, первая=80)
    итог = ИНС.проверить("x.test")
    формы = {ф["форма"]: ф["итог"] for ф in итог["формы"]}
    assert формы["одиночный genre"] == "совпал первой страницей, дальше различается"
    assert итог["находки"] == []


