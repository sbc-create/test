"""Состав рантайма шаблона против того, что рантайм ИМПОРТИРУЕТ.

Зачем эта проверка появилась
----------------------------

Генератор нового сайта (`factory/cell/newsite.py`) копирует в проект ровно то,
что перечислено в `РАНТАЙМ_LORDS`. Прежние проверки сверяли список сам с собой:
что каждый названный файл существует и что журнал версий называет тот же
состав. Ни одна не спрашивала главного — не импортирует ли рантайм модуль,
которого в списке нет.

Именно это и случилось. Исправление доступности серий (сентябрь,
`docs/EPISODE_AVAILABILITY.md`) добавило рядом с рантаймом `episode_sync.py` и
импорт этого модуля. До работающих витрин модуль доехал инструментом
наложения, в состав шаблона его не внесли, и генератор честно скопировал семь
файлов из семи. Измерено 2026-10-15 на узле K2: у всех восьми витрин партии
модуля в `src/` нет, у живых витрин семейства есть. Рантайм импортирует его в
`try/except ImportError` и без него тихо возвращается к числу `avail` — то
есть к дефекту, из-за которого карточка обещала серию 1 у записи с
единственной дорожкой «серия 0».

Поэтому правило: КАЖДЫЙ соседний модуль, который рантайм импортирует, обязан
быть либо в составе шаблона, либо в списке поставляемого отдельно с названным
владельцем. `try/except ImportError` в коде — не разрешение не копировать:
он защищает витрину от падения, а не состав шаблона от пропуска.
"""
from __future__ import annotations

import ast
import importlib.util
import re
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ХОСТ = КОРЕНЬ / "automation" / "host"


@pytest.fixture(scope="module")
def newsite():
    """Генератор импортируется по пути: пакет тянет за собой факторные модули."""
    путь = КОРЕНЬ / "factory" / "cell" / "newsite.py"
    спец = importlib.util.spec_from_file_location("_newsite_для_проверки", путь)
    модуль = importlib.util.module_from_spec(спец)
    sys.modules[спец.name] = модуль
    sys.path.insert(0, str(КОРЕНЬ))
    спец.loader.exec_module(модуль)
    return модуль


def соседние_модули() -> set[str]:
    """Имена модулей, которые лежат рядом с рантаймом семейства."""
    return {ф.stem for ф in ХОСТ.glob("*.py")}


def импорты(путь: Path) -> set[str]:
    """Что файл импортирует — по разбору, а не по регулярному выражению.

    Разбор важен: `import episode_sync` встречается внутри функции и внутри
    `try`, и поиск по началу строки его бы пропустил — ровно так пропуск и
    дожил до партии из восьми витрин.
    """
    дерево = ast.parse(путь.read_text(encoding="utf-8"))
    имена: set[str] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            for псевдоним in узел.names:
                имена.add(псевдоним.name.split(".")[0])
        elif isinstance(узел, ast.ImportFrom) and узел.level == 0 and узел.module:
            имена.add(узел.module.split(".")[0])
    return имена


def test_рантайм_не_импортирует_того_чего_генератор_не_копирует(newsite):
    состав = set(newsite.РАНТАЙМ_LORDS)
    отдельно = set(newsite.ПОСТАВЛЯЕТСЯ_ОТДЕЛЬНО)
    соседи = соседние_модули()
    пропуски: dict[str, set[str]] = {}
    for имя in состав:
        файл = ХОСТ / имя
        if not файл.is_file():
            continue
        нужно = {f"{м}.py" for м in импорты(файл) & соседи}
        не_хватает = нужно - состав - отдельно - {имя}
        if не_хватает:
            пропуски[имя] = не_хватает
    assert not пропуски, (
        "рантайм шаблона импортирует модули, которых генератор не копирует и "
        "которые не объявлены поставляемыми отдельно — новый сайт молча "
        f"потеряет их поведение: {пропуски}")


def test_согласование_доступности_входит_в_состав(newsite):
    """Поимённо: это тот самый модуль, которого не было у восьми витрин K2."""
    assert "episode_sync.py" in newsite.РАНТАЙМ_LORDS, (
        "без episode_sync.py доступность серии остаётся одним числом avail, и "
        "карточка снова обещает серию, которой у провайдера нет")


def test_проверка_доступности_ставится_в_новый_проект(newsite):
    источник = ХОСТ / newsite.ИСТОЧНИК_ПРОВЕРКИ_ДОСТУПНОСТИ
    assert источник.is_file(), f"нет источника проверки {источник}"
    тело = источник.read_text(encoding="utf-8")
    for случай in ("skotty", "master-omyur"):
        assert случай in тело, (
            f"проверка доступности потеряла случай {случай}: именно он пришёл "
            "в жалобе, и проверка без него закрывает не тот дефект")


def test_установщик_проверки_вызывается_после_инструментария():
    """Порядок: иначе `checks/run.sh` перезапишут и вызов исчезнет молча."""
    текст = (КОРЕНЬ / "factory" / "cell" / "newsite.py").read_text(encoding="utf-8")
    поз_инструментов = текст.find("add_tooling")
    поз_доступности = текст.find("_записать_проверку_доступности(источник, куда)")
    assert поз_инструментов > 0 and поз_доступности > 0
    assert поз_доступности > поз_инструментов, (
        "проверка доступности ставится раньше инструментария — её вызов в "
        "checks/run.sh будет затёрт, и проверка ни разу не исполнится")


def test_отсутствие_согласования_называется_в_журнале():
    """Молчаливое отсутствие неотличимо от исправности — так и было найдено."""
    текст = (ХОСТ / "lords-frontend.py").read_text(encoding="utf-8")
    м = re.search(r"except ImportError:(.{0,1500}?)if _согласование is not None",
                  текст, re.S)
    assert м, "точка запуска согласования изменилась — проверку надо обновить"
    ветка = м.group(1)
    assert "print(" in ветка and "episode_sync" in ветка, (
        "отсутствие episode_sync.py снова молчит: витрина без согласования "
        "выглядит в журнале так же, как витрина с ним")


def test_созданный_проект_несёт_модуль_и_проверку(newsite, tmp_path):
    """Поведением, а не чтением списка: собирается настоящий проект.

    Список можно прочитать и ошибиться в том, как он применяется, — поэтому
    здесь генератор запускается и его результат осматривается. Ровно так и
    обнаружился пропуск: не чтением кода, а осмотром восьми собранных витрин.
    """
    заказ = newsite.Заказ(
        site_id="probe-avail", domain="probe-avail.test",
        profile="lords-general", port=9998, family="lords",
        site_name="Проба доступности",
        remote="https://example.invalid/probe.git")
    проект = tmp_path / "проект"
    newsite.создать(заказ, корень=КОРЕНЬ, куда=проект,
                    регистрировать=False, допустить_грязное=True)

    модуль = проект / "src" / "episode_sync.py"
    assert модуль.is_file(), (
        "в собранном проекте нет src/episode_sync.py — новая витрина опять "
        "поднимется без согласования доступности серий")
    assert модуль.read_bytes() == (ХОСТ / "episode_sync.py").read_bytes(), (
        "копия модуля разошлась с шаблоном")

    проверка = проект / "checks" / "episode_availability.py"
    assert проверка.is_file(), "в собранном проекте нет checks/episode_availability.py"
    assert проверка.read_bytes() == (
        ХОСТ / newsite.ИСТОЧНИК_ПРОВЕРКИ_ДОСТУПНОСТИ).read_bytes()

    бегунок = (проект / "checks" / "run.sh").read_text(encoding="utf-8")
    assert "checks/episode_availability.py" in бегунок, (
        "проверка лежит в проекте, но не вызывается — такая проверка выпуск "
        "не держит")

    замок = __import__("json").loads(
        (проект / "pins.lock.json").read_text(encoding="utf-8"))
    assert "episode_sync.py" in замок["files"], (
        "модуль скопирован, но не закреплён в pins.lock.json: нечем ответить, "
        "из какой версии шаблона он взят")


