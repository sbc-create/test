"""Имена переменных в сценариях оболочки — только латиницей.

Повторы №9, №10, №11 и №14 в журнале — одна и та же ошибка: оболочка не считает
идентификатором имя из кириллицы. Строка `цель=""` не создаёт переменную, а
выполняется как команда, и вывод выглядит так:

    automation/host/finish-new-site-repo.sh: line 21: цель=: command not found

Дальше сценарий идёт с пустыми значениями и делает не то, что написано. Три раза
ошибку ловила моя же проверка ASCII, запущенная вручную в той же команде, что
писала файл, — то есть защита была ритуалом, а не механизмом. Четвёртый раз я
её не запустил.

Повтор №15 (2026-10-03, `install-mcp-bridge-grant.sh`) добавляет к этому отдельный
урок. Установщик канала MCP упал у ВЛАДЕЛЬЦА на первой же строке кода:

    install-mcp-bridge-grant.sh: line 44: КОРЕНЬ=/home/claude/...: No such file
    or directory

Этот тест к тому моменту уже существовал и на дефектной версии падает
(`строка 56: 'КОРЕНЬ'` — проверено возвратом дефекта). Он не был запущен перед
передачей команды: прогонялся только тест моста. Вывод не «нужна ещё одна
проверка», а «команда владельцу не отдаётся без прогона проверок хостовых
сценариев». Поэтому здесь расширен ОХВАТ (все сценарии репозитория, а не только
`automation/host`) и состав форм, а исполнение самого установщика проверяется в
`test_install_mcp_bridge_grant.py`.

Измерено на bash 5.1.16: кириллическое имя в `ИМЯ=значение` даёт запуск команды
(`rc=127`), в `for ИМЯ in` — `not a valid identifier`, в `${ИМЯ}` — `bad
substitution`, в `export ИМЯ=` — `not a valid identifier`, а `$ИМЯ` без скобок
МОЛЧА раскрывается в литерал `$ИМЯ`. `bash -n` не находит ни одного из этих
случаев: все они синтаксически законны.

Проверяются формы, которые ломаются. Текст сообщений, комментарии, значения,
подстановки по умолчанию (`${var:-нет}`) и содержимое heredoc не
ограничиваются: сценарии проекта пишут по-русски намеренно, а в телах heredoc
лежит python, где unicode-имена законны.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
#: Каталоги, которых проверка не касается: чужой код и кэши.
ПРОПУСК = {".git", ".venv", "node_modules", "__pycache__"}
СЦЕНАРИИ = sorted(п for п in КОРЕНЬ.rglob("*.sh") if ПРОПУСК.isdisjoint(п.parts))

#: Присваивание в начале строки: `name=`, `local name=`, `export name=`,
#: `readonly name=`, а также `for name in` и `read -r name`.
#: Присваивание, включая добавление в массив `name+=(...)`: плюс относится к
#: форме операции, а не к имени, и ловить его как посторонний символ — ошибка
#: проверки, а не сценария.
ПРИСВАИВАНИЕ = re.compile(
    r"^\s*(?:local\s+|export\s+|readonly\s+|declare\s+(?:-\w+\s+)?)?"
    r"([^\s=(){}\[\]]+?)\+?=(?!=)"
)
ЦИКЛ = re.compile(r"^\s*for\s+([^\s]+)\s+in\b")
ЧТЕНИЕ = re.compile(r"^\s*read\s+(?:-\w+\s+)*([^\s<]+)")
ТОЛЬКО_ASCII = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

НЕ_ASCII = r"[^\x00-\x7f]"
#: Имя внутри `${...}` — только `[A-Za-z_0-9]`. Не-ASCII СРАЗУ после имени ломает
#: подстановку; после `:-`, `:?`, `:+`, `#`, `%`, `/` это текст, и он законен.
ПОДСТАНОВКА = re.compile(rf"\$\{{!?#?([A-Za-z_0-9]*{НЕ_ASCII})")
#: `$ИМЯ` без скобок: оболочка молча оставляет литерал — хуже явной ошибки.
#: Внутри класса символов не-ASCII задаётся ДИАПАЗОНОМ: подстановка готового
#: класса `[^\x00-\x7f]` внутрь другого класса даёт вложенные скобки, и правило
#: молча перестаёт срабатывать — поймано самопроверкой ниже.
ГОЛОЕ_ИМЯ = re.compile(r"\$([A-Za-z_]*[^\x00-\x7f][A-Za-z_0-9\x80-\U0010ffff]*)")
#: Начало heredoc в любом месте строки: `cat <<EOF > файл` тоже начинает тело.
#: Ограничитель может быть и не-ASCII — bash такие принимает.
НАЧАЛО_HEREDOC = re.compile(r"<<-?\s*(['\"]?)([^\s'\"<>|&;()]+)\1")


def не_путь(имя: str) -> bool:
    """Отсекает то, что присваиванием не является: пути, флаги, подстановки."""
    return not (имя.startswith(("$", "-", "/", '"', "'", "[")) or "/" in имя)


def находки(текст: str) -> list[str]:
    """Строки с не-ASCII идентификатором оболочки; тела heredoc пропускаются."""
    плохие: list[str] = []
    внутри_heredoc = ""
    for номер, строка in enumerate(текст.splitlines(), 1):
        голая = строка.strip()
        # Тело heredoc — не язык оболочки. Внутри него лежит python, и `for з in`
        # там совершенно законен. Первая версия проверки этого не учитывала и
        # ругалась на встроенный python: проверка, ошибающаяся на правильном
        # коде, заставляет либо портить код, либо отключить проверку.
        if внутри_heredoc:
            if голая == внутри_heredoc:
                внутри_heredoc = ""
            continue
        начало = НАЧАЛО_HEREDOC.search(строка)
        if голая and not голая.startswith("#"):
            for образец in (ПРИСВАИВАНИЕ, ЦИКЛ, ЧТЕНИЕ):
                совпало = образец.match(строка)
                if not совпало:
                    continue
                for имя in совпало.group(1).split(","):
                    имя = имя.strip()
                    # `read -r a b` даёт несколько имён: проверяем все слова строки
                    # только для чтения, у остальных форм имя одно.
                    if имя and not ТОЛЬКО_ASCII.match(имя) and не_путь(имя):
                        плохие.append(f"строка {номер}: {имя!r}")
            for вид, образец in (("${...}", ПОДСТАНОВКА), ("$ИМЯ", ГОЛОЕ_ИМЯ)):
                совпало = образец.search(строка)
                if совпало:
                    плохие.append(f"строка {номер}: {совпало.group(1)!r} ({вид})")
            if голая.startswith("read "):
                for слово in голая.split()[1:]:
                    if слово.startswith("-") or слово.startswith("<"):
                        continue
                    if not ТОЛЬКО_ASCII.match(слово) and не_путь(слово):
                        плохие.append(f"строка {номер}: {слово!r} (read)")
        if начало:
            внутри_heredoc = начало.group(2)
    return плохие


def test_есть_что_проверять() -> None:
    assert len(СЦЕНАРИИ) > 10, f"сценариев найдено {len(СЦЕНАРИИ)} — проверять нечего"
    assert any("automation/host" in str(п) for п in СЦЕНАРИИ)


@pytest.mark.parametrize("сценарий", СЦЕНАРИИ, ids=lambda p: str(p.relative_to(КОРЕНЬ)))
def test_идентификаторы_оболочки_латиницей(сценарий: Path) -> None:
    плохие = находки(сценарий.read_text(encoding="utf-8", errors="replace"))
    assert not плохие, (
        f"{сценарий.name}: имена переменных не латиницей — оболочка выполнит строку "
        "как команду и пойдёт дальше с пустым значением:\n  " + "\n  ".join(плохие))


def test_проверка_ловит_именно_те_формы_которые_ломаются() -> None:
    """Контроль самой проверки: без него зелёный результат ничего не значит."""
    ломается = [
        'КОРЕНЬ="/home/claude/wt-portable-site-cell-01"',   # повтор №15
        'цель=""',                                          # повторы №9-№11, №14
        'for К in a b; do echo "$К"; done',
        'echo "${ЦЕЛЬ}"',
        'export ИМЯ=1',
        'echo "$ДОМЕН"',
    ]
    for строка in ломается:
        assert находки(строка), f"не поймано: {строка}"

    законно = [
        'ROOT_DIR="/home/claude/wt-portable-site-cell-01"',
        'echo "${live_sha:-нет файла}"',          # текст по умолчанию
        'echo "путь: ${ROOT_DIR}"',               # русский текст рядом с именем
        ': "${1:?нужен размер staging в КБ}"',
        '# КОРЕНЬ="/x" — это комментарий',
        'printf "ячеек: %s\\n" "$count"',
        'names+=("$domain")',
    ]
    for строка in законно:
        assert not находки(строка), f"ложное срабатывание: {строка}"


def test_тело_heredoc_не_проверяется_а_код_после_него_снова_проверяется() -> None:
    # В телах heredoc лежит python: там unicode-имена законны.
    тело = "python3 - <<'PY'\nпуть = \"/x\"\nfor я in [1]: print(я)\nPY\necho конец\n"
    assert not находки(тело), находки(тело)
    # Heredoc, начатый не в конце строки, тоже открывает тело. Имя переменной
    # в самой этой строке — код оболочки, и оно остаётся под проверкой.
    середина = 'cat <<EOF > "$target_file"\nДОМ=/x\nEOF\n'
    assert not находки(середина), находки(середина)
    # …но после ограничителя проверка возобновляется.
    после = "cat <<EOF\nтекст\nEOF\nДОМ=\"/var/lib/x\"\n"
    assert находки(после) == ["строка 4: 'ДОМ'"], находки(после)
