"""Имена переменных в хостовых сценариях — только латиницей.

Повторы №9, №10, №11 и №14 в журнале — одна и та же ошибка: оболочка не считает
идентификатором имя из кириллицы. Строка `цель=""` не создаёт переменную, а
выполняется как команда, и вывод выглядит так:

    automation/host/finish-new-site-repo.sh: line 21: цель=: command not found

Дальше сценарий идёт с пустыми значениями и делает не то, что написано. Три раза
ошибку ловила моя же проверка ASCII, запущенная вручную в той же команде, что
писала файл, — то есть защита была ритуалом, а не механизмом. Четвёртый раз я
её не запустил.

Проверяется присваивание в начале строки — та форма, которая ломается. Текст
сообщений, комментарии и содержимое строк не ограничиваются: сценарии проекта
пишут по-русски намеренно.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИИ = sorted((КОРЕНЬ / "automation" / "host").glob("*.sh"))

#: Присваивание в начале строки: `name=`, `local name=`, `export name=`,
#: `readonly name=`, а также `for name in` и `read -r name`.
#: Присваивание, включая добавление в массив `name+=(...)`: плюс относится к
#: форме операции, а не к имени, и ловить его как посторонний символ — ошибка
#: проверки, а не сценария.
ПРИСВАИВАНИЕ = re.compile(
    r"^\s*(?:local\s+|export\s+|readonly\s+|declare\s+(?:-\w+\s+)?)?"
    r"([^\s=(){}\[\]]+?)\+?=(?!=)"
)
ЦИКЛ = re.compile(r"^\s*for\s+([^\s]+)\s+in\b")
ЧТЕНИЕ = re.compile(r"^\s*read\s+(?:-\w+\s+)*([^\s<]+)")
ТОЛЬКО_ASCII = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def test_есть_что_проверять() -> None:
    assert СЦЕНАРИИ, "в automation/host нет ни одного сценария"


@pytest.mark.parametrize("сценарий", СЦЕНАРИИ, ids=lambda p: p.name)
def test_идентификаторы_оболочки_латиницей(сценарий: Path) -> None:
    плохие: list[str] = []
    внутри_heredoc = ""
    for номер, строка in enumerate(сценарий.read_text(encoding="utf-8").splitlines(), 1):
        голая = строка.strip()
        # Тело heredoc — не язык оболочки. Внутри него лежит python, и `for з in`
        # там совершенно законен. Первая версия проверки этого не учитывала и
        # ругалась на встроенный python: проверка, ошибающаяся на правильном
        # коде, заставляет либо портить код, либо отключить проверку.
        if внутри_heredoc:
            if голая == внутри_heredoc:
                внутри_heredoc = ""
            continue
        начало = re.search(r"<<-?'?([A-Za-z_][A-Za-z0-9_]*)'?\s*$", строка)
        if начало:
            внутри_heredoc = начало.group(1)
            continue
        if not голая or голая.startswith("#"):
            continue
        for образец in (ПРИСВАИВАНИЕ, ЦИКЛ, ЧТЕНИЕ):
            совпало = образец.match(строка)
            if not совпало:
                continue
            for имя in совпало.group(1).split(","):
                имя = имя.strip()
                # `read -r a b` даёт несколько имён: проверяем все слова строки
                # только для чтения, у остальных форм имя одно.
                if имя and not ТОЛЬКО_ASCII.match(имя) and не_путь(имя):
                    плохие.append(f"строка {номер}: {имя!r}")
        if голая.startswith("read "):
            for слово in голая.split()[1:]:
                if слово.startswith("-") or слово.startswith("<"):
                    continue
                if not ТОЛЬКО_ASCII.match(слово) and не_путь(слово):
                    плохие.append(f"строка {номер}: {слово!r} (read)")
    assert not плохие, (
        f"{сценарий.name}: имена переменных не латиницей — оболочка выполнит строку "
        "как команду и пойдёт дальше с пустым значением:\n  " + "\n  ".join(плохие))


def не_путь(имя: str) -> bool:
    """Отсекает то, что присваиванием не является: пути, флаги, подстановки."""
    return not (имя.startswith(("$", "-", "/", '"', "'", "[")) or "/" in имя)
