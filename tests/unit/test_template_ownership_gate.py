"""Единственный writer template-release и единственный контракт коллекций.

Зачем нужен машинный gate. Шаблонный релиз одновременно правили три ветки:
PR #69 чинил дефекты слоёв, PR #74 вводил контракт коллекций, PR #76 переписывал
каркас. Файлы `automation/host/lords-frontend.py` и
`factory/lords/collection_contract.py` оказались общими, и любая пара веток
расходилась в тех же строках. Один артефакт при этом обслуживает шесть витрин,
поэтому расхождение стоило бы дороже, чем сам конфликт.

Решение владельца (TEMPLATE-POSTDEPLOY-REMEDIATION-03A): владельцем релиза
назначен PR #76, остальные ветки — только источники. Здесь это решение
проверяется, а не пересказывается: переписка не мешает второму resolver
появиться, а падающий тест мешает.

Проверяется три свойства:

1. владение записано в манифесте и совпадает с фактическим содержимым файлов;
2. контракт коллекций ровно один — и как модуль, и как точка входа;
3. рендерер ровно один.
"""

from __future__ import annotations

import ast
import hashlib
import json
import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
МАНИФЕСТ = КОРЕНЬ / "config" / "TEMPLATE-BASELINE-MANIFEST.json"

#: Каталоги, которые не относятся к исходникам репозитория.
ПРОПУСК = {".git", "node_modules", ".venv", "var", "artifacts", "__pycache__"}


def _исходники(шаблон: str) -> list[Path]:
    найдено = []
    for путь in КОРЕНЬ.rglob(шаблон):
        if any(часть in ПРОПУСК for часть in путь.parts):
            continue
        найдено.append(путь)
    return sorted(найдено)


@pytest.fixture(scope="module")
def владение() -> dict:
    данные = json.loads(МАНИФЕСТ.read_text(encoding="utf-8"))
    assert "ownership" in данные, (
        "манифест без блока ownership не отвечает на вопрос, кто ведёт релиз")
    return данные["ownership"]


def test_канонический_writer_назван_поимённо(владение):
    """Решение владельца записано значениями, а не описанием."""
    assert владение["canonical_pr"] == 76
    assert владение["canonical_head_ref"] == "claude/fleet-tpl-baseline-001"
    assert re.fullmatch(r"[0-9a-f]{40}", владение["canonical_head_sha"])


def test_источники_названы_с_коммитами(владение):
    """У каждого переноса есть PR и точный коммит, иначе провенанс недоказуем."""
    источники = {и["pr"]: и for и in владение["source_prs"]}
    assert set(источники) == {69, 74}, (
        "оба источника обязаны быть названы: контракт коллекций и дефекты слоёв")
    for pr, и in источники.items():
        assert re.fullmatch(r"[0-9a-f]{40}", и["commit"]), f"PR {pr}: неполный коммит"
        assert и["took"], f"PR {pr}: не сказано, что именно перенесено"


def test_дайджесты_владения_совпадают_с_файлами(владение):
    """Запись о владении обязана описывать то, что лежит в дереве сейчас.

    Разошедшийся дайджест означает, что общий файл изменили мимо канонической
    линии — ровно тот случай, ради которого gate и вводится.
    """
    for запись in владение["owned_files"]:
        путь = КОРЕНЬ / запись["path"]
        assert путь.exists(), f"файл владения отсутствует: {запись['path']}"
        фактический = hashlib.sha256(путь.read_bytes()).hexdigest()
        assert фактический == запись["sha256"], (
            f"{запись['path']}: дайджест в манифесте {запись['sha256'][:12]}… "
            f"не совпадает с файлом {фактический[:12]}… — общий файл изменён "
            f"вне канонической линии либо манифест не обновлён")


def test_контракт_коллекций_ровно_один(владение):
    """Второй экземпляр контракта — это второй источник правды о лентах."""
    модули = _исходники("collection_contract*.py")
    assert len(модули) == 1, f"контрактов коллекций больше одного: {модули}"
    assert модули[0] == КОРЕНЬ / "factory" / "lords" / "collection_contract.py"
    assert владение["collection_contract_version"] >= 1


def test_resolver_ровно_один():
    """`разрешить` для коллекций объявлен один раз.

    Сверяется не по имени функции вообще — оно встречается и в разрешении
    адресов, и в SEO-привязках, — а по объявлениям внутри самого контракта.
    """
    контракт = КОРЕНЬ / "factory" / "lords" / "collection_contract.py"
    дерево = ast.parse(контракт.read_text(encoding="utf-8"))
    точки = [у.name for у in дерево.body
             if isinstance(у, ast.FunctionDef | ast.AsyncFunctionDef)
             and у.name == "разрешить"]
    assert len(точки) == 1, f"точек входа resolver больше одной: {точки}"


def test_рендерер_ровно_один():
    """Копия рендерера обслуживала бы часть витрин мимо канонической линии."""
    рендереры = _исходники("lords-frontend*.py")
    assert len(рендереры) == 1, f"рендереров больше одного: {рендереры}"


def test_перекрытый_scope_назван(владение):
    """Сказано, чей именно scope передан, чтобы источники не продолжили правку."""
    текст = " ".join(владение["superseded_scope"])
    assert "#69" in текст and "#74" in текст, (
        "перекрытый scope обязан называть оба исходных PR поимённо")
