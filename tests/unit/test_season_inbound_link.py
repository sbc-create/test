"""Страница сезона обязана иметь входящую внутреннюю ссылку.

Дефект найден 2026-10-26 применением внешнего источника
(SRC-GH-MARKETINGSKILLS, навык `site-architecture`): «every page must have at
least one internal link pointing to it» и «breadcrumbs mirror the URL
hierarchy». Измерено на живой витрине 1lordserials1.online:

* `/title/skotty/season-1/` отдаёт 200, `robots: index, follow`, canonical на
  себя, h1 «Скотты — 1 сезон» и список серий — страница не тонкая;
* ссылок на неё нет НИГДЕ: страница тайтла даёт 8 ссылок на серии и ноль на
  сезоны, страница серии — ноль, а цепочка крошек серии шла
  «Главная → Сериалы → Скотты → 1 сезон, 1 серия», то есть уровень сезона
  отсутствовал.

Класс дефекта общий (`scope: common`): цепочка строилась одинаково в обоих
шаблонах рантайма, lords и zona.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМ = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"
ТЕКСТ = РАНТАЙМ.read_text(encoding="utf-8")


def test_цепочка_серии_несёт_звено_сезона_с_адресом():
    """В обоих шаблонах, а не в одном: иначе семейства разойдутся."""
    образец = re.compile(
        r"звенья = \[\(\"/\", self\.имя\), \(\"/catalog/\?kind=Сериал\", \"Сериалы\"\),\s*"
        r"\(f\"/title/\{запись\['slug'\]\}/\", имя\),\s*"
        r"\(self\.адрес_сезона\(запись\[\"slug\"\], сезон\), f\"\{сезон\} сезон\"\),\s*"
        r"\(\"\", подпись_серии_в_крошках\(эпизод\)\)\]")
    найдено = образец.findall(ТЕКСТ)
    assert len(найдено) == 2, f"цепочек со звеном сезона: {len(найдено)}, ожидалось 2"


def test_последнее_звено_не_повторяет_сезон():
    """Иначе выходит «1 сезон → 1 сезон, 1 серия»."""
    import importlib.util
    сп = importlib.util.spec_from_file_location("lords_frontend_подписи", РАНТАЙМ)
    # Модуль рантайма при импорте поднимает окружение витрины, поэтому берётся
    # только текст функции: проверяется поведение подписи, а не весь рантайм.
    источник = ТЕКСТ[ТЕКСТ.index("def подпись_серии_в_крошках"):]
    источник = источник[:источник.index("\n\n\n")]
    пространство: dict = {"СПЕЦВЫПУСК": 0}
    exec(compile(источник, str(РАНТАЙМ), "exec"), пространство)  # noqa: S102
    подпись = пространство["подпись_серии_в_крошках"]
    assert подпись(1) == "1 серия"
    assert подпись(12) == "12 серия"
    assert подпись(0) == "спецвыпуск — серия 0"
    assert "сезон" not in подпись(1)


def test_длинная_подпись_сохранена_для_заголовка():
    """Заголовок и соседние серии по-прежнему называют сезон целиком."""
    источник = ТЕКСТ[ТЕКСТ.index("def подпись_сезон_серия"):]
    источник = источник[:источник.index("\n\n\n")]
    пространство: dict = {"СПЕЦВЫПУСК": 0}
    exec(compile(источник, str(РАНТАЙМ), "exec"), пространство)  # noqa: S102
    подпись = пространство["подпись_сезон_серия"]
    assert подпись(2, 5) == "2 сезон, 5 серия"
    assert подпись(1, 0) == "1 сезон, спецвыпуск — серия 0"


def test_страница_сезона_по_прежнему_ссылается_вверх():
    """Связь двусторонняя: сезон ссылается на тайтл, тайтл и серии — на сезон."""
    assert ТЕКСТ.count('вернуться к описанию</a>') >= 1
    assert ТЕКСТ.count('Вернуться к </a>') == 0  # опечатка разрыва ссылки
    assert 'Вернуться к ' in ТЕКСТ or 'вернуться к описанию' in ТЕКСТ


# --- Проверка ОТРИСОВКОЙ, а не чтением текста --------------------------------

def _вид(имя_класса: str):
    """Вид витрины с пустыми источниками: крошки от данных не зависят."""
    import importlib.util
    import os
    import sys
    os.environ.setdefault("LORDS_SITE_DOMAIN", "проба.invalid")
    os.environ.setdefault("LORDS_SITE_NAME", "Проба")
    сп = importlib.util.spec_from_file_location("lords_frontend_отрисовка", РАНТАЙМ)
    м = importlib.util.module_from_spec(сп)
    sys.modules["lords_frontend_отрисовка"] = м
    сп.loader.exec_module(м)
    пусто = type("П", (), {"__getattr__": lambda s, и: (lambda *a, **к: None)})
    return м, getattr(м, имя_класса)(семейство="lords", данные=пусто(), подробности=пусто(),
                                     индекс=пусто(), имя_витрины="Проба")


def _цепочка(м, вид):
    return [("/", вид.имя), ("/catalog/?kind=Сериал", "Сериалы"),
            ("/title/skotty/", "Скотты"),
            (вид.адрес_сезона("skotty", 1), "1 сезон"),
            ("", м.подпись_серии_в_крошках(1))]


def test_видимые_крошки_несут_ссылку_на_сезон():
    """Отрисовка, а не текст файла: читатель получает ссылку на страницу сезона."""
    import re
    for имя_класса in ("ВидЛордс", "ВидЗона"):
        м, вид = _вид(имя_класса)
        видимые = вид.крошки(_цепочка(м, вид))
        ссылки = re.findall(r'href="([^"]+)"', видимые)
        на_сезон = [с for с in ссылки if "/season-" in с]
        assert на_сезон == ["/title/skotty/season-1/"], (имя_класса, ссылки)


def test_разметка_крошек_отражает_путь_url():
    """BreadcrumbList обязан повторять путь адреса, включая уровень сезона."""
    import json
    for имя_класса in ("ВидЛордс", "ВидЗона"):
        м, вид = _вид(имя_класса)
        разметка = json.loads(вид.schema_крошек(_цепочка(м, вид)))
        звенья = [(э.get("name"), bool(э.get("item"))) for э in разметка["itemListElement"]]
        assert звенья == [("Проба", True), ("Сериалы", True), ("Скотты", True),
                          ("1 сезон", True), ("1 серия", False)], (имя_класса, звенья)
