def test_ветка_без_данных_не_обещает_состав():
    """Там страница честно говорит «Расписание уточняется». Называть её
    «Онгоингами сезона» значило бы обещать то, чего в этот момент нет."""
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    кусок = текст[текст.index('data-b04="nodata"'):][:600]
    assert "Расписание уточняется" in кусок
    assert "Онгоинги" not in кусок


def test_сезон_в_родительном_падеже(сезон):
    """Сезон стоит в обороте «Онгоинги <чего> 2026». Именительный падеж там
    читается как ошибка — именно так и выглядела живая страница («Онгоинги
    осень 2026»), пока приёмка не назвала это."""
    for месяц in range(1, 13):
        имя, _ = сезон(datetime(2026, месяц, 15, tzinfo=timezone.utc))
        assert имя.endswith(("ы", "а", "и")), (месяц, имя)
        assert имя not in ("зима", "весна", "лето", "осень"), (месяц, имя)


def test_вступление_расписания_короче_измеренной_границы():
    """`.zsub` держит две строки, и на 390 текст длиннее обрезается.

    Границы ИЗМЕРЕНЫ подстановкой на живой странице приёмкой 27.10: при 83
    знаках clientHeight 44 против scrollHeight 65 — хвост «вышедшие серии
    отмечены» скрывался многоточием; при 70 знаках помещается целиком.

    Порог здесь — ПРОКСИ, выведенный из этих двух точек, а не доказательство:
    строки переносятся по словам, и то же число знаков может занять разное
    число строк. Первая версия этого теста требовала «меньше 150», я взял
    число из головы, тест прошёл — и текст в 110 знаков всё равно обрезался.
    Доказывает соответствие только замер отрисованной высоты.
    """
    текст = _текст_рантайма()
    начало = текст.index('<p class="zsub">Выход серий')
    фраза = текст[начало:текст.index("</p>", начало)]
    видимое = "".join(ч for ч in фраза.split("'")
                      if "class=" not in ч and ч.strip() != "f")
    assert "Время московское" in фраза and "отмечены" in фраза, фраза
    assert len(видимое) <= 75, (
        f"фраза {len(видимое)} знаков: измеренная граница — 70 помещается, "
        "83 обрезается")


def test_порог_вступления_назван_прокси():
    """Если следующий читатель примет порог за доказательство, он повторит
    мою ошибку. Поэтому оговорка обязана лежать в самом рантайме."""
    текст = _текст_рантайма()
    кусок = текст[текст.index("ИЗМЕРЕННАЯ граница") - 200:]
    assert "ИЗМЕРЕННАЯ граница" in кусок
    assert "clientHeight 44" in кусок and "scrollHeight 65" in кусок
