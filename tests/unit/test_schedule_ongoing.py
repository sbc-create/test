"""`/schedule/` называет себя страницей онгоингов, и сезон в заголовке считается.

ПОВОД (T339, п. 2). Линия SEO предложила подборку «Онгоинги сезона» и сама же
от неё отказалась, измерив: признаку отвечают 73 названия, и все 73 уже есть
на `/schedule/`. Третий адрес с той же выдачей — это дубль, такой же, как
убранный в этот же день раздел «Этого года».

ПОЧЕМУ СЕЗОН ПРОВЕРЯЕТСЯ ПОМЕСЯЧНО. Он попадает в H1 и в description живой
страницы. Ошибка в одной границе квартала означает, что витрина три месяца
называет сезон неверно, и заметит это посетитель, а не прогон.
"""
from __future__ import annotations

import ast
import pathlib
from datetime import datetime, timedelta, timezone

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМ = (КОРЕНЬ / "var" / "site-repos" / "animedia-icu" / "src"
           / "animedia-frontend.py")


@pytest.fixture(scope="module")
def сезон():
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    дерево = ast.parse(текст, РАНТАЙМ.name)
    узлы = [у for у in ast.walk(дерево)
            if isinstance(у, ast.FunctionDef) and у.name == "_сезон_и_год"]
    assert len(узлы) == 1, f"_сезон_и_год найден {len(узлы)} раз"
    окр = {"datetime": datetime, "timezone": timezone, "timedelta": timedelta,
           "АНИМЕДИА_TZ": timezone(timedelta(hours=3))}
    exec(compile(ast.Module(body=узлы, type_ignores=[]), str(РАНТАЙМ), "exec"), окр)
    return окр["_сезон_и_год"]


#: Правило названо линией SEO: январь–март зима, апрель–июнь весна,
#: июль–сентябрь лето, октябрь–декабрь осень. Декабрь здесь ОСЕНЬ — по этому
#: правилу, а не по тому, как сезон называет аниме-индустрия: витрина
#: объявляет календарный квартал, и расходиться с собственным правилом ради
#: привычки отрасли нельзя. Первая версия этого перечня ставила декабрю зиму
#: и противоречила своему же описанию в заголовке файла.
ОЖИДАНИЕ = {1: "зимы", 2: "зимы", 3: "зимы", 4: "весны", 5: "весны",
            6: "весны", 7: "лета", 8: "лета", 9: "лета", 10: "осени",
            11: "осени", 12: "осени"}


@pytest.mark.parametrize("месяц,имя", sorted(ОЖИДАНИЕ.items()))
def test_сезон_каждого_месяца(сезон, месяц, имя):
    """Границы кварталов названы линией SEO: январь–март зима, апрель–июнь
    весна, июль–сентябрь лето, октябрь–декабрь осень."""
    получено, год = сезон(datetime(2026, месяц, 15, tzinfo=timezone.utc))
    assert получено == имя, (месяц, получено)
    assert год == 2026


def test_границы_кварталов(сезон):
    """Первое и последнее число месяца — там, где ошибка в сравнении видна."""
    assert сезон(datetime(2026, 3, 31, 23, 59, tzinfo=timezone.utc))[0] == "зимы"
    assert сезон(datetime(2026, 4, 1, 0, 0, tzinfo=timezone.utc))[0] == "весны"
    assert сезон(datetime(2026, 9, 30, 23, 59, tzinfo=timezone.utc))[0] == "лета"
    assert сезон(datetime(2026, 10, 1, 0, 0, tzinfo=timezone.utc))[0] == "осени"
    assert сезон(datetime(2026, 12, 31, 23, 59, tzinfo=timezone.utc))[0] == "осени"
    assert сезон(datetime(2027, 1, 1, 0, 0, tzinfo=timezone.utc)) == ("зимы", 2027)


def test_год_берётся_из_даты(сезон):
    assert сезон(datetime(2031, 7, 4, tzinfo=timezone.utc))[1] == 2031


def test_без_аргумента_считает_сам(сезон):
    """На живой странице аргумента нет: функция обязана взять текущее время."""
    имя, год = сезон()
    assert имя in ("зимы", "весны", "лета", "осени")
    assert 2020 < год < 2100


