"""Поиск мест, где отказ не доходит до итога: что инструмент видит и чего нет.

Главное, что закреплено здесь, — НЕ находки, а отсутствие ложных. Инструмент
начинался с признака «вызов команды, которой не существует»: прямой общий
случай находки 12.10. На `automation/` он дал 649 находок, потом 129, 22, 16,
10 — и ни одной настоящей. Признак убран, причина записана в заголовке
инструмента, а класс закрыт поведенчески в `run-sh-guard-audit.py`.

Поэтому проверки ниже требуют тишины там, где её ломал каждый круг уточнений:
тело heredoc, многострочный аргумент в кавычках, апостроф в комментарии, ветвь
`case`.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "silent-failure-audit.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("silent_failure_audit",
                                                  ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    sys.modules["silent_failure_audit"] = м
    спец.loader.exec_module(м)
    return м


ау = _модуль()


def виды(текст: str) -> set[str]:
    return {вид for _, вид, _ in ау.разобрать(текст)}


# ------------------------------------------------------- код из конвейера
def test_код_после_конвейера_без_pipefail_это_находка():
    """`$?` принадлежит последнему звену: отказ первого теряется.

    Я сам дважды за вечер прочитал так код возврата и получил ноль там, где
    команда отказала.
    """
    текст = '#!/bin/bash\nset -u\npython3 что-то.py | tail -5\nесли=$?\n'
    assert ау.КОД_ИЗ_КОНВЕЙЕРА in виды(текст)


def test_с_pipefail_конвейер_находкой_не_считается():
    """Граница: с `pipefail` код конвейера — код первого отказавшего звена."""
    текст = '#!/bin/bash\nset -uo pipefail\npython3 что-то.py | tail -5\nесли=$?\n'
    assert ау.КОД_ИЗ_КОНВЕЙЕРА not in виды(текст)


def test_логическое_или_конвейером_не_считается():
    """`||` — не конвейер, и путать их значило бы кричать на каждом скрипте."""
    текст = '#!/bin/bash\nset -u\nкоманда || эхо\nесли=$?\n'
    assert ау.КОД_ИЗ_КОНВЕЙЕРА not in виды(текст)


# ----------------------------------------------------------- поглощённый отказ
def test_отказ_поглощён_находится():
    assert ау.ОТКАЗ_ПОГЛОЩЁН in виды("#!/bin/sh\nважное-дело || true\n")
    assert ау.ОТКАЗ_ПОГЛОЩЁН in виды("#!/bin/sh\nважное-дело || :\n")


def test_ошибки_в_никуда_находятся():
    assert ау.ОШИБКИ_В_НИКУДА in виды('#!/bin/sh\nдело 2>/dev/null\n')


def test_проверенный_отказ_в_никуда_находкой_не_считается():
    """Код рядом проверен — значит отказ замечен, причина просто не нужна."""
    текст = '#!/bin/sh\nif дело 2>/dev/null; then эхо; fi\n'
    assert ау.ОШИБКИ_В_НИКУДА not in виды(текст)


# ------------------------------------------------------------- без ложных
def test_тело_heredoc_не_разбирается():
    """649 ложных находок первого прогона были ровно этим."""
    текст = """#!/bin/bash
python3 - <<PY
import json
print(json.dumps({}))
PY
"""
    assert виды(текст) == set(), ау.разобрать(текст)


def test_heredoc_с_меткой_в_кавычках_и_отступом():
    текст = """#!/bin/bash
cat <<-'КОНЕЦ'
это данные || true
КОНЕЦ
"""
    # Строка внутри тела не должна дать даже ОТКАЗ_ПОГЛОЩЁН.
    assert виды(текст) == set(), ау.разобрать(текст)


def test_многострочный_аргумент_в_кавычках_не_разбирается():
    """Остаток после heredoc: `sh -c "…"` на десяток строк — ОДНА команда."""
    текст = '''#!/bin/bash
docker exec -i контейнер sh -c "
cat > /tmp/запрос.json
import json, sys
"
'''
    assert виды(текст) == set(), ау.разобрать(текст)


def test_апостроф_в_комментарии_разбор_не_ломает():
    """Один апостроф в английском комментарии ломал разбор ВСЕГО файла.

    Он открывал кавычку, которая не закрывается, и весь учёт ниже сдвигался:
    данные становились «командами», а команды — данными.
    """
    текст = """#!/bin/bash
# Backup of the control host's own state
важное || true
"""
    assert ау.ОТКАЗ_ПОГЛОЩЁН in виды(текст), (
        "после комментария с апострофом разбор сбился")


def test_ветвь_case_командой_не_считается():
    """`deploy) shift; cmd_deploy "$@" ;;` — образец, а не вызов."""
    текст = """#!/bin/bash
case "$1" in
  deploy)   shift; дело ;;
  status)   иное ;;
esac
"""
    assert виды(текст) == set(), ау.разобрать(текст)


def test_живой_прогон_не_падает_и_называет_предел():
    """Инструмент обязан работать на настоящем каталоге."""
    код = ау.главное(["--path", "automation"])
    assert код in (0, 1, 3), код
