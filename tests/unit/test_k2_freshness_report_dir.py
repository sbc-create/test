"""REQ-K2-FRESHNESS-REPORTS: свежесть сверяется со САМЫМ НОВЫМ отчётом.

Измерено 2026-10-18 10:50 UTC: инструмент объявил «УСТАРЕЛО» все восемь
витрин при свежих данных.

    установлено на витринах:        ревизия ab5cd6f7…, 2026-10-18T07:27Z
    отчёт, который он читал:        pub-f4cf3e59a548, 2026-10-17T17:21Z,
                                    ревизия 76475e36…
    отчёт, который он НЕ читал:     pub-d3152f65109d, 2026-10-18T07:23Z,
                                    ревизия ab5cd6f7… ← сходится

Отчёты издателя пишутся в ПОСТОЯННЫЙ каталог доставки, а инструмент смотрел
только в рабочую копию. Та же ошибка была исправлена в сторожевом цикле
(`seo_operator/regular.py: K2_REPORTS`), но сюда не доехала.

Цена ошибки ровно та, которую инструмент сторожит: «устарело» на исправном
состоянии учит не смотреть на его вывод вообще.

Выбор каталога — по ВРЕМЕНИ самого свежего отчёта, а не по наличию: оба
каталога обычно существуют, и брать постоянный всегда значило бы игнорировать
более новый прогон в рабочей копии (например, при отладке издателя).
"""
from __future__ import annotations

import importlib.util
import os
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "k2-freshness.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("k2_freshness", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def _отчёт(каталог: Path, имя: str, время: float) -> Path:
    каталог.mkdir(parents=True, exist_ok=True)
    ф = каталог / имя
    ф.write_text("{}", encoding="utf-8")
    os.utime(ф, (время, время))
    return ф


def test_каталог_без_отчётов_не_считается_свежим(tmp_path):
    пусто = tmp_path / "пусто"
    пусто.mkdir()
    assert МОД._свежесть_каталога(пусто) == 0.0


def test_несуществующий_каталог_не_роняет(tmp_path):
    assert МОД._свежесть_каталога(tmp_path / "нет-такого") == 0.0


def test_берётся_время_самого_свежего_отчёта(tmp_path):
    к = tmp_path / "отчёты"
    _отчёт(к, "pub-старый.json", 1_000_000.0)
    _отчёт(к, "pub-новый.json", 2_000_000.0)
    assert МОД._свежесть_каталога(к) == 2_000_000.0


def test_посторонние_файлы_не_считаются(tmp_path):
    """Отрицательный контроль: считаются только отчёты издателя.

    Иначе любой файл, положенный рядом, делал бы каталог «свежее» и перетянул
    бы выбор на себя.
    """
    к = tmp_path / "отчёты"
    _отчёт(к, "pub-настоящий.json", 1_000_000.0)
    посторонний = к / "README.md"
    посторонний.write_text("не отчёт", encoding="utf-8")
    os.utime(посторонний, (9_000_000.0, 9_000_000.0))
    assert МОД._свежесть_каталога(к) == 1_000_000.0


def test_постоянный_каталог_объявлен_и_не_придуман():
    """Путь тот же, что у сторожевого цикла: расхождение означало бы, что
    два инструмента смотрят в разные места и спорят о состоянии."""
    assert str(МОД.ПОСТОЯННАЯ_ДОСТАВКА) == "/srv/site-factory/k2-delivery"
    сторож = (Path(__file__).resolve().parents[2] / "seo_operator"
              / "regular.py").read_text(encoding="utf-8")
    assert 'K2_DELIVERY_ROOT = Path("/srv/site-factory/k2-delivery")' in сторож


def test_выбор_каталога_по_времени_а_не_по_наличию():
    """В коде сравниваются ВРЕМЕНА обоих каталогов."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "_свежесть_каталога(постоянные) > _свежесть_каталога(отчёты)" in текст
    assert "not отчёты.is_dir()" in текст, (
        "отсутствие рабочего каталога обязано приводить к постоянному")
