"""REQ-ANALYTICS-COMPARABLE: недельные числа сравниваются сопоставимо.

Отчёт недели 11–17.10 сравнивал СУММЫ за периоды с разным числом дней с
данными, вёл столбец «дней 5000+» по чужому периоду и сводил вклад одного
произведения по трём страницам из шести. Каждая ошибка меняет вывод в свою
сторону, поэтому правила сравнения закреплены здесь:

* делитель среднего — число дней С ДАННЫМИ, и он печатается;
* пропущенный день не входит ни в сумму, ни в делитель («пропуск — не ноль»);
* дополнительно считается одинаковое окно (N = минимум делителей);
* дни «5000+» считаются по каждому периоду отдельно;
* вклад группы страниц считается по ВСЕМ её страницам, и их число печатается.

Измерено 2026-10-18: у 12 из 21 домена делители периодов различались; «дней
5000+» в текущем периоде — 0 у всех (день 09.10 принадлежал базовому);
группа «ДжоДжо» — 6 страниц в каждом периоде, 11 475 → 6 534.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "week-recompute.py")


def _модуль():
    имя = "week_recompute"
    спец = importlib.util.spec_from_file_location(имя, ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


МОД = _модуль()
БАЗА = ("2026-10-04", "2026-10-10")
ТЕКУЩИЙ = ("2026-10-11", "2026-10-17")


def _запись(визиты: dict) -> dict:
    return {"daily_human_visits": визиты, "daily_organic_visits_human": визиты}


def test_пропущенный_день_не_ноль():
    """База из двух дней не превращается в семь дней с нулями."""
    с = МОД.свод_домена(_запись({
        "2026-10-09": 2.0, "2026-10-10": 2.0,
        "2026-10-11": 40.0, "2026-10-12": 50.0, "2026-10-13": 60.0,
        "2026-10-14": 40.0, "2026-10-15": 40.0, "2026-10-16": 40.0,
        "2026-10-17": 54.0}), БАЗА, ТЕКУЩИЙ)
    assert с["дней_с_данными"] == {"база": 2, "текущий": 7}
    assert с["в_сутки"]["база"] == 2.0, "делитель — дни с данными, а не 7"
    assert len(с["пропущено"]["база"]) == 5


def test_одинаковое_окно_считается_отдельно():
    """Главное исправление: сумма за 2 дня против суммы за 7 — не сравнение."""
    с = МОД.свод_домена(_запись({
        "2026-10-09": 2.0, "2026-10-10": 2.0,
        "2026-10-11": 10.0, "2026-10-12": 20.0, "2026-10-13": 30.0,
        "2026-10-14": 40.0, "2026-10-15": 50.0, "2026-10-16": 60.0,
        "2026-10-17": 100.0}), БАЗА, ТЕКУЩИЙ)
    окно = с["одинаковое_окно"]
    assert окно["дней"] == 2
    assert окно["база"] == 2.0
    assert окно["текущий"] == 80.0, "последние два дня текущего периода"
    assert окно["изменение"] == 78.0


def test_дни_5000_по_каждому_периоду_отдельно():
    """В отчёте этот столбец нёс день 09.10 — день БАЗОВОГО периода."""
    с = МОД.свод_домена(_запись({
        "2026-10-09": 5597.0, "2026-10-10": 3962.0,
        "2026-10-16": 3963.0, "2026-10-17": 3565.0}), БАЗА, ТЕКУЩИЙ)
    assert с["дней_5000плюс"] == {"база": 1, "текущий": 0}


def test_ровно_порог_считается_достижением():
    с = МОД.свод_домена(_запись({"2026-10-11": 5000.0}), БАЗА, ТЕКУЩИЙ)
    assert с["дней_5000плюс"]["текущий"] == 1
    с2 = МОД.свод_домена(_запись({"2026-10-11": 4999.0}), БАЗА, ТЕКУЩИЙ)
    assert с2["дней_5000плюс"]["текущий"] == 0


def test_пустой_домен_не_даёт_среднего():
    """Ноль дней с данными — это None, а не 0,0: иначе домен без счётчика
    попадёт в таблицу как домен с нулевым трафиком."""
    с = МОД.свод_домена(_запись({}), БАЗА, ТЕКУЩИЙ)
    assert с["в_сутки"] == {"база": None, "текущий": None}
    assert с["одинаковое_окно"]["дней"] == 0


def test_вклад_группы_считает_все_её_страницы():
    """Отчёт свёл произведение по трём страницам, а их шесть."""
    база = [(5889.0, "/anime/dzhodzho-gonka-stalnoy-shar/season-7/episode-1"),
            (3649.0, "/anime/dzhodzho-gonka-stalnoy-shar/season-7/episode-2"),
            (1576.0, "/anime/dzhodzho-gonka-stalnoy-shar/season-7"),
            (342.0, "/anime/dzhodzho-gonka-stalnoy-shar/season-7/episode-3"),
            (3110.0, "/"),
            (127.0, "/anime/vo-vseoruzhii-sila-artefaktov")]
    текущий = [(3596.0, "/anime/dzhodzho-gonka-stalnoy-shar/season-7/episode-4"),
               (905.0, "/anime/dzhodzho-gonka-stalnoy-shar/season-7"),
               (3476.0, "/"),
               (111.0, "/anime/ne-slishkom-li-ty-sladkaya")]
    в = МОД.вклад(база, текущий, "dzhodzho-gonka-stalnoy-shar")
    assert в["страниц_в_группе"] == {"база": 4, "текущий": 2}
    assert в["визиты_группы"] == {"база": 11456, "текущий": 4501}
    assert в["изменение_группы"] == -6955
    assert в["изменение_остального"] == 350
    # Доля считается от общего изменения, включая знак.
    assert в["доля_группы_в_изменении"] == round(
        100 * -6955 / ((4501 + 3587) - (11456 + 3237)), 1)
    assert в["страниц_входа_всего"] == {"база": 6, "текущий": 4}


def test_без_изменения_доля_не_делится_на_ноль():
    один = [(10.0, "/anime/x"), (5.0, "/")]
    в = МОД.вклад(один, один, "/anime/x")
    assert в["изменение_группы"] == 0
    assert в["доля_группы_в_изменении"] is None


def test_правила_названы_в_выводе_инструмента():
    тело = ПУТЬ.read_text(encoding="utf-8")
    for правило in ("пропуск не считается нулём",
                    "одинаковое окно по минимуму делителей",
                    "дни 5000+ по каждому периоду отдельно"):
        assert правило in тело
    assert "фильтры визитов и поиска названы раздельно" in тело, (
        "визиты отфильтрованы от роботов, а разрез поиска — нет; "
        "сравнивать их как однородные нельзя")
