"""Обратная сверка реестра защищённых полей: поле, которого реестр не знает.

Повод. Реестр `config/editorial-protected-fields.json` отвечает на вопрос
«пропало ли внесённое решением»: названное поле исчезло — потеря, код 1. Но
обратного вопроса он не закрывал, а именно так дефект и возник бы снова:

1. поле вносится решением на новой витрине;
2. в реестр его не кладут — забыли, или решение приняла другая сессия;
3. публикация описания его затирает;
4. проверка молчит, потому что защищать было нечего.

Проверено по передаче 114: на 11.10 во всей сети такое поле одно — `name` у
`zonafilm.space` (решение D200), и оно в реестре. То есть реестр полон на
сегодня, и эта сверка сторожит завтрашнее пополнение, а не чинит прошлое.

Коды возврата различают положения, потому что действия разные: 0 — всё на
месте, 1 — ПОТЕРЯ (восстанавливать), 2 — файлов правок нет (смотреть
окружение), 3 — поле вне реестра (вносить в реестр).
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "editorial-overrides-audit.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("overrides_audit", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["overrides_audit"] = м
    спец.loader.exec_module(м)
    return м


def _витрина(имя: str, поля: list[str]) -> dict:
    return {"витрина": имя, "изменён": "2026-10-11T17:08:02Z",
            "правок": len(поля), "схема": 1, "поля": поля,
            "только_описания": поля == ["description"]}


@pytest.fixture
def модуль(monkeypatch):
    м = _модуль()
    monkeypatch.setattr(м, "защищённые", lambda: {
        "zonafilm.space": {"fields": ["name"], "decision": "D200"}})
    return м


def test_описания_в_реестре_не_нуждаются(модуль):
    """Описания пишет сам издатель — защищать их реестром нечего."""
    assert модуль.вне_реестра([_витрина("lordserial33-biz", ["description"])]) == []


def test_известное_поле_не_считается_незащищённым(модуль):
    найдено = [_витрина("zonafilm-space", ["description", "name"])]
    assert модуль.вне_реестра(найдено) == []


def test_поле_которого_реестр_не_знает_называется(модуль):
    """Ровно тот случай, из-за которого потеря прошла бы молча снова."""
    найдено = [_витрина("lordserial33-biz", ["description", "original_name"])]
    (итог,) = модуль.вне_реестра(найдено)
    assert итог["витрина"] == "lordserial33-biz"
    assert итог["поля"] == ["original_name"]


def test_незнакомое_поле_у_витрины_которая_в_реестре(модуль):
    """Реестр знает `name`, а в файле появился ещё и `poster_url`.

    Частичное знание опаснее полного незнания: проверка «защищённые на месте»
    прошла бы, а новое поле осталось бы без защиты.
    """
    найдено = [_витрина("zonafilm-space", ["description", "name", "poster_url"])]
    (итог,) = модуль.вне_реестра(найдено)
    assert итог["поля"] == ["poster_url"]


def test_несколько_полей_перечисляются_по_алфавиту(модуль):
    найдено = [_витрина("zona-x", ["kind", "description", "year"])]
    (итог,) = модуль.вне_реестра(найдено)
    assert итог["поля"] == ["kind", "year"]


def test_имя_витрины_сверяется_по_окончанию_как_в_прямой_сверке(модуль):
    """Путь даёт `zonafilm-space`, реестр — домен `zonafilm.space`."""
    найдено = [_витрина("srv-zonafilm-space", ["description", "name"])]
    assert модуль.вне_реестра(найдено) == []


def test_пустой_реестр_делает_незащищённым_каждое_ручное_поле(monkeypatch):
    """Без реестра защищать нечем — и проверка обязана это сказать."""
    м = _модуль()
    monkeypatch.setattr(м, "защищённые", lambda: {})
    найдено = [_витрина("zonafilm-space", ["description", "name"])]
    (итог,) = м.вне_реестра(найдено)
    assert итог["поля"] == ["name"]


def test_реестр_сети_на_сегодня_полон():
    """Живой реестр против живых файлов правок: незащищённых полей нет.

    Эта проверка ходит по настоящим файлам и потому может упасть при
    появлении нового ручного поля — так и задумано: падение означает
    «внесите поле в реестр», а не ошибку проверки.
    """
    м = _модуль()
    пути = м.файлы()
    if not пути:
        pytest.skip("файлов правок нет в этом окружении")
    найдено = [м.разобрать(п) for п in пути]
    assert м.вне_реестра(найдено) == []


def test_реестр_называет_решение_для_каждого_поля():
    """Поле без решения в реестре — это чьё-то мнение, а не основание."""
    документ = json.loads(
        (КОРЕНЬ / "config" / "editorial-protected-fields.json")
        .read_text(encoding="utf-8"))
    for домен, правило in (документ.get("sites") or {}).items():
        assert правило.get("fields"), домен
        assert правило.get("decision"), домен
