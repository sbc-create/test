"""Приёмка выпуска сверяется с меткой ЭТОГО выпуска, а не с ревизией шаблона.

Повод. Кандидат zona-02 поднялся из нужного коммита и отвечал 200 на обоих
маршрутах, но был откачен с `build_matches: false`. Заголовок
`X-Site-Factory-Build-Id` назвал `zona-02-0fb857b26f85` — ревизию ЗАКРЕПЛЁННОГО
шаблона, которая одинакова у всех выпусков витрины и читается процессом один раз
при старте. Сам исполнитель об этом свойстве заголовка предупреждает в
`написать_release_json`, и всё равно спрашивал сначала его.

Проверяется поведение, а не строка в коде: подставляются те тела ответа, которые
отдают настоящие семейства.
"""
from __future__ import annotations

from pathlib import Path

from factory.cell.privileged import _метка_выпуска

ВЫПУСК = "060149731561-zona-02"
ШАБЛОН = "zona-02-0fb857b26f85"


def test_мета_тег_сильнее_заголовка() -> None:
    тело = (f'<html><head><meta name="site-factory-release-id" content="{ВЫПУСК}">'
            "</head><body>x</body></html>").encode()
    метка, источник = _метка_выпуска(ШАБЛОН, тело)
    assert метка == ВЫПУСК, "взята ревизия шаблона вместо метки выпуска"
    assert источник == "мета-тег"


def test_второе_написание_мета_тега_тоже_читается() -> None:
    """Семейства называют метку по-разному; приёмке важно не имя, а изменчивость."""
    тело = f'<head><meta name="site-factory-build-id" content="{ВЫПУСК}"></head>'.encode()
    assert _метка_выпуска(ШАБЛОН, тело) == (ВЫПУСК, "мета-тег")


def test_без_разметки_остаётся_заголовок_и_он_назван() -> None:
    """Yummy проксирует стороннее приложение: мета-тега нет и быть не может.

    Отказ от заголовка означал бы откат исправного кандидата. Но источник обязан
    быть назван, иначе «сверено по заголовку» читается как «сверено по выпуску».
    """
    метка, источник = _метка_выпуска(ШАБЛОН, b"<html><body>proxied</body></html>")
    assert метка == ШАБЛОН
    assert "заголовок" in источник and "не выпуска" in источник


def test_нет_ни_того_ни_другого() -> None:
    assert _метка_выпуска(None, b"<html></html>") == (None, "нет")


def test_приёмка_зовёт_общий_разбор() -> None:
    """verify() не читает заголовок сам: иначе порядок разошёлся бы снова."""
    текст = Path("factory/cell/privileged.py").read_text(encoding="utf-8")
    начало = текст.index("def verify(")
    конец = текст.index("\ndef ", начало + 1)
    тело_verify = текст[начало:конец]
    assert "_метка_выпуска(" in тело_verify
    assert тело_verify.count("X-Site-Factory-Build-Id") == 1, (
        "verify() снова разбирает заголовок сам, помимо общего разбора")
