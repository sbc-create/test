# --- опора «до»: пишется один раз -----------------------------------------
#
# Повод — свой же брак 22.10 в 06:1xZ: первая редакция писала опору каждым
# прогоном, и прогон `--slugs tristiya,kukolka` затёр закреплённую выборку из
# десяти работ двумя. Приёмка «после» сравнила бы тогда две работы вместо
# десяти и назвала бы это полнотой.

def полный_итог(домен="x.test", исход=None):
    return {"домен": домен, "исход": исход or шлюз.НЕПОЛНО,
            "полнота": {"измерено": True, "адресов_серий": 464,
                        "работ_в_каталоге": 8379, "работ_с_неназванными": 6,
                        "работы": [работа("ок", 1, "a"),
                                   работа("НЕ НАЗВАНЫ", 2, "b")],
                        "проблемы": []},
            "сохранность": сохранность("БЕЗ ИЗМЕНЕНИЙ")}


def test_опора_пишет_слаги_выборки(tmp_path, monkeypatch):
    monkeypatch.setattr(шлюз, "ОПОРА", tmp_path)
    файл = шлюз.записать_опору(полный_итог())
    import json
    з = json.loads(файл.read_text(encoding="utf-8"))
    assert з["слаги_выборки"] == ["a", "b"]
    assert з["адресов_серий_в_карте"] == 464
    assert з["работ_с_неназванными"] == 6


def test_второй_прогон_опору_не_трогает(tmp_path, monkeypatch):
    monkeypatch.setattr(шлюз, "ОПОРА", tmp_path)
    monkeypatch.setattr(шлюз, "проверить",
                        lambda д, п, с=(): полный_итог(д))
    assert шлюз.main(["x.test"]) == 1
    файл = шлюз.путь_опоры("x.test")
    было = файл.read_text(encoding="utf-8")
    # второй прогон с ДРУГОЙ выборкой
    monkeypatch.setattr(
        шлюз, "проверить",
        lambda д, п, с=(): {**полный_итог(д),
                            "полнота": {**полный_итог(д)["полнота"],
                                        "работы": [работа("ок", 1, "одна")]}})
    assert шлюз.main(["x.test", "--slugs", "одна"]) == 1
    assert файл.read_text(encoding="utf-8") == было, "опора затёрта"


