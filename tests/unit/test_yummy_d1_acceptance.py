# --- был ли промежуток различающим ----------------------------------------
#
# Измерено 22.10: между 05:50Z, 06:51Z и 07:03Z у yummyani.site не изменилось
# НИЧЕГО. Прочитать это как «после выпуска ничего не сломалось» было бы
# ошибкой: проверено лишь то, что условие потери не наступало. Дату части у
# этой витрины смотреть бесполезно — она заморожена (MOD-104).

def множество(добавилось=0, исчезло=0, исход="БЕЗ ИЗМЕНЕНИЙ"):
    return {"исход": исход, "было": 100, "стало": 100 + добавилось - исчезло,
            "добавилось": добавилось, "исчезло": исчезло}


def test_ничего_не_менялось_промежуток_не_различающий():
    assert шлюз.промежуток_различающий(множество(), множество()) is False


def test_новый_адрес_серии_доказывает_пересборку():
    assert шлюз.промежуток_различающий(множество(добавилось=5),
                                       множество()) is True


def test_новое_произведение_тоже_доказывает_пересборку():
    """Каталог сменился — значит голова обхода сдвинулась."""
    assert шлюз.промежуток_различающий(множество(),
                                       множество(добавилось=1)) is True


def test_исчезновение_само_является_пересборкой():
    assert шлюз.промежуток_различающий(множество(исчезло=1217),
                                       множество()) is True


def test_первый_снимок_различающим_не_считается():
    """У первого снимка нет ни добавленных, ни исчезших — сравнивать не с чем."""
    первый = {"исход": "ПЕРВЫЙ СНИМОК", "стало": 464}
    assert шлюз.промежуток_различающий(первый, первый) is False

