"""Шлюз приёмки D1: ни одна мера по отдельности его не проходит.

Цена ошибки здесь — принятый выпуск, который дефект не исправил. Поэтому
проверяются не только отказы, но и ГРАНИЦЫ: каждое условие по отдельности
обязано оставить исход неуспешным, а неизмеренное условие не имеет права
выглядеть успехом.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "yummy_d1_acceptance",
    КОРЕНЬ / "automation" / "local" / "yummy-d1-acceptance.py")
шлюз = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(шлюз)


def покрытие(работы, измерено=True):
    return {"домен": "x.test", "измерено": измерено, "работы": работы,
            "проблемы": [], "частей_серий": 1, "адресов_серий": 100,
            "работ_в_каталоге": 8378}


def работа(итог, позиция=1, слаг="w"):
    return {"позиция": позиция, "слаг": слаг, "итог": итог,
            "на_странице": 10, "в_карте": 10, "не_названы": 0, "лишние": 0}


def сохранность(исход, исчезло=0, добавилось=0):
    return {"исход": исход, "было": 100, "стало": 100 - исчезло + добавилось,
            "исчезло": исчезло, "добавилось": добавилось}


# --- оба условия выполнены ------------------------------------------------

def test_полнота_и_сверенный_рост_это_приёмка():
    итог = шлюз.свести(покрытие([работа("ок")]),
                       сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.ПРИНЯТО


def test_лишние_адреса_в_карте_приёмку_не_валят():
    """`лишние` — не дефект: страница может листать серии порциями."""
    итог = шлюз.свести(покрытие([работа("ок, но есть лишние")]),
                       сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.ПРИНЯТО


def test_без_изменений_сохранность_сверена():
    """Ничего не исчезло — условие сохранности выполнено."""
    итог = шлюз.свести(покрытие([работа("ок")]),
                       сохранность("БЕЗ ИЗМЕНЕНИЙ"))
    assert итог == шлюз.ПРИНЯТО


# --- каждое условие по отдельности шлюз не проходит -----------------------

def test_сохранность_без_полноты_не_принимается():
    """Ничего не исчезло, но каталог по-прежнему не назван."""
    итог = шлюз.свести(покрытие([работа("ок"), работа("НЕ НАЗВАНЫ", 2)]),
                       сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.НЕПОЛНО


def test_полнота_без_сохранности_не_принимается():
    """Первый снимок: сравнивать не с чем, и это не успех."""
    итог = шлюз.свести(покрытие([работа("ок")]),
                       {"исход": "ПЕРВЫЙ СНИМОК", "стало": 100})
    assert итог == шлюз.СОХРАННОСТЬ_НЕ_СВЕРЕНА


def test_потери_весомее_неполноты():
    """Потеря отзывает уже названную страницу — исход называет именно её."""
    итог = шлюз.свести(покрытие([работа("НЕ НАЗВАНЫ")]),
                       сохранность("ПОТЕРИ", исчезло=1217))
    assert итог == шлюз.ПОТЕРИ


def test_потери_видны_даже_если_исход_меры_молчит():
    """Число исчезших адресов — самостоятельное основание отказа."""
    итог = шлюз.свести(покрытие([работа("ок")]),
                       {"исход": "НАДМНОЖЕСТВО", "исчезло": 2,
                        "добавилось": 2})
    assert итог == шлюз.ПОТЕРИ


# --- неизмеренное не выглядит успехом -------------------------------------

def test_выборка_где_терять_нечего_полноты_не_измеряет():
    """Ноль проблем при нуле измерений — это не приёмка.

    Признак `нечего терять` в дефект не идёт намеренно, поэтому выборка
    целиком из таких работ дала бы ноль проблем и ложное «принято».
    """
    итог = шлюз.свести(покрытие([работа("нечего терять"),
                                 работа("нечего терять", 2)]),
                       сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.ПОЛНОТА_НЕ_ИЗМЕРЕНА


def test_одной_измеренной_работы_уже_достаточно():
    """Граница предыдущей проверки: она не должна валить годную выборку."""
    итог = шлюз.свести(покрытие([работа("нечего терять"),
                                 работа("ок", 2)]),
                       сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.ПРИНЯТО


def test_непрочитанные_страницы_полнотой_не_считаются():
    """`не измерено` у работы — не «ок»."""
    итог = шлюз.свести(
        покрытие([{"позиция": 1, "слаг": "w", "итог": "не измерено"}]),
        сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.ПОЛНОТА_НЕ_ИЗМЕРЕНА


def test_позиции_которой_нет_в_каталоге_не_считаются():
    итог = шлюз.свести(покрытие([{"позиция": 9999, "итог": "позиции нет"}]),
                       сохранность("НАДМНОЖЕСТВО", добавилось=5))
    assert итог == шлюз.ПОЛНОТА_НЕ_ИЗМЕРЕНА


def test_непрочитанная_карта_это_не_измерено():
    итог = шлюз.свести(покрытие([], измерено=False),
                       сохранность("НЕ ИЗМЕРЕНО"))
    assert итог == шлюз.НЕ_ИЗМЕРЕНО


def test_несверенная_сохранность_не_маскирует_неполноту():
    """Два незакрытых условия — называется более дорогое."""
    итог = шлюз.свести(покрытие([работа("НЕ НАЗВАНЫ")]),
                       {"исход": "ПЕРВЫЙ СНИМОК", "стало": 100})
    assert итог == шлюз.НЕПОЛНО


# --- счётчики --------------------------------------------------------------

def test_счётчик_измеренных_работ_считает_все_три_признака():
    работы = [работа("ок"), работа("ок, но есть лишние", 2),
              работа("НЕ НАЗВАНЫ", 3), работа("нечего терять", 4),
              {"позиция": 5, "итог": "позиции нет"}]
    assert шлюз.работ_с_потерей(покрытие(работы)) == 3
    assert шлюз.работ_неполных(покрытие(работы)) == 1


def test_пустая_выборка_не_роняет_счётчики():
    assert шлюз.работ_с_потерей(покрытие([])) == 0
    assert шлюз.работ_неполных(покрытие([])) == 0


def test_исходы_сохранности_перечислены_теми_же_словами_что_в_мере():
    """Опечатка в названии исхода превратила бы приёмку в молчаливый пропуск.

    Поэтому список сверяется с константами самой меры, а не с литералами.
    """
    _с = importlib.util.spec_from_file_location(
        "sitemap_part_monotonic",
        КОРЕНЬ / "automation" / "local" / "sitemap-part-monotonic.py")
    мера = importlib.util.module_from_spec(_с)
    _с.loader.exec_module(мера)
    assert set(шлюз.СОХРАННОСТЬ_СВЕРЕНА) == {
        мера.НАДМНОЖЕСТВО, мера.БЕЗ_ИЗМЕНЕНИЙ, мера.ПОТЕРИ}
    assert мера.ПЕРВЫЙ not in шлюз.СОХРАННОСТЬ_СВЕРЕНА
    assert мера.НЕ_ИЗМЕРЕНО not in шлюз.СОХРАННОСТЬ_СВЕРЕНА


def test_код_возврата_ноль_только_у_приёмки(monkeypatch):
    monkeypatch.setattr(шлюз, "проверить",
                        lambda д, п: {"домен": д, "исход": шлюз.ПРИНЯТО,
                                      "полнота": покрытие([работа("ок")]),
                                      "сохранность": сохранность(
                                          "НАДМНОЖЕСТВО", добавилось=5)})
    assert шлюз.main(["x.test", "--json"]) == 0


@pytest.mark.parametrize("исход,код", [
    (шлюз.НЕПОЛНО, 1), (шлюз.ПОТЕРИ, 1),
    (шлюз.СОХРАННОСТЬ_НЕ_СВЕРЕНА, 1), (шлюз.ПОЛНОТА_НЕ_ИЗМЕРЕНА, 1),
    (шлюз.НЕ_ИЗМЕРЕНО, 2)])
def test_коды_возврата_различают_отказ_и_неизмеренность(monkeypatch, исход,
                                                        код):
    monkeypatch.setattr(шлюз, "проверить",
                        lambda д, п: {"домен": д, "исход": исход,
                                      "полнота": покрытие([работа("ок")]),
                                      "сохранность": сохранность(
                                          "НАДМНОЖЕСТВО", добавилось=5)})
    assert шлюз.main(["x.test", "--json"]) == код
