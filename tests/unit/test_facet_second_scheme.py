"""Вторая форма адреса фасета: `/catalog/?year=2024` рядом с `/year/2024/`.

Повод. Замер ходил только по форме пути, а тот же отбор доступен запросом — и
у него своя канонизация. Семейства свели схемы в РАЗНЫЕ стороны: у Lords и
AnimeGo побеждает путь (`/catalog/?year=2024` → canonical `/year/2024/`), у
Animedia и Zona запрос (`/year/2024/` → canonical `/catalog/?year=2024`). Обе
стороны ломаются одинаково, и ни одна из поломок не видна с другой:

* отбор применяет только одна форма — тогда вторая полная копия каталога под
  своим адресом, то есть дубль, которого никто не объявлял;
* canonical второй формы сбрасывает условие — тот же дефект, что нашёлся у
  семи витрин на форме пути, только с обратной стороны.

Применимость проверена измерением перед тем, как норма появилась: 11.10 все
двенадцать витрин отбирают обеими формами одинаково и ни одна не отвечает
«неизвестный фильтр». Иначе норма выдала бы неподдерживаемую форму за дефект —
эту ошибку я уже делал на `/genre/` у an1mego.site.

Сеть мерится без сети: `достать` подменяется таблицей ответов.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

ПУТЁМ = "https://x.test/year/2024/"
ЗАПРОСОМ = "https://x.test/catalog/?year=2024"
ПУСТО = "<html></html>"


def _карточки(префикс: str, сколько: int = 48) -> str:
    return "".join(f'<a href="/title/{префикс}-{i}">' for i in range(сколько))


def _страница(канон: str, префикс: str, сколько: int = 48) -> str:
    return (f'<link rel="canonical" href="{канон}"/>'
            + _карточки(префикс, сколько))


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    def __init__(self, таблица: dict):
        self.таблица = таблица
        self.запрошено: list[str] = []

    def __call__(self, url: str, таймаут: int = 45):
        self.запрошено.append(url)
        код, тело, итоговый = self.таблица.get(url, ("404", ПУСТО, url))
        return код, тело, {"итоговый-адрес": итоговый}


def прогнать(таблица: dict, раздел: str = "/year/2024/",
             набор_путём: set | None = None):
    м = _модуль()
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    если_нет = {f"/title/facet-{i}" for i in range(48)}
    м.норма_второй_схемы("x.test", раздел,
                         если_нет if набор_путём is None else набор_путём,
                         lambda и, ок, п: шаги.append((и, ок, п)))
    return шаги


def найти(шаги, часть: str):
    подходящие = [ш for ш in шаги if часть in ш[0]]
    assert len(подходящие) == 1, [ш[0] for ш in шаги]
    return подходящие[0]


def test_адрес_второй_формы_выводится_из_раздела():
    м = _модуль()
    assert м._запросная_форма("x.test", "/year/2024/") == ЗАПРОСОМ
    assert (м._запросная_форма("x.test", "/country/rossiya/")
            == "https://x.test/catalog/?country=rossiya")
    assert (м._запросная_форма("x.test", "/genre/drama/")
            == "https://x.test/catalog/?genre=drama")


def test_у_нефасетного_раздела_второй_формы_нет():
    м = _модуль()
    for раздел in ("/catalog/", "/movies/", "/series/", "/new/", "/animation/"):
        assert м._запросная_форма("x.test", раздел) is None, раздел


def test_обе_формы_отбирают_одинаково_и_canonical_на_путь():
    """Так сделаны Lords и AnimeGo: победила схема пути."""
    шаги = прогнать({
        ЗАПРОСОМ: ("200", _страница(ПУТЁМ, "facet"), ЗАПРОСОМ),
        ПУТЁМ: ("200", _страница(ПУТЁМ, "facet"), ПУТЁМ),
    })
    _и, ок, подробно = найти(шаги, "обе формы адреса отбирают одинаково")
    assert ок is True, подробно
    assert "тот же отбор" in подробно
    _и2, ок2, подробно2 = найти(шаги, "canonical второй формы")
    assert ок2 is True, подробно2
    assert "сведение схем" in подробно2


def test_canonical_второй_формы_на_себя_это_норма():
    """Так сделаны Animedia и Zona: победила схема запроса."""
    шаги = прогнать({ЗАПРОСОМ: ("200", _страница(ЗАПРОСОМ, "facet"), ЗАПРОСОМ)})
    _и, ок, подробно = найти(шаги, "canonical второй формы")
    assert ок is True
    assert "на себя" in подробно


def test_отбор_применяет_только_форма_пути():
    """Вторая форма показывает весь каталог — дубль под своим адресом."""
    шаги = прогнать({
        ЗАПРОСОМ: ("200", _страница(ЗАПРОСОМ, "catalog"), ЗАПРОСОМ)})
    _и, ок, подробно = найти(шаги, "обе формы адреса отбирают одинаково")
    assert ок is False, подробно
    assert "одна из форм условие не применяет" in подробно
    assert "общих 0" in подробно


def test_canonical_второй_формы_сбросил_условие():
    """Тот же дефект, что у семи витрин, но с обратной стороны."""
    каталог = "https://x.test/catalog/"
    шаги = прогнать({
        ЗАПРОСОМ: ("200", _страница(каталог, "facet"), ЗАПРОСОМ),
        каталог: ("200", _страница(каталог, "catalog"), каталог),
    })
    _и, ок, подробно = найти(шаги, "canonical второй формы")
    assert ок is False, подробно
    assert "СОСТАВ РАЗНЫЙ" in подробно
    assert "сбросил условие отбора" in подробно


def test_отсутствие_второй_формы_расхождением_не_считается():
    """Витрина вправе второй формы не иметь: отсутствие — не дефект."""
    шаги = прогнать({ЗАПРОСОМ: ("404", ПУСТО, ЗАПРОСОМ)})
    (имя, ок, подробно) = найти(шаги, "вторая форма адреса")
    assert ок is True
    assert "второй формы нет" in подробно
    # Канонизацию отсутствующей формы проверять не за что.
    assert not [ш for ш in шаги if "canonical второй формы" in ш[0]]


def test_отсутствие_canonical_у_второй_формы_это_расхождение():
    шаги = прогнать({ЗАПРОСОМ: ("200", _карточки("facet"), ЗАПРОСОМ)})
    _и, ок, подробно = найти(шаги, "canonical второй формы")
    assert ок is False
    assert "canonical нет" in подробно


def test_состав_сверяется_по_слагам_а_не_по_числу():
    """У каталога и у фасета бывает по 48 карточек — разных."""
    шаги = прогнать({
        ЗАПРОСОМ: ("200", _страница(ЗАПРОСОМ, "catalog", 48), ЗАПРОСОМ)})
    _и, ок, подробно = найти(шаги, "обе формы адреса отбирают одинаково")
    assert ок is False
    assert "путём 48, запросом 48" in подробно


def test_цель_canonical_не_отвечающая_двумястами_это_расхождение():
    шаги = прогнать({
        ЗАПРОСОМ: ("200", _страница("https://x.test/year/1999/", "facet"),
                   ЗАПРОСОМ)})
    _и, ок, подробно = найти(шаги, "canonical второй формы")
    assert ок is False
    assert "не отвечает 200" in подробно


def test_норма_зовётся_из_замера_раздела_для_фасетов():
    """Норма, которую никто не зовёт, ничего не измеряет."""
    источник = СЦЕНАРИЙ.read_text(encoding="utf-8")
    assert "норма_второй_схемы(домен, раздел, набор1, шаг)" in источник
