"""Проверки инструмента сигнала свежести в карте сайта.

Главное, что здесь закрепляется, — определение рода адреса не зависит от
написания. Первая версия замера искала только `season-2` и напечатала
«сезонов 0, серий 0» на витрине, где таких адресов 129 814: витрина объявляет
`season/2`. Это третий за ночь случай класса 25 — отрицательный результат от
слепого измерителя, — и единственный способ не повторить его в четвёртый раз
это проверка, а не внимание.
"""
import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ФАЙЛ = КОРЕНЬ / "automation/local/sitemap-freshness-signal.py"


@pytest.fixture(scope="module")
def модуль():
    с = importlib.util.spec_from_file_location("freshness", ФАЙЛ)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


@pytest.mark.parametrize("путь,ожидание", [
    # Дефис — семейства Lords и Zona.
    ("/title/mentalist/season-1/episode-3/", "серия"),
    ("/title/mentalist/season-1/", "сезон"),
    # Косая черта — семейство Yummy. Ровно это написание и было упущено.
    ("/anime/kiberpank/season/2/episode/3", "серия"),
    ("/anime/kiberpank/season/2", "сезон"),
    # Без номера — тоже род, а не «прочее».
    ("/anime/kiberpank/episode/12", "серия"),
    ("/title/x/season-10/episode-100/", "серия"),
    ("/title/mentalist/", "произведение"),
    ("/anime/kiberpank", "произведение"),
    ("/catalog", "раздел"),
    ("/", "раздел"),
    ("/genre/drama/page-2", "прочее"),
])
def test_род_адреса_не_зависит_от_написания(модуль, путь, ожидание):
    assert модуль.род(путь) == ожидание, путь


def test_серия_важнее_сезона_в_одном_пути(модуль):
    """У адреса серии есть и сегмент сезона — род должен быть «серия»."""
    assert модуль.род("/title/x/season-1/episode-2/") == "серия"
    assert модуль.род("/anime/x/season/1/episode/2") == "серия"


def test_витрины_не_берут_ожидающих_замены(модуль):
    import json
    реестр = json.loads(
        (КОРЕНЬ / "config/active-domains.json").read_text("utf-8"))
    ждут = {з["domain"] for з in реестр.get("awaiting_replacement") or []}
    assert ждут
    assert not (set(модуль.витрины("")) & ждут)


def test_отсутствие_даты_не_называется_нулём(модуль):
    """Инструмент не предлагает подставить «сегодня» и не считает ноль датой."""
    текст = ФАЙЛ.read_text("utf-8")
    assert "НЕ ИЗМЕРЕНО: ни одной карты разобрать не удалось" in текст
    assert "ложный сигнал свежести" in текст
    # Доля считается от адресов рода, а не от всех: иначе род с одним адресом
    # и датой выглядел бы так же, как род с сотней тысяч без даты.
    assert 'о["с_датой"] * 100.0 / о["всего"]' in текст


def test_вывод_отличает_нет_сигнала_от_не_измерено(модуль):
    текст = ФАЙЛ.read_text("utf-8")
    место_неизмерено = текст.index("НЕ ИЗМЕРЕНО: ни одной карты")
    место_вывода = текст.index("ВЫВОД: у этих родов адресов сигнала свежести")
    assert место_неизмерено < место_вывода, (
        "«не измерено» обязано проверяться до вывода о родах адресов")
    assert "return 3" in текст and "return 1" in текст


def test_род_без_адресов_не_печатается(модуль):
    """Род, которого на витрине нет, в таблицу не попадает и нулём не зовётся."""
    текст = ФАЙЛ.read_text("utf-8")
    assert 'if not о or not о["всего"]:' in текст


@pytest.mark.parametrize("robots,ожидание", [
    ("User-agent: *\nDisallow: /\n", True),
    ("user-agent: *\ndisallow: /\n", True),
    ("User-agent: *\nDisallow: /search\nAllow: /\n", False),
    ("User-agent: Yandex\nDisallow: /\nUser-agent: *\nAllow: /\n", False),
    ("", False),
])
def test_закрытие_по_решению_отличается_от_частичных_запретов(
        модуль, monkeypatch, robots, ожидание):
    """`Disallow: /` для всех — решение; запрет одного раздела — не решение.

    Без этого различения витрины партии K2 печатались как «карта не разобрана»,
    что читается неисправностью. Закрытие K2 однажды уже попало в находки и
    было изъято оттуда — повторять не нужно.
    """
    monkeypatch.setattr(модуль, "добыть", lambda адрес, предел: robots)
    assert модуль.закрыта_по_решению("пример.рф", 5) is ожидание


def test_запрет_только_для_другого_обходчика_не_закрытие(модуль, monkeypatch):
    """`Disallow: /` под чужим User-agent не закрывает витрину для всех."""
    monkeypatch.setattr(
        модуль, "добыть",
        lambda адрес, предел: "User-agent: BadBot\nDisallow: /\n")
    assert модуль.закрыта_по_решению("пример.рф", 5) is False


def test_закрытая_витрина_не_считается_неизмеренной(модуль):
    текст = ФАЙЛ.read_text("utf-8")
    assert "закрыта от обхода по решению" in текст
    # Витрина, закрытая по решению, не должна давать код 3.
    assert "закрытых == len(список)" in текст
