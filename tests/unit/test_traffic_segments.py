"""REQ-TRAFFIC-SEGMENTS: сегменты трафика считаются взвешенно и с основаниями.

Повод (19.10, yummyani.site): дашборд показывал отказы 83 % и время 31 с, а
очищенный от автоматики сегмент дал отказы 14.9 % и время 166 с. Разница целиком
в составе трафика: 71 477 визитов HeadlessChrome с отказом 97.9 % и временем
1.9 с. Поэтому разделение сегментов и способ усреднения — не деталь, а суть.

Закрепляется:

* среднее по сегменту — ВЗВЕШЕННОЕ по визитам (среднее от средних врёт);
* «робот Метрики» и «автоматизация по браузеру» — разные основания, и каждое
  печатается с числом визитов;
* обычный браузер автоматикой не считается (иначе исключили бы людей);
* нет показателя — «не измерено», а не нулевой сегмент.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/traffic-segments.py"
_спец = importlib.util.spec_from_file_location("traffic_segments", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)


def _стр(дата, источник, устройство, браузер, робот, визиты, отказы, глубина, время):
    return {"dimensions": [{"name": дата}, {"name": источник}, {"name": устройство},
                           {"name": браузер}, {"name": робот}],
            "metrics": [визиты, отказы, глубина, время]}


ПРОФИЛЬ = [
    _стр("2026-10-15", "Direct traffic", "PC", "HeadlessChrome", "People",
         20000, 98.0, 1.0, 1.6),
    _стр("2026-10-15", "Search engine traffic", "PC", "Yandex Browser", "People",
         1000, 10.0, 1.3, 160.0),
    _стр("2026-10-16", "Direct traffic", "PC", "HeadlessChrome", "Robots",
         17000, 98.0, 1.0, 1.8),
    _стр("2026-10-16", "Search engine traffic", "Smartphones", "Chrome Mobile",
         "People", 500, 20.0, 1.2, 140.0),
]


def test_строки_разбираются_и_мусор_пропускается():
    стр = ИНСТР.строки(ПРОФИЛЬ + [{"dimensions": [{"name": "x"}], "metrics": [1]}])
    assert len(стр) == 4
    assert стр[0]["браузер"] == "HeadlessChrome" and стр[0]["визиты"] == 20000


@pytest.mark.parametrize("браузер,ожидание", [
    ("HeadlessChrome", True),
    ("headlesschrome", True),
    ("Chrome Headless 120", True),
    ("PhantomJS", True),
    ("curl", True),
    ("Yandex Browser", False),
    ("Google Chrome", False),
    ("Chrome Mobile", False),
    ("Opera", False),
    ("", False),
])
def test_автоматизация_узнаётся_и_людей_не_захватывает(браузер, ожидание):
    assert ИНСТР.автоматизация(браузер) is ожидание


def test_свод_взвешен_по_визитам():
    """Среднее от средних дало бы 54 %, взвешенное даёт 93.8 %."""
    стр = ИНСТР.строки(ПРОФИЛЬ[:2])
    с = ИНСТР.свод(стр)
    assert с["визиты"] == 21000
    assert abs(с["отказы"] - (98.0 * 20000 + 10.0 * 1000) / 21000) < 1e-9
    assert с["отказы"] > 90, "взвешивание потеряно: получилось среднее от средних"


def test_пустой_сегмент_даёт_none_а_не_ноль():
    с = ИНСТР.свод([])
    assert с["визиты"] == 0 and с["отказы"] is None and с["время"] is None


def test_сегменты_исключают_роботов_и_автоматику():
    стр = ИНСТР.строки(ПРОФИЛЬ)
    сег = ИНСТР.сегменты(стр)
    assert сег["весь трафик"]["визиты"] == 38500
    assert сег["без роботов Метрики"]["визиты"] == 21500
    assert сег["без роботов и автоматизации"]["визиты"] == 1500
    # Очищенный сегмент ведёт себя как люди: отказы заметно ниже.
    assert сег["без роботов и автоматизации"]["отказы"] < 20


def test_основания_различают_два_рода_исключений():
    осн = ИНСТР.основания(ИНСТР.строки(ПРОФИЛЬ))
    пары = {(о["основание"], о["браузер"]): о["визиты"] for о in осн}
    assert пары[("автоматизация по браузеру", "HeadlessChrome")] == 20000
    assert пары[("робот Метрики", "HeadlessChrome")] == 17000


def _выгрузка(tmp_path, профиль, измерено=True):
    п = tmp_path / "analytics.json"
    п.write_text(json.dumps({
        "collected_at": "2026-10-19T05:11:55Z",
        "domains": [{"domain": "x.test", "measurements": [
            {"key": "visits", "measured": True, "value": 38500},
            {"key": "daily_traffic_profile", "measured": измерено,
             "state": "" if измерено else "ИСТОЧНИК_НЕДОСТУПЕН",
             "value": профиль}]}]}), encoding="utf-8")
    return п


def test_окно_дат_отсекает_сутки(tmp_path):
    п = _выгрузка(tmp_path, ПРОФИЛЬ)
    и = ИНСТР.разобрать(п, "x.test", "2026-10-16", "2026-10-16")
    assert и["измерено"] is True
    assert и["период"] == "2026-10-16..2026-10-16"
    assert и["сегменты"]["весь трафик"]["визиты"] == 17500


def test_пустое_окно_не_измерено(tmp_path):
    п = _выгрузка(tmp_path, ПРОФИЛЬ)
    и = ИНСТР.разобрать(п, "x.test", "2026-10-01", "2026-10-02")
    assert и["измерено"] is False and "нет суток в окне" in и["почему"]


def test_показатель_не_измерен_даёт_причину(tmp_path):
    п = _выгрузка(tmp_path, [], измерено=False)
    и = ИНСТР.разобрать(п, "x.test")
    assert и["измерено"] is False and "ИСТОЧНИК_НЕДОСТУПЕН" in и["почему"]


def test_чужой_домен_не_измерен(tmp_path):
    п = _выгрузка(tmp_path, ПРОФИЛЬ)
    и = ИНСТР.разобрать(п, "нет.test")
    assert и["измерено"] is False and "нет" in и["почему"]


def test_main_код_2_на_чужом_домене(tmp_path, capsys):
    п = _выгрузка(tmp_path, ПРОФИЛЬ)
    assert ИНСТР.main(["--domain", "нет.test", "--file", str(п)]) == 2
    assert "НЕ ИЗМЕРЕНО" in capsys.readouterr().out


def test_живая_выгрузка_считается(capsys):
    """Отрицательный контроль инструмента на живом хосте."""
    код = ИНСТР.main(["--domain", "yummyani.site"])
    вывод = capsys.readouterr().out
    assert код == 0, вывод
    assert "без роботов и автоматизации" in вывод
