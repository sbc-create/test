"""Отзыв ключа подписи действует немедленно, а не с перезапуска службы.

Дыра, ради которой файл написан. `Состояние.__init__` проверяло состояние
ключа один раз — при старте. Владелец мог пометить ключ `REVOKED` в наборе
проверки, но работающая служба держала `pem` и `kid` с момента запуска и
продолжала подписывать одобрения, пока её не перезапустят.

Отзыв, вступающий в силу «когда-нибудь при перезапуске», отзывом не является:
защита нужна именно в промежуток между решением владельца и рестартом, и
длину этого промежутка задаёт не политика, а случайность эксплуатации.

Проверка отзыва при ВЕРИФИКАЦИИ подписи существовала и раньше
(`keyring.проверить` → `APPROVAL_KEY_REVOKED`). Она ловит предъявленное
одобрение, но не мешает выпустить новое — а выпущенное отозванным ключом
одобрение уже успевает разрешить действие до того, как кто-то его проверит.

Обе стороны отзыва проверяются здесь, и это не дублирование: выпуск и
предъявление — разные моменты и разные защиты. Отзыв обязан действовать и на
уже выданные одобрения тоже, иначе ротация ключа оставляла бы вчерашние
разрешения в силе.

Вторая половина файла — про предъявление. Она написана рядом с первой не потому,
что проверки не было: коды отказа на проверке подписи покрывает `TestПодпись` в
`tests/credentials/test_secret_boundary.py`, и покрывает зелено. Здесь они
стоят рядом с отзывом на выпуске, потому что читаются вместе: одна дыра
закрывается с двух сторон, и видеть обе стороны в одном месте важнее, чем
избежать пересечения с соседним набором.

Чего в соседнем наборе, судя по именам его проверок, нет: семантики `RETIRED` —
выведенный из обращения ключ подписывать уже не вправе, но подписанное им ДО
вывода остаётся действительным. Это и есть граница между плановой ротацией и
отзывом, и стоит она дорого: свести два состояния к одному значит либо ломать
ротацию, либо ослаблять отзыв.

Отдельно: `TestОдобрениеПослеОтзыва` в том же соседнем файле красный и негоден —
он просит подписать набор `cs-1`, не существующий ни в одном хранилище, тогда
как служба подписи с коммита `f402676` читает каноническое состояние сама.
Свойство, которое он заявлял, проверяется здесь.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from factory.site_engine.approval import keyring as K
from factory.site_engine.approval import service as S


@pytest.fixture()
def каталог_ключей(tmp_path: Path, monkeypatch) -> Path:
    """Отдельный набор ключей прогона. Боевой не читается и не меняется."""
    каталог = tmp_path / "credentials"
    каталог.mkdir(parents=True, exist_ok=True)
    kid, pem, публичный = K.создать_ключ()
    (каталог / S.ПРИВАТНЫЙ).write_text(pem, encoding="utf-8")
    (каталог / S.НАБОР).write_text(
        K.НаборКлючей([K.Ключ(kid, публичный, "ACTIVE")]).в_json(), encoding="utf-8")
    (каталог / S.ВЫЗЫВАЮЩИЕ).write_text(json.dumps({"callers": {}}), encoding="utf-8")
    monkeypatch.setenv("CREDENTIALS_DIRECTORY", str(каталог))
    return каталог


def _пометить(каталог: Path, состояние: str) -> None:
    """Владелец меняет состояние ключа в наборе проверки — уже после старта."""
    путь = каталог / S.НАБОР
    набор = K.НаборКлючей.из_json(путь.read_text("utf-8"))
    ключи = [K.Ключ(к.kid, к.публичный, состояние) for к in набор.ключи.values()]
    путь.write_text(K.НаборКлючей(ключи).в_json(), encoding="utf-8")


def test_действующий_ключ_проверку_проходит(каталог_ключей):
    состояние = S.Состояние()
    состояние.проверить_ключ_действующим()  # не должно бросить


def test_отозванный_после_старта_ключ_подписывать_не_даёт(каталог_ключей):
    """Служба уже запущена с активным ключом; отзыв происходит потом."""
    состояние = S.Состояние()
    состояние.проверить_ключ_действующим()

    _пометить(каталог_ключей, "REVOKED")

    with pytest.raises(S.Отказ) as ош:
        состояние.проверить_ключ_действующим()
    assert ош.value.код == "APPROVAL_KEY_REVOKED"
    assert ош.value.статус == 403


def test_выведенный_из_обращения_ключ_тоже_не_подписывает(каталог_ключей):
    """RETIRED — не REVOKED, но подписывать им уже нельзя.

    Отдельный код: «выведен из обращения» и «отозван» — разные события, и
    сводить их к одному значит потерять причину в журнале.
    """
    состояние = S.Состояние()
    _пометить(каталог_ключей, "RETIRED")

    with pytest.raises(S.Отказ) as ош:
        состояние.проверить_ключ_действующим()
    assert ош.value.код == "SIGNING_KEY_NOT_ACTIVE"


def test_исчезнувший_из_набора_ключ_не_подписывает(каталог_ключей):
    """Подписанное ключом вне набора проверки никто не сможет проверить."""
    состояние = S.Состояние()
    (каталог_ключей / S.НАБОР).write_text(
        K.НаборКлючей([]).в_json(), encoding="utf-8")

    with pytest.raises(S.Отказ) as ош:
        состояние.проверить_ключ_действующим()
    assert ош.value.код == "SIGNING_KEY_NOT_IN_KEYSET"


def test_проверка_читает_диск_а_не_кэш(каталог_ключей):
    """Решение владельца живёт в файле; копия в памяти о нём не знает.

    Тест закрывает именно тот способ «починки», которым дыру легко вернуть:
    достаточно начать проверять `self.набор`, прочитанный при старте, и
    проверка снова перестанет замечать отзыв.
    """
    состояние = S.Состояние()
    кэш_до = {k: з.состояние for k, з in состояние.набор.ключи.items()}

    _пометить(каталог_ключей, "REVOKED")

    with pytest.raises(S.Отказ):
        состояние.проверить_ключ_действующим()
    # Кэш намеренно остался прежним — значит отказ пришёл не из него.
    assert {k: з.состояние for k, з in состояние.набор.ключи.items()} == кэш_до
    assert set(кэш_до.values()) == {"ACTIVE"}


# =============================================================================
# Вторая сторона отзыва: уже ВЫДАННОЕ одобрение перестаёт действовать
# =============================================================================
#
# Выпуск и предъявление разнесены во времени, и защищают их разные проверки.
# Выше закрыт выпуск: отозванным ключом нельзя подписать. Ниже — предъявление:
# подписанное ДО отзыва тоже обязано перестать приниматься, иначе ротация
# оставляла бы вчерашние разрешения в силе ровно до их истечения.


ТЕЛО = '{"changeset_id":"cs-контрактный","approver":"human:owner"}'


@pytest.fixture()
def подписанное(каталог_ключей: Path) -> tuple[Path, str, str]:
    """Действующий ключ подписывает тело. Возвращает каталог, kid и подпись."""
    pem = (каталог_ключей / S.ПРИВАТНЫЙ).read_text("utf-8")
    подпись = K.подписать(pem, ТЕЛО)
    kid = подпись.split(":")[1]
    return каталог_ключей, kid, подпись


def _набор(каталог: Path) -> K.НаборКлючей:
    return K.НаборКлючей.из_json((каталог / S.НАБОР).read_text("utf-8"))


def test_подпись_действующего_ключа_принимается(подписанное):
    """Отрицательные случаи ниже бессмысленны, если не работает законный."""
    каталог, kid, подпись = подписанное
    итог = _набор(каталог).проверить(подпись, ТЕЛО)
    assert итог == {"kid": kid, "state": "ACTIVE"}


def test_одобрение_перестаёт_действовать_после_отзыва(подписанное):
    """Та же подпись, то же тело — и отказ, потому что ключ отозван.

    Это и есть смысл отзыва: он относится к ключу, а не к моменту подписи.
    Одобрение не переподписывается и не меняется — меняется решение владельца
    о ключе, и уже выданное перестаёт что-либо разрешать.
    """
    каталог, _, подпись = подписанное
    assert _набор(каталог).проверить(подпись, ТЕЛО)["state"] == "ACTIVE"

    _пометить(каталог, "REVOKED")

    with pytest.raises(K.KeyringError) as ош:
        _набор(каталог).проверить(подпись, ТЕЛО)
    assert ош.value.error_code == "APPROVAL_KEY_REVOKED"


def test_выведенный_из_обращения_ключ_прежние_одобрения_не_отменяет(подписанное):
    """RETIRED — не REVOKED, и разница здесь существенная.

    Выведенный из обращения ключ больше не подписывает (проверено выше), но
    подписанное им до вывода остаётся действительным: плановая ротация не
    обязана обесценивать вчерашние решения владельца. Отзыв обесценивает — тем
    и отличается, и сводить эти два состояния к одному значило бы либо ломать
    ротацию, либо ослаблять отзыв.
    """
    каталог, _, подпись = подписанное
    _пометить(каталог, "RETIRED")
    assert _набор(каталог).проверить(подпись, ТЕЛО)["state"] == "RETIRED"


def test_подпись_ключом_вне_набора_не_принимается(подписанное):
    """Отличается от отзыва: ключ не отозван, он неизвестен."""
    каталог, _, подпись = подписанное
    (каталог / S.НАБОР).write_text(K.НаборКлючей([]).в_json(), encoding="utf-8")

    with pytest.raises(K.KeyringError) as ош:
        _набор(каталог).проверить(подпись, ТЕЛО)
    assert ош.value.error_code == "SIGNATURE_KEY_UNKNOWN"


def test_подпись_не_покрывает_другое_тело(подписанное):
    """Подпись привязана к тому, что подписано, а не к тому, что предъявлено."""
    каталог, _, подпись = подписанное
    подменённое = ТЕЛО.replace("human:owner", "service:templates")

    with pytest.raises(K.KeyringError) as ош:
        _набор(каталог).проверить(подпись, подменённое)
    assert ош.value.error_code == "APPROVAL_SIGNATURE_INVALID"


def test_отзыв_проверяется_раньше_подлинности(подписанное):
    """Отозванный ключ не даёт по коду ответа узнать, верна ли подпись.

    Порядок здесь — не деталь реализации. Если бы подлинность проверялась
    первой, держатель отозванного ключа различал бы «подпись верна, но ключ
    отозван» и «подпись подделана», то есть получал бы оракул на вопрос, задавать
    который он уже не вправе.
    """
    каталог, _, подпись = подписанное
    _пометить(каталог, "REVOKED")
    испорченное = ТЕЛО.replace("cs-контрактный", "cs-другой")

    with pytest.raises(K.KeyringError) as ош:
        _набор(каталог).проверить(подпись, испорченное)
    assert ош.value.error_code == "APPROVAL_KEY_REVOKED", (
        "у отозванного ключа сначала сообщается об отзыве, а не о подписи")
