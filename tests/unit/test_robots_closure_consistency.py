"""Закрытость от индексации: исходы и разбор robots.txt.

Правила взяты из официального источника («Метатеги, которые учитывает
Яндекс»), и каждый тест ниже назван так, чтобы было видно, какое именно
правило он держит:

* запрет на странице, обход которой запрещён, НЕ ДЕЙСТВУЕТ;
* разрешающая директива рядом с запрещающей ПОБЕЖДАЕТ;
* отсутствие директивы разрешающей директивой НЕ ЯВЛЯЕТСЯ.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "robots-closure-consistency.py"

спец = importlib.util.spec_from_file_location("robots_closure", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


def замер(**поля) -> dict:
    основа = {"домен": "пример.test", "путь": "/", "код": 200,
              "мета_robots": "", "x_robots_tag": "", "обход_запрещён": False}
    основа.update(поля)
    return основа


# --- директивы -------------------------------------------------------------

def test_nofollow_к_индексации_не_относится():
    assert модуль.директивы("noindex, nofollow") == {"noindex"}
    assert модуль.директивы("nofollow") == set()


def test_пустое_значение_директив_не_даёт():
    assert модуль.директивы("") == set()
    assert модуль.директивы(None) == set()


def test_регистр_и_пробелы_не_мешают():
    assert модуль.директивы("  NoIndex ,  FOLLOW ") == {"noindex"}
    assert модуль.директивы("ALL") == {"all"}


# --- исходы ----------------------------------------------------------------

def test_запрет_при_разрешённом_обходе_закрыт_надёжно():
    итог = модуль.сверить(замер(мета_robots="noindex, nofollow"), "CLOSED")
    assert итог["исход"] == модуль.ЗАКРЫТО_НАДЁЖНО
    assert итог["расхождение"] is False


def test_запрет_при_запрещённом_обходе_не_прочитается():
    # Правило источника: директива метатега не действует, если страница
    # запрещена в robots.txt.
    итог = модуль.сверить(
        замер(мета_robots="noindex", обход_запрещён=True), "CLOSED")
    assert итог["исход"] == модуль.НЕ_ПРОЧИТАЕТСЯ
    # Замысел «закрыто» при этом не нарушен: закрытость слабее, но есть.
    assert итог["расхождение"] is False


def test_разрешающая_рядом_с_запрещающей_побеждает():
    итог = модуль.сверить(
        замер(мета_robots="noindex", x_robots_tag="all"), "CLOSED")
    assert итог["исход"] == модуль.РАЗРЕШАЮЩАЯ
    assert итог["расхождение"] is True


def test_только_обход_оставляет_адрес_известным():
    итог = модуль.сверить(замер(обход_запрещён=True), "CLOSED")
    assert итог["исход"] == модуль.ТОЛЬКО_ОБХОД


def test_открытая_витрина_с_замыслом_открыто_не_расхождение():
    итог = модуль.сверить(замер(мета_robots="index, follow"), "OPEN")
    assert итог["исход"] == модуль.ОТКРЫТО
    assert итог["расхождение"] is False


def test_закрытая_при_замысле_открыто_это_расхождение():
    итог = модуль.сверить(замер(мета_robots="noindex"), "OPEN")
    assert итог["исход"] == модуль.ЗАКРЫТО_НАДЁЖНО
    assert итог["расхождение"] is True


def test_открытая_при_замысле_закрыто_это_расхождение():
    итог = модуль.сверить(замер(), "CLOSED")
    assert итог["исход"] == модуль.ОТКРЫТО
    assert итог["расхождение"] is True


def test_неназванный_замысел_расхождением_не_объявляется():
    # Пустое поле — не разрешение подставить значение по умолчанию.
    итог = модуль.сверить(замер(), "НЕ НАЗВАН")
    assert итог["расхождение"] is False


def test_отсутствие_директивы_не_считается_разрешающей():
    # Иначе `noindex` в метатеге при пустом заголовке читался бы как
    # конфликт и «разрешающая побеждает».
    итог = модуль.сверить(замер(мета_robots="noindex", x_robots_tag=""),
                          "CLOSED")
    assert итог["исход"] == модуль.ЗАКРЫТО_НАДЁЖНО


def test_запрет_в_заголовке_равноценен_запрету_в_метатеге():
    итог = модуль.сверить(замер(x_robots_tag="noindex"), "CLOSED")
    assert итог["исход"] == модуль.ЗАКРЫТО_НАДЁЖНО


def test_ошибка_замера_не_выдаётся_за_открытость():
    итог = модуль.сверить({"ошибка": "главная не получена"}, "CLOSED")
    assert итог["исход"] == модуль.НЕ_ИЗМЕРЕНО
    assert итог["расхождение"] is False


# --- robots.txt ------------------------------------------------------------

def test_пустой_robots_txt_обход_не_запрещает():
    assert модуль.обход_запрещён("") is False


def test_запрет_всего_для_звёздочки():
    assert модуль.обход_запрещён("User-agent: *\nDisallow: /") is True


def test_запрет_для_яндекса_учитывается():
    текст = "User-agent: Yandex\nDisallow: /\n\nUser-agent: Googlebot\nAllow: /"
    assert модуль.обход_запрещён(текст) is True


def test_запрет_для_чужого_робота_нас_не_касается():
    текст = "User-agent: AhrefsBot\nDisallow: /"
    assert модуль.обход_запрещён(текст) is False


def test_пустой_disallow_это_разрешение():
    assert модуль.обход_запрещён("User-agent: *\nDisallow:") is False


def test_allow_длиннее_disallow_побеждает():
    текст = "User-agent: *\nDisallow: /\nAllow: /catalog"
    assert модуль.обход_запрещён(текст, "/catalog") is False
    assert модуль.обход_запрещён(текст, "/") is True


def test_комментарии_и_пустые_строки_не_мешают():
    текст = "# закрыто до замены домена\nUser-agent: *\n\nDisallow: / # всё"
    assert модуль.обход_запрещён(текст) is True


def test_запрет_другого_раздела_главной_не_касается():
    текст = "User-agent: *\nDisallow: /search/"
    assert модуль.обход_запрещён(текст, "/") is False
    assert модуль.обход_запрещён(текст, "/search/") is True


@pytest.mark.parametrize("замысел,ожидание", [
    ("CLOSED", True), ("OPEN", False), ("НЕ НАЗВАН", False)])
def test_расхождение_зависит_от_замысла_а_не_от_исхода(замысел, ожидание):
    итог = модуль.сверить(замер(мета_robots="index"), замысел)
    assert итог["расхождение"] is ожидание


def test_замысел_закрыто_из_desired_state():
    assert модуль.замысел_ячейки(
        {"indexing": {"desired_state": "CLOSED"}}) == "CLOSED"


def test_разрешение_сильнее_устаревшего_desired_state(tmp_path):
    # Так записаны шестнадцать живых ячеек: `desired_state: CLOSED` остался
    # снимком прежнего состояния, а разрешение владельца уже выдано.
    (tmp_path / "animeg0.site.json").write_text("{}", encoding="utf-8")
    ячейка = {"domain": "animeg0.site",
              "indexing": {"desired_state": "CLOSED", "open_authorized": True}}
    assert модуль.замысел_ячейки(ячейка, согласия=tmp_path) == "OPEN"


def test_флаг_без_файла_согласия_разрешением_не_считается(tmp_path):
    ячейка = {"domain": "ничего.test",
              "indexing": {"open_authorized": True}}
    assert модуль.замысел_ячейки(ячейка, согласия=tmp_path) == "CLOSED"


def test_разрешение_читается_по_названной_ссылке(tmp_path):
    файл = tmp_path / "своё-имя.json"
    файл.write_text("{}", encoding="utf-8")
    ячейка = {"domain": "другое.test",
              "indexing": {"open_authorized": True,
                           "open_authorization_ref": str(файл)}}
    assert модуль.замысел_ячейки(ячейка, согласия=tmp_path) == "OPEN"


def test_прямой_запрет_открытия_это_закрыто():
    assert модуль.замысел_ячейки(
        {"domain": "х.test", "indexing": {"open_authorized": False}}) == "CLOSED"


def test_исключение_из_продвижения_замыслом_по_индексации_не_является():
    # Общий профиль шаблона исключается из ПРОДВИЖЕНИЯ, оставаясь открытым
    # (решение D208). Если читать это поле как запрет индексации, признак
    # окажется шире самого признака.
    assert модуль.замысел_ячейки(
        {"domain": "х.test", "promotion": {"excluded": True}}) == "НЕ НАЗВАН"


def test_пустая_ячейка_замысла_не_придумывает():
    assert модуль.замысел_ячейки({}) == "НЕ НАЗВАН"


def test_при_равной_длине_разрешение_сильнее_запрета():
    # Правило приоритетов: самый длинный путь сильнее, а при равной длине
    # сильнее РАЗРЕШЕНИЕ. Первая редакция разбора отдавала победу запрету,
    # то есть читала правило наоборот.
    текст = "User-agent: *\nDisallow: /catalog\nAllow: /catalog"
    assert модуль.обход_запрещён(текст, "/catalog") is False


def test_более_длинный_запрет_сильнее_короткого_разрешения():
    текст = "User-agent: *\nAllow: /cat\nDisallow: /catalog"
    assert модуль.обход_запрещён(текст, "/catalog") is True

