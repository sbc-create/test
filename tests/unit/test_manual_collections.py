"""Ручной состав подборки по постоянным идентификаторам.

Редакционные подборки владельца описывают СОСТАВ, а не фильтр: у каждой работы
свой порядок и своё пояснение, зачем она здесь. Фильтром это не выражается —
«восемь сериалов, которые заканчиваются в одном сезоне» из снимка не получить,
потому что поля «закончился» в снимке нет.

Ключ состава — `id` подробностей, а не слаг (решение владельца витрины 26.10):
слаг меняется вместе с названием у поставщика. Измерено на `chuzhaya-zhizn` —
слаг исчез из снимка целиком; по id пропажу видно сразу и именно как пропажу.
"""
from __future__ import annotations

import importlib.util
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "collection_contract_ручной",
    КОРЕНЬ / "automation" / "host" / "collection_contract.py")
кк = importlib.util.module_from_spec(_сп)
# Модуль обязан стоять в `sys.modules` ДО исполнения: `dataclass` при
# `from __future__ import annotations` разбирает подписи через модуль класса, и
# без записи он получает None.
sys.modules["collection_contract_ручной"] = кк
_сп.loader.exec_module(кк)


def _файл(работы: list, *, индексация: dict | None = None) -> dict:
    return {"collections": [{
        "key": "trillery-na-vecher",
        "title": "Триллеры на вечер",
        "viewer_request": "посмотреть напряжённое кино на один вечер",
        "intro": "Три фильма с закрытой историей.",
        "section": "/movies/",
        "indexing": индексация if индексация is not None else
                    {"open": True, "reason": "страница несёт пояснения к каждой работе"},
        "items": работы,
    }]}


def _работа(н: int, *, идент: str = "", слаг: str = "") -> dict:
    return {"order": н, "id": идент or f"catalog-{н:04d}",
            "slug": слаг or f"proba-{н}", "url": f"https://proba.invalid/title/proba-{н}/",
            "name": f"Проба {н}", "year": 2024,
            "reason": f"причина {н}", "checked": "2026-10-26"}


class Снимок:
    """Минимальный снимок: записи каталога и подробности с идентификаторами."""

    def __init__(self, записи, подробности):
        self.items = записи
        self.подробности = подробности


def test_порядок_берётся_из_объявления_а_не_из_снимка():
    """Читателю обещан порядок редакции, и снимок его менять не вправе."""
    данные = _файл([_работа(3), _работа(1), _работа(2)])
    подборки = кк.ручные_подборки(данные)
    assert len(подборки) == 1
    assert [р.order for р in подборки[0].works] == [1, 2, 3]


def test_состав_разрешается_по_идентификатору_а_не_по_слагу():
    """Слаг сменился у поставщика — работа обязана остаться на месте."""
    данные = _файл([_работа(1, идент="catalog-0001", слаг="старый-слаг")])
    подборка = кк.ручные_подборки(данные)[0]
    снимок = Снимок([{"slug": "новый-слаг", "title": "Проба 1"}],
                    {"новый-слаг": {"id": "catalog-0001"}})
    итог = кк.разрешить_ручную(подборка, снимок)
    assert итог["missing"] == []
    assert [з["запись"]["slug"] for з in итог["works"]] == ["новый-слаг"]


def test_исчезнувший_идентификатор_помечается_а_не_подменяется():
    """Подмена соседней работой — выдуманный факт: обещали конкретную работу."""
    данные = _файл([_работа(1), _работа(2)])
    подборка = кк.ручные_подборки(данные)[0]
    снимок = Снимок([{"slug": "proba-1", "title": "Проба 1"},
                     {"slug": "посторонняя", "title": "Посторонняя"}],
                    {"proba-1": {"id": "catalog-0001"},
                     "посторонняя": {"id": "catalog-9999"}})
    итог = кк.разрешить_ручную(подборка, снимок)
    assert [з["запись"]["slug"] for з in итог["works"]] == ["proba-1"]
    assert [р.id for р in итог["missing"]] == ["catalog-0002"]
    # Пояснение редакции остаётся при пропавшей работе: подборка обязана
    # показать потерю, а не стать короче молча.
    assert итог["missing"][0].reason == "причина 2"


def test_слаг_остаётся_запасом_когда_идентификатора_нет_в_подробностях():
    данные = _файл([_работа(1, слаг="proba-1")])
    подборка = кк.ручные_подборки(данные)[0]
    снимок = Снимок([{"slug": "proba-1", "title": "Проба 1"}], {})
    итог = кк.разрешить_ручную(подборка, снимок)
    assert [з["запись"]["slug"] for з in итог["works"]] == ["proba-1"]


def test_подборка_без_причины_индексации_не_собирается():
    """Решение об индексации без причины — не решение."""
    данные = _файл([_работа(1)], индексация={"open": True})
    assert кк.ручные_подборки(данные) == []


def test_работа_без_пояснения_в_состав_не_попадает():
    """Карточка без «зачем она здесь» — это фильтр, а не редакционный выбор."""
    работа = _работа(1)
    работа["reason"] = "  "
    данные = _файл([работа, _работа(2)])
    подборка = кк.ручные_подборки(данные)[0]
    assert [р.id for р in подборка.works] == ["catalog-0002"]


def test_адрес_подборки_считается_от_ключа():
    данные = _файл([_работа(1)])
    assert кк.ручные_подборки(данные)[0].canonical_path == "/collection/trillery-na-vecher/"


def test_решение_об_индексации_сохраняется_целиком():
    данные = _файл([_работа(1)], индексация={"open": False,
                                             "reason": "витрина закрыта целиком"})
    п = кк.ручные_подборки(данные)[0]
    assert п.indexing_open is False
    assert п.indexing_reason == "витрина закрыта целиком"


def test_повторный_идентификатор_в_подробностях_берёт_первый():
    """Два слага с одним id — в снимке бывает; выбор обязан быть устойчивым."""
    индекс = кк.индекс_по_идентификатору({"б": {"id": "один"}, "а": {"id": "один"}})
    assert индекс["один"] in ("а", "б")
    assert len(индекс) == 1
