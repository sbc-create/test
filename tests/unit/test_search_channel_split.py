"""Проверки разделения поискового канала на Яндекс и Google.

Отрицательные контроли названы заранее, и каждый ловит свою ошибку:

* «не измерено» не превращается в ноль — иначе домен без счётчика
  неотличим от домена без посетителей;
* обрезанная разбивка не выдаётся за полную сумму;
* посетители не печатаются под подписью визитов;
* рост одного канала при падении другого называется словами, а не
  скрывается знаком суммы.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "search_channel_split", КОРЕНЬ / "automation/local/search-channel-split.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)


def _разбивка(строки, *, измерено=True, причина=None):
    return {"key": "search_engines", "measured": измерено,
            "reason": причина, "value": {"data": строки},
            "source": "ym:s:lastsignSearchEngine"}


def _ряд(строки, *, измерено=True, причина=None):
    return {"key": "daily_search", "measured": измерено, "reason": причина,
            "value": {"data": строки},
            "source": "ym:s:users, ym:s:visits × ym:s:date × …"}


def _снимок(домен, измерения):
    return {"collected_at": "2026-10-20T05:11:38Z",
            "domains": [{"domain": домен, "measurements": измерения}]}


def _строка_поисковика(имя, визиты):
    return {"dimensions": [{"name": имя}], "metrics": [визиты]}


def _строка_суток(дата, поисковик, посетители, визиты):
    return {"dimensions": [{"name": дата},
                           {"name": "Search engine traffic", "id": "organic"},
                           {"name": поисковик.title(), "id": поисковик}],
            "metrics": [посетители, визиты]}


# --- «не измерено» не равно нулю ---------------------------------------------

def test_не_измеренный_домен_не_даёт_нулей():
    с = _снимок("a.site", [_разбивка([], измерено=False,
                                     причина="счётчик Метрики не создан")])
    итог = ИНСТР.канал_за_окно(с, "a.site")
    assert "визиты" not in итог
    assert итог["не_измерено"] == "счётчик Метрики не создан"


def test_домена_нет_в_выгрузке():
    с = _снимок("a.site", [_разбивка([_строка_поисковика("Yandex", 5)])])
    assert "не_измерено" in ИНСТР.канал_за_окно(с, "b.site")


def test_не_измеренный_канал_не_называется_падением():
    """Отрицательный контроль: отсутствие данных — не вывод о росте."""
    с = _снимок("a.site", [_разбивка([], измерено=False, причина="нет счётчика")])
    было = {"визиты": {ИНСТР.ЯНДЕКС: 100.0}}
    assert ИНСТР.чем_растёт(было, ИНСТР.канал_за_окно(с, "a.site")) == "не измерено"


def test_отсутствие_причины_не_молчит():
    с = _снимок("a.site", [_разбивка([], измерено=False)])
    assert ИНСТР.канал_за_окно(с, "a.site")["не_измерено"] == "причина не названа"


# --- обрезанная разбивка ------------------------------------------------------

def test_полная_разбивка_не_помечается_обрезанной():
    строки = [_строка_поисковика(f"Поисковик {n}", 1) for n in range(5)]
    assert ИНСТР.канал_за_окно(_снимок("a.site", [_разбивка(строки)]),
                               "a.site")["нижняя_граница"] is False


def test_разбивка_в_предел_строк_помечается_нижней_границей():
    """Отрицательный контроль: сумма ровно по пределу — не полная сумма."""
    строки = [_строка_поисковика(f"Поисковик {n}", 1)
              for n in range(ИНСТР.ПРЕДЕЛ_РАЗБИВКИ)]
    итог = ИНСТР.канал_за_окно(_снимок("a.site", [_разбивка(строки)]), "a.site")
    assert итог["нижняя_граница"] is True
    assert итог["строк"] == ИНСТР.ПРЕДЕЛ_РАЗБИВКИ


# --- разделение поисковиков ---------------------------------------------------

def test_мобильный_яндекс_идёт_в_яндекс():
    строки = [_строка_поисковика("Yandex, search results", 10),
              _строка_поисковика("Yandex Mobile", 7),
              _строка_поисковика("Yandex: mobile app", 3)]
    итог = ИНСТР.канал_за_окно(_снимок("a.site", [_разбивка(строки)]), "a.site")
    assert итог["визиты"][ИНСТР.ЯНДЕКС] == 20


def test_bing_и_mail_не_сливаются_с_google():
    строки = [_строка_поисковика("Google, search results", 10),
              _строка_поисковика("Bing, search results", 4),
              _строка_поисковика("Mail.ru", 2)]
    итог = ИНСТР.канал_за_окно(_снимок("a.site", [_разбивка(строки)]), "a.site")
    assert итог["визиты"][ИНСТР.ГУГЛ] == 10
    assert итог["визиты"]["прочие"] == 6


# --- словесный вывод ----------------------------------------------------------

def test_рост_google_при_падении_яндекса_назван():
    было = {"визиты": {ИНСТР.ЯНДЕКС: 188.0, ИНСТР.ГУГЛ: 61.0}}
    стало = {"визиты": {ИНСТР.ЯНДЕКС: 165.0, ИНСТР.ГУГЛ: 664.0},
             "нижняя_граница": False}
    assert ИНСТР.чем_растёт(было, стало) == "Google, Яндекс падает"


def test_рост_яндекса_при_падении_google_назван():
    было = {"визиты": {ИНСТР.ЯНДЕКС: 80.0, ИНСТР.ГУГЛ: 61.0}}
    стало = {"визиты": {ИНСТР.ЯНДЕКС: 746.0, ИНСТР.ГУГЛ: 20.0},
             "нижняя_граница": False}
    assert ИНСТР.чем_растёт(было, стало) == "Яндекс, Google падает"


def test_единицы_визитов_не_называются_ростом():
    """Отрицательный контроль: 7 визитов из нуля — не вывод о канале."""
    стало = {"визиты": {ИНСТР.ГУГЛ: 7.0}, "нижняя_граница": False}
    assert ИНСТР.чем_растёт({"визиты": {}}, стало) == "мало данных"


def test_нулевой_канал_не_растёт():
    стало = {"визиты": {ИНСТР.ЯНДЕКС: 0.0, ИНСТР.ГУГЛ: 30.0},
             "нижняя_граница": False}
    было = {"визиты": {ИНСТР.ЯНДЕКС: 0.0, ИНСТР.ГУГЛ: 40.0}}
    assert ИНСТР.чем_растёт(было, стало) == "не растёт"


# --- суточный ряд: посетители и визиты не смешиваются -------------------------

def test_ряд_посетителей_и_ряд_визитов_различаются():
    строки = [_строка_суток("2026-10-19", "yandex", 6, 7),
              _строка_суток("2026-10-19", "google", 98, 136)]
    с = _снимок("a.site", [_ряд(строки)])
    посетители = ИНСТР.канал_по_суткам(с, "a.site", ИНСТР.ПОСЕТИТЕЛИ)["ряд"]
    визиты = ИНСТР.канал_по_суткам(с, "a.site", ИНСТР.ВИЗИТЫ)["ряд"]
    assert посетители[ИНСТР.ЯНДЕКС]["2026-10-19"] == 6
    assert визиты[ИНСТР.ЯНДЕКС]["2026-10-19"] == 7
    assert посетители[ИНСТР.ГУГЛ]["2026-10-19"] == 98
    assert визиты[ИНСТР.ГУГЛ]["2026-10-19"] == 136


def test_ряд_без_второй_метрики_не_выдумывает_визиты():
    строка = {"dimensions": [{"name": "2026-10-19"},
                             {"name": "Search engine traffic", "id": "organic"},
                             {"name": "Yandex", "id": "yandex"}],
              "metrics": [6]}
    с = _снимок("a.site", [_ряд([строка])])
    assert ИНСТР.канал_по_суткам(с, "a.site", ИНСТР.ВИЗИТЫ)["ряд"] == {}


def test_ряд_не_измерен_печатает_причину():
    с = _снимок("a.site", [_ряд([], измерено=False, причина="429 от источника")])
    assert ИНСТР.канал_по_суткам(с, "a.site")["не_измерено"] == "429 от источника"


def test_осыпание_канала_видно_в_ряду_а_не_в_окнах():
    """Ряд обязателен: две недели могут сойтись, а канал внутри осыпаться."""
    дни = [(f"2026-10-{д:02d}", п) for д, п in
           ((13, 21), (14, 26), (15, 21), (16, 16), (17, 5), (18, 9), (19, 6))]
    строки = [_строка_суток(д, "yandex", п, п) for д, п in дни]
    ряд = ИНСТР.канал_по_суткам(_снимок("a.site", [_ряд(строки)]),
                                "a.site")["ряд"][ИНСТР.ЯНДЕКС]
    начало = sum(ряд[d] for d, _ in дни[:3])
    конец = sum(ряд[d] for d, _ in дни[-3:])
    assert начало > конец * 2


# --- коды возврата ------------------------------------------------------------

def test_коды_возврата(tmp_path, capsys):
    измерен = _снимок("a.site", [_разбивка([_строка_поисковика("Yandex", 50)]),
                                 _ряд([_строка_суток("2026-10-19", "yandex", 6, 7)])])
    пусто = _снимок("b.site", [_разбивка([], измерено=False, причина="нет счётчика")])
    for имя, данные in (("after.json", измерен), ("empty.json", пусто)):
        (tmp_path / имя).write_text(__import__("json").dumps(данные),
                                    encoding="utf-8")
    assert ИНСТР.main(["--after", str(tmp_path / "after.json")]) == 0
    assert ИНСТР.main(["--after", str(tmp_path / "empty.json")]) == 2


@pytest.mark.parametrize("серия", ("users", "visits", "none"))
def test_ряд_печатается_по_выбору(tmp_path, capsys, серия):
    данные = _снимок("a.site", [_разбивка([_строка_поисковика("Yandex", 50)]),
                                _ряд([_строка_суток("2026-10-19", "yandex", 6, 7)])])
    путь = tmp_path / "after.json"
    путь.write_text(__import__("json").dumps(данные), encoding="utf-8")
    ИНСТР.main(["--after", str(путь), "--series", серия])
    вывод = capsys.readouterr().out
    assert ("по суткам" in вывод) is (серия != "none")
    if серия == "users":
        assert "ПОСЕТИТЕЛИ" in вывод
    if серия == "visits":
        assert "ВИЗИТЫ" in вывод
