"""Проверки инструмента доступности источника у плеера.

Главное, что здесь закрепляется, — исходы не подменяются друг другом.
«Не разрешилось» не равно «нет источника», а витрина, которую не удалось
измерить, не считается витриной без источника: ровно такие подмены делают
отчёт ложным.
"""
import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ФАЙЛ = КОРЕНЬ / "automation/local/player-availability-sweep.py"


@pytest.fixture(scope="module")
def модуль():
    с = importlib.util.spec_from_file_location("player_sweep", ФАЙЛ)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


def test_пути_с_доменом_разбираются(модуль, tmp_path):
    ф = tmp_path / "пути.tsv"
    ф.write_text("lordserials22.info\t/title/mentalist\n"
                 "animedia.icu\t/anime/koe/\n", encoding="utf-8")
    получено = модуль.читать_пути(str(ф))
    assert получено == {"lordserials22.info": ["/title/mentalist/"],
                        "animedia.icu": ["/anime/koe/"]}


def test_пустые_строки_и_примечания_пропускаются(модуль, tmp_path):
    ф = tmp_path / "пути.tsv"
    ф.write_text("# примечание\n\nlordserials22.info\t/title/a\n",
                 encoding="utf-8")
    assert модуль.читать_пути(str(ф)) == {
        "lordserials22.info": ["/title/a/"]}


def test_общий_путь_достаётся_каждой_витрине(модуль, tmp_path):
    """Строка без домена относится ко всем витринам файла."""
    ф = tmp_path / "пути.tsv"
    ф.write_text("lordserials22.info\t/title/a\n"
                 "animedia.icu\t/anime/b\n"
                 "/title/общая\n", encoding="utf-8")
    получено = модуль.читать_пути(str(ф))
    assert получено["lordserials22.info"] == ["/title/a/", "/title/общая/"]
    assert получено["animedia.icu"] == ["/anime/b/", "/title/общая/"]


def test_витрины_не_берут_ожидающих_замены(модуль):
    """Четыре домена ждут замены — по заданию владельца их не трогаем."""
    import json
    реестр = json.loads(
        (КОРЕНЬ / "config/active-domains.json").read_text("utf-8"))
    ждут = {з["domain"] for з in реестр.get("awaiting_replacement") or []}
    assert ждут, "в реестре нет ожидающих замены — проверка потеряла смысл"
    список = модуль.витрины("")
    assert not (set(список) & ждут), (
        f"в замер попали домены, ожидающие замены: {set(список) & ждут}")


def test_названные_домены_перекрывают_реестр(модуль):
    assert модуль.витрины("a.ru, b.ru") == ["a.ru", "b.ru"]


def test_состояния_различимы_в_словаре_исходов(модуль):
    """Четыре исхода названы раздельно и ни один не склеен с другим."""
    текст = ФАЙЛ.read_text("utf-8")
    for исход in ("источник", "нет источника", "не разрешилось",
                  "страница не отдалась"):
        assert f'"{исход}"' in текст, f"исход {исход} не назван в коде"
    # Витрина без источника объявляется только когда сообщение ВИДЕЛИ:
    # нерешённое состояние такой вывод делать не даёт.
    assert 'счёт["источник"] == 0 and счёт["нет источника"]' in текст, (
        "вывод «источника нет ни на одной» не должен опираться на"
        " нерешённые состояния")


