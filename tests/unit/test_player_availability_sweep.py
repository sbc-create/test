def test_неизмеренная_витрина_не_попадает_в_вывод_о_поломке(модуль):
    """`None` в сводке означает «не измерено» и не считается нулём."""
    текст = ФАЙЛ.read_text("utf-8")
    assert "всего[домен] = None" in текст
    assert "НЕ ИЗМЕРЕНО НИ НА ОДНОЙ ВИТРИНЕ" in текст
    assert "raise SystemExit(3)" in текст


def test_файл_путей_задаёт_состав_витрин(модуль):
    """Витрине, которой нет в файле путей, нельзя приписывать причину.

    Первый настоящий прогон шёл по всему реестру и четырнадцати витринам
    напечатал «на главной нет ссылок проверенных форм» — причину, которую
    инструмент даже не проверял, потому что при заданном файле он главную не
    запрашивает. Ложная причина хуже отсутствия строки.
    """
    текст = ФАЙЛ.read_text("utf-8")
    assert "только_из_файла = bool(заданные) and not а.domains" in текст
    assert "в файле путей нет строк для этой витрины" in текст


def test_успех_требует_хотя_бы_одного_разрешённого_источника(модуль):
    """Прогон, где всё «не разрешилось», успехом не объявляется.

    Первый прогон дал 16 страниц, из них 16 «не разрешилось», и напечатал
    «у каждой измеренной витрины источник есть хотя бы на одной карточке».
    Это тот же молчаливый успех, что и в `playback-check.py` — класс 24.
    """
    текст = ФАЙЛ.read_text("utf-8")
    место_успеха = текст.index("ВЫВОД: у каждой измеренной витрины источник")
    место_запрета = текст.index("НЕ ИЗМЕРЕНО: источник не разрешился НИ НА ОДНОЙ")
    assert место_запрета < место_успеха, (
        "проверка «ни одного источника» обязана стоять ДО печати успеха")
    assert "if not с_источником:" in текст


def test_положительный_контроль_обязателен_и_останавливает_прогон(модуль):
    """Без живого контроля «не разрешилось» у всех — не вывод о витринах.

    16 таких строк уже были приняты за данные. Контроль — страница, которая
    заведомо играет; если не играет и она, замер не состоялся.
    """
    текст = ФАЙЛ.read_text("utf-8")
    assert '"--control"' in текст
    assert "НЕ ИЗМЕРЕНО: страница контроля" in текст
    # Контроль идёт ДО обхода витрин, иначе он ничего не защищает.
    assert текст.index("--control") < текст.index("for домен in список")
    assert текст.index("НЕ ИЗМЕРЕНО: страница контроля") < текст.index(
        "for домен in список")
