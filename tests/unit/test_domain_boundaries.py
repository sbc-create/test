"""REQ-DOMAIN-BOUNDARIES: доменные границы закреплены кодом, а не документом.

Документ о том, «кто кого не должен импортировать», расходится с кодом за
неделю — это уже проверено на настройке навигации, которую не читал никто, и
на отпечатке шаблона, отвечавшем не на тот вопрос. Поэтому границы объявлены
реестром `config/domains.yaml`, а сверяет их гейт, читающий сам код.

Слой над гейтом модулей `site_engine/boundaries.py`, а не второй механизм
рядом: тот проверяет устройство внутри одного пакета, этот — девять доменов,
которые шире пакета.

Раскладка выведена из кода, а не назначена. Первый черновик не разложил 55
файлов, и они оказались информативнее разложенных: почти все были
`factory/lords`. Отсюда две единицы, доменами не являющиеся: `site_families`
(реализации семейств витрин, потребляющие сразу каталог, шаблоны и релизы) и
`control_plane` (Control API с админкой, который не делится по решению
владельца).

Гейт уже поправил модель четырежды: `identity_resolver` разрешает тождество
произведений, а не людей; `cli` — точка входа, а не опора; `retry` — утилита;
`pipeline` оркеструет выкат. Раскладка по именам ошибалась, код — нет.
"""

from __future__ import annotations

import pathlib

import pytest

from factory.architecture import domains as гейт

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]

#: Сколько нарушений признано известными. Число может только уменьшаться.
#: Рост означает, что границу перешли и записали это как норму.
ИЗВЕСТНЫХ_НЕ_БОЛЬШЕ = 0

#: Сколько файлов ещё не отнесено ни к одному домену. Тоже только вниз:
#: нераспределённый файл — работа впереди, а не нарушение, но их число
#: обязано убывать, иначе раскладка остановится на половине.
НЕРАСПРЕДЕЛЁННЫХ_НЕ_БОЛЬШЕ = 10


@pytest.fixture(scope="module")
def итог():
    return гейт.проверить(КОРЕНЬ)


class TestРеестрОписываетСуществующее:
    def test_реестр_разбирается(self):
        данные = гейт.загрузить(КОРЕНЬ)
        assert данные["domains"], "доменов не объявлено"
        assert len(данные["domains"]) == 9, (
            "доменов должно быть девять — перечень задан постановкой этапа")

    def test_каждый_домен_называет_владение_и_запреты(self):
        for домен in гейт.загрузить(КОРЕНЬ)["domains"]:
            ид = домен["id"]
            assert домен.get("purpose"), f"{ид}: домен без назначения"
            assert домен.get("owns"), f"{ид}: домен, не владеющий ничем, не домен"
            assert домен.get("public_interface"), (
                f"{ид}: без публичного интерфейса к нему придётся лезть внутрь")
            assert домен.get("check"), f"{ид}: нечем проверить"
            assert домен.get("rollback"), f"{ид}: не сказано, как откатывать"

    def test_объявленные_пути_существуют(self, итог):
        нет_пути = [н for н in итог.нарушения if "которого нет" in н]
        assert not нет_пути, (
            f"граница проведена по несуществующему файлу: {нет_пути}")


class TestГраницыДержатся:
    def test_запрещённых_зависимостей_нет(self, итог):
        assert итог.ok, "нарушены доменные границы:\n  " + "\n  ".join(итог.нарушения)

    def test_список_известных_нарушений_не_растёт(self, итог):
        assert len(итог.известные) <= ИЗВЕСТНЫХ_НЕ_БОЛЬШЕ, (
            f"известных нарушений стало {len(итог.известные)} при пределе "
            f"{ИЗВЕСТНЫХ_НЕ_БОЛЬШЕ}: перечень долгов превращается в "
            f"договорённость терпеть\n  " + "\n  ".join(итог.известные))

    def test_каждое_известное_нарушение_названо_с_лечением(self):
        for з in гейт.загрузить(КОРЕНЬ).get("known_violations") or []:
            assert з.get("why"), f"{з['file']}: долг без объяснения"
            assert з.get("fix"), (
                f"{з['file']}: долг без плана лечения — это не долг, "
                f"а договорённость терпеть")
            assert з.get("planned_cycle"), f"{з['file']}: не сказано когда"

    def test_нераспределённых_файлов_не_становится_больше(self, итог):
        assert len(итог.нераспределённых) <= НЕРАСПРЕДЕЛЁННЫХ_НЕ_БОЛЬШЕ, (
            f"нераспределённых файлов стало {len(итог.нераспределённых)} при "
            f"пределе {НЕРАСПРЕДЕЛЁННЫХ_НЕ_БОЛЬШЕ}: раскладка остановилась\n  "
            + "\n  ".join(итог.нераспределённых))

    def test_файл_не_принадлежит_двум_доменам(self, итог):
        двойные = [н for н in итог.нарушения if "владельца нет" in н]
        assert not двойные, f"файл с двумя владельцами: {двойные}"


class TestЕдиницыВнеДоменов:
    def test_control_plane_объявлен_неделимым(self):
        блок = гейт.загрузить(КОРЕНЬ)["control_plane"]
        assert "не делится" in (блок.get("note") or "").lower(), (
            "неделимость управляющего контура не записана — решение владельца "
            "должно быть видно в реестре, а не только в переписке")

    def test_семейства_витрин_не_домен(self):
        блок = гейт.загрузить(КОРЕНЬ)["site_families"]
        assert блок.get("note"), (
            "не объяснено, почему семейства витрин не домен — без этого "
            "следующий читатель попробует сделать их доменом снова")
