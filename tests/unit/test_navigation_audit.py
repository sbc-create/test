"""Навигация по собственным ссылкам витрины, с оценкой по СОДЕРЖИМОМУ.

Повод измерен 20.10: на всех пяти витринах Yummy страницы каталога 335-349
отдают HTTP 200 и ни одной карточки (MOD-108). Проверка кода ответа такую
страницу пропускает, поэтому здесь каждая ссылка оценивается по содержимому.

Виды страниц НЕ задаются списком, а собираются из ссылок главной: список
разошёлся бы с витриной и проверял бы мои представления о ней.

Отрицательные контроли, названные заранее:

* статический файл (`/favicon.svg`) страницей навигации не считается — ровно
  эта ложная находка и случилась на zonafilm.space при первом прогоне;
* страница с текстом, но без карточек и h1, находкой не считается, если текста
  хватает: раздел-описание — законная страница;
* главная, не ответившая 200, даёт «НЕ ИЗМЕРЕНО» по всему домену, а не ноль
  находок;
* один образец на вид: восемь тысяч карточек не проверяются.

Сеть не используется: загрузчик подменяется.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "navigation_audit", КОРЕНЬ / "automation/local/navigation-audit.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

Д = "x.site"


def _с_карточками(n: int = 8) -> str:
    ссылки = "".join(f'<a href="/title/t{и}/">x</a>' for и in range(n))
    return f"<html><body><h1>Раздел</h1>{ссылки}</body></html>"


ПУСТАЯ = "<html><body><div class='chrome'></div></body></html>"
ТЕКСТОВАЯ = "<html><body><p>" + ("слово " * 120) + "</p></body></html>"


# --- сбор видов ----------------------------------------------------------------

def test_виды_собираются_по_первому_сегменту():
    тело = ('<a href="/catalog/">a</a><a href="/catalog/?page=2">b</a>'
            '<a href="/title/odin/">c</a><a href="/title/dva/">d</a>'
            '<a href="/new/">e</a>')
    виды = ИНСТР.виды_ссылок(тело, Д)
    assert sorted(виды) == ["/catalog/", "/new/", "/title/"]


def test_один_образец_на_вид():
    """Отрицательный контроль: восемь тысяч карточек не проверяются."""
    тело = "".join(f'<a href="/title/t{и}/">x</a>' for и in range(8000))
    виды = ИНСТР.виды_ссылок(тело, Д)
    assert list(виды) == ["/title/"]


def test_свой_абсолютный_адрес_тоже_берётся():
    тело = f'<a href="https://{Д}/schedule/">x</a>'
    assert "/schedule/" in ИНСТР.виды_ссылок(тело, Д)


def test_чужой_домен_не_берётся():
    тело = '<a href="https://chuzhoy.example/catalog/">x</a>'
    assert ИНСТР.виды_ссылок(тело, Д) == {}


def test_статический_файл_страницей_не_считается():
    """Живая ложная находка: /favicon.svg давал «ПУСТО»."""
    тело = ('<a href="/favicon.svg">i</a><a href="/style.css">s</a>'
            '<a href="/app.js">j</a><a href="/sitemap.xml">m</a>'
            '<a href="/catalog/">c</a>')
    assert list(ИНСТР.виды_ссылок(тело, Д)) == ["/catalog/"]


def test_главная_остаётся_видом():
    assert ИНСТР.виды_ссылок('<a href="/">дом</a>', Д) == {"/": "/"}


# --- оценка страницы -----------------------------------------------------------

def test_страница_с_карточками_ок():
    исход, чем = ИНСТР.оценить(200, _с_карточками())
    assert исход == "ок"
    assert "карточек 8" in чем


def test_пустая_двести_это_находка():
    """Главный признак: ровно так выглядят страницы 335-349 у Yummy."""
    исход, чем = ИНСТР.оценить(200, ПУСТАЯ)
    assert исход == "ПУСТО"
    assert "карточек 0" in чем and "h1 нет" in чем


def test_текстовая_страница_находкой_не_считается():
    """Отрицательный контроль: раздел-описание — законная страница."""
    assert ИНСТР.оценить(200, ТЕКСТОВАЯ)[0] == "ок"


def test_страница_только_с_h1_это_ок():
    assert ИНСТР.оценить(200, "<html><body><h1>Поиск</h1></body></html>")[0] == "ок"


def test_не_двести_это_отдельная_находка():
    исход, чем = ИНСТР.оценить(404, "")
    assert исход == "НЕ 200" and "код 404" in чем


def test_нет_соединения_отличается_от_кода():
    assert ИНСТР.оценить(0, "")[0] == "НЕ ОТВЕТИЛА"


def test_видимый_текст_не_считает_скрипты():
    """Иначе страница с большим скриптом сошла бы за содержательную."""
    тело = "<html><script>" + ("x" * 5000) + "</script><body></body></html>"
    assert ИНСТР.оценить(200, тело)[0] == "ПУСТО"


# --- проход по домену ----------------------------------------------------------

def _загрузчик(карта: dict):
    def достать(url):
        for ключ in sorted(карта, key=len, reverse=True):
            if url.endswith(ключ):
                return 200, карта[ключ]
        return 404, ""
    return достать


def test_проход_называет_вид_и_исход():
    главная = ('<html><body><h1>Дом</h1><a href="/catalog/">c</a>'
               '<a href="/new/">n</a><a href="/title/odin/">t</a></body></html>')
    карта = {"/": главная, "/catalog/": _с_карточками(),
             "/new/": ПУСТАЯ, "/title/odin/": _с_карточками(3)}
    итог = ИНСТР.проверить(Д, загрузчик=_загрузчик(карта))
    assert итог["ok"] is True
    исходы = {с["вид"]: с["исход"] for с in итог["строки"]}
    assert исходы["/catalog/"] == "ок"
    assert исходы["/new/"] == "ПУСТО"
    assert исходы["/title/"] == "ок"


def test_главная_не_ответила_это_не_измерено():
    итог = ИНСТР.проверить(Д, загрузчик=lambda url: (503, ""))
    assert итог["ok"] is False
    assert "503" in итог["почему"]
    assert итог["строки"] == []


def test_код_возврата_один_при_находке(monkeypatch, capsys):
    главная = '<html><body><h1>Дом</h1><a href="/new/">n</a></body></html>'
    monkeypatch.setattr(ИНСТР, "достать",
                        _загрузчик({"/": главная, "/new/": ПУСТАЯ}))
    assert ИНСТР.главное([Д]) == 1
    вывод = capsys.readouterr().out
    assert "ПУСТО" in вывод
    assert "код 200 содержанием не считается" in вывод


def test_двоичный_ответ_не_роняет_проход(monkeypatch):
    """Измерено 20.10: ссылка отдала PNG, и text=True уронил весь проход.

    Падение инструмента хуже находки: оно оставило без ответа остальные десять
    витрин. Признак: двоичное тело проходит через разбор и оценивается как
    любая другая страница.
    """
    class _Итог:
        stdout = b"\x89PNG\r\n\x1a\n" + bytes(range(256)) + b"\n200"

    monkeypatch.setattr(ИНСТР.subprocess, "run", lambda *а, **к: _Итог())
    код, тело = ИНСТР.достать("https://x.site/kartinka")
    assert код == 200
    assert ИНСТР.оценить(код, тело)[0] == "ПУСТО"


def test_код_возврата_ноль_без_находок(monkeypatch, capsys):
    главная = ('<html><body><h1>Дом</h1><a href="/catalog/">c</a></body></html>')
    monkeypatch.setattr(ИНСТР, "достать",
                        _загрузчик({"/": главная,
                                    "/catalog/": _с_карточками()}))
    assert ИНСТР.главное([Д]) == 0
    assert "находок: 0" in capsys.readouterr().out
