"""Цель «5 000 визитов в сутки»: роботы отброшены, «не измерено» не ноль.

Три свойства, ради которых счёт вынесен в инструмент, и каждое проверяется
отрицательным контролем: строки роботов в сумму не идут; делитель — число
РАЗЛИЧНЫХ дат в самой мере, а не длина запрошенного окна; витрина без меры
попадает в список «не измерено» и в знаменатель доли сети не входит.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "goal-visits-per-site.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("goal_visits_per_site", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def _строка(дата, источник, визиты, робот="no"):
    return {"dimensions": [{"name": дата}, {"id": источник},
                           {"id": "desktop"}, {"id": "204"}, {"id": робот}],
            "metrics": [визиты, 0.0, 0.0, 0.0]}


def test_визиты_делятся_на_число_дат():
    профиль = [_строка("2026-10-20", "direct", 10),
               _строка("2026-10-21", "direct", 20)]
    в, п, суток = МОД.визиты_в_сутки(профиль)
    assert суток == 2
    assert в == 15.0 and п == 0.0


def test_роботы_в_счёт_не_идут():
    профиль = [_строка("2026-10-20", "direct", 10),
               _строка("2026-10-20", "direct", 990, робот="yes")]
    в, _, суток = МОД.визиты_в_сутки(профиль)
    assert суток == 1 and в == 10.0


def test_поисковые_считаются_отдельно():
    профиль = [_строка("2026-10-20", "organic", 7),
               _строка("2026-10-20", "direct", 3)]
    в, п, _ = МОД.визиты_в_сутки(профиль)
    assert в == 10.0 and п == 7.0


def test_день_только_с_роботами_делителя_не_даёт():
    """Иначе средняя занижалась бы днями, где живых визитов не было вовсе."""
    профиль = [_строка("2026-10-20", "direct", 10),
               _строка("2026-10-21", "direct", 50, робот="yes")]
    в, _, суток = МОД.визиты_в_сутки(профиль)
    assert суток == 1 and в == 10.0


def test_пустая_мера_даёт_ноль_суток():
    в, п, суток = МОД.визиты_в_сутки([])
    assert (в, п, суток) == (0.0, 0.0, 0)


def test_витрина_без_меры_попадает_в_не_измерено():
    снимок = {"domains": [
        {"domain": "есть.ru", "measurements": [
            {"key": "daily_traffic_profile", "measured": True,
             "value": [_строка("2026-10-20", "organic", 12)]}]},
        {"domain": "нет.ru", "measurements": [
            {"key": "daily_traffic_profile", "measured": False,
             "value": "не измерено"}]},
    ]}
    измерено, нет = МОД.разобрать(снимок)
    assert [д for д, *_ in измерено] == ["есть.ru"]
    assert нет == [("нет.ru", "не измерено")]


def test_витрины_упорядочены_по_убыванию():
    снимок = {"domains": [
        {"domain": "малая", "measurements": [
            {"key": "daily_traffic_profile", "value": [_строка("2026-10-20", "direct", 1)]}]},
        {"domain": "большая", "measurements": [
            {"key": "daily_traffic_profile", "value": [_строка("2026-10-20", "direct", 100)]}]},
    ]}
    измерено, _ = МОД.разобрать(снимок)
    assert [д for д, *_ in измерено] == ["большая", "малая"]
