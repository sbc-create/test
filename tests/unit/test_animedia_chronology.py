"""Хронология Animedia: порядок «сначала новое» доказывается перемешиванием.

Тест, который подаёт уже упорядоченный список и радуется результату, не
проверяет ничего. Поэтому здесь вход намеренно перемешан, даты приходят в
разных записях времени, а часть записей несёт одну и ту же отметку — как в
настоящем снимке, где 4003 записи из 7425 добавлены одним мгновением массовой
загрузки. Именно на таких равных датах прежняя сортировка строк давала
произвольный порядок.
"""
from __future__ import annotations

import datetime as dt
import random
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from factory.animedia import chronology as х  # noqa: E402


def запись(slug: str, дата, **прочее) -> dict:
    return {"slug": slug, "published_at": дата, **прочее}


# --- разбор момента -----------------------------------------------------------

@pytest.mark.parametrize("значение, ожидание", [
    ("2026-09-18T14:59:02Z", dt.datetime(2026, 9, 18, 14, 59, 2, tzinfo=dt.timezone.utc)),
    ("2026-09-18T17:59:02+03:00", dt.datetime(2026, 9, 18, 14, 59, 2, tzinfo=dt.timezone.utc)),
    ("2026-09-18T14:59:02", dt.datetime(2026, 9, 18, 14, 59, 2, tzinfo=dt.timezone.utc)),
    ("2026-09-18", dt.datetime(2026, 9, 18, tzinfo=dt.timezone.utc)),
    ("2026-09-18 14:59:02", dt.datetime(2026, 9, 18, 14, 59, 2, tzinfo=dt.timezone.utc)),
    ("18.09.2026", dt.datetime(2026, 9, 18, tzinfo=dt.timezone.utc)),
])
def test_разные_записи_времени_дают_один_момент(значение, ожидание):
    assert х.разобрать_момент(значение) == ожидание


@pytest.mark.parametrize("мусор", ["", "   ", None, True, False, "вчера", "2026-13-45", {}])
def test_не_дата_остаётся_не_датой(мусор):
    assert х.разобрать_момент(мусор) is None


def test_смещение_учитывается_а_не_обрезается():
    """Строковое сравнение считало бы «+03:00» новее «Z» при равном моменте."""
    поздний = запись("a", "2026-09-18T14:00:00Z")
    ранний = запись("b", "2026-09-18T16:00:00+03:00")  # это 13:00 UTC
    assert х.по_добавлению([ранний, поздний])[0]["slug"] == "a"


# --- порядок ------------------------------------------------------------------

def test_перемешанный_вход_упорядочивается_по_убыванию():
    даты = ["2024-11-12T12:20:11Z", "2026-09-18T14:59:02Z", "2025-03-02T23:45:07Z",
            "2026-01-01T00:00:00Z", "2024-12-24T11:05:09Z"]
    записи = [запись(f"s{i}", д) for i, д in enumerate(даты)]
    случайный = random.Random(20260921)
    for _ in range(25):
        случайный.shuffle(записи)
        итог = х.по_добавлению(записи)
        полученные = [з["published_at"] for з in итог]
        assert полученные == sorted(даты, reverse=True), полученные


def test_равные_даты_дают_один_и_тот_же_порядок_при_любом_входе():
    """Это и есть случай массовой загрузки: 4003 записи с одной отметкой."""
    одна = "2024-11-12T12:20:11Z"
    записи = [запись(f"slug-{i:03d}", одна) for i in range(40)]
    случайный = random.Random(7)
    порядки = set()
    for _ in range(10):
        случайный.shuffle(записи)
        порядки.add(tuple(з["slug"] for з in х.по_добавлению(записи)))
    assert len(порядки) == 1, "порядок при равных датах должен быть устойчивым"
    # И он документирован: канонический ключ по возрастанию.
    единственный = порядки.pop()
    assert list(единственный) == sorted(единственный)


def test_факт_опережает_оценку_при_равной_дате():
    одна = "2025-05-05T05:05:05Z"
    оценочная = запись("aaa", одна, published_at_estimated=True)
    фактическая = запись("zzz", одна)
    assert х.по_добавлению([оценочная, фактическая])[0]["slug"] == "zzz"


def test_записи_без_даты_уходят_в_конец():
    итог = х.по_добавлению([запись("нет", None), запись("есть", "2026-01-01T00:00:00Z"),
                            запись("мусор", "когда-то")])
    assert итог[0]["slug"] == "есть"
    assert {з["slug"] for з in итог[1:]} == {"нет", "мусор"}


def test_added_at_важнее_published_at():
    з = {"slug": "x", "published_at": "2020-01-01T00:00:00Z",
         "added_at": "2026-09-01T00:00:00Z"}
    момент, поле = х.дата_добавления(з)
    assert поле == "added_at"
    assert момент.year == 2026


def test_ленты_новых_серий_идут_по_дате_серии_а_не_по_году():
    """Год произведения не заменяет дату серии: это разные утверждения."""
    старое_произведение_свежая_серия = {
        "slug": "старое", "year": 1999, "episode_published_at": "2026-09-20T10:00:00Z"}
    новое_произведение_старая_серия = {
        "slug": "новое", "year": 2026, "episode_published_at": "2026-01-02T10:00:00Z"}
    итог = х.по_эпизодам([новое_произведение_старая_серия,
                          старое_произведение_свежая_серия])
    assert [з["slug"] for з in итог] == ["старое", "новое"]


# --- проверка уже собранного списка -------------------------------------------

def test_проверка_порядка_находит_нарушение():
    плохой = [запись("a", "2024-01-01T00:00:00Z"), запись("b", "2026-01-01T00:00:00Z")]
    беды = х.проверить_порядок(плохой)
    assert len(беды) == 1 and "новее предыдущей" in беды[0]


def test_проверка_порядка_молчит_на_правильном():
    хороший = х.по_добавлению([запись("a", "2024-01-01T00:00:00Z"),
                               запись("b", "2026-01-01T00:00:00Z"),
                               запись("c", "2026-01-01T00:00:00Z")])
    assert х.проверить_порядок(хороший) == []


# --- контракт коллекций пользуется тем же порядком ----------------------------

def test_снимок_коллекций_сортирует_через_хронологию():
    from factory.animedia import collection_contract as кк

    записи = [запись("b", "2024-11-12T12:20:11Z"), запись("a", "2026-09-18T14:59:02Z"),
              запись("c", "2024-11-12T12:20:11Z")]
    снимок = кк.Снимок(записи)
    assert [з["slug"] for з in снимок.по_дате()] == ["a", "b", "c"]
