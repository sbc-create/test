"""Сдвиг набора страниц с поисковыми входами: толкование по ЧИСТОМУ изменению.

Повод — своя же ошибка 22.10: первая редакция объявляла «набор сузился» при
любом уходе страницы и поставила этот вывод домену, у которого набор ВЫРОС с
48 до 129 страниц. Такой вывод отправил бы работу не туда, поэтому здесь
закреплены все исходы и границы между ними.

Отдельно закреплён отказ сравнивать перекрывающиеся окна: окно снимка — семь
суток, соседние суточные снимки перекрываются на шесть дней из семи, и их
разность — сдвиг окна, а не изменение.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "search_page_set_shift",
    КОРЕНЬ / "automation" / "local" / "search-page-set-shift.py")
мера = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(мера)


# --- окна -----------------------------------------------------------------

def test_семь_суток_врозь_это_годное_сравнение(tmp_path):
    а = tmp_path / "analytics-2026-10-15.json"
    б = tmp_path / "analytics-2026-10-22.json"
    годно, почему = мера.окна_не_перекрываются(а, б)
    assert годно is True
    assert "не перекрываются" in почему


@pytest.mark.parametrize("вторая", ["2026-10-16", "2026-10-18", "2026-10-21"])
def test_перекрывающиеся_окна_сравнивать_нельзя(tmp_path, вторая):
    а = tmp_path / "analytics-2026-10-15.json"
    б = tmp_path / f"analytics-{вторая}.json"
    годно, почему = мера.окна_не_перекрываются(а, б)
    assert годно is False
    assert "перекрываются" in почему


def test_снимок_без_даты_в_имени_не_сравнивается(tmp_path):
    годно, почему = мера.окна_не_перекрываются(
        tmp_path / "analytics.json", tmp_path / "analytics-2026-10-22.json")
    assert годно is False
    assert "нет даты" in почему


# --- толкование: каждый исход и его граница -------------------------------

def test_рост_набора_и_входов():
    и = мера.истолковать({"/a": 10}, {"/a": 12, "/b": 5})
    assert и.startswith("РОСТ")


def test_рост_не_называется_сужением_при_обмене():
    """Ровно та ошибка, из-за которой проверка написана.

    Набор вырос с 48 до 129 страниц при 16 ушедших — это обновление набора,
    а не потеря.
    """
    было = {f"/стр-{и}": 10 for и in range(48)}
    стало = {f"/стр-{и}": 10 for и in range(16, 48)}
    стало.update({f"/новая-{и}": 20 for и in range(97)})
    и = мера.истолковать(было, стало)
    assert и.startswith("РОСТ"), и
    assert "обмен: ушло 16, пришло 97" in и


def test_сужение_набора_и_падение_входов():
    было = {"/a": 10, "/b": 10, "/c": 10}
    стало = {"/a": 2}
    и = мера.истолковать(было, стало)
    assert и.startswith("НАБОР СУЗИЛСЯ")


def test_набор_держится_а_входы_упали():
    было = {"/a": 100, "/b": 100}
    стало = {"/a": 20, "/b": 20}
    и = мера.истолковать(было, стало)
    assert "НАБОР ДЕРЖИТСЯ, ВХОДЫ УПАЛИ" in и


def test_сужение_без_падения_входов_называется_отдельно():
    """Спрос сошёлся на меньшем числе страниц — это не потеря."""
    было = {"/a": 10, "/b": 10, "/c": 10}
    стало = {"/a": 40}
    и = мера.истолковать(было, стало)
    assert "спрос сошёлся" in и


def test_страниц_не_было_и_появились():
    и = мера.истолковать({}, {"/a": 1})
    assert "НЕ БЫЛО" in и


def test_страницы_исчезли_все():
    и = мера.истолковать({"/a": 5}, {})
    assert "ИСЧЕЗЛИ ВСЕ" in и
    assert "только Вебмастером" in и


def test_нет_данных_ни_до_ни_после():
    assert мера.истолковать({}, {}) == "нет данных ни до, ни после"


def test_обмен_печатается_всегда():
    """Обмен может быть велик при неизменном итоге — молчать о нём нельзя."""
    было = {f"/a{и}": 10 for и in range(10)}
    стало = {f"/b{и}": 10 for и in range(10)}
    и = мера.истолковать(было, стало)
    assert "обмен: ушло 10, пришло 10" in и


