def test_набор_из_снимка_читается(tmp_path):
    снимок = tmp_path / "analytics-2026-10-22.json"
    снимок.write_text(json.dumps({"domains": [{
        "domain": "d.test",
        "measurements": [{
            "key": "search_landing_pages", "measured": True,
            "value": [{"dimensions": [
                {"name": "Search engine traffic", "id": "organic"},
                {"name": "/x", "favicon": "d.test"}], "metrics": [7.0]}],
        }],
    }]}), encoding="utf-8")
    assert мера.набор(снимок) == {"d.test": {"/x": 7}}


def test_неизмеренный_разрез_в_набор_не_идёт(tmp_path):
    снимок = tmp_path / "analytics-2026-10-22.json"
    снимок.write_text(json.dumps({"domains": [{
        "domain": "d.test",
        "measurements": [{"key": "search_landing_pages", "measured": False,
                          "reason": "нет доступа"}],
    }]}), encoding="utf-8")
    assert мера.набор(снимок) == {}
