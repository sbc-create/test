def _запись_установки(цель: Path, когда: str, источник: str = "/дерево/службы") -> Path:
    ф = цель / "cell-install.json"
    ф.write_text(json.dumps({
        "installed_at": когда,
        "code_source": источник,
        "package_id": None,
        "package_digest": None,
        "package_commit": None,
        "site_repos_root": источник,
    }, ensure_ascii=False), encoding="utf-8")
    return ф


def test_расхождение_объясняется_временем_установки(tmp_path):
    """Главный разбор: установка БЫЛА, а источник ушёл вперёд.

    Измерено 13.10: cell-install.json говорит 17:34:02Z, а три компонента
    правлены в 17:41:55Z и 18:53:21Z. Без этого «установлено нет» нельзя было
    отличить от «установки не было», и в очереди с инструментом расходились
    две записи.
    """
    ветвь, цель, к = _компонент(tmp_path)
    (цель / "модуль.py").write_text("ПРЕЖНИЙ код\n", encoding="utf-8")
    к.имя_в_цели = "модуль.py"
    _запись_установки(цель, "2000-01-01T00:00:00Z")
    итог = _разобрать(ветвь, к)
    состояние, причина = итог["установлено"]
    assert состояние == вид.НЕТ
    assert "установлено 2000-01-01T00:00:00Z" in причина
    assert "установка БЫЛА, а источник ушёл вперёд" in причина


