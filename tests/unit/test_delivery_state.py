"""Поведение единого вида состояния доставки.

Главное свойство, которое этот вид и обязан держать: стадии НЕ выводятся одна
из другой. «Установлено» не означает «загружено» — за вечер 12.10 это спутали
четыре раза, и мост MCP два часа исполнял код старше файла, пока отчёты
называли правку доставленной.

Процессы в проверках настоящие: запускается `sleep` с узнаваемой командной
строкой, и время его старта сравнивается с mtime файла. Подделывать здесь
нечего — измеряется ровно тот механизм, которым работает инструмент.
"""
from __future__ import annotations

import importlib.util
import os
import subprocess
import json
import sys
import time
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "delivery-state.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("delivery_state", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    # Регистрация ДО исполнения обязательна: `dataclass` ищет модуль класса в
    # sys.modules, и без этого разбор падает на объявлении `Компонент`.
    sys.modules["delivery_state"] = м
    спец.loader.exec_module(м)
    return м


вид = _модуль()


def _ждущий(метка: str) -> list[str]:
    """Процесс, несущий метку в своей командной строке.

    `sleep 30 <метка>` не годится: лишние аргументы он считает ещё
    интервалами и отказывает, а тест при этом измерял бы отсутствие процесса.
    """
    return [sys.executable, "-c", "import time; time.sleep(30)", метка]


def _компонент(tmp_path: Path, **правки):
    """Компонент на одноразовом стенде: своя «ветвь» и своя «цель»."""
    ветвь = tmp_path / "branch"
    (ветвь / "factory").mkdir(parents=True, exist_ok=True)
    (ветвь / "factory" / "модуль.py").write_text("новый код\n", encoding="utf-8")
    цель = tmp_path / "target"
    цель.mkdir(exist_ok=True)
    осн = dict(ключ="проба", имя="проба", файл="factory/модуль.py", цель=цель)
    осн.update(правки)
    return ветвь, цель, вид.Компонент(**осн)


def _разобрать(ветвь: Path, к):
    прежняя = вид.ВЕТВЬ
    вид.ВЕТВЬ = ветвь
    try:
        return вид.разобрать(к)
    finally:
        вид.ВЕТВЬ = прежняя


def test_установлено_не_означает_загружено(tmp_path):
    """Файл в цели совпадает, а процесс стартовал раньше правки.

    Ровно случай моста MCP: правка лежала в дереве службы, суммы совпадали,
    и это считалось доставкой. Процесс при этом исполнял прежний код.
    """
    ветвь, цель, _ = _компонент(tmp_path)
    (цель / "factory").mkdir(parents=True)
    файл = цель / "factory" / "модуль.py"
    файл.write_text("новый код\n", encoding="utf-8")

    метка = f"проба-доставки-{os.getpid()}"
    процесс = subprocess.Popen(_ждущий(метка))
    try:
        time.sleep(0.3)
        # Файл правлен ПОЗЖЕ старта процесса.
        будущее = time.time() + 60
        os.utime(файл, (будущее, будущее))

        к = вид.Компонент(ключ="проба", имя="проба", файл="factory/модуль.py",
                          цель=цель, процесс=метка)
        итог = _разобрать(ветвь, к)
    finally:
        процесс.kill()
        процесс.wait(timeout=10)

    assert итог["установлено"][0] == вид.ДА, итог["установлено"]
    assert итог["загружено"][0] == вид.НЕТ, итог["загружено"]
    assert "СТАРЫЙ код" in итог["загружено"][1]


def test_процесс_стартовавший_после_правки_загружен(tmp_path):
    ветвь, цель, _ = _компонент(tmp_path)
