def test_берётся_самый_ранний_процесс(tmp_path):
    """Если процессов несколько, вопрос решает стартовавший раньше всех.

    Остальные код уже перечитали, а он нет. Взять любой значило бы объявить
    доставку по тому экземпляру, которому повезло.
    """
    метка = f"проба-ранний-{os.getpid()}"
    первый = subprocess.Popen(_ждущий(метка))
    time.sleep(1.2)
    второй = subprocess.Popen(_ждущий(метка))
    try:
        time.sleep(0.3)
        найдено = вид.старт_процесса(метка)
        assert найдено, "ни один процесс не найден"
        когда, pid = найдено
        assert pid == первый.pid, (
            f"взят pid {pid}, а самый ранний — {первый.pid}")
    finally:
        первый.kill(); второй.kill()
        первый.wait(timeout=10); второй.wait(timeout=10)


