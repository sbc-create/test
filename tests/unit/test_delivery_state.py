def test_приёмка_старше_кода_не_приёмка(tmp_path):
    """Третье условие стадии, и оно делает её честной.

    `editorial-fix-install-20261011.md` удостоверяет правку от 11.10, а
    исправление авторства сделано 12.10. Артефакт прежней версии, зачтённый
    как приёмка нынешней, и есть «выглядит проверенным, не будучи».
    """
    import os
    ветвь, цель, _ = _компонент(tmp_path)
    (ветвь / "docs").mkdir()
    артефакт = ветвь / "docs" / "приёмка.md"
    артефакт.write_text("итог: verified\n", encoding="utf-8")
    # Артефакт СТАРШЕ кода на час.
    код = ветвь / "factory" / "модуль.py"
    будущее = артефакт.stat().st_mtime + 3600
    os.utime(код, (будущее, будущее))

    к = вид.Компонент(ключ="проба", имя="проба", файл="factory/модуль.py",
                      цель=цель, приёмка=("docs/приёмка.md", "verified"))
    итог = _разобрать(ветвь, к)
    assert итог["проверено"][0] == вид.НЕТ, итог["проверено"]
    assert "СТАРШЕ кода" in итог["проверено"][1]
    # Обе метки названы: без них «старше» нечем проверить.
    assert "артефакт 2" in итог["проверено"][1] and "код 2" in итог["проверено"][1]


