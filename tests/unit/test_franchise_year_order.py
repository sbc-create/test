"""Масштаб ошибок года в снимке — внутренним признаком, без внешнего источника.

Повод. MOD-102 измерил расхождение года с источником на шести записях, но долю
на каталог перенести нельзя: записи выбирались по ждущим черновикам. Сверить
весь каталог с источником тоже нельзя — в записях снимка нет `shikimori_id`, а
выдумывать поиск запрещено (D199). Масштаб оставался неизвестным.

Внутренний признак: у нумерованного продолжения год не может быть РАНЬШЕ, чем у
предыдущей части. Измерено 20.10 на animedia.icu: `rukovodstvo-soten-demonov`
даёт 2020, 2021, 2022, **2020**, 2025, и именно у четвёртой части источник
сказал `aired_on 2024-02-23`. То есть внутренний признак нашёл ту же запись,
что внешняя сверка.

Отрицательные контроли, названные заранее, и каждый взят из живых данных:

* ПРОСТОЕ УБЫВАНИЕ НЕ ОШИБКА. `berserk` 2016 → `berserk-2` 1997 и
  `brodyaga-kensin-2` 2023 → `-3` 1996 — ремейки и разные экранизации, где
  нумерация слагов не хронологическая. На живом снимке простых падений 100, а
  строгих кандидатов 14: разница и есть цена этого контроля;
* пара частей строгим кандидатом быть НЕ может: на паре удаление любого
  элемента делает ряд неубывающим тривиально;
* две и больше выпадающих части — не «одна неверная запись», и кандидатом не
  объявляются;
* равные годы у соседних частей находкой не считаются: два сезона в одном году
  — обычное дело;
* часть без года в ряд не попадает: отсутствие года — не убывание.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "franchise_year_order", КОРЕНЬ / "automation/local/franchise-year-order.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)


def _снимок(годы: dict[str, int | None]) -> dict[str, dict]:
    return {с: ({} if г is None else {"year": г}) for с, г in годы.items()}


# --- разбор слагов -------------------------------------------------------------

def test_нумерованные_хвосты_разбираются():
    ф = ИНСТР.франшизы(_снимок({"a": 2020, "a-2": 2021, "a-chast-3": 2022}))
    assert sorted(н for н, _, _ in ф["a"]) == [1, 2, 3]


def test_слаг_без_номера_франшизой_не_становится():
    assert ИНСТР.франшизы(_снимок({"odinochka": 2020})) == {}


def test_часть_без_года_в_ряд_не_попадает():
    ф = ИНСТР.франшизы(_снимок({"a": 2020, "a-2": None, "a-3": 2022}))
    assert [н for н, _, _ in ф["a"]] == [1, 3]


# --- простое убывание ----------------------------------------------------------

def test_падение_находится():
    части = [(1, "a", 2022), (2, "a-2", 2019)]
    assert ИНСТР.падения(части) == [("a", 2022, "a-2", 2019)]


def test_равные_годы_падением_не_считаются():
    """Два сезона в одном году — обычное дело."""
    assert ИНСТР.падения([(1, "a", 2020), (2, "a-2", 2020)]) == []


# --- строгий признак -----------------------------------------------------------

def test_одна_выпадающая_часть_находится():
    """Живой случай: 2020, 2021, 2022, 2020, 2025 — выпадает четвёртая."""
    части = [(1, "r", 2020), (2, "r-2", 2021), (3, "r-3", 2022),
             (4, "r-4", 2020), (5, "r-5", 2025)]
    assert ИНСТР.одиночная_выпадающая(части) == "r-4"


def test_неубывающий_ряд_кандидата_не_даёт():
    части = [(1, "r", 2020), (2, "r-2", 2021), (3, "r-3", 2021)]
    assert ИНСТР.одиночная_выпадающая(части) == ""


def test_пара_строгим_кандидатом_не_бывает():
    """Отрицательный контроль: ремейк `berserk` 2016 → `berserk-2` 1997."""
    assert ИНСТР.одиночная_выпадающая([(1, "berserk", 2016),
                                       (2, "berserk-2", 1997)]) == ""


def test_две_выпадающие_кандидата_не_дают():
    части = [(1, "a", 2011), (2, "a-2", 2012), (3, "a-3", 2010),
             (4, "a-4", 2010)]
    assert ИНСТР.одиночная_выпадающая(части) == ""


def test_ожидаемый_диапазон_называется():
    части = [(1, "r", 2020), (2, "r-2", 2021), (3, "r-3", 2022),
             (4, "r-4", 2020), (5, "r-5", 2025)]
    assert ИНСТР._диапазон(части, "r-4") == "2022…2025"


def test_диапазон_у_крайней_части_односторонний():
    части = [(1, "r", 2020), (2, "r-2", 2021), (3, "r-3", 2015)]
    assert ИНСТР._диапазон(части, "r-3") == "не раньше 2021"


# --- год франшизы на сезоне ----------------------------------------------------

def test_год_франшизы_на_сезоне_отмечается():
    """Названная причина: сезону проставлен год ПЕРВОЙ части."""
    итог = ИНСТР.разобрать(_снимок({
        "r": 2020, "r-2": 2021, "r-3": 2022, "r-4": 2020, "r-5": 2025}))
    assert итог["строгих кандидатов"] == 1
    assert итог["из них год франшизы на сезоне"] == 1
    к = итог["строгие"][0]
    assert к["выпадает"] == "r-4" and к["это год франшизы"] is True


def test_иной_неверный_год_годом_франшизы_не_зовётся():
    """Отрицательный контроль: 1992 у третьей части — не год первой (2022)."""
    итог = ИНСТР.разобрать(_снимок({
        "u": 2022, "u-2": 2023, "u-3": 1992}))
    assert итог["строгих кандидатов"] == 1
    assert итог["из них год франшизы на сезоне"] == 0
    assert итог["строгие"][0]["это год франшизы"] is False


# --- итог и код возврата -------------------------------------------------------

def test_код_один_при_находках(tmp_path, capsys):
    п = tmp_path / "s.json"
    п.write_text(json.dumps({"details": _снимок(
        {"r": 2020, "r-2": 2021, "r-3": 2022, "r-4": 2020, "r-5": 2025})}),
        encoding="utf-8")
    assert ИНСТР.главное([str(п)]) == 1
    вывод = capsys.readouterr().out
    assert "из них год франшизы на сезоне: 1" in вывод
    assert "это год ПЕРВОЙ части франшизы" in вывод


def test_код_ноль_без_находок(tmp_path):
    п = tmp_path / "s.json"
    п.write_text(json.dumps({"details": _снимок(
        {"r": 2020, "r-2": 2021, "r-3": 2022})}), encoding="utf-8")
    assert ИНСТР.главное([str(п)]) == 0


def test_итог_называет_чего_не_означает(tmp_path, capsys):
    """Перечень — кандидаты, а не ошибки, и это обязан сказать сам вывод."""
    п = tmp_path / "s.json"
    п.write_text(json.dumps({"details": _снимок(
        {"r": 2020, "r-2": 2021, "r-3": 2022, "r-4": 2020, "r-5": 2025})}),
        encoding="utf-8")
    ИНСТР.главное([str(п)])
    вывод = capsys.readouterr().out
    assert "Это КАНДИДАТЫ" in вывод
    assert "НИЖНЯЯ ГРАНИЦА" in вывод
    assert "shikimori_id" in вывод


def test_не_снимок_отвергается(tmp_path):
    п = tmp_path / "s.json"
    п.write_text(json.dumps({"items": []}), encoding="utf-8")
    with pytest.raises(SystemExit) as ош:
        ИНСТР.записи(п)
    assert "не снимок каталога" in str(ош.value)


def test_нелепый_год_в_счёт_не_идёт():
    """Год вне 1900-2100 — это не год, и ряд им не ломается."""
    ф = ИНСТР.франшизы(_снимок({"a": 2020, "a-2": 12, "a-3": 2022}))
    assert [н for н, _, _ in ф["a"]] == [1, 3]
