# --- плотность номеров ряда ----------------------------------------------------
#
# Повод, измеренный 20.10 на киновитрине (каталог zona/lords, 67 681 запись).
# Прежние два условия строгости дали 466 кандидатов, и проверка шести вручную
# показала, что признак сгруппировал РАЗНЫЕ фильмы с числами в названиях:
#   k-9 2009, k-11 2012, k-12 2019, k-13 2019, k-19 2002  — пять разных фильмов;
#   nomer-6 … nomer-55, statya-15 … statya-99             — то же самое.
# «Цифра подтверждена названием» их не отсеивает: число в названии ЕСТЬ.


def test_плотный_ряд_франшизы_проходит():
    части = [(1, "a", 2020), (2, "a-2", 2021), (3, "a-3", 2022)]
    assert ИНСТР.ряд_плотный(части)


def test_числа_в_названиях_отсеиваются():
    """Живой случай `k-9 … k-19`: пять разных фильмов, а не франшиза."""
    части = [(9, "k-9", 2009), (11, "k-11", 2012), (12, "k-12", 2019),
             (13, "k-13", 2019), (19, "k-19", 2002)]
    assert not ИНСТР.ряд_плотный(части)


def test_ряд_с_пропуском_частей_остаётся():
    """`zabyt-proshloe` 1, 2, 5 — ПОДТВЕРЖДЁННАЯ ошибка (1909 против 2006).

    Первый порог («наибольший ≤ числа частей + 1») её терял. Потерять
    подтверждённую ошибку ради чистоты признака нельзя, поэтому порог — двойное
    число частей, и этот тест закрепляет именно тот случай, на котором первый
    порог сломался.
    """
    части = [(1, "zabyt-proshloe", 2001), (2, "zabyt-proshloe-2", 2003),
             (5, "zabyt-proshloe-5", 1909)]
    assert ИНСТР.ряд_плотный(части)


def test_порог_плотности_назван_числом_и_обоснован():
    # 55 при пяти частях — отсев; 5 при трёх частях — проход.
    assert not ИНСТР.ряд_плотный([(н, f"s{н}", 2000) for н in (6, 9, 10, 24, 55)])
    assert ИНСТР.ряд_плотный([(н, f"s{н}", 2000) for н in (1, 2, 5)])
    текст = " ".join(
        pathlib.Path(ИНСТР.__file__).read_text(encoding="utf-8").split())
    assert "zabyt-proshloe-5" in текст and "k-*" in текст


def test_неплотные_ряды_считаются_в_итоге():
    снимок = {
        "k-9": {"year": 2009, "name": "К-9"},
        "k-11": {"year": 2012, "name": "K-11"},
        "k-12": {"year": 2019, "name": "K-12"},
        "k-13": {"year": 2019, "name": "K-13"},
        "k-19": {"year": 2002, "name": "К-19"},
    }
    итог = ИНСТР.разобрать(снимок)
    assert итог["рядов отвергнуто неплотностью номеров"] == 1
    assert итог["строгих кандидатов"] == 0, "числа в названиях кандидатами не станут"
