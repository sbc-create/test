def test_сборка_переклеймляющая_авторство_не_принимается(tmp_path, capsys):
    """Самый коварный случай: правка «на месте», а дефект жив.

    Издатель читает живой файл, собирает состав — и снимает авторство у КАЖДОЙ
    записи, а не только у записей этой публикации. Так и было 12.10 в 22:47Z:
    публикация одного тайтла переписала `actor` и `reason` у трёх чужих
    записей, а тексты остались байт в байт. Прежний признак — поиск строки
    `for ключ, запись in _живые_правки(` в тексте — такого издателя принимал за
    исправного, и дефект дожил до живой витрины.
    """
    м = _модуль()
    дерево = _дерево(tmp_path / "переклейм", ИЗДАТЕЛЬ_ПЕРЕКЛЕЙМЛЯЕТ)
    код = м.главное(["--tree", str(дерево), "--skip-service"])
    вывод = capsys.readouterr().out
    assert код == 1, вывод
    assert "авторство записи вне публикации сохранено" in вывод
    assert "НЕ подтверждена" in вывод


