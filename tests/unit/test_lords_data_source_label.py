"""Метка происхождения данных обязана называть то, что на страницах.

Дефект наблюдался на всех трёх боевых витринах одновременно. Страницы отдавали
живой каталог CDNVideoHub — 53 230 записей, отпечаток
`151f0d5cdd9d06545e69426b1a61bce7bb9094b2efd35c25d51293165035fb1b`, — и при
этом печатали `<meta name="lords-data-source" content="fixture/test">`.
Значение было зашито в `factory/lords/render.py` строкой и не зависело ни от
чего.

Цена ошибки не косметическая. По этой метке делались выводы: handoff
`CORE_TO_OWNER-011` заключил «витрины отдают синтетический каталог» и назвал
это условием, которое «не снимается подписью владельца». Вывод был сделан по
метке, а не по данным, и оказался неверным — на витринах живой каталог.
Definition of Done запрещает `DONE` при test/demo данных в production, и
лгущая метка одинаково опасна в обе стороны: она может как выдумать блокер,
так и спрятать настоящий.

Рендерер знал правду всё это время: `ctx["fixture_catalog"]` управляет
баннером «Каталог синтетический» и значками карточек. На живых витринах ни
баннера, ни значков не было — только метка.
"""
from __future__ import annotations

from factory.lords import render as render_mod


class TestМеткаПроисхожденияНеЗашита:
    """Решение о метке проверяется как функция, а не через сборку всего
    документа: `_document` требует полный контекст витрины — токены темы,
    навигацию, хлебные крошки, — и восстанавливать их ради одной строки значило
    бы проверять оснастку теста, а не правило."""

    def test_живой_каталог_не_называется_фикстурой(self):
        метка = render_mod._data_source_label({"fixture_catalog": False})
        assert "fixture" not in метка, (
            f"живой каталог объявлен как «{метка}»: метка называет данные тем, "
            "чем они не являются")

    def test_фикстурный_каталог_называется_фикстурой(self):
        # Обратная сторона: живой меткой нельзя прикрыть синтетику.
        метка = render_mod._data_source_label({"fixture_catalog": True})
        assert "fixture" in метка, (
            f"синтетический каталог объявлен как «{метка}»: живая метка над "
            "выдуманными данными хуже отсутствующей")

    def test_метка_различает_два_состояния(self):
        живая = render_mod._data_source_label({"fixture_catalog": False})
        фикстура = render_mod._data_source_label({"fixture_catalog": True})
        assert живая != фикстура, (
            "метка одинакова в обоих состояниях — она ничего не сообщает")

    def test_неизвестное_состояние_не_выдаётся_за_живое(self):
        # Отсутствие признака — не разрешение объявить данные живыми.
        метка = render_mod._data_source_label({})
        assert "fixture" in метка or "unknown" in метка, (
            f"при неизвестном происхождении напечатано «{метка}»")

    def test_значение_не_зашито_в_разметку(self):
        """Страж против возврата к константе.

        Проверка смотрит в исходный текст намеренно: правило легко откатить
        одной строкой, и тогда все проверки выше останутся зелёными — они
        вызывают функцию, которую документ перестанет использовать.
        """
        import inspect
        текст = inspect.getsource(render_mod._document)
        assert 'content="fixture/test"' not in текст, (
            "метка происхождения снова зашита в документ строкой")
        assert "_data_source_label" in текст, (
            "документ не спрашивает функцию о происхождении данных")


class TestЗакреплённыйОтпечатокСовпадаетСДеревом:
    """Закрепление артефакта не должно расходиться с тем, что в дереве.

    Константа в сценарии выкладки — ворота: она не следует за кодом
    автоматически. Но расхождение обязано быть видно сразу, а не в момент
    привилегированного запуска, когда таймер уже остановлен.
    """

    def test_константа_сценария_равна_посчитанному_отпечатку(self):
        import re

        from factory.paths import PATHS
        from factory.templates import digest as digest_mod

        сценарий = PATHS.root / "automation" / "host" / "lords-canary-apply.sh"
        текст = сценарий.read_text(encoding="utf-8")
        m = re.search(r'readonly EXPECT_DIGEST="([0-9a-f]{64})"', текст)
        assert m, "закреплённый отпечаток в сценарии не найден"
        посчитанный = digest_mod.compute()["template_digest"]
        assert m.group(1) == посчитанный, (
            f"сценарий закрепляет {m.group(1)[:16]}…, а дерево даёт "
            f"{посчитанный[:16]}…: выкладка отказала бы при запуске от root")
