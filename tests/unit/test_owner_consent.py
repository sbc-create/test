"""Разрешение владельца: флаг в реестре сам по себе ничего не разрешает.

Поводом стал не вкус, а устройство прав. Разрешение жило одним полем реестра
(`cells[].indexing.open_authorized`), писателя у него в фабрике не было вовсе
(задать можно было только правкой JSON руками), а сам файл реестра принадлежит
учётной записи, под которой работают ИНСТРУМЕНТЫ: `config/site-cells.json`,
режим `rw-------`, владелец `claude`. То есть флаг мог поставить кто угодно,
кому доступен этот файл, включая модель. Проверка, которую проверяемый может
выполнить сам, защитой не является.

Второй факт — файл подтверждения в каталоге root
(`/var/lib/site-cells/owner-consent/<домен>.json`, root:root, 0444): создать
его может только root, прочитать — кто угодно. Разрешение считается данным
только при совпадении обоих фактов.
"""
from __future__ import annotations

import json
import os
import pathlib

import pytest

from factory.cell import owner_consent
from factory.qwen import editorial, indexing, registry

ДОМЕН = "t-consent.example"
САЙТ = "consent-01"


def _подтверждение(каталог: pathlib.Path, *, домен=ДОМЕН, сайт=САЙТ,
                   authorized=True, схема=1) -> pathlib.Path:
    каталог.mkdir(parents=True, exist_ok=True)
    п = каталог / f"{домен}.json"
    п.write_text(json.dumps({
        "schema_version": схема, "domain": домен, "site_id": сайт,
        "authorized": authorized, "by": "owner", "at": "2026-10-04T08:00:00Z",
        "id": "11111111-2222-3333-4444-555555555555",
        "note": "проверка"}, ensure_ascii=False), encoding="utf-8")
    return п


def _реестр(tmp: pathlib.Path, *, флаг) -> pathlib.Path:
    п = tmp / "site-cells.json"
    п.write_text(json.dumps({"cells": [{
        "site_id": САЙТ, "domain": ДОМЕН,
        "repo": {"path": "var/site-repos/нет"},
        "runtime": {"account": САЙТ},
        "indexing": ({"open_authorized": флаг, "desired_state": "CLOSED",
                      "reason": "проверка"}
                     if флаг is not None else
                     {"desired_state": "CLOSED", "reason": "проверка"}),
    }]}, ensure_ascii=False), encoding="utf-8")
    return п


@pytest.fixture()
def площадка(tmp_path, monkeypatch):
    согласия = tmp_path / "owner-consent"
    monkeypatch.setattr(owner_consent, "КОРЕНЬ", согласия)
    monkeypatch.setattr(registry, "КОРЕНЬ", tmp_path)
    editorial.сбросить_кэш_реестра()
    return {"согласия": согласия, "tmp": tmp_path, "monkeypatch": monkeypatch}


def _владелец_root(площадка):
    """Считать файл подтверждения принадлежащим root.

    В проверке файл создаёт та же учётная запись, что и тесты, поэтому
    настоящая проверка владельца отвергла бы его раньше, чем дело дошло бы до
    проверяемого утверждения. Сама проверка владельца закреплена отдельно
    (`test_файл_не_от_root_не_считается_подтверждением`), и подменять её там
    нельзя — здесь подменяется ровно она и ровно затем, чтобы проверить
    остальное.
    """
    площадка["monkeypatch"].setattr(owner_consent, "_права",
                                    lambda путь: (True, ""))


def _подключить_реестр(площадка, *, флаг):
    площадка["monkeypatch"].setattr(
        registry, "РЕЕСТР_ЯЧЕЕК", _реестр(площадка["tmp"], флаг=флаг))
    editorial.сбросить_кэш_реестра()


def test_флаг_в_реестре_без_подтверждения_не_разрешение(площадка):
    """ГЛАВНЫЙ случай: модель может записать флаг, но не файл root."""
    _подключить_реестр(площадка, флаг=True)
    разрешено, объявлен, пояснение = indexing.разрешение_владельца(САЙТ)
    assert разрешено is False, "флаг без подтверждения принят за разрешение"
    assert "ПОДТВЕРЖДЕНИЯ ВЛАДЕЛЬЦА нет" in пояснение, пояснение
    assert "authorize-indexing.sh" in пояснение, (
        "отказ обязан называть команду, которая выдаёт подтверждение")


def test_подтверждение_без_флага_тоже_не_разрешение(площадка):
    _подключить_реестр(площадка, флаг=None)
    _подтверждение(площадка["согласия"])
    разрешено, _, пояснение = indexing.разрешение_владельца(САЙТ)
    assert разрешено is False
    assert "open_authorized" in пояснение, пояснение


def test_совпадение_обоих_фактов_разрешает(площадка):
    _владелец_root(площадка)
    _подключить_реестр(площадка, флаг=True)
    _подтверждение(площадка["согласия"])
    разрешено, объявлен, пояснение = indexing.разрешение_владельца(САЙТ)
    assert разрешено is True, пояснение
    assert "подтверждено владельцем" in пояснение, пояснение
    assert объявлен == "CLOSED", "объявленный режим не трогается разрешением"


def test_чужое_подтверждение_не_открывает_домен(площадка):
    """Один файл не становится разрешением на сеть."""
    _владелец_root(площадка)
    _подключить_реестр(площадка, флаг=True)
    # Файл назван нашим домено, но ВНУТРИ объявляет другой.
    п = площадка["согласия"] / f"{ДОМЕН}.json"
    п.parent.mkdir(parents=True, exist_ok=True)
    п.write_text(json.dumps({
        "schema_version": 1, "domain": "other.example", "site_id": "other-01",
        "authorized": True, "by": "owner", "at": "2026-10-04T08:00:00Z"},
        ensure_ascii=False), encoding="utf-8")
    разрешено, _, пояснение = indexing.разрешение_владельца(САЙТ)
    assert разрешено is False
    assert "чужое подтверждение не применяется" in пояснение, пояснение


