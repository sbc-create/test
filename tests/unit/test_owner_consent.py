def test_файл_не_от_root_не_считается_подтверждением(площадка):
    """Проверяется ВЛАДЕЛЕЦ файла, а не его наличие.

    В проверке файл создаёт та же учётная запись, что и тесты, то есть uid не
    равен нулю — и этого достаточно: именно такой файл мог бы подложить кто-то
    кроме владельца. Под root проверка пропускается: там uid совпадёт.
    """
    _подключить_реестр(площадка, флаг=True)
    п = _подтверждение(площадка["согласия"])
    if п.stat().st_uid == 0:
        pytest.skip("проверка идёт от root: файл не от root не получить")
    разрешено, _, пояснение = indexing.разрешение_владельца(САЙТ)
    assert разрешено is False
    assert "не root" in пояснение, пояснение


def test_открытый_на_запись_файл_не_доказательство(площадка, monkeypatch):
    """0666 — подтверждение, которое можно переписать."""
    _подключить_реестр(площадка, флаг=True)
    п = _подтверждение(площадка["согласия"])
    п.chmod(0o666)
    # Подменяется только проверка владельца: интересует именно режим файла.
    monkeypatch.setattr(owner_consent, "_права", lambda путь: (
        (False, f"{путь} открыт на запись группе или всем")
        if путь.stat().st_mode & 0o022 else (True, "")))
    разрешено, _, пояснение = indexing.разрешение_владельца(САЙТ)
    assert разрешено is False
    assert "на запись" in пояснение, пояснение


def test_путь_подтверждения_не_строится_из_чего_угодно():
    """Имя файла — домен. Подстановка пути исключена."""
