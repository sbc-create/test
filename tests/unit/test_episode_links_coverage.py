def test_обе_формы_адреса_узнаются():
    """Lords/Zona/AnimeGo пишут через дефис, Yummy — через косую черту.

    Знать одну форму значило выдать ЧИСТЫЙ ПРОХОД по витрине с наибольшим
    трафиком: 699 ссылок на карточке `yummyani.site` не были увидены, и вывод
    сказал «ссылок не меньше объявленного ни у одной карточки».
    """
    дефис = '<a href="/title/x/season-1/episode-5/">с</a>'
    косая = '<a href="/anime/x/season/1/episode/5">с</a>'
    assert по.связанные(дефис) == {(1, 5)}
    assert по.связанные(косая) == {(1, 5)}


def test_форма_yummy_с_большими_номерами():
    """У Yummy номера серий сквозные и большие — 561, не 5."""
    разметка = '<a href="/anime/x/season/1/episode/561">с</a>'
    assert по.связанные(разметка) == {(1, 561)}


def test_упоминание_серии_без_разобранных_пар_это_предел(monkeypatch, capsys):
    """Ложное успокоение хуже ложной тревоги: тревогу проверяют, его — нет.

    Если в разметке есть `/episode`, а пар не разобрано, это «форма адреса не
    узнана», и прогон обязан сказать это вслух и сменить код возврата.
    """
    страницы = {
        "https://проба.test/sitemap.xml":
            "<loc>https://проба.test/sitemap-1.xml</loc>",
        "https://проба.test/sitemap-1.xml":
            "<loc>https://проба.test/title/один</loc>",
        # Серия без сегмента сезона: форма правдоподобная и в пары не
        # разбирается — ровно тот случай, когда молчание опасно.
        "https://проба.test/title/один":
            '<a href="/title/один/episode/4">с</a>',
    }
    monkeypatch.setattr(по, "достать",
                        lambda адрес, предел, байт=0: страницы[адрес])
    код = по.главное(["--limit", "5", "проба.test"])
    вывод = capsys.readouterr().out
    assert код == 2, вывод
    assert "НЕ ИЗМЕРЕНО" in вывод
    assert "форму" in вывод and "не узнал" in вывод
    # Область действия вывода обязана быть названа: «ни у одной карточки»
    # рядом с «не измерено: 1» успокаивает, хотя про эту карточку не известно
    # ничего.
    assert "ИЗ ИЗМЕРЕННЫХ" in вывод, вывод
    assert "ссылок не меньше объявленного ни у одной карточки" not in вывод, (
        "неузнанная форма прочиталась как чистый проход по всем карточкам")


def test_фильм_без_серий_пределом_не_считается(monkeypatch, capsys):
    """Обратная сторона: у фильма серий нет, и это нормально.

    Иначе каждый фильм в выборке давал бы «не измерено», и сигнал утонул бы.
    """
    страницы = {
        "https://проба.test/sitemap.xml":
            "<loc>https://проба.test/sitemap-1.xml</loc>",
        "https://проба.test/sitemap-1.xml":
            "<loc>https://проба.test/title/фильм</loc>",
        "https://проба.test/title/фильм":
            '<h1>Фильм</h1><a href="/catalog">каталог</a>',
    }
    monkeypatch.setattr(по, "достать",
                        lambda адрес, предел, байт=0: страницы[адрес])
    код = по.главное(["--limit", "5", "проба.test"])
    вывод = capsys.readouterr().out
    assert код == 0, вывод
    assert "НЕ ИЗМЕРЕНО" not in вывод
