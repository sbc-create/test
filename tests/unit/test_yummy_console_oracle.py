"""Оракул записей консоли: послабление ровно одно и оно не растягивается.

Зачем эта проверка существует
-----------------------------

На маршруте, который ОБЯЗАН отвечать 404, браузер сам пишет в консоль
«Failed to load resource: the server responded with a status of 404». Это
сообщение браузера о запрошенном документе, а не ошибка страницы. Считать его
дефектом значит требовать, чтобы страница 404 не отвечала 404 — и один
повторяющийся случай превращается в столько «провалов», сколько в матрице
ширин и браузеров.

Обратная ошибка дороже: простить любую запись со словом «404» значит
перестать видеть настоящие потери ресурсов. Поэтому послабление выдаётся
только при выполнении всех признаков сразу, а проверка ниже подсаживает
заведомые дефекты и требует, чтобы оракул их НЕ проглотил.

Инструмент проверяется самим собой: оракул написан на JavaScript и живёт
рядом с матрицей, поэтому вызывается тем же интерпретатором, что и в бою.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ОРАКУЛ = КОРЕНЬ / "tools" / "yummy" / "oracle.mjs"

#: Та самая запись, которую браузер делает сам на странице 404.
ЗАПИСЬ_404 = "Failed to load resource: the server responded with a status of 404 (Not Found)"


def _node() -> str:
    путь = shutil.which("node")
    if not путь:
        pytest.skip("node недоступен: оракул матрицы проверить нечем")
    return путь


def спросить(наблюдение: dict) -> dict:
    """Вызвать оракул тем же интерпретатором, что и матрица."""
    сценарий = (
        f"import {{ разобрать_консоль }} from {json.dumps(str(ОРАКУЛ))};\n"
        f"const н = {json.dumps(наблюдение, ensure_ascii=False)};\n"
        "process.stdout.write(JSON.stringify(разобрать_консоль(н)));\n"
    )
    готово = subprocess.run([_node(), "--input-type=module", "-e", сценарий],
                            capture_output=True, text=True, timeout=60)
    assert готово.returncode == 0, готово.stderr
    return json.loads(готово.stdout)


ПУСТО: dict = {"консоль": [], "исключения": [], "сбои": [], "коды": []}


class TestОжидаемый404:
    def test_на_странице_404_запись_браузера_не_дефект(self):
        итог = спросить({**ПУСТО, "status": 404, "консоль": [ЗАПИСЬ_404]})
        assert итог["реальные"] == []
        assert итог["ожидаемый"] == [ЗАПИСЬ_404]
        assert итог["ошибок"] == 0

    def test_все_признаки_названы_поимённо(self):
        итог = спросить({**ПУСТО, "status": 404, "консоль": [ЗАПИСЬ_404]})
        assert итог["признаки"] == {
            "документ_404": True, "нет_5xx": True,
            "нет_исключений": True, "нет_потерянных_запросов": True}


class TestПослаблениеНеРастягивается:
    """Каждый признак проверяется отдельно: нарушен один — послабления нет."""

    def test_на_странице_200_такая_же_запись_дефект(self):
        """200 с записью про 404 — это потерянный ресурс, а не штатный ответ."""
        итог = спросить({**ПУСТО, "status": 200, "консоль": [ЗАПИСЬ_404]})
        assert итог["реальные"] == [ЗАПИСЬ_404]
        assert итог["ошибок"] == 1

    def test_пятисотый_ответ_снимает_послабление(self):
        итог = спросить({**ПУСТО, "status": 404, "консоль": [ЗАПИСЬ_404],
                         "коды": [{"url": "/x", "status": 500}]})
        assert итог["признаки"]["нет_5xx"] is False
        assert итог["реальные"] == [ЗАПИСЬ_404]

    def test_необработанное_исключение_снимает_послабление(self):
        итог = спросить({**ПУСТО, "status": 404, "консоль": [ЗАПИСЬ_404],
                         "исключения": ["TypeError: x is not a function"]})
        assert итог["признаки"]["нет_исключений"] is False
        assert итог["реальные"] == [ЗАПИСЬ_404]
        assert итог["ошибок"] == 2

    def test_потерянный_запрос_снимает_послабление(self):
        """Отсутствующий обязательный ресурс — дефект и на странице 404."""
        итог = спросить({**ПУСТО, "status": 404, "консоль": [ЗАПИСЬ_404],
                         "сбои": [{"url": "/styles.css", "failure": "net::ERR_FAILED"}]})
        assert итог["признаки"]["нет_потерянных_запросов"] is False
        assert итог["реальные"] == [ЗАПИСЬ_404]


class TestНастоящиеОшибкиНеГлотаются:
    """На странице 404 всё остальное по-прежнему считается дефектом."""

    @pytest.mark.parametrize("запись", [
        "Uncaught TypeError: Cannot read properties of null (reading 'removeChild')",
        "Minified React error #418; visit https://react.dev/errors/418",
        "Failed to load resource: the server responded with a status of 404 "
        "(Not Found) — Uncaught ReferenceError",
        "Refused to apply style from '/app.css' because its MIME type is wrong",
        "Failed to load resource: the server responded with a status of 500",
    ])
    def test_запись_остаётся_ошибкой(self, запись):
        итог = спросить({**ПУСТО, "status": 404, "консоль": [запись]})
        assert итог["реальные"] == [запись], итог

    def test_ожидаемая_и_настоящая_разделяются(self):
        настоящая = "Uncaught TypeError: x is not a function"
        итог = спросить({**ПУСТО, "status": 404,
                         "консоль": [ЗАПИСЬ_404, настоящая]})
        assert итог["ожидаемый"] == [ЗАПИСЬ_404]
        assert итог["реальные"] == [настоящая]
        assert итог["ошибок"] == 1

    def test_потеря_ресурса_на_странице_404_видна(self):
        """404 документа прощается, 404 таблицы стилей — нет."""
        потеря = ("Failed to load resource: the server responded with a status "
                  "of 404 (Not Found)")
        итог = спросить({**ПУСТО, "status": 404, "консоль": [потеря, потеря],
                         "сбои": [{"url": "/app.css", "failure": "net::ERR_ABORTED"}]})
        # Потерянный запрос снимает послабление со всей страницы: отличить
        # 404 документа от 404 ресурса по тексту записи нельзя, а молча
        # простить оба — значит перестать видеть потерю.
        assert итог["реальные"] == [потеря, потеря]
