"""Два дефекта расписания Animedia: что закрыто, что осталось и где.

Состояние на 2026-10-15 19:30, перемерено снаружи после поправки сессии
витрины animedia.icu (её измерение я проверил независимо):

* **animedia.icu — оба дефекта закрыты** её выпуском 15:58
  (`releases/7fb87d322a67`): восемь ссылок дня, ответов не-200 ноль; карточка
  дня «доступно 2 / следующая 3» непротиворечива. Сессия витрины отдельно
  взяла десять тайтлов: у всех строка «Следующая серия» на месте и у всех
  next = доступно + 1, то есть блок жив, а не снят;
* **animedia.space — закрыт** выпусками 18:14 и 18:41: восемь ссылок, ноль
  не-200. В 16:50 там было четыре 404 из шести;
* **animeg0.site — противоречие ЖИВО**: на карточке «ДжоДжо: Гонка „Стальной
  шар“» `data-next-episode="4"` и «Следующая серия: 4 серия — 16 октября» при
  четырёх доступных сериях (сезон 7, серии 1–4). У этой витрины рантайм
  `animego-frontend.py`, и готовое решение animedia.icu к нему не подходит.

Мой патч убран: он был собран против `animedia-frontend.py` для дефекта,
который там уже закрыт. Причина — `var/animedia-patches/УСТАРЕЛО.md`.
Проверки, которые его накладывали, заменены измерением выложенного кода:
пропуск, который никто не читает, — это тихая потеря проверки.
"""
from __future__ import annotations

import importlib.util
import pathlib
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
#: Проверяется ВЫЛОЖЕННЫЙ код — он и работает у посетителя. Общая рабочая
#: копия остаётся запасным источником для окружения без /srv.
_ВЫЛОЖЕНО = pathlib.Path("/srv/animedia-icu/current/src/animedia-frontend.py")
ИСТОЧНИК = (_ВЫЛОЖЕНО if _ВЫЛОЖЕНО.is_file()
            else КОРЕНЬ / "var/site-repos/animedia-icu/src/animedia-frontend.py")
#: Патч лежит ВНЕ отслеживаемого дерева: гигиена репозитория запрещает
#: отслеживаемые *.patch (tests/unit/test_repo_hygiene.py), и для патчей в
#: проекте уже есть место в var/ — там же лежат патчи выпуска B016.
ПАТЧ = (КОРЕНЬ / "var/animedia-patches"
        / "t134-next-episode-already-released.patch")

#: Данные ДжоДжо в той форме, в которой их читает рантайм: сезон 7 с
#: доступными сериями 1–4, более ранние сезоны без доступных.
ДЖОДЖО = {"seasons": [{"number": 1, "nums": []},
                      {"number": 7, "nums": [1, 2, 3, 4]}]}


def test_номер_сезона_в_расписании_уже_исправлен():
    """Первый дефект закрыт ДРУГОЙ сессией — проверяется факт, не мой патч.

    Выпуск 15:58 15.10 (releases/7fb87d322a67) передаёт номер сезона в строку
    расписания готовым (`з["сезон"]`), а не подставляет единицу. Измерено на
    живом сайте в 16:46: все шесть ссылок дня отвечают 200, у ДжоДжо
    `/season-7/episode-4/`. Моя версия того же исправления снята, чтобы два
    решения одной задачи не расходились.
    """
    текст = ИСТОЧНИК.read_text(encoding="utf-8")
    assert 'self.адрес_эпизода(запись["slug"], з["сезон"], эпизод)' in текст, (
        "в выложенном коде нет передачи сезона в строку расписания")
    assert 'self.адрес_эпизода(запись["slug"], 1,' not in текст, (
        "зашитая единица вернулась")


def test_противоречие_осталось_только_у_animego_и_это_другой_рантайм():
    """Оставшийся случай назван точно: витрина, файл и почему не переносится.

    Без этой проверки запись «дефект закрыт» в реестре читалась бы как
    «закрыт везде», а он жив на animeg0.site. Патч animedia сюда не подходит:
    у витрины другой рантайм, и подгонять его «по похожим местам» — та самая
    догадка, из-за которой в этот день дважды выходила мёртвая правка.
    """
    import json

    реестр = json.loads((КОРЕНЬ / "config" / "seo-module-defects.json"
                         ).read_text(encoding="utf-8"))
    запись = next(з for з in реестр["defects"] if з["id"] == "MOD-29")
    assert "animeg0.site" in запись["example"]
    assert "animego-frontend.py" in запись["example"], (
        "в записи не назван рантайм витрины — переносить решение будет некуда")
    assert запись["state"] == "proposed", (
        "дефект отмечен закрытым, а он жив на animeg0.site")


def test_патч_убран_и_причина_записана():
    """Исчезнувший патч обязан оставить объяснение, а не пустое место."""
    записка = КОРЕНЬ / "var" / "animedia-patches" / "УСТАРЕЛО.md"
    if not записка.is_file():
        pytest.skip("каталог патчей вне этого окружения")
    текст = записка.read_text(encoding="utf-8")
    assert "animego-frontend.py" in текст
    assert "animedia.space" in текст and "animedia.icu" in текст
