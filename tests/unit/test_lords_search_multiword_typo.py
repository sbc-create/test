"""Опечатка в многословном запросе не находится — измеренный предел поиска.

Замер на боевом lordfilm47.space 7 сентября 2026:

    «100 дней до прощания, дорогой»  → 1 запись   (точное название)
    «100 dney do proschaniya»        → 1 запись   (транслитерация)
    «!)) lytq lj ghjofybz»           → 1 запись   (чужая раскладка)
    «ёлка» / «елка»                  → 20 записей (ё/е)
    «елкo» с латинской o             → 7 записей  (опечатка, одно слово)
    «100 днеи»                       → 0 записей  ← опечатка, два слова
    «100 днй»                        → 0 записей  ← опечатка, два слова

То есть нестрогость работает, пока запрос из ОДНОГО слова, и пропадает, как
только слов становится больше.

Причина найдена в двух местах, и оба меряют запрос целиком, а не по словам:

* `_score`: `limit = max(1, len(query) // 4)`, и дальше каждое СЛОВО названия
  сравнивается со ВСЕЙ строкой запроса. Слово «дней» никогда не окажется на
  расстоянии 2 от строки «100 днеи» — длины несопоставимы;
* `_fuzzy_candidates`: словарные слова отбираются по расстоянию до всей
  строки запроса, поэтому для многословного запроса множество кандидатов
  пусто ещё до оценки.

Починка — разбор запроса по словам на обоих уровнях: кандидаты по каждому
слову, затем требование, чтобы каждое слово запроса нашло себе слово в
названии. Это правка горячего пути: в комментариях рядом зафиксированы замеры
скорости (порог общих двубуквий выбирался против восьмисот миллисекунд на
многословном запросе), поэтому она требует собственного замера
производительности и собственного наблюдения на витрине.

Проверка ниже помечена `xfail(strict=True)`: пока предел на месте, она
проходит как ожидаемый провал, а в день починки набор упадёт и потребует
снять пометку. Так предел не забудется молча.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from factory.lords import search as search_mod  # noqa: E402


КАТАЛОГ = [
    {"slug": "100-dney", "name": "100 дней до прощания, дорогой", "original": ""},
    {"slug": "matrica", "name": "Матрица", "original": "The Matrix"},
    {"slug": "elki", "name": "Ёлки", "original": ""},
]


def _названия(запрос: str) -> list[str]:
    return [row["name"] for row in search_mod.search(КАТАЛОГ, запрос)]


class TestОдноСловоНаходитсяСОпечаткой:
    """Эта половина работает и должна работать дальше."""

    def test_точное_название(self):
        assert "Матрица" in _названия("Матрица")

    def test_опечатка_в_одном_слове(self):
        assert "Матрица" in _названия("Матриа")

    def test_чужая_раскладка(self):
        assert "Матрица" in _названия("vfnhbwf")

    def test_транслитерация(self):
        assert "Матрица" in _названия("matrica")

    def test_е_вместо_ё(self):
        assert "Ёлки" in _названия("елки")


class TestМногословнаяОпечатка:
    @pytest.mark.xfail(
        strict=True,
        reason=(
            "Предел измерен на боевой витрине: нестрогое сравнение меряет "
            "запрос целиком, поэтому опечатка в многословном запросе не "
            "находится. Починка затрагивает горячий путь отбора кандидатов и "
            "требует замера скорости — вынесена в следующий этап."
        ),
    )
    def test_опечатка_в_многословном_запросе(self):
        assert "100 дней до прощания, дорогой" in _названия("100 днеи")

    def test_без_опечатки_многословный_запрос_находится(self):
        """Контроль: дело именно в опечатке, а не в числе слов."""
        assert "100 дней до прощания, дорогой" in _названия("100 дней")
