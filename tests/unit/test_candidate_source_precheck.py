"""Кандидат без завязки в источнике до модели не доходит.

Повод измерен. За 18–25.10 фоновый редактор разобрал 1 463 материала за
$224,79 ($0,154 за материал), и 922 разбора кончились `SOURCES_MISSING`:
модель читала записанный источник и не находила, из чего писать. Тот же факт
обычный код узнаёт одним запросом карточки Shikimori. На 22 кандидатах 25.10:
завязка есть у 8, нет у 8, не измерено у 6.

Два требования равно обязательны. Первое: кандидат без завязки снимается и
уходит в `needs_source` с названной причиной — подготовка источников остаётся
отдельной задачей. Второе: «НЕ ИЗМЕРЕНО» кандидата НЕ снимает — сбой сети не
повод остановить редакционную работу, и отказ источника не доказывает
отсутствие завязки. Нарушение второго требования выглядело бы как экономия, а
было бы остановкой.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ))

from seo_operator import regular  # noqa: E402

КАНДИДАТ = {"site": "animedia.space", "slug": "x", "reason": "GAP", "weight": 3.0}


def проверка(исход: str, знаков: int = 0, причина: str = ""):
    return lambda к: (исход, знаков, причина)


def test_завязка_есть_кандидат_остаётся() -> None:
    нужны: list[dict] = []
    годные = regular.отсеять_без_завязки([dict(КАНДИДАТ)], нужны,
                                         проверка("ЗАВЯЗКА ЕСТЬ", 540))
    assert [к["slug"] for к in годные] == ["x"] and нужны == []
    assert годные[0]["source_chars"] == 540


def test_завязки_нет_кандидат_уходит_в_нужен_источник() -> None:
    нужны: list[dict] = []
    годные = regular.отсеять_без_завязки(
        [dict(КАНДИДАТ)], нужны, проверка("ЗАВЯЗКИ НЕТ", 0, "описание источника 0 знаков"))
    assert годные == []
    assert нужны[0]["slug"] == "x"
    assert "0 знаков" in нужны[0]["source_plan"]
    assert "SOURCES_MISSING" in нужны[0]["source_plan"], "причина снятия не названа"


def test_не_измерено_кандидата_не_снимает() -> None:
    """Сбой сети не повод остановить работу — иначе остановка зовётся экономией."""
    нужны: list[dict] = []
    годные = regular.отсеять_без_завязки(
        [dict(КАНДИДАТ)], нужны, проверка("НЕ ИЗМЕРЕНО", 0, "источник отказал: status 503"))
    assert [к["slug"] for к in годные] == ["x"] and нужны == []


def test_падение_самой_проверки_кандидата_не_снимает() -> None:
    def падает(к):
        raise RuntimeError("источник недоступен")

    нужны: list[dict] = []
    годные = regular.отсеять_без_завязки([dict(КАНДИДАТ)], нужны, падает)
    assert [к["slug"] for к in годные] == ["x"] and нужны == []


def test_без_инструмента_отбор_идёт_как_прежде(monkeypatch) -> None:
    monkeypatch.setattr(regular, "_проверка_завязки", lambda: None)
    нужны: list[dict] = []
    годные = regular.отсеять_без_завязки([dict(КАНДИДАТ)], нужны)
    assert годные == [КАНДИДАТ] and нужны == []


def test_инструмент_находится_по_объявленному_пути() -> None:
    assert regular.ПРОВЕРКА_ИСТОЧНИКА.is_file(), (
        f"нет инструмента проверки завязки: {regular.ПРОВЕРКА_ИСТОЧНИКА}")
    проверить = regular._проверка_завязки()
    assert проверить is not None


def test_отбор_вызван_в_сборе_кандидатов() -> None:
    """Иначе проверка есть, а работа идёт мимо неё."""
    текст = (КОРЕНЬ / "seo_operator/regular.py").read_text(encoding="utf-8")
    шаг = текст[текст.index("def step_candidates("):]
    шаг = шаг[:шаг.index("def step_queue(")]
    assert "отсеять_без_завязки(" in шаг


@pytest.mark.parametrize("исход", ["ЗАВЯЗКА ЕСТЬ", "НЕ ИЗМЕРЕНО"])
def test_исход_проверки_записан_в_кандидата(исход) -> None:
    """Отчёт должен говорить, чем кандидат подтверждён, а не «проверено»."""
    годные = regular.отсеять_без_завязки([dict(КАНДИДАТ)], [], проверка(исход, 300))
    assert годные[0]["source_check"] == исход
