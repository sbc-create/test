"""Сверка года снимка с источником: невыполнимое требование заменяется причиной.

Повод — измерение 20.10. Ворота требуют назвать в тексте год из снимка, а у
трёх записей из шести снимок расходится с `aired_on` источника
(`rukovodstvo-soten-demonov-4`: снимок 2020, источник 2024-02-23). На такой
записи требование невыполнимо честно: написать снимковый год — опубликовать
ложный факт, не написать — не пройти ворота. Черновик ждал 125 часов.

Решение согласовано с линией ячейки 20.10 и НЕ ослабляет ворота: требование
остаётся, а на записи с неподтверждённым годом оно заменяется отказом с
настоящей причиной (BLOCKED_INPUT), потому что чинить надо снимок, а не текст.

Отрицательные контроли, названные заранее:

* источник недоступен → «не измерено», поведение прежнее. Падение источника не
  должно останавливать подготовку;
* id источника в черновике нет → сверка не делается, поиск не выдумывается
  (D199);
* год совпал → ни одного нового замечания, прежнее требование в силе;
* сверка НЕ ослабляет остальные проверки: запрещённый оборот по-прежнему ловится.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))
_с = importlib.util.spec_from_file_location(
    "qwen_editorial_year", КОРЕНЬ / "factory/qwen/editorial.py")
ED = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ED)

ТЕЛО = ("«Руководство сотен демонов 4» — четвёртый сезон китайского "
        "анимационного сериала о Тао Яо, Мо Я и молодом господине Лю, "
        "который держится на мысли о близости людей и небожителей.")


# --- выделение id -------------------------------------------------------------

def test_ид_берётся_из_источников():
    assert ED._шикимори_ид(["https://shikimori.io/animes/57995"]) == "57995"
    assert ED._шикимори_ид(["https://shikimori.one/animes/42"]) == "42"


def test_без_шикимори_ида_пусто():
    """Поиск не выдумывается: нет id — нет сверки (D199)."""
    assert ED._шикимори_ид(["https://ru.wikipedia.org/wiki/Нечто"]) == ""
    assert ED._шикимори_ид([]) == ""
    assert ED._шикимори_ид(None) == ""


def test_манга_за_аниме_не_принимается():
    assert ED._шикимори_ид(["https://shikimori.io/mangas/172546"]) == ""


# --- сверка года --------------------------------------------------------------

def test_расхождение_года_видно():
    итог = ED.сверить_год_с_источником(
        "57995", 2020, читать=lambda ид: {"ok": True, "aired_on": "2024-02-23"})
    assert итог["измерено"] is True and итог["совпал"] is False
    assert итог["год_снимка"] == 2020 and итог["год_источника"] == 2024


def test_совпадение_года_видно():
    итог = ED.сверить_год_с_источником(
        "54853", 2024, читать=lambda ид: {"ok": True, "aired_on": "2024-10-13"})
    assert итог["измерено"] is True and итог["совпал"] is True


def test_недоступный_источник_это_не_измерено():
    """Отрицательный контроль: падение источника не блокирует подготовку."""
    итог = ED.сверить_год_с_источником(
        "57995", 2020, читать=lambda ид: {"ok": False, "почему": "таймаут"})
    assert итог["измерено"] is False
    assert "таймаут" in итог["почему"]


def test_источник_без_даты_это_не_измерено():
    итог = ED.сверить_год_с_источником(
        "1", 2020, читать=lambda ид: {"ok": True, "aired_on": None})
    assert итог["измерено"] is False
    assert "нет даты выхода" in итог["почему"]


def test_без_года_в_снимке_сверка_не_делается():
    assert ED.сверить_год_с_источником("1", None)["измерено"] is False


# --- как это попадает в замечания подготовки ----------------------------------

class _Сайт:
    domain = "x.site"
    adapter = "editorial"
    handover_state = "released"
    handover_reason = ""


@pytest.fixture()
def площадка(tmp_path, monkeypatch):
    monkeypatch.setattr(ED, "_сайт", lambda site, **кв: _Сайт())
    monkeypatch.setattr(ED, "_каталог", lambda s: tmp_path)
    monkeypatch.setattr(ED, "_требует", lambda s, оп: None)
    monkeypatch.setattr(ED.actors, "проверить", lambda автор, оп: None)
    monkeypatch.setattr(ED, "факты", lambda site, slug: {
        "title_id": "t1", "source": "снимок",
        "facts": {"name": "Руководство сотен демонов 4", "year": 2020}})
    return tmp_path


def _подготовить(площадка, *, читать, тело=ТЕЛО):
    return ED.подготовить("x.site", "slug-a", тело, author="claude/test",
                          источники=["https://shikimori.io/animes/57995"],
                          сверка_года=читать)


def test_невыполнимое_требование_заменяется_причиной(площадка):
    итог = _подготовить(площадка,
                        читать=lambda ид: {"ok": True, "aired_on": "2024-02-23"})
    беды = итог["quality_problems"]
    assert итог["state"] == "prepared"
    assert not any("нет года" in б for б in беды), беды
    причина = [б for б in беды if "не подтверждён источником" in б]
    assert причина, беды
    assert "в снимке 2020" in причина[0] and "2024-02-23" in причина[0]
    assert "BLOCKED_INPUT" in причина[0]


def test_при_совпадении_года_прежнее_требование_в_силе(площадка):
    """Отрицательный контроль: сверка не отменяет требование назвать год."""
    итог = _подготовить(площадка,
                        читать=lambda ид: {"ok": True, "aired_on": "2020-05-01"})
    беды = итог["quality_problems"]
    assert any("нет года 2020" in б for б in беды), беды
    assert not any("не подтверждён источником" in б for б in беды)


def test_недоступный_источник_оставляет_прежнее_поведение(площадка):
    итог = _подготовить(площадка,
                        читать=lambda ид: {"ok": False, "почему": "сеть"})
    беды = итог["quality_problems"]
    assert any("нет года 2020" in б for б in беды), беды
    assert not any("не подтверждён источником" in б for б in беды)


def test_остальные_проверки_не_ослаблены(площадка):
    """Запрещённый оборот ловится и при расхождении года."""
    тело = ТЕЛО + " Сериал доступен для просмотра на платформе."
    итог = _подготовить(площадка, тело=тело,
                        читать=lambda ид: {"ok": True, "aired_on": "2024-02-23"})
    беды = итог["quality_problems"]
    assert any("обещает то, чего снимок не подтверждает" in б
               for б in беды), беды
    assert any("не подтверждён источником" in б for б in беды), беды


def test_отпечаток_и_замечания_попадают_в_журнал(площадка):
    _подготовить(площадка, читать=lambda ид: {"ok": True,
                                              "aired_on": "2024-02-23"})
    журнал = [json.loads(с) for с
              in (площадка / ED.ИСТОРИЯ).read_text(encoding="utf-8").splitlines()
              if с.strip()]
    запись = [з for з in журнал if з.get("op") == "prepare"][-1]
    assert запись["body_digest"] == ED.отпечаток(ED.обрезать(ТЕЛО))
    assert any("не подтверждён источником" in б for б in запись["problems"])
