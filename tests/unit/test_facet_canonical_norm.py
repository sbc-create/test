"""Норма фасета: canonical страницы с условием отбора.

Повод. 11 октября в замер впервые попали поверхности `/year/<гггг>/` и
`/country/<код>/` — до этого они не мерились вовсе. Оказалось, что у четырёх
витрин Lords и трёх AnimeGo первая страница фасета объявляет канонической
`/catalog/`: условие отбора из canonical СБРОШЕНО, и цель показывает другой
набор карточек (общих 0-1 из 45-48). Это §1 п.4 замороженной базы — canonical
не указывает на нерелевантную страницу, — и касается не только страниц
пагинации, а самой первой страницы поверхности.

Почему норма не повторяет п.3 и не живёт в списке исключений:

* расхождение п.3 (`?page=2` → canonical на раздел) записано решением D202 как
  известное и спорное — там canonical ведёт на страницу ТОГО ЖЕ отбора;
* здесь отбор теряется, и канонической становится страница другого состава.
  Спорных прочтений у этого нет, поэтому проверка жёсткая сразу для всех.

Две формы canonical признаются нормой, и различить их можно только походом по
цели — поэтому норма ходит:

* **на себя** (так у Lords сделан `/genre/<код>/`);
* **на другую схему адреса** (`/catalog/?year=2024`), если цель отвечает 200 и
  состав совпадает. Так сделаны Animedia и Zona, и это сведение дублей к одной
  схеме (п.1), а не потеря поверхности.

Сеть мерится без сети: `достать` подменяется таблицей ответов.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

ФАСЕТ = "https://x.test/year/2024/"
КАТАЛОГ = "https://x.test/catalog/"
КАТАЛОГ_С_ГОДОМ = "https://x.test/catalog/?year=2024"
ПУСТО = "<html></html>"


def _карточки(префикс: str, сколько: int = 48) -> str:
    return "".join(f'<a href="/title/{префикс}-{i}">' for i in range(сколько))


def _страница(канон: str, префикс: str, сколько: int = 48) -> str:
    return (f'<link rel="canonical" href="{канон}"/>'
            + _карточки(префикс, сколько))


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    def __init__(self, таблица: dict):
        self.таблица = таблица
        self.запрошено: list[str] = []

    def __call__(self, url: str, таймаут: int = 45):
        self.запрошено.append(url)
        код, тело, итоговый = self.таблица.get(url, ("404", ПУСТО, url))
        return код, тело, {"итоговый-адрес": итоговый}


def прогнать(тело_фасета: str, цели: dict | None = None):
    """Норма фасета на одном разделе, без остальных проверок."""
    м = _модуль()
    таблица = {ФАСЕТ: ("200", тело_фасета, ФАСЕТ)}
    таблица.update(цели or {})
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    набор = set(f"/title/facet-{i}" for i in range(48))
    м.норма_фасета("x.test", "/year/2024/", ФАСЕТ, набор, тело_фасета,
                   lambda имя, ок, подробно: шаги.append((имя, ок, подробно)))
    (шаг,) = шаги
    return шаг


def test_canonical_на_себя_это_норма():
    _имя, ок, подробно = прогнать(_страница(ФАСЕТ, "facet"))
    assert ок is True
    assert "на себя" in подробно


def test_canonical_на_себя_без_завершающего_слеша_тоже_норма():
    """Витрина вправе писать canonical без слеша — это тот же адрес."""
    _имя, ок, _п = прогнать(_страница(ФАСЕТ.rstrip("/"), "facet"))
    assert ок is True


def test_canonical_на_другую_схему_с_тем_же_составом_это_норма():
    """Так сделаны Animedia и Zona: фасет сведён к схеме запроса."""
    цель = _страница(КАТАЛОГ_С_ГОДОМ, "facet")
    _имя, ок, подробно = прогнать(
        _страница(КАТАЛОГ_С_ГОДОМ, "facet"),
        {КАТАЛОГ_С_ГОДОМ: ("200", цель, КАТАЛОГ_С_ГОДОМ)})
    assert ок is True
    assert "сведение схем" in подробно


def test_canonical_сбросивший_условие_это_расхождение():
    """Ровно то, что нашлось у Lords и AnimeGo."""
    каталог = _страница(КАТАЛОГ, "catalog")
    _имя, ок, подробно = прогнать(
        _страница(КАТАЛОГ, "facet"),
        {КАТАЛОГ: ("200", каталог, КАТАЛОГ)})
    assert ок is False
    assert "СОСТАВ РАЗНЫЙ" in подробно
    assert "общих 0" in подробно


def test_состав_сверяется_по_слагам_а_не_по_числу_карточек():
    """У Lords `/year/2024/` и `/catalog/` отдают по 48 карточек — разных.

    Проверка по длине страницы или по числу карточек пропустила бы этот
    случай целиком: совпадает и то, и другое.
    """
    каталог = _страница(КАТАЛОГ, "catalog", 48)
    _имя, ок, подробно = прогнать(
        _страница(КАТАЛОГ, "facet", 48),
        {КАТАЛОГ: ("200", каталог, КАТАЛОГ)})
    assert ок is False
    assert "у фасета 48, у цели 48" in подробно


def test_частичное_пересечение_состава_тоже_расхождение():
    """Цель, где карточки фасета лишь частично, канонической не является."""
    смесь = ('<link rel="canonical" href="' + КАТАЛОГ + '"/>'
             + "".join(f'<a href="/title/facet-{i}">' for i in range(10))
             + _карточки("catalog", 38))
    _имя, ок, подробно = прогнать(
        _страница(КАТАЛОГ, "facet"), {КАТАЛОГ: ("200", смесь, КАТАЛОГ)})
    assert ок is False
    assert "общих 10" in подробно


def test_цель_не_отвечающая_двумястами_это_расхождение():
    _имя, ок, подробно = прогнать(
        _страница("https://x.test/year/1999/", "facet"))
    assert ок is False
    assert "не отвечает 200" in подробно


def test_отсутствие_canonical_это_расхождение():
    _имя, ок, подробно = прогнать(_карточки("facet"))
    assert ок is False
    assert "отсутствует" in подробно


def test_норма_ходит_по_цели_ровно_один_раз():
    """Тело фасета уже прочитано вызывающим — норма его не перезапрашивает."""
    м = _модуль()
    тело = _страница(КАТАЛОГ, "facet")
    сеть = Сеть({КАТАЛОГ: ("200", _страница(КАТАЛОГ, "catalog"), КАТАЛОГ)})
    м.достать = сеть
    м.норма_фасета("x.test", "/year/2024/", ФАСЕТ,
                   {f"/title/facet-{i}" for i in range(48)}, тело,
                   lambda *_а: None)
    assert сеть.запрошено == [КАТАЛОГ]


def test_фасетами_считаются_только_поверхности_с_условием_в_адресе():
    м = _модуль()
    assert "/year/2024/".startswith(м.ФАСЕТЫ)
    assert "/country/rossiya/".startswith(м.ФАСЕТЫ)
    assert "/genre/drama/".startswith(м.ФАСЕТЫ)
    # У каталога и разделов вида терять в canonical нечего.
    assert not "/catalog/".startswith(м.ФАСЕТЫ)
    assert not "/movies/".startswith(м.ФАСЕТЫ)
    assert not "/new/".startswith(м.ФАСЕТЫ)


def test_все_фасеты_из_перечня_мерятся():
    """Поверхность, которой нет в перечне разделов, не мерится вовсе.

    Так `/animation/` у всех одиннадцати витрин оставался непроверенным, и так
    же фасеты года и страны не мерились до 11.10.
    """
    м = _модуль()
    фасеты_в_замере = [р for р in м.РАЗДЕЛЫ_ПАГИНАЦИИ if р.startswith(м.ФАСЕТЫ)]
    assert "/year/2024/" in фасеты_в_замере
    assert "/country/rossiya/" in фасеты_в_замере
    assert "/genre/drama/" in фасеты_в_замере
