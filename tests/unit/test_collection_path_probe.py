"""Порог признака воспроизведения в проверке публичного пути.

Две беды этой проверки измерены 27.10, и обе были в ней, а не на витрине.
Первая: читалась `window.__pmLastPos` — переменной с таким именем нет ни в
одном рантайме, то есть при плеере в чужом кадре проверка не могла ответить
«играет» никогда. Вторая: признаком считалась позиция больше нуля, а
поставщик после ОДНОГО нажатия отдаёт один `timeupdate` с позицией 0.09 и
держит её 45 секунд при состоянии `ready` — источник разрешён, картинка стоит.

Здесь закрепляется порог: воспроизведение — это РОСТ позиции либо метка
`playing` самой витрины. Сеть не нужна: решение принимает одна функция.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "collection-path-probe.py"


@pytest.fixture(scope="module")
def модуль():
    спец = importlib.util.spec_from_file_location("collection_path_probe", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


class Страница:
    """Страница, у которой спрашивают только состояние плеера."""

    def __init__(self, состояние: str = "ready"):
        self.состояние = состояние
        self.спросили = 0

    def evaluate(self, _код):  # noqa: D401 — подмена playwright
        self.спросили += 1
        return {"состояние": self.состояние, "плашка": "",
                "события поставщика": []}


def test_позиция_без_роста_не_воспроизведение(модуль):
    """Ровно тот случай, что измерен: 0.09 пришла и не растёт."""
    с = Страница("ready")
    assert модуль._идёт(с, 0.09, 0.09) is False


def test_рост_позиции_это_воспроизведение(модуль):
    с = Страница("ready")
    assert модуль._идёт(с, 0.09 + модуль.РОСТ_С, 0.09) is True


def test_рост_меньше_порога_не_считается(модуль):
    с = Страница("ready")
    assert модуль._идёт(с, 0.3, 0.09) is False


def test_метка_витрины_сильнее_порога(модуль):
    """Рантайм ставит `playing` только при позиции от трёх секунд: если он уже
    признал показ, спорить с ним нечем."""
    с = Страница("playing")
    assert модуль._идёт(с, 0.0, None) is True


def test_позиции_не_было_вовсе(модуль):
    с = Страница("resolving")
    assert модуль._идёт(с, 0.0, None) is False


def test_придуманной_переменной_в_проверке_нет(модуль):
    """`__pmLastPos` не должен вернуться: имя взято не из рантайма."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    тело = текст.split('"""', 2)[2] if текст.count('"""') >= 2 else текст
    строки = [с for с in тело.splitlines()
              if "__pmLastPos" in с and not с.lstrip().startswith("#")
              and "Прежняя версия" not in с]
    assert строки == [], строки


def test_перехват_читает_события_поставщика(модуль):
    """Позиция у плеера в чужом кадре приходит сообщением — перехват обязан
    стоять ДО загрузки страницы и брать её из `timeupdate`."""
    assert "cdnvideohub" in модуль.ПЕРЕХВАТ
    assert "timeupdate" in модуль.ПЕРЕХВАТ
    assert "data.position" in модуль.ПЕРЕХВАТ.replace("данные.position",
                                                      "data.position")
