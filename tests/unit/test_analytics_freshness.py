"""Статусы аналитики и свежесть артефакта сбора.

Отчёт о посещаемости опасен не ошибкой в числе, а тем, что число из
позавчерашнего сбора выглядит как сегодняшнее. Поэтому здесь проверяется не
«считает правильно», а четыре вида подмены: устаревшее за свежее, отказ в праве
за отсутствие связи, неизвестная причина за известную и отсутствие измерения за
нулевую посещаемость.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "analytics-freshness.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("analytics_freshness",
                                                  ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    sys.modules["analytics_freshness"] = м
    спец.loader.exec_module(м)
    return м


св = _модуль()


def артефакт(tmp_path: Path, измерения: list[dict], *,
             собрано: str = "2026-10-12T10:11:27Z") -> Path:
    путь = tmp_path / "cabinet-latest.json"
    путь.write_text(json.dumps({
        "collected_at": собрано,
        "period": {"date1": "7daysAgo", "date2": "yesterday"},
        "domains": [{"domain": "проба.test", "measurements": измерения}],
    }, ensure_ascii=False), encoding="utf-8")
    return путь


def прогон(путь: Path, *ещё: str) -> int:
    return св.главное(["--artifact", str(путь), *ещё])


def test_отказ_в_праве_не_попадает_в_недоступность_сети():
    """Два разных исхода, и смешать их значило бы искать не ту причину.

    «Сеть недоступна» ведёт к проверке связи, «отказано в праве» — к проверке
    токена. Образец ошибки доступа обязан проверяться РАНЬШЕ: текст отказа
    часто содержит и то слово, и другое.
    """
    имя, _ = св.статус({"measured": False,
                        "reason": "webmaster: HTTP 403, доступ запрещён. "
                                  "Повторы исчерпаны"})
    assert имя == св.ОШИБКА_ДОСТУПА, имя

    имя, _ = св.статус({"measured": False,
                        "reason": "webmaster: сеть недоступна (URLError). "
                                  "Повторы исчерпаны"})
    assert имя == св.ИСТОЧНИК_НЕДОСТУПЕН, имя


def test_неизвестная_причина_видна_и_меняет_код(tmp_path, capsys):
    """Новый вид сбоя не должен уходить в известную корзину.

    Иначе «источник недоступен: 86» читалось бы как прежняя беда, а это был бы
    другой отказ, о котором никто не узнает.
    """
    путь = артефакт(tmp_path, [
        {"key": "visitors", "measured": True, "value": 50},
        {"key": "bounce", "measured": False,
         "reason": "провайдер вернул ответ неизвестного вида"},
    ])
    код = прогон(путь, "--now", "2026-10-12T12:00:00Z")
    вывод = capsys.readouterr()
    весь = вывод.out + вывод.err
    assert код == 3, весь
    assert "ПРИЧИНА_НЕ_РАЗОБРАНА" in вывод.out
    assert "неизвестного вида" in вывод.out, "причина не напечатана целиком"
    assert "статусы неполны" in вывод.err


def test_неизмеренное_без_причины_известным_не_считается():
    """Худший случай: ни значения, ни причины. Отдельной корзины он не получает."""
    имя, довод = св.статус({"measured": False, "reason": ""})
    assert имя == св.ПРИЧИНА_НЕ_РАЗОБРАНА
    assert "не названа" in довод


def test_настоящий_ноль_это_данные():
    """Нулевая посещаемость — измерение, а не сбой.

    Две витрины сети дают ровно 0 посетителей при живом счётчике, и записать
    это в ошибки значило бы потерять факт.
    """
    имя, _ = св.статус({"key": "visitors", "measured": True, "value": 0.0})
    assert имя == св.ИЗМЕРЕНО


def test_устаревшие_данные_это_отдельный_исход(tmp_path, capsys):
    путь = артефакт(tmp_path, [{"key": "visitors", "measured": True,
                                "value": 10}],
                    собрано="2026-10-10T05:00:00Z")
    код = прогон(путь, "--now", "2026-10-12T21:00:00Z",
                 "--max-age-hours", "24")
    вывод = capsys.readouterr()
    assert код == 1, вывод.out + вывод.err
    assert "УСТАРЕЛИ" in вывод.out
    assert "вчерашнее как сегодняшнее" in вывод.err


def test_в_пределах_срока_данные_свежие(tmp_path, capsys):
    """Обратная сторона: иначе инструмент объявлял бы устаревшим всё."""
    путь = артефакт(tmp_path, [{"key": "visitors", "measured": True,
                                "value": 10}],
                    собрано="2026-10-12T10:00:00Z")
    код = прогон(путь, "--now", "2026-10-12T21:00:00Z",
                 "--max-age-hours", "24")
    вывод = capsys.readouterr()
    assert код == 0, вывод.out + вывод.err
    assert "СВЕЖИЕ" in вывод.out


def test_нет_артефакта_это_не_нулевая_посещаемость(tmp_path, capsys):
    код = прогон(tmp_path / "нет-такого.json")
    вывод = capsys.readouterr()
    assert код == 2
    assert "не «нулевая посещаемость»" in вывод.err


def test_неразобранная_метка_сбора_свежестью_не_считается(tmp_path, capsys):
    """Без метки свежесть НЕ ИЗМЕРЕНА, а не «свежо».

    Молчаливое «свежо» при неразобранной метке и есть та подмена, от которой
    инструмент создан.
    """
    путь = артефакт(tmp_path, [{"key": "visitors", "measured": True,
                                "value": 10}],
                    собрано="позавчера")
    код = прогон(путь, "--now", "2026-10-12T21:00:00Z")
    вывод = capsys.readouterr()
    assert код == 2, вывод.out + вывод.err
    assert "НЕ ИЗМЕРЕНА" in вывод.err
    assert "СВЕЖИЕ" not in вывод.out


def test_часовой_пояс_берётся_из_паспорта(tmp_path, capsys):
    """Пояс называется из данных, а не предполагается.

    Отчёт без пояса не позволяет сверить сутки с чужой выгрузкой, а
    подставленный пояс сдвинул бы границы суток молча.
    """
    путь = артефакт(tmp_path, [
        {"key": "counter_passport", "measured": True,
         "value": {"id": 1, "time_zone_name": "Europe/Moscow"}},
    ])
    прогон(путь, "--now", "2026-10-12T12:00:00Z")
    вывод = capsys.readouterr()
    assert "Europe/Moscow" in вывод.out

    пустой = артефакт(tmp_path, [{"key": "visitors", "measured": True,
                                  "value": 1}])
    прогон(пустой, "--now", "2026-10-12T12:00:00Z")
    вывод = capsys.readouterr()
    assert "НЕ НАЙДЕН в артефакте" in вывод.out


def test_живой_артефакт_разобран_полностью():
    """На настоящих данных сети неразобранных причин быть не должно.

    Если появятся — это и есть сигнал, ради которого статус существует.
    """
    if not св.АРТЕФАКТ.is_file():
        import pytest
        pytest.skip("артефакта сбора на машине нет")
    код = св.главное(["--artifact", str(св.АРТЕФАКТ),
                      "--max-age-hours", "100000"])
    assert код == 0, (
        "на живом артефакте остались неразобранные причины — посмотрите вывод "
        "analytics-freshness.py: появился новый вид сбоя")
