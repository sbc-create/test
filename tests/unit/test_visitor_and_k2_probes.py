def test_перенаправление_битой_ссылкой_не_считается(monkeypatch):
    """308 на карточке — штатное поведение, а не дефект.

    С 22.10 у перенаправления проверяется ЦЕЛЬ, поэтому тест подменяет и
    второй шаг: без этого он уходил в сеть, получал 0 и объявлял штатное
    перенаправление битой ссылкой. Замысел теста при этом не изменился.
    """
