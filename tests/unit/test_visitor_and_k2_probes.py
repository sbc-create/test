"""Поверхность посетителя и готовность K2: две меры, два класса ложных находок.

У поверхности посетителя ложная находка уже случалась этой ночью: полка без
КАРТОЧЕК объявлялась пустой, и проход назвал пустыми «Жанры» и «Подборки» —
законные хабы, где ссылки ведут на фасеты. Поэтому здесь закреплены два разных
состояния: `пустая` (ни одной ссылки) и `без карточек` (ссылки есть, карточек
нет), и второе находкой не является.

У готовности K2 ложная находка тоже случалась: путь данных читался из поля
`data` вместо `runtime.data_dir`, и проход печатал «каталог данных не назван» у
всех восьми витрин подряд — признак, дающий один ответ независимо от предмета.
Плюс витрины живут на другом узле, и это третье состояние, а не ноль.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


def _модуль(имя: str, файл: str):
    спец = importlib.util.spec_from_file_location(имя, КОРЕНЬ / файл)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


ПОСЕТИТЕЛЬ = _модуль("visitor_surface_probe",
                     "automation/local/visitor-surface-probe.py")
K2 = _модуль("k2_readiness_probe", "automation/local/k2-readiness-probe.py")


# --- поверхность посетителя -----------------------------------------------------


def test_хаб_со_ссылками_пустой_полкой_не_считается():
    """«Жанры» и «Подборки» ведут на фасеты: карточек нет, но раздел полон."""
    тело = ("<h2>Жанры</h2><div>"
            '<a href="/catalog/?genre=drama">драма</a>'
            '<a href="/catalog/?genre=comedy">комедия</a></div>'
            "<h2>Новинки</h2><div><a href='/title/a/'>A</a></div>")
    пустые, без_карточек = ПОСЕТИТЕЛЬ.полки(тело)
    assert пустые == []
    assert без_карточек == ["Жанры"]


def test_полка_без_единой_ссылки_это_пустая_полка():
    тело = "<h2>Новости</h2><div>пока ничего</div><h2>Каталог</h2><div><a href='/title/a/'>A</a></div>"
    пустые, без_карточек = ПОСЕТИТЕЛЬ.полки(тело)
    assert пустые == ["Новости"]
    assert без_карточек == []


def test_технические_фразы_ищутся_в_тексте_а_не_в_разметке():
    """`null` внутри JSON-LD — норма, в абзаце — нет."""
    с_данными = ('<script type="application/ld+json">{"a": null}</script>'
                 "<p>Обычный текст</p>")
    текст = ПОСЕТИТЕЛЬ.текст_страницы(с_данными)
    assert "null" not in текст
    в_абзаце = ПОСЕТИТЕЛЬ.текст_страницы("<p>Значение: undefined</p>")
    assert "undefined" in в_абзаце


