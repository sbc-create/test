"""Поверхность посетителя и готовность K2: две меры, два класса ложных находок.

У поверхности посетителя ложная находка уже случалась этой ночью: полка без
КАРТОЧЕК объявлялась пустой, и проход назвал пустыми «Жанры» и «Подборки» —
законные хабы, где ссылки ведут на фасеты. Поэтому здесь закреплены два разных
состояния: `пустая` (ни одной ссылки) и `без карточек` (ссылки есть, карточек
нет), и второе находкой не является.

У готовности K2 ложная находка тоже случалась: путь данных читался из поля
`data` вместо `runtime.data_dir`, и проход печатал «каталог данных не назван» у
всех восьми витрин подряд — признак, дающий один ответ независимо от предмета.
Плюс витрины живут на другом узле, и это третье состояние, а не ноль.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]


def _модуль(имя: str, файл: str):
    спец = importlib.util.spec_from_file_location(имя, КОРЕНЬ / файл)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


ПОСЕТИТЕЛЬ = _модуль("visitor_surface_probe",
                     "automation/local/visitor-surface-probe.py")
K2 = _модуль("k2_readiness_probe", "automation/local/k2-readiness-probe.py")


# --- поверхность посетителя -----------------------------------------------------


def test_хаб_со_ссылками_пустой_полкой_не_считается():
    """«Жанры» и «Подборки» ведут на фасеты: карточек нет, но раздел полон."""
    тело = ("<h2>Жанры</h2><div>"
            '<a href="/catalog/?genre=drama">драма</a>'
            '<a href="/catalog/?genre=comedy">комедия</a></div>'
            "<h2>Новинки</h2><div><a href='/title/a/'>A</a></div>")
    пустые, без_карточек = ПОСЕТИТЕЛЬ.полки(тело)
    assert пустые == []
    assert без_карточек == ["Жанры"]


def test_полка_без_единой_ссылки_это_пустая_полка():
    тело = "<h2>Новости</h2><div>пока ничего</div><h2>Каталог</h2><div><a href='/title/a/'>A</a></div>"
    пустые, без_карточек = ПОСЕТИТЕЛЬ.полки(тело)
    assert пустые == ["Новости"]
    assert без_карточек == []


def test_технические_фразы_ищутся_в_тексте_а_не_в_разметке():
    """`null` внутри JSON-LD — норма, в абзаце — нет."""
    с_данными = ('<script type="application/ld+json">{"a": null}</script>'
                 "<p>Обычный текст</p>")
    текст = ПОСЕТИТЕЛЬ.текст_страницы(с_данными)
    assert "null" not in текст
    в_абзаце = ПОСЕТИТЕЛЬ.текст_страницы("<p>Значение: undefined</p>")
    assert "undefined" in в_абзаце


def test_служебные_ссылки_в_выборку_не_попадают():
    тело = ('<a href="/api/x">api</a><a href="/poster/1">постер</a>'
            '<a href="/__debug">служебное</a><a href="/catalog/">каталог</a>')
    assert ПОСЕТИТЕЛЬ.ссылки(тело) == ["/catalog/"]


def test_битая_ссылка_это_замечание(monkeypatch):
    тело = '<a href="/catalog/">каталог</a><a href="/битая/">битая</a>'
    monkeypatch.setattr(ПОСЕТИТЕЛЬ, "достать",
                        lambda адрес, таймаут=40: (200, тело))
    monkeypatch.setattr(ПОСЕТИТЕЛЬ, "код",
                        lambda адрес, таймаут=30: 404 if "битая" in адрес else 200)
    итог = ПОСЕТИТЕЛЬ.проверить("x.test", 10)
    assert len(итог["битых"]) == 1
    assert any("битых ссылок 1" in з for з in итог["замечания"])


def test_перенаправление_битой_ссылкой_не_считается(monkeypatch):
    """308 на карточке — штатное поведение, а не дефект."""
    тело = '<a href="/catalog/">каталог</a>'
    monkeypatch.setattr(ПОСЕТИТЕЛЬ, "достать",
                        lambda адрес, таймаут=40: (200, тело))
    monkeypatch.setattr(ПОСЕТИТЕЛЬ, "код", lambda адрес, таймаут=30: 308)
    итог = ПОСЕТИТЕЛЬ.проверить("x.test", 10)
    assert итог["битых"] == []


def test_выборка_ссылок_повторяема(monkeypatch):
    """Семя фиксировано: два прогона сравнимы, иначе «стало лучше» недоказуемо."""
    ссылки = "".join(f'<a href="/catalog/?p={н}">{н}</a>' for н in range(60))
    monkeypatch.setattr(ПОСЕТИТЕЛЬ, "достать",
                        lambda адрес, таймаут=40: (200, ссылки))
    monkeypatch.setattr(ПОСЕТИТЕЛЬ, "код", lambda адрес, таймаут=30: 200)
    первый = ПОСЕТИТЕЛЬ.проверить("x.test", 10)
    второй = ПОСЕТИТЕЛЬ.проверить("x.test", 10)
    assert первый["ссылок_проверено"] == второй["ссылок_проверено"] == 10


# --- готовность K2 --------------------------------------------------------------


def test_данные_на_другом_узле_это_третье_состояние(tmp_path):
    """«Каталога нет» означало бы отсутствие данных, а не предел измерения."""
    ячейка = {"runtime": {"data_dir": str(tmp_path / "нет-такого")},
              "deploy_target": {"ref": "k2-zomro-01"}}
    ответ = K2.свежесть(ячейка)
    assert "k2-zomro-01" in ответ
    assert "НЕ ИЗМЕРЯЕТСЯ" in ответ


def test_путь_данных_читается_из_runtime(tmp_path):
    """Первая редакция читала поле `data` и печатала одно и то же у всех восьми."""
    каталог = tmp_path / "data"
    каталог.mkdir()
    (каталог / "lords-13-catalog.json").write_text(
        json.dumps({"builtAt": "2026-10-21T03:00:00Z", "items": [1, 2, 3]}),
        encoding="utf-8")
    ячейка = {"runtime": {"data_dir": str(каталог)},
              "data": {"database": None, "media": None},
              "deploy_target": {"ref": "local"}}
    ответ = K2.свежесть(ячейка)
    assert "3 записей" in ответ
    assert "2026-10-21T03:00:00Z" in ответ


def test_главная_без_карточек_это_замечание(monkeypatch):
    monkeypatch.setattr(K2, "достать",
                        lambda адрес, таймаут=40: (200, "<html><body></body></html>"))
    monkeypatch.setattr(K2, "свежесть", lambda ячейка: "—")
    итог = K2.проверить("lordfilm.group", {"lordfilm.group": {}})
    assert any("карточек нет" in з for з in итог["замечания"])


def test_перечень_витрин_совпадает_с_заданием():
    """Восемь новых K2, названных владельцем, и ни одной лишней."""
    assert len(K2.ВИТРИНЫ) == 8
    assert set(K2.ВИТРИНЫ.values()) == {f"lords-{н}" for н in range(10, 18)}
    assert "lordfilm.group" in K2.ВИТРИНЫ and "lordserial.net.ru" in K2.ВИТРИНЫ
