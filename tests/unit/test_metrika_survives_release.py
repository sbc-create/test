"""Счётчик Метрики обязан переживать выпуск и перенос витрины в ячейку.

История дефекта. При переносе витрин в ячейки значение счётчика потерялось у
четырёх доменов: оно было объявлено ТОЛЬКО в drop-in монолитной службы
(`/etc/systemd/system/<юнит>.service.d/metrika.conf`), а юнит ячейки drop-in
монолита не наследует. Переменная оставалась пустой, рантайм не выводил
разметку, и публичный HTTP 200 этого не показывал.

Отсюда требование: у витрины, которая сама отрисовывает страницы, счётчик
объявлен В ЕЁ РЕПОЗИТОРИИ. Тогда выпуск переносит его вместе с кодом, а
состояние хоста перестаёт быть единственным местом, где он живёт.

Семейство, проксирующее сторонее приложение (Yummy), — отдельный случай и не
исключение «чтобы прошло»: разметку отдаёт приложение выше по потоку, ячейка
передаёт её как есть. Измерено: контейнер на 3103 и ячейка на 9130 отдают
одинаковые байты с тем же `ym("111881039","init")`. Требовать объявления
переменной у такой витрины значило бы требовать мёртвую настройку.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
АНАЛИТИКА = КОРЕНЬ / "config" / "analytics.json"
ЯЧЕЙКИ = КОРЕНЬ / "config" / "site-cells.json"

#: Переменная, из которой рантайм семейств lords/zona берёт идентификатор.
ПЕРЕМЕННАЯ = "LORDS_METRIKA_COUNTER"
#: Признак витрины, проксирующей сторонее приложение.
ПРОКСИ = "LORDS_LEGACY_UPSTREAM"


def реестр_аналитики() -> list[dict]:
    return json.loads(АНАЛИТИКА.read_text(encoding="utf-8"))["properties"]


def ячейки() -> dict[str, dict]:
    return {c["site_id"]: c for c in json.loads(ЯЧЕЙКИ.read_text(encoding="utf-8"))["cells"]}


def со_счётчиком() -> list[tuple[dict, dict, Path]]:
    """Домены, у которых есть и счётчик, и своя ячейка с рабочей копией."""
    я = ячейки()
    итог = []
    for з in реестр_аналитики():
        if not з.get("counter_id"):
            continue
        ячейка = я.get(з.get("site_id") or "")
        if not ячейка:
            continue
        путь = КОРЕНЬ / ((ячейка.get("repo") or {}).get("path") or "")
        if (путь / "config" / "site.json").is_file():
            итог.append((з, ячейка, путь))
    return итог


def конфиг(путь: Path) -> dict:
    return json.loads((путь / "config" / "site.json").read_text(encoding="utf-8"))


def test_есть_что_проверять() -> None:
    """Пустая выборка сделала бы все проверки ниже зелёными и бессмысленными."""
    найдено = со_счётчиком()
    assert len(найдено) >= 4, f"витрин со счётчиком и ячейкой найдено {len(найдено)}"


@pytest.mark.parametrize("домен", [з["domain"] for з, _, _ in со_счётчиком()])
def test_счётчик_объявлен_в_репозитории_витрины(домен: str) -> None:
    з, _ячейка, путь = next(т for т in со_счётчиком() if т[0]["domain"] == домен)
    окружение = конфиг(путь).get("environment") or {}
    if ПРОКСИ in окружение:
        # Разметку отдаёт приложение выше по потоку. Требование к репозиторию
        # здесь неприменимо, а проверка счётчика — на публичной странице.
        pytest.skip(f"{домен}: витрина проксирует {окружение[ПРОКСИ]}, "
                    "разметку счётчика отдаёт приложение выше по потоку")
    # Объявление читается в ДВУХ местах, потому что семейства объявляют его
    # по-разному, и требовать одну форму значило бы проверять форму, а не
    # свойство. Свойство одно: счётчик записан в репозитории витрины, а не
    # живёт только в drop-in службы — именно так он и пропал у четырёх доменов.
    #
    #   environment.LORDS_METRIKA_COUNTER — Lords, Zona: лаунчер отдаёт
    #       окружение рантайму как есть;
    #   analytics.counter_id (+ analytics.enabled) — AnimeGo: лаунчер
    #       подставляет счётчик, только если аналитика включена И значение
    #       задано, чтобы выдуманный идентификатор не увёл статистику домена в
    #       чужой кабинет.
    аналитика = конфиг(путь).get("analytics") or {}
    из_аналитики = аналитика.get("counter_id") if аналитика.get("enabled") else None
    объявлено = окружение.get(ПЕРЕМЕННАЯ) or из_аналитики
    assert объявлено, (
        f"{домен}: счётчик не объявлен в config/site.json — ни "
        f"environment.{ПЕРЕМЕННАЯ}, ни включённый analytics.counter_id. "
        "Значение, живущее только в drop-in службы, теряется при переносе в "
        "ячейку — именно так счётчик и пропал у четырёх доменов."
    )
    assert str(объявлено) == str(з["counter_id"]), (
        f"{домен}: в репозитории {объявлено}, в реестре аналитики {з['counter_id']}"
    )


#: Код, который РИСУЕТ тег в отдельном процессе. Прежняя версия этой проверки
#: искала имя переменной в тексте `src/*.py` — то есть проверяла существование
#: кода, а не его поведение. Упоминание переменной в комментарии прошло бы её
#: так же успешно, как рабочий вызов, а мёртвая настройка выглядит рабочей ровно
#: до первого отчёта Метрики.
РИСОВАЛЬЩИК = """
import importlib.util, os, re, sys
спец = importlib.util.spec_from_file_location("fe", sys.argv[1])
м = importlib.util.module_from_spec(спец)
# Регистрация ДО исполнения: рантайм обращается к sys.modules[__name__] на
# импорте, и без записи падает с KeyError: 'fe'. Та же ошибка описана в
# lords-deploy-broker, и я повторил её здесь.
sys.modules["fe"] = м
спец.loader.exec_module(м)
тег = м.тег_метрики()
print("%d %d %d %d" % (
    len(тег), len(re.findall(r"ym\\(", тег)),
    int("__sfMetrikaReady" in тег),
    int(('data-metrika-counter="%s"' % os.environ.get("LORDS_METRIKA_COUNTER", "")) in тег)))
"""

#: Заведомо не существующий счётчик. Нужен только внутри временного процесса и
#: ни в один реестр, отчёт или юнит не попадает.
ПРОБНЫЙ_СЧЁТЧИК = "77777777"


def _манифест_репозитория(репозиторий: Path) -> str:
    """Собственный манифест шаблона витрины, если он в репозитории есть.

    Нужен затем, что рантайм animego больше не берёт манифест по умолчанию:
    прежнее умолчание вело на файл СОСЕДНЕЙ витрины, и при незаданной переменной
    AnimeGo поднимался бы на чужом оформлении. Умолчание убрано — значит тест
    обязан подать тот же файл, что подаёт `run.py` в работе. Это не придуманный
    вход: файл лежит в самом репозитории витрины.
    """
    for кандидат in (репозиторий / "config" / "template-manifest.json",
                     репозиторий / "template-manifest.json"):
        if кандидат.is_file():
            return str(кандидат)
    return ""


def _нарисовать(файл: Path, значение: str, манифест: str = "") -> tuple[int, int, int, int]:
    import os  # noqa: PLC0415
    import subprocess  # noqa: PLC0415
    import sys  # noqa: PLC0415

    # Окружение задаётся ЯВНО и целиком, а не наследуется от процесса тестов.
    #
    # Причина конкретная. Прогон целиком роняло на `animedia-icu`: его рантайм
    # берёт манифест из `ANIMEDIA_TEMPLATE_MANIFEST`, а при её отсутствии — из
    # `LORDS_TEMPLATE_MANIFEST`, и какой-то из соседних тестов оставляет вторую
    # в окружении процесса. Рантайм читал манифест семейства lords и честно
    # отказывался работать: «этот рантайм обслуживает только семейство
    # animedia». По отдельности файл проходил, в общем прогоне падал.
    #
    # Тест измеряет тег как функцию ОДНОЙ переменной, поэтому всё остальное
    # окружение здесь — источник ложных результатов, а не удобство.
    среда = {
        "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
        "HOME": os.environ.get("HOME", "/tmp"),
        "LANG": os.environ.get("LANG", "C.UTF-8"),
        "PYTHONDONTWRITEBYTECODE": "1",
        "LORDS_METRIKA_COUNTER": значение,
    }
    if манифест:
        среда["LORDS_TEMPLATE_MANIFEST"] = манифест
    r = subprocess.run([sys.executable, "-c", РИСОВАЛЬЩИК, str(файл)],
                       capture_output=True, text=True, env=среда, timeout=180)
    if r.returncode != 0 and "the following arguments are required" in (r.stderr + r.stdout):
        # Рантайм разбирает аргументы командной строки на импорте, поэтому тег
        # нельзя нарисовать в изоляции. Подставлять аргументы нельзя: это
        # придуманный вход. Случай назван, а не замолчан.
        pytest.skip(f"{файл.parent.parent.name}: рантайм требует аргументов "
                    "командной строки на импорте — тег в изоляции не рисуется")
    assert r.returncode == 0, f"{файл.name}: рисовальщик упал — {r.stderr[-400:]}"
    числа = r.stdout.strip().splitlines()[-1].split()
    return tuple(int(ч) for ч in числа)  # type: ignore[return-value]


def _витрины_с_тегом() -> list[tuple[Path, Path]]:
    """Точка входа берётся из `config/site.json`, а не из имени файла.

    Отбор по маске `src/lords-frontend.py` был неверен с двух сторон сразу:

    * он ЗАХВАТЫВАЛ `animedia-icu`, где файл с таким именем лежит, но точка
      входа объявлена другая, а сам файл на импорте отказывает словами «этот
      рантайм обслуживает только семейство animedia»;
    * и ПРОПУСКАЛ `lordfilm47-space` и `lordserial33-biz`, у которых точки
      входа называются `lords01-frontend.py` и `lords02-frontend.py`, — то есть
      две действующие витрины оставались непроверенными.

    Имя файла не источник истины о том, чем обслуживается домен; реестр —
    источник.
    """
    итог = []
    for конфиг_путь in sorted((КОРЕНЬ / "var" / "site-repos").glob("*/config/site.json")):
        репозиторий = конфиг_путь.parent.parent
        точка = json.loads(конфиг_путь.read_text(encoding="utf-8")).get("entrypoint")
        if not точка:
            continue
        файл = репозиторий / "src" / точка
        if not файл.is_file():
            continue
        if "def тег_метрики" not in файл.read_text(encoding="utf-8", errors="replace"):
            continue
        итог.append((репозиторий, файл))
    return итог


ВИТРИНЫ_С_ТЕГОМ = _витрины_с_тегом()


def test_есть_чем_проверить_отрисовку() -> None:
    assert len(ВИТРИНЫ_С_ТЕГОМ) >= 4, (
        f"витрин с собственным рантаймом найдено {len(ВИТРИНЫ_С_ТЕГОМ)}")


@pytest.mark.parametrize("репозиторий,файл", ВИТРИНЫ_С_ТЕГОМ,
                         ids=lambda з: з.name if isinstance(з, Path) else str(з))
def test_рантайм_рисует_тег_ровно_один_раз(репозиторий: Path, файл: Path) -> None:
    """Проверяется отрисовка, а не наличие строки в исходнике.

    Три свойства, каждое из которых однажды ломалось или могло сломаться:

    * пустое значение даёт страницу БЕЗ тега, а не тег, который молчит:
      молчащий тег неотличим от работающего до первого отчёта;
    * при заданном счётчике инициализация ровно одна — иначе один визит
      посчитается дважды;
    * в теге стоит именно тот идентификатор, который дан в окружении.
    """
    манифест = _манифест_репозитория(репозиторий)
    длина, инициализаций, защёлка, признак = _нарисовать(файл, "", манифест)
    assert длина == 0, f"{репозиторий.name}: без счётчика тег всё равно нарисован"

    длина, инициализаций, защёлка, признак = _нарисовать(файл, ПРОБНЫЙ_СЧЁТЧИК, манифест)
    assert длина > 0, f"{репозиторий.name}: со счётчиком тег не нарисован"
    assert инициализаций == 1, (
        f"{репозиторий.name}: инициализаций {инициализаций}, а не одна — "
        "визит посчитается столько же раз")
    assert защёлка, (
        f"{репозиторий.name}: в теге нет защёлки от повторной инициализации; "
        "страница, прошедшая двумя путями разметки, даст двойной счёт")
    assert признак, f"{репозиторий.name}: в теге нет данного идентификатора"


def test_счётчик_не_приписан_двум_доменам() -> None:
    счётчики = [з["counter_id"] for з in реестр_аналитики() if з.get("counter_id")]
    assert len(set(счётчики)) == len(счётчики), f"счётчик повторяется: {счётчики}"


def test_каждая_витрина_с_доменом_есть_в_реестре_аналитики() -> None:
    """Домен без записи не попадает ни в аудит, ни в план — и это незаметно.

    Именно так zonafilm.cc и animedia.icu, работающие публично, не значились в
    реестре аналитики вовсе.
    """
    домены = {з["domain"] for з in реестр_аналитики()}
    пропущены = []
    for site_id, ячейка in ячейки().items():
        домен = ячейка.get("domain") or ""
        # Локальные стенды в аналитике не нужны: они никуда не смотрят наружу.
        if not домен or домен.endswith((".localhost", ".localhost.test", ".test")):
            continue
        if домен not in домены:
            пропущены.append(f"{site_id} ({домен})")
    assert not пропущены, f"витрины вне реестра аналитики: {пропущены}"
