"""Счётчик Метрики обязан переживать выпуск и перенос витрины в ячейку.

История дефекта. При переносе витрин в ячейки значение счётчика потерялось у
четырёх доменов: оно было объявлено ТОЛЬКО в drop-in монолитной службы
(`/etc/systemd/system/<юнит>.service.d/metrika.conf`), а юнит ячейки drop-in
монолита не наследует. Переменная оставалась пустой, рантайм не выводил
разметку, и публичный HTTP 200 этого не показывал.

Отсюда требование: у витрины, которая сама отрисовывает страницы, счётчик
объявлен В ЕЁ РЕПОЗИТОРИИ. Тогда выпуск переносит его вместе с кодом, а
состояние хоста перестаёт быть единственным местом, где он живёт.

Семейство, проксирующее сторонее приложение (Yummy), — отдельный случай и не
исключение «чтобы прошло»: разметку отдаёт приложение выше по потоку, ячейка
передаёт её как есть. Измерено: контейнер на 3103 и ячейка на 9130 отдают
одинаковые байты с тем же `ym("111881039","init")`. Требовать объявления
переменной у такой витрины значило бы требовать мёртвую настройку.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
АНАЛИТИКА = КОРЕНЬ / "config" / "analytics.json"
ЯЧЕЙКИ = КОРЕНЬ / "config" / "site-cells.json"

#: Переменная, из которой рантайм семейств lords/zona берёт идентификатор.
ПЕРЕМЕННАЯ = "LORDS_METRIKA_COUNTER"
#: Признак витрины, проксирующей сторонее приложение.
ПРОКСИ = "LORDS_LEGACY_UPSTREAM"


def реестр_аналитики() -> list[dict]:
    return json.loads(АНАЛИТИКА.read_text(encoding="utf-8"))["properties"]


def ячейки() -> dict[str, dict]:
    return {c["site_id"]: c for c in json.loads(ЯЧЕЙКИ.read_text(encoding="utf-8"))["cells"]}


def со_счётчиком() -> list[tuple[dict, dict, Path]]:
    """Домены, у которых есть и счётчик, и своя ячейка с рабочей копией."""
    я = ячейки()
    итог = []
    for з in реестр_аналитики():
        if not з.get("counter_id"):
            continue
        ячейка = я.get(з.get("site_id") or "")
        if not ячейка:
            continue
        путь = КОРЕНЬ / ((ячейка.get("repo") or {}).get("path") or "")
        if (путь / "config" / "site.json").is_file():
            итог.append((з, ячейка, путь))
    return итог


def конфиг(путь: Path) -> dict:
    return json.loads((путь / "config" / "site.json").read_text(encoding="utf-8"))


def test_есть_что_проверять() -> None:
    """Пустая выборка сделала бы все проверки ниже зелёными и бессмысленными."""
    найдено = со_счётчиком()
    assert len(найдено) >= 4, f"витрин со счётчиком и ячейкой найдено {len(найдено)}"


@pytest.mark.parametrize("домен", [з["domain"] for з, _, _ in со_счётчиком()])
def test_счётчик_объявлен_в_репозитории_витрины(домен: str) -> None:
    з, _ячейка, путь = next(т for т in со_счётчиком() if т[0]["domain"] == домен)
    окружение = конфиг(путь).get("environment") or {}
    if ПРОКСИ in окружение:
        # Разметку отдаёт приложение выше по потоку. Требование к репозиторию
        # здесь неприменимо, а проверка счётчика — на публичной странице.
        pytest.skip(f"{домен}: витрина проксирует {окружение[ПРОКСИ]}, "
                    "разметку счётчика отдаёт приложение выше по потоку")
    объявлено = окружение.get(ПЕРЕМЕННАЯ)
    assert объявлено, (
        f"{домен}: {ПЕРЕМЕННАЯ} не объявлена в config/site.json. Значение, "
        "живущее только в drop-in службы, теряется при переносе в ячейку — "
        "именно так счётчик и пропал у четырёх доменов."
    )
    assert str(объявлено) == str(з["counter_id"]), (
        f"{домен}: в репозитории {объявлено}, в реестре аналитики {з['counter_id']}"
    )


@pytest.mark.parametrize("домен", [з["domain"] for з, _, _ in со_счётчиком()])
def test_рантайм_читает_переменную(домен: str) -> None:
    """Объявление без чтения — мёртвая настройка, которая выглядит рабочей."""
    з, _ячейка, путь = next(т for т in со_счётчиком() if т[0]["domain"] == домен)
    окружение = конфиг(путь).get("environment") or {}
    if ПРОКСИ in окружение:
        pytest.skip(f"{домен}: разметку отдаёт приложение выше по потоку")
    исходники = list((путь / "src").glob("*.py"))
    assert исходники, f"{домен}: в репозитории нет src/*.py"
    читают = [п.name for п in исходники
              if ПЕРЕМЕННАЯ in п.read_text(encoding="utf-8", errors="replace")]
    assert читают, f"{домен}: ни один файл в src/ не читает {ПЕРЕМЕННАЯ}"


def test_счётчик_не_приписан_двум_доменам() -> None:
    счётчики = [з["counter_id"] for з in реестр_аналитики() if з.get("counter_id")]
    assert len(set(счётчики)) == len(счётчики), f"счётчик повторяется: {счётчики}"


def test_каждая_витрина_с_доменом_есть_в_реестре_аналитики() -> None:
    """Домен без записи не попадает ни в аудит, ни в план — и это незаметно.

    Именно так zonafilm.cc и animedia.icu, работающие публично, не значились в
    реестре аналитики вовсе.
    """
    домены = {з["domain"] for з in реестр_аналитики()}
    пропущены = []
    for site_id, ячейка in ячейки().items():
        домен = ячейка.get("domain") or ""
        # Локальные стенды в аналитике не нужны: они никуда не смотрят наружу.
        if not домен or домен.endswith((".localhost", ".localhost.test", ".test")):
            continue
        if домен not in домены:
            пропущены.append(f"{site_id} ({домен})")
    assert not пропущены, f"витрины вне реестра аналитики: {пропущены}"
