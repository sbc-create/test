"""Откат конфигурации nginx обязан сообщать о СВОЁМ провале.

Прежняя редакция глотала оба отказа через `|| true`: и неудачное копирование
отдельного файла, и непрохождение `nginx -t` после восстановления. Оператор
видел «возврат конфигурации из …» и больше ничего, тогда как восстановленная
конфигурация могла быть нерабочей, а nginx продолжал отдавать прежнюю. Правило
проекта прямое: наличие файла бэкапа доказательством восстановления не считается.

Проверки исполняют СОБСТВЕННЫЙ текст функции из сценария, а не его копию:
копия разошлась бы с оригиналом, и проверка стала бы проверять себя.
`nginx` и `cp` подменены заглушками — предмет измерения здесь сообщения и код
возврата, а не работа nginx.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "host" / "wire-nginx-upstream.sh"


def текст_функции(имя: str) -> str:
    """Текст функции из сценария: от `имя() {` до строки ровно `}`."""
    строки = СЦЕНАРИЙ.read_text(encoding="utf-8").splitlines()
    собрано: list[str] = []
    внутри = False
    for строка in строки:
        if not внутри:
            if строка.startswith(f"{имя}() {{"):
                внутри = True
                собрано.append(строка)
            continue
        собрано.append(строка)
        if строка == "}":
            return "\n".join(собрано)
    raise AssertionError(f"функция {имя} в {СЦЕНАРИЙ.name} не найдена")


@pytest.fixture()
def стенд(tmp_path):
    """Заглушки nginx и cp плюс окружение, которое читает функция."""
    заглушки = tmp_path / "bin"
    заглушки.mkdir()

    def положить(имя: str, тело: str) -> None:
        путь = заглушки / имя
        путь.write_text(тело, encoding="utf-8")
        путь.chmod(0o755)

    копии = tmp_path / "backup" / "метка"
    копии.mkdir(parents=True)
    (копии / "сайт.conf").write_text("server {}\n", encoding="utf-8")
    цель = tmp_path / "конфигурации"
    цель.mkdir()
    (цель / "сайт.conf").write_text("сломано\n", encoding="utf-8")

    среда = dict(os.environ)
    среда["PATH"] = f"{заглушки}:{среда.get('PATH', '')}"
    среда["BACKUP_ROOT"] = str(tmp_path / "backup")
    среда["stamp"] = "метка"
    return {"положить": положить, "среда": среда,
            "цель": цель / "сайт.conf", "копии": копии}


def прогон(стенд, тело_nginx: str, *, cp_отказывает: bool = False):
    стенд["положить"]("nginx", тело_nginx)
    if cp_отказывает:
        стенд["положить"]("cp", "#!/bin/sh\nexit 1\n")
    сценарий = (
        "set -uo pipefail\n"
        f"configs=('{стенд['цель']}')\n"
        + текст_функции("restore")
        + "\nrestore\n"
    )
    return subprocess.run(["/bin/bash", "-c", сценарий], env=стенд["среда"],
                          capture_output=True, text=True, timeout=120)


def test_непрохождение_проверки_после_отката_названо(стенд):
    """Самый опасный исход: откат сделан, а конфигурация нерабочая."""
    готово = прогон(стенд, "#!/bin/sh\nexit 1\n")
    assert готово.returncode != 0, готово.stderr
    assert "ОТКАТ НЕ ЗАВЕРШЁН" in готово.stderr
    assert "nginx -t" in готово.stderr
    # Оператору сказано, что именно продолжает работать и где лежат копии.
    assert "ПРЕЖНЕЙ" in готово.stderr
    assert "backup/метка" in готово.stderr


def test_успешный_откат_говорит_что_завершён(стенд):
    """Без этого предыдущая проверка прошла бы и у отката, падающего всегда."""
    готово = прогон(стенд, "#!/bin/sh\nexit 0\n")
    assert готово.returncode == 0, готово.stderr
    assert "откат завершён" in готово.stderr
    assert "ОТКАТ НЕ ЗАВЕРШЁН" not in готово.stderr


def test_отказ_перезагрузки_отличается_от_отказа_проверки(стенд):
    """`nginx -t` прошёл, а `reload` отказал — это другой исход.

    Смешать их значило бы искать не ту причину: один ведёт к конфигурации,
    другой к состоянию процесса.
    """
    тело = '#!/bin/sh\ncase "$1" in\n  -t) exit 0 ;;\n  -s) exit 1 ;;\nesac\nexit 0\n'
    готово = прогон(стенд, тело)
    assert готово.returncode != 0, готово.stderr
    assert "reload отказал" in готово.stderr
    assert "не проходит nginx -t" not in готово.stderr


def test_невосстановленный_файл_назван_по_имени(стенд):
    """Копирование отдельного файла тоже могло не состояться."""
    готово = прогон(стенд, "#!/bin/sh\nexit 0\n", cp_отказывает=True)
    assert готово.returncode != 0, готово.stderr
    assert "НЕ ВОССТАНОВЛЕН" in готово.stderr
    assert "сайт.conf" in готово.stderr


def test_код_отката_гасится_только_названно():
    """Вызов под `set -e` обязан гасить код НАМЕРЕННО и с объяснением.

    Иначе ненулевой возврат оборвал бы сценарий до `die`, и оператор потерял
    бы главную причину — ради которой весь откат и запускался.
    """
    текст = СЦЕНАРИЙ.read_text(encoding="utf-8")
    assert "restore || true" in текст, (
        "вызов отката не гасит код — под set -e сценарий оборвётся до die")
    место = текст.index("restore || true")
    рядом = текст[max(0, место - 400):место]
    assert "НАМЕРЕННО" in рядом, (
        "гашение кода не объяснено рядом с вызовом; молчаливое `|| true` и "
        "было исходным дефектом")
