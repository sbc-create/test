"""REQ-RATING-ENRICHMENT: обогащение готово, источника нет — и это видно.

Измерено на снимке каталога 7 сентября, 53 257 записей, единый знаменатель:
идентификатор Кинопоиска есть у 87,7 %, оценка — у 36,8 %. Половина каталога,
50,9 %, имеет идентификатор и не имеет оценки. Голоса не передаются вовсе.

Первый вопрос был не «как добрать», а «не теряем ли мы». Проверены 755
детальных ответов поставщика по записям с идентификатором и без оценки: оценки
нет ни в одном. Данных нет у источника.

Поэтому здесь проверяется машинерия, а не числа: очередь, лестница
сопоставления, отказ несуществующего источника, отрицательный кэш и то, что
ничего не выдумывается.
"""

from __future__ import annotations

import pytest

from factory.site_engine import rating_enrichment as об


@pytest.fixture()
def хранилище(tmp_path):
    return об.Хранилище(root=tmp_path)


def _запись(**поля):
    основа = {"external_id": "e1", "name": "Матрица", "original_name": "The Matrix",
              "year": 1999, "is_series": False, "external_ids": {"kinopoisk": "301"},
              "kinopoisk_rating": None}
    основа.update(поля)
    return основа


# --- наблюдения --------------------------------------------------------------

def test_наблюдение_без_источника_не_принимается(хранилище):
    with pytest.raises(об.EnrichmentError, match="неизвестно кем"):
        хранилище.добавить_наблюдение(об.Наблюдение(
            content_id="e1", metric="kinopoisk", value=7.8, scale=10.0,
            source="", legal_basis=""))


def test_значение_вне_шкалы_не_принимается(хранилище):
    with pytest.raises(об.EnrichmentError, match="шкалу"):
        хранилище.добавить_наблюдение(об.Наблюдение(
            content_id="e1", metric="kinopoisk", value=88.0, scale=10.0,
            source="feed", legal_basis="договор"))


def test_нестрогое_совпадение_не_записывается(хранилище):
    """Ремейк и одноимённое произведение сливаются молча — и это не чинится."""
    with pytest.raises(об.EnrichmentError, match="ремейк"):
        хранилище.добавить_наблюдение(об.Наблюдение(
            content_id="e1", metric="kinopoisk", value=7.8, scale=10.0,
            source="feed", legal_basis="договор",
            match_method=об.Способ.КАНДИДАТ.value))


def test_журнал_только_дополняется(хранилище):
    for значение, когда in ((7.8, "2026-09-01T00:00:00Z"), (7.9, "2026-09-02T00:00:00Z")):
        хранилище.добавить_наблюдение(об.Наблюдение(
            content_id="e1", metric="kinopoisk", value=значение, scale=10.0,
            source="feed", legal_basis="договор", observed_at=когда))
    наблюдения = хранилище.наблюдения()
    assert len(наблюдения) == 2, "прежнее наблюдение переписано — объяснять изменение нечем"
    текущее = хранилище.текущие()[("e1", "kinopoisk")]
    assert текущее["value"] == 7.9


# --- очередь -----------------------------------------------------------------

def test_доли_очереди_соблюдаются():
    сейчас = 1_800_000_000_000
    свежие = [_запись(external_id=f"н{н}", updated_at_ms=сейчас - 1000) for н in range(50)]
    популярные = [_запись(external_id=f"п{н}", popular=True) for н in range(50)]
    хвост = [_запись(external_id=f"х{н}") for н in range(200)]
    задания = об.распределить(свежие + популярные + хвост, бюджет=100, сейчас_ms=сейчас)
    по_долям = {}
    for з in задания:
        по_долям[з.bucket] = по_долям.get(з.bucket, 0) + 1
    assert по_долям.get("свежие") == 40
    assert по_долям.get("популярные") == 25
    assert по_долям.get("хвост", 0) >= 25, "хвост не уменьшается — он не разберётся никогда"
    assert len(задания) == 100


def test_записи_с_оценкой_в_очередь_не_попадают():
    задания = об.распределить([_запись(kinopoisk_rating=7.8)], бюджет=10)
    assert задания == []


def test_недобор_доли_отдаётся_хвосту():
    хвост = [_запись(external_id=f"х{н}") for н in range(100)]
    задания = об.распределить(хвост, бюджет=50)
