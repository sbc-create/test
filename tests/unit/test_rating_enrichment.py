def test_покрытие_считается_на_одном_знаменателе(хранилище):
    записи = [_запись(external_id="a", kinopoisk_rating=7.0),
              _запись(external_id="b"), _запись(external_id="c")]
    хранилище.добавить_наблюдение(об.Наблюдение(
        content_id="b", metric="kinopoisk", value=6.5, scale=10.0,
        source="feed", legal_basis="договор"))
    из = об.покрытие(записи, хранилище)
    assert из["denominator"] == 3
    assert из["fromFeed"] == 1 and из["fromEnrichment"] == 1
    assert из["coveragePercent"] == pytest.approx(66.7, abs=0.1)
