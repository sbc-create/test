"""Characterization: адрес из названия — до переноса и после.

`slugify` превращает название в адрес страницы. Живёт она в
`factory/lords/live_catalog.py`, то есть внутри семейства витрин, а нужна
управляющему контуру: `adapters/lords_seo_binding` берёт её оттуда. Этот
единственный импорт держит цикл `site_engine ↔ lords`, а цикл означает, что ни
одну из подсистем нельзя вынести, не вынеся вторую.

Функция при этом не знает ни одной витрины: это чистое преобразование текста.

Цена ошибки здесь выше обычной. Вывод этой функции — адреса страниц на трёх
боевых доменах. Изменение одного символа переименовало бы страницы, поломало
внешние ссылки и заставило поисковики переиндексировать каталог из 52 тысяч
записей. Поэтому проверок много и они мелочные: перенос обязан не изменить
ничего.

Все случаи взяты из боевых адресов и из устройства самой функции.
"""

from __future__ import annotations

import pytest

from factory.lords.live_catalog import slugify

#: Адреса, которые сейчас отдают боевые витрины. Проверялись браузером.
БОЕВЫЕ = [
    ("Матрица (1999)", "matrica-1999"),
    ("Ведьмак", "vedmak"),
    ("100 дней до прощания, дорогой", "100-dney-do-proschaniya-dorogoy"),
]


class TestБоевыеАдресаНеМеняются:
    @pytest.mark.parametrize("название,адрес", БОЕВЫЕ,
                             ids=[а for _, а in БОЕВЫЕ])
    def test_адрес_совпадает_с_выложенным(self, название, адрес):
        assert slugify(название) == адрес, (
            "адрес изменился: страницы переименуются, внешние ссылки умрут, "
            "а поисковикам придётся переиндексировать каталог заново")


class TestПравилаПреобразования:
    def test_пусто_на_входе_пусто_на_выходе(self):
        assert slugify("") == ""
        assert slugify("   ") == ""

    def test_регистр_опускается(self):
        assert slugify("МАТРИЦА") == "matrica"

    def test_кириллица_транслитерируется(self):
        assert slugify("щука") == "schuka"
        assert slugify("ёж") == slugify("ёж")

    def test_пробелы_и_знаки_становятся_дефисом(self):
        assert slugify("а б") == "a-b"
        assert slugify("а, б") == "a-b", "два знака подряд дают один дефис"

    def test_дефисы_по_краям_срезаются(self):
        assert not slugify("—точка—").startswith("-")
        assert not slugify("—точка—").endswith("-")

    def test_длина_ограничена_восемьюдесятью(self):
        длинное = "очень " * 40
        assert len(slugify(длинное)) <= 80

    def test_цифры_сохраняются(self):
        assert slugify("2024 год") == "2024-god"

    def test_незнакомая_письменность_пропускает_символ_а_не_запись(self):
        """Иероглиф не должен обнулять весь адрес."""
        assert slugify("你好 матрица") == "matrica", (
            "символ незнакомой письменности выбросил и остальное название")

    def test_только_незнакомая_письменность_даёт_пусто(self):
        assert slugify("你好") == ""


class TestУстойчивость:
    def test_повторный_вызов_даёт_то_же(self):
        for название in ("Матрица (1999)", "а б в", "", "Ёлки-2"):
            assert slugify(название) == slugify(название)

    def test_адрес_пригоден_для_url(self):
        for название, _ in БОЕВЫЕ:
            адрес = slugify(название)
            assert all(с.isalnum() and с.isascii() or с == "-" for с in адрес), (
                f"в адресе {адрес!r} есть символ, непригодный для URL")
