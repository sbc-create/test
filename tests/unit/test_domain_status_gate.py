"""Выведенный из работы домен не получает ни задачи, ни выпуска.

ПОВОД, измеренный 27.10. `animedia.space` выведен владельцем из активной
работы 2026-10-25 и переведён в `awaiting_replacement` в
`config/active-domains.json`. Реестр ячеек `config/site-cells.json`, по
которому идёт ВЫПУСК, остался со `status: live`. Два источника правды
разошлись, путь выпуска читал тот, который не обновили, и на выведенный домен
уехали два выпуска подряд.

Причина не в невнимательности: до этой проверки статус домена на пути работы
не спрашивался ВООБЩЕ — ни при назначении задачи, ни перед подачей заявки.

ЧТО ЗАЩИЩАЕТСЯ ЗДЕСЬ.

1. Заявка на выпуск для выведенного домена отвергается ДО любой работы.
2. Для активного домена та же проверка молчит — иначе она остановила бы сеть.
3. Отсутствие домена в реестре отказом НЕ считается: так выглядит витрина,
   которую ещё только заводят.
4. Расхождение двух реестров видно числом. Именно оно пропустило выпуск, и
   тест называет его поимённо, а не «в целом».
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ВОРОТА = КОРЕНЬ / "automation" / "local" / "domain-status-gate.py"


@pytest.fixture(scope="module")
def ворота():
    спец = importlib.util.spec_from_file_location("domain_status_gate", ВОРОТА)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


@pytest.fixture(scope="module")
def очередь():
    from factory.cell import queue as q
    return q


def _выведенные() -> list[dict]:
    данные = json.loads((КОРЕНЬ / "config" / "active-domains.json")
                        .read_text(encoding="utf-8"))
    return данные.get("awaiting_replacement") or []


def test_выведенные_домены_в_реестре_есть():
    """Пустой раздел превратил бы остальные тесты в молчаливое «ок»."""
    assert _выведенные(), "раздел awaiting_replacement пуст — проверять нечего"


@pytest.mark.parametrize("запись", _выведенные(),
                         ids=lambda з: str(з.get("domain")))
def test_заявка_на_выведенный_домен_отвергается(очередь, запись):
    with pytest.raises(очередь.RequestRejected) as сбой:
        очередь.проверить_статус_домена(str(запись["site_id"]))
    assert "выведен владельцем" in str(сбой.value)


def test_активный_домен_проходит(очередь):
    """Проверка обязана молчать на активной витрине: иначе она остановит сеть."""
    очередь.проверить_статус_домена("animedia-01")
    очередь.проверить_статус_домена("zona-01")


def test_неизвестный_домен_не_запрещается(очередь):
    """Витрина, которую ещё только заводят, в реестре активных не значится.
    Запрет на её первый выпуск был бы выдумкой, а не правилом."""
    очередь.проверить_статус_домена("нет-такой-витрины-01")
    состояние, _ = очередь.статус_домена("нет-такой-витрины-01")
    assert состояние == "не измерено"


def test_ворота_различают_три_ответа(ворота):
    """Активен, выведен, не измерено — три разных ответа и три разных кода
    выхода. Сводить «не измерено» к одному из крайних нельзя."""
    assert ворота.статус("animedia-01")["состояние"] == "active"
    assert ворота.статус("animedia-02")["состояние"] == "awaiting_replacement"
    assert ворота.статус("нет-такой-витрины-01")["состояние"] == "НЕ ИЗМЕРЕНО"


def test_расхождение_реестров_названо_поимённо(ворота):
    """Тест, который поймал бы дефект 27.10 до выпуска.

    Он НЕ требует, чтобы расхождений не было: привести реестр ячеек в
    согласие — работа владельца этого реестра, и делать её здесь молча нельзя.
    Он требует, чтобы расхождение было ВИДНО и названо, а не обнаруживалось
    двумя выпусками на выведенный домен.
    """
    расход = [з for з in ворота.все() if not з.get("реестры согласны", True)]
    имена = sorted(str(з.get("домен")) for з in расход)
    # Снимок на 27.10: шесть выведенных домéнов, у двух из них реестр ячеек
    # говорит «live» — именно по этому полю путь выпуска и пропускал заявку.
    assert имена, "расхождений нет — снимок устарел, обновите ожидание"
    живые = [з for з in расход if з.get("реестр ячеек") == "live"]
    assert all(з["состояние"] == "awaiting_replacement" for з in расход)
    # Главное утверждение: сколько бы их ни было, выпуск на них теперь
    # закрыт воротами, а не согласием реестров.
    from factory.cell import queue as q
    for з in расход:
        with pytest.raises(q.RequestRejected):
            q.проверить_статус_домена(str(з["site_id"]))
    assert len(живые) <= len(расход)
