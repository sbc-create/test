def test_успешный_проход_пишет_наложение_и_память_о_записи(tmp_path, monkeypatch):
    """Результат ложится В НАЛОЖЕНИЕ, а страница видит его сразу, в памяти."""
    записи = {"skotty": {"id": "a", "seasons": [{"n": 1, "eps": 6, "avail": 1}]}}
    п = Подробности(tmp_path / "d.json", записи)
    monkeypatch.setattr(es, "_плейлист",
                        lambda *а, **к: {"items": [дорожка(1, 0)]})
    monkeypatch.setattr(es.time, "sleep", lambda _: None)
    итог = es.Согласование(Рантайм(п), домен="x.test",
                           снимок=tmp_path / "d.json").проход(п)
    assert итог["согласовано"] == 1 and итог["записано"] is True
    # в памяти — сразу, без перезапуска службы
    assert записи["skotty"]["seasons"][0]["nums"] == [0]
    на_диске = es.прочитать_наложение(tmp_path / "d.nums.json")
    assert на_диске["skotty"]["seasons"]["1"]["nums"] == [0]
    assert на_диске["skotty"]["shape"] == [[1, 6, 1]]


def test_наложение_копится_а_не_перетирается(tmp_path, monkeypatch):
    """Второй проход не должен терять то, что запомнил первый."""
    записи = {"a": {"id": "a", "seasons": [{"n": 1, "eps": 2, "avail": 0}]},
              "b": {"id": "b", "seasons": [{"n": 1, "eps": 2, "avail": 0}]}}
    п = Подробности(tmp_path / "d.json", записи)
    monkeypatch.setattr(es, "_плейлист",
                        lambda *а, **к: {"items": [дорожка(1, 1)]})
    monkeypatch.setattr(es.time, "sleep", lambda _: None)
    monkeypatch.setattr(es, "ЗА_ПРОХОД", 1)
    с = es.Согласование(Рантайм(п), домен="x.test", снимок=tmp_path / "d.json")
    с.проход(п)
    с.проход(п)
    на_диске = es.прочитать_наложение(tmp_path / "d.nums.json")
    assert sorted(на_диске) == ["a", "b"], "память о первой записи потеряна"


