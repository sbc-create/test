"""Нумерация сезонов в снимке витрины: три подкласса дыры, а не один дефект.

Повод. MOD-110 нашёл дыры в нумерации сезонов по КАРТЕ `yummyani.biz`, но на
animedia адресов серий в карте нет вовсе (0 из 8 234), и проверка карты там
честно отвечает «не измерено». Этот проход смотрит сами данные витрины.

Измерено 20.10 на animedia-01 (8 674 записи, 6 003 с сезонами): дыр 30, из них
8 законных (пропуск лежит ОТДЕЛЬНОЙ записью каталога), 5 — номер части в поле
сезона, 9 — одна дыра, 8 — много дыр. Сезонов у фильма ноль.

Отрицательные контроли, названные заранее, и каждый взят из живых данных:

* **«минимальный сезон не 1» дефектом НЕ является** — таких 1 078. Объявить их
  дефектом значило бы выдать тысячу ложных находок на различии «франшиза /
  произведение / сезон»;
* **большой номер сезона сам по себе дефектом не является**: у `pokemon`
  двадцать пять сезонов подряд, и дыр у него нет. Поэтому «номер выше предела»
  печатается наблюдением, а не находкой, и в подклассы не попадает;
* **пропуск, лежащий отдельной записью, законен**: «Невероятное приключение
  ДжоДжо. Часть 3» рядом с «Частью 2» — это устройство каталога;
* **сезоны у фильма** — отдельный случай (дефект Yummy), и здесь он равен нулю,
  то есть признак умеет отвечать «нет».
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "season_numbering_audit",
    КОРЕНЬ / "automation/local/season-numbering-audit.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)


def _з(имя: str, номера: list[int], *, тип: str = "tv") -> dict:
    return {"name": имя, "type": тип,
            "seasons": [{"n": н, "eps": 12, "avail": 12} for н in номера]}


# --- что дефектом не является ---------------------------------------------------

def test_минимальный_сезон_не_один_дефектом_не_является():
    """Живых случаев 1 078: сезон вынесен в отдельную запись каталога."""
    итог = ИНСТР.разобрать({"a-2": _з("Работа 2", [2, 3, 4])})
    assert итог["минимальный сезон не 1 (НЕ дефект)"] == 1
    assert итог["дыр всего"] == 0
    assert all(not с for с in итог["подклассы"].values())


def test_много_сезонов_подряд_дефектом_не_является():
    """`pokemon`: 25 сезонов подряд, дыр нет — находкой это быть не должно."""
    итог = ИНСТР.разобрать({"pokemon": _з("Покемон", list(range(1, 26)))})
    assert итог["дыр всего"] == 0
    assert [с["слаг"] for с in итог["номер сезона выше предела"]] == ["pokemon"]


def test_запись_без_сезонов_не_считается():
    итог = ИНСТР.разобрать({"a": {"name": "Без сезонов", "type": "movie"}})
    assert итог["записей с сезонами"] == 0


def test_пропуск_отдельной_записью_законен():
    снимок = {
        "dzhodzho-chast-3": _з("ДжоДжо. Часть 3", [1, 3]),
        "dzhodzho-chast-2": _з("ДжоДжо. Часть 2", [1]),
    }
    итог = ИНСТР.разобрать(снимок)
    законные = итог["дыра законна (пропуск лежит отдельной записью)"]
    assert [с["слаг"] for с in законные] == ["dzhodzho-chast-3"]
    assert all(not с for с in итог["подклассы"].values())


# --- три подкласса --------------------------------------------------------------

def test_номер_части_в_сезонах():
    """«Симфогир [ТВ-4]» с сезонами 1 и 4 — номер части, а не пропуск."""
    итог = ИНСТР.разобрать({"simfogir-tv-4": _з("Симфогир [ТВ-4]", [1, 4])})
    assert [с["слаг"] for с in итог["подклассы"]["номер части в сезонах"]] == \
        ["simfogir-tv-4"]


def test_номер_части_хвостом_названия():
    итог = ИНСТР.разобрать({"proslavlennyy-3": _з("Прославленный 3", [1, 3])})
    assert итог["подклассы"]["номер части в сезонах"]


def test_одна_дыра():
    итог = ИНСТР.разобрать({"akvarion": _з("Акварион", [1, 3])})
    assert [с["слаг"] for с in итог["подклассы"]["одна дыра"]] == ["akvarion"]


def test_много_дыр():
    итог = ИНСТР.разобрать({"gandam": _з("Мобильный воин Гандам", [1, 6])})
    assert [с["слаг"] for с in итог["подклассы"]["много дыр"]] == ["gandam"]


def test_номер_части_важнее_числа_дыр():
    """У «Тэнти — лишний! Рёоки 5» дыр три, но причина — номер части."""
    итог = ИНСТР.разобрать({"tenti-5": _з("Тэнти — лишний! Рёоки 5", [1, 5])})
    assert итог["подклассы"]["номер части в сезонах"]
    assert not итог["подклассы"]["много дыр"]


# --- сезоны у фильма ------------------------------------------------------------

def test_сезоны_у_фильма_находка():
    итог = ИНСТР.разобрать({"film": _з("Фильм", [2], тип="movie")})
    assert [с["слаг"] for с in итог["сезоны у фильма"]] == ["film"]


def test_один_сезон_у_фильма_находкой_не_является():
    итог = ИНСТР.разобрать({"film": _з("Фильм", [1], тип="movie")})
    assert итог["сезоны у фильма"] == []


# --- вывод и коды ---------------------------------------------------------------

def test_вывод_называет_чего_не_говорит(tmp_path, capsys):
    ф = tmp_path / "s.json"
    ф.write_text(json.dumps({"details": {"akvarion": _з("Акварион", [1, 3])}}),
                 encoding="utf-8")
    assert ИНСТР.главное([str(ф)]) == 1
    вывод = capsys.readouterr().out
    assert "«минимальный сезон не 1» дефектом не считается" in вывод
    assert "а не его ответ" in вывод


def test_чистый_снимок_это_ноль(tmp_path):
    ф = tmp_path / "s.json"
    ф.write_text(json.dumps({"details": {"a": _з("Работа", [1, 2, 3])}}),
                 encoding="utf-8")
    assert ИНСТР.главное([str(ф)]) == 0


def test_не_снимок_отвергается(tmp_path):
    ф = tmp_path / "s.json"
    ф.write_text(json.dumps({"items": []}), encoding="utf-8")
    with pytest.raises(SystemExit) as ош:
        ИНСТР.записи(ф)
    assert "не снимок витрины" in str(ош.value)


def test_предел_выброса_назван_числом_и_обоснован():
    assert ИНСТР.ВЫБРОС_НОМЕРА == 20
    текст = " ".join(
        pathlib.Path(ИНСТР.__file__).read_text(encoding="utf-8").split())
    assert "61" in текст and "22" in текст, "основание предела должно быть названо"
