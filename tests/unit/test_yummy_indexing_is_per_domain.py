"""Решение об индексации переехало из кода посредника в версионируемый профиль.

Прежняя редакция этого файла закрепляла список открытых доменов ПРЯМО В КОДЕ
посредника: ``ДОМЕНЫ_С_ОТКРЫТОЙ_ИНДЕКСАЦИЕЙ = frozenset({"yummyani.site"})``.
Для своего времени это было верно — список хотя бы существовал в одном месте и
был покрыт проверками.

Но именно это и оказалось дефектом. Решение владельца жило в коде, то есть в
одном из трёх независимых мест наряду с непрослеживаемым профилем на хосте и
compose-файлом ветки, которой нет в ``main``. Совпадали они случайно, и обычный
deploy закрывал живую витрину.

Теперь источник один — ``config/site-profiles/<site_id>.json``, а посредник
читает собранный из профилей артефакт. Прежние утверждения не потеряны: каждое
заменено более строгим.

===========================================  ==================================
прежнее утверждение                          где оно теперь
===========================================  ==================================
список открыт только для yummyani.site       ``test_indexing_policy``::
                                             ``test_реальные_профили_дают_матрицу_владельца``
разрешённый домен открыт                     ``test_yummy_indexing_from_policy``::
                                             ``test_открытый_домен_открыт``
соседние домены закрыты                      то же::``test_закрытые_домены_закрыты``
незаданная переменная означает закрыто       то же::``test_незаданная_переменная_означает_закрыто``
заголовок зависит от решения                 то же::``test_заголовок_и_robots_решаются_одной_функцией``
robots.txt не перехватывается на открытом    то же
открыт ровно один домен                      ``test_indexing_policy``::
                                             ``test_реальные_профили_дают_матрицу_владельца``
===========================================  ==================================

Здесь остаётся то, чего в новых файлах нет: проверка, что старый механизм
действительно убран, а не сосуществует рядом с новым. Два источника решения —
это тот же дефект, от которого уходили.
"""

from __future__ import annotations

import json
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ФРОНТ = КОРЕНЬ / "automation" / "host" / "yummy-frontend.py"
ПРОФИЛИ = КОРЕНЬ / "config" / "site-profiles"


def test_список_доменов_убран_из_кода_посредника() -> None:
    """Прежний механизм не должен сосуществовать с новым."""
    исходник = ФРОНТ.read_text(encoding="utf-8")
    assert "ДОМЕНЫ_С_ОТКРЫТОЙ_ИНДЕКСАЦИЕЙ" not in исходник, (
        "список открытых доменов вернулся в код: решение снова живёт в двух местах"
    )


def test_посредник_читает_артефакт_политики() -> None:
    исходник = ФРОНТ.read_text(encoding="utf-8")
    assert "LORDS_INDEXING_POLICY" in исходник
    assert "indexing-policy.json" in исходник


def test_решение_живёт_в_профиле_а_не_в_коде() -> None:
    """Открытие названо в профиле, и там же его основание."""
    профиль = json.loads((ПРОФИЛИ / "yummyani-site.json").read_text(encoding="utf-8"))
    seo = профиль["seo_profile"]
    assert seo["indexing_expected"] == "open"
    assert seo["indexing_reason"].strip(), "открытие без основания не проверить"


def test_ни_один_другой_профиль_не_открыт() -> None:
    открытые = []
    for путь in sorted(ПРОФИЛИ.glob("*.json")):
        профиль = json.loads(путь.read_text(encoding="utf-8"))
        if профиль["seo_profile"]["indexing_expected"] == "open":
            открытые.append(профиль["canonical_domain"])
    assert открытые == ["yummyani.site"], f"открытыми числятся: {открытые}"
