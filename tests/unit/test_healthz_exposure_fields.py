"""Что считать раскрытием устройства машины в публичном `/healthz`.

Инструмент опирался на закрытый перечень имён и находил четыре поля, говоря
«показывают устройство машины: 9». Фактически на тех же витринах раскрывающих
полей двадцать два: пять путей в файловой системе, десять хешей содержимого,
шесть идентификаторов версий, включая git-коммиты приватных репозиториев.
Недооценка была пятикратной.

Закрытый перечень имён — неверный приём для этой задачи: поля добавляются
выпусками, и каждое новое по умолчанию считалось безобидным. Поэтому главная
проверка здесь — что НОВОЕ поле попадает под признак само, без правки списка.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "healthz-exposure.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("healthz_exposure", ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    sys.modules["healthz_exposure"] = м
    спец.loader.exec_module(м)
    return м


hz = _модуль()


def test_путь_в_файловой_системе_это_раскрытие():
    for имя in ("runtime_path", "catalog_path", "details_path",
                "player_config_path", "template_manifest_path", "data_dir"):
        assert hz.раскрывает(имя), имя


def test_хеш_содержимого_это_раскрытие():
    for имя in ("runtime_sha256", "artifact_sha256", "assets_sha256",
                "catalog_digest", "profile_digest", "ratings_snapshot_digest"):
        assert hz.раскрывает(имя), имя


def test_коммит_и_ревизия_это_раскрытие():
    """Коммит приватного репозитория говорит, какая ревизия работает.

    Это позволяет снаружи точно сопоставить работающий код с любым известным
    дефектом и показывает ритм работы над репозиторием.
    """
    for имя in ("runtime_commit", "source_commit", "catalog_revision",
                "details_revision", "release_id", "build_id"):
        assert hz.раскрывает(имя), имя


def test_состояние_раскрытием_не_считается():
    """`ok` — ответ о живости, ради которого endpoint и существует."""
    assert not hz.раскрывает("ok")


def test_ответ_о_совпадении_без_самой_цифры_не_раскрытие():
    """`runtime_digest_match` — да/нет, а не цифра.

    Пометить его значило бы требовать убрать то, что ничего не выдаёт, и
    приучить спорить с инструментом.
    """
    assert not hz.раскрывает("runtime_digest_match")


def test_новое_поле_попадает_под_признак_само():
    """Главное свойство замены перечня на вид.

    Поля добавляются выпусками. При закрытом перечне имён каждое новое поле
    по умолчанию считалось безобидным — и так двадцать два раскрывающих поля
    выглядели как четыре.
    """
    assert hz.раскрывает("новый_слой_sha256")
    assert hz.раскрывает("backup_path")
    assert hz.раскрывает("schema_revision")


def test_безобидное_новое_поле_не_помечается():
    """Обратная сторона: признак по виду не должен ловить всё подряд.

    Иначе вывод станет шумом, и его перестанут читать — то же, что погубило
    бы любой слишком широкий признак.
    """
    for имя in ("uptime_seconds", "requests_total", "ok", "status",
                "cache_hits"):
        assert not hz.раскрывает(имя), имя


def test_имена_вне_видового_признака_сохранены():
    """`pid` и время старта под вид не подходят, но раскрывают не меньше."""
    assert hz.раскрывает("pid")
    assert hz.раскрывает("process_start_time")
    assert hz.раскрывает("account")
    assert hz.раскрывает("unit")
