"""REQ-CELL-COLLECTION-MEMO: набор подборки считается один раз на снимок.

Измерено 2026-10-18 локально на снимке витрины (64 508 записей): главная
страница стоила 1.4 с, и 1.68 с из 2.18 с под профилировщиком уходило в шесть
вызовов `разрешить` — каждый со своим обходом и сортировкой каталога
(1 790 757 вызовов `dict.get`, 131 557 вызовов `_оценка`).

Класс `Снимок` заведён ровно против этого: «раньше каждый блок главной
отдельно обходил весь каталог на каждом HTTP-запросе». Отбор при этом —
ЧИСТАЯ функция снимка и спецификации: окно свежести отсчитывается от самой
свежей записи СНИМКА, а не от часов машины (так в коде и записано, с
причиной).

Главное, что сторожит эта проверка, — ГДЕ живёт памятка. Первая редакция
ключевала её по `снимок.data_revision`, и общий прогон сразу поймал подмену:
два снимка оснастки объявляют одну ревизию, и набор первого достался второму —
в разметку поехали карточки чужого снимка. `data_revision` — ОБЪЯВЛЕННОЕ
значение, и если доставка положит новый каталог, не сменив объявление,
глобальная памятка повторила бы это на живой витрине.

Поэтому памятка живёт на самом объекте снимка: новый снимок — новый объект —
пустая памятка.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "host" / "collection_contract.py"


def _модуль():
    """Модуль регистрируется в sys.modules до исполнения: `dataclass`
    обращается к `sys.modules[cls.__module__]`, и без регистрации падает на
    первом же объявлении."""
    имя = "collection_contract_memo"
    спец = importlib.util.spec_from_file_location(имя, ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def _записи(сколько: int, начало: int = 0) -> list:
    return [{"slug": f"t{н:04d}", "title": f"Тайтл {н}", "kind": "Фильм",
             "year": 2020 + (н % 5), "published_at": f"2026-10-{1 + н % 28:02d}",
             "poster": f"/posters/t{н:04d}.jpg"}
            for н in range(начало, начало + сколько)]


def test_памятка_живёт_на_снимке_а_не_в_модуле():
    """Глобального словаря быть не должно: он и дал подмену снимков."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "_НАБОРЫ" not in текст, (
        "памятка снова глобальная — снимки с одинаковой объявленной ревизией "
        "начнут делить наборы")
    assert 'getattr(снимок, "_наборы", None)' in текст


def test_второй_вызов_берёт_готовый_набор():
    снимок = МОД.Снимок(_записи(40), {}, revision="rev-1")
    спецы = МОД.спецификации("lords")
    assert спецы, "у семейства нет ни одной подборки — проверять нечего"
    ключ = спецы[0].collection_key
    первая = МОД.разрешить(ключ, снимок, "lords", предел=6)
    assert первая is not None
    assert getattr(снимок, "_наборы", None), "памятка не появилась"
    вторая = МОД.разрешить(ключ, снимок, "lords", предел=6)
    assert [и.entity_id for и in вторая.items] == \
           [и.entity_id for и in первая.items]


def test_разные_снимки_с_одной_ревизией_не_делят_наборы():
    """Отрицательный контроль к измеренной подмене.

    Ревизия объявлена одинаковой НАМЕРЕННО: именно так оснастка и поймала
    первую редакцию памятки.
    """
    спецы = МОД.спецификации("lords")
    ключ = спецы[0].collection_key
    первый = МОД.Снимок(_записи(40, 0), {}, revision="одна-и-та-же")
    второй = МОД.Снимок(_записи(40, 500), {}, revision="одна-и-та-же")
    слуги_1 = [и.entity_id
               for и in МОД.разрешить(ключ, первый, "lords", предел=6).items]
    слуги_2 = [и.entity_id
               for и in МОД.разрешить(ключ, второй, "lords", предел=6).items]
    assert слуги_1 and слуги_2
    assert set(слуги_1).isdisjoint(слуги_2), (
        f"наборы разных снимков совпали: {слуги_1} и {слуги_2}")


def test_страница_и_предел_не_кешируются():
    """Памятка хранит ОТБОР, а срез считается на каждый вызов: иначе лента и
    полная страница отдали бы одно и то же."""
    снимок = МОД.Снимок(_записи(200), {}, revision="rev-2")
    спецы = [с for с in МОД.спецификации("lords")]
    ключ = спецы[0].collection_key
    лента = МОД.разрешить(ключ, снимок, "lords", предел=6)
    страница2 = МОД.разрешить(ключ, снимок, "lords", страница=2, на_странице=6)
    if страница2 is None or not страница2.items:
        return  # у этой подборки одна страница — проверять нечего
    assert [и.entity_id for и in лента.items] != \
           [и.entity_id for и in страница2.items]


def test_время_сборки_не_замораживается():
    """`generated_at` обязан быть настоящим: он говорит, когда ответ собран,
    а не когда посчитался отбор."""
    import time

    снимок = МОД.Снимок(_записи(40), {}, revision="rev-3")
    ключ = МОД.спецификации("lords")[0].collection_key
    первая = МОД.разрешить(ключ, снимок, "lords", предел=6)
    time.sleep(1.05)
    вторая = МОД.разрешить(ключ, снимок, "lords", предел=6)
    assert первая.generated_at != вторая.generated_at


def test_второй_вызов_не_повторяет_отбор(monkeypatch):
    """Самая прямая проверка памятки: отбор не выполняется заново.

    Время на малом снимке — шум, поэтому считаются ВЫЗОВЫ выборки. Именно это
    свойство и правилось: шесть подборок главной обходили каталог каждая.
    """
    снимок = МОД.Снимок(_записи(80), {}, revision="rev-счёт")
    ключ = МОД.спецификации("lords")[0].collection_key

    счёт = {"раз": 0}

    def обёрнуть(функция):
        def обёртка(снимок_, спец_):
            счёт["раз"] += 1
            return функция(снимок_, спец_)
        return обёртка

    for имя, функция in dict(МОД.ВЫБОРКИ).items():
        monkeypatch.setitem(МОД.ВЫБОРКИ, имя, обёрнуть(функция))

    МОД.разрешить(ключ, снимок, "lords", предел=6)
    после_первого = счёт["раз"]
    assert после_первого >= 1, "выборка не вызывалась вовсе — проверка слепа"
    МОД.разрешить(ключ, снимок, "lords", предел=6)
    МОД.разрешить(ключ, снимок, "lords", страница=2, на_странице=6)
    assert счёт["раз"] == после_первого, (
        f"отбор повторился: было {после_первого}, стало {счёт['раз']}")


def test_в_ключе_памятки_есть_сутки():
    """Предупреждение соседней линии, пришедшее ДО слияния, а не после.

    В их ветке в том же конвейере отбора стоит фильтр новинок, граница
    которого считается ОТ СЕГОДНЯ. В этой ветке такого фильтра нет: окно
    свежести отсчитывается от самой свежей записи СНИМКА, и это записано в
    коде с причиной. Дефекта нет ни в одной из двух ветвей — он появился бы в
    момент слияния: ключ без суток заморозил бы границу на весь срок жизни
    объекта снимка, а снимок живёт до следующей доставки, и доставка
    простаивала сутками.

    Цена — один пересчёт в сутки на подборку; выигрыш памятки снимался не с
    ежесекундного пересчёта, а с пересчёта вообще.
    """
    текст = ПУТЬ.read_text(encoding="utf-8")
    начало = текст.index("ключ_памятки = (")
    кусок = текст[начало:текст.index("готовый = памятка.get", начало)]
    assert "date().isoformat()" in кусок, (
        "в ключе памятки нет суток: фильтр, считающий границу от сегодня, "
        "замёрзнет на срок жизни снимка")
    # И оговорка про местное время должна остаться в коде: без неё следующая
    # правка сделает ведро по UTC достаточным по виду.
    assert "МЕСТНОМУ" in текст, (
        "пропала оговорка: при границе по местному времени в ключ обязана "
        "идти сама граница, а не дата UTC")


def test_ключ_памятки_меняется_с_сутками(monkeypatch):
    """Поведение, а не наличие строки: другой день — другой ключ."""
    снимок = МОД.Снимок(_записи(40), {}, revision="rev-сутки")
    ключ = МОД.спецификации("lords")[0].collection_key
    МОД.разрешить(ключ, снимок, "lords", предел=6)
    было = set(снимок._наборы)
    assert было, "памятка пуста"

    настоящий = МОД.datetime

    class ДругойДень(настоящий):
        @classmethod
        def now(cls, tz=None):
            return настоящий.now(tz) + МОД.timedelta(days=1)

    monkeypatch.setattr(МОД, "datetime", ДругойДень)
    МОД.разрешить(ключ, снимок, "lords", предел=6)
    стало = set(снимок._наборы)
    assert стало - было, "на следующие сутки ключ не изменился"


def test_условие_срока_жизни_названо_в_коде():
    """Памятка верна, только если ячейку ПЕРЕЗАПУСКАЮТ при смене каталога.

    У партии K2 это так: измерено 2026-10-18 — в описи доставки у всех восьми
    `reload: restart`. Но у сценария установки есть ветка `reload: mtime`
    («рантайм перечитывает снимок сам, перезапуск не нужен»), и ячейке с таким
    режимом памятка переживёт смену снимка.

    Шаблон общий, его сливают другие линии, поэтому условие обязано стоять
    рядом с памяткой, а не только в отчёте.
    """
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "reload: mtime" in текст, (
        "из кода исчезло условие, при котором памятка верна: ячейке с "
        "режимом mtime она переживёт смену снимка")
    assert "отпечатку ФАЙЛА" in текст, (
        "не назван способ починки для такой ячейки")
