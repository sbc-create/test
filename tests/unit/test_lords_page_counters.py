"""REQ-LORDS-INCREMENTAL: одна запись не переписывает весь раздел.

Разбиения по годам оказалось мало. Замер на боевом цикле 2026-09-03: после
перехода на блоки годов добавление четырёх записей всё равно перерисовало 9266
страниц из 9717. Дифф страницы в нетронутом году показал причину:

    Записей в разделе: 52678.  →  52682.
    2026 (1842)                →  2026 (1843)

Это сквозные счётчики: общее число записей раздела и числа в подписях фильтров.
Считаются по всему разделу и стоят на каждой странице — то есть любая правка
каталога меняет каждую страницу, каким бы ни было разбиение.

Здесь закрепляется: числа остаются на первой странице раздела и уходят с
остальных.
"""
from __future__ import annotations

import re

import pytest
import yaml

from factory.lords import fixtures as fx
from factory.lords import render
from factory.paths import PATHS

SITE = "lords-01"


def пакет() -> dict:
    return yaml.safe_load(PATHS.site_package(SITE).read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def сайт():
    return render.render_site(пакет(), catalog=fx.build_catalog())


def страницы_списка(сайт) -> list[str]:
    return sorted(p for p in сайт.pages if p.endswith("page/2/"))


def test_общее_число_записей_только_на_первой_странице(сайт):
    глубокие = страницы_списка(сайт)
    if not глубокие:
        pytest.skip("на фикстурном каталоге разделы умещаются в одну страницу")
    for путь in глубокие:
        assert "Записей в разделе" not in сайт.pages[путь].body, путь
    первая = глубокие[0][: -len("page/2/")]
    assert "Записей в разделе" in сайт.pages[первая].body


def test_числа_в_фильтрах_только_на_первой_странице(сайт):
    глубокие = страницы_списка(сайт)
    if not глубокие:
        pytest.skip("на фикстурном каталоге разделы умещаются в одну страницу")
    подпись_с_числом = re.compile(r"<option[^>]*>[^<]*\(\d+\)</option>")
    for путь in глубокие:
        assert not подпись_с_числом.search(сайт.pages[путь].body), путь


def test_фильтры_на_глубокой_странице_не_исчезли(сайт):
    # Числа убраны, а сами фильтры обязаны остаться: иначе с глубокой страницы
    # нельзя перейти в жанр или год, и раздел превращается в тупик.
    глубокие = страницы_списка(сайт)
    if not глубокие:
        pytest.skip("на фикстурном каталоге разделы умещаются в одну страницу")
    for путь in глубокие:
        body = сайт.pages[путь].body
        if "<option" in сайт.pages[глубокие[0][: -len("page/2/")]].body:
            assert "<option" in body, путь
