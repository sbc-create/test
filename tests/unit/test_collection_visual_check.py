"""Проверка раскладки подборки судит по числам, и это проверяемо без браузера.

Повод: визуальную приёмку 27.10 прошли и линия SEO, и мои прежние проверки —
страница отдавала 200, состав был верен, ссылки работали, картинки не биты. Ни
одна не спрашивала, сколько карточек в ряду. Поэтому решающая функция вынесена
отдельно и проверяется здесь: «0 дефектов» обязано что-то значить.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "collection-visual-check.py"


@pytest.fixture(scope="module")
def м():
    спец = importlib.util.spec_from_file_location("collection_visual", ПУТЬ)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def _хорошо(**поправки):
    итог = {
        "карточек всего": 5, "карточек в ряду": 5, "рядов": 1,
        "доля постера от окна": 0.18, "доля содержимого от окна": 0.93,
        "название ниже постера на": 8, "пояснение есть": True,
        "горизонтальная прокрутка": 0, "перенос за рамку": 0,
    }
    итог.update(поправки)
    return итог


def test_хорошая_раскладка_без_дефектов(м):
    assert м.беда_прохода(_хорошо(), 1440) == []


def test_одна_карточка_в_ряду_дефект(м):
    """Ровно то, что увидел владелец: одна колонка на широком экране."""
    причины = м.беда_прохода(_хорошо(**{"карточек в ряду": 1}), 1440)
    assert any("в ряду 1" in п for п in причины), причины


def test_две_карточки_на_телефоне_норма_а_одна_дефект(м):
    assert м.беда_прохода(_хорошо(**{"карточек в ряду": 2}), 390) == []
    assert м.беда_прохода(_хорошо(**{"карточек в ряду": 1}), 390)


def test_постер_во_всю_ширину_дефект(м):
    причины = м.беда_прохода(_хорошо(**{"доля постера от окна": 0.93}), 1440)
    assert any("рамки нет" in п for п in причины), причины


def test_на_телефоне_крупный_постер_не_дефект(м):
    """На 390 постер законно занимает половину ширины: колонок всего две."""
    assert м.беда_прохода(_хорошо(**{"карточек в ряду": 2,
                                     "доля постера от окна": 0.46}), 390) == []


def test_пустота_справа_дефект(м):
    причины = м.беда_прохода(_хорошо(**{"доля содержимого от окна": 0.4}), 1920)
    assert any("пустота справа" in п for п in причины), причины


def test_рамка_оригинала_на_широком_экране_не_дефект(м):
    """1920 при ограничении 1420 даёт 0.74 — это рамка, а не пустота."""
    assert м.беда_прохода(_хорошо(**{"доля содержимого от окна": 0.74}), 1920) == []


def test_название_далеко_внизу_дефект(м):
    причины = м.беда_прохода(_хорошо(**{"название ниже постера на": 420}), 1440)
    assert any("ниже постера" in п for п in причины), причины


def test_горизонтальная_прокрутка_дефект(м):
    assert м.беда_прохода(_хорошо(**{"горизонтальная прокрутка": 12}), 1440)


def test_без_пояснения_дефект(м):
    """Редакционное пояснение — требование владельца к карточке подборки."""
    причины = м.беда_прохода(_хорошо(**{"пояснение есть": False}), 1440)
    assert any("пояснени" in п for п in причины), причины


def test_страница_без_карточек_не_зеленеет(м):
    причины = м.беда_прохода(_хорошо(**{"карточек всего": 0}), 1440)
    assert причины


def test_не_измеренный_проход_не_дефект_и_не_ок(м):
    """Недоступная страница не становится ни «ок», ни «дефектом»."""
    assert м.беда_прохода({"беда": "TimeoutError"}, 1440) == ["TimeoutError"]
    assert м.не_измерено({"беда": "TimeoutError"}) is True


def test_проба_называет_себя(м):
    """Иначе на animedia.icu замер упрётся в предел для роботов (MOD-175)."""
    assert м.АГЕНТ.startswith("factory-")


def test_ширины_из_поручения(м):
    assert [ш for ш, *_ in м.ШИРИНЫ] == [390, 1440, 1920]


def test_карточки_считаются_прямыми_детьми_сетки(м):
    """`.col__i` и вложенная `.c` имеют один offsetTop: запрос по потомкам
    считал бы каждую карточку дважды. Первая редакция так и соврала на 390."""
    assert "сетка0.children" in м.ОСМОТР
    assert ".col__grid .col__i" not in м.ОСМОТР
