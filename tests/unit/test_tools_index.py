"""REQ-TOOLS-INDEX: указатель инструментов не отстаёт от инструментов.

В `tests/tools/` пятьдесят шесть сценариев и не было ни одного способа узнать,
какой из них отвечает на нужный вопрос. Оператор, которому надо выяснить,
исчерпан ли источник оценок или во что упирается задержка поиска, инструмент не
найдёт и напишет пятьдесят седьмой.

Указатель собирается из самих сценариев, а не ведётся отдельно. Причина
измерена в этом же контуре дважды: настройка навигации, которую никто не
читает, и заявление о совпадении выдачи, которое шире правды. Список, который
ведут отдельно от того, что он описывает, расходится с ним на первой правке —
и расхождение никак себя не выдаёт.

Проверка и есть то, что не даёт указателю отстать.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "tests" / "tools" / "tools_index.py"
УКАЗАТЕЛЬ = КОРЕНЬ / "tests" / "tools" / "INDEX.md"


@pytest.fixture(scope="module")
def сборщик():
    спец = importlib.util.spec_from_file_location("tools_index", СЦЕНАРИЙ)
    модуль = importlib.util.module_from_spec(спец)
    sys.modules["tools_index"] = модуль
    спец.loader.exec_module(модуль)
    return модуль


def test_указатель_существует():
    assert УКАЗАТЕЛЬ.is_file(), (
        "указателя нет: пятьдесят шесть сценариев без единого способа их найти")


def test_указатель_совпадает_с_каталогом(сборщик):
    assert УКАЗАТЕЛЬ.read_text(encoding="utf-8") == сборщик.собрать(), (
        "указатель отстал от инструментов — пересоберите: "
        "python3 tests/tools/tools_index.py --write")


def test_каждый_инструмент_описан(сборщик):
    безымянные = [имя for имя, что in сборщик.инструменты() if not что]
    assert not безымянные, (
        "инструменты без первой содержательной строки: "
        f"{', '.join(безымянные)} — по ним нельзя понять, что они делают")


def test_строка_запуска_не_считается_описанием(сборщик):
    подозрительные = [имя for имя, что in сборщик.инструменты()
                      if "/usr/bin/env" in что or что.startswith("!")]
    assert not подозрительные, (
        f"строка запуска попала в описание: {', '.join(подозрительные)}")


def test_описания_не_обрывки(сборщик):
    короткие = [(имя, что) for имя, что in сборщик.инструменты() if len(что) < 16]
    assert not короткие, f"описания слишком коротки, чтобы что-то сообщать: {короткие}"
