"""MOD-149: приоритет загрузки достаётся тому, что видно на первом экране.

Повод измерен 23.10 инструментом `automation/local/poster-priority-probe.py`
настоящим браузером на двух окнах — телефон 390×844 плотность 3 и настольное
1440×900 плотность 1. На главной `lordfilm.group`:

* первая ВИДИМАЯ обложка (верх 289 px, отрисовка 138 px) имела
  `loading="lazy"` и `fetchpriority="low"` — браузеру было сказано отдать
  полосу чему-то другому ровно на кандидате LCP;
* срочность уходила карточкам сетки #28–#29, а видимым плиткам карусели —
  нет. На настольном окне отложено 11 видимых обложек из 13.

Причина: бюджет срочности жил в `ВидЛордс.сетка` и доставался ПЕРВОЙ СЕТКЕ
страницы, а первым блоком с обложками на главной идёт КАРУСЕЛЬ «Недавние
поступления» (`плитка` вызывала `заглушка_постера` без `срочно`).

Проверки отрисовывают страницу рантаймом, а не читают исходник: дефект был
именно в том, ЧТО получилось на странице. Каждая опровержима — возврат
`понижать=True` по умолчанию в первом блоке или снятие срочности у карусели
их ломает (проверено подменой).
"""
from __future__ import annotations

import re

from lords_runtime_harness import Стенд, вид, выгрузить, загрузить, запись, подробность

#: Первый экран занимают ДВА блока: карусель и первый ряд сетки под ней.
#: Поэтому бюджет даётся первому блоку КАЖДОГО вида, и срочных ожидается
#: вдвое больше, чем `СРОЧНЫХ_ПОСТЕРОВ`.
БЛОКОВ_НА_ПЕРВОМ_ЭКРАНЕ = 2


def _главная(tmp_path, monkeypatch, *, записей: int = 60):
    стенд = Стенд(tmp_path, профиль="lords-general")
    записи = [запись(f"film-{i:03d}", title=f"Фильм {i}", kind="Фильм",
                     year=2020 + i % 6,
                     poster=f"https://poster.example/{i:03d}.webp")
              for i in range(записей)]
    стенд.записать_каталог(записи)
    стенд.записать_подробности([подробность(з["slug"], type_="movie",
                                            genres=("Драма",))
                                for з in записи])
    стенд.записать_плеер()
    модуль = загрузить(стенд, monkeypatch)
    try:
        return модуль, вид(модуль)
    except BaseException:
        выгрузить(модуль)
        raise


def _обложки(html: str) -> list[str]:
    """Теги обложек в порядке разметки. Отбор по `data-poster`: его ставит
    `заглушка_постера`, и он не зависит ни от класса, ни от хоста картинки."""
    return re.findall(r"<img[^>]*data-poster[^>]*>", html)


def _лента(html: str) -> str:
    начало = html.find('data-shelf="intake"')
    assert начало >= 0, "ленты поступлений на главной нет — страница изменилась"
    return html[начало:html.find("</section>", начало)]


def _первая_сетка(html: str) -> str:
    начало = html.find("data-card-grid")
    assert начало >= 0, "сетки карточек на главной нет — страница изменилась"
    return html[начало:html.find("</div>", html.find("</a>", начало))]


def test_первая_обложка_страницы_не_отложена(tmp_path, monkeypatch):
    """Главная проверка дефекта: кандидат LCP грузится сразу."""
    модуль, представление = _главная(tmp_path, monkeypatch)
    try:
        обложки = _обложки(представление.главная())
        assert обложки, "обложек на главной нет — стенд собран неверно"
        assert 'loading="eager"' in обложки[0], (
            f"первая обложка страницы отложена: {обложки[0][:160]}")
        assert 'fetchpriority="high"' in обложки[0], (
            f"первой обложке не задан высокий приоритет: {обложки[0][:160]}")
    finally:
        выгрузить(модуль)


def test_у_обложек_первых_блоков_нет_низкого_приоритета(tmp_path, monkeypatch):
    """Низкий приоритет внутри первого экрана — это и был дефект."""
    модуль, представление = _главная(tmp_path, monkeypatch)
    try:
        html = представление.главная()
        for имя, кусок in (("лента поступлений", _лента(html)),
                           ("первая сетка", _первая_сетка(html))):
            понижённые = [т for т in _обложки(кусок)
                          if 'fetchpriority="low"' in т]
            assert not понижённые, (
                f"{имя}: {len(понижённые)} обложек с низким приоритетом на"
                f" первом экране, первая — {понижённые[0][:160]}")
    finally:
        выгрузить(модуль)


def test_срочность_досталась_и_карусели_и_сетке(tmp_path, monkeypatch):
    """Бюджет — на блок каждого вида, а не один на страницу.

    Один бюджет на страницу переселил бы срочность с видимых карточек сетки
    на видимые плитки карусели и ничего не исправил: на первом экране
    измерены оба блока.
    """
    модуль, представление = _главная(tmp_path, monkeypatch)
    try:
        html = представление.главная()
        в_ленте = sum('loading="eager"' in т for т in _обложки(_лента(html)))
        в_сетке = sum('loading="eager"' in т
                      for т in _обложки(_первая_сетка(html)))
        бюджет = представление.СРОЧНЫХ_ПОСТЕРОВ
        assert в_ленте == бюджет, f"срочных в ленте {в_ленте}, ждали {бюджет}"
        assert в_сетке == бюджет, f"срочных в сетке {в_сетке}, ждали {бюджет}"
        всего = sum('loading="eager"' in т for т in _обложки(html))
        assert всего == бюджет * БЛОКОВ_НА_ПЕРВОМ_ЭКРАНЕ, (
            f"срочных на странице {всего}: срочность разошлась за пределы"
            " первого экрана, а это расход полосы на то, чего не видно")
    finally:
        выгрузить(модуль)


def test_ниже_первого_экрана_приоритет_по_прежнему_понижается(
        tmp_path, monkeypatch):
    """Отрицательный контроль: оптимизация не выброшена целиком.

    Без него правка «снять low везде» прошла бы все проверки выше, а она
    отдала бы полосу картинкам, до которых посетитель не дошёл.
    """
    модуль, представление = _главная(tmp_path, monkeypatch)
    try:
        html = представление.главная()
        понижённые = [т for т in _обложки(html)
                      if 'fetchpriority="low"' in т]
        assert понижённые, (
            "низкого приоритета на странице нет вовсе: блоки ниже первого"
            " экрана теперь соревнуются за полосу с первым экраном")
    finally:
        выгрузить(модуль)


def test_заглушка_постера_без_правки_понижает_как_раньше(tmp_path,
                                                         monkeypatch):
    """Опровержимость: функция всё ещё УМЕЕТ понижать приоритет.

    Если `понижать` перестанет действовать, проверки выше будут проходить по
    причине «такого вывода не бывает», а не по причине исправленного дефекта.
    """
    модуль, _ = _главная(tmp_path, monkeypatch)
    try:
        з = {"title": "Пример", "poster": "https://poster.example/x.webp",
             "url": "/title/x/", "slug": "x"}
        понижено = модуль.заглушка_постера(з, "c__none", "c__img",
                                           понижать=True)
        assert 'fetchpriority="low"' in понижено
        не_понижено = модуль.заглушка_постера(з, "c__none", "c__img",
                                              понижать=False)
        assert 'fetchpriority="low"' not in не_понижено
        assert 'loading="lazy"' in не_понижено, (
            "отсрочка должна остаться: снят только низкий приоритет")
        срочно = модуль.заглушка_постера(з, "c__none", "c__img", срочно=True)
        assert 'loading="eager"' in срочно and 'fetchpriority="high"' in срочно
    finally:
        выгрузить(модуль)


def test_на_странице_произведения_срочен_только_её_постер(tmp_path,
                                                          monkeypatch):
    """Страница произведения отдаёт срочность своему главному изображению, и
    сетка похожих под ним получать её НЕ должна.

    До 23.10 это делалось записью `_срочные_выданы` в обход бюджета. С общим
    бюджетом такая запись перестала действовать, и сетка похожих начала
    получать срочность второй раз — ровно то, против чего предупреждает
    описание `заглушка_постера`. Проверка опровержима: снятие
    `_отметить_срочность` из страницы произведения её ломает.
    """
    модуль, представление = _главная(tmp_path, monkeypatch)
    try:
        з = {"slug": "film-000", "title": "Фильм 0",
             "url": "/title/film-000/", "kind": "Фильм", "year": 2020,
             "poster": "https://poster.example/000.webp"}
        html = представление.тайтл(з, представление.деталь("film-000"))
        обложки = _обложки(html)
        срочные = [т for т in обложки if 'loading="eager"' in т]
        assert len(срочные) == 1, (
            f"срочных изображений на странице произведения {len(срочные)},"
            f" ждали одно — её постер: {[т[:90] for т in срочные]}")
        assert "tw__img" in срочные[0], (
            f"срочность досталась не постеру произведения: {срочные[0][:140]}")
    finally:
        выгрузить(модуль)
