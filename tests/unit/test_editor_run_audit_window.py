"""Провал чтения журнала не должен печататься как вывод о редакторе.

Измерено 13.10 на живой машине. Вызов с самой очевидной формой времени —
`2026-10-12T19:00:00Z`, той, которой пользуются все прочие инструменты
фабрики, — кончался трассировкой. Без `Z` разбор проходил, но `journalctl`
формы с `T` не принимает: он отвечал «Failed to parse timestamp», вызовов
возвращалось ноль, и инструмент печатал на stdout

    ВЫЗОВОВ НЕТ. Работа до фабрики не дошла.

При том что вызовов в этом окне было **890**, а обращений 11. То есть провал
ЧТЕНИЯ выдавался за измеренный провал РЕДАКТОРА, и причина уходила в stderr.
"""
from __future__ import annotations

import datetime as dt
import importlib.util
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "editor-run-audit.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("editor_run_audit", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_окно_принимает_форму_с_Z():
    """Та самая форма, на которой инструмент прежде падал трассировкой."""
    т = МОД.окно("2026-10-12T19:00:00Z")
    assert т == dt.datetime(2026, 10, 12, 19, 0, 0, tzinfo=dt.timezone.utc)


def test_окно_принимает_форму_с_T_без_Z():
    assert МОД.окно("2026-10-12T19:00:00") == МОД.окно("2026-10-12T19:00:00Z")


def test_окно_принимает_форму_с_пробелом():
    """Прежняя рабочая форма должна продолжать работать."""
    assert МОД.окно("2026-10-12 19:00:00") == МОД.окно("2026-10-12T19:00:00Z")


def test_непонятное_время_даёт_внятный_отказ_а_не_трассировку():
    try:
        МОД.окно("вчера вечером")
    except SystemExit as exc:
        текст = str(exc)
        assert "не разобрано время" in текст, текст
        # В отказе названы ОБЕ принятые формы: иначе человек угадывает.
        assert "ГГГГ-ММ-ДД ЧЧ:ММ:СС" in текст and "Z" in текст
    else:
        raise AssertionError("непонятное время прошло молча")


def test_журналу_передаётся_его_форма():
    """`journalctl` понимает пробел, а не `T`. Это и было причиной.

    Проверяется, что форма названа в коде константой, а не собирается на месте
    из того, что набрал человек.
    """
    assert МОД.ФОРМА_ЖУРНАЛА == "%Y-%m-%d %H:%M:%S"
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "с.strftime(ФОРМА_ЖУРНАЛА)" in текст
    assert "до.strftime(ФОРМА_ЖУРНАЛА)" in текст


def test_вызовы_возвращают_причину_непрочтения():
    """Пустой список сам по себе не различает «нет вызовов» и «нет доступа»."""
    import inspect
    подпись = inspect.signature(МОД.вызовы)
    assert str(подпись.return_annotation).replace(" ", "").endswith(
        "tuple[list[dict],str|None]"), подпись


def test_непрочитанный_журнал_не_даёт_вывода_о_запусках(tmp_path):
    """Главная проверка: при непрочтённом журнале «ВЫЗОВОВ НЕТ» не печатается.

    Журнал недоступен в любой среде, где нет systemd-журнала этого юнита, —
    именно на таком прогоне старый код и выдавал ложный вывод.
    """
    г = subprocess.run(
        [sys.executable, str(ПУТЬ), "--since", "1999-01-01T00:00:00Z",
         "--until", "1999-01-01T01:00:00Z"],
        capture_output=True, text=True, timeout=180, cwd=str(КОРЕНЬ))
    вывод = г.stdout
    if "ЖУРНАЛ МОСТА НЕ ПРОЧИТАН" in вывод:
        assert "Работа до фабрики не дошла" not in вывод, вывод
        assert "НЕ ИЗМЕРЕНО" in вывод, вывод
        assert "разные вещи" in вывод, вывод
    else:
        # Журнал прочитан: тогда пустое окно 1999 года законно даёт «ВЫЗОВОВ НЕТ».
        assert "вызовов инструментов: 0" in вывод, вывод


def test_перевёрнутое_окно_отказывает():
    """Конец раньше начала — ошибка ввода, а не пустой результат."""
    г = subprocess.run(
        [sys.executable, str(ПУТЬ), "--since", "2026-10-12T20:00:00Z",
         "--until", "2026-10-12T19:00:00Z"],
        capture_output=True, text=True, timeout=180, cwd=str(КОРЕНЬ))
    assert г.returncode != 0, г.stdout
    assert "не позже начала" in (г.stdout + г.stderr)
