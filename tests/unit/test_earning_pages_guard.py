def test_404_с_noindex_закрытием_не_прикрывается(м):
    """Регрессия, найденная на живых данных: обработчик 404 сам ставит noindex.

    У `lordserials22.info/title/akademiya-minerva/` страница 404 отдаёт
    `noindex, follow` и в теле, и в заголовке — так устроен обработчик
    ошибки. Признак «закрыто намеренно» прикрыл настоящую потерю: исход домена
    стал «исправно 10 из 10» при живом 404 на зарабатывающем адресе. Код
    ответа сильнее любого запрета: страницы нет.
    """
    з = {"код": "404", "путь": "/title/akademiya-minerva/", "попыток": 3,
         "отказов": 0, "x_robots": "noindex, follow", "соседи_открыты": True,
         "признаки": {"robots": "noindex, follow", "canonical": "на себя",
                      "h1": "Не найдено", "плеер": None}}
    assert м.закрыто_намеренно(з) is False
    assert м.закрыто_маршрутом(з) is False
    assert м.закрыта(з) is False
    assert "код 404" in м.беда(з)
    и = м.исход([з, _страница()], [_страница()], карта_прочитана=True)
    assert и.startswith("БЕДА НА ЗАРАБАТЫВАЮЩИХ: 1 из 2")


def test_у_неответившей_страницы_содержание_не_толкуется(м):
    """В строке 404 не должно быть ни «закрыта», ни «плеера нет»."""
    з = {"код": "404", "путь": "/title/x/", "попыток": 3, "отказов": 0,
         "соседи_открыты": True,
         "признаки": {"robots": "noindex, follow", "canonical": "на /other/",
                      "h1": "", "плеер": False}}
    assert м.беда(з) == ["код 404"]
