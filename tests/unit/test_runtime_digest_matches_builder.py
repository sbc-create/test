"""REQ-CELL-RUNTIME-DIGEST: цифра рантайма считается так же, как у сборщика.

Измерено 2026-10-18 на живой витрине семейства: `/healthz` отдавал
`runtime_digest_match = False` при исправном выпуске. Причина — предикат
сравнивал РАЗНОЕ:

    runtime_sha256       = sha256(один файл lords-frontend.py)
    artifact_sha256      = цифра ВСЕГО рантайма (все src/*.py плюс run.py),
                           её кладёт в манифест сборщик витрины

В каталоге витрины восемь файлов `src/*.py`, поэтому равенство было
невозможно по построению. Поле, обещающее «исполняемый код — тот же, что в
артефакте», всегда отвечало «нет». Это хуже отсутствия поля: настоящая
подмена кода выглядела бы точно так же.

Проверка пиннит ДВЕ реализации друг к другу. Рамку сборщика она описывает
явно и считает ею же, а не вызывает функцию рантайма дважды: иначе проверка
подтверждала бы саму себя.
"""
from __future__ import annotations

import hashlib
import importlib.util
import sys
from pathlib import Path

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _функция():
    """Взять `цифра_рантайма_выпуска` из рантайма, не импортируя его целиком.

    Рантайм на импорте читает манифест и снимок каталога; нам нужна одна
    функция, поэтому исполняется кусок исходника до неё.
    """
    исходник = ТЕКСТ[:ТЕКСТ.index("def мета_роботов")]
    # Срез начинается с ПАМЯТКИ, а не с `def`: памятка живёт уровнем модуля, и
    # без неё функция падает на первом же обращении.
    начало = исходник.index("_ЦИФРА_РАНТАЙМА: dict = {}")
    приставка = "from pathlib import Path\n"
    место: dict = {}
    exec(compile(приставка + исходник[начало:], str(ШАБЛОН), "exec"), место)  # noqa: S102
    return место["цифра_рантайма_выпуска"]


ЦИФРА = _функция()


def _как_сборщик(корень: Path) -> str:
    """Рамка `tools/build_release.py: сумма_рантайма`, выписанная явно.

    Все `src/*.py` по порядку имён, затем `run.py`; для каждого файла — имя,
    NUL, байты, NUL. Имя входит затем, что иначе переименование модуля цифру
    не меняло бы.
    """
    файлы = sorted((корень / "src").glob("*.py"))
    if (корень / "run.py").is_file():
        файлы.append(корень / "run.py")
    сумма = hashlib.sha256()
    for файл in файлы:
        сумма.update(файл.relative_to(корень).as_posix().encode("utf-8"))
        сумма.update(b"\0")
        сумма.update(файл.read_bytes())
        сумма.update(b"\0")
    return сумма.hexdigest() if файлы else ""


def _дерево(корень: Path, файлы: dict) -> Path:
    (корень / "src").mkdir(parents=True, exist_ok=True)
    for имя, текст in файлы.items():
        (корень / имя).write_text(текст, encoding="utf-8")
    return корень


def test_цифра_совпадает_со_сборщиком(tmp_path):
    корень = _дерево(tmp_path, {
        "src/lords-frontend.py": "print('точка входа')\n",
        "src/collection_contract.py": "ТЕКСТЫ = {}\n",
        "src/seo_layer.py": "КАРТА = 1\n",
        "run.py": "import sys\n",
    })
    assert ЦИФРА(корень) == _как_сборщик(корень)
    assert len(ЦИФРА(корень)) == 64


def test_правка_соседнего_модуля_меняет_цифру(tmp_path):
    """Отрицательный контроль из решения D207 — ради него рамка и такая.

    Сумма одной точки входа пропускала правку соседнего модуля молча: на
    живой ячейке это дало exit=0, а через 25 минут exit=1.
    """
    корень = _дерево(tmp_path / "a", {
        "src/lords-frontend.py": "print('точка входа')\n",
        "src/оформление.py": "ЦВЕТ = 'синий'\n",
        "run.py": "import sys\n",
    })
    было = ЦИФРА(корень)
    (корень / "src" / "оформление.py").write_text("ЦВЕТ = 'красный'\n",
                                                  encoding="utf-8")
    _ОЧИСТИТЬ()
    assert ЦИФРА(корень) != было, "правка соседнего модуля цифру не изменила"


def test_переименование_модуля_меняет_цифру(tmp_path):
    """Имя файла входит в сумму — иначе переименование было бы невидимо."""
    корень = _дерево(tmp_path / "b", {
        "src/lords-frontend.py": "print('точка входа')\n",
        "src/один.py": "X = 1\n",
    })
    было = ЦИФРА(корень)
    (корень / "src" / "один.py").rename(корень / "src" / "два.py")
    _ОЧИСТИТЬ()
    assert ЦИФРА(корень) != было, "переименование модуля цифру не изменило"


def test_пустое_дерево_даёт_пустую_цифру(tmp_path):
    """Отсутствие файлов — не повод выдать сумму пустой строки за цифру."""
    корень = tmp_path / "c"
    (корень / "src").mkdir(parents=True)
    assert ЦИФРА(корень) == ""


def test_в_сравнение_идут_обе_цифры():
    """Прежняя редакция сравнивала ТОЛЬКО сумму одного файла, и поле всегда
    отвечало false. Нынешняя — отдаёт обе цифры рамке, которая и решает:
    многофайловая рамка проверяется первой, однофайловая остаётся для ячеек,
    чей сборщик объявляет её (см. блок про две рамки ниже)."""
    начало = ТЕКСТ.index('if путь == "/healthz":')
    кусок = ТЕКСТ[начало:ТЕКСТ.index('if путь == "/assets/nova.webmanifest":', начало)]
    assert "_рамка_цифры(" in кусок[кусок.index('"runtime_digest_match"'):]
    начало_рамки = кусок.index('"runtime_digest_frame"')
    вызов = кусок[начало_рамки:
                  кусок.index('"runtime_digest_match"', начало_рамки)]
    assert "цифра_рантайма_выпуска()" in вызов and "runtime_sha" in вызов, (
        "в рамку обязаны идти обе цифры: иначе одна из двух согласованных "
        "рамок объявления перестанет сходиться")


def test_сумма_одного_файла_осталась_отдельным_полем():
    """Отрицательный контроль: её читает проверка происхождения соседней
    линии, и убирать её нельзя — менялся предикат, а не состав ответа."""
    assert '"runtime_sha256": runtime_sha' in ТЕКСТ


def _ОЧИСТИТЬ() -> None:
    """Пересобрать функцию, чтобы памятка цифры не отвечала за прежнее дерево.

    Памятка хранит цифру по корню, а в этих проверках файлы внутри одного и
    того же корня меняются намеренно.
    """
    global ЦИФРА
    ЦИФРА = _функция()


# ---------------------------------------------------------------------------
# Две рамки объявления цифры артефакта
# ---------------------------------------------------------------------------
#
# Предупреждение линии lordfilm47.space, проверенное в репозитории: рамок
# ДВЕ, и обе согласованы проектом.
#
# * `tests/unit/test_cell_entrypoint_contract.py`: «`entrypoint` означает файл
#   под `src/`, который исполняется, и ЕГО ЖЕ цифру несёт `artifact_sha256`»;
# * решение D207 и сборщик партии K2: цифра считается по ВСЕМУ рантайму,
#   потому что сумма одной точки входа пропускает правку соседнего модуля.
#
# Сравнение только с многофайловой цифрой ломало чужую приёмку выпуска,
# которая требует `runtime_digest_match == true`. «Ложное нет» для исправного
# выпуска — не строгость, а ошибка.


def _рамка():
    исходник = ТЕКСТ[:ТЕКСТ.index("def мета_роботов")]
    начало = исходник.index("def _рамка_цифры")
    место: dict = {}
    exec(compile(исходник[начало:], str(ШАБЛОН), "exec"), место)  # noqa: S102
    return место["_рамка_цифры"]


РАМКА = _рамка()
ПО_РАНТАЙМУ = "a" * 64
ПО_ТОЧКЕ = "b" * 64


def test_многофайловая_рамка_называется_runtime():
    assert РАМКА(ПО_РАНТАЙМУ, ПО_РАНТАЙМУ, ПО_ТОЧКЕ) == "runtime"


def test_однофайловая_рамка_называется_entrypoint():
    """Та, на которой держится приёмка соседней линии."""
    assert РАМКА(ПО_ТОЧКЕ, ПО_РАНТАЙМУ, ПО_ТОЧКЕ) == "entrypoint"


def test_чужая_цифра_не_сходится_ни_одной_рамкой():
    assert РАМКА("c" * 64, ПО_РАНТАЙМУ, ПО_ТОЧКЕ) == ""


def test_отсутствие_объявления_не_совпадение():
    """Отрицательный контроль: пустое поле — не доказательство, и выдавать
    его за совпадение значило бы считать непроверенное проверенным."""
    for пусто in ("", None, "   "):
        assert РАМКА(пусто, ПО_РАНТАЙМУ, ПО_ТОЧКЕ) == ""


def test_строгая_рамка_называется_первой():
    """Когда совпали бы обе (ячейка с единственным модулем), называется
    строгая: иначе отчёт обещал бы меньше, чем проверено."""
    одна = "d" * 64
    assert РАМКА(одна, одна, одна) == "runtime"


def test_поле_совпадения_выведено_из_рамки():
    """`runtime_digest_match` не считается отдельным условием: два условия
    разошлись бы при первой же правке."""
    кусок = ТЕКСТ[ТЕКСТ.index('if путь == "/healthz":'):]
    кусок = кусок[:кусок.index('if путь == "/assets/nova.webmanifest":')]
    хвост = кусок[кусок.index('"runtime_digest_match"'):]
    хвост = хвост[:хвост.index("),")]
    assert "_рамка_цифры(" in хвост


def test_имя_рамки_отдаётся_наблюдению():
    """Слабость однофайловой рамки обязана быть ВИДНА, а не умолчана."""
    кусок = ТЕКСТ[ТЕКСТ.index('if путь == "/healthz":'):]
    assert '"runtime_digest_frame"' in кусок
