"""Состояние целей в кабинете берётся из API, а не из записи реестра.

Дефект, ради которого тест написан, измерен 30.10 на `zonafilm.space`: в реестре
аналитики поле `goals` пусто, и сборщик из-за этого отвечал «цели не созданы»,
НЕ спрашивая API — ни одного дня из 34 снимков. То есть утверждение о КАБИНЕТЕ
выводилось из объявления РЕЕСТРА, а состояние кабинета не было известно ни в
одну сторону, при 839 визитах за неделю.

Правило, которое тест закрепляет: запись реестра — объявление, ответ API —
наблюдение. Спрашивать надо всегда; когда API вернул пусто, так и говорить — но
уже как факт о кабинете, а не как пересказ реестра.
"""
from __future__ import annotations

import sys
import types
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))

from seo_operator import analytics_collect as сбор  # noqa: E402


class Поставщик:
    """Минимальный поставщик: считает обращения и отдаёт заданное."""

    def __init__(self, цели: dict | None, отчёт: dict | None = None):
        self._цели = цели
        # Форма ответа API: totals — плоский список чисел, по одному на метрику
        # (так его и разбирает сборщик: dict(zip(names, totals))).
        self._отчёт = отчёт or {"totals": []}
        self.спрошено = 0

    def list_goal_ids(self, counter_id):  # noqa: D401, N803
        self.спрошено += 1
        return self._цели

    def get_metrica_report(self, counter_id, **кв):  # noqa: D401, N803
        return self._отчёт


def test_пустой_реестр_не_отменяет_запрос_к_api():
    """Пустое поле `goals` больше не решает за кабинет."""
    поставщик = Поставщик(цели={"title_view": 7})
    поставщик._отчёт = {"totals": [42.0]}
    итог = сбор._goal_reaches(поставщик, {"goals": []}, 112582938, "7daysAgo", "yesterday")

    assert поставщик.спрошено == 1, (
        "при пустом реестре API не спросили — вернулась догадка, а не наблюдение")
    assert итог.measured is True, f"измерение не состоялось: {итог}"
    assert итог.value == {"title_view": 42.0}, итог.value


def test_пустой_ответ_api_называется_фактом_о_кабинете():
    """Если API не отдал ни одного goal_id, причина говорит про кабинет."""
    поставщик = Поставщик(цели={})
    итог = сбор._goal_reaches(поставщик, {"goals": []}, 112582938, "7daysAgo", "yesterday")

    assert поставщик.спрошено == 1
    assert итог.measured is False
    assert "в кабинете целей нет" in итог.reason, итог.reason


def test_расхождение_объявления_и_кабинета_называется_числом():
    """Реестр объявляет цели, кабинет пуст — это расхождение, и оно в причине."""
    поставщик = Поставщик(цели={})
    итог = сбор._goal_reaches(поставщик, {"goals": ["title_view", "search"]},
                              113105751, "7daysAgo", "yesterday")

    assert итог.measured is False
    assert "расхождение" in итог.reason and "2" in итог.reason, итог.reason
