"""REQ-SETTINGS-INPUT: показ настройки и её ввод — разные виды одного значения.

Незаданная настройка показывается тире: пустая ячейка читалась бы как пустая
строка, а это другое значение. То же тире подставлялось и в поле ввода — и
«Проверить» на нетронутой форме возвращало 422 «допустимы только буквы, цифры и
знаки _.:-». Оператор ничего не вводил и получал отказ на собственное текущее
состояние; настроить незаданное поле было нельзя вовсе, не стерев тире руками.
"""

from __future__ import annotations

from factory.site_engine.admin import ui


class TestПоказ:
    def test_незаданное_показывается_тире(self):
        assert ui._значение(None) == "—", "пустая ячейка прочиталась бы как пустая строка"

    def test_логическое_показывается_словом_контракта(self):
        assert ui._значение(True) == "true"
        assert ui._значение(False) == "false"

    def test_составное_показывается_разбираемым_видом(self):
        assert ui._значение({"a": 1}) == '{"a": 1}'


class TestВвод:
    def test_незаданное_даёт_пустое_поле(self):
        assert ui._ввод(None) == "", "в поле ввода попадает тире — форма отвергается"

    def test_заданное_вводится_обратно_как_есть(self):
        for значение in ("partner-1", 42, True, False, {"a": 1}, ["b"]):
            assert ui._ввод(значение) == ui._значение(значение), (
                f"вид для ввода разошёлся с показом на {значение!r}")

    def test_ноль_и_пустая_строка_не_путаются_с_незаданным(self):
        assert ui._ввод(0) == "0", "ноль пропал бы из формы как незаданное"
        assert ui._ввод("") == "", "пустая строка и незаданное вводятся одинаково пусто"


class TestФормыБерутВводимыйВид:
    def _данные(self, значение):
        return {
            "siteId": "s-1",
            "canWrite": True,
            "version": "sha256:aa",
            "fields": [{"key": "advertising_partner_id", "value": значение,
                        "type": "string", "description": "партнёр"}],
        }

    def test_страница_настроек_не_подставляет_тире_в_поле(self):
        html = ui.settings(self._данные(None), ["s-1"], предпросмотр=None,
                           flash=None, session_label="стенд", csrf="c")
        i = html.find('name="value"')
        assert i >= 0
        assert 'value=""' in html[i:i + 120], f"в поле ввода подставлено: {html[i:i + 120]}"

    def test_карточка_флота_не_подставляет_тире_в_поле(self):
        записи = [{"siteId": "s-1", "fields": {}}]
        html = ui.control_center(записи, {}, flash=None, session_label="стенд", csrf="c",
                                 настройки={"s-1": self._данные(None)})
        i = html.find('name="value"')
        assert i >= 0
        assert 'value=""' in html[i:i + 160], f"в поле ввода подставлено: {html[i:i + 160]}"
