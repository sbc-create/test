def test_витрины_yummy_исключены_с_измеренной_причиной(capsys):
    """Их выгрузка каталога на диске устарела — сравнение дало бы ложь.

    Измерено 21.10 на `yummyani7.site`: выгрузка собрана 2026-09-28T14:41:47Z
    и содержит 7 386 записей, живая карта — 8 378 произведений. Сравнение по
    ней дало бы 1 078 «лишних» и 86 «отсутствующих»: около 1 164 ложных
    находок на одной витрине. `adskaya-mishen` в выгрузке нет, а живая
    страница отвечает 200 — значит страницы отдаются не из неё.
    """
    assert set(ИНСТР.НЕ_СРАВНИВАЕМ) == {
        "yummyani.site", "yummyani.biz", "yummyani.org",
        "yummyani7.site", "yummyani7.info"}
    код = ИНСТР.главное(["--domain", "yummyani7.site"])
    вывод = capsys.readouterr().out
    # Код 2 = «не измерено». Ноль здесь был бы ложью: регулярная сверка
    # напечатала бы «ок» в столбце, где проход витрину даже не сравнивал —
    # ровно это и случилось в прогоне 21.10 07:00Z у пяти витрин Yummy.
    assert код == 2
    assert "НЕ СРАВНИВАЕТСЯ" in вывод
    assert "sitemap-completeness.py" in вывод


