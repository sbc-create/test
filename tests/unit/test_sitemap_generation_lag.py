"""Отставание карты от доставленного каталога: признак и его ложные находки.

Повод — MOD-81: карта `1lordserials1.online` не переписывалась, пока каталог
рос. Измерено 21.10: файлы карты записаны 20.10 06:19:15Z (через две секунды
после запуска процесса витрины), каталог доставлен 21.10 04:14:41Z, в каталоге
68 451 запись, в карте 67 681, отсутствуют 770, и у 12 из 12 опрошенных стоит
`index, follow`. Семь витрин-сестёр переписали карту через 2-4 минуты после
доставки — значит отставание не свойство устройства, а отказ ОДНОЙ витрины.

Отрицательные контроли, названные заранее:

* **отсутствие `noindex`-записи в карте дефектом НЕ является.** Первая версия
  прохода объявляла расхождением любое отсутствие — и выдала ложную находку
  `animedia.icu` и `animedia.space`, где карта свежая, а 463 отсутствующие
  записи стоят `noindex` (очередь тематического допуска). Карта обязана
  описывать индексируемое;
* **отставание файла по времени само по себе ничего не значит**: снимок
  перезаписывается тем же содержимым, и у `animedia.icu` измерено отставание
  1,2 ч при полностью согласованной карте. Поэтому вывод делается по СОСТАВУ;
* **без опроса индексируемости проход говорит «НЕ ИЗМЕРЕНО»**, а не «ок» и не
  «пробел»;
* **лишний адрес в карте — отдельный исход**: карта обещает обходчику то, чего
  у витрины нет.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "sitemap_generation_lag",
    КОРЕНЬ / "automation/local/sitemap-generation-lag.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

ДОМЕН = "проба.ru"


def _витрина(tmp_path, слаги_каталога, слаги_карты, *, карта_старше_ч=0.0):
    import os
    import time
    д = tmp_path / "data"
    (д / "sitemap").mkdir(parents=True, exist_ok=True)
    кат = д / "проба-01-catalog.json"
    кат.write_text(json.dumps({
        "count": len(слаги_каталога), "revision": "рев",
        "builtAt": "2026-10-21T03:15:26Z",
        "items": [{"slug": с, "url": f"/title/{с}/"} for с in слаги_каталога],
    }), encoding="utf-8")
    карта = д / "sitemap" / "sitemap.xml"
    карта.write_text("<sitemapindex/>", encoding="utf-8")
    if карта_старше_ч:
        прошлое = time.time() - карта_старше_ч * 3600
        os.utime(карта, (прошлое, прошлое))
    return str(д), слаги_карты


def _подготовить(monkeypatch, tmp_path, слаги_каталога, слаги_карты, *,
                 robots: dict[str, str] | None = None, карта_старше_ч=0.0):
    каталог, в_карте = _витрина(tmp_path, слаги_каталога, слаги_карты,
                                карта_старше_ч=карта_старше_ч)
    monkeypatch.setitem(ИНСТР.ВИТРИНЫ, ДОМЕН, (каталог, "проба-01"))
    monkeypatch.setattr(ИНСТР, "слаги_карты",
                        lambda домен, д: (set(в_карте), "подменено"))
    роботс = robots or {}

    def загрузчик(url: str) -> str:
        слаг = url.rstrip("/").rsplit("/", 1)[-1]
        метка = роботс.get(слаг, "index, follow")
        return f'<html><meta name="robots" content="{метка}"></html>'

    return загрузчик


def test_index_страница_вне_карты_это_пробел(monkeypatch, tmp_path):
    з = _подготовить(monkeypatch, tmp_path, ["a", "b", "c"], ["a", "b"])
    итог = ИНСТР.разобрать(ДОМЕН, проб=5, загрузчик=з)
    assert итог["итог"] == "ПРОБЕЛ КАРТЫ"
    assert итог["нет в карте"] == 1
    assert итог["проба отсутствующих"]["index (пробел карты)"] == ["c"]


def test_noindex_страница_вне_карты_не_дефект(monkeypatch, tmp_path):
    """Живой случай: 463 записи очереди допуска на animedia."""
    з = _подготовить(monkeypatch, tmp_path, ["a", "b", "c"], ["a", "b"],
                     robots={"c": "noindex, follow"})
    итог = ИНСТР.разобрать(ДОМЕН, проб=5, загрузчик=з)
    assert итог["итог"] == "отсутствия согласованы с допуском"
    assert итог["проба отсутствующих"]["noindex (отсутствие согласовано)"] == 1


