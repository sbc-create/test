def test_перечень_витрин_покрывает_все_кроме_yummy():
    """«Не измерено» должно оставаться только там, где сверка невозможна.

    21.10 трое витрин animego печатались в регулярной сверке как «не
    измерено» просто потому, что их не было в перечне. Проверено, что сверка
    по ним возможна и чиста (каталог 8 691 запись, builtAt
    2026-10-21T03:15:26Z, состав карты совпадает точно: 8 691 = 8 691), и они
    добавлены. Исключены по измеренной причине только пять витрин Yummy.
    """
    покрыто = set(ИНСТР.ВИТРИНЫ)
    исключено = set(ИНСТР.НЕ_СРАВНИВАЕМ)
    assert {"an1mego.site", "animeg0.site", "an1meg0.site"} <= покрыто
    assert not (покрыто & исключено), "витрина не может быть и в перечне, и в исключении"
    assert len(покрыто) == 12, sorted(покрыто)
