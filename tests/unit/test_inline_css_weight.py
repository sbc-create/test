"""Вес комментариев в inline-CSS: что признак обязан различать.

Главное различение здесь — «блоков `<style>` нет» против «комментариев в них
нет». Оба дают ноль байт комментариев, но означают разное: в первом случае
мерить нечего, во втором страница уже чистая. Один общий исход «0 КиБ, всё
хорошо» выдал бы `yummyani.biz` за исправленную витрину, хотя его inline-CSS
просто не существует.
"""
from __future__ import annotations

import gzip
import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "inline-css-weight.py"

спец = importlib.util.spec_from_file_location("inline_css_weight", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


def страница(стиль: str = "", тело: str = "<p>карточки</p>") -> str:
    блок = f"<style>{стиль}</style>" if стиль else ""
    return f"<html><head>{блок}</head><body>{тело}</body></html>"


def test_без_блоков_style_мерить_нечего():
    итог = модуль.оценить(модуль.разобрать(страница()))
    assert итог["исход"] == модуль.CSS_НЕТ


def test_блок_без_комментариев_это_не_то_же_самое():
    итог = модуль.оценить(модуль.разобрать(страница(".a{color:red}")))
    assert итог["исход"] == модуль.КОММЕНТАРИЕВ_НЕТ


def test_пустое_тело_не_измерено():
    итог = модуль.оценить(модуль.разобрать(""))
    assert итог["исход"] == модуль.НЕ_ИЗМЕРЕНО


def test_мелкий_комментарий_в_пределах():
    итог = модуль.оценить(модуль.разобрать(
        страница("/* почему 22.1px */.a{color:red}")))
    assert итог["исход"] == модуль.В_ПРЕДЕЛАХ


def test_крупные_комментарии_заметный_вес():
    # Один и тот же текст-пояснение, повторённый так, что после сжатия
    # прирост выходит за порог.
    пояснение = "".join(
        f"/* Измерено в Chromium {i}: сумма 205+259=464px, потолок срезал"
        f" текст — 74px, высоту задаёт содержимое, иначе ряд растянется под"
        f" природную пропорцию портретного постера {i}. */.r{i}{{color:#{i}}}"
        for i in range(400))
    замер = модуль.разобрать(страница(пояснение))
    итог = модуль.оценить(замер)
    assert итог["исход"] == модуль.ЗАМЕТНО
    assert замер["gzip_прирост_байт"] / 1024 >= модуль.ПОРОГ_ПРИРОСТА_КИБ


def test_прирост_считается_по_сжатому_а_не_по_сырому():
    # Сырые байты комментариев заведомо больше прироста после сжатия: если
    # когда-нибудь сравняются, значит считается не то.
    пояснение = "/* " + ("пояснение к вёрстке " * 2000) + "*/.a{color:red}"
    замер = модуль.разобрать(страница(пояснение))
    assert замер["комментариев_байт"] > замер["gzip_прирост_байт"] * 3


def test_доля_комментариев_в_css_а_не_в_странице():
    стиль = "/*" + "x" * 500 + "*/" + ".a{color:red}"
    замер = модуль.разобрать(страница(стиль, тело="<p>" + "т" * 5000 + "</p>"))
    assert замер["доля_комментариев_в_css"] > 90


def test_несколько_блоков_складываются():
    тело = ("<html><head><style>/*один*/.a{color:red}</style>"
            "<style>/*два*/.b{color:blue}</style></head><body>x</body></html>")
    замер = модуль.разобрать(тело)
    assert замер["блоков_style"] == 2
    assert замер["комментариев_байт"] == len("/*один*//*два*/".encode())


def test_комментарий_через_несколько_строк_учтён():
    стиль = "/* строка один\n   строка два\n   строка три */.a{color:red}"
    замер = модуль.разобрать(страница(стиль))
    assert замер["комментариев_байт"] == len(
        "/* строка один\n   строка два\n   строка три */".encode())


def test_разметка_вне_style_не_трогается():
    # Комментарий HTML — не CSS, и в счёт идти не должен.
    тело = ("<html><head><style>.a{color:red}</style></head>"
            "<body><!-- заметка редактора --><p>x</p></body></html>")
    замер = модуль.разобрать(тело)
    assert замер["комментариев_байт"] == 0


def test_урезанная_страница_меньше_исходной_по_сжатию():
    стиль = "/* " + ("пояснение " * 800) + "*/.a{color:red}"
    замер = модуль.разобрать(страница(стиль))
    assert замер["gzip_прирост_байт"] > 0
    assert замер["gzip_байт"] == len(
        gzip.compress(страница(стиль).encode(), 9))


def test_порог_назван_числом_а_не_словом():
    assert isinstance(модуль.ПОРОГ_ПРИРОСТА_КИБ, float)
    assert 0 < модуль.ПОРОГ_ПРИРОСТА_КИБ < 50
