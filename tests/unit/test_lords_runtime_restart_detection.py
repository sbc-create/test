"""Перезапуск витрины решается по ВСЕМУ рантайму, а не по одному `serve.py`.

Дефект измерен на канарейке lords-01 8 сентября 2026.

Релиз `0dea0dc5e4d8` был принят, в нём лежал новый
`lib/factory/lords/search.py`, а `serve.py` остался побайтово прежним — его
генерирует `emit-runtime.py`, и он не зависит от библиотек. Условие перезапуска
сравнивало только `serve.py`, объявило рантайм неизменным, и витрина продолжила
отвечать СТАРЫМ кодом при новом релизе.

Почему это тихо. Страницы отдавались, HTTP 200, ошибок в журнале нет. Разница
видна только в выдаче: `100 дней` находил ноль записей там, где соседние
витрины находили пять. Без сверки с соседями дефект прошёл бы незамеченным.

Почему нельзя вернуть безусловный перезапуск: рядом в сценарии записано, что он
давал 243 перезапуска в сутки, и в секундное окно между «остановлен» и
«запущен» nginx отвечал 502 живому посетителю. Поэтому проверка расширяется,
а не отменяется.
"""

from __future__ import annotations

from pathlib import Path

СЦЕНАРИЙ = Path(__file__).resolve().parents[2] / "automation" / "host" / "lords-content-refresh.sh"

СРАВНЕНИЕ_SERVE = "cmp -s " + chr(34) + "${current}/serve.py" + chr(34)
СРАВНЕНИЕ_LIB = "diff -rq " + chr(34) + "${current}/lib" + chr(34)


def _блок_решения(текст: str) -> str:
    начало = текст.index("need_restart=0")
    конец = текст.index("systemctl restart", начало)
    return текст[начало:конец]


class TestРешениеОПерезапуске:
    def setup_method(self):
        self.текст = СЦЕНАРИЙ.read_text(encoding="utf-8")

    def test_сценарий_на_месте(self):
        assert СЦЕНАРИЙ.is_file()

    def test_serve_py_по_прежнему_сравнивается(self):
        assert СРАВНЕНИЕ_SERVE in self.текст

    def test_библиотеки_рантайма_тоже_сравниваются(self):
        assert СРАВНЕНИЕ_LIB in self.текст, (
            "изменение lib/ не приводит к перезапуску — витрина останется на старом коде"
        )

    def test_сравнение_lib_ведёт_к_перезапуску(self):
        блок = _блок_решения(self.текст)
        assert СРАВНЕНИЕ_LIB in блок, "сравнение lib/ стоит вне блока решения о перезапуске"
        хвост = блок[блок.index(СРАВНЕНИЕ_LIB):]
        assert "need_restart=1" in хвост, "ветка lib/ не выставляет need_restart"

    def test_перезапуск_остаётся_условным(self):
        """Расширение проверки не должно превратиться в безусловный перезапуск.

        Считать вхождения `systemctl restart` бесполезно: их пять, и одно из
        них — в комментарии. Существенно другое: перезапуск на переключении
        релиза стоит ПОД условием, а не рядом с ним.
        """
        assert "need_restart=0" in self.текст, "исчезло начальное значение"
        охрана = "if [ " + chr(34) + "$need_restart" + chr(34) + " = " + chr(34) + "1" + chr(34) + " ]"
        assert охрана in self.текст, "перезапуск на переключении релиза больше не под условием"
        после = self.текст[self.текст.index(охрана):]
        assert "systemctl restart" in после[:200], "под условием нет самого перезапуска"
