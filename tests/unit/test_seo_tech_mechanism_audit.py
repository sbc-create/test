#  Живое состояние службы приёмка не трогает.
# --------------------------------------------------------------------------- #
def test_живое_состояние_не_трогается(м, tmp_path, текст_механизма):
    """Всё, что приёмка пишет, лежит в стенде; дерево службы только читается."""
    дер = дерево(tmp_path, текст_механизма, следы=True)
    состояние = дер / "var" / "seo-tech"
    отпечаток = {п.relative_to(дер).as_posix(): п.read_bytes()
                 for п in sorted(дер.rglob("*")) if п.is_file()}
    прогон(м, tmp_path, дер)
    после = {п.relative_to(дер).as_posix(): п.read_bytes()
             for п in sorted(дер.rglob("*")) if п.is_file()}
    assert после == отпечаток, "приёмка изменила дерево службы"
    assert not (состояние / "claims").exists(), "захваты ушли в живой каталог"
    assert (tmp_path / "стенд" / "state" / "claims").is_dir(), "стенд не использован"


def test_стенд_пересобирается_между_прогонами(м, tmp_path, текст_механизма):
    """Остатки прежнего прогона не должны влиять на вердикт."""
    дер = дерево(tmp_path, текст_механизма)
    первый_код, _ = прогон(м, tmp_path, дер)
    мусор = tmp_path / "стенд" / "state" / "claims" / "ПРОБА-1.claim"
    assert мусор.exists(), "стенд не содержит ожидаемого следа"
    второй_код, вывод = прогон(м, tmp_path, дер)
    assert второй_код == первый_код == 0, вывод


def test_стенд_не_собрался_это_исход_два(м, tmp_path, текст_механизма, monkeypatch):
    """Не смогли построить стенд — значит не проверили, а не «всё хорошо»."""
    дер = дерево(tmp_path, текст_механизма)
    monkeypatch.setattr(м, "собрать_стенд",
                        lambda стенд: (_ for _ in ()).throw(OSError("нет места")))
    assert м.главное(["--tree", str(дер), "--stand", str(tmp_path / "с2")]) == 2


def test_стенд_не_оставляет_рабочих_копий_в_дереве(м, tmp_path, текст_механизма):
    """Копии стенда — внутри стенда, и каталог tmp_path после прогона чист."""
    дер = дерево(tmp_path, текст_механизма)
    прогон(м, tmp_path, дер)
    чужие = [п for п in tmp_path.iterdir() if п.name not in ("дерево", "стенд")]
    assert not чужие, f"приёмка оставила {чужие}"
    shutil.rmtree(tmp_path / "стенд")
