def test_неascii_путь_проверки_расхождением_больше_не_считается(
        м, tmp_path, текст_механизма):
    """Признак снят, потому что механизм это закрыл (`ls-tree -r -z`).

    Оставленный, он кричал бы волка на законных задачах — а проверка, которая
    тревожит по устаревшей причине, кончается тем, что её перестают читать.
    Само свойство проверяется теперь ПОВЕДЕНИЕМ: в стенде есть задача с
    кириллическим именем файла проверки, и она обязана получить вердикт.
    """
    дер = дерево(tmp_path, текст_механизма, очередь={"tasks": [
        {"id": "T001", "status": "queued", "repo": "r1",
         "check": "checks/проверка.py"}]})
    код, вывод = прогон(м, tmp_path, дер)
    assert код == 0, вывод
    assert "к сведению" in вывод and "не-ASCII" in вывод
    assert строка_признака(вывод, "не-ASCII именем").startswith("   [ок ]")


