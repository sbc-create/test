def test_живой_механизм_приёмку_проходит(м, tmp_path, текст_механизма):
    """Без этого мутационные тесты ничего не доказывают.

    Падение здесь — факт о механизме, а не о тесте: смотри прогон
    `automation/local/seo-tech-mechanism-audit.py`, он называет признак.
    """
    код, вывод = прогон(м, tmp_path, дерево(tmp_path, текст_механизма))
    assert код == 0, вывод
    assert "расхождений: 0" in вывод


