"""Приёмка механизма автопродолжения: умеет ли она ещё падать.

Инструмент проверяет чужой механизм (`seo_operator.tech_run` ведёт SEO-сессия),
и после того как все его признаки позеленели, у приёмки появляется ровно одна
опасность: зелёный результат может означать не исправный механизм, а
разучившуюся проверку. Поэтому главные тесты здесь — **мутационные**: берётся
живой модуль, в нём ломается ровно одно свойство, и приёмка ОБЯЗАНА назвать
именно его. Проверка, которая не умеет упасть, доверия не несёт (D205).

Остальное — про то, что приёмка не путает незнание с обвинением: отсутствие
следов прогонов это факт о приёмке, а не о механизме.

Сеть не нужна; git нужен — механизм построен на `git worktree`, и проверять его
без git нечем. Все записи идут в одноразовый стенд внутри tmp_path.
"""
from __future__ import annotations

import importlib.util
import io
import json
import shutil
from contextlib import redirect_stdout
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "seo-tech-mechanism-audit.py"
#: Живой механизм под проверкой. Копируется, а не правится.
#:
#: Путь абсолютный намеренно: файл принадлежит ЭТОМУ репозиторию, но живёт на
#: соседней ветке — `claude/nova-publish-memory-01`, выложенной в рабочую копию
#: `wt-portable-site-cell-01` (там же и коммит `a093ee7`, на который ссылаются
#: пояснения). В ветке этой сессии `seo_operator/tech_run.py` не отслеживается
#: вовсе, поэтому читать его «у себя» нечем, а подменять проверяемый код
#: копией в своей ветке значило бы проверять не то, что работает.
#:
#: Принадлежность названа прямо, потому что однажды была названа неверно:
#: 2026-10-15 провал этой приёмки был описан как правка «соседней SEO-сессии»,
#: хотя у той нет ни `seo_operator`, ни `tech_run.py` — у неё `seo_engine`.
#: Перенос каталога копий сделала наша же линия работ, и расхождение было
#: внутренним, а не чужим. Имя каталога `seo_operator` и ввело в заблуждение.
МЕХАНИЗМ = Path("/home/claude/wt-portable-site-cell-01/seo_operator/tech_run.py")

ОЧЕРЕДЬ_ДЕРЕВА = {"tasks": [
    {"id": "T001", "status": "queued", "repo": "r1", "check": "checks/a.py"},
    {"id": "T002", "status": "queued", "repo": "r2", "check": "checks/b.py"}]}


def _модуль():
    спец = importlib.util.spec_from_file_location("audit", ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


@pytest.fixture(scope="module")
def м():
    return _модуль()


@pytest.fixture(scope="module")
def текст_механизма():
    if not МЕХАНИЗМ.is_file():
        pytest.skip(f"нет {МЕХАНИЗМ} — механизм ведёт другая сессия")
    return МЕХАНИЗМ.read_text(encoding="utf-8")


def дерево(tmp_path: Path, текст: str, *, очередь=None, следы: bool = False) -> Path:
    """Подставное дерево службы: копия механизма, очередь и, по просьбе, следы."""
    корень = tmp_path / "дерево"
    (корень / "seo_operator").mkdir(parents=True, exist_ok=True)
    (корень / "seo_operator" / "tech_run.py").write_text(текст, encoding="utf-8")
    (корень / "config").mkdir(parents=True, exist_ok=True)
    (корень / "config" / "seo-tech-queue.json").write_text(
        json.dumps(очередь if очередь is not None else ОЧЕРЕДЬ_ДЕРЕВА,
                   ensure_ascii=False), encoding="utf-8")
    состояние = корень / "var" / "seo-tech"
    состояние.mkdir(parents=True, exist_ok=True)
    if следы:
        (состояние / "claims.jsonl").write_text("", encoding="utf-8")
        (состояние / "runs.jsonl").write_text("", encoding="utf-8")
    return корень


def прогон(м, tmp_path: Path, дер: Path):
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        код = м.главное(["--tree", str(дер), "--stand", str(tmp_path / "стенд")])
    return код, буфер.getvalue()


def строка_признака(вывод: str, кусок: str) -> str:
    найдено = [с for с in вывод.splitlines() if кусок in с]
    assert найдено, f"признака {кусок!r} в выводе нет:\n{вывод}"
    return найдено[0]


def мутировать(текст: str, было: str, стало: str) -> str:
    assert текст.count(было) == 1, (
        f"мутация неоднозначна: {было!r} встречается {текст.count(было)} раз — "
        "тест сломался бы молча, проверив не то свойство")
    return текст.replace(было, стало)


