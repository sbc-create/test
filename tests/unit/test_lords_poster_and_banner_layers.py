"""Слои постера и баннера в оформлении витрин.

Два дефекта были измерены на боевых animedia.icu и animedia.space
(TEMPLATE-POSTDEPLOY-ACCEPTANCE-01) и оба сводились к одной причине: правило,
которое есть в первом семействе оформления, при копировании во второе и третье
потерялось.

1. Заглушка постера рисуется слоем НИЖЕ изображения — так задумано в
   `заглушка_постера`. Но лежать ниже она может только если у изображения есть
   своя позиция и `z-index`: `.zt__none` позиционирован (`position:absolute`),
   а позиционированный элемент красится поверх статического независимо от
   порядка в разметке. Без правила для `<img>` надпись «постер не открылся»
   проступала поверх успешно загруженного постера — измерено 6/6 на двух
   доменах и трёх ширинах.

2. Внутри `<div class="zban__img">` лежит `<img>` без класса. Правило
   `.zban__img{width:100%}` применялось к контейнеру, а не к картинке, и
   картинка рисовалась в натуральную ширину: 715 px внутри 1438 px, то есть
   половина баннера оставалась пустой.

Проверяется контракт правил, а не наличие подстроки: из артефакта берётся
настоящий CSS каждого семейства и разбирается на правила. Артефакт при этом не
исполняется — он подключает `seo_layer`, который живёт рядом с ним на хосте и в
репозиторий не входит; разбор через `ast` даёт тот же текст без этой зависимости.
"""

from __future__ import annotations

import ast
import re

import pytest

from factory.paths import PATHS

ARTIFACT = PATHS.root / "automation/host/lords-frontend.py"

#: Константа оформления каждого семейства. Имя — то же, что в артефакте.
СТИЛИ = {
    "lords-1.1.0": "ЛОРДС_СТИЛЬ",
    "zona-1.1.0": "ЗОНА_СТИЛЬ_1_1",
    "zona-1.2.0": "ЗОНА_СТИЛЬ",
    "animedia-1.2.0": "АНИМЕДИА_СТИЛЬ",
}


def _строковые_константы() -> dict:
    """Строковые константы верхнего уровня артефакта, без его исполнения."""
    дерево = ast.parse(ARTIFACT.read_text(encoding="utf-8"))
    найдено = {}
    for узел in дерево.body:
        if not isinstance(узел, ast.Assign):
            continue
        if not isinstance(узел.value, ast.Constant) or not isinstance(узел.value.value, str):
            continue
        for цель in узел.targets:
            if isinstance(цель, ast.Name):
                найдено[цель.id] = узел.value.value
    return найдено


@pytest.fixture(scope="module")
def стили() -> dict:
    константы = _строковые_константы()
    пропущено = [имя for имя in СТИЛИ.values() if имя not in константы]
    assert not пропущено, (
        f"в артефакте нет констант оформления {пропущено}: тест сверяет "
        f"поимённо, чтобы переименование не превратило проверку в пустую")
    return константы


def _правило(css: str, селектор: str) -> str | None:
    """Тело правила по точному селектору, или None.

    Комментарии снимаются до разбора: иначе `/* … */` перед селектором
    приклеивается к нему, и правило считается отсутствующим.
    """
    без_комментариев = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for м in re.finditer(r"([^{}]+)\{([^}]*)\}", без_комментариев):
        if селектор in {с.strip() for с in м.group(1).split(",")}:
            return м.group(2).replace(" ", "").replace("\n", "")
    return None


@pytest.mark.parametrize("витрина", sorted(СТИЛИ))
def test_заглушка_не_перекрывает_загруженный_постер(стили, витрина):
    """У постера страницы тайтла есть свой слой выше заглушки."""
    css = стили[СТИЛИ[витрина]]
    if ".zhead__ps" not in css:
        pytest.skip("в этом оформлении нет крупного постера страницы тайтла")

    заглушка = _правило(css, ".zt__none")
    assert заглушка and "position:absolute" in заглушка, (
        "заглушка позиционирована — поэтому изображению нужен собственный слой")

    # Оформление Animedia не держит крупный постер в `.zhead__ps`: контейнер там
    # объявлен `display:contents`, а рамку задаёт своя обёртка — `.ztitle__poster`
    # на странице тайтла и `.aep-ctx__poster` на точной серии. Контракт от этого
    # не меняется: у изображения обязан быть свой слой выше заглушки, поэтому
    # ищем правило и по этим селекторам тоже.
    правило = (_правило(css, ".zhead__img")
               or _правило(css, ".zhead__ps img")
               or _правило(css, ".ztitle__poster .zhead__img")
               or _правило(css, ".aep-ctx__poster .zhead__img"))
    assert правило is not None, (
        "у постера страницы тайтла нет собственного правила: заглушка будет "
        "краситься поверх успешно загруженной картинки")
    assert "z-index:1" in правило, "постер обязан лежать выше заглушки"
    assert "position:relative" in правило or "position:absolute" in правило, (
        "без собственной позиции z-index у постера не действует")


@pytest.mark.parametrize("витрина", sorted(СТИЛИ))
def test_картинка_баннера_заполняет_контейнер(стили, витрина):
    """Правило адресует вложенный `<img>`, а не только его контейнер."""
    css = стили[СТИЛИ[витрина]]
    if ".zban__img" not in css:
        pytest.skip("в этом оформлении нет баннера страницы тайтла")

    вложенное = _правило(css, ".zban__img img")
    assert вложенное is not None, (
        "разметка баннера — <div class=zban__img><img></div>: без правила для "
        "вложенной картинки она рисуется в натуральную ширину")
    assert "width:100%" in вложенное and "height:100%" in вложенное
    assert "object-fit:cover" in вложенное, "иначе картинка исказится по пропорциям"


@pytest.mark.parametrize("витрина", sorted(СТИЛИ))
def test_контейнер_баннера_не_схлопывается(стили, витрина):
    """Абсолютный слой внутри требует собственной высоты у контейнера.

    Если `.zban__img` позиционирован абсолютно, он выпадает из потока, и без
    `min-height` у `.zban` баннер получил бы нулевую высоту — то есть исчез бы.
    """
    css = стили[СТИЛИ[витрина]]
    if ".zban__img" not in css:
        pytest.skip("в этом оформлении нет баннера страницы тайтла")

    слой = _правило(css, ".zban__img") or ""
    if "position:absolute" not in слой:
        pytest.skip("слой баннера остаётся в потоке — высота берётся от него")

    контейнер = _правило(css, ".zban")
    assert контейнер and "min-height" in контейнер, (
        "контейнер баннера схлопнется в ноль: внутри только абсолютный слой")


def test_правило_скрытия_идёт_после_правил_отображения(стили):
    """`img[hidden]` обязан побеждать `display:block` у тех же картинок.

    Специфичность `img[hidden]` и `.zhead__ps img` совпадает, поэтому исход
    решает порядок в таблице. Обработчик ошибки снимает картинку через
    `i.hidden=true`; если правило скрытия окажется выше по тексту, сломанный
    постер останется видимым, а заглушка под ним — недостижимой.
    """
    for витрина, имя in sorted(СТИЛИ.items()):
        css = стили[имя]
        if "img[hidden]" not in css:
            continue
        скрытие = css.index("img[hidden]")
        for селектор in (".zhead__ps img,.zhead__img", ".zt__p img,.zt__img"):
            место = css.find(селектор)
            if место != -1:
                assert место < скрытие, (
                    f"{витрина}: правило {селектор} объявлено после "
                    f"img[hidden] и перебьёт скрытие сломанной картинки")
