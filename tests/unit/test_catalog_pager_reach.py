"""Докуда доходит просмотр каталога: двоичный поиск последней непустой страницы.

Этой мерой измерен дефект D4 (MOD-108): листалка объявляет 350 страниц, а
содержимое кончается на 334-й — ровно 8 000 записей, то есть 80 запросов по 100.
Ошибка в мере дороже отсутствия меры: «доходит до 350» у обрезанного каталога
закрыло бы дефект, которого никто не исправлял.

Проверяются обе стороны: находка там, где обрезка есть, и молчание там, где
каталог кончается честно. Отдельно — что непрочитанная страница не считается
пустой: иначе сетевой сбой выглядел бы как обрезка.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "catalog_pager_reach",
    КОРЕНЬ / "automation/local/catalog-pager-reach.py")
ИНС = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНС)


def страница(карточек: int, найдено: int | None = None,
             страниц: int | None = None, первая: int = 0) -> str:
    части = []
    if найдено is not None:
        части.append(f"<p>Найдено {найдено} записей</p>")
    if страниц is not None:
        части.append(f'<a href="?page=2">2</a><a href="?page={страниц}">{страниц}</a>')
    for н in range(первая, первая + карточек):
        части.append(f'<a href="/anime/s{н}">T{н}</a>')
    return "<html>" + "".join(части) + "</html>"


@pytest.fixture()
def сеть(monkeypatch):
    таблица: dict[str, str] = {}

    def достать(адрес, таймаут=45):
        return таблица.get(адрес)

    monkeypatch.setattr(ИНС, "достать", достать)
    return таблица


def _каталог(сеть, последняя_с_карточками: int, объявлено: int,
             найдено: int | None = None, размер: int = 24):
    """Витрина, у которой содержимое кончается на заданной странице."""
    for н in range(1, объявлено + 2):
        хвост = "" if н <= 1 else f"?page={н}"
        карточек = размер if н < последняя_с_карточками else (
            8 if н == последняя_с_карточками else 0)
        сеть[f"https://x.test/catalog/{хвост}"] = страница(
            карточек, найдено=найдено if н == 1 else None,
            страниц=объявлено if н == 1 else None, первая=н * 100)


def test_обрезка_каталога_находится(сеть):
    """Тот самый дефект: объявлено 350, содержимое до 334-й, охват 8 000."""
    _каталог(сеть, последняя_с_карточками=334, объявлено=350)
    итог = ИНС.проверить("x.test", образцы=())
    assert итог["измерено"] is True
    assert итог["объявлено_страниц"] == 350
    assert итог["доходит_до_страницы"] == 334
    assert итог["карточек_на_ней"] == 8
    assert итог["охват_записей"] == 333 * 24 + 8 == 8000
    assert any("кратен тысяче" in з for з in итог["замечания"])
    assert any("объявлены" in з and "пусты" in з for з in итог["замечания"])


def test_честный_конец_каталога_замечаний_не_даёт(сеть):
    """Последняя объявленная страница несёт карточки — обрезки нет."""
    _каталог(сеть, последняя_с_карточками=12, объявлено=12)
    итог = ИНС.проверить("x.test", образцы=())
    assert итог["доходит_до_страницы"] == 12
    assert итог["замечания"] == []


def test_недостижимые_записи_считаются_от_объявленного_числа(сеть):
    _каталог(сеть, последняя_с_карточками=334, объявлено=350, найдено=8378)
    итог = ИНС.проверить("x.test", образцы=())
    assert итог["каталог_записей"] == 8378
    assert итог["недостижимо"] == 8378 - 8000
    assert any("недостижимо 378" in з for з in итог["замечания"])


def test_непрочитанная_страница_не_считается_пустой(сеть):
    """Сетевой сбой не должен выглядеть обрезкой каталога."""
    _каталог(сеть, последняя_с_карточками=20, объявлено=20)
    del сеть["https://x.test/catalog/?page=15"]
    итог = ИНС.проверить("x.test", образцы=())
    # Двоичный поиск сдвигается вниз, но страницы ниже по-прежнему непустые:
    # вердикт не превращается в «доходит до 1».
    assert итог["доходит_до_страницы"] >= 10


def test_непрочитанный_каталог_это_не_измерено(сеть):
    итог = ИНС.проверить("x.test", образцы=())
    assert итог["измерено"] is False
    assert "НЕ ИЗМЕРЕНО" in итог["замечания"][0]


def test_двоичный_поиск_дешевле_перебора(сеть):
    """Запросов должно быть порядка логарифма, иначе проход бьёт по витрине."""
    _каталог(сеть, последняя_с_карточками=334, объявлено=350)
    итог = ИНС.проверить("x.test", образцы=())
    assert итог["запросов_поиска"] <= 12, итог["запросов_поиска"]


def test_образцы_страниц_сохраняются_для_сверки(сеть):
    """Состав страниц до и после правки сравнивается по этим образцам."""
    _каталог(сеть, последняя_с_карточками=334, объявлено=350)
    итог = ИНС.проверить("x.test", образцы=(1, 100))
    assert sorted(итог["образцы"]) == [1, 100]
    assert итог["образцы"][1] and итог["образцы"][100]
    assert итог["образцы"][1] != итог["образцы"][100]


