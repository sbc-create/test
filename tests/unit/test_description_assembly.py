def test_редакционный_текст_проходит_насквозь(сборка):
    деталь = dict(ПОЛНАЯ)
    деталь["description"] = ("Редакторский текст о сериале, написанный "
                            "человеком и не подлежащий переписыванию кодом "
                            "ни при каких условиях.")
    деталь["_edited"] = True
    строка = сборка.описание({}, деталь, "lordserials22.info")
    assert строка.startswith("Редакторский текст")
    assert "сериал 2020 года" not in строка.lower()


def test_обрезка_не_рвёт_слово_и_не_оставляет_многоточия(сборка):
    деталь = dict(ПОЛНАЯ)
    деталь["description"] = ("Очень длинный текст поставщика, который заведомо "
                            "не поместится в отведённые сто шестьдесят знаков "
                            "и обязан быть обрезан по границе, а не посередине "
                            "слова, и уж точно без многоточия на конце...")
    for хост in сборка.ПРОФИЛИ:
        строка = сборка.описание({}, dict(деталь), хост)
        assert len(строка) <= сборка.ДЛИНА_МАКС, хост
        assert not строка.endswith("..."), хост
        assert not строка.endswith("…"), хост
        assert "  " not in строка, хост
        assert строка[-1] not in ",;:·-", хост


