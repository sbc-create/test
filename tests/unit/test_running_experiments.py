def test_реестры_включают_и_владельца_и_свой():
    пути = [str(п) for п in мера.реестры()]
    assert пути, "ни один реестр не найден"
    assert any("wt-portable-site-cell-01" in п for п in пути), пути


def test_реестр_владельца_читается_первым():
    """Порядок важен: свой реестр беднее и не должен затенять владельца."""
    пути = мера.реестры()
    if len(пути) > 1:
        assert "wt-portable-site-cell-01" in str(пути[0]), пути


# --- чтение ---------------------------------------------------------------

def test_читается_и_список_и_объект(tmp_path):
    как_объект = tmp_path / "a.json"
    как_объект.write_text(json.dumps({"experiments": [{"experiment_id": "x"}]}),
                          encoding="utf-8")
    как_список = tmp_path / "b.json"
    как_список.write_text(json.dumps([{"experiment_id": "y"}]),
                          encoding="utf-8")
    assert мера.прочитать(как_объект)[0]["experiment_id"] == "x"
    assert мера.прочитать(как_список)[0]["experiment_id"] == "y"


def test_в_живом_реестре_владельца_есть_действующие_опыты():
    """Если их ноль — либо все закрыты, либо мера читает не тот файл.

    Проверка намеренно мягкая: она требует не конкретного числа, а того, что
    мера ВИДИТ реестр владельца и разбирает его.
    """
    пути = [п for п in мера.реестры()
            if "wt-portable-site-cell-01" in str(п)]
    if not пути:
        return  # копии владельца здесь нет — это отдельный случай
    записи = мера.прочитать(пути[0])
    assert записи, "реестр владельца прочитан пустым"
    assert all("experiment_id" in з or "id" in з for з in записи)

# --- КОНТРОЛИ опыта, а не только канарейка ---------------------------------
#
# Измерено на себе 22.10: мера печатала только канарейку, а все три витрины
# AnimeGo одновременно служат контролями чужих опытов — и названы они в поле
# `applicability`, которого мера не печатала. Правило канарейки этот случай не
# покрывает: гипотеза не переносится, а КОНТРОЛЬ портится. Контроль обязан
# остаться неизменным, иначе сравнивать не с чем.

ОПЫТ_С_КОНТРОЛЕМ = {
    "experiment_id": "exp-x",
    "site_id": "cell-01",
    "hypothesis": "гипотеза про серии",
    "applicability": "canary.site: 206 адресов; контроль — control.site и"
                     " other.site (тот же код)",
    "primary_metric": "входы на страницы серий",
}


def test_домен_контроля_находится_хотя_канарейкой_не_является():
    н = мера.упоминания("control.site", [ОПЫТ_С_КОНТРОЛЕМ])
    assert len(н) == 1
    assert "applicability" in н[0]["поля"]


def test_домен_не_упомянутый_не_находится():
    assert мера.упоминания("чужой.site", [ОПЫТ_С_КОНТРОЛЕМ]) == []


def test_применимость_возвращается_целиком_без_обрезки():
    """Обрезка применимости скрыла бы как раз список контролей."""
    н = мера.упоминания("control.site", [ОПЫТ_С_КОНТРОЛЕМ])
    assert н[0]["применимость"] == ОПЫТ_С_КОНТРОЛЕМ["applicability"]
    assert "other.site" in н[0]["применимость"]


def test_поле_применимости_входит_в_перечень_просматриваемых():
    """Пропустить это поле значит не увидеть контроль ни у одного опыта."""
    assert "applicability" in мера.ПОЛЯ_ТЕКСТА


def test_роль_из_текста_не_объявляется_а_из_поля_канарейки_объявляется():
    """Граница между фактом и домыслом проходит по ИСТОЧНИКУ.

    Поле `canary`/`site_id` существует ровно для того, чтобы назвать
    канарейку, — вывод из него факт. Из ПРОЗЫ (`applicability`) роль не
    выводится: на этом я уже ошибалась дважды, привязывая недостаток к домену
    по тексту. Поэтому мера отдаёт поля, где домен назван, и отдельный флаг,
    опирающийся только на поле канарейки, — и никакой общей «роли».
    """
    н = мера.упоминания("control.site", [ОПЫТ_С_КОНТРОЛЕМ])
    assert "роль" not in н[0]
    assert set(н[0]) == {"опыт", "канарейка", "канарейка_это_он", "поля",
                         "применимость"}
    # домен назван ТОЛЬКО в прозе — значит роль не объявляется
    assert н[0]["поля"] == ["applicability"]
    assert н[0]["канарейка_это_он"] is False


def test_код_3_означает_прочти_запись_а_не_запрет():
    """0 и 3 различаются: 3 — «домен участвует», а не «менять нельзя»."""
    код = мера.main(["--domain", "заведомо-отсутствующий.invalid"])
    assert код == 0


def test_живые_витрины_animego_названы_контролями_в_реестре_владельца():
    """Тот самый случай. Если перестанет быть правдой — опыты закрылись."""
    пути = [п for п in мера.реестры()
            if "wt-portable-site-cell-01" in str(п)]
    if not пути:
        return
    дей = мера.действующие(мера.прочитать(пути[0]))
    for домен in ("an1meg0.site", "an1mego.site", "animeg0.site"):
        н = мера.упоминания(домен, дей)
        assert н, f"{домен} не найден в действующих опытах"
        assert any("applicability" in з["поля"] for з in н), (
            f"{домен} найден, но не в применимости — контроль не виден")

# --- поле канарейки несёт то домен, то ИМЯ ЯЧЕЙКИ -------------------------
#
# Из-за этого канарейка `exp-animego-episode-jsonld` (site_id animego-04)
# печаталась как «возможен КОНТРОЛЬ» для an1meg0.site: домена в поле нет, там
# имя ячейки. Docstring обещал искать и ячейку, а код искал только домен —
# обещание без кода равно отчёту о непроведённой проверке.

ОПЫТ_ПО_ЯЧЕЙКЕ = {
    "experiment_id": "exp-y",
    "site_id": "animego-04",
    "hypothesis": "разметка серий",
    "applicability": "an1meg0.site: 860 серий; контроль — an1mego.site",
}


def test_канарейка_узнаётся_по_имени_ячейки():
    н = мера.упоминания("an1meg0.site", [ОПЫТ_ПО_ЯЧЕЙКЕ], "animego-04")
    assert н and н[0]["канарейка_это_он"] is True


def test_без_имени_ячейки_канарейка_не_узнаётся_и_это_видно():
    """Прежнее поведение: не ошибка вывода, а потеря точности."""
    н = мера.упоминания("an1meg0.site", [ОПЫТ_ПО_ЯЧЕЙКЕ])
    assert н, "домен должен находиться по применимости и без ячейки"
    assert н[0]["канарейка_это_он"] is False


def test_контроль_не_становится_канарейкой_от_имени_ячейки():
    н = мера.упоминания("an1mego.site", [ОПЫТ_ПО_ЯЧЕЙКЕ], "animego-02")
    assert н and н[0]["канарейка_это_он"] is False
    assert "applicability" in н[0]["поля"]


