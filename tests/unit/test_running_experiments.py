"""Мера действующих опытов: отличать идущий опыт от завершённого.

Повод измеренный, 22.10: реестр опытов в этой копии содержит один
демонстрационный прогон, а действующие опыты живут в копии-владельце. Из-за
этого две задачи из исследования повторили гипотезы идущих опытов, то есть
нарушали правило канарейки. Мера читает реестр ВЛАДЕЛЬЦА и печатает
действующие опыты; здесь закреплено, что она считает действующим.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "running_experiments",
    КОРЕНЬ / "automation" / "local" / "running-experiments.py")
мера = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(мера)


# --- что считается действующим -------------------------------------------

def test_опыт_без_вердикта_действует():
    з = {"experiment_id": "exp-1", "phase": "canary"}
    assert [x["experiment_id"] for x in мера.действующие([з])] == ["exp-1"]


def test_опыт_с_вердиктом_не_действует():
    з = {"experiment_id": "exp-1", "phase": "rolled_back",
         "verdict": "rollback"}
    assert мера.действующие([з]) == []


def test_вердикт_pending_это_ещё_действующий():
    """«Ожидает» — не вердикт: правило канарейки продолжает действовать."""
    з = {"experiment_id": "exp-1", "phase": "observing",
         "verdict": "pending"}
    assert len(мера.действующие([з])) == 1


def test_синтетический_прогон_в_счёт_не_идёт():
    """Демонстрационный опыт на фикстуре правило канарейки не включает."""
    з = {"experiment_id": "exp-demo", "synthetic": True, "phase": "canary"}
    assert мера.действующие([з]) == []


def test_фаза_из_перечня_действующих_достаточна():
    for фаза in мера.ДЕЙСТВУЮТ:
        з = {"experiment_id": "exp-1", "phase": фаза, "verdict": "keep"}
        assert len(мера.действующие([з])) == 1, фаза


def test_пустой_реестр_не_роняет_меру():
    assert мера.действующие([]) == []


# --- владелец реестра -----------------------------------------------------

def test_владелец_берётся_из_объявления():
    """Не из догадки: иначе мера прочитает свою копию и ничего не найдёт."""
    assert мера.владелец_опытов() == "wt-portable-site-cell-01"


def test_владелец_объявлен_в_активном_списке():
    д = json.loads((КОРЕНЬ / "config" / "active-domains.json").read_text(
        encoding="utf-8"))
    общие = д["shared_components"]
    assert "experiments" in общие, (
        "реестр опытов без объявленного владельца — именно так задачи и"
        " разошлись с действующими опытами")
    assert общие["experiments"]["owner"]


def test_реестры_включают_и_владельца_и_свой():
    пути = [str(п) for п in мера.реестры()]
    assert пути, "ни один реестр не найден"
    assert any("wt-portable-site-cell-01" in п for п in пути), пути


def test_реестр_владельца_читается_первым():
    """Порядок важен: свой реестр беднее и не должен затенять владельца."""
    пути = мера.реестры()
    if len(пути) > 1:
        assert "wt-portable-site-cell-01" in str(пути[0]), пути


# --- чтение ---------------------------------------------------------------

def test_читается_и_список_и_объект(tmp_path):
    как_объект = tmp_path / "a.json"
    как_объект.write_text(json.dumps({"experiments": [{"experiment_id": "x"}]}),
                          encoding="utf-8")
    как_список = tmp_path / "b.json"
    как_список.write_text(json.dumps([{"experiment_id": "y"}]),
                          encoding="utf-8")
    assert мера.прочитать(как_объект)[0]["experiment_id"] == "x"
    assert мера.прочитать(как_список)[0]["experiment_id"] == "y"


def test_в_живом_реестре_владельца_есть_действующие_опыты():
    """Если их ноль — либо все закрыты, либо мера читает не тот файл.

    Проверка намеренно мягкая: она требует не конкретного числа, а того, что
    мера ВИДИТ реестр владельца и разбирает его.
    """
    пути = [п for п in мера.реестры()
            if "wt-portable-site-cell-01" in str(п)]
    if not пути:
        return  # копии владельца здесь нет — это отдельный случай
    записи = мера.прочитать(пути[0])
    assert записи, "реестр владельца прочитан пустым"
    assert all("experiment_id" in з or "id" in з for з in записи)
