"""Рецензия материала обязательна, и допуск стоит в самой публикации.

ЗАДАНИЕ ВЛАДЕЛЬЦА 24.10: рецензия материалов перед публикацией обязательна;
её выполняет отдельный уполномоченный проверяющий; автор не одобряет свою
работу; проверка допуска действует в САМОЙ операции публикации; изменение
одобренного текста требует повторной проверки.

ПОВОД ИЗМЕРЕННЫЙ: из 29 размещённых за сутки 24.10 текстов запись о прочтении
имели НОЛЬ, при том что источники были записаны у всех 29. Причина — не
забывчивость: инструмента рецензии МАТЕРИАЛА не существовало, тогда как у
комментариев цепочка была полной (prepare → submit → review → publish).

Проверяется чистая функция допуска и права операции: сеть и витрина не нужны.
"""
from __future__ import annotations

import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))

from factory.qwen import actors, editorial, mcp  # noqa: E402

ТЕКСТ = "«Произведение» — сериал 2026 года о чём-то важном и понятном."
АВТОР = "editor/claude-auto/run-20261024T144003Z"
ПРОВЕРЯЮЩИЙ = "architect/claude-session/run-20261024T1500Z"


def _отзыв(**замены) -> dict:
    о = {
        "reviewer": ПРОВЕРЯЮЩИЙ,
        "verdict": "accepted",
        "body_digest": editorial.отпечаток(editorial.обрезать(ТЕКСТ)),
        "at": "2026-10-24T15:00:00Z",
        "notes": ["сверено по снимку каталога"],
        "checks": {к: True for к in editorial.ПРОВЕРКИ_РЕЦЕНЗИИ},
        "author_reviewed": АВТОР,
        "sources_at_review": ["https://shikimori.io/animes/1"],
    }
    о.update(замены)
    return о


def _черновик(**замены) -> dict:
    ч = {"slug": "x", "body": ТЕКСТ, "author": АВТОР,
         "body_digest": editorial.отпечаток(editorial.обрезать(ТЕКСТ)),
         "state": "verified", "quality_problems": [],
         "sources": ["https://shikimori.io/animes/1"], "review": _отзыв()}
    ч.update(замены)
    return ч


# --- допуск: отказы -------------------------------------------------------

def test_без_рецензии_выпуск_запрещён():
    отказ = editorial.допуск_по_рецензии(_черновик(review=None), ТЕКСТ)
    assert "рецензии нет" in отказ, отказ


def test_отклонённый_вердикт_к_выпуску_не_допускает():
    отказ = editorial.допуск_по_рецензии(
        _черновик(review=_отзыв(verdict="rejected")), ТЕКСТ)
    assert "не допускает к выпуску" in отказ, отказ


def test_изменение_одобренного_текста_требует_повторной_проверки():
    """Отзыв привязан к отпечатку: правка сама делает его устаревшим."""
    отказ = editorial.допуск_по_рецензии(_черновик(), ТЕКСТ + " Добавлено.")
    assert "ДРУГОЙ редакции" in отказ, отказ
    assert "повторной проверки" in отказ


def test_рецензия_без_названных_проверок_не_годится():
    отказ = editorial.допуск_по_рецензии(
        _черновик(review=_отзыв(checks={})), ТЕКСТ)
    assert "не подтверждены проверки" in отказ, отказ
    for к in editorial.ПРОВЕРКИ_РЕЦЕНЗИИ:
        assert к in отказ


def test_одной_проверки_мало():
    частично = {к: True for к in editorial.ПРОВЕРКИ_РЕЦЕНЗИИ}
    частично["посторонних_вставок_нет"] = False
    отказ = editorial.допуск_по_рецензии(
        _черновик(review=_отзыв(checks=частично)), ТЕКСТ)
    assert "посторонних_вставок_нет" in отказ, отказ


def test_автор_не_одобряет_свою_работу():
    отказ = editorial.допуск_по_рецензии(
        _черновик(review=_отзыв(reviewer=АВТОР)), ТЕКСТ)
    assert "автор и проверяющий совпадают" in отказ, отказ


def test_другой_прогон_той_же_автоматизации_не_считается_проверяющим():
    """Два прогона одного редактора — это он же, разделения нет."""
    отказ = editorial.допуск_по_рецензии(
        _черновик(review=_отзыв(reviewer="editor/claude-auto/run-20261024T9999Z")),
        ТЕКСТ)
    assert "тот же исполнитель" in отказ, отказ


# --- допуск: разрешение (отрицательный контроль) --------------------------

def test_принятая_рецензия_выпуск_разрешает():
    """Застава обязана уметь и пропустить, иначе публикация невозможна."""
    assert editorial.допуск_по_рецензии(_черновик(), ТЕКСТ) == ""


def test_вердикт_с_замечаниями_тоже_допускает():
    assert editorial.допуск_по_рецензии(
        _черновик(review=_отзыв(verdict="accepted_with_notes")), ТЕКСТ) == ""


def test_пробелы_в_теле_допуску_не_мешают():
    """Публикуется обрезанное тело; отпечаток считается от него же."""
    assert editorial.допуск_по_рецензии(_черновик(), "  " + ТЕКСТ + "  ") == ""


# --- права и подключение --------------------------------------------------

def test_роли_qwen_рецензия_не_разрешена():
    """Автор черновиков не может сам ставить «принято»."""
    try:
        actors.проверить("qwen/непроверенный-канал/x", "review-material")
    except actors.ОперацияНеРазрешена:
        return
    raise AssertionError("роль qwen допущена к рецензии материала")


def test_проверяющей_роли_рецензия_разрешена():
    actors.проверить(ПРОВЕРЯЮЩИЙ, "review-material")


def test_инструмент_моста_объявлен_и_пишущий():
    """Без инструмента фоновый редактор рецензию записать не может."""
    assert "review_material" in mcp.ИНСТРУМЕНТЫ
    assert "review_material" in mcp.ПИШУЩИЕ
    assert mcp.ОПЕРАЦИЯ_ИНСТРУМЕНТА["review_material"] == "review-material"
    схема = mcp.ИНСТРУМЕНТЫ["review_material"]["схема"]
    assert set(схема["required"]) == {"site", "slug", "verdict", "body_digest"}
    свойства = схема["properties"]["checks"]["properties"]
    assert set(свойства) == set(editorial.ПРОВЕРКИ_РЕЦЕНЗИИ)


def test_в_режиме_только_чтения_рецензия_недоступна(monkeypatch):
    """Отзыв — запись, и в read-only мосте его быть не должно."""
    monkeypatch.setattr(mcp, "ТОЛЬКО_ЧТЕНИЕ", True)
    assert "review_material" not in mcp.доступные()
