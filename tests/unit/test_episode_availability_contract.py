# --- пропуски и перебор относительно заявленного -----------------------------

def test_пропуск_в_начале_не_скрывает_остальные(tmp_path, monkeypatch):
    """`18-koles-pravosudiya`: второй сезон начинается со второй серии."""
    модуль = стенд(tmp_path, monkeypatch, "gaps",
                   ({"n": 2, "eps": 21, "avail": 21,
                     "nums": list(range(2, 23))},))
    try:
        деталь = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ).get("gaps")
        assert модуль.серия_с_дорожкой(деталь, 2, 1) is False
        assert модуль.серия_с_дорожкой(деталь, 2, 2) is True
        assert модуль.выбрать_доступную_серию(деталь) == (2, 2)
    finally:
        h.выгрузить(модуль)


def test_серии_выше_заявленного_не_прячутся(tmp_path, monkeypatch):
    """`boec-baki`: сезон объявлен из 24 серий, провайдер отдаёт 26."""
    модуль = стенд(tmp_path, monkeypatch, "boec-baki",
                   ({"n": 2, "eps": 24, "avail": 24,
                     "nums": list(range(1, 27))},))
    try:
        деталь = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ).get("boec-baki")
        сезон = [с for с in модуль.список_серий(деталь) if с["n"] == 2][0]
        assert 26 in сезон["номера"] and сезон["доступно"] == 26
        assert модуль.серия_с_дорожкой(деталь, 2, 26) is True
    finally:
        h.выгрузить(модуль)


def test_заявленная_но_неиграющая_серия_остаётся_видимой(tmp_path, monkeypatch):
    """Разница между «сезон из 12» и «вышло 3 из 12» обязана быть видна."""
    модуль = стенд(tmp_path, monkeypatch, "part",
                   ({"n": 1, "eps": 12, "avail": 3, "nums": [1, 2, 3]},))
    try:
        деталь = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ).get("part")
        сезон = [с for с in модуль.список_серий(деталь) if с["n"] == 1][0]
        assert сезон["номера"] == list(range(1, 13))
        assert сезон["доступно"] == 3
        assert модуль.серия_с_дорожкой(деталь, 1, 4) is False
    finally:
        h.выгрузить(модуль)


# --- отсутствие значения не превращается в номер -----------------------------

@pytest.mark.parametrize("сырое", [[], "", {}, None, ["x"], [-3]])
def test_пустой_перечень_не_становится_спецвыпуском(tmp_path, monkeypatch, сырое):
    """Иначе каждый сериал подряд получил бы вечное обещание серии 0."""
    модуль = стенд(tmp_path, monkeypatch, "empty",
                   ({"n": 1, "eps": 4, "avail": 2, "nums": сырое},))
    try:
        деталь = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ).get("empty")
        assert модуль.серия_с_дорожкой(деталь, 1, 0) is False
        # `nums` без чисел — не «нет поля»: прежний смысл `avail` возвращается
        # только там, где перечня нет вовсе.
        ожидание = [] if isinstance(сырое, (list, tuple)) else [1, 2]
        играют = sorted(
            n for n in range(0, 5) if модуль.серия_с_дорожкой(деталь, 1, n))
        assert играют == ожидание
    finally:
        h.выгрузить(модуль)


def test_снимок_без_перечня_ведёт_себя_как_раньше(tmp_path, monkeypatch):
    """Совместимость: витрина на старом снимке не должна ничего потерять."""
    модуль = стенд(tmp_path, monkeypatch, "old",
                   ({"n": 1, "eps": 9, "avail": 3},))
    try:
        деталь = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ).get("old")
        играют = [n for n in range(0, 10) if модуль.серия_с_дорожкой(деталь, 1, n)]
        assert играют == [1, 2, 3]
    finally:
        h.выгрузить(модуль)


