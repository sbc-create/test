"""Доступность серии — множество номеров, а не одно число.

Жалоба приходила трижды и каждый раз выглядела по-новому, а причина была одна:
рантайм выводил список доступных серий из ОДНОГО числа `avail` по правилу
«серии с первой по avail». Такое правило не описывает ни спецвыпуск с номером
0, ни пропуски в нумерации, ни сезон, у которого играет больше серий, чем
заявлено.

Оба названных владельцем случая закреплены здесь поимённо и с настоящими
данными источника, чтобы проверка не прошла мимо уже известного дефекта:

СКОТТЫ (`/title/skotty/`, `01a0e27f-8175-7115-8972-83cce31b15d3`). Замер
2026-09-28 у трёх издателей (10238, 10252, 10261 — отвечают одинаково):
провайдер отдаёт РОВНО ОДНУ дорожку, `Pilot`, season 1, episode 0, с `vkId` и
`cvhId`. Снимок объявляет `avail=1, eps=6`. Витрина показывала «доступно 1»,
монтировала `<video-player episode="1">`, и провайдер отвечал на неё noData:
«Провайдер не отдал источник», «Видео пока не добавлено».

МАСТЕР ОМЮР (`/title/master-omyur/`, `01a0e45a-ba66-7613-879c-f209068f60e3`).
Снимок собран раз в сутки и объявлял `avail=0` при живой дорожке s1e1:
доступность отстала от источника, а витрина читала её как факт.

Проверяется НАШЕ поведение на подставленных данных: сеть здесь запрещена, и
ответ провайдера в проверку не ходит. Что провайдер отдаёт на самом деле —
измеряет `automation/host/episode-availability-survey.py`, и это отдельная
работа с ограниченной нагрузкой.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lords_runtime_harness as h  # noqa: E402

#: Настоящие сезоны «Скоттов» из боевого снимка 2026-09-28 плюс `nums`,
#: который согласование выводит из ответа провайдера.
СКОТТЫ = ({"n": 1, "eps": 6, "avail": 1, "nums": [0]},
          {"n": 2, "eps": 1, "avail": 0})

#: «Мастер Омюр»: один сезон, одна серия, снимок отстал.
ОМЮР_ОТСТАЛ = ({"n": 1, "eps": 1, "avail": 0},)
ОМЮР_СВЕРЕН = ({"n": 1, "eps": 1, "avail": 1, "nums": [1]},)


def стенд(tmp_path, monkeypatch, slug: str, сезоны, *, профиль="lords-general"):
    с = h.Стенд(tmp_path, профиль=профиль)
    с.записать_плеер()
    с.записать_каталог([h.запись(slug, title="Проверка", kind="Сериал")])
    с.записать_подробности([h.подробность(slug, type_="tv", seasons=сезоны)])
    модуль = h.загрузить(с, monkeypatch)
    return модуль


@pytest.fixture
def скотты(tmp_path, monkeypatch):
    модуль = стенд(tmp_path, monkeypatch, "skotty", СКОТТЫ)
    yield модуль
    h.выгрузить(модуль)


# --- контракт доступности ---------------------------------------------------

def test_скотты_играют_нулевую_серию(скотты):
    """Единственная дорожка записи имеет номер 0 — и она достижима."""
    деталь = скотты.Подробности(скотты.ПОДРОБНОСТИ_ФАЙЛ).get("skotty")
    assert скотты.серия_с_дорожкой(деталь, 1, 0) is True


def test_скотты_не_обещают_первую_серию(скотты):
    """Той серии, которую витрина обещала, у источника нет вовсе."""
    деталь = скотты.Подробности(скотты.ПОДРОБНОСТИ_ФАЙЛ).get("skotty")
    assert скотты.серия_с_дорожкой(деталь, 1, 1) is False


def test_скотты_хаб_выбирает_настоящую_серию(скотты):
    """Хаб обязан предложить то, что играет, а не первый номер подряд."""
    деталь = скотты.Подробности(скотты.ПОДРОБНОСТИ_ФАЙЛ).get("skotty")
    assert скотты.выбрать_доступную_серию(деталь) == (1, 0)


def test_скотты_счётчик_доступных_не_врёт(скотты):
    """«доступно 1» при нуле играющих серий из заявленных — та самая ложь."""
    деталь = скотты.Подробности(скотты.ПОДРОБНОСТИ_ФАЙЛ).get("skotty")
    первый = [с for с in скотты.список_серий(деталь) if с["n"] == 1][0]
    assert первый["доступно"] == 1 and первый["доступные"] == {0}
    assert 0 in первый["номера"], "номер спецвыпуска обязан быть в списке"


def test_ноль_не_подменяет_первую_серию_на_прямом_адресе(скотты):
    """Прямая ссылка на серию 1 честно говорит «дорожки нет», а не играет 0."""
    деталь = скотты.Подробности(скотты.ПОДРОБНОСТИ_ФАЙЛ).get("skotty")
    запись = {"slug": "skotty", "title": "Скотты", "url": "/title/skotty/",
              "year": 2020, "kind": "Сериал", "poster": ""}
    код, _ = скотты.разметка_плеера(h.вид(скотты), запись, деталь, 1, 1)
    assert код == "unavailable"


def test_страница_тайтла_поднимает_плеер_на_нулевой_серии(скотты):
    """Страница произведения обязана показать спецвыпуск, а не пустую рамку."""
    запись = {"slug": "skotty", "title": "Скотты", "url": "/title/skotty/",
              "year": 2020, "kind": "Сериал", "poster": ""}
    деталь = скотты.Подробности(скотты.ПОДРОБНОСТИ_ФАЙЛ).get("skotty")
