"""Учёт несущих путей: запись осмысленна и ни один путь не потерян.

Зачем тест, а не только инструмент. Три индексируемые витрины Yummy подняты
файлом, который лежит в рабочей копии агента размером 8,8 МБ без движения с
1 октября: при уборке копий ради места её снесли бы одной из первых. Документ
про это читает владелец, а каталог удаляет тот, кто освобождает место.
Поэтому факт живёт в проверяемой записи, и её целость проверяется прогоном.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "load-bearing-paths.json"
ИНСТРУМЕНТ = КОРЕНЬ / "automation" / "local" / "load-bearing-check.py"


@pytest.fixture(scope="module")
def учёт() -> dict:
    return json.loads(РЕЕСТР.read_text(encoding="utf-8"))


def test_реестр_и_инструмент_на_месте():
    assert РЕЕСТР.is_file()
    assert ИНСТРУМЕНТ.is_file()


def test_каждая_запись_называет_причину_и_замер(учёт):
    assert учёт["paths"], "пустой учёт бессмыслен"
    for з in учёт["paths"]:
        assert з["path"].startswith("/"), з
        # Причина — не украшение: по ней решают, можно ли удалять. Короткая
        # причина вида «нужно» не даёт решить ничего.
        assert len(з.get("why", "")) >= 80, з["path"]
        assert з.get("measured_at"), з["path"]
        assert isinstance(з.get("release_blocking"), bool), з["path"]
        assert з.get("owner_action"), з["path"]


def test_несущие_пути_целы(учёт):
    пропали = [з["path"] for з in учёт["paths"] if not Path(з["path"]).exists()]
    assert not пропали, (
        "несущий путь исчез — это ломает работающие витрины: "
        f"{пропали}")


def test_блокирующие_выпуск_пути_названы_дефектом(учёт):
    """У пути, который блокирует выпуск, обязан быть номер дефекта.

    Иначе запись остаётся предупреждением без владельца: кто-то должен
    привести состояние домена в файл выпуска, и это именно дефект, а не
    особенность.
    """
    for з in учёт["paths"]:
        if з.get("release_blocking"):
            assert з.get("defect"), з["path"]


def test_разряды_не_смешиваются(учёт):
    """Несущий путь и зависимость метки — разные утверждения.

    Несущий: файла больше нигде нет, утрата невосполнима. Зависимость метки:
    на путь ссылается метка контейнера, но содержимое есть и в другом месте
    побайтово — удаление стоит пересоздания, а не восстановления из ничего.
    Запись, преувеличивающая опасность, обесценивает весь учёт, поэтому один
    и тот же путь не может стоять в двух разрядах.
    """
    несущие = {з["path"] for з in учёт["paths"]}
    зависимости = {з["path"] for з in учёт.get("label_dependencies", [])}
    assert not (несущие & зависимости), несущие & зависимости
    for з in учёт.get("label_dependencies", []):
        assert len(з.get("why", "")) >= 80, з["path"]
        assert з.get("measured_at"), з["path"]


def test_путь_выпуска_в_учёт_не_попадает(учёт):
    """Файлы под /srv несущими не считаются: это и есть путь выпуска.

    Запись такого пути означала бы, что мы считаем нормой жизнь состояния вне
    файла выпуска — а задача обратная: перенести его туда.
    """
    под_srv = [з["path"] for з in учёт["paths"] if з["path"].startswith("/srv/")]
    assert not под_srv, под_srv
