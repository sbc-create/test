"""Премодерация, ответы и правка в модуле сообщества Animedia.

Модуль уже работает на animedia.icu: оценки 1–10 и сообщения посетителей
принимаются и сохраняются. Здесь проверяется то, чего в нём не было и что
требуется для публичной работы: сообщение ждёт разбора, автор видит своё
ожидающим, посторонний — не видит, модератор разбирает очередь.

Отдельно закреплено обратное совместимое поведение: записи, сделанные до
премодерации, поля `status` не имеют и остаются опубликованными. Спрятать их
задним числом значило бы убрать со страницы чужие сообщения, которые уже
показаны посетителям.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

MODULE = Path(__file__).resolve().parents[3] / "factory" / "animedia" / "community.py"


def load():
    spec = importlib.util.spec_from_file_location("animedia_community", MODULE)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    # Регистрация до exec: @dataclass ищет модуль класса в sys.modules, и без
    # записи разрешение аннотаций падает на пустом месте.
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


CM = load()


@pytest.fixture()
def store(tmp_path):
    return CM.Хранилище(tmp_path / "community.json")


ГОСТЬ, ДРУГОЙ = "1.2.3.4", "5.6.7.8"


class TestПремодерация:
    def test_новое_сообщение_ждёт_разбора(self, store):
        store.добавить_комментарий("t", "Гость", "привет", ГОСТЬ)
        чужой = store.состояние("t", ДРУГОЙ)
        assert чужой.комментарии == [], "сообщение опубликовано без разбора"
        assert чужой.всего_на_модерации == 1

    def test_автор_видит_своё_ожидающим(self, store):
        store.добавить_комментарий("t", "Гость", "привет", ГОСТЬ)
        своё = store.состояние("t", ГОСТЬ)
        assert len(своё.комментарии) == 1
        assert своё.комментарии[0]["status"] == CM.СТАТУС_ОЖИДАЕТ
        assert своё.комментарии[0]["моё"] is True

    def test_одобренное_видно_всем(self, store):
        store.добавить_комментарий("t", "Гость", "привет", ГОСТЬ)
        ид = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", ид, CM.СТАТУС_ОДОБРЕН)
        чужой = store.состояние("t", ДРУГОЙ)
        assert [с["text"] for с in чужой.комментарии] == ["привет"]
        assert чужой.всего_на_модерации == 0

    def test_отклонённое_не_видно_никому_кроме_модератора(self, store):
        store.добавить_комментарий("t", "Гость", "привет", ГОСТЬ)
        ид = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", ид, CM.СТАТУС_ОТКЛОНЁН)
        assert store.состояние("t", ДРУГОЙ).комментарии == []
        assert store.состояние("t", ГОСТЬ).комментарии == []
        модератор = store.состояние("t", "", модератор=True)
        assert [с["id"] for с in модератор.на_модерации] == [ид]

    def test_очередь_модерации_собирает_все_витрины(self, store):
        store.добавить_комментарий("a", "Гость", "раз", ГОСТЬ)
        store.добавить_комментарий("b", "Гость", "два", ДРУГОЙ)
        очередь = store.очередь_модерации()
        assert {с["subject"] for с in очередь} == {"a", "b"}


