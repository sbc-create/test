        ид = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", ид, CM.СТАТУС_ОДОБРЕН)
        чужой = store.состояние("t", ДРУГОЙ)
        assert [с["text"] for с in чужой.комментарии] == ["привет"]
        assert чужой.всего_на_модерации == 0

