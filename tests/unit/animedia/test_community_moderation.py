class TestОтветы:
    def test_ответ_на_одобренное(self, store):
        store.добавить_комментарий("t", "Гость", "вопрос", ГОСТЬ)
        корень = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", корень, CM.СТАТУС_ОДОБРЕН)
        store.добавить_комментарий("t", "Второй", "ответ", ДРУГОЙ, ответ_на=корень)
        свои = store.состояние("t", ДРУГОЙ).комментарии
        ответ = next(с for с in свои if с["text"] == "ответ")
        assert ответ["parent_id"] == корень

    def test_ответ_на_ожидающее_отклонён(self, store):
        store.добавить_комментарий("t", "Гость", "вопрос", ГОСТЬ)
        корень = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        with pytest.raises(ValueError, match="пока нельзя ответить"):
            store.добавить_комментарий("t", "Второй", "ответ", ДРУГОЙ, ответ_на=корень)

    def test_ответ_на_ответ_отклонён(self, store):
        store.добавить_комментарий("t", "Гость", "вопрос", ГОСТЬ)
        корень = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", корень, CM.СТАТУС_ОДОБРЕН)
        store.добавить_комментарий("t", "Второй", "ответ", ДРУГОЙ, ответ_на=корень)
        ответ = next(с for с in store.состояние("t", ДРУГОЙ).комментарии
                     if с["text"] == "ответ")
        store.решить_комментарий("t", ответ["id"], CM.СТАТУС_ОДОБРЕН)
        with pytest.raises(ValueError, match="глубже одного уровня"):
            store.добавить_комментарий("t", "Третий", "вглубь", "9.9.9.9",
                                       ответ_на=ответ["id"])

    def test_удаление_забирает_ответы(self, store):
        store.добавить_комментарий("t", "Гость", "вопрос", ГОСТЬ)
        корень = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", корень, CM.СТАТУС_ОДОБРЕН)
        store.добавить_комментарий("t", "Второй", "ответ", ДРУГОЙ, ответ_на=корень)
        store.удалить_комментарий("t", корень, ГОСТЬ)
        всё = store.состояние("t", "", модератор=True)
        assert всё.комментарии == [] and всё.на_модерации == []


