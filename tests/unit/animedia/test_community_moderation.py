class TestКонкурентныеГолоса:
    """Двойной клик и параллельные запросы не должны создавать второй голос."""

    def test_параллельные_одинаковые_запросы_дают_один_голос(self, tmp_path):
        import threading
        хранилище = CM.Хранилище(tmp_path / "c.json", витрина="animedia-01")
        ошибки, барьер = [], threading.Barrier(8)

        def голосовать():
            барьер.wait()
            try:
                хранилище.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ)
            except CM.ГолосЗакреплён:
                pass
            except Exception as e:  # noqa: BLE001
                ошибки.append(e)

        нити = [threading.Thread(target=голосовать) for _ in range(8)]
        for н in нити:
            н.start()
        for н in нити:
            н.join()

        assert not ошибки, ошибки
        с = хранилище.состояние(ПОСТОЯННЫЙ, ГОСТЬ)
        assert (с.голосов, с.мой_голос) == (1, 7), "параллельные клики задвоили голос"

    def test_гонка_разных_оценок_оставляет_ровно_одну(self, tmp_path):
        import threading
        хранилище = CM.Хранилище(tmp_path / "c.json", витрина="animedia-01")
        принято, барьер = [], threading.Barrier(10)

        def голосовать(значение):
            барьер.wait()
            try:
                хранилище.добавить_голос(ПОСТОЯННЫЙ, значение, ГОСТЬ)
                принято.append(значение)
            except CM.ГолосЗакреплён:
                pass

        нити = [threading.Thread(target=голосовать, args=(v,))
                for v in range(1, 11)]
        for н in нити:
            н.start()
        for н in нити:
            н.join()

        с = хранилище.состояние(ПОСТОЯННЫЙ, ГОСТЬ)
        assert с.голосов == 1, "гонка создала больше одного голоса"
        assert с.мой_голос in range(1, 11)
        # Приняты могут быть только записи ТОГО ЖЕ значения, что осталось.
        assert set(принято) <= {с.мой_голос}, (
            f"засчитано несколько разных оценок: {принято}, осталась {с.мой_голос}"
        )


class TestКаждыйМетодВызываем:
    """Каждый публичный метод обязан пережить обычный вызов.

    `списки_посетителя` падал с NameError: при переходе на 2.0 в нём заменили
    тело на `_голосующий(ключ_посетителя, account_id)`, но параметр account_id
    методу не добавили. Ни один тест его не звал, поэтому падение нашла не
    проверка, а соседняя витрина — на живой странице «Списки».

    Здесь вызывается ВСЁ, что модуль объявляет публичным: дешёвый способ не
    повторить ровно эту ошибку. Проверяется не результат, а то, что вызов
    вообще проходит.
    """

    ТЕМА = "01a0b507-3280-7b2a-8af4-674dd73cff72"

    def _аргументы(self, имя: str) -> tuple:
        return {
            "состояние": ((self.ТЕМА, ГОСТЬ), {}),
            "выбрать_список": ((self.ТЕМА, "watching", ГОСТЬ), {}),
            "списки_посетителя": ((ГОСТЬ,), {}),
            "добавить_голос": ((self.ТЕМА, 7, ГОСТЬ), {}),
            "снять_голос": ((self.ТЕМА, ГОСТЬ), {}),
            "переключить_реакцию": ((self.ТЕМА, "огонь", ГОСТЬ), {}),
            "добавить_комментарий": ((self.ТЕМА, "Гость", "текст", ГОСТЬ), {}),
            "решить_комментарий": ((self.ТЕМА, "нет-такого", CM.СТАТУС_ОДОБРЕН), {}),
            "изменить_комментарий": ((self.ТЕМА, "нет-такого", "новый", ГОСТЬ), {}),
            "удалить_комментарий": ((self.ТЕМА, "нет-такого", ГОСТЬ), {}),
            "очередь_модерации": ((), {}),
            "главный_рейтинг": ((self.ТЕМА,), {"внешние": {"shikimori": 8.0}}),
            "зафиксировать_базу": ((self.ТЕМА,), {"внешние": {"shikimori": 8.0}}),
            "темы_без_базы": ((), {}),
        }.get(имя)

    def test_все_публичные_методы_вызываются_без_NameError(self, store):
        публичные = [и for и in dir(store)
                     if not и.startswith("_") and callable(getattr(store, и))]
        непокрытые = [и for и in публичные if self._аргументы(и) is None]
        assert not непокрытые, (
            f"у модуля появились методы без вызова в этом тесте: {непокрытые}. "
            f"Добавьте их сюда — иначе NameError в них снова найдёт не тест."
        )
        for имя in публичные:
            args, kwargs = self._аргументы(имя)
            try:
                getattr(store, имя)(*args, **kwargs)
            except (ValueError, RuntimeError):
                # Отказ по правилам модуля — нормальный исход вызова.
                pass
            except NameError as e:
                pytest.fail(f"{имя}: NameError — {e}")
            except TypeError as e:
                pytest.fail(f"{имя}: не принимает обычные аргументы — {e}")

    def test_списки_посетителя_принимают_учётную_запись(self, store):
        """Как у соседних методов 2.0: cookie или account_id."""
        store.выбрать_список(self.ТЕМА, "watching", ГОСТЬ)
        по_куке = store.списки_посетителя(ГОСТЬ)
        assert по_куке["watching"] == [self.ТЕМА]
        по_записи = store.списки_посетителя("", account_id="u-7")
        assert по_записи["watching"] == [], "чужой список виден по учётной записи"
