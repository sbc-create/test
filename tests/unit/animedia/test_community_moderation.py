СТАРЫЙ_SLUG = "master-lda-i-plameni-2"
ПОСТОЯННЫЙ = "01a0b507-3280-7b2a-8af4-674dd73cff72"


class TestПостоянныйКлюч:
    """f54a5f6: ключом обсуждения стал постоянный идентификатор, не адрес.

    Адрес меняется — переименование тайтла осиротило бы все его записи. На
    Animedia данные под старым ключом уже есть (в отличие от Zona, где правку
    успели внести до раскатки), поэтому проверяется именно перенос.
    """

    def test_записи_из_под_адреса_переезжают_с_содержимым(self, tmp_path):
        путь = tmp_path / "community.json"
        путь.write_text(json.dumps({
            "schema_version": 1,
            "titles": {СТАРЫЙ_SLUG: {
                "votes": {CM._посетитель(ГОСТЬ): 5},
                "reactions": {},
                "comments": [{"id": "old1", "name": "Проверка",
                              "text": "живое сообщение", "author_key": "кто-то",
                              "created_at": "2026-09-22T21:52:24Z"}],
            }},
        }), encoding="utf-8")
        хранилище = CM.Хранилище(путь, витрина="animedia-01")

        # До первой правки старая запись ещё читается по адресу.
        было = хранилище.состояние(ПОСТОЯННЫЙ, ГОСТЬ, slug=СТАРЫЙ_SLUG)
        assert было.мой_голос == 5
        assert [с["text"] for с in было.комментарии] == ["живое сообщение"]

        # Первая же правка переносит её под постоянный ключ, ничего не теряя.
        # Голос у этого посетителя уже есть и он окончателен, поэтому переносит
        # его повторная отправка ТОЙ ЖЕ оценки — перенос обязан случиться даже
        # тогда, когда сам голос не меняется.
        хранилище.добавить_голос(ПОСТОЯННЫЙ, 5, ГОСТЬ, slug=СТАРЫЙ_SLUG)
        данные = json.loads(путь.read_text(encoding="utf-8"))
        assert ПОСТОЯННЫЙ in данные["titles"], "запись не переехала"
        assert СТАРЫЙ_SLUG not in данные["titles"], "адрес остался вторым ключом"
        перенесено = данные["titles"][ПОСТОЯННЫЙ]
        assert перенесено["migrated_from_slug"] == СТАРЫЙ_SLUG
        assert [с["text"] for с in перенесено["comments"]] == ["живое сообщение"]

        стало = хранилище.состояние(ПОСТОЯННЫЙ, ГОСТЬ)
        assert стало.мой_голос == 5 and стало.голосов == 1, "голос задвоился"

    def test_переименование_тайтла_не_теряет_записи(self, tmp_path):
        хранилище = CM.Хранилище(tmp_path / "c.json", витрина="animedia-01")
        хранилище.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ, slug="старый-адрес")
        после = хранилище.состояние(ПОСТОЯННЫЙ, ГОСТЬ, slug="совершенно-новый-адрес")
        assert после.мой_голос == 7


class TestИзоляцияВитрин:
    """f54a5f6: пространство — конкретная витрина, а не семейство.

    animedia.icu и animedia.space — один шаблон и разные публичные сайты, как
    zonafilm.space и zonafilm.cc. Общий ключ показал бы записи одного на другом.
    """

    def test_две_витрины_семейства_не_видят_записей_друг_друга(self, tmp_path):
        первая = CM.Хранилище(tmp_path / "animedia-01.json", витрина="animedia-01")
        вторая = CM.Хранилище(tmp_path / "animedia-02.json", витрина="animedia-02")
        первая.добавить_голос(ПОСТОЯННЫЙ, 10, ГОСТЬ)
        первая.добавить_комментарий(ПОСТОЯННЫЙ, "Гость", "только на icu", ГОСТЬ)

        у_второй = вторая.состояние(ПОСТОЯННЫЙ, ГОСТЬ, модератор=True)
        assert у_второй.голосов == 0, "голос утёк на соседнюю витрину"
