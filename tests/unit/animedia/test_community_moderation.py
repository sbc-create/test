class TestОдинГолосНавсегда:
    """Первая сохранённая оценка окончательна.

    Это отменяет прежнее правило «менять можно». Проверяется не только отказ,
    но и то, что при отказе НИЧЕГО не сдвинулось: ни сам голос, ни среднее, ни
    счётчик. Отказ, который всё-таки что-то записал, хуже разрешения.
    """

    def test_повтор_той_же_оценки_идемпотентен_и_не_пишет_файл(self, store, tmp_path):
        store.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ)
        файл = store.путь
        отпечаток = (файл.read_bytes(), файл.stat().st_mtime_ns)

        снова = store.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ)
        assert (снова.мой_голос, снова.голосов, снова.средняя) == (7, 1, 7.0)
        assert (файл.read_bytes(), файл.stat().st_mtime_ns) == отпечаток, (
            "повторная отправка той же оценки перезаписала хранилище"
        )

    def test_другая_оценка_отклоняется_и_ничего_не_двигает(self, store):
        store.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ)
        было = store.состояние(ПОСТОЯННЫЙ, ГОСТЬ)
        with pytest.raises(CM.ГолосЗакреплён) as отказ:
            store.добавить_голос(ПОСТОЯННЫЙ, 2, ГОСТЬ)
        assert отказ.value.сохранённая == 7
        стало = store.состояние(ПОСТОЯННЫЙ, ГОСТЬ)
        assert (стало.мой_голос, стало.голосов, стало.средняя) == \
               (было.мой_голос, было.голосов, было.средняя)

    def test_отказ_ловится_как_ValueError(self, store):
        """Обработчик витрины ловит ValueError — иначе посетитель получит 500."""
        store.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ)
        with pytest.raises(ValueError):
            store.добавить_голос(ПОСТОЯННЫЙ, 9, ГОСТЬ)

    def test_снять_голос_больше_нельзя(self, store):
        store.добавить_голос(ПОСТОЯННЫЙ, 7, ГОСТЬ)
        with pytest.raises(CM.ГолосЗакреплён):
            store.снять_голос(ПОСТОЯННЫЙ, ГОСТЬ)
        assert store.состояние(ПОСТОЯННЫЙ, ГОСТЬ).мой_голос == 7

    def test_разные_посетители_считаются_отдельно(self, store):
        store.добавить_голос(ПОСТОЯННЫЙ, 10, ГОСТЬ)
        store.добавить_голос(ПОСТОЯННЫЙ, 4, ДРУГОЙ)
        с = store.состояние(ПОСТОЯННЫЙ, ГОСТЬ)
        assert (с.голосов, с.средняя, с.мой_голос) == (2, 7.0, 10)
        with pytest.raises(CM.ГолосЗакреплён):
            store.добавить_голос(ПОСТОЯННЫЙ, 1, ДРУГОЙ)
        assert store.состояние(ПОСТОЯННЫЙ, ДРУГОЙ).мой_голос == 4

    def test_разные_тайтлы_независимы(self, store):
        store.добавить_голос("aaa", 3, ГОСТЬ)
        store.добавить_голос("bbb", 9, ГОСТЬ)
