class TestПремодерация:
    def test_новое_сообщение_ждёт_разбора(self, store):
        store.добавить_комментарий("t", "Гость", "привет", ГОСТЬ)
        чужой = store.состояние("t", ДРУГОЙ)
        assert чужой.комментарии == [], "сообщение опубликовано без разбора"
        assert чужой.всего_на_модерации == 1

    def test_автор_видит_своё_ожидающим(self, store):
        store.добавить_комментарий("t", "Гость", "привет", ГОСТЬ)
        своё = store.состояние("t", ГОСТЬ)
        assert len(своё.комментарии) == 1
        assert своё.комментарии[0]["status"] == CM.СТАТУС_ОЖИДАЕТ
        assert своё.комментарии[0]["моё"] is True

