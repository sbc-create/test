class TestПравка:
    def test_автор_правит_своё_и_оно_возвращается_в_очередь(self, store):
        store.добавить_комментарий("t", "Гость", "было", ГОСТЬ)
        ид = store.состояние("t", ГОСТЬ).комментарии[0]["id"]
        store.решить_комментарий("t", ид, CM.СТАТУС_ОДОБРЕН)
        store.изменить_комментарий("t", ид, "стало", ГОСТЬ)
        assert store.состояние("t", ДРУГОЙ).комментарии == []
