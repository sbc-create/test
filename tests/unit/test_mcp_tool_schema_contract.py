"""Каждое поле схемы инструмента доходит до его обработчика.

Зачем эта проверка существует. 2026-10-07 редактор сообщил, что
`publish_material` с телом отвечает «черновика нет». Схема инструмента поле
`body` объявляла, описание обещало «текст берётся из черновика ИЛИ передаётся
полем `body`», а `editorial.публиковать` умеет принимать `тело=` и сама
подсказывает «сначала prepare, либо передайте тело». Обработчик моста это поле
НЕ ЧИТАЛ и вызывал функцию без него.

Отказ выглядел ошибкой вызывающего. Для витрин Yummy он блокировал публикацию
полностью: источника фактов у семейства нет, `prepare_material` недоступен по
построению, и переданное тело — единственный путь.

Объявить поле и не прочитать его — это обещание, которого нет. Проверка держит
ровно это свойство у ВСЕХ инструментов, а не у одного исправленного: следующий
инструмент с новым полем либо читает его, либо падает здесь.
"""
from __future__ import annotations

import inspect

import pytest

from factory.qwen import mcp

#: Поля, которые обработчик законно не читает САМ, потому что их читает слой
#: ниже по стеку вызова, и имя в исходнике обработчика не встречается. Список
#: пустой намеренно: пока он пуст, правило простое и исключений не требует.
#: Пополнять его можно только с причиной в этой же строке.
РАЗРЕШЁННЫЕ_ИСКЛЮЧЕНИЯ: dict[str, set[str]] = {}


def поля_схемы(имя: str) -> list[str]:
    схема = (mcp.ИНСТРУМЕНТЫ[имя].get("схема") or {})
    return sorted((схема.get("properties") or {}))


@pytest.mark.parametrize("имя", sorted(mcp.ИНСТРУМЕНТЫ))
def test_поля_схемы_читаются_обработчиком(имя: str) -> None:
    обработчик = mcp.ИНСТРУМЕНТЫ[имя]["обработчик"]
    исходник = inspect.getsource(обработчик)
    разрешено = РАЗРЕШЁННЫЕ_ИСКЛЮЧЕНИЯ.get(имя, set())
    потеряны = [п for п in поля_схемы(имя)
                if п not in разрешено
                and f'"{п}"' not in исходник and f"'{п}'" not in исходник]
    assert not потеряны, (
        f"{имя}: схема объявляет поля {потеряны}, но обработчик их не читает. "
        "Объявленное и непрочитанное поле — обещание, которого нет: вызов с ним "
        "отвечает отказом, и отказ выглядит ошибкой вызывающего")


def test_publish_material_передаёт_тело_дальше() -> None:
    """Именно тот случай, из которого проверка выросла."""
    исходник = inspect.getsource(mcp.инструмент_публикации)
    assert '"body"' in исходник or "'body'" in исходник
    assert "тело=" in исходник, (
        "обработчик обязан передать тело в editorial.публиковать: без этого "
        "вызов с телом получает «черновика нет»")


def test_у_функции_публикации_есть_параметр_тела() -> None:
    """Параметр, в который мост передаёт тело, существует и необязателен."""
    from factory.qwen import editorial

    параметры = inspect.signature(editorial.публиковать).parameters
    assert "тело" in параметры, "функция публикации потеряла параметр тела"
    assert параметры["тело"].default is None, (
        "тело обязано быть необязательным: публикация из черновика должна "
        "работать по-прежнему")


def test_тело_доходит_через_протокол_без_публикации(monkeypatch) -> None:
    """Вызов идёт ПРОТОКОЛОМ, публикация подменена: production не затрагивается.

    Проверяется ровно тот вызов, который у редактора отвечал «черновика нет»:
    `publish_material` с `site`, `slug` и `body`. Сама публикация подменена
    перехватчиком — на живой домен ничего не уходит, а в ответе видно, с какими
    аргументами её позвали.
    """
    import json

    from factory.qwen import editorial

    поймано: dict = {}

    def перехват(site, slug, *, author, expected_generation=None, тело=None):
        поймано.update({"site": site, "slug": slug, "author": author,
                        "expected_generation": expected_generation, "тело": тело})
        return {"state": "confirmed", "slug": slug, "note": "перехват проверки"}

    monkeypatch.setattr(editorial, "публиковать", перехват)
    ответ = mcp.обработать({"jsonrpc": "2.0", "id": 1, "method": "tools/call",
                            "params": {"name": "publish_material",
                                       "arguments": {"site": "yummyani.org",
                                                     "slug": "primer",
                                                     "body": "Текст описания "
                                                             "для проверки.",
                                                     "author": "проверка"}}})
    конверт = ответ["result"]
    assert not конверт.get("isError"), конверт
    данные = json.loads(конверт["content"][0]["text"])
    assert данные["confirmed"] is True, данные
    assert поймано["тело"] == "Текст описания для проверки.", (
        "тело обязано дойти до публикации тем же значением, каким пришло")
    assert поймано["site"] == "yummyani.org" and поймано["slug"] == "primer"


def test_без_тела_путь_через_черновик_не_сломан(monkeypatch) -> None:
    """Пустое и отсутствующее тело по-прежнему означают «взять черновик»."""
    from factory.qwen import editorial

    поймано: list = []

    def перехват(site, slug, *, author, expected_generation=None, тело=None):
        поймано.append(тело)
        return {"state": "confirmed", "slug": slug}

    monkeypatch.setattr(editorial, "публиковать", перехват)
    for аргументы in ({"site": "s", "slug": "p"},
                      {"site": "s", "slug": "p", "body": "   "}):
        mcp.обработать({"jsonrpc": "2.0", "id": 1, "method": "tools/call",
                        "params": {"name": "publish_material",
                                   "arguments": аргументы}})
    assert поймано == [None, None], (
        "пустое тело не должно превращаться в пустую публикацию: это путь "
        "через черновик")
