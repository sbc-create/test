"""REQ-EDITORIAL-OUTCOME-VERDICT: вердикт по долям исходов называется словами.

Две дыры, найденные 19.10 на живых данных.

1. Ниже порога 30 заданий инструмент печатал «ВЫВОДА НЕТ», а ВЫШЕ порога
   молчал — то есть молчание означало и «сравнивай сам», и «всё хорошо».
   Проверка, которая не произносит вывод, оставляет его читателю, а читатель
   возьмёт то, что подсказывают цифры.

2. Сравнение смешивало состав заданий. Замер 10:23Z: до рубежа 1 505 заданий
   смешанных направлений, после — 47 заданий ТОЛЬКО направления `anime`
   (все три прогона после рубежа ушли в anime, последний `lords` был в
   09:20Z). Доля `SOURCES_MISSING` «выросла» с 53.7 % до 70.2 %, но у anime и
   lords разные источники (шикимори с успехом 98.8 % против Википедии с 17.0 %),
   поэтому такая разница — свойство состава, а не правки.

Вердикт поэтому говорит одним из четырёх слов и отдельно называет состав.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/editor-outcomes.py"
_спец = importlib.util.spec_from_file_location("editor_outcomes_verdict", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)


def _свод(заданий: int, доля_нехватки: float, направления: dict) -> dict:
    нехватка = round(заданий * доля_нехватки)
    return {
        "прогонов": max(1, заданий // 10),
        "заданий": заданий,
        "публикаций": 0,
        "исходы": {"SOURCES_MISSING": нехватка,
                   "TEXT_WRITTEN": заданий - нехватка},
        "доли": {"SOURCES_MISSING": round(100 * нехватка / заданий, 1),
                 "TEXT_WRITTEN": round(100 * (заданий - нехватка) / заданий, 1)},
        "период": "2026-10-19T00:00Z..2026-10-19T09:00Z",
        "направления": направления,
    }


СМЕШАННОЕ = {"anime": 60, "lords": 40}


# --- порог --------------------------------------------------------------------

def test_мало_заданий_данных_недостаточно():
    слово, почему = ИНСТР.вердикт(_свод(100, 0.54, СМЕШАННОЕ),
                                  _свод(12, 0.70, СМЕШАННОЕ))
    assert слово == "данных недостаточно"
    assert "12" in почему


def test_порог_назван_числом():
    assert ИНСТР.ПОРОГ_ЗАДАНИЙ == 30


# --- состав -------------------------------------------------------------------

def test_разный_состав_направлений_данных_недостаточно():
    """Ровно случай 19.10: после рубежа только anime."""
    слово, почему = ИНСТР.вердикт(_свод(1505, 0.537, СМЕШАННОЕ),
                                  _свод(47, 0.702, {"anime": 47}))
    assert слово == "данных недостаточно"
    assert "состав" in почему
    assert "anime" in почему


def test_одинаковый_состав_сравнение_допускает():
    """Отрицательный контроль: при схожем составе вердикт выносится."""
    слово, почему = ИНСТР.вердикт(_свод(1000, 0.54, {"anime": 600, "lords": 400}),
                                  _свод(200, 0.70, {"anime": 118, "lords": 82}))
    assert слово != "данных недостаточно", почему


def test_неизвестный_состав_не_повод_для_вывода():
    """Направление не прочитано — это «не измерено», а не «состав совпал»."""
    слово, почему = ИНСТР.вердикт(_свод(1000, 0.54, {}), _свод(200, 0.70, {}))
    assert слово == "данных недостаточно"
    assert "состав" in почему


# --- сила различия ------------------------------------------------------------

def test_заметная_разница_предварительный_сигнал():
    слово, почему = ИНСТР.вердикт(_свод(1000, 0.54, СМЕШАННОЕ),
                                  _свод(200, 0.70, {"anime": 120, "lords": 80}))
    assert слово == "предварительный сигнал"
    assert "16.0" in почему or "16" in почему


def test_разница_в_пределах_шума_эффект_не_обнаружен():
    """Отрицательный контроль: малая разница не объявляется находкой."""
    слово, почему = ИНСТР.вердикт(_свод(1000, 0.54, СМЕШАННОЕ),
                                  _свод(200, 0.56, {"anime": 120, "lords": 80}))
    assert слово == "эффект не обнаружен"


def test_шум_считается_по_меньшей_части():
    """На 40 заданиях та же разница в 2 пункта остаётся шумом."""
    слово, _ = ИНСТР.вердикт(_свод(1000, 0.54, СМЕШАННОЕ),
                             _свод(40, 0.56, {"anime": 24, "lords": 16}))
    assert слово == "эффект не обнаружен"


def test_подтверждённый_результат_требует_обеих_частей_крупными():
    """Четвёртое слово достаётся только большому и устойчивому различию."""
    слово, _ = ИНСТР.вердикт(_свод(1000, 0.54, СМЕШАННОЕ),
                             _свод(600, 0.20, {"anime": 360, "lords": 240}))
    assert слово == "подтверждённый результат"


# --- печать -------------------------------------------------------------------

def test_живой_прогон_печатает_вердикт(capsys):
    код = ИНСТР.main(["--split", "2026-10-19T06:30Z"])
    вывод = capsys.readouterr().out
    assert код == 0, вывод
    assert "ВЕРДИКТ:" in вывод, "выше порога инструмент обязан произнести вывод"
    assert "направления" in вывод
