"""Одна цепочка запуска домена: отсутствующий вход называется, а не подставляется.

Проверяется поведение, из-за отсутствия которого цепочка была бы вредной:
отказ и замечание не путаются местами, а происхождение шаблона и идентификатор
издателя читаются оттуда, где они действительно записаны.
"""
from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "host" / "launch-domain.py"


def загрузить():
    спец = importlib.util.spec_from_file_location("launch_domain", СЦЕНАРИЙ)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def test_сценарий_существует_и_загружается() -> None:
    модуль = загрузить()
    for имя in ("проверить_днс", "проверить_реестр", "проверить_шаблон",
                "проверить_издателя", "проверить_репозиторий", "проверить_ci",
                "проверить_снимок", "проверить_хост", "проверить_публично"):
        assert hasattr(модуль, имя), f"в цепочке нет этапа {имя}"


def test_замечание_не_считается_помехой() -> None:
    """Иначе работающая витрина останавливается из-за унаследованной настройки.

    Общий publisher_id стоит у пяти доменов; объявить это отказом значило бы
    объявить сломанными четыре работающих сайта.
    """
    текст = СЦЕНАРИЙ.read_text(encoding="utf-8")
    assert 'ЗАМЕЧАНИЕ = "замечание"' in текст
    assert 'ш["state"] not in (ОК, ЗАМЕЧАНИЕ)' in текст, (
        "замечание попадает в список помех")


def test_новый_домен_обязан_иметь_свой_publisher_id() -> None:
    """Послабление для унаследованного состояния не распространяется на новый.

    У выпущенной витрины общий идентификатор — записанный факт. У домена,
    который ещё не выпускался, это отсутствующий вход, и подставлять чужой
    нельзя.
    """
    текст = СЦЕНАРИЙ.read_text(encoding="utf-8")
    место_условия = текст.find("if уже_выпущена(ячейка):\n            return этап(\"player_configured\", ЗАМЕЧАНИЕ")
    место_отказа = текст.find('return этап("player_configured", НЕТ_ВХОДА,\n                    f"publisher_id {свой} уже принадлежит')
    assert место_условия != -1, "нет разделения по выпущенности"
    assert место_отказа != -1, "новый домен не получает отказа на чужой идентификатор"
    assert место_условия < место_отказа


def test_цепочка_не_подставляет_значения() -> None:
    """Ни одного значения по умолчанию: пустой вход — отказ с именем входа."""
    текст = СЦЕНАРИЙ.read_text(encoding="utf-8")
    for запрет in ("publisher_id = 10", 'publisher_id", "10', "template_id = \"zona"):
        assert запрет not in текст, f"в цепочке подставляется значение: {запрет}"
    assert "НЕТ ВХОДА" in текст


@pytest.mark.parametrize("домен", ["zonafilm.space", "zonafilm12.site"])
def test_цепочка_запускается_на_реальном_домене(домен: str) -> None:
    """Прогон обязан завершаться и давать машиночитаемый ответ.

    Код 0 означает «все этапы пройдены», 1 — «есть помеха»; оба нормальны.
    Падение с трассировкой не нормально ни при каком состоянии домена.
    """
    гот = subprocess.run([sys.executable, str(СЦЕНАРИЙ), "--domain", домен, "--json"],
                         capture_output=True, text=True, timeout=180, cwd=КОРЕНЬ)
    assert гот.returncode in (0, 1), гот.stderr[-400:]
    import json as _json

    итог = _json.loads(гот.stdout)
    assert итог["domain"] == домен
    assert итог["stages"], "ни одного этапа не проверено"
    if not итог["complete"]:
        assert итог["blocking_stage"], "помеха есть, а этап не назван"
        assert итог["blocking_reason"], "помеха есть, а причина не названа"
