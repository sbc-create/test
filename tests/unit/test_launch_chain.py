def _запись_реестра(site_id: str) -> dict:
    """Настоящая запись ячейки: правило проверяется на том, что лежит в git."""
    import json as _json

    реестр = _json.loads((КОРЕНЬ / "config" / "site-cells.json").read_text(encoding="utf-8"))
    return next(c for c in реестр["cells"] if c["site_id"] == site_id)


def test_освобождение_от_аналитики_не_требует_входа_владельца() -> None:
    """Владелец запретил Метрику на партии — цепочка не вправе просить её снова.

    Измерено 2026-10-14: цепочка сообщала «НЕТ ВХОДА metrika_counter — домен не
    объявлен в реестре аналитики» и то же про Topvisor, тогда как запись
    удовлетворяет правилу D209 целиком. Так восемь витрин навсегда остались бы
    «не готовы» из-за входа, в котором владелец уже отказал.
    """
    модуль = загрузить()
    ячейка = _запись_реестра("lords-10")
    метрика = модуль.проверить_метрику(ячейка, "lordfilm.group", действовать=False)
    assert метрика["state"] == модуль.ОК, метрика
    assert "решением владельца" in метрика["detail"]
    topvisor = модуль.проверить_topvisor(ячейка, "lordfilm.group", действовать=False)
    assert topvisor["state"] == модуль.ОК, topvisor
    assert "решением владельца" in topvisor["detail"]


