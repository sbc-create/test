"""REQ-CELL-HEALTHZ-COST: служебный ответ не читает 110 МиБ на каждый запрос.

Измерено 2026-10-18 на узле (`k2-cell-latency.py lords-13`):

    главная  [0.816, 0.840, 0.803] с
    healthz  [1.854] с

Служебный путь отвечал ВДВОЕ ДОЛЬШЕ страницы каталога. Причина в составе
ответа: суммы снимка каталога (20 МиБ) и подробностей (90 МиБ) считались
чтением файлов ЦЕЛИКОМ на каждый запрос, а файл подробностей вдобавок
разбирался как JSON и обходился весь — по всем записям и всем их источникам —
ради двух диагностических проекций.

Почему это не мелочь: `/healthz` опрашивают наблюдение и сценарий выпуска,
причём в цикле, а под нагрузкой медленный служебный путь маскирует настоящее
состояние — «витрина жива» узнаётся дороже, чем «витрина отдала страницу».

Памятки ключуются по (путь, mtime, размер): файл выпуска и снимка неизменен,
пока его не заменили, а замена меняет одно из двух. Пересчёт происходит ровно
тогда, когда цифра и должна измениться.
"""
from __future__ import annotations

import re
from pathlib import Path

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _обработчик() -> str:
    начало = ТЕКСТ.index('if путь == "/healthz":')
    return ТЕКСТ[начало:ТЕКСТ.index('if путь == "/assets/nova.webmanifest":',
                                    начало)]


def test_памятки_объявлены_уровнем_модуля():
    """Иначе они жили бы на запрос и не экономили ничего."""
    for имя in ("_ПАМЯТКА_СУММ", "_ПАМЯТКА_ПРОЕКЦИЙ"):
        assert re.search(rf"^{имя}: dict = {{}}", ТЕКСТ, re.M), имя


def test_ключ_памятки_включает_mtime_и_размер():
    """Ключ по одному пути держал бы цифру прежнего выпуска вечно."""
    кусок = _обработчик()
    assert "st_mtime_ns" in кусок and "st_size" in кусок


def test_проекции_не_пересчитываются_при_попадании():
    """Отрицательный контроль: при попадании в памятку разбор JSON не
    выполняется — иначе экономии нет, а код только усложнился."""
    кусок = _обработчик()
    и_готовые = кусок.index("_готовые = (_ПАМЯТКА_ПРОЕКЦИЙ.get")
    и_разбор = кусок.index("json.loads(det_path.read_text")
    assert и_готовые < и_разбор, (
        "разбор файла подробностей обязан стоять в ветке промаха")
    ветка = кусок[кусок.index("if _готовые is not None:"):и_разбор]
    assert "json.loads" not in ветка


def test_памятка_держит_одну_запись_на_файл():
    """Рост без границы — это утечка: снимок меняется ежедневно."""
    кусок = _обработчик()
    assert "for прежний in [к for к in _ПАМЯТКА_СУММ if к[0] == str(путь_о)]" in кусок
    assert "_ПАМЯТКА_ПРОЕКЦИЙ.pop(_прежний, None)" in кусок


def test_состав_ответа_не_изменился():
    """Правка про СТОИМОСТЬ, а не про состав: поля остались те же."""
    кусок = _обработчик()
    for поле in ("catalog_digest", "details_digest",
                 "provider_projection_digest", "ratings_snapshot_digest",
                 "player_config_digest", "template_manifest_digest"):
        assert f'"{поле}"' in кусок, f"поле {поле} пропало из ответа"


def test_нечитаемый_файл_не_кладётся_в_памятку():
    """Пустая строка на ошибке чтения — прежнее поведение, и запоминать её
    нельзя: следующий запрос должен попробовать снова."""
    кусок = _обработчик()
    начало = кусок.find("def _dig(p):")
    assert начало >= 0, "функция суммы файла не найдена"
    тело = кусок[начало:]
    тело = тело[:тело.index("\n            тело = {")]
    # Возврат "" на OSError стоит ДО записи в памятку.
    и_ошибка = тело.index('except OSError:\n                    return ""')
    и_запись = тело.index("_ПАМЯТКА_СУММ[ключ] = цифра")
    assert и_ошибка < и_запись
