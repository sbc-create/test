"""Путь 1 MOD-116: появился ли постер у записи в ответе поставщика.

Ошибка этого прохода стоит дорого в обе стороны. Ложное «появился» закрыло бы
дефект, которого никто не исправлял; ложное «пусто» на пропавшей записи выдало
бы вопрос о данных за вопрос о картинке. Поэтому «записи нет в ответе» — это
`не измерено`, а не `пусто`, и опознание идёт только по `external_id`.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "poster_provider_watch",
    КОРЕНЬ / "automation/local/poster-provider-watch.py")
ИНС = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНС)


def запись(ид, постер="", создана="2026-10-12", обновлена="2026-10-12",
           внешние=None, имя="Проба"):
    return {"external_id": ид, "poster_url": постер, "name": имя,
            "created_at": f"{создана}T00:00:00Z",
            "updated_at": f"{обновлена}T00:00:00Z",
            "external_ids": внешние if внешние is not None else {}}


def test_появившийся_постер_назван():
    итог = ИНС.проверить([запись("a1", "https://poster.test/a1.jpg")],
                         [("karta", "a1")])
    assert итог["появился"] == [("karta", "https://poster.test/a1.jpg")]
    assert итог["пусто"] == [] and итог["не_измерено"] == []


def test_пустой_постер_это_пусто():
    итог = ИНС.проверить([запись("a1", "")], [("karta", "a1")])
    assert итог["пусто"] == ["karta"]


def test_пробелы_постером_не_считаются():
    итог = ИНС.проверить([запись("a1", "   ")], [("karta", "a1")])
    assert итог["пусто"] == ["karta"]


def test_пропавшая_запись_это_не_измерено():
    """Нулём это подменять нельзя: пропажа записи — отдельный вопрос."""
    итог = ИНС.проверить([запись("b2", "https://poster.test/b2.jpg")],
                         [("karta", "a1")])
    assert итог["не_измерено"] == ["karta"]
    assert итог["появился"] == [] and итог["пусто"] == []


def test_опознание_только_по_идентификатору():
    """Совпадение названий постером чужой записи не считается."""
    записи = [запись("b2", "https://poster.test/b2.jpg", имя="Проба")]
    итог = ИНС.проверить(записи, [("Проба", "a1")])
    assert итог["не_измерено"] == ["Проба"]


def test_внешние_идентификаторы_строкой_разбираются():
    """Поставщик присылает `external_ids` то словарём, то его записью строкой."""
    assert ИНС._внешние("{'kinopoisk': '144540'}") == {"kinopoisk": "144540"}
    assert ИНС._внешние({"imdb": "0062758"}) == {"imdb": "0062758"}
    assert ИНС._внешние("не словарь") == {}
    assert ИНС._внешние(None) == {}


def test_не_трогали_считается_по_дню_а_не_по_метке():
    assert ИНС.не_трогали(запись("a", создана="2026-10-12",
                                 обновлена="2026-10-12")) is True
    assert ИНС.не_трогали(запись("a", создана="2026-10-12",
                                 обновлена="2026-10-21")) is False
    # Без даты создания утверждать нечего.
    пустая = {"external_id": "a", "updated_at": "2026-10-21T00:00:00Z"}
    assert ИНС.не_трогали(пустая) is False


def test_сводка_считает_доли_по_обеим_группам():
    записи = [
        запись("1", "", внешние={"kinopoisk": "1"}),
        запись("2", "", создана="2026-10-12", обновлена="2026-10-20"),
        запись("3", "https://p.test/3.jpg"),
        запись("4", "https://p.test/4.jpg", создана="2026-10-12",
               обновлена="2026-10-20"),
    ]
    с = ИНС.сводка(записи)
    assert с == {"записей": 4, "без_постера": 2, "с_постером": 2,
                 "с_внешним_идентификатором": 1,
                 "не_трогали_без_постера": 1, "не_трогали_с_постером": 1,
                 "по_месяцу_создания": {"2026-10": 2}}


def test_равные_доли_печатаются_как_непройденный_контроль(capsys, tmp_path):
    """Если признак не различает группы, вывод обязан это сказать."""
    записи = [запись(str(н), "" if н < 5 else "https://p.test/x.jpg")
              for н in range(10)]
    файл = tmp_path / "ответ.json"
    файл.write_text(json.dumps({"items": записи, "fetched_at_ms": 1}),
                    encoding="utf-8")
    assert ИНС.main(["--source", str(файл)]) == 0
    вывод = capsys.readouterr().out
    assert "РАЗЛИЧАЮЩИЙ КОНТРОЛЬ НЕ ПРОЙДЕН" in вывод


def test_непрочитанный_ответ_не_читается_как_успех(capsys, tmp_path):
    assert ИНС.main(["--source", str(tmp_path / "нет.json")]) == 2
    assert "НЕ ИЗМЕРЕНО" in capsys.readouterr().out


def test_пустой_ответ_не_читается_как_успех(capsys, tmp_path):
    файл = tmp_path / "пусто.json"
    файл.write_text(json.dumps({"items": [], "fetched_at_ms": 1}),
                    encoding="utf-8")
    assert ИНС.main(["--source", str(файл)]) == 2
    assert "нет записей" in capsys.readouterr().out


def test_список_карточек_читается_по_work_id(tmp_path):
    файл = tmp_path / "строки.json"
    файл.write_text(json.dumps({"rows": [
        {"url": "https://x.test/title/pervye-radosti/", "work_id": "a1"},
        {"url": "https://x.test/title/bez-ид/"},
    ]}), encoding="utf-8")
    assert ИНС.разобрать_список(файл) == [("pervye-radosti", "a1")]
