"""В конфигурации витрины нет значений соседа.

Дважды за сутки экземпляр, созданный из проверенного выпуска, унаследовал чужие
значения, и оба раза это было незаметно:

* `an1meg0.site` получил `topvisor.project_id: 33751941` и
  `topvisor.site: "an1mego.site"` — инструмент семейства переписывал блок
  `analytics` и не переписывал `topvisor`. Отчёт по позициям ушёл бы в чужой
  проект;
* `yummyani7.site` и `yummyani7.info` получили
  `YUMMY_VARIANT_DOMAIN: "yummyani.site"` и общий с тремя действующими витринами
  файл read-model. Витрина отдавала бы чужой вариант и писала бы в чужое
  хранилище пользовательских данных.

Общее у обоих случаев: копирование переносит ВСЁ, а переписывается руками
ЧАСТЬ. Половина замены выглядит как полная — поэтому проверка сверяет значения
конфигурации со значениями ВСЕХ остальных ячеек реестра, а не с памятью автора.

Проверяются значения, а не текст: слово «yummyani.site» в пояснении или в списке
доменов, открытых для индексации, — это документация и запрет, а не настройка
этого сайта.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
АНАЛИТИКА = КОРЕНЬ / "config" / "analytics.json"

#: Ключи, значение которых относится ИМЕННО к этому сайту. Всё, что здесь, —
#: настройка, а не текст: чужое значение в любом из них означает, что сайт
#: обслуживает не свой домен, не свои данные или не свой отчёт.
КЛЮЧИ_НАСТРОЙКИ = (
    "domain", "canonical_host", "port", "site_id", "install_root", "service_name",
    "YUMMY_VARIANT_DOMAIN", "YUMMY_READMODEL", "LORDS_CATALOG",
    "LORDS_LEGACY_UPSTREAM", "counter_id", "project_id", "metrika_counter_id",
    "topvisor_project_id", "site",
)


def _ячейки() -> list[dict]:
    return json.loads(РЕЕСТР.read_text(encoding="utf-8"))["cells"]


def _счётчики() -> dict[str, object]:
    return {з["domain"]: з.get("counter_id")
            for з in json.loads(АНАЛИТИКА.read_text(encoding="utf-8"))["properties"]}


def _домены_манифеста() -> tuple[str, ...]:
    import sys  # noqa: PLC0415

    sys.path.insert(0, str(КОРЕНЬ))
    from factory.topvisor.manifest import domains  # noqa: PLC0415

    return domains()


def _проекты_отчёта() -> dict[int, str]:
    """Идентификаторы проектов из САМОГО СВЕЖЕГО отчёта службы, если он есть.

    Отчёт — не конфигурация, поэтому его отсутствие не делает проверку слабее:
    домены соседей она берёт из реестров в любом случае. Но когда отчёт есть,
    голый числовой идентификатор чужого проекта тоже становится ловимым.
    """
    import re  # noqa: PLC0415

    итог: dict[int, str] = {}
    отчёты = [КОРЕНЬ / "var" / "topvisor" / имя
              for имя in ("check-after-connect.txt", "check-latest.txt")]
    существующие = [п for п in отчёты if п.is_file() and п.stat().st_size]
    if not существующие:
        return итог
    свежий = max(существующие, key=lambda п: п.stat().st_mtime)
    for строка in свежий.read_text(encoding="utf-8", errors="replace").splitlines():
        с = re.match(r"^\s*#(\d+)\s+(\S+):", строка) or re.match(r"^\s*#(\d+)\s+(\S+)\s+—", строка)
        if с:
            итог[int(с.group(1))] = с.group(2)
    return итог


def _порты_хоста() -> dict[int, str]:
    """Порт → домен по установленным юнитам витрин.

    Нужен затем, что порт СОСЕДА может не быть ни в одном реестре этого
    репозитория: площадки, которые ведёт другая сессия, здесь не объявлены, а
    на хосте их юниты лежат рядом. Именно так проверка пропустила порт 9150
    (an1mego.site) в конфигурации an1meg0.site.

    Каталог юнитов доступен на чтение; его отсутствие не ослабляет проверку —
    остальные источники работают.
    """
    import re  # noqa: PLC0415

    итог: dict[int, str] = {}
    каталог = Path("/etc/systemd/system")
    try:
        файлы = sorted(каталог.glob("nova-*.service"))
    except OSError:
        return итог
    for файл in файлы:
        try:
            текст = файл.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        порт = re.search(r"--port\s+(\d+)", текст)
        if not порт:
            continue
        # Имя юнита nova-<домен с дефисами>.service → домен.
        имя = файл.stem.removeprefix("nova-").removesuffix("-candidate")
        итог[int(порт.group(1))] = имя
    return итог


def _значения(узел, ключи=КЛЮЧИ_НАСТРОЙКИ, путь=""):
    """Пары «путь → значение» только для ключей настройки, на любой глубине."""
    if isinstance(узел, dict):
        for ключ, значение in узел.items():
            новый = f"{путь}.{ключ}" if путь else ключ
            if ключ in ключи and not isinstance(значение, dict | list):
                yield новый, значение
            yield from _значения(значение, ключи, новый)
    elif isinstance(узел, list):
        for i, значение in enumerate(узел):
            yield from _значения(значение, ключи, f"{путь}[{i}]")


С_КОНФИГОМ = [c for c in _ячейки()
              if ((c.get("repo") or {}).get("path")
                  and (КОРЕНЬ / (c["repo"]["path"]) / "config" / "site.json").is_file())]


def test_есть_что_проверять() -> None:
    assert len(С_КОНФИГОМ) >= 5, f"витрин с конфигурацией найдено {len(С_КОНФИГОМ)}"


@pytest.mark.parametrize("ячейка", С_КОНФИГОМ, ids=lambda c: c["site_id"])
def test_в_конфигурации_нет_значений_соседа(ячейка: dict) -> None:
    свой = ячейка["domain"]
    счётчики = _счётчики()
    чужие: dict[str, str] = {}

    # Соседи — это НЕ только ячейки этого реестра. Первая версия проверки брала
    # только их и пропустила ровно тот случай, ради которого написана: у
    # an1meg0.site чужим был `an1mego.site` — площадка, которую ведёт другая
    # сессия и которой в реестре ячеек нет. Поэтому источников три: реестр
    # ячеек, реестр аналитики (там есть все домены со счётчиками) и манифест
    # Topvisor (там перечислены все домены, за которыми следит фабрика).
    for домен, счёт in счётчики.items():
        if домен == свой:
            continue
        чужие[домен] = "домен из реестра аналитики"
        if счёт:
            чужие[str(счёт)] = f"счётчик {домен}"
    for spec in _домены_манифеста():
        if spec != свой:
            чужие.setdefault(spec, "домен из манифеста Topvisor")
    for проект, домен in _проекты_отчёта().items():
        if домен != свой:
            чужие[str(проект)] = f"проект Topvisor {домен}"
    # Юниты на хосте названы по-разному: часть по домену (`nova-an1mego-site`),
    # часть по идентификатору ячейки (`nova-lords-03`). Сверять надо с обоими,
    # иначе собственный порт витрины объявляется чужим — первая версия этой
    # ветки так и падала на lords-03.
    свои_имена = {свой.replace(".", "-"), ячейка["site_id"]}
    for порт, имя in _порты_хоста().items():
        if имя not in свои_имена:
            чужие.setdefault(str(порт), f"порт витрины {имя} (юнит на хосте)")

    for другая in _ячейки():
        if другая["domain"] == свой:
            continue
        чужие[другая["domain"]] = f"домен ячейки {другая['site_id']}"
        порт = (другая.get("runtime") or {}).get("port")
        if порт:
            чужие[str(порт)] = f"порт ячейки {другая['site_id']}"
        аналитика = другая.get("analytics") or {}
        for поле in ("metrika_counter_id", "topvisor_project_id"):
            if аналитика.get(поле):
                чужие[str(аналитика[поле])] = f"{поле} ячейки {другая['site_id']}"
        счёт = счётчики.get(другая["domain"])
        if счёт:
            чужие[str(счёт)] = f"счётчик {другая['site_id']}"

    конфиг = json.loads(
        (КОРЕНЬ / ячейка["repo"]["path"] / "config" / "site.json").read_text(encoding="utf-8"))
    найдено = []
    for путь, значение in _значения(конфиг):
        текст = str(значение)
        for чужое, чьё in чужие.items():
            # Точное совпадение значения или вхождение домена в путь/адрес.
            if текст == чужое or (chr(46) in чужое and чужое in текст):
                найдено.append(f"{путь} = {значение!r} — это {чьё}")
    assert not найдено, (
        f"{свой}: в конфигурации значения соседа. Копирование переносит всё, а "
        "переписывается часть — и половина замены выглядит как полная:\n  "
        + "\n  ".join(sorted(set(найдено))))
