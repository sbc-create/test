"""srcset обещает только те ширины, которые источник действительно отдаёт.

ПОВОД (MOD-214), измеренный 27.10 прямым запросом тринадцати обложек ленты
главной `animedia.icu`: `?w=160` отдаёт 160 у всех тринадцати, `?w=240` — 240
у всех, `?w=480` — только у десяти; у трёх возвращается 424, 317 и 443.
Источник не увеличивает картинку, и это верно. Растягивали мы: дескрипторы
объявлялись одинаково для каждой обложки.

ПОЧЕМУ ТЕСТ ПОВЕДЕНЧЕСКИЙ. У сборки дескрипторов две ветки — ширина известна
и неизвестна, — и ошибка в любой выходит на живую страницу. Проверка «строка
есть в файле» ни одной из них не касается.
"""
from __future__ import annotations

import ast
import html as _html
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМ = (КОРЕНЬ / "var" / "site-repos" / "animedia-icu" / "src"
           / "animedia-frontend.py")
ИМЕНА = ("_srcset_постера", "_постер_безопасный_ключ", "_ширина_оригинала")


@pytest.fixture()
def окружение():
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    дерево = ast.parse(текст, РАНТАЙМ.name)
    узлы = [у for у in ast.walk(дерево)
            if isinstance(у, ast.FunctionDef) and у.name in ИМЕНА]
    пропали = set(ИМЕНА) - {у.name for у in узлы}
    assert not пропали, f"в рантайме нет: {sorted(пропали)}"
    окр: dict = {"html": _html, "re": __import__("re"),
                 "ПОСТЕР_ШИРИНЫ": (160, 240, 320, 720),
                 "ПОСТЕР_МАКС_ШИРИНА": 480,
                 "_ПОСТЕР_РАЗМЕР": {}}
    exec(compile(ast.Module(body=узлы, type_ignores=[]), str(РАНТАЙМ), "exec"), окр)
    return окр


АДРЕС = "/poster/0191526c-27a2-768c-8c2f-920000000000.webp"
КЛЮЧ = АДРЕС[len("/poster/"):]


def _дескрипторы(строка: str) -> list[int]:
    import re
    return [int(ч) for ч in re.findall(r"\s(\d+)w", строка)]


def test_без_замера_поведение_прежнее(окружение):
    """Разметка готовится раньше, чем браузер попросит картинку. Пока ширина
    не измерена, выдумывать нечего — дескрипторы прежние."""
    с = окружение["_srcset_постера"](АДРЕС, 150)
    assert _дескрипторы(с) == [160, 240, 320, 480]


def test_мелкий_оригинал_не_обещает_лишнего(окружение):
    """Тот самый случай: оригинал 317 при объявленных 480."""
    окружение["_ПОСТЕР_РАЗМЕР"][КЛЮЧ] = (0.0, 317)
    с = окружение["_srcset_постера"](АДРЕС, 150)
    assert _дескрипторы(с) == [160, 240, 317], с
    assert "?w=320" not in с and "480w" not in с


def test_оригинал_между_кандидатами(окружение):
    """424 — между 320 и 480: кандидаты мельче остаются, 480 исчезает."""
    окружение["_ПОСТЕР_РАЗМЕР"][КЛЮЧ] = (0.0, 424)
    assert _дескрипторы(окружение["_srcset_постера"](АДРЕС, 150)) == [160, 240, 320, 424]


def test_крупный_оригинал_не_теряет_кандидатов(окружение):
    """У широкого оригинала поведение прежнее: предел наш, а не источника."""
    окружение["_ПОСТЕР_РАЗМЕР"][КЛЮЧ] = (0.0, 1086)
    assert _дескрипторы(окружение["_srcset_постера"](АДРЕС, 150)) == [160, 240, 320, 480]


def test_оригинал_мельче_самого_мелкого_кандидата(окружение):
    """144 — меньше 160. Объявить нечего, кроме самой картинки; выдавать
    160w за неё — та же ложь, только мельче."""
    окружение["_ПОСТЕР_РАЗМЕР"][КЛЮЧ] = (0.0, 144)
    с = окружение["_srcset_постера"](АДРЕС, 150)
    assert _дескрипторы(с) == [144], с


def test_внешний_адрес_без_srcset(окружение):
    """Источник не наш — параметра ширины он не понимает."""
    assert окружение["_srcset_постера"]("https://чужой/обложка.webp", 150) == ""


def test_замер_не_выдумывает_число(окружение):
    """Битые байты и неизвестный тип — None, а не догадка."""
    ш = окружение["_ширина_оригинала"]
    assert ш(b"not-an-image", "image/webp") is None
    assert ш(b"", "image/jpeg") is None
    assert ш(b"\x89PNG\r\n\x1a\n", "text/plain") is None


def test_замер_читает_настоящую_ширину(окружение):
    """На настоящем файле замер обязан дать настоящее число."""
    PIL = pytest.importorskip("PIL")
    import io

    from PIL import Image
    буфер = io.BytesIO()
    Image.new("RGB", (317, 475), (10, 20, 30)).save(буфер, format="WEBP")
    assert окружение["_ширина_оригинала"](буфер.getvalue(), "image/webp") == 317
