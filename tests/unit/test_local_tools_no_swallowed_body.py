"""Тело инструмента не должно оказаться внутри неиспользуемого помощника.

ПОВОД. 23.10 в `automation/local/playback-check.py` определение помощника
`_запрет_счётчиков` встало столбцом 0 ПОСЛЕ открытия `with sync_playwright()`.
Python прочёл весь остаток файла — щелчок по плееру, шестнадцать замеров
`currentTime`, печать вердикта и три аварийных выхода — как ТЕЛО ЭТОЙ ФУНКЦИИ.
Функция не вызывалась ниоткуда, поэтому инструмент запускал браузер и молча
заканчивался с кодом 0. Проверка доступности плеера сообщала успех, не
проверив ничего, и синтаксис был при этом безупречен.

ЧТО ЛОВИТ ПРОВЕРКА. Приватную функцию верхнего уровня (имя с `_`), которая в
своём же модуле ни разу не упомянута и при этом содержит печать, аварийный
выход или больше десяти инструкций. Приватное имя не предназначено для импорта
извне, поэтому «определена, но нигде не названа» означает либо мёртвый код,
либо проглоченное тело — и то и другое требует правки.

ПОЧЕМУ НЕ ПРОЩЕ. Запрет на любую неиспользуемую функцию дал бы ложные отказы:
`traffic-segments.py` держит правило автоматики, которое читают ДРУГИЕ
инструменты, и в своём модуле оно не вызывается. Поэтому судятся только
приватные имена, а размер и наличие печати отделяют заготовку в три строки от
проглоченной программы.
"""
import ast
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
КАТАЛОГИ = ("automation/local", "automation/host")
ПОРОГ_ИНСТРУКЦИЙ = 10


def инструменты():
    for каталог in КАТАЛОГИ:
        d = КОРЕНЬ / каталог
        if d.is_dir():
            yield from sorted(d.glob("*.py"))


def упоминания(дерево, кроме):
    """Имена, названные где-либо ВНЕ определения `кроме` и его тела.

    Исключается всё поддерево `кроме`, а не только его корень. Иначе
    проглоченное тело «использует» помощника само: в дефекте 23.10 вызов
    `_перехвачено = _запрет_счётчиков(к)` провалился внутрь той же функции и
    имя выглядело занятым. Настоящая рекурсия приватного помощника, которого
    снаружи никто не звал, — тоже мёртвый код, и отказ по ней верен.
    """
    свои = {id(у) for у in ast.walk(кроме)}
    названо = set()
    for узел in ast.walk(дерево):
        if id(узел) in свои:
            continue
        if isinstance(узел, ast.Name) and isinstance(узел.ctx, ast.Load):
            названо.add(узел.id)
        elif isinstance(узел, ast.Attribute):
            названо.add(узел.attr)
        elif isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            названо.add(узел.value)
    return названо


def проглоченные(текст):
    """Приватные функции верхнего уровня, похожие на проглоченное тело."""
    дерево = ast.parse(текст)
    плохие = []
    for узел in дерево.body:
        if not isinstance(узел, ast.FunctionDef | ast.AsyncFunctionDef):
            continue
        if not узел.name.startswith("_"):
            continue
        if узел.name in упоминания(дерево, узел):
            continue
        внутри = list(ast.walk(узел))
        печатает = any(
            isinstance(у, ast.Call) and isinstance(у.func, ast.Name)
            and у.func.id == "print" for у in внутри)
        выходит = any(
            isinstance(у, ast.Raise) or (
                isinstance(у, ast.Call) and isinstance(у.func, ast.Name)
                and у.func.id == "SystemExit") for у in внутри)
        инструкций = sum(1 for у in внутри if isinstance(у, ast.stmt))
        if печатает or выходит or инструкций > ПОРОГ_ИНСТРУКЦИЙ:
            плохие.append((узел.name, узел.lineno, узел.end_lineno,
                           инструкций, печатает, выходит))
    return плохие


@pytest.mark.parametrize("файл", list(инструменты()),
                         ids=lambda п: п.name)
def test_нет_проглоченного_тела(файл):
    найдено = проглоченные(файл.read_text("utf-8"))
    assert not найдено, (
        f"{файл.relative_to(КОРЕНЬ)}: приватная функция определена, нигде в"
        f" модуле не названа и содержит печать, выход или больше"
        f" {ПОРОГ_ИНСТРУКЦИЙ} инструкций — вероятно, в неё провалилось тело"
        f" инструмента: {найдено}")


def test_проверка_ловит_известный_случай():
    """Подмена: восстановить дефект 23.10 и убедиться, что он отлавливается."""
    образец = (
        "with открыть() as п:\n"
        "    б = п.запуск()\n"
        "def _помощник(ц):\n"
        "    return ц\n"
        "\n"
        "    стр = б.new_page()\n"
        # Вызов помощника провалился в его же тело — именно так дефект и
        # выглядел, и именно на этом первая версия проверки его упустила.
        "    _перехвачено = _помощник(б)\n"
        "    print('замер')\n"
        "    raise SystemExit(1)\n")
    найдено = проглоченные(образец)
    assert [и[0] for и in найдено] == ["_помощник"], найдено


def test_приватный_помощник_который_вызван_допустим():
    образец = (
        "def _помощник(ц):\n"
        "    print('шаг')\n"
        "    return ц\n"
        "\n"
        "with открыть() as п:\n"
        "    _помощник(п)\n")
    assert проглоченные(образец) == []


def test_публичное_имя_не_судится():
    """Правило автоматики из traffic-segments.py читают другие инструменты."""
    образец = (
        "def правило_автоматики(с):\n"
        "    print('это читает другой инструмент')\n"
        "    return с\n")
    assert проглоченные(образец) == []


def test_проверка_отклоняет_файл_до_починки():
    """На настоящем дефектном файле из истории проверка обязана отказать.

    Берётся версия `playback-check.py` из коммита 1414fce — того самого, где
    помощник встал ниже `with`. Это не синтетический образец, а состояние,
    которое пролежало в репозитории работающим на вид.
    """
    import subprocess
    готово = subprocess.run(
        ["git", "show", "1414fce:automation/local/playback-check.py"],
        cwd=КОРЕНЬ, capture_output=True, text=True, timeout=60)
    if готово.returncode != 0:
        pytest.skip("коммит 1414fce недоступен в этой копии")
    найдено = проглоченные(готово.stdout)
    assert [и[0] for и in найдено] == ["_запрет_счётчиков"], найдено
    имя, начало, конец, инструкций, печатает, выходит = найдено[0]
    assert конец - начало > 100, (
        "проглочено должно быть всё тело инструмента, а не пара строк:"
        f" строки {начало}-{конец}")
    assert печатает and выходит
