"""REQ-CELL-EPISODE-NOINDEX: пустая страница серии не индексируется никогда.

Измерено 2026-10-18 на lordserial.su (витрина K2, общий рантайм):

* адреса серий отвечают 200 по верхнюю ОБЪЯВЛЕННУЮ серию сезона (`eps`), а
  источник есть только у `avail` из них. У «Скотты» сезон 1: `eps` 6,
  `avail` 1 — серии 2…6 отдают 200 и пустое состояние, серия 7 отдаёт 404;
* по каталогу витрины объявлено 602 566 серий, доступно 557 368,
  объявлено-но-недоступно 45 198 (7.5 %);
* `<meta name="robots">` зависел ТОЛЬКО от режима сайта. Витрины K2 закрыты,
  и страницы отдают `noindex, nofollow`; в день открытия те же 45 198 пустых
  страниц стали бы `index, follow` с canonical на себя.

Правило узкое намеренно: закрывается страница, у которой НЕТ дорожки.
Страница с плеером содержательна, и закрывать её незачем. Соседние линии
закрывают все страницы серий подряд — их выбор, и без решения владельца он
не копируется.

`follow`, а не `nofollow`: по пустой странице обходчик обязан пройти к
соседним сериям, у которых источник есть.
"""
from __future__ import annotations

import re
from pathlib import Path

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def test_значение_для_закрытой_страницы_названо_один_раз():
    assert 'НЕ_ИНДЕКСИРУЕМА = "noindex, follow"' in ТЕКСТ
    assert ТЕКСТ.count("НЕ_ИНДЕКСИРУЕМА =") == 1, (
        "значение объявлено дважды — копии разойдутся")


def test_обходчик_проходит_по_закрытой_странице():
    """nofollow здесь был бы ошибкой: соседние серии доступны."""
    м = re.search(r'НЕ_ИНДЕКСИРУЕМА = "([^"]+)"', ТЕКСТ)
    assert м and "noindex" in м.group(1)
    assert "nofollow" not in м.group(1)


def test_все_оболочки_видов_учитывают_признак():
    """Иначе правка закрыла бы страницы одного семейства и пропустила другие.

    Проверяется ровно то, что ломалось бы молча: мета-тег внутри классов
    видов не должен считаться без признака.
    """
    хвост = ТЕКСТ[ТЕКСТ.index("class Вид:"):]
    без_признака = хвост.count('<meta name="robots" content="{мета_роботов()}">')
    assert без_признака == 0, (
        f"{без_признака} оболочек вида считают robots без признака")
    с_признаком = хвост.count(
        '<meta name="robots" content="{мета_роботов() if индексируема '
        'else НЕ_ИНДЕКСИРУЕМА}">')
    assert с_признаком == 4, f"оболочек с признаком {с_признаком}, ожидалось 4"


def test_страница_серии_передаёт_признак_из_наличия_дорожки():
    """Признак берётся у того же предиката, которым решается показ плеера."""
    assert ТЕКСТ.count(
        "индексируема=серия_с_дорожкой(деталь, сезон, эпизод)") == 2, (
        "обе реализации страницы серии обязаны передавать признак")


def test_признак_по_умолчанию_не_закрывает_прочие_страницы():
    """Отрицательный контроль: главная, каталог и карточка индексируются как
    раньше. Значение по умолчанию — True во всех оболочках."""
    хвост = ТЕКСТ[ТЕКСТ.index("class Вид:"):]
    объявлений = len(re.findall(r"индексируема: bool = True", хвост))
    assert объявлений == 3, (
        f"оболочек с признаком по умолчанию {объявлений}, ожидалось 3")


def test_предикат_наличия_дорожки_не_подменён():
    """`серия_с_дорожкой` отвечает на вопрос «есть ли источник у этой серии».

    Если бы признак считался по `avail` напрямую, спецвыпуск с номером 0 и
    пропуски в нумерации закрылись бы заодно — ровно та ошибка, из-за которой
    в `доступные_номера` и появился явный перечень `nums`.
    """
    тело = ТЕКСТ[ТЕКСТ.index("def серия_с_дорожкой"):]
    тело = тело[:тело.index("\ndef ", 1)]
    assert "список_серий(деталь)" in тело and '"доступные"' in тело, (
        "предикат обязан спрашивать перечень номеров сезона")
    # А перечень, в свою очередь, строится явными номерами, а не одним числом.
    список = ТЕКСТ[ТЕКСТ.index("def список_серий"):]
    список = список[:список.index("\ndef ", 1)]
    assert "доступные_номера" in список, (
        "перечень серий сезона считается одним числом — спецвыпуск с номером 0 "
        "и пропуски в нумерации потерялись бы")
