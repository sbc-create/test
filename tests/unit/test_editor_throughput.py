"""Полезный выход редактора против пустой работы.

ПОВОД ИЗМЕРЕННЫЙ, 24.10. За сутки редактор закрыл 296 заданий: текст написан у
51, пустых исходов 245, и из них **211 повторены без изменения условий** —
очередь САМА пишет это в `detail` («повтор без изменения условий … реестр
источников не менялся»), но срок следующей попытки от этого признака не
зависит (`ПОВТОР_ФАКТОВ_Ч = 24`). То есть 71 % работы редактора — заведомо
бессмысленный повтор (MOD-168).

Главное свойство инструмента: он НЕ путает три разные вещи — написанный
текст, первый отказ по новому произведению (это цена разбора) и повтор по
кругу (это потеря). Инструмент, считающий «пусто» одним числом, показал бы
82,8 % и не сказал бы, какую часть можно вернуть.
"""
from __future__ import annotations

import datetime
import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "editor-throughput.py"
_с = importlib.util.spec_from_file_location("editor_throughput", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(МОДУЛЬ)

СЕЙЧАС = datetime.datetime(2026, 10, 24, 12, 0, tzinfo=datetime.timezone.utc)


def _аренда(site: str, work: str, шаги: list[dict]) -> dict:
    return {"site": site, "work_id": work, "history": шаги}


def _шаг(исход: str, час: int, detail: str = "") -> dict:
    return {"at": f"2026-10-24T{час:02d}:00:00Z", "outcome": исход,
            "detail": detail}


def test_круг_отличается_от_первого_отказа():
    """Повтор по кругу — потеря; первый отказ — цена разбора."""
    assert МОДУЛЬ.по_кругу({"detail": "повтор без изменения условий:"
                                      " прежний отказ 2026-10-23T06:36:02Z,"
                                      " реестр источников не менялся"})
    assert not МОДУЛЬ.по_кругу({"detail": "источники проверены,"
                                          " фактов о годе нет"})
    assert not МОДУЛЬ.по_кругу({})


def test_свод_считает_написанное_пустое_и_круг_раздельно():
    пары = [
        (_аренда("а", "1", []), _шаг("TEXT_WRITTEN", 1)),
        (_аренда("а", "2", []), _шаг("SOURCES_MISSING", 2,
                                     "повтор без изменения условий")),
        (_аренда("б", "3", []), _шаг("SOURCES_MISSING", 3,
                                     "фактов о годе нет")),
        (_аренда("б", "4", []), _шаг("PAGE_ABSENT", 4,
                                     "адрес не отдался, реестр не менялся")),
    ]
    д = МОДУЛЬ.свод(пары)
    assert д["всего"] == 4
    assert д["написано"] == 1
    assert д["пусто"] == 3
    assert д["пусто_по_кругу"] == 2, д
    assert д["различных_произведений"] == 4
    assert д["витрин"] == 2


def test_написанный_текст_пустым_не_считается():
    """TEXT_WRITTEN не входит в пустые даже с непустым detail."""
    д = МОДУЛЬ.свод([(_аренда("а", "1", []),
                      _шаг("TEXT_WRITTEN", 1, "условия не менялись"))])
    assert д["пусто"] == 0 and д["пусто_по_кругу"] == 0


def test_окно_отсекает_прошлые_сутки():
    записи = [_аренда("а", "1", [{"at": "2026-10-20T10:00:00Z",
                                  "outcome": "TEXT_WRITTEN"},
                                 {"at": "2026-10-24T10:00:00Z",
                                  "outcome": "SOURCES_MISSING"}])]
    пары = МОДУЛЬ.шаги(записи, СЕЙЧАС - datetime.timedelta(hours=24), СЕЙЧАС)
    assert len(пары) == 1
    assert пары[0][1]["outcome"] == "SOURCES_MISSING"


def test_метка_без_часового_пояса_не_теряется():
    """Журнал пишет Z, но запись без пояса считается UTC, а не пропускается."""
    записи = [_аренда("а", "1", [{"at": "2026-10-24T10:00:00",
                                  "outcome": "TEXT_WRITTEN"}])]
    assert len(МОДУЛЬ.шаги(записи, СЕЙЧАС - datetime.timedelta(hours=24),
                           СЕЙЧАС)) == 1


def test_битая_метка_не_валит_замер():
    записи = [_аренда("а", "1", [{"at": "вчера", "outcome": "TEXT_WRITTEN"},
                                 {"at": "2026-10-24T10:00:00Z",
                                  "outcome": "TEXT_WRITTEN"}])]
    assert len(МОДУЛЬ.шаги(записи, СЕЙЧАС - datetime.timedelta(hours=24),
                           СЕЙЧАС)) == 1


def test_пустое_окно_это_не_измерено_а_не_ноль(tmp_path):
    """Редактор не работал и журнал не пишется — разные вещи от «0 текстов»."""
    ф = tmp_path / "leases.json"
    ф.write_text(json.dumps({"leases": [_аренда("а", "1", [
        {"at": "2026-09-01T10:00:00Z", "outcome": "TEXT_WRITTEN"}])]}),
        encoding="utf-8")
    assert МОДУЛЬ.главное(["--leases", str(ф), "--hours", "24"]) == 2


def test_нет_журнала_это_не_измерено(tmp_path):
    assert МОДУЛЬ.главное(["--leases", str(tmp_path / "нет.json")]) == 2


def test_высокая_доля_пустых_отражается_кодом_выхода(tmp_path, capsys):
    """Замер обязан уметь ОТКАЗАТЬ, иначе он украшение."""
    час = СЕЙЧАС.hour - 1
    ф = tmp_path / "leases.json"
    ф.write_text(json.dumps({"leases": [
        _аренда("а", "1", [_шаг("TEXT_WRITTEN", час)]),
        _аренда("а", "2", [_шаг("SOURCES_MISSING", час,
                                "повтор без изменения условий")]),
        _аренда("а", "3", [_шаг("SOURCES_MISSING", час,
                                "повтор без изменения условий")]),
    ]}), encoding="utf-8")
    код = МОДУЛЬ.главное(["--leases", str(ф), "--hours", "24"])
    из = capsys.readouterr().out
    assert код == 1, из
    assert "MOD-168" in из


def test_низкая_доля_пустых_проходит(tmp_path, capsys):
    """Отрицательный контроль: порог должен уметь не срабатывать."""
    час = СЕЙЧАС.hour - 1
    ф = tmp_path / "leases.json"
    ф.write_text(json.dumps({"leases": [
        _аренда("а", str(н), [_шаг("TEXT_WRITTEN", час)]) for н in range(3)
    ] + [_аренда("а", "x", [_шаг("SOURCES_MISSING", час, "фактов нет")])]}),
        encoding="utf-8")
    assert МОДУЛЬ.главное(["--leases", str(ф), "--hours", "24"]) == 0
