"""REQ-SEO-SITEMAP-MASS-DATE: подстановка одной даты отличается от импорта.

Владелец запретил массовую подстановку `lastmod`: дата должна говорить, когда
запись менялась, иначе поисковая система перестаёт ей верить. Признак этого
дефекта трижды называл исправное состояние провалом, и каждый раз — потому что
мерил ОДНУ цифру вместо состава:

1. доля самой частой даты 29.6 % на `yummyani.site/sitemap/titles.xml` —
   оказалась двумя крупными партиями импорта при 255 различных датах и плавном
   хвосте;
2. «75 % одной даты» на статике из 20 адресов — три значения, а не
   подстановка;
3. доля 53.7 % в `yummyani.org/sitemap/episodes-2.xml` — дата есть у 54
   адресов из 50 000, из них 29 на одну дату. Подстановка — это дата,
   поставленная ВСЕМ; 29 адресов из 50 000 не «все».

Проверка держит все три исхода И настоящий дефект, измеренный там же:
`yummyani.site/sitemap/episodes.xml`, 1 647 адресов, 100 % на 2026-08-21.
"""
from __future__ import annotations

import datetime as dt
import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "sitemap-lastmod-check.py")
ЮТС = dt.timezone.utc
ПОРОГ = dt.datetime(2024, 1, 1, tzinfo=ЮТС)
ПРЕДЕЛ = 0.20


def _модуль():
    спец = importlib.util.spec_from_file_location("sitemap_lastmod_check", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def _данные(части: dict) -> dict:
    return {"domain": "пример", "measured_at": "2026-10-18T08:00:00+00:00",
            "index": {}, "parts": части}


def _часть(даты: list, пустых: int = 0) -> dict:
    адреса = {f"/a/{н}": д for н, д in enumerate(даты)}
    for н in range(пустых):
        адреса[f"/b/{н}"] = None
    return адреса


def _провалов(часть: dict) -> int:
    return МОД.проверить(_данные({"часть.xml": часть}), ПОРОГ, ПРЕДЕЛ)


def test_подстановка_одной_даты_всем_адресам_это_провал():
    """Измерено: episodes.xml на yummyani.site, 1 647 адресов, одна дата."""
    assert _провалов(_часть(["2026-08-21T00:00:00+00:00"] * 1647)) == 1


def test_крупный_импорт_с_плавным_хвостом_не_провал():
    """Измерено: titles.xml, 255 различных дат, у верхней 29.6 %."""
    # Даты только в прошлом: предмет проверки — доля, а дата из будущего
    # роняет ДРУГОЕ, тоже верное условие, и подменила бы вывод.
    начало = dt.date(2026, 10, 1)
    даты = []
    for н in range(255):
        сколько = 2470 if н == 0 else max(1, 1700 // (н + 1))
        день = (начало - dt.timedelta(days=н)).isoformat()
        даты += [f"{день}T05:00:00+00:00"] * сколько
    часть = _часть(даты)
    доля_верхней = 2470 / len(даты)
    assert 0.20 < доля_верхней < 0.50, f"проверка потеряла предмет: {доля_верхней}"
    assert len({д[:10] for д in даты}) == 255
    assert _провалов(часть) == 0


def test_редкая_дата_в_огромной_части_не_подстановка():
    """Та же доля, что у провала, но дата есть у малой части адресов."""
    часть = _часть(["2026-10-17T12:00:00+00:00"] * 29
                   + [f"2026-10-{1 + н % 16:02d}T12:00:00+00:00" for н in range(25)],
                   пустых=49946)
    assert _провалов(часть) == 0


def test_та_же_доля_при_полном_покрытии_это_провал():
    """Отрицательный контроль к предыдущему: различает ПОКРЫТИЕ, не доля.

    Состав дат тот же — 29 адресов на одну дату и 25 на разные; убраны только
    адреса без даты. Если бы условие про покрытие исчезло, оба случая дали бы
    одинаковый вердикт, и проверка перестала бы отличать подстановку от
    редкого исключения.
    """
    часть = _часть(["2026-10-17T12:00:00+00:00"] * 29
                   + [f"2026-10-{1 + н % 16:02d}T12:00:00+00:00" for н in range(25)])
    assert _провалов(часть) == 1


def test_скудный_состав_при_полном_покрытии_это_провал():
    """Дат единицы: доля ниже половины, но выбирать было не из чего."""
    даты = (["2026-08-21T00:00:00+00:00"] * 60
            + ["2026-08-22T00:00:00+00:00"] * 45
            + ["2026-08-23T00:00:00+00:00"] * 45)
    assert _провалов(_часть(даты)) == 1


def test_малая_часть_не_оценивается():
    """20 адресов статики: 75 % одной даты — это три значения."""
    часть = _часть(["2026-08-21T00:00:00+00:00"] * 15
                   + ["2026-08-22T00:00:00+00:00"] * 5)
    assert _провалов(часть) == 0


def test_отсутствие_даты_вовсе_не_провал():
    """Разрешённое состояние: lastmod — необязательное поле."""
    assert _провалов(_часть([], пустых=50000)) == 0
