"""Приёмка главной меряет то, что обещает, и не ходит в сеть сама по себе.

Инструмент решает, что считать бедой, и эта логика должна быть проверяема без
браузера: иначе «0 бед» ничего не значит. Здесь проверяется разбор адреса
(стенд по http, витрина по https) и сам счёт бед.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "home-acceptance.py"


@pytest.fixture(scope="module")
def м():
    спец = importlib.util.spec_from_file_location("home_acceptance", ПУТЬ)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def test_схема_адреса_по_месту(м):
    """Стенд отвечает по http, витрина — по https. Прибить https нельзя:
    тогда приёмку не прогнать ДО выпуска."""
    assert м._адрес("127.0.0.1:8731") == "http://127.0.0.1:8731"
    assert м._адрес("localhost:9000") == "http://localhost:9000"
    assert м._адрес("zonafilm.space") == "https://zonafilm.space"
    assert м._адрес("https://animedia.icu/") == "https://animedia.icu"


def test_порог_роста_позиции_назван(м):
    """«Позиция больше нуля» просмотром не является: поставщик отдаёт 0.09 и
    держит её. Признак — рост."""
    assert м.РОСТ_С >= 0.5
    assert м.НАЖАТИЙ >= 2 and м.ОЖИДАНИЕ_С >= 10


def test_осмотр_считает_ссылки_на_просмотр_в_анонсах(м):
    """Главное свойство блока анонсов: в нём не бывает ссылки на /title/."""
    assert "ссылок на просмотр в анонсах" in м.ОСМОТР
    assert "includes('/title/')" in м.ОСМОТР


def test_осмотр_различает_видимые_и_ленивые_обложки(м):
    assert "'обложек без файла'" in м.ОСМОТР
    assert "'обложек ждут прокрутки'" in м.ОСМОТР
    assert "видна(i)" in м.ОСМОТР


def test_технический_прогон_глушит_метрику(м):
    """Иначе приёмка попадает в статистику людей и раздувает показы блоков."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert текст.count('route("**mc.yandex.*/**"') >= 3, текст.count('route(')


def test_осмотр_смотрит_на_заголовок_первого_уровня(м):
    """H1 принадлежит странице. 27.10 его забрала редакционная полка, и ни
    одна проверка этого не заметила."""
    assert "'заголовков h1'" in м.ОСМОТР
    assert "'h1 забрала полка'" in м.ОСМОТР
    assert "'h1 равен заголовку'" in м.ОСМОТР
    assert "подпись_полки" in м.ОСМОТР
    assert "document.title" in м.ОСМОТР


@pytest.mark.parametrize("проход, беда", (
    ({"заголовков h1": 1, "h1 забрала полка": False}, False),
    ({"заголовков h1": 0}, True),
    ({"заголовков h1": 2}, True),
    ({"заголовков h1": 1, "h1 забрала полка": True}, True),
    # H1 побайтно равен <title> — страница повторяет себя и не добавляет ни
    # слова (измерено линией SEO на zonafilm.cc 27.10).
    ({"заголовков h1": 1, "h1 равен заголовку": True}, True),
    ({"заголовков h1": 1, "h1 равен заголовку": False}, False),
    # Поля нет вовсе — осмотр не исполнился; молчаливым «ок» это становиться
    # не должно, но и бедой по этому полю тоже: беду даёт ключ «беда».
    ({"беда": "TimeoutError: нет ответа"}, True),
    ({}, False),
))
def test_итог_реагирует_на_заголовки(м, проход, беда):
    assert м.беда_прохода(проход) is беда


@pytest.mark.parametrize("проход, беда", (
    # Отсутствие значения не должно превращаться в «равны»: именно так
    # 27.10 получилось ложное равенство у соседней линии — сравнивались две
    # пустые строки. Пустой H1 даёт беду по своему признаку, а не равенством.
    ({"заголовков h1": 0, "h1 главной": "", "заголовок страницы": "",
      "h1 равен заголовку": False}, True),
    ({"заголовков h1": 1, "h1 главной": "", "заголовок страницы": "",
      "h1 равен заголовку": True}, True),
    ({"заголовков h1": 1, "h1 главной": "Предмет страницы",
      "заголовок страницы": "Имя — раздел", "h1 равен заголовку": False}, False),
))
def test_пустой_заголовок_не_проходит_равенством(м, проход, беда):
    assert м.беда_прохода(проход) is беда


def test_осмотр_не_считает_пустое_равным(м):
    """Осмотр берёт `textContent` первого H1 и `document.title`; если H1 нет
    вовсе, список пуст и равенство не вычисляется — считается `заголовков h1`."""
    assert "h1.length > 0" in м.ОСМОТР
    assert "'заголовков h1': h1.length," in м.ОСМОТР


def test_итог_реагирует_на_прежние_признаки(м):
    assert м.беда_прохода({"обложек без файла": 1}) is True
    assert м.беда_прохода({"растянутых обложек": 2}) is True
    assert м.беда_прохода({"ссылок на просмотр в анонсах": 1}) is True
    assert м.беда_прохода({"горизонтальная прокрутка": 7}) is True
    assert м.беда_прохода({"обложек ждут прокрутки": 9}) is False
