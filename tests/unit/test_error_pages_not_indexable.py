"""REQ-SEO-ERROR-PAGES: страницы 404 и 503 закрыты от индексации всегда.

Матрица индексируемости (`knowledge/SEO_INDEXABILITY_MATRIX.yaml:415`) для типа
`not_found` требует `robots: "noindex,follow"`. Фронтенд семейств Lords/Zona
этого не делал: `не_найдено` вызывает `оболочка` без `индексируема=False`, и
страница ошибки наследовала ОБЩУЮ директиву витрины.

Измерено 19.10 на живых витринах:

    zonafilm.cc/404/                    404  robots index, follow
    zonafilm.cc/net-takogo-puti-xyz/    404  robots index, follow
    zonafilm.space/title/net-takogo/    404  robots index, follow
    lordserials22.info/catalog/?page=99999  404  robots noindex, follow
    animedia.icu/404/ (Next.js)         404  robots noindex, follow

На lordserials22.info значение правильное СЛУЧАЙНО: витрина целиком закрыта от
индексации, и общая директива совпала с нужной. Как только витрина открывается,
её страницы ошибок приглашают в индекс — то есть дефект проявляется ровно на
тех сайтах, где он вреден.

Для 503 записи в матрице нет; направление выбрано безопасное (закрыть), оно
совпадает с правилом `мета_роботов_пути`: служебные ответы закрыты всегда.
Открыть индексацию страницы ошибки это решение не может.
"""
from __future__ import annotations

import importlib.util
import inspect
import json
import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/host/lords-frontend.py"
_спец = importlib.util.spec_from_file_location("lords_frontend_errors", _путь)
ФРОНТ = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ФРОНТ)

ТЕКСТ = _путь.read_text(encoding="utf-8")
ОТКРЫТО = "index, follow"


@pytest.fixture
def открытая_витрина(monkeypatch):
    """Витрина, открытая для индексации: именно здесь дефект виден."""
    monkeypatch.setattr(ФРОНТ, "мета_роботов", lambda: ОТКРЫТО)
    return ОТКРЫТО


@pytest.fixture(scope="module")
def снимок(tmp_path_factory):
    """Настоящие `Данные` и `Подробности`: заглушки оболочку не проходят.

    Витрина обязана подниматься на пустом снимке (см. docstring `Подробности`),
    поэтому один тайтл — достаточная и честная основа: страница ошибки от
    состава каталога не зависит.
    """
    кат = tmp_path_factory.mktemp("снимок")
    (кат / "catalog.json").write_text(json.dumps({"items": [
        {"title": "Проверка", "slug": "proverka", "year": 2026,
         "kind": "anime", "url": "/title/proverka/"}]}, ensure_ascii=False),
        encoding="utf-8")
    return (ФРОНТ.Данные(str(кат / "catalog.json")),
            ФРОНТ.Подробности(str(кат / "details.json")))


def _вид(класс, имя: str, снимок):
    данные, подробности = снимок
    в = класс(ФРОНТ.СЕМЕЙСТВА_1_1[имя], данные, подробности,
              {"genre_names": [], "titles": []}, имя.capitalize())
    в.хост = f"{имя}-proverka.test"
    return в


def роботы(страница: str) -> str:
    м = re.search(r'name="robots" content="([^"]*)"', страница)
    return м.group(1) if м else ""


# --- страница 404 каждого семейства ------------------------------------------

@pytest.mark.parametrize("класс, семейство", [
    (ФРОНТ.ВидЛордс, "lords"),
    (ФРОНТ.ВидЗона, "zona"),
    (ФРОНТ.ВидАнимедиа, "animedia"),
])
def test_страница_404_закрыта_на_открытой_витрине(класс, семейство,
                                                  открытая_витрина, снимок):
    страница = _вид(класс, семейство, снимок).не_найдено("/net-takogo-puti-xyz/")
    assert роботы(страница) == ФРОНТ.НЕ_ИНДЕКСИРУЕМА, (
        f"404 семейства {семейство} объявила себя индексируемой")


@pytest.mark.parametrize("класс, семейство", [
    (ФРОНТ.ВидЛордс, "lords"),
    (ФРОНТ.ВидЗона, "zona"),
    (ФРОНТ.ВидАнимедиа, "animedia"),
])
def test_страница_404_без_канона(класс, семейство, открытая_витрина, снимок):
    """Матрица: canonical_rule none_no_index — у 404 канона быть не должно."""
    страница = _вид(класс, семейство, снимок).не_найдено("/net-takogo-puti-xyz/")
    assert 'rel="canonical"' not in страница


@pytest.mark.parametrize("класс, семейство", [
    (ФРОНТ.ВидЛордс, "lords"),
    (ФРОНТ.ВидЗона, "zona"),
    (ФРОНТ.ВидАнимедиа, "animedia"),
])
def test_обычная_страница_директиву_витрины_сохраняет(класс, семейство,
                                                      открытая_витрина, снимок):
    """Отрицательный контроль: правка не закрывает обычные страницы.

    Проверка, которая не может отличить 404 от каталога, запретила бы индексацию
    всей витрины и была бы «пройдена» ровно так же.
    """
    в = _вид(класс, семейство, снимок)
    страница = в.оболочка("<p>тело</p>", "Каталог", "/catalog/")
    assert роботы(страница) == ОТКРЫТО


def test_закрытая_витрина_остаётся_закрытой(monkeypatch, снимок):
    """Вторая сторона: на закрытой витрине 404 не открывается.

    Общая директива закрытой витрины — `noindex, nofollow`; подстановка
    `НЕ_ИНДЕКСИРУЕМА` («noindex, follow») не имеет права ослабить её до follow
    у остальных страниц.
    """
    monkeypatch.setattr(ФРОНТ, "мета_роботов", lambda: "noindex, nofollow")
    в = _вид(ФРОНТ.ВидЗона, "zona", снимок)
    assert роботы(в.оболочка("<p>тело</p>", "Каталог", "/catalog/")) == "noindex, nofollow"
    assert "noindex" in роботы(в.не_найдено("/нет/"))


# --- статическая выдача: 404 и 503 обработчика -------------------------------

def test_оболочка_модуля_умеет_закрывать_страницу():
    """У общей оболочки должен быть сам признак — иначе закрыть нечем."""
    доводы = inspect.signature(ФРОНТ.оболочка).parameters
    assert "индексируема" in доводы, (
        "module-level оболочка не умеет отдавать неиндексируемую страницу")
    assert доводы["индексируема"].default is True, (
        "по умолчанию страница остаётся индексируемой: признак закрывает "
        "служебный ответ, а не витрину")


def test_статическая_404_и_503_закрыты_в_коде():
    """Вызовы обработчика статики проверяются по тексту: он работает с запросом.

    Поведение самой оболочки проверено выше; здесь важно, что оба служебных
    ответа обработчика передают признак.
    """
    for тело, код in (("Страница не найдена.", "404"), ("Страница недоступна.", "503")):
        и = ТЕКСТ.index(f"'<div class=\"empty\">{тело}</div>', \"{код}\"")
        кусок = ТЕКСТ[и:и + 260]
        assert "индексируема=False" in кусок, (
            f"служебный ответ {код} статической выдачи наследует директиву витрины")
