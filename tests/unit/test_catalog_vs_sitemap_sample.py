"""Выборка по листалке и разбор ненайденных адресов.

Главное требование к классификации: отсутствие в карте само по себе потерей
НЕ является. Страницу с `noindex` наша сеть в карте не перечисляет
(правило сети, а не требование Яндекса), а страница, которая
не открылась, в потери не записывается без разбора.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "catalog-vs-sitemap-sample.py"

спец = importlib.util.spec_from_file_location("catalog_vs_sitemap", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


# --- выборка ---------------------------------------------------------------

def test_выборка_берёт_первую_и_последнюю():
    номера = модуль.выборка_страниц(2444, 40)
    assert номера[0] == 1
    assert номера[-1] == 2444


def test_выборка_детерминирована():
    # Два прогона обязаны взять одни и те же страницы, иначе их не сравнить.
    assert модуль.выборка_страниц(2444, 40) == модуль.выборка_страниц(2444, 40)


def test_выборка_равномерна_по_диапазону():
    номера = модуль.выборка_страниц(1000, 10)
    разрывы = [б - а for а, б in zip(номера, номера[1:])]
    assert max(разрывы) - min(разрывы) <= 1


def test_маленький_каталог_берётся_целиком():
    assert модуль.выборка_страниц(5, 40) == [1, 2, 3, 4, 5]


@pytest.mark.parametrize("всего,сколько", [(0, 10), (10, 0), (-3, 5)])
def test_бессмысленные_границы_дают_пустую_выборку(всего, сколько):
    assert модуль.выборка_страниц(всего, сколько) == []


def test_одна_страница_в_выборке():
    assert модуль.выборка_страниц(2444, 1) == [1]


# --- классификация ---------------------------------------------------------

def test_адрес_в_карте_названа():
    assert модуль.классифицировать("title/x", True, 200, "") == модуль.НАЗВАНА


def test_индексируемая_страница_вне_карты_это_потеря():
    assert модуль.классифицировать(
        "title/x", False, 200, "index, follow") == модуль.ПОТЕРЯ


def test_страница_без_метатега_тоже_индексируема():
    # Отсутствие директивы запретом не является.
    assert модуль.классифицировать("title/x", False, 200, "") == модуль.ПОТЕРЯ


def test_закрытая_страница_вне_карты_не_потеря():
    assert модуль.классифицировать(
        "title/x", False, 200, "noindex, follow") == модуль.ЗАКРЫТА
    assert модуль.классифицировать(
        "title/x", False, 200, "none") == модуль.ЗАКРЫТА


def test_не_открывшаяся_страница_отдельный_исход():
    assert модуль.классифицировать(
        "title/x", False, 404, "") == модуль.НЕ_ОТКРЫЛАСЬ
    assert модуль.классифицировать(
        "title/x", False, 0, "") == модуль.НЕ_ОТКРЫЛАСЬ


def test_nofollow_индексации_не_запрещает():
    assert модуль.классифицировать(
        "title/x", False, 200, "nofollow") == модуль.ПОТЕРЯ


def test_регистр_директивы_не_важен():
    assert модуль.классифицировать(
        "title/x", False, 200, "NoIndex") == модуль.ЗАКРЫТА


def test_в_карте_перевешивает_код_ответа():
    # Если адрес в карте есть, разбирать его страницу незачем.
    assert модуль.классифицировать("title/x", True, 500, "") == модуль.НАЗВАНА


# --- разбор разметки -------------------------------------------------------

def test_карточки_узнаются_по_трём_формам():
    тело = ('<a href="/title/alpha/">A</a><a href="/anime/beta">B</a>'
            '<a href="/film/gamma/">G</a><a href="/catalog/?page=2">2</a>')
    найдено = set(модуль.КАРТОЧКА.findall(тело))
    assert найдено == {"/title/alpha/", "/anime/beta", "/film/gamma/"}


def test_адрес_карты_с_параметром_не_карточка():
    тело = '<a href="/title/alpha/?season=2">A</a>'
    assert модуль.КАРТОЧКА.findall(тело) == []
