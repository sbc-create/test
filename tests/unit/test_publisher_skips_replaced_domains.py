"""Публикатор не обслуживает домены, которые владелец заменяет.

Измерено 2026-10-15: копии «до публикации» четырёх таких витрин занимали на
управляющем узле 6 271 МиБ и прибавляли ~390 МиБ в сутки — почти треть всего
суточного прироста. Сайтов по этим именам нет: делегирование снято реестром,
домены заменяются. Собирать и копировать для них данные незачем.

Проверяется текст таблицы и правило отбора, а не прогон: прогон публикует
боевые данные, и в проверках ему не место. Сам отбор — несколько строк, и
ошибка в них молча вернула бы четыре витрины в суточный прогон.
"""
import json
import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПУБЛИКАТОР = КОРЕНЬ / "automation" / "host" / "nova-catalog-publish.py"
ЗАМЕНЯЕМЫЕ = ("lords-06", "lords-07", "lords-08", "lords-09")


@pytest.fixture(scope="module")
def текст() -> str:
    return ПУБЛИКАТОР.read_text(encoding="utf-8")


def test_у_каждой_заменяемой_витрины_названа_причина(текст):
    for site_id in ЗАМЕНЯЕМЫЕ:
        м = re.search(rf'"{site_id}":\s*{{(.*?)}},', текст, re.S)
        assert м, f"витрины {site_id} нет в таблице публикатора"
        блок = м.group(1)
        assert "не_публикуется" in блок, f"{site_id}: ключ пропуска не стоит"
        assert "замены домена" in блок, f"{site_id}: причина не названа"


def test_отбор_по_умолчанию_пропускает_их(текст):
    """Отбор обязан читать ОБА ключа пропуска, а не один."""
    м = re.search(r"сайты = сайты or \[s for s in sorted\(ВИТРИНЫ\)(.*?)\]",
                  текст, re.S)
    assert м, "правило отбора не найдено"
    assert "пропущено" in м.group(1)
    объявление = текст[:м.start()]
    assert 'ВИТРИНЫ[s].get("не_публикуется")' in объявление
    assert 'ВИТРИНЫ[s].get("известный_дефект_шаблона")' in объявление


def test_пропуск_попадает_в_отчёт(текст):
    """Молчаливый пропуск неотличим от забытой витрины."""
    assert '"skipped": пропущено' in текст


def test_явный_список_сильнее_умолчания(текст):
    """Оператор вправе запустить прогон и по исключённой витрине."""
    assert "сайты = сайты or [" in текст, (
        "отбор перестал уважать явный список: исключение стало запретом")


def test_заменяемые_домены_совпадают_с_учётом():
    """Перечень не из головы: в реестре у них стоит отметка замены."""
    реестр = json.loads((КОРЕНЬ / "config" / "site-cells.json").read_text(encoding="utf-8"))
    помечены = {я["site_id"] for я in реестр["cells"]
                if "замены домена" in str((я.get("promotion") or {}).get("reason") or "")}
    assert помечены == set(ЗАМЕНЯЕМЫЕ), помечены
