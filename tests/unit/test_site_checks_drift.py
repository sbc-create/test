"""Расхождение проверок витрин с шаблонами: что считать опасным.

Главное решение этого инструмента: побайтовое расхождение дефектом НЕ
считается. Копию проверки могли осознанно приспособить под семейство, и
требовать совпадения байтов значило бы откатывать осмысленную работу. Опасно
ровно одно направление — копия проверяет МЕНЬШЕ шаблона: тогда ячейку судят по
более слабым правилам, чем объявляет фабрика, её собственная проверка зеленеет,
и этого никто не видит.

Поэтому сравнивается состав проверок, а не текст, и тесты закрепляют именно
матрицу исходов: слабее / иначе / богаче / совпадает.
"""
from __future__ import annotations

import importlib.util
import io
from contextlib import redirect_stdout
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "site-checks-drift.py"

ШАБЛОН = '''
плохо = []
if 1:
    плохо.append("первая проверка шаблона не прошла")
if 2:
    плохо.append(f"вторая проверка: {значение} не совпал с замком")
'''

#: Та же проверка, переписанная иначе, но с тем же составом: пробелы, порядок
#: и подстановки отличаются, а проверок столько же и те же.
ТОТ_ЖЕ_СОСТАВ = '''
плохо = []
if 2:
    плохо.append(f"вторая проверка: {другое_имя} не совпал с замком")
if 1:
    плохо.append("первая проверка шаблона не прошла")
'''

СЛАБЕЕ = '''
плохо = []
if 1:
    плохо.append("первая проверка шаблона не прошла")
'''

БОГАЧЕ = ШАБЛОН + '''
if 3:
    плохо.append("третья проверка, которой в шаблоне нет")
'''

ИНАЧЕ = '''
плохо = []
if 1:
    плохо.append("первая проверка шаблона не прошла")
if 3:
    плохо.append("третья проверка, которой в шаблоне нет")
'''


def _модуль():
    спец = importlib.util.spec_from_file_location("drift", ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


@pytest.fixture(scope="module")
def м():
    return _модуль()


def стенд(tmp_path: Path, копии: dict[str, str], *, шаблон: str = ШАБЛОН):
    шаблоны = tmp_path / "templates"
    шаблоны.mkdir(parents=True, exist_ok=True)
    (шаблоны / "проба.py").write_text(шаблон, encoding="utf-8")
    ячейки = tmp_path / "cells"
    for имя, текст in копии.items():
        каталог = ячейки / имя / "checks"
        каталог.mkdir(parents=True, exist_ok=True)
        (каталог / "проба.py").write_text(текст, encoding="utf-8")
    ячейки.mkdir(parents=True, exist_ok=True)
    return шаблоны, ячейки


def прогон(м, шаблоны: Path, ячейки: Path):
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        код = м.главное(["--templates", str(шаблоны), "--cells", str(ячейки)])
    return код, буфер.getvalue()


def test_ослабленная_копия_это_расхождение(м, tmp_path):
    код, вывод = прогон(м, *стенд(tmp_path, {"тихая": СЛАБЕЕ}))
    assert код == 1
    assert "СЛАБЕЕ у 1" in вывод
    assert "НЕ проверяет 1 из 2" in вывод
    assert "вторая проверка" in вывод


def test_тот_же_состав_иначе_написанный_это_не_расхождение(м, tmp_path):
    """Байты разные, проверок столько же и те же — судят одинаково."""
    код, вывод = прогон(м, *стенд(tmp_path, {"переписанная": ТОТ_ЖЕ_СОСТАВ}))
    assert код == 0
    assert "состав тот же у 1" in вывод
    assert "СЛАБЕЕ" not in вывод


def test_обогащённая_копия_это_замечание(м, tmp_path):
    """Копия проверяет больше — повод перенести в шаблон, а не отказ."""
    код, вывод = прогон(м, *стенд(tmp_path, {"строгая": БОГАЧЕ}))
    assert код == 0
    assert "богаче у 1" in вывод
    assert "на 1 больше" in вывод


def test_разошлась_в_обе_стороны_это_замечание_с_перечнем(м, tmp_path):
    код, вывод = прогон(м, *стенд(tmp_path, {"своя": ИНАЧЕ}))
    assert код == 0
    assert "иначе у 1" in вывод
    assert "нет в копии:" in вывод
    assert "только в копии:" in вывод


def test_ослабление_перебивает_обогащение(м, tmp_path):
    """Если копия что-то потеряла — это расхождение, сколько бы ни добавила."""
    код, вывод = прогон(м, *стенд(tmp_path, {"слабая": СЛАБЕЕ,
                                             "своя": ИНАЧЕ}))
    assert код == 1
    assert "СЛАБЕЕ у 1" in вывод


def test_битая_копия_не_роняет_и_называется(м, tmp_path):
    шаблоны, ячейки = стенд(tmp_path, {"битая": "def ("})
    код, вывод = прогон(м, шаблоны, ячейки)
    assert "не разобрана" in вывод
    assert "не разобрано: 1" in вывод
    assert код == 0, "неразобранный файл — не обвинение"


def test_сообщение_целиком_из_подстановок_не_сравнивается(м, tmp_path):
    """По такому сообщению проверку не опознать, и выдумывать расхождение нельзя.

    Подстановки выбрасываются нарочно: в них имена ячеек и цифры, и из-за них
    одна и та же проверка выглядела бы разной в каждом репозитории.
    """
    файл = tmp_path / "п.py"
    файл.write_text('плохо = []\nплохо.append(f"{имя}: {причина}")\n',
                    encoding="utf-8")
    найдено, причина = м.состав(файл)
    assert найдено == set(), найдено
    assert not причина


def test_подстановки_внутри_сообщения_не_мешают_опознать(м, tmp_path):
    """Литеральная часть остаётся — по ней проверка и опознаётся."""
    файл = tmp_path / "п.py"
    файл.write_text(
        'плохо = []\nплохо.append(f"{имя}: отпечаток не совпадает с замком")\n',
        encoding="utf-8")
    найдено, _причина = м.состав(файл)
    assert найдено == {": отпечаток не совпадает с замком"}, найдено


def test_нет_шаблонов_это_исход_два(м, tmp_path):
    пусто = tmp_path / "нет"
    пусто.mkdir()
    assert м.главное(["--templates", str(пусто), "--cells", str(пусто)]) == 2


def test_имя_проверки_можно_ограничить(м, tmp_path):
    шаблоны, ячейки = стенд(tmp_path, {"тихая": СЛАБЕЕ})
    (шаблоны / "другая.py").write_text(ШАБЛОН, encoding="utf-8")
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        м.главное(["--templates", str(шаблоны), "--cells", str(ячейки),
                   "--check", "другая.py"])
    assert "проба.py" not in буфер.getvalue()
    assert "проверок: 1" in буфер.getvalue()


#: Второй принятый способ сообщить отказ: печать в поток ошибок и выход 1.
ПЕЧАТЬЮ = '''
import sys
if 1:
    print("первая проверка шаблона не прошла", file=sys.stderr)
    sys.exit(1)
if 2:
    print(f"вторая проверка: {значение} не совпал с замком", file=sys.stderr)
    sys.exit(1)
'''


def test_отказ_печатью_в_поток_ошибок_тоже_проверка(м, tmp_path):
    """Способов сообщить отказ два, и признак обязан знать оба.

    Пока он знал только `плохо.append(...)`, шаблон `no_secrets.py` — он
    печатает отказ сразу в поток ошибок и выходит кодом 1 — выглядел как файл
    БЕЗ проверок, и копия объявлялась «богаче». Вывод «ослабленных копий нет»
    на таком пропуске держаться не может: шаблон с одним способом и копия с
    другим дали бы ложную тревогу или ложное спокойствие.
    """
    шаблоны, ячейки = стенд(tmp_path, {"списком": ТОТ_ЖЕ_СОСТАВ},
                            шаблон=ПЕЧАТЬЮ)
    код, вывод = прогон(м, шаблоны, ячейки)
    assert код == 0, вывод
    assert "состав тот же у 1" in вывод, вывод


def test_печать_не_в_поток_ошибок_проверкой_не_считается(м, tmp_path):
    """Обычный `print` — это отчёт о ходе, а не отказ."""
    файл = tmp_path / "п.py"
    файл.write_text('print("проверяем состав манифеста витрины")\n',
                    encoding="utf-8")
    найдено, _причина = м.состав(файл)
    assert найдено == set(), найдено


def test_в_итоге_названо_число_потерявших_проверки(м, tmp_path):
    """«Ослабленных ноль» без этого числа читается спокойнее, чем есть."""
    _код, вывод = прогон(м, *стенд(tmp_path, {"своя": ИНАЧЕ}))
    assert "потерявших хотя бы одну проверку шаблона: 1" in вывод


# --------------------------------------------------------------------------- #
#  Третий источник: копия, УСТАНОВЛЕННАЯ у исполнителя.
# --------------------------------------------------------------------------- #
def прогон3(м, шаблоны: Path, ячейки: Path, установленные: Path):
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        код = м.главное(["--templates", str(шаблоны), "--cells", str(ячейки),
                         "--installed", str(установленные)])
    return код, буфер.getvalue()


def test_отставшая_копия_исполнителя_называется(м, tmp_path):
    """«В дереве всё сошлось» и «выпуск пройдёт» — разные утверждения.

    Договор ячейки (`checks/deploy_request.py`) требует ПОБАЙТОВОГО совпадения
    с копией, установленной у исполнителя, а не с рабочим деревом. Обновление
    той копии — действие владельца по устройству: иначе запись в рабочий
    каталог равнялась бы исполнению от root.
    """
    шаблоны, ячейки = стенд(tmp_path, {"ячейка": ШАБЛОН})
    установленные = tmp_path / "installed"
    установленные.mkdir()
    (установленные / "проба.py").write_text(СЛАБЕЕ, encoding="utf-8")
    _код, вывод = прогон3(м, шаблоны, ячейки, установленные)
    assert "установленная копия отстала от дерева у 1" in вывод
    assert "действие ВЛАДЕЛЬЦА" in вывод
    assert "install-cell-executor.sh" in вывод


def test_копия_ячейки_мимо_установленной_называется(м, tmp_path):
    шаблоны, ячейки = стенд(tmp_path, {"ячейка": ТОТ_ЖЕ_СОСТАВ})
    установленные = tmp_path / "installed"
    установленные.mkdir()
    (установленные / "проба.py").write_text(ШАБЛОН, encoding="utf-8")
    _код, вывод = прогон3(м, шаблоны, ячейки, установленные)
    assert "не совпадающих побайтово с установленной: 1" in вывод
    assert "НИКТО не сторожит" in вывод


def test_побайтовое_совпадение_с_установленной_это_тишина(м, tmp_path):
    шаблоны, ячейки = стенд(tmp_path, {"ячейка": ШАБЛОН})
    установленные = tmp_path / "installed"
    установленные.mkdir()
    (установленные / "проба.py").write_text(ШАБЛОН, encoding="utf-8")
    _код, вывод = прогон3(м, шаблоны, ячейки, установленные)
    assert "совпадает с деревом по всем проверкам" in вывод
    assert "все копии ячеек совпадают с установленной побайтово" in вывод


def test_шаблон_без_копий_в_checks_всё_равно_сверяется_с_исполнителем(м, tmp_path):
    """Слепое пятно, найденное SEO-сессией 12.10.

    Сверка с установленной копией стояла ПОСЛЕ отсева «копий в `checks/` нет»,
    и `build_release.py` — он уезжает в ячейку как `tools/build_release.py` —
    не сверялся с исполнителем ВООБЩЕ: инструмент называл пять отставших
    шаблонов вместо шести. Слепое пятно в инструменте, созданном искать слепые
    пятна, поэтому проверка именно на этот порядок.
    """
    шаблоны = tmp_path / "templates"
    шаблоны.mkdir(parents=True)
    (шаблоны / "сборщик.py").write_text(ШАБЛОН, encoding="utf-8")
    ячейки = tmp_path / "cells"
    (ячейки / "витрина" / "tools").mkdir(parents=True)
    (ячейки / "витрина" / "tools" / "сборщик.py").write_text(
        ШАБЛОН, encoding="utf-8")
    установленные = tmp_path / "installed"
    установленные.mkdir()
    (установленные / "сборщик.py").write_text(СЛАБЕЕ, encoding="utf-8")

    _код, вывод = прогон3(м, шаблоны, ячейки, установленные)
    assert "установленная копия отстала от дерева у 1" in вывод, вывод
    # И копия из tools/ найдена: состав сверен, а не пропущен.
    assert "копий 1" in вывод, вывод


def test_нет_копии_исполнителя_это_не_проверено_а_не_порядок(м, tmp_path):
    """Отсутствие копии не значит «договор соблюдён»."""
    шаблоны, ячейки = стенд(tmp_path, {"ячейка": ШАБЛОН})
    _код, вывод = прогон3(м, шаблоны, ячейки, tmp_path / "нет-такого")
    assert "копия исполнителя не найдена" in вывод
    assert "не проверен" in вывод
