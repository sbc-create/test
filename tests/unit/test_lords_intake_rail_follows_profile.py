"""REQ-LORDS-INTAKE-DIRECTION: лента «Недавние поступления» следует направлению витрины.

Повод измерен 2026-10-17 на живых витринах K2. На сериальной `lordserial.su`
лента «Недавние поступления» совпадала с фильмовой `lordfilm.group` адрес в
адрес — 28 из 28 карточек, и внутри обеих было 22 фильма против 6 сериалов.
Заголовок обещал поступления витрины, а отбор брал общий пул кандидатов
главной, ничего не зная о профиле.

Проверяется СОСТАВ ленты, а не её наличие: наличие было и при дефекте.
Проверка опровержима — снятие `НАПРАВЛЕНИЕ_ЛЕНТЫ` из сборки главной её ломает.

Отдельно закреплён запас: витрина, у которой направленных записей меньше, чем
лента обещает, возвращается к общему пулу. Иначе молодой сериальный сайт
показывал бы ленту из четырёх карточек — обрубленную полку вместо ленты.
"""
from __future__ import annotations

import re

import pytest

from lords_runtime_harness import (Стенд, вид, выгрузить, загрузить, запись,
                                   подробность)


def _наполнение(фильмов: int, сериалов: int):
    """Каталог и боковой файл: `n` фильмов и `m` сериалов, все смотрибельные.

    Записи ЧЕРЕДУЮТСЯ. Рантайм отдаёт кандидатов в порядке снимка, и если
    сложить сначала все фильмы, а потом все сериалы, первые двадцать восемь
    кандидатов окажутся фильмами сами собой — измерено на первой версии этого
    стенда. Тогда отрицательный контроль ниже падал бы из-за порядка укладки,
    а не из-за поведения витрины.
    """
    записи, детали = [], []
    фильм = сериал = 0
    while фильм < фильмов or сериал < сериалов:
        if фильм < фильмов:
            slug = f"film-{фильм:03d}"
            записи.append(запись(slug, title=f"Фильм {фильм}", kind="Фильм",
                                 year=2020 + фильм % 6))
            детали.append(подробность(slug, type_="movie", genres=("Драма",)))
            фильм += 1
        if сериал < сериалов:
            slug = f"serial-{сериал:03d}"
            записи.append(запись(slug, title=f"Сериал {сериал}", kind="Сериал",
                                 year=2020 + сериал % 6))
            детали.append(подробность(slug, type_="tv", genres=("Драма",)))
            сериал += 1
    return записи, детали


def _лента(html: str) -> list[str]:
    """Слуги карточек ленты поступлений в порядке разметки."""
    начало = html.find('data-shelf="intake"')
    if начало < 0:
        return []
    конец = html.find("</section>", начало)
    return re.findall(r'href="/title/([^/"]+)/"', html[начало:конец])


def _главная(tmp_path, monkeypatch, профиль: str, фильмов: int, сериалов: int):
    """Модуль рантайма на своём стенде и слуги ленты его главной."""
    стенд = Стенд(tmp_path, профиль=профиль)
    записи, детали = _наполнение(фильмов, сериалов)
    стенд.записать_каталог(записи)
    стенд.записать_подробности(детали)
    стенд.записать_плеер()
    модуль = загрузить(стенд, monkeypatch)
    try:
        представление = вид(модуль)
        return модуль, представление, _лента(представление.главная())
    except BaseException:
        выгрузить(модуль)
        raise


@pytest.mark.parametrize("профиль,дизайн,ожидаемый_вид", [
    ("lords-serials", "lords-serials-v2", "serial-"),
    ("lords-films", "lords-films-v2", "film-"),
])
def test_лента_направленной_витрины_состоит_из_её_раздела(
        tmp_path, monkeypatch, профиль, дизайн, ожидаемый_вид):
    модуль, представление, слуги = _главная(
        tmp_path, monkeypatch, профиль, 40, 40)
    try:
        assert модуль.ДИЗАЙН_ID == дизайн
        assert len(слуги) == представление.ЛЕНТА_ПОСТУПЛЕНИЙ, (
            f"лента не собралась: карточек {len(слуги)}")
        чужие = [с for с in слуги if not с.startswith(ожидаемый_вид)]
        assert not чужие, f"в ленте {профиль} посторонние записи: {чужие[:5]}"
    finally:
        выгрузить(модуль)


def test_общий_каталог_ленту_не_сужает(tmp_path, monkeypatch):
    """Отрицательный контроль: у профиля без направления лента прежняя.

    Без него проверка выше прошла бы и на правке, которая сузила бы ленту у
    всех витрин семейства — а у общего каталога поступления и есть общие.
    """
    модуль, представление, слуги = _главная(
        tmp_path, monkeypatch, "lords-general", 40, 40)
    try:
        assert модуль.ДИЗАЙН_ID == "lords-cinema-v2"
        assert "lords-cinema-v2" not in модуль.НАПРАВЛЕНИЕ_ЛЕНТЫ
        assert len(слуги) == представление.ЛЕНТА_ПОСТУПЛЕНИЙ
        виды = {"film" if с.startswith("film-") else "serial" for с in слуги}
        assert виды == {"film", "serial"}, (
            f"лента общего каталога оказалась односоставной: {sorted(виды)}")
    finally:
        выгрузить(модуль)


def test_нехватка_направленных_записей_возвращает_общий_пул(tmp_path, monkeypatch):
    """Запас: сериалов меньше, чем обещает лента — лента остаётся полной.

    28 обещанных карточек против 10 сериалов. Сужение здесь дало бы ленту из
    десяти, то есть обрубленную полку под заголовком «Недавние поступления».
    """
    модуль, представление, слуги = _главная(
        tmp_path, monkeypatch, "lords-serials", 60, 10)
    try:
        assert len(слуги) == представление.ЛЕНТА_ПОСТУПЛЕНИЙ, (
            f"лента обрублена до {len(слуги)} карточек")
    finally:
        выгрузить(модуль)
