"""Порядок запуска проверок: правила закреплены, а не только описаны.

Повод — измеренный расход GitHub Actions за 48 часов 11–13.10 (минуты
восстановлены по заданиям, округление вверх до минуты, только раннеры
GitHub; поле `billable` этому токену возвращает 0 и потому не используется):

    закрытые репозитории (тратят квоту)   4 143 мин = 2 072 мин/сутки
      ott-app-sandbox:CI                  2 982 мин   72 %
      21 ячейка site-*:release            1 161 мин   28 %
    открытый sbc-create/test (бесплатно)    276 мин

    по причине запуска: workflow_dispatch 2 783 мин при 39 прогонах,
                        push 1 158 при 297, pull_request 475 при 158
    по исходу:          failure 2 741 мин — больше половины минут ушло
                        в прогоны, которые не дали зелёного ответа
    повторная проверка одной версии: 39 групп, 42 лишних прогона, 230 мин

Состав одного прогона ячейки (38326498490): `checks/run.sh` 183 с из 190 с
всего; `build_release.py` — 0 с. Поэтому разделение на «быстрое» и «полное»
задание здесь ничего не экономит, и экономия идёт только с ЧИСЛА прогонов.

Эти проверки держат три свойства шаблона ячейки, каждое из которых умеет
провалиться: правка документации проверок не запускает, вытесненный коммит
не доверяется, у задания есть предел времени.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]


def _шаблон() -> str:
    if str(КОРЕНЬ) not in sys.path:
        sys.path.insert(0, str(КОРЕНЬ))
    спец = importlib.util.spec_from_file_location(
        "cell_extract_policy", КОРЕНЬ / "factory" / "cell" / "extract.py")
    м = importlib.util.module_from_spec(спец)
    sys.modules["cell_extract_policy"] = м
    спец.loader.exec_module(м)
    return м.CI_WORKFLOW.format(domain="пример.site", site_id="lords-02")


@pytest.fixture(scope="module")
def текст() -> str:
    return _шаблон()


@pytest.fixture(scope="module")
def разобран(текст: str) -> dict:
    yaml = pytest.importorskip("yaml")
    # В YAML 1.1 ключ `on` разбирается как булево True — свойство PyYAML, а не
    # файла: GitHub читает его как строку. Поэтому ключ берётся по значению.
    return yaml.safe_load(текст)


def _триггеры(разобран: dict) -> dict:
    for ключ in (True, "on"):
        if ключ in разобран:
            return разобран[ключ]
    raise AssertionError("в шаблоне нет блока триггеров")


def test_правка_документации_проверок_не_запускает(разобран):
    """Коммит в docs/ или .md не должен стоить четырёх минут квоты."""
    т = _триггеры(разобран)
    for событие in ("push", "pull_request"):
        игнор = т[событие].get("paths-ignore") or []
        assert "docs/**" in игнор, f"{событие}: docs/** не исключён"
        assert "**/*.md" in игнор, f"{событие}: файлы .md не исключены"
        assert "reports/**" in игнор, f"{событие}: reports/** не исключён"


def test_вытесненный_коммит_не_доверяется(разобран):
    """На рабочей ветви новый коммит обязан отменять прежний прогон."""
    c = разобран["concurrency"]
    assert "github.ref" in c["group"], (
        "группа без ветви: прогоны разных ветвей встанут в очередь друг за "
        "другом вместо параллельной работы")
    отмена = str(c["cancel-in-progress"])
    assert "github.ref" in отмена and "refs/heads/main" in отмена, (
        "отмена должна зависеть от ветви: на рабочей — да, на main — нет")


def test_на_main_отмена_выключена(разобран):
    """Приёмку перед выпуском обрывать нельзя."""
    отмена = str(разобран["concurrency"]["cancel-in-progress"])
    assert "!=" in отмена, (
        "выражение должно ВЫКЛЮЧАТЬ отмену на main, а не включать её")


def test_у_задания_есть_предел_времени(разобран):
    """Без предела зависшее задание списывает минуты до шести часов."""
    предел = разобран["jobs"]["release"].get("timeout-minutes")
    assert предел, "timeout-minutes не задан"
    assert 5 <= предел <= 30, (
        f"предел {предел} мин не соответствует измеренной длительности "
        "(около 4 мин): слишком тесно или слишком широко")


def test_pull_request_не_повторяет_push(разобран):
    """Каждый push в ветвь PR уже проверен; второй прогон — плата за ответ."""
    типы = _триггеры(разобран)["pull_request"].get("types") or []
    assert типы, "без types прогон пойдёт на каждый synchronize"
    assert "synchronize" not in типы, (
        "synchronize повторяет то, что уже проверил триггер push")
    assert "opened" in типы


def test_push_по_прежнему_покрывает_рабочие_ветви(разобран):
    """Сокращение не должно превратиться в «CI не запускается никогда»."""
    ветви = _триггеры(разобран)["push"].get("branches") or []
    assert "main" in ветви
    assert any("claude" in в for в in ветви), (
        "рабочие ветви должны оставаться под проверкой: иначе затвор исчезает")


def test_ручной_запуск_сохранён(разобран):
    assert "workflow_dispatch" in _триггеры(разобран)


def test_проверки_и_сборка_остались_в_одном_задании(разобран):
    """Измерено: build_release.py занимает 0 с, второй checkout дороже.

    Разделение на задания здесь не экономит, и проверка держит это решение:
    если задания разведут, кто-то должен будет заново измерить и объяснить.
    """
    задания = разобран["jobs"]
    assert list(задания) == ["release"], (
        f"заданий стало {list(задания)}: разделение требует нового замера, "
        "потому что сборка артефакта измерена как бесплатная")


def test_шаги_приёмки_сохранены(текст):
    """Сокращение расхода не отменяет обязательных проверок выпуска."""
    for шаг in ("./checks/run.sh",
                "конфигурация описывает",
                "tools/build_release.py",
                "upload-artifact"):
        assert шаг in текст, f"пропал обязательный шаг: {шаг}"
