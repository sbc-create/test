# --- T286 и T287: подборки Zona ----------------------------------------------
#
# Решение по T286 состоит из ДВУХ частей: убрать подборку из раздела И
# поправить число в описании. Половина правки оставила бы раздел обещающим то,
# чего нет, поэтому признак требует обе части.
#
# У T287 признак — пересечение по АДРЕСАМ, а не по числу карточек: одинаковое
# число у двух подборок ничего не значит. Порог 30 % взят из приёмки передачи
# SEO; измеренное состояние до правки — 80 %.

def _раздел(ключи, объявлено):
    ссылки = "".join(f'<a href="/collection/{к}/">x</a>' for к in ключи)
    return (f'<html><body><p>Подборки на Zona: {объявлено} подборок —'
            f' тематические списки.</p>{ссылки}</body></html>' + ПОДВАЛ)


ВОСЕМЬ = ["recently_added", "recently_added_movies", "new_movie_releases",
          "new_series_releases", "new_episodes", "top_rated", "current_season",
          "video_available"]


def test_t286_до_выпуска_живо(monkeypatch):
    _подменить(monkeypatch, _раздел(ВОСЕМЬ, 8))
    исход, подробно = ИНСТР.измерить("T286", "https://x/")
    assert исход == "ЖИВО"
    assert "video_available в разделе" in подробно


def test_t286_после_выпуска_закрыто(monkeypatch):
    """Положительный контроль: подборка убрана И число поправлено."""
    _подменить(monkeypatch, _раздел(ВОСЕМЬ[:-1], 7))
    исход, подробно = ИНСТР.измерить("T286", "https://x/")
    assert исход == "ЗАКРЫТО"
    assert "убрана" in подробно


def test_t286_половина_правки_не_принимается(monkeypatch):
    """Отрицательный контроль: ссылку убрали, число не поправили."""
    _подменить(monkeypatch, _раздел(ВОСЕМЬ[:-1], 8))
    исход, подробно = ИНСТР.измерить("T286", "https://x/")
    assert исход == "ЖИВО"
    assert "объявляет 8" in подробно and "ссылок 7" in подробно


def test_t286_без_числа_не_измерено(monkeypatch):
    ссылки = "".join(f'<a href="/collection/{к}/">x</a>' for к in ВОСЕМЬ)
    _подменить(monkeypatch, f"<html><body>{ссылки}</body></html>" + ПОДВАЛ)
    исход, подробно = ИНСТР.измерить("T286", "https://x/")
    assert исход == "НЕ ИЗМЕРЕНО"
    assert "нет числа подборок" in подробно


def _две_подборки(monkeypatch, общая, фильмовая):
    def достать(url, **к):
        тело = (_страница_подборки(фильмовая) if "movies" in url
                else _страница_подборки(общая))
        return 200, тело
    monkeypatch.setattr(ИНСТР, "достать", достать)


def _страница_подборки(пути):
    ссылки = "".join(f'<a href="{п}">x</a>' for п in пути)
    return f"<html><body>{ссылки}</body></html>" + ПОДВАЛ


def test_t287_до_выпуска_живо(monkeypatch):
    общие = [f"/title/t{n}/" for n in range(10)]
    _две_подборки(monkeypatch, общие, общие[:9] + ["/title/z/"])
    исход, подробно = ИНСТР.измерить("T287", "https://x/collection/recently_added/")
    assert исход == "ЖИВО"
    assert "90.0 %" in подробно


def test_t287_после_выпуска_закрыто(monkeypatch):
    """Положительный контроль: чередование видов развело первые страницы."""
    _две_подборки(monkeypatch, [f"/title/t{n}/" for n in range(10)],
                  [f"/title/t{n}/" for n in range(2)]
                  + [f"/title/u{n}/" for n in range(8)])
    исход, подробно = ИНСТР.измерить("T287", "https://x/collection/recently_added/")
    assert исход == "ЗАКРЫТО"
    assert "20.0 %" in подробно


def test_t287_пустая_подборка_не_измерено(monkeypatch):
    _две_подборки(monkeypatch, [f"/title/t{n}/" for n in range(10)], [])
    исход, подробно = ИНСТР.измерить("T287", "https://x/collection/recently_added/")
    assert исход == "НЕ ИЗМЕРЕНО"
    assert "пуста" in подробно
