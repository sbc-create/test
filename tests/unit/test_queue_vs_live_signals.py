"""Признаки живой приёмки T283 и T284 в queue-vs-live.

Признак здесь обратный обычному: «ЖИВО» означает, что правка ещё НЕ вышла,
«ЗАКРЫТО» — что вышла. Поэтому проверяются оба исхода: признак, умеющий только
«ЖИВО», ничего не докажет после выпуска.

Отрицательные контроли, названные заранее:

* подписей оценок на странице нет вовсе → «НЕ ИЗМЕРЕНО», а не «ЗАКРЫТО»:
  иначе сломанная разметка читалась бы как выполненная правка;
* годов в ведущей полке нет → «НЕ ИЗМЕРЕНО». Ровно эта ошибка и случилась
  20.10: год лежит в подписи `zt__m` вместе со страной, а шаблон искал span с
  одним числом, и инструмент печатал «НЕ ИЗМЕРЕНО» на витрине, где годы есть;
* неизвестный идентификатор в `--only` → отказ с перечнем, а не KeyError.

Сеть не используется: `достать` подменяется.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "queue_vs_live", КОРЕНЬ / "automation/local/queue-vs-live.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

ПОДВАЛ = "x" * 300  # страница должна быть длиннее порога 200 байт


def _подменить(monkeypatch, тело: str, код: int = 200):
    monkeypatch.setattr(ИНСТР, "достать", lambda url, **к: (код, тело))


# --- T283: голоса в подписях оценок карточек ---------------------------------

БЕЗ_ГОЛОСОВ = ('<a class="zt"><span title="IMDb 9.4 из 10">9.4</span></a>'
               '<a class="zt"><span title="IMDb 9.2 из 10">9.2</span></a>'
               + ПОДВАЛ)
С_ГОЛОСАМИ = ('<a class="zt"><span title="IMDb 9.4 из 10, 5 голосов">9.4</span></a>'
              '<a class="zt"><span title="IMDb 9.2 из 10, 47 голосов">9.2</span></a>'
              + ПОДВАЛ)


def test_t283_до_выпуска_живо(monkeypatch):
    _подменить(monkeypatch, БЕЗ_ГОЛОСОВ)
    исход, подробно = ИНСТР.измерить("T283", "https://x/")
    assert исход == "ЖИВО"
    assert "0 из 2" in подробно


def test_t283_после_выпуска_закрыто(monkeypatch):
    """Положительный контроль: признак обязан увидеть выпуск."""
    _подменить(monkeypatch, С_ГОЛОСАМИ)
    исход, подробно = ИНСТР.измерить("T283", "https://x/")
    assert исход == "ЗАКРЫТО"
    assert "2 из 2" in подробно


def test_t283_без_подписей_не_измерено(monkeypatch):
    _подменить(monkeypatch, '<a class="zt">карточка без оценки</a>' + ПОДВАЛ)
    исход, подробно = ИНСТР.измерить("T283", "https://x/")
    assert исход == "НЕ ИЗМЕРЕНО"
    assert "подписей оценок" in подробно


def test_t283_страница_не_ответила_не_измерено(monkeypatch):
    _подменить(monkeypatch, "", код=503)
    assert ИНСТР.измерить("T283", "https://x/")[0] == "НЕ ИЗМЕРЕНО"


# --- T284: возраст карточек ведущей полки ------------------------------------

def _полка(годы, заголовок="Сейчас на Zona"):
    карточки = "".join(
        f'<a class="zt"><span class="zt__m">{г} · Аргентина</span></a>'
        for г in годы)
    return (f'<h1 class="zh">{заголовок}</h1><div class="zrl--hero">'
            f'{карточки}</div><h2>Высокие оценки недели</h2>'
            f'<a class="zt"><span class="zt__m">1971 · Италия</span></a>'
            + ПОДВАЛ)


def test_t284_до_выпуска_живо(monkeypatch):
    _подменить(monkeypatch, _полка([1920, 2013, 2025, 2026]))
    исход, подробно = ИНСТР.измерить("T284", "https://x/")
    assert исход == "ЖИВО"
    assert "2 из 4" in подробно


def test_t284_после_выпуска_закрыто(monkeypatch):
    """Положительный контроль: в полке новинок старых работ не остаётся."""
    _подменить(monkeypatch, _полка([2025, 2026, 2026]))
    assert ИНСТР.измерить("T284", "https://x/")[0] == "ЗАКРЫТО"


def test_t284_соседняя_полка_в_счёт_не_идёт(monkeypatch):
    """Отрицательный контроль: 1971 из «Высоких оценок» не должен попасть."""
    _подменить(monkeypatch, _полка([2025, 2026]))
    исход, подробно = ИНСТР.измерить("T284", "https://x/")
    assert исход == "ЗАКРЫТО"
    assert "из 2" in подробно


def test_t284_без_годов_не_измерено(monkeypatch):
    _подменить(monkeypatch, '<h1>Сейчас на Zona</h1><a class="zt">нет года</a>'
               + ПОДВАЛ)
    исход, подробно = ИНСТР.измерить("T284", "https://x/")
    assert исход == "НЕ ИЗМЕРЕНО"
    assert "годов" in подробно


def test_t284_год_в_подписи_со_страной_находится(monkeypatch):
    """Ошибка 20.10: год лежит в zt__m вместе со страной, а не отдельным span."""
    _подменить(monkeypatch, _полка([2013]))
    assert ИНСТР.измерить("T284", "https://x/")[0] == "ЖИВО"


def test_t284_полки_нет_не_измерено(monkeypatch):
    _подменить(monkeypatch, _полка([2013], заголовок="Другая полка"))
    assert ИНСТР.измерить("T284", "https://x/")[0] == "НЕ ИЗМЕРЕНО"


