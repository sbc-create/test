# --- индексируемый фильтр обязан быть self-canonical ----------------------
#
# §3 п.1 дословно: «Фильтр становится индексируемым лишь при подтверждённом
# назначении, стабильном URL, уникальном переданном контенте, self-canonical и
# внутренних ссылках». Отсюда два следствия, и ни одно не очевидно:
#
# * требовать от рабочего фильтра ИНДЕКСИРУЕМОСТИ нельзя — по п.2 её по
#   умолчанию нет, и noindex у комбинации норма, а не поломка. Первая редакция
#   моей пробы требовала индексируемости и была неправа;
# * но если страница ВСЁ-ТАКИ индексируемая, её canonical обязан вести на тот
#   же состав. Измерено у AnimeGo: ?genre=drama self-canonical, а ?yf=2026 при
#   той же индексируемости канонизирован на /catalog/, где общих карточек НОЛЬ
#   из 24. Несогласие внутри одной витрины, и видно оно только если мерить оба.

КАТАЛОГ_С_ФОРМОЙ = ('<html>'
                    '<select name="yf"><option value="2026">2026</option></select>'
                    '<a href="/year/2026/">2026</a>'
                    '<a href="/year/2025/">2025</a></html>')


def test_рабочий_фильтр_под_noindex_нормален():
    """Требовать индексируемости нельзя: §3 п.2 её по умолчанию не даёт."""
    закрытый = ("200", '<meta name="robots" content="noindex, follow">'
                + "".join(f'<a href="/title/d-{i}">' for i in range(48)))
