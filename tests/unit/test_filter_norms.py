"""§3 п.3-4: пустые, неизвестные и повторяющиеся фильтры.

Норма замороженной базы дословно:

* п.3 «Порядок параметров нормализуется; повторяющиеся и неизвестные ключи
  запрещены — это предотвращает комбинаторный взрыв URL»;
* п.4 «Пустые категории/теги/фильтры не публикуются как indexable 200».

Направление назвала SEO-сессия 11.10: она измерила 19 нарушений п.4 и закрыла
их на семи витринах. Проверяя её выкладки, я заметил, что в п.3 названы ТРИ
вещи, а измерялась одна — неизвестное ЗНАЧЕНИЕ. Неизвестный КЛЮЧ
(`?nosuchkey=1`) и ПОВТОР ключа (`?genre=drama&genre=komediya`) не мерил никто,
и оба отдают индексируемую двухсотку с полным каталогом на всех двенадцати
витринах. Именно они дают комбинаторный взрыв, от которого норма защищает:
пустой фильтр добавляет один лишний адрес, неизвестный ключ — сколько угодно.

Два решения в мере, оба — чтобы мерить норму, а не чужую реализацию:

* **404 не обязателен.** Норма запрещает не двухсотку, а ИНДЕКСИРУЕМУЮ
  двухсотку: `noindex` при 200 ей соответствует. SEO-сессия выбрала 404 —
  выбор годный и более строгий, но требовать именно его значило бы требовать
  чужое решение;
* **год берётся из витрины.** Подставить «1066» было бы догадкой: у витрины
  может оказаться и такой год. Читается её собственный список годов, берётся
  первый свободный из заведомо старых.

Отдельно закреплена ошибка, которую я почти сообщил как регресс: `?sort=new`
на выложенных Lords отдаёт 404, и это выглядело как «правка задела годную
сортировку». Разметка показала, что витрина предлагает только date, title,
year и rating — значит `new` это неизвестное значение, и 404 верен. Все
четыре годные сортировки отвечают 200 и дают ЧЕТЫРЕ различных порядка.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

ПУСТО = "<html></html>"


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    def __init__(self, таблица: dict, по_умолчанию=("404", ПУСТО)):
        self.таблица = таблица
        self.по_умолчанию = по_умолчанию
        self.запрошено: list[str] = []

    def __call__(self, url: str, таймаут: int = 45):
        self.запрошено.append(url)
        запись = self.таблица.get(url)
        if запись is None:
            код, тело = self.по_умолчанию
            заг = {}
        elif len(запись) == 3:
            код, тело, заг = запись
        else:
            код, тело = запись
            заг = {}
        return код, тело, {**заг, "итоговый-адрес": url}


