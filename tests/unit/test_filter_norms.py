def прогнать(таблица: dict, строгие_фильтры=(), строгие_ключи=()):
    м = _модуль()
    м.ФИЛЬТРЫ_СТРОГО = строгие_фильтры
    м.КЛЮЧИ_СТРОГО = строгие_ключи
    полная = {КАТАЛОГ: ("200", "<html>каталог</html>")}
    полная.update(таблица)
    м.достать = Сеть(полная)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_фильтров("x-proba.ru", lambda и, ок, п: шаги.append((и, ок, п)))
    return шаги


def найти(шаги, часть: str):
    подходящие = [ш for ш in шаги if часть in ш[0]]
    assert len(подходящие) == 1, [ш[0] for ш in шаги]
    return подходящие[0]


