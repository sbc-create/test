"""REQ-CELL-VISITOR-COOKIE: кука посетителя — только там, где есть формы.

Измерено 2026-10-18 на `lordserial.su` (витрина K2):

    каждая страница отдаёт `Set-Cookie: lords_13_v=…; Max-Age=31536000`
    и `Cache-Control: no-store`;
    на странице произведения: форм сообщества 0, полей токена 0, блоков
    комментариев 0, звёзд оценки 0, маршрутов сообщества 0.

Причина — в порядке проверок: настройка сообщества задана, модуль хранилища
нет, поэтому `подключён()` False и формы не рисуются, а
`подготовить_посетителя` смотрел только на настройку и куку выдавал.

Почему это не косметика: общий кеш не имеет права хранить ответ с
`Set-Cookie`, то есть одно это поле держало `no-store` на всех страницах
витрины, у которой нечему быть персональным. Запись R-17 — про то же на
четырёх других витринах сети.

Документированная причина выдачи куки на ЛЮБОМ ответе («иначе посетитель,
пришедший сразу на страницу произведения, получал форму с пустым токеном»)
сохраняется там, где формы есть.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "host"
        / "community_http.py")


@pytest.fixture()
def мод():
    спец = importlib.util.spec_from_file_location("community_http_под_тест", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["community_http_под_тест"] = м
    try:
        спец.loader.exec_module(м)
        yield м
    finally:
        sys.modules.pop("community_http_под_тест", None)


class _Обработчик:
    def __init__(self, куки: str = ""):
        self.headers = {"Cookie": куки} if куки else {}


def test_без_настройки_куки_нет(мод):
    о = _Обработчик()
    мод.НАСТРОЙКА = None
    мод.подготовить_посетителя(о)
    assert not hasattr(о, "_новая_кука")
    assert мод.заголовок_куки(о) == ""


def test_настройка_есть_а_модуля_нет_куки_нет(мод):
    """Ровно измеренное состояние витрин K2: формы невозможны, кука выдавалась."""
    class Н:
        кука_посетителя = "lords_13_v"
        путь_env = "LORDS_COMMUNITY_PATH"
        site_id = "lords-13"
    мод.НАСТРОЙКА = Н()
    мод.МОДУЛЬ = None
    assert мод.подключён() is False, "предпосылка теста не выполнена"
    о = _Обработчик()
    мод.подготовить_посетителя(о)
    assert мод.заголовок_куки(о) == "", (
        "кука выдаётся там, где ни одной формы сообщества быть не может")


def test_когда_сообщество_подключено_кука_выдаётся(мод):
    """Отрицательный контроль: правка не должна сломать витрины с формами.

    Там причина выдачи куки на любом ответе остаётся в силе — иначе первая
    отправка формы отбивается как подделка.
    """
    class Н:
        кука_посетителя = "lords_02_v"
        путь_env = "LORDS_COMMUNITY_PATH"
        site_id = "lords-02"
    мод.НАСТРОЙКА = Н()
    мод.МОДУЛЬ = object()
    assert мод.подключён() is True, "предпосылка теста не выполнена"
    о = _Обработчик()
    мод.подготовить_посетителя(о)
    заголовок = мод.заголовок_куки(о)
    assert заголовок.startswith("lords_02_v=")
    assert "Max-Age=31536000" in заголовок
    assert "HttpOnly" in заголовок and "SameSite=Lax" in заголовок


def test_у_пришедшего_с_кукой_новая_не_выдаётся(мод):
    """Иначе каждый ответ переписывал бы куку и кеш был бы невозможен всегда."""
    class Н:
        кука_посетителя = "lords_02_v"
        путь_env = "LORDS_COMMUNITY_PATH"
        site_id = "lords-02"
    мод.НАСТРОЙКА = Н()
    мод.МОДУЛЬ = object()
    о = _Обработчик("lords_02_v=уже-есть")
    мод.подготовить_посетителя(о)
    assert мод.заголовок_куки(о) == ""
    assert о._куки_посетителя == "уже-есть"
