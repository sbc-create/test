"""Числа в названии произведения — не даты. Ворота качества, ложное срабатывание.

Измерено 2026-10-20 на `povelitel-demonov-2099` (animeg0.site). Ворота требовали
назвать произведение («в тексте нет названия тайтла»). Как только название
появилось в тексте, те же ворота объявили «2099» неподтверждённой датой — и
материал стало нельзя опубликовать ни с названием, ни без него. Это ложное
срабатывание, а не строгость: 2099 стоит в поле `name` того же снимка, с
которым идёт сверка.

Проверяется обе стороны, иначе правка была бы послаблением:

* число из названия больше не делает текст непроходным;
* настоящая лишняя дата по-прежнему ловится;
* требование назвать год снимка не ослаблено;
* требование назвать произведение не ослаблено.
"""
from __future__ import annotations

import importlib.util
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
if str(КОРЕНЬ) not in sys.path:
    sys.path.insert(0, str(КОРЕНЬ))
_с = importlib.util.spec_from_file_location(
    "qwen_editorial_digits", КОРЕНЬ / "factory/qwen/editorial.py")
ED = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ED)

ФАКТЫ = {"facts": {"name": "Повелитель демонов 2099", "year": 2024}}
ОСНОВА = ("«Повелитель демонов 2099» (Demon Lord 2099) — телесериал 2024 года. "
          "Пятьсот лет назад в мире Алнис герой смертных Грэм победил Владыку "
          "Демонов Велтола, а спустя пять веков его возвращают к жизни в "
          "техномагическом Синдзюку.")


def test_число_названия_не_считается_лишней_датой():
    беды = ED.проверить_материал(ОСНОВА, ФАКТЫ)
    assert беды == [], беды


def test_настоящая_лишняя_дата_ловится():
    """Отрицательный контроль: правка не должна глушить реальную проверку."""
    текст = ОСНОВА + " Первый сезон вышел в 1999 году."
    беды = ED.проверить_материал(текст, ФАКТЫ)
    assert any("лишние даты не подтверждены" in б for б in беды), беды
    assert any("1999" in б for б in беды), беды


def test_в_сообщении_названы_числа_названия():
    текст = ОСНОВА + " Продолжение обещают в 2031 году."
    беды = [б for б in ED.проверить_материал(текст, ФАКТЫ)
            if "лишние даты" in б]
    assert беды
    assert "[2099]" in беды[0]


def test_требование_назвать_год_снимка_не_ослаблено():
    текст = ("«Повелитель демонов 2099» — телесериал про Велтола, которого "
             "возвращают к жизни в техномагическом Синдзюку спустя пять веков "
             "после его гибели от руки героя смертных.")
    беды = ED.проверить_материал(текст, ФАКТЫ)
    assert any("нет года 2024" in б for б in беды), беды


def test_требование_назвать_произведение_не_ослаблено():
    текст = ("Телесериал 2024 года про Велтола, которого возвращают к жизни в "
             "техномагическом Синдзюку спустя пять веков после его гибели от "
             "руки героя смертных по имени Грэм.")
    беды = ED.проверить_материал(текст, ФАКТЫ)
    assert any("нет названия тайтла" in б for б in беды), беды


def test_без_чисел_в_названии_поведение_прежнее():
    факты = {"facts": {"name": "Рейтинг короля", "year": 2022}}
    текст = ("«Рейтинг короля» — телесериал 2022 года о принце Бодже, которого "
             "не принимают всерьёз, и о его дружбе с тенью по имени Кагэ.")
    assert ED.проверить_материал(текст, факты) == []
    беды = ED.проверить_материал(текст + " Ремейк выйдет в 2035 году.", факты)
    assert any("лишние даты" in б for б in беды)
    assert "числа названия" not in " ".join(беды)
