"""Порядок и запреты в `k2-release-code.sh`: выпуск кода не имеет права на данные.

Сценарий исполняется от root на узле восьми витрин. Четыре его свойства нельзя
потерять при будущей правке, и каждое оплачено измерением:

* **данные витрины он не трогает вовсе.** `k2-launch-site.sh` переустанавливает
  `stage/data/<site>` — для первого запуска это доставка, для правки в коде это
  потеря: рядом со снимком лежат наложение проверенных номеров серий
  (`*.nums.json`) и редакционные правки, и комплект доставки их не содержит.
  Правило — `docs/RUNTIME_DATA_OWNERSHIP.md`;
* **`config/player.json` переносится из ТЕКУЩЕГО выпуска.** В git его нет, он
  несёт publisher_id, и без него служба намеренно не стартует. Брать его из
  комплекта значило бы зависеть от того, что комплект ещё на узле;
* **ссылка переключается ПОСЛЕ сборки выпуска и возвращается при неудаче.**
  Иначе витрина остаётся на каталоге, которого нет, или на выпуске, который не
  поднялся;
* **повторный запуск безопасен**: совпадение головы — выход без изменений.

Проверяется текст сценария: прогон требует root, узла и живого бандла. Так же
проверяются остальные host-сценарии этого репозитория.
"""
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "host" / "k2-release-code.sh"


@pytest.fixture(scope="module")
def текст() -> str:
    assert СЦЕНАРИЙ.is_file(), f"нет {СЦЕНАРИЙ}"
    return СЦЕНАРИЙ.read_text(encoding="utf-8")


def место(текст: str, кусок: str) -> int:
    и = текст.find(кусок)
    assert и >= 0, f"в сценарии нет {кусок!r}"
    return и


def без_комментариев(текст: str) -> str:
    """Только исполняемые строки: запрет проверяется по делу, а не по тексту.

    Первая редакция проверки падала на самом объяснении запрета в шапке
    сценария — то есть требовала не упоминать то, о чём обязана предупредить.
    """
    строки = [с for с in текст.splitlines() if not с.lstrip().startswith("#")]
    return "\n".join(строки)


def test_данные_витрины_не_переустанавливаются(текст):
    """Ни одной записи в каталог данных: выпуск их только читает."""
    дело = без_комментариев(текст)
    assert "stage/data" not in дело, (
        "сценарий добрался до комплекта данных — наложение номеров серий и "
        "редакционные правки были бы стёрты")
    for запрет in ('"$root/data"', "$data_src"):
        assert запрет not in дело, f"сценарий пишет в данные витрины: {запрет}"


def test_плеер_берётся_из_текущего_выпуска(текст):
    assert место(текст, 'player_src="$old_release/config/player.json"') > 0
    assert место(текст, "player_src") < место(текст, "git clone"), (
        "отсутствие плеера обнаруживается уже после сборки выпуска — лишняя "
        "работа и лишний каталог на диске с 2 % свободного")


def test_отсутствие_плеера_останавливает_до_мутаций(текст):
    голова = текст[:место(текст, "git clone")]
    assert "exit 3" in голова, "нет остановки без publisher_id до изменений"
    assert "подставлять чужой или выдуманный запрещено" in голова


def test_повторный_запуск_ничего_не_делает(текст):
    assert место(текст, 'if [ "$old_sha" = "$head_sha" ]') < место(текст, "git clone")
    хвост = текст[место(текст, 'if [ "$old_sha" = "$head_sha" ]'):]
    assert "exit 0" in хвост[:хвост.index("fi")]


def test_ссылка_переключается_после_сборки(текст):
    assert место(текст, "git clone") < место(текст, 'ln -sfn "$release" "$current_link"')


def test_прежний_выпуск_запоминается_до_переключения(текст):
    assert место(текст, "$previous_file") < место(текст, 'ln -sfn "$release" "$current_link"')


def test_неудача_healthz_возвращает_прежний_выпуск(текст):
    отказ = текст[место(текст, 'if [ "$ready" = 0 ]'):]
    голова = отказ[:отказ.index("\nfi")]
    assert 'ln -sfn "$old_release" "$current_link"' in голова, голова
    assert "systemctl restart" in голова
    assert "journalctl" in голова, "причина неудачи не печатается"


def test_не_200_на_главной_тоже_откатывает(текст):
    отказ = текст[место(текст, 'if [ "$code" != 0 ]'):]
    assert 'ln -sfn "$old_release" "$current_link"' in отказ


def test_сценарий_не_трогает_соседние_слои(текст):
    for запрет in ("certbot", "/etc/nginx/lords", "nginx -t", "indexing",
                   "dns", "nova-catalog"):
        assert запрет not in текст, (
            f"выпуск кода трогает чужой слой: {запрет} — у каждого свой "
            "инструмент и свой откат")


def test_признак_версии_ищется_в_журнале_службы(текст):
    """Файл на диске доказывает доставку, журнал — что рантайм его исполняет."""
    assert "journalctl" in текст and "согласование доступности серий" in текст


def test_имена_переменных_только_ascii(текст):
    import re
    for м in re.finditer(r"(?m)^\s*([A-Za-zА-Яа-яЁё_][\w]*)=", текст):
        имя = м.group(1)
        assert имя.isascii(), (
            f"имя переменной {имя!r} не ASCII: bash считает именем лишь "
            "[A-Za-z_][A-Za-z0-9_]*, и такая строка — вызов команды")
