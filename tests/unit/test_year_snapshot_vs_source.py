"""Частота расхождения года: «года нет» не считается совпадением.

Повод — MOD-178: ворота требуют назвать год снимка, а источник называет другой,
и материал становится непубликуемым в обе стороны. Инструмент мерит ЧАСТОТУ,
которой у записи не было, и отрицательные контроли названы заранее: работа без
года в снимке попадает в «не измерено» и в знаменатель доли не идёт, а сиквелы
считаются отдельно — иначе редкий случай растворится в среднем.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "year-snapshot-vs-source.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("year_snapshot_vs_source", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_сиквел_узнаётся_по_числу_в_конце():
    assert МОД.вид_работы("rukovodstvo-soten-demonov-4") == "сиквел"
    assert МОД.вид_работы("chernyy-klever-2") == "сиквел"


def test_число_в_середине_сиквелом_не_делает():
    assert МОД.вид_работы("detektiv-konan-pentagramma-na-milliard") == "прочее"
    assert МОД.вид_работы("gintama") == "прочее"


def test_год_берётся_из_даты_источника():
    assert МОД.год_даты("2024-02-23") == "2024"
    assert МОД.год_даты("") == ""
    assert МОД.год_даты("неизвестно") == ""


def test_расхождение_и_совпадение_различаются():
    assert МОД.исход("2020", "2024") == "расходятся"
    assert МОД.исход("2024", "2024") == "совпадают"


def test_отсутствие_любого_из_годов_это_не_измерено():
    assert МОД.исход("", "2024") == "НЕ ИЗМЕРЕНО"
    assert МОД.исход("2020", "") == "НЕ ИЗМЕРЕНО"


def test_знаменатель_доли_не_включает_неизмеренное():
    с = МОД.свод([("сиквел", "совпадают"), ("сиквел", "расходятся"),
                  ("сиквел", "НЕ ИЗМЕРЕНО")])
    assert с["сиквел"]["измерено"] == 2
    assert с["сиквел"]["расходятся"] == 1
    assert с["сиквел"]["не измерено"] == 1
    assert с["сиквел"]["доля"] == "50 %"


def test_виды_считаются_раздельно():
    с = МОД.свод([("сиквел", "расходятся"), ("прочее", "совпадают"),
                  ("прочее", "совпадают")])
    assert с["сиквел"]["доля"] == "100 %"
    assert с["прочее"]["доля"] == "0 %"


def test_полностью_неизмеренный_вид_доли_не_получает():
    """Ноль измерений — это прочерк, а не ноль процентов."""
    с = МОД.свод([("прочее", "НЕ ИЗМЕРЕНО")])
    assert с["прочее"]["измерено"] == 0
    assert с["прочее"]["доля"] == "—"


def test_черновики_берут_только_записи_с_карточкой_источника(tmp_path):
    import json
    д = tmp_path / "srv" / "x" / "runtime" / "overlays" / "animedia.space"
    д.mkdir(parents=True)
    (д / "drafts.json").write_text(json.dumps({"items": [
        {"slug": "с-источником", "sources": ["https://shikimori.io/animes/42950"]},
        {"slug": "без-источника", "sources": ["https://animedia.space/title/x/"]},
        {"slug": "без-поля"},
    ]}, ensure_ascii=False), encoding="utf-8")
    шаблон = str(tmp_path / "srv" / "*" / "runtime" / "overlays" / "*" / "drafts.json")
    итог = МОД.черновики(шаблон)
    assert итог == [("animedia.space", "с-источником", "42950")]
