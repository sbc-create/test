"""Опора для сверки имён берётся со СТРАНИЦЫ, когда снимка каталога нет.

Повод — собственная ошибка 25.10 (класс 45 в `docs/RECURRING_FAILURES.md`).
Пакетная рецензия читает запись каталога из снимков подробностей
(`/srv/lords/.frontend/*-details.json` и каталоги данных ячеек), а у семейства
Yummy такого снимка НЕТ: факты его витрин живут в разметке schema.org самой
страницы. Поэтому для пяти витрин Yummy проверка «посторонних вставок нет» не
выполнялась никогда — инструмент писал «(записи каталога нет)», и имена
сверялись руками. Рецензируя `van-pis-epizod-sabo-…`, я так и сделала: судила
имя автора по одному режиму источника и ОТКЛОНИЛА подтверждённый факт.

Отсюда два требования, и второе не менее важно первого: опора берётся со
страницы, когда снимка нет, И источник опоры НАЗЫВАЕТСЯ в выводе. «Посторонних
вставок нет» без сказанной опоры — не проверка, а молчание.
"""
from __future__ import annotations

import importlib.util
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ))
_путь = КОРЕНЬ / "automation/local/review-materials-batch.py"
_спец = importlib.util.spec_from_file_location("review_batch", _путь)
ПАЧКА = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ПАЧКА)


def test_опора_со_страницы_отдаёт_поля_записи(monkeypatch) -> None:
    monkeypatch.setattr(ПАЧКА.editorial, "факты", lambda д, с: {
        "facts": {"name": "Ван-Пис. Эпизод Сабо", "original_name": "One Piece",
                  "year": 2015, "type": "movie", "description": None}})
    о = ПАЧКА.опора_со_страницы("yummyani7.site", "van-pis")
    assert о["name"] == "Ван-Пис. Эпизод Сабо" and о["year"] == 2015
    assert "description" not in о, "пустое поле в опору не попадает"


def test_страница_не_прочиталась_опоры_нет(monkeypatch) -> None:
    """«Не измерено» подменять пустой опорой нельзя: любое имя стало бы чужим."""
    def падает(д, с):
        raise RuntimeError("страница ответила 404")

    monkeypatch.setattr(ПАЧКА.editorial, "факты", падает)
    assert ПАЧКА.опора_со_страницы("yummyani7.site", "нет-такого") == {}


def test_проверка_без_опоры_не_принимает_материал() -> None:
    итог = ПАЧКА.проверить({"body": "Текст про Сабо и Луффи длиной более восьмидесяти "
                                     "знаков, чтобы ворота качества не жаловались.",
                            "slug": "van-pis", "sources": ["https://shikimori.io/animes/1"]},
                           {})
    assert итог["посторонних_вставок_нет"] is False
    assert итог["_посторонние"] == ["(записи каталога нет)"]


def test_с_опорой_со_страницы_имена_каталога_не_считаются_чужими() -> None:
    запись = {"name": "Ван-Пис. Эпизод Сабо", "original_name": "One Piece: Episode of Sabo",
              "year": 2015, "type": "movie"}
    итог = ПАЧКА.проверить({"body": "«Ван-Пис. Эпизод Сабо» — спецвыпуск 2015 года, "
                                     "и речь в нём идёт не о Луффи, а о Сабо.",
                            "slug": "van-pis-epizod-sabo",
                            "sources": ["https://shikimori.io/animes/31289"]}, запись)
    assert итог["_посторонние"] != ["(записи каталога нет)"]


def test_источник_опоры_печатается_всегда_когда_он_не_снимок() -> None:
    """Закреплено текстом инструмента: иначе молчание не отличить от проверки."""
    текст = _путь.read_text(encoding="utf-8")
    assert '"_откуда_опора"' in текст
    assert "опора сверки:" in текст
    assert "разметка страницы" in текст
