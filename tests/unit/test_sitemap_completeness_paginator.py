def test_число_меньше_карточек_на_странице_отвергается(monkeypatch):
    """Страховка: каталог не может объявить меньше, чем сам показывает."""
    первая = ("<html><body><p>14 записей</p>"
              + "".join(f'<a href="/title/t{н}/">x</a>' for н in range(48))
              + "".join(f'<a href="/catalog/?page={н}">{н}</a>'
                        for н in (2, 3, 100))
              + "</body></html>")
    страницы = {"": первая, "?page=2": _страница(48),
                "?page=99": _страница(48), "?page=100": _страница(7)}
    _подменить(monkeypatch, страницы)
    всего, откуда = МОД.объявлено_записей("x.site")
    assert всего == 99 * 48 + 7, (всего, откуда)
    assert "число отвергнуто" in откуда
    assert "карточек 48" in откуда


def test_число_больше_карточек_принимается(monkeypatch):
    """Отрицательный контроль: нормальное число страховка не трогает."""
    первая = ("<html><body><p>8226 записей</p>"
              + "".join(f'<a href="/title/t{н}/">x</a>' for н in range(48))
              + "</body></html>")
    _подменить(monkeypatch, {"": первая})
    всего, откуда = МОД.объявлено_записей("x.site")
