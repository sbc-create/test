def test_css_комментарий_эталоном_не_становится():
    """Измерено 20.10 на lordserials22.info: «записей: 14» при 68 323 адресах.

    Источником четырнадцати был КОММЕНТАРИЙ В CSS — «Полка набирает
    РЯД_ПОЛКИ = 14 записей», — который после срезания одних тегов стал обычным
    текстом. Эталон брался из разметки оформления, а не из того, что витрина
    говорит посетителю, и расхождение 68 309 печаталось как безобидное.
    """
    тело = ('<html><head><style>/* Полка набирает РЯД_ПОЛКИ = 14 записей */'
            '</style></head><body><p>показано 24 из 67 681 записей в выборке'
            '</p></body></html>')
    текст = МОД.видимый_текст(тело)
    assert "РЯД_ПОЛКИ" not in текст
    assert "67 681 записей в выборке" in текст


def test_скрипт_и_html_комментарий_тоже_срезаются():
    тело = ('<html><script>var n = "1 записей";</script>'
            '<!-- 2 записей в разделе -->'
            '<body>3 тайтлов</body></html>')
    текст = МОД.видимый_текст(тело)
    assert "var n" not in текст and "2 записей" not in текст
    assert "3 тайтлов" in текст


