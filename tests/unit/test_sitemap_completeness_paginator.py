"""Эталон размера каталога по собственной листалке, когда числа записей нет.

Повод измерен 20.10. Ни одна из 17 индексируемых витрин сети не печатает «N
записей», и проход полноты выдавал «замечаний: 0» при НУЛЕ измерений — то есть
главный вопрос («полна ли карта») не был измерен ни разу, а итог читался как
«всё в порядке», и код возврата был нулевым.

Листалка объявляет число страниц сама, и это тоже утверждение САМОГО сайта о
размере своего каталога. На animedia.icu измерено: страниц 172, на первой 48
карточек, на второй и 171-й по 58, на последней 28. Разность 10 — ссылки ВНЕ
сетки каталога, появляющиеся со второй страницы. Отсюда 171 × 48 + 18 = 8 226,
и это же число витрина печатает у фасетов — два независимых источника совпали.

Отрицательные контроли, названные заранее:

* серединные страницы с РАЗНЫМ числом карточек → число не выдаётся вовсе.
  Оценка, выданная за измерение, хуже отсутствия измерения;
* на серединной странице карточек МЕНЬШЕ, чем на первой → отказ, а не
  вычитание отрицательного;
* листалки нет → «не измерено», а не ноль;
* ноль измерений даёт код возврата 2 и отдельную строку в итоге: «замечаний 0»
  по неизмеренному домену не означает «карта полна».

Сеть не используется: `достать` подменяется.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "sitemap_completeness_pag", КОРЕНЬ / "automation/local/sitemap-completeness.py")
МОД = importlib.util.module_from_spec(_с)
_с.loader.exec_module(МОД)


def _страница(карточек: int, номера: tuple[int, ...] = ()) -> str:
    """Страница каталога: `карточек` ссылок на произведения и листалка.

    `номера` задаётся списком явно, а не «до последней»: листалка из двух
    страниц и из ста семидесяти двух — разные случаи, и подменять их счётом
    нельзя.
    """
    ссылки = "".join(f'<a href="/title/t{н}/">x</a>' for н in range(карточек))
    листалка = "".join(f'<a href="/catalog/?page={н}">{н}</a>' for н in номера)
    return f"<html><body>{листалка}{ссылки}</body></html>"


def _подменить(monkeypatch, страницы: dict[str, str]):
    """страницы: {'?page=2': html, ...}; ключ '' — первая страница.

    Страница с `page=`, которой нет в наборе, даёт 404, а НЕ первую страницу:
    иначе проверка «последняя не ответила» прошла бы на подложенной первой.
    """
    def достать(url, таймаут=45):
        for ключ in sorted(страницы, key=len, reverse=True):
            if ключ and ключ in url:
                return "200", страницы[ключ]
        if "page=" in url:
            return "404", ""
        if "" in страницы:
            return "200", страницы[""]
        return "404", ""
    monkeypatch.setattr(МОД, "достать", достать)


ПОСЛЕДНЯЯ = 172


def _сеть_как_у_animedia() -> dict[str, str]:
    """Измеренная 20.10 картина: 48 / 58 / 58 / 28."""
    return {
        "": _страница(48, (2, 3, ПОСЛЕДНЯЯ)),
        "?page=2": _страница(58),
        f"?page={ПОСЛЕДНЯЯ - 1}": _страница(58),
        f"?page={ПОСЛЕДНЯЯ}": _страница(28),
    }


def test_итог_считается_по_сетке_без_внесеточных(monkeypatch):
    """Главный признак: 171 × 48 + 18 = 8 226, а не 171 × 48 + 28."""
    страницы = _сеть_как_у_animedia()
    _подменить(monkeypatch, страницы)
    всего, откуда = МОД.по_листалке("x.site", страницы[""])
    assert всего == 8226, (всего, откуда)
    assert "171 × 48 + 18" in откуда
    assert "вне сетки на странице: 10" in откуда


def test_без_внесеточных_ссылок_итог_прямой(monkeypatch):
    """Положительный контроль: когда лишних нет, вычитать нечего."""
    страницы = {"": _страница(48, (2, 3, 10)), "?page=2": _страница(48),
                "?page=9": _страница(48), "?page=10": _страница(7)}
    _подменить(monkeypatch, страницы)
    всего, откуда = МОД.по_листалке("x.site", страницы[""])
    assert всего == 9 * 48 + 7
    assert "вне сетки на странице: 0" in откуда


