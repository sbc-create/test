"""REQ-SEO-SITEMAP-FACETS: карта перечисляет фасеты, которые себя канонизируют.

До 2026-10-18 страницы жанра, страны и года объявляли `canonical` на
`/catalog/`: они отдавали отобранный каталог, но от себя отказывались.
Включать такие адреса в карту было бы ошибкой — карта перечисляла бы страницы,
которые сами указывают на другую.

В тот же день они получили свой заголовок, свой h1 и canonical на себя
(измерено публично на восьми витринах: h1 «Великобритания», canonical на
`/country/velikobritaniya/`). После этого их отсутствие в карте стало потерей:
около 100 жанров, страны и годы — это сотни посадочных страниц без
перечисления.

Две осторожности закреплены здесь же:

* состав берётся из ИНДЕКСА витрины, а не придумывается;
* `lastmod` у фасета НЕ ставится: даты изменения у выборки нет, а подставить
  «сегодня» значило бы соврать обходчику обо всех фасетах сразу — тот самый
  дефект, который в этот же день исправлялся на страницах произведений.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "host"
        / "seo_layer.py")


def _модуль():
    имя = "seo_layer_фасеты"
    спец = importlib.util.spec_from_file_location(имя, ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


class _Обработчик:
    def __init__(self, данные, индекс):
        self.данные = данные
        self.индекс = индекс


class _Данные:
    def __init__(self, items, years=()):
        self.items = items
        self.years = years


class _Рантайм:
    def __init__(self, семейство, items, индекс, years=(), разделы=()):
        self.СЕМЕЙСТВО = семейство
        self.Обработчик = _Обработчик(_Данные(items, years), индекс)
        self.РАЗДЕЛЫ_КАРТЫ = разделы


ЗАПИСИ = [{"slug": "alpha", "url": "/title/alpha/", "updated_at": "2026-10-10"}]
ИНДЕКС = {"genre_names": [("boevik", "боевик"), ("drama", "драма")],
          "country_names": [("ssha", "США")]}


def test_фасеты_попадают_в_карту_у_lords():
    страницы, _ = МОД.адреса_карты(
        _Рантайм("lords", ЗАПИСИ, ИНДЕКС, years=[2026, 2025]))
    адреса = [с["url"] for с in страницы]
    assert "/genre/boevik/" in адреса
    assert "/genre/drama/" in адреса
    assert "/country/ssha/" in адреса
    assert "/year/2026/" in адреса and "/year/2025/" in адреса
    assert "/title/alpha/" in адреса, "карточки произведений не должны исчезнуть"


def test_у_фасета_нет_даты_изменения():
    """Подставленная дата у выборки — та же неправда, что и на карточках."""
    страницы, _ = МОД.адреса_карты(
        _Рантайм("lords", ЗАПИСИ, ИНДЕКС, years=[2026]))
    для_фасетов = [с for с in страницы
                   if с["url"].startswith(("/genre/", "/country/", "/year/"))]
    assert для_фасетов
    assert all(not с["lastmod"] for с in для_фасетов)
    # Отрицательный контроль: у карточки дата осталась.
    карточка = next(с for с in страницы if с["url"] == "/title/alpha/")
    assert карточка["lastmod"] == "2026-10-10"


def test_у_других_семейств_путей_фасетов_в_карте_нет():
    """У Zona и Animedia путь фасета ПЕРЕВОДИТ на query-форму.

    Перечислять адрес, отвечающий перенаправлением, — значит обещать
    обходчику страницу, которой по этому адресу нет.
    """
    for семейство in ("zona", "animedia"):
        страницы, _ = МОД.адреса_карты(
            _Рантайм(семейство, ЗАПИСИ, ИНДЕКС, years=[2026]))
        адреса = [с["url"] for с in страницы]
        assert not [а for а in адреса
                    if а.startswith(("/genre/", "/country/", "/year/"))], семейство


def test_состав_берётся_из_индекса_а_не_придумывается():
    """Пустой индекс — пустой список фасетов, а не выдуманные коды."""
    страницы, _ = МОД.адреса_карты(_Рантайм("lords", ЗАПИСИ, {}, years=[]))
    адреса = [с["url"] for с in страницы]
    assert адреса == ["/title/alpha/"]


def test_повторов_в_карте_нет():
    индекс = {"genre_names": [("boevik", "боевик"), ("boevik", "боевик")],
              "country_names": []}
    страницы, _ = МОД.адреса_карты(
        _Рантайм("lords", ЗАПИСИ, индекс, years=[2026, 2026]))
    адреса = [с["url"] for с in страницы]
    assert адреса.count("/genre/boevik/") == 1
    assert адреса.count("/year/2026/") == 1


def test_нечисловой_год_не_попадает():
    страницы, _ = МОД.адреса_карты(
        _Рантайм("lords", ЗАПИСИ, {}, years=["не год", None, 2024]))
    адреса = [с["url"] for с in страницы]
    assert "/year/2024/" in адреса
    assert not [а for а in адреса if а.startswith("/year/") and а != "/year/2024/"]
