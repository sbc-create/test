"""Процент тренда печатается только тогда, когда его не решает выбор окна.

ПОВОД ИЗМЕРЕННЫЙ, 24.10, и это ошибка в числах, которые я назвала владельцу
дважды за сутки. Было сказано: «очищенный поиск сети −9,2 %» и «yummyani.site
−30 %». На ТЕХ ЖЕ данных сдвиг окна на двое суток даёт:

  сеть:          +45,6 % (−2 сут), +1,9 % (−1), −9,2 % (окно), −21,4 % (+1), −30,3 % (+2)
  yummyani.site: +15 % (−2 сут), −23 % (−1), −30 % (окно), −37 % (+1), −41 % (+2)

Ряд волатилен: у yummyani.site 715 поисковых визитов 15.10 против 3 113
десятого и 2 921 двадцать третьего — разброс 4,4 раза. Сравнение «неделя к
неделе» на таком ряде знака не определяет, и процент, напечатанный без этой
проверки, выглядит как измерение тренда, а является выбором окна.

Проверяются чистые функции: выгрузка подставляется, сеть не нужна.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "network-search-two-weeks.py"
_с = importlib.util.spec_from_file_location("network_search_two_weeks", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(МОДУЛЬ)

Н1 = ("2026-10-05", "2026-10-11")
Н2 = ("2026-10-12", "2026-10-18")


def test_сдвиг_окна_считается_по_календарю():
    assert МОДУЛЬ.сдвиг_окна(Н1, 2) == ("2026-10-07", "2026-10-13")
    assert МОДУЛЬ.сдвиг_окна(Н1, -1) == ("2026-10-04", "2026-10-10")
    assert МОДУЛЬ.сдвиг_окна(("2026-03-01", "2026-03-07"), -1) == (
        "2026-02-28", "2026-03-06")


def _профиль(по_дням: dict[str, float]) -> list[dict]:
    """Профиль в том виде, в каком его читают `срез` и `числа`.

    Поля взяты из самих функций, а не угаданы: дата, источник, робот, браузер,
    визиты. Источник обязан содержать признак поиска, иначе `поиск()` его не
    посчитает и ряд выйдет нулевым — тогда проверка молча ничего не проверит.
    """
    return [{"дата": дата, "источник": "Search engine traffic",
             "робот": "People", "браузер": "Chrome", "визиты": зн}
            for дата, зн in по_дням.items()]


def test_ровный_рост_признаётся_устойчивым():
    """Отрицательный контроль: сторож обязан уметь НЕ срабатывать.

    Иначе он объявит неопределённым всякий тренд, и его выключат.
    """
    дни = {f"2026-10-{д:02d}": (100 + д * 10) for д in range(1, 25)}
    у = МОДУЛЬ.устойчивость(_профиль(дни), Н1, Н2)
    assert у["проб"] >= 2, у
    assert у["устойчив"] is True, у
    assert у["базовый"] > 0


def test_ровное_падение_признаётся_устойчивым():
    дни = {f"2026-10-{д:02d}": (1000 - д * 20) for д in range(1, 25)}
    у = МОДУЛЬ.устойчивость(_профиль(дни), Н1, Н2)
    assert у["устойчив"] is True, у
    assert у["базовый"] < 0


def test_волатильный_ряд_признаётся_неопределённым():
    """Ровно случай yummyani.site: провал в середине и всплеск в конце."""
    дни = {
        "2026-10-03": 3000, "2026-10-04": 3000, "2026-10-05": 3100,
        "2026-10-06": 1600, "2026-10-07": 1000, "2026-10-08": 800,
        "2026-10-09": 780, "2026-10-10": 715, "2026-10-11": 2600,
        "2026-10-12": 2300, "2026-10-13": 1700, "2026-10-14": 1280,
        "2026-10-15": 1350, "2026-10-16": 1270, "2026-10-17": 1600,
        "2026-10-18": 2900, "2026-10-19": 2900, "2026-10-20": 2900,
    }
    у = МОДУЛЬ.устойчивость(_профиль(дни), Н1, Н2)
    assert у["проб"] >= 2, у
    assert у["устойчив"] is False, у
    знаки = {1 if п > 0 else -1 for _, п in у["пробы"]}
    assert len(знаки) > 1, у["пробы"]


def test_окно_без_данных_расхождением_знака_не_считается():
    """Сдвиг вышел за выгрузку — это не «тренд не определён», а нет данных.

    Иначе сторож срабатывал бы на краю любой выгрузки и обесценился.
    """
    дни = {f"2026-10-{д:02d}": 100 for д in range(5, 19)}
    у = МОДУЛЬ.устойчивость(_профиль(дни), Н1, Н2, сдвиги=(-30, 30))
    assert у["проб"] == 0, у["пробы"]
    assert у["устойчив"] is False  # нечем подтвердить — и не подтверждаем


def test_прирост_от_нуля_не_выдумывается():
    assert МОДУЛЬ.прирост(0, 10) is None
    assert МОДУЛЬ.прирост(10, 0) == -100.0
