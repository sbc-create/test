"""У каждой ячейки с собственным репозиторием есть чем собрать выпуск.

Повод. Из семнадцати ячеек `tools/build_release.py` не было ровно у `animego-04`
— и узналось это трассировкой `ExecutorRefused` в середине подачи заявки, после
зелёного CI, заведённой площадки, nginx и сертификата. Проверка стоит один
вызов `is_file()` и не требует ни прав, ни сети: место ей до подачи, а не в
обработчике исключений.

Второе свойство, которое здесь же закрепляется: проверка обязана стоять в ОБОИХ
путях подачи. Проверки, обходимой соседней командой, у нас уже было достаточно —
`cell trigger` шёл мимо всего, что стояло только в `cell submit`, и заявки
подавались именно им.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from factory.cell import queue as q

КОРЕНЬ = Path(__file__).resolve().parents[2]


#: Как витрина получает КОД. Объявляет реестр (`runtime.delivery`), а не
#: догадка по наличию файлов.
#:
#: Повод отделить. Измерено 2026-10-05: у `an1mego.site` и `animeg0.site`
#: сборщика выпуска нет и не будет — код им доставляет собственный
#: `deploy/install.sh` от root, очереди выпусков у них не существует (D179,
#: D190). Пока доставка нигде не объявлялась, отбор шёл по признаку «есть
#: рабочая копия», и проверка выпускаемости требовала от этих двух витрин
#: сборщик, которого у них не будет: четыре отказа на зелёном в остальном
#: прогоне.
#:
#: Выводить доставку из НАЛИЧИЯ сборщика нельзя — проверка стала бы
#: тавтологией: «есть сборщик у тех, у кого есть сборщик». Поэтому источник
#: истины — объявление, а проверка сверяет с ним репозиторий.
ОЧЕРЕДЬЮ = "release-queue"
СВОИМ_УСТАНОВЩИКОМ = "own-installer"


def ячейки_с_репозиторием() -> list[tuple[str, Path, str]]:
    реестр = json.loads((КОРЕНЬ / "config" / "site-cells.json").read_text(encoding="utf-8"))
    итог = []
    for ячейка in реестр["cells"]:
        путь = (ячейка.get("repo") or {}).get("path")
        if not путь:
            continue
        рабочая = КОРЕНЬ / путь
        if (рабочая / ".git").exists():
            доставка = str((ячейка.get("runtime") or {}).get("delivery") or "")
            итог.append((ячейка["site_id"], рабочая, доставка))
    return итог


ВСЕ_ЯЧЕЙКИ = ячейки_с_репозиторием()
ЯЧЕЙКИ = [(с, р) for с, р, д in ВСЕ_ЯЧЕЙКИ if д == ОЧЕРЕДЬЮ]
УСТАНОВЩИКОМ = [(с, р) for с, р, д in ВСЕ_ЯЧЕЙКИ if д == СВОИМ_УСТАНОВЩИКОМ]


def test_есть_что_проверять() -> None:
    assert len(ЯЧЕЙКИ) >= 10, f"ячеек с рабочей копией найдено {len(ЯЧЕЙКИ)}"


def test_каждая_рабочая_копия_объявляет_способ_доставки() -> None:
    """Необъявленная доставка — не умолчание в пользу очереди.

    Пустое поле здесь означало бы, что проверка сама выбирает, чего требовать
    от витрины. Это и есть то самое «пустое поле — не разрешение»: отбор
    обязан опираться на объявление, а не на его отсутствие.
    """
    без_объявления = [с for с, _, д in ВСЕ_ЯЧЕЙКИ
                      if д not in (ОЧЕРЕДЬЮ, СВОИМ_УСТАНОВЩИКОМ)]
    assert not без_объявления, (
        "у этих ячеек не объявлен runtime.delivery, и проверка выпускаемости "
        f"не знает, чего от них требовать: {без_объявления}")
    assert len(ЯЧЕЙКИ) + len(УСТАНОВЩИКОМ) == len(ВСЕ_ЯЧЕЙКИ)


@pytest.mark.parametrize("site_id,репозиторий", УСТАНОВЩИКОМ,
                         ids=[с for с, _ in УСТАНОВЩИКОМ])
def test_витрина_своего_установщика_его_действительно_имеет(
        site_id: str, репозиторий: Path) -> None:
    """`own-installer` — не отговорка от проверки, а другое требование.

    Объявив доставку собственным установщиком, витрина обязана его иметь:
    иначе объявление снимало бы проверку, ничего не обещая взамен.
    """
    установщик = репозиторий / "deploy" / "install.sh"
    assert установщик.is_file(), (
        f"{site_id}: объявлена доставка {СВОИМ_УСТАНОВЩИКОМ}, но нет "
        f"{установщик.relative_to(репозиторий)} — доставлять нечем")
    текст = установщик.read_text(encoding="utf-8")
    # Установщик требует root по делу: он пишет в /etc (TLS и юниты) и
    # вызывает systemctl. Это и есть причина, по которой `sudo -u <учётная
    # запись сайта>` установкой не является (D190).
    assert "/etc/nginx" in текст and "systemctl" in текст, (
        f"{site_id}: установщик не пишет в /etc/nginx и не вызывает systemctl "
        "— тогда неясно, почему он требует root")


@pytest.mark.parametrize("site_id,репозиторий", ЯЧЕЙКИ, ids=[с for с, _ in ЯЧЕЙКИ])
def test_у_ячейки_есть_сборщик(site_id: str, репозиторий: Path) -> None:
    сборщик = репозиторий / q.СБОРЩИК_ПАКЕТА
    assert сборщик.is_file(), (
        f"{site_id}: нет {q.СБОРЩИК_ПАКЕТА} — выпуск этой ячейки невозможен, "
        "и узнается это только при подаче заявки")


@pytest.mark.parametrize("site_id,репозиторий", ЯЧЕЙКИ, ids=[с for с, _ in ЯЧЕЙКИ])
def test_предполётная_проверка_пропускает_готовую_ячейку(site_id: str, репозиторий: Path) -> None:
    q.проверить_сборщик(site_id)


def test_проверка_отказывает_без_сборщика(tmp_path: Path, monkeypatch) -> None:
    from factory.cell import registry as реестр_ячеек

    (tmp_path / "репо" / ".git").mkdir(parents=True)

    class Ячейка:
        site_id = "проба"
        domain = "проба.test"
        repo = {"path": "репо"}

    monkeypatch.setattr(q, "КОРЕНЬ_ПРОЕКТА", tmp_path)
    monkeypatch.setattr(реестр_ячеек, "resolve", lambda _: Ячейка())
    with pytest.raises(q.RequestRejected) as отказ:
        q.проверить_сборщик("проба")
    assert q.СБОРЩИК_ПАКЕТА in str(отказ.value)

    (tmp_path / "репо" / "tools").mkdir()
    (tmp_path / "репо" / q.СБОРЩИК_ПАКЕТА).write_text("# пусто\n", encoding="utf-8")
    q.проверить_сборщик("проба")


def test_проверка_стоит_в_обоих_путях_подачи() -> None:
    for файл in ("factory/cell/cli.py", "factory/cell/trigger.py"):
        текст = (КОРЕНЬ / файл).read_text(encoding="utf-8")
        assert "проверить_сборщик" in текст, f"{файл} не вызывает проверить_сборщик"


def test_имя_сборщика_одно_и_то_же_у_очереди_и_у_исполнителя() -> None:
    """Два написания одного имени разойдутся, и проверка начнёт мерить не то."""
    from factory.cell import admin_exec

    assert str(admin_exec.СБОРЩИК) == q.СБОРЩИК_ПАКЕТА
    # И берётся оно у него же, а не повторено строкой: иначе два
    # написания разойдутся молча.
    исходник = (КОРЕНЬ / "factory" / "cell" / "queue.py").read_text(encoding="utf-8")
    assert 'СБОРЩИК_ПАКЕТА = str(_admin_exec.СБОРЩИК)' in исходник
