"""У каждой публичной ячейки есть заготовка nginx, и она ссылается на свой upstream.

Повод. `install-site-nginx.sh` отказывается словами «нет заготовки конфигурации»
и отдельно проверяет, что заготовка ссылается ровно на тот upstream, который он
создаст: `cell_<site_id с подчёркиваниями>`. Отсутствие файла обнаруживалось в
момент запуска установщика — то есть после того, как владелец уже выполнил
команду, — и каждый такой случай стоил отдельного круга «подготовь заготовку,
запусти снова». Заготовка ничего не запускает, её можно проверить заранее.

Имя upstream считается тем же правилом, что в установщике
(`tr '.-' '__'`), а не переписывается сюда словами: расхождение двух написаний
даёт непереключаемый маршрут, и это худший вид ошибки — конфигурация есть, а
выкладка не меняет ничего.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЗАГОТОВКИ = КОРЕНЬ / "automation" / "host" / "nginx-site"
РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"

НЕПУБЛИЧНЫЕ = (".localhost", ".localhost.test", ".test", ".local", ".invalid")

#: Ячейки, обслуживаемые не через заготовку этого каталога. Названы явно: у
#: работающих витрин конфигурация установлена давно и живёт на хосте, а
#: заготовка для них не создавалась. Строгая отметка заставит убрать строку,
#: когда заготовка появится.
БЕЗ_ЗАГОТОВКИ = {
    "zona-01": "витрина работает с августа, конфигурация установлена до появления заготовок",
    "zona-02": "то же: конфигурация zona-02.conf установлена на хосте",
    "lords-01": "то же",
    "lords-02": "то же",
    "lords-03": "то же",
    "yummy-site": "семейство Yummy обслуживается контейнером, конфигурация иной формы",
    "yummy-org": "то же",
    "yummy-biz": "то же",
    "animedia-01": "семейство Animedia ведётся вне этого реестра заготовок",
    "animedia-02": "то же",
    # Внесены в реестр 2026-10-03 как ВИДИМЫЕ, но не как ячейки: рантайм
    # установлен напрямую (`runtime.managed_by: monolith`), конфигурация живёт
    # в `sites-available/<домен>.conf` и `sites-enabled/`, заготовки для них
    # фабрика не делала и выкладкой их не управляет. Требовать заготовку
    # значило бы требовать её для сайта, который этой очередью не выпускается.
    "animego-02": "прямая установка (managed_by: monolith): своя конфигурация в sites-available, заготовка не создавалась",
    "animego-03": "то же",
}


def _ячейки() -> list[dict]:
    данные = json.loads(РЕЕСТР.read_text(encoding="utf-8"))["cells"]
    return [c for c in данные if not str(c["domain"]).endswith(НЕПУБЛИЧНЫЕ)]


def upstream(site_id: str) -> str:
    """Ровно то же правило, что в install-site-nginx.sh: `tr '.-' '__'`."""
    return "cell_" + re.sub(r"[.-]", "_", site_id)


ЯЧЕЙКИ = _ячейки()


def test_есть_что_проверять() -> None:
    assert ЯЧЕЙКИ, "публичных ячеек в реестре нет"


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["site_id"])
def test_заготовка_есть_и_ссылается_на_свой_upstream(ячейка: dict) -> None:
    site_id, домен = ячейка["site_id"], ячейка["domain"]
    if site_id in БЕЗ_ЗАГОТОВКИ:
        pytest.skip(f"{site_id}: {БЕЗ_ЗАГОТОВКИ[site_id]}")
    имя = upstream(site_id)
    for суффикс in ("", "-tls"):
        путь = ЗАГОТОВКИ / f"{site_id}{суффикс}.conf"
        assert путь.is_file(), (
            f"{site_id}: нет {путь.name}. install-site-nginx.sh откажет уже после "
            "того, как владелец выполнил команду")
        текст = путь.read_text(encoding="utf-8")
        assert re.search(rf"proxy_pass http://{re.escape(имя)}\b", текст), (
            f"{путь.name}: не ссылается на {имя} — маршрут окажется непереключаемым")
        строки = [с.strip() for с in текст.splitlines()
                  if с.strip().startswith("server_name")]
        assert строки, f"{путь.name}: нет server_name"
        имена = строки[0].rstrip(";").split()[1:]
        assert домен in имена, f"{путь.name}: server_name {имена} не содержит {домен}"
        # Чужой домен в заготовке означает, что два сайта обслужит одна
        # конфигурация — ровно то, что задание запрещает.
        чужие = [и for и in имена
                 if и not in (домен, f"www.{домен}")]
        assert not чужие, f"{путь.name}: посторонние домены в server_name: {чужие}"


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["site_id"])
def test_индексация_закрыта_в_заготовке(ячейка: dict) -> None:
    """Заготовка закрытой витрины обязана НЕСТИ МЕХАНИЗМ режима.

    Прежде здесь требовалось слово `noindex` в тексте заготовки — то есть
    зашитый запрет. С 2026-10-03 режим живёт во включаемом файле, который
    установщик создаёт закрытым, а заготовка несёт заголовок на переменной.
    Требовать `noindex` в конфигурации значило бы требовать вернуть тот самый
    зашитый запрет, из-за которого слой нового сайта оказывался
    неуправляемым.

    Закрытость при этом проверяется не словом в файле, а двумя фактами:
    заголовок режима в заготовке ЕСТЬ (иначе домен не отдаёт запрет вовсе) и
    установщик создаёт включаемый файл в режиме CLOSED
    (`test_установщик_создаёт_включаемый_файл_закрытым`).
    """
    from factory.cell import nginx_indexing as ни

    site_id = ячейка["site_id"]
    if site_id in БЕЗ_ЗАГОТОВКИ:
        pytest.skip(f"{site_id}: {БЕЗ_ЗАГОТОВКИ[site_id]}")
    желаемое = (ячейка.get("indexing") or {}).get("desired_state")
    if желаемое != "CLOSED":
        pytest.skip(f"{site_id}: индексация объявлена как {желаемое!r}")
    for суффикс in ("", "-tls"):
        файл = ЗАГОТОВКИ / f"{site_id}{суффикс}.conf"
        текст = файл.read_text(encoding="utf-8")
        assert "X-Robots-Tag" in текст, (
            f"{файл.name}: индексация объявлена закрытой, а заголовка режима нет")
        assert ни.уже_на_переменной(текст, site_id), (
            f"{файл.name}: заголовок режима не на переменной")
        assert ни.ФИКСИРОВАННАЯ not in текст, (
            f"{файл.name}: зашитый запрет вернулся в заготовку")


# --- режим индексации приходит включаемым файлом, а не фиксированной строкой

@pytest.mark.parametrize("site_id", sorted({
    (ф.stem[:-4] if ф.stem.endswith("-tls") else ф.stem)
    for ф in ЗАГОТОВКИ.glob("*.conf")}))
def test_заготовка_не_зашивает_режим_индексации(site_id: str) -> None:
    """Новая витрина рождается с УПРАВЛЯЕМЫМ слоем, а не с зашитым запретом.

    Пока заготовка несла `add_header X-Robots-Tag "noindex, nofollow" always;`,
    каждый установленный из неё сайт получал слой, которым операция не
    управляет: первое же открытие домена требовало отдельного перевода
    конфигурации — того самого ручного шага, ради устранения которого заявка
    `indexing-nginx` и появилась. Проверяется ИСТОЧНИК, а не живой файл: правка
    живого файла новых сайтов не касается.

    Объявление `map` — РОВНО ОДНО на сайт: файлы `<site>.conf` и
    `<site>-tls.conf` попадают в один контекст http, и при двух объявлениях
    nginx молча пользуется одним из них (измерено 2026-10-03 на nginx 1.18.0),
    то есть режим из включаемого файла второго перестал бы действовать без
    единой ошибки.
    """
    from factory.cell import nginx_indexing as ни

    файлы = sorted(ф for ф in ЗАГОТОВКИ.glob(f"{site_id}*.conf")
                   if (ф.stem[:-4] if ф.stem.endswith("-tls") else ф.stem) == site_id)
    assert файлы, site_id
    объявлений = 0
    на_переменной = 0
    for ф in файлы:
        текст = ф.read_text(encoding="utf-8")
        assert ни.ФИКСИРОВАННАЯ not in текст, (
            f"{ф.name}: режим зашит фиксированной строкой — новый сайт родится "
            "со слоем, которым операция не управляет")
        if "X-Robots-Tag" in текст:
            assert ни.уже_на_переменной(текст, site_id), (
                f"{ф.name}: заголовок не на переменной режима")
            на_переменной += 1
        if ни.map_объявлен(текст, site_id):
            объявлений += 1
            assert f"include {ни.путь_включаемого(site_id)};" in текст, (
                f"{ф.name}: объявление map есть, а include режима нет — "
                "переменная окажется пустой")
            # Объявление обязано стоять в файле `:80`: его установщик ставит
            # ПЕРВЫМ, до выпуска сертификата. Объявление только в `-tls.conf`
            # означало бы установленную конфигурацию со ссылкой на
            # необъявленную переменную, то есть отказ `nginx -t` на установке
            # новой витрины.
            assert not ф.stem.endswith("-tls"), (
                f"{ф.name}: объявление переменной в файле 443; при установке "
                "нового сайта (сначала :80) переменная будет необъявленной")
    assert на_переменной >= 1, f"{site_id}: заголовка режима нет ни в одном файле"
    assert объявлений == 1, (
        f"{site_id}: объявлений map {объявлений}, должно быть ровно одно")


def test_установщик_создаёт_включаемый_файл_закрытым() -> None:
    """Установщик витрины обязан создать файл режима ДО `nginx -t`.

    Конфигурация на него ссылается: без файла проверка откажет, и установка
    новой витрины падала бы на ровном месте. Создаётся он ЗАКРЫТЫМ — открытие
    остаётся отдельным решением владельца и отдельной операцией.
    """
    скрипт = (КОРЕНЬ / "automation" / "host" / "install-site-nginx.sh").read_text(
        encoding="utf-8")
    до_проверки = скрипт.split("log \"проверка конфигурации\"", 1)[0]
    assert "robots_include" in до_проверки, "файл режима не создаётся до nginx -t"
    assert 'тело_включаемого("CLOSED")' in до_проверки, (
        "режим создаётся не закрытым — новый домен нельзя открывать молча")
    assert "уже есть, не трогаем" in скрипт, (
        "повторная установка обязана оставить существующий режим как есть: "
        "перезапись вернула бы CLOSED домену, который владелец открыл")
    assert 'не включает ${robots_include}' in скрипт, (
        "установщик не проверяет, что заготовка ссылается на файл режима")


# --- сертификат обязан покрывать все имена, которые отвечают по 443 ---------

@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["site_id"])
def test_имена_в_tls_покрыты_сертификатом(ячейка: dict) -> None:
    """Каждое `server_name` блока 443 обязано быть в доменах ячейки.

    Почему проверка появилась. `install-site-tls.sh` строит список имён для
    certbot из реестра: `domain` плюс `aliases`. Заготовка TLS партии от
    2026-10-13 несла ОТДЕЛЬНЫЙ блок 443 для `www.<домен>` со ссылкой на тот же
    сертификат, а `aliases` у восьми ячеек были пусты — то есть certbot
    запросил бы только apex, и www отвечал бы непокрывающим сертификатом.
    Найдено сухим прогоном `launch-new-site.sh --dry-run`, и закреплено здесь:
    имя, отвечающее по HTTPS, но отсутствующее в реестре, — это ошибка TLS на
    живом домене.

    Обратное не требуется: псевдоним может быть объявлен и без своего блока —
    certbot покроет имя, а nginx отдаст его основным блоком.
    """
    site_id = ячейка["site_id"]
    if site_id in БЕЗ_ЗАГОТОВКИ:
        pytest.skip(f"{site_id}: {БЕЗ_ЗАГОТОВКИ[site_id]}")
    файл = ЗАГОТОВКИ / f"{site_id}-tls.conf"
    if not файл.is_file():
        pytest.skip(f"{site_id}: блока TLS нет")
    покрыто = {str(ячейка["domain"]).lower(),
               *(str(a).lower() for a in (ячейка.get("aliases") or ()))}
    имена: set[str] = set()
    for строка in файл.read_text(encoding="utf-8").splitlines():
        с = строка.strip()
        if с.startswith("server_name"):
            имена.update(и.lower() for и in с.rstrip(";").split()[1:])
    непокрытые = sorted(имена - покрыто)
    assert not непокрытые, (
        f"{файл.name}: по HTTPS отвечают имена {непокрытые}, которых нет в "
        "доменах ячейки — certbot их не запросит, и они отдадут непокрывающий "
        "сертификат")
