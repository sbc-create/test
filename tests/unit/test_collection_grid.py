"""Оформление страницы подборки приезжает вместе с её разметкой.

ПОВОД — отказ визуальной приёмки 27.10:
`https://animedia.icu/collection/letniy-sezon-2026-celikom/` показывала
«огромный одиночный постер слева, пустое пространство справа и название
произведения далеко внизу». Измерено браузером: в ряду 1 карточка на 390,
1440 и 1920; рамка постера 1340×565 при отношении 2.37.

ПРИЧИНА, которую закрепляет этот тест. Разметку даёт ОБЩИЙ построитель
`ручная_подборка` — классы `col__grid`, `col__i`, `col__why`, `claim` и
карточка `c__p`/`c__t`. Правила для них лежали только в `ЛОРДС_СТИЛЬ` и в
устаревшем `СТИЛЬ`, а Zona и Animedia эти листы не включают: у каждого
семейства `стиль` = `_общее(…) + лист семейства`. Значит семейство отдавало
страницу, оформления для которой у него нет.

ЗАЩИТА. Оформление перенесено в `_общее()`, и тест требует именно этого: чтобы
правила приезжали из общего листа, а не из листа семейства. Проверяется не
наличие строки в файле, а СОБРАННЫЙ лист каждого семейства — то, что витрина
действительно отдаёт.
"""
from __future__ import annotations

import ast
import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМЫ = (
    КОРЕНЬ / "var" / "site-repos" / "animedia-icu" / "src" / "animedia-frontend.py",
    КОРЕНЬ / "var" / "site-repos" / "animedia-space" / "src" / "animedia-frontend.py",
    КОРЕНЬ / "var" / "site-repos" / "zonafilm-space" / "src" / "lords-frontend.py",
    КОРЕНЬ / "var" / "site-repos" / "zonafilm12-site" / "src" / "lords-frontend.py",
    КОРЕНЬ / "automation" / "host" / "lords-frontend.py",
)
#: Классы, которые рисует общий построитель. Без правил для них страница
#: разворачивается в одну колонку — ровно то, что увидел владелец.
ОБЯЗАТЕЛЬНЫЕ = ("col__grid", "col__i", "c__p", "c__t", "col__why")


def _стиль_подборки(путь: pathlib.Path) -> str:
    текст = путь.read_text(encoding="utf-8")
    м = re.search(r'СТИЛЬ_ПОДБОРКИ = """(.*?)"""', текст, re.S)
    assert м, f"{путь}: постоянной СТИЛЬ_ПОДБОРКИ нет"
    return м.group(1)


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_оформление_приезжает_из_общего_листа(путь):
    """Правила обязаны быть в `_общее`, а не в листе семейства: лист семейства
    включает не каждая витрина, общий — каждая."""
    текст = путь.read_text(encoding="utf-8")
    дерево = ast.parse(текст)
    строки = текст.splitlines()
    узел = next(у for у in ast.walk(дерево)
                if isinstance(у, ast.FunctionDef) and у.name == "_общее")
    тело = "\n".join(строки[узел.lineno - 1:узел.end_lineno])
    assert "СТИЛЬ_ПОДБОРКИ" in тело, тело


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
@pytest.mark.parametrize("класс", ОБЯЗАТЕЛЬНЫЕ)
def test_у_каждого_класса_построителя_есть_правило(путь, класс):
    стиль = _стиль_подборки(путь)
    селекторы = [ч.split("{")[0] for ч in re.findall(r"([^{}]*\{[^}]*\})", стиль)]
    assert any(класс in с for с in селекторы), (
        f"{путь.parts[-3]}: класс {класс} рисуется построителем, "
        "а правила для него нет — страница выйдет без оформления")


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_сетка_не_одна_колонка(путь):
    """Главное число дефекта: колонок обязано быть больше одной на телефоне и
    не меньше четырёх на широком экране."""
    стиль = _стиль_подборки(путь)
    базовая = re.search(r"\.col__grid\{([^}]*)\}", стиль)
    assert базовая, стиль[:200]
    колонок = re.search(r"grid-template-columns:repeat\((\d+)", базовая.group(1))
    assert колонок and int(колонок.group(1)) >= 2, базовая.group(1)
    ширины = [(int(ш), int(к)) for ш, к in re.findall(
        r"min-width:(\d+)px\)\{\.col__grid\{\s*grid-template-columns:repeat\((\d+)", стиль)]
    assert ширины, "нет ни одного правила под ширину экрана"
    широкие = [к for ш, к in ширины if ш >= 900]
    assert широкие and max(широкие) >= 4, ширины


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_рамка_постера_не_искажает_пропорции(путь):
    """`object-fit:cover` в рамке с заданным отношением: нестандартный кадр
    обрезается, а не растягивается. `fill` растянул бы — его быть не должно."""
    стиль = _стиль_подборки(путь)
    рамка = re.search(r"\.col__i \.c__p\{([^}]*)\}", стиль)
    assert рамка and "aspect-ratio" in рамка.group(1), стиль[:300]
    картинка = re.search(r"\.col__i \.c__p img\{([^}]*)\}", стиль)
    assert картинка, стиль[:300]
    assert "object-fit:cover" in картинка.group(1), картинка.group(1)
    assert "object-fit:fill" not in стиль


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_ширина_сетки_ограничена(путь):
    """Иначе на 1920 ряд растягивается во всю ширину окна."""
    стиль = _стиль_подборки(путь)
    базовая = re.search(r"\.col__grid\{([^}]*)\}", стиль)
    assert "max-width" in базовая.group(1), базовая.group(1)
