"""Малый раздел не режется на страницы по одной записи.

Разбиение по блокам годов (ADR-0007) придумано для каталога в пятьдесят с
лишним тысяч записей: одна добавленная запись перерисовывала 8172 страницы из
9430, и блоки годов свели правку к одному году. Расчёт цены в ADR — «по одной
неполной странице на год, от 1 до 23 записей вместо 24» — сделан для годов, в
которых тысячи записей.

Малые разделы в этот расчёт не попали. Подборка из десяти записей,
разложенных по семи годам, получала семь страниц: на первой — одна карточка, и
пейджер на семь номеров под ней. Смысла у такого разбиения нет ни для зрителя,
ни для инкрементальной публикации, ради которой блоки заводились: раздел,
помещающийся на одну страницу, перерисовывается целиком в любом случае.

Правило поэтому такое: блоки годов применяются там, где они что-то экономят.
Если раздел помещается на одну страницу — страница одна. Для каталога ничего не
меняется, и договор ADR-0007 остаётся в силе.
"""

from __future__ import annotations

from factory.lords import pagination as pag


def _записи(годы):
    """Записи только с годом: разбиению больше ничего не нужно."""
    return [type("Z", (), {"year": год, "name": f"z{i}", "slug": f"z{i}"})()
            for i, год in enumerate(годы)]


class TestРазделНаОднуСтраницу:
    def test_десять_записей_семи_годов_дают_одну_страницу(self):
        items = _записи([2026, 2025, 2024, 2023, 2022, 2021, 2020, 2020, 2019, 2019])
        страницы = pag.разбить(items, 24, по_годам=True)
        assert len(страницы) == 1, (
            f"раздел из {len(items)} записей разбит на {len(страницы)} страниц; "
            "зритель увидит пейджер, за которым почти ничего нет"
        )
        assert len(страницы[0]) == len(items), "записи потерялись при склейке"

    def test_ровно_страница_остаётся_одной_страницей(self):
        items = _записи(list(range(2000, 2024)))
        assert len(items) == 24
        assert len(pag.разбить(items, 24, по_годам=True)) == 1

    def test_порядок_записей_не_меняется(self):
        items = _записи([2026, 2025, 2024])
        [страница] = pag.разбить(items, 24, по_годам=True)
        assert [z.slug for z in страница] == [z.slug for z in items]


class TestДоговорADR0007Сохранён:
    """Ради чего блоки заводились, должно продолжать работать."""

    def test_большой_раздел_по_прежнему_режется_по_годам(self):
        items = _записи([2026] * 30 + [2025] * 30)
        страницы = pag.разбить(items, 24, по_годам=True)
        # Две страницы 2026-го (24 и 6) и две 2025-го (24 и 6): год начинается
        # с новой страницы, и это ровно то, что покупает инкрементальность.
        assert [len(p) for p in страницы] == [24, 6, 24, 6]

    def test_год_не_смешивается_с_соседним(self):
        items = _записи([2026] * 20 + [2025] * 20)
        страницы = pag.разбить(items, 24, по_годам=True)
        assert len(страницы) == 2
        assert {z.year for z in страницы[0]} == {2026}
        assert {z.year for z in страницы[1]} == {2025}

    def test_пустой_раздел_даёт_одну_пустую_страницу(self):
        assert pag.разбить([], 24, по_годам=True) == [[]]
