# --- почему витрина молчит -------------------------------------------------
#
# «Витрины, вероятно, и нет» законно сказать только когда молчание — это
# неразрешённое имя. Истёкший предел ожидания означает обратное: витрина есть и
# отвечает слишком медленно. Измерено 12.10 на zonafilm12.site: при curl 28
# прежняя редакция печатала «витрины, вероятно, и нет», тогда как домен в тот
# момент отдавал посетителю 504 и каталог за 18 с. Такая формулировка читается
# как «смотреть нечего» на падающем сайте, и это хуже молчания.


def test_предел_ожидания_не_читается_как_отсутствие_витрины(модуль, monkeypatch):
    monkeypatch.setattr(модуль, "живой_build",
                        lambda д, таймаут=25: ("", "витрина не ответила (curl 28)"))
    и = модуль.разбор("z.proba.ru", "z-01", "planned")
    assert и["состояние"] == "не измерено", "это не «не открыта»"
    assert "ПРЕДЕЛ ОЖИДАНИЯ" in и["вывод"]
    assert "вероятно, и нет" not in и["вывод"]
    # Статус реестра назван, но как справка, а не как объяснение.
    assert "в реестре planned" in и["вывод"]


