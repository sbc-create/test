"""Место показа обложки определяется по предкам, а не по классу картинки.

Повод измеренный, 23.10: на главной Animedia и карусель `.ahero`, и сетки
подборок в секциях `zsec` носят ОДИН класс картинки `zt__img`. По классу их
различить нельзя, а ширины у них расходятся вдвое (112 против 174 px при окне
390), и строка `sizes` у них разная. Приёмка T335 судит именно по месту
показа, поэтому ошибка здесь тихо превратит «карусель взяла 240» в «что-то
взяло 240».

Проверяются чистые функции: ни сети, ни браузера.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "t335-acceptance.py"

_с = importlib.util.spec_from_file_location("t335_acceptance", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(МОДУЛЬ)


def _строка(предки: list[str], адрес: str = "") -> dict:
    return {"предки": предки, "адрес": адрес}


def test_карусель_узнаётся_по_предкам_а_не_по_классу():
    """Цепочка предков карусели главной Animedia, снятая живьём 23.10."""
    живая = ["zt__p", "zt", "zrl__track", "zrl__vp", "zrl ahero__rl", "ahero"]
    assert МОДУЛЬ.место(_строка(живая)) == "карусель"


def test_сетка_в_секции_узнаётся_отдельно():
    assert МОДУЛЬ.место(_строка(["zt__p", "zt", "grid grid--poster",
                                 "sec-rail"])) == "сетка"
    assert МОДУЛЬ.место(_строка(["zt__p", "zt", "zsec__g", "zsec"])) == "сетка"


def test_подборка_и_серии_не_путаются_с_сеткой():
    assert МОДУЛЬ.место(_строка(["hub__p", "hub__i", "zhub__g"])) == "подборка"
    assert МОДУЛЬ.место(_строка(["aeps__p", "aeps__i"])) == "серии"


def test_без_узнаваемых_предков_место_называется_прочим():
    """«Прочее» честнее, чем отнести к сетке по умолчанию: разрез с «прочим»
    видно в выводе, а молчаливое отнесение — нет."""
    assert МОДУЛЬ.место(_строка([])) == "прочее"
    assert МОДУЛЬ.место(_строка(["something", "else"])) == "прочее"


def test_параметр_ширины_читается_из_адреса():
    assert МОДУЛЬ.параметр("https://x.test/poster/a.webp?w=240") == "240"
    assert МОДУЛЬ.параметр("https://x.test/poster/a.webp?w=720&q=1") == "720"
    assert МОДУЛЬ.параметр("https://x.test/poster/a.webp") == "без"


def test_ключ_постера_это_его_uuid():
    """Сравнение идёт по пересечению постеров, и ключ обязан быть одинаков у
    канарейки и контроля, у которых разные хосты и разные параметры."""
    a = "https://animedia.icu/poster/01a0e48e-3091-7af5-9abe-e2a4056c7426.webp?w=240"
    b = "https://animedia.space/poster/01a0e48e-3091-7af5-9abe-e2a4056c7426.webp"
    assert МОДУЛЬ.ключ({"адрес": a}) == МОДУЛЬ.ключ({"адрес": b})
    assert МОДУЛЬ.ключ({"адрес": "https://x.test/poster/plain.webp"}) is None
