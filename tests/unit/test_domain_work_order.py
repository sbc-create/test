def test_при_отсутствии_свободной_задачи_называется_причина_и_исполнитель():
    данные = {"executor": "линия-очереди", "tasks": [
        {"id": "T-9", "state": "заблокировано", "title": "ждёт",
         "blocked_by": "решение владельца о сведении копий", "owner": "линия-задачи"}]}
    наряд = инс.наряд_домена(данные, "пример.ru", аудит=_Аудит, источники=None,
                             канарейки=None, сегодня=СЕГОДНЯ)
    assert наряд["следующая"] is None
    assert наряд["ожидание"]["вид"] == "вход_владельца"
    assert наряд["ожидание"]["исполнитель"] == "линия-задачи"


def test_выведенный_домен_в_наряд_не_попадает(tmp_path):
    """Выведенные домены в продвижение не возвращаются — и в наряде их нет."""
    реестр = tmp_path / "site-cells.json"
    реестр.write_text(json.dumps({"cells": [
        {"site_id": "x-01", "domain": "живой.ru"},
        {"site_id": "x-02", "domain": "выведенный.ru",
         "withdrawal": {"withdrawn": True}}]}, ensure_ascii=False), encoding="utf-8")
    активные = инс.активные_домены(реестр)
    assert "живой.ru" in активные and "выведенный.ru" not in активные


def test_живые_очереди_разбираются_без_ошибок():
    записи = инс.собрать(КОРЕНЬ / "config" / "domain-queues", сегодня=СЕГОДНЯ)
    assert записи, "ни одного активного домена с очередью"
    for з in записи:
        assert з["домен"] and з["site_id"]
        # Либо есть следующая задача, либо названа причина ожидания — третьего
        # состояния быть не должно: «нет задачи и нет причины» это и есть
        # потерянный домен.
        assert з["следующая"] or з["ожидание"] or not з["задач_всего"], з["домен"]
