"""Один тег canonical в ответе: два источника дают противоречивый сигнал.

Повод. Все проверки пагинации берут canonical ПЕРВЫМ совпадением регулярного
выражения — второго тега для них не существует. А он появляется ровно тогда,
когда canonical ставят два источника: оформление витрины и общий SEO-слой.

Риск назван не в воздух. У `1lordserials1.online` оформление коллекции
canonical не ставит, и его подставляет общий слой по запрошенному адресу
вместе с `page`. Правка коллекций на четырёх Lords добавляет canonical именно
в оформление — то есть источников становится два. SEO-сессия показала кодом,
что слой добавляет тег только при его отсутствии в теле
(`seo_layer.обогатить`: `if b'rel="canonical"' not in тело`), значит дубля по
устройству нет. Проверка всё равно нужна: устройство меняется, а норма
остаётся, и ровно по этой причине у сети уже был случай с ДРУГИМ заголовком —
решение D166, где `/healthz` отдавал `index, follow` от приложения и
`noindex, nofollow` от nginx одновременно. Полагаться на то, что обходчик
выберет «правильный», нельзя — так же, как нельзя было полагаться, что он
выберет более строгий `robots`.

Мерится страница 2, когда она есть: правка оформления добавляет canonical
именно странице N>1. Когда второй страницы нет — первая.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


def прогнать(тело: str):
    м = _модуль()
    шаги: list[tuple[str, bool, str]] = []
    м.норма_одного_canonical(тело, "catalog",
                             lambda и, ок, п: шаги.append((и, ок, п)))
    (шаг,) = шаги
    return шаг


ОДИН = '<link rel="canonical" href="https://x.test/catalog/?page=2"/>'
ДРУГОЙ = '<link rel="canonical" href="https://x.test/catalog/"/>'


def test_один_тег_это_норма():
    _и, ок, подробно = прогнать(f"<head>{ОДИН}</head>")
    assert ок is True
    assert "тегов 1" in подробно


def test_ни_одного_тега_эта_норма_не_судит():
    """Отсутствие canonical ловят другие нормы; здесь считается количество.

    Две проверки об одном — это две причины покраснеть на одном дефекте, и
    отчёт становится труднее читать, а не надёжнее.
    """
    _и, ок, подробно = прогнать("<head></head>")
    assert ок is True
    assert "тегов 0" in подробно


def test_два_тега_с_разными_адресами_это_противоречивый_сигнал():
    """Тот случай, ради которого норма и появилась."""
    _и, ок, подробно = прогнать(f"<head>{ОДИН}{ДРУГОЙ}</head>")
    assert ок is False
    assert "тегов 2" in подробно
    assert "адресов 2" in подробно
    assert "ПРОТИВОРЕЧИВЫЙ СИГНАЛ" in подробно


def test_два_тега_с_одним_адресом_тоже_расхождение():
    """Дубль тега безобиден по смыслу, но означает два источника.

    Сегодня они согласны, завтра один из них изменится — и расхождение
    появится без всякой правки. Поэтому дубль называется, а не прощается.
    """
    _и, ок, подробно = прогнать(f"<head>{ОДИН}{ОДИН}</head>")
    assert ок is False
    assert "тегов 2" in подробно
    assert "дубль тега" in подробно
    assert "ПРОТИВОРЕЧИВЫЙ" not in подробно


def test_три_тега_перечисляются_не_все():
    """В отчёт идут первые три адреса: строка должна остаться читаемой."""
    теги = "".join(
        f'<link rel="canonical" href="https://x.test/p{i}/"/>' for i in range(5))
    _и, ок, подробно = прогнать(f"<head>{теги}</head>")
    assert ок is False
    assert "тегов 5" in подробно
    assert подробно.count("https://x.test/p") == 3


def test_амперсанд_в_сущности_не_создаёт_мнимого_второго_адреса():
    """`&amp;` и `&` — один адрес; иначе норма ругалась бы на кодировку."""
    а = '<link rel="canonical" href="https://x.test/c/?a=1&amp;b=2"/>'
    б = '<link rel="canonical" href="https://x.test/c/?a=1&b=2"/>'
    _и, ок, подробно = прогнать(f"<head>{а}{б}</head>")
    assert ок is False, подробно
    assert "адресов 1" in подробно
    assert "дубль тега" in подробно


def test_порядок_атрибутов_тега_распознаётся():
    """Витрина вправе писать href раньше rel — тег от этого не исчезает."""
    м = _модуль()
    обратный = '<link href="https://x.test/c/" rel="canonical"/>'
    # Выражение требует rel перед href, и это ИЗВЕСТНОЕ ограничение: все
    # витрины сети пишут rel первым (проверено на живых ответах 11.10).
    # Тест закрепляет ограничение явно, чтобы оно не было сюрпризом.
    assert м.ВСЕ_CANONICAL.findall(обратный) == []


def test_норма_зовётся_из_замера_раздела():
    источник = СЦЕНАРИЙ.read_text(encoding="utf-8")
    assert "норма_одного_canonical(тело, где, шаг)" in источник
    assert "норма_одного_canonical(т1, где, шаг)" in источник
