"""REQ-CELL-FACET-LANDING: страницы страны и года называют себя, как и жанра.

Измерено 2026-10-18 на `lordserial.su`, уже ПОСЛЕ правки жанров:

    /country/velikobritaniya/  title «Каталог», h1 «Каталог»,
                               canonical /catalog/, 48 карточек
    /year/2026/                то же
    блок «Страна» на карточке произведения: ссылок /country/ — НОЛЬ,
                               страна показана текстом «Великобритания»,
                               а страница страны отвечает 200

То есть ровно та картина, что была у жанров: фасет отдаёт отобранный каталог,
объявляет себя копией полного и нигде себя не называет; на карточке фасет
показан текстом, хотя его страница существует.

Осторожности те же: имя из индекса витрины (не придумывается), ссылка только
на известный код (иначе маршрут отдаёт 404), канон — путь фасета ТОЛЬКО когда
он единственный выбранный на первой странице.

Год — не имя, а число: заголовок «2026» честен. Приставка вида «Фильмы 2026»
здесь не ставится — раздел может быть любым, и обещать вид записей заголовком
нельзя.
"""
from __future__ import annotations

from pathlib import Path

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _список_лордс() -> str:
    начало = ТЕКСТ.index("class ВидЛордс(Вид):")
    кусок = ТЕКСТ[начало:ТЕКСТ.index("class ВидЗона(Вид):", начало)]
    и = кусок.index("    def список(self, разд: str, зпр: dict) -> str:")
    return кусок[и:кусок.index("\n    def ", и + 10)]


def _факты() -> str:
    начало = ТЕКСТ.index("def факты(вид: Вид, запись: dict, деталь: dict)")
    return ТЕКСТ[начало:ТЕКСТ.index("\ndef ", начало + 10)]


def test_имя_страны_берётся_из_индекса():
    тело = _список_лордс()
    assert 'self.индекс.get("country_names")' in тело
    assert "титул = страна_имя[:1].upper() + страна_имя[1:]" in тело


def test_год_в_заголовке_это_число_без_приставки():
    тело = _список_лордс()
    assert "титул = str(год_знач)" in тело
    # Отрицательный контроль: приставка обещала бы вид записей, которого
    # страница не гарантирует.
    for выдумка in ('f"Фильмы {', 'f"Сериалы {', 'f"Год {'):
        assert выдумка not in тело, выдумка


def test_канон_у_каждого_фасета_свой():
    тело = _список_лордс()
    for образец in ('f"/genre/{жанр_код}/"', 'f"/country/{страна_код}/"',
                    'f"/year/{год_знач}/"'):
        assert образец in тело, образец


def test_канон_только_при_единственном_фасете():
    """Главная осторожность: `?country=X&year=Y` — другая страница."""
    тело = _список_лордс()
    assert "if стр == 1:" in тело
    for фасет in ("genre", "country", "year"):
        assert f'not _без("{фасет}")' in тело, фасет


def test_страна_на_карточке_ссылкой():
    тело = _факты()
    assert 'getattr(вид, "индекс", {}).get("country")' in тело
    assert 'f\'<a href="/country/{код_страны}/">\'' in тело


def test_неизвестная_страна_остаётся_текстом():
    """Маршрут отдаёт 404 на неизвестный код — ссылка вела бы в никуда."""
    тело = _факты()
    assert "код_страны in индекс_стран" in тело
    assert "ссылки_стран.append(html.escape(имя_страны))" in тело


def test_пустой_список_стран_не_ломает_блок():
    """Отрицательный контроль: раньше пустой список давал пустую строку, и
    `добавить` её отбрасывал. Поведение обязано сохраниться."""
    тело = _факты()
    assert 'добавить("Страна", "")' in тело
