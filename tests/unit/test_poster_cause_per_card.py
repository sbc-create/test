"""Причина отсутствующего постера ПО КАЖДОЙ карточке: четыре версии владельца.

Повод. Владелец назвал четыре возможные причины — данные, соответствие тайтла,
адрес изображения, загрузка — и потребовал ответ по КАЖДОЙ карточке, а не по
совокупности. Измерено 20.10: на `lordserial33.biz` 14 заглушек, на
`zonafilm.space` 7, на `zonafilm12.site` 5, и у всех 26 причина одна — ДАННЫЕ:
`poster_url` пуст и у поставщика, и в доставленном каталоге.

Отрицательные контроли, названные заранее:

* **карточка с рабочим постером причины не получает.** Иначе признак говорил
  бы «виновно всё» и не различал ничего. В живом проходе контролем берутся три
  карточки ТЕХ ЖЕ полок, у которых постер есть, и все три дают «НЕ НАЙДЕНА»;
* **у записи без `poster_url` версии «адрес» и «загрузка» НЕ ПРОЙДЕНЫ, а НЕ
  ПРИМЕНИМЫ.** «Загрузка в порядке» при отсутствующем адресе читалось бы как
  исправность;
* **причина называется ПЕРВАЯ сработавшая**, в порядке сопоставление → данные →
  адрес → загрузка: спор о картинке у карточки, показывающей чужое
  произведение, преждевременен;
* **тесты в сеть не ходят**: загрузчик подставляется.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "poster_cause_per_card", КОРЕНЬ / "automation/local/poster-cause-per-card.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

ИД = "01a145fb-0000-7000-8000-000000000001"
ПОСТЕР = f"https://poster.cdnvideohub.com/{ИД}.webp"


def _поставщик(**п) -> dict:
    з = {"id": ИД, "name": "Между строк", "poster_url": ПОСТЕР}
    з.update(п)
    return {ИД: з}


def _каталог(**п) -> dict:
    з = {"slug": "mezhdu-strok-2", "entity_id": ИД, "title": "Между строк",
         "poster": ПОСТЕР}
    з.update(п)
    return з


def _разбор(*, каталог=None, деталь=None, поставщик=None, загрузчик=None):
    return ИНСТР.разобрать_карточку(
        "mezhdu-strok-2",
        запись_каталога=_каталог() if каталог is None else каталог,
        деталь=деталь or {},
        поставщик=_поставщик() if поставщик is None else поставщик,
        домен="lordserial33.biz",
        загрузчик=загрузчик or (lambda url: {"url": url, "код": 200,
                                             "тип": "image/webp",
                                             "байт": 12345}))


# --- четыре версии -------------------------------------------------------------

def test_рабочая_карточка_причины_не_получает():
    """Главный отрицательный контроль: признак обязан уметь говорить «нет»."""
    итог = _разбор()
    assert итог["причина"] == "НЕ НАЙДЕНА"
    assert "в порядке" in итог["пояснение"]


def test_пустой_постер_везде_это_данные():
    итог = _разбор(каталог=_каталог(poster=""),
                   поставщик=_поставщик(poster_url=None))
    assert итог["причина"] == "ДАННЫЕ"
    assert итог["версии_не_применимы"] == ["АДРЕС ИЗОБРАЖЕНИЯ", "ЗАГРУЗКА"]


def test_записи_нет_у_поставщика_это_сопоставление():
    итог = _разбор(поставщик={})
    assert итог["причина"] == "СОПОСТАВЛЕНИЕ"
    assert "нет в ответе поставщика" in итог["пояснение"]


def test_название_расходится_это_сопоставление():
    итог = _разбор(поставщик=_поставщик(name="Вечная любовь", poster_url=None))
    assert итог["причина"] == "СОПОСТАВЛЕНИЕ", итог["пояснение"]
    assert "название расходится" in итог["пояснение"]


def test_нет_id_у_карточки_это_сопоставление():
    итог = _разбор(каталог=_каталог(entity_id=""))
    assert итог["причина"] == "СОПОСТАВЛЕНИЕ"


def test_чужой_хост_это_адрес():
    итог = _разбор(каталог=_каталог(poster="https://example.net/p.webp"),
                   поставщик=_поставщик(poster_url="https://example.net/p.webp"))
    assert итог["причина"] == "АДРЕС ИЗОБРАЖЕНИЯ"
    assert итог["версии_не_применимы"] == ["ЗАГРУЗКА"]


def test_адрес_без_схемы_это_адрес():
    итог = _разбор(каталог=_каталог(poster="poster.cdnvideohub.com/x.webp"),
                   поставщик=_поставщик(poster_url="poster.cdnvideohub.com/x.webp"))
    assert итог["причина"] == "АДРЕС ИЗОБРАЖЕНИЯ"


def test_не_изображение_по_пути_это_адрес():
    плохой = "https://poster.cdnvideohub.com/x.html"
    итог = _разбор(каталог=_каталог(poster=плохой),
                   поставщик=_поставщик(poster_url=плохой))
    assert итог["причина"] == "АДРЕС ИЗОБРАЖЕНИЯ"


def test_локальный_путь_витрины_адресом_годен():
    итог = _разбор(каталог=_каталог(poster="/poster/x.webp"),
                   поставщик=_поставщик(poster_url="/poster/x.webp"))
    assert итог["причина"] == "НЕ НАЙДЕНА"
    assert итог["загрузка"]["url"].startswith("https://lordserial33.biz/poster/")


def test_код_не_двести_это_загрузка():
    итог = _разбор(загрузчик=lambda url: {"url": url, "код": 404, "тип": "",
                                          "байт": 0})
    assert итог["причина"] == "ЗАГРУЗКА"
    assert "404" in итог["пояснение"]


def test_не_картинка_в_ответе_это_загрузка():
    итог = _разбор(загрузчик=lambda url: {"url": url, "код": 200,
                                          "тип": "text/html", "байт": 500})
    assert итог["причина"] == "ЗАГРУЗКА"
    assert "не изображение" in итог["пояснение"]


def test_нулевая_длина_это_загрузка():
    итог = _разбор(загрузчик=lambda url: {"url": url, "код": 200,
                                          "тип": "image/webp", "байт": 0})
    assert итог["причина"] == "ЗАГРУЗКА"
    assert "нулевую длину" in итог["пояснение"]


# --- порядок версий ------------------------------------------------------------

def test_сопоставление_проверяется_раньше_данных():
    """У карточки с чужим произведением спор о картинке преждевременен."""
    итог = _разбор(каталог=_каталог(poster=""),
                   поставщик=_поставщик(name="Вечная любовь", poster_url=None))
    assert итог["причина"] == "СОПОСТАВЛЕНИЕ"


def test_данные_проверяются_раньше_адреса():
    итог = _разбор(каталог=_каталог(poster=""),
                   поставщик=_поставщик(poster_url=""))
    assert итог["причина"] == "ДАННЫЕ"


def test_постер_из_подробностей_идёт_в_счёт():
    """Каталог может быть пуст, а подробности нести живой постер."""
    итог = _разбор(каталог=_каталог(poster=""),
                   деталь={"id": ИД, "poster_url": ПОСТЕР},
                   поставщик=_поставщик(poster_url=None))
    assert итог["причина"] == "НЕ НАЙДЕНА"


# --- пределы -------------------------------------------------------------------

def test_незнакомый_домен_отвергается(capsys):
    код = ИНСТР.главное(["--domain", "example.org"])
    assert код == 2
    assert "нет в перечне витрин" in capsys.readouterr().out


def test_годность_адреса_называет_причину():
    годен, почему = ИНСТР.адрес_годен("")
    assert not годен and почему == "адреса нет"
    годен, почему = ИНСТР.адрес_годен(ПОСТЕР)
    assert годен and "poster.cdnvideohub.com" in почему
