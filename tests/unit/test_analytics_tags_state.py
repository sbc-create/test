    текст = (КОРЕНЬ / "automation" / "local" / "analytics-tags-state.py").read_text(
        encoding="utf-8")
    assert "цели МОГУТ идти:   {len(могут)}" in текст
    assert "len(записи) - len(без_целей)}\")" not in текст
