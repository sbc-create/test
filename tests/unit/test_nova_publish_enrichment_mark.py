"""Признак обогащения: «не спрашивали» и «источник не отдал» — разные случаи.

Повод. «Жанров нет» означало сразу две разные вещи:

* про запись ещё НЕ СПРАШИВАЛИ у detail API — закроется добором;
* источник жанров НЕ ОТДАЛ — не закроется никогда, а выдумывать их запрещено.

Измерено 2026-10-11: на lords-02 2 277 записей первого вида и 17 второго. По
самому снимку их не различить — у 8 из 17 «спрошенных» поля выглядят точно так
же, как у неспрошенных. Знает разницу только цикл сборки, который читает кэш, и
до сих пор это знание терялось.

Почему это важно для допуска к индексации: у неспрошенных записей пусто ВСЁ, а
не только жанры — описание 0%, сезоны 0%, страны 0% против 73,8%, 70,7% и 54,9%
у обогащённых. Правило допуска, не различающее эти случаи, открывало бы
индексации каждую новую непрогруженную партию в тот момент, когда её страницы
беднее всего.

Как проверяется. Издатель живёт в своём дереве, и часть его зависимостей
(`canonical_projection`) есть только там, поэтому проверка идёт подпроцессом:
корень издателя впереди в `sys.path` — для зависимостей, а сам проверяемый файл
берётся ИЗ ВЕТКИ. Иначе проверка смотрела бы на выложенный прежний код и о
правке молчала.
"""
from __future__ import annotations

import json
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
КОРЕНЬ_ИЗДАТЕЛЯ = Path("/srv/site-factory/repo")
МОДУЛЬ_ВЕТКИ = КОРЕНЬ / "factory" / "lords" / "nova_publish.py"

pytestmark = pytest.mark.skipif(
    not (КОРЕНЬ_ИЗДАТЕЛЯ / "factory" / "lords" / "canonical_projection.py").is_file(),
    reason="зависимостей издателя нет в этом окружении")

СЦЕНАРИЙ = textwrap.dedent('''
    import importlib.util, json, sys
    корень_издателя, модуль_ветки, вид = sys.argv[1], sys.argv[2], sys.argv[3]
    sys.path.insert(0, корень_издателя)

    спец = importlib.util.spec_from_file_location("nova_publish_ветка", модуль_ветки)
    м = importlib.util.module_from_spec(спец)
    sys.modules["nova_publish_ветка"] = м
    спец.loader.exec_module(м)

    ИД = "01a12348-f23e-7000-8000-00000000aaaa"

    def снимок():
        запись = {"external_id": ИД, "name": "Проба обогащения", "year": 2024,
                  "created_at": "2026-10-01T10:00:00Z"}
        return м.Снимок(записи={ИД: запись}, получен="2026-10-11T03:16:25Z",
                        отпечаток="проба" * 8)

    def деталь(**поля):
        основа = {"id": ИД, "name": "Проба обогащения", "original_name": None,
                  "type": "tv", "year": 2024, "description": "",
                  "poster_url": "https://poster/x.webp", "genres": [],
                  "countries": [], "seasons": [], "sources": [],
                  "external_ids": {"myanimelist": "1"}}
        основа.update(поля)
        return основа

    читатели = {
        # Файла кэша нет — про запись не спрашивали.
        "pending": lambda кэш, ид: None,
        # Пустой словарь — это ОТВЕТ, а не его отсутствие.
        "fetched-empty": lambda кэш, ид: {},
        # Спросили, источник отдал описание и страну, но не жанры.
        "fetched-no-genres": lambda кэш, ид: деталь(
            description="Полное описание из detail, достаточной длины "
                        "для того, чтобы считаться описанием.",
            countries=["СССР"]),
        # Короткий текст и заглушка описанием НЕ считаются: иначе покрытие
        # описаний отчитывалось бы о том, чего нет. Порог — 40 знаков.
        "fetched-short": lambda кэш, ид: деталь(
            description="Слишком коротко", countries=["СССР"]),
        "fetched-stub": lambda кэш, ид: деталь(
            description="описание отсутствует", countries=["СССР"]),
        # Обычный обогащённый ответ.
        "fetched-full": lambda кэш, ид: деталь(
            genres=["комедия"], countries=["Япония"]),
    }

    реестр = м.РеестрСлагов(по_ид={ИД: "proba"}, по_слагу={"proba": ИД})
    каталог, подробности, ст = м.собрать_сайт(
        снимок=снимок(), реестр=реестр, детали_кэш=".", site_id="lords-02",
        читатель=читатели[вид])
    (запись,) = подробности["details"].values()
    print(json.dumps({"enrichment": запись.get("enrichment"),
                      "genres": запись.get("genres"),
                      "countries": запись.get("countries"),
                      "description": (запись.get("description") or "").strip(),
                      "поля": sorted(запись)}, ensure_ascii=False))
''')


def прогон(вид: str) -> dict:
    г = subprocess.run([sys.executable, "-c", СЦЕНАРИЙ, str(КОРЕНЬ_ИЗДАТЕЛЯ),
                        str(МОДУЛЬ_ВЕТКИ), вид],
                       capture_output=True, text=True, timeout=300,
                       cwd=str(КОРЕНЬ))
    assert г.returncode == 0, г.stdout + г.stderr
    return json.loads(г.stdout.strip().splitlines()[-1])


def test_не_спрашивали_помечено_pending():
    итог = прогон("pending")
    assert итог["enrichment"] == "pending"
    # Пустые значения в запись не попадают вовсе — это действующая семантика
    # слияния («пустое не отменяет уже известное»), поэтому отсутствие жанров
    # выглядит как отсутствие КЛЮЧА, а не как пустой список. Признак
    # обогащения нужен именно поэтому: ключа нет, и причина по записи неясна.
    assert not итог["genres"], итог["genres"]
    assert "enrichment" in итог["поля"]


def test_пустой_ответ_источника_это_не_неспрошенность():
    """Разница тонкая и важная.

    `{}` от читателя означает «спросили, получили пустоту», `None` — «файла
    кэша нет». Если смешать, все 17 записей lords-02 с пустым ответом станут
    «ещё не спрошены», и добор будет обещать то, чего не произойдёт.
    """
    assert прогон("fetched-empty")["enrichment"] == "fetched"


def test_спросили_и_жанров_нет_помечено_fetched():
    итог = прогон("fetched-no-genres")
    assert итог["enrichment"] == "fetched"
    assert not итог["genres"], "жанров у источника нет — и не появилось"
    assert итог["description"].startswith("Полное описание из detail")
    assert итог["countries"] == ["СССР"], "непустое значение источника дошло"


@pytest.mark.parametrize("вид", ["fetched-short", "fetched-stub"])
def test_короткое_описание_и_заглушка_не_считаются_описанием(вид):
    """Действующая строгость издателя, и здесь она не ослабляется.

    Порог 40 знаков и перечень заглушек («описание отсутствует» и подобные)
    существуют ровно для того, чтобы покрытие описаний не отчитывалось о том,
    чего нет. Проверка стоит рядом с признаком обогащения намеренно: у
    «описания нет» тоже две причины, и смешивать их нельзя.
    """
    итог = прогон(вид)
    assert итог["enrichment"] == "fetched"
    assert итог["description"] == "", "заглушка или обрывок стали описанием"
    assert итог["countries"] == ["СССР"], "а страна дошла: порога у неё нет"


def test_обогащённая_запись_тоже_fetched():
    итог = прогон("fetched-full")
    assert итог["enrichment"] == "fetched"
    assert итог["genres"] == ["комедия"]


def test_признак_ничего_не_заполняет():
    """Он объясняет отсутствие, а не подменяет его значениями."""
    итог = прогон("pending")
    assert not итог["genres"], "жанры выдуманы"
    assert not итог["countries"], "страны выдуманы"
    assert итог["description"] == ""


def test_карточка_остаётся_полной():
    итог = прогон("fetched-full")
    for поле in ("id", "name", "type", "year", "poster_url", "genres",
                 "countries", "enrichment"):
        assert поле in итог["поля"], поле
    # `sources` в этой пробе пуст, а пустое в запись не попадает: проверять
    # его наличие значило бы сторожить не ту семантику.
    assert "sources" not in итог["поля"]
