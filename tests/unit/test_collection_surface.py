"""Страница коллекции в замере: ключ берётся из хаба витрины, а не придумывается.

Повод. `/collection/<ключ>/` — такая же списковая поверхность с пагинацией,
как каталог или раздел вида, но её адрес нельзя записать в перечень: ключи у
витрин разные (`comedy_series`, `current_season`, `genre_boevik`, `action`…).
Пока поверхность не мерилась, у пяти витрин canonical второй страницы указывал
на первую, и 48-60 НОВЫХ карточек на каждой второй странице были доступны
только через неё; у двух Zona вдобавок `?page=9999` отдавал 200 с пустым
шаблоном (soft 404, §1 п.8), а `?page=0` и `?page=abc` — копию первой.

Замер 11.10, по которому сделан выбор «одной коллекции довольно»: поведение
canonical у витрины ОДНО на все её коллекции. У `1lordserials1.online`
self-canonical на всех двенадцати, у `lordserial33.biz` «на раздел» на всех
восьми, у `zonafilm.space` — на всех двенадцати. Различие доменное, не по
коллекции, поэтому мерить каждую значит платить десяток запросов за один и тот
же ответ.

Выбор первой ссылки по алфавиту — ради повторяемости: «какая попалась» дало бы
замер, который нельзя сравнить с прошлым.

Правило CLOSED_WORLD здесь действует буквально: ключ не выдумывается, а
читается из хаба самой витрины. Пустой хаб означает «поверхности нет», а не
«подставь что-нибудь».
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

ХАБ = "https://x.test/collections/"
ПУСТО = "<html></html>"


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    def __init__(self, таблица: dict):
        self.таблица = таблица
        self.запрошено: list[str] = []

    def __call__(self, url: str, таймаут: int = 45):
        self.запрошено.append(url)
        код, тело, итоговый = self.таблица.get(url, ("404", ПУСТО, url))
        return код, тело, {"итоговый-адрес": итоговый}


def хаб(ключи: list[str]) -> str:
    return "".join(f'<a class="c" href="/collection/{к}/">{к}</a>'
                   for к in ключи)


def test_ключ_берётся_из_хаба():
    м = _модуль()
    м.достать = Сеть({ХАБ: ("200", хаб(["current_season", "top_rated"]), ХАБ)})
    путь, причина = м.коллекция_витрины("x.test")
    assert путь == "/collection/current_season/"
    assert "коллекций в хабе 2" in причина


def test_выбор_детерминированный_первый_по_алфавиту():
    """«Какая попалась» дало бы замер, который нельзя сравнить с прошлым."""
    м = _модуль()
    м.достать = Сеть({ХАБ: ("200", хаб(["top_rated", "action", "mini_series"]),
                            ХАБ)})
    assert м.коллекция_витрины("x.test")[0] == "/collection/action/"


def test_порядок_ссылок_в_хабе_на_выбор_не_влияет():
    м = _модуль()
    первый = Сеть({ХАБ: ("200", хаб(["b_two", "a_one"]), ХАБ)})
    второй = Сеть({ХАБ: ("200", хаб(["a_one", "b_two"]), ХАБ)})
    м.достать = первый
    один = м.коллекция_витрины("x.test")[0]
    м.достать = второй
    два = м.коллекция_витрины("x.test")[0]
    assert один == два == "/collection/a_one/"


def test_повторы_ссылок_не_мешают():
    """Хаб может вести на одну коллекцию и карточкой, и ссылкой в списке."""
    м = _модуль()
    м.достать = Сеть({ХАБ: ("200", хаб(["zed", "zed", "alpha"]), ХАБ)})
    assert м.коллекция_витрины("x.test")[0] == "/collection/alpha/"


def test_пустой_хаб_означает_отсутствие_поверхности():
    """Пустое поле — не разрешение подставить значение по умолчанию.

    И это ФАКТ О ВИТРИНЕ: хаб ответил, ссылок в нём нет.
    """
    м = _модуль()
    м.достать = Сеть({ХАБ: ("200", "<html>нет коллекций</html>", ХАБ)})
    путь, причина = м.коллекция_витрины("x.test")
    assert путь is None
    assert причина.startswith("нет")


def test_хаб_отвечающий_не_двумястами_это_НЕ_ИЗМЕРЕНО():
    """Разницу между «нет» и «не смог» смешивать нельзя.

    Сначала я написал пробу, считавшую любую неудачу отсутствием, и она
    записала zonafilm12.site как витрину без коллекций. Коллекций у неё
    двенадцать, а один запрос не дошёл. Доклад «поверхности нет» вместо «не
    смог измерить» — та же ошибка, что метрика 0 вместо «не измерено».
    """
    м = _модуль()
    м.достать = Сеть({ХАБ: ("308", ПУСТО, "https://x.test/catalog/")})
    путь, причина = м.коллекция_витрины("x.test")
    assert путь is None
    assert причина.startswith("не измерено")
    assert "308" in причина


