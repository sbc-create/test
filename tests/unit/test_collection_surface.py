def test_отсутствие_коллекций_не_расхождение():
    """Хаб ответил, ссылок нет — факт о витрине, не расхождение."""
    м = _модуль()
    основа = "https://x.test/catalog/"
    м.достать = Сеть({основа: ("404", ПУСТО, основа),
                      ХАБ: ("200", "<html>пусто</html>", ХАБ)})
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_пагинации("x.test", lambda и, ок, п: шаги.append((и, ок, п)))
    (строка,) = [ш for ш in шаги if "[коллекция]" in ш[0]]
    assert строка[1] is True, строка
    assert строка[2].startswith("нет")


def test_неизмеренная_поверхность_это_расхождение():
    """«Не смог измерить» обязано быть видно, а не выглядеть как «нечего».

    Иначе недоступный хаб тихо выключает замер целой поверхности — и отчёт
    скажет «все проверки пройдены», не проверив ничего.
    """
    м = _модуль()
    основа = "https://x.test/catalog/"
    м.достать = Сеть({основа: ("404", ПУСТО, основа)})
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_пагинации("x.test", lambda и, ок, п: шаги.append((и, ок, п)))
    (строка,) = [ш for ш in шаги if "[коллекция]" in ш[0]]
    assert строка[1] is False, строка
    assert строка[2].startswith("не измерено")


def test_коллекция_мерится_теми_же_нормами():
    """Не отдельная проверка, а тот же набор норм: п.2, п.3, п.8.

    Иначе у поверхности появился бы свой, более слабый набор требований — а
    она ничем не отличается от раздела, кроме способа узнать её адрес.
    """
    м = _модуль()
    путь = "/collection/action/"
    основа = f"https://x.test{путь}"
    первая = ('<link rel="canonical" href="' + основа + '"/>'
              + "".join(f'<a href="/title/one-{i}">' for i in range(48)))
    вторая = ('<link rel="canonical" href="' + основа + '"/>'
              + "".join(f'<a href="/title/two-{i}">' for i in range(48)))
    таблица = {
        ХАБ: ("200", хаб(["action"]), ХАБ),
        основа: ("200", первая, основа),
        основа + "?page=1": ("200", первая, основа),
        основа + "?page=2": ("200", вторая, основа + "?page=2"),
        основа + "?page=9999": ("404", ПУСТО, основа + "?page=9999"),
        основа + "?page=0": ("404", ПУСТО, основа + "?page=0"),
        основа + "?page=-1": ("404", ПУСТО, основа + "?page=-1"),
        основа + "?page=abc": ("404", ПУСТО, основа + "?page=abc"),
    }
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_раздела("x.test", путь,
                    lambda и, ок, п: шаги.append((и, ок, п)))
    имена = [и for и, _ок, _п in шаги]
    assert any("номер за пределом" in и for и in имена), имена
    assert any("?page=1" in и for и in имена), имена
    assert any("canonical страницы 2" in и for и in имена), имена
    # Ровно тот дефект, что нашёлся у пяти витрин: canonical страницы 2 на
    # раздел при 48 новых карточках.
    (_и, _ок, подробно) = [ш for ш in шаги if "canonical страницы 2" in ш[0]][0]
    assert "новых карточек 48" in подробно


