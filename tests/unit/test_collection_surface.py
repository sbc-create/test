def test_ограниченный_проход_коллекцию_не_трогает():
    """`--разделы` для быстрой сверки не должен тянуть лишние запросы."""
    м = _модуль()
    основа = "https://x.test/catalog/"
    сеть = Сеть({основа: ("404", ПУСТО, основа)})
    м.достать = сеть
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_пагинации("x.test", lambda и, ок, п: шаги.append((и, ок, п)),
                      разделы=("/catalog/",))
    assert not [ш for ш in шаги if "[коллекция]" in ш[0]]
    assert ХАБ not in сеть.запрошено
