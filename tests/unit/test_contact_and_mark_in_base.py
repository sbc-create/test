"""Обязательные по контракту сети элементы живут в ОСНОВЕ, а не ниже неё.

Повод измерен 26.10 на двадцати одной привязке шаблона. Две правки стояли
только в копиях проектов партии K2 и отсутствовали в каноническом
`automation/host/lords-frontend.py`:

* `_контакт_подвала` — адрес обратной связи, который владелец подтвердил один
  на всю сеть и который обязан быть виден посетителю на КАЖДОЙ странице;
* `_метка_по_имени` — пара букв знака в шапке по имени витрины (сериальные
  домены показывали «LF» от имени семейства).

Следствие измерено, а не предположено: новая пятёрка (lords-18…22) закреплена
от канона, и у неё этих правок не было ни одной; перезакрепление живых восьми
витрин партии K2 на канон, наоборот, стёрло бы их с работающих сайтов. Это
ровно тот случай, который `docs/COMMON_FIX_INHERITANCE.md` запрещает: общая
правка жила ниже канонического слоя и новым экземпляром не наследовалась.

Проверка здесь — ОТРИСОВКОЙ на штатной оснастке `lords_runtime_harness`: текст
файла уже один раз обманул (инструмент отчитался «ок», увидев вызов в одном
подвале из трёх).
"""
from __future__ import annotations

import pathlib
import subprocess
import sys

import pytest

import lords_runtime_harness as оснастка

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМ = КОРЕНЬ / "automation" / "host" / "lords-frontend.py"
АДРЕС = "proba@example.invalid"

#: Семейство → (имя витрины, метод подвала). Трое — потому что подвалов в файле
#: трое; «хотя бы один» здесь не считается, именно на этом прежняя проверка и
#: отвечала «ок» при двух неприведённых полосах.
#: Версия оформления указана там, где вид существует только в переработанном:
#: вид Animedia объявлен для 1.2.x, на умолчании 1.0.2 поднялся бы ВидЛордс —
#: и проверка молча шла бы по чужому подвалу.
СЕМЕЙСТВА = [("lords", "_подвал", None), ("zona", "_подвал_зона", "1.2.0"),
             ("animedia", "подвал", "1.2.2")]


def _стенд(tmp_path, monkeypatch, семейство: str, *, адрес: str = АДРЕС,
           имя: str = "lordserial.su", оформление: str | None = None):
    с = оснастка.Стенд(tmp_path, site_id=f"{семейство}-test",
                       имя_витрины=имя, семейство=семейство,
                       версия_оформления=оформление)
    с.записать_каталог([оснастка.запись("skotty", title="Скотты", kind="Сериал")])
    с.записать_подробности([оснастка.подробность("skotty", type_="series")])
    с.записать_плеер()
    if адрес:
        monkeypatch.setenv("SITE_CONTACT_EMAIL", адрес)
    else:
        monkeypatch.delenv("SITE_CONTACT_EMAIL", raising=False)
    модуль = оснастка.загрузить(с, monkeypatch)
    return модуль, оснастка.вид(модуль)


@pytest.mark.parametrize("семейство,метод,оформление", СЕМЕЙСТВА)
def test_адрес_обратной_связи_выходит_в_подвале(tmp_path, monkeypatch,
                                                семейство, метод, оформление):
    модуль, вид = _стенд(tmp_path, monkeypatch, семейство, оформление=оформление)
    try:
        разметка = getattr(вид, метод)()
        assert АДРЕС in разметка, f"{семейство}.{метод}: адреса нет в разметке"
        assert f'href="mailto:{АДРЕС}"' in разметка, семейство
    finally:
        оснастка.выгрузить(модуль)


@pytest.mark.parametrize("семейство,метод,оформление", СЕМЕЙСТВА)
def test_пустой_адрес_не_подставляет_умолчание(tmp_path, monkeypatch,
                                               семейство, метод, оформление):
    """Выдуманный адрес хуже отсутствующего: письма по нему уходят в никуда."""
    модуль, вид = _стенд(tmp_path, monkeypatch, семейство, адрес="",
                         оформление=оформление)
    try:
        разметка = getattr(вид, метод)()
        assert "mailto:" not in разметка, семейство
        assert "Обратная связь" not in разметка, семейство
    finally:
        оснастка.выгрузить(модуль)


def test_знак_в_шапке_от_имени_витрины_а_не_семейства(tmp_path, monkeypatch):
    модуль, _ = _стенд(tmp_path, monkeypatch, "lords")
    try:
        метка = модуль._метка_по_имени
        assert метка("lordserial.su") == "LS"
        assert метка("lordfilm.group") == "LF"
        assert метка("zonafilm.cc") == "ZO"
        # Пустой результат — отказ, а не заглушка: вызывающий берёт метку
        # семейства.
        assert метка("") == ""
    finally:
        оснастка.выгрузить(модуль)


def test_знак_доходит_до_разметки_шапки(tmp_path, monkeypatch):
    модуль, вид = _стенд(tmp_path, monkeypatch, "lords", имя="lordserial.su")
    try:
        страница = вид.оболочка("<main></main>", "Проба", "/")
        assert '<span class="hd__mark" aria-hidden="true">LS</span>' in страница
        # И адрес на той же странице: контракт требует его на КАЖДОЙ, а не
        # только в отдельно вызванном подвале.
        assert f'href="mailto:{АДРЕС}"' in страница
    finally:
        оснастка.выгрузить(модуль)


def _прогон(аргументы: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, *аргументы], cwd=КОРЕНЬ,
                          capture_output=True, text=True, timeout=180)


def test_канон_приведён_общим_инструментом_контакта():
    """Сторож от возврата: правка обязана ОСТАТЬСЯ в основе."""
    и = _прогон(["automation/host/apply-contact-footer.py", "--check",
                 str(РАНТАЙМ.relative_to(КОРЕНЬ))])
    assert и.returncode == 0, и.stdout + и.stderr


def test_канон_приведён_набором_правок_партии():
    и = _прогон(["automation/local/fix-lords-cell-ui.py", "--file",
                 str(РАНТАЙМ.relative_to(КОРЕНЬ)), "--check"])
    assert и.returncode == 0, и.stdout + и.stderr


def test_одного_прогона_набора_достаточно(tmp_path):
    """Второй прогон не имеет права что-то донастраивать.

    Измерено 26.10: пары правила крошек стояли ПОСЛЕ общей замены цвета, и
    один прогон оставлял текст крошек на @DIM@ — контраст 4.38 при пороге 4.5,
    то есть ровно тот дефект, который набор и закрывает. Доводил до @INK@
    только второй прогон, а в выпуск уходит результат первого.
    """
    копия = tmp_path / "lords-frontend.py"
    копия.write_text(РАНТАЙМ.read_text(encoding="utf-8"), encoding="utf-8")
    первый = _прогон(["automation/local/fix-lords-cell-ui.py", "--file", str(копия)])
    assert первый.returncode == 0, первый.stdout + первый.stderr
    после_первого = копия.read_text(encoding="utf-8")
    второй = _прогон(["automation/local/fix-lords-cell-ui.py", "--file", str(копия)])
    assert второй.returncode == 0, второй.stdout + второй.stderr
    assert копия.read_text(encoding="utf-8") == после_первого, \
        "второй прогон изменил файл — один прогон набора недостаточен"


def test_крошки_не_приглушены_на_своей_полосе():
    """Цвет текста крошек — @INK@: на потемневшем фоне @DIM@ не проходит порог."""
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    assert (".crumbs{background:@LINE@;border-bottom:1px solid @LINE@;"
            "font-size:12px;color:@INK@") in текст
