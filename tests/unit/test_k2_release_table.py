"""Таблица выпуска: выбор витрин и вывод остаточного блокера.

Проверки не выходят в сеть и не зовут узел: проверяется решающая часть —
какие витрины попадают в таблицу и как из измеренных столбцов выводится
остаточный блокер. Именно здесь возможна тихая ошибка: таблица, которая
показывает «нет блокера» у витрины без сертификата, хуже отсутствующей таблицы.
"""
import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "k2_release_table", КОРЕНЬ / "automation" / "local" / "k2-release-table.py")
инс = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(инс)

ЦЕЛЬ = инс.ЦЕЛЕВОЙ_АДРЕС


def строка(**поля) -> dict:
    основа = {"dns": ЦЕЛЬ, "https": "есть, с www", "service": "active",
              "publisher": "10454", "publisher_expected": "10454"}
    основа.update(поля)
    return основа


def test_в_таблицу_идут_только_витрины_своего_узла():
    витрины = инс.партия()
    assert len(витрины) == 8, [в["site_id"] for в in витрины]
    assert [в["site_id"] for в in витрины] == [f"lords-{n}" for n in range(10, 18)]
    # Ожидаемый номер берётся из учёта, а не из кода инструмента.
    assert {в["publisher_expected"] for в in витрины} == {"10454"}


def test_блокер_называет_первое_незакрытое():
    assert инс.блокер(строка(dns="45.131.182.225")) == "DNS → TLS"
    assert инс.блокер(строка(https="нет")) == "TLS"
    assert инс.блокер(строка(https="есть, без www")) == "TLS"
    assert инс.блокер(строка(service="inactive")) == "служба"
    assert инс.блокер(строка(publisher="10238")) == "номер издателя"
    assert инс.блокер(строка()) == "нет"


def test_сертификат_без_www_не_считается_готовым():
    """Блок 443 заготовки несёт имя www и один каталог сертификата."""
    assert инс.блокер(строка(https="есть, без www")) == "TLS"


def test_непрочитанный_столбец_не_читается_как_успех():
    """«не измерено» обязано остаться блокером, а не превратиться в «нет»."""
    assert инс.блокер(строка(service="не измерено")) == "служба"
    assert инс.блокер(строка(publisher="не измерено")) == "номер издателя"
    assert инс.блокер(строка(https="не измерено")) == "TLS"


def test_целевой_адрес_не_зашит_в_логику_отдельно():
    """Один источник адреса: поменяв константу, меняем и вывод блокера."""
    assert инс.блокер(строка(dns=ЦЕЛЬ)) == "нет"
    assert инс.блокер(строка(dns=ЦЕЛЬ + "1")) == "DNS → TLS"
