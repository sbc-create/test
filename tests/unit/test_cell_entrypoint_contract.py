"""Точка входа ячейки: одно имя, один смысл, и пин ему не врёт.

ПОПРАВКА 2026-09-26. Два отказа на lordserial33-biz были ошибкой ЭТОЙ
проверки, а не дефектом того репозитория, и я успел назвать их дефектом в
отчёте. Разбор: `config/site.json` называет точкой входа `lords02-frontend.py`,
а `pins.lock.json` закрепляет `lords-frontend.py`. Выглядит как «исполняется
незакреплённое». На деле `lords02-frontend.py` — пускатель на 3.5 КБ,
принадлежащий сайту и лежащий в его git; он загружает ОБЩИЙ рантайм
`lords-frontend.py` и ставит поверх него слой витрины. AGENTS.md того проекта
описывает это прямо (п. 3: общее ядро приезжает отдельным коммитом,
поднимающим версию в `pins.lock.json`), и замок там закрепляет именно
заимствованное ядро — то, для чего замок и нужен.

То есть моделей закрепления не две, а три, и третью проверка не знала. Цена
ошибки ровно та, которую я сторожу в соседних проверках: ложная тревога на
исправном репозитории учит не смотреть на тревоги вообще.

Свойство, которое сторожится теперь: исполняемое либо закреплено само, либо
это собственный пускатель сайта поверх ЗАКРЕПЛЁННОГО ядра — и то, что он
грузит именно закреплённое ядро, проверяется по его исходнику, а не со слов.

`entrypoint` означает файл под `src/`, который исполняется, и его же цифру
несёт `artifact_sha256`. Пускатель `run.py` в контракт не входит: он одинаков
во всех ячейках и версионируется вместе с фабрикой.

Существование файла проверяет сам репозиторий сайта — `checks/entrypoint_present.py`
разрешает `src/<entrypoint>` и падает, если файла нет. Не проверялось другое:
что ПИН повторяет то же имя. Пин никто не исполняет, поэтому расхождение не
роняет витрину — оно просто делает зеркало лживым, а решают по нему.

Соседняя ячейка ровно так и разошлась: пин стал называть пускатель вместо
рантайма, и поймать это «наличием ключа» было нельзя — только сверкой значения
с файлом.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ))

#: Рабочие копии репозиториев сайтов. Каталог создаётся установщиком ячеек и
#: в Git не хранится (`var/` игнорируется), поэтому в чистом клоне и на раннере
#: CI его нет вовсе.
#:
#: Раньше отсутствие каталога роняло СБОР тестов — `iterdir` на несуществующем
#: пути бросает `FileNotFoundError` на уровне модуля, и вместе с этим файлом не
#: собирался весь набор. Отказ при этом выглядел как поломка проверки, хотя
#: проверять было нечего: выделенных ячеек на машине нет.
#:
#: Пропуск здесь не прячет расхождение. Он говорит ровно то, что есть: на этой
#: машине нет ни одной ячейки, а значит и контракта точки входа не у чего
#: сверять. Там, где ячейки есть, проверка работает как прежде и падает на
#: расхождении.
КАТАЛОГ_ЯЧЕЕК = КОРЕНЬ / "var" / "site-repos"
ЯЧЕЙКИ = sorted(
    p for p in (КАТАЛОГ_ЯЧЕЕК.iterdir() if КАТАЛОГ_ЯЧЕЕК.is_dir() else ())
    if (p / "config" / "site.json").is_file())

pytestmark = pytest.mark.skipif(
    not ЯЧЕЙКИ,
    reason=(f"нет рабочих копий репозиториев сайтов в {КАТАЛОГ_ЯЧЕЕК}: "
            "контракт точки входа сверять не у чего"))


def _пины(ячейка: Path) -> dict:
    файл = ячейка / "pins.lock.json"
    return json.loads(файл.read_text(encoding="utf-8")).get("pins", {}) \
        if файл.is_file() else {}


def _замок(ячейка: Path) -> dict:
    файл = ячейка / "pins.lock.json"
    return json.loads(файл.read_text(encoding="utf-8")).get("files") or {} \
        if файл.is_file() else {}


def _закреплено(замок: dict, имя: str) -> bool:
    """Ключи замка пишутся в двух видах: голое имя и путь с `src/`."""
    return bool({имя, f"src/{имя}"} & set(замок))


def ядро_пускателя(ячейка: Path, точка: str) -> str | None:
    """Имя ЗАКРЕПЛЁННОГО ядра, которое грузит этот пускатель, либо None.

    Третья модель закрепления: точка входа принадлежит сайту и лежит в его
    git, а закреплён заимствованный рантайм, который она загружает. Проверять
    надо не «совпали ли имена», а «то ли ядро грузится, что закреплено», и
    ответ читается из исходника пускателя, а не из его обещаний.
    """
    исходник = ячейка / "src" / точка
    if not исходник.is_file():
        return None
    текст = исходник.read_text(encoding="utf-8", errors="replace")
    for имя in _замок(ячейка):
        голое = имя.split("/")[-1]
        if голое != точка and голое in текст:
            return голое
    return None


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda p: p.name)
def test_точка_входа_указывает_на_существующий_файл(ячейка):
    """«Ключ есть» не то же самое, что «файл есть».

    Имя берётся из конфигурации, а если ключа там нет — из пина. Пропустить
    такую ячейку значило бы не проверить её вовсе: именно там, где источник
    имени лежит не в конфиге, зеркало и врёт молча, потому что ничего не
    переключает. Проверять надо то, что имя указывает на настоящий файл, —
    откуда бы оно ни пришло.
    """
    конфиг = json.loads((ячейка / "config" / "site.json").read_text(
        encoding="utf-8")).get("entrypoint")
    имя = конфиг or _пины(ячейка).get("entrypoint")
    if not имя:
        pytest.skip(f"{ячейка.name}: имени точки входа нет ни в конфигурации, ни в пине")
    assert (ячейка / "src" / имя).is_file(), (
        f"{ячейка.name}: entrypoint={имя!r} "
        f"({'конфигурация' if конфиг else 'пин'}) не указывает на файл под src/")


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda p: p.name)
def test_пин_повторяет_точку_входа(ячейка):
    """Пин — зеркало, и врущее зеркало хуже отсутствующего.

    Витрину это не уронит: исполняется значение из config/site.json. Но по пину
    судят о том, что закреплено, и разошедшееся имя читается как «закреплён
    другой рантайм».
    """
    конфиг = json.loads((ячейка / "config" / "site.json").read_text(
        encoding="utf-8")).get("entrypoint")
    пин = _пины(ячейка).get("entrypoint")
    if not конфиг or not пин:
        pytest.skip(f"{ячейка.name}: сверять нечего")
    if пин == конфиг:
        return
    ядро = ядро_пускателя(ячейка, конфиг)
    assert ядро == пин, (
        f"{ячейка.name}: пин закрепляет {пин!r}, исполняется {конфиг!r}, "
        + (f"и пускатель грузит {ядро!r} — это третье имя"
           if ядро else
           "и пускатель не грузит закреплённого ядра вовсе"))


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda p: p.name)
def test_цифра_артефакта_считается_по_точке_входа(ячейка):
    """`artifact_sha256` обязан быть суммой того файла, который исполняется.

    Сборщик это поле пока не штампует, поэтому оно устаревает молча: у части
    ячеек цифра уже не та. Тест отмечает такие как ожидаемо провальные, чтобы
    исправление в сборщике было видно по их позеленению, а не по обещанию.
    """
    манифест = ячейка / "config" / "template-manifest.json"
    имя = json.loads((ячейка / "config" / "site.json").read_text(
        encoding="utf-8")).get("entrypoint")
    if not манифест.is_file() or not имя:
        pytest.skip(f"{ячейка.name}: сверять нечего")
    заявлено = json.loads(манифест.read_text(encoding="utf-8")).get("artifact_sha256")
    # Пустое значение — не «нечего сверять», а пропавшее закрепление. Под
    # прежним `if not заявлено: skip` удалить поле было ДЕШЕВЛЕ, чем привести
    # его в порядок: проверка зеленела ровно в тот момент, когда происхождение
    # кода переставало быть закреплённым.
    # Пустое значение допустимо ровно в одном случае: манифест САМ объявляет
    # себя нештампованным. Репозиторий lordfilm47-space пришёл к этому 26.09
    # («в артефакт попадает индекс Git, а не рабочий каталог»): в коммите
    # лежит `build_id: worktree-unbuilt` и пустая цифра, а штампует их
    # сборщик. Это честнее устаревшей суммы, которая у соседей держится
    # ожидаемым провалом. Молча пустое поле по-прежнему провал: иначе удалить
    # закрепление было бы дешевле, чем привести его в порядок.
    объявлено_нештампованным = (
        str(json.loads(манифест.read_text(encoding="utf-8")).get("build_id") or "")
        == "worktree-unbuilt")
    if not заявлено and объявлено_нештампованным:
        pytest.skip(f"{ячейка.name}: манифест объявлен нештампованным "
                    "(build_id=worktree-unbuilt), цифру ставит сборщик")
    assert заявлено, (
        f"{ячейка.name}: artifact_sha256 не объявлен в template-manifest.json — "
        "происхождение кода ничем не закреплено")
    факт = hashlib.sha256((ячейка / "src" / имя).read_bytes()).hexdigest()
    if заявлено != факт:
        pytest.xfail(f"{ячейка.name}: сборщик не пересчитывает artifact_sha256 — "
                     f"объявлено {заявлено[:16]}…, фактически {факт[:16]}…")
    assert заявлено == факт


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda p: p.name)
def test_замок_исходников_не_пустой(ячейка):
    """Пустой перечень закреплённых файлов проходит `verify_pins` зелёным.

    Проверка в репозитории ячейки идёт циклом по `pins["files"]`: нет записей —
    нет и расхождений, выход 0. То есть удалить замок дешевле, чем привести
    исходники в соответствие с ним, и «закрепление» исчезает молча.

    Здесь это ловится со стороны фабрики, не трогая репозитории витрин.
    """
    файл = ячейка / "pins.lock.json"
    if not файл.is_file():
        pytest.fail(f"{ячейка.name}: pins.lock.json отсутствует")
    данные = json.loads(файл.read_text(encoding="utf-8"))
    # Моделей закрепления две, и они не взаимозаменяемы:
    #
    #   files{}            каждый исходник по своему sha256 — восемь ячеек;
    #   template_sha256    закреплён артефакт шаблона целиком, а правки живут
    #                      оверлеем — zonafilm-cc.
    #
    # Требовать первую модель от второй значит сравнивать с чужим контрактом:
    # проверка объявила бы дефектом исправный репозиторий. Свойство, которое
    # сторожится, одно — закрепление ЕСТЬ и оно не пустое; чем именно закреплено,
    # решает модель.
    замок = данные.get("files") or {}
    шаблон = ((данные.get("pins") or {}).get("template_sha256")
              or данные.get("template_sha256") or "")
    assert замок or len(шаблон) == 64, (
        f"{ячейка.name}: закрепления нет ни одной из известных моделей — "
        "ни перечня файлов, ни template_sha256. Проверка замка при этом "
        "завершится успехом, ничего не проверив")


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda p: p.name)
def test_точка_входа_закреплена_замком(ячейка):
    """Закрепить всё, кроме исполняемого файла, — закрепить не то."""
    конфиг = json.loads((ячейка / "config" / "site.json").read_text(
        encoding="utf-8")).get("entrypoint")
    имя = конфиг or _пины(ячейка).get("entrypoint")
    if not имя:
        pytest.skip(f"{ячейка.name}: имени точки входа нет ни в конфигурации, ни в пине")
    замок = json.loads((ячейка / "pins.lock.json").read_text(
        encoding="utf-8")).get("files") or {}
    # см. test_замок_исходников_не_пустой: моделей закрепления две
    # Ключи замка пишутся в двух видах: голое имя и путь с `src/`. Свойство,
    # которое здесь сторожится, — «исполняемый файл закреплён», а не одно из
    # двух написаний: проверка на одну форму объявила бы дефектом соседнюю
    # ячейку, у которой всё в порядке.
    if not замок:
        pytest.skip(f"{ячейка.name}: закрепление моделью template_sha256 — "
                    "исходники по отдельности не пинуются по построению")
    if _закреплено(замок, имя):
        return
    # Третья модель: пускатель сайта поверх закреплённого ядра. Он лежит в
    # git этого проекта и версионируется им; закреплять его сумму незачем —
    # закрепление нужно заимствованному. Но ядро, которое он грузит, обязано
    # быть в замке, иначе закреплено действительно не то.
    ядро = ядро_пускателя(ячейка, имя)
    assert ядро and _закреплено(замок, ядро), (
        f"{ячейка.name}: {имя} исполняется, в замке его нет, и "
        + (f"ядро {ядро!r}, которое он грузит, тоже не закреплено"
           if ядро else
           "закреплённого ядра он не грузит: исполняется незакреплённый код"))
