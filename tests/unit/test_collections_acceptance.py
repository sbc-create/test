"""Приёмка подборок: требования владельца проверяются механизмом, а не прозой.

Три части отвечают на разные вопросы: схема — есть ли потребность, принцип,
описание, устойчивый ключ, порядок, постоянные идентификаторы и решение об
индексации; живые факты — отвечает ли адрес и индексируется ли страница;
неповторяемость — не размножены ли одинаковые подборки по сети.

Мобильный сценарий здесь намеренно НЕ измеряется: он измеряется событиями
аналитики, и пока цели выпущены не на всех витринах, признак остаётся «не
измерено».
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "collections_acceptance", КОРЕНЬ / "automation" / "local" / "collections-acceptance.py")
инс = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(инс)


def _подборка(**замены):
    основа = {
        "key": "novinki-2026", "title": "Новинки 2026 года, которые уже вышли целиком",
        "viewer_request": "Что из новинок этого года можно посмотреть сразу целиком?",
        "intro": ("Сериалы и фильмы 2026 года, у которых на витрине доступны все серии: "
                  "подборка собрана по полноте сезонов, а не по дате импорта, поэтому "
                  "в неё не попадают работы с одной выложенной серией."),
        "section": "/series/",
        "indexing": {"open": True, "reason": "устойчивый адрес, своё описание, спрос подтверждён"},
        "items": [
            {"order": н, "id": f"01a11a9d-1fc6-749f-b5aa-5a4a74eb64{50 + н}",
             "slug": f"работа-{н}", "url": f"https://пример.ru/title/работа-{н}/",
             "name": f"Работа {н}", "year": 2026,
             "reason": "Канадский триллер о рыбаке; шесть серий доступны целиком.",
             "checked": "26.10.2026: 200, canonical на себя, index, постер и плеер"}
            for н in (1, 2, 3)],
    }
    основа.update(замены)
    return основа


def _файл(tmp_path, подборки, **замены):
    д = {"schema": "primer-ru.collections/2", "site": "пример.ru", "site_id": "x-01",
         "prepared_at": "2026-10-26", "status": "PREPARED_NOT_RELEASED",
         "key": "id = details[].id",
         "direction_rule": "пример.ru — профиль general: только игровые фильмы и сериалы своего раздела",
         "collections": подборки}
    д.update(замены)
    п = tmp_path / "подборки.json"
    п.write_text(json.dumps(д, ensure_ascii=False), encoding="utf-8")
    return п, д


def test_полная_подборка_схему_проходит(tmp_path):
    _, д = _файл(tmp_path, [_подборка()])
    assert инс.проверить_схемой(д) == []


def test_отсутствие_решения_об_индексации_это_нарушение(tmp_path):
    """Ровно то, чего не хватало подготовленной поставке zonafilm.cc: 8 подборок из 8."""
    п = _подборка()
    del п["indexing"]
    _, д = _файл(tmp_path, [п])
    ош = инс.проверить_схемой(д)
    assert any("indexing" in с for с in ош), ош


def test_непроверенная_работа_это_нарушение(tmp_path):
    """У подборки dorama-novye-i-celikom ни один из семи элементов не проверялся живым."""
    п = _подборка()
    del п["items"][0]["checked"]
    _, д = _файл(tmp_path, [п])
    assert any("checked" in с for с in инс.проверить_схемой(д))


def test_технический_заголовок_и_пустое_описание_не_проходят(tmp_path):
    """«Содержательное описание» — требование, а не пожелание."""
    п = _подборка(intro="Фильтр: year=2026&complete=1", viewer_request="новинки")
    _, д = _файл(tmp_path, [п])
    ош = инс.проверить_схемой(д)
    assert len(ош) >= 2, ош


def test_меньше_трёх_работ_подборкой_не_считается(tmp_path):
    п = _подборка()
    п["items"] = п["items"][:2]
    _, д = _файл(tmp_path, [п])
    assert any("minItems" in с or "too short" in с for с in инс.проверить_схемой(д))


def test_одинаковые_подборки_у_разных_витрин_называются(tmp_path):
    """Общими должны быть механизм и требования, а не состав и подача."""
    первый, _ = _файл(tmp_path, [_подборка()])
    второй = tmp_path / "второй.json"
    д2 = json.loads(первый.read_text(encoding="utf-8"))
    д2["site"] = "другой.ru"
    второй.write_text(json.dumps(д2, ensure_ascii=False), encoding="utf-8")
    повторы = инс.неповторяемость([первый, второй])
    виды = {п["что"] for п in повторы}
    assert виды == {"ключ", "заголовок"}, повторы
    assert повторы[0]["сайты"] == ["другой.ru", "пример.ru"]


def test_одна_витрина_повтором_не_считается(tmp_path):
    первый, _ = _файл(tmp_path, [_подборка(), _подборка(key="drugaya-podborka",
                                                        title="Другая подборка целиком вышедших работ")])
    assert инс.неповторяемость([первый]) == []
