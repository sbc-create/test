"""Семейная принадлежность Publisher ID витрины.

Проверяется не «работает ли функция», а свойства, потеря которых означает
выдачу витрине чужого доступа к плееру:

* семейное значение одно и берётся из файла. Значение, повторённое в операции
  подключения и в описании семейства, неизбежно разъедется — и разъезд будет
  выглядеть как работающий плеер с чужим каталогом;
* снятое значение не возвращается. Витрина семейства не вправе получить ни
  один из снятых идентификаторов, чем бы он ни был передан;
* чужое семейное значение не проходит. Animedia не получает значение Zona,
  Zona не получает значение Animedia — даже если оно действующее;
* семейства вне области операции не проверяются вовсе. Lords и Yummy обязаны
  проходить политику без изменения поведения: операция их не трогает.

Отказ здесь громкий намеренно. Тихая подстановка «похожего» идентификатора
даёт витрину, которая отвечает 200 и показывает чужие дорожки.
"""

from __future__ import annotations

import textwrap
from pathlib import Path

import pytest

from factory.site_engine import publisher_policy as политика

ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture(autouse=True)
def _чистый_кэш():
    политика.сбросить_кэш()
    yield
    политика.сбросить_кэш()


def записать(tmp_path: Path, текст: str) -> Path:
    каталог = tmp_path / "config"
    каталог.mkdir(parents=True, exist_ok=True)
    (каталог / "publisher-ids.yaml").write_text(textwrap.dedent(текст), encoding="utf-8")
    return tmp_path


ОБРАЗЕЦ = """
    schema_version: 1
    policy_version: "1.0.0"
    families:
      animedia:
        publisher_id: "10252"
        credential_profile: yami
      zona:
        publisher_id: "10238"
        credential_profile: lords
    retired:
      - "10331"
      - "10332"
      - "10333"
    onboarding:
      - domain: zonafilm.cc
        family: zona
        state: not_deployed
"""


# --- семейное значение одно и берётся из файла ---------------------------


def test_семейное_значение_читается_из_файла(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    assert политика.ожидаемый("animedia", root=корень) == "10252"
    assert политика.ожидаемый("zona", root=корень) == "10238"


def test_действующий_файл_репозитория_описывает_оба_семейства():
    """Файл в репозитории — тот самый источник, а не только фикстура теста."""
    assert политика.ожидаемый("animedia", root=ROOT) == "10252"
    assert политика.ожидаемый("zona", root=ROOT) == "10238"


# --- снятое значение не возвращается -------------------------------------


@pytest.mark.parametrize("снятый", ["10331", "10332", "10333"])
def test_снятое_значение_отклоняется(tmp_path, снятый):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    with pytest.raises(политика.PublisherIdОтклонён) as отказ:
        политика.проверить("animedia-01", "animedia", снятый, root=корень)
    assert снятый in str(отказ.value)


def test_снятое_значение_не_значится_семейным(tmp_path):
    """Снятый идентификатор не может одновременно быть действующим."""
    корень = записать(tmp_path, ОБРАЗЕЦ)
    действующие = {
        политика.ожидаемый(с, root=корень) for с in политика.семейства(root=корень)
    }
    assert действующие.isdisjoint(set(политика.снятые(root=корень)))


# --- чужое семейное значение не проходит ---------------------------------


def test_animedia_не_получает_значение_zona(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    with pytest.raises(политика.PublisherIdОтклонён):
        политика.проверить("animedia-01", "animedia", "10238", root=корень)


def test_zona_не_получает_значение_animedia(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    with pytest.raises(политика.PublisherIdОтклонён):
        политика.проверить("zona-01", "zona", "10252", root=корень)


def test_своё_семейное_значение_проходит(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    политика.проверить("animedia-01", "animedia", "10252", root=корень)
    политика.проверить("animedia-02", "animedia", "10252", root=корень)
    политика.проверить("zona-01", "zona", "10238", root=корень)


def test_отказ_не_печатает_иного_значения(tmp_path):
    """Сообщение называет отвергнутое значение и семейство, но не выдаёт чужое."""
    корень = записать(tmp_path, ОБРАЗЕЦ)
    with pytest.raises(политика.PublisherIdОтклонён) as отказ:
        политика.проверить("zona-01", "zona", "10252", root=корень)
    текст = str(отказ.value)
    assert "10252" in текст and "zona" in текст
    assert "10238" not in текст


# --- семейства вне области операции не проверяются ------------------------


@pytest.mark.parametrize("семейство", ["lords", "yummy", "books", None, ""])
def test_чужое_семейство_политика_не_трогает(tmp_path, семейство):
    """Lords, Yummy и прочие проходят любым значением: операция их не ведёт."""
    корень = записать(tmp_path, ОБРАЗЕЦ)
    политика.проверить("lords-01", семейство, "10238", root=корень)
    политика.проверить("lords-01", семейство, "99999", root=корень)


def test_семейство_без_описания_не_policed(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    assert политика.ожидаемый("lords", root=корень) is None


# --- непригодное значение ------------------------------------------------


@pytest.mark.parametrize("плохое", ["", "  ", "abc", "0252", "102.52", None])
def test_непригодное_значение_отклоняется(tmp_path, плохое):
    """Плеер зовёт Number(publisherId): нечисловое даёт NaN и 400 у провайдера."""
    корень = записать(tmp_path, ОБРАЗЕЦ)
    with pytest.raises(политика.PublisherIdОтклонён):
        политика.проверить("animedia-01", "animedia", плохое, root=корень)


# --- onboarding ----------------------------------------------------------


def test_невыложенный_домен_закреплён_за_семейством(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    assert политика.семейство_домена("zonafilm.cc", root=корень) == "zona"


def test_zonafilm_cc_закреплён_в_репозитории():
    """Шаг онбординга: значение известно до выкладки, DNS при этом не трогается."""
    assert политика.семейство_домена("zonafilm.cc", root=ROOT) == "zona"
    семейство = политика.семейство_домена("zonafilm.cc", root=ROOT)
    assert политика.ожидаемый(семейство, root=ROOT) == "10238"


def test_неизвестный_домен_не_получает_семейства(tmp_path):
    корень = записать(tmp_path, ОБРАЗЕЦ)
    assert политика.семейство_домена("example.org", root=корень) is None


# --- файл обязан быть пригодным ------------------------------------------


def test_нет_файла_это_отказ(tmp_path):
    with pytest.raises(политика.PublisherIdОтклонён):
        политика.ожидаемый("animedia", root=tmp_path)
