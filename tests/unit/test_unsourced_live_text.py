"""Живые тексты без прослеживаемого происхождения.

ПОВОД ИЗМЕРЕННЫЙ, 24.10, и он задевает главное правило: факт без одобренного
источника не появляется. Соседняя линия нашла в черновиках Zona подробности,
которых нет ни в фактах витрины, ни у поставщика («Фриц Бреннер», «Джаспер,
Гранд-Джанкшен»), и показала, что `state: verified` — ворота ФОРМЫ, а не
проверка фактов. Замер по сети: из 1 252 черновиков 73 без непустого
`sources`, 67 из них уже размещены, у 42 происхождение записано в реестре
оператора, у 25 — нигде, и у 19 из этих 25 в тексте есть имена, которых нет
ни в записи каталога, ни в слаге (Айзен, Ферн, Аскеладд, Торфинн, Мидория).

Проверяется главное свойство эвристики: она не путает ИМЯ с обычным словом в
начале предложения. Первая редакция ловила «Второй», «Сериал», «После» — на
таком списке вывод не защитить.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "unsourced-live-text.py"
_с = importlib.util.spec_from_file_location("unsourced_live_text", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(МОДУЛЬ)


def test_обычное_слово_в_начале_предложения_именем_не_считается():
    """Ровно шум первой редакции: «Второй», «Сериал», «После»."""
    тело = ("«Сага о Винланде» — сериал 2023 года. Второй сезон продолжает"
            " историю. После пролога действие переносится дальше.")
    assert МОДУЛЬ.чужие_слова(тело, "сага о винланде 2023", "saga") == []


def test_имя_внутри_предложения_находится():
    тело = "Второй сезон продолжает путь Торфинна после смерти Аскеладда."
    из = МОДУЛЬ.чужие_слова(тело, "сага о винланде 2023", "saga-o-vinlande-2")
    assert "Торфинна" in из and "Аскеладда" in из, из
    assert "Второй" not in из


def test_слово_из_записи_каталога_чужим_не_считается():
    """Текст, собранный из полей каталога, прослеживается к данным."""
    тело = "Это «Аркнайтс: Морозная погибель» — боевик и фэнтези."
    опора = "Аркнайтс: Морозная погибель Arknights боевик фэнтези 2023"
    assert МОДУЛЬ.чужие_слова(тело, опора, "arknayts") == []


def test_название_из_записи_каталога_покрывает_имя_в_тексте():
    """Опорой служит НАЗВАНИЕ записи каталога, а не слаг.

    Слаг латинский («frieren»), имя в тексте — кириллицей («Фрирен»), и слаг
    его не покрывает. Покрывает поле `name` записи каталога. Поэтому на живых
    данных «Фрирен» в список непрослеживаемого не попала, а «Айзен», «Ферн» и
    «Химмель» попали: их в записи каталога нет.
    """
    тело = "Герой по имени Фрирен идёт дальше, с ней Ферн."
    из = МОДУЛЬ.чужие_слова(тело, "Провожающая в последний путь Фрирен",
                            "frieren")
    assert "Фрирен" not in из, из
    assert "Ферн" in из, из


def test_после_кавычки_и_многоточия_начало_предложения_тоже_узнаётся():
    тело = 'Сюжет такой… Потом Ферн уходит. «Прощай» — Химмель молчит.'
    из = МОДУЛЬ.чужие_слова(тело, "", "x")
    assert "Потом" not in из, из
    assert "Ферн" in из and "Химмель" in из, из


def test_размещённое_берётся_из_обоих_хранилищ(tmp_path, monkeypatch):
    """Наложение И накладка: у семейств Lords и Zona размещает накладка."""
    к = tmp_path / "семейство" / "runtime" / "overlays" / "д.site"
    к.mkdir(parents=True)
    (к / "title-overlays.json").write_text(json.dumps(
        {"site": "д.site", "items": [{"slug": "a", "body": "из наложения"}]}),
        encoding="utf-8")
    monkeypatch.setattr(МОДУЛЬ.ОПИСЬ, "накладка_витрины", lambda д: None)
    из = МОДУЛЬ.размещённые(к)
    assert МОДУЛЬ.ОПИСЬ.отпечаток("из наложения") in из

    накл = tmp_path / "over.json"
    накл.write_text(json.dumps({"overrides": [
        {"fields": {"description": "из накладки"}}]}), encoding="utf-8")
    monkeypatch.setattr(МОДУЛЬ.ОПИСЬ, "накладка_витрины", lambda д: накл)
    из2 = МОДУЛЬ.размещённые(к)
    assert МОДУЛЬ.ОПИСЬ.отпечаток("из накладки") in из2
    assert МОДУЛЬ.ОПИСЬ.отпечаток("из наложения") in из2


def test_без_реестра_это_не_измерено_а_не_ноль(monkeypatch, capsys):
    """«Происхождения нет» и «я не посмотрела» — разные ответы."""
