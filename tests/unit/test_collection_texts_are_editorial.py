"""REQ-COLLECTION-TEXT: подборка рассказывает о содержимом, а не о механике отбора.

Измерено 2026-10-17 на живых страницах: посетитель читал «Записи с
подтверждённой оценкой источника не ниже 7.5, по убыванию» и «Записи самого
свежего года каталога с оценкой не ниже 7.0, по убыванию оценки. Это не список
поступлений: он в «Новом за 14 дней»». Это описание устройства, а не раздела;
порог и порядок сортировки посетителю ничего не говорят.

Отбор при этом не менялся: порог остался в фильтре, адреса прежние. Проверка
смотрит на ТЕКСТЫ контракта, то есть на то, что попадёт на страницу.

Проверка опровержима: возврат прежних формулировок её ломает.
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

КОНТРАКТ_ФАЙЛ = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "collection_contract.py"
_спец = importlib.util.spec_from_file_location("_контракт_подборок",
                                               КОНТРАКТ_ФАЙЛ)
контракт = importlib.util.module_from_spec(_спец)
sys.modules["_контракт_подборок"] = контракт
_спец.loader.exec_module(контракт)

#: Слова и обороты, которые объясняют УСТРОЙСТВО, а не содержание.
СЛУЖЕБНЫЕ = (
    (re.compile(r"по убыванию", re.I), "порядок сортировки"),
    (re.compile(r"не ниже \d", re.I), "числовой порог отбора"),
    (re.compile(r"Это не (?:список|срез)", re.I), "оговорка «это не…»"),
    (re.compile(r"подтверждённ\w+ (?:оценк|дат)", re.I), "ссылка на источник"),
    (re.compile(r"\bв источнике\b", re.I), "ссылка на источник"),
    (re.compile(r"подключённой дорожкой", re.I), "внутреннее устройство плеера"),
    (re.compile(r"\bсрез\b", re.I), "слово «срез»"),
)

СЕМЕЙСТВА = ("lords", "zona", "animedia")


#: Ключи подборок, которые есть не у всех семейств: у аниме-сети свой набор.
КЛЮЧИ = ("recently_added", "recently_added_movies", "new_episodes",
         "top_rated", "current_season", "video_available")


def _все_спецификации():
    """Пары (семейство, спецификация) по всем доступным ключам.

    Отсутствующий у семейства ключ пропускается молча — это законное
    различие наборов, а не отказ. Первая редакция падала на нём с
    AttributeError, и негативный контроль «проходил» по неверной причине.
    """
    итог = []
    for семейство in СЕМЕЙСТВА:
        for ключ in КЛЮЧИ:
            try:
                итог.append((семейство, контракт.спецификация(семейство, ключ)))
            except (AttributeError, KeyError, ValueError):
                continue
    assert итог, "ни одной спецификации не получено — контракт изменился"
    return итог


def test_в_текстах_подборок_нет_объяснений_механики():
    плохо = []
    for семейство, с in _все_спецификации():
        for поле in ("title", "description"):
            текст = getattr(с, поле, "") or ""
            for образец, имя in СЛУЖЕБНЫЕ:
                if образец.search(текст):
                    плохо.append(f"{семейство}/{с.collection_key}.{поле}: {имя} — «{текст}»")
    assert not плохо, "служебные формулировки в текстах подборок:\n" + \
        "\n".join(плохо)


def test_тексты_подборок_не_пустые_и_называют_предмет():
    """Отрицательный контроль: нельзя «починить» проверку пустой строкой."""
    for семейство, с in _все_спецификации():
        assert (с.title or "").strip(), (
            f"{семейство}/{с.collection_key}: пустой заголовок")
        описание = (с.description or "").strip()
        assert len(описание) >= 20, (
            f"{семейство}/{с.collection_key}: описание «{описание}» "
            f"ничего не говорит")


def test_порог_высокой_оценки_остался_в_отборе():
    """Слова ушли, а фильтр остался: иначе это была бы подмена смысла."""
    с = контракт.спецификация("lords", "top_rated")
    assert с.filter_spec.get("min_rating") == контракт.ПОРОГ_ВЫСОКОЙ_ОЦЕНКИ
    assert с.sort_spec.get("order") == "desc"
    assert с.canonical_path == "/collection/top_rated/", "адрес менять нельзя"
