"""Вступление страницы фильтра года: что в нём измерено и чего в нём нет.

ПОВОД (T339, п. 3). `/catalog/?year=2026` отдаёт 200, `index`, canonical на
себя и собственный H1 «Аниме 2026 года», но своего вступления у страницы не
было: под заголовком сразу служебная строка «Найдено N · страница 1 из …».

ЗАЧЕМ ТЕСТ ПОВЕДЕНЧЕСКИЙ, А НЕ ТЕКСТОВЫЙ. У метода есть ветки, и ошибка в
любой выходит на живую страницу текстом: сужающий фильтр, отсутствие
подборки своего года, согласование числа со словом. Проверка «строка есть в
файле» ни одной из них не касается — поэтому метод вынимается из рантайма и
исполняется.
"""
from __future__ import annotations

import ast
import html as _html
import pathlib
import types

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
РАНТАЙМ = (КОРЕНЬ / "var" / "site-repos" / "animedia-icu" / "src"
           / "animedia-frontend.py")


def _достать(имена: tuple[str, ...], подборки: dict) -> dict:
    """Вынуть названные функции из рантайма и исполнить их в своём окружении.

    Витрина не поднимается: нужны чистые функции, а не снимок и шаблон.
    """
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    дерево = ast.parse(текст, РАНТАЙМ.name)
    узлы = [у for у in ast.walk(дерево)
            if isinstance(у, (ast.FunctionDef,)) and у.name in имена]
    пропали = set(имена) - {у.name for у in узлы}
    assert not пропали, f"в рантайме нет: {sorted(пропали)}"
    окружение: dict = {"html": _html, "РУЧНЫЕ_ПОДБОРКИ": подборки}
    exec(compile(ast.Module(body=узлы, type_ignores=[]), str(РАНТАЙМ), "exec"),
         окружение)
    return окружение


class _Подборка:
    def __init__(self, key, title):
        self.key, self.title = key, title

    @property
    def canonical_path(self):
        return f"/collection/{self.key}/"


ЛЕТО = {"л": _Подборка("letniy-sezon-2026-celikom",
                       "Летний сезон 2026: аниме, которое уже вышло целиком")}
НАБОР = ([{"type": "tv"}] * 3) + ([{"type": "movie"}] * 2)


def _строка(выбрано, набор=НАБОР, подборки=None):
    # `_по_числу` — уже существовавший в рантайме склонятель. Первая версия
    # правки завела рядом второй такой же; тест берёт именно штатный, чтобы
    # дубликат не вернулся незамеченным.
    окр = _достать(("_вступление_года", "склонение_записей", "_по_числу"),
                   подборки if подборки is not None else {})
    пусто = types.SimpleNamespace()
    return окр["_вступление_года"](пусто, выбрано, набор)


def test_числа_взяты_из_выборки_а_не_объявлены():
    """Три сериала и два фильма — счёт по полю `type` той же выборки."""
    с = _строка({"year": "2026"})
    assert "5 названий" in с
    assert "3 сериала" in с and "2 фильма" in с


def test_число_согласовано_со_словом():
    """Несогласованное число рядом со словом заметнее любого огреха вёрстки —
    довод тот же, что у счётчика записей."""
    один = _строка({"year": "2026"}, набор=[{"type": "tv"}])
    assert "1 название" in один and "1 сериал" in один and "сериала" not in один
    пять = _строка({"year": "2026"}, набор=[{"type": "movie"}] * 5)
    assert "5 фильмов" in пять
    одиннадцать = _строка({"year": "2026"}, набор=[{"type": "movie"}] * 11)
    assert "11 фильмов" in одиннадцать


def test_при_сузившем_фильтре_строки_нет():
    """С жанром или типом та же фраза описывала бы не ту выборку, что на
    экране."""
    for ключ in ("genre", "type", "country", "kind"):
        assert _строка({"year": "2026", ключ: "что-нибудь"}) == "", ключ


def test_без_года_строки_нет():
    assert _строка({}) == ""
    assert _строка({"year": ""}) == ""


def test_на_пустой_выборке_строки_нет():
    """Пустая выдача говорит о себе своим блоком, и обещать там состав
    нечему."""
    assert _строка({"year": "2026"}, набор=[]) == ""


def test_ссылка_на_расписание_есть_всегда():
    assert '/schedule/' in _строка({"year": "2026"})


def test_ссылка_на_подборку_только_своего_года():
    """Подборка сезона существует для одного года. Ссылка на неё со страницы
    другого года стала бы ложью сама собой через год, без единой правки."""
    свой = _строка({"year": "2026"}, подборки=ЛЕТО)
    assert "/collection/letniy-sezon-2026-celikom/" in свой
    чужой = _строка({"year": "2024"}, подборки=ЛЕТО)
    assert "/collection/" not in чужой


def test_без_подборок_строка_всё_равно_собирается():
    """Отсутствие редакционных подборок — рабочее состояние витрины, а не
    повод остаться без вступления."""
    с = _строка({"year": "2026"}, подборки={})
    assert "Аниме 2026 года" in с and "/collection/" not in с


def test_про_дунхуа_не_утверждается():
    """Признак страны лежит в подробностях, а не в каталоге: на этой странице
    его нет, и говорить о нём нельзя (согласовано с линией SEO 27.10)."""
    assert "дунхуа" not in _строка({"year": "2026"}).lower()


def test_год_экранируется():
    """Год приходит из адреса. Он проверен на `isdigit`, но экранирование —
    это второй замок, а не украшение."""
    с = _строка({"year": "2026"})
    assert "<script" not in с


def test_склонятель_не_задвоен():
    """В рантайме уже был `_по_числу` с тем же правилом. Первая версия этой
    правки добавила рядом второй такой же — два источника правды на одно
    правило. Тест не даёт дубликату вернуться."""
    текст = РАНТАЙМ.read_text(encoding="utf-8")
    assert "def склонение_трёх" not in текст
    assert текст.count("def _по_числу") == 1
