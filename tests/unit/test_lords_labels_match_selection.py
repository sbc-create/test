"""REQ-LORDS-LABEL-TRUTH: подпись раздела не обещает того, чего отбор не делает.

Измерено 2026-10-17 на живых витринах K2:

* меню сериальной витрины вело на `/new/` подписью «Новые серии», а страница и
  по своему заголовку («Недавно добавлено»), и по составу отдавала недавно
  добавленные записи: 35 фильмов, 5 мультфильмов и 8 сериалов из 48, самый
  старый — 1957 года;
* меню фильмовой витрины вело туда же подписью «Новое в прокате» — проката у
  записи каталога нет вовсе;
* полка «Популярное» вела на `/collection/top_rated/`, где страница прямо
  говорит принцип: «Записи с подтверждённой оценкой источника не ниже 7.5, по
  убыванию». Оценка — не популярность, и источника популярности у витрины нет.

Честная подпись для этой полки уже была принята в том же файле для
`lords-curated-v2` («Высокие оценки», с пометкой «no editorial claim without
ledger»); проверка закрепляет её для остальных ветвей.

Проверка читает ИСХОДНИК шаблона: так она падает до выпуска. Запрещены именно
ложные обещания, а не любые слова: «Новинки» остаётся допустимым — страница
действительно показывает новое для каталога, — а «премьера», «прокат» и
«серии» обещают то, чего отбор не знает.
"""
from __future__ import annotations

import re
from pathlib import Path

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")

#: Слова, которые обещают событие выпуска, а не попадание в каталог.
ЛОЖНЫЕ_ОБЕЩАНИЯ = ("прокат", "премьер", "сери")


def подписи_ссылки(адрес: str) -> list[str]:
    """Все подписи, которыми шаблон ведёт на этот адрес."""
    образец = re.compile(r'\("' + re.escape(адрес) + r'",\s*"([^"]+)"\)')
    return образец.findall(ТЕКСТ)


def test_ссылка_на_недавно_добавленное_не_обещает_выпуск_или_серии():
    подписи = подписи_ссылки("/new/")
    assert подписи, "ссылок на /new/ в шаблоне не найдено — он изменился"
    плохие = [п for п in подписи
              if any(с in п.lower() for с in ЛОЖНЫЕ_ОБЕЩАНИЯ)]
    assert not плохие, (
        f"подписи обещают выпуск или серии, а страница отдаёт недавно "
        f"добавленное: {плохие}")


def test_полка_оценок_не_называется_популярным():
    """Отбор полки — оценка источника; слова о популярности её не описывают."""
    строки = [с.strip() for с in ТЕКСТ.splitlines()
              if "/collection/top_rated/" in с]
    assert строки, "полка /collection/top_rated/ в шаблоне не найдена"
    плохие = [с for с in строки if "Популярн" in с or "популярн" in с]
    # `data-popular-*` — это служебные атрибуты снимка недели, а не подпись
    # для посетителя: они допустимы и проверке не мешают.
    плохие = [с for с in плохие
              if re.search(r'"\s*[А-ЯЁ][^"]*[Пп]опулярн', с)
              or re.match(r'^"?[Пп]опулярн', с)]
    assert not плохие, f"подпись обещает популярность: {плохие}"


def test_честная_подпись_осталась_в_шаблоне():
    """Отрицательный контроль: сами подписи на месте, а не вычищены целиком.

    Без него обе проверки выше прошли бы на шаблоне, из которого полку и
    ссылку просто удалили.
    """
    assert ТЕКСТ.count('"Высокие оценки"') >= 3, (
        "честной подписи полки оценок в шаблоне нет")
    assert "Недавно добавлено" in ТЕКСТ
