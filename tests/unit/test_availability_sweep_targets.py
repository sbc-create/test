"""Владение витриной решает реестр и inventory, а не адрес этого узла.

Повод измерен 20.10. Проход доступности считал «нашей» только витрину,
разрешающуюся в адрес узла, где он запущен. Восемь витрин партии K2
(lords-10…lords-17) живы, отдают 200 и свой build-id, а проход объявлял их
чужими: они разрешаются в `145.63.129.86`, то есть в цель `k2-zomro-01`,
записанную в `inventory/ssh-hosts.yaml`. Доступность этих витрин не
измерялась вовсе.

Это тот же род ошибки, что ловится всю смену: признак выбран заранее («адрес
равен адресу этого узла») вместо настоящего вопроса («наша ли это витрина»).

Отрицательные контроли, названные заранее:

* домен, который не разрешается ни в один записанный адрес, по-прежнему
  отвергается — защита не снята, а уточнена;
* адреса берутся ТОЛЬКО из inventory: ни одного в коде проверки нет, и
  подменённый inventory без узлов возвращает пусто, а не умолчание;
* витрина, закрытая для индексации, отдаёт на карту 404 ПРАВИЛЬНО, и это не
  замечание: слаги тогда берутся с главной, тоже из содержимого сайта;
* если ни карта, ни главная адресов не дали — это замечание, а не тишина.

Сеть не используется: `адреса` и `забрать` подменяются.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "availability_sweep", КОРЕНЬ / "automation/local/availability-sweep.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

ГЛАВНАЯ = (
    '<html><head><meta name="robots" content="noindex, nofollow"/></head>'
    '<body><a href="/title/pervaya/">a</a><a href="/title/vtoraya/">b</a>'
    '</body></html>')
def карточка(домен: str, путь: str = "/title/pervaya/") -> str:
    """Карточка с canonical на СВОЙ домен и штатным скриптом провайдера."""
    return (f'<html><head><link rel="canonical"'
            f' href="https://{домен}{путь}"/></head><body><h1>Первая</h1>'
            f'<img src="https://cdn.test/poster.jpg"/>'
            f'<script src="https://player.cdnvideohub.com/player.js"'
            f' data-publisher-id="10454"></script></body></html>')


# --- чтение целей из inventory ------------------------------------------------

def test_цели_читаются_из_инвентаря():
    цели = ИНСТР.цели_инвентаря()
    assert цели.get("145.63.129.86") == "k2-zomro-01", цели


def test_закомментированные_записи_не_берутся():
    """В ssh-hosts.yaml есть пример под комментарием — он не цель."""
    цели = ИНСТР.цели_инвентаря()
    assert not any("example" in ref for ref in цели.values()), цели
    assert "staging.example.tld" not in цели


def test_без_файла_инвентаря_пусто(monkeypatch, tmp_path):
    """Адресов в коде проверки нет: нет файла — нет целей, а не умолчание."""
    monkeypatch.setattr(ИНСТР, "КОРЕНЬ", tmp_path)
    assert ИНСТР.цели_инвентаря() == {}


# --- владение витриной --------------------------------------------------------

def _подменить(monkeypatch, адрес: str, страницы: dict | None = None):
    monkeypatch.setattr(ИНСТР, "адреса", lambda д: [адрес])
    стр = страницы if страницы is not None else {}

    def забрать(url, **к):
        # Ключи перебираются от самого длинного: ключ "/" совпадает с любым
        # адресом, и при обратном порядке карточка получила бы главную.
        for ключ in sorted(стр, key=len, reverse=True):
            if url.endswith(ключ):
                return 200, стр[ключ]
        return 404, ""
    monkeypatch.setattr(ИНСТР, "забрать", забрать)


def test_витрина_на_другой_нашей_цели_проверяется(monkeypatch):
    """Главный признак: прежде здесь был отказ «не наш адрес»."""
    _подменить(monkeypatch, "145.63.129.86",
               {"/": ГЛАВНАЯ, "/title/pervaya/": карточка("lordfilm.group")})
    итог = ИНСТР.проверить("lordfilm.group")
    assert итог["наш_адрес"] is True
    assert итог["цель"] == "k2-zomro-01"
    assert итог["главная_код"] == 200
    assert итог["карточка_код"] == 200
    assert итог["карточка_h1"] == "Первая"


def test_чужой_адрес_по_прежнему_отвергается(monkeypatch):
    """Отрицательный контроль: защита уточнена, а не снята."""
    _подменить(monkeypatch, "203.0.113.7", {"/": ГЛАВНАЯ})
    итог = ИНСТР.проверить("chuzhoy.example")
    assert итог["наш_адрес"] is False
    assert итог["цель"] == ""
    assert "не наш адрес" in итог["вывод"]
    assert "главная_код" not in итог


def test_адрес_этого_узла_цели_не_получает(monkeypatch):
    """У витрины на своём узле столбец цели пуст — проверять нечего."""
    _подменить(monkeypatch, ИНСТР.НАШ_АДРЕС,
               {"/": ГЛАВНАЯ, "/title/pervaya/": карточка("svoy.test")})
    итог = ИНСТР.проверить("svoy.test")
    assert итог["наш_адрес"] is True
    assert итог["цель"] == ""


# --- слаги при закрытой индексации --------------------------------------------

def test_при_отсутствии_карты_слаги_берутся_с_главной(monkeypatch):
    """Карта 404 у закрытой витрины — правильный ответ, а не замечание."""
    _подменить(monkeypatch, "145.63.129.86",
               {"/": ГЛАВНАЯ, "/title/pervaya/": карточка("lordfilm.group")})
    итог = ИНСТР.проверить("lordfilm.group")
    assert итог["источник_слагов"] == "главная"
    assert итог["карточка_адрес"].endswith("/title/pervaya/")
    assert итог["беды"] == [], итог["беды"]
    assert итог["вывод"] == "исправно"


def test_карта_в_приоритете_когда_она_есть(monkeypatch):
    """Положительный контроль: прежний путь не сломан."""
    индекс = "<sitemapindex><sitemap><loc>https://x/sitemap/t.xml</loc></sitemap></sitemapindex>"
    часть = "<urlset><url><loc>https://x/title/iz-karty</loc></url></urlset>"
    _подменить(monkeypatch, "145.63.129.86",
               {"/sitemap.xml": индекс, "/sitemap/t.xml": часть,
                "/": ГЛАВНАЯ, "/title/iz-karty": карточка("x.test", "/title/iz-karty")})
    итог = ИНСТР.проверить("x.test")
    assert итог["источник_слагов"] == "карта"
    assert итог["карточка_адрес"].endswith("/title/iz-karty")


def test_ни_карта_ни_главная_не_дали_это_замечание(monkeypatch):
    """Отрицательный контроль: отсутствие адресов не становится тишиной."""
    пустая = ('<html><head><meta name="robots" content="index, follow"/></head>'
              '<body>нет карточек</body></html>')
    _подменить(monkeypatch, "145.63.129.86", {"/": пустая})
    итог = ИНСТР.проверить("pusto.test")
    assert итог["источник_слагов"] == ""
    assert any("ни карта, ни главная" in б for б in итог["беды"]), итог["беды"]
