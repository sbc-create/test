    assert editorial.обрезать("  текст\n\n") == "текст"
    assert editorial.обрезать(None) == ""
    исходник = (КОРЕНЬ / "factory" / "qwen" / "editorial.py").read_text("utf-8")
    подг = исходник.split("def подготовить", 1)[1].split("\ndef ", 1)[0]
