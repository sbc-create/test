def test_новостные_операции_предлагаются_по_факту_доставки(monkeypatch):
    """Перечень операций сайта не должен противоречить инструкции.

    Сессия редактора начинает с `sites`. Если новости в этом перечне не
    названы, она снова заключит, что механизма нет, — ровно так и вышло
    2026-10-05, когда новость оказалась записана в накладку описания карточки.
    Поэтому `posts-status` предлагается КАЖДОМУ сайту семейства, у которого
    механизм новостей есть: ею и выясняется, подключена ли доставка. А три
    пишущие операции — только там, где доставка ИЗМЕРЕНА: предлагать их
    домену, чей контейнер файла не видит, значит обещать отказ.
    """
    s = registry.Сайт(site_id="y", domain="y.example", adapter="yummy",
                      public_http="200", published_release="deadbeef")
    monkeypatch.setattr(registry, "_доставка_новостей", lambda _s: "")
    monkeypatch.setattr(registry, "наложение_в_контейнере", lambda _d: "")
    без_доставки = registry.доступные_операции(s)
    assert "posts-status" in без_доставки, (
        "без posts-status сессия не может выяснить, подключена ли доставка")
    for оп in ("posts-prepare", "posts-publish", "posts-unpublish"):
        assert оп not in без_доставки, (
            f"{оп} предложена домену, чей контейнер файла доставки не видит")

    monkeypatch.setattr(registry, "_доставка_новостей",
                        lambda _s: "контейнер читает /app/content/x.json")
    с_доставкой = registry.доступные_операции(s)
    for оп in ("posts-status", "posts-prepare", "posts-publish",
               "posts-unpublish"):
        assert оп in с_доставкой, оп


