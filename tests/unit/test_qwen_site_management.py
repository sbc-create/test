# --- 1. Внутри инструмента нет второго списка домен ------------------------

def test_в_коде_инструмента_нет_зашитых_домен():
    """Задание: «Не создавай отдельный вручную поддерживаемый список доменов
    внутри инструмента». Проверяется не упоминание домена вообще — в описании
    возможности адаптера стоит «проверено на yummyani.site», и это запись о
    проведённой проверке, а не список.

    Проверяется другое: домен не участвует в ПОВЕДЕНИИ. Литерал домена не может
    быть ключом словаря, элементом перечисления или стороной сравнения —
    именно так выглядел бы второй список, расходящийся с реестром.
    """
    зона = re.compile(r"^[a-z0-9][a-z0-9-]*\.(?:biz|org|site|space|info|icu|cc|online)$")

    def домен(узел) -> str:
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            if зона.match(узел.value.strip()):
                return узел.value
        return ""

    найдено: list[str] = []
    for файл in sorted((КОРЕНЬ / "factory" / "qwen").glob("*.py")):
        дерево = ast.parse(файл.read_text(encoding="utf-8"))
        for узел in ast.walk(дерево):
            подозрительные = []
            if isinstance(узел, ast.Dict):
                подозрительные = [к for к in узел.keys if к is not None]
            elif isinstance(узел, (ast.List, ast.Set, ast.Tuple)):
                подозрительные = list(узел.elts)
            elif isinstance(узел, ast.Compare):
                подозрительные = [узел.left, *узел.comparators]
            for п in подозрительные:
                если = домен(п)
                if если:
                    найдено.append(f"{файл.name}:{getattr(п, 'lineno', '?')} {если}")
    assert not найдено, (
        f"домены участвуют в поведении инструмента: {найдено} — это второй "
        "список, который разойдётся с реестром")


