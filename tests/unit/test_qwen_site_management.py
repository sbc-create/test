def test_домен_только_из_сетевого_списка_всё_равно_попадает_в_обзор(monkeypatch):
    """Два работающих сайта однажды пропустили именно потому, что реестр ячеек
    приняли за полный список. Проверяется МЕХАНИЗМ объединения источников.

    Прежняя редакция требовала, чтобы расхождение существовало НА САМОМ ДЕЛЕ:
    `_домены_сети() - домены_ячеек` обязано было быть непустым. Это требование
    от теста к состоянию мира, а не к коду: 2026-10-03 оба пропущенных домена
    внесены в реестр ячеек (`animego-02`, `animego-03`), расхождение исчезло —
    и тест покраснел на ЗАКРЫТОМ дефекте. Тест не должен требовать, чтобы
    дефект сохранялся.

    Поэтому домен, которого нет в реестре ячеек, подставляется в сетевой
    список стендом: механизм обязан его подхватить независимо от того, есть ли
    такие домены сегодня.
    """
    список = tmp_сетевой(monkeypatch, "только-в-сети.example")
    assert список in (registry.СЕТЕВОЙ_СПИСОК,), "подмена списка не применилась"
    из_ячеек: set[str] = set()
    for я in registry._ячейки():
        из_ячеек.update(я.get("domains") or ([я["domain"]] if я.get("domain") else []))
    сеть = registry._домены_сети()
    assert "только-в-сети.example" in сеть, сеть
    только_в_сети = set(сеть) - из_ячеек
    assert "только-в-сети.example" in только_в_сети, (
        "домен, которого нет в реестре ячеек, потерялся при объединении "
        "источников: именно так однажды и пропали два работающих сайта")
    сайты = registry.собрать(опрашивать_сеть=False)
    домены = {s.domain for s in сайты}
    assert "только-в-сети.example" in домены, (
        "обзор берёт домены только из реестра ячеек — второй источник бесполезен")
    чужой = next(s for s in сайты if s.domain == "только-в-сети.example")
    assert чужой.site_id.startswith("(вне реестра)"), (
        "домену вне реестра выдан идентификатор ячейки: это выдумка, а не факт")


def tmp_сетевой(monkeypatch, домен: str):
    """Сетевой список стенда: настоящий разбор, свой файл."""
    import tempfile

    каталог = pathlib.Path(tempfile.mkdtemp())
    файл = каталог / "network-allowlist.yaml"
    строки = ["hosts:"]
    for я in registry._ячейки()[:3]:
        if я.get("domain"):
            строки += [f"  - ref: site-{я['site_id']}", f"    host: {я['domain']}"]
    строки += ["  - ref: site-вне-реестра", f"    host: {домен}"]
    файл.write_text("\n".join(строки) + "\n", encoding="utf-8")
    monkeypatch.setattr(registry, "СЕТЕВОЙ_СПИСОК", файл)
    return файл


