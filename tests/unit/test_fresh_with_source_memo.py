"""REQ-CELL-FRESH-MEMO: новинки с источником считаются один раз на снимок.

Профиль главной ПОСЛЕ памятки подборок: страница 0.23 с, и весь остаток — это
`новинки_с_источником` (0.595 с под профилировщиком): сортировка всех 64 508
записей по дате и 64 508 вызовов `состояние_плеера`/`источник_плеера`.
Сканировался весь каталог, потому что playable-записей среди самых свежих
мало.

Срок жизни памятки подсказан устройством доставки, а не удобством:
`k2-catalog-apply.sh` ПЕРЕЗАПУСКАЕТ юнит — «рантайм читает каталог при старте,
а не по mtime», — и `Снимок.получить` в рантайме тоже держит снимок на время
процесса. Новый каталог означает новый процесс, поэтому памятка на объекте
подробностей живёт ровно столько, сколько должна.

После правки главная на том же стенде: 0.0013 с против 1.4 с, при побайтово
совпавшей разметке (sha256).
"""
from __future__ import annotations

from pathlib import Path

import pytest

from lords_runtime_harness import (Стенд, выгрузить, загрузить, запись,
                                   подробность)

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _тело() -> str:
    начало = ТЕКСТ.index("def новинки_с_источником(")
    return ТЕКСТ[начало:ТЕКСТ.index("\ndef ", начало + 10)]


def test_памятка_живёт_на_подробностях():
    тело = _тело()
    assert 'getattr(подробности, "_новинки", None)' in тело
    assert "подробности._новинки = памятка" in тело


def test_ключ_памятки_включает_сколько():
    """Лента главной и другие вызовы просят разное число записей."""
    тело = _тело()
    assert "сколько in памятка" in тело
    assert "памятка[сколько] = собрано" in тело


def test_отбор_остался_прежним():
    """Правка про стоимость: условие playable и порядок по дате не менялись."""
    тело = _тело()
    assert 'состояние_плеера(подробности.get(запись["slug"]))[0] != "playable"' in тело
    assert 'key=lambda з: з.get("published_at") or ""' in тело
    assert "reverse=True" in тело


@pytest.fixture()
def модуль(tmp_path, monkeypatch):
    стенд = Стенд(tmp_path, профиль="lords-films")
    записи = [запись(f"film-{н:03d}", title=f"Фильм {н}",
                     published_at=f"2026-10-{1 + н % 28:02d}")
              for н in range(10)]
    детали = [подробность(f"film-{н:03d}", type_="movie") for н in range(10)]
    стенд.записать_каталог(записи)
    стенд.записать_подробности(детали)
    стенд.записать_плеер()
    м = загрузить(стенд, monkeypatch)
    try:
        yield м
    finally:
        выгрузить(м)


def test_второй_вызов_не_повторяет_обход(модуль):
    """Считаются ВЫЗОВЫ `состояние_плеера`: время на малом снимке — шум."""
    д = модуль.Данные(модуль.КАТАЛОГ_ФАЙЛ)
    п = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    счёт = {"раз": 0}
    исходная = модуль.состояние_плеера

    def обёртка(деталь):
        счёт["раз"] += 1
        return исходная(деталь)

    модуль.состояние_плеера = обёртка
    try:
        первый = модуль.новинки_с_источником(д, п, 4)
        после = счёт["раз"]
        assert после >= 1, "обход не состоялся — проверка слепа"
        второй = модуль.новинки_с_источником(д, п, 4)
        assert счёт["раз"] == после, (
            f"обход повторился: было {после}, стало {счёт['раз']}")
        assert [з["slug"] for з in второй] == [з["slug"] for з in первый]
    finally:
        модуль.состояние_плеера = исходная


def test_другое_число_считается_заново(модуль):
    """Отрицательный контроль: памятка по `сколько`, а не одна на всё."""
    д = модуль.Данные(модуль.КАТАЛОГ_ФАЙЛ)
    п = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    четыре = модуль.новинки_с_источником(д, п, 4)
    восемь = модуль.новинки_с_источником(д, п, 8)
    assert len(четыре) <= 4
    assert len(восемь) >= len(четыре), (
        "по большему пределу вернулось меньше записей — памятка отдала чужой "
        "ответ")


def test_новые_подробности_память_не_наследуют(модуль, tmp_path):
    """Новый снимок — новый объект — пустая памятка."""
    д = модуль.Данные(модуль.КАТАЛОГ_ФАЙЛ)
    п1 = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    модуль.новинки_с_источником(д, п1, 4)
    assert getattr(п1, "_новинки", None), "памятка не появилась"
    п2 = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    assert getattr(п2, "_новинки", None) in (None, {}), (
        "новый объект подробностей унаследовал память прежнего")
