def test_dry_run_ничего_не_записывает(м, tmp_path):
    каталог = _песочница(м, tmp_path, домены=[{"domain": ДОМЕН,
                                               "family": "k2"}])
    м.ИЗМЕРЕНО = {ДОМЕН: {"MOD-1": {"state": "подготовлено"}}}
    м.K2 = ()
    файл = каталог / "q.json"
