import pytest

ИСТОЧНИК = (Path(__file__).resolve().parents[2]
            / "automation" / "local" / "first-cycle.py")

ДОМЕН = "example.test"


@pytest.fixture()
def м():
    спец = importlib.util.spec_from_file_location("first_cycle", ИСТОЧНИК)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def _очередь(задачи, домен=ДОМЕН, stage=2):
    return {"domain": домен, "executor": "линия-1", "stage": stage,
            "tasks": задачи}


def _задача(ид, state, **ещё):
    з = {"id": ид, "state": state, "title": f"задача {ид}",
         "problem": "п", "evidence": "д", "action": "а"}
    з.update(ещё)
    return з


def _песочница(м, tmp_path, *, домены=(), снимок=None, разбор=None):
    """Подменить ВСЕ внешние чтения модуля на каталог теста."""
    м.ОЧЕРЕДИ = tmp_path / "queues"
    м.ОЧЕРЕДИ.mkdir(exist_ok=True)
    м.СПИСОК = tmp_path / "active-domains.json"
    м.СПИСОК.write_text(json.dumps({"domains": list(домены)},
                                   ensure_ascii=False), encoding="utf-8")
    м.СНИМОК_СПРОСА = tmp_path / "demand.json"
    if снимок is not None:
        м.СНИМОК_СПРОСА.write_text(json.dumps(снимок, ensure_ascii=False),
                                   encoding="utf-8")
    м.РАЗБОР_КОНКУРЕНТОВ = tmp_path / "competitive.md"
    if разбор is not None:
        м.РАЗБОР_КОНКУРЕНТОВ.write_text(разбор, encoding="utf-8")
    return м.ОЧЕРЕДИ


def test_названный_блокер_не_перебивается_таблицей(м):
    оч = _очередь([_задача("T-1", "заблокировано", defect="MOD-1",
                           blocked_by="решение владельца: подмена сценария")])
    изм = м.применить(оч, {"MOD-1": {"state": "подготовлено"}})
    assert оч["tasks"][0]["state"] == "заблокировано"
    assert len(изм) == 1 and "СОХРАНЕНО" in изм[0]


def test_блокер_без_названной_причины_таблица_перебивает(м):
    """Пустой `blocked_by` — не вывод, а пропуск: защищать нечего."""
    оч = _очередь([_задача("T-1", "заблокировано", defect="MOD-1",
                           blocked_by="   ")])
    изм = м.применить(оч, {"MOD-1": {"state": "подготовлено"}})
    assert оч["tasks"][0]["state"] == "подготовлено"
    assert изм == ["T-1 заблокировано → подготовлено"]


def test_таблица_подтверждающая_блокировку_не_считается_сохранением(м):
    оч = _очередь([_задача("T-1", "заблокировано", defect="MOD-1",
                           blocked_by="доступ не выдан")])
