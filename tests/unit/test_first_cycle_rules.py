"""Правила первого цикла: чего он НЕ делает.

Проверки защищают выводы, сделанные ПОЗЖЕ таблицы цикла, и честность его
собственной печати. Все найдены повторным запуском самого цикла 2026-10-22,
а не чтением кода.
"""
from __future__ import annotations

import importlib.util
