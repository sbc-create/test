def _прогнать(м, аргв=("--dry-run",)):
    буфер = io.StringIO()
    with redirect_stdout(буфер):
        код = м.main(list(аргв))
    return код, буфер.getvalue()


def test_каждое_изменение_печатается_целиком(м, tmp_path):
    """Склейка в одну обрезанную строку спрятала восемь изменений из восьми.

    Печать `метка[:72]` показывала только первую запись домена; остальные
    исчезали без следа, и печать расходилась со счётчиком — на сверку этого
    расхождения ушёл отдельный разбор.
    """
    каталог = _песочница(м, tmp_path, домены=[{"domain": ДОМЕН,
                                               "family": "k2"}])
    длинная = "причина, названная подробно: " + "ы" * 90
    м.ИЗМЕРЕНО = {ДОМЕН: {"MOD-1": {"state": "подготовлено"},
                          "MOD-2": {"state": "опубликовано",
                                    "published_url": "https://x.test/"}}}
    м.K2 = ()
    (каталог / "q.json").write_text(json.dumps(_очередь([
        _задача("T-1", "заблокировано", defect="MOD-1", blocked_by=длинная),
        _задача("T-2", "проверено", defect="MOD-2"),
    ]), ensure_ascii=False), encoding="utf-8")
    код, вывод = _прогнать(м)
    assert код == 0
    assert "T-2 проверено → опубликовано" in вывод
    assert "T-1" in вывод and "СОХРАНЕНО" in вывод


