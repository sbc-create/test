def test_очередь_целиком_в_блокерах_не_получает_задачу_этапа_2(м, tmp_path):
    """Нет рабочих задач по ДВУМ разным причинам, лечение у них разное.

    «Закрыто» — работа сделана, нужна следующая. «Заблокировано с названной
    причиной» — работа стоит на внешнем ограничении, и выдача задачи в
    рабочем состоянии объявила бы доступным шаг, которого нет.
    """
    _песочница(м, tmp_path, домены=[{"domain": ДОМЕН, "family": "k2"}])
    оч = _очередь([_задача("T-1", "закрыто"),
                   _задача("T-2", "заблокировано",
                           blocked_by="решение владельца не принято")])
    assert м.добавить_задачу_спроса(оч) is False
    assert len(оч["tasks"]) == 2


def test_полностью_закрытая_очередь_задачу_этапа_2_получает(м, tmp_path):
    _песочница(м, tmp_path, домены=[{"domain": ДОМЕН, "family": "k2"}])
