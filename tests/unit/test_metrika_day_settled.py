"""Присутствующие сутки могут быть занижены: это не «пропуск» и не измерение.

Повод записан в самой мере: сутки 11.10 у `yummyani.site` читались как 341
визит в выгрузках 12.10 и 13.10 и доросли до 2 997 в выгрузке 14.10 — 11 % от
итога. Правило «пропуск — не ноль» этого не ловит: сутки на месте.

Допуск проверяется в обе стороны: устоявшиеся сутки меняются на единицы
визитов (4 065 → 4 068), и объявлять их «не устоявшимися» нельзя.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "metrika-day-settled.py"

спец = importlib.util.spec_from_file_location("metrika_day_settled", ПУТЬ)
модуль = importlib.util.module_from_spec(спец)
assert спец.loader is not None
спец.loader.exec_module(модуль)


def _ряд(*пары) -> dict:
    """Запись домена с суточным разрезом из пар (сутки, визиты)."""
    return {"measurements": [{
        "key": "daily_users", "measured": True,
        "value": [{"dimensions": [{"name": с}, {"name": "People", "id": "no"}],
                   "metrics": [v, v]} for с, v in пары]}]}


# --- чтение ряда -----------------------------------------------------------

def test_люди_и_роботы_складываются():
    запись = {"measurements": [{"key": "daily_users", "measured": True, "value": [
        {"dimensions": [{"name": "2026-10-11"}, {"name": "People", "id": "no"}],
         "metrics": [10.0, 20.0]},
        {"dimensions": [{"name": "2026-10-11"}, {"name": "Robots", "id": "yes"}],
         "metrics": [1.0, 5.0]},
    ]}]}
    assert модуль.ряд_суток(запись) == {"2026-10-11": 25.0}


def test_вторая_метрика_это_визиты():
    # Источник разреза — `ym:s:users × ym:s:date × ym:s:isRobot`, но метрик две,
    # и берётся ВТОРАЯ: сравнение идёт по визитам, как в показателе `visits`.
    запись = _ряд(("2026-10-11", 7.0))
    запись["measurements"][0]["value"][0]["metrics"] = [7.0, 12.0]
    assert модуль.ряд_суток(запись) == {"2026-10-11": 12.0}


def test_неизмеренный_разрез_это_None_а_не_пустой_ряд():
    запись = {"measurements": [{"key": "daily_users", "measured": False,
                                "reason": "счётчик Метрики не создан"}]}
    assert модуль.ряд_суток(запись) is None


def test_отсутствующий_разрез_это_None():
    assert модуль.ряд_суток({"measurements": [{"key": "visits",
                                               "measured": True,
                                               "value": 5}]}) is None


def test_сутки_без_имени_пропускаются():
    запись = {"measurements": [{"key": "daily_users", "measured": True, "value": [
        {"dimensions": [], "metrics": [5.0, 5.0]},
        {"dimensions": [{"name": "2026-10-11"}], "metrics": [1.0, 2.0]},
    ]}]}
    assert модуль.ряд_суток(запись) == {"2026-10-11": 2.0}


# --- устойчивость ----------------------------------------------------------

def test_рост_в_разы_это_не_устоялось():
    assert модуль.устоялось([341.0, 341.0, 2997.0]) == модуль.НЕ_УСТОЯЛОСЬ


def test_три_визита_на_четыре_тысячи_это_устоялось():
    assert модуль.устоялось([4065.0, 4068.0]) == модуль.УСТОЯЛОСЬ


def test_малый_домен_с_четырёх_до_восьмидесяти_пяти_не_устоялся():
    # 4 → 85 проходит по абсолютному допуску только если смотреть на долю.
    assert модуль.устоялось([4.0, 85.0]) == модуль.НЕ_УСТОЯЛОСЬ


def test_большой_скачок_в_пределах_пяти_визитов_всё_равно_устоялся():
    assert модуль.устоялось([1000.0, 1004.0]) == модуль.УСТОЯЛОСЬ


def test_два_визита_из_трёх_не_устоялись():
    # Три визита — это 33 % от трёх: доля решает, допуск в визитах не спасает.
    assert модуль.устоялось([1.0, 3.0]) == модуль.НЕ_УСТОЯЛОСЬ


def test_единственное_чтение_не_исход_а_отсутствие_сверки():
    assert модуль.устоялось([2997.0]) == модуль.НЕ_С_ЧЕМ


def test_пустые_чтения_это_не_измерено():
    assert модуль.устоялось([]) == модуль.НЕ_ИЗМЕРЕНО


def test_смотрятся_только_два_последних_чтения():
    # Сутки доросли и застыли: раннее занижение не делает их неустоявшимися.
    assert модуль.устоялось([341.0, 2997.0, 2997.0]) == модуль.УСТОЯЛОСЬ


# --- выбор выгрузки --------------------------------------------------------

def test_выбирается_самая_ранняя_выгрузка_где_окно_устоялось():
    ряды = {
        "analytics-2026-10-12.json": {"2026-10-10": 4065.0, "2026-10-11": 341.0},
        "analytics-2026-10-13.json": {"2026-10-10": 4065.0, "2026-10-11": 341.0},
        "analytics-2026-10-14.json": {"2026-10-10": 4068.0, "2026-10-11": 2997.0},
        "analytics-2026-10-15.json": {"2026-10-10": 4068.0, "2026-10-11": 2997.0},
    }
    окно = ["2026-10-10", "2026-10-11"]
    assert модуль.первая_устоявшаяся(окно, ряды) == "analytics-2026-10-14.json"


def test_выгрузка_без_всех_суток_окна_не_годится():
    ряды = {
        "analytics-2026-10-12.json": {"2026-10-11": 2997.0},
        "analytics-2026-10-13.json": {"2026-10-11": 2997.0,
                                      "2026-10-12": 2157.0},
    }
    окно = ["2026-10-11", "2026-10-12"]
    assert модуль.первая_устоявшаяся(окно, ряды) == "analytics-2026-10-13.json"


def test_суток_за_пределами_всех_окон_значит_брать_нечего():
    """Сутки, которых не покрывает ни одно окно, — не измерены, а не ноль."""
    ряды = {"analytics-2026-10-13.json": {"2026-10-11": 2997.0}}
    assert модуль.первая_устоявшаяся(["2026-10-11", "2026-10-30"], ряды) is None


def test_сутки_без_строки_внутри_окна_это_ноль_визитов_а_не_пробел():
    """Моя первая редакция меры дала «НЕ НАЙДЕНА» у 8 домов из 21 из-за этого.

    Измерено 22.10: у `zonafilm.space` суток 08.10 нет ни в одной из 12
    выгрузок, которые её покрывают, при наличии соседних суток. Метрика не
    отдаёт нулевых строк, и объявлять из-за них всё окно непригодным нельзя.
    """
    ряды = {
        "analytics-2026-10-13.json": {"2026-10-07": 5.0, "2026-10-09": 7.0},
        "analytics-2026-10-14.json": {"2026-10-07": 5.0, "2026-10-09": 7.0},
    }
    окно = ["2026-10-07", "2026-10-08", "2026-10-09"]
    assert модуль.сутки_без_визитов(окно, ряды) == {"2026-10-08": 2}
    assert модуль.первая_устоявшаяся(окно, ряды) == "analytics-2026-10-13.json"


def test_покрытие_различает_сутки_внутри_и_снаружи_ряда():
    ряды = {"a.json": {"2026-10-07": 1.0, "2026-10-09": 2.0}}
    assert модуль.покрывают("2026-10-08", ряды) == ["a.json"]
    assert модуль.покрывают("2026-10-10", ряды) == []


def test_верхний_край_окна_берётся_из_имени_а_не_из_строк():
    assert модуль.конец_окна("analytics-2026-10-19.json") == "2026-10-18"
    assert модуль.конец_окна("без-даты.json") == ""


def test_последние_сутки_окна_без_визитов_не_делают_выгрузку_короткой():
    """Случай `1lordserials1.online`: нет строк за 16.10 и 18.10.

    Если верхний край окна считать по строкам, выгрузка 19.10 окажется
    «кончающейся 17.10» и будет отвергнута, хотя она покрывает всё окно.
    """
    ряды = {
        "analytics-2026-10-19.json": {"2026-10-15": 3.0, "2026-10-17": 4.0},
        "analytics-2026-10-20.json": {"2026-10-15": 3.0, "2026-10-17": 4.0},
    }
    окно = ["2026-10-15", "2026-10-16", "2026-10-17", "2026-10-18"]
    assert модуль.сутки_без_визитов(окно, ряды) == {"2026-10-16": 2,
                                                   "2026-10-18": 2}
    assert модуль.первая_устоявшаяся(окно, ряды) == "analytics-2026-10-19.json"


def test_ноль_визитов_не_назначается_там_где_окно_не_покрыто():
    # Сутки позже всех прочитанных — не «ноль визитов», а отсутствие данных.
    ряды = {"a.json": {"2026-10-07": 1.0}}
    assert модуль.сутки_без_визитов(["2026-10-30"], ряды) == {}


def test_итоговым_считается_чтение_из_самой_поздней_выгрузки():
    # Если бы итог брался из первой, занижение 341 стало бы «итогом», и вся
    # мера показывала бы устойчивость там, где её нет.
    ряды = {
        "analytics-2026-10-12.json": {"2026-10-11": 341.0},
        "analytics-2026-10-20.json": {"2026-10-11": 2997.0},
    }
    assert модуль.первая_устоявшаяся(["2026-10-11"], ряды) == \
        "analytics-2026-10-20.json"


# --- разбор ----------------------------------------------------------------

def test_разбор_называет_долю_первого_чтения():
    ряды = {
        "analytics-2026-10-12.json": {"2026-10-11": 341.0},
        "analytics-2026-10-13.json": {"2026-10-11": 341.0},
        "analytics-2026-10-14.json": {"2026-10-11": 2997.0},
    }
    разбор = модуль.разобрать(ряды)
    запись = разбор["2026-10-11"]
    assert запись["исход"] == модуль.НЕ_УСТОЯЛОСЬ
    assert запись["чтений"] == 3
    assert запись["первое_чтение"] == 341.0
    assert запись["итоговое"] == 2997.0
    assert запись["доля_первого"] == pytest.approx(341 / 2997)
    assert запись["выгрузки"] == ["2026-10-12", "2026-10-13", "2026-10-14"]


def test_незнакомый_разрез_отклоняется_а_не_складывает_отказы():
    """Порядок метрик у разрезов разный: у профиля вторая метрика — отказы."""
    with pytest.raises(KeyError):
        модуль.ряд_суток(_ряд(("2026-10-11", 5.0)), ключ="visits")


def test_у_профиля_визиты_первая_метрика():
    запись = {"measurements": [{
        "key": "daily_traffic_profile", "measured": True,
        "value": [{"dimensions": [{"name": "2026-10-11"}],
                   "metrics": [120.0, 81.95, 1.05, 33.4]}]}]}
    assert модуль.ряд_суток(запись, ключ="daily_traffic_profile") == \
        {"2026-10-11": 120.0}


def test_исходы_различимы():
    assert len({модуль.УСТОЯЛОСЬ, модуль.НЕ_УСТОЯЛОСЬ, модуль.НЕ_С_ЧЕМ,
                модуль.НЕ_ИЗМЕРЕНО}) == 4
