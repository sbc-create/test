"""Полнота карты сайта: предел внутри ОДНОЙ карты не растворяется в сумме.

Измерено 13.10 на `yummyani.site`: всего 17 697 адресов в пяти картах — выглядит
благополучно. А `titles.xml` в них **ровно 8000**, и это B016: обрезка
`walkAnimeListItems(maxPages=80, limit=100)`, из-за которой 366 живых тайтлов в
карту не попали. Признак, считающий только сумму, этого не видит.

Эталон числа записей берётся из того, что витрина печатает САМА, а не из моего
представления о размере каталога.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "sitemap-completeness.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("sitemap_completeness", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_круглые_пределы_названы_числами():
    """«Подозрительно круглое» непроверяемо; перечень — проверяемое утверждение."""
    assert 8000 in МОД.КРУГЛЫЕ, МОД.КРУГЛЫЕ
    assert 10000 in МОД.КРУГЛЫЕ
    assert all(isinstance(ч, int) for ч in МОД.КРУГЛЫЕ)


def test_предел_ищется_по_каждой_карте_а_не_по_сумме():
    """Главное свойство: в сумме 17 697 предел 8000 не виден."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "ПО КАЖДОЙ карте" in текст
    assert "for имя, сколько in карты:" in текст
    # И сумма пяти карт Yummy названа в коде как измеренный пример.
    assert "17 697" in текст


def test_число_записей_берётся_из_текста_страницы():
    """Четыре формы, и все встречаются в сети."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    for форма in ("записей в выборке", "записей в разделе", "тайтлов"):
        assert форма in текст, форма


def test_пробелы_внутри_числа_не_ломают_разбор():
    """Витрина печатает «62 978» с неразрывным пробелом."""
    import re
    образец = "показано 24 из 62 978 записей в выборке"
    м = re.search(r"([\d\s  ]{3,})\s*записей в выборке", образец)
    assert м, образец
    assert int(re.sub(r"[^\d]", "", м.group(1))) == 62978


def test_без_числа_записей_вывод_о_полноте_не_делается():
    """Нечитаемое число — предел измерения, а не «карта полна»."""
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "вывод о полноте НЕ делается" in текст
    assert "сравнивать не с чем" in текст


def test_карта_не_двести_это_не_измерено():
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "карта НЕ ИЗМЕРЕНА" in текст


def test_зарезервированные_имена_не_обходятся():
    assert all(not д.endswith((".test", ".localhost")) for д in МОД.домены())
