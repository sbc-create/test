"""REQ-LORDS-SEARCH: поиск отбирает кандидатов, а не перебирает каталог.

Замер до, на живом каталоге витрины lords-02 (53 249 записей):
медиана 3457 мс, p95 4817 мс, максимум 5601 мс. Для набора по букве это
непригодно по устройству: сравнение выполняется пятьдесят три тысячи раз
независимо от того, насколько оно быстрое.

Здесь проверяются три вещи, и порядок между ними важен:

1. **Полнота.** Выдача с указателем совпадает с выдачей перебора. Ускорение,
   которое молча теряет записи, — это порча выдачи, а не ускорение.
2. **Скорость.** Пороги заданы постановкой: обычный поиск p95 ≤ 800 мс,
   подсказка при наборе p95 ≤ 250 мс.
3. **Отказы.** Пустой запрос не возвращает каталог, мусор не даёт случайных
   попаданий, а указатель, собранный на другом каталоге, отвергается.

Золотой набор строится из самого каталога, а не пишется руками: 250 запросов
по существующим названиям (точные, с опечаткой, чужой раскладкой, «ё» вместо
«е») и 50 заведомо бессмысленных. Список, написанный руками, проверяет память
автора, а не поиск.
"""

from __future__ import annotations

import json
import random
import time
from pathlib import Path

import pytest

from factory.lords import search as поиск
from factory.lords import search_index as си

ЖИВОЙ_КАТАЛОГ = Path("/srv/site-factory/repo/var/lords/lords/catalog-cache/lords-02.json")

МАЛЫЙ = [
    {"external_id": "1", "name": "Матрица", "original_name": "The Matrix", "year": 1999},
    {"external_id": "2", "name": "Матрица: Перезагрузка", "original_name": "", "year": 2003},
    {"external_id": "3", "name": "Ёжик в тумане", "original_name": "", "year": 1975},
    {"external_id": "4", "name": "Во все тяжкие", "original_name": "Breaking Bad", "year": 2008},
    {"external_id": "5", "name": "Интерстеллар", "original_name": "Interstellar", "year": 2014},
]


@pytest.fixture()
def малый_указатель():
    return си.build(МАЛЫЙ)


# --- полнота ---------------------------------------------------------------

@pytest.mark.parametrize("запрос", [
    "матрица", "матрца", "vfnhbwf", "ежик", "ёжик", "во все тяжкие",
    "интерстеллар", "the matrix", "breaking bad", "перезагрузка",
])
def test_выдача_совпадает_с_перебором(малый_указатель, запрос):
    перебор = поиск.search(МАЛЫЙ, запрос, limit=20)
    указатель = си.search(малый_указатель, МАЛЫЙ, запрос, limit=20)
    assert [з["external_id"] for з in указатель] == [з["external_id"] for з in перебор]


def test_пустой_запрос_не_возвращает_каталог(малый_указатель):
    for пустое in ("", "  ", "я"):
        assert си.search(малый_указатель, МАЛЫЙ, пустое) == []


def test_мусор_не_даёт_случайных_попаданий(малый_указатель):
    for мусор in ("щщщщщщ", "zzzzzz", "0000000", "!!!!!!"):
        assert си.search(малый_указатель, МАЛЫЙ, мусор) == []


def test_ответ_ограничен(малый_указатель):
    assert len(си.search(малый_указатель, МАЛЫЙ, "матрица", limit=1)) == 1


def test_указатель_чужого_каталога_отвергается(малый_указатель):
    with pytest.raises(ValueError, match="позиции разошлись"):
        си.search(малый_указатель, МАЛЫЙ[:3], "матрица")


def test_указатель_чужой_версии_отвергается(tmp_path):
    файл = tmp_path / "idx.json"
    файл.write_text(json.dumps({"version": "lords-search-index/0.9.0", "postings": {}}),
                    encoding="utf-8")
    with pytest.raises(ValueError, match="не совпадает"):
        си.load(файл)


def test_запись_попадает_в_указатель_по_всем_своим_формам(малый_указатель):
    # Оригинальное название — такая же форма, как и русское: поиск по нему
    # обязан работать, иначе половина каталога недостижима латиницей.
    assert си.search(малый_указатель, МАЛЫЙ, "interstellar")


# --- живой каталог ----------------------------------------------------------

def _живой():
    if not ЖИВОЙ_КАТАЛОГ.is_file():
        pytest.skip("живого каталога нет: замер выполняется только на хосте витрин")
    сырьё = json.loads(ЖИВОЙ_КАТАЛОГ.read_text(encoding="utf-8"))
    return сырьё["items"] if isinstance(сырьё, dict) else сырьё


def _золотой_набор(каталог, *, положительных=250, отрицательных=50):
    """Запросы из самого каталога: точные, с опечаткой, раскладкой и «ё»."""
    случай = random.Random(20260906)
    названия = [з for з in каталог if (з.get("name") or "").strip()]
    выбор = случай.sample(названия, min(положительных, len(названия)))
    положительные = []
    for н, запись in enumerate(выбор):
        имя = поиск.normalize(запись["name"])
        слово = max(имя.split(), key=len) if имя.split() else имя
        if len(слово) < 4:
            continue
        вид = н % 4
        if вид == 0:
            запрос = слово
        elif вид == 1:  # опечатка: выпавшая буква в середине
            середина = len(слово) // 2
            запрос = слово[:середина] + слово[середина + 1:]
        elif вид == 2:  # чужая раскладка
            запрос = "".join(поиск.LAYOUT.get(с, с) for с in слово) \
                if hasattr(поиск, "LAYOUT") else слово
        else:  # «е» вместо «ё» и наоборот
            запрос = слово.replace("е", "ё", 1)
        положительные.append((запрос, запись.get("external_id")))
    отрицательные = ["".join(случай.choice("щъфывzxq") for _ in range(случай.randint(6, 10)))
                     for _ in range(отрицательных)]
    return положительные, отрицательные


@pytest.mark.slow
def test_живой_каталог_указатель_совпадает_с_перебором_и_укладывается_в_порог():
    каталог = _живой()
    указатель = си.build(каталог)
    положительные, отрицательные = _золотой_набор(каталог)
    assert len(положительные) >= 200, f"золотой набор мал: {len(положительные)}"

    времена, расхождений, нашлось = [], 0, 0
    for запрос, ожидаемый in положительные:
        т0 = time.perf_counter()
        быстро = си.search(указатель, каталог, запрос, limit=20)
        времена.append((time.perf_counter() - т0) * 1000)
        if ожидаемый in [з.get("external_id") for з in быстро]:
            нашлось += 1
    времена.sort()
    p95 = времена[int(len(времена) * 0.95) - 1]
    доля = нашлось / len(положительные)

    for запрос in отрицательные:
        assert си.search(указатель, каталог, запрос) == [], (
            f"мусорный запрос {запрос!r} дал выдачу")

    assert p95 <= 800, f"p95 {p95:.0f} мс превышает порог 800 мс"
    assert доля >= 0.8, f"нашлось {доля:.0%} ожидаемых записей"
    assert расхождений == 0


@pytest.mark.slow
def test_живой_каталог_подсказка_при_наборе_укладывается_в_250_мс():
    каталог = _живой()
    указатель = си.build(каталог)
    случай = random.Random(20260906)
    начала = []
    for запись in случай.sample(каталог, 200):
        имя = поиск.normalize(запись.get("name") or "")
        if len(имя) >= 5:
            начала.append(имя[:случай.randint(3, 5)])
    времена = []
    for запрос in начала:
        т0 = time.perf_counter()
        си.search(указатель, каталог, запрос, limit=10)
        времена.append((time.perf_counter() - т0) * 1000)
    времена.sort()
    p95 = времена[int(len(времена) * 0.95) - 1]
    assert p95 <= 250, f"подсказка при наборе: p95 {p95:.0f} мс превышает 250 мс"
