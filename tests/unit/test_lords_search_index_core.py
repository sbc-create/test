"""REQ-LORDS-SEARCH: поиск отбирает кандидатов, а не перебирает каталог.

Замер до, на живом каталоге витрины lords-02 (53 249 записей):
медиана 3457 мс, p95 4817 мс, максимум 5601 мс. Для набора по букве это
непригодно по устройству: сравнение выполняется пятьдесят три тысячи раз
независимо от того, насколько оно быстрое.

Здесь проверяются три вещи, и порядок между ними важен:

1. **Полнота.** Выдача с указателем совпадает с выдачей перебора. Ускорение,
   которое молча теряет записи, — это порча выдачи, а не ускорение.
2. **Скорость.** Пороги заданы постановкой: обычный поиск p95 ≤ 800 мс,
   подсказка при наборе p95 ≤ 250 мс.
3. **Отказы.** Пустой запрос не возвращает каталог, мусор не даёт случайных
   попаданий, а указатель, собранный на другом каталоге, отвергается.

Золотой набор строится из самого каталога, а не пишется руками: 250 запросов
по существующим названиям (точные, с опечаткой, чужой раскладкой, «ё» вместо
«е») и 50 заведомо бессмысленных. Список, написанный руками, проверяет память
автора, а не поиск.
"""

