"""Перепись и остановка процессов: признак сироты и отказы остановки.

Повод. 2026-10-11 фоновый редактор встал на своём пороге (MemAvailable 675 МиБ
при пороге 2048), а память держали пробные копии витрин, запущенные сессиями
24–29 сентября и оставшиеся без родителя. Останавливать их можно только с
доказательством, что они ничего не обслуживают, — цена ошибки здесь упавший
сайт.

Первая версия переписи определяла порт по сокетам процесса
(`/proc/<pid>/fd` + `/proc/net/tcp`) и записала в сироты ПОЛОВИНУ боевых
витрин: каталог `fd` читается не для всех процессов (витрины работают под
uid 984), и «порт не найден» было истолковано как «порт не слушается». Поэтому
признак строится на двух источниках, читаемых для любого процесса: порт из
командной строки и cgroup. Здесь это и сторожится — вместе с отказами
остановки, которые и есть главная защита.
"""
from __future__ import annotations

import importlib.util
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПЕРЕПИСЬ = КОРЕНЬ / "automation" / "local" / "orphan-process-audit.py"
ОСТАНОВКА = КОРЕНЬ / "automation" / "local" / "orphan-process-stop.py"
ПРОБНЫЙ_ПОРТ = 59997


def _модуль(путь: Path, имя: str):
    спец = importlib.util.spec_from_file_location(имя, путь)
    м = importlib.util.module_from_spec(спец)
    sys.modules[имя] = м
    спец.loader.exec_module(м)
    return м


@pytest.fixture()
def перепись():
    return _модуль(ПЕРЕПИСЬ, "orphan_process_audit")


@pytest.fixture()
def остановка():
    return _модуль(ОСТАНОВКА, "orphan_process_stop")


@pytest.fixture()
def пробный_процесс():
    """Настоящий процесс с `--port` в командной строке — наш и ничего не слушает."""
    п = subprocess.Popen(
        [sys.executable, "-c",
         # SIG_IGN наследуется от родителя: без явного возврата обработчика по
         # умолчанию пробный процесс не ответил бы на TERM, и проверка
         # остановки ничего бы не проверяла. Поймано на первом прогоне.
         "import signal,time; signal.signal(signal.SIGTERM, signal.SIG_DFL); "
         "time.sleep(120)", "--port", str(ПРОБНЫЙ_ПОРТ)],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(20):
        if Path(f"/proc/{п.pid}").exists():
            break
        time.sleep(0.1)
    yield п
    if п.poll() is None:
        try:
            os.kill(п.pid, signal.SIGKILL)
        except OSError:
            pass
        п.wait(timeout=10)


def test_порт_берётся_из_командной_строки(перепись, пробный_процесс):
    """Не из сокетов: `fd` читается не для всех процессов."""
    загрузка = float(Path("/proc/uptime").read_text().split()[0])
    п = перепись.процесс(пробный_процесс.pid, загрузка)
    assert п is not None
    assert п["port"] == ПРОБНЫЙ_ПОРТ
    assert п["uid"] == os.getuid()


def test_процесс_без_порта_не_считается_витриной(перепись):
    загрузка = float(Path("/proc/uptime").read_text().split()[0])
    assert перепись.процесс(os.getpid(), загрузка) is None, (
        "сам прогон проверок витриной не является")


def test_боевые_витрины_не_попадают_в_сироты(перепись):
    """Главная защита переписи, проверяемая на живом хосте.

    Витрина определяется независимо от инструмента: её командная строка ведёт в
    `/srv/<витрина>/releases/`. Ни одна такая не должна оказаться сиротой.
    """
    процессы, _ = перепись.собрать()
    выпуски = [п for п in процессы
               if "/srv/" in п["cmd"] and "/releases/" in п["cmd"]]
    if not выпуски:
        pytest.skip("на этом хосте нет выложенных витрин")
    ошибки = [(п["pid"], п["cmd"][:60]) for п in выпуски if п["вид"] == "сирота"]
    assert not ошибки, f"выложенные витрины записаны в сироты: {ошибки}"


def test_спорное_не_смешивается_с_сиротой(перепись):
    """Расхождение признаков — повод смотреть руками, а не вывод."""
    процессы, _ = перепись.собрать()
    for п in процессы:
        if п["in_nginx"] != п["service"]:
            assert п["вид"] == "спорно", п
        elif п["in_nginx"]:
            assert п["вид"] == "обслуживает", п
        else:
            assert п["вид"] == "сирота", п


# --- отказы остановки -------------------------------------------------------


def test_остановка_отказывает_чужому_владельцу(остановка, перепись,
                                                пробный_процесс, monkeypatch):
    настоящий = перепись.процесс
    monkeypatch.setattr(
        перепись, "процесс",
        # 984 — под этим uid на хосте работают выложенные витрины.
        lambda pid, загрузка: {**настоящий(pid, загрузка), "uid": 984})
    можно, причина = остановка.проверить(пробный_процесс.pid, перепись, {})
    assert можно is False
    assert "не наш" in причина


def test_остановка_отказывает_при_порте_в_nginx(остановка, перепись,
                                                пробный_процесс):
    можно, причина = остановка.проверить(
        пробный_процесс.pid, перепись, {ПРОБНЫЙ_ПОРТ: ["site.conf"]})
    assert можно is False
    assert "объявлен в nginx" in причина


def test_остановка_отказывает_службе(остановка, перепись, пробный_процесс,
                                     monkeypatch):
    настоящий = перепись.процесс
    monkeypatch.setattr(
        перепись, "процесс",
        lambda pid, загрузка: {**настоящий(pid, загрузка),
                               "cgroup": "nova-animedia-icu.service"})
    можно, причина = остановка.проверить(пробный_процесс.pid, перепись, {})
    assert можно is False
    assert "службе" in причина


def test_остановка_отказывает_несуществующему(остановка, перепись):
    можно, причина = остановка.проверить(4194300, перепись, {})
    assert можно is False
    assert "процесса нет" in причина


def test_без_подтверждения_сигнал_не_посылается(остановка, пробный_процесс, capsys):
    код = остановка.главное(["--pid", str(пробный_процесс.pid)])
    вывод = capsys.readouterr().out
    assert "[план ]" in вывод
    assert "сигналы не посылались" in вывод
    assert пробный_процесс.poll() is None, "процесс остановлен без --confirm"
    assert код == 0


def test_с_подтверждением_процесс_останавливается(остановка, пробный_процесс,
                                                  capsys):
    код = остановка.главное(["--pid", str(пробный_процесс.pid), "--confirm"])
    вывод = capsys.readouterr().out
    assert "[стоп ]" in вывод, вывод
    assert код == 0
    for _ in range(20):
        if пробный_процесс.poll() is not None:
            break
        time.sleep(0.2)
    assert пробный_процесс.poll() is not None, "процесс остался жив"


def test_остановка_не_добивает_sigkill():
    """Процесс, не ответивший на TERM, разбирается отдельно, а не добивается."""
    текст = ОСТАНОВКА.read_text(encoding="utf-8")
    assert "signal.SIGKILL" not in текст, "инструмент добивает процессы"
    assert "SIGTERM" in текст
    assert "не ответил на TERM" in текст
