"""Сбой между записью комментария и отметкой о публикации.

Самая опасная последовательность в редакционной публикации, и она не была
закрыта ни одной проверкой. Порядок в `_опубликовать_в_ячейке` такой: запись
подаётся в хранилище ячейки, затем ожидается её появление на карточке, затем
черновик отмечается опубликованным. Если прогон прерывается между первым и
третьим шагом, система считает черновик неопубликованным, **а посетитель
комментарий уже видит**.

Что обязано произойти при повторе: отказ со ссылкой на уже видимую запись, а
не второй комментарий под той же карточкой. Спасает это сторож дубля в самом
начале функции — путь, который до сих пор не исполнялся ни в одном тесте.

Проверки идут на изолированных данных: состояние карточки и подача в ячейку
подменены, живая витрина не задействована. Граница подтверждения названа в
последней проверке: поведение самого обрыва процесса через живую службу здесь
не измеряется — измеряется то, что система делает ПОСЛЕ него.
"""
from __future__ import annotations

import pathlib

import pytest

from factory.qwen import comments


НАШ_ТЕКСТ = "Подборка дополнена: добавлены сезоны и уточнены озвучки."


class _Сайт:
    """Минимальный сайт: функция берёт из него только домен и семейство."""

    domain = "proba.test"
    site_id = "proba-01"
    family = "animedia"
    # Форма публичного адреса берётся из таблицы по адаптеру; без него отказ
    # невидимости не смог бы назвать карточку, по которой надо смотреть.
    adapter = "animedia"


@pytest.fixture()
def стенд(tmp_path, monkeypatch):
    """Карточка с одним чужим сообщением; подача и отметка — под наблюдением."""
    подано: list[dict] = []
    отмечено: list[dict] = []
    состояния: list[dict] = []

    def состояние_ячейки(домен, slug):
        return состояния.pop(0) if состояния else {"items": [], "total": 0}

    def подать(s, slug, *, текст, author):
        подано.append({"slug": slug, "текст": текст, "author": author})
        return {"comment_id": "c-777", "request_id": "r-777",
                "snapshot": "s-777"}

    def отметить(s, slug, *, comment_id, author):
        отмечено.append({"slug": slug, "comment_id": comment_id,
                         "author": author})

    monkeypatch.setattr(comments, "состояние_ячейки", состояние_ячейки)
    monkeypatch.setattr(comments, "_подать_в_ячейку", подать)
    monkeypatch.setattr(comments, "отметить_опубликованным", отметить)
    monkeypatch.setattr(comments, "_каталог", lambda s: tmp_path)
    # Бюджет ожидания оставлен ПОЛОЖИТЕЛЬНЫМ, а быстрым его делает подмена
    # сна. Ноль здесь был бы подгонкой под стенд: подтверждение видимости
    # читается только внутри цикла ожидания, и при неположительном бюджете не
    # читается ни разу. Живая постоянная положительна, так что изъян не
    # стреляет, но закреплять в проверке состояние, в котором проверки
    # видимости нет, нельзя.
    monkeypatch.setattr(comments, "ОЖИДАНИЕ_СТРАНИЦЫ_С", 30)
    # Часы виртуальные: сон продвигает время, а не сжигает его. Голая подмена
    # сна на пустую превращала ожидание в холостой прогон на настоящих часах —
    # шесть проверок занимали минуту и грели процессор, ничего не измеряя.
    часы = {"сейчас": 1_000_000.0}
    monkeypatch.setattr(comments.time, "time", lambda: часы["сейчас"])
    def сон(с):
        часы["сейчас"] += max(с, 0.001)
    monkeypatch.setattr(comments.time, "sleep", сон)
    return {"подано": подано, "отмечено": отмечено, "состояния": состояния}


def test_повтор_после_обрыва_не_создаёт_второй_комментарий(стенд):
    """Запись в ячейке есть, отметки нет — повтор обязан отказать.

    Это и есть след обрыва: черновик не закрыт, а текст уже отдаётся
    посетителю. Второй комментарий под карточкой был бы необратимой порчей
    страницы, и снять его пришлось бы вручную.
    """
    стенд["состояния"].append({
        "items": [f"Редакция: {НАШ_ТЕКСТ}"], "total": 1})

    with pytest.raises(comments.ОперацияОтклонена) as отказ:
        comments._опубликовать_в_ячейке(
            _Сайт(), "kartochka", текст=НАШ_ТЕКСТ, author="editor/проба")

    assert "уже виден" in str(отказ.value)
    assert "Повтор не записывается" in str(отказ.value)
    # Главное: подачи не было. Отказ до записи, а не после.
    assert стенд["подано"] == [], стенд["подано"]
    assert стенд["отмечено"] == [], стенд["отмечено"]


def test_сторож_дубля_узнаёт_текст_среди_чужих_сообщений(стенд):
    """Чужие сообщения на карточке сторожа не обманывают."""
    стенд["состояния"].append({"items": [
        "Гость: первым написал посетитель",
        "Другой гость: согласен",
        f"Редакция: {НАШ_ТЕКСТ}",
        "Третий: и я",
    ], "total": 4})

    with pytest.raises(comments.ОперацияОтклонена):
        comments._опубликовать_в_ячейке(
            _Сайт(), "kartochka", текст=НАШ_ТЕКСТ, author="editor/проба")
    assert стенд["подано"] == []


def test_без_нашего_текста_публикация_идёт(стенд):
    """Обратная сторона: сторож не должен запрещать первую публикацию.

    Без этой проверки предыдущие прошли бы и у сторожа, который отказывает
    всегда, — а такой не публикует ничего.
    """
    стенд["состояния"].append({"items": ["Гость: чужое сообщение"], "total": 1})
    # Второе состояние — чтение для подтверждения видимости.
    стенд["состояния"].append({
        "items": ["Гость: чужое сообщение",
                  f"{comments.ПОДПИСЬ}: {НАШ_ТЕКСТ}"], "total": 2})

    итог = comments._опубликовать_в_ячейке(
        _Сайт(), "kartochka", текст=НАШ_ТЕКСТ, author="editor/проба")

    assert итог["state"] == "published"
    assert итог["comment_id"] == "c-777"
    assert len(стенд["подано"]) == 1, стенд["подано"]
    assert len(стенд["отмечено"]) == 1, стенд["отмечено"]


def test_невидимая_запись_опубликованной_не_отмечается(стенд):
    """Запись легла, но на карточке не появилась — черновик не закрывается.

    Это второй вид того же обрыва, только внутри одного прогона. Отметить
    публикацию здесь значило бы потерять запись: черновик закрыт, а
    посетитель текста не видит.
    """
    стенд["состояния"].append({"items": [], "total": 0})
    стенд["состояния"].append({"items": [], "total": 0})

    with pytest.raises(comments.ОперацияОтклонена) as отказ:
        comments._опубликовать_в_ячейке(
            _Сайт(), "kartochka", текст=НАШ_ТЕКСТ, author="editor/проба")

    сообщение = str(отказ.value)
    assert "не появилась" in сообщение
    assert "Повторять нельзя" in сообщение
    # Отказ обязан назвать, чем снять уже сделанную запись: иначе она
    # останется в хранилище без владельца.
    assert "c-777" in сообщение
    assert len(стенд["подано"]) == 1
    assert стенд["отмечено"] == [], (
        "невидимая запись отмечена опубликованной — черновик потерян")


def test_история_пишется_и_при_невидимости(стенд, tmp_path):
    """След обязан остаться даже у неудачной публикации.

    Без записи в историю обрыв был бы неотличим от «публикации не было», и
    найти бесхозную запись в хранилище стало бы нечем.
    """
    стенд["состояния"].append({"items": [], "total": 0})
    стенд["состояния"].append({"items": [], "total": 0})
    with pytest.raises(comments.ОперацияОтклонена):
        comments._опубликовать_в_ячейке(
            _Сайт(), "kartochka", текст=НАШ_ТЕКСТ, author="editor/проба")

    следы = list(pathlib.Path(tmp_path).rglob("*.json*"))
    текст = "".join(п.read_text(encoding="utf-8", errors="replace")
                    for п in следы)
    assert "publish-comment" in текст, (
        f"следа публикации нет; файлы: {[п.name for п in следы]}")
    assert "c-777" in текст
    assert '"visible": false' in текст.lower().replace("False", "false")


def test_граница_подтверждения_названа():
    """Чего эти проверки НЕ доказывают.

    Сам обрыв процесса здесь не воспроизводится: измеряется поведение системы
    ПОСЛЕ него — то, что повтор отказывает, а невидимая запись не закрывает
    черновик. Поведение живой службы при аварийном завершении через работающий
    мост проверить этой сессией нечем: она не управляет его перезапуском.
    Поэтому утверждение ограничено состоянием данных, а не живым прогоном.
    """
    assert comments.ОЖИДАНИЕ_СТРАНИЦЫ_С > 0, (
        "в живом коде ожидание страницы обязано быть положительным: "
        "подтверждение видимости читается ТОЛЬКО внутри цикла ожидания, и при "
        "неположительном бюджете не читается ни разу — публикация тогда "
        "объявлялась бы невидимой всегда")
