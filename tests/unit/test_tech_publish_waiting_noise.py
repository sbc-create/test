"""REQ-PUBLISH-WAITING-NOISE: одна причина ожидания — одна запись, не триста.

T175, измерено 19.10 по живому журналу `var/seo-tech/publish.jsonl`: 903
записи, из них «ожидание» 763, и 697 из них — одна задача с одной и той же
причиной. Журнал в таком виде отвечает не на вопрос «что происходит», а на
вопрос «как часто срабатывал таймер».

Правило: пока решение и причина не изменились, новая запись не пишется. Исход
при этом возвращается (`waiting_skipped`), задача остаётся кандидатом, ничего
не выпускается.

Три условия, за которые правило отвечает, и каждое проверяется отдельно:

1. причина сравнивается ЦЕЛИКОМ, а не по префиксу: причины отличаются хвостом
   («…живой d1627b4b7eaa» против «…живой 321bd7e»), и префикс склеил бы разные
   обстановки в одну;
2. счёт ведётся ПО ЖУРНАЛУ: публикатор запускается таймером, в памяти прогона
   счётчик всегда был бы единицей;
3. молчание небесконечно: раз в `БИЕНИЕ_ОЖИДАНИЯ_Ч` та же причина попадает в
   журнал снова, иначе «жив, но ждёт» неотличимо от «не запускался».
"""
from __future__ import annotations

import datetime as dt
import json

from seo_operator import tech_publish as ТП

СЕЙЧАС = dt.datetime(2026, 10, 19, 12, 0, 0, tzinfo=dt.timezone.utc)
ПРИЧИНА = ("голова ветки выпуска aceb5cccb154 не равна живому d1627b4b7eaa"
           " (идёт CI или чужой push)")


def _запись(минут_назад: int, *, task: str = "T175", head: str = "aceb5cc",
            outcome: str = "waiting", причина: str = ПРИЧИНА) -> dict:
    когда = (СЕЙЧАС - dt.timedelta(minutes=минут_назад)).strftime(
        "%Y-%m-%dT%H:%M:%SZ")
    return {"at": когда, "task_id": task, "head": head, "outcome": outcome,
            "reason": причина}


def _состояние(tmp_path, записи: list[dict]):
    with (tmp_path / "publish.jsonl").open("w", encoding="utf-8") as fh:
        for з in записи:
            fh.write(json.dumps(з, ensure_ascii=False) + "\n")
    return tmp_path


def _спросить(tmp_path, записи, *, причина=ПРИЧИНА, head="aceb5cc",
              task="T175"):
    return ТП._повтор_ожидания(_состояние(tmp_path, записи), task, head,
                               причина, сейчас=СЕЙЧАС)


def test_пустой_журнал_запись_нужна(tmp_path):
    и = _спросить(tmp_path, [])
    assert и["повтор"] is False and и["сколько"] == 0


def test_та_же_причина_пропускается(tmp_path):
    и = _спросить(tmp_path, [_запись(1)])
    assert и["повтор"] is True and и["сколько"] == 1


def test_счёт_по_журналу_а_не_по_памяти(tmp_path):
    """Условие 2: публикатор каждый раз — новый процесс."""
    и = _спросить(tmp_path, [_запись(м) for м in (50, 40, 30, 20, 10)])
    assert и["повтор"] is True and и["сколько"] == 5


def test_причина_сравнивается_целиком(tmp_path):
    """Условие 1: отличие в хвосте — другая обстановка."""
    другая = ПРИЧИНА.replace("d1627b4b7eaa", "321bd7e00000")
    assert _спросить(tmp_path, [_запись(5, причина=другая)])["повтор"] is False


def test_смена_головы_возобновляет_запись(tmp_path):
    assert _спросить(tmp_path, [_запись(5, head="0000000")])["повтор"] is False


def test_биение_раз_в_шесть_часов(tmp_path):
    """Условие 3: молчание небесконечно."""
    и = _спросить(tmp_path, [_запись(м) for м in (900, 800, 420)])
    assert и["повтор"] is False and "биение" in и["почему"]


def test_внутри_шести_часов_молчим(tmp_path):
    и = _спросить(tmp_path, [_запись(м) for м in (299, 200, 100)])
    assert и["повтор"] is True and и["сколько"] == 3


def test_биение_считается_от_последней_записи(tmp_path):
    """Иначе шум возвращается целиком: каждый такт после шести часов — запись.

    Проверено проигрыванием живого журнала: отсчёт от первой записи серии убирал
    22 % записей, от последней — 97 %.
    """
    серия = [_запись(м) for м in range(400, 44, -1)]
    и = _спросить(tmp_path, серия)
    assert и["повтор"] is True and и["сколько"] == 356


def test_прерванная_серия_считается_с_конца(tmp_path):
    и = _спросить(tmp_path, [_запись(50), _запись(40, outcome="ci_failure"),
                             _запись(30)])
    assert и["повтор"] is True and и["сколько"] == 1


def test_последняя_запись_не_ожидание(tmp_path):
    и = _спросить(tmp_path, [_запись(50), _запись(40, outcome="ci_failure")])
    assert и["повтор"] is False


def test_чужие_задачи_серию_не_ломают(tmp_path):
    и = _спросить(tmp_path, [_запись(50), _запись(45, task="T200"),
                             _запись(40)])
    assert и["повтор"] is True and и["сколько"] == 2


def test_нечитаемое_время_не_повод_молчать(tmp_path):
    плохая = _запись(5)
    плохая["at"] = "вчера"
    и = _спросить(tmp_path, [плохая])
    assert и["повтор"] is False and "не разобрано" in и["почему"]


def test_пустые_причины_сравниваются_так_же(tmp_path):
    и = _спросить(tmp_path, [_запись(5, причина="")], причина="")
    assert и["повтор"] is True


def test_исход_пропуска_не_считается_опубликованным():
    """Задача обязана остаться кандидатом: правило ничего не выпускает."""
    assert "waiting_skipped" not in ТП.ОПУБЛИКОВАНО


def test_постоянная_биения_разумна():
    """Ни нулевое биение (шум вернётся), ни суточное (ожидание станет невидимым)."""
    assert 1 <= ТП.БИЕНИЕ_ОЖИДАНИЯ_Ч <= 12
