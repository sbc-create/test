"""Проверка воспроизведения обязана отличать поломку витрины от ответа провайдера.

Повод, и он повторился дважды за день в разных видах.

Первый: инструмент всегда шёл на `/title/<slug>/season-1/episode-1/`, а у фильма
серий нет — 404 читался как «воспроизведение не работает». Пять таких «отказов»
я приписал издателю 10238 и чуть не доложил владельцу.

Второй: у записи, для которой источник не передан вовсе, витрина НЕ рисует
элемент плеера — она показывает «Источник для этой записи не передан». Инструмент
печатал «ни адрес серии, ни адрес карточки не ответили 200», хотя обе страницы
отвечали 200. Формулировка была просто неправдой, и причина была проглочена
через `catch { continue; }`.

Проверяется не текст, а свойства инструмента, из-за отсутствия которых обе
ошибки и стали возможны.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

ИНСТРУМЕНТ = Path(__file__).resolve().parents[2] / "automation" / "host" / "playback-check.js"
ТЕКСТ = ИНСТРУМЕНТ.read_text(encoding="utf-8")


def test_инструмент_на_месте() -> None:
    assert ИНСТРУМЕНТ.is_file()


def test_адрес_записи_выбирается_по_ответу_а_не_по_догадке() -> None:
    """У фильма серий нет, и жёсткий адрес серии мерил бы 404, а не плеер."""
    assert "открыть_запись" in ТЕКСТ
    м = re.search(r"async function открыть_запись[\s\S]{0,4000}?\n}", ТЕКСТ)
    assert м, "функция выбора адреса исчезла"
    тело = м.group(0)
    assert "/season-1/episode-1/" in тело and "/title/${slug}/" in тело, (
        "проверяется только один адрес — у одного из двух видов записей он неверен")


def test_причина_неудачи_не_проглатывается() -> None:
    """`catch { continue; }` — не осторожность, а отчёт, называющий не то."""
    м = re.search(r"async function открыть_запись[\s\S]{0,4000}?\n}", ТЕКСТ)
    тело = м.group(0)
    assert "причины.push" in тело, "причины попыток не сохраняются"
    # Комментарии выбрасываются: в них эта конструкция названа как та самая
    # ошибка, и искать её вместе с объяснением значит ловить собственный текст.
    код = "\n".join(с for с in тело.splitlines() if not с.lstrip().startswith("//"))
    assert not re.search(r"catch\s*\{\s*continue;\s*\}", код), (
        "причина отказа снова проглатывается пустым catch")


def test_ответ_провайдера_считается_отдельно_от_отказа() -> None:
    """«Этой серии у провайдера нет» и «плеер сломан» — разные вещи.

    Считать первое отказом значит записывать в поломку отсутствие контента у
    поставщика. Но и молчать нельзя: счётчик отдельный и печатается в итоге.
    """
    assert "СОСТОЯНИЯ_БЕЗ_ДОРОЖКИ" in ТЕКСТ
    assert "нет_дорожки" in ТЕКСТ
    assert "безДорожки" in ТЕКСТ
    assert "НЕТ ДОРОЖКИ" in ТЕКСТ, "отдельный исход не печатается в итоге"


@pytest.mark.parametrize("состояние", ["nosource", "unavailable", "provider",
                                       "error", "slow", "noaccess"])
def test_состояния_витрины_перечислены(состояние: str) -> None:
    """Набор состояний берётся у самой витрины, а не придумывается здесь."""
    м = re.search(r"СОСТОЯНИЯ_БЕЗ_ДОРОЖКИ = new Set\(\s*\[([^\]]+)\]", ТЕКСТ)
    assert м, "набор состояний не найден"
    assert f"'{состояние}'" in м.group(1)


def test_молчащая_витрина_остаётся_отказом() -> None:
    """Если плеера нет И состояние не объявлено — это дефект витрины, а не провайдера.

    Без этой ветки «нет дорожки» стало бы корзиной, в которую уходит любая
    неудача, и проверка перестала бы что-либо ловить.
    """
    assert "плеера нет и витрина молчит" in ТЕКСТ
    assert "это её дефект" in ТЕКСТ


def test_отсутствие_publisher_остаётся_отказом() -> None:
    """Неподключённая к провайдеру витрина — настройка витрины, а не запись."""
    assert "не объявлен publisher_id" in ТЕКСТ
