# --- `--preflight-only`: проверить политику, ничего не записав ---------------
#
# В блоке владельца политика проверялась командой с числами, измеренными днём
# (28311552 / 3251892 / 2422308 КБ). Числа живут своей жизнью: `publish-backups`
# растёт суточными копиями, свободное место меняется. Повторять в документе
# цикл `du` по пяти источникам нельзя — перечень живёт в сценарии, и второй
# список разошёлся бы с первым. Поэтому режим добавлен в сам сценарий.


def test_режим_preflight_only_объявлен_и_выходит_до_сбора():
    т = СЦЕНАРИЙ.read_text(encoding="utf-8")
    assert "--preflight-only" in т, "режима проверки без записи нет"
    выход = т.index('preflight-only: места достаточно')
    сбор = т.index("collect() {")
    политика = т.index("backup-preflight-space.sh")
    assert политика < выход < сбор, (
        "выход режима обязан стоять ПОСЛЕ политики и ДО сбора")


def test_режим_preflight_only_ничего_не_создаёт(tmp_path):
    """Проверка без записи обязана быть без записи — включая каталоги."""
    т = СЦЕНАРИЙ.read_text(encoding="utf-8")
    # mkdir каталогов копий и журналов — под условием режима.
    строки = т.splitlines()
    i = next(н for н, с in enumerate(строки)
             if 'mkdir -p "$BACKUP_DIR" "$LOG_DIR"' in с)
    окно = "\n".join(строки[max(0, i - 3):i + 1])
    assert 'PREFLIGHT_ONLY" = 0' in окно, (
        "создание каталогов не ограничено режимом: проверка писала бы на диск")


def test_режим_preflight_only_работает_на_живом_хосте():
    """Запуск настоящий: политика считает свои источники и отвечает кодом.

    Код 1 здесь — ожидаемый исход на этом хосте (свободного меньше
    требуемого), и он подтверждает, что защита на месте. Код 0 возможен, если
    место освободили; оба исхода допустимы, недопустим третий — падение на
    чём-то другом.
    """
    import shutil
    import subprocess as sp

    if not Path("/srv/site-factory/repo").is_dir():
        pytest.skip("живой копии репозитория на этом хосте нет")
    готово = sp.run(["bash", str(СЦЕНАРИЙ), "--preflight-only"],
                    capture_output=True, text=True, timeout=900)
    вывод = готово.stdout + готово.stderr
    assert готово.returncode in (0, 1), вывод
    assert "источники" in вывод and "нужно" in вывод, вывод
    if готово.returncode == 1:
        assert "Сбор не начинался" in вывод, вывод
    else:
        assert "ничего не записано" in вывод, вывод
    # Свободное место после проверки не уменьшилось на величину сбора.
    assert shutil.disk_usage("/").free > 1 * 2**30, "проверка съела место"
