def _каталог(сколько: int, *, без_постера: tuple[int, ...] = ()) -> tuple[list, dict]:
    """Синтетический снимок: `сколько` записей, у части нет постера.

    Числа взяты так, чтобы раздел топа мог набрать сотню мест: меньший набор
    проверял бы недобор, а не полный список.
    """
    items, details = [], {}
    for i in range(сколько):
        slug = f"t{i:04d}"
        items.append({
            "slug": slug,
            "title": f"Произведение {i}",
            "kind": "Аниме",
            "year": 2020 + (i % 6),
            "poster": "" if i in без_постера else f"/p/{i}.webp",
            "url": f"/title/{slug}/",
            "id": f"cid-{i}",
            "published_at": f"2026-09-{(25 - (i % 24)):02d}T10:00:00Z",
        })
        details[slug] = {
            "id": f"cid-{i}",
            "slug": slug,
            "playable": True,
            "description": "Описание произведения. " * 20,
            "genres": ["Экшен", "Драма"],
            "countries": ["Япония"],
            "seasons": [{"n": 1, "eps": 24, "avail": 12}],
            "kinopoisk_rating": 7.5,
            "imdb_rating": 7.1,
        }
    return items, details


