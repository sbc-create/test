def _событие(запись: dict, сезон: int, эпизод: int, когда: str, *,
             снизу: int | None = None) -> dict:
    return {
        "event_id": f"{запись['id']}:s{сезон}:e{эпизод}",
        "content_id": запись["id"],
        "slug": запись["slug"],
        "title": запись["title"],
        "season": сезон,
        "episode": эпизод,
        "episode_from": снизу if снизу is not None else эпизод,
        "episode_to": эпизод,
        "first_seen_at": когда,
        "episode_published_at": когда,
        "timestamp_semantics": "appeared_on_site",
    }


def _контур(tmp_path: Path) -> tuple[Path, Path]:
    данные = tmp_path / "данные"
    источник = tmp_path / "источник"
    данные.mkdir(exist_ok=True)
    источник.mkdir(exist_ok=True)
    return данные, источник


def _доставка(источник: Path, по_ид: dict[str, int], *, собрано: str) -> None:
    (источник / f"{САЙТ}-details.json").write_text(json.dumps({
        "catalog_built_at": собрано,
        "details": {f"s-{ид}": {"id": ид, "slug": f"s-{ид}",
                                "seasons": [{"n": 1, "avail": сколько,
                                             "eps": max(сколько, 24)}]}
                    for ид, сколько in по_ид.items()},
    }), encoding="utf-8")


def _наложение(данные: Path, по_ид: dict[str, dict[str, tuple[int, str]]]) -> None:
    (данные / f"{САЙТ}-freshness-overlay.json").write_text(json.dumps({
        "titles": {ид: {номер: {"avail": сколько, "source": "provider-api",
                                "checked_at": когда}
                        for номер, (сколько, когда) in сезоны.items()}
                   for ид, сезоны in по_ид.items()},
    }), encoding="utf-8")


def _указатель(обновление, по_ид: dict[str, tuple[int, int]], *,
               постер: str = "/p.webp", озвучка: str = "Студия",
               оценка: float = 7.0):
    """Указатель, собранный из снимка, как в бою.

    Подделывать `Указатель` руками нельзя: `шаг_серий` читает именно его поля,
    и подделка проверяла бы согласие теста с самим собой.
    """
    каталог = {"items": [{"slug": f"s-{ид}", "title": f"Тайтл {ид}",
                          "kind": "Аниме", "year": 2026}
                         for ид in по_ид]}
    подробности = {"details": {
        f"s-{ид}": {"id": ид, "slug": f"s-{ид}", "poster": постер,
                    "voice": озвучка, "rating": оценка,
                    "seasons": [{"n": 1, "avail": доступно, "eps": всего}]}
        for ид, (доступно, всего) in по_ид.items()}}
    return обновление.Указатель(каталог, подробности)


