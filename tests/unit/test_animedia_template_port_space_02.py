def test_подборки_следуют_за_часами_а_не_за_снимком(рантайм):
    """Дефект-ловушка: кэш с ключом из одного снимка заморозит две выборки.

    `recent` — скользящее окно, `current_year` — календарный год. Соседняя
    витрина на этом уже попалась. Здесь часы подменяются, и ответ ОБЯЗАН
    измениться: если однажды появится кэш без момента в ключе, эта проверка
    упадёт раньше, чем витрина покажет прошлый год под именем «Этого года».
    """
    контракт = рантайм.КОЛЛЕКЦИИ
    items = [
        {"slug": "a", "title": "A", "kind": "Аниме", "year": 2026,
         "poster": "", "url": "/title/a/", "id": "ca",
         "published_at": "2026-09-20T00:00:00Z"},
        {"slug": "b", "title": "B", "kind": "Аниме", "year": 2025,
         "poster": "", "url": "/title/b/", "id": "cb",
         "published_at": "2025-12-31T21:00:00Z"},
    ]
    снимок = контракт.Снимок(items, {})
    зона = снимок.ЗОНА_ВИТРИНЫ

    class Часы:
        def __init__(self, момент):
            self.момент = момент

        def __call__(self):
            return self.момент

    # 1. Скользящее окно скользит: через два месяца запись из него выпадает.
    снимок.сейчас = Часы(datetime(2026, 9, 26, 12, 0, tzinfo=зона))
    было = {з["slug"] for з in снимок.недавние()}
    снимок.сейчас = Часы(datetime(2026, 11, 30, 12, 0, tzinfo=зона))
    стало = {з["slug"] for з in снимок.недавние()}
    assert "a" in было and "a" not in стало, (было, стало)

    # 2. «Этого года» меняется между 31 декабря 23:59 и 1 января 00:01.
    снимок.сейчас = Часы(datetime(2025, 12, 31, 23, 59, tzinfo=зона))
    канун = {з["slug"] for з in снимок.календарный_год()}
    снимок.сейчас = Часы(datetime(2026, 1, 1, 0, 1, tzinfo=зона))
    новый_год = {з["slug"] for з in снимок.календарный_год()}
    assert канун == {"b"} and новый_год == {"a"}, (канун, новый_год)


