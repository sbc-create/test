def test_постеры_первого_экрана_не_ждут_прокрутки(вид, с_постером):
    """Дефект: `loading="lazy"` стоял у ВСЕХ карточек, включая первый экран.

    Постеры отдаются за десятки миллисекунд, но запрашивались только после
    прокрутки: посетитель видел ряд серых букв-заглушек и делал вывод, что
    постеры пропали.
    """
    сетка = вид.плитки(с_постером[:12], первый_экран=True)
    assert 'loading="lazy"' not in сетка, "первый экран всё ещё ленивый"
    assert сетка.count('fetchpriority="high"') == вид.ПРИОРИТЕТНЫХ_ПОСТЕРОВ
    assert сетка.count('loading="eager"') == 12


def test_срочность_свойство_блока_а_не_порядка_разметки(вид, с_постером):
    """Дефект: бюджет съедал первый попавшийся блок в порядке разметки.

    На странице серии его целиком забирал блок «Похожее аниме» ВНИЗУ страницы:
    двенадцать высокоприоритетных запросов за постерами, которых на первом
    экране нет вовсе. Блок, не объявивший `первый_экран`, бюджет не просит —
    и не отбирает его у того, что видно.
    """
    низ = вид.плитки(с_постером[:12], вариант="recommendation")
    assert 'fetchpriority="high"' not in низ
    assert 'loading="lazy"' in низ
    # Бюджет после нижнего блока цел: верхний получает всё своё.
    верх = вид.плитки(с_постером[12:24], первый_экран=True)
    assert верх.count('fetchpriority="high"') == вид.ПРИОРИТЕТНЫХ_ПОСТЕРОВ


def test_бюджет_ограничен_и_не_растёт_со_страницей(вид, с_постером):
    """Дефект наоборот: «грузить всё сразу» отбирает полосу у видимого."""
