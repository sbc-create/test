def test_топ_отдаёт_сто_мест_а_не_сорок_восемь(вид):
    """Дефект: раздел назывался ТОП-100 и показывал 48 мест.

    Номеров на странице не было вовсе, поэтому обрезанный список выглядел как
    короткий: посетитель не мог отличить «данных мало» от «список обрезан».
    """
    страница = вид.страница_топа({})
    карточки = re.findall(r'<a class="zt"[^>]*data-rank="(\d+)"', страница)
    assert len(карточки) == 100, f"мест на странице {len(карточки)}"
    assert [int(н) for н in карточки] == list(range(1, 101)), "нумерация не сквозная"
    assert 'data-top-limit="100"' in страница


def test_каждое_место_топа_отдельное_произведение(вид):
    """Дефект: повтор в топе крадёт чужое место, а список выглядит полным."""
    страница = вид.страница_топа({})
    адреса = re.findall(r'<a class="zt"[^>]*href="(/title/[^"]+)"', страница)
    assert len(адреса) == len(set(адреса)) == 100
    assert 'data-top-unique="100"' in страница


def test_порядок_топа_задан_правилом_а_не_порядком_строк_файла(вид, стенд):
    """Дефект: место в списке нельзя было объяснить.

    В файле топа строки намеренно перемешаны. Если порядок берётся из файла,
    первое место достанется не тому, у кого выше сводная оценка.
    """
    страница = вид.страница_топа({})
    первый = re.search(r'<a class="zt"[^>]*data-rank="1"[^>]*href="/title/([^/]+)/',
                       страница)
    assert первый is not None
    assert первый.group(1) == "t0000", "первое место не у наибольшей оценки"
    # И повторное построение на неизменённых данных даёт то же самое.
    assert re.findall(r'data-rank="(\d+)"[^>]*href="(/title/[^"]+)"', страница) == \
        re.findall(r'data-rank="(\d+)"[^>]*href="(/title/[^"]+)"', вид.страница_топа({}))


def test_нехватка_мест_названа_числом_и_причиной(вид, рантайм, tmp_path):
    """Дефект: недобор кандидатов и обрезанный список выглядят одинаково.

    Числа берутся из сводки самого файла топа, а не из длины показанного:
    иначе витрина объясняет свою нехватку своей же нехваткой.
    """
    файл = tmp_path / "top-short.json"
    файл.write_text(json.dumps({
        "basis": "ratings-aggregate", "generated_at": "2026-09-26T08:00:00Z",
        "summary": {"places": 12, "candidates": 12, "threshold_votes": 5},
        "places": [{"slug": f"t{i:04d}", "value": 9 - i * 0.1, "votes": 9}
                   for i in range(12)]}), encoding="utf-8")
    прежний = рантайм.АНИМЕДИА_ТОП_ПО_ОЦЕНКАМ_ПУТЬ
    рантайм.АНИМЕДИА_ТОП_ПО_ОЦЕНКАМ_ПУТЬ = str(файл)
    try:
        страница = вид.страница_топа({})
    finally:
        рантайм.АНИМЕДИА_ТОП_ПО_ОЦЕНКАМ_ПУТЬ = прежний
    assert 'data-top-full="0"' in страница
    assert "Мест в списке: 12 из 100" in страница
    # Причина — из сводки файла, а не «столько нашлось».
    assert "кандидатов набралось 12" in страница
    assert "при пороге 5 голосов" in страница


