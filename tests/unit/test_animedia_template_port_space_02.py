def test_колонок_не_больше_чем_карточек(вид):
    """Дефект: две подборки в сетке на четыре колонки читаются как сбой."""
    for сколько in (1, 2, 3):
        карточки = вид.подборки_для_показа(предел=сколько)
        if len(карточки) < сколько:
            continue
        сетка = вид.сетка_подборок(карточки)
        колонок = int(re.search(r'zhub--cols-(\d+)', сетка).group(1))
        assert колонок == min(сколько, 3), (сколько, колонок)
        assert f'data-collections-count="{len(карточки)}"' in сетка
    # И жёсткого «четыре колонки» в стиле больше нет.
    assert ".zsec--home-cols .zhub--home{display:grid" not in вид.се["стиль"]()


def test_подборка_без_обложек_не_прячется_и_не_рисует_битых(рантайм, стенд, tmp_path):
    """Дефект в обе стороны: спрятать существующую подборку — или показать
    сломанную картинку. У подборки без обложек остаётся компактная карточка.
    """
    каталог = tmp_path / "нет-постеров.json"
    подробности = tmp_path / "нет-постеров-d.json"
    свои = [{"slug": f"np{i}", "title": f"Без обложки {i}", "kind": "Аниме",
             "year": 2026, "poster": "", "url": f"/title/np{i}/", "id": f"cnp{i}",
             "published_at": "2026-09-24T10:00:00Z"} for i in range(8)]
    каталог.write_text(json.dumps({"items": свои, "revision": "rnp"}),
                       encoding="utf-8")
