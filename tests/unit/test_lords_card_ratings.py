"""Карточка показывает обе оценки, когда обе есть.

## Что было и чего не было

Прежняя разметка показывала одну оценку: Кинопоиск, если он есть, иначе IMDb.
Это было решением, а не ошибкой, и оно записано в коде: «две мелкие подписи
под обложкой спорят друг с другом».

Измерение на боевой витрине подтвердило, что потери данных не было. На первой
странице каталога: в источнике оба источника у 2 записей, только IMDb у 3, без
оценок у 19. В разметке — Кинопоиск 2, IMDb 3. Ровно столько, сколько
предписывает правило «одна оценка на карточку».

Первоначальный вывод «теряется IMDb у двух записей» был ошибкой измерения:
число по каждому источнику сравнивалось с разметкой, показывающей одну оценку.

## Что меняется и почему

Требование этапа — показывать оба источника независимо, когда оба доступны.
Скрытая оценка не теряется в данных, но теряется для зрителя: он не знает, что
у записи есть вторая, и не может сравнить.

Компактность решается вёрсткой, а не умолчанием одного из источников.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from factory.lords import render as render_mod  # noqa: E402


class Запись:
    def __init__(self, kp=None, imdb=None):
        self.kinopoisk_rating = kp
        self.imdb_rating = imdb


class TestОбеОценкиНаКарточке:
    def test_обе_показаны_когда_обе_есть(self):
        html = render_mod._card_rating(Запись(kp=6.7, imdb=7.4))
        assert "Кинопоиск" in html and "IMDb" in html, (
            "вторая оценка скрыта: зритель не знает, что она есть")
        assert "6,7" in html or "6.7" in html
        assert "7,4" in html or "7.4" in html

    def test_только_кинопоиск(self):
        html = render_mod._card_rating(Запись(kp=6.7))
        assert "Кинопоиск" in html
        assert "IMDb" not in html, "показан источник, которого нет"

    def test_только_imdb(self):
        html = render_mod._card_rating(Запись(imdb=7.4))
        assert "IMDb" in html
        assert "Кинопоиск" not in html

    def test_без_оценок_ничего_не_рисуется(self):
        assert render_mod._card_rating(Запись()) == ""

    def test_ноль_не_считается_оценкой(self):
        """Ноль — не оценка, а её отсутствие: шкала начинается с единицы."""
        assert render_mod._card_rating(Запись(kp=0, imdb=0)) == ""

    def test_каждая_оценка_подписана_своим_источником(self):
        """Число без источника бессмысленно: шкалы у Кинопоиска и IMDb разные
        по восприятию, и 7,4 у одного не равно 7,4 у другого."""
        html = render_mod._card_rating(Запись(kp=6.7, imdb=7.4))
        # Подпись обязана стоять рядом со своим числом, а не одна на две.
        assert html.count("card__rating-source") == 2
        assert html.count("card__rating-value") == 2
