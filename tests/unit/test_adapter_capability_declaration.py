"""Объявление возможностей адаптера против рантайма: два направления, не одно.

MOD-172 измерен 24.10 и перемерен 25.10: из 33 витрин у **15** объявление
отстало от факта — витрина ПОКАЗЫВАЕТ редакционный текст (наложение в дереве,
наложение в контейнере или накладка витрины), а `display` ей не объявлен,
поэтому `queue_bridge.доставка_описаний` отказывает в задании на описание.

Направления расхождения НЕ равны по цене, и проверка их различает.

* **Опасное** — объявлено больше, чем есть: очередь выдаст задание, текст
  будет подготовлен и «опубликован», а показать его нечем. Это запрещено
  жёстко: такой случай обязан валить проверку.
* **Осторожное** — объявлено меньше, чем есть: публикация запрещена там, где
  она возможна. Это потеря, но не ложь, и правка объявления СНИМАЕТ
  действующий запрет у четырёх семейств — поэтому она требует решения
  владельца, а не молчаливого выравнивания. Пока решения нет, отставание
  допускается ТОЛЬКО при открытой записи реестра, которая его называет.

Так проверка не заставляет менять общий код без разрешения и одновременно не
даёт отставанию стать нормой: закрыв запись, не выровняв объявление, суд
получит красный.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
АУДИТ = КОРЕНЬ / "automation" / "local" / "adapter-capability-audit.py"
РЕЕСТР_ДЕФЕКТОВ = КОРЕНЬ / "config" / "seo-module-defects.json"
ОТКРЫТЫЕ = ("proposed", "measured", "implemented", "installed")


@pytest.fixture(scope="module")
def аудит():
    спец = importlib.util.spec_from_file_location("adapter_capability_audit", АУДИТ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


@pytest.fixture(scope="module")
def объявлено():
    import sys
    sys.path.insert(0, str(КОРЕНЬ))
    from factory.qwen import registry
    return registry.ВОЗМОЖНОСТИ_АДАПТЕРА


def _маршруты(аудит) -> dict[str, tuple[str, str]]:
    """Маршрут показа по витрине: (вид, подтверждение) или («—», причина)."""
    из: dict[str, tuple[str, str]] = {}
    кон = аудит.контейнеры()
    for з in аудит.витрины():
        домен = з.get("domain") or ""
        if not домен:
            continue
        к = аудит.дерево(домен)
        вид, чем = аудит.читатель_в_дереве(к) if к else ("", "")
        if not вид:
            вид, чем = аудит.маршрут_контейнера(домен, кон)
        из[домен] = (вид or "—", чем)
    return из


def test_объявление_не_обещает_того_чего_нет(аудит, объявлено):
    """Опасное направление: обещанный показ без читателя в рантайме."""
    маршруты = _маршруты(аудит)
    лжёт = []
    for з in аудит.витрины():
        домен = з.get("domain") or ""
        адаптер = з.get("adapter") or ""
        если = set(объявлено.get(адаптер) or ())
        вид, _ = маршруты.get(домен, ("—", ""))
        if "display" in если and вид == "—" and з.get("status") == "live":
            лжёт.append(f"{домен} ({адаптер}): display объявлен, читателя нет")
    assert not лжёт, (
        "объявление обещает показ, которого в рантайме нет — очередь выдаст"
        " задание, а показать текст будет нечем:\n" + "\n".join(лжёт))


def test_отставание_объявления_допустимо_только_при_открытой_записи(аудит, объявлено):
    """Осторожное направление: запрет там, где показ есть."""
    маршруты = _маршруты(аудит)
    отстают = []
    for з in аудит.витрины():
        домен = з.get("domain") or ""
        адаптер = з.get("adapter") or ""
        если = set(объявлено.get(адаптер) or ())
        вид, _ = маршруты.get(домен, ("—", ""))
        if вид != "—" and "display" not in если:
            отстают.append(домен)
    if not отстают:
        return
    д = json.loads(РЕЕСТР_ДЕФЕКТОВ.read_text(encoding="utf-8"))
    запись = next(
        (з for з in д["defects"]
         if з.get("state") in ОТКРЫТЫЕ
         and "ВОЗМОЖНОСТИ_АДАПТЕРА" in (з.get("example") or "")), None)
    assert запись is not None, (
        f"объявление отстало у {len(отстают)} витрин ({', '.join(отстают[:4])}…),"
        " и ни одна открытая запись реестра этого не называет: тогда отставание"
        " становится нормой, а публикация остаётся запрещённой молча")
    assert запись.get("owner_action"), (
        f"{запись['id']}: отставание названо, но действие владельца не описано —"
        " правка снимает действующий запрет и молча делаться не может")


def test_требование_для_публикации_не_смягчено():
    """Отрицательный контроль: смягчить требование вместо правки — не выход."""
    import sys
    sys.path.insert(0, str(КОРЕНЬ))
    from factory.qwen import registry
    assert registry.ТРЕБУЕТ_ВОЗМОЖНОСТИ["publish"] == ("deliver", "display"), (
        "требование к публикации изменено: это не выравнивание объявления, а"
        " ослабление условия — публикация стала бы возможна там, где показать"
        " текст нечем")
