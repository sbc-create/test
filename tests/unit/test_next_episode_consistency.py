"""Согласованность «следующей серии»: число берётся из ячейки, а не со страницы.

Эта проверка стоит на двух уже совершённых ошибках.

1. Разбор ТЕКСТА всей страницы дал 25.10 у шести карточек одно и то же
   «следующая: 71» при доступных 12, 8, 19, 3, 3 и 2 — образец зацепил
   постороннее число. Поэтому доступные серии читаются ТОЛЬКО из ячейки
   «Эпизоды», и здесь есть прямая проверка-ловушка с посторонними числами.
2. Вердикт без знаменателя. Если селектор сломан, все страницы дают «блока
   нет», и «противоречий 0» неотличимо от замера, который ничего не прочитал.
   Поэтому контроль обязателен и проверяется отдельной функцией.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "next-episode-consistency.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("next_episode_consistency", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_число_берётся_после_слова_доступно():
    assert МОД.доступно_из_ячейки("12 серий, доступно 4") == 4


def test_ноль_доступных_это_число_а_не_пусто():
    assert МОД.доступно_из_ячейки("24 серии, доступно 0") == 0


def test_посторонние_числа_в_ячейке_не_принимаются_за_доступные():
    """Ровно тот промах, из-за которого появилось «следующая: 71»."""
    assert МОД.доступно_из_ячейки("71 оценка, 12 серий, доступно 3") == 3


def test_ячейка_без_слова_доступно_не_даёт_числа():
    assert МОД.доступно_из_ячейки("12 серий") is None
    assert МОД.доступно_из_ячейки("") is None
    assert МОД.доступно_из_ячейки(None) is None


def test_регистр_слова_не_важен():
    assert МОД.доступно_из_ячейки("Доступно 7 серий") == 7


def test_следующая_на_одну_больше_согласовано():
    и, почему = МОД.исход(5, 4)
    assert и == "согласовано" and "4 + 1" in почему


def test_названная_серия_уже_вышла_это_противоречие():
    assert МОД.исход(4, 4)[0] == "противоречие"
    assert МОД.исход(3, 4)[0] == "противоречие"


def test_разрыв_больше_одной_серии_назван_отдельно():
    """Критерий MOD-29 такой случай допускает — но он не «согласовано»."""
    и, почему = МОД.исход(7, 4)
    assert и == "опережает" and "разрыв" in почему


def test_нет_атрибута_это_блока_нет_а_не_согласовано():
    assert МОД.исход(None, 4)[0] == "блока нет"


def test_нет_ячейки_это_не_измерено():
    и, почему = МОД.исход(5, None)
    assert и == "не измерено" and "Эпизоды" in почему


def test_контроль_требует_оба_числа():
    assert МОД.контроль_пройден({"следующая": 5, "доступно": 4})
    assert not МОД.контроль_пройден({"следующая": None, "доступно": 4})
    assert not МОД.контроль_пройден({"следующая": 5, "доступно": None})
    assert not МОД.контроль_пройден({})


def test_проба_называет_себя_классом_factory():
    """Без имени запрос попадает в класс other_bot и получает 503."""
    assert МОД.АГЕНТ.startswith("factory-")


def test_технический_прогон_глушит_метрику():
    исходник = ПУТЬ.read_text(encoding="utf-8")
    assert 'route("**mc.yandex.*/**"' in исходник


def test_форма_animedia_подпись_с_числом_в_соседней_ячейке():
    """`<dt>Доступно серий</dt><dd>4</dd>` — та же ячейка, другая подпись.

    Из-за единственной формы разбора 25.10 тринадцать страниц семейства
    animedia ушли в «не измерено»: ячейка там есть, просто называется иначе.
    """
    assert МОД.доступно_из_ячейки("Доступно серий: 4") == 4


def test_подпись_без_числа_не_даёт_значения():
    assert МОД.доступно_из_ячейки("Доступно серий: нет данных") is None


def test_ловушка_с_посторонними_числами_выдерживает_новую_форму():
    assert МОД.доступно_из_ячейки("71 оценка, 12 серий, доступно 3") == 3


def test_число_сезонов_читается_из_той_же_ячейки():
    assert МОД.сезонов_из_ячейки("4 сезона, 50 серий, доступно 49") == 4
    assert МОД.сезонов_из_ячейки("12 серий, доступно 4") is None


def test_многосезонная_карточка_не_даёт_противоречия():
    """Настоящий случай 25.10, где я чуть не записала ложное противоречие.

    «Блич: Тысячелетняя кровавая война» — 4 сезона, доступно 49, следующая 10.
    Прямое сравнение объявило бы серию 10 вышедшей, хотя 10 — номер внутри
    сезона. Числа разных шкал сравнению не подлежат.
    """
    и, почему = МОД.исход(10, 49, 4)
    assert и == "несопоставимо"
    assert "внутри сезона" in почему


def test_один_сезон_сравнивается_как_прежде():
    assert МОД.исход(5, 4, 1)[0] == "согласовано"
    assert МОД.исход(4, 4, 1)[0] == "противоречие"
    assert МОД.исход(5, 4, None)[0] == "согласовано"
