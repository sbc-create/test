# --- место на хосте в сводке -------------------------------------------------

ГИБ = 2**30


def test_критичное_место_называет_последствие_а_не_число():
    """Измерено 23.10: при 0.23 % суточная копия обрезалась по ENOSPC."""
    с = отчёт.место_на_хосте(int(0.48 * ГИБ), int(203.3 * ГИБ))
    assert "0.48 ГиБ" in с and "0.24 %" in с
    assert "НИЖЕ ПОРОГА ЖИВОЙ ПРОВЕРКИ" in с
    assert "MOD-144" in с and "ENOSPC" in с


def test_малое_место_отличается_от_критичного():
    """2.6 ГиБ — ещё можно собрать копии, но прогон занимает около 0.5 ГБ."""
    с = отчёт.место_на_хосте(int(2.6 * ГИБ), int(203.3 * ГИБ))
    assert "мало" in с and "MOD-144 не закрыт" in с
    assert "НИЖЕ ПОРОГА" not in с


def test_достаточное_место_обходится_без_оговорок():
    с = отчёт.место_на_хосте(int(40 * ГИБ), int(203.3 * ГИБ))
    assert с.startswith("свободно 40.00 ГиБ")
    assert "мало" not in с and "НИЖЕ ПОРОГА" not in с


