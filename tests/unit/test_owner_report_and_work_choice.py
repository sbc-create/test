def _самооценка() -> dict:
    д = json.loads((КОРЕНЬ / "config" / "learning-queue.json").read_text(
        encoding="utf-8"))
    return д["self_assessment"]


def test_уровень_не_присваивается_самому_себе():
    """«8 из 10» — внутренний критерий, а не звание.

    ПРЕЖНЯЯ РЕДАКЦИЯ ЭТОЙ ПРОВЕРКИ БЫЛА НЕВЕРНА и падала 22.10, когда
    самооценка была заполнена: она требовала `cases == []` и все направления
    `null`, то есть ЗАПРЕЩАЛА записывать доказательства до ревью. Правило
    владельца этого не запрещает — оно запрещает присваивать звание себе и
    требует для статуса «подтверждено ревью» трёх кейсов и ОТДЕЛЬНОГО ревью,
    а согласие второго ИИ доказательством не считает. Без записанных кейсов и
    оценок порог нечем проверить, то есть прежняя проверка мешала выполнению
    требования, а не охраняла его.
    """
    с = _самооценка()
    if с["status"] == "подтверждено ревью":
        assert len(с["cases"]) >= 3, "звание без трёх кейсов"
        семьи = {к["family"] for к in с["cases"]}
        assert len(семьи) >= 3, семьи
    else:
        assert с["status"] == "готово к проверке"


def test_ни_один_кейс_не_объявляет_чужого_ревью_как_доказательства():
    """Согласие второго ИИ доказательством не является — так в задании."""
    for к in _самооценка()["cases"]:
        ревью = к["reviewed_by"].lower()
        assert "самооценка" in ревью, к["case"][:40]
        if "линия" in ревью or "ии" in ревью:
            assert ("доказательством не является" in ревью
                    or "не считается" in ревью), к["reviewed_by"]


