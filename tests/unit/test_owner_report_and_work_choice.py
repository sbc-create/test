def _очд(домен, задачи):
    return {"domain": домен, "tasks": задачи}


def _зд(ид, state="подготовлено", title="одно и то же", problem="та же беда"):
    return {"id": ид, "state": state, "title": title, "problem": problem}


def test_два_живых_задания_одного_предмета_называются_дублем():
    """Найдено 23.10 в своих же очередях: у всех пяти Yummy по две записи."""
    д = выбор.дубли([_очд("a.test", [_зд("T-1"), _зд("T-2")])])
    assert д == [("a.test", "одно и то же", ["T-1", "T-2"])]


