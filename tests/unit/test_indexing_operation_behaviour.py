"""Поведение штатной операции открытия — на изолированном окружении.

Пять случаев из задания владельца, и ни один не проверяется чтением кода:

  * отказ при отсутствии разрешения владельца;
  * отказ при несовпадении ожидаемого выпуска;
  * открытие и закрытие РАЗРЕШЁННОГО тестового сайта;
  * частичный сбой с восстановлением исходного состояния;
  * повтор операции без непредусмотренных изменений.

Живых доменов проверка не касается: свой реестр, свой каталог выпуска, свой
корень файлов состояния, своя конфигурация nginx и подставная очередь. Ни
одного обращения к сети: публичные сигналы задаёт сценарий — именно так
проверяется поведение операции, а не доступность сайта.
"""
from __future__ import annotations

import json
import pathlib

import pytest

from factory.cell import nginx_indexing, owner_consent
from factory.cell import queue as q
from factory.qwen import editorial, indexing, registry

ДОМЕН = "t.example"
САЙТ = "test-01"


#: Точка входа -> семейство (`factory.qwen.registry`). Здесь перечислены
#: семейства, у которых режимом распоряжается ОПЕРАЦИЯ: именно их штатное
#: открытие, закрытие и откат проверяются ниже на изолированном экземпляре.
#: `yummy` сюда не входит и входить не должен: его режимом распоряжается
#: переменная контейнера (`mode_owner: compose`), и операция ячейки его не
#: меняет — требовать от неё этого значило бы проверять не тот механизм.
СЕМЕЙСТВА = {
    "lords": "lords-frontend.py",
    "zona-serve": "serve.py",
    "animego": "animego-frontend.py",
    "animedia": "animedia-frontend.py",
}


def _репозиторий(tmp: pathlib.Path, точка_входа: str = "lords-frontend.py") -> str:
    """Подставной репозиторий сайта: по его точке входа выводится семейство.

    Семейство — не выдумка инструмента: оно берётся из `config/site.json`
    репозитория, и без него контракт режима неизвестен. Поэтому в песочнице
    репозиторий настоящий, просто свой.
    """
    репо = tmp / "var" / "site-repos" / САЙТ
    (репо / "config").mkdir(parents=True, exist_ok=True)
    (репо / "config" / "site.json").write_text(json.dumps({
        "site_id": САЙТ, "domain": ДОМЕН, "entrypoint": точка_входа,
    }, ensure_ascii=False), encoding="utf-8")
    return f"var/site-repos/{САЙТ}"


#: Идентификатор подтверждения владельца на стенде. Он же кладётся в реестр:
#: расхождение идентификаторов исполнитель считает устаревшим снимком.
ПОДТВЕРЖДЕНИЕ = "стенд-0000-0000"


def _реестр(tmp: pathlib.Path, *, разрешено: bool,
            точка_входа: str = "lords-frontend.py") -> pathlib.Path:
    п = tmp / "site-cells.json"
    п.write_text(json.dumps({"cells": [{
        "site_id": САЙТ, "domain": ДОМЕН,
        "repo": {"path": _репозиторий(tmp, точка_входа)},
        "runtime": {"account": САЙТ, "port": 9999,
                    "unit": f"nova-{САЙТ}.service"},
        "template": {"template_id": "lords-animation"},
        "indexing": ({"open_authorized": True, "reason": "тестовый сайт",
                      "open_authorization_id": ПОДТВЕРЖДЕНИЕ}
                     if разрешено else
                     {"desired_state": "CLOSED", "reason": "разрешения нет"}),
    }]}, ensure_ascii=False), encoding="utf-8")
    return п


def _подтверждение_владельца(tmp: pathlib.Path) -> pathlib.Path:
    """Корневой якорь согласия владельца — вторая половина договора.

    Разрешением считается не флаг в реестре, а файл в каталоге root: реестр
    доступен на запись той же учётной записи, под которой работают инструменты,
    и флаг в нём подделывается. На стенде каталог свой, а проверка владельца
    файла подменяется отдельно — она закреплена в `test_owner_consent`.
    """
    каталог = tmp / "owner-consent"
    каталог.mkdir(exist_ok=True)
    (каталог / f"{ДОМЕН}.json").write_text(json.dumps({
        "schema_version": 1, "domain": ДОМЕН, "site_id": САЙТ,
        "authorized": True, "by": "owner", "at": "2026-10-04T00:00:00Z",
        "id": ПОДТВЕРЖДЕНИЕ}, ensure_ascii=False), encoding="utf-8")
    return каталог


def _выпуск(tmp: pathlib.Path, *, разрешает: bool,
            точка_входа: str = "lords-frontend.py") -> pathlib.Path:
    """Каталог «выложенного» выпуска с читателем и конфигурацией."""
    выпуск = tmp / "srv" / САЙТ / "current"
    (выпуск / "src").mkdir(parents=True)
    (выпуск / "config").mkdir(parents=True)
    общий = pathlib.Path(__file__).resolve().parents[2] / "automation" / "host" \
        / "indexing_mode.py"
    (выпуск / "src" / "indexing_mode.py").write_bytes(общий.read_bytes())
    (выпуск / "src" / точка_входа).write_text(
        "import indexing_mode  # читатель подключён\n", encoding="utf-8")
    (выпуск / "config" / "site.json").write_text(json.dumps({
        "site_id": САЙТ, "domain": ДОМЕН, "entrypoint": точка_входа,
        "indexing": {"release_permits_open": разрешает},
    }, ensure_ascii=False), encoding="utf-8")
    return выпуск


def _nginx(tmp: pathlib.Path, *, запрещает: bool) -> pathlib.Path:
    корень = tmp / "nginx"
    (корень / "lords").mkdir(parents=True)
    (корень / "cells").mkdir(parents=True)
    перем = nginx_indexing.имя_переменной(САЙТ)
    включаемый = корень / "cells" / f"{САЙТ}.robots"
    строка = (nginx_indexing.ФИКСИРОВАННАЯ if запрещает
              else f"add_header X-Robots-Tag ${перем} always;")
    объявление = ("" if запрещает else
                  f"map $uri ${перем} {{\n    include {включаемый};\n}}\n\n")
    (корень / "lords" / f"{САЙТ}.conf").write_text(
        объявление +
        "server {\n"
        f"    server_name {ДОМЕН};\n"
        f"    {строка}\n"
        "    location / { proxy_pass http://127.0.0.1:9999; }\n"
        "}\n", encoding="utf-8")
    if not запрещает:
        включаемый.write_text('default "";\n', encoding="utf-8")
    return корень


class Очередь:
    """Подставная очередь: записывает заявки и МЕНЯЕТ состояние слоя.

    Исполнитель здесь не настоящий, но его роль та же: по заявке он
    переключает слой. Иначе проверялась бы не петля операции, а набор
    подмен — и «слой переключился» нельзя было бы отличить от «мы так
    сказали».
    """

    def __init__(self, слой: dict, исход: str = "applied", база=None):
        self.заявки: list[dict] = []
        self.исход = исход
        self.слой = слой
        self.база = база
        #: НАСТОЯЩЕЕ чтение состояния, снятое до подмены: стенд подменяет
        #: `q.состояние` собой, и обращение к модулю внутри стенда ушло бы в
        #: него же. Проверять надо то, что работает в бою.
        self._читать_состояние = q.состояние

    def собрать(self, site_id, commit, digest, **kw):
        return q.собрать(site_id, commit, digest, **kw)

    def подать(self, заявка, **kw):
        self.заявки.append(заявка.as_dict())
        if self.исход == "applied":
            self.слой["режим"] = заявка.mode
        # Результат пишется НАСТОЯЩИМ файлом очереди, и читается он настоящей
        # `queue.состояние`. Прежде стенд отдавал заранее собранный словарь
        # правильной формы — и ровно поэтому мимо тестов прошёл дефект чтения:
        # собственный `status` результата перезаписывал внешний, отклонённая
        # заявка не выглядела завершённой, а ожидание слоя крутилось 420 с.
        # Подменять чтение состояния нельзя: проверять надо то, что работает.
        q.записать_атомарно(
            self.база / "results" / f"{заявка.request_id}.json",
            {"request_id": заявка.request_id, "site_id": заявка.site_id,
             # `nothing-to-do` — тоже применённый исход (`ПРИМЕНЁННЫЕ_ИСХОДЫ`):
             # исполнитель отработал, менять было нечего. Отказ — это другое.
             "status": ("ok" if self.исход in q.ПРИМЕНЁННЫЕ_ИСХОДЫ else "rejected"),
             "outcome": ({"status": self.исход,
                          "stage": "indexing_layer_applied"}
                         if self.исход in q.ПРИМЕНЁННЫЕ_ИСХОДЫ else None),
             "error": ("" if self.исход in q.ПРИМЕНЁННЫЕ_ИСХОДЫ
                       else "nginx -t отказал")})
        return {"status": "queued", "request_id": заявка.request_id}

    def состояние(self, request_id, *, не_раньше: str = ""):
        # Сигнатура повторяет настоящую: `не_раньше` отделяет результат ЭТОЙ
        # попытки от результата прошлой (см. test_queue_stale_result), и стенд
        # обязан передавать его дальше, а не глотать.
        return self._читать_состояние(request_id, база=self.база,
                                      не_раньше=не_раньше)


