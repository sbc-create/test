def test_слой_открыт_а_ответ_не_подтвердил_слой_возвращается(площадка):
    """Худший частичный отказ: слой УЖЕ открыт, а публичный ответ закрыт.

    Здесь восстановления файла состояния недостаточно. Слой nginx — тоже
    изменённое состояние: если его оставить открытым, домен теряет запрет
    уровня nginx, а запрет остаётся только у приложения (fail-closed). Это
    наполовину открытый домен после НЕУДАВШЕЙСЯ попытки открытия, то есть
    ровно то, что обязано исключаться восстановлением.
    """
    п = площадка(разрешено=True, разрешает_выпуск=True,
                 nginx_запрещает=True, публично="CLOSED")
    # Исполнитель применит слой (как в успешном случае), но публичный ответ
    # останется закрытым: сценарий режим сети не меняет.
    итог = indexing.установить(ДОМЕН, mode="open", author="тест",
                               корень=п["корень_состояния"])
    assert итог["confirmed"] is False, итог
    assert итог.get("restored") is True, итог
    # Файл состояния вернулся (его не было) — это уже работало.
    assert not (п["корень_состояния"] / f"{ДОМЕН}.json").exists()
    # А ВОТ ЭТО — то, чего не хватало: слой обязан вернуться в закрытый.
    assert п["слой"]["режим"] == "CLOSED", (
        "слой nginx остался открытым после неудачной попытки открытия: "
        "домен наполовину открыт")
    assert итог.get("nginx_restored", {}).get("mode") == "CLOSED", итог
    # И возврат слоя шёл ШТАТНОЙ заявкой, а не правкой файлов.
    assert п["очередь"].заявки[-1]["mode"] == "CLOSED", п["очередь"].заявки


