class TestРазмерУказателя:
    def test_указатель_знает_свой_размер(self, указатель):
        stats = указатель.stats()
        assert stats["items"] == 3000
        assert stats["vocabulary"] > 0
        assert stats["bigrams"] > 0

    def test_словарь_меньше_числа_слов_каталога(self, каталог, указатель):
        всего = sum(len(f.split()) for item in каталог for f in search_mod._forms(item))
        assert указатель.stats()["vocabulary"] < всего, (
            "словарь не экономит: значит слова не свёрнуты и нестрогий проход "
            "будет сравнивать одно и то же по многу раз"
        )
