"""REQ-CELL-TITLE-GENRE-LINKS: жанры произведения — ссылки, а не текст.

Измерено 2026-10-18 на `lordserial.su/title/eto-vse-eda/`:

    жанры этой записи: «документальный · западный контент» — ТЕКСТОМ;
    ссылок `/genre/` на странице: 8, и это ровно подвал — один и тот же набор
    на всех карточках, включая `anime` у документального сериала.

Код для ссылок в `факты` существовал, но включался только при наличии
`деталь["genre_codes"]`, а в установленных подробностях этого поля нет. Индекс
витрины в таком случае выводит код из имени сам (`_построить_коды`:
`нормализовать(транслит(значение))`) — именно поэтому `/genre/boevik/` вообще
отвечает 200. Страница этим способом не пользовалась.

Это та же форма, что у записи R-01 по витринам Yummy («блок жанров есть,
ссылок ноль»), только на другом семействе.
"""
from __future__ import annotations

from pathlib import Path

ШАБЛОН = (Path(__file__).resolve().parents[2] / "automation" / "host"
          / "lords-frontend.py")
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _факты() -> str:
    начало = ТЕКСТ.index("def факты(вид: Вид, запись: dict, деталь: dict)")
    return ТЕКСТ[начало:ТЕКСТ.index("\ndef ", начало + 10)]


def test_код_жанра_выводится_тем_же_способом_что_у_индекса():
    """Иначе страница и индекс разошлись бы: ссылка вела бы на 404."""
    тело = _факты()
    assert "нормализовать(транслит(имя))" in тело
    построение = ТЕКСТ[ТЕКСТ.index("def _построить_коды"):]
    построение = построение[:построение.index("\ndef ", 10)]
    assert "нормализовать(транслит(значение))" in построение, (
        "способ вывода кода в индексе изменился — страница разойдётся с ним")


def test_ссылка_ставится_только_на_известный_жанр():
    """Отрицательный контроль: маршрут отдаёт 404 на неизвестный код, и
    ссылка на него вела бы в никуда."""
    тело = _факты()
    assert "код in индекс_жанров" in тело
    assert "ссылки.append(html.escape(имя))" in тело, (
        "неизвестный жанр обязан остаться текстом, а не исчезнуть"
    )


def test_форма_адреса_зависит_от_семейства():
    """У Lords канон жанра — путь, у Zona и Animedia тот же путь переводит на
    query-форму, и ставить его значило бы добавлять переход на каждой
    карточке."""
    тело = _факты()
    assert 'СЕМЕЙСТВО == "lords"' in тело
    assert 'f"/genre/{код}/"' in тело
    assert "запрос_строкой({'genre': код})" in тело


def test_индекс_берётся_у_вида_а_не_собирается_заново():
    """Второй сбор индекса на каждой карточке стоил бы обхода каталога."""
    тело = _факты()
    assert 'getattr(вид, "индекс", {}).get("genre")' in тело


def test_готовые_коды_из_данных_имеют_приоритет():
    """Если поставщик однажды начнёт присылать `genre_codes`, берутся они:
    выведенный код — запасной путь, а не замена данным."""
    тело = _факты()
    и_данные = тело.index('коды[i] if i < len(коды) else ""')
    и_вывод = тело.index("нормализовать(транслит(имя))")
    assert и_данные < и_вывод
