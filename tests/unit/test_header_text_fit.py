"""Шапка не режет своё имя и не выпускает текст кнопок за рамку.

ПОВОД — приёмка линии SEO 27.10 на живой `zonafilm12.site`, телефон 390,
тёмная тема: логотип показан как «Zona Cinen», слово «Поиск» выходит за рамку
своей кнопки.

ПОЧЕМУ ТЕСТ ЖИВЁТ ЗДЕСЬ, А НЕ В ПРОВЕРКАХ ВИТРИНЫ. Ровно этот дефект нашли и
починили 10.10, и тогда же написали `checks/header_fit.py`. Её поставили на
ОДНУ витрину парка из 21 — поэтому исправление не унаследовалось и полгода
этого никто не видел. Перенести ту проверку как есть нельзя: она закрепляет
архитектуру шапки `zonafilm.space` (ящик меню до 1279px), а у
`zonafilm12.site` строка меню стоит с 768px — это другое решение, а не
дефект. Здесь закрепляется только то, что от архитектуры НЕ зависит и верно
для любой шапки: имя сайта не режется, а кнопка не уже своего слова.

ЧТО ИМЕННО ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО.

1. У `.zhd__logo` нет жёсткой `width` и нет `overflow:hidden`/`ellipsis`.
   «Zona Cinema» при 18px занимает около 129px, а ширина стояла 110px —
   обрезка наступала на любом экране, и многоточия не было видно, потому что
   элемент inline-flex.
2. Ни одно правило, задающее размер кнопок шапки, не ставит им фиксированную
   `width`. У кнопки `.zhd__searchbtn` внутри слово, а не значок: её ширину
   задаёт текст, а 44 пикселя — это минимум для пальца (`min-width`), а не
   ширина слова.
"""
from __future__ import annotations

import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИМЕНА_РАНТАЙМОВ = ("lords-frontend.py", "animedia-frontend.py",
                   "animego-frontend.py")


def _рантаймы() -> list[pathlib.Path]:
    """Все рантаймы парка, у которых есть шапка `.zhd`.

    Нечитаемый файл (чужая учётная запись) пропускается с пометкой, а не
    выдаётся за «в порядке»: невозможность измерить — не доказательство.
    """
    найдено = []
    корень = КОРЕНЬ / "var" / "site-repos"
    if not корень.is_dir():
        return найдено
    for репо in sorted(корень.iterdir()):
        for имя in ИМЕНА_РАНТАЙМОВ:
            ф = репо / "src" / имя
            if not ф.is_file():
                continue
            try:
                т = ф.read_text(encoding="utf-8")
            except (OSError, PermissionError):
                continue
            if ".zhd__logo{" in т:
                найдено.append(ф)
    return найдено


РАНТАЙМЫ = _рантаймы()
ЕСТЬ = pytest.mark.skipif(not РАНТАЙМЫ, reason="рантаймов парка нет в дереве")


@ЕСТЬ
def test_рантаймы_вообще_нашлись():
    """Пустой перечень превратил бы остальные тесты в молчаливое «ок»."""
    assert len(РАНТАЙМЫ) >= 10, [str(п) for п in РАНТАЙМЫ]


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_логотип_не_режется(путь):
    текст = путь.read_text(encoding="utf-8")
    беды = []
    for правило in re.findall(r"\.zhd__logo\{[^}]*\}", текст):
        if re.search(r"(?<![-a-z])width:\s*\d", правило):
            беды.append("жёсткая ширина: " + правило[:120])
        if "ellipsis" in правило or "overflow:hidden" in правило:
            беды.append("обрезка: " + правило[:120])
    assert not беды, беды


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_кнопки_шапки_не_уже_своего_слова(путь):
    """`min-width` — это палец, `width` — это запрет расти. Внутри кнопки
    слово, и запрещать ей расти нельзя."""
    текст = путь.read_text(encoding="utf-8")
    беды = []
    for правило in re.findall(r"[^{}\n]*\.zhd__searchbtn[^{}\n]*\{[^}]*\}", текст):
        тело = правило.split("{", 1)[1]
        if re.search(r"(?<![-a-z])width:\s*\d", тело):
            беды.append(правило[:160])
    assert not беды, беды
