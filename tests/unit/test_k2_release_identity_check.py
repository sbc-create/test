"""REQ-K2-RELEASE-IDENTITY: выпуск подтверждается опознанием, а не ответом порта.

Ответ на `/healthz` доказывает, что КТО-ТО на порту жив. Это не то же, что
«эта витрина исполняет этот выпуск»: порт мог занять сосед, а служба —
остаться на прежнем коде после неудачного рестарта. Оба случая выглядят как
успех, и сценарий выпуска объявлял бы их выпуском.

Повод — измеренный случай у соседней линии (2026-10-18): её проверка
происхождения сверяла сумму ОДНОГО рантайма с отпечатком ДРУГОГО, потому что
читала поля «того, кто оказался на порту». Пока проекты поднимали по одному
экземпляру — сходилось.

Проверяется ПОВЕДЕНИЕ различителя, встроенного в сценарий: он извлекается из
heredoc и исполняется на подготовленных ответах. Пустой вывод — «опознано»,
любой текст — причина отказа.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

СЦЕНАРИЙ = (Path(__file__).resolve().parents[2] / "automation" / "host"
            / "k2-release-code.sh")
ТЕКСТ = СЦЕНАРИЙ.read_text(encoding="utf-8")
ВЫПУСК = "/srv/lords-13/releases/abc123abc123"
ГОЛОВА = "abc123abc123"


@pytest.fixture(scope="module")
def различитель() -> str:
    """Python из heredoc сценария — тот же код, что исполняется на узле.

    Берётся из файла, а не копируется в тест: копия разошлась бы с
    оригиналом при первой же правке, и проверка начала бы подтверждать
    саму себя.
    """
    кусок = ТЕКСТ[ТЕКСТ.index('identity="$(python3 - "$health_file"'):]
    начало = кусок.index("<<'PY'\n") + len("<<'PY'\n")
    конец = кусок.index("\nPY\n", начало)
    тело = кусок[начало:конец]
    assert "runtime_path" in тело, "из сценария извлёкся не тот кусок"
    return тело


def _запуск(различитель: str, ответ, tmp_path: Path) -> str:
    файл = tmp_path / "healthz.json"
    файл.write_text(ответ if isinstance(ответ, str)
                    else json.dumps(ответ, ensure_ascii=False), encoding="utf-8")
    г = subprocess.run([sys.executable, "-", str(файл), ВЫПУСК],
                       input=различитель, capture_output=True, text=True)
    assert г.returncode == 0, г.stderr
    return г.stdout.strip()


def test_свой_выпуск_опознаётся(различитель, tmp_path):
    """Путь измерен на живой витрине: <выпуск>/src/lords-frontend.py."""
    вывод = _запуск(различитель, {
        "runtime_path": f"{ВЫПУСК}/src/lords-frontend.py",
        "release_id": f"{ГОЛОВА}-lords-13"}, tmp_path)
    assert вывод == "", f"исправный выпуск назван неопознанным: {вывод}"


def test_сосед_на_порту_это_отказ(различитель, tmp_path):
    """Тот самый случай: отвечает другая витрина, а код ответа — 200."""
    вывод = _запуск(различитель, {
        "runtime_path": "/srv/lordserials22-info/releases/2d8237f8fea7/src/"
                        "lords-frontend.py",
        "release_id": "2d8237f8fea7-lords-05"}, tmp_path)
    assert "lordserials22-info" in вывод and ВЫПУСК in вывод


def test_прежний_выпуск_той_же_витрины_это_отказ(различитель, tmp_path):
    """Служба осталась на старом коде: учётка совпала, выпуск — нет."""
    вывод = _запуск(различитель, {
        "runtime_path": "/srv/lords-13/releases/000000000000/src/"
                        "lords-frontend.py",
        "release_id": "000000000000-lords-13"}, tmp_path)
    assert вывод, "прежний выпуск принят за новый"


def test_похожий_путь_не_проходит_по_приставке(различитель, tmp_path):
    """Отрицательный контроль к сравнению строк: каталог-сосед с тем же началом."""
    вывод = _запуск(различитель, {
        "runtime_path": f"{ВЫПУСК}-candidate/src/lords-frontend.py",
        "release_id": f"{ГОЛОВА}-lords-13"}, tmp_path)
    assert вывод, "каталог с совпадающим началом имени принят за выпуск"


def test_отсутствие_поля_это_отказ_а_не_успех(различитель, tmp_path):
    """Закрытый отказ: «подтвердить нечем» — не «подтверждено»."""
    вывод = _запуск(различитель, {"ok": True}, tmp_path)
    assert "подтвердить выпуск нечем" in вывод


def test_нечитаемый_ответ_это_отказ(различитель, tmp_path):
    вывод = _запуск(различитель, "это не json", tmp_path)
    assert "не разобран" in вывод


def test_release_id_не_участвует_в_опознании(различитель, tmp_path):
    """Отрицательный контроль к измерению на узле.

    У всех восьми витрин K2 `release_id` равен `worktree-unbuilt` — это метка
    сборки, а не номер выпуска (измерено 2026-10-18,
    `k2-release-code.sh --verify`). Условие по этому полю отвергало бы каждую
    исправную выкладку, поэтому опознание держится на пути. Проверка следит,
    чтобы поле не вернулось в различитель: с ним выпуск сломался бы молча.
    """
    вывод = _запуск(различитель, {
        "runtime_path": f"{ВЫПУСК}/src/lords-frontend.py",
        "release_id": "worktree-unbuilt"}, tmp_path)
    assert вывод == "", f"метка сборки принята за номер выпуска: {вывод}"


def test_опознание_стоит_между_ожиданием_и_успехом():
    """Порядок: ждём healthz → опознаём → только потом маршруты и успех."""
    ждём = ТЕКСТ.index('log "healthz отвечает через $waited с"')
    опознание = ТЕКСТ.index('identity="$(python3 -')
    маршруты = ТЕКСТ.index('for route in "/" "/catalog/"')
    assert ждём < опознание < маршруты


def test_неопознанная_витрина_возвращает_прежний_выпуск():
    начало = ТЕКСТ.index('if [ -n "$identity" ]')
    кусок = ТЕКСТ[начало:ТЕКСТ.index("\nfi\n", начало)]
    assert 'ln -sfn "$old_release" "$current_link"' in кусок
    assert 'restart_unit "$unit"' in кусок
    assert "exit 1" in кусок
