def test_полная_страница_записей_без_постера_НЕ_теряет(снимок):
    """Отрицательный контроль, и он важнее остальных.

    Полная страница подборки — поверхность каталога. Терять в ней высокую
    оценку из-за отсутствия картинки нельзя, и отбор к ней не применяется.
    """
    записи = list(снимок.items)
    for з in записи[:40]:
        з["poster"] = ""
    снимок_без = контракт.Снимок(записи, снимок.подробности, revision="no-poster")
    полная = контракт.разрешить("top_rated", снимок_без, "lords",
                                страница=1, на_странице=10_000)
    без_постера = [к for к in полная.items if not к.poster]
    assert без_постера, "полная страница не должна отбрасывать записи без постера"


def test_превью_полки_действительно_обходит_заглушку(снимок):
    """Проводка, а не только функция. Подстановка показала, что её не было.

    Прямые проверки `превью_с_постерами` проходили и при сломанном `_собрать`:
    снимок модуля несёт постеры у всех записей, и отбор ничего не менял. То
    есть проверялась функция, а не её применение. Здесь постер снят у записи,
    которая иначе попала бы в превью ПЕРВОЙ.
    """
    спец = контракт.спецификация("lords", "top_rated")
    эталон = контракт.разрешить("top_rated", снимок, "lords",
                                предел=спец.card_limit)
    голова = эталон.items[0].raw["slug"]

    записи = [dict(з, poster="") if з["slug"] == голова else dict(з)
              for з in снимок.items]
    снимок_с_дырой = контракт.Снимок(записи, снимок.подробности,
                                     revision="hole")
    превью = контракт.разрешить("top_rated", снимок_с_дырой, "lords",
                                предел=спец.card_limit)
    слаги = [к.raw["slug"] for к in превью.items]
    assert голова not in слаги, (
        f"{голова} без постера осталась в превью — отбор не применён")
    assert all(к.poster for к in превью.items), [к.raw["slug"] for к in превью.items
                                                 if not к.poster]
    assert len(слаги) == спец.card_limit, len(слаги)


def test_полка_новизны_порядок_по_дате_НЕ_меняет(снимок):
    """Отрицательный контроль, названный линией SEO, и он сужает правку.

    На lordserial33.biz все карточки без постера лежат в СЕРИАЛЬНЫХ полках, а
    не в «Высоких оценках». Для полки новизны отбор «с постером сначала»
    переставил бы порядок по дате, то есть сломал бы её смысл: «новое первым»
    важнее, чем «с картинкой первым». Поэтому отбор применяется только там, где
    сортировка по ОЦЕНКЕ.
    """
    спец = контракт.спецификация("lords", "recently_added")
    assert (спец.sort_spec or {}).get("field") == "published_at", спец.sort_spec

    записи = list(снимок.items)
    эталон = контракт.разрешить("recently_added", снимок, "lords",
                                предел=спец.card_limit)
    голова = эталон.items[0].raw["slug"]
    без_постера = [dict(з, poster="") if з["slug"] == голова else dict(з)
                   for з in записи]
    снимок_2 = контракт.Снимок(без_постера, снимок.подробности, revision="nov")
    превью = контракт.разрешить("recently_added", снимок_2, "lords",
                                предел=спец.card_limit)
    assert превью.items[0].raw["slug"] == голова, (
        "полка новизны переставила порядок из-за постера — это запрещено")


