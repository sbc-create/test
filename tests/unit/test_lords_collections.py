def test_карточка_подборки_обещает_свою_страницу(витрина):
    """Обязательная проверка дефекта Lords-03.

    Карточка «Боевики» вела в каталог другого состава. Теперь число записей,
    адрес и обложки берутся из ОДНОГО определения, и это сверяется со
    страницей, которую карточка открывает.
    """
    модуль, в = витрина
    import re
    хаб = в.хаб_подборок()
    карточки = re.findall(
        r'data-collection="([a-z_]+)" data-collection-total="(\d+)"'
        r' data-collection-previews="(\d+)"', хаб)
    assert карточки, "карточек подборок на /collections/ не нашлось"
    снимок = модуль.Снимок.получить(в.д, в.п)
    for ключ, всего, превью in карточки:
        страница = модуль.КОЛЛЕКЦИИ.разрешить(ключ, снимок, "lords",
                                              страница=1, на_странице=10_000)
        assert int(всего) == страница.total, (
            f"{ключ}: карточка обещает {всего}, страница отдаёт {страница.total}")
        assert f'href="/collection/{ключ}/"' in хаб, (
            f"{ключ}: карточка ведёт не на свою страницу")
        assert 0 < int(превью) <= в.ПОСТЕРОВ_В_ПОДБОРКЕ


def test_обложки_взяты_из_состава_и_в_его_порядке(витрина):
    модуль, в = витрина
    снимок = модуль.Снимок.получить(в.д, в.п)
    for данные in в._подборки_витрины():
        полная = модуль.КОЛЛЕКЦИИ.разрешить(данные.collection_key, снимок, "lords",
                                            страница=1, на_странице=10_000)
        состав = [к.raw["slug"] for к in полная.items]
        места = [состав.index(к.raw["slug"]) for к in данные.items
                 if к.raw["slug"] in состав]
        assert len(места) == len(данные.items), (
            f"{данные.collection_key}: на обложке запись вне состава подборки")
        assert места == sorted(места), (
            f"{данные.collection_key}: обложки идут не в порядке состава")


def test_в_превью_нет_повторов_и_есть_читаемые_названия(витрина):
    _, в = витрина
    import re
    хаб = в.хаб_подборок()
    for блок in re.findall(r'<span class="hub__g">(.*?)</span></a>', хаб, re.S):
        имена = re.findall(r'<span class="hub__n">([^<]*)</span>', блок)
        assert имена, "названия произведений в превью не выведены"
        assert all(и.strip() for и in имена), "пустое название в превью"
        assert len(имена) == len(set(имена)), f"повтор внутри превью: {имена}"


def test_названия_видны_без_наведения(витрина):
    """Название — текст в разметке, а не только `title=` у ссылки."""
    _, в = витрина
    хаб = в.хаб_подборок()
    assert '<span class="hub__n">' in хаб


def test_отсутствующий_постер_не_даёт_битой_картинки(tmp_path, monkeypatch):
    записи, детали = _каталог(60)
    for з in записи:
        з["poster"] = ""
    с = h.Стенд(tmp_path)
    с.записать_каталог(записи)
    с.записать_подробности([
        dict(д, slug=slug, type_="movie", external_ids={"kp": f"kp-{slug}"})
        for slug, д in детали.items()])
    с.записать_плеер()
    модуль = h.загрузить(с, monkeypatch)
    try:
        в = h.вид(модуль)
        хаб = в.хаб_подборок()
        блоки = хаб.split('<span class="hub__g">')[1:]
        assert блоки, "превью подборок не собрались"
        for блок in блоки:
            голова = блок.split("</a>")[0]
            assert "<img" not in голова, "пустой постер отдан тегом img"
            assert 'class="hub__ph"' in голова, "места под постер нет — раскладка прыгнет"
    finally:
        h.выгрузить(модуль)
