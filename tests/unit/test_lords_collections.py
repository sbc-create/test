def test_окно_новизны_действительно_отсекает(снимок):
    """Проверка «от обратного»: без окна подборка была бы хвостом в 240."""
    состав = _составы(снимок)["recently_added"]
    дней = контракт.спецификация("lords", "recently_added").filter_spec["fresh_days"]
    новейшая = max(str(з["published_at"])[:10] for з in снимок.items)
    from datetime import datetime, timedelta
    край = (datetime.fromisoformat(новейшая) - timedelta(days=дней)).date().isoformat()
    по_slug = {з["slug"]: з for з in снимок.items}
    assert состав, "подборка новизны пуста — окно отсекло всё"
    for slug in состав:
        assert str(по_slug[slug]["published_at"])[:10] >= край, (
            f"{slug} старше окна в {дней} дней, но объявлен новинкой")
    assert len(состав) < len(снимок.items), "окно не отсекло ничего"


