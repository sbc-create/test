# --- 8. свежие поступления одного вида не превращают общую подборку в фильмовую
#
# Измерено на живой витрине zonafilm.space 20.10: первые 60 карточек
# `/collection/recently_added/` совпадали с `/collection/recently_added_movies/`
# на 48 из 60 — 80,0 %. Контрактная проверка различия этого НЕ ловила, потому
# что её снимок раскладывает виды по датам поровну (`i % 3`), и в порядке по
# дате сериалы оказываются перемешаны сами. На живом каталоге пополнение идёт
# пачками одного вида, и тогда голова общей подборки повторяет фильмовую.
#
# Признак здесь — первая СТРАНИЦА, а не весь состав: посетитель и обходчик
# видят её, а Жаккар по полному составу у этих двух подборок законно высок
# (фильмы — подмножество каталога).

ПЕРВАЯ_СТРАНИЦА = 60
ПРЕДЕЛ_ПЕРВОЙ_СТРАНИЦЫ = 50


def _каталог_пачками(n: int = 600) -> tuple[list[dict], dict[str, dict]]:
    """Каталог, где САМЫЕ СВЕЖИЕ записи — почти все фильмы.

    Так пополняется живой каталог: пачкой одного вида. Доля видов в каталоге
    при этом прежняя, меняется только их расположение по датам — то есть
    проверяется ровно расположение, а не состав.
    """
    записи, детали = _каталог(n)
    по_дате = sorted(записи, key=lambda з: з["published_at"], reverse=True)
    for н, з in enumerate(по_дате[:120]):
        # В голове оставляем сериалом каждую двадцатую: пачка не идеальна, но
        # фильмы в ней решительно преобладают — как на живой витрине.
        з["kind"] = "Сериал" if н % 20 == 0 else "Фильм"
    return записи, детали


