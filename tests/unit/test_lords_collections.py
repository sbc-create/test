"""Подборки: разный состав под разными названиями, карточка равна странице.

Два дефекта, найденных на lords-03, оба в общем контуре, а не в одной витрине.

**Разные названия над одной выборкой.** Замер по спецификациям контракта на
снимке 53 772 записи: первые 14 карточек `top_rated` и `video_available`
совпадали на 85 %, `recently_added` и `current_season` — на 71 %, а
`new_episodes` отдавала ноль записей. Заменой обложек это не лечится:
различаться обязан СОСТАВ.

**Карточка рассказывает о другой странице.** Замер на живом сайте: карточка
«Боевики» обещала 5 439 записей по убыванию оценки, а переход вёл на выборку
из 9 533 записей по дате, с аниме и дорамами, под заголовком «Каталог».

Пересечение меряется ДВУМЯ величинами, и обе названы формулой:

* «первые видимые» — |A∩B| / min(|A|,|B|) по первым ВИДИМЫХ записям. Отвечает
  на вопрос «видит ли посетитель одно и то же на двух полках»;
* «полный состав» — Жаккар, |A∩B| / |A∪B|. Метрика «% от меньшего» на полном
  составе вводит в заблуждение: у вложенных наборов она даёт почти 100 %
  просто потому, что один набор больше.

Пороги — граница между «две разные подборки» и «одна с двумя подписями», а не
вкус. Жанры произведений ради красивого процента здесь не меняются: данные
проверки разнесены по свойствам заранее.
"""
from __future__ import annotations

import sys

import pytest

import lords_runtime_harness as h

sys.path.insert(0, str(h.КОРЕНЬ / "automation" / "host"))
import collection_contract as контракт  # noqa: E402

#: Сколько первых записей считаются «на виду».
ВИДИМЫХ = 14
ПРЕДЕЛ_ВИДИМЫХ = 50
ПРЕДЕЛ_ЖАККАРА = 50


def _каталог(n: int = 600) -> tuple[list[dict], dict[str, dict]]:
    """Каталог с независимыми свойствами.

    Вид, год, оценка, дата и играбельность меняются по разным периодам,
    иначе «различие подборок» проверялось бы на данных, где оно получается
    само собой.
    """
    записи: list[dict] = []
    детали: dict[str, dict] = {}
    for i in range(n):
        slug = f"t{i:03d}"
        # Даты разложены на три месяца: часть попадает в окно новизны, часть
        # нет. Иначе окно ничего не отсекало бы и проверка была бы пустой.
        день = (i % 90)
        месяц, число = (9, 26 - день) if день < 26 else (
            (8, 31 - (день - 26)) if день < 57 else (7, 31 - (день - 57)))
        записи.append({
            "slug": slug,
            "url": f"/title/{slug}/",
            "title": f"Тайтл {i}",
            "kind": "Фильм" if i % 3 else "Сериал",
            "year": 2026 if i % 7 == 0 else 2019 + (i % 6),
            "poster": f"/posters/{slug}.jpg",
            "published_at": f"2026-{месяц:02d}-{max(1, число):02d}T00:00:00Z",
        })
        детали[slug] = {
            "id": f"id-{slug}",
            "genres": ["драма"],
            "imdb_rating": round(4.0 + (i % 61) / 10.0, 1),
            # Играбельны не все: иначе «С видео» совпала бы с каталогом по
            # построению, а не по дефекту.
            "playable": (i % 4) != 0,
        }
    return записи, детали


@pytest.fixture(scope="module")
def снимок():
    записи, детали = _каталог()
    return контракт.Снимок(записи, детали, revision="test")


def _составы(снимок) -> dict[str, list[str]]:
    готово = {}
    for спец in контракт.спецификации("lords"):
        полная = контракт.разрешить(спец.collection_key, снимок, "lords",
                                    страница=1, на_странице=10_000)
        готово[спец.collection_key] = [к.raw["slug"] for к in полная.items]
    return готово


# --- 1. подборка не пуста и не равна каталогу -------------------------------

def test_подборка_не_повторяет_каталог(снимок):
    составы = _составы(снимок)
    всего = len(снимок.items)
    for ключ, состав in составы.items():
        assert len(состав) <= всего * контракт.ПРЕДЕЛ_ДОЛИ_ПУЛА, (
            f"{ключ}: {len(состав)} из {всего} — это каталог, а не подборка")


def test_подборка_без_данных_объявлена_пустой_а_не_показана(снимок):
    """`new_episodes` отдаёт ноль: отметки времени эпизода в снимке нет вовсе.

    Пустую подборку показывать нельзя, и выдумывать ей состав — тоже.
    """
    составы = _составы(снимок)
    assert составы["new_episodes"] == []
    спец = контракт.спецификация("lords", "new_episodes")
    assert спец.empty_policy == контракт.СКРЫТЬ


# --- 2. правила отбора не повторяются ---------------------------------------

def test_правила_отбора_не_повторяются():
    видели: dict[tuple, str] = {}
    for спец in контракт.спецификации("lords"):
        ключ = (спец.source, tuple(sorted(спец.filter_spec.items())),
                tuple(sorted(спец.sort_spec.items())))
        assert ключ not in видели, (
            f"{спец.collection_key} и {видели[ключ]}: одинаковое правило отбора "
            "под разными названиями")
        видели[ключ] = спец.collection_key


# --- 3. пересечение: две величины, обе с формулой ---------------------------

def _пара(составы, a, b):
    A, B = set(составы[a][:ВИДИМЫХ]), set(составы[b][:ВИДИМЫХ])
    видимые = 100 * len(A & B) // max(1, min(len(A), len(B))) if A and B else 0
    ПА, ПБ = set(составы[a]), set(составы[b])
    жаккар = 100 * len(ПА & ПБ) // max(1, len(ПА | ПБ)) if (ПА or ПБ) else 0
    return видимые, жаккар


def test_подборки_различны_по_составу(снимок):
    составы = {к: v for к, v in _составы(снимок).items() if v}
    ключи = sorted(составы)
    провалы = []
    for i, a in enumerate(ключи):
        for b in ключи[i + 1:]:
            видимые, жаккар = _пара(составы, a, b)
            if видимые > ПРЕДЕЛ_ВИДИМЫХ:
                провалы.append(
                    f"{a} и {b}: первые {ВИДИМЫХ} совпадают на {видимые}% "
                    f"(|A∩B|/min(|A|,|B|)) при пределе {ПРЕДЕЛ_ВИДИМЫХ}%")
            if жаккар > ПРЕДЕЛ_ЖАККАРА:
                провалы.append(
                    f"{a} и {b}: полный состав пересекается на {жаккар}% "
                    f"(Жаккар |A∩B|/|A∪B|) при пределе {ПРЕДЕЛ_ЖАККАРА}%")
    assert not провалы, "\n  ".join(["подборки неразличимы:"] + провалы)


