"""Выбор серий для проверки: по номеру, и нулевая отдельно.

Два изъяна, которые проверяются здесь, по сети воспроизвести нечем.

Первый: выборка шла по порядку в разметке. На витрине, перечисляющей серии от
новых к старым, первая серия не проверялась бы никогда — а такой витрины
сейчас нет, и живой прогон об этом молчал бы.

Второй: владелец называл повторяющийся дефект «доступность эпизодов считается
по счётчику, серия 0 теряется». Выборка первая-средняя-последняя нулевую серию
не задевает, если список начинается с единицы, то есть почти всегда. Значит
«0 расхождений» об этом дефекте не говорило ничего, и теперь прогон обязан
сказать «не измерено».
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "episode-nav-check.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("episode_nav_check",
                                                  ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    sys.modules["episode_nav_check"] = м
    спец.loader.exec_module(м)
    return м


эн = _модуль()


def _путь(сезон: int, серия: int) -> str:
    return f"/title/проба/season-{сезон}/episode-{серия}/"


def test_номер_разбирает_сезон_и_серию():
    assert эн.номер(_путь(2, 13)) == (2, 13)


def test_непонятный_адрес_не_роняет_разбор():
    """Отказ здесь стоил бы всего прогона из-за одной странной ссылки."""
    assert эн.номер("/title/проба/") == (0, 0)


def test_порядок_в_разметке_на_выбор_не_влияет():
    """Главное свойство: витрина с обратным порядком серий.

    До правки `серии[0]` была бы последней серией, и первая не проверялась бы
    никогда.
    """
    прямой = [_путь(1, н) for н in range(1, 13)]
    обратный = list(reversed(прямой))
    выборка_п, _ = эн.выбрать(прямой)
    выборка_о, _ = эн.выбрать(обратный)
    assert выборка_п == выборка_о, (выборка_п, выборка_о)
    assert выборка_п[0] == _путь(1, 1), выборка_п
    assert выборка_п[-1] == _путь(1, 12), выборка_п


def test_серии_разных_сезонов_упорядочены_по_сезону():
    серии = [_путь(2, 1), _путь(1, 5), _путь(1, 1), _путь(2, 18)]
    выборка, _ = эн.выбрать(серии)
    assert выборка[0] == _путь(1, 1), выборка
    assert выборка[-1] == _путь(2, 18), выборка


def test_нулевая_серия_попадает_в_выборку():
    серии = [_путь(1, н) for н in range(0, 7)]
    выборка, нулевые = эн.выбрать(серии)
    assert нулевые == [_путь(1, 0)], нулевые
    assert _путь(1, 0) in выборка, выборка


def test_нулевая_серия_добавляется_даже_когда_не_первая_и_не_средняя():
    """Длинный список: первая по номеру — нулевая, значит она уже внутри.

    Проверяется обратный случай: нулевая есть во ВТОРОМ сезоне, а выборка
    первая-средняя-последняя её не задевает.
    """
    серии = [_путь(1, н) for н in range(1, 13)] + [_путь(2, 0), _путь(2, 1)]
    выборка, нулевые = эн.выбрать(серии)
    assert нулевые == [_путь(2, 0)], нулевые
    assert _путь(2, 0) in выборка, выборка


def test_без_нулевой_серии_список_пуст_и_это_сигнал():
    """Пустой список нулевых — то, из-за чего прогон говорит «не измерено»."""
    _, нулевые = эн.выбрать([_путь(1, н) for н in range(1, 13)])
    assert нулевые == []


def test_повторы_в_выборке_не_остаются():
    """У короткого списка первая и средняя совпадают — страница тянулась бы дважды."""
    выборка, _ = эн.выбрать([_путь(1, 1), _путь(1, 2)])
    assert len(выборка) == len(set(выборка)), выборка
