"""Проверка готовности доставки не должна вводить в заблуждение дважды.

Повод измеренный, 23.10. Инструмент `automation/local/k2-install-delivery.py`
готовит доставку каталога восьми витрин K2 и печатает её готовность. Две его
черты сегодня обошлись мне часом работы не в ту сторону:

1. СВОДКА ПРОТИВОРЕЧИЛА СТРОКАМ. Три факта печатались как ` НЕТ ` (нет
   `var/ansible/hosts.yml`, нет `var/k2-data`, нет `var/k2-data/publish-reports`),
   а итог говорил «нехваток: 0» и код возврата был 0. Предупреждение «пока
   есть нехватки, таймер включать нельзя» при этом подавлялось. Читающий сводку
   включил бы таймер, и он бы упал — ровно та ошибка, ради которой инструмент
   и написан. Это тот же класс, что 16-й в `docs/RECURRING_FAILURES.md`.

2. КАТАЛОГ ПО УМОЛЧАНИЮ — НЕ ТОТ, КОТОРЫЙ РАБОТАЕТ. По умолчанию проверялся
   `/srv/site-factory/repo`, тогда как включённый пользовательский юнит
   `k2-catalog-deliver.user.service` работает в `/srv/site-factory/k2-delivery`,
   и в самом юните написано, почему первая копия не годится. Проверка честно
   показывала шесть нехваток КОПИИ, которая к доставке не относится.

Проверяется поведение, а не текст: инструмент запускается на подготовленных
каталогах, и сверяется его код возврата и то, что он печатает.
"""
from __future__ import annotations

import pathlib
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИНСТРУМЕНТ = КОРЕНЬ / "automation" / "local" / "k2-install-delivery.py"


def запуск(*аргв: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(ИНСТРУМЕНТ), *аргв],
                          capture_output=True, text=True, cwd=str(КОРЕНЬ),
                          timeout=180)


def test_сводка_не_противоречит_строкам(tmp_path):
    """Если хоть один факт напечатан как НЕТ, итог не может быть «нехваток: 0»."""
    п = запуск("--root", str(tmp_path))
    строк_нет = [с for с in п.stdout.splitlines() if с.startswith(" НЕТ")]
    assert строк_нет, "на пустом каталоге нехватки обязаны быть — проверять нечего"
    итог = [с for с in п.stdout.splitlines() if с.startswith("нехваток:")]
    assert итог, f"итоговой строки нет:\n{п.stdout}"
    число = int(итог[0].split(":")[1].split()[0])
    assert число >= len(строк_нет), (
        f"напечатано {len(строк_нет)} строк НЕТ, а итог говорит {число}:"
        f"\n{п.stdout}")
    assert п.returncode != 0, "при нехватках код возврата обязан быть ненулевым"


def test_инструмент_называет_каталог_включённого_таймера(tmp_path):
    """Проверка обязана сказать, в каком каталоге работает включённый юнит.

    Без этого проверка исправной копии читается как проверка доставки, а это
    разные каталоги: юнит работает в постоянном каталоге доставки, а не в
    рабочей копии репозитория.
    """
    п = запуск("--root", str(tmp_path))
    текст = п.stdout
    assert "k2-catalog-deliver.user" in текст, (
        f"инструмент не упоминает юнит доставки:\n{текст}")
    assert "WorkingDirectory" in текст or "рабочий каталог юнита" in текст, (
        f"инструмент не называет рабочий каталог юнита:\n{текст}")


def test_расхождение_с_каталогом_юнита_называется_прямо(tmp_path):
    """Когда проверяют не тот каталог, инструмент говорит это словами."""
    п = запуск("--root", str(tmp_path))
    assert "НЕ тот каталог" in п.stdout or "не тот каталог" in п.stdout, (
        f"расхождение проверяемого каталога с каталогом юнита не названо:"
        f"\n{п.stdout}")
