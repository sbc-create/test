"""Каждый объявленный домен обязан быть виден обеим интеграциям.

Пробел, который здесь закрывается, повторялся дважды и оба раза ничем не
проявлялся снаружи: домен, отсутствующий в `config/analytics.json`, не получает
счётчика, а домен, отсутствующий в манифесте Topvisor, не попадает ни в план, ни
в отчёт. Так пропали zonafilm.space (работала публично без проекта) и все шесть
новых доменов сразу. «Нет записи» выглядит точно так же, как «всё сделано»:
в обоих случаях в отчёте нет строки.

Проверяется соответствие реестру ячеек — единственному списку, который заводится
раньше всего остального. Домены, выведенные из эксплуатации, исключаются по
явному признаку, а не по отсутствию строки.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРЕНЬ))

from factory.topvisor.manifest import by_domain  # noqa: E402

РЕЕСТР = КОРЕНЬ / "config" / "site-cells.json"
АНАЛИТИКА = КОРЕНЬ / "config" / "analytics.json"

#: Состояния жизненного цикла, при которых интеграции не нужны.
ВНЕ_ЭКСПЛУАТАЦИИ = {"decommissioned", "retired"}

#: Непубличные домены: пилот и локальные стенды. Счётчик и проект позиций для
#: них бессмысленны — их нельзя ни открыть из браузера пользователя, ни снять в
#: поиске. Признак — суффикс, а не перечисление имён: новый стенд не должен
#: требовать правки теста.
НЕПУБЛИЧНЫЕ_СУФФИКСЫ = (".localhost", ".localhost.test", ".test", ".local", ".invalid")

#: Известные пробелы: домены, работающие без проекта Topvisor. Здесь они не
#: замолчаны, а названы с причиной, и отметка строгая — как только проект
#: появится, тест упадёт на XPASS и строку придётся убрать. Молчаливый пропуск
#: ровно этого класса и привёл к тому, что zonafilm.space жила публично без
#: проекта, и заметить это было нечем.
ИЗВЕСТНЫЙ_ПРОБЕЛ_TOPVISOR = {
    "animedia.icu": "проект не создавался: семья Animedia вне текущего задания",
    "animedia.space": "проект не создавался: семья Animedia вне текущего задания",
}


def _ячейки() -> list[dict]:
    данные = json.loads(РЕЕСТР.read_text(encoding="utf-8"))
    return [c for c in данные["cells"]
            if str(c.get("lifecycle_state") or "").lower() not in ВНЕ_ЭКСПЛУАТАЦИИ
            and not str(c["domain"]).endswith(НЕПУБЛИЧНЫЕ_СУФФИКСЫ)]


def _домены_аналитики() -> dict[str, dict]:
    данные = json.loads(АНАЛИТИКА.read_text(encoding="utf-8"))
    return {p["domain"]: p for p in данные["properties"]}


ЯЧЕЙКИ = _ячейки()
assert ЯЧЕЙКИ, "реестр ячеек пуст — проверять нечего"


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["domain"])
def test_домен_есть_в_реестре_аналитики(ячейка: dict) -> None:
    свойства = _домены_аналитики()
    домен = ячейка["domain"]
    assert домен in свойства, (
        f"{домен} ({ячейка['site_id']}) не объявлен в config/analytics.json — "
        "счётчик ему никогда не создадут, и в отчёте не будет даже строки")


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["domain"])
def test_домен_есть_в_манифесте_topvisor(ячейка: dict, request) -> None:
    домен = ячейка["domain"]
    if домен in ИЗВЕСТНЫЙ_ПРОБЕЛ_TOPVISOR:
        request.node.add_marker(pytest.mark.xfail(
            reason=ИЗВЕСТНЫЙ_ПРОБЕЛ_TOPVISOR[домен], strict=True))
    assert by_domain(домен) is not None, (
        f"{домен} ({ячейка['site_id']}) отсутствует в манифесте Topvisor — "
        "он не попадёт ни в план, ни в отчёт, и это не будет заметно")


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["domain"])
def test_счётчик_не_делится_с_другим_доменом(ячейка: dict) -> None:
    """Один счётчик на два домена смешивает две аудитории безвозвратно."""
    свойства = _домены_аналитики()
    мой = свойства.get(ячейка["domain"], {}).get("counter_id")
    if мой is None:
        pytest.skip(f"{ячейка['domain']}: счётчик ещё не создан")
    чужие = [d for d, p in свойства.items()
             if d != ячейка["domain"] and p.get("counter_id") == мой]
    assert not чужие, f"счётчик {мой} указан ещё у: {', '.join(чужие)}"


#: Приставка имени счётчика по префиксу site_id. Выведена из счётчиков, которые
#: уже созданы в кабинете, а не назначена: имя нового счётчика обязано попадать
#: в тот же ряд, что у соседей по семейству.
def _приставки() -> dict[str, str]:
    import re

    итог: dict[str, str] = {}
    for з in _домены_аналитики().values():
        имя = str(з.get("counter_name") or "")
        if з.get("counter_id") and " — " in имя:
            семья = re.split(r"[-_]", str(з.get("site_id") or ""), maxsplit=1)[0]
            итог.setdefault(семья, имя.split(" — ", 1)[0])
    return итог


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["domain"])
def test_имя_счётчика_не_заготовка(ячейка: dict) -> None:
    """`counter_name` уходит в Метрику как НАЗВАНИЕ счётчика в кабинете.

    У всех шести новых доменов там стояла строка «новый домен без счётчика —
    <домен>»: пометка состояния реестра, которая при первом же создании стала бы
    настоящим именем счётчика у владельца и осталась бы им навсегда. Поле
    состояния и поле имени совпали по виду, и различить их было нечем.
    """
    import re

    свойства = _домены_аналитики()
    запись = свойства.get(ячейка["domain"])
    if запись is None:
        pytest.skip(f"{ячейка['domain']}: нет записи в реестре аналитики")
    имя = str(запись.get("counter_name") or "")
    assert имя, f"{ячейка['domain']}: имя счётчика пусто"
    for заготовка in ("новый домен", "без счётчика", "todo", "TODO", "placeholder", "заготовка"):
        assert заготовка.lower() not in имя.lower(), (
            f"{ячейка['domain']}: в имени счётчика пометка состояния «{заготовка}» — "
            "она станет названием счётчика в кабинете")
    assert имя.endswith(f" — {ячейка['domain']}"), (
        f"{ячейка['domain']}: имя «{имя}» не кончается доменом — счётчик не опознать в списке")
    приставки = _приставки()
    семья = re.split(r"[-_]", str(запись.get("site_id") or ""), maxsplit=1)[0]
    ожидаемая = приставки.get(семья)
    if ожидаемая:
        # Требуется совпадение НАЧАЛА приставки, а не её равенство. Уточнение
        # внутри семейства бывает осмысленным: «Zona Cinema — zonafilm.cc» рядом
        # с «Zona — zonafilm.space» — это названная разница между витринами, а не
        # опечатка. Ловится другое: приставка чужого семейства, из-за которой
        # счётчик Yummy назывался «Lords — yummyani7.site» и в кабинете попал бы
        # не в тот ряд.
        приставка = имя.split(" — ", 1)[0]
        assert приставка.startswith(ожидаемая), (
            f"{ячейка['domain']}: приставка «{приставка}» — чужое семейство; "
            f"у {семья} счётчики называются «{ожидаемая} — …»")


@pytest.mark.parametrize("ячейка", ЯЧЕЙКИ, ids=lambda c: c["domain"])
def test_запись_аналитики_знает_свою_ячейку(ячейка: dict) -> None:
    """Без `site_id` охрана «счётчик пережил выпуск» молча пропускает домен.

    У пяти из шести новых доменов поле было пустым: проверка, требующая
    объявления счётчика в репозитории витрины, находила запись, не находила
    ячейку и пропускала домен — то есть выглядела зелёной ровно там, где ничего
    не проверяла.
    """
    свойства = _домены_аналитики()
    запись = свойства.get(ячейка["domain"])
    if запись is None:
        pytest.skip(f"{ячейка['domain']}: нет записи в реестре аналитики")
    assert запись.get("site_id") == ячейка["site_id"], (
        f"{ячейка['domain']}: в реестре аналитики site_id={запись.get('site_id')!r}, "
        f"в реестре ячеек {ячейка['site_id']!r}")
