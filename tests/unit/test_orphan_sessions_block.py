"""Сессии агента в переписи памяти: только сообщать, никогда не останавливать.

Перепись считала процессы ВИТРИН и находила сирот на ~500 МиБ. Процессы
`claude` при этом держат 9520 МиБ — в девятнадцать раз больше и больше, чем
все витрины вместе, — и в перепись не входили вовсе. Это объясняет живой
сигнал: ворота редактора отказывают по памяти около восьми раз в сутки с
провалом до 605 МиБ при пороге 2048.

Главное, что здесь закреплено, — границы. Сессии не попадают в список на
остановку ни при каких условиях: по всем трём меркам сироты (нет порта, нет
юнита, нет места в конфигурации nginx) они «сироты», а остановка прервала бы
чью-то работу. Признак сироты у витрин уже однажды ошибался опасным образом,
и смешивать с ним сессии нельзя.

Стенд — поддельное дерево `/proc`: настоящее дерево меняется между запусками,
и проверка на нём измеряла бы машину, а не инструмент.
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "local" / "orphan-process-audit.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("orphan_process_audit",
                                                  ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    sys.modules["orphan_process_audit"] = м
    спец.loader.exec_module(м)
    return м


оп = _модуль()

#: Такт системы: возраст считается через него, и стенд обязан считать так же.
ТАКТ = os.sysconf("SC_CLK_TCK")


def _процесс(корень: Path, pid: int, команда: str, страниц: int,
             запущен_тиков: int) -> None:
    каталог = корень / str(pid)
    каталог.mkdir()
    (каталог / "cmdline").write_bytes(
        команда.replace(" ", "\0").encode("utf-8") + b"\0")
    # statm: второе поле — резидентные страницы.
    (каталог / "statm").write_text(f"0 {страниц} 0 0 0 0 0\n",
                                   encoding="utf-8")
    # stat: двадцатое поле после закрывающей скобки — время старта в тактах.
    поля = ["0"] * 19
    поля[18] = str(запущен_тиков)
    (каталог / "stat").write_text(f"{pid} (claude) S " + " ".join(поля) + "\n",
                                  encoding="utf-8")


def _дерево(tmp_path: Path, uptime_с: float = 100_000.0) -> Path:
    корень = tmp_path / "proc"
    корень.mkdir()
    (корень / "uptime").write_text(f"{uptime_с} 0.0\n", encoding="utf-8")
    return корень


def test_считаются_только_исполняемые_claude(tmp_path, monkeypatch):
    """Ровно исполняемый файл, а не любое упоминание слова.

    Иначе в перечень попал бы и сам инструмент, и любой grep по слову — и
    число «памяти сессий» стало бы бессмысленным.
    """
    корень = _дерево(tmp_path)
    _процесс(корень, 100, "/home/claude/.local/bin/claude --resume", 50_000,
             1_000)
    _процесс(корень, 101, "python3 упомянул claude в аргументах", 50_000, 1_000)
    _процесс(корень, 102, "/usr/bin/grep -r claude /home", 50_000, 1_000)
    monkeypatch.setattr(оп, "ПРОЦ", корень)

    итог = оп.сессии_агента()
    assert [с["pid"] for с in итог] == ["100"], итог


def test_порядок_от_старых_к_новым(tmp_path, monkeypatch):
    """Старые и есть предмет решения: именно они копятся."""
    корень = _дерево(tmp_path)
    _процесс(корень, 200, "claude", 10_000, int(90_000 * ТАКТ))   # молодой
    _процесс(корень, 201, "claude", 10_000, int(1_000 * ТАКТ))    # старый
    monkeypatch.setattr(оп, "ПРОЦ", корень)

    итог = оп.сессии_агента()
    assert [с["pid"] for с in итог] == ["201", "200"], итог
    assert итог[0]["age_h"] > итог[1]["age_h"]


def test_возраст_и_память_считаются_верно(tmp_path, monkeypatch):
    корень = _дерево(tmp_path, uptime_с=36_000.0)  # 10 часов работы машины
    # Процесс стартовал в момент 0 → ему 10 часов. 256 страниц по 4 КиБ = 1 МиБ.
    _процесс(корень, 300, "claude", 256, 0)
    monkeypatch.setattr(оп, "ПРОЦ", корень)

    итог = оп.сессии_агента()
    assert len(итог) == 1
    assert abs(итог[0]["age_h"] - 10.0) < 0.01, итог
    assert итог[0]["rss_mib"] == 1, итог


def test_свой_процесс_в_перечень_не_идёт(tmp_path, monkeypatch):
    """Инструмент не считает себя: иначе число росло бы от самого замера."""
    корень = _дерево(tmp_path)
    _процесс(корень, os.getpid(), "claude", 50_000, 1_000)
    monkeypatch.setattr(оп, "ПРОЦ", корень)
    assert оп.сессии_агента() == []


def test_нечитаемая_запись_прогон_не_роняет(tmp_path, monkeypatch):
    """Процесс может исчезнуть между перечислением и чтением.

    Отказ здесь стоил бы всей переписи из-за одного завершившегося процесса.
    """
    корень = _дерево(tmp_path)
    _процесс(корень, 400, "claude", 10_000, 1_000)
    (корень / "401").mkdir()          # ни cmdline, ни statm
    (корень / "не-число").mkdir()     # вообще не процесс
    monkeypatch.setattr(оп, "ПРОЦ", корень)

    итог = оп.сессии_агента()
    assert [с["pid"] for с in итог] == ["400"], итог


def test_без_дерева_процессов_пустой_перечень(tmp_path, monkeypatch):
    """Невозможность измерить — пустой перечень, а не отказ."""
    monkeypatch.setattr(оп, "ПРОЦ", tmp_path / "такого-нет")
    assert оп.сессии_агента() == []


def test_живой_прогон_называет_сессии_и_не_включает_их_в_остановку():
    """На настоящей машине блок обязан быть виден и помечен как несносимый."""
    import subprocess
    готово = subprocess.run([sys.executable, str(ИСТОЧНИК)],
                            capture_output=True, text=True, timeout=600)
    assert готово.returncode == 0, готово.stderr[-500:]
    if "сессии агента:" not in готово.stdout:
        import pytest
        pytest.skip("сессий агента на машине нет")
    assert "НЕ ВХОДЯТ НИ ПРИ КАКИХ УСЛОВИЯХ" in готово.stdout
