"""Третий гейт: разрешение владельца проверяет ЧИТАТЕЛЬ, а не только писатель.

Повод нашла линия витрины `animedia.icu`, читая выложенный файл своей
витрины: заголовок модуля обещал «решение собирается из трёх независимых
источников… открыто только если ВСЕ три говорят открыто», а функция `решить`
проверяла два — разрешение выпуска и файл состояния. Поля
`owner_authorized_open` в читателе не было вовсе.

Третий гейт при этом существовал: его проверяет операция, которая файл пишет
(`factory/qwen/indexing.py` ставит блокер «владелец не разрешал открытие» и
делает `ok` ложным). То есть защита держалась на том, что файл состояния
пишет ТОЛЬКО эта операция. Любой другой писатель, положивший
`desired_state: OPEN` с `owner_authorized_open: false`, открыл бы витрину —
читатель бы не заметил.

Безопасность правки измерена, а не предположена: все 12 файлов состояния на
узле несут `owner_authorized_open: true`, то есть требование поля не закрывает
ни одной работающей витрины; у восьми витрин партии K2 файла состояния нет
вовсе, и они остаются закрытыми.

Проверяется ПОВЕДЕНИЕ читателя на подставленных файлах — без сети и без
витрин.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ЧИТАТЕЛЬ = КОРЕНЬ / "automation" / "host" / "indexing_mode.py"


@pytest.fixture(scope="module")
def модуль():
    спец = importlib.util.spec_from_file_location("_режим_индексации", ЧИТАТЕЛЬ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[спец.name] = м
    спец.loader.exec_module(м)
    return м


def состояние(корень: Path, домен: str, **поля) -> Path:
    корень.mkdir(parents=True, exist_ok=True)
    запись = {"schema_version": 1, "site": домен, "desired_state": "OPEN",
              "owner_authorized_open": True}
    запись.update(поля)
    п = корень / f"{домен}.json"
    п.write_text(json.dumps(запись, ensure_ascii=False), encoding="utf-8")
    return п


def test_открыто_при_всех_трёх_источниках(модуль, tmp_path):
    состояние(tmp_path, "проба.test")
    режим, причина = модуль.решить("проба.test", разрешено_выпуском=True,
                                   корень=tmp_path)
    assert режим == модуль.ОТКРЫТ, причина
    assert причина == "", "у открытого режима причина обязана быть пустой"


def test_без_разрешения_владельца_закрыто(модуль, tmp_path):
    """Главный случай: OPEN в файле без разрешения владельца не открывает."""
    состояние(tmp_path, "проба.test", owner_authorized_open=False)
    режим, причина = модуль.решить("проба.test", разрешено_выпуском=True,
                                   корень=tmp_path)
    assert режим == модуль.ЗАКРЫТ
    assert "владелец не разрешал открытие" in причина, причина


def test_отсутствие_поля_тоже_закрывает(модуль, tmp_path):
    """Файл прежнего образца не открывает витрину молча."""
    п = состояние(tmp_path, "проба.test")
    д = json.loads(п.read_text(encoding="utf-8"))
    д.pop("owner_authorized_open")
    п.write_text(json.dumps(д, ensure_ascii=False), encoding="utf-8")
    режим, причина = модуль.решить("проба.test", разрешено_выпуском=True,
                                   корень=tmp_path)
    assert режим == модуль.ЗАКРЫТ
    assert "owner_authorized_open" in причина


@pytest.mark.parametrize("значение", ["true", "True", 1, "yes", [True], {}])
def test_разрешением_считается_только_булево(модуль, tmp_path, значение):
    """Строка «true» разрешением не является — как и у разрешения выпуска."""
    состояние(tmp_path, "проба.test", owner_authorized_open=значение)
    режим, _ = модуль.решить("проба.test", разрешено_выпуском=True,
                             корень=tmp_path)
    assert режим == модуль.ЗАКРЫТ, (
        f"значение {значение!r} открыло витрину, хотя разрешением считается "
        "только булево true")


def test_закрытое_состояние_не_требует_разрешения(модуль, tmp_path):
    """Закрытие — не привилегия: его не нужно разрешать владельцем."""
    состояние(tmp_path, "проба.test", desired_state="CLOSED",
              owner_authorized_open=False)
    режим, причина = модуль.решить("проба.test", разрешено_выпуском=True,
                                   корень=tmp_path)
    assert режим == модуль.ЗАКРЫТ
    assert "файл состояния: CLOSED" in причина, причина


def test_заголовок_модуля_совпадает_с_кодом():
    """Обещание, которое переживает механизм, — тот же дефект, что и реестр.

    Заголовок обязан называть ровно те источники, которые проверяет функция.
    """
    текст = ЧИТАТЕЛЬ.read_text(encoding="utf-8")
    шапка = текст.split('"""')[1]
    assert "ТРЁХ источников" in шапка, "заголовок больше не называет три"
    assert "owner_authorized_open" in шапка, (
        "третий источник в заголовке не назван по имени поля")
    # И код действительно его проверяет.
    тело = текст.split('"""', 2)[2]
    assert 'сырое.get("owner_authorized_open") is not True' in тело
