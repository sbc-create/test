"""REQ-EDITORIAL-RESTART-ACCEPT: приёмка перезапуска моста не даёт ложного «да».

`automation/local/after-mcp-restart.py` — единственная команда, по которой
владелец и линия SEO узнают, что перезапуск `site-factory-mcp` состоялся и
публикации можно снимать с паузы. Такая проверка обязана уметь сказать «нет» и
«не измерено»; 19.10 она этого не умела:

    измерено = bool(вывод.strip())        # любой непустой вывод = «измерено»
    перезапущен = измерено and not устарел  # нет строки про старый код = «да»

Измерено подстановкой фактического вывода `service-code-freshness.py`: при
остановленной службе («процесс не найден», «не измерено: 1») и при падении
инструмента свежести (traceback) приёмка печатала «ПЕРЕЗАПУСК СОСТОЯЛСЯ» и
возвращала 0. Опаснее всего первый случай: служба остановлена — это середина
перезапуска, и зелёная приёмка там снимает паузу с публикаций раньше времени.

Поэтому «перезапущен» требует положительного признака по каждому из трёх
пунктов, а не отсутствия плохой строки.
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_путь = КОРЕНЬ / "automation/local/after-mcp-restart.py"
_спец = importlib.util.spec_from_file_location("after_mcp_restart", _путь)
ИНСТР = importlib.util.module_from_spec(_спец)
_спец.loader.exec_module(ИНСТР)

ЗАГОЛОВОК = ("служба                         pid      запущен"
             "           код правлен       вывод\n")


def _свежесть(строка_юнита: str, *, устаревших: int = 0, не_измерено: int = 0) -> str:
    return (ЗАГОЛОВОК + f"site-factory-mcp.service       {строка_юнита}\n\n"
            f"служб с устаревшим кодом: {устаревших}; не измерено: {не_измерено}")


