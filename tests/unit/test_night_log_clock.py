"""Метка времени в журнале прогона не должна опережать часы.

Повод измеренный, 23.10, и дважды за сутки. В журнале стояли 22:10 и 22:20
при фактических 21:48 и 21:51; в сообщении соседней линии — «22:2xZ» при её
`date -u` 21:52Z. Второй раз ошибку нашла не я, а она. Метка, написанная по
памяти, выглядит как измерение, и по журналу потом судят, что когда делалось
и не оборвался ли прогон.

Проверяется чистая функция: часы подставляются, сеть и файлы не нужны.
"""
from __future__ import annotations

import datetime
import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "night-log-clock-check.py"

_с = importlib.util.spec_from_file_location("night_log_clock_check", ПУТЬ)
МОДУЛЬ = importlib.util.module_from_spec(_с)
assert _с.loader is not None
_с.loader.exec_module(МОДУЛЬ)

СЕЙЧАС = datetime.datetime(2026, 10, 23, 21, 53, tzinfo=datetime.timezone.utc)

ЖУРНАЛ = """# Журнал

| время (UTC) | взятая задача | состояние | доказательство |
| --- | --- | --- | --- |
| 21:40 | причина обрыва | выполнено | класс 20 |
| 21:48 | посадочные страницы | выполнено | файл |
| 22:20 | приёмка | выполнено | файл |

Текст рядом: выпуск соседней линии был в 22:47Z вчера, и это не метка журнала.
"""


def test_метка_позже_часов_найдена():
    плохие = МОДУЛЬ.опережающие(ЖУРНАЛ, СЕЙЧАС, запас_минут=2)
    assert [м for _, м in плохие] == ["22:20"], плохие


def test_метки_не_позже_часов_проходят():
    """Отрицательный контроль: проверка не должна ругаться на прошедшее."""
    без_будущего = ЖУРНАЛ.replace("| 22:20 |", "| 21:51 |")
    assert МОДУЛЬ.опережающие(без_будущего, СЕЙЧАС, запас_минут=2) == []


def test_время_в_тексте_рядом_не_считается_меткой():
    """Отбор только по первому столбцу таблицы.

    В тексте журнала встречаются времена чужих выпусков и прошлых суток;
    судить их по текущим часам нельзя, иначе проверка начнёт падать на
    верных записях и её выключат.
    """
    метки = МОДУЛЬ.метки(ЖУРНАЛ)
    assert [(ч, м) for _, ч, м in метки] == [(21, 40), (21, 48), (22, 20)]
    assert "22:47" not in str(метки)


def test_небольшой_запас_вперёд_допускается():
    """Запись делается в начале шага: минута-две расхождения — не ошибка."""
    журнал = ЖУРНАЛ.replace("| 22:20 |", "| 21:54 |")
    assert МОДУЛЬ.опережающие(журнал, СЕЙЧАС, запас_минут=2) == []
    assert МОДУЛЬ.опережающие(журнал, СЕЙЧАС, запас_минут=0) != []


def test_метка_после_полуночи_опережением_не_считается():
    """Журнал ведётся через полночь: «01:10» в 21:53 — следующие сутки.

    Без этого исключения проверка валила бы верные утренние записи, и это
    был бы ровно тот случай, из-за которого проверки выключают.
    """
    журнал = ЖУРНАЛ.replace("| 22:20 |", "| 01:10 |")
    assert МОДУЛЬ.опережающие(журнал, СЕЙЧАС, запас_минут=2) == []


# --- многодневные журналы --------------------------------------------------

МНОГОДНЕВНЫЙ = """# Журнал оператора

## 21.10

| время (UTC) | что | состояние |
| --- | --- | --- |
| 22:53 | вечерний разбор | выполнено |
| 23:02 | выпуск | выполнено |

## 22.10

| 22:06 | ночная доставка | выполнено |

## 23.10

| 21:40 | причина обрыва | выполнено |
| 23:30 | это будущее | выполнено |
"""


def test_метки_прошлых_суток_не_судятся_по_сегодняшним_часам():
    """Повод измеренный: первая версия дала соседней линии 5 отказов из 41
    метки, и все пять были в разделах за 21 и 22 октября. Проверка, которая
    ругается на верные записи, будет выключена — это хуже её отсутствия."""
    плохие = МОДУЛЬ.опережающие(МНОГОДНЕВНЫЙ, СЕЙЧАС, запас_минут=2,
                                имя_файла="NIGHT_20261022.md")
    assert [м for _, м in плохие] == ["23:30"], плохие


def test_судятся_только_метки_сегодняшнего_раздела():
    судимые = МОДУЛЬ.метки(МНОГОДНЕВНЫЙ, имя_файла="NIGHT_20261022.md",
                           сегодня=СЕЙЧАС)
    assert [(ч, м) for _, ч, м in судимые] == [(21, 40), (23, 30)]
    # Без указания часов — все метки файла, это другой вопрос.
    assert len(МОДУЛЬ.метки(МНОГОДНЕВНЫЙ)) == 5


def test_дата_берётся_из_имени_файла_когда_заголовков_нет():
    """Однодневный журнал без заголовков с датой: судить его по имени файла —
    единственный способ не пропустить и не наврать."""
    журнал = "| 23:30 | будущее | выполнено |\n"
    вчера = МОДУЛЬ.опережающие(журнал, СЕЙЧАС, запас_минут=2,
                               имя_файла="NIGHT_RUN_20261022.md")
    сегодня = МОДУЛЬ.опережающие(журнал, СЕЙЧАС, запас_минут=2,
                                 имя_файла="NIGHT_RUN_20261023.md")
    assert вчера == [], вчера
    assert [м for _, м in сегодня] == ["23:30"], сегодня


def test_порядок_день_месяц_в_заголовке():
    """«## 22.10» — это 22 октября, а не 10 февраля: в сети принят порядок
    день.месяц, и перепутанный порядок молча снял бы проверку с раздела."""
    assert МОДУЛЬ.дата_заголовка("## 22.10", 2026) == (10, 22)
    assert МОДУЛЬ.дата_заголовка("## 2026-10-22", 2026) == (10, 22)
    assert МОДУЛЬ.дата_заголовка("## Итоги ночи", 2026) is None


def test_утренние_метки_вчерашнего_раздела_судятся():
    """Ночь переходит полночь, а раздел остаётся вчерашним.

    Журнал ночного прогона называется по дате НАЧАЛА ночи. После полуночи его
    раздел перестаёт быть «сегодняшним», и проверка переставала судить все
    метки сразу — молча. Ровно так 24.10 в 00:04Z мимо неё прошли метки 00:25
    и 00:48, написанные вперёд часов; их пришлось исправлять по времени
    коммитов.
    """
    текст = ("| время (UTC) | взятая задача |\n"
             "| --- | --- |\n"
             "| 23:57 | строка вечера |\n"
             "| 00:48 | строка после полуночи, вперёд часов |\n")
    сейчас = datetime.datetime(2026, 10, 24, 0, 5,
                              tzinfo=datetime.timezone.utc)
    плохие = МОДУЛЬ.опережающие(текст, сейчас, 2,
                                  имя_файла="NIGHT_RUN_20261023.md")
    assert [м for _, м in плохие] == ["00:48"], плохие


def test_вечерние_метки_вчерашнего_раздела_после_полуночи_не_судятся():
    """Метка 23:57 в 00:05 следующих суток — прошлое, а не опережение."""
    текст = ("| 23:57 | вечер той же ночи |\n"
             "| 21:40 | ранний вечер |\n")
    сейчас = datetime.datetime(2026, 10, 24, 0, 5,
                              tzinfo=datetime.timezone.utc)
    assert МОДУЛЬ.опережающие(текст, сейчас, 2,
                                имя_файла="NIGHT_RUN_20261023.md") == []


def test_метка_позапрошлой_ночи_не_судится():
    """Журнал двухдневной давности сравнивать с сегодняшними часами нельзя."""
    текст = "| 09:30 | строка позапрошлой ночи |\n"
    сейчас = datetime.datetime(2026, 10, 24, 0, 5,
                              tzinfo=datetime.timezone.utc)
    assert МОДУЛЬ.опережающие(текст, сейчас, 2,
                                имя_файла="NIGHT_RUN_20261022.md") == []


def test_ноль_судимых_метк_не_выдаётся_за_отсутствие_нарушений(tmp_path):
    """Сторож обязан отличать «не измерено» от «нарушений нет».

    24.10 в 00:04Z он напечатал «опережающих 0» и вернул ноль, не рассудив ни
    одной из сорока метк: после полуночи раздел журнала перестал быть
    сегодняшним. Сторож класса 22 сработал по классу 24.
    """
    ф = tmp_path / "NIGHT_RUN_20261020.md"
    ф.write_text("| 09:30 | позапрошлая ночь |\n| 10:15 | она же |\n",
                 encoding="utf-8")
    assert МОДУЛЬ.main(["--file", str(ф)]) == 3


def test_файл_без_метк_вовсе_не_считается_неизмеренным(tmp_path):
    """Нечего судить и нечего было — это не отказ, а пустой файл."""
    ф = tmp_path / "NIGHT_RUN_20261024.md"
    ф.write_text("# Заголовок без таблицы\n\nтекст без метк\n",
                 encoding="utf-8")
    assert МОДУЛЬ.main(["--file", str(ф)]) == 0
