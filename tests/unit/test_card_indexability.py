"""Карточка: один canonical и режим индексации.

Повод. Карточка — главная индексируемая страница витрины, и до 12.10 приёмка
проверяла у неё код, H1, постер, число серий и совпадение canonical со слагом.
Двух норм не было, а цена ошибки на карточке выше, чем на любом разделе:

* **один canonical.** На разделах проверка стоит (`норма_одного_canonical`), и
  повод к ней подробно описан в `test_single_canonical_norm.py`: canonical
  ставят два источника — оформление витрины и общий SEO-слой. На карточке та
  же опасность, а проверки не было: все остальные чтения берут canonical
  ПЕРВЫМ совпадением, то есть второй тег для них не существует;
* **режим индексации.** Случайный `noindex` на карточке убирает из индекса
  самое ценное, и по коду 200 этого не видно. Проверяются ОБА слоя — заголовок
  `X-Robots-Tag` и мета `robots`, — потому что запрет может стоять в любом: у
  сети уже было ровно это (D150, D166, D187 — `/healthz` отдавал
  `index, follow` от приложения и `noindex, nofollow` от nginx одновременно).

Сеть не используется: `достать` подменяется. Проверяется, какие шаги приёмки
появляются и какой у них вердикт.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

СЛАГ = "test-title"
ГЛАВНАЯ = f'<a href="https://x.example/title/{СЛАГ}/">карточка</a>'


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


def карточка(*, canonical_тегов: int = 1, robots_мета: str = "index, follow",
             robots_заголовок: str = "") -> tuple[str, dict[str, str]]:
    теги = "".join(
        f'<link rel="canonical" href="https://x.example/title/{СЛАГ}/">'
        for _ in range(canonical_тегов))
    тело = (f"<html><head>{теги}"
            + (f'<meta name="robots" content="{robots_мета}">'
               if robots_мета else "")
            + f"</head><body><h1>Название</h1>"
              f'<img src="https://poster.cdnvideohub.com/x.webp">'
              f"</body></html>")
    заг = {"итоговый-адрес": f"https://x.example/title/{СЛАГ}/"}
    if robots_заголовок:
        заг["x-robots-tag"] = robots_заголовок
    return тело, заг


@pytest.fixture()
def прогон(monkeypatch):
    """Возвращает функцию: тело и заголовки карточки → список шагов приёмки."""
    м = _модуль()

    def запустить(тело_карточки: str, заг_карточки: dict[str, str]):
        def поддельный(url, таймаут=45):
            if url.rstrip("/").endswith(СЛАГ):
                return "200", тело_карточки, dict(заг_карточки)
            # Всё остальное витрина «не отдаёт»: нас интересует только
            # карточка, а прочие шаги приёмки в этом тесте не проверяются.
            return "", "", {"итоговый-адрес": url}
        monkeypatch.setattr(м, "достать", поддельный)
        monkeypatch.setattr(
            м, "карточки",
            lambda тело, домен: [f"https://x.example/title/{СЛАГ}/"])
        # Пагинация и фильтры здесь не предмет: их пробы вернут пустые ответы.
        отчёт = м.проверить("x.example")
        return [(п["что"], п["ок"], п["подробно"]) for п in отчёт["проверки"]]
    return запустить


def _шаг(шаги, подстрока):
    найдено = [ш for ш in шаги if подстрока in ш[0]]
    assert найдено, f"шага с {подстрока!r} нет; есть: {[ш[0] for ш in шаги]}"
    return найдено[0]


def test_исправная_карточка_проходит_обе_новые_нормы(прогон):
    шаги = прогон(*карточка())
    assert _шаг(шаги, f"один canonical [карточка {СЛАГ[:20]}")[1] is True
    assert _шаг(шаги, "индексируется")[1] is True


def test_два_canonical_на_карточке_это_отказ(прогон):
    """Второй тег делает выбор адреса непредсказуемым."""
    шаги = прогон(*карточка(canonical_тегов=2))
    assert _шаг(шаги, "один canonical [карточка")[1] is False


def test_noindex_в_мете_карточки_это_отказ(прогон):
    """Код 200 этого не показывает, а из индекса уходит самое ценное."""
    шаги = прогон(*карточка(robots_мета="noindex, follow"))
    имя, ок, подробно = _шаг(шаги, "индексируется")
    assert ок is False
    assert "ЗАКРЫТА" in подробно


def test_noindex_в_заголовке_карточки_тоже_отказ(прогон):
    """Запрет может стоять в любом слое — проверяются оба (D150, D166, D187)."""
    шаги = прогон(*карточка(robots_заголовок="noindex, nofollow"))
    assert _шаг(шаги, "индексируется")[1] is False


def test_противоречивая_пара_слоёв_считается_запретом(прогон):
    """`index` от приложения и `noindex` от nginx — ровно случай D166.

    Полагаться на то, что обходчик выберет «правильный», нельзя, поэтому пара
    читается как запрет и даёт отказ.
    """
    шаги = прогон(*карточка(robots_мета="index, follow",
                            robots_заголовок="noindex, nofollow"))
    имя, ок, подробно = _шаг(шаги, "индексируется")
    assert ок is False
    assert "noindex" in подробно


def test_отсутствие_обоих_слоёв_запретом_не_считается(прогон):
    """Нет ни меты, ни заголовка — страница открыта по умолчанию."""
    шаги = прогон(*карточка(robots_мета=""))
    assert _шаг(шаги, "индексируется")[1] is True


def test_новые_нормы_не_спрашиваются_у_неответившей_карточки(monkeypatch):
    """Код не 200 — проверять нечего, и зелёных строк быть не должно.

    Иначе молчащая карточка набирала бы пройденные нормы, а это ровно та
    ошибка «не измерено читается как норма соблюдена», которую в этом же
    инструменте пришлось править для разделов пагинации.
    """
    м = _модуль()
    monkeypatch.setattr(м, "достать",
                        lambda url, таймаут=45: ("", "", {"итоговый-адрес": url}))
    monkeypatch.setattr(м, "карточки",
                        lambda тело, домен: [f"https://x.example/title/{СЛАГ}/"])
    отчёт = м.проверить("x.example")
    шаги = [(п["что"], п["ок"], п["подробно"]) for п in отчёт["проверки"]]
    assert [ш for ш in шаги if "индексируется" in ш[0]] == []
    assert [ш for ш in шаги if "один canonical [карточка" in ш[0]] == []
