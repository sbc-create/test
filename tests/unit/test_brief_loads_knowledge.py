"""Исполнитель действительно получает три уровня знаний, а не ссылки на них.

Задание владельца прямо предупреждает: «Само существование файлов ещё не
означает, что исполнитель ими пользуется». Поэтому здесь проверяется не
наличие файлов, а ПОВЕДЕНИЕ инструктажа: что он выдаёт, на чём отказывает и
что печатает про следующий шаг.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
СПИСОК = КОРЕНЬ / "config" / "active-domains.json"

_сп = importlib.util.spec_from_file_location(
    "brief", КОРЕНЬ / "automation" / "local" / "brief.py")
брифинг = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(брифинг)


@pytest.fixture(scope="module")
def домены() -> list[str]:
    return [з["domain"] for з in json.loads(
        СПИСОК.read_text(encoding="utf-8"))["domains"]]


# --- три уровня существуют у КАЖДОГО активного домена --------------------

def test_у_каждого_домена_все_три_уровня_на_месте(домены):
    нет = {д: брифинг.чего_нет(д) for д in домены if брифинг.чего_нет(д)}
    assert not нет, нет


def test_уровни_это_разные_файлы(домены):
    """Паспорт, подменённый файлом семейства, не паспорт."""
    for д in домены:
        п = брифинг.уровни(д)
        assert len({п["сеть"], п["семейство"], п["паспорт"]}) == 3, д


def test_паспорт_называет_свой_домен(домены):
    плохие = [д for д in домены
              if д not in брифинг.уровни(д)["паспорт"].read_text(
                  encoding="utf-8")]
    assert not плохие, плохие


def test_паспорт_ссылается_на_правила_своего_семейства(домены):
    активные = {з["domain"]: з for з in json.loads(
        СПИСОК.read_text(encoding="utf-8"))["domains"]}
    плохие = []
    for д in домены:
        текст = брифинг.уровни(д)["паспорт"].read_text(encoding="utf-8")
        if f"family/{активные[д]['family']}.md" not in текст:
            плохие.append(д)
    assert not плохие, плохие


def test_правила_сети_не_превращаются_в_историю():
    """Исполнителю даются правила и ссылки, а не вся история сети.

    Задание прямо запрещает загружать каждому исполнителю всю историю:
    поэтому у общего уровня есть предел размера, и он проверяется.
    """
    текст = брифинг.СЕТЬ.read_text(encoding="utf-8")
    assert len(текст) < 12000, len(текст)
    assert "docs/RECURRING_FAILURES.md" in текст, "нет ссылки на доказательства"


# --- поведение инструктажа ------------------------------------------------

def test_инструктаж_выдаёт_содержимое_всех_уровней(capsys, домены):
    код = брифинг.main(["--domain", домены[0]])
    вывод = capsys.readouterr().out
    assert код == 0
    for имя in ("сеть", "семейство", "паспорт"):
        assert f"=== УРОВЕНЬ: {имя}" in вывод, имя
    # содержимое, а не только заголовки
    assert "Что считается результатом" in вывод
    assert "Паспорт домена" in вывод


def test_короткий_инструктаж_называет_этап_и_следующий_шаг(capsys, домены):
    брифинг.main(["--domain", домены[0], "--short"])
    вывод = capsys.readouterr().out
    assert "этап" in вывод
    assert "следующий шаг:" in вывод
    assert "=== УРОВЕНЬ:" not in вывод, "короткий режим вывалил всё"


def test_неактивный_домен_получает_отказ(capsys):
    код = брифинг.main(["--domain", "никакой.test"])
    assert код == 1
    assert "не в списке активных" in capsys.readouterr().err


def test_домен_в_ожидании_замены_отказывается_с_причиной(capsys):
    ждут = json.loads(СПИСОК.read_text(encoding="utf-8"))[
        "awaiting_replacement"]
    код = брифинг.main(["--domain", ждут[0]["domain"]])
    assert код == 1
    assert "ОЖИДАЕТ ЗАМЕНЫ" in capsys.readouterr().err


def test_отсутствующий_уровень_это_отказ_а_не_молчание(capsys, monkeypatch,
                                                       домены, tmp_path):
    """Исполнитель без правил семейства опаснее неначавшего."""
    настоящие = брифинг.уровни

    def подмена(домен):
        п = dict(настоящие(домен))
        п["семейство"] = tmp_path / "нет.md"
        return п

    monkeypatch.setattr(брифинг, "уровни", подмена)
    код = брифинг.main(["--domain", домены[0]])
    assert код == 2
    assert "ОТСУТСТВУЮТ уровни знаний" in capsys.readouterr().err


# --- следующий шаг --------------------------------------------------------

def test_следующий_шаг_пропускает_снятое_и_ждущее():
    очередь = {"tasks": [
        {"id": "Q-1", "state": "снято", "title": "снятая"},
        {"id": "Q-2", "state": "ожидание", "title": "ждёт"},
        {"id": "Q-3", "state": "исследовано", "title": "рабочая"},
    ]}
    assert брифинг.следующий_шаг(очередь).startswith("Q-3")


def test_когда_всё_ждёт_называется_блокер():
    очередь = {"tasks": [
        {"id": "Q-1", "state": "заблокировано", "title": "ждёт",
         "blocked_by": "пароли баз у владельца"},
    ]}
    шаг = брифинг.следующий_шаг(очередь)
    assert "все задачи ждут" in шаг
    assert "пароли баз" in шаг


def test_ждущая_задача_без_блокера_называется_прямо():
    очередь = {"tasks": [{"id": "Q-1", "state": "ожидание", "title": "x"}]}
    assert "причина не названа" in брифинг.следующий_шаг(очередь)


def test_пустая_очередь_не_выдаётся_за_работу():
    assert брифинг.следующий_шаг({"tasks": []}) == "очередь пуста"
