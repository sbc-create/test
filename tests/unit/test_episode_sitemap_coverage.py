def test_непрочитанная_карта_не_читается_как_успех(сеть):
    _настроить(сеть, ["/anime/rabota/season/1/episode/1"], [(1, 1)])
    del сеть["https://x.test/sitemap/episodes.xml"]
    итог = инс.проверить("x.test", (1,))
    assert итог["измерено"] is False
    assert "НЕ ИЗМЕРЕНО" in итог["проблемы"][0]


def test_адреса_других_работ_в_счёт_не_идут(сеть):
    """Префикс слага обязан быть точным, иначе `rabota-2` зачтётся `rabota`."""
    сеть["https://x.test/sitemap.xml"] = индекс(["episodes.xml"])
    сеть["https://x.test/sitemap/episodes.xml"] = urlset(
        ["/anime/rabota-2/season/1/episode/1"])
    сеть["https://x.test/sitemap/titles.xml"] = urlset(
        ["/anime/rabota", "/anime/rabota-2"])
    сеть["https://x.test/anime/rabota"] = страница("rabota", [(1, 1)])
    итог = инс.проверить("x.test", (1,))
    assert итог["работы"][0]["итог"] == "НЕ НАЗВАНЫ"
    assert итог["работы"][0]["в_карте"] == 0


