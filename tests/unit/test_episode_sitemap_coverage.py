"""Сверка МНОЖЕСТВ адресов серий: страница домена против его же карты.

Ошибка здесь дороже отсутствия проверки: «ок» у домена, который не назвал
поисковику существующие страницы, закрыл бы MOD-103 без исправления. Поэтому
проверяются обе стороны — и находка, и её отсутствие там, где терять нечего.
"""
import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "episode_sitemap_coverage",
    КОРЕНЬ / "automation" / "local" / "episode-sitemap-coverage.py")
инс = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(инс)


def индекс(части):
    тело = "".join(f"<sitemap><loc>https://x.test/sitemap/{и}</loc></sitemap>"
                   for и in части)
    return f"<sitemapindex>{тело}</sitemapindex>"


def urlset(адреса):
    тело = "".join(f"<url><loc>https://x.test{а}</loc></url>" for а in адреса)
    return f"<urlset>{тело}</urlset>"


def страница(слаг, серии):
    ссылки = "".join(
        f'<a href="/anime/{слаг}/season/{с}/episode/{э}">серия</a>'
        for с, э in серии)
    return f"<html><body>{ссылки}</body></html>"


@pytest.fixture()
def сеть(monkeypatch):
    таблица = {}

    def достать(адрес, таймаут=240, кешировать=False):
        return таблица.get(адрес)

    monkeypatch.setattr(инс, "достать", достать)
    return таблица


def _настроить(сеть, серии_карты, серии_страницы, слаги=("rabota",)):
    сеть["https://x.test/sitemap.xml"] = индекс(["episodes.xml"])
    сеть["https://x.test/sitemap/episodes.xml"] = urlset(серии_карты)
    сеть["https://x.test/sitemap/titles.xml"] = urlset(
        [f"/anime/{с}" for с in слаги])
    сеть["https://x.test/anime/rabota"] = страница("rabota", серии_страницы)


def test_страница_печатает_серию_которой_в_карте_нет(сеть):
    """Тот самый дефект: существующая страница поисковику не названа."""
    _настроить(сеть, ["/anime/rabota/season/1/episode/1"],
               [(1, 1), (1, 2), (1, 3)])
    итог = инс.проверить("x.test", (1,))
    assert итог["работы"][0]["итог"] == "НЕ НАЗВАНЫ"
    assert итог["работы"][0]["не_названы"] == 2
    assert "не названы 2" in итог["проблемы"][0]


def test_совпадение_множеств_это_ок(сеть):
    _настроить(сеть, ["/anime/rabota/season/1/episode/1",
                      "/anime/rabota/season/1/episode/2"],
               [(1, 1), (1, 2)])
    итог = инс.проверить("x.test", (1,))
    assert итог["работы"][0]["итог"] == "ок"
    assert итог["проблемы"] == []


def test_равные_числа_при_разном_составе_не_проходят(сеть):
    """Условие, которого не даёт сверка чисел: по счёту 2 = 2, по составу нет."""
    _настроить(сеть, ["/anime/rabota/season/1/episode/1",
                      "/anime/rabota/season/9/episode/9"],
               [(1, 1), (1, 2)])
    итог = инс.проверить("x.test", (1,))
    assert итог["работы"][0]["итог"] == "НЕ НАЗВАНЫ"
    assert итог["работы"][0]["не_названы"] == 1
    assert итог["работы"][0]["лишние"] == 1


def test_работа_без_серий_на_странице_в_дефект_не_идёт(сеть):
    """Отрицательный контроль метода: там, где терять нечего, находки нет."""
    _настроить(сеть, [], [])
    итог = инс.проверить("x.test", (1,))
    assert итог["работы"][0]["итог"] == "нечего терять"
