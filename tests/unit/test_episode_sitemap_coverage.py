# --- срок годности кеша ----------------------------------------------------
#
# Измерено 22.10 в 05:4xZ: кеш карты держал файлы от 21.10 13:02 (17 часов), и
# сверка живых страниц шла против вчерашней карты. Для приёмки выпуска это
# означает отказ годному выпуску или приём негодного, поэтому срок закреплён
# проверками с обеих сторон границы.

def test_свежий_кеш_годен(tmp_path):
    файл = tmp_path / "ф.txt"
    файл.write_text("x", encoding="utf-8")
    assert инс.кеш_годен(файл, срок=900) is True


def test_вчерашний_кеш_негоден(tmp_path):
    файл = tmp_path / "ф.txt"
    файл.write_text("x", encoding="utf-8")
    import os
    вчера = файл.stat().st_mtime - 17 * 3600
    os.utime(файл, (вчера, вчера))
    assert инс.кеш_годен(файл, срок=900) is False


def test_ровно_на_границе_кеш_негоден(tmp_path):
    """Граница включается в негодность: равенство читается как «истёк»."""
    файл = tmp_path / "ф.txt"
    файл.write_text("x", encoding="utf-8")
    м = файл.stat().st_mtime
    assert инс.кеш_годен(файл, срок=900, сейчас=м + 900) is False
    assert инс.кеш_годен(файл, срок=900, сейчас=м + 899.5) is True


def test_отсутствующего_файла_кеша_не_существует(tmp_path):
    assert инс.кеш_годен(tmp_path / "нет.txt", срок=900) is False


def test_срок_по_умолчанию_меньше_часа():
    """Кеш живёт заметно меньше промежутка между выпусками."""
    assert 0 < инс.СРОК_КЕША_С <= 3600

