"""REQ-CELL-TEMPLATE-VERSION-PUBLIC: рядом с /healthz был открыт второй путь.

Правка R-10 закрыла публичный `/healthz`. Измерено 2026-10-18
(`automation/local/healthz-exposure.py --path /__template_version`): маршрут
`/__template_version` публичен у ВСЕХ 25 живых витрин сети и отдаёт 14–34
поля, из них 6–14 описывают устройство машины — включая `artifact_path` и
`release_dir`, то есть настоящие пути в файловой системе. Закрыть один
служебный путь и оставить рядом равноценный — это закрыть дверь при открытом
окне.

Разделение безопасно, и это измерено, а не предположено: подробность читает
фабрика по петле (`factory/cell/content.py`, `ПУТЬ_ОПРОСА`), публичных
вызовов в инструментах репозитория нет.

Проверка читает ИСХОДНИК обработчика: поднимать сервер ради этого не нужно, а
падать она обязана до выпуска.
"""
from __future__ import annotations

from pathlib import Path

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")

#: Поля, которые описывают устройство машины или содержимое выпуска.
ВНУТРЕННИЕ = ("artifact_sha256", "code_file_sha256", "entrypoint_sha256",
              "artifact_path", "release_dir", "runtime_commit",
              "source_commit", "catalog_revision", "details_catalog_revision",
              "build_id", "profile")


def _кусок() -> str:
    начало = ТЕКСТ.index('if путь == "/__template_version":')
    конец = ТЕКСТ.index('if путь == "/healthz":', начало)
    return ТЕКСТ[начало:конец]


def _публичная_часть() -> str:
    кусок = _кусок()
    начало = кусок.index("if not вызов_изнутри(self.headers):")
    return кусок[начало:кусок.index("return self._отдать", начало)]


def test_публичный_ответ_отделён_от_подробного():
    кусок = _кусок()
    assert "вызов_изнутри(self.headers)" in кусок, (
        "публичный ответ не отделён: маршрут отдаёт манифест целиком")


def test_в_публичном_ответе_нет_полей_об_устройстве():
    публичный = _публичная_часть()
    плохие = [п for п in ВНУТРЕННИЕ if f'"{п}"' in публичный]
    assert not плохие, f"в публичном ответе поля об устройстве: {плохие}"


def test_публичный_ответ_называет_версию_шаблона():
    """Маршрут назван про версию шаблона — её он и обязан отдавать.

    Иначе «починка» выродилась бы в пустой ответ, и маршрут перестал бы
    отвечать на свой же вопрос.
    """
    публичный = _публичная_часть()
    assert '"template"' in публичный and '"design_version"' in публичный


def test_подробность_для_петли_осталась():
    """Отрицательный контроль: фабрика опрашивает этот путь по петле."""
    кусок = _кусок()
    for поле in ("core_runtime", "family_template", "catalog_revision",
                 "details_catalog_revision", "catalog_details_skew"):
        assert f'свод["{поле}"]' in кусок, f"поле {поле} пропало из подробного ответа"


def test_опознание_идёт_через_общую_функцию():
    """Условие одно на оба служебных пути: копии разошлись бы при правке."""
    кусок = _кусок()
    assert "вызов_изнутри(self.headers)" in кусок
    assert 'хост_запроса' not in кусок, (
        "в обработчике снова появилась копия условия вместо общей функции")
