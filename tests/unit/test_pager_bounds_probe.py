"""Границы листалки: проверяются оба исхода и оба предела измерения.

Инструмент читает живые витрины, поэтому проверяется не он целиком, а его
разбор: именно в разборе и сидели два изъяна первого прогона.

1. **Форма адреса карточки.** Признак знал только `/title/<slug>` и напечатал
   «карточек 0» про страницу Yummy с 24 карточками на `/anime/<slug>`. Ноль
   утверждает «страница пуста», а нераспознанная форма означает «мерить
   нечем» — выдавать второе за первое нельзя.
2. **Отсутствие раздела.** `?page=99999` отдаёт 404 и там, где раздела нет
   вовсе, — то есть отсутствие страницы читалось как исправная листалка.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "pager-bounds-probe.py")


def _модуль():
    спец = importlib.util.spec_from_file_location("pager_bounds_probe", ПУТЬ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


МОД = _модуль()


def test_форма_title_считается():
    тело = '<a href="/title/alpha">A</a><a href="/title/beta">B</a>'
    assert МОД.карточек(тело) == (2, "/title/")


def test_форма_anime_считается_тоже():
    """Вторая форма — та, на которой признак и ослеп."""
    тело = '<a href="/anime/alpha">A</a><a href="/anime/beta">B</a>'
    assert МОД.карточек(тело) == (2, "/anime/")


def test_нераспознанная_форма_это_не_ноль():
    """None и 0 — разные утверждения, и путать их нельзя."""
    тело = '<a href="/film/alpha">A</a><a href="/serial/beta">B</a>'
    assert МОД.карточек(тело) is None


def test_страница_без_карточек_это_ноль_а_не_none():
    """Обратная сторона: пустая страница ИЗВЕСТНОЙ формы — именно ноль.

    Если бы None возвращался и здесь, пустая индексируемая страница перестала
    бы быть находкой.
    """
    тело = '<a href="/title/alpha">A</a>'
    assert МОД.карточек(тело) == (1, "/title/")
    # Ни одной ссылки известной формы на странице нет вовсе.
    assert МОД.карточек("<p>ничего</p>") is None


def test_повторная_ссылка_не_удваивает_счёт():
    """Карточка в каталоге встречается дважды (постер и название)."""
    тело = ('<a href="/anime/alpha"><img></a><a href="/anime/alpha">A</a>'
            '<a href="/anime/beta">B</a>')
    assert МОД.карточек(тело) == (2, "/anime/")


def test_параметры_и_якорь_не_создают_лишних_карточек():
    тело = ('<a href="/title/alpha">A</a><a href="/title/alpha?x=1">A</a>'
            '<a href="/title/alpha#top">A</a>')
    сколько, _ = МОД.карточек(тело)
    assert сколько == 1, "параметр и якорь — та же карточка"


def test_режим_индексации_читается_из_обоих_мест():
    """Заголовок и meta — два факта, и оба называются."""
    тело = '<meta name="robots" content="noindex, follow">'
    р = МОД.режим(тело, {"x-robots-tag": "index, follow"})
    assert "X-Robots-Tag: index, follow" in р
    assert "meta: noindex, follow" in р
    assert not МОД.индексируется(р), "noindex где-либо закрывает страницу"


def test_режим_не_объявлен_называется_прямо():
    assert МОД.режим("", {}) == "режим не объявлен"
    # Не объявлен — значит индексируется по умолчанию, и это надо говорить.
    assert МОД.индексируется(МОД.режим("", {}))


def test_зарезервированные_имена_не_считаются_витринами():
    """RFC 6761: `.test` и `.localhost` — не домены сети."""
    имена = МОД.домены()
    assert all(not и.endswith((".test", ".localhost")) for и in имена), имена


def test_предел_за_которым_страниц_нет_назван_числом_а_не_словом():
    """«Очень большой номер» непроверяем; 99999 — проверяемое утверждение."""
    assert МОД.ЗА_ПРЕДЕЛОМ == 99999
    текст = ПУТЬ.read_text(encoding="utf-8")
    assert "62 978" in текст, "основание предела должно быть названо в коде"
