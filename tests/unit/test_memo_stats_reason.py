"""Причина промаха называется по числам, и порог возвратов не на глаз.

Инструмент `automation/host/memo-stats.py` печатает по каждой памяти витрины
одну строку с выводом «что лечить». Вывод должен следовать замеру, а не
настроению: 30.10 у памяти каталога было 3145 вытеснений и 12 возвратов — то
есть поднимать предел бессмысленно, и строка обязана говорить именно это. У
памяти главной в тех же условиях вытеснения шли вместе с возвратами, и предел
действительно мешал.
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ФАЙЛ = КОРЕНЬ / "automation" / "host" / "memo-stats.py"


def _модуль():
    spec = importlib.util.spec_from_file_location("memo_stats", ФАЙЛ)
    м = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(м)
    return м


@pytest.fixture(scope="module")
def м():
    return _модуль()


def test_много_вытеснений_и_мало_возвратов_предел_не_поднимать(м):
    причина = м.главная_причина({"вытеснено": 3145, "вернувшихся": 12, "устарело": 0})
    assert "поднимать незачем" in причина, причина
    assert "12 из 3145" in причина


def test_возвраты_сравнимы_с_вытеснениями_предел_мешает(м):
    причина = м.главная_причина({"вытеснено": 100, "вернувшихся": 40, "устарело": 0})
    assert "спрашивают снова" in причина, причина


def test_истечение_срока_называется_сроком(м):
    assert м.главная_причина({"вытеснено": 0, "вернувшихся": 0, "устарело": 24}) == "срок"


def test_без_промахов_причины_нет(м):
    assert м.главная_причина({"вытеснено": 0, "вернувшихся": 0, "устарело": 0}) == "—"


def test_доля_попаданий_считается_от_обращений(м):
    assert м.доля_попаданий({"попаданий": 19, "промахов": 78}) == "20%"
    assert м.доля_попаданий({"попаданий": 0, "промахов": 0}) == "—"


def test_нет_счётчиков_в_сводке_это_не_пустой_перечень_а_отказ(м):
    """Витрина без сводки памяти не должна выглядеть как витрина без промахов."""
    assert м.строки_памяти({"totals": {}}) == []
    assert м.строки_памяти({"память": [{"память": "главная"}]}) == [{"память": "главная"}]
