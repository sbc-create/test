"""Панель разделов вынута из потока — иначе открытое меню пусто.

ПОВОД, названный приёмкой 27.10 на `zonafilm12.site`. Кнопка «Меню разделов»
нажималась, `aria-expanded` становился `true`, а в экране не было НИ ОДНОГО
пункта: на 390 у всех восьми ссылок left 279, right 645 при ширине экрана
390, у четырёх top отрицательный. На 1024 то же.

ПРИЧИНА. У строки шапки `flex-wrap:nowrap` и жёсткая высота. Панель была
объявлена как `flex:1 0 100%` — это расчёт на перенос на свою строку,
которого при `nowrap` не происходит: панель встаёт в ту же строку справа от
кнопок и обрезается высотой.

ЧТО ЭТОТ ТЕСТ ЛОВИТ. Прежнее сломанное поведение: панель в потоке при
`nowrap`-строке. И проходит на исправленном: панель вынута абсолютным
позиционированием, как у соседней витрины той же линии.

ПОЧЕМУ ТЕСТ ЕСТЬ ВООБЩЕ. Проверка, требовавшая именно этого, в парке была —
`checks/header_fit.py`. Я снял её, решив, что она «закрепляет разметку одной
витрины». Она закрепляла требование, без которого ящик не работает вовсе.
Снятие было ошибкой, и этот тест возвращает защиту на уровень парка.
"""
from __future__ import annotations

import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ИМЕНА = ("lords-frontend.py", "animedia-frontend.py", "animego-frontend.py")


def _рантаймы() -> list[pathlib.Path]:
    найдено = []
    корень = КОРЕНЬ / "var" / "site-repos"
    if not корень.is_dir():
        return найдено
    for репо in sorted(корень.iterdir()):
        for имя in ИМЕНА:
            ф = репо / "src" / имя
            if not ф.is_file():
                continue
            try:
                т = ф.read_text(encoding="utf-8")
            except (OSError, PermissionError):
                continue
            if ".zhd__n{" in т and ".zhd__in{" in т:
                найдено.append(ф)
    return найдено


РАНТАЙМЫ = _рантаймы()


def _правила(текст: str, селектор: str) -> list[str]:
    экран = re.escape(селектор)
    return re.findall(r"(?<![\w-])" + экран + r"\{[^}]*\}", текст)


def _строка_без_переноса(текст: str) -> bool:
    """Есть ли у строки шапки запрет переноса — тогда панель обязана быть
    вынута из потока."""
    return any("flex-wrap:nowrap" in п for п in _правила(текст, ".zhd__in"))


def test_рантаймы_нашлись():
    """Пустой перечень превратил бы остальное в молчаливое «ок»."""
    assert len(РАНТАЙМЫ) >= 10, [str(п) for п in РАНТАЙМЫ]


@pytest.mark.parametrize("путь", РАНТАЙМЫ, ids=lambda п: п.parts[-3])
def test_выпадающая_панель_вынута_из_потока(путь):
    """Правило, которое ловит прежнее сломанное поведение.

    Панель считается выпадающей, если она скрыта и показывается классом
    `is-open`. У такой панели при `nowrap`-строке обязано быть
    `position:absolute` — иначе она встанет в строку шапки и обрежется.
    """
    текст = путь.read_text(encoding="utf-8")
    if not _строка_без_переноса(текст):
        pytest.skip("строка шапки переносится — панель может лежать в потоке")
    выпадающие = [п for п in _правила(текст, ".zhd__n")
                  if "display:none" in п and "flex-direction:column" in п]
    if not выпадающие:
        # НЕ «всё в порядке», а «этим тестом не проверено». Колоночная
        # выпадающая панель объявлена сегодня у двух витрин Zona; у
        # остальных тринадцати устройство другое, и я его не разбирал.
        # Расширять шаблон вслепую — значит ловить здоровые витрины.
        # Парковую гарантию даёт поведенческая проверка
        # automation/local/header-nav-reach.py: она открывает меню и меряет,
        # что видно, независимо от того, как витрина это устроила.
        pytest.skip("колоночной выпадающей панели нет; поведенческую проверку "
                    "даёт automation/local/header-nav-reach.py")
    беды = []
    for п in выпадающие:
        if "position:absolute" not in п:
            беды.append("панель в потоке при nowrap-строке: " + п[:160])
        elif "top:100%" not in п:
            беды.append("панель не привязана к низу шапки: " + п[:160])
    assert not беды, беды


def test_правило_ловит_прежнее_поведение():
    """Доказательство, что проверка не пустая: прежний текст её ВАЛИТ.

    Без этого теста легко написать условие, которое проходит всегда, — и
    именно так я уже ошибся сегодня с порогами по длине текста.
    """
    сломано = (".zhd__in{display:flex;flex-wrap:nowrap;height:56px}\n"
               ".zhd__n{display:none;flex:1 0 100%;order:4;"
               "flex-direction:column;overflow-y:auto}\n"
               ".zhd__n.is-open{display:flex}")
    assert _строка_без_переноса(сломано)
    выпадающие = [п for п in _правила(сломано, ".zhd__n")
                  if "display:none" in п and "flex-direction:column" in п]
    assert выпадающие, "образец сломанного не распознан как выпадающая панель"
    assert all("position:absolute" not in п for п in выпадающие), (
        "образец сломанного прошёл бы проверку — условие бесполезно")


def test_правило_проходит_на_исправленном():
    """И проходит на том, что считается верным."""
    верно = (".zhd__in{display:flex;flex-wrap:nowrap;height:56px}\n"
             ".zhd__n{display:none;position:absolute;top:100%;left:0;right:0;"
             "flex-direction:column;overflow-y:auto}\n"
             ".zhd__n.is-open{display:flex}")
    выпадающие = [п for п in _правила(верно, ".zhd__n")
                  if "display:none" in п and "flex-direction:column" in п]
    assert выпадающие
    assert all("position:absolute" in п and "top:100%" in п for п in выпадающие)
