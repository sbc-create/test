"""Порядок блоков главной, названия разделов и сетка подборок.

ПОВОД — поручение владельца 27.10: «рекомендации и подборки вытеснили
привычные разделы с актуальными сериями». На живой главной это видно числом:
редакционная лента начиналась на 121 715-м байте документа, визитки подборок
на 127 153-м, а «Аниме недели» только на 135 687-м и «Новые серии» на
155 070-м. Постоянный посетитель, пришедший за новой серией, встречал два
редакционных блока до первой серии.

ЧТО ЗАЩИЩАЕТ ТЕСТ. Не наличие строки в файле, а четыре проверяемых свойства:

1. редакционные блоки собираются ПОСЛЕ «Лучшего по оценкам», а не до
   карусели;
2. слот объявлен полем профиля, а не захардкожен — иначе порядок аниме-витрины
   однажды переедет на кинотеатральные Zona и Lords, чего владелец запретил;
3. блок подборок на главной ставится РОВНО один раз при любом слоте;
4. правила сетки для него селектируются двумя классами — одноклассовый
   `.zhub--big` с тремя колонками остаётся в файле и иначе перевесил бы.

Плюс названия: «Аниме-сериалы» вместо «Сериалы с сериями» в подписи полки и в
спецификации коллекции одновременно, иначе полка и её «Все →» расходятся.
"""
