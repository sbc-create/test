# --- сама правка ------------------------------------------------------------

def test_правка_идемпотентна_и_проверяет_себя():
    """`--check` на приведённых файлах обязан давать ноль: иначе «уже стоит» и
    «не применено» различить нечем, и повторный проход что-нибудь удвоит."""
    итог = subprocess.run(
        [sys.executable, "-I", str(ПРАВКА), "--check",
         *[str(п) for п in РАНТАЙМЫ], *[str(п) for п in КОНТРАКТЫ]],
        capture_output=True, text=True, cwd=КОРЕНЬ)
    assert итог.returncode == 0, итог.stdout + итог.stderr
    assert "НЕ ПРИВЕДЁН" not in итог.stdout


def test_правка_отказывает_при_пропавшем_якоре(tmp_path):
    """Требование файла выполнено, якоря нет — это разошедшийся рантайм, и
    писать в него нельзя. Отказ обязан наступить ДО единой правки."""
    подделка = tmp_path / "runtime.py"
    подделка.write_text("def _полка_главной(self):\n    return '', set()\n",
                        encoding="utf-8")
    было = подделка.read_text(encoding="utf-8")
    итог = subprocess.run([sys.executable, "-I", str(ПРАВКА), str(подделка)],
                          capture_output=True, text=True, cwd=КОРЕНЬ)
    assert итог.returncode != 0
    assert "ОТКАЗ" in (итог.stdout + итог.stderr)
    assert подделка.read_text(encoding="utf-8") == было, "файл изменён при отказе"


def test_правка_молчит_о_чужой_линии(tmp_path):
    """Файл без единого требования — не «разошёлся», а чужой. Отказ здесь был
    бы ложным, но и молча записать в него тоже нельзя."""
    чужой = tmp_path / "other.py"
    чужой.write_text("print('ни ленты, ни подборок, ни сетки')\n", encoding="utf-8")
    итог = subprocess.run([sys.executable, "-I", str(ПРАВКА), str(чужой)],
                          capture_output=True, text=True, cwd=КОРЕНЬ)
    assert итог.returncode != 0
    assert "не тот файл" in (итог.stdout + итог.stderr)


