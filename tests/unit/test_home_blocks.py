def test_правила_сетки_перевешивают_одноклассовые():
    """Трёхколоночное правило `.zhub--big` в файле ОСТАЁТСЯ — оно нужно хабу
    `/collections/`. Значит новые правила обязаны выигрывать весом селектора,
    а не местом в файле: два класса против одного."""
    текст = _текст(РАНТАЙМ_ЛЕНТЫ)
    assert "@media(min-width:1024px){.zhub--big{grid-template-columns:repeat(3," in текст
    for правило in re.findall(r"\.zsec--home-cols \.zhub--big\{[^}]*\}", текст):
        селектор = правило.split("{")[0]
        assert селектор.count(".") >= 2, f"селектор слабее одноклассового: {селектор}"


