"""REQ-SEO-EPISODE-BUDGET: решение о сериях в карте опирается на число.

MOD-79 измерен: карта семейства Lords не выпускает адресов серий. Прежде чем
это менять, нужен бюджет — сколько адресов добавится и сколько файлов карты это
даст. Измерено 2026-10-18 по lords-03: 565 008 доступных серий, 12 файлов по
50 000, рост карты примерно десятикратный.

Два свойства инструмента проверяются здесь, потому что без них число было бы
хуже отсутствия числа:

* в карту имеют право только ДОСТУПНЫЕ серии. Правка 18.10 закрыла пустые
  страницы серий `noindex, follow`; подать их роботу значило бы отправить его
  на закрытые адреса;
* файл подробностей читается ПОТОКОМ. Разбор 86 МиБ в память на узле, где
  рядом работают семнадцать витрин, — не измерение, а риск.
"""
from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

ПУТЬ = (Path(__file__).resolve().parents[2] / "automation" / "local"
        / "episode-url-budget.py")


def _прогон(файл: Path) -> str:
    г = subprocess.run([sys.executable, str(ПУТЬ), str(файл)],
                       capture_output=True, text=True)
    assert г.returncode == 0, г.stderr
    return г.stdout


def _подробности(tmp_path: Path, сезоны: list[tuple[int, int]]) -> Path:
    """Файл подробностей с сезонами (eps, avail)."""
    записи = {
        f"title-{н}": {"seasons": {"1": {"n": 1, "eps": eps, "avail": avail}}}
        for н, (eps, avail) in enumerate(сезоны)
    }
    ф = tmp_path / "details.json"
    ф.write_text(json.dumps({"details": записи, "details_total": len(записи)}),
                 encoding="utf-8")
    return ф


def test_считаются_и_объявленные_и_доступные(tmp_path):
    вывод = _прогон(_подробности(tmp_path, [(12, 12), (24, 10), (6, 0)]))
    assert "серий объявлено (сумма eps):   42" in вывод
    assert "серий доступно (сумма avail):  22" in вывод
    assert "сезонов в подробностях: 3" in вывод


def test_право_на_карту_только_у_доступных(tmp_path):
    """Главное различение: недоступные закрыты `noindex` с 18.10."""
    вывод = _прогон(_подробности(tmp_path, [(100, 40)]))
    assert "адресов серий, имеющих право на карту (доступные): 40" in вывод
    assert "в карту идти НЕ должны" in вывод
    assert "60" in вывод.split("НЕ должны")[1]


def test_число_файлов_карты_по_пределу_протокола(tmp_path):
    вывод = _прогон(_подробности(tmp_path, [(50001, 50001)]))
    assert "файлов карты по 50000: 2" in вывод


def test_ноль_доступных_не_превращается_в_ноль_файлов_молча(tmp_path):
    вывод = _прогон(_подробности(tmp_path, [(10, 0)]))
    assert "адресов серий, имеющих право на карту (доступные): 0" in вывод
    assert "файлов карты по 50000: 0" in вывод


def test_файл_читается_потоком_а_не_разбирается_в_память():
    """Иначе измерение на боевом узле само становится риском."""
    тело = ПУТЬ.read_text(encoding="utf-8")
    assert "поток.read(" in тело
    assert "json.load" not in тело, (
        "разбор 86 МиБ в память рядом с семнадцатью витринами недопустим")
    assert "хвост" in тело, (
        "кусок обязан склеиваться с хвостом предыдущего, иначе число на "
        "границе чтения потеряется")


def test_граница_кусков_не_теряет_числа(tmp_path):
    """Отрицательный контроль к склейке: много сезонов, читается кусками."""
    сезоны = [(2, 1)] * 20000
    вывод = _прогон(_подробности(tmp_path, сезоны))
    assert "серий доступно (сумма avail):  20000" in вывод
    assert "серий объявлено (сумма eps):   40000" in вывод
