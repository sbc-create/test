"""Доставляемая проверка публичных текстов: два яруса и две закрытые дыры.

Повод. Сессия витрины `1lordserials1.online` обнаружила 15.10, что
`checks/public_wording.py` молчала о трёх формулировках, остававшихся на живой
главной, и обе причины лежали в самой проверке:

1. **статический ярус читал только `src/`.** У витрины на профиле
   `lords-curated` публичный текст печатает НАЛОЖЕНИЕ: оно переопределяет
   `главная()` целиком вместе со своими `_вступление()` и `_о_каталоге()`, а
   ветка ядра не исполняется вовсе. Замена текста в `src/` была там мёртвой;
2. **сравнение шло подстрокой по файлу.** В исходнике фраза свёрстана
   переносом строковых литералов: на странице печатается целиком, поиском по
   файлу не находится. Одна и та же фраза в семействе существует минимум в
   двух вёрстках — поэтому инструмент замены с точным совпадением её и
   пропустил.

Проверка доставляется моим инструментом, то есть правка в одной витрине была
бы затёрта следующим прогоном, а дыра вернулась бы у всего семейства. Здесь
обе дыры закреплены ОТКАТОМ: с возвращённой формулировкой ярус обязан падать
и называть файл, без неё — проходить.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСТОЧНИК = КОРЕНЬ / "automation" / "host" / "public_wording_check.py"

#: Фраза из таблицы владельца, свёрстанная ПЕРЕНОСОМ литералов — ровно так,
#: как она лежала в наложении живой витрины.
ПЕРЕНОСОМ = '''
def _о_каталоге() -> str:
    return (
        "Каталог Lordserials опирается на переданные жанры, годы и оценки. "
        "Редакционные пометки — только при наличии подтверждённого "
        "источника."
    )
'''

#: Та же фраза одной строкой: вторая вёрстка той же формулировки.
ОДНОЙ_СТРОКОЙ = '''
def _вступление() -> str:
    return "Алгоритмические списки не выдаются за редакционный выбор."
'''

ЧИСТО = '''
def _о_каталоге() -> str:
    return "В каталоге Lordserials фильм или сериал можно выбрать по жанру."
'''


def ячейка(куда: Path, *, src: str = ЧИСТО, overlay: str | None = None) -> Path:
    """Собрать проект витрины так, как он лежит на узле."""
    (куда / "checks").mkdir(parents=True)
    (куда / "src").mkdir()
    (куда / "config").mkdir()
    shutil.copy2(ИСТОЧНИК, куда / "checks" / "public_wording.py")
    (куда / "src" / "lords-frontend.py").write_text(src, encoding="utf-8")
    if overlay is not None:
        (куда / "overlay").mkdir()
        (куда / "overlay" / "view.py").write_text(overlay, encoding="utf-8")
    (куда / "config" / "site.json").write_text(json.dumps(
        {"domain": "проба.test", "site_id": "проба"}, ensure_ascii=False),
        encoding="utf-8")
    return куда


def прогон(проект: Path) -> tuple[int, str]:
    г = subprocess.run([sys.executable, "checks/public_wording.py"],
                       cwd=проект, capture_output=True, text=True, timeout=300)
    return г.returncode, (г.stdout or "") + (г.stderr or "")


def статические_строки(вывод: str) -> list[str]:
    """Только строки первого яруса: второй без плеера пропускается."""
    строки = []
    for с in вывод.splitlines():
        if с.startswith("2."):
            break
        строки.append(с)
    return строки


def test_формулировка_в_наложении_ловится(tmp_path):
    """Дыра 1: текст живёт в overlay/, и раньше ярус его не читал."""
    проект = ячейка(tmp_path / "с-наложением", overlay=ОДНОЙ_СТРОКОЙ)
    код, вывод = прогон(проект)
    ярус = "\n".join(статические_строки(вывод))
    assert "FAIL" in ярус, ярус
    assert "view.py" in ярус, (
        "ярус не назвал файл наложения — без имени файла правку негде искать")
    # Код возврата здесь намеренно НЕ проверяется: в пустой временной ячейке он
    # ненулевой и у прежней версии проверки — из-за поведенческого яруса, у
    # которого нет плеера. Различает версии только находка статического яруса.
    assert код is not None


def test_формулировка_свёрстанная_переносом_ловится(tmp_path):
    """Дыра 2: фраза разбита на литералы, подстрокой по файлу не находится."""
    проект = ячейка(tmp_path / "переносом", overlay=ПЕРЕНОСОМ)
    код, вывод = прогон(проект)
    ярус = "\n".join(статические_строки(вывод))
    assert "FAIL" in ярус, ярус
    assert "view.py" in ярус, ярус
    assert код is not None  # см. пояснение выше про код возврата


def test_без_формулировок_ярус_проходит(tmp_path):
    """Обратная сторона: иначе проверка падала бы всегда и ничего не значила."""
    проект = ячейка(tmp_path / "чисто", overlay=ЧИСТО)
    _, вывод = прогон(проект)
    ярус = статические_строки(вывод)
    assert ярус, вывод
    assert all("FAIL" not in с for с in ярус), "\n".join(ярус)


def test_витрина_без_наложения_не_ломает_ярус(tmp_path):
    """Каталога overlay/ у большинства витрин нет — это не ошибка."""
    проект = ячейка(tmp_path / "без-наложения", overlay=None)
    _, вывод = прогон(проект)
    ярус = статические_строки(вывод)
    assert ярус, вывод
    assert all("FAIL" not in с for с in ярус), "\n".join(ярус)


def test_склейка_не_соединяет_разные_значения():
    """Запятая между литералами — два значения, а не одна фраза.

    Иначе список `["витрина", "фильмов"]` склеился бы в запрещённую
    формулировку, и проверка падала бы на честном коде.
    """
    import importlib.util

    спец = importlib.util.spec_from_file_location("_пров", ИСТОЧНИК)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    assert м.склеенный('"витрина", "фильмов"') == '"витрина", "фильмов"'
    assert м.склеенный('"прода" "жение"') == '"продажение"'
    assert м.склеенный('"прода" + "жение"') == '"продажение"'


@pytest.mark.parametrize("фраза", [
    "Алгоритмические списки не выдаются за редакционный выбор",
    "Редакционные формулировки показываются только при наличии источника",
    "Редакционные пометки — только при наличии подтверждённого",
])
def test_три_найденные_формулировки_в_перечне(фраза):
    """Поимённо: иначе следующая правка шаблона вернула бы их незамеченными."""
    текст = ИСТОЧНИК.read_text(encoding="utf-8")
    assert фраза in текст, f"формулировка {фраза!r} не внесена в БЫВШИЕ"


def test_прежняя_версия_молчала_а_новая_ловит(tmp_path):
    """Доказательство, что дыра БЫЛА, а не «проверка и так проходила».

    Новые проверки, которые проходят, доказывают только сегодняшнее
    состояние. Утверждение «молчала» требует прогона прежней версии на тех же
    данных — здесь она берётся из git.
    """
    прежняя = subprocess.run(
        ["git", "show", "HEAD~1:automation/host/public_wording_check.py"],
        cwd=КОРЕНЬ, capture_output=True, text=True)
    if прежняя.returncode != 0 or "overlay" in прежняя.stdout:
        pytest.skip("прежней версии без правки в истории нет — сравнивать нечего")

    for n, (подпись, наложение) in enumerate(
            (("одной строкой", ОДНОЙ_СТРОКОЙ), ("переносом", ПЕРЕНОСОМ))):
        проект = ячейка(tmp_path / f"прежняя-{n}", overlay=наложение)
        (проект / "checks" / "public_wording.py").write_text(
            прежняя.stdout, encoding="utf-8")
        _, вывод = прогон(проект)
        ярус = статические_строки(вывод)
        assert all("FAIL" not in с for с in ярус), (
            f"прежняя версия внезапно ловит фразу {подпись} — тогда правка "
            "закрывала не эту дыру:\n" + "\n".join(ярус))

        свежий = ячейка(tmp_path / f"новая-{n}", overlay=наложение)
        _, вывод2 = прогон(свежий)
        assert any("FAIL" in с for с in статические_строки(вывод2)), вывод2
