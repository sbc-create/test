"""Обход заголовков по парку: что он считает дефектом и чего не считает.

Повод: до 27.10 заголовки главных по парку не проверяла ни одна проверка, и
дефект «H1 описывает одну полку» жил на двух витринах Zona, а «H1 равен
<title>» — ещё на трёх. Приёмка главной это ловит, но поднимает браузер и ходит
по путям, по парку её гонять дорого.

Главное, что здесь закрепляется: НЕДОСТУПНАЯ витрина не становится «ок», а
пустые строки не сравниваются между собой. Ложное равенство из двух отсутствий
— измеренная 27.10 ошибка соседней линии, и повторять её нельзя.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "automation" / "local" / "home-headings-survey.py"


@pytest.fixture(scope="module")
def м():
    спец = importlib.util.spec_from_file_location("headings_survey", ПУТЬ)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def _страница(*, title="Имя — раздел", h1=None, h2=(), лента_h1=False):
    голова = f"<head><title>{title}</title></head>"
    тело = []
    if лента_h1:
        тело.append(
            '<section data-block-key="rail:выбор"><div>'
            f'<h1 id="r">{h1}</h1></div></section>')
    elif h1 is not None:
        тело.append(f'<h1 class="vh">{h1}</h1>')
    тело.extend(f"<h2>{т}</h2>" for т in h2)
    return голова + "<body>" + "".join(тело) + "</body>"


def test_правильная_главная_без_дефектов(м):
    итог = м.разобрать(_страница(h1="Предмет страницы", h2=("Подборки",)))
    assert итог["заголовков h1"] == 1
    assert м.дефекты({**итог}) == []


def test_h1_внутри_ленты_ловится(м):
    """Сравнение с первым H2 этого не поймало бы: у ленты, забравшей H1,
    своего H2 не остаётся — именно так было на zonafilm.space."""
    итог = м.разобрать(_страница(h1="Сериалы, которые стоит посмотреть",
                                 h2=("Подборки",), лента_h1=True))
    assert итог["h1 внутри ленты"] is True
    assert "H1 стоит внутри рекомендательной ленты" in м.дефекты(итог)


def test_h1_равен_заголовку_ловится(м):
    итог = м.разобрать(_страница(title="Animedia ICU — аниме",
                                 h1="Animedia ICU — аниме"))
    assert итог["h1 равен title"] is True
    assert "H1 равен <title>" in м.дефекты(итог)


def test_h1_равен_подписи_первой_ленты_ловится(м):
    итог = м.разобрать(_страница(h1="Аниме недели", h2=("Аниме недели",)))
    assert итог["h1 равен подписи ленты"] is True


def test_без_h1_дефект_и_не_равенство(м):
    """Пустое с пустым не сравнивается: отсутствие даёт свой признак."""
    итог = м.разобрать(_страница(title="", h1=None))
    assert итог["заголовков h1"] == 0
    assert итог["h1 равен title"] is False
    assert итог["h1 равен подписи ленты"] is False
    причины = м.дефекты(итог)
    assert "заголовков h1: 0" in причины
    assert "H1 равен <title>" not in причины


def test_пустой_h1_дефект_по_своему_признаку(м):
    итог = м.разобрать(_страница(title="", h1=""))
    assert итог["h1 пуст"] is True
    assert итог["h1 равен title"] is False, "сравнялись два отсутствия"
    assert "H1 пуст" in м.дефекты(итог)


def test_два_h1_дефект(м):
    страница = ("<head><title>Имя</title></head><body>"
                "<h1>Первый</h1><h1>Второй</h1></body>")
    итог = м.разобрать(страница)
    assert итог["заголовков h1"] == 2
    assert "заголовков h1: 2" in м.дефекты(итог)


def test_не_измеренное_не_дефект_и_не_ок(м):
    """Недоступная витрина не попадает ни в «ок», ни в «с дефектом»."""
    assert м.дефекты({"домен": "x", "не измерено": "curl код 7"}) == []


def test_домены_парка_берутся_из_реестра(м):
    """Список витрин не пишется в коде: исключённые и не извлечённые не
    трогаются, живые берутся из config/site-cells.json."""
    домены = м.домены_парка()
    assert "zonafilm.space" in домены
    assert "animedia.icu" in домены
    # Исключённые из продвижения не опрашиваются.
    assert "lordfilm.group" not in домены
    # Не извлечённые витрины — тем более.
    assert "pilot.localhost.test" not in домены


def test_запрос_помечен_собой(м):
    """Иначе обход попадает в статистику людей."""
    assert м.АГЕНТ.startswith("factory-")


def test_ожидание_не_короткое(м):
    """20 с на странице под 400 КБ давали чтение неудавшегося запроса —
    измеренная 27.10 ошибка соседней линии."""
    assert м.ОЖИДАНИЕ_С >= 60
