"""REQ-CONTROL-ZONES: до каждой зоны центра управления есть ссылка.

Экран, до которого нет ссылки, существует только для того, кто помнит его
адрес. Возможность, добавленная без ссылки, на практике не используется — и
через месяц её считают несделанной.

Отдельно проверяется обратное: внутри контура витрины ссылок на флот нет.
Иначе местный администратор видел бы вход в чужой массив и решал бы, что права
у него шире, чем есть.
"""

from __future__ import annotations

import pytest

from factory.site_engine.admin import ui

ЗОНЫ = ("/admin/fleet", "/admin/templates", "/admin/analytics")


@pytest.fixture(autouse=True)
def общий_контур():
    метка = ui.БАЗА.set("/admin")
    yield
    ui.БАЗА.reset(метка)


@pytest.mark.parametrize("адрес", ЗОНЫ)
def test_ссылка_на_зону_есть_в_общем_контуре(адрес):
    html = ui.page("Что-нибудь", "<p>тело</p>", session_label="кто-то", csrf="t")
    assert f'href="{адрес}"' in html, f"до {адрес} нельзя дойти по ссылке"


def test_внутри_контура_витрины_ссылок_на_флот_нет():
    метка = ui.БАЗА.set("/s/site-1/admin")
    try:
        html = ui.page("Что-нибудь", "<p>тело</p>", session_label="кто-то", csrf="t")
    finally:
        ui.БАЗА.reset(метка)
    for адрес in ЗОНЫ:
        assert адрес not in html, (
            f"из контура витрины видна ссылка на {адрес}: местный администратор "
            "решит, что права у него шире")


def test_зоны_названы_по_смыслу_а_не_по_адресу():
    html = ui.page("Что-нибудь", "<p>тело</p>", session_label="кто-то", csrf="t")
    for подпись in ("Флот", "Шаблоны", "Аналитика и SEO"):
        assert f">{подпись}<" in html, f"зона {подпись} без понятной подписи"
