"""Поправки года и вида, сверенные с источником: применение и отказы.

Повод. Год записи приезжает из ответа поставщика, и у продолжений он несёт дату
ПЕРВОЙ части франшизы. Измерено 20.10 на animedia-01 штатным путём (D199): из
14 строгих кандидатов внутреннего признака сверка подтвердила 7 неверных, а на
случайном образце из 300 записей расхождение года нашлось у 7 из 282
измеренных. Поправка кладётся в репозиторий и применяется при сборке каталога.

Отрицательные контроли, названные заранее, — каждый отвечает на ошибку, которую
такой механизм совершает естественно:

* **поправка без источника и даты замера отвергается.** Иначе это подстановка
  года, а не поправка, и отличить одно от другого через месяц будет нечем;
* **ключ — постоянный id поставщика, а не слаг.** Слаг переезжает на другое
  произведение (так было с `dlya-tebya-vo-vsem-cvetu-2`), и поправка по слагу
  приписала бы год чужой записи;
* **поправка НЕ применяется, если поставщик сменил значение после замера.** Он
  мог исправиться сам, возможно на третье значение, и перетирать его замером
  недельной давности нельзя. Этот случай обязан считаться отдельно;
* **вид вне словаря снимка в поправку не попадает вовсе.** В снимке два
  значения (`tv`, `movie`), и `ona` в нём невыразима: это предел словаря, а не
  ошибка записи.
"""
from __future__ import annotations

import json

import pytest

from factory.lords import year_corrections as ПОПР


def _запись(**п) -> dict:
    з = {
        "id": "01918cd7-61fd-75e3-8410-67fe2f763a0d",
        "slug_at_measure": "rukovodstvo-soten-demonov-4",
        "source_id": "57995",
        "source_url": "https://shikimori.io/animes/57995",
        "measured_at": "2026-10-20T13:39:06Z",
        "matching": "external_id_from_record+title_verified",
        "aired_on": "2024-02-23",
        "year_provider": 2020,
        "year_source": 2024,
    }
    з.update(п)
    return з


def _набор(*записи) -> dict[str, ПОПР.Поправка]:
    return ПОПР.разобрать({"corrections": list(записи)})


# --- применение ----------------------------------------------------------------

def test_сверенный_год_подменяет_поставщика():
    набор = _набор(_запись())
    год, вид, источник = ПОПР.применить(
        набор, "01918cd7-61fd-75e3-8410-67fe2f763a0d", 2020, "tv")
    assert год == 2024
    assert вид == "tv"
    assert "shikimori.io/animes/57995" in источник
    assert "2026-10-20" in источник


def test_без_поправки_значение_поставщика_не_меняется():
    набор = _набор(_запись())
    assert ПОПР.применить(набор, "другой-id", 2020, "tv") == (2020, "tv",
                                                              "provider")


def test_поправка_не_применяется_по_слагу():
    """Ключ — id. Слаг переезжает, и поправка по нему уехала бы на чужое."""
    набор = _набор(_запись())
    год, _, источник = ПОПР.применить(набор, "rukovodstvo-soten-demonov-4",
                                      2020, "tv")
    assert год == 2020
    assert источник == "provider"


def test_поставщик_сменил_год_поправка_отступает():
    """Он мог исправиться сам, возможно на третье значение."""
    набор = _набор(_запись())
    год, _, источник = ПОПР.применить(
        набор, "01918cd7-61fd-75e3-8410-67fe2f763a0d", 2023, "tv")
    assert год == 2023, "перетирать новое значение поставщика нельзя"
    assert источник == "provider/stale-correction"


def test_поставщик_сменил_вид_поправка_вида_отступает():
    набор = _набор(_запись(year_source=None, year_provider=None,
                           type_provider="tv", type_source="movie"))
    вид = ПОПР.применить(набор, "01918cd7-61fd-75e3-8410-67fe2f763a0d",
                         2020, "movie")[1]
    assert вид == "movie"


def test_поправка_только_вида_год_не_трогает():
    набор = _набор(_запись(year_provider=None, year_source=None,
                           type_provider="tv", type_source="movie"))
    год, вид, _ = ПОПР.применить(набор, "01918cd7-61fd-75e3-8410-67fe2f763a0d",
                                 1999, "tv")
    assert (год, вид) == (1999, "movie")


def test_поправка_без_года_поставщика_применяется_безусловно():
    """Если замер не записал прежнее значение, сверять нечего — применяем."""
    набор = _набор(_запись(year_provider=None))
    год = ПОПР.применить(набор, "01918cd7-61fd-75e3-8410-67fe2f763a0d",
                         1812, "tv")[0]
    assert год == 2024


# --- отказы при загрузке -------------------------------------------------------

@pytest.mark.parametrize("убрать", ["source_url", "measured_at", "matching"])
def test_поправка_без_основания_отвергается(убрать):
    з = _запись()
    з.pop(убрать)
    with pytest.raises(ПОПР.ПоправкаОтвергнута) as ош:
        _набор(з)
    assert убрать in str(ош.value)


def test_поправка_без_id_отвергается():
    з = _запись()
    з["id"] = ""
    with pytest.raises(ПОПР.ПоправкаОтвергнута):
        _набор(з)


def test_повторный_id_отвергается():
    with pytest.raises(ПОПР.ПоправкаОтвергнута) as ош:
        _набор(_запись(), _запись(year_source=2025))
    assert "дважды" in str(ош.value)


def test_пустая_поправка_отвергается():
    with pytest.raises(ПОПР.ПоправкаОтвергнута) as ош:
        _набор(_запись(year_source=None))
    assert "ничего не исправляет" in str(ош.value)


def test_нелепый_год_отвергается():
    with pytest.raises(ПОПР.ПоправкаОтвергнута) as ош:
        _набор(_запись(year_source=12))
    assert "это не год" in str(ош.value)


def test_вид_вне_словаря_снимка_отвергается():
    """`ona` в снимке невыразима — поправка на неё не заводится."""
    with pytest.raises(ПОПР.ПоправкаОтвергнута) as ош:
        _набор(_запись(type_source="ona"))
    assert "вне словаря" in str(ош.value)


def test_нет_списка_поправок_это_отказ():
    with pytest.raises(ПОПР.ПоправкаОтвергнута):
        ПОПР.разобрать({})


# --- загрузка файла ------------------------------------------------------------

def test_нет_файла_это_пустой_набор(tmp_path):
    assert ПОПР.загрузить(tmp_path / "нет.json") == {}


def test_файл_читается(tmp_path):
    ф = tmp_path / "c.json"
    ф.write_text(json.dumps({"schema_version": 1, "corrections": [_запись()]}),
                 encoding="utf-8")
    набор = ПОПР.загрузить(ф)
    assert набор["01918cd7-61fd-75e3-8410-67fe2f763a0d"].год_источника == 2024


def test_рабочий_файл_репозитория_читается_и_непуст():
    """Файл в config/ обязан быть пригодным: иначе сборка молча не поправит."""
    набор = ПОПР.загрузить()
    assert набор, "config/anime-year-corrections.json пуст или не читается"
    for п in набор.values():
        assert п.источник.startswith("https://")
        assert п.сопоставление
        assert п.год_источника is not None or п.вид_источника is not None
