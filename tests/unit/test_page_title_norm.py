"""п.7: title, H1 и description страницы N>1 несут номер страницы.

Норма замороженной базы дословно: «Для page 2+ используется утверждённый
шаблон title/H1/description с номером страницы; новый фактический текст не
генерируется». Три поля, не одно.

Повод. До 11.10 приёмка заголовки не мерила ВОВСЕ — проверялись canonical,
номер за пределом и редирект. Нашлось со стороны: SEO-сессия заметила на
коллекциях Animedia, что title страницы 2 совпадает с первой, и оговорила «по
п.3 это не нарушение». По п.3 действительно нет, по п.7 — да. Первый же мой
замер показал, что у ВСЕХ двенадцати витрин, на всех разделах, совпадает
**H1**: title и description номер несут, H1 нет.

Разделение строгости не вкусовое:

* title и description — жёстко у всех: норму они уже соблюдают, значит
  совпадение с первой страницей это регресс;
* H1 — по списку `П7_H1_СТРОГО`, пустому на 11.10 и растущему по измерению.
  Жёсткая проверка покрасила бы всю сеть на известном и исправляемом месте, а
  молчание вернуло бы положение, в котором норма не измеряется вообще.

Проверяется НАЛИЧИЕ НОМЕРА, а не просто различие: заголовок, отличающийся от
первой страницы чем-то другим, норме не удовлетворяет.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


def страница(титул: str, h1: str, описание: str) -> str:
    return (f"<html><head><title>{титул}</title>"
            f'<meta name="description" content="{описание}"></head>'
            f"<body><h1>{h1}</h1></body></html>")


ПЕРВАЯ = страница("Каталог — Lordserial", "Каталог",
                  "Каталог на Lordserial.")


def прогнать(тело2: str, домен: str = "x.test", строгий_h1=()):
    м = _модуль()
    м.П7_H1_СТРОГО = строгий_h1
    шаги: list[tuple[str, bool, str]] = []
    м.норма_заголовка_страницы(домен, "catalog", ПЕРВАЯ, тело2,
                               lambda и, ок, п: шаги.append((и, ок, п)))
    (шаг,) = шаги
    return шаг


def test_номер_во_всех_трёх_полях_это_норма():
    вторая = страница("Каталог — страница 2 — Lordserial",
                      "Каталог — страница 2",
                      "Каталог на Lordserial — страница 2.")
    _и, ок, подробно = прогнать(вторая, строгий_h1=("x.test",))
    assert ок is True, подробно
    assert подробно.count("номер есть") == 3


def test_совпадение_title_с_первой_страницей_это_расхождение():
    """Ровно то, что SEO нашла на коллекциях Animedia, а я — у lords-02."""
    вторая = страница("Каталог — Lordserial", "Каталог",
                      "Каталог на Lordserial — страница 2.")
    _и, ок, подробно = прогнать(вторая)
    assert ок is False, подробно
    assert "title: совпадает с первой" in подробно


def test_совпадение_description_это_расхождение():
    вторая = страница("Каталог — страница 2 — Lordserial", "Каталог",
                      "Каталог на Lordserial.")
    _и, ок, подробно = прогнать(вторая)
    assert ок is False
    assert "description: совпадает с первой" in подробно


def test_H1_без_номера_не_красит_сеть_пока_список_пуст():
    """Состояние всех двенадцати витрин на 11.10: H1 номер не несёт."""
    вторая = страница("Каталог — страница 2 — Lordserial", "Каталог",
                      "Каталог на Lordserial — страница 2.")
    _и, ок, подробно = прогнать(вторая)
    assert ок is True, подробно
    assert "H1: совпадает с первой" in подробно
    assert "H1 по сети номер не несёт" in подробно


def test_H1_без_номера_у_домена_из_строгого_списка_это_расхождение():
    """Как только витрина норму выполнит, её регресс обязан падать."""
    вторая = страница("Каталог — страница 2 — Lordserial", "Каталог",
                      "Каталог на Lordserial — страница 2.")
    _и, ок, подробно = прогнать(вторая, строгий_h1=("x.test",))
    assert ок is False, подробно
    assert "H1: совпадает с первой" in подробно
    assert "строго не проверяется" not in подробно


def test_отличие_без_номера_нормой_не_считается():
    """«Каталог — вторая часть» отличается от первой страницы, но п.7 просит
    НОМЕР: иначе шаблон перестаёт быть утверждённым, и текст генерируется."""
    вторая = страница("Каталог — ещё — Lordserial", "Каталог",
                      "Каталог на Lordserial — продолжение.")
    _и, ок, подробно = прогнать(вторая)
    assert ок is False
    assert "title: отличается, но номера нет" in подробно
    assert "description: отличается, но номера нет" in подробно


def test_отсутствие_поля_называется_отдельно():
    """Пустой title — не то же, что совпадающий: причины разные."""
    вторая = страница("", "Каталог", "")
    _и, ок, подробно = прогнать(вторая)
    assert ок is False
    assert "title: отсутствует" in подробно
    assert "description: отсутствует" in подробно


def test_номер_ищется_в_добавленной_части_а_не_во_всём_заголовке():
    """Раздел, в названии которого уже есть «2», не должен проходить даром.

    `/year/2024/` носит год в заголовке, и проверка «есть ли где-то цифра 2»
    приняла бы совпадающий заголовок за нормальный.
    """
    первая_год = страница("2024 год — Lordserial", "2024 год",
                          "Фильмы 2024 года.")
    м = _модуль()
    м.П7_H1_СТРОГО = ()
    шаги: list[tuple[str, bool, str]] = []
    м.норма_заголовка_страницы("x.test", "year/2024", первая_год, первая_год,
                               lambda и, ок, п: шаги.append((и, ок, п)))
    (_и, ок, подробно) = шаги[0]
    assert ок is False, подробно
    assert "title: совпадает с первой" in подробно


def test_разметка_внутри_заголовка_не_мешает():
    вторая = страница("Каталог — страница 2 — Lordserial",
                      "Каталог <span>— страница 2</span>",
                      "Каталог на Lordserial — страница 2.")
    _и, ок, подробно = прогнать(вторая, строгий_h1=("x.test",))
    assert ок is True, подробно


def test_в_строгом_списке_H1_стоят_измеренные_витрины():
    """Пополнение списка проходит через эту проверку, а не молча.

    Список начинался пустым: H1 не несла номер ни одна витрина сети. Правка
    идёт одной общей точкой (`seo_layer.обогатить` добавляет номер к первому
    `<h1>`, если он уже стоит в `<title>`), поэтому витрина входит в список
    целиком, а не по разделам — в отличие от карт п.2 и п.3, где строгость
    по разделам, потому что там один дефект жил в разном коде.
    """
    м = _модуль()
    assert set(м.П7_H1_СТРОГО) == {"lordserials22.info", "lordserial33.biz",
                                   "lordfilm47.space",
                                   "1lordserials1.online", "zonafilm.space"}


def test_норма_зовётся_из_замера_раздела():
    источник = СЦЕНАРИЙ.read_text(encoding="utf-8")
    assert "норма_заголовка_страницы(домен, где, т1, тело, шаг)" in источник
