"""Цель Метрики узнаётся по адресу goal://, а не по телеметрии браузера.

Повод. Первая редакция пробы живой страницы (`metrika-hit-probe.py`) брала за
имя цели параметр `t` запроса `mc.yandex.ru/watch/...`. Этот параметр — набор
браузерной телеметрии вида `gdpr(14)clc(0-0-0)...`, он есть в КАЖДОМ запросе
счётчика. На выводе получалось «названные цели: gdpr(14)ti(4)» и у
`yummyani.site`, где цели действительно отправляются, и у `lordserials22.info`,
где за семь суток ноль достижений. То есть проба подтверждала бы работу целей
на любом сайте, где счётчик просто считает визиты, — измерение, доказывающее
что угодно.

Цель `reachGoal` передаётся адресом `goal://<домен>/<имя>`. После правки проба
на странице тайтла `yummyani.site` называет `title_view`, `player_ready` и
`player_start`, а на странице тайтла `lordserials22.info` — ни одной, при
двенадцати запросах счётчика. Сеть в проверках не используется: здесь
проверяется только разбор.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИНСТРУМЕНТ = КОРЕНЬ / "automation" / "local" / "metrika-hit-probe.py"


@pytest.fixture(scope="module")
def проба():
    спец = importlib.util.spec_from_file_location("_проба_метрики", ИНСТРУМЕНТ)
    м = importlib.util.module_from_spec(спец)
    sys.modules[спец.name] = м
    спец.loader.exec_module(м)
    return м


@pytest.mark.parametrize("адрес, ожидание", [
    ("goal://yummyani.site/title_view", "title_view"),
    ("goal://yummyani.site/player_ready", "player_ready"),
    ("goal://lordserials22.info/search", "search"),
])
def test_цель_узнаётся(проба, адрес, ожидание):
    assert проба.цель_из_адреса(адрес) == ожидание


@pytest.mark.parametrize("адрес", [
    "https://yummyani.site/anime/x",
    "gdpr(14)clc(0-0-0)rqnt(1)aw(1)rcm(1)cdl(na)ti(1)",
    "",
    "goal:/yummyani.site/title_view",
])
def test_не_цель_целью_не_называется(проба, адрес):
    """Главное свойство: обычный запрос счётчика целью не считается."""
    assert проба.цель_из_адреса(адрес) == "", (
        "проба назвала целью то, что приходит с каждым визитом — такое "
        "измерение подтверждает работу целей на любом сайте")


def test_телеметрия_не_путается_с_целью(проба):
    """Поимённо тот случай, который испортил первую редакцию."""
    телеметрия = "gdpr(14)ti(4)"
    assert проба.цель_из_адреса(телеметрия) == ""


def test_проба_называет_свои_действия():
    """Отсутствие цели доказательно только вместе с перечнем действий.

    Часть целей привязана к нажатию, которого проба не делает. Если она не
    скажет, что делала, «целей нет» прочитается как «цели не работают».
    """
    текст = ИНСТРУМЕНТ.read_text(encoding="utf-8")
    assert "действия пробы" in текст
    assert "нажатий не было" in текст


def test_проба_не_выдаёт_отсутствие_запроса_за_настройку_целей():
    """Три исхода различены: нет запроса, есть без цели, есть с целью."""
    текст = ИНСТРУМЕНТ.read_text(encoding="utf-8")
    assert "запроса нет вовсе" in текст
    assert "считаются только визиты" in текст
    assert "НЕ «цель не настроена»" in текст
