"""Сборщик патча MOD-81: наложение перечитало снимок, ядро об этом не знает.

Дефект стоит 770 индексируемых страниц вне карты, и правка — три присваивания.
Именно поэтому проверяются ГРАНИЦЫ: патч не имеет права сбрасывать кэши (их
сброс из потока перечитывания даёт 500 на главной), не имеет права отдавать
ядру поколение при битом снимке и обязан отказываться на изменившемся файле,
а не подгоняться по похожему месту.

Отдельный урок, закреплённый тестом: первая редакция проверки «патч не
сбрасывает кэш» искала подстроку и падала на КОММЕНТАРИИ наложения, где это
имя стоит в объяснении, почему сброса нет. Признак давал один ответ на
исправном и неисправном тексте, то есть ничего не измерял.
"""
from __future__ import annotations

import importlib.util
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "prepare_overlay_reload_patch",
    КОРЕНЬ / "automation/local/prepare-overlay-reload-patch.py")
ИНС = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНС)

ОБРАЗЕЦ = '''"""Проба наложения."""


class Слежение:
    def принять(self, данные, подробности, индекс) -> None:
        self.поступления.пересчитать(данные, подробности)
        self.набор = Набор(данные, подробности, индекс, self.метка_старта,
                           shelves.собрать(данные, подробности, self.поступления))

    def _перестроить(self) -> None:
        try:
            метка = self.метка()
            данные = self.ядро.Данные(str(self.каталог))
            подробности = self.ядро.Подробности(self.ядро.ПОДРОБНОСТИ_ФАЙЛ)
            индекс = self.ядро.построить_индекс_исходный(данные, подробности)
            # Недельную полку НЕ трогаем: сброс_популярного_кэша() из этого
            # потока даёт KeyError и 500 на главной.
            self.поступления.пересчитать(данные, подробности)
            self.набор = Набор(данные, подробности, индекс, метка,
                               shelves.собрать(данные, подробности, self.поступления))
            self.перечитано += 1
        except Exception as ош:  # noqa: BLE001
            self.последняя_ошибка = f"{type(ош).__name__}: {ош}"
'''


def test_правка_вписывается():
    стало = ИНС.переписать(ОБРАЗЕЦ)
    assert "self.ядро.Обработчик.данные = данные" in стало
    assert "self.ядро.Обработчик.подробности = подробности" in стало
    assert "self.ядро.Обработчик.индекс = индекс" in стало


def test_присваивание_стоит_после_сборки_набора():
    """На битом снимке ядро обязано остаться на прежнем поколении целиком."""
    стало = ИНС.переписать(ОБРАЗЕЦ)
    набор = стало.index("self.набор = Набор(данные, подробности, индекс, метка")
    ядру = стало.index("self.ядро.Обработчик.данные = данные")
    счётчик = стало.index("self.перечитано += 1")
    assert набор < ядру < счётчик


def test_порядок_присваивания_как_у_прецедента():
    """Сначала данные, потом подробности и индекс — безопасная сторона окна."""
    стало = ИНС.переписать(ОБРАЗЕЦ)
    д = стало.index("self.ядро.Обработчик.данные")
    п = стало.index("self.ядро.Обработчик.подробности")
    и = стало.index("self.ядро.Обработчик.индекс")
    assert д < п < и


def test_принять_не_тронуто():
    """Якорь обязан различать `_перестроить` и похожий на него `принять`."""
    стало = ИНС.переписать(ОБРАЗЕЦ)
    принять = стало[стало.index("def принять"):стало.index("def _перестроить")]
    assert "Обработчик" not in принять


def test_патч_не_добавляет_сброса_кэша():
    стало = ИНС.переписать(ОБРАЗЕЦ)
    assert ИНС._вызовы_сброса(стало) == ИНС._вызовы_сброса(ОБРАЗЕЦ) == 0


def test_имя_в_комментарии_вызовом_не_считается():
    """Та самая ошибка признака: в наложении имя стоит в объяснении."""
    assert ИНС._вызовы_сброса("    # сброс_популярного_кэша() даёт KeyError") == 0
    assert ИНС._вызовы_сброса("    ядро.сброс_популярного_кэша()") == 1
    assert ИНС._вызовы_сброса("    ядро.сброс_популярного_кэша()  # зачем-то") == 1


def test_неоднозначный_якорь_это_отказ():
    with pytest.raises(SystemExit) as ош:
        ИНС.переписать(ОБРАЗЕЦ + "\n" + ОБРАЗЕЦ)
    assert "вместо одного" in str(ош.value)


def test_отсутствие_якоря_это_отказ():
    with pytest.raises(SystemExit):
        ИНС.переписать('"""Пусто."""\n')


def test_уже_исправленный_файл_это_отказ():
    with pytest.raises(SystemExit) as ош:
        ИНС.переписать(ИНС.переписать(ОБРАЗЕЦ))
    assert "УЖЕ есть" in str(ош.value)


def test_необслуживаемое_дерево_отвергается(capsys, tmp_path):
    ловушка = tmp_path / "srv" / "site" / "app" / "overlay"
    ловушка.mkdir(parents=True)
    файл = ловушка / "freshness.py"
    файл.write_text(ОБРАЗЕЦ, encoding="utf-8")
    assert ИНС.главное(["--source", str(файл)]) == 2
    assert "не обслуживаемое витриной дерево" in capsys.readouterr().out


def test_поколение_читается_так_же_как_в_ядре():
    """Модель обязана читать то же, что поток карты: revision и число записей."""
    import types

    класс = type("Обработчик", (), {"данные": types.SimpleNamespace(
        revision="r7", items=[1, 2, 3])})
    assert ИНС._поколение(types.SimpleNamespace(Обработчик=класс)) == ("r7", 3)
    пусто = type("Обработчик", (), {"данные": None})
    assert ИНС._поколение(types.SimpleNamespace(Обработчик=пусто)) == ("", 0)
