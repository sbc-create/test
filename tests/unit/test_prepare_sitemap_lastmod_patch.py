def test_прочитать_прежние_только_читает(tmp_path):
    м = _модуль(_собрать(tmp_path, ИНСТР.переписать(ОБРАЗЕЦ)), "обр_чтение")
    каталог = tmp_path / "карта"
    каталог.mkdir()
    (каталог / "sitemap.xml").write_bytes(b"<sitemapindex/>")
    (каталог / "sitemap-1.xml").write_bytes(b"<urlset/>")
    (каталог / "robots.txt").write_bytes(b"User-agent: *")
    до = sorted(п.name for п in каталог.iterdir())
    набор = м.прочитать_прежние(каталог)
    assert set(набор) == {"sitemap.xml", "sitemap-1.xml"}
    assert sorted(п.name for п in каталог.iterdir()) == до


