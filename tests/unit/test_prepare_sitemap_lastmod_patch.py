def test_нарезка_устойчива_к_пополнению(tmp_path):
    """Новый адрес не сдвигает границы: меняется один файл, а не все."""
    м = _модуль(_собрать(tmp_path, ИНСТР.переписать(ОБРАЗЕЦ)), "обр_нарезка")
    м.ПРЕДЕЛ_URL = 5
    страницы = [{"slug": f"s{н:02d}", "lastmod": f"2025-06-{н + 1:02d}"}
                for н in range(10)]
    первый = dict(м.построить_sitemap("x.test", страницы, ()))
    свежая = [{"slug": "novinka", "lastmod": "2026-10-21"}] + страницы
    второй = dict(м.построить_sitemap("x.test", свежая, (), первый))
    изменились = {и for и in второй
                  if и != "sitemap.xml" and первый.get(и) != второй[и]}
    assert изменились == {"sitemap-3.xml"}, изменились
    assert первый["sitemap-1.xml"] == второй["sitemap-1.xml"]


def test_удалённый_адрес_исчезает_а_часть_остаётся(tmp_path):
    """Часть не «сжимается»: сжатие пришлось бы делать сдвигом."""
    м = _модуль(_собрать(tmp_path, ИНСТР.переписать(ОБРАЗЕЦ)), "обр_удал")
    м.ПРЕДЕЛ_URL = 5
    страницы = [{"slug": f"s{н:02d}", "lastmod": f"2025-06-{н + 1:02d}"}
                for н in range(10)]
    первый = dict(м.построить_sitemap("x.test", страницы, ()))
    без = [с for с in страницы if с["slug"] != "s00"]
    второй = dict(м.построить_sitemap("x.test", без, (), первый))
    assert len(второй) == len(первый)
    assert второй["sitemap-1.xml"].count(b"<loc>") == 4
    assert второй["sitemap-2.xml"] == первый["sitemap-2.xml"]


