"""Сборщик патча `lastmod` частей карты, РЕДАКЦИЯ 2: отказы и репетиция.

Повод — MOD-111: у 12 домéнов сети `lastmod` частей в `/sitemap.xml` нет вовсе,
и обходчику нечем решать, перезапрашивать ли часть на 45 000 адресов.

Редакция 1 ставила части максимум дат страниц внутри неё. По спецификации
sitemaps.org `lastmod` в `<sitemapindex>` — время изменения САМОГО ФАЙЛА части,
поэтому редакция 2 ставит дату по факту изменения байтов и раскладывает адреса
устойчиво к пополнению. Прежние проверки этого файла требовали равенства
максимуму — требование было неверным, и они переписаны, а не удалены.

Отрицательные контроли, названные заранее:

* **неоднозначный якорь — отказ**, а не правка «по похожему месту»;
* **уже исправленный файл — отказ**, иначе патч наложился бы вторым слоем;
* **не обслуживаемое витриной дерево — отказ** с указанием работающего пути
  (ошибку с `/app/` поймала линия zona-01 на другом патче 20.10);
* **репетиция обязана ронять** подстановку времени сборки в новую часть,
  нарезку подряд (её сдвиг меняет все файлы) и дату, которая не двигается при
  изменении файла — то есть ровно поведение редакции 1;
* предел на часть в репетиции понижен: на настоящем пределе набор уместился бы
  в одну часть, и «изменился один файл» от «изменились все» не отличить.
"""
