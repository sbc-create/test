def _модуль(файл: pathlib.Path, имя: str):
    спец = importlib.util.spec_from_file_location(имя, файл)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def _собрать(tmp_path, текст: str, имя: str = "после"):
    файл = tmp_path / f"{имя}.py"
    файл.write_text(текст, encoding="utf-8")
    return файл


