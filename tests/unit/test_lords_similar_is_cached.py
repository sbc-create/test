"""REQ-LORDS-SIMILAR-CACHE: коды соседей считаются раз на снимок, а не на запрос.

Измерено 2026-10-17 профилем на настоящем каталоге витрины (64 508 записей):
страница произведения собиралась 1.72 с, и почти всё это время уходило в
`похожие_с_мета` — он обходил весь каталог и пересчитывал коды жанров и стран
каждой записи (`транслит` вызывался 269 832 раза ЗА ОДИН запрос).

Снаружи это выглядело как 504. На узле витрина отдавала страницу строго по
очереди (1 запрос — 0.99 с, 16 одновременных — 15.12 с каждый), и при тридцати
одновременных предел nginx `proxy_read_timeout 30s` переставал выполняться.

Проверка требует двух вещей: коды берутся из разбора снимка, а не из обхода
каталога, и повторный вызов не пересчитывает их заново.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from lords_runtime_harness import (Стенд, выгрузить, загрузить, запись,
                                   подробность)

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def _тело_подбора() -> str:
    """Кусок, где начисляются баллы кандидатам."""
    начало = ТЕКСТ.index("кандидаты: list[tuple[int, str, str, dict]] = []")
    конец = ТЕКСТ.index("доказанные = [т for т in кандидаты", начало)
    return ТЕКСТ[начало:конец]


def test_подбор_похожего_не_транслитерирует_каталог_на_каждом_запросе():
    """Корень дефекта: транслитерация внутри обхода каталога."""
    тело = _тело_подбора()
    assert "транслит(" not in тело, (
        "в обходе каталога снова считается транслитерация: это секунда "
        "процессорного времени на каждый запрос страницы произведения")
    assert "коды_соседей(" in тело


def test_подбор_не_обходит_весь_каталог():
    """Второй корень того же дефекта, измеренный профилем 2026-10-18.

    Страница произведения стоила 0.573 с, из них 0.560 с — подбор похожего:
    полный обход 64 508 записей со скорингом и сортировка 58 472 кандидатов,
    чтобы взять шесть. В выдачу попадают только кандидаты с совпавшим жанром
    или страной, поэтому осматриваются ровно они — через обратный индекс.
    """
    тело = _тело_подбора()
    assert "for сосед in self.д.items" not in тело, (
        "подбор снова обходит весь каталог: это 98 % времени страницы")
    assert "обратные_коды(" in тело
    assert "возможные" in тело


def test_шесть_лучших_берутся_без_сортировки_всего():
    кусок = ТЕКСТ[ТЕКСТ.index("доказанные = [т for т in кандидаты"):]
    кусок = кусок[:кусок.index("итог: list[dict] = []")]
    assert "heapq.nsmallest(" in кусок
    assert ".sort(" not in кусок, "сортировка всего списка вернулась"


def test_обратный_индекс_живёт_тем_же_ключом_что_прямые_коды():
    """Иначе одна карта пережила бы доставку, а другая нет."""
    assert "def _ключ_снимка(" in ТЕКСТ
    чтение = ТЕКСТ[ТЕКСТ.index("def обратные_коды("):]
    чтение = чтение[:чтение.index("\ndef ", 1)]
    assert "_ключ_снимка(подробности)" in чтение
    прямые = ТЕКСТ[ТЕКСТ.index("def коды_соседей("):]
    прямые = прямые[:прямые.index("\ndef ", 1)]
    assert "_ключ_снимка(подробности, записи)" in прямые


