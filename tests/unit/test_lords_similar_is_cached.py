def test_коды_считаются_один_раз_на_снимок(модуль):
    """Второй вызов обязан вернуть ТОТ ЖЕ объект, а не равный ему."""
    подробности = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    первый = модуль.коды_соседей(подробности)
    второй = модуль.коды_соседей(подробности)
    assert первый is второй, "коды пересчитались на повторном вызове"
    assert первый["film-000"][0] == frozenset({"drama", "boevik"})
    # Страны у этой оснастки пусты намеренно: её помощник пишет поле
    # `country` строкой, а рантайм читает список `countries`. Коды стран
    # проверяются ниже, на снимке с настоящим полем.
    assert первый["film-000"][1] == frozenset()


def test_новый_снимок_коды_пересчитывает(модуль, tmp_path):
    """Доставка кладёт новый файл на то же место — коды обязаны обновиться."""
    подробности = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    первый = модуль.коды_соседей(подробности)
    # Другой снимок: иной путь и состав.
    другой_файл = tmp_path / "другие-details.json"
    другой_файл.write_text(
        '{"catalog_revision":"rev-2","details":{"film-000":'
        '{"slug":"film-000","genres":["Комедия"],"countries":["Франция"],'
        '"type":"movie","seasons":[]}}}', encoding="utf-8")
    другие = модуль.Подробности(str(другой_файл))
    второй = модуль.коды_соседей(другие)
    assert второй is not первый
    assert второй["film-000"][0] == frozenset({"komediya"})
    assert второй["film-000"][1] == frozenset({"franciya"})


# --- риски кеша: смена снимка, память, одновременность ----------------------

def test_замена_файла_по_тому_же_пути_сбрасывает_кеш(модуль, tmp_path):
    """Доставка кладёт новый снимок НА ТО ЖЕ МЕСТО.

    Ключ кеша включает время файла, поэтому путь остаётся прежним, а карта
    обязана пересобраться. Проверка именно этого случая: отдельный путь
    (другой файл) ничего не доказывает — так доставка не работает.
    """
    import os

    файл = Path(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    первый = модуль.коды_соседей(модуль.Подробности(str(файл)))
    было = файл.stat().st_mtime
    данные = json.loads(файл.read_text(encoding="utf-8"))
    данные["details"]["film-000"]["genres"] = ["Комедия"]
    файл.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
    os.utime(файл, (было + 60, было + 60))
    второй = модуль.коды_соседей(модуль.Подробности(str(файл)))
    assert второй is not первый
    assert второй["film-000"][0] == frozenset({"komediya"})


def test_память_не_копит_прежние_снимки(модуль, tmp_path):
    """После смены снимка в памяти остаётся ровно один набор кодов."""
    import os

    файл = Path(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    for сдвиг in (10, 20, 30):
        было = файл.stat().st_mtime
        os.utime(файл, (было + сдвиг, было + сдвиг))
        модуль.коды_соседей(модуль.Подробности(str(файл)))
    assert len(модуль._КОДЫ_СОСЕДЕЙ) == 1, (
        f"в памяти {len(модуль._КОДЫ_СОСЕДЕЙ)} наборов кодов вместо одного")


def test_всплеск_после_смены_снимка_строит_карту_один_раз(модуль):
    """Восемь одновременных запросов — одно построение, а не восемь.

    Без замка каждый поток строил свою карту: измерено 2026-10-17 на настоящем
    снимке — 6.33 с суммарно при 0.675 с на одно построение.
    """
    import threading

    модуль._КОДЫ_СОСЕДЕЙ.clear()
    счётчик = {"построений": 0}
    настоящий = модуль._построить_коды

    def считающий(записи, ключ):
        счётчик["построений"] += 1
        return настоящий(записи, ключ)

    модуль._построить_коды = считающий
    try:
        подробности = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
        потоки = [threading.Thread(
            target=lambda: модуль.коды_соседей(подробности)) for _ in range(8)]
        for п in потоки:
            п.start()
        for п in потоки:
            п.join()
    finally:
        модуль._построить_коды = настоящий
    assert счётчик["построений"] == 1, (
        f"карта построена {счётчик['построений']} раз вместо одного")


# --- поведение подбора: выдача не изменилась от ускорения -------------------
#
# Эквивалентность проверялась и вне тестов: на снимке живой витрины (64 508
# записей) снят эталон выдачи по 375 произведениям — включая записи без
# жанров, с одним жанром, с самым частым жанром «западный контент» и с
# наибольшим числом стран — и после правки сравнение дало НОЛЬ расхождений.
# Здесь тот же предмет закрепляется на малом снимке, где ожидаемое видно
# глазами.


def _вид(модуль, подробности_файл=None):
    д = модуль.Данные(модуль.КАТАЛОГ_ФАЙЛ)
    п = модуль.Подробности(подробности_файл or модуль.ПОДРОБНОСТИ_ФАЙЛ)
    индекс = модуль.построить_индекс(д, п)
    описание = (модуль.СЕМЕЙСТВА_1_1.get(модуль.СЕМЕЙСТВО)
                or модуль.СЕМЕЙСТВА_1_1["lords"])
    класс = модуль.ВИДЫ_1_1.get(описание["вид"], модуль.ВидЛордс)
    return класс(описание, д, п, индекс, "стенд"), индекс, п


def test_похожее_подбирается_по_совпавшему_жанру(модуль):
    """Все двенадцать записей оснастки делят оба жанра, поэтому похожих шесть
    и это не добор по виду."""
    вид, индекс, п = _вид(модуль)
    итог, мета = вид.похожие_с_мета(индекс["slug"]["film-000"],
                                    п.get("film-000"))
    слуги = [з["slug"] for з in итог]
    assert слуги == ["film-001", "film-002", "film-003", "film-004",
                     "film-005", "film-006"], слуги
    assert мета["heading"] == "Похожее"
    assert all("genre_overlap" in р for р in мета["reason_codes"])
    assert "film-000" not in слуги, "запись не может быть похожа на себя"


def test_без_жанров_и_стран_остаётся_добор_по_виду(модуль, tmp_path):
    """Отрицательный контроль: обратный индекс не должен лишать выдачи того,
    у кого совпадений нет вовсе. Прежний обход давал ему добор по виду, и это
    поведение сохраняется."""
    файл = tmp_path / "пустые-details.json"
    файл.write_text(
        '{"catalog_revision":"rev-3","details":{"film-000":'
        '{"slug":"film-000","genres":[],"countries":[],"type":"movie",'
        '"seasons":[]}}}', encoding="utf-8")
    вид, индекс, п = _вид(модуль, str(файл))
    итог, мета = вид.похожие_с_мета(индекс["slug"]["film-000"],
                                    п.get("film-000"))
    assert [з["slug"] for з in итог], "выдача опустела"
    assert мета["heading"] == "Ещё в каталоге"
    assert set(мета["reason_codes"]) == {"kind_fallback"}
