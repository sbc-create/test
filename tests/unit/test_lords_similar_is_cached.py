"""REQ-LORDS-SIMILAR-CACHE: коды соседей считаются раз на снимок, а не на запрос.

Измерено 2026-10-17 профилем на настоящем каталоге витрины (64 508 записей):
страница произведения собиралась 1.72 с, и почти всё это время уходило в
`похожие_с_мета` — он обходил весь каталог и пересчитывал коды жанров и стран
каждой записи (`транслит` вызывался 269 832 раза ЗА ОДИН запрос).

Снаружи это выглядело как 504. На узле витрина отдавала страницу строго по
очереди (1 запрос — 0.99 с, 16 одновременных — 15.12 с каждый), и при тридцати
одновременных предел nginx `proxy_read_timeout 30s` переставал выполняться.

Проверка требует двух вещей: коды берутся из разбора снимка, а не из обхода
каталога, и повторный вызов не пересчитывает их заново.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from lords_runtime_harness import (Стенд, выгрузить, загрузить, запись,
                                   подробность)

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")


def test_подбор_похожего_не_транслитерирует_каталог_на_каждом_запросе():
    """Корень дефекта: транслитерация внутри обхода каталога."""
    начало = ТЕКСТ.index("кандидаты: list[tuple[int, str, str, dict]] = []")
    конец = ТЕКСТ.index("кандидаты.sort(", начало)
    тело = ТЕКСТ[начало:конец]
    assert "транслит(" not in тело, (
        "в обходе каталога снова считается транслитерация: это секунда "
        "процессорного времени на каждый запрос страницы произведения")
    assert "коды_соседей(" in тело


@pytest.fixture()
def модуль(tmp_path, monkeypatch):
    стенд = Стенд(tmp_path, профиль="lords-films")
    записи = [запись(f"film-{н:03d}", title=f"Фильм {н}") for н in range(12)]
    детали = [подробность(f"film-{н:03d}", type_="movie",
                          genres=("Драма", "Боевик"), country="США")
              for н in range(12)]
    стенд.записать_каталог(записи)
    стенд.записать_подробности(детали)
    стенд.записать_плеер()
    м = загрузить(стенд, monkeypatch)
    try:
        yield м
    finally:
        выгрузить(м)


def test_коды_считаются_один_раз_на_снимок(модуль):
    """Второй вызов обязан вернуть ТОТ ЖЕ объект, а не равный ему."""
    подробности = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    первый = модуль.коды_соседей(подробности)
    второй = модуль.коды_соседей(подробности)
    assert первый is второй, "коды пересчитались на повторном вызове"
    assert первый["film-000"][0] == frozenset({"drama", "boevik"})
    # Страны у этой оснастки пусты намеренно: её помощник пишет поле
    # `country` строкой, а рантайм читает список `countries`. Коды стран
    # проверяются ниже, на снимке с настоящим полем.
    assert первый["film-000"][1] == frozenset()


def test_новый_снимок_коды_пересчитывает(модуль, tmp_path):
    """Доставка кладёт новый файл на то же место — коды обязаны обновиться."""
    подробности = модуль.Подробности(модуль.ПОДРОБНОСТИ_ФАЙЛ)
    первый = модуль.коды_соседей(подробности)
    # Другой снимок: иной путь и состав.
    другой_файл = tmp_path / "другие-details.json"
    другой_файл.write_text(
        '{"catalog_revision":"rev-2","details":{"film-000":'
        '{"slug":"film-000","genres":["Комедия"],"countries":["Франция"],'
        '"type":"movie","seasons":[]}}}', encoding="utf-8")
    другие = модуль.Подробности(str(другой_файл))
    второй = модуль.коды_соседей(другие)
    assert второй is not первый
    assert второй["film-000"][0] == frozenset({"komediya"})
    assert второй["film-000"][1] == frozenset({"franciya"})
