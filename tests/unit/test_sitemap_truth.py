def test_живые_адреса_структурно_чисты() -> None:
    записи = [запись(i) for i in range(50)]
    отчёт = проверить_адреса(записи, домен=ДОМЕН)
    assert отчёт.ok, отчёт.report()
    assert отчёт.счётчики["duplicates"] == 0


@pytest.mark.parametrize(
    "адрес, признак",
    [
        (f"http://{ДОМЕН}/a", "не https"),
        ("https://example.invalid/a", "чужой домен"),
        (f"https://{ДОМЕН}/a?utm=1", "параметрами"),
        (f"https://{ДОМЕН}/api/x", "служебный маршрут"),
    ],
)
def test_запрещённые_адреса(адрес: str, признак: str) -> None:
    отчёт = проверить_адреса([запись(1, loc=адрес)], домен=ДОМЕН)
    assert not отчёт.ok
    assert any(признак in н for н in отчёт.нарушения)


def test_дубли_ловятся() -> None:
    один = запись(1)
    отчёт = проверить_адреса([один, один], домен=ДОМЕН)
    assert not отчёт.ok
    assert отчёт.счётчики["duplicates"] == 1


# --- согласие карты с индексацией ----------------------------------------------

def test_адрес_в_карте_с_noindex_ловится() -> None:
    """Живой дефект: /catalog/schedule объявлен в карте и отдаёт noindex."""
    расписание = f"https://{ДОМЕН}/catalog/schedule"
    отчёт = проверить_согласие_с_индексацией(
        [запись(1, loc=расписание), запись(2)], noindex_адреса={расписание}
    )
    assert not отчёт.ok
    assert отчёт.счётчики["sitemap_noindex_conflicts"] == 1
    assert any("noindex" in н for н in отчёт.нарушения)


def test_карта_без_противоречий_проходит() -> None:
    отчёт = проверить_согласие_с_индексацией([запись(1)], noindex_адреса=set())
    assert отчёт.ok


def test_require_останавливает_релиз() -> None:
    отчёт = проверить_lastmod([запись(1, lastmod_source="build_time")], сейчас=СЕЙЧАС)
    with pytest.raises(SitemapTruthError, match="карта сайта"):
        require(отчёт)
