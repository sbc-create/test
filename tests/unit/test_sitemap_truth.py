"""Правила достоверности карты сайта и то, как они ловят найденные дефекты.

Проверки написаны от трёх измеренных фактов живой витрины ``yummyani.site``
(замер 2026-09-16, только чтение):

* 3479 адресов сезонов и эпизодов несут одну дату ``2026-08-21T00:00:00.000Z``
  — она же стоит в индексе карты, то есть это время сборки;
* ``images.xml`` содержит 7296 карточек из 7299, и причина трёх исключений
  нигде не записана;
* ``/catalog/schedule`` объявлен в карте и при этом отдаёт ``noindex``.

Каждый факт здесь превращён в правило. Проверки не требуют уникальной даты для
каждой страницы: одинаковые даты законны, когда за ними стоит одно и то же
подтверждённое событие.
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone

import pytest

from factory.seo.sitemap_truth import (
    SitemapTruthError,
    Запись,
    require,
    проверить_lastmod,
    проверить_адреса,
    проверить_изображения,
    проверить_согласие_с_индексацией,
)

ДОМЕН = "yummyani.site"
СЕЙЧАС = datetime(2026, 9, 16, 12, 0, 0, tzinfo=timezone.utc)


def запись(n: int, **kw) -> Запись:
    основа = {
        "loc": f"https://{ДОМЕН}/anime/title-{n}",
        "lastmod": "2026-09-04T08:00:52.000Z",
        "lastmod_source": "content_updated_at",
    }
    основа.update(kw)
    return Запись(**основа)


# --- дата изменения ------------------------------------------------------------

def test_массовая_заглушка_ловится() -> None:
    """Воспроизводит эпизоды: одна дата на весь шард."""
    записи = [запись(i, lastmod="2026-08-21T00:00:00.000Z", lastmod_source="build_time")
              for i in range(3449)]
    отчёт = проверить_lastmod(записи, сейчас=СЕЙЧАС, шард="episodes")
    assert not отчёт.ok
    assert any("массовая заглушка" in н for н in отчёт.нарушения)


def test_дата_из_времени_сборки_запрещена() -> None:
    отчёт = проверить_lastmod([запись(1, lastmod_source="build_time")], сейчас=СЕЙЧАС)
    assert not отчёт.ok
    assert any("время процесса" in н for н in отчёт.нарушения)


@pytest.mark.parametrize("источник", ["deploy_time", "current_time", "constant"])
def test_остальные_запрещённые_источники(источник: str) -> None:
    отчёт = проверить_lastmod([запись(1, lastmod_source=источник)], сейчас=СЕЙЧАС)
    assert not отчёт.ok


def test_происхождение_обязательно() -> None:
    """Неизвестную дату следует пропустить, а не подставить."""
    отчёт = проверить_lastmod([запись(1, lastmod_source="")], сейчас=СЕЙЧАС)
    assert not отчёт.ok
    assert any("происхождение" in н for н in отчёт.нарушения)


def test_пропущенная_дата_допустима() -> None:
    отчёт = проверить_lastmod([запись(1, lastmod=None, lastmod_source="")], сейчас=СЕЙЧАС)
    assert отчёт.ok, отчёт.report()
    assert отчёт.счётчики["without_lastmod"] == 1


def test_дата_из_будущего_запрещена() -> None:
    будущее = (СЕЙЧАС + timedelta(days=2)).strftime("%Y-%m-%dT%H:%M:%SZ")
    отчёт = проверить_lastmod([запись(1, lastmod=будущее)], сейчас=СЕЙЧАС)
    assert not отчёт.ok
    assert отчёт.счётчики["future_lastmod"] == 1


def test_неверный_формат_запрещён() -> None:
    отчёт = проверить_lastmod([запись(1, lastmod="21.08.2026")], сейчас=СЕЙЧАС)
    assert not отчёт.ok
    assert any("ISO 8601" in н for н in отчёт.нарушения)


def test_одинаковые_даты_допустимы_если_их_немного() -> None:
    """Одно подтверждённое событие на несколько адресов — законно."""
    записи = [запись(i) for i in range(6)] + [
        запись(100 + i, lastmod="2026-09-10T10:00:00Z") for i in range(6)
    ]
    отчёт = проверить_lastmod(записи, сейчас=СЕЙЧАС)
    assert отчёт.ok, отчёт.report()


def test_повторная_проверка_того_же_набора_даёт_тот_же_итог() -> None:
    """Дрейф даты без изменения данных = 0.

    Часы идут, набор не менялся — итог обязан совпасть. Две оговорки, обе
    выяснились на этом же тесте:

    * двадцать одинаковых дат сами по себе сработали бы как заглушка;
    * даты обязаны быть прошедшими, иначе сдвиг часов законно меняет число
      «дат из будущего», и проверка измеряла бы работу часов, а не дрейф.
    """
    записи = [
        запись(i, lastmod=f"2026-08-{1 + i % 28:02d}T08:00:52.000Z") for i in range(20)
    ]
    первый = проверить_lastmod(записи, сейчас=СЕЙЧАС)
    второй = проверить_lastmod(записи, сейчас=СЕЙЧАС + timedelta(days=30))
    assert первый.счётчики == второй.счётчики
    assert первый.ok and второй.ok


# --- изображения ---------------------------------------------------------------

def набор_изображений(всего: int, без_картинки: int, *, причина: str) -> list[Запись]:
    записи = [запись(i, image_loc=f"https://poster.cdnvideohub.com/{i}.webp")
              for i in range(всего - без_картинки)]
    записи += [запись(1000 + i, image_loc=None, image_excluded_reason=причина)
               for i in range(без_картинки)]
    return записи


def test_живое_расхождение_объяснено_проходит() -> None:
    """7296 из 7299: три карточки без исходного изображения, причина записана."""
    отчёт = проверить_изображения(набор_изображений(7299, 3, причина="нет исходного изображения"))
    assert отчёт.ok, отчёт.report()
    assert отчёт.счётчики["total_titles"] == 7299
    assert отчёт.счётчики["included"] == 7296
    assert отчёт.счётчики["excluded_with_reason"] == 3
    assert отчёт.счётчики["silent_omissions"] == 0
    assert отчёт.счётчики["eligible"] == 7296
    assert отчёт.счётчики["eligible_coverage_pct"] == 100


def test_молчаливое_исключение_ловится() -> None:
    """Сегодняшнее состояние: причина нигде не записана."""
    отчёт = проверить_изображения(набор_изображений(7299, 3, причина=""))
    assert not отчёт.ok
    assert отчёт.счётчики["silent_omissions"] == 3


def test_знаменатель_считается_от_всех_карточек() -> None:
    """Иначе доля равна 100% при любом числе потерь."""
    отчёт = проверить_изображения(набор_изображений(100, 40, причина="источник недоступен"))
    assert отчёт.счётчики["total_titles"] == 100
    assert отчёт.счётчики["eligible"] == 100, "недоступность источника не сужает знаменатель"
    assert отчёт.счётчики["eligible_coverage_pct"] == 60
    assert not отчёт.ok


def test_заглушка_в_карте_запрещена() -> None:
    записи = [запись(1, image_loc=f"https://{ДОМЕН}/opengraph-image")]
    отчёт = проверить_изображения(записи)
    assert not отчёт.ok
    assert any("заглушка" in н for н in отчёт.нарушения)


def test_изображение_не_по_https_запрещено() -> None:
    отчёт = проверить_изображения([запись(1, image_loc="http://poster.cdnvideohub.com/1.webp")])
    assert not отчёт.ok


