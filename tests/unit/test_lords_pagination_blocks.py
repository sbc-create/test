"""REQ-LORDS-PAGINATION: одна добавленная запись не переписывает весь сайт.

Замер на настоящем событии 3 сентября 2026: добавлена одна запись 2026 года
(«Вышка 2: Мёртвая точка»), перерисовано 8172 страницы из 9430, и три витрины
опубликовались через 8, 17 и 26 минут при сроке в пятнадцать.

Причина — сплошной срез: `items[(n-1)*24 : n*24]` сдвигает всё, что стоит после
вставленной записи. Здесь проверяется разбиение по блокам годов и, главное, то,
ради чего оно сделано: число затронутых страниц.

Договор: adr/0007-pagination-by-year-blocks.md.
"""

from __future__ import annotations

from dataclasses import dataclass

import pytest

from factory.lords import pagination


@dataclass(frozen=True)
class Запись:
    year: int | None
    name: str

    def __repr__(self) -> str:  # для читаемых расхождений
        return f"{self.year}:{self.name}"


def каталог(по_годам: dict[int | None, int]) -> list[Запись]:
    """Каталог порядком витрины: свежие годы раньше, внутри года — по имени."""
    записи: list[Запись] = []
    for год in sorted((y for y in по_годам if y), reverse=True):
        записи += [Запись(год, f"{год}-{i:04d}") for i in range(по_годам[год])]
    if None in по_годам:
        записи += [Запись(None, f"без-{i:04d}") for i in range(по_годам[None])]
    return записи


class TestБлокиГодов:
    def test_год_начинается_с_новой_страницы(self):
        страницы = pagination.страницы_по_годам(каталог({2026: 25, 2025: 10}), 24)
        assert [len(p) for p in страницы] == [24, 1, 10]
        assert {з.year for з in страницы[1]} == {2026}
        assert {з.year for з in страницы[2]} == {2025}

    def test_на_странице_записи_только_одного_года(self):
        страницы = pagination.страницы_по_годам(каталог({2026: 7, 2025: 7, 2024: 7}), 24)
        for страница in страницы:
            assert len({з.year for з in страница}) == 1

    def test_записи_без_года_идут_последним_блоком(self):
        страницы = pagination.страницы_по_годам(каталог({2026: 3, None: 3}), 24)
        assert [з.year for з in страницы[-1]] == [None, None, None]

    def test_пустых_страниц_не_бывает(self):
        страницы = pagination.страницы_по_годам(каталог({2026: 48, 2025: 1}), 24)
        assert all(страницы), страницы

    def test_пустой_список_даёт_одну_пустую_страницу(self):
        assert pagination.страницы_по_годам([], 24) == [[]]

    def test_размер_страницы_обязан_быть_положительным(self):
        with pytest.raises(ValueError):
            pagination.страницы_по_годам(каталог({2026: 5}), 0)


class TestСколькоСтраницПерерисовывается:
    """То, ради чего всё сделано."""

    СОСТАВ = {2026: 1950, 2025: 4426, 2024: 4048, 2023: 3840, 2022: 4448, None: 2749}

    def _добавить(self, записи: list[Запись], новая: Запись) -> list[Запись]:
        # Вставка в порядке витрины: свежие годы раньше, внутри года — по имени.
        ключ = lambda з: (-(з.year or 0), з.name)  # noqa: E731
        return sorted(записи + [новая], key=ключ)

    def test_сплошной_срез_переписывает_почти_всё(self):
        было = каталог(self.СОСТАВ)
        стало = self._добавить(было, Запись(2026, "2026-0000-новая"))
        затронуто = pagination.затронутые_страницы(
            pagination.сплошные_страницы(было, 24),
            pagination.сплошные_страницы(стало, 24),
        )
        всего = len(pagination.сплошные_страницы(стало, 24))
        # Ровно та беда, которая измерена на живом сайте: 87 % страниц.
        assert затронуто / всего > 0.8, (затронуто, всего)

    def test_блоки_годов_ограничивают_правку_одним_годом(self):
        было = каталог(self.СОСТАВ)
        стало = self._добавить(было, Запись(2026, "2026-0000-новая"))
        по_годам = pagination.затронутые_страницы(
            pagination.страницы_по_годам(было, 24),
            pagination.страницы_по_годам(стало, 24),
        )
        сплошь = pagination.затронутые_страницы(
            pagination.сплошные_страницы(было, 24),
            pagination.сплошные_страницы(стало, 24),
        )
        # Утверждение о сути, а не подогнанная доля: правка не выходит за блок
        # своего года. Блок 2026 — 1950 записей, то есть 82 страницы; сплошной
        # срез трогает всё, что стоит после вставки.
        блок_2026 = -(-self.СОСТАВ[2026] // 24) + 1
        assert по_годам <= блок_2026, (по_годам, блок_2026)
        assert по_годам * 8 < сплошь, (по_годам, сплошь)

    def test_запись_старого_года_не_трогает_свежие_страницы(self):
        было = каталог(self.СОСТАВ)
        стало = self._добавить(было, Запись(2022, "2022-0000-новая"))
        страницы_было = pagination.страницы_по_годам(было, 24)
        страницы_стало = pagination.страницы_по_годам(стало, 24)
        # Блоки 2026, 2025, 2024, 2023 стоят раньше и обязаны остаться теми же.
        граница = sum(1 for p in страницы_было if p and p[0].year and p[0].year > 2022)
        assert страницы_было[:граница] == страницы_стало[:граница]
        assert граница > 500  # блоки свежих годов действительно велики
