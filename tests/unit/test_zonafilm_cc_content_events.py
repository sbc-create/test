"""Синтетический прогон событий каталога zonafilm.cc.

Пять сценариев задания проверяются на сборке витрины, а не на живой выдаче:
собирается каталог из подставного снимка и смотрится, куда попала запись.
Производственные файлы при этом не трогаются вовсе — снимок свой, вывод в
tmp_path. Именно поэтому синтетика не может остаться в публичном каталоге:
она туда физически не попадает.

Сценарии:

1. добавление нового разрешённого тайтла;
2. обновление существующего тайтла;
3. добавление новой серии;
4. повторная доставка того же события;
5. некорректное событие.

Проверяется не «запись появилась», а то, что она появилась ТАМ, где обещано, и
не появилась там, где не обещано.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest

from factory.lords.nova_publish import PublishError, РеестрСлагов, загрузить_снимок, собрать_сайт

СНИМОК = Path("/srv/site-factory/repo/var/lords/lords/catalog-cache/lords-01.json")

pytestmark = pytest.mark.skipif(
    not СНИМОК.is_file(), reason="канонический снимок поставщика недоступен")


def _срез(фильмов: int = 90, сериалов: int = 30) -> list[dict]:
    """Небольшой срез настоящего снимка: тест должен идти секунды, а не минуты.

    Виды отбираются квотами, а не «первыми N по идентификатору». Первый вариант
    так и сделали — и в срез не попало ни одного сериала, отчего проверка новой
    серии пропускалась. Пропущенная проверка выглядит в отчёте почти как
    пройденная, и это худший из возможных исходов.
    """
    сырое = json.loads(СНИМОК.read_text(encoding="utf-8"))
    записи = sorted(сырое["items"], key=lambda з: str(з.get("external_id")))
    сериал = [з for з in записи if з.get("is_series") or з.get("type") == "tv"]
    фильм = [з for з in записи if not (з.get("is_series") or з.get("type") == "tv")]
    срез = фильм[:фильмов] + сериал[:сериалов]
    assert срез, "снимок не дал ни одной записи"
    return sorted(срез, key=lambda з: str(з.get("external_id")))


def _снимок_из(записи: list[dict], путь: Path):
    путь.write_text(json.dumps({"items": записи, "mark": "synthetic"}, ensure_ascii=False),
                    encoding="utf-8")
    return загрузить_снимок(путь)


def _собрать(записи: list[dict], tmp_path: Path, имя: str):
    снимок = _снимок_из(записи, tmp_path / f"{имя}.json")
    реестр = РеестрСлагов.загрузить(tmp_path / f"ledger-{имя}.json")
    кэш = tmp_path / "detail-cache"
    кэш.mkdir(exist_ok=True)
    каталог, подробности, ст = собрать_сайт(
        снимок=снимок, реестр=реестр, детали_кэш=кэш, site_id="zona-02",
        читатель=lambda _кэш, _ид: {})
    return каталог, подробности, ст


def _по_слагу(каталог: dict) -> dict[str, dict]:
    return {з["slug"]: з for з in каталог["items"]}


@pytest.fixture(scope="module")
def база() -> list[dict]:
    return _срез()


# ---------------------------------------------------------------------------
# 1. Новый тайтл
# ---------------------------------------------------------------------------
def test_новый_тайтл_попадает_в_каталог_и_наверх_недавних(база, tmp_path):
    исходный, _, _ = _собрать(база, tmp_path, "base")
    было = _по_слагу(исходный)

    новый = copy.deepcopy(база[0])
    новый["external_id"] = "synthetic-new-0001"
    новый["name"] = "Синтетическая новинка приёмки"
    новый["created_at"] = "2026-09-22T00:00:00Z"
    новый["updated_at"] = "2026-09-22T00:00:00Z"

    каталог, _, _ = _собрать(база + [новый], tmp_path, "new")
    стало = _по_слагу(каталог)

    добавленные = set(стало) - set(было)
    assert len(добавленные) == 1, f"ожидалась одна новая запись, получено {добавленные}"
    slug = добавленные.pop()

    # «Недавно добавленные» — это порядок по published_at, и он обязан брать
    # created_at поставщика, а не время изменения файла.
    assert стало[slug]["published_at"] == "2026-09-22T00:00:00Z"
    assert стало[slug]["published_at_estimated"] is False

    порядок = [з["slug"] for з in каталог["items"]]
    assert порядок[0] == slug, (
        "самая свежая по created_at запись обязана быть первой: именно этот "
        "порядок читает блок «Недавно добавленные»")


def test_запись_без_даты_поставщика_помечена_оценочной(база, tmp_path):
    """Отсутствие даты не подменяется «сейчас»: выдуманная дата — выдуманный факт."""
    безымянный = copy.deepcopy(база[0])
    безымянный["external_id"] = "synthetic-nodate-0001"
    безымянный["name"] = "Синтетическая запись без даты"
    безымянный.pop("created_at", None)

    каталог, _, _ = _собрать(база + [безымянный], tmp_path, "nodate")
    запись = next(з for з in каталог["items"]
                  if з["title"] == "Синтетическая запись без даты")
    assert запись["published_at_estimated"] is True


# ---------------------------------------------------------------------------
# 2. Обновление существующего
# ---------------------------------------------------------------------------
def test_обновление_не_выдаёт_себя_за_новое_добавление(база, tmp_path):
    """Правка описания не имеет права поднять тайтл в «недавно добавленные»."""
    исходный, _, _ = _собрать(база, tmp_path, "upd-base")
    первый_slug = исходный["items"][0]["slug"]

    обновлённые = copy.deepcopy(база)
    цель = min(обновлённые, key=lambda з: str(з.get("created_at") or ""))
    цель["updated_at"] = "2026-09-22T23:59:59Z"
    цель["name"] = (цель.get("name") or "") + " (обновлено)"

    каталог, _, _ = _собрать(обновлённые, tmp_path, "upd")
    assert каталог["items"][0]["slug"] == первый_slug, (
        "обновление старой записи изменило порядок недавних: блок «последние "
        "добавления» начал показывать последние ИЗМЕНЕНИЯ")


# ---------------------------------------------------------------------------
# 3. Новая серия
# ---------------------------------------------------------------------------
def test_новая_серия_не_создаёт_второй_записи_тайтла(база, tmp_path):
    """Серия принадлежит тайтлу. Новая серия не имеет права породить дубликат."""
    сериалы = [з for з in база if з.get("is_series") or з.get("type") == "tv"]
    assert сериалы, "срез обязан содержать сериалы: иначе проверка серии не выполняется"
    исходный, _, _ = _собрать(база, tmp_path, "ep-base")
    было = _по_слагу(исходный)

    обновлённые = copy.deepcopy(база)
    цель = next(з for з in обновлённые
                if str(з.get("external_id")) == str(сериалы[0].get("external_id")))
    цель["updated_at"] = "2026-09-22T12:00:00Z"
    цель.setdefault("playback", {})["episode_published_at"] = "2026-09-22T12:00:00Z"

    каталог, _, _ = _собрать(обновлённые, tmp_path, "ep")
    стало = _по_слагу(каталог)
    assert set(стало) == set(было), "появление серии изменило состав каталога тайтлов"
    assert len(каталог["items"]) == len({з["slug"] for з in каталог["items"]}), \
        "в каталоге появились дубликаты"


# ---------------------------------------------------------------------------
# 4. Повторная доставка
# ---------------------------------------------------------------------------
def test_повторная_доставка_того_же_события_идемпотентна(база, tmp_path):
    новый = copy.deepcopy(база[0])
    новый["external_id"] = "synthetic-dup-0001"
    новый["name"] = "Синтетическая запись для повтора"
    новый["created_at"] = "2026-09-22T01:00:00Z"

    первый, п1, _ = _собрать(база + [новый], tmp_path, "dup1")
    # Та же запись доставлена второй раз: поставщик прислал дубль события.
    второй, п2, _ = _собрать(база + [новый, copy.deepcopy(новый)], tmp_path, "dup2")

    assert len(первый["items"]) == len(второй["items"]), "повтор события удвоил запись"
    assert [з["slug"] for з in первый["items"]] == [з["slug"] for з in второй["items"]]
    assert json.dumps(первый, ensure_ascii=False, sort_keys=True) == \
           json.dumps(второй, ensure_ascii=False, sort_keys=True), \
        "повторная доставка изменила каталог: сборка не идемпотентна"


# ---------------------------------------------------------------------------
# 5. Некорректное событие
# ---------------------------------------------------------------------------
def test_запись_без_идентификатора_прекращает_сборку_а_не_публикуется(база, tmp_path):
    битое = copy.deepcopy(база[0])
    битое.pop("external_id", None)
    битое.pop("id", None)
    битое["name"] = "Синтетическое битое событие"
    путь = tmp_path / "broken.json"
    путь.write_text(json.dumps({"items": база + [битое]}, ensure_ascii=False),
                    encoding="utf-8")
    with pytest.raises(PublishError) as excinfo:
        загрузить_снимок(путь)
    assert "идентификатор" in str(excinfo.value)


def test_непроецируемая_запись_отклоняется_и_попадает_в_отказы(база, tmp_path):
    """Отклонение обязано быть видно в статистике, а не проглочено молча."""
    битое = {"external_id": "synthetic-bad-0001", "name": None, "type": None,
             "created_at": "не-дата", "year": "позапрошлый"}
    каталог, _, ст = _собрать(база + [битое], tmp_path, "bad")
    опубликованные = {з["title"] for з in каталог["items"]}
    assert "synthetic-bad-0001" not in опубликованные
    assert all(з.get("title") for з in каталог["items"]), \
        "в каталог попала запись без названия — пустая карточка"
    assert all(з.get("url", "").startswith("/title/") for з in каталог["items"])
    # Отказ обязан быть посчитан: молчаливый пропуск и молчаливая публикация
    # одинаково плохи тем, что о них никто не узнает.
    assert ст["отказы"].get("empty_title") == 1, f"отказ не записан: {ст['отказы']}"


