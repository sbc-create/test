def test_синтетика_не_попала_в_опубликованный_каталог():
    опубликованный = Path("/srv/lords/.frontend/zona-02-catalog.json")
    if not опубликованный.is_file():
        pytest.skip("витрина zona-02 не развёрнута")
    текст = опубликованный.read_text(encoding="utf-8")
    for метка in ("synthetic-", "Синтетическая"):
        assert метка not in текст, f"в публичном каталоге найдена метка {метка}"
