def test_загрузчик_разрешается_в_момент_вызова(monkeypatch):
    """Контроль на ошибку инструмента, а не карты.

    `загрузчик=взять` в объявлении связало бы исходную функцию навсегда, и
    подмена `взять` перестала бы действовать: проверки молча ушли бы в сеть.
    Именно так и вышло при первом прогоне — четыре проверки повисли на
    реальном запросе. Признак: после подмены `взять` сеть не нужна.
    """
    звонки = []

    def подменный(url, таймаут=180):
        звонки.append(url)
        return _индекс([]) if url.endswith("/sitemap.xml") else ""

    monkeypatch.setattr(ИНСТР, "взять", подменный)
    снимок = ИНСТР.снять(Д)
    assert снимок["ok"] is True
    assert звонки == [f"https://{Д}/sitemap.xml"]


