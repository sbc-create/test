"""Защита от повторения дефектов карты: сверка с эталоном и признак обрыва.

Повод — MOD-103 и MOD-106, измеренные 20.10 на yummyani.site. Соседние
инструменты проверяют текущий ответ и ПАМЯТИ НЕ ИМЕЮТ: ни один не умеет сказать
«вчера этот адрес в карте был, сегодня его нет». Защита от повторения состоит
именно в этом, поэтому проверяется в обе стороны.

Отрицательные контроли, названные заранее:

* часть ровно на 50 000 адресов, у которой продолжение В ИНДЕКСЕ ЕСТЬ, провалом
  не считается — иначе законно разделённая карта читалась бы как обрыв;
* рост числа адресов провалом не считается: карта имеет право расти, и
  исправление покрытия обязано её увеличить;
* работа, у которой серии есть, а адресов сезонов в карте нет, даёт
  «НЕ ИЗМЕРЕНО», а не провал — отсутствие части это другой дефект, и подменять
  им проверку соответствия значит получить проверку, падающую не на том, что
  она проверяет;
* ПУСТОЙ перечень названных адресов даёт код 2, а не успех: проверка, которой
  нечего проверять, утверждать «всё на месте» не имеет права;
* недоступная карта даёт код 2, а не 0 и не 1.

Сеть не используется: загрузчик подменяется.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "sitemap_regression_guard",
    КОРЕНЬ / "automation/local/sitemap-regression-guard.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)

Д = "x.site"


def _индекс(имена):
    блоки = "".join(
        f"<sitemap><loc>https://{Д}/sitemap/{и}.xml</loc></sitemap>"
        for и in имена)
    return f"<sitemapindex>{блоки}</sitemapindex>"


def _urlset(пути):
    return "<urlset>" + "".join(
        f"<url><loc>https://{Д}{п}</loc></url>" for п in пути) + "</urlset>"


def _загрузчик(карта: dict):
    def достать(url, **к):
        for ключ, тело in карта.items():
            if url.endswith(ключ):
                return тело
        return ""
    return достать


def _снимок(части: dict):
    """части: {'titles': ['/anime/a/'], ...} → снимок как его даёт `снять`."""
    карта = {"/sitemap.xml": _индекс(list(части))}
    for имя, пути in части.items():
        карта[f"/sitemap/{имя}.xml"] = _urlset(пути)
    return ИНСТР.снять(Д, загрузчик=_загрузчик(карта))


