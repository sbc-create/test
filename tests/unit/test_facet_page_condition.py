"""Canonical второй страницы фасета обязан нести И номер, И условие отбора.

Повод — дыра в собственной мере, найденная до того, как она что-то пропустила.
Проверка п.3 спрашивала подстроку: `"page=2" in canonical`. Для раздела этого
довольно, для ФАСЕТА — нет. Если правка донесёт номер страницы, но потеряет
условие отбора, `/year/2024/?page=2` объявит канонической `/catalog/?page=2` —
вторую страницу КАТАЛОГА, с другим составом. Подстрока `page=2` при этом на
месте, и прежняя проверка сказала бы «canonical на себя».

Случай не выдуманный. У `zonafilm.cc` перечень разрешённых параметров и
разбор условия из пути — два РАЗНЫХ места в коде витрины, и правка одного без
другого даёт ровно такой canonical. Я назвал этот случай SEO-сессии как
опасный и только потом заметил, что сам его не мерил.

Проверяется составом, а не именем параметра: имена условий у семейств разные
(`year`, `country`, `genre`), а «цель показывает то же» значит одно и то же
везде. Заодно это ловит случай, когда условие в адресе есть, но витрина его
не применила.

Сеть мерится без сети: `достать` подменяется таблицей ответов.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "local" / "public-acceptance.py"

ФАСЕТ = "https://x.test/year/2024/"
ПУСТО = "<html></html>"


def _карточки(префикс: str, сколько: int = 48) -> str:
    return "".join(f'<a href="/title/{префикс}-{i}">' for i in range(сколько))


def _страница(канон: str, префикс: str, сколько: int = 48) -> str:
    return (f'<link rel="canonical" href="{канон}"/>'
            + _карточки(префикс, сколько))


def _модуль():
    спец = importlib.util.spec_from_file_location("public_acceptance", СЦЕНАРИЙ)
    м = importlib.util.module_from_spec(спец)
    sys.modules["public_acceptance"] = м
    спец.loader.exec_module(м)
    return м


class Сеть:
    def __init__(self, таблица: dict):
        self.таблица = таблица

    def __call__(self, url: str, таймаут: int = 45):
        код, тело, итоговый = self.таблица.get(url, ("404", ПУСТО, url))
        return код, тело, {"итоговый-адрес": итоговый}


def прогнать(канон_второй: str, цели: dict | None = None):
    """Нормы фасета `/year/2024/` при заданном canonical второй страницы."""
    м = _модуль()
    таблица = {
        ФАСЕТ: ("200", _страница(ФАСЕТ, "facet"), ФАСЕТ),
        ФАСЕТ + "?page=1": ("200", _страница(ФАСЕТ, "facet"), ФАСЕТ),
        ФАСЕТ + "?page=2": ("200", _страница(канон_второй, "facet2"),
                            ФАСЕТ + "?page=2"),
        ФАСЕТ + "?page=9999": ("404", ПУСТО, ФАСЕТ + "?page=9999"),
        ФАСЕТ + "?page=0": ("404", ПУСТО, ФАСЕТ + "?page=0"),
        ФАСЕТ + "?page=-1": ("404", ПУСТО, ФАСЕТ + "?page=-1"),
        ФАСЕТ + "?page=abc": ("404", ПУСТО, ФАСЕТ + "?page=abc"),
    }
    таблица.update(цели or {})
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_раздела("x.test", "/year/2024/",
                    lambda имя, ок, п: шаги.append((имя, ок, п)))
    return шаги


def найти(шаги, часть: str):
    подходящие = [ш for ш in шаги if часть in ш[0]]
    assert len(подходящие) == 1, [ш[0] for ш in шаги]
    return подходящие[0]


def test_canonical_на_себя_условие_нести_не_обязан():
    """`/year/2024/?page=2` → сам себя: условие в пути, проверять нечего."""
    шаги = прогнать(ФАСЕТ + "?page=2")
    assert not [ш for ш in шаги if "несёт условие отбора" in ш[0]]
    _имя, ок, _п = найти(шаги, "canonical страницы 2 (п.3)")
    assert ок is True


def test_номер_дошёл_а_условие_нет_это_расхождение():
    """Тот самый тихий случай: подстрока page=2 на месте, состав чужой."""
    чужая = "https://x.test/catalog/?page=2"
    шаги = прогнать(чужая, {чужая: ("200", _страница(чужая, "catalog2"),
                                    чужая)})
    _имя, ок, подробно = найти(шаги, "несёт условие отбора")
    assert ок is False, подробно
    assert "СОСТАВ РАЗНЫЙ" in подробно
    assert "условие отбора нет" in подробно
    # И отдельно: прежняя проверка п.3 этот canonical пропускает — показываем,
    # что новая норма не дублирует её, а закрывает её дыру.
    _и, ок3, _п = найти(шаги, "canonical страницы 2 (п.3)")
    assert ок3 is True


def test_номер_и_условие_дошли_оба_это_норма():
    цель = "https://x.test/catalog/?year=2024&page=2"
    шаги = прогнать(цель, {цель: ("200", _страница(цель, "facet2"), цель)})
    _имя, ок, подробно = найти(шаги, "несёт условие отбора")
    assert ок is True, подробно
    assert "тот же состав" in подробно


def test_цель_не_отвечающая_двумястами_это_расхождение():
    цель = "https://x.test/catalog/?year=2024&page=2"
    шаги = прогнать(цель)  # цели в таблице нет → 404
    _имя, ок, подробно = найти(шаги, "несёт условие отбора")
    assert ок is False
    assert "не отвечает 200" in подробно


def test_состав_сверяется_по_слагам_а_не_по_числу():
    """У каталога и у фасета может быть по 48 карточек — разных."""
    чужая = "https://x.test/catalog/?page=2"
    шаги = прогнать(чужая, {чужая: ("200", _страница(чужая, "catalog2", 48),
                                    чужая)})
    _имя, ок, подробно = найти(шаги, "несёт условие отбора")
    assert ок is False
    assert "карточек на странице 48, у цели 48" in подробно
    assert "общих 0" in подробно


def test_условие_в_адресе_есть_но_витрина_его_не_применила():
    """Адрес верный, состав каталожный — тоже расхождение.

    Проверка по имени параметра такое пропустила бы: `year=2024` в адресе
    стоит. Сверка состава видит, что отбор не применён.
    """
    цель = "https://x.test/catalog/?year=2024&page=2"
    шаги = прогнать(цель, {цель: ("200", _страница(цель, "catalog2"), цель)})
    _имя, ок, подробно = найти(шаги, "несёт условие отбора")
    assert ок is False
    assert "СОСТАВ РАЗНЫЙ" in подробно


def test_у_нефасетного_раздела_нормы_нет():
    """У `/catalog/` терять в canonical нечего — лишний запрос не делается."""
    м = _модуль()
    основа = "https://x.test/catalog/"
    чужая = "https://x.test/other/?page=2"
    таблица = {
        основа: ("200", _страница(основа, "cat"), основа),
        основа + "?page=1": ("200", _страница(основа, "cat"), основа),
        основа + "?page=2": ("200", _страница(чужая, "cat2"),
                             основа + "?page=2"),
        основа + "?page=9999": ("404", ПУСТО, основа + "?page=9999"),
        основа + "?page=0": ("404", ПУСТО, основа + "?page=0"),
        основа + "?page=-1": ("404", ПУСТО, основа + "?page=-1"),
        основа + "?page=abc": ("404", ПУСТО, основа + "?page=abc"),
    }
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_раздела("x.test", "/catalog/",
                    lambda и, ок, п: шаги.append((и, ок, п)))
    assert not [ш for ш in шаги if "несёт условие отбора" in ш[0]]


def test_второй_страницы_нет_норма_не_применяется():
    м = _модуль()
    таблица = {
        ФАСЕТ: ("200", _страница(ФАСЕТ, "facet"), ФАСЕТ),
        ФАСЕТ + "?page=1": ("200", _страница(ФАСЕТ, "facet"), ФАСЕТ),
        ФАСЕТ + "?page=2": ("404", ПУСТО, ФАСЕТ + "?page=2"),
    }
    м.достать = Сеть(таблица)
    шаги: list[tuple[str, bool, str]] = []
    м.нормы_раздела("x.test", "/year/2024/",
                    lambda и, ок, п: шаги.append((и, ок, п)))
    assert not [ш for ш in шаги if "несёт условие отбора" in ш[0]]
    _и, ок, подробно = найти(шаги, "canonical страницы 2 (п.3)")
    assert ок is True
    assert "второй страницы нет" in подробно
