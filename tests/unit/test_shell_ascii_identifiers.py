"""Имена переменных и функций в shell-скриптах фабрики — только ASCII.

Bash считает именем переменной лишь ``[A-Za-z_][A-Za-z0-9_]*``. Строка
``СУХОЙ=0`` для него не присваивание, а попытка выполнить команду с таким
именем, и падает она только в момент запуска::

    activate.sh: line 18: СУХОЙ=0: command not found

``bash -n`` этого не ловит: синтаксически там законный вызов команды. Проверка
живёт отдельно именно поэтому — она смотрит на то, чего разбор синтаксиса не
видит.

Ограничение касается только идентификаторов: русские сообщения, комментарии и
значения не трогаются, иначе эксплуатационные скрипты пришлось бы переписать
на английский без всякой пользы.

Проверка появилась в репозиториях выделенных сайтов, а дефект родом отсюда —
и при первой же правке ``lords-staging-apply.sh`` в монорепозитории снова
возникло кириллическое имя массива. Поэтому она стоит и здесь.
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]

#: Присваивание в начале строки и любое обращение через $ или ${...}.
ПРИСВАИВАНИЕ = re.compile(r"^\s*(?:export\s+|local\s+|declare\s+|readonly\s+)?"
                          r"([^\s=]*[^\x00-\x7F][^\s=]*)=")
ОБРАЩЕНИЕ = re.compile(r"\$\{?([A-Za-z_]*[^\x00-\x7F][^\s}/:\-]*)")
ФУНКЦИЯ = re.compile(r"^\s*(?:function\s+)?([^\s()]*[^\x00-\x7F][^\s()]*)\s*\(\s*\)")

ПРАВИЛА = ((ПРИСВАИВАНИЕ, "присваивание"), (ОБРАЩЕНИЕ, "обращение"),
           (ФУНКЦИЯ, "объявление функции"))


#: Начало heredoc: `<< EOF`, `<<-'EOF'`, `<<"EOF"`. Запоминаем и метку, и
#: то, была ли она в кавычках: от этого зависит, подставляет bash переменные
#: внутри или нет.
HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")


def беды_файла(текст: str, имя: str) -> list[str]:
    """Беды ТОЛЬКО в коде оболочки.

    Тело heredoc кодом оболочки не является: там лежат либо данные, либо
    программа на другом языке. Присваивание `плохо.append("host=…")` на Python
    внутри `<<'PY' … PY` bash вообще не разбирает, а проверка считала его
    кириллическим именем переменной — ложное срабатывание на исправном файле
    (измерено на automation/srv-qwen/connect-site-factory-bridge.sh).

    Различие между кавычками сохранено: внутри НЕЗАКАВЫЧЕННОГО heredoc bash
    подставляет переменные, поэтому обращение к не-ASCII имени там — настоящий
    дефект (подставится пустая строка), и его проверка продолжает ловить.
    """
    найдено = []
    метка = None          # ожидаемая закрывающая метка heredoc
    закавычена = False
    for номер, строка in enumerate(текст.splitlines(), 1):
        if метка is not None:
            if строка.strip() == метка:
                метка = None
                закавычена = False
                continue
            if закавычена:
                continue
            # Незакавыченный heredoc: подстановка идёт, присваиваний нет.
            for найденное in ОБРАЩЕНИЕ.findall(строка.split("#", 1)[0]):
                найдено.append(
                    f"{имя}:{номер}: обращение к не-ASCII имени {найденное!r}")
            continue
        без_комментария = строка.split("#", 1)[0]
        for правило, что in ПРАВИЛА:
            for найденное in правило.findall(без_комментария):
                найдено.append(f"{имя}:{номер}: {что} к не-ASCII имени {найденное!r}")
        начало = HEREDOC.search(без_комментария)
        if начало:
            закавычена = bool(начало.group(1))
            метка = начало.group(2)
    return найдено


def скрипты() -> list[Path]:
    исключить = {".git", ".venv", "var", "node_modules", "knowledge"}
    return sorted(p for p in КОРЕНЬ.rglob("*.sh")
                  if not (исключить & set(p.relative_to(КОРЕНЬ).parts)))


def test_скрипты_найдены():
    """Пустой список означал бы, что проверка ничего не проверяет."""
    assert len(скрипты()) >= 5


@pytest.mark.parametrize("путь", скрипты(), ids=lambda p: str(p.relative_to(КОРЕНЬ)))
def test_имена_в_shell_только_ascii(путь: Path):
    беды = беды_файла(путь.read_text(encoding="utf-8"), str(путь.relative_to(КОРЕНЬ)))
    assert not беды, "\n".join(беды)


def test_проверка_ловит_то_чего_не_ловит_bash_n(tmp_path: Path):
    """Доказательство, что проверка не дублирует `bash -n`.

    Без этого теста легко поверить, что синтаксической проверки достаточно —
    именно эта вера и пропустила дефект в production.
    """
    плохой = tmp_path / "broken.sh"
    плохой.write_text("#!/usr/bin/env bash\nset -euo pipefail\nСУХОЙ=0\necho \"$СУХОЙ\"\n",
                      encoding="utf-8")

    разбор = subprocess.run(["bash", "-n", str(плохой)], capture_output=True, text=True)
    assert разбор.returncode == 0, "bash -n внезапно стал ловить это сам"

    запуск = subprocess.run(["bash", str(плохой)], capture_output=True, text=True)
    assert запуск.returncode != 0
    assert "command not found" in запуск.stderr

    assert беды_файла(плохой.read_text(encoding="utf-8"), "broken.sh")


def test_тело_heredoc_не_считается_кодом_оболочки(tmp_path: Path):
    """Python внутри `<<'PY'` — не присваивание bash.

    Ложное срабатывание измерено на живом файле: строка
    `плохо.append("host=...")` внутри heredoc попала в отчёт как кириллическое
    имя переменной, и сторож покраснел на исправном скрипте. Сторож, который
    кричит на правильный код, перестают слушать — а он здесь единственный, кто
    видит дефект, невидимый для `bash -n`.
    """
    файл = tmp_path / "with_heredoc.sh"
    файл.write_text(
        "#!/usr/bin/env bash\n"
        "python3 - <<'PY'\n"
        "плохо = []\n"
        'плохо.append("host=нет")\n'
        "PY\n", encoding="utf-8")
    assert беды_файла(файл.read_text(encoding="utf-8"), "with_heredoc.sh") == []


def test_подстановка_в_незакавыченном_heredoc_всё_ещё_ловится(tmp_path: Path):
    """Там bash подставляет переменные, и не-ASCII имя даст пустую строку."""
    файл = tmp_path / "unquoted.sh"
    файл.write_text(
        "#!/usr/bin/env bash\n"
        "cat <<EOF\n"
        "значение: $ИМЯ\n"
        "EOF\n", encoding="utf-8")
    беды = беды_файла(файл.read_text(encoding="utf-8"), "unquoted.sh")
    assert беды and "обращение" in беды[0], беды


def test_код_после_heredoc_снова_проверяется(tmp_path: Path):
    """Закрывающая метка возвращает проверку в силу."""
    файл = tmp_path / "after.sh"
    файл.write_text(
        "#!/usr/bin/env bash\n"
        "cat <<'PY'\n"
        "это данные\n"
        "PY\n"
        "СУХОЙ=0\n", encoding="utf-8")
    беды = беды_файла(файл.read_text(encoding="utf-8"), "after.sh")
    assert беды and "присваивание" in беды[0], беды


# --- Команды, которые отдаются ВЛАДЕЛЬЦУ -----------------------------------
#
# Тот же дефект, но дороже. 2026-10-15 в `docs/OWNER_HTTPS_WWW_20261015.md`
# порядок операции был написан с переменными `Д=`, `Ф=`, `Р=`: владелец
# скопировал бы это в bash и получил «command not found» на первой же строке —
# посреди правки живого nginx, без подсказки, что сломалось. Скрипты
# репозитория такую ошибку ловят с четвёртого раза за сутки; документы не ловил
# никто.

#: Блок кода оболочки в Markdown: ```bash … ``` или ```sh … ```.
БЛОК_ОБОЛОЧКИ = re.compile(r"```(?:bash|sh|shell)\n(.*?)```", re.S)


def документы() -> list[Path]:
    исключить = {".git", ".venv", "var", "node_modules", "knowledge"}
    return sorted(p for p in (КОРЕНЬ / "docs").rglob("*.md")
                  if not (исключить & set(p.relative_to(КОРЕНЬ).parts)))


def документы_с_командами() -> list[Path]:
    return [п for п in документы()
            if БЛОК_ОБОЛОЧКИ.search(п.read_text(encoding="utf-8"))]


def test_документы_с_командами_найдены():
    """Пустой список означал бы, что проверка ничего не проверяет."""
    assert len(документы_с_командами()) >= 5


@pytest.mark.parametrize("путь", документы_с_командами(),
                         ids=lambda p: str(p.relative_to(КОРЕНЬ)))
def test_команды_в_документах_только_ascii(путь: Path):
    """Команда из документа обязана работать при копировании как есть."""
    беды: list[str] = []
    текст = путь.read_text(encoding="utf-8")
    for м in БЛОК_ОБОЛОЧКИ.finditer(текст):
        строка_блока = текст[:м.start()].count("\n") + 2
        for сдвиг, строка in enumerate(м.group(1).split("\n")):
            # Комментарий кодом не является: пояснения по-русски нужны.
            if строка.strip().startswith("#"):
                continue
            # Одинарные кавычки bash не раскрывает: имя ветки, которое так и
            # называется (её создала прежняя ошибка этого же рода), обращением
            # к переменной не является. Иначе проверка требовала бы переписать
            # ДАННЫЕ, с которыми владельцу и надо работать.
            строка = re.sub(r"'[^']*'", "''", строка)
            for правило, что in ПРАВИЛА:
                н = правило.search(строка)
                if н:
                    беды.append(
                        f"{путь.relative_to(КОРЕНЬ)}:{строка_блока + сдвиг}: "
                        f"{что} {н.group(1)!r} — bash так не умеет")
    assert not беды, "\n".join(беды)


def test_проверка_документов_ловит_кириллическое_имя(tmp_path: Path):
    """Доказательство, что проверка выше не проходит мимо дефекта."""
    док = tmp_path / "operation.md"
    док.write_text("Порядок:\n\n```bash\nД=zonafilm.cc\nnginx -t\n```\n",
                   encoding="utf-8")
    блок = БЛОК_ОБОЛОЧКИ.search(док.read_text(encoding="utf-8"))
    assert блок
    строки = [с for с in блок.group(1).split("\n")
              if not с.strip().startswith("#")]
    найдено = [п.search(с) for с in строки for п, _ in ПРАВИЛА if п.search(с)]
    assert найдено, "кириллическое присваивание в документе не поймано"
