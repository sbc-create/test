"""Вырезка блока характеристик: главное свойство — сквозное меню в неё не попадает.

Признак жанровых ссылок карточки дважды дал неверный ответ, пока мерил страницу
целиком, и оба раза ответ выглядел правдоподобным:

1. совпали наборы жанровых ссылок у двух карточек — но это были две индийские
   драмы с одними жанрами, а не сквозной блок;
2. вычитание сквозного блока убирало жанр, который И в меню, И свой у тайтла.

Поэтому блок вырезается разбором разметки. Проверяется и то, что в него
попадает, и то, что НЕ попадает: без второго вырезка ничего не решает.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "automation" / "local"))
import card_facts_block as блок_модуль  # noqa: E402


def test_меню_вне_блока_не_попадает_в_вырезку():
    """Главное свойство. Без него признак мерит страницу, а не карточку."""
    тело = (
        '<nav class="menu"><a href="/genre/anime/">аниме</a>'
        '<a href="/genre/drama/">драма</a></nav>'
        '<dl class="facts"><div><dt>Жанр</dt>'
        '<dd><a href="/genre/horror/">ужасы</a></dd></div></dl>'
    )
    разметка, имя = блок_модуль.блок(тело)
    assert имя == "facts"
    assert "/genre/horror/" in разметка
    assert "/genre/anime/" not in разметка, "сквозное меню попало в блок"
    assert "/genre/drama/" not in разметка


def test_свой_жанр_совпадающий_с_меню_остаётся():
    """Обратная сторона: вычитание меню убивало именно этот случай."""
    тело = (
        '<nav class="menu"><a href="/genre/drama/">драма</a></nav>'
        '<dl class="facts"><div><dt>Жанр</dt>'
        '<dd><a href="/genre/drama/">драма</a></dd></div></dl>'
    )
    разметка, _ = блок_модуль.блок(тело)
    assert "/genre/drama/" in разметка, "свой жанр потерян из-за совпадения с меню"


def test_вложенность_не_обрывает_блок_раньше_времени():
    тело = ('<dl class="facts"><div><dt>Жанр</dt><dd><span><b>'
            '<a href="/genre/x/">x</a></b></span></dd></div>'
            '<div><dt>Год</dt><dd><a href="/year/2026/">2026</a></dd></div></dl>'
            '<a href="/genre/после/">после</a>')
    разметка, _ = блок_модуль.блок(тело)
    assert "/genre/x/" in разметка and "/year/2026/" in разметка
    assert "/genre/после/" not in разметка, "блок не закрылся на своём теге"


def test_пустые_элементы_не_ломают_глубину():
    """`<img>` и `<br>` без закрывающего тега: глубину они не увеличивают."""
    тело = ('<div class="ag-facts"><img src="a.png"><br>'
            '<a href="/genre/y/">y</a></div><a href="/genre/вне/">вне</a>')
    разметка, имя = блок_модуль.блок(тело)
    assert имя == "ag-facts"
    assert "/genre/y/" in разметка
    assert "/genre/вне/" not in разметка


def test_несколько_контейнеров_берётся_самый_объёмный():
    тело = ('<div class="facts">краткий</div>'
            '<div class="facts"><a href="/genre/z/">z</a> и ещё много текста '
            'для объёма, чтобы этот блок был длиннее первого</div>')
    разметка, _ = блок_модуль.блок(тело)
    assert "/genre/z/" in разметка


def test_неизвестный_контейнер_это_отказ_а_не_ноль():
    """None и «ноль связей» — разные утверждения.

    Из неизвестной разметки не следует, что связей нет: следует, что мерить
    нечем. Это та же разница, что между «не измерено» и «нуль».
    """
    тело = '<div class="новая-разметка"><a href="/genre/q/">q</a></div>'
    assert блок_модуль.блок(тело) is None


def test_блок_есть_но_пуст_это_ноль_а_не_отказ():
    """Карточка без ссылок в известном блоке — находка, а не предел измерения."""
    тело = ('<dl class="ztitle__facts"><div><dt>Год</dt><dd>2026</dd></div>'
            '<div><dt>Страна</dt><dd>США</dd></div></dl>')
    разметка, имя = блок_модуль.блок(тело)
    assert имя == "ztitle__facts"
    assert "href=" not in разметка, разметка
    assert "Страна" in разметка, "текст блока должен сохраняться"


def test_класс_среди_нескольких_распознаётся():
    тело = '<dl class="card__dl facts tight"><a href="/genre/w/">w</a></dl>'
    разметка, имя = блок_модуль.блок(тело)
    assert имя == "facts" and "/genre/w/" in разметка


def test_все_четыре_семейства_названы_явно():
    """Контейнеры измерены на живых карточках, а не угаданы."""
    assert блок_модуль.КОНТЕЙНЕРЫ == (
        "facts", "ztitle__facts", "ag-facts", "portal-meta-list")
