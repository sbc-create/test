def test_в_поправку_идёт_только_сверенное():
    подробности = {
        "расходится": _запись(),
        "совпадает": _запись(year=2024),
        "без_ид": _запись(external_ids={}),
    }
    строки = [
        ИНСТР.разобрать_одну("расходится", подробности["расходится"], _карточка()),
        ИНСТР.разобрать_одну("совпадает", подробности["совпадает"], _карточка()),
        ИНСТР.разобрать_одну("без_ид", подробности["без_ид"], None),
    ]
    подробности["расходится"]["id"] = "01918cd7"
