"""Сверка года и вида каталога с источником по id САМОЙ записи.

Повод. В приёмке MOD-102 и MOD-109 стояло: «сверить каталог с источником нечем,
в записях снимка нет shikimori_id». Чтение снимка 20.10 это опровергло — id
лежит в `external_ids.mal` у 8 080 записей из 8 674, и у 7 765 есть ещё и
`year`, то есть они сверяемы. Этот проход и делает сверку.

Отрицательные контроли, названные заранее, потому что каждый из них отвечает на
УЖЕ допущенную ошибку:

* **чужой id не делает находку.** На `iz-odnoy-komnaty-2` год сверялся по id
  36431 из ЧЕРНОВИКА, а в записи стоит 41364, и по нему год верен. Поэтому при
  несовпадении названий год объявляется НЕ ИЗМЕРЕННЫМ, а не расходящимся;
* **`ona` против `tv` расхождением не считается.** В словаре снимка всего два
  значения (`tv` 6 037, `movie` 2 637), различить ONA в нём нечем. Проход
  обязан сказать «совпадает», иначе выдаст сотни ложных находок;
* **«не измерено» никогда не печатается совпадением** — ни при отсутствии id,
  ни при отсутствии `aired_on` у источника;
* **образец воспроизводим семенем** и при ДРУГОМ семени даёт другой набор:
  иначе «случайная выборка» была бы словом, а не выборкой.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "catalog_year_source_audit",
    КОРЕНЬ / "automation/local/catalog-year-source-audit.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)


def _запись(**п) -> dict:
    з = {
        "name": "Руководство сотен демонов 4",
        "original_name": "Bai yao pu",
        "type": "tv",
        "year": 2020,
        "external_ids": {"mal": "57995"},
    }
    з.update(п)
    return з


def _карточка(**п) -> dict:
    к = {
        "ok": True,
        "russian": "Руководство сотен демонов 4",
        "name": "Bai Yao Pu 4th Season",
        "kind": "tv",
        "episodes": 12,
        "aired_on": "2024-02-23",
    }
    к.update(п)
    return к


def _снимок(tmp_path, подробности: dict) -> pathlib.Path:
    ф = tmp_path / "snapshot.json"
    ф.write_text(json.dumps({"details": подробности}, ensure_ascii=False),
                 encoding="utf-8")
    return ф


