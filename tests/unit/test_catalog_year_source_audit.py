    подробности["без_ид"]["id"] = "03"
    итог = ИНСТР.поправки(строки, подробности)
    assert [з["slug_at_measure"] for з in итог] == ["расходится"]
    з = итог[0]
    assert з["id"] == "01918cd7", "ключ — id поставщика, а не слаг"
    assert з["year_provider"] == 2020 and з["year_source"] == 2024
