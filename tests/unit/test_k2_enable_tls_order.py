"""Порядок шагов в `k2-enable-tls.sh`: переставленная строка стоит дорого.

Сценарий исполняется от root на узле восьми витрин, и три его свойства нельзя
потерять при будущей правке:

* проверка DNS стоит ДО выпуска сертификата — иначе сжигается попытка у Let's
  Encrypt (у них предел на домен в неделю);
* блок 443 ставится ПОСЛЕ выпуска и откатывается при неудаче `nginx -t` —
  иначе ссылка на несуществующий сертификат роняет перезагрузку ВСЕХ восьми;
* домен берётся из заготовки, а не из таблицы в самом сценарии — таблица
  разошлась бы с конфигурацией молча.

Проверяется текст сценария, а не его прогон: прогон требует root, живого
certbot и переведённого DNS. Это тот же способ, которым в репозитории уже
проверяются ASCII-имена в host-сценариях.
"""
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СЦЕНАРИЙ = КОРЕНЬ / "automation" / "host" / "k2-enable-tls.sh"


@pytest.fixture(scope="module")
def текст() -> str:
    assert СЦЕНАРИЙ.is_file(), f"нет {СЦЕНАРИЙ}"
    return СЦЕНАРИЙ.read_text(encoding="utf-8")


def место(текст: str, кусок: str) -> int:
    и = текст.find(кусок)
    assert и >= 0, f"в сценарии нет {кусок!r}"
    return и


def test_проверка_dns_раньше_выпуска(текст):
    """Выпуск до перевода записи сжигает попытку у Let's Encrypt."""
    assert место(текст, "перевод DNS ещё не выполнен") < место(текст, "certbot certonly")


def test_путь_acme_проверяется_раньше_выпуска(текст):
    """Совпадения адреса мало: впереди может стоять чужой прокси."""
    assert место(текст, "acme-challenge/probe-") < место(текст, "certbot certonly")


def test_блок_443_ставится_после_выпуска(текст):
    assert место(текст, "certbot certonly") < место(текст, 'install -m 0644 -o root -g root "$staged"')


def test_проверка_конфигурации_раньше_перезагрузки(текст):
    assert место(текст, "if ! nginx -t") < место(текст, "systemctl reload nginx || {")


def test_откат_убирает_установленный_файл(текст):
    """Иначе витрина остаётся с блоком, из-за которого не поднимется никто."""
    отказ = текст[место(текст, "if ! nginx -t"):]
    голова = отказ[:отказ.index("fi")]
    assert 'rm -f "$installed"' in голова, голова
    assert "осталась на HTTP" in голова


def test_домен_берётся_из_заготовки_а_не_из_таблицы(текст):
    assert "awk '/server_name/" in текст
    # Ни одного домена партии в тексте сценария быть не должно.
    for домен in ("lordfilm.group", "lordserial.su", "lordserial.net.ru"):
        assert домен not in текст, f"в сценарии зашит домен {домен}"


def test_повторный_запуск_не_выпускает_лишнего(текст):
    assert "сертификат уже есть и покрывает www" in текст
    assert "--keep-until-expiring" in текст


def test_сертификат_покрывает_www(текст):
    """Заготовка 443 несёт блок www с тем же каталогом сертификата."""
    assert '-d "$domain" -d "www.$domain"' in текст
    assert "A-запись www." in текст


def test_адрес_для_уведомлений_не_придумывается(текст):
    """Пустое поле — не разрешение подставить что-нибудь."""
    assert "K2_ACME_EMAIL:?" in текст


def test_хук_продления_ставится_или_предупреждает(текст):
    """Продление без перезагрузки отдаёт посетителю прежний сертификат."""
    assert "renewal-hooks/deploy/reload-nginx.sh" in текст
    assert "продолжит отдавать ПРЕЖНИЙ сертификат" in текст


def test_результат_проверяется_а_не_предполагается(текст):
    for кусок in ("subjectAltName", "апекс https", "www   https", "http  апекс"):
        assert кусок in текст, кусок
