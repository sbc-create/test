"""Охват проверки сертификатов: чистый вердикт не должен молчать о пропущенных.

ПОВОД. 24.10 прогон `tls-expiry-probe.py --all` напечатал «замечаний: 0», и это
выглядело полным благополучием сети. На деле он посмотрел 21 домен из 29: его
источником был только паспорт ячеек, а восьми живых витрин партии K2 в паспорте
нет вовсе (MOD-107). Сертификаты у восьми оказались в порядке (83 дня), но
узнать это удалось лишь отдельным запуском по именам — то есть чистый вердикт
исключал восемь работающих сайтов и не говорил об этом.

Это тот же молчаливый успех, что класс 24, только не в теле инструмента, а в
его ОХВАТЕ: проверка делала работу честно, просто не над всем, над чем нужно.
"""
import importlib.util
import json
import pathlib

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
ФАЙЛ = КОРЕНЬ / "automation/local/tls-expiry-probe.py"
K2 = ("lordfilm.group", "lordfilm.spb.ru", "lordfilm.msk.ru",
      "lordserial.su", "lordserial.group", "lordserial.spb.ru",
      "lordserial.msk.ru", "lordserial.net.ru")


@pytest.fixture(scope="module")
def модуль():
    с = importlib.util.spec_from_file_location("tls_probe", ФАЙЛ)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


def test_витрины_k2_попадают_в_охват(модуль):
    """Главная регрессия: восемь живых витрин не должны пропадать из прогона."""
    цели = модуль.домены()
    пропущены = [д for д in K2 if д not in цели]
    assert not пропущены, (
        f"из охвата выпали живые витрины: {пропущены}. Именно так прогон"
        " печатал «замечаний: 0», посмотрев 21 домен из 29")


def test_реестр_даёт_только_действующие(модуль):
    """Ожидающие замены не берутся: по заданию владельца их не трогаем."""
    реестр = json.loads(
        (КОРЕНЬ / "config/active-domains.json").read_text("utf-8"))
    ждут = {з["domain"] for з in реестр.get("awaiting_replacement") or []}
    assert ждут
    из_реестра = set(модуль.из_реестра())
    assert not (из_реестра & ждут)
    действующие = {з["domain"] for з in реестр["domains"]
                   if з.get("state") == "active"}
    assert из_реестра == действующие - ждут


def test_объединение_без_повторов_и_паспорт_первым(модуль):
    цели = модуль.домены()
    assert len(цели) == len(set(цели)), "в охвате есть повторы"
    паспорт = модуль.из_паспорта()
    if паспорт:
        assert цели[:len(паспорт)] == list(dict.fromkeys(паспорт)), (
            "порядок нарушен: паспорт должен идти первым")


def test_расхождение_источников_называет_обе_стороны(модуль):
    р = модуль.расхождение_источников()
    assert set(р) == {"нет_в_паспорте", "нет_в_реестре"}
    # Восемь витрин K2 отсутствуют в паспорте — это и есть измеренное 24.10
    # расхождение, и проверка фиксирует его, пока оно не исправлено.
    assert set(K2) <= set(р["нет_в_паспорте"]), (
        "расхождение перестало называть витрины K2 — либо паспорт исправлен"
        " (тогда проверку надо обновить), либо источник сломан")


def test_вердикт_печатает_охват(модуль):
    текст = ФАЙЛ.read_text("utf-8")
    assert "осмотрено домéнов:" in текст
    assert "расхождение_источников()" in текст
    # Число осмотренных печатается ВСЕГДА, а не только при замечаниях.
    место_охвата = текст.index("осмотрено домéнов:")
    место_возврата = текст.index("return 1 if замечания else 0")
    assert место_охвата < место_возврата


def test_не_измерено_не_путается_с_порядком(модуль):
    """«Не измерено» прямо отделено от «в порядке» — это уже было и остаётся."""
    текст = ФАЙЛ.read_text("utf-8")
    assert "«не измерено» — это не «просрочен» и не «в порядке»" in текст
