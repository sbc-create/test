"""Копия профиля в ячейке помечена справочной — иначе она выглядит настройкой.

Измерено 2026-10-15: `factory/cell/newsite.py` копирует профиль шаблона в
`config/profile.yaml` новой витрины, но НИ `run.py`, НИ точка входа его не
читают — поиск по всему репозиторию ячейки не находит обращений. Дизайн задают
таблицы рантайма по `template_id` из `config/template-manifest.json`.

Как происхождение файл полезен: видно, из какого профиля пула выросла витрина.
Как настройка — обманчив: правка палитры в нём не меняет сайт ничем, а это
ровно те «мёртвые данные, выглядящие содержимым», которые в проекте запрещены.
Поэтому копия обязана нести заголовок, и проверка сторожит именно это.
"""
from __future__ import annotations

import json
from pathlib import Path

from factory.cell import newsite

КОРЕНЬ = Path(__file__).resolve().parents[2]


def test_справка_называет_и_место_настоящего_дизайна():
    """Заголовок бесполезен, если не говорит, ГДЕ менять по-настоящему."""
    справка = newsite.СПРАВКА_ПРОФИЛЯ
    assert "НЕ читает" in справка
    assert "template-manifest.json" in справка, "не названо место настоящего дизайна"
    assert "`profile`" in справка, (
        "заголовок обязан называть ТОЧНОЕ поле: рантайм читает `profile`, "
        "а не `template_id` — неверная подсказка хуже отсутствующей")
    assert справка.lstrip().startswith("#"), "заголовок обязан быть комментарием YAML"


def test_копия_профиля_в_восьми_ячейках_помечена():
    """Витрины партии K2 уже созданы — у них проверяется факт, а не замысел."""
    без_справки = []
    for н in range(10, 18):
        путь = КОРЕНЬ / "var" / "new-sites" / f"lords-{н}" / "config" / "profile.yaml"
        if not путь.is_file():
            continue
        if "СПРАВОЧНО" not in путь.read_text(encoding="utf-8"):
            без_справки.append(путь.parents[1].name)
    assert not без_справки, f"копия профиля без пометки: {без_справки}"


def test_профиль_остаётся_разбираемым_yaml():
    """Заголовок не должен ломать разбор: это по-прежнему YAML профиля."""
    import yaml

    путь = КОРЕНЬ / "var" / "new-sites" / "lords-10" / "config" / "profile.yaml"
    if not путь.is_file():
        return
    данные = yaml.safe_load(путь.read_text(encoding="utf-8"))
    assert данные.get("profile"), данные
    манифест = json.loads(
        (путь.parent / "template-manifest.json").read_text(encoding="utf-8"))
    # Происхождение обязано сходиться с тем, по чему рантайм выбирает дизайн.
    assert данные["profile"] == манифест.get("profile"), (
        "справочный профиль называет не тот шаблон, по которому рантайм "
        "выбирает дизайн — это хуже отсутствия копии")
