"""REQ-CELL-HEALTHZ-PUBLIC: наружу /healthz отдаёт состояние, а не устройство.

Измерено 2026-10-12 и перемерено 2026-10-18
(`automation/local/healthz-exposure.py`): девять витрин отдавали публично
24–26 полей, из них 22–24 описывают устройство машины — пути в файловой
системе, суммы файлов, номер процесса, идентификаторы сборки. Правила проекта
требуют, чтобы служебные данные не были публично доступны.

Сам путь остаётся публичным (решения D150, D166, D187 — это не
пересматривается). Меняется состав ответа: внутренний вызов (Host петли)
по-прежнему получает подробность, нужную наблюдению и выпуску, публичный —
короткий ответ.

Проверка читает ИСХОДНИК обработчика: поднимать сервер ради этого не нужно, а
падать она обязана до выпуска.
"""
from __future__ import annotations

import re
from pathlib import Path

ШАБЛОН = Path(__file__).resolve().parents[2] / "automation" / "host" / \
    "lords-frontend.py"
ТЕКСТ = ШАБЛОН.read_text(encoding="utf-8")

#: Поля, которые описывают устройство машины, а не состояние службы.
ВНУТРЕННИЕ = ("runtime_path", "catalog_path", "details_path",
              "player_config_path", "template_manifest_path", "pid",
              "runtime_sha256", "catalog_digest", "details_digest")


def _кусок_healthz() -> str:
    начало = ТЕКСТ.index('if путь == "/healthz":')
    конец = ТЕКСТ.index('if путь == "/assets/nova.webmanifest":', начало)
    return ТЕКСТ[начало:конец]


def test_публичный_ответ_собирается_отдельно_от_подробного():
    кусок = _кусок_healthz()
    assert "изнутри" in кусок, (
        "в обработчике /healthz нет различения внутреннего и публичного вызова")
    assert re.search(r"if not изнутри:", кусок), (
        "публичный ответ не отделён от подробного")


def test_публичный_ответ_не_содержит_полей_об_устройстве():
    кусок = _кусок_healthz()
    публичный = кусок[кусок.index("if not изнутри:"):]
    публичный = публичный[:публичный.index("return self._отдать")]
    плохие = [п for п in ВНУТРЕННИЕ if f'"{п}"' in публичный]
    assert not плохие, f"в публичном ответе поля об устройстве: {плохие}"


def test_внутренний_вызов_узнаётся_по_адресу_петли():
    """Подделать Host снаружи нельзя: его подставляет nginx."""
    кусок = _кусок_healthz()
    assert "127.0.0.1" in кусок and "localhost" in кусок
    assert 'self.headers.get("Host")' in кусок


def test_подробные_поля_в_обработчике_остались():
    """Отрицательный контроль: нельзя «починить» вырезав подробность вовсе —
    её читают наблюдение и выпуск по адресу петли."""
    кусок = _кусок_healthz()
    for поле in ("runtime_sha256", "catalog_revision", "artifact_sha256",
                 "runtime_digest_match"):
        assert f'"{поле}"' in кусок, f"поле {поле} пропало из подробного ответа"
