"""Объявленная версия оформления обязана исполняться, а не проваливаться молча.

Воспроизведение дефекта, найденного при заведении zonafilm.cc.

Артефакт шаблона Zona `7ccf094a…` (`releases/zona-slider-2650fad6`) исполняет
оформление только для версий `{1.1.0, 1.2.0, 1.2.1}`:

    ОФОРМЛЕНИЕ_ВЕРСИИ = {ОФОРМЛЕНИЕ_1_1, ОФОРМЛЕНИЕ_1_2, ОФОРМЛЕНИЕ_1_2_1}
    ОФОРМЛЕНИЕ_НОВОЕ  = (ВЕРСИЯ in ОФОРМЛЕНИЕ_ВЕРСИИ)

Манифест витрины `zona-01` объявляет `design_version = "1.3.0"`. Значение не
входит в набор, `ОФОРМЛЕНИЕ_НОВОЕ` становится `False`, и витрина исполняет
дореформенные ветки — не сообщая об этом ничем. Маршруты 1.1+ (`/title/`,
`/collection/`, `/genre/`, `/country/`, `/year/`) при этом уходят в
`старое()` — отдачу из ранее отрисованного статического релиза.

У `zona-01` это незаметно: у неё такой релиз есть, и страницы тайтлов
отдаются из него. У новой витрины его нет — и все 53 652 карточки ведут в 404.

Тест не требует запуска витрины: он читает исходник артефакта и сверяет его
набор версий с тем, что объявляют манифесты. Падение теста означает, что
какая-то витрина объявила версию, которой в её артефакте нет.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

ФРОНТ = Path("/srv/lords/.frontend")

#: Разбор идёт регулярными выражениями, а не импортом: артефакт при импорте
#: читает каталог на 16 МиБ и поднимает сервер, и тест превратился бы в запуск
#: витрины.
НАБОР = re.compile(r"^ОФОРМЛЕНИЕ_ВЕРСИИ\s*=\s*\{(?P<body>[^}]*)\}", re.M)
КОНСТАНТА = re.compile(r"^(?P<name>ОФОРМЛЕНИЕ_1_[0-9_]+)\s*=\s*\"(?P<value>[^\"]+)\"", re.M)
ПЕРЕРАБОТАНО = re.compile(
    r"^ПЕРЕРАБОТАНО_С\s*=\s*\{(?P<body>.*?)^\}", re.M | re.S)


def версии_артефакта(исходник: str) -> set[str] | None:
    """Набор версий оформления или None, если это не рантайм витрины.

    None — значимый результат, а не сбой разбора. По пути `current` у части
    витрин лежит совместимая заглушка, которая только передаёт управление
    настоящему релизу через `execv`; в ней набора версий нет и быть не должно.
    Считать такой случай поломкой значило бы падать на устройстве стенда,
    а не на расхождении, ради которого тест написан.
    """
    константы = {m.group("name"): m.group("value") for m in КОНСТАНТА.finditer(исходник)}
    совпало = НАБОР.search(исходник)
    if not совпало:
        return None
    имена = [ч.strip() for ч in совпало.group("body").split(",") if ч.strip()]
    пропущенные = [и for и in имена if и not in константы]
    assert not пропущенные, f"не разобраны константы версий: {пропущенные}"
    return {константы[и] for и in имена}


def переработано_с(исходник: str) -> dict[str, set[str]]:
    константы = {m.group("name"): m.group("value") for m in КОНСТАНТА.finditer(исходник)}
    совпало = ПЕРЕРАБОТАНО.search(исходник)
    if not совпало:
        return {}
    out: dict[str, set[str]] = {}
    for семейство, тело in re.findall(r'"([a-z0-9-]+)"\s*:\s*frozenset\(\{([^}]*)\}\)',
                                      совпало.group("body")):
        out[семейство] = {константы[ч.strip()] for ч in тело.split(",")
                          if ч.strip() and ч.strip() in константы}
    return out


def артефакт_витрины(site_id: str) -> Path | None:
    ссылка = ФРОНТ / "sites" / site_id / "current" / "lords-frontend.py"
    if not ссылка.exists():
        return None
    return ссылка.resolve()


def манифест_витрины(site_id: str) -> dict | None:
    путь = ФРОНТ / f"template-manifest-{site_id}.json"
    if not путь.is_file():
        return None
    return json.loads(путь.read_text(encoding="utf-8"))


pytestmark = pytest.mark.skipif(
    not ФРОНТ.is_dir(), reason="рантайм фабрики недоступен: проверять нечего")


def test_артефакт_объявляет_конечный_набор_версий():
    """Форма, на которой держится вся проверка, существует и читается."""
    артефакт = артефакт_витрины("zona-02")
    if артефакт is None:
        pytest.skip("витрина zona-02 ещё не развёрнута")
    версии = версии_артефакта(артефакт.read_text(encoding="utf-8"))
    assert версии, "набор версий пуст или не найден"
    assert "1.2.0" in версии


def test_zona_02_объявляет_версию_которую_её_артефакт_исполняет():
    """Ради этого тест и написан: своя витрина не имеет права деградировать молча."""
    артефакт = артефакт_витрины("zona-02")
    манифест = манифест_витрины("zona-02")
    if артефакт is None or манифест is None:
        pytest.skip("витрина zona-02 ещё не развёрнута")
    исходник = артефакт.read_text(encoding="utf-8")
    версии = версии_артефакта(исходник)
    assert версии is not None, "по ссылке current лежит не рантайм витрины"
    объявлено = манифест["design_version"]
    assert объявлено in версии, (
        f"zona-02 объявляет оформление {объявлено}, которого нет в наборе артефакта "
        f"{sorted(версии)}: витрина исполнила бы дореформенные ветки, а маршруты "
        f"/title/, /collection/, /genre/, /country/, /year/ ушли бы в старый релиз"
    )
    семейство = манифест["template_family"]
    карта = переработано_с(исходник)
    if семейство in карта:
        assert объявлено in карта[семейство], (
            f"версия {объявлено} не включает переработанное оформление семейства "
            f"{семейство}: артефакт включает его только на {sorted(карта[семейство])}"
        )


def test_расхождение_у_соседей_видно_а_не_замолчано():
    """Соседей не чиним — но и не делаем вид, что расхождения нет.

    Тест сообщает о витрине, которая объявляет версию вне набора своего
    артефакта. Это чужой контур, поэтому проверка не падает: она печатает
    расхождение, чтобы оно было зафиксировано, а не потеряно.
    """
    расхождения = []
    for путь in sorted(ФРОНТ.glob("template-manifest-*.json")):
        site_id = путь.name[len("template-manifest-"):-len(".json")]
        if site_id == "zona-02":
            continue
        артефакт = артефакт_витрины(site_id)
        манифест = манифест_витрины(site_id)
        if артефакт is None or манифест is None or "design_version" not in манифест:
            continue
        версии = версии_артефакта(артефакт.read_text(encoding="utf-8"))
        if версии is None:
            continue
        if манифест["design_version"] not in версии:
            расхождения.append({
                "site": site_id,
                "declared": манифест["design_version"],
                "artifact_supports": sorted(версии),
                "artifact": str(артефакт),
            })
    if расхождения:
        print("\nTEMPLATE_ZONA_BLOCKER-02 — объявлено не то, что исполняется:")
        for р in расхождения:
            print(json.dumps(р, ensure_ascii=False))
    assert isinstance(расхождения, list)
