"""Разделы, главная и заполнение блоков семейства Lords.

Три дефекта одного класса, найденные на трёх сайтах по отдельности:

1. Раздел считался одним полем `kind`. У источника `type=tv` одинаково стоит
   у игрового сериала, у дорамы и у дунхуа, поэтому «Сериалы» набирались из
   всего сразу, а разделов `/anime/` и `/dorama/` не существовало вовсе.
2. Полка набиралась константой 12 — свойством одного экрана, а не сетки.
3. Отбор выполнялся ПОСЛЕ ограничения количества: `взять(набор, 12)` брал
   первые двенадцать и не добирал замену отсеянным.

Проверки написаны «от обратного»: при возврате к `kind == "Сериал"` каждая из
них падает и называет именно те записи, из-за которых задача и появилась.
"""
from __future__ import annotations

import re

import pytest

import lords_runtime_harness as h


# Снимок нарочно повторяет форму живых данных: у дорамы и у дунхуа `type=tv` и
# `kind="Сериал"`, ровно как у игрового сериала. Различить их можно ТОЛЬКО по
# нормализованным жанрам.
ЗАПИСИ = [
    ("film-01", "Живое кино", "Фильм", "movie", ()),
    ("film-02", "Второе кино", "Фильм", "movie", ()),
    ("film-03", "Третье кино", "Фильм", "movie", ("боевик",)),
    ("serial-01", "Британская драма", "Сериал", "tv", ("драма",)),
    ("serial-02", "Детектив", "Сериал", "tv", ("детектив", "драма")),
    ("serial-03", "Ещё сериал", "Сериал", "tv", ()),
    ("dorama-01", "Корейская история", "Сериал", "tv", ("дорама", "драма")),
    ("dorama-02", "Список Ланъя", "Сериал", "tv", ("дорама", "уся")),
    ("anime-01", "Сёнен-тайтл", "Сериал", "tv", ("сёнен", "боевик")),
    ("anime-02", "Прямое аниме", "Сериал", "tv", ("аниме",)),
    ("anime-03", "Дунхуа", "Сериал", "tv", ("дунхуа",)),
    ("mult-01", "Мультсериал", "Мультфильм", "tv", ("мультфильм",)),
    ("mult-02", "Мультфильм", "Мультфильм", "movie", ("мультфильм",)),
]


def _наполнить(с, *, штук_кино: int = 0) -> None:
    записи, детали = [], []
    for slug, титул, kind, тип, жанры in ЗАПИСИ:
        записи.append(h.запись(slug, title=титул, kind=kind))
        детали.append(h.подробность(slug, genres=жанры, type_=тип))
    # Дополнительное кино — чтобы полке было чем добирать до полного ряда.
    for i in range(штук_кино):
        slug = f"extra-{i:02d}"
        записи.append(h.запись(slug, title=f"Кино номер {i}", kind="Фильм"))
        детали.append(h.подробность(slug, type_="movie"))
    с.записать_каталог(записи)
    с.записать_подробности(детали)
    с.записать_плеер()


@pytest.fixture()
def витрина(tmp_path, monkeypatch):
    с = h.Стенд(tmp_path)
    _наполнить(с, штук_кино=40)
    модуль = h.загрузить(с, monkeypatch)
    yield с, модуль, h.вид(модуль)
    h.выгрузить(модуль)


