def test_дорама_и_аниме_не_считаются_игровым_сериалом(витрина):
    _, модуль, в = витрина
    разделы = модуль.разделы_снимка(в.д, в.п)
    assert разделы is not None, "модуль разделов не подключился — проверка пуста"
    по_slug = разделы.по_slug
    assert по_slug["serial-01"] == "series"
    assert по_slug["dorama-01"] == "dorama"
    assert по_slug["dorama-02"] == "dorama"
    assert по_slug["anime-01"] == "anime"
    assert по_slug["anime-02"] == "anime"
    assert по_slug["anime-03"] == "anime"
    assert по_slug["mult-01"] == "animation"


def test_драма_не_означает_дораму(витрина):
    """Два разных значения словаря снимка; спутать их — увести пятую часть каталога."""
    _, модуль, в = витрина
    разделы = модуль.разделы_снимка(в.д, в.п)
    assert разделы.по_slug["serial-01"] == "series"
    assert разделы.по_slug["serial-02"] == "series"


def test_уся_не_переводит_дораму_в_аниме(витрина):
    """202 записи снимка с этим жанром — костюмные дорамы, а не анимация."""
    _, модуль, в = витрина
    assert модуль.разделы_снимка(в.д, в.п).по_slug["dorama-02"] == "dorama"


def test_страна_разделом_не_является(tmp_path, monkeypatch):
    """«Япония» стоит и у дорамы, и у аниме: страна не разделяет их."""
    с = h.Стенд(tmp_path)
    с.записать_каталог([h.запись("x", title="Без жанров", kind="Сериал")])
    с.записать_подробности([h.подробность("x", type_="tv", country="Япония")])
    с.записать_плеер()
    модуль = h.загрузить(с, monkeypatch)
    try:
        в = h.вид(модуль)
        assert модуль.разделы_снимка(в.д, в.п).по_slug["x"] == "series"
    finally:
        h.выгрузить(модуль)


# --- главная ----------------------------------------------------------------

def _слаги(html_: str) -> list[str]:
    return re.findall(r'href="/title/([a-z0-9-]+)/"', html_)


ПОЛКА = re.compile(r'<section class="sec-rail"(?![^>]*data-collections)(.*?)</section>', re.S)


def _полки(html_: str) -> list[str]:
    """Только полки карточек.

    Полоса подборок сюда не входит намеренно. Подборка — это выборка по
    контракту, её состав объявлен и одинаков с её собственной страницей; она
    вправе быть каталожной и включать аниме, и превью обязано ей
    соответствовать (см. `test_lords_collections.py`). Правило «главная
    профиля Lords — это его кино и игровые сериалы» относится к ПОЛКАМ, где
    записи отбирает витрина, а не контракт.
    """
    return ПОЛКА.findall(html_)


def test_на_полки_главной_не_попадают_аниме_дорамы_и_мультфильмы(витрина):
    _, _, в = витрина
    полки = _полки(в.главная())
    assert полки, "полок на главной не нашлось"
    чужие = {s for полка in полки for s in _слаги(полка)
             if s.startswith(("anime-", "dorama-", "mult-"))}
    assert not чужие, f"на полках профиля Lords оказались чужие разделы: {sorted(чужие)}"


def test_на_полках_главной_нет_повторов(витрина):
    _, _, в = витрина
    слаги = [s for полка in _полки(в.главная()) for s in _слаги(полка)]
    повторы = {s for s in слаги if слаги.count(s) > 1}
    assert not повторы, f"один тайтл в двух полках — это повтор: {sorted(повторы)}"


def test_полка_набирает_полный_ряд_когда_записей_хватает(витрина):
    _, модуль, в = витрина
    страница = в.главная()
    размеры = [int(n) for n in re.findall(r'data-shelf-size="(\d+)"', страница)]
    assert размеры, "полок на главной не нашлось"
    assert размеры[0] == модуль.РЯД_ПОЛКИ, (
        f"первая полка набрала {размеры[0]} при ряде {модуль.РЯД_ПОЛКИ}")


def test_полка_добирает_замену_отсеянным(tmp_path, monkeypatch):
    """Отбор до предела, а не после.

    В голове списка стоят три аниме. Прежний `взять` взял бы первые N и вернул
    N-3 карточки; правильное поведение — пропустить их и добрать следующие
    подходящие.
    """
    с = h.Стенд(tmp_path)
    записи, детали = [], []
    for slug, жанры, kind, тип in (
            ("anime-a", ("аниме",), "Сериал", "tv"),
            ("anime-b", ("аниме",), "Сериал", "tv"),
            ("anime-c", ("дунхуа",), "Сериал", "tv")):
        записи.append(h.запись(slug, title=slug, kind=kind, published_at="2026-09-25"))
        детали.append(h.подробность(slug, genres=жанры, type_=тип))
    for i in range(20):
        slug = f"kino-{i:02d}"
        записи.append(h.запись(slug, title=f"Кино {i}", kind="Фильм",
                               published_at="2026-09-20"))
        детали.append(h.подробность(slug, type_="movie"))
    с.записать_каталог(записи)
    с.записать_подробности(детали)
    с.записать_плеер()
    модуль = h.загрузить(с, monkeypatch)
    try:
        в = h.вид(модуль)
        страница = в.главная()
        размеры = [int(n) for n in re.findall(r'data-shelf-size="(\d+)"', страница)]
        assert размеры[0] == модуль.РЯД_ПОЛКИ, (
            "полка не добрала замену отсеянным аниме: " + str(размеры))
        на_полках = {s for полка in _полки(страница) for s in _слаги(полка)}
        assert "anime-a" not in на_полках
    finally:
        h.выгрузить(модуль)


def test_при_нехватке_записей_полка_называет_фактическое_число(tmp_path, monkeypatch):
    """Ни добора чужой категорией, ни повторов, ни выдуманных новинок."""
    с = h.Стенд(tmp_path)
    записи, детали = [], []
    for i in range(4):
        slug = f"kino-{i}"
        записи.append(h.запись(slug, title=f"Кино {i}", kind="Фильм"))
        детали.append(h.подробность(slug, type_="movie"))
    с.записать_каталог(записи)
    с.записать_подробности(детали)
    с.записать_плеер()
    модуль = h.загрузить(с, monkeypatch)
    try:
        в = h.вид(модуль)
        страница = в.главная()
        размеры = [int(n) for n in re.findall(r'data-shelf-size="(\d+)"', страница)]
        assert размеры and max(размеры) <= 4
        слаги = _слаги(страница)
        assert len(слаги) == len(set(слаги)), "карточки размножены ради ровного ряда"
    finally:
        h.выгрузить(модуль)


СЕТКА = re.compile(r'<div class="grid[^"]*"[^>]*>')


def _сетки(html_: str) -> list[str]:
    """Только открывающие теги сеток: в таблице стилей пометка упоминается
    правилом и попала бы в поиск по всей странице."""
    тело = html_.split("</style>", 1)[-1]
    return СЕТКА.findall(тело)


def test_компактная_раскладка_помечена_только_у_полок(витрина):
    """Сетки каталога пометку не несут: их число обещано листалкой."""
    _, _, в = витрина
    полки = _сетки(в.главная())
    assert полки, "сеток на главной не нашлось"
    assert any('data-rows="full"' in с for с in полки)
    сетки_каталога = _сетки(в.список("/catalog", {}))
    assert сетки_каталога, "сеток в каталоге не нашлось"
    assert not [с for с in сетки_каталога if 'data-rows="full"' in с], (
        "на странице каталога нельзя прятать обещанные записи ради ровного ряда")


# --- разделы как страницы ---------------------------------------------------

@pytest.mark.parametrize("ключ,ожидаемые", [
    ("series", {"serial-01", "serial-02", "serial-03"}),
    ("dorama", {"dorama-01", "dorama-02"}),
    ("anime", {"anime-01", "anime-02", "anime-03"}),
    ("animation", {"mult-01", "mult-02"}),
])
def test_раздел_каталога_содержит_только_своё(витрина, ключ, ожидаемые):
    _, _, в = витрина
    страница = в.список(f"/{ключ}", {"section": [ключ]})
    показаны = set(_слаги(страница))
    assert ожидаемые <= показаны, f"{ключ}: не хватает {sorted(ожидаемые - показаны)}"
    чужие = показаны - ожидаемые
    assert not чужие, f"{ключ}: чужие записи {sorted(чужие)}"


def test_прежний_адрес_kind_продолжает_работать_и_отбирает_по_разделу(витрина):
    """Сохранённая ссылка `?kind=Сериал` обязана открыться — и без дорам."""
    _, _, в = витрина
    страница = в.список("/catalog", {"kind": ["Сериал"]})
    показаны = set(_слаги(страница))
    assert {"serial-01", "serial-02"} <= показаны
    assert not {s for s in показаны if s.startswith(("dorama-", "anime-"))}
