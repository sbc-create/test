"""Перечень подборок: мёртвая карточка найдена, а пустое измерение не выдано за чистоту.

Повод измеренный, 22.10: у трёх витрин Yummy перечень подборок показывает по
три карточки, ведущие на 404 (`agent-vremeni-3`, `krovavyy-lager-akula-kloun`,
`motor-siti`), и ни одной из них нет в карте сайта при живых контрольных
карточках. У пары `yummyani7.*` мёртвых нет вовсе — то есть признак различает
состояния, а не красит всё одним цветом.

Проверки здесь — на ЧИСТЫХ функциях разбора и исхода: сеть в тестах не
трогается (правило `.claude/rules/tests.md`).
"""
from __future__ import annotations

import importlib.util
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_сп = importlib.util.spec_from_file_location(
    "collections_hub_cards",
    КОРЕНЬ / "automation" / "local" / "collections-hub-cards.py")
мера = importlib.util.module_from_spec(_сп)
_сп.loader.exec_module(мера)


def test_карточки_собираются_без_повторов_и_в_порядке():
    тело = ('<a href="/anime/beta"></a><a href="/anime/alpha"></a>'
            '<a href="/anime/beta"></a>')
    assert мера.карточки(тело) == ["/anime/alpha", "/anime/beta"]


def test_ссылки_навигации_карточками_не_считаются():
    """Широкий шаблон раздул бы «число карточек» и испортил бы долю живых."""
    тело = ('<a href="/catalog"></a><a href="/collections"></a>'
            '<a href="/anime/alpha"></a><a href="/anime/alpha/season/1"></a>')
    assert мера.карточки(тело) == ["/anime/alpha"]


def test_исход_различает_пустое_измерение_от_чистоты():
    """Главное требование: «ноль мёртвых» и «карточек нет» — разные исходы."""
    assert мера.исход(0, 0) == "НЕ ИЗМЕРЕНО"
    assert мера.исход(10, 0) == "мёртвых нет"
    assert мера.исход(10, 3) == "мёртвые есть"


def test_одна_мёртвая_карточка_уже_исход():
    assert мера.исход(40, 1) == "мёртвые есть"


def test_все_мёртвые_это_не_не_измерено():
    """Если все карточки мертвы, это находка, а не предел измерения."""
    assert мера.исход(0, 5) == "мёртвые есть"


def test_robots_читается_и_отсутствие_названо():
    assert мера.роботс('<meta name="robots" content="noindex, nofollow"/>') \
        == "noindex, nofollow"
    assert мера.роботс("<html></html>") == "—"


def test_перечень_витрин_не_пуст_и_без_повторов():
    assert len(мера.ВИТРИНЫ) == len(set(мера.ВИТРИНЫ))
    assert "yummyani.biz" in мера.ВИТРИНЫ


def test_без_домéнов_и_без_all_мера_отказывает(capsys):
    """Молчаливый ноль витрин был бы «мёртвых нет» на пустом множестве."""
    assert мера.main([]) == 2


def test_код_возврата_2_означает_предел_измерения(monkeypatch):
    """Ни одна витрина не измерена → 2, а не 0."""
    monkeypatch.setattr(мера, "проверить", lambda д: {
        "домен": д, "исход": "НЕ ИЗМЕРЕНО", "почему": "проба",
        "карточек": 0, "живых": 0, "мёртвых": 0, "мёртвые": [],
        "robots": "—"})
    assert мера.main(["x.test"]) == 2


def test_код_возврата_1_при_мёртвых(monkeypatch):
    monkeypatch.setattr(мера, "проверить", lambda д: {
        "домен": д, "исход": "мёртвые есть", "почему": "",
        "карточек": 10, "живых": 9, "мёртвых": 1,
        "мёртвые": [{"адрес": "/anime/x", "код": "404"}],
        "robots": "noindex, nofollow"})
    assert мера.main(["x.test"]) == 1


def test_код_возврата_0_только_когда_измерено_и_чисто(monkeypatch):
    monkeypatch.setattr(мера, "проверить", lambda д: {
        "домен": д, "исход": "мёртвых нет", "почему": "",
        "карточек": 10, "живых": 10, "мёртвых": 0, "мёртвые": [],
        "robots": "index, follow"})
    assert мера.main(["x.test"]) == 0


# --- второй шаблон карточки и непустая причина -------------------------------

ПЕРЕЧЕНЬ_ANIMEDIA = (
    '<h1>Подборки аниме</h1><p>подборок: 11.</p>'
    '<a href="/collection/action/">Экшен</a>'
    '<a href="/collection/anime_movies/">Фильмы</a>'
    '<a href="/collections/?sort=name">по названию</a>'
    '<a href="/catalog/">каталог</a>'
)


def test_карточки_подборок_опознаются_когда_произведений_нет():
    """У Animedia карточка ведёт на ПОДБОРКУ, а не на произведение.

    Измерено 23.10: перечень `animedia.icu` объявляет 11 подборок на
    `/collection/<slug>/`, и все одиннадцать отвечают 200. Пока шаблон был
    один, по этому семейству печаталось «НЕ ИЗМЕРЕНО» с пустой причиной.
    """
    assert мера.карточки(ПЕРЕЧЕНЬ_ANIMEDIA) == ["/collection/action/",
                                             "/collection/anime_movies/"]


def test_шаблон_произведений_сильнее_и_не_смешивается():
    """Иначе одна страница посчиталась бы дважды там, где есть и то и другое."""
    тело = ('<a href="/anime/x">x</a>'
            '<a href="/collection/action/">Экшен</a>')
    assert мера.карточки(тело) == ["/anime/x"]


def test_навигация_в_карточки_не_попадает():
    """Шаблон узкий намеренно: иначе «число карточек» раздувается."""
    адреса = мера.карточки(ПЕРЕЧЕНЬ_ANIMEDIA)
    assert "/collections/?sort=name" not in адреса
    assert "/catalog/" not in адреса


def test_витрины_animedia_в_перечне_измеренных():
    """Перечень не расширяется догадкой: эти две витрины ИЗМЕРЕНЫ 23.10."""
    assert "animedia.icu" in мера.ВИТРИНЫ
    assert "animedia.space" in мера.ВИТРИНЫ
