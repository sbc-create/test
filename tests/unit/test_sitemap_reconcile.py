"""Регулярная сверка карт: три исхода и находка вместо оговорки.

Повод. Пять проверок карты существовали по отдельности и запускались по случаю.
MOD-103 (в карте yummyani.site 1 424 адреса серий вместо порядка 123 000) и
MOD-108 (15 объявленных пустых страниц, открытых для индексации) простояли по
несколько суток и нашлись разбором по заданию, а не мониторингом.

Отрицательные контроли, названные заранее:

* код 0 даётся ТОЛЬКО когда всё измерено и чисто. При неизмеренном — 2, и это
  не придирка: ноль утверждал бы «витрина чистая» там, где измерить не удалось;
* «провал» и «не измерено» НЕ сливаются: у них разные коды и разные столбцы;
* находка в отчёте не вытесняется оговоркой. Измерено: проход напечатал три
  строки «чего инструмент НЕ отвечает» вместо настоящей причины «часть не
  ответила»;
* заголовок «ПРОВАЛЫ:» сам причины не несёт — нужны строки после него.

Подпроцессы не запускаются: `запустить` подменяется.
"""
from __future__ import annotations

import importlib.util
import json
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[2]
_с = importlib.util.spec_from_file_location(
    "sitemap_reconcile", КОРЕНЬ / "automation/local/sitemap-reconcile.py")
ИНСТР = importlib.util.module_from_spec(_с)
_с.loader.exec_module(ИНСТР)


# --- извлечение находки из вывода ---------------------------------------------

ОГОВОРКА = (
    "провалов нет\n"
    "\nчего этот инструмент НЕ отвечает: полна ли карта относительно каталога.\n"
    "   ноль провалов здесь означает «по сравнению со снимком ничего не"
    " потеряно»,\n"
    "   а не «все страницы каталога в карте». Полнота — sitemap-completeness.py\n")


def test_находка_не_вытесняется_оговоркой():
    """Живой случай: вместо «часть не ответила» печаталась оговорка."""
    вывод = ("витрина animedia.space, частей в индексе: 1\n"
             "ПРОВАЛЫ:\n"
             "   https://animedia.space/sitemap-1.xml: часть не ответила\n"
             "провалов: 1\n" + ОГОВОРКА)
    строки = ИНСТР.существо(вывод)
    assert any("часть не ответила" in с for с in строки), строки
    assert not any("чего этот инструмент" in с for с in строки), строки


def test_заголовок_провалов_тянет_за_собой_причину():
    """«ПРОВАЛЫ:» сам причины не несёт: она на следующей строке."""
    вывод = "ПРОВАЛЫ:\n   части исчезли из индекса: episodes\nпровалов: 1\n"
    строки = ИНСТР.существо(вывод)
    assert any("части исчезли из индекса" in с for с in строки), строки


def test_строка_с_маркером_берётся():
    вывод = "шапка\n   → sitemap-1.xml: в индексе нет lastmod\nподвал\n"
    assert any("нет lastmod" in с for с in ИНСТР.существо(вывод))


def test_без_маркеров_берётся_хвост():
    """Отрицательный контроль: вывод без маркеров не теряется целиком."""
    строки = ИНСТР.существо("раз\nдва\nтри\nчетыре\nпять\n")
    assert строки and "пять" in строки[-1]


def test_пустой_вывод_не_падает():
    assert ИНСТР.существо("") == []


# --- своды и коды возврата ----------------------------------------------------

def _подменить(monkeypatch, коды: dict[str, int]):
    def запустить(части, таймаут):
        имя = next((и for и in коды if и in " ".join(части)), None)
        код = коды.get(имя, 0) if имя else 0
        return код, ("ПРОВАЛЫ:\n   что-то не так\n" if код == 1
                     else "НЕ ИЗМЕРЕНО: нечем\n" if код == 2 else "всё ок\n")
    monkeypatch.setattr(ИНСТР, "запустить", запустить)


def test_исходы_различаются_по_коду(monkeypatch):
    _подменить(monkeypatch, {"sitemap-index-audit": 1,
                             "sitemap-completeness": 2})
    итог = ИНСТР.свести("x.site")
    по_имени = {с["проверка"]: с["исход"] for с in итог["проверки"]}
    assert по_имени["индекс"] == "провал"
    assert по_имени["полнота"] == "не измерено"
    assert по_имени["цепочка"] == "ок"
    assert итог["провалов"] == 1 and итог["неизмеренных"] == 1


def test_код_ноль_только_когда_всё_чисто(monkeypatch, capsys):
    _подменить(monkeypatch, {})
    assert ИНСТР.главное(["--domain", "x.site"]) == 0
    assert "провалов 0, неизмеренных 0" in capsys.readouterr().out


def test_неизмеренное_даёт_код_два_а_не_ноль(monkeypatch, capsys):
    """Главный контроль: ноль утверждал бы «витрина чистая»."""
    _подменить(monkeypatch, {"sitemap-completeness": 2})
    assert ИНСТР.главное(["--domain", "x.site"]) == 2
    вывод = capsys.readouterr().out
    assert "неизмеренных 1" in вывод
    assert "код 0 даётся ТОЛЬКО когда всё измерено и чисто" in вывод


def test_провал_даёт_код_один(monkeypatch):
    _подменить(monkeypatch, {"sitemap-index-audit": 1,
                             "sitemap-completeness": 2})
    assert ИНСТР.главное(["--domain", "x.site"]) == 1


def test_таймаут_это_не_измерено(monkeypatch):
    """Отрицательный контроль: не уложилось — не значит «чисто»."""
    _подменить(monkeypatch, {"sitemap-lastmod-check": 124})
    итог = ИНСТР.свести("x.site")
    по_имени = {с["проверка"]: с["исход"] for с in итог["проверки"]}
    assert по_имени["даты"] == "не измерено"


def test_без_доменов_код_два(capsys):
    assert ИНСТР.главное([]) == 2
    assert "не названо ни одной витрины" in capsys.readouterr().out


def test_отчёт_записывается(monkeypatch, tmp_path):
    _подменить(monkeypatch, {})
    п = tmp_path / "отчёт.json"
    ИНСТР.главное(["--domain", "x.site", "--report", str(п)])
    отчёт = json.loads(п.read_text(encoding="utf-8"))
    assert отчёт["витрины"][0]["домен"] == "x.site"
    # Сверяются ИМЕНА, а не их число: по числу не видно, какая проверка
    # выпала. Добавление проверки — осознанная правка этого перечня (21.10
    # добавлена «поколение»: описывает ли карта то же поколение каталога, из
    # которого витрина отдаёт страницы — MOD-81).
    assert [п["проверка"] for п in отчёт["витрины"][0]["проверки"]] == [
        "цепочка", "индекс", "даты", "листалка", "полнота", "потери",
        "поколение"]


# --- выбор эталона ------------------------------------------------------------

def test_при_отсутствии_эталона_он_снимается(monkeypatch, tmp_path):
    """Отсутствие эталона — не ошибка: он снимается на будущее."""
    monkeypatch.setattr(ИНСТР, "ЭТАЛОНЫ", tmp_path)
    строки = ИНСТР.проверки("x.site")
    страж = next(ч for и, ч, _ in строки if и == "потери" for ч in [ч])
    assert "--snapshot" in страж and "--baseline" not in страж


def test_при_наличии_эталона_идёт_сверка(monkeypatch, tmp_path):
    monkeypatch.setattr(ИНСТР, "ЭТАЛОНЫ", tmp_path)
    (tmp_path / "x.site.json").write_text("{}", encoding="utf-8")
    строки = ИНСТР.проверки("x.site")
    страж = next(ч for и, ч, _ in строки if и == "потери" for ч in [ч])
    assert "--baseline" in страж and "--snapshot" not in страж


