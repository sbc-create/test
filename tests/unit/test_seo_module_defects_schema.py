"""REQ-SEO-DEFECTS-REGISTRY: заявленная правка обязана нести способ проверки.

Схема реестра недостатков разошлась с реестром: измерено 2026-10-18 — 35
записей из 77 её не проходили. Расхождение накопилось не от небрежности, а
потому что схема описывала словарь меньшего реестра: `zone` знал три значения
на одной оси («кто правит»), а записи пошли по другой («где живёт»); исходов
«измерено», «выпущено» и «дефектом не оказалось» в `state` не было вовсе, и
сессии называли их самодельными словами.

Схема изменена сознательно, а не ослаблена: словарь приведён к тому, что
используется, зато добавлено условие, которого прежде не было ни в схеме, ни
в данных, — запись, ЗАЯВЛЯЮЩАЯ правку, обязана нести `acceptance` либо
`verify_live`. Восемь записей его не несли: критерий лежал в тексте
`owner_action`, то есть читался глазами и схемой не проверялся.

Проверка держит обе стороны границы: и то, что реестр проходит схему, и то,
что схема по-прежнему отвергает настоящий мусор.
"""
from __future__ import annotations

import json
from pathlib import Path

import jsonschema
import pytest

КОРЕНЬ = Path(__file__).resolve().parents[2]
СХЕМА = json.loads((КОРЕНЬ / "schemas" / "seo-module-defects.schema.json")
                   .read_text(encoding="utf-8"))
РЕЕСТР = json.loads((КОРЕНЬ / "config" / "seo-module-defects.json")
                    .read_text(encoding="utf-8"))
ПРОВЕРЯЮЩИЙ = jsonschema.Draft202012Validator(СХЕМА)

ОБРАЗЕЦ = {
    "id": "MOD-99",
    "title": "образец записи для проверки схемы",
    "zone": "seo",
    "priority": "P2",
    "state": "measured",
    "example": "измерено 2026-10-18 инструментом, который называется в тексте",
}


def _ошибки(запись: dict) -> list:
    документ = {"version": 1, "updated_at": "2026-10-18", "defects": [запись]}
    return list(ПРОВЕРЯЮЩИЙ.iter_errors(документ))


def test_реестр_проходит_свою_схему():
    ошибки = list(ПРОВЕРЯЮЩИЙ.iter_errors(РЕЕСТР))
    плохие = sorted({"/".join(str(ч) for ч in о.absolute_path) for о in ошибки})
    assert not ошибки, f"записей с ошибками: {плохие[:10]}"


def test_измерение_без_правки_допустимо():
    """Состояние `measured` — это ещё не правка, и требовать от него
    изменения и ошибочного решения значило бы заставлять выдумывать."""
    assert _ошибки(ОБРАЗЕЦ) == []


@pytest.mark.parametrize("состояние", ["implemented", "installed", "released",
                                       "verified"])
def test_заявленная_правка_без_критерия_отвергается(состояние):
    """Главное условие схемы: «исправлено» без способа проверить — не запись."""
    запись = dict(ОБРАЗЕЦ, state=состояние)
    ошибки = _ошибки(запись)
    assert ошибки, f"состояние {состояние} прошло без критерия приёмки"


@pytest.mark.parametrize("поле", ["acceptance", "verify_live"])
def test_критерий_в_любом_из_двух_полей_подходит(поле):
    запись = dict(ОБРАЗЕЦ, state="released",
                  **{поле: "прогон инструмента даёт ноль провалов"})
    assert _ошибки(запись) == []


def test_пример_обязателен_всегда():
    """Пункт без воспроизводимого примера — гипотеза, а не недостаток."""
    запись = {к: v for к, v in ОБРАЗЕЦ.items() if к != "example"}
    assert _ошибки(запись)


def test_короткий_пример_не_считается_примером():
    assert _ошибки(dict(ОБРАЗЕЦ, example="сломано"))


def test_неизвестное_поле_по_прежнему_отвергается():
    """`additionalProperties: false` оставлен на месте: расширение словаря
    было решением, а не разрешением писать что угодно."""
    assert _ошибки(dict(ОБРАЗЕЦ, какое_то_новое_поле="значение"))


def test_самодельные_имена_состояний_отвергаются():
    """Те самые, что встречались в данных: единое имя исхода — смысл enum."""
    for плохое in ("fix_prepared", "corrected", "fixed", "measured-no-defect",
                   "готово"):
        assert _ошибки(dict(ОБРАЗЕЦ, state=плохое)), плохое


def test_неизвестная_зона_отвергается():
    assert _ошибки(dict(ОБРАЗЕЦ, zone="где-то"))


def test_все_значения_словаря_встречаются_в_реестре():
    """Отрицательный контроль к расширению: словарь расширен ПО ДАННЫМ.

    Если значение в enum есть, а в реестре его нет ни у одной записи, значит
    оно добавлено на будущее, а не по измерению, — и тогда расширение надо
    обосновывать заново.
    """
    записи = РЕЕСТР["defects"]
    свойства = СХЕМА["properties"]["defects"]["items"]["properties"]
    # Значения, стоявшие в схеме ДО расширения 2026-10-18. Их обоснование —
    # прежнее решение, и спрашивать с них данные эта проверка не вправе;
    # `installed` в реестре действительно не встречается ни разу.
    БЫЛИ_РАНЬШЕ = {"zone": {"seo", "shared", "owner"},
                   "state": {"proposed", "implemented", "installed", "verified"}}
    for поле in ("zone", "state"):
        объявлено = set(свойства[поле]["enum"]) - БЫЛИ_РАНЬШЕ[поле]
        в_данных = {з.get(поле) for з in записи}
        лишние = объявлено - в_данных
        assert not лишние, (
            f"{поле}: добавлено в словарь, но в данных не встречается: "
            f"{sorted(лишние)}")
