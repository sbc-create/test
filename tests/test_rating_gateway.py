def test_первичная_оценка_не_перезаписывается():
    """Значение основного поставщика остаётся на месте.

    Иначе витрина показывала бы то одно число, то другое — в зависимости от
    того, какой прогон был последним.
    """
    п = rg.ЖурналПоставщик(ответы={"kp-1": [оценка("kp-1", 3.0)]})
    д = детали(film={"id": "id-1", "kinopoisk_rating": 8.4})
    итог, отчёт = rg.обогатить(д, {"id-1": {"kinopoisk": "kp-1"}}, поставщики=[п])
    assert итог["film"]["kinopoisk_rating"] == 8.4
    assert п.запрошено == []          # спрашивать было незачем
    assert отчёт["rejections"][rg.УЖЕ_ЕСТЬ] >= 1


def test_пустое_значение_заполняется():
    п = rg.ЖурналПоставщик(ответы={"kp-1": [оценка("kp-1", 6.2)]})
