def test_бюджет_соблюдается():
    ответы = {f"kp-{n}": [оценка(f"kp-{n}", 7.0)] for n in range(10)}
    п = rg.ЖурналПоставщик(ответы=ответы)
    д = детали(**{f"s{n}": {"id": f"id-{n}"} for n in range(10)})
    внешние = {f"id-{n}": {"kinopoisk": f"kp-{n}"} for n in range(10)}
    _, отчёт = rg.обогатить(д, внешние, поставщики=[п], бюджет=3)
    assert len(п.запрошено) == 3
    assert отчёт["requested"] == 3
    assert отчёт["rejections"][rg.БЮДЖЕТ] == 7


def test_знаменатель_покрытия_не_уменьшается():
    д = детали(a={"kinopoisk_rating": 7.0}, b={}, c={}, d={})
    п = rg.покрытие_по_источникам(д)
    assert п["published"] == 4
    assert п["by_source"][rg.ИСТОЧНИК_КП] == {"count": 1, "pct": 25.0}
    assert п["by_source"][rg.ИСТОЧНИК_IMDB] == {"count": 0, "pct": 0.0}


