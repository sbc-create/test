def test_привязка_только_по_внешнему_идентификатору():
    """Записи без внешнего ид не спрашиваются вовсе."""
    п = rg.ЖурналПоставщик(ответы={"kp-1": [оценка("kp-1", 7.5)]})
    д = детали(есть={"id": "id-1"}, нет={"id": "id-2"})
    внешние = {"id-1": {"kinopoisk": "kp-1"}, "id-2": {}}
    итог, отчёт = rg.обогатить(д, внешние, поставщики=[п])
    assert п.запрошено == ["kp-1"]
    assert итог["есть"]["kinopoisk_rating"] == 7.5
    assert "kinopoisk_rating" not in итог["нет"]
    assert отчёт["rejections"][rg.НЕТ_ВНЕШНЕГО_ИД] == 1


def test_чужой_идентификатор_в_ответе_отвергается():
    """Ответ про другое произведение — отказ, а не «почти то же самое».

    Принять его значит показать чужое число под правильным названием: снаружи
    страница выглядит исправной, и замечено это не будет.
    """
    п = rg.ЖурналПоставщик(ответы={"kp-1": [оценка("kp-999", 9.9)]})
    д = детали(film={"id": "id-1"})
    итог, отчёт = rg.обогатить(д, {"id-1": {"kinopoisk": "kp-1"}}, поставщики=[п])
    assert "kinopoisk_rating" not in итог["film"]
    assert отчёт["rejections"][rg.ЧУЖОЙ_ИД] == 1
    assert отчёт["applied"] == 0


