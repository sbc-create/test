"""Проверки шлюза вторичных источников оценок.

Раздел существует до того, как появился сам источник, и это осознанно: иначе
первым испытанием интеграции окажется боевой прогон на живых витринах.

Проверяется ровно то, чем оценка из второго источника опасна: чужое число под
правильным названием, подмена уже известного значения, ноль вместо
отсутствия, смешение источников в одном поле и молчаливый пропуск.
"""
from __future__ import annotations

import pytest

from factory.lords import rating_gateway as rg


@pytest.fixture(autouse=True)
def чистый_реестр():
    rg.очистить_реестр()
    yield
    rg.очистить_реестр()


def оценка(external_id, value, *, source=rg.ИСТОЧНИК_КП, provider="test",
           scale=10.0, votes=None):
    return rg.ОценкаИсточника(source=source, provider=provider,
                              external_id=str(external_id), value=value,
                              scale=scale, votes=votes,
                              retrieved_at="2026-09-14T00:00:00Z")


def детали(**записи):
    return {слаг: dict(з) for слаг, з in записи.items()}


# ----------------------------------------------------------------------
#  Нормальное состояние сегодня: источников нет
# ----------------------------------------------------------------------

def test_без_поставщиков_ничего_не_меняется():
    """Отсутствие вторичного источника — состояние, а не отказ."""
    д = детали(film={"id": "id-1"})
    было = {к: dict(v) for к, v in д.items()}
    итог, отчёт = rg.обогатить(д, {"id-1": {"kinopoisk": "123"}})
    assert итог == было
    assert отчёт["applied"] == 0
    assert "не зарегистрировано" in отчёт["note"]


def test_реестр_отвергает_привязку_по_чему_попало():
    class Кривой:
        имя = "кривой"
        ключ_привязки = "title"      # привязка по названию
        отдаёт = (rg.ИСТОЧНИК_КП,)
        def оценки(self, запрос): return {}
    with pytest.raises(rg.RatingGatewayError, match="не.*разрешена"):
        rg.зарегистрировать(Кривой())


def test_реестр_отвергает_поставщика_без_источников():
    class Пустой:
        имя = "пустой"
        ключ_привязки = "kinopoisk"
        отдаёт = ()
        def оценки(self, запрос): return {}
    with pytest.raises(rg.RatingGatewayError, match="ни одного источника"):
        rg.зарегистрировать(Пустой())


