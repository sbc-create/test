def test_каждый_источник_хранится_отдельно():
    """Оценка TMDb не попадает в поле Кинопоиска ни при каких условиях."""
    class ТМДБ:
        имя = "tmdb-adapter"
        ключ_привязки = "tmdb"
        отдаёт = ("tmdb",)
        def оценки(self, запрос):
            return {к: [оценка(к, 78.0, source="tmdb", provider=self.имя,
                               scale=100.0, votes=1200)] for к in запрос}
    д = детали(film={"id": "id-1"})
    итог, отчёт = rg.обогатить(д, {"id-1": {"tmdb": "t-1"}}, поставщики=[ТМДБ()])
    з = итог["film"]
    # У TMDb нет своего плоского поля на витрине — и он в чужое не лезет.
    assert "kinopoisk_rating" not in з
    assert "imdb_rating" not in з
    разрез = з["ratings_by_source"]["tmdb"]
    assert разрез["provider"] == "tmdb-adapter"
    assert разрез["external_id"] == "t-1"
    assert разрез["scale"] == 100.0
    assert разрез["votes"] == 1200
    # Шкала приведена по одной записанной формуле, а не «на глаз».
    assert разрез["value_on_ten"] == 7.8


def test_происхождение_записано_полностью():
    п = rg.ЖурналПоставщик(ответы={"kp-1": [оценка("kp-1", 7.0, votes=55)]})
    д = детали(film={"id": "id-1"})
    итог, _ = rg.обогатить(д, {"id-1": {"kinopoisk": "kp-1"}}, поставщики=[п])
    р = итог["film"]["ratings_by_source"][rg.ИСТОЧНИК_КП]
    for ключ in ("source", "provider", "external_id", "value", "scale",
                 "retrieved_at", "votes"):
        assert ключ in р, ключ


