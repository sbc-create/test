@pytest.mark.parametrize("значение,код", [
    (0, rg.ВНЕ_ДИАПАЗОНА),
    (0.0, rg.ВНЕ_ДИАПАЗОНА),
    (-1.0, rg.ВНЕ_ДИАПАЗОНА),
    (10.5, rg.ВНЕ_ДИАПАЗОНА),
    ("нет", rg.НЕ_ЧИСЛО),
    (None, rg.НЕ_ЧИСЛО),
])
def test_не_оценка_отвергается_с_кодом(значение, код):
    """Ноль — это отсутствие, а не оценка в ноль баллов."""
    п = rg.ЖурналПоставщик(ответы={"kp-1": [оценка("kp-1", значение)]})
    д = детали(film={"id": "id-1"})
    итог, отчёт = rg.обогатить(д, {"id-1": {"kinopoisk": "kp-1"}}, поставщики=[п])
    assert "kinopoisk_rating" not in итог["film"]
    assert отчёт["rejections"][код] == 1


