"""Предусловие набора: собственный эфемерный Audit API, поднятый здесь же.

Тесты этого каталога интеграционные: они пишут события по HTTP и проверяют
цепочку, роли, карантин и восстановление. Журнал только дописывается, поэтому
написанное тестом остаётся в нём навсегда — набор обязан работать по своему
экземпляру и ни по какому другому.

Опасность, ради которой этот файл существует, конкретна. Умолчание
`AUDIT_API_BASE` в `test_ledger.py` — `http://127.0.0.1:8790`, то есть
**канонический** control API машины. Голый `pytest tests/` попадал прямо в него,
и от записи тестовых событий в историю системы спасал лишь несовпавший токен:
единственной преградой был ответ 401. Поэтому адрес здесь не проверяется, а
**задаётся**: набор направляется на заведомо свой экземпляр до того, как
тестовые модули прочитают окружение.

Почему запуск на уровне модуля, а не фикстурой. `test_ledger.py` читает адрес и
токены при импорте. Фикстура вызывается позже, к её моменту модуль уже прочитал
умолчания и ходил бы в чужой журнал. conftest импортируется раньше тестовых
модулей своего каталога — это единственное место, где правка окружения ещё
что-то значит.

Почему здесь нет `skip`. Прежняя редакция пропускала набор, когда экземпляр не
объявлен, и на машине без обвязки проверка становилась зелёной, не выполнив ни
одного сравнения. «Служба не поднялась» и «всё хорошо» обязаны выглядеть
по-разному, иначе сломанную службу не заметит никто. Не поднявшийся журнал роняет
импорт conftest, pytest сообщает об ошибке сбора, обязательная проверка краснеет.
"""
from __future__ import annotations

import atexit
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tests import _ledger_harness as обвязка  # noqa: E402

#: Порт канонического control API. Собственный экземпляр берёт свободный порт у
#: ядра, поэтому совпасть с этим номером не может; проверка остаётся как
#: страховка от случайной правки обвязки.
КАНОНИЧЕСКИЙ_ПОРТ = 8790

_ЭКЗЕМПЛЯР = обвязка.поднять()

if _ЭКЗЕМПЛЯР.порт == КАНОНИЧЕСКИЙ_ПОРТ:  # pragma: no cover - страховка
    _ЭКЗЕМПЛЯР.погасить()
    raise RuntimeError(
        "эфемерный экземпляр занял канонический порт; набор пишет события "
        "и по каноническому журналу не выполняется")

#: Что было в окружении ДО правки. Снимок нужен, чтобы её снять.
#:
#: Правка глобальная — иначе она бессмысленна: тестовые модули этого каталога
#: читают адрес и пути при импорте, а импорт происходит раньше любой фикстуры.
#: Но глобальная правка, которую никто не снимает, живёт до конца процесса и
#: достаётся КАЖДОМУ набору, собранному после этого.
#:
#: Так и случилось. `REGISTRY_DB` эфемерного прогона оставался выставленным, и
#: `/api/v1/sites` читал реестр прогона вместо профилей репозитория: админка
#: показывала `ephemeral-ledger-site-a` вместо витрин флота, а
#: `tests/unit/test_admin_http.py` падал — но только в полном прогоне, и только
#: после того, как обвязка обзавелась полным набором таблиц. До этого запрос к
#: реестру прогона падал, API молча откатывался к профилям, и утечка ничем себя
#: не проявляла. Ошибка была всё это время; её просто нечем было заметить.
_ПРЕЖНЕЕ_ОКРУЖЕНИЕ = {
    ключ: os.environ.get(ключ)
    for ключ in {*_ЭКЗЕМПЛЯР.окружение, "AUDIT_API_BASE"}
}

# Порядок важен: окружение правится до импорта тестовых модулей этого каталога.
os.environ.update(_ЭКЗЕМПЛЯР.окружение)
os.environ["AUDIT_API_BASE"] = _ЭКЗЕМПЛЯР.адрес


#: Правка целиком, чтобы её можно было накладывать повторно.
_ЭФЕМЕРНОЕ_ОКРУЖЕНИЕ = {**_ЭКЗЕМПЛЯР.окружение,
                        "AUDIT_API_BASE": _ЭКЗЕМПЛЯР.адрес}


def применить_окружение() -> None:
    os.environ.update(_ЭФЕМЕРНОЕ_ОКРУЖЕНИЕ)


def вернуть_окружение() -> None:
    """Снять правку: ключи, которых не было, удалить; прежние — вернуть."""
    for ключ, значение in _ПРЕЖНЕЕ_ОКРУЖЕНИЕ.items():
        if значение is None:
            os.environ.pop(ключ, None)
        else:
            os.environ[ключ] = значение


# Правка действует ровно на тесты этого каталога — ни раньше, ни позже.
#
# Хуки, а не фикстура. Фикстура со scope="package" выглядит уместнее, но её
# финализация откладывается до конца сессии: проверено `--setup-show` —
# `TEARDOWN P` печатается последней строкой прогона, уже после чужих наборов.
# То есть ровно та утечка, которую фикстура должна была закрыть, оставалась бы
# открытой. Хуки conftest применяются только к элементам своего каталога, и их
# порядок определён.
def pytest_runtest_setup(item):  # noqa: ARG001 - контракт хука
    применить_окружение()


def pytest_runtest_teardown(item, nextitem):  # noqa: ARG001 - контракт хука
    вернуть_окружение()


atexit.register(_ЭКЗЕМПЛЯР.погасить)
atexit.register(вернуть_окружение)

# Мост реестра доводится до догнавшего состояния ОДИН раз, до тестов.
#
# `test_06` проверяет идемпотентность переноса: два вызова подряд не должны
# ничего добавить, и меряет это равенством «сколько было в журнале, столько и
# осталось». Утверждение верно для моста, который уже догнал реестр, — так он и
# живёт в работающем контуре. На пустом журнале первый же перенос законно
# добавляет записи, и проверка падает, измерив не идемпотентность, а отставание.
#
# Импорт здесь, а не наверху: модуль читает REGISTRY_DB и AUDIT_LEDGER_DB при
# импорте, а к этой строке окружение уже указывает на эфемерные хранилища.
from factory.site_engine.audit import registry_bridge as _мост  # noqa: E402

_мост.перенести()
