"""Проверки адаптеров реальных источников оценок.

Главное здесь — `tconst`. Поставщик каталога отдаёт голое число, а IMDb
дополняет его нулями до семи знаков. Ошибка в одну позицию означает не
«оценка не нашлась», а оценку другого фильма: `tt0035990` и `tt35990570` оба
существуют, и оба вернут число. Такую ошибку не видно ни в одном счётчике —
покрытие вырастет, а значения будут чужими.
"""
from __future__ import annotations

import gzip

import pytest

from factory.lords import rating_sources as rs
from factory.lords.rating_gateway import ОценкаИсточника


# ----------------------------------------------------------------------
#  tconst
# ----------------------------------------------------------------------

@pytest.mark.parametrize("сырое,ожидание", [
    ("1", "tt0000001"),
    ("12345", "tt0012345"),
    ("1234567", "tt1234567"),
    ("35990570", "tt35990570"),      # длиннее семи — не дополняется
    ("tt0012345", "tt0012345"),      # уже с префиксом
    ("TT12345", "tt0012345"),
    ("  12345  ", "tt0012345"),
])
def test_tconst_дополняется_правильно(сырое, ожидание):
    assert rs.tconst(сырое) == ожидание


@pytest.mark.parametrize("плохое", ["", None, "abc", "tt", "12a45"])
def test_tconst_отвергает_непригодное(плохое):
    assert rs.tconst(плохое) is None


def test_короткий_и_длинный_не_совпадают():
    """Разные числа обязаны давать разные идентификаторы.

    Если бы дополнение применялось к длинным, `35990570` превратилось бы в
    `tt3599057` — существующий, но чужой фильм.
    """
    assert rs.tconst("35990570") != rs.tconst("3599057")


