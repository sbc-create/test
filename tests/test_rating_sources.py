@pytest.fixture
def датасет(tmp_path):
    п = tmp_path / "title.ratings.tsv.gz"
    with gzip.open(п, "wt", encoding="utf-8") as ф:
        ф.write("tconst\taverageRating\tnumVotes\n")
        ф.write("tt0012345\t7.4\t1200\n")
        ф.write("tt35990570\t6.1\t88\n")
        ф.write("tt0000009\t0.0\t0\n")       # ноль — не оценка
        ф.write("битая строка\n")
    return п


def test_imdb_читает_датасет(датасет):
    и = rs.ИсточникIMDb(путь=датасет).загрузить()
    assert и.загружено_строк == 3            # битая строка отброшена
    assert и.ключ_привязки == "imdb"
    assert и.отдаёт == (rs.ИСТОЧНИК_IMDB,)


def test_imdb_возвращает_идентификатор_как_спросили(датасет):
    """Шлюз сверяет ответ с запросом: приведённая форма выглядела бы чужой."""
    и = rs.ИсточникIMDb(путь=датасет).загрузить()
    ответ = и.оценки(["12345"])
    assert list(ответ) == ["12345"]
    (о,) = ответ["12345"]
    assert о.external_id == "12345"           # не "tt0012345"
    assert о.value == 7.4
    assert о.votes == 1200
    assert о.source == rs.ИСТОЧНИК_IMDB
    assert о.scale == 10.0


def test_imdb_длинный_идентификатор(датасет):
    (о,) = rs.ИсточникIMDb(путь=датасет).загрузить().оценки(["35990570"])["35990570"]
    assert о.value == 6.1


def test_imdb_чего_нет_того_нет(датасет):
    assert rs.ИсточникIMDb(путь=датасет).загрузить().оценки(["999999"]) == {}


def test_imdb_ноль_доходит_но_отвергается_шлюзом(датасет):
    """Адаптер не решает за шлюз, но ноль обязан быть отвергнут."""
    from factory.lords.rating_gateway import проверить_значение, ВНЕ_ДИАПАЗОНА
    (о,) = rs.ИсточникIMDb(путь=датасет).загрузить().оценки(["0000009"])["0000009"]
    assert проверить_значение(о) == ВНЕ_ДИАПАЗОНА


