class ОтветЗаглушка:
    def __init__(self, тело): self._тело = тело
    def read(self): return self._тело
    def __enter__(self): return self
    def __exit__(self, *a): return False


def открыватель(тело):
    def _(запрос, таймаут):
        открыватель.последний = запрос.full_url
        return ОтветЗаглушка(тело.encode("utf-8"))
    return _


def test_shikimori_разбирает_ответ():
    тело = ('[{"id":1037,"score":"6.04","russian":"Священные звери"},'
            '{"id":2,"score":"0.0","russian":"Без оценки"},'
            '{"id":3,"score":null,"name":"Нет поля"}]')
    и = rs.ИсточникShikimori(пауза=0)
    и.открыватель = открыватель(тело)
    ответ = и.оценки(["1037", "2", "3"])
    assert list(ответ) == ["1037"]            # ноль и null — не оценки
    (о,) = ответ["1037"]
    assert о.value == 6.04
    assert о.source == rs.ИСТОЧНИК_SHIKIMORI
    assert о.external_id == "1037"
    assert и.названия["1037"] == "Священные звери"


def test_shikimori_бьёт_на_пакеты():
    и = rs.ИсточникShikimori(пауза=0, пакет=2)
    и.открыватель = открыватель("[]")
    и.оценки(["1", "2", "3", "4", "5"])
    assert и.запросов == 3                    # 2+2+1


def test_shikimori_отказ_источника_не_роняет_прогон():
    def падающий(запрос, таймаут):
        raise OSError("источник недоступен")
    и = rs.ИсточникShikimori(пауза=0)
    и.открыватель = падающий
    assert и.оценки(["1"]) == {}
    assert и.ошибок == 1


def test_shikimori_представляется():
    """Обход без User-Agent — нарушение условий источника, а не находчивость."""
    и = rs.ИсточникShikimori(пауза=0)
    заголовки = {}
    def запомнить(запрос, таймаут):
        заголовки.update(запрос.headers)
        return ОтветЗаглушка(b"[]")
    и.открыватель = запомнить
    и.оценки(["1"])
    assert "site-factory-nova" in заголовки.get("User-agent", "")


