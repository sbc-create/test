class TestСпособностьСлужбыПодписи:
    """Блокер, который здесь фиксировался, снят коммитом 6cd5a5e.

    Раньше аудитории `templates-executor` не существовало вовсе, и набор
    документировал именно это: «механизм работает, аудитории нет». Контракт
    `template.release` её добавил и выдал полное разрешение на исполнение,
    поэтому прежние утверждения стали неверными — не потому, что что-то
    сломалось, а потому, что блокер устранён.

    Оставить их как есть значило бы держать красным набор, доказывающий
    отсутствие того, что уже сделано. Поэтому проверки переписаны на то, что
    гарантирует новый контракт: они и дальше поймают регресс, но теперь —
    настоящий.
    """

    def test_аудитория_привязана_к_своему_роду_ресурса(self, стенд):
        """`templates-executor` допущена, но исполняет только `template.release`.

        Проверяется не отказ вообще, а ПРИЧИНА отказа. Разница существенная:
        `AUDIENCE_NOT_ALLOWED` означал бы, что аудитории нет, и тогда привязку
        к роду ресурса никто не проверял. `AUDIENCE_RESOURCE_MISMATCH` означает,
        что аудитория есть и связь «кто исполняет что» действует — иначе
        разрешение на шаблон предъявили бы исполнителю чужого ресурса.
        """
        цель = собрать_цель(стенд)
        cid, _ = довести_до_approved(стенд, цель)
        аренда = S.взять_аренду(стенд["соед"], cid, "changeset-worker")
        код, тело = запросить_grant(стенд, cid, audience=G.АУДИТОРИЯ,
                                    fencing_token=аренда["fencing_token"])
        assert код == 403
        assert тело["error_code"] == "AUDIENCE_RESOURCE_MISMATCH"

    def test_механизм_при_этом_исправен(self, стенд):
        цель = собрать_цель(стенд)
        cid, _ = довести_до_approved(стенд, цель)
        аренда = S.взять_аренду(стенд["соед"], cid, "changeset-worker")
        код, тело = запросить_grant(стенд, cid, audience="changeset-worker",
                                    fencing_token=аренда["fencing_token"])
        assert код == 200 and тело["grant"]["typ"] == "execution-grant"

    def test_разрешение_несёт_все_обязательные_притязания(self, стенд):
        """Ни одного пропущенного притязания — включая три прежде отсутствовавших.

        `jti`, `resource_kind` и `artifact_digest` названы поимённо не для
        красоты: именно их не хватало, пока блокер держался, и именно их
        пропажу нужно заметить первой. Проверка всего перечня `ОБЯЗАТЕЛЬНЫЕ`
        оставлена рядом, чтобы новое обязательное притязание не появилось
        молча пустым: «необязательное» притязание безопасности — это то,
        которое однажды не придёт, а проверка промолчит.
        """
        цель = собрать_цель(стенд)
        cid, _ = довести_до_approved(стенд, цель)
        аренда = S.взять_аренду(стенд["соед"], cid, "changeset-worker")
        _, тело = запросить_grant(стенд, cid, audience="changeset-worker",
                                  fencing_token=аренда["fencing_token"])
        нет = [п for п in G.ОБЯЗАТЕЛЬНЫЕ if not тело["grant"].get(п)]
        assert нет == [], f"разрешение выдано без притязаний: {нет}"
        assert {"jti", "resource_kind", "artifact_digest"} <= set(G.ОБЯЗАТЕЛЬНЫЕ)


