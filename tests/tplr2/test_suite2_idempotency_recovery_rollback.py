class TestОбрывПослеЭффекта:
    def test_возобновление_не_повторяет_эффект(self, стенд):
        с = _стенд_исполнителя(стенд, ключ_набора="crash-1",
                               журнал="crash.sqlite3")
        ключ = "crash-idem-1"
        с["цель"]["мир"].сломать(F.ПАДЕНИЕ_ПОСЛЕ_ЭФФЕКТА)
        with pytest.raises(F.Обрыв):
            с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                               ожидания=ожидания(**с["основа"]),
                               план=с["план"], idempotency_key=ключ)
        эффектов_до = с["цель"]["мир"].эффектов("create")
        assert эффектов_до == 1, "эффект обязан быть durable до обрыва"
        притязание = с["исп"].притязание(ключ)
        assert притязание["state"] == "CLAIMED", (
            "неизвестный исход не даёт права утверждать, что эффекта не было")

        # Тот же исполнитель поднимается заново на том же журнале.
        с["исп"].закрыть()
        с["цель"]["мир"].починить()
        снова = TemplatesExecutor(стенд["tmp"] / "crash.sqlite3",
                                  с["цель"]["адаптер"], набор_ключей(стенд),
                                  наблюдатель=с["наблюдать"])
        свод = снова.возобновить()
        assert свод == {"checked": 1, "confirmed_existing": 1, "reapplied": 0,
                        "unresolved": 0}
        assert с["цель"]["мир"].эффектов("create") == эффектов_до
        итог = снова.притязание(ключ)
        assert итог["state"] == "SUCCEEDED"
        assert итог["effect_ref"] == f"template:counter_tag:{стенд['site_id']}"
        снова.закрыть()

    def test_после_возобновления_повтор_безвреден(self, стенд):
        с = _стенд_исполнителя(стенд, ключ_набора="crash-2",
                               журнал="crash2.sqlite3")
        ключ = "crash-idem-2"
        с["цель"]["мир"].сломать(F.ПАДЕНИЕ_ПОСЛЕ_ЭФФЕКТА)
        with pytest.raises(F.Обрыв):
            с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                               ожидания=ожидания(**с["основа"]),
                               план=с["план"], idempotency_key=ключ)
        с["цель"]["мир"].починить()
        с["исп"].возобновить()
        повтор = с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                                    ожидания=ожидания(**с["основа"]),
                                    план=с["план"], idempotency_key=ключ)
        assert повтор.replay is True and повтор.effects == 0
        assert с["цель"]["мир"].эффектов("create") == 1
        assert с["исп"].незавершённые() == []

    def test_терминальное_состояние_набора(self, стенд):
        """Набор доводится каноническим путём, а не записью статуса."""
        с = _стенд_исполнителя(стенд, ключ_набора="crash-3",
                               журнал="crash3.sqlite3")
        # Тот же исполнитель, что держит аренду: чужой получил бы LEASE_HELD,
        # и это правильное поведение, а не помеха проверке.
        аренда = S.взять_аренду(стенд["соед"], с["cid"], "changeset-worker")
        итог = с["движок"].применить(с["cid"],
                                     actor_id="service:control-plane",
                                     служба="control-plane",
                                     fencing_token=аренда["fencing_token"])
        assert итог["status"] == M.SUCCEEDED
        assert M.SUCCEEDED in M.ТЕРМИНАЛЬНЫЕ
