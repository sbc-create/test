"""SUITE_2 — идемпотентность: последовательная, одновременная, после обрыва.

Три отдельных стенда и три отдельных набора изменений. Счётчики не
смешиваются: «один эффект» в трёх разных смыслах — три разных утверждения,
и общий счётчик скрыл бы, какое из них не выполняется.
"""
from __future__ import annotations

import threading

import pytest

from factory.site_engine.changeset import model as M
from factory.site_engine.changeset import store as S
from factory.site_engine.provisioner.providers import fake as F
from factory.site_engine.provisioner.templates_executor import TemplatesExecutor

from ._путь import (выпустить_grant, довести_до_approved, набор_ключей,
                    ожидания, отпечаток_реестра, собрать_цель)


def _стенд_исполнителя(стенд, *, ключ_набора: str, журнал: str):
    """Свежая цель, свой набор изменений, свой журнал исполнителя."""
    цель = собрать_цель(стенд)
    cid, движок = довести_до_approved(стенд, цель, ключ=ключ_набора)
    аренда = S.взять_аренду(стенд["соед"], cid, "changeset-worker")
    набор = S.получить(стенд["соед"], cid)
    план = набор["dry_run_result"]["per_site_plan"][стенд["site_id"]]
    основа = {"changeset_id": cid, "site_id": стенд["site_id"],
              "plan_hash": набор["plan_hash"],
              "artifact_digest": план["expected_fingerprint"],
              "registry_fingerprint": отпечаток_реестра(стенд),
              "fencing_token": аренда["fencing_token"]}

    def наблюдать(site_id: str):
        ключ = f"template:counter_tag:{site_id}"
        return ключ if ключ in цель["мир"].объекты else None

    исполнитель = TemplatesExecutor(стенд["tmp"] / журнал, цель["адаптер"],
                                    набор_ключей(стенд), наблюдатель=наблюдать)
    подпись, полезное = выпустить_grant(стенд, **основа)
    return {"цель": цель, "cid": cid, "движок": движок, "план": план,
            "основа": основа, "исп": исполнитель, "подпись": подпись,
            "полезное": полезное, "наблюдать": наблюдать}


# =============================================================================
# Последовательная идемпотентность
# =============================================================================

class TestПоследовательная:
    def test_два_последовательных_вызова_дают_один_эффект(self, стенд):
        с = _стенд_исполнителя(стенд, ключ_набора="seq-1", журнал="seq.sqlite3")
        ключ = "seq-idem-1"
        первый = с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                                    ожидания=ожидания(**с["основа"]),
                                    план=с["план"], idempotency_key=ключ)
        второй = с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                                    ожидания=ожидания(**с["основа"]),
                                    план=с["план"], idempotency_key=ключ)
        assert (первый.replay, второй.replay) == (False, True)
        assert первый.effects == 1 and второй.effects == 0
        assert первый.effect_ref == второй.effect_ref
        assert с["цель"]["мир"].эффектов("create") == 1

    def test_повтор_не_создаёт_второго_притязания(self, стенд):
        с = _стенд_исполнителя(стенд, ключ_набора="seq-2", журнал="seq2.sqlite3")
        ключ = "seq-idem-2"
        for _ in range(3):
            с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                               ожидания=ожидания(**с["основа"]),
                               план=с["план"], idempotency_key=ключ)
        строки = с["исп"].соед.execute(
            "SELECT COUNT(*) c FROM execution_claim").fetchone()["c"]
        assert строки == 1
        assert с["цель"]["мир"].эффектов("create") == 1


