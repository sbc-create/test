class TestОдновременная:
    def test_два_пересекающихся_вызова_один_победитель(self, стенд):
        с = _стенд_исполнителя(стенд, ключ_набора="conc-1",
                               журнал="conc.sqlite3")
        ключ = "conc-idem-1"
        барьер = threading.Barrier(2)
        исходы: list = [None, None]
        ошибки: list = []

        def вызвать(номер: int):
            # У каждого потока СВОЙ исполнитель на общем журнале — так и
            # выглядит настоящая гонка двух рабочих процессов. Общее
            # соединение SQLite между потоками не переносится, и проверка на
            # нём измеряла бы ограничение драйвера, а не поведение контура.
            своя_цель = собрать_цель(стенд, мир=с["цель"]["мир"],
                                     метка=f"-t{номер}")
            своя_цель["адаптер"].changeset_id = с["cid"]
            свой = TemplatesExecutor(стенд["tmp"] / "conc.sqlite3",
                                     своя_цель["адаптер"], набор_ключей(стенд),
                                     наблюдатель=с["наблюдать"])
            try:
                барьер.wait(timeout=10)
                исходы[номер] = свой.выполнить(
                    подпись=с["подпись"], полезное=с["полезное"],
                    ожидания=ожидания(**с["основа"]), план=с["план"],
                    idempotency_key=ключ)
            except Exception as ош:            # исход потока не теряем
                ошибки.append(f"{type(ош).__name__}: {ош}")
            finally:
                свой.закрыть()

        потоки = [threading.Thread(target=вызвать, args=(i,)) for i in range(2)]
        for п in потоки:
            п.start()
        for п in потоки:
            п.join(timeout=20)

        assert not ошибки, f"поток завершился ошибкой: {ошибки}"
        победители = [и for и in исходы if и and и.fence_winner]
        assert len(победители) == 1, "победитель гонки обязан быть ровно один"
        assert с["цель"]["мир"].эффектов("create") == 1
        ссылки = {и.effect_ref for и in исходы if и and и.effect_ref}
        assert len(ссылки) == 1, "оба вызова обязаны указывать на один эффект"

    def test_проигравший_не_исполняет(self, стенд):
        с = _стенд_исполнителя(стенд, ключ_набора="conc-2",
                               журнал="conc2.sqlite3")
        ключ = "conc-idem-2"
        первый = с["исп"].выполнить(подпись=с["подпись"], полезное=с["полезное"],
                                    ожидания=ожидания(**с["основа"]),
                                    план=с["план"], idempotency_key=ключ)
        проигравший = с["исп"].выполнить(
            подпись=с["подпись"], полезное=с["полезное"],
            ожидания=ожидания(**с["основа"]), план=с["план"],
            idempotency_key=ключ)
        assert первый.fence_winner is True
        assert проигравший.fence_winner is False
        assert проигравший.effects == 0
        assert с["цель"]["мир"].эффектов("create") == 1


