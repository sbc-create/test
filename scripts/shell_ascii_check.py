#!/usr/bin/env python3
"""Имена в shell-сценариях обязаны быть ASCII. Русский — только в тексте.

Дефект LORDS-NIGHT-RUNNER-NONASCII-VAR-34. В runner ночной выкладки стояло

    СВОЙ="$(readlink -f "$0")"

Кириллица недопустима в имени переменной, поэтому bash разбирает строку не как
присваивание, а как имя команды — и падает уже в бою:

    line 25: СВОЙ=/usr/local/sbin/lords-night-release: No such file or directory

`bash -n` этого не ловит и поймать не может: синтаксически строка безупречна,
это корректный вызов команды с необычным именем. Разбор проходит, исполнение —
нет. Значит нужна отдельная проверка, и она перед вами.

Проверяется не «есть ли кириллица в файле» — она разрешена и полезна в
комментариях и сообщениях, — а есть ли она там, где shell ожидает идентификатор
или голое слово: в присваивании, в имени функции, в переменной цикла.

Запуск:
    python3 scripts/shell_ascii_check.py automation/host/*.sh
Код возврата 1 — есть нарушения.
"""

from __future__ import annotations

import sys
from pathlib import Path


def _без_строк_и_комментария(строка: str) -> str:
    """Строка без кавычек и хвостового комментария.

    Разбор посимвольный, а не регулярным выражением: `#` внутри кавычек не
    начинает комментарий, а кавычка внутри комментария ничего не открывает.
    """
    итог: list[str] = []
    стек: list[str] = [""]          # состояние кавычек, по уровню подстановки
    i = 0
    while i < len(строка):
        с = строка[i]
        кавычка = стек[-1]
        # `$(` открывает новый разбор — и делает это ВНУТРИ двойных кавычек тоже.
        # Первая редакция проверяла подстановку только вне кавычек, и безупречная
        # строка `x="$(cmd "путь" || echo "СЛОВО")"` разбиралась так, что слово
        # оказывалось вне кавычек. Одиночные кавычки подстановку не открывают.
        if кавычка != "'" and строка[i:i + 2] == "$(":
            стек.append("")
            i += 2
            continue
        if с == ")" and len(стек) > 1 and not кавычка:
            стек.pop()
            i += 1
            continue
        if кавычка:
            if с == "\\" and кавычка == '"':
                i += 2
                continue
            if с == кавычка:
                стек[-1] = ""
            i += 1
            continue
        if с in "'\"":
            стек[-1] = с
            i += 1
            continue
        if с == "#" and (not итог or итог[-1].isspace()):
            break
        итог.append(с)
        i += 1
    return "".join(итог)


def нарушения(текст: str) -> list[tuple[int, str]]:
    беды: list[tuple[int, str]] = []
    маркер = None
    for номер, сырая in enumerate(текст.splitlines(), 1):
        # Тело heredoc — данные для другого языка, а не shell.
        if маркер is not None:
            if сырая.strip() == маркер:
                маркер = None
            continue
        обрезанная = сырая.split("#", 1)[0]
        if "<<" in обрезанная:
            хвост = обрезанная.split("<<", 1)[1].strip()
            хвост = хвост.lstrip("-")
            имя = хвост.strip("'\"").split()[0] if хвост.strip("'\"") else ""
            if имя.isidentifier() or (имя and имя.isupper()):
                маркер = имя
                continue
        видимая = _без_строк_и_комментария(сырая)
        if видимая.isascii():
            continue
        for кусок in видимая.split():
            if кусок.isascii():
                continue
            беды.append((номер, кусок))
    return беды


def main(argv: list[str]) -> int:
    файлы = [Path(a) for a in argv[1:]]
    if not файлы:
        print("укажите файлы", file=sys.stderr)
        return 2
    всего = 0
    for путь in файлы:
        for номер, кусок in нарушения(путь.read_text(encoding="utf-8")):
            всего += 1
            print(f"{путь}:{номер}: не-ASCII вне строки и комментария: {кусок}")
    if всего:
        print(f"нарушений: {всего}")
        return 1
    print(f"проверено файлов: {len(файлы)}; не-ASCII вне строк и комментариев нет")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
