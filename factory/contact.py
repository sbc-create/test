def пригоден(адрес: str) -> bool:
    """Похоже ли значение на адрес, а не на заглушку.

    Проверка намеренно грубая: задача — отсечь пустое поле, пробел внутри и
    «TODO», а не повторить RFC. Пустое поле — `BLOCKED_INPUT`, а не повод
    подставить умолчание.
    """
    адрес = (адрес or "").strip()
    if not адрес or " " in адрес or адрес.count("@") != 1:
        return False
    имя, _, домен = адрес.partition("@")
    return bool(имя) and "." in домен and not домен.startswith(".") \
        and not домен.endswith(".")


