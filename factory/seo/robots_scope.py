"""Закрывает ли robots.txt обход ЦЕЛИКОМ — по строкам, а не по подстроке.

Зачем отдельный предикат. Проверки сети спрашивали `"Disallow: /" in текст`,
и подстрока совпадает с `Disallow: /poster/`. Нашла линия витрины
lordfilm47.space 2026-10-16 у своего сторожа `tools/verify_live.py`: условие
«режим индексации не изменился» (`"Disallow: /" not in robots`) молча
проходило И при закрытой витрине, И при открытой — то есть сторож не заметил
бы ни открытия, ни закрытия. Тот же текст нашёлся в пяти местах этого
репозитория.

Правильный вопрос — построчный: запрет на весь сайт это строка `Disallow: /`
целиком, в блоке, который относится к спрашивающему агенту. Разбор здесь
маленький и намеренно скучный:

* строки с комментариями и пустые пропускаются;
* блок начинается с одной или нескольких строк `User-agent:`;
* `Disallow:` с пустым значением запретом НЕ является (это разрешение);
* путь `/` — запрет всего; `/что-нибудь` — запрет части и ничем больше;
* `Allow:` внутри блока не отменяет `Disallow: /` для этого предиката:
  вопрос «закрыт ли обход целиком» решается наличием полного запрета, а
  тонкости приоритетов правил — не его дело.
"""
from __future__ import annotations

ВСЕ_АГЕНТЫ = "*"


def _блоки(текст: str) -> list[tuple[list[str], list[tuple[str, str]]]]:
    """[(агенты, [(директива, значение)])] в порядке появления."""
    блоки: list[tuple[list[str], list[tuple[str, str]]]] = []
    агенты: list[str] = []
    правила: list[tuple[str, str]] = []
    ждём_агентов = True
    for сырая in (текст or "").splitlines():
        строка = сырая.split("#", 1)[0].strip()
        if not строка or ":" not in строка:
            continue
        имя, _, значение = строка.partition(":")
        имя = имя.strip().lower()
        значение = значение.strip()
        if имя == "user-agent":
            if not ждём_агентов:
                блоки.append((агенты, правила))
                агенты, правила = [], []
            ждём_агентов = True
            агенты.append(значение.lower())
            continue
        if имя in ("disallow", "allow"):
            ждём_агентов = False
            правила.append((имя, значение))
    if агенты or правила:
        блоки.append((агенты, правила))
    return блоки


def закрывает_весь_обход(текст: str, агент: str = ВСЕ_АГЕНТЫ) -> bool:
    """Есть ли в robots.txt полный запрет обхода для этого агента.

    `agent` сравнивается без регистра; блок `*` учитывается всегда.
    """
    агент = (агент or ВСЕ_АГЕНТЫ).strip().lower()
    for агенты, правила in _блоки(текст):
        подходит = any(а == агент or а == ВСЕ_АГЕНТЫ for а in агенты)
        if not подходит:
            continue
        for имя, значение in правила:
            if имя == "disallow" and значение == "/":
                return True
    return False


def запрещённые_пути(текст: str, агент: str = ВСЕ_АГЕНТЫ) -> list[str]:
    """Непустые значения Disallow для агента — для отчётов, не для решений."""
    агент = (агент or ВСЕ_АГЕНТЫ).strip().lower()
    итог: list[str] = []
    for агенты, правила in _блоки(текст):
        if not any(а == агент or а == ВСЕ_АГЕНТЫ for а in агенты):
            continue
        итог += [значение for имя, значение in правила
                 if имя == "disallow" and значение]
    return итог
