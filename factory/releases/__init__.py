"""Домен релизов: как построенное становится выложенным.

Манифест релиза, закрепление артефакта шаблона, канареечная выкладка,
переключение и откат.

Собран рядом с движком, а не внутри него, и это существенно. Релизы знают про
семейства витрин, а движок про них знать не должен: эта зависимость
разрывалась в этом же этапе, и возвращать её сборкой внутрь нельзя.

Интерфейс ленивый: пакет с немедленным реэкспортом втягивает свои модули в
момент импорта самого пакета, и связь между ними и остальным кодом
превращается в кольцо.
"""
from __future__ import annotations

import importlib
from typing import Any

_МОДУЛИ = (
    "release_manifest",
    "refresh_release",
    "template_artifact",
    "canary",
)


def __getattr__(имя: str) -> Any:
    if имя in _МОДУЛИ:
        return importlib.import_module(f"{__name__}.{имя}")
    raise AttributeError(
        f"домен релизов не отдаёт «{имя}»: возьмите его у нужного модуля")


def __dir__() -> list[str]:
    return sorted(_МОДУЛИ)
