def токены(текст: str) -> list[str]:
    """Слова текста в исходном виде, без пунктуации."""
    return re.findall(r"[а-яa-z0-9]+", нормализовать(текст))


def основы_токенов(текст: str) -> list[str]:
    return [стем(с) for с in токены(текст)]


def найти_фразы(текст: str, фразы) -> dict:
    """Найти словосочетания по основам слов, вытесняя короткие длинными.

    Литеральное сравнение здесь не работает: «документальным фильмом» — то же
    словосочетание, что «документальный фильм», но ни одна его половина не
    совпадает посимвольно, зато «фильмом» совпадает с «фильм» — и один тип
    произведения превращается в два, из которых второй объявляется
    опровергнутым.

    Возвращает `{фраза: (начало, конец)}` по позициям токенов. Найденные
    позиции закрываются, поэтому «фильм» внутри «документального фильма»
    второй раз не засчитывается.
    """
    основы = основы_токенов(текст)
    занято = [False] * len(основы)
    найдено: dict = {}
    for фраза in sorted(фразы, key=lambda ф: len(токены(ф)), reverse=True):
        цель = основы_токенов(фраза)
        if not цель:
            continue
        for i in range(len(основы) - len(цель) + 1):
            if any(занято[i:i + len(цель)]):
                continue
            if основы[i:i + len(цель)] == цель:
                найдено[фраза] = (i, i + len(цель))
                for j in range(i, i + len(цель)):
                    занято[j] = True
                break
    return найдено
