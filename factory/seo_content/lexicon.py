def стем(слово: str) -> str:
    """Грубая основа слова.

    Полноценной морфологии здесь нет и заявлять её нельзя: `pymorphy` в
    окружении отсутствует, а необязательная зависимость не должна решать,
    проходит ли текст. Отсечение окончания достаточно, чтобы «боевика» и
    «боевик» встретились, и честно недостаточно для тонких случаев — это
    записано в отчёте, а не спрятано.
    """
    с = (слово or "").strip().lower().replace("ё", "е")
    if len(с) <= 3:
        return с
    # Порог основы — три буквы, а не четыре. С четырьмя «южной» теряло бы
    # только «й» и давало «южно», тогда как «южная» давало «южн»: «Южная
    # Корея» и «Южной Кореи» переставали быть одной страной.
    for о in _ОКОНЧАНИЯ:
        if с.endswith(о) and len(с) - len(о) >= 3:
            return с[: -len(о)]
    return с


def нормализовать(текст: str) -> str:
    return re.sub(r"\s+", " ", (текст or "").strip().lower().replace("ё", "е"))


def стемы(текст: str) -> list[str]:
    return [стем(с) for с in re.findall(r"[а-яa-z0-9]+", нормализовать(текст))]


