"""Числа, записанные словами.

Проверки чисел до сих пор смотрели только на цифры, и этого оказалось мало:
«две тысячи четырнадцатого года», «сто шестая серия» и «семь сезонов»
проходили мимо всех числовых ворот. Дыра не теоретическая — именно так текст
и пишут по-русски, когда число невелико.

Устройство разбора намеренно осторожное. Русская морфология здесь не
реализуется: берётся закрытый список форм числительных, и слово считается
числительным, только если совпало с ним целиком. «Стоит» не превращается в
сто, «семья» — в семь, «сотня» — в сотню лет: этих форм в списке нет.

Второй предохранитель — контекст. Группа числительных засчитывается только
рядом со словом, к которому она относится: год, серия, сезон, часть. Без
этого «один из героев» читалось бы как число один.
"""
from __future__ import annotations

import re
from typing import Iterator

#: Корень -> значение. Порядок внутри разбора — от длинного корня к короткому,
#: иначе «пят» съедает «пятьдесят».
КОРНИ: dict[str, int] = {
    "нол": 0, "нул": 0,
    "один": 1, "одн": 1, "перв": 1,
    "два": 2, "две": 2, "двух": 2, "втор": 2,
    "три": 3, "трех": 3, "трет": 3,
    "четыре": 4, "четырех": 4, "четверт": 4,
    "пять": 5, "пяти": 5, "пят": 5,
    "шесть": 6, "шести": 6, "шест": 6,
    "семь": 7, "семи": 7, "седьм": 7,
    "восемь": 8, "восьми": 8, "восьм": 8,
    "девять": 9, "девяти": 9, "девят": 9,
    "десять": 10, "десяти": 10, "десят": 10,
    "одиннадцат": 11, "двенадцат": 12, "тринадцат": 13,
    "четырнадцат": 14, "пятнадцат": 15, "шестнадцат": 16,
    "семнадцат": 17, "восемнадцат": 18, "девятнадцат": 19,
    "двадцат": 20, "тридцат": 30, "сорок": 40, "сороков": 40,
    "пятьдесят": 50, "пятидесят": 50,
    "шестьдесят": 60, "шестидесят": 60,
    "семьдесят": 70, "семидесят": 70,
    "восемьдесят": 80, "восьмидесят": 80,
    "девяност": 90,
    "сто": 100, "сот": 100, "ста": 100,
    "двести": 200, "двухсот": 200,
    "триста": 300, "трехсот": 300,
    "четыреста": 400, "четырехсот": 400,
    "пятьсот": 500, "пятисот": 500,
    "шестьсот": 600, "шестисот": 600,
    "семьсот": 700, "семисот": 700,
    "восемьсот": 800, "восьмисот": 800,
    "девятьсот": 900, "девятисот": 900,
}

ТЫСЯЧА_КОРНИ = ("тысяч",)

#: Корни, которые бывают только порядковыми.
ПОРЯДКОВЫЕ_КОРНИ = frozenset({
    "перв", "втор", "трет", "четверт", "седьм", "восьм", "сороков", "сот",
    "девяност",
})

#: Окончания прилагательного. Числительное с таким окончанием — порядковое:
#: «пятом сезоне» — пятый, а не пять (количественное дало бы «пяти»).
ПОРЯДКОВЫЕ_ОКОНЧАНИЯ = frozenset({
    "ый", "ой", "ая", "ое", "ые", "ого", "ому", "ым", "ых", "ыми", "яя",
    "ья", "ом", "ем", "им", "их", "ими", "ую", "ей",
})


def _порядковое(слово: str) -> bool:
    for корень in sorted(КОРНИ, key=len, reverse=True):
        if слово.startswith(корень):
            if корень in ПОРЯДКОВЫЕ_КОРНИ:
                return True
            return слово[len(корень):] in ПОРЯДКОВЫЕ_ОКОНЧАНИЯ
    return False

#: Окончания, с которыми корень остаётся числительным. Список короткий
#: намеренно: каждое лишнее окончание открывает дорогу постороннему слову.
ОКОНЧАНИЯ = ("", "ь", "и", "а", "о", "е", "у", "ю", "ы", "ой", "ом", "ым",
             "ых", "ые", "ыми", "ого", "ому", "ый", "ая", "ое", "ей", "ем",
             "ью", "ух", "им", "их", "ими", "яя", "ья")

#: Слова, которые собрались бы из корня и окончания, но числительными не
#: являются. Проверены поимённо, потому что тихая ошибка здесь дороже
#: пропуска: «стоит» вместо «сто» подменило бы год.
ИСКЛЮЧЕНИЯ = frozenset({
    "стая", "стае", "стой", "стом", "сты", "одна", "одни",
    "семье", "семьи", "семья", "сема", "сема", "трех", "двух", "тремя",
    "трое", "двое", "стал", "стала", "стало", "стали", "стоя",
    # «Трио» собирается из «три» и «о», но числительным не является.
    "трио", "стои",
})


def _формы() -> dict[str, int]:
    итог: dict[str, int] = {}
    for корень, значение in КОРНИ.items():
        for о in ОКОНЧАНИЯ:
            слово = корень + о
            if слово in ИСКЛЮЧЕНИЯ:
                continue
            # Более длинный корень выигрывает: «пятьдесят» не должен быть
            # перезаписан формой «пят» + «ьдесят», которой в списке и нет.
            прежний = итог.get(слово)
            if прежний is None or len(корень) > len(
                    max((к for к in КОРНИ if слово.startswith(к)), key=len)) - 1:
                итог.setdefault(слово, значение)
    # Явные формы с собственным значением перекрывают производные.
    for корень, значение in КОРНИ.items():
        итог[корень] = значение
    return итог


ФОРМЫ = _формы()
ТЫСЯЧИ = {к + о for к in ТЫСЯЧА_КОРНИ
          for о in ("а", "и", "", "ам", "ами", "ах", "е", "ей", "ный", "ная",
                    "ное", "ного", "ному")}

#: Существительные, рядом с которыми группа числительных действительно
#: называет количество или номер.
КОНТЕКСТ = {
    "год": "year", "года": "year", "году": "year", "годов": "year",
    "годах": "year", "лет": "year", "годы": "year",
    "серия": "episode", "серии": "episode", "серий": "episode",
    "серию": "episode", "серией": "episode", "сериях": "episode",
    "эпизод": "episode", "эпизода": "episode", "эпизодов": "episode",
    "сезон": "season", "сезона": "season", "сезонов": "season",
    "сезоне": "season", "сезоны": "season",
    "часть": "part", "части": "part", "частей": "part",
}

_СЛОВО = re.compile(r"[а-я]+", re.I)


def _токены(текст: str) -> list[tuple[str, int, int]]:
    н = (текст or "").lower().replace("ё", "е")
    return [(м.group(0), м.start(), м.end()) for м in _СЛОВО.finditer(н)]


def читать(текст: str) -> Iterator[tuple[int, str, int, int, bool]]:
    """Числа словами: `(значение, вид, начало, конец, порядковое)`.

    Вид — `year`, `episode`, `season` или `part`; он берётся из соседнего
    существительного. Группа без такого соседа не возвращается вовсе: без
    него неизвестно, о чём число, и утверждать что-либо было бы догадкой.

    Порядковое отмечается отдельно, потому что смысл у него другой:
    «продолжение первого сезона» говорит о ДРУГОМ сезоне, а не о количестве
    сезонов, равном одному. Смешать их — значит получить ложное
    опровержение на совершенно правильном тексте.
    """
    токены = _токены(текст)
    i = 0
    while i < len(токены):
        слово, начало, _ = токены[i]
        if слово not in ФОРМЫ and слово not in ТЫСЯЧИ:
            i += 1
            continue
        всего, текущая, конец, j = 0, 0, токены[i][2], i
        порядковое = False
        while j < len(токены):
            с, _, к = токены[j]
            if с in ТЫСЯЧИ:
                всего += max(текущая, 1) * 1000
                текущая = 0
                конец, j = к, j + 1
                continue
            if с in ФОРМЫ:
                текущая += ФОРМЫ[с]
                порядковое = порядковое or _порядковое(с)
                конец, j = к, j + 1
                continue
            break
        значение = всего + текущая
        # Существительное сразу после группы либо сразу перед ней.
        вид = None
        if j < len(токены) and токены[j][0] in КОНТЕКСТ:
            вид = КОНТЕКСТ[токены[j][0]]
        elif i > 0 and токены[i - 1][0] in КОНТЕКСТ:
            вид = КОНТЕКСТ[токены[i - 1][0]]
        if вид is not None and значение > 0:
            yield значение, вид, начало, конец, порядковое
        i = max(j, i + 1)


def в_цифрах(текст: str) -> str:
    """Тот же текст, где числительные словами заменены цифрами.

    Нужен одному потребителю — числовым проверкам: им проще смотреть на
    цифры, чем заводить второй разбор. Для показа человеку этот текст не
    предназначен.
    """
    замены = sorted(читать(текст), key=lambda з: з[2], reverse=True)
    итог = текст
    for значение, вид, начало, конец, порядковое in замены:
        # Порядковое остаётся порядковым: «1-го сезона» читается проверками
        # как номер, а «1 сезон» — как количество. Год — исключение: по-русски
        # он порядковый, но пишется голой цифрой.
        цифрами = (f"{значение}-го" if порядковое and вид != "year"
                   else str(значение))
        итог = итог[:начало] + цифрами + итог[конец:]
    return итог
