#!/usr/bin/env python3
"""Запись состава маршрутов в пакеты.

Каждому пакету назначается набор стратегий — каталог, подача тайтла, разведка,
применение полосы — и этот набор разворачивается в явный состав блоков внутри
`template.json`. Назначение детерминированное и обязано быть различным: два
пакета с одинаковым набором стратегий отличались бы только главной, а это ровно
то, что запрещено.

Полосу получает не всякий пакет. `rail=none` — законный выбор: шаблон, которому
полоса не нужна, использует другую полноценную композицию, а не имитирует
карусель ради галочки.
"""

from __future__ import annotations

import argparse
import itertools
import json
import pathlib
import sys

import routes as маршруты_модуль

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

#: Шаг обхода набора сочетаний. Взаимно прост с размером набора, поэтому первые
#: пятьдесят значений попарно различны — это свойство проверяется, а не
#: предполагается.
ШАГ = 53


def сочетания() -> list[dict]:
    все = [
        {"catalog": к, "title": т, "discovery": р, "rail": п}
        for к, т, р, п in itertools.product(
            маршруты_модуль.СТРАТЕГИИ_КАТАЛОГА,
            маршруты_модуль.СТРАТЕГИИ_ТАЙТЛА,
            маршруты_модуль.СТРАТЕГИИ_РАЗВЕДКИ,
            маршруты_модуль.ПРИМЕНЕНИЕ_ПОЛОСЫ)
    ]
    return все


def варианты_обхода() -> list[tuple[int, str]]:
    """Порядок перебора композиций каталога: сначала тело, потом раскладка."""
    return [(в, р) for р in маршруты_модуль.РАСКЛАДКИ_КАТАЛОГА
            for в in range(15)]


def назначить_и_применить(пакеты: list[pathlib.Path]) -> tuple[dict, list[str]]:
    """Назначить стратегии и записать маршруты, не допустив одинаковых открытий.

    Проверять различие после отрисовки поздно: к этому моменту уже сделаны
    снимки, и остаётся либо чинить вручную, либо смягчать порог. Поэтому
    подпись первого экрана каталога проверяется здесь, на каждом пакете, и
    занятая подпись заставляет взять следующую композицию.
    """
    все = сочетания()
    размер = len(все)
    назначения, беды = {}, []
    занятые_открытия: set = set()
    занятые_композиции: dict[str, set] = {}

    for i, пакет in enumerate(пакеты):
        tid = пакет.name[:4]
        модель = dict(все[(i * ШАГ) % размер])
        манифест = json.loads((пакет / "template.json").read_text(encoding="utf-8"))
        лестницы = маршруты_модуль.лестницы_из_css(
            (пакет / "layout.css").read_text(encoding="utf-8"))
        группа = модель["catalog"]
        свободные = занятые_композиции.setdefault(группа, set())

        выбрано = None
        for вариант, раскладка in варианты_обхода():
            if (вариант, раскладка) in свободные:
                continue
            проба = dict(модель, catalog_variant=вариант, catalog_layout=раскладка)
            состав = маршруты_модуль.развернуть(проба, лестницы, манифест["card_grammar"])
            подпись = маршруты_модуль.подпись_открытия(состав["catalog"])
            if подпись in занятые_открытия:
                continue
            if маршруты_модуль.проверить(состав, лестницы):
                continue
            выбрано = (проба, состав, подпись, (вариант, раскладка))
            break

        if выбрано is None:
            беды.append(f"{tid}: не нашлось композиции каталога с непохожим "
                        f"первым экраном — набор вариантов исчерпан")
            continue

        проба, состав, подпись, ключ = выбрано
        занятые_открытия.add(подпись)
        свободные.add(ключ)
        манифест["route_model"] = проба
        манифест["routes"] = состав
        (пакет / "template.json").write_text(
            json.dumps(манифест, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        назначения[tid] = проба

    уникальных = {json.dumps(м, sort_keys=True) for м in назначения.values()}
    if назначения and len(уникальных) != len(назначения):
        беды.append("назначение стратегий дало повтор — шаг обхода негоден")
    return назначения, беды


def применить(пакет: pathlib.Path, модель: dict) -> list[str]:
    манифест = json.loads((пакет / "template.json").read_text(encoding="utf-8"))
    лестницы = маршруты_модуль.лестницы_из_css(
        (пакет / "layout.css").read_text(encoding="utf-8"))
    состав = маршруты_модуль.развернуть(модель, лестницы, манифест["card_grammar"])
    беды = маршруты_модуль.проверить(состав, лестницы)
    if беды:
        return [f'{манифест["template_id"]}: {б}' for б in беды]
    манифест["route_model"] = модель
    манифест["routes"] = состав
    (пакет / "template.json").write_text(
        json.dumps(манифест, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return []


def главное() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(КОРЕНЬ))
    args = parser.parse_args()
    корень = pathlib.Path(args.root)
    пакеты = sorted(п for п in корень.iterdir()
                    if п.is_dir() and (п / "template.json").is_file())
    назначения, беды = назначить_и_применить(пакеты)
    if беды:
        for б in беды:
            print("ОТКАЗ:", б, file=sys.stderr)
        return 2
    свод: dict[str, int] = {}
    for м in назначения.values():
        свод[м["catalog"]] = свод.get(м["catalog"], 0) + 1
    открытия = len({маршруты_модуль.подпись_открытия(
        json.loads((п / "template.json").read_text(encoding="utf-8"))["routes"]["catalog"])
        for п in пакеты})
    print(json.dumps({"пакетов": len(пакеты), "различных открытий каталога": открытия,
                      "каталоги": свод,
                      "полоса_не_используется":
                          sum(1 for м in назначения.values() if м["rail"] == "none")},
                     ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
