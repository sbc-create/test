#!/usr/bin/env python3
"""Состав маршрутов пакета: что именно шаблон показывает на каждой странице.

## Зачем это отдельный слой

Шаблон, который различается только главной, — не шаблон, а заставка. Каталог,
страница фильма, сериал, сезон, серия и поиск посещаются чаще главной, и если
они у всех пятидесяти одинаковы, то пятьдесят пакетов — это одна композиция с
разными обложками.

Поэтому у каждого пакета объявлена не только главная, но и стратегия каждого
маршрута: как устроен каталог, как подаётся тайтл, чем открывается поиск, как
выглядит пустая выдача. Стратегии здесь разворачиваются в явный состав блоков,
который записывается в `template.json` пакета. Он лежит в репозитории, виден в
истории и проверяется теми же измерениями, что и главная, — а не остаётся
намерением в голове автора.

## Почему разворачивается, а не вычисляется при отрисовке

Вычисляемый на лету состав нельзя прочитать глазами и нельзя сравнить в
истории. Развёрнутый — можно: `git diff` показывает, что каталог T014 стал
перечнем, а не сеткой. Ядро отрисовки берёт объявленное и ничего не
додумывает.

## Границы

Маршрутизация, выбор данных, канонический адрес, коды ответа и политика
индексации принадлежат ядру витрины (`ROUTE_OWNED_BY_CORE`). Пакет владеет
представлением маршрута. Разворачивается здесь только вторая часть, и только
она объявляется проверенной.
"""

from __future__ import annotations

import re

#: Стратегии каталога. Различаются не плотностью, а способом смотреть на
#: каталог: витрина, перечень, разворот, доска по видам, азбука, журнал.
СТРАТЕГИИ_КАТАЛОГА = ("grid", "rows", "mosaic", "board", "index", "split", "magazine")

#: Стратегии страницы тайтла: что стоит первым — постер, заголовок, описание,
#: панель фактов или таблица данных.
СТРАТЕГИИ_ТАЙТЛА = ("poster-aside", "hero-wide", "editorial", "panel", "data-first")

#: Чем шаблон ведёт разведку: жанровые фишки, азбука, доска, полоса, фильтры.
СТРАТЕГИИ_РАЗВЕДКИ = ("chips", "index", "board", "rail", "filters")

#: Где пакет применяет прокручиваемую полосу. `none` — законное решение:
#: имитировать полосу ради галочки запрещено.
ПРИМЕНЕНИЕ_ПОЛОСЫ = ("similar", "discovery", "none")

ГРАММАТИКА_КАТАЛОГА = {
    "grid": ("poster", "rich", "editorial"),
    "rows": ("compact",),
    "mosaic": ("poster", "rich"),
    "board": ("tile", "compact"),
    "index": ("row",),
    "split": ("poster", "rich"),
    "magazine": ("editorial", "rich"),
}


def лестницы_из_css(текст: str) -> dict[str, list[list[int]]]:
    """Лестницы колонок, объявленные пакетом, — источник истины о его сетках."""
    лестницы: dict[str, list[list[int]]] = {}
    for кусок in текст.split("@media"):
        точка = 0
        совпало = re.match(r"\(min-width:(\d+)px\)", кусок.strip())
        if совпало:
            точка = int(совпало.group(1))
        for класс, колонок in re.findall(
                r"\.([a-zA-Z0-9_-]+)\{grid-template-columns:repeat\((\d+)", кусок):
            лестницы.setdefault(класс, []).append([точка, int(колонок)])
    for ступени in лестницы.values():
        ступени.sort()
    return лестницы


def одинокий_хвост(количество: int, колонок: int) -> bool:
    """Останется ли в последнем ряду ровно одна карточка (от трёх колонок)."""
    return колонок >= 3 and количество % колонок == 1


def подобрать_количество(предпочтительно: int, ступени: list[list[int]],
                         минимум: int = 4, тип: str = "grid") -> int:
    """Ближайшее к желаемому количество карточек без одинокого хвоста.

    Блок объявляет, сколько карточек хочет показать; лестница колонок пакета
    решает, какое соседнее число не оставит в последнем ряду одну. Подгонять
    вручную для пятидесяти пакетов и пятнадцати маршрутов нельзя — забудется.
    """
    колонки = [к for _, к in ступени] or [4]
    добавка = 3 if тип == "mosaic" else 0
    for шаг in range(0, 12):
        for сколько in (предпочтительно + шаг, предпочтительно - шаг):
            if сколько < минимум:
                continue
            if not any(одинокий_хвост(сколько + добавка, к) for к in колонки):
                return сколько
    return предпочтительно


def размер_страницы(ступени: list[list[int]], предпочтительно: int = 24) -> int:
    """Столько карточек на страницу, чтобы ни одна ступень не дала одинокий хвост.

    Перебор идёт от предпочтительного значения в обе стороны: страница должна
    остаться привычного объёма, а не превратиться в шесть карточек ради
    арифметики.
    """
    колонки = [к for _, к in ступени] or [4]
    порядок = [предпочтительно]
    for шаг in range(1, 9):
        порядок += [предпочтительно + шаг, предпочтительно - шаг]
    for сколько in порядок:
        if сколько < 12:
            continue
        if not any(одинокий_хвост(сколько, к) for к in колонки):
            return сколько
    return предпочтительно


def _класс_сетки(лестницы: dict, грамматика: str, запасной: str) -> tuple[str, list]:
    """Самая плотная объявленная пакетом сетка, годная для этой грамматики.

    Классы пакета переиспользуются намеренно: ритм колонок — часть его
    оформления, и подменять его общим «каталожным» классом значило бы стереть
    ровно то, чем пакеты различаются.
    """
    годные = []
    for класс, ступени in лестницы.items():
        if not класс.startswith("g--"):
            continue
        макс = max((к for _, к in ступени), default=0)
        # Строка-карточка требует широкой колонки; плотные сетки ей не годятся.
        if грамматика == "compact" and макс > 3:
            continue
        if грамматика in ("poster", "rich", "editorial") and макс < 3:
            continue
        годные.append((макс, класс, ступени))
    if not годные:
        return запасной, [[0, 2], [768, 3], [1200, 4]]
    годные.sort(reverse=True)
    _, класс, ступени = годные[0]
    return класс, ступени


def _грамматика(стратегия: str, предпочтения: list[str]) -> str:
    допустимые = ГРАММАТИКА_КАТАЛОГА[стратегия]
    for г in предпочтения:
        if г in допустимые:
            return г
    return допустимые[0]


def развернуть(модель: dict, лестницы: dict, грамматики: list[str]) -> dict:
    """Стратегии → явный состав блоков каждого маршрута."""
    каталог = модель["catalog"]
    тайтл = модель["title"]
    разведка = модель["discovery"]
    полоса = модель["rail"]

    г_каталога = _грамматика(каталог, грамматики)
    класс_сетки, ступени = _класс_сетки(лестницы, г_каталога, "g--cat")
    на_странице = размер_страницы(ступени)
    # Количество карточек в мелких блоках подбирается под лестницу пакета:
    # одинокая карточка в последнем ряду — дефект, а не мелочь оформления.
    мелкий = подобрать_количество(6, ступени, минимум=4)
    мозаика = подобрать_количество(7, ступени, минимум=5, тип="mosaic")

    крошки = {"тип": "crumbs"}
    шапка = {"тип": "pagehead", "заголовок": ""}

    колонки = sorted({к for _, к in ступени}) or [4]

    def перечень(заголовок: str, грамматика: str | None = None,
                 класс: str | None = None) -> dict:
        return {"тип": "listing", "заголовок": заголовок,
                "грамматика": грамматика or г_каталога,
                "класс": класс or класс_сетки, "на_странице": на_странице,
                "колонки": колонки}

    # --- разведка: чем маршрут помогает выбрать -----------------------------
    def блок_разведки(заголовок: str) -> list[dict]:
        if разведка == "chips":
            return [{"тип": "taxonomy", "заголовок": заголовок, "источник": "genres",
                     "максимум": 12}]
        if разведка == "index":
            return [{"тип": "index", "заголовок": заголовок, "минимум": 4}]
        if разведка == "board":
            return [{"тип": "board", "заголовок": заголовок, "по": "genres",
                     "грамматика": "tile", "колонок": 4, "максимум_в_группе": 4,
                     "минимум_в_группе": 3, "минимум": 2}]
        if разведка == "rail":
            return [{"тип": "rail", "заголовок": заголовок, "грамматика": "poster",
                     "максимум": 12, "минимум": 4}]
        return [{"тип": "filters", "заголовок": заголовок, "источник": "genres",
                 "максимум": 8}]

    # --- каталог -------------------------------------------------------------
    тело_каталога: list[dict] = []
    if каталог == "mosaic":
        тело_каталога.append({"тип": "mosaic", "заголовок": "Вход в каталог",
                              "грамматика": "poster", "максимум": мозаика,
                              "минимум": 4, "класс": класс_сетки,
                              "колонки": колонки})
    elif каталог == "split":
        тело_каталога.append({"тип": "split", "заголовок": "Чем открыть каталог",
                              "грамматика": "compact", "максимум": 6, "минимум": 4})
    elif каталог == "board":
        тело_каталога.append({"тип": "board", "заголовок": "Каталог по видам",
                              "по": "kind", "грамматика": "tile", "колонок": 3,
                              "максимум_в_группе": 5, "минимум": 2})
    elif каталог == "magazine":
        тело_каталога.append({"тип": "rail", "заголовок": "Отобранное",
                              "грамматика": "editorial", "максимум": 10, "минимум": 4})
    elif каталог == "index":
        тело_каталога.append({"тип": "index", "заголовок": "По алфавиту", "минимум": 4})

    маршруты: dict[str, list[dict]] = {}
    маршруты["catalog"] = [
        крошки, шапка,
        {"тип": "filters", "заголовок": "Отбор", "источник": "genres", "максимум": 8},
        *тело_каталога,
        перечень("Все записи"),
    ]

    маршруты["new"] = [
        крошки, шапка,
        {"тип": "feed", "заголовок": "Добавлено недавно",
         "грамматика": "compact" if г_каталога != "compact" else "poster",
         "максимум": 8, "минимум": 3},
        перечень("Все новинки"),
    ]

    # --- поиск ---------------------------------------------------------------
    маршруты["search"] = [
        крошки,
        {"тип": "search", "заголовок": "Результаты",
         "грамматика": "compact" if каталог == "rows" else г_каталога,
         "класс": класс_сетки},
    ]
    маршруты["search_empty"] = [
        крошки,
        {"тип": "search", "заголовок": "Результаты", "грамматика": г_каталога,
         "класс": класс_сетки},
        *блок_разведки("Чем можно продолжить"),
        {"тип": "grid", "заголовок": "Из каталога", "грамматика": "poster",
         "класс": класс_сетки, "максимум": мелкий, "минимум": 4,
         "источник": "catalog", "колонки": колонки},
    ]

    # --- разделы -------------------------------------------------------------
    for имя, подпись in (("genre", "Соседние жанры"), ("year", "Другие годы"),
                         ("country", "Другие страны")):
        источник = {"genre": "genres", "year": "years", "country": "countries"}[имя]
        маршруты[имя] = [
            крошки, шапка,
            {"тип": "taxonomy", "заголовок": подпись, "источник": источник,
             "максимум": 12},
            перечень("Записи раздела"),
        ]

    маршруты["collection"] = [
        крошки, шапка,
        перечень("Состав подборки"),
        *блок_разведки("Другие срезы каталога"),
    ]

    # --- тайтл ---------------------------------------------------------------
    класс_тайтла = {
        "poster-aside": "", "hero-wide": "ttl--wide", "editorial": "ttl--editorial",
        "panel": "ttl--panel", "data-first": "ttl--data",
    }[тайтл]
    похожее = ({"тип": "similar", "заголовок": "Похожее", "полосой": True,
                "грамматика": "poster", "максимум": 12, "минимум": 3}
               if полоса == "similar" else
               {"тип": "similar", "заголовок": "Похожее", "грамматика": г_каталога,
                "класс": класс_сетки, "колонки": колонки,
                "максимум": подобрать_количество(8, ступени, минимум=4), "минимум": 3})

    маршруты["title_movie"] = [
        крошки,
        {"тип": "title", "класс": класс_тайтла},
        похожее,
    ]
    маршруты["title_series"] = [
        крошки,
        {"тип": "title", "класс": класс_тайтла},
        {"тип": "seasons", "заголовок": "Сезоны и серии"},
        похожее,
    ]
    маршруты["season"] = [
        крошки, шапка,
        {"тип": "seasons", "заголовок": "Состав сезона"},
        похожее,
    ]
    эпизод = [
        крошки, шапка,
        {"тип": "player", "заголовок": "Просмотр"},
        {"тип": "seasons", "заголовок": "Другие серии"},
        похожее,
    ]
    маршруты["episode"] = эпизод
    # Маршрут «эпизод с плеером» — то же представление; отличается состоянием
    # после нажатия, и проверяется действием, а не отдельной разметкой.
    маршруты["episode_player"] = эпизод

    маршруты["notfound"] = [
        {"тип": "notfound"},
        *блок_разведки("Куда можно пойти"),
        {"тип": "grid", "заголовок": "Из каталога", "грамматика": "poster",
         "класс": класс_сетки, "максимум": мелкий, "минимум": 4,
         "источник": "catalog", "колонки": колонки},
    ]
    return маршруты


def проверить(маршруты: dict, лестницы: dict) -> list[str]:
    """Композиционные запреты на маршрутах — те же, что и на главной."""
    беды = []
    for имя, блоки in маршруты.items():
        for блок in блоки:
            класс = блок.get("класс")
            количество = блок.get("максимум") or блок.get("на_странице")
            if not класс or not количество:
                continue
            if блок["тип"] not in ("grid", "mosaic", "feed", "listing"):
                continue
            занято = количество + 3 if блок["тип"] == "mosaic" else количество
            for точка, колонок in лестницы.get(класс, []):
                if одинокий_хвост(занято, колонок):
                    беды.append(
                        f"маршрут {имя}: блок «{блок.get('заголовок', блок['тип'])}» — "
                        f"{количество} карточек в {колонок} колонках на "
                        f"{точка or 320}px оставляют в последнем ряду одну")
    return беды
