#: Блоки-обёртки: они есть у всех и первым экраном не являются.
ОБЁРТКИ = ("crumbs", "pagehead")


def подпись_открытия(блоки: list[dict], сколько: int = 2) -> tuple:
    """Чем страница открывается — с точностью до того, что видно на экране.

    Перцептивный отпечаток первого экрана видит примерно два первых
    содержательных блока. Если у двух шаблонов они совпадают по типу,
    грамматике и плотности, страницы будут неотличимы, какими бы разными ни
    были токены. Измерение это и показало: девятнадцать пар каталогов, семь из
    них попиксельно.

    Поэтому подпись строится из того же, что видит отпечаток, и проверяется
    генератором — до отрисовки, а не после.
    """
    содержательные = [б for б in блоки if б["тип"] not in ОБЁРТКИ][:сколько]
    # В подпись идёт только то, что меняет геометрию: тип блока, грамматика
    # карточки и плотность. Источник данных — `genres` вместо `countries` —
    # меняет слова, а не форму: страницы, различающиеся лишь этим, для глаза
    # одинаковы, и объявлять их разными нельзя. Первая версия подписи именно
    # это и делала, и генератор считал непохожими четыре пары, которые
    # отпечаток первого экрана нашёл совпадающими.
    return tuple(
        (б["тип"], б.get("грамматика") or "",
         б.get("колонок") or б.get("максимум") or б.get("на_странице") or 0)
        for б in содержательные)


def проверить(маршруты: dict, лестницы: dict) -> list[str]:
    """Композиционные запреты на маршрутах — те же, что и на главной."""
    лестницы = dict(ЗАПАСНЫЕ_ЛЕСТНИЦЫ, **лестницы)
    беды = []
    for имя, блоки in маршруты.items():
        for блок in блоки:
            класс = блок.get("класс")
            количество = блок.get("максимум") or блок.get("на_странице")
            if not класс or not количество:
                continue
            if блок["тип"] not in ("grid", "mosaic", "feed", "listing"):
                continue
            занято = количество + 3 if блок["тип"] == "mosaic" else количество
            for точка, колонок in лестницы.get(класс, []):
                if (блок.get("грамматика") == "compact"
                        and ширина_колонки(точка, колонок) < МИН_КОЛОНКА_COMPACT):
                    беды.append(
                        f"маршрут {имя}: строка-карточка в сетке {класс} на "
                        f"{точка or 320}px даёт колонку "
                        f"{ширина_колонки(точка, колонок):.0f}px при минимуме "
                        f"{МИН_КОЛОНКА_COMPACT}px: обязательная дата обрежется")
                if одинокий_хвост(занято, колонок):
                    беды.append(
                        f"маршрут {имя}: блок «{блок.get('заголовок', блок['тип'])}» — "
                        f"{количество} карточек в {колонок} колонках на "
                        f"{точка or 320}px оставляют в последнем ряду одну")
    return беды
