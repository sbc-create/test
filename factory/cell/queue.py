СВЕЖЕСТЬ_СНИМКА_Ч = 48


def _верховое_приложение(site_id: str) -> str:
    """Объявлено ли у витрины верховое приложение.

    Признак читается из конфигурации САМОЙ витрины, а не угадывается по имени
    семейства: семейства меняются, а объявление живёт рядом со всем остальным,
    что про витрину известно.
    """
    import json as _json  # noqa: PLC0415

    from factory.cell import registry as _registry  # noqa: PLC0415

    try:
        ячейка = _registry.resolve(site_id)
    except Exception:  # noqa: BLE001 — нет ячейки, нет и объявления
        return ""
    путь = (ячейка.repo or {}).get("path") or ""
    if not путь:
        return ""
    файл = КОРЕНЬ_ПРОЕКТА / путь / "config" / "site.json"
    try:
        данные = _json.loads(файл.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    return str((данные.get("environment") or {}).get("LORDS_LEGACY_UPSTREAM") or "")


def проверить_комплектность_данных(site_id: str) -> None:
    """Снимок каталога для этой витрины существует и не протух.

    Выпуск в пустую витрину даёт публичный HTTP 200 без содержимого — состояние,
    которое выглядит успехом и им не является. Проверяется наличие снимка
    производителя под идентификатором ЭТОЙ ячейки: именно его витрина читает
    после установки.

    Отсутствие каталога производителя — не всегда отказ: у семейств, которые
    заимствуют снимок соседа (AnimeGo) или получают данные из контейнера
    (Yummy), своего файла нет по построению. Поэтому отсутствие сообщается как
    отказ только тогда, когда снимок для этого site_id РАНЬШЕ был и исчез —
    иначе это замечание, и решение принимает вызывающий.
    """
    каталог = ВЫХОД_ПРОИЗВОДИТЕЛЯ / f"{site_id}-catalog.json"
    if not каталог.exists():
        return
    # Витрина, которая ПРОКСИРУЕТ приложение, снимок посетителю не отдаёт: тот
    # видит ответ верхового приложения, а снимок нужен ячейке лишь для страниц,
    # что она рисует сама. Возраст снимка у такой витрины не делает выпуск
    # опасным, и отказывать по нему значит блокировать исправный выпуск.
    #
    # Поймано на yummy-org: заявка отвергалась словами «снимок старше 431 ч» —
    # при том, что главная витрины обновляется каждые полчаса, а снимок она не
    # читает вовсе. То же различие уже проведено в `factory.cell.content`.
    if _верховое_приложение(site_id):
        return
    import time  # noqa: PLC0415

    возраст = (time.time() - каталог.stat().st_mtime) / 3600
    if возраст > СВЕЖЕСТЬ_СНИМКА_Ч:
        raise RequestRejected(
            f"{site_id}: снимок каталога {каталог.name} старше "
            f"{возраст:.0f} ч. Выпуск поставил бы витрине устаревшие данные, а "
            "публичный HTTP 200 этого не показал бы. Сначала обновить каталог")
    if каталог.stat().st_size < 1024:
        raise RequestRejected(
            f"{site_id}: снимок каталога {каталог.name} пуст "
            f"({каталог.stat().st_size} Б): выпуск дал бы сайт без содержимого")




