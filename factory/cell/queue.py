"""Очередь заявок на выпуск: что именно принимает привилегированный исполнитель.

Зачем очередь, а не команда
---------------------------

Активация требует root. Соблазнительное решение — разрешить владельцу один раз
выполнить «любой скрипт по такому-то пути от root». Оно не работает как
граница: кто может писать в этот путь, тот выполняет код от root, а писать в
рабочий каталог может кто угодно из сессии.

Поэтому между непривилегированной стороной и root стоит файл заявки со строгой
схемой. Заявка не может назвать путь, службу, команду или репозиторий. В ней
только идентификаторы, которые исполнитель проверяет по реестру и по GitHub:

* `site_id`   — обязан быть в реестре ячеек и иметь собственный репозиторий;
* `commit`    — 40 шестнадцатеричных знаков, обязан существовать в этом репозитории;
* `digest`    — ожидаемый отпечаток артефакта; исполнитель собирает артефакт сам
                и сверяет, поэтому подложить байты нечем;
* `ci_run`    — прогон, на котором digest получен; проверяется отдельно.

Всё остальное — пути, юниты, порты, учётные записи — исполнитель берёт из
реестра, а не из заявки. Это и есть граница.

Повтор
------

У заявки есть `request_id`. Повторная подача того же идентификатора не заводит
вторую операцию: возвращается состояние первой. Так выглядит обрыв сети со
стороны подающего — он не знает, дошла ли заявка, и обязан иметь право
повторить без последствий.
"""
from __future__ import annotations

import json
import os
import re
import tempfile
import uuid
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

#: Каталог очереди. Пишет непривилегированная сторона, читает root-исполнитель.
#: Тот же приём, что у прижившегося lords-deploy-broker: граница проходит по
#: схеме заявки, а не по правам на каталог.
БАЗА = Path(os.environ.get("SITE_CELL_QUEUE", "/var/lib/site-cells"))
ЗАЯВКИ = БАЗА / "requests"
РЕЗУЛЬТАТЫ = БАЗА / "results"
СОСТОЯНИЕ = БАЗА / "state"

ХЕКС40 = re.compile(r"^[0-9a-f]{40}$")
ДАЙДЖЕСТ = re.compile(r"^sha256:[0-9a-f]{64}$")
ИДЕНТ = re.compile(r"^[a-z][a-z0-9-]{2,63}$")
ЗАПРОС_ID = re.compile(r"^[a-z0-9][a-z0-9-]{7,63}$")

#: Что исполнителю разрешено делать. Список закрытый: «выполнить произвольную
#: операцию» отсутствует как понятие, а не запрещено проверкой.
#: `access-check` ничего не меняет: исполнитель проверяет СВОЙ доступ к
#: репозиторию сайта и пишет результат. Нужна потому, что права
#: интерактивной сессии и права исполнителя — разные, и разошлись они молча:
#: выпуск нового домена отклонялся HTTP 404, пока та же команда из сессии
#: читала прогон без ошибок.
ОПЕРАЦИИ = ("activate", "update", "deliver", "rollback", "editorial",
            "access-check")

#: Операции, которые ничего не выкладывают: коммит и digest им не нужны.
ОПЕРАЦИИ_БЕЗ_ВЫПУСКА = ("access-check",)

#: Этапы операции. Расширение уже существующей схемы онбординга, не вторая.
#: Этапы, которыми заявка отмечается по ходу. Перечень закрыт: неизвестный этап
#: отвергает заявку, и это правильно — иначе в журнале появлялись бы состояния,
#: которых никто не определял. Поэтому новая операция обязана объявить свои
#: этапы ЗДЕСЬ. `access-check` этого не сделала, и проверка доступа, отработав
#: верно и вернув точный required_input, записалась как `rejected`: «неизвестный
#: этап access_missing». Это тот же класс, что «доставка записана как failed» и
#: «откат записан как успех» — итог верный, а учёт врёт.
ЭТАПЫ = ("received", "validated", "artifact_verified", "candidate_ready",
         "switched", "live_verified", "failed", "rolled_back",
         "access_verified", "access_missing")


class RequestRejected(Exception):
    """Заявка отвергнута до единой мутации."""


@dataclass
class Заявка:
    request_id: str
    operation: str
    site_id: str
    commit: str
    digest: str
    ci_run: str = ""
    repo: str = ""
    submitted_at: str = ""
    submitted_by: str = ""
    note: str = ""
    stages: list[dict[str, Any]] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def _проверить(значение: str, правило: re.Pattern, поле: str) -> str:
    очищенное = (значение or "").strip()
    if not правило.match(очищенное):
        raise RequestRejected(
            f"{поле}={значение!r} не проходит форму {правило.pattern}. "
            "Форма проверяется до всего остального: значение уходит в аргументы "
            "внешних программ, и единственный надёжный способ не спорить с "
            "оболочкой — не пропускать ничего, что могло бы ей что-то значить")
    return очищенное


def разобрать(сырое: dict[str, Any]) -> Заявка:
    """Проверить форму заявки. Ни одного обращения к диску и сети."""
    if not isinstance(сырое, dict):
        raise RequestRejected("заявка обязана быть объектом JSON")
    лишние = set(сырое) - set(Заявка.__dataclass_fields__)
    if лишние:
        raise RequestRejected(
            f"в заявке неизвестные поля: {sorted(лишние)}. Заявка со свободными "
            "полями перестаёт быть договором: завтра в ней окажется путь")
    операция = (сырое.get("operation") or "").strip()
    if операция not in ОПЕРАЦИИ:
        raise RequestRejected(f"operation={операция!r}; разрешены {list(ОПЕРАЦИИ)}")
    # Проверке доступа коммит и digest не нужны по смыслу: она ничего не
    # выкладывает. Требовать их значило бы заставлять подставлять
    # правдоподобные выдуманные значения, а заявка на этом перестаёт быть
    # договором. Для всех операций, которые ставят код или данные, оба поля
    # остаются обязательными.
    без_выпуска = операция in ОПЕРАЦИИ_БЕЗ_ВЫПУСКА
    заявка = Заявка(
        request_id=_проверить(сырое.get("request_id", ""), ЗАПРОС_ID, "request_id"),
        operation=операция,
        site_id=_проверить(сырое.get("site_id", ""), ИДЕНТ, "site_id"),
        commit=("" if без_выпуска and not сырое.get("commit")
                else _проверить(сырое.get("commit", ""), ХЕКС40, "commit")),
        digest=("" if без_выпуска and not сырое.get("digest")
                else _проверить(сырое.get("digest", ""), ДАЙДЖЕСТ, "digest")),
        ci_run=str(сырое.get("ci_run") or "").strip(),
        repo=str(сырое.get("repo") or "").strip(),
        submitted_at=str(сырое.get("submitted_at") or ""),
        submitted_by=str(сырое.get("submitted_by") or ""),
        note=str(сырое.get("note") or "")[:500],
        stages=list(сырое.get("stages") or []),
    )
    if заявка.ci_run and not заявка.ci_run.isdigit():
        raise RequestRejected(f"ci_run={заявка.ci_run!r} должен быть числом прогона")
    return заявка


def новый_идентификатор(site_id: str, commit: str, *, operation: str = "activate",
                        snapshot: str = "") -> str:
    """Устойчивый идентификатор заявки.

    Выводится из того, ЧТО выкладывается, поэтому повтор той же работы даёт тот
    же идентификатор и не заводит вторую операцию.

    Операция входит в идентификатор обязательно. Без неё обновление данных на
    том же коммите сталкивалось с уже выполненным выпуском кода: заявка
    возвращала `already-finished`, и снимок молча не доезжал.

    Для обновления данных к идентификатору добавляется отпечаток снимка: тот же
    коммит с НОВЫМ снимком — это новая работа, а тот же снимок — повтор,
    который обязан ничего не менять.
    """
    хвост = (snapshot or commit)[:12]
    краткая = {"activate": "code", "update": "code", "deliver": "data",
               "rollback": "back", "editorial": "edit"}.get(operation, operation[:4])
    return f"{site_id}-{краткая}-{хвост}"[:64].lower()


def записать_атомарно(путь: Path, данные: dict[str, Any], *,
                      режим: int = 0o640) -> None:
    """Атомарная запись с явным режимом И группой каталога назначения.

    Двух вещей не хватало по очереди, и каждая поодиночке ломала обратную связь.

    Режим: NamedTemporaryFile создаёт файл 0600, и результат операции оказывался
    нечитаемым для того, кто её подал. Снаружи это молчание — заявка исчезла,
    ответа нет, причину узнать нечем.

    Группа: каталог результатов принадлежит `root:<подающий>`, но новый файл
    получает ПЕРВИЧНУЮ группу процесса, то есть root. Исполнитель работает от
    root, и файл выходил `rw-r----- root:root` — режим правильный, а группа
    такая, что читать его всё равно некому. Поэтому группа берётся у каталога
    назначения явно, а не через надежду на setgid: setgid ставится установщиком
    и может не стоять на каталоге, созданном раньше или руками.

    Смена группы возможна только root. Обычный процесс пишет свои файлы себе и
    в подмене группы не нуждается — отказ здесь не ошибка.
    """
    путь.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=путь.parent, delete=False,
                                     encoding="utf-8") as врем:
        json.dump(данные, врем, ensure_ascii=False, indent=2)
        врем.write("\n")
        временный = Path(врем.name)
    os.chmod(временный, режим)
    try:
        гид = путь.parent.stat().st_gid
        if гид != временный.stat().st_gid:
            os.chown(временный, -1, гид)
    except OSError:
        pass
    os.replace(временный, путь)


#: Исходы, при которых операция ДЕЙСТВИТЕЛЬНО применена к витрине.
#: Всё остальное — включая откат — означает, что выпуска не было.
#:
#: `delivered` — успех операции `deliver`, и его здесь не было. Пока через
#: очередь шли только выпуски кода, это молчало: `activate` возвращает
#: `activated`. Первая же доставка данных получила бы `status: failed` при
#: полностью успешной доставке — каталог на витрине новый, отчёт говорит
#: «не применено», а заявка считается неповторённой и подаётся снова.
#: Тот же род ошибки, что и с откатом выше: судить об успехе по перечню, в
#: который забыли внести исход.
ПРИМЕНЁННЫЕ_ИСХОДЫ = ("activated", "delivered", "edited", "unchanged", "dry-run",
                      "checked")


def _применено(итог: dict[str, Any]) -> bool:
    """Была ли операция применена на самом деле.

    Верхний `status` говорит только о том, что исполнитель отработал без
    исключения. Откат тоже отрабатывает без исключения: он возвращает
    `stage: rolled_back`, а не `failed`, и результат получал `status: ok`.
    Повтор такой заявки отвергался как «уже выполнено» — притом что витрина
    осталась на прежнем выпуске. Наблюдалось на lords-01: повышение получило
    старый build-id с занятого порта, откат сработал верно, и заявка после
    этого стала неповторяемой.

    Поэтому успех определяется по ИСХОДУ операции, а не по тому, что она
    завершилась.
    """
    if итог.get("status") != "ok":
        return False
    исход = (итог.get("outcome") or {}).get("status")
    # Старые результаты без `outcome` судим по верхнему статусу, как раньше.
    return исход in ПРИМЕНЁННЫЕ_ИСХОДЫ if исход else True


def подать(заявка: Заявка, *, база: Path | None = None) -> dict[str, Any]:
    """Положить заявку в очередь. Повтор возвращает состояние первой."""
    корень = база or БАЗА
    очередь = корень / "requests"
    результаты = корень / "results"
    файл = очередь / f"{заявка.request_id}.json"
    готовый = результаты / f"{заявка.request_id}.json"

    if готовый.is_file():
        try:
            итог = json.loads(готовый.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            итог = {"status": "нечитаем"}
        # Повторять нельзя только УСПЕШНУЮ операцию: она уже применена, и второй
        # прогон стал бы повторной выкладкой. Неудачная — наоборот, обязана быть
        # повторяемой: причина отказа устраняется, и заявка подаётся снова. Иначе
        # один сбой запирал бы выпуск этого коммита навсегда.
        if _применено(итог):
            return {"status": "already-finished", "request_id": заявка.request_id,
                    "result": итог}
        предыдущий = итог.get("status")
        # Прежний результат НЕ удаляется. Каталог результатов принадлежит
        # исполнителю, подающая сторона его только читает — ровно затем, чтобы
        # не могла подменить или стереть чужой вывод. Попытка убрать здесь файл
        # роняла подачу на живом сервере с EACCES, и повторить неудачную заявку
        # было нельзя вообще.
        #
        # Убирать его и не нужно: исполнитель перезапишет результат атомарно,
        # а признаком «операция идёт» служит сам файл заявки, а не отсутствие
        # результата.
        заявка.stages = [{"stage": "received", "at": заявка.submitted_at,
                          "retry_after": предыдущий}]
        записать_атомарно(файл, заявка.as_dict())
        return {"status": "requeued-after-failure", "request_id": заявка.request_id,
                "previous_status": предыдущий, "path": str(файл)}
    if файл.is_file():
        существующая = json.loads(файл.read_text(encoding="utf-8"))
        if (существующая.get("commit") != заявка.commit
                or существующая.get("operation") != заявка.operation):
            raise RequestRejected(
                f"заявка {заявка.request_id} уже есть и описывает другой выпуск "
                f"({существующая.get('commit', '')[:12]} / {существующая.get('operation')}). "
                "Молча заменить её значило бы потерять идущую операцию")
        return {"status": "already-queued", "request_id": заявка.request_id,
                "request": существующая}

    заявка.stages = [{"stage": "received", "at": заявка.submitted_at}]
    записать_атомарно(файл, заявка.as_dict())
    return {"status": "queued", "request_id": заявка.request_id,
            "path": str(файл), "request": заявка.as_dict()}


def состояние(request_id: str, *, база: Path | None = None) -> dict[str, Any]:
    корень = база or БАЗА
    готовый = корень / "results" / f"{request_id}.json"
    если_в_очереди = корень / "requests" / f"{request_id}.json"
    if готовый.is_file():
        return {"status": "finished", **json.loads(готовый.read_text(encoding="utf-8"))}
    if если_в_очереди.is_file():
        return {"status": "queued", **json.loads(если_в_очереди.read_text(encoding="utf-8"))}
    return {"status": "unknown", "request_id": request_id}


def отметить(заявка_путь: Path, этап: str, детали: dict[str, Any] | None = None) -> None:
    """Записать переход. Журнал живёт вне процесса.

    Восстановление после гибели процесса или перезагрузки хоста возможно только
    если намерение записано до действия, а результат — после. Shell-trap этого
    не даёт: его не будет ни при SIGKILL, ни при перезагрузке.
    """
    if этап not in ЭТАПЫ:
        raise RequestRejected(f"неизвестный этап {этап!r}")
    данные = json.loads(заявка_путь.read_text(encoding="utf-8"))
    данные.setdefault("stages", []).append(
        {"stage": этап, "at": _сейчас(), **(детали or {})})
    записать_атомарно(заявка_путь, данные)


def _сейчас() -> str:
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).isoformat()


def идентификатор_проверки(site_id: str) -> str:
    """Идентификатор проверки доступа: один на сайт в сутки.

    Без суток повторная проверка после выдачи прав вернула бы
    `already-finished` и состояние выглядело бы неизменившимся. С временем до
    секунды очередь копила бы по заявке на каждый запуск.
    """
    сутки = _сейчас()[:10]
    return f"{site_id}-access-{сутки}"


#: Корень проекта: этот файл лежит в factory/cell/.
КОРЕНЬ_ПРОЕКТА = Path(__file__).resolve().parents[2]


def проверить_рабочую_копию(site_id: str, commit: str) -> None:
    """Репозиторий и коммит существуют ДО подачи заявки, а не после.

    Повод конкретный. Заявка на выпуск `yummy-07` — ячейки, у которой нет ни
    репозитория, ни рабочей копии, — была принята очередью с заведомо
    несуществующим коммитом. Отказ пришёл бы минутой позже от исполнителя и
    выглядел бы как ошибка GitHub («не ответил про прогон»), то есть уводил бы в
    сторону прав доступа вместо отсутствующего репозитория. Одна и та же
    формулировка отказа на две совершенно разные причины — и есть механизм, из-за
    которого ночь уходит на диагностику.

    Проверяется то, что submitter может проверить у себя: объявлен ли
    репозиторий, есть ли рабочая копия, знает ли она этот коммит. Прав CI и
    GitHub здесь не требуется — и именно поэтому проверка стоит здесь.
    """
    import subprocess  # noqa: PLC0415

    from factory.cell import registry as реестр_ячеек  # noqa: PLC0415

    # Первая версия этой проверки звала несуществующий `registry.cell()` и
    # глотала любое исключение через `except Exception: return`. Охрана молча
    # выключилась целиком, и обе заведомо негодные заявки снова были приняты.
    # Проглоченное исключение — не осторожность, а отключённая проверка;
    # поэтому здесь ловится ровно одно ожидаемое: «такой ячейки нет».
    try:
        ячейка = реестр_ячеек.resolve(site_id)
    except реестр_ячеек.RegistryError as exc:
        raise RequestRejected(f"{site_id}: ячейки нет в реестре ({exc})") from exc
    путь_строкой = (ячейка.repo or {}).get("path") or ""
    if not путь_строкой:
        raise RequestRejected(
            f"{site_id}: в реестре не объявлен собственный репозиторий сайта "
            "(repo.path). Выпускать нечего: заявка не создаётся")
    путь = КОРЕНЬ_ПРОЕКТА / путь_строкой
    if not (путь / ".git").exists():
        raise RequestRejected(
            f"{site_id}: рабочей копии {путь_строкой} нет. Репозиторий объявлен, но "
            "не создан — заявка на выпуск не создаётся, чтобы отказ не пришёл "
            "минутой позже как ошибка GitHub")
    if commit:
        r = subprocess.run(["git", "-C", str(путь), "cat-file", "-e", f"{commit}^{{commit}}"],
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise RequestRejected(
                f"{site_id}: коммита {commit[:12]} нет в {путь_строкой}. "
                "Заявка на выпуск коммита, которого нет в рабочей копии, не создаётся")


#: Сколько часов результат проверки доступа считается свежим. Права меняются
#: мгновенно и без предупреждения; вчерашнее «доступ есть» ничего не говорит о
#: сегодняшнем дне.
СВЕЖЕСТЬ_ДОСТУПА_Ч = 12


def проверить_доступ_исполнителя(site_id: str) -> None:
    """Доступ ИСПОЛНИТЕЛЯ к репозиторию и CI — до сборки и подачи заявки.

    Повод: ошибка повторилась. Четыре заявки на выпуск (zona-03, lords-05,
    lords-06, lords-07) прошли все локальные проверки, дождались зелёного CI и
    были отвергнуты исполнителем одной и той же причиной — его токен не видит
    репозиторий. До этого тем же способом были отвергнуты zona-03 и lords-05
    ещё дважды. Каждый раз отказ приходил ПОСЛЕ работы, а не до неё.

    Проверяется то, что можно проверить заранее: результат операции
    `access-check`, которую выполняет сам исполнитель своим токеном. Доступ
    интерактивной сессии здесь ничего не доказывает и не используется.

    Три различимых исхода вместо двух:

    * проверки не было или она старше суток — отказ с командой, как её сделать;
    * проверка была и говорит «нет доступа» — отказ с точным именем репозитория;
    * проверка была и говорит «доступ есть» — заявка создаётся.
    """
    import datetime as _dt  # noqa: PLC0415

    каталог = БАЗА / "results"
    файлы = sorted(каталог.glob(f"{site_id}-access-*.json"),
                   key=lambda п: п.stat().st_mtime) if каталог.is_dir() else []
    если_нет = (
        f"{site_id}: доступ исполнителя к репозиторию не проверялся. "
        f"Сначала: python3 -m factory cell submit --site {site_id} "
        "--cell-operation access-check — проверку делает сам исполнитель своим "
        "токеном, и её результат отвечает на вопрос «примут ли заявку» ДО сборки")
    if not файлы:
        raise RequestRejected(если_нет)
    свежий = файлы[-1]
    возраст = (_dt.datetime.now().timestamp() - свежий.stat().st_mtime) / 3600
    if возраст > СВЕЖЕСТЬ_ДОСТУПА_Ч:
        raise RequestRejected(
            f"{site_id}: последняя проверка доступа исполнителя — "
            f"{возраст:.0f} ч назад, это устарело. Права меняются без "
            f"предупреждения. Повторить: python3 -m factory cell submit "
            f"--site {site_id} --cell-operation access-check")
    try:
        итог = (json.loads(свежий.read_text(encoding="utf-8")).get("outcome") or {})
    except (OSError, ValueError) as ош:
        raise RequestRejected(
            f"{site_id}: результат проверки доступа не читается ({ош})") from ош
    if not (итог.get("repo_read") and итог.get("actions_read")):
        сообщение = (
            f"{site_id}: у исполнителя нет доступа к {итог.get('repo', 'репозиторию')} "
            f"(repo_read={итог.get('repo_read')}, actions_read={итог.get('actions_read')}). "
            f"{итог.get('repo_error') or ''} "
            "Заявка не создаётся: она была бы отвергнута после сборки и зелёного CI — "
            "так уже произошло четыре раза подряд")
        raise RequestRejected(" ".join(сообщение.split()))


#: Где производитель оставляет снимки каталога. Путь установленный, не
#: вычисляемый: витрины читают именно его.
ВЫХОД_ПРОИЗВОДИТЕЛЯ = Path("/srv/lords/.frontend")

#: Сколько часов снимок считается пригодным. Производитель работает раз в сутки.
СВЕЖЕСТЬ_СНИМКА_Ч = 48


def проверить_комплектность_данных(site_id: str) -> None:
    """Снимок каталога для этой витрины существует и не протух.

    Выпуск в пустую витрину даёт публичный HTTP 200 без содержимого — состояние,
    которое выглядит успехом и им не является. Проверяется наличие снимка
    производителя под идентификатором ЭТОЙ ячейки: именно его витрина читает
    после установки.

    Отсутствие каталога производителя — не всегда отказ: у семейств, которые
    заимствуют снимок соседа (AnimeGo) или получают данные из контейнера
    (Yummy), своего файла нет по построению. Поэтому отсутствие сообщается как
    отказ только тогда, когда снимок для этого site_id РАНЬШЕ был и исчез —
    иначе это замечание, и решение принимает вызывающий.
    """
    каталог = ВЫХОД_ПРОИЗВОДИТЕЛЯ / f"{site_id}-catalog.json"
    if not каталог.exists():
        return
    import time  # noqa: PLC0415

    возраст = (time.time() - каталог.stat().st_mtime) / 3600
    if возраст > СВЕЖЕСТЬ_СНИМКА_Ч:
        raise RequestRejected(
            f"{site_id}: снимок каталога {каталог.name} старше "
            f"{возраст:.0f} ч. Выпуск поставил бы витрине устаревшие данные, а "
            "публичный HTTP 200 этого не показал бы. Сначала обновить каталог")
    if каталог.stat().st_size < 1024:
        raise RequestRejected(
            f"{site_id}: снимок каталога {каталог.name} пуст "
            f"({каталог.stat().st_size} Б): выпуск дал бы сайт без содержимого")


