#: здесь не требуется и не используется.
NGINX = Path("/etc/nginx")


def проверить_маршрут(site_id: str) -> None:
    """Upstream ячейки включён хотя бы в одну конфигурацию nginx.

    Повод: три заявки подряд (lords-05, lords-06, lords-07) отвергнуты
    исполнителем с одним текстом — «upstream не включён ни в одну конфигурацию
    nginx: переключение маршрута ничего бы не изменило». Отказ правильный и
    безопасный, но приходит он ПОСЛЕ сборки и проверки происхождения, то есть
    после всей работы. Проверить включение можно заранее и без прав.

    Отсутствие файла upstream не отказ: его создаёт сам выпуск. Отказ — когда
    файл есть, а включения нет: это состояние, в котором переключение маршрута
    молча не влияет ни на что.
    """
    # Проверяется НЕ файл upstream — его создаёт сам выпуск, — а наличие
    # server-блока с доменом витрины. Первая версия смотрела на upstream и
    # молчала, потому что до первого выпуска файла нет: заявка снова уходила в
    # очередь и снова отвергалась. Условие исполнителя («upstream включён в
    # конфигурацию») выполнимо только там, где такой блок есть.
    from factory.cell import registry as реестр_ячеек  # noqa: PLC0415

    try:
        ячейка = реестр_ячеек.resolve(site_id)
    except реестр_ячеек.RegistryError:
        return
    домен = ячейка.domain
    # «Не могу проверить» и «блока нет» — разные ответы. `rglob` по
    # несуществующему каталогу возвращает пустой список без исключения, и без
    # этой ветки отсутствие доступа к /etc/nginx выглядело бы как отсутствие
    # server-блока: проверка блокировала бы выпуск там, где ничего не знает.
    try:
        if not NGINX.is_dir():
            return
        конфиги = list(NGINX.rglob("*.conf"))
    except OSError:
        return
    if not конфиги:
        return
    for путь in конфиги:
        try:
            for строка in путь.read_text(encoding="utf-8", errors="replace").splitlines():
                голая = строка.strip()
                if голая.startswith("server_name") and домен in голая.rstrip(";").split():
                    return
        except OSError:
            continue
    raise RequestRejected(
        f"{site_id}: ни в одной конфигурации nginx нет server_name {домен}. "
        "Исполнитель отвергнет заявку после сборки: переключать маршрут будет "
        "некуда. Сначала: "
        f"sudo bash automation/host/launch-new-site.sh --site {site_id}")


