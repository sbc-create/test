"""Одноразовые коды владельца: доказательство, что согласие дал ОН.

Зачем это нужно
---------------

Согласие владельца на открытие домена хранится в каталоге root
(`factory.cell.owner_consent`), и создать его может только команда владельца:
флаг в реестре разрешением не считается, потому что реестр доступен на запись
той же учётной записи, под которой работают инструменты. Пока единственным
способом была оболочка, согласие нельзя было выдать из рабочего чата.

Прямой инструмент моста эту задачу НЕ решает: мост работает от `claude`, то
есть «инструмент регистрации согласия» без доказательства превратился бы в
право модели выдавать разрешения себе. Тогда весь корневой якорь становится
украшением.

Поэтому вызов из чата несёт ДОКАЗАТЕЛЬСТВО: одноразовый код, который знает
только владелец. Код выдаётся один раз командой установки, хранится ТОЛЬКО
отпечатком в каталоге root и действует один раз и ограниченное время.

Что это даёт и чего не даёт
---------------------------

Даёт: без свежего кода владельца ни модель, ни кто-либо под `claude` согласие
не зарегистрирует — проверку делает root, отпечатки ему недоступны на чтение
никому другому.

НЕ даёт: код, который владелец вписал в чат, модель видит — он пришёл ей
аргументом. Поэтому код одноразовый и с коротким сроком: захваченное значение
мертво сразу после операции, на которую владелец его и дал. Это ограничение
названо здесь, а не скрыто.

Ещё одно свойство: на диск, доступный `claude`, код не попадает НИ РАЗУ. В
заявку кладётся не он, а привязка `sha256(код|домен|действие)`; заявка, снятая
с диска, не годится ни для другого домена, ни для другого действия. Сами коды
лежат в файле root (0600) — иначе привязку было бы нечем проверить: её нельзя
вычислить из отпечатка кода, а проверяющая сторона обязана убедиться, что
владелец назвал ИМЕННО этот домен и ИМЕННО это действие.
"""
from __future__ import annotations

import hashlib
import json
import os
import pathlib
import tempfile
from typing import Any

#: Где лежат отпечатки кодов. root:root 0600 — никому, кроме root.
ХРАНИЛИЩЕ = pathlib.Path(os.environ.get(
    "SITE_CELLS_OWNER_CODES", "/etc/site-factory/owner-consent-codes.json"))

#: Сколько минут код годен с момента выдачи команды установки.
СРОК_МИН = 60 * 24 * 30

СХЕМА = 1


class КодОтвергнут(RuntimeError):
    """Код не принят. Причина называется, значение кода не повторяется."""


def привязка(код: str, домен: str, действие: str) -> str:
    """Отпечаток, который кладётся в заявку ВМЕСТО кода.

    Домен и действие входят в отпечаток: заявка, снятая с диска, не годится
    ни для другого домена, ни для отзыва вместо выдачи.
    """
    сырое = f"{(код or '').strip()}|{(домен or '').strip().lower()}|{(действие or '').strip().lower()}"
    return hashlib.sha256(сырое.encode("utf-8")).hexdigest()


def отпечаток_кода(код: str) -> str:
    """Короткая подпись кода для журнала: сам код в журнал не попадает."""
    return hashlib.sha256((код or "").strip().encode("utf-8")).hexdigest()


def _прочитать() -> dict[str, Any]:
    данные = json.loads(ХРАНИЛИЩЕ.read_text(encoding="utf-8"))
    if данные.get("schema_version") != СХЕМА:
        raise КодОтвергнут(
            f"{ХРАНИЛИЩЕ}: схема {данные.get('schema_version')!r}, "
            f"ожидается {СХЕМА}")
    return данные


def _права() -> tuple[bool, str]:
    """Хранилище обязано принадлежать root и не читаться никем иным."""
    try:
        св = ХРАНИЛИЩЕ.stat()
    except OSError as ош:
        return False, f"{ХРАНИЛИЩЕ} недоступно: {type(ош).__name__}"
    if св.st_uid != 0:
        return False, f"{ХРАНИЛИЩЕ} принадлежит uid {св.st_uid}, а не root"
    if св.st_mode & 0o077:
        return False, (f"{ХРАНИЛИЩЕ} доступно не только root "
                       f"({oct(св.st_mode & 0o7777)})")
    return True, ""


def проверить_и_погасить(привязка_из_заявки: str, домен: str, действие: str
                         ) -> dict[str, Any]:
    """Принять привязку ОДИН раз. Возвращает запись кода; иначе `КодОтвергнут`.

    На вход идёт не код, а привязка `sha256(код|домен|действие)` из заявки.
    Проверяющая сторона перебирает СВОИ непогашенные коды и считает привязку
    для названного домена и действия: совпало — владелец назвал именно этот
    домен и именно это действие, не совпало — заявка не доказывает ничего.

    Вызывается ТОЛЬКО привилегированной стороной: хранилище кодов читает и
    пишет один root.
    """
    ок, почему = _права()
    if not ок:
        raise КодОтвергнут(почему)
    данные = _прочитать()
    домен_н = (домен or "").strip().lower()
    действие_н = (действие or "").strip().lower()
    привязка_н = (привязка_из_заявки or "").strip().lower()
    if not привязка_н:
        raise КодОтвергнут("в заявке нет привязки согласия")
    import datetime as _dt
    сейчас = _dt.datetime.now(_dt.timezone.utc)
    совпало = None
    просрочено = False
    использовано = None
    for запись in данные.get("codes") or []:
        код = str(запись.get("code") or "")
        if not код:
            continue
        if привязка(код, домен_н, действие_н) != привязка_н:
            continue
        # Привязка совпала: код назван владельцем для этого домена и действия.
        if запись.get("used_at"):
            использовано = запись
            continue
        годен_до = str(запись.get("valid_until") or "")
        if годен_до:
            try:
                предел = _dt.datetime.fromisoformat(годен_до.replace("Z", "+00:00"))
            except ValueError:
                предел = None
            if предел is not None and сейчас > предел:
                просрочено = True
                continue
        совпало = запись
        break
    if совпало is None:
        if использовано is not None:
            raise КодОтвергнут(
                f"код уже использован {использовано['used_at']} для "
                f"{использовано.get('used_for') or 'неизвестного домена'}: "
                "коды одноразовые")
        if просрочено:
            raise КодОтвергнут("срок кода истёк")
        # Ни код, ни его значение в тексте отказа не повторяются.
        raise КодОтвергнут(
            f"согласие не доказано: ни один код владельца не подтверждает "
            f"{действие_н} для {домен_н}")
    совпало["used_at"] = сейчас.strftime("%Y-%m-%dT%H:%M:%SZ")
    совпало["used_for"] = f"{домен_н}:{действие_н}"
    _записать(данные)
    return {"id": совпало.get("id"), "used_at": совпало["used_at"],
            "used_for": совпало["used_for"],
            "code_fingerprint": отпечаток_кода(str(совпало.get("code") or ""))[:12]}


def _записать(данные: dict[str, Any]) -> None:
    """Запись атомарна и сохраняет владельца и режим файла."""
    св = ХРАНИЛИЩЕ.stat()
    with tempfile.NamedTemporaryFile("w", dir=ХРАНИЛИЩЕ.parent, delete=False,
                                     encoding="utf-8") as врем:
        json.dump(данные, врем, ensure_ascii=False, indent=2)
        врем.write("\n")
        времянка = pathlib.Path(врем.name)
    os.chown(времянка, св.st_uid, св.st_gid)
    os.chmod(времянка, св.st_mode & 0o7777)
    времянка.replace(ХРАНИЛИЩЕ)


def сведения() -> dict[str, Any]:
    """Сколько кодов есть и сколько осталось. Без самих кодов и отпечатков.

    Читается диагностикой, в том числе непривилегированной: хранилище ей
    недоступно, и тогда ответ честно говорит об этом, а не делает вид, что
    кодов нет.
    """
    ок, почему = _права()
    if not ок:
        return {"present": ХРАНИЛИЩЕ.exists(), "readable": False,
                "reason": почему}
    try:
        данные = _прочитать()
    except (OSError, ValueError, КодОтвергнут) as ош:
        return {"present": True, "readable": False,
                "reason": f"{type(ош).__name__}: {ош}"}
    коды = данные.get("codes") or []
    return {"present": True, "readable": True,
            "total": len(коды),
            "unused": len([к for к in коды if not к.get("used_at")]),
            "issued_at": данные.get("issued_at"),
            "store": str(ХРАНИЛИЩЕ)}
