"""Привилегированный исполнитель заявок: закрытый набор операций, журнал, замок.

Что он делает и чего не делает
------------------------------

Делает: берёт заявку из очереди, проверяет её по реестру и по GitHub, выполняет
одну из четырёх операций и записывает результат. Между «намерен» и «сделал»
всегда есть запись на диске — после гибели процесса или перезагрузки хоста
восстановление начинается со сверки журнала с фактом, а не с догадки.

Не делает: не выполняет путей, скриптов и команд из заявки. Их там нет как
понятия — схема заявки закрыта. Пути, юниты, порты и учётные записи берутся из
реестра, а артефакт собирается из названного коммита и сверяется по digest.

Почему замок с владельцем, а не с возрастом
-------------------------------------------

Старый замок направления лежал без pid, и решение «протух или нет» пришлось
принимать человеку. Возраст ничего не доказывает: долгая выкладка живёт часами,
а мёртвый процесс не становится живым от того, что замок свежий. Поэтому в
замке записан владелец — pid и время старта процесса — и живость проверяется,
а не предполагается. Совпадение одного pid недостаточно: номера переиспользуются,
и время старта отличает нового владельца от призрака.
"""
from __future__ import annotations

import contextlib
import json
import re
import os
import subprocess
import tempfile
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from factory.cell import indexing_core, nginx_indexing, owner_consent
from factory.cell import privileged, protected, queue, registry, runtime


class ExecutorError(Exception):
    """Операция не выполнена. Витрина не тронута либо возвращена."""


def _сейчас() -> str:
    return datetime.now(timezone.utc).isoformat()


def _время_старта(pid: int) -> str:
    """Отметка старта процесса из /proc. Отличает живого владельца от тёзки."""
    try:
        поля = Path(f"/proc/{pid}/stat").read_text(encoding="utf-8").rsplit(")", 1)[1].split()
        return поля[19]  # starttime в тиках с загрузки системы
    except (OSError, IndexError):
        return ""


@dataclass
class Замок:
    путь: Path
    владелец: dict[str, Any]

    def снять(self) -> None:
        with contextlib.suppress(OSError):
            self.путь.unlink()


def взять_замок(site_id: str, *, база: Path, операция: str) -> Замок:
    """Живая блокировка на сайт. Возраст не является разрешением на захват."""
    каталог = база / "locks"
    каталог.mkdir(parents=True, exist_ok=True)
    файл = каталог / f"{site_id}.json"
    мой = {"pid": os.getpid(), "starttime": _время_старта(os.getpid()),
           "site": site_id, "operation": операция, "at": _сейчас(),
           "host": os.uname().nodename}

    if файл.is_file():
        try:
            чужой = json.loads(файл.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            raise ExecutorError(
                f"замок {файл} нечитаем. Испорченный замок хуже отсутствующего: "
                "он молча разрешает всё. Нужно решение человека") from None
        pid = чужой.get("pid")
        живой = False
        if isinstance(pid, int) and pid > 0:
            try:
                os.kill(pid, 0)
                живой = _время_старта(pid) == (чужой.get("starttime") or "")
            except OSError:
                живой = False
        if живой:
            raise ExecutorError(
                f"{site_id}: операцию {чужой.get('operation')} держит живой процесс "
                f"{pid} с {чужой.get('at')}. Ждём его, а не отнимаем")
        if not чужой.get("starttime"):
            raise ExecutorError(
                f"{site_id}: в замке {файл} нет отметки старта владельца. "
                "Снимать такой замок автоматически нельзя — возраст не "
                "доказывает смерть процесса")
        # Владелец мёртв и это доказано: pid не отвечает либо это другой процесс.
        файл.unlink()

    queue.записать_атомарно(файл, мой)
    return Замок(путь=файл, владелец=мой)


#: Команда владельца, которая единственная создаёт якорь согласия. Путь
#: АБСОЛЮТНЫЙ: привилегированная сторона не ищет её по PATH — иначе порядок
#: каталогов решал бы, что именно запустит root. Отдельной константой, чтобы
#: стенд мог подменить её, не подменяя запуск процессов.
КОМАНДА_СОГЛАСИЯ = Path("/home/claude/wt-portable-site-cell-01/automation/host/"
                        "authorize-indexing.sh")


def зарегистрировать_согласие(заявка: queue.Заявка, *,
                              dry_run: bool = True) -> dict[str, Any]:
    """Согласие владельца, выданное ИЗ ЧАТА и доказанное его кодом.

    Зачем это операция исполнителя. Корневой якорь согласия
    (`/var/lib/site-cells/owner-consent/<домен>.json`) создаётся только
    привилегированной стороной — в этом весь смысл: флаг в реестре разрешением
    не считается, потому что реестр доступен на запись учётной записи
    инструментов. Пока единственным способом была оболочка, выдать согласие из
    рабочего чата было нечем, и операция открытия домена упиралась в человека с
    терминалом.

    Почему это НЕ делает инструмент моста напрямую. Мост работает от `claude`.
    Инструмент, создающий согласие без доказательства, означал бы право модели
    выдавать разрешения себе, и якорь стал бы украшением.

    Доказательство — одноразовый код владельца. В заявке лежит не код, а
    привязка `sha256(код|домен|действие)`: каталог заявок доступен на запись
    инструментам, и код, записанный туда, можно было бы снять и применить
    второй раз. Привязка же не годится ни для другого домена, ни для отзыва
    вместо выдачи. Сверяет её root по своему хранилищу кодов (0600), гасит код
    и только после этого вызывает ТУ ЖЕ команду владельца
    `automation/host/authorize-indexing.sh` — второй реализации согласия не
    появляется.
    """
    from factory.cell import owner_codes

    cell = registry.resolve(заявка.site_id)
    домен = (cell.domain or "").strip().lower()
    действие = заявка.consent_action
    шаги: dict[str, Any] = {"domain": домен, "action": действие}
    if not домен:
        raise ExecutorError(
            f"{заявка.site_id}: в реестре ячеек нет домена — согласие выдаётся "
            "домену, а не идентификатору")
    if dry_run:
        return {"stage": "consent_dry_run", "status": "nothing-to-do",
                "steps": шаги, "domain": домен, "action": действие,
                "note": "сухой прогон: код не гасится и согласие не меняется"}
    if действие == "sync":
        # Перенос уже подтверждённого решения: кода нет и не требуется.
        # Проверяется ЯКОРЬ, и не наличием файла, а функцией фабрики.
        ок, почему, запись = owner_consent.проверить(заявка.site_id, домен)
        if not ок:
            raise ExecutorError(
                f"{заявка.site_id}: переносить нечего — якорь согласия не "
                f"подтверждён: {почему}")
        шаги["code"] = {"not_required": True, "anchor_id": (запись or {}).get("id"),
                        "reason": ("действие sync переносит решение владельца, "
                                   "уже подтверждённое якорём, и нового "
                                   "разрешения не выдаёт")}
    else:
        try:
            погашен = owner_codes.проверить_и_погасить(
                заявка.consent_proof, домен, действие)
        except owner_codes.КодОтвергнут as отказ:
            # Текст отказа не повторяет ни кода, ни его привязки.
            raise ExecutorError(f"{заявка.site_id}: {отказ}") from None
        шаги["code"] = погашен
    сценарий = КОМАНДА_СОГЛАСИЯ
    if not сценарий.is_file():
        raise ExecutorError(f"нет команды владельца {сценарий}: согласие "
                            "выдаётся только ею, второй реализации нет")
    аргументы = ["bash", str(сценарий), "--domain", домен]
    if действие == "revoke":
        аргументы.append("--undo")
    elif действие == "sync":
        аргументы.append("--sync")
    готово = subprocess.run(аргументы, capture_output=True, text=True,
                            timeout=300)
    шаги["script"] = {"returncode": готово.returncode,
                      "stdout_tail": (готово.stdout or "").strip()[-600:],
                      "stderr_tail": (готово.stderr or "").strip()[-400:]}
    if готово.returncode != 0:
        raise ExecutorError(
            f"{заявка.site_id}: команда владельца отказала (код "
            f"{готово.returncode}): {(готово.stderr or готово.stdout).strip()[-300:]}")
    # Итог проверяется ЧТЕНИЕМ якоря, а не выводом скрипта.
    сведения = owner_consent.сведения(домен)
    шаги["consent"] = сведения
    ожидается_есть = действие in ("grant", "sync")
    if bool(сведения.get("present")) is not ожидается_есть:
        raise ExecutorError(
            f"{заявка.site_id}: команда отработала, но якорь согласия "
            f"{'не появился' if ожидается_есть else 'не исчез'}: {сведения}")
    return {"stage": "consent_applied", "status": "applied", "steps": шаги,
            "domain": домен, "action": действие,
            "consent_id": сведения.get("id") or ""}


def _требовать_согласия(заявка: queue.Заявка, cell, домен: str,
                        предмет: str) -> dict[str, Any]:
    """Разрешение владельца на СНЯТИЕ запрета. Закрытие его не требует.

    Одна проверка на обе привилегированные части режима — слой nginx и реестр
    ядра семейства. Две копии этой проверки разошлись бы, и разошлись бы в
    худшую сторону: одна из частей снимала бы запрет по более слабому условию,
    а снаружи это неотличимо от разрешённого открытия.
    """
    if (заявка.mode or "").strip().upper() != "OPEN":
        return {"required": False,
                "reason": f"{заявка.mode!r} добавляет запрет, а не снимает: "
                          "разрешение владельца не требуется"}
    # УСТАРЕВШИЙ РЕЕСТР ОТЛИЧАЕТСЯ ОТ ОТСУТСТВИЯ РАЗРЕШЕНИЯ.
    #
    # Измерено 2026-10-04: владелец выдал разрешение в 08:32:42, запись легла
    # в авторитетный реестр; исполнитель читал копию, снятую установкой в
    # 07:10:34, и отказал словами «open_authorized не равно true». Отказ
    # выглядел отсутствием разрешения, а был устаревшим снимком — и искать
    # причину пришлось по двум файлам с одним путём.
    подтверждение, почему_подтв, запись_подтв = owner_consent.проверить(
        заявка.site_id, домен)
    объявлено = (cell.indexing or {}).get("open_authorized")
    ид_реестра = str((cell.indexing or {}).get("open_authorization_id") or "")
    ид_подтв = str((запись_подтв or {}).get("id") or "")
    if подтверждение and (объявлено is not True or (ид_подтв and ид_реестра != ид_подтв)):
        raise ExecutorError(
            f"{заявка.site_id}: подтверждение владельца ЕСТЬ "
            f"({ид_подтв or 'без идентификатора'}), а прочитанный реестр "
            f"его не знает: open_authorized = {объявлено!r}, "
            f"open_authorization_id = {ид_реестра or 'нет'}. Прочитан "
            f"{registry.registry_path()}. Это устаревший снимок реестра, а "
            "не отсутствие разрешения: исполнитель обязан читать "
            "авторитетный файл (ссылка пакета и SITE_CELLS_REGISTRY)")
    if объявлено is not True:
        raise ExecutorError(
            f"{заявка.site_id}: открытие ({предмет}) запрещено — в реестре "
            f"ячеек indexing.open_authorized не равно true (прочитан "
            f"{registry.registry_path()}). Разрешением считается только "
            "булево true; закрытие (mode=closed) разрешения не требует")
    # Флага НЕДОСТАТОЧНО, и это не перестраховка. Файл реестра принадлежит
    # учётной записи, под которой работают инструменты, писателя у поля в
    # фабрике не было вовсе — значит флаг не доказывает, что разрешение дал
    # владелец. Доказательство — файл подтверждения в каталоге root, который
    # может создать только root (`automation/host/authorize-indexing.sh`).
    if not подтверждение:
        raise ExecutorError(
            f"{заявка.site_id}: открытие ({предмет}) запрещено — "
            f"подтверждения владельца нет: {почему_подтв}")
    return {"required": True, "confirmed": True,
            "authorization_id": ид_подтв,
            "anchor": (запись_подтв or {}).get("path") or "",
            "reason": почему_подтв}


def переключить_ядро_индексации(заявка: queue.Заявка, *,
                                dry_run: bool = True) -> dict[str, Any]:
    """Режим в СОБСТВЕННОМ реестре семейства + перезапуск юнита.

    Зачем это одна операция. У семейства Yummy режим решает не наш файл
    состояния, а реестр площадки, который читает её же модуль
    (`src/nova_core_indexability.py`) — и читает ПРИ ИМПОРТЕ точки входа.
    Поэтому запись без перезапуска оставляла бы решение, о котором работающий
    процесс не знает: реестр утверждает одно, домен отдаёт другое, и
    следующий читатель поверит реестру. А перезапуск без записи вернул бы
    прежний режим.

    Чего эта операция НЕ делает: не создаёт записей (отсутствие домена в
    реестре — отсутствие решения владельца о нём), не придумывает
    идентификатор разрешения (он переписывается из якоря согласия), не
    трогает чужие записи и проверяет результат ЧИТАТЕЛЕМ ПЛОЩАДКИ до подмены
    файла.
    """
    cell = registry.resolve(заявка.site_id)
    площадка = privileged.Площадка.из_реестра(заявка.site_id)
    домен = runtime.размещение(заявка.site_id).domain or ""
    режим = (заявка.mode or "").strip().upper()
    шаги: dict[str, Any] = {}

    файл, источник = indexing_core.путь_реестра(площадка.account)
    if файл is None:
        raise ExecutorError(
            f"{заявка.site_id}: {источник}. Реестр ядра брать негде, а "
            "подставлять путь по соседству нельзя: чужой реестр решает режим "
            "чужих доменов")
    шаги["registry_path"] = {"path": str(файл), "declared_by": источник}

    подкл = indexing_core.связанный_читатель(площадка.account)
    шаги["reader"] = подкл
    if not подкл.get("connected"):
        raise ExecutorError(
            f"{заявка.site_id}: читатель реестра не подключён — "
            f"{подкл.get('reason')}. Запись в реестр ничего бы не изменила: "
            "решение читать нечем")

    согласие = _требовать_согласия(заявка, cell, домен, "реестр ядра семейства")
    шаги["owner_consent"] = согласие

    # Идентификатор разрешения. Для ОТКРЫТИЯ он берётся из якоря согласия —
    # акт владельца, который может создать только root. Для ЗАКРЫТИЯ
    # разрешения не требуется, и прежний идентификатор сохраняется: закрытие
    # не отменяет того, кто когда-то разрешил, и придумывать новое значение
    # было бы подменой записи о решении.
    текущая = indexing_core.запись(файл, домен)
    if режим == "OPEN":
        ид = str(согласие.get("authorization_id") or "")
        if not ид:
            raise ExecutorError(
                f"{заявка.site_id}: якорь согласия не называет идентификатора "
                "разрешения — переписывать в реестр нечего, а придумать его "
                "нельзя")
    else:
        ид = str(текущая.get("owner_authorization_id") or "") or "BOOTSTRAP-CLOSED"

    причина = (f"решение владельца {ид}; применено штатной операцией "
               f"indexing-core по заявке {заявка.request_id}")

    # ВОРОТА ЗАЩИЩЁННЫХ ДАННЫХ. Реестр ядра — постоянные данные сайта
    # (`indexing_core`): писать его вправе только названная операция.
    шаги["protected_data"] = protected.проверить_запись(
        заявка.site_id, домен, файл, операция="indexing_core")

    шаги["registry_write"] = indexing_core.переписать(
        файл, домен, режим=режим, authorization_id=ид, причина=причина,
        аккаунт=площадка.account, dry_run=dry_run)

    # ПЕРЕЗАПУСК. Режим резолвится при импорте, и без него запись осталась бы
    # решением, о котором процесс не знает.
    if dry_run:
        шаги["restart"] = {"planned": f"systemctl restart {площадка.unit}",
                           "dry_run": True}
        return {"status": "applied", "stage": "indexing_core_applied",
                "site_id": заявка.site_id, "domain": домен, "mode": режим,
                "policy_revision": (шаги["registry_write"].get("after") or {}
                                    ).get("policy_revision"),
                "steps": шаги}

    if not шаги["registry_write"].get("changed"):
        шаги["restart"] = {"skipped": "запись не менялась: перезапускать нечего"}
        return {"status": "nothing-to-do", "stage": "indexing_core_applied",
                "site_id": заявка.site_id, "domain": домен, "mode": режим,
                "steps": шаги}

    privileged._systemctl("restart", площадка.unit)
    готовность = privileged.готов(площадка.port, предел=120)
    шаги["restart"] = {"unit": площадка.unit, "port": площадка.port,
                       **готовность}
    if not готовность.get("ready"):
        raise ExecutorError(
            f"{заявка.site_id}: после записи режима {режим} юнит "
            f"{площадка.unit} не ответил на /healthz ({готовность.get('reason')}). "
            "Запись в реестре осталась — операция обязана вернуть её сама")

    # ПРОВЕРКА НА САМОМ ПРИЛОЖЕНИИ. Заголовок читается у процесса, а не у
    # nginx: слой nginx переключает отдельная операция, и смешивать их значило
    # бы объявить режим применённым по чужому запрету.
    шаги["app_header"] = _заголовок_робота(площадка.port)
    запрещает = шаги["app_header"].get("noindex")
    if режим == "OPEN" and запрещает is not False:
        raise ExecutorError(
            f"{заявка.site_id}: реестр переписан и юнит перезапущен, а "
            f"приложение на порту {площадка.port} по-прежнему отдаёт "
            f"X-Robots-Tag {шаги['app_header'].get('value')!r}. Режим не "
            "применён; запись в реестре подлежит возврату")
    if режим == "CLOSED" and запрещает is not True:
        raise ExecutorError(
            f"{заявка.site_id}: реестр переписан и юнит перезапущен, а "
            f"приложение запрет не отдаёт (X-Robots-Tag "
            f"{шаги['app_header'].get('value')!r}): закрытие не применено")

    return {"status": "applied", "stage": "indexing_core_applied",
            "site_id": заявка.site_id, "domain": домен, "mode": режим,
            "policy_revision": (шаги["registry_write"].get("after") or {}
                                ).get("policy_revision"),
            "steps": шаги}


def _заголовок_робота(порт: int) -> dict[str, Any]:
    """Что отдаёт САМО приложение на своём порту. Только чтение."""
    import urllib.error
    import urllib.request
    try:
        запрос = urllib.request.Request(f"http://127.0.0.1:{порт}/",
                                        headers={"Host": "localhost"})
        with urllib.request.urlopen(запрос, timeout=15) as о:
            значение = о.headers.get("X-Robots-Tag")
            тело = о.read(4096).decode("utf-8", "replace")
    except (urllib.error.URLError, OSError, TimeoutError) as ош:
        return {"read": False, "reason": f"{type(ош).__name__}: {ош}"}
    # МЕТА-ТЕГ ИЩЕТСЯ ТЕГОМ, А НЕ ПОДСТРОКОЙ. Слово `noindex` встречается в
    # теле страницы и безобидно: во встроенном JSON приложения есть ключи
    # вида `"noindex":false`, и поиск подстрокой объявил бы запрет там, где
    # его нет. Решение о режиме домена по такому признаку принимать нельзя.
    мета = re.search(
        r'<meta[^>]+name=["\']robots["\'][^>]*content=["\']([^"\']*)["\']',
        тело, re.IGNORECASE)
    значение_меты = (мета.group(1) if мета else "")
    в_мете = "noindex" in значение_меты.lower()
    return {"read": True, "value": значение,
            "meta": значение_меты or None,
            "meta_noindex": в_мете,
            "noindex": bool(значение and "noindex" in значение.lower()) or в_мете}


def _имя_репозитория_для_отчёта(cell) -> str:
    """Имя рабочей копии ДЛЯ ОТЧЁТА. Отчёт не вправе отменить операцию.

    `repo_path` — не поле, а свойство, и оно ВОЗБУЖДАЕТ `RegistryError`, когда
    путь в реестре не записан. Вычислялось это свойство ПОСЛЕ применения слоя,
    поэтому у витрины прямой установки, у которой в реестре исполнителя пути
    нет, операция выглядела так: слой nginx переключён, заявка отвергнута
    словами «у ячейки не записан путь репозитория», откат отвергнут тем же
    самым, и домен объявлен в режиме слоя `UNKNOWN` с требованием немедленного
    разбора. Измерено 2026-10-05 на `an1mego.site`: два результата заявок
    (`animego-02-idx-open`, `animego-02-idx-closed-rst140706`) со статусом
    `rejected` и одной и той же ошибкой, при фактически переключённом слое.

    Слою nginx репозиторий не нужен вовсе — операция названа в
    `ОПЕРАЦИИ_БЕЗ_РЕПОЗИТОРИЯ`. Значит отсутствие пути законно, а падать на
    украшении отчёта нельзя тем более.
    """
    try:
        путь = cell.repo_path
    except registry.RegistryError:
        return ""
    return путь.name if путь else ""


def переключить_слой_индексации(заявка: queue.Заявка, *,
                                dry_run: bool = True) -> dict[str, Any]:
    """Слой индексации в nginx — единственная часть режима, требующая root.

    Почему это операция исполнителя, а не скрипт владельца. Пока слой
    переключался руками, штатной операции открытия домена не существовало:
    редактор не мог довести её до конца, и «открыто» в файле состояния
    расходилось с закрытым доменом. Привилегированная сторона делает ровно то,
    что делал root-скрипт, в том же порядке и с теми же отказами.

    Кода операция не ставит: ни коммита, ни digest ей не нужно. Зато нужен
    режим, и он проверен формой в самой заявке.
    """
    cell = registry.resolve(заявка.site_id)
    домен = runtime.размещение(заявка.site_id).domain or ""
    шаги: dict[str, Any] = {}
    # РАЗРЕШЕНИЕ ВЛАДЕЛЬЦА — на СНЯТИЕ запрета, и спрашивается здесь.
    #
    # Почему не только в `indexing-set`. Заявку в очередь может подать любая
    # сторона, которой доступен каталог заявок; проверка разрешения, живущая
    # только в вызывающей операции, обходится подачей заявки напрямую. Запрет
    # в nginx — один из четырёх слоёв, и снятие его без разрешения владельца
    # остаётся снятием, даже если домен и после этого отдаёт `noindex` от
    # приложения.
    шаги["owner_consent"] = _требовать_согласия(заявка, cell, домен, "слой nginx")
    # ВОРОТА ЗАЩИЩЁННЫХ ДАННЫХ. Слой nginx — тоже постоянные данные сайта
    # (`nginx_indexing` в перечне защищённых путей): переключать его вправе
    # только названная операция, и только у того сайта, который назван.
    шаги["protected_data"] = protected.проверить_запись(
        заявка.site_id, домен,
        nginx_indexing.путь_включаемого(заявка.site_id),
        операция="indexing_nginx")
    шаги["apply"] = privileged.слой_индексации(
        заявка.site_id, mode=заявка.mode, домен=домен, dry_run=dry_run)
    применено = bool(шаги["apply"].get("changed")) or dry_run
    return {"status": "applied" if применено else "nothing-to-do",
            "stage": "indexing_layer_applied",
            "site_id": заявка.site_id, "domain": домен, "mode": заявка.mode,
            "cell_repo": _имя_репозитория_для_отчёта(cell),
            "steps": шаги}


#: Операции, которым собственный репозиторий сайта не нужен.
#:
#: Требование `repo.remote` защищает ВЫКЛАДКУ: сайт, выложенный из
#: монорепозитория, остаётся без своей истории и без отката. К слою индексации
#: это не относится — он не ставит кода, не трогает артефакт и не создаёт
#: версии: правятся конфигурация nginx и включаемый файл режима, и обе величины
#: принадлежат хосту, а не репозиторию. Требовать от него remote значит
#: запрещать управление слоем у зарегистрированной витрины, которую выпускают
#: не из своего репозитория, — причём по признаку, к слою не относящемуся.
#: `owner-consent` репозитория не касается тем же образом: она записывает
#: согласие владельца в каталог root и не ставит ни кода, ни данных. Перечень
#: в очереди я поправил, а ЭТОТ — свой, и забыл: измерено 2026-10-04 на
#: изолированной ячейке, заявка дошла до исполнителя и была отвергнута словами
#: «не записан собственный репозиторий» — по признаку, к согласию не
#: относящемуся. Два перечня с одним смыслом — повод для расхождения, и здесь
#: оно случилось.
ОПЕРАЦИИ_БЕЗ_РЕПОЗИТОРИЯ = ("indexing-nginx", "indexing-core", "owner-consent")

#: Операции, которым не нужно РАЗМЕЩЕНИЕ (куда доставлять, кого
#: перезапускать). `owner-consent` ничего не доставляет: она записывает
#: согласие владельца и берёт домен из реестра ячеек.
ОПЕРАЦИИ_БЕЗ_РАЗМЕЩЕНИЯ = ("owner-consent",)


def проверить_заявку(заявка: queue.Заявка) -> dict[str, Any]:
    """Всё, что можно проверить до единой мутации."""
    try:
        cell = registry.resolve(заявка.site_id)
    except registry.RegistryError as exc:
        raise ExecutorError(
            f"{заявка.site_id}: сайта нет в реестре ячеек — исполнитель работает "
            "только с зарегистрированными сайтами") from exc
    if заявка.operation in ОПЕРАЦИИ_БЕЗ_РЕПОЗИТОРИЯ:
        remote = str((cell.repo or {}).get("remote") or "")
    else:
        remote = registry.require_own_repo(cell)

    # Имя репозитория из заявки — не источник доверия, а повод отказать при
    # расхождении: доверенным остаётся то, что записано в реестре.
    if заявка.repo and заявка.repo.split("/")[-1].removesuffix(".git") not in remote:
        raise ExecutorError(
            f"заявка называет репозиторий {заявка.repo}, а в реестре у "
            f"{заявка.site_id} записан {remote}")

    # РАЗМЕЩЕНИЕ нужно не всякой операции.
    #
    # Оно отвечает на вопросы «куда доставлять» и «кого перезапускать», и для
    # выкладки его отсутствие — повод остановиться. Но `owner-consent` не
    # доставляет и не перезапускает ничего: она записывает согласие владельца
    # в каталог root, а домен берёт из реестра ячеек. Измерено 2026-10-04 на
    # изолированной ячейке `site-a`: заявка отвергалась словами «в реестре нет
    # блока runtime» — по признаку, к согласию не относящемуся, и приёмку на
    # изолированном сайте это делало невозможной.
    if заявка.operation in ОПЕРАЦИИ_БЕЗ_РАЗМЕЩЕНИЯ:
        return {"remote": remote, "runtime": None,
                "note": (f"операции {заявка.operation} размещение не нужно: "
                         "она ничего не доставляет и никого не перезапускает")}
    размещение = runtime.размещение(заявка.site_id)
    if размещение.previous_unit and размещение.unit == размещение.previous_unit:
        raise ExecutorError(
            f"{заявка.site_id}: реестр называет один и тот же юнит текущим и "
            "прежним; исполнять по такому описанию нельзя")
    return {"remote": remote, "runtime": размещение.as_dict()}


#: Имя файла учётных данных, которое юнит получает через LoadCredential.
ФАЙЛ_ТОКЕНА = "gh-token"


class ПроисхождениеНеПодтверждено(ExecutorError):
    """Спросить GitHub не удалось. Это отказ, а не примечание к успеху.

    Раньше здесь возвращалось `checked: false`, и выпуск шёл дальше. Проверка,
    которая отключается сама и никого не останавливает, хуже отсутствующей:
    результат выглядит одинаково и когда происхождение доказано, и когда его
    не спросили. Единственная связка, отделяющая выпуск от произвольного кода,
    не может быть необязательной.
    """


def _окружение_gh() -> dict[str, str]:
    """Учётные данные GitHub для root — из systemd, а не из чьего-то HOME.

    Исполнитель работает от root, у root нет входа в gh. Значение читается из
    каталога учётных данных юнита и никуда не пишется: ни в результат, ни в
    журнал, ни в отчёт.
    """
    окружение = dict(os.environ)
    каталог = окружение.get("CREDENTIALS_DIRECTORY")
    if каталог and not окружение.get("GH_TOKEN"):
        файл = Path(каталог) / ФАЙЛ_ТОКЕНА
        if файл.is_file():
            окружение["GH_TOKEN"] = файл.read_text(encoding="utf-8").strip()
    return окружение


def проверить_доступ(заявка: queue.Заявка, *, remote: str) -> dict[str, Any]:
    """Видит ли ТОКЕН ИСПОЛНИТЕЛЯ репозиторий сайта. Ничего не меняет.

    Права интерактивной сессии и права исполнителя — разные, и разошлись они
    молча: выпуск нового домена отклонялся HTTP 404, пока та же команда из
    сессии читала прогон без ошибок. Проверять доступ «своей рукой» бесполезно,
    поэтому спрашивать надо того, кто будет действовать.

    Ответ 404 у приватного репозитория неотличим от «нет такого репозитория»,
    и это не недостаток проверки, а свойство GitHub: он не раскрывает
    существование того, к чему нет доступа. Поэтому в результат идёт и то, что
    видно без токена, — если без токена тоже 404, а с токеном 200, доступ есть.
    """
    проект = "/".join(remote.rstrip("/").removesuffix(".git").split("/")[-2:])
    окружение = _окружение_gh()
    итог: dict[str, Any] = {
        "operation": "access-check", "site_id": заявка.site_id, "repo": проект,
        "token_available": bool(окружение.get("GH_TOKEN")),
    }
    готово = subprocess.run(
        ["gh", "api", f"repos/{проект}", "--jq", ".full_name,.private"],
        capture_output=True, text=True, env=окружение)
    итог["repo_read"] = готово.returncode == 0
    if готово.returncode != 0:
        итог["repo_error"] = (готово.stderr or "").strip()[:200]
    прогоны = subprocess.run(
        ["gh", "run", "list", "-R", проект, "--limit", "1",
         "--json", "databaseId,conclusion"],
        capture_output=True, text=True, env=окружение)
    итог["actions_read"] = прогоны.returncode == 0
    if прогоны.returncode != 0:
        итог["actions_error"] = (прогоны.stderr or "").strip()[:200]
    else:
        try:
            строки = json.loads(прогоны.stdout or "[]")
            итог["latest_run"] = (строки[0].get("databaseId") if строки else None)
        except ValueError:
            итог["actions_read"] = False
            итог["actions_error"] = "ответ нечитаем"
    # Чтение репозитория без чтения Actions бесполезно: происхождение выпуска
    # проверяется именно по прогону.
    итог["status"] = "checked"
    итог["stage"] = "access_verified" if (итог["repo_read"] and итог["actions_read"]) else "access_missing"
    итог["ok"] = итог["repo_read"] and итог["actions_read"]
    if not итог["ok"]:
        итог["required_input"] = (
            f"выдать токену в /etc/site-factory/gh-token права на чтение "
            f"Contents и Actions для {проект}; у fine-grained токена список "
            "репозиториев не расширяется сам при создании новых")
    return итог


#: Операции, которые ставят на сайт НОВЫЙ исполняемый код. Только им нужна
#: связка с прогоном CI. Доставка данных и откат её не требуют: доставка не
#: зовёт install_release вовсе, а откат возвращает выпуск, происхождение
#: которого доказывали при установке. Требовать прогон от доставки значило бы
#: остановить обновление каталога ради проверки, которой там нечего проверять.
ОПЕРАЦИИ_С_КОДОМ = ("activate",)


def проверить_ci(заявка: queue.Заявка, *, remote: str,
                 операция: str = "activate") -> dict[str, Any]:
    """Прогон CI обязан относиться именно к этому выпуску.

    Один хеш файла не доказывает происхождение: артефакт с тем же digest можно
    собрать где угодно. Доверие даёт связка целиком — РЕПОЗИТОРИЙ из реестра,
    РАЗРЕШЁННАЯ ветка, ТОЧНЫЙ коммит и УСПЕШНЫЙ прогон, — и проверяется она у
    GitHub, а не по словам заявки. Выпадение любого звена означает отказ.

    Репозиторий задаётся ключом `-R`, а не берётся из ответа: иначе прогон из
    чужого проекта с подходящим SHA прошёл бы проверку.
    """
    if операция not in ОПЕРАЦИИ_С_КОДОМ:
        return {"checked": False, "applicable": False,
                "reason": f"операция {операция} не ставит новый код"}
    if not заявка.ci_run:
        raise ПроисхождениеНеПодтверждено(
            f"{заявка.site_id}: заявка не называет прогон CI")
    проект = "/".join(remote.rstrip("/").split("/")[-2:]).removesuffix(".git")
    готово = subprocess.run(
        ["gh", "run", "view", заявка.ci_run, "-R", проект, "--json",
         "headSha,headBranch,conclusion,status,workflowName,databaseId"],
        capture_output=True, text=True, env=_окружение_gh())
    if готово.returncode != 0:
        ошибка = готово.stderr.strip()[:200]
        # 404 на приватный репозиторий почти всегда означает не «прогона нет», а
        # «этот токен его не видит»: у исполнителя свой токен из
        # /etc/site-factory/gh-token, и он не обязан совпадать по доступу с
        # токеном сессии. Сообщение обязано называть причину и действие, иначе
        # отказ читается как «CI не прошёл» и ищут не там: так и вышло при
        # первом выпуске zonafilm12.site — прогон был успешным, а токен
        # исполнителя нового репозитория не видел.
        подсказка = ""
        if "404" in ошибка:
            подсказка = (
                f". Приватный {проект} отвечает 404 и тому, у кого нет доступа: "
                "проверьте, что токен в /etc/site-factory/gh-token видит ЭТОТ "
                "репозиторий (у fine-grained токена репозитории перечислены, и "
                "созданный позже в список не попадает сам)")
        raise ПроисхождениеНеПодтверждено(
            f"{заявка.site_id}: GitHub не ответил про прогон {заявка.ci_run} "
            f"в {проект}: {ошибка}{подсказка}")
    try:
        данные = json.loads(готово.stdout or "{}")
    except ValueError as exc:
        raise ПроисхождениеНеПодтверждено(
            f"{заявка.site_id}: ответ GitHub нечитаем: {exc}") from exc
    if not данные:
        raise ПроисхождениеНеПодтверждено(
            f"{заявка.site_id}: прогона {заявка.ci_run} в {проект} нет")
    if данные.get("status") != "completed":
        raise ExecutorError(
            f"прогон {заявка.ci_run} ещё не завершён ({данные.get('status')!r})")
    if данные.get("conclusion") != "success":
        raise ExecutorError(
            f"прогон {заявка.ci_run} завершился как {данные.get('conclusion')!r}; "
            "выкладывается только проверенный выпуск")
    if (данные.get("headSha") or "") != заявка.commit:
        raise ExecutorError(
            f"прогон {заявка.ci_run} относится к коммиту "
            f"{(данные.get('headSha') or '')[:12]}, а заявка — к {заявка.commit[:12]}. "
            "Зелёный CI на другом коммите ничего не доказывает об этом выпуске")
    ветка = данные.get("headBranch") or ""
    if not registry.ветка_разрешена(ветка):
        raise ExecutorError(
            f"прогон {заявка.ci_run} сделан на ветке {ветка!r}, а выпуск "
            f"разрешён только с {list(registry.ВЕТКИ_ВЫПУСКА)}. Зелёная ветка "
            "эксперимента — не разрешение выложить её на живой сайт")
    return {"checked": True, "repo": проект, "branch": ветка,
            "run": str(данные.get("databaseId") or заявка.ci_run),
            "workflow": данные.get("workflowName"),
            "conclusion": данные.get("conclusion")}


def происхождение_выпусков(*, база: Path | None = None) -> dict[str, Any]:
    """Какой выпуск исполняется у каждой витрины и кем он установлен.

    Исполнитель — не единственный, кто умеет ставить выпуск: в репозитории
    каждой витрины остались `deploy/activate.sh` и `deploy/rollback.sh`, и
    запуск их от root кладёт выпуск мимо очереди. Проверки происхождения
    (разрешённая ветка, точный коммит, успешный прогон) при этом не
    выполняются вовсе.

    Наблюдалось на lords-02: из четырёх выпусков в `releases/` результат
    исполнителя есть ровно у одного, а витрина исполняет тот, которого в
    результатах нет. Снаружи это неотличимо от штатного выпуска — сайт
    отвечает 200 и называет ожидаемый build-id, и следующий триггер честно
    говорит «нечего выкладывать».

    Отменить чужой путь отсюда нельзя — root есть root. Но молчание о нём
    хуже самого обхода: пока он невидим, отчёт «выложено исполнителем»
    описывает не то, что работает. Здесь он становится видимым.
    """
    корень = база or queue.БАЗА
    результаты = корень / "results"
    итог: list[dict[str, Any]] = []
    for site_id in sorted(registry.extracted_sites()):
        try:
            п = privileged.Площадка.из_реестра(site_id)
        except (privileged.PrivilegedRefused, registry.RegistryError) as exc:
            итог.append({"site_id": site_id, "state": "не размещён",
                         "reason": str(exc)[:120]})
            continue
        ссылка = п.current
        текущий = ссылка.resolve().name if ссылка.is_symlink() or ссылка.exists() else None
        # Различаются две вещи, которые легко спутать:
        #   тронутые  — исполнитель этот коммит РАЗВОРАЧИВАЛ, чем бы оно ни
        #               кончилось. Выпуск, поставленный в попытке, которая
        #               потом откатилась, остаётся в releases/ и обходом НЕ
        #               является. На первом же прогоне эта проверка назвала
        #               обходом zona-01/f0d1a9413e1a — ровно такой случай;
        #   успешные  — дошли до конца. Только они годятся в ответ на вопрос
        #               «исполняется ли то, что выпущено штатно».
        тронутые, успешные = set(), set()
        for файл in результаты.glob(f"{site_id}-*.json"):
            try:
                д = json.loads(файл.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            коммит = (д.get("commit") or "")[:12]
            if not коммит:
                continue
            тронутые.add(коммит)
            if д.get("status") == "ok":
                успешные.add(коммит)
        установлены = sorted(p.name for p in п.releases.iterdir()) if п.releases.is_dir() else []
        вне = [r for r in установлены if r not in тронутые]
        итог.append({
            "site_id": site_id, "current": текущий,
            "by_executor": bool(текущий and текущий in успешные),
            "releases_installed": len(установлены),
            "outside_queue": вне,
        })
    обход = [с for с in итог if с.get("outside_queue")]
    return {"sites": итог, "bypassed": [с["site_id"] for с in обход]}


def готовность_проверки() -> dict[str, Any]:
    """Может ли ИСПОЛНИТЕЛЬ спросить GitHub — не может ли это кто-то другой.

    Успешный `gh` у подающей стороны ничего не говорит о службе: у неё другой
    пользователь, другой HOME и учётные данные приходят от systemd. Поэтому
    вопрос задаётся тем же кодом и тем же окружением, каким пойдёт настоящая
    проверка, и по каждому разрешённому репозиторию отдельно — токен может
    открывать один проект и не открывать соседний.

    Ни одного значения токена наружу: возвращается только «да/нет» и причина.
    """
    окружение = _окружение_gh()
    итог: dict[str, Any] = {
        "credentials_directory": bool(os.environ.get("CREDENTIALS_DIRECTORY")),
        "token_available": bool(окружение.get("GH_TOKEN")),
        "sites": [],
    }
    for site_id in sorted(registry.extracted_sites()):
        try:
            cell = registry.resolve(site_id)
            remote = registry.require_own_repo(cell)
        except registry.RegistryError as exc:
            итог["sites"].append({"site_id": site_id, "ready": False,
                                  "reason": str(exc)[:200]})
            continue
        проект = "/".join(remote.rstrip("/").split("/")[-2:]).removesuffix(".git")
        готово = subprocess.run(
            ["gh", "run", "list", "-R", проект, "--limit", "1", "--json", "databaseId"],
            capture_output=True, text=True, env=окружение)
        if готово.returncode != 0:
            итог["sites"].append({"site_id": site_id, "repo": проект, "ready": False,
                                  "reason": готово.stderr.strip()[:200]})
        else:
            итог["sites"].append({"site_id": site_id, "repo": проект, "ready": True})
    итог["ready"] = bool(итог["sites"]) and all(с["ready"] for с in итог["sites"])
    итог["blocked"] = [с["site_id"] for с in итог["sites"] if not с["ready"]]
    return итог


def _засеять_хранилище(site_id: str, *, dry_run: bool) -> dict[str, Any]:
    """Первый выпуск витрины: положить каталог в ЕЁ хранилище.

    Витрина под монолитом читает общий каталог производителя; у выделенной
    ячейки хранилище своё, и при первом выпуске оно пустое. Кандидат в таком
    хранилище не поднимается вовсе — отказывается до первого запроса: «нет
    снимка каталога …: витрине нечего показывать». Проверено сборкой lords-01
    на пустом каталоге данных.

    Прежний сценарий активации делал это копированием из общего каталога; здесь
    то же самое, но проверенным путём снимка. Шаг выполняется ТОЛЬКО когда
    каталога нет: у витрины с наполненным хранилищем данные обновляются
    отдельной операцией, и трогать их выпуском кода нельзя.
    """
    from factory.cell import delivery

    п = privileged.Площадка.из_реестра(site_id)
    # Проверяется ВЕСЬ снимок, а не один каталог. Пятиминутный конвейер
    # доставляет в хранилище ячейки только каталог, как только витрина
    # объявлена управляемой; подробностей он не кладёт. По наличию каталога
    # витрина выглядела бы наполненной, а выложилась бы обеднённой: замерено на
    # сборке lords-01 — с каталогом и подробностями главная отдаёт 48 карточек
    # и 8 ссылок на серии, с одним каталогом 12 карточек и НОЛЬ ссылок на серии.
    # Для посетителя это пропавшие серии, а не «частичные данные».
    # Набор обязательных файлов берётся из контракта САЙТА, а не из общей
    # таблицы. У семейства Yummy подробностей нет в природе, и общий набор
    # отказал бы выпуску на отсутствии файла, которого никто не производит.
    # Путь репозитория — через реестр: он единственный знает, где лежит проект
    # сайта, и `repo_path` уже разрешает его относительно корня установки.
    try:
        репозиторий = registry.resolve(site_id).repo_path
    except (registry.RegistryError, AttributeError):
        репозиторий = None
    контракт = privileged.контракт_данных(
        site_id, площадка=п, репозиторий=репозиторий)
    нехватка = [и for и in (ш.format(site=site_id) for ш in контракт["delivered"])
                if not (п.data / и).is_file()]

    # Пользовательское засевается ОТДЕЛЬНО и независимо от снимка: у витрины
    # может быть наполненный каталог и при этом ни разу не созданная база
    # оценок. Засев идёт один раз и не повторяется — иначе он затирал бы
    # принятые оценки.
    своё = privileged.засеять_пользовательское(
        site_id, Path(delivery.ОБЩИЙ), dry_run=dry_run, площадка=п,
        репозиторий=репозиторий)

    if not нехватка:
        return {"seeded": False, "reason": "хранилище уже наполнено",
                "contract": контракт["source"], "user_writable": своё}
    снимок = privileged.stage_snapshot(site_id, Path(delivery.ОБЩИЙ), dry_run=dry_run)
    повышение = privileged.promote_snapshot(site_id, dry_run=dry_run)
    return {"seeded": True, "missing": нехватка, "contract": контракт["source"],
            "user_writable": своё,
            "stage_snapshot": снимок, "promote_snapshot": повышение}


def активировать(заявка: queue.Заявка, *, файл: Path,
                 dry_run: bool = True) -> dict[str, Any]:
    """Выпуск без остановки работающего сайта и без кода репозитория от root.

    Порядок проверен на стенде с настоящими systemd и nginx:

      1. сборка ПОД УЧЁТНОЙ ЗАПИСЬЮ САЙТА — сборщик это код репозитория, и
         запускать его от root значило бы отдать root тому, кто может туда
         писать; root получает файл и сверяет digest;
      2. распаковка в отдельный выпуск — действующая версия продолжает
         исполнять свой;
      3. прогрев кандидата на отдельном порту, пока старая версия отвечает;
      4. кандидат обязан не просто ответить, а назвать ожидаемый выпуск;
      5. переключение трафика — замена одного файла upstream, nginx -t, reload;
      6. повышение: основная служба переводится на тот же выпуск и забирает
         трафик обратно, кандидат гасится.

    Любой отказ после шага 5 — откат маршрута с проверкой ответом.
    """
    cell = registry.resolve(заявка.site_id)
    try:
        repo = cell.repo_path
    except registry.RegistryError as exc:
        raise ExecutorError(f"{заявка.site_id}: {exc}") from exc
    if not (repo / "tools" / "build_release.py").is_file():
        # Отказ здесь, а не внутри сборки: понятно, что искали и где.
        raise ExecutorError(
            f"{заявка.site_id}: рабочей копии репозитория нет по пути {repo}. "
            f"Основание путей — {registry.корень_репозиториев()}")
    размещение = runtime.размещение(заявка.site_id)
    шаги: dict[str, Any] = {}

    # ВОРОТА ЗАЩИЩЁННЫХ ДАННЫХ. Стоят ПЕРВЫМИ — до подготовки площадки, до
    # засева хранилища и до сборки. Иначе отказ пришёл бы после того, как
    # `prepare` и `seed_data` уже что-то создали.
    #
    # Проверяется одно: умеет ли ВЫПУСКАЕМЫЙ коммит читать то, что редактору
    # уже принадлежит. Выпуск без читателя файлы не испортит, но перестанет их
    # читать — открытый сайт станет закрытым, опубликованные тексты исчезнут
    # со страниц, и со стороны это неотличимо от потери данных.
    шаги["protected_data"] = protected.проверить_выпуск(
        заявка.site_id, размещение.domain or "", repo, заявка.commit)

    # Площадка готовится ДО сборки. Сборщик запускается под учётной записью
    # САЙТА, а создаёт её именно `prepare`: при первом выпуске витрины учётной
    # записи ещё нет, и сборка падала на `getpwnam` раньше, чем что-либо
    # происходило. Проверено на lords-01: учётной записи lordfilm47-space не
    # существует, заявка уходила в бесконечный повтор по таймеру.
    шаги["prepare"] = privileged.prepare(заявка.site_id, dry_run=dry_run)
    шаги["seed_data"] = _засеять_хранилище(заявка.site_id, dry_run=dry_run)

    with tempfile.TemporaryDirectory() as tmp:
        артефакт, манифест = privileged.собрать_без_прав(
            repo, Path(tmp), размещение.account or "nobody")
        if манифест.get("source_commit") != заявка.commit:
            raise ExecutorError(
                f"собран коммит {манифест.get('source_commit', '')[:12]}, "
                f"а заявка о {заявка.commit[:12]}")
        if манифест.get("source_dirty"):
            # Совпадение digest здесь ничего не доказывает: и заявку, и дерево
            # правит одна и та же непривилегированная сторона. Выложить дерево
            # с несохранённой правкой значит выложить то, чего нет в коммите.
            raise ExecutorError(
                f"{заявка.site_id}: рабочая копия {repo} содержит несохранённые "
                f"изменения; выкладывается коммит, а не рабочий стол")
        if манифест.get("digest") != заявка.digest:
            raise ExecutorError(
                f"digest сборки {манифест.get('digest')} не совпал с заявленным "
                f"{заявка.digest}; выкладывается проверенный выпуск или никакой")
        build_id = манифест.get("live_build_id") or ""
        if файл.is_file():
            queue.отметить(файл, "artifact_verified", {"digest": заявка.digest})

        шаги["install_release"] = privileged.install_release(
            заявка.site_id, артефакт, заявка.digest,
            commit=заявка.commit, dry_run=dry_run)
        # Предпроверка обработчика ДО прогрева: выпуск, после которого
        # обработчик обновлений исполнял бы не выложенный код, не выпускается
        # вовсе, а не обнаруживается неделей позже по отсутствующей карте сайта.
        выпуск = (шаги["install_release"] or {}).get("release")
        if выпуск:
            шаги["updater_units"] = privileged.сверить_обработчик(
                заявка.site_id, выпуск=Path(выпуск))
            план = (шаги["updater_units"].get("plan") or {})
            if план.get("действие") == "отказ":
                raise ExecutorError(
                    f"{заявка.site_id}: обработчик обновлений не будет исполнять "
                    f"выложенный код — {план.get('причина')}")

    шаги["warm_up"] = privileged.warm_up(
        заявка.site_id, dry_run=dry_run, ожидаемый_build=build_id)
    прогрет = dry_run or (шаги["warm_up"].get("ready") or {}).get("ready")
    проверен = dry_run or (шаги["warm_up"].get("verify") or {}).get("ok")
    if not (прогрет and проверен):
        # Трафик не переключался: действующая версия и не переставала отвечать.
        шаги["rollback"] = privileged.rollback(заявка.site_id, dry_run=dry_run)
        return {"status": "candidate-failed", "stage": "failed", "steps": шаги,
                "build_id": build_id}
    if файл.is_file():
        queue.отметить(файл, "candidate_ready", {"build_id": build_id})

    порт_кандидата = privileged.Площадка.из_реестра(заявка.site_id).candidate_port
    шаги["switch_route"] = privileged.switch_route(
        заявка.site_id, порт_кандидата, dry_run=dry_run)
    if файл.is_file() and not dry_run:
        queue.отметить(файл, "switched")

    шаги["promote"] = privileged.promote(
        заявка.site_id, dry_run=dry_run, ожидаемый_build=build_id)
    повышено = dry_run or (шаги["promote"].get("verify") or {}).get("ok")
    if not повышено:
        шаги["rollback"] = privileged.rollback(заявка.site_id, dry_run=dry_run)
        return {"status": "rolled-back", "stage": "rolled_back", "steps": шаги,
                "build_id": build_id}

    шаги["verify"] = privileged.verify(заявка.site_id, ожидаемый_build=build_id)
    if not dry_run and not шаги["verify"].get("ok"):
        шаги["rollback"] = privileged.rollback(заявка.site_id, dry_run=False)
        return {"status": "rolled-back", "stage": "rolled_back", "steps": шаги,
                "build_id": build_id}
    обработчик = (шаги["promote"] or {}).get("updater") or {}
    if not dry_run and обработчик.get("declared") and not обработчик.get("ok"):
        # Витрина уже на новом выпуске и исправна, откатывать её незачем. Но
        # «выложено» без обработчика на том же коде — неправда, и итог
        # называет это прямо, а не live_verified.
        return {"status": "activated", "stage": "updater_failed", "steps": шаги,
                "build_id": build_id,
                "error": f"обработчик обновлений не установлен: {обработчик.get('error')}"}
    return {"status": "dry-run" if dry_run else "activated",
            "stage": "validated" if dry_run else "live_verified",
            "steps": шаги, "digest": заявка.digest, "build_id": build_id}


def обновить_данные(заявка: queue.Заявка, *, файл: Path,
                    dry_run: bool = True) -> dict[str, Any]:
    """Обновление каталога тем же прогревом, что и выпуск кода.

    Работающий процесс отдаёт ПРЕЖНИЙ снимок, пока кандидат читает и
    индексирует новый. Раньше снимок подменялся под живым процессом, и на
    время перестроения запросы ждали секундами.

    Повтор того же снимка не делает ничего: «данные не изменились» — это
    законный исход, а не повод поднимать кандидата на четыре минуты.
    """
    from factory.cell import delivery

    размещение = runtime.размещение(заявка.site_id)
    шаги: dict[str, Any] = {}
    источник = Path(delivery.ОБЩИЙ)

    шаги["stage_snapshot"] = privileged.stage_snapshot(
        заявка.site_id, источник, dry_run=dry_run)
    if шаги["stage_snapshot"].get("unchanged"):
        return {"status": "unchanged", "stage": "live_verified", "steps": шаги}

    п = privileged.Площадка.из_реестра(заявка.site_id)
    шаги["warm_up"] = privileged.warm_up(
        заявка.site_id, dry_run=dry_run, данные=п.data_candidate)
    прогрет = dry_run or (шаги["warm_up"].get("ready") or {}).get("ready")
    if not прогрет:
        шаги["rollback"] = privileged.rollback(заявка.site_id, dry_run=dry_run)
        return {"status": "candidate-failed", "stage": "failed", "steps": шаги}
    if файл.is_file():
        queue.отметить(файл, "candidate_ready", {"data": True})

    шаги["switch_route"] = privileged.switch_route(
        заявка.site_id, п.candidate_port, dry_run=dry_run)
    шаги["promote_snapshot"] = privileged.promote_snapshot(
        заявка.site_id, dry_run=dry_run)
    шаги["promote"] = privileged.promote(
        заявка.site_id, dry_run=dry_run,
        ожидаемый_build=(размещение.as_dict().get("build_id") or ""))
    повышено = dry_run or (шаги["promote"].get("ready") or {}).get("ready")
    if not повышено:
        шаги["rollback"] = privileged.rollback(заявка.site_id, dry_run=dry_run)
        return {"status": "rolled-back", "stage": "rolled_back", "steps": шаги}

    шаги["verify"] = privileged.verify(заявка.site_id)
    if not dry_run and not шаги["verify"].get("ok"):
        шаги["rollback"] = privileged.rollback(заявка.site_id, dry_run=False)
        return {"status": "rolled-back", "stage": "rolled_back", "steps": шаги}
    return {"status": "dry-run" if dry_run else "delivered",
            "stage": "validated" if dry_run else "live_verified", "steps": шаги}


def применить_правки(заявка: queue.Заявка, *, dry_run: bool = True) -> dict[str, Any]:
    """Правки редактора: подготовлены управляющим слоем, применяет исполнитель.

    Заявка не несёт ни путей, ни содержимого — схема закрытая. Путь
    подготовленного выводится из `site_id` обеими сторонами по одному правилу,
    а `digest` доказывает, что применено ИМЕННО подготовленное: не «файл по
    такому-то пути», а конкретное содержимое. Расхождение — отказ до записи.

    Перезапуск витрины не нужен: файл перечитывается по mtime тем же способом,
    что снимок каталога. Поэтому здесь нет ни прогрева кандидата, ни
    переключения маршрута — их отсутствие не упрощение, а следствие того, что
    код не меняется.
    """
    from factory.cell import editorial_store

    try:
        содержимое = editorial_store.прочитать_подготовленное(заявка.site_id)
    except editorial_store.StoreRejected as ош:
        raise ExecutorError(f"{заявка.site_id}: {ош}") from None
    факт = editorial_store.отпечаток(содержимое)
    if факт != заявка.digest:
        raise ExecutorError(
            f"{заявка.site_id}: digest подготовленных правок {факт} не совпал "
            f"с заявленным {заявка.digest}; применено не будет")
    шаг = privileged.применить_правки(заявка.site_id, содержимое, dry_run=dry_run)
    return {"status": "dry-run" if dry_run else "edited",
            "stage": "validated" if dry_run else "live_verified",
            "steps": {"apply_overrides": шаг}}


def выполнить(заявка: queue.Заявка, *, база: Path, dry_run: bool = True) -> dict[str, Any]:
    """Одна операция целиком, с журналом переходов."""
    файл = база / "requests" / f"{заявка.request_id}.json"
    результат: dict[str, Any] = {"request_id": заявка.request_id,
                                 "site_id": заявка.site_id,
                                 "operation": заявка.operation,
                                 "commit": заявка.commit,
                                 "dry_run": dry_run,
                                 "started_at": _сейчас()}
    замок = None
    try:
        проверено = проверить_заявку(заявка)
        if файл.is_file():
            queue.отметить(файл, "validated", {"remote": проверено["remote"]})
        результат["runtime"] = проверено["runtime"]

        результат["ci"] = проверить_ci(заявка, remote=проверено["remote"],
                                       операция=заявка.operation)

        замок = взять_замок(заявка.site_id, база=база, операция=заявка.operation)
        результат["lock"] = замок.владелец

        if заявка.operation == "access-check":
            итог = проверить_доступ(заявка, remote=проверено["remote"])
            результат["outcome"] = итог
            этап = итог["stage"]
        elif заявка.operation == "activate":
            итог = активировать(заявка, файл=файл, dry_run=dry_run)
            результат["outcome"] = итог
            этап = итог["stage"]
        elif заявка.operation == "deliver":
            итог = обновить_данные(заявка, файл=файл, dry_run=dry_run)
            результат["outcome"] = итог
            этап = итог["stage"]
        elif заявка.operation == "editorial":
            итог = применить_правки(заявка, dry_run=dry_run)
            результат["outcome"] = итог
            этап = итог["stage"]
        elif заявка.operation == "indexing-nginx":
            итог = переключить_слой_индексации(заявка, dry_run=dry_run)
            результат["outcome"] = итог
            этап = итог["stage"]
        elif заявка.operation == "indexing-core":
            итог = переключить_ядро_индексации(заявка, dry_run=dry_run)
            результат["outcome"] = итог
            этап = итог["stage"]
        elif заявка.operation == "owner-consent":
            итог = зарегистрировать_согласие(заявка, dry_run=dry_run)
            результат["outcome"] = итог
            этап = итог["stage"]
        else:
            raise ExecutorError(
                f"операция {заявка.operation} ещё не реализована исполнителем; "
                "объявлять её выполненной нельзя")

        if файл.is_file():
            queue.отметить(файл, этап, {"dry_run": dry_run})
        # Откат отрабатывает без исключения, но выпуска не было. Называть это
        # `ok` значит объявить применённым то, что откатили.
        применено = (итог.get("status") in queue.ПРИМЕНЁННЫЕ_ИСХОДЫ
                     if isinstance(итог, dict) else False)
        результат["status"] = "ok" if применено else "failed"
    except (ExecutorError, privileged.PrivilegedRefused, protected.ЗащитаДанных,
            registry.RegistryError) as exc:
        результат["status"] = "rejected"
        результат["error"] = str(exc)
        if файл.is_file():
            queue.отметить(файл, "failed", {"error": str(exc)[:500]})
    except Exception as exc:   # noqa: BLE001 — см. ниже, это не «на всякий случай»
        # Заявка, на которой исполнитель падает непредвиденно, остаётся в
        # очереди без результата — и таймер повторяет её каждую минуту вечно.
        # Наблюдалось на lords-01: сборка под несуществующей учётной записью
        # давала KeyError, заявка переписывалась раз в минуту, результата не
        # появлялось, и снаружи это выглядело как «операция идёт».
        #
        # Широкий перехват здесь не прячет ошибку, а наоборот: без него она
        # видна только в журнале службы, а с ним — в результате, который читает
        # подающая сторона. Тип исключения называется явно.
        результат["status"] = "rejected"
        результат["error"] = f"непредвиденный отказ {type(exc).__name__}: {exc}"
        if файл.is_file():
            queue.отметить(файл, "failed", {"error": результат["error"][:500]})
    finally:
        if замок is not None:
            замок.снять()
        результат["finished_at"] = _сейчас()
    return результат


def обслужить_очередь(*, база: Path | None = None, dry_run: bool = True,
                      предел: int = 10) -> list[dict[str, Any]]:
    """Разобрать накопившиеся заявки. Порядок — по времени появления."""
    корень = база or queue.БАЗА
    очередь = корень / "requests"
    if not очередь.is_dir():
        return []
    итоги = []
    for файл in sorted(очередь.glob("*.json"), key=lambda p: p.stat().st_mtime)[:предел]:
        try:
            заявка = queue.разобрать(json.loads(файл.read_text(encoding="utf-8")))
        except (queue.RequestRejected, ValueError) as exc:
            итоги.append({"request_id": файл.stem, "status": "rejected",
                          "error": str(exc)})
            queue.записать_атомарно(корень / "results" / файл.name,
                                    итоги[-1])
            файл.unlink()
            continue
        итог = выполнить(заявка, база=корень, dry_run=dry_run)
        queue.записать_атомарно(корень / "results" / файл.name, итог)
        # Заявка уходит из очереди только после записи результата: обратный
        # порядок терял бы операцию при гибели процесса между двумя шагами.
        файл.unlink()
        итоги.append(итог)
    return итоги


def ждать(*, база: Path | None = None, интервал: float = 5.0,
          dry_run: bool = True, циклов: int = 0) -> None:
    """Цикл службы. `циклов=0` — до остановки."""
    сделано = 0
    while циклов == 0 or сделано < циклов:
        обслужить_очередь(база=база, dry_run=dry_run)
        сделано += 1
        if циклов and сделано >= циклов:
            break
        time.sleep(интервал)
