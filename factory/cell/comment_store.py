"""Подготовка редакционного комментария между управляющим слоем и ячейкой.

Зачем это нужно отдельно от редакционных правок. Правки (`editorial_store`) —
это НАШ файл в хранилище витрины: его целиком пишет фабрика, и перезапись
прежнего значения ничего чужого не теряет. Комментарии устроены наоборот: они
лежат в одном хранилище с сообщениями ПОСЕТИТЕЛЕЙ (`src/community.py` ячейки),
и всякая запись туда — это изменение файла, большая часть которого принадлежит
не нам. Поэтому заявка несёт не файл, а ОДНУ запись, а применяет её не наша
запись в JSON, а тот самый модуль ячейки, который пишет сообщения посетителей:
формат, блокировка, предел длины и защита от повторов остаются его работой.

Путь тот же, что у правок, и по той же причине:

    редактор → черновик в подготовительном каталоге управляющего слоя
             → заявка в очередь (site_id, коммит выпуска, digest содержимого)
             → исполнитель читает подготовленное, сверяет digest, добавляет
               ОДНУ запись модулем ячейки от имени учётной записи сайта

Что НЕ умеет эта подготовка, и это главное свойство: ни удалить, ни изменить
чужое сообщение, ни переписать хранилище целиком. В содержимом нет ни
идентификатора существующей записи, ни пути к файлу — назвать чужое сообщение
в заявке технически нечем.

Автор у записи один — «Редакция». Имя посетителя подставить нельзя: сообщение
от лица выдуманного зрителя — это именно то, что запрещено правилами
редактуры, и запрет держится здесь формой данных, а не внимательностью.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any

#: Подготовительный каталог управляющего слоя. Витрина сюда не смотрит.
#: Рядом с каталогом правок и с теми же правами: это тот же слой.
БАЗА = Path(os.environ.get("SITE_COMMENT_STAGING", "/var/lib/site-cells/comments"))

СХЕМА = 1

#: Единственный допустимый автор. Проверяется и здесь, и на стороне
#: исполнителя: подпись решает, кем выглядит сообщение на странице.
АВТОР = "Редакция"

#: Предел длины. Совпадает с `ДЛИНА_КОММЕНТАРИЯ` модуля ячейки: подготовить
#: текст, который витрина потом откажется принять, значит отложить отказ до
#: момента записи вместо отказа при подготовке.
ДЛИНА = 1200


class StoreRejected(Exception):
    """Подготовка отвергнута до записи."""


def путь_подготовки(site_id: str, *, база: Path | None = None) -> Path:
    if not site_id or "/" in site_id or site_id.startswith("."):
        raise StoreRejected(f"негодный site_id: {site_id!r}")
    return (база or БАЗА) / f"{site_id}.json"


#: Что делает заявка. `publish` добавляет запись, `retract` прячет СВОЮ уже
#: опубликованную (статус `rejected` — ровно то, чем модерация ячейки убирает
#: сообщение со страницы).
#:
#: Зачем снятие вообще есть. Публикация, которую нечем снять, необратима, а
#: необратимая публикация — это то, на чём уже обожглись: первая же ошибочная
#: запись в комментариях Yummy оказалась неудаляемой, потому что маршрута
#: снятия не было. Поэтому обратный путь появляется ВМЕСТЕ с прямым, а не
#: после первой ошибки.
ДЕЙСТВИЯ = ("publish", "retract")


def собрать(site_id: str, *, slug: str, текст: str = "", actor: str,
            reason: str, sources: list[str] | None = None,
            действие: str = "publish",
            comment_id: str = "") -> dict[str, Any]:
    """Содержимое подготовленной заявки. Чистая функция: ничего не пишет.

    `slug` — публичный адрес карточки. Ключ темы по нему вычисляет сторона
    ячейки по своему правилу (`details[slug].id`), а не мы: адрес может
    смениться, и ключ, посчитанный здесь, указывал бы на другую тему.
    """
    if действие not in ДЕЙСТВИЯ:
        raise StoreRejected(f"действие {действие!r}; разрешены {list(ДЕЙСТВИЯ)}")
    слаг = (slug or "").strip().strip("/")
    if not слаг or "/" in слаг:
        raise StoreRejected(f"негодный slug карточки: {slug!r}")
    тело = " ".join((текст or "").split())
    ид = (comment_id or "").strip()
    if действие == "publish":
        if not тело:
            raise StoreRejected("пустой комментарий не публикуется")
        if len(тело) > ДЛИНА:
            raise StoreRejected(f"комментарий длиннее {ДЛИНА} знаков: {len(тело)}")
        if ид:
            raise StoreRejected("comment_id при публикации не принимается: "
                                "идентификатор выдаёт модуль ячейки, а не мы")
    else:
        if not ид or not ид.isalnum():
            raise StoreRejected(
                f"снятие называет идентификатор СВОЕЙ записи; получено {comment_id!r}")
        тело = ""
    if not (reason or "").strip():
        raise StoreRejected("заявка без причины не принимается: журнал без "
                            "причины отвечает «что», но не «почему»")
    if not (actor or "").strip():
        raise StoreRejected("не назван actor: запись без автора операции "
                            "непроверяема")
    return {"schema_version": СХЕМА, "site_id": site_id, "slug": слаг,
            "action": действие, "comment_id": ид,
            "author": АВТОР, "text": тело, "actor": actor.strip(),
            "reason": reason.strip(),
            "sources": [и for и in (sources or []) if str(и).strip()]}


def текст(содержимое: dict[str, Any]) -> str:
    """Каноническая запись: отсортированные ключи, перевод строки в конце."""
    return json.dumps(содержимое, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":")) + "\n"


def отпечаток(содержимое: dict[str, Any]) -> str:
    """sha256 канонической записи. Тот же байт-в-байт текст и прочитается."""
    return "sha256:" + hashlib.sha256(текст(содержимое).encode("utf-8")).hexdigest()


def подготовить(site_id: str, *, slug: str, текст_комментария: str = "",
                actor: str, reason: str, sources: list[str] | None = None,
                действие: str = "publish", comment_id: str = "",
                база: Path | None = None) -> dict[str, Any]:
    """Положить черновик в подготовительный каталог и вернуть его digest."""
    содержимое = собрать(site_id, slug=slug, текст=текст_комментария,
                         actor=actor, reason=reason, sources=sources,
                         действие=действие, comment_id=comment_id)
    путь = путь_подготовки(site_id, база=база)
    путь.parent.mkdir(parents=True, exist_ok=True)
    врем = путь.with_suffix(".json.new")
    врем.write_text(текст(содержимое), encoding="utf-8")
    os.replace(врем, путь)
    return {"site_id": site_id, "path": str(путь), "digest": отпечаток(содержимое),
            "slug": содержимое["slug"], "action": содержимое["action"],
            "comment_id": содержимое["comment_id"],
            "length": len(содержимое["text"])}


def прочитать_подготовленное(site_id: str, *, база: Path | None = None) -> dict[str, Any]:
    путь = путь_подготовки(site_id, база=база)
    if not путь.is_file():
        raise StoreRejected(f"подготовленного комментария для {site_id} нет")
    try:
        содержимое = json.loads(путь.read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        raise StoreRejected(f"подготовленное не читается: {ош}") from None
    if содержимое.get("site_id") != site_id:
        # Чужой файл в своём месте — это не опечатка, а перепутанная область.
        raise StoreRejected(
            f"подготовлено для сайта {содержимое.get('site_id')!r}, "
            f"а применяется к {site_id!r}")
    if содержимое.get("author") != АВТОР:
        raise StoreRejected(
            f"автор подготовленного — {содержимое.get('author')!r}; "
            f"публикуется только от имени {АВТОР!r}")
    return содержимое
