"""Подтверждение ВЛАДЕЛЬЦА на открытие домена — якорь, который не подделать.

Зачем понадобилось
------------------
Разрешение владельца жило одним полем реестра ячеек
(`cells[].indexing.open_authorized`). Писателя у этого поля в фабрике не было
вовсе: задать его можно было только правкой `config/site-cells.json` руками.
А сам файл принадлежит учётной записи, под которой работают инструменты
(`claude`, режим `rw-------`) — то есть флаг в реестре НЕ доказывает, что
разрешение дал владелец. Его могла поставить любая сторона, которой доступен
этот файл, включая модель. Проверка, которую проверяемый может выполнить сам,
защитой не является.

Что здесь добавлено
-------------------
Второй, независимый факт: файл подтверждения в каталоге, который принадлежит
root и недоступен на запись никому другому
(`/var/lib/site-cells/owner-consent/<домен>.json`, root:root, 0444). Создать
его может только root — то есть владелец через свою единственную команду
(`automation/host/authorize-indexing.sh`). Прочитать его может кто угодно,
поэтому проверка работает и из инструмента, запущенного от `claude`.

Разрешение считается данным, только когда СОВПАДАЮТ оба факта: объявление в
реестре и подтверждение root. Флаг без подтверждения — не разрешение, и
причина называется прямо. Подтверждение без флага — тоже: реестр остаётся
местом, где объявлено решение, а файл — доказательством его происхождения.

Разделение разрешений сохраняется: это разрешение ВЛАДЕЛЬЦА. Разрешение
ВЫПУСКА (`config/site.json: indexing.release_permits_open`) живёт в выпуске и
этим файлом не выдаётся.
"""
from __future__ import annotations

import json
import os
import pathlib
import re
from typing import Any

#: Каталог подтверждений. root:root, 0755 — читать может кто угодно, писать
#: только root. Переопределяется только для проверок.
КОРЕНЬ = pathlib.Path(os.environ.get(
    "SITE_CELLS_OWNER_CONSENT_ROOT", "/var/lib/site-cells/owner-consent"))

СХЕМА = 1

#: Домен в имени файла: буквы, цифры, точка и дефис. Всё остальное — не домен,
#: и подставлять его в путь нельзя.
ДОМЕН_ОК = re.compile(r"^[a-z0-9][a-z0-9.-]{1,252}[a-z0-9]$")


def путь(домен: str, *, корень: pathlib.Path | None = None) -> pathlib.Path:
    """Файл подтверждения этого домена. Имя файла — сам домен."""
    чистый = (домен or "").strip().lower()
    if not ДОМЕН_ОК.match(чистый):
        raise ValueError(f"домен {домен!r} не похож на домен: путь не строится")
    return (корень or КОРЕНЬ) / f"{чистый}.json"


def _права(п: pathlib.Path) -> tuple[bool, str]:
    """Принадлежит ли файл root и закрыт ли он на запись для остальных."""
    try:
        св = п.stat()
    except OSError as ош:
        return False, f"{п}: {type(ош).__name__}"
    if св.st_uid != 0:
        return False, (f"{п} принадлежит uid {св.st_uid}, а не root: такой файл "
                       "мог создать не владелец")
    if св.st_mode & 0o022:
        return False, (f"{п} открыт на запись группе или всем "
                       f"({oct(св.st_mode & 0o777)}): подтверждение, которое "
                       "можно переписать, доказательством не является")
    return True, ""


def прочитать(домен: str, *, корень: pathlib.Path | None = None
              ) -> tuple[dict[str, Any] | None, str]:
    """Запись подтверждения или причина, почему её нет."""
    try:
        п = путь(домен, корень=корень)
    except ValueError as ош:
        return None, str(ош)
    if not п.exists():
        return None, (f"подтверждения владельца нет: файла {п} не существует. "
                      "Его создаёт только команда владельца "
                      "automation/host/authorize-indexing.sh")
    if not п.is_file():
        return None, f"{п} не обычный файл"
    ок, беда = _права(п)
    if not ок:
        return None, беда
    try:
        данные = json.loads(п.read_text(encoding="utf-8"))
    except (OSError, ValueError) as ош:
        return None, f"{п} не читается как JSON: {type(ош).__name__}"
    if not isinstance(данные, dict):
        return None, f"{п}: ожидался объект JSON"
    return данные, ""


def проверить(site_id: str, домен: str, *, корень: pathlib.Path | None = None
              ) -> tuple[bool, str, dict[str, Any]]:
    """(подтверждено ли, причина, запись).

    Проверяется не только наличие файла: запись обязана называть ТОТ ЖЕ сайт и
    ТОТ ЖЕ домен. Подтверждение одного домена не открывает другой — иначе один
    файл стал бы разрешением на сеть.
    """
    данные, беда = прочитать(домен, корень=корень)
    if данные is None:
        return False, беда, {}
    if int(данные.get("schema_version") or 0) != СХЕМА:
        return False, (f"версия схемы подтверждения "
                       f"{данные.get('schema_version')!r}, ожидается {СХЕМА}"), данные
    if данные.get("authorized") is not True:
        return False, (f"в подтверждении authorized = "
                       f"{данные.get('authorized')!r}: разрешением считается "
                       "только булево true"), данные
    чей_домен = str(данные.get("domain") or "").strip().lower()
    чей_сайт = str(данные.get("site_id") or "").strip()
    if чей_домен != (домен or "").strip().lower():
        return False, (f"подтверждение выдано домену {чей_домен!r}, а читает "
                       f"его {домен!r}: чужое подтверждение не применяется"), данные
    if чей_сайт and site_id and чей_сайт != site_id:
        return False, (f"подтверждение выдано сайту {чей_сайт!r}, а читает его "
                       f"{site_id!r}"), данные
    кем = str(данные.get("by") or "неизвестно")
    когда = str(данные.get("at") or "без времени")
    return True, (f"подтверждено владельцем: {кем}, {когда}, "
                  f"идентификатор {данные.get('id') or 'без идентификатора'}"), данные


def сведения(домен: str, *, корень: pathlib.Path | None = None) -> dict[str, Any]:
    """Короткая справка для вердикта и отчётов. Значений секретов тут нет."""
    данные, беда = прочитать(домен, корень=корень)
    try:
        п = str(путь(домен, корень=корень))
    except ValueError:
        п = ""
    if данные is None:
        return {"present": False, "path": п, "reason": беда}
    return {"present": True, "path": п,
            "by": данные.get("by"), "at": данные.get("at"),
            "id": данные.get("id"), "site_id": данные.get("site_id"),
            "note": данные.get("note")}
