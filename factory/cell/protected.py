"""Постоянные данные сайта, переданного редактору: запрет на их изменение.

Что защищается и почему именно это
----------------------------------

После передачи сайта редактору (Qwen) часть состояния перестаёт принадлежать
выпуску. Её создал не сборщик и не установщик, её нельзя вывести из шаблона, и
восстановить её из старой копии значит отменить чужую работу:

* **состояние индексации** — `/srv/sites/indexing/<домен>.json`. Один файл
  решает, открыт сайт для обхода или закрыт. Перезапись шаблонным значением
  закрыла бы открытый сайт молча;
* **журнал и снимки режима** — `/srv/sites/indexing/_log/`. По ним делается
  адресный откат; без них откатывать нечего;
* **редакционные материалы** — каталог домена в хранилище наложений:
  опубликованные тексты, черновики, снятое с публикации, журнал операций и
  `last-good`. Это написанный текст, а не производное от каталога;
* **слой индексации nginx** — `/etc/nginx/cells/<site_id>.robots`. Строка
  `default` в нём отличает открытый сайт от закрытого.

Чтение для диагностики разрешено и ничем не ограничено. Запрещены именно
запись, удаление, очистка, переинициализация и восстановление из прежних
копий.

Что НЕ даёт разрешения
----------------------

Обновление шаблона, исправление ошибки, повторный деплой, откат выпуска,
отсутствие файла и несовпадение схемы. Ни одно из этих событий не является
поводом тронуть защищённые данные: отсутствующий файл означает «данных нет», а
не «можно создать шаблонные», а несовпадение схемы означает «выпуск не умеет
их читать», а не «их пора переписать».

Первичная инициализация допускается РОВНО ОДИН РАЗ — при создании сайта, пока
защищённых данных ещё нет ни одного файла. Как только появился первый, сайт
считается переданным, и повторная инициализация запрещена. Признак передачи
выводится из факта на диске, а не из отдельного флага: флаг разошёлся бы с
действительностью, а файл — это и есть действительность.

Несовместимый выпуск останавливается ДО активации
-------------------------------------------------

Выпуск, в котором нет читателя защищённых данных, активировать нельзя: он не
сломает файлы, но перестанет их читать, и это выглядит ровно как их потеря.
Открытый сайт стал бы закрытым, опубликованные тексты исчезли бы со страниц.
Поэтому проверка смотрит, что выпускаемый коммит несёт читателя для каждого
вида присутствующих данных, и отказывает до сборки.

Исключение — только по поручению владельца
------------------------------------------

Исключение объявляется переменной окружения `SITE_PROTECTED_DATA_EXCEPTION`, в
которой названы сайт, конкретные файлы и разрешённое изменение. Claude не
может объявить исключение сам: переменную выставляет тот, кто запускает
операцию, и в журнал попадает её содержимое целиком. Исключение без имён
файлов, без сайта или с подстановочным знаком не принимается — «разрешено всё»
это не исключение, а отмена запрета.
"""
from __future__ import annotations

import json
import os
import pathlib
import subprocess
from typing import Any

#: Корень состояния индексации. То же значение, что у операции редактора
#: (`factory.qwen.indexing.КОРЕНЬ`) и у читателя витрины
#: (`src/indexing_mode.py: КОРЕНЬ`). Совпадение закрепляет тест: расхождение
#: означало бы, что защищается не то, что читается.
КОРЕНЬ_ИНДЕКСАЦИИ = pathlib.Path(
    os.environ.get("QWEN_INDEXING_ROOT", "/srv/sites/indexing"))

#: Куда исполнитель пишет включаемый файл слоя nginx.
КОРЕНЬ_NGINX_ЯЧЕЕК = pathlib.Path(
    os.environ.get("SITE_NGINX_UPSTREAMS", "/etc/nginx/cells"))

#: Переменная исключения. Содержимое — JSON с полями `site`, `files`, `change`.
ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ = "SITE_PROTECTED_DATA_EXCEPTION"

#: Где хранится ОТМЕТКА о завершённой инициализации. Вне выпусков и вне
#: каталога данных сайта: отметка обязана переживать и смену выпуска, и смену
#: версии шаблона, и очистку хранилища.
#:
#: Зачем отметка, если есть сами данные. Признак «файла сейчас нет» для
#: разрешения повторной инициализации НЕДОСТАТОЧЕН: пропавший файл у уже
#: созданного сайта означает утрату, а не новый сайт, и подстановка шаблонных
#: значений в этот момент — худшее из возможных действий. Отметка отличает
#: «ещё не создавали» от «создавали, а данных нет».
КОРЕНЬ_ОТМЕТОК = pathlib.Path(
    os.environ.get("SITE_OWNERSHIP_MARKERS", "/srv/sites/ownership"))

#: Производные файлы: их пересобирают штатные службы, и защищать их нельзя —
#: иначе остановится обновление каталога, кешей и карты сайта. Перечень по
#: ИМЕНИ, а не по каталогу: каталог данных целиком замораживать запрещено.
ПРОИЗВОДНЫЕ = ("sitemap",)

#: Читатели, без которых выпуск не умеет работать с данным видом данных.
#: Путь — внутри репозитория сайта; проверяется в ВЫПУСКАЕМОМ коммите.
ЧИТАТЕЛИ = {
    "indexing_state": ("src/indexing_mode.py",),
    "indexing_journal": (),           # журнал читает инструмент, не витрина
    # Имя читателя правок у семейств РАЗНОЕ: Animedia читает наложения
    # `seo_overlay.py`, витрины на общем рантайме Lords — `editorial_overlay.py`,
    # а у Yummy материал читает приложение в контейнере, и в репозитории ячейки
    # читателя нет вовсе. Этот перечень — последний рубеж для РАСПОЗНАННОГО
    # семейства: требовать у Lords файл Animedia значило бы блокировать
    # исправный выпуск, а не защищать данные.
    "editorial": ("src/seo_overlay.py", "src/editorial_overlay.py"),
    "nginx_indexing": (),             # слой nginx витрина не читает
    "site_declared": (),              # читает сама витрина, отдельного нет
}

#: Читатель правок в выпуске — по семейству рантайма. Пустая строка означает,
#: что читателя в репозитории ячейки нет по устройству семейства.
ЧИТАТЕЛЬ_ПРАВОК = {
    "animedia": "src/seo_overlay.py",
    "lords": "src/editorial_overlay.py",
    "animego": "src/editorial_overlay.py",
    "zona-serve": "src/editorial_overlay.py",
    "yummy": "",
}


class ЗащитаДанных(Exception):
    """Операция остановлена ДО изменения защищённых данных."""


def _корни_наложений() -> dict[str, str]:
    """Корни хранилищ редакционных материалов — из одного места с инструментом.

    Импорт отложенный и дешёвый: в модуле реестра на уровне модуля только
    константы. Копировать перечень сюда нельзя — второй список разошёлся бы с
    первым, и защищался бы каталог, в который никто не пишет.
    """
    from factory.qwen import registry as _р
    return dict(_р.КОРНИ_ХРАНИЛИЩ)


def _контрактные(site_id: str) -> list[pathlib.Path]:
    """Файлы, объявленные САМИМ САЙТОМ как принадлежащие не выпуску.

    Источник — `config/site.json: data_contract.user_writable` выпущенного
    кода. Это уже существующий контракт, и перечислять те же имена вторым
    списком здесь значило бы завести расхождение: у Yummy это база оценок, у
    Zona — `editorial-overrides.json` и каталог сообщества, у AnimeGo —
    состояние серий и просмотров. Ни одно из этих имён не выдумано.

    Производные имена (`ПРОИЗВОДНЫЕ`) исключаются: карту сайта пересобирает
    штатная служба, и защита остановила бы её.
    """
    try:
        from factory.cell import privileged as _пр
        п = _пр.Площадка.из_реестра(site_id)
        контракт = _пр.контракт_данных(site_id, площадка=п)
    except Exception:  # noqa: BLE001 — нет реестра или площадки: контракта нет
        return []
    итог: list[pathlib.Path] = []
    for шаблон in контракт.get("user_writable") or ():
        имя = шаблон.format(site=site_id)
        if имя in ПРОИЗВОДНЫЕ:
            continue
        итог.append(п.data / имя)
    return итог


def пути(site_id: str, домен: str, *, adapter: str = "") -> dict[str, list[pathlib.Path]]:
    """Что именно защищено у этого сайта, по видам.

    `adapter` сужает поиск хранилища материалов; без него проверяются корни
    ВСЕХ семейств — иначе каталог, лежащий не там, где ожидали, остался бы
    без защиты.
    """
    итог: dict[str, list[pathlib.Path]] = {
        "indexing_state": [КОРЕНЬ_ИНДЕКСАЦИИ / f"{домен}.json"] if домен else [],
        # Журнал и снимки режима ОБЩИЕ на все сайты: каталог один, а файлы в
        # нём названы доменом. Защищается каталог целиком, а признаком
        # передачи ЭТОГО сайта служат только его собственные файлы — иначе
        # первый же сайт сделал бы «переданными» все остальные, включая
        # несозданные.
        "indexing_journal": [КОРЕНЬ_ИНДЕКСАЦИИ / "_log"],
        "editorial": [],
        "nginx_indexing": ([КОРЕНЬ_NGINX_ЯЧЕЕК / f"{site_id}.robots"]
                           if site_id else []),
        # Объявленное самим сайтом: данные посетителей, оценки, правки
        # редактора у семейств Lords и Zona, состояние серий у AnimeGo.
        "site_declared": _контрактные(site_id) if site_id else [],
    }
    if домен:
        корни = _корни_наложений()
        выбранные = ([корни[adapter]] if adapter in корни else list(корни.values()))
        for корень in выбранные:
            итог["editorial"].append(pathlib.Path(корень) / домен)
    return итог


def существующие(site_id: str, домен: str, *, adapter: str = "") -> dict[str, list[str]]:
    """Какие защищённые данные ФАКТИЧЕСКИ есть. Это и есть признак передачи."""
    итог: dict[str, list[str]] = {}
    for вид, список in пути(site_id, домен, adapter=adapter).items():
        есть = []
        if вид == "indexing_journal":
            # Общий каталог: ищем снимки и записи ИМЕННО этого домена.
            for п in список:
                свои = sorted(str(ф) for ф in п.glob(f"{домен}.*")) if домен else []
                журнал = п / "operations.jsonl"
                if журнал.is_file() and домен:
                    try:
                        if f'"site": "{домен}"' in журнал.read_text(encoding="utf-8"):
                            свои.append(str(журнал))
                    except OSError:
                        pass
                есть.extend(свои)
            if есть:
                итог[вид] = есть
            continue
        for п in список:
            try:
                if п.is_dir():
                    # Каталог может быть закрыт на чтение для этой учётной
                    # записи — например `site-data` принадлежит сайту с правами
                    # 0700. Отказ в чтении означает «каталог есть», а не
                    # «пуст»: считать его отсутствующим значило бы разрешить
                    # повторную инициализацию поверх чужих данных.
                    есть.append(str(п))
                elif п.exists():
                    есть.append(str(п))
            except OSError:
                есть.append(str(п))
        if есть:
            итог[вид] = есть
    return итог


def передан(site_id: str, домен: str, *, adapter: str = "") -> bool:
    """Передан ли сайт редактору — по факту наличия данных, а не по флагу.

    Отдельный флаг «передан» разошёлся бы с действительностью при первом же
    ручном вмешательстве. Файл на диске разойтись не может: он либо есть, либо
    нет.
    """
    return bool(существующие(site_id, домен, adapter=adapter))


def отметка_пути(site_id: str) -> pathlib.Path:
    return КОРЕНЬ_ОТМЕТОК / f"{site_id}.json"


def отметка(site_id: str) -> dict[str, Any] | None:
    """Отметка о завершённой инициализации или None."""
    п = отметка_пути(site_id)
    try:
        д = json.loads(п.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return д if isinstance(д, dict) else None


def поставить_отметку(site_id: str, домен: str, *, кем: str,
                      виды: list[str] | None = None) -> dict[str, Any]:
    """Записать отметку один раз. Повторный вызов её НЕ перезаписывает.

    Перезапись стёрла бы время первой инициализации — единственное, чем
    «создавали давно» отличается от «создают сейчас».
    """
    п = отметка_пути(site_id)
    было = отметка(site_id)
    if было is not None:
        return {"created": False, "marker": str(п), "existing": было}
    import time
    запись = {"schema_version": 1, "site_id": site_id, "domain": домен,
              "initialised_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              "initialised_by": кем,
              "kinds": sorted(виды or []),
              "note": ("Отметка завершённой первичной инициализации. Пока она "
                       "есть, повторная инициализация постоянных данных "
                       "запрещена — независимо от версии шаблона, выпуска и "
                       "от того, лежат ли сейчас файлы на диске.")}
    п.parent.mkdir(parents=True, exist_ok=True)
    врем = п.with_name(п.name + ".tmp")
    врем.write_text(json.dumps(запись, ensure_ascii=False, indent=1) + "\n",
                    encoding="utf-8")
    os.replace(врем, п)
    return {"created": True, "marker": str(п), "record": запись}


def состояние_владения(site_id: str, домен: str, *, adapter: str = "") -> dict[str, Any]:
    """Одно решение на все проверки: можно ли инициализировать и что есть.

    Три исхода, и смешивать их нельзя:

    * `first_init` — отметки нет и данных нет: новый сайт, инициализация
      разрешена ровно один раз;
    * `managed`   — есть отметка либо есть данные: сайт передан, запись
      запрещена;
    * `lost`      — отметка ЕСТЬ, а данных нет: у созданного сайта пропали
      постоянные данные. Это остановка с диагностикой, а не повод подставить
      шаблонные значения. Автоматическое восстановление запрещено прямо.
    """
    есть = существующие(site_id, домен, adapter=adapter)
    отм = отметка(site_id)
    if отм is None and not есть:
        состояние = "first_init"
    elif отм is not None and not есть:
        состояние = "lost"
    else:
        состояние = "managed"
    return {"site_id": site_id, "domain": домен, "state": состояние,
            "marker": отм, "marker_path": str(отметка_пути(site_id)),
            "present": {к: v for к, v in есть.items()},
            "may_initialise": состояние == "first_init"}


def исключение() -> dict[str, Any] | None:
    """Разобранное поручение владельца или None.

    Принимается только полная форма: назван сайт, перечислены конкретные файлы
    и сказано, что именно разрешено. Подстановочный знак в именах не
    принимается — «разрешено всё» это отмена запрета, а не исключение.
    """
    сырое = (os.environ.get(ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ) or "").strip()
    if not сырое:
        return None
    try:
        д = json.loads(сырое)
    except ValueError:
        raise ЗащитаДанных(
            f"{ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ} не разбирается как JSON: исключение не "
            "принято. Ожидается {\"site\": …, \"files\": [...], \"change\": …}"
        ) from None
    if not isinstance(д, dict):
        raise ЗащитаДанных(f"{ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ}: ожидался объект")
    сайт = str(д.get("site") or "").strip()
    файлы = д.get("files")
    что = str(д.get("change") or "").strip()
    if not сайт:
        raise ЗащитаДанных(f"{ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ}: не назван site")
    if not isinstance(файлы, list) or not файлы or not all(
            isinstance(ф, str) and ф.strip() for ф in файлы):
        raise ЗащитаДанных(
            f"{ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ}: files должен быть непустым перечнем "
            "конкретных путей")
    if any("*" in ф or "?" in ф for ф in файлы):
        raise ЗащитаДанных(
            f"{ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ}: подстановочный знак в files не "
            "принимается — исключение называет конкретные файлы")
    if not что:
        raise ЗащитаДанных(
            f"{ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ}: не сказано, какое изменение разрешено")
    return {"site": сайт, "files": [ф.strip() for ф in файлы], "change": что}


def _покрыто_исключением(site_id: str, домен: str, цель: pathlib.Path) -> str:
    искл = исключение()
    if искл is None:
        return ""
    if искл["site"] not in (site_id, домен):
        return ""
    ц = str(цель.resolve()) if цель.exists() else str(цель)
    for ф in искл["files"]:
        if ц == str(pathlib.Path(ф)):
            return искл["change"]
    return ""


def проверить_запись(site_id: str, домен: str, цель: str | os.PathLike[str], *,
                     операция: str, adapter: str = "") -> dict[str, Any]:
    """Разрешена ли запись по этому пути. Отказ — ДО единого изменения.

    Возвращает запись для журнала. Поднимает `ЗащитаДанных`, если путь
    защищён, сайт передан и поручения владельца на этот файл нет.
    """
    ц = pathlib.Path(цель)
    защищённые = пути(site_id, домен, adapter=adapter)
    задето: list[tuple[str, pathlib.Path]] = []
    for вид, список in защищённые.items():
        for п in список:
            try:
                совпало = ц == п or п in ц.parents or ц in п.parents
            except OSError:
                совпало = False
            if совпало:
                задето.append((вид, п))
    if not задето:
        return {"allowed": True, "reason": "путь не защищён", "target": str(ц)}

    сост = состояние_владения(site_id, домен, adapter=adapter)
    есть = сост["present"]
    if сост["state"] == "first_init":
        # Первичная инициализация: ни отметки, ни данных. Ровно один раз.
        return {"allowed": True, "target": str(ц),
                "reason": "первичная инициализация: отметки и данных нет",
                "kinds": [в for в, _ in задето]}
    if сост["state"] == "lost":
        raise ЗащитаДанных(
            f"{site_id}: отметка инициализации есть "
            f"({сост['marker_path']}), а защищённых данных на диске нет. "
            "Это УТРАТА данных уже созданного сайта, а не новый сайт. "
            "Операция остановлена: автоматическое восстановление шаблонных "
            "значений запрещено. Разберитесь с причиной пропажи и верните "
            "данные осознанно — отметка хранит время первой инициализации "
            f"({(сост['marker'] or {}).get('initialised_at')})")

    разрешение = _покрыто_исключением(site_id, домен, ц)
    if разрешение:
        return {"allowed": True, "target": str(ц), "exception": разрешение,
                "reason": f"поручение владельца: {разрешение}",
                "kinds": [в for в, _ in задето]}

    виды = sorted({в for в, _ in задето})
    raise ЗащитаДанных(
        f"{site_id}: операция {операция!r} пытается изменить защищённые данные "
        f"{виды} по пути {ц}. Сайт передан редактору — на диске есть "
        f"{sorted(есть)}. Обновление шаблона, исправление ошибки, повторный "
        "деплой, откат выпуска, отсутствие файла и несовпадение схемы "
        "разрешения не дают. Изменение возможно только по поручению владельца "
        f"через {ПЕРЕМЕННАЯ_ИСКЛЮЧЕНИЯ} с названными файлами")


def _адаптер_выпуска(репозиторий: pathlib.Path, коммит: str) -> str:
    """Семейство рантайма ВЫПУСКАЕМОГО кода.

    Берётся из `config/site.json` того самого коммита, а не из реестра: у
    выпуска может быть другая точка входа, чем у того, что стоит сейчас, и
    требовать читателя по старому семейству значило бы сверять не тот файл.
    """
    текст = ""
    if коммит:
        r = subprocess.run(["git", "show", f"{коммит}:config/site.json"],
                           cwd=str(репозиторий), capture_output=True, text=True)
        текст = r.stdout if r.returncode == 0 else ""
    else:
        ф = репозиторий / "config" / "site.json"
        текст = ф.read_text(encoding="utf-8") if ф.is_file() else ""
    try:
        точка = (json.loads(текст) or {}).get("entrypoint") or ""
    except ValueError:
        точка = ""
    if not точка:
        # Часть ячеек точку входа в конфигурации не объявляет — там её
        # определяет имя файла рантайма. Тем же правилом, что в реестре:
        # второе правило вывода разошлось бы с первым.
        точка = _рантайм_в_коммите(репозиторий, коммит)
    if not точка:
        return ""
    from factory.qwen import registry as _р
    return _р.АДАПТЕРЫ_ПО_РАНТАЙМУ.get(точка, "")


def _рантайм_в_коммите(репозиторий: pathlib.Path, коммит: str) -> str:
    """Имя файла рантайма в выпуске: `src/*frontend*.py`, иначе `serve.py`."""
    имена: list[str] = []
    if коммит:
        r = subprocess.run(["git", "ls-tree", "--name-only", f"{коммит}:src"],
                           cwd=str(репозиторий), capture_output=True, text=True)
        имена = [с.strip() for с in r.stdout.split("\n") if с.strip()] \
            if r.returncode == 0 else []
    elif (репозиторий / "src").is_dir():
        имена = sorted(п.name for п in (репозиторий / "src").iterdir()
                       if п.is_file())
    витрины = sorted(и for и in имена
                     if и.endswith(".py") and "frontend" in и)
    if витрины:
        return витрины[0]
    return "serve.py" if "serve.py" in имена else ""


def читатели(вид: str, adapter: str = "") -> tuple[str, ...]:
    """Какие файлы выпуск обязан нести, чтобы читать данные вида `вид`.

    Семейство определяет имя читателя. Нераспознанное семейство — не повод
    пропустить проверку: тогда годится ЛЮБОЙ из известных читателей этого
    вида, и выпуск без всякого читателя всё равно отклоняется.
    """
    if вид == "indexing_state" and adapter:
        from factory.qwen.indexing import КОНТРАКТ_РЕЖИМА
        контракт = КОНТРАКТ_РЕЖИМА.get(adapter)
        if контракт is None:
            # Семейство не распознано — послабления не даёт: действует общий
            # перечень. Иначе опечатка в имени семейства открывала бы ворота.
            return tuple(ЧИТАТЕЛИ.get(вид, ()))
        правило = контракт.get("reader") or ""
        if not правило or правило.startswith("container:"):
            # Режимом распоряжается не выпуск ячейки: требовать от него файл
            # нечестно, и отказ был бы отказом об устройстве семейства.
            return ()
        return (правило,)
    if вид == "editorial" and adapter:
        правило = ЧИТАТЕЛЬ_ПРАВОК.get(adapter, None)
        if правило is None:
            return tuple(ЧИТАТЕЛИ.get(вид, ()))
        return (правило,) if правило else ()
    return tuple(ЧИТАТЕЛИ.get(вид, ()))


def _файл_в_коммите(репозиторий: pathlib.Path, коммит: str, путь: str) -> bool:
    if not коммит:
        return (репозиторий / путь).is_file()
    r = subprocess.run(["git", "cat-file", "-e", f"{коммит}:{путь}"],
                       cwd=str(репозиторий), capture_output=True, text=True)
    return r.returncode == 0


def проверить_выпуск(site_id: str, домен: str, репозиторий: str | os.PathLike[str],
                     коммит: str = "", *, adapter: str = "") -> dict[str, Any]:
    """Умеет ли выпускаемый коммит читать присутствующие защищённые данные.

    Отказ ДО сборки и ДО активации. Выпуск без читателя файлы не испортит, но
    перестанет их читать: открытый сайт станет закрытым, опубликованные тексты
    исчезнут со страниц. Со стороны это неотличимо от потери данных, и
    пропускать такую активацию нельзя.
    """
    есть = существующие(site_id, домен, adapter=adapter)
    итог: dict[str, Any] = {"site_id": site_id, "domain": домен,
                            "present": sorted(есть), "commit": коммит[:12],
                            "missing_readers": []}
    if not есть:
        итог["compatible"] = True
        итог["reason"] = "защищённых данных нет: сверять нечего"
        return итог
    репо = pathlib.Path(репозиторий)
    семейство = adapter or _адаптер_выпуска(репо, коммит)
    итог["adapter"] = семейство
    нет: list[str] = []
    for вид in есть:
        нужны = читатели(вид, семейство)
        if not нужны:
            continue
        # Любой из названных читателей годится: у нераспознанного семейства их
        # несколько, и наличие одного означает, что данные читаются.
        if not any(_файл_в_коммите(репо, коммит, ч) for ч in нужны):
            нет.append(f"{вид}: {' или '.join(нужны)}")
    итог["missing_readers"] = нет
    итог["compatible"] = not нет
    if нет:
        raise ЗащитаДанных(
            f"{site_id}: выпуск {коммит[:12] or 'рабочей копии'} не несёт "
            f"читателей защищённых данных — {нет}. Активация остановлена ДО "
            "сборки: такой выпуск перестал бы читать то, что уже записано, и "
            "это выглядит как потеря данных. Перенесите читателя в выпускаемую "
            "ветку и повторите")
    итог["reason"] = "читатели на месте"
    return итог
