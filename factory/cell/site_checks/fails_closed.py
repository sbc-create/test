"""Запуск отказывает, а не подставляет чужое."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
#: Где на машине лежат каталоги данных витрин. Имя каталога — имя
#: РЕПОЗИТОРИЯ, а не site_id: это и есть причина правки ниже.
КОРЕНЬ_ДАННЫХ = Path("/srv")

r = subprocess.run([sys.executable, str(ROOT / "run.py"), "--check"],
                   capture_output=True, text=True, cwd=ROOT)
if r.returncode == 0:
    print("запуск без --data-dir не отказал", file=sys.stderr)
    sys.exit(1)

cfg = json.loads((ROOT / "config" / "site.json").read_text(encoding="utf-8"))
if "neighbour_site_ids" not in cfg:
    print("в config/site.json нет поля neighbour_site_ids", file=sys.stderr)
    sys.exit(1)

# Отказ проверяется ИСПОЛНЕНИЕМ, а не наличием списка соседей.
#
# Раньше требовался непустой список — и у сайта, заведённого из шаблона, его
# взяться неоткуда: соседей на машине ещё нет. Но защита нужна ему ровно так
# же: умолчания рантайма этого семейства указывают на чужую ячейку, и одна
# незаданная переменная означала бы витрину, молча отдающую каталог соседа.
# Поэтому проверяется то, ради чего защита написана: запуск с каталогом
# данных ЧУЖОГО сайта обязан отказать.
#
# Чужой каталог ищется НА МАШИНЕ, а не выводится из site_id, и это поправка по
# измерению SEO-сессии 12.10. Прежняя редакция брала `/srv/<site_id>/data` —
# такого пути нет ни у одной ячейки: каталоги в /srv названы по репозиторию
# (`lordfilm47-space`, `site-1lordserials1-online`), и ни один из 19 не назван
# по site_id. Проверка на несуществующем пути доказывала только «каталога нет
# → отказ», а регрессию «витрина берёт любой *-catalog.json из каталога» не
# поймала бы: по пустому пути такая витрина тоже падает, и шаг проходил бы
# впустую. Опознаётся чужой каталог по имени снимка — оно несёт site_id.
#
# Сосед из `neighbour_site_ids` берётся ПЕРВЫМ, и это поправка по замечанию
# SEO-сессии: `sorted(glob)` отдавал всем 17 ячейкам один и тот же каталог —
# первый по алфавиту, `/srv/an1meg0-site/data`. Для Lords, Zona и Yummy это
# каталог ДРУГОГО семейства, и отказ на нём мог прийти из-за несовместимого
# формата, а не из-за чужести. Доказательство тогда подменяется: шаг зеленеет,
# не проверив того, ради чего написан. Сосед того же семейства формат имеет
# тот же, поэтому отказ на нём означает именно «каталог не мой».
#
# Порядок предпочтения: сосед СВОЕГО семейства → любой объявленный сосед →
# любой чужой каталог. Семейство выводится из site_id до первого дефиса, и
# брать «первого соседа из списка» недостаточно: списки семейством НЕ
# ограничены — у `lords-01` первым объявлен `animedia-01`, то есть наивное
# «первый сосед» снова дало бы чужое семейство.
свой = cfg["site_id"]
семейство = свой.split("-")[0]
снимки = {с.name[: -len("-catalog.json")]: str(с.parent)
          for с in sorted(КОРЕНЬ_ДАННЫХ.glob("*/data/*-catalog.json"))}
#
# Снимок своего семейства ищется НА МАШИНЕ и БЕЗ оглядки на список соседей —
# поправка по второму замечанию SEO-сессии. У пяти новейших ячеек Lords
# (lordfilm077-site, lordserial101-site, lordserials22-info/-site/-space)
# `neighbour_site_ids` пуст, и опора на список уводила их на каталог чужого
# семейства, хотя снимки своего на машине есть. Список нужен дальше: он
# объявляет соседство, которого на диске может не быть вовсе.
соседи = [с for с in (cfg.get("neighbour_site_ids") or []) if с != свой]
подстава, откуда_взят = "", ""
for чей, каталог in снимки.items():
    if чей != свой and чей.split("-")[0] == семейство:
        подстава, откуда_взят = каталог, "каталог того же семейства"
        break
if not подстава:
    for сосед in соседи:
        if сосед in снимки:
            подстава = снимки[сосед]
            откуда_взят = "объявленный сосед другого семейства"
            break
if not подстава:
    for чей, каталог in снимки.items():
        if чей != свой:
            подстава, откуда_взят = каталог, "чужой каталог не из списка соседей"
            break

если_чужого_нет = not подстава
if если_чужого_нет:
    # Молчаливого «прошло» здесь быть не должно: без чужого каталога на машине
    # шаг проверяет слабее, и читающий отчёт обязан это видеть.
    подстава = "/srv/chuzhoy-sayt/data"
    print("ЗАМЕЧАНИЕ: каталога данных чужого сайта на машине не нашлось, "
          f"проверка идёт по несуществующему пути {подстава} — она слабее: "
          "отказ по «каталога нет» не доказывает отказа по «каталог чужой»",
          file=sys.stderr)

r = subprocess.run([sys.executable, str(ROOT / "run.py"), "--check",
                    "--data-dir", подстава],
                   capture_output=True, text=True, cwd=ROOT)
if r.returncode == 0:
    print(f"запуск с чужим каталогом данных {подстава} не отказал", file=sys.stderr)
    sys.exit(1)
if если_чужого_нет:
    откуда = "не найден, проверен несуществующий путь"
elif откуда_взят == "каталог того же семейства":
    откуда = f"{подстава} ({откуда_взят}: формат тот же, отказ означает чужесть)"
else:
    # Названо вслух: отказ на каталоге другого семейства может прийти и из-за
    # несовместимого формата, то есть доказательство слабее, чем кажется.
    откуда = (f"{подстава} ({откуда_взят}; другое семейство — отказ мог прийти "
              "и из-за формата, а не из-за чужести)")
print(f"fails_closed: отказ подтверждён; чужой каталог {откуда}")
