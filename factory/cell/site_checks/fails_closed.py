"""Запуск отказывает, а не подставляет чужое."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
#: Где на машине лежат каталоги данных витрин. Имя каталога — имя
#: РЕПОЗИТОРИЯ, а не site_id: это и есть причина правки ниже.
КОРЕНЬ_ДАННЫХ = Path("/srv")

r = subprocess.run([sys.executable, str(ROOT / "run.py"), "--check"],
                   capture_output=True, text=True, cwd=ROOT)
if r.returncode == 0:
    print("запуск без --data-dir не отказал", file=sys.stderr)
    sys.exit(1)

cfg = json.loads((ROOT / "config" / "site.json").read_text(encoding="utf-8"))
if "neighbour_site_ids" not in cfg:
    print("в config/site.json нет поля neighbour_site_ids", file=sys.stderr)
    sys.exit(1)

# Отказ проверяется ИСПОЛНЕНИЕМ, а не наличием списка соседей.
#
# Раньше требовался непустой список — и у сайта, заведённого из шаблона, его
# взяться неоткуда: соседей на машине ещё нет. Но защита нужна ему ровно так
# же: умолчания рантайма этого семейства указывают на чужую ячейку, и одна
# незаданная переменная означала бы витрину, молча отдающую каталог соседа.
# Поэтому проверяется то, ради чего защита написана: запуск с каталогом
# данных ЧУЖОГО сайта обязан отказать.
#
# Чужой каталог ищется НА МАШИНЕ, а не выводится из site_id, и это поправка по
# измерению SEO-сессии 12.10. Прежняя редакция брала `/srv/<site_id>/data` —
# такого пути нет ни у одной ячейки: каталоги в /srv названы по репозиторию
# (`lordfilm47-space`, `site-1lordserials1-online`), и ни один из 19 не назван
# по site_id. Проверка на несуществующем пути доказывала только «каталога нет
# → отказ», а регрессию «витрина берёт любой *-catalog.json из каталога» не
# поймала бы: по пустому пути такая витрина тоже падает, и шаг проходил бы
# впустую. Опознаётся чужой каталог по имени снимка — оно несёт site_id.
свой = cfg["site_id"]
подстава = ""
for снимок in sorted(КОРЕНЬ_ДАННЫХ.glob("*/data/*-catalog.json")):
    чей = снимок.name[: -len("-catalog.json")]
    if чей != свой:
        подстава = str(снимок.parent)
        break

если_чужого_нет = not подстава
if если_чужого_нет:
    # Молчаливого «прошло» здесь быть не должно: без чужого каталога на машине
    # шаг проверяет слабее, и читающий отчёт обязан это видеть.
    подстава = "/srv/chuzhoy-sayt/data"
    print("ЗАМЕЧАНИЕ: каталога данных чужого сайта на машине не нашлось, "
          f"проверка идёт по несуществующему пути {подстава} — она слабее: "
          "отказ по «каталога нет» не доказывает отказа по «каталог чужой»",
          file=sys.stderr)

r = subprocess.run([sys.executable, str(ROOT / "run.py"), "--check",
                    "--data-dir", подстава],
                   capture_output=True, text=True, cwd=ROOT)
if r.returncode == 0:
    print(f"запуск с чужим каталогом данных {подстава} не отказал", file=sys.stderr)
    sys.exit(1)
print(f"fails_closed: отказ подтверждён; чужой каталог "
      f"{'не найден, проверен несуществующий путь' if если_чужого_нет else подстава}")
