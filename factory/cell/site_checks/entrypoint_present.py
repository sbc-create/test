"""Точка входа существует, и зеркало о ней не врёт.

Проверок две, и вторая — та, ради которой файл перестал быть одной строкой.

1. ФАЙЛ СУЩЕСТВУЕТ. `config/site.json: entrypoint` разрешается как
   `src/<значение>`. Имя, указывающее в пустоту, — это отказ на старте, а не
   опечатка в бумажке.

2. ЗЕРКАЛО НЕ ВРЁТ. Если `run.py` держит имя артефакта В КОДЕ, оно обязано
   совпадать с объявленным. Такой пин ничего не переключает — его никто не
   исполняет, — и поэтому разойтись с действительностью он может МОЛЧА.
   Измерено на соседней ячейке: пин какое-то время объявлял `run.py`, то есть
   файл, которого под `src/` нет вовсе, а витрина работала как ни в чём не
   бывало. Поймать это «наличием ключа» было нельзя — только сверкой с тем,
   что запускается.

   Если `run.py` читает имя из конфигурации (так устроена часть семейств),
   расходиться нечему: об этом печатается строка, и шаг не делает вид, что
   проверил. «Не проверялось» и «проверено» — разные утверждения.

Обобщено из копии `animedia-space`, где сверка зеркала появилась первой. Её
собственная редакция читает `pins.lock.json` и опознаёт запуск по образцу
`КОРЕНЬ / "src" / "<имя>"`; здесь то же свойство проверяется так, чтобы
подходить и семействам, которые держат имя в `config/site.json`.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Как в `run.py` может быть записан запуск артефакта из `src/`. Образцы — по
#: наблюдению в живых пускателях, а не по догадке.
ОБРАЗЦЫ_ЗАПУСКА = (
    re.compile(r'(?:КОРЕНЬ|ROOT|BASE)\s*/\s*"src"\s*/\s*"([^"]+)"'),
    re.compile(r'"src"\s*,\s*"([^"]+\.py)"'),
    re.compile(r'[\'"]src/([^\'"]+\.py)[\'"]'),
)

# Имя точки входа объявляется в ОДНОМ из двух мест, и это не беспорядок, а
# измеренная действительность: 20 ячеек держат его в `config/site.json`, а
# `animedia-space` — в `pins.lock.json: pins.entrypoint`, и её собственная
# проверка читает именно пин. Шаблон, знающий только первое место, объявил бы
# «entrypoint не задан» у исправной ячейки — то есть судил бы не её.
cfg = json.loads((ROOT / "config" / "site.json").read_text(encoding="utf-8"))
объявлено = str(cfg.get("entrypoint") or "").strip()
где = "config/site.json"
if not объявлено:
    пины_путь = ROOT / "pins.lock.json"
    if пины_путь.is_file():
        пины = json.loads(пины_путь.read_text(encoding="utf-8"))
        объявлено = str((пины.get("pins") or {}).get("entrypoint") or "").strip()
        где = "pins.lock.json"
if not объявлено:
    print("ни config/site.json: entrypoint, ни pins.lock.json: pins.entrypoint "
          "не задают имя точки входа", file=sys.stderr)
    sys.exit(1)

entry = ROOT / "src" / объявлено
if not entry.is_file():
    print(f"нет точки входа {entry}", file=sys.stderr)
    sys.exit(1)

пускатель = ROOT / "run.py"
if not пускатель.is_file():
    print(f"нет пускателя {пускатель}", file=sys.stderr)
    sys.exit(1)

исходник = пускатель.read_text(encoding="utf-8", errors="replace")
запускает = ""
for образец in ОБРАЗЦЫ_ЗАПУСКА:
    найдено = образец.search(исходник)
    if найдено:
        запускает = найдено.group(1)
        break

if not запускает:
    # Имя в коде не записано — значит пускатель берёт его из конфигурации, и
    # расходиться нечему. Говорится вслух: шаг не выдаёт это за проверку.
    print(f"entrypoint: src/{объявлено}; зеркало не сверялось — "
          "run.py не держит имя артефакта в коде")
    sys.exit(0)

if запускает != объявлено:
    print(f"зеркало разошлось: {где} объявляет {объявлено}, "
          f"а run.py запускает {запускает}", file=sys.stderr)
    sys.exit(1)

print(f"entrypoint: src/{объявлено} (из {где}); зеркало совпадает с run.py")
