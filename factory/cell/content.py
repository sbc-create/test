"""Свежесть содержимого витрин: судим по ревизии, а не по времени файла.

Зачем отдельная проверка
------------------------

Трое суток четыре витрины показывали каталог от 23 сентября при источнике от
25-го, и ни одна имевшаяся проверка этого не называла: сайты отвечали 200,
файлы снимков имели свежее `mtime`, службы были подняты, выпуски проходили.
Я сам в отчёте назвал доставку исправной, потому что смотрел на `mtime`.

`mtime` доказывает, что файл записали. Он не доказывает, ЧТО в нём. Оба
наблюдённых отказа выглядели как исправная работа именно поэтому:

* пятиминутный проход честно перезаписывал хранилище ячейки каждые пять минут
  содержимым отрисованного релиза, который не двигался с 19 сентября —
  свежайший `mtime`, ревизия трёхдневной давности;
* витрина zona-02 не значилась ни у одного производителя каталога, и её снимок
  просто лежал с 22 сентября — тоже без единой ошибки.

Поэтому здесь сравниваются РЕВИЗИИ в трёх точках, и каждое расхождение
называет свою причину:

    источник → хранилище ячейки → то, что витрина отвечает по своему порту

    источник старше предела        source-stale     не собрался снимок
    хранилище ≠ источник           delivery-stale   снимок не доставлен
    витрина ≠ хранилище            runtime-stale    доставлен, но не перечитан
    витрина не отвечает            unreachable      служба не обслуживает
    всё сошлось                     ok

Различать их обязательно: «каталог устарел» — не диагноз, а три разных
неисправности с тремя разными исправлениями, и лечение не той из них было
главной потерей времени в этой работе.

Секретов проверка не касается: читаются только заголовки ответа и служебные
поля снимка.
"""
from __future__ import annotations

import json
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable

from factory.cell import registry, runtime

#: Общее хранилище производителей снимков — источник для всех ячеек.
ОБЩИЙ = Path("/srv/lords/.frontend")

#: Дольше этого снимок источника считается несобранным: суточная публикация
#: ходит раз в сутки, и запас нужен на её собственную длительность и на сдвиг
#: времени запуска. 30 ч — сутки плюс шесть часов, а не «примерно день».
ПРЕДЕЛ_ЧАСОВ = 30.0

#: Путь, по которому витрина называет свою ревизию дешевле всего: он не
#: отрисовывает каталог. Заголовок тот же, что на любой странице.
ПУТЬ_ОПРОСА = "/__template_version"


def _края(путь: Path, сколько: int = 8192) -> dict[str, str]:
    """Ревизия и время сборки без разбора всего снимка.

    Снимок каталога — десятки мегабайт, и разбирать его целиком ради двух
    полей значит держать проверку, которую не захочется запускать часто.

    Читаются ОБА края, а не только начало. Производитель пишет поля по
    алфавиту, и `items` стоит между `builtAt` и `revision`: в голове файла
    есть время сборки, а ревизия — за шестнадцатью мегабайтами записей, в
    хвосте. Первая версия читала только голову, находила `builtAt`, не
    находила `revision` и на каждой исправной витрине печатала «каталог не
    собирается». Ровно тот род ошибки, который эта проверка и сторожит:
    отсутствие измерения выдавалось за измеренное отсутствие.
    """
    try:
        размер = путь.stat().st_size
        with путь.open("rb") as ф:
            голова = ф.read(сколько)
            if размер > сколько:
                ф.seek(max(0, размер - сколько))
                хвост_б = ф.read(сколько)
            else:
                хвост_б = b""
    except OSError:
        return {}
    текст = голова.decode("utf-8", "replace") + хвост_б.decode("utf-8", "replace")
    итог: dict[str, str] = {}
    for поле, ключ in (("revision", "revision"), ("builtAt", "built_at")):
        метка = f'"{поле}":'
        if метка in текст:
            хвост = текст.split(метка, 1)[1].lstrip()
            if хвост.startswith('"'):
                итог[ключ] = хвост[1:].split('"', 1)[0]
    return итог


def _опросить(порт: int, *, таймаут: float = 10.0) -> dict[str, str]:
    """Что витрина отвечает о своём каталоге прямо сейчас."""
    запрос = urllib.request.Request(f"http://127.0.0.1:{порт}{ПУТЬ_ОПРОСА}")
    try:
        with urllib.request.urlopen(запрос, timeout=таймаут) as ответ:
            рев = ответ.headers.get("X-Catalog-Revision", "")
            построен = ответ.headers.get("X-Catalog-Built-At", "")
            тело = ответ.read(65536)
    except (urllib.error.URLError, OSError, ValueError) as ош:
        return {"error": type(ош).__name__}
    if not рев:
        # Старый рантайм заголовка не отдаёт, но поле в своде называет.
        try:
            свод = json.loads(тело.decode("utf-8", "replace"))
            рев = str(свод.get("catalog_revision") or "")
        except ValueError:
            pass
    return {"revision": рев, "built_at": построен}


def _возраст_часов(метка: str) -> float | None:
    if not метка:
        return None
    try:
        когда = datetime.fromisoformat(метка.replace("Z", "+00:00"))
    except ValueError:
        return None
    if когда.tzinfo is None:
        когда = когда.replace(tzinfo=timezone.utc)
    return (datetime.now(timezone.utc) - когда).total_seconds() / 3600.0


def состояние_витрины(site_id: str, *, общий: Path = ОБЩИЙ,
                      предел_часов: float = ПРЕДЕЛ_ЧАСОВ,
                      опрос: Callable[[int], dict[str, str]] | None = None,
                      ) -> dict[str, Any]:
    """Свежесть одной витрины и причина расхождения, если оно есть."""
    опрос = опрос or _опросить
    итог: dict[str, Any] = {"site_id": site_id}
    try:
        место = runtime.размещение(site_id)
    except (runtime.RuntimeUnknown, registry.RegistryError) as ош:
        return {**итог, "status": "unplaced", "reason": str(ош)[:160]}
    итог["managed_by"] = место.managed_by
    if место.managed_by != "cell":
        return {**итог, "status": "not-a-cell"}

    имя = f"{site_id}-catalog.json"
    источник = _края(общий / имя)
    итог["source"] = источник
    итог["source_age_hours"] = _возраст_часов(источник.get("built_at", ""))

    хранилище = _края(Path(место.data_dir) / имя) if место.data_dir else {}
    итог["cell"] = хранилище

    живое = опрос(место.port) if место.port else {"error": "порта в реестре нет"}
    итог["live"] = живое

    # Порядок проверок — от источника к витрине: иначе «доставлено старьё»
    # неотличимо от «источник сам старый», и починят не то.
    if not источник.get("revision"):
        return {**итог, "status": "no-source",
                "reason": f"снимка {имя} нет в {общий} — каталог не собирается"}
    возраст = итог["source_age_hours"]
    if возраст is not None and возраст > предел_часов:
        return {**итог, "status": "source-stale",
                "reason": f"снимок источника собран {возраст:.1f} ч назад "
                          f"(предел {предел_часов:.0f} ч): производитель не отработал"}
    # Ячейка, у которой снимка в своём хранилище нет ВОВСЕ, но витрина отвечает
    # ревизией источника, читает общее хранилище напрямую: у неё другой способ
    # доставки, а не устаревшая доставка. Назвать это `delivery-stale` значило
    # бы поднять тревогу на исправной витрине — а ложная тревога кончается тем,
    # что перестают смотреть и на настоящую.
    if not хранилище.get("revision"):
        if живое.get("revision") == источник["revision"]:
            return {**итог, "status": "ok", "note": "data-outside-cell",
                    "reason": "снимка в хранилище ячейки нет, витрина читает "
                              "общее хранилище и отвечает ревизией источника"}
        return {**итог, "status": "delivery-stale",
                "reason": f"снимка {имя} нет в хранилище ячейки "
                          f"{место.data_dir}, и витрина отвечает ревизией "
                          f"{(живое.get('revision') or 'нет')[:12]} "
                          f"при источнике {источник['revision'][:12]}"}
    if хранилище["revision"] != источник["revision"]:
        return {**итог, "status": "delivery-stale",
                "reason": "в хранилище ячейки ревизия "
                          f"{хранилище['revision'][:12]}, "
                          f"в источнике {источник['revision'][:12]}: снимок не доставлен"}
    if живое.get("error"):
        return {**итог, "status": "unreachable",
                "reason": f"витрина на порту {место.port} не ответила: {живое['error']}"}
    if живое.get("revision") != источник["revision"]:
        return {**итог, "status": "runtime-stale",
                "reason": f"витрина отвечает ревизией {(живое.get('revision') or 'нет')[:12]} "
                          f"при доставленной {источник['revision'][:12]}: "
                          "снимок не перечитан"}
    return {**итог, "status": "ok"}


def свежесть(*, общий: Path = ОБЩИЙ, предел_часов: float = ПРЕДЕЛ_ЧАСОВ,
             сайты: list[str] | None = None,
             опрос: Callable[[int], dict[str, str]] | None = None,
             ) -> dict[str, Any]:
    """Свежесть всех выделенных витрин одним ответом."""
    цели = сайты if сайты is not None else sorted(registry.extracted_sites())
    состояния = [состояние_витрины(s, общий=общий, предел_часов=предел_часов,
                                   опрос=опрос) for s in цели]
    плохие = [с for с in состояния
              if с["status"] not in ("ok", "not-a-cell", "unplaced")]
    return {"checked_at": datetime.now(timezone.utc).isoformat(),
            "limit_hours": предел_часов,
            "sites": состояния,
            "stale": [с["site_id"] for с in плохие],
            "ok": not плохие}
