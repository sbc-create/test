"""Сайты, исключённые из активной работы SEO и редакции.

Решение владельца 25.10.2026: animedia.space, lordfilm47.space,
lordserials22.site и lordserials22.space исключены из активного продвижения,
написания текстов и регулярных проверок до замены доменов. История и
подготовленные материалы сохраняются. lordserials22.info работает дальше.
Инфраструктура этих сайтов (службы, счётчики, перенос lordfilm47.space на
lords3rial.site) ведётся линией Архитектора; здесь только то, что раздаёт
работу SEO и редакции.

Признаков два:

* `ИСКЛЮЧЕНЫ` — перечень доменов с решением. Исключение — по ДОМЕНУ, а не по
  site_id: ячейка lords-01 переезжает на lords3rial.site, и новый домен после
  подтверждённого запуска возвращается в работу без правки этого перечня;
* статус ячейки `retired` в реестре ячеек (значение объявлено схемой) — для
  будущих выводов, которые запишет владелец реестра.

Зачем отдельный модуль. Работу раздают несколько независимых потребителей:
шлюз и кандидаты редактора, регулярные проверки (обнаружение доменов по
реестру ячеек и реестру аналитики), техочередь, сбор аналитики, мост очереди и
пишущие операции инструментов Qwen, манифест Topvisor. Свой статический
перечень у каждого — это места, где исключённый домен вернётся после
следующей правки перечня или через автоматическое обнаружение. Здесь одна
проверка, и потребители спрашивают её.

Нечитаемый реестр ячеек — только перечень `ИСКЛЮЧЕНЫ`, а не отказ: беда
окружения не должна останавливать работу остальных сайтов.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

СТАТУС = "retired"

РЕШЕНИЕ = ("владелец 25.10.2026: исключён из активного продвижения, написания "
           "текстов и регулярных проверок до замены домена; история и материалы "
           "сохраняются")

#: Домен → решение. Тот же перечень литералом держит seo_operator/tech_run.py
#: (файл грузится вне пакета); равенство закрепляет тест.
ИСКЛЮЧЕНЫ: dict[str, str] = {
    "animedia.space": РЕШЕНИЕ,
    "lordfilm47.space": РЕШЕНИЕ + "; переезд на lords3rial.site ведёт Архитектор",
    "lordserials22.site": РЕШЕНИЕ,
    "lordserials22.space": РЕШЕНИЕ,
}

_КОРЕНЬ = Path(__file__).resolve().parents[2]


def _путь(путь: Path | None) -> Path:
    if путь is not None:
        return Path(путь)
    из_среды = os.environ.get("SITE_CELLS_REGISTRY")
    return Path(из_среды) if из_среды else _КОРЕНЬ / "config" / "site-cells.json"


def _ячейки(путь: Path | None) -> list[dict]:
    try:
        данные = json.loads(_путь(путь).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    сп = данные.get("cells") if isinstance(данные, dict) else None
    return [я for я in (сп or []) if isinstance(я, dict)]


def выведенные(путь: Path | None = None) -> frozenset[str]:
    """Исключённые домены (с www-формой) и домены/алиасы/site_id ячеек `retired`."""
    итог: set[str] = set()
    for домен in ИСКЛЮЧЕНЫ:
        итог.update({домен, "www." + домен})
    for я in _ячейки(путь):
        if я.get("status") != СТАТУС:
            continue
        for имя in [я.get("domain"), я.get("site_id"), *(я.get("aliases") or [])]:
            if имя:
                итог.add(str(имя).strip().lower())
    return frozenset(итог)


def выведен(имя: str | None, путь: Path | None = None,
            *, набор: frozenset[str] | None = None) -> bool:
    """Исключён ли домен (или site_id ячейки `retired`). `набор` — уже прочитанный `выведенные()`."""
    if not имя:
        return False
    н = набор if набор is not None else выведенные(путь)
    имя = str(имя).strip().lower()
    return имя in н or имя.removeprefix("www.") in н
