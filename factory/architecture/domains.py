"""Гейт доменных границ: объявленное сверяется с написанным.

Слой над гейтом модулей (`site_engine/boundaries.py`), а не второй механизм
рядом. Тот проверяет устройство внутри `site_engine`; этот — девять доменов,
которые шире одного пакета: релизы живут в `factory/lords` и `factory/targets`,
очередь — в `factory/queue`.

Проверяется пять правил, и каждое соответствует уже случившемуся смешению:

1. Объявленный путь существует. Граница, проведённая по несуществующему файлу,
   не проведена.
2. Файл принадлежит не более чем одному домену. Двойная принадлежность значит,
   что владельца нет.
3. Домен не импортирует того, что ему запрещено.
4. Общая опора не знает доменов. Опора, знающая домен, перестаёт быть опорой.
5. Семейство витрин не управляет флотом.

Правило «каждый файл принадлежит домену» намеренно НЕ проверяется как отказ:
раскладка вводится постепенно, и нераспределённый файл — это работа впереди, а
не нарушение. Их число печатается и закреплено отдельной проверкой, чтобы оно
уменьшалось, а не росло.
"""
from __future__ import annotations

import ast
from dataclasses import dataclass, field
from pathlib import Path

import yaml

РЕЕСТР = Path("config/domains.yaml")
ПАКЕТ = "factory"


@dataclass
class Итог:
    нарушения: list[str] = field(default_factory=list)
    известные: list[str] = field(default_factory=list)
    файлов: int = 0
    распределено: int = 0
    нераспределённых: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.нарушения

    def отказ(self, текст: str) -> None:
        self.нарушения.append(текст)


def загрузить(root: Path) -> dict:
    return yaml.safe_load((root / РЕЕСТР).read_text(encoding="utf-8"))


def _импорты(исходник: str) -> set[str]:
    try:
        дерево = ast.parse(исходник)
    except SyntaxError:
        return set()
    найдено: set[str] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            найдено.update(и.name for и in узел.names)
        elif isinstance(узел, ast.ImportFrom) and узел.module and not узел.level:
            найдено.add(узел.module)
    return {и for и in найдено if и.split(".")[0] == ПАКЕТ}


def _владелец(отн: str, карта: list[tuple[str, str]]) -> str | None:
    """Единица, которой принадлежит файл. Более длинный путь выигрывает."""
    лучший, длина = None, -1
    for путь, единица in карта:
        подходит = отн == путь or (путь.endswith("/") and отн.startswith(путь))
        if подходит and len(путь) > длина:
            лучший, длина = единица, len(путь)
    return лучший


def проверить(root: Path | str = ".") -> Итог:
    root = Path(root)
    реестр = загрузить(root)
    итог = Итог()

    известные = {
        (з["file"], з["imports"]) for з in (реестр.get("known_violations") or [])
    }

    карта: list[tuple[str, str]] = []
    запреты: dict[str, set[str]] = {}
    единицы: dict[str, dict] = {}

    for домен in реестр["domains"]:
        единицы[домен["id"]] = домен
        запреты[домен["id"]] = set(домен.get("forbidden") or [])
        for путь in домен["paths"]:
            карта.append((путь, домен["id"]))
    for имя in ("shared", "control_plane", "site_families"):
        блок = реестр.get(имя) or {}
        единицы[имя] = блок
        for путь in блок.get("paths") or []:
            карта.append((путь, имя))

    # 1. Объявленный путь существует.
    for путь, единица in карта:
        if not (root / путь).exists():
            итог.отказ(f"{единица}: объявлен путь {путь}, которого нет")

    # 2. Файл принадлежит не более чем одному домену.
    по_путям: dict[str, set[str]] = {}
    for путь, единица in карта:
        по_путям.setdefault(путь, set()).add(единица)
    for путь, кто in по_путям.items():
        if len(кто) > 1:
            итог.отказ(f"{путь}: объявлен сразу в {sorted(кто)} — владельца нет")

    # --- обход исходников ---------------------------------------------------
    for файл in sorted((root / ПАКЕТ).rglob("*.py")):
        if "__pycache__" in файл.parts:
            continue
        отн = файл.relative_to(root).as_posix()
        итог.файлов += 1
        владелец = _владелец(отн, карта)
        if владелец is None:
            итог.нераспределённых.append(отн)
            continue
        итог.распределено += 1

        исходник = файл.read_text(encoding="utf-8")
        for импорт in _импорты(исходник):
            цель = _владелец_модуля(импорт, карта)
            if цель is None or цель == владелец:
                continue

            # 3. Запрещённая зависимость.
            if цель in запреты.get(владелец, ()):
                текст = (f"{отн}: домен «{владелец}» импортирует «{цель}» "
                         f"({импорт}), а реестр это запрещает")
                # Известное нарушение остаётся нарушением: оно печатается и
                # закреплено проверкой на нерост списка. Молчать о нём нельзя,
                # но и валить прогон на уже названном долге бессмысленно.
                if (отн, импорт) in известные:
                    итог.известные.append(текст)
                else:
                    итог.отказ(текст)

            # 4. Опора не знает доменов.
            if владелец == "shared" and цель not in ("shared",):
                итог.отказ(
                    f"{отн}: общая опора импортирует «{цель}» ({импорт}); "
                    f"опора, знающая домен, перестаёт быть опорой")

            # 5. Витрина не управляет флотом.
            if владелец == "site_families" and цель == "control_plane":
                итог.отказ(
                    f"{отн}: семейство витрин импортирует управляющий контур "
                    f"({импорт})")

    return итог


def _владелец_модуля(модуль: str, карта: list[tuple[str, str]]) -> str | None:
    """Единица, которой принадлежит импортируемый модуль."""
    как_путь = модуль.replace(".", "/") + ".py"
    владелец = _владелец(как_путь, карта)
    if владелец:
        return владелец
    return _владелец(модуль.replace(".", "/") + "/", карта)


if __name__ == "__main__":
    итог = проверить(".")
    print(f"файлов: {итог.файлов}, распределено: {итог.распределено}, "
          f"нераспределённых: {len(итог.нераспределённых)}, "
          f"известных нарушений: {len(итог.известные)}")
    for и in итог.известные:
        print("  ИЗВЕСТНО", и)
    for н in итог.нарушения:
        print("  ОТКАЗ", н)
    raise SystemExit(0 if итог.ok else 1)
