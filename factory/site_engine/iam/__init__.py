"""Домен личности: кто действует и вправе ли.

Люди, роли, сессии, приглашения и машинные личности AI-клиентов. Здесь нет
ничего про содержимое: разрешатель тождества произведений (`identity_resolver`)
в этот домен не входит, хотя слово «identity» в его имени и есть — он про
тождество тайтлов, а не людей. Раскладка по именам ошиблась ровно на нём, и
гейт границ это показал.

Интерфейс ленивый по той же причине, что и у заведения витрин: пакет с
немедленным реэкспортом втягивает свои модули в момент импорта самого пакета,
и связь, безобидная между плоскими модулями, замыкается в кольцо. Ленивое
разрешение имени откладывает импорт до первого обращения, когда инициализация
уже закончена.
"""
from __future__ import annotations

import importlib
from typing import Any

_МОДУЛИ = ("operators", "accounts", "account_app", "account_ui")


def __getattr__(имя: str) -> Any:
    if имя in _МОДУЛИ:
        return importlib.import_module(f"{__name__}.{имя}")
    raise AttributeError(
        f"домен личности не отдаёт «{имя}»: возьмите его у нужного модуля")


def __dir__() -> list[str]:
    return sorted(_МОДУЛИ)
