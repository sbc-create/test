"""Домен заведения витрин: новая витрина через публичные контракты остальных.

Интерфейс собирается лениво, и это не украшение. Пакет с немедленным
реэкспортом втягивает свой `core` в момент импорта самого пакета, а `core`
зависит от плана сайта, который зависит от заявки — то есть обратно от этого
пакета. Пока модули были плоскими, кольца не возникало: замыкает его именно
`__init__`, выполняющийся раньше подмодулей.

Ленивый доступ разрывает кольцо, ничего не меняя в самих модулях: имя
разрешается при первом обращении, когда инициализация уже закончена.
"""
from __future__ import annotations

import importlib
from typing import Any

#: Что домен отдаёт наружу. Перечислено поимённо, потому что собрать список
#: из модуля можно только импортировав его, а импортировать рано — нельзя.
_ИЗ_CORE = ("SiteProvisioner", "ProvisionError", "provision")


def __getattr__(имя: str) -> Any:
    """Имя разрешается при первом обращении, а не при импорте пакета."""
    if имя in ("core", "site_request", "scaffold"):
        return importlib.import_module(f"{__name__}.{имя}")
    if имя.startswith("_"):
        raise AttributeError(имя)
    модуль = importlib.import_module(f"{__name__}.core")
    try:
        return getattr(модуль, имя)
    except AttributeError as отказ:
        raise AttributeError(
            f"домен заведения витрин не отдаёт «{имя}»") from отказ


def __dir__() -> list[str]:
    return sorted({*_ИЗ_CORE, "core", "site_request", "scaffold"})
