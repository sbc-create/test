"""Обогащение оценок: хранение, очередь и сопоставление — без выдуманных чисел.

Измерено на снимке каталога от 7 сентября (53 257 записей, единый знаменатель):
у 87,7 % есть идентификатор Кинопоиска, а оценка — у 36,8 %. Половина каталога,
50,9 %, имеет идентификатор и не имеет оценки. Голоса не передаются вовсе —
ноль записей из 53 257.

Первый вопрос был не «как добрать», а «теряем ли мы». Проверены 755 детальных
ответов поставщика по записям с идентификатором и без оценки: оценки нет ни в
одном. Значит, чинить проекцию нечего — данных нет у источника.

Отсюда устройство модуля. Он умеет всё, кроме одного: он не ходит ни в какой
источник, которого владелец не разрешил. Разрешение действует на договорный фид
поставщика; Кинопоиск, IMDb и прочие сайты запрещены отдельно и прямо. Поэтому
здесь есть схема, очередь, сопоставление, происхождение, отрицательный кэш,
пределы частоты и метрики покрытия — и нет ни одного сетевого вызова.

Четыре хранилища, и каждое отвечает за своё:

`external_title_ids`  — какие внешние идентификаторы у произведения и откуда
                        они известны. Идентификатор без происхождения нельзя
                        перепроверить.
`rating_observations` — журнал наблюдений, только добавление. Оценка меняется
                        со временем, и перезапись стирает то, по чему потом
                        объясняют изменение.
`current_ratings`     — текущее значение на каждую пару «произведение +
                        метрика». Считается из наблюдений, а не пишется рядом.
`enrichment_jobs`     — что запрошено, что сделано, что отложено и почему.
"""

from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any

ВЕРСИЯ = "rating-enrichment/1.0.0"

ХРАНИЛИЩЕ = "var/state/rating-enrichment"

#: Доли очереди. Числа не произвольные: новинки меняются чаще всего и видны на
#: главной; популярное определяет впечатление большинства; хвост обязан
#: уменьшаться, иначе он не разберётся никогда; на повторы нужен запас, иначе
#: неоднозначные записи вытеснят полезную работу.
ДОЛИ = {"свежие": 0.40, "популярные": 0.25, "хвост": 0.25, "повторы": 0.10}


class Способ(str, Enum):
    """Как сопоставлено произведение с внешней записью. Порядок — по убыванию
    доверия; ниже `КАНДИДАТ` автоматическое применение запрещено."""

    ТОЧНЫЙ_ID = "EXACT_ID"
    ПЕРЕКРЁСТНЫЙ_ID = "CROSSWALK_ID"
    НАЗВАНИЕ_ГОД_ТИП = "TITLE_YEAR_KIND"
    ОРИГИНАЛ_ГОД_ТИП = "ORIGINAL_YEAR_KIND"
    КАНДИДАТ = "FUZZY_CANDIDATE"


#: Способы, которым можно верить без человека.
ДОВЕРЕННЫЕ = (Способ.ТОЧНЫЙ_ID, Способ.ПЕРЕКРЁСТНЫЙ_ID,
              Способ.НАЗВАНИЕ_ГОД_ТИП, Способ.ОРИГИНАЛ_ГОД_ТИП)


class Состояние(str, Enum):
    ОЖИДАЕТ = "PENDING"
    ВЫПОЛНЕНО = "DONE"
    ОТЛОЖЕНО = "DEFERRED"
    ОТКАЗ = "FAILED"
    МЁРТВОЕ = "DEAD_LETTER"
    ИСТОЧНИК_НЕ_ПОДКЛЮЧЁН = "SOURCE_NOT_CONNECTED"


@dataclass(frozen=True)
class Наблюдение:
    """Одно измерение оценки. Добавляется, никогда не переписывается."""

    content_id: str
    metric: str
    value: float
    scale: float
    source: str
    legal_basis: str
    provider_updated_at: str = ""
    observed_at: str = ""
    votes: int | None = None
    confidence: float = 1.0
    match_method: str = Способ.ТОЧНЫЙ_ID.value

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class Задание:
    content_id: str
    reason: str
    state: str = Состояние.ОЖИДАЕТ.value
    attempts: int = 0
    not_before: float = 0.0
    last_error: str = ""
    bucket: str = "хвост"

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


class EnrichmentError(Exception):
    """Обогащение отказано. Причина названа."""


@dataclass
class Хранилище:
    """Файловое хранилище. Не база: обогащение читается пакетно и пишется
    построчно, и заводить под это отдельную службу значило бы добавить точку
    отказа там, где её можно не заводить."""

    root: Path
    _наблюдения: list[dict] = field(default_factory=list)

    @property
    def каталог(self) -> Path:
        return Path(self.root) / ХРАНИЛИЩЕ

    def _файл(self, имя: str) -> Path:
        return self.каталог / имя

    def записать_идентификаторы(self, content_id: str, ids: dict[str, str],
                                *, source: str) -> None:
        if not content_id:
            raise EnrichmentError("идентификатор произведения пуст")
        чистые = {к: str(з) for к, з in (ids or {}).items() if з}
        if not чистые:
            return
        строка = {"contentId": content_id, "ids": чистые, "source": source,
                  "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
        self._добавить("external_title_ids.jsonl", строка)

    def добавить_наблюдение(self, н: Наблюдение) -> None:
        if н.value is None:
            raise EnrichmentError("наблюдение без значения: отсутствие оценки — не ноль")
        if not н.source or not н.legal_basis:
            raise EnrichmentError(
                "наблюдение без источника или правового основания: число, "
                "поставленное неизвестно кем, нельзя ни проверить, ни объяснить")
        if н.scale <= 0 or н.value > н.scale:
            raise EnrichmentError(f"значение {н.value} не укладывается в шкалу {н.scale}")
        if н.match_method not in {с.value for с in Способ}:
            raise EnrichmentError(f"неизвестный способ сопоставления: {н.match_method}")
        if н.match_method == Способ.КАНДИДАТ.value:
            raise EnrichmentError(
                "нестрогое совпадение не записывается как наблюдение: ремейк и "
                "одноимённое произведение сливаются молча")
        запись = н.as_dict()
        запись["observed_at"] = н.observed_at or time.strftime(
            "%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        self._добавить("rating_observations.jsonl", запись)

    def _добавить(self, имя: str, строка: dict) -> None:
        self.каталог.mkdir(parents=True, exist_ok=True)
        with open(self._файл(имя), "a", encoding="utf-8") as ф:
            ф.write(json.dumps(строка, ensure_ascii=False) + "\n")

    def наблюдения(self) -> list[dict]:
        путь = self._файл("rating_observations.jsonl")
        if not путь.is_file():
            return []
        из = []
        for строка in путь.read_text(encoding="utf-8").splitlines():
            if строка.strip():
                try:
                    из.append(json.loads(строка))
                except ValueError:
                    continue
        return из

    def текущие(self) -> dict[tuple[str, str], dict]:
        """Текущая оценка по паре «произведение + метрика».

        Считается из журнала, а не хранится отдельно: отдельное хранение
        расходится с журналом ровно тогда, когда по журналу и приходят
        разбираться.
        """
        из: dict[tuple[str, str], dict] = {}
        for н in self.наблюдения():
            ключ = (н["content_id"], н["metric"])
            прежнее = из.get(ключ)
            if прежнее is None or н.get("observed_at", "") >= прежнее.get("observed_at", ""):
                из[ключ] = н
        return из


# --- очередь ----------------------------------------------------------------


def распределить(записи: list[dict], *, бюджет: int, сейчас_ms: int | None = None,
                 повторы: list[Задание] | None = None) -> list[Задание]:
    """Что обогащать сегодня. Доли соблюдаются, хвост обязан уменьшаться.

    Очередь строится от каталога, а не от прошлых заданий: задание, потерянное
    при перезапуске, иначе не вернётся никогда, и хвост будет расти молча.
    """
    if бюджет <= 0:
        return []
    сейчас = сейчас_ms if сейчас_ms is not None else int(time.time() * 1000)
    сутки = 48 * 3600 * 1000

    нужны = [з for з in записи if _нужна_оценка(з)]
    свежие = [з for з in нужны
              if int(з.get("updated_at_ms") or з.get("created_at_ms") or 0) >= сейчас - сутки]
    популярные = [з for з in нужны if з.get("popular")]
    свежие_id = {з.get("external_id") for з in свежие}
    популярные = [з for з in популярные if з.get("external_id") not in свежие_id]
    занятые = свежие_id | {з.get("external_id") for з in популярные}
    хвост = [з for з in нужны if з.get("external_id") not in занятые]

    из: list[Задание] = []
    план = {"свежие": свежие, "популярные": популярные, "хвост": хвост}
    for имя, доля in ДОЛИ.items():
        if имя == "повторы":
            continue
        сколько = int(бюджет * доля)
        for з in план[имя][:сколько]:
            из.append(Задание(content_id=str(з.get("external_id") or ""),
                              reason=имя, bucket=имя))

    место = int(бюджет * ДОЛИ["повторы"])
    for задание in (повторы or [])[:место]:
        if задание.not_before <= сейчас / 1000:
            из.append(задание)

    # Недобор одной доли отдаётся хвосту: пустое место в бюджете означает, что
    # хвост в этот день не уменьшился ни на запись.
    if len(из) < бюджет:
        уже = {з.content_id for з in из}
        for з in хвост:
            если_id = str(з.get("external_id") or "")
            if если_id and если_id not in уже:
                из.append(Задание(content_id=если_id, reason="хвост-добор", bucket="хвост"))
                уже.add(если_id)
            if len(из) >= бюджет:
                break
    return из[:бюджет]


def _нужна_оценка(запись: dict) -> bool:
    значение = запись.get("kinopoisk_rating")
    return значение in (None, "", 0, "0")


# --- сопоставление ----------------------------------------------------------


def сопоставить(запись: dict, кандидаты: list[dict]) -> tuple[dict | None, Способ, str]:
    """Какому внешнему произведению соответствует запись каталога.

    Лестница строгая, и последняя ступень — не решение, а кандидат: ремейк и
    одноимённое произведение отличаются только годом и типом, а иногда и ими не
    отличаются. Автоматическое слияние здесь стоило бы чужой оценки на чужой
    карточке.
    """
    свои = запись.get("external_ids") or {}
    if свои.get("kinopoisk"):
        для = [к for к in кандидаты if str(к.get("kinopoisk_id") or "") == str(свои["kinopoisk"])]
        if len(для) == 1:
            return для[0], Способ.ТОЧНЫЙ_ID, ""
        if len(для) > 1:
            return None, Способ.КАНДИДАТ, "несколько записей с одним идентификатором"
    if свои.get("imdb"):
        для = [к for к in кандидаты if str(к.get("imdb_id") or "") == str(свои["imdb"])]
        if len(для) == 1:
            return для[0], Способ.ПЕРЕКРЁСТНЫЙ_ID, ""
        if len(для) > 1:
            return None, Способ.КАНДИДАТ, "перекрёстная ссылка неоднозначна"

    год = запись.get("year")
    вид = "series" if запись.get("is_series") else "movie"
    имя = _ключ(запись.get("name"))
    оригинал = _ключ(запись.get("original_name"))

    for поле, способ in (("title", Способ.НАЗВАНИЕ_ГОД_ТИП),
                         ("original_title", Способ.ОРИГИНАЛ_ГОД_ТИП)):
        искомое = имя if поле == "title" else оригинал
        if not искомое or not год:
            continue
        для = [к for к in кандидаты
               if _ключ(к.get(поле)) == искомое
               and int(к.get("year") or 0) == int(год)
               and str(к.get("kind") or вид) == вид]
        if len(для) == 1:
            return для[0], способ, ""
        if len(для) > 1:
            return None, Способ.КАНДИДАТ, (
                f"по «{поле}» {len(для)} совпадения одного года и типа: ремейк или "
                "одноимённое произведение")
    return None, Способ.КАНДИДАТ, "строгого совпадения нет"


def _ключ(значение) -> str:
    return " ".join(str(значение or "").lower().replace("ё", "е").split())


# --- источник и его отсутствие ----------------------------------------------


class Источник:
    """Договор с поставщиком оценок. Реализации здесь нет намеренно.

    Владелец разрешил показывать оценки, которые уже приходят в договорном фиде
    поставщика содержимого. Кинопоиск, IMDb и прочие сайты запрещены отдельно и
    прямо, включая обход ограничений доступа. Поэтому источник — это интерфейс,
    а не клиент: подключать нечего, пока не появится разрешение.
    """

    name = "abstract"
    legal_basis = ""

    def доступен(self) -> tuple[bool, str]:
        raise NotImplementedError

    def запросить(self, ключ: str) -> dict:
        raise NotImplementedError


class ИсточникНеПодключён(Источник):
    """Источник, которого нет. Отвечает причиной, а не пустотой.

    Пустой ответ неотличим от «оценки нет у произведения», и по нему витрина
    показала бы отсутствие оценки как факт. Здесь же отказ говорит, что мы не
    спрашивали.
    """

    name = "not-connected"

    def __init__(self, причина: str) -> None:
        self.причина = причина

    def доступен(self) -> tuple[bool, str]:
        return False, self.причина

    def запросить(self, ключ: str) -> dict:
        raise EnrichmentError(f"источник не подключён: {self.причина}")


@dataclass
class Пределы:
    """Ограничения обращения к источнику. Числа задаются договором, а не гаданием."""

    в_минуту: int = 60
    попыток: int = 5
    базовая_пауза: float = 2.0
    предохранитель_после: int = 10

    def пауза(self, попытка: int) -> float:
        """Экспоненциальная выдержка. Ограничена сверху: пауза в часы означает,
        что задание не выполнится никогда, а очередь этого не покажет."""
        return min(self.базовая_пауза ** max(1, попытка), 900.0)


@dataclass
class Прогон:
    """Итог одного прохода обогащения."""

    запрошено: int = 0
    получено: int = 0
    отложено: int = 0
    отказов: int = 0
    мёртвых: int = 0
    кандидатов: int = 0
    источник_недоступен: str = ""

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def прогон(задания: list[Задание], источник: Источник, хранилище: Хранилище, *,
           пределы: Пределы | None = None, dry_run: bool = True) -> Прогон:
    """Один проход. По умолчанию — сухой: обогащение обязано быть проверяемым
    до того, как получит право писать."""
    пределы = пределы or Пределы()
    итог = Прогон(запрошено=len(задания))
    доступен, причина = источник.доступен()
    if not доступен:
        итог.источник_недоступен = причина
        for задание in задания:
            задание.state = Состояние.ИСТОЧНИК_НЕ_ПОДКЛЮЧЁН.value
        итог.отложено = len(задания)
        return итог

    подряд_отказов = 0
    for задание in задания:
        if подряд_отказов >= пределы.предохранитель_после:
            задание.state = Состояние.ОТЛОЖЕНО.value
            задание.last_error = "предохранитель разомкнут: источник отвечает отказами подряд"
            итог.отложено += 1
            continue
        try:
            ответ = источник.запросить(задание.content_id)
        except EnrichmentError as ошибка:
            задание.attempts += 1
            задание.last_error = str(ошибка)
            подряд_отказов += 1
            if задание.attempts >= пределы.попыток:
                задание.state = Состояние.МЁРТВОЕ.value
                итог.мёртвых += 1
            else:
                задание.state = Состояние.ОТЛОЖЕНО.value
                задание.not_before = time.time() + пределы.пауза(задание.attempts)
                итог.отложено += 1
            итог.отказов += 1
            continue
        подряд_отказов = 0
        if not ответ:
            задание.state = Состояние.ВЫПОЛНЕНО.value
            continue
        if not dry_run:
            хранилище.добавить_наблюдение(Наблюдение(
                content_id=задание.content_id,
                metric=str(ответ.get("metric") or ""),
                value=float(ответ["value"]),
                scale=float(ответ.get("scale") or 10.0),
                source=источник.name,
                legal_basis=источник.legal_basis,
                provider_updated_at=str(ответ.get("updated_at") or ""),
                votes=ответ.get("votes"),
                confidence=float(ответ.get("confidence") or 1.0),
                match_method=str(ответ.get("match_method") or Способ.ТОЧНЫЙ_ID.value),
            ))
        задание.state = Состояние.ВЫПОЛНЕНО.value
        итог.получено += 1
    return итог


def покрытие(записи: list[dict], хранилище: Хранилище) -> dict[str, Any]:
    """Покрытие на одном знаменателе — общем числе записей снимка.

    Проценты от разных знаменателей складываются в картину, которой нет:
    «половина с оценкой» и «половина с идентификатором» звучат одинаково.
    """
    всего = len(записи)
    текущие = хранилище.текущие()
    из_фида = sum(1 for з in записи if not _нужна_оценка(з))
    обогащено = sum(1 for з in записи
                    if (str(з.get("external_id") or ""), "kinopoisk") in текущие)
    return {
        "denominator": всего,
        "fromFeed": из_фида,
        "fromEnrichment": обогащено,
        "covered": из_фида + обогащено,
        "coveragePercent": round((из_фида + обогащено) / всего * 100, 1) if всего else 0.0,
        "observations": len(хранилище.наблюдения()),
    }
