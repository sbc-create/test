"""Нормализация названий — только для поиска кандидатов.

Отображаемое название не меняется никогда. Это правило, а не осторожность:
нормализация теряет сведения (регистр, пунктуацию, различие ё/е), а витрина
обязана показывать название так, как его дал источник. Нормализованные
варианты живут отдельным полем и используются исключительно при сопоставлении.

Одного совпадения русского названия недостаточно ни при каких условиях —
модуль даёт кандидатов, а решение принимает резолвер по совокупности
признаков. «Хищник» 1987 и «Хищник» 2018 нормализуются одинаково, и это
правильно: различает их год, а не написание.
"""

