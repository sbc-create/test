_ПУНКТУАЦИЯ = re.compile(r"[^\w\s]", re.UNICODE)
_ПРОБЕЛЫ = re.compile(r"\s+")
_ГОД_В_СКОБКАХ = re.compile(r"[\(\[]\s*(1[89]\d{2}|20\d{2})\s*[\)\]]")
_ЧАСТЬ = re.compile(
    r"\b(" + "|".join(PART_WORDS) + r")\s*[-–—:]?\s*(\d{1,2}|[ivxIVX]{1,6})\b",
    re.IGNORECASE | re.UNICODE,
)


def _nfkc(текст: str) -> str:
    return unicodedata.normalize("NFKC", текст)


def извлечь_год(название: str) -> tuple[str, int | None]:
    """Год из скобок. Возвращает название без него и сам год.

    Год в скобках — это не часть названия, а его уточнение, и оставлять его в
    строке значит промахиваться мимо той же записи без скобок.
    """
    совпадение = _ГОД_В_СКОБКАХ.search(название or "")
    if not совпадение:
        return (название or ""), None
    год = int(совпадение.group(1))
    return _ГОД_В_СКОБКАХ.sub(" ", название), год


def извлечь_части(название: str) -> tuple[str, dict[str, int]]:
    """Номера сезона, части и cour. Возвращает название без них и номера."""
    найдено: dict[str, int] = {}

    def заменить(m: re.Match) -> str:
        слово = m.group(1).lower()
        сырое = m.group(2)
        номер = ROMAN.get(сырое.lower()) if not сырое.isdigit() else int(сырое)
        if номер is None:
            return " "
        ключ = (
            "season"
            if слово in ("сезон", "season")
            else "cour"
            if слово in ("cour", "кур")
            else "part"
        )
        найдено.setdefault(ключ, номер)
        return " "

    return _ЧАСТЬ.sub(заменить, название or ""), найдено


def римские_в_арабские(текст: str) -> str:
    """«Рокки IV» и «Рокки 4» обязаны давать один ключ поиска."""
    слова = []
    for слово in (текст or "").split():
        номер = ROMAN.get(слово.lower())
        слова.append(str(номер) if номер is not None else слово)
    return " ".join(слова)


def убрать_пометки(текст: str) -> str:
    низ = (текст or "").lower()
    for метка in RELEASE_MARKERS:
        низ = низ.replace(метка, " ")
    return низ


def транслитерировать(текст: str) -> str:
    return "".join(TRANSLIT.get(с, с) for с in (текст or "").lower())


def базовая(название: str) -> str:
    """Регистр, пунктуация, пробелы. Ё и Е ещё различаются."""
    текст = _nfkc(название or "").lower()
    текст = _ПУНКТУАЦИЯ.sub(" ", текст)
    return _ПРОБЕЛЫ.sub(" ", текст).strip()


def ключ_поиска(название: str) -> str:
    """Ключ для поиска кандидатов. Ё сводится к Е — только здесь.

    В отображаемом названии этой замены нет и быть не может: «Ёлки» и «Елки»
    читателю не одно и то же, а искать по ним нужно вместе.
    """
    без_года, _ = извлечь_год(название or "")
    без_частей, _ = извлечь_части(без_года)
    текст = базовая(убрать_пометки(без_частей))
    текст = римские_в_арабские(текст)
    return _ПРОБЕЛЫ.sub(" ", текст.replace("ё", "е")).strip()


_ХВОСТОВОЙ_НОМЕР = re.compile(r"\s+\d{1,2}$")


def ключ_без_хвостового_номера(название: str) -> str:
    """Ключ без завершающего числа. Только для расширения списка кандидатов.

    Голое число в конце названия неоднозначно принципиально: в «Рокки 4» это
    часть названия, в «Атака титанов 3» — номер сезона. Отличить их по строке
    нельзя, и угадывать здесь нечего. Поэтому выдаются оба ключа, а решает
    резолвер по совокупности признаков — году, числу эпизодов, студии.

    Пустая строка означает, что убирать было нечего.
    """
    ключ = ключ_поиска(название)
    сокращённый = _ХВОСТОВОЙ_НОМЕР.sub("", ключ).strip()
    return сокращённый if сокращённый and сокращённый != ключ else ""


def ключ_транслита(название: str) -> str:
    """Ключ, сводящий кириллицу и латиницу. Для кросс-язычного поиска."""
    return _ПРОБЕЛЫ.sub(" ", транслитерировать(ключ_поиска(название))).strip()


def варианты(название: str) -> dict[str, object]:
    """Все нормализованные представления одного названия.

    Исходное значение сохраняется целиком: восстановить его из ключей
    невозможно, а показывать читателю нужно именно его.
    """
    без_года, год = извлечь_год(название or "")
    без_частей, части = извлечь_части(без_года)
    return {
        "source": название,
        "base": базовая(без_частей),
        "searchKey": ключ_поиска(название),
        "translitKey": ключ_транслита(название),
        "searchKeyNoTail": ключ_без_хвостового_номера(название),
        "yearInTitle": год,
        "parts": части,
    }


def ключи(названия) -> set[str]:
    """Множество ключей поиска по всем названиям записи.

    Пустые строки отбрасываются: пустой ключ совпал бы со всем сразу.
    """
    итог: set[str] = set()
    for название in названия or ():
        if not название:
            continue
        for ключ in (
            ключ_поиска(название),
            ключ_транслита(название),
            ключ_без_хвостового_номера(название),
        ):
            if ключ:
                итог.add(ключ)
    return итог
