"""Аттестация живого хоста и ворота релиза, которые её требуют.

Разделение, ради которого пакет существует.

Обычный прогон `pytest tests/` проверяет **воспроизводимые программные
контракты**: то, что верно в любом клоне репозитория на любой машине. Такой
прогон не обращается к `/srv/site-factory`, не требует живых systemd-юнитов,
боевых баз, реальных доменов и фиксированных портов.

Факты о живом флоте — перепись production, ответы публичных доменов, версия
работающего реестра, состояние резервной копии, слушатели и юниты — проверкой
кода не являются и в герметичном прогоне не проверяются. Но и исчезнуть они не
вправе: «не проверяли» и «проверили, всё хорошо» обязаны выглядеть по-разному.
Поэтому они вынесены в явно запускаемый host-контур (`bin/host-attest`),
который выпускает машиночитаемое свидетельство, а релиз без годного
свидетельства не выпускается — см. `gate`.

Что здесь есть:

* `contract` — форма свидетельства, перечень обязательных проверок, сборка и
  разбор; единственное место, где объявлено, что считается полным измерением;
* `gate` — ворота релиза, закрытые по умолчанию;
* `credential_boundary` — снятие и проверка границы учётных данных Templates.
"""
