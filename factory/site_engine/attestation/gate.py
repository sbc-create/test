"""Ворота релиза: без годного свидетельства о живом хосте выката нет.

Ворота закрыты по умолчанию. Это не осторожность, а единственная работающая
конструкция: свидетельство отсутствует ровно тогда, когда его не сняли, —
то есть когда о состоянии флота ничего не известно. Ворота, пропускающие
отсутствие, пропускают именно тот случай, ради которого они поставлены.

Пять способов, которыми свидетельство перестаёт что-либо значить, и все пять
блокируют выкат:

* его нет — никто не измерял;
* оно протухло — измеряли, но давно, и с тех пор флот мог стать другим;
* оно о другом дереве — измеряли не то, что выкатывают;
* оно неполно — часть обязательных проверок не выполнялась;
* в нём есть провалившаяся или недоступная обязательная проверка.

Отдельно: свидетельство, снятое не на control host, не принимается. Документ
объявленной формы получить легко где угодно; ценность ему придаёт то, что он
снят там, где живёт флот.
"""
from __future__ import annotations

import datetime as _dt
from pathlib import Path
from typing import Any

from . import contract as C

#: Сколько свидетельство считается свежим. Сутки — это «сегодняшнее утро ещё
#: годится, позавчерашнее нет». Значение задаётся здесь, а не по месту вызова:
#: срок годности доказательства — свойство доказательства.
МАКСИМАЛЬНЫЙ_ВОЗРАСТ = _dt.timedelta(hours=24)


class РелизЗаблокирован(Exception):
    """Выкат запрещён: свидетельства о живом хосте нет или оно негодно."""

    def __init__(self, код: str, detail: str,
                 required_input: str = "") -> None:
        super().__init__(f"{код}: {detail}")
        self.код = код
        self.detail = detail
        self.required_input = required_input or (
            "Снять свидетельство на control host: "
            "bin/host-attest --candidate-sha <sha>")


def _разобрать_время(значение: str, поле: str) -> _dt.datetime:
    try:
        момент = _dt.datetime.fromisoformat(значение.replace("Z", "+00:00"))
    except ValueError as ош:
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_MALFORMED",
            f"{поле} не разбирается как время: {значение!r}") from ош
    if момент.tzinfo is None:
        # Время без зоны нельзя сравнить ни с чем: «10:00» на хосте в другой
        # зоне — это не тот же момент. Догадка здесь стоила бы суток свежести.
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_MALFORMED",
            f"{поле} без часового пояса: момент измерения не определён")
    return момент


def загрузить(candidate_sha: str, *, каталог: Path | None = None
              ) -> dict[str, Any] | None:
    """Прочитать свидетельство для дерева. Отсутствие — не ошибка чтения."""
    путь = C.путь_свидетельства(candidate_sha, каталог)
    if not путь.is_file():
        return None
    return C.разобрать(путь.read_text(encoding="utf-8"))


def проверить(документ: dict[str, Any] | None, *, candidate_sha: str,
              сейчас_utc: _dt.datetime | None = None,
              максимальный_возраст: _dt.timedelta = МАКСИМАЛЬНЫЙ_ВОЗРАСТ,
              ) -> dict[str, Any]:
    """Допустить выкат дерева `candidate_sha` или отказать с точной причиной.

    Возвращает разобранное свидетельство — вызывающему есть что записать в
    отчёт. Отказ — всегда исключение: молчаливый «ложный» ответ рано или
    поздно кто-нибудь не проверит.
    """
    if документ is None:
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_MISSING",
            f"свидетельства о живом хосте для {candidate_sha} нет: "
            "состояние флота не измерялось")

    try:
        документ = C.разобрать(документ)
    except C.АттестацияНевалидна as ош:
        raise РелизЗаблокирован(ош.код, ош.detail) from ош

    if документ["candidate_sha"] != candidate_sha:
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_SHA_MISMATCH",
            f"свидетельство снято для {документ['candidate_sha']}, "
            f"а выкатывается {candidate_sha}")

    if not документ["host"]["control_host"]:
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_NOT_CONTROL_HOST",
            f"измерение выполнено на {документ['host']['hostname']}, "
            "который не объявлен control host: о боевом флоте это ничего не говорит")

    момент = _разобрать_время(документ["measured_at"], "measured_at")
    сейчас_utc = сейчас_utc or _dt.datetime.now(_dt.timezone.utc)
    возраст = сейчас_utc - момент
    if возраст > максимальный_возраст:
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_STALE",
            f"свидетельство измерено {документ['measured_at']}, "
            f"возраст {возраст} превышает допустимые {максимальный_возраст}")
    if возраст < -_dt.timedelta(minutes=5):
        # Измерение из будущего означает разъехавшиеся часы или подделанное
        # время. И то и другое лишает срок годности смысла.
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_MALFORMED",
            f"measured_at в будущем на {-возраст}: сроку годности верить нельзя")

    по_идентификатору = {п["check_id"]: п for п in документ["checks"]}
    if len(по_идентификатору) != len(документ["checks"]):
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_MALFORMED",
            "одна проверка записана дважды: какой из результатов действителен, "
            "документ не сообщает")

    нет = sorted(C.ОБЯЗАТЕЛЬНЫЕ - set(по_идентификатору))
    if нет:
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_INCOMPLETE",
            f"обязательные проверки не выполнялись: {', '.join(нет)}")

    неисправные = sorted(
        (п["check_id"], п["status"]) for п in документ["checks"]
        if п["required"] and п["status"] != "PASS")
    if неисправные:
        перечень = ", ".join(f"{cid}={ст}" for cid, ст in неисправные)
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_CHECK_FAILED",
            f"обязательные проверки не прошли: {перечень}")

    if документ["verdict"] != "PASS":
        # Сюда приходят только документы, где все обязательные проверки PASS.
        # Несовпадение вердикта значит, что его посчитали не по этим данным.
        raise РелизЗаблокирован(
            "HOST_ATTESTATION_MALFORMED",
            f"вердикт {документ['verdict']} не следует из результатов проверок")

    return документ


def допустить(*, candidate_sha: str, каталог: Path | None = None,
              сейчас_utc: _dt.datetime | None = None,
              максимальный_возраст: _dt.timedelta = МАКСИМАЛЬНЫЙ_ВОЗРАСТ,
              ) -> dict[str, Any]:
    """Загрузить свидетельство с диска и пропустить его через ворота."""
    return проверить(загрузить(candidate_sha, каталог=каталог),
                     candidate_sha=candidate_sha, сейчас_utc=сейчас_utc,
                     максимальный_возраст=максимальный_возраст)
