"""Канонический предикат отбора сайтов. Одна реализация на всех.

Зачем отдельный модуль
----------------------

Фильтр `/api/v1/sites` и проекция `/api/v1/registry/snapshot` отвечают на
один и тот же вопрос: какие записи считаются production ACTIVE. Две
независимо написанные реализации одного правила неизбежно разойдутся — и
разойдутся молча, потому что каждая по отдельности выглядит правильной.
Поэтому правило живёт здесь, а оба места его вызывают.

Почему перечни закрыты
----------------------

Неизвестное значение фильтра не игнорируется и не приводится к похожему.
Молча проигнорированный фильтр — это ответ на другой вопрос, выданный за
ответ на заданный: клиент попросил production, получил весь реестр и
посчитал двенадцать записей девятью. Приведение «Production» к
«production» не лучше: оно превращает опечатку в успех и прячет ошибку
вызывающего до того момента, когда она станет дорогой.
"""

from __future__ import annotations

#: Состояния жизненного цикла. Совпадают с CHECK-ограничением таблицы site:
#: перечень в коде, разошедшийся с перечнем в схеме, — это два источника правды.
LIFECYCLE_STATES: tuple[str, ...] = ("DRAFT", "ACTIVE", "QUARANTINED", "RETIRED")

#: Среды. Закрытый перечень: среда, которой здесь нет, не существует, и
#: запрос о ней — ошибка вызывающего, а не повод отдать всё подряд.
ENVIRONMENTS: tuple[str, ...] = ("production", "non-production", "test")

#: Каноническое определение «боевой действующий сайт». Ровно это множество
#: обязаны возвращать и фильтр, и снимок.
PRODUCTION_ACTIVE = {"environment": "production", "lifecycle_state": "ACTIVE"}


class FilterValidationError(ValueError):
    """Значение фильтра недопустимо. Несёт стабильный код ошибки."""

    def __init__(self, error_code: str, parameter: str, detail: str):
        super().__init__(detail)
        self.error_code = error_code
        self.parameter = parameter
        self.detail = detail


def _единственное(значение, параметр: str) -> str | None:
    """Одно значение параметра. Повтор ключа — ошибка, а не «последний победил».

    Два разных значения одного параметра означают, что вызывающий сам не
    знает, чего просит. Выбрать за него первое или последнее — значит
    ответить на вопрос, которого не задавали.
    """
    if значение is None:
        return None
    if isinstance(значение, (list, tuple)):
        уникальные = {str(v) for v in значение}
        if len(уникальные) > 1:
            raise FilterValidationError(
                "FILTER_VALUE_CONFLICT", параметр,
                f"параметр {параметр} повторён с разными значениями: "
                f"{sorted(уникальные)}")
        значение = значение[0] if значение else None
    if значение is None:
        return None
    текст = str(значение)
    if not текст.strip():
        raise FilterValidationError(
            "FILTER_VALUE_EMPTY", параметр,
            f"параметр {параметр} задан пустым значением")
    return текст


def validate_filters(params: dict | None) -> dict[str, str]:
    """Разобрать и проверить фильтры. Возвращает только заданные.

    Регистр не нормализуется намеренно: канонические значения объявлены, и
    `Production` — это не `production`, а опечатка.
    """
    params = params or {}
    итог: dict[str, str] = {}
    for параметр, допустимые in (("environment", ENVIRONMENTS),
                                 ("lifecycle_state", LIFECYCLE_STATES)):
        значение = _единственное(params.get(параметр), параметр)
        if значение is None:
            continue
        if значение not in допустимые:
            raise FilterValidationError(
                "FILTER_VALUE_UNKNOWN", параметр,
                f"значение {значение!r} не входит в перечень "
                f"{list(допустимые)}")
        итог[параметр] = значение
    return итог


def where_clause(фильтры: dict[str, str]) -> tuple[str, list]:
    """SQL-условие и параметры. Несколько фильтров соединяются через AND.

    Условие строится из объявленных имён столбцов, значения уходят
    параметрами: подстановка значения в текст запроса — это место, где
    чужая строка становится запросом.
    """
    части, значения = [], []
    for столбец in ("environment", "lifecycle_state"):
        if столбец in фильтры:
            части.append(f"{столбец} = ?")
            значения.append(фильтры[столбец])
    return (" AND ".join(части), значения)


def matches(запись: dict, фильтры: dict[str, str]) -> bool:
    """Тот же предикат в памяти — для проверок и клиентов."""
    return all(str(запись.get(k)) == v for k, v in фильтры.items())


def production_active_where() -> tuple[str, list]:
    """Условие канонической production-проекции. Используется снимком."""
    return where_clause(PRODUCTION_ACTIVE)
