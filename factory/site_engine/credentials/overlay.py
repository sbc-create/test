"""Подстановка секретов из credentials в конфигурацию службы.

Конфигурация Control API собирается из окружения — это нормально для путей,
флагов и адресов. Секретам там не место: `EnvironmentFile` отдаётся юниту
целиком, и токены управляющего слоя достались бы заодно мосту и рабочему
процессу, которым они не нужны ни для чего.

Поэтому секретные ключи конфигурации берутся из `$CREDENTIALS_DIRECTORY` и
накладываются поверх словаря настроек, а не поверх `os.environ`: окружение
процесса остаётся чистым, и потомок ничего не наследует.
"""
from __future__ import annotations

from factory.site_engine.credentials import store as C

#: Ключ конфигурации → имя credential. Только то, что действительно секрет:
#: пути к базам и флаги секретами не являются и остаются в конфигурации.
СООТВЕТСТВИЕ = {
    "SITE_ENGINE_CONTROL_TOKENS": "site-engine-control-tokens",
}


def наложить(настройки: dict[str, str]) -> dict[str, str]:
    """Вернуть копию настроек с секретами из credentials."""
    итог = dict(настройки)
    for ключ, имя in СООТВЕТСТВИЕ.items():
        значение = C.получить_или_none(имя)
        if значение:
            итог[ключ] = значение
    return итог


def секреты_в_окружении(настройки: dict[str, str]) -> list[str]:
    """Какие секретные ключи пришли из окружения, а не из credentials.

    Возвращаются ИМЕНА, не значения. Пустой список — то состояние, ради
    которого всё делается.
    """
    остались = []
    for ключ, имя in СООТВЕТСТВИЕ.items():
        if настройки.get(ключ) and not C.есть(имя):
            остались.append(ключ)
    return остались
