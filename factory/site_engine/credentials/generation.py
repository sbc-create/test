"""Поколение модели безопасности управляющего слоя.

Зачем нужен номер
-----------------

Откат возвращает КОД, но не возвращает решения о безопасности. Прежний релиз
знает, как принимать общий файл окружения, как подписывать присланное тело и
как выдавать двум процессам одну личность, — и после отката он снова начнёт
это уметь. Права и секреты монотонны по замыслу: однажды закрытое не должно
открываться само собой из-за смены символической ссылки.

Поэтому вместе с учётными данными на хосте хранится «пол» — минимальное
поколение, ниже которого выкладка не опускается. Проверяет его оснастка
выкладки, а не сам релиз: релиз, которому не доверяют, не может и проверить
себя.

Повышать `ПОКОЛЕНИЕ` следует тогда, когда изменение делает НЕБЕЗОПАСНОЙ любую
предыдущую версию, а не при каждой правке.
"""
from __future__ import annotations

import json
from pathlib import Path

#: 1 — общий EnvironmentFile, HMAC-подпись, общая личность публикаторов.
#: 2 — учётные данные по личностям, Ed25519 с kid и отзывом, раздельные
#:     личности публикаторов, служба подписи не принимает готовое тело.
ПОКОЛЕНИЕ = 2

СВОЙСТВА = (
    "per-identity-credentials",      # каждый сервис получает только своё
    "asymmetric-approval-signing",   # приватный ключ ровно у одного процесса
    "no-raw-payload-signing",        # служба подписи не заверяет присланное
    "split-publisher-identities",    # мост и рабочий процесс различимы
)

ФАЙЛ_ПОЛА = Path("/etc/site-factory/credentials/security-floor.json")


def пол(путь: Path | None = None) -> int:
    """Минимальное допустимое поколение. Ноль означает «пол не установлен»."""
    п = путь or ФАЙЛ_ПОЛА
    if not п.is_file():
        return 0
    try:
        return int(json.loads(п.read_text("utf-8")).get("generation", 0))
    except (ValueError, OSError):
        return 0


def поднять_пол(путь: Path | None = None) -> dict:
    """Записать пол не ниже текущего поколения. Понижение невозможно."""
    п = путь or ФАЙЛ_ПОЛА
    текущий = пол(п)
    новый = max(текущий, ПОКОЛЕНИЕ)
    п.parent.mkdir(parents=True, exist_ok=True)
    п.write_text(json.dumps({"generation": новый, "properties": list(СВОЙСТВА)},
                            ensure_ascii=False, indent=1) + "\n",
                 encoding="utf-8")
    return {"previous": текущий, "current": новый}


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "raise":
        print(json.dumps(поднять_пол(), ensure_ascii=False))
    else:
        print(json.dumps({"generation": ПОКОЛЕНИЕ, "floor": пол(),
                          "properties": list(СВОЙСТВА)}, ensure_ascii=False))
