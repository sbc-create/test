"""Выдача и ротация учётных данных по личностям.

Задача одна: у каждой личности — свой файл, и ни один процесс не получает
чужого. Общий `EnvironmentFile` этого не даёт по устройству: systemd отдаёт
файл целиком, поэтому «положим всё в одно место и раздадим нужное» —
невыполнимое обещание.

Ротация и отзыв здесь разделены сознательно. Замена значения сама по себе
ничего не отменяет: старый токен остаётся годным всюду, где переменную ещё
не перечитали. Поэтому отпечаток выводимого из обращения значения
записывается в список отозванных, и предъявивший его получает отказ
независимо от того, совпало ли оно с чьим-то прежним.

Значения не печатаются никогда. Наружу идут только имена, состояния и
двенадцать знаков отпечатка — по ним нельзя восстановить секрет, но можно
ответить «тот же ключ или другой».
"""
from __future__ import annotations

import hashlib
import json
import os
import secrets
import stat
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from factory.site_engine.approval import keyring as K

КОРЕНЬ = Path(os.environ.get("SITE_FACTORY_CREDENTIALS_DIR",
                             "/etc/site-factory/credentials"))
СТАРЫЙ_ОБЩИЙ = Path("/etc/site-factory/control-api.env")

#: Служебные личности журнала аудита. Каждая получает собственный файл.
ЛИЧНОСТИ = ("control-plane", "architect", "registry", "templates", "content",
            "seo", "monitoring", "backup", "integrations", "qwen")

ОТПЕЧАТКИ = "audit-token-fingerprints"
ПРИВАТНЫЙ = "approval-signing-key"
НАБОР = "approval-verify-keys"
ТОКЕН_SIGNER = "approval-signer-token"

#: Секреты, которые ПЕРЕНОСЯТСЯ без ротации. Токены управляющего слоя
#: выданы неизвестно кому за пределами этого хоста; сменить их здесь значило
#: бы отобрать доступ у того, кто о смене не узнает. Из общего файла они
#: уходят — это и убирает их у моста и рабочего процесса, — а ротация
#: принадлежит владельцу.
ПЕРЕНОСИМЫЕ = {"SITE_ENGINE_CONTROL_TOKENS": "site-engine-control-tokens"}


def _имя_файла(личность: str) -> str:
    return f"audit-token-{личность}"


def _отпечаток(значение: str) -> str:
    return hashlib.sha256(значение.encode("utf-8")).hexdigest()


@dataclass
class Итог:
    выдано: list[str]
    ротировано: list[str]
    отозвано_отпечатков: int
    активный_kid: str
    отозванные_kid: list[str]

    def в_json(self) -> str:
        return json.dumps({
            "issued": sorted(self.выдано),
            "rotated": sorted(self.ротировано),
            "revoked_fingerprints": self.отозвано_отпечатков,
            "active_kid": self.активный_kid,
            "revoked_kids": sorted(self.отозванные_kid),
        }, ensure_ascii=False, indent=1)


def _записать(путь: Path, содержимое: str, режим: int = 0o400) -> None:
    """Атомарно и сразу с правами: файл не должен и на миг быть открытым."""
    врем = путь.with_suffix(путь.suffix + ".new")
    старый = os.umask(0o077)
    try:
        врем.write_text(содержимое, encoding="utf-8")
        os.chmod(врем, режим)
        os.replace(врем, путь)
    finally:
        os.umask(старый)


def _значения_из_общего(имена: set[str]) -> dict[str, str]:
    """Значения указанных переменных. Наружу из модуля не возвращаются."""
    if not СТАРЫЙ_ОБЩИЙ.is_file():
        return {}
    try:
        содержимое = СТАРЫЙ_ОБЩИЙ.read_text("utf-8", errors="replace")
    except PermissionError:
        return {}
    итог = {}
    for строка in содержимое.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#") or "=" not in строка:
            continue
        имя, _, значение = строка.partition("=")
        имя = имя.strip()
        if имя in имена:
            итог[имя] = значение.strip().strip('"').strip("'")
    return итог


def _прочитать_старые_токены() -> dict[str, str]:
    """Отпечатки токенов из общего файла — чтобы отозвать их, а не показать.

    Значения не возвращаются: наружу уходит только хэш.
    """
    если_нет: dict[str, str] = {}
    if not СТАРЫЙ_ОБЩИЙ.is_file():
        return если_нет
    try:
        содержимое = СТАРЫЙ_ОБЩИЙ.read_text("utf-8", errors="replace")
    except PermissionError:
        # Не root — значит и отзывать по этому файлу нечего. Молча пропустить
        # правильнее, чем упасть: провизионер обязан быть запускаем и для
        # проверки состояния.
        return если_нет
    итог = {}
    for строка in содержимое.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#") or "=" not in строка:
            continue
        имя, _, значение = строка.partition("=")
        имя, значение = имя.strip(), значение.strip().strip('"').strip("'")
        if значение and (имя.startswith("AUDIT_TOKEN_")
                         or имя == "CHANGESET_APPROVAL_KEY"):
            итог[имя] = _отпечаток(значение)
    return итог


def выдать(*, ротировать: bool = True) -> Итог:
    """Создать каталог, выдать личности и ключи, отозвать прежние значения."""
    КОРЕНЬ.mkdir(parents=True, exist_ok=True)
    os.chmod(КОРЕНЬ, stat.S_IRWXU)          # 0700: читает только root

    прежние_отпечатки = _прочитать_старые_токены()

    # Прежний список отозванных сохраняется: отзыв не отменяется ротацией.
    прежний_реестр: dict[str, Any] = {}
    файл_отпечатков = КОРЕНЬ / ОТПЕЧАТКИ
    if файл_отпечатков.is_file():
        прежний_реестр = json.loads(файл_отпечатков.read_text("utf-8"))
    отозванные = set(прежний_реестр.get("revoked") or [])
    прежние_службы = dict(прежний_реестр.get("services") or {})

    выдано, ротировано = [], []
    службы: dict[str, str] = {}
    for личность in ЛИЧНОСТИ:
        путь = КОРЕНЬ / _имя_файла(личность)
        если_есть = путь.is_file()
        if если_есть and not ротировать:
            службы[личность] = _отпечаток(путь.read_text("utf-8").strip())
            continue
        if если_есть:
            # Выводим из обращения то, что было выдано раньше.
            отозванные.add(_отпечаток(путь.read_text("utf-8").strip()))
            ротировано.append(личность)
        else:
            выдано.append(личность)
        новое = secrets.token_urlsafe(48)
        _записать(путь, новое + "\n")
        службы[личность] = _отпечаток(новое)

    # Токены из общего файла отзываются независимо от того, совпали ли они
    # с чем-либо: они были выданы нескольким процессам сразу и считаются
    # скомпрометированными самим фактом такой выдачи.
    for имя, отпечаток in прежние_отпечатки.items():
        отозванные.add(отпечаток)
    # Прежние отпечатки из реестра тоже выводим из обращения.
    for личность, отпечаток in прежние_службы.items():
        if службы.get(личность) != отпечаток:
            отозванные.add(отпечаток)
    # Действующие значения отозванными быть не могут.
    отозванные -= set(службы.values())

    _записать(файл_отпечатков,
              json.dumps({"services": службы, "revoked": sorted(отозванные)},
                         ensure_ascii=False, indent=1) + "\n",
              режим=0o440)

    # --- ключ подписи одобрения ------------------------------------------
    файл_набора = КОРЕНЬ / НАБОР
    ключи: list[K.Ключ] = []
    прежний = (K.НаборКлючей.из_json(файл_набора.read_text("utf-8"))
               if файл_набора.is_file() else None)

    if not ротировать and прежний is not None and прежний.активный \
            and (КОРЕНЬ / ПРИВАТНЫЙ).is_file():
        # Режим «доведи до нужного состояния» не обязан ротировать ключ.
        # Иначе повторный запуск миграции молча сменил бы подпись и отозвал
        # все действующие одобрения — побочный эффект, которого никто не
        # просил и никто бы не заметил до первого отказа.
        return Итог(выдано=выдано, ротировано=ротировано,
                    отозвано_отпечатков=len(отозванные),
                    активный_kid=прежний.активный.kid,
                    отозванные_kid=[к.kid for к in прежний.ключи.values()
                                    if к.состояние == "REVOKED"])

    if прежний is not None:
        # Прежние ключи ОТЗЫВАЮТСЯ, а не просто выводятся из обращения:
        # старые одобрения должны перестать действовать.
        ключи = [K.Ключ(к.kid, к.публичный, "REVOKED", к.not_after)
                 for к in прежний.ключи.values()]
    новый_kid, pem, публичный = K.создать_ключ()
    ключи.append(K.Ключ(новый_kid, публичный, "ACTIVE"))
    _записать(КОРЕНЬ / ПРИВАТНЫЙ, pem)
    _записать(файл_набора, K.НаборКлючей(ключи).в_json() + "\n", режим=0o444)

    # Токен, которым Control API обращается к службе подписи.
    путь_signer = КОРЕНЬ / ТОКЕН_SIGNER
    if путь_signer.is_file():
        # Отзываем прежний: он тоже мог быть выдан не тому.
        prev = путь_signer.read_text("utf-8").strip()
        if prev:
            реестр = json.loads(файл_отпечатков.read_text("utf-8"))
            реестр["revoked"] = sorted(set(реестр["revoked"]) | {_отпечаток(prev)})
            _записать(файл_отпечатков,
                      json.dumps(реестр, ensure_ascii=False, indent=1) + "\n",
                      режим=0o440)
    _записать(путь_signer, secrets.token_urlsafe(48) + "\n")

    # --- перенос без ротации ---------------------------------------------
    перенесено = []
    исходные = _значения_из_общего(set(ПЕРЕНОСИМЫЕ))
    for переменная, имя in ПЕРЕНОСИМЫЕ.items():
        путь = КОРЕНЬ / имя
        if путь.is_file():
            continue
        значение = исходные.get(переменная, "")
        if значение:
            _записать(путь, значение + "\n")
            перенесено.append(имя)

    return Итог(выдано=выдано, ротировано=ротировано,
                отозвано_отпечатков=len(отозванные),
                активный_kid=новый_kid,
                отозванные_kid=[к.kid for к in ключи if к.состояние == "REVOKED"])


def состояние() -> dict[str, Any]:
    """Что выдано. Только имена, режимы и отпечатки."""
    if not КОРЕНЬ.is_dir():
        return {"root": str(КОРЕНЬ), "exists": False}
    файлы = []
    for п in sorted(КОРЕНЬ.iterdir()):
        if not п.is_file():
            continue
        ст = п.stat()
        запись = {"name": п.name, "mode": oct(stat.S_IMODE(ст.st_mode)),
                  "uid": ст.st_uid, "gid": ст.st_gid}
        if п.name not in (ОТПЕЧАТКИ, НАБОР):
            запись["fingerprint"] = _отпечаток(п.read_text("utf-8").strip())[:12]
        файлы.append(запись)
    набор = КОРЕНЬ / НАБОР
    ключи = []
    if набор.is_file():
        n = K.НаборКлючей.из_json(набор.read_text("utf-8"))
        ключи = [{"kid": к.kid, "state": к.состояние} for к in n.ключи.values()]
    return {"root": str(КОРЕНЬ), "exists": True, "mode": oct(
        stat.S_IMODE(КОРЕНЬ.stat().st_mode)), "files": файлы, "keys": ключи}


if __name__ == "__main__":
    import sys
    команда = sys.argv[1] if len(sys.argv) > 1 else "status"
    if команда == "issue":
        print(выдать(ротировать=True).в_json())
    elif команда == "ensure":
        print(выдать(ротировать=False).в_json())
    else:
        print(json.dumps(состояние(), ensure_ascii=False, indent=1))
