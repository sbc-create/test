"""Поправки года и вида записи, СВЕРЕННЫЕ с источником, — по id поставщика.

Зачем этот слой вообще нужен
----------------------------

Год записи приезжает из ответа поставщика (`year` в его карточке, рядом лежит
`premiere_date`), и у продолжений он несёт дату ПЕРВОЙ части франшизы.
Измерено 20.10 на `animedia-01` штатным путём к источнику (D199):

    rukovodstvo-soten-demonov-4   поставщик 2020 (premiere_date 2020-04-25)
                                  источник  2024-02-23 → 2024
    skazaniya-o-demonah-i-bogah-8 поставщик 2017, источник 2024
    zabyt-proshloe-5              поставщик 1909, источник 2006

Из 14 строгих кандидатов внутреннего признака (`franchise-year-order.py`)
сверка с источником подтвердила 7 неверных и сняла 7. Витрина печатает этот год
сама («аниме-сериал 2020 года» в заголовке и ссылка `/catalog/?year=2020`), а
ворота качества ТРЕБУЮТ назвать снимковый год в тексте — то есть неверный год
не просто неточность, он заставляет автора написать ложный факт.

Почему поправка, а не правка снимка
-----------------------------------

Снимок витрины (`<site_id>-details.json`) принадлежит суточному конвейеру и
приезжает доставкой целиком: значение, записанное прямо в него, исчезает к
утру. Правка ответа поставщика нам не принадлежит вовсе. Поэтому поправка
лежит в репозитории (`config/anime-year-corrections.json`), применяется при
СБОРКЕ каталога и переживает любую доставку.

Три свойства, без которых это была бы подстановка
-------------------------------------------------

1. **Ключ — постоянный id поставщика, а не слаг.** Слаг может переехать на
   другое произведение (так было с `dlya-tebya-vo-vsem-cvetu-2` при миграции
   реестра), и тогда поправка приписала бы год чужой записи. По тем же
   соображениям наследуется постер — строго по совпадению `id`.
2. **Поправка знает, ОТ какого значения она исправляет.** Если поставщик с
   момента замера сменил год, поправка НЕ применяется: он мог исправиться сам,
   возможно на третье значение, и перетирать его замером недельной давности
   нельзя. Такой случай считается отдельно (`year_correction_stale`) и обязан
   быть виден в отчёте.
3. **Каждая поправка называет источник и дату замера.** Запись без
   `source_url` и `measured_at` отвергается при загрузке: год без источника —
   это и есть выдуманный факт.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПУТЬ = КОРЕНЬ / "config" / "anime-year-corrections.json"

#: Что считается годом. Шире — не год, а опечатка.
ГОД_ОТ, ГОД_ДО = 1900, 2100

#: Вид записи в снимке. Словарь закрыт: в нём ровно два значения, и `ona`,
#: `ova`, `special` в нём невыразимы — это предел словаря, а не ошибка записи.
ВИДЫ = ("tv", "movie")


class ПоправкаОтвергнута(ValueError):
    """Запись поправок не принята — применять её нельзя."""


@dataclass(frozen=True)
class Поправка:
    ид: str
    год_поставщика: int | None
    год_источника: int | None
    вид_поставщика: str | None
    вид_источника: str | None
    источник: str
    замерено: str
    слаг_при_замере: str
    сопоставление: str

    @property
    def метка(self) -> str:
        return f"{self.источник} ({self.замерено})"


def _целый_год(значение, где: str) -> int | None:
    if значение is None:
        return None
    if not isinstance(значение, int) or not (ГОД_ОТ < значение < ГОД_ДО):
        raise ПоправкаОтвергнута(f"{где}: {значение!r} — это не год")
    return значение


def _вид(значение, где: str) -> str | None:
    if значение is None:
        return None
    if значение not in ВИДЫ:
        raise ПоправкаОтвергнута(
            f"{где}: вид {значение!r} вне словаря снимка {ВИДЫ}")
    return значение


def разобрать(документ: dict) -> dict[str, Поправка]:
    """{id поставщика: Поправка}. Неполная запись отвергается, а не пропускается."""
    записи = документ.get("corrections")
    if not isinstance(записи, list):
        raise ПоправкаОтвергнута("нет списка `corrections`")
    итог: dict[str, Поправка] = {}
    for н, з in enumerate(записи):
        где = f"corrections[{н}]"
        if not isinstance(з, dict):
            raise ПоправкаОтвергнута(f"{где}: не объект")
        ид = str(з.get("id") or "").strip()
        if not ид:
            raise ПоправкаОтвергнута(f"{где}: нет id записи поставщика")
        if ид in итог:
            raise ПоправкаОтвергнута(f"{где}: id {ид} встречается дважды")
        for обязательное in ("source_url", "measured_at", "matching"):
            if not str(з.get(обязательное) or "").strip():
                raise ПоправкаОтвергнута(
                    f"{где}: нет `{обязательное}` — год без источника и даты"
                    " замера это выдуманный факт")
        год_и = _целый_год(з.get("year_source"), f"{где}.year_source")
        вид_и = _вид(з.get("type_source"), f"{где}.type_source")
        if год_и is None and вид_и is None:
            raise ПоправкаОтвергнута(
                f"{где}: поправка ничего не исправляет (нет ни year_source,"
                " ни type_source)")
        итог[ид] = Поправка(
            ид=ид,
            год_поставщика=_целый_год(з.get("year_provider"),
                                      f"{где}.year_provider"),
            год_источника=год_и,
            вид_поставщика=_вид(з.get("type_provider"), f"{где}.type_provider"),
            вид_источника=вид_и,
            источник=str(з["source_url"]),
            замерено=str(з["measured_at"]),
            слаг_при_замере=str(з.get("slug_at_measure") or ""),
            сопоставление=str(з["matching"]),
        )
    return итог


def загрузить(путь: Path | None = None) -> dict[str, Поправка]:
    """Поправки из файла. Нет файла — пустой набор, и это не ошибка."""
    ф = путь or ПУТЬ
    if not ф.exists():
        return {}
    return разобрать(json.loads(ф.read_text(encoding="utf-8")))


def применить(поправки: dict[str, Поправка], ид, год_поставщика,
             вид_поставщика=None) -> tuple[int | None, str | None, str]:
    """(год, вид, источник_года).

    `источник_года` — одно из:

    * `"provider"` — поправки нет, значение поставщика сохранено как есть;
    * `"<url> (<дата замера>)"` — применена сверенная поправка;
    * `"provider/stale-correction"` — поправка ЕСТЬ, но поставщик сменил
      значение после замера, и перетирать его нельзя.
    """
    п = поправки.get(str(ид))
    if п is None:
        return год_поставщика, вид_поставщика, "provider"
    устарела = (п.год_источника is not None
                and п.год_поставщика is not None
                and год_поставщика != п.год_поставщика)
    устарела = устарела or (п.вид_источника is not None
                            and п.вид_поставщика is not None
                            and вид_поставщика != п.вид_поставщика)
    if устарела:
        return год_поставщика, вид_поставщика, "provider/stale-correction"
    год = п.год_источника if п.год_источника is not None else год_поставщика
    вид = п.вид_источника if п.вид_источника is not None else вид_поставщика
    return год, вид, п.метка
