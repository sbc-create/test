"""Единое versioned-отображение сущности каталога в адрес витрины.

Зачем одно место
----------------

Адрес карточки, перечень маршрутов и разрешение адреса рантаймом обязаны
происходить из ОДНОГО правила. Пока их было три — генератор списков брал
полный каталог, генератор страниц брал выборку, а рантайм раздавал файлы, —
рассогласование жило на стыке и не обнаруживалось ни одной из трёх сторон:
каждая была исправна по-своему.

Идентичность сущности, а не домен
---------------------------------

Ключ — стабильный слаг произведения. Домен в адрес не входит и входить не
должен: одна и та же сущность на трёх витринах обязана иметь один и тот же
маршрут, иначе переезд домена переписывал бы все ссылки.

Детерминированность
-------------------

Один и тот же вход даёт один и тот же перечень и один и тот же отпечаток.
Отпечаток карты — то, чем релиз сверяется сам с собой: несовпадение означает,
что карточки и страницы собраны из разных списков.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass

ВЕРСИЯ = "lords-urlmap/1.0.0"

#: Допустимый вид слага. Всё прочее адресом не становится: адрес, собранный
#: из непроверенной строки, однажды окажется чужим путём.
СЛАГ = re.compile(r"^[a-z0-9][a-z0-9\-]{0,190}$")
ПРЕФИКС = "/title/"


class UrlMapError(ValueError):
    def __init__(self, код: str, детали: str):
        super().__init__(детали)
        self.error_code, self.detail = код, детали


def нормализовать(адрес: str) -> str:
    """Канонический вид адреса. Совпадает с правилом рантайма."""
    а = (адрес or "/").split("#")[0].split("?")[0]
    while "//" in а:
        а = а.replace("//", "/")
    if not а.startswith("/"):
        а = "/" + а
    а = а.lower()
    if а != "/" and "." not in а.rsplit("/", 1)[-1] and not а.endswith("/"):
        а += "/"
    return а


def маршрут(slug: str) -> str:
    """Единственное определение канонического адреса произведения."""
    s = (slug or "").strip().lower()
    if not СЛАГ.match(s):
        raise UrlMapError("SLUG_INVALID",
                          f"слаг {slug!r} не является идентичностью сущности")
    return f"{ПРЕФИКС}{s}/"


def слаг_из_маршрута(адрес: str) -> str | None:
    а = нормализовать(адрес)
    if not а.startswith(ПРЕФИКС):
        return None
    хвост = а[len(ПРЕФИКС):].strip("/")
    return хвост if хвост and "/" not in хвост else None


@dataclass(frozen=True)
class Карта:
    """Перечень канонических маршрутов опубликованных сущностей."""
    version: str
    routes: tuple[tuple[str, str], ...]        # (slug, route), отсортировано

    @property
    def слаги(self) -> frozenset[str]:
        return frozenset(с for с, _ in self.routes)

    @property
    def адреса(self) -> frozenset[str]:
        return frozenset(а for _, а in self.routes)

    def в_словарь(self) -> dict:
        return {"version": self.version,
                "routes": {с: а for с, а in self.routes}}

    @property
    def отпечаток(self) -> str:
        сырое = json.dumps(self.в_словарь(), ensure_ascii=False, sort_keys=True,
                           separators=(",", ":"))
        return hashlib.sha256(сырое.encode("utf-8")).hexdigest()


def построить(слаги) -> Карта:
    """Карта маршрутов по множеству опубликованных сущностей.

    Порядок фиксирован сортировкой: перечень, зависящий от порядка обхода,
    давал бы разный отпечаток при одном и том же содержимом.
    """
    уникальные = sorted({(s or "").strip().lower() for s in слаги if s})
    пары, занятые = [], {}
    for s in уникальные:
        а = маршрут(s)
        if а in занятые:
            raise UrlMapError(
                "ROUTE_COLLISION",
                f"адрес {а} занят сущностями {занятые[а]!r} и {s!r}")
        занятые[а] = s
        пары.append((s, а))
    return Карта(version=ВЕРСИЯ, routes=tuple(пары))


@dataclass(frozen=True)
class Паритет:
    orphan_targets: tuple[str, ...]     # карточка есть, маршрута нет
    unreferenced_routes: tuple[str, ...]  # маршрут есть, карточки нет
    collisions: tuple[str, ...]

    @property
    def ок(self) -> bool:
        return not self.orphan_targets and not self.collisions


def паритет(цели_карточек, карта: Карта) -> Паритет:
    """Сходятся ли адреса карточек с перечнем маршрутов.

    Маршрут без карточки нарушением не является: страница может быть доступна
    по прямому адресу и не попадать ни в один список. Карточка без маршрута —
    является всегда: это обещание страницы, которой нет.
    """
    цели = {нормализовать(ц) for ц in цели_карточек}
    адреса = карта.адреса
    осиротевшие = tuple(sorted(цели - адреса))
    неупомянутые = tuple(sorted(адреса - цели))
    return Паритет(orphan_targets=осиротевшие,
                   unreferenced_routes=неупомянутые, collisions=())


# ---------------------------------------------------------------------------
# Назначение адресов: разрешение коллизий естественных слагов
# ---------------------------------------------------------------------------
#
# Прежнее правило давало второму совпадению позиционный суффикс `-2`. У него
# два независимых порока, и оба наблюдались на живом каталоге.
#
# Первый: суффикс зависит от порядка входных записей. Перестановка снимка
# меняла владельца адреса, то есть публичный URL произведения. Адрес,
# зависящий от порядка строк в выгрузке, стабильным не является.
#
# Второй: `-2` попадает в настоящее название. «Акулы» получали `akuly-2`,
# который уже принадлежит фильму «Акулы 2». На полном каталоге таких
# столкновений 206, и разрешались они молча — словарь `by_slug` оставлял
# последнюю запись, и по адресу сиквела открывалась чужая карточка. Ровно
# это и есть wrong-entity 200: код ответа верный, сущность чужая.
#
# Здесь разделителем служит двойной дефис. `slugify` схлопывает подряд идущие
# дефисы, поэтому естественный слаг не может содержать `--` ни при каком
# названии: столкновение суффикса с настоящим названием исключено строением,
# а не проверкой постфактум.

РАЗДЕЛИТЕЛЬ = "--"

#: Признаки различения перебираются в этом порядке. Каждый следующий строго
#: информативнее предыдущего; последний — канонический идентификатор, который
#: уникален всегда.
ПРИЗНАКИ = ("year", "year_kind", "id8", "id")


def нормализовать_слаг(slug: str) -> str:
    """Вид слага для ПОИСКА скрытых столкновений.

    Сравнивать надо не байты: `Ё`/`Е`, регистр, составные формы Unicode и
    повторные дефисы дают разные строки и один и тот же публичный адрес.
    Эта функция приводит их к общему виду и применяется только для проверки
    уникальности — адресом становится исходный слаг, а не результат.
    """
    import unicodedata
    s = unicodedata.normalize("NFC", (slug or "")).casefold().replace("ё", "е")
    while "--" in s:
        s = s.replace("--", "-")
    return s.strip("-")


def _вариант(основа: str, запись: dict, признак: str) -> str | None:
    ид = (запись.get("external_id") or "").replace("-", "")
    if признак == "year":
        год = запись.get("year")
        return f"{основа}{РАЗДЕЛИТЕЛЬ}{год}" if год else None
    if признак == "year_kind":
        год, вид = запись.get("year"), (запись.get("type") or "").lower()
        вид = re.sub(r"[^a-z0-9]+", "", вид)
        return f"{основа}{РАЗДЕЛИТЕЛЬ}{год}{РАЗДЕЛИТЕЛЬ}{вид}" if год and вид else None
    if признак == "id8":
        return f"{основа}{РАЗДЕЛИТЕЛЬ}{ид[:8]}" if len(ид) >= 8 else None
    if признак == "id":
        return f"{основа}{РАЗДЕЛИТЕЛЬ}{ид}" if ид else None
    return None


@dataclass(frozen=True)
class Назначение:
    """Кому какой адрес и почему."""
    by_id: dict                      # external_id -> slug
    natural: dict                    # external_id -> естественный слаг
    groups: int                      # групп коллизий естественных слагов
    affected: int                    # сущностей в этих группах
    from_ledger: int                 # закреплённых назначений применено
    disambiguated: int               # сущностей получили признак различения
    by_feature: dict                 # признак -> сколько раз пригодился


def назначить(записи, *, закреплённые: dict | None = None,
              слаг_из=None) -> Назначение:
    """Слаг каждой сущности: устойчивый, различающий и не зависящий от порядка.

    `закреплённые` — карта `external_id -> slug`, снятая с действующей
    выкладки. Она существует не ради алгоритма, а ради людей: адрес, который
    уже опубликован и проиндексирован, менять без нужды нельзя. Всё, чего в
    ней нет, назначается правилом ниже, поэтому новые сущности не требуют
    ручного вмешательства.

    Порядок разрешения внутри группы задаётся старшинством записи — датой
    регистрации, а при равенстве каноническим идентификатором. Не позицией во
    входе: только так перестановка снимка оставляет адреса на месте. И именно
    старшинством, а не одним идентификатором: по идентификатору новая запись
    могла бы отсортироваться первой и забрать адрес у произведения, которое
    уже год как опубликовано по нему.
    """
    закреплённые = закреплённые or {}
    получить_слаг = слаг_из or (lambda з: з.get("slug"))

    естественные: dict[str, str] = {}
    порядок: list[str] = []
    по_основе: dict[str, list[str]] = {}
    сведения: dict[str, dict] = {}
    for з in записи:
        ид = з.get("external_id")
        if not ид:
            raise UrlMapError("ENTITY_WITHOUT_CANONICAL_ID",
                              "запись без external_id не может получить адрес")
        if ид in сведения:
            raise UrlMapError("DUPLICATE_CANONICAL_ID",
                              f"идентификатор {ид} встречается дважды")
        основа = получить_слаг(з)
        if not основа:
            raise UrlMapError("SLUG_SOURCE_EMPTY",
                              f"у {ид} нет основы слага")
        сведения[ид] = з
        естественные[ид] = основа
        порядок.append(ид)
        по_основе.setdefault(основа, []).append(ид)

    группы = {о: ии for о, ии in по_основе.items() if len(ии) > 1}
    занято_точно: dict[str, str] = {}
    занято_норм: dict[str, str] = {}
    результат: dict[str, str] = {}
    счёт_признаков: dict[str, int] = {}
    из_ledger = 0
    различено = 0

    def занять(ид: str, слаг: str) -> bool:
        н = нормализовать_слаг(слаг)
        if слаг in занято_точно or н in занято_норм:
            return False
        занято_точно[слаг] = ид
        занято_норм[н] = ид
        результат[ид] = слаг
        return True

    # 1) Закреплённые адреса — первыми и без обсуждения: они уже публичны.
    for ид in порядок:
        зкр = закреплённые.get(ид)
        if зкр and занять(ид, зкр):
            из_ledger += 1

    # 2) Одиночки берут естественный слаг.
    for основа, ии in sorted(по_основе.items()):
        if len(ии) > 1:
            continue
        ид = ии[0]
        if ид in результат:
            continue
        if not занять(ид, основа):
            # Естественный слаг занят закреплённым назначением другой
            # сущности — различаем эту, а не отбираем чужой адрес.
            for признак in ПРИЗНАКИ:
                в = _вариант(основа, сведения[ид], признак)
                if в and занять(ид, в):
                    счёт_признаков[признак] = счёт_признаков.get(признак, 0) + 1
                    различено += 1
                    break
            else:
                raise UrlMapError("ROUTE_ASSIGNMENT_EXHAUSTED",
                                  f"для {ид} не нашлось свободного адреса")

    # 3) Группы: владелец основы определяется каноническим идентификатором.
    def старшинство(ид: str):
        з = сведения[ид]
        return (str(з.get("created_at") or "9999"), ид)

    for основа, ии in sorted(группы.items()):
        оставшиеся = [и for и in sorted(ии, key=старшинство)
                      if и not in результат]
        if основа not in занято_точно and оставшиеся:
            владелец = оставшиеся[0]
            занять(владелец, основа)
            оставшиеся = оставшиеся[1:]
        for ид in оставшиеся:
            for признак in ПРИЗНАКИ:
                в = _вариант(основа, сведения[ид], признак)
                if в and занять(ид, в):
                    счёт_признаков[признак] = счёт_признаков.get(признак, 0) + 1
                    различено += 1
                    break
            else:
                raise UrlMapError("ROUTE_ASSIGNMENT_EXHAUSTED",
                                  f"для {ид} не нашлось свободного адреса")

    if len(результат) != len(порядок):
        потеряны = [и for и in порядок if и not in результат]
        raise UrlMapError("ENTITY_LOST",
                          f"без адреса осталось сущностей: {len(потеряны)}")
    return Назначение(by_id=результат, natural=естественные, groups=len(группы),
                      affected=sum(len(и) for и in группы.values()),
                      from_ledger=из_ledger, disambiguated=различено,
                      by_feature=счёт_признаков)
