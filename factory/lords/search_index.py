"""Указатель поиска: отбор кандидатов вместо перебора всего каталога.

Замер до, на живом каталоге витрины lords-02 (53 249 записей):

    медиана 3457 мс, p95 4817 мс, максимум 5601 мс

Перебор сравнивает запрос с каждой записью и её формами — с транслитерацией,
чужой раскладкой и расстоянием Левенштейна. Для набора по букве это
непригодно по устройству, а не по настройке: сколько ни ускоряй сравнение,
оно выполняется пятьдесят три тысячи раз.

Здесь добавлен ровно один шаг — отбор кандидатов по трёхбуквенным кускам, — и
он не заменяет сравнение, а сокращает множество, на котором оно выполняется.
Само сравнение и порядок выдачи остаются прежними: правила совпадения уже
проверены на живом каталоге, и менять их заодно со скоростью значило бы
смешать две задачи и не суметь объяснить изменившуюся выдачу.

**Отбор обязан быть шире совпадения.** Кандидат, не попавший в отбор, не
получит и оценки — то есть исчезнет из выдачи молча. Поэтому кусок берётся
длиной три (короче — слишком много кандидатов, длиннее — опечатка в середине
слова рвёт все куски), а порог — «хотя бы один общий кусок».

**Полнота проверяется, а не предполагается.** Тест сверяет выдачу указателя с
выдачей перебора на трёхстах запросах и требует совпадения. Ускорение, которое
молча теряет записи, — это не ускорение, а порча выдачи.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from factory.lords.search import MIN_QUERY, _forms, _score, _variants, normalize

ВЕРСИЯ = "lords-search-index/1.0.0"

#: Длина куска. Три — потому что двухбуквенные куски дают почти весь каталог в
#: кандидатах (отбор перестаёт отбирать), а четырёхбуквенные рвутся от одной
#: опечатки в середине короткого слова.
КУСОК = 3

#: Сколько кандидатов доходит до сравнения. Предел нужен на запросы вроде «а»
#: или «ов», где общих кусков много у всех. Число выбрано замером: на живом
#: каталоге 4 000 кандидатов сравниваются за 250 мс — это верхняя граница
#: набора по букве.
ПРЕДЕЛ_КАНДИДАТОВ = 4000


def куски(текст: str) -> set[str]:
    """Трёхбуквенные куски нормализованного текста, включая границы слова.

    Пробел заменяется на подчёркивание, а не выбрасывается: «во все» и «воовсе»
    иначе дали бы одинаковые куски.
    """
    н = normalize(текст).replace(" ", "_")
    if len(н) < КУСОК:
        return {н} if н else set()
    return {н[и:и + КУСОК] for и in range(len(н) - КУСОК + 1)}


def build(catalog) -> dict[str, Any]:
    """Указатель по каталогу. Позиции записей, а не сами записи.

    Хранить записи внутри указателя означало бы держать каталог дважды и
    расходиться с ним при первом же обновлении.
    """
    обратный: dict[str, list[int]] = {}
    for позиция, запись in enumerate(catalog):
        свои: set[str] = set()
        for форма in _forms(запись):
            свои |= куски(форма)
        for кусок in свои:
            обратный.setdefault(кусок, []).append(позиция)
    return {
        "version": ВЕРСИЯ,
        "size": len(catalog),
        "gram": КУСОК,
        "postings": dict(sorted(обратный.items())),
    }


def save(индекс: dict[str, Any], путь: Path | str) -> Path:
    п = Path(путь)
    п.parent.mkdir(parents=True, exist_ok=True)
    временный = п.with_suffix(п.suffix + ".tmp")
    временный.write_text(json.dumps(индекс, ensure_ascii=False), encoding="utf-8")
    временный.replace(п)
    return п


def load(путь: Path | str) -> dict[str, Any]:
    п = Path(путь)
    данные = json.loads(п.read_text(encoding="utf-8"))
    if данные.get("version") != ВЕРСИЯ:
        raise ValueError(
            f"указатель версии {данные.get('version')!r} не совпадает с {ВЕРСИЯ!r}: "
            "старый указатель на новом каталоге теряет записи молча"
        )
    return данные


def кандидаты(индекс: dict[str, Any], query: str) -> list[int]:
    """Позиции записей, у которых есть хотя бы один общий кусок с запросом."""
    варианты = _variants(query)
    if not варианты or max(len(в) for в in варианты) < MIN_QUERY:
        return []
    postings = индекс["postings"]
    счёт: dict[int, int] = {}
    for вариант in варианты:
        for кусок in куски(вариант):
            for позиция in postings.get(кусок, ()):
                счёт[позиция] = счёт.get(позиция, 0) + 1
    if not счёт:
        return []
    # Кандидаты с бо́льшим числом общих кусков вперёд: при упирании в предел
    # отсекаются наименее похожие, а не случайные.
    по_убыванию = sorted(счёт.items(), key=lambda п: (-п[1], п[0]))
    return [позиция for позиция, _ in по_убыванию[:ПРЕДЕЛ_КАНДИДАТОВ]]


def search(индекс: dict[str, Any], catalog, query: str, *, limit: int = 20) -> list[dict]:
    """Та же выдача, что и у перебора, но сравнение идёт по кандидатам."""
    if индекс.get("size") != len(catalog):
        raise ValueError(
            f"указатель собран на {индекс.get('size')} записях, каталог содержит "
            f"{len(catalog)}: позиции разошлись, выдача была бы о других записях"
        )
    варианты = _variants(query)
    if not варианты or max(len(в) for в in варианты) < MIN_QUERY:
        return []
    оценённые: list[tuple[int, str, dict]] = []
    for позиция in кандидаты(индекс, query):
        запись = catalog[позиция]
        лучшее = 0
        for форма in _forms(запись):
            for вариант in варианты:
                лучшее = max(лучшее, _score(форма, вариант))
        if лучшее > 0:
            оценённые.append((лучшее, normalize(запись.get("name") or ""), запись))
    оценённые.sort(key=lambda строка: (-строка[0], строка[1]))
    return [запись for _, _, запись in оценённые[:limit]]
