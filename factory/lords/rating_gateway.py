"""Шлюз вторичных источников оценок для витрин Nova.

Зачем
-----

Основной поставщик отдаёт оценку Кинопоиска у 36.68 % каталога и IMDb у
50.66 %. Это его потолок: адресный опрос 673 записей, у которых внешний
идентификатор есть, а оценки нет, добыл ноль значений; в `titles/filters` нет
даже фасета оценки. Поднять покрытие можно только другим источником.

Другого источника сейчас нет — ни учётных данных в Secret Hub, ни адаптера в
реестре. Заводить его самостоятельно задача запрещает, и правильно: это
внешняя учётная запись, а не строчка кода.

Поэтому здесь готово всё, кроме самой учётной записи. Когда владелец решит
подключить провайдера, останется зарегистрировать адаптер и завести
направление в Secret Hub — без правок в конвейере публикации.

Чего этот модуль не делает
--------------------------

* **не сопоставляет по названию.** Привязка только по стабильному внешнему
  идентификатору. Совпадение названий — повод для кандидата, а не для оценки:
  «Мышеловка» 1963 года и «Мышеловка» 2021-го получили бы чужие числа;
* **не перезаписывает первичное значение.** Оценка основного поставщика
  остаётся на месте. Вторичный источник заполняет только пустое — иначе
  витрина начала бы показывать то одно число, то другое в зависимости от
  того, какой прогон был последним;
* **не смешивает источники.** Каждый источник хранится отдельно и со своим
  происхождением. Записать оценку TMDb в поле Кинопоиска значит соврать о
  происхождении числа, и обнаружится это не скоро;
* **не считает ноль оценкой.** Ноль, пустая строка и нечисловое значение —
  отсутствие, а не оценка в ноль баллов;
* **не молчит.** Каждая непринятая оценка получает код причины: «не пришло»
  и «пришло и отвергнуто» — разные события.

Без зарегистрированных поставщиков модуль ничего не делает и ничего не
меняет: это его нормальное состояние сегодня.
"""
from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any, Protocol, runtime_checkable

#: Ключи внешних идентификаторов, по которым вообще можно привязываться.
#: Список закрыт намеренно: привязка по чему-то ещё — это привязка по догадке.
КЛЮЧИ_ПРИВЯЗКИ = ("kinopoisk", "imdb", "tmdb", "mal", "mydramalist")

#: Имена источников оценок. Поле витрины у каждого своё, и смешивать их нельзя.
ИСТОЧНИК_КП = "kinopoisk"
ИСТОЧНИК_IMDB = "imdb"

#: Куда ложится значение источника в плоских полях бокового файла. Источник,
#: которого здесь нет, хранится только в разрезе по источникам и в плоское
#: поле не попадает: у него нет своего поля на витрине.
ПЛОСКОЕ_ПОЛЕ = {ИСТОЧНИК_КП: "kinopoisk_rating", ИСТОЧНИК_IMDB: "imdb_rating"}

# Коды причин. Без них «не применено 12 000» — это не отчёт, а его видимость.
НЕТ_ВНЕШНЕГО_ИД = "NO_EXTERNAL_ID"
УЖЕ_ЕСТЬ = "ALREADY_PRESENT_FROM_PRIMARY"
НЕ_ОТДАЛ = "NOT_AVAILABLE_AT_SOURCE"
ВНЕ_ДИАПАЗОНА = "OUT_OF_RANGE"
НЕ_ЧИСЛО = "NOT_NUMERIC"
ЧУЖОЙ_ИД = "IDENTIFIER_MISMATCH"
БЮДЖЕТ = "BUDGET_EXHAUSTED"


class RatingGatewayError(RuntimeError):
    """Нарушение контракта шлюза: прогон прекращается, а не продолжается."""


@dataclass(frozen=True)
class ОценкаИсточника:
    """Одно значение с полным происхождением.

    Происхождение не украшение отчёта: без него нельзя ни перепроверить
    число, ни отличить свежее от протухшего, ни понять, кому писать, когда
    оценка окажется неверной.
    """
    source: str
    provider: str
    external_id: str
    value: float
    scale: float = 10.0
    votes: int | None = None
    retrieved_at: str = ""

    def as_dict(self) -> dict[str, Any]:
        d = {"source": self.source, "provider": self.provider,
             "external_id": self.external_id, "value": self.value,
             "scale": self.scale, "retrieved_at": self.retrieved_at}
        if self.votes is not None:
            d["votes"] = self.votes
        return d


@runtime_checkable
class ПоставщикОценок(Protocol):
    """Что обязан уметь вторичный источник, чтобы его пустили в конвейер."""

    #: Имя адаптера — оно попадёт в происхождение каждой оценки.
    имя: str
    #: По какому внешнему идентификатору он ищет.
    ключ_привязки: str
    #: Какие источники оценок он отдаёт.
    отдаёт: tuple[str, ...]

    def оценки(self, запрос: list[str]) -> dict[str, list[ОценкаИсточника]]:
        """Значения по внешним идентификаторам. Чего нет — того нет в ответе."""


_РЕЕСТР: dict[str, ПоставщикОценок] = {}


def зарегистрировать(поставщик: ПоставщикОценок) -> None:
    if поставщик.ключ_привязки not in КЛЮЧИ_ПРИВЯЗКИ:
        raise RatingGatewayError(
            f"{поставщик.имя}: привязка по «{поставщик.ключ_привязки}» не "
            f"разрешена; допустимы {КЛЮЧИ_ПРИВЯЗКИ}")
    if not поставщик.отдаёт:
        raise RatingGatewayError(f"{поставщик.имя}: не объявлено ни одного источника")
    _РЕЕСТР[поставщик.имя] = поставщик


def зарегистрированные() -> tuple[str, ...]:
    return tuple(sorted(_РЕЕСТР))


def очистить_реестр() -> None:
    """Только для тестов: реестр модульного уровня иначе течёт между ними."""
    _РЕЕСТР.clear()


def _число(значение: Any) -> float | None:
    if значение is None or isinstance(значение, bool):
        return None
    try:
        return float(значение)
    except (TypeError, ValueError):
        return None


def проверить_значение(оценка: ОценкаИсточника) -> str | None:
    """Код причины, по которой значение нельзя принять, или None."""
    ч = _число(оценка.value)
    if ч is None:
        return НЕ_ЧИСЛО
    верх = оценка.scale if оценка.scale and оценка.scale > 0 else 10.0
    if not (0.0 < ч <= верх):
        # Ноль сюда попадает намеренно: это отсутствие, а не оценка в ноль.
        return ВНЕ_ДИАПАЗОНА
    return None


def _к_десяти(оценка: ОценкаИсточника) -> float:
    """Привести к шкале витрины. Формула одна и записана здесь.

    Источник со стобалльной шкалой без приведения показал бы «87» рядом с
    «7.2», и это выглядело бы как ошибка данных, а не как разные шкалы.
    """
    верх = оценка.scale if оценка.scale and оценка.scale > 0 else 10.0
    return round(float(оценка.value) * 10.0 / верх, 3)


def обогатить(детали: dict, внешние_по_ид: dict[str, dict],
              *, поставщики: list[ПоставщикОценок] | None = None,
              бюджет: int | None = None) -> tuple[dict, dict]:
    """Дополнить оценки вторичными источниками.

    `детали` — боковой файл витрины, `внешние_по_ид` — внешние идентификаторы
    из канонического снимка. Возвращает (детали, отчёт). Без поставщиков
    возвращает вход неизменным: это нормальное состояние, а не отказ.
    """
    поставщики = list(поставщики if поставщики is not None else _РЕЕСТР.values())
    отчёт: dict[str, Any] = {
        "providers": [п.имя for п in поставщики],
        "requested": 0, "received": 0, "applied": 0,
        "applied_by_source": {}, "rejections": {},
        "budget": бюджет,
    }
    if not поставщики:
        отчёт["note"] = ("вторичных источников оценок не зарегистрировано; "
                         "покрытие ограничено основным поставщиком")
        return детали, отчёт

    def отказ(код: str, сколько: int = 1) -> None:
        отчёт["rejections"][код] = отчёт["rejections"].get(код, 0) + сколько

    остаток = бюджет
    for поставщик in поставщики:
        # Спрашиваем только про то, чего не хватает и к чему можно привязаться.
        нужны: dict[str, list[str]] = {}
        for слаг, запись in детали.items():
            ид = str(запись.get("id") or "")
            внешние = (внешние_по_ид.get(ид) or {})
            ключ = внешние.get(поставщик.ключ_привязки)
            нехватка = [и for и in поставщик.отдаёт
                        if not _заполнено(запись, и)]
            if not нехватка:
                отказ(УЖЕ_ЕСТЬ, len(поставщик.отдаёт))
                continue
            if not ключ:
                отказ(НЕТ_ВНЕШНЕГО_ИД, len(нехватка))
                continue
            нужны.setdefault(str(ключ), []).append(слаг)

        ключи = sorted(нужны)
        if остаток is not None:
            if остаток <= 0:
                отказ(БЮДЖЕТ, len(ключи))
                continue
            if len(ключи) > остаток:
                отказ(БЮДЖЕТ, len(ключи) - остаток)
                ключи = ключи[:остаток]
            остаток -= len(ключи)
        отчёт["requested"] += len(ключи)

        ответ = поставщик.оценки(ключи) or {}
        for ключ in ключи:
            найденные = ответ.get(ключ) or []
            if not найденные:
                отказ(НЕ_ОТДАЛ)
                continue
            for оценка in найденные:
                отчёт["received"] += 1
                if str(оценка.external_id) != str(ключ):
                    # Источник ответил про другое произведение. Принять это
                    # значит показать чужое число под правильным названием.
                    отказ(ЧУЖОЙ_ИД)
                    continue
                причина = проверить_значение(оценка)
                if причина:
                    отказ(причина)
                    continue
                значение = _к_десяти(оценка)
                for слаг in нужны[ключ]:
                    запись = детали[слаг]
                    разрез = запись.setdefault("ratings_by_source", {})
                    # Разрез по источникам ведётся всегда: он и есть место,
                    # где источники не смешиваются.
                    разрез[оценка.source] = {
                        **оценка.as_dict(), "value_on_ten": значение}
                    поле = ПЛОСКОЕ_ПОЛЕ.get(оценка.source)
                    if поле and not _заполнено(запись, оценка.source):
                        запись[поле] = значение
                        запись.setdefault("ratings_source", {})[оценка.source] = \
                            оценка.provider
                        отчёт["applied"] += 1
                        отчёт["applied_by_source"][оценка.source] = \
                            отчёт["applied_by_source"].get(оценка.source, 0) + 1
                    elif поле:
                        отказ(УЖЕ_ЕСТЬ)
    return детали, отчёт


def _заполнено(запись: dict, источник: str) -> bool:
    поле = ПЛОСКОЕ_ПОЛЕ.get(источник)
    if not поле:
        return bool((запись.get("ratings_by_source") or {}).get(источник))
    return _число(запись.get(поле)) is not None and _число(запись.get(поле)) > 0


def применить_хранилище(детали: dict, хранилище: dict) -> tuple[dict, dict]:
    """Наложить накопленные оценки на боковой файл витрины.

    Добор ходит в источники отдельно и складывает результат в хранилище по
    каноническому идентификатору. Публикация берёт готовое: иначе каждая
    пересборка витрины означала бы новый обход внешних источников, а
    временный отказ любого из них — исчезновение оценок со страниц.

    Правила те же, что и при доборе: чужое поле не занимается, первичное
    значение не перезаписывается, ноль оценкой не считается.
    """
    отчёт = {"store_entries": len(хранилище), "applied": 0,
             "applied_by_source": {}, "rejections": {}}

    def отказ(код: str) -> None:
        отчёт["rejections"][код] = отчёт["rejections"].get(код, 0) + 1

    for запись in детали.values():
        ид = str(запись.get("id") or "")
        сохранённое = хранилище.get(ид)
        if not сохранённое:
            continue
        for источник, оценка in сохранённое.items():
            значение = _число(оценка.get("value_on_ten", оценка.get("value")))
            if значение is None or значение <= 0:
                отказ(ВНЕ_ДИАПАЗОНА)
                continue
            разрез = запись.setdefault("ratings_by_source", {})
            разрез[источник] = dict(оценка)
            поле = ПЛОСКОЕ_ПОЛЕ.get(источник)
            if not поле:
                # У источника нет своего поля на витрине. В чужое он не
                # попадёт: подпись под числом обязана быть правдой.
                continue
            if _заполнено(запись, источник):
                отказ(УЖЕ_ЕСТЬ)
                continue
            запись[поле] = значение
            запись.setdefault("ratings_source", {})[источник] = \
                оценка.get("provider", источник)
            отчёт["applied"] += 1
            отчёт["applied_by_source"][источник] = \
                отчёт["applied_by_source"].get(источник, 0) + 1
    return детали, отчёт


def покрытие_по_источникам(детали: dict) -> dict:
    """Покрытие в разрезе источников. Знаменатель один — всё опубликованное."""
    всего = len(детали) or 1
    итог: dict[str, Any] = {"published": len(детали), "by_source": {}}
    источники = {ИСТОЧНИК_КП, ИСТОЧНИК_IMDB}
    for запись in детали.values():
        источники |= set((запись.get("ratings_by_source") or {}).keys())
    for и in sorted(источники):
        n = sum(1 for з in детали.values() if _заполнено(з, и))
        итог["by_source"][и] = {"count": n, "pct": round(n * 100 / всего, 2)}
    return итог


@dataclass
class ЖурналПоставщик:
    """Поставщик из готовых ответов: для фикстур, тестов и сухих прогонов.

    Нужен, чтобы конвейер можно было проверить целиком до того, как появится
    настоящая учётная запись: иначе первым испытанием интеграции окажется
    боевой прогон.
    """
    имя: str = "journal"
    ключ_привязки: str = "kinopoisk"
    отдаёт: tuple[str, ...] = (ИСТОЧНИК_КП,)
    ответы: dict[str, list[ОценкаИсточника]] = field(default_factory=dict)
    вызовов: int = 0
    запрошено: list[str] = field(default_factory=list)

    def оценки(self, запрос: list[str]) -> dict[str, list[ОценкаИсточника]]:
        self.вызовов += 1
        self.запрошено.extend(запрос)
        return {к: self.ответы[к] for к in запрос if к in self.ответы}


def отметка() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
