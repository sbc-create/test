"""Политика свободного места для публикации каталога.

Отдельный модуль, а не часть `nova_publish`, по измеренной причине: тот в
репозитории не импортируется — тянет `canonical_projection` и `rating_gateway`,
которых здесь нет (они живут только в развёрнутой копии). Политика отказа,
которую нельзя прогнать тестом, опаснее отсутствующей: отказать она может и
зря, и проверить это будет нечем.

Что здесь есть и чего здесь НЕТ. Есть измерение места и основание отказать до
первой записи. Нет и не будет уборки: суточные копии «до публикации» — снимки
постоянных данных сайта, выпуск их только читает, а срок хранения назначает
владелец (`docs/RUNTIME_DATA_OWNERSHIP.md`).
"""
from __future__ import annotations

import os
from pathlib import Path


#: Резерв работающим сайтам при публикации каталога. Раздел общий: на нём
#: витрины, их данные и журналы, и публикация не вправе занимать последние
#: гигабайты. Число и переменная — та же политика, что у
#: `automation/host/backup-preflight-space.sh`
#: (`SITE_FACTORY_BACKUP_RESERVE_KB`), чтобы два рубежа не расходились.
РЕЗЕРВ_САЙТАМ_КБ = int(os.environ.get("NOVA_PUBLISH_RESERVE_KB", 5 * 1024 * 1024))


def место_для_публикации(каталог: Path, собранное: dict | None = None,
                        копии: Path | None = None,
                        резерв_кб: int | None = None) -> dict:
    """Свободно, сколько запишет прогон, что останется сайтам.

    Повод измерен 2026-10-15. Публикация пишет копию «до» каждого файла в
    `var/lords/publish-backups` и НИЧЕГО оттуда не удаляет: срока хранения в
    коде нет вовсе. Накопилось 640 файлов на 25,50 ГиБ за 30 суток, прирост
    около 1,18 ГиБ в сутки, а свободно на разделе было 7,3 ГиБ из 203,3
    (3,6 %). При такой скорости раздел заполняется примерно за шесть суток, и
    встают не копии, а САМИ ВИТРИНЫ: раздел общий.

    Уборку эта функция не делает и делать не вправе: суточные копии — снимки
    постоянных данных сайта, выпуск их только читает, а срок хранения
    назначает владелец. Она измеряет и даёт основание отказать ДО записи,
    когда после прогона сайтам осталось бы меньше резерва.

    Пустого успеха не бывает: если место не прочитать, `ok` равен False и
    названа причина — иначе недоступность статистики раздела выглядела бы
    разрешением писать.
    """
    резерв = РЕЗЕРВ_САЙТАМ_КБ if резерв_кб is None else резерв_кб
    итог: dict = {"reserve_kb": резерв}
    try:
        с = os.statvfs(str(каталог))
    except OSError as ош:
        итог.update({"ok": False,
                     "error": f"{type(ош).__name__}: {ош}",
                     "reason": f"свободное место на {каталог} не прочитано: "
                               "это не разрешение писать"})
        return итог
    итог["free_kb"] = с.f_bavail * с.f_frsize // 1024
    # Прогон записывает копию «до» И сам файл — считаются оба.
    запишет = 0
    for пара in (собранное or {}).values():
        источники = пара.values() if isinstance(пара, dict) else [пара]
        for источник in источники:
            try:
                запишет += Path(источник).stat().st_size
            except OSError:
                continue
    # ПИК и ОСТАТОК — разные вопросы, и названы оба.
    #
    # Пик: прогон держит на диске одновременно копию «до» КАЖДОГО файла и
    # временный файл атомарной записи, то есть примерно удвоенный объём
    # собранного. Остаток после прогона меньше: переименование временного
    # файла освобождает прежний, и на диске прирастают только копии «до».
    #
    # Отказ — по пику. Беда, которую политика предотвращает, случается ВО
    # ВРЕМЯ прогона: если раздел кончится посреди записи, витрины встанут
    # тогда же, и аккуратный остаток «после» никого не спасёт. Печатать при
    # этом только пик нельзя — отказ выглядел бы произвольным рядом с
    # честным подсчётом «после», который даёт другое число.
    итог["write_peak_kb"] = запишет // 1024 * 2
    итог["write_net_kb"] = запишет // 1024
    итог["write_kb"] = итог["write_peak_kb"]      # прежнее имя, по пику
    итог["left_to_sites_kb"] = итог["free_kb"] - итог["write_peak_kb"]
    итог["left_after_run_kb"] = итог["free_kb"] - итог["write_net_kb"]
    итог["ok"] = итог["left_to_sites_kb"] >= резерв
    # Накопленное в копиях — в том же отчёте, чтобы причина не искалась
    # отдельно. Это измерение, а не повод для уборки.
    if копии is not None:
        накоплено = файлов = 0
        try:
            for ф in Path(копии).glob("*.before.*"):
                try:
                    накоплено += ф.stat().st_size
                    файлов += 1
                except OSError:
                    continue
        except OSError:
            pass
        итог["kept_backups_kb"] = накоплено // 1024
        итог["kept_backups_files"] = файлов
    if not итог["ok"]:
        итог["reason"] = (
            f"свободно {итог['free_kb'] / 1024 / 1024:.2f} ГиБ; пик прогона "
            f"{итог['write_peak_kb'] / 1024 / 1024:.2f} ГиБ (копии «до» плюс "
            f"временный файл атомарной записи), и в пике сайтам осталось бы "
            f"{итог['left_to_sites_kb'] / 1024 / 1024:.2f} ГиБ при резерве "
            f"{резерв / 1024 / 1024:.2f} ГиБ. После прогона осталось бы "
            f"{итог['left_after_run_kb'] / 1024 / 1024:.2f} ГиБ — отказ именно "
            "по пику: раздел, кончившийся посреди записи, останавливает "
            "витрины тогда же"
            + (f". В копиях «до» накоплено "
               f"{итог.get('kept_backups_kb', 0) / 1024 / 1024:.2f} ГиБ "
               f"({итог.get('kept_backups_files', 0)} файлов) — срока хранения "
               "у них нет, и назначает его владелец: удалять их публикация не "
               "вправе" if копии is not None else ""))
    return итог
