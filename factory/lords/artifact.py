"""Тождество собранного артефакта витрины.

Отпечаток считается по СОДЕРЖИМОМУ и относительным путям. Абсолютный путь в
отпечатке означал бы, что один и тот же срез в двух каталогах даёт разные
значения, и сравнение «собрано дважды одинаково» ломалось бы на пустом месте.

Отчёт о сборке в отпечаток не входит. Он описывает не витрину, а прогон:
длительность сборки меняется от запуска к запуску и различается на машинах
разной загрузки. Пока он входил в отпечаток, две побайтно одинаковые витрины
объявлялись разными артефактами — измерено на полном каталоге: из 65 032
файлов различался ровно один, и это был отчёт.

Обратное тоже важно: `route-map.json` в отпечаток входит. Это не отчёт, а
перечень маршрутов релиза — часть того, что витрина обещает читателю.
"""
from __future__ import annotations

import hashlib
import pathlib

#: Файлы о прогоне, а не о витрине.
ОТЧЁТЫ_СБОРКИ = frozenset({"preview-report.json", "candidate-report.json"})


def файлы_артефакта(корень: pathlib.Path):
    """Файлы витрины в устойчивом порядке."""
    return sorted(ф for ф in корень.rglob("*")
                  if ф.is_file() and ф.name not in ОТЧЁТЫ_СБОРКИ)


def отпечаток(корень: pathlib.Path) -> str:
    h = hashlib.sha256()
    for ф in файлы_артефакта(корень):
        h.update(str(ф.relative_to(корень)).encode("utf-8"))
        h.update(hashlib.sha256(ф.read_bytes()).digest())
    return h.hexdigest()
