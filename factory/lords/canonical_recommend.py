"""Подбор рекомендаций по каноническому каталогу.

Здесь только данные и контракт: ни одной строки разметки. Витрина получает
перечень канонических идентификаторов и решает сама, как их показать.

Правило отбора простое и проверяемое: рекомендуется то, что существует в
каталоге, имеет адрес и не является текущей записью. Выдумывать связи не из
чего — ни отзывов, ни просмотров у нас нет, — поэтому близость считается по
тем признакам, которые источник действительно даёт: тип, жанры, страна, год.

Запасной вариант детерминирован и берётся из того же каталога: случайный
подбор давал бы разные рекомендации на одинаковый запрос, и проверить его
было бы нечем.
"""
from __future__ import annotations

from typing import Iterable

#: Сколько отдавать. Меньше шести выглядит как обрывок ленты, больше
#: двенадцати витрина всё равно не покажет.
МИНИМУМ = 6
МАКСИМУМ = 12


def _близость(а, б) -> int:
    """Во сколько признаков совпали две записи. Больше — ближе."""
    очки = 0
    if а.type and а.type == б.type:
        очки += 3
    общие_жанры = set(а.genres) & set(б.genres)
    очки += 2 * min(len(общие_жанры), 3)
    if set(а.countries) & set(б.countries):
        очки += 1
    if а.year and б.year and abs(а.year - б.year) <= 3:
        очки += 1
    # Оценка — признак качества, а не близости; она лишь разводит равных.
    if б.ratings:
        очки += 1
    return очки


def подобрать(текущая, каталог: Iterable, *,
              сколько: int = МАКСИМУМ) -> list[str]:
    """Идентификаторы рекомендаций для одной записи.

    Возвращается ровно то, что существует: чужих и несуществующих
    идентификаторов в перечне быть не может по построению.
    """
    сколько = max(МИНИМУМ, min(int(сколько), МАКСИМУМ))
    кандидаты = []
    for з in каталог:
        if з.id == текущая.id:
            continue
        if not з.name:
            continue
        кандидаты.append((_близость(текущая, з), з.id))
    if not кандидаты:
        return []
    # Сортировка по близости, затем по идентификатору: устойчивый порядок
    # важнее разнообразия, иначе один и тот же запрос даёт разные ответы.
    кандидаты.sort(key=lambda п: (-п[0], п[1]))
    отобрано, видели = [], set()
    for _, ид in кандидаты:
        if ид in видели:
            continue
        видели.add(ид)
        отобрано.append(ид)
        if len(отобрано) >= сколько:
            break
    return отобрано
