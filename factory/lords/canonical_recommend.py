"""Подбор рекомендаций по каноническому каталогу.

Здесь только данные и контракт: ни одной строки разметки. Витрина получает
перечень канонических идентификаторов и решает сама, как их показать.

Правило отбора простое и проверяемое: рекомендуется то, что существует в
каталоге, имеет адрес и не является текущей записью. Выдумывать связи не из
чего — ни отзывов, ни просмотров у нас нет, — поэтому близость считается по
тем признакам, которые источник действительно даёт: тип, жанры, страна, год.

Запасной вариант детерминирован и берётся из того же каталога: случайный
подбор давал бы разные рекомендации на одинаковый запрос, и проверить его
было бы нечем.
"""
from __future__ import annotations

from typing import Iterable

#: Сколько отдавать. Меньше шести выглядит как обрывок ленты, больше
#: двенадцати витрина всё равно не покажет.
МИНИМУМ = 6
МАКСИМУМ = 12


def _близость(а, б) -> int:
    """Во сколько признаков совпали две записи. Больше — ближе."""
    очки = 0
    if а.type and а.type == б.type:
        очки += 3
    общие_жанры = set(а.genres) & set(б.genres)
    очки += 2 * min(len(общие_жанры), 3)
    if set(а.countries) & set(б.countries):
        очки += 1
    if а.year and б.year and abs(а.year - б.year) <= 3:
        очки += 1
    # Оценка — признак качества, а не близости; она лишь разводит равных.
    if б.ratings:
        очки += 1
    return очки


#: Сколько кандидатов брать в рассмотрение. Перебор всего каталога для каждой
#: записи — это квадрат: на пятидесяти трёх тысячах записей получается почти
#: три миллиарда сравнений, и прогон не заканчивается вовсе. Проверено
#: попыткой: сухой прогон висел, пока его не остановили.
ПРЕДЕЛ_КАНДИДАТОВ = 400


def построить_корзины(каталог: Iterable) -> dict:
    """Разложить каталог по виду и жанру — один раз на весь прогон.

    Без этого каждая запись заново просматривала бы весь каталог. Корзина
    сужает круг до тех, кто вообще может оказаться близким, и ответ от этого
    не портится: за пределами корзины близость всё равно нулевая.
    """
    корзины: dict = {}
    for з in каталог:
        if not getattr(з, "name", ""):
            continue
        for жанр in (з.genres or [""])[:2]:
            корзины.setdefault((з.type, жанр), []).append(з)
        корзины.setdefault((з.type, "*"), []).append(з)
    return корзины


def подобрать(текущая, каталог: Iterable, *, сколько: int = МАКСИМУМ,
              корзины: dict | None = None) -> list[str]:
    """Идентификаторы рекомендаций для одной записи.

    Возвращается ровно то, что существует: чужих и несуществующих
    идентификаторов в перечне быть не может по построению.
    """
    сколько = max(МИНИМУМ, min(int(сколько), МАКСИМУМ))
    if корзины is None:
        источник = list(каталог)
    else:
        источник = []
        видели_ид = set()
        ключи = [(текущая.type, ж) for ж in (текущая.genres or [])[:2]]
        ключи.append((текущая.type, "*"))
        for ключ in ключи:
            for з in корзины.get(ключ, ())[:ПРЕДЕЛ_КАНДИДАТОВ]:
                if з.id not in видели_ид:
                    видели_ид.add(з.id)
                    источник.append(з)
            if len(источник) >= ПРЕДЕЛ_КАНДИДАТОВ:
                break
        # Корзина может оказаться бедной: у произведения редкий жанр, или в
        # каталоге мало записей его вида. Вернуть меньше шести — нарушить
        # контракт, поэтому круг расширяется до всего каталога. Это тот
        # случай, когда экономия перебора не стоит пустой ленты.
        if len({з.id for з in источник} - {текущая.id}) < МИНИМУМ:
            for з in каталог:
                if з.id not in видели_ид:
                    видели_ид.add(з.id)
                    источник.append(з)
                if len(источник) >= ПРЕДЕЛ_КАНДИДАТОВ:
                    break
    кандидаты = []
    for з in источник:
        if з.id == текущая.id:
            continue
        if not з.name:
            continue
        кандидаты.append((_близость(текущая, з), з.id))
    if not кандидаты:
        return []
    # Сортировка по близости, затем по идентификатору: устойчивый порядок
    # важнее разнообразия, иначе один и тот же запрос даёт разные ответы.
    кандидаты.sort(key=lambda п: (-п[0], п[1]))
    отобрано, видели = [], set()
    for _, ид in кандидаты:
        if ид in видели:
            continue
        видели.add(ид)
        отобрано.append(ид)
        if len(отобрано) >= сколько:
            break
    return отобрано
