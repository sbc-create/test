"""Детерминированная публикация каталога витрин Nova из канонического снимка.

Зачем этот модуль существует
----------------------------

До него каталог витрины собирался обходом её собственного отрисованного
релиза: `content-pipeline/refresh.py` вычитывал HTML из
`/srv/lords/<site>/current/site` и делал из него `{site}-catalog.json`.
Витрина, таким образом, публиковала не каталог поставщика, а копию самой себя.

Последствие видно на числах. Релиз Lords перерисовывался, и его каталог дорос
до 52 683 записей. Релиз Zona последний раз собирали 10 сентября, Zona не
входит даже в список `lords-content-refresh.sh` — и её каталог остался на
3 868 записях. Один и тот же поставщик, одна и та же база, разница в
четырнадцать раз, и ни одного сообщения об ошибке: обе витрины отвечали 200.

Здесь источник один — канонический снимок поставщика. Обе витрины собираются
из него в одном прогоне и одним поколением. Отдельной копии, которая умеет
устареть незаметно, больше нет.

Устойчивость адресов
--------------------

Адрес записи — `/title/<slug>/`. Slug обязан пережить пересборку: страница,
сменившая адрес, теряет ссылки и позиции. Поэтому привязка идентификатор →
slug хранится в реестре и только дополняется. Уже выданный slug не
переназначается никогда, даже если у поставщика сменилось название.

Столкновения slug'ов реальны: у 53 390 записей поставщика 53 184 различных
slug'а. Принятая в системе развязка — суффикс `-2`, `-3`; она сохранена.
Взять при столкновении «любую» запись значило бы показать чужое произведение
по знакомому адресу — снаружи это выглядит как работающая страница.
"""
from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from factory.lords.canonical_projection import спроецировать
from factory.lords.live_catalog import slugify

СХЕМА_КАТАЛОГА = "nova-catalog/2.0.0"
СХЕМА_ПОДРОБНОСТЕЙ = "nova.details.sidecar/2.0.0"
ИСТОЧНИК = "canonical-snapshot/1.0.0"

#: Вид записи в словаре витрины. Поставщик различает только movie/tv, а
#: «Мультфильм» витрина показывает отдельным разделом, и определяется он
#: жанром. Жанр приходит из detail, который есть не у всех, — поэтому запись
#: без detail попадает в «Фильм»/«Сериал», а не в пустой вид.
ВИД_ФИЛЬМ = "Фильм"
ВИД_СЕРИАЛ = "Сериал"
ВИД_МУЛЬТФИЛЬМ = "Мультфильм"
ВИД_АНИМЕ = "Аниме"
_ЖАНР_МУЛЬТФИЛЬМА = "мультфильм"

#: Признаки аниме, от самого надёжного к самому слабому. Порядок не
#: декоративный: идентификатор аниме-базы сильнее жанра, жанр сильнее страны.
#: Иначе японский боевик без анимации попал бы в аниме по одной лишь стране.
_ЖАНР_АНИМЕ = re.compile(r"\b(аниме|anime|донхуа|donghua)\b", re.I)
_ЖАНР_АНИМАЦИИ = re.compile(r"\b(мультфильм|мультсериал|анимация|animation)\b", re.I)
_СТРАНЫ_АНИМЕ = {"япония", "japan", "китай", "china", "южная корея", "korea"}


def это_аниме(запись: dict, жанры: list[str], страны: list[str]) -> str | None:
    """Признак, по которому запись отнесена к аниме, или None.

    Возвращается именно признак, а не «да/нет»: по нему потом видно, на чём
    держится классификация каждой записи, и спорные случаи можно пересчитать
    не гадая.
    """
    if (запись.get("external_ids") or {}).get("myanimelist"):
        return "myanimelist_id"
    текст = " ".join(жанры or [])
    if _ЖАНР_АНИМЕ.search(текст):
        return "genre_anime"
    страны_н = {(с or "").strip().lower() for с in (страны or [])}
    if _ЖАНР_АНИМАЦИИ.search(текст) and (страны_н & _СТРАНЫ_АНИМЕ):
        return "animation+origin"
    return None


class PublishError(RuntimeError):
    """Нарушение контракта публикации: прогон прекращается, а не продолжается."""


# ----------------------------------------------------------------------
#  Снимок поставщика
# ----------------------------------------------------------------------

@dataclass
class Снимок:
    """Канонический снимок поставщика — единственный источник каталога."""
    записи: dict[str, dict]
    получен: str
    отпечаток: str

    @property
    def всего(self) -> int:
        return len(self.записи)


def загрузить_снимок(путь: Path) -> Снимок:
    сырое = json.loads(Path(путь).read_text(encoding="utf-8"))
    записи = сырое.get("items") if isinstance(сырое, dict) else сырое
    if not isinstance(записи, list):
        raise PublishError(f"{путь}: в снимке нет списка items")
    по_ид: dict[str, dict] = {}
    без_ид = 0
    for з in записи:
        ид = з.get("external_id") or з.get("id")
        if not ид:
            без_ид += 1
            continue
        по_ид[str(ид)] = з
    if без_ид:
        raise PublishError(f"{путь}: {без_ид} записей без канонического идентификатора")
    if not по_ид:
        raise PublishError(f"{путь}: снимок пуст")
    отп = hashlib.sha256("\n".join(sorted(по_ид)).encode("utf-8")).hexdigest()
    return Снимок(записи=по_ид, получен=str(сырое.get("mark") or ""), отпечаток=отп)


def контрольная_сумма(идентификаторы) -> str:
    """Отпечаток множества идентификаторов.

    Считается по отсортированному множеству: равенство количеств ничего не
    доказывает, а совпадение этого числа означает, что витрины несут ровно
    один и тот же набор произведений.
    """
    return hashlib.sha256("\n".join(sorted(set(идентификаторы)))
                          .encode("utf-8")).hexdigest()


