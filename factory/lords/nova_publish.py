def оценка_есть(значение: Any) -> bool:
    """Действительная числовая оценка — и ничего, что на неё похоже.

    Ноль оценкой не считается. Источник отдаёт его там, где оценки нет, и
    засчитать его значило бы поднять покрытие, ничего не узнав: на странице
    посетитель увидит «0», а не оценку. Пустая строка, None и нечисловое
    значение — тем более не оценка.
    """
    if значение is None or isinstance(значение, bool):
        return False
    try:
        число = float(значение)
    except (TypeError, ValueError):
        return False
    return 0.0 < число <= 10.0


def покрытие(подробности: dict) -> dict:
    """Покрытие по полям. Знаменатель — всё опубликованное, без исключений.

    Уменьшать знаменатель ради прохождения порога запрещено, поэтому он здесь
    один и берётся из того же словаря, что и числители.
    """
    всего = len(подробности) or 1
    def есть(к):
        return sum(1 for з in подробности.values()
                   if з.get(к) not in (None, "", [], {}))
    кп = sum(1 for з in подробности.values() if оценка_есть(з.get("kinopoisk_rating")))
    имдб = sum(1 for з in подробности.values() if оценка_есть(з.get("imdb_rating")))
    любая = sum(1 for з in подробности.values()
                if оценка_есть(з.get("kinopoisk_rating"))
                or оценка_есть(з.get("imdb_rating")))
    ид_источника = sum(1 for з in подробности.values() if з.get("sources"))
    внешние = sum(1 for з in подробности.values()
                  if (з.get("external_ids") or {}))
    return {
        "published": len(подробности),
        "kp": кп, "kp_pct": round(кп * 100 / всего, 2),
        "imdb": имдб, "imdb_pct": round(имдб * 100 / всего, 2),
        "any_rating": любая, "any_rating_pct": round(любая * 100 / всего, 2),
        "description": есть("description"),
        "description_pct": round(есть("description") * 100 / всего, 2),
        "poster_url": есть("poster_url"),
        "poster_pct": round(есть("poster_url") * 100 / всего, 2),
        "source_id": ид_источника,
        "source_id_pct": round(ид_источника * 100 / всего, 2),
        "external_id_binding": внешние,
        "external_id_pct": round(внешние * 100 / всего, 2),
    }


#: Почему у записи нет оценки. Код обязателен: «нет оценки» и «оценку
#: потеряли по дороге» — разные вещи, и общий процент их прячет.
НЕТ_У_ИСТОЧНИКА = "NOT_AVAILABLE_AT_SOURCE"
НЕТ_ВНЕШНЕГО_ИД = "NO_EXTERNAL_ID"


def причины_отсутствия(подробности: dict, снимок: Снимок) -> dict:
    """Поимённая причина для каждой записи без оценки.

    Проверяется индивидуально по снимку: у записи есть внешний идентификатор
    источника, но нет значения, — это «источник не отдал». Нет и
    идентификатора — «не к чему привязаться». Массово проставить один код,
    не заглянув в запись, значило бы выдать незнание за проверку.
    """
    итог = {"kinopoisk": {}, "imdb": {}}
    for ключ, поле, внешний in (("kinopoisk", "kinopoisk_rating", "kinopoisk"),
                                ("imdb", "imdb_rating", "imdb")):
        коды: dict[str, int] = {}
        for слаг, з in подробности.items():
            if оценка_есть(з.get(поле)):
                continue
            запись = снимок.записи.get(str(з.get("id"))) or {}
            внешние = запись.get("external_ids") or {}
            код = НЕТ_У_ИСТОЧНИКА if внешние.get(внешний) else НЕТ_ВНЕШНЕГО_ИД
            коды[код] = коды.get(код, 0) + 1
        итог[ключ] = коды
    return итог
