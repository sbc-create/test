def _вид(запись: dict, жанры: list[str], страны: list[str] | None = None,
         аниме_видом: bool = False) -> str:
    """Вид записи для словаря витрины.

    `аниме_видом` включает отдельный вид «Аниме». По умолчанию он выключен:
    на киновитринах аниме показывается фильмом или сериалом, и менять это
    задним числом значило бы переписать вид у семи тысяч уже опубликованных
    карточек ради витрин, которых это не касается.
    """
    if аниме_видом and это_аниме(запись, жанры, страны or []):
        return ВИД_АНИМЕ
    if any((ж or "").strip().lower() == _ЖАНР_МУЛЬТФИЛЬМА for ж in жанры or []):
        return ВИД_МУЛЬТФИЛЬМ
    return ВИД_СЕРИАЛ if (запись.get("type") == "tv") else ВИД_ФИЛЬМ


def _момент(значение) -> str:
    текст = str(значение or "").strip()
    return текст or ""


def собрать_сайт(*, снимок: Снимок, реестр: РеестрСлагов, детали_кэш: Path,
                 site_id: str, прежние_подробности: dict | None = None,
                 читатель=None, только_аниме: bool = False,
                 аниме_видом: bool = False) -> tuple[dict, dict, dict]:
    """Каталог и боковой файл одной витрины из общего снимка.

    Возвращает (каталог, подробности, статистика). Обе витрины вызывают это
    с одним и тем же снимком и получают один и тот же набор произведений:
    равенство наборов — следствие устройства, а не последующей сверки.
    """
    прежние_подробности = прежние_подробности or {}
    читать = читатель or _прочитать_деталь
    записи_каталога: list[dict] = []
    подробности: dict[str, dict] = {}
    ст = {"снимок": снимок.всего, "опубликовано": 0, "без_постера": 0,
          "отказы": {}, "новых_слагов": 0, "аниме_по_признаку": {}}

    for ид in sorted(снимок.записи):
        запись = снимок.записи[ид]
        деталь = читать(детали_кэш, ид) or {}
        try:
            п = спроецировать(запись, деталь)
        except (ValueError, TypeError):
            ст["отказы"]["projection_error"] = ст["отказы"].get("projection_error", 0) + 1
            continue
        if str(п.id) != str(ид):
            ст["отказы"]["entity_rebind_refused"] = \
                ст["отказы"].get("entity_rebind_refused", 0) + 1
            continue
        д = п.as_dict()
        жанры = д.get("genres") or []
        страны = д.get("countries") or []
        признак = это_аниме(запись, жанры, страны)
        if только_аниме and not признак:
            continue
        if признак:
            ст["аниме_по_признаку"][признак] = \
                ст["аниме_по_признаку"].get(признак, 0) + 1
        название = п.name or запись.get("name") or ""
        слаг = реестр.слаг(ид, название)
        вид = _вид(запись, жанры, страны, аниме_видом=аниме_видом)
        постер = д.get("poster")
        if not постер:
            ст["без_постера"] += 1

        записи_каталога.append({
            "slug": слаг,
            "title": название,
            "poster": постер,
            "kind": вид,
            "year": д.get("year"),
            "url": f"/title/{слаг}/",
            "published_at": _момент(запись.get("created_at")),
            "published_at_estimated": not bool(запись.get("created_at")),
        })

        было = прежние_подробности.get(слаг) or {}
        новое = {
            "id": д["id"],
            "name": д["name"],
            "original_name": д["original_name"],
            "type": д["type"],
            "year": д["year"],
            "description": д["description"],
            "description_source": д["description_source"],
            "poster_url": постер,
            "poster_source": д["poster_source"],
            "kinopoisk_rating": д["ratings"].get("kinopoisk"),
            "imdb_rating": д["ratings"].get("imdb"),
            "ratings_source": д["ratings_source"],
            "external_ids": д["external_ids"],
            "sources": д["sources"],
            "playable": д["playable"],
            "seasons": сезоны_рендерера(д["seasons"]),
            "genres": жанры,
            "countries": д.get("countries") or [],
        }
        # Пустое значение снимка не отменяет уже известное: обогащение имеет
        # право добавлять и уточнять, но не отнимать.
        слито = dict(было)
        for ключ, значение in новое.items():
            if значение in (None, "", [], {}):
                continue
            слито[ключ] = значение
        for ключ in ("crew", "voice_studios", "genre_codes", "duration",
                     "premiere_date", "short_description", "backdrop_url"):
            if ключ in было and ключ not in слито:
                слито[ключ] = было[ключ]
        подробности[слаг] = слито
        ст["опубликовано"] += 1

    ст["новых_слагов"] = реестр.выдано

    # Витрина сортирует новинки по `published_at`; порядок в файле задаётся
    # здесь, чтобы он не зависел от обхода словаря.
    записи_каталога.sort(key=lambda з: (з.get("published_at") or "", з["slug"]),
                         reverse=True)

    каталог = {
        "version": 2,
        "schema": СХЕМА_КАТАЛОГА,
        "site": site_id,
        "source": ИСТОЧНИК,
        "count": len(записи_каталога),
        "without_poster": ст["без_постера"],
        "fields_present": ["slug", "title", "poster", "kind", "year", "url",
                           "published_at"],
        "fields_absent": [],
        "absent_reason": "",
        "revision": снимок.отпечаток[:32],
        "builtAt": снимок.получен,
        "items": записи_каталога,
    }
    подробности_док = {
        "schema": СХЕМА_ПОДРОБНОСТЕЙ,
        "site": site_id,
        "source": ИСТОЧНИК,
        "catalog_revision": снимок.отпечаток[:32],
        "catalog_built_at": снимок.получен,
        "items_total": len(записи_каталога),
        "details_total": len(подробности),
        "details": {с: подробности[с] for с in sorted(подробности)},
    }
    return каталог, подробности_док, ст


def _прочитать_деталь(каталог_деталей: Path, ид: str) -> dict | None:
    п = Path(каталог_деталей) / f"{ид}.json"
    if not п.is_file():
        return None
    try:
        return json.loads(п.read_text(encoding="utf-8")).get("detail") or {}
    except (OSError, ValueError):
        return None


