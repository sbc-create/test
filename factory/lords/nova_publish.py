#  Реестр slug'ов
# ----------------------------------------------------------------------

_ЧИСТКА = re.compile(r"[^a-z0-9]+")


def _запасной_слаг(название: str, ид: str) -> str:
    """Slug для записи, название которой не даёт ни одного пригодного символа.

    Такое бывает: название целиком из иероглифов или знаков. Адрес всё равно
    нужен, и он делается из идентификатора — выдуманного в нём ничего нет.
    """
    очищено = _ЧИСТКА.sub("-", unicodedata.normalize("NFKD", (название or "").lower()))
    очищено = очищено.strip("-")
    return очищено or f"title-{ид[:12]}"


@dataclass
class РеестрСлагов:
    """Привязка канонический идентификатор → slug, только на дополнение.

    Реестр — не кэш. Его назначение в том, чтобы адрес страницы не зависел от
    того, в каком порядке поставщик отдал записи сегодня.
    """
    по_ид: dict[str, str] = field(default_factory=dict)
    по_слагу: dict[str, str] = field(default_factory=dict)
    выдано: int = 0
    столкновений: int = 0

    @classmethod
    def загрузить(cls, путь: Path) -> "РеестрСлагов":
        р = cls()
        if путь.is_file():
            try:
                сырое = json.loads(путь.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                сырое = {}
            for ид, слаг in (сырое.get("by_id") or {}).items():
                р._занять(str(ид), str(слаг))
        return р

    def _занять(self, ид: str, слаг: str) -> None:
        self.по_ид[ид] = слаг
        self.по_слагу[слаг] = ид

    def засеять(self, пары: dict[str, str]) -> int:
        """Принять уже действующие привязки: адреса витрины не меняются.

        Сеется из того, что опубликовано прямо сейчас. Сгенерировать slug'и
        заново значило бы переименовать десятки тысяч живых страниц.
        """
        принято = 0
        for ид, слаг in пары.items():
            if not ид or not слаг:
                continue
            ид, слаг = str(ид), str(слаг)
            if ид in self.по_ид:
                continue
            if слаг in self.по_слагу:
                # Slug уже принадлежит другому произведению: адрес остаётся за
                # первым, второе получит собственный ниже.
                continue
            self._занять(ид, слаг)
            принято += 1
        return принято

    def слаг(self, ид: str, название: str) -> str:
        """Действующий slug записи или новый, свободный и устойчивый."""
        ид = str(ид)
        текущий = self.по_ид.get(ид)
        if текущий:
            return текущий
        основа = slugify(название or "") or _запасной_слаг(название, ид)
        кандидат = основа
        н = 2
        while кандидат in self.по_слагу:
            self.столкновений += 1
            кандидат = f"{основа}-{н}"
            н += 1
        self._занять(ид, кандидат)
        self.выдано += 1
        return кандидат

    def сохранить(self, путь: Path) -> None:
        путь.parent.mkdir(parents=True, exist_ok=True)
        врем = путь.with_suffix(путь.suffix + ".tmp")
        врем.write_text(json.dumps(
            {"schema": "nova.slug-ledger/1.0.0",
             "count": len(self.по_ид),
             "by_id": {и: с for и, с in sorted(self.по_ид.items())}},
            ensure_ascii=False, sort_keys=True), encoding="utf-8")
        врем.replace(путь)


# ----------------------------------------------------------------------
#  Форма, которую витрина читает по индексу
# ----------------------------------------------------------------------

def _целое(значение) -> int | None:
    try:
        return int(str(значение).strip())
    except (TypeError, ValueError):
        return None


def сезоны_рендерера(значение) -> list[dict]:
    """Сезоны как `{n, eps, avail}` — витрина берёт `сезон["n"]` по индексу.

    Сырая форма поставщика (`number`/`episodes_count`) однажды уже уронила
    публичные страницы в 502 при полностью корректных значениях: данные были
    верные, форма чужая. Обе формы распознаются, чтобы повтор ничего не портил.
    """
    if not isinstance(значение, list):
        return []
    итог = []
    for сезон in значение:
        if not isinstance(сезон, dict):
            continue
        н = _целое(сезон.get("n") if сезон.get("n") is not None
                   else сезон.get("number"))
        if н is None:
            continue
        серий = _целое(сезон.get("eps") if сезон.get("eps") is not None
                       else сезон.get("episodes_count")) or 0
        доступно = _целое(сезон.get("avail") if сезон.get("avail") is not None
                          else сезон.get("available_episodes_count"))
        итог.append({"n": н, "eps": серий,
                     "avail": доступно if доступно is not None else серий})
    итог.sort(key=lambda с: с["n"])
    return итог


def проверить_контракт_рендерера(детали: dict) -> list[dict]:
    """Нарушения формы, которые витрина не переживёт.

    Проверяются ровно те обращения по индексу, которые есть в шаблоне. Отчёт
    о покрытии поверх файла, из-за которого сайт отдаёт 502, не стоит ничего.
    """
    беды = []
    for слаг, з in детали.items():
        for сезон in (з.get("seasons") or []):
            if not isinstance(сезон, dict) or "n" not in сезон or "eps" not in сезон:
                беды.append({"slug": слаг, "field": "seasons"})
                break
        for член in (з.get("crew") or []):
            if not isinstance(член, dict) or "name" not in член:
                беды.append({"slug": слаг, "field": "crew"})
                break
        for поле in ("genres", "countries"):
            if з.get(поле) is not None and not isinstance(з.get(поле), list):
                беды.append({"slug": слаг, "field": поле})
        if з.get("external_ids") is not None and not isinstance(з.get("external_ids"), dict):
            беды.append({"slug": слаг, "field": "external_ids"})
    return беды


