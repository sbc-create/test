"""Разбиение списков витрины на страницы.

Сплошной срез `items[(n-1)*24 : n*24]` связывает все страницы между собой: одна
добавленная запись сдвигает всё, что стоит после неё. Замер на настоящем
событии 3 сентября 2026 — добавлена одна запись 2026 года, перерисовано 8172
страницы из 9430, и три витрины опубликовались за 8, 17 и 26 минут вместо
пятнадцати.

Здесь состав страницы определяется блоком года: каждый год начинается с новой
страницы, последняя страница года заполнена частично. Порядок внутри года и
порядок самих годов прежние, первая страница по-прежнему показывает самый
свежий год.

Договор описан в `adr/0007-pagination-by-year-blocks.md`; без согласия владельца
на однократную смену состава страниц режим не включается.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from itertools import groupby
from typing import Any

#: Записи без года идут последним блоком. Разбрасывать их по годам нельзя —
#: года у них нет, а выдумывать его значило бы сообщать посетителю то, чего
#: источник не говорил.
БЕЗ_ГОДА = None


def _год(item: Any) -> Any:
    year = getattr(item, "year", None)
    return year if isinstance(year, int) else БЕЗ_ГОДА


def сплошные_страницы(items: Sequence, per_page: int) -> list[list]:
    """Прежнее разбиение: срез от начала. Оставлено как поведение по умолчанию."""
    if per_page <= 0:
        raise ValueError("на странице должна быть хотя бы одна запись")
    if not items:
        return [[]]
    return [list(items[i: i + per_page]) for i in range(0, len(items), per_page)]


def страницы_по_годам(items: Sequence, per_page: int) -> list[list]:
    """Разбиение по блокам годов.

    Ожидается, что `items` уже отсортированы порядком витрины: свежие годы
    раньше, внутри года — по названию. Функция не сортирует: порядок — решение
    вызывающего, и переупорядочивание здесь молча меняло бы витрину.

    Пустых страниц не бывает. Резервировать номера под будущий рост нарочно не
    стали: резерв — это тонкие страницы, которые хуже той связности, ради
    которой их бы завели. Когда блок года перерастает свои страницы, номера
    последующих блоков сдвигаются; это происходит раз на `per_page` добавлений
    в год и стоит ровно того, что сегодня стоит каждая запись.
    """
    if per_page <= 0:
        raise ValueError("на странице должна быть хотя бы одна запись")
    if not items:
        return [[]]
    страницы: list[list] = []
    for _, блок in groupby(items, key=_год):
        записи = list(блок)
        for i in range(0, len(записи), per_page):
            страницы.append(записи[i: i + per_page])
    return страницы or [[]]


def разбить(items: Sequence, per_page: int, *, по_годам: bool) -> list[list]:
    """Единственная точка выбора разбиения."""
    return страницы_по_годам(items, per_page) if по_годам else сплошные_страницы(items, per_page)


def затронутые_страницы(было: Iterable[list], стало: Iterable[list]) -> int:
    """Сколько страниц изменилось между двумя разбиениями.

    Нужна не витрине, а доказательству: без числа разговор о связности
    разбиения остаётся разговором о вкусе.
    """
    было_list = [list(p) for p in было]
    стало_list = [list(p) for p in стало]
    сколько = abs(len(было_list) - len(стало_list))
    for старая, новая in zip(было_list, стало_list, strict=False):
        if старая != новая:
            сколько += 1
    return сколько
