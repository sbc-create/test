"""Желаемое состояние проектов Topvisor. Один источник истины на все домены.

Manifest декларативен: он описывает, чем сайты отличаются друг от друга, а не
последовательность вызовов API. Отличия здесь настоящие — у сайтов разные
редакционные профили, и запросы, по которым их имеет смысл отслеживать, тоже
разные. Шесть одинаковых проектов с подменённым доменом не дали бы владельцу
ничего: позиции по одному и тому же списку слов на нескольких витринах — это
столько же копий одного измерения.

Домен, которого здесь нет, не попадает ни в план, ни в отчёт, и его отсутствие
ничем не заметно. Поэтому состав манифеста сверяется с реестром ячеек тестом, а
не глазами.

Группы запросов собраны из того, что на сайте действительно есть: разделы,
жанры и типы контента. Выдуманных названий произведений здесь нет.
"""
