REGION_MOSCOW = 213


@dataclass(frozen=True)
class KeywordGroup:
    name: str
    keywords: tuple[str, ...]


@dataclass(frozen=True)
class ProjectSpec:
    domain: str
    name: str
    profile: str
    #: Чем этот проект отличается от остальных пяти. Строка попадает в отчёт.
    focus: str
    metrika_counter: int
    groups: tuple[KeywordGroup, ...]
    searchers: tuple[int, ...] = (YANDEX, GOOGLE)
    region: int = REGION_MOSCOW
    #: Съём позиций платный, поэтому расписание описывает намерение, а не
    #: включённую задачу. Включение — отдельное решение владельца.
    schedule: str = "вручную, после отдельного разрешения владельца"
    #: Технический аудит у Topvisor платный. Здесь фиксируется, что он нужен,
    #: но не запускается.
    technical_audit: str = "запланирован, не запускался: платная операция"
    contact: str = CONTACT_EMAIL

    @property
    def url(self) -> str:
        return f"https://{self.domain}/"


