"""Сообщество Animedia: голоса, комментарии и реакции — без выдуманных людей.

Модуль хранит то, что оставили посетители, и ничего не придумывает: пустое
хранилище означает пустой раздел, а не «пока никто не оставил отзыв» с тремя
готовыми отзывами. Ни одного синтетического автора, ни одной заготовленной
оценки здесь не появляется и появиться не может — записи создаются только
вызовами `добавить_*`.

Почему файл, а не база. Витрине нужен маленький общий счётчик на тайтл и
короткая лента сообщений; отдельная база ради этого — лишняя зависимость,
которой пришлось бы управлять отдельно. Файл пишется атомарно (временный файл
рядом и `os.replace`), а одновременный доступ разводится файловой блокировкой:
процесс витрины многопоточный, и две правки в одну секунду — обычное дело.

Когда хранилище недоступно (каталог не создан, нет прав на запись), модуль
сообщает об этом честно: `доступно = False` и причина. Витрина в этом случае
показывает раздел выключенным и объясняет, чего не хватает, — но не прячет его
и не делает вид, что сообщений нет.
"""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
import re
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path

#: Допустимые реакции. Список закрыт намеренно: произвольная реакция от
#: посетителя — это произвольный текст на странице.
РЕАКЦИИ: tuple[str, ...] = ("огонь", "сердце", "смех", "грусть", "вау")

#: Границы оценки. Шкала та же, что у сводной, иначе их нельзя ставить рядом.
ОЦЕНКА_МИН, ОЦЕНКА_МАКС = 1, 10

#: Списки посетителя: ключ и подпись. Список закрыт намеренно — произвольное
#: имя списка от посетителя означает произвольный заголовок на странице.
#: Одно произведение лежит ровно в одном списке: «смотрю» и «брошено»
#: одновременно — это не состояние, а противоречие.
СПИСКИ: tuple[tuple[str, str], ...] = (
    ("watching", "Смотрю"),
    ("planned", "Буду смотреть"),
    ("watched", "Просмотрено"),
    ("dropped", "Брошено"),
    ("favorite", "Любимое"),
)
КЛЮЧИ_СПИСКОВ: tuple[str, ...] = tuple(к for к, _ in СПИСКИ)
ПОДПИСИ_СПИСКОВ: dict = dict(СПИСКИ)

#: Предел длины сообщения. Не цензура, а защита страницы от полотна.
ДЛИНА_КОММЕНТАРИЯ = 1200

#: Сколько сообщений держать на тайтл.
ПРЕДЕЛ_КОММЕНТАРИЕВ = 200

#: Состояния сообщения. Премодерация — это состояние записи, а не отдельная
#: очередь: очередь пришлось бы держать в согласии с лентой, и рассогласование
#: этих двух списков означало бы сообщение, которое видно не тому, кому можно.
СТАТУС_ОЖИДАЕТ, СТАТУС_ОДОБРЕН, СТАТУС_ОТКЛОНЁН = "pending", "approved", "rejected"
СТАТУСЫ: tuple[str, ...] = (СТАТУС_ОЖИДАЕТ, СТАТУС_ОДОБРЕН, СТАТУС_ОТКЛОНЁН)

#: Записи, созданные до премодерации, поля `status` не имеют. Они уже видны
#: посетителям, и задним числом их прятать нельзя: это чужие опубликованные
#: сообщения, а не очередь, которую забыли разобрать.
СТАТУС_ПО_УМОЛЧАНИЮ = СТАТУС_ОДОБРЕН

#: Минимальный интервал между сообщениями одного автора, секунды. Не цензура:
#: форма без всякого предела — это приглашение залить ленту скриптом.
ИНТЕРВАЛ_СООБЩЕНИЙ = 30

#: Глубина ответов. Ровно один уровень: ветка произвольной глубины на витрине
#: превращается в лестницу, которую нельзя прочитать с телефона.
ГЛУБИНА_ОТВЕТОВ = 1

#: Версия формата. 1 — записи под slug, 2 — под постоянным идентификатором.
#: Переход не ломающий: запись, заведённая под адресом, переезжает под
#: постоянный ключ при первом же изменении, с сохранением содержимого.
ФОРМАТ = 2


@dataclass
class Состояние:
    """Что витрина знает о сообществе конкретного тайтла."""

    slug: str
    голосов: int = 0
    сумма: int = 0
    средняя: float | None = None
    распределение: dict = field(default_factory=dict)
    реакции: dict = field(default_factory=dict)
    комментарии: list = field(default_factory=list)
    на_модерации: list = field(default_factory=list)
    всего_на_модерации: int = 0
    мой_голос: int | None = None
    моя_реакция: str | None = None
    мой_список: str | None = None


def _посетитель(ключ: str) -> str:
    """Устойчивый обезличенный идентификатор посетителя.

    Хранить адрес или cookie как есть незачем: для «один голос от одного
    посетителя» достаточно отпечатка. Он не позволяет узнать человека и не
    выдаёт себя за учётную запись, которой у витрины нет.
    """
    return hashlib.sha256(("animedia-community/1.0:" + ключ).encode("utf-8")).hexdigest()[:24]


class Хранилище:
    """Файловое хранилище сообщества одной витрины."""

    def __init__(self, путь: str | os.PathLike, витрина: str = "") -> None:
        """`витрина` — идентификатор КОНКРЕТНОГО сайта, не семейства.

        Семейство — не граница данных: animedia.icu и animedia.space, как
        zonafilm.space и zonafilm.cc, принадлежат одному семейству и остаются
        разными публичными сайтами. Общий ключ показал бы сообщения одного на
        другом, а это та самая cross-site утечка, которую Definition of Done
        запрещает прямо. Хранилище помнит, чьё оно, и чужое не обслуживает.
        """
        self.путь = Path(путь)
        self.витрина = str(витрина or "").strip()
        self.доступно = False
        self.причина = ""
        self._проверить()

    # --- ключ темы ---------------------------------------------------------

    @staticmethod
    def _найти_запись(данные: dict, тема: str, slug: str = "") -> dict:
        """Запись темы для чтения. Старый ключ по адресу ещё понимается."""
        titles = данные.get("titles") or {}
        запись = titles.get(тема)
        if запись is None and slug:
            запись = titles.get(slug)
        return запись if isinstance(запись, dict) else {}

    def _проверить(self) -> None:
        try:
            self.путь.parent.mkdir(parents=True, exist_ok=True)
            if not self.путь.exists():
                self._записать({"schema_version": ФОРМАТ,
                                "site_id": self.витрина, "titles": {}})
            иначе = self._прочитать().get("site_id") or ""
            if self.витрина and иначе and иначе != self.витрина:
                # Один сайт — одно хранилище и один писатель. Файл, заведённый
                # другой витриной, не дописывается: это её записи.
                raise PermissionError(
                    f"хранилище принадлежит витрине {иначе}, а не {self.витрина}")
            # Проверяется именно запись: каталог может существовать и быть
            # чужим, и тогда «доступно» было бы неправдой.
            if not os.access(self.путь, os.W_OK):
                raise PermissionError(f"нет прав на запись: {self.путь}")
            self.доступно = True
            self.причина = ""
        except (OSError, PermissionError) as ош:
            self.доступно = False
            self.причина = f"{type(ош).__name__}: {ош}"

    # --- чтение и запись ---------------------------------------------------

    def _прочитать(self) -> dict:
        try:
            return json.loads(self.путь.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {"schema_version": 1, "titles": {}}

    def _записать(self, данные: dict) -> None:
        с, врем = tempfile.mkstemp(dir=str(self.путь.parent),
                                   prefix=self.путь.name, suffix=".tmp")
        try:
            with os.fdopen(с, "w", encoding="utf-8") as ф:
                json.dump(данные, ф, ensure_ascii=False)
            os.replace(врем, self.путь)
        except BaseException:
            Path(врем).unlink(missing_ok=True)
            raise

    def _изменить(self, тема: str, правка, slug: str = "") -> dict:
        """Правка под файловой блокировкой: соседний поток не затрёт чужое."""
        if not self.доступно:
            raise RuntimeError(self.причина or "хранилище недоступно")
        замок = self.путь.with_suffix(self.путь.suffix + ".lock")
        with open(замок, "w", encoding="utf-8") as ф:
            fcntl.flock(ф, fcntl.LOCK_EX)
            try:
                данные = self._прочитать()
                данные["schema_version"] = ФОРМАТ
                if self.витрина:
                    данные.setdefault("site_id", self.витрина)
                titles = данные.setdefault("titles", {})
                # Перенос записи, заведённой под адресом. Один раз, с
                # содержимым: голоса и сообщения посетителей переживают смену
                # ключа, иначе смысл постоянного идентификатора теряется.
                if тема not in titles and slug and slug in titles:
                    titles[тема] = titles.pop(slug)
                    titles[тема]["migrated_from_slug"] = slug
                запись = titles.setdefault(
                    тема, {"votes": {}, "reactions": {}, "comments": []})
                правка(запись)
                данные["updated_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
                self._записать(данные)
                return запись
            finally:
                fcntl.flock(ф, fcntl.LOCK_UN)

    # --- чтение состояния --------------------------------------------------

    @staticmethod
    def _статус(с: dict) -> str:
        значение = str(с.get("status") or "").strip()
        return значение if значение in СТАТУСЫ else СТАТУС_ПО_УМОЛЧАНИЮ

    def состояние(self, тема: str, ключ_посетителя: str = "",
                  модератор: bool = False, slug: str = "") -> Состояние:
        запись = self._найти_запись(self._прочитать(), тема, slug)
        голоса = запись.get("votes") or {}
        значения = [int(v) for v in голоса.values()
                    if isinstance(v, (int, float)) and ОЦЕНКА_МИН <= int(v) <= ОЦЕНКА_МАКС]
        распределение: dict = {}
        for v in значения:
            распределение[str(v)] = распределение.get(str(v), 0) + 1
        я = _посетитель(ключ_посетителя) if ключ_посетителя else ""
        реакции = {р: len(список) for р, список in (запись.get("reactions") or {}).items()
                   if isinstance(список, list) and список}
        моя = next((р for р, список in (запись.get("reactions") or {}).items()
                    if isinstance(список, list) and я and я in список), None)
        все_сообщения = [с for с in (запись.get("comments") or []) if isinstance(с, dict)]
        # Кто что видит. Одобренное — всем. Своё, пока оно ждёт разбора, —
        # автору, иначе он решит, что отправка не сработала, и напишет ещё раз.
        # Отклонённое не показывается никому, кроме модератора: это решение
        # модератора, а не сообщение ленты.
        видимые, ожидают = [], []
        for с in все_сообщения:
            статус = self._статус(с)
            своё = bool(я) and с.get("author_key") == я
            if статус == СТАТУС_ОДОБРЕН:
                видимые.append(dict(с, status=статус, моё=своё))
            elif статус == СТАТУС_ОЖИДАЕТ:
                ожидают.append(dict(с, status=статус, моё=своё))
                if своё:
                    видимые.append(dict(с, status=статус, моё=True))
            elif модератор:
                ожидают.append(dict(с, status=статус, моё=своё))
        комментарии = видимые
        мой_список = None
        if я:
            for имя in КЛЮЧИ_СПИСКОВ:
                если_в = (запись.get("lists") or {}).get(имя)
                if isinstance(если_в, list) and я in если_в:
                    мой_список = имя
                    break
        return Состояние(
            slug=(slug or тема),
            голосов=len(значения),
            сумма=sum(значения),
            средняя=(round(sum(значения) / len(значения), 1) if значения else None),
            распределение=распределение,
            реакции=реакции,
            комментарии=комментарии[:ПРЕДЕЛ_КОММЕНТАРИЕВ],
            на_модерации=(ожидают[:ПРЕДЕЛ_КОММЕНТАРИЕВ] if модератор else []),
            всего_на_модерации=sum(
                1 for с in все_сообщения if self._статус(с) == СТАТУС_ОЖИДАЕТ),
            мой_голос=(int(голоса.get(я)) if я and голоса.get(я) is not None else None),
            моя_реакция=моя,
            мой_список=мой_список,
        )

    # --- списки посетителя -------------------------------------------------

    def выбрать_список(self, тема: str, список: str | None,
                       ключ_посетителя: str, slug: str = "") -> Состояние:
        """Положить произведение в список посетителя или убрать из списков.

        `список=None` или повторный выбор того же списка убирают запись: у
        кнопки, которая умеет только добавлять, нет обратного хода, и
        посетитель остаётся с ошибкой навсегда.
        """
        if список is not None and список not in КЛЮЧИ_СПИСКОВ:
            raise ValueError(f"неизвестный список: {список}")
        я = _посетитель(ключ_посетителя)

        def правка(з: dict) -> None:
            все = з.setdefault("lists", {})
            был = None
            for имя in КЛЮЧИ_СПИСКОВ:
                участники = все.get(имя)
                if isinstance(участники, list) and я in участники:
                    был = имя
                    участники.remove(я)
                    if not участники:
                        все.pop(имя, None)
            if список is not None and список != был:
                все.setdefault(список, []).append(я)

        self._изменить(тема, правка, slug=slug)
        return self.состояние(тема, ключ_посетителя, slug=slug)

    def списки_посетителя(self, ключ_посетителя: str) -> dict:
        """Что посетитель разложил по спискам: ключ списка → список тема.

        Пустой словарь — обычное состояние нового посетителя, а не ошибка.
        """
        я = _посетитель(ключ_посетителя) if ключ_посетителя else ""
        итог: dict = {к: [] for к in КЛЮЧИ_СПИСКОВ}
        if not я:
            return итог
        for тема, запись in (self._прочитать().get("titles") or {}).items():
            for имя, участники in (запись.get("lists") or {}).items():
                if имя in итог and isinstance(участники, list) and я in участники:
                    итог[имя].append(тема)
        return итог

    # --- изменения ---------------------------------------------------------

    def добавить_голос(self, тема: str, значение: int, ключ_посетителя: str,
                       slug: str = "") -> Состояние:
        значение = int(значение)
        if not ОЦЕНКА_МИН <= значение <= ОЦЕНКА_МАКС:
            raise ValueError(f"оценка вне шкалы {ОЦЕНКА_МИН}–{ОЦЕНКА_МАКС}")
        я = _посетитель(ключ_посетителя)
        self._изменить(тема, lambda з: з.setdefault("votes", {}).__setitem__(я, значение),
                       slug=slug)
        return self.состояние(тема, ключ_посетителя, slug=slug)

    def снять_голос(self, тема: str, ключ_посетителя: str, slug: str = "") -> Состояние:
        я = _посетитель(ключ_посетителя)
        self._изменить(тема, lambda з: (з.get("votes") or {}).pop(я, None), slug=slug)
        return self.состояние(тема, ключ_посетителя, slug=slug)

    def переключить_реакцию(self, тема: str, реакция: str,
                            ключ_посетителя: str, slug: str = "") -> Состояние:
        if реакция not in РЕАКЦИИ:
            raise ValueError(f"неизвестная реакция: {реакция}")
        я = _посетитель(ключ_посетителя)

        def правка(з: dict) -> None:
            все = з.setdefault("reactions", {})
            for имя, список in list(все.items()):
                if isinstance(список, list) and я in список:
                    список.remove(я)
                    if not список:
                        все.pop(имя, None)
                    if имя == реакция:
                        return  # повторное нажатие снимает реакцию
            все.setdefault(реакция, []).append(я)

        self._изменить(тема, правка)
        return self.состояние(тема, ключ_посетителя, slug=slug)

    def добавить_комментарий(self, тема: str, имя: str, текст: str,
                             ключ_посетителя: str, ответ_на: str = "",
                             slug: str = "") -> Состояние:
        текст = re.sub(r"\s+", " ", str(текст or "")).strip()
        имя = re.sub(r"\s+", " ", str(имя or "")).strip()[:40]
        if not текст:
            raise ValueError("пустое сообщение")
        if len(текст) > ДЛИНА_КОММЕНТАРИЯ:
            raise ValueError(f"сообщение длиннее {ДЛИНА_КОММЕНТАРИЯ} знаков")
        if not имя:
            # Имя не выдумывается за посетителя: он либо назвался, либо
            # остаётся гостем, и это видно в ленте.
            имя = "Гость"
        я = _посетитель(ключ_посетителя)
        сейчас = time.time()
        существующие = [с for с in (self._найти_запись(
                            self._прочитать(), тема, slug).get("comments") or [])
                        if isinstance(с, dict)]

        # Ответ возможен только на существующее сообщение этого же тайтла и
        # только на верхний уровень: ответ на ответ — уже лестница.
        родитель = ""
        if ответ_на:
            цель = next((с for с in существующие if с.get("id") == ответ_на), None)
            if цель is None:
                raise ValueError("сообщение, на которое отвечают, не найдено")
            if str(цель.get("parent_id") or ""):
                raise ValueError("ответы глубже одного уровня не поддерживаются")
            if self._статус(цель) != СТАТУС_ОДОБРЕН:
                # Отвечать на то, чего ещё нет на странице, нельзя: ответ
                # пережил бы отклонение родителя и повис бы без вопроса.
                raise ValueError("на это сообщение пока нельзя ответить")
            родитель = str(цель.get("id"))

        # Защита от заливки. Два простых правила вместо счётчика в отдельном
        # хранилище: слишком часто и слово в слово то же самое.
        for с in существующие:
            if с.get("author_key") != я:
                continue
            if str(с.get("text") or "") == текст:
                raise ValueError("это сообщение уже отправлено")
            try:
                было = time.mktime(time.strptime(
                    str(с.get("created_at") or ""), "%Y-%m-%dT%H:%M:%SZ")) - time.timezone
            except (ValueError, OverflowError):
                continue
            if сейчас - было < ИНТЕРВАЛ_СООБЩЕНИЙ:
                осталось = int(ИНТЕРВАЛ_СООБЩЕНИЙ - (сейчас - было)) + 1
                raise ValueError(f"следующее сообщение можно отправить через {осталось} с")

        запись = {
            "id": hashlib.sha256(
                f"{тема}|{текст}|{time.time_ns()}".encode("utf-8")).hexdigest()[:16],
            "name": имя,
            "text": текст,
            "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "author_key": я,
            # Новое сообщение ждёт разбора. Старые записи поля не имеют и
            # остаются опубликованными — см. СТАТУС_ПО_УМОЛЧАНИЮ.
            "status": СТАТУС_ОЖИДАЕТ,
            "parent_id": родитель,
        }
        self._изменить(тема, lambda з: з.setdefault("comments", []).insert(0, запись),
                       slug=slug)
        return self.состояние(тема, ключ_посетителя, slug=slug)

    # --- модерация и правка ------------------------------------------------

    def _правка_сообщения(self, тема: str, ид: str, правка, slug: str = "") -> None:
        найдено = [False]

        def изменить(з: dict) -> None:
            for с in з.get("comments") or []:
                if isinstance(с, dict) and с.get("id") == ид:
                    правка(с)
                    найдено[0] = True
                    return

        self._изменить(тема, изменить, slug=slug)
        if not найдено[0]:
            raise ValueError("сообщение не найдено")

    def решить_комментарий(self, тема: str, ид: str, статус: str,
                           ключ_посетителя: str = "", slug: str = "") -> Состояние:
        """Одобрить или отклонить сообщение. Только для модератора."""
        if статус not in (СТАТУС_ОДОБРЕН, СТАТУС_ОТКЛОНЁН):
            raise ValueError(f"недопустимое решение: {статус}")
        self._правка_сообщения(тема, ид, lambda с: с.update({
            "status": статус,
            "moderated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }), slug=slug)
        return self.состояние(тема, ключ_посетителя, модератор=True, slug=slug)

    def изменить_комментарий(self, тема: str, ид: str, текст: str,
                             ключ_посетителя: str, модератор: bool = False,
                             slug: str = "") -> Состояние:
        """Правка текста автором или модератором.

        Чужое сообщение правит только модератор: иначе достаточно угадать
        идентификатор, чтобы переписать чужие слова под чужим именем.
        """
        текст = re.sub(r"\s+", " ", str(текст or "")).strip()
        if not текст:
            raise ValueError("пустое сообщение")
        if len(текст) > ДЛИНА_КОММЕНТАРИЯ:
            raise ValueError(f"сообщение длиннее {ДЛИНА_КОММЕНТАРИЯ} знаков")
        я = _посетитель(ключ_посетителя)

        def правка(с: dict) -> None:
            if not модератор and с.get("author_key") != я:
                raise ValueError("это сообщение написал не ты")
            с["text"] = текст
            с["edited_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            # Правка возвращает сообщение в очередь: иначе одобренное можно
            # было бы после одобрения переписать во что угодно.
            if not модератор:
                с["status"] = СТАТУС_ОЖИДАЕТ

        self._правка_сообщения(тема, ид, правка, slug=slug)
        return self.состояние(тема, ключ_посетителя, модератор=модератор, slug=slug)

    def удалить_комментарий(self, тема: str, ид: str, ключ_посетителя: str,
                            модератор: bool = False, slug: str = "") -> Состояние:
        """Удаление автором или модератором. Ответы на удалённое уходят с ним."""
        я = _посетитель(ключ_посетителя)
        отказ = []

        def изменить(з: dict) -> None:
            сообщения = з.get("comments") or []
            цель = next((с for с in сообщения
                         if isinstance(с, dict) and с.get("id") == ид), None)
            if цель is None:
                отказ.append("сообщение не найдено")
                return
            if not модератор and цель.get("author_key") != я:
                отказ.append("это сообщение написал не ты")
                return
            з["comments"] = [с for с in сообщения
                             if с.get("id") != ид and с.get("parent_id") != ид]

        self._изменить(тема, изменить, slug=slug)
        if отказ:
            raise ValueError(отказ[0])
        return self.состояние(тема, ключ_посетителя, модератор=модератор, slug=slug)

    def очередь_модерации(self) -> list:
        """Все ждущие разбора сообщения витрины, свежие первыми."""
        итог = []
        for тема, запись in (self._прочитать().get("titles") or {}).items():
            for с in запись.get("comments") or []:
                if isinstance(с, dict) and self._статус(с) == СТАТУС_ОЖИДАЕТ:
                    итог.append(dict(с, subject=тема))
        итог.sort(key=lambda с: str(с.get("created_at") or ""), reverse=True)
        return итог


def открыть(путь: str | os.PathLike | None, витрина: str = "") -> Хранилище | None:
    """Хранилище по пути или None, если путь не задан вовсе.

    `витрина` — идентификатор конкретного сайта (animedia-01, а не animedia):
    у каждого публичного сайта своё хранилище и один писатель.
    """
    if not путь:
        return None
    return Хранилище(путь, витрина=витрина)
