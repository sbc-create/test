"""Хронология Animedia: единый порядок «сначала новое» и его правила.

Зачем отдельный модуль. Ленты добавлений сортировались сравнением строк, и на
этом снимке каталога это давало произвол: 4003 записи из 7425 несут одну и ту
же отметку времени массовой загрузки, а сортировка строк среди равных
сохраняет порядок файла. Посетитель видел «новое в каталоге», собранное в
случайном порядке, и это ровно то, что заметил владелец.

Правила порядка — по убыванию доказанности, каждое названо:

1. дата добавления, разобранная как момент времени, по убыванию;
2. при равной дате — сначала записи с фактической датой, затем помеченные как
   оценочные (`published_at_estimated`): оценка не должна опережать факт;
3. при прочих равных — канонический идентификатор по возрастанию.

Третье правило нужно не ради красоты, а ради устойчивости: без него две
одинаковые даты дают разный порядок на разных страницах, и одна и та же
карточка появляется дважды или исчезает при листании.

Записи с неразобранной или отсутствующей датой уходят в конец: «дата
неизвестна» и «добавлено давно» — разные утверждения, но ни одно из них не
даёт права показать запись как новинку.
"""
from __future__ import annotations

import datetime as _dt
from typing import Any, Iterable, Sequence

#: Момент, ниже которого дата считается отсутствующей. Нужен, чтобы записи без
#: даты уходили в конец при сортировке по убыванию.
_ДАВНО = _dt.datetime.min.replace(tzinfo=_dt.timezone.utc)

#: Поля, в которых может лежать дата добавления. Порядок — приоритет.
ПОЛЯ_ДАТЫ_ДОБАВЛЕНИЯ: tuple[str, ...] = ("added_at", "published_at")

#: Поля даты появления серии. Год произведения сюда не входит намеренно:
#: подставлять год вместо даты эпизода — подмена, а не запасной вариант.
ПОЛЯ_ДАТЫ_ЭПИЗОДА: tuple[str, ...] = (
    "episode_published_at", "published_at", "available_at")


def разобрать_момент(значение: Any) -> _dt.datetime | None:
    """Момент времени из значения снимка или None, если его там нет.

    Принимаются ISO-8601 с `Z` и со смещением, значение без смещения (считается
    UTC) и чистая дата. Число трактуется как unix-время: некоторые источники
    отдают именно его. Всё остальное — не дата, и притворяться датой не должно.
    """
    if значение is None or значение is True or значение is False:
        return None
    if isinstance(значение, _dt.datetime):
        return значение if значение.tzinfo else значение.replace(tzinfo=_dt.timezone.utc)
    if isinstance(значение, (int, float)):
        try:
            return _dt.datetime.fromtimestamp(float(значение), _dt.timezone.utc)
        except (OverflowError, OSError, ValueError):
            return None
    текст = str(значение).strip()
    if not текст:
        return None
    if текст.endswith("Z"):
        текст = текст[:-1] + "+00:00"
    try:
        момент = _dt.datetime.fromisoformat(текст)
    except ValueError:
        for образец in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d", "%d.%m.%Y"):
            try:
                момент = _dt.datetime.strptime(текст, образец)
                break
            except ValueError:
                continue
        else:
            return None
    return момент if момент.tzinfo else момент.replace(tzinfo=_dt.timezone.utc)


def дата_добавления(запись: dict, поля: Sequence[str] = ПОЛЯ_ДАТЫ_ДОБАВЛЕНИЯ):
    """Дата добавления записи и поле, из которого она взята."""
    for поле in поля:
        момент = разобрать_момент(запись.get(поле))
        if момент is not None:
            return момент, поле
    return None, None


def канонический_идентификатор(запись: dict) -> str:
    """Устойчивый ключ записи: slug, иначе id, иначе адрес, иначе название."""
    for поле in ("slug", "canonical_id", "id", "url", "title"):
        значение = запись.get(поле)
        if значение:
            return str(значение)
    return ""


def ключ_порядка(запись: dict, поля: Sequence[str] = ПОЛЯ_ДАТЫ_ДОБАВЛЕНИЯ) -> tuple:
    """Ключ сортировки «сначала новое», пригодный для `sorted(..., reverse=True)`.

    Возвращается кортеж, где все составляющие сравниваются в одну сторону:
    дата по убыванию, факт раньше оценки, идентификатор по возрастанию. Чтобы
    последнее работало при `reverse=True`, идентификатор инвертируется парой
    (длина, коды символов) — иначе пришлось бы сортировать дважды.
    """
    момент, _ = дата_добавления(запись, поля)
    оценочная = bool(запись.get("published_at_estimated")
                     or запись.get("added_at_estimated"))
    ид = канонический_идентификатор(запись)
    # Инверсия строки для обратной сортировки: сравниваем по отрицанию кодов.
    ид_обратно = tuple(-ord(с) for с in ид)
    return (момент or _ДАВНО, not оценочная, ид_обратно)


def по_добавлению(записи: Iterable[dict],
                  поля: Sequence[str] = ПОЛЯ_ДАТЫ_ДОБАВЛЕНИЯ) -> list:
    """Записи в порядке «сначала новое» по правилам модуля."""
    return sorted(записи, key=lambda з: ключ_порядка(з, поля), reverse=True)


def по_эпизодам(записи: Iterable[dict]) -> list:
    """То же для лент новых серий: дата появления серии, а не год произведения."""
    return по_добавлению(записи, ПОЛЯ_ДАТЫ_ЭПИЗОДА)


def проверить_порядок(записи: Sequence[dict],
                      поля: Sequence[str] = ПОЛЯ_ДАТЫ_ДОБАВЛЕНИЯ) -> list[str]:
    """Нарушения порядка в уже собранном списке — для проверок и отчётов.

    Возвращает человекочитаемые описания мест, где следующая запись новее
    предыдущей. Пустой список означает, что порядок соблюдён.
    """
    беды: list[str] = []
    прошлый = None
    for н, запись in enumerate(записи):
        ключ = ключ_порядка(запись, поля)
        if прошлый is not None and ключ > прошлый:
            момент, поле = дата_добавления(запись, поля)
            беды.append(
                f"позиция {н}: {канонический_идентификатор(запись)} "
                f"({поле}={момент.isoformat() if момент else 'нет'}) новее предыдущей")
        прошлый = ключ
    return беды

def найти_невозможные_даты(записи, сейчас: _dt.datetime | None = None,
                           поля: Sequence[str] = ПОЛЯ_ДАТЫ_ДОБАВЛЕНИЯ) -> list[dict]:
    """Записи с датой из будущего — их не бывает у уже добавленного материала.

    Дата добавления в будущем означает сбой источника или часового пояса, и
    такая запись, отсортированная честно, встанет первой и вытеснит настоящие
    новинки. Поэтому она не просто допускается к показу «как есть», а
    называется отдельно — чтобы решение принимал человек, а не молчание.
    """
    порог = сейчас or _dt.datetime.now(_dt.timezone.utc)
    найдено = []
    for запись in записи:
        момент, поле = дата_добавления(запись, поля)
        if момент is not None and момент > порог:
            найдено.append({"id": канонический_идентификатор(запись),
                            "поле": поле, "дата": момент.isoformat(),
                            "опережение_часов": round(
                                (момент - порог).total_seconds() / 3600, 2)})
    return найдено
