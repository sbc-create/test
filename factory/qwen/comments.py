def проверить_текст(текст: str) -> list[str]:
    """Те же запрещённые обороты, что у описаний. Комментарий — тоже текст сети.

    До 2026-10-09 у комментария проверялась только длина. Обещания доступности,
    упоминания озвучек и субтитров запрещены правилами сети ровно по той же
    причине, по которой они запрещены в описаниях: подтвердить их нечем, а
    посетителю они обещают то, чего может не быть. Длину проверяет приложение,
    и её границы здесь свои — поэтому берутся только словесные замечания.
    """
    беды = editorial.проверить_материал(текст, {})
    return [б for б in беды if "знаков" not in б]


