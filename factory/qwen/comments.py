def _ключ_треда(s: registry.Сайт, slug: str) -> str:
    """Чем тред карточки называется в приложении. Не публичный слаг.

    Измерено 2026-10-09 отрисовкой карточки
    `yummyani.org/anime/chernaya-koshka-i-klass-vedm`: блок комментариев
    запрашивает `GET /api/comments?titleSlug=019d83b9-311a-7b38-b7af-9ac9c10fc9af`
    — идентификатор поставщика, а не SEO-слаг. Это то же свойство, что у
    накладок: `title.slug` в данных приложения остаётся UUID
    (`src/modules/editorial/title-overlay.ts`, строки про publicSlug).

    Цена ошибки измерена на себе: комментарий, записанный с публичным слагом,
    создаётся успешно и читается запросом по тому же слагу, но НИ ОДНА страница
    такой тред не запрашивает — посетитель его не видит, а операция отвечает
    «опубликовано». Поэтому ключ берётся из наших источников
    (`editorial._известный_title_id`: хранилище накладок, last-good, поиск
    приложения по href), и при его отсутствии операция отказывает.
    """
    ключ = editorial._известный_title_id(s, slug, {})
    if ключ:
        return ключ
    raise ОперацияОтклонена(
        f"{s.domain}: не установлен идентификатор тайтла для {slug!r}, а блок "
        "комментариев карточки запрашивает тред ИМЕННО по нему. Запись с "
        "публичным слагом создаст тред, которого карточка не показывает. "
        "Идентификатор берётся из накладки, last-good или поиска приложения — "
        "ни один из трёх не ответил; выдумывать его нельзя")


#: Подпись перехвата: POST на публичный адрес из этой сессии не доходит.
#: Отвечает Python http.server на пути («Unsupported method»), а не приложение.
#: Измерено 2026-10-09: GET проходит (405 от приложения на тот же маршрут),
#: POST — 501 от прослойки. Поэтому чтение и проверка видимости остаются
#: публичными, а запись уходит в тот же контейнер по петле.
_ПЕРЕХВАТ = "Unsupported method"


def _послать(адрес: str, *, тело: dict | None, домен: str,
             добавить: dict[str, str] | None = None,
             вернуть_заголовки: bool = False):
    данные = None if тело is None else json.dumps(тело, ensure_ascii=False).encode()
    заголовки = {
        "User-Agent": "site-factory-editorial/1.0",
        "Accept": "application/json",
        # Приложение проверяет Origin против своего APP_URL, а по петле ещё и
        # Host: без них запрос от «не того» источника законно отвергается.
        "Host": домен,
        "Origin": f"https://{домен}",
        "Referer": f"https://{домен}/",
    }
    if данные is not None:
        заголовки["Content-Type"] = "application/json"
    заголовки.update(добавить or {})
    запрос = urllib.request.Request(адрес, data=данные, headers=заголовки,
                                    method="POST" if данные else "GET")
    try:
        with urllib.request.urlopen(запрос, timeout=45) as о:
            итог = (о.status, о.read().decode("utf-8", "replace"))
            входящие = dict(о.headers.items())
    except urllib.error.HTTPError as ош:
        итог = (ош.code, ош.read().decode("utf-8", "replace"))
        входящие = dict(ош.headers.items()) if ош.headers else {}
    except Exception as ош:  # noqa: BLE001 — недоступность приложения не падение
        итог, входящие = (0, f"{type(ош).__name__}: {ош}"), {}
    return (*итог, входящие) if вернуть_заголовки else итог


def _запрос(адрес: str, *, тело: dict | None = None, домен: str,
            добавить: dict[str, str] | None = None) -> tuple[int, str]:
    """Запрос к приложению витрины, публичным адресом или по петле.

    Порядок именно такой: сперва публичный адрес — он и есть то, чем пользуется
    посетитель. Если ответ несёт подпись перехвата (`_ПЕРЕХВАТ`), запрос
    повторяется в ТОТ ЖЕ контейнер по петле, с заголовками домена. Петля — не
    обход проверок приложения: Origin и Host остаются домена, приложение
    проверяет их само, и база у контейнера та же.
    """
    код, ответ = _послать(адрес, тело=тело, домен=домен, добавить=добавить)
    if _ПЕРЕХВАТ not in ответ:
        return код, ответ
    петля = registry.приложение_в_петле(домен)
    if not петля:
        return код, (ответ + f" | публичный POST перехвачен, а контейнер домена "
                              f"{домен} среди работающих не найден: писать некуда")
    хвост = адрес.split(домен, 1)[1] if домен in адрес else адрес
    return _послать(петля.rstrip("/") + хвост, тело=тело, домен=домен,
                    добавить=добавить)


#: Разрешение владельца опубликовать комментарий там, где снять его нечем.
#: Значение — домен (или `*`). Пусто — публикация требует пути снятия.
СОГЛАСИЕ_НА_НЕОБРАТИМОСТЬ = "FACTORY_COMMENTS_IRREVERSIBLE_OK"


def путь_снятия(s: registry.Сайт) -> tuple[bool, str]:
    """Можно ли снять уже опубликованный комментарий. (можно, чем измерено)

    У ячейки с нашим рантаймом ответ известен без запроса: снятие делает та же
    заявка `comment-publish` действием `retract`, а статус `rejected` — ровно
    то состояние, которым модерация ячейки убирает сообщение со страницы.
    Проверяется только то, что модуль сообщества в выпуске есть: без него
    писать было бы нечем и публикации тоже не было бы.

    Приложение публикует комментарий сразу (`status: published`), а снимает его
    только маршрут модерации `POST /api/admin/comments/<id>`, и тот работает
    лишь при настроенном `ADMIN_MODERATION_SECRET` (>= 16 знаков,
    `src/modules/admin/session.ts`): иначе он отвечает 503 `not_configured`.

    Измерено 2026-10-09: ни у `web-org`, ни у `web-site` переменная не задана —
    то есть опубликованное сообщение снять было бы НЕЧЕМ. Это и есть причина
    отказа: правило сети требует, чтобы у изменения был откат, а не чтобы
    текст был хорошим.
    """
    модуль = _модуль_ячейки(s)
    if модуль is not None:
        return True, (f"операция retract исполнителя через модуль ячейки "
                      f"{модуль}")
    код, тело = _запрос(
        f"https://{s.domain}/api/admin/comments/00000000-0000-0000-0000-000000000000",
        тело={"action": "hide"}, домен=s.domain)
    if код in (401, 403):
        return True, f"HTTP {код}: модерация настроена, снятие требует секрета владельца"
    if код == 503 or "not_configured" in тело:
        return False, f"HTTP {код} not_configured: модерация не настроена"
    # Любой другой ответ — НЕ доказательство, что снятие возможно.
    # Так и ошиблась первая редакция этой проверки: 501 от прослойки сети она
    # прочитала как «маршрут отвечает» и разрешила бы необратимую публикацию.
    return False, (f"HTTP {код}: ответ не подтверждает, что снятие возможно "
                   f"({тело[:120].strip()})")


#: Где лежит секрет модерации. Файл ВНЕ репозитория, по домену, в форме
#: `ADMIN_MODERATION_SECRET=<значение>` — тот же файл, что подкладывается
#: контейнеру compose-секретом. Значение не печатается ни в ответ, ни в журнал.
ФАЙЛ_СЕКРЕТА = ("/srv/sites/yummyani-staging/runtime/moderation/{домен}/env")

#: Имя cookie сессии модерации в приложении (src/modules/admin/session.ts).
COOKIE_МОДЕРАЦИИ = "yami_moderation"


def _секрет_модерации(s: registry.Сайт) -> str:
    путь = os.environ.get("FACTORY_MODERATION_SECRET_FILE", "").strip() or \
        ФАЙЛ_СЕКРЕТА.format(домен=s.domain)
    try:
        текст = pathlib.Path(путь).read_text(encoding="utf-8")
    except OSError:
        return ""
    for строка in текст.splitlines():
        ключ, _, значение = строка.partition("=")
        if ключ.strip() == "ADMIN_MODERATION_SECRET":
            return значение.strip()
    return ""


def снять(site: str, comment_id: str, *, author: str,
          действие: str = "delete") -> dict[str, Any]:
    """Снять ОДИН комментарий по идентификатору. Остальные не затрагиваются.

    Это откат публикации, которого у операции не было: приложение публикует
    комментарий сразу, а снимает только маршрут модерации
    `POST /api/admin/comments/<id>` при настроенном секрете. Операция работает
    с ОДНИМ идентификатором, потому что так устроен и сам маршрут
    (`moderateComment({id, action})`), — сообщения посетителей она не трогает
    по построению, а не по обещанию.

    Подтверждение — чтением треда, в котором запись жила. Тред берётся из
    ОТВЕТА маршрута (`titleSlug`), а не из догадки: 2026-10-09 ошибочная запись
    оказалась в треде публичного слага, которого карточка не показывает, и
    проверка «не той» ветки ничего бы не доказала.
    """
    actors.проверить(author, "comment-unpublish")
    s = _сайт(site)
    _требует_семейство(s)
    if способ(s) == "cell":
        return _снять_в_ячейке(s, comment_id, author=author)
    if действие not in ("delete", "reject", "spam", "approve"):
        raise ОперацияОтклонена(
            f"действие {действие!r} приложению неизвестно: delete, reject, spam, approve")
    секрет = _секрет_модерации(s)
    if not секрет:
        raise ОперацияОтклонена(
            f"{s.domain}: секрет модерации не прочитан "
            f"({ФАЙЛ_СЕКРЕТА.format(домен=s.domain)}). Снятие без него невозможно")
    код, тело, заголовки = _послать(
        f"https://{s.domain}/api/admin/moderation/session",
        тело={"secret": секрет}, домен=s.domain, вернуть_заголовки=True)
    if код == 501 or "Unsupported method" in тело:
        петля = registry.приложение_в_петле(s.domain)
        if not петля:
            raise ОперацияОтклонена(
                f"{s.domain}: публичный POST перехвачен, контейнер домена не найден")
        код, тело, заголовки = _послать(
            петля.rstrip("/") + "/api/admin/moderation/session",
            тело={"secret": секрет}, домен=s.domain, вернуть_заголовки=True)
    if код not in (200, 204):
        raise ОперацияОтклонена(
            f"{s.domain}: сессия модерации не открыта (HTTP {код}): {тело[:200]}")
    печенье = ""
    for имя, значение in заголовки.items():
        if имя.lower() == "set-cookie" and COOKIE_МОДЕРАЦИИ in значение:
            печенье = значение.split(";", 1)[0]
    if not печенье:
        raise ОперацияОтклонена(
            f"{s.domain}: ответ сессии модерации не содержит cookie "
            f"{COOKIE_МОДЕРАЦИИ}: снимать нечем")
    код2, ответ = _запрос(f"https://{s.domain}/api/admin/comments/{comment_id}",
                          тело={"action": действие}, домен=s.domain,
                          добавить={"Cookie": печенье})
    if код2 not in (200, 204):
        raise ОперацияОтклонена(
            f"{s.domain}: приложение не сняло комментарий {comment_id} "
            f"(HTTP {код2}): {ответ[:300]}")
    данные = json.loads(ответ) if ответ.strip().startswith("{") else {}
    запись = данные.get("comment") or данные
    тред = str(запись.get("titleSlug") or "")
    осталось, было_видно = None, None
    if тред:
        к3, т3 = _запрос(f"https://{s.domain}/api/comments?titleSlug={тред}",
                         домен=s.domain)
        если = json.loads(т3) if к3 == 200 else {}
        записи = если.get("comments") or []
        осталось = если.get("total")
        было_видно = any(з.get("id") == comment_id for з in записи)
    editorial._дописать_историю(_каталог(s), {
        "at": editorial._сейчас(), "op": "unpublish-comment",
        "comment_id": comment_id, "action": действие, "prepared_by": author,
        "thread": тред or None, "still_listed": было_видно,
        "remaining_in_thread": осталось,
    })
    if было_видно:
        raise ОперацияОтклонена(
            f"{s.domain}: приложение ответило успехом, но комментарий "
            f"{comment_id} всё ещё в списке треда {тред!r}")
    return {"site": s.domain, "comment_id": comment_id, "action": действие,
            "state": "unpublished", "thread": тред or None,
            "status": запись.get("status"),
            "remaining_in_thread": осталось}


#: Где на карточке ячейки живёт блок сообщества. Атрибут объявляет сама
#: витрина, и число в нём посчитано СЕРВЕРОМ при отрисовке — это не оценка по
#: разметке, а то же число, которое видит посетитель.
_БЛОК_СООБЩЕСТВА = re.compile(
    r'<section[^>]*id="community"[^>]*data-community-comments="(\d+)"[^>]*>(.*?)</section>',
    re.S)
_ЭЛЕМЕНТ_ЛЕНТЫ = re.compile(r"<li\b[^>]*>(.*?)</li>", re.S)


def _текстом(разметка: str) -> str:
    без_тегов = re.sub(r"<[^>]+>", " ", разметка)
    return " ".join(html_mod.unescape(без_тегов).split())


def состояние_ячейки(site: str, slug: str) -> dict[str, Any]:
    """Что посетитель ВИДИТ под карточкой ячейки. Только чтение страницы.

    Хранилище прочитать нельзя и не нужно: оно принадлежит учётной записи
    сайта, а вопрос здесь ровно один — что отдаётся посетителю. Витрина
    отрисовывает ленту на сервере, поэтому ответ страницы и есть ответ.
    """
    s = _сайт(site)
    адрес = _адрес_карточки(s, slug)
    код, тело = _запрос(адрес, домен=s.domain)
    if код != 200:
        raise ОперацияОтклонена(
            f"{s.domain}: карточка {slug!r} не прочитана (HTTP {код})")
    найдено = _БЛОК_СООБЩЕСТВА.search(тело)
    if найдено is None:
        raise ОперацияОтклонена(
            f"{s.domain}: на карточке {slug!r} нет блока сообщества — "
            "комментарии этой страницей не показываются")
    счёт, разметка = int(найдено.group(1)), найдено.group(2)
    записи = [_текстом(э) for э in _ЭЛЕМЕНТ_ЛЕНТЫ.findall(разметка)]
    записи = [з for з in записи if з]
    return {"site": s.domain, "slug": slug, "url": адрес, "backend": "cell",
            "total": счёт, "items": записи,
            "comments": [{"id": None, "author": (ПОДПИСЬ if ПОДПИСЬ in з else None),
                          "created_at": None, "body": з} for з in записи]}


def состояние(site: str, slug: str) -> dict[str, Any]:
    """Что уже опубликовано под карточкой. Только чтение."""
    s = _сайт(site)
    _требует_семейство(s)
    if способ(s) == "cell":
        return состояние_ячейки(site, slug)
    ключ = _ключ_треда(s, slug)
    код, тело = _запрос(f"https://{s.domain}/api/comments?titleSlug={ключ}",
                        домен=s.domain)
    if код != 200:
        raise ОперацияОтклонена(
            f"{s.domain}: список комментариев не прочитан (HTTP {код}): "
            f"{тело[:200]}")
    данные = json.loads(тело)
    записи = данные.get("comments") or []
    return {
        "site": s.domain, "slug": slug, "url": _адрес_карточки(s, slug),
        "total": данные.get("total"),
        "comments": [{"id": з.get("id"), "author": з.get("authorName"),
                      "created_at": з.get("createdAt"),
                      "body": з.get("body")} for з in записи],
    }


def _черновики(s: registry.Сайт) -> dict:
    return editorial._прочитать(_каталог(s) / ЧЕРНОВИКИ,
                                {"site": s.domain, "items": {}})


def подготовить(site: str, slug: str, тело: str, *, author: str) -> dict[str, Any]:
    """Записать черновик комментария. Публичного следствия нет."""
    actors.проверить(author, "comment-prepare")
    s = _сайт(site)
    _требует_семейство(s)
    текст = editorial.обрезать(тело)
    # Предел — у ТОГО, кто примет запись. У приложения Yummy он свой
    # (2000 знаков), у модуля ячейки свой (1200, `ДЛИНА_КОММЕНТАРИЯ`), и
    # черновик, который примет один и отвергнет другой, означал бы отказ в
    # момент публикации вместо отказа при подготовке.
    предел = МАКСИМУМ_ТЕЛА if способ(s) == "app" else МАКСИМУМ_ТЕЛА_ЯЧЕЙКИ
    if not (МИНИМУМ_ТЕЛА <= len(текст) <= предел):
        raise ОперацияОтклонена(
            f"тело комментария {len(текст)} знаков: эта площадка принимает от "
            f"{МИНИМУМ_ТЕЛА} до {предел}")
    беды = проверить_текст(текст)
    к = _каталог(s)
    к.mkdir(parents=True, exist_ok=True)
    черновики = _черновики(s)
    черновики.setdefault("items", {})[slug] = {
        "slug": slug, "body": текст, "author": ПОДПИСЬ,
        "prepared_by": author, "prepared_at": editorial._сейчас(),
        "body_digest": editorial.отпечаток(текст),
        "quality_problems": беды,
    }
    editorial._записать_атомарно(к / ЧЕРНОВИКИ, черновики)
    return {"site": s.domain, "slug": slug,
            "state": "drafted" if not беды else "needs-fix",
            "quality_problems": беды,
            "chars": len(текст), "url": _адрес_карточки(s, slug)}


def _коммит_выпуска(s: registry.Сайт) -> str:
    return editorial._коммит_выпуска(s)


def _слаг_записи(s: registry.Сайт, comment_id: str) -> str:
    """Под какой карточкой лежит НАША запись. Источник — наш же журнал.

    Спрашивать это у витрины нечем: хранилище закрыто, а на странице
    идентификатора записи нет. Журнал публикаций — единственное место, где
    связь «id записи → карточка» у нас есть, и он пишется той же операцией,
    которая запись создала.
    """
    файл = _каталог(s) / editorial.ИСТОРИЯ
    найдено = ""
    try:
        строки = файл.read_text(encoding="utf-8").splitlines()
    except OSError:
        строки = []
    for строка in строки:
        try:
            запись = json.loads(строка)
        except ValueError:
            continue
        if (запись.get("op") == "publish-comment"
                and str(запись.get("comment_id") or "") == comment_id):
            найдено = str(запись.get("slug") or "")
    if not найдено:
        raise ОперацияОтклонена(
            f"{s.domain}: в журнале {файл} нет публикации с id {comment_id!r} — "
            "под какой карточкой лежит эта запись, неизвестно, а угадывать "
            "карточку при снятии нельзя")
    return найдено


def _снять_в_ячейке(s: registry.Сайт, comment_id: str, *,
                    author: str) -> dict[str, Any]:
    """Спрятать СВОЮ запись в ячейке: статус `rejected`, как у модерации."""
    slug = _слаг_записи(s, comment_id)
    запись = _подать_в_ячейку(s, slug, текст="", author=author,
                              действие="retract", comment_id=comment_id)
    сейчас = состояние_ячейки(s.domain, slug)
    видно = any(ПОДПИСЬ in з for з in сейчас["items"])
    editorial._дописать_историю(_каталог(s), {
        "at": editorial._сейчас(), "op": "retract-comment", "slug": slug,
        "comment_id": comment_id, "prepared_by": author, "backend": "cell",
        "request_id": запись.get("request_id"),
        "editorial_still_visible": видно,
    })
    return {"site": s.domain, "slug": slug, "state": "retracted",
            "backend": "cell", "comment_id": comment_id,
            "request_id": запись.get("request_id"),
            "url": _адрес_карточки(s, slug),
            "visible_now": сейчас.get("total")}


def _подать_в_ячейку(s: registry.Сайт, slug: str, *, текст: str, author: str,
                     действие: str = "publish",
                     comment_id: str = "") -> dict[str, Any]:
    """Подготовка → заявка → исполнитель. Управляющий слой в данные не пишет."""
    from factory.cell import comment_store, queue as q

    причина = (f"редакционный комментарий под {slug}" if действие == "publish"
               else f"снятие своей записи {comment_id} под {slug}")
    try:
        подготовлено = comment_store.подготовить(
            s.site_id, slug=slug, текст_комментария=текст, actor=author,
            reason=причина, действие=действие, comment_id=comment_id)
    except OSError as ош:
        raise ОперацияОтклонена(
            f"подготовительный каталог {comment_store.БАЗА} недоступен "
            f"({type(ош).__name__}): комментарий не подготовлен. Каталог "
            "создаётся один раз владельцем, как и каталог правок") from None
    except comment_store.StoreRejected as ош:
        raise ОперацияОтклонена(f"подготовка отклонена: {ош}") from None

    цифра = подготовлено["digest"]
    try:
        заявка = q.собрать(s.site_id, _коммит_выпуска(s), цифра,
                           operation="comment-publish",
                           snapshot=цифра.split(":", 1)[1],
                           note=причина[:200])
        подача = q.подать(заявка)
    except q.RequestRejected as ош:
        raise ОперацияОтклонена(f"заявка отклонена: {ош}") from None

    итог = editorial._дождаться_исполнителя(
        заявка.request_id, подача, не_раньше=заявка.submitted_at)
    результат = итог.get("result") or итог
    исход = результат.get("outcome") or {}
    статус = исход.get("status") or результат.get("status")
    if статус != "commented":
        raise ОперацияОтклонена(
            f"исполнитель не записал комментарий: статус {статус!r}, причина "
            f"{результат.get('error') or 'не названа'}. Повторять слепо нельзя "
            "— причина названа выше")
    шаг = (исход.get("steps") or {}).get("publish_comment") or {}
    return {"request_id": заявка.request_id, "digest": цифра,
            "comment_id": шаг.get("comment_id"), "snapshot": шаг.get("snapshot"),
            "store": шаг.get("store"), "topic": шаг.get("topic")}


#: Переменная с ОСНОВАНИЕМ для второго комментария «Редакции» под той же
#: карточкой. Значение — человекочитаемая причина; пусто — второго не бывает.
#:
#: Зачем это появилось. 2026-10-09 в 22:32 и 22:37 под карточкой
#: `yummyani.org/mir-otome-igr-eto-tyazhelyy-mir-dlya-mobov-2` оказались ДВА
#: наших комментария: один написал ночной заход вручную, второй — часовой
#: запуск редактора. Тексты разные и оба содержательные, но правило владельца
#: прямо запрещает несколько похожих комментариев под одной карточкой, а
#: проверка повтора ловила только совпадение текста. Лишний снят
#: (`unpublish_comment`), а запрет теперь выражен проверкой, а не вниманием.
ОСНОВАНИЕ_ВТОРОГО = "FACTORY_COMMENT_SECOND_REASON"


def _уже_есть_наш(записи: list[dict[str, Any]] | list[str]) -> str:
    """Есть ли под карточкой комментарий «Редакции». Возвращает его начало."""
    for з in записи:
        текст = з if isinstance(з, str) else (
            f"{з.get('author') or ''} {з.get('body') or ''}")
        if ПОДПИСЬ in текст:
            return текст.strip()[:160]
    return ""


def _второй_под_карточкой(s: registry.Сайт, slug: str, найдено: str) -> None:
    """Второй комментарий требует НАЗВАННОГО основания, иначе это объём."""
    причина = os.environ.get(ОСНОВАНИЕ_ВТОРОГО, "").strip()
    if причина:
        return
    raise ОперацияОтклонена(
        f"{s.domain}: под карточкой {slug!r} комментарий «Редакции» уже есть "
        f"(«{найдено}»). Второй под той же карточкой правило сети разрешает "
        "только при НОВОМ содержательном основании, и оно должно быть названо: "
        f"переменная {ОСНОВАНИЕ_ВТОРОГО}=<причина>. Без неё второй комментарий "
        "— это объём, а не польза")


def _опубликовать_в_ячейке(s: registry.Сайт, slug: str, *, текст: str,
                           author: str) -> dict[str, Any]:
    """Комментарий в хранилище сообщества ячейки и проверка его на странице."""
    было = состояние_ячейки(s.domain, slug)
    for з in было["items"]:
        if текст in з:
            raise ОперацияОтклонена(
                f"такой комментарий под карточкой уже виден: «{з[:120]}». "
                "Повтор не записывается")
    наш = _уже_есть_наш(было["items"])
    if наш:
        _второй_под_карточкой(s, slug, наш)
    запись = _подать_в_ячейку(s, slug, текст=текст, author=author)

    # Подтверждение — чтением карточки. Ответ исполнителя говорит, что в
    # хранилище легло подготовленное; посетителю важно, что это ОТДАЁТСЯ.
    видно, предел = False, time.time() + ОЖИДАНИЕ_СТРАНИЦЫ_С
    сейчас: dict[str, Any] = {}
    while time.time() < предел:
        time.sleep(5)
        сейчас = состояние_ячейки(s.domain, slug)
        видно = any(текст in з and ПОДПИСЬ in з for з in сейчас["items"])
        if видно:
            break
    editorial._дописать_историю(_каталог(s), {
        "at": editorial._сейчас(), "op": "publish-comment", "slug": slug,
        "author": ПОДПИСЬ, "prepared_by": author,
        "comment_id": запись.get("comment_id"), "backend": "cell",
        "request_id": запись.get("request_id"),
        "body_digest": editorial.отпечаток(текст), "visible": видно,
    })
    if not видно:
        raise ОперацияОтклонена(
            f"запись добавлена (id {запись.get('comment_id')}), но на карточке "
            f"{_адрес_карточки(s, slug)} за {ОЖИДАНИЕ_СТРАНИЦЫ_С} с не "
            "появилась. Повторять нельзя: вторая попытка создаст второй "
            f"комментарий. Снятие — unpublish_comment по id "
            f"{запись.get('comment_id')}")
    return {"site": s.domain, "slug": slug, "state": "published",
            "backend": "cell", "comment_id": запись.get("comment_id"),
            "author": ПОДПИСЬ, "request_id": запись.get("request_id"),
            "snapshot": запись.get("snapshot"),
            "url": _адрес_карточки(s, slug), "visible_in_list": True,
            "total_visible": сейчас.get("total")}


def опубликовать(site: str, slug: str, *, author: str,
                 тело: str | None = None) -> dict[str, Any]:
    """Опубликовать комментарий под карточкой и подтвердить его видимость.

    Повтор проверяется ДО записи: тем же текстом под тем же слагом комментарий
    второй раз не пишется, и это отказ, а не тихий успех.
    """
    actors.проверить(author, "comment-publish")
    s = _сайт(site)
    _требует_семейство(s)
    текст = editorial.обрезать(тело) if тело else ""
    if not текст:
        черновик = (_черновики(s).get("items") or {}).get(slug) or {}
        текст = str(черновик.get("body") or "")
    if not текст:
        raise ОперацияОтклонена(
            f"для {slug!r} нет ни черновика комментария, ни переданного тела: "
            "публиковать нечего. Выдумывать текст нельзя")
    беды = проверить_текст(текст)
    if беды:
        raise ОперацияОтклонена(
            "комментарий не прошёл проверку текста: " + "; ".join(беды[:3]))
    if способ(s) == "cell":
        # У ячейки и дубль, и видимость проверяются по самой карточке, а
        # обратимость обеспечена операцией снятия той же заявкой.
        return _опубликовать_в_ячейке(s, slug, текст=текст, author=author)
    если = состояние(site, slug)
    for з in если["comments"]:
        if str(з.get("body") or "").strip() == текст.strip():
            raise ОперацияОтклонена(
                f"такой комментарий под карточкой уже есть (id {з.get('id')}, "
                f"автор {з.get('author')!r}, {з.get('created_at')}): повтор не "
                "записывается")
    # Не только дословный повтор: ВТОРОЙ комментарий «Редакции» под той же
    # карточкой — это объём, а не польза, и правило сети его запрещает без
    # названного основания. Поймано на себе 2026-10-09: ночной заход и часовой
    # запуск написали под одной карточкой два разных текста в течение пяти
    # минут, и ни одна проверка этого не остановила.
    наш = _уже_есть_наш(если["comments"])
    if наш:
        _второй_под_карточкой(s, slug, наш)
    # Обратимость проверяется ДО записи: комментарий публикуется сразу и
    # навсегда, если снимать его нечем. Решение владельца снимает проверку
    # переменной, но молчаливого исключения здесь нет.
    снимается, чем = путь_снятия(s)
    согласие = os.environ.get(СОГЛАСИЕ_НА_НЕОБРАТИМОСТЬ, "").strip()
    if not снимается and согласие not in (s.domain, "*"):
        raise ОперацияОтклонена(
            f"{s.domain}: публиковать нельзя — снять комментарий нечем ({чем}). "
            "Приложение публикует сразу, а снимает только маршрут модерации при "
            "настроенном ADMIN_MODERATION_SECRET (>= 16 знаков). Нужно задать его "
            "контейнеру витрины и передать фабрике через secret_ref; до этого "
            f"публикация необратима. Решение владельца — переменная "
            f"{СОГЛАСИЕ_НА_НЕОБРАТИМОСТЬ}={s.domain}")
    код, ответ = _запрос(f"https://{s.domain}/api/comments",
                         тело={"titleSlug": _ключ_треда(s, slug),
                               "authorName": ПОДПИСЬ, "body": текст},
                         домен=s.domain)
    if код not in (200, 201):
        raise ОперацияОтклонена(
            f"{s.domain}: приложение не приняло комментарий (HTTP {код}): "
            f"{ответ[:300]}")
    данные = json.loads(ответ) if ответ.strip().startswith("{") else {}
    ид = данные.get("id") or (данные.get("comment") or {}).get("id") or ""
    # Подтверждение — чтением списка, а не ответом на запись: ответ говорит,
    # что приложение приняло, а посетителю важно, что оно ОТДАЁТ.
    видно, запись = False, {}
    for _ in range(6):
        time.sleep(2)
        сейчас = состояние(site, slug)
        for з in сейчас["comments"]:
            if (ид and з.get("id") == ид) or str(з.get("body") or "").strip() == текст.strip():
                видно, запись = True, з
                break
        if видно:
            break
    editorial._дописать_историю(_каталог(s), {
        "at": editorial._сейчас(), "op": "publish-comment", "slug": slug,
        "author": ПОДПИСЬ, "prepared_by": author, "comment_id": ид or None,
        "body_digest": editorial.отпечаток(текст), "visible": видно,
    })
    if not видно:
        raise ОперацияОтклонена(
            f"комментарий записан (id {ид or 'не назван'}), но в списке "
            f"карточки не появился за 12 секунд. Проверьте {_адрес_карточки(s, slug)} "
            "прежде чем повторять: повтор создаст второй комментарий")
    return {"site": s.domain, "slug": slug, "state": "published",
            "comment_id": ид or запись.get("id"),
            "author": запись.get("author") or ПОДПИСЬ,
            "created_at": запись.get("created_at"),
            "url": _адрес_карточки(s, slug), "visible_in_list": True}
