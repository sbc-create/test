def _модуль_ячейки(s: registry.Сайт) -> pathlib.Path | None:
    """Модуль сообщества в ВЫПУЩЕННОМ коде ячейки или None.

    Признак измеряется, а не выводится из названия семейства: у lords модуль
    есть не у всех ячеек (`lords-02`, `lords-03` — есть, `lords-01` — нет), и
    решать по семейству значило бы обещать публикацию там, где писать нечем.
    """
    try:
        from factory.cell import privileged as _пр
        п = _пр.Площадка.из_реестра(s.site_id)
    except Exception:  # noqa: BLE001 — нет реестра или площадки: нет и пути
        return None
    выпуск = п.current.resolve() if п.current.exists() else п.app
    модуль = выпуск / _пр.МОДУЛЬ_СООБЩЕСТВА
    return модуль if модуль.is_file() else None


def способ(s: registry.Сайт) -> str:
    """Чем на этой площадке публикуется комментарий: `app`, `cell` или ничем."""
    if getattr(s, "adapter", "") in СЕМЕЙСТВА_С_КОММЕНТАРИЯМИ:
        return "app"
    return "cell" if _модуль_ячейки(s) is not None else ""


def _требует_семейство(s: registry.Сайт) -> None:
    если = способ(s)
    if если:
        return
    raise ОперацияОтклонена(
        f"{s.domain}: редакционные комментарии под карточкой этой площадкой "
        f"не поддерживаются. Ни приложение витрины (семейство "
        f"{getattr(s, 'adapter', '')!r}), ни выпущенный код ячейки не несут "
        "места для комментариев: модуля сообщества (src/community.py) в "
        "выпуске нет, и писать комментарий некуда. Подменять его публикацией "
        "в /posts запрещено")


