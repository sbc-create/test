def _ссылка_на_читателя(выпуск: pathlib.Path, читатель: str) -> dict:
    """Чем ВЫЛОЖЕННЫЙ код пользуется читателем. Факты, а не догадка.

    Пустое поле `runtime_reader` не означает «механизма нет»: у семейства
    `zona-serve` рантайм — закреплённый артефакт, а читателя подключает
    отдельная правка витрины (`src/indexing.py`). Поэтому ищется ЛЮБАЯ из
    известных форм подключения, и каждая называется.
    """
    итог = {"imports": [], "substitution": None, "entrypoint": None}
    кф = выпуск / "config" / "site.json"
    точка = ""
    if кф.is_file():
        try:
            точка = (json.loads(кф.read_text(encoding="utf-8")).get("entrypoint")
                     or "")
        except ValueError:
            точка = ""
    if not точка:
        витрины = sorted(п.name for п in (выпуск / "src").glob("*frontend*.py")) \
            if (выпуск / "src").is_dir() else []
        точка = витрины[0] if витрины else ("serve.py"
                                            if (выпуск / "src" / "serve.py").is_file()
                                            else "")
    итог["entrypoint"] = точка or None
    имя_модуля = pathlib.Path(читатель).stem
    for файл in sorted((выпуск / "src").glob("*.py")) if (выпуск / "src").is_dir() else []:
        try:
            текст = файл.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if файл.name == pathlib.Path(читатель).name:
            continue
        if f"import {имя_модуля}" in текст:
            итог["imports"].append(файл.name)
            if "установить(" in текст and "send_header" in текст:
                итог["substitution"] = файл.name
    return итог


def доказательство_чтения(s, *, таймаут: int = 90) -> dict:
    """Доказать, что ВЫЛОЖЕННЫЙ релиз читает конфигурацию режима.

    Статический признак этого не доказывает: зашитый `noindex` в закрытом
    режиме выглядит точно так же, как вычисленный. Поэтому выложенный код
    поднимается в ИЗОЛЯЦИИ — свой порт, свой корень файла состояния, копия
    данных ссылками — и проверяется, что сигналы меняются ровно вместе с
    конфигурацией: при разрешении и `OPEN` открываются, без разрешения или
    при `CLOSED` остаются закрытыми.

    Живого домена это не касается: ни файл состояния, ни его порт не
    затрагиваются.
    """
    import shutil
    import socket
    import subprocess as _sp
    import tempfile

    итог = {"method": "released runtime raised in isolation", "ok": False}
    выпуск = pathlib.Path(f"/srv/{s.account}/current").resolve()
    итог["release_dir"] = выпуск.name
    if not (выпуск / "run.py").is_file():
        итог["reason"] = f"в выпуске нет run.py: {выпуск / 'run.py'}"
        return итог
    данные_живые = pathlib.Path(f"/srv/{s.account}/data")
    if not данные_живые.is_dir():
        итог["reason"] = f"каталога данных нет: {данные_живые}"
        return итог

    def свободный() -> int:
        с = socket.socket()
        с.bind(("127.0.0.1", 0))
        п = с.getsockname()[1]
        с.close()
        return п

    with tempfile.TemporaryDirectory() as тмп:
        корень = pathlib.Path(тмп)
        # КОПИЯ выпуска, а не сам выпуск: `config/player.json` лежит правами
        # 0600 под учётной записью сайта, и пускатель под другой учётной
        # записью отказывает на нём ещё до первого запроса. Подменяется РОВНО
        # этот файл — код копируется байт в байт, и подмена названа в ответе.
        копия = корень / "release"
        try:
            shutil.copytree(выпуск, копия, symlinks=True,
                            ignore=shutil.ignore_patterns("player.json"))
        except OSError as ош:
            итог["reason"] = f"копия выпуска не сделана: {type(ош).__name__}: {ош}"
            return итог
        пускатель = копия / "run.py"
        ожидаемый_плеер = ""
        кф = копия / "config" / "site.json"
        if кф.is_file():
            try:
                ожидаемый_плеер = str(json.loads(кф.read_text(encoding="utf-8"))
                                      .get("publisher_id_expected") or "")
            except ValueError:
                ожидаемый_плеер = ""
        if ожидаемый_плеер:
            (копия / "config").mkdir(parents=True, exist_ok=True)
            (копия / "config" / "player.json").write_text(
                json.dumps({"publisher_id": ожидаемый_плеер}), encoding="utf-8")
            итог["substituted"] = ["config/player.json (0600 у учётной записи "
                                   "сайта; подставлен publisher_id из "
                                   "config/site.json)"]
        данные = корень / "data"
        данные.mkdir()
        for ф in данные_живые.glob("*.json"):
            try:
                (данные / ф.name).symlink_to(ф)
            except OSError:
                pass
        (данные / "site-data").mkdir(exist_ok=True)
        состояние_корень = корень / "indexing"
        состояние_корень.mkdir()
        файл_состояния = состояние_корень / f"{s.domain}.json"

        def разрешение_в_копии(значение: bool) -> None:
            """Поставить разрешение выпуска в КОПИИ конфигурации.

            Переменной окружения тут не обойтись, и это правильно: пускатель
            выпуска сам выводит разрешение из `config/site.json` и
            перезаписывает окружение. Значит и доказывать надо чтение
            КОНФИГУРАЦИИ, а не переменной — меняется ровно одно поле копии, и
            подмена названа в ответе.
            """
            if not кф.is_file():
                return
            д = json.loads(кф.read_text(encoding="utf-8"))
            раздел = dict(д.get("indexing") or {})
            раздел["release_permits_open"] = значение
            д["indexing"] = раздел
            кф.write_text(json.dumps(д, ensure_ascii=False, indent=2) + "\n",
                          encoding="utf-8")

        def поднять(разрешение: str, режим: str) -> dict:
            файл_состояния.unlink(missing_ok=True)
            if режим:
                файл_состояния.write_text(json.dumps(
                    {"schema_version": СХЕМА, "site": s.domain,
                     "desired_state": режим}), encoding="utf-8")
            разрешение_в_копии(разрешение == "true")
            порт = свободный()
            среда = dict(os.environ)
            # Имена переменных корня состояния у семейств разные, и обе формы
            # читает один и тот же модуль: передаются обе.
            среда["LORDS_INDEXING_ROOT"] = str(состояние_корень)
            среда["ANIMEDIA_INDEXING_ROOT"] = str(состояние_корень)
            среда["LORDS_INDEXING_TTL"] = "0"
            среда["ANIMEDIA_INDEXING_TTL"] = "0"
            пр = _sp.Popen([sys.executable, str(пускатель), "--port", str(порт),
                            "--data-dir", str(данные)],
                           cwd=str(копия), env=среда,
                           stdout=_sp.PIPE, stderr=_sp.STDOUT, text=True)
            try:
                предел = time.time() + таймаут
                while time.time() < предел:
                    time.sleep(0.5)
                    if пр.poll() is not None:
                        вывод = (пр.stdout.read() if пр.stdout else "")[-300:]
                        return {"error": f"витрина не поднялась: {вывод}"}
                    код, значения, тело = _ответ(f"http://127.0.0.1:{порт}/", 20)
                    if код == "200":
                        _, _, роботс = _ответ(
                            f"http://127.0.0.1:{порт}/robots.txt", 20)
                        м = re.search(
                            r'<meta name="robots" content="([^"]*)"', тело)
                        return {"x_robots": значения,
                                "meta": м.group(1) if м else None,
                                "robots_txt_closed": bool(re.search(
                                    r"(?mi)^\s*Disallow:\s*/\s*$", роботс))}
                return {"error": f"витрина не ответила за {таймаут} с"}
            finally:
                пр.terminate()
                try:
                    пр.wait(timeout=30)
                except Exception:  # noqa: BLE001
                    пр.kill()

        итог["note"] = (
            "разрешение выпуска меняется в КОПИИ config/site.json: пускатель "
            "выводит его оттуда и перезаписывает окружение")
        итог["closed_without_permission"] = поднять("false", ОТКРЫТ)
        итог["open_with_permission"] = поднять("true", ОТКРЫТ)
        итог["closed_with_permission"] = поднять("true", ЗАКРЫТ)

    беды = [к for к, з in итог.items()
            if isinstance(з, dict) and з.get("error")]
    if беды:
        итог["reason"] = "; ".join(f"{к}: {итог[к]['error']}" for к in беды)
        return итог
    без = итог["closed_without_permission"]
    с_раз = итог["open_with_permission"]
    закр = итог["closed_with_permission"]

    def открыт(з: dict) -> bool:
        return (з.get("meta") == МЕТА_ОЖИДАЕМАЯ[ОТКРЫТ]
                and not з.get("robots_txt_closed")
                and all("noindex" not in (в or "").lower()
                        for в in (з.get("x_robots") or [])))

    итог["ok"] = (открыт(с_раз) and not открыт(без) and not открыт(закр))
    if not итог["ok"]:
        итог["reason"] = (
            "выложенный релиз не изменил сигналы вместе с конфигурацией: "
            f"без разрешения {без}, с разрешением {с_раз}, закрыто {закр}")
    return итог


def _замерить(s, итог: dict, доказательства: dict):
    """Публичные сигналы, слой nginx, слой приложения и файл состояния.

    Отдельной функцией, потому что замер нужен не только полному вердикту. У
    домена, в выпуске которого ещё нет читателя, вердикт останавливался на
    `reader_missing` и НЕ сообщал ни публичного режима, ни того, управляется ли
    слой nginx механизмом. Для сети это были самые нужные поля: именно по ним
    видно, что слой уже переведён, а ждёт домен только выпуска. Вердикт обязан
    быть надмножеством, а не выбирать, что измерить.
    """
    сиг = сигналы(s.domain, порт=порт_приложения(s.site_id))
    фактически, запрещают = оценить(сиг)
    итог["public_mode"] = фактически
    итог["denying_signals"] = запрещают
    доказательства["public"] = {
        "home_https": сиг.get("home_http"),
        "robots_txt_http": сиг.get("robots_txt_http"),
        "robots_txt_head": [с for с in (сиг.get("robots_txt") or "").strip()
                            .split("\n")[:6]],
        "sitemap_http": сиг.get("sitemap_http"),
        "meta_robots_home": сиг.get("meta_robots_home"),
        "canonical_home": сиг.get("canonical_home"),
        "x_robots_https": сиг.get("x_robots_values"),
        "redirects_http80": сиг.get("redirects_http80"),
    }
    слой_ng = слой_nginx(s.site_id, s.domain, сиг)
    доказательства["nginx_layer"] = слой_ng
    доказательства["app_layer"] = слой_приложения(сиг)
    итог["state_file"] = текущее(s.domain)
    return сиг, фактически, запрещают, слой_ng


def готовность(site: str, *, доказать: bool = True) -> dict:
    """ОДИН вердикт о готовности домена к открытию. Ничего не меняет.

    Статус берётся из закрытого словаря `СТАТУСЫ`, и порядок проверок — от
    беды окружения к факту о сайте: иначе отказ доступа читался бы как вывод
    о домене. Поля `registry`, `instruction_version`, `published_release` и
    `evidence` присутствуют ВСЕГДА: вердикт без источника и версии проверить
    нельзя.
    """
    from factory.qwen import __main__ as точка_входа

    итог: dict = {
        "site": site,
        "checked_at": _сейчас(),
        "instruction_version": точка_входа.ВЕРСИЯ_ИНСТРУКЦИИ,
        "instruction": точка_входа.ИНСТРУКЦИЯ,
        "statuses_known": list(СТАТУСЫ),
    }

    # 1. Окружение и реестры. Пустой успешный ответ здесь запрещён.
    try:
        все = registry.собрать(опрашивать_сеть=False)
    except registry.РеестрНедоступен as ош:
        итог.update({"status": "ENV_UNAVAILABLE", "ok": False,
                     "reason": str(ош),
                     "registry": registry.состояние_источников(),
                     "next_action": ДАЛЬШЕ["ENV_UNAVAILABLE"]})
        return итог
    итог["registry"] = registry.состояние_источников()

    # 2. Домен в прочитанном реестре.
    s = next((x for x in все if site in (x.domain, x.site_id)), None)
    if s is None:
        итог.update({"status": "DOMAIN_UNKNOWN", "ok": False,
                     "reason": f"домена {site!r} нет в прочитанных реестрах "
                               f"({итог['registry']['site_cells']['path']}); "
                               "это отсутствие записи, а не вывод о механизме",
                     "next_action": ДАЛЬШЕ["DOMAIN_UNKNOWN"]})
        return итог

    итог.update({"site": s.domain, "site_id": s.site_id, "adapter": s.adapter,
                 "account": s.account, "published_release": s.published_release})
    к = контракт(s.adapter)
    итог["contract"] = к or None
    итог["mode_owner"] = (к or {}).get("mode_owner") or "unknown"
    # Может ли ОПЕРАЦИЯ открыть этот домен вообще. У семейства, чьим режимом
    # распоряжается compose, ответ «нет» при любом разрешении: там решает
    # переменная окружения контейнера, и подменять её файлом состояния значило
    # бы завести второе решение о том же. Поле стоит ЗДЕСЬ, а не в конце:
    # оно нужно в каждом вердикте, включая уже открытый домен.
    итог["operation_can_open"] = итог["mode_owner"] != "compose"
    if not итог["operation_can_open"]:
        # Названа СУЩЕСТВУЮЩАЯ операция площадки, а не «поменяйте переменную».
        # Ручная правка переменной конечным решением не является: у площадки
        # Yummy есть авторитетный реестр владельца и сторож, который запрещает
        # выкладку, расходящуюся с ним. Вторая реализация того же решения в
        # нашей очереди завела бы два разных ответа на один вопрос.
        итог["owner_action"] = (
            "режим этого семейства — значение SEO_INDEXING_ENABLED в "
            "окружении контейнера; решение о нём объявляется в "
            "авторитетном реестре владельца "
            f"{РЕЕСТР_ЯДРА_YUMMY} (desired_state + owner_authorization_id), "
            "после чего применяется ШТАТНОЙ операцией площадки: "
            "bash /srv/sites/yummyani-staging/repo/deploy/staging/"
            "indexability-preflight.sh && bash /srv/sites/yummyani-staging/"
            "repo/deploy/staging/deploy.sh. Сторож "
            "deploy/staging/indexability_guard.py не даст выкладке разойтись с "
            "реестром; операция indexing-set режимом этого семейства не "
            "распоряжается и подменять его файлом состояния не вправе")
    доказательства: dict = {}
    итог["evidence"] = доказательства

    # 3. Механизм в ВЫЛОЖЕННОМ релизе — по контракту семейства.
    if not к:
        итог.update({"status": "MECHANISM_UNSUPPORTED", "ok": False,
                     "reason": f"семейство {s.adapter or 'не определено'} не "
                               "объявило контракта режима индексации",
                     "next_action": ДАЛЬШЕ["MECHANISM_UNSUPPORTED"]})
        return итог
    контейнерный = (к.get("reader") or "").startswith("container:")
    if контейнерный:
        св = читатель_контейнера(s.domain)
        доказательства["container"] = св
        итог["runtime_reader"] = (f"{св.get('container')}: "
                                  f"{к['reader'].split(':', 1)[1]}"
                                  if св.get("found") else "")
        if not св.get("found"):
            итог.update({"status": "MECHANISM_UNPROVEN", "ok": False,
                         "reason": "переменную приложения не прочитать: "
                                   f"{св.get('reason')}. Пустое поле "
                                   "runtime_reader здесь НЕ означает "
                                   "отсутствия механизма",
                         "proof": "не получено: контейнер не опрошен",
                         "next_action": ДАЛЬШЕ["MECHANISM_UNPROVEN"]})
            return итог
        доказательства["delivery"] = (
            "переменная окружения контейнера; доставляется пересборкой "
            "окружения владельцем (compose), выпуском ячейки не управляется")
        доказательства["change_control"] = (
            "смена значения — действие владельца в compose; операция "
            "indexing-set режимом этого семейства не распоряжается")
    else:
        читатель = читатель_режима(s.account, s.adapter)
        итог["runtime_reader"] = str(читатель) if читатель else ""
        if читатель is None:
            # Замер ВСЁ РАВНО делается: по нему видно, что слой nginx уже под
            # управлением механизма и домен ждёт только выпуска. Без этого
            # вердикт отвечал «читателя нет» и умалчивал о том, что остальное
            # готово.
            _замерить(s, итог, доказательства)
            итог.update({"status": "MECHANISM_UNSUPPORTED", "ok": False,
                         "release_gap": "reader_missing",
                         "required_release": ТРЕБУЕТ_ВЫПУСКА["reader_missing"],
                         "reason": f"в выложенном релизе {s.published_release} "
                                   f"нет {к['reader']}",
                         "next_action": ДАЛЬШЕ["MECHANISM_UNSUPPORTED"]})
            return итог
        выпуск = pathlib.Path(f"/srv/{s.account}/current").resolve()
        доказательства["reader"] = {
            "path": str(читатель),
            "bytes": читатель.stat().st_size,
            "sha256": hashlib.sha256(читатель.read_bytes()).hexdigest()[:16],
            "release_dir": выпуск.name,
        }
        подключение = _ссылка_на_читателя(выпуск, к["reader"])
        доказательства["wiring"] = подключение
        if not подключение["imports"]:
            итог.update({"status": "MECHANISM_UNPROVEN", "ok": False,
                         "reason": "читатель в релизе есть, но ни один файл "
                                   "выпуска его не подключает: использование "
                                   "не подтверждено",
                         "proof": "не получено: нет подключения в коде выпуска",
                         "next_action": ДАЛЬШЕ["MECHANISM_UNPROVEN"]})
            return итог

    # 3б. Фактическое доказательство чтения конфигурации выложенным кодом.
    if доказать and not контейнерный:
        док = доказательство_чтения(s)
        доказательства["read_proof"] = док
        if not док.get("ok"):
            итог.update({"status": "MECHANISM_UNPROVEN", "ok": False,
                         "reason": "выложенный релиз не доказал чтение "
                                   f"конфигурации: {док.get('reason')}",
                         "proof": "не получено",
                         "next_action": ДАЛЬШЕ["MECHANISM_UNPROVEN"]})
            return итог
        итог["proof"] = ("получено: выложенный релиз поднят в изоляции и "
                         "менял сигналы вместе с конфигурацией")
    elif контейнерный:
        итог["proof"] = ("получено по переменной ФАКТИЧЕСКИ запущенного "
                         "контейнера")
    else:
        итог["proof"] = "НЕ ПРОВЕРЕНО: доказательство чтения отключено (--no-prove)"

    # 4. Публичное состояние и слои.
    сиг, фактически, запрещают, слой_ng = _замерить(s, итог, доказательства)

    разрешено_выпуском, откуда = разрешение_выпуска(s.account, s.adapter, s.domain)
    итог["release_permits_open"] = разрешено_выпуском
    доказательства["release_permission_source"] = откуда
    # ИСТОЧНИКИ называются рядом со значениями, и это не украшение ответа.
    #
    # Отчёт Qwen однажды выглядел противоречивым: `published_release` называл
    # 4b1340fb2ecf, а `release_permits_open` был `true`. Оба значения верны по
    # отдельности и оба про УСТАНОВЛЕННЫЙ выпуск — разошлись они из-за кэша
    # реестра, в ключ которого не входила ссылка `current` (исправлено).
    # Но разобрать это по ответу было нельзя: источники в нём не назывались.
    # Теперь готовность прямо говорит, ЧТО она прочитала.
    итог["installed_release"] = {
        "release": s.published_release or None,
        "source": f"/srv/{s.account}/current",
        "release_permits_open": разрешено_выпуском,
        "release_permission_source": откуда,
        "note": ("готовность открытия определяется ФАКТИЧЕСКИ УСТАНОВЛЕННЫМ "
                 "выпуском: и версия, и разрешение выпуска прочитаны из него"),
    }
    # Кандидат — то, что лежит в рабочей копии репозитория. К посетителю это
    # не приедет, пока не выложено, поэтому он назван ОТДЕЛЬНО и в решение не
    # входит.
    итог["candidate"] = {
        "work_branch": s.work_branch or None,
        "work_head": (s.work_head or "")[:12] or None,
        "installed": bool(s.published_release
                          and s.work_head
                          and s.work_head.startswith(s.published_release[:12])),
        "note": ("параметры рабочей копии репозитория; на готовность не "
                 "влияют и разрешением выпуска не являются"),
    }
    # Разрешение ВЛАДЕЛЬЦА: у семейства с авторитетным реестром владельца
    # спрашивается ЕГО реестр, а не наша запись. Наш реестр ячеек у `yummy-*`
    # раздела `indexing` не содержит, и ответ «не объявлено» называл бы
    # неразрешённым открытие, которое владелец разрешил и которое ФАКТИЧЕСКИ
    # действует на двух доменах семейства.
    if контейнерный:
        разрешил, объявлен, пояснение = разрешение_владельца_ядра(s.domain)
        доказательства["core_registry"] = реестр_ядра(s.domain)
        # Расхождение реестра владельца с ФАКТОМ — дефект учёта, и назвать его
        # обязан вердикт: сторож площадки запрещает выкладку при расхождении,
        # но о уже случившемся расхождении он молчит.
        живое = (доказательства.get("container") or {}).get("SEO_INDEXING_ENABLED")
        if объявлен:
            ожидаемое = "true" if объявлен == ОТКРЫТ else "false"
            доказательства["core_registry_matches_live"] = (
                str(живое).lower() == ожидаемое)
        итог["owner_registry"] = доказательства["core_registry"]["path"]
    else:
        разрешил, объявлен, пояснение = разрешение_владельца(s.site_id)
    итог["owner_authorized_open"] = разрешил
    итог["owner_declared_state"] = объявлен or None
    доказательства["owner_note"] = пояснение

    # 5. Открыт и подтверждён — терминальное состояние.
    if фактически == ОТКРЫТ and not запрещают:
        итог.update({"status": "OPEN_CONFIRMED", "ok": True,
                     "reason": "публичный ответ открыт, запрещающих сигналов "
                               "нет",
                     "next_action": ДАЛЬШЕ["OPEN_CONFIRMED"]})
        return итог

    # 6. Разрешение владельца есть, но обязательные проверки не прошли.
    блокеры: list[str] = []
    if not разрешено_выпуском:
        блокеры.append(f"выпуск не разрешает открытие: {откуда}")
    if слой_ng.get("denying") is not False:
        блокеры.append(
            f"слой nginx: {слой_ng.get('mode')} — {слой_ng.get('evidence')}")
    if итог["mode_owner"] == "compose":
        блокеры.append(
            "режимом семейства распоряжается compose: операция indexing-set "
            "его не меняет")
    if разрешил:
        итог["blockers"] = блокеры
        итог.update({"status": "CHECKS_FAILED", "ok": False,
                     "reason": "; ".join(блокеры) or
                               "разрешение владельца есть, но публичный ответ "
                               "закрыт, а ни один слой запрета не назван — "
                               "расхождение требует разбора, а не повтора",
                     "next_action": ДАЛЬШЕ["CHECKS_FAILED"]})
        return итог

    # 6в. Выпуск не разрешает открытие — домен НЕ готов технически, и
    #     «осталось только разрешение владельца» было бы неправдой. Разрешение
    #     владельца живёт в реестре и выпуск не заменяет: без выпуска с
    #     `indexing.release_permits_open: true` рантайм остаётся закрытым даже
    #     при открытом файле состояния — это его объявленное поведение.
    if not разрешено_выпуском and итог["operation_can_open"]:
        итог.update({
            "status": "MECHANISM_UNSUPPORTED", "ok": False,
            "release_gap": "permission_false",
            "required_release": ТРЕБУЕТ_ВЫПУСКА["permission_false"],
            "owner_permission_is_not_enough": True,
            "prerequisites_pending": блокеры,
            "reason": f"механизм в выпуске {s.published_release} есть и "
                      f"подтверждён, но {ПРОБЕЛ_ВЫПУСКА['permission_false']} "
                      f"({откуда}). Нужен НОВЫЙ выпуск: "
                      f"{ТРЕБУЕТ_ВЫПУСКА['permission_false']}. Разрешение "
                      f"владельца ({'есть' if разрешил else 'нет'}) этого не "
                      "отменяет и не заменяет",
            "next_action": ДАЛЬШЕ["MECHANISM_UNSUPPORTED"]})
        return итог

    # 7. Технически готов к ПРОЦЕДУРЕ открытия, ждёт владельца.
    #
    # То, что перечислено в `prerequisites_pending`, выполняет сама операция
    # после команды владельца: разрешение выпуска поднимается выпуском, слой
    # nginx — привилегированным исполнителем. Это НЕ «готов к немедленному
    # открытию»: без них открытие не состоится, и прятать их нельзя.
    итог["prerequisites_pending"] = блокеры
    начало = ("механизм на месте и подтверждён, выпуск открытие разрешает"
              if итог["operation_can_open"]
              else f"механизм на месте, но режимом распоряжается "
                   f"{итог['mode_owner']}, а не эта операция")
    итог.update({"status": "AWAITING_OWNER", "ok": False,
                 "reason": f"{начало}; разрешения владельца нет: {пояснение}"
                           + (f". До открытия предстоит: {'; '.join(блокеры)}"
                              if блокеры else ""),
                 "next_action": (ДАЛЬШЕ["AWAITING_OWNER"]
                                 if итог["operation_can_open"]
                                 else "ждать решения владельца; открытие этого "
                                      "семейства выполняется не этой операцией "
                                      "(см. owner_action)")})
    return итог


# ----------------------------------------------------------------- запись
def _отпечаток(запись: dict) -> str:
    основа = {k: запись[k] for k in ("site", "desired_state", "revision",
                                     "authorized_by")}
    return "sha256:" + hashlib.sha256(
        json.dumps(основа, sort_keys=True, ensure_ascii=False,
                   separators=(",", ":")).encode()).hexdigest()


def _снимок(s, сиг: dict, прежнее: dict) -> pathlib.Path:
    ЖУРНАЛ.mkdir(parents=True, exist_ok=True)
    п = ЖУРНАЛ / f"{s.domain}.{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}.before.json"
    п.write_text(json.dumps({"site": s.domain, "site_id": s.site_id,
                             "at": _сейчас(), "state_file": прежнее,
                             "public": сиг}, ensure_ascii=False, indent=1) + "\n",
                 encoding="utf-8")
    return п


def _записать(п: pathlib.Path, запись: dict) -> None:
    п.parent.mkdir(parents=True, exist_ok=True)
    врем = п.with_name(п.name + f".tmp.{os.getpid()}")
    текст = json.dumps(запись, ensure_ascii=False, indent=1) + "\n"
    with open(врем, "w", encoding="utf-8") as fh:
        fh.write(текст)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(врем, п)
    try:
        дк = os.open(str(п.parent), os.O_RDONLY)
        try:
            os.fsync(дк)
        finally:
            os.close(дк)
    except OSError:
        pass
    json.loads(п.read_text(encoding="utf-8"))  # битое не оставляем


def _дописать_журнал(запись: dict) -> None:
    ЖУРНАЛ.mkdir(parents=True, exist_ok=True)
    with (ЖУРНАЛ / "operations.jsonl").open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(запись, ensure_ascii=False) + "\n")


#: Сколько ждать привилегированного исполнителя. Таймер ходит раз в минуту,
#: поэтому предел — несколько его оборотов, а не секунды.
ОЖИДАНИЕ_СЛОЯ_С = 420
ШАГ_СЛОЯ_С = 10


def слой_в_нужном_режиме(слой: dict, режим: str) -> bool:
    """Соответствует ли слой nginx требуемому режиму. Только чтение."""
    if режим == ОТКРЫТ:
        return слой.get("denying") is False
    return слой.get("denying") is True


def переключить_слой(s, *, режим: str, author: str, повтор: str = "") -> dict:
    """Переключить слой nginx ШТАТНОЙ ОЧЕРЕДЬЮ, а не руками редактора.

    Конфигурация nginx принадлежит root, и до этой операции редактор не мог
    довести открытие до конца: приходилось просить человека запустить скрипт.
    Теперь заявка уходит привилегированному исполнителю, который делает ровно
    то же самое и отвечает результатом.

    Повтор того же режима очередь отвечает `already-finished` — менять нечего.
    Неудачная попытка переподаётся тем же идентификатором.
    """
    from factory.cell import queue as q

    итог: dict = {"requested_mode": режим}
    try:
        заявка = q.собрать(s.site_id, "", "", operation="indexing-nginx",
                           mode=режим, suffix=повтор,
                           note=f"indexing layer -> {режим} by {author}"[:200])
        подача = q.подать(заявка)
    except q.RequestRejected as ош:
        raise Отказано(
            f"{s.domain}: заявка на слой nginx отвергнута очередью: {ош}") from None
    except OSError as ош:
        raise Отказано(
            f"{s.domain}: очередь недоступна ({type(ош).__name__}): слой "
            "nginx не переключён, публичное состояние не менялось") from None
    итог["request_id"] = заявка.request_id
    итог["submit"] = подача.get("status")
    if подача.get("status") == "already-finished":
        # «Уже выполнено» — утверждение о ЗАЯВКЕ, а не о состоянии слоя.
        #
        # Измерено 2026-10-04 на lordserials22.info: в 12:25:00 исполнитель
        # ПРИМЕНИЛ открытие по заявке `lords-05-idx-open`, в 12:26 операция
        # откатила его своей причиной и закрыла слой заявкой с суффиксом, а в
        # 12:31 новая попытка получила `already-finished` по тому же
        # идентификатору, исполнителя не спросила вовсе — и операция сообщила
        # «слой остался closed». Очередь права: успешную операцию она не
        # повторяет. Но предмет здесь РЕЖИМ, и просить его снова после
        # возврата назад законно.
        #
        # Поэтому решает ЧТЕНИЕ слоя. Уже в нужном режиме — менять нечего. Не в
        # нужном — подаём заново с суффиксом, ровно тем приёмом, которым
        # пользуется возврат (`вернуть_слой`).
        сейчас = слой_nginx(s.site_id, s.domain,
                            сигналы(s.domain, порт=порт_приложения(s.site_id)))
        итог["layer_now"] = {"mode": сейчас.get("mode"),
                             "denying": сейчас.get("denying")}
        if слой_в_нужном_режиме(сейчас, режим):
            итог["note"] = "слой уже в этом режиме: менять нечего"
            return итог
        if повтор:
            raise Отказано(
                f"{s.domain}: заявка с суффиксом {повтор} снова получила "
                f"«уже выполнено», а слой в режиме {сейчас.get('mode')!r}: "
                "очередь и слой расходятся, нужен разбор")
        итог["requeued_as"] = time.strftime("rep%H%M%S", time.gmtime())
        повторная = переключить_слой(s, режим=режим, author=author,
                                     повтор=итог["requeued_as"])
        повторная["first_submit"] = подача.get("status")
        повторная["layer_before_retry"] = итог["layer_now"]
        повторная["requeued_as"] = итог["requeued_as"]
        return повторная

    предел = time.time() + ОЖИДАНИЕ_СЛОЯ_С
    последнее: dict = {"status": "unknown"}
    while time.time() < предел:
        try:
            # Время подачи обязательно: идентификатор заявки на слой
            # детерминирован, и результат прошлой попытки лежит рядом.
            последнее = q.состояние(заявка.request_id,
                                    не_раньше=заявка.submitted_at)
        except OSError as ош:
            # Нечитаемое состояние — не повод подать заявку снова.
            последнее = {"status": "status-unreadable",
                         "reason": f"{type(ош).__name__}: {ош}"}
        if последнее.get("status") == "finished":
            итог["result"] = последнее.get("result") or последнее
            исход = ((итог["result"].get("outcome") or {}).get("status")
                     if isinstance(итог["result"], dict) else None)
            итог["outcome"] = исход
            if исход not in ("applied", "nothing-to-do"):
                raise Отказано(
                    f"{s.domain}: исполнитель не применил слой nginx "
                    f"(исход {исход!r}): "
                    f"{str((итог['result'] or {}).get('error'))[:300]}")
            return итог
        time.sleep(ШАГ_СЛОЯ_С)
    raise Отказано(
        f"{s.domain}: исполнитель не ответил за {ОЖИДАНИЕ_СЛОЯ_С} с про заявку "
        f"{заявка.request_id}; последнее состояние {последнее.get('status')!r}. "
        "Заявка остаётся в очереди — не подавайте её заново, прочтите "
        "состояние")


def _слой_с_измерением(s, режим: str, *, попыток: int = 6,
                       пауза: float = 2.0) -> dict:
    """Вердикт слоя nginx ПОСЛЕ переключения — с публичным измерением.

    Зачем измерение. Вердикт слоя читает конфигурации nginx, и часть их
    непривилегированной стороне недоступна навсегда:
    `/etc/nginx/conf.d/lords.conf` — `root:root 0600`. В таком случае вердикт
    честно отвечает `unknown` вместо «открыт» — и операция откатывала уже
    сделанное открытие. Измерено 2026-10-04 на lordserials22.info: исполнитель
    применил слой (`default ""`, заголовок не добавляется), а операция
    объявила это неудачей, потому что звала вердикт без сигналов.

    Логика вердикта этот случай предусматривает: нечитаемая конфигурация плюс
    НУЛЕВАЯ надбавка nginx к заголовкам приложения означает «открыт». Здесь
    измерение и делается — после записи файла состояния и работы исполнителя.

    Зачем повтор. nginx перезагружается не мгновенно, а витрина перечитывает
    файл состояния по mtime: первое измерение может застать прежний ответ.
    Повтор ограничен и ничего не меняет — это только чтение.
    """
    порт = порт_приложения(s.site_id)
    последний: dict = {}
    for попытка in range(попыток):
        сиг = сигналы(s.domain, порт=порт)
        последний = слой_nginx(s.site_id, s.domain, сиг)
        if слой_в_нужном_режиме(последний, режим):
            return последний
        if попытка + 1 < попыток:
            time.sleep(пауза)
    return последний


def установить(site: str, *, mode: str, author: str,
               expect_release: str = "", корень=None) -> dict:
    """Сменить режим одного сайта и проверить результат на его ответе."""
    режим = (mode or "").strip().upper()
    пред = проверить(site, mode=режим, expect_release=expect_release,
                     корень=корень)
    if not пред["ok"]:
        raise Отказано(
            f"{пред['site']}: предпроверка не пройдена — "
            + "; ".join(пред["blockers"]))
    s = editorial._сайт(site)
    прежнее = пред["current_state_file"]
    снимок = _снимок(s, пред["public_now"], прежнее)

    if прежнее.get("desired_state") == режим:
        # Повтор не пишет ничего: иначе в журнале появлялась бы операция,
        # которая ничего не изменила, а время файла сдвигалось бы впустую.
        итог = подтвердить(site, ожидаемый=режим)
        итог.update({"changed": False, "state_file": прежнее,
                     "note": "файл состояния уже в этом режиме — запись не велась",
                     "snapshot": str(снимок)})
        return итог

    ревизия = int(прежнее.get("revision") or 0) + 1
    запись = {
        "schema_version": СХЕМА,
        "site": s.domain,
        "site_id": s.site_id,
        "desired_state": режим,
        "revision": ревизия,
        "changed_at": _сейчас(),
        "authorized_by": author,
        "owner_authorized_open": пред["owner_authorized_open"],
        "owner_note": пред["owner_note"],
        "release": s.published_release,
        "note": ("Состояние читает рантайм витрины (src/indexing_mode.py). "
                 "Разрешения живут отдельно: у владельца — в реестре ячеек, у "
                 "выпуска — в config/site.json. Этот файл один сайт не "
                 "открывает."),
    }
    запись["policy_digest"] = _отпечаток(запись)
    п = _файл(s.domain, корень=корень)
    _записать(п, запись)
    _дописать_журнал({"at": _сейчас(), "op": "set", "site": s.domain,
                      "from": прежнее.get("desired_state") or "(нет файла)",
                      "to": режим, "revision": ревизия, "author": author,
                      "snapshot": str(снимок), "state_file": str(п)})

    # --- слой nginx. Публичное состояние меняется ТОЛЬКО после того, как
    #     записан файл состояния: иначе открытый слой остался бы при закрытом
    #     приложении, и запрет исчез бы раньше, чем появилось разрешение.
    слой = пред["nginx_layer"]
    итог_слоя: dict = {"needed": not слой_в_нужном_режиме(слой, режим),
                       "before": {"mode": слой.get("mode"),
                                  "denying": слой.get("denying")}}
    if итог_слоя["needed"]:
        try:
            итог_слоя.update(переключить_слой(s, режим=режим, author=author))
        except Отказано as отказ:
            # Частичный отказ: приложение уже переключено, слой — возможно,
            # тоже (исполнитель мог применить режим и не ответить вовремя).
            # Поэтому возвращается И файл, И слой — по ФАКТИЧЕСКОМУ чтению
            # слоя, а не по предположению, что он остался прежним.
            возврат = _восстановить(s, прежнее, корень=корень,
                                    причина="слой nginx не переключён",
                                    слой_до=слой, author=author)
            сл = возврат.get("nginx_restored") or {}
            if сл.get("needed") and not сл.get("ok"):
                raise Отказано(
                    f"{отказ} | ВНИМАНИЕ: слой nginx вернуть не удалось "
                    f"({сл.get('reason')}), домен остался в режиме слоя "
                    f"{сл.get('mode')!r} — требуется немедленный разбор") from None
            raise
        слой_после = _слой_с_измерением(s, режим)
        итог_слоя["after"] = {"mode": слой_после.get("mode"),
                              "denying": слой_после.get("denying"),
                              "evidence": слой_после.get("evidence")}
        if not слой_в_нужном_режиме(слой_после, режим):
            возврат = _восстановить(s, прежнее, корень=корень,
                                    причина=f"слой nginx остался в режиме "
                                            f"{слой_после.get('mode')}",
                                    слой_до=слой, author=author)
            сл = возврат.get("nginx_restored") or {}
            raise Отказано(
                f"{s.domain}: исполнитель отработал, но слой nginx остался "
                f"{слой_после.get('mode')!r}: {слой_после.get('evidence')}. "
                "Состояние приложения возвращено к исходному"
                + ("" if not (сл.get("needed") and not сл.get("ok")) else
                   f" | ВНИМАНИЕ: слой вернуть не удалось ({сл.get('reason')})"))

    if итог_слоя.get("needed"):
        # Запись о слое ОТДЕЛЬНАЯ и идёт после его переключения: запись `set`
        # пишется ДО, иначе порядок «намерение раньше действия» нарушится, и
        # идентификатора заявки в ней быть не может. Без этой записи операцию
        # нельзя связать с заявкой, которая её исполнила: повторная подача
        # носит суффикс, и журнал называл детерминированное имя чужой попытки
        # (измерено 2026-10-04: `lords-05-idx-open` вместо
        # `lords-05-idx-open-rep123904`).
        _дописать_журнал({
            "at": _сейчас(), "op": "layer", "site": s.domain, "to": режим,
            "request_id": итог_слоя.get("request_id") or "",
            "outcome": итог_слоя.get("outcome") or "",
            "requeued_as": итог_слоя.get("requeued_as") or "",
            "revision": ревизия})

    итог = подтвердить(site, ожидаемый=режим)
    итог.update({"changed": True, "revision": ревизия, "state_file": str(п),
                 "snapshot": str(снимок),
                 "nginx_layer": слой_nginx(s.site_id, s.domain),
                 "nginx_switch": итог_слоя})
    if итог.get("confirmed") is False:
        # Публичный ответ не подтвердил режим. Это частичный отказ: возвращаем
        # исходное состояние — и файл, и слой nginx. Возврат одного файла
        # оставлял домен наполовину открытым: запрет уровня nginx снят,
        # запрет приложения вернулся. Проверено на изолированной площадке.
        возврат = _восстановить(s, прежнее, корень=корень,
                                причина="публичный ответ не подтвердил режим",
                                слой_до=слой, author=author)
        итог["restored"] = True
        итог["nginx_restored"] = возврат.get("nginx_restored")
        итог["nginx_layer"] = слой_nginx(s.site_id, s.domain)
        сл = итог["nginx_restored"] or {}
        итог["reason"] = (
            f"{s.domain}: режим записан, но публичный ответ его не подтвердил "
            f"({итог.get('denying_signals')}). Исходное состояние возвращено"
            + ("" if not (сл.get("needed") and not сл.get("ok")) else
               f" | ВНИМАНИЕ: слой nginx вернуть не удалось ({сл.get('reason')}): "
               f"домен остался в режиме слоя {сл.get('mode')!r}"))
    return итог


def вернуть_слой(s, слой_до: dict | None, *, author: str) -> dict:
    """Вернуть слой nginx в режим, в котором он был ДО операции.

    Зачем это отдельная работа. Восстановления одного файла состояния
    недостаточно: слой nginx — тоже изменённое состояние. Измерено на
    изолированной площадке: после НЕУДАВШЕЙСЯ попытки открытия слой оставался
    открытым, запрет оставался только у приложения (fail-closed), и домен
    выходил наполовину открытым — то есть попытка открытия без разрешения
    фактически снимала часть запретов.

    Возврат идёт ШТАТНОЙ заявкой с суффиксом: без него идентификатор совпал бы
    с прежней успешной заявкой того же режима, очередь ответила бы
    `already-finished`, и возврат оказался бы словесным. Итог проверяется
    ЧТЕНИЕМ слоя, а не исходом заявки.

    Неизвестный исходный режим слоя возвращается в ЗАКРЫТЫЙ: при неизвестности
    безопасное направление одно, и оно называется в ответе (`assumed_closed`).
    """
    если_нет = {"needed": False, "ok": True, "mode": "", "note": "слой не менялся"}
    if not слой_до:
        return если_нет
    запрещал = слой_до.get("denying")
    предполагали = запрещал is None
    исходный = ЗАКРЫТ if (запрещал or предполагали) else ОТКРЫТ
    сейчас = слой_nginx(s.site_id, s.domain)
    итог = {"needed": not слой_в_нужном_режиме(сейчас, исходный),
            "target": исходный, "assumed_closed": предполагали,
            "mode": (сейчас.get("mode") or "").upper()}
    if not итог["needed"]:
        итог["ok"] = True
        return итог
    метка = time.strftime("rst%H%M%S", time.gmtime())
    try:
        итог["switch"] = переключить_слой(s, режим=исходный, author=author,
                                          повтор=метка)
    except Отказано as отказ:
        итог.update({"ok": False, "reason": str(отказ)})
        _дописать_журнал({"at": _сейчас(), "op": "restore-layer-failed",
                          "site": s.domain, "to": исходный,
                          "reason": str(отказ)[:300]})
        return итог
    после = слой_nginx(s.site_id, s.domain)
    итог["mode"] = (после.get("mode") or "").upper()
    итог["ok"] = слой_в_нужном_режиме(после, исходный)
    if not итог["ok"]:
        итог["reason"] = (
            f"слой остался {после.get('mode')!r}: {после.get('evidence')}")
    _дописать_журнал({"at": _сейчас(),
                      "op": "restore-layer" if итог["ok"] else "restore-layer-failed",
                      "site": s.domain, "to": исходный, "mode": итог["mode"],
                      "request_id": (итог.get("switch") or {}).get("request_id")})
    return итог


def _восстановить(s, прежнее: dict, *, корень=None, причина: str,
                  слой_до: dict | None = None, author: str = "") -> dict:
    """Вернуть состояние к тому, что было ДО операции: файл И слой nginx.

    Частично применённая смена режима — худший исход: файл состояния говорит
    одно, домен отдаёт другое, и следующий читатель поверит файлу. Поэтому при
    любом отказе после записи состояние возвращается, а причина называется.

    Слой возвращается после файла: сначала запрет приложения, потом запрет
    nginx — в таком порядке домен ни на миг не остаётся без обоих.
    """
    п = _файл(s.domain, корень=корень)
    было_файла = bool(прежнее.get("desired_state"))
    if было_файла:
        _записать(п, {к: з for к, з in прежнее.items() if not к.startswith("_")})
    else:
        п.unlink(missing_ok=True)
    _дописать_журнал({"at": _сейчас(), "op": "restore", "site": s.domain,
                      "to": прежнее.get("desired_state") or "(нет файла)",
                      "reason": причина, "state_file": str(п)})
    слой = вернуть_слой(s, слой_до, author=author or "restore")
    return {"restored": True, "to": прежнее.get("desired_state") or None,
            "reason": причина, "nginx_restored": слой}


def подтвердить(site: str, *, ожидаемый: str = "", ждать: bool = True) -> dict:
    """Что сайт ОТДАЁТ сейчас. Итог считается по ответу, а не по команде."""
    s = editorial._сайт(site)
    ожид = (ожидаемый or "").strip().upper()
    предел = time.time() + (ОЖИДАНИЕ_С if (ждать and ожид) else 0)
    попыток = 0
    while True:
        попыток += 1
        сиг = сигналы(s.domain, порт=порт_приложения(s.site_id))
        фактически, запрещают = оценить(сиг)
        if not ожид or фактически == ожид or time.time() >= предел:
            break
        time.sleep(ШАГ_С)
    итог = {
        "site": s.domain, "site_id": s.site_id,
        "expected": ожид or None,
        "public_mode": фактически,
        "confirmed": (фактически == ожид) if ожид else None,
        "denying_signals": запрещают,
        "attempts": попыток,
        "signals": сиг,
        "state_file": текущее(s.domain),
    }
    if ожид == ОТКРЫТ and запрещают:
        # Причина обязана называть СЛОЙ, а не просто перечислять заголовки:
        # иначе «снимите запрет в nginx» звучало бы и тогда, когда nginx уже
        # открыт, а закрыто приложение.
        слой_ng = слой_nginx(s.site_id, s.domain, сиг)
        слой_пр = слой_приложения(сиг)
        итог["nginx_layer"] = слой_ng
        итог["app_layer"] = слой_пр
        части = ["сайт отдаёт запрет: " + "; ".join(запрещают)]
        if слой_ng.get("denying"):
            части.append(
                "запрет добавляет nginx: заголовок стоит в конфигурации "
                "фиксированной строкой и этой операцией пока не управляется. "
                "Перевод под управление — та же штатная заявка в ТЕКУЩЕМ "
                "режиме домена, действия владельца он не требует: "
                f"python3 -m factory cell submit --site {s.site_id} "
                "--cell-operation indexing-nginx --mode closed. Основание: "
                + str(слой_ng.get("evidence") or ""))
        elif слой_ng.get("denying") is None:
            части.append(
                "слой nginx не определён: " + str(слой_ng.get("evidence") or ""))
        else:
            части.append(
                "слой nginx открыт (" + str(слой_ng.get("evidence") or "")
                + "); запрет приходит от приложения")
        if слой_пр.get("denying") and not текущее(s.domain).get("present"):
            части.append(
                "приложение закрыто штатно: файла состояния нет, а без него "
                "режим вычисляется закрытым (fail-closed). Это и снимает "
                "indexing-set --mode open")
        итог["reason"] = ". ".join(части)
    return итог


def откатить(site: str, *, author: str, корень=None) -> dict:
    """Вернуть прежнее состояние по журналу. Адресно и только этому сайту.

    `корень` — каталог файлов состояния, тот же довод, что у `установить`.
    Без него откат писал бы в боевой каталог даже когда вся остальная
    операция работает на изолированном стенде: смену режима направить в
    сторону можно, а её откат — нет. Это делало откат непроверяемым иначе как
    на живых доменах.
    """
    s = editorial._сайт(site)
    файл = ЖУРНАЛ / "operations.jsonl"
    если_нет = f"журнала операций нет: {файл}"
    try:
        строки = [json.loads(с) for с in файл.read_text(encoding="utf-8").split("\n")
                  if с.strip()]
    except OSError:
        raise Отказано(если_нет) from None
    свои = [з for з in строки if з.get("site") == s.domain and з.get("op") == "set"]
    if not свои:
        raise Отказано(f"в журнале нет смен режима для {s.domain}: откатывать нечего")
    последняя = свои[-1]
    куда = str(последняя.get("from") or "")
    if куда == "(нет файла)":
        п = _файл(s.domain, корень=корень)
        прежнее = текущее(s.domain, корень=корень)
        п.unlink(missing_ok=True)
        _дописать_журнал({"at": _сейчас(), "op": "rollback", "site": s.domain,
                          "from": прежнее.get("desired_state"), "to": "(нет файла)",
                          "author": author, "undo_of": последняя.get("revision")})
        итог = подтвердить(site, ожидаемый=ЗАКРЫТ)
        итог.update({"rolled_back_to": "(нет файла)", "changed": True})
        return итог
    итог = установить(site, mode=куда, author=author, корень=корень)
    итог["rolled_back_to"] = куда
    итог["undo_of"] = последняя.get("revision")
    return итог


def состояние(site: str) -> dict:
    """Всё, что известно о режиме этого сайта, без единой записи."""
    s = editorial._сайт(site)
    разрешено, откуда = разрешение_выпуска(s.account, s.adapter, s.domain)
    разрешил, объявлен, пояснение = разрешение_владельца(s.site_id)
    сиг = сигналы(s.domain, порт=порт_приложения(s.site_id))
    фактически, запрещают = оценить(сиг)
    читатель = читатель_режима(s.account, s.adapter)
    return {
        "site": s.domain, "site_id": s.site_id,
        "public_mode": фактически,
        "denying_signals": запрещают,
        "layers": {
            "owner_authorization": {"open_authorized": разрешил,
                                    "declared_state": объявлен or None,
                                    "note": пояснение or None,
                                    "source": str(registry.РЕЕСТР_ЯЧЕЕК)},
            "release_permission": {"permits_open": разрешено, "source": откуда},
            "state_file": текущее(s.domain),
            "nginx_header": слой_nginx(s.site_id, s.domain, сиг),
            "app": слой_приложения(сиг),
        },
        "runtime_reader": str(читатель) if читатель else "",
        "signals": сиг,
        "log": str(ЖУРНАЛ / "operations.jsonl"),
    }
