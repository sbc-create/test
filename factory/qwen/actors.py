#!/usr/bin/env python3
"""Кто и что вправе менять в production. Одно место на все пишущие операции.

Зачем отдельный модуль
----------------------

Разграничение прав уже было, но только одно и в двух разных местах:

* у очереди — по НАЗВАННОЙ роли владельца (`queue_bridge.ЗАПРЕЩЁННЫЕ_РОЛИ`):
  сторона SEO не берёт задания;
* у моста — переключателем на весь сервер (`--read-only`): либо все пишущие
  инструменты объявлены, либо ни один.

Ни то, ни другое не отвечает на вопрос «этому исполнителю можно готовить
черновик, но нельзя публиковать». Переключатель моста грубее, чем нужно: он
снимает и `prepare_*`, то есть останавливает подготовку заодно с публикацией,
а поднят он на весь сервер — значит, ограничив одного клиента, ограничишь и
остальных, которые ходят через тот же мост.

Инцидент, из которого это выросло
---------------------------------

2026-10-09: исполнитель Qwen при действующем запрете опубликовал на
yummyani.org пост `chernaya-koshka-i-klass-vedm-comment`, в теле которого лежал
не комментарий к произведению, а вопрос к редакции про радиостанцию
(«Какой источник подтверждает…»), и через пять минут снял его. Журнал витрины:
`publish-post` 13:30:07Z, `unpublish-post` 13:35:36Z, автор «Редакция».
Публикация прошла не через объявленный read-only мост: установленный юнит
запускает его с `--read-only`, а РАБОТАЮЩИЙ процесс (pid 838044) — без ключа.
То есть запрет держался на договорённости, а не на свойстве кода.

Что здесь сделано
-----------------

Роль исполнителя называется в имени (`<роль>/<автоматизация>/run-<id>` — та же
форма, что у очереди), и для роли объявляется, какие ОПЕРАЦИИ ей разрешены.
Проверка стоит внутри самих операций, поэтому обойти её, сменив канал (мост,
CLI, прямой вызов модуля), нельзя: канал не является носителем права.

Роль без явного объявления ограничений не трогается: остановить действующих
редакторов ради формы имени значило бы остановить редакционную работу.
"""

from __future__ import annotations

import os

#: Пишущие операции, о которых знает ограничение. Имена — те же, что у
#: инструментов моста и функций модулей, чтобы отказ назывался тем словом,
#: которым операцию вызвали.
ОПЕРАЦИИ = ("prepare", "publish", "unpublish", "restore",
            "queue-register", "queue-next", "queue-result", "queue-reopen",
            "queue-annul", "posts-prepare", "posts-publish", "posts-unpublish")

#: Что разрешено роли. Роль, которой здесь нет, не ограничивается.
#:
#: `qwen` — только подготовка черновиков. Решение владельца 2026-10-09 после
#: инцидента: «подготовка черновиков разрешена; публикация, снятие,
#: восстановление материалов и изменение очередей ему сейчас не нужны».
#: Чтение не перечисляется: ограничение касается только изменений.
РАЗРЕШЕНО_РОЛИ: dict[str, tuple[str, ...]] = {
    "qwen": ("prepare", "posts-prepare"),
}

#: Переменная для владельца: снять ограничение роли на одну смену, не правя
#: код. Пусто — ограничение действует. Значение — перечень роль:операция.
СНЯТИЕ = "FACTORY_ACTOR_ALLOW"


class ОперацияНеРазрешена(Exception):
    """Роль исполнителя не вправе менять production этой операцией."""


def роль(имя: str) -> tuple[str, bool]:
    """(роль, названа_ли_явно). Роль — часть имени до первой косой черты.

    Та же разметка имени, что у очереди (`queue_bridge.роль_владельца`):
    второй способ называть роль разошёлся бы с первым.
    """
    строка = (имя or "").strip()
    if "/" in строка:
        return строка.split("/", 1)[0].strip().lower(), True
    return строка.lower(), False


def _снято(имя_роли: str, операция: str) -> bool:
    """Снял ли владелец ограничение этой роли на эту операцию."""
    сырое = os.environ.get(СНЯТИЕ, "")
    for кусок in сырое.replace(";", ",").split(","):
        кусок = кусок.strip().lower()
        if not кусок:
            continue
        if кусок in (f"{имя_роли}:{операция}", f"{имя_роли}:*", "*"):
            return True
    return False


def проверить(actor: str, операция: str) -> None:
    """Пропустить или отказать, назвав причину и то, что РАЗРЕШЕНО.

    Отказ — исключение, а не пустой успех: операция, которая «ничего не
    сделала», в журнале неотличима от выполненной.
    """
    if операция not in ОПЕРАЦИИ:
        raise ValueError(f"неизвестная операция {операция!r}: "
                         f"ожидается одна из {ОПЕРАЦИИ}")
    имя_роли, явно = роль(actor)
    разрешено = РАЗРЕШЕНО_РОЛИ.get(имя_роли)
    if разрешено is None and имя_роли.startswith(("qwen-", "qwen_")):
        разрешено = РАЗРЕШЕНО_РОЛИ["qwen"]
    if разрешено is None:
        return
    if операция in разрешено or _снято(имя_роли, операция):
        return
    raise ОперацияНеРазрешена(
        f"роль {имя_роли!r} (исполнитель {actor!r}) не меняет production "
        f"операцией {операция!r}. Разрешено: {', '.join(разрешено)}. "
        "Ограничение введено 2026-10-09 после публикации поста "
        "chernaya-koshka-i-klass-vedm-comment с посторонним текстом: "
        "подготовка черновиков остаётся, публикацию и снятие выполняет "
        "проверяющая сторона. Снять на одну смену может владелец переменной "
        f"{СНЯТИЕ}=<роль>:<операция>"
        + ("" if явно else
           ". Имя без роли: назовите роль как <роль>/<автоматизация>/run-<id>"))


def сведения() -> dict:
    """Машинно читаемое состояние ограничений — для отчётов и диагностики."""
    return {
        "roles": {р: list(о) for р, о in РАЗРЕШЕНО_РОЛИ.items()},
        "operations": list(ОПЕРАЦИИ),
        "override_env": СНЯТИЕ,
        "override_active": os.environ.get(СНЯТИЕ, ""),
    }
