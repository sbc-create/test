"""Постоянная веб-панель Secret Hub.

Панель — отдельный непривилегированный процесс. Она умеет показать состояние
направлений и принять новые credentials, но не умеет ни расшифровать их, ни
прочитать уже сохранённые: и то и другое остаётся за root-owned сервисом хаба,
с которым панель разговаривает по unix-сокету.

Разделение ответственности:

===================  ==========================================================
процесс              что ему доступно
===================  ==========================================================
``sfpanel``          HTTP, WebAuthn, сессии; значения проходят насквозь в хаб и
                     не задерживаются нигде, кроме памяти обработчика запроса
``root`` (хаб)       мастер-ключ, расшифровка, запись файлов потребителям,
                     перезапуск unit'ов
``claude``           только чтение состояния через сокет; ни записать, ни
                     прочитать значение не может
===================  ==========================================================

В собственной базе панели нет ни одного секрета направлений: там лежат
публичные ключи passkey'ев, хеши recovery-кодов, идентификаторы сессий и
счётчики попыток. Публичный ключ на то и публичный; хеш восстановить нельзя.
"""
from __future__ import annotations

#: Имя cookie сессии. Префикс ``__Secure-`` обязывает браузер отдавать её
#: только по HTTPS. ``__Host-`` не подходит: он требует ``Path=/``, а панель
#: живёт на ``/__factory-secrets`` и не должна отправлять свою cookie на
#: страницы самого сайта.
SESSION_COOKIE = "__Secure-sfpanel"

#: Сколько живёт сессия владельца. Панель постоянная, но сессия — нет.
SESSION_TTL_SECONDS = 12 * 60 * 60

#: Тело запроса не больше 8 KiB — на уровне nginx и ещё раз здесь.
MAX_BODY_BYTES = 8 * 1024

#: Сколько recovery-кодов выдаётся владельцу за раз.
RECOVERY_CODE_COUNT = 10

__all__ = [
    "SESSION_COOKIE",
    "SESSION_TTL_SECONDS",
    "MAX_BODY_BYTES",
    "RECOVERY_CODE_COUNT",
]
