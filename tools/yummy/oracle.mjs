/**
 * Оракул записей консоли: что считать дефектом страницы, а что — не считать.
 *
 * Зачем отдельный модуль
 * ----------------------
 *
 * На маршруте, который ОБЯЗАН отвечать 404, браузер сам пишет в консоль
 * «Failed to load resource: the server responded with a status of 404».
 * Это сообщение браузера о запрошенном документе, а не ошибка страницы.
 * Считать его дефектом значит требовать, чтобы страница 404 не отвечала 404,
 * — и один повторяющийся случай превращается в столько «провалов», сколько
 * ширин и браузеров в матрице.
 *
 * Обратная ошибка дороже: молча простить любую запись со словом «404» значит
 * перестать видеть настоящие потери ресурсов. Поэтому послабление выдаётся
 * только при выполнении ВСЕХ признаков сразу, и любая другая запись остаётся
 * ошибкой.
 *
 * Модуль вынесен отдельно, чтобы его можно было проверить самим собой:
 * подсадить заведомые дефекты и убедиться, что он их не проглатывает.
 */

/** Похоже ли сообщение на браузерное уведомление о 404 документа. */
export function похоже_на_404(текст) {
  const т = String(текст || '');
  return /404/.test(т)
    && /failed to load resource|the server responded with a status/i.test(т)
    // Ошибка приложения со словом «404» в тексте послаблением не пользуется.
    && !/uncaught|typeerror|referenceerror|syntaxerror|minified react/i.test(т);
}

/**
 * Разобрать наблюдения страницы на настоящие ошибки и ожидаемое уведомление.
 *
 * @param {object} набл
 * @param {number|null} набл.status   код ответа основного документа
 * @param {string[]}    набл.консоль  записи консоли уровня error
 * @param {string[]}    набл.исключения необработанные исключения страницы
 * @param {object[]}    набл.сбои     запросы, не состоявшиеся вовсе
 * @param {object[]}    набл.коды     коды ответов всех запросов страницы
 */
export function разобрать_консоль({ status, консоль = [], исключения = [], сбои = [], коды = [] }) {
  // Все признаки проверяются вместе: достаточно одного нарушенного, чтобы
  // послабление не выдавалось никому на этой странице.
  const признаки = {
    документ_404: status === 404,
    нет_5xx: !коды.some((к) => к && к.status >= 500),
    нет_исключений: исключения.length === 0,
    нет_потерянных_запросов: сбои.length === 0,
  };
  const можно = Object.values(признаки).every(Boolean);
  const ожидаемый = можно ? консоль.filter(похоже_на_404) : [];
  const реальные = консоль.filter((т) => !ожидаемый.includes(т));
  return { признаки, ожидаемый, реальные, ошибок: реальные.length + исключения.length };
}
