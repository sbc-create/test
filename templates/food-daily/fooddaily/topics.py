CURRENT_SEASON = "autumn"  # октябрь 2026 — от даты задания, не от спроса


def _slug_tokens(url: str) -> list[str]:
    """Токены слага: скелет и исходный вид — `скелет|исходный`."""
    path = urllib.parse.urlsplit(url).path.rstrip("/")
    slug = re.sub(r"\.html$", "", path.split("/")[-1])
    slug = re.sub(r"^\d+-|-\d+$", "", slug)
    return [skel(t) + "|" + t.lower() for t in re.split(r"[-_]", slug) if t and not t.isdigit()]


def term(word: str) -> str:
    """Условие совпадения по исходному токену слага: префикс слова без
    окончания (≥4 букв) — так совпадают kurinyj/kurinyi, tushenaja/tushenaia;
    короткие слова — только точно. Скелет без гласных отвергнут: он склеивал
    tost/testo, olive/lavandovyj, а «uha» превращал в пустую строку."""
    alts = []
    for w in word.lower().split("/"):
        alts.append(("p:" + w[: max(4, len(w) - 2)]) if len(w) > 4 else ("w:" + w))
    return "&".join(alts)


def tok_match(tok: str, cond: str) -> bool:
    raw = tok.split("|", 1)[1]
    return any(raw.startswith(c[2:]) if c[0] == "p" else raw == c[2:] for c in cond.split("&"))


def topic_matches(tokens: list[str], need: list[str], exclude: list[str]) -> bool:
    return all(any(tok_match(t, c) for t in tokens) for c in need) and not any(
        any(tok_match(t, c) for t in tokens) for c in exclude
    )


def coverage(hosts: list[str]) -> dict[str, dict]:
    need = {t["topic_id"]: [term(x) for x in t["need"]] for t in TOPICS}
    excl = {t["topic_id"]: [term(x) for x in t["exclude"]] for t in TOPICS}
    cov = {t["topic_id"]: {"hosts": collections.Counter(), "examples": {}} for t in TOPICS}
    for h in hosts:
        p = CRAWL_ROOT / h / "urls.jsonl"
        if not p.exists():
            continue
        seen = set()
        for line in p.open():
            d = json.loads(line)
            if d["url"] in seen:
                continue
            seen.add(d["url"])
            if classify(h, d["url"], d.get("sitemap"))[0] != "recipe":
                continue
            toks = _slug_tokens(d["url"])
            for tid, req in need.items():
                if topic_matches(toks, req, excl[tid]):
                    cov[tid]["hosts"][h] += 1
                    cov[tid]["examples"].setdefault(h, d["url"])
    return cov


def priority(t: dict, c: dict, n_hosts: int) -> tuple[float, str]:
    hosts = len(c["hosts"])
    urls = sum(c["hosts"].values())
    s_cov = 4 * hosts / max(n_hosts, 1)  # 0..4: доля каталогов с темой
    s_vol = min(2.0, math.log10(urls + 1))  # 0..2: глубина темы у конкурентов
    s_fit = 2 if t["site_id"] == "food-daily" and t["meal"] in ("breakfast", "lunch", "dinner") else 1
    s_vid = (t["video"] - 1) * 0.5  # 0..1: польза видео
    s_cx = (3 - t["complexity"]) * 0.5  # 0..1: проще подготовить
    s_season = 0.5 if t["season"] in (CURRENT_SEASON, "all") else -0.5
    score = round(s_cov + s_vol + s_fit + s_vid + s_cx + s_season, 2)
    why = (
        f"в {hosts} из {n_hosts} каталогов, {urls} URL; применимость {s_fit}; видео {t['video']}/3; "
        f"сложность {t['complexity']}/3; сезон {t['season']}"
    )
    return score, why


def build(out_csv: Path, hosts: list[str]) -> list[dict]:
    cov = coverage(hosts)
    rows = []
    for t in TOPICS:
        c = cov[t["topic_id"]]
        score, why = priority(t, c, len(hosts))
        rows.append(
            {
                "topic_id": t["topic_id"],
                "topic": t["label"],
                "intent": t["intent"],
                "sources": " ".join(c["examples"].values()),
                "source_hosts": len(c["hosts"]),
                "source_recipe_urls": sum(c["hosts"].values()),
                "search_demand": "",  # не измерялось
                "site_id": t["site_id"],
                "category": t["category"],
                "planned_url": t["planned_url"],
                "priority": score,
                "priority_reason": why,
                "season": t["season"],
                "status": "queued",
                "label_source": "slug_transliteration",
            }
        )
    rows.sort(key=lambda r: (r["site_id"] != "food-daily", -r["priority"]))
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    with out_csv.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    return rows
