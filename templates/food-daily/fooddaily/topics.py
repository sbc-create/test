def skel(w: str) -> str:
    w = w.lower()
    for a, b in (
        ("shch", "S"),
        ("shh", "S"),
        ("sch", "S"),
        ("zh", "Z"),
        ("ch", "C"),
        ("sh", "W"),
        ("kh", "H"),
        ("ts", "c"),
        ("x", "ks"),
    ):
        w = w.replace(a, b)
    return re.sub(r"[aeiouyj'h_]", "", w)


